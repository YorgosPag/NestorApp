/**
 * @fileoverview **Η ΑΓΚΥΡΑ ΤΟΥ ΦΡΕΝΟΥ** — «κρίνει ΠΡΟΓΡΑΜΜΑ ή κρίνει ΠΡΟΖΑ;»
 * @related .claude/hooks/heavy-mutex.js · CLAUDE.md N.16 · ADR-783 (πύλη χωρίς δοκιμή)
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ — ΔΥΟ ΜΕΤΡΗΜΕΝΑ ΠΕΡΙΣΤΑΤΙΚΑ, 01/09/2026
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το φρένο δεν μετρά CPU ούτε διεργασίες: είναι **regex πάνω σε ΟΛΟΚΛΗΡΗ τη
 * συμβολοσειρά της εντολής**. Άρα μπλοκάρει ό,τι **ΑΝΑΦΕΡΕΙ** «jest»/«tsc», ακόμη κι
 * όταν το ωφέλιμο φορτίο είναι **κείμενο προς εγγραφή**. Μετρήθηκαν δύο:
 *
 * 1. 🔴 **Το `git commit` του άλλου agent κράτησε το κλειδί.** Η εξαίρεση είναι
 *    `\bgit\s+commit\b`, αλλά ο **N.16 επιβάλλει** τη μορφή
 *    `"C:\Program Files\Git\cmd\git.exe" commit …` ⇒ `git.exe" commit` **δεν ταιριάζει**.
 *    Μετά, το μήνυμα του commit ανέφερε `tsc` ⇒ χαρακτηρίστηκε **βαρύ**. Το σχόλιο
 *    πάνω από το `EXEMPT` λέει ρητά *«αν το φρένο το έπιανε, ο Giorgio δεν θα μπορούσε
 *    να κάνει commit»*. **Το έπιανε.**
 * 2. 🔴 **Ένα `node -e` που έγραφε markdown μπλοκαρίστηκε**, επειδή το **κείμενο** που
 *    έγραφε περιείχε `jest-suite.yml`. Δηλαδή: όσο καλύτερα τεκμηριώνεις, τόσο πιο
 *    πιθανό να μπλοκαριστείς — και οι δύο περιπτώσεις μιλούσαν **για** τις πύλες.
 *
 * ⚠️ **ΤΟ ΦΡΕΝΟ ΔΕΝ ΕΙΝΑΙ ΣΥΝΟΡΟ ΑΣΦΑΛΕΙΑΣ** — είναι συνεργατικό mutex ανάμεσα σε δύο
 * συνεδρίες του **ίδιου** ανθρώπου. Κανείς δεν προσπαθεί να το ξεγελάσει· το μετρημένο
 * κακό είναι τα **ψευδώς θετικά** που μπλοκάρουν νόμιμη δουλειά (και τα commits του
 * ίδιου του Giorgio). Γι' αυτό η αποκοπή ωφέλιμου φορτίου είναι σωστή ανταλλαγή — αλλά
 * **όχι απεριόριστη**: η ομάδα `Φ` είναι ο φρουρός κατά της υπερ-αποκοπής.
 */

'use strict';

const { isHeavy, STALE_MINUTES } = require('../heavy-mutex.js');

/** Η **πραγματική** εντολή που κράτησε το κλειδί (περιστατικό 1). */
const N16_COMMIT =
  '"C:\\Program Files\\Git\\cmd\\git.exe" commit -m "feat(adr-841): F3 — oi eikones ' +
  'ftanoun sto rafi" -m "ADR-777 §8.46: o frouros gia to sfalma seiras orismatwn tou ' +
  'sideOfPolyline pou ekfyge epeidi o N.17 apagorevei tsc ston praktora."';

/** Η **πραγματική** εντολή που μπλοκαρίστηκε (περιστατικό 2), σε μικρογραφία. */
const NODE_WRITES_PROSE =
  `node -e 'const fs=require("fs"); fs.writeFileSync(f, "Pyles: 3.54 PASS ` +
  `(jest-suite.yml, anev oron kai mplokaron) · 3.28 PASS")'`;

// =============================================================================
// Κ — ΚΡΙΝΕΙ ΠΡΟΓΡΑΜΜΑ, ΟΧΙ ΠΡΟΖΑ
// =============================================================================

describe('🔴 Κ — το φρένο κρίνει ΤΙ ΤΡΕΧΕΙ, όχι τι λέει', () => {
  it('🔑 Κ1 — το `git commit` στη μορφή που ΕΠΙΒΑΛΛΕΙ ο N.16 εξαιρείται', () => {
    expect(isHeavy(N16_COMMIT)).toBe(false);
  });

  /**
   * ⚠️ **Ο μάρτυρας ότι φταίει η ΜΟΡΦΗ.** Η ίδια εντολή με σκέτο `git` περνούσε ήδη —
   * άρα η διαφορά δεν είναι το περιεχόμενο αλλά το `git.exe"` του N.16.
   */
  it('Κ2 — το ίδιο commit με σκέτο `git` εξαιρείται επίσης (ίδιο ερώτημα, μία απάντηση)', () => {
    expect(isHeavy(N16_COMMIT.replace(/"[^"]*git\.exe"/, 'git'))).toBe(false);
  });

  it('🔑 Κ3 — `node -e` που ΓΡΑΦΕΙ κείμενο με τη λέξη «jest» δεν είναι βαρύ', () => {
    expect(isHeavy(NODE_WRITES_PROSE)).toBe(false);
  });

  it('🔑 Κ4 — μήνυμα commit που ΑΝΑΦΕΡΕΙ `tsc` δεν κάνει το commit βαρύ', () => {
    expect(isHeavy('git commit -m "giati o N.17 apagorevei tsc ston praktora"')).toBe(false);
  });

  it('Κ5 — heredoc που ΠΕΡΙΕΧΕΙ τις λέξεις-σκανδάλη δεν είναι βαρύ', () => {
    const cmd = ["cat > notes.md << 'EOF'", 'trexe npm run test:jest-partition', 'EOF'].join('\n');
    expect(isHeavy(cmd)).toBe(false);
  });
});

// =============================================================================
// Φ — ΦΡΟΥΡΟΙ ΚΑΤΑ ΤΗΣ ΥΠΕΡ-ΑΠΟΚΟΠΗΣ: ό,τι ΟΝΤΩΣ γεμίζει τους 4 πυρήνες
// =============================================================================

describe('Φ — και όμως πιάνει ΑΚΡΙΒΩΣ ό,τι πρέπει', () => {
  it.each([
    ['npx jest src/components/demand/form/__tests__/DemandFrontageField.gesture.test.tsx --ci'],
    ['npm run test:jest-partition'],
    ['pnpm exec jest scripts/__tests__/check-anchor-execution.test.js --ci'],
    ['npx tsc --noEmit'],
    ['npm run jscpd:diff -- src/foo.ts'],
    ['npm run ssot:audit'],
    ['next build'],
  ])('Φ — «%s» ΕΙΝΑΙ βαρύ', (cmd) => {
    expect(isHeavy(cmd)).toBe(true);
  });

  /**
   * 🔴 **Το `-c` ΔΕΝ αποκόπτεται, επίτηδες.** Είναι **κώδικας προς εκτέλεση**, όχι
   * δεδομένα: αποκόπτοντάς το, το `bash -c "npx jest"` θα ξέφευγε — δηλαδή η διόρθωση
   * θα άνοιγε τρύπα ακριβώς στο πράγμα που το φρένο υπάρχει να πιάνει.
   */
  it('🔑 Φ8 — `bash -c "npx jest"` παραμένει βαρύ: το `-c` είναι κώδικας, όχι πρόζα', () => {
    expect(isHeavy('bash -c "npx jest src/foo.test.ts"')).toBe(true);
  });
});

// =============================================================================
// Μ — Η ΚΛΕΙΔΑΡΙΑ ΔΕΝ ΚΡΑΤΑ ΟΜΗΡΟ ΤΟ ΜΗΧΑΝΗΜΑ
// =============================================================================

describe('Μ — το μπαγιάτικο κλειδί', () => {
  /**
   * ⚠️ Το `PostToolUse` δεν τρέχει αν η συνεδρία πεθάνει ⇒ το κλειδί μένει ως το
   * `STALE_MINUTES`. Το ταβάνι του **εργαλείου** Bash είναι **10 λεπτά**, οπότε καμία
   * νόμιμη εντολή προσκηνίου δεν ζει τόσο· τα 90′ ήταν εννιαπλάσια του χειρότερου
   * πραγματικού χρόνου.
   */
  it('🔑 Μ1 — νεκρή συνεδρία δεν κλειδώνει το δέντρο για ώρες', () => {
    expect(STALE_MINUTES).toBeLessThanOrEqual(20);
  });
});
