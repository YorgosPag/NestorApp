/**
 * `same_tenant_user` × εγγραφές — **42 κελιά.**
 *
 * Εδώ η πρόθεση **πραγματικά διαφέρει ανά συλλογή** και αυτό είναι τεκμηριωμένο:
 * το `crmDirectMatrix` δίνει `create: allow` ενώ το κανονικό `tenant_direct`
 * όχι, και το `attendanceEventMatrix` προσθέτει το δικό του. Άρα δεν υπάρχει
 * καθολική απάντηση να γραφτεί στο πρότυπο — **κάθε συλλογή που ξέρει, δηλώνει
 * το κελί της** με `overrideDefinition()` και η εξαίρεση φεύγει μόνη της.
 */
export const sameTenantUserPerCollection = (
  operations: readonly Operation[],
): readonly Exemption[] =>
  exempt(
    ['same_tenant_user'],
    operations,
    meta(
      'ΑΠΟΚΛΙΝΕΙ ΑΝΑ ΣΥΛΛΟΓΗ, ΤΕΚΜΗΡΙΩΜΕΝΑ. Το crmDirectMatrix δίνει ' +
        'create:allow ενώ το κανονικό tenant_direct όχι, και το ' +
        'attendanceEventMatrix προσθέτει δικό του κελί — δηλαδή δεν υπάρχει ' +
        'καθολική απάντηση που να ανήκει στο ΠΡΟΤΥΠΟ. Κλείνει ανά συλλογή με ' +
        'overrideDefinition(), όπου η εξαίρεση αφαιρείται αυτόματα.',
    ),
  );

/**
 * Ad-hoc εξαίρεση για κελί που δεν πέφτει σε καμία από τις παραπάνω κατηγορίες.
 *
 * ⚠️ Αν βρεθείς να τη χρησιμοποιείς **τρίτη φορά με τον ίδιο λόγο**, ο λόγος
 * ανήκει σε σταθερά παραπάνω — αλλιώς φτιάχνεις τον sibling clone που το CHECK
 * 3.28 (N.18) υπάρχει για να πιάνει.
 */
export const openCell = (
  personas: readonly Persona[],
  operations: readonly Operation[],
  why: string,
): readonly Exemption[] => exempt(personas, operations, meta(why));
