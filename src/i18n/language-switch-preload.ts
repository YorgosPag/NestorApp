/**
 * =============================================================================
 * 🌐 ADR-831 — ΤΙ ΠΡΕΠΕΙ ΝΑ ΦΤΑΣΕΙ **ΠΡΙΝ** ΓΥΡΙΣΕΙ Η ΟΘΟΝΗ
 * =============================================================================
 *
 * Μία καθαρή απόφαση, χωρίς εξαρτήσεις: *«ποια namespaces προφορτώνονται σε μια
 * αλλαγή γλώσσας;»*.
 *
 * 🔴 **ΓΙΑΤΙ ΔΙΚΟ ΤΟΥ ΑΡΧΕΙΟ ΚΑΙ ΟΧΙ ΜΕΣΑ ΣΤΟ HOOK.** Το
 * `useLanguagePreference` εισάγει `AuthContext` → Firebase, οπότε **δεν
 * σηκώνεται** σε περιβάλλον node: κάθε άγκυρα πάνω σε αυτή την απόφαση θα
 * χρειαζόταν να στήσει ταυτότητα και βάση για να ρωτήσει κάτι που είναι
 * **συνάρτηση συνόλων**. Το έμαθα εκτελώντας το — `ReferenceError: fetch is not
 * defined`, πριν τρέξει ούτε ένα test.
 *
 * Είναι το ίδιο ιδίωμα με το `compat-translate.ts` (ADR-798 §13): η **λογική**
 * ζει καθαρή και δοκιμάσιμη, το hook κρατά μόνο τη **σύνδεση**.
 *
 * @module i18n/language-switch-preload
 * @see docs/centralized-systems/reference/adrs/ADR-831-language-switch-preload.md
 */

import { SUPPORTED_NAMESPACES, type Namespace } from './lazy-config';
import { getRequestedNamespaces } from './bundle-registry';

/** Ό,τι ξέρει να φορτώσει ο loader. Ό,τι άλλο θα κατέληγε σε άδειο bundle. */
const LOADABLE_NAMESPACES = new Set<string>(SUPPORTED_NAMESPACES);

/**
 * **Τι πρέπει να φτάσει ΠΡΙΝ γυρίσει η οθόνη** (ADR-831).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΜΗΤΡΩΟ ΑΠΑΝΤΑ, ΟΧΙ Η ΛΙΣΤΑ ΤΟΥ ΚΑΛΟΥΝΤΟΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η παλιά γραφή ήταν `namespaceKey.split('|')` — **μόνο** όσα θυμήθηκε να δηλώσει
 * ο καλών. Μετρήθηκε (ADR-830 §1) τι κόστιζε: με τον switcher να δηλώνει
 * `COMMON_NAMESPACES`, **κάθε άλλο** namespace της οθόνης έμπαινε στη νέα γλώσσα
 * **μετά** το `changeLanguage` — δηλαδή περνούσε από ένα καρέ όπου το i18next
 * απαντούσε από το `fallbackLng`. Ελληνικό κείμενο σε αγγλική οθόνη.
 *
 * 🔑 **Η ένωση, όχι η αντικατάσταση.** Το μητρώο είναι *μετρημένα* υπερσύνολο του
 * `COMMON_NAMESPACES` (φορτώνονται στο boot), αλλά η δήλωση του καλούντος
 * κρατιέται: είναι η **πρόθεση** —*«αυτά χρειάζομαι σίγουρα»*— και μια πρόθεση δεν
 * ακυρώνεται επειδή μια μέτρηση συμφωνεί μαζί της σήμερα. Αν αύριο κάποιος
 * ζητήσει namespace που δεν έχει ακόμη φορτωθεί, η ένωση το τιμά· η αφαίρεση όχι.
 *
 * ⚠️ **ΤΟ ΦΙΛΤΡΟ ΕΙΝΑΙ ΥΠΟΧΡΕΩΤΙΚΟ.** Το μητρώο κρατά ό,τι **εγκαταστάθηκε**, και
 * σε αυτό περιλαμβάνονται compat splits (ADR-280) που **δεν** έχουν `case` στον
 * loader. Χωρίς φιλτράρισμα, το `loadNamespace` θα έπεφτε στο `default: null`,
 * θα κατέγραφε **άδειο** bundle και θα πλήρωνε ένα δυναμικό `import` για το τίποτα
 * — σε **κάθε** αλλαγή γλώσσας.
 *
 * 💰 **Το κόστος είναι σκόπιμο.** Η αλλαγή γλώσσας συμβαίνει **μία φορά ανά
 * συνεδρία** και ο άνθρωπος περιμένει μπροστά της με ενδείκτη φόρτωσης. Το να
 * φορτωθούν παράλληλα όσα JSON άγγιξε η συνεδρία είναι ασύγκριτα φθηνότερο από το
 * να δει λάθος γλώσσα — και **δεν** επιβαρύνει καμία άλλη διαδρομή.
 *
 * 🔬 **ΕΞΑΓΕΤΑΙ ΓΙΑ ΝΑ ΔΟΚΙΜΑΖΕΤΑΙ**, στο ίδιο πνεύμα με το `compat-translate.ts`:
 * είναι **καθαρή και ντετερμινιστική**, οπότε ελέγχεται χωρίς να σηκωθούν React,
 * Firestore και AuthContext. Ο μόνος άλλος καταναλωτής είναι το ίδιο το hook.
 */
export function resolveNamespacesToPreload(namespaceKey: string): Namespace[] {
  const declared = namespaceKey ? namespaceKey.split('|') : [];
  const union = new Set<string>([...declared, ...getRequestedNamespaces()]);
  return [...union].filter((ns) => LOADABLE_NAMESPACES.has(ns)) as Namespace[];
}
