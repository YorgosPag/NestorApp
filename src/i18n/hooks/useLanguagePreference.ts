import { useCallback } from 'react';

import { useAuthOptional } from '@/auth/contexts/AuthContext';
import { db } from '@/lib/firebase';
import { safeSetItem, STORAGE_KEYS } from '@/lib/storage';
import { createModuleLogger } from '@/lib/telemetry';
import { userNotificationSettingsService } from '@/services/user-notification-settings';

import {
  changeLanguage as applyLanguageToUi,
  loadNamespace,
  type Namespace,
} from '../lazy-config';
import { isHumanLanguage, type Language } from '../languages';

const logger = createModuleLogger('useLanguagePreference');

/** Τι απέγινε η επιλογή. **Ονομασμένο, ποτέ boolean** — τέσσερις ρητές καταλήξεις. */
export type LanguagePreferenceOutcome =
  /** Άλλαξε η οθόνη **και** αποθηκεύτηκε στη βάση. */
  | { readonly kind: 'persisted' }
  /** Άλλαξε η οθόνη· δεν υπάρχει συνδεδεμένος χρήστης να αποθηκευτεί. **Κανονικό.** */
  | { readonly kind: 'anonymous' }
  /** Άλλαξε η οθόνη· το `pseudo` **δεν** αποθηκεύεται ποτέ (όργανο, όχι γλώσσα). */
  | { readonly kind: 'instrument' }
  /** 🔴 Άλλαξε η οθόνη, αλλά η βάση **δεν** το έμαθε. Τα email θα φύγουν στην παλιά. */
  | { readonly kind: 'not-persisted'; readonly error: unknown };

export interface LanguagePreference {
  /** Άλλαξε τη γλώσσα **παντού**. Δεν πετά ποτέ: επιστρέφει την κατάληξη. */
  readonly setLanguage: (language: Language) => Promise<LanguagePreferenceOutcome>;
}

/**
 * **Ο ένας τρόπος να αλλάξει γλώσσα.**
 *
 * ⚠️ **Η σειρά είναι συμβόλαιο**, όχι προτίμηση:
 *
 * 0. **Τα κείμενα της τρέχουσας οθόνης πρώτα** — δες την παράμετρο `namespaces`.
 * 1. **Οθόνη** — ο άνθρωπος περιμένει μπροστά της· κάθε άλλη σειρά της προσθέτει
 *    την καθυστέρηση της Firestore χωρίς κανένα κέρδος.
 * 2. **`localStorage` μετά** — χωρίς αυτό, μια ανανέωση σελίδας γυρίζει πίσω τη
 *    γλώσσα και ο χρήστης νομίζει ότι η επιλογή αγνοήθηκε.
 * 3. **Βάση τελευταία** — είναι ο μόνος αποδέκτης που **δεν** βλέπει ο χρήστης
 *    τώρα, και ο μόνος του οποίου η αποτυχία επιτρέπεται να μη σταματήσει τα άλλα δύο.
 *
 * 🔑 **Ιδεμποτής**: δύο κλήσεις με την ίδια γλώσσα αφήνουν το ίδιο αποτέλεσμα — το
 * `updateSettings` γράφει την ίδια τιμή, δεν προσθέτει.
 *
 * @param namespaces Τα κείμενα που χρειάζεται **η οθόνη του καλούντος**, πέρα από τα
 * κρίσιμα. **Δεν είναι προαιρετική λεπτομέρεια**: μετρήθηκε ότι το
 * `COMMON_NAMESPACES` (~137 καταναλωτές) **δεν** περιέχεται στα `CRITICAL_NAMESPACES`
 * — λείπουν μεταξύ άλλων τα `common-actions`, `common-status`, `common-validation`.
 * Χωρίς αυτό το βήμα, η ίδια η σελίδα ρυθμίσεων θα έβαφε **ωμά κλειδιά** τη στιγμή
 * που ο χρήστης αλλάζει γλώσσα, δηλαδή ακριβώς εκεί που κοιτάζει.
 */
export function useLanguagePreference(
  namespaces: readonly Namespace[] = [],
): LanguagePreference {
  const userId = useAuthOptional()?.user?.uid ?? null;
  // Το `join` δίνει σταθερή ταυτότητα σε πίνακα που ο καλών συχνά γράφει inline —
  // αλλιώς το `useCallback` θα ξαναγεννιόταν σε **κάθε** απόδοση και η σταθερότητα
  // της αναφοράς θα ήταν διακοσμητική.
  const namespaceKey = namespaces.join('|');

  const setLanguage = useCallback(
    async (language: Language): Promise<LanguagePreferenceOutcome> => {
      const wanted = namespaceKey ? (namespaceKey.split('|') as Namespace[]) : [];

      // 0. Τα κείμενα της οθόνης που κοιτάζει **τώρα** ο χρήστης.
      //    ⚠️ Μη μοιραίο: αν αποτύχει ένα namespace, η γλώσσα αλλάζει ούτως ή
      //    άλλως και το i18next πέφτει στα ελληνικά για τα κλειδιά που λείπουν —
      //    προτιμότερο από επιλογέα που «δεν κάνει τίποτα».
      await Promise.all(
        wanted.map((namespace) =>
          loadNamespace(namespace, language).catch((error: unknown) => {
            logger.warn('Απέτυχε η προφόρτωση κειμένων πριν την αλλαγή γλώσσας', {
              error,
              data: { namespace, language },
            });
          }),
        ),
      );

      // 1. Η οθόνη. Το `changeLanguage` της lazy-config προφορτώνει τα κρίσιμα
      //    namespaces **πριν** αλλάξει γλώσσα, ώστε να μη βαφτούν ωμά κλειδιά.
      await applyLanguageToUi(language);

      // 2. Η περιήγηση. Το `config.ts` το διαβάζει στο επόμενο boot.
      safeSetItem(STORAGE_KEYS.PREFERRED_LANGUAGE, language);

      // 3. Ο διακομιστής — μόνο για γλώσσες που διαβάζει άνθρωπος.
      //
      // ⚠️ Ο έλεγχος **δεν** είναι διπλός με τον τύπο του `setLanguage` της
      // υπηρεσίας: εκείνος απαγορεύει τη **συγγραφή** λάθους κλήσης, αυτός
      // απαντά τι κάνουμε με μια **έγκυρη** επιλογή του επιλογέα ανάπτυξης.
      if (!isHumanLanguage(language)) return { kind: 'instrument' };
      if (!userId || !db) return { kind: 'anonymous' };

      try {
        userNotificationSettingsService.initialize(db);
        await userNotificationSettingsService.setLanguage(userId, language);
        return { kind: 'persisted' };
      } catch (error) {
        // 🔴 Η οθόνη **έχει ήδη αλλάξει** και μένει έτσι. Η μόνη συνέπεια είναι
        // ότι τα αυτόματα email θα φύγουν στην προηγούμενη γλώσσα — σύμπτωμα που
        // εμφανίζεται ώρες αργότερα και δεν θα συνδεόταν ποτέ με αυτή τη στιγμή
        // αν δεν καταγραφόταν εδώ.
        logger.error('Η γλώσσα άλλαξε στην οθόνη αλλά ΔΕΝ αποθηκεύτηκε', {
          error,
          data: { language, userId },
        });
        return { kind: 'not-persisted', error };
      }
    },
    [userId, namespaceKey],
  );

  return { setLanguage };
}

export default useLanguagePreference;
