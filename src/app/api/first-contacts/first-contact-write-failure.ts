import { NextResponse } from 'next/server';

/**
 * Το σώμα των δύο κοινών αστοχιών.
 *
 * ⚠️ **Υποσύνολο** και των δύο ενώσεων απάντησης (`FirstContactResponse`,
 * `WithdrawalResponse`) — το `NextResponse<Body>` κρατά το `Body` σε θέση **ιδιότητας**,
 * άρα η ανάθεση προς την ευρύτερη ένωση είναι τυπικά ασφαλής.
 */
export type FirstContactWriteFailureBody =
  /** 🔴 **Δεν μάθαμε** — ποτέ ίδιο με «δεν υπάρχει» ή «δεν επιτρέπεται» (N.12). */
  | { readonly error: 'CONTACT_UNVERIFIED' }
  | { readonly error: 'WRITE_FAILED' };

/**
 * **Η μία απάντηση στις δύο αστοχίες που κάθε γραφέας της πράξης μοιράζεται.**
 *
 * 🔑 Δέχεται **ακριβώς** τα δύο `kind` που κουβαλούν και τα δύο αποτελέσματα υπηρεσίας,
 * ώστε ο καλών να μπορεί να γράψει `case 'unavailable': case 'failed':` — δηλαδή το
 * κλειστό σύνολο του `switch` μένει **στη διαδρομή**, όπου διαβάζεται μαζί με τις
 * υπόλοιπες καταστάσεις της, και **δεν** μεταναστεύει εδώ.
 */
export function firstContactWriteFailure(
  kind: 'unavailable' | 'failed',
): NextResponse<FirstContactWriteFailureBody> {
  return kind === 'unavailable'
    ? NextResponse.json({ error: 'CONTACT_UNVERIFIED' } as const, { status: 503 })
    : NextResponse.json({ error: 'WRITE_FAILED' } as const, { status: 500 });
}
