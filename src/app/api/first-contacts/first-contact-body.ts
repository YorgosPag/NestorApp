import { z } from 'zod';

/**
 * **Προς ποιον στρέφεται η πράξη** — διακριτή ένωση, ίδια με τον τύπο.
 *
 * 🔑 **`discriminatedUnion` και όχι δύο προαιρετικά πεδία**: ένα
 * `{listingId?, agencyCompanyId?}` θα επέτρεπε **και τα δύο** ή **κανένα** στο σύρμα —
 * δύο καταστάσεις που δεν υπάρχουν στον κόσμο, και που ο γραφέας θα έπρεπε να θυμάται
 * να αποκλείσει. Εδώ είναι **ανέκφραστες**.
 */
export const firstContactTargetSchema = z.discriminatedUnion('kind', [
  z.object({
    kind: z.literal('listing'),
    listingId: z.string().max(128),
  }),
  z.object({
    kind: z.literal('professional'),
    agencyCompanyId: z.string().max(128),
  }),
]);

/**
 * **Τα στοιχεία που δίνει ο ζητών** — όσα **εκείνος** διάλεξε (ΠΕ4).
 *
 * ⚠️ **Καμία ταυτότητα χρήστη στο σχήμα, και είναι δομικό**: το `seekerUserId` το
 * γράφει ο γραφέας από την **απόδειξη**. Δεν υπάρχει πεδίο να ζητήσει κάποιος να
 * γραφτεί πράξη στο όνομα άλλου — άρα η κατάχρηση δεν απαγορεύεται, είναι **ανέκφραστη**.
 *
 * 🔑 **Το `email` ΔΕΝ περνά από `z.string().email()`**: το ερώτημα *«έχει τρόπο να
 * απαντηθεί;»* το κρίνει το αμετάβλητο `contact-no-channel`. Ένας έλεγχος μορφής εδώ
 * θα απέρριπτε **ολόκληρη την πράξη** για ένα τυπογραφικό, με μήνυμα «κακό σώμα» —
 * ενώ ο άνθρωπος έχει δώσει και τηλέφωνο.
 */
export const seekerDisclosureSchema = z.object({
  displayName: z.string().max(200),
  email: z.string().max(320).nullable(),
  phone: z.string().max(64).nullable(),
  acceptsPlatformMessages: z.boolean(),
});

/**
 * ⚠️ **Το `demandId` είναι `nullable`, ΟΧΙ `optional`** — και η διαφορά είναι
 * σημασιολογική: *«δεν έχω δηλώσει ζήτηση»* είναι **ρητή δήλωση** του πελάτη, όχι
 * πεδίο που ξέχασε. Ένα `optional` θα έκανε τη σιωπή και την άρνηση **αδιάκριτες** —
 * το ίδιο σχήμα με το `never-asked` ⇄ `owner-declined` της Α5.
 */
export const firstContactBodySchema = z.object({
  target: firstContactTargetSchema,
  demandId: z.string().max(128).nullable(),
  disclosure: seekerDisclosureSchema,
});

/**
 * **Η απόσυρση, ονομασμένη** (ΠΕ6).
 *
 * 🔑 **`z.literal('withdrawn')` και όχι κενό σώμα**: η μόνη μετάβαση που υπάρχει
 * γράφεται **ρητά** από τον πελάτη. Έτσι μια μελλοντική τρίτη κατάσταση —που το
 * `types/first-contact.ts` **απαγορεύει** ονομαστικά— δεν μπορεί να σταλεί «κατά
 * λάθος» σε πόρτα που δέχεται ό,τι της έρθει.
 */
export const firstContactWithdrawalSchema = z.object({
  lifecycle: z.literal('withdrawn'),
});
