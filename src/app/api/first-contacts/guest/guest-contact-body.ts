/**
 * @fileoverview **ΤΟ ΣΩΜΑ ΤΩΝ ΔΥΟ ΔΗΜΟΣΙΩΝ ΠΟΡΤΩΝ** — το σύνορο, εκτελέσιμο.
 * @related app/api/first-contacts/guest/route.ts · ADR-844
 * @module app/api/first-contacts/guest/guest-contact-body
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΞΑΝΑΧΡΗΣΙΜΟΠΟΙΕΙ ΤΟ `firstContactBodySchema` **ΑΥΤΟΥΣΙΟ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η δήλωση που στέλνει ο **φιλοξενούμενος** είναι **η ίδια** με του συνδεδεμένου —
 * ίδιος στόχος, ίδια ζήτηση, ίδια στοιχεία. Ένα δεύτερο σχήμα εδώ θα ήταν δεύτερη
 * απάντηση στο *«τι είναι δήλωση»*, ελεύθερη να αποκλίνει στην πρώτη προσθήκη:
 * ο συνδεδεμένος θα έστελνε πεδίο που ο ανώνυμος θα **έχανε σιωπηλά** (το zod
 * αφαιρεί ό,τι δεν δηλωθεί) — και κανείς δεν θα το έβλεπε.
 *
 * ⇒ **Ό,τι προστίθεται στην πράξη, το παίρνουν και οι δύο πόρτες.** Χωρίς να το
 * θυμηθεί κανείς.
 *
 * **Layering**: leaf — μόνο zod. Κανένα `server-only`, καμία ανάγνωση, κανένα ρολόι.
 */

import { z } from 'zod';

import { firstContactBodySchema } from '../first-contact-body';

/** Η υποβολή του φιλοξενούμενου — **ταυτόσημη** με του συνδεδεμένου. */
export const guestContactBodySchema = firstContactBodySchema;

/**
 * **Η επιβεβαίωση με τον εξαψήφιο κωδικό** (πόρτα Β).
 *
 * 🔑 **Απαιτεί ΚΑΙ το `invitationId`, και εκεί ζει η ασφάλεια των έξι ψηφίων.** Ο
 * κωδικός μόνος του θα ήταν «ένα εκατομμύριο συνδυασμοί για ολόκληρο το σύστημα»·
 * με το αναγνωριστικό, είναι «ένα εκατομμύριο για **μία** πρόσκληση, με **πέντε**
 * δοκιμές». Το αναγνωριστικό το κρατά η **ανοιχτή καρτέλα** — δεν ταξιδεύει σε email.
 *
 * ⚠️ **Κανένα `regex(/^\d{6}$/)` εδώ, και είναι απόφαση.** Ο άνθρωπος αντιγράφει
 * `472 913` με το κενό, ή αφήνει κενό στην αρχή. Ο έλεγχος μορφής στο σύνορο θα του
 * έλεγε **«κακό σώμα»** για κάτι που είναι **σωστό**· ο επαληθευτής κάνει `trim()` και
 * απαντά *«λάθος κωδικός»* — ονομαστικά, με τις δοκιμές του να μετρούν. Ίδιο σκεπτικό
 * με το «κανένα `min(1)`» της αδελφής πόρτας.
 */
export const guestConfirmBodySchema = z.object({
  invitationId: z.string().max(128),
  code: z.string().max(32),
});
