/**
 * «Ανήκει ΑΥΤΗ η επαφή;» — η ερώτηση και η **μία** απάντηση του πεδίου ορισμού
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΥΠΗΡΧΕ ΠΡΙΝ (μετρημένο 2026-08-01, ADR-742 §7octies)
 * ─────────────────────────────────────────────────────────────────────────────
 * Ο πόρος `contact` είχε **τέσσερα** σημεία μισογραμμένης μεταμφίεσης, γραμμένα
 * σε **δύο** διαφορετικά σχήματα σύρματος, με **δύο** διαφορετικά δόγματα
 * υπεργραφείου — για το **ίδιο** `contacts/{id}`:
 *
 * | Σημείο | σχήμα | bypass |
 * |---|---|---|
 * | `[contactId]/route.ts:74` (GET) | `NextResponse` + `contactId` | **όχι** |
 * | `[contactId]/properties/route.ts:153` | `NextResponse` + `contactId` | **όχι** |
 * | `identity-impact-preview/route.ts:50` | `ApiError` | **ναι** |
 * | `service-identity-impact-preview/route.ts:50` | `ApiError` | **ναι** |
 * | `route.ts` DELETE (μέσω `softDelete`) | — | **ναι** |
 *
 * Και τα τέσσερα απαντούσαν `403 'Access denied - Contact not found'` ενώ ο
 * γνήσιος κλάδος απαντά `404 'Contact not found'`: **η μισογραμμένη μεταμφίεση**
 * του ADR-742 §7sexies, ίδια αυτολεξεί με των έργων. Σωστό κείμενο, λάθος
 * κωδικός, περιττό πρόθεμα ⇒ ο καλών ξεχωρίζει τα δύο «όχι» με **οποιοδήποτε**
 * από τα δύο πεδία, άρα το `id` επιβεβαιώνεται ως υπαρκτό.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΟ ΔΟΓΜΑ BYPASS: ΓΙΑΤΙ ΕΝΟΠΟΙΕΙΤΑΙ **ΜΕ** BYPASS — ΚΑΙ ΤΙ ΧΡΕΟΣ ΜΕΝΕΙ
 * ─────────────────────────────────────────────────────────────────────────────
 * Δύο δόγματα στον ίδιο πόρο **δεν** μπορούν να μείνουν: η ασυμμετρία ήταν
 * μάλιστα προς τη **λάθος** κατεύθυνση — ο υπεργραφέας **δεν** μπορούσε να
 * διαβάσει ξένη επαφή (`GET`), αλλά **μπορούσε** να τρέξει πάνω της
 * προεπισκόπηση επίπτωσης ταυτότητας, που διαβάζει **σχέσεις ολόκληρης** της
 * επαφής. Το πιο διεισδυτικό μονοπάτι ήταν το πιο ανοιχτό.
 *
 * Η ενοποίηση γίνεται **με** bypass, για ευθυγράμμιση με το
 * {@link checkProjectAccess} των έργων, το `requireDocInTenant` (§7septies, έξι
 * οντότητες) και τη μηχανή `softDelete` — δηλαδή με το **υπάρχον** δόγμα του
 * έργου (ADR-232). Η εναλλακτική (στένωση των 4 σημείων) θα έσπαγε
 * λειτουργικότητα υπεργραφείου χωρίς εντολή και θα έκανε το `contact` τη
 * **μοναδική** εξαίρεση σε ολόκληρο τον κώδικα.
 *
 * 🔴 **ΑΥΤΟ ΠΑΡΑΜΕΝΕΙ ΓΝΩΣΤΟ ΧΡΕΟΣ, ΟΧΙ ΛΥΣΗ** (ADR-742 §7ter.3). Η έρευνα
 * βιομηχανίας (2026-08-01) είναι ομόφωνη ότι το *standing* cross-tenant
 * προνόμιο είναι **το ίδιο το πρόβλημα**:
 *
 * - **Google Cloud** — μοντέλο *zero standing privilege*: «access to Customer
 *   Data is **denied by default** for all Google personnel»· όταν δίνεται είναι
 *   **προσωρινή**, απαιτεί **έγκυρη αιτιολόγηση**, και καταγράφεται στο Access
 *   Transparency· το Access Approval απαιτεί **έγκριση του ίδιου του πελάτη**.
 * - **Atlassian** — Tenant Context Service: το tenant επιβάλλεται «from the
 *   cloud edge through backend services»· πρόσβαση «only for the time required».
 * - **Γενική πρακτική SaaS** — break-glass με **JIT elevation**, χρονικά
 *   φραγμένη, με καταγεγραμμένο λόγο· *«never grant standing cross-tenant
 *   access»*.
 *
 * Ο κώδικας εδώ **δεν** υλοποιεί JIT — θα ήταν αλλαγή δόγματος σε **47 σημεία**
 * και απαιτεί απόφαση Giorgio (N.8). Αυτό που κάνει είναι να καταστήσει τη
 * μετάβαση **εφικτή**: η bypass απόφαση γίνεται **ονομασμένη κατάσταση**
 * ({@link ContactAccessVerdict}) αντί για σκόρπιο `!isSuperAdmin &&`, και
 * καταγράφεται **με τον λόγο** (`action`) σε **ένα** σημείο. Όταν έρθει η ώρα
 * του JIT, αλλάζει **αυτή η συνάρτηση** — όχι πέντε διαδρομές.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΓΙΑΤΙ ΔΥΟ ΕΡΓΟΣΤΑΣΙΑ ΚΑΙ ΟΧΙ ΕΝΑ
 * ─────────────────────────────────────────────────────────────────────────────
 * Ο πόρος απαντά με **δύο** σχήματα σύρματος που **δεν** ενοποιούνται εδώ:
 * η οικογένεια `ApiError` (τα preview) και η οικογένεια `NextResponse` με
 * `contactId` στο σώμα (`GET`, `properties`). Το δεύτερο είναι **δημόσιο
 * συμβόλαιο** του γνήσιου 404 — αλλάζοντάς το θα άλλαζε ο πελάτης.
 *
 * ⇒ Δύο εργοστάσια, **ένα** κείμενο ({@link CONTACT_NOT_FOUND_MESSAGE}). Το
 * καθένα παράγει **byte-προς-byte** ό,τι παρήγαγε ο γνήσιος κλάδος του δικού
 * του σχήματος, ώστε η μεταμφίεση να μην ξεχωρίζει σε **κανένα** πεδίο.
 *
 * 🔴 Το εργοστάσιο της οικογένειας `NextResponse` ζει σε **ξεχωριστό** αρχείο
 * (`./contact-not-found-response`) και **όχι εδώ**. Δεν είναι οργανωτική
 * προτίμηση: το `next/server` σέρνει μαζί του το runtime του Next, και σκέτο
 * `import` του **έσπασε** ολόκληρη τη σουίτα με `ReferenceError: Request is not
 * defined` — δηλαδή ο φύλακας θα γινόταν **αδοκίμαστος** σε περιβάλλον `node`.
 * Το «καθαρό module» δεν είναι στολίδι στο σχόλιο· είναι η προϋπόθεση για να
 * δοκιμάζεται η απόφαση ασφαλείας χωρίς πλαστό HTTP.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΓΙΑΤΙ ΚΑΘΑΡΟ MODULE (μηδέν Firebase, μηδέν `server-only`)
 * ─────────────────────────────────────────────────────────────────────────────
 * Ίδιος λόγος με τα έργα: ο φύλακας δέχεται το **φορτίο που ήδη διαβάστηκε** —
 * ποτέ δεν κάνει `get()`. Τα σημεία έχουν ήδη το έγγραφο στα χέρια τους· ένας
 * φύλακας που ξαναδιάβαζε θα έκανε δεύτερο `get()` ανά αίτημα (§7ter.4).
 *
 * @module app/api/contacts/_shared/contact-ownership
 * @see @/lib/auth/tenant-ownership — ο SSoT της ερώτησης (μην τον ξαναγράψεις)
 * @see ../../projects/_shared/project-ownership — το πρότυπο (§7sexies)
 * @see ADR-742 §3.3 (κανόνας αποκάλυψης) · §3.4 (ποιος αποφασίζει) · §7octies
 */

import { ApiError } from '@/lib/api/api-error-types';
import type { MaybeTenantOwned } from '@/lib/auth/tenant-ownership';
import {
  createOwnershipDecision,
  type ResourceAccessCaller,
  type ResourceAccessVerdict,
} from '@/lib/auth/resource-ownership-guard';

/**
 * Η διαδικασία απόφασης, δεμένη στο λεξιλόγιο των επαφών.
 *
 * ⚠️ **Μην ξαναγράψεις εδώ τη λογική** (bypass → owned → denied): ζει στο
 * `lib/auth/resource-ownership-guard.ts` ακριβώς για να μην έχει ο κάθε πόρος
 * δικό της αντίγραφο. Τρία αντίγραφα υπήρξαν και το `jscpd` τα βρήκε **καθαρά**,
 * επειδή τα ονόματα διέφεραν (§7octies).
 */
const decide = createOwnershipDecision('Contact', 'contactId');

/**
 * Το κείμενο του «δεν βρέθηκε» — **SSoT**.
 *
 * ⚠️ Είναι **ακριβώς** η τιμή που έγραφαν τα χειρόγραφα σημεία πριν τη
 * μετανάστευση, και στα **δύο** σχήματα σύρματος. Το σύρμα του γνήσιου «δεν
 * βρέθηκε» δεν αλλάζει — αλλιώς το ίδιο το κείμενο γίνεται μαντείο ύπαρξης.
 */
export const CONTACT_NOT_FOUND_MESSAGE = 'Contact not found';

/**
 * Εργοστάσιο «δεν βρέθηκε» για την οικογένεια **`ApiError`** (τα preview).
 *
 * Μηδέν ορίσματα **επίτηδες**: δεν υπάρχει τιμή που θα μπορούσε να διαφέρει
 * ανάμεσα στον γνήσιο κλάδο (`!doc.exists`) και στην άρνηση ιδιοκτησίας, άρα
 * δεν υπάρχει τρόπος να αποκλίνουν χωρίς να αλλάξει **αυτό** το αρχείο.
 */
export function contactNotFound(): ApiError {
  return new ApiError(404, CONTACT_NOT_FOUND_MESSAGE);
}

/**
 * Ό,τι χρειάζεται η απόφαση από τον καλούντα. Δηλώνεται **δομικά** ώστε το
 * module να μένει καθαρό και ο φύλακας να δοκιμάζεται με σκέτα αντικείμενα.
 * Κάθε `AuthContext` το ικανοποιεί.
 */
export type ContactAccessCaller = ResourceAccessCaller;

/** Τι ρωτήθηκε — μπαίνει στο log ώστε η απόπειρα να εντοπίζεται. */
export interface ContactAccessSpec {
  /** Το φορτίο **όπως βγήκε από τη βάση**. Ποτέ `as Contact` — βλ. §7.5. */
  readonly contactData: MaybeTenantOwned | null | undefined;
  readonly caller: ContactAccessCaller;
  readonly contactId: string;
  /** Ποιο μονοπάτι ρώτησε, π.χ. `'view'`, `'properties'`, `'identity-impact-preview'`. */
  readonly action: string;
}

/**
 * Η ετυμηγορία. **Τρεις ονομασμένες καταστάσεις, όχι μια boolean** — μια
 * boolean σε κλήση ασφαλείας είναι αυτό που ρυθμίζεται λάθος στο review
 * (ADR-742 §3.2). Η μεσαία κατάσταση είναι επίσης το **σημείο εισόδου του
 * μελλοντικού JIT**: σήμερα περνά, αύριο θα απαιτεί ενεργή, χρονικά φραγμένη
 * ανύψωση.
 */
export type ContactAccessVerdict = ResourceAccessVerdict;

/**
 * **Η απόφαση (PDP)** για τις επαφές — ολική, χωρίς ρίψη, ώστε κάθε διαδρομή να
 * την επιβάλλει με **το δικό της** σχήμα σύρματος (PEP). ADR-742 §7ter.4.
 *
 * Η λογική ζει στο {@link createOwnershipDecision}· εδώ μένει μόνο το λεξιλόγιο
 * του πόρου, ώστε οι καλούντες να γράφουν `contactData` και όχι γενικό `data`.
 */
export function checkContactAccess(spec: ContactAccessSpec): ContactAccessVerdict {
  return decide({
    data: spec.contactData,
    caller: spec.caller,
    resourceId: spec.contactId,
    action: spec.action,
  });
}

/**
 * **Η επιβολή (PEP) για την οικογένεια `ApiError`** — ρίχνει το μεταμφιεσμένο
 * «δεν βρέθηκε» όταν η απόφαση είναι `denied`, αλλιώς επιστρέφει σιωπηλά.
 *
 * Το σφάλμα παράγεται από το {@link contactNotFound}, δηλαδή **τον ίδιο
 * constructor με τα ίδια ορίσματα** που χρησιμοποιεί ο γνήσιος κλάδος.
 */
export function requireContactAccess(spec: ContactAccessSpec): void {
  if (checkContactAccess(spec) === 'denied') {
    throw contactNotFound();
  }
}
