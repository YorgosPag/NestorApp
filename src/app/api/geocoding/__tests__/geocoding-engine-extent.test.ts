/**
 * Άγκυρες της **ΕΚΤΑΣΗΣ** — η τιμή που έφτανε πάντα και πεταγόταν πάντα.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΙ ΦΥΛΑΝΕ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ως τις 2026-09-02 το `boundingbox` του Nominatim ήταν **δηλωμένο** στον τύπο
 * `NominatimResult` — δηλαδή κάποιος το είχε δει — και **καμία γραμμή δεν το διάβαζε**.
 * Το κόστος δεν ήταν θεωρητικό: κάθε επιφάνεια που ήθελε να δείξει το αποτέλεσμα
 * μάντευε ζουμ από τον βαθμό ακρίβειας, δηλαδή απαντούσε με **σταθερά** μια ερώτηση
 * που ο πάροχος είχε ήδη απαντήσει **με μέτρηση, ανά αποτέλεσμα**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ Η ΠΑΓΙΔΑ ΕΙΝΑΙ Η **ΣΕΙΡΑ**, ΚΑΙ ΕΙΝΑΙ ΑΘΟΡΥΒΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο Nominatim δίνει **`[νότος, βορράς, δύση, ανατολή]`** — σειρά που **δεν** ταιριάζει
 * με καμία βιβλιοθήκη χάρτη (όλες θέλουν `[δ, ν, α, β]`). Μια αντιμετάθεση δεν πετάει
 * σφάλμα και δεν κοκκινίζει τύπο: **στέλνει τον χάρτη αλλού στον πλανήτη**, σιωπηλά.
 * Είναι κυριολεκτικά το σχήμα που το `geo-geojson.ts` περιγράφει ως *«τοποθετεί το
 * κτίριο σε άλλη ήπειρο χωρίς να το πει κανείς»*.
 *
 * 🔑 Γι' αυτό η μετάφραση γίνεται **μία φορά, στο σύνορο, σε ονομαστικά πεδία** — και
 * γι' αυτό η άγκυρα ελέγχει **ονόματα**, όχι θέσεις πίνακα: μια δοκιμή γραμμένη ως
 * `toEqual([40.6, 40.7, 22.9, 23.0])` θα ήταν πράσινη και για ανεστραμμένη ανάγνωση.
 */

/* global describe, it, expect */

import { extractExtent } from '../geocoding-engine-helpers';

/** Το ελάχιστο σχήμα που δέχεται ο μεταφραστής — ό,τι άλλο δεν τον αφορά. */
const resultWith = (boundingbox?: string[]) =>
  ({ lat: '40.6403', lon: '22.9444', display_name: 'Θεσσαλονίκη', boundingbox }) as Parameters<
    typeof extractExtent
  >[0];

describe('Κ1 — η έκταση φτάνει, και με τη ΣΩΣΤΗ σειρά', () => {
  /** ⛔ ΜΕΤΑΛΛΑΞΗ: αντιμετάθεσε δύο πεδία στην αποδόμηση ⇒ **κόκκινο**. */
  it('🔴 `[νότος, βορράς, δύση, ανατολή]` διαβάζεται ΟΝΟΜΑΣΤΙΚΑ', () => {
    expect(extractExtent(resultWith(['40.60', '40.68', '22.90', '22.99']))).toEqual({
      south: 40.6,
      north: 40.68,
      west: 22.9,
      east: 22.99,
    });
  });

  /**
   * 🔑 **Ο ΠΑΡΟΝΟΜΑΣΤΗΣ ΤΗΣ ΣΕΙΡΑΣ.** Χωρίς αυτόν, η Κ1 θα ήταν πράσινη ακόμη κι αν ο
   * μεταφραστής διάβαζε τα τέσσερα σε λάθος σειρά — αρκεί οι τιμές να έμοιαζαν. Εδώ οι
   * δύο άξονες είναι **αδύνατο** να μπερδευτούν: το γεωγραφικό πλάτος είναι αρνητικό
   * και το μήκος τριψήφιο, οπότε κάθε αντιμετάθεση δίνει τιμή **εκτός εύρους**.
   */
  it('🔴 οι δύο άξονες δεν μπερδεύονται — πλάτος και μήκος με ασύμβατα εύρη', () => {
    const extent = extractExtent(resultWith(['-33.95', '-33.85', '151.15', '151.25']));

    expect(extent?.south).toBeLessThan(0);
    expect(extent?.north).toBeLessThan(0);
    expect(extent?.west).toBeGreaterThan(100);
    expect(extent?.east).toBeGreaterThan(100);
  });
});

describe('Κ2 — η απουσία είναι ΔΕΔΟΜΕΝΟ, ποτέ `NaN`', () => {
  /**
   * 🔴 Ένα `parseFloat` που γυρίζει `NaN` **δεν πετάει**: θα ταξίδευε ως έγκυρη έκταση
   * μέχρι το `fitBounds`, και θα έριχνε τον χάρτη — μακριά από την αιτία, σε επιφάνεια
   * που δεν έφταιγε. Το `undefined` σημαίνει «δεν ξέρω την έκταση», απάντηση που ο
   * καταναλωτής **ξέρει** να χειριστεί (πέφτει στον πίνακα βαθμών).
   */
  it('🔴 μη αριθμητικό περιεχόμενο δίνει `undefined`, όχι έκταση με `NaN`', () => {
    expect(extractExtent(resultWith(['a', 'b', 'c', 'd']))).toBeUndefined();
    expect(extractExtent(resultWith(['40.60', '', '22.90', '22.99']))).toBeUndefined();
  });

  it('λείπον ή κολοβό `boundingbox` δίνει `undefined`', () => {
    expect(extractExtent(resultWith(undefined))).toBeUndefined();
    expect(extractExtent(resultWith([]))).toBeUndefined();
    expect(extractExtent(resultWith(['40.60', '40.68']))).toBeUndefined();
  });
});
