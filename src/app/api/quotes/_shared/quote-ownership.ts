/**
 * «Ανήκει ΑΥΤΗ η προσφορά;» — η δήλωση του πόρου `quote`
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΥΠΗΡΧΕ ΠΡΙΝ (μετρημένο 2026-08-01, ADR-742 §7undecies)
 * ─────────────────────────────────────────────────────────────────────────────
 * Ο πόρος είχε **τέσσερα** σημεία, με **τρεις** διαφορετικές υλοποιήσεις της
 * ίδιας ερώτησης — και, παραδόξως, **καμία** από αυτές δεν είχε μαντείο
 * ύπαρξης: όλες απαντούσαν `404 'Not found'` και στους δύο κλάδους.
 *
 * | σημείο | πώς ρωτούσε | τι έλειπε |
 * |---|---|---|
 * | `[id]/route.ts` | `getQuote(ctx.companyId, id)` | **τίποτα** — ήδη περιορισμένο στην πηγή (Βήμα Α) |
 * | `[id]/comments/route.ts` | `verifyQuoteOwnership()` → `=== companyId` | παγίδα κενού · χωρίς bypass |
 * | `[id]/notify-vendor` | `(snap.data() as …)?.companyId !== ctx.companyId` | παγίδα κενού · **λάθος ΣΕΙΡΑ** |
 * | `[id]/comments/[commentId]` | `data.companyId !== companyId` (υποσυλλογή) | παγίδα κενού |
 *
 * 🔴 **Το ακριβότερο δεν ήταν ο κωδικός — ήταν η ΣΕΙΡΑ.** Το `notify-vendor`
 * **έστελνε το email** και **μετά** ρωτούσε αν η προσφορά είναι δική σου. Ο
 * φύλακας *κλήθηκε*, απλώς αργά· κάθε test του θα έμενε πράσινο (§7.1, το ίδιο
 * σχήμα που περιγράφει ο `owned-doc-loader`).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΓΙΑΤΙ ΤΟ ΚΕΙΜΕΝΟ ΜΕΝΕΙ ΣΚΕΤΟ `'Not found'`
 * ─────────────────────────────────────────────────────────────────────────────
 * Είναι δελεαστικό να γίνει `'Quote not found'`, ώστε ο πόρος να γίνει
 * **σαρώσιμος** από την ομοιομορφία του anchor. Θα ήταν **λάθος**: και τα
 * **πέντε** σημεία της οικογένειας `quotes` γράφουν σήμερα `'Not found'`, οπότε
 * αλλάζοντας τα τέσσερα που αγγίζει η Ομάδα 6 θα **έσπαγε** η ομοιομορφία που
 * υπάρχει ήδη — ακριβώς το σφάλμα που κλείνει η §7septies, ανάποδα.
 *
 * ⇒ Δηλωμένη συνέπεια: ο `quote` **δεν** μπαίνει στους σαρωμένους πόρους του
 * `resource-concealment-anchor` (το `'Not found'` είναι πολύ γενικό για
 * κειμενική σάρωση — θα έβγαζε θόρυβο, και *ένα gate που βγάζει θόρυβο το
 * χαλαρώνει κάποιος*). Η κάλυψή του είναι η **καθολική απογραφή**.
 *
 * @module app/api/quotes/_shared/quote-ownership
 * @see @/lib/api/owned-resource-http — μία υλοποίηση, N δηλώσεις
 * @see ADR-742 §4, §7.1 (η σειρά), §7septies, §7undecies
 */

import 'server-only';

import { NextResponse } from 'next/server';
import { COLLECTIONS } from '@/config/firestore-collections';
import { defineOwnedResource } from '@/lib/api/owned-resource-http';

/**
 * ⚠️ Δηλωμένη διεύρυνση: ο bypass ρόλος αποκτά πρόσβαση (ADR-232). Κανένα από
 * τα τέσσερα σημεία δεν είχε κλάδο bypass — η εναλλακτική θα έκανε τις
 * προσφορές εξαίρεση απέναντι σε κάθε άλλον μεταναστευμένο πόρο. Παραμένει
 * **γνωστό χρέος** (§7ter.3), σε **ένα** σημείο απόφασης.
 */
export const quoteResource = defineOwnedResource({
  collection: COLLECTIONS.QUOTES,
  resourceLabel: 'Quote',
  idLogField: 'quoteId',
  notFoundMessage: 'Not found',
});

/**
 * Το **ένα** «δεν βρέθηκε» της οικογένειας `quotes` που απαντά με σκέτο
 * `{ error }` — `comments` (GET/POST) και `notify-vendor`.
 *
 * Το `[id]/route.ts` γράφει `{ success:false, error }` και **σωστά κρατά** το
 * δικό του σχήμα: εκεί ο περιορισμός γίνεται στην **πηγή** (`getQuote` δέχεται
 * `companyId`), οπότε δεν υπάρχει δεύτερος κλάδος να αποκλίνει.
 */
export function quoteNotFoundResponse(): NextResponse {
  return NextResponse.json({ error: quoteResource.notFoundMessage }, { status: 404 });
}
