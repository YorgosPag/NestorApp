/**
 * «Ανήκει ΑΥΤΟ το έργο;» — η ερώτηση και η **μία** απάντηση του πεδίου ορισμού
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΥΠΗΡΧΕ ΠΡΙΝ (μετρημένο 2026-08-01, ADR-742 §7sexies)
 * ─────────────────────────────────────────────────────────────────────────────
 * Δέκα σημεία απόφασης σε εννιά αρχεία έγραφαν **την ίδια** τριάδα με το χέρι:
 *
 * ```ts
 * if (!projectDoc.exists) throw new ApiError(404, 'Project not found');
 * const isSuperAdmin = isRoleBypass(ctx.globalRole);
 * if (!isSuperAdmin && projectData?.companyId !== ctx.companyId) {
 *   throw new ApiError(403, 'Access denied - Project not found');   // ← εδώ
 * }
 * ```
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 Η ΜΕΤΑΜΦΙΕΣΗ ΗΤΑΝ **ΜΙΣΟΓΡΑΜΜΕΝΗ** — ΚΑΙ ΓΙ' ΑΥΤΟ ΧΕΙΡΟΤΕΡΗ ΑΠΟ ΚΑΜΙΑ
 * ─────────────────────────────────────────────────────────────────────────────
 * Κάποιος **ήδη είχε καταλάβει** τον κανόνα αποκάλυψης: έβαλε το `'Project not
 * found'` μέσα στο κείμενο της άρνησης. Αλλά κράτησε τον **κωδικό 403** και
 * πρόσθεσε το πρόθεμα `'Access denied - '`. Αποτέλεσμα:
 *
 * | | γνήσιο «δεν βρέθηκε» | άρνηση ιδιοκτησίας |
 * |---|---|---|
 * | κωδικός | `404` | **`403`** ← προδίδει |
 * | μήνυμα | `Project not found` | **`Access denied - Project not found`** ← προδίδει |
 *
 * Δύο διαφορετικά σχήματα για τα δύο «δεν το παίρνεις» ⇒ ο καλών τα ξεχωρίζει
 * με **οποιοδήποτε** από τα δύο πεδία, άρα το `id` επιβεβαιώνεται ως υπαρκτό.
 * Είναι η §7quater **ανάποδα**: εκεί το κείμενο έλεγε «not found» ενώ το σχήμα
 * πρόδιδε· εδώ το κείμενο *προσποιείται* ενώ ο κωδικός προδίδει.
 *
 * ⇒ **Η μεταμφίεση κρίνεται στο ΟΛΟΚΛΗΡΟ ΣΧΗΜΑ — κωδικός + σώμα + μήνυμα.**
 * Γι' αυτό το «δεν βρέθηκε» παράγεται **μόνο** από το {@link projectNotFound}:
 * και ο γνήσιος κλάδος (`!doc.exists`) και η άρνηση καλούν το **ίδιο**
 * εργοστάσιο με **μηδέν** ορίσματα, οπότε δεν υπάρχει τρόπος να αποκλίνουν
 * χωρίς να αλλάξει **αυτό** το αρχείο (ADR-742 §7.1: η ταυτότητα είναι δομική,
 * όχι θέμα προσοχής).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ **ΔΕΝ** ΚΑΛΕΙΤΑΙ ΤΟ `concealCrossTenant` ΕΔΩ (ρητή απόφαση)
 * ─────────────────────────────────────────────────────────────────────────────
 * Το `concealCrossTenant` είναι **διαδικασία απόφασης πάνω σε ρόλο**: bypass →
 * ειλικρινές 403 · κάθε άλλος → σιωπή. Στις προμήθειες (Ομάδα 2) ο κλάδος
 * `reveal` είναι **ζωντανός**, γιατί εκεί η υπηρεσία ρίχνει για **όλους** —
 * ακόμη και για τον υπεργραφέα.
 *
 * Εδώ ο ρόλος έχει ήδη κριθεί **νωρίτερα και ισχυρότερα**: ο bypass καλών
 * **παίρνει το έγγραφο** και δεν φτάνει ποτέ σε άρνηση. Άρα κάθε καλών που
 * φτάνει στην άρνηση είναι **εξ ορισμού** μη-bypass, και το `reveal` δεν μπορεί
 * να εκτελεστεί. Δύο λόγοι το κάνουν λάθος επιλογή:
 *
 * 1. **Κώδικας που δεν εκτελείται δεν δοκιμάζεται — άρα σαπίζει.** Θα
 *    τεκμηρίωνε την πολιτική με μια γραμμή που κανένα test δεν μπορεί να
 *    πιάσει, και η επόμενη μετάλλαξη εκεί θα έμενε αόρατη.
 * 2. **Θα έλεγε ψέματα για το πού ζει η απόφαση.** Η απόφαση bypass λαμβάνεται
 *    στη {@link checkProjectAccess} — και *εκεί* πρέπει να φαίνεται, ώστε η
 *    μελλοντική μετάβαση σε JIT elevation (ADR-742 §7ter.3) να έχει **ένα**
 *    σημείο να αλλάξει, όχι δύο συνεννοημένα.
 *
 * ⇒ Η άρνηση είναι **σκέτο** {@link projectNotFound}. Ο κανόνας αποκάλυψης
 * (§3.3) τηρείται **αυστηρότερα**, όχι χαλαρότερα: όποιος θα δικαιούταν την
 * αλήθεια, την έχει ήδη πάρει ολόκληρη — με τη μορφή του ίδιου του εγγράφου.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΑΠΟΡΡΟΦΩΝΤΑΙ ΚΑΙ ΟΙ ΔΥΟ `log-only` ΚΛΑΔΟΙ ΤΟΥ ΥΠΕΡΓΡΑΦΕΙΟΥ
 * ─────────────────────────────────────────────────────────────────────────────
 * Η σάρωση της §7ter τους έβγαλε **έξω** από τα σημεία απόφασης — και σωστά:
 * `if (isSuperAdmin && projectData?.companyId !== ctx.companyId) logger.info(…)`
 * **γράφει log, δεν αποφασίζει**. Όμως το Βήμα 7 (κλείδωμα) βάζει το
 * `\.companyId !== ctx\.companyId` στα `forbiddenPatterns`, και **αυτό είναι
 * έλεγχος κειμένου**: οι δύο log-only κλάδοι το γράφουν αυτολεξεί. Αν έμεναν,
 * το κλείδωμα του πεδίου ορισμού θα ήταν αδύνατο.
 *
 * Άρα απορροφώνται ως **παρατήρηση**, όχι ως απόφαση: η ίδια συνάρτηση που
 * κρίνει την πρόσβαση είναι και η μόνη που ξέρει ότι ο υπεργραφέας κοιτάζει
 * ξένο έργο — γιατί είναι **η ίδια σύγκριση**, όχι δύο ανεξάρτητες.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΓΙΑΤΙ ΚΑΘΑΡΟ MODULE (μηδέν Firebase, μηδέν `server-only`)
 * ─────────────────────────────────────────────────────────────────────────────
 * Το καλούν **και** οι διαδρομές που έχουν ήδη διαβάσει με Admin SDK **και** ο
 * εκτελεστής των preview. Ο φύλακας δέχεται το **φορτίο** που ήδη διαβάστηκε —
 * ποτέ δεν κάνει `get()`. Γι' αυτό **δεν** χρησιμοποιείται το
 * `requireProjectInTenant` (ADR-255): είναι PDP+PEP+**PIP** μαζί (κάνει το ίδιο
 * το read), και τα δέκα σημεία έχουν **ήδη** το έγγραφο στα χέρια τους — θα
 * έκανε δεύτερο `get()` ανά αίτημα (ADR-742 §7ter.4).
 *
 * @module app/api/projects/_shared/project-ownership
 * @see @/lib/auth/tenant-ownership — ο SSoT της ερώτησης (μην τον ξαναγράψεις)
 * @see ADR-742 §3.3 (κανόνας αποκάλυψης) · §3.4 (ποιος αποφασίζει) · §7.1 (ταυτότητα)
 */

import { ApiError } from '@/lib/api/api-error-types';
import type { MaybeTenantOwned } from '@/lib/auth/tenant-ownership';
import {
  createOwnershipDecision,
  type ResourceAccessCaller,
  type ResourceAccessVerdict,
} from '@/lib/auth/resource-ownership-guard';

/**
 * Η διαδικασία απόφασης, δεμένη στο λεξιλόγιο των έργων.
 *
 * 🔄 **2026-08-01 (§7octies)**: η λογική (bypass → owned → denied) μετακόμισε
 * στο `lib/auth/resource-ownership-guard.ts`. Η Ομάδα 4 χρειαζόταν την **ίδια**
 * απόφαση για επαφές και κτήρια, και τα τρία αντίγραφα πέρασαν **καθαρά** από
 * το `jscpd` επειδή τα ονόματα διέφεραν (`projectData`/`contactData`/
 * `buildingData` = διαφορετικά tokens). Η δημόσια υπογραφή **δεν άλλαξε**.
 */
const decide = createOwnershipDecision('Project', 'projectId');

/**
 * Το κείμενο του «δεν βρέθηκε» — **SSoT**.
 *
 * Μπαίνει αυτούσιο στο γνήσιο **και** στο μεταμφιεσμένο, και το ίδιο κείμενο
 * χρησιμοποιεί και η διαδρομή `structure/[projectId]` που έχει **άλλο σχήμα
 * σύρματος** (`NextResponse.json` με `projectId` στο σώμα). Μια αναντιστοιχία
 * εδώ θα έκανε το ίδιο το κείμενο μαντείο ύπαρξης.
 *
 * ⚠️ Είναι **ακριβώς** η τιμή που έγραφαν τα δέκα χειρόγραφα σημεία πριν τη
 * μετανάστευση — το σύρμα του γνήσιου «δεν βρέθηκε» δεν αλλάζει.
 */
export const PROJECT_NOT_FOUND_MESSAGE = 'Project not found';

/**
 * Το **ένα** εργοστάσιο του «δεν βρέθηκε», για την οικογένεια που απαντά με
 * `ApiError` (εννιά από τα δέκα σημεία).
 *
 * Καλείται από **δύο** κλάδους που πρέπει να είναι πανομοιότυποι:
 *
 * 1. το έγγραφο **όντως** λείπει (`!doc.exists`)
 * 2. το έγγραφο υπάρχει αλλά **ανήκει αλλού** και ο καλών δεν δικαιούται να το
 *    μάθει ({@link requireProjectAccess})
 *
 * Μηδέν ορίσματα **επίτηδες**: δεν υπάρχει τιμή που θα μπορούσε να διαφέρει
 * ανάμεσα στους δύο κλάδους, άρα δεν υπάρχει τρόπος να αποκλίνουν. Το σύρμα
 * που παράγεται (`{ success:false, error, errorCode:'HTTP_404' }`) είναι
 * byte-προς-byte το ίδιο και στις δύο περιπτώσεις.
 */
export function projectNotFound(): ApiError {
  return new ApiError(404, PROJECT_NOT_FOUND_MESSAGE);
}

/**
 * Ό,τι χρειάζεται η απόφαση από τον καλούντα.
 *
 * Δηλώνεται **δομικά** αντί να εισαχθεί το `AuthContext` για δύο λόγους: το
 * module μένει καθαρό, και ο φύλακας δοκιμάζεται με σκέτα αντικείμενα αντί για
 * πλαστό context ολόκληρου του `withAuth`. Κάθε `AuthContext` το ικανοποιεί.
 */
export type ProjectAccessCaller = ResourceAccessCaller;

/** Τι ρωτήθηκε — μπαίνει στο log ώστε η απόπειρα να εντοπίζεται. */
export interface ProjectAccessSpec {
  /** Το φορτίο **όπως βγήκε από τη βάση**. Ποτέ `as Project` — βλ. παρακάτω. */
  readonly projectData: MaybeTenantOwned | null | undefined;
  readonly caller: ProjectAccessCaller;
  readonly projectId: string;
  /** Ποιο μονοπάτι ρώτησε, π.χ. `'view'`, `'update'`, `'address-impact-preview'`. */
  readonly action: string;
}

/**
 * Η ετυμηγορία. **Τρεις ονομασμένες καταστάσεις, όχι μια boolean** — μια
 * boolean σε κλήση ασφαλείας είναι αυτό που ρυθμίζεται λάθος στο review
 * (ADR-742 §3.2).
 */
export type ProjectAccessVerdict = ResourceAccessVerdict;

/**
 * **Η απόφαση (PDP)** — ολική, χωρίς ρίψη, ώστε κάθε διαδρομή να την επιβάλλει
 * με **το δικό της** σχήμα σύρματος (PEP). ADR-742 §7ter.4.
 *
 * Η σειρά των βημάτων **είναι** το συμβόλαιο:
 *
 * 1. **Bypass ρόλος ⇒ περνά**, και αν το έργο είναι ξένο **καταγράφεται**. Αυτό
 *    απορροφά τους δύο `log-only` κλάδους που πριν ήταν χωριστά `if` — η ίδια
 *    σύγκριση, μία φορά.
 * 2. **Ανήκει ⇒ περνά.**
 * 3. **Αλλιώς ⇒ `denied`**, με προειγηθείσα καταγραφή: η απόπειρα είναι σήμα
 *    ασφαλείας και πρέπει να επιβιώνει ακόμη κι αν ο καλών καταπιεί το σφάλμα.
 *
 * 🔴 **Δέχεται `MaybeTenantOwned`, όχι `Project`** — και αυτό είναι ουσία, όχι
 * χαλάρωση τύπου. Τα εννιά από τα δέκα σημεία έγραφαν
 * `{ ...doc.data() } as Project` και ρωτούσαν σκέτο `!==`: **ο τύπος υπόσχεται
 * `companyId: string`, η βάση δεν το εγγυάται** (ADR-742 §7.5). Καλών με
 * χαλασμένο token (`companyId: ''`) περνούσε σε κάθε έργο με κενό `companyId`.
 * Ρωτά πλέον {@link isPayloadOwnedByCompany}: **το κενό δεν είναι tenant, είναι
 * απουσία tenant** (§4).
 */
export function checkProjectAccess(spec: ProjectAccessSpec): ProjectAccessVerdict {
  return decide({
    data: spec.projectData,
    caller: spec.caller,
    resourceId: spec.projectId,
    action: spec.action,
  });
}

/**
 * **Η επιβολή (PEP) για την οικογένεια `ApiError`** — ρίχνει το μεταμφιεσμένο
 * «δεν βρέθηκε» όταν η απόφαση είναι `denied`, αλλιώς επιστρέφει σιωπηλά.
 *
 * Το σφάλμα παράγεται από το {@link projectNotFound}, δηλαδή **τον ίδιο
 * constructor με τα ίδια ορίσματα** που χρησιμοποιεί ο γνήσιος κλάδος.
 * Χειρόγραφο `new ApiError(404, 'Project not found')` εδώ θα ήταν ακριβώς η
 * μετάλλαξη που απαγορεύει το ADR-742 §3.4 — και θα περνούσε απαρατήρητη μέχρι
 * κάποιος να αλλάξει το ένα από τα δύο κείμενα.
 */
export function requireProjectAccess(spec: ProjectAccessSpec): void {
  if (checkProjectAccess(spec) === 'denied') {
    throw projectNotFound();
  }
}
