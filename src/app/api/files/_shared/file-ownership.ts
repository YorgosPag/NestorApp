/**
 * «Ανήκει ΑΥΤΟ το αρχείο;» — η δήλωση του πόρου `file`
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΙ ΒΡΕΘΗΚΕ (μετρημένο 2026-08-01, ADR-742 §7undecies)
 * ─────────────────────────────────────────────────────────────────────────────
 * Ο πόρος `file` δεν είχε **ένα** πρόβλημα αλλά **δύο τάξεις** προβλήματος, και
 * η δεύτερη είναι βαρύτερη από όλη την υπόλοιπη Ομάδα 6:
 *
 * | διαδρομή | δικαίωμα | φύλακας ιδιοκτησίας |
 * |---|---|---|
 * | `floorplans/process` | `floorplans:floorplans:process` | ναι — αλλά **403** (μαντείο) + **παγίδα του κενού** |
 * | `floorplans/scene` | `floorplans:floorplans:process` | ναι — ίδια δύο ελαττώματα |
 * | `files/[fileId]/download` | `dxf:files:view` | **ΚΑΝΕΝΑΣ** |
 * | `files/[fileId]/excel-preview` | **κανένα** | **ΚΑΝΕΝΑΣ** |
 *
 * Οι δύο τελευταίες **δεν** ήταν μαντείο ύπαρξης· ήταν **διαρροή
 * περιεχομένου** — το ίδιο σχήμα με τις τέσσερις αφύλακτες `contact preview`
 * της §7octies. Οποιοσδήποτε συνδεδεμένος χρήστης, **οποιασδήποτε** εταιρείας,
 * κατέβαζε ξένο αρχείο δίνοντας το id του· το `excel-preview` το απέδιδε και σε
 * **HTML** χωρίς να ζητά καν δικαίωμα. Το `_ctx` τους ήταν αχρησιμοποίητο,
 * δηλαδή ο tenant **δεν συμμετείχε καθόλου** στην απάντηση.
 *
 * 🔴 Δεν τις έδειξε καμία σάρωση της εκστρατείας — και **δεν γινόταν**: όλοι οι
 * ανιχνευτές ψάχνουν **λάθος σύγκριση**, και εκεί δεν υπήρχε σύγκριση **καθόλου**.
 * Βρέθηκαν όταν ο πόρος `file` επρόκειτο να δηλωθεί «κρυμμένος» και μετρήθηκαν
 * οι διαδρομές του μία-μία. *Η ομοιομορφία είναι ιδιότητα ΠΟΡΟΥ* (§7septies):
 * δηλώνοντας τον πόρο, οφείλεις να μετρήσεις **κάθε** διαδρομή του.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠️ Η ΠΑΓΙΔΑ ΤΟΥ ΚΕΝΟΥ ΕΔΩ ΕΙΝΑΙ **ΡΗΤΗ**, ΟΧΙ ΑΠΡΟΣΕΞΙΑ (§4)
 * ─────────────────────────────────────────────────────────────────────────────
 * Και οι δύο floorplan διαδρομές έγραφαν `if (fileData.companyId && …)` — δηλαδή
 * **παρέκαμπταν τον έλεγχο επίτηδες** όταν το αρχείο δεν είχε tenant. Αρχείο
 * χωρίς `companyId` περνούσε για **οποιονδήποτε**. Είναι το **πέμπτο και έκτο**
 * σημείο με το ίδιο σφάλμα (§7quinquies, §7octies, §7decies ×2).
 *
 * ⇒ Δηλωμένη συνέπεια: αρχεία **χωρίς** `companyId` παύουν να είναι ορατά σε
 * κανονικό χρήστη. Η θεραπεία **υπάρχει ήδη** στο repo:
 * `POST /api/admin/backfill-file-companyid`. Το κενό δεν είναι tenant.
 *
 * @module app/api/files/_shared/file-ownership
 * @see @/lib/api/owned-resource-http — μία υλοποίηση, N δηλώσεις
 * @see ADR-742 §3.3, §4, §7octies (η διαρροή περιεχομένου), §7undecies
 */

import { COLLECTIONS } from '@/config/firestore-collections';
import { defineOwnedResource } from '@/lib/api/owned-resource-http';

/**
 * ⚠️ Το κείμενο είναι **ακριβώς** αυτό που έγραφαν και οι τέσσερις διαδρομές
 * στον γνήσιο κλάδο τους (`'File not found'`). Το σχήμα γύρω του **διαφέρει**
 * ανά διαδρομή (`{ success, error, errorCode }` στο `process`, σκέτο
 * `{ error }` στο `download`) και **πρέπει** να διαφέρει: η μεταμφίεση οφείλει
 * να μοιάζει με το γνήσιο «δεν βρέθηκε» **ΤΗΣ ΙΔΙΑΣ** διαδρομής (§7.1).
 */
export const fileResource = defineOwnedResource({
  collection: COLLECTIONS.FILES,
  resourceLabel: 'File',
  idLogField: 'fileId',
  notFoundMessage: 'File not found',
});
