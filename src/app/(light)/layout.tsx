/**
 * Το κέλυφος των **δημόσιων** οθονών (ADR-777 §8.12 · §8.13).
 *
 * 🔴 **ΤΟ `<main>` ΕΦΥΓΕ ΑΠΟ ΕΔΩ, ΚΑΙ ΗΤΑΝ ΕΛΑΤΤΩΜΑ.** Το §8.12.10 #5 το είχε
 * μετρήσει και **δηλώσει ανοιχτό**: αυτό το αρχείο απέδιδε `<main>` **και** οι τρεις
 * δημόσιες σελίδες αποδίδουν δικό τους ⇒ **δύο landmarks `main` ανά σελίδα**, ενώ το
 * WCAG επιτρέπει **ένα**. (Πριν τη μετακόμιση του κελύφους ήταν **τρία** — η
 * μετακόμιση δεν το γέννησε, το **αποκάλυψε**.) Ο ιδιοκτήτης του `<main>` είναι η
 * **σελίδα**, γιατί μόνο εκείνη ξέρει τι είναι το κύριο περιεχόμενό της.
 *
 * 🔑 **ΓΙΑΤΙ ΕΓΙΝΕ ΣΤΗΛΗ FLEX.** Η κεφαλίδα καταναλώνει ύψος. Η οθόνη 2 είναι
 * **χάρτης + λίστα σε πλήρες παράθυρο**: με `h-screen` κάτω από κεφαλίδα, το κάτω
 * μέρος του χάρτη θα έβγαινε **εκτός οθόνης** και θα εμφανιζόταν μπάρα κύλισης σε
 * επιφάνεια που σχεδιάστηκε να μην κυλά. Το ύψος το κατέχει **το κέλυφος** και οι
 * σελίδες ζητούν «ό,τι περισσεύει», που είναι η **μόνη** εκδοχή που μένει σωστή όταν
 * αλλάξει το ύψος της κεφαλίδας.
 *
 * 🔴 **ΚΑΙ ΑΥΤΗ Η ΠΑΡΑΓΡΑΦΟΣ ΗΤΑΝ ΨΕΥΔΗΣ ΜΕΧΡΙ ΤΙΣ 2026-08-25** (ADR-797 ΦΑΣΗ Γ).
 * Έλεγε ότι «το ύψος το κατέχει το κέλυφος» ενώ η γραμμή από κάτω έγραφε
 * `min-h-screen` — δηλαδή **ελάχιστο**, όχι κατεχόμενο ύψος. Το `flex-1` της σελίδας
 * δεν είχε τι να μοιράσει (**CSS 2.2 §10.5**: containing block χωρίς ρητό ύψος ⇒ το
 * παιδί υπολογίζεται ως `auto`), ο χάρτης πήρε **φυσικό** ύψος και έσπρωξε τη σελίδα
 * **161px** κάτω από την οθόνη: η 7η πινέζα ήταν αόρατη ενώ η λογιστική από πάνω της
 * έγραφε «7 στον χάρτη». **Η περιγραφή της διόρθωσης ΗΤΑΝ η απόκλιση** — το σχήμα που
 * σε αυτό το repo έχει πληρωθεί σε CHECK 3.34 · 3.37 · 3.49 · 3.57.
 *
 * ⚠️ **ΜΗΝ ξαναγράψεις ύψος παραθύρου εδώ.** Το `data-shell-frame` είναι η **μόνη**
 * αυθεντία ύψους (`shell-surface.css` §5)· ο κανόνας **Υ1** του CHECK 3.63 μπλοκάρει
 * χειρόγραφο `h-screen`/`min-h-screen` σε ρίζα γειτονιάς. Η προεπιλογή είναι
 * **δάπεδο** — το έγγραφο κυλά· κλειδώνει **μόνο** σελίδα που το δηλώνει.
 */

import { TooltipProvider } from '@/components/ui/tooltip';
import { COLOR_BRIDGE } from '@/design-system/color-bridge';
import { ShellSurface } from '@/core/containers/ShellSurface';
import { PublicSiteHeader } from '@/components/public-site/PublicSiteHeader';
import { LegalLinksNav } from '@/components/legal/LegalLinksNav';
import { LandingHeroesProvider } from '@/components/shared/landing-hero/LandingHeroesProvider';
import { readLandingHeroes } from '@/services/landing-hero/landing-hero-reader';

export default async function LightLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // 🖼️ ADR-881 §4.3 — οι δημοσιευμένοι ήρωες, διαβασμένοι ΕΔΩ (server) ώστε το URL να είναι μέσα
  //    στο HTML (LCP). Μνήμη με tag + δίχτυ: ποτέ δεν πετά, κάθε αποτυχία ⇒ ενσωματωμένες εικόνες.
  const heroes = await readLandingHeroes();

  return (
    <div data-shell-frame className={`w-full ${COLOR_BRIDGE.bg.primary}`}>
    <TooltipProvider delayDuration={300}>
      {/*
        🔴 **ΖΩΝΤΑΝΗ ΒΛΑΒΗ 2026-08-26 (ADR-813)**: «`Tooltip` must be used within
        `TooltipProvider`» ⇒ **ολόκληρη η διαδρομή** έπεφτε στο `global-error`.

        Μετρημένο: **81 components** του `src/` χρησιμοποιούν `<Tooltip>` **χωρίς
        δικό τους provider** — η σύμβαση της εφαρμογής είναι *«τον δίνει το
        layout»*, και τον έδιναν **τρεις** γειτονιές (`(app)` · `(auth)` ·
        `(bare)`)· οι `(light)` και `(me)` **ΟΧΙ**. Το ADR-809 έβαλε εδώ τα
        καθολικά utilities, και το ADR-797 τις πρώτες πλούσιες σελίδες.

        ⚠️ **ΔΕΝ μπήκε μέσα στο `ShellUtilities`**: θα ήταν **έκτο** αντίγραφο και
        θα κάλυπτε **μόνο** τα utilities — όχι τα υπόλοιπα 80 components της
        σελίδας. Η απόφαση ανήκει εκεί όπου την έχει ήδη η εφαρμογή.

        ⚠️ Το `delayDuration={300}` είναι **ταυτόσημο** με των άλλων τριών.
        🔶 Ανοιχτό (ADR-813 §8): **πέντε** πανομοιότυπες δηλώσεις — η σωστή
        θεραπεία είναι **μία** στη ρίζα· δεν έγινε εδώ γιατί το `app/layout.tsx`
        το κρατά άλλος πράκτορας και η βλάβη ήταν ζωντανή.
      */}
      <PublicSiteHeader />
      {/*
        🏛️ Ο ΔΙΑΔΡΟΜΟΣ (ADR-797 ΦΑΣΗ Β). Το ίδιο `data-shell-surface` με το κέλυφος,
        η ίδια ρευστή συνάρτηση, οι ίδιοι πόλοι — και **μηδέν** νέο CSS: το
        `--shell-sidebar-occupied` δεν ορίζεται εδώ, οπότε πέφτει στο `0px` και το
        pane γίνεται όλο το παράθυρο. Αποδεδειγμένο ζωντανά 2026-08-25.

        ⚠️ **ΕΞΩ από την κεφαλίδα, επίτηδες.** Η κεφαλίδα είναι πλάτους οθόνης και
        έχει δικό της εσωτερικό κενό· ένας διάδρομος γύρω της θα την ξεκολλούσε από
        την άκρη — άλλο σχέδιο, όχι «λίγο κενό».

        ⚠️ **ΚΑΝΕΝΑ `measure` εδώ.** Η γειτονιά είναι **ετερογενής**, μετρημένα: η
        αρχική είναι κεντραρισμένο μενού, η καρτέλα ακινήτου διάταξη δύο στηλών, τα
        αποτελέσματα **χάρτης σε πλήρες παράθυρο**. Ένα ταβάνι για όλες θα ήταν
        λάθος στις τρεις από τις τέσσερις — γι' αυτό το δηλώνει **η σελίδα**.
      */}
      <ShellSurface className="flex flex-1 flex-col">
        {/* ⚠️ Ο provider ΔΕΝ προσθέτει κόμβο DOM — η αλυσίδα `:has(> [data-shell-surface] > …)` μένει ανέπαφη. */}
        <LandingHeroesProvider heroes={heroes}>{children}</LandingHeroesProvider>
      </ShellSurface>
      {/*
        ⚖️ **ΤΟ ΥΠΟΣΕΛΙΔΟ ΤΟΥ ΔΗΜΟΣΙΟΥ ΙΣΤΟΤΟΠΟΥ** (ADR-861 Φ2, απόφαση Giorgio 2026-09-16).

        🔴 **Το κενό που έκλεισε**: οι νομικοί σύνδεσμοι ζούσαν στο πλαϊνό μενού του `(app)`
        και κάτω από την κάρτα σύνδεσης — δηλαδή **πουθενά** για τον ανώνυμο επισκέπτη της
        αναζήτησης, της αγγελίας ή της σελίδας επαγγελματία. Το Π.Δ. 131/2003 άρθ. 4 ζητά
        «**εύκολη, άμεση και συνεχή** πρόσβαση», και η νομολογία το διαβάζει ως «σε όλο τον
        ιστότοπο» — όχι μόνο εκεί όπου υπάρχει λογαριασμός.

        🔑 **ΓΙΑΤΙ ΕΙΝΑΙ ΑΣΦΑΛΕΣ ΣΕ ΚΛΕΙΔΩΜΕΝΗ ΕΠΙΦΑΝΕΙΑ (το `/search/results`)**: το
        `[data-shell-frame]` είναι **στήλη flex** (`shell-surface.css` §5) και στο κλείδωμα
        παίρνει `block-size: 100svh` + `overflow: clip`. Ένα αδελφό υποσέλιδο **μοιράζεται**
        αυτό το ύψος: ο διάδρομος (`flex-1`) παίρνει ό,τι περισσεύει, ο χάρτης μικραίνει
        κατά το ύψος του υποσέλιδου και **καμία κύλιση δεν γεννιέται** — η βλάβη των 48px
        του `(auth)` και των 161px της ΦΑΣΗΣ Γ ήταν ακριβώς το αντίθετο σχήμα (σελίδα που
        **ξαναδήλωνε** ύψος παραθύρου, εδώ δεν δηλώνεται κανένα).
        ⚠️ Η αλυσίδα του `:has(> [data-shell-surface] > [data-shell-viewport])` μένει
        **ανέπαφη**: το υποσέλιδο είναι **αδελφός** του διαδρόμου, όχι κρίκος της.

        ⚠️ **ΜΕΣΑ στο κάδρο, ΕΞΩ από τον διάδρομο**: ο διάδρομος ανήκει στο **περιεχόμενο**
        (ADR-797) — ένα υποσέλιδο πλάτους οθόνης μέσα του θα ήταν δεύτερη αυθεντία κενού.
      */}
      <footer className="w-full border-t border-border px-4 py-2">
        <LegalLinksNav variant="standalone" />
      </footer>
    </TooltipProvider>
    </div>
  );
}
