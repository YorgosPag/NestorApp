/**
 * Το κέλυφος των **δημόσιων** οθονών (ADR-777 §8.12 · §8.13).
 *
 * 🔴 **ΤΟ `<main>` ΕΦΥΓΕ ΑΠΟ ΕΔΩ, ΚΑΙ ΗΤΑΝ ΕΛΑΤΤΩΜΑ.** Το §8.12.10 #5 το είχε
 * μετρήσει και **δηλώσει ανοιχτό**: αυτό το αρχείο απέδιδε `<main>` **και** οι τρεις
 * δημόσιες σελίδες αποδίδουν δικό τους ⇒ **δύο landmarks `main` ανά σελίδα**, ενώ το
 * WCAG επιτρέπει **ένα**. (Πριν τη μετακόμιση του κελύφους ήταν **τρία** — η
 * μετακόμιση δεν το γέννησε, το **αποκάλυψε**.) Ο ιδιοκτήτης του `<main>` είναι η
 * **σελίδα**, γιατί μόνο εκείνη ξέρει τι είναι το κύριο περιεχόμενό της.
 *
 * 🔑 **ΓΙΑΤΙ ΕΓΙΝΕ ΣΤΗΛΗ FLEX.** Η κεφαλίδα καταναλώνει ύψος. Η οθόνη 2 είναι
 * **χάρτης + λίστα σε πλήρες παράθυρο**: με `h-screen` κάτω από κεφαλίδα, το κάτω
 * μέρος του χάρτη θα έβγαινε **εκτός οθόνης** και θα εμφανιζόταν μπάρα κύλισης σε
 * επιφάνεια που σχεδιάστηκε να μην κυλά. Το ύψος το κατέχει **το κέλυφος** και οι
 * σελίδες ζητούν «ό,τι περισσεύει», που είναι η **μόνη** εκδοχή που μένει σωστή όταν
 * αλλάξει το ύψος της κεφαλίδας.
 *
 * 🔴 **ΚΑΙ ΑΥΤΗ Η ΠΑΡΑΓΡΑΦΟΣ ΗΤΑΝ ΨΕΥΔΗΣ ΜΕΧΡΙ ΤΙΣ 2026-08-25** (ADR-797 ΦΑΣΗ Γ).
 * Έλεγε ότι «το ύψος το κατέχει το κέλυφος» ενώ η γραμμή από κάτω έγραφε
 * `min-h-screen` — δηλαδή **ελάχιστο**, όχι κατεχόμενο ύψος. Το `flex-1` της σελίδας
 * δεν είχε τι να μοιράσει (**CSS 2.2 §10.5**: containing block χωρίς ρητό ύψος ⇒ το
 * παιδί υπολογίζεται ως `auto`), ο χάρτης πήρε **φυσικό** ύψος και έσπρωξε τη σελίδα
 * **161px** κάτω από την οθόνη: η 7η πινέζα ήταν αόρατη ενώ η λογιστική από πάνω της
 * έγραφε «7 στον χάρτη». **Η περιγραφή της διόρθωσης ΗΤΑΝ η απόκλιση** — το σχήμα που
 * σε αυτό το repo έχει πληρωθεί σε CHECK 3.34 · 3.37 · 3.49 · 3.57.
 *
 * ⚠️ **ΜΗΝ ξαναγράψεις ύψος παραθύρου εδώ.** Το `data-shell-frame` είναι η **μόνη**
 * αυθεντία ύψους (`shell-surface.css` §5)· ο κανόνας **Υ1** του CHECK 3.63 μπλοκάρει
 * χειρόγραφο `h-screen`/`min-h-screen` σε ρίζα γειτονιάς. Η προεπιλογή είναι
 * **δάπεδο** — το έγγραφο κυλά· κλειδώνει **μόνο** σελίδα που το δηλώνει.
 */

import { COLOR_BRIDGE } from '@/design-system/color-bridge';
import { ShellSurface } from '@/core/containers/ShellSurface';
import { PublicSiteHeader } from '@/components/public-site/PublicSiteHeader';

export default function LightLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <div data-shell-frame className={`w-full ${COLOR_BRIDGE.bg.primary}`}>
      <PublicSiteHeader />
      {/*
        🏛️ Ο ΔΙΑΔΡΟΜΟΣ (ADR-797 ΦΑΣΗ Β). Το ίδιο `data-shell-surface` με το κέλυφος,
        η ίδια ρευστή συνάρτηση, οι ίδιοι πόλοι — και **μηδέν** νέο CSS: το
        `--shell-sidebar-occupied` δεν ορίζεται εδώ, οπότε πέφτει στο `0px` και το
        pane γίνεται όλο το παράθυρο. Αποδεδειγμένο ζωντανά 2026-08-25.

        ⚠️ **ΕΞΩ από την κεφαλίδα, επίτηδες.** Η κεφαλίδα είναι πλάτους οθόνης και
        έχει δικό της εσωτερικό κενό· ένας διάδρομος γύρω της θα την ξεκολλούσε από
        την άκρη — άλλο σχέδιο, όχι «λίγο κενό».

        ⚠️ **ΚΑΝΕΝΑ `measure` εδώ.** Η γειτονιά είναι **ετερογενής**, μετρημένα: η
        αρχική είναι κεντραρισμένο μενού, η καρτέλα ακινήτου διάταξη δύο στηλών, τα
        αποτελέσματα **χάρτης σε πλήρες παράθυρο**. Ένα ταβάνι για όλες θα ήταν
        λάθος στις τρεις από τις τέσσερις — γι' αυτό το δηλώνει **η σελίδα**.
      */}
      <ShellSurface className="flex flex-1 flex-col">{children}</ShellSurface>
    </div>
  );
}
