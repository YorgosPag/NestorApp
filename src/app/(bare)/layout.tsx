'use client';

/**
 * 🔴 ΓΥΜΝΗ ΕΠΙΦΑΝΕΙΑ — route group `(bare)`   (ADR-775 §13 · ADR-777 §8.12)
 *
 * **Κανένα κέλυφος εφαρμογής, καθόλου.** Εδώ ζουν οι επιφάνειες των οποίων η
 * φωτογραφία είναι **συμβόλαιο**.
 *
 * ## Γιατί ΟΧΙ απλώς «κλειστό sidebar»
 * Το `/test-harness/dxf-perf` ζει στο `(app)` με **αντίθετο** σκεπτικό, γραμμένο ρητά
 * (ADR-726 §13.1): προσαρτά τον **ίδιο** viewer με το `/dxf/viewer` και οφείλει να
 * μετρά τη **γεωμετρία που παραδίδεται**, άρα θέλει το κέλυφος. Το
 * `/test-harness/dxf-canvas` είναι το ακριβώς αντίθετο πράγμα: προσαρτά **μόνο τον
 * ζωγράφο**, και η φωτογραφία του κρίνει **τον ζωγράφο**.
 *
 * ## Το πρότυπο (Skia GM · Rive)
 * Ένα golden image test αποδίδει σε **καμβά σταθερού μεγέθους**: καμία μπάρα, κανένα
 * sidebar, καμία γλώσσα. Ό,τι μπαίνει στο κάδρο και **δεν** το ζωγράφισε ο ζωγράφος
 * είναι μελλοντικό ψευδώς-θετικό. Μετρημένο 2026-08-08: με το κέλυφος μέσα στο κάδρο,
 * η καθαρή διαφορά της σουίτας ήταν **0 δομικά pixels** και **100%** θόρυβος κελύφους
 * (αλλαγή γλώσσας el→en, νέα μπάρα «All jobs», token θέματος της εκστρατείας ADR-770)
 * — δηλαδή **43 tests** που έσπαγαν για λόγους **άσχετους με το DXF**.
 *
 * ⚠️ Η απομόνωση γίνεται **από τη δομή** και όχι με αδιαφανές `z-index` πάνω στο
 * harness: ένα καπάκι κρύβει το κέλυφος **μέχρι** κάποιο μελλοντικό στοιχείο να πάρει
 * μεγαλύτερο `z-index`, οπότε το κέλυφος επιστρέφει στο κάδρο **σιωπηλά**. Εδώ δεν
 * αποδίδεται καθόλου — και αυτό δεν εξαρτάται από καμία λίστα.
 *
 * ⚠️ Ο `TooltipProvider` διατηρείται αυτούσιος από τον `ConditionalAppShell` (γρ. 244),
 * όπου το σχόλιο τον κρατούσε «*για να μείνει ένα και μόνο σημείο εξόδου*». Δεν
 * αποδίδει DOM, άρα **δεν** μπαίνει στο κάδρο του golden image.
 *
 * @module app/(bare)/layout
 */

import { TooltipProvider } from '@/components/ui/tooltip';

export default function BareGroupLayout({ children }: Readonly<{ children: React.ReactNode }>) {
  return <TooltipProvider delayDuration={300}>{children}</TooltipProvider>;
}
