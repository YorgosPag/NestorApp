/**
 * =============================================================================
 * 🔗 ΣΕΛΙΔΕΣ ΣΥΝΔΕΣΜΟΥ ΜΕ ΚΛΕΙΔΙ — route group `(link)`   (ADR-939 §6 · ADR-777 §8.12)
 * =============================================================================
 *
 * Εδώ ζουν οι σελίδες που ανοίγουν με **κλειδί μέσα στη διεύθυνση** και ανήκουν σε
 * **άλλον** (τον εκδότη): `/shared/<token>` (παραστατικό · αρχείο · περιήγηση),
 * `/shared/po/<token>`, `/showcase/<token>`, `/share/photo/<id>`.
 *
 * 🔴 **ΓΙΑΤΙ ΒΓΗΚΑΝ ΑΠΟ ΤΟ `(app)`.** Ζούσαν εκεί χωρίς καμία δήλωση — καμία γραμμή σε
 * `.shell-boundary.json`, `.shell-surface.json`, `.shell-utilities.json` ή ADR. Το
 * `(app)/layout.tsx` αποδίδει το κέλυφος **άνευ όρων**, άρα ο πελάτης του εκδότη έβλεπε
 * τα εργαλεία του **γραφείου** (μπάρα έργων/λογιστικής, εναλλαγή εταιρείας, αναζήτηση,
 * φωνητικό βοηθό). Οι πύλες ήταν πράσινες: ο Κ1 της 3.52 είναι αυτο-συνεπής με τον
 * φάκελο, και ο Κ2 κοιτά μόνο τα hooks δημόσιων αγγελιών.
 *
 * 📏 **ΜΕΤΡΗΜΕΝΟ ΠΡΙΝ ΤΗ ΜΕΤΑΚΟΜΙΣΗ (2026-11-12)**: κλειστότητα εισαγωγών των τεσσάρων
 * σελίδων (ίδιος επιλυτής με τον Κ2 της 3.52) — από τους 12 providers του `(app)` ζητούν
 * **μόνο** τον `TooltipProvider` (`/shared/[token]` · `/showcase/[token]`)· οι άλλες δύο
 * **κανέναν**. Η ταυτότητα (`AuthProvider`) ζει στο ριζικό layout, άρα υπάρχει κι εδώ.
 *
 * 🔑 **ΓΙΑΤΙ ΟΧΙ `(auth)`**, όπου ζουν ήδη 14 σελίδες με κλειδί: το `(auth)` τυλίγει τα
 * παιδιά σε `<main>` που **κεντράρει** (`flex items-center justify-center`). Και οι
 * τέσσερις σελίδες εδώ είναι **αυτοτελή έγγραφα** με δικό τους `<main>`/`min-h-screen`
 * ⇒ εκεί θα έπαιρναν **δεύτερο `<main>`** (ακριβώς η βλάβη που είχαν μέσα στον
 * `MainContentBridge` του `(app)`) και το κεντράρισμα θα συρρίκνωνε τις σελίδες
 * πλήρους πλάτους στο πλάτος του περιεχομένου τους.
 * **ΓΙΑΤΙ ΟΧΙ `(light)`**: εκείνο είναι ο ιστότοπος της **πλατφόρμας** (κεφαλίδα και
 * υποσέλιδο της)· η σελίδα παραστατικού ανήκει στον **εκδότη** (Stripe hosted invoice ·
 * FreshBooks/Zoho client portal: καμία πλοήγηση του παρόχου).
 *
 * ⚠️ **ΜΗΔΕΝ ΔΙΚΟ ΤΟΥ DOM ΓΥΡΩ ΑΠΟ ΤΑ ΠΑΙΔΙΑ, ΕΠΙΤΗΔΕΣ.** Κάθε σελίδα κατέχει το
 * `<main>`, το ύψος και το περιθώριό της (δηλωμένο στο `.shell-surface.json`, CHECK 3.63).
 * Το layout προσθέτει **μόνο**:
 *   - τον `TooltipProvider` (ADR-813: `Tooltip` χωρίς provider ρίχνει την επιφάνεια)·
 *   - την `AuthToolbar` — τον **ΕΝΑΝ** υπάρχοντα σταθερό συναρμολογητή των καθολικών
 *     δυνατοτήτων (γλώσσα · θέμα · λογαριασμός όταν υπάρχει, CHECK 3.72). `fixed`,
 *     άρα δεν μπαίνει στη ροή και δεν γεννά φάντασμα κύλισης πάνω από `min-h-screen`.
 *
 * Τα `noindex`/`no-referrer` δηλώνονται ανά υποδέντρο (`shared/layout.tsx`,
 * `showcase/[token]/page.tsx`) από το SSoT `CREDENTIAL_LINK_PAGE_METADATA`.
 *
 * @module app/(link)/layout
 */

import { AuthToolbar } from '@/auth/components/AuthScreenChrome';
import { TooltipProvider } from '@/components/ui/tooltip';

export default function CredentialLinkGroupLayout({ children }: Readonly<{ children: React.ReactNode }>) {
  return (
    <TooltipProvider delayDuration={300}>
      <AuthToolbar />
      {children}
    </TooltipProvider>
  );
}
