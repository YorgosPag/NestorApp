import fs from 'fs';
import path from 'path';
import { parseSync } from '@swc/core';

const SRC = path.join(process.cwd(), 'src');

/** Φάκελοι που δεν είναι πηγαίος κώδικας μας. */
const SKIP_DIRS = new Set(['node_modules', '.next', 'dist', 'build', 'coverage']);

function sourceFiles(dir: string, out: string[] = []): string[] {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) sourceFiles(full, out);
    } else if (/\.(ts|tsx)$/.test(entry.name) && !entry.name.endsWith('.d.ts')) {
      out.push(full);
    }
  }
  return out;
}

/**
 * ⚠️ **Ρητό όριο, γιατί η προεπιλογή του Jest είναι 5s και η σάρωση θέλει ~25s.**
 * Χωρίς αυτό η άγκυρα αποτυγχάνει **σε χρόνο**, όχι σε εύρημα — δηλαδή θα διαβαζόταν
 * ως θόρυβος και θα απενεργοποιούνταν. Το 120s δίνει ×5 περιθώριο για αργό δίσκο.
 */
const PARSE_SCAN_TIMEOUT_MS = 120_000;

describe('Π1 — ΚΑΘΕ ΑΡΧΕΙΟ ΤΟΥ `src/` ΕΙΝΑΙ ΠΡΟΓΡΑΜΜΑ', () => {
  it('🔴 κανένα αρχείο δεν αποτυγχάνει στον parser του Turbopack', () => {
    // 🔴 **Η ΜΕΤΑΛΛΑΞΗ, ΕΚΤΕΛΕΣΜΕΝΗ**: αφαιρέθηκε το `}` του
    //    `PlausibilityAssessment` (ακριβώς η ζωντανή βλάβη) ⇒ αυτή η δοκιμή κοκκίνισε
    //    με το αρχείο ονομαστικά. Επαναφορά ⇒ πράσινο.
    const failures: string[] = [];

    for (const file of sourceFiles(SRC)) {
      try {
        parseSync(fs.readFileSync(file, 'utf8'), {
          syntax: 'typescript',
          tsx: file.endsWith('.tsx'),
          decorators: true,
        });
      } catch (error) {
        const reason = error instanceof Error ? error.message.split('\n')[0].trim() : String(error);
        failures.push(`${path.relative(process.cwd(), file)} :: ${reason}`);
      }
    }

    // Το μήνυμα **ονομάζει** τα αρχεία: η βλάβη του περιστατικού εμφανιζόταν στον
    // περιηγητή ως σφάλμα του `(app)/layout.tsx`, **18 κρίκους** μακριά από την αιτία.
    expect(failures).toEqual([]);
  }, PARSE_SCAN_TIMEOUT_MS);

  it('🔴 σαρώνει πραγματικά το δέντρο — φρουρός κατά κενής σάρωσης', () => {
    // ⚠️ Χωρίς αυτό, ένα λάθος στο `sourceFiles` (π.χ. λάθος ρίζα) θα έκανε τη δοκιμή
    //    **μονίμως πράσινη σαρώνοντας μηδέν αρχεία** — το σχήμα «0 = κανείς δεν
    //    κοίταξε» που αυτό το repo έχει πληρώσει σε 3.18, 3.28 και i18n.
    expect(sourceFiles(SRC).length).toBeGreaterThan(10_000);
  });
});
