/** Είναι αυτό αποτύπωμα που θα μπορούσε να έχει παραχθεί από τον γραφέα; */
export function isPublicShelfContentHash(value: string): boolean {
  return CONTENT_HASH_PATTERN.test(value);
}

/** Είναι αυτή μορφή που **παράγει** ο καθαριστής μας; */
export function isPublicShelfExtension(value: string): value is PublicShelfExtension {
  return (PUBLIC_SHELF_EXTENSIONS as readonly string[]).includes(value);
}

