/**
 * **Πόσες φωτογραφίες φεύγουν το πολύ** (ADR-841 §7 Α2.1 · Α14.4 · Ο-17).
 *
 * Μετρημένο, όχι στρογγυλό: η έρευνα της **Zillow** δίνει **22–27** ως ιδανικό εύρος,
 * με πτώση πάνω από **28** *(«οι σημαντικές θάβονται»)*· η **Rightmove** δουλεύει σε
 * **10–20**. Το **24** είναι μέσα στο πρώτο και πάνω από το δεύτερο.
 *
 * ⚠️ **Δεν είναι όριο ασφαλείας** — είναι όριο **προσοχής του επισκέπτη**. Το όριο
 * ασφαλείας είναι η ίδια η **επιλογή** (Α2.7): χωρίς αυτήν, δεν φεύγει **τίποτα**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ ΖΕΙ ΕΔΩ ΚΑΙ ΟΧΙ ΔΙΠΛΑ ΣΤΟΝ ΕΝΑΝ ΑΠΟ ΤΟΥΣ ΔΥΟ *(Ο-17, μετακινήθηκε 2026-09-03)*
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Μέχρι την **Α14** ο μόνος που δημοσίευε συλλογή ήταν ο **ιδιώτης**, οπότε η σταθερά
 * κατοικούσε στο `lib/owner-property/owner-media-publication.ts` — και ήταν **σωστό**. Η
 * Α14 έδωσε συλλογή **και στο γραφείο** ⇒ η σταθερά έγινε **του ραφιού**, ενώ το σπίτι
 * της εξακολουθούσε να έχει **όνομα ιδιώτη**: ο γραφέας του επαγγελματία εισήγαγε από
 * `@/lib/owner-property/…` — πρόταση που **δεν θα υπερασπιζόταν κανείς** αν γραφόταν ρητά.
 *
 * 🔑 **Ο ΑΡΙΘΜΟΣ ΕΙΝΑΙ ΕΝΑΣ, ΚΑΙ Η ΕΞΑΡΤΗΣΗ ΡΗΤΗ — ΠΟΤΕ ΑΝΤΙΓΡΑΜΜΕΝΗ ΤΙΜΗ.** Δύο
 * αριθμοί θα σήμαιναν ότι η **ίδια** βιτρίνα κουράζει διαφορετικά ανάλογα με το ποιος
 * δημοσίευσε — ιδιότητα **εκείνου που κοιτάζει**, όχι εκείνου που ανέβασε (Α14.4).
 *
 * ⇒ Σωστό σπίτι είναι το **ουδέτερο** module που **και οι δύο** οικογένειες ήδη
 * εισάγουν *(αμφότερες για το {@link PublicShelfSource})*.
 */
export const PUBLISHED_MEDIA_LIMIT = 24;

/** Η ρίζα του ραφιού μέσα στον δημόσιο κάδο — γραμμένη **μία** φορά. */
export const PUBLIC_SHELF_ROOT = 'listings';

/**
 * 🔴 **ΤΟ `max-age` ΕΙΝΑΙ Ο ΠΡΟΫΠΟΛΟΓΙΣΜΟΣ ΤΗΣ ΑΠΟΣΥΡΣΗΣ — ΟΧΙ ΡΥΘΜΙΣΗ ΕΠΙΔΟΣΗΣ.**
 *
 * **Μετρημένο περπατώντας τη Φ2 (2026-09-01)** — και ανέτρεψε την πρώτη γραφή αυτής
 * της γραμμής, που έλεγε `max-age=31536000, immutable`:
 *
 * ```
 * απόσυρση → removed: 1 → ο κάδος έχει 0 αντικείμενα
 * ανώνυμο GET στο ΙΔΙΟ URL → HTTP 200, Age: 74      ← ΤΟ EDGE CACHE ΣΕΡΒΙΡΕΙ ΑΚΟΜΗ
 * ```
 *
 * Η τεκμηρίωση της Cloud Storage το λέει ρητά: το built-in cache προσφέρει **καμία
 * ακύρωση** *(«no cache invalidation capability»)* — είναι η δηλωμένη διαφορά του από
 * το Cloud CDN. Άρα ένα δημοσιευμένο αντικείμενο μένει προσβάσιμο **όσο λέει το
 * `max-age`**, ακόμη κι αφού σβηστεί από τον κάδο.
 *
 * ⇒ **`max-age = 31536000` σήμαινε «η απόσυρση ισχύει σε ΕΝΑ ΕΤΟΣ».** Για αγγελία που
 * ο άνθρωπος **απέσυρε** — και για το δικαίωμα διαγραφής του GDPR — αυτό δεν είναι
 * ρύθμιση επίδοσης· είναι **διαρροή με ημερομηνία λήξης δώδεκα μηνών**.
 *
 * 🔑 **Η ΜΙΑ ΩΡΑ ΔΕΝ ΧΑΝΕΙ ΤΟ ΟΦΕΛΟΣ.** Το edge εξακολουθεί να απορροφά **κάθε**
 * αίτημα εντός της ώρας ανά POP — η οικονομία του CDN είναι ήδη ~ολόκληρη στην πρώτη
 * ώρα. Αυτό που αλλάζει δεν είναι το κόστος: είναι το **παράθυρο έκθεσης**, από
 * **έτος** σε **ώρα**.
 *
 * ⚠️ **ΜΗΝ το ανεβάσεις «για επίδοση».** Η επιστροφή στο έτος είναι θεμιτή **μόνο**
 * όταν μπει μπροστά υποδομή με **ακύρωση** *(Cloud CDN, ή δικό μας `media.` hostname)*
 * — τότε η απόσυρση θα μπορεί να καθαρίζει το edge, και το παράθυρο παύει να είναι το
 * `max-age`. Άγκυρα φυλάει το όριο.
 *
 * 🔑 Το `immutable` **παραμένει αληθές και χρήσιμο**: αφορά το **περιεχόμενο** στο URL
 * (content-addressed ⇒ δεν αλλάζει ποτέ), όχι την **ύπαρξή** του. Γλιτώνει τις
 * επικυρώσεις μέσα στο παράθυρο φρεσκάδας.
 */
export const PUBLIC_SHELF_CACHE_CONTROL = 'public, max-age=3600, immutable';

/**
 * Το **ανώτατο** αποδεκτό `max-age` για δημόσιο ράφι, σε δευτερόλεπτα (24 ώρες).
 *
 * Υπάρχει ώστε το σκεπτίκο του {@link PUBLIC_SHELF_CACHE_CONTROL} να είναι
 * **εκτελούμενο**: χωρίς όριο, η επόμενη «βελτιστοποίηση» θα το ξανάκανε έτος και
 * **καμία πύλη δεν θα ρωτούσε**.
 */
export const PUBLIC_SHELF_MAX_CACHE_SECONDS = 86_400;

/**
 * Οι μορφές που **παράγει ο δικός μας** καθαριστής — ποτέ ό,τι ανέβασε ο άνθρωπος.
 *
 * ⚠️ Κλειστό σύνολο επίτηδες: το ράφι σερβίρει σε **ανώνυμο**, οπότε κάθε νέα μορφή
 * είναι απόφαση (π.χ. SVG **ποτέ** — εκτελεί script στον περιηγητή του επισκέπτη).
 *
 * 🔴 **ΤΟ `glb` ΛΕΙΠΕΙ ΕΠΙΤΗΔΕΣ.** Μπαίνει στη **Φ4**, **μαζί** με τον ψήστη που το
 * παράγει *(καθαρισμός → meshopt, ADR-841 §7 Α3 ②③)*. Μια μορφή δηλωμένη εδώ χωρίς
 * καθαριστή που να την παράγει θα ήταν **υπόσχεση χωρίς μηχανισμό** — και θα άνοιγε
 * διαδρομή να δημοσιευτεί μοντέλο **ωμό**, με `companyId`, κόστη και BOQ μέσα του.
 */
export const PUBLIC_SHELF_EXTENSIONS = ['webp'] as const;

export type PublicShelfExtension = (typeof PUBLIC_SHELF_EXTENSIONS)[number];

/** Το αποτύπωμα που παράγει ο γραφέας: sha256, πεζό δεκαεξαδικό, 64 χαρακτήρες. */
const CONTENT_HASH_PATTERN = /^[0-9a-f]{64}$/;

/**
 * Πρόθεμα ταυτότητας μισθωτή — **απαγορευμένο** σε δημόσιο κλειδί.
 *
 * 🔴 Η Φ1 μέτρησε ότι τα ζωντανά αναγνωριστικά αγγελιών είναι `prop_*` / `ownp_*` και
 * **κανένα** `comp_*`. Ο φρουρός εδώ κάνει τη μέτρηση **εκτελούμενη**: αν κάποτε
 * περάσει `companyId` ως ταυτότητα αγγελίας, η δημοσίευση **σταματά** αντί να
 * τυπώσει την ταυτότητα του μισθωτή σε δημόσιο URL.
 */
const TENANT_IDENTITY_PREFIX = 'comp_';

