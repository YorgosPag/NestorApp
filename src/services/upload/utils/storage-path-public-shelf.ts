/**
 * **Η μία διατύπωση του δημόσιου URL.**
 *
 * ⚠️ **Χωριστή από το κλειδί επίτηδες.** Το κλειδί είναι **αμετάβλητο**· ο κεντρικός
 * υπολογιστής **όχι**: όταν κάποτε μπει δικό μας όνομα (`media.nestorconstruct.gr`,
 * το πρότυπο `photos.zillowstatic.com` της Zillow), αλλάζει **αυτή η συνάρτηση και
 * τίποτε άλλο** — κανένα αποθηκευμένο URL δεν παλιώνει, γιατί **δεν αποθηκεύουμε URL**.
 *
 * ⛔ **ΟΧΙ `firebasestorage.googleapis.com`**: εκείνη η διαδρομή κρίνεται από το
 * `storage.rules` και **δεν** ενεργοποιεί το built-in edge cache (Α12.1). Εδώ μιλάμε
 * στο ίδιο το Cloud Storage, όπου η δημοσιότητα είναι IAM και το cache δουλεύει.
 */
export function publicShelfUrl(bucketName: string, key: string): string {
  return `https://storage.googleapis.com/${bucketName}/${key}`;
}
