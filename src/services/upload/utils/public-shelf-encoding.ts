/**
 * @fileoverview 🏆 **ΤΙ ΕΙΔΟΥΣ BYTES, ΚΑΙ ΜΕ ΠΟΙΑ ΣΥΝΤΑΓΗ** — ο άξονας της κωδικοποίησης.
 * @related ADR-845 §3 (Φ4.0) · §6.2 (Φ4.2) · ADR-841 §7 Α21.10 · Α2.3
 * @module services/upload/utils/public-shelf-encoding
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΤΡΙΤΟ ΑΡΧΕΙΟ — ΚΑΙ ΓΙΑΤΙ Η ΤΟΜΗ ΔΕΝ ΕΙΝΑΙ ΤΟ ΟΡΙΟ ΤΩΝ 500 ΓΡΑΜΜΩΝ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ζεύγος ήταν ήδη δύο ερωτήσεις: *«**ΠΩΣ** χτίζεται μια διαδρομή;»*
 * *(`./storage-path-public-shelf`)* και *«**ΠΟΙΑ** είδη υπάρχουν;»* *(`./public-shelf-kinds`)*.
 * Η **Φ4.0** γέννησε την **τρίτη**, και το `public-shelf-kinds` την κουβαλούσε αμίλητη:
 * *«**ΤΙ ΕΙΔΟΥΣ bytes** είναι αυτά, και **πώς ψήνονται**;»*
 *
 * 🔑 **Η τρίτη ερώτηση είναι ορθογώνια στις δύο πρώτες, και το αποδεικνύει η Φ4.2**: ο πίνακας
 * των ειδών αποκτά **μία** γραμμή για το μοντέλο, ενώ η κωδικοποίηση αποκτά **ολόκληρο δεύτερο
 * λεξιλόγιο** *(παράμετροι ψησίματος, συνταγή `glb:`)*. Δύο πράγματα που μεγαλώνουν με **εντελώς
 * διαφορετικό ρυθμό** δεν είναι μία ευθύνη.
 *
 * ⚠️ **ΤΟ ΟΡΙΟ ΤΩΝ 500 ΤΟ ΑΠΟΚΑΛΥΨΕ, ΔΕΝ ΤΟ ΔΗΜΙΟΥΡΓΗΣΕ — ΚΑΙ ΕΙΝΑΙ Η ΔΕΥΤΕΡΗ ΦΟΡΑ.** Το ίδιο
 * το `public-shelf-kinds` γράφει ότι έσπασε στις **562** γραμμές μόλις μπήκε το δεύτερο *είδος*.
 * Μετρημένο 2026-09-08: είχε φτάσει ξανά τις **503** *(από 491 στο `HEAD`)* μόλις μπήκε το δεύτερο
 * *είδος bytes*. Ίδιο σχήμα, άλλος άξονας.
 *
 * 🔴 **ΚΑΙ ΓΙ' ΑΥΤΟ ΤΟ `public-shelf-kinds` ΞΑΝΑ-ΕΞΑΓΕΙ ΑΥΤΑ ΤΑ ΣΥΜΒΟΛΑ**: δεκατρία αρχεία τα
 * εισάγουν από εκεί, και **τέσσερα από αυτά είναι σταδιοποιημένη δουλειά άλλης συνεδρίας** την
 * ώρα που γράφεται αυτό. Μια μετακίνηση διαδρομών θα μετέλλασσε ξένα αρχεία για **μηδέν** κέρδος:
 * *«πού ζει η κωδικοποίηση»* είναι γνώση που **δεν χρειάζεται να μαθευτεί σε δεκατρία σημεία**.
 * Ίδιο ιδίωμα με τα περιτυλίγματα του `io/mesh3d-roundtrip` *(ADR-845 Φ4.2, βήμα 0)*.
 *
 * ⛔ **ΚΑΘΑΡΟ MODULE — καμία I/O, κανένα `sharp`, κανένα `gltf-transform`.** Οι κωδικοποιήσεις
 * είναι **δεδομένα**· μόνο η **εφαρμογή** τους είναι εγγενής, και ζει στους δύο καθαριστές
 * *(`public-shelf-sanitise` για τις εικόνες, `public-shelf-model-bake` για τα μοντέλα)*.
 */

/**
 * **ΠΩΣ ΚΩΔΙΚΟΠΟΙΕΙΤΑΙ ΜΙΑ ΕΙΚΟΝΑ** — σκέτα δεδομένα, **κανένα `sharp`**.
 *
 * 🔑 **Ζει στο ΚΑΘΑΡΟ module επίτηδες.** Θα ήταν φυσικό να κατοικεί δίπλα στον καθαριστή
 * που τα καταναλώνει — αλλά τότε ο **περιγραφέας** ({@link PublicShelfKind}) θα έπρεπε να
 * εισάγει από module που φορτώνει `sharp`, δηλαδή ο πελάτης δεν θα μπορούσε ποτέ να
 * ρωτήσει *«ποια είναι η ρίζα της βιτρίνας;»*. Πλάτη και ποιότητα είναι **αριθμοί**·
 * μόνο η **εφαρμογή** τους είναι εγγενής.
 *
 * ⚠️ **Τα πλάτη είναι ΑΥΞΟΥΣΑ, και το τελευταίο είναι το «κανονικό»** — η προβολή
 * διαβάζει το τελευταίο ως τον στόχο του `src`. Άγκυρα φυλάει τη σειρά.
 *
 * 🔴 **ΤΟ `kind: 'raster'` ΔΕΝ ΕΙΝΑΙ ΔΙΑΚΟΣΜΗΤΙΚΟ** *(ADR-845 §3, Φ4.0)*. Ως σήμερα αυτός
 * ο τύπος **ήταν** η κωδικοποίηση — δηλαδή το ράφι δήλωνε, σιωπηλά, ότι κάθε πράγμα που
 * δημοσιεύεται είναι **εικόνα**. Ο διακριτής το κάνει **ερώτηση που πρέπει να απαντηθεί**:
 * κάθε καταναλωτής υποχρεώνεται να πει *«τι είδους bytes;»* πριν αγγίξει πλάτος ή ποιότητα.
 */
export interface RasterShelfEncoding {
  readonly kind: 'raster';
  readonly widths: readonly number[];
  /**
   * `'lossless'` για **σήματα**, αριθμός για **φωτογραφίες** — και δεν είναι γούστο.
   *
   * Η τεκμηρίωση του `cwebp` δίνει χωριστά preset για `photo` και `icon`/`drawing`
   * ακριβώς επειδή η lossy συμπίεση **θολώνει τις σκληρές μεταβάσεις**: ένα λογότυπο
   * είναι επίπεδες περιοχές + αιχμηρές ακμές, δηλαδή **μόνο** σκληρές μεταβάσεις.
   * Το `q82` που κρατά ευανάγνωστες τις κατόψεις θα έτρωγε τις ακμές ενός σήματος.
   */
  readonly quality: number | 'lossless';
  readonly preset: 'photo' | 'icon';
}

/**
 * **ΠΩΣ ΚΩΔΙΚΟΠΟΙΕΙΤΑΙ ΕΝΑ ΤΡΙΣΔΙΑΣΤΑΤΟ ΜΟΝΤΕΛΟ** — ✅ **ΑΠΑΝΤΗΘΗΚΕ ΣΤΗ Φ4.2** *(ADR-845 §6.2)*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΗΤΑΝ **ΚΕΝΟ ΕΠΙΤΗΔΕΣ** ΩΣ ΤΗ Φ4.1 — ΚΑΙ Ο ΟΡΟΣ ΕΚΠΛΗΡΩΘΗΚΕ, ΔΕΝ ΚΑΜΦΘΗΚΕ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο χώρος παραμέτρων ενός ψησίματος μοντέλου **δεν είναι μικρός**: τα `glTF-Transform` /
 * `gltf-pipeline` εκθέτουν συμπίεση γεωμετρίας *(`draco` με `method`, `quantizeColorBits`,
 * `quantizeGenericBits`, `unifiedQuantization`, `uncompressedFallback` — ή `meshopt` με
 * `level`)* **και** συμπίεση υφών *(`ktx2` με `UASTC`/`ETC1S`, `level`, `rdo-lambda`,
 * `zstd`)*. Κάθε υποσύνολο που θα **μαντεύαμε** τότε θα γινόταν {@link shelfRecipe} που
 * **λέει ψέματα** — και επειδή το κλειδί είναι content-addressed, το ψέμα θα γινόταν
 * **μόνιμη διεύθυνση**.
 *
 * ⇒ Ο κανόνας ήταν: *«οι παράμετροι μπαίνουν **μαζί με τον ψήστη που τις εκτελεί**, ποτέ
 * πριν»*. Ο ψήστης ήρθε *(`services/listings/public-shelf-model-bake`)*, άρα ήρθαν κι αυτές.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ **ΑΚΡΙΒΩΣ ΑΥΤΑ ΤΑ ΔΥΟ** ΚΑΙ ΟΧΙ ΤΑ ΔΕΚΑ ΠΟΥ ΠΡΟΣΦΕΡΕΙ Η ΒΙΒΛΙΟΘΗΚΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * **Ό,τι είναι εδώ ΑΛΛΑΖΕΙ ΤΑ BYTES. Ό,τι δεν τα αλλάζει, ΔΕΝ επιτρέπεται να είναι εδώ** —
 * γιατί αυτό το αντικείμενο γίνεται {@link shelfRecipe}, δηλαδή **η ταυτότητα των παραγώγων**.
 * Μια παράμετρος που δεν αγγίζει bytes θα ακύρωνε **κάθε δημοσιευμένο μοντέλο** την ημέρα
 * που κάποιος την πείραζε, για **μηδέν** διαφορά στο αρχείο.
 *
 * ⛔ **Γι' αυτό το ταβάνι των 5 MB ΔΕΝ είναι εδώ** *(ζει ως `PUBLIC_SHELF_MODEL_MAX_BYTES`
 * δίπλα στον ψήστη, με την πηγή του)*: είναι κριτήριο **αποδοχής**, όχι κωδικοποίησης.
 *
 * ⛔ **ΟΧΙ Draco, και είναι μετρημένο**: ο decoder του ξεπερνά τα **100 KB**, οπότε σε μικρό
 * μοντέλο **κοστίζει περισσότερο απ' όσο γλιτώνει** *(ADR-841 §6.5, με πηγή)*, και server-side
 * Draco μετρήθηκε **~30 λεπτά** σε μοντέλο 150 MB. Το `meshopt` δίνει −91% *(29 MB → 2,5 MB)*
 * χωρίς κανένα από τα δύο τιμήματα. Ξανα-εξετάζεται **με μέτρηση**, αν τα δημοσιευμένα
 * μοντέλα ξεπερνούν συστηματικά τον στόχο *(ADR-845 §6.2.2)*.
 *
 * ⛔ **ΟΧΙ KTX2 στην πρώτη έκδοση**: απαιτεί εγγενή κωδικοποιητή *(`toktx`/`basisu`)* — δηλαδή
 * **δεύτερη εγγενή εξάρτηση** στον διακομιστή δίπλα στο `sharp`, με δική της άδεια και δικό
 * της κύκλο ζωής, για υφές που το BIM μας **σήμερα δεν έχει** *(τα υλικά είναι επίπεδα χρώματα)*.
 */
export interface ModelShelfEncoding {
  readonly kind: 'model';
  /**
   * Επίπεδο `EXT_meshopt_compression`. **Το ίδιο λεξιλόγιο με τη βιβλιοθήκη** *(`medium` |
   * `high`)* — δεν μεταφράζεται σε δικό μας, γιατί μια μετάφραση εδώ θα ήταν δεύτερο όνομα
   * για το ίδιο πράγμα, ελεύθερο να αποκλίνει στην επόμενη έκδοση του `gltf-transform`.
   */
  readonly meshopt: 'medium' | 'high';
  /**
   * Bits κβαντισμού ανά είδος δεδομένων — **προηγείται** της συμπίεσης και είναι ο λόγος
   * που εκείνη πιάνει.
   *
   * ⚠️ **Η θέση είναι 14 bit, και η επιλογή δένεται με κτίρια**: σε οριακό κουτί ~100 m τα
   * 14 bit δίνουν βήμα **~6 mm** — αόρατο σε θεατή αγγελίας, και **μία τάξη μικρότερο** από
   * το πάχος ενός σοβά.
   *
   * 🔴 **ΚΑΙ ΓΙ' ΑΥΤΟ Η ΛΟΓΙΣΤΙΚΗ ΜΕΤΡΑ ΠΡΙΝ ΤΟ ΨΗΣΙΜΟ, ΟΧΙ ΜΕΤΑ** *(σειρά του §6.2, βήματα
   * ①→④)*. Τα 6 mm είναι **δεκαπλάσια** από την ανοχή μήκους του
   * `@/lib/geometry/mesh3d/geometry-fingerprint` *(`GEOMETRY_LENGTH_TOLERANCE_M` = 1 mm)*.
   * Μια λογιστική που συνέκρινε τη δήλωση του πελάτη με τη **μετά-την-κβάντιση** γεωμετρία
   * θα απέρριπτε **κάθε** δημοσίευση — gate με 100% ψευδώς θετικά, δηλαδή θόρυβος.
   * ⇒ Ο κριτής ρωτά *«είναι αυτό που στάλθηκε;»* πάνω στα bytes **που παρελήφθησαν**·
   * το ψήσιμο τρέχει **αφού** η απάντηση είναι ναι.
   */
  readonly quantise: {
    readonly position: number;
    readonly normal: number;
    readonly texcoord: number;
  };
}

/**
 * 🏆 **ΤΙ ΕΙΔΟΥΣ BYTES ΔΗΜΟΣΙΕΥΟΝΤΑΙ** — ο άξονας που έλειπε *(ADR-845 §3, Φ4.0)*.
 *
 * 🔴 **Ο {@link PUBLIC_SHELF_KINDS} γενικεύει ΑΛΛΟΝ άξονα**, και η διάκριση είναι όλο το
 * εύρημα: εκείνος απαντά *«ποιο πράγμα δημοσιεύεται;»* *(αγγελία, βιτρίνα)*. **Δεν**
 * απαντά *«τι είδους bytes είναι;»*. Ένα `MODEL_SHELF` με `widths: [640, 1280, 2560]`
 * θα ήταν πρόταση **χωρίς νόημα** — γι' αυτό ο διακριτής μπαίνει **εδώ**, μέσα στην
 * κωδικοποίηση, και όχι ως τρίτη γραμμή στον πίνακα των ειδών.
 *
 * ⛔ **ΠΟΤΕ `extension: string` με προεπιλογή `'webp'`** — ίδια κλάση με το «προαιρετικό
 * `at`» που το `listing-material.ts` απέρριψε γραπτώς: μια προεπιλογή εδώ σημαίνει ότι ο
 * πρώτος που θα ξεχάσει να απαντήσει **θα δημοσιεύσει μοντέλο ως webp**, σιωπηλά.
 *
 * 🔑 **Ακολουθεί τον γείτονά του**: το {@link ShelfFraming} από κάτω είναι ήδη διακριτή
 * ένωση. Το σχήμα **δεν** εισάγεται εδώ — υιοθετείται.
 */
export type ShelfEncoding = RasterShelfEncoding | ModelShelfEncoding;

/**
 * 🏆 **ΠΩΣ ΠΛΑΙΣΙΩΝΕΤΑΙ ΤΟ ΠΕΡΙΕΧΟΜΕΝΟ ΜΕΣΑ ΣΤΑ BYTES** (ADR-841 §7 Α21.10).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΕΙΝΑΙ ΞΕΧΩΡΙΣΤΗ ΕΡΩΤΗΣΗ ΑΠΟ ΤΗΝ {@link ShelfEncoding}
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η κωδικοποίηση απαντά *«πόσο μεγάλο και πόσο συμπιεσμένο;»* — ερώτηση του **είδους
 * του ραφιού**, ίδια για κάθε αντικείμενο μέσα του. Το πλαισίωμα απαντά *«ποιο κομμάτι
 * της εικόνας είναι το περιεχόμενο;»* — ερώτηση του **υλικού**, και οι δύο κάτοικοι της
 * βιτρίνας δίνουν **αντίθετες** απαντήσεις:
 *
 * - Το **λογότυπο** έχει περιθώριο που κανείς δεν επέλεξε *(το άφησε το εργαλείο
 *   εξαγωγής)* ⇒ κόβεται, ώστε δύο σήματα να έχουν **ίδιο οπτικό βάρος**.
 * - Το **πορτρέτο** έχει περιθώριο που **είναι** η καδραρισμένη φωτογραφία ⇒ ένα τρίμμα
 *   θα κόλλαγε το κεφάλι στην άκρη του κύκλου.
 *
 * 🔴 **ΓΙ' ΑΥΤΟ ΤΟ `preset: 'icon'` ΔΕΝ ΗΤΑΝ ΠΟΤΕ ΤΟ ΣΩΣΤΟ ΚΡΙΤΗΡΙΟ**, παρότι έτσι
 * γράφτηκε το αρχικό σχέδιο της Φάσης Β: το {@link SHOWCASE_SHELF} σερβίρει **και τα
 * δύο** είδη με το ίδιο preset. Κριτήριο πάνω στην κωδικοποίηση θα **κούρευε selfie**.
 */
export type ShelfFraming =
  /** Τα bytes μένουν **όπως τα έδωσε ο άνθρωπος**. Η προεπιλογή κάθε υλικού. */
  | { readonly mode: 'as-given' }
  /**
   * Τα bytes κόβονται **στο μελάνι** — αλλά **μόνο** αν ο κριτής του περιγράμματος δώσει
   * άδεια *(`public-shelf-border`)*. Το κατώφλι ταξιδεύει μαζί επειδή **αλλάζει τα
   * bytes**, άρα οφείλει να βρίσκεται στην υπογραφή της συνταγής.
   */
  | { readonly mode: 'ink-tight'; readonly threshold: number };

/** Το υλικό δεν έχει περιθώριο να χάσει — ή δεν επιτρέπεται να το χάσει. */
export const FRAMING_AS_GIVEN: ShelfFraming = { mode: 'as-given' };

/**
 * **Κόψε το περιθώριο, κράτα το μελάνι** — και ο αέρας μπαίνει από την **παρουσίαση**.
 *
 * 🔑 **Κατώφλι 25, μετρημένο**: στην προεπιλογή του `sharp` *(10)* το ringing του JPEG
 * άφηνε υπόλειμμα 2px — το **ίδιο** λογότυπο σε PNG και σε JPEG έδινε **διαφορετικές**
 * διαστάσεις *(`670×160` έναντι `671×162`)*, δηλαδή η κανονικοποίηση θα εξαρτιόταν από
 * τη μορφή του αρχείου. Στο 25 τα δύο ταυτίζονται.
 *
 * ⛔ **Το `lineArt: true` ΔΟΚΙΜΑΣΤΗΚΕ ΚΑΙ ΑΠΟΡΡΙΦΘΗΚΕ**, παρότι η τεκμηρίωση το προτείνει
 * ακριβώς για διανυσματικό υλικό: στο ίδιο δείγμα **χειροτέρεψε** το αποτέλεσμα σε
 * `671×176`. Η τεκμηρίωση περιγράφει πρόθεση· η μέτρηση περιγράφει τη μηχανή.
 */
export const FRAMING_INK_TIGHT: ShelfFraming = { mode: 'ink-tight', threshold: 25 };

/**
 * 🔴 **Η ΥΠΟΓΡΑΦΗ ΤΗΣ ΣΥΝΤΑΓΗΣ — ΠΑΡΑΓΟΜΕΝΗ, ΠΟΤΕ ΓΡΑΜΜΕΝΗ ΜΕ ΤΟ ΧΕΡΙ** (Α2.3).
 *
 * Ταξιδεύει ως μεταδεδομένο κάθε δημοσιευμένου αντικειμένου, ώστε η συμφιλίωση να μπορεί
 * να απαντήσει *«αυτό το παράγωγο βγήκε από τη ΣΗΜΕΡΙΝΗ συνταγή;»* **χωρίς να
 * αποκωδικοποιήσει τίποτα**.
 *
 * ⚠️ **Ήταν σταθερά, έγινε συνάρτηση, και ο λόγος είναι ο ίδιος με πριν.** Ένα
 * χειρόγραφο `'v1'` θα ξεχνιόταν στην πρώτη αλλαγή ποιότητας· μια **σταθερά** ξεχνιέται
 * την πρώτη φορά που υπάρχουν **δύο** κωδικοποιήσεις — και τότε τα παράγωγα του ενός
 * είδους θα φαίνονταν «σωστά» για το άλλο. Δύο κωδικοποιήσεις δίνουν **δύο συνταγές
 * μόνες τους**.
 *
 * 🔑 **Το `preset` μπαίνει στην υπογραφή**, όχι μόνο η ποιότητα: `lossless:icon` και
 * `lossless:photo` δίνουν **διαφορετικά bytes**, άρα οφείλουν να είναι διαφορετική
 * συνταγή — αλλιώς αλλαγή preset θα άφηνε τα παλιά παράγωγα δημοσιευμένα ως έγκυρα.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΤΟ `as-given` ΔΕΝ ΓΡΑΦΕΙ **ΤΙΠΟΤΑ** — ΣΙΩΠΗ ΜΕ ΝΟΗΜΑ, ΟΧΙ ΠΑΡΑΛΕΙΨΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το πλαισίωμα μπήκε στην υπογραφή επειδή **αλλάζει τα bytes** (Α21.10). Αλλά μια
 * υπογραφή που θα έγραφε `…:framing=as-given` για **κάθε** αντικείμενο θα **ακύρωνε
 * ολόκληρο το ράφι**: κάθε δημοσιευμένη φωτογραφία κάθε αγγελίας θα ξανακατέβαινε,
 * ξανα-αποκωδικοποιούνταν και ξανα-ανέβαινε — **χιλιάδες** πράξεις για μηδέν διαφορά
 * στα bytes.
 *
 * 🔑 **Άρα η προεπιλογή σιωπά, και μόνο η ΑΠΟΚΛΙΣΗ μιλά.** Ό,τι δεν τρίβεται κρατά
 * **κατά γράμμα** τη συμβολοσειρά που ζει σήμερα στα μεταδεδομένα της παραγωγής, και
 * μόνο τα **λογότυπα** αποκτούν `:trim25` ⇒ ξαναπαράγονται. Είναι το ίδιο ιδίωμα με
 * τις εκδόσεις συνταγών του `ffmpeg`, και το φυλά **άγκυρα κατά γράμμα** *(Κ2 στο
 * `public-shelf-invariants.test`)* ώστε η σιωπή να μην μπορεί να σπάσει κατά λάθος.
 *
 * ✅ **Και έχει δώρο**: τα ενεργά λογότυπα, ξαναπαραγόμενα, αποκτούν **και το παράγωγο
 * 512** που τους έλειπε από την Α21.9.7 — μισό δηλωμένο κενό κλείνει χωρίς εκστρατεία.
 */
export function shelfRecipe(encoding: RasterShelfEncoding, framing: ShelfFraming): string;
export function shelfRecipe(encoding: ModelShelfEncoding): string;
export function shelfRecipe(encoding: ShelfEncoding, framing?: ShelfFraming): string {
  // 🔴 **ΤΟ `webp:` ΠΑΥΕΙ ΝΑ ΓΡΑΦΕΤΑΙ ΑΝΕΥ ΟΡΩΝ** *(ADR-845 §3, άγκυρα Α-1)*. Ως τη Φ4.0
  //    αυτή η γραμμή ήταν το **πιο βαθύ** σημείο όπου το ράφι δήλωνε ότι κάθε πράγμα
  //    είναι εικόνα — και το χειρότερο, γιατί η συνταγή γίνεται **μεταδεδομένο** που
  //    ταξιδεύει με τα bytes και **κλειδί** που είναι content-addressed. Μια συνταγή που
  //    λέει ψέματα δεν είναι λάθος συμβολοσειρά: είναι **μόνιμη διεύθυνση** που λέει ψέματα.
  // ✅ **Φ4.2: ΤΟ ΜΟΝΤΕΛΟ ΠΑΥΕΙ ΝΑ ΠΕΤΑ** — γιατί απέκτησε ψήστη. Ως τη Φ4.1 αυτός ο
  //    κλάδος πετούσε *«no baker produces it yet»*, και ήταν **ακριβής**: μορφή δηλωμένη
  //    χωρίς καθαριστή που να την παράγει είναι **υπόσχεση χωρίς μηχανισμό**.
  if (encoding.kind === 'model') return modelRecipe(encoding);

  // ⚠️ **Ο ΤΥΠΟΣ ΤΟ ΕΓΓΥΑΤΑΙ, Ο ΕΛΕΓΧΟΣ ΤΟ ΕΚΤΕΛΕΙ.** Οι υπερφορτώσεις κάνουν το
  //    *«raster χωρίς πλαισίωμα»* αδύνατο σε χρόνο μεταγλώττισης — αλλά ο **N.17**
  //    απαγορεύει στον πράκτορα να τρέξει `tsc`, άρα μια εγγύηση μόνο σε χρόνο
  //    μεταγλώττισης θα ήταν **ανεπαλήθευτη**: ακριβώς το «0 = κανείς δεν κοίταξε».
  //    Ίδιο σκεπτικό με τη γραμμένη αιτιολόγηση του `MODEL_ENCODING` στις άγκυρες.
  if (framing === undefined) {
    // 🔗 ADR-841 §7 Α21.10 — η αναφορά ζει ΕΔΩ και όχι μέσα στη συμβολοσειρά:
    //    το κεφαλαίο «Α» της ενότητας είναι **ελληνικό γράμμα**, και ο σαρωτής
    //    ωμών κειμένων (N.11) διαβάζει κάθε ελληνικό χαρακτήρα μέσα σε
    //    `throw new Error(...)` ως κείμενο προς μετάφραση. Είναι invariant
    //    προγραμματιστή, όχι μήνυμα προς άνθρωπο — άρα το σωστό δεν είναι
    //    `t()`, ούτε λατινικό «A» που θα έσπαγε το CHECK 3.53.
    throw new Error('Raster shelf recipe requires a framing decision');
  }

  const quality = encoding.quality === 'lossless' ? 'lossless' : `q${encoding.quality}`;
  const base = `webp:${quality}:${encoding.preset}:w${encoding.widths.join('-')}`;

  return framing.mode === 'as-given' ? base : `${base}:trim${framing.threshold}`;
}

/**
 * **Η ΣΥΝΤΑΓΗ ΤΟΥ ΜΟΝΤΕΛΟΥ** — ό,τι αλλάζει τα bytes, και **τίποτα άλλο** (ADR-845 Φ4.2).
 *
 * ⛔ **ΚΑΝΕΝΑ ΠΛΑΙΣΙΩΜΑ, ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΠΑΡΑΛΕΙΨΗ.** Το {@link ShelfFraming} απαντά *«ποιο
 * κομμάτι της **εικόνας** είναι το περιεχόμενο;»* — ερώτηση που σε ένα μοντέλο **δεν έχει
 * νόημα**. Γι' αυτό το `framingOf` ζει στο `RasterShelfKind` και **όχι** στο `PublicShelfKind`:
 * η γραμμή του μοντέλου δεν επιτρέπεται να **μαντέψει** απάντηση σε ερώτηση που δεν την αφορά.
 * Μια συνταγή που έγραφε `:trim25` για GLB θα δήλωνε πράξη που **δεν εκτελείται ποτέ**.
 *
 * ⛔ **ΚΑΙ ΚΑΝΕΝΑ ΤΑΒΑΝΙ BYTES**: το όριο των 5 MB είναι κριτήριο **αποδοχής**, όχι
 * κωδικοποίησης. Μέσα στη συνταγή θα ακύρωνε **κάθε δημοσιευμένο μοντέλο** την ημέρα που
 * κάποιος το πείραζε, για **ταυτόσημα** bytes.
 */
function modelRecipe(encoding: ModelShelfEncoding): string {
  const { position, normal, texcoord } = encoding.quantise;
  return `glb:meshopt-${encoding.meshopt}:q${position}-${normal}-${texcoord}`;
}
