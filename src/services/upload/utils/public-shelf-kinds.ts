/**
 * 🏆 **ΤΟ ΣΗΜΑ ΤΟΥ ΕΠΑΓΓΕΛΜΑΤΙΑ** — λογότυπο ή πορτρέτο (ADR-841 §7 Α21, Στάδιο 2).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΑ ΠΛΑΤΗ ΕΙΝΑΙ **ΜΕΤΡΗΜΕΝΑ ΑΠΟ ΤΗΝ ΟΘΟΝΗ**, ΟΧΙ ΣΤΡΟΓΓΥΛΕΜΕΝΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `ShowcaseMarkView` ζωγραφίζει **44px** *(κάρτα καταλόγου, `h-11`)* και **64px**
 * *(σελίδα προφίλ, `h-16`)*. Με πυκνότητες 1×/2×/3× αυτό ζητά `{44, 88, 132}` και
 * `{64, 128, 192}`:
 *
 * | σκαλί | καλύπτει |
 * |---|---|
 * | **64** | 44@1× · 64@1× ακριβώς |
 * | **128** | 44@2×=88 · 64@2×=128 ακριβώς |
 * | **256** | 44@3×=132 · 64@3×=192 · **64@4×=256 ακριβώς** |
 *
 * ⇒ **Καμία πυκνότητα ως 4× στα 64px δεν υπο-εξυπηρετείται**, και το μεγαλύτερο παράγωγο
 * είναι **256px έναντι 2560px** της αγγελίας: **δέκα φορές μικρότερη ακμή, ~εκατό φορές
 * λιγότερα pixel**. Το να κατέβαζε ο επισκέπτης παράγωγο 2560px για σήμα μεγέθους νυχιού
 * ήταν το εύρημα που γέννησε ολόκληρο το Στάδιο 2.
 *
 * 🔴 **`lossless` ΚΑΙ ΟΧΙ «λίγο υψηλότερο q»**: λογότυπο = επίπεδες περιοχές + αιχμηρές
 * ακμές, δηλαδή **μόνο** οι μεταβάσεις που θολώνει η lossy συμπίεση. Το `cwebp` της
 * Google δίνει χωριστό `-preset icon`/`drawing` ακριβώς γι' αυτό. Και σε **256px** το
 * lossless δεν έχει κόστος που να αξίζει συζήτηση.
 *
 * ⚠️ **Η διαφάνεια ΜΕΝΕΙ** — δεν «ψήνεται» πλάκα φόντου: μια πλάκα είναι απόφαση για
 * **ένα** θέμα και **λάθος** στο άλλο *(ίδια οικογένεια με ADR-777 §8.57.3 α)*. Το
 * `bg-card` κάνει τη δουλειά, και στα δύο θέματα, χωρίς δεύτερο αντικείμενο.
 */
