/**
 * Είναι αυτό αποδεκτή ταυτότητα **αγγελίας** για δημόσιο κλειδί;
 *
 * 🔴 **ΜΕΝΕΙ ΕΞΑΓΟΜΕΝΟ ΜΕ ΤΟ ΙΔΙΟ ΟΝΟΜΑ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ.** Το Στάδιο 2 μπορούσε να το
 * απορροφήσει σε ανώνυμο κατηγόρημα μέσα στον {@link LISTING_SHELF} — ⛔ **απορρίφθηκε**:
 * η άγκυρα **Κ2** (`public-shelf-invariants.test.ts`) το καλεί **ονομαστικά**, οπότε θα
 * είχε συνεχίσει να **μεταγλωττίζεται και να περνά** δείχνοντας σε κάτι άλλο. Ο φρουρός
 * των αγγελιών θα είχε χάσει **σιωπηλά** το test του — «πράσινο επειδή κανείς δεν
 * κοίταξε», στην πιο ακριβή του μορφή.
 *
 * ⚠️ Ο περιγραφέας τον **δείχνει** αντί να τον αντιγράψει: `LISTING_SHELF.acceptsSubject`
 * **είναι** αυτή η συνάρτηση, όχι δίδυμό της.
 *
 * Δες τον αντίστροφό του: {@link isPublicShelfShowcaseId}.
 */
export function isPublicShelfListingId(value: string): boolean {
  if (!isSafeSubjectSegment(value)) return false;
  return !value.startsWith(TENANT_IDENTITY_PREFIX);
}

/**
 * 🔴 **Ο ΑΝΤΙΣΤΡΟΦΟΣ ΦΡΟΥΡΟΣ** — είναι αυτό αποδεκτή ταυτότητα για ράφι **βιτρίνας**;
 *
 * Ό,τι **απορρίπτει** το {@link isPublicShelfListingId} είναι ακριβώς ό,τι **απαιτεί**
 * αυτό, και ο λόγος δεν είναι συμμετρία — είναι ότι οι δύο ρίζες απαντούν **αντίθετες
 * ερωτήσεις ιδιωτικότητας**:
 *
 * - Σε **αγγελία** το `comp_` θα έλεγε *«αυτό το σπίτι το κρατά ΑΥΤΟΣ ο μισθωτής»* σε
 *   ανώνυμο επισκέπτη — πληροφορία που το `PublicListing` **επίτηδες** δεν κουβαλά.
 * - Σε **βιτρίνα** το `comp_` **ΕΙΝΑΙ** το περιεχόμενο: ο οργανισμός δημοσίευσε τον
 *   εαυτό του, και το ίδιο το έγγραφο διαβάζεται από **ανώνυμο**
 *   *(`firestore.rules:1079` → `allow read: if true`)*.
 *
 * 🏆 **Γι' αυτό είναι δύο κατηγορήματα και όχι ένα με σημαία**: έτσι καμία από τις δύο
 * ρίζες **δεν μπορεί** να ταΐσει την ταυτότητα της άλλης, ακόμη κι αν κάποιος περάσει
 * λάθος περιγραφέα. Η εγγύηση είναι **δομική**, όχι διαδικαστική.
 */
export function isPublicShelfShowcaseId(value: string): boolean {
  if (!isSafeSubjectSegment(value)) return false;
  return value.startsWith(TENANT_IDENTITY_PREFIX);
}

/**
 * **Ο ΚΟΙΝΟΣ ΠΥΡΗΝΑΣ ΤΩΝ ΔΥΟ ΦΡΟΥΡΩΝ** — ό,τι ισχύει για **κάθε** υποκείμενο.
 *
 * 🔑 **Εξήχθη επειδή το ζητά πύλη, όχι επειδή φάνηκε ωραίο** (N.18 / CHECK 3.28): οι δύο
 * φρουροί διαφέρουν σε **μία** γραμμή και συμφωνούν στις υπόλοιπες τρεις — δηλαδή ήταν
 * ακριβώς το σχήμα *«κεντρικοποιείς το Α, γράφεις το Β ως δίδυμο»*.
 *
 * ⚠️ **Δεν αρκεί το {@link isValidPathSegment}**, και είναι μετρημένο: το μοτίβο
 * `/^[\p{L}\p{N}_.\-]+$/u` επιτρέπει τελείες, άρα δέχεται **`..`** — αθώο για τα
 * παραγόμενα enterprise ids όπου χρησιμοποιείται σήμερα, **όχι** αθώο εδώ όπου το τμήμα
 * γίνεται πρόθεμα **διαγραφής**.
 */
function isSafeSubjectSegment(value: string): boolean {
  if (!isValidPathSegment(value)) return false;
  return value !== '.' && value !== '..';
}


