/**
 * **ΠΩΣ ΚΩΔΙΚΟΠΟΙΕΙΤΑΙ ΜΙΑ ΕΙΚΟΝΑ** — σκέτα δεδομένα, **κανένα `sharp`**.
 *
 * 🔑 **Ζει στο ΚΑΘΑΡΟ module επίτηδες.** Θα ήταν φυσικό να κατοικεί δίπλα στον καθαριστή
 * που τα καταναλώνει — αλλά τότε ο **περιγραφέας** ({@link PublicShelfKind}) θα έπρεπε να
 * εισάγει από module που φορτώνει `sharp`, δηλαδή ο πελάτης δεν θα μπορούσε ποτέ να
 * ρωτήσει *«ποια είναι η ρίζα της βιτρίνας;»*. Πλάτη και ποιότητα είναι **αριθμοί**·
 * μόνο η **εφαρμογή** τους είναι εγγενής.
 *
 * ⚠️ **Τα πλάτη είναι ΑΥΞΟΥΣΑ, και το τελευταίο είναι το «κανονικό»** — η προβολή
 * διαβάζει το τελευταίο ως τον στόχο του `src`. Άγκυρα φυλάει τη σειρά.
 *
 * 🔴 **ΤΟ `kind: 'raster'` ΔΕΝ ΕΙΝΑΙ ΔΙΑΚΟΣΜΗΤΙΚΟ** *(ADR-845 §3, Φ4.0)*. Ως σήμερα αυτός
 * ο τύπος **ήταν** η κωδικοποίηση — δηλαδή το ράφι δήλωνε, σιωπηλά, ότι κάθε πράγμα που
 * δημοσιεύεται είναι **εικόνα**. Ο διακριτής το κάνει **ερώτηση που πρέπει να απαντηθεί**:
 * κάθε καταναλωτής υποχρεώνεται να πει *«τι είδους bytes;»* πριν αγγίξει πλάτος ή ποιότητα.
 */
export interface RasterShelfEncoding {
  readonly kind: 'raster';
  readonly widths: readonly number[];
  /**
   * `'lossless'` για **σήματα**, αριθμός για **φωτογραφίες** — και δεν είναι γούστο.
   *
   * Η τεκμηρίωση του `cwebp` δίνει χωριστά preset για `photo` και `icon`/`drawing`
   * ακριβώς επειδή η lossy συμπίεση **θολώνει τις σκληρές μεταβάσεις**: ένα λογότυπο
   * είναι επίπεδες περιοχές + αιχμηρές ακμές, δηλαδή **μόνο** σκληρές μεταβάσεις.
   * Το `q82` που κρατά ευανάγνωστες τις κατόψεις θα έτρωγε τις ακμές ενός σήματος.
   */
  readonly quality: number | 'lossless';
  readonly preset: 'photo' | 'icon';
}

/**
 * **ΠΩΣ ΚΩΔΙΚΟΠΟΙΕΙΤΑΙ ΕΝΑ ΤΡΙΣΔΙΑΣΤΑΤΟ ΜΟΝΤΕΛΟ** — ⛔ **ΚΕΝΟ ΕΠΙΤΗΔΕΣ** *(ADR-845 §3)*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΚΕΝΟ ΕΙΝΑΙ **ΜΕΤΡΗΜΕΝΟ**, ΟΧΙ ΗΜΙΤΕΛΕΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο χώρος παραμέτρων ενός ψησίματος μοντέλου **δεν είναι μικρός**: τα `glTF-Transform` /
 * `gltf-pipeline` εκθέτουν συμπίεση γεωμετρίας *(`draco` με `method`, `quantizeColorBits`,
 * `quantizeGenericBits`, `unifiedQuantization`, `uncompressedFallback` — ή `meshopt` με
 * `level`)* **και** συμπίεση υφών *(`ktx2` με `UASTC`/`ETC1S`, `level`, `rdo-lambda`,
 * `zstd`)*. Κάθε υποσύνολο που θα **μαντεύαμε** σήμερα θα γινόταν {@link shelfRecipe} που
 * **λέει ψέματα** — και επειδή το κλειδί είναι content-addressed, το ψέμα θα γινόταν
 * **μόνιμη διεύθυνση**.
 *
 * ⇒ Οι παράμετροι μπαίνουν **μαζί με τον ψήστη που τις εκτελεί**, ποτέ πριν. Ακριβώς ο
 * κανόνας που το `storage-path-public-shelf` γράφει για το `glb`: *«μορφή δηλωμένη χωρίς
 * καθαριστή που να την παράγει είναι υπόσχεση χωρίς μηχανισμό»*.
 *
 * 🔑 **Και όμως ΔΕΝ είναι άχρηστο.** Ως δεύτερο μέλος της ένωσης κάνει τρία πράγματα που
 * ένα σχόλιο δεν μπορεί: στενεύει τον καθαριστή ώστε ένα μοντέλο να **μην μπορεί** να
 * φτάσει στο `sharp`, σπάει τη μεταγλώττιση σε όποιον δεν απάντησε, και δίνει στις άγκυρες
 * **νόμιμη** τιμή να ρωτήσουν *«γράφει `webp:` για μη-εικόνα;»* — **χωρίς κανένα cast**.
 *
 * ⚠️ **Δεν υπάρχει ακόμη {@link PublicShelfKind} που να το φοράει**, και είναι το νόημα:
 * η Φ4.0 ανοίγει την πόρτα· **δεν** περνά κανείς.
 */
export interface ModelShelfEncoding {
  readonly kind: 'model';
}

/**
 * 🏆 **ΤΙ ΕΙΔΟΥΣ BYTES ΔΗΜΟΣΙΕΥΟΝΤΑΙ** — ο άξονας που έλειπε *(ADR-845 §3, Φ4.0)*.
 *
 * 🔴 **Ο {@link PUBLIC_SHELF_KINDS} γενικεύει ΑΛΛΟΝ άξονα**, και η διάκριση είναι όλο το
 * εύρημα: εκείνος απαντά *«ποιο πράγμα δημοσιεύεται;»* *(αγγελία, βιτρίνα)*. **Δεν**
 * απαντά *«τι είδους bytes είναι;»*. Ένα `MODEL_SHELF` με `widths: [640, 1280, 2560]`
 * θα ήταν πρόταση **χωρίς νόημα** — γι' αυτό ο διακριτής μπαίνει **εδώ**, μέσα στην
 * κωδικοποίηση, και όχι ως τρίτη γραμμή στον πίνακα των ειδών.
 *
 * ⛔ **ΠΟΤΕ `extension: string` με προεπιλογή `'webp'`** — ίδια κλάση με το «προαιρετικό
 * `at`» που το `listing-material.ts` απέρριψε γραπτώς: μια προεπιλογή εδώ σημαίνει ότι ο
 * πρώτος που θα ξεχάσει να απαντήσει **θα δημοσιεύσει μοντέλο ως webp**, σιωπηλά.
 *
 * 🔑 **Ακολουθεί τον γείτονά του**: το {@link ShelfFraming} από κάτω είναι ήδη διακριτή
 * ένωση. Το σχήμα **δεν** εισάγεται εδώ — υιοθετείται.
 */
export type ShelfEncoding = RasterShelfEncoding | ModelShelfEncoding;

/**
 * 🏆 **ΠΩΣ ΠΛΑΙΣΙΩΝΕΤΑΙ ΤΟ ΠΕΡΙΕΧΟΜΕΝΟ ΜΕΣΑ ΣΤΑ BYTES** (ADR-841 §7 Α21.10).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΕΙΝΑΙ ΞΕΧΩΡΙΣΤΗ ΕΡΩΤΗΣΗ ΑΠΟ ΤΗΝ {@link ShelfEncoding}
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η κωδικοποίηση απαντά *«πόσο μεγάλο και πόσο συμπιεσμένο;»* — ερώτηση του **είδους
 * του ραφιού**, ίδια για κάθε αντικείμενο μέσα του. Το πλαισίωμα απαντά *«ποιο κομμάτι
 * της εικόνας είναι το περιεχόμενο;»* — ερώτηση του **υλικού**, και οι δύο κάτοικοι της
 * βιτρίνας δίνουν **αντίθετες** απαντήσεις:
 *
 * - Το **λογότυπο** έχει περιθώριο που κανείς δεν επέλεξε *(το άφησε το εργαλείο
 *   εξαγωγής)* ⇒ κόβεται, ώστε δύο σήματα να έχουν **ίδιο οπτικό βάρος**.
 * - Το **πορτρέτο** έχει περιθώριο που **είναι** η καδραρισμένη φωτογραφία ⇒ ένα τρίμμα
 *   θα κόλλαγε το κεφάλι στην άκρη του κύκλου.
 *
 * 🔴 **ΓΙ' ΑΥΤΟ ΤΟ `preset: 'icon'` ΔΕΝ ΗΤΑΝ ΠΟΤΕ ΤΟ ΣΩΣΤΟ ΚΡΙΤΗΡΙΟ**, παρότι έτσι
 * γράφτηκε το αρχικό σχέδιο της Φάσης Β: το {@link SHOWCASE_SHELF} σερβίρει **και τα
 * δύο** είδη με το ίδιο preset. Κριτήριο πάνω στην κωδικοποίηση θα **κούρευε selfie**.
 */
export type ShelfFraming =
  /** Τα bytes μένουν **όπως τα έδωσε ο άνθρωπος**. Η προεπιλογή κάθε υλικού. */
  | { readonly mode: 'as-given' }
  /**
   * Τα bytes κόβονται **στο μελάνι** — αλλά **μόνο** αν ο κριτής του περιγράμματος δώσει
   * άδεια *(`public-shelf-border`)*. Το κατώφλι ταξιδεύει μαζί επειδή **αλλάζει τα
   * bytes**, άρα οφείλει να βρίσκεται στην υπογραφή της συνταγής.
   */
  | { readonly mode: 'ink-tight'; readonly threshold: number };

/** Το υλικό δεν έχει περιθώριο να χάσει — ή δεν επιτρέπεται να το χάσει. */
export const FRAMING_AS_GIVEN: ShelfFraming = { mode: 'as-given' };

/**
 * **Κόψε το περιθώριο, κράτα το μελάνι** — και ο αέρας μπαίνει από την **παρουσίαση**.
 *
 * 🔑 **Κατώφλι 25, μετρημένο**: στην προεπιλογή του `sharp` *(10)* το ringing του JPEG
 * άφηνε υπόλειμμα 2px — το **ίδιο** λογότυπο σε PNG και σε JPEG έδινε **διαφορετικές**
 * διαστάσεις *(`670×160` έναντι `671×162`)*, δηλαδή η κανονικοποίηση θα εξαρτιόταν από
 * τη μορφή του αρχείου. Στο 25 τα δύο ταυτίζονται.
 *
 * ⛔ **Το `lineArt: true` ΔΟΚΙΜΑΣΤΗΚΕ ΚΑΙ ΑΠΟΡΡΙΦΘΗΚΕ**, παρότι η τεκμηρίωση το προτείνει
 * ακριβώς για διανυσματικό υλικό: στο ίδιο δείγμα **χειροτέρεψε** το αποτέλεσμα σε
 * `671×176`. Η τεκμηρίωση περιγράφει πρόθεση· η μέτρηση περιγράφει τη μηχανή.
 */
export const FRAMING_INK_TIGHT: ShelfFraming = { mode: 'ink-tight', threshold: 25 };

/**
 * 🏆 **ΕΝΑ ΕΙΔΟΣ ΠΡΑΓΜΑΤΟΣ ΠΟΥ ΔΗΜΟΣΙΕΥΕΤΑΙ** — μία γραμμή του {@link PUBLIC_SHELF_KINDS}.
 *
 * Κάθε γραμμή απαντά **τρία**: *«σε ποια ρίζα;»*, *«ποια ταυτότητα επιτρέπεται εκεί;»*
 * και *«με ποια κωδικοποίηση;»*. Νέο είδος ⇒ **μία γραμμή**, τίποτα άλλο —
 * το ιδίωμα του `BOUNDARIES` (CHECK 3.74).
 *
 * 🔴 **ΤΟ `acceptsSubject` ΕΙΝΑΙ Ο ΛΟΓΟΣ ΠΟΥ ΑΥΤΟ ΕΙΝΑΙ ΠΙΝΑΚΑΣ ΚΑΙ ΟΧΙ ΣΗΜΑΙΑ.** Δύο
 * είδη με **αντίθετους** φρουρούς δεν εκφράζονται με `if (isShowcase)`: η άρνηση του
 * ενός είναι η **απαίτηση** του άλλου, και μια σημαία θα άφηνε τον επόμενο να ρωτήσει
 * *«ποιο είναι το προεπιλεγμένο;»* — ερώτηση που **δεν έχει ασφαλή απάντηση**.
 */
export interface PublicShelfKind<M> {
  readonly root: string;
  /** Ο φρουρός ταυτότητας **αυτού** του είδους — δες τον πίνακα στο σκεπτικό του module. */
  readonly acceptsSubject: (value: string) => boolean;
  readonly encoding: ShelfEncoding;
  /**
   * 🏆 **ΠΩΣ ΠΛΑΙΣΙΩΝΕΤΑΙ ΑΥΤΟ ΤΟ ΥΛΙΚΟ** — η γραμμή ρωτιέται, η μηχανή δεν ερμηνεύει.
   *
   * ⚠️ **ΔΕΝ ΠΑΡΑΒΙΑΖΕΙ ΤΟ «ΤΟ ΡΑΦΙ ΚΟΥΒΑΛΑ, ΔΕΝ ΕΡΜΗΝΕΥΕΙ»**, και η διάκριση είναι
   * ακριβώς η ίδια με το {@link acceptsSubject}: ο **γραφέας** εξακολουθεί να μην
   * ξέρει τι σημαίνει «λογότυπο» — καλεί τη γραμμή. Η **γραμμή** ξέρει, γιατί αυτό
   * είναι όλη της η δουλειά. Ένα `if (isShowcase)` μέσα στη μηχανή θα ήταν η
   * παραβίαση· ένα ακόμη κελί στον πίνακα είναι η **τήρηση**.
   *
   * 🔴 **ΚΑΙ ΕΙΝΑΙ Ο ΛΟΓΟΣ ΠΟΥ Ο ΠΕΡΙΓΡΑΦΕΑΣ ΕΓΙΝΕ ΓΕΝΙΚΟΣ.** Ως εδώ το
   * `reconcilePublicShelf<M>(kind: PublicShelfKind, …)` άφηνε το είδος **ασύνδετο** από
   * το υλικό: μπορούσες να περάσεις το {@link SHOWCASE_SHELF} με πηγές αγγελίας και
   * **τίποτα δεν διαμαρτυρόταν** — ενώ οι δύο φρουροί ταυτότητας είναι **αντίθετοι**,
   * δηλαδή η αστοχία θα ήταν βέβαιη και σε χρόνο εκτέλεσης. Το `M` την κάνει
   * **αδύνατη σε χρόνο μεταγλώττισης**.
   *
   * ⚠️ **Συνάρτηση και όχι σταθερά**, γιατί η απάντηση εξαρτάται από το **αντικείμενο**:
   * η ίδια ρίζα δημοσιεύει λογότυπα *(τρίβονται)* και πορτρέτα *(δεν αγγίζονται)*.
   */
  readonly framingOf: (material: M) => ShelfFraming;
}

/**
 * **Οποιαδήποτε γραμμή, χωρίς να ρωτηθεί το υλικό της.**
 *
 * 🔑 Υπάρχει για τις άγκυρες που ρωτούν *«ισχύει για ΚΑΘΕ γραμμή;»* πάνω στο
 * {@link PUBLIC_SHELF_KINDS} — και για τα κοινά βήματα του γραφέα *(ρίζα, σάρωση,
 * διαγραφή)* που δεν αγγίζουν ποτέ το υλικό. Το `never` είναι η **ασφαλής** εκδοχή:
 * κάθε συγκεκριμένο είδος ανατίθεται σε αυτό, αλλά κανείς δεν μπορεί να **καλέσει** το
 * `framingOf` χωρίς πρώτα να ξέρει τι κρατά.
 */
export type AnyPublicShelfKind = PublicShelfKind<never>;

/**
 * 🏆 **ΜΙΑ ΓΡΑΜΜΗ ΠΟΥ ΔΗΜΟΣΙΕΥΕΙ ΕΙΚΟΝΕΣ** — ο περιγραφέας **αφού** απαντηθεί το
 * *«τι είδους bytes;»* *(ADR-845 §3, Φ4.0)*.
 *
 * 🔴 **ΕΙΝΑΙ Ο ΤΥΠΟΣ ΠΟΥ ΖΗΤΑ Ο ΓΡΑΦΕΑΣ, ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΤΥΠΙΚΟΤΗΤΑ.** Ολόκληρη η μηχανή
 * του `public-shelf.service` είναι **σχήματος raster από άκρη σε άκρη**: η μνήμη του
 * ραφιού έχει κλειδί το **πλάτος**, τα μεταδεδομένα κουβαλούν `requestedWidths`, και η
 * γρήγορη διαδρομή ρωτά *«υπάρχουν ΟΛΑ τα πλάτη;»*. Αυτό **δεν** είναι τρεις τυχαίες
 * αναφορές σε πεδίο — είναι η **πληθυντικότητα** του raster: μια εικόνα δημοσιεύεται ως
 * **οικογένεια** παραγώγων, ένα ανά πυκνότητα οθόνης.
 *
 * 🔑 **Ένα μοντέλο ΔΕΝ έχει αυτή την πληθυντικότητα**, και είναι μετρημένο, όχι υπόθεση:
 * η πρακτική του κλάδου βάζει τα επίπεδα λεπτομέρειας **μέσα** στο ίδιο αρχείο
 * *(`MSFT_lod`, προοδευτικά υποκατάστατα, `KHR_materials_variants`)* αντί για Ν αρχεία
 * ανά μέγεθος. Γι' αυτό και το ADR-841 §6 μιλά για **«το δημοσιευμένο GLB»**, στον ενικό.
 *
 * ⇒ Η στένωση γίνεται **μία φορά, στο σύνορο** του γραφέα — και ό,τι είναι από κάτω
 * μένει **αναλλοίωτο**. Ένας έλεγχος ανά συνάρτηση θα ήταν τέσσερις ευκαιρίες να
 * ξεχαστεί η μία.
 */
export interface RasterShelfKind<M> extends PublicShelfKind<M> {
  readonly encoding: RasterShelfEncoding;
}

/**
 * **Δημοσιεύει αυτή η γραμμή εικόνες;** — ο φρουρός που στενεύει το σύνορο.
 *
 * ⚠️ **Ρωτά την ΚΩΔΙΚΟΠΟΙΗΣΗ, ποτέ τη ρίζα.** Ένα `kind.root === 'listings'` θα ήταν η
 * ίδια αστοχία με το `if (isShowcase)`: κριτήριο πάνω σε **ποιο πράγμα** δημοσιεύεται,
 * για ερώτηση που αφορά **τι είδους bytes** είναι. Οι δύο άξονες είναι ανεξάρτητοι —
 * αυτό ακριβώς ανακάλυψε το ADR-845 §3.
 */
export function isRasterShelfKind<M>(kind: PublicShelfKind<M>): kind is RasterShelfKind<M> {
  return kind.encoding.kind === 'raster';
}

/**
 * **Οποιαδήποτε γραμμή εικόνων, χωρίς να ρωτηθεί το υλικό της** — η αδελφή του
 * {@link AnyPublicShelfKind}, για τα βήματα του γραφέα που αγγίζουν **πλάτη** αλλά όχι υλικό.
 */
export type AnyRasterShelfKind = RasterShelfKind<never>;

