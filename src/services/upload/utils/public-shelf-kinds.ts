/**
 * 🔴 **Η ΥΠΟΓΡΑΦΗ ΤΗΣ ΣΥΝΤΑΓΗΣ — ΠΑΡΑΓΟΜΕΝΗ, ΠΟΤΕ ΓΡΑΜΜΕΝΗ ΜΕ ΤΟ ΧΕΡΙ** (Α2.3).
 *
 * Ταξιδεύει ως μεταδεδομένο κάθε δημοσιευμένου αντικειμένου, ώστε η συμφιλίωση να μπορεί
 * να απαντήσει *«αυτό το παράγωγο βγήκε από τη ΣΗΜΕΡΙΝΗ συνταγή;»* **χωρίς να
 * αποκωδικοποιήσει τίποτα**.
 *
 * ⚠️ **Ήταν σταθερά, έγινε συνάρτηση, και ο λόγος είναι ο ίδιος με πριν.** Ένα
 * χειρόγραφο `'v1'` θα ξεχνιόταν στην πρώτη αλλαγή ποιότητας· μια **σταθερά** ξεχνιέται
 * την πρώτη φορά που υπάρχουν **δύο** κωδικοποιήσεις — και τότε τα παράγωγα του ενός
 * είδους θα φαίνονταν «σωστά» για το άλλο. Δύο κωδικοποιήσεις δίνουν **δύο συνταγές
 * μόνες τους**.
 *
 * 🔑 **Το `preset` μπαίνει στην υπογραφή**, όχι μόνο η ποιότητα: `lossless:icon` και
 * `lossless:photo` δίνουν **διαφορετικά bytes**, άρα οφείλουν να είναι διαφορετική
 * συνταγή — αλλιώς αλλαγή preset θα άφηνε τα παλιά παράγωγα δημοσιευμένα ως έγκυρα.
 */
export function shelfRecipe(encoding: ShelfEncoding): string {
  const quality = encoding.quality === 'lossless' ? 'lossless' : `q${encoding.quality}`;
  return `webp:${quality}:${encoding.preset}:w${encoding.widths.join('-')}`;
}

/**
 * **ΟΙ ΦΩΤΟΓΡΑΦΙΕΣ ΜΙΑΣ ΑΓΓΕΛΙΑΣ** — η αρχική, και ακόμη η πολυπληθέστερη, γραμμή.
 *
 * Τα πλάτη είναι της **γκαλερί ακινήτου** *(Α2.2)*: η Zillow σερβίρει γύρω στα 1536px,
 * και κρατάμε περιθώριο για οθόνες υψηλής πυκνότητας. Το `q82` είναι διαλεγμένο ώστε να
 * μένουν **ευανάγνωστα τα τεκμήρια** — κατόψεις, διαστάσεις, κείμενα μέσα στην εικόνα.
 */
export const LISTING_SHELF: PublicShelfKind = {
  root: PUBLIC_SHELF_LISTING_ROOT,
  acceptsSubject: isPublicShelfListingId,
  encoding: { widths: [640, 1280, 2560], quality: 82, preset: 'photo' },
};

/**
 * 🏆 **ΤΟ ΣΗΜΑ ΤΟΥ ΕΠΑΓΓΕΛΜΑΤΙΑ** — λογότυπο ή πορτρέτο (ADR-841 §7 Α21, Στάδιο 2).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΑ ΠΛΑΤΗ ΕΙΝΑΙ **ΜΕΤΡΗΜΕΝΑ ΑΠΟ ΤΗΝ ΟΘΟΝΗ**, ΟΧΙ ΣΤΡΟΓΓΥΛΕΜΕΝΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `ShowcaseMarkView` ζωγραφίζει **44px** *(κάρτα καταλόγου, `h-11`)* και **64px**
 * *(σελίδα προφίλ, `h-16`)*. Με πυκνότητες 1×/2×/3× αυτό ζητά `{44, 88, 132}` και
 * `{64, 128, 192}`:
 *
 * | σκαλί | καλύπτει |
 * |---|---|
 * | **64** | 44@1× · 64@1× ακριβώς |
 * | **128** | 44@2×=88 · 64@2×=128 ακριβώς |
 * | **256** | 44@3×=132 · 64@3×=192 · **64@4×=256 ακριβώς** |
 *
 * ⇒ **Καμία πυκνότητα ως 4× στα 64px δεν υπο-εξυπηρετείται**, και το μεγαλύτερο παράγωγο
 * είναι **256px έναντι 2560px** της αγγελίας: **δέκα φορές μικρότερη ακμή, ~εκατό φορές
 * λιγότερα pixel**. Το να κατέβαζε ο επισκέπτης παράγωγο 2560px για σήμα μεγέθους νυχιού
 * ήταν το εύρημα που γέννησε ολόκληρο το Στάδιο 2.
 *
 * 🔴 **`lossless` ΚΑΙ ΟΧΙ «λίγο υψηλότερο q»**: λογότυπο = επίπεδες περιοχές + αιχμηρές
 * ακμές, δηλαδή **μόνο** οι μεταβάσεις που θολώνει η lossy συμπίεση. Το `cwebp` της
 * Google δίνει χωριστό `-preset icon`/`drawing` ακριβώς γι' αυτό. Και σε **256px** το
 * lossless δεν έχει κόστος που να αξίζει συζήτηση.
 *
 * ⚠️ **Η διαφάνεια ΜΕΝΕΙ** — δεν «ψήνεται» πλάκα φόντου: μια πλάκα είναι απόφαση για
 * **ένα** θέμα και **λάθος** στο άλλο *(ίδια οικογένεια με ADR-777 §8.57.3 α)*. Το
 * `bg-card` κάνει τη δουλειά, και στα δύο θέματα, χωρίς δεύτερο αντικείμενο.
 */
export const SHOWCASE_SHELF: PublicShelfKind = {
  root: PUBLIC_SHELF_SHOWCASE_ROOT,
  acceptsSubject: isPublicShelfShowcaseId,
  encoding: { widths: [64, 128, 256], quality: 'lossless', preset: 'icon' },
};

/**
 * **Όλα τα είδη** — ώστε οι άγκυρες να μπορούν να ρωτήσουν *«ισχύει για ΚΑΘΕ γραμμή;»*
 * χωρίς να τις απαριθμεί καθεμιά ξεχωριστά και να ξεχάσει την επόμενη.
 */
export const PUBLIC_SHELF_KINDS: readonly PublicShelfKind[] = [LISTING_SHELF, SHOWCASE_SHELF];
