/**
 * 🏆 **ΤΟ ΣΗΜΑ ΤΟΥ ΕΠΑΓΓΕΛΜΑΤΙΑ** — λογότυπο ή πορτρέτο (ADR-841 §7 Α21, Στάδιο 2).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΑ ΠΛΑΤΗ ΕΙΝΑΙ **ΜΕΤΡΗΜΕΝΑ ΑΠΟ ΤΗΝ ΟΘΟΝΗ**, ΟΧΙ ΣΤΡΟΓΓΥΛΕΜΕΝΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `ShowcaseMarkView` ζωγραφίζει **44px** *(κάρτα καταλόγου, `h-11`)* και **64px**
 * *(σελίδα προφίλ, `h-16`)*. Με πυκνότητες 1×/2×/3× αυτό ζητά `{44, 88, 132}` και
 * `{64, 128, 192}`:
 *
 * | σκαλί | καλύπτει |
 * |---|---|
 * | **64** | 44@1× · 64@1× ακριβώς |
 * | **128** | 44@2×=88 · 64@2×=128 ακριβώς |
 * | **256** | 44@3×=132 · 64@3×=192 · **64@4×=256 ακριβώς** |
 *
 * ⇒ **Καμία πυκνότητα ως 4× στα 64px δεν υπο-εξυπηρετείται**, και το μεγαλύτερο παράγωγο
 * είναι **256px έναντι 2560px** της αγγελίας: **δέκα φορές μικρότερη ακμή, ~εκατό φορές
 * λιγότερα pixel**. Το να κατέβαζε ο επισκέπτης παράγωγο 2560px για σήμα μεγέθους νυχιού
 * ήταν το εύρημα που γέννησε ολόκληρο το Στάδιο 2.
 *
 * 🔴 **`lossless` ΚΑΙ ΟΧΙ «λίγο υψηλότερο q»**: λογότυπο = επίπεδες περιοχές + αιχμηρές
 * ακμές, δηλαδή **μόνο** οι μεταβάσεις που θολώνει η lossy συμπίεση. Το `cwebp` της
 * Google δίνει χωριστό `-preset icon`/`drawing` ακριβώς γι' αυτό. Και σε **256px** το
 * lossless δεν έχει κόστος που να αξίζει συζήτηση.
 *
 * ⚠️ **Η διαφάνεια ΜΕΝΕΙ** — δεν «ψήνεται» πλάκα φόντου: μια πλάκα είναι απόφαση για
 * **ένα** θέμα και **λάθος** στο άλλο *(ίδια οικογένεια με ADR-777 §8.57.3 α)*. Το
 * `bg-card` κάνει τη δουλειά, και στα δύο θέματα, χωρίς δεύτερο αντικείμενο.
 */
export const SHOWCASE_SHELF: RasterShelfKind<ShowcaseMarkMaterial> = {
  root: PUBLIC_SHELF_SHOWCASE_ROOT,
  acceptsSubject: isPublicShelfShowcaseId,
  // 🔴 **ΤΟ 512 ΜΠΗΚΕ ΜΕ ΤΗ ΖΩΝΗ** (ADR-841 §7 Α21.9). Όσο κάθε σήμα ήταν **τετράγωνο
  //    ως 64px**, το 256 κάλυπτε ακόμη και 4×. Από τη στιγμή που ένα wordmark απλώνεται
  //    ως **240 λογικά px**, η διπλή πυκνότητα ζητά **480** — και το ράφι θα έδινε 256,
  //    δηλαδή τεντωμένο ×1,9. **Θολούρα χωρίς κανένα σφάλμα πουθενά**, ακριβώς το
  //    σχήμα που κυνηγά η άγκυρα Κ5 του `showcase-mark-box.test` — που το **έπιασε**.
  encoding: { kind: 'raster', widths: [64, 128, 256, 512], quality: 'lossless', preset: 'icon' },
  // 🏆 **ΤΟ ΣΗΜΕΙΟ ΟΠΟΥ Η ΜΙΑ ΡΙΖΑ ΔΙΝΕΙ ΔΥΟ ΑΠΑΝΤΗΣΕΙΣ** (ADR-841 §7 Α21.10):
  //    το **λογότυπο** κουβαλά περιθώριο που **κανείς δεν επέλεξε** — το άφησε το
  //    εργαλείο εξαγωγής — και δύο γραφεία φαίνονται «μεγάλο» και «μικρό» χωρίς να το
  //    έχει αποφασίσει άνθρωπος. Το **πορτρέτο** κουβαλά περιθώριο που **ΕΙΝΑΙ** το
  //    κάδρο της φωτογραφίας: τρίμμα εκεί κολλάει το κεφάλι στην άκρη του κύκλου.
  //    ⚠️ Το `preset` είναι **κοινό** και στα δύο — γι' αυτό δεν μπορούσε ποτέ να είναι
  //    αυτό το κριτήριο.
  framingOf: (material) => (material.kind === 'logo' ? FRAMING_INK_TIGHT : FRAMING_AS_GIVEN),
};

/**
 * 🏆 **ΤΟ ΤΡΙΣΔΙΑΣΤΑΤΟ ΜΟΝΤΕΛΟ ΜΙΑΣ ΑΓΓΕΛΙΑΣ** — η τρίτη γραμμή *(ADR-845 Φ4.2, άγκυρα Α-1γ)*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΙΔΙΑ ΡΙΖΑ ΜΕ ΤΙΣ ΦΩΤΟΓΡΑΦΙΕΣ, ΚΑΙ **ΔΕΝ ΣΥΓΚΡΟΥΟΝΤΑΙ** — ΜΕΤΡΗΜΕΝΟ, ΟΧΙ ΣΥΜΦΩΝΙΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Δύο γραμμές που μοιράζονται ρίζα **και** ταυτότητα υποκειμένου μοιράζονται και **πρόθεμα**:
 * `listings/<id>/`. Ο γραφέας σαρώνει αυτό το πρόθεμα και **σβήνει ό,τι περισσεύει**
 * *(`deleteExtra`)* — άρα η προφανής ανησυχία είναι *«θα σβήσει η συμφιλίωση των εικόνων το
 * `.glb`;»*.
 *
 * ✅ **ΟΧΙ, ΚΑΙ Η ΕΓΓΥΗΣΗ ΕΙΝΑΙ ΔΟΜΙΚΗ**: το `deleteExtra` αγγίζει **μόνο** κλειδιά που
 * αναγνωρίζει το `parsePublicShelfKey(kind, …)`, και εκείνο επιστρέφει `null` όταν η κατάληξη
 * δεν είναι εκείνη **αυτού** του είδους. Η συμφιλίωση των εικόνων **δεν βλέπει** τα `.glb`, και
 * η συμφιλίωση των μοντέλων **δεν βλέπει** τα `.webp`. Ο *«ανεκτικός αναγνώστης απέναντι στον
 * αυστηρό γραφέα»* — γραμμένος για άλλο λόγο — απαντά **και** αυτή την ερώτηση.
 *
 * 🔑 **Γι' αυτό ΔΕΝ επινοήθηκε τέταρτη ρίζα** *(`listing-models/`)*: θα ήταν δεύτερη θέση για
 * το υλικό **της ίδιας αγγελίας**, με δικό της κύκλο ζωής και δική της απόσυρση — δηλαδή δύο
 * πράγματα να θυμάται κανείς αντί για ένα, όπου το ένα δούλευε ήδη.
 *
 * ⚠️ **Το υλικό είναι `ListingMaterial`, ίδιο με τη γραμμή των φωτογραφιών**: το `M` δένει τη
 * γραμμή με το **λεξιλόγιο** της αγγελίας, όχι με το είδος των bytes. Η διάκριση raster/model
 * ζει στην **κωδικοποίηση** — οι δύο άξονες είναι ανεξάρτητοι, και αυτό ακριβώς ανακάλυψε το
 * ADR-845 §3.
 */
