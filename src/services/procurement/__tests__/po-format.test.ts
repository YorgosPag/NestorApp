/**
 * ADR-923 §5.11 «3γ» Α11 — ΕΝΑ όνομα αρχείου για το PDF παραγγελίας (διακομιστής · πελάτης · email).
 */

import { poPdfFilename } from '../po-format';

describe('poPdfFilename', () => {
  it('λήψη ⇒ ο αριθμός παραγγελίας, όχι το εσωτερικό id', () => {
    expect(poPdfFilename('PO-0001')).toBe('PO-0001.pdf');
  });

  it('συνημμένο email ⇒ αριθμός + προμηθευτής, κενά σε κάτω παύλες', () => {
    expect(poPdfFilename('PO-0001', 'Γεωργία Ζέρβα')).toBe('PO-0001_Γεωργία_Ζέρβα.pdf');
  });

  it('χαρακτήρες που απαγορεύονται σε όνομα αρχείου αφαιρούνται', () => {
    expect(poPdfFilename('PO-0002', 'Α/Β: "Δοκιμή" <ΑΕ>')).toBe('PO-0002_ΑΒ_Δοκιμή_ΑΕ.pdf');
  });

  it('προμηθευτής μόνο από απαγορευμένους χαρακτήρες ⇒ σκέτος αριθμός, όχι «PO-0003_.pdf»', () => {
    expect(poPdfFilename('PO-0003', '<>?*')).toBe('PO-0003.pdf');
  });

  it('μακρύ όνομα κόβεται στους 50 χαρακτήρες', () => {
    expect(poPdfFilename('PO-0004', 'Α'.repeat(80))).toBe(`PO-0004_${'Α'.repeat(50)}.pdf`);
  });
});
