/**
 * `IBOQReadService` — η επιφάνεια **μόνο ανάγνωσης** του BOQ (ADR-734 §8.3)
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΓΙΑΤΙ ΥΠΑΡΧΕΙ ΞΕΧΩΡΙΣΤΟ ΣΥΜΒΟΛΑΙΟ ΑΝΤΙ ΓΙΑ ΣΚΕΤΟ `IBOQService`
 * ─────────────────────────────────────────────────────────────────────────────
 * Τα επτά εργαλεία του πράκτορα (ADR-734 §7) είναι **όλα** μόνο ανάγνωσης, και
 * η πολιτική τους (`BOQ_READ_POLICY`) το επιβάλλει σε χρόνο εκτέλεσης. Όσο όμως
 * τους δίνεται ολόκληρο το `IBOQService`, το `deps.boq.delete(id)` παραμένει
 * **συντακτικά διαθέσιμο** μέσα σε handler ανάγνωσης: η μόνη άμυνα είναι ότι
 * κανείς δεν το έγραψε.
 *
 * Ο διαχωρισμός το κάνει **δομικά αδύνατο**. Είναι η ίδια αρχή που εφαρμόζει το
 * ADR-734 §5.4 στα annotations: η εγγύηση δεν ανατίθεται στην καλή πρόθεση του
 * συγγραφέα αλλά σε μηχανισμό που δεν μπορεί να παρακαμφθεί κατά λάθος. Εδώ ο
 * μηχανισμός είναι ο μεταγλωττιστής, και κοστίζει μηδέν σε χρόνο εκτέλεσης.
 *
 * ⚠️ **`Pick<IBOQService, …>` σκόπιμα, ΟΧΙ ξαναγραμμένες υπογραφές.** Αν κάποια
 * υπογραφή αλλάξει στο `contracts.ts`, αλλάζει **αυτόματα** και εδώ. Χειρόγραφο
 * αντίγραφο των υπογραφών θα ήταν δεύτερη πηγή αλήθειας που θα σάπιζε σιωπηλά —
 * ακριβώς το πρόβλημα που λύνει το `boq-document-normalize.ts` για τα δεδομένα.
 * Συνέπεια: το υπάρχον `boqService` **ικανοποιεί ήδη** αυτό το interface δομικά,
 * χωρίς καμία δήλωση `implements` και χωρίς αλλαγή στον υπάρχοντα κώδικα.
 *
 * @module services/measurements/boq-read-contract
 * @see ADR-734 §7 (τα επτά εργαλεία), §8.3 (Φάση 3), §9 (τι δεν αγγίζουμε)
 */

import type { IBOQService } from './contracts';

/**
 * Οι **έξι** μέθοδοι που χρειάζονται τα εργαλεία του πράκτορα — και καμία άλλη.
 *
 * Ο κατάλογος δεν είναι αυθαίρετος: προέκυψε από τις πραγματικές κλήσεις των
 * επτά δυνατοτήτων. Νέο εργαλείο που χρειάζεται έβδομη μέθοδο πρέπει να την
 * **προσθέσει ρητά εδώ** — δηλαδή η διεύρυνση της επιφάνειας γίνεται ορατή σε
 * review αντί να συμβαίνει σιωπηλά.
 */
export type IBOQReadService = Pick<
  IBOQService,
  | 'getByBuilding'
  | 'getById'
  | 'search'
  | 'getStatistics'
  | 'getCategories'
  | 'getBuildingSummary'
>;
