import 'server-only';

import type { Firestore as AdminFirestore } from 'firebase-admin/firestore';

import { COLLECTIONS } from '@/config/firestore-collections';
import { createModuleLogger } from '@/lib/telemetry';
// 🔑 **Ο ΕΝΑΣ ΚΑΤΑΣΚΕΥΑΣΤΗΣ ΓΡΑΜΜΗΣ** (Α18.12.ζ E1) — ποτέ δεύτερη σύνθεση: η καρτέλα
//    και ο κατάλογος οφείλουν να λένε **την ίδια** κατάσταση για την ίδια εντολή.
import { toMandateCatalogRow } from '@/lib/mandate/mandate-catalog-row';
// 🔑 **Η ΘΕΜΑΤΟΦΥΛΑΚΗ ΕΧΕΙ ΕΝΑ SSoT, ΚΑΙ ΔΕΝ ΞΑΝΑΓΡΑΦΕΤΑΙ ΕΔΩ** (ADR-777 §8.39/§8.42,
//    CHECK 3.56). Μια ωμή `property.authorCompanyId !== companyId` θα ήταν **τέταρτη**
//    αυθεντία στην ίδια ερώτηση — και θα έχανε **δύο** πράγματα που το SSoT ξέρει: ότι
//    κενή εταιρεία **δεν ταιριάζει ούτε με κενή** (fail-closed) και ότι ο **ιδιωτικός
//    χώρος δεν διευρύνεται ποτέ**.
import {
  custodyOf,
  isPersonalCustody,
  mayAdminister,
  type ListingActor,
} from '@/lib/owner-property/listing-custody';
// 🔑 **ΤΟ ΛΕΞΙΛΟΓΙΟ ΖΕΙ ΣΕ LEAF, ΟΧΙ ΕΔΩ** (ADR-841 §7 Α18.12): τις τέσσερις σταθερές
//    τις διαβάζει **και ο πελάτης δικτύου** *(για να ξεχωρίσει «δεν υπάρχει» από «δεν σε
//    ακούσαμε»)*, και ένα `'server-only'` module δεν μπορεί να τους δώσει **τιμές** —
//    μόνο τύπους. Ίδιο σκεπτικό, γραμμένο, στο `mandate-client-name.ts`.
import {
  MANDATE_FOUND,
  MANDATE_MISSING,
  MANDATE_NOT_A_MANDATE,
  MANDATE_NOT_YOURS,
  type MandateDetailOutcome,
} from '@/lib/mandate/mandate-detail-outcome';
// 🔑 **Ο ΕΝΑΣ ΑΝΑΓΝΩΣΤΗΣ ΟΝΟΜΑΤΩΝ** — εξήχθη για ακριβώς αυτό. Δεύτερη υλοποίηση θα
//    ξαναγεννούσε το ελάττωμα του ADR-834 §6.5.δ (δύο άγνοιες ισοπεδωμένες σε μία).
import { readClientNames } from '@/services/mandate/mandate-catalog.service';
import { ownerPropertyFromDocument } from '@/lib/owner-property/owner-property-from-document';
import type { OwnerProperty } from '@/types/owner-property';
import { mandatesOf } from '@/types/owner-property-mandate';

const logger = createModuleLogger('mandate-detail.service');

/**
 * **Η εντολή πάνω σε αυτό το ακίνητο**, όπως τη βλέπει **αυτό** το γραφείο.
 *
 * @param actor — **από το `ctx`**, ποτέ από το σώμα ή το query του αιτήματος. Είναι ο
 *   **μόνος** λόγος που το `not-yours` δεν μπορεί να παρακαμφθεί: δεν υπάρχει πεδίο με
 *   το οποίο να ζητήσει κάποιος ξένη εμβέλεια. Είναι **ολόκληρη** η ταυτότητα και όχι
 *   σκέτο `companyId`, γιατί αυτό ζητά το SSoT της θεματοφυλακής — ο ίδιος τύπος που
 *   διαβάζουν όλες οι υπόλοιπες πόρτες.
 * @param nowISOValue — το ρολόι, **περασμένο**: η κατάσταση της εντολής είναι
 *   υπολογισμένη, και δύο αναγνώσεις του ίδιου πράγματος δεν επιτρέπεται να
 *   διαφωνήσουν επειδή πέρασε ένα δευτερόλεπτο (ίδιος κανόνας με `mandateStandingOf`).
 */
export async function readMandateDetail(
  adminDb: AdminFirestore,
  actor: ListingActor,
  ownerPropertyId: string,
  nowISOValue: string,
): Promise<MandateDetailOutcome> {
  const snapshot = await adminDb
    .collection(COLLECTIONS.OWNER_PROPERTIES)
    .doc(ownerPropertyId)
    .get();

  if (!snapshot.exists) return { kind: MANDATE_MISSING };

  // 🔴 **ΤΟ ΣΥΝΟΡΟ** (ADR-842 §7.6.12) — η ταυτότητα του εγγράφου νικά.
  const property = ownerPropertyFromDocument(snapshot.data(), snapshot.id);
  if (property === null) return { kind: MANDATE_MISSING };

  // 🔴 **Η ΕΜΒΕΛΕΙΑ, ΚΑΙ ΕΙΝΑΙ Ο ΜΟΝΟΣ ΦΡΟΥΡΟΣ ΠΟΥ ΖΕΙ ΕΔΩ.** Ο κατάλογος τον έχει
  //    ενσωματωμένο στο ερώτημά του (`where(AUTHOR_COMPANY_ID, '==', companyId)`)· μια
  //    ανάγνωση **κατά ταυτότητα** δεν έχει `where`, άρα η ίδια ερώτηση πρέπει να
  //    τεθεί **ρητά** — αλλιώς η γνώση ενός `ownp_*` θα άνοιγε εντολή ξένου γραφείου.
  //
  // ⚠️ **Το ίδιο πεδίο με τον κατάλογο** (`authorCompanyId`), και είναι δέσμευση: ο
  //    κατάλογος υπάρχει για να **επιβιώνει όταν ο υπάλληλος φύγει**, άρα η καρτέλα δεν
  //    επιτρέπεται να ρωτά `authorUserId` — θα κλείδωνε τον συνάδελφο έξω από γραμμή
  //    που βλέπει δύο κλικ πιο πίσω.
  //
  // 🔴 **ΔΥΟ ΕΡΩΤΗΣΕΙΣ, ΚΑΙ ΟΙ ΔΥΟ ΣΤΟ SSoT — και η πρώτη ΔΕΝ είναι περιττή.** Ο
  //    κατάλογος φιλτράρει `authorCompanyId == companyId`, δηλαδή **δεν δείχνει ποτέ**
  //    προσωπική αγγελία· μόνο το `mayAdminister` θα την άνοιγε εδώ στον συγγραφέα της
  //    (`personal` ⇒ κρίνεται με `uid`), και η καρτέλα θα έδειχνε γραμμή που ο κατάλογος
  //    αρνείται. Ο ιδιωτικός χώρος έχει **δική του** διαδρομή· εδώ είναι `not-yours`.
  if (isPersonalCustody(property) || !mayAdminister(custodyOf(property), actor)) {
    logger.warn('Ζητήθηκε εντολή εκτός εμβέλειας γραφείου', {
      data: { ownerPropertyId, companyId: actor.companyId },
    });
    return { kind: MANDATE_NOT_YOURS };
  }

  const clientNames = await readClientNames(
    adminDb,
    // 🔴 **`mandatesOf`, ΠΟΤΕ σκέτο `property.mandates`.** Ο αναγνώστης SSoT μεταφράζει
    //    **και το παλιό σχήμα** (`mandate` στον ενικό, πριν το ADR-832): ένα
    //    `property.mandates ?? []` θα απαντούσε **κενό** σε κάθε έγγραφο που δεν έχει
    //    ακόμη μεταναστεύσει ⇒ ο πελάτης θα εμφανιζόταν «δεν βρέθηκε» για εντολή που
    //    υπάρχει. Ίδιος κανόνας με τον κατάλογο, ίδιο ιδίωμα με το `notifyOutcomeOf`.
    //
    // ⚠️ Αν δεν υπάρχει καμία εντολή, ο πίνακας είναι κενός και η ομαδική ανάγνωση
    //    επιστρέφει **αμέσως** — καμία περιττή διαδρομή για ακίνητο που θα απαντηθεί
    //    `not-a-mandate` έτσι κι αλλιώς.
    [...new Set(mandatesOf(property).map((mandate) => mandate.clientContactId))],
  );

  const row = toMandateCatalogRow(property, clientNames, nowISOValue);
  // 🔑 **ΕΔΩ το `null` του κατασκευαστή αποκτά ΟΝΟΜΑ.** Στον κατάλογο ήταν αδύνατο
  //    (το ερώτημα φιλτράρει ήδη), και γι' αυτό η παλιά υπογραφή του έλεγε ψέματα
  //    (`: MandateCatalogRow` με `return null`, με `strict: true`). Εδώ είναι
  //    **υπαρκτή, φυσιολογική** έκβαση: το γραφείο μπορεί κάλλιστα να έχει αγγελία
  //    χωρίς εντολή.
  if (row === null) return { kind: MANDATE_NOT_A_MANDATE };

  return { kind: MANDATE_FOUND, row };
}
