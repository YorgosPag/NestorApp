import type { Firestore as AdminFirestore } from 'firebase-admin/firestore';

import { COLLECTIONS } from '@/config/firestore-collections';
import { createModuleLogger } from '@/lib/telemetry';
import { isValidGreekVat } from '@/lib/validation/vat-validation';
import type { UserProfileDocument } from '@/auth/types/auth.types';

const logger = createModuleLogger('mandate-owner-identity');

/** Ό,τι ταξιδεύει από το προφίλ του ιδιώτη στην επαφή — **και τίποτα άλλο** (§8.3). */
export interface OwnerIdentity {
  readonly givenName: string;
  readonly familyName: string;
  readonly email: string;
  readonly vatNumber: string;
}

/**
 * **Ο ΚΡΙΤΗΣ** — καθαρή συνάρτηση, κανένα I/O, κανένα ρολόι.
 *
 * 🔑 **Καθαρός επίτηδες**: τα άκρα (κενό όνομα · μόνο επώνυμο · ΑΦΜ με σπασμένο
 * ψηφίο ελέγχου · έγγραφο που δεν υπάρχει) δοκιμάζονται **χωρίς βάση**. Ο αναγνώστης
 * από κάτω δεν κρίνει τίποτα — ρωτά αυτόν.
 *
 * ⚠️ **ΚΑΙ ΤΑ ΔΥΟ ονόματα, όχι «κάποιο»** (απόφαση Giorgio 2026-08-30): η σύμβαση
 * ονομάζει **φυσικό πρόσωπο**, και «Παγώνης» χωρίς όνομα δεν ταυτοποιεί εντολέα.
 * Ίδιο δόγμα με Stripe/DocuSign, όπου τα δύο πεδία είναι **και τα δύο** υποχρεωτικά.
 *
 * ⚠️ **Το ΑΦΜ επικυρώνεται με τον ΥΠΑΡΧΟΝΤΑ ελεγκτή, και δεν είναι δυσπιστία προς τη
 * δική μας πόρτα**: το πεδίο είναι `server-owned` και γράφεται **μόνο** από το
 * `/api/account/vat-number`, αλλά αυτή η ανάγνωση συμβαίνει **μήνες αργότερα** και
 * παράγει **νομικό** κείμενο. Ο έλεγχος κοστίζει έναν βρόχο εννέα ψηφίων.
 * ⛔ **ΜΗΝ γράψεις δεύτερο mod-11 εδώ** — ο ελεγκτής είναι ένας, εισάγεται.
 *
 * @returns Η ταυτότητα, ή `null` όταν **δεν είναι πλήρης**. Ποτέ μερική: μια
 *   ταυτότητα «με ό,τι βρέθηκε» θα ταξίδευε στην επαφή και από εκεί στη σύμβαση.
 */
export function ownerIdentityOf(
  profile: UserProfileDocument | undefined,
): OwnerIdentity | null {
  if (profile === undefined) return null;

  const givenName = (profile.givenName ?? '').trim();
  const familyName = (profile.familyName ?? '').trim();
  const email = (profile.email ?? '').trim();
  const vatNumber = (profile.vatNumber ?? '').trim();

  if (givenName === '' || familyName === '') return null;
  if (email === '') return null;
  if (!isValidGreekVat(vatNumber)) return null;

  return { givenName, familyName, email, vatNumber };
}

/**
 * **Τι έμαθε ο αναγνώστης** — τρία σκέλη, ποτέ δύο (N.12: *άγνωστο ≠ κενό*).
 *
 * 🔴 Το `unavailable` **δεν** επιτρέπεται να ισοπεδωθεί με το `incomplete`: το πρώτο
 * λέει στον άνθρωπο *«ξαναδοκίμασε, μην αλλάξεις τίποτα»*, το δεύτερο *«πήγαινε
 * συμπλήρωσε το προφίλ σου»*. Μια βλάβη δικτύου διαβασμένη ως «λείπει το ΑΦΜ σου»
 * στέλνει τον άνθρωπο να διορθώσει κάτι που είναι **ήδη σωστό**.
 */
export type OwnerIdentityReading =
  | { readonly kind: 'complete'; readonly identity: OwnerIdentity }
  | { readonly kind: 'incomplete' }
  | { readonly kind: 'unavailable' };

/**
 * **Η ταυτότητα του ιδιώτη, από την ΠΗΓΗ.**
 *
 * 🔑 **Πηγή, όχι αποτύπωμα** (§9.20): διαβάζεται από το `users/{uid}` κάθε φορά. Το
 * αντίγραφο που θα γραφτεί στην επαφή **δεν** ακολουθεί τον άνθρωπο αν αργότερα
 * διορθώσει το προφίλ του — ίδιο δόγμα με τη διεύθυνση χρέωσης ενός τιμολογίου.
 *
 * ⚠️ **Δεν μεταφράζει σε άρνηση.** Οι δύο καλούντες έχουν **διαφορετικά** λεξιλόγια
 * (`MandateRequestRejection` · `MandateDecisionRefusal`) και ο καθένας κάνει τη δική
 * του μετάφραση. Μια άρνηση γεννημένη εδώ θα ανάγκαζε το ένα λεξιλόγιο να γνωρίζει
 * το άλλο.
 */
export async function readOwnerIdentity(
  adminDb: AdminFirestore,
  uid: string,
): Promise<OwnerIdentityReading> {
  try {
    const snapshot = await adminDb.collection(COLLECTIONS.USERS).doc(uid).get();
    const identity = ownerIdentityOf(snapshot.data() as UserProfileDocument | undefined);
    return identity === null ? { kind: 'incomplete' } : { kind: 'complete', identity };
  } catch (error) {
    logger.error('[MANDATE-IDENTITY] Η ανάγνωση της ταυτότητας απέτυχε — άγνωστο, όχι κενό', {
      uid,
      error: error instanceof Error ? error.message : String(error),
    });
    return { kind: 'unavailable' };
  }
}
