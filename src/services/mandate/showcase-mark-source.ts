import 'server-only';

import type { Firestore as AdminFirestore } from 'firebase-admin/firestore';

import { COLLECTIONS } from '@/config/firestore-collections';
import { createModuleLogger } from '@/lib/telemetry';
import { isShowcaseMarkKind } from '@/lib/agency/showcase-mark-kind';
import { nowISO } from '@/lib/date-local';
import type { ShowcaseMarkDeclaration } from '@/services/mandate/showcase-mark-publication';

const logger = createModuleLogger('showcase-mark-source');

/**
 * **Η σημείωση**, όπως γράφεται και όπως διαβάζεται.
 *
 * 🔑 **Το `companyId` γράφεται ΚΑΙ ΜΕΣΑ στο έγγραφο**, παρότι είναι ήδη το κλειδί του:
 * η μαζική σάρωση διαβάζει **αντικείμενα**, και ένα έγγραφο που δεν ξέρει σε ποιον
 * ανήκει υποχρεώνει τον καλούντα να το ζευγαρώσει με τη θέση του στη λίστα — ακριβώς η
 * αντιστοίχιση-με-δείκτη που το `PublicShelfImage.material` απαγόρευσε γραπτώς.
 */
export interface ShowcaseMarkSource extends ShowcaseMarkDeclaration {
  readonly companyId: string;
  /** ISO στιγμή — **πότε καταγράφηκε**, ώστε η σάρωση να μπορεί να αναφέρει ηλικία. */
  readonly recordedAt: string;
}

/**
 * **Κατέγραψε πού είναι το πρωτότυπο** — μετά από **επιτυχημένη** δημοσίευση.
 *
 * ⚠️ **ΠΟΤΕ πριν**: μια σημείωση για σήμα που τελικά δεν δημοσιεύτηκε θα έστελνε τη
 * μελλοντική σάρωση να ξαναπαράγει κάτι που **δεν υπάρχει** — και θα το έκανε σιωπηλά,
 * αφού η αποτυχία θα φαινόταν ίδια με «δεν άλλαξε τίποτα».
 *
 * ⚠️ **Δεν πετά ποτέ.** Ίδιο συμβόλαιο με τον γραφέα του ραφιού: αποτυχία **εδώ** δεν
 * επιτρέπεται να ακυρώσει σήμα που **ήδη δημοσιεύτηκε σωστά**. Το κόστος της αποτυχίας
 * είναι ότι αυτό το σήμα θα χάσει την επόμενη μαζική αναπαραγωγή — **υποβαθμισμένο,
 * όχι σπασμένο**, ακριβώς όπως πριν υπάρξει αυτό το αρχείο.
 */
export async function recordShowcaseMarkSource(
  adminDb: AdminFirestore,
  companyId: string,
  declaration: ShowcaseMarkDeclaration,
): Promise<void> {
  const record: ShowcaseMarkSource = {
    companyId,
    kind: declaration.kind,
    privateStoragePath: declaration.privateStoragePath,
    recordedAt: nowISO(),
  };

  try {
    // 🔑 `setDoc` με **ντετερμινιστικό** κλειδί (`companyId`), όπως το `agency_profiles`:
    //    η σχέση είναι **1:1** με τη βιτρίνα. Γεννήτρια αναγνωριστικού εδώ θα επέτρεπε
    //    **δύο** σημειώσεις για τον ίδιο οργανισμό, δηλαδή δύο απαντήσεις στο «πού είναι
    //    το πρωτότυπο;» — ελεύθερες να διαφωνήσουν (N.6, το πνεύμα του κανόνα).
    await adminDb.collection(COLLECTIONS.SHOWCASE_MARK_SOURCES).doc(companyId).set(record);
  } catch (error) {
    logger.warn('Η προέλευση του σήματος ΔΕΝ καταγράφηκε — το σήμα μένει δημοσιευμένο', {
      companyId,
      error: error instanceof Error ? error.message : String(error),
    });
  }
}

/**
 * **Σβήσε τη σημείωση** — όταν το σήμα αποσύρεται.
 *
 * 🔑 **Η απόσυρση παίρνει τη σημείωση μαζί της**, αλλιώς η επόμενη σάρωση θα
 * **ανέσταινε** σήμα που ο άνθρωπος αφαίρεσε. Είναι η ίδια αρχή με το ράφι: *«απόσυρση
 * = το πρόθεμα αδειάζει»*, και μια σημείωση που επιβιώνει θα ήταν **δεύτερη κατάσταση**
 * δίπλα στην ύπαρξη του εγγράφου, ελεύθερη να διαφωνήσει μαζί της.
 */
export async function forgetShowcaseMarkSource(
  adminDb: AdminFirestore,
  companyId: string,
): Promise<void> {
  try {
    await adminDb.collection(COLLECTIONS.SHOWCASE_MARK_SOURCES).doc(companyId).delete();
  } catch (error) {
    logger.warn('Η προέλευση του σήματος δεν σβήστηκε', {
      companyId,
      error: error instanceof Error ? error.message : String(error),
    });
  }
}

/**
 * **Όλες οι καταγεγραμμένες προελεύσεις** — η είσοδος της μαζικής αναπαραγωγής.
 *
 * 🔴 **ΚΑΘΕ ΕΓΓΡΑΦΗ ΞΑΝΑΚΡΙΝΕΤΑΙ, ΔΕΝ ΕΜΠΙΣΤΕΥΕΤΑΙ.** Ό,τι δεν έχει έγκυρο είδος ή
 * μονοπάτι **πετιέται εδώ**, και ο φρουρός κατοχής τρέχει **ξανά** στον καλούντα. Η
 * σημείωση είναι υπόμνηση, **ποτέ διαπιστευτήριο** — δες την κεφαλίδα του module.
 */
export async function listShowcaseMarkSources(
  adminDb: AdminFirestore,
): Promise<readonly ShowcaseMarkSource[]> {
  const snapshot = await adminDb.collection(COLLECTIONS.SHOWCASE_MARK_SOURCES).get();

  return snapshot.docs.flatMap((doc) => {
    const data = doc.data() as Partial<ShowcaseMarkSource>;

    if (!isShowcaseMarkKind(data.kind)) return [];
    if (typeof data.privateStoragePath !== 'string' || data.privateStoragePath.length === 0) {
      return [];
    }

    return [
      {
        // 🔑 Το **κλειδί** νικά το πεδίο: το `doc.id` είναι η θέση στην οποία γράψαμε,
        //    ενώ το πεδίο είναι αντίγραφο. Αν ποτέ διαφωνήσουν, η θέση είναι η αλήθεια.
        companyId: doc.id,
        kind: data.kind,
        privateStoragePath: data.privateStoragePath,
        recordedAt: typeof data.recordedAt === 'string' ? data.recordedAt : '',
      },
    ];
  });
}
