/**
 * **ΟΙ ΖΩΝΤΑΝΕΣ ΑΓΓΕΛΙΕΣ ΕΝΟΣ ΓΡΑΦΕΙΟΥ** — φραγμένο ερώτημα, ποτέ σάρωση.
 *
 * 🔴 **ΥΠΟΧΡΕΩΤΙΚΟ ΣΥΝΟΡΟ (CHECK 3.74, zero-tolerance)**: κάθε έγγραφο περνά από
 * {@link publicListingFromDocument} — τον **μοναδικό** επιτρεπόμενο ισχυρισμό
 * `PublicListing` σε όλο το repo. Ένα `as PublicListing` εδώ θα έσπαγε την πύλη.
 *
 * ⚠️ **Έγγραφο που δεν περνά τον φρουρό ΠΕΦΤΕΙ σιωπηλά**, και είναι σωστό: μια αγγελία
 * αδιάβαστη δεν αποδεικνύει τίποτα, και δεν επιτρέπεται να παγώσει την ενημέρωση των
 * υπολοίπων. Η ίδια η αδιαβασιά μετριέται **αλλού** *(ο αναγνώστης καταγράφει)*.
 */
async function liveListingsOf(
  adminDb: AdminFirestore,
  companyId: string
): Promise<readonly PublicListing[]> {
  // tenant-scope-exempt: το `public_listings` είναι δημοσιευμένη προβολή
  // (`unscopedCategory: 'published-projection'`), και το `agencyId` **δεν είναι
  // ταυτότητα πελάτη**: είναι το κλειδί εγγράφου του `agency_profiles/{companyId}`,
  // που ο κανόνας δίνει σε **ανώνυμο** (ADR-841 §7 Α1). Το φίλτρο είναι **στενότερο**
  // από το αφιλτράριστο ερώτημα που ο ίδιος κανόνας ήδη επιτρέπει.
  const snapshot = await adminDb
    .collection(COLLECTIONS.PUBLIC_LISTINGS)
    .where('agencyId', '==', companyId)
    .get();

  const listings: PublicListing[] = [];
  for (const doc of snapshot.docs) {
    const listing = publicListingFromDocument(doc.data(), doc.id);
    if (listing !== null) listings.push(listing);
  }
  return listings;
}

/**
 * **Ξαναχτίζει το `presence` ΕΝΟΣ γραφείου από τις ζωντανές αγγελίες του.**
 *
 * 🔑 **Ιδεμποτής** *(N.7.2 #3)*: ίδιες αγγελίες ⇒ ίδιο σύνολο ⇒ ίδια γραφή. Δύο κλήσεις
 * στη σειρά δεν παράγουν τίποτα διαφορετικό από μία.
 *
 * ⚠️ **`update`, ΟΧΙ `set`** — και είναι απόφαση: το έγγραφο της βιτρίνας ανήκει στον
 * **άνθρωπο** *(`publishShowcase`)*, και αυτή η πράξη αγγίζει **ένα** παράγωγο πεδίο του.
 * Ένα `set` εδώ θα διεκδικούσε ολόκληρο το έγγραφο, δηλαδή θα γινόταν **δεύτερος γραφέας
 * της βιτρίνας** — ακριβώς αυτό που η επικεφαλίδα αποκλείει.
 *
 * 🔴 **Η ΒΙΤΡΙΝΑ ΠΟΥ ΔΕΝ ΥΠΑΡΧΕΙ ΕΙΝΑΙ Η ΚΑΝΟΝΙΚΗ ΠΕΡΙΠΤΩΣΗ, ΟΧΙ Η ΕΞΑΙΡΕΣΗ — ΚΑΙ
 * ΓΙ' ΑΥΤΟ ΡΩΤΙΕΤΑΙ ΠΡΩΤΗ.**
 *
 * Η βιτρίνα είναι **opt-in** *(§4.2)*: οι περισσότεροι οργανισμοί δημοσιεύουν **αγγελίες**
 * χωρίς να δημοσιεύσουν ποτέ **βιτρίνα**. Άρα:
 *
 * · ⛔ **Ένα `warn` εκεί θα χτυπούσε στην ΠΛΕΙΟΨΗΦΙΑ των δημοσιεύσεων** — δηλαδή θα
 *   εκπαίδευε τον αναγνώστη **να μη διαβάζει** το ημερολόγιο, ακριβώς όταν κάτι πραγματικό
 *   πάει στραβά. *(Μετρήθηκε: το ίχνος βγήκε στην πρώτη εκτέλεση του `brokered-listing`.)*
 * · 🔑 **Ο έλεγχος ύπαρξης προηγείται του ερωτήματος αγγελιών**, οπότε η συνήθης διαδρομή
 *   κοστίζει **μία ανάγνωση εγγράφου κατά ταυτότητα** και **τίποτε άλλο** — ούτε σάρωση,
 *   ούτε γραφή.
 *
 * ⛔ **ΚΑΙ ΔΕΝ ΓΙΝΕΤΑΙ `set(..., {merge:true})`** για να «λυθεί» το ανύπαρκτο έγγραφο: θα
 * **γεννούσε** βιτρίνα για οργανισμό που **δεν ζήτησε ποτέ** να δημοσιευτεί. Η παρουσία
 * του εγγράφου **ΕΙΝΑΙ** η συγκατάθεση *(ADR-827)*.
 *
 * 🔴 **ΑΝΑΜΕΝΕΤΑΙ (`await`), ΚΑΙ Η ΑΠΟΜΟΝΩΣΗ ΤΟΥ ΣΦΑΛΜΑΤΟΣ ΖΕΙ ΕΔΩ ΜΕΣΑ** *(N.7.2 #6)*.
 *
 * Το `presence` είναι **μάρκετινγκ**· η αγγελία είναι **δέσμευση προς τον ιδιοκτήτη**
 * *(θεματοφυλακή, CHECK 3.56)*. Άρα μια αποτυχία εδώ **δεν** επιτρέπεται να ακυρώσει τη
 * δημοσίευση εκείνης — και γι' αυτό **δεν πετά ποτέ**.
 *
 * ⛔ **ΚΑΙ ΔΕΝ ΓΙΝΕΤΑΙ fire-and-forget στον καλούντα**, που θα ήταν ο προφανής τρόπος να
 * ειπωθεί το ίδιο: σε **serverless** διαδρομή η εκτέλεση τερματίζει με την απόκριση, και
 * ένα ξεκρέμαστο `Promise` θα **σκοτωνόταν στη μέση** — δηλαδή το πεδίο θα έμενε
 * μπαγιάτικο **τυχαία**, χωρίς κανένα ίχνος. Η σωστή διατύπωση του *«δεν μπλοκάρει»* είναι
 * **συνάρτηση που δεν αποτυγχάνει**, όχι κλήση που δεν αναμένεται.
 *
 * @param companyId Η ταυτότητα του γραφείου — **και το κλειδί του εγγράφου βιτρίνας**.
 */
export async function refreshShowcasePresence(
  adminDb: AdminFirestore,
  companyId: string
): Promise<void> {
  if (companyId.trim() === '') return;

  try {
    const ref = adminDb.collection(COLLECTIONS.AGENCY_PROFILES).doc(companyId);

    // 🔑 **ΠΡΩΤΑ Η ΒΙΤΡΙΝΑ, ΜΕΤΑ ΟΙ ΑΓΓΕΛΙΕΣ** — δες την επικεφαλίδα: η απουσία βιτρίνας
    //    είναι η **συνήθης** κατάσταση, και δεν αξίζει ούτε ερώτημα ούτε ημερολόγιο.
    const showcase = await ref.get();
    if (!showcase.exists) return;

    const listings = await liveListingsOf(adminDb, companyId);
    const presence = presenceFromListings(listings);

    // ⚠️ **Η υπέρβαση του ταβανιού λέγεται.** Η συνέπεια είναι **ψευδώς αρνητικό** — το
    //    γραφείο δεν εμφανίζεται κάπου όπου δουλεύει — και είναι το είδος της σιωπηλής
    //    απώλειας που **κανείς δεν ανακαλύπτει από την οθόνη**.
    if (presence.length >= MAX_PRESENCE_AREAS) {
      logger.warn('Η αποδεδειγμένη παρουσία άγγιξε το ταβάνι — κάποιες περιοχές δεν γράφτηκαν', {
        companyId,
        scannedListings: listings.length,
        cap: MAX_PRESENCE_AREAS,
      });
    }

    // 🔴 **ΤΟ ΠΕΔΙΟ ΠΡΟΣΤΙΘΕΤΑΙ ΕΔΩ ΜΕ ΤΟ ΧΕΡΙ, ΚΑΙ ΚΑΝΕΙΣ ΔΕΝ ΤΟ ΕΠΙΒΑΛΛΕΙ.** Το
    //    `update()` δέχεται **μερικό** αντικείμενο και **δεν** τυπίζεται έναντι του
    //    `PublicShowcase` — δηλαδή μια παράλειψη εδώ **δεν είναι σφάλμα μεταγλώττισης**,
    //    είναι πεδίο που μένει **μπαγιάτικο για πάντα**, με όλα τα σήματα πράσινα. Ίδιο
    //    ακριβώς σχήμα με τον ρητό κατασκευαστή που πέταγε το `interior` *(§8.8.17)*.
    //    Άγκυρα: `showcase-presence-admin-ids.test.ts`.
    const presenceAdminIds = await resolvedAdminIds(presence, companyId);
    await ref.update(
      presenceAdminIds === null ? { presence } : { presence, presenceAdminIds },
    );
  } catch (error) {
    logger.warn('Η αποδεδειγμένη παρουσία δεν ενημερώθηκε — η βιτρίνα μένει ΜΠΑΓΙΑΤΙΚΗ', {
      companyId,
      error: error instanceof Error ? error.message : String(error),
    });
  }
}

/**
 * **Οι κύκλοι παρουσίας σε διοικητική γλώσσα** — ή `null` όταν **δεν μπορέσαμε να
 * ρωτήσουμε** *(ADR-846 §9 #13)*.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΓΙΑΤΙ `null` ΚΑΙ ΟΧΙ `[]` — Η ΔΙΑΦΟΡΑ ΓΡΑΦΕΤΑΙ ΣΕ **ΔΗΜΟΣΙΟ** ΕΓΓΡΑΦΟ
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * Το `[]` σημαίνει **«καμία απόδειξη»** — γεγονός για τον **επαγγελματία**. Το «δεν
 * διάβασα τα αποτυπώματα» είναι βλάβη **δική μας**. Αν τα δύο συγχέονταν, μια αποτυχία
 * ανάγνωσης θα **έσβηνε** την αποδεδειγμένη παρουσία κάθε γραφείου που τυχαίνει να
 * ξαναδημοσιεύσει όσο η βλάβη διαρκεί — σιωπηλά, μόνιμα, και **με όλα τα σήματα
 * πράσινα**. Είναι **ακριβώς** το *«το `0` σημαίνει “κανείς δεν κοίταξε”»* του N.11/N.12,
 * σε δεδομένα αντί για μετρήσεις.
 *
 * ⇒ Με `null` ο καλών **παραλείπει** το πεδίο από το `update()`: η προηγούμενη τιμή
 * **επιβιώνει**. Μπαγιάτικη, αλλά **αληθινή** — και η επόμενη επιτυχημένη δημοσίευση τη
 * διορθώνει.
 *
 * ⚠️ **Και οι δύο αναγνώστες ζητούνται ΜΑΖΙ** *(`Promise.all`)*: χωρίς **και** τα
 * αποτυπώματα **και** την ιεραρχία δεν υπάρχει απάντηση — η γεωμετρία βρίσκει το
 * βαθύτερο κελί, η ιεραρχία **επαληθεύει** ότι εξηγεί τα υπόλοιπα.
 */
async function resolvedAdminIds(
  presence: readonly GeoCircle[],
  companyId: string,
): Promise<readonly string[] | null> {
  const [footprints, lineageOf] = await Promise.all([
    readAdminFootprints(),
    readAdministrativeLineage(),
  ]);

  if (footprints === null || lineageOf === null) {
    logger.error('Οι διοικητικές ταυτότητες παρουσίας ΔΕΝ υπολογίστηκαν — το πεδίο μένει ως είχε', {
      companyId,
      footprints: footprints === null ? 'άγνωστα' : 'εντάξει',
      hierarchy: lineageOf === null ? 'άγνωστη' : 'εντάξει',
    });
    return null;
  }

  return presenceAdminIdsOf(presence, footprints, lineageOf);
}
