/**
 * =============================================================================
 * ADR-841 §7 **Α18.14** — **ΦΤΑΝΕΙ ΤΟ ΚΛΕΙΔΙ ΣΤΟΝ ΑΝΑΓΝΩΣΤΗ ΤΟΥ;**
 * =============================================================================
 *
 * Το ερώτημα: *«αυτό το `titleKey` που γράφει ο παραγωγός — **μπορεί** ο
 * `NotificationDrawer` να το αποδώσει;»*
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΓΕΝΝΗΘΗΚΕ: Ο ΚΑΝΟΝΑΣ ΗΤΑΝ ΓΡΑΜΜΕΝΟΣ **ΤΡΕΙΣ ΦΟΡΕΣ ΣΕ ΣΧΟΛΙΑ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * *«Χωρίς πρόθεμα namespace: ο `NotificationDrawer` αποδίδει με `COMMON_NAMESPACES`,
 * άρα το κλειδί ζει στο `common-shared`»* — γραμμένο **και στους δύο** ειδοποιητές
 * εντολής **και** στον drawer.
 *
 * **Και τρεις παραγωγοί το έσπασαν** *(μετρημένο 2026-09-05)*: τέσσερα κλειδιά
 * `quotes:quotes.notifications.*` έδειχναν σε namespace που ο drawer **δεν φορτώνει
 * ποτέ**. Μετά την **Α18.10** δεν έβγαζαν πια ωμό κλειδί — έβγαζαν το **αποθηκευμένο**
 * κείμενο: *«παγωμένο και μονόγλωσσο»*, από τη **σωστή πλέον αιτία**.
 *
 * > **Σχόλιο που το σπάνε τρεις από τους καταναλωτές του δεν είναι κανόνας· είναι ευχή.**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΕΔΩ ΞΕΠΕΡΝΑΜΕ ΤΗΝ ΠΡΑΚΤΙΚΗ, ΚΑΙ Η ΔΙΑΦΟΡΑ ΕΙΝΑΙ ΜΕΤΡΗΣΙΜΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η **CHECK 3.8** ρωτά *«υπάρχει αυτό το κλειδί;»* — και θα έλεγε **ναι** για κάθε ένα
 * από τα τέσσερα: υπήρχαν, στο `quotes.json`. Το ερώτημα που **κανείς** δεν έκανε είναι
 * *«υπάρχει **εκεί όπου θα το ζητήσει ο αναγνώστης**;»*. Είναι η ίδια κλάση με το
 * **CHECK 3.36** *(reachability namespace)*, σε άλλη επιφάνεια.
 *
 * ⚠️ **ΚΑΘΕ ΚΡΙΤΗΡΙΟ ΠΟΥ ΑΝΑΚΑΛΥΠΤΕΙ, ΜΕΤΡΑΕΙ ΚΑΙ ΠΟΣΑ ΑΝΑΚΑΛΥΨΕ** — το μάθημα (δ) της
 * 05/09: ένα κριτήριο γεννήθηκε **κενό** και ήταν πράσινο επειδή **δεν κοίταξε**.
 */

import fs from 'node:fs';
import path from 'node:path';

import { COMMON_NAMESPACES } from '@/i18n/namespace-bundles';

const ROOT = process.cwd();
const SRC = path.join(ROOT, 'src');

/** Ο **ένας** αναγνώστης — και ό,τι φορτώνει, το φορτώνει από εδώ. */
const READER_NAMESPACES: readonly string[] = COMMON_NAMESPACES;

// =============================================================================
// Η ΑΝΑΚΑΛΥΨΗ — ΑΠΟ ΤΟΝ ΔΙΣΚΟ, ΠΟΤΕ ΧΕΙΡΟΓΡΑΦΗ ΛΙΣΤΑ
// =============================================================================

function walk(dir: string, out: string[] = []): string[] {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== '__tests__' && entry.name !== 'node_modules') walk(full, out);
    } else if (entry.name.endsWith('.ts') || entry.name.endsWith('.tsx')) {
      out.push(full);
    }
  }
  return out;
}

/**
 * **Ποια αρχεία γράφουν `titleKey`** — και η ανακάλυψη είναι **η ίδια η λέξη**, όχι το
 * όνομα του αποστολέα.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Η ΠΡΩΤΗ ΓΡΑΦΗ ΗΤΑΝ ΤΥΦΛΗ ΣΤΟΥΣ ΠΑΡΑΓΩΓΟΥΣ ΠΟΥ ΤΗ ΓΕΝΝΗΣΑΝ — ΚΑΙ ΤΟ ΕΔΕΙΞΕ ΜΕΤΑΛΛΑΞΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ρωτούσε `source.includes('dispatchNotification(')`. Υπάρχει όμως **δεύτερος**
 * αποστολέας — `dispatchProcurementNotification` — και **ακριβώς** οι τρεις παραγωγοί
 * του `quotes:` που γέννησαν αυτή την πύλη τον χρησιμοποιούν. ⇒ Οι μεταλλάξεις πάνω
 * τους **επέζησαν**: η πύλη ήταν πράσινη **επειδή δεν τους κοίταξε**.
 *
 * 🔑 **Η θεραπεία δεν είναι «πρόσθεσε και το δεύτερο όνομα»** — θα ήταν χειρόγραφη
 * λίστα που παλιώνει στον **τρίτο** αποστολέα. Το κριτήριο είναι πλέον **η ίδια η λέξη
 * `titleKey`**: αν ένα αρχείο τη γράφει, το κλειδί του **κρίνεται**, όποιος κι αν το
 * στέλνει. Ίδιο ιδίωμα με το Κ0 της `notification-destination-custody`.
 */
function isProducer(source: string): boolean {
  // ⚠️ **ΓΕΝΙΚΟ ΩΣ ΠΡΟΣ ΤΟΝ ΑΠΟΣΤΟΛΕΑ, ΟΧΙ ΛΙΣΤΑ ΟΝΟΜΑΤΩΝ**: `dispatch…Notification(`
  //    πιάνει **και** τον `dispatchProcurementNotification` **και** τον επόμενο που θα
  //    γραφτεί. Μια λίστα δύο ονομάτων θα ξαναπάλιωνε στον τρίτο.
  //
  // ⛔ **ΚΑΙ ΟΧΙ σκέτο «αναφέρει `titleKey`»**: μετρήθηκε ότι δίνει **103** αρχεία —
  //    props και τύποι που **δεν** στέλνουν ειδοποίηση. Πύλη με 103 ευρήματα και 13
  //    πραγματικά είναι θόρυβος, και αστοχεί στον πήχη false-positive της Google.
  return /dispatch\w*Notification\s*\(/.test(source) && /titleKey/.test(source);
}

/**
 * ⛔ **Ο ΙΔΙΟΣ Ο ΜΗΧΑΝΙΣΜΟΣ ΔΕΝ ΕΙΝΑΙ ΠΑΡΑΓΩΓΟΣ** — και το βρήκε το **Κ0β**.
 *
 * Το `server/notifications/**` **ορίζει** τους αποστολείς και **δηλώνει** το πεδίο
 * `titleKey` στον τύπο του· δεν γράφει **κανένα** κλειδί. Χωρίς αυτή τη γραμμή, η πύλη
 * θα κατήγγελλε το ίδιο το σύνορο ως «παραγωγό που δεν έδωσε κλειδί».
 *
 * ⚠️ **Εξαίρεση κατά ΕΥΘΥΝΗ, όχι κατά όνομα αρχείου**: ο κανόνας είναι *«εδώ ζει ο
 * μηχανισμός»*, άρα καλύπτει και το επόμενο αρχείο που θα προστεθεί δίπλα του.
 */
function isDispatcherItself(file: string): boolean {
  // ⚠️ **`split(path.sep)`, ΟΧΙ regex με ανάστροφη κάθετο**: σε Windows ο διαχωριστής
  //    είναι `\` και κάθε γραφή του μέσα σε regex είναι μια ευκαιρία για διαφυγή που
  //    σπάει σιωπηλά. Ο διαχωριστής **λέγεται**, δεν γράφεται.
  const relative = path.relative(ROOT, file).split(path.sep).join('/');
  return relative.startsWith('src/server/notifications/');
}

/**
 * **Τα κλειδιά που γράφει αυτό το αρχείο** — και οι **δύο** μορφές, επίτηδες.
 *
 * 🔑 Ένα σκέτο `titleKey: '…'` θα έχανε **τους δύο ειδοποιητές εντολής**, που διαλέγουν
 * κλειδί από `Record` *(`TITLE_KEYS`, `DECISION_TITLE_KEYS`)* — ακριβώς το ιδίωμα που
 * το ίδιο το repo **επιβάλλει** για να μη γεννιούνται δυναμικά κλειδιά. Μια πύλη που
 * τιμωρεί το σωστό ιδίωμα θα ήταν χειρότερη από καμία πύλη.
 */
function titleKeysOf(source: string): readonly string[] {
  const keys = new Set<string>();

  for (const m of source.matchAll(/titleKey\s*[:=]\s*'([^']+)'/g)) keys.add(m[1]);

  // 🔴 **ΚΑΙ Η ΤΡΙΤΗ ΜΟΡΦΗ — ΤΗΝ ΒΡΗΚΕ ΤΟ Κ0β, ΟΧΙ Η ΣΚΕΨΗ.** Το
  //    `api/vendor/quote/[token]/route.ts` γράφει `const titleKey = συνθήκη ? 'α' : 'β';`
  //    και μετά σκέτο `titleKey,`. Ο εξαγωγέας έβρισκε **μηδέν** κλειδιά εκεί, δηλαδή
  //    **δύο πραγματικά κλειδιά δεν κρίνονταν από κανέναν** — και η πύλη ήταν πράσινη.
  for (const block of source.matchAll(/const\s+titleKey\s*=[\s\S]*?;/g)) {
    for (const m of block[0].matchAll(/'([^']+)'/g)) keys.add(m[1]);
  }

  for (const block of source.matchAll(/const\s+\w*TITLE_KEYS\b[\s\S]*?\n\};/g)) {
    for (const m of block[0].matchAll(/'([A-Za-z][\w.:-]*\.[\w.:-]+)'/g)) keys.add(m[1]);
  }

  return [...keys];
}

function localeKeyExists(language: string, namespace: string, dotted: string): boolean {
  const file = path.join(SRC, 'i18n', 'locales', language, `${namespace}.json`);
  if (!fs.existsSync(file)) return false;

  let node: unknown = JSON.parse(fs.readFileSync(file, 'utf8'));
  for (const segment of dotted.split('.')) {
    if (typeof node !== 'object' || node === null) return false;
    node = (node as Record<string, unknown>)[segment];
    if (node === undefined) return false;
  }
  return typeof node === 'string';
}

const PRODUCERS = walk(SRC)
  .filter((file) => !isDispatcherItself(file))
  .filter((file) => isProducer(fs.readFileSync(file, 'utf8')))
  .sort();

const ENTRIES = PRODUCERS.flatMap((file) =>
  titleKeysOf(fs.readFileSync(file, 'utf8')).map(
    (key) => [path.relative(ROOT, file), key] as const,
  ),
);

// =============================================================================

describe('ADR-841 §7 Α18.14 — κάθε `titleKey` φτάνει στον αναγνώστη του', () => {
  it('Κ0 — η ανακάλυψη βρίσκει παραγωγούς ΚΑΙ κλειδιά (αλλιώς η πύλη δεν κοίταξε)', () => {
    // 🔴 **ΤΟ `0` ΣΗΜΑΙΝΕΙ «ΚΑΝΕΙΣ ΔΕΝ ΚΟΙΤΑΞΕ», ΟΧΙ «ΚΑΘΑΡΟ».** Χωρίς αυτές τις δύο
    //    γραμμές, μια μετονομασία ή αλλαγή ιδιώματος θα έκανε ολόκληρη τη σουίτα
    //    **μονίμως πράσινη** — το σχήμα που το `CLAUDE.md` καταγγέλλει στα 3.18/3.28.
    expect(PRODUCERS.length).toBeGreaterThanOrEqual(8);
    // ⚠️ Κατώφλι **με περιθώριο**: ο παρονομαστής ρωτά *«κοίταξε καθόλου;»*, όχι
    //    *«είναι ακριβώς τόσα;»*. Ένα καρφωμένο πλήθος θα κοκκίνιζε σε κάθε νόμιμη
    //    αφαίρεση ειδοποίησης — θόρυβος, όχι σήμα. Μετρημένο σήμερα: **17**.
    expect(ENTRIES.length).toBeGreaterThanOrEqual(12);
  });

  /**
   * 🔴 **Ο ΠΑΡΟΝΟΜΑΣΤΗΣ ΤΟΥ ΠΑΡΟΝΟΜΑΣΤΗ — ΚΛΕΙΣΤΟΤΗΤΑ, ΟΧΙ ΠΛΗΘΟΣ.**
   *
   * Το Κ0 μετρά *«βρήκα αρκετά;»*. Αυτό μετρά *«βρήκα **ΟΛΑ**;»* — και είναι το
   * κριτήριο που **έλειπε** όταν η πρώτη γραφή ρωτούσε για έναν μόνο αποστολέα και
   * **έχασε τρεις παραγωγούς**: το Κ0 περνούσε *(υπήρχαν άλλοι έξι)* ενώ η πύλη ήταν
   * τυφλή ακριβώς εκεί που έπρεπε να βλέπει.
   *
   * ⚠️ **Ένα αρχείο που γράφει `titleKey` και ΔΕΝ έδωσε κανένα κλειδί** σημαίνει ότι το
   * γράφει με μορφή που ο εξαγωγέας **δεν διαβάζει** *(π.χ. νέο ιδίωμα Record)*. Αυτό
   * είναι **εύρημα**, όχι θόρυβος: το κλειδί του δεν κρίνεται από κανέναν.
   */
  it('Κ0β 🔴 — ΚΑΘΕ αρχείο που γράφει `titleKey` έδωσε τουλάχιστον ένα κλειδί', () => {
    const withKeys = new Set(ENTRIES.map(([file]) => file));
    const silent = PRODUCERS.map((f) => path.relative(ROOT, f)).filter(
      (f) => !withKeys.has(f),
    );

    expect(PRODUCERS.length).toBeGreaterThan(0); // ΠΑΡΟΝΟΜΑΣΤΗΣ
    expect(silent).toEqual([]);
  });

  /**
   * 🔴 **ΤΟ ΚΡΙΤΗΡΙΟ ΠΟΥ ΘΑ ΕΙΧΕ ΠΙΑΣΕΙ ΤΟ `quotes:`.**
   *
   * Ένα πρόθεμα είναι **υπόσχεση** ότι ο αναγνώστης φορτώνει εκείνο το namespace. Ο
   * δικός μας αναγνώστης φορτώνει **ακριβώς** το {@link COMMON_NAMESPACES} — τίποτα
   * άλλο, ποτέ κατ' απαίτηση.
   */
  it.each(ENTRIES)('Κ1 🔴 — %s: το πρόθεμα του «%s» ζει στον αναγνώστη', (_file, key) => {
    const [maybeNamespace] = key.split(':');
    if (!key.includes(':')) return; // χωρίς πρόθεμα ⇒ το κρίνει το Κ2

    expect(READER_NAMESPACES).toContain(maybeNamespace);
  });

  /**
   * 🔴 **ΚΑΙ ΤΟ ΑΛΛΟ ΜΙΣΟ — ΧΩΡΙΣ ΑΥΤΟ Η ΠΥΛΗ ΘΑ ΗΤΑΝ ΜΙΣΗ.**
   *
   * Ένα κλειδί **χωρίς** πρόθεμα λύνεται με τη **σειρά** των namespaces του αναγνώστη.
   * Αν δεν υπάρχει σε **κανένα** από αυτά, η κάρτα πέφτει στο αποθηκευμένο κείμενο —
   * η **ίδια** βλάβη με το `quotes:`, από την πίσω πόρτα.
   *
   * ⚠️ **`el` ΚΑΙ `en`**: ένα κλειδί που υπάρχει μόνο στο ένα είναι *«δουλεύει στη
   * γλώσσα που δοκίμασα»* — και το ADR-841 έχει ήδη πληρώσει μία φορά το ότι ο
   * διακόπτης γλώσσας δεν περπατήθηκε.
   */
  it.each(ENTRIES)('Κ2 🔴 — %s: το «%s» υπάρχει σε el ΚΑΙ en του αναγνώστη', (_file, key) => {
    if (key.includes(':')) {
      const [namespace, dotted] = key.split(':');
      for (const language of ['el', 'en']) {
        expect(localeKeyExists(language, namespace, dotted)).toBe(true);
      }
      return;
    }

    for (const language of ['el', 'en']) {
      const found = READER_NAMESPACES.some((ns) => localeKeyExists(language, ns, key));
      expect(found).toBe(true);
    }
  });
});
