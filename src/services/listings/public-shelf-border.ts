/** Ένα εικονοστοιχείο, όπως το δίνει ο αποκωδικοποιητής: `[R, G, B, A]`, 0-255. */
export type BorderPixel = readonly [number, number, number, number];

/**
 * **Τι είναι το περίγραμμα αυτής της εικόνας.**
 *
 * 🔑 **Τέσσερις τιμές και όχι boolean**, επίτηδες: το `'body'` και το `'disagree'`
 * οδηγούν στην **ίδια** πράξη *(μην αγγίξεις)* αλλά για **αντίθετους** λόγους — το ένα
 * λέει *«βρήκα πλαίσιο και είναι περιεχόμενο»*, το άλλο *«δεν υπάρχει πλαίσιο»*. Ένα
 * `boolean` θα τα ισοπέδωνε, και το ημερολόγιο δεν θα μπορούσε ποτέ να πει **ποιο** από
 * τα δύο συνέβη σε ένα σήμα που ο άνθρωπος αναρωτιέται γιατί δεν κανονικοποιήθηκε.
 */
export type BorderVerdict =
  /** Πλήρως διάφανες γωνίες — το κλασικό λογότυπο σε PNG με alpha. */
  | 'empty'
  /** Λευκές γωνίες — λογότυπο σε «χαρτί», συνήθως JPEG ή ισοπεδωμένο PNG. */
  | 'paper'
  /** Χρωματιστό, συμφωνημένο πλαίσιο — **είναι το σήμα**. Δες το περιστατικό του app-icon. */
  | 'body'
  /** Οι γωνίες δεν συμφωνούν — **δεν υπάρχει** πλαίσιο για να αφαιρεθεί. */
  | 'disagree';

/**
 * **Κάτω από αυτό το alpha το εικονοστοιχείο είναι κενό.**
 *
 * 🔑 **8 και όχι 0**: τα εργαλεία εξαγωγής αφήνουν υπόλειμμα 1-3 σε πλήρως διάφανες
 * περιοχές *(dithering του καναλιού alpha)*. Το απόλυτο `0` θα έκανε τον κανόνα να
 * αποτυγχάνει σε λογότυπα που είναι **ολοφάνερα** διάφανα.
 */
export const BORDER_ALPHA_EMPTY = 8;

/**
 * **Πάνω από αυτή την τιμή, σε ΚΑΘΕ κανάλι, το χρώμα είναι «χαρτί».**
 *
 * ⚠️ **244 και όχι 255, και ο λόγος μετρήθηκε**: το ίδιο λογότυπο σε λευκό JPEG δίνει
 * γωνίες που η συμπίεση έχει μετακινήσει. Ένα κατώφλι στο 255 θα έλεγε *«δεν είναι
 * λευκό»* για εικόνα που κάθε άνθρωπος βλέπει λευκή.
 *
 * ⛔ **ΜΗΝ το κατεβάσεις άλλο** για να «πιάνει και τα ανοιχτόγκριζα φόντα»: το ανοιχτό
 * γκρι *είναι* σχεδιαστική απόφαση, και ένα χαμηλότερο κατώφλι θα άρχιζε να τρώει
 * σκόπιμα παστέλ πλαίσια. Το όριο είναι εκεί που σταματά η **συμπίεση** και αρχίζει η
 * **πρόθεση**.
 */
export const BORDER_PAPER_FLOOR = 244;

/**
 * **Πόσο επιτρέπεται να διαφέρουν οι γωνίες μεταξύ τους** ώστε να λέγονται «πλαίσιο».
 *
 * ⚠️ Καλύπτει τον θόρυβο της lossy συμπίεσης, **όχι** βαθμώσεις: ένα φόντο με ντεγκραντέ
 * έχει γωνίες που διαφέρουν κατά δεκάδες μονάδες ⇒ `'disagree'` ⇒ **δεν αγγίζεται**.
 * Σωστό: σε ντεγκραντέ δεν υπάρχει «περιθώριο» να αφαιρεθεί — υπάρχει **σχέδιο**.
 */
export const BORDER_CORNER_AGREEMENT = 12;

/**
 * 🏆 **Ο ΚΡΙΤΗΣ** — τι είναι το περίγραμμα, από τις τέσσερις γωνίες του.
 *
 * ⚠️ **Η διαφάνεια κρίνεται ΠΡΩΤΗ και ΜΟΝΗ ΤΗΣ**, πριν συγκριθεί οποιοδήποτε χρώμα, και
 * είναι διόρθωση πραγματικού σφάλματος του πρωτοτύπου: κάτω από `alpha = 0` τα RGB είναι
 * **αδιάφορα** και τα αρχεία τα γεμίζουν με ό,τι να 'ναι *(ο ίδιος ο καθαριστής βασίζεται
 * σε αυτό — το `exact: false` του WebP τα πετά ως όφελος ασφαλείας)*. Σύγκριση RGB σε
 * διάφανες γωνίες θα απαντούσε `'disagree'` σε **ολοφάνερα διάφανο** λογότυπο.
 */
export function classifyBorder(corners: readonly BorderPixel[]): BorderVerdict {
  if (corners.length === 0) return 'disagree';

  const empty = corners.filter((pixel) => pixel[3] <= BORDER_ALPHA_EMPTY).length;
  if (empty === corners.length) return 'empty';
  // Μερικώς διάφανο περίγραμμα: άλλες γωνίες κενές, άλλες όχι ⇒ δεν είναι πλαίσιο.
  if (empty > 0) return 'disagree';

  const [reference] = corners;
  const agree = corners.every((pixel) =>
    pixel.every((channel, index) => Math.abs(channel - reference[index]) <= BORDER_CORNER_AGREEMENT),
  );
  if (!agree) return 'disagree';

  const paper = reference.slice(0, 3).every((channel) => channel >= BORDER_PAPER_FLOOR);
  return paper ? 'paper' : 'body';
}

/**
 * **Επιτρέπεται να αφαιρεθεί αυτό το περίγραμμα;** — η **μία** διατύπωση της άδειας.
 *
 * 🔑 **Υπάρχει ως ονομασμένο κατηγόρημα και όχι ως `verdict === 'empty' || …` στον
 * καλούντα**: η άδεια είναι **μία** απόφαση, και ένας δεύτερος καλών κάποτε θα την
 * έγραφε ελαφρώς αλλιώς. Ίδιο σκεπτικό με το `marksBand()` του `showcase-mark-box`.
 */
export function borderIsPackaging(verdict: BorderVerdict): boolean {
  return verdict === 'empty' || verdict === 'paper';
}
