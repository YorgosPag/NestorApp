/**
 * **Τα αρχεία που το γραφείο σήμανε δημόσια, σε σταθερή σειρά, κομμένα στο όριο.**
 *
 * 🔑 **Το όριο είναι ΤΟ ΙΔΙΟ με του ιδιώτη** (Α14.4): ο λόγος του είναι η **προσοχή του
 * επισκέπτη** *(Zillow 22–27)* — ιδιότητα εκείνου που **κοιτάζει**, όχι εκείνου που
 * ανέβασε. Δύο αριθμοί θα σήμαιναν ότι η ίδια βιτρίνα κουράζει διαφορετικά ανάλογα με
 * το ποιος δημοσίευσε.
 *
 * ⚠️ Ποτέ bytes και ποτέ URL — **μονοπάτι στον ιδιωτικό κάδο**, ίδιο συμβόλαιο με τον
 * ιδιώτη: ο γραφέας κατεβάζει το πρωτότυπο **ο ίδιος**, ώστε ο καθαρισμός EXIF/GPS να
 * μην μπορεί να παρακαμφθεί από τον καλούντα *(Α12.7)*.
 *
 * 🔑 **`PHOTO_MATERIAL` ΣΤΑΘΕΡΑ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΔΕΙΞΗ — ΟΧΙ ΠΑΡΑΔΟΧΗ** (ADR-841 §7 Α17.4).
 * Ο φρουρός #2 έχει **ήδη** εγγυηθεί, δέκα γραμμές πιο πάνω, ότι μόνο
 * `category === 'photos'` φτάνει ως εδώ — δηλαδή το «είναι φωτογραφία;» **απαντήθηκε από
 * ανθρώπινη πράξη** (το σημείο εισόδου του ανεβάσματος), δεν υποτίθεται. ⚠️ Γι' αυτό μια
 * μελλοντική χαλάρωση της λευκής λίστας κατηγορίας **οφείλει** να αλλάξει και αυτή τη
 * γραμμή: είναι οι δύο άκρες του **ίδιου** ισχυρισμού, και η άγκυρα του Ο-20 τις ρωτά μαζί.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Η ΣΕΙΡΑ ΕΧΕΙ **ΔΥΟ ΣΚΕΛΗ**, ΚΑΙ ΤΟ ΟΡΙΟ ΚΟΒΕΙ **ΜΕΤΑ** ΑΠΟ ΑΥΤΑ (Α14.7.3)
 * ────────────────────────────────────────────────────────────────────────────
 *
 *   1. ό,τι **δήλωσε** ο άνθρωπος του γραφείου, στη σειρά που το δήλωσε
 *   2. ό,τι **δεν** δήλωσε, στη ρητά ουδέτερη σειρά του
 *      {@link compareAgencyMediaForPublication}
 *
 * ⚠️ **Η σειρά του `slice` ΕΙΝΑΙ ΟΥΣΙΩΔΗΣ, όχι ύφος**: αν το `PUBLISHED_MEDIA_LIMIT`
 * έκοβε **πριν** την τακτοποίηση, μια φωτογραφία που ο άνθρωπος έβαλε **πρώτη** θα
 * μπορούσε να έχει ήδη πεταχτεί έξω — δηλαδή η πράξη του θα ήταν **αόρατη ακριβώς όταν
 * μετράει**. ⛔ Και το όριο μένει **ΕΝΑ** *(Α14.4)*: κανένα δεύτερο για τη δήλωση.
 *
 * ⚠️ **Η κενή δήλωση ΔΕΝ είναι ειδική περίπτωση** — η μηχανή επιστρέφει τότε ακριβώς τη
 * σειρά που έδινε αυτό το αρχείο πριν την Α14.7. Καμία υπάρχουσα αγγελία δεν αλλάζει
 * μέχρι να μιλήσει άνθρωπος.
 */
export function publishedAgencyMediaSources(
  files: readonly AgencyMediaCandidate[],
  declaration: AgencyMediaDeclaration = NO_AGENCY_DECLARATION,
): readonly PublicShelfSource[] {
  const declaredFloorplans = new Set(declaration.floorplans);

  return orderedPublishableAgencyMedia(files, declaration).flatMap((file) => {
    const material = agencyMediaMaterial(file, declaredFloorplans);
    // ⚠️ Το `null` είναι **αδύνατο** εδώ — το ίδιο ερώτημα έκανε το φιλτράρισμα μια
    //    γραμμή πιο πάνω. Ο κλάδος υπάρχει για να **μη χρειαστεί `!`**: ένας ισχυρισμός
    //    εδώ θα ήταν ακριβώς ο τρόπος με τον οποίο οι δύο άκρες αρχίζουν να αποκλίνουν.
    return material === null ? [] : [{ privateStoragePath: file.storagePath, material }];
  });
}

/**
 * **ΤΙ ΦΕΥΓΕΙ, ΜΕ ΠΟΙΑ ΣΕΙΡΑ — ΤΑ ΙΔΙΑ ΤΑ ΑΡΧΕΙΑ** (ADR-841 §7 Α14.7 · Α17.7).
 *
 * 🔴 **ΕΞΗΧΘΗ ΓΙΑ ΝΑ ΜΗΝ ΥΠΑΡΞΕΙ ΔΕΥΤΕΡΗ ΑΠΑΝΤΗΣΗ, ΚΑΙ ΤΟ ΣΧΗΜΑ ΕΙΝΑΙ ΓΡΑΜΜΕΝΟ ΑΠΟ
 * ΤΗΝ ΑΛΛΗ ΠΛΕΥΡΑ**: το `owner-media-publication` βάζει *«τι φεύγει;»* και *«τι βλέπει ο
 * κάτοχος;»* στο **ίδιο** module ακριβώς επειδή δύο `filter` σε δύο αρχεία θα ήταν *«δύο
 * απαντήσεις ελεύθερες να αποκλίνουν — και η απόκλιση θα ήταν **αόρατη**: η οθόνη θα
 * έλεγε “δημοσιεύονται 30” ενώ ο κόσμος θα έβλεπε 24»*. Το γραφείο απέκτησε οθόνη με την
 * Α14.7 ⇒ **ίδιος κίνδυνος, ίδια θεραπεία**.
 *
 * 🔑 **Γενικό στο `T`, ώστε η οθόνη να κρατά τα ΔΙΚΑ ΤΗΣ πεδία** *(μικρογραφία, όνομα)*
 * χωρίς δεύτερο πέρασμα αντιστοίχισης: ο κανόνας χρειάζεται μόνο το
 * {@link AgencyMediaCandidate}, ο καλών παίρνει πίσω **ό,τι έδωσε**.
 *
 * 🔴 **ΦΩΤΟΓΡΑΦΙΕΣ ΚΑΙ ΚΑΤΟΨΕΙΣ ΣΕ ΕΝΑ ΡΕΥΜΑ, ΜΕ ΕΝΑ ΟΡΙΟ — ΚΑΙ Ο ΙΔΙΩΤΗΣ ΤΟ ΕΙΧΕ
 * ΗΔΗ ΑΠΑΝΤΗΣΕΙ** (Α17.7.5). Το `publishedOwnerMedia` κόβει στο `PUBLISHED_MEDIA_LIMIT`
 * **πριν** χωρίσει φωτογραφίες από κατόψεις: ένα, **συνολικό** όριο. ⛔ Δεύτερο όριο για
 * κατόψεις θα ήταν ακριβώς ο δεύτερος αριθμός που απαγορεύει η **Α14.4**.
 *
 * ⚠️ **Και γι\' αυτό η πράξη σειράς οφείλει να ΠΡΟΗΓΕΙΤΑΙ**: με ένα συνολικό όριο, μια
 * κάτοψη μπορεί να **κοπεί** από φωτογραφίες που προηγούνται χρονικά. Η **Α14.7** έδωσε
 * τη λαβή — το `publishedMediaOrder` δέχεται **οποιαδήποτε** ταυτότητα, άρα και κάτοψης.
 *
 * ⚠️ **Το `PUBLISHED_MEDIA_LIMIT` κόβει ΕΔΩ, ΜΕΤΑ τη σειρά** — άρα η οθόνη δείχνει και
 * το κόψιμο: ένα αρχείο εκτός ορίου **δεν εμφανίζεται**, γιατί δεν φεύγει.
 */
export function orderedPublishableAgencyMedia<T extends AgencyMediaCandidate>(
  files: readonly T[],
  declaration: AgencyMediaDeclaration = NO_AGENCY_DECLARATION,
): readonly T[] {
  const declaredFloorplans = new Set(declaration.floorplans);
  const publishable = files.filter(
    (file) => agencyMediaMaterial(file, declaredFloorplans) !== null,
  );

  return orderByDeclaration(
    // 🔴 **Η ΕΠΙΜΕΛΕΙΑ ΤΡΕΧΕΙ ΕΔΩ — ΜΕΤΑ τη συμμετοχή, ΠΡΙΝ τη σειρά και ΠΡΙΝ το όριο.**
    //    Και οι τρεις θέσεις είναι απόφαση, όχι στιλ — δες {@link currentPerIdentity}.
    currentPerIdentity(publishable),
    (file) => file.id,
    declaration.order,
    compareAgencyMediaForPublication,
  ).slice(0, PUBLISHED_MEDIA_LIMIT);
}

/**
 * 🏆 **ΙΔΙΑ ΤΑΥΤΟΤΗΤΑ ⇒ ΕΚΔΟΧΕΣ ⇒ ΕΠΙΒΙΩΝΕΙ ΤΟ ΝΕΟΤΕΡΟ** (ADR-845 Ο-27, άγκυρα **Α-15**).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΓΕΓΟΝΟΣ — ΜΕΤΡΗΜΕΝΟ ΣΤΗΝ ΠΑΡΑΓΩΓΗ, 2026-09-09
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Δεύτερη δημοσίευση του **ίδιου** ορόφου έδωσε **δύο** κάρτες δίπλα-δίπλα με **ταυτόσημη**
 * λεζάντα *(«Μετρημένο — παράχθηκε από το σχέδιο»)*. Το ζωντανό `public_listings` το
 * επιβεβαίωσε: κάθε πεδίο ίδιο πλην `url` και `at` — και το `at` **δεν αποδίδεται πουθενά**.
 * Ο επισκέπτης **δομικά** δεν είχε από πού να μάθει ποιο ισχύει.
 *
 * 🔑 **Ο πληθυντικός ΜΕΝΕΙ, και είναι ολόκληρο το νόημα**: *«σήμερα vs μετά την ανακαίνιση»*
 * *(`as-built` + `proposal`)* και **δύο ανεξάρτητοι παραγωγοί** *(εργολάβος `measured` ·
 * αρχιτέκτονας ιδιώτη `declared`)* συνεχίζουν να συνυπάρχουν — **διαφορετική ταυτότητα,
 * διαφορετικό πράγμα**. Αυτό που φεύγει είναι μόνο το **διπλότυπο**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΤΟΝ ΑΝΑΓΝΩΣΤΗ, ΣΤΟΝ ΨΗΣΤΗ Η ΣΤΗΝ ΟΘΟΝΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * | υποψήφια θέση | γιατί **όχι** |
 * |---|---|
 * | `agency-media.reader` *(το ερώτημα Firestore)* | Η κεφαλίδα του το **απαγορεύει ρητά**: *«αυτή η λίστα είναι **στένωση κόστους**, όχι δεύτερο κριτήριο»*. Και δομικά αδύνατο: η ομαδοποίηση θέλει **όλα** τα αδέλφια στη μνήμη |
 * | ο **ψήστης** | Θα έψηνε **και τα δύο** και θα πετούσε το ένα ⇒ πλήρης λήψη + WASM για bytes που δεν φεύγουν |
 * | η **οθόνη** | Το ρητό «ΜΗΝ διορθώσεις το σύμπτωμα»: το `models[]` θα εξακολουθούσε να γράφεται με δύο, και ένα screenshot / syndication feed θα τα έδειχνε **και τα δύο** |
 *
 * 🏆 **ΕΔΩ, ΕΠΕΙΔΗ ΑΥΤΗ Η ΣΥΝΑΡΤΗΣΗ ΕΧΕΙ ΔΥΟ ΚΑΤΑΝΑΛΩΤΕΣ**: τον **γραφέα** *(μέσω του
 * {@link publishedAgencyMediaSources})* **και την οθόνη του γραφείου**. Το γραμμένο σκεπτικό
 * της, αυτούσιο: *«δύο `filter` σε δύο αρχεία θα ήταν δύο απαντήσεις ελεύθερες να αποκλίνουν —
 * και η απόκλιση θα ήταν **αόρατη**»*. ⇒ Ο άνθρωπος βλέπει **ακριβώς** ό,τι ο κόσμος.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΟΙ ΤΡΕΙΣ ΘΕΣΕΙΣ ΤΗΣ ΚΛΗΣΗΣ, ΚΑΙ ΓΙΑΤΙ ΚΑΜΙΑ ΔΕΝ ΕΙΝΑΙ ΑΥΘΑΙΡΕΤΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * - **ΜΕΤΑ τη συμμετοχή**: ένα αρχείο που δεν φεύγει *(ιδιωτικό, `trashed`, μη έτοιμο)* δεν
 *   επιτρέπεται να **διαδεχθεί** τίποτα. Αλλιώς ένα ημιτελές ανέβασμα θα έσβηνε το ζωντανό
 *   μοντέλο από την αγγελία — ακριβώς το `PENDING` που ο κύκλος ζωής κρατά **αόρατο**.
 * - **ΠΡΙΝ τη σειρά**: η δήλωση σειράς *«δεν μπορεί να δημοσιεύσει τίποτα — μόνο να
 *   τακτοποιήσει ό,τι ήδη φεύγει»* (Α14.7.2). Ένα μπαγιάτικο ταυτοποιητικό στο
 *   `publishedMediaOrder` **δεν** το ανασταίνει.
 * - **ΠΡΙΝ το όριο**: ίδιο ακριβώς επιχείρημα με το γραμμένο *«το `slice` κόβει ΜΕΤΑ την
 *   τακτοποίηση»*. Αν έκοβε πρώτο, ένα **αποσυρμένο** μοντέλο θα κρατούσε θέση στο
 *   `PUBLISHED_MEDIA_LIMIT` και θα έσπρωχνε έξω **πραγματική** φωτογραφία.
 *
 * ⚠️ **Το «νεότερο» το ορίζει ο {@link compareAgencyMediaForPublication}, ανάποδα** — ποτέ
 * δεύτερη σύγκριση χρόνου. Έχει **ήδη** ισοπαλία στο `id` για αρχεία του ίδιου χιλιοστού, και
 * ο λόγος της είναι ο ίδιος εδώ: **ασταθής νικητής ⇒ άλλο μοντέλο σε κάθε πέρασμα ⇒ δημόσια
 * bytes που αναβοσβήνουν** χωρίς να έχει αλλάξει τίποτα.
 *
 * 🔴 **ΧΩΡΙΣ ΤΑΥΤΟΤΗΤΑ ⇒ ΠΟΤΕ ΣΥΓΧΩΝΕΥΣΗ** *(fail-closed, με φορά προς την **προβολή**)*.
 * Κάθε αρχείο που δημοσιεύτηκε **πριν** από αυτή τη φάση — και υπάρχουν δύο, ζωντανά — δεν
 * έχει πεδίο. *«Δεν ξέρω τι είναι»* δεν σημαίνει **ποτέ** *«είναι το ίδιο με εκείνο»*: μια
 * σιωπηλή συγχώνευση θα **έκρυβε** υλικό που κάποιος δημοσίευσε ρητά. Ίδια κατεύθυνση με το
 * `fingerprint: null` του `compareModelLedger` — *«δεν ξέρω» δεν σημαίνει «ίδιο»*.
 *
 * ⚠️ **Καμία ταξινόμηση της εξόδου**: επιστρέφεται με τη σειρά **εισόδου** των επιζώντων. Η
 * σειρά είναι δουλειά του `orderByDeclaration` μία γραμμή πιο κάτω, και δύο ταξινομήσεις θα
 * ήταν δύο απαντήσεις στο *«ποια πρώτη;»*.
 */
function currentPerIdentity<T extends AgencyMediaCandidate>(files: readonly T[]): readonly T[] {
  const winners = new Map<string, T>();

  for (const file of files) {
    const identity = publicationIdentityOf(file);
    if (identity === null) continue;

    const held = winners.get(identity);
    if (held === undefined || compareAgencyMediaForPublication(held, file) < 0) {
      winners.set(identity, file);
    }
  }

  // ⚠️ Δεύτερο πέρασμα **πάνω στην είσοδο**, όχι έξοδος του `Map`: κρατά τη σειρά εισόδου
  //    ακέραιη *(η σειρά εισαγωγής ενός `Map` είναι σειρά **πρώτης** εμφάνισης, όχι σειρά του
  //    νικητή)* και αφήνει τα ανώνυμα στη θέση τους, χωρίς δεύτερη λίστα να συγχωνευτεί.
  return files.filter((file) => {
    const identity = publicationIdentityOf(file);
    if (identity === null) return true;
    return winners.get(identity) === file;
  });
}

/**
 * **Έχει αυτό το αρχείο ταυτότητα δημοσίευσης;** — `null` για κάθε άλλη απάντηση.
 *
 * 🔑 **ΜΙΑ διατύπωση του «δεν ξέρω», δύο αναγνώστες** *(ο νικητής και ο διάδοχος)*. Ως
 * ξεχωριστοί έλεγχοι, ο ένας θα μπορούσε να δεχτεί κενή συμβολοσειρά και ο άλλος όχι — και
 * τότε ένα αρχείο θα **διαδεχόταν** χωρίς να **επιβιώνει**, ή αντίστροφα.
 *
 * ⚠️ **Το κενό είναι «δεν ξέρω», ποτέ ταυτότητα**: το Firestore δεν γράφει `undefined`, αλλά
 * γράφει `''` — και μια κενή συμβολοσειρά ως κλειδί θα συγχώνευε **κάθε** αρχείο που την έχει
 * με **κάθε άλλο**, ανεξαρτήτως είδους.
 */
function publicationIdentityOf(file: AgencyMediaCandidate): string | null {
  const identity = file.publicationIdentity;
  return typeof identity === 'string' && identity !== '' ? identity : null;
}

/**
 * 🏆 **ΠΟΙΟΥΣ ΔΙΑΔΕΧΕΤΑΙ ΑΥΤΗ Η ΔΗΜΟΣΙΕΥΣΗ;** — η **ίδια** κρίση, από την ανάποδη (Ο-27).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ ΥΠΑΡΧΕΙ **ΚΑΙ ΑΥΤΗ**, ΕΝΩ Η ΕΠΙΜΕΛΕΙΑ ΑΡΚΕΙ ΓΙΑ ΤΟΝ ΚΟΣΜΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η {@link currentPerIdentity} κάνει το **κοινό** σωστό — **παράγωγα**, σε κάθε πέρασμα, ό,τι
 * κι αν έπεσε στη μέση. Αυτό είναι η **ορθότητα**, και δεν χρειάζεται τίποτα άλλο.
 *
 * ⚠️ **Αλλά ο άνθρωπος δεν είναι το κοινό.** Χωρίς αυτό, το παλιό μοντέλο μένει `active` στον
 * διαχειριστή αρχείων: ο κάτοχος βλέπει **δύο** και ο κόσμος **ένα**, χωρίς να λέει κανείς
 * γιατί. Το **ISO 19650 §10.2** το ονομάζει: ένα superseded έγγραφο είναι **μη χρησιμοποιήσιμο,
 * ΟΧΙ ανύπαρκτο** — και ο διάδοχός του πρέπει να είναι **ευρέσιμος**. Το `supersedeFileRecord`
 * γράφει ακριβώς αυτό *(`cdeState: 'SUPERSEDED'` + `supersededByFileId`)*, και **υπάρχει ήδη**
 * από το Ο-16.
 *
 * ⇒ **Δύο ρόλοι, ρητά άνισοι**: η επιμέλεια κρατά την **αλήθεια**, αυτή γράφει την **ιστορία**.
 * Αν η δεύτερη αποτύχει, **τίποτα δεν σπάει** — γι' αυτό επιτρέπεται να ζει στον πελάτη, όπου
 * ζει και η **μία** πόρτα της απόσυρσης.
 *
 * 🌐 Ο συνδυασμός δεν υπάρχει σε κανέναν από τους τρεις κόσμους που ρωτήθηκαν: το **RESO**
 * *(Zillow · Idealista)* δεν έχει καθόλου διαδοχή· το **ISO 19650** *(Revit · ACC)* ζητά από
 * τον **άνθρωπο** να δηλώσει το revision· το **OCI/Git** μετακινεί το tag αλλά **χάνει** την
 * ιστορία του. Εδώ και τα τρία απαντιούνται, γιατί η ταυτότητα είναι **παράγωγη**.
 *
 * ⚠️ **Καθαρή συνάρτηση, καμία εγγραφή**: αποφασίζει *ποιοι*, ποτέ *πράττει*. Ο διακομιστής
 * τη ρωτά και **επιστρέφει** την απάντηση· την πράξη την κάνει ο πελάτης — η **μία** πόρτα
 * (`supersedeFileRecord`) είναι client SDK, και ένα admin δίδυμό της θα ήταν δεύτερη μηχανή
 * για την ίδια ερώτηση *(N.18 · ADR-749)*.
 *
 * ⛔ **ΔΕΝ φιλτράρει κύκλο ζωής, και είναι σκόπιμο**: ο καλών δίνει ό,τι του επιστρέφει το
 * ερώτημά του, και το `supersedeFileRecord` είναι **ιδεμποτητικό** — ένα ήδη αποσυρμένο
 * αρχείο απλώς ξαναγράφει την ίδια κατάσταση. Ένας δεύτερος φρουρός κύκλου ζωής εδώ θα ήταν
 * τρίτη διατύπωση του `isDeliverableAgencyFile`.
 */
export function supersededByPublication(
  files: readonly AgencyMediaCandidate[],
  newcomer: AgencyMediaCandidate,
): readonly string[] {
  const identity = publicationIdentityOf(newcomer);
  if (identity === null) return [];

  return files
    .filter((file) => file.id !== newcomer.id && publicationIdentityOf(file) === identity)
    .map((file) => file.id);
}
