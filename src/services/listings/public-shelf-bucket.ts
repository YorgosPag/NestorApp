/**
 * @fileoverview 🏆 **Ο ΚΑΔΟΣ ΤΟΥ ΔΗΜΟΣΙΟΥ ΡΑΦΙΟΥ** — οι τρεις πράξεις, **χωρίς καμία γνώση υλικού**.
 * @related ADR-845 Φ4.2β · ADR-841 §7 Α12 (.4 · .6 · .11) · ADR-749 (μία μηχανή)
 * @module services/listings/public-shelf-bucket
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΧΩΡΙΣΕ ΑΠΟ ΤΟΝ ΓΡΑΦΕΑ — **ΔΥΟ ΚΕΦΑΛΙΑ, ΕΝΑΣ ΣΒΗΣΤΗΣ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Από τη **Φ4.2** το `listings/<id>/` δέχεται **δύο** είδη bytes: εικόνες *(`.webp`)* και
 * μοντέλα *(`.glb`)*. Τα δύο ψήνονται **εντελώς ανόμοια** — το ένα με `sharp` σε **οικογένεια**
 * παραγώγων ανά πλάτος, το άλλο με `gltf-transform` σε **ένα** αρχείο — αλλά τα **βήματα του
 * κάδου** είναι **ταυτόσημα**: πρόθεμα, σάρωση, ανέβασμα ό,τι λείπει, σβήσιμο ό,τι περισσεύει.
 *
 * ⛔ **ΔΥΟ ΑΝΤΙΓΡΑΦΑ ΤΟΥΣ ΘΑ ΗΤΑΝ ΤΟ ADR-749 ΣΤΗΝ ΠΙΟ ΑΚΡΙΒΗ ΤΟΥ ΜΟΡΦΗ**: δύο μηχανές που
 * **σβήνουν στο ίδιο πρόθεμα**. Η στιγμή που θα απέκλιναν δεν θα ήταν σφάλμα μεταγλώττισης —
 * θα ήταν **δημοσιευμένα bytes που δεν σβήνονται ποτέ**.
 *
 * ⇒ **ΕΝΑΣ** {@link deleteExtra}, **ΕΝΑΣ** {@link scanShelfPrefix}, **ΕΝΑΣ** {@link uploadMissing}.
 *   Τα δύο κεφάλια *(`public-shelf.service` · `public-shelf-model.service`)* διαφέρουν **μόνο**
 *   στο πώς παράγουν το επιθυμητό σύνολο.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΚΑΙ Ο ΚΑΔΟΣ ΕΠΑΨΕ ΝΑ ΞΕΡΕΙ ΤΙ ΕΙΝΑΙ «ΠΛΑΤΟΣ» — ΔΙΟΡΘΩΣΗ, ΟΧΙ ΜΕΤΑΚΙΝΗΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ως τη Φ4.2α το `uploadMissing` έγραφε **καρφωτά** πέντε raster μεταδεδομένα *(`shelfPixelWidth`,
 * `shelfRequestedWidths`, …)*. Ήταν η **βαθύτερη** εναπομείνασα δήλωση ότι κάθε πράγμα στο ράφι
 * είναι εικόνα — ίδια κλάση με το `webp:` που έλυσε η **Φ4.0** στη `shelfRecipe`.
 *
 * ⇒ Ο κάδος δέχεται πλέον {@link ShelfWrite}: *«κλειδί, bytes, τύπος, και ό,τι μεταδεδομένα
 * **λέει** ο καλών»*. Η **μετάφραση** των δομημένων πεδίων σε συμβολοσειρές ζει σε **ΕΝΑ**
 * σημείο ανά είδος *(`toShelfWrite` για το raster)*, δίπλα στον **μοναδικό αναγνώστη** τους.
 *
 * ⚠️ **ΚΑΙ ΓΙ' ΑΥΤΟ ΔΕΝ ΓΕΝΙΚΕΥΤΗΚΕ ΤΟ `PendingUpload`**: ένα `metadata` **δίπλα** στα
 * `width`/`height` θα ήταν **δύο αλήθειες για τον ίδιο αριθμό**, ελεύθερες να αποκλίνουν — και
 * το `toObject` διαβάζει τα δομημένα. Ο μικρότερος τύπος στο **σύνορο** λύνει και τα δύο.
 *
 * ⛔ **ΤΑ ΟΝΟΜΑΤΑ ΚΑΙ ΟΙ ΤΙΜΕΣ ΤΩΝ RASTER ΜΕΤΑΔΕΔΟΜΕΝΩΝ ΕΜΕΙΝΑΝ ΤΑΥΤΟΣΗΜΑ**, και δεν είναι
 * λεπτομέρεια: το `cachedVariants` τα διαβάζει για τη **γρήγορη διαδρομή**. Παραμικρή απόκλιση
 * ⇒ κάθε δημοσιευμένη φωτογραφία γίνεται **αόρατη** στη μνήμη του ραφιού ⇒ **ολική
 * επανακωδικοποίηση σε κάθε αποθήκευση τίτλου**. Άλλαξε **μόνο η θέση παραγωγής**.
 *
 * ⚠️ **ΔΕΝ ΔΗΜΙΟΥΡΓΕΙ ΤΟΝ ΚΑΔΟ** — η δημιουργία δημόσιου κάδου είναι **πράξη**, και ζει στο
 * `public-shelf-provision`. Δες το σκεπτικό στο `public-shelf.service`.
 */

import type { Bucket, File } from '@google-cloud/storage';

import { GCS_PUBLIC_MEDIA_BUCKET } from '@/config/gcs-buckets';
import { getAdminStorage } from '@/lib/firebaseAdmin';
import {
  PUBLIC_SHELF_CACHE_CONTROL,
  parsePublicShelfKey,
  publicShelfPrefix,
} from '@/services/upload/utils/storage-path-public-shelf';
import type { AnyPublicShelfKind } from '@/services/upload/utils/public-shelf-kinds';

// ---------------------------------------------------------------------------
// Τύποι — ό,τι χρειάζεται ο κάδος, και τίποτε άλλο
// ---------------------------------------------------------------------------

/**
 * **Μία εγγραφή στο ράφι**, στη γλώσσα του κάδου.
 *
 * 🔑 **Το `metadata` είναι ΑΔΙΑΦΑΝΕΣ εδώ**, με τον ίδιο ακριβώς κανόνα που το
 * `PublicShelfSource.material` είναι αδιαφανές στον γραφέα: *ο κάδος το **κουβαλά**, δεν το
 * **ερμηνεύει** ποτέ*. Καμία διακλάδωση αυτού του αρχείου δεν το κοιτά.
 */
export interface ShelfWrite {
  readonly key: string;
  readonly bytes: Buffer;
  readonly contentType: string;
  readonly metadata: Readonly<Record<string, string>>;
}

/**
 * **Τι κάθεται ήδη στο πρόθεμα αυτού του υποκειμένου** — μία σάρωση, τρεις απαντήσεις.
 *
 * ⚠️ Το {@link files} περιέχει **ΟΛΑ** τα αντικείμενα του προθέματος, **και των δύο ειδών**:
 * η διαμέριση γίνεται από το `parsePublicShelfKey` μέσα στον {@link deleteExtra}, ποτέ εδώ.
 * Ένα φιλτράρισμα σε αυτό το σημείο θα ήταν **δεύτερος** κριτής ταυτότητας κλειδιού.
 */
export interface ShelfScan {
  readonly bucket: Bucket;
  readonly prefix: string;
  readonly files: readonly File[];
  /** Τα ονόματα του {@link files}, ως σύνολο — η ερώτηση *«υπάρχει ήδη;»* σε O(1). */
  readonly keys: ReadonlySet<string>;
}

// ---------------------------------------------------------------------------
// Πρόσβαση στον κάδο
// ---------------------------------------------------------------------------

/** Ο **ΜΟΝΟΣ** δείκτης προς τον δημόσιο κάδο σε όλο το δέντρο. */
export function shelfBucket(): Bucket {
  return getAdminStorage().bucket(GCS_PUBLIC_MEDIA_BUCKET);
}

/**
 * **Άνοιξε το πρόθεμα αυτού του υποκειμένου και πες τι βρήκες.**
 *
 * 🔴 **Ο ΦΡΟΥΡΟΣ ΤΡΕΧΕΙ ΕΔΩ, ΠΡΩΤΟΣ**: το {@link publicShelfPrefix} **πετά** αν η ταυτότητα
 * δεν περνά τον φρουρό **αυτού** του είδους, και οι φρουροί των ριζών είναι **αντίθετοι**.
 * Ένα λάθος είδος δεν μπορεί να σαρώσει ξένη ρίζα — δεν είναι σύμβαση, είναι **αδύνατο**.
 */
export async function scanShelfPrefix(
  kind: AnyPublicShelfKind,
  subjectId: string,
): Promise<ShelfScan> {
  const prefix = publicShelfPrefix(kind, subjectId);
  const bucket = shelfBucket();
  const [files] = await bucket.getFiles({ prefix });

  return { bucket, prefix, files, keys: new Set(files.map((file) => file.name)) };
}

// ---------------------------------------------------------------------------
// Οι δύο πλευρές της συμφιλίωσης
// ---------------------------------------------------------------------------

/**
 * Ανεβάζει ό,τι **λείπει**. Ό,τι υπάρχει ήδη **δεν ξαναγράφεται**.
 *
 * 🔑 Το «υπάρχει ήδη» είναι απάντηση **ανά byte**, όχι ανά χρόνο: ίδια bytes ⇒ ίδιο κλειδί ⇒
 * **μηδέν** εγγραφή, μηδέν κόστος, μηδέν ακύρωση cache *(N.7.2 #3)*.
 *
 * ⚠️ Τα μεταδεδομένα **γράφονται μαζί με τα bytes**, ποτέ σε δεύτερη κλήση: ένα αντικείμενο
 * χωρίς `sourceRef` είναι **αόρατο** στη γρήγορη διαδρομή, και μια αποτυχία ανάμεσα στις δύο
 * κλήσεις θα άφηνε **μόνιμη** αποτυχία επαναχρησιμοποίησης.
 *
 * 🔴 **ΔΕΝ ΞΕΡΕΙ ΤΟ ΕΙΔΟΣ, ΚΑΙ ΔΕΝ ΞΕΡΕΙ ΤΙ ΕΙΝΑΙ ΤΑ ΜΕΤΑΔΕΔΟΜΕΝΑ ΤΟΥ** *(Α21.10, επεκταμένο
 * στη Φ4.2β)*. Ο πίνακας είναι **ισοπεδωμένος από ΠΟΛΛΕΣ πηγές**, και από την Α21.10 δύο πηγές
 * της **ίδιας** ρίζας μπορούν να έχουν **διαφορετική** συνταγή *(λογότυπο τριμμένο, πορτρέτο
 * άτριφτο)* — από τη Φ4.2 μπορούν να έχουν και **διαφορετικό σχήμα μεταδεδομένων** *(εικόνα
 * με πλάτη, μοντέλο χωρίς)*. Ένας υπολογισμός εδώ θα έγραφε τη **μία** απάντηση πάνω σε bytes
 * της **άλλης**, και επειδή η γρήγορη διαδρομή δεν αποκωδικοποιεί τίποτα, το ψέμα θα ήταν
 * **μόνιμο**.
 */
export async function uploadMissing(
  bucket: Bucket,
  writes: readonly ShelfWrite[],
  existing: ReadonlySet<string>,
): Promise<void> {
  const missing = writes.filter((write) => !existing.has(write.key));

  await Promise.all(
    missing.map((write) =>
      bucket.file(write.key).save(write.bytes, {
        contentType: write.contentType,
        metadata: {
          cacheControl: PUBLIC_SHELF_CACHE_CONTROL,
          metadata: { ...write.metadata },
        },
      }),
    ),
  );
}

/**
 * Σβήνει ό,τι **περισσεύει** μέσα στο πρόθεμα **αυτής** της αγγελίας.
 *
 * ⚠️ **Αγγίζει ΜΟΝΟ κλειδιά που αναγνωρίζει** ({@link parsePublicShelfKey}): ό,τι βρεθεί εκεί
 * και δεν είναι δικής μας μορφής **μένει**. Ο αυστηρός γραφέας απέναντι στον ανεκτικό
 * αναγνώστη — ένας σαρωτής που σβήνει ό,τι δεν καταλαβαίνει είναι ο σαρωτής της 27/08
 * *(«θα έσβηνε την αγορά»)*.
 *
 * 🔴 **ΚΑΙ ΑΥΤΗ Η ΓΡΑΜΜΗ ΕΙΝΑΙ ΠΟΥ ΚΡΑΤΑ ΤΑ ΔΥΟ ΕΙΔΗ ΖΩΝΤΑΝΑ ΣΤΟ ΙΔΙΟ ΠΡΟΘΕΜΑ** *(άγκυρα
 * **Α-1ε**)*: το `parsePublicShelfKey` απαντά `null` όταν η **κατάληξη** δεν είναι εκείνη
 * **αυτού** του είδους ⇒ η συμφιλίωση των εικόνων **δεν βλέπει** τα `.glb`, και το αντίστροφο.
 * Ο *«ανεκτικός αναγνώστης»* — γραμμένος για άλλο λόγο — απαντά **και** αυτή την ερώτηση.
 *
 * ⚠️ **ΔΕΝ ΔΕΧΕΤΑΙ ΚΑΔΟ, ΚΑΙ ΕΙΝΑΙ ΔΙΟΡΘΩΣΗ** *(N.0.2, Φ4.2β)*: η παράμετρος υπήρχε και ήταν
 * **νεκρή** — το `File` ξέρει τον κάδο του, οπότε το σβήσιμο γίνεται με `file.delete()`. Σε
 * ιδιωτική συνάρτηση περνούσε απαρατήρητη· σε **δημόσια επιφάνεια** που θα καλέσουν δύο
 * κεφάλια, θα ήταν όρισμα που ο επόμενος θα προσπαθούσε να **δικαιολογήσει**.
 */
export async function deleteExtra(
  kind: AnyPublicShelfKind,
  existingFiles: readonly File[],
  desired: ReadonlySet<string>,
): Promise<number> {
  const doomed = existingFiles.filter(
    (file) => parsePublicShelfKey(kind, file.name) !== null && !desired.has(file.name),
  );

  await Promise.all(doomed.map((file) => file.delete({ ignoreNotFound: true })));
  return doomed.length;
}
