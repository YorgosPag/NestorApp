/**
 * @fileoverview **«ΠΟΙΑ ΑΡΧΕΙΑ ΤΟΥ ΓΡΑΦΕΙΟΥ ΔΗΜΟΣΙΕΥΟΝΤΑΙ;»** — η μία απάντηση (ADR-841 §7 Α14).
 * @related ADR-841 §7 (Α14.2 · Α14.3 · Α14.4) · lib/owner-property/owner-media-publication
 * @module services/listings/agency-media-publication
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΔΥΟ ΕΡΩΤΗΣΕΙΣ, ΔΥΟ ΦΡΟΥΡΟΙ — και η **ανεξαρτησία** τους ΕΙΝΑΙ η ασφάλεια
 * ────────────────────────────────────────────────────────────────────────────
 *
 *   1. **ΕΞΟΥΣΙΟΔΟΤΗΣΗ** — *«επιτρέπεται να φύγει από την εταιρεία;»*
 *      ⇒ `classification === 'public'`, **ανθρώπινη** πράξη σε υπάρχουσα οθόνη.
 *   2. **ΚΑΤΑΛΛΗΛΟΤΗΤΑ** — *«είναι φωτογραφία του ακινήτου;»*
 *      ⇒ κατηγορία `photos` + αποκωδικοποιήσιμη εικόνα + έτοιμο + όχι στα σκουπίδια.
 *
 * 🔴 **Γιατί ο δεύτερος φρουρός δεν είναι περιττός, ΜΕΤΡΗΜΕΝΑ (Α14.1)**: η ζωντανή
 * `files` έχει **3 κατόψεις DXF**. Είναι **νόμιμα** δημόσια πληροφορία *(δημοσιευμένη
 * οικοδομική άδεια)* — μια μέρα κάποιος **θα** τις σημάνει `public` με απόλυτο δίκιο.
 * Με **έναν** φρουρό, εκείνη η **σωστή** πράξη διακυβέρνησης θα δημοσίευε **κατόψεις
 * στη βιτρίνα**. Ο δρόμος «αυτόματα» απορρίφθηκε ακριβώς γι' αυτό· ένας μόνο φρουρός
 * θα τον ξανάνοιγε από την πίσω πόρτα.
 *
 * 🏆 Είναι ο διαχωρισμός της **RESO** *(το πρότυπο των MLS)*: το `Media` resource κρατά
 * **χωριστά** τα δικαιώματα από την κατηγορία. Δεν τον μιμηθήκαμε — τον βρήκαμε **ήδη
 * μοντελοποιημένο** εδώ, σε δύο πεδία γραμμένα από δύο διαφορετικά ADR *(031 · 191)*.
 *
 * ⛔ **ΚΑΝΕΝΑ νέο πεδίο.** Η σημαία `publicVisibility` που πρότεινε το handoff θα ήταν
 * **δεύτερη απάντηση στο «είναι δημόσιο;»** δίπλα σε πεδίο που ορίζεται αυτολεξεί ως
 * *«can be shared externally (e.g. marketing photos)»*.
 */

import { compareInstantsAsc } from '@/lib/date-local';
import {
  FILE_CATEGORIES,
  FILE_CLASSIFICATIONS,
  FILE_LIFECYCLE_STATES,
  FILE_STATUS,
} from '@/config/domain-constants';
import { FILE_TYPE_CONFIG } from '@/config/file-upload-config';
import { PUBLISHED_MEDIA_LIMIT } from '@/services/upload/utils/storage-path-public-shelf';
import { PHOTO_MATERIAL } from '@/lib/listings/listing-material';
import { orderByDeclaration } from '@/lib/ordering/declared-order';
import type { FileRecord } from '@/types/file-record';
import type { PublicShelfSource } from '@/services/upload/utils/storage-path-public-shelf';

/**
 * **Το `FileRecord` όσο το χρειάζεται η απόφαση** — και ούτε πεδίο παραπάνω.
 *
 * 🔑 Γράφεται ως `Pick` του **αληθινού** συμβολαίου και όχι ως ελεύθερο σχήμα: αν κάποια
 * μέρα το `classification` μετονομαστεί ή αλλάξει τύπο, αυτό εδώ **σπάει** αντί να
 * συνεχίσει να διαβάζει πεδίο που δεν υπάρχει πια — που είναι ακριβώς ο τρόπος με τον
 * οποίο ένα προαιρετικό πεδίο γίνεται σιωπηλά μόνιμο `undefined`.
 */
export type AgencyMediaCandidate = Pick<
  FileRecord,
  | 'id'
  | 'entityType'
  | 'storagePath'
  | 'category'
  | 'classification'
  | 'contentType'
  | 'status'
  | 'createdAt'
  | 'lifecycleState'
  | 'isDeleted'
>;

/**
 * Οι μορφές που ο καθαριστής του ραφιού μπορεί να **αποκωδικοποιήσει**.
 *
 * 🔑 **Δανεικές από το SSoT των ανεβασμάτων** (`FILE_TYPE_CONFIG.image`) και όχι
 * γραμμένες ξανά εδώ: μια δεύτερη λίστα θα σήμαινε ότι κάτι που **επιτρέπεται** να
 * ανέβει μπορεί να **μη** δημοσιεύεται ποτέ, χωρίς να το λέει κανείς.
 */
const DECODABLE_IMAGE_TYPES: readonly string[] = FILE_TYPE_CONFIG.image.mimeTypes;

/**
 * **Επιτρέπεται αυτό το αρχείο να φύγει από την εταιρεία;** — ο φρουρός #1.
 *
 * ⚠️ **`=== 'public'`, ποτέ «όχι εμπιστευτικό»**: το πεδίο είναι **προαιρετικό** και η
 * προεπιλογή του είναι `internal`. Ό,τι δεν είναι **ρητά** `public` *(απόν, `undefined`,
 * `internal`, `confidential`)* σημαίνει **ιδιωτικό**. Ένας έλεγχος «δεν είναι
 * `confidential`» θα δημοσίευε **κάθε αρχείο που κανείς δεν ταξινόμησε ποτέ** — δηλαδή,
 * σήμερα, **όλα τους**.
 */
export function isPubliclyClassified(file: AgencyMediaCandidate): boolean {
  return file.classification === FILE_CLASSIFICATIONS.PUBLIC;
}

/**
 * **Είναι αυτό φωτογραφία του ακινήτου, έτοιμη και ζωντανή;** — ο φρουρός #2.
 *
 * ⚠️ Το `lifecycleState` και το `isDeleted` είναι **δύο** πεδία για μία κατάσταση *(η
 * ζωντανή βάση έχει και τα δύο σε κάθε έγγραφο)*. Ελέγχονται **αμφότερα**: το ένα να
 * λείπει σε παλιό έγγραφο δεν επιτρέπεται να σημαίνει «δημοσίευσέ το».
 */
export function isPublishableShape(file: AgencyMediaCandidate): boolean {
  if (file.entityType !== 'property') return false;
  if (file.category !== FILE_CATEGORIES.PHOTOS) return false;
  if (file.status !== FILE_STATUS.READY) return false;
  if (file.isDeleted === true) return false;
  if (
    file.lifecycleState !== undefined &&
    file.lifecycleState !== FILE_LIFECYCLE_STATES.ACTIVE
  ) {
    return false;
  }
  if (!DECODABLE_IMAGE_TYPES.includes(file.contentType)) return false;
  return typeof file.storagePath === 'string' && file.storagePath.trim() !== '';
}

/**
 * **Και οι δύο φρουροί.** Η σύζευξη γράφεται **μία** φορά, εδώ.
 */
export function isPublishableAgencyPhoto(file: AgencyMediaCandidate): boolean {
  return isPubliclyClassified(file) && isPublishableShape(file);
}

/**
 * **Η σειρά ΟΣΩΝ ΚΑΝΕΙΣ ΔΕΝ ΔΗΛΩΣΕ** — ντετερμινιστική, και ρητά **όχι** επιλογή ανθρώπου.
 *
 * 🔴 **ΑΥΤΟΣ Ο ΣΥΓΚΡΙΤΗΣ ΑΛΛΑΞΕ ΡΟΛΟ ΣΤΗΝ Α14.7 — ΔΕΝ ΕΙΝΑΙ ΠΙΑ «Η ΣΕΙΡΑ».** Μέχρι τις
 * 2026-09-06 ήταν η **μόνη** απάντηση στο *«ποια φωτογραφία είναι πρώτη;»*, και η Α14.3
 * το ονόμασε ανοιχτό πρόβλημα αντί να το κρύψει: ο ιδιώτης απαντούσε με **ανθρώπινη
 * πράξη** *(Α2.1)* και το γραφείο με **χρόνο** — τον χρόνο που η **Α6.2** είχε
 * απορρίψει **ρητά** ως κριτήριο σειράς. Τώρα το γραφείο **έχει** πράξη
 * *(`publishedMediaOrder`)*, και εδώ έμεινε η ουρά της: *«με ποια σειρά μπαίνουν όσα ο
 * άνθρωπος **δεν** τακτοποίησε»*.
 *
 * 🔑 **Η ένσταση της Α6.2 ΕΞΕΠΝΕΥΣΕ, ΔΕΝ ΠΑΡΑΚΑΜΦΘΗΚΕ**: *«χρόνος που δεν επέλεξε ο
 * άνθρωπος διαβάζεται ως επιλογή του»* ισχύει όσο ο άνθρωπος **δεν έχει φωνή**. Από τη
 * στιγμή που έχει, ο χρόνος παύει να μιλά στη θέση του — γίνεται η **ρητά ουδέτερη**
 * σειρά για ό,τι δεν σχολίασε.
 *
 * ⛔ **ΜΗΝ τον διαγράψεις «τώρα που υπάρχει η δήλωση».** Η δήλωση είναι **αραιή**: στη
 * συνήθη περίπτωση είναι **κενή**, και τότε αυτός ο συγκριτής είναι **ολόκληρη** η σειρά.
 *
 * ⛔ Και **δεν** διαλέχτηκε το `purpose` *(`'exterior'`/`'interior'`)*, παρότι η RESO
 * προτιμά εξωτερική όψη ως πρωτεύουσα: οι τιμές του ζουν στο μητρώο **σημείων εισόδου**
 * και **όχι** στο `PHOTO_PURPOSES` ⇒ κατάταξη με βάση τους θα **εφεύρισκε λεξιλόγιο
 * τομέα** (CHECK 3.73).
 *
 * 🔑 **Ο ντετερμινισμός ΔΕΝ είναι καλλωπισμός**: το ράφι συμφιλιώνεται σε **κάθε**
 * επανασύνθεση. Ασταθής σειρά ⇒ άλλο `gallery` κάθε πέρασμα ⇒ **δημόσια bytes που
 * αναβοσβήνουν** χωρίς να έχει αλλάξει τίποτα. Γι' αυτό υπάρχει και η **ισοπαλία στο
 * `id`**: δύο αρχεία ανεβασμένα στο ίδιο χιλιοστό του δευτερολέπτου δεν επιτρέπεται να
 * αφήνουν τη σειρά τους στην υλοποίηση του `sort`.
 */
export function compareAgencyMediaForPublication(
  a: AgencyMediaCandidate,
  b: AgencyMediaCandidate,
): number {
  const byInstant = compareInstantsAsc(a.createdAt, b.createdAt);
  if (byInstant !== 0) return byInstant;
  return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
}

/**
 * **Η ΠΡΑΞΗ ΣΕΙΡΑΣ ΤΟΥ ΓΡΑΦΕΙΟΥ, ΟΠΩΣ ΤΗ ΔΙΑΒΑΖΕΙ Ο ΓΡΑΦΕΑΣ** (ADR-841 §7 Α14.7).
 *
 * Πίνακας **ταυτοτήτων `FileRecord.id`** στη σειρά που τις θέλει ο άνθρωπος του γραφείου,
 * φυλαγμένος στο **έγγραφο του ακινήτου** — `properties/{id}.publishedMediaOrder`.
 *
 * 🔴 **ΔΕΝ ΕΙΝΑΙ ΛΙΣΤΑ ΣΥΜΜΕΤΟΧΗΣ, ΚΑΙ ΑΥΤΟ ΕΙΝΑΙ ΟΛΟ ΤΟ ΣΧΕΔΙΟ.** Το *«ποια φεύγουν;»*
 * το απαντούν **αποκλειστικά** οι δύο φρουροί της Α14.2. Ταυτότητα εδώ που δεν τους
 * περνά **δεν δημοσιεύεται** — απλώς αγνοείται. Γι' αυτό δεν γεννιέται ποτέ η ερώτηση
 * *«ποια από τις δύο πηγές κερδίζει;»*: δεν απαντούν την ίδια ερώτηση.
 */
export type AgencyMediaOrderDeclaration = readonly string[];

/** Καμία δήλωση σειράς — μοιράζεται, γιατί είναι αμετάβλητη και κενή. */
export const NO_MEDIA_ORDER: AgencyMediaOrderDeclaration = [];

/**
 * **ΤΙ ΔΗΛΩΣΕ Ο ΑΝΘΡΩΠΟΣ;** — η **μία** ανάγνωση του πεδίου από ωμό έγγραφο.
 *
 * 🔴 **ΥΠΑΡΧΕΙ ΕΠΕΙΔΗ Η ΠΟΡΤΑ ΕΙΝΑΙ `.passthrough()`** (ADR-841 §7 Α14.7.5). Το
 * `PropertyPatchSchema` επικυρώνει ονομαστικά 13 πεδία και αφήνει τα υπόλοιπα να
 * περάσουν· η νέα ρητή γραμμή του σχήματος φυλά **τα αιτήματα από σήμερα**, όχι το
 * ιστορικό ενός εγγράφου που μπορεί να έχει περάσει από άλλη διαδρομή. Ο γραφέας
 * **δεν επιτρέπεται να εμπιστευτεί** το σχήμα του δίσκου.
 *
 * ⚠️ **Δεν πετά ποτέ, και δεν «διορθώνει»**: ό,τι δεν είναι πίνακας ⇒ *καμία δήλωση*.
 * Μια εξαίρεση εδώ θα ακύρωνε τη **δημοσίευση ολόκληρης** της αγγελίας επειδή κάποιος
 * έγραψε σκουπίδι σε ένα προαιρετικό πεδίο σειράς.
 *
 * ⚠️ **ΚΑΝΕΝΑ ΚΟΨΙΜΟ ΣΤΟ ΟΡΙΟ ΕΔΩ, ΕΠΙΤΗΔΕΣ.** Θα ήταν εύλογο *(δεν δημοσιεύονται πάνω
 * από `PUBLISHED_MEDIA_LIMIT`)* και θα ήταν **λάθος**: η δήλωση περιέχει και ταυτότητες
 * που **δεν** ταιριάζουν πια σε δημοσιεύσιμο αρχείο, άρα ένα κόψιμο στη θέση 24 μπορεί
 * να πετάξει ταυτότητα που **ταιριάζει**. Το όριο επιβάλλεται εκεί που είναι αληθές —
 * στο **αποτέλεσμα** — και το μήκος της εισόδου το φράζει η **πόρτα**.
 */
export function declaredMediaOrder(value: unknown): AgencyMediaOrderDeclaration {
  if (!Array.isArray(value)) return NO_MEDIA_ORDER;

  const ids = value.filter(
    (entry): entry is string => typeof entry === 'string' && entry.trim() !== '',
  );
  return ids.length === 0 ? NO_MEDIA_ORDER : ids;
}

/**
 * **Τα αρχεία που το γραφείο σήμανε δημόσια, σε σταθερή σειρά, κομμένα στο όριο.**
 *
 * 🔑 **Το όριο είναι ΤΟ ΙΔΙΟ με του ιδιώτη** (Α14.4): ο λόγος του είναι η **προσοχή του
 * επισκέπτη** *(Zillow 22–27)* — ιδιότητα εκείνου που **κοιτάζει**, όχι εκείνου που
 * ανέβασε. Δύο αριθμοί θα σήμαιναν ότι η ίδια βιτρίνα κουράζει διαφορετικά ανάλογα με
 * το ποιος δημοσίευσε.
 *
 * ⚠️ Ποτέ bytes και ποτέ URL — **μονοπάτι στον ιδιωτικό κάδο**, ίδιο συμβόλαιο με τον
 * ιδιώτη: ο γραφέας κατεβάζει το πρωτότυπο **ο ίδιος**, ώστε ο καθαρισμός EXIF/GPS να
 * μην μπορεί να παρακαμφθεί από τον καλούντα *(Α12.7)*.
 *
 * 🔑 **`PHOTO_MATERIAL` ΣΤΑΘΕΡΑ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΔΕΙΞΗ — ΟΧΙ ΠΑΡΑΔΟΧΗ** (ADR-841 §7 Α17.4).
 * Ο φρουρός #2 έχει **ήδη** εγγυηθεί, δέκα γραμμές πιο πάνω, ότι μόνο
 * `category === 'photos'` φτάνει ως εδώ — δηλαδή το «είναι φωτογραφία;» **απαντήθηκε από
 * ανθρώπινη πράξη** (το σημείο εισόδου του ανεβάσματος), δεν υποτίθεται. ⚠️ Γι' αυτό μια
 * μελλοντική χαλάρωση της λευκής λίστας κατηγορίας **οφείλει** να αλλάξει και αυτή τη
 * γραμμή: είναι οι δύο άκρες του **ίδιου** ισχυρισμού, και η άγκυρα του Ο-20 τις ρωτά μαζί.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Η ΣΕΙΡΑ ΕΧΕΙ **ΔΥΟ ΣΚΕΛΗ**, ΚΑΙ ΤΟ ΟΡΙΟ ΚΟΒΕΙ **ΜΕΤΑ** ΑΠΟ ΑΥΤΑ (Α14.7.3)
 * ────────────────────────────────────────────────────────────────────────────
 *
 *   1. ό,τι **δήλωσε** ο άνθρωπος του γραφείου, στη σειρά που το δήλωσε
 *   2. ό,τι **δεν** δήλωσε, στη ρητά ουδέτερη σειρά του
 *      {@link compareAgencyMediaForPublication}
 *
 * ⚠️ **Η σειρά του `slice` ΕΙΝΑΙ ΟΥΣΙΩΔΗΣ, όχι ύφος**: αν το `PUBLISHED_MEDIA_LIMIT`
 * έκοβε **πριν** την τακτοποίηση, μια φωτογραφία που ο άνθρωπος έβαλε **πρώτη** θα
 * μπορούσε να έχει ήδη πεταχτεί έξω — δηλαδή η πράξη του θα ήταν **αόρατη ακριβώς όταν
 * μετράει**. ⛔ Και το όριο μένει **ΕΝΑ** *(Α14.4)*: κανένα δεύτερο για τη δήλωση.
 *
 * ⚠️ **Η κενή δήλωση ΔΕΝ είναι ειδική περίπτωση** — η μηχανή επιστρέφει τότε ακριβώς τη
 * σειρά που έδινε αυτό το αρχείο πριν την Α14.7. Καμία υπάρχουσα αγγελία δεν αλλάζει
 * μέχρι να μιλήσει άνθρωπος.
 */
export function publishedAgencyMediaSources(
  files: readonly AgencyMediaCandidate[],
  declaredOrder: AgencyMediaOrderDeclaration = NO_MEDIA_ORDER,
): readonly PublicShelfSource[] {
  return orderedPublishableAgencyMedia(files, declaredOrder).map((file) => ({
    privateStoragePath: file.storagePath,
    material: PHOTO_MATERIAL,
  }));
}

/**
 * **ΤΙ ΦΕΥΓΕΙ, ΜΕ ΠΟΙΑ ΣΕΙΡΑ — ΤΑ ΙΔΙΑ ΤΑ ΑΡΧΕΙΑ** (ADR-841 §7 Α14.7).
 *
 * 🔴 **ΕΞΗΧΘΗ ΓΙΑ ΝΑ ΜΗΝ ΥΠΑΡΞΕΙ ΔΕΥΤΕΡΗ ΑΠΑΝΤΗΣΗ, ΚΑΙ ΤΟ ΣΧΗΜΑ ΕΙΝΑΙ ΓΡΑΜΜΕΝΟ ΑΠΟ
 * ΤΗΝ ΑΛΛΗ ΠΛΕΥΡΑ**: το `owner-media-publication` βάζει *«τι φεύγει;»* και *«τι βλέπει ο
 * κάτοχος;»* στο **ίδιο** module ακριβώς επειδή δύο `filter` σε δύο αρχεία θα ήταν *«δύο
 * απαντήσεις ελεύθερες να αποκλίνουν — και η απόκλιση θα ήταν **αόρατη**: η οθόνη θα
 * έλεγε “δημοσιεύονται 30” ενώ ο κόσμος θα έβλεπε 24»*. Το γραφείο απέκτησε οθόνη με την
 * Α14.7 ⇒ **ίδιος κίνδυνος, ίδια θεραπεία**.
 *
 * 🔑 **Γενικό στο `T`, ώστε η οθόνη να κρατά τα ΔΙΚΑ ΤΗΣ πεδία** *(μικρογραφία, όνομα)*
 * χωρίς δεύτερο πέρασμα αντιστοίχισης: ο κανόνας χρειάζεται μόνο το
 * {@link AgencyMediaCandidate}, ο καλών παίρνει πίσω **ό,τι έδωσε**.
 *
 * ⚠️ **Το `PUBLISHED_MEDIA_LIMIT` κόβει ΕΔΩ, ΜΕΤΑ τη σειρά** — άρα η οθόνη δείχνει και
 * το κόψιμο: ένα αρχείο εκτός ορίου **δεν εμφανίζεται**, γιατί δεν φεύγει.
 */
export function orderedPublishableAgencyMedia<T extends AgencyMediaCandidate>(
  files: readonly T[],
  declaredOrder: AgencyMediaOrderDeclaration = NO_MEDIA_ORDER,
): readonly T[] {
  const publishable = files.filter(isPublishableAgencyPhoto);

  return orderByDeclaration(
    publishable,
    (file) => file.id,
    declaredOrder,
    compareAgencyMediaForPublication,
  ).slice(0, PUBLISHED_MEDIA_LIMIT);
}
