/**
 * **Το `FileRecord` όσο το χρειάζεται η απόφαση** — και ούτε πεδίο παραπάνω.
 *
 * 🔑 Γράφεται ως `Pick` του **αληθινού** συμβολαίου και όχι ως ελεύθερο σχήμα: αν κάποια
 * μέρα το `classification` μετονομαστεί ή αλλάξει τύπο, αυτό εδώ **σπάει** αντί να
 * συνεχίσει να διαβάζει πεδίο που δεν υπάρχει πια — που είναι ακριβώς ο τρόπος με τον
 * οποίο ένα προαιρετικό πεδίο γίνεται σιωπηλά μόνιμο `undefined`.
 */
export type AgencyMediaCandidate = Pick<
  FileRecord,
  | 'id'
  | 'entityType'
  | 'storagePath'
  | 'category'
  | 'classification'
  | 'contentType'
  | 'status'
  | 'createdAt'
  | 'lifecycleState'
  | 'isDeleted'
  // ADR-845 Ο-27 — *«ποιο πράγμα δημοσιεύει;»*. Απόν ⇒ **ποτέ** συγχώνευση.
  | 'publicationIdentity'
>;

/**
 * Οι μορφές που ο καθαριστής του ραφιού μπορεί να **αποκωδικοποιήσει**.
 *
 * 🔑 **Δανεικές από το SSoT των ανεβασμάτων** (`FILE_TYPE_CONFIG.image`) και όχι
 * γραμμένες ξανά εδώ: μια δεύτερη λίστα θα σήμαινε ότι κάτι που **επιτρέπεται** να
 * ανέβει μπορεί να **μη** δημοσιεύεται ποτέ, χωρίς να το λέει κανείς.
 */
const DECODABLE_IMAGE_TYPES: readonly string[] = FILE_TYPE_CONFIG.image.mimeTypes;

/**
 * Οι μορφές που ο **ψήστης μοντέλου** μπορεί να παραλάβει *(ADR-845 Φ4.2β/Βήμα Γ)*.
 *
 * 🔴 **ΚΑΤΑΦΑΤΙΚΟΣ ΑΔΕΛΦΟΣ, ΠΟΤΕ ΑΡΝΗΣΗ ΤΟΥ {@link DECODABLE_IMAGE_TYPES}.** Ένα
 * `!DECODABLE_IMAGE_TYPES.includes(...)` θα σήμαινε *«ό,τι δεν είναι εικόνα είναι μοντέλο»* —
 * **άρνηση πάνω σε λεξιλόγιο που μεγαλώνει**, δηλαδή το γραμμένο σφάλμα της Φ4.1: την ημέρα
 * που μπει τρίτο είδος υλικού, θα δημοσιευόταν **ως μοντέλο** χωρίς κανείς να το ζητήσει.
 *
 * 🔑 **Ίδια πηγή με τον αδελφό του**: `FILE_TYPE_CONFIG.model.mimeTypes`. Ό,τι επιτρέπεται να
 * **ανέβει** ως μοντέλο είναι ακριβώς ό,τι μπορεί να **φύγει** ως μοντέλο — μία λίστα, ποτέ δύο.
 */
const DELIVERABLE_MODEL_TYPES: readonly string[] = FILE_TYPE_CONFIG.model.mimeTypes;

/**
 * **Επιτρέπεται αυτό το αρχείο να φύγει από την εταιρεία;** — ο φρουρός #1.
 *
 * ⚠️ **`=== 'public'`, ποτέ «όχι εμπιστευτικό»**: το πεδίο είναι **προαιρετικό** και η
 * προεπιλογή του είναι `internal`. Ό,τι δεν είναι **ρητά** `public` *(απόν, `undefined`,
 * `internal`, `confidential`)* σημαίνει **ιδιωτικό**. Ένας έλεγχος «δεν είναι
 * `confidential`» θα δημοσίευε **κάθε αρχείο που κανείς δεν ταξινόμησε ποτέ** — δηλαδή,
 * σήμερα, **όλα τους**.
 */
export function isPubliclyClassified(file: AgencyMediaCandidate): boolean {
  return file.classification === FILE_CLASSIFICATIONS.PUBLIC;
}

/**
 * **Μπορούν αυτά τα bytes να ΦΥΓΟΥΝ ως εικόνα αυτού του ακινήτου;** — ο φρουρός #2,
 * **χωρίς** το σκέλος της κατηγορίας.
 *
 * 🔴 **ΕΞΗΧΘΗ ΣΤΗΝ Α17.7, ΚΑΙ Η ΓΡΑΜΜΗ ΤΗΣ ΤΟΜΗΣ ΕΙΝΑΙ Η ΑΠΟΦΑΣΗ.** Το υλικο-ανεξάρτητο
 * μέρος *(κηδεμονία · ετοιμότητα · ζωή · μονοπάτι)* ζει στο {@link isDeliverableAgencyFile}·
 * εδώ μένει **μόνο** το *«είναι αποκωδικοποιήσιμη εικόνα;»*. Το *«τι είδους υλικό είναι;»*
 * απαντιέται **χωριστά** από κάθε οικογένεια — γιατί οι δύο οικογένειες το απαντούν
 * **ανόμοια**, και η ανομοιότητα είναι δικαιολογημένη *(Α17.7.4)*.
 *
 * ⚠️ **Το συμβόλαιο ΔΕΝ άλλαξε στο Βήμα Γ** — ίδια υπογραφή, ίδια απάντηση για κάθε είσοδο.
 * Άλλαξε **ποιος** κρατά τους τέσσερις κοινούς ελέγχους, ώστε ο αδελφός του μοντέλου να μην
 * τους αντιγράψει.
 *
 * 🔑 **Ο έλεγχος MIME μένει εδώ και είναι ο λόγος που τα DXF δεν είναι θέμα**: μετρημένο
 * ζωντανά *(Α17.7.1)*, και οι κατόψεις της βάσης είναι `application/dxf` ⇒ **δεν μπαίνουν
 * σε `<img>`**, όσο κι αν κάποιος τις δηλώσει. Η δήλωση της Α17.7 **δεν** τις ξεκλειδώνει.
 */
export function isDeliverableAgencyImage(file: AgencyMediaCandidate): boolean {
  return isDeliverableAgencyFile(file) && DECODABLE_IMAGE_TYPES.includes(file.contentType);
}

/**
 * **Μπορούν αυτά τα bytes να ΦΥΓΟΥΝ ως 3D μοντέλο αυτού του ακινήτου;** — ο αδελφός του
 * {@link isDeliverableAgencyImage} *(ADR-845 Φ4.2β/Βήμα Γ, φράγμα Ο-9)*.
 *
 * 🔴 **ΚΑΤΑΦΑΤΙΚΟΣ**: ρωτά *«είναι μοντέλο;»*, **ποτέ** *«δεν είναι εικόνα;»*. Δες
 * {@link DELIVERABLE_MODEL_TYPES} για το γιατί η άρνηση θα ήταν δομικά λάθος.
 *
 * ⚠️ **Δεν επαναλαμβάνει ΤΙΠΟΤΑ από τον αδελφό του**: κηδεμονία, ετοιμότητα, ζωή και
 * μονοπάτι ζουν στο {@link isDeliverableAgencyFile}. Δύο σώματα που θα έλεγαν τους ίδιους
 * τέσσερις ελέγχους θα ήταν **sibling clone** — ο N.18 τον έπιασε ήδη μία φορά σε αυτή τη
 * φάση, και το `ssot:discover` **δεν** θα τον έβλεπε ποτέ *(διαφορετικά ονόματα)*.
 */
export function isDeliverableAgencyModel(file: AgencyMediaCandidate): boolean {
  return isDeliverableAgencyFile(file) && DELIVERABLE_MODEL_TYPES.includes(file.contentType);
}

/**
 * **Ό,τι ισχύει ΑΝΕΞΑΡΤΗΤΑ από το είδος του υλικού** — κηδεμονία · ετοιμότητα · ζωή · μονοπάτι.
 *
 * 🔑 **Η γραμμή της τομής μετακινήθηκε ΕΝΑ σκαλί, και είναι η ίδια απόφαση της Α17.7.** Ως το
 * Βήμα Γ, ο έλεγχος MIME ζούσε **μέσα** στο *«παραδοτέο»*, επειδή υπήρχε **ένα** είδος bytes.
 * Με δύο, το *«αποκωδικοποιήσιμη εικόνα»* έπαψε να είναι υλικο-ανεξάρτητο — και ό,τι έπαψε να
 * είναι κοινό **βγαίνει από το κοινό**, αντί να αντιγραφεί.
 *
 * ⚠️ Το `lifecycleState` και το `isDeleted` είναι **δύο** πεδία για μία κατάσταση *(η ζωντανή
 * βάση έχει και τα δύο σε κάθε έγγραφο)*. Ελέγχονται **αμφότερα**: το ένα να λείπει σε παλιό
 * έγγραφο δεν επιτρέπεται να σημαίνει «δημοσίευσέ το».
 */
function isDeliverableAgencyFile(file: AgencyMediaCandidate): boolean {
  if (file.entityType !== 'property') return false;
  if (file.status !== FILE_STATUS.READY) return false;
  if (file.isDeleted === true) return false;
  if (
    file.lifecycleState !== undefined &&
    file.lifecycleState !== FILE_LIFECYCLE_STATES.ACTIVE
  ) {
    return false;
  }
  return typeof file.storagePath === 'string' && file.storagePath.trim() !== '';
}

/**
 * **ΤΙ ΦΕΥΓΕΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ — ΚΑΙ ΩΣ ΤΙ;** ΜΙΑ ερώτηση, μία απάντηση (Α17.7.4).
 *
 * 🔴 **ΓΡΑΦΤΗΚΕ ΩΣ ΕΝΑ ΕΡΩΤΗΜΑ ΕΠΙΤΗΔΕΣ, ΚΑΙ ΤΟ ΠΡΟΕΙΔΟΠΟΙΟΥΣΕ Η Α17.4**:
 * *«μια μελλοντική χαλάρωση της λευκής λίστας **οφείλει** να αλλάξει και τη γραμμή του
 * υλικού: είναι οι **δύο άκρες του ίδιου ισχυρισμού**»*. Δύο ξεχωριστές συναρτήσεις —
 * *«φεύγει;»* και *«τι είναι;»* — θα μπορούσαν να διαφωνήσουν σιωπηλά: αρχείο θα έφευγε
 * ως **φωτογραφία** ενώ ο άνθρωπος το δήλωσε **κάτοψη**, ή αντίστροφα. Με **μία**
 * συνάρτηση, η διαφωνία είναι **δομικά αδύνατη**: `null` σημαίνει «δεν φεύγει», και ό,τι
 * δεν είναι `null` **είναι** το υλικό του.
 *
 * ```
 * ΦΩΤΟΓΡΑΦΙΑ  →  public + σχήμα + category === 'photos'                    ⇒ photo
 * ΚΑΤΟΨΗ      →  public + σχήμα + category === 'floorplans'
 *                            + ΟΝΟΜΑΣΤΙΚΗ ΔΗΛΩΣΗ + αναγνώσιμη στιγμή        ⇒ floorplan
 * ΜΟΝΤΕΛΟ 3D  →  public + σχήμα + category === 'models'                    ⇒ model
 * ```
 *
 * ⚠️ **ΤΟ ΜΟΝΤΕΛΟ ΔΕΝ ΖΗΤΑΕΙ ΟΝΟΜΑΣΤΙΚΗ ΔΗΛΩΣΗ ΕΔΩ, ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΧΑΛΑΡΩΣΗ.** Η κάτοψη τη
 * χρειάζεται επειδή ζει στον **ίδιο** κάδο με σχέδια που κανείς δεν προόριζε για δημοσίευση
 * *(Ο-21)*. Το μοντέλο έχει **δικό του** κάδο, στον οποίο μπαίνει **μόνο** μέσω μιας διαδρομής
 * που **απαιτεί** σήμανση κατάστασης και υπογράφοντα *(Α-3 · Α-4)* πριν γραφτεί ένα byte —
 * δηλαδή η ανθρώπινη πράξη έχει **ήδη** συμβεί, νωρίτερα και αυστηρότερα.
 *
 * 🔴 **Η ΛΕΥΚΗ ΛΙΣΤΑ ΔΕΝ ΧΑΛΑΡΩΣΕ — ΑΠΕΚΤΗΣΕ ΔΕΥΤΕΡΟ ΣΚΕΛΟΣ ΜΕ ΑΥΣΤΗΡΟΤΕΡΗ
 * ΑΠΑΙΤΗΣΗ.** Το Ο-21 προειδοποιούσε ρητά: *«ΜΗΝ λυθεί χαλαρώνοντας τη λευκή λίστα — θα
 * δημοσίευε **κάθε** αρχείο `floorplans` που κάποιος σήμανε `public`»*. Δεν συμβαίνει:
 * η κάτοψη θέλει `classification: 'public'` **ΚΑΙ** ρητή αναφορά της ταυτότητάς της.
 * ⇒ Η άγκυρα **Κ4** του `listing-floorplan-separation` μένει **αληθής**, και απέκτησε
 * αδελφό: *«ούτε τότε, παρά μόνο αν κάποιος την **ονόμασε**»*.
 *
 * ⚠️ **ΑΝΑΓΝΩΣΙΜΗ ΣΤΙΓΜΗ ΕΙΝΑΙ ΦΡΟΥΡΟΣ, ΟΧΙ ΛΕΠΤΟΜΕΡΕΙΑ.** Το `ListingMaterial` της
 * κάτοψης έχει **υποχρεωτικό** `at`, επειδή το δημόσιο έγγραφο τη γράφει ως
 * `SourcedAttribute` — και κάθε τέτοιο **οφείλει** να πει *πότε το έμαθε η πηγή*. Κάτοψη
 * με μη αναγνώσιμο `createdAt` **δεν δημοσιεύεται**· ⛔ **ποτέ ρολόι του γραφέα**, που θα
 * απαντούσε *«πότε το πρόβαλα»* σε πεδίο που ρωτά *«πότε το είπε ο άνθρωπος»*.
 *
 * ⚠️ **`declaredFloorplans` είναι ΣΥΝΟΛΟ, όχι πίνακας**: ρωτιέται μία φορά ανά αρχείο σε
 * βρόχο πάνω σε **όλα** τα αρχεία του ακινήτου· ένα `includes` θα ήταν `O(n·m)` για
 * απάντηση που είναι `O(1)`.
 *
 * 🔴 **ΚΑΙ ΓΙ' ΑΥΤΟ ΕΦΥΓΑΝ ΤΑ `isPublishableShape` / `isPublishableAgencyPhoto`**
 * *(2026-09-06)*. Μετά την Α17.7 δεν τα καλούσε **κανείς** — ούτε παραγωγός, ούτε άγκυρα
 * *(μετρημένο με `grep` σε όλο το `src/`)* — και θα έμεναν ως **δεύτερη διατύπωση** του
 * κριτηρίου που ζει τώρα εδώ: ακριβώς το σχήμα που το **ADR-749** ονομάζει «δύο μηχανές
 * για την ίδια ερώτηση». *«Νεκρό **και** διπλότυπο» δεν είναι δύο προβλήματα — είναι το
 * ίδιο πρόβλημα σε δύο ηλικίες.*
 */
export function agencyMediaMaterial(
  file: AgencyMediaCandidate,
  declaredFloorplans: ReadonlySet<string>,
): ListingMaterial | null {
  if (!isPubliclyClassified(file)) return null;

  switch (file.category) {
    case FILE_CATEGORIES.PHOTOS:
      return isDeliverableAgencyImage(file) ? PHOTO_MATERIAL : null;

    // ADR-845 Φ4.2β/Βήμα Γ — το δεύτερο σκέλος του φράγματος **Ο-9**. Ως εδώ, ένα μοντέλο
    // **δεν είχε κατηγορία**: έπεφτε στο τελικό `null` και ο αγωγός δημοσίευσης — που
    // ψήνει `{kind:'model'}` **σωστά** από τη Φ4.2α — δεν έβλεπε ποτέ πηγή.
    case FILE_CATEGORIES.MODELS:
      return isDeliverableAgencyModel(file) ? MODEL_MATERIAL : null;

    case FILE_CATEGORIES.FLOORPLANS:
      return declaredFloorplanOrNull(file, declaredFloorplans);

    // 🔑 **Σιωπή, όχι `assertNever`**: το `FILE_CATEGORIES` απαριθμεί **ιδιωτικούς κάδους**
    //    (τιμολόγια, συμβόλαια, άδειες), και τα περισσότερα **οφείλουν** να μη δημοσιεύονται.
    //    Ένας εξαντλητικός φρουρός εδώ θα ζητούσε από κάθε νέο κάδο απάντηση σε ερώτηση που
    //    δεν τον αφορά. Το λεξιλόγιο που **πρέπει** να απαντηθεί εξαντλητικά είναι το
    //    `LISTING_MATERIAL_KINDS` — και το φυλά ήδη ο `partitionListingSources` (άγκυρα Α-2).
    default:
      return null;
  }
}

/**
 * Η κάτοψη: **παραδοτέα εικόνα + ονομαστική δήλωση + αναγνώσιμη στιγμή** — και τα τρία.
 *
 * ⚠️ Ξεχωριστό σώμα ώστε ο `switch` να μείνει **μία ερώτηση ανά κλάδο**· καμία απόφαση δεν
 * μετακινήθηκε και καμία δεν προστέθηκε *(N.7.1: ≤40 γραμμές ανά συνάρτηση)*.
 */
function declaredFloorplanOrNull(
  file: AgencyMediaCandidate,
  declaredFloorplans: ReadonlySet<string>,
): ListingMaterial | null {
  if (!isDeliverableAgencyImage(file)) return null;
  if (!declaredFloorplans.has(file.id)) return null;

  const at = normalizeToISO(file.createdAt);
  return at === null ? null : declaredFloorplanMaterial(at);
}

/**
 * **Η σειρά ΟΣΩΝ ΚΑΝΕΙΣ ΔΕΝ ΔΗΛΩΣΕ** — ντετερμινιστική, και ρητά **όχι** επιλογή ανθρώπου.
 *
 * 🔴 **ΑΥΤΟΣ Ο ΣΥΓΚΡΙΤΗΣ ΑΛΛΑΞΕ ΡΟΛΟ ΣΤΗΝ Α14.7 — ΔΕΝ ΕΙΝΑΙ ΠΙΑ «Η ΣΕΙΡΑ».** Μέχρι τις
 * 2026-09-06 ήταν η **μόνη** απάντηση στο *«ποια φωτογραφία είναι πρώτη;»*, και η Α14.3
 * το ονόμασε ανοιχτό πρόβλημα αντί να το κρύψει: ο ιδιώτης απαντούσε με **ανθρώπινη
 * πράξη** *(Α2.1)* και το γραφείο με **χρόνο** — τον χρόνο που η **Α6.2** είχε
 * απορρίψει **ρητά** ως κριτήριο σειράς. Τώρα το γραφείο **έχει** πράξη
 * *(`publishedMediaOrder`)*, και εδώ έμεινε η ουρά της: *«με ποια σειρά μπαίνουν όσα ο
 * άνθρωπος **δεν** τακτοποίησε»*.
 *
 * 🔑 **Η ένσταση της Α6.2 ΕΞΕΠΝΕΥΣΕ, ΔΕΝ ΠΑΡΑΚΑΜΦΘΗΚΕ**: *«χρόνος που δεν επέλεξε ο
 * άνθρωπος διαβάζεται ως επιλογή του»* ισχύει όσο ο άνθρωπος **δεν έχει φωνή**. Από τη
 * στιγμή που έχει, ο χρόνος παύει να μιλά στη θέση του — γίνεται η **ρητά ουδέτερη**
 * σειρά για ό,τι δεν σχολίασε.
 *
 * ⛔ **ΜΗΝ τον διαγράψεις «τώρα που υπάρχει η δήλωση».** Η δήλωση είναι **αραιή**: στη
 * συνήθη περίπτωση είναι **κενή**, και τότε αυτός ο συγκριτής είναι **ολόκληρη** η σειρά.
 *
 * ⛔ Και **δεν** διαλέχτηκε το `purpose` *(`'exterior'`/`'interior'`)*, παρότι η RESO
 * προτιμά εξωτερική όψη ως πρωτεύουσα: οι τιμές του ζουν στο μητρώο **σημείων εισόδου**
 * και **όχι** στο `PHOTO_PURPOSES` ⇒ κατάταξη με βάση τους θα **εφεύρισκε λεξιλόγιο
 * τομέα** (CHECK 3.73).
 *
 * 🔑 **Ο ντετερμινισμός ΔΕΝ είναι καλλωπισμός**: το ράφι συμφιλιώνεται σε **κάθε**
 * επανασύνθεση. Ασταθής σειρά ⇒ άλλο `gallery` κάθε πέρασμα ⇒ **δημόσια bytes που
 * αναβοσβήνουν** χωρίς να έχει αλλάξει τίποτα. Γι' αυτό υπάρχει και η **ισοπαλία στο
 * `id`**: δύο αρχεία ανεβασμένα στο ίδιο χιλιοστό του δευτερολέπτου δεν επιτρέπεται να
 * αφήνουν τη σειρά τους στην υλοποίηση του `sort`.
 */
export function compareAgencyMediaForPublication(
  a: AgencyMediaCandidate,
  b: AgencyMediaCandidate,
): number {
  const byInstant = compareInstantsAsc(a.createdAt, b.createdAt);
  if (byInstant !== 0) return byInstant;
  return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
}

/**
 * **Η ΠΡΑΞΗ ΤΟΥ ΑΝΘΡΩΠΟΥ ΤΟΥ ΓΡΑΦΕΙΟΥ** — δύο δηλώσεις, ένα δοχείο (ADR-841 §7 Α14.7 · Α17.7).
 *
 * | Πεδίο | Ρωτά | Ζει στο |
 * |---|---|---|
 * | `order` | *«με ποια σειρά;»* — **ποτέ** «ποια;» | `properties/{id}.publishedMediaOrder` |
 * | `floorplans` | *«ποιες κατόψεις είναι υλικό **ΑΥΤΗΣ** της αγγελίας;» | `properties/{id}.publishedFloorplans` |
 *
 * 🔴 **ΟΙ ΔΥΟ ΔΕΝ ΕΙΝΑΙ ΤΟ ΙΔΙΟ ΕΙΔΟΣ ΔΗΛΩΣΗΣ, ΚΑΙ Η ΔΙΑΦΟΡΑ ΕΙΝΑΙ Η ΑΣΦΑΛΕΙΑ.**
 * Η `order` **δεν μπορεί να δημοσιεύσει τίποτα** — μόνο να τακτοποιήσει ό,τι ήδη φεύγει *(Α14.7.2)*.
 * Η `floorplans` **ΕΙΝΑΙ** σκέλος συμμετοχής — αλλά **προστίθεται** στους φρουρούς,
 * ποτέ δεν τους αντικαθιστά *(Α17.7.4)*: κάτοψη χωρίς `classification: \'public\'` δεν φεύγει
 * **ούτε όταν δηλωθεί**. ⚠️ Για να μην συγχυθούν ποτέ, μένουν **δύο ονομασμένα πεδία**
 * και **όχι** δύο ομόηχοι πίνακες σε σειρά ορισμάτων, όπου μια αντιμετάθεση θα ήταν **σιωπηλή**.
 */
export interface AgencyMediaDeclaration {
  /** Η σειρά — πρόθεμα, ποτέ συμμετοχή. */
  readonly order: DeclaredFileIds;
  /** Οι κατόψεις — ένας φρουρός ΕΠΙΠΛΕΟΝ, ποτέ αντί για. */
  readonly floorplans: DeclaredFileIds;
}

/** Καμία δήλωση — μοιράζεται, γιατί είναι αμετάβλητη και κενή. */
export const NO_AGENCY_DECLARATION: AgencyMediaDeclaration = {
  order: NO_DECLARED_FILE_IDS,
  floorplans: NO_DECLARED_FILE_IDS,
};

/**
 * **ΤΙ ΔΗΛΩΣΕ Ο ΑΝΘΡΩΠΟΣ;** — η **μία** ανάγνωση του ωμού εγγράφου.
 *
 * 🔑 **ΕΝΑ ΣΗΜΕΙΟ ΓΙΑ ΚΑΙ ΤΑ ΔΥΟ ΠΕΔΙΑ**: ο γραφέας κάνει **μία** κλήση, άρα
 * δεν υπάρχει περίπτωση να διαβάσει το ένα και να **ξεχάσει** το άλλο — το σχήμα που έκανε
 * το `publishedMedia` να μείνει άδειο επί μήνες *(Α14.5)*.
 *
 * ⚠️ **Δέχεται ωμό αντικείμενο, και κάθε πεδίο περνά από το {@link declaredFileIds}**:
 * ο δίσκος δεν είναι έμπιστος όσο η πόρτα του PATCH είναι `.passthrough()` *(Α14.7.5)*.
 */
export function agencyMediaDeclaration(source: {
  readonly publishedMediaOrder?: unknown;
  readonly publishedFloorplans?: unknown;
}): AgencyMediaDeclaration {
  return {
    order: declaredFileIds(source.publishedMediaOrder),
    floorplans: declaredFileIds(source.publishedFloorplans),
  };
}
