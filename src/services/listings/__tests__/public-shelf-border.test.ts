/**
 * @fileoverview **ΟΙ ΑΓΚΥΡΕΣ ΤΟΥ ΚΡΙΤΗ ΤΟΥ ΠΕΡΙΓΡΑΜΜΑΤΟΣ** (ADR-841 §7 Α21.10).
 *
 * 🔴 **Η Κ3 ΕΙΝΑΙ Ο ΛΟΓΟΣ ΠΟΥ ΥΠΑΡΧΕΙ ΟΛΟ ΤΟ ΑΡΧΕΙΟ.** Η πρώτη μέτρηση της Φάσης Β
 * έδειξε ότι σκέτο `sharp.trim()` μετατρέπει ένα λογότυπο τύπου app-icon *(λευκό σύμβολο
 * σε μπλε πλακίδιο)* από **400×200 σε 120×120** — τρώει ολόκληρο το σώμα και αλλάζει την
 * αναλογία. Αν αυτή η σουίτα γίνει ποτέ πράσινη με τον έλεγχο αφαιρεμένο, το σύστημα
 * **καταστρέφει σήματα και τα δημοσιεύει αμετάκλητα** *(content-addressed bytes)*.
 *
 * ⚠️ **Καμία εικόνα, κανένα `sharp`**: ο κριτής είναι καθαρή συνάρτηση πάνω σε τέσσερις
 * τετράδες. Το ότι οι τετράδες αυτές **όντως** διαβάζονται από γωνίες πραγματικών
 * αρχείων το φυλά η **Κ5** του `public-shelf-sanitise.test` — δύο ερωτήσεις, δύο σουίτες.
 */

import {
  BORDER_ALPHA_EMPTY,
  BORDER_CORNER_AGREEMENT,
  BORDER_PAPER_FLOOR,
  borderIsPackaging,
  classifyBorder,
  type BorderPixel,
} from '../public-shelf-border';

/** Τέσσερις **ίδιες** γωνίες — το σχήμα κάθε ομοιόμορφου πλαισίου. */
const uniform = (pixel: BorderPixel): readonly BorderPixel[] => [pixel, pixel, pixel, pixel];

describe('Κ1 — ΔΙΑΦΑΝΟ περίγραμμα είναι συσκευασία', () => {
  it('πλήρως διάφανες γωνίες ⇒ `empty`', () => {
    expect(classifyBorder(uniform([0, 0, 0, 0]))).toBe('empty');
  });

  it('🔑 και τα RGB κάτω από το διάφανο ΔΕΝ κρίνονται — ούτε καν συγκρίνονται', () => {
    // 🔴 ΔΙΟΡΘΩΣΗ ΠΡΑΓΜΑΤΙΚΟΥ ΣΦΑΛΜΑΤΟΣ ΤΟΥ ΠΡΩΤΟΤΥΠΟΥ: με `alpha = 0` τα RGB είναι
    //    αδιάφορα και τα αρχεία τα γεμίζουν με ό,τι να 'ναι. Μια σύγκριση RGB εδώ θα
    //    απαντούσε `disagree` σε ΟΛΟΦΑΝΕΡΑ διάφανο λογότυπο — δηλαδή η κανονικοποίηση
    //    θα σταματούσε ακριβώς στην πιο συνηθισμένη περίπτωση που υπάρχει.
    expect(
      classifyBorder([
        [255, 0, 0, 0],
        [0, 255, 0, 0],
        [0, 0, 255, 0],
        [17, 99, 200, 0],
      ]),
    ).toBe('empty');
  });

  it('υπόλειμμα alpha από dithering μετρά ακόμη ως κενό', () => {
    expect(classifyBorder(uniform([0, 0, 0, BORDER_ALPHA_EMPTY]))).toBe('empty');
  });

  it('🔴 ΜΕΡΙΚΩΣ διάφανο περίγραμμα ΔΕΝ είναι πλαίσιο', () => {
    // Δύο γωνίες κενές, δύο όχι ⇒ δεν υπάρχει ομοιόμορφο πλαίσιο να αφαιρεθεί, και ένα
    // τρίμμα θα ακολουθούσε μόνο την πάνω-αριστερή — δηλαδή λοξό κόψιμο.
    expect(
      classifyBorder([
        [0, 0, 0, 0],
        [0, 0, 0, 0],
        [10, 20, 30, 255],
        [10, 20, 30, 255],
      ]),
    ).toBe('disagree');
  });
});

describe('Κ2 — ΛΕΥΚΟ περίγραμμα είναι χαρτί, με ανοχή στη συμπίεση', () => {
  it('καθαρό λευκό ⇒ `paper`', () => {
    expect(classifyBorder(uniform([255, 255, 255, 255]))).toBe('paper');
  });

  it('🔑 λευκό μετατοπισμένο από ringing JPEG μετρά ακόμη ως χαρτί', () => {
    // Χωρίς αυτή την ανοχή, το ΙΔΙΟ λογότυπο σε PNG και σε JPEG θα έπαιρνε διαφορετική
    // απόφαση — δηλαδή η κανονικοποίηση θα εξαρτιόταν από τη μορφή του αρχείου.
    expect(classifyBorder(uniform([BORDER_PAPER_FLOOR, 250, 247, 255]))).toBe('paper');
  });

  it('ανοιχτό γκρι κάτω από το κατώφλι ΔΕΝ είναι χαρτί — είναι απόφαση κάποιου', () => {
    const belowFloor = BORDER_PAPER_FLOOR - 1;
    expect(classifyBorder(uniform([belowFloor, belowFloor, belowFloor, 255]))).toBe('body');
  });

  it('🔴 ΕΝΑ κανάλι κάτω από το κατώφλι αρκεί — το «σχεδόν λευκό» έχει απόχρωση', () => {
    expect(classifyBorder(uniform([255, 255, 200, 255]))).toBe('body');
  });
});

describe('🔴 Κ3 — ΧΡΩΜΑΤΙΣΤΟ περίγραμμα ΕΙΝΑΙ ΤΟ ΣΗΜΑ, και δεν αγγίζεται ΠΟΤΕ', () => {
  it('το μπλε πλακίδιο του app-icon κρίνεται `body`', () => {
    // Η μετρημένη καταστροφή: `sharp.trim()` σε αυτό δίνει 400×200 → 120×120.
    expect(classifyBorder(uniform([29, 78, 216, 255]))).toBe('body');
  });

  it('και το ΜΑΥΡΟ πλαίσιο επίσης — σκούρα επωνυμία δεν είναι «κενό»', () => {
    expect(classifyBorder(uniform([0, 0, 0, 255]))).toBe('body');
  });

  it('🔑 και ΚΑΝΕΝΑ από τα δύο δεν παίρνει άδεια αφαίρεσης', () => {
    expect(borderIsPackaging('body')).toBe(false);
    expect(borderIsPackaging('disagree')).toBe(false);
    expect(borderIsPackaging('empty')).toBe(true);
    expect(borderIsPackaging('paper')).toBe(true);
  });
});

describe('Κ4 — ΤΕΣΣΕΡΙΣ γωνίες, γιατί το `trim` κοιτά μόνο ΜΙΑ', () => {
  it('🔴 λευκή πάνω-αριστερή με χρωματιστές υπόλοιπες ⇒ `disagree`', () => {
    // Χωρίς αυτόν τον έλεγχο, το `trim` θα ακολουθούσε την πάνω-αριστερή και θα έκοβε
    // **λοξά** — τρίμμα που υπακούει σε ένα εικονοστοιχείο αντί για τη δομή.
    expect(
      classifyBorder([
        [255, 255, 255, 255],
        [29, 78, 216, 255],
        [29, 78, 216, 255],
        [29, 78, 216, 255],
      ]),
    ).toBe('disagree');
  });

  it('διαφορά μέσα στην ανοχή μετρά ως συμφωνία', () => {
    const drift = BORDER_CORNER_AGREEMENT;
    expect(
      classifyBorder([
        [100, 100, 100, 255],
        [100 + drift, 100, 100, 255],
        [100, 100 - drift, 100, 255],
        [100, 100, 100 + drift, 255],
      ]),
    ).toBe('body');
  });

  it('🔑 ΝΤΕΓΚΡΑΝΤΕ φόντο ⇒ `disagree` — εκεί δεν υπάρχει περιθώριο, υπάρχει σχέδιο', () => {
    expect(
      classifyBorder([
        [240, 240, 240, 255],
        [200, 200, 200, 255],
        [160, 160, 160, 255],
        [120, 120, 120, 255],
      ]),
    ).toBe('disagree');
  });

  it('κενή λίστα ⇒ `disagree` — η άγνοια δεν δίνει ποτέ άδεια', () => {
    expect(classifyBorder([])).toBe('disagree');
  });
});
