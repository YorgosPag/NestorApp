/**
 * **Μια δημοσιευμένη εικόνα, όπως τη μαθαίνει ο γραφέας από το ράφι.**
 *
 * ⚠️ **Δομικός τύπος και ΟΧΙ ο τύπος της υπηρεσίας**: το `public-shelf.service` σέρνει
 * `firebase-admin` και `sharp`, και αυτό το αρχείο δηλώνει ρητά ότι είναι **καθαρό**.
 * Η μία γραμμή μετάφρασης στον γραφέα είναι φθηνότερη από μια εξάρτηση που θα έκανε την
 * προβολή αδύνατη να δοκιμαστεί χωρίς κάδο.
 *
 * 🔴 **ΕΙΝΑΙ RASTER, ΚΑΙ ΤΟ ΛΕΕΙ ΤΟ ΙΔΙΟ ΤΟΥ ΤΟ ΣΧΗΜΑ** *(ADR-845 Φ4.1)*: `width`/`height`
 * και **`sources` ανά πλάτος** *(`srcset`)*. Παράγεται **αποκλειστικά** από το raster ράφι
 * *(`isRasterShelfKind`, άγκυρα Α-1δ)*. Ένα τρισδιάστατο μοντέλο **δεν μπορεί να είναι**
 * τέτοιο αντικείμενο — γι' αυτό ο `case 'model'` παρακάτω **αρνείται με όνομα** αντί να
 * κατασκευάσει `ListingModel` από πεδία που δεν υπάρχουν.
 */
export interface ProjectedShelfImage {
  readonly url: string;
  readonly width: number;
  readonly height: number;
  readonly sources: readonly ListingImageSource[];
  /** **Τι είναι αυτό** — δες `PublicShelfImage.material` (ADR-841 §7 Α17.4). */
  readonly material: ListingMaterial;
}

/**
 * Το ωφέλιμο φορτίο μιας εικόνας, με το κλειδί αποκάλυψης **ήδη διαλεγμένο**.
 *
 * 🔑 Module-level και όχι κλείσιμο μέσα στον δρομολογητή: παίρνει το `altKey` ως όρισμα,
 * ώστε η **επιλογή** του κλειδιού να μένει ορατή στο σημείο της δρομολόγησης — εκεί όπου
 * ζει η απόφαση *«τι είδους υλικό είναι αυτό;»*, και όχι κρυμμένη σε βοηθητική συνάρτηση.
 */
function toListingImage(image: ProjectedShelfImage, altKey: string): ListingImage {
  return {
    url: image.url,
    width: image.width,
    height: image.height,
    altKey,
    sources: image.sources,
  };
}

/**
 * **Ο ΦΡΟΥΡΟΣ ΤΟΥ ΛΕΞΙΛΟΓΙΟΥ** — τοπικός και **με όνομα**, όπως όλοι οι αδελφοί του.
 *
 * 🔑 **Το ιδίωμα του σπιτιού είναι ΤΟΠΙΚΟ + ΟΝΟΜΑΣΜΕΝΟ, και μετρήθηκε** *(ADR-845 Φ4.1,
 * `grep` σε όλο το `src/`)*: υπάρχουν **τρεις** τέτοιοι — `assertNeverShape` /
 * `assertNeverAccuracy` *(`lib/listings/listing-map-shape`)* και `assertNeverProvenance`
 * *(`lib/property/attribute-provenance`)* — και **κανένας κεντρικός**. ⛔ **Μην γεννήσεις
 * κεντρικό `assertNever`**: η αξία δεν είναι το `throw`, είναι το **μήνυμα** — αυτό λέει
 * *ποια* ερώτηση έμεινε αναπάντητη, και ένα γενικό βοήθημα θα την αφαιρούσε.
 *
 * ⚠️ Μήνυμα **προγραμματιστή**, όχι οθόνης *(σύμβαση `src/lib`/`src/services` + N.11)*.
 */
function assertNeverMaterial(material: never): never {
  throw new Error(
    `withPublishedGallery: άγνωστο είδος υλικού — ${JSON.stringify(material)}. ` +
      'Νέα τιμή στο LISTING_MATERIAL_KINDS χωρίς απάντηση στο «σε ποιο κουτί της ' +
      'δημόσιας αγγελίας κάθεται;» (ADR-845 §2.2, άγκυρα Α-2).',
  );
}

/**
 * **Η αγγελία με τη συλλογή της δεμένη** — η στιγμή που το έγγραφο γίνεται *manifest*.
 *
 * 🔑 **ΕΝΑΣ γραφέας του πεδίου, εδώ.** Ο πειρασμός ήταν ένα `{ ...listing, gallery }`
 * μέσα στον `writeListingProjection`, δίπλα στο `schemaVersion`. Αλλά το `schemaVersion`
 * είναι μεταδεδομένο **αποθήκευσης** *(κανείς επισκέπτης δεν το διαβάζει)*, ενώ η
 * συλλογή είναι **περιεχόμενο αγγελίας** — και το περιεχόμενο συντίθεται σε αυτό το
 * αρχείο, αλλιώς το κλειστό σχήμα θα είχε **δύο** τόπους σύνθεσης.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴🔴 ΕΝΑ ΠΕΡΑΣΜΑ ΜΕ `switch`, ΚΑΙ ΟΧΙ ΔΥΟ ΜΕ ΑΡΝΗΣΗ — **ADR-845 Φ4.1**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ως τη Φ4.1 εδώ υπήρχαν **δύο περάσματα με δυαδικό κατηγόρημα**:
 * `filter(i => !isFloorplanMaterial(…))` για τη συλλογή, `flatMap(… ? [ ] : [])` για τις
 * κατόψεις. Και το `listing-material.ts` **υποσχόταν γραπτώς** ότι *«ο εξαντλητικός
 * κλάδος του `withPublishedGallery` θα σπάσει τη μεταγλώττιση»* — υπόσχεση που πέρασε
 * **αυτούσια** μέσα στο ADR-845 §2.2 ως τεκμηριωμένο γεγονός.
 *
 * ⛔ **ΗΤΑΝ ΨΕΥΔΗΣ, ΚΑΙ ΔΟΜΙΚΑ**: μια **άρνηση είναι πάντα ολική**. Τρίτο είδος υλικού θα
 * έδινε `isFloorplanMaterial → false ⇒ !false ⇒ μπαίνει στη ΣΥΛΛΟΓΗ, ως φωτογραφία,
 * σιωπηλά` — δηλαδή **ακριβώς το Ο-20**, με μεταγλώττιση ✅, tests ✅, δημοσίευση ✅.
 *
 * 🔑 **Ένα πέρασμα ⇒ κάθε εικόνα δρομολογείται ΑΚΡΙΒΩΣ ΜΙΑ ΦΟΡΑ.** Δύο ανεξάρτητα
 * κατηγορήματα μπορούν να αφήσουν **κενό** *(κανένα δεν πιάνει)* **ή** να **διπλογράψουν**
 * *(και τα δύο πιάνουν)*· ένας `switch` δεν μπορεί ούτε το ένα ούτε το άλλο. Ίδιο
 * επιχείρημα με το `dxf-entity-layer-skip.ts` — **μία ερώτηση, ένας κριτής**.
 *
 * 🔑 **Και το `altKey` μπαίνει ΕΔΩ, μία φορά**: είναι απόφαση **αποκάλυψης** *(τι λέμε
 * σε όποιον δεν βλέπει την εικόνα)*, όχι λεπτομέρεια απόδοσης. Δες
 * {@link LISTING_MATERIAL_KEYS} για το γιατί δεν είναι κενό και δεν περιγράφει.
 *
 * 🔴 **ΚΑΙ ΤΟ ΚΛΕΙΔΙ ΔΙΑΛΕΓΕΤΑΙ ΑΠΟ ΤΗΝ `authorship` ΤΗΣ ΙΔΙΑΣ ΑΓΓΕΛΙΑΣ** (Α15). Μέχρι
 * την **Α14** ήταν **σταθερά** — και ήταν σωστό, γιατί υπήρχε **ΕΝΑΣ** παραγωγός
 * συλλογής. Τη μέρα που το γραφείο απέκτησε συλλογή, η ίδια σταθερά έλεγε *«υλικό του
 * κατόχου»* σε **6 στις 7** αγγελίες. ⚠️ **Καμία νέα παράμετρος**: η `authorship` ήταν
 * **ήδη εδώ**, μέσα στο `listing` που αυτή η συνάρτηση δέχεται ολόκληρο.
 *
 * 🔑 **Ο ΛΟΓΟΣ ΠΟΥ Η ΕΠΙΛΟΓΗ ΓΙΝΕΤΑΙ ΤΗ ΣΤΙΓΜΗ ΤΗΣ ΠΡΟΒΟΛΗΣ**: το `galleryAlt` **παγώνει**
 * μέσα στο δημοσιευμένο έγγραφο, ενώ η ορατή σημείωση από κάτω υπολογίζεται στην
 * **απόδοση** από την `authorship` του **ίδιου** εγγράφου. Δύο χρόνοι, **μία** πηγή ⇒ οι
 * δύο προτάσεις **δεν μπορούν** να διαφωνήσουν χωρίς το έγγραφο να είναι ασυνεπές με τον
 * εαυτό του — πράγμα που η άγκυρα ρωτά ρητά.
 *
 * ⚠️ **Η σειρά ταξιδεύει αυτούσια** από τη συμφιλίωση, που την πήρε αυτούσια από την
 * επιλογή του κατόχου *(Α2.1)*. Καμία ταξινόμηση σε κανένα από τα τρία σημεία — και ο
 * βρόχος τη διατηρεί για τον ίδιο λόγο που τη διατηρούσαν τα δύο `filter`.
 */
export function withPublishedGallery(
  listing: PublicListing,
  images: readonly ProjectedShelfImage[],
): PublicListing {
  const keys = LISTING_MATERIAL_KEYS[listing.authorship];
  const gallery: ListingImage[] = [];
  const floorplans: ListingFloorplan[] = [];

  for (const image of images) {
    const material = image.material;

    switch (material.kind) {
      case 'photo':
        gallery.push(toListingImage(image, keys.galleryAlt));
        break;

      case 'floorplan':
        // ⚠️ Το `at` έρχεται από **το υλικό**, ποτέ από ρολόι εδώ: *«πότε το έμαθε η
        //    πηγή»*, όχι *«πότε το πρόβαλα»* (ADR-841 §7 Α17.3).
        floorplans.push({
          provenance: 'declared',
          value: toListingImage(image, keys.floorplanAlt),
          at: material.at,
        });
        break;

      case 'model':
        // 🔴 **ΑΡΝΗΣΗ ΜΕ ΟΝΟΜΑ, ΚΑΙ ΕΙΝΑΙ ΑΠΑΝΤΗΣΗ — ΟΧΙ ΠΑΡΑΛΕΙΨΗ** *(ADR-845 Φ4.1)*.
        //    Η είσοδος αυτής της συνάρτησης είναι `ProjectedShelfImage`: **raster με
        //    `srcset`**, παραγόμενο **αποκλειστικά** από το raster ράφι (άγκυρα Α-1δ).
        //    Ένα μοντέλο **δεν μπορεί να είναι** τέτοιο αντικείμενο — και για να μπει
        //    στο `models[]` θα έπρεπε να **επινοηθούν** πεδία που δεν υπάρχουν *(το
        //    `sources` ανά πλάτος θα ήταν ψέμα: τα LOD ζουν ΜΕΣΑ στο GLB)*.
        // 🔑 **Το `models[]` το γράφει ΑΛΛΟΣ γραφέας, στη Φ4.2**, από άλλη είσοδο.
        // ⚠️ **Ίδιο ακριβώς ιδίωμα με το `shelfRecipe()` της Φ4.0**: απροσπέλαστο στην
        //    παραγωγή *(κανείς δεν εκπέμπει σήμερα τέτοιο υλικό σε αυτή τη διαδρομή)*,
        //    υπάρχει ως **δεύτερος φρουρός** και ως η **νόμιμη** τιμή που μπορεί να
        //    ρωτήσει η άγκυρα **χωρίς cast**.
        throw new Error(
          'withPublishedGallery: το τρισδιάστατο μοντέλο δεν περνά από τη διαδρομή των ' +
            'εικόνων — το `models[]` το γράφει ο ψήστης της Φ4.2 (ADR-845 §2.3, άγκυρα Α-2).',
        );

      default:
        return assertNeverMaterial(material);
    }
  }

  return { ...listing, gallery, floorplans };
}
