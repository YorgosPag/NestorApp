/**
 * @fileoverview **Η ΣΦΡΑΓΙΔΑ «ΠΟΤΕ ΜΠΗΚΕ ΣΤΗΝ ΑΓΟΡΑ» — γράφεται ΜΙΑ φορά, ποτέ ξανά.**
 * @related ADR-777 §8.61 · types/public-listing.ts ({@link ListedAt}) · lib/cron/cron-lease.ts
 * @module services/listings/listed-at-stamp
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΓΙΑΤΙ ΑΥΤΟ ΕΙΝΑΙ ΑΞΙΟΠΙΣΤΟΤΕΡΟ ΑΠΟ ΤΟ ΠΡΟΤΥΠΟ ΤΟΥ ΚΛΑΔΟΥ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το «Days on Market» των αμερικανικών portals είναι **χειραγωγήσιμο κατά σχεδίαση**: ο
 * μεσίτης αποσύρει την αγγελία και την ξαναδημοσιεύει, ο μετρητής μηδενίζεται, και ο
 * μηδενισμός **ρέει** προς Zillow/Redfin ως «νέα αγγελία». Το RESO Data Dictionary 1.7
 * έχει **δύο** πεδία, και **και τα δύο** έχουν διαδρομή:
 *
 * | Πεδίο RESO | Διαδρομή χειραγώγησης |
 * |---|---|
 * | `OnMarketDate` | *«η ημερομηνία που **εισήγαγε ο πράκτορας**»* — **την πληκτρολογεί άνθρωπος** |
 * | `OriginalEntryTimestamp` | αυτόματο, αλλά δεμένο στην **εγγραφή αγγελίας**: ακύρωση + επαναδημοσίευση = **νέα** εγγραφή = **νέα** σφραγίδα |
 *
 * Το αντίμετρο του κλάδου (CDOM) είναι **κατώφλι** — το CRMLS μηδενίζει αν η αγγελία
 * λείψει >30 μέρες (παλιά 90) — δηλαδή **παρακάμπτεται με αναμονή**.
 *
 * 🔑 **Η ΔΙΚΗ ΜΑΣ ΣΦΡΑΓΙΔΑ ΔΕΝΕΤΑΙ ΣΤΟ ΑΚΙΝΗΤΟ, ΟΧΙ ΣΤΗΝ ΑΓΓΕΛΙΑ.** Το
 * `properties/{id}` **επιβιώνει** της απόσυρσης: ο γραφέας της προβολής κάνει
 * `ref.delete()` στο **`public_listings`** και **μόνο** εκεί. ⇒ καμία πληκτρολόγηση,
 * καμία επαναδημιουργία, **κανένα κατώφλι να περιμένεις**. Η χειραγώγηση δεν είναι
 * «απαγορευμένη με πολιτική» — είναι **δομικά αδύνατη**, ίδιο ιδίωμα με το
 * `listing-map-shape.ts` (*«δεν υπάρχει διαδρομή από το ένα στο άλλο μέσα σε αυτό το
 * αρχείο»*).
 *
 * ⛔ **ΓΙ' ΑΥΤΟ ΑΠΟΡΡΙΦΘΗΚΕ ΤΟ ΠΡΟΦΑΝΕΣ**: *«κράτα ό,τι `listedAt` έχει ήδη η
 * προβολή»*. Μοιάζει ισοδύναμο και **δεν είναι**: η απόσυρση **σβήνει** το έγγραφο της
 * προβολής, οπότε απόσυρση + επαναδημοσίευση θα μηδένιζε τον μετρητή. Θα είχαμε
 * υλοποιήσει **ακριβώς** το σκάνδαλο που το πεδίο υπάρχει για να αποκλείσει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΜΙΑ ΠΟΛΙΤΙΚΗ, ΔΥΟ ΔΙΕΥΘΥΝΣΕΙΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Δύο συλλογές γεννούν αγγελίες (`properties` · `owner_properties`) και **δεν
 * επιτρέπεται να αποκλίνουν** στο *πότε* σφραγίζουν. Γι' αυτό η **απόφαση** ζει εδώ,
 * **μία** φορά, και ο καλών δίνει μόνο τη **διεύθυνση** — ακριβώς το ιδίωμα που το
 * `republishListing` ήδη χρησιμοποιεί για τα `resolveAgency` / `resolveMedia`.
 */

import { COLLECTIONS } from '@/config/firestore-collections';
import type { AdminFirestore } from '@/lib/api/guarded-route';
import { readListedAt } from '@/lib/listings/public-listing-schema';
import { createModuleLogger } from '@/lib/telemetry';
import type { ListedAt } from '@/types/public-listing';

const logger = createModuleLogger('ListedAtStamp');

/**
 * **Η τιμή που λέει «δεν το καταγράψαμε, και το ξέρουμε».**
 *
 * ⚠️ **ΔΕΝ είναι το `'predates-record'`**, και η διάκριση είναι σκόπιμη: εκείνο
 * σημαίνει *«ήταν ήδη στην αγορά πριν αρχίσουμε»* — **οριστικό**. Αυτό σημαίνει *«η
 * σφραγίδα απέτυχε»* — **βλάβη προς διόρθωση**. Συγχωνευμένα, ένα σπασμένο CAS θα
 * κρυβόταν μέσα στο κανονικό ιστορικό και **κανείς δεν θα το μετρούσε ποτέ**.
 */
const NOT_RECORDED: ListedAt = { kind: 'unknown', reason: 'not-recorded' };

/**
 * **Πότε μπήκε στην αγορά αυτό το ακίνητο** — διαβάζοντας ή, την πρώτη φορά, γράφοντας.
 *
 * @param current Ό,τι κουβαλά **ήδη** το έγγραφο πηγής. **Η απουσία είναι η ερώτηση**:
 *   σημαίνει *«δεν πέρασε ΠΟΤΕ από εδώ»*, δηλαδή αυτή είναι η **πρώτη** δημοσίευση.
 * @param at Η στιγμή, **ως όρισμα** — ίδιο συμβόλαιο με το `projectedAt` του γραφέα:
 *   ένα πέρασμα οφείλει να μιλά για **μία** στιγμή. Δεύτερη ανάγνωση ρολογιού εδώ θα
 *   παρήγαγε έγγραφο που λέει ότι μπήκε στην αγορά **πριν** ή **μετά** από την προβολή
 *   που το περιέχει.
 *
 * 🔑 **ΚΑΛΕΙΤΑΙ ΜΟΝΟ ΓΙΑ ΔΗΜΟΣΙΕΥΣΙΜΟ ΑΚΙΝΗΤΟ.** Η κρίση *«δημοσιεύεται;»* ανήκει στο
 * `isPubliclyListed` και **δεν ξαναγράφεται εδώ** — ένας δεύτερος κριτής θα ήταν η
 * θέση όπου τα δύο θα διαφωνούσαν, και τότε ένα ακίνητο θα αποκτούσε ημερομηνία
 * εισόδου **χωρίς ποτέ να μπει** στην αγορά.
 *
 * ⚠️ **Μηδέν επιπλέον ανάγνωση για ώριμη αγγελία.** Η συναλλαγή ανοίγει **μόνο** όταν
 * το `current` δεν φέρει σφραγίδα — δηλαδή **μία φορά στη ζωή** κάθε ακινήτου.
 *
 * ⚠️ **Δεν πετά ΠΟΤΕ** — ίδιο συμβόλαιο με τον γραφέα της προβολής: η αποτυχία της
 * σφραγίδας δεν ακυρώνει τη δημοσίευση. Χάνεται η **ημερομηνία**, όχι η αγγελία, και
 * το λέμε ({@link NOT_RECORDED}) αντί να το κρύψουμε.
 */
export async function resolveListedAt(
  adminDb: AdminFirestore,
  collectionName: string,
  docId: string,
  current: unknown,
  at: string,
): Promise<ListedAt> {
  const existing = readListedAt(current);
  if (existing) return existing;

  const ref = adminDb.collection(collectionName).doc(docId);

  try {
    return await adminDb.runTransaction<ListedAt>(async (transaction) => {
      // 🔴 **Η ΔΕΥΤΕΡΗ ΑΝΑΓΝΩΣΗ ΕΙΝΑΙ ΤΟ CAS, ΟΧΙ ΣΠΑΤΑΛΗ.** Το `current` ήρθε από
      //    έγγραφο που διαβάστηκε **έξω** από τη συναλλαγή· δύο ταυτόχρονες πρώτες
      //    δημοσιεύσεις θα έβλεπαν και οι δύο «κενό» και θα έγραφαν **διαφορετική**
      //    στιγμή. Εδώ μέσα, νικά **ένας** — και ο άλλος επιστρέφει τη **δική του**
      //    τιμή, όχι τη δική του μαντεψιά.
      const snapshot = await transaction.get(ref);
      const winner = readListedAt(snapshot.data()?.listedAt);
      if (winner) return winner;

      // 🔴 **ΤΟ ΔΙΧΤΥ ΠΟΥ ΚΑΝΕΙ ΤΗ ΣΕΙΡΑ ΤΩΝ ΠΡΑΞΕΩΝ ΑΔΙΑΦΟΡΗ** (N.7.2 #4).
      //
      //    Χωρίς αυτό, η ορθότητα θα κρεμόταν από **άνθρωπο**: την πρώτη φορά που θα
      //    ξαναδημοσιευόταν ένα ήδη δημοσιευμένο ακίνητο, η σφραγίδα θα έβλεπε «κενό»
      //    και θα έγραφε **σήμερα** — δηλαδή θα γεννούσε ακριβώς την ψεύτικη ιστορία
      //    που το πεδίο υπάρχει για να αποκλείσει, εκτός αν κάποιος είχε θυμηθεί να
      //    τρέξει πρώτα τη μετανάστευση.
      //
      // 🔑 **Η ΕΡΩΤΗΣΗ ΕΙΝΑΙ ΑΚΡΙΒΗΣ, ΟΧΙ ΕΥΡΕΤΙΚΗ**: *«υπάρχει ΗΔΗ δημόσια αγγελία
      //    γι' αυτό το ακίνητο;»*. Ο γραφέας γράφει την προβολή **μετά** από εδώ, άρα
      //    η ύπαρξή της σημαίνει **προηγούμενη** δημοσίευση — δηλαδή το ακίνητο ήταν
      //    στην αγορά πριν αρχίσουμε να καταγράφουμε, που είναι κατά γράμμα το
      //    `'predates-record'`. Καμία μαντεψιά, κανένα κατώφλι ημερομηνίας.
      //
      // ⚠️ **Κοστίζει ΜΙΑ ανάγνωση, μία φορά στη ζωή κάθε ακινήτου** — μόνο στη
      //    διαδρομή όπου η σφραγίδα λείπει ούτως ή άλλως.
      const published = await transaction.get(
        adminDb.collection(COLLECTIONS.PUBLIC_LISTINGS).doc(docId),
      );

      const stamped: ListedAt = published.exists
        ? { kind: 'unknown', reason: 'predates-record' }
        : { kind: 'known', at };

      // ⚠️ **`update`, ΟΧΙ `set`** — δεν συνθέτουμε έγγραφο, γράφουμε **ένα** πεδίο σε
      //    έγγραφο που ήδη υπάρχει. Ένα `set` με merge θα **δημιουργούσε** έγγραφο για
      //    ακίνητο που διαγράφηκε στη μέση του περάσματος.
      transaction.update(ref, { listedAt: stamped });
      return stamped;
    });
  } catch (error) {
    logger.error('Η σφραγίδα εισόδου στην αγορά ΔΕΝ γράφτηκε — η αγγελία δημοσιεύεται κανονικά', {
      collection: collectionName,
      docId,
      error: error instanceof Error ? error.message : String(error),
    });
    return NOT_RECORDED;
  }
}
