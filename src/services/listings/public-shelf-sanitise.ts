/**
 * @fileoverview **Ο ΚΑΘΑΡΙΣΤΗΣ** — τα bytes που φεύγουν στον κόσμο (ADR-841 §7 Α12.7).
 * @related ADR-841 §7 Α12.5 · Α12.7 · Α5 (`locationDisclosure`) · public-shelf.service
 * @module services/listings/public-shelf-sanitise
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ ΕΙΝΑΙ ΑΣΦΑΛΕΙΑ, ΟΧΙ ΜΟΡΦΟΠΟΙΗΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Φωτογραφία ακινήτου κουβαλά **συντεταγμένες**. Δημοσιευμένη ωμή, **ακυρώνει** το
 * `locationDisclosure: 'declined'` της **Α5**: η πλατφόρμα αποκαλύπτει ό,τι ο κάτοχος
 * **αρνήθηκε** να πει. Και δεν είναι θεωρητικό — υπάρχουν καταγεγραμμένες διαρρήξεις
 * σε ακίνητα εντοπισμένα από GPS σε φωτογραφίες αγγελιών.
 *
 * 🏆 **ΚΑΙ ΓΙ' ΑΥΤΟ Ο ΚΑΘΑΡΙΣΜΟΣ ΔΕΝ ΕΙΝΑΙ ΒΗΜΑ — ΕΙΝΑΙ Η ΓΕΝΝΗΣΗ ΤΗΣ ΔΙΕΥΘΥΝΣΗΣ.**
 * Οι μεγάλες πλατφόρμες αφαιρούν μεταδεδομένα ως **βήμα αγωγού**, και η βιβλιογραφία
 * το λέει αναξιόπιστο *(«their algorithms are not foolproof»)*. Εδώ το κλειδί του
 * ραφιού είναι το **sha256 της εξόδου αυτού του αρχείου** ⇒ *χωρίς καθαρισμό δεν
 * υπάρχει διεύθυνση, χωρίς διεύθυνση δεν υπάρχει δημοσίευση*. Ένας μελλοντικός
 * γραφέας που θα «ξεχνούσε» τον καθαρισμό δεν θα δημοσίευε ωμή φωτογραφία —
 * **δεν θα είχε κλειδί**.
 *
 * ⚠️ **SERVER-ONLY**: το `sharp` είναι εγγενές module. Καμία εισαγωγή από πελάτη.
 */

import sharp from 'sharp';

import { createModuleLogger } from '@/lib/telemetry';
import type { PublicShelfExtension } from '@/services/upload/utils/storage-path-public-shelf';
import type { ShelfEncoding } from '@/services/upload/utils/public-shelf-kinds';

const logger = createModuleLogger('public-shelf-sanitise');

// ---------------------------------------------------------------------------
// Παράμετροι — γραμμένες μία φορά
// ---------------------------------------------------------------------------

/** Ο τύπος περιεχομένου που δηλώνει ο γραφέας στο αντικείμενο του ραφιού. */
export const PUBLIC_SHELF_IMAGE_CONTENT_TYPE = 'image/webp';

/**
 * **Πόσο σκληρά ψάχνει ο κωδικοποιητής** — 0 (γρήγορο) ως 6 (μικρότερο αρχείο).
 *
 * 🔑 **Ανεβασμένο από την προεπιλογή 4**, και το τίμημα το πληρώνει **ο διακομιστής μία
 * φορά** ενώ το όφελος το εισπράττει **κάθε επισκέπτης**: τα bytes είναι
 * content-addressed, άρα κωδικοποιούνται **μόνο όταν αλλάξουν** *(η γρήγορη διαδρομή του
 * γραφέα δεν αποκωδικοποιεί καν)*. Ασυμμετρία που κάνει το `6` προφανές.
 */
const PUBLIC_SHELF_ENCODER_EFFORT = 6;

// ---------------------------------------------------------------------------
// Τύποι
// ---------------------------------------------------------------------------

/** Ό,τι παράγει ο καθαριστής — **αυτά** τα bytes δημοσιεύονται, κανένα άλλο. */
export interface SanitisedShelfAsset {
  /** Τα καθαρισμένα bytes. Το sha256 **τους** γίνεται το κλειδί. */
  readonly bytes: Buffer;
  readonly ext: PublicShelfExtension;
  readonly contentType: string;
  readonly width: number;
  readonly height: number;
}

/** Γιατί ένα αρχείο **δεν** μπόρεσε να γίνει δημοσιεύσιμο. */
export type ShelfSanitiseFailure = 'undecodable' | 'empty' | 'too-large-to-decode';

export class ShelfSanitiseError extends Error {
  constructor(readonly failure: ShelfSanitiseFailure, message: string) {
    super(message);
    this.name = 'ShelfSanitiseError';
  }
}

// ---------------------------------------------------------------------------
// Ο καθαριστής
// ---------------------------------------------------------------------------


/**
 * **Ωμή εικόνα → ΟΛΑ τα δημοσιεύσιμα παράγωγα**, ένα ανά πλάτος της κωδικοποίησης.
 *
 * 🔴 **Η ΚΩΔΙΚΟΠΟΙΗΣΗ ΕΡΧΕΤΑΙ ΑΠΟ ΤΟΝ ΚΑΛΟΥΝΤΑ, ΚΑΙ ΕΙΝΑΙ ΤΟ ΣΤΑΔΙΟ 2 ΟΛΟΚΛΗΡΟ.** Ως
 * την Α21 τα πλάτη και η ποιότητα ήταν **σταθερές αυτού του αρχείου** — σωστό όσο
 * υπήρχε **ένα** είδος πράγματος. Με το σήμα του επαγγελματία η ίδια σταθερά θα σήμαινε
 * ότι ο επισκέπτης κατεβάζει παράγωγο **2560px** για εικόνα που ζωγραφίζεται **44px**,
 * κωδικοποιημένη με ποιότητα ρυθμισμένη για **φωτογραφία**. Δύο απαντήσεις σε ερώτηση
 * που έχει **μία** ανά είδος ⇒ η ερώτηση ανήκει στον {@link ShelfEncoding}.
 *
 * 🔑 **ΜΙΑ αποκωδικοποίηση, Ν κωδικοποιήσεις.** Το `clone()` του `sharp` μοιράζεται την
 * **ίδια** αποκωδικοποιημένη εικόνα σε πολλούς αγωγούς εξόδου — τρεις χωριστές
 * `sharp(input)` θα αποκωδικοποιούσαν το ίδιο JPEG **τρεις** φορές, που είναι το
 * ακριβότερο βήμα ολόκληρης της διαδρομής.
 *
 * ⚠️ **Το `.rotate()` μπαίνει ΠΡΙΝ το `clone()`**, ώστε ο προσανατολισμός του EXIF να
 * εφαρμοστεί **μία** φορά και να τον κληρονομήσουν όλα τα παράγωγα. Ένα παράγωγο
 * γυρισμένο στο πλάι δίπλα σε δύο σωστά θα ήταν χειρότερο από τρία λάθος.
 *
 * 🔑 **Ταυτόσημα παράγωγα ΔΕΝ φιλτράρονται εδώ** — τα φιλτράρει η **διεύθυνσή** τους:
 * ίδια bytes ⇒ ίδιο sha256 ⇒ ίδιο κλειδί. Ένα `distinct()` εδώ θα ήταν δεύτερος κριτής
 * ταυτότητας δίπλα στο content-addressing, ελεύθερος να διαφωνήσει μαζί του.
 *
 * @throws {ShelfSanitiseError} όταν τα bytes δεν είναι αποκωδικοποιήσιμη εικόνα.
 */
export async function sanitiseImageVariants(
  input: Buffer,
  encoding: ShelfEncoding,
): Promise<readonly SanitisedShelfAsset[]> {
  return decodableOrThrow(input, (decoded) =>
    Promise.all(
      encoding.widths.map((width) => encodeOne(decoded.clone(), width, encoding)),
    ),
  );
}

/**
 * **Ο ΕΝΑΣ ΦΡΟΥΡΟΣ ΤΗΣ ΑΠΟΚΩΔΙΚΟΠΟΙΗΣΗΣ** — κενό, στραμμένο, ή ονομασμένη αποτυχία.
 *
 * 🔑 **Εξήχθη επειδή το ΜΕΤΡΗΣΕ πύλη, όχι επειδή φάνηκε ωραίο** (N.18 / CHECK 3.28): οι
 * δύο δημόσιες είσοδοι είχαν **ταυτόσημο** έλεγχο κενού και **ταυτόσημο** `catch` — 10
 * γραμμές δίδυμα μέσα στο ίδιο αρχείο, δηλαδή ακριβώς το σχήμα *«κεντρικοποιείς το Α,
 * γράφεις το Β ως δίδυμο»*.
 *
 * ⚠️ **Το `.rotate()` μπαίνει ΕΔΩ, μία φορά.** Είναι απόφαση του **πρωτοτύπου** — αν
 * ζούσε στους δύο καλούντες, ο ένας θα μπορούσε κάποτε να το χάσει και να δημοσιεύσει
 * φωτογραφίες κινητού **γυρισμένες στο πλάι**.
 */
async function decodableOrThrow<T>(
  input: Buffer,
  produce: (decoded: sharp.Sharp) => Promise<T>,
): Promise<T> {
  if (input.length === 0) {
    throw new ShelfSanitiseError('empty', 'Κενά bytes — δεν υπάρχει εικόνα να καθαριστεί');
  }

  try {
    return await produce(sharp(input, { failOn: 'error' }).rotate());
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    logger.warn('Το αρχείο δεν είναι αποκωδικοποιήσιμη εικόνα — δεν δημοσιεύεται', {
      bytes: input.length,
      error: message,
    });
    throw new ShelfSanitiseError('undecodable', message);
  }
}

/**
 * **Ένας αγωγός `sharp` → ένα δημοσιεύσιμο παράγωγο.** Ο κοινός πυρήνας των δύο εισόδων.
 *
 * ⚠️ **Δέχεται αγωγό ΗΔΗ στραμμένο** και δεν ξανακαλεί `.rotate()`: η στροφή είναι
 * απόφαση του **πρωτοτύπου**, όχι του παραγώγου, και πρέπει να συμβεί **μία** φορά πριν
 * τον κλώνο — αλλιώς κάθε παράγωγο θα την ξαναέπαιρνε από μεταδεδομένα που έχουν ήδη
 * καταναλωθεί.
 */
async function encodeOne(
  pipeline: sharp.Sharp,
  maxEdgePx: number,
  encoding: ShelfEncoding,
): Promise<SanitisedShelfAsset> {
  const { data, info } = await pipeline
    .resize({
      width: maxEdgePx,
      height: maxEdgePx,
      fit: 'inside',
      withoutEnlargement: true,
    })
    .webp(webpOptions(encoding))
    .toBuffer({ resolveWithObject: true });

  return {
    bytes: data,
    ext: 'webp',
    contentType: PUBLIC_SHELF_IMAGE_CONTENT_TYPE,
    width: info.width,
    height: info.height,
  };
}

/**
 * **Η κωδικοποίηση, στη γλώσσα του `sharp`** — η **μία** μετάφραση.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΤΟ ΣΗΜΑ ΘΕΛΕΙ `lossless` ΚΑΙ ΟΧΙ ΑΠΛΩΣ «ΥΨΗΛΟΤΕΡΟ q»
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `cwebp` της Google δίνει **χωριστά preset** για `photo` και για `icon`/`drawing`
 * ακριβώς επειδή τα δύο υλικά έχουν αντίθετη στατιστική: μια φωτογραφία είναι **συνεχείς
 * βαθμίδες** *(όπου η lossy πετά ό,τι δεν βλέπει το μάτι)*, ενώ ένα λογότυπο είναι
 * **επίπεδες περιοχές + αιχμηρές ακμές** — δηλαδή **μόνο** οι μεταβάσεις που η lossy
 * θολώνει. Ένα `q95` θα ήταν «λιγότερο χάλια», όχι σωστό.
 *
 * 🔑 **Και σε 256px το lossless δεν έχει κόστος που να αξίζει συζήτηση** — το επιχείρημα
 * υπέρ της lossy ζει σε μεγέθη γκαλερί, όχι σε σήμα μεγέθους νυχιού.
 *
 * ⚠️ **Καμία ρύθμιση διαφάνειας εδώ, ΕΠΙΤΗΔΕΣ.** Το WebP κρατά το κανάλι alpha και στους
 * δύο τρόπους *(`alphaQuality` = 100 από προεπιλογή)*, οπότε ένα λογότυπο με διάφανο
 * φόντο **επιβιώνει αυτούσιο** και κάθεται σωστά σε **δύο θέματα**. Ψημένη πλάκα φόντου
 * θα ήταν απόφαση για **ένα** θέμα και **λάθος** στο άλλο.
 *
 * 🔑 **Το `exact` μένει στην προεπιλογή του (`false`) και είναι όφελος ΑΣΦΑΛΕΙΑΣ**: τα
 * RGB των **πλήρως διάφανων** pixel δεν διατηρούνται, άρα δεν υπάρχει πού να επιβιώσει
 * δεδομένο μέσα σε αόρατη περιοχή.
 */
function webpOptions(encoding: ShelfEncoding): sharp.WebpOptions {
  const base = { preset: encoding.preset, effort: PUBLIC_SHELF_ENCODER_EFFORT } as const;

  return encoding.quality === 'lossless'
    ? { ...base, lossless: true }
    : { ...base, quality: encoding.quality };
}
