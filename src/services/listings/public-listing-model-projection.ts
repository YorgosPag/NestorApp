/**
 * @fileoverview 🏆 **ΤΟ ΚΟΥΤΙ ΤΩΝ ΜΟΝΤΕΛΩΝ ΠΑΥΕΙ ΝΑ ΕΙΝΑΙ ΚΕΝΟ** — ο γραφέας του `models[]`.
 * @related ADR-845 §7.3 · §8 (Α-7) · ADR-841 §7 Α10 · Α11 · Α15 · ADR-842 §8 #5
 * @module services/listings/public-listing-model-projection
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Ο **ΑΛΛΟΣ** ΓΡΑΦΕΑΣ — ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΚΛΑΔΟΣ ΤΟΥ `withPublishedGallery`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο `public-listing-gallery-projection` το γράφει ρητά στον `case 'model'`, και **παραμένει
 * αληθές**: η είσοδός του είναι `ProjectedShelfImage` — **raster με `srcset`**, παραγόμενο
 * αποκλειστικά από το raster ράφι *(άγκυρα Α-1δ)*. Ένα μοντέλο **δεν μπορεί να είναι** τέτοιο
 * αντικείμενο· για να μπει εκεί θα έπρεπε να **επινοηθούν** `width`/`height`/`sources`.
 *
 * ⇒ *«Το `models[]` το γράφει **ΑΛΛΟΣ** γραφέας»* — αυτός. **Άλλη είσοδος, άλλο κουτί, ίδια
 * εγγύηση**: χτίζεται **ΑΠΟ ΤΗΝ ΑΝΑΦΟΡΑ** του ραφιού, ποτέ από τις πηγές.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🎯 Η ΑΓΚΥΡΑ **Α-7**, ΚΑΙ Η ΜΙΣΗ ΤΗΣ ΖΕΙ ΣΤΟΝ ΤΥΠΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * > **«Μπορεί να γραφτεί `models[]` με URL που ΔΕΝ πέρασε από τον ψήστη;»**
 *
 * **Όχι, και είναι δομικό.** Αυτή η συνάρτηση δέχεται **μόνο** {@link ProjectedShelfModel}, που
 * παράγεται **αποκλειστικά** από το `PublicShelfModelReport.published` — και εκεί το `url`
 * γεννιέται από το `contentAddress` των bytes **που παρήγαγε ο ψήστης**. Το γραμμένο ιδίωμα του
 * ραφιού, αυτούσιο: *«το κλειδί είναι το sha256 των καθαρισμένων bytes ⇒ **χωρίς καθαρισμό δεν
 * υπάρχει διεύθυνση**»*.
 *
 * ⛔ **ΓΙ' ΑΥΤΟ ΔΕΝ ΔΕΧΕΤΑΙ `string[]` ΑΠΟ URL**, όσο κι αν θα ήταν βολικό: ένας τύπος που
 * δέχεται *οποιοδήποτε* URL είναι τύπος που **επιτρέπει** τη διαφήμιση μοντέλου που δεν κάθεται
 * στον κάδο. Η βολή θα ήταν η ίδια· η **εγγύηση** θα είχε φύγει.
 *
 * ⛔ **ΚΑΘΑΡΟ MODULE** — καμία I/O, κανένα `firebase-admin`, κανένα WASM. Ίδιος λόγος με το
 * `public-listing-gallery-projection`: η **κρίση** δοκιμάζεται χωρίς κάδο.
 */

import { LISTING_MATERIAL_KEYS } from '@/lib/listings/listing-authorship';
import type { ListingModel, PublicListing } from '@/types/public-listing';

/**
 * 🔴 **Ο ΔΕΙΚΤΗΣ ΠΗΓΗΣ ΓΙΑ ΜΟΝΤΕΛΑ ΨΗΜΕΝΑ ΑΠΟ ΤΟ BIM.**
 *
 * ⚠️ **ΚΑΤΗΓΟΡΙΑ ΠΗΓΗΣ, ΟΧΙ ΤΑΥΤΟΤΗΤΑ ΣΧΕΔΙΟΥ — και είναι ΑΝΤΙΓΡΑΦΗ ΓΡΑΜΜΕΝΗΣ ΑΠΟΦΑΣΗΣ**, όχι
 * νέα κρίση. Το αδελφό του `LEVELS_MODEL_SOURCE_REF = 'property-model:levels'`
 * *(`public-listing-attributes.ts`)* το εξηγεί, και το **ADR-842 §8 #5** το δεσμεύει: *«η
 * ταυτότητα του σχεδίου ανήκει στη **Φ6**, και θα ήταν **επινόηση** να οριστεί εδώ, πριν
 * υπάρξει ο παραγωγός»*. Μια δομημένη ταυτότητα σήμερα θα ήταν **τρίτο λεξιλόγιο** ταυτότητας
 * σχεδίου.
 *
 * 🔑 **Και δεν δημοσιεύει κανένα αναγνωριστικό**: ένα `bldg_…` ή ένα ιδιωτικό μονοπάτι θα
 * ταξίδευε **ιδιωτικό κλειδί σε ανώνυμο επισκέπτη**, για μηδενικό όφελος — το ίδιο μάθημα με το
 * χασαρισμένο `sourceRef` του ραφιού.
 */
export const LISTING_MODEL_SOURCE_REF = 'property-model:glb';

/**
 * **Ένα δημοσιευμένο μοντέλο, όπως το μαθαίνει ο γραφέας από το ράφι.**
 *
 * ⚠️ **Δομικός τύπος και ΟΧΙ ο τύπος της υπηρεσίας** — ταυτόσημη σύμβαση με το
 * `ProjectedShelfImage`: το `public-shelf-model.service` σέρνει `firebase-admin` **και** WASM
 * *(`meshoptimizer`, `gltf-validator`)*, και αυτό το αρχείο δηλώνει ότι είναι **καθαρό**. Η μία
 * γραμμή μετάφρασης στον ενορχηστρωτή είναι φθηνότερη από μια εξάρτηση που θα έκανε την προβολή
 * αδύνατη να δοκιμαστεί.
 *
 * 🔑 **ΔΥΟ ΠΕΔΙΑ, ΚΑΙ ΤΑ ΔΥΟ ΑΠΑΡΑΙΤΗΤΑ**: το `url` *(τι δείχνουμε)* και το `at` *(πότε το
 * έμαθε η πηγή)*. Το δεύτερο **δεν** είναι διακοσμητικό — το `SourcedAttribute` το **απαιτεί**,
 * και ο μόνος εναλλακτικός μάντης θα ήταν το **ρολόι του διακομιστή**, που το σκέλος της
 * κάτοψης απορρίπτει γραπτώς.
 */
export interface ProjectedShelfModel {
  readonly url: string;
  /** ISO στιγμή — *«πότε το έμαθε **η πηγή**»*, ποτέ *«πότε το πρόβαλα»* (Α17.3). */
  readonly at: string;
}

/**
 * **Η αγγελία με τα μοντέλα της δεμένα** — ο αδελφός του `withPublishedGallery`.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΓΙΑΤΙ `measured`, ΚΑΙ ΤΙ ΕΠΙΦΕΡΕΙ ΑΥΤΟ ΠΟΥ ΔΕΝ ΕΙΧΕ ΟΝΟΜΑΣΤΕΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `attribute-provenance` ορίζει: *«`measured` — **υπολογισμένο από DXF/BIM**. Βεβαιότητα,
 * όχι πρόβλεψη»*. Το μοντέλο του εργολάβου **είναι** ακριβώς αυτό — ψημένο από τη σκηνή του
 * DXF viewer *(§7.3, Φ4.2)*. Το μοντέλο του **αρχιτέκτονα ιδιώτη** θα είναι `declared` *(Φ4β)*.
 *
 * 🔴 **ΚΑΙ ΤΟ ΣΚΕΛΟΣ `measured` ΑΠΑΙΤΕΙ `sourceRef` — ΤΟ ΕΠΑΚΟΛΟΥΘΟ ΠΟΥ ΔΕΝ ΗΤΑΝ ΓΡΑΜΜΕΝΟ.**
 * Δεν είναι επιλογή αυτής της συνάρτησης: ο τύπος **δεν μεταγλωττίζεται** χωρίς αυτό. Η
 * απάντηση είναι το {@link LISTING_MODEL_SOURCE_REF} — δες εκεί γιατί είναι **κατηγορία**.
 *
 * ⚠️ **Η ΠΡΟΕΛΕΥΣΗ ΕΙΝΑΙ ΟΡΘΟΓΩΝΙΑ ΠΡΟΣ ΤΗ ΣΗΜΑΝΣΗ Α11, ΚΑΙ Ο ΠΕΙΡΑΣΜΟΣ ΝΑ ΤΙΣ ΔΕΣΕΙΣ ΕΙΝΑΙ
 * ΛΑΘΟΣ.** Το `proposal` *(«μελέτη»)* μοιάζει «λιγότερο αληθινό» από το `as-built`, οπότε
 * μοιάζει να θέλει `declared`. Αλλά οι δύο απαντούν **διαφορετικές** ερωτήσεις: η προέλευση λέει
 * *«από πού βγήκε ο αριθμός»* *(από BIM — και στις δύο περιπτώσεις)*, η **Α11** λέει *«χτισμένο
 * ή μελέτη»*. Δένοντάς τες, το **ίδιο ακριβώς αρχείο** θα άλλαζε **βαθμίδα αξιοπιστίας** επειδή
 * κάποιος άλλαξε **ετικέτα κατάστασης** — δύο αλήθειες για ένα πράγμα.
 *
 * 🔑 **Το `altKey` διαλέγεται από την `authorship` ΤΗΣ ΙΔΙΑΣ ΑΓΓΕΛΙΑΣ** *(Α15)*, με τον
 * **ίδιο** μηχανισμό που το κάνει ο `withPublishedGallery`: το `LISTING_MATERIAL_KEYS` είναι
 * `Record<ListingAuthorship, …>`, άρα **δεν τυπώνεται** αν λείψει σκέλος. ⚠️ **Καμία νέα
 * παράμετρος** — η `authorship` ήταν **ήδη εδώ**, μέσα στο `listing`.
 *
 * ⛔ **ΤΟ ΚΛΕΙΔΙ ΥΠΑΡΧΕΙ ΗΔΗ σε `el` ΚΑΙ `en`** *(`detail.media.modelAlt.*`)*, και το ταβάνι του
 * `search-results` ξανασφραγίστηκε 15.200 → 15.400 στη Φ4.2α **με τον όρο ότι θα υπάρξει
 * παραγωγός που το αποδίδει**. Αυτή η συνάρτηση **είναι** ο όρος. ⚠️ Περιθώριο **~74 bytes** —
 * μην προσθέσεις κλειδί εδώ χωρίς να ξαναμετρήσεις.
 *
 * ⚠️ **Η σειρά ταξιδεύει αυτούσια** από τη συμφιλίωση, που την πήρε αυτούσια από την επιλογή
 * του ανθρώπου *(Α2.1)*. Καμία ταξινόμηση — ίδιος κανόνας με τη συλλογή.
 */
export function withPublishedModels(
  listing: PublicListing,
  models: readonly ProjectedShelfModel[],
): PublicListing {
  const altKey = LISTING_MATERIAL_KEYS[listing.authorship].modelAlt;

  const published: readonly ListingModel[] = models.map((model) => ({
    provenance: 'measured',
    value: { url: model.url, altKey },
    at: model.at,
    sourceRef: LISTING_MODEL_SOURCE_REF,
  }));

  return { ...listing, models: published };
}
