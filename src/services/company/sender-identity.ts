/**
 * 🔴 **ΠΡΑΓΜΑΤΙΚΟ symbol, ΜΗ ΕΞΑΓΟΜΕΝΟ — και τα δύο είναι απαραίτητα.**
 *
 * *«Πραγματικό»*: ένα `declare const … : unique symbol` είναι **μόνο τύπος** και σβήνεται
 * στη μεταγλώττιση. *«Μη εξαγόμενο»*: όποιος δεν βλέπει το κλειδί **δεν μπορεί** να γράψει
 * τιμή που να ικανοποιεί τον τύπο. Ίδιο ιδίωμα με το `BrokerageAuthority` (ADR-824 §6) —
 * **δεν εφευρίσκεται δεύτερη παραλλαγή**.
 */
const SENDER_HEADER: unique symbol = Symbol('SenderHeader');

/**
 * **Η γραμμή `From:`, ΚΑΘΑΡΙΣΜΕΝΗ ΚΑΙ ΕΙΣΑΓΩΓΙΚΟΠΟΙΗΜΕΝΗ** — τύπος που **μόνο αυτό το
 * αρχείο** μπορεί να κατασκευάσει.
 *
 * 🏆 **ΠΡΟΛΗΨΗ ΑΝΤΙ ΑΝΙΧΝΕΥΣΗΣ, ΚΑΙ ΕΙΝΑΙ ΤΕΚΜΗΡΙΩΜΕΝΗ ΠΡΑΚΤΙΚΗ** (έρευνα 2026-09-14): το
 * **Flow** συνιστά **ρητά** τα opaque types ακριβώς για *«callers must obtain a value only
 * through a constructor function the defining module controls — π.χ. IDs, sanitized
 * strings»*· το **Rust newtype** είναι το ίδιο μοτίβο με smart constructor· το **Effect**
 * το τυποποιεί ως `Brand`. Μια διαδρομή που ξεχνά να ρωτήσει τη ρίζα **δεν
 * μεταγλωττίζεται** — δεν χρειάζεται πύλη να το πιάσει, ούτε άνθρωπος να το θυμηθεί.
 *
 * ⛔ **ΤΙ ΔΕΝ ΠΙΑΝΕΙ, ΔΗΛΩΜΕΝΟ** *(το ίδιο η έρευνα, με υψηλή βεβαιότητα)*:
 * 1. `as unknown as SenderHeader` — πλήρης παράκαμψη. Γίνεται όμως **ορατή σε αναθεώρηση**
 *    αντί για σιωπηλά απούσα κλήση.
 * 2. **Παράλληλη πηγή που ΔΕΝ αγγίζει ποτέ τον τύπο** — κάποιος διαβάζει `process.env`
 *    αλλού και επιστρέφει σκέτο `string`. Ο τύπος φράζει το *πέρασμα*, όχι τη *γέννηση*.
 * 3. Τίποτα σε χρόνο εκτέλεσης (μηδενικό κόστος ⇒ μηδενική επιβολή).
 *
 * ⇒ Γι' αυτό ο τύπος **δεν είναι μόνος του**: το *residue* (#2) το πιάνει η πύλη AST, και
 * η σύσταση «τύπος **και** lint μαζί» είναι ρητή του **typescript-eslint** — *«ο τύπος
 * αφήνει residue που δομικά δεν μπορεί να πιάσει, και καταλήγει στην παραγωγή»*.
 */
export type SenderHeader = string & { readonly [SENDER_HEADER]: true };

/** Από πού ήρθε η ταυτότητα. **Ονομασμένο, ποτέ boolean** — σχήμα του φακέλου. */
export type SenderIdentitySource = 'tenant' | 'environment' | 'platform';

/**
 * Ό,τι μπορεί να δηλώσει ο **ένοικος** για τον εαυτό του.
 *
 * ⚠️ **Μερικό επίτηδες**: ένας ένοικος μπορεί να έχει όνομα χωρίς δική του διεύθυνση
 * (στέλνει από το domain της πλατφόρμας με δικό του όνομα) — η συνηθέστερη μορφή
 * πολυ-ενοικίας πριν το BYOD domain.
 */
export interface TenantSenderOverride {
  readonly name?: string;
  readonly address?: string;
}

/** **Ποιος υπογράφει** — ένα ζεύγος, ποτέ δύο ανεξάρτητες τιμές. */
export interface SenderIdentity {
  /** Το όνομα εμφάνισης, όπως το διαβάζει άνθρωπος στα εισερχόμενα. */
  readonly name: string;
  /** Η διεύθυνση του φακέλου — αυτή κρίνει την ευθυγράμμιση SPF/DKIM/DMARC. */
  readonly address: string;
  /** Ποιο σκαλί της αλυσίδας απάντησε. Υπάρχει για να **φαίνεται**, όχι για λογική. */
  readonly source: SenderIdentitySource;
}

function firstNonEmpty(...values: ReadonlyArray<string | undefined>): string | undefined {
  for (const value of values) {
    if (typeof value === 'string' && value.trim().length > 0) return value.trim();
  }
  return undefined;
}

/**
 * **Ποιος υπογράφει αυτό το μήνυμα;**
 *
 * Αλυσίδα: **ένοικος** *(⏳ Στάδιο 2 — κανείς δεν την περνά σήμερα)* → **περιβάλλον**
 * (`FROM_NAME` / `FROM_EMAIL`) → **πλατφόρμα** ({@link PRODUCT_NAME} +
 * {@link PLATFORM_SENDER_ADDRESS}).
 *
 * ⚠️ **Το όνομα και η διεύθυνση κρίνονται ΧΩΡΙΣΤΑ, και το `source` λέει το ισχυρότερο
 * σκαλί που απάντησε.** Ένοικος με όνομα αλλά χωρίς διεύθυνση παίρνει `'tenant'`: η
 * απάντηση στο «ποιος υπογράφει;» είναι ο ένοικος, ακόμη κι αν ο φάκελος είναι δικός μας.
 *
 * ⚠️ **Το περιβάλλον διαβάζεται σε ΚΑΘΕ κλήση, όχι σε module scope.** Σταθερή τιμή θα
 * διάβαζε το περιβάλλον **μία φορά, τη στιγμή της εισαγωγής** — ίδιο ακριβώς σχήμα «η
 * ρύθμιση λέει ψέματα» που διόρθωσε το `defaultEmailChain()` (ADR-777 §8.26).
 */
export function resolveSenderIdentity(tenant?: TenantSenderOverride): SenderIdentity {
  const envName = firstNonEmpty(process.env.FROM_NAME);
  const envAddress = firstNonEmpty(process.env.FROM_EMAIL);
  const tenantName = firstNonEmpty(tenant?.name);
  const tenantAddress = firstNonEmpty(tenant?.address);

  const name = firstNonEmpty(tenantName, envName) ?? PRODUCT_NAME;
  const address = firstNonEmpty(tenantAddress, envAddress) ?? PLATFORM_SENDER_ADDRESS;

  const source: SenderIdentitySource = tenantName || tenantAddress
    ? 'tenant'
    : envName || envAddress
      ? 'environment'
      : 'platform';

  return { name, address, source };
}

/**
 * 🔴 **ΤΑ ΟΝΟΜΑΤΑ ΕΜΦΑΝΙΣΗΣ ΕΡΧΟΝΤΑΙ ΚΑΙ ΑΠΟ ΧΡΗΣΤΗ — ΚΑΙ ΚΑΝΕΙΣ ΔΕΝ ΤΑ ΦΥΛΑΓΕ.**
 *
 * Το `email.service.ts` περνά `senderName` **από φόρμα κοινοποίησης** κατευθείαν στη
 * γραμμή `From:`. Ο υπάρχων φρουρός έγχυσης (`safeHeaderEntries`) φυλάει **μόνο** τις
 * *custom* κεφαλίδες — το `from` **δεν** περνούσε από πουθενά. Μια τιμή με `\r\n` μέσα
 * της **γράφει νέα κεφαλίδα** (π.χ. `Bcc:` που κανείς δεν έβαλε).
 *
 * ⚠️ **ΚΑΘΑΡΙΖΕΙ, δεν πετά** — αντίθετα από το `safeHeaderEntries`, και επίτηδες: εκεί
 * η άκυρη τιμή είναι **λάθος προγραμματιστή** (token/διεύθυνση που φτιάχνουμε εμείς)·
 * εδώ είναι **είσοδος ανθρώπου**, και μια εξαίρεση θα ακύρωνε την κοινοποίηση αντί να
 * τη διορθώσει.
 *
 * 🔴 **ΟΙ ΧΑΡΑΚΤΗΡΕΣ ΕΛΕΓΧΟΥ ΓΡΑΦΟΝΤΑΙ ΜΕ ΔΙΑΦΥΓΕΣ, ΠΟΤΕ ΚΥΡΙΟΛΕΚΤΙΚΑ — ΜΕΤΡΗΜΕΝΟ.**
 * Η πρώτη γραφή αυτής της γραμμής τους είχε **κυριολεκτικά**. Λειτουργούσε· ήταν όμως
 * **αόρατη**, και ο ίδιος ο συγγραφέας της τη διάβασε λίγα λεπτά αργότερα ως `[ -]`
 * (κενό–παύλα) και πήγε να τη «διορθώσει» — δηλαδή να σβήσει τον φρουρό **νομίζοντας
 * ότι τον φτιάχνει**. Αόρατος κώδικας δεν είναι σφάλμα· είναι **παγίδα για τον
 * επόμενο**, και εδώ η παγίδα έπιασε τον συγγραφέα. Ίδια οικογένεια με το `\b` μέσα σε
 * template literal που γέννησε **σπασμένη** την πύλη 3.73.
 */
function sanitizeDisplayName(name: string): string {
  // eslint-disable-next-line no-control-regex
  return name.replace(/[\u0000-\u001F\u007F]/g, ' ').replace(/\s+/g, ' ').trim();
}

/** Χαρακτήρες που κατά **RFC 5322 §3.2.3** υποχρεώνουν το όνομα σε `quoted-string`. */
const RFC5322_SPECIALS = /[()<>@,;:\\".[\]]/;

/**
 * **Η γραμμή `From:` — `Όνομα <διεύθυνση>`.**
 *
 * ⚠️ **Εισαγωγικά μόνο όταν χρειάζονται** (RFC 5322 §3.2.3): ένα όνομα με `,` ή `.` —
 * π.χ. *«Παπαδόπουλος, Α.»* — **χωρίς** εισαγωγικά σπάει τη γραμμή σε δύο διευθύνσεις.
 * Μέσα στο `quoted-string` διαφεύγουν `\` και `"`, με αυτή τη σειρά.
 *
 * 🔶 **Δηλωμένο όριο — ΔΕΝ κάνουμε RFC 2047**: ένα ελληνικό όνομα μένει ωμό UTF-8. Και
 * οι δύο πάροχοί μας (Mailgun `FormData`, Resend JSON) κωδικοποιούν οι ίδιοι, και μια
 * **δεύτερη** κωδικοποίηση από εμάς θα παρήγε `=?UTF-8?B?…?=` **μέσα** σε ήδη
 * κωδικοποιημένη κεφαλίδα — ορατά σκουπίδια στα εισερχόμενα. Αν κάποτε μπει πάροχος
 * που **δεν** το κάνει, μπαίνει **εδώ**, σε ένα σημείο.
 */
export function senderHeader(identity: SenderIdentity): SenderHeader {
  const name = sanitizeDisplayName(identity.name);
  if (!name) return identity.address as SenderHeader;

  const display = RFC5322_SPECIALS.test(name)
    ? `"${name.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
    : name;

  // 🔑 **Ο ΜΟΝΟΣ ΕΠΙΤΡΕΠΤΟΣ ΙΣΧΥΡΙΣΜΟΣ ΣΕ ΟΛΟ ΤΟ ΔΕΝΤΡΟ** — και είναι εδώ επειδή **εδώ**
  //    έγινε ο καθαρισμός και η εισαγωγικοποίηση. Ένα `as SenderHeader` οπουδήποτε αλλού
  //    σημαίνει «παρέκαμψα τον καθαρισμό έγχυσης», και η πύλη το κυνηγά ονομαστικά.
  return `${display} <${identity.address}>` as SenderHeader;
}

/**
 * Συντομογραφία: **η γραμμή `From:` κατευθείαν**, για τους καλούντες που δεν
 * χρειάζονται το `source`.
 *
 * @param displayName Όνομα που **υπερισχύει** του ονόματος της ταυτότητας — π.χ. ο
 *   άνθρωπος που κοινοποιεί ένα ακίνητο. ⚠️ Η **διεύθυνση δεν αλλάζει ποτέ** από εδώ:
 *   αυτή κρίνει την ευθυγράμμιση DKIM, και ένας χρήστης δεν επιλέγει domain αποστολής.
 */
export function resolveSenderHeader(
  displayName?: string,
  tenant?: TenantSenderOverride,
): SenderHeader {
  const identity = resolveSenderIdentity(tenant);
  const override = firstNonEmpty(displayName);
  return senderHeader(override ? { ...identity, name: override } : identity);
}

/**
 * **Η ΟΥΡΑ ΕΠΙΣΤΡΕΦΕΙ ΣΚΕΤΟ `string` — ΕΔΩ ΓΙΝΕΤΑΙ ΡΗΤΗ ΥΙΟΘΕΣΙΑ, ΟΧΙ ΣΙΩΠΗΛΟ `as`.**
 *
 * 🔴 Το `messages/{id}.from` γράφτηκε **πριν λεπτά ή ώρες** και είναι ό,τι επιτρέπει η
 * Firestore: `unknown`. Δεν υπάρχει τρόπος ο τύπος να ταξιδέψει μέσα από τη βάση — αυτό
 * είναι **δομικό όριο κάθε branded type**, όχι ελάττωμα εδώ.
 *
 * 🔑 **Και γι' αυτό η υιοθεσία ΞΑΝΑΚΑΘΑΡΙΖΕΙ**: ένα ουραγμένο έγγραφο μπορεί να κουβαλά
 * τιμή γραμμένη από **παλιότερη** έκδοση του κώδικα — ακριβώς το σχήμα που φυλάει το
 * `KNOWN_PAST_SPELLINGS` για τα θέματα. Περνώντας την από τον **ίδιο** καθαρισμό, μια
 * αποθηκευμένη γραμμή με `\r\n` **δεν** μπορεί να γράψει κεφαλίδα στην έξοδο.
 *
 * ⚠️ Επιστρέφει `undefined` για ό,τι δεν είναι μη κενή συμβολοσειρά — **ποτέ κενή
 * γραμμή**: ο καλών πέφτει τότε στη ρίζα, που είναι η σωστή απάντηση.
 */
export function adoptStoredSenderHeader(stored: unknown): SenderHeader | undefined {
  const raw = typeof stored === 'string' ? stored : '';
  const cleaned = sanitizeDisplayName(raw);
  return cleaned === '' ? undefined : (cleaned as SenderHeader);
}
