import 'server-only';

/**
 * @fileoverview **ΠΟΙΟΝ ΦΤΑΝΕΙ Η ΠΡΑΞΗ** — μία ερώτηση, μία κατοικία, δύο καλούντες.
 * @related ADR-843 §10.17 · services/contact/first-contact-guards.ts · services/listings/listing-resolver.ts
 * @module services/contact/first-contact-target-locator
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ: Η ΙΔΙΑ ΡΙΖΑ ΜΕ ΤΟ §10.16, ΕΝΑ ΕΠΙΠΕΔΟ ΠΙΟ ΠΑΝΩ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το §10.16 έδωσε **κατοικία** στο *«ποιες οικογένειες αγγελιών υπάρχουν;»* — και η
 * ρίζα του ελαττώματος ήταν ότι η γνώση υπήρχε σωστά, **σκορπισμένη ως πρόζα**, χωρίς
 * λίστα από την οποία να μπορεί κανείς να **ξεχάσει** μια γραμμή.
 *
 * 🔴 **Ένα επίπεδο πιο πάνω ζούσε ΑΚΡΙΒΩΣ το ίδιο σχήμα, και δεν το είχε δει κανείς**:
 * η ερώτηση *«ποιον φτάνει αυτή η πράξη;»* απαντιόταν σε **δύο** σημεία μέσα στον
 * `resolveTarget` — μία φορά ενσωματωμένη για τον **επαγγελματία** *(μία γραμμή, χωρίς
 * όνομα)* και μία φορά μέσω του επιλυτή για την **αγγελία**. Και οι δύο ήταν σωστές·
 * καμία δεν ήταν **προσβάσιμη**, γιατί ήταν μπλεγμένες με εξουσιοδότηση και ζωντάνια.
 *
 * ⇒ Όταν το Στάδιο ΣΤ χρειάστηκε την **ίδια** απάντηση για το backfill του
 * {@link FirstContact.offerer}, δεν υπήρχε τίποτα να καλέσει: μόνο να **ξαναγράψει**
 * τη διάκριση των δύο ειδών — δηλαδή να γίνει το **τρίτο** σημείο, και η επόμενη
 * προσθήκη είδους στόχου να το ξεχάσει σιωπηλά. **Ίδιο ελάττωμα, νέα εμφάνιση.**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 Η ΤΟΜΗ: «ΠΟΙΟΝ ΦΤΑΝΕΙ» ≠ «ΕΠΙΤΡΕΠΕΣΑΙ» ≠ «ΕΙΝΑΙ ΖΩΝΤΑΝΟΣ»
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Τρεις ερωτήσεις που ο `resolveTarget` απαντούσε ως **μία**. Εδώ ζει **μόνο η πρώτη**,
 * και ο διαχωρισμός δεν είναι αισθητικός — είναι ο λόγος που το backfill μπορεί να
 * υπάρξει καθόλου:
 *
 * | Ερώτηση | Ποιος την απαντά | Την χρειάζεται το backfill; |
 * |---|---|---|
 * | «ποιον φτάνει;» | **αυτό το αρχείο** | ✅ ΝΑΙ — είναι όλη η δουλειά του |
 * | «επιτρέπεσαι;» | `mayAdminister` *(CHECK 3.56)* | ❌ όχι — δεν υπάρχει «καλών» |
 * | «είναι ζωντανός;» | `buildPublicListing` · `lookupAgencyProfile` | ❌ **και ΔΕΝ ΠΡΕΠΕΙ** |
 *
 * 🔴 **Το τελευταίο «ΔΕΝ ΠΡΕΠΕΙ» είναι ουσιαστικό, όχι λεπτολογία.** Η πράξη έγινε
 * **τότε**. Μια αγγελία που αποσύρθηκε **μετά** δεν ακυρώνει το ότι κάποιος άνθρωπος
 * συστήθηκε — και ένα backfill που ρωτούσε «είναι ακόμη ζωντανή;» θα άφηνε **μόνιμα
 * αόρατες** ακριβώς τις πράξεις προς αποσυρμένες αγγελίες, δηλαδή θα έσβηνε ιστορία
 * επειδή άλλαξε το παρόν.
 *
 * ⚠️ **ΚΑΙ Η ΖΩΝΤΑΝΙΑ ΔΕΝ ΜΕΤΑΚΟΜΙΣΕ ΕΔΩ, ΕΠΙΤΗΔΕΣ.** Δεν είναι η ίδια ερώτηση με δύο
 * απαντήσεις — είναι **δύο διαφορετικές ερωτήσεις**: για τον επαγγελματία *«είναι η
 * βιτρίνα δημοσιευμένη;»* *(και η απουσία της είναι `target-absent`, με **συγκάλυψη**:
 * δες `lookupAgencyProfile`)*· για την αγγελία *«έχει ζωντανή διάθεση στην αγορά;»*
 * *(και η απουσία της είναι `target-not-live`, **ξεχωριστός** κωδικός επίτηδες)*.
 * Ενοποιημένες σε ένα `live: boolean` θα παρήγαγαν **λάθος άρνηση** για το ένα από τα
 * δύο — και θα άλλαζαν τη **σειρά** των ελέγχων, στέλνοντας στον ιδιοκτήτη μιας
 * αδημοσίευτης βιτρίνας «δεν υπάρχει» αντί για «είναι δικό σου».
 *
 * **Layering**: server — Admin SDK ως **όρισμα**, ποτέ singleton· καμία ανάγνωση ρολογιού.
 */

import type { Firestore as AdminFirestore } from 'firebase-admin/firestore';

import type { ListingMatchFacts } from '@/lib/demand/demand-match-vocabulary';
import type { ListingCustody } from '@/lib/owner-property/listing-custody';
import { resolveListing } from '@/services/listings/listing-resolver';
import type { FirstContactTarget } from '@/types/first-contact';

// =============================================================================
// 1. ΤΟ ΣΥΜΒΟΛΑΙΟ
// =============================================================================

/**
 * **Ο στόχος, εντοπισμένος** — ποιον φτάνει, και τι ξέρουμε γι' αυτόν.
 *
 * ⚠️ **Το `facts: null` ΔΕΝ σημαίνει «κακός στόχος»**: για τον **επαγγελματία** είναι
 * το φυσιολογικό *(βιτρίνα δεν είναι αγγελία — δεν υπάρχει τίποτα να συγκριθεί με
 * ζήτηση)*, ενώ για την **αγγελία** σημαίνει *«υπάρχει, αλλά δεν είναι στην αγορά»*.
 * Ο καλών ξέρει ποια από τις δύο ρώτησε· αυτό το αρχείο δεν χρειάζεται να το ξέρει.
 */
export interface LocatedTarget {
  /** 🏆 **Ο παραλήπτης της πράξης** — η τιμή που γράφεται ως `FirstContact.offerer`. */
  readonly custody: ListingCustody;
  /** Τα γεγονότα που κρίνουν το «γιατί ταιριάζει», ή `null` όταν δεν υπάρχουν. */
  readonly facts: ListingMatchFacts | null;
}

/**
 * **Το τρίπτυχο, κληρονομημένο αυτούσιο**: `null` = **βλάβη** *(δεν μάθαμε)* ·
 * `'absent'` = **δεν υπάρχει** · αλλιώς ο στόχος.
 *
 * 🔑 Δεν είναι νέα σύμβαση — είναι **ακριβώς** η {@link ListingResolution} του
 * `listing-resolver.ts`, και ο λόγος της είναι μετρημένος (N.12): ένα `null` που
 * σκεπάζει και τα δύο λέει στον άνθρωπο *«δεν υπάρχει»* κάθε φορά που πέφτει η
 * Firestore. Το backfill το τηρεί **αυστηρότερα από την οθόνη**: σε `null` σταματά,
 * γιατί μια εικασία γράφεται **μόνιμα**.
 */
export type TargetLocation = LocatedTarget | 'absent' | null;

// =============================================================================
// 2. Η ΔΗΜΟΣΙΑ ΠΟΡΤΑ — εξαντλητική, με φρουρό στον μεταγλωττιστή
// =============================================================================

/**
 * **Ποιον φτάνει αυτή η πράξη;**
 *
 * 🔴 **ΕΔΩ ΕΙΝΑΙ Ο ΦΡΟΥΡΟΣ ΤΟΥ ΤΡΙΤΟΥ ΕΙΔΟΥΣ ΣΤΟΧΟΥ.** Το `switch` πάνω σε κλειστή
 * διακριτή ένωση με **δηλωμένο** τύπο επιστροφής: ένα τρίτο είδος στο
 * {@link FirstContactTarget} αφήνει διαδρομή που δεν επιστρέφει `TargetLocation`, και
 * ο μεταγλωττιστής **σταματά** — αντί να «δουλέψει» με σιωπηλή απουσία παραλήπτη.
 * Ίδιο ιδίωμα με το `LISTING_FAMILY_READERS` του §10.16, μία βαθμίδα πιο πάνω.
 *
 * ⛔ **ΜΗΝ προσθέσεις εδώ έλεγχο ζωντάνιας ή εξουσιοδότησης** — δες την κεφαλίδα.
 * Αν βρεθείς να γράφεις `mayAdminister`, `lifecycle !== …` ή `lookupAgencyProfile`,
 * η απάντηση ανήκει στον καλούντα, όχι εδώ.
 */
export async function locateTarget(
  adminDb: AdminFirestore,
  target: FirstContactTarget,
  nowISO: string,
): Promise<TargetLocation> {
  switch (target.kind) {
    case 'listing':
      return locateListing(adminDb, target.listingId, nowISO);
    case 'professional':
      return locateProfessional(target.agencyCompanyId);
    default: {
      // Η κλειστή ένωση εξαντλήθηκε· ένα τρίτο είδος κοκκινίζει ΕΔΩ, στη μεταγλώττιση.
      const exhaustive: never = target;
      return exhaustive;
    }
  }
}

// =============================================================================
// 3. ΟΙ ΔΥΟ ΕΝΤΟΠΙΣΜΟΙ — καμία γραμμή κρίσης, μόνο ανάθεση
// =============================================================================

/**
 * **Η ΑΓΓΕΛΙΑ** — ο ΕΝΑΣ επιλυτής, για **αμφότερες** τις οικογένειες (§10.16).
 *
 * 🔑 **Καμία γνώση οικογένειας δεν ζει εδώ**, και αυτό είναι το κέρδος: μια τρίτη
 * οικογένεια αγγελιών αύριο **δεν αφορά καθόλου** αυτό το αρχείο.
 */
async function locateListing(
  adminDb: AdminFirestore,
  listingId: string,
  nowISO: string,
): Promise<TargetLocation> {
  const resolved = await resolveListing(adminDb, listingId, nowISO);
  if (resolved === null || resolved === 'absent') return resolved;

  return { custody: resolved.custody, facts: resolved.facts };
}

/**
 * **Ο ΕΠΑΓΓΕΛΜΑΤΙΑΣ** — και **καμία ανάγνωση**, επίτηδες.
 *
 * 🏆 **Ο παραλήπτης ΕΙΝΑΙ ο ίδιος ο στόχος**: η βιτρίνα ζει σε `agency_profiles/{companyId}`,
 * δηλαδή η ταυτότητα που ο άνθρωπος πάτησε **είναι** ο χώρος στον οποίο φτάνει η πράξη.
 * Μια ανάγνωση για να το «επιβεβαιώσουμε» δεν θα μάθαινε τίποτα που δεν κρατάμε ήδη.
 *
 * ⚠️ **Και γι' αυτό δεν επιστρέφει ΠΟΤΕ `'absent'` ή `null`.** Το *«η βιτρίνα δεν είναι
 * δημοσιευμένη»* είναι **άλλη** ερώτηση, ζει στον καλούντα, και έχει **συγκάλυψη**
 * *(αδημοσίευτο και ανύπαρκτο είναι αδιάκριτα — δες `lookupAgencyProfile`)*. Αν έμπαινε
 * εδώ, το backfill θα αρνιόταν να δώσει παραλήπτη σε πράξη προς γραφείο που απλώς
 * **απέσυρε** τη βιτρίνα του — και ο άνθρωπος που το πλησίασε θα χανόταν.
 *
 * 🔴 **ΕΔΩ ΓΡΑΦΕΤΑΙ Η ΘΕΜΑΤΟΦΥΛΑΚΗ ΤΟΥ ΕΠΑΓΓΕΛΜΑΤΙΑ — ΜΙΑ ΦΟΡΑ, ΣΕ ΟΛΟ ΤΟ ΕΡΓΟ.** Ήταν
 * ενσωματωμένη στον `resolveTarget` και ο γραφέας την περνούσε παρακάτω· τώρα ο γραφέας
 * και το backfill διαβάζουν **την ίδια** γραμμή. Δύο εκφράσεις του ίδιου πράγματος θα
 * ήταν ελεύθερες να αποκλίνουν — και η απόκλιση θα φαινόταν ως *«η πράξη έφτασε σε
 * λάθος γραφείο»*, το χειρότερο είδος σφάλματος αυτού του ADR.
 */
async function locateProfessional(agencyCompanyId: string): Promise<TargetLocation> {
  return { custody: { kind: 'company', companyId: agencyCompanyId }, facts: null };
}
