/**
 * **Η απάντηση στο «γίνεσαι δεκτός;»**
 *
 * 🔑 **Το `unchanged` ΔΕΝ είναι άρνηση, και γι' αυτό δανείζεται τον τύπο του γραφέα**
 * αντί να γεννήσει δικό του: *«την έχεις ήδη ανοιχτή»* είναι **επιτυχία** — ο άνθρωπος
 * πέτυχε ήδη αυτό που πάει να κάνει. Ο γραφέας το **προωθεί αυτούσιο**, και η οθόνη το
 * δείχνει ως **κατάσταση**, ποτέ ως σφάλμα.
 *
 * ⚠️ **`Extract<…>` και όχι χειρόγραφο αντίγραφο του σχήματος**: αν αύριο το `unchanged`
 * αποκτήσει πεδίο, αυτό εδώ **δεν μεταγλωττίζεται** μέχρι να το μάθει — αντί να
 * αποκλίνει σιωπηλά από τον γραφέα που υπάρχει για να εξυπηρετεί.
 */
export type ContactAdmission =
  /** ✅ Γίνεται δεκτός — και ο **εντοπισμένος** στόχος ταξιδεύει, ώστε ο γραφέας να μην ξαναδιαβάσει. */
  | { readonly kind: 'admitted'; readonly located: LocatedTarget }
  | Extract<FirstContactWriteResult, { readonly kind: 'unchanged' }>
  | FirstContactRefusal
  | FirstContactUnavailable;

/**
 * **Επιτρέπεται σε αυτόν τον άνθρωπο να ανοίξει πράξη προς αυτόν τον στόχο, τώρα;**
 *
 * 🔴 **Η ΣΕΙΡΑ ΕΙΝΑΙ ΣΥΜΒΟΛΑΙΟ, ΚΑΙ ΜΕΤΑΚΟΜΙΣΕ ΑΥΤΟΥΣΙΑ** από την κεφαλίδα του γραφέα:
 *
 * 1. **Ιδεμποτησία πρώτη** *(Stripe)* — το δεύτερο πάτημα δεν επιτρέπεται **ούτε** να
 *    ξοδέψει δεύτερη θέση **ούτε** να ακούσει «γέμισε» για κάτι που **πέτυχε**.
 * 2. **Χωρητικότητα** — η **μία** ανάγνωση έχει ήδη γίνει για το (1)· και όταν είσαι
 *    γεμάτος **καμία** πράξη δεν περνά, άρα το «γέμισε» είναι η αληθινή **και**
 *    ενεργήσιμη απάντηση.
 * 3. **Ο στόχος** — πληρώνει ανάγνωση, και δεν την πληρώνουμε για κάποιον που **δεν
 *    μπορεί** να πράξει ούτως ή άλλως.
 *
 * ⛔ **ΜΗΝ αντιστρέψεις το (2) με το (3) «για καλύτερο μήνυμα».** Ο ιδιοκτήτης που είναι
 * **και** γεμάτος οφείλει να ακούσει *«γέμισε»* — γιατί αυτό είναι το εμπόδιο που τον
 * αφορά σε **κάθε** αγγελία, όχι μόνο σε τούτη· και θα πλήρωνε ανάγνωση για να πάρει
 * **στενότερη** απάντηση.
 *
 * @param nowISO — η **περασμένη** στιγμή· κανένα ρολόι εδώ μέσα, ώστε τα άκρα να είναι
 *   δοκιμάσιμα. Ίδιο ιδίωμα με τον γραφέα και τον εντοπιστή.
 */
export async function admitFirstContact(
  adminDb: AdminFirestore,
  actor: ListingActor,
  target: FirstContactTarget,
  nowISO: string,
): Promise<ContactAdmission> {
  const existing = await loadSeekerContacts(adminDb, actor.uid);
  if (existing === null) return UNAVAILABLE;

  const already = existing.find(
    (contact) => contact.lifecycle === 'open' && sameFirstContactTarget(contact.target, target),
  );
  if (already !== undefined) return { kind: 'unchanged', contact: shownToSeeker(already) };

  if (!canOpenAnotherContact(existing)) return refuse('capacity-full');

  const located = await resolveTarget(adminDb, actor, target, nowISO);
  // ⚠️ Ο εντοπισμένος στόχος **δεν έχει** `kind` — οι δύο αποτυχίες έχουν. Ίδιος
  //    διακριτής με τον γραφέα, γιατί είναι **η ίδια** τιμή που έκρινε ως τώρα εκείνος.
  if ('kind' in located) return located;

  return { kind: 'admitted', located };
}

/**
 * **Πού διαχειρίζεται ο ΙΔΙΟΣ αυτό που μόλις προσπάθησε να πλησιάσει** — ή `null`.
 *
 * 🔑 **Καλείται ΜΟΝΟ μετά από `contact-own-target`**, δηλαδή αφού ο **ένας** κριτής
 * *(`mayAdminister`, CHECK 3.56)* έχει ήδη πει *«είναι δικό σου»*. Άρα η μία επιπλέον
 * ανάγνωση την πληρώνει **μόνο ο ιδιοκτήτης**, **μόνο στη δική του σελίδα** — και
 * καμία απόφαση εξουσιοδότησης δεν λαμβάνεται εδώ.
 *
 * ⛔ **ΜΗΝ γράψεις εδώ σύγκριση ταυτότητας** για να «γλιτώσεις» την ανάγνωση. Ο
 * πειρασμός είναι το *«αν ο δρων δεν έχει εταιρεία, τότε η θεματοφυλακή είναι
 * προσωπική»* — **αληθές**, αλλά **μονόδρομο**: υπάλληλος γραφείου έχει `companyId`
 * **και** μπορεί να κατέχει δική του αγγελία στο `(me)`. Ο συλλογισμός θα έδινε
 * **λάθος σύνδεσμο** ακριβώς σε αυτόν, και σιωπηλά.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔶 ΤΟ `null` ΤΟΥ ΕΤΑΙΡΙΚΟΥ ΧΩΡΟΥ ΕΙΝΑΙ **ΟΝΟΜΑΣΜΕΝΗ ΑΠΟΥΣΙΑ**, ΟΧΙ ΠΑΡΑΛΕΙΨΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η σελίδα διαχείρισης μιας **εταιρικής** αγγελίας ζει **μέσα σε χώρο**
 * (`/o/[workspace]/properties/[id]`), και από **δημόσια** σελίδα κανείς δεν μπορεί να
 * την ονομάσει — για **δύο** ανεξάρτητους λόγους:
 *
 * 1. **Ο διακομιστής** δεν έχει το ψευδώνυμο: η αντίστροφη αναζήτηση
 *    `companyId → alias` είναι **σάρωση**, και το `alias-registry.ts` την αρνείται εξ
 *    ορισμού (ADR-787 Ε-5 §4 #1) — το ίδιο γράφει και το `AgencyProfileContent`.
 * 2. **Ο πελάτης** δεν το έχει ούτε αυτός: το σύνορο πλοήγησης διαβάζει τον ενεργό
 *    χώρο από το **μονοπάτι** (`extractWorkspaceSegment`), και το `/listing/[id]` ζει
 *    στο `(light)` — **εκτός** χώρου. Ένα `<Link href="/properties/…">` εκεί θα έβγαζε
 *    **404**.
 *
 * ⇒ Ο πίνακας δείχνει τη **δήλωση** χωρίς σύνδεσμο, αντί για σύνδεσμο που σπάει. Όταν
 * κάποιος δώσει στο δημόσιο κέλυφος τρόπο να ονομάσει χώρο, **αυτή η γραμμή** είναι το
 * σημείο που το μαθαίνει.
 */
export async function manageHrefOfOwnTarget(
  adminDb: AdminFirestore,
  target: FirstContactTarget,
  nowISO: string,
): Promise<string | null> {
  // Η βιτρίνα ζει πάντα σε **εταιρικό** χώρο ⇒ ποτέ ονομάσιμη από εδώ (δες παραπάνω).
  if (target.kind !== 'listing') return null;

  const located = await locateTarget(adminDb, target, nowISO);
  if (located === null || located === 'absent') return null;

  return located.custody.kind === 'personal' ? offerDetailHref(target.listingId) : null;
}
