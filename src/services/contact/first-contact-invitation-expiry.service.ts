import 'server-only';

/**
 * @fileoverview **Η ΠΡΟΣΚΛΗΣΗ ΠΟΥ ΔΕΝ ΠΑΤΗΘΗΚΕ** — σβήνεται, και δεν το μαθαίνει κανείς.
 * @related ADR-844 Β6 · types/first-contact-invitation.ts · services/mandate/mandate-expiry.service.ts
 * @module services/contact/first-contact-invitation-expiry.service
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΔΙΑΓΡΑΦΗ — ΚΑΙ ΕΙΝΑΙ ΤΟ **ΑΝΤΙΘΕΤΟ** ΤΟΥ ΚΑΝΟΝΑ ΤΗΣ ΠΡΑΞΗΣ, ΕΠΙΤΗΔΕΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο κανόνας του `first_contacts` λέει **«καμία διαγραφή, από κανέναν»** (ΠΕ6: *«ανακαλείται
 * η ΣΧΕΣΗ, ποτέ η ΙΣΤΟΡΙΑ»*), και ο λόγος είναι γραμμένος στο `firestore.rules`: αν αύριο ο
 * ένας πει *«με παρενόχλησε»* και ο άλλος *«συμφωνήσαμε»*, το σβήσιμο αφήνει **και τους δύο**
 * χωρίς τίποτα να δείξουν.
 *
 * 🔑 **Εδώ δεν υπάρχουν δύο.** Μια πρόσκληση που δεν πατήθηκε ποτέ **δεν γέννησε σχέση**:
 * ο ιδιοκτήτης **δεν έμαθε ποτέ ότι υπήρξε**, δεν στάλθηκε τίποτα, δεν είδε κανείς τίποτα.
 * Δεν υπάρχει ιστορία **δύο ανθρώπων** να προστατευτεί, γιατί **δεν συναντήθηκαν ποτέ** —
 * υπάρχει μόνο ένα εφήμερο έγγραφο με το **email και το τηλέφωνο** ενός ανθρώπου.
 *
 * ⇒ Η διατήρησή του δεν προστατεύει κανέναν· είναι **ελαχιστοποίηση δεδομένων** (GDPR
 * άρθρο 5.1.γ), και η κατάσταση `expired` του τύπου λέει κατά λέξη *«λήγει και σβήνεται»*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ ΣΒΗΝΟΝΤΑΙ **ΚΑΙ ΟΙ ΕΞΑΡΓΥΡΩΜΕΝΕΣ**, ΟΧΙ ΜΟΝΟ ΟΙ ΑΠΑΤΗΤΕΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Μια `redeemed` πρόσκληση είναι **σκαλωσιά**: η πράξη που γέννησε ζει στο
 * `first_contacts` με τη δική της ημερομηνία και το δικό της ίχνος. Το να κρατάμε
 * **δεύτερο** αντίγραφο των στοιχείων του ανθρώπου, σε συλλογή που κανείς δεν διαβάζει,
 * είναι καθαρή έκθεση χωρίς κανέναν αναγνώστη.
 *
 * ⚠️ **Το τίμημα είναι ονομαστικό και μετρημένο**: μετά τη διαγραφή, ένα δεύτερο κλικ στον
 * **ίδιο** σύνδεσμο απαντά `invitation-unknown` αντί για `already-used`. Και τα δύο κείμενα
 * στέλνουν στην **ίδια** ενέργεια *(«ζητήστε νέο σύνδεσμο»)*, και ο σύνδεσμος έχει έτσι κι
 * αλλιώς λήξει — άρα το `already-used` δεν είχε τι να προσφέρει που δεν προσφέρει το άλλο.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΜΙΑ ΑΝΙΣΟΤΗΤΑ, ΚΑΝΕΝΑ ΣΥΝΘΕΤΟ ΕΥΡΕΤΗΡΙΟ — ΙΔΙΟ ΜΑΘΗΜΑ ΜΕ ΤΟ `mandate-expiry`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ερώτημα είναι **σκέτο** `expiresAt <= now`. Ο πειρασμός να προστεθεί
 * `.where('state','==','sent')` θα ζητούσε **σύνθετο ευρετήριο** *(ισότητα + ανισότητα σε
 * διαφορετικά πεδία)* — και θα ήταν **λάθος**, γιατί ακριβώς οι υπόλοιπες καταστάσεις είναι
 * αυτές που πρέπει να φύγουν πρώτες.
 *
 * 🔶 **ΔΗΛΩΜΕΝΟ ΚΕΝΟ**: έγγραφο **χωρίς** `expiresAt` *(χαλασμένη γραφή)* **δεν** μπαίνει
 * ποτέ σε ερώτημα ανισότητας — το Firestore αποκλείει τα έγγραφα που δεν έχουν το πεδίο.
 * Τέτοιο έγγραφο θα ζούσε για πάντα. **Δεν είναι τρύπα ασφαλείας**: το
 * `readStoredInvitationState` το διαβάζει fail-closed ως `expired`, άρα **δεν εξαργυρώνεται
 * ποτέ**. Είναι σκουπίδι, όχι κίνδυνος — και η θεραπεία *(πλήρης σάρωση της συλλογής)* θα
 * κόστιζε περισσότερο από όσο αξίζει. Καταγράφεται αντί να σιωπηθεί.
 */

import type { Firestore as AdminFirestore } from 'firebase-admin/firestore';

import { COLLECTIONS } from '@/config/firestore-collections';
import { nowISO as clockNowISO } from '@/lib/date-local';
import { createModuleLogger } from '@/lib/telemetry';

const logger = createModuleLogger('first-contact-invitation-expiry.service');

/**
 * Πόσες προσκλήσεις κοιτάζει **ένα** πέρασμα.
 *
 * ⚠️ **Το όριο λέγεται στην αναφορά όταν χτυπηθεί** (`truncated`), ποτέ σιωπηλά: μια σάρωση
 * που έκοψε στις 500 και ανέφερε «500 εξετάστηκαν» διαβάζεται ως *«αυτά ήταν όλα»*. Ίδιο
 * συμβόλαιο με τον σαρωτή των εντολών.
 */
const SCAN_LIMIT = 500;

/**
 * Πόσες διαγραφές ανά δέσμη.
 *
 * ⚠️ **Κάτω από το σκληρό όριο των 500 πράξεων/δέσμης του Firestore, με περιθώριο.** Ένα
 * ακριβές `500` θα έσπαγε την ημέρα που κάποιος προσθέσει **μία** ακόμη πράξη στον βρόχο.
 */
const BATCH_SIZE = 400;

/** Τι έκανε το πέρασμα — **κάθε κάδος εκπέμπεται, ΚΑΙ ΟΤΑΝ ΕΙΝΑΙ ΜΗΔΕΝ**. */
export interface InvitationExpiryReport {
  readonly considered: number;
  readonly deleted: number;
  readonly failed: number;
  readonly truncated: boolean;
}

/**
 * **Ένα πέρασμα: «σβήσε ό,τι πέρασε η ώρα του».**
 *
 * @param at Η **περασμένη** στιγμή· κανένα ρολόι εδώ μέσα, ώστε τα άκρα να είναι
 *   δοκιμάσιμα. Ίδιο ιδίωμα με τον γραφέα της πρόσκλησης.
 *
 * ⚠️ **Ιδεμποτο εξ ορισμού**: δεύτερη εκτέλεση βρίσκει **μηδέν** έγγραφα. Δύο περάσματα
 * που τρέχουν παράλληλα διαγράφουν το ίδιο έγγραφο δύο φορές — και η διπλή διαγραφή στο
 * Firestore είναι **αθόρυβα επιτυχής**, όχι σφάλμα.
 */
export async function purgeExpiredInvitations(
  adminDb: AdminFirestore,
  at: string = clockNowISO(),
): Promise<InvitationExpiryReport> {
  // tenant-scope-exempt: καθολικό πέρασμα λήξης (Admin SDK, ποτέ από αίτημα χρήστη). Η λήξη
  // μιας πρόσκλησης είναι **γεγονός του ρολογιού**, όχι δεδομένο μισθωτή — το πέρασμα οφείλει
  // να δει κάθε ληγμένη, ανεξάρτητα από εταιρεία. Καμία απάντηση δεν φεύγει προς πελάτη: το
  // μόνο αποτέλεσμα είναι ότι ληγμένες προσκλήσεις **διαγράφονται**.
  const collection = adminDb.collection(COLLECTIONS.FIRST_CONTACT_INVITATIONS);

  // 🔑 **`SCAN_LIMIT + 1`**: το επιπλέον έγγραφο είναι ο **μόνος** τρόπος να ξεχωρίσεις
  //    «βρέθηκαν ακριβώς 500» από «υπάρχουν κι άλλα». Χωρίς αυτό, το `truncated` θα ήταν
  //    μαντεψιά — και θα έλεγε ψέματα ακριβώς στην περίπτωση που μετράει.
  const snapshot = await collection
    .where('expiresAt', '<=', at)
    .limit(SCAN_LIMIT + 1)
    .get();

  const truncated = snapshot.docs.length > SCAN_LIMIT;
  const doomed = snapshot.docs.slice(0, SCAN_LIMIT);

  let deleted = 0;
  let failed = 0;

  for (let start = 0; start < doomed.length; start += BATCH_SIZE) {
    const slice = doomed.slice(start, start + BATCH_SIZE);
    const batch = adminDb.batch();

    // ⚠️ **`collection.doc(doc.id)` και ΟΧΙ `doc.ref`** — ο ίδιος λόγος με το
    //    `supersedePreviousInvitations`: μετρημένο 2026-09-05 ότι το `.ref` στον κοινό
    //    πλαστό ξυπνά **δύο ξένες σουίτες** σε διαδρομή που χτυπά πραγματικό Storage.
    for (const doc of slice) batch.delete(collection.doc(doc.id));

    try {
      await batch.commit();
      deleted += slice.length;
    } catch (cause) {
      // 🔑 **Η δέσμη που έπεσε ΔΕΝ σταματά τις επόμενες.** Οι προσκλήσεις είναι
      //    ανεξάρτητες μεταξύ τους: μια αποτυχία στις πρώτες 400 δεν λέει τίποτα για τις
      //    υπόλοιπες, και μια πρόωρη έξοδος θα άφηνε δεδομένα ανθρώπων να λιμνάζουν
      //    επειδή κάποιο **άλλο** έγγραφο ήταν προβληματικό.
      failed += slice.length;
      logger.error('Δέσμη διαγραφής προσκλήσεων απέτυχε', {
        data: { size: slice.length },
        error: cause instanceof Error ? cause.message : String(cause),
      });
    }
  }

  return { considered: doomed.length, deleted, failed, truncated };
}
