/**
 * =============================================================================
 * ADR-842 §7.6.13 — **Ο ΔΕΥΤΕΡΟΣ ΑΝΑΓΝΩΣΤΗΣ ΔΕΝ ΞΑΝΑΝΟΙΓΕΙ**
 * =============================================================================
 *
 * Το ερώτημα: *«ξαναέγινε το `properties.service.ts` **αναγνώστης** της βάσης;»*
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΙ ΕΓΙΝΕ, ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΗΤΑΝ «ΣΥΓΚΛΙΣΗ» ΑΛΛΑ **ΔΙΑΓΡΑΦΗ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η συλλογή `properties` είχε **δύο** αναγνώστες με ασύμβατη φιλοσοφία:
 *
 * | Ποιος | Πώς |
 * |---|---|
 * | `lib/firestore-mappers.ts` → `mapPropertyDoc` | **λίστα επιτρεπόμενων πεδίων** — χτίζει ρητό αντικείμενο |
 * | `services/properties.service.ts` → `toProperty` | **διαπερατός** — τερμάτιζε σε `as unknown as Property` |
 *
 * Το `as unknown as` είναι **διπλός** ισχυρισμός: ούτε καν ο μεταγλωττιστής δεν είχε
 * λόγο να πιστέψει το αποτέλεσμα.
 *
 * 🔑 **Η μέτρηση ανέτρεψε τον σχεδιασμό.** Το `knip --include exports,types` έδειξε ότι
 * ο **μόνος** καλών του `getProperties()` ήταν το `useContactsState` — **πρόγονος** του
 * ζωντανού `useContactsPageState`, που έμεινε πίσω στην εξαγωγή του ADR-233. Άρα ο
 * δεύτερος αναγνώστης δεν χρειαζόταν σύγκλιση· ήταν **νεκρός**.
 *
 * ⚠️ **Γιατί καμία πύλη δεν το είχε πιάσει**: το `.deadcode-baseline.json` έχει **μόνο**
 * κλειδί `files` — **όχι** `exports`. Το αρχείο μετρούσε ως ζωντανό επειδή **ένα**
 * `import type { ViewMode }` στο `ContactsHeader.tsx` το κρατούσε. Πέμπτη εμφάνιση του
 * σχήματος *«`0` σημαίνει *κανείς δεν κοίταξε*, όχι *καθαρό*»*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΑΓΚΥΡΑ ΠΑΝΩ ΣΕ **ΠΗΓΑΙΟ ΚΩΔΙΚΑ** ΚΑΙ ΟΧΙ ΣΕ ΣΥΜΠΕΡΙΦΟΡΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ελάττωμα που φυλάμε είναι **απουσία**, όχι λάθος τιμή: «κανείς δεν πρόσθεσε
 * δεύτερη πόρτα ανάγνωσης». Μια άγκυρα συμπεριφοράς θα δοκίμαζε τις συναρτήσεις **που
 * υπάρχουν** και θα ήταν **δομικά τυφλή** σε αυτή που θα γραφτεί αύριο — δηλαδή θα
 * φύλαγε το **δείγμα**, όχι την **κλάση**.
 *
 * ⚠️ **ΤΙ ΔΕΝ ΕΙΝΑΙ ΑΥΤΗ Η ΑΓΚΥΡΑ**: δεν φυλάει *«η συλλογή `properties` έχει έναν
 * αναγνώστη»* — αυτό είναι **ευρύτερο** και το φυλάει το **CHECK 3.74** (πίνακας
 * `BOUNDARIES`). Εδώ φυλάγεται **ένα** αρχείο: αυτό που **ήταν** η δεύτερη πόρτα και
 * είναι το πιθανότερο σημείο υποτροπής, γιατί το όνομά του (`properties.service`)
 * προσκαλεί ακριβώς αυτή την προσθήκη.
 */

import fs from 'node:fs';
import path from 'node:path';

const SERVICE_PATH = path.join(process.cwd(), 'src', 'services', 'properties.service.ts');

function serviceSource(): string {
  return fs.readFileSync(SERVICE_PATH, 'utf8');
}

/**
 * **Ο κώδικας χωρίς σχόλια** — και είναι ουσιώδες, όχι καλλωπισμός.
 *
 * Το ίδιο το αρχείο **ονομάζει** τον `toProperty` και το `firestoreQueryService` μέσα
 * στο επιτύμβιο σχόλιό του, ώστε ο επόμενος να ξέρει τι έφυγε και γιατί. Χωρίς αυτή
 * την αφαίρεση, η άγκυρα θα κοκκίνιζε στην **τεκμηρίωση** — δηλαδή θα τιμωρούσε
 * ακριβώς τη συμπεριφορά που θέλουμε να ενθαρρύνουμε.
 */
function codeWithoutComments(source: string): string {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/.*$/gm, '$1');
}

/**
 * **Οι τρόποι που ΑΥΤΟ το repo διαβάζει Firestore** — κλειστό σύνολο, με λόγο ο καθένας.
 *
 * 🔑 Δεν είναι «ό,τι μου ήρθε»: κάθε γραμμή αντιστοιχεί σε πραγματική πόρτα ανάγνωσης
 * που χρησιμοποιείται αλλού στον κώδικα. Αν προστεθεί έκτη πόρτα στο έργο, **ανήκει
 * εδώ** — και η προσθήκη είναι φθηνή, ενώ η παράλειψη είναι σιωπηλή.
 */
const READER_DOORS: ReadonlyArray<{ readonly why: string; readonly pattern: RegExp }> = [
  {
    why: 'Ο κεντρικός πελατικός αναγνώστης (ήταν ακριβώς η πόρτα του νεκρού getProperties)',
    pattern: /\bfirestoreQueryService\b/,
  },
  {
    why: 'Ωμές αναγνώσεις του πελατικού SDK',
    pattern: /\b(getDocs|getDoc|onSnapshot)\s*\(/,
  },
  {
    why: 'Admin SDK — δεν έχει θέση σε αρχείο με «use client»',
    pattern: /\b(getAdminFirestore|adminDb)\b/,
  },
  {
    why: 'Κατασκευή αναφοράς συλλογής/εγγράφου του πελατικού SDK',
    pattern: /^\s*import\s[^;]*\bfrom\s+'firebase\/firestore'/m,
  },
];

/**
 * **Οι εξαγωγές που ΟΦΕΙΛΟΥΝ να επιβιώσουν** — η ρήτρα Κ2 του έργου.
 *
 * 🔴 Χωρίς αυτήν, η άγκυρα περνά **πράσινη σε άδειο αρχείο**: αν κάποιος διαγράψει
 * ολόκληρο το `properties.service.ts`, «καμία ανάγνωση» γίνεται τετριμμένα αληθές και
 * η πύλη γιορτάζει τη ζημιά. Το ίδιο μάθημα που έγραψε το CHECK 3.74 όταν έγινε
 * πίνακας δύο συνόρων: *«ένα σύνορο χωρίς καταναλωτές δίνει πράσινο επειδή κανείς δεν
 * διαβάζει»*.
 */
const SURVIVING_WRITERS: readonly string[] = [
  'createProperty',
  'updateProperty',
  'deleteProperty',
  'getBuildingsList',
  'updatePropertyCoverage',
];

describe('ADR-842 §7.6.13 — το properties.service δεν είναι αναγνώστης', () => {
  it.each(READER_DOORS)('δεν ανοίγει την πόρτα: $why', ({ pattern }) => {
    expect(codeWithoutComments(serviceSource())).not.toMatch(pattern);
  });

  it('δεν παράγει Property από ωμό έγγραφο με ισχυρισμό', () => {
    const code = codeWithoutComments(serviceSource());
    // `as unknown as Property` ήταν η υπογραφή του νεκρού `toProperty`. Το
    // `as Property['field']` (δεικτοδότηση πεδίου) είναι **άλλο πράγμα** και επιτρέπεται.
    expect(code).not.toMatch(/\bas\s+unknown\s+as\s+Property\b/);
    // Το `\b` μετά το όνομα είναι ουσιώδες: χωρίς αυτό, το νόμιμο
    // `as PropertyCoverage` θα κοκκίνιζε ως ισχυρισμός εγγράφου.
    expect(code).not.toMatch(/\bas\s+Property\b\s*(?!\[)/);
  });

  it.each(SURVIVING_WRITERS)('εξακολουθεί να προσφέρει τον γραφέα: %s', (name) => {
    expect(serviceSource()).toMatch(
      new RegExp(`export\\s+async\\s+function\\s+${name}\\b`),
    );
  });

  it('ο νεκρός αναγνώστης και οι δικοί του δεν επέστρεψαν ως εξαγωγές', () => {
    const code = codeWithoutComments(serviceSource());
    for (const gone of ['toProperty', 'getProperties', 'updateMultiplePropertiesOwner']) {
      expect(code).not.toMatch(new RegExp(`\\bfunction\\s+${gone}\\b`));
    }
  });
});
