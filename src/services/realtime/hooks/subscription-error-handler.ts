'use client';

/**
 * ADR-798 §22.6 #1 — **ΤΙ ΚΑΝΟΥΜΕ ΟΤΑΝ ΜΙΑ ΣΥΝΔΡΟΜΗ ΑΠΟΤΥΧΕΙ**, μία φορά.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΤΙ ΑΝΤΙΚΑΘΙΣΤΑ — Η ΣΙΩΠΗΛΗ ΚΑΤΑΠΟΣΗ
 *
 * Τρεις συνδρομές *(`useRealtimeBuildingFloors` ×2 · `useRealtimeBuildingFloorplan`)*
 * είχαν χειριστή σφάλματος **ακριβώς αυτόν**:
 *
 *     () => { setLoading(false); }
 *
 * **Ούτε** το σφάλμα, **ούτε** καταγραφή, **ούτε** κριτής. Δεν έκαναν **θόρυβο**
 * *(άρα δεν ήταν το πρόβλημα του §21, όπου ο αυτόνομος έβγαζε κόκκινες γραμμές
 * σε κάθε φόρτωση)* — αλλά πραγματική βλάβη εκεί ήταν **αόρατη**: το spinner
 * έσβηνε, η οθόνη έλεγε «κανένας όροφος», και **κανείς δεν μάθαινε ποτέ** ότι το
 * ερώτημα είχε αποτύχει. Απουσία γνώσης παρουσιασμένη ως γνώση.
 *
 * ⚠️ **ΟΙ ΔΥΟ ΣΙΩΠΕΣ ΔΕΝ ΕΙΝΑΙ Η ΙΔΙΑ** — και αυτός είναι όλος ο λόγος που
 * υπάρχει αυτό το αρχείο:
 *
 * | Η αιτία | Τι σημαίνει | Τι κάνουμε |
 * |---|---|---|
 * | `MissingTenantError` | ο αυτόνομος **δεν έχει** οργανισμό, **εκ σχεδιασμού** *(ADR-807)* | άδειο αποτέλεσμα, **καμία** γραμμή |
 * | οτιδήποτε άλλο | **βλάβη** | `logger.error` **και** ορατό `error` στην οθόνη |
 *
 * Ο **κριτής** που τις ξεχωρίζει ζει ήδη *(`routeTenantScopedError`, §21)*. Αυτό
 * που **έλειπε** ήταν το δεύτερο σκέλος: *ποιο μήνυμα, σε ποιο επίπεδο*. Ήταν
 * γραμμένο **μέσα** στη μηχανή *(`create-realtime-collection-hook`)* και
 * **πουθενά** στα τρία hooks με αντιδραστικό κλειδί — που έμειναν έξω από τη
 * μηχανή **με λόγο** *(το ερώτημά τους εξαρτάται από `buildingId`, γνήσια
 * επέκταση, όχι παραλλαγή)*.
 *
 * ⛔ **ΜΗΝ** το συγχωνεύσεις με το `tenant-scoped-error.ts`: εκείνο απαντά *«είναι
 * βλάβη;»* και δηλώνει ρητά ότι **δεν** παίρνει `logger`. Αυτό απαντά *«και τι
 * λέμε γι' αυτήν;»*. Δύο ερωτήματα, δύο σπίτια — ο κανόνας του §22.3.
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * @module services/realtime/hooks/subscription-error-handler
 * @see ./tenant-scoped-error.ts — ο κριτής «σχεδιασμένη κατάσταση ή βλάβη;»
 * @see docs/centralized-systems/reference/adrs/ADR-798-person-professional-identity.md §22
 */

import type { Logger } from '@/lib/telemetry';
import { routeTenantScopedError } from './tenant-scoped-error';

export interface SubscriptionErrorHandlerConfig {
  /** Ο καταγραφέας **του καλούντος** — η γραμμή λέει ποιος μίλησε. */
  readonly logger: Logger;
  /** Ποια συλλογή· μπαίνει σε κάθε γραμμή ώστε να μη χρειάζεται stack trace. */
  readonly collection: string;
  /**
   * «Δεν ανήκεις σε εταιρεία» ⇒ **υγιής** άδεια κατάσταση.
   *
   * ⚠️ Η **συνέπεια** μένει στον καλούντα: το «κενό» του καθενός είναι
   * διαφορετικό *(άδειος πίνακας · άδειο σύνολο · μηδενικός μετρητής)*.
   */
  readonly onDesignedEmpty: () => void;
  /** Πραγματική βλάβη ⇒ ό,τι δείχνει ο καλών στον άνθρωπο. */
  readonly onFailure: (message: string) => void;
}

/**
 * Ο **ένας** χειριστής σφάλματος συνδρομής: κρίνει, καταγράφει, ενημερώνει.
 *
 * ⚠️ Το `logger.error` καλείται **μόνο** στην πραγματική βλάβη. Αυτό είναι το
 * μάθημα του §21: κόκκινη γραμμή σε **σχεδιασμένη** κατάσταση δεν είναι
 * πληροφορία — είναι θόρυβος **που κρύβει τα αληθινά σφάλματα**.
 */
export function createSubscriptionErrorHandler(
  config: SubscriptionErrorHandlerConfig,
): (error: Error) => void {
  return (error: Error): void => {
    routeTenantScopedError(error, config.onDesignedEmpty, () => {
      config.logger.error('Realtime subscription error', {
        collection: config.collection,
        error: error.message,
      });
      config.onFailure(error.message);
    });
  };
}
