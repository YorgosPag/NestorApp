/**
 * ADR-798 §21 — **Η ΚΡΙΣΗ «σχεδιασμένη κατάσταση ή βλάβη;»**, μία φορά.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ — ΤΟ ΕΠΕΒΑΛΕ ΤΟ CHECK 3.28 (jscpd), ΜΕΣΑ ΣΤΟ ΙΔΙΟ COMMIT
 *
 * Ο αυτόνομος επαγγελματίας **δεν έχει** οργανισμό **εκ σχεδιασμού** (ADR-807).
 * Κάθε εταιρικό realtime ερώτημα του πετά `MissingTenantError`, ο κώδικας
 * ανακάμπτει σωστά — και το κατέγραφε ως **`[ERROR]`** σε **κάθε φόρτωση
 * σελίδας**. Ο θόρυβος **κρύβει τα αληθινά σφάλματα**.
 *
 * Το **ADR-809** το έλυσε σε **έναν** καταναλωτή. Ζωντανά 2026-08-26 βγήκε
 * **ξανά** από `useRealtimeProperties` — αδελφό που κανείς δεν κοίταξε:
 * μετρημένα **1 στους 5** ρωτούσε τον κριτή.
 *
 * ⚠️ Η πρώτη θεραπεία **επικόλλησε** το ίδιο μπλοκ σε τέσσερα αρχεία και το
 * `jscpd` το κατήγγειλε **αμέσως**: *«κεντρικοποιείς το Α, γράφεις Β+Γ ως
 * δίδυμα»* (N.18). Αυτό το module είναι η **εξαγωγή**, όχι τρίτο αντίγραφο.
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 ΤΙ ΜΕΝΕΙ ΕΞΩ, ΚΑΙ ΓΙΑΤΙ ΕΙΝΑΙ ΣΩΣΤΟ
 *
 * Οι **μεταβάσεις κατάστασης** μένουν στον καλούντα: το «κενό αποτέλεσμα» του
 * καθενός είναι **διαφορετικό** *(άδειος πίνακας · άδειος χάρτης · μηδενικός
 * μετρητής)*, και ένας κοινός setter θα απαιτούσε από κάθε hook να σχηματίσει
 * ένα ψεύτικο κοινό σχήμα. Κοινή είναι **η ΚΡΙΣΗ**, όχι η συνέπειά της.
 *
 * ⛔ **ΜΗΝ** προσθέσεις εδώ `logger`: ποιο μήνυμα και σε ποιο επίπεδο είναι
 * απόφαση του καλούντος. Αυτό το αρχείο απαντά **ένα** ερώτημα.
 *
 * @module services/realtime/hooks/tenant-scoped-error
 * @see docs/centralized-systems/reference/adrs/ADR-798-person-professional-identity.md §21
 * @see src/services/firestore/auth-context.ts — ο κριτής (`isMissingTenantError`)
 */

import { isMissingTenantError } from '@/services/firestore/auth-context';

/**
 * Δρομολογεί ένα σφάλμα realtime συνδρομής στη **σωστή** από τις δύο εκβάσεις.
 *
 * @param error            ό,τι έδωσε το `onSnapshot`
 * @param onDesignedEmpty  «δεν ανήκεις σε εταιρεία» ⇒ **κενό αποτέλεσμα, υγιής
 *                         κατάσταση**. Ποτέ σφάλμα, ποτέ θόρυβος.
 * @param onFailure        πραγματική βλάβη ⇒ ό,τι κάνει ο καλών σήμερα.
 *
 * ⚠️ **Brand, ποτέ σύγκριση κειμένου** — ο `isMissingTenantError` κρίνει την
 * ταυτότητα του σφάλματος και επιβιώνει τη σειριοποίηση (ADR-809 `Α5`).
 */
export function routeTenantScopedError(
  error: Error,
  onDesignedEmpty: () => void,
  onFailure: () => void,
): void {
  if (isMissingTenantError(error)) {
    onDesignedEmpty();
    return;
  }
  onFailure();
}
