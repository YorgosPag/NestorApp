/**
 * @fileoverview **Η ΠΟΡΤΑ ΤΟΥ ΚΑΤΑΛΟΓΟΥ** — η κρίση που κάνει την απουσία αδιάκριτη.
 * @related ADR-827 §9.4 · §9.6 #2 · services/realtime/hooks/usePublicAgencies
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΙ ΦΥΛΑΕΙ, ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΑΡΚΕΙ ΝΑ ΓΡΑΦΤΕΙ ΣΩΣΤΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η {@link agencyDoorFor} είναι **τρεις γραμμές**, και η «βελτίωσή» της είναι
 * φυσιολογική κίνηση: κάποιος που βλέπει `null` να γίνεται *«δεν υπάρχει»* θα σκεφτεί
 * ότι είναι πιο **ειλικρινές** να πει *«ο σύνδεσμος δεν λύθηκε»*. Θα ήταν — και θα
 * μετέτρεπε τη σελίδα σε **μαντείο**: σφάλμα για ανύπαρκτο ψευδώνυμο, «δεν
 * δημοσιεύεται» για υπαρκτό. Δηλαδή απαρίθμηση γραφείων, ένα ερώτημα τη φορά
 * (Ε-5 §4 #1 · §9.4).
 *
 * ⚠️ Ο κανόνας είναι **ιδιωτικότητας**, όχι εγκυρότητας εισόδου — γι' αυτό η άγκυρα
 * ρωτά *«απαντούν ΤΑΥΤΟΣΗΜΑ;»* και όχι *«απορρίπτει το κενό;»*.
 */

import { agencyDoorFor } from '../usePublicAgencies';

const REAL = 'comp_9c7c1a50-f370-466d-bdf7-aa7b2b2d7757';

describe('Π. Η πόρτα — «ρωτάμε καθόλου;»', () => {
  it('Π1 — λυμένο ψευδώνυμο ⇒ ρωτάμε, με την ταυτότητα άθικτη', () => {
    expect(agencyDoorFor(REAL)).toEqual({ kind: 'ask', companyId: REAL });
  });

  it('Π2 🔑 — ΑΛΥΤΟ ψευδώνυμο (`null`) και ΚΕΝΗ ταυτότητα απαντούν ΤΑΥΤΟΣΗΜΑ', () => {
    // 🔴 Η ΑΓΚΥΡΑ ΤΟΥ §9.4. Δεν ελέγχει «απορρίπτει το κενό;» — ελέγχει ότι οι δύο
    //    δρόμοι προς την απουσία είναι **ο ίδιος δρόμος**. Μια «πιο ειλικρινής»
    //    διάκριση εδώ (`error` για το `null`) θα περνούσε κάθε έλεγχο εγκυρότητας
    //    και θα άνοιγε το μαντείο.
    const unresolved = agencyDoorFor(null);
    const blank = agencyDoorFor('');
    const spaces = agencyDoorFor('   ');

    expect(unresolved).toEqual({ kind: 'absent' });
    expect(unresolved).toEqual(blank);
    expect(unresolved).toEqual(spaces);
  });

  it('Π3 — ΠΑΡΟΝΟΜΑΣΤΗΣ: υπαρκτή ταυτότητα ΔΕΝ απαντά `absent`', () => {
    // Χωρίς αυτό, ένα `agencyDoorFor = () => ({ kind: 'absent' })` θα περνούσε το Π2.
    expect(agencyDoorFor(REAL).kind).toBe('ask');
  });

  it('Π4 — τα περιθώρια κόβονται πριν φτάσουν στο `doc()`', () => {
    // ⚠️ Το Firestore ΔΕΝ κόβει κενά· ένα `doc(db, col, ' x ')` ψάχνει άλλο έγγραφο.
    expect(agencyDoorFor(`  ${REAL}  `)).toEqual({ kind: 'ask', companyId: REAL });
  });
});
