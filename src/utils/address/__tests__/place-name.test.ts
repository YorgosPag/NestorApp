/**
 * Άγκυρες του **ενός** κανόνα ονομάτων τόπου — ADR-332 D27 Βήμα Β (Β7).
 *
 * Η δεύτερη ομάδα **εκτελεί τους καταναλωτές** (διάλογος συρσίματος, γραμμή κάρτας): ένας κανόνας
 * που υπάρχει αλλά δεν τον ρωτά κανείς δεν διορθώνει τίποτα (ADR-749).
 */

import { cleanPlaceName, foldPlaceName, stripGreekAdminPrefix } from '../place-name';
import { formatContactAddressLine } from '../address-line';
import { diffAddressReplacement } from '@/components/shared/addresses/editor/helpers/diffAddressFields';

describe('place-name — ο ΕΝΑΣ κανόνας', () => {
  it.each([
    ['Δήμος Λαγκαδά', 'Λαγκαδά'],
    ['ΔΗΜΟΣ ΛΑΓΚΑΔΑ', 'ΛΑΓΚΑΔΑ'],
    ['Δημοτική Ενότητα Ελευθερίου Κορδελιού', 'Ελευθερίου Κορδελιού'],
    ['ΔΗΜΟΤΙΚΗ ΕΝΟΤΗΤΑ ΕΛΕΥΘΕΡΙΟΥ ΚΟΡΔΕΛΙΟΥ', 'ΕΛΕΥΘΕΡΙΟΥ ΚΟΡΔΕΛΙΟΥ'],
    ['Περιφέρεια Κεντρικής Μακεδονίας', 'Κεντρικής Μακεδονίας'],
    ['Περιφερειακή Ενότητα Θεσσαλονίκης', 'Θεσσαλονίκης'],
    ['Αποκεντρωμένη Διοίκηση Μακεδονίας-Θράκης', 'Μακεδονίας-Θράκης'],
  ])('πρόθεμα ΜΕ ή ΧΩΡΙΣ τόνους, κεφαλαία ή πεζά: «%s» → «%s»', (input, expected) => {
    expect(stripGreekAdminPrefix(input)).toBe(expected);
  });

  it('🔴 ΠΑΡΟΝΟΜΑΣΤΗΣ: «Δημοσθένους» ΔΕΝ είναι «Δήμος» — μόνο ολόκληρες λέξεις', () => {
    expect(stripGreekAdminPrefix('Δημοσθένους 5')).toBe('Δημοσθένους 5');
  });

  it('όνομα που είναι ΜΟΝΟ πρόθεμα μένει αυτούσιο (κενό όνομα θα ήταν χειρότερο)', () => {
    expect(stripGreekAdminPrefix('Δήμος')).toBe('Δήμος');
  });

  it('η παύλα και τα πολλαπλά κενά είναι ΓΡΑΦΗ, όχι όνομα', () => {
    expect(foldPlaceName('  Ελευθέριο-Κορδελιό  ')).toBe('Ελευθέριο Κορδελιό');
  });

  it('`cleanPlaceName` = ό,τι έκανε το `cleanNominatimName` του reverse route', () => {
    expect(cleanPlaceName('Δημοτική Ενότητα Ελευθερίου-Κορδελιού')).toBe('Ελευθερίου Κορδελιού');
  });
});

describe('οι ΚΑΤΑΝΑΛΩΤΕΣ του κανόνα', () => {
  it('Β7 — διάλογος συρσίματος: διαφορά ΜΟΝΟ στην παύλα ⇒ καμία γραμμή «αλλαγής»', () => {
    expect(diffAddressReplacement(
      { neighborhood: 'Ελευθέριο-Κορδελιό' },
      { neighborhood: 'Ελευθέριο Κορδελιό' },
    )).toEqual([]);
  });

  it('ΠΑΡΟΝΟΜΑΣΤΗΣ: πραγματική αλλαγή ονόματος ΜΕΝΕΙ αλλαγή', () => {
    expect(diffAddressReplacement(
      { neighborhood: 'Ελευθέριο Κορδελιό' },
      { neighborhood: 'Εύοσμος' },
    )).toHaveLength(1);
  });

  it('Β7 — η κάρτα: αποθηκευμένο «Σαμοθράκης » + «16» ⇒ «Σαμοθράκης, 16», χωρίς ορφανό κενό', () => {
    expect(formatContactAddressLine({ street: 'Σαμοθράκης ', number: '16' })).toBe('Σαμοθράκης, 16');
  });
});
