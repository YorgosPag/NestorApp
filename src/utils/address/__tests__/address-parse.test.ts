/**
 * @fileoverview ΑΓΚΥΡΑ — **η ανάλυση μιλάει μόνο με άγκυρα**, και η σιωπή της είναι τιμή.
 * @related utils/address/address-parse · ADR-777 §7 (Α14)
 *
 * 🔑 **Τι φυλάει**: όχι «τρέχει ο parser», αλλά τα **τέσσερα** πράγματα που μπορούν να
 * χαλάσουν σιωπηλά και να παραγάγουν **σημείο που μοιάζει σωστό**:
 *
 * 1. Η παγίδα των ελληνικών οδωνυμίων («**25ης** Μαρτίου 12») — ο αριθμός είναι ο
 *    **τελευταίος**, όχι ο πρώτος που συναντάς.
 * 2. Η κλοπή του αριθμού από τον Τ.Κ. («Εγνατίας **147 54622**»).
 * 3. Ο όροφος που περνιέται για αριθμό («3ος»).
 * 4. Η μαντεψιά όταν **δεν** υπάρχει άγκυρα («Σαμοθράκης» σκέτο) — εκεί η σωστή
 *    συμπεριφορά είναι **να μην αποφασίσει**.
 */

import {
  parseAddressLine,
  extractPostalCode,
  splitStreetAndNumber,
  isHouseNumberToken,
} from '../address-parse';

// =============================================================================
// Ο ΑΡΙΘΜΟΣ — η γραμματική
// =============================================================================

describe('isHouseNumberToken', () => {
  it.each(['16', '7', '234Α', '42α', '8-10', '12/14', '1234', '5Β', '3A'])(
    'δέχεται «%s»',
    (token) => {
      expect(isHouseNumberToken(token)).toBe(true);
    },
  );

  it.each([
    ['3ος', 'τακτικό αριθμητικό — ΔΥΟ γράμματα, δηλαδή όροφος'],
    ['25ης', 'τακτικό αριθμητικό οδωνυμίου'],
    ['54622', 'πέντε ψηφία — είναι Τ.Κ., όχι αριθμός'],
    ['Μαρτίου', 'λέξη'],
    ['', 'κενό'],
    ['16ος', 'όροφος με δύο γράμματα'],
  ])('απορρίπτει «%s» (%s)', (token) => {
    expect(isHouseNumberToken(token)).toBe(false);
  });
});

describe('splitStreetAndNumber', () => {
  it('«Σαμοθράκης 16» → οδός + αριθμός', () => {
    expect(splitStreetAndNumber('Σαμοθράκης 16')).toEqual({
      street: 'Σαμοθράκης',
      number: '16',
    });
  });

  it('🔴 «25ης Μαρτίου 12» — ο αριθμός είναι ο ΤΕΛΕΥΤΑΙΟΣ, η οδός μένει ακέραιη', () => {
    expect(splitStreetAndNumber('25ης Μαρτίου 12')).toEqual({
      street: '25ης Μαρτίου',
      number: '12',
    });
  });

  it('🔴 «25ης Μαρτίου» χωρίς αριθμό — ΔΕΝ κόβεται στη μέση', () => {
    expect(splitStreetAndNumber('25ης Μαρτίου')).toEqual({ street: '25ης Μαρτίου' });
  });

  it('«Λεωφ. Κηφισίας 234Α» — γράμμα στον αριθμό', () => {
    expect(splitStreetAndNumber('Λεωφ. Κηφισίας 234Α')).toEqual({
      street: 'Λεωφ. Κηφισίας',
      number: '234Α',
    });
  });

  it('🔴 σκέτο «16» — αριθμός χωρίς πράγμα ΔΕΝ γεννά οδό', () => {
    expect(splitStreetAndNumber('16')).toEqual({ street: '16' });
  });

  it('«Αριστοτέλους 5 3ος» — ο όροφος ΔΕΝ είναι αριθμός, άρα κανένας αριθμός', () => {
    expect(splitStreetAndNumber('Αριστοτέλους 5 3ος')).toEqual({
      street: 'Αριστοτέλους 5 3ος',
    });
  });
});

// =============================================================================
// Ο Τ.Κ. — η ισχυρότερη άγκυρα
// =============================================================================

describe('extractPostalCode', () => {
  it('ενιαία μορφή', () => {
    expect(extractPostalCode('Σαμοθράκης 16, 56334')).toEqual({
      postalCode: '56334',
      remainder: 'Σαμοθράκης 16',
    });
  });

  it('επίσημη μορφή ΕΛΤΑ με κενό → κανονικοποιείται', () => {
    expect(extractPostalCode('Τσιμισκή 43, 546 23')).toEqual({
      postalCode: '54623',
      remainder: 'Τσιμισκή 43',
    });
  });

  it('🔴 «Εγνατίας 147 54622» — ο Τ.Κ. ΔΕΝ κλέβει τον αριθμό της οδού', () => {
    expect(extractPostalCode('Εγνατίας 147 54622')).toEqual({
      postalCode: '54622',
      remainder: 'Εγνατίας 147',
    });
  });

  it('Τ.Κ. πριν την πόλη', () => {
    expect(extractPostalCode('Τσιμισκή 42, 54623 Θεσσαλονίκη')).toEqual({
      postalCode: '54623',
      remainder: 'Τσιμισκή 42, Θεσσαλονίκη',
    });
  });

  /**
   * ⚠️ **ΙΣΟΠΑΛΙΑ, ΟΧΙ ΑΜΥΝΑ.** Όταν η είσοδος περιέχει **και** τις δύο μορφές, κάποια
   * πρέπει να προηγηθεί. Ο αυτοτελής πενταψήφιος κερδίζει, γιατί το ζεύγος 3+2 μπορεί
   * να είναι αριθμός οδού· ο πενταψήφιος δεν είναι τίποτε άλλο. Χωρίς αυτή την άγκυρα η
   * απόφαση της σειράς ήταν **αφύλαχτη** — μετάλλαξη που την αντέστρεψε άφησε τα
   * υπόλοιπα 37 πράσινα (μετρημένο 2026-09-02).
   */
  it('ισοπαλία δύο μορφών — ο ΑΥΤΟΤΕΛΗΣ πενταψήφιος προηγείται', () => {
    expect(extractPostalCode('Λεωφ. Στρατού 128 40, 54621')).toEqual({
      postalCode: '54621',
      remainder: 'Λεωφ. Στρατού 128 40',
    });
  });

  it('χωρίς Τ.Κ. — το κείμενο επιστρέφεται ανέπαφο', () => {
    expect(extractPostalCode('Ερμού 15, Αθήνα')).toEqual({ remainder: 'Ερμού 15, Αθήνα' });
  });

  it('«Μελά 8 10» — δύο μικρές συστάδες ΔΕΝ είναι Τ.Κ.', () => {
    expect(extractPostalCode('Μελά 8 10')).toEqual({ remainder: 'Μελά 8 10' });
  });

  it('η αφαίρεση δεν αφήνει διπλό κόμμα ούτε κρεμασμένο κόμμα', () => {
    expect(extractPostalCode('Αθήνα, 11526, Ελλάδα').remainder).toBe('Αθήνα, Ελλάδα');
    expect(extractPostalCode('Αθήνα, 11526').remainder).toBe('Αθήνα');
  });
});

