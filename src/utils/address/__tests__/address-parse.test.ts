describe('parseAddressLine — με άγκυρα', () => {
  it('«Σαμοθράκης 16, 56334» — η αναφορά του ADR-777', () => {
    expect(parseAddressLine('Σαμοθράκης 16, 56334')).toEqual({
      street: 'Σαμοθράκης',
      number: '16',
      postalCode: '56334',
      city: undefined,
      reading: 'street-and-number',
    });
  });

  it('«Εγνατίας 147, Θεσσαλονίκη 54622»', () => {
    expect(parseAddressLine('Εγνατίας 147, Θεσσαλονίκη 54622')).toEqual({
      street: 'Εγνατίας',
      number: '147',
      postalCode: '54622',
      city: 'Θεσσαλονίκη',
      reading: 'street-and-number',
    });
  });

  it('τρία τμήματα — το υπόλοιπο μένει ΕΝΩΜΕΝΟ, δεν σπάει σε ιεραρχία', () => {
    expect(parseAddressLine('Σαμοθράκης 16, Εύοσμος, Θεσσαλονίκη')).toEqual({
      street: 'Σαμοθράκης',
      number: '16',
      postalCode: undefined,
      city: 'Εύοσμος, Θεσσαλονίκη',
      reading: 'street-and-number',
    });
  });
});

describe('parseAddressLine — ΧΩΡΙΣ άγκυρα: η σιωπή είναι η σωστή απάντηση', () => {
  it('🔴 σκέτο «Σαμοθράκης» — ΔΕΝ αποφασίζει αν είναι οδός ή τοπωνύμιο', () => {
    const parsed = parseAddressLine('Σαμοθράκης');
    expect(parsed.reading).toBe('unstructured');
    expect(parsed.street).toBeUndefined();
    expect(parsed.number).toBeUndefined();
    expect(parsed.city).toBe('Σαμοθράκης');
  });

  it('«Θεσσαλονίκη» — ίδια συμπεριφορά, γιατί είναι αδιάκριτο από το παραπάνω', () => {
    expect(parseAddressLine('Θεσσαλονίκη')).toEqual({
      postalCode: undefined,
      city: 'Θεσσαλονίκη',
      reading: 'unstructured',
    });
  });

  it('«Ερμού, Αθήνα» — χωρίς αριθμό, το κείμενο μένει ΟΛΟΚΛΗΡΟ στην πόλη', () => {
    expect(parseAddressLine('Ερμού, Αθήνα')).toEqual({
      postalCode: undefined,
      city: 'Ερμού, Αθήνα',
      reading: 'unstructured',
    });
  });

  it('Τ.Κ. χωρίς οδό — η μία άγκυρα κρατά, η άλλη όχι', () => {
    expect(parseAddressLine('Θεσσαλονίκη 54622')).toEqual({
      postalCode: '54622',
      city: 'Θεσσαλονίκη',
      reading: 'unstructured',
    });
  });

  it('κενό κείμενο', () => {
    expect(parseAddressLine('   ')).toEqual({ reading: 'unstructured' });
  });

  it('μόνο Τ.Κ.', () => {
    expect(parseAddressLine('56334')).toEqual({ postalCode: '56334', reading: 'unstructured' });
  });
});
