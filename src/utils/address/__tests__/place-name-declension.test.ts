/**
 * @fileoverview Άγκυρες του `samePlaceName` — ίδιος τόπος ανεξάρτητα από πρόθεμα, τόνο, σίγμα και πτώση.
 * @related utils/address/place-name · lib/geocoding/field-match · ADR-332 D28
 *
 * ⚠️ **Οι ΑΡΝΗΤΙΚΕΣ άγκυρες είναι η ουσία.** Μια ταύτιση που «πιάνει περισσότερα» είναι ακριβώς η
 * ανεκτικότητα που ο D27 μέτρησε να βγάζει **δήμο Χίου για το Χαλάνδρι**. Κάθε γραμμή του πίνακα
 * ζευγών πρέπει να κρατά αυτές πράσινες.
 */

/* global describe, it, expect */

import { samePlaceName } from '../place-name';

describe('samePlaceName — θετικά: ίδιος τόπος', () => {
  it.each([
    ['Θεσσαλονίκη', 'Μητροπολιτική Ενότητα Θεσσαλονίκης'], // το περιστατικό
    ['Θεσσαλονίκη', 'ΘΕΣΣΑΛΟΝΙΚΗΣ'],
    ['Αθήνα', 'Αθηνών'],
    ['Πειραιάς', 'Δήμος Πειραιά'],
    ['Πάτρα', 'Δήμος Πάτρας'],
    ['Βόλος', 'Βόλου'],
    ['Κορδελιό', 'Κορδελιού'],
    ['Αχαρνές', 'Δήμος Αχαρνών'],
    ['Ελευθέριο-Κορδελιό', 'Δημοτική Ενότητα Ελευθερίου - Κορδελιού'],
    ['Χαλάνδρι', 'Χαλανδρίου'],
  ])('«%s» ⇄ «%s»', (a, b) => {
    expect(samePlaceName(a, b)).toBe(true);
    expect(samePlaceName(b, a)).toBe(true);
  });
});

describe('samePlaceName — 🔴 αρνητικά: άλλος τόπος', () => {
  it.each([
    ['Χαλάνδρι', 'Χάλανδρα'], // κοινή ρίζα, -ι ⇄ -α ΔΕΝ είναι ζεύγος (D27: δήμος Χίου)
    ['Καλαμαριά', 'Καλαμάτα'],
    ['Σμύρνη', 'Νέα Σμύρνη'], // ποτέ «περιέχει»
    ['Καλαμαριά', 'Θεσσαλονίκη'],
    ['Άργος', 'Άργους Ορεστικού'],
    ['Ίος', 'Ίου'], // ρίζα κάτω από το ελάχιστο
    ['', 'Θεσσαλονίκη'],
  ])('«%s» ≠ «%s»', (a, b) => {
    expect(samePlaceName(a, b)).toBe(false);
  });
});
