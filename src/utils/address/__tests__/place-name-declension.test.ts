/**
 * @fileoverview Άγκυρες του `samePlaceName` — ίδιος τόπος ανεξάρτητα από πρόθεμα, τόνο, σίγμα και πτώση.
 * @related utils/address/place-name · lib/geocoding/field-match · ADR-332 D28
 *
 * ⚠️ **Οι ΑΡΝΗΤΙΚΕΣ άγκυρες είναι η ουσία.** Μια ταύτιση που «πιάνει περισσότερα» είναι ακριβώς η
 * ανεκτικότητα που ο D27 μέτρησε να βγάζει **δήμο Χίου για το Χαλάνδρι**. Κάθε γραμμή του πίνακα
 * ζευγών πρέπει να κρατά αυτές πράσινες.
 */

/* global describe, it, expect */

import { demoticPlaceNameForms, samePlaceName } from '../place-name';

describe('samePlaceName — θετικά: ίδιος τόπος', () => {
  it.each([
    ['Θεσσαλονίκη', 'Μητροπολιτική Ενότητα Θεσσαλονίκης'], // το περιστατικό
    ['Θεσσαλονίκη', 'ΘΕΣΣΑΛΟΝΙΚΗΣ'],
    ['Αθήνα', 'Αθηνών'],
    ['Πειραιάς', 'Δήμος Πειραιά'],
    ['Πάτρα', 'Δήμος Πάτρας'],
    ['Βόλος', 'Βόλου'],
    ['Κορδελιό', 'Κορδελιού'],
    ['Αχαρνές', 'Δήμος Αχαρνών'],
    ['Ελευθέριο-Κορδελιό', 'Δημοτική Ενότητα Ελευθερίου - Κορδελιού'],
    ['Χαλάνδρι', 'Χαλανδρίου'],
  ])('«%s» ⇄ «%s»', (a, b) => {
    expect(samePlaceName(a, b)).toBe(true);
    expect(samePlaceName(b, a)).toBe(true);
  });
});

describe('samePlaceName — 🔴 αρνητικά: άλλος τόπος', () => {
  it.each([
    ['Χαλάνδρι', 'Χάλανδρα'], // κοινή ρίζα, -ι ⇄ -α ΔΕΝ είναι ζεύγος (D27: δήμος Χίου)
    ['Καλαμαριά', 'Καλαμάτα'],
    ['Σμύρνη', 'Νέα Σμύρνη'], // ποτέ «περιέχει»
    ['Καλαμαριά', 'Θεσσαλονίκη'],
    ['Άργος', 'Άργους Ορεστικού'],
    ['Ίος', 'Ίου'], // ρίζα κάτω από το ελάχιστο
    ['', 'Θεσσαλονίκη'],
  ])('«%s» ≠ «%s»', (a, b) => {
    expect(samePlaceName(a, b)).toBe(false);
  });
});

/**
 * ADR-332 D31 — **καθαρεύουσα ⇄ δημοτική**. Το περιστατικό: ο οικισμός ΕΛΣΤΑΤ «Ωραιόκαστρον» δεν
 * ταυτιζόταν με το «Ωραιόκαστρο» του OSM, και η έδρα έπεφτε σε «δεν βρέθηκε». ~21% του μητρώου.
 */
describe('samePlaceName — καθαρεύουσα: ίδιος τόπος (D31)', () => {
  it.each([
    ['Ωραιόκαστρον', 'Ωραιόκαστρο'], // το περιστατικό
    ['ΩΡΑΙΟΚΑΣΤΡΟΝ', 'Ωραιόκαστρο'],
    ['Μεσοχώριον', 'Μεσοχώρι'],
    ['Προσήλιον', 'Προσήλιο'],
    ['Λουτρόν', 'Λουτρό'],
    ['Θερμοπύλαι', 'Θερμοπύλες'],
    ['Νέον Μοναστήριον', 'Νέο Μοναστήρι'],
    ['Νέαι Κυδωνίαι', 'Νέες Κυδωνίες'], // ανά λέξη — μετρημένη αστοχία του σχεδίου
  ])('«%s» ⇄ «%s»', (a, b) => {
    expect(samePlaceName(a, b)).toBe(true);
    expect(samePlaceName(b, a)).toBe(true);
  });
});

describe('samePlaceName — 🔴 καθαρεύουσα: άλλος τόπος (D31)', () => {
  it.each([
    ['Μελίσσιον', 'Μελίσσια'], // -ιον ⇄ -ια ΔΕΝ είναι ζεύγος: το Μελίσσι δεν είναι τα Μελίσσια Αττικής
    ['Ωραιόκαστρον', 'Ωραιόκαστρα'],
    ['Λουτρόν', 'Λουτρά'], // Λουτρό ≠ Λουτρά
    ['Πέτραι', 'Πέτρα'],
    ['Νέον Μοναστήριον', 'Μοναστήρι'], // ποτέ «περιέχει»
  ])('«%s» ≠ «%s»', (a, b) => {
    expect(samePlaceName(a, b)).toBe(false);
  });
});

describe('demoticPlaceNameForms — η μορφή που ξέρει ο χάρτης (D31)', () => {
  it.each([
    ['Ωραιόκαστρον', ['Ωραιόκαστρο']],
    ['ΩΡΑΙΟΚΑΣΤΡΟΝ', ['ΩΡΑΙΟΚΑΣΤΡΟ']],
    // Η σειρά είναι ΜΕΤΡΗΜΕΝΗ: «-ι» 12/12 στο OSM, «-ιο» 2/12 — πρώτα το «-ι».
    ['Μεσοχώριον', ['Μεσοχώρι', 'Μεσοχώριο']],
    ['Λουτρόν', ['Λουτρό']],
    ['Καρυώται', ['Καρυώτες']],
    ['Νέον Μοναστήριον', ['Νέο Μοναστήρι', 'Νέο Μοναστήριο']],
    ['Νέαι Κυδωνίαι', ['Νέες Κυδωνίες']],
    // 🔴 Δίφθογγος + «ιον» ⇒ ΜΟΝΟ «-ιο» (μετρημένο: «Λατομεί» 0, «Νυμφαί» 0).
    ['Λατομείον', ['Λατομείο']],
    ['Νυμφαίον', ['Νυμφαίο']],
    ['Αμύνταιον', ['Αμύνταιο']],
    ['Αγροτικόν Ορφανοτροφείον', ['Αγροτικό Ορφανοτροφείο']],
  ])('«%s» → %j', (name, forms) => {
    expect(demoticPlaceNameForms(name)).toEqual(forms);
  });

  it.each(['Θεσσαλονίκη', 'Ωραιόκαστρο', 'Αθήνα', 'Ίον', ''])('«%s» → [] (όχι καθαρεύουσα)', (name) => {
    expect(demoticPlaceNameForms(name)).toEqual([]);
  });

  it('κάθε μορφή ταυτίζεται με το πρωτότυπο — η γραφή και η σύγκριση βγαίνουν από ΕΝΑ πίνακα', () => {
    for (const name of ['Ωραιόκαστρον', 'Μεσοχώριον', 'Νέαι Κυδωνίαι', 'Αγροτικόν Ορφανοτροφείον']) {
      for (const form of demoticPlaceNameForms(name)) expect(samePlaceName(name, form)).toBe(true);
    }
  });
});
