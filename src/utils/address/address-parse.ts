/**
 * Διαβάζει μια γραμμή διεύθυνσης όπως τη γράφει άνθρωπος.
 *
 * ```
 * «Σαμοθράκης 16, 56334»            → street Σαμοθράκης · number 16 · postalCode 56334
 * «Εγνατίας 147, Θεσσαλονίκη 54622» → + city Θεσσαλονίκη
 * «Θεσσαλονίκη»                     → city Θεσσαλονίκη · reading 'unstructured'
 * ```
 *
 * ⚠️ Στο `'unstructured'` **δεν** υπάρχει `street`: το κείμενο μπαίνει ολόκληρο στην
 * `city`, που είναι **ακριβώς** ό,τι έκανε ο καλών πριν από αυτό το αρχείο. Καμία
 * παλινδρόμηση δεν είναι δυνατή σε αυτή τη διαδρομή — δες την επικεφαλίδα.
 */
export function parseAddressLine(raw: string): ParsedAddressLine {
  const trimmed = raw.trim();
  if (trimmed === '') return { reading: 'unstructured' };

  const { postalCode, remainder } = extractPostalCode(trimmed);
  const segments = remainder
    .split(',')
    .map((segment) => segment.trim())
    .filter((segment) => segment !== '');

  if (segments.length === 0) return { postalCode, reading: 'unstructured' };

  const { street, number } = splitStreetAndNumber(segments[0]);
  if (number === undefined) {
    return { postalCode, city: segments.join(', '), reading: 'unstructured' };
  }

  const rest = segments.slice(1).join(', ');
  return {
    street,
    number,
    postalCode,
    city: rest === '' ? undefined : rest,
    reading: 'street-and-number',
  };
}
