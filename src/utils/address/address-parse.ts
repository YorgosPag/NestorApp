import { toCanonicalGreekPostalCode } from './postal-code';

/**
 * **Τι κατάφερε να διαβάσει** η ανάλυση — ποτέ «πόσο σίγουρη είναι».
 *
 * Δύο τιμές επίτηδες, όχι κλίμακα: ή υπάρχει η άγκυρα του αριθμού, ή δεν υπάρχει.
 * Μια ενδιάμεση βαθμίδα («μάλλον οδός») θα ήταν ακριβώς η μαντεψιά που το αρχείο αρνείται.
 */
export type AddressLineReading = 'street-and-number' | 'unstructured';

/**
 * Ό,τι διαβάστηκε από τη γραμμή. **Κάθε πεδίο λείπει όταν δεν διαβάστηκε** — ποτέ κενή
 * συμβολοσειρά: το `''` και το «δεν ξέρω» είναι διαφορετικά πράγματα, και το πρώτο
 * ταξιδεύει αθόρυβα μέσα από κάθε έλεγχο αλήθειας.
 */
export interface ParsedAddressLine {
  readonly street?: string;
  readonly number?: string;
  /** **Κανονική μορφή** (5 ψηφία, χωρίς κενό) — ADR-332 D16. */
  readonly postalCode?: string;
  /**
   * Ό,τι απέμεινε, **ενωμένο ως έχει**. Δες την ιδιότητα ταυτότητας στην επικεφαλίδα:
   * το σπάσιμο σε ιεραρχία θα πετούσε κείμενο από το ερώτημα που απαντά.
   */
  readonly city?: string;
  readonly reading: AddressLineReading;
}

