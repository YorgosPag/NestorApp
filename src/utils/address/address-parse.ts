// ΑΡΙΘΜΟΣ — η γραμματική, σε ένα σημείο
// =============================================================================

/**
 * Πότε ένα λεκτικό **είναι** αριθμός διεύθυνσης.
 *
 * «16» · «234Α» · «42α» · «8-10» · «12/14»
 *
 * ⚠️ **Το γράμμα είναι ΕΝΑ, και αυτό είναι η άμυνα απέναντι στα τακτικά αριθμητικά**:
 * το «3ος» *(όροφος)* έχει **δύο** γράμματα ⇒ απορρίπτεται. Ένα «οσαδήποτε γράμματα»
 * θα το δεχόταν και θα έκανε τον όροφο αριθμό διεύθυνσης.
 *
 * ⚠️ **Τέσσερα ψηφία το πολύ**: ο πενταψήφιος είναι Τ.Κ., και η άγκυρά του
 * προηγείται ({@link extractPostalCode}).
 */
const HOUSE_NUMBER_TOKEN = /^\d{1,4}(?:[-–—/]\d{1,4})?[Α-Ωα-ωΆ-ώA-Za-z]?$/;

/** Είναι αυτό το λεκτικό αριθμός διεύθυνσης; Δες {@link HOUSE_NUMBER_TOKEN}. */
export function isHouseNumberToken(token: string): boolean {
  return HOUSE_NUMBER_TOKEN.test(token.trim());
}

/**
 * «Σαμοθράκης 16» → οδός + αριθμός. Χωρίς αριθμό, **η οδός επιστρέφεται ακέραιη**.
 *
 * 🔑 **Κρίνει το ΤΕΛΕΥΤΑΙΟ λεκτικό, όχι το πρώτο που μοιάζει με αριθμό** — και αυτό
 * είναι ολόκληρη η παγίδα των ελληνικών οδωνυμίων: «**25ης** Μαρτίου 12», «**28ης**
 * Οκτωβρίου 45», «**2ας** Μαΐου». Μια αναζήτηση «βρες ψηφία» θα έκοβε την οδό στη μέση.
 *
 * ⚠️ **Απαιτούνται δύο λεκτικά**: σκέτο «16» δεν είναι διεύθυνση — είναι αριθμός χωρίς
 * πράγμα, και η οδός δεν επιτρέπεται να προκύψει από το πουθενά.
 */
export function splitStreetAndNumber(segment: string): {
  readonly street: string;
  readonly number?: string;
} {
  const tokens = segment.trim().split(/\s+/).filter((token) => token !== '');
  if (tokens.length < 2) return { street: segment.trim() };

  const last = tokens[tokens.length - 1];
  if (!isHouseNumberToken(last)) return { street: segment.trim() };

  return { street: tokens.slice(0, -1).join(' '), number: last };
}

// =============================================================================
// Τ.Κ. — η ισχυρότερη άγκυρα, και ΓΙ' ΑΥΤΟ κρίνεται πρώτη
// =============================================================================

/** Πέντε ψηφία, πρώτο 1-9 — η κανονική μορφή του {@link toCanonicalGreekPostalCode}. */
const CANONICAL_DIGITS = 5;
/** Η επίσημη γραφή ΕΛΤΑ σπάει σε **3 + 2**. */
const SPACED_HEAD_DIGITS = 3;
const SPACED_TAIL_DIGITS = 2;

interface DigitRun {
  readonly text: string;
  readonly start: number;
  readonly end: number;
}

/** Οι συστάδες ψηφίων του κειμένου, με τις θέσεις τους. Καμία ερμηνεία εδώ. */
function digitRuns(text: string): DigitRun[] {
  const runs: DigitRun[] = [];
  const pattern = /\d+/g;
  let match = pattern.exec(text);
  while (match !== null) {
    runs.push({ text: match[0], start: match.index, end: match.index + match[0].length });
    match = pattern.exec(text);
  }
  return runs;
}

const startsWithNonZero = (run: DigitRun): boolean => run.text[0] !== '0';

/**
 * Βρίσκει τον Τ.Κ. και **τον αφαιρεί** από το κείμενο.
 *
 * 🔴 **ΤΙ ΕΜΠΟΔΙΖΕΙ ΤΗΝ ΚΛΟΠΗ ΤΟΥ ΑΡΙΘΜΟΥ — και ΔΕΝ είναι η σειρά.** Στο «Εγνατίας
 * **147 54622**» το προφανές regex «τρία ψηφία, κενό, δύο ψηφία» ταιριάζει στο
 * «**147 54**»: κλέβει τον **αριθμό της οδού** και αφήνει πίσω σκουπίδια («622»). Αυτό
 * που το εμποδίζει είναι ότι οι συστάδες του {@link digitRuns} είναι **ΜΕΓΙΣΤΕΣ** — το
 * «54622» δεν σπάει **ποτέ** σε «54» + «622», άρα το ζεύγος 3+2 δεν μπορεί καν να
 * σχηματιστεί. Η άμυνα είναι **δομική**, όχι θέμα προτεραιότητας.
 *
 * ⚠️ **ΜΕΤΡΗΜΕΝΟ, ΟΧΙ ΥΠΟΤΙΘΕΜΕΝΟ** (2026-09-02): αυτή η παράγραφος έγραφε αρχικά ότι
 * *«η σειρά είναι διόρθωση σφάλματος»*. **Μετάλλαξη που αντέστρεψε τη σειρά άφησε και
 * τις 37 άγκυρες πράσινες** — δηλαδή η αιτιολογία ήταν λάθος. Μετάλλαξη που
 * αντικατέστησε τη σάρωση συστάδων με το αφελές regex **κοκκίνισε αμέσως**. Η σειρά
 * είναι **ισοπαλία** για είσοδο που έχει *και* τις δύο μορφές (π.χ. «128 40, 54621»),
 * και ο πενταψήφιος προηγείται γιατί είναι **αυτοτελής**· δεν είναι άμυνα.
 *
 * ⚠️ **Χωρίς `lookbehind`, επίτηδες**: το αρχείο τρέχει και στον πελάτη, και οι
 * συστάδες ψηφίων απαντούν στην ίδια ερώτηση με τιμές αντί για διάλεκτο regex.
 */
export function extractPostalCode(text: string): {
  readonly postalCode?: string;
  readonly remainder: string;
} {
  const runs = digitRuns(text);

  const canonical = runs.find(
    (run) => run.text.length === CANONICAL_DIGITS && startsWithNonZero(run),
  );
  if (canonical) {
    return { postalCode: canonical.text, remainder: cut(text, canonical.start, canonical.end) };
  }

  for (let index = 0; index < runs.length - 1; index += 1) {
    const head = runs[index];
    const tail = runs[index + 1];
    const spacedPair =
      head.text.length === SPACED_HEAD_DIGITS &&
      tail.text.length === SPACED_TAIL_DIGITS &&
      startsWithNonZero(head) &&
      /^\s$/.test(text.slice(head.end, tail.start));
    if (spacedPair) {
      return {
        postalCode: toCanonicalGreekPostalCode(`${head.text} ${tail.text}`),
        remainder: cut(text, head.start, tail.end),
      };
    }
  }

  return { remainder: text };
}

/**
 * Κόβει ένα διάστημα και **επουλώνει** ό,τι μένει: το «Θεσσαλονίκη 54622» δεν
 * επιτρέπεται να γίνει «Θεσσαλονίκη » ούτε το «Αθήνα, 11526, Ελλάδα» να αφήσει
 * κόμμα δίπλα σε κόμμα — τα δύο κόμματα θα γεννούσαν **κενό τμήμα**, δηλαδή
 * φάντασμα τοπωνυμίου.
 */
function cut(text: string, start: number, end: number): string {
  return `${text.slice(0, start)}${text.slice(end)}`
    .replace(/\s*,\s*,/g, ',')
    .replace(/\s{2,}/g, ' ')
    .replace(/^[\s,]+|[\s,]+$/g, '')
    .trim();
}

