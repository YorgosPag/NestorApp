import { normalizeGreekText } from '@/utils/greek-text';

/**
 * **ΤΟ ΕΝΑ ΔΙΠΛΩΜΑ ΟΝΟΜΑΤΟΣ ΤΟΠΟΥ** — η μορφή στην οποία **συγκρίνονται** ονόματα τόπων,
 * ποτέ η μορφή που αποθηκεύεται.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 **ΤΟ ΤΕΛΙΚΟ ΣΙΓΜΑ ΕΙΝΑΙ ΠΑΓΙΔΑ ΜΕ ΧΡΟΝΟΚΑΘΥΣΤΕΡΗΣΗ — ΜΕΤΡΗΜΕΝΟ 2026-09-12**
 *
 * Το `toLowerCase()` της JavaScript υλοποιεί τον κανόνα **τελικού σίγμα** του Unicode:
 * `'ΔΗΜΟΣ'.toLowerCase()` δίνει `ς` *(U+03C2)*, όχι `σ` *(U+03C3)*. Τα ελληνικά τοπωνύμια
 * είναι συντριπτικά σε **γενική** και άρα λήγουν σε σίγμα, οπότε αυτό αφορά **το μεγαλύτερο
 * μέρος του μητρώου**.
 *
 * ⚠️ Και το ίδιο το `administrative-hierarchy.json` είναι **ΕΣΩΤΕΡΙΚΑ ΑΣΥΝΕΠΕΣ**: το
 * προϋπολογισμένο του `nn` διαφέρει από κάθε δίπλωμα της εφαρμογής σε **6.333 από 20.720**
 * ονόματα *(**30,6%**)* — **6.187** από αυτά **ακριβώς** στο `ς` vs `σ` *(το `δημος λαγκαδα`
 * έχει `ς`, το `αττικησ` έχει `σ`: άλλες γραμμές γράφτηκαν από Python, άλλες από JS)*.
 * ⛔ **ΜΗΝ κλειδώσεις ευρετήριο στο `nn`** — χάνει σιωπηλά το 30,6% του μητρώου.
 *
 * 🔴 **Η ΑΠΟΤΥΧΙΑ ΕΙΝΑΙ ΣΙΩΠΗΛΗ ΚΑΙ ΥΠΟΒΑΘΜΙΖΕΤΑΙ ΠΡΟΣ ΤΗ ΛΑΘΟΣ ΚΑΤΕΥΘΥΝΣΗ**: η ακριβής
 * αντιστοίχιση αστοχεί, οπότε ενεργοποιείται η **ανεκτική** βαθμίδα — αυτή που δεν
 * εμπιστευόμαστε. Δηλαδή ένας αόρατος χαρακτήρας μετατρέπει «απόδειξη» σε «μαντεψιά».
 *
 * ⚠️ **ΤΟ ΔΙΠΛΩΜΑ ΕΦΑΡΜΟΖΕΤΑΙ ΚΑΙ ΣΤΟΥΣ ΠΙΝΑΚΕΣ ΣΤΑΘΕΡΩΝ, ΟΧΙ ΜΟΝΟ ΣΤΑ ΔΕΔΟΜΕΝΑ.**
 * Μετρημένο στο ίδιο μου το εργαλείο μέτρησης: με τον πίνακα προθεμάτων γραμμένο με `ς`
 * και τα δεδομένα διπλωμένα σε `σ`, **14 από 14** ετικέτες βγήκαν «αδήλωτο επίπεδο».
 * Γι' αυτό το {@link ADMIN_LEVEL_PREFIXES} διπλώνεται **μία φορά στη φόρτωση**.
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * ⚠️ **ΓΙΑΤΙ ΟΧΙ `normalizeForSearch`** *(`utils/greek-text.ts`)*: εκείνο πετά `.-_/\()`
 * αλλά **δεν** ενοποιεί το σίγμα και **δεν** πετά το κόμμα — και το επίπεδο 2 του μητρώου
 * έχει **και** κόμμα **και** παύλα *(«ΑΠΟΚΕΝΤΡΩΜΕΝΗ ΔΙΟΙΚΗΣΗ ΠΕΛΟΠΟΝΝΗΣΟΥ, ΔΥΤΙΚΗΣ
 * ΕΛΛΑΔΑΣ ΚΑΙ ΙΟΝΙΟΥ»)*. Είναι δίπλωμα **ταυτότητας τόπου**, όχι γενικής αναζήτησης.
 */
export function foldPlaceIdentity(name: string): string {
  return normalizeGreekText(name)
    .replace(/ς/g, 'σ')
    .replace(/[-,()]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * **ΤΟ ΠΡΟΘΕΜΑ ΔΗΛΩΝΕΙ ΤΟ ΕΠΙΠΕΔΟ** — ο ένας πίνακας, με τη βαθμίδα του καθενός.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 **ΓΙΑΤΙ Ο ΠΙΝΑΚΑΣ ΑΠΕΚΤΗΣΕ ΔΕΥΤΕΡΗ ΣΤΗΛΗ** *(ADR-332 D27 Φάση Β′)*
 *
 * Το μητρώο αποθηκεύει τα επίπεδα **2–7 ΜΑΖΙ με το πρόθεμά τους** — μετρημένο:
 * `L2 «ΑΠΟΚΕΝΤΡΩΜΕΝΗ ΔΙΟΙΚΗΣΗ …»` · `L3 «ΠΕΡΙΦΕΡΕΙΑ …»` · `L4 «ΠΕΡΙΦΕΡΕΙΑΚΗ ΕΝΟΤΗΤΑ …»` ·
 * `L5 «ΔΗΜΟΣ …»` · `L6 «ΔΗΜΟΤΙΚΗ ΕΝΟΤΗΤΑ …»` · `L7 «Δημοτική/Τοπική Κοινότητα …»`.
 * Άρα το πρόθεμα δεν είναι θόρυβος προς αφαίρεση: είναι **η δήλωση της βαθμίδας**, και
 * χωρίς αυτή κάθε ετικέτα ρωτιέται στο επίπεδο 8 *(οικισμός)*, **όπου αυτή η μορφή
 * ονόματος δεν υπάρχει καν**.
 *
 * 🔴 **Το κόστος της αφαίρεσης, μετρημένο**: «Χαλάνδρι» → «Χάλανδρα» **ΔΗΜΟΣ ΧΙΟΥ** ·
 * «Παγκράτι» → «Παγκράται» **ΔΗΜΟΣ ΣΟΥΛΙΟΥ** · «Ιλίσια» → «Φιλίσια» **ΔΗΜΟΣ ΑΡΧΑΝΩΝ**.
 * Με τη βαθμίδα δηλωμένη, **καμία** από αυτές τις ετικέτες δεν ρωτιέται στο λάθος επίπεδο.
 *
 * ⚠️ **«ΜΗΤΡΟΠΟΛΙΤΙΚΗ ΕΝΟΤΗΤΑ» ΕΙΝΑΙ ΤΟΥ OSM, ΟΧΙ ΤΗΣ ΕΛΣΤΑΤ** *(μετρημένο: το Nominatim
 * το στέλνει για Θεσσαλονίκη/Αττική, το μητρώο γράφει «ΠΕΡΙΦΕΡΕΙΑΚΗ ΕΝΟΤΗΤΑ»)*. Μπαίνει
 * επειδή **δηλώνει σωστά τη βαθμίδα**· το ότι το **όνομα** δεν θα βρεθεί είναι σωστή
 * απάντηση *(«απόν»)*, όχι αστοχία — και είναι **ακριβώς** ο λόγος που δεν μαντεύουμε.
 *
 * ⚠️ Τα **διπλά** προθέματα πριν από τα μονά, ώστε το «Δημοτική Ενότητα» να μη διαβαστεί
 * ποτέ ως «Δήμος» + υπόλοιπο, και το «Περιφερειακή Ενότητα» ποτέ ως «Περιφέρεια».
 * ⚠️ Το **επίπεδο 1** *(«ΒΟΡΕΙΑ ΕΛΛΑΔΑ», 5 εγγραφές)* και το **8** *(οικισμός)* είναι
 * **αδήλωτα** — δεν φέρουν πρόθεμα, και το δηλώνουμε με την απουσία γραμμής.
 *
 * 🔑 **Η ΓΡΑΠΤΗ ΜΟΡΦΗ ΕΙΝΑΙ Η ΠΗΓΗ, Η ΔΙΠΛΩΜΕΝΗ ΠΑΡΑΓΕΤΑΙ** *(ADR-893)*: ο γεννήτορας των
 * ονομάτων εμφάνισης γράφει «Δήμος Αθηναίων» από το «ΔΗΜΟΣ ΑΘΗΝΑΙΩΝ» ρωτώντας **αυτόν** τον
 * πίνακα — ένα δεύτερο λεξιλόγιο προθεμάτων θα διαφωνούσε κάποτε με τον κριτή της βαθμίδας.
 * ═════════════════════════════════════════════════════════════════════════════
 */
const ADMIN_LEVEL_PREFIXES: readonly { readonly written: string; readonly level: number }[] = [
  { written: 'Αποκεντρωμένη Διοίκηση', level: 2 },
  { written: 'Περιφερειακή Ενότητα', level: 4 },
  { written: 'Μητροπολιτική Ενότητα', level: 4 },
  { written: 'Δημοτική Ενότητα', level: 6 },
  { written: 'Δημοτική Κοινότητα', level: 7 },
  { written: 'Τοπική Κοινότητα', level: 7 },
  { written: 'Περιφέρεια', level: 3 },
  { written: 'Δήμος', level: 5 },
] as const;

/** Τα προθέματα ως καθαρές λέξεις (`normalizeGreekText`) — η **μία** πηγή για αφαίρεση και βαθμίδα. */
const ADMIN_PREFIX_WORDS: readonly { readonly written: string; readonly words: readonly string[]; readonly level: number }[] =
  ADMIN_LEVEL_PREFIXES.map(({ written, level }) => ({ written, words: normalizeGreekText(written).split(' '), level }));

/**
 * Ο ίδιος πίνακας, **διπλωμένος μία φορά** — βλ. την προειδοποίηση του
 * {@link foldPlaceIdentity} για το τι κοστίζει η παράλειψη.
 */
const ADMIN_PREFIXES_FOLDED: readonly { readonly words: readonly string[]; readonly level: number }[] =
  ADMIN_PREFIX_WORDS.map(({ words, level }) => ({ words: words.map(foldPlaceIdentity), level }));

/**
 * **Ποια βαθμίδα δηλώνει αυτή η ετικέτα;** — `null` όταν δεν δηλώνει καμία.
 *
 * 🔑 `null` σημαίνει **«αδήλωτη βαθμίδα»**, ΠΟΤΕ «οικισμός». Η διαφορά είναι ολόκληρη η
 * ασφάλεια: μια αδήλωτη ετικέτα *(«Κολωνάκι», «Χαλάνδρι», «Λαδάδικα»)* συνήθως **δεν
 * υπάρχει** στο μητρώο, και το να τη ρωτήσουμε «στο 8, αφού δεν είπε τίποτα» είναι
 * ακριβώς η μαντεψιά που παράγει δήμο Χίου για προάστιο της Αθήνας.
 */
export function declaredAdminLevel(label: string): number | null {
  const words = foldPlaceIdentity(label).split(' ');
  for (const { words: prefix, level } of ADMIN_PREFIXES_FOLDED) {
    if (words.length > prefix.length && prefix.every((part, i) => words[i] === part)) {
      return level;
    }
  }
  return null;
}

/** Ένα όνομα χωρισμένο στο πρόθεμα της βαθμίδας του και στο υπόλοιπο. */
export interface AdminPrefixSplit {
  /** Το πρόθεμα **όπως γράφεται** («Δήμος»), από τον πίνακα — όχι όπως ήρθε («ΔΗΜΟΣ»). */
  readonly written: string;
  readonly level: number;
  /** Το υπόλοιπο **αυτούσιο**, με τη δική του στίξη («ΜΑΚΕΔΟΝΙΑΣ - ΘΡΑΚΗΣ»). */
  readonly rest: string;
}

/**
 * **Ποιο πρόθεμα βαθμίδας έχει αυτό το όνομα, και τι μένει;** — `null` χωρίς πρόθεμα.
 *
 * ⚠️ **Μόνο στην αρχή και μόνο ολόκληρες λέξεις**: το «Δημοσθένους 5» δεν χάνει τίποτα.
 * ⚠️ Όνομα που είναι **μόνο** πρόθεμα («Δήμος») δεν χωρίζεται — ένα κενό όνομα θα ήταν χειρότερο.
 */
export function splitAdminPrefix(name: string): AdminPrefixSplit | null {
  const words = name.trim().split(/\s+/);
  const folded = words.map((word) => normalizeGreekText(word));
  for (const { written, words: prefix, level } of ADMIN_PREFIX_WORDS) {
    if (words.length > prefix.length && prefix.every((part, i) => folded[i] === part)) {
      return { written, level, rest: words.slice(prefix.length).join(' ') };
    }
  }
  return null;
}

/**
 * **Ένα σύντομο όνομα με το πρόθεμα βαθμίδας ενός πλήρους** — «Δημοτική Ενότητα Σταγίρων-Ακάνθου» +
 * «ΣΤΑΓΕΙΡΩΝ-ΑΚΑΝΘΟΥ» → «Δημοτική Ενότητα ΣΤΑΓΕΙΡΩΝ-ΑΚΑΝΘΟΥ». Έτσι τα εναλλακτικά ονόματα (`an`, σύντομα
 * όπως το `sn`) μπαίνουν σε ευρετήριο **πλήρων** ονομάτων με την ίδια δήλωση βαθμίδας (ADR-893 §7).
 */
export function withAdminPrefixOf(fullName: string, shortName: string): string {
  const split = splitAdminPrefix(fullName);
  return split === null ? shortName : `${split.written} ${shortName}`;
}

/** Αφαιρεί το διοικητικό πρόθεμα: «Δήμος Λαγκαδά» / «ΔΗΜΟΣ ΛΑΓΚΑΔΑ» → «Λαγκαδά» / «ΛΑΓΚΑΔΑ». */
export function stripGreekAdminPrefix(name: string): string {
  return splitAdminPrefix(name)?.rest ?? name.trim();
}

/**
 * **ΖΕΥΓΗ ΚΑΤΑΛΗΞΕΩΝ ΤΟΠΩΝΥΜΙΩΝ** — ονομαστική ⇄ γενική, σε **διπλωμένη** μορφή (`σ`, χωρίς τόνους).
 *
 * 🔴 **ΖΕΥΓΗ, ΟΧΙ ΛΙΣΤΑ ΚΑΤΑΛΗΞΕΩΝ — ΜΕΤΡΗΜΕΝΟ ΣΤΟ ΣΧΕΔΙΟ, 2026-09-14** (ADR-332 D28).
 * Η προφανής λύση *(«κόψε ό,τι κατάληξη βρεις και σύγκρινε ρίζες»)* κάνει **Χαλάνδρι = Χάλανδρα**
 * (ρίζα `χαλανδρ` και στα δύο) — το ίδιο ζεύγος που ο D27 κατέγραψε ως **δήμο Χίου για προάστιο της
 * Αθήνας**. Εδώ δύο λέξεις ταυτίζονται μόνο αν διαφέρουν **κατά ένα γνωστό ζεύγος** πάνω σε **κοινή**
 * ρίζα: `-ι ⇄ -α` δεν είναι ζεύγος, άρα Χαλάνδρι ≠ Χάλανδρα.
 *
 * ⚠️ **Κλειστός πίνακας, επίτηδες.** Κάθε νέα γραμμή διευρύνει το τι «ταυτίζεται» — προσθήκη μόνο με
 * περιστατικό και αρνητική άγκυρα (`__tests__/place-name-declension.test.ts`).
 */
const DECLENSION_PAIRS: readonly (readonly [string, string])[] = [
  ['η', 'ησ'], // Θεσσαλονίκη ⇄ Θεσσαλονίκης
  ['α', 'ασ'], // Πάτρα ⇄ Πάτρας
  ['ασ', 'α'], // Πειραιάς ⇄ Πειραιά
  ['α', 'ων'], // Αθήνα ⇄ Αθηνών
  ['οσ', 'ου'], // Βόλος ⇄ Βόλου
  ['ο', 'ου'], // Κορδελιό ⇄ Κορδελιού
  ['ι', 'ιου'], // Χαλάνδρι ⇄ Χαλανδρίου
  ['οι', 'ων'], // Μελισσοχώρι… / Άνω Λιόσια ⇄ Άνω Λιοσίων
  ['εσ', 'ων'], // Αχαρνές ⇄ Αχαρνών
  ['αι', 'ων'], // Αθήναι ⇄ Αθηνών
];

/**
 * Ρίζα κάτω από αυτό το μήκος δεν ταυτίζει τίποτα — τα σύντομα ονόματα συμπίπτουν τυχαία.
 *
 * ⚠️ **`3`, μετρημένο από την ίδια την άγκυρα**: με `4` η **Βόλος ⇄ Βόλου** (ρίζα `βολ`) έβγαινε
 * «άλλος τόπος» — τρίτη μεγαλύτερη ελληνική πόλη. Η προστασία από τις τυχαίες συμπτώσεις δεν
 * κρέμεται από το μήκος αλλά από τα **ζεύγη**: η Ίος ⇄ Ίου (ρίζα `ι`) μένει εκτός.
 */
const MIN_PLACE_STEM = 3;

function differsByPair(a: string, b: string, [left, right]: readonly [string, string]): boolean {
  if (!a.endsWith(left) || !b.endsWith(right)) return false;
  const stem = a.slice(0, -left.length);
  return stem.length >= MIN_PLACE_STEM && stem === b.slice(0, -right.length);
}

function sameDeclinedWord(a: string, b: string): boolean {
  if (a === b) return true;
  return DECLENSION_PAIRS.some((pair) => differsByPair(a, b, pair) || differsByPair(b, a, pair));
}

/**
 * **ΙΔΙΟΣ ΤΟΠΟΣ;** — ανεξάρτητα από πρόθεμα βαθμίδας, τόνους, σίγμα και **πτώση** (ADR-332 D28).
 *
 * «Θεσσαλονίκη» ⇄ «Μητροπολιτική Ενότητα Θεσσαλονίκης» ⇒ `true`. Σύγκριση **λέξη-προς-λέξη** και
 * **ίδιο πλήθος λέξεων**: ποτέ «περιέχει» — το «Νέα Σμύρνη» δεν είναι η «Σμύρνη».
 *
 * ⚠️ Αφορά **ονόματα τόπων**. Για οδούς, αριθμούς ή Τ.Κ. δεν έχει νόημα και δεν χρησιμοποιείται.
 */
export function samePlaceName(a: string, b: string): boolean {
  const left = foldPlaceIdentity(stripGreekAdminPrefix(a)).split(' ').filter(Boolean);
  const right = foldPlaceIdentity(stripGreekAdminPrefix(b)).split(' ').filter(Boolean);
  if (left.length === 0 || left.length !== right.length) return false;
  return left.every((word, index) => sameDeclinedWord(word, right[index]));
}

/** Η **γραφή**, όχι το όνομα: παύλα ⇄ κενό, πολλαπλά κενά, κενά στα άκρα. */
export function foldPlaceName(name: string): string {
  return name.replace(/-/g, ' ').replace(/\s+/g, ' ').trim();
}

/** Η κανονική μορφή ονόματος από τον πάροχο — χωρίς πρόθεμα, χωρίς παύλες (ό,τι έκανε το `cleanNominatimName`). */
export function cleanPlaceName(name: string): string {
  return foldPlaceName(stripGreekAdminPrefix(foldPlaceName(name)));
}
