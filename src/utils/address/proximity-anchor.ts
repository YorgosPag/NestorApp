/**
 * @fileoverview **ΑΠΟ ΠΟΥ ΜΕΤΡΑΜΕ ΤΟ «ΚΟΝΤΑ»** — και ποιος έχει προτεραιότητα όταν υπάρχουν δύο απαντήσεις.
 * @related ADR-332 D23 *(ο κανόνας)* · D25 *(η πινέζα)* · utils/address/address-list-center
 * @module utils/address/proximity-anchor
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ ΔΕΝ ΖΕΙ ΣΤΟ `address-list-center`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Εκείνο απαντά *«ποιο **σημείο** εκπροσωπεί αυτή τη λίστα;»* — ερώτηση για **μία** πηγή.
 * Αυτό εδώ απαντά *«από πού μετράμε το κοντά;»*, που είναι **ιεράρχηση δύο πηγών**: μιας
 * ανθρώπινης πράξης και μιας ιδιότητας της οντότητας. Η δεύτερη ερώτηση **καλεί** την
 * πρώτη· δεν είναι η ίδια.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Η ΙΕΡΑΡΧΗΣΗ, ΚΑΙ ΓΙΑΤΙ Ο ΑΝΘΡΩΠΟΣ ΝΙΚΑΕΙ ΤΗΝ ΟΝΤΟΤΗΤΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * 1. **Το σημείο που τοποθέτησε ο άνθρωπος** *(αν υπάρχει)*.
 * 2. Αλλιώς **το σημείο της οντότητας** — οι άλλες διευθύνσεις της ίδιας λίστας (D23).
 * 3. Αλλιώς `undefined`: *«δεν ξέρουμε πού είναι»* — **δεδομένο, όχι σφάλμα**.
 *
 * Το D23 απέρριψε ρητά **το κέντρο προβολής του χάρτη**, με το επιχείρημα ότι εκφράζει
 * *«τι κοιτάς τώρα»*, που είναι **τυχαίο**. Η πινέζα που ο άνθρωπος **έσυρε** δεν είναι
 * τυχαία: είναι **δήλωση πρόθεσης**, ισχυρότερη από κάθε συναγωγή — ο άνθρωπος είπε
 * *«εδώ»* πριν πληκτρολογήσει τίποτα. Ένα έργο στη Θεσσαλονίκη με νέα διεύθυνση στην
 * Καλαμαριά κατατάσσει σωστά **μόνο** έτσι.
 *
 * ⚠️ **Δεν είναι επέκταση της απορριφθείσας επιλογής — είναι το αντίθετό της.** Η διαφορά
 * δεν είναι «χάρτης εναντίον δεδομένων», είναι **«ποιος το είπε»**: το κέντρο προβολής
 * μετακινείται από κάθε σύρσιμο *σάρωσης*, η πινέζα μόνο από σύρσιμο **τοποθέτησης**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ ΓΙΑΤΙ ΔΕΝ ΥΠΑΡΧΕΙ ΠΑΡΑΜΕΤΡΟΣ `hasDragged` — ΚΑΙ ΔΕΝ ΘΑ ΥΠΑΡΞΕΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η προφανής υπογραφή θα ήταν `(point, hasDragged, addresses)`. **Απορρίφθηκε**, με το
 * ίδιο επιχείρημα που το `lib/primary-entry.ts` γράφει για το φιλτράρισμα:
 *
 * > *«Ένα δεύτερο όρισμα-κατηγόρημα είναι παράμετρος που ο καλών **μπορεί να ξεχάσει**·
 * > ένα φιλτραρισμένο όρισμα είναι **αδύνατο** να ξεχαστεί, γιατί το γράφει ο ίδιος.»*
 *
 * Ο καλών κάνει **ο ίδιος** τη διάκριση και περνά `humanPlacedPoint` **μόνο** όταν
 * ισχύει. Το όνομα του πεδίου κάνει τη λάθος χρήση **ψέμα στο σημείο κλήσης**, που είναι
 * ο φθηνότερος φρουρός που υπάρχει.
 *
 * 🔴 **ΚΑΙ Η ΔΙΑΚΡΙΣΗ ΕΧΕΙ ΗΔΗ ΕΝΑΝ ΙΔΙΟΚΤΗΤΗ**: το `useProjectLocations` απαντούσε ήδη
 * *«το τοποθέτησε άνθρωπος;»* για να αποφασίσει αν θα **αποθηκεύσει** τις συντεταγμένες
 * *(«αλλιώς η διεύθυνση κολλάει στην προεπιλεγμένη θέση»)*. Δεν γεννήθηκε δεύτερη
 * απάντηση — **εκτέθηκε η υπάρχουσα**.
 *
 * **Layering**: leaf — καθαρή συνάρτηση, μηδέν εξαρτήσεις πέρα από το `address-list-center`.
 */

import {
  addressListCenter,
  usablePoint,
  type AddressWithOptionalPosition,
  type CoordinatePoint,
} from './address-list-center';

export interface ProximityAnchorSources {
  /**
   * Το σημείο που **τοποθέτησε ο άνθρωπος** — και τίποτε άλλο.
   *
   * ⛔ **ΠΟΤΕ μαντεμένο σημείο εδώ.** Η πινέζα της φόρμας προσθήκης γεννιέται σε
   * *κεντροειδές*, ή 150 m βόρεια της μοναδικής υπάρχουσας, ή στο **προεπιλεγμένο κέντρο
   * Αθήνας** όταν δεν υπάρχει καμία θέση. Αν περνιόταν εκείνη, η αφετηρία θα ήταν η Αθήνα
   * για κάθε καινούργιο έργο — δηλαδή **ακριβώς η αστοχία που απέρριψε το D23**, από άλλη
   * πόρτα. Πέρασέ το μόνο αφού βεβαιωθείς ότι ο άνθρωπος το έσυρε.
   */
  readonly humanPlacedPoint?: { readonly lat: number; readonly lng: number } | null;
  /** Οι διευθύνσεις της **ίδιας οντότητας** — η υποχώρηση του D23. */
  readonly addresses?: readonly AddressWithOptionalPosition[] | null;
}

/**
 * Η αφετηρία από την οποία κρίνεται ποιος υποψήφιος είναι «κοντά».
 *
 * `undefined` σημαίνει *«δεν ξέρουμε»* — ο καλών οφείλει να καταταξει **μόνο** με
 * βεβαιότητα και να μη δείξει απόσταση, **ποτέ** να μαντέψει σημείο.
 */
export function resolveProximityAnchor(
  sources: ProximityAnchorSources,
): CoordinatePoint | undefined {
  // ⚠️ Το `NaN` περνά κάθε `typeof === 'number'` και μολύνει **κάθε** απόσταση που
  // μετριέται από αυτό — οι συγκρίσεις του είναι όλες ψευδείς, οπότε η κατάταξη θα
  // κατέρρεε σιωπηλά στη σειρά του παρόχου. Ίδιος κριτής με το `addressListCenter`.
  const placed = usablePoint(sources.humanPlacedPoint);
  if (placed) return placed;

  return addressListCenter(sources.addresses);
}
