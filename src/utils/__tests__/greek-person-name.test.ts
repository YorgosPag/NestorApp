/**
 * @fileoverview Ταυτοποίηση προσώπου από ελληνικό όνομα (ADR-745 Φ3β).
 *
 * Τα ονόματα του δείγματος είναι τα ΠΡΑΓΜΑΤΙΚΑ του `G753_ergasia F.dxf`.
 */

import {
  expandsGreekContraction,
  parsePersonName,
  personNameMatch,
} from '../greek-person-name';

describe('συστολή με κάθετο — ο ελληνικός τύπος', () => {
  it.each([
    ['ΚΩΝ/ΝΟΣ', 'ΚΩΝΣΤΑΝΤΙΝΟΣ'],
    ['ΠΑΝ/ΤΗΣ', 'ΠΑΝΑΓΙΩΤΗΣ'],
    ['ΔΗΜ/ΟΣ', 'ΔΗΜΗΤΡΙΟΣ'],
    ['ΑΘΑΝ/ΟΣ', 'ΑΘΑΝΑΣΙΟΣ'],
    ['ΧΑΡ/ΠΟΣ', 'ΧΑΡΑΛΑΜΠΟΣ'],
    ['Κων/νος', 'Κωνσταντίνος'],
  ])('«%s» αναπτύσσεται σε «%s» χωρίς κανέναν κατάλογο', (short, full) => {
    expect(expandsGreekContraction(short, full)).toBe(true);
  });

  it('🔴 δεν δέχεται ανάπτυξη που δεν προσθέτει τίποτα στη μέση', () => {
    // Χωρίς τον έλεγχο «γνήσια μακρύτερο», πρόθεμα και κατάληξη επικαλύπτονται και κάθε
    // συστολή ταιριάζει με τον εαυτό της.
    expect(expandsGreekContraction('ΚΩΝ/ΝΟΣ', 'ΚΩΝΝΟΣ')).toBe(false);
    expect(expandsGreekContraction('ΚΩΝ/ΝΟΣ', 'ΚΩΝ/ΝΟΣ')).toBe(false);
  });

  it('δεν δέχεται λάθος ανάπτυξη', () => {
    expect(expandsGreekContraction('ΚΩΝ/ΝΟΣ', 'ΙΩΑΝΝΗΣ')).toBe(false);
    expect(expandsGreekContraction('ΠΑΝ/ΤΗΣ', 'ΠΑΝΑΓΙΩΤΟΥ')).toBe(false);
    expect(expandsGreekContraction('ΚΩΝΣΤΑΝΤΙΝΟΣ', 'ΚΩΝΣΤΑΝΤΙΝΟΣ')).toBe(false);
  });
});

describe('ανάλυση ονόματος', () => {
  it('το αρχικό πατρωνύμου ΔΕΝ γίνεται συστατικό', () => {
    expect(parsePersonName('ΝΙΚΟΛΑΟΥ ΕΥ. ΙΩΑΝΝΗΣ').map(t => t.raw)).toEqual([
      'ΝΙΚΟΛΑΟΥ',
      'ΙΩΑΝΝΗΣ',
    ]);
  });

  it('η συστολή αναγνωρίζεται ως τέτοια, με τα δύο μέρη της', () => {
    const tokens = parsePersonName('ΜΑΥΡΟΜΙΧΑΛΗΣ ΚΩΝ/ΝΟΣ');
    expect(tokens).toHaveLength(2);
    expect(tokens[1].contraction).toEqual({ prefix: 'κων', suffix: 'νοσ' });
  });
});

describe('ταυτοποίηση προσώπου', () => {
  it('🔴 ο κύριος μελετητής του δείγματος βρίσκεται παρά τη συστολή ΚΑΙ την αντίστροφη σειρά', () => {
    expect(personNameMatch('ΜΑΥΡΟΜΙΧΑΛΗΣ ΚΩΝ/ΝΟΣ', 'Κωνσταντίνος Μαυρομιχάλης')).toBe('abbrev');
  });

  it('ο δεύτερος μελετητής βρίσκεται αγνοώντας το πατρώνυμο', () => {
    expect(personNameMatch('ΝΙΚΟΛΑΟΥ ΕΥ. ΙΩΑΝΝΗΣ', 'Ιωάννης Νικολάου')).toBe('exact');
  });

  it('η ιδιοκτήτρια του δείγματος ταυτοποιείται ακριβώς', () => {
    expect(personNameMatch('ΖΕΡΒΑ ΓΕΩΡΓΙΑ', 'Γεωργία Ζέρβα')).toBe('exact');
  });

  it('επιπλέον μεσαίο όνομα στη ΒΑΣΗ δεν εμποδίζει — λιγότερα συστατικά εμποδίζουν', () => {
    expect(personNameMatch('ΖΕΡΒΑ ΓΕΩΡΓΙΑ', 'Γεωργία Παναγιώτα Ζέρβα')).toBe('exact');
    expect(personNameMatch('ΖΕΡΒΑ ΓΕΩΡΓΙΑ ΠΑΝΑΓΙΩΤΑ', 'Γεωργία Ζέρβα')).toBeNull();
  });

  it('🔴 συνονόματοι ΔΕΝ ταυτίζονται', () => {
    expect(personNameMatch('ΝΙΚΟΛΑΟΥ ΙΩΑΝΝΗΣ', 'Δημήτριος Νικολάου')).toBeNull();
    expect(personNameMatch('ΜΑΥΡΟΜΙΧΑΛΗΣ ΚΩΝ/ΝΟΣ', 'Κωνσταντίνος Παπαδόπουλος')).toBeNull();
  });

  it('🔴 σκέτο επώνυμο ΔΕΝ είναι ταυτοποίηση προσώπου', () => {
    expect(personNameMatch('ΜΑΥΡΟΜΙΧΑΛΗΣ', 'Κωνσταντίνος Μαυρομιχάλης')).toBeNull();
  });

  it('🔴 τυπογραφικό λάθος σε ΜΑΚΡΥ επώνυμο συγχωρείται…', () => {
    // 12 γράμματα, ένα λάθος γράμμα (ΠΑΠΑΔΟΠΟΥΛΟΣ → ΠΑΠΑΔΟΠΩΥΛΟΣ): τυπογραφικό, όχι άλλο άτομο.
    expect(personNameMatch('ΠΑΠΑΔΟΠΩΥΛΟΣ ΓΕΩΡΓΙΟΣ', 'Γεώργιος Παπαδόπουλος')).toBe('fuzzy');
  });

  it('🔴 …σε ΣΥΝΤΟΜΟ όχι — εκεί ένα γράμμα είναι άλλο όνομα', () => {
    // «ΖΕΡΒΑ» vs «ΣΕΡΒΑ»: πέντε γράμματα, απόσταση 1 — και δύο διαφορετικοί άνθρωποι. Το
    // «ΖΕΡΒΑ» είναι η ιδιοκτήτρια του δείγματος: εδώ ακριβώς κοστίζει η χαλαρότητα.
    expect(personNameMatch('ΖΕΡΒΑ ΓΕΩΡΓΙΑ', 'Γεωργία Σέρβα')).toBeNull();
    expect(personNameMatch('ΠΕΤΡΟΥ ΜΑΡΙΑ', 'Μαρία Πέτρος')).toBeNull();
  });

  it('τόνοι και τελικό σίγμα ΔΕΝ καταναλώνουν την ανοχή — είναι κανονικοποίηση', () => {
    expect(personNameMatch('ΜΑΥΡΟΜΙΧΑΛΗΣ ΚΩΝΣΤΑΝΤΙΝΟΣ', 'Κωνσταντίνος Μαυρομιχάλης')).toBe('exact');
    expect(personNameMatch('ΠΑΠΑΔΟΠΟΥΛΟΣ ΓΕΩΡΓΙΟΣ', 'Γεώργιος Παπαδόπουλος')).toBe('exact');
  });

  it('τόνοι, πεζά/κεφαλαία και τελικό σίγμα δεν κάνουν διαφορά', () => {
    expect(personNameMatch('ΙΩΑΝΝΗΣ ΝΙΚΟΛΑΟΥ', 'ιωάννης νικολάου')).toBe('exact');
  });

  it('κενή ή μονολεκτική είσοδος δεν παράγει ποτέ ταύτιση', () => {
    expect(personNameMatch('', 'Γεωργία Ζέρβα')).toBeNull();
    expect(personNameMatch('ΖΕΡΒΑ ΓΕΩΡΓΙΑ', '')).toBeNull();
    expect(personNameMatch('   ', '   ')).toBeNull();
  });

  it('🔴 η αντιστοίχιση γίνεται κατά ΙΣΧΥ — ένα προσεγγιστικό δεν κλέβει το συστατικό ενός ακριβούς', () => {
    // Το «ΓΕΩΡΓΙΟΥ» ταιριάζει προσεγγιστικά με το «ΓΕΩΡΓΙΟΣ» (απόσταση 1) αλλά ακριβώς με το
    // «Γεωργίου». Άπληστη αντιστοίχιση ανά λέξη θα δέσμευε το λάθος και θα έχανε το σωστό.
    expect(personNameMatch('ΓΕΩΡΓΙΟΥ ΓΕΩΡΓΙΟΣ', 'Γεώργιος Γεωργίου')).toBe('exact');
  });
});
