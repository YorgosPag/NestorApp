/**
 * @fileoverview **Ποιο πάνελ δείχνει ο θεατής** — και γιατί η απάντηση **δεν** ρωτά το παράθυρο.
 * @related ADR-777 §7 (Α8) · §8.20 · SPEC-777D §26.6β · §26.8 · hooks/media/useViewportClass
 * @module features/read-only-viewer/viewer-panes
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΙ ΗΤΑΝ ΣΠΑΣΜΕΝΟ — ΜΕΤΡΗΜΕΝΟ ΖΩΝΤΑΝΑ ΣΤΑ 515 px, ΟΧΙ ΕΚΤΙΜΗΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο θεατής ήταν **τρεις στήλες** με **720 px καθηλωμένα** στα πλαϊνά και **μηδέν**
 * ερώτηση για το πλάτος σε ολόκληρο το χαρακτηριστικό. Το SPEC-777D §26.6β το έγραφε
 * ως «**πολύ φαρδύ** για κινητό». Η ζωντανή μέτρηση έδειξε κάτι **χειρότερο**:
 *
 * | Πάνελ | Πλάτος στα 515 px | Τι σήμαινε |
 * |---|---|---|
 * | Λίστα | 360 px | ορατή |
 * | **Προβολέας μέσων** | **ακριβώς 0 px** | **αποδιδόταν με περιεχόμενο, και ήταν αόρατος** |
 * | Λεπτομέρειες | 360 px, **217 κομμένα** | το δοχείο είναι `overflow-x: hidden` ⇒ **καμία χειρονομία δεν τα έφτανε** |
 *
 * Δηλαδή δεν ήταν «στριμωγμένο»: το κεντρικό πάνελ είναι `flex-1`, οπότε ανάμεσα σε δύο
 * `shrink-0` των 360 px **συνθλιβόταν στο μηδέν** — και η κάτοψη, ο **λόγος ύπαρξης** του
 * θεατή, δεν υπήρχε στην οθόνη ενώ τα bytes της είχαν ήδη ταξιδέψει. Είναι το ίδιο σχήμα
 * που το §2.3 ονομάζει *«μια οθόνη που αποδίδεται και μετά κρύβεται είναι οθόνη που
 * στάλθηκε»*, στη χειρότερη εκδοχή του: **δεν κρύφτηκε καν, εκμηδενίστηκε**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΤΟ ΠΡΟΤΥΠΟ ΔΕΝ ΕΠΙΝΟΗΘΗΚΕ — ΕΙΝΑΙ ΤΕΚΜΗΡΙΩΜΕΝΗ ΣΥΝΑΙΝΕΣΗ, ΚΑΙ ΕΙΝΑΙ ΔΙΜΕΡΗΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Τα τρία πάνελ **δεν** είναι τρία ισότιμα. Μετρήθηκε ότι **και** ο προβολέας **και** οι
 * λεπτομέρειες λένε, χωρίς επιλογή, «*επιλέξτε ένα ακίνητο*»: είναι **και τα δύο κατάντη
 * της επιλογής**. Άρα η λίστα είναι **ευρετήριο** και τα άλλα δύο είναι η **λεπτομέρειά**
 * της — δηλαδή κλασικό `list-detail`, όχι τρεις ισότιμες όψεις.
 *
 * • **Λίστα ⇄ λεπτομέρεια** → *stack / drill-down*. Material 3: *«Medium- and compact-width
 *   displays show either the list or the detail… selection of a list item displays the detail
 *   in place of the list. When just the detail is visible, pressing the back button redisplays
 *   the list.»* Apple HIG: *«The split view collapses into a stack navigation for compact
 *   screens.»*
 * • **Το τρίτο, βοηθητικό πάνελ** → *bottom sheet πίσω από κουμπί*. Material 3, Supporting
 *   Pane: *«For compact-width displays, place the supporting content below the main content
 *   or inside a bottom sheet.»*
 *
 * ⛔ **ΚΑΡΤΕΛΕΣ ΑΠΟΡΡΙΦΘΗΚΑΝ ΜΕ ΠΗΓΗ, ΟΧΙ ΜΕ ΓΟΥΣΤΟ.** Το Apple HIG τις ορίζει για *«flat
 * navigation between peer sections»*, **ρητά αντιδιαστελλόμενες** από την ιεραρχική πλοήγηση.
 * Τα πάνελ εδώ **δεν** είναι ισότιμα — το ένα γεννά τα άλλα δύο.
 *
 * 🔑 **Και από τις ΔΥΟ επιλογές του Material 3 κρατήθηκε η δεύτερη, με μετρημένο λόγο.** Το
 * «*below the main content*» θα έβαζε τον προβολέα **μέσα σε κατακόρυφο κυλιόμενο** — και ο
 * προβολέας είναι **επιφάνεια χειρονομιών** (κρατά `zoom` και `panOffset`). Το σύρσιμο για
 * μετακίνηση της κάτοψης θα **κύλιε τη σελίδα**: σύγκρουση χειρονομιών, όχι θέμα αισθητικής.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ ΕΔΩ ΤΟ «ΜΕΤΡΑΩ ΑΚΟΜΗ» ΔΕΝ ΚΟΣΤΙΖΕΙ ΤΙΠΟΤΑ — ΚΑΙ ΕΙΝΑΙ ΑΛΛΟΣ ΛΟΓΟΣ ΑΠΟ ΤΟ ΦΥΛΛΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το SPEC-777D §26.7 έλυσε το ίδιο δίλημμα βάζοντας τη **γεωμετρία στο CSS** και τη
 * **συμπεριφορά** στο `useViewportClass`. Εδώ ισχύει το ίδιο συμπέρασμα από **ισχυρότερη**
 * αφετηρία: το ερώτημα «**ποιο** πάνελ;» δεν απαντιέται από το πλάτος **καθόλου** — το
 * απαντά η **κατάσταση επιλογής**, που δεν είναι μέτρηση παραθύρου. Το πλάτος απαντά μόνο
 * «**πόσα** πάνελ», και αυτό το γράφει το CSS στο `md`.
 *
 * Άρα το `measuring` δεν χρειάζεται να διαλέξει **τίποτα** γεωμετρικό: δεν είναι ότι
 * προλαβαίνει η μέτρηση, είναι ότι **δεν ρωτιέται**. Μοναδικός καταναλωτής του πλάτους
 * μένει η **συμπεριφορά** του πίσω κουμπιού — και η **αναφορά** παρακάτω, που δεν αποφασίζει
 * τίποτα.
 */

import type { ViewportClass } from '@/hooks/media/useViewportClass';

/**
 * Το γνώρισμα DOM που **αναφέρει** τι δείχνει ο θεατής.
 *
 * ⚠️ Είναι **αναφορά, όχι απόφαση** (Ζ4 του §26.7): καμία κλάση, κανένα ύψος, κανένα
 * `overflow` δεν κρέμεται από αυτό. Υπάρχει για να μπορεί μια άγκυρα — και ένας άνθρωπος
 * με ανοιχτό τον επιθεωρητή — να ρωτήσει την οθόνη τι νομίζει ότι δείχνει.
 */
export const VIEWER_PANE_ATTRIBUTE = 'data-viewer-pane' as const;

/**
 * Οι **τέσσερις** ειλικρινείς απαντήσεις. **Ποτέ τρεις.**
 *
 * 🔴 Το `measuring` **δεν** συμπτύσσεται σε `columns`, και ο λόγος είναι πληρωμένος: στο
 * §26.7 η πρώτη γραφή της αντίστοιχης αναφοράς έλεγε **«στήλη»** στον διακομιστή **κάθε**
 * συσκευής, χωρίς να έχει μετρήσει τίποτα. Το είδε **μόνο** η ζωντανή επαλήθευση — καμία
 * σουίτα δεν ρωτούσε *«τι λες όταν δεν ξέρεις;»*. Εδώ η ερώτηση ρωτιέται από άγκυρα.
 */
export const VIEWER_PANES = ['measuring', 'list', 'media', 'columns'] as const;

export type ViewerPane = (typeof VIEWER_PANES)[number];

/**
 * Η καταχώριση **στην ουρά ιστορικού** που ανήκει στη λεπτομέρεια του θεατή.
 *
 * 🔑 **Κάθε επιφάνεια φέρνει το δικό της κλειδί** — ο μηχανισμός του `useSheetBackDismiss`
 * είναι κοινός, η **ταυτότητα** όχι. Δύο επιφάνειες με ένα κλειδί θα ήταν δύο αλήθειες για
 * το «ποιανού είναι αυτή η καταχώριση» (ADR-749), και θα φαινόταν σωστό όσο δεν συνυπήρχαν.
 */
export const VIEWER_DETAIL_HISTORY_KEY = '__readOnlyViewerDetail' as const;

/**
 * **Τι δείχνει ο θεατής** — για την αναφορά, ποτέ για τη διάταξη.
 *
 * @param viewport Η κλάση πλάτους· `measuring` όσο δεν έχει μετρηθεί παράθυρο.
 * @param hasSelection Υπάρχει επιλεγμένο ακίνητο; **Αυτό** είναι που ξεχωρίζει λίστα από μέσα.
 */
export function reportedViewerPane(viewport: ViewportClass, hasSelection: boolean): ViewerPane {
  if (viewport === 'measuring') return 'measuring';
  if (viewport === 'wide') return 'columns';
  return hasSelection ? 'media' : 'list';
}
