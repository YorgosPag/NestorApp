/**
 * =============================================================================
 * TEST-HARNESS ROUTE ACCESS (SSoT)
 * =============================================================================
 *
 * Ποιος επιτρέπεται να δει τις διαδρομές `/test-harness/**`.
 *
 * Μέχρι τώρα η απάντηση ζούσε **inline σε κάθε `page.tsx`** ως
 * `process.env.NODE_ENV === 'production'` — τρία αντίγραφα του ίδιου κανόνα, και το
 * ADR-726 χρειαζόταν ένα τέταρτο με **διαφορετική** απάντηση. Τέσσερις σκόρπιες
 * εκδοχές μιας πολιτικής έκθεσης είναι ακριβώς ο τρόπος που μια διαδρομή δοκιμών
 * καταλήγει κατά λάθος ζωντανή. Ένα σημείο, δύο ρητά ονόματα (N.0.2).
 *
 * @module config/test-harness-access
 */

/**
 * Το «κανονικό» harness: **ΜΟΝΟ σε ανάπτυξη**, ποτέ σε παραγωγή.
 *
 * Χρήση: `/test-harness/dxf-canvas`, `/test-harness/bim-3d`,
 * `/test-harness/contact-mutation`. Συμπεριφορά **ταυτόσημη** με τον inline φρουρό
 * που αντικατέστησε.
 */
export function isTestHarnessRouteEnabled(): boolean {
  return process.env.NODE_ENV !== 'production';
}

/**
 * Το harness **μέτρησης απόδοσης** (ADR-726 §13.5): ανάπτυξη **Ή** production build
 * που το ζήτησε ρητά.
 *
 * Γιατί χρειάζεται εξαίρεση: το κριτήριο **Φ5** απαιτεί μέτρηση σε **production
 * build**. Η έκδοση ανάπτυξης κουβαλά StrictMode (διπλό render) + dev overhead — τα
 * νούμερά της δεν περιγράφουν τι νιώθει ο χρήστης. Ένα harness που δεν μπορεί να
 * τρέξει εκεί που ισχύει το κριτήριο δεν μετράει το κριτήριο.
 *
 * **Είναι διακόπτης χρόνου ΚΑΤΑΣΚΕΥΗΣ, όχι χρόνου εκτέλεσης** — η σελίδα
 * προ-αποδίδεται στο `next build`, οπότε η απόφαση ψήνεται μέσα στο artifact:
 *
 * ```bash
 * ENABLE_PERF_HARNESS=1 npm run build && npm start   # τοπικά: η διαδρομή υπάρχει
 * npm run build                                       # nestorconstruct.gr: 404
 * ```
 *
 * Αυτό είναι **αυστηρότερο** από έλεγχο χρόνου εκτέλεσης: το build της παραγωγής δεν
 * περιέχει καν τη σελίδα, άρα καμία μεταβλητή στον διακομιστή δεν μπορεί να την
 * ανοίξει εκ των υστέρων. Η μεταβλητή **δεν** έχει πρόθεμα `NEXT_PUBLIC_`, άρα δεν
 * φτάνει ποτέ στο πρόγραμμα περιήγησης.
 */
export function isPerfHarnessRouteEnabled(): boolean {
  return isTestHarnessRouteEnabled() || process.env.ENABLE_PERF_HARNESS === '1';
}
