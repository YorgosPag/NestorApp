/**
 * @fileoverview Πώς **ονομάζονται στην οθόνη** τα δεδομένα του τοπογραφικού (ADR-759 Φ4β).
 *
 * Δύο ερωτήματα, μία απάντηση το καθένα, και **δύο δέντρα καταναλωτών**: η καρτέλα
 * «Στοιχεία Τοπογραφικού» (`components/projects/survey-data`) και η παλέτα σύνδεσης του DXF
 * viewer (`subapps/dxf-viewer/…/title-block-binding`). Ό,τι γράφεται σε ένα από τα δύο και
 * όχι στο άλλο **αποκλίνει** — και η απόκλιση εδώ είναι από τις χειρότερες: ο μηχανικός
 * διαβάζει στην παλέτα ένα όνομα και ψάχνει άλλο στην καρτέλα, για την **ίδια** εγγραφή.
 *
 * ## 1. Το όνομα της εγγραφής — και γιατί έπαψε να είναι παύλα
 *
 * 🔴 **Η παύλα ήταν απάντηση σε λάθος ερώτηση.** Το `surveyRecordLabel()` απαντά *«τι
 * ταυτοποιεί αυτό το έγγραφο»* — καθαρό ερώτημα δεδομένων, χωρίς `t()`. Μέσα του όμως ζούσε
 * και το *«τι τυπώνω όταν δεν ταυτοποιείται τίποτα»*, που είναι ερώτημα **διεπαφής**. Η
 * απάντηση `'—'` έβγαινε από αρχείο που δεν έχει δικαίωμα να μιλήσει στον χρήστη, και ήταν
 * **ακριβώς η κατάσταση κάθε νέας καρτέλας**: ο μηχανικός έβλεπε «γράφονται στο: —» και δεν
 * ήξερε πού πάνε 26 τιμές.
 *
 * ⇒ Το `surveyRecordLabel()` επιστρέφει πλέον `string | null`. Το `null` είναι **κατάσταση**
 * («το έγγραφο δεν λέει τίποτα αναγνωρίσιμο ακόμη»), ίδιο δόγμα με το `value: null` του
 * `Sourced` — και η **μία** φράση που το ντύνει ζει εδώ, όχι σε δύο οθόνες.
 *
 * ⚠️ **ΚΑΜΙΑ υποχώρηση στο `createdAt`.** Είναι ο προφανής «έξυπνος» εφεδρικός δείκτης και
 * είναι **λάθος**: το `SurveyRecord.surveyDate` τεκμηριώνεται ρητά ως *«πότε συντάχθηκε το
 * τοπογραφικό — **όχι** πότε το πληκτρολογήσαμε»*. Τυπώνοντας το `createdAt` στη θέση του
 * ονόματος, ο μηχανικός θα διάβαζε ημερομηνία σύνταξης που **κανείς τοπογράφος δεν δήλωσε**
 * — «ψέμα με σωστή μορφή» (ADR-759 §2β.5), δηλαδή χειρότερο από την παύλα.
 *
 * ## 2. Η λογική τιμή — «Ναι», όχι η φράση που την προκάλεσε
 *
 * 🔴 Η παλέτα έγραφε `Ζώνη κοινωνικού συντελεστή → ΕΝΤΟΣ ΖΩΝΗΣ ΚΟΙΝΩΝΙΚΟΥ ΣΥΝΤΕΛΕΣΤΗ` ενώ η
 * έγκριση γράφει **checkbox = true**. Το βέλος «→» σημαίνει «αυτό θα γραφτεί», άρα η γραμμή
 * υποσχόταν κάτι που δεν ίσχυε. Το λεξιλόγιο «Ναι/Όχι» **υπήρχε ήδη** στην καρτέλα
 * (`SourcedFieldRow`, `actions.yes`/`actions.no`) — δεύτερο στο `dxf-viewer-shell` θα ήταν
 * δεύτερη πηγή αλήθειας για δύο λέξεις που ο χρήστης βλέπει **δίπλα δίπλα** στις δύο οθόνες.
 *
 * @see ADR-759 §4.9
 * @module config/survey-record-labels
 */

import type { ConfigTranslateFn } from './config-translate-fn';

/**
 * Το namespace στο οποίο ζουν οι ετικέτες.
 *
 * ⚠️ **Ο καταναλωτής πρέπει να το δηλώσει στο `useTranslation([...])` του.** Τα κλειδιά φέρουν
 * ήδη το πρόθεμα, και για προθεματισμένο κλειδί ο resolver του ADR-716 Φ5 **βγαίνει αμέσως**
 * (`useTranslation.ts:99`): δεν υπάρχει δίχτυ — χωρίς φορτωμένο namespace βάφεται **ωμό
 * κλειδί στην οθόνη ενώ η μετάφραση υπάρχει** (η βλάβη του ADR-752). Ίδιο συμβόλαιο με το
 * {@link PROJECT_ROLE_LABEL_NAMESPACE}, και το φυλάει ο ίδιος έλεγχος
 * (`title-block-binding-wiring.test.ts`).
 */
export const SURVEY_RECORD_LABEL_NAMESPACE = 'surveyRecord' as const;

/**
 * Πώς παρουσιάζεται μια εγγραφή τοπογραφικού — **ονομασμένη ή όχι**.
 *
 * Οι δύο εκβάσεις είναι **πλήρεις φράσεις**, όχι ένα πρότυπο με προαιρετικό κομμάτι: το
 * «Τοπογραφικό {name}» και το «Τοπογραφικό χωρίς ημερομηνία» δεν είναι η ίδια πρόταση με
 * κενό, και μια γλώσσα μπορεί να τις χρειάζεται δομικά διαφορετικές.
 */
export const SURVEY_RECORD_NAME_LABEL = {
  named: 'surveyRecord:card.recordLabel',
  unnamed: 'surveyRecord:card.recordUnnamed',
} as const;

/** Οι δύο λέξεις με τις οποίες η καρτέλα διαβάζει μια λογική τιμή. */
export const SURVEY_AFFIRMATION_LABEL: Record<'yes' | 'no', string> = {
  yes: 'surveyRecord:actions.yes',
  no: 'surveyRecord:actions.no',
};

/**
 * `surveyRecordLabel(record)` → το κείμενο που βλέπει ο άνθρωπος.
 *
 * 🔑 **Η μοναδική σύνθεση**, ώστε η παλέτα και η καρτέλα να λένε **κατά λέξη το ίδιο**. Μέχρι
 * σήμερα δεν το έλεγαν: η καρτέλα τύπωνε «Τοπογραφικό 30/7/2026» και η παλέτα σκέτο
 * «30/7/2026», παρότι το docblock της SSoT υποσχόταν ρητά το αντίθετο.
 */
export function surveyRecordDisplayName(label: string | null, t: ConfigTranslateFn): string {
  return label === null
    ? t(SURVEY_RECORD_NAME_LABEL.unnamed)
    : t(SURVEY_RECORD_NAME_LABEL.named, { name: label });
}

/**
 * Μια **αναλυμένη** λογική τιμή → «Ναι» / «Όχι».
 *
 * Δέχεται `boolean`, όχι `boolean | null`: το `null` σημαίνει «δεν αναλύθηκε» και **δεν έχει
 * λέξη** — εκεί η αλήθεια είναι το ωμό κείμενο του σχεδίου, και ο καλών το κρατά.
 */
export function surveyAffirmationLabel(value: boolean, t: ConfigTranslateFn): string {
  return t(value ? SURVEY_AFFIRMATION_LABEL.yes : SURVEY_AFFIRMATION_LABEL.no);
}
