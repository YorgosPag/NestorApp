/** Μετά από τόσο, μια ανάγνωση σε `classifying` θεωρείται κολλημένη (ο διακομιστής την ξαναξεκινά· ο πελάτης σταματά να περιμένει). */
export const CLASSIFICATION_STUCK_AFTER_MS = 3 * 60 * 1000;

/** Τα πρώτα διαστήματα αναμονής του πελάτη — οι περισσότερες αναγνώσεις τελειώνουν σε 10–25 s. */
const POLL_RAMP_MS = [2_000, 3_000, 5_000] as const;
/** Μετά τη ράμπα, σταθερό βήμα. */
const POLL_STEADY_MS = 8_000;

/** Πόσο περιμένει ο πελάτης πριν ξαναδιαβάσει την εγγραφή (`attempt` από 0). */
export function classificationPollDelayMs(attempt: number): number {
  return attempt < POLL_RAMP_MS.length ? POLL_RAMP_MS[attempt] : POLL_STEADY_MS;
}
