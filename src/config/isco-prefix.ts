/**
 * ADR-798 — Η **ΑΝΑΛΥΣΗ ΠΡΟΘΕΜΑΤΟΣ ISCO-08**, μία φορά.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 ΓΙΑΤΙ ΥΠΑΡΧΕΙ ΞΕΧΩΡΙΣΤΑ — Ο ΜΗΧΑΝΙΣΜΟΣ ΔΕΝ ΕΙΝΑΙ Η ΑΠΟΦΑΣΗ
 *
 * Δύο **ανεξάρτητα** ερωτήματα κλειδώνουν στο **ίδιο** πράγμα, ένα πρόθεμα
 * ISCO-08:
 *   • *«ποια **δουλειά** υποδεικνύει αυτό το επάγγελμα;»* → `isco-job-affinity.ts`
 *   • *«ποιος **ρόλος IFC** αντιστοιχεί;»*                → `isco-ifc-role.ts`
 *
 * Οι **πίνακες** είναι διαφορετικοί και οφείλουν να μείνουν διαφορετικοί
 * *(ADR-798 §6.2 · handoff §3.4)*: άλλοι καταναλωτές, άλλη ανάλυση — ο πίνακας
 * IFC χρειάζεται `2142`/`2144` που ο πίνακας δουλειάς **δεν έχει**, γιατί για την
 * πλοήγηση «πολιτικός» και «μηχανολόγος» είναι η ίδια απάντηση, ενώ για το IFC
 * είναι `CIVILENGINEER` και `MECHANICALENGINEER`.
 *
 * Ο **ΜΗΧΑΝΙΣΜΟΣ** όμως είναι ένας και ο ίδιος, και γραμμένος δύο φορές θα ήταν
 * δύο διάλεκτοι της ίδιας ερώτησης — το σχήμα του **ADR-749** *(τέσσερις μηχανές,
 * πέντε διάλεκτοι regex, τρεις αριθμοί για το ίδιο δέντρο)*. Εδώ θα γεννούσε κάτι
 * χειρότερο από απόκλιση αριθμού: **δύο ορισμοί του «τι είναι έγκυρος κωδικός
 * ISCO»**, δηλαδή δύο απαντήσεις στο `malformed`.
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 ΓΙΑΤΙ ΤΟ ΠΡΟΘΕΜΑ ΕΙΝΑΙ ΑΚΡΙΒΕΙΑ, ΟΧΙ ΕΥΡΕΤΙΚΗ
 *
 * Το ISCO-08 είναι **ιεραρχικό με πρόθεμα**, και αυτό είναι **εγγύηση του
 * προτύπου**: **10** μείζονες *(1 ψηφίο)* → **43** υπο-μείζονες *(2)* → **130**
 * ελάσσονες *(3)* → **436** μοναδιαίες *(4)*, όπου τα πρώτα ψηφία ενός κωδικού
 * **ΕΙΝΑΙ** η γονική του ομάδα. Άρα η ιεραρχία **είναι** η συμβολοσειρά: δεν
 * χρειάζεται ούτε πίνακας γονέων ούτε δεύτερη δομή.
 *
 * ⛔ **ΜΗΝ** το γενικεύσεις σε «οποιαδήποτε ιεραρχική ταξινομία». Η ασφάλεια της
 * αναζήτησης *(βλ. `ISCO_CODE_SHAPE`)* στηρίζεται στο ότι ο κωδικός είναι
 * **μόνο ψηφία**· ένα λεξιλόγιο με γράμματα θα έφερνε πίσω το `constructor`.
 *
 * @module config/isco-prefix
 * @see docs/centralized-systems/reference/adrs/ADR-798-person-professional-identity.md
 * @see https://isco.ilo.org/en/isco-08 — η δομή
 */

/** Μέγιστο μήκος κωδικού ISCO-08 (μοναδιαία ομάδα). **Δεδομένο του προτύπου.** */
export const ISCO_UNIT_GROUP_LENGTH = 4;

/**
 * Μόνο ψηφία, 1 έως 4. Οτιδήποτε άλλο είναι `malformed`.
 *
 * 🔑 Είναι **και ο φρουρός της αναζήτησης**: επειδή ο κωδικός αποδεδειγμένα
 * αποτελείται μόνο από ψηφία, κανένα πρόθεμα δεν μπορεί ποτέ να είναι
 * `constructor`/`toString`/`__proto__` — η αναζήτηση στο αντικείμενο είναι
 * **δομικά** ασφαλής, όχι ασφαλής κατά σύμβαση.
 */
const ISCO_CODE_SHAPE = /^\d{1,4}$/;

/**
 * Η ετυμηγορία, σε **τέσσερις ρητές καταστάσεις** — ποτέ `TEntry | undefined`.
 *
 * Η διάκριση `absent` / `undeclared` / `malformed` **δεν είναι πολυτέλεια**:
 * «δεν δήλωσε επάγγελμα», «δήλωσε επάγγελμα που δεν ξέρουμε πού ανήκει» και
 * «η τιμή δεν είναι καν κωδικός ISCO» έχουν **τρεις διαφορετικές θεραπείες**,
 * και μόνο η τελευταία είναι σφάλμα. Ένα κοινό `null` θα τις ισοπέδωνε και θα
 * έκρυβε το σφάλμα μέσα στη νόμιμη σιωπή.
 */
export type IscoPrefixVerdict<TEntry> =
  /** Δηλωμένο. Το `prefix` λέει **σε ποιο επίπεδο** απαντήθηκε. */
  | { readonly kind: 'declared'; readonly entry: TEntry; readonly prefix: string }
  /** Έγκυρος κωδικός, καμία δήλωση στον πίνακα. **Σιωπή εκ σχεδιασμού**, όχι κενό. */
  | { readonly kind: 'undeclared'; readonly code: string }
  /** Κανένας κωδικός: ελεύθερο κείμενο, ή καμία δήλωση καθόλου. */
  | { readonly kind: 'absent' }
  /** Η τιμή δεν είναι κωδικός ISCO-08. Fail-closed **και ορατό**. */
  | { readonly kind: 'malformed'; readonly value: string };

/**
 * **Ανάλυση μεγαλύτερου προθέματος** πάνω σε πίνακα με κλειδί πρόθεμα ISCO-08.
 *
 * Ο βρόχος τρέχει το πολύ `ISCO_UNIT_GROUP_LENGTH` φορές και ρωτά **δηλωμένα
 * κλειδιά**, ποτέ «όλα τα πιθανά μήκη» — γι' αυτό ο πίνακας μπορεί να μιλά σε
 * **ανάμεικτη** ανάλυση *(`214` για μια ολόκληρη ελάσσονα ομάδα, `2142` για μία
 * μοναδιαία μέσα της)* χωρίς καμία επιπλέον δομή. **Ο μακρύτερος νικά.**
 */
export function resolveIscoPrefix<TEntry>(
  table: Readonly<Record<string, TEntry>>,
  iscoCode: string | null | undefined,
): IscoPrefixVerdict<TEntry> {
  if (iscoCode === null || iscoCode === undefined || iscoCode.length === 0) {
    return { kind: 'absent' };
  }
  if (!ISCO_CODE_SHAPE.test(iscoCode)) {
    return { kind: 'malformed', value: iscoCode };
  }

  for (let length = iscoCode.length; length >= 1; length -= 1) {
    const prefix = iscoCode.slice(0, length);
    const entry: TEntry | undefined = table[prefix];
    if (entry !== undefined) {
      return { kind: 'declared', entry, prefix };
    }
  }

  return { kind: 'undeclared', code: iscoCode };
}
