/**
 * ADR-748 Φάση 3.5α — Η **ΠΡΟΤΑΣΗ** δουλειάς. Όχι ερώτηση.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * ΓΙΑΤΙ ΔΕΝ ΡΩΤΑΜΕ — ΤΟ ΕΙΠΕ Η ΕΒΔΟΜΗ ΕΡΕΥΝΑ, ΟΧΙ Η ΠΡΟΤΙΜΗΣΗ ΜΑΣ (§6.14)
 *
 * Το **Ε7.γ** ζητούσε «μία προαιρετική ερώτηση: τι δουλειά κάνεις;». Η έρευνα
 * στους ίδιους παίκτες που επικαλείται όλο το ADR το ανέτρεψε:
 *
 *   • **Revit 2022+** ρωτά — modal «Hello There!» (ειδικότητα **+** ρόλος), με
 *     λίστα προτεινόμενων αλλαγών για review και accept/decline. **Και το
 *     πληρώνει**: υπάρχει αίτημα στο Autodesk Ideas *«Disable "Hello There!"
 *     Prompt on First Run»* **και επίσημο άρθρο υποστήριξης «How to disable»**.
 *   • **ArchiCAD** δεν ρωτά ξεχωριστά: ο επιλογέας προφίλ ζει **μέσα** στο
 *     «Start ArchiCAD», δίπλα στο *«What would you like to do?»*.
 *   • **Cinema 4D** δεν ρωτά καθόλου: **Standard** layout + μόνιμος επιλογέας.
 *   • **NN/g**: *«Personalization is over-rated»* · **active user paradox** —
 *     οι χρήστες **αρνούνται** να ρυθμίσουν· η Amazon πετυχαίνει επειδή απαιτεί
 *     ***«no extra work on the users»***.
 *
 * 🔑 **Και το αποφασιστικό**: το Revit ρωτά επειδή **δεν ξέρει** — ένα προϊόν,
 * όλοι οι κλάδοι, καμία πληροφορία ρόλου. Ο Νέστωρ **ΞΕΡΕΙ**: 13 ρόλοι με ρητά
 * permissions, και το `pickDefaultJob()` υπολογίζει ζωντανά. Ερώτηση για κάτι
 * που ήδη ξέρεις **είναι** το active user paradox.
 *
 * ⚠️ Οι πηγές του §6.11.4 («+30–50% activation») είναι **appcues.com** και
 * **saasui.design** — εταιρείες που **πουλάνε onboarding**. Το NN/g μέτρησε ότι
 * όσοι πέρασαν το onboarding τα πήγαν **εξίσου καλά** με όσους το προσπέρασαν.
 * ═════════════════════════════════════════════════════════════════════════════
 * ΤΟ ΣΥΜΒΟΛΑΙΟ: **ΜΙΑ** ΠΡΟΤΑΣΗ, ΜΕ ΜΕΤΡΗΜΕΝΟ ΑΠΟΤΕΛΕΣΜΑ, ΑΝΑΣΤΡΕΨΙΜΗ
 *
 * 🔒 **Ο αριθμός ΔΕΝ μπορεί να αποκλίνει** — και είναι ιδιότητα, όχι σύμβαση:
 * βγαίνει από το **ίδιο** `filterItemsByJob()` που κάνει το πραγματικό
 * φιλτράρισμα, στα **ίδια** δέντρα που βάφει η οθόνη. Δεύτερος μετρητής θα
 * ήταν κατά λέξη το ελάττωμα των 17:13 (δύο μονοπάτια, δύο μονάδες).
 *
 * ⛔ **ΜΗΝ ονομάσεις τίποτα εδώ «onboarding»**: η λέξη είναι **πιασμένη** από το
 * **ADR-326** (`/api/onboarding/organization`, `OnboardingBanner`) με άλλο
 * νόημα — onboarding **οργανωτικής δομής** για **υπάρχοντα** `company_admin`.
 * Θα ήταν το έκτο λεξιλόγιο (Π-9), δηλαδή το ίδιο το ελάττωμα που θεραπεύουμε.
 *
 * ⛔ **ΜΗΝ το κάνεις React hook.** Είναι αριθμητική λογική — ίδιος λόγος με το
 * `jobs-visibility.ts`: μέσα σε hook θα ήταν αδοκίμαστη χωρίς render.
 *
 * @see docs/centralized-systems/reference/adrs/ADR-748-role-based-workspaces.md §6.14 / Ε7.γ′ / Υ-12
 */

import {
  JOB_ALL,
  decideJobAccess,
  pickDefaultJob,
  resolveAvailableJobs,
  type JobAccessInput,
  type JobSelection,
} from './jobs-access';
import { filterItemsByJob, summarizeHidden, type JobFilterableItem } from './jobs-visibility';
import type { JobId } from './jobs-registry';

// =============================================================================
// ΤΥΠΟΙ
// =============================================================================

/**
 * Ο **ελάχιστος** αριθμός δουλειών για να έχει νόημα πρόταση.
 *
 * Ε7.ια: *«Μία μόνο δουλειά ⇒ δεν υπάρχει καν επιλογή»*. Με μία διαθέσιμη, η
 * πρόταση θα ήταν «διάλεξε το μοναδικό πράγμα που μπορείς» — θόρυβος.
 */
export const MIN_JOBS_FOR_SUGGESTION = 2;

export interface JobSuggestionInput<T extends JobFilterableItem & { readonly subItems?: readonly T[] }> {
  /** Η **ίδια** είσοδος με τον ζωντανό υπολογισμό (Ε5.α) — ποτέ αποθηκευμένη. */
  readonly access: JobAccessInput;
  /** Η ενεργή δουλειά **τώρα**. Πρόταση υπάρχει μόνο όσο δεν έχει διαλέξει. */
  readonly activeJob: JobSelection;
  /** Την απέρριψε ήδη ο χρήστης; (Α-3: μία φορά «όχι» σημαίνει όχι.) */
  readonly dismissed: boolean;
  /**
   * ADR-798 Φάση 3 — η δουλειά που **υποδεικνύει το δηλωμένο επάγγελμα**, όταν
   * υπάρχει. **Σπάει ισοβαθμία, δεν διευρύνει σύνολο** (`jobs-access.ts`).
   *
   * ⚠️ **Προαιρετικό, και αυτό είναι το συμβόλαιο**: χωρίς αυτό η πρόταση είναι
   * γραμμή προς γραμμή η προηγούμενη. Το επάγγελμα **δεν είναι προϋπόθεση** για
   * να μιλήσουμε — είναι κριτήριο **ανάμεσα** σε ισοδύναμες απαντήσεις.
   *
   * 🔒 Περνά **ανέπαφο** στο `pickDefaultJob` και **δεν παρακάμπτει** τον έλεγχο
   * `granted` παρακάτω: επάγγελμα που δείχνει σε δουλειά για την οποία δεν
   * έχουμε **μετρημένο** δικαίωμα οδηγεί ξανά σε **σιωπή**, όχι σε πρόταση.
   */
  readonly tiebreak?: JobId | null;
  /**
   * Τα δέντρα πλοήγησης **ΗΔΗ φιλτραρισμένα κατά δικαίωμα** — ακριβώς αυτά που
   * βάφει η οθόνη. Δίνονται απ' έξω και δεν χτίζονται εδώ: έτσι το αρχείο μένει
   * καθαρό (μηδέν εξάρτηση από `navigation`/React) και ο έλεγχος μπορεί να
   * περάσει στημένα δέντρα.
   */
  readonly menus: readonly (readonly T[])[];
}

/**
 * Το αποτέλεσμα — **θετικά διατυπωμένο** και είναι κανόνας, όχι ύφος.
 *
 * **Ε14.ιγ (κανόνας θέσης)**: θετικός αριθμός («πόσα **θα δεις**») σε πρόταση
 * που δεν έχει γίνει ακόμη δεκτή· ο **αρνητικός** («πόσα λείπουν») ανήκει
 * **μόνο** στο ανοιγμένο δοχείο, με ρήμα και ενέργεια. Η ίδια οπτική θέση με
 * δύο νοήματα είναι το σχήμα ελαττώματος που πιάστηκε **τέσσερις** φορές εδώ.
 */
/**
 * **ΓΙΑΤΙ** προτείνεται — η αλυσίδα αιτίασης του **Υ-6**.
 *
 * 🔴 Βρέθηκε **ΣΤΗΝ ΟΘΟΝΗ** (2026-08-25): το popover έλεγε «με βάση τα
 * δικαιώματά σου» σε **υπερδιαχειριστή**, όπου **όλες** οι δουλειές έχουν
 * ταυτόσημα δικαιώματα — η αιτία ήταν το **επάγγελμα**. Το απέδειξε το ίδιο το
 * πείραμα: σβήνοντας τη δήλωση η πρόταση **εξαφανίστηκε**, με τα δικαιώματα
 * **αμετάβλητα**.
 *
 * ⚠️ Ένα μήνυμα που ονομάζει **λάθος** αιτία είναι χειρότερο από κανένα:
 * διδάσκει στον άνθρωπο **λάθος μοντέλο** του συστήματος. Κανένα test δεν
 * μπορούσε να το δει — το κλειδί i18n ήταν υπαρκτό και η μετάφραση σωστή.
 */
export type JobSuggestionBasis = 'occupation' | 'permissions';

export interface JobSuggestionOutcome {
  readonly job: JobId;
  /** Υ-6 — **μετρημένη**, ποτέ υποτιθέμενη. */
  readonly basis: JobSuggestionBasis;
  /** Πόσα στοιχεία πρώτου επιπέδου θα μείνουν στην οθόνη αν δεχτεί. */
  readonly visibleCount: number;
  /** Πόσα βλέπει **τώρα** — ο παρονομαστής του «Χ από Υ». */
  readonly totalCount: number;
}

