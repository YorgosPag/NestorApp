/**
 * *«ΠΟΙΕΣ ΠΡΑΞΕΙΣ επιτρέπεται να ζητήσει ο επισκέπτης από ΑΥΤΟ το επάγγελμα;»*
 *
 * @related ADR-841 §7 Α5 (οι επαγγελματίες δεν είναι αγγελία) · Α9.1 (ποιος εξέδωσε
 *          τον αριθμό) · ADR-827 §9.8 (το προφίλ ΕΙΝΑΙ κουμπί) · ADR-824 §6
 * @module config/isco-showcase-acts
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΤΟ ΜΕΤΡΗΜΕΝΟ ΓΕΓΟΝΟΣ ΠΟΥ ΤΟ ΓΕΝΝΗΣΕ (2026-09-06, στην οθόνη)
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * Η βιτρίνα ενός γραφείου **εγκαταστάσεων φυσικού αερίου** *(ISCO `7126`, μητρώο
 * ΦΑ-4471 από την Περιφέρεια)* πρόσφερε **«Ζητήστε του να αναλάβει το ακίνητό
 * σας»**, και από κάτω *«η **μεσιτική σύμβαση** καταρτίζεται εγγράφως…»*.
 *
 * Δηλαδή ζητούσαμε από τεχνίτη να ασκήσει **μεσιτεία** — δραστηριότητα που ο
 * **Ν.4072/2012** επιτρέπει μόνο σε εγγεγραμμένους μεσίτες. Το
 * `AgencyProfileContent` απέδιδε το κουμπί **χωρίς καμία συνθήκη**: δεν ήταν
 * λάθος κανόνας, ήταν **απουσία ερωτήματος**.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΓΙΑΤΙ ΔΕΝ ΠΑΡΑΓΕΤΑΙ ΑΠΟ ΤΟ `authority` — ΤΟ ΑΠΕΔΕΙΞΕ Ο ΔΙΚΗΓΟΡΟΣ
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * Ο πειρασμός είναι μια γραμμή, χωρίς νέο αρχείο:
 *
 * ```ts
 * resolveRegistryAuthority(isco).authority === 'gemi' ? 'mandate' : 'work-request'
 * ```
 *
 * ⛔ **Λάθος, και όχι οριακά.** Το `ISCO_REGISTRY_AUTHORITY` απαντά *«ποιος
 * **εξέδωσε** τον αριθμό»*. Εδώ το ερώτημα είναι *«τι επιτρέπεται να σου
 * **ζητήσω**»*. Τα δύο συμπίπτουν σε 13 από τα 15 επαγγέλματα — και **αποκλίνουν**
 * ακριβώς εκεί που η απόκλιση κοστίζει:
 *
 *   • **`2611` δικηγόρος** *(`bar-association`)* και **`2411` λογιστής** *(`oee`)*
 *     έχουν αρχή μητρώου, άρα ο συντομευμένος κανόνας θα τους έδινε
 *     «ζητήστε προσφορά». Η **σύγκριση αμοιβών** σε αυτά τα επαγγέλματα είναι
 *     ρυθμιζόμενη ύλη· ένα κουμπί που καλεί σε προσφορά τιμής **διαφημίζει πράξη
 *     που δεν μας ανήκει να διαφημίσουμε**.
 *
 * ⇒ **Δεύτερη δήλωση, ΙΔΙΑ ρίζα.** Ο πίνακας εδώ έχει τα **ίδια ακριβώς κλειδιά**
 * με το `ISCO_REGISTRY_AUTHORITY`, και η άγκυρα *(`__tests__/isco-showcase-acts`)*
 * **απαγορεύει να διαφωνήσουν**: νέο επάγγελμα στον έναν πίνακα κοκκινίζει αμέσως
 * αν λείπει από τον άλλον. Είναι το ιδίωμα του `workspace-scope.ts` — *«οι δύο
 * μηχανές επιτρέπεται να υπάρχουν, δεν επιτρέπεται να διαφωνήσουν»*.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 ΤΟ `contact` ΔΕΝ ΔΗΛΩΝΕΤΑΙ ΕΔΩ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * *«Πλησιάστε το γραφείο»* **δεν εξαρτάται από το επάγγελμα** — κάθε δημοσιευμένος
 * επαγγελματίας οφείλει να είναι προσεγγίσιμος. Αν ήταν γραμμένο σε κάθε γραμμή,
 * η **πρώτη ξεχασμένη γραμμή** θα έκανε έναν υπαρκτό επαγγελματία **απροσπέλαστο**
 * — βλάβη σιωπηλή και χειρότερη από αυτή που διορθώνουμε.
 *
 * ⇒ **Fail-open για την επαφή, fail-closed για όλα τα άλλα**: το `contact` το
 * προσθέτει το σύνορο *(`lib/professional/showcase-acts.ts`)*, πάντα· εδώ
 * δηλώνονται **μόνο** οι πράξεις που πρέπει να **κερδηθούν**.
 *
 * ⚠️ **Το κενό `acts: []` ΕΙΝΑΙ ΔΗΛΩΣΗ, όχι παράλειψη** — γι' αυτό απαιτείται `why`.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔶 ΔΗΛΩΜΕΝΟ ΑΝΟΙΧΤΟ — ΔΥΟ ΕΠΑΓΓΕΛΜΑΤΑ ΤΩΝ ΔΟΚΙΜΑΣΤΙΚΩΝ ΔΕΔΟΜΕΝΩΝ ΣΙΩΠΟΥΝ
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * Το `demo-professionals.ts` περιέχει **`7112`** *(κτίστης)* και **`7212`*
 * *(συγκολλητής)*, που **δεν έχουν γραμμή σε κανέναν από τους δύο πίνακες** ⇒
 * `unexamined` ⇒ **μόνο επαφή**. Αυτό είναι **σωστό fail-closed**, όχι ελάττωμα:
 * η προσθήκη τους είναι απόφαση του `ISCO_REGISTRY_AUTHORITY` *(ποιο μητρώο;)* και
 * γίνεται **εκεί πρώτα** — αλλιώς θα δηλώναμε πράξη για επάγγελμα του οποίου την
 * ταυτότητα δεν έχουμε εξετάσει.
 */

