/**
 * **Τι μπορεί να ζητήσει ο επισκέπτης από μια βιτρίνα** — κλειστό σύνολο.
 *
 * ⚠️ **ΔΕΝ είναι λίστα κουμπιών.** Είναι λίστα **πράξεων με έγγραφο**: κάθε τιμή
 * αντιστοιχεί σε αίτημα που γράφεται με ημερομηνία και μπορεί να ανακληθεί.
 */
export type ShowcaseAct =
  /** *«Ανάλαβε το ακίνητό μου»* — εντολή μεσιτείας (ADR-827). Ρυθμιζόμενη. */
  | 'mandate'
  /** *«Δώσε μου προσφορά για εργασία»* — τεχνικά/μελετητικά επαγγέλματα. */
  | 'work-request'
  /** *«Πλησιάστε»* — καθολική, δεν δηλώνεται ανά επάγγελμα (δες docblock). */
  | 'contact';

/**
 * Οι πράξεις που **κερδίζονται από το επάγγελμα** — το `contact` εξαιρείται
 * **με τον τύπο**, ώστε μια γραμμή του πίνακα να μην μπορεί καν να το δηλώσει.
 */
export type DeclaredShowcaseAct = Exclude<ShowcaseAct, 'contact'>;

export interface IscoShowcaseActEntry {
  /** ⚠️ Κενός πίνακας = **δηλωμένο μηδέν**, και ο `why` λέει γιατί. */
  readonly acts: readonly DeclaredShowcaseAct[];
  /** Ο **επίσημος** τίτλος ISCO-08 + γιατί δικαιολογεί (ή αρνείται) την πράξη. */
  readonly why: string;
}

