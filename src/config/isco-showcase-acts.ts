/**
 * *«Ποιες δηλωμένες πράξεις δέχεται αυτό το επάγγελμα;»*
 *
 * @param iscoCode Ο κωδικός ISCO-08 της **δηλωμένης ειδικότητας**.
 * @returns Οι κερδισμένες πράξεις — **κενό** για κάθε μη-δηλωμένη κατάσταση.
 *
 * 🔒 **FAIL-CLOSED, ΚΑΙ ΕΙΝΑΙ ΤΟ ΝΟΗΜΑ ΤΟΥ ΑΡΧΕΙΟΥ.** Οι τρεις μη-δηλωμένες
 * ετυμηγορίες του `resolveIscoPrefix` *(`undeclared` · `absent` · `malformed`)*
 * ισοπεδώνονται σε **καμία πράξη**: άγνωστο επάγγελμα **δεν κερδίζει** δικαίωμα.
 *
 * ⚠️ Η ισοπέδωση γίνεται **μόνο εδώ**, στο σύνορο με τον καταναλωτή — που πράγματι
 * δεν έχει διαφορετική ενέργεια για καθεμία *(ίδιο ιδίωμα με το
 * `resolveJobAffinity`)*. Η **διάκρισή** τους μένει ζωντανή στο `isco-prefix.ts`
 * για όποιον τη χρειαστεί.
 */
export function resolveShowcaseActs(
  iscoCode: string | null | undefined,
): readonly DeclaredShowcaseAct[] {
  const verdict = resolveIscoPrefix(ISCO_SHOWCASE_ACTS, iscoCode);
  return verdict.kind === 'declared' ? verdict.entry.acts : [];
}
