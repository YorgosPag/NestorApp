/**
 * ADR-824 Φάση 4 — **ΤΟ ΤΡΙΤΟ ΦΙΛΤΡΟ ΤΗΣ ΠΛΟΗΓΗΣΗΣ: Η ΙΚΑΝΟΤΗΤΑ ΤΟΥ ΟΡΓΑΝΙΣΜΟΥ.**
 *
 * ΚΑΘΑΡΗ ΣΥΝΑΡΤΗΣΗ. Μηδέν I/O, μηδέν React — όπως το `jobs-visibility.ts` δίπλα του.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΓΙΑΤΙ **ΤΡΙΤΟ** ΦΙΛΤΡΟ ΚΑΙ ΟΧΙ ΓΡΑΜΜΗ ΣΕ ΚΑΠΟΙΟ ΑΠΟ ΤΑ ΔΥΟ ΥΠΑΡΧΟΝΤΑ
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * Το ADR-748 §14.5 έχει ήδη γραμμένα **δύο διαδοχικά και ανεξάρτητα** φίλτρα, και
 * το `useJobFilteredNavigation` απαγορεύει ρητά την ένωσή τους:
 *
 *   1. **ΔΙΚΑΙΩΜΑ**       → `filterItemsByPermissions()` — «τι επιτρέπεται σε ΣΕΝΑ»
 *   2. **ΕΝΕΡΓΗ ΔΟΥΛΕΙΑ** → `filterItemsByJob()`        — «τι ταιριάζει στη δουλειά σου»
 *
 * Η ικανότητα οργανισμού είναι **τέταρτο διακριτό ερώτημα** (ADR-824 §1): *«επιτρέπεται
 * σε αυτόν τον ΟΡΓΑΝΙΣΜΟ αυτή η ρυθμιζόμενη δραστηριότητα;»*. Το υποκείμενο δεν είναι
 * ο άνθρωπος ούτε η δουλειά του — είναι **το γραφείο**.
 *
 * ⛔ **ΓΙΑΤΙ ΟΧΙ ΜΕΣΑ ΣΤΟ `filterItemsByPermissions`**: εκείνο δέχεται `string[]`. Να
 * περάσει η ικανότητα από εκεί σημαίνει να γίνει **σημαία σε σάκο σημαιών** — και το
 * **ADR-824 §4.3 το απέρριψε ονομαστικά**: *«ανοιχτό σύνολο κλειδιών, χωρίς αυθεντία,
 * χωρίς κύκλο ζωής, χωρίς αιτιολογία»*. Η ικανότητα έχει και τα τρία.
 *
 * ⛔ **ΓΙΑΤΙ ΟΧΙ ΜΕΣΑ ΣΤΟ `filterItemsByJob`**: εκείνο είναι **προβολή** και το ADR-748
 * το δηλώνει — *«Δεν αλλάζει δικαιώματα, μόνο τι εμφανίζεται»*. Η προβολή είναι
 * **αναστρέψιμη**: υπάρχει κουμπί «Αποκάλυψη κρυμμένων» που την ακυρώνει. Δες παρακάτω
 * γιατί αυτό είναι το επικίνδυνο μισό.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΣΗΜΕΙΟ ΕΦΑΡΜΟΓΗΣ ΕΙΝΑΙ ΜΕΡΟΣ ΤΗΣ ΟΡΘΟΤΗΤΑΣ — ΟΧΙ ΛΕΠΤΟΜΕΡΕΙΑ
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * Το `useJobFilteredNavigation` στον τρόπο «Αποκάλυψη κρυμμένων» επιστρέφει τα
 * **ΑΦΙΛΤΡΑΡΙΣΤΑ** δέντρα (`pick(menus.main, …)`) ώστε κάθε κρυμμένο στοιχείο να
 * ξαναβρεθεί **στη θέση του**. Άρα ό,τι κόβεται στη **βαθμίδα της δουλειάς**
 * ξαναγυρίζει με **ένα κλικ**.
 *
 * ⇒ Αν αυτό το φίλτρο έτρεχε εκεί, η Μαρία θα πατούσε «Αποκάλυψη κρυμμένων» και η
 * εφαρμογή θα της **ξαναπρόσφερε** τη μεσιτεία. Γι' αυτό εφαρμόζεται **μέσα στο
 * `buildJobMenus`**, πριν χτιστούν τα δέντρα: το στοιχείο δεν είναι «κρυμμένο», είναι
 * **ανύπαρκτο** — ακριβώς η διάκριση που το `JobFilteredNavigation.hiddenCount`
 * τεκμηριώνει για τα δικαιώματα *(«δεν είναι κρυμμένα, είναι ανύπαρκτα για τον χρήστη
 * και δεν επαναφέρονται με κλικ»)*.
 *
 * 🔑 **Και γι' αυτό δεν προσμετράται στο `hiddenCount`**: ένας δείκτης «+1 κρυμμένο»
 * που δεν αποκαλύπτεται ποτέ θα ήταν υπόσχεση που η οθόνη δεν μπορεί να τηρήσει.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ ΔΕΝ ΕΙΝΑΙ ΑΣΦΑΛΕΙΑ
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * Ο φρουρός είναι ο τύπος `BrokerageAuthority` στον διακομιστή (ADR-824 §6): διαδρομή
 * που τον ξεχνά **δεν μεταγλωττίζεται**. Εδώ ζει **ειλικρίνεια της επιφάνειας** — να
 * μην προσφέρεται πόρτα που θα απαντήσει 403. Το OWASP το γράφει κατά λέξη:
 * *«Developers must **never** rely on client-side access control checks»*.
 *
 * @see docs/centralized-systems/reference/adrs/ADR-824-organization-regulated-capability.md
 * @see src/config/jobs-visibility.ts — το **δεύτερο** φίλτρο· ποτέ μην τα ενώσεις
 * @module config/navigation-capability
 */

import {
  isCapabilityKnownToOrganization,
  type CapabilityStatus,
  type OrganizationCapability,
} from '@/types/organization-capability';

// =============================================================================
// Ο ΠΙΝΑΚΑΣ — ποια διαδρομή απαιτεί ποια ικανότητα
// =============================================================================

/**
 * **Κλειστός πίνακας: διαδρομή → ικανότητα οργανισμού.**
 *
 * ⚠️ **Οι διαδρομές γράφονται ΧΩΡΙΣ το πρόθεμα χώρου** (`/o/<ψευδώνυμο>`), όπως
 * ακριβώς είναι γραμμένες στο `smart-navigation-factory` και στο `jobs-registry`
 * (`'/listings/mandates'`). Το πρόθεμα το προσθέτει το σύνορο πλοήγησης αργότερα·
 * μια εγγραφή με πρόθεμα εδώ **δεν θα ταίριαζε ποτέ** και θα ήταν σιωπηλά ανενεργή.
 *
 * 🔑 **Ο κατάλογος αρκεί· η φόρμα δεν χρειάζεται γραμμή.** Το
 * `/listings/mandates/new` **δεν υπάρχει στο πλαϊνό μενού** — ο μόνος σύνδεσμος προς
 * αυτήν ζει *μέσα* στον κατάλογο, και ο κατάλογος τον σβήνει μόνος του χωρίς `active`.
 * Γραμμή εδώ θα ήταν φρουρός για πόρτα που κανείς δεν ζωγραφίζει.
 */
export const CAPABILITY_GATED_ROUTES: ReadonlyMap<string, OrganizationCapability> = new Map([
  ['/listings/mandates', 'brokerage_listings'],
]);

/**
 * **Η κατάσταση ΚΑΘΕ ικανότητας του οργανισμού, μαζί.**
 *
 * 🔑 **`Record` πάνω στο κλειστό σύνολο, ΟΧΙ `Partial` και ΟΧΙ συνάρτηση-αναγνώστης.**
 * Μια δεύτερη ικανότητα στο `ORGANIZATION_CAPABILITIES` **δεν θα μεταγλωττιστεί** μέχρι
 * κάθε καταναλωτής να πει τι κάνει μαζί της. Με `Partial` θα διάβαζε `undefined` και θα
 * χρειαζόταν σιωπηλή προεπιλογή — δηλαδή απόφαση παρμένη από τον τύπο αντί για άνθρωπο.
 */
export type OrganizationCapabilityView = Readonly<
  Record<OrganizationCapability, CapabilityStatus>
>;

/** Το ελάχιστο που χρειάζεται το φίλτρο. Δομικός τύπος: **καμία** σύζευξη με το `MenuItem`. */
export interface CapabilityFilterableItem {
  readonly href: string;
}

// =============================================================================
// Η ΚΡΙΣΗ
// =============================================================================

/**
 * **Προσφέρεται αυτή η διαδρομή σε αυτόν τον οργανισμό;**
 *
 * 🔴 **ΑΤΑΞΙΝΟΜΗΤΟ ⇒ ΠΡΟΣΦΕΡΕΤΑΙ.** Διαδρομή εκτός πίνακα δεν είναι ρυθμιζόμενη, άρα
 * δεν αφορά αυτό το φίλτρο. Η αντίστροφη επιλογή («δεν το ξέρω ⇒ κρύψ' το») θα έκρυβε
 * **ολόκληρο το μενού** την πρώτη φορά που κάποιος ξεχνούσε μια γραμμή — και είναι
 * ακριβώς το λάθος που το `isRouteVisibleForJob` τεκμηριώνει ότι πλήρωσε ζωντανά.
 *
 * ⚠️ Το fail-closed **δεν** ζει εδώ, ζει στην **πηγή**: ο
 * {@link useOrganizationCapability} επιστρέφει `unrequested` σε κάθε αστοχία ανάγνωσης,
 * άρα η άγνωστη κατάσταση φτάνει εδώ ήδη ως «μην το προσφέρεις».
 */
export function isRouteOfferable(href: string, view: OrganizationCapabilityView): boolean {
  const required = CAPABILITY_GATED_ROUTES.get(href);
  if (required === undefined) return true;
  return isCapabilityKnownToOrganization(view[required]);
}

/**
 * **Κόβει ό,τι δεν προσφέρεται — αναδρομικά.**
 *
 * ⚠️ **Αναδρομικό επίτηδες, παρότι σήμερα ο πίνακας έχει ΜΟΝΟ διαδρομή πρώτου
 * επιπέδου.** Και τα δύο αδελφά φίλτρα (`filterItemsByPermissions`, `filterItemsByJob`)
 * είναι αναδρομικά· ένα ρηχό τρίτο θα δούλευε **σήμερα** και θα αστοχούσε σιωπηλά την
 * ημέρα που μια ρυθμιζόμενη διαδρομή μπει ως υπο-στοιχείο. Άγκυρα: ομάδα «Υ».
 *
 * ⚠️ **Ο γονιός κρίνεται ΠΡΩΤΑ**: αν πέφτει ο γονιός, πέφτουν και τα παιδιά του μαζί
 * του — δεν έχει νόημα να επιβιώσει παιδί κάτω από πόρτα που δεν ζωγραφίζεται.
 *
 * 🔑 `Object.assign` και όχι `{ ...item }`: το spread πάνω σε generic `T` **δεν** είναι
 * εκχωρήσιμο στο `T` (γνωστός περιορισμός TS) και θα απαιτούσε assertion — το ίδιο
 * ιδίωμα, για τον ίδιο λόγο, με το `filterItemsByJob`.
 */
export function filterItemsByCapability<
  T extends CapabilityFilterableItem & { readonly subItems?: readonly T[] },
>(items: readonly T[], view: OrganizationCapabilityView): T[] {
  const kept: T[] = [];

  for (const item of items) {
    if (!isRouteOfferable(item.href, view)) continue;

    const subItems = item.subItems;
    if (subItems === undefined) {
      kept.push(item);
      continue;
    }

    kept.push(Object.assign({}, item, { subItems: filterItemsByCapability(subItems, view) }));
  }

  return kept;
}
