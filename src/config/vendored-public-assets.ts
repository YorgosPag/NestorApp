/**
 * Ένα αντίγραφο τρίτου μέσα στο `public/`.
 *
 * 🔑 Το `expectation` είναι **δήλωση της πραγματικότητας**, όχι ευχή: η πύλη απαιτεί το
 * αρχείο να είναι **ακριβώς** ό,τι λέει εδώ. Έτσι μια σιωπηλή απόκλιση κοκκινίζει, ενώ μια
 * **σκόπιμη** ανανέωση απαιτεί κάποιον να γυρίσει συνειδητά αυτή τη λέξη.
 */
export interface VendoredPublicAsset {
  /** Η διαδρομή μέσα στο `public/`, όπως τη ζητά ο browser *(χωρίς αρχική κάθετο)*. */
  readonly publicPath: string;
  /** Το αρχείο-πηγή μέσα στο `node_modules`, από το οποίο **παράγεται** το αντίγραφο. */
  readonly packagePath: string;
  /** Το πακέτο που το δημοσιεύει — για να ξέρει ο άνθρωπος τι να αναβαθμίσει. */
  readonly packageName: string;
  /** Άδεια — N.5: μόνο MIT / Apache-2.0 / BSD διανέμονται. */
  readonly license: 'MIT' | 'Apache-2.0' | 'BSD-3-Clause';
  /**
   * `identical` — το αντίγραφο **πρέπει** να είναι byte-ίδιο με την πηγή.
   * `drifted`   — **μετρημένη, δηλωμένη** απόκλιση που δεν έχει ακόμη εξεταστεί.
   */
  readonly expectation: 'identical' | 'drifted';
  /** Γιατί το `drifted` είναι ακόμη ανεκτό — υποχρεωτικό όταν δεν είναι `identical`. */
  readonly driftNote?: string;
}

