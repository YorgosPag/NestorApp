/**
 * Πόσο βαθιά πάει η βλάβη όταν λείπει η ρύθμιση.
 *
 * - `fatal` — η εφαρμογή δεν μπορεί να σερβίρει **τίποτα** σωστά. Το boot **πετά**.
 * - `feature` — **μία** δυνατότητα πέφτει, και πέφτει **σιωπηλά**. Το boot **ονομάζει**.
 */
export type EnvironmentSeverity = 'fatal' | 'feature';

/** Μία δηλωμένη ρύθμιση: τι είναι, ποιος τη χρειάζεται, τι σπάει χωρίς αυτήν. */
export interface EnvironmentRequirement {
  /** Το όνομα της μεταβλητής, ακριβώς όπως το ζητά ο κώδικας. */
  readonly name: string;
  /** Πόσο βαθιά πάει η βλάβη. */
  readonly severity: EnvironmentSeverity;
  /** Ποια δυνατότητα την κατέχει — με ανθρώπινο όνομα, όχι μονοπάτι αρχείου. */
  readonly feature: string;
  /**
   * 🔑 **ΤΙ ΒΛΕΠΕΙ Ο ΑΝΘΡΩΠΟΣ ΟΤΑΝ ΛΕΙΠΕΙ.** Το πιο σημαντικό πεδίο του μητρώου:
   * είναι η διαφορά ανάμεσα σε «λείπει μια μεταβλητή» (που δεν λέει τίποτα σε κανέναν)
   * και «**ο ιδιοκτήτης παίρνει “άκυρος σύνδεσμος” και δεν μπορεί να εγκρίνει**».
   */
  readonly consequence: string;
  /** Το αρχείο που την καταναλώνει — για να μη χρειάζεται `grep` όποιος τη διορθώνει. */
  readonly consumer: string;
}

