/**
 * @fileoverview **ΟΙ ΕΙΚΟΝΕΣ ΠΟΥ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΜΠΟΥΝ ΣΕ EMAIL** — μία δήλωση, μία πύλη.
 * @related ADR-853 §19 (Θ4/Θ5) · ADR-848 · config/vendored-public-assets *(αδελφό ιδίωμα)*
 * @module config/email-assets
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ — Η ΚΛΑΣΗ ΠΟΥ ΚΑΝΕΝΑ ΕΡΓΑΛΕΙΟ ΔΕΝ ΒΛΕΠΕΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Μια εικόνα email είναι **συμβολοσειρά** που δείχνει σε **αρχείο του `public/`**. Ανάμεσα
 * στα δύο δεν στέκεται **τίποτα**: ο μεταγλωττιστής δεν βλέπει συμβολοσειρά, το `next build`
 * δεν ελέγχει το `public/`, κανένα test απόδοσης δεν τρέχει πριν φύγει το μήνυμα. Μετονομασία
 * ή διαγραφή του αρχείου είναι **αθόρυβη**, και η αστοχία εμφανίζεται **στον παραλήπτη** —
 * εβδομάδες αργότερα, χωρίς να ονομάσει την αιτία.
 *
 * Με αυτό το μητρώο, εμφανίζεται **στο `git add`**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ ΚΑΜΙΑ SVG — ΚΑΙ ΤΟ ΕΠΙΒΑΛΛΕΙ Ο ΤΥΠΟΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το Outlook *(web + new Windows)* **σταμάτησε** να αποδίδει SVG από **09/2025** — ο
 * παραλήπτης βλέπει **κενό πλαίσιο**· το Gmail δεν τα υποστήριξε ποτέ πλήρως. Το
 * `public/images/logo-email.svg` **υπάρχει** στο δέντρο, με όνομα που προσκαλεί τη χρήση του
 * σε email. Δεν αποκτά γραμμή εδώ, και ο τύπος {@link EmailImageMediaType} κάνει **αδύνατο**
 * να αποκτήσει.
 *
 * ⚠️ **ΤΑ ΛΟΓΟΤΥΠΑ ΤΟΥ ΕΝΟΙΚΟΥ ΔΕΝ ΖΟΥΝ ΕΔΩ.** Το `companyLogoUrl` *(ADR-312 Φάση 8)* είναι
 * **δεδομένα πελάτη** — απόλυτο URL από το Storage, που δεν ελέγχουμε και δεν προδιαγράφουμε.
 * Εδώ ζουν **μόνο** τα δικά μας πακεταρισμένα αρχεία.
 *
 * **Layering**: config — καθαρά δεδομένα, μηδέν εισαγωγές, μηδέν παρενέργειες.
 */

/**
 * Οι **μόνοι** τύποι που αποδίδει κάθε πρόγραμμα email το 2026.
 *
 * ⛔ **ΜΗΝ προσθέσεις `image/svg+xml`** — δες την επικεφαλίδα. ⛔ **ΜΗΝ προσθέσεις
 * `image/webp`**: το Outlook σε Windows δεν το αποδίδει, και μια εικόνα που λείπει στον μισό
 * κόσμο είναι χειρότερη από μια εικόνα που δεν στάλθηκε ποτέ.
 */
export type EmailImageMediaType = 'image/png' | 'image/jpeg';

/**
 * Μία εικόνα που **επιτρέπεται** να αναφερθεί από πρότυπο email.
 *
 * 🔑 Τα `byteSize`/διαστάσεις είναι **δήλωση της πραγματικότητας**, όχι ευχή: η άγκυρα
 * απαιτεί το αρχείο στον δίσκο να είναι **ακριβώς** ό,τι λέει εδώ. Έτσι μια σιωπηλή
 * μετονομασία κοκκινίζει, ενώ μια **σκόπιμη** αντικατάσταση απαιτεί κάποιον να γυρίσει
 * συνειδητά αυτόν τον αριθμό — και να δει τι μεγέθους πράγμα στέλνει.
 */
export interface EmailImageAsset {
  /** Η διαδρομή όπως τη ζητά ο browser, **με** αρχική κάθετο. */
  readonly publicPath: string;
  /** Ο τύπος — περιορισμένος σε ό,τι αποδίδουν όλα τα προγράμματα email. */
  readonly mediaType: EmailImageMediaType;
  /** Το πλάτος απόδοσης σε `<img width>` — κρατά τον χώρο όσο η εικόνα είναι μπλοκαρισμένη. */
  readonly renderWidth: number;
  /** Το ύψος απόδοσης σε `<img height>`. */
  readonly renderHeight: number;
  /** **Μετρημένα** bytes του αρχείου στον δίσκο. */
  readonly byteSize: number;
  /** Ποιος το δείχνει και πού — σε ανθρώπινη γλώσσα. */
  readonly purpose: string;
  /** Γιατί το μέγεθος ξεπερνά τον προϋπολογισμό — **υποχρεωτικό** όταν τον ξεπερνά. */
  readonly oversizeNote?: string;
}

/**
 * Πόσα bytes είναι **ευπρεπές** να κατεβάσει κάποιος για ένα λογότυπο email.
 *
 * Δεν είναι αυθαίρετο: ο proxy της Google κατεβάζει **κάθε** εικόνα για **κάθε** παραλήπτη.
 * Ό,τι περνά αυτό το όριο πρέπει να **δηλώσει γιατί** — δεν μπλοκάρεται, **ονομάζεται**.
 */
export const EMAIL_IMAGE_BYTE_BUDGET = 64 * 1024;

