/**
 * @fileoverview Ο τύπος του `t` **ως παράμετρος** — μία φορά, για κάθε αρχείο ρύθμισης.
 *
 * ## 🔑 Γιατί ξεχωριστό αρχείο για ένα ψευδώνυμο τύπου
 *
 * Ένα αρχείο ρύθμισης που παράγει ανθρώπινη ετικέτα **δεν επιτρέπεται να εισάγει τον hook**:
 * θα έσερνε React/i18next μέσα σε κώδικα που καταναλώνει και ο καθαρός Λ2, και η άγκυρα
 * `title-block-purity.test.ts` ελέγχει τις εξαρτήσεις **μεταβατικά** — δηλαδή θα κοκκίνιζε
 * αρχεία που δεν άγγιξε κανείς. Η θεραπεία είναι type-only import, και ήταν ήδη γραμμένη
 * **δύο** φορές (`project-role-labels.ts`, `ProjectParticipationSection.tsx`), με το ένα
 * αντίγραφο ονομασμένο κατά τον **πρώτο του καταναλωτή**. Ο τρίτος θα έγραφε τρίτο.
 *
 * ⇒ Ζει εδώ, **ουδέτερα ονομασμένο** (N.0.2). Ο ρόλος δεν είναι ιδιότητα του `t`.
 *
 * ⚠️ **Type-only, πάντα.** Το `import type` δεν αφήνει runtime ίχνος· ένα σκέτο `import`
 * εδώ θα ακύρωνε ολόκληρο τον λόγο ύπαρξης του αρχείου — **χωρίς κανένα σφάλμα**, και η
 * μόνη ένδειξη θα ήταν η άγκυρα καθαρότητας να κοκκινίζει σε άσχετο αρχείο.
 *
 * @module config/config-translate-fn
 */

/** Το `t` όπως το επιστρέφει ο hook — δεκτό ως όρισμα από καθαρά αρχεία ρύθμισης. */
export type ConfigTranslateFn = ReturnType<
  typeof import('@/i18n/hooks/useTranslation').useTranslation
>['t'];
