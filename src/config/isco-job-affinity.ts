/**
 * ADR-798 Φάση 3 — Η **ΣΥΓΓΕΝΕΙΑ** επαγγέλματος και δουλειάς. Όχι χαρτογράφηση.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔒 ΤΙ ΚΑΝΕΙ ΚΑΙ ΤΙ ΔΕΝ ΚΑΝΕΙ — Η ΓΡΑΜΜΗ ΕΙΝΑΙ ΑΣΦΑΛΕΙΑ, ΟΧΙ ΥΦΟΣ
 *
 *   ✅ **ΣΠΑΕΙ ΙΣΟΒΑΘΜΙΑ** ανάμεσα σε δουλειές που ο χρήστης **ΗΔΗ δικαιούται**.
 *   ⛔ **ΠΟΤΕ δεν προσθέτει δουλειά** στο διαθέσιμο σύνολο.
 *
 * Το επάγγελμα είναι **αυτο-δηλωμένο** (ADR-798 Α4): ο χρήστης το γράφει μόνος
 * του σε ένα πεδίο. Αν διεύρυνε το σύνολο, θα ήταν **κλιμάκωση προνομίων με ένα
 * dropdown**. Η δομική εγγύηση δεν ζει εδώ αλλά στο `pickDefaultJob()`: το
 * `tiebreak` συγκρίνεται **μόνο** με μέλη του `available`, που υπολογίζεται
 * αποκλειστικά από permissions και **δεν βλέπει ποτέ** αυτό το αρχείο.
 *
 * 🏆 Το ίδιο λέει και το **NIST SP 800-63**: σε IAL1 τα αυτο-δηλωμένα γνωρίσματα
 * είναι κατάλληλα για **εξατομίκευση**, ενώ οι **αποφάσεις εξουσιοδότησης**
 * απαιτούν **επαληθευμένα** γνωρίσματα (IAL2/IAL3). Η Φάση 5 (`verified`) είναι
 * ακριβώς αυτό το σκαλί — ADR-798 §7.
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 ΓΙΑΤΙ ΚΛΕΙΔΙ ΤΟ **ΠΡΟΘΕΜΑ** ISCO ΚΑΙ ΟΧΙ Ο ΤΕΤΡΑΨΗΦΙΟΣ — ΟΥΤΕ ΤΟ ESCO URI
 *
 * Το ISCO-08 είναι **ιεραρχικό με πρόθεμα**, και αυτό είναι **εγγύηση του
 * προτύπου**, όχι σύμπτωση: **10** μείζονες *(1 ψηφίο)* → **43** υπο-μείζονες
 * *(2)* → **130** ελάσσονες *(3)* → **436** μοναδιαίες *(4)*, όπου τα πρώτα
 * ψηφία ενός κωδικού **ΕΙΝΑΙ** η γονική του ομάδα. Άρα η ανάλυση **μεγαλύτερου
 * προθέματος** δεν είναι ευρετική — είναι **ακριβής**.
 *
 * Αυτό επιτρέπει να δηλώνεται συγγένεια **στο επίπεδο που όντως ξέρουμε**:
 * `214` για **όλους** τους μηχανικούς με μία γραμμή, αλλά `2161` ξεχωριστά
 * επειδή η αδελφή ομάδα `2163` *(σχεδιαστές προϊόντος)* **δεν** σχεδιάζει
 * κτίρια. Ο εναλλακτικός σχεδιασμός — πίνακας **436** μοναδιαίων ομάδων — θα
 * ήταν 436 γραμμές από τις οποίες θα ξέραμε τις ~20.
 *
 * ⛔ **ΟΧΙ ESCO URI**: τα ESCO occupations είναι **3.039** και οι ταυτότητές
 * τους αλλάζουν ανά έκδοση, ενώ το ISCO-08 είναι παγωμένο από το 2008. Και η
 * κατεύθυνση ESCO→ISCO είναι **ολική** *(κάθε occupation ανήκει σε ακριβώς μία
 * unit group)*, άρα το πρόθεμα απαντά για **όλα** τα ESCO χωρίς να τα απαριθμεί.
 * ═════════════════════════════════════════════════════════════════════════════
 * 🏆 ΠΟΥ ΞΕΠΕΡΝΑΜΕ ΤΙΣ ΙΔΙΕΣ ΤΙΣ ΔΙΑΣΤΑΥΡΩΣΕΙΣ ΤΗΣ ΕΕ — ΤΟ «ΔΕΝ ΞΕΡΩ»
 *
 * Η ΕΕ συντηρεί **ESCO→O*NET** και **ESCO→NACE**. Και οι δύο χαρτογραφούν
 * **και τα 3.039** επαγγέλματα σε «**τουλάχιστον μία**» κατηγορία — δηλαδή
 * **δεν μπορούν δομικά να εκφράσουν «δεν ξέρω»**: κάθε επάγγελμα *πρέπει* να
 * πάρει απάντηση, ακόμη κι όταν δεν υπάρχει. Το O*NET crosswalk χτίστηκε
 * μάλιστα με **AI + ανθρώπινη επικύρωση** ακριβώς γι' αυτόν τον λόγο.
 *
 * Εδώ η **απουσία είναι ονομασμένη κατάσταση** (`undeclared`), όχι κενό. Ένα
 * επάγγελμα εκτός πίνακα δίνει **σιωπή**, ποτέ μαντεψιά — και η σιωπή είναι
 * **σωστή απάντηση**: ο υπολογισμός των permissions συνεχίζει αναλλοίωτος.
 * *Όπου δεν ξέρουμε, σωπαίνουμε* (`job-suggestion.ts:137`).
 * ═════════════════════════════════════════════════════════════════════════════
 * ⛔ ΤΙ ΝΑ ΜΗΝ ΚΑΝΕΙΣ
 *
 * • **ΜΗΝ** το διαβάσεις μέσα από το `resolveAvailableJobs()` — εκεί θα ήταν
 *   πηγή δικαιώματος (Α4). Ζει **μόνο** ως `tiebreak` του `pickDefaultJob()`.
 * • **ΜΗΝ** δηλώσεις ομάδα «για πληρότητα». Κάθε γραμμή φέρει **υποχρεωτικό**
 *   `why`, και υπάρχει άγκυρα που το απαιτεί μη κενό.
 * • **ΜΗΝ** δηλώσεις ομάδα της οποίας ο **πλησιέστερος δηλωμένος πρόγονος**
 *   λέει το ίδιο πράγμα: είναι πλεονασμός που θα αποκλίνει σιωπηλά (άγκυρα Χ-7).
 * • **ΜΗΝ** ενώσεις με το `profession-bridge.config.ts`: εκείνο απαντά
 *   *«ποιο επάγγελμα αντιστοιχεί σε ρόλο έργου»* (ADR-282/745) — **άλλο
 *   ερώτημα, άλλη κατεύθυνση**. Ένωση θα γεννούσε δεύτερο λεξιλόγιο ρόλων.
 * • **ΜΗΝ** γράψεις εδώ ετικέτες προς εμφάνιση: η αυθεντία της ετικέτας είναι
 *   το `escoLabel`/`profession` του ίδιου του χρήστη (ADR-132).
 *
 * @module config/isco-job-affinity
 * @see docs/centralized-systems/reference/adrs/ADR-798-person-professional-identity.md §6.2
 * @see src/config/jobs-access.ts — ο **μόνος** καταναλωτής της απόφασης
 * @see https://isco.ilo.org/en/isco-08 — η δομή· οι τίτλοι κάτω είναι οι επίσημοι
 */

