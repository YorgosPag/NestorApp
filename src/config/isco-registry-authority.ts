/**
 * ADR-841 **Α9** — *«ΠΟΙΑ ΑΡΧΗ ΚΡΑΤΑ ΜΗΤΡΩΟ ΓΙ' ΑΥΤΟ ΤΟ ΕΠΑΓΓΕΛΜΑ;»*
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 ΤΡΙΤΟΣ ΚΑΤΑΝΑΛΩΤΗΣ ΤΟΥ ΙΔΙΟΥ ΜΗΧΑΝΙΣΜΟΥ — **ΚΑΜΙΑ ΝΕΑ ΜΗΧΑΝΗ**
 *
 * Το `config/isco-prefix.ts` λύνει την **ανάλυση προθέματος** μία φορά, και την
 * καταναλώνουν ήδη δύο πίνακες *(`isco-job-affinity` · `isco-ifc-role`)*. Αυτός
 * είναι ο **τρίτος**: ίδιος μηχανισμός, **τρίτο** ερώτημα.
 *
 * ⛔ **ΜΗΝ συγχωνευθεί με τους άλλους δύο.** Οι πίνακες οφείλουν να μείνουν
 * διαφορετικοί *(ADR-798 §6.2)*: εδώ το `2611` *(δικηγόροι)* είναι κρίσιμο και
 * στους άλλους δύο **απουσιάζει**, ενώ το `2144` *(μηχανολόγος)* που ο πίνακας
 * IFC χρειάζεται είναι εδώ **αδιάφορο** — το ΤΕΕ απαντά ήδη στο `214`.
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΤΡΕΙΣ ΑΠΑΝΤΗΣΕΙΣ, ΚΑΙ ΟΙ ΔΥΟ ΠΡΩΤΕΣ ΔΕΝ ΕΙΝΑΙ Η ΙΔΙΑ
 *
 * | Απάντηση | Σημαίνει | Παράδειγμα |
 * |---|---|---|
 * | **αρχή** | υπάρχει μητρώο, και ξέρουμε ποιο | δικηγόρος → Δικηγορικός Σύλλογος |
 * | **`no-registry`** | **δηλωμένη απουσία** — κανένα μητρώο υπάρχει | ελαιοχρωματιστής |
 * | **`unexamined`** | έγκυρος κωδικός, **καμία γραμμή εδώ** — *κανείς δεν κοίταξε* | ό,τι δεν απαριθμείται |
 *
 * 🔴 **ΟΙ ΔΥΟ ΤΕΛΕΥΤΑΙΕΣ ΔΕΝ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΙΣΟΠΕΔΩΘΟΥΝ, ΚΑΙ ΕΙΝΑΙ Ο ΛΟΓΟΣ ΠΟΥ
 * ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ ΕΧΕΙ ΡΗΤΕΣ ΕΓΓΡΑΦΕΣ `null`.** Ένας κοινός «δεν βρέθηκε» θα
 * έλεγε στον ελαιοχρωματιστή *«δεν ξέρουμε»* ενώ **ξέρουμε**: δεν υπάρχει πού να
 * γραφτεί, και αυτό είναι **πληροφορία που του ανήκει**. Είναι **ακριβώς** το
 * σχήμα «0 = κανείς δεν κοίταξε» που το `CLAUDE.md` ονομάζει σε N.11 · N.12 ·
 * N.18 και που οκτώ πύλες υπάρχουν για να κλείσουν.
 * ═════════════════════════════════════════════════════════════════════════════
 * ⚠️ **Η ΑΠΟΥΣΙΑ ΜΗΤΡΩΟΥ ΔΕΝ ΑΠΟΚΛΕΙΕΙ ΚΑΝΕΝΑΝ** *(ADR-841 Α9.3)*. Ο
 * ελαιοχρωματιστής **μπαίνει** στον κατάλογο, με την απουσία **ονομασμένη** —
 * ίδιο πρότυπο με το `LISTING_OPEN_SUBJECTS`: η απουσία είναι **κατάσταση**,
 * ποτέ σιωπή.
 *
 * @module config/isco-registry-authority
 * @see config/isco-prefix.ts — ο μηχανισμός
 * @see constants/professional-registries.ts — το λεξιλόγιο των αρχών
 * @see docs/centralized-systems/reference/adrs/ADR-841-public-listing-body-and-platform-verticals.md — Α9.1
 */

