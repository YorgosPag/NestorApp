/**
 * Η ετυμηγορία, σε **πέντε ρητές καταστάσεις** — ποτέ `RegistryAuthorityId | null`.
 *
 * ⚠️ Το `no-registry` και το `unexamined` **δεν** συγχωνεύονται: δες την
 * επικεφαλίδα του αρχείου. Το πρώτο είναι **γνώση**, το δεύτερο **άγνοια**.
 */
export type RegistryAuthorityVerdict =
  /** Υπάρχει μητρώο, και ξέρουμε ποιο. Το `prefix` λέει **σε ποιο επίπεδο** απαντήθηκε. */
  | {
      readonly kind: 'authority';
      readonly authority: RegistryAuthorityId;
      readonly prefix: string;
    }
  /** **Δηλωμένη απουσία**: το επάγγελμα δεν έχει μητρώο. Η οθόνη το λέει **ρητά**. */
  | { readonly kind: 'no-registry'; readonly prefix: string }
  /** Έγκυρος κωδικός, **καμία γραμμή** στον πίνακα — *κανείς δεν το εξέτασε*. */
  | { readonly kind: 'unexamined'; readonly code: string }
  /** Κανένας κωδικός: ελεύθερο κείμενο, ή καμία δήλωση επαγγέλματος. */
  | { readonly kind: 'absent' }
  /** Η τιμή δεν είναι κωδικός ISCO-08. Fail-closed **και ορατό**. */
  | { readonly kind: 'malformed'; readonly value: string };

/**
 * *«Ποια αρχή κρατά μητρώο γι' αυτό το επάγγελμα;»*
 *
 * 🔑 **Δεν ρωτά τον άνθρωπο — ρωτά το ΕΠΑΓΓΕΛΜΑ.** Το *«τι δήλωσε ο ίδιος»* είναι
 * άλλο ερώτημα *(`ProfessionalAttestation`)*, και η **οθόνη** συνθέτει τα δύο.
 * Η σύζευξή τους εδώ θα γεννούσε **τέταρτη** κατάσταση επαλήθευσης, που το
 * ADR-841 Α9.2 απαγορεύει ρητά.
 */
export function resolveRegistryAuthority(
  iscoCode: string | null | undefined,
): RegistryAuthorityVerdict {
  const verdict = resolveIscoPrefix(ISCO_REGISTRY_AUTHORITY, iscoCode);

  switch (verdict.kind) {
    case 'declared':
      return verdict.entry.authority === null
        ? { kind: 'no-registry', prefix: verdict.prefix }
        : { kind: 'authority', authority: verdict.entry.authority, prefix: verdict.prefix };
    case 'undeclared':
      return { kind: 'unexamined', code: verdict.code };
    case 'absent':
      return { kind: 'absent' };
    case 'malformed':
      return { kind: 'malformed', value: verdict.value };
  }
}
