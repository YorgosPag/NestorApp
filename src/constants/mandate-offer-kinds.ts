import { isOfferKindEligible } from '@/constants/offer-kind-eligibility';
import { OFFER_KINDS, type OfferKind } from '@/types/property-offers';

/**
 * **Με ποια σύμβαση αναθέτει ο ιδιοκτήτης αυτή τη διάθεση σε τρίτο επαγγελματία.**
 *
 * - `brokerage` — μεσιτική εντολή (άρθρο 200 Ν.4072/2012): ο μεσίτης φέρνει
 *   αντισυμβαλλόμενο για **μία** σύμβαση και αμείβεται όταν κλείσει.
 * - `management` — σύμβαση διαχείρισης: συνεχής λειτουργία (τιμολόγηση, check-in,
 *   καθαρισμός), αμοιβή επί των εσόδων. **Δεν** είναι εντολή και **δεν** καταλαμβάνει
 *   πόρο με τους κανόνες της εντολής.
 */
export const OFFER_KIND_ENGAGEMENTS = ['brokerage', 'management'] as const;

export type OfferKindEngagement = (typeof OFFER_KIND_ENGAGEMENTS)[number];

export const OFFER_KIND_ENGAGEMENT: Readonly<Record<OfferKind, OfferKindEngagement>> = {
  sell: 'brokerage',
  leaseOut: 'brokerage',
  /** Η αντιπαροχή είναι **μία** σύμβαση με κατασκευαστή — ο μεσίτης τον φέρνει. */
  exchange: 'brokerage',
  /** 🔴 Δες την κεφαλίδα: συνεχής λειτουργία, όχι μία σύμβαση. */
  leaseShort: 'management',
};

/** Οι διαθέσεις που **ανατίθενται με μεσιτική εντολή**. */
export type MandateOfferKind = {
  [K in OfferKind]: (typeof OFFER_KIND_ENGAGEMENT)[K] extends 'brokerage' ? K : never;
}[OfferKind];

/** **Ανατίθεται αυτή η διάθεση με μεσιτική εντολή;** */
export function isMandateOfferKind(kind: OfferKind): kind is MandateOfferKind {
  return OFFER_KIND_ENGAGEMENT[kind] === 'brokerage';
}

/**
 * Οι πράξεις μιας εντολής, σε σειρά `OFFER_KINDS`.
 *
 * 🔑 **Παραγόμενο από τον πίνακα, ποτέ δεύτερη λίστα.**
 */
export const MANDATE_OFFER_KINDS: readonly MandateOfferKind[] = OFFER_KINDS.filter(isMandateOfferKind);

/**
 * **Οι πράξεις που μπορεί να καλύψει εντολή για αυτό το είδος ακινήτου.**
 *
 * 🔑 **Δύο άξονες, δύο πίνακες, μία τομή**: *«ανατίθεται σε μεσίτη;»* (εδώ) ∧ *«έχει
 * νόημα σε αυτό το είδος;»* (`OFFER_KIND_CLASSES`). Η αντιπαροχή σε διαμέρισμα **δεν**
 * προσφέρεται — ίδιος κριτής με τη φόρμα της αγγελίας (`exchange-requires-land`).
 *
 * ⚠️ **Άγνωστο είδος ⇒ όλες οι πράξεις εντολής**, ίδιο συμβόλαιο με το
 * `isOfferKindEligible`: ο άνθρωπος δεν έχει διαλέξει ακόμη ακίνητο, και ένα «όχι»
 * εκεί θα ήταν κατηγορία για κάτι που δεν ρωτήθηκε.
 */
export function mandateOfferKindsFor(propertyType: unknown): readonly MandateOfferKind[] {
  return MANDATE_OFFER_KINDS.filter((kind) => isOfferKindEligible(kind, propertyType));
}
