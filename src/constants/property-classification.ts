import { normalizePropertyType } from './property-type-aliases';
import { PROPERTY_TYPE_CLASS, type PropertyClass } from './property-types';

/**
 * **Η κατηγορία μιας ΟΠΟΙΑΣΔΗΠΟΤΕ τιμής** — κανονικής, παρωχημένης, ελληνικής
 * legacy, με κενά, με άλλα πεζά/κεφαλαία.
 *
 * 🔑 **Η σύνθεση ζει ΕΔΩ και όχι στον καταναλωτή**, και αυτός είναι όλος ο λόγος
 * ύπαρξης του αρχείου: το `field-completion-weights.ts` έγραφε **χειρόγραφα**
 * `propertyClassOf(normalizePropertyType(t))` και ήταν ο **μόνος** που το θυμήθηκε.
 * Μια σύνθεση που ο καθένας οφείλει να ξαναγράψει σωστά είναι σύνθεση που **κάποιος
 * θα ξεχάσει** — και ήδη την είχαν ξεχάσει έξι.
 *
 * @param type Οτιδήποτε: τιμή Firestore, τιμή φόρμας, `undefined`, αριθμός.
 * @returns Η κατηγορία, ή `null` όταν η τιμή δεν αναγνωρίζεται ως είδος ακινήτου.
 *
 * @example
 * resolvedPropertyClassOf('plot')       // → 'land'
 * resolvedPropertyClassOf('Οικόπεδο')   // → 'land'   (ήταν `null` πριν το §7.6.11)
 * resolvedPropertyClassOf('  STORE  ')  // → 'commercial'
 * resolvedPropertyClassOf('κάτι')       // → null
 * resolvedPropertyClassOf(undefined)    // → null
 */
export function resolvedPropertyClassOf(type: unknown): PropertyClass | null {
  const canonical = normalizePropertyType(type);
  return canonical === null ? null : PROPERTY_TYPE_CLASS[canonical];
}

/**
 * **Είναι γη;** — ο **ΕΝΑΣ** κριτής, αυτός που ξεκλειδώνει την αντιπαροχή.
 *
 * 🔑 **Ονομάζεται `isLandProperty` και όχι `isLandPropertyType`, επίτηδες**: το παλιό
 * όνομα ρωτούσε για ένα **σύμβολο του λεξιλογίου** (*«είναι αυτό το είδος γη;»*) και
 * δικαιολογούσε το να δέχεται μόνο κανονικές τιμές. Αυτό εδώ ρωτά για **το πράγμα**
 * (*«είναι γη αυτό το ακίνητο;»*) — που είναι η ερώτηση που έκαναν **και οι έξι**
 * καταναλωτές, ενώ καλούσαν τη συνάρτηση της άλλης.
 *
 * ⚠️ **Άγνωστη ή κενή είσοδος ⇒ `false`, ποτέ σφάλμα.** Η φόρμα ξεκινά με `type: ''`
 * και ο άνθρωπος δεν έχει απαντήσει ακόμη· ένα σφάλμα εκεί θα ήταν κατηγορία για κάτι
 * που δεν ρωτήθηκε. Το κενό είδος το πιάνει ο **δικός του** κωδικός (`type-missing`).
 *
 * @example
 * isLandProperty('parcel')     // → true
 * isLandProperty('Οικόπεδο')   // → true   (ήταν `false` πριν το §7.6.11)
 * isLandProperty('Αποθήκη')    // → false  (λύνεται σε `storage` ⇒ εμπορικό)
 * isLandProperty(undefined)    // → false
 */
export function isLandProperty(type: unknown): boolean {
  return resolvedPropertyClassOf(type) === 'land';
}
