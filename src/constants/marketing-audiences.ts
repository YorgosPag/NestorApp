// =============================================================================
// 1. Η ΡΙΖΑ — κλειστό λεξιλόγιο (CHECK 3.73)
// =============================================================================

/**
 * Τα κοινά, **από το στενότερο στο ευρύτερο** — η σειρά είναι σημασιολογική (§5.2:
 * διεύρυνση = προς τα δεξιά, στένεμα = προς τα αριστερά).
 *
 * - `custodians` — συντάκτης + γραφεία με ζωντανή εντολή (+ ρητές συμμετοχές, Φ4)
 * - `network`    — τα παραπάνω + επαγγελματικό δίκτυο των κατόχων (Φ5, ADR-862)
 * - `public`     — όλοι· **η μόνη τιμή που παράγει `PublicListing`**
 */
export const MARKETING_AUDIENCES = ['custodians', 'network', 'public'] as const;

export type MarketingAudience = (typeof MARKETING_AUDIENCES)[number];

/**
 * **Η προεπιλογή είναι `public`, και είναι εγγύηση προς τα υπάρχοντα δεδομένα** (Α3).
 *
 * 🔴 Κάθε καταχώρηση που γράφτηκε πριν υπάρξει αυτός ο άξονας **δεν έχει** το πεδίο. Μια
 * προεπιλογή `custodians` θα **εξαφάνιζε σιωπηλά** κάθε σημερινή αγγελία από τον χάρτη, με
 * όλες τις πύλες πράσινες — η μετάλλαξη που η Α3 υπάρχει για να πιάσει. Και αντιστοιχεί
 * στην απόφαση Giorgio 2026-08-11: *«δημοσιεύεται αμέσως»*.
 */
export const DEFAULT_MARKETING_AUDIENCE: MarketingAudience = 'public';

/** Η τιμή είναι κοινό του λεξιλογίου; */
export function isMarketingAudience(value: unknown): value is MarketingAudience {
  return typeof value === 'string' && (MARKETING_AUDIENCES as readonly string[]).includes(value);
}

/**
 * **Αποθηκευμένη τιμή → κοινό.** Το ΕΝΑ σημείο που ερμηνεύει την απουσία.
 *
 * ⚠️ **Λείπει ή δεν αναγνωρίζεται ⇒ `public`**, και η δεύτερη περίπτωση είναι επιλογή με
 * λόγο: το λεξιλόγιο γράφεται **μόνο** από κλειστές πύλες (`z.enum` στις δύο διαδρομές
 * PATCH), άρα άγνωστη λέξη σημαίνει έγγραφο που **δεν πέρασε ποτέ από εκεί** — δηλαδή
 * γράφτηκε πριν τον άξονα. Η σημερινή του συμπεριφορά ήταν «δημόσιο».
 */
export function marketingAudienceOf(stored: unknown): MarketingAudience {
  return isMarketingAudience(stored) ? stored : DEFAULT_MARKETING_AUDIENCE;
}

/**
 * **Στενεύει το κοινό;** — ό,τι ήταν ορατό σε κάποιους παύει να είναι.
 *
 * Χρειάζεται στη διεπαφή (επιβεβαίωση πριν το στένεμα, ADR-864 Ε-10) και παράγεται από τη
 * **σειρά** της ρίζας — κανένας δεύτερος πίνακας «βαθμού».
 */
export function narrowsAudience(from: MarketingAudience, to: MarketingAudience): boolean {
  return MARKETING_AUDIENCES.indexOf(to) < MARKETING_AUDIENCES.indexOf(from);
}
