/**
 * **Η ΡΙΖΑ** του λεξιλογίου ποσοτήτων — ADR-812 / CHECK 3.73.
 *
 * ⚠️ Η σειρά είναι **σημασιολογική, όχι αλφαβητική**: πρώτα οι τρεις που μοιάζουν
 * ίδιες και **δεν είναι** *(μήκος μοντέλου · μήκος χαρτιού · pixel οθόνης)* — η
 * σύγχυσή τους είναι η ακριβώς η βλάβη που αυτό το λεξιλόγιο αποτρέπει.
 */
export const QUANTITY_SPECS = [
  /**
   * Φυσικό μέγεθος **του κτιρίου**, αποθηκευμένο σε **χιλιοστά** (canonical mm,
   * ADR-462). **Η ΜΟΝΗ** ποσότητα που ξαναγράφεται στη μονάδα του θεατή.
   */
  'model-length',
  /**
   * Χιλιοστά **ΠΑΝΩ ΣΤΟ ΤΥΠΩΜΕΝΟ ΦΥΛΛΟ** (ύψος κειμένου ISO 2,5 mm · βέλος 3,5 mm).
   * Μήκος, αλλά **του χαρτιού**: μένει 2,5 mm όποια κι αν είναι η μονάδα του έργου —
   * ο ίδιος κανόνας που η Revit εφαρμόζει στα annotation μεγέθη. **ΠΟΤΕ** μετατροπή.
   */
  'paper-length',
  /** **Pixel οθόνης** (μέγεθος γραμματοσειράς ετικέτας, πάχος περιγράμματος) — γραφικό μέγεθος, όχι μέγεθος του κόσμου. */
  'screen-px',
  /** **Μοίρες** (στροφή, κλίση, γωνία λοξοτομής, διεύθυνση ρύσης). */
  'angle',
  /** **Ακέραιο πλήθος**: βαθμίδες, όροφοι, γραμμές, πλευρές πολυγώνου, διαιρέσεις. */
  'count',
  /** **Ποσοστό** (απόδοση λέβητα, ρύση %, διασπορά). */
  'percent',
  /** **Καθαρός συντελεστής**: κλίμακα X/Y, συντελεστής πλάτους, κλίμακα τύπου γραμμής, αραίωση. */
  'ratio',
  /**
   * **ΟΝΟΜΑΣΤΙΚΟ** μέγεθος καταλόγου (DN15, DN80, DN110). Ο αριθμός **ονομάζει**
   * προϊόν αντί να το μετρά — το ίδιο σκεπτικό που κρατά το preset «900 mm» μιας
   * πόρτας γραμμένο ως 900 *(ADR-677 §7.1)*. **ΠΟΤΕ** μετατροπή.
   */
  'nominal-diameter',
  /** **Ισχύς** — θερμική ή ηλεκτρική (W). */
  'power',
  /** **Πίεση** (bar). */
  'pressure',
  /** **Θερμοκρασία** (°C). */
  'temperature',
  /** **Χωρητικότητα** (λίτρα). ⚠️ Χωρητικότητα δοχείου — **όχι** ο όγκος επιμέτρησης του ΑΤΟΕ. */
  'volume',
  /** **Μάζα** (kg). */
  'mass',
  /** Ό,τι **δεν έχει μονάδα**: σπόροι τυχαιότητας, εναλλαγές αέρα/ώρα, dB(A), mg/kWh. */
  'dimensionless',
] as const;

/**
 * Η ποσότητα που κρατά ένα αριθμητικό πεδίο — **παράγεται** από τη ρίζα, καμία
 * δεύτερη λίστα.
 *
 * ⚠️ Το `undefined` *(αδήλωτο πεδίο)* είναι **έγκυρη κατάσταση** και σημαίνει
 * *«δεν ξέρω»*. Οι καταναλωτές το δέχονται ρητά ως `QuantitySpec | undefined` —
 * ποτέ με σιωπηλή προεπιλογή.
 */
export type QuantitySpec = (typeof QUANTITY_SPECS)[number];
