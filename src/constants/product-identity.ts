/** Το όνομα του προϊόντος — **μία** γραφή, σε κάθε γλώσσα (άκλιτο, λατινικό). */
export const PRODUCT_NAME = 'Nestor App';

/**
 * Το **νομικό πρόσωπο** — δικαιώματα, όχι προϊόν.
 *
 * ⚠️ **Δεν είναι συνώνυμο του {@link PRODUCT_NAME}.** Μια γραμμή `©` που ονομάζει προϊόν αντί
 * για πρόσωπο είναι **λάθος τύπου**, όχι στιλ.
 */
export const LEGAL_ENTITY_NAME = 'Nestor Pagonis';

/**
 * 🔴 **ΟΙ ΠΑΛΙΕΣ ΓΡΑΦΕΣ — ΚΑΙ ΥΠΑΡΧΟΥΝ ΓΙΑ ΤΗΝ ΟΥΡΑ, ΟΧΙ ΓΙΑ ΝΟΣΤΑΛΓΙΑ.**
 *
 * Το `brandedSubject` κρίνει με `endsWith` αν ένα θέμα **υπογράφει ήδη**. Τα ήδη γραμμένα
 * `pending` έγγραφα της ουράς κουβαλούν το **παλιό** επίθεμα *«για πάντα»* (ADR-777 §8.54).
 * Αν ο έλεγχος γινόταν **μόνο** στο νέο όνομα, ένα ουραγμένο «Νέα αγγελία — ΝΕΣΤΩΡ» θα έφευγε
 * ως **«Νέα αγγελία — ΝΕΣΤΩΡ — Nestor App»**, στα εισερχόμενα πραγματικού ανθρώπου.
 *
 * ⚠️ **Συρρικνώνεται ΜΟΝΟ αφού αδειάσει η ουρά** — και αυτό είναι απόφαση, όχι αμέλεια.
 * ⚠️ Η σειρά **δεν** είναι σημασιολογική: αρκεί **οποιαδήποτε** να ταιριάξει.
 */
export const KNOWN_PAST_SPELLINGS: readonly string[] = [
  'ΝΕΣΤΩΡ',
  'Nestor Pagonis',
  'Nestor Construct',
  // ⚠️ Τελευταίο επίτηδες: είναι **πρόθεμα** των άλλων· ως `endsWith` δεν συγκρούεται, αλλά
  //    ο αναγνώστης πρέπει να δει ότι το ξέρουμε.
  'Nestor',
];

/**
 * **Υπογράφει ήδη αυτό το κείμενο;** — με το σημερινό όνομα ή με οποιοδήποτε παλιό.
 *
 * 🔑 Η ερώτηση είναι *«υπογράφει ήδη;»*, **όχι** *«υπογράφει με τον δικό μας τρόπο;»*: ο
 * έλεγχος γίνεται στο **όνομα**, ποτέ στο πλήρες επίθεμα, γιατί η στίξη έχει αλλάξει στο
 * παρελθόν (παύλα em, κενά) και μπορεί να ξαναλλάξει.
 */
export function alreadySignedByProduct(text: string): boolean {
  const trimmed = text.trim();
  return trimmed.endsWith(PRODUCT_NAME) || KNOWN_PAST_SPELLINGS.some((name) => trimmed.endsWith(name));
}

/**
 * Το όνομα με προσδιορισμό — `Nestor App · Πίνακας`, `Nestor App · BIM Schedule`.
 *
 * Υπάρχει ώστε οι εξαγωγείς να **μην** ξαναγράφουν το όνομα για να του κολλήσουν μια λέξη.
 */
export function productQualified(qualifier: string): string {
  return `${PRODUCT_NAME} · ${qualifier}`;
}
