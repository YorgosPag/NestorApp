/**
 * **Η ΡΙΖΑ** του λεξιλογίου — CHECK 3.73 *(ADR-812)*.
 *
 * ⚠️ **ΕΔΩ ΑΠΑΡΙΘΜΟΥΝΤΑΙ ΟΙ ΤΙΜΕΣ, ΚΑΙ ΜΟΝΟ ΕΔΩ.** Η πρώτη γραφή είχε τη ρίζα
 * ως `[...NATIONAL, ...CHAPTERED]` — και **το CHECK 3.73 τη μπλόκαρε, σωστά**:
 * μια ρίζα που δεν απαριθμεί δεν είναι ρίζα, είναι **παράγωγο**, και τότε το
 * λεξιλόγιο ζει σε **δύο** σώματα που κανείς δεν συγκρίνει. Τώρα η διάκριση
 * *εθνική / με παραρτήματα* **παράγεται** από τον `REGISTRY_AUTHORITY_SCOPE`.
 */
export const REGISTRY_AUTHORITIES = [
  /** Τεχνικό Επιμελητήριο Ελλάδας — μηχανικοί κάθε ειδικότητας, **ένα** μητρώο. */
  'tee',
  /** Γενικό Εμπορικό Μητρώο — **επιχειρήσεις**, όχι πρόσωπα. Ήδη σε χρήση: `agency-profile.ts:105`. */
  'gemi',
  /** Οικονομικό Επιμελητήριο Ελλάδας — λογιστές/φοροτεχνικοί, **ένα** μητρώο. */
  'oee',
  /** Δικηγορικός Σύλλογος — **ανά πόλη** *(ΔΣΑ · ΔΣΘ · ΔΣ Πατρών · …)*. */
  'bar-association',
  /** Συμβολαιογραφικός Σύλλογος — **ανά εφετειακή περιφέρεια**. */
  'notary-association',
  /**
   * **Διεύθυνση Ανάπτυξης Περιφερειακής Ενότητας** — άδειες τεχνικών επαγγελμάτων
   * του **ν.3982/2011** *(υδραυλικοί · ηλεκτρολόγοι · ψυκτικοί · χειριστές)*.
   *
   * 🔴 **ΠΡΟΣΤΕΘΗΚΕ ΣΤΗ Φ6-Β ΚΑΙ ΕΚΛΕΙΣΕ ΑΝΟΙΧΤΟ ΤΗΣ Α9.4.** Η Φ6-Α είχε δηλώσει
   * ρητά ως **ανοιχτό (α)** ότι *«οι υδραυλικοί/ηλεκτρολόγοι έχουν άδεια
   * Περιφέρειας, που **δεν είναι** μητρώο επιμελητηρίου»* και τους άφησε
   * `unexamined` — **σωστά, γιατί κανείς δεν είχε κοιτάξει**. Η έρευνα κοίταξε:
   * τηρείται **«ενιαίο μητρώο προσώπων που ασκούν τεχνικά επαγγέλματα του
   * ν.3982/2011»**, από τη **Διεύθυνση Ανάπτυξης** κάθε Περιφερειακής Ενότητας.
   *
   * ⚠️ **Άρα ΔΕΝ είναι `no-registry`** — αυτό θα έλεγε *«δεν υπάρχει τίποτα»* ενώ
   * **υπάρχει**, και θα ήταν η ίδια βλάβη με το «0 = κανείς δεν κοίταξε», απλώς
   * από την ανάποδη: **βεβαιότητα με πρόσωπο γνώσης**.
   *
   * 🔑 **`chapter` και όχι `national`**: η άδεια εκδίδεται **ανά Περιφερειακή
   * Ενότητα** — ίδιο ακριβώς σχήμα με τον Δικηγορικό Σύλλογο ανά πόλη. Ένας
   * αριθμός χωρίς την Περιφερειακή Ενότητα που τον εξέδωσε **δεν επαληθεύεται
   * από κανέναν** *(Α9.1)*.
   */
  'regional-authority',
] as const;

/** Κάθε αρχή που ξέρει το σύστημα. */
export type RegistryAuthorityId = (typeof REGISTRY_AUTHORITIES)[number];

/**
 * **Πόσους εκδότες** έχει μια αρχή — και άρα **ποιο σχήμα απόδειξης** ισχύει.
 *
 * 🔑 Αυτός ο πίνακας είναι ο **μόνος** τόπος της διάκρισης, και είναι **ολικός**:
 * μια έκτη αρχή **σπάει το build** μέχρι να απαντήσει *«ένας εκδότης ή πολλοί;»*
 * — ερώτημα που **δεν** έχει προεπιλογή. Μια σιωπηλή προεπιλογή `'national'` θα
 * δεχόταν αριθμό δικηγόρου χωρίς σύλλογο, δηλαδή ακριβώς τη βλάβη της Α9.1.
 */
export const REGISTRY_AUTHORITY_SCOPE = {
  tee: 'national',
  gemi: 'national',
  oee: 'national',
  'bar-association': 'chapter',
  'notary-association': 'chapter',
  // Ανά Περιφερειακή Ενότητα (ν.3982/2011) — δες τη ρίζα.
  'regional-authority': 'chapter',
} as const satisfies Readonly<Record<RegistryAuthorityId, 'national' | 'chapter'>>;

/**
 * Αρχή με **έναν** εκδότη πανελλαδικά: ο αριθμός **μόνος του** αρκεί για να
 * σηκώσει κάποιος το τηλέφωνο και να ρωτήσει.
 *
 * ⚠️ **Παράγεται** από τον πίνακα — καμία δεύτερη λίστα.
 */
export type NationalRegistryId = {
  [K in RegistryAuthorityId]: (typeof REGISTRY_AUTHORITY_SCOPE)[K] extends 'national' ? K : never;
}[RegistryAuthorityId];

/**
 * Αρχή με **πολλούς** εκδότες — ο εκδότης δηλώνεται **πάντα** δίπλα στον αριθμό.
 *
 * ⚠️ **Παράγεται** από τον πίνακα — καμία δεύτερη λίστα.
 */
export type ChapteredRegistryId = {
  [K in RegistryAuthorityId]: (typeof REGISTRY_AUTHORITY_SCOPE)[K] extends 'chapter' ? K : never;
}[RegistryAuthorityId];

