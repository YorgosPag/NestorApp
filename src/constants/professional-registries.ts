/**
 * *«Είναι αυτή η τιμή αρχή με **πολλούς** εκδότες;»*
 *
 * 🔑 Υπάρχει επειδή η απάντηση καθορίζει **ποιο σχήμα απόδειξης** ισχύει, και
 * ένα `includes()` γραμμένο στον καταναλωτή θα ήταν δεύτερος ορισμός του ίδιου
 * ερωτήματος — με τον δεύτερο να ξεχνά την τρίτη αρχή που θα προστεθεί.
 */
export function isChapteredRegistry(value: string): value is ChapteredRegistryId {
  return isRegistryAuthority(value) && REGISTRY_AUTHORITY_SCOPE[value] === 'chapter';
}

/** *«Είναι αυτή η τιμή αρχή με **έναν** εκδότη;»* — το συμπλήρωμα, ρητά. */
export function isNationalRegistry(value: string): value is NationalRegistryId {
  return isRegistryAuthority(value) && REGISTRY_AUTHORITY_SCOPE[value] === 'national';
}

/**
 * *«Ξέρει το σύστημα αυτή την αρχή;»* — ο φρουρός της **εισόδου**.
 *
 * ⚠️ Χρειάζεται στο σύνορο ανάγνωσης: το Firestore επιστρέφει `string`, και ένα
 * `as RegistryAuthorityId` θα δεχόταν ό,τι γράφτηκε ποτέ σε παλιό έγγραφο.
 *
 * 🔑 Είναι ο **μοναδικός** που ρωτά τη ρίζα· οι άλλοι δύο τον καταναλώνουν και
 * μετά ρωτούν τον πίνακα. Τρία ανεξάρτητα `includes()` θα ήταν τρεις ορισμοί
 * του «γνωστή αρχή», με τον τρίτο να ξεχνά την έκτη τιμή.
 */
export function isRegistryAuthority(value: string): value is RegistryAuthorityId {
  return (REGISTRY_AUTHORITIES as readonly string[]).includes(value);
}
