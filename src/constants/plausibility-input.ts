/**
 * Ο πυρήνας: **ένα** πέρασμα από `unknown` σε πεπερασμένο αριθμό.
 *
 * ⚠️ Το κενό αλφαριθμητικό γίνεται `null` **πριν** από το `Number()`, επίτηδες: το
 * `Number('')` είναι `0`, δηλαδή «δεν συμπλήρωσε τίποτα» θα γινόταν «δήλωσε μηδέν» — η
 * ακριβώς αντίθετη πληροφορία, και αόρατη.
 */
function toFinite(value: unknown): number | null {
  if (typeof value === 'number') {
    return Number.isFinite(value) ? value : null;
  }
  if (typeof value === 'string') {
    const trimmed = value.trim();
    if (trimmed.length === 0) return null;
    const parsed = Number(trimmed);
    return Number.isFinite(parsed) ? parsed : null;
  }
  return null;
}

/**
 * **Κάθε πεπερασμένος αριθμός**, θετικός ή αρνητικός.
 *
 * 🔑 Ο μόνος καταναλωτής είναι ο **όροφος**, και ο λόγος είναι σημασιολογικός: το
 * υπόγειο είναι `-1`. Μια πύλη «μη αρνητικών» εκεί θα έσβηνε το υπόγειο από τον κόσμο.
 */
export function toFiniteNumber(value: unknown): number | null {
  return toFinite(value);
}

/**
 * **Μη αρνητικός**, με δεκαδικούς — εμβαδά και μεγέθη.
 *
 * ⚠️ Δέχεται `0`: «μηδέν τ.μ. κήπου» είναι **δήλωση** *(«απάντησα, δεν έχει»)*, όχι
 * απουσία — και το `0` υπάρχει ζωντανά στα έγγραφα (μετρημένο, ADR-842 Φ3).
 */
export function toNonNegativeNumber(value: unknown): number | null {
  const n = toFinite(value);
  return n === null || n < 0 ? null : n;
}

/**
 * **Μη αρνητικός ακέραιος** — δωμάτια, μπάνια, WC.
 *
 * ⚠️ `Math.floor` και όχι `Math.round`: «2,7 υπνοδωμάτια» σημαίνει ότι κάποιος μέτρησε
 * κάτι άλλο· η στρογγυλοποίηση **προς τα πάνω** θα εφεύρισκε δωμάτιο που δεν υπάρχει.
 */
export function toNonNegativeInt(value: unknown): number | null {
  const n = toNonNegativeNumber(value);
  return n === null ? null : Math.floor(n);
}

/**
 * **Γνησίως θετικός** — τιμές.
 *
 * 🔑 Το `0` απορρίπτεται **επίτηδες**: ακίνητο με τιμή μηδέν δεν είναι δωρεάν, είναι
 * ακίνητο **χωρίς δηλωμένη τιμή**. Η διάκριση ανήκει εδώ και όχι στον καλούντα.
 */
export function toPositiveNumber(value: unknown): number | null {
  const n = toFinite(value);
  return n === null || n <= 0 ? null : n;
}
