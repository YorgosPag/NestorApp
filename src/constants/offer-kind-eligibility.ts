import { resolvedPropertyClassOf } from '@/constants/property-classification';
import {
  PROPERTY_CLASSES,
  type PropertyClass,
} from '@/constants/property-types';
import { OFFER_KINDS, type OfferKind } from '@/types/property-offers';

/**
 * **Ποιες κατηγορίες ακινήτου δέχεται κάθε διάθεση.**
 *
 * ⚠️ Ο τύπος `Record<OfferKind, …>` μένει **κλειστός**: πέμπτο είδος διάθεσης **δεν
 * μεταγλωττίζεται** μέχρι κάποιος να απαντήσει σε ποια ακίνητα έχει νόημα — ακόμη κι
 * αν η απάντηση είναι «όλα», που τότε γράφεται ρητά και **φαίνεται**.
 *
 * 🔑 **Η ερώτηση είναι ανά ΚΑΤΗΓΟΡΙΑ, ποτέ ανά είδος**: μια λίστα ειδών εδώ θα έπρεπε
 * να θυμηθεί το «Αγροτεμάχιο» δίπλα στο «Οικόπεδο», και θα ξεχνούσε το τρίτο είδος γης
 * την ημέρα που θα προστεθεί. Η κατηγορία είναι ήδη ο **δεύτερος άξονας** του
 * `property-types.ts` και υπάρχει ακριβώς γι' αυτό.
 */
export const OFFER_KIND_CLASSES: Readonly<Record<OfferKind, readonly PropertyClass[]>> = {
  /** Πωλείται **οτιδήποτε** — και η γη είναι η καθαρότερη περίπτωση. */
  sell: PROPERTY_CLASSES,

  /**
   * Εκμισθώνεται **οτιδήποτε**, και η γη **επίτηδες μέσα**: το *ground lease*
   * (25–99 έτη) είναι η κύρια μακροχρόνια πράξη γης διεθνώς, και στην Ελλάδα
   * νοικιάζονται χωράφια, μαντριά και υπαίθριοι χώροι στάθμευσης.
   */
  leaseOut: PROPERTY_CLASSES,

  /**
   * 🔴 **ΜΟΝΟ ΓΗ** — ο κανόνας του τομέα, κατά λέξη: *«η αντιπαροχή αφορά **ΜΟΝΟ** το
   * οικόπεδο»* (Giorgio 2026-08-20, ADR-777 §8.32). Ήταν ήδη γραμμένος **στο σώμα**
   * του `ownerPropertyInvariantViolations`· εδώ αποκτά γραμμή δίπλα στους αδελφούς του.
   */
  exchange: ['land'],

  /**
   * 🔴 **ΜΟΝΟ ΚΑΤΟΙΚΙΑ**, και η γη δεν είναι το μόνο που αποκλείεται.
   *
   * Η διάθεση κουβαλά `nightlyRate` · `minNights` · `maxGuests` — **διανυκτέρευση και
   * επισκέπτες**. Αυτό είναι λεξιλόγιο **διαμονής**, όχι «σύντομης διάρκειας»:
   *
   * - **Γη** — δεν κοιμάται κανείς σε γυμνό οικόπεδο· η αγορά τη χρεώνει ανά ώρα,
   *   μήνα ή δεκαετία (δες τον πίνακα της κεφαλίδας).
   * - **Εμπορικό** — ένα γραφείο ή μια αίθουσα **όντως** νοικιάζονται βραχυχρόνια,
   *   αλλά **ανά ώρα ή ανά ημέρα** (co-working, pop-up, εκδήλωση). Το «μέγιστος
   *   αριθμός επισκεπτών» εκεί σημαίνει **χωρητικότητα**, όχι πόσοι κοιμούνται.
   *
   * ⚠️ **Άρα ο αποκλεισμός του εμπορικού ΔΕΝ είναι «ό,τι και της γης»** — είναι
   * «λείπει η μονάδα». Αν κάποτε προστεθεί διάθεση με **δική της μονάδα** (ανά ώρα /
   * ανά ημέρα), το εμπορικό και η γη ανήκουν **εκεί**, όχι εδώ: ADR-842 §8 #10.
   */
  leaseShort: ['residential'],
};

/**
 * **Δέχεται αυτό το είδος ακινήτου αυτή τη διάθεση;**
 *
 * ⚠️ **Άγνωστο ή κενό είδος ⇒ `true`, ποτέ σφάλμα.** Η φόρμα ξεκινά με `type: ''` και
 * ο άνθρωπος **δεν έχει απαντήσει ακόμη** — ένα «όχι» εκεί θα ήταν κατηγορία για κάτι
 * που δεν ρωτήθηκε. Το κενό είδος το πιάνει ο **δικός του** κωδικός (`type-missing`),
 * που ξέρει να πει «διάλεξε είδος».
 */
export function isOfferKindEligible(kind: OfferKind, propertyType: unknown): boolean {
  const klass = resolvedPropertyClassOf(propertyType);
  return klass === null || OFFER_KIND_CLASSES[kind].includes(klass);
}

/**
 * **Οι διαθέσεις που έχουν νόημα για αυτό το είδος** — σε σειρά `OFFER_KINDS`.
 *
 * 🔑 Παραγόμενο από τον πίνακα, ποτέ δεύτερη λίστα: μια οθόνη που θέλει να προσφέρει
 * μόνο τα σχετικά τσεκ ρωτά **αυτό**, και δεν μπορεί να αποκλίνει από το invariant που
 * θα την κρίνει.
 */
export function offerKindsFor(propertyType: unknown): readonly OfferKind[] {
  return OFFER_KINDS.filter((kind) => isOfferKindEligible(kind, propertyType));
}
