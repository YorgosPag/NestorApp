/**
 * @fileoverview Οι **θέσεις** των χειριστηρίων πάνω σε χάρτη — μία φορά.
 * @related ADR-777 §8.85 · overlay-surface.ts (η επιφάνεια) · CHECK 3.50 (στρώση)
 * @module subapps/geo-canvas/components/map-overlays/map-overlay-slots
 *
 * 🔴 **ΤΙ ΗΤΑΝ ΠΡΙΝ (στιγμιότυπο του Giorgio, 2026-10-02).** Η στήλη χειριστηρίων του χάρτη
 * αναζήτησης ήταν **μία** κεντραρισμένη στοίβα στην κορυφή, και κάθε ADR πρόσθετε μια σειρά
 * (885 «Σχεδίαση» → 888 «Αποθήκευση» → 890 «Τιμές €/τ.μ.»). Τέσσερα κουμπιά κάθονταν **ακριβώς**
 * εκεί που κοιτάζει ο άνθρωπος. Κανείς δεν το αποφάσισε: η σειρά ήταν γραμμένη με το χέρι, άρα
 * το επόμενο χειριστήριο θα έπεφτε στο ίδιο σημείο.
 *
 * ✅ **ΤΩΡΑ — θέσεις με ρόλο, όπως οι `ControlPosition` του Google Maps Platform:**
 *
 * | Θέση | Ρόλος | Παράδειγμα |
 * |---|---|---|
 * | `status` | **ΕΝΑ** στοιχείο: η κατάσταση ή το εφήμερο | διακόπτης «καθώς μετακινώ» + «Αναζήτηση εδώ» (ένα χάπι, Airbnb) · chip ορίου · ζώνη σχεδίασης |
 * | `tools` | εργαλεία του χάρτη, κάθετα, στο δεξί άκρο | Σχεδίαση · Στρώσεις (Redfin / Google Maps) |
 * | `key` | υπόμνημα, παθητικό | «+5 = …» |
 *
 * ⚠️ Ό,τι αφορά την **αναζήτηση** (π.χ. «Αποθήκευση αναζήτησης») **ΔΕΝ** έχει θέση εδώ: ζει
 * στη γραμμή φίλτρων, όπως στη Zillow και στη Redfin.
 *
 * ⚠️ **`pointer-events-none` στο δοχείο, `pointer-events-auto` στα παιδιά.** Χωρίς αυτό, η αόρατη
 * λωρίδα του δοχείου θα κάλυπτε ζώνη του χάρτη και θα **έτρωγε τα κλικ** πάνω σε σχήματα από
 * κάτω — θα έσπαγε σιωπηλά τον δεσμό λίστας/χάρτη. Κάθε καταναλωτής βάζει `MAP_OVERLAY_INTERACTIVE`
 * στα παιδιά του.
 *
 * 🔴 **`overflow-visible` ΡΗΤΑ — βρέθηκε ζωντανά στο κινητό (2026-10-02).** Το `globals.css` δίνει σε
 * ≤640px `:where(.flex, .grid) { overflow-x: clip }`. Οι θέσεις είναι `.flex`, άρα **έκοβαν οριζόντια** ό,τι
 * απλώνεται έξω από το κουτί τους — το πάνελ τιμών (352px) κάτω από την μπάρα (50px) φαινόταν ως στήλη
 * 50px. Η θέση **ανήκει** σε περιεχόμενο που ξεχειλίζει επίτηδες (πάνελ, tooltips), οπότε δηλώνει το δικό
 * της overflow — ο καθολικός κανόνας έχει μηδενική ειδικότητα ακριβώς για να νικά η ρητή utility.
 *
 * ⚠️ **`z-10` και όχι μεγαλύτερο**: ο χάρτης ζει μέσα σε `isolate`, άρα η στρώση είναι **τοπική**
 * (CHECK 3.50 — ο περιορισμός είναι ανώτερος από το δάμασμα με αριθμό).
 */

