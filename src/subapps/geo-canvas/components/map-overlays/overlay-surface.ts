/**
 * @fileoverview Η **επιφάνεια** των overlays του χάρτη — μία φορά, θεματική.
 * @related ADR-777 §2.2 · CHECK 3.38/3.39/3.43 (αντίθεση) · N.0.2 (Boy Scout)
 * @module subapps/geo-canvas/components/map-overlays/overlay-surface
 *
 * 🔴 **ΤΙ ΗΤΑΝ ΠΡΙΝ, ΜΕΤΡΗΜΕΝΟ 2026-08-11.** Η ίδια συμβολοσειρά κλάσεων ήταν
 * αντιγραμμένη σε **τρία** overlays (`GeoCoordinateDisplay:101` · `GeoAccuracyLegend:189`
 * · `GeoStatusBar:163`):
 *
 *     `${colors.bg.secondary} bg-opacity-90 text-white p-3 rounded-lg shadow-lg`
 *
 * και έκρυβε **δύο** ελαττώματα που κανένα εργαλείο δεν ρωτούσε:
 *
 * 1. 🔴 **Αόρατο κείμενο στο ΦΩΤΕΙΝΟ θέμα.** Το `colors.bg.secondary` λύνεται σε
 *    `--bg-secondary`, που στο φωτεινό είναι `213 92% 95%` = `rgb(231,241,254)`.
 *    `text-white` πάνω του δίνει **1,13:1** — δηλαδή το πάνελ δεν είναι δυσανάγνωστο,
 *    είναι **ανύπαρκτο**. (Στο σκοτεινό, `217 27% 11%`, έδινε ~17:1 — γι' αυτό
 *    επέζησε: το προεπιλεγμένο θέμα είναι το σκοτεινό, άρα η βλάβη ήταν **λανθάνουσα**.)
 *    Καμία πύλη δεν το έβλεπε: η **3.38** ψάχνει `text-primary`, οι **3.39/3.40**
 *    διαβάζουν *token modules*, η **3.43** διαβάζει `.css`, και η **3.42** κρίνει μόνο
 *    τα αρχεία της allowlist του 3.26 — ένα `text-white` γραμμένο σε component
 *    **δεν είναι τίποτα από αυτά**.
 *
 * 2. ⚠️ **Το `bg-opacity-90` ΔΕΝ ΕΚΑΝΕ ΤΙΠΟΤΑ.** Σε Tailwind 3.4 το `bg-opacity-*`
 *    θέτει `--tw-bg-opacity`, που το **arbitrary** `bg-[hsl(var(--bg-secondary))]`
 *    ποτέ δεν καταναλώνει. Δηλαδή τα πάνελ ήταν **ήδη αδιαφανή** επί μήνες, ενώ ο
 *    κώδικας δήλωνε διαφάνεια.
 *
 * ✅ **ΤΩΡΑ.** Σημασιολογικό ζεύγος `bg-card` / `text-card-foreground` — ακριβώς η
 * θεραπεία που ονομάζει το ADR-770 (CHECK 3.42: *«η θεραπεία είναι σημασιολογικά
 * tokens»*), με **μετρημένη** αντίθεση **16,1:1** στο φωτεινό και **14,2:1** στο
 * σκοτεινό. Στο φωτεινό το `--card` είναι **ταυτόσημο** (`213 92% 95%`) με το
 * `--bg-secondary` ⇒ το **φόντο δεν αλλάζει καθόλου**· αλλάζει μόνο ότι το κείμενο
 * γίνεται ορατό.
 *
 * ⚠️ **Αδιαφανές, όχι ημιδιαφανές — και είναι απόφαση.** Ημιδιαφανές πάνελ πάνω σε
 * χάρτη σημαίνει ότι η αντίθεσή του εξαρτάται από τα **πλακίδια** που τυχαίνει να
 * είναι από κάτω — δηλαδή δεν είναι αποδείξιμη σε **καμία** πύλη. Το Google Maps
 * σερβίρει τον δικό του διακόπτη υποβάθρου **αδιαφανή**, για τον ίδιο λόγο.
 */

