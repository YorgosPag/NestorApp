/**
 * IDLE RE-RASTER TIMER — «πότε ησύχασε η όψη;» (ADR-743 Φ1 / ADR-726 Φ3)
 *
 * Ο χρονιστής που, `IDLE_RERASTER_MS` μετά την τελευταία μετατοπισμένη προβολή, επιβάλλει **μία**
 * ανακατασκευή του raster στο ζωντανό transform — αποκαθιστώντας ακριβή pixels ΚΑΙ ξανα-κεντράροντας
 * το overscan, που είναι αυτό που δίνει στην ΕΠΟΜΕΝΗ χειρονομία το budget της πίσω.
 *
 * ──────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΒΓΗΚΕ ΣΕ ΔΙΚΟ ΤΟΥ MODULE — ΚΑΙ ΓΙΑΤΙ ΡΩΤΑΕΙ ΑΝΤΙ ΝΑ ΥΠΟΘΕΤΕΙ
 * ──────────────────────────────────────────────────────────────────────────────
 * **Μετρημένο (ADR-743 Φ0, production 2026-08-03):** στο zoom, **43 στις 43** πλήρεις
 * ανακατασκευές (110,5ms η καθεμία, **78,2%** όλου του `frame:dxf-canvas`) πυροδοτήθηκαν από
 * αυτόν τον χρονιστή **ΜΕΣΑ σε χειρονομία**. Ο λόγος ήταν δομικός, όχι ρύθμιση:
 *
 *   `RASTER_IDLE` (120ms) < `WHEEL_IDLE` (220ms)
 *
 * και η εκκρεμότητα ελεγχόταν **ΠΡΙΝ** από τον gesture guard του `resolveProjectionReason`. Άρα
 * ο χρονιστής **παρέκαμπτε** την προστασία ADR-726 Φ3.1 («κανένα transform-driven rebuild μέσα
 * στη χειρονομία») ενώ εκείνη νόμιζε ότι φυλάει.
 *
 * ⚠️ **Η ΠΡΟΦΑΝΗΣ ΔΙΟΡΘΩΣΗ ΕΙΝΑΙ ΛΑΘΟΣ.** «Ανέβασε το `RASTER_IDLE` πάνω από το `WHEEL_IDLE`»
 * δημιουργεί **σιωπηλή σύζευξη δύο σταθερών**: μια μελλοντική αλλαγή στο `WHEEL_IDLE` επαναφέρει
 * το σφάλμα **χωρίς καμία ένδειξη** — ακριβώς ο «μαγικός αριθμός» που απαγορεύει το ADR-516.
 *
 * Η δομικά σωστή διόρθωση: το ερώτημα «τελείωσε η χειρονομία;» έχει **ΕΝΑΝ ιδιοκτήτη**
 * (`NavigationGestureStore`, ADR-728 Φ1) και ο χρονιστής **τον ρωτά**. Αν η χειρονομία τρέχει
 * ακόμη, **ξανα-οπλίζεται** αντί να δηλώσει εκκρεμότητα. Σωστό **ανεξαρτήτως τιμών**.
 *
 * 🔑 **Η ίδια αρχή που ακολουθούν όλοι οι μεγάλοι** (έρευνα ADR-743 §Φ1): το «τέλος χειρονομίας»
 * είναι **κατάσταση εισόδου**, ποτέ σκέτο χρονόμετρο. Revit: *«when the camera is not being
 * manipulated»*. Google Maps: *«waiting until they let go»*. Το `scrollend` του Chrome απαιτεί
 * ρητά **ΔΥΟ** συνθήκες: *«no pending updates AND the user has completed their gesture»*.
 *
 * ──────────────────────────────────────────────────────────────────────────────
 * ΣΥΓΚΛΙΣΗ — ΑΠΟΔΕΙΞΙΜΗ, ΟΧΙ ΕΛΠΙΔΑ
 * ──────────────────────────────────────────────────────────────────────────────
 * Η επανόπλιση δεν μπορεί να γίνει βρόχος: περίοδος 120ms, παράθυρο χειρονομίας 220ms. Αν το
 * transform ΔΕΝ ξανά-αλλάξει, ο επόμενος χτύπος βρίσκει `120 + 120 = 240ms > 220ms` ησυχίας ⇒
 * η χειρονομία έχει λήξει ⇒ πυροδοτεί κανονικά. **Το πολύ ΜΙΑ επανόπλιση.** Αν το transform
 * αλλάξει, το `blit()` καλεί `sync()` και ο χρονιστής μηδενίζεται έτσι κι αλλιώς.
 *
 * ──────────────────────────────────────────────────────────────────────────────
 * ΓΙΑΤΙ ΕΓΧΥΣΗ ΚΑΙ ΟΧΙ ΕΙΣΑΓΩΓΗ ΤΟΥ STORE
 * ──────────────────────────────────────────────────────────────────────────────
 * Το `isGestureActive` δίνεται ως **εξάρτηση**, δεν εισάγεται εδώ. Έτσι το module μένει
 * DOM-free/store-free και δοκιμάζεται με ψεύτικους χρονιστές χωρίς κανένα mock — ίδιο ιδίωμα
 * καθαρότητας με το `dxf-bitmap-cache-anchor`. Ο ΕΝΑΣ ιδιοκτήτης της απάντησης παραμένει το
 * `NavigationGestureStore`· εδώ δηλώνεται μόνο ότι **κάποιος** τη γνωρίζει.
 *
 * @module canvas-v2/dxf-canvas/dxf-bitmap-cache-idle-timer
 * @see canvas-v2/dxf-canvas/dxf-bitmap-cache — ο μοναδικός καταναλωτής
 * @see systems/navigation/NavigationGestureStore — ο ΕΝΑΣ ιδιοκτήτης του «είμαστε σε χειρονομία;»
 * @see ADR-743 §Φ1 — η μέτρηση που γέννησε αυτό το αρχείο
 */

import { IDLE_RERASTER_MS } from './dxf-bitmap-cache-anchor';

export interface IdleRerasterTimerOptions {
  /**
   * «Τρέχει ΤΩΡΑ χειρονομία πλοήγησης;» — η **έγχυση** του `isNavigationGesture()`.
   * Ερωτάται τη στιγμή του χτύπου, ΠΟΤΕ σε στιγμιότυπο: μια απάντηση παρμένη νωρίτερα θα ήταν
   * παλιά ακριβώς όταν μετράει (ADR-040 κανόνας 2).
   */
  isGestureActive: () => boolean;
  /**
   * Σήμανε τον καμβά βρόμικο ώστε ο scheduler να τρέξει ένα ακόμη καρέ και η ανακατασκευή να
   * συμβεί. Χωρίς αυτό το raster θα έμενε προβεβλημένο (και το overscan εκτός κέντρου) μέχρι
   * κάτι άλλο να τύχει να ζωγραφίσει.
   */
  requestRepaint?: () => void;
}

/**
 * Ο χρονιστής της ανακατασκευής ηρεμίας. Μία εκκρεμότητα, ένας χρονιστής, μηδέν γνώση για
 * raster/καμβά/transform — δέχεται μόνο το «η προβολή απέχει από την άγκυρα;» ως boolean.
 */
export class IdleRerasterTimer {
  private timerId: ReturnType<typeof setTimeout> | null = null;
  private due = false;

  constructor(private readonly options: IdleRerasterTimerOptions) {}

  /** Εκκρεμεί ανακατασκευή στο ζωντανό transform; */
  get isDue(): boolean {
    return this.due;
  }

  /**
   * Οπλίζει (ή αφοπλίζει) τον χρονιστή μετά από κάθε προβολή.
   *
   * @param drifted `true` όταν η προβολή απέχει από την άγκυρα — τότε και μόνο τότε υπάρχει
   *                κάτι να αποκατασταθεί. Ξανα-οπλίζεται σε **κάθε** μετατοπισμένο καρέ, ώστε
   *                να χτυπά ακριβώς μία φορά αφού η κίνηση σταματήσει.
   */
  sync(drifted: boolean): void {
    this.disarm();
    if (drifted) this.arm();
  }

  /**
   * Το raster ξαναχτίστηκε στο ζωντανό transform (ή δεν υπάρχει πια raster): καμία εκκρεμότητα.
   * Ιδεμποτεντικό — δύο κλήσεις αφήνουν ακριβώς την ίδια κατάσταση.
   */
  standDown(): void {
    this.due = false;
    this.disarm();
  }

  dispose(): void {
    this.standDown();
  }

  private arm(): void {
    this.timerId = setTimeout(() => this.fire(), IDLE_RERASTER_MS);
  }

  /**
   * 🔴 ΤΟ ΣΗΜΕΙΟ ΤΗΣ ΘΕΡΑΠΕΙΑΣ. Ρωτά τον ιδιοκτήτη· δεν συμπεραίνει από τον δικό του χρόνο.
   * Μια χειρονομία σε εξέλιξη **δεν** παράγει εκκρεμότητα και **δεν** ζητά ζωγραφική — απλώς
   * ξανα-οπλίζει (σύγκλιση: το πολύ μία φορά, βλ. κεφαλίδα).
   */
  private fire(): void {
    this.timerId = null;
    if (this.options.isGestureActive()) {
      this.arm();
      return;
    }
    this.due = true;
    this.options.requestRepaint?.();
  }

  private disarm(): void {
    if (this.timerId === null) return;
    clearTimeout(this.timerId);
    this.timerId = null;
  }
}
