'use client';

/**
 * ADR-763 Φ2.4 — **ποιο κουτί ορίσματος είναι ποιο, και πού είναι ο κέρσοράς του**.
 *
 * ## 🔴 Γιατί υπάρχει αυτό το μικρό αρχείο
 * Η ταυτότητα DOM των κουτιών ήταν ιδιωτική λεπτομέρεια της όψης (`idPrefix` prop) όσο τη
 * ρωτούσε **μόνο** το `<label htmlFor>`. Η Φ2.4 προσθέτει **δεύτερο** αναγνώστη, και μάλιστα
 * από άλλο στρώμα: ο χειριστής του ποντικιού πρέπει να μάθει «πού είναι ο κέρσορας μέσα στο
 * ενεργό κουτί;» για να αποφασίσει τι σημαίνει το κλικ σε κελί. Δύο σημεία που συνθέτουν το
 * ίδιο `id` με δικό τους πρόθεμα είναι ακριβώς το διπλότυπο που **καμία πύλη δεν βλέπει** και
 * που αποκλίνει στην πρώτη μετονομασία — με συνέπεια όχι σφάλμα αλλά **σιωπή**: ο κέρσορας θα
 * διαβαζόταν πάντα `null` και η υπόδειξη θα έγραφε στο τέλος του κειμένου, πάντα.
 *
 * ## Γιατί ΤΑΥΤΟΤΗΤΑ και όχι «είναι το ενεργό κουτί;» με `data-*`
 * Το `id` **υπάρχει ήδη** και είναι υποχρεωτικό (το `<label htmlFor>` το απαιτεί για την
 * προσβασιμότητα). Ένα δεύτερο σημάδι θα ήταν δεύτερη δήλωση της ίδιας σχέσης «σειρά ↔
 * στοιχείο», με δικό της κύκλο ζωής.
 *
 * ⚠️ Ο έλεγχος είναι **ανά δείκτη**, όχι «είναι κουτί ορίσματος;»: το ερώτημα του καλούντος
 * είναι «κρατά την εστίαση **το κουτί που θα γράψω**;». Ένα γενικό «κάποιο κουτί» θα έδινε τον
 * κέρσορα **άλλης** σειράς μετρημένο πάνω στο κείμενο αυτής — δηλαδή ακριβώς το σφάλμα δύο
 * συστημάτων συντεταγμένων που η Φ2.4 ήρθε να κλείσει, ξαναγεννημένο ένα επίπεδο πιο μέσα.
 *
 * @module subapps/dxf-viewer/ui/dialogs/function-argument-field
 * @see ui/table-cell-editor/table-point-target.ts — ο δεύτερος αναγνώστης
 * @see docs/centralized-systems/reference/adrs/ADR-763-table-insert-function-dialog.md §21
 */

/**
 * Το πρόθεμα ταυτότητας των κουτιών — **η μία πηγή**. Σταθερό: ζει σε `<label htmlFor>` και σε
 * ανάγνωση DOM, δηλαδή σε δύο μέρη που πρέπει να συμφωνούν χαρακτήρα προς χαρακτήρα.
 */
const FIELD_ID_PREFIX = 'dxf-fn-arg';

/** Η ταυτότητα DOM του κουτιού της σειράς `index`. */
export function functionArgumentFieldId(index: number): string {
  return `${FIELD_ID_PREFIX}-${index}`;
}

/**
 * 🔴 **Ο κέρσορας ΜΕΣΑ στο κουτί `index`** — `null` όταν εκείνο δεν κρατά την εστίαση.
 *
 * Ίδιο μοτίβο και ίδιος λόγος με το {@link activeTableCellSessionCaret}: η θέση του κέρσορα
 * **δεν είναι παράγωγη** του κειμένου — την κινεί ο χρήστης με βέλη, με κλικ μέσα στη λέξη, με
 * IME — άρα ιδιοκτήτης της είναι το πεδίο, και η ανάγνωση γίνεται **τη στιγμή του συμβάντος**
 * (ADR-040: getter, ποτέ στιγμιότυπο).
 *
 * Το `null` **δεν** είναι σφάλμα και δεν ακυρώνει την υπόδειξη: ο καλών το μεταφράζει σε «τέλος
 * του κειμένου», που είναι η σωστή απάντηση όταν κανείς δεν έχει τοποθετήσει κέρσορα — δες το
 * σκεπτικό στο `table-point-target.ts`.
 */
export function focusedFunctionArgumentCaret(index: number): number | null {
  if (typeof document === 'undefined') return null;
  const active = document.activeElement;
  if (!(active instanceof HTMLInputElement)) return null;
  if (active.id !== functionArgumentFieldId(index)) return null;
  return active.selectionStart;
}
