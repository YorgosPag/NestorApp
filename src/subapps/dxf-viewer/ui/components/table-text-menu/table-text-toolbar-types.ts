/**
 * ADR-739 §67 — **το συμβόλαιο** της γραμμής εργαλείων που ανοίγει το δεξί κλικ μέσα σε πεδίο
 * κειμένου κελιού.
 *
 * Ξεχωριστό αρχείο με το ίδιο κριτήριο που το έκαναν και τα τρία αδελφά μενού: **το συμβόλαιο
 * είναι γνώση, ο κύκλος ζωής είναι μηχανική**, και τα δύο δεν διαβάζονται μαζί.
 *
 * @module subapps/dxf-viewer/ui/components/table-text-menu/table-text-toolbar-types
 * @see ui/components/TableTextMiniToolbar.tsx — ο κύκλος ζωής και η απόδοση
 * @see ui/table-cell-editor/use-table-text-toolbar.ts — ποιος τον γεμίζει
 */

import type {
  TableFontControlsState,
  TableFormatSnapshot,
  TableToggleFormatKey,
} from '../table-format-toolbar/TableFormatToolbar';
import type { TableAxisStyleOverride } from '../../../types/table';
import type { TextHeightStepDirection } from '../../../bim/table/table-text-height-scale';

/** Τα δύο πεδία κειμένου της συνεδρίας: το κελί (textarea) και η γραμμή τύπων (input). */
export type TableTextField = HTMLTextAreaElement | HTMLInputElement;

/**
 * Ο στόχος, **παγωμένος στο άνοιγμα**: τι δείχνουν τα χειριστήρια, και **ποιο πεδίο** πάτησε ο
 * χρήστης.
 *
 * ## 🔴 Γιατί κουβαλά το ΙΔΙΟ το πεδίο
 * Η εστίαση πρέπει να γυρίσει **εκεί** όταν φύγει η γραμμή. Ο δρόμος των αδελφών μενού
 * (`restartTableCellCursorSession`) ξαναστήνει **το κελί** — σωστό εκεί, γιατί το δεξί κλικ έγινε
 * στον καμβά· εδώ μπορεί να έγινε στη **γραμμή τύπων**, και μια επαναφορά «στο κελί» θα
 * μετακόμιζε το πληκτρολόγιο σε άλλο πεδίο από αυτό που άγγιξε ο χρήστης.
 *
 * ## 🔴 ADR-753 Φ4 — γιατί η **επιλογή χαρακτήρων** ΔΕΝ είναι εδώ μέσα
 * Εδώ έγραφε: *«καμία επιλογή κειμένου δεν ταξιδεύει εδώ (§67.10): τα χειριστήρια βάφουν
 * ολόκληρο το κελί, γιατί ο πίνακας δεν έχει μορφοποίηση ανά χαρακτήρα»*. Η **αιτιολογία** ήταν
 * ψευδής (το `TableCell.runs` υπάρχει από το ADR-753 Φ1), αλλά το **συμπέρασμα** μένει, για
 * εντελώς άλλον λόγο: η επιλογή είναι κατάσταση του **ιδιοκτήτη**, όχι της επιφάνειας.
 *
 * Η γραμμή δεν παίρνει ποτέ απόφαση για το «ποια γράμματα» — δεν έχει ούτε έναν χειριστή που
 * να δέχεται στόχο (δες {@link TableTextFormatActions}). Ένα πεδίο εδώ θα ήταν πληροφορία που
 * η επιφάνεια **δεν χρησιμοποιεί**, δηλαδή δεύτερο αντίγραφο μιας αλήθειας που ζει σε ένα ref
 * του `use-table-text-toolbar` — και θα πάλιωνε στο πρώτο πάτημα.
 */
export interface TableTextToolbarTarget {
  readonly field: TableTextField;
  /** `C3` — η ονομασία του κελιού, για το προσβάσιμο όνομα της γραμμής. */
  readonly label: string;
  /** Τι δείχνουν τα Β/Ι/Υ και τα δύο χρώματα για **αυτό** το κελί. */
  readonly format: TableFormatSnapshot;
  /** §55 — γραμματοσειρά + μέγεθος, οι δύο πρώτες θέσεις της σειράς 1. */
  readonly fonts: TableFontControlsState;
  /** Ό,τι μπορεί να διαλέξει ο χρήστης στο combobox γραμματοσειράς (getter-read, ADR-040). */
  readonly fontNames: readonly string[];
}

/**
 * Τα χειριστήρια — **χωρίς όρισμα στόχου**.
 *
 * Ο στόχος τους είναι **τα γράμματα που μάρκαρε ο χρήστης, αλλιώς το κελί που γράφεται**, και
 * τον ξέρει ο ιδιοκτήτης (δρομέας + παγωμένη επιλογή): μια παράμετρος εδώ θα ζητούσε από την
 * επιφάνεια να αποφασίσει «ποια γράμματα», δηλαδή θα ήταν δεύτερη απάντηση. Ο ιδιοκτήτης τον
 * ξαναφτιάχνει **μέσα** σε κάθε χειριστή, ώστε ένα undo ενόσω η γραμμή ήταν ανοιχτή να σημαίνει
 * «καμία πράξη».
 *
 * ## 🔴 ADR-753 Φ4 — ΤΕΣΣΕΡΑ ΧΕΙΡΙΣΤΗΡΙΑ ΕΦΥΓΑΝ, ΚΑΙ ΤΟ ΕΞΗΓΕΙ ΤΟ EXCEL
 * Έλειπαν από τον τύπο το `onReset` και το `onSetFillColor`, μαζί με την **υπογράμμιση** και το
 * **πινέλο** (που δεν είχαν ποτέ δικό τους χειριστή — δηλώνονται στη γραμμή). Ο ιδιοκτήτης
 * μέτρησε το mini toolbar του Excel σε λειτουργία Επεξεργασίας: δείχνει **ακριβώς**
 * `[Γραμματοσειρά][Μέγεθος] │ Β Ι Α▾ A↑ A↓`.
 *
 * Δεν είναι μόνο μίμηση: τα τέσσερα που έφυγαν είναι ακριβώς εκείνα που **δεν έχουν νόημα σε
 * γράμματα** — το γέμισμα βάφει το κελί, η επαναφορά καθαρίζει το κελί, το πινέλο αντιγράφει
 * μορφή **κελιού**. Το ένα που έχει (η υπογράμμιση) φεύγει με ρητή εντολή, γιατί εκεί βαραίνει
 * περισσότερο η ταύτιση με το εργαλείο που ο χρήστης ξέρει ήδη.
 *
 * ⚠️ **Καμία λειτουργία δεν χάθηκε**: και τα τέσσερα ζουν αυτούσια στο mini toolbar της
 * **περιοχής** (δεξί κλικ σε κελιά) και στην κορδέλα — εκεί όπου ο στόχος είναι κελιά.
 */
export interface TableTextFormatActions {
  readonly onToggle: (key: TableToggleFormatKey) => void;
  readonly onStepSize: (direction: TextHeightStepDirection) => void;
  readonly onSetTextColor: (value: string | undefined) => void;
  readonly onSetField: <K extends keyof TableAxisStyleOverride>(
    key: K,
    value: TableAxisStyleOverride[K] | undefined,
  ) => void;
}

export interface TableTextToolbarProps {
  readonly formatActions: TableTextFormatActions;
  /**
   * Η γραμμή έφυγε **με πρωτοβουλία του χρήστη** (πλήκτρο, κύλιση, κλικ έξω) — εδώ επιστρέφει η
   * εστίαση στο πεδίο που πάτησε.
   *
   * ⚠️ **Δεν** καλείται από το `close()` του συμβολαίου: εκείνο είναι εντολή του ιδιοκτήτη (η
   * συνεδρία πέθανε), και τότε δεν υπάρχει πεδίο να επιστρέψει τίποτα.
   */
  readonly onClosed: () => void;
}

export interface TableTextToolbarHandle {
  open: (x: number, y: number, target: TableTextToolbarTarget) => void;
  close: () => void;
}
