/**
 * 🔴 ADR-828 §7.2 — **η διάταξη του μενού δεξιού συρσίματος της λαβής συμπλήρωσης**.
 *
 * ## Γιατί μητρώο και όχι JSX με τη σειρά γραμμένη μέσα του
 * Ίδιο κριτήριο, ίδιος λόγος με το `table-range-menu-commands.ts`: **η γνώση χωριστά από την
 * υποδοχή**. Η σειρά και οι ομάδες είναι το προϊόν της αντιστοίχισης με το Excel — δηλαδή
 * γνώση που ελέγχεται με test χωρίς DOM — ενώ τα εικονίδια είναι React και ζουν στο `.tsx`.
 *
 * ## 🔴 Τι ΔΕΝ ξέρει αυτό το αρχείο
 * **Ποιες εντολές είναι πατήσιμες.** Το ξέρει ο καλών, από τη **μία** ανίχνευση που έτρεξε η
 * χειρονομία ({@link TableFillMenuEnabled} πάνω στον στόχο). Μια σταθερά «disabled» εδώ θα
 * ήταν ψέμα την ημέρα που η πράξη θα γραφτεί — και, χειρότερα, θα ήταν **δεύτερη** άποψη για
 * το αν αυτό το γέμισμα είναι σειρά, δίπλα σε εκείνη του `tableFillMenuOffer`.
 *
 * ## Όψη τώρα, λειτουργία σταδιακά — **με ίχνος**
 * Οι τρεις τελευταίες εντολές («Γραμμική τάση», «Αύξηση τάσης», «Σειρά…») εμφανίζονται
 * **γκρίζες**: υπάρχουν στη θέση τους ώστε ο χρήστης να μάθει πού ζουν πριν υπάρξουν, και να
 * μην πατήσει ποτέ κάτι που δεν κάνει τίποτα. Είναι η ίδια απόφαση με τα οκτώ γκρίζα items
 * του μενού περιοχής (Α17 του ADR-750: «όλα ή τίποτα, με ίχνος»).
 *
 * ⚠️ **Η «Γραμμική τάση» ΔΕΝ είναι το ίδιο με τη σημερινή προσαρμογή ελαχίστων τετραγώνων.**
 * Εκείνη τρέχει μέσα στο `'auto'` όταν η πηγή **δεν** είναι ακριβής πρόοδος (ADR-828 §2)· η
 * εντολή του Excel είναι κάτι άλλο — **επιβάλλει** γραμμική προσαρμογή ακόμη και σε ακριβή
 * πρόοδο, δηλαδή είναι πράξη του ανθρώπου, όχι υποχώρηση της μηχανής. Γι' αυτό μένει γκρίζα
 * αντί να «συνδεθεί» με ό,τι υπάρχει ήδη.
 *
 * @module subapps/dxf-viewer/ui/components/table-fill-menu/table-fill-menu-commands
 * @see ui/components/table-fill-menu/TableFillMenuItems.tsx — η υποδοχή (εικονίδια + JSX)
 * @see bim/table/table-fill-plan.ts — `tableFillMenuOffer`, ποιες έχουν νόημα
 * @see docs/centralized-systems/reference/adrs/ADR-828-table-autofill-series.md §7.2
 */

/**
 * Οι **έντεκα** εντολές του μενού. Η ταυτότητα είναι και το κλειδί i18n (δες παρακάτω).
 *
 * 🔑 Οι οκτώ πρώτες ονομάζονται **όπως η πρόθεση**, όχι όπως η κατάσταση γεμίσματος
 * (`copyCells`, όχι `copy`): το μενού είναι διεπαφή και το `TableFillMode` είναι μηχανή, και
 * μια ταυτότητα που τυχαίνει να συμπίπτει σε επτά από τις οκτώ θα διάβαζε ως συμβόλαιο. Ο
 * χάρτης προς τις καταστάσεις γράφεται **μία φορά**, στην υποδοχή.
 */
export type TableFillMenuCommandId =
  | 'copyCells'
  | 'fillSeries'
  | 'formatOnly'
  | 'withoutFormat'
  | 'fillDays'
  | 'fillWeekdays'
  | 'fillMonths'
  | 'fillYears'
  | 'linearTrend'
  | 'growthTrend'
  | 'series';

/**
 * **Ποιες εντολές έχουν νόημα ΤΩΡΑ** — η απάντηση του καλούντος, ανά άνοιγμα.
 *
 * `Partial` επίτηδες, με την ίδια σημασία όπως στο μενού περιοχής: η **απουσία** σημαίνει «δεν
 * το ρώτησε κανείς», που είναι διαφορετικό από το `false` («ρωτήθηκε και δεν γίνεται»). Ο
 * κανόνας ενεργοποίησης απαιτεί χειριστή *και* μη-`false`, οπότε η απουσία δεν μπορεί ποτέ να
 * ανοίξει εντολή που δεν υπάρχει.
 */
export type TableFillMenuEnabled = Readonly<Partial<Record<TableFillMenuCommandId, boolean>>>;

interface TableFillMenuEntry {
  readonly id: TableFillMenuCommandId;
  readonly labelKey: string;
}

/**
 * Μια ομάδα = ό,τι ζει **ανάμεσα σε δύο διαχωριστές**.
 *
 * Τύπος μη-κενής πλειάδας, ίδιος λόγος με το μενού περιοχής: το διαχωριστικό μπαίνει *πριν*
 * από κάθε ομάδα πλην της πρώτης, άρα μια κενή ομάδα θα ζωγράφιζε **δύο γραμμές κολλητά** —
 * σφάλμα που φαίνεται μόνο με το μάτι. Έτσι είναι αδύνατο να γραφτεί.
 */
type TableFillMenuGroup = readonly [TableFillMenuEntry, ...TableFillMenuEntry[]];

const ITEM_PREFIX = 'table.fillMenu.items';

/**
 * Το κλειδί είναι **παράγωγο της ταυτότητας**, ποτέ δεύτερος χειρόγραφος πίνακας έντεκα
 * γραμμών — εκεί δεν υπάρχει τίποτα να αποκλίνει.
 */
function command(id: TableFillMenuCommandId): TableFillMenuEntry {
  return { id, labelKey: `${ITEM_PREFIX}.${id}` };
}

/**
 * 🔴 **Η ΣΕΙΡΑ ΤΟΥ EXCEL, ΣΕ ΤΡΕΙΣ ΟΜΑΔΕΣ.**
 *
 * 1. **Τι ταξιδεύει** — αντιγραφή, σειρά, μόνο μορφή, χωρίς μορφή. Οι τέσσερις που ισχύουν
 *    για κάθε είδος περιεχομένου (οι τρεις από αυτές **πάντα**).
 * 2. **Μονάδα ημερολογίου** — έχει αντικείμενο μόνο όταν η πηγή είναι ημερομηνία, αλλιώς και
 *    οι τέσσερις είναι γκρίζες. Εδώ ζει η **μόνη** πόρτα προς τις «καθημερινές» (ADR-828 §2:
 *    δεν συμπεραίνονται ποτέ).
 * 3. **Τάση και διάλογος** — οι τρεις χωρίς πράξη σήμερα.
 */
export const TABLE_FILL_MENU_GROUPS: readonly TableFillMenuGroup[] = [
  [command('copyCells'), command('fillSeries'), command('formatOnly'), command('withoutFormat')],
  [command('fillDays'), command('fillWeekdays'), command('fillMonths'), command('fillYears')],
  [command('linearTrend'), command('growthTrend'), command('series')],
];
