/**
 * ADR-750 Φάση 3 — **τι δείχνει το μενού περιγραμμάτων**: εντολές, σειρά, ομάδες, ετικέτες.
 *
 * ## Γιατί χωριστά από τα δύο components
 * Οι εντολές εμφανίζονται σε **δύο** υποδοχές: ως πάνελ μέσα στο mini toolbar των ζωνών δείκτη
 * (Φ3) και ως στοιχεία μενού στο δεξί κλικ πάνω σε επιλογή κελιών (Φ4). Οι δύο υποδοχές έχουν
 * διαφορετική **παρουσίαση** (σκέτο `<button>` σε `role="menu"` του δικού μας δοχείου εναντίον
 * `DxfMenuItem` του Radix) αλλά **ταυτόσημη γνώση**: ποιες εντολές, με ποια σειρά, ποια είναι η
 * αρχή νέας ομάδας, ποιο i18n κλειδί, ποιες προσφέρονται σήμερα.
 *
 * Δύο αντίγραφα αυτής της γνώσης θα ήταν το κλασικό σχήμα σιωπηλής απόκλισης: η μέρα που η Φ5
 * ενεργοποιεί τη διπλή γραμμή, η μία υποδοχή θα την έδειχνε και η άλλη όχι.
 *
 * ## Τίποτα δεν ξαναδηλώνεται
 * Η **σειρά** και οι **ομάδες** ζουν στο μητρώο της Φ2 (`TABLE_BORDER_COMMANDS`, πεδίο `group`),
 * μετρημένες από στιγμιότυπο του ελληνικού Excel. Εδώ γίνεται μόνο η **μετάφραση σε UI**: πού
 * πέφτει διαχωριστικό (εκεί που αλλάζει το `group`) και ποιο κλειδί i18n αντιστοιχεί σε κάθε
 * ταυτότητα (το ίδιο το `id`, χωρίς χειρόγραφο πίνακα 13 γραμμών).
 *
 * @module subapps/dxf-viewer/ui/components/table-format-toolbar/table-border-menu-items
 * @see bim/table/table-range-border-ops.ts — το μητρώο (σειρά + ομάδες + διαθεσιμότητα)
 * @see docs/centralized-systems/reference/adrs/ADR-750-table-cell-borders.md §8.1 · §18
 */

import {
  TABLE_BORDER_COMMANDS,
  type TableBorderCommand,
} from '../../../bim/table/table-range-border-ops';

/** Το πρόθεμα των 13 ορατών ονομάτων· η ταυτότητα της εντολής συμπληρώνει το κλειδί. */
const COMMAND_LABEL_PREFIX = 'table.borders.commands';

export interface TableBorderMenuItem {
  readonly command: TableBorderCommand;
  /** Πλήρες i18n κλειδί — παράγωγο της ταυτότητας, ποτέ δεύτερος χειρόγραφος πίνακας. */
  readonly labelKey: string;
  /**
   * Αρχή νέας ομάδας ⇒ διαχωριστικό **πριν** από αυτό το στοιχείο.
   *
   * Προκύπτει από το `group` του μητρώου, όχι από χειρόγραφη λίστα θέσεων («μετά την 4η και
   * την 8η»). Η επιλογή δικαιώθηκε στη Φ5: όσο έλειπαν οι δύο διπλές γραμμές, οι θέσεις των
   * διαχωριστικών ήταν 4/7· με το ξεκλείδωμά τους έγιναν 4/8 — **χωρίς καμία αλλαγή εδώ**.
   * Μια σταθερή λίστα θέσεων θα είχε βάλει το διαχωριστικό σε λάθος σημείο, σιωπηλά.
   */
  readonly startsGroup: boolean;
}

/**
 * Τα στοιχεία του μενού, **έτοιμα προς απόδοση** — και τα **13**.
 *
 * ## ✅ ADR-750 Φ5 — το φίλτρο διαθεσιμότητας διαγράφηκε (Α17 → Α24)
 * Μέχρι τη Φ4 εδώ υπήρχε `if (!isTableBorderCommandAvailable(...)) continue`, που έκοβε τις
 * δύο διπλές γραμμές: ο μηχανισμός δεν υπήρχε ακόμη και ένα κουμπί που φαίνεται ενεργό χωρίς
 * να κάνει τίποτα είναι χειρότερο από ένα που λείπει (Α17, «όλα ή τίποτα, **με ίχνος**»).
 *
 * Η Φ5 έκλεισε την τρύπα, άρα η πύλη **έφυγε μαζί της**. Δεν έμεινε επιστρέφοντας μονίμως
 * `true`: μια συνάρτηση που δεν μπορεί δομικά να πει «όχι» δεν είναι φύλακας — είναι ψέμα που
 * ο επόμενος αναγνώστης θα πάρει στα σοβαρά, και νεκρός κώδικας για το CHECK 3.22.
 */
export function tableBorderMenuItems(): readonly TableBorderMenuItem[] {
  const items: TableBorderMenuItem[] = [];
  let previousGroup: TableBorderCommand['group'] | null = null;

  for (const command of TABLE_BORDER_COMMANDS) {
    items.push({
      command,
      labelKey: `${COMMAND_LABEL_PREFIX}.${command.id}`,
      // Το πρώτο στοιχείο δεν ανοίγει ομάδα με διαχωριστικό: δεν υπάρχει τίποτα να χωρίσει.
      startsGroup: previousGroup !== null && previousGroup !== command.group,
    });
    previousGroup = command.group;
  }

  return items;
}
