/**
 * ADR-739 Φ.Ε/Φ4β — **ποια γραμμή του μενού χρώματος είναι η ενεργή**. Καθαρή συνάρτηση, μηδέν
 * React: η μία απόφαση που ένα χειριστήριο **τριών** καταστάσεων οφείλει να πάρει σωστά.
 *
 * ## 🔴 ΓΙΑΤΙ ΤΟ `current === undefined` ΔΕΝ ΑΡΚΕΙ ΠΙΑ
 * Για το **κείμενο** το `undefined` σήμαινε μονοσήμαντα «μεικτή σειρά», γιατί το
 * `TableCellStyle.textColorHex` είναι **υποχρεωτικό**: κάθε κελί έχει πάντα χρώμα, άρα η μόνη
 * περίπτωση να μην υπάρχει κοινή τιμή είναι η διαφωνία.
 *
 * Το `fillColorHex` όμως είναι **προαιρετικό**, και το ίδιο `undefined` καταρρέει **τρεις**
 * εντελώς διαφορετικές πραγματικότητες σε μία:
 *
 * ```
 *   μεικτός άξονας            →  mixed: true          (καμία γραμμή ενεργή)
 *   ρητά «κανένα γέμισμα»     →  explicit + !mixed    (η γραμμή «Κανένα» ενεργή)
 *   κληρονομεί, και κενό      →  !explicit            (η γραμμή «Αυτόματο» ενεργή)
 * ```
 *
 * Οι δύο τελευταίες **ζωγραφίζουν ολόιδια** στην οθόνη — και οι δύο δείχνουν άδειο κελί. Ένα
 * χειριστήριο που τις μπέρδευε θα έδειχνε «Κανένα γέμισμα» επιλεγμένο σε στήλη που απλώς δεν
 * έχει αγγιχτεί ποτέ, δηλαδή θα έλεγε ότι ο χρήστης πήρε μια απόφαση που δεν πήρε.
 *
 * 🔑 Το `resolveAxisFormat` **επιστρέφει ήδη** και το `mixed` και το `overridden` — απλώς το
 * πρώτο πεταγόταν. Καμία αλλαγή μοντέλου: μόνο σταματάμε να πετάμε πληροφορία που υπήρχε.
 *
 * @module subapps/dxf-viewer/ui/components/table-format-toolbar/table-color-menu-selection
 * @see bim/table/table-axis-style-ops.ts — `resolveAxisFormat`, από όπου έρχονται οι σημαίες
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §35
 */

/**
 * Η κατάσταση ενός πεδίου χρώματος κατά μήκος του άξονα, όπως τη διαβάζει το μενού.
 *
 * Τα τέσσερα πεδία είναι **ορθογώνια** — κανένα δεν συνάγεται από τα άλλα, και γι' αυτό
 * μεταφέρονται όλα αντί να μαντεύονται.
 */
export interface TableAxisColorState {
  /**
   * Η **κοινή επιλυμένη** τιμή όλων των κελιών του άξονα.
   *
   * `undefined` σημαίνει «δεν υπάρχει κοινή τιμή **ή** η κοινή τιμή είναι “κανένα γέμισμα”» —
   * ποια από τις δύο, το λέει το {@link mixed}. Δες την κεφαλίδα.
   */
  readonly current: string | undefined;
  /** Τα κελιά του άξονα **δεν συμφωνούν** — Figma «Mixed», Revit «<varies>». */
  readonly mixed: boolean;
  /** Ο άξονας δηλώνει **ρητά** αυτό το πεδίο — και το ρητό `null` μετράει κι αυτό ως δήλωση. */
  readonly explicit: boolean;
  /**
   * Τι θα ίσχυε **χωρίς** την παράκαμψη — το δείγμα δίπλα στο «Αυτόματο».
   *
   * `undefined` ⇒ κληρονομεί «κανένα» **ή** κληρονομεί διαφορετικά ανά κελί· ποια από τις δύο,
   * το λέει το {@link inheritedMixed}.
   */
  readonly inheritedColor: string | undefined;
  /**
   * 🔴 Η κληρονομιά **δεν είναι μία** κατά μήκος του άξονα.
   *
   * ── ΤΟ ΕΛΑΤΤΩΜΑ ΠΟΥ ΒΡΗΚΕ Η ΟΘΟΝΗ (ζωντανή επαλήθευση 2026-08-03) ──
   * Μια **κεφαλίδα** που περνά πάνω από στήλη με ρητό γέμισμα κληρονομεί `#EDEDED` σε δύο κελιά
   * και ματζέντα στο τρίτο. Χωρίς αυτή τη σημαία, το `inheritedColor` έπεφτε στην κλάση `data`
   * (που συνήθως **δεν βάφει**) και η γραμμή «Αυτόματο» δήλωνε «Κληρονομεί **«κανένα γέμισμα»**
   * από το στυλ» — **αναληθές**, ακριβώς στο χειριστήριο που υπάρχει για να λέει την αλήθεια.
   *
   * Για το **κείμενο** η ίδια πτώση ήταν αβλαβής: η κλάση `data` δηλώνει πάντα χρώμα, και η
   * υπόδειξη ήταν γενική («κληρονομείται από το στυλ») — δεν κατονόμαζε τίποτα. Για το γέμισμα
   * η πτώση **αντιστρέφει το νόημα**: από «κάποιο χρώμα» σε «κανένα». Το Revit απαντά την ίδια
   * ερώτηση με `<varies>` — μια **μη-δήλωση**, όχι μια λάθος δήλωση.
   */
  readonly inheritedMixed: boolean;
  /** Τα «χρώματα του σχεδίου», μαζεμένα από τον γονέα τη στιγμή του ανοίγματος. */
  readonly drawingColors: readonly string[];
}

/**
 * Ποια γραμμή του μενού φοράει το `aria-checked`.
 *
 * Διακριτή ένωση και όχι τρία booleans: με booleans υπάρχουν οκτώ συνδυασμοί, από τους οποίους
 * οι πέντε είναι αδύνατοι — και ο μεταγλωττιστής δεν θα το έλεγε ποτέ. Εδώ οι καταστάσεις είναι
 * **ακριβώς** όσες υπάρχουν.
 */
export type TableColorMenuSelection =
  /** Μεικτή σειρά — καμία γραμμή ενεργή. Το Figma δείχνει «Mixed» ακριβώς έτσι: τίποτα επιλεγμένο. */
  | { readonly kind: 'mixed' }
  /** Κληρονομιά από το στυλ — η γραμμή «Αυτόματο». */
  | { readonly kind: 'automatic' }
  /** Ρητά **καμία** βαφή (`null` στο μοντέλο) — η γραμμή «Κανένα γέμισμα». */
  | { readonly kind: 'none' }
  /** Ρητό χρώμα — το δείγμα με αυτό το hex φοράει το πλαίσιο. */
  | { readonly kind: 'color'; readonly hex: string };

/**
 * Η μία ανάγνωση της κατάστασης. **Η σειρά των ελέγχων είναι η σημασιολογία:**
 *
 * 1. Το `mixed` **πρώτο**, γιατί επισκιάζει τα πάντα: σε μεικτή σειρά καμία απάντηση για
 *    «ποιο χρώμα ισχύει» δεν είναι αληθινή, ούτε καν «κανένα».
 * 2. Το `explicit` **μετά**, γιατί ξεχωρίζει «το είπε ο χρήστης» από «το λέει το στυλ» — και
 *    αυτή είναι η ερώτηση που το Excel δεν απαντά ποτέ.
 * 3. Το `current` **τελευταίο**, γιατί μόνο τότε ξέρουμε ότι το `undefined` του σημαίνει
 *    «ρητά κανένα» και όχι κάτι από τα προηγούμενα δύο.
 */
export function resolveColorMenuSelection(state: TableAxisColorState): TableColorMenuSelection {
  if (state.mixed) return { kind: 'mixed' };
  if (!state.explicit) return { kind: 'automatic' };
  return state.current === undefined ? { kind: 'none' } : { kind: 'color', hex: state.current };
}

/**
 * Το hex που πρέπει να φοράει πλαίσιο στο πλέγμα· `undefined` σε κάθε άλλη κατάσταση.
 *
 * Βοηθός του καταναλωτή ώστε το JSX να μη γράψει `selection.kind === 'color' ? … : undefined`
 * σε **δύο** σημεία (πλέγμα και ζώνη εγγράφου) — δύο αντίγραφα της ίδιας συνθήκης είναι δύο
 * ευκαιρίες να αποκλίνουν.
 */
export function selectedSwatchHex(selection: TableColorMenuSelection): string | undefined {
  return selection.kind === 'color' ? selection.hex : undefined;
}
