'use client';

/**
 * 🔴 ADR-739 §64 — **η εφήμερη επιφάνεια υποχωρεί στη μόνιμη.**
 *
 * ## Τι λύνει, με μία πρόταση
 * Το mini toolbar του δεξιού κλικ ζωγραφιζόταν **πάνω** στον διάλογο «Μορφοποίηση κελιών» που
 * ανοίγει το **δικό του** μενού, καλύπτοντας μετρημένα **456×63 px = 12,8%** της επιφάνειάς
 * του — και το `elementFromPoint` στο κέντρο της επικάλυψης επέστρεφε **κουμπί του toolbar**,
 * δηλαδή το περιεχόμενο από κάτω δεν ήταν απλώς κρυμμένο, ήταν **απάτητο**.
 *
 * ## 🔬 Η ΕΡΕΥΝΑ — ο κανόνας υπάρχει, και είναι κανόνας ΚΥΚΛΟΥ ΖΩΗΣ, όχι z-index
 * Το mini toolbar του **Excel** — αυτό ακριβώς που αντιγράφει η Α7 — είναι **transient**:
 * *«if you move the mouse elsewhere, the Mini toolbar disappears so that it doesn't get in the
 * way of your work»* · *«if you use the scroll wheel or press any key then the toolbar
 * automatically disappears»*. Το **Fluent 2** ονομάζει την ίδια διάκριση: **transient /
 * light-dismiss** επιφάνειες (μενού, popovers) έναντι **primary** επιφανειών, με ιεραρχία
 * **elevation** — όχι αυθαίρετο αριθμό.
 *
 * ⇒ Το ελάττωμα **δεν** είναι «ο διάλογος έχει χαμηλό z-index». Είναι ότι μια επιφάνεια που
 * **οφείλει να έχει ήδη φύγει** ήταν ακόμη εκεί. Ένα z-index bump θα άφηνε το toolbar να
 * αιωρείται άσκοπα πάνω από τον πίνακα (μετρημένο: επιβιώνει και μετά το κλείσιμο του
 * διαλόγου) — θα έκρυβε το σύμπτωμα, όχι την αιτία.
 *
 * ## 🔑 ΓΙΑΤΙ ΑΥΤΟ ΔΕΝ ΑΝΑΙΡΕΙ ΤΗΝ ΑΠΟΦΑΣΗ §28.13 — το ΑΝΤΙΘΕΤΟ, τη ΣΥΜΠΛΗΡΩΝΕΙ
 * Η απόφαση του ιδιοκτήτη ήταν ότι η γραμμή **επιβιώνει του μενού**, επειδή η μορφοποίηση
 * είναι κατεξοχήν **επαναλαμβανόμενη** πράξη (έντονα, μετά πλάγια, μετά ένα μέγεθος πάνω) και
 * κάθε εντολή της γραμμής επιστρέφει τον χρήστη στην ίδια γραμμή.
 *
 * Το «Μορφοποίηση κελιών…» **δεν είναι εντολή της γραμμής**: δεν γράφει τίποτα, **παραδίδει τη
 * σκυτάλη** σε μια μόνιμη επιφάνεια που περιέχει **υπερσύνολο** των χειριστηρίων της γραμμής
 * (έξι καρτέλες έναντι εννιά κουμπιών). Δύο επιφάνειες που κάνουν την ίδια δουλειά, με τη
 * μικρότερη να κάθεται πάνω στη μεγαλύτερη, δεν είναι επιλογή — είναι υπόλειμμα.
 *
 * ## 🔑 ΓΙΑΤΙ ΕΔΩ, ΚΑΙ ΟΧΙ ΣΤΟ ΣΗΜΕΙΟ ΠΟΥ ΠΑΤΗΘΗΚΕ ΤΟ ITEM
 * Ο **προφανής** τόπος είναι το `onFormatCells` των δύο μενού: «αυτό το item κλείνει και τη
 * γραμμή». Απορρίφθηκε **με μέτρηση**: οι υποδοχές του διαλόγου είναι **πέντε** (§61) — δύο
 * βελάκια κορδέλας, `Ctrl+1`, και τα δύο μενού. Με τη γνώση στα items, η ακολουθία
 * «δεξί κλικ σε κελί *(γραμμή ζωντανή)* ▸ βελάκι «Αριθμός» της κορδέλας» θα ξαναγεννούσε
 * **ακριβώς** την ίδια επικάλυψη, από δρόμο που κανείς δεν κοίταξε. Η ερώτηση δεν είναι «ποιο
 * item πατήθηκε» αλλά «**υπάρχει μόνιμη επιφάνεια;**» — και αυτή έχει **μία** απάντηση, το
 * store του §61, που είναι ήδη η **μία πόρτα** κάθε ανοίγματος.
 *
 * ⚠️ Γι' αυτό το hook ακούει το **αίτημα**, όχι το συμβάν. Ένα `onFormatCells` που καλεί
 * `dismiss()` θα ήταν σωστό για **δύο** από τις πέντε υποδοχές, δηλαδή θα ήταν λάθος.
 *
 * ## ⚠️ ΤΙ ΔΕΝ ΚΑΝΕΙ ΑΥΤΟ ΤΟ HOOK — δηλωμένο, όχι σιωπηλό
 * **Δεν** διορθώνει τη στρώση. Μετρημένο ζωντανά (2026-08-08, DOM `getComputedStyle`):
 * ```
 *   διάλογος (FloatingPanel)      1700   ← από το SSoT (zIndex.toast)
 *   Select μέσα σε παλέτα         2000   ← ωμό, αλλά ΤΕΚΜΗΡΙΩΜΕΝΟ («above FloatingPanel»)
 *   κορδέλα (flyouts)             9000 / 9001   ← ωμό
 *   παλέτα ιδιοτήτων              9900          ← ωμό
 *   μενού δεξιού κλικ             9999          ← ωμό
 *   mini toolbar                 10000          ← ωμό
 * ```
 * Ολόκληρη η ζώνη **9000-10000 δεν ανήκει σε καμία δηλωμένη κλίμακα** (το SSoT σταματά στο
 * `tooltip: 1800`), ενώ η γέφυρα προς το CSS **υπάρχει ήδη και δεν τη ρωτά κανείς**
 * (`--z-index-*` στο `design-system/generated/variables.css`). Αν αύριο μια **άλλη** μόνιμη
 * επιφάνεια συναντήσει το toolbar, θα χάσει ξανά. Είναι δηλωμένο ανοιχτό στο ADR-739 §64.3 και
 * στο `.claude-rules/pending-ratchet-work.md` — **με αριθμούς**, ώστε να μη διαβαστεί ως
 * πληρότητα.
 *
 * @module subapps/dxf-viewer/ui/components/table-format-toolbar/use-yield-to-persistent-surface
 * @see state/table-format-cells-dialog-store.ts — η ΜΙΑ πόρτα κάθε ανοίγματος (§61)
 */

import { useEffect } from 'react';
import { useTableFormatCellsRequest } from '../../../state/table-format-cells-dialog-store';

/**
 * Διώχνει την εφήμερη επιφάνεια **μόλις** υπάρξει αίτημα μόνιμης.
 *
 * @param dismiss Η αποχώρηση της εφήμερης επιφάνειας. Πρέπει να είναι **σταθερή** (`useCallback`
 *        χωρίς εξαρτήσεις): με αστάθεια το effect θα ξανάτρεχε σε κάθε απόδοση και θα καλούσε
 *        `dismiss()` ξανά όσο ο διάλογος ζει — ακίνδυνο μεν (το `setTarget(null)` είναι
 *        ταυτοδύναμο), αλλά θα ήταν εργασία που δεν χρειάζεται κανείς.
 *
 * 🔑 Η εξάρτηση είναι το **boolean**, όχι το αίτημα: ένα δεύτερο άνοιγμα (νέο `id`) ενόσω ο
 * διάλογος ζει είναι **άλλη ερώτηση για τον χρήστη** αλλά **ίδια απάντηση εδώ** — η γραμμή έχει
 * ήδη φύγει. Με εξάρτηση το αντικείμενο, κάθε αλλαγή καρτέλας θα ξανακαλούσε `dismiss()`.
 */
export function useYieldToPersistentSurface(dismiss: () => void): void {
  const hasPersistentSurface = useTableFormatCellsRequest() !== null;

  useEffect(() => {
    if (!hasPersistentSurface) return;
    dismiss();
  }, [hasPersistentSurface, dismiss]);
}
