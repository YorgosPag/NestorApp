'use client';

/**
 * 🔴 ADR-754 §4 — **ΠΟΥ ΣΤΗΝΕΤΑΙ Ο ΚΕΡΣΟΡΑΣ ΟΤΑΝ ΤΟΝ ΤΟΠΟΘΕΤΕΙ Ο ΚΩΔΙΚΑΣ**, για **και τα
 * δύο** πεδία της συνεδρίας.
 *
 * ## Γιατί υπάρχει αυτό το αρχείο — μία μηχανή, όχι δύο
 * Ο επεξεργαστής κελιού είχε ήδη ένα effect «στήσε τον κέρσορα στο άνοιγμα» (ADR-739 Φ.Δ
 * βήμα 3: το διπλό κλικ βάζει τον κέρσορα **στο γράμμα που έδειξες**, όπως στο Excel). Η
 * υπόδειξη κελιού χρειάζεται **την ίδια ακριβώς πράξη** σε άλλη αφορμή. Δύο effects με
 * ταυτόσημο σώμα, σε δύο αρχεία, είναι ο ορισμός του sibling clone που πιάνει το CHECK 3.28
 * (N.18) — και, χειρότερα, δύο σημεία όπου μπορεί να ξεχαστεί το `Math.min`.
 *
 * Άρα δεν προστίθεται μηχανισμός: το υπάρχον effect **γενικεύεται** και αποκτά δεύτερο
 * καταναλωτή. Η αφορμή είναι πλέον ρητή — ο αύξων {@link TableCellCursorState.caretRevision}.
 *
 * ## 🔴 Γιατί `useLayoutEffect` και όχι `useEffect`
 * Η διαφορά είναι **ορατή στην οθόνη**, όχι δογματική. Όταν αλλάζει η τιμή ενός πεδίου
 * κειμένου, ο browser πηγαίνει τον κέρσορα στο **τέλος**. Με `useEffect` η διόρθωση τρέχει
 * **μετά** τη ζωγραφιά, δηλαδή υπάρχει ένα καρέ όπου ο χρήστης βλέπει τον κέρσορα στο λάθος
 * σημείο και, αν πληκτρολογήσει μέσα σε αυτό, γράφει στο λάθος σημείο. Με `useLayoutEffect`
 * η διόρθωση μπαίνει **πριν** τη ζωγραφιά: το ενδιάμεσο καρέ δεν υπάρχει.
 *
 * Δεν υπάρχει κίνδυνος SSR: κανένα από τα δύο πεδία δεν αποδίδεται ποτέ στον διακομιστή —
 * γεννιούνται μόνο όταν υπάρχει δρομέας, δηλαδή μόνο μετά από ενέργεια του χρήστη.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/use-table-cell-caret
 * @see state/table-cell-cursor-store.ts — γιατί χρειάζεται **αριθμός** και όχι μόνο θέση
 * @see ui/table-cell-editor/table-point-mode-pointer.ts — ο ένας από τους δύο γραφείς
 * @see docs/centralized-systems/reference/adrs/ADR-754-table-point-mode.md §4
 */

import { useLayoutEffect, type RefObject } from 'react';

/**
 * Τα δύο πεδία της συνεδρίας: στοιχείο `textarea` το κελί, στοιχείο `input` η γραμμή τύπων.
 *
 * ⚠️ Τα ονόματα γράφονται **χωρίς γωνιώδεις αγκύλες** επίτηδες: ο σαρωτής του CHECK N.11
 * είναι regex και διαβάζει `<textarea>…` μέσα σε σχόλιο ως κείμενο JSX, οπότε το ελληνικό
 * που ακολουθεί μοιάζει με hardcoded ετικέτα οθόνης. Ο κανόνας εξαιρεί τα σχόλια· ο σαρωτής
 * δεν το ξέρει. Η αναδιατύπωση κοστίζει μηδέν και δεν ζητά χαλάρωση της πύλης.
 */
export type TableCellSessionField = HTMLTextAreaElement | HTMLInputElement;

/**
 * Τοποθετεί τον κέρσορα στο `caretIndex` (ή στο **τέλος** όταν λείπει) κάθε φορά που αλλάζει
 * το `caretRevision` — δηλαδή στο στήσιμο του πεδίου **και** σε κάθε υπόδειξη κελιού.
 *
 * @param enabled `false` σε **πλοήγηση**: εκεί δεν γράφεται τίποτα και το πεδίο είναι
 *   διαφανές· μια τοποθέτηση κέρσορα θα ήταν πράξη χωρίς νόημα σε κείμενο που δεν φαίνεται.
 */
export function useTableCellCaret(
  fieldRef: RefObject<TableCellSessionField | null>,
  caretIndex: number | undefined,
  caretRevision: number,
  enabled: boolean,
): void {
  useLayoutEffect(() => {
    if (!enabled) return;
    const field = fieldRef.current;
    if (!field) return;
    // Το `Math.min` δεν είναι παράνοια: ο δείκτης μπορεί να υπολογίστηκε πάνω στο
    // **δεσμευμένο** κείμενο (διπλό κλικ) ενώ εδώ διαβάζεται το πρόχειρο — μια ασύγχρονη
    // ενημέρωση σκηνής ανάμεσα στα δύο δίνει δείκτη εκτός ορίων.
    const at = caretIndex === undefined ? field.value.length : Math.min(caretIndex, field.value.length);
    field.setSelectionRange(at, at);
    // 🔴 Η **μόνη** εξάρτηση είναι η αφορμή, και είναι σκόπιμο:
    //  - το `caretIndex` **δεν** μπαίνει, γιατί δύο υποδείξεις στην ίδια θέση είναι δύο
    //    γεγονότα (δες το σχόλιο του `caretRevision` στο store)·
    //  - το `enabled` **δεν** μπαίνει, γιατί η μετάβαση πλοήγηση → γραφή γίνεται με τον
    //    **πρώτο χαρακτήρα** που πληκτρολογεί ο χρήστης: εκεί τον κέρσορα τον έχει ήδη βάλει
    //    σωστά ο browser, και μια επιβολή θα τον πολεμούσε.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [caretRevision]);
}
