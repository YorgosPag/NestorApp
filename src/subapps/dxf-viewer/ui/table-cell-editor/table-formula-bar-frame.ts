/**
 * ADR-739 Φ.Δ βήμα 7 — **το κουτί της γραμμής τύπων σε px οθόνης**. Καθαρή συνάρτηση.
 *
 * Ξεχωριστό αρχείο για τον ίδιο λόγο που είναι ξεχωριστό και το
 * `table-cell-editor-frame.ts`: η γεωμετρία ενός επεξεργαστή είναι **αριθμοί**, και οι
 * αριθμοί δοκιμάζονται χωρίς DOM, χωρίς React και χωρίς καμβά. Ένα λάθος εδώ είναι λάθος
 * απόφασης, όχι καλωδίωσης.
 *
 * ## Πού κάθεται
 * Το άγκυρο είναι η **πάνω-αριστερή γωνία του πίνακα** (πλαίσιο `0,0`). Από εκεί η γραμμή
 * μετατοπίζεται:
 *  - **αριστερά** ως την αριστερή ακμή της ζώνης `1 2 3` — ακριβώς όπως το πλαίσιο ονόματος
 *    του Excel κάθεται πάνω από τη στήλη των αριθμών γραμμής·
 *  - **πάνω** ως πάνω από τη ζώνη `A B C`, συν κενό, συν το δικό της ύψος.
 *
 * ## 🔴 ADR-739 §27.13 — ΔΕΝ ΞΕΡΕΙ ΠΟΥ ΤΕΛΕΙΩΝΕΙ Ο ΔΕΙΚΤΗΣ· ΡΩΤΑΕΙ
 * Εδώ έγραφε `TABLE_INDICATOR.columnBandPx + …` και `-TABLE_INDICATOR.rowBandPx`, δηλαδή
 * **ξανάφτιαχνε** το εξωτερικό όριο του δείκτη από τα συστατικά του. Δούλευε όσο η ζώνη
 * ακουμπούσε το πλέγμα· τη στιγμή που η ζώνη απέκτησε **κενό** (§27.11), η γραμμή έμεινε
 * στην παλιά της θέση και **σκέπασε τα γράμματα των στηλών** — το ακριβώς αντίθετο από τον
 * λόγο που υπάρχει.
 *
 * Τώρα καταναλώνει το `TABLE_INDICATOR_OUTER_PX`: **κενό + ζώνη, μετρημένα σε ένα σημείο**.
 * Ό,τι κι αν αποφασιστεί αύριο για τη θέση ή το πάχος της ζώνης, η γραμμή το μαθαίνει δωρεάν.
 *
 * 🔴 Και οι δύο μετατοπίσεις είναι σε **px οθόνης**, άρα δεν μπορούν να ψηθούν στο σημείο
 * κόσμου: εκείνο υπολογίζεται μία φορά ανά συνεδρία, ενώ αυτές αλλάζουν σε κάθε zoom (οι
 * ζώνες έχουν σταθερό πάχος σε px). Γι' αυτό ταξιδεύουν ως `offsetXPx`/`offsetYPx` του
 * ζωντανού κουτιού — δες {@link TextEditorAnchorBox}.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-formula-bar-frame
 * @see bim/table/table-indicator-geometry.ts — `TABLE_INDICATOR_OUTER_PX`, το ΕΝΑ όριο
 */

import { TABLE_INDICATOR_OUTER_PX } from '../../bim/table/table-indicator-geometry';

/** Ύψος της γραμμής σε px οθόνης — μία σειρά κειμένου + περιθώρια, σαν την μπάρα του Excel. */
const BAR_HEIGHT_PX = 26;

/** Κενό ανάμεσα στη γραμμή τύπων και τη ζώνη γραμμάτων, σε px οθόνης. */
const BAR_GAP_PX = 4;

/**
 * Ελάχιστο πλάτος: κάτω από αυτό δεν χωρά ούτε η αναφορά ούτε μια τιμή που να αξίζει να
 * διαβαστεί, οπότε η γραμμή θα ήταν διακοσμητική. Ένας στενός πίνακας παίρνει γραμμή
 * **πλατύτερη από τον εαυτό του** — σωστά: η γραμμή δείχνει ό,τι στο κελί **δεν χωρά**.
 */
const MIN_BAR_WIDTH_PX = 260;

/**
 * Μέγιστο πλάτος: ένας πίνακας 60 στηλών σε zoom-in θα έδινε γραμμή χιλιάδων px, δηλαδή
 * μια λωρίδα που διασχίζει την οθόνη για να δείξει μία τιμή. Το Excel έχει το ίδιο όριο
 * de facto (το πλάτος του παραθύρου)· εδώ δηλώνεται ρητά.
 */
const MAX_BAR_WIDTH_PX = 720;

/** Το κουτί της γραμμής τύπων, έτοιμο για το {@link TextEditorAnchorBox}. */
export interface TableFormulaBarFrame {
  readonly widthPx: number;
  readonly heightPx: number;
  /** Μετατόπιση από την πάνω-αριστερή γωνία του πίνακα (αρνητικές = αριστερά / πάνω). */
  readonly offsetXPx: number;
  readonly offsetYPx: number;
  /**
   * `true` όταν η γραμμή αναγκάστηκε να πάει **κάτω** από τον πίνακα. Δεν είναι στυλ —
   * είναι μαρτυρία: ένα test που έλεγχε μόνο «η μετατόπιση είναι αρνητική» θα περνούσε και
   * από μια υλοποίηση που δεν αναποδογυρίζει ποτέ.
   */
  readonly flipped: boolean;
}

/**
 * Πόσος κατακόρυφος χώρος χρειάζεται πάνω από τον πίνακα για να χωρέσει η γραμμή **και**
 * ολόκληρος ο δείκτης από κάτω της (ζώνη γραμμάτων **συν** το κενό της προς το πλέγμα).
 */
const SPACE_NEEDED_ABOVE_PX = TABLE_INDICATOR_OUTER_PX.top + BAR_GAP_PX + BAR_HEIGHT_PX;

/**
 * Το κουτί, δεδομένου του πλάτους του πίνακα και της ζωντανής κλίμακας.
 *
 * Το πλάτος περιλαμβάνει τη ζώνη αριθμών, γιατί η γραμμή ξεκινά από την **αριστερή ακμή
 * της ζώνης** και όχι από την ακμή του πίνακα — αλλιώς θα ήταν μετατοπισμένη κατά ένα
 * πλάτος ζώνης ως προς αυτό που σκεπάζει.
 *
 * Μη πεπερασμένη ή μη θετική κλίμακα ⇒ ελάχιστο πλάτος: ένας εκφυλισμένος μετασχηματισμός
 * (offscreen pass, μηδενικός καμβάς) δεν επιτρέπεται να παράγει `NaN` σε CSS, που θα
 * άφηνε τη γραμμή αόρατη χωρίς κανένα μήνυμα.
 */
export function computeTableFormulaBarFrame(params: {
  readonly tableWidthMm: number;
  readonly tableHeightMm: number;
  readonly pxPerMm: number;
  /**
   * Πόσα px υπάρχουν ανάμεσα στην πάνω ακμή του πίνακα και την πάνω ακμή της **περιοχής
   * σχεδίασης**. `null` όταν δεν μπορεί να μετρηθεί (ο container δεν έχει προσαρτηθεί) ⇒
   * καμία υπόθεση, η γραμμή μένει πάνω.
   */
  readonly spaceAbovePx: number | null;
}): TableFormulaBarFrame {
  const { tableWidthMm, tableHeightMm, pxPerMm, spaceAbovePx } = params;
  const usable = Number.isFinite(pxPerMm) && pxPerMm > 0;
  const spanPx = usable
    ? tableWidthMm * pxPerMm + TABLE_INDICATOR_OUTER_PX.left
    : MIN_BAR_WIDTH_PX;

  // 🔴 Το αναποδογύρισμα — βρέθηκε στη ΖΩΝΤΑΝΗ επαλήθευση, όχι σε test (2026-08-01).
  //
  // Ο πίνακας ήταν κοντά στο πάνω χείλος του σχεδίου, και η γραμμή τύπων κάθισε **έξω** από
  // την περιοχή σχεδίασης, πάνω στις κορδέλες της εφαρμογής. Το clamping του
  // `TextEditorAnchorLayer` δεν το πιάνει: αυτό περιορίζει στο **παράθυρο**, και η θέση ήταν
  // απολύτως έγκυρη μέσα στο παράθυρο — απλώς όχι μέσα στον καμβά.
  //
  // Η απάντηση δεν είναι «περιόρισέ την στον καμβά»: εκεί η γραμμή θα κολλούσε στο χείλος
  // και θα σκέπαζε τα γράμματα των στηλών, δηλαδή θα έκρυβε ακριβώς αυτό που εξηγεί. Πάει
  // **κάτω** από τον πίνακα — η ίδια απόφαση που παίρνει κάθε tooltip όταν δεν χωρά.
  const flipped = spaceAbovePx !== null && spaceAbovePx < SPACE_NEEDED_ABOVE_PX;
  const belowPx = usable ? tableHeightMm * pxPerMm + BAR_GAP_PX : BAR_GAP_PX;

  return {
    widthPx: Math.min(Math.max(spanPx, MIN_BAR_WIDTH_PX), MAX_BAR_WIDTH_PX),
    heightPx: BAR_HEIGHT_PX,
    offsetXPx: -TABLE_INDICATOR_OUTER_PX.left,
    offsetYPx: flipped ? belowPx : -SPACE_NEEDED_ABOVE_PX,
    flipped,
  };
}
