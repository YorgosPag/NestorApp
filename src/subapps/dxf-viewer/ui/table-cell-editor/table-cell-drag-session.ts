'use client';

/**
 * 🔴 ADR-739 §27.15 — **η σύρση επιλογής**: πάτα σε ένα κελί, σύρε, άσε — η περιοχή
 * ακολουθεί το χέρι. Η χειρονομία που έλειπε για να λέγεται «όπως στο Excel».
 *
 * ## Γιατί ΔΙΚΟ ΤΟΥ module και όχι άλλες 60 γραμμές στον pointer
 * Ο `use-table-cell-pointer` απαντά σε **μία** ερώτηση: «πού έπεσε αυτό το πάτημα;». Εδώ
 * ζει μια **δεύτερη**, με δικό της κύκλο ζωής: «όσο το κουμπί είναι κάτω, πού βρίσκομαι
 * τώρα;». Δύο ερωτήσεις, δύο αρχεία — και το όριο των 40 γραμμών ανά συνάρτηση (N.7.1)
 * μένει σεβαστό αντί να φουσκώσει ένας ήδη πυκνός χειριστής.
 *
 * ## 🔴 ΔΕΝ είναι τέταρτος drag controller — και αυτό ήταν ρητή απόφαση
 * Το SSoT audit (2026-08-02) μέτρησε **τρεις** ανεξάρτητες κλάσεις με το ίδιο
 * `idle → dragging` σχήμα (`OpeningTagDragController`, `MepWireWaypointDragController`,
 * `bim-3d/WaypointDragController`) και **κανέναν** γενικό `press→move→release` SSoT να
 * καταναλωθεί. Μια τέταρτη κλάση θα ήταν ακριβώς ο structural clone που πιάνει το CHECK
 * 3.28. Εδώ δεν υπάρχει μηχανή καταστάσεων: υπάρχουν **δύο ακροατές που ζουν όσο η
 * χειρονομία** — καμία κλάση, κανένα `getState()`, καμία δεύτερη έννοια «drag».
 *
 * ## Γιατί οι ακροατές ζουν στο `document` και όχι στο δοχείο
 * Το χέρι φεύγει από τον καμβά. Στο Excel η επιλογή συνεχίζει να ακολουθεί και το `mouseup`
 * μετράει **όπου κι αν γίνει** — αλλιώς μένει «κολλημένη» σύρση που κανείς δεν τερμάτισε.
 * Δεν χρησιμοποιείται `setPointerCapture`: **δεν υπάρχει πουθενά** στο subapp (μετρημένο),
 * και θα άλλαζε τη δρομολόγηση συμβάντων για **όλους** τους υπόλοιπους ακροατές του καμβά.
 *
 * ## 🔴 Γιατί γράφει ΜΟΝΟ όταν αλλάζει κελί — ADR-735
 * Το `setTableCellSelection` ζητά καρέ **άνευ όρων** (τεκμηριωμένο στο store: «ένα περιττό
 * repaint ανά **πάτημα πλήκτρου** κοστίζει μηδέν»). Η σύρση όμως δεν είναι πάτημα πλήκτρου:
 * είναι 60-120 συμβάντα το δευτερόλεπτο. Χωρίς αυτόν τον φύλακα, κάθε pixel κίνησης θα
 * ζητούσε επαναβαφή ολόκληρης της σκηνής — το ακριβές σχήμα «δουλειά ανάλογη της κίνησης,
 * όχι της αλλαγής» που ο ADR-735 πλήρωσε σε παραγωγή. Ο φύλακας ζει **εδώ** και όχι στο
 * store, γιατί το συμβόλαιο του store είναι σωστό για τον καλούντα που είχε.
 *
 * ## 🔴 ADR-739 §27.16 Ε1 — Η ΑΚΡΗ: **δύο** πηγές κίνησης, **μία** ερμηνεία
 * Από εδώ και πέρα το κινούμενο άκρο ξαναλύνεται από **δύο** αφορμές: το `mousemove` (το
 * χέρι κουνήθηκε) και το auto-pan (**ο κόσμος** κουνήθηκε κάτω από ακίνητο χέρι). Είναι η
 * ίδια ερώτηση, άρα περνούν και οι δύο από την **ίδια** `applyAt` — μαζί με τον ίδιο φύλακα
 * «γράψε μόνο όταν αλλάζει κελί». Δύο μονοπάτια εγγραφής θα ήταν δύο φύλακες που αποκλίνουν.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-cell-drag-session
 * @see ui/table-cell-editor/use-table-cell-pointer.ts — ποιος την ξεκινά, και με τι γεωμετρία
 * @see bim/table/table-cell-range.ts — τι σημαίνει η κάθε επιλογή (`TableSelectionKind`)
 * @see systems/navigation/drag-edge-autopan.ts — η άκρη· γιατί δεν είναι scroll αλλά pan
 */

import { setTableCellSelection } from '../../state/table-cell-cursor-store';
import { setTableDragSpan } from '../../state/table-drag-span-store';
import {
  edgeAutoPanSample,
  startDragEdgeAutoPan,
  stopDragEdgeAutoPan,
} from '../../systems/navigation/drag-edge-autopan';
import type {
  TableCellRef,
  TableSelectionKind,
  TableSelectionSpan,
} from '../../bim/table/table-cell-range';

/** Ό,τι χρειάζεται η χειρονομία για να ζήσει. Καμία γνώση γεωμετρίας — τη δίνει ο καλών. */
export interface TableCellDragStart {
  /**
   * Η γωνία που **ΜΕΝΕΙ** — και είναι το κελί εκκίνησης, όχι το κελί απελευθέρωσης.
   * Τεκμηριωμένη συμπεριφορά Excel: μετά τη σύρση `A1→F1`, ενεργό κελί παραμένει το `A1`.
   */
  readonly anchor: TableCellRef;
  /** Τι διαλέγει αυτή η σύρση — κελιά, ολόκληρες στήλες ή ολόκληρες γραμμές. */
  readonly kind: TableSelectionKind;
  /**
   * «Πού βρίσκομαι **τώρα**;» — από σημείο οθόνης σε ταυτότητα κελιού· `null` έξω από το
   * πλέγμα. Ζει στον καλούντα επειδή **μόνο εκείνος** ξέρει τη ζωντανή προβολή, τη γωνία
   * του πίνακα και τη διάταξη. Καλείται **μία φορά ανά κίνηση**.
   */
  readonly resolveAt: (event: MouseEvent) => TableCellRef | null;
  /**
   * 🔴 §27.16 Ε1 — το δοχείο του καμβά· **η μόνη** γνώση που χρειάζεται η άκρη.
   *
   * **Υποχρεωτικό, χωρίς προεπιλογή**, με τον ίδιο λόγο που το `kind` είναι υποχρεωτικό
   * (§27.15): ένας γραφέας που το ξεχνά θα έπαιρνε σιωπηλά σύρση **χωρίς** auto-pan — δηλαδή
   * ακριβώς το κενό που κλείνει εδώ, ξαναγεννημένο χωρίς να το πει κανείς.
   */
  readonly container: HTMLElement;

  /**
   * 🔴 ADR-754 §5 — **τι γράφεται σε κάθε αλλαγή κελιού**· προεπιλογή: η επιλογή του δρομέα.
   *
   * ## Γιατί έγινε παράμετρος — γενίκευση, όχι δεύτερη μηχανή
   * Η **υπόδειξη κελιού** (`=` + σύρσιμο ⇒ `=SUM(A1:B5`) είναι η **ίδια ακριβώς χειρονομία**:
   * κουμπί κάτω, ακολούθα το χέρι, γράψε μόνο όταν αλλάζει κελί, συνέχισε στην άκρη με
   * auto-pan, τερμάτισε στο `mouseup` **όπου κι αν γίνει**. Ένας δεύτερος βρόχος `mousemove`
   * γι' αυτήν θα ήταν structural clone ολόκληρου του κύκλου ζωής (N.18 / CHECK 3.28) — και,
   * χειρότερα, δεύτερος φύλακας «γράψε μόνο όταν αλλάζει κελί», δηλαδή δεύτερη ευκαιρία να
   * ξαναγεννηθεί το κόστος του ADR-735.
   *
   * Αλλάζει **μόνο ο παραλήπτης**: εκεί μαρκάρονται κελιά, εδώ γράφονται χαρακτήρες μέσα σε
   * τύπο. Η υπόδειξη **δεν επιτρέπεται** να γράψει επιλογή δρομέα: θα φώτιζε κελιά που ο
   * χρήστης δεν διάλεξε και θα άλλαζε σιωπηλά το αντικείμενο του επόμενου `Ctrl+C`.
   *
   * ⚠️ **Προαιρετική, με ρητή προεπιλογή** — σε αντίθεση με τα υποχρεωτικά `kind`/`container`
   * από πάνω, και η διαφορά είναι μετρήσιμη: εκεί ο γραφέας που ξεχνά παίρνει **λάθος**
   * συμπεριφορά (κούμπωμα που δεν ζήτησε, σύρση χωρίς άκρη)· εδώ παίρνει την **ιστορική και
   * σωστή** συμπεριφορά, που είναι αυτό που θέλουν και οι τρεις υπάρχουσες χειρονομίες.
   */
  readonly write?: (span: TableSelectionSpan) => void;

  /**
   * 🔴 ADR-754 Γ4 — **τι γίνεται στο `mouseup`**· απόν ⇒ τίποτα, που είναι το σωστό για κάθε
   * χειρονομία **επιλογής**: εκεί η κατάσταση γράφεται ήδη συνεχώς και η απελευθέρωση δεν
   * προσθέτει τίποτα.
   *
   * ## Γιατί το χρειάστηκε η **λαβή συμπλήρωσης** και όχι οι τρεις πρώτες
   * Οι τρεις πρώτες γράφουν **κατάσταση διεπαφής** (επιλογή) ή **πρόχειρο κειμένου** — και τα
   * δύο είναι αναστρέψιμα και ασήμαντα ανά κίνηση. Η συμπλήρωση γράφει **μοντέλο**, δηλαδή
   * παράγει βήμα undo: γραμμένη ανά κίνηση, μια σύρση δέκα γραμμών θα άφηνε δέκα βήματα
   * αναίρεσης για **μία** χειρονομία. Άρα η σύρση δείχνει **υπόσχεση** (store προεπισκόπησης)
   * και η απελευθέρωση **εκτελεί** — ίδια δομή με τη μεταφορά περιοχής (§36.15: «το `mouseup`
   * εκτελεί το σχέδιο που τροφοδοτούσε το φάντασμα»).
   *
   * ⚠️ Καλείται **μία φορά**, και μόνο από τον φυσικό τερματισμό (`mouseup`, ή κουμπί που
   * αφέθηκε εκτός παραθύρου). Ένα `endTableCellDrag()` από αλλού —αποπροσάρτηση συνεδρίας,
   * νέα χειρονομία που κλείνει την προηγούμενη— **δεν** το τρέχει: εκεί η χειρονομία
   * **ακυρώθηκε**, και μια ακύρωση που γράφει μοντέλο είναι το χειρότερο είδος έκπληξης.
   */
  readonly onEnd?: () => void;

  /**
   * 🔴 ADR-739 §69 — **τι μέγεθος ανακοινώνει αυτή η χειρονομία** στο πλαίσιο ονόματος·
   * `null` από τη συνάρτηση ⇒ καμία ένδειξη σε αυτό το καρέ.
   *
   * ## Γιατί συνάρτηση και όχι σκέτο `boolean`
   * Επειδή για **μία** από τις τέσσερις χειρονομίες το εύρος που σέρνεται **δεν είναι** το
   * εύρος που πιάνει ο χρήστης, και η διαφορά είναι ορατή στην οθόνη. Η λαβή συμπλήρωσης
   * σέρνει από τη **γωνία της λαβής** προς το χέρι — δηλαδή το span της είναι η **διαδρομή
   * του χεριού**, ενώ ο χρήστης βλέπει (και θα πάρει) την **προεπισκόπηση γεμίσματος**, που
   * περιλαμβάνει και την πηγή. Ένα `boolean` θα ανακοίνωνε `3R x 1C` ενώ το περίγραμμα
   * δείχνει `4R x 1C`: το πλαίσιο ονόματος θα διαφωνούσε με το ίδιο του το καρέ.
   *
   * ## Γιατί ΥΠΟΧΡΕΩΤΙΚΟ, χωρίς προεπιλογή
   * Ο ίδιος ακριβώς λόγος με τα {@link TableCellDragStart.kind} και
   * {@link TableCellDragStart.container}: ο γραφέας που το ξεχνά θα έπαιρνε σιωπηλά σύρση
   * **χωρίς ένδειξη** — δηλαδή ακριβώς το κενό που κλείνει εδώ, ξαναγεννημένο χωρίς να το
   * πει κανείς. Οι τρεις χειρονομίες που ανακοινώνουν το ίδιο εύρος που σέρνουν περνούν την
   * κοινή {@link TABLE_DRAG_SIZE_AS_DRAGGED}, όχι τρία πανομοιότυπα inline lambdas.
   */
  readonly sizeReadout: (span: TableSelectionSpan) => TableSelectionSpan | null;
}

/**
 * 🔴 ADR-739 §69 — «**ανακοινώνω ό,τι σέρνω**», η απάντηση των τριών από τις τέσσερις.
 *
 * Εξαγόμενη σταθερά και όχι `(span) => span` γραμμένο τρεις φορές: τρία αντίγραφα μιας
 * γραμμής δεν πιάνονται από το jscpd (κάτω από τα 50 tokens) και **αποκλίνουν σιωπηλά** —
 * το ίδιο ακριβώς επιχείρημα που γέννησε το `extendTableSelectionTo` (§27.16 Ε2).
 */
export const TABLE_DRAG_SIZE_AS_DRAGGED = (span: TableSelectionSpan): TableSelectionSpan => span;

/** Οι ακροατές της τρέχουσας σύρσης· `null` όταν δεν σέρνεται τίποτα. */
let activeTeardown: (() => void) | null = null;

/**
 * Ξεκινά σύρση επιλογής. Ιδεμποτής ως προς την προηγούμενη: μια νέα χειρονομία **κλείνει**
 * την προηγούμενη αντί να προστεθεί σε αυτήν — δύο ταυτόχρονες σύρσεις δεν υπάρχουν.
 */
export function startTableCellDrag(start: TableCellDragStart): void {
  if (typeof document === 'undefined') return;
  endTableCellDrag();

  // Η αφετηρία: το ίδιο το κελί της άγκυρας. Ο φύλακας «άλλαξε κελί;» ξεκινά από εδώ, ώστε
  // η πρώτη κίνηση **μέσα** στο ίδιο κελί να μη γράψει τίποτα.
  let lastCell: TableCellRef = start.anchor;
  /** ADR-754 §5 — ο παραλήπτης, λυμένος **μία** φορά· δες το {@link TableCellDragStart.write}. */
  const write = start.write ?? setTableCellSelection;
  /**
   * 🔴 ADR-739 §69 — η ανακοίνωση μεγέθους, από τον **ίδιο** ένα δρόμο με την εγγραφή.
   *
   * Γράφεται **αμέσως στο πάτημα**, πριν κουνηθεί το χέρι: το Excel δείχνει `1R x 1C` από τη
   * στιγμή που πατάς, όχι από τη στιγμή που φτάνεις σε δεύτερο κελί. Δεν αντιφάσκει με το
   * «καμία επιλογή ≠ επιλογή 1×1» (§27.15): εκείνο μιλά για το τι **μαρκάρεται**, αυτό για
   * το τι **ανακοινώνεται** — και ένα σκέτο κλικ σβήνει την ανακοίνωση στο `mouseup` χωρίς
   * ποτέ να έχει γράψει επιλογή.
   */
  const announce = (span: TableSelectionSpan): void => {
    setTableDragSpan(start.sizeReadout(span));
  };
  announce({ from: start.anchor, to: start.anchor, kind: start.kind });
  /**
   * Το τελευταίο συμβάν κίνησης — **η θέση του χεριού**, όχι η θέση στον κόσμο.
   *
   * §27.16 Ε1: το auto-pan το χρειάζεται επειδή ο δείκτης μπορεί να μένει **ακίνητος** πάνω
   * στην άκρη επ' άπειρον, οπότε δεν έρχεται κανένα νέο `mousemove` — και ακριβώς τότε το
   * κάδρο πρέπει να συνεχίσει. `null` πριν την πρώτη κίνηση: σκέτο πάτημα στην άκρη **δεν**
   * μετακινεί τίποτα (Excel: η αυτόματη κύλιση ξεκινά όταν σέρνεις, όχι όταν πατάς).
   */
  let lastEvent: MouseEvent | null = null;

  /**
   * «Πού φτάνει τώρα η επιλογή;» — ο **ΕΝΑΣ** δρόμος, για **δύο** αφορμές: κίνησε το χέρι,
   * ή κίνησε ο κόσμος (auto-pan). Ο φύλακας ζει εδώ, άρα ισχύει και για τις δύο.
   */
  const applyAt = (event: MouseEvent): void => {
    const cell = start.resolveAt(event);
    // Έξω από το πλέγμα: η επιλογή **μένει** εκεί που έφτασε. Ίδια σύμβαση με το `Shift+βέλος`
    // στην άκρη — ποτέ αναδίπλωση, ποτέ σβήσιμο από παραδρομή του χεριού.
    if (!cell) return;
    if (cell.rowId === lastCell.rowId && cell.colId === lastCell.colId) return;
    lastCell = cell;
    const span = { from: start.anchor, to: cell, kind: start.kind };
    // ADR-754 §5 — ο **ίδιος** φύλακας και ο ίδιος κύκλος ζωής για δύο παραλήπτες.
    write(span);
    // 🔴 §69 — και ο **τρίτος**: πίσω από τον ίδιο φύλακα «άλλαξε κελί;», άρα η ανακοίνωση
    // κοστίζει όσο και η εγγραφή — μηδέν καρέ ανά pixel κίνησης (ADR-735).
    //
    // ⚠️ **Η ΣΕΙΡΑ ΕΙΝΑΙ ΣΥΜΒΟΛΑΙΟ, ΟΧΙ ΤΥΧΑΙΑ**: το `announce` τρέχει **μετά** το `write`,
    // γιατί μια χειρονομία επιτρέπεται να ανακοινώνει κάτι που το `write` της μόλις
    // υπολόγισε. Η λαβή συμπλήρωσης το κάνει ακριβώς αυτό — ανακοινώνει την **προεπισκόπηση
    // γεμίσματος**, που γεννιέται μέσα στο δικό της `write`. Αντεστραμμένη, η ένδειξη θα
    // έμενε ένα κελί πίσω σε κάθε καρέ της σύρσης.
    announce(span);
  };

  const onMove = (event: MouseEvent): void => {
    // Το κουμπί αφέθηκε εκτός παραθύρου (ή το `mouseup` χάθηκε): τερμάτισε. Χωρίς αυτό, η
    // επιλογή θα ακολουθούσε τον κέρσορα **χωρίς πατημένο κουμπί** — μια σύρση-φάντασμα που
    // ο χρήστης δεν μπορεί να σταματήσει.
    if ((event.buttons & 1) === 0) {
      finish();
      return;
    }
    lastEvent = event;
    applyAt(event);
  };

  /**
   * 🔴 ADR-754 Γ4 — ο **φυσικός** τερματισμός: ξηλώνει τους ακροατές **και** εκτελεί το
   * {@link TableCellDragStart.onEnd}. Χωριστός από το {@link endTableCellDrag}, γιατί εκείνο
   * καλείται και ως **ακύρωση** (αποπροσάρτηση, νέα χειρονομία) — και μια ακύρωση δεν
   * επιτρέπεται να γράψει μοντέλο.
   *
   * Η σειρά είναι υποχρεωτική: **πρώτα** ξηλώνονται οι ακροατές. Το `onEnd` γράφει τη σκηνή,
   * δηλαδή παράγει συμβάντα· ακροατής που ζει ακόμη θα τα άκουγε ως συνέχεια της σύρσης.
   */
  const finish = (): void => {
    const done = start.onEnd;
    endTableCellDrag();
    done?.();
  };

  const onUp = (): void => finish();

  document.addEventListener('mousemove', onMove);
  document.addEventListener('mouseup', onUp);
  // §27.16 Ε1 — η άκρη. Το auto-pan δεν ξέρει τίποτα για κελιά: του δίνουμε «πού είναι το
  // χέρι» και μας λέει «το κάδρο μετακινήθηκε, ξαναρώτα».
  startDragEdgeAutoPan({
    sample: () => (lastEvent ? edgeAutoPanSample(lastEvent, start.container) : null),
    onPanned: () => {
      if (lastEvent) applyAt(lastEvent);
    },
  });
  activeTeardown = (): void => {
    document.removeEventListener('mousemove', onMove);
    document.removeEventListener('mouseup', onUp);
    stopDragEdgeAutoPan();
  };
}

/** Τερματίζει τη σύρση **χωρίς** να αγγίξει την επιλογή. Ιδεμποτής. */
export function endTableCellDrag(): void {
  activeTeardown?.();
  activeTeardown = null;
  // 🔴 ADR-739 §69 — η ανακοίνωση σβήνει **εδώ** και όχι στο `finish()`, δηλαδή και στην
  // **ακύρωση** (αποπροσάρτηση συνεδρίας, νέα χειρονομία που κλείνει την προηγούμενη). Ο
  // διαχωρισμός των δύο τερματισμών υπάρχει επειδή μια ακύρωση δεν επιτρέπεται να γράψει
  // **μοντέλο** (ADR-754 Γ4)· αυτό εδώ δεν είναι μοντέλο, είναι ένα κείμενο έξι χαρακτήρων
  // — και αν έμενε, το πλαίσιο ονόματος θα κρατούσε για πάντα το `2R x 2C` μιας σύρσης που
  // κανείς δεν ολοκλήρωσε.
  setTableDragSpan(null);
}

/** Σέρνεται κάτι αυτή τη στιγμή; Μόνο για tests και για τον φύλακα αποπροσάρτησης. */
export function isTableCellDragActive(): boolean {
  return activeTeardown !== null;
}
