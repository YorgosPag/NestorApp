'use client';

/**
 * 🔴 ADR-753 §25.6 — **ΠΟΙΟΣ ΚΑΤΕΧΕΙ ΤΟ ΠΛΗΚΤΡΟΛΟΓΙΟ, ΚΑΙ ΠΟΙΟΣ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΤΟΥ ΤΟ ΠΑΡΕΙ.**
 *
 * Το ελάττωμα, ακριβώς: πατάς «Έντονα» με το **ποντίκι**, η εστίαση μεταφέρεται στο κουμπί, και
 * το `Enter` που πατάς περιμένοντας να **δεσμεύσεις το κελί** ξαναπατά το κουμπί (toggle OFF).
 *
 * ## 🔴 Η ΕΝΤΑΣΗ ΛΥΘΗΚΕ ΜΕ ΜΕΤΡΗΣΗ, ΟΧΙ ΜΕ ΠΡΟΤΙΜΗΣΗ
 * Η προφανής θεραπεία — `preventDefault` στο `mousedown` — φαινόταν να συγκρούεται με τον
 * χρήστη **πληκτρολογίου**: ο `useRovingToolbar` υπάρχει ακριβώς για να μπαίνει κανείς στη
 * γραμμή με `Tab` και να κινείται με βέλη, και εκεί η εστίαση στο κουμπί είναι **σωστή** — το
 * WAI-ARIA APG ορίζει ρητά ότι σε `role="toolbar"` τα `Enter`/`Space` ενεργοποιούν το
 * χειριστήριο. Οι δύο απαιτήσεις μοιάζουν αντίθετες, και η βιβλιογραφία τις έχει καταγράψει
 * **και τις δύο** ως αιτήματα στο ίδιο έργο (Quill #4752: «μη μου παίρνεις την εστίαση από τον
 * επεξεργαστή» · Quill #1869: «η εστίαση οφείλει να μείνει στο κουμπί για τον χρήστη
 * πληκτρολογίου»).
 *
 * **Δεν είναι αντίθετες. Μετρήθηκε ζωντανά (2026-08-11, πραγματικό Chrome, το ίδιο κουμπί):**
 *
 * ```
 *   πραγματικό κλικ  →  mousedown(detail:1) → focusin(κουμπί) → mouseup → click(detail:1)
 *   Enter στο κουμπί →  keydown(Enter)      → click(detail:0) → keyup
 *                       ^^^^^^^^^^^^^^^^^^^^ ΚΑΝΕΝΑ mousedown
 * ```
 *
 * Η ενεργοποίηση με πληκτρολόγιο **δεν εκδίδει `mousedown`** — είναι η *synthetic activation
 * behavior* του HTML, που παράγει σκέτο `click`. Άρα ένας φρουρός τοποθετημένος στο `mousedown`
 * είναι **δομικά αδύνατο** να αγγίξει τη διαδρομή του πληκτρολογίου: εκεί το συμβάν πάνω στο
 * οποίο κάθεται **δεν υπάρχει**. Η ερώτηση «ποιος το δήλωσε, ποντίκι ή `Tab`;» απαντιέται από
 * το ίδιο το event model, χωρίς σημαία, χωρίς `:focus-visible`, χωρίς ανίχνευση τρόπου.
 *
 * (Το `detail` δίνει **δεύτερο**, ανεξάρτητο διακριτικό — `1` για pointer, `0` για πληκτρολόγιο
 * — και γι' αυτό δεν χρειάζεται: θα ήταν δεύτερη απάντηση στο ίδιο ερώτημα.)
 *
 * ## 🔑 ΠΟΥ ΠΑΜΕ ΠΑΝΩ ΑΠΟ ΤΟΥΣ ΜΕΓΑΛΟΥΣ: ο φρουρός είναι **υπό όρο**
 * ProseMirror, Quill και Slate βάζουν **άνευ όρων** `preventDefault` στο `mousedown` της
 * γραμμής τους. Αυτό είναι λάθος σε μια μετρήσιμη περίπτωση: όταν **κανένα** πεδίο δεν κρατά
 * το πληκτρολόγιο, δεν υπάρχει εστίαση να διατηρηθεί — και η άνευ όρου αποτροπή αφήνει το
 * κουμπί **μη εστιάσιμο με ποντίκι**, δηλαδή αφαιρεί άγκυρα εστίασης από χρήστη αναγνώστη
 * οθόνης χωρίς κανένα αντάλλαγμα. Εδώ ο φρουρός ρωτά πρώτα: *υπάρχει εστίαση που αξίζει να
 * διατηρηθεί;* Τρεις καταστάσεις, καμία σιωπηλή:
 *
 * | Ποιος έχει το πληκτρολόγιο | Τι κάνει ο φρουρός | Γιατί |
 * |---|---|---|
 * | **πεδίο** της συνεδρίας (κελί ή γραμμή τύπων) | αποτρέπει | ο χρήστης γράφει· δεν ζήτησε να φύγει |
 * | **κουμπί** της γραμμής (roving με `Tab`/βέλη) | αφήνει | APG: η γραμμή κατέχει ήδη το πληκτρολόγιο |
 * | κανείς (καμβάς, `body`) | αφήνει | δεν υπάρχει τι να διατηρηθεί· το κουμπί οφείλει να εστιαστεί |
 *
 * ## 🔴 ΚΑΜΙΑ ΝΕΑ ΕΡΩΤΗΣΗ — η αυθεντία είναι ήδη γραμμένη
 * Το «κατέχει **πεδίο** της συνεδρίας το πληκτρολόγιο;» **δεν** ξαναγράφεται εδώ: το απαντά το
 * {@link activeTableCellSessionCaret}, που είναι ήδη ο ΕΝΑΣ ορισμός και του οποίου η
 * τεκμηρίωση προβλέπει **κατά λέξη** αυτή τη χρήση — «*ένα μελλοντικό τρίτο μέλος της
 * συνεδρίας (π.χ. κουμπί μενού) φέρει το ίδιο σημάδι και **δεν** έχει κέρσορα — εκεί η σωστή
 * απάντηση είναι `null`*». Δηλαδή ξεχωρίζει **πεδίο** από **κουμπί** χωρίς να χρειαστεί δεύτερο
 * κατηγόρημα. Ένα `isTableCellSessionElement(document.activeElement)` **θα ήταν λάθος** εδώ:
 * τα κουμπιά φορούν κι εκείνα το σημάδι της συνεδρίας, οπότε θα απαντούσε «ναι» στη γραμμή του
 * roving και θα πάγωνε την εστίαση στο **προηγούμενο** κουμπί.
 *
 * ## ⚠️ ΓΙΑΤΙ ΑΥΤΟ ΔΕΝ ΑΝΑΙΡΕΙ ΤΗΝ ΑΠΟΡΡΙΨΗ ΤΟΥ `table-cell-session-focus.ts`
 * Εκείνο απορρίπτει ρητά το `onMouseDown preventDefault` **στα κουμπιά της κορδέλας**, με λόγο
 * «*θα άλλαζε εστίαση και προσβασιμότητα σε ολόκληρη την κορδέλα — ~700 κουμπιά — για χάρη δύο
 * καρτελών*». Η απόρριψη **ισχύει ακέραιη**· απλώς δεν αφορά αυτή την επιφάνεια. Μετρημένο με
 * grep: το `ToolbarButton` του mini toolbar εισάγεται από **έξι** αρχεία, **όλα** μέσα στον
 * φάκελο `table-format-toolbar/`, και η κορδέλα ζωγραφίζει τα δικά της κουμπιά
 * (`ribbon/components/buttons/ribbon-icon-table.tsx`). Καμία κορδέλα δεν περνά από εδώ.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-cell-keyboard-ownership
 * @see ui/table-cell-editor/table-cell-session-focus.ts — ΠΟΙΟΣ ανήκει στη συνεδρία (ταυτότητα)
 * @see ui/components/table-format-toolbar/ToolbarButton.tsx — ο κύριος καταναλωτής
 * @see ui/table-cell-editor/table-text-selection.ts — ο φρουρός «εστιασμένο ⇒ σιωπή» (§1.5)
 */

import { activeTableCellSessionCaret } from './table-cell-session-focus';

/**
 * Ό,τι χρειάζεται ο φρουρός από ένα συμβάν — και **τίποτα** παραπάνω.
 *
 * Δομικός τύπος και όχι `React.MouseEvent`: ο ίδιος φρουρός πρέπει να μπορεί να μπει και σε
 * ωμό ακροατή του DOM (τα πάνελ που δεν περνούν από React props), και μια δήλωση δεμένη με το
 * React θα γεννούσε **δεύτερη** εκδοχή του για εκείνη τη διαδρομή.
 */
export interface PreventableEvent {
  preventDefault(): void;
}

/**
 * Κρατά **πεδίο κειμένου** της συνεδρίας το πληκτρολόγιο αυτή τη στιγμή;
 *
 * `!== null` και όχι έλεγχος αληθοφάνειας: ο κέρσορας στη **θέση 0** είναι απολύτως έγκυρος
 * και θα διαβαζόταν ως «κανείς» — δηλαδή ο φρουρός θα σιωπούσε ακριβώς όταν ο χρήστης γράφει
 * στην αρχή του κελιού.
 */
export function tableCellFieldOwnsKeyboard(): boolean {
  return activeTableCellSessionCaret() !== null;
}

/**
 * 🔴 Ο φρουρός του `mousedown`: **το πάτημα του ποντικιού δεν μετακινεί το πληκτρολόγιο.**
 *
 * Μπαίνει στο `mousedown` και **όχι** στο `click`: η μεταφορά της εστίασης είναι η
 * *προεπιλεγμένη ενέργεια* του `mousedown`, δηλαδή έχει ήδη συμβεί μέχρι να εκδοθεί το `click`.
 * Είναι ο ίδιος λόγος για τον οποίο το §26.15 τεκμηριώνει ότι «*ό,τι εστιάσουμε μέσα στο
 * `mousedown` το ξεεστιάζει ο ίδιος ο browser αμέσως μετά*» — εδώ απλώς δεν του δίνουμε ποτέ
 * την ευκαιρία, αντί να παλεύουμε μαζί του ένα καρέ αργότερα.
 *
 * ⚠️ **Δεν** κάνει `stopPropagation`: το πάτημα οφείλει να φτάσει στους φύλακες που
 * παρακολουθούν τη **χειρονομία** (η λήξη των δηλώσεων του `installClaimExpiry`, ο φύλακας
 * `keepOpenOnToolbar` του Radix). Ο φρουρός αφαιρεί **μία** προεπιλεγμένη ενέργεια, δεν
 * καταπίνει το συμβάν.
 */
export function keepTableCellKeyboardOwnership(event: PreventableEvent): void {
  if (!tableCellFieldOwnsKeyboard()) return;
  event.preventDefault();
}

/**
 * 🔴 Η **συμμετρική** πράξη: επιστροφή εστίασης που **δεν κλέβει**.
 *
 * Το κλείσιμο ενός πτυσσόμενου πάνελ επιστρέφει την εστίαση στον trigger του — σωστό κατά APG,
 * και απαραίτητο για τον χρήστη πληκτρολογίου, που αλλιώς μένει σε στοιχείο που μόλις
 * ξεμόνταρε (η εστίαση πέφτει στο `body` και το επόμενο `Tab` ξεκινά από την αρχή της σελίδας).
 *
 * Μόλις όμως ο φρουρός από πάνω αρχίσει να κρατά το πληκτρολόγιο στο πεδίο, η **ίδια** γραμμή
 * γίνεται κλοπή: ο χρήστης ποντικιού δεν έδωσε ποτέ την εστίαση στον trigger, οπότε μια
 * «επιστροφή» εκεί τη **μετακινεί** — και ξαναγεννά το §25.6 από δεύτερη πόρτα. Δηλαδή η
 * διόρθωση του ενός μονοπατιού θα έσπαγε σιωπηλά το άλλο.
 *
 * Ίδια αρχή, γραμμένη ήδη δύο φορές στο έργο: «*η εστίαση γυρίζει **μόνο αν την είχε** η
 * γραμμή*» ({@link restoreFocus} του `use-table-text-toolbar.ts`) και «*εστιασμένο πεδίο ⇒
 * σιωπή*» ({@link restoreTableTextSelection}). Τρίτη περίπτωση, **ένας** κανόνας.
 */
export function focusUnlessTableCellFieldOwnsKeyboard(target: HTMLElement | null): void {
  if (tableCellFieldOwnsKeyboard()) return;
  target?.focus();
}
