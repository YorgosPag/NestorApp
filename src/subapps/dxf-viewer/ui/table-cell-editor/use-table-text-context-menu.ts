'use client';

/**
 * ADR-739 §67 — **ο ΕΝΑΣ χειριστής δεξιού κλικ των δύο πεδίων της συνεδρίας.**
 *
 * ## Το ελάττωμα που κλείνει (αναφορά ιδιοκτήτη, 10/08)
 * Μέσα σε λειτουργία **γραφής** κελιού, το δεξί κλικ έδειχνε το **native** μενού του browser
 * («Emoji», «Αναίρεση», «Ορθογραφικός έλεγχος»). Η αιτία είναι δομική και όχι ξεχασμένο
 * `preventDefault`: ο δρομολογητής δεξιού κλικ ζει σε capture πάνω στον `containerRef` του
 * καμβά, ενώ τα δύο πεδία κειμένου ζουν στο `CanvasSectionOverlays` — **αδελφό** του
 * `CanvasLayerStack`, δηλαδή **εκτός** εκείνου του δοχείου. Το συμβάν δεν περνούσε ποτέ από
 * εκεί που θα το σταματούσε κάποιος.
 *
 * ⚠️ Σε **πλοήγηση** δεν υπήρχε ποτέ ελάττωμα, και ο λόγος εξηγεί γιατί κανείς δεν το είδε
 * νωρίτερα: εκεί το κέλυφος του επεξεργαστή φέρει `pointer-events-none`
 * ({@link TextEditorAnchorLayer}), άρα το δεξί κλικ πέφτει στον καμβά και ανοίγει κανονικά το
 * μενού περιοχής. Η βλάβη γεννιέται **ακριβώς** τη στιγμή που το κουτί γίνεται πατήσιμο.
 *
 * ## 🔴 Γιατί ΕΝΑΣ χειριστής και όχι δύο `onContextMenu` inline
 * Είναι το ίδιο μοτίβο με το {@link useTableCellSessionBlur}: ό,τι αφορά **και τα δύο** πεδία
 * της συνεδρίας ζει σε ένα σημείο, αλλιώς η πρώτη αλλαγή κανόνα θα εφαρμοστεί στο ένα και θα
 * ξεχαστεί στο άλλο — και η απόκλιση είναι αόρατη όσο κάθε πλευρά δουλεύει.
 *
 * ## 🔴 Το `preventDefault` είναι ΥΠΟ ΟΡΟ, και ο όρος είναι το άνοιγμα
 * Καταναλώνουμε το συμβάν **μόνο** όταν η θύρα δηλώσει ότι άνοιξε μενού. Χωρίς τον όρο, μια
 * στιγμή χωρίς ζωντανή συνεδρία (ή ένα ξεμονταρισμένο μενού) θα έδινε δεξί κλικ που **δεν
 * κάνει τίποτα** — και το «τίποτα» είναι χειρότερο από το native, γιατί ο χρήστης δεν έχει
 * τρόπο να μάθει ότι κάτι πήγε στραβά.
 *
 * ⚠️ **Καμία `stopPropagation`.** Το συμβάν γεννιέται σε στοιχείο εκτός του καμβά, άρα δεν
 * υπάρχει ανταγωνιστής να αποκλειστεί — και μια σιωπή εδώ θα ήταν ο τρίτος ακροατής που
 * κανείς δεν θυμάται όταν προστεθεί ο τέταρτος.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/use-table-text-context-menu
 * @see ui/table-cell-editor/table-text-menu-port.ts — γιατί θύρα και όχι νέα προτεραιότητα
 * @see ui/table-cell-editor/use-table-text-menu.ts — ο ιδιοκτήτης που την γεμίζει
 */

import { useCallback, type MouseEvent } from 'react';
import { getTableTextMenuPort } from './table-text-menu-port';
import type { TableTextField } from '../components/table-text-menu/table-text-toolbar-types';

/**
 * Ο χειριστής `onContextMenu` που φορούν **και τα δύο** πεδία κειμένου της συνεδρίας.
 *
 * Σταθερή ταυτότητα (`useCallback` χωρίς εξαρτήσεις): η θύρα διαβάζεται τη **στιγμή του
 * συμβάντος**, ποτέ ως στιγμιότυπο απόδοσης — ADR-040 κανόνας #2, ο ίδιος που τηρούν και οι
 * τρεις αδελφές θύρες μέσα στον δρομολογητή του καμβά.
 */
export function useTableTextContextMenu(): (event: MouseEvent<TableTextField>) => void {
  return useCallback((event: MouseEvent<TableTextField>) => {
    if (getTableTextMenuPort()?.open(event.clientX, event.clientY, event.currentTarget)) {
      event.preventDefault();
    }
  }, []);
}
