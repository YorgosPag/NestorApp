/**
 * ADR-739 Φ.Δ βήμα 6 — **ο φύλακας της μονής γραμμής.**
 *
 * ## Γιατί γεννήθηκε ΤΩΡΑ ένας φύλακας που δεν χρειαζόταν ποτέ
 * Μέχρι το βήμα 5 ο επεξεργαστής ήταν `<input>`, που **δεν δέχεται** αλλαγή γραμμής: μια
 * επικόλληση πολυγραμμικού κειμένου έμπαινε ισοπεδωμένη, δωρεάν, από τον ίδιο τον browser.
 * Το βήμα 6 το έκανε `<textarea>` (χρειάζεται δεύτερη **οπτική** γραμμή) — και μαζί
 * κληρονόμησε τη δυνατότητα να κρατά πραγματικά `\n`.
 *
 * Το `TableCell.value` όμως είναι **απλό `string`** (τεκμηριωμένη απόφαση, ADR-739 Φ.Α):
 * ένας χαρακτήρας ελέγχου εκεί μέσα ταξιδεύει στη διάταξη (που τον μετρά σαν γράμμα), στο
 * PDF και στο DXF — δηλαδή σε **παραδοτέο σχέδιο** που άλλα προγράμματα διαβάζουν.
 *
 * Η **οπτική** αναδίπλωση του επεκτεταμένου κουτιού είναι άσχετη με αυτό: εκείνη ζει στο
 * CSS και δεν αγγίζει την τιμή. Το ένα είναι εμφάνιση, το άλλο δεδομένα.
 */

import { flattenToSingleLine } from '../TableCellEditorOverlay';

describe('flattenToSingleLine — καμία αλλαγή γραμμής δεν φτάνει στο μοντέλο', () => {
  it('κείμενο χωρίς αλλαγές γραμμής μένει ΑΓΓΙΧΤΟ (καμία «καθαριότητα» εκ των υστέρων)', () => {
    const text = 'ΠΕΡΙΓΡΑΦΗ  ΕΡΓΑΣΙΑΣ 12,50 m²';
    expect(flattenToSingleLine(text)).toBe(text);
  });

  it('η αλλαγή γραμμής γίνεται ΚΕΝΟ — ποτέ δεν κολλάνε δύο λέξεις', () => {
    expect(flattenToSingleLine('ΠΡΩΤΗ\nΔΕΥΤΕΡΗ')).toBe('ΠΡΩΤΗ ΔΕΥΤΕΡΗ');
  });

  it('το `\\r\\n` των Windows μετρά ΜΙΑ φορά — αλλιώς κάθε επικόλληση θα άφηνε διπλά κενά', () => {
    expect(flattenToSingleLine('ΠΡΩΤΗ\r\nΔΕΥΤΕΡΗ')).toBe('ΠΡΩΤΗ ΔΕΥΤΕΡΗ');
  });

  it('κενή γραμμή στο πρωτότυπο δεν είναι περιεχόμενο', () => {
    expect(flattenToSingleLine('ΠΡΩΤΗ\n\n\nΔΕΥΤΕΡΗ')).toBe('ΠΡΩΤΗ ΔΕΥΤΕΡΗ');
  });

  it('🔴 ΤΟ ΣΕΝΑΡΙΟ: επικόλληση στήλης από Excel ⇒ μία γραμμή, κανένας χαρακτήρας ελέγχου', () => {
    const pasted = 'ΣΚΥΡΟΔΕΜΑ C20/25\r\nΞΥΛΟΤΥΠΟΣ\r\nΟΠΛΙΣΜΟΣ B500C';
    const flat = flattenToSingleLine(pasted);
    expect(flat).toBe('ΣΚΥΡΟΔΕΜΑ C20/25 ΞΥΛΟΤΥΠΟΣ ΟΠΛΙΣΜΟΣ B500C');
    expect(/[\r\n]/u.test(flat)).toBe(false);
  });

  it('κενό αλφαριθμητικό ⇒ κενό (το άδειασμα κελιού δεν γίνεται κενό διάστημα)', () => {
    expect(flattenToSingleLine('')).toBe('');
  });
});
