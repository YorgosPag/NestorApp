/**
 * Οι **δομικές** πράξεις της καρτέλας «Ιδιότητες Πίνακα».
 *
 * Ξεχωριστό υπο-αντικείμενο και όχι επτά ακόμη μέθοδοι στο ίδιο επίπεδο: απαντούν σε άλλη
 * ερώτηση («τι σχήμα έχει ο πίνακας») και έχουν άλλη προϋπόθεση — η μορφοποίηση χρειάζεται
 * **στόχο** (δρομέα), η αλλαγή στυλ χρειάζεται μόνο **επιλεγμένη οντότητα**. Ο διαχωρισμός
 * κάνει τη διαφορά ορατή στον τύπο αντί να ζει σε σχόλιο.
 */
export interface TableStructurePort {
  /** Το ενεργό ονοματισμένο στυλ του πίνακα· `null` χωρίς πίνακα. */
  readonly styleId: () => string | null;
  /** Αλλάζει στυλ — μία εντολή, ένα `Ctrl+Z`, καμία απώλεια παρακάμψεων. */
  readonly setStyleId: (styleId: string) => void;
  /**
   * Εισαγωγή γραμμής/στήλης **γύρω από τον στόχο του δρομέα** — η ίδια σημασιολογία με το
   * δεξί κλικ στη ζώνη δείκτη (§27.17: ολόκληρη η επιλογή, αν είναι του ίδιου είδους).
   */
  readonly insertAxis: (axis: 'row' | 'column', side: 'before' | 'after') => void;
  readonly deleteAxis: (axis: 'row' | 'column') => void;
  /** Επιτρέπεται η διαγραφή; (ο πίνακας δεν μένει ποτέ χωρίς γραμμή ή στήλη). */
  readonly canDeleteAxis: (axis: 'row' | 'column') => boolean;
  /**
   * 🔴 ADR-739 §58 Γ2 — **«Αυτόματο ύψος γραμμής»**: σβήνει το ρητό `heightMm` των γραμμών του
   * στόχου, ώστε το ύψος να ξαναπροκύπτει από το περιεχόμενο.
   *
   * Ζει στις **δομικές** πράξεις και όχι στη μορφοποίηση, γιατί απαντά στην ερώτηση «τι σχήμα
   * έχει ο πίνακας» και γράφει σε **γραμμή**, όχι σε κελί — η ίδια διαίρεση που τεκμηριώνει η
   * κεφαλίδα αυτού του υπο-αντικειμένου. Είναι επίσης η θέση του Excel: *Home ▸ Cells ▸ Format
   * ▸ AutoFit Row Height*, δηλαδή ομάδα «Κελιά», όχι «Στοίχιση».
   *
   * ⚠️ Ο **στόχος** είναι ο ίδιος με της «Διαγραφής γραμμής» (§27.17: ο άξονας του δρομέα, ή
   * ολόκληρη η επιλογή αν είναι του ίδιου είδους). Δεύτερος κανόνας εδώ θα σήμαινε ότι το ίδιο
   * μαρκάρισμα δίνει άλλες γραμμές σε δύο κουμπιά που κάθονται δίπλα-δίπλα.
   */
  readonly autoFitRowHeight: () => void;
  /**
   * Υπάρχει **τι** να επαναφερθεί; — `some`, όχι `every` (δες `hasFixedTableRowHeight`).
   *
   * 🏆 Το κουμπί του Excel είναι **πάντα** πατήσιμο και πάντα σιωπηλό, οπότε ο χρήστης δεν
   * μπορεί να μάθει από τη διεπαφή αν η γραμμή που βλέπει είναι καρφωμένη. Εδώ το ίδιο κουμπί
   * **είναι η ένδειξη**.
   */
  readonly canAutoFitRowHeight: () => boolean;
  /** `Ctrl+A` του πίνακα — ο ΕΝΑΣ γραφέας του §43. */
  readonly selectAll: () => void;
}

/**
 * Ό,τι μπορεί να ζητήσει μια επιφάνεια μορφοποίησης πίνακα.
 *
 * Τα `borders` / `merge` περνούν **αυτούσια** τα υπάρχοντα συμβόλαια (ADR-750 / ADR-755): οι
 * πράξεις τους είναι ήδη παραμετρικές ως προς τα **όρια**, οπότε η κορδέλα δεν χρειάζεται
 * τίποτα δικό της — μόνο το {@link TableFormatPort.bounds} να τους δώσει τον στόχο.
 */
export interface TableFormatPort {
  /**
   * Ο πίνακας που αφορούν οι εντολές: ο πίνακας του **δρομέα**, αλλιώς ο **μοναδικός
   * επιλεγμένος**. `null` όταν δεν υπάρχει ούτε το ένα ούτε το άλλο.
   *
   * Η σειρά έχει σημασία και είναι η σειρά του Excel: μόλις μπεις σε κελί, οι εντολές
   * αφορούν **αυτόν** τον πίνακα, ακόμη κι αν η επιλογή οντοτήτων λέει κάτι άλλο.
   */
  readonly table: () => TableEntity | null;
  /** Πού γράφει η **μορφοποίηση**· `null` χωρίς δρομέα ή σε μπαγιάτικη επιλογή. */
  readonly scope: () => TableFormatScope | null;
  /** Ο ίδιος στόχος ως **ορθογώνιο** — ό,τι δέχονται περιγράμματα και συγχώνευση. */
  readonly bounds: () => TableCellRangeBounds | null;
  /** Τι δείχνει ένα χειριστήριο· `null` όταν δεν υπάρχει στόχος (⇒ σβηστό, ποτέ μαντεψιά). */
  readonly state: <K extends TableCellStyleKey>(
    key: K,
  ) => TableFormatState<TableCellStyle[K]> | null;
  /**
   * Οι **τέσσερις** ερωτήσεις ενός πεδίου χρώματος (§34/§35), για την ίδια παλέτα.
   *
   * ⚠️ Δεν παίρνει `PlotColorRole`: ο ρόλος **προκύπτει** από το πεδίο (`textColorHex` ⇒ μελάνι,
   * `fillColorHex` ⇒ γέμισμα) και τον ξέρει ήδη το στιγμιότυπο. Μια δεύτερη παράμετρος θα ήταν
   * ευκαιρία να ζητηθεί «χρώμα κειμένου με ρόλο γεμίσματος» — κατάσταση που δεν σημαίνει
   * τίποτα, και που θα έδινε λάθος «χρώματα του σχεδίου» χωρίς κανένα σφάλμα.
   */
  readonly colorState: (key: 'textColorHex' | 'fillColorHex') => TableAxisColorState;
  /**
   * Πάτημα δίτιμου χειριστηρίου. Ο κανόνας «**μεικτό ⇒ όλα ναι**» ζει **μέσα** (μέσω
   * `nextBooleanFormat`) και όχι στον καλούντα: με δύο επιφάνειες να τον εφαρμόζουν, η μία
   * θα μπορούσε κάποτε να μάθει «αντίστροφη» σημασιολογία και η οθόνη δεν θα το έδειχνε.
   */
  readonly toggle: (key: TableToggleFormatKey) => void;
  /** Ρητή τιμή / `null` ρητά κανένα / `undefined` αφαίρεση — οι τρεις καταστάσεις αυτούσιες. */
  readonly setField: <K extends keyof TableAxisStyleOverride>(
    key: K,
    value: TableAxisStyleOverride[K] | undefined,
  ) => void;
  readonly stepTextHeight: (direction: TextHeightStepDirection) => void;
  /** Το τρέχον ύψος κειμένου σε sheet-mm· `null` όταν τα κελιά δεν συμφωνούν ή δεν υπάρχει στόχος. */
  readonly textHeightMm: () => number | null;
  /**
   * 🔴 ADR-739 §56 / ADR-760 — **τι μορφή αριθμού ισχύει** στον στόχο.
   *
   * ## Γιατί ΔΙΚΟ ΤΟΥ μέλος και όχι `state('numberFormat')`
   * Δεν **γίνεται**: το {@link TableFormatPort.state} δέχεται `TableCellStyleKey`, που είναι η
   * τομή `keyof TableAxisStyleOverride & keyof TableCellStyle` — και το `numberFormat` ζει μόνο
   * στο πρώτο σκέλος, επειδή έχει **δική του** αλυσίδα κληρονομιάς (κελί▸γραμμή▸στήλη▸
   * `valueType`). Είναι ο ίδιος αποκλεισμός που τεκμηριώνει ήδη το `table-format-payload.ts`,
   * και η ίδια αιτία που το χρώμα χρειάστηκε το {@link TableFormatPort.colorState}: όταν η
   * ερώτηση δεν χωρά στο γενικό λεξιλόγιο, αποκτά δικό της μέλος αντί να παραμορφωθεί.
   *
   * Χωρίς στόχο ⇒ `EMPTY_TABLE_NUMBER_FORMAT_STATE` (κανένα κουμπί πατημένο), ποτέ μαντεψιά.
   * ⚠️ Η **εγγραφή** δεν αποκτά μέλος: το `setField('numberFormat', …)` δουλεύει ήδη, γιατί
   * εκείνο δέχεται `keyof TableAxisStyleOverride` — το ευρύτερο από τα δύο σκέλη.
   */
  readonly numberFormat: () => TableNumberFormatState;
  /**
   * 🔴 ADR-739 §58 Γ2 — **τι ξεχείλισμα ισχύει** στον στόχο· `null` = ανάμεικτο **ή** χωρίς στόχο.
   *
   * ## Γιατί ΔΙΚΟ ΤΟΥ μέλος — και γιατί ΔΥΟ, όχι ένα
   * Ούτε η ανάγνωση ούτε η εγγραφή χωρούν στα γενικά μέλη, και για **δύο διαφορετικούς** λόγους
   * που τυχαίνει να δείχνουν στο ίδιο πεδίο:
   * ```
   *   state('overflow')     ✗  δέχεται TableCellStyleKey — το `overflow` ΔΕΝ είναι στο TableCellStyle
   *   setField('overflow')  ✗  δέχεται keyof TableAxisStyleOverride — το `overflow` ΔΕΝ είναι εκεί
   * ```
   * Το `numberFormat` χρειάστηκε **ένα** μέλος ακριβώς επειδή αποκλειόταν μόνο από το πρώτο (η
   * γραφή του δούλευε ήδη). Το ξεχείλισμα αποκλείεται και από τα δύο άκρα, γιατί ζει **μόνο**
   * στο `TableCellStyleOverride` — το στενότερο σκέλος και των δύο τομών.
   *
   * ⚠️ Η σύμπτωση «ανάμεικτο» ≡ «χωρίς στόχο» είναι η **ίδια** που κωδικοποιεί ήδη το
   * {@link numberFormat}, και έχει την ίδια θεραπεία στην κορδέλα: ο φύλακας `scope()` πριν την
   * ανάγνωση, αλλιώς τα δύο κουμπιά γίνονται indeterminate για επιλογή που δεν υπάρχει (§56 β).
   */
  readonly overflow: () => TableCellOverflow | null;
  /**
   * Γράφει το ξεχείλισμα. Δέχεται την **τελική** τιμή: ο κανόνας «ίδια ⇒ ξεπάτωμα» ζει στο
   * `bim/table/table-overflow-ops.ts`, που ρωτούν **και οι δύο** επιφάνειες — ίδια ακριβώς
   * διαίρεση με τη στοίχιση.
   *
   * 🔑 Η **αμοιβαία αποκλειστικότητα** αναδίπλωσης/σμίκρυνσης δεν επιβάλλεται εδώ και δεν
   * χρειάζεται: την κάνει **μη εκφράσιμη** ο τύπος `TableCellOverflow` (ένωση, ποτέ δύο σημαίες).
   */
  readonly setOverflow: (value: TableCellOverflow) => void;
  /**
   * 🔴 ADR-739 §56 — **ποιες γραμματοσειρές υπάρχουν**, τη στιγμή της κλήσης.
   *
   * Getter και όχι συνδρομή, για τον λόγο που το τεκμηριώνει ήδη το `use-toolbar-font-names.ts`:
   * ο κάτοχος της θύρας ζει μέσα στον `CanvasSection`, όπου κάθε συνδρομή είναι re-render του
   * orchestrator (ADR-040 κανόνας #1). Η **γνώση** μένει μία (`collectAvailableFontNames`) — εδώ
   * περνά μόνο το κανάλι, ώστε η κορδέλα να μη χρειαστεί δεύτερη πρόσβαση στον `levelManager`.
   */
  readonly fontNames: () => readonly string[];
  readonly reset: () => void;
  /** Υπάρχει **οτιδήποτε** να επαναφερθεί; (`some`, όχι `every` — δες `canResetTableFormatScope`.) */
  readonly canReset: () => boolean;
  /**
   * 🔴 ADR-739 §60 — **ΤΟ «ΟΚ» ΕΝΟΣ ΔΙΑΛΟΓΟΥ**: ένα έτοιμο μοντέλο, ένα `Ctrl+Z`.
   *
   * ## Γιατί υπάρχει, και γιατί είναι το **μόνο** νέο μέλος της Φάσης Ε
   * Κάθε άλλο μέλος εδώ δέχεται **πρόθεση** («κάνε το έντονο») και παράγει μία εντολή. Ένας
   * διάλογος με «ΟΚ / Άκυρο» δουλεύει αντίστροφα: επεξεργάζεται **προσχέδιο** και παραδίδει το
   * αποτέλεσμα **μία** φορά. Δεκαπέντε αλλαγές μέσα στον διάλογο = ένα βήμα αναίρεσης, όπως στο
   * Excel — και το «Άκυρο» είναι σκέτη απόρριψη μιας τοπικής μεταβλητής.
   *
   * ## 🔴 ΜΕΤΑΚΟΜΙΣΕ, ΔΕΝ ΓΕΝΝΗΘΗΚΕ (N.0.2)
   * Ζούσε ως `borders.commitModel` από το ADR-750 Φ6, και **ποτέ δεν ήταν πράξη
   * περιγραμμάτων**: δεν παίρνει μολύβι, δεν ξέρει ακμές, δεν αγγίζει το `table-edges`. Ήταν
   * εκεί επειδή ο πρώτος διάλογος του έργου τύχαινε να είναι ο διάλογος περιγραμμάτων. Με
   * **δεύτερο** διάλογο, δύο μέλη με το ίδιο σώμα σε δύο υπο-αντικείμενα θα ήταν δύο πόρτες
   * προς την ίδια ουρά — και η μέρα που η μία μάθαινε φύλακα (π.χ. «μη γράφεις σε κλειδωμένο
   * κελί») θα άφηνε την άλλη πίσω, σιωπηλά.
   *
   * 🔴 **ΔΙΟΡΘΩΣΗ §63 — εδώ έγραφε ότι γράφει στον πίνακα «του δρομέα», και αυτό ήταν το
   * ελάττωμα, όχι η προδιαγραφή.** Η αιτιολόγηση ήταν: *«ένα προσχέδιο γεννιέται πάντα από στόχο
   * μορφοποίησης, και στόχος υπάρχει μόνο μέσα σε συνεδρία κελιού»*. Η προκείμενη είναι αληθής
   * στη **γέννηση** και ψευδής στη **δέσμευση**: από το ADR-750 Φ6β ο διάλογος είναι
   * **αιωρούμενος**, άρα ζει πέρα από τη συνεδρία που τον γέννησε. Ο συλλογισμός ήταν σωστός για
   * modal και δεν ξαναεξετάστηκε όταν έπαψε να είναι modal.
   *
   * Πλέον δέχεται **ρητά τον στόχο** και γράφει σε **αυτόν**: το `target.entityId` λέει ποιος
   * πίνακας και το `target.model` είναι η **βάση σύγκρισης** ενός compare-and-swap. Οι τρεις
   * σιωπηλές καταστάσεις που έκλεισαν — και γιατί η σειρά των φρουρών είναι το συμβόλαιο — στο
   * `bim/table/table-format-commit-plan.ts`.
   *
   * ⚠️ **Επιστρέφει το πλάνο, ποτέ `void`.** Ένα «ΟΚ» που δεν μπορεί να αποτύχει *ορατά* είναι
   * ένα «ΟΚ» που αποτυγχάνει *σιωπηλά*: ο διάλογος έκλεινε ούτως ή άλλως και ο χρήστης πίστευε
   * ότι εφάρμοσε. Ο καλών **οφείλει** να κρίνει την απάντηση.
   *
   * 🔑 Περνά από την **ίδια** ουρά με κάθε άλλη πράξη, οπότε ο φύλακας του no-op by-reference
   * ισχύει: «άνοιξα, πείραξα, το ξαναέφερα όπως ήταν, ΟΚ» **δεν** γεννά βήμα αναίρεσης — και
   * πλέον το λέει **ρητά** (`status: 'unchanged'`) αντί να μη συμβαίνει τίποτα.
   */
  readonly commitModel: (
    target: FormatTarget,
    model: PersistedTableModel,
  ) => TableFormatCommitPlan;
  /**
   * 🔴 ADR-739 §60 — **η ΑΦΕΤΗΡΙΑ ενός προσχεδίου**: μοντέλο + στυλ + στόχος + χρώματα σχεδίου,
   * σε μία ερώτηση, **τη στιγμή που ο χρήστης πατά** (ADR-040 κανόνας #2).
   *
   * ## Γιατί ο **υπάρχων** `FormatTarget` και όχι νέο σχήμα
   * Είναι ακριβώς ό,τι κατασκευάζουν ήδη και οι τρεις υποδοχές μορφοποίησης, με τον ίδιο κανόνα
   * «τι διάλεξε ο χρήστης → πού γράφεται» (§52). Ένα `{bounds, model, style}` — όπως το παλιό
   * `borders.resolveDialogTarget` — θα ήταν **δεύτερη** απάντηση στο ίδιο ερώτημα και θα έχανε
   * το `scope`, δηλαδή τη διαφορά ανάμεσα σε «γράψε στα κελιά» και «γράψε στη στήλη». Ο
   * διάλογος γράφει **στυλ**: χωρίς `scope` θα ισοπέδωνε κάθε μαρκαρισμένη στήλη σε κελιά.
   *
   * `null` χωρίς δρομέα ⇒ ο διάλογος **δεν ανοίγει**, αντί να ανοίξει πάνω σε φάντασμα.
   */
  readonly formatTarget: () => FormatTarget | null;
  readonly borders: TableBorderActions;
  readonly merge: TableMergeActions;
  readonly structure: TableStructurePort;
  /**
   * 🔴 ADR-767 Δ3 — ο **δεσμός** του πίνακα: «τρέφεται από πηγή;» και «ξαναρώτησέ την».
   *
   * Ξεχωριστό υπο-αντικείμενο για τον ίδιο λόγο που ξεχωρίζει το {@link TableStructurePort}:
   * απαντά σε **άλλη ερώτηση** («από πού ήρθαν τα νούμερα») και έχει **άλλη προϋπόθεση** — η
   * μορφοποίηση θέλει δρομέα, η δομή θέλει δρομέα, ο δεσμός θέλει μόνο **δεμένο πίνακα**.
   */
  readonly binding: TableBindingPort;
  /**
   * 🔴 ADR-768 Βήμα 5 — το **Πινέλο Μορφοποίησης**: «ρούφα τη μορφή» και «σβήσε το πινέλο».
   *
   * Μπαίνει στη θύρα και όχι σε props για τον λόγο που γεννήθηκε η θύρα: το κουμπί ζωγραφίζεται
   * σε **δύο** επιφάνειες — το εφήμερο mini toolbar (μενού δεξιού κλικ) και τη **μόνιμη**
   * κορδέλα. Χωρίς κοινή θύρα, η δεύτερη επιφάνεια θα ήταν δεύτερη υλοποίηση της ίδιας
   * χειρονομίας, με δύο ευκαιρίες να διαφωνήσουν για το τι σημαίνει «διπλό κλικ».
   *
   * ⚠️ Το **βάψιμο** δεν είναι εδώ, και δεν πρόκειται να μπει: γεννιέται από **κλικ στον
   * καμβά**, δηλαδή από ερώτηση που καμία επιφάνεια δεν μπορεί να απαντήσει («σε ποιο κελί
   * έπεσε το χέρι;»). Ζει στο `use-table-format-painter-click.ts`.
   */
  readonly painter: TableFormatPainterPort;
  /**
   * 🔴 ADR-739 §57 — **το πρόχειρο**: αποκοπή, αντιγραφή, και «Επικόλληση Ειδική».
   *
   * ⚠️ Περνά **αυτούσιο** το συμβόλαιο του §54 (`TableMenuClipboardActions`), όπως ακριβώς
   * περνούν αυτούσια τα `borders` / `merge`: οι πράξεις του είναι ήδη παραμετρικές ως προς τα
   * **όρια**, οπότε η κορδέλα δεν χρειάζεται τίποτα δικό της — μόνο το {@link
   * TableFormatPort.bounds} να τους δώσει τον στόχο. Ένα δεύτερο, «για την κορδέλα» συμβόλαιο θα
   * ήταν δεύτερη απάντηση στο «τι σημαίνει αντιγραφή», με το μενού δεξιού κλικ να λέει άλλα.
   *
   * 🔑 Ο λόγος που η **ίδια** θύρα κουβαλά και το πινέλο: στο Excel το «Πινέλο μορφοποίησης»
   * ζει **μέσα** στην ομάδα «Πρόχειρο», και όχι τυχαία — είναι κι αυτό αντιγραφή, απλώς μόνο της
   * όψης. Το §57 τα ξαναενώνει και στη δική μας κορδέλα.
   */
  readonly clipboard: TableMenuClipboardActions;
}

let port: TableFormatPort | null = null;

/**
 * Το κανάλι ειδοποίησης — **version signal** πάνω στο SSoT εργοστάσιο (ADR-294, module
 * `create-external-store`). Χειρόγραφο `Set<() => void>` εδώ θα ήταν η ~100ή αντιγραφή της
 * ίδιας μηχανικής· η κατάσταση που **διαβάζεται** δεν ζει ποτέ μέσα του (δες παραπάνω),
 * οπότε το store κρατά μόνο τον αριθμό έκδοσης.
 */
const revisionStore = createExternalStore<number>(0);

function emit(): void {
  revisionStore.set(revisionStore.get() + 1);
}

/**
 * Ο κάτοχος δηλώνεται όσο είναι μονταρισμένος· `null` τον αποσύρει.
 *
 * ## 🔴 ΕΙΔΟΠΟΙΕΙ ΜΟΝΟ ΟΤΑΝ ΑΛΛΑΖΕΙ Η **ΠΑΡΟΥΣΙΑ** — ΑΛΛΙΩΣ ΕΙΝΑΙ ΑΠΕΙΡΟΣ ΒΡΟΧΟΣ
 *
 * Η ταυτότητα του αντικειμένου-θύρας εξαρτάται από `levelManager` /
 * `getSelectedEntityIds`, δηλαδή από τιμές που **δεν εγγυάται** κανείς ότι είναι σταθερές ανά
 * render του `CanvasSection`. Ένα άνευ όρων `emit()` εδώ κλείνει τον κύκλο:
 *
 * ```
 *   νέα θύρα → emit → re-render του bridge → re-render DxfViewerContent → CanvasSection
 *            → νέα θύρα → emit → …
 * ```
 *
 * Και οι αναγνώστες **δεν το χρειάζονται**: κάθε μέθοδος είναι getter, οπότε μια θύρα με νέα
 * ταυτότητα αλλά ίδιο περιεχόμενο δίνει τις ίδιες απαντήσεις. Ό,τι όντως αλλάζει απάντηση
 * φτάνει από τα δύο ρητά σήματα του εκδότη ({@link notifyTableFormatPort}).
 *
 * Η **παρουσία** είναι η εξαίρεση: `null → θύρα` σημαίνει «υπάρχει πλέον κάποιος να ρωτήσω» και
 * κανένα άλλο σήμα δεν το λέει· χωρίς αυτό το emit, η κορδέλα θα έμενε αδρανής μέχρι το
 * επόμενο πάτημα πλήκτρου.
 *
 * 🔴 **ΔΙΟΡΘΩΣΗ (μετρήθηκε 2026-08-07, ADR-768):** εδώ έγραφε «`null → θύρα` σημαίνει *η συνεδρία
 * πίνακα ξεκίνησε*». **Ψευδές.** Το `useTableFormatActions` καλείται **άνευ όρων**
 * (`hooks/canvas/useCanvasSectionUI.ts:98`), άρα η θύρα υπάρχει όσο ζει ο viewer: η παρουσία της
 * αλλάζει με το **mount του καμβά**, όχι με τη συνεδρία. Το σήμα συνεδρίας είναι ο **δρομέας**,
 * και μόνο αυτός — γι' αυτό ο ιδιοκτήτης κύκλου ζωής του πινέλου (ADR-768 Φ4) είναι το store του
 * δρομέα και όχι αυτή η θύρα. Δεν είναι λεπτομέρεια σχολίου: όποιος το πίστευε θα έγραφε φύλακα
 * «υπάρχει θύρα ⇒ υπάρχει συνεδρία», που είναι **μονίμως αληθής** — δηλαδή κανένας φύλακας.
 */
export function setTableFormatPort(next: TableFormatPort | null): void {
  const presenceChanged = (port === null) !== (next === null);
  port = next;
  if (presenceChanged) emit();
}

/** Ανάγνωση **τη στιγμή** που χρειάζεται — ποτέ στιγμιότυπο σε κλείσιμο. */
export function getTableFormatPort(): TableFormatPort | null {
  return port;
}

/**
 * «Κάτι που βλέπει η θύρα άλλαξε» — ο δρομέας μετακινήθηκε, η επιλογή άλλαξε, ή γράφτηκε νέο
 * μοντέλο. Το **φίλτρο** (τι μετράει ως αλλαγή) ανήκει στον εκδότη, όχι εδώ: αυτό το module
 * δεν ξέρει τι είναι «πρόχειρο κείμενο», και δεν πρέπει να μάθει.
 */
export function notifyTableFormatPort(): void {
  emit();
}

/** Συνδρομή για `useSyncExternalStore`· επιστρέφει την αποδέσμευση. */
export function subscribeTableFormatPort(listener: () => void): () => void {
  return revisionStore.subscribe(listener);
}

/**
 * Ο αριθμός έκδοσης — το **μόνο** στιγμιότυπο που επιτρέπεται να κρατήσει καταναλωτής.
 *
 * Πρωτόγονος επίτηδες: το `Object.is` του `useSyncExternalStore` κάνει τη σύγκριση χωρίς
 * cache υπογραφής, και ένα αντικείμενο-στιγμιότυπο θα ξανα-απέδιδε σε κάθε παλμό ακόμη κι
 * όταν τίποτα δεν άλλαξε.
 */
export function getTableFormatRevision(): number {
  return revisionStore.get();
}

/** Test helper — μηδενισμός μεταξύ tests, ίδιο μοτίβο με τα stores του subapp. */
export function __resetTableFormatPortForTests(): void {
  port = null;
  revisionStore.reset(0);
}
