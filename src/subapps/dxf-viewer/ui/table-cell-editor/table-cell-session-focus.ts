// 🔴 ADR-739 §52 — ΤΟ ΔΕΥΤΕΡΟ ΣΗΜΑΔΙ: «δέσμευσε, αλλά ΜΗ ΜΕ ΚΛΕΙΣΕΙΣ»
// ──────────────────────────────────────────────────────────────────────────────

const KEEPALIVE_MARKER_ATTRIBUTE = 'data-table-session-keepalive';

/**
 * 🔴 Το σημάδι που φορούν τα panels των **contextual καρτελών πίνακα** στην κορδέλα.
 *
 * ## Το ελάττωμα που κλείνει — επαληθευμένο στον κώδικα πριν γραφτεί μία γραμμή
 * Κλικ στο «Β» της κορδέλας **ενώ γράφεις κελί**:
 * `relatedTarget` = κουμπί κορδέλας ⇒ όχι μέλος συνεδρίας ⇒ `onCommit()` (**σωστό**) ⇒ `rAF`
 * ⇒ `activeElement` δεν είναι μέλος **και** δεν υπάρχει δήλωση pointer (τη δήλωση την κάνει
 * μόνο ο καμβάς) ⇒ **`onClose()`**. Δηλαδή ο δρομέας κλείνει, χάνεται το token
 * `table-cell-active`, **και η καρτέλα εξαφανίζεται τη στιγμή που την πατάς**.
 *
 * Και το χειρότερο: το `rAF` μπορεί να τρέξει **πριν** από το `click` (κράτημα >16ms = πάντα),
 * οπότε μια «διόρθωση μετά» — `restartTableCellCursorSession()` μέσα στον χειριστή του click —
 * είναι **δομικά αδύνατη**.
 *
 * ## Γιατί ΤΕΤΑΡΤΗ μορφή και όχι επέκταση του {@link TABLE_CELL_SESSION_MARKER}
 * Τα δύο σημάδια λένε **διαφορετικά πράγματα**, και η διαφορά τους είναι ακριβώς η
 * συμπεριφορά του Excel:
 *
 * ```
 *   TABLE_CELL_SESSION_MARKER      «είμαι μέλος»      → ΜΗ δεσμεύσεις· δεν έφυγες
 *   TABLE_SESSION_KEEPALIVE_MARKER «δεν είμαι μέλος»  → δέσμευσε, αλλά ΜΗ με κλείσεις
 * ```
 *
 * Το πρώτο σε κουμπί κορδέλας θα σήμαινε ότι η γραφή **δεν δεσμεύεται** όταν πατάς «Β» — και
 * το έντονο θα εφαρμοζόταν σε κείμενο που δεν έχει γραφτεί ακόμη. Το Excel δεσμεύει.
 *
 * ❌ **ΑΠΟΡΡΙΦΘΗΚΕ**: `onMouseDown preventDefault` στα κουμπιά της κορδέλας (το κλασικό μοτίβο
 * των combobox). Θα άλλαζε εστίαση και προσβασιμότητα σε **ολόκληρη** την κορδέλα — ~700
 * κουμπιά — για χάρη δύο καρτελών.
 *
 * ⚠️ Το φορούν **μόνο** τα panels που το δηλώνουν (`RibbonPanelDef.keepsTableCellSession`),
 * ώστε το «Αρχική → Γραμμή» να κλείνει κανονικά τη συνεδρία: πατώντας εργαλείο σχεδίασης ο
 * χρήστης **φεύγει** από τον πίνακα, και μια καθολική εξαίρεση θα τον κρατούσε κλειδωμένο.
 */
export const TABLE_SESSION_KEEPALIVE_MARKER = { [KEEPALIVE_MARKER_ATTRIBUTE]: 'true' } as const;

/**
 * Βρίσκεται αυτό το στοιχείο **μέσα** σε ζώνη «μη με κλείσεις»;
 *
 * `closest()` και όχι έλεγχος του ίδιου του στοιχείου, σε αντίθεση με το
 * {@link isTableCellSessionElement}: εκεί η ερώτηση αφορά το `relatedTarget` ενός `blur`, που
 * **είναι** το πεδίο· εδώ αφορά το `document.activeElement` μετά από κλικ σε κορδέλα, που
 * μπορεί να είναι κουμπί βαθιά μέσα σε ένα panel — και το σημάδι μπαίνει στο panel, μία φορά,
 * αντί για ~40 κουμπιά. Ίδια σχέση με το {@link isInsideTableCellSession}: **ένας** ορισμός,
 * δύο εμβέλειες, και ο καλών δηλώνει τι ρωτά.
 */
export function isTableSessionKeepAliveElement(target: EventTarget | null): boolean {
  if (!(target instanceof HTMLElement)) return false;
  return target.closest(`[${KEEPALIVE_MARKER_ATTRIBUTE}="true"]`) !== null;
}

/**
 * 🔴 ADR-739 §26.15 — «το πάτημα του ποντικιού έπεσε **μέσα** στην ίδια συνεδρία».
 *
 * Ζει εδώ και όχι στον pointer γιατί είναι **η ίδια έννοια** με το {@link
 * TABLE_CELL_SESSION_MARKER}: τι μετράει ως «δεν έφυγα». Η μία μορφή της απαντά για
 * **στοιχεία** του DOM, η άλλη για **χειρονομίες** πάνω στον καμβά — όπου δεν υπάρχει
 * στοιχείο να σημαδέψεις, γιατί ο καμβάς **δεν επιτρέπεται** να φέρει το σημάδι (θα κρατούσε
 * τη συνεδρία ζωντανή σε κάθε κλικ οπουδήποτε στο σχέδιο). Δύο ορισμοί σε δύο αρχεία θα
 * ήταν ακριβώς το διπλότυπο που γέννησε αυτό το module.
 */
let pointerDownClaim = false;

/**
 * Ο pointer δηλώνει ότι το τρέχον `mousedown` έπεσε μέσα στη συνεδρία.
 *
 * 🔴 **Η δήλωση αγνοείται όταν κανένα πεδίο της συνεδρίας δεν κρατά την εστίαση**, και αυτό
 * είναι που κάνει τη σημαία **αδύνατο να μπαγιατέψει**: μόνο ένα εστιασμένο πεδίο μπορεί να
 * κάνει `blur`, άρα η δήλωση γεννιέται **μόνο** όταν το blur που θα την καταναλώσει είναι
 * βέβαιο ότι έρχεται — στην ίδια αποστολή συμβάντος, μερικές γραμμές παρακάτω. Χωρίς αυτόν
 * τον όρο θα χρειαζόταν χρονόμετρο λήξης, δηλαδή μαγικός αριθμός· με αυτόν, ο κύκλος ζωής
 * είναι **δομικός**.
 */
export function claimTableCellSessionPointerDown(): void {
  if (!isTableCellSessionElement(document.activeElement)) return;
  installClaimExpiry();
  pointerDownClaim = true;
}

/**
 * 🔴 Η δήλωση ζει όσο **η χειρονομία**, όχι όσο ένα συμβάν.
 *
 * Ήταν «διάβασε-και-σβήσε» — μια γραμμή που φαινόταν αυστηρότερη και ήταν **λάθος**.
 * Μετρημένο ζωντανά (καταγραφή συμβάντων, 2026-08-02): ένα κλικ σε κελί παράγει **δύο**
 * `focusout`, όχι ένα —
 *
 *   `mousedown` → `focusout` (Α) → `focusin` → `focusout` (Β) → `mouseup`
 *
 * το (Α) από το ξαναστήσιμο του πεδίου και το (Β) από τη μεταφορά εστίασης του browser, που
 * είναι **προεπιλεγμένη ενέργεια** και έρχεται τελευταία. Η δήλωση καταναλωνόταν από το (Α)
 * και το (Β) έμενε ορφανό: η συνεδρία επιβίωνε αλλά **έχανε το πληκτρολόγιο** — «ζωντανή
 * αλλά κουφή», διαλείπουσα, 2 στα 3 τρεξίματα.
 *
 * Πλέον λήγει με **νέα είσοδο του χρήστη**, όχι με την πρώτη ανάγνωση:
 *  - **επόμενο `mousedown`** — άλλη χειρονομία ποντικιού, όπου κι αν γίνει· γι' αυτό το κλικ
 *    **έξω** από τον πίνακα εξακολουθεί να κλείνει τη συνεδρία, ακόμα κι αν έγινε σε στοιχείο
 *    που δεν φτάνει ποτέ στον ακροατή του καμβά (κορδέλα, πλευρικός πίνακας)·
 *  - **επόμενο `keydown`** — αλλιώς ένα `Tab` έξω, μετά από κλικ σε κελί, θα ανακτούσε το
 *    πληκτρολόγιο και ο χρήστης **δεν θα μπορούσε να βγει από τον πίνακα**.
 *
 * Φάση **σύλληψης** στο `document`: τρέχει πάντα **πριν** από τον ακροατή του πίνακα (που ζει
 * βαθύτερα, στον καμβά), άρα η σειρά είναι αναλλοίωτα «λήξη → ίσως νέα δήλωση». Δύο ακροατές
 * χαμηλής συχνότητας, μηδέν συνδρομές React, καμία χρονική σταθερά.
 */
let claimExpiryInstalled = false;

function installClaimExpiry(): void {
  if (claimExpiryInstalled || typeof document === 'undefined') return;
  claimExpiryInstalled = true;
  // §27.15 — **μία** λήξη για τις δύο σημαίες: ο κύκλος ζωής είναι ο ίδιος (η χειρονομία),
  // και δύο ξεχωριστές λήξεις θα ήταν το μόνο σημείο όπου θα μπορούσαν να αποκλίνουν.
  const expire = (): void => { pointerDownClaim = false; pointerGestureClaim = false; };
  document.addEventListener('mousedown', expire, { capture: true });
  document.addEventListener('keydown', expire, { capture: true });
}

/** Ισχύει η δήλωση αυτή τη στιγμή; Δεν καταναλώνεται — δες το {@link installClaimExpiry}. */
function hasPointerDownClaim(): boolean {
  return pointerDownClaim;
}

/**
 * 🔴 ADR-739 §27.15 — «**η ΧΕΙΡΟΝΟΜΙΑ ανήκει σε αυτόν τον πίνακα**».
 *
 * ## Γιατί ΔΕΥΤΕΡΗ σημαία και όχι η ίδια με το {@link claimTableCellSessionPointerDown}
 * Οι δύο απαντούν σε **διαφορετικές** ερωτήσεις, και η διαφορά είναι μετρήσιμη σε μία
 * γραμμή: η πρώτη είναι **δεμένη με την εστίαση** (`document.activeElement`), επίτηδες —
 * εκεί ακριβώς στηρίζεται η εγγύηση που την κάνει αδύνατο να μπαγιατέψει: γεννιέται μόνο
 * όταν το `blur` που θα την καταναλώσει είναι **βέβαιο** ότι έρχεται.
 *
 * Η ερώτηση εδώ είναι άλλη: «θα επιτραπεί σε αυτό το πάτημα να **μετακινήσει την
 * οντότητα**;». Η απάντηση δεν επιτρέπεται να εξαρτάται από το ποιος κρατά την εστίαση —
 * ένα πάτημα μέσα στο πλέγμα δεν είναι μετακίνηση πίνακα **ποτέ**, ακόμα κι αν η εστίαση
 * έχει περιπλανηθεί. Με κοινή σημαία, μια χαμένη εστίαση θα σήμαινε «ο πίνακας μετακινείται
 * ενώ ο χρήστης σέρνει για να επιλέξει κελιά» — δηλαδή **αλλοίωση δεδομένων** από χειρονομία
 * επιλογής.
 *
 * ⚠️ Δύο σημαίες, **μία λήξη** ({@link installClaimExpiry}): δεν μπορούν να αποκλίνουν στον
 * κύκλο ζωής τους, που είναι το μόνο σημείο όπου δύο σημαίες θα ήταν επικίνδυνες.
 */
let pointerGestureClaim = false;

/**
 * Ο pointer δηλώνει ότι το τρέχον `mousedown` έπεσε μέσα στο πλέγμα ή στις ζώνες δείκτη
 * **του δικού του** πίνακα. Χωρίς όρο εστίασης — δες το σκεπτικό παραπάνω.
 */
export function claimTableCellPointerGesture(): void {
  installClaimExpiry();
  pointerGestureClaim = true;
}

/**
 * Ανήκει το τρέχον πάτημα σε πίνακα υπό επεξεργασία;
 *
 * Καταναλωτής: η πύλη body-drag του `useCentralizedMouseHandlers` (ADR-560). Είναι η **ίδια**
 * μορφή φύλακα με τον grip-guard που ζει ήδη δίπλα της — «πάτημα σημαδεμένο αλλού δεν
 * μετακινεί ποτέ ολόκληρο το σώμα» — απλώς για δεύτερο σημάδι.
 */
export function isTableCellPointerGestureClaimed(): boolean {
  return pointerGestureClaim;
}

