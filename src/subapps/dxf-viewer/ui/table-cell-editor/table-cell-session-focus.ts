'use client';

/**
 * ADR-739 Φ.Δ βήμα 7 — **ποια στοιχεία του DOM ανήκουν στη συνεδρία επεξεργασίας κελιού**,
 * και τι σημαίνει «έχασα την εστίαση» όταν είναι περισσότερα από ένα.
 *
 * ## 🔴 Γιατί γεννήθηκε αυτό το αρχείο
 * Μέχρι το βήμα 6 υπήρχε **ένα** εστιασμένο πεδίο, το `<textarea>` του κελιού, και το
 * κριτήριο εξόδου ήταν μια γραμμή μέσα στο `handleBlur`:
 *
 *     active.dataset.tableCellCursor !== 'true'  ⇒ κλείσε τον δρομέα
 *
 * Ολόκληρη η λειτουργία Excel (η αποκοπή **43** window listeners, Φ.Δ.4) στηρίζεται σε
 * αυτό: ο δομικός φύλακας `isTextEntryTarget` βλέπει ένα εστιασμένο πεδίο κειμένου και
 * όλοι οι επιταχυντές παραιτούνται. Ένα **δεύτερο** πεδίο — η γραμμή τύπων — σπάει το
 * κριτήριο με τον χειρότερο δυνατό τρόπο: μεταφέροντας την εστίαση εκεί, το κελί κάνει
 * blur, το `handleBlur` δεν αναγνωρίζει τον παραλήπτη, και **κλείνει τον δρομέα** ένα καρέ
 * αργότερα — δηλαδή η γραμμή τύπων θα σκότωνε τη συνεδρία τη στιγμή που την πατάς.
 *
 * Το handoff έθεσε τη διάζευξη ρητά: «είτε να φέρει το σημάδι, είτε να αλλάξει το κριτήριο
 * **ρητά και σε ένα σημείο**». Εδώ γίνονται **και τα δύο**, γιατί είναι το ίδιο πράγμα: το
 * σημάδι γίνεται «ανήκω στη συνεδρία» αντί για «είμαι ο δρομέας», και ζει σε έναν ορισμό
 * που δεν μπορεί να ξαναγραφτεί με ορθογραφικό λάθος.
 *
 * ## Γιατί `relatedTarget` και όχι έλεγχος ένα καρέ αργότερα
 * Το `blur` κουβαλά **ποιος παίρνει** την εστίαση. Αν είναι μέλος της συνεδρίας, δεν
 * συνέβη τίποτα: ούτε έξοδος, ούτε δέσμευση. Ο έλεγχος μετά από `requestAnimationFrame`
 * παραμένει — αλλά **μόνο** για την περίπτωση που η εστίαση δεν πάει πουθενά (κλικ στον
 * καμβά), όπου ο παραλήπτης είναι `null` και η ερώτηση δεν μπορεί να απαντηθεί συγχρόνως.
 *
 * ## 🔴 ADR-739 §26.15 — ΓΙΑΤΙ Ο ΕΛΕΓΧΟΣ ΤΟΥ ΕΝΟΣ ΚΑΡΕ ΔΕΝ ΑΡΚΕΙ (μετρημένο, 11/11)
 *
 * Το βήμα 8 στηρίχθηκε σε μια **δηλωμένη εγγύηση** που δεν υπάρχει: «ένα καρέ μετά το κλικ,
 * το React θα έχει στήσει νέο `<textarea autoFocus>` και ο έλεγχος θα βρει μέλος της
 * συνεδρίας». Ζωντανά, **κάθε** κλικ μέσα στον πίνακα σκότωνε τη λειτουργία — και το πιο
 * διαφωτιστικό: **και το κλικ στο ΙΔΙΟ κελί**, όπου δεν υπάρχει καν μετακίνηση να χαλάσει.
 *
 * Οι δύο αιτίες, και οι δύο **δομικές**:
 *
 *  1. **Στο ίδιο κελί δεν ξαναστήνεται τίποτα.** Το `key` του επεξεργαστή είναι
 *     `entityId:rowId:colId:sessionId`. Κλικ στο ίδιο κελί δεν αλλάζει κανένα από τα
 *     τέσσερα ⇒ το `autoFocus` **δεν ξανατρέχει ποτέ**. Καμία αναμονή δεν το νικά αυτό:
 *     δεν είναι κούρσα, είναι απουσία.
 *  2. **Η μεταφορά της εστίασης είναι η προεπιλεγμένη ενέργεια του `mousedown`**, δηλαδή
 *     τρέχει **μετά** τους ακροατές — ακόμα και μετά τον ακροατή **σύλληψης** του pointer,
 *     ακόμα και μετά από ένα σύγχρονο πέρασμα του React. Ό,τι εστιάσουμε μέσα στο
 *     `mousedown` το **ξεεστιάζει** ο ίδιος ο browser αμέσως μετά.
 *
 * ## Γιατί η λύση ΔΕΝ είναι καμία από τις τρεις προφανείς
 *  - ❌ `preventDefault` στο `mousedown` — είναι το κλασικό μοτίβο (react-select, Downshift,
 *    ProseMirror, φύλλα υπολογισμού σε καμβά) και εδώ **απαγορεύεται**: ο καμβάς είναι ο
 *    ιδιοκτήτης του ποντικιού, και θα έσπαγαν το σύρσιμο λαβών και η μετακίνηση οντότητας.
 *  - ❌ `focus()` μέσα στον χειριστή `blur` — τεκμηριωμένα «παλεύει με τον χρήστη» και
 *    διαφέρει ανά μηχανή (το Firefox αγνοούσε ιστορικά την επανεστίαση στο ίδιο συμβάν).
 *  - ❌ `setTimeout` με μαγικό αριθμό — αντικαθιστά μια κούρσα με μια άλλη.
 *
 * ## Η λύση: **αλλάζει η ερώτηση**, όχι ο χρονισμός
 * Ο φύλακας ρωτούσε μόνο **«ποιος έχει την εστίαση;»** — ερώτηση του DOM, που ένα κλικ στον
 * καμβά απαντά πάντα «κανείς». Τώρα ρωτά **δεύτερο**, μόνο όταν το πρώτο απαντήσει «κανείς»:
 * **«μήπως αυτό το blur το προκάλεσε δικό μου κλικ;»** — ερώτηση που **μόνο ο pointer**
 * μπορεί να απαντήσει, γιατί μόνο αυτός έτρεξε hit-test. Το δηλώνει με το
 * {@link claimTableCellSessionPointerDown}, και ο φύλακας **ανακτά** το πληκτρολόγιο αντί να
 * κλείσει. Καμία εγγύηση χρονισμού: και οι τρεις δυνατές σειρές (React πριν το `blur`, μετά
 * το `blur`, ή μετά το καρέ) καταλήγουν στο ίδιο αποτέλεσμα.
 *
 * 🔴 Και το ουσιώδες: όταν η εστίαση μετακινείται **μέσα** στη συνεδρία, **δεν γίνεται
 * commit**. Αλλιώς ο φρουρός «μία φορά» του `useInlineEditorKeys` θα κλείδωνε στο πρώτο
 * πέρασμα κελί→γραμμή τύπων, και ό,τι έγραφε ο χρήστης μετά **δεν θα δεσμευόταν ποτέ** —
 * σιωπηλή απώλεια πληκτρολόγησης, ακριβώς το είδος σφάλματος που κανένα test κατάστασης
 * δεν δείχνει.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-cell-session-focus
 * @see ui/table-cell-editor/TableCellEditorOverlay.tsx — το πεδίο του κελιού
 * @see ui/table-cell-editor/TableFormulaBar.tsx — το δεύτερο πεδίο της ίδιας συνεδρίας
 * @see lib/a11y/keyboard-scope.ts — γιατί ένα εστιασμένο πεδίο αρκεί για την ιδιοκτησία
 */

import { useCallback, type FocusEvent } from 'react';

/**
 * Το `data-*` γνώρισμα που δηλώνει «ανήκω στη συνεδρία επεξεργασίας κελιού». Απλώνεται σε
 * **κάθε** εστιάσιμο στοιχείο της συνεδρίας.
 *
 * ⚠️ Το όνομα μένει `data-table-cell-cursor` παρότι η σημασία διευρύνθηκε: μια μετονομασία
 * θα ήταν καθαρότερη στα λόγια και θα κόστιζε μια σιωπηλή παλινδρόμηση αν κάποιο σημείο
 * έμενε πίσω. Η σημασία τεκμηριώνεται εδώ· ο ορισμός είναι ένας.
 */
export const TABLE_CELL_SESSION_MARKER = { 'data-table-cell-cursor': 'true' } as const;

/** Το κλειδί του ίδιου γνωρίσματος όπως το βλέπει το `dataset` — ο ΕΝΑΣ ορισμός. */
const SESSION_DATASET_KEY = 'tableCellCursor';

/** Ανήκει αυτό το στοιχείο στη συνεδρία επεξεργασίας κελιού; */
export function isTableCellSessionElement(target: EventTarget | null): boolean {
  return target instanceof HTMLElement && target.dataset[SESSION_DATASET_KEY] === 'true';
}

/**
 * 🔴 ADR-739 §26.15 — «το πάτημα του ποντικιού έπεσε **μέσα** στην ίδια συνεδρία».
 *
 * Ζει εδώ και όχι στον pointer γιατί είναι **η ίδια έννοια** με το {@link
 * TABLE_CELL_SESSION_MARKER}: τι μετράει ως «δεν έφυγα». Η μία μορφή της απαντά για
 * **στοιχεία** του DOM, η άλλη για **χειρονομίες** πάνω στον καμβά — όπου δεν υπάρχει
 * στοιχείο να σημαδέψεις, γιατί ο καμβάς **δεν επιτρέπεται** να φέρει το σημάδι (θα κρατούσε
 * τη συνεδρία ζωντανή σε κάθε κλικ οπουδήποτε στο σχέδιο). Δύο ορισμοί σε δύο αρχεία θα
 * ήταν ακριβώς το διπλότυπο που γέννησε αυτό το module.
 */
let pointerDownClaim = false;

/**
 * Ο pointer δηλώνει ότι το τρέχον `mousedown` έπεσε μέσα στη συνεδρία.
 *
 * 🔴 **Η δήλωση αγνοείται όταν κανένα πεδίο της συνεδρίας δεν κρατά την εστίαση**, και αυτό
 * είναι που κάνει τη σημαία **αδύνατο να μπαγιατέψει**: μόνο ένα εστιασμένο πεδίο μπορεί να
 * κάνει `blur`, άρα η δήλωση γεννιέται **μόνο** όταν το blur που θα την καταναλώσει είναι
 * βέβαιο ότι έρχεται — στην ίδια αποστολή συμβάντος, μερικές γραμμές παρακάτω. Χωρίς αυτόν
 * τον όρο θα χρειαζόταν χρονόμετρο λήξης, δηλαδή μαγικός αριθμός· με αυτόν, ο κύκλος ζωής
 * είναι **δομικός**.
 */
export function claimTableCellSessionPointerDown(): void {
  if (!isTableCellSessionElement(document.activeElement)) return;
  pointerDownClaim = true;
}

/** Διάβασε-και-σβήσε: η δήλωση ισχύει για **ένα** blur, ποτέ για το επόμενο. */
function consumePointerDownClaim(): boolean {
  const claimed = pointerDownClaim;
  pointerDownClaim = false;
  return claimed;
}

/** Test helper — μηδενισμός μεταξύ tests, ίδιο μοτίβο με τα stores. */
export function __resetTableCellSessionFocusForTests(): void {
  pointerDownClaim = false;
}

/**
 * Ο χειριστής `onBlur` κάθε πεδίου της συνεδρίας.
 *
 * Τρεις περιπτώσεις, με **μία** απόφαση η καθεμία:
 *  1. η εστίαση πάει σε **άλλο μέλος** της συνεδρίας ⇒ τίποτα (δεν έφυγες, δεν δέσμευσες)·
 *  2. η εστίαση πάει αλλού ⇒ δέσμευσε, και κλείσε αν ένα καρέ μετά κανένα μέλος δεν την έχει·
 *  3. η εστίαση δεν πάει πουθενά (`null`) ⇒ ίδιο με το (2) — το `null` είναι και η
 *     περίπτωση «το παλιό πεδίο ξεφορτώθηκε ενώ το νέο δεν έχει προλάβει να εστιαστεί»,
 *     γι' αυτό ακριβώς η απόφαση κλεισίματος μένει ένα καρέ αργότερα.
 *
 * ADR-739 §26.15 — και **μία** τέταρτη, που δεν είναι δρόμος εστίασης αλλά χειρονομίας:
 *  4. κανείς δεν έχει την εστίαση ένα καρέ μετά, **αλλά** το blur το προκάλεσε κλικ μέσα
 *     στην ίδια συνεδρία ⇒ **ανάκτηση**, όχι κλείσιμο.
 *
 * ## Η σειρά των δύο ερωτήσεων ΕΙΝΑΙ η προδιαγραφή
 * Πρώτα το DOM («την πήρε κάποιο μέλος;»), μετά η δήλωση («ήταν δικό μου κλικ;»). Ανάποδα, η
 * κάθε επιτυχημένη μετακίνηση θα πλήρωνε ένα περιττό ξαναστήσιμο του πεδίου· έτσι, η ανάκτηση
 * τρέχει **μόνο** όταν όντως λείπει το πληκτρολόγιο. Και το `null` της δήλωσης δεν είναι
 * σιωπή: το κλικ **έξω** από τον πίνακα δεν δηλώνεται ποτέ, άρα κλείνει — που είναι η μισή
 * προδιαγραφή και ελέγχεται ρητά.
 *
 * @param onCommit δέσμευση — ιδεμποτής στον καλούντα
 * @param onClose κλείσιμο συνεδρίας
 * @param onReclaim **ξαναπιάσε το πληκτρολόγιο** χωρίς να αλλάξει τίποτα άλλο — στην πράξη
 *   το `restartTableCellCursorSession`, δηλαδή ο **ίδιος** δρόμος που επαναφέρει την εστίαση
 *   μετά το μενού κεφαλίδων (βήμα 9). Η ανάκτηση περνά από το React (`key` ⇒ νέο
 *   `<textarea autoFocus>`) και **όχι** από ωμό `focus()`: μια επανεστίαση μέσα στον κύκλο
 *   του `blur` παλεύει με τη μεταφορά εστίασης που ο browser δεν έχει ολοκληρώσει ακόμα.
 */
export function useTableCellSessionBlur(
  onCommit: () => void,
  onClose: () => void,
  onReclaim: () => void,
): (event: FocusEvent<HTMLElement>) => void {
  return useCallback(
    (event: FocusEvent<HTMLElement>) => {
      if (isTableCellSessionElement(event.relatedTarget)) return;
      // Καταναλώνεται **συγχρόνως**, μέσα στην ίδια αποστολή συμβάντος που τη γέννησε: έτσι η
      // δήλωση δεν μπορεί να ταξιδέψει σε επόμενο blur, ούτε καν αν το καρέ αργήσει.
      const reclaimable = consumePointerDownClaim();
      onCommit();
      if (typeof requestAnimationFrame === 'undefined') return;
      requestAnimationFrame(() => {
        if (isTableCellSessionElement(document.activeElement)) return;
        if (reclaimable) {
          onReclaim();
          return;
        }
        onClose();
      });
    },
    [onCommit, onClose, onReclaim],
  );
}
