/**
 * Ο χειριστής `onBlur` κάθε πεδίου της συνεδρίας.
 *
 * Τρεις περιπτώσεις, με **μία** απόφαση η καθεμία:
 *  1. η εστίαση πάει σε **άλλο μέλος** της συνεδρίας ⇒ τίποτα (δεν έφυγες, δεν δέσμευσες)·
 *  2. η εστίαση πάει αλλού ⇒ δέσμευσε, και κλείσε αν ένα καρέ μετά κανένα μέλος δεν την έχει·
 *  3. η εστίαση δεν πάει πουθενά (`null`) ⇒ ίδιο με το (2) — το `null` είναι και η
 *     περίπτωση «το παλιό πεδίο ξεφορτώθηκε ενώ το νέο δεν έχει προλάβει να εστιαστεί»,
 *     γι' αυτό ακριβώς η απόφαση κλεισίματος μένει ένα καρέ αργότερα.
 *
 * ADR-739 §26.15 — και **μία** τέταρτη, που δεν είναι δρόμος εστίασης αλλά χειρονομίας:
 *  4. κανείς δεν έχει την εστίαση ένα καρέ μετά, **αλλά** το blur το προκάλεσε κλικ μέσα
 *     στην ίδια συνεδρία ⇒ **ανάκτηση**, όχι κλείσιμο.
 *
 * ADR-739 §52 — και **μία** πέμπτη, που είναι δρόμος εστίασης αλλά προς τα **έξω**:
 *  5. την εστίαση την πήρε κουμπί σε ζώνη «μη με κλείσεις» (κορδέλα: οι δύο contextual
 *     καρτέλες πίνακα) ⇒ **δέσμευσε** (έγινε ήδη) και **ανάκτησε**, ποτέ κλείσιμο.
 *     Δες το {@link TABLE_SESSION_KEEPALIVE_MARKER} για το γιατί δεν αρκεί το σημάδι μέλους.
 *
 * ## Η σειρά των δύο ερωτήσεων ΕΙΝΑΙ η προδιαγραφή
 * Πρώτα το DOM («την πήρε κάποιο μέλος;»), μετά η δήλωση («ήταν δικό μου κλικ;»). Ανάποδα, η
 * κάθε επιτυχημένη μετακίνηση θα πλήρωνε ένα περιττό ξαναστήσιμο του πεδίου· έτσι, η ανάκτηση
 * τρέχει **μόνο** όταν όντως λείπει το πληκτρολόγιο. Και το `null` της δήλωσης δεν είναι
 * σιωπή: το κλικ **έξω** από τον πίνακα δεν δηλώνεται ποτέ, άρα κλείνει — που είναι η μισή
 * προδιαγραφή και ελέγχεται ρητά.
 *
 * @param onCommit δέσμευση — ιδεμποτής στον καλούντα
 * @param onClose κλείσιμο συνεδρίας
 * @param onReclaim **ξαναπιάσε το πληκτρολόγιο** χωρίς να αλλάξει τίποτα άλλο — στην πράξη
 *   το `restartTableCellCursorSession`, δηλαδή ο **ίδιος** δρόμος που επαναφέρει την εστίαση
 *   μετά το μενού κεφαλίδων (βήμα 9). Η ανάκτηση περνά από το React (`key` ⇒ νέο
 *   `<textarea autoFocus>`) και **όχι** από ωμό `focus()`: μια επανεστίαση μέσα στον κύκλο
 *   του `blur` παλεύει με τη μεταφορά εστίασης που ο browser δεν έχει ολοκληρώσει ακόμα.
 */
export function useTableCellSessionBlur(
  onCommit: () => void,
  onClose: () => void,
  onReclaim: () => void,
): (event: FocusEvent<HTMLElement>) => void {
  return useCallback(
    (event: FocusEvent<HTMLElement>) => {
      if (isTableCellSessionElement(event.relatedTarget)) return;
      // Διαβάζεται **συγχρόνως** (η κατάσταση μπορεί να αλλάξει μέχρι το καρέ) αλλά **δεν**
      // καταναλώνεται: ένα κλικ παράγει δύο `focusout`, και η λήξη ανήκει στη χειρονομία.
      const reclaimable = hasPointerDownClaim();
      onCommit();
      if (typeof requestAnimationFrame === 'undefined') return;
      requestAnimationFrame(() => {
        if (isTableCellSessionElement(document.activeElement)) return;
        // 🔴 §52 — η **πέμπτη** περίπτωση: η εστίαση βρίσκεται σε ζώνη «μη με κλείσεις» (τα
        // panels των contextual καρτελών πίνακα). Ο έλεγχος μπαίνει **εδώ**, πριν το
        // `onClose()`, γιατί το `rAF` μπορεί να τρέξει **πριν** από το `click` — διόρθωση μέσα
        // στον χειριστή του κουμπιού θα ήταν πάντα αργοπορημένη. Δες το
        // {@link TABLE_SESSION_KEEPALIVE_MARKER}.
        if (reclaimable || isTableSessionKeepAliveElement(document.activeElement)) {
          onReclaim();
          return;
        }
        onClose();
      });
    },
    [onCommit, onClose, onReclaim],
  );
}
