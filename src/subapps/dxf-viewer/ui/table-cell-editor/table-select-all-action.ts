'use client';

/**
 * 🔴 ADR-739 §43 — **Ο ΕΝΑΣ ΓΡΑΦΕΑΣ ΤΟΥ «ΕΠΙΛΕΞΕ ΤΑ ΠΑΝΤΑ»**.
 *
 * ## Γιατί υπάρχει: τρεις πόρτες, μία εντολή
 * Η ίδια πράξη ζητιέται πλέον από **τρία** ανεξάρτητα σημεία:
 *
 *  1. `Ctrl+A` — `use-table-cell-session-keys` → `useTableRangeActions.selectAll`
 *  2. **αριστερό** κλικ στο τετραγωνάκι της γωνίας — `use-table-cell-pointer` (§43)
 *  3. **δεξί** κλικ στο ίδιο τετραγωνάκι — `use-table-range-menu` (§43, Excel parity)
 *
 * Μέχρι το §43 υπήρχε μία πόρτα, οπότε το σώμα ζούσε σωστά μέσα στο `useCallback` του hook. Με
 * τρεις, ένα δεύτερο `setTableCellSelection` θα ήταν sibling clone που πιάνει το CHECK 3.28
 * (N.18) — αλλά το σοβαρό δεν είναι οι γραμμές: θα ήταν **δεύτερη άποψη για το τι σημαίνει
 * «όλα»**. Την ημέρα που ο ορισμός αλλάξει (π.χ. κρυμμένες γραμμές), οι δύο θα αποκλίνουν και
 * η απόκλιση θα είναι **αόρατη**, γιατί και οι δύο απαντήσεις είναι απολύτως έγκυρες.
 *
 * ## Γιατί ΔΕΝ ζει στο `bim/table/` παρότι μοιάζει καθαρό
 * Γράφει σε store. Το `table-cell-range` είναι καθαρή γεωμετρία/λογική περιοχών και **δεν
 * επιτρέπεται** να μάθει τι είναι «δρομέας» — η ίδια μονόδρομη εξάρτηση που κρατά καθαρό και
 * το `table-indicator-geometry`. Εδώ ζει η **πράξη**· εκεί ο **ορισμός** ({@link
 * tableWholeGridRange}), και αυτή η συνάρτηση απλώς τον εκτελεί.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-select-all-action
 * @see bim/table/table-cell-range.ts — ο ΕΝΑΣ ορισμός του «όλα» (`tableWholeGridRange`)
 * @see bim/table/table-select-all-corner.ts — ΠΟΥ πατιέται (η γωνία)
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §43
 */

import { tableWholeGridRange, type TableCellRangeBounds } from '../../bim/table/table-cell-range';
import { setTableCellCursor, setTableCellSelection } from '../../state/table-cell-cursor-store';
import { tableCursorAt } from '../../bim/table/table-cell-navigation';
import { resolveTableModel } from '../../bim/table/table-model-helpers';
import type { TableEntity } from '../../types/table-entity';
import type { TableModel } from '../../types/table';

/**
 * Μαρκάρει **όλα** τα κελιά αυτού του πίνακα και επιστρέφει τα όρια που γράφτηκαν· `null` σε
 * εκφυλισμένο μοντέλο (μηδέν γραμμές ή μηδέν στήλες), όπου δεν υπάρχει τίποτα να μαρκαριστεί.
 *
 * ## 🔴 Το ενεργό κελί ΔΕΝ μετακινείται — **και αυτό αφορά ΜΟΝΟ την ΕΝΤΟΛΗ**
 * Το `Ctrl+A` **επιλέγει**, δεν πλοηγεί — Excel και Sheets συμφωνούν, και ο ιδιοκτήτης το
 * μέτρησε στην οθόνη (04/08): με ενεργό το `A9`, μετά την «επιλογή όλων» το πλαίσιο ονόματος
 * εξακολουθεί να γράφει **`A9`**, όχι `A1`. Γι' αυτό ακριβώς η επιλογή κρατά **δύο δικές της
 * γωνίες** και δεν αντλεί τη μία από τη θέση του δρομέα — δες το σχόλιο του `selection` στο
 * store.
 *
 * ⚠️ 🔴 **§68.9 (20/08) — Η ΜΕΤΡΗΣΗ ΗΤΑΝ ΤΟΥ ΠΛΗΚΤΡΟΛΟΓΙΟΥ ΚΑΙ ΓΕΝΙΚΕΥΤΗΚΕ ΣΤΟ ΠΟΝΤΙΚΙ.**
 * Μέχρι σήμερα **και οι τρεις** πόρτες καλούσαν αυτή τη συνάρτηση, άρα το πάτημα στη γωνία
 * κληρονομούσε τον κανόνα του `Ctrl+A`. Το πάτημα όμως είναι **χειρονομία**, και κάθε
 * χειρονομία ποντικιού ορίζει **άγκυρα** — δες {@link selectWholeTableFromCorner}. Αυτή η
 * συνάρτηση μένει η **εντολή** και ο κανόνας της είναι ακέραιος.
 *
 * ## Επιστρέφει τα όρια, και δεν είναι διακοσμητικό
 * Ο τρίτος καλών (το **δεξί** κλικ) χρειάζεται **ακριβώς αυτά** τα όρια για να τιτλοφορήσει το
 * μενού που ανοίγει αμέσως μετά. Ένας δεύτερος υπολογισμός τους εκεί θα ήταν η κλασική
 * ρωγμή: το μενού να γράφει `A1:E7` ενώ γράφτηκε κάτι άλλο. Μία πράξη, μία απάντηση.
 */
export function selectWholeTable(model: TableModel): TableCellRangeBounds | null {
  const whole = tableWholeGridRange(model);
  if (!whole) return null;
  setTableCellSelection({
    from: { rowId: model.rows[whole.firstRow].id, colId: model.columns[whole.firstCol].id },
    to: { rowId: model.rows[whole.lastRow].id, colId: model.columns[whole.lastCol].id },
    // ADR-739 §27.15 — **περιοχή**, και το κούμπωμα είναι ταυτοτικό: όλες οι συγχωνεύσεις είναι
    // ήδη μέσα εξ ορισμού. Δεν χρειάζεται τέταρτο είδος «όλα» για να ειπωθεί κάτι που το
    // ορθογώνιο ήδη λέει.
    kind: 'range',
  });
  return whole;
}

/**
 * 🔴 ADR-739 §68.9 — **ΤΟ ΠΑΤΗΜΑ ΣΤΗ ΓΩΝΙΑ**: όλα τα κελιά, **και το ενεργό κελί στο `A1`**.
 *
 * ## Το ελάττωμα, όπως το είδε ο ιδιοκτήτης (20/08, με δύο στιγμιότυπα)
 * Στο Excel το πάτημα στο τετραγωνάκι αφήνει το πλαίσιο ονόματος να γράφει **`A1`**· στο ΝΕΣΤΩΡ
 * έγραφε ό,τι έγραφε πριν (`B2` στο στιγμιότυπο).
 *
 * ## 🔑 Η ΜΕΤΡΗΣΗ ΤΟΥ §43 ΗΤΑΝ ΣΩΣΤΗ — ΚΑΙ ΓΕΝΙΚΕΥΤΗΚΕ ΣΕ ΛΑΘΟΣ ΧΕΙΡΟΝΟΜΙΑ
 * Το §43 μέτρησε ότι *«το `Ctrl+A` επιλέγει, δεν πλοηγεί»* — και είναι αλήθεια. Ύστερα όμως
 * έδωσε **στις τρεις πόρτες τον ίδιο γραφέα**, οπότε ο κανόνας του **πλήκτρου** επιβλήθηκε και
 * στο **ποντίκι**. Δύο διαφορετικές χειρονομίες, ένας κανόνας, καμία μέτρηση για τη δεύτερη.
 *
 * ## 🔴 Η ΑΠΟΔΕΙΞΗ ΕΙΝΑΙ ΜΕΣΑ ΣΤΟ ΙΔΙΟ ΤΟ ΣΥΣΤΗΜΑ, ΟΧΙ ΣΕ ΤΕΚΜΗΡΙΩΣΗ
 * Ο **διπλανός** κλάδος του ίδιου `mousedown` κάνει ήδη το αντίθετο: το {@link selectWholeAxis}
 * (κλικ σε γράμμα στήλης / αριθμό γραμμής) μετακινεί το ενεργό κελί στην **αρχή του άξονα**,
 * με γραμμένη αιτιολογία *«όπως στο Excel: εκεί αρχίζει η πληκτρολόγηση αν συνεχίσεις να
 * γράφεις»*. Δηλαδή για τις **ζώνες** είχε ήδη γίνει δεκτό ότι το ποντίκι ορίζει άγκυρα.
 *
 * ```
 * κλικ στο «B»   ⇒  ενεργό B1   (ήδη έτσι)
 * κλικ στο «3»   ⇒  ενεργό A3   (ήδη έτσι)
 * κλικ στη γωνία ⇒  ενεργό A1   ← έλειπε ΜΟΝΟ αυτό
 * ```
 *
 * Η γωνία είναι η **ίδια κλάση χειρονομίας** με τις δύο από πάνω — απλώς στα δύο άκρα μαζί.
 *
 * ## Γιατί το `A1` είναι ΠΑΝΤΑ ασφαλές, σε αντίθεση με το `B1` του §29.15
 * Το §29.15 πλήρωσε ακριβώς αυτό: το `selectWholeAxis` έβαλε δρομέα στο `B1`, που ήταν
 * **καλυμμένο** από συγχωνευμένο τίτλο ⇒ `findCell` → `undefined` ⇒ `overlay` → `null` ⇒ ο
 * φύλακας του κλειδώματος αποπροσαρτήθηκε **μέσα στο ίδιο commit**. Το `A1` **δεν μπορεί** να
 * είναι καλυμμένο: καμία συγχώνευση δεν ξεκινά πριν από το πάνω-αριστερό κελί, άρα ή είναι
 * σκέτο κελί ή είναι **άγκυρα** συγχώνευσης. Η ασφάλεια είναι δομική, όχι τυχερή.
 *
 * ## Η σειρά είναι το συμβόλαιο
 * `setTableCellCursor` **πρώτα** (διαλύει κάθε επιλογή, τεκμηριωμένο στο store), η επιλογή
 * **μετά** — ταυτόσημο με το {@link selectWholeAxis}. Ανάποδα, η επιλογή θα έσβηνε τη στιγμή
 * που γεννιέται.
 *
 * ⚠️ Ο ΕΝΑΣ ορισμός του «όλα» μένει **ένας**: αυτή η συνάρτηση δεν ξαναγράφει τα όρια, τα ζητά
 * από το {@link selectWholeTable}. Ό,τι αλλάξει αύριο στο «τι σημαίνει όλα» (κρυμμένες γραμμές;)
 * το μαθαίνουν και οι δύο πόρτες δωρεάν.
 */
export function selectWholeTableFromCorner(entity: TableEntity): TableCellRangeBounds | null {
  const model = resolveTableModel(entity.model);
  const whole = tableWholeGridRange(model);
  if (!whole) return null;

  setTableCellCursor(
    entity.id,
    tableCursorAt(model.rows[whole.firstRow].id, model.columns[whole.firstCol].id),
    'nav',
  );
  return selectWholeTable(model);
}
