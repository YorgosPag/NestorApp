'use client';

/**
 * 🔴 ADR-763 Φ2.4 / ADR-754 §3 — **ΠΟΥ ΠΑΕΙ Η ΔΙΕΥΘΥΝΣΗ ΠΟΥ ΜΟΛΙΣ ΕΔΕΙΞΕ Ο ΧΡΗΣΤΗΣ;**
 *
 * Μία ερώτηση, δύο δυνατοί παραλήπτες: το **πρόχειρο του κελιού** (η ιστορική διαδρομή) και,
 * όσο ο διάλογος «Ορίσματα συνάρτησης» είναι ανοιχτός, το **ενεργό κουτί ορίσματος**.
 *
 * ## 🔴 Η ΑΙΤΙΑ ΠΟΥ ΓΕΝΝΗΣΕ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ — δύο συστήματα συντεταγμένων σε μία γραμμή
 * Ο `table-point-mode-pointer` ρωτούσε τον κέρσορα με το `activeTableCellSessionCaret()` και
 * τον μετρούσε πάνω στο `cursor.draft`. Ήταν σωστό όσο **ένα** πεδίο έφερε το σημάδι
 * συνεδρίας. Η Φ2.2 έβαλε το ίδιο σημάδι στα κουτιά ορισμάτων — **υποχρεωτικά**, αλλιώς η
 * μεταφορά εστίασης κλείνει τον δρομέα και ξυπνούν 43 window listeners (ADR-763 §10) — και από
 * εκείνη τη στιγμή ο κέρσορας **του κουτιού** μετριόταν πάνω στο κείμενο **του κελιού**:
 *
 * | κουτί | `caret` | πάνω σε | αποτέλεσμα |
 * |---|---|---|---|
 * | κενό | `0` | `=SUM()` | `0 < bodyStart(1)` ⇒ **`off`** ⇒ το κλικ δεν έγραφε πουθενά |
 * | `CO` | `2` | `=CONCATENATE()` | δείκτης **μέσα στο όνομα** ⇒ διεύθυνση μέσα στη λέξη |
 *
 * Το πρώτο ήταν το ορατό ελάττωμα («δεν καταλαβαίνει ποιο κελί επέλεξα»)· το δεύτερο ήταν το
 * επικίνδυνο, γιατί **γράφει** — σιωπηλά και σε λάθος σημείο.
 *
 * ## 🔑 ΕΝΑ ΠΕΔΙΟ ΟΡΙΣΜΑΤΟΣ ΕΙΝΑΙ ΘΡΑΥΣΜΑ ΤΥΠΟΥ — και γι' αυτό δεν χρειάστηκε δεύτερη μηχανή
 * Το κείμενο ενός κουτιού (`A1`, `A1+`, `SUM(B1:B4)`) είναι **ακριβώς** ό,τι θα υπήρχε στη
 * θέση του μέσα στον τύπο. Βάζοντας μπροστά του το {@link FORMULA_PREFIX} και μετατοπίζοντας
 * τον κέρσορα κατά το μήκος του, ο **υπάρχων** `resolveFormulaPointState` απαντά σωστά χωρίς
 * να μάθει τίποτα: κενό ⇒ `armed` · `A1` ⇒ `liveRef` (το κλικ **αντικαθιστά**) · `A1+` ⇒ ξανά
 * `armed` · σύρσιμο ⇒ `A1:B5` ολόκληρο. Μια δεύτερη, «ελαφριά» γραμματική για τα ορίσματα θα
 * ήταν τρίτος ορισμός του τι είναι αναφορά (N.18) — και θα διαφωνούσε με τα χρωματιστά
 * περιγράμματα που βλέπει ο χρήστης την ίδια στιγμή.
 *
 * Γι' αυτό ο στόχος εκφράζεται **πάντα ως τύπος** ({@link TablePointTarget.formulaText}): ο
 * καταναλωτής δεν έχει κλάδο «είναι όρισμα;», και η αφαίρεση του συνθετικού `=` γίνεται σε
 * **ένα** σημείο — μέσα στον ίδιο τον γραφέα που το πρόσθεσε.
 *
 * ## Γιατί ο γραφέας είναι το `setFunctionArgumentValue` και ΠΟΤΕ το `setTableCellCursorDraftAt`
 * Ο διάλογος έχει **έναν** γραφέα προς το κελί (ADR-763 §15), και είναι εκείνος: γράφει την
 * τιμή **και** ξαναχτίζει το πρόχειρο στην ίδια πράξη. Μια απευθείας εγγραφή προχείρου εδώ θα
 * ήταν δεύτερη διαδρομή — τα κουτιά θα έδειχναν άλλα από το κελί, και το επόμενο πάτημα
 * πλήκτρου θα τα ξανασυμφωνούσε σβήνοντας ό,τι έγραψε το ποντίκι.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-point-target
 * @see ui/table-cell-editor/table-point-mode-pointer.ts — ο ΕΝΑΣ φρουρός που το καταναλώνει
 * @see state/function-arguments-dialog-store.ts — ο ΕΝΑΣ γραφέας του διαλόγου
 * @see docs/centralized-systems/reference/adrs/ADR-763-table-insert-function-dialog.md §21
 */

import { FORMULA_PREFIX } from '../../bim/table/formula/table-formula-lex';
import {
  getFunctionArgumentsDialogState,
  setFunctionArgumentValue,
} from '../../state/function-arguments-dialog-store';
import { focusedFunctionArgumentCaret } from '../dialogs/function-argument-field';
import { activeTableCellSessionCaret } from './table-cell-session-focus';
import { setTableCellCursorDraftAt } from '../../state/table-cell-cursor-store';
import type { TableCellCursorState } from '../../state/table-cell-cursor-store';

/**
 * Ο παραλήπτης μιας υπόδειξης: **τι κείμενο** κρίνεται, **πού** μέσα του κάθεται ο κέρσορας,
 * και **πού** γράφεται το αποτέλεσμα.
 *
 * Το {@link formulaText} είναι **πάντα** πλήρης τύπος (ξεκινά με `=`), ακόμη κι όταν ο
 * πραγματικός ιδιοκτήτης κρατά θραύσμα: το `=` το προσθέτει και το αφαιρεί ο ίδιος ο στόχος.
 * Έτσι ο καταναλωτής μιλά **ένα** σύστημα συντεταγμένων — αυτό του `selectionStart` — και δεν
 * χρειάζεται καμία μετάφραση, δηλαδή δεν υπάρχει σημείο όπου να ξεχαστεί.
 */
export interface TablePointTarget {
  readonly formulaText: string;
  /** Δείκτης χαρακτήρα **μέσα στο {@link formulaText}**. */
  readonly caretIndex: number;
  /** Το αποτέλεσμα, στις ίδιες συντεταγμένες — ο στόχος ξέρει πώς να το ξεδιπλώσει. */
  readonly write: (formulaText: string, caretIndex: number) => void;
}

/**
 * 🔴 **Η ΣΕΙΡΑ ΕΙΝΑΙ Η ΠΡΟΔΙΑΓΡΑΦΗ: ο διάλογος ρωτιέται ΠΡΩΤΟΣ.**
 *
 * Όσο η Φάση 2 είναι ανοιχτή, το `cursor.draft` **δεν χρησιμοποιείται καθόλου** — είναι το
 * κείμενο που ο ίδιος ο διάλογος μόλις έγραψε, και ο κέρσορας που θα το έκρινε ανήκει σε άλλο
 * πεδίο. Ρωτημένος δεύτερος, ο διάλογος θα έπαιρνε απόφαση **ήδη παρμένη** με λάθος δεδομένα.
 *
 * `null` ⇒ κανείς δεν γράφει ⇒ το κλικ σημαίνει ό,τι σήμαινε πάντα. Είναι η **συνηθισμένη**
 * έκβαση και κοστίζει μία ανάγνωση store + μία ανάγνωση DOM.
 */
export function resolveTablePointTarget(cursor: TableCellCursorState): TablePointTarget | null {
  return functionArgumentTarget() ?? cellEditorTarget(cursor);
}

/**
 * Το ενεργό κουτί ορίσματος ως θραύσμα τύπου — ή `null` όταν ο διάλογος δεν είναι ανοιχτός.
 *
 * ## 🔴 §5.3 — ΤΙ ΓΙΝΕΤΑΙ ΟΤΑΝ ΚΑΝΕΝΑ ΚΟΥΤΙ ΔΕΝ ΕΧΕΙ ΤΗΝ ΕΣΤΙΑΣΗ. Ρητή απόφαση:
 * **ο κέρσορας θεωρείται στο τέλος του κειμένου** και η υπόδειξη **γίνεται κανονικά**.
 *
 * Οι δύο εναλλακτικές είναι χειρότερες, και μετρήσιμα:
 *  - «μην κάνεις τίποτα» ⇒ το κλικ αμέσως μετά το άνοιγμα (πριν προλάβει το `autoFocus`, ή
 *    αφού ο χρήστης πατήσει το `⬆`, ή μετά από κλικ στην κάρτα) θα **σιωπούσε** — δηλαδή
 *    ακριβώς το ελάττωμα που η Φ2.4 ήρθε να κλείσει, με άλλη αφορμή.
 *  - «γράψε στην αρχή» ⇒ `A1` + κλικ θα έδινε `B2A1`, δηλαδή σκουπίδι αντί για αντικατάσταση.
 *
 * Το τέλος του κειμένου είναι και **η θέση που κάνει τα σωστά πράγματα δωρεάν**: κενό ⇒
 * `armed`, `A1` ⇒ `liveRef` (αντικατάσταση), `A1+` ⇒ `armed`. Είναι επίσης η θέση όπου
 * βρίσκεται ο κέρσορας μετά από κάθε εγγραφή του ίδιου του διαλόγου.
 */
function functionArgumentTarget(): TablePointTarget | null {
  const state = getFunctionArgumentsDialogState();
  if (!state.open) return null;

  const index = state.activeIndex;
  const value = state.values[index] ?? '';
  // Το `Math.min` δεν είναι παράνοια: το `selectionStart` διαβάζεται από το **DOM**, ενώ το
  // κείμενο από το **store**. Ανάμεσά τους υπάρχει ένα καρέ React, και ένας δείκτης πέρα από
  // το μήκος θα έδινε `off` (`caret > draft.length`) — δηλαδή σιωπηλή απώλεια του κλικ.
  const caret = Math.min(focusedFunctionArgumentCaret(index) ?? value.length, value.length);

  return {
    formulaText: FORMULA_PREFIX + value,
    caretIndex: FORMULA_PREFIX.length + caret,
    // Ο κέρσορας του κουτιού **δεν** γράφεται από εδώ: το `<input>` είναι ελεγχόμενο και ο
    // browser τον φέρνει στο τέλος της νέας τιμής — που είναι ακριβώς εκεί που τον θέλει το
    // Excel μετά από υπόδειξη, ώστε ο επόμενος τελεστής να γράφεται κατευθείαν.
    write: (text) => setFunctionArgumentValue(index, text.slice(FORMULA_PREFIX.length)),
  };
}

/**
 * Η ιστορική διαδρομή, αυτούσια: το πρόχειρο του κελιού κριμένο με τον κέρσορα του
 * **εστιασμένου πεδίου της συνεδρίας** — του `<textarea>` του κελιού ή της γραμμής τύπων.
 *
 * ⚠️ Εδώ το `null` παραμένει **άρνηση**, σε αντίθεση με τα ορίσματα: χωρίς εστιασμένο
 * επεξεργαστή κανείς δεν γράφει τύπο, και το κλικ σε κελί σημαίνει «μετακίνησε τον δρομέα».
 * Είναι η δομική εγγύηση που κρατά την υπόδειξη ανενεργή στο 99% του χρόνου της εφαρμογής.
 */
function cellEditorTarget(cursor: TableCellCursorState): TablePointTarget | null {
  const caretIndex = activeTableCellSessionCaret();
  if (caretIndex === null) return null;
  return { formulaText: cursor.draft, caretIndex, write: setTableCellCursorDraftAt };
}
