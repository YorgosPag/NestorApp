'use client';

/**
 * 🔴 ADR-739 §68 — **ΤΟ ΔΕΞΙ ΚΛΙΚ ΕΓΚΑΘΙΣΤΑ ΤΟΝ ΣΤΟΧΟ ΤΟΥ** (full parity με το Excel).
 *
 * ## Το ελάττωμα, όπως το είδε ο ιδιοκτήτης (2026-08-20, με στιγμιότυπο)
 * Επιλεγμένο το `A1`, δεξί κλικ στο `B2`: το μενού άνοιγε **σωστά** τιτλοφορημένο «Περιγράμματα
 * B2» — και η οθόνη έδειχνε ακόμα μαρκαρισμένο το `A1`. Ο στόχος ήταν σωστός· έλειπε η
 * **μεταβολή** που τον κάνει ορατό. Ο χρήστης έβλεπε δύο πράγματα ταυτόχρονα.
 *
 * ## Γιατί αντιστρέφεται ο κανόνας Α22 — και γιατί ήταν ήδη μισοαντεστραμμένος
 * Το §27.14 έλεγε «*το δεξί σταματά εδώ: δήλωσε και παραδώσου*», και ο Α22 (ADR-750 Φ4) έβγαζε
 * τον στόχο από την **ερώτηση** αντί από τη μεταβολή, με ρητό επιχείρημα: «*η σημασιολογία του
 * Excel, **χωρίς την παρενέργειά του***». Ο ιδιοκτήτης ζήτησε ρητά **full parity** (20/08).
 *
 * 🔑 Και η ίδια απόφαση **είχε ήδη παρθεί μία φορά**: το §43 έσπασε τον ίδιο κανόνα για τη
 * **γωνία**, αφού μετρήθηκε στο πραγματικό Excel (04/08) ότι το δεξί κλικ εκεί *«χάνει την
 * επιλογή σου κι επιλέγει όλο το φύλλο»*. Άρα μέχρι σήμερα οι διαδρομές δεξιού κλικ
 * **διαφωνούσαν μεταξύ τους**: η γωνία έγραφε, το κελί και η ζώνη όχι. Αυτό το module δεν
 * προσθέτει εξαίρεση — **αφαιρεί** μία.
 *
 * ## 🔑 Γιατί η μεταβολή ζει στο `mousedown` και ΟΧΙ στις θύρες των μενού
 * Είναι το σημείο όπου το **αριστερό** κλικ κάνει ήδη ακριβώς την ίδια πράξη. Τρεις συνέπειες,
 * και οι τρεις είναι ορθότητα:
 *
 *  1. **Μία άποψη για το πού πάει ο δρομέας.** Τα δύο πλήκτρα καλούν τους ίδιους γραφείς με τα
 *     ίδια ορίσματα· δεν υπάρχει δεύτερος δρόμος να αποκλίνει.
 *  2. **Το πρόχειρο δεσμεύεται.** Ο `commitPending` υπάρχει **μόνο** εδώ (ζει στο
 *     `useTableCellDoubleClickEditor`, όχι στο `useCanvasSectionUI` όπου ζουν τα μενού). Μια
 *     μεταβολή από τη θύρα του μενού θα μετακινούσε το ενεργό κελί **αφήνοντας πίσω** ό,τι
 *     γραφόταν — σιωπηλή απώλεια πληκτρολόγησης.
 *  3. **Η σειρά είναι εγγυημένη.** Το `mousedown` προηγείται πάντα του `contextmenu`, και ο
 *     κώδικας ήδη στηρίζεται σε αυτό («*τα υπόλοιπα τα κάνει ο δρομολογητής στο `contextmenu`,
 *     που τώρα βρίσκει ζωντανό δρομέα*», §27.14). Όταν το μενού ρωτήσει, η απάντηση είναι ήδη
 *     γραμμένη.
 *
 * ⚠️ Γι' αυτό **καμία** από τις τρεις θύρες μενού δεν άλλαξε κριτήριο: ο Α22 και το
 * `resolveTableAxisActionTarget` απαντούν πλέον «η επιλογή» από μόνα τους, επειδή η επιλογή
 * είναι εκεί. Έπαψαν να είναι ο μηχανισμός και έμειναν **φρουροί** — δες το σχόλιο στην
 * κεφαλίδα του `table-axis-action-target.ts`.
 *
 * ## 🔴 Ο φρουρός `nav`: όσο γράφεται κάτι, το δεξί κλικ ΔΕΝ μετακινεί
 * Μετρημένο στο Excel: με ανοιχτή καταχώριση (`abc` ή `=SUM(`), το δεξί κλικ σε άλλο κελί
 * **δεν** τερματίζει τη γραφή. Και εδώ ο φρουρός δεν είναι ευλάβεια — είναι το ίδιο φράγμα που
 * έχουν ήδη ο ζωγράφος της λαβής συμπλήρωσης και το πιάσιμο περιγράμματος (§36.9 / ADR-754
 * §13.5): *όσο ο χρήστης πληκτρολογεί, το ενεργό κελί δεν είναι χειριστήριο*.
 *
 * ⚠️ **Χωρίς αυτόν θα έτρωγε μισογραμμένους τύπους**: το `tryTablePointModeMouseDown` —
 * ο φρουρός που μετατρέπει το κλικ σε **διεύθυνση** μέσα σε τύπο — βγαίνει στο `event.button
 * !== 0`, δηλαδή **παραιτείται** από το δεξί. Μέχρι σήμερα αυτό ήταν ακίνδυνο επειδή τίποτα
 * δεν ακολουθούσε· από τη στιγμή που το δεξί μετακινεί, θα ήταν η διαδρομή που σβήνει το
 * `=SUM(` χωρίς κανένα σφάλμα πουθενά.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-context-menu-selection
 * @see ui/table-cell-editor/table-range-menu-target.ts — το κριτήριο «είναι ήδη μέσα;»
 * @see ui/table-cell-editor/table-select-all-action.ts — ο ΕΝΑΣ γραφέας του «όλα»
 * @see ui/table-cell-editor/table-pointer-axis-selection.ts — η **τρίτη** διαδρομή (ζώνη
 *      δείκτη): ζει εκεί μαζί με τον γραφέα της· δες {@link tableContextMenuMayMoveSelection}
 */

import { resolveTableModel } from '../../bim/table/table-model-helpers';
import { tableCursorAt } from '../../bim/table/table-cell-navigation';
import { setTableCellCursor } from '../../state/table-cell-cursor-store';
import { selectWholeTableFromCorner } from './table-select-all-action';
import { tableContextMenuMovesSelection } from './table-range-menu-target';
import type { TableCellRef } from '../../bim/table/table-cell-range';
import type { TableCellCursorState } from '../../state/table-cell-cursor-store';
import type { TableEntity } from '../../types/table-entity';
import { activeTableModel } from '../../bim/table/table-worksheet-resolve';

/**
 * Ό,τι χρειάζεται **κάθε** από τις τρεις διαδρομές: ποιος πίνακας, τι ισχύει τώρα, και πώς
 * δεσμεύεται ό,τι γράφεται πριν κουνηθεί το ενεργό κελί.
 *
 * Ο δρομέας περνά **ολόκληρος** και όχι μόνο το `selection`: η ερώτηση «είναι ο στόχος ήδη
 * μέσα;» θέλει **και τη θέση** (δες {@link tableContextMenuMovesSelection}), και ο φρουρός
 * `nav` θέλει το `mode`. Δύο πεδία, ένα όρισμα — αντί για τρία ορίσματα που ο επόμενος
 * καλών θα μπορούσε να συνδυάσει λάθος.
 */
interface TableContextMenuSelectionParams {
  readonly entity: TableEntity;
  readonly cursor: TableCellCursorState;
  /** Δέσμευση ό,τι γράφεται, **πριν** κουνηθεί ο δρομέας (§26.15) — ίδιο συμβόλαιο με το αριστερό. */
  readonly commitPending: () => void;
}

/**
 * 🔴 **Ο ΕΝΑΣ φρουρός `nav`** — δες την κεφαλίδα για το γιατί (τύπος που τρώγεται σιωπηλά).
 *
 * Εξαγόμενος επειδή τον ρωτούν **δύο** modules: εδώ (κελί) και ο ιδιοκτήτης της ζώνης
 * ({@link handleTableBandMouseDown}). Ο δεύτερος δεν μπορεί να κληθεί από εδώ χωρίς **κύκλο
 * εισαγωγών** — το `table-pointer-axis-selection` κατέχει τον γραφέα του άξονα — και ο κύκλος
 * θα ήταν χειρότερος από τη μετακίνηση: **κάθε διαδρομή δηλώνει τη μεταβολή της εκεί όπου ζει
 * ο γραφέας της**, και ο κοινός *κανόνας* γράφεται μία φορά. Εδώ.
 *
 * ⚠️ Ένα δεύτερο `cursor.mode !== 'nav'` γραμμένο με το χέρι στη ζώνη θα ήταν sibling clone
 * (N.18) — αλλά το σοβαρό δεν είναι οι γραμμές: θα ήταν **δεύτερη άποψη** για το πότε ο
 * χρήστης «γράφει», και η μέρα που προστεθεί τέταρτη κατάσταση δρομέα θα τις άφηνε να
 * αποκλίνουν σιωπηλά.
 */
export function tableContextMenuMayMoveSelection(cursor: TableCellCursorState): boolean {
  return cursor.mode === 'nav';
}

/**
 * 🔴 Δεξί κλικ **μέσα στο πλέγμα**: το κελί γίνεται το ενεργό, εκτός αν ήταν ήδη στόχος.
 *
 * Η εγγραφή είναι **γραμμή προς γραμμή** αυτή του αριστερού κλικ (`use-table-cell-pointer`,
 * κλάδος κελιού): ίδιο `tableCursorAt` — άρα **νέα στήλη αγκύρωσης**, δηλαδή το επόμενο `Enter`
 * επιστρέφει εδώ — και ίδια κατάσταση `nav`. Δεν είναι αντιγραφή τριών γραμμών: είναι η
 * απαίτηση ότι τα **δύο πλήκτρα δεν επιτρέπεται να διαφωνήσουν** για το τι σημαίνει «έδειξες
 * αυτό το κελί».
 *
 * ⚠️ **Καμία σύρση.** Το αριστερό συνεχίζει σε `startTableCellDrag`· το δεξί δεν σύρει ποτέ,
 * και μια σύρση οπλισμένη εδώ θα ζούσε στο `document` περιμένοντας ένα `mouseup` που ήρθε
 * ήδη — δηλαδή θα μάρκαρε κελιά στην **επόμενη** κίνηση του χεριού.
 */
export function installTableCellMenuSelection(
  params: TableContextMenuSelectionParams & { readonly cell: TableCellRef },
): void {
  const { entity, cursor, cell, commitPending } = params;
  // Ο φρουρός της κεφαλίδας — ο πρώτος έλεγχος, όχι ο τελευταίος: ό,τι ακολουθεί γράφει.
  if (!tableContextMenuMayMoveSelection(cursor)) return;

  const model = resolveTableModel(activeTableModel(entity));
  const active: TableCellRef = { rowId: cursor.position.rowId, colId: cursor.position.colId };
  if (!tableContextMenuMovesSelection(model, cell, active, cursor.selection)) return;

  commitPending();
  setTableCellCursor(entity, tableCursorAt(cell.rowId, cell.colId), 'nav');
}

/**
 * 🔴 §43 — Δεξί κλικ στο **τετραγωνάκι της γωνίας**: όλα τα κελιά.
 *
 * ## Η πράξη δεν είναι καινούρια — μετακόμισε
 * Ζούσε μέσα στο `resolveTarget` του `use-table-range-menu`, δηλαδή στη **θύρα του μενού**, και
 * ήταν εκεί η **μοναδική** παρενέργεια σε ολόκληρη τη διαδρομή δεξιού κλικ — ρητά τεκμηριωμένη
 * ως «συνειδητή εξαίρεση». Από τη στιγμή που το κελί και η ζώνη κάνουν το ίδιο πράγμα στο
 * `mousedown`, μια εξαίρεση που ζει σε **άλλο στρώμα** παύει να είναι εξαίρεση και γίνεται
 * **δεύτερη αυθεντία** για την ίδια αρχή (ADR-749). Ίδια πράξη, ίδιος ΕΝΑΣ γραφέας
 * ({@link selectWholeTable}), ένα στρώμα.
 *
 * ## Γιατί ΔΕΝ ρωτά «είναι ήδη μέσα;»
 * Η γωνία είναι **κουμπί**, όχι θέση: το πάτημά της σημαίνει «όλα», και «όλα» δεν έχει έννοια
 * «ήταν ήδη έτσι» που να δικαιολογεί σιωπή — το `Ctrl+A` δεν ρωτά ούτε αυτό. Και το ίδιο το
 * §43 το μέτρησε στο Excel: το δεξί κλικ εκεί **χάνει** την επιλογή σου, ό,τι κι αν ήταν.
 *
 * ## 🔴 §68.9 — ΤΟ ΕΝΕΡΓΟ ΚΕΛΙ ΠΑΕΙ ΣΤΟ `A1`, ΚΑΙ ΤΟ ΠΛΗΚΤΡΟ ΔΕΝ ΤΟ ΚΑΝΕΙ
 * Ο γραφέας είναι πλέον το {@link selectWholeTableFromCorner}, όχι το `selectWholeTable`: το
 * πάτημα είναι **χειρονομία** και ορίζει άγκυρα, ενώ το `Ctrl+A` είναι **εντολή** και δεν
 * πλοηγεί. Το σκεπτικό — και η απόδειξη από τον διπλανό κλάδο των ζωνών — ζει εκεί.
 *
 * ⚠️ **Καμία δέσμευση προχείρου παρ' όλα αυτά.** Θα φαινόταν αντίφαση τώρα που το ενεργό κελί
 * **όντως** κουνιέται, αλλά δεν είναι: όσο υπάρχει ζωντανή γραφή, το `<textarea>` σκεπάζει το
 * κελί του και το πάτημα στη **γωνία** πέφτει έξω από αυτό — ο δρομέας μετακινείται, το
 * πρόχειρο **σβήνεται μαζί** από το `setTableCellCursor`. Το ίδιο ισχύει για την **εντολή** και
 * για το **αριστερό** κλικ, οπότε οι τρεις πόρτες συμφωνούν· δες §68.9 για το ανοιχτό σημείο.
 */
export function installTableCornerMenuSelection(entity: TableEntity): void {
  selectWholeTableFromCorner(entity);
}
