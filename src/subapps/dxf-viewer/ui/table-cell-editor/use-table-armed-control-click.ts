'use client';

/**
 * 🔴 ADR-739 §42 — **ΤΟ ΠΑΤΗΜΑ ΕΝΟΣ ΟΠΛΙΣΜΕΝΟΥ ΧΕΙΡΙΣΤΗΡΙΟΥ ΠΙΝΑΚΑ**, μία φορά για όλα.
 *
 * Ο ΕΝΑΣ ακροατής που εξυπηρετεί το ⊕ της εισαγωγής (§40) και το ⊖ της διαγραφής (§42).
 *
 * ## 🔴 ΔΕΝ ΞΑΝΑΚΑΝΕΙ HIT-TEST — και αυτό είναι ολόκληρη η σχεδίαση
 * Ο ακροατής **δεν** ρωτά τη γεωμετρία «πού έπεσε αυτό το κλικ;». Διαβάζει τι απάντησε ήδη η
 * τελευταία κίνηση ποντικιού — δηλαδή **ακριβώς** το χειριστήριο που ο χρήστης βλέπει
 * ζωγραφισμένο τη στιγμή που πατά.
 *
 * Μια δεύτερη σάρωση εδώ θα ήταν ταυτόσημη αριθμητική με το `mousemove`, οπότε «θα έδινε το
 * ίδιο». Θα το έδινε **σχεδόν πάντα** — και το «σχεδόν» είναι το πρόβλημα: ανάμεσα στην
 * τελευταία κίνηση και το πάτημα μπορεί να έχει αλλάξει το zoom (τροχός), το επίπεδο, ή το
 * ίδιο το μοντέλο (undo από συντόμευση). Τότε η γεωμετρία θα απαντούσε για **άλλο** στοιχείο
 * από εκείνο που είναι βαμμένο στην οθόνη, και ο χρήστης θα έπαιρνε αποτέλεσμα που δεν
 * στόχευσε — σφάλμα που δεν αφήνει ίχνος, γιατί το αποτέλεσμα είναι απολύτως έγκυρο.
 *
 * Ο κανόνας: *ό,τι πατιέται είναι ό,τι φαίνεται*. 🔑 Με το ⊖ ο κανόνας παύει να είναι
 * ευπρέπεια και γίνεται **ασφάλεια**: η πράξη από πίσω **καταστρέφει**.
 *
 * ## 🔴 Η ΚΑΤΑΝΑΛΩΣΗ ΠΡΟΗΓΕΙΤΑΙ ΤΟΥ ΑΠΟΤΕΛΕΣΜΑΤΟΣ — το ελάττωμα του §40.8, σε ΕΝΑ σημείο
 * Το κλικ ανήκει στο χειριστήριο επειδή το χειριστήριο είναι **οπλισμένο**, όχι επειδή η πράξη
 * πέτυχε. Ένα απενεργοποιημένο κουμπί εξακολουθεί να καταπίνει το πάτημά του — δεν το παραδίδει
 * σε ό,τι βρίσκεται από πίσω. Με την ανάποδη σειρά, στο **όριο πλήθους** (`canInsert*` /
 * `canDelete*` → «όχι») το `mousedown` συνέχιζε τη διαδρομή του και ο καμβάς έπαιρνε τη
 * μεταφορά εστίασης: δηλαδή `blur` στο `<textarea>` της συνεδρίας ⇒ **η λειτουργία πίνακα
 * έκλεινε** επειδή ο χρήστης πάτησε ένα κουμπί που δεν είχε τίποτα να κάνει.
 *
 * 🔑 Ο κανόνας ζει πλέον σε **ένα** σημείο. Πριν την εξαγωγή ήταν γραμμένος μία φορά και ο
 * δεύτερος καταναλωτής θα τον αντέγραφε — δηλαδή θα υπήρχαν δύο ευκαιρίες να ξαναγραφτεί η
 * σειρά ανάποδα, και το σύμπτωμα («έκλεισε ο πίνακας μόνος του») δεν δείχνει ποτέ προς την
 * αιτία.
 *
 * ## Γιατί `mousedown` σε φάση σύλληψης
 * Ο πίνακας είναι **επιλεγμένη οντότητα** τη στιγμή που φαίνεται το χειριστήριο. Ένα
 * `mousedown` που φτάνει στον καμβά ξεκινά είτε σύρση οντότητας είτε πλαίσιο επιλογής — δηλαδή
 * το πάτημα του κουμπιού θα μετακινούσε τον πίνακα. Γι' αυτό, **και μόνο όταν το χειριστήριο
 * είναι οπλισμένο**, το συμβάν σταματά εδώ.
 *
 * ## 🔴 §40.9 — ΤΟ ΚΟΥΜΠΙ ΚΑΤΑΠΙΝΕΙ ΤΗ ΧΕΙΡΟΝΟΜΙΑ ΤΟΥ, ΟΧΙ ΜΙΣΗ
 * Το `mousedown` δεν είναι ολόκληρη η χειρονομία. Η **επιλογή οντότητας** του καμβά γεννιέται
 * στο `mouseup` (`mouse-handler-up.ts` → `onCanvasClick`), και ο έλεγχος εκεί δεν ρωτά ποτέ αν
 * είδε το αντίστοιχο `mousedown` — άρα ένα κουμπί που καταναλώνει μόνο το πάτημα παραδίδει το
 * **σήκωμα** στον καμβά. Το ⊕ κάθεται **έξω** από τον πίνακα, οπότε ο καμβάς το διαβάζει ως
 * «κλικ στο κενό» ⇒ **αποεπιλογή**: ο χρήστης εισάγει στήλη και χάνει τον πίνακα με την ίδια
 * κίνηση.
 *
 * 🔑 Σε **λειτουργία πίνακα** αυτό δεν συνέβαινε ποτέ, και γι' αυτό δεν είχε βρεθεί: το
 * κλείδωμα του §29 κόβει ήδη το `mouseup` (§40.8 — «η ασυμμετρία είναι η προδιαγραφή:
 * `mousedown` ναι, τίποτε άλλο»). Σε **απλή επιλογή** το κλείδωμα δεν υπάρχει καθόλου (οδηγείται
 * από τη ζωντανή οντότητα του δρομέα), οπότε το `mouseup` περνά ελεύθερο. Η ασυμμετρία του §40.8
 * ήταν σωστή — απλώς ζούσε σε **έναν** από τους δύο δρόμους.
 *
 * Θεραπεία: όταν το πάτημα καταναλωθεί, ο ακροατής διεκδικεί **και το ζευγάρι του** — μία φορά,
 * στο `document` σε σύλληψη. Δες το {@link claimNextMouseUp}.
 *
 * ⚠️ Στη φάση `nearby` το συμβάν **περνά ανέγγιχτο** — ο καλών απλώς δεν επιστρέφει τίποτα από
 * το {@link UseTableArmedControlClickParams.resolveArmed}. Μια σιωπηλή κατανάλωση εκεί θα
 * σήμαινε ότι ο χρήστης χάνει κλικ σε ολόκληρη περιοχή χωρίς να συμβαίνει τίποτα — η χειρότερη
 * εκδοχή του «δεν δουλεύει».
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/use-table-armed-control-click
 * @see ui/table-cell-editor/use-table-insert-control-click.ts — ο ⊕ καταναλωτής (§40)
 * @see ui/table-cell-editor/use-table-delete-control-click.ts — ο ⊖ καταναλωτής (§42)
 * @see ui/table-cell-editor/use-table-container-mousedown.ts — ο ΕΝΑΣ τρόπος προσάρτησης
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §40.8, §42
 */

