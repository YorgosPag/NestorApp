'use client';

/**
 * 🔴 ADR-739 §42 — **ΤΟ ΠΑΤΗΜΑ ΕΝΟΣ ΟΠΛΙΣΜΕΝΟΥ ΧΕΙΡΙΣΤΗΡΙΟΥ ΠΙΝΑΚΑ**, μία φορά για όλα.
 *
 * Ο ΕΝΑΣ ακροατής που εξυπηρετεί το ⊕ της εισαγωγής (§40) και το ⊖ της διαγραφής (§42).
 *
 * ## 🔴 ΔΕΝ ΞΑΝΑΚΑΝΕΙ HIT-TEST — και αυτό είναι ολόκληρη η σχεδίαση
 * Ο ακροατής **δεν** ρωτά τη γεωμετρία «πού έπεσε αυτό το κλικ;». Διαβάζει τι απάντησε ήδη η
 * τελευταία κίνηση ποντικιού — δηλαδή **ακριβώς** το χειριστήριο που ο χρήστης βλέπει
 * ζωγραφισμένο τη στιγμή που πατά.
 *
 * Μια δεύτερη σάρωση εδώ θα ήταν ταυτόσημη αριθμητική με το `mousemove`, οπότε «θα έδινε το
 * ίδιο». Θα το έδινε **σχεδόν πάντα** — και το «σχεδόν» είναι το πρόβλημα: ανάμεσα στην
 * τελευταία κίνηση και το πάτημα μπορεί να έχει αλλάξει το zoom (τροχός), το επίπεδο, ή το
 * ίδιο το μοντέλο (undo από συντόμευση). Τότε η γεωμετρία θα απαντούσε για **άλλο** στοιχείο
 * από εκείνο που είναι βαμμένο στην οθόνη, και ο χρήστης θα έπαιρνε αποτέλεσμα που δεν
 * στόχευσε — σφάλμα που δεν αφήνει ίχνος, γιατί το αποτέλεσμα είναι απολύτως έγκυρο.
 *
 * Ο κανόνας: *ό,τι πατιέται είναι ό,τι φαίνεται*. 🔑 Με το ⊖ ο κανόνας παύει να είναι
 * ευπρέπεια και γίνεται **ασφάλεια**: η πράξη από πίσω **καταστρέφει**.
 *
 * ## 🔴 Η ΚΑΤΑΝΑΛΩΣΗ ΠΡΟΗΓΕΙΤΑΙ ΤΟΥ ΑΠΟΤΕΛΕΣΜΑΤΟΣ — το ελάττωμα του §40.8, σε ΕΝΑ σημείο
 * Το κλικ ανήκει στο χειριστήριο επειδή το χειριστήριο είναι **οπλισμένο**, όχι επειδή η πράξη
 * πέτυχε. Ένα απενεργοποιημένο κουμπί εξακολουθεί να καταπίνει το πάτημά του — δεν το παραδίδει
 * σε ό,τι βρίσκεται από πίσω. Με την ανάποδη σειρά, στο **όριο πλήθους** (`canInsert*` /
 * `canDelete*` → «όχι») το `mousedown` συνέχιζε τη διαδρομή του και ο καμβάς έπαιρνε τη
 * μεταφορά εστίασης: δηλαδή `blur` στο `<textarea>` της συνεδρίας ⇒ **η λειτουργία πίνακα
 * έκλεινε** επειδή ο χρήστης πάτησε ένα κουμπί που δεν είχε τίποτα να κάνει.
 *
 * 🔑 Ο κανόνας ζει πλέον σε **ένα** σημείο. Πριν την εξαγωγή ήταν γραμμένος μία φορά και ο
 * δεύτερος καταναλωτής θα τον αντέγραφε — δηλαδή θα υπήρχαν δύο ευκαιρίες να ξαναγραφτεί η
 * σειρά ανάποδα, και το σύμπτωμα («έκλεισε ο πίνακας μόνος του») δεν δείχνει ποτέ προς την
 * αιτία.
 *
 * ## Γιατί `mousedown` σε φάση σύλληψης
 * Ο πίνακας είναι **επιλεγμένη οντότητα** τη στιγμή που φαίνεται το χειριστήριο. Ένα
 * `mousedown` που φτάνει στον καμβά ξεκινά είτε σύρση οντότητας είτε πλαίσιο επιλογής — δηλαδή
 * το πάτημα του κουμπιού θα μετακινούσε τον πίνακα. Γι' αυτό, **και μόνο όταν το χειριστήριο
 * είναι οπλισμένο**, το συμβάν σταματά εδώ.
 *
 * ⚠️ Στη φάση `nearby` το συμβάν **περνά ανέγγιχτο** — ο καλών απλώς δεν επιστρέφει τίποτα από
 * το {@link UseTableArmedControlClickParams.resolveArmed}. Μια σιωπηλή κατανάλωση εκεί θα
 * σήμαινε ότι ο χρήστης χάνει κλικ σε ολόκληρη περιοχή χωρίς να συμβαίνει τίποτα — η χειρότερη
 * εκδοχή του «δεν δουλεύει».
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/use-table-armed-control-click
 * @see ui/table-cell-editor/use-table-insert-control-click.ts — ο ⊕ καταναλωτής (§40)
 * @see ui/table-cell-editor/use-table-delete-control-click.ts — ο ⊖ καταναλωτής (§42)
 * @see ui/table-cell-editor/use-table-container-mousedown.ts — ο ΕΝΑΣ τρόπος προσάρτησης
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §40.8, §42
 */

import { type RefObject } from 'react';
import { useEventCallback } from '@/hooks/useEventCallback';
// 🔴 §40.8 — ο ΕΝΑΣ ορισμός του «το πάτημα έπεσε μέσα στη συνεδρία» (§26.15), κοινός με τον pointer.
import { claimTableCellSessionPointerDown } from './table-cell-session-focus';
// 🔴 §40.8 — ο ΕΝΑΣ τρόπος προσάρτησης ακροατή σύλληψης στο δοχείο (κοινός με τον pointer, N.18).
import { useTableContainerMouseDown } from './use-table-container-mousedown';
import { resolveTableById } from './table-entity-lookup';
import type { TableEntity } from '../../types/table-entity';
import type { LevelManagerLike } from '../../hooks/canvas/canvas-click-types';

/**
 * Ό,τι πρέπει να ξέρει ο ακροατής για ένα οπλισμένο χειριστήριο: **σε ποιον πίνακα ανήκει**.
 * Ο,τιδήποτε άλλο είναι γνώση του καταναλωτή και ταξιδεύει μαζί μέσω της παραμέτρου τύπου.
 */
export interface ArmedControlState {
  readonly entityId: string;
}

export interface UseTableArmedControlClickParams<S extends ArmedControlState> {
  /** Χωρίς πίνακα δεν υπάρχει τίποτα να πατηθεί — το **ίδιο** `active` με τον hover. */
  readonly active: boolean;
  readonly containerRef: RefObject<HTMLDivElement | null>;
  readonly levelManager: LevelManagerLike;
  /**
   * Το **οπλισμένο** χειριστήριο τη στιγμή του συμβάντος, ή `null`.
   *
   * Ο καλών διαβάζει το δικό του store και ελέγχει ο ίδιος τη φάση: η φάση είναι γνώση του
   * χειριστηρίου, όχι του ακροατή. Επιστροφή `null` ⇒ **τίποτα δεν καταναλώνεται**.
   */
  readonly resolveArmed: () => S | null;
  /**
   * Η πράξη. Καλείται **αφού** το συμβάν έχει ήδη καταναλωθεί — δες την κεφαλίδα για το γιατί
   * η σειρά είναι αυτή και όχι η αντίστροφη.
   *
   * Η οντότητα διαβάζεται **τη στιγμή του συμβάντος** από τη σκηνή, ποτέ από στιγμιότυπο: η
   * σκηνή ανανεώνεται ασύγχρονα (autosave) και μια κρατημένη αναφορά γίνεται μπαγιάτικη χωρίς
   * ορατό σημάδι — δες την κεφαλίδα του `table-entity-lookup`.
   */
  readonly run: (live: TableEntity, armed: S) => void;
}

/** Εκτελεί ό,τι υπόσχεται το οπλισμένο χειριστήριο, όσο υπάρχει πίνακας στο προσκήνιο. */
export function useTableArmedControlClick<S extends ArmedControlState>(
  params: UseTableArmedControlClickParams<S>,
): void {
  const { active, containerRef, levelManager, resolveArmed, run } = params;

  const handleMouseDown = useEventCallback((event: MouseEvent): void => {
    // Μόνο το κύριο κουμπί: το δεξί κλικ ανήκει στον δρομολογητή μενού, το μεσαίο στο pan.
    if (event.button !== 0) return;
    const armed = resolveArmed();
    if (!armed) return;

    const live = resolveTableById(levelManager, armed.entityId);
    if (!live) return;

    // 🔴 §40.8 — **Η ΚΑΤΑΝΑΛΩΣΗ ΠΡΟΗΓΕΙΤΑΙ ΤΟΥ ΑΠΟΤΕΛΕΣΜΑΤΟΣ.** Δες την κεφαλίδα.
    event.preventDefault();
    event.stopPropagation();
    // 🔴 §40.8 — **δίχτυ, όχι πρωτεύων δρόμος** (N.7.2 #4). Ο πρωτεύων είναι το `preventDefault`
    // από πάνω: χωρίς μεταφορά εστίασης δεν γεννιέται `blur`, άρα δεν υπάρχει τίποτα να
    // σκοτώσει τη συνεδρία. Η δήλωση καλύπτει τον **δεύτερο** δρόμο προς το ίδιο `focusout` —
    // το ξαναστήσιμο του πεδίου όταν η πράξη αλλάξει τη διάταξη κάτω από τον δρομέα
    // (`focusout` (Α) του §26.15, που δεν είναι προεπιλεγμένη ενέργεια και δεν αναιρείται).
    claimTableCellSessionPointerDown();

    run(live, armed);
  });

  // Σύλληψη: πρέπει να προλάβει τον χειριστή επιλογής/σύρσης του καμβά, που ζει στο ίδιο
  // container. Ο **ίδιος** ένας τρόπος προσάρτησης με τον pointer (§40.8, N.18): η σειρά
  // εγγραφής ακροατών δεν είναι συμβόλαιο, η φάση είναι, και δύο αντίγραφα της φάσης είναι
  // δύο ευκαιρίες να αποκλίνει.
  useTableContainerMouseDown({ active, containerRef, onMouseDown: handleMouseDown });
}
