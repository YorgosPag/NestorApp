import { useEventCallback } from '@/hooks/useEventCallback';
// 🔴 §40.8 — ο ΕΝΑΣ ορισμός του «το πάτημα έπεσε μέσα στη συνεδρία» (§26.15), κοινός με τον pointer.
import { claimTableCellSessionPointerDown } from './table-cell-session-focus';
// 🔴 §40.8 — ο ΕΝΑΣ τρόπος προσάρτησης ακροατή σύλληψης στο δοχείο (κοινός με τον pointer, N.18).
import { useTableContainerMouseDown } from './use-table-container-mousedown';
import { resolveTableById } from './table-entity-lookup';
import type { TableEntity } from '../../types/table-entity';
import type { LevelManagerLike } from '../../hooks/canvas/canvas-click-types';

/**
 * Ό,τι πρέπει να ξέρει ο ακροατής για ένα οπλισμένο χειριστήριο: **σε ποιον πίνακα ανήκει**.
 * Ο,τιδήποτε άλλο είναι γνώση του καταναλωτή και ταξιδεύει μαζί μέσω της παραμέτρου τύπου.
 */
export interface ArmedControlState {
  readonly entityId: string;
}

/**
 * 🔴 §40.9 — **Η ΔΙΕΚΔΙΚΗΣΗ ΤΟΥ ΖΕΥΓΑΡΙΟΥ**: το `mouseup` που ακολουθεί το καταναλωμένο πάτημα.
 *
 * Στο `document` σε **σύλληψη**, για τον ίδιο δομικό λόγο που το §29 διάλεξε το `document`: ο
 * ακροατής επιλογής του καμβά ζει στο δοχείο, και «πρόγονος ⇒ πάντα πρώτος στη σύλληψη» είναι
 * η μόνη σειρά που δεν εξαρτάται από τη σειρά **εγγραφής**.
 *
 * **One-shot, όχι κατάσταση.** Το κουμπί διεκδικεί **μία** χειρονομία· μια σημαία που ζει ώσπου
 * να τη σβήσει κάποιος θα ήταν τρίτος κύκλος ζωής να ξεχαστεί ανοιχτός. Το `once: true` το κάνει
 * ο ίδιος ο browser — και ο disposer επιστρέφεται ώστε μια αποπροσάρτηση **πριν** έρθει το
 * `mouseup` (κλείσιμο viewer με το κουμπί ακόμα κάτω) να μην αφήσει ακροατή να επιζεί.
 *
 * ⚠️ **ΠΟΤΕ `stopImmediatePropagation`** (§29): στο ίδιο `document` ζει η λήξη των δηλώσεων του
 * §26.15/§27.15. Το `stopPropagation` δεν αγγίζει συνακροατές του ίδιου κόμβου, άρα σε λειτουργία
 * πίνακα — όπου ο φύλακας του §29 έχει ήδη κόψει το ίδιο συμβάν — αυτό εδώ είναι απλώς ιδεμποτές.
 */
function claimNextMouseUp(): () => void {
  const swallow = (event: Event): void => {
    if (event instanceof MouseEvent && event.button !== 0) return;
    event.stopPropagation();
  };
  document.addEventListener('mouseup', swallow, { capture: true, once: true });
  return () => document.removeEventListener('mouseup', swallow, { capture: true });
}

export interface UseTableArmedControlClickParams<S extends ArmedControlState> {
  readonly containerRef: RefObject<HTMLDivElement | null>;
  readonly levelManager: LevelManagerLike;
  /**
   * Το **οπλισμένο** χειριστήριο τη στιγμή του συμβάντος, ή `null`.
   *
   * Ο καλών διαβάζει το δικό του store και ελέγχει ο ίδιος τη φάση: η φάση είναι γνώση του
   * χειριστηρίου, όχι του ακροατή. Επιστροφή `null` ⇒ **τίποτα δεν καταναλώνεται**.
   */
  readonly resolveArmed: () => S | null;
  /**
   * Η πράξη. Καλείται **αφού** το συμβάν έχει ήδη καταναλωθεί — δες την κεφαλίδα για το γιατί
   * η σειρά είναι αυτή και όχι η αντίστροφη.
   *
   * Η οντότητα διαβάζεται **τη στιγμή του συμβάντος** από τη σκηνή, ποτέ από στιγμιότυπο: η
   * σκηνή ανανεώνεται ασύγχρονα (autosave) και μια κρατημένη αναφορά γίνεται μπαγιάτικη χωρίς
   * ορατό σημάδι — δες την κεφαλίδα του `table-entity-lookup`.
   */
  readonly run: (live: TableEntity, armed: S) => void;
}

/** Εκτελεί ό,τι υπόσχεται το οπλισμένο χειριστήριο, όσο υπάρχει πίνακας στο προσκήνιο. */
export function useTableArmedControlClick<S extends ArmedControlState>(
  params: UseTableArmedControlClickParams<S>,
): void {
  const { containerRef, levelManager, resolveArmed, run } = params;

  /** Ο disposer της τρέχουσας διεκδίκησης `mouseup`· `null` όσο δεν εκκρεμεί καμία. */
  const pendingMouseUpRef = useRef<(() => void) | null>(null);

  const handleMouseDown = useEventCallback((event: MouseEvent): void => {
    // Μόνο το κύριο κουμπί: το δεξί κλικ ανήκει στον δρομολογητή μενού, το μεσαίο στο pan.
    if (event.button !== 0) return;
    const armed = resolveArmed();
    if (!armed) return;

    const live = resolveTableById(levelManager, armed.entityId);
    if (!live) return;

    // 🔴 §40.8 — **Η ΚΑΤΑΝΑΛΩΣΗ ΠΡΟΗΓΕΙΤΑΙ ΤΟΥ ΑΠΟΤΕΛΕΣΜΑΤΟΣ.** Δες την κεφαλίδα.
    event.preventDefault();
    event.stopPropagation();
    // 🔴 §40.8 — **δίχτυ, όχι πρωτεύων δρόμος** (N.7.2 #4). Ο πρωτεύων είναι το `preventDefault`
    // από πάνω: χωρίς μεταφορά εστίασης δεν γεννιέται `blur`, άρα δεν υπάρχει τίποτα να
    // σκοτώσει τη συνεδρία. Η δήλωση καλύπτει τον **δεύτερο** δρόμο προς το ίδιο `focusout` —
    // το ξαναστήσιμο του πεδίου όταν η πράξη αλλάξει τη διάταξη κάτω από τον δρομέα
    // (`focusout` (Α) του §26.15, που δεν είναι προεπιλεγμένη ενέργεια και δεν αναιρείται).
    claimTableCellSessionPointerDown();

    run(live, armed);
  });

  // Σύλληψη: πρέπει να προλάβει τον χειριστή επιλογής/σύρσης του καμβά, που ζει στο ίδιο
  // container. Ο **ίδιος** ένας τρόπος προσάρτησης με τον pointer (§40.8, N.18): η σειρά
  // εγγραφής ακροατών δεν είναι συμβόλαιο, η φάση είναι, και δύο αντίγραφα της φάσης είναι
  // δύο ευκαιρίες να αποκλίνει.
  useTableContainerMouseDown({ active, containerRef, onMouseDown: handleMouseDown });
}
