/**
 * ADR-739 Φ.Δ βήμα 7 — **το συμβόλαιο ενεργειών μιας συνεδρίας επεξεργασίας κελιού**, μία φορά.
 *
 * Από αυτό το βήμα η συνεδρία έχει **δύο** πεδία κειμένου (το κελί και τη γραμμή τύπων) και
 * **έναν** ενδιάμεσο που τα στήνει. Και οι τρεις χρειάζονται τις ίδιες τέσσερις ενέργειες.
 *
 * Γραμμένες τρεις φορές, θα ήταν sibling clone — και το CHECK 3.28 (jscpd, N.18) το
 * χαρακτήρισε **ακριβώς έτσι** μόλις γεννήθηκε το δεύτερο αντίγραφο (22 γραμμές / 52 tokens,
 * μετρημένο 2026-08-01). Το σοβαρό όμως δεν είναι οι γραμμές: αν κάποτε η υπογραφή του
 * `onCommit` αποκτούσε δεύτερο όρισμα, τα δύο πεδία θα μπορούσαν να το μάθουν σε
 * **διαφορετικές στιγμές** — δηλαδή η γραμμή τύπων θα έγραφε αλλιώς από το κελί, που είναι
 * ακριβώς η δεύτερη διαδρομή εγγραφής που ολόκληρο το βήμα απαγορεύει (§5.5 του handoff).
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-cell-session-types
 */

import type { TableCursorMove } from '../../bim/table/table-cell-navigation';

/** Οι τέσσερις ενέργειες που κατέχει ο **καλών** — ποτέ το ίδιο το πεδίο κειμένου. */
export interface TableCellSessionHandlers {
  /**
   * Γράψε το κείμενο στο μοντέλο (undoable). Η **μία** διαδρομή εγγραφής: και τα δύο πεδία
   * περνούν από εδώ, δηλαδή από το ίδιο `buildTableCellEditCommand`.
   */
  readonly onCommit: (nextText: string) => void;
  /** Πήγαινε στο κελί που ορίζει η κίνηση· ο καλών κατέχει το μοντέλο. */
  readonly onMove: (move: TableCursorMove) => void;
  /** `Delete` σε κατάσταση πλοήγησης — άδειασμα κελιού (Excel). */
  readonly onClear: () => void;
  /**
   * ADR-739 Φ.Δ βήμα 4 — `Ctrl+Z`/`Ctrl+Y` σε **πλοήγηση**. Σε γραφή δεν καλείται ποτέ:
   * εκεί το undo ανήκει στο πεδίο και το κάνει ο browser (δες `table-cell-key-intent`).
   */
  readonly onHistory: (direction: 'undo' | 'redo') => void;
}
