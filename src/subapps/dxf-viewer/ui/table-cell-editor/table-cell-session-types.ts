/**
 * ADR-739 Φ.Δ βήμα 7 — **το συμβόλαιο ενεργειών μιας συνεδρίας επεξεργασίας κελιού**, μία φορά.
 *
 * Από αυτό το βήμα η συνεδρία έχει **δύο** πεδία κειμένου (το κελί και τη γραμμή τύπων) και
 * **έναν** ενδιάμεσο που τα στήνει. Και οι τρεις χρειάζονται τις ίδιες τέσσερις ενέργειες.
 *
 * Γραμμένες τρεις φορές, θα ήταν sibling clone — και το CHECK 3.28 (jscpd, N.18) το
 * χαρακτήρισε **ακριβώς έτσι** μόλις γεννήθηκε το δεύτερο αντίγραφο (22 γραμμές / 52 tokens,
 * μετρημένο 2026-08-01). Το σοβαρό όμως δεν είναι οι γραμμές: αν κάποτε η υπογραφή του
 * `onCommit` αποκτούσε δεύτερο όρισμα, τα δύο πεδία θα μπορούσαν να το μάθουν σε
 * **διαφορετικές στιγμές** — δηλαδή η γραμμή τύπων θα έγραφε αλλιώς από το κελί, που είναι
 * ακριβώς η δεύτερη διαδρομή εγγραφής που ολόκληρο το βήμα απαγορεύει (§5.5 του handoff).
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-cell-session-types
 */

import type { TableCursorMove } from '../../bim/table/table-cell-navigation';

/**
 * Οι ενέργειες που κατέχει ο **καλών** — ποτέ το ίδιο το πεδίο κειμένου.
 *
 * ## ADR-739 Φ.Δ βήμα 8 — γιατί οι χειριστές ΠΡΟΧΕΙΡΟΥ ΔΕΝ είναι εδώ
 * Η συνεδρία έχει **δύο** πεδία κειμένου, οπότε το πρώτο ένστικτο είναι να μοιραστούν και
 * τα `copy`/`cut`/`paste`. Δεν χρειάζεται, και ο λόγος είναι **δομικός**: το `onFocus` της
 * γραμμής τύπων περνά τη συνεδρία σε κατάσταση `edit` (κλικ στη γραμμή = «διορθώνω αυτή
 * την τιμή», Excel/Sheets). Άρα όσο η γραμμή τύπων είναι εστιασμένη, η κατάσταση **ποτέ**
 * δεν είναι `nav`, και το {@link tableClipboardScope} απαντά πάντα `'text'` — δηλαδή το
 * πρόχειρο ανήκει ούτως ή άλλως στον browser. Χειριστές περιοχής εκεί θα ήταν κώδικας που
 * δεν μπορεί να εκτελεστεί.
 *
 * Τα `onExtend`/`onSelectAll` **μένουν** εδώ, γιατί είναι προθέσεις **πλήκτρων** και
 * περνούν από τον κοινό `useTableCellSessionKeys` — που τα απαιτεί και από τα δύο πεδία.
 */
export interface TableCellSessionHandlers {
  /**
   * Γράψε το κείμενο στο μοντέλο (undoable). Η **μία** διαδρομή εγγραφής: και τα δύο πεδία
   * περνούν από εδώ, δηλαδή από το ίδιο `buildTableCellEditCommand`.
   */
  readonly onCommit: (nextText: string) => void;
  /** Πήγαινε στο κελί που ορίζει η κίνηση· ο καλών κατέχει το μοντέλο. */
  readonly onMove: (move: TableCursorMove) => void;
  /**
   * `Delete` σε κατάσταση πλοήγησης — άδειασμα.
   *
   * ADR-739 Φ.Δ βήμα 8: αδειάζει **ολόκληρη την επιλεγμένη περιοχή**, όχι μόνο το ενεργό
   * κελί. Χωρίς αυτό, έξι φωτισμένα κελιά και ένα `Delete` θα άδειαζαν **ένα** — η οθόνη θα
   * υποσχόταν κάτι που η ενέργεια δεν κάνει.
   */
  readonly onClear: () => void;
  /**
   * ADR-739 Φ.Δ βήμα 4 — `Ctrl+Z`/`Ctrl+Y` σε **πλοήγηση**. Σε γραφή δεν καλείται ποτέ:
   * εκεί το undo ανήκει στο πεδίο και το κάνει ο browser (δες `table-cell-key-intent`).
   */
  readonly onHistory: (direction: 'undo' | 'redo') => void;
  /**
   * ADR-739 Φ.Δ βήμα 8 — `Shift + βέλος/Home/End`: μεγαλώνει την **περιοχή**. Το ενεργό
   * κελί δεν κουνιέται — αυτή είναι όλη η διαφορά από το {@link onMove}.
   */
  readonly onExtend: (move: TableCursorMove) => void;
  /** ADR-739 Φ.Δ βήμα 8 — `Ctrl+A`: όλα τα κελιά **αυτού** του πίνακα. */
  readonly onSelectAll: () => void;
  /**
   * 🔴 ADR-754 Γ3 — `F4` σε **γραφή**: κλείδωσε/ξεκλείδωσε την αναφορά του δρομέα.
   *
   * ## Γιατί εδώ, ενώ το `onOpenLink` έμεινε έξω
   * Το κριτήριο αυτού του συμβολαίου είναι «**το χρειάζονται και τα δύο πεδία;**». Το
   * `onOpenLink` παράγεται μόνο σε κατάσταση `nav`, όπου η γραμμή τύπων **δεν μπορεί** να
   * βρεθεί (το `onFocus` της την περνά σε `edit`) — άρα εκεί θα ήταν κώδικας που δεν
   * εκτελείται. Το `F4` είναι το **ακριβώς αντίστροφο**: παράγεται μόνο σε γραφή, δηλαδή στη
   * μία κατάσταση όπου **και τα δύο** πεδία ζουν. Ο χρήστης που γράφει `=A1` στη γραμμή τύπων
   * περιμένει το ίδιο `F4` με τον χρήστη που το γράφει στο κελί.
   */
  readonly onToggleAbsoluteRef: () => void;
}
