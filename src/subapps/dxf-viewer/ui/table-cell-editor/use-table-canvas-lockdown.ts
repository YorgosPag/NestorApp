export function __setCanvasLockedByTableSessionForTests(locked: boolean): void {
  setCanvasLockDepth(locked ? 1 : 0);
}

export interface UseTableCanvasLockdownParams {
  /**
   * 🔴 **Ο ΜΟΝΑΔΙΚΟΣ ΔΙΑΚΟΠΤΗΣ: η ζωντανή οντότητα του δρομέα.**
   *
   * Είναι ταυτόχρονα (α) η γεωμετρία που απαντά «μέσα ή έξω;» και (β) η **απάντηση στο αν
   * υπάρχει καθόλου λειτουργία πίνακα** — δες το §29.15 στην κεφαλίδα για το γιατί αυτά τα
   * δύο **πρέπει** να είναι μία τιμή και όχι δύο παράμετροι.
   *
   * `null` σημαίνει **και** «δεν υπάρχει συνεδρία» **και** «ο πίνακας χάθηκε από κάτω μου»
   * (undo / διαγραφή / αλλαγή επιπέδου) — και οι δύο δίνουν σωστά **ξεκλείδωτο** καμβά.
   */
  readonly entity: TableEntity | null;
  readonly containerRef: RefObject<HTMLDivElement | null>;
  readonly transformRef: RefObject<ViewTransform>;
}

/** Τα συμβάντα που ο καμβάς δεν επιτρέπεται να δει. Δες τον πίνακα στην κεφαλίδα. */
const GUARDED_EVENTS = ['mousedown', 'mouseup', 'click', 'dblclick', 'contextmenu'] as const;

/**
 * Κλειδώνει τον καμβά όσο ζει η λειτουργία πίνακα.
 *
 * Καλείται **δίπλα** στο `useModalKeyboardScope(overlay !== null)` αλλά **όχι** με την ίδια
 * συνθήκη — δες το §29.15 στην κεφαλίδα: οι δύο μηχανισμοί απαντούν σε **διαφορετικές
 * ερωτήσεις**, και υπάρχει ορατή κατάσταση όπου οι απαντήσεις διίστανται.
 */
export function useTableCanvasLockdown(params: UseTableCanvasLockdownParams): void {
  const { entity, containerRef, transformRef } = params;
  const active = entity !== null;

  /**
   * 🔴 **ΤΟ ΒΑΘΟΣ ΖΕΙ ΜΟΝΟ ΤΟΥ, ΜΕ ΕΞΑΡΤΗΣΗ ΕΝΑΝ BOOLEAN** — και δεν είναι καλλωπισμός.
   *
   * Η οντότητα είναι **νέο αντικείμενο** σε κάθε αλλαγή σκηνής, δηλαδή σε κάθε δέσμευση
   * κελιού. Με το βάθος δεμένο στην ταυτότητά της, ο ίδιος effect έκανε `cleanup → setup`,
   * άρα `1 → 0 → 1`, άρα **δύο** αλλαγές ιδιοκτησίας ⇒ **δύο περιττά `markSystemsDirty`
   * ανά πάτημα πλήκτρου** — ολόκληρη επαναβαφή του `dxf-canvas`, δύο φορές, ενώ στην οθόνη
   * δεν άλλαξε τίποτα. Το §29.12 είχε γράψει ρητά «το αίτημα μπαίνει **μόνο στην αλλαγή της
   * απάντησης**»· η σύζευξη με την οντότητα το παραβίαζε σιωπηλά.
   *
   * Χωρισμένο έτσι, η απάντηση αλλάζει **δύο φορές ανά συνεδρία** — όσες και τα καρέ.
   */
  useEffect(() => {
    if (!active) return;
    setCanvasLockDepth(canvasLockDepthStore.get() + 1);
    return () => setCanvasLockDepth(canvasLockDepthStore.get() - 1);
  }, [active]);

  /** Οι ακροατές, που **χρειάζονται** τη ζωντανή γεωμετρία και σωστά ξαναδένονται μαζί της. */
  useEffect(() => {
    if (!entity) return;

    const guard = (event: Event): void => {
      if (!(event instanceof MouseEvent)) return;
      if (!shouldBlock(event, containerRef.current, transformRef.current, entity)) return;
      event.stopPropagation();
      // Μόνο εκεί που η προεπιλεγμένη ενέργεια βλάπτει: μεταφορά εστίασης (⇒ θα σκότωνε τη
      // συνεδρία) και μενού του browser. Στα `click`/`dblclick`/`mouseup` δεν υπάρχει
      // προεπιλογή να αναιρεθεί, και μια αδιάκριτη `preventDefault` θα έκρυβε ό,τι εμφανιστεί
      // αύριο.
      if (event.type === 'mousedown' || event.type === 'contextmenu') event.preventDefault();
    };

    for (const type of GUARDED_EVENTS) {
      document.addEventListener(type, guard, { capture: true });
    }
    return () => {
      for (const type of GUARDED_EVENTS) {
        document.removeEventListener(type, guard, { capture: true });
      }
    };
  }, [entity, containerRef, transformRef]);
}

/**
 * Η απόφαση, ολόκληρη — με σειρά από τη φθηνότερη ερώτηση στην ακριβότερη.
 *
 * ⚠️ Ο αριθμός τους δεν γράφεται στην περιγραφή **επίτηδες**: έλεγε «πέντε» και έγινε έξι με
 * το §40.8, δηλαδή ένα ακόμα νούμερο που παλιώνει σιωπηλά. Οι αριθμημένοι κλάδοι από κάτω
 * είναι η πηγή.
 *
 * Εξαγόμενη από το `guard` επίτηδες: είναι **καθαρή** συνάρτηση της κατάστασης του συμβάντος,
 * άρα δοκιμάζεται χωρίς DOM στήσιμο και διαβάζεται ως προδιαγραφή.
 */
function shouldBlock(
  event: MouseEvent,
  container: HTMLDivElement | null,
  transform: ViewTransform | null,
  entity: TableEntity | null,
): boolean {
  if (!container || !entity) return false;
  // 1. Μεσαίο/δεξί **πάτημα** = pan (AutoCAD/BricsCAD). Το `contextmenu` που ίσως ακολουθήσει
  //    κρίνεται χωριστά — έτσι το δεξί σύρσιμο κάνει pan ΚΑΙ το δεξί κλικ δεν ανοίγει μενού.
  if ((event.type === 'mousedown' || event.type === 'mouseup') && event.button !== 0) return false;
  // 2. Έξω από τον καμβά: κορδέλα, πλευρικός πίνακας, μενού σε portal. Δεν μας αφορούν ποτέ.
  if (!(event.target instanceof Node) || !container.contains(event.target)) return false;
  // 3. Μέσα σε μέλος της ίδιας συνεδρίας: το `<textarea>` του κελιού, η γραμμή τύπων, το
  //    μενού ζωνών. Ρωτιέται **πριν** τη γεωμετρία γιατί ένα πεδίο μπορεί να ξεπερνά το κελί
  //    του (το κουτί μεγαλώνει με το κείμενο) — το DOM είναι εδώ πιο αληθινό από τα mm.
  if (isInsideTableCellSession(event.target)) return false;
  // 4. Πάνω στον ίδιο τον πίνακα (κελί ή ζώνη δείκτη): ο pointer του πίνακα το χειρίζεται,
  //    και ο καμβάς έχει ακόμα δουλειά εκεί (λαβές, μετακίνηση οντότητας).
  const world = tableEventWorldPoint(event, container, transform);
  if (!world || !transform) return false;
  const hit = tablePointerHitAtWorld(entity, world, transform.scale);
  // 5. 🔴 §40.8 — **ΤΟ ⊕ ΕΙΝΑΙ ΚΟΥΜΠΙ, ΚΑΙ ΤΑ ΚΟΥΜΠΙΑ ΔΕΝ ΜΟΙΡΑΖΟΝΤΑΙ ΤΟ ΠΑΤΗΜΑ.**
  //
  //    Είναι η **μόνη** ασύμμετρη απάντηση αυτής της συνάρτησης, και η ασυμμετρία είναι το
  //    νόημα: το `mousedown` **οφείλει** να περάσει (ο ακροατής του δοχείου εκτελεί την
  //    εισαγωγή και το καταναλώνει επί τόπου), αλλά κανένα άλλο συμβάν δεν έχει δουλειά στον
  //    καμβά. Το `mouseup` ειδικά είναι το επικίνδυνο — εκεί γεννιέται η **επιλογή οντότητας**
  //    (`mouse-handler-up.ts`, `onCanvasClick`), και ο καμβάς την κάνει **ακόμα κι όταν δεν
  //    είδε ποτέ το `mousedown`**. Μια συμμετρική «άσ' τα όλα να περάσουν» θα διόρθωνε την
  //    εισαγωγή και θα αποεπέλεγε τον πίνακα με την ίδια κίνηση.
  if (hit?.where === 'insert-control') return event.type !== 'mousedown';
  return hit === null;
}
