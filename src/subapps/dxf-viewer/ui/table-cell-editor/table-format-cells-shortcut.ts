'use client';

/**
 * 🔴 ADR-739 §61 — **`Ctrl+1`: ΕΝΑ ΠΛΗΚΤΡΟ, ΔΥΟ ΝΟΜΙΜΟΙ ΙΔΙΟΚΤΗΤΕΣ.**
 *
 * ```
 *   Excel    Ctrl+1  →  Μορφοποίηση κελιών
 *   AutoCAD  Ctrl+1  →  Παλέτα Ιδιοτήτων
 * ```
 * Και οι δύο συμβάσεις είναι σωστές, και ο ΝΕΣΤΩΡ είναι **και τα δύο προγράμματα ταυτόχρονα**.
 *
 * ## 🔴 ΔΙΟΡΘΩΣΗ ΠΡΟΗΓΟΥΜΕΝΟΥ ΙΣΧΥΡΙΣΜΟΥ — ΔΕΝ ΥΠΗΡΞΕ ΠΟΤΕ ΣΥΓΚΡΟΥΣΗ
 * Η αναφορά της Φάσης Ε έγραφε: *«το `Ctrl+1` είναι ήδη πιασμένο από την Παλέτα Ιδιοτήτων — δύο
 * σωστές συμβάσεις, ένα πλήκτρο, απόφαση τομέα»*. **Ελλιπές.** Ο φύλακας
 * `INPUT`/`TEXTAREA`/`contentEditable` υπάρχει στο `useCanvasSectionUI` **από πάντα**, και ο
 * δρομέας κελιού είναι `<textarea>` — άρα με δρομέα μέσα σε κελί το `Ctrl+1` έβγαινε νωρίς και
 * **δεν έκανε απολύτως τίποτα**. Δεν ήταν σύγκρουση· ήταν **τρύπα**. *(Μετρημένο, όχι
 * συλλογισμένο: δες την άγκυρα `Κ0` στο `table-format-cells-shortcut.test.ts`, που στήνει
 * πραγματικό `<textarea>` σε jsdom και επαληθεύει ότι το `e.target` ενός `keydown` με `capture`
 * στο `window` **είναι** το εστιασμένο πεδίο.)*
 *
 * ## 🔑 ΤΟ ΚΡΙΤΗΡΙΟ ΕΙΝΑΙ Η ΣΥΝΕΔΡΙΑ, ΟΧΙ Η ΕΣΤΙΑΣΗ — και γι' αυτό ζει ΕΔΩ
 * Ο φύλακας εστίασης απαντά «γράφει κάπου ο χρήστης;». Χρήσιμο, αλλά **λάθος ερώτηση** για αυτό
 * το πλήκτρο: με ανοιχτή συνεδρία κελιού η εστίαση μπορεί κάλλιστα να είναι σε **κουμπί** του
 * mini toolbar ή της κορδέλας, και τότε ο φύλακας θα άφηνε το `Ctrl+1` να ανοίξει την Παλέτα
 * Ιδιοτήτων ενώ ο χρήστης βρίσκεται μέσα σε πίνακα. Η σωστή ερώτηση είναι «**υπάρχει στόχος
 * μορφοποίησης;**» — και την απαντά **μόνο** η θύρα.
 *
 * Είναι κατά γράμμα το μοντέλο των `when` clauses του VS Code: ένα keybinding, πολλαπλά
 * περιβάλλοντα, **η πρώτη κατάσταση που ταιριάζει κερδίζει** — και ο καλών εδώ ρωτά αυτόν τον
 * ιδιοκτήτη **πρώτο**, ακριβώς μία φορά, σε ένα σημείο.
 *
 * ⚠️ Γι' αυτό ο κώδικας είναι **συνάρτηση με boolean**, όχι `if` μέσα στο `useCanvasSectionUI`:
 * ένα `if` εκεί θα ήταν δεύτερη υλοποίηση της ερώτησης «είμαι σε πίνακα;» δίπλα στη θύρα, με
 * δύο ευκαιρίες να αποκλίνουν. Εδώ ο καλών δεν μαθαίνει **τίποτα** για πίνακες: ρωτά «το πήρε
 * κάποιος;» και προχωρά.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-format-cells-shortcut
 * @see state/table-format-cells-dialog-store.ts — η κατάσταση του διαλόγου
 * @see hooks/canvas/useCanvasSectionUI.ts — ο **ΕΝΑΣ** καλών
 */

import {
  getTableFormatCellsRequest,
  openTableFormatCellsDialog,
} from '../../state/table-format-cells-dialog-store';
import { getTableFormatPort } from './table-format-port';

/**
 * Διεκδικεί το `Ctrl+1` για τη «Μορφοποίηση κελιών». Επιστρέφει `true` αν το **πήρε**.
 *
 * `false` σημαίνει «δεν με αφορά» — και ο καλών προχωρά στη σημασία του AutoCAD, **ακριβώς όπως
 * σήμερα**. Καμία υπάρχουσα συμπεριφορά δεν αλλάζει έξω από τη συνεδρία πίνακα.
 *
 * 🔴 **Ο ΦΥΛΑΚΑΣ ΤΗΣ ΔΕΥΤΕΡΗΣ ΠΑΤΗΜΑΤΙΑΣ.** Με τον διάλογο ήδη ανοιχτό, η συντόμευση
 * **καταναλώνεται και δεν κάνει τίποτα**. Το store, για κάθε άλλη υποδοχή, τεκμηριώνει ότι «το
 * τελευταίο κλικ αποφασίζει» — σωστό για **κουμπί**, που πατιέται όταν το βλέπεις. Ένα πλήκτρο
 * πατιέται δεύτερη φορά από **μνήμη χεριού** («δεν έγινε τίποτα;»), και τότε το φρέσκο προσχέδιο
 * θα πετούσε **σιωπηλά** ό,τι είχε ήδη ρυθμίσει ο χρήστης. Η σιωπηλή απώλεια εργασίας είναι
 * ακριβώς το ελάττωμα που γέννησε ολόκληρο το store στο §60.
 *
 * ⚠️ Καταναλώνει (`true`) και δεν επιστρέφει `false`: ένα `false` εδώ θα άνοιγε την **Παλέτα
 * Ιδιοτήτων** πάνω από τον ανοιχτό διάλογο — δηλαδή το «δεν έγινε τίποτα» θα γινόταν «έγινε κάτι
 * άσχετο».
 */
export function claimTableFormatCellsShortcut(): boolean {
  if (getTableFormatCellsRequest() !== null) return true;

  // Getter τη στιγμή του πατήματος (ADR-040 κανόνας #2): χωρίς δρομέα ⇒ `null` ⇒ το πλήκτρο
  // ανήκει στον AutoCAD-ιδιοκτήτη του, χωρίς να χρειαστεί κανείς να ρωτήσει «τι είναι πίνακας».
  const target = getTableFormatPort()?.formatTarget() ?? null;
  if (target === null) return false;

  // Χωρίς καρτέλα **επίτηδες**: το Excel ανοίγει στην τελευταία που είδε ο χρήστης, και η μνήμη
  // χεριού είναι ο λόγος ύπαρξης μιας συντόμευσης. Δες την κεφαλίδα του store.
  openTableFormatCellsDialog({ target });
  return true;
}
