'use client';

/**
 * 🔴 ADR-739 §66 — **Η ΠΕΜΠΤΗ ΧΕΙΡΟΝΟΜΙΑ ΤΟΥ ΠΙΝΑΚΑ**: μετακίνηση ολόκληρης της οντότητας
 * κρατώντας πατημένο το τετραγωνάκι της γωνίας (Giorgio 2026-08-09).
 *
 * ## Το αίτημα, και γιατί ΔΕΝ λύνεται με «άσε τον καμβά να κάνει τη δουλειά του»
 * Ο προφανής δρόμος ήταν να **σβηστεί** το `claimTableCellPointerGesture()` στον κλάδο της
 * γωνίας: ο σχολιασμός του §27.15 λέει ρητά ότι χωρίς τη δήλωση «το body-drag του ADR-560
 * armάρει στα 3 px και ένα κλικ με μικροκίνηση θα **μετακινούσε τον πίνακα**». Μια γραμμή, και
 * η μετακίνηση θα ερχόταν δωρεάν από υπάρχοντα μηχανισμό.
 *
 * **Μετρήθηκε ότι δεν ισχύει πια, και η αιτία είναι το §29.** Το `resolveBodyDragTarget`
 * απαιτεί `hoveredEntityId`, και όσο ζει η λειτουργία πίνακα ο `mouse-handler-move` γράφει
 * `setHoveredEntity(null)` σε **κάθε** κίνηση (§29, ο κλάδος «κανένα hover τώρα»). Δηλαδή σε
 * edit mode το body-drag είναι **δομικά αδύνατο**, με ή χωρίς δήλωση — το σχόλιο περιγράφει
 * κόσμο που έπαψε να υπάρχει όταν το ποντίκι απέκτησε modality. Η δήλωση μένει ακέραιη
 * (φυλάει τη σύρση επιλογής κελιών, που **δεν** έχει τέτοιο φύλακα), και η μετακίνηση από τη
 * γωνία γίνεται εδώ, ρητά.
 *
 * ## 🔑 ΚΑΜΙΑ ΝΕΑ ΑΡΙΘΜΗΤΙΚΗ — η ΙΔΙΑ που τρέχει ο σταυρός μετακίνησης
 * Ο πίνακας **έχει ήδη** λαβή μετακίνησης (`TABLE_MOVE_KIND`, λίγο μέσα από την πάνω-αριστερή
 * γωνία) και η μεταφορά της άγκυρας ζει σε **μία** καθαρή συνάρτηση: `applyTableGripDrag`.
 * Αυτό το module δεν υπολογίζει θέση — **ρωτά** εκείνη. Ένα `translatePoint` εδώ θα ήταν
 * δεύτερη άποψη για το «τι σημαίνει μετακίνηση πίνακα» (N.18 / CHECK 3.28), και θα αποκλίνει
 * τη μέρα που η λαβή μάθει κάτι (κβάντιση, έλξη, κλείδωμα άξονα) και η γωνία όχι.
 *
 * Γι' αυτόν ακριβώς τον λόγο **δεν** προστέθηκε δεύτερη λαβή `table-move` πάνω στη γωνία: το
 * κοινό μητρώο καλεί `getTableGrips(entity)` **χωρίς viewScale** (§31.8), ενώ η γωνία έχει
 * σταθερό μέγεθος σε **px οθόνης** — δηλαδή θέση σε mm που εξαρτάται από το zoom. Το ίδιο
 * ακριβώς εμπόδιο που ανάγκασε και το διαχωριστικό στηλών να γίνει χειρονομία του πίνακα
 * (§31.9), και η ίδια απάντηση.
 *
 * ## 🔴 ΤΟ ΚΑΤΩΦΛΙ ΔΕΝ ΕΙΝΑΙ ΓΥΑΛΙΣΜΑ — η γωνία έχει ΔΥΟ νοήματα
 * Το τετραγωνάκι είναι ήδη το κουμπί «επιλογή όλων» (§43). Χωρίς κατώφλι, ένα **κλικ** με 1 px
 * τρέμουλο του χεριού θα μετακινούσε τον πίνακα και θα έγραφε βήμα αναίρεσης που ο χρήστης δεν
 * ζήτησε ποτέ — δηλαδή η νέα χειρονομία θα **έτρωγε** την παλιά. Η σύμβαση είναι του Excel και
 * του Figma: *κλικ = η εντολή του κουμπιού· σύρσιμο = μετακίνηση*, και τα ξεχωρίζει απόσταση σε
 * px **οθόνης** — {@link DXF_TIMING.threshold.DRAG_PX}, ο ΕΝΑΣ αριθμός του subapp για «πόσο
 * κουνήθηκε το χέρι πριν γίνει σύρσιμο». Σε px και όχι σε mm επίτηδες: το κατώφλι μετρά
 * **πρόθεση ανθρώπου**, που δεν αλλάζει με το zoom.
 *
 * ⚠️ Το `onSelectAll()` τρέχει **ούτως ή άλλως** στο πάτημα (ο καλών το κάνει πριν από εδώ),
 * ακριβώς όπως στο Excel το πάτημα στη γωνία μαρκάρει αμέσως. Η σύρση **δεν το αναιρεί** —
 * μετακινεί έναν πίνακα που είναι ολόκληρος επιλεγμένος, που είναι και το σωστό νοητικό μοντέλο.
 *
 * ## 🔴 Η ΕΠΑΝΑΦΟΡΑ ΠΡΙΝ ΤΟ COMMIT — αλλιώς το `Ctrl+Z` δεν κάνει τίποτα
 * Το `UpdateEntityCommand` παίρνει το στιγμιότυπο αναίρεσης **τη στιγμή του `execute()`**,
 * διαβάζοντας τη σκηνή (`this.snapshot = deepClone(entity)`). Η ζωντανή προεπισκόπηση έχει όμως
 * ήδη γράψει εκεί την **τελική** θέση ⇒ το στιγμιότυπο θα ήταν η θέση στην οποία μόλις
 * καταλήξαμε, και το `Ctrl+Z` θα επέστρεφε τον πίνακα… εκεί που είναι.
 *
 * Γι' αυτό το `commit` καλείται **αφού** η σκηνή επιστραφεί στην αρχική θέση: `preview(αρχική)`
 * και αμέσως μετά `commit(τελική)`, μέσα στον **ίδιο** χειριστή συμβάντος — ένα batch, κανένα
 * ενδιάμεσο καρέ. Έτσι η εντολή γεννιέται με σωστό «πριν» χωρίς να μάθει το `UpdateEntityCommand`
 * τίποτα καινούργιο και χωρίς δεύτερο είδος εντολής.
 *
 * 🔶 **ΔΗΛΩΜΕΝΟ ΟΡΙΟ**: το ίδιο σχήμα «preview γράφει τη σκηνή → commit διαβάζει τη σκηνή» το
 * τρέχουν και οι χειρονομίες μεγέθους (`table-axis-resize-drag`) και συμπλήρωσης
 * (`table-fill-handle-drag`), **χωρίς** αυτή την επαναφορά. Δεν αγγίχθηκαν εδώ (εκτός εμβέλειας
 * του αιτήματος) αλλά η υπόθεση είναι ότι πάσχουν από το ίδιο — αναφέρθηκε στον ιδιοκτήτη ως
 * ξεχωριστό εύρημα προς επαλήθευση, όχι ως σιωπηλή παράπλευρη διόρθωση.
 *
 * ## Ο κύκλος ζωής είναι ο ίδιος με τις τέσσερις αδελφές
 * Ακροατές στο `document` σε **σύλληψη**, ένας ενεργός κύκλος τη φορά, ρητό
 * {@link endTableMoveDrag} στην αποπροσάρτηση της συνεδρίας. Καμία νέα μηχανική — δες την
 * κεφαλίδα του `table-axis-resize-drag` για ολόκληρο το σκεπτικό, που ισχύει αυτούσιο.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-move-drag
 * @see bim/table/table-entity-grips.ts — `applyTableGripDrag` (η ΜΙΑ αριθμητική της μεταφοράς)
 * @see ui/table-cell-editor/table-axis-resize-drag.ts — η αδελφή χειρονομία (μέγεθος)
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §66
 */

import { applyTableGripDrag, TABLE_MOVE_KIND } from '../../bim/table/table-entity-grips';
// §66 — ο ΕΝΑΣ αριθμός του subapp για «πόσο κουνήθηκε το χέρι πριν γίνει σύρσιμο» (ADR-516).
import { DXF_TIMING } from '../../config/dxf-timing';
import { tableEventWorldPoint } from './table-cell-pointer-hit';
// §66 — ο ΕΝΑΣ κύκλος ζωής χειρονομίας (ακροατές σύλληψης, «ένας τη φορά», ιδεμποτής τερματισμός).
import { createTablePointerDragSession } from './table-pointer-drag-session';
import type { RefObject } from 'react';
import type { TableEntity } from '../../types/table-entity';
import type { Point2D, ViewTransform } from '../../rendering/types/Types';

/** Ό,τι χρειάζεται η χειρονομία για να ζήσει. Καμία γνώση σκηνής — τη δίνει ο καλών. */
export interface TableMoveParams {
  /** Η οντότητα **τη στιγμή του πατήματος**: η αρχική θέση είναι η βάση κάθε καρέ. */
  readonly entity: TableEntity;
  readonly container: HTMLElement;
  readonly transformRef: RefObject<ViewTransform>;
  /** Ζωντανή προεπισκόπηση — καλείται σε **κάθε** κίνηση. Καμία καταγραφή αναίρεσης. */
  readonly preview: (entity: TableEntity, position: Point2D) => void;
  /** Η τελική θέση, **μία** φορά. Δεν καλείται καθόλου όταν το χέρι δεν πέρασε το κατώφλι. */
  readonly commit: (entity: TableEntity, position: Point2D) => void;
}

/**
 * Η **δική** της συνεδρία σύρσης — ο κοινός μηχανισμός, ποτέ κοινή κατάσταση: ένα κοινό slot
 * θα σήμαινε ότι ο τερματισμός της μετακίνησης σκοτώνει τη σύρση μεγέθους (δες την κεφαλίδα
 * του `table-pointer-drag-session`).
 */
const session = createTablePointerDragSession();

/**
 * Ξεκινά τη μετακίνηση από το τετραγωνάκι της γωνίας. Ιδεμποτής ως προς την προηγούμενη: μια
 * νέα χειρονομία **κλείνει** την προηγούμενη αντί να προστεθεί — το χέρι είναι ένα.
 *
 * Σιωπηλό no-op όταν το πάτημα δεν μεταφράζεται σε σημείο του κόσμου (χαμένη προβολή): χωρίς
 * αρχή δεν υπάρχει μετατόπιση να μετρηθεί, και μια σύρση με αυθαίρετη αρχή θα πετούσε τον
 * πίνακα στο πρώτο καρέ.
 */
export function beginTableMove(event: MouseEvent, params: TableMoveParams): void {
  const { entity, container, transformRef, preview, commit } = params;
  const origin = tableEventWorldPoint(event, container, transformRef.current);
  if (!origin) return;
  // Η αρχή σε px **οθόνης**: το κατώφλι μετρά πρόθεση ανθρώπου, όχι απόσταση στον κόσμο.
  const originClientX = event.clientX;
  const originClientY = event.clientY;

  // Η τελευταία θέση **αφού** περαστεί το κατώφλι. `null` ⇒ σκέτο κλικ ⇒ καμία εντολή, και ο
  // πίνακας δεν κουνήθηκε ποτέ ούτε στην προεπισκόπηση.
  let lastPosition: Point2D | null = null;

  const onMove = (moveEvent: MouseEvent): void => {
    if (
      Math.hypot(moveEvent.clientX - originClientX, moveEvent.clientY - originClientY)
      < DXF_TIMING.threshold.DRAG_PX
    ) {
      return;
    }
    const world = tableEventWorldPoint(moveEvent, container, transformRef.current);
    if (!world) return;
    // Η μετατόπιση μετριέται **πάντα από την αρχή**, ποτέ αθροιστικά ανά καρέ: έτσι μια χαμένη
    // ανάγνωση δεν αφήνει μόνιμο σφάλμα, και η θέση είναι συνάρτηση **μόνο** του πού είναι το
    // χέρι τώρα — δηλαδή ταυτόσημη με ό,τι θα έδινε η λαβή για το ίδιο συνολικό delta.
    const patch = applyTableGripDrag(
      TABLE_MOVE_KIND,
      entity,
      entity.position,
      { x: world.x - origin.x, y: world.y - origin.y },
    );
    if (!patch.position) return;
    lastPosition = patch.position;
    preview(entity, lastPosition);
  };

  const onUp = (): void => {
    // Η σειρά είναι το συμβόλαιο: **πρώτα** σβήνουν οι ακροατές, μετά γράφεται ο κόσμος. Το
    // commit αλλάζει τη σκηνή, δηλαδή μπορεί να παράγει συμβάντα· ακροατής που ζει ακόμα θα τα
    // έβλεπε ως συνέχεια της σύρσης που μόλις τελείωσε (ίδιος κανόνας με τη σύρση μεγέθους).
    const position = lastPosition;
    endTableMoveDrag();
    if (!position) return;
    // 🔴 Η επαναφορά **πριν** το commit — δες την κεφαλίδα: αλλιώς το στιγμιότυπο αναίρεσης
    // γεννιέται πάνω στην προεπισκόπηση και το `Ctrl+Z` γίνεται no-op.
    preview(entity, entity.position);
    commit(entity, position);
  };

  session.start({ onMove, onUp });
}

/**
 * Τερματίζει τη μετακίνηση **χωρίς** commit. Ιδεμποτής — και γι' αυτό μπορεί να κληθεί από το
 * cleanup ενός effect, όπου η συνεδρία μπορεί να έκλεισε με το κουμπί ακόμα κάτω: οι ακροατές
 * ζουν στο `document` και **δεν** θα έφευγαν μόνοι τους.
 *
 * ⚠️ Αφήνει τη σκηνή στην **τελευταία προεπισκόπηση**, όχι στην αρχική θέση. Είναι σκόπιμο και
 * είναι η συμπεριφορά και των τεσσάρων αδελφών χειρονομιών: η αποπροσάρτηση σημαίνει «ο πίνακας
 * έπαψε να επεξεργάζεται», όχι «άκυρο ό,τι έγινε» — για ακύρωση υπάρχει το `Ctrl+Z`.
 */
export function endTableMoveDrag(): void {
  session.end();
}

/** Test helper — «σέρνεται πίνακας τώρα;», χωρίς να εκτεθεί ο ίδιος ο κύκλος ζωής. */
export function isTableMoveDragging(): boolean {
  return session.isActive();
}
