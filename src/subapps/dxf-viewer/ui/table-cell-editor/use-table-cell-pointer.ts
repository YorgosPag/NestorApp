export interface UseTableCellPointerParams {
  readonly cursor: TableCellCursorState | null;
  /** Η **ζωντανή** οντότητα του δρομέα· `null` όταν ο πίνακας χάθηκε από κάτω του. */
  readonly entity: TableEntity | null;
  readonly containerRef: RefObject<HTMLDivElement | null>;
  readonly transformRef: RefObject<ViewTransform>;
  /** `Shift+κλικ` — δεύτερη γωνία περιοχής, χωρίς να κουνηθεί το ενεργό κελί. */
  readonly onSelectTo: (cell: TableCellRef) => void;
  /**
   * 🔴 ADR-739 §26.15 — **δέσμευσε ό,τι γράφεται τώρα, πριν κουνηθεί ο δρομέας**. No-op σε
   * πλοήγηση (δεν γράφεται τίποτα) και ιδεμποτής (μια δεύτερη κλήση με ίδιο κείμενο δεν
   * παράγει εντολή — `buildTableCellEditCommand` επιστρέφει `null`).
   *
   * ## Γιατί δεν αρκεί το commit του `blur`
   * Η σειρά του browser είναι αμείλικτη: ο ακροατής **σύλληψης** τρέχει **πριν** από τη
   * μεταφορά εστίασης, άρα πριν από κάθε `blur`. Αν εδώ μετακινηθεί πρώτα ο δρομέας, το
   * `setTableCellCursor` έχει ήδη **σβήσει το πρόχειρο** — και ο επεξεργαστής έχει
   * ξαναστηθεί σε `nav`, όπου το commit είναι εξ ορισμού σιωπηλό (και σωστά: ένα «γράψε το
   * άδειο πρόχειρο» θα **έσβηνε** το κελί). Αποτέλεσμα: η πληκτρολόγηση χάνεται χωρίς
   * μήνυμα.
   *
   * Δεν είναι νέος κανόνας — είναι ο **ίδιος** που τηρεί ήδη το πληκτρολόγιο: δες
   * `use-table-cell-session-keys`, `case 'move'`, «η σειρά είναι το συμβόλαιο: πρώτα
   * δεσμεύεται το πρόχειρο, μετά μετακινείται ο δρομέας». Το ποντίκι απλώς του έλειπε.
   */
  readonly onCommitPending: () => void;
}

export function useTableCellPointer(params: UseTableCellPointerParams): void {
  const { cursor, entity, containerRef, transformRef, onSelectTo, onCommitPending } = params;

  /**
   * 🔴 ADR-739 §27.16 Ε6 — **Ο ΧΕΙΡΙΣΤΗΣ ΕΧΕΙ ΣΤΑΘΕΡΗ ΤΑΥΤΟΤΗΤΑ, ΚΑΙ ΕΙΝΑΙ ΔΟΜΙΚΟ.**
   *
   * Εδώ ο χειριστής οριζόταν **μέσα** στο effect, άρα το effect εξαρτιόταν από τον **δρομέα**
   * — και το cleanup του καλεί `endTableCellDrag()`. Κάθε γραφή που κάνει **η ίδια η σύρση**
   * (`setTableCellSelection` σε κάθε αλλαγή κελιού· και στο πρώτο πάτημα το
   * `setTableCellCursor`) παράγει **νέο** αντικείμενο δρομέα ⇒ το effect ξανατρέχει ⇒ το
   * cleanup **σκότωνε τη σύρση που μόλις είχε ξεκινήσει**. Η νέα εκτέλεση ξαναγράφει μόνο
   * τον `mousedown`· τη σύρση δεν την ξαναστήνει κανείς.
   *
   * Μετρημένο ζωντανά (02/08, raw-CDP): σύρση `A2 → C4` ⇒ **καμία** επιλογή· και με το
   * πάτημα στο ήδη ενεργό κελί ⇒ επιλογή **παγωμένη στο πρώτο κελί που διασχίστηκε**.
   *
   * ## Γιατί `useEventCallback` και όχι «βγάλε το `cursor` από τις εξαρτήσεις»
   * Το δεύτερο θα έδινε **μπαγιάτικο** `cursor.selection` στο `extendWholeAxis` — το ίδιο
   * ακριβώς σφάλμα που ο ADR-040 απαγορεύει ονομαστικά («event handlers MUST receive
   * getters, not snapshot values — snapshots become stale when the orchestrator skips
   * re-renders»). Ο σταθεροποιητής δίνει **και** τα δύο: ταυτότητα που δεν αλλάζει ποτέ,
   * και ανάγνωση των **τελευταίων** τιμών τη στιγμή του συμβάντος. Δεν είναι νέος
   * μηχανισμός — είναι ο ΕΝΑΣ που ήδη χρησιμοποιεί το subapp σε τρία σημεία.
   */
  const handleMouseDown = useEventCallback((event: MouseEvent): void => {
    // Χωρίς ενεργό δρομέα δεν υπάρχει τίποτα να μετακινηθεί: το πρώτο κλικ σε πίνακα τον
    // **επιλέγει** ως οντότητα (δουλειά του καμβά), και η λειτουργία πίνακα ανοίγει με
    // διπλό κλικ ή `Enter`/`F2`. Ο φύλακας μετακόμισε από το effect **εδώ**, ώστε η
    // εγγραφή του ακροατή να μην εξαρτάται πια από το **περιεχόμενο** της συνεδρίας.
    if (!cursor || !entity) return;
    const container = containerRef.current;
    if (!container) return;

    // 🔴 ADR-739 §27.14 — ΔΥΟ πλήκτρα μπαίνουν, ΕΝΑ ενεργεί.
    //
    // Εδώ έγραφε `if (event.button !== 0) return;` με αιτιολογία «το δεξί ανοίγει το μενού
    // και δεν επιτρέπεται να μετακινήσει την επιλογή». Η αιτιολογία είναι **σωστή** — αλλά
    // η πρόωρη έξοδος έκανε **δύο** πράγματα, όχι ένα: μαζί με τη μετακίνηση απέκλεισε και
    // τη **δήλωση** του §26.15. Αποτέλεσμα: ο browser μετέφερε την εστίαση, ο φύλακας δεν
    // έβλεπε δήλωση, η συνεδρία **έκλεινε** — και όταν έφτανε το `contextmenu`, το
    // `getHit` του μενού ζωνών ρωτούσε δρομέα που δεν υπήρχε πια και απαντούσε `null`.
    // Ο δρομολογητής έπεφτε σωστά στο μενού **οντότητας**: αυτό ακριβώς ανέφερε ο Giorgio
    // ως «στις λωρίδες εμφανίζεται το μενού του καμβά».
    //
    // Ο κανόνας του §26.15 δεν είπε ποτέ «αριστερό»: είπε «**όποτε αυτός ο ακροατής
    // αναγνωρίζει ότι το πάτημα έπεσε μέσα στον δικό του πίνακα, το δηλώνει**». Εδώ ο
    // κανόνας απλώς εφαρμόζεται ακέραιος.
    const primary = event.button === 0;
    // Το μεσαίο πλήκτρο είναι pan του καμβά — ούτε δηλώνεται, ούτε μας αφορά.
    if (!primary && event.button !== 2) return;
    // ADR-739 §26.15 — το πάτημα έπεσε πάνω σε **πεδίο της ίδιας συνεδρίας**, όχι στον
    // καμβά: σε γραφή το `<textarea>` σκεπάζει το κελί, και το κλικ μέσα στο κείμενο είναι
    // **τοποθέτηση κέρσορα**. Ο ακροατής ζει στο ίδιο δοχείο και σε φάση σύλληψης, άρα το
    // βλέπει· χωρίς αυτόν τον φύλακα θα το ερμήνευε ως «κλικ στο κελί» και θα γύριζε τη
    // συνεδρία σε `nav` — δηλαδή θα σου έκοβε τη γραφή τη στιγμή που διορθώνεις ένα γράμμα.
    // Ο ίδιος ΕΝΑΣ ορισμός του «ανήκω στη συνεδρία», καμία δεύτερη σύγκριση.
    if (isTableCellSessionElement(event.target)) return;
    const transform = transformRef.current;
    const worldPoint = tableEventWorldPoint(event, container, transform);
    if (!worldPoint || !transform) return;

    // 🔴 ADR-739 §29 — **η ΜΙΑ ερώτηση «πού έπεσε;»**, η ίδια ακριβώς που ρωτά ο φύλακας
    // του κλειδώματος (`use-table-canvas-lockdown`). Ήταν δύο κλήσεις εδώ (ζώνη, μετά
    // κελί) με τη γεωμετρία υπολογισμένη τοπικά· εξήχθη ώστε να μην μπορεί να αποκλίνει
    // από την ερώτηση που αποφασίζει **αν** το συμβάν φτάνει καν εδώ. Δες την κεφαλίδα του
    // `table-cell-pointer-hit` για το τι θα σήμαινε μια απόκλιση έστω κατά ένα pixel.
    //
    // ADR-739 Φ.Δ βήμα 9 — η **σειρά** (ζώνη πριν από κελί) ζει πλέον μέσα σε εκείνη τη
    // συνάρτηση: ένα κλικ στο `B` επιλέγει ολόκληρη τη στήλη, στο `3` ολόκληρη τη γραμμή.
    const pointerHit = tablePointerHitAtWorld(entity, worldPoint, transform.scale);
    if (pointerHit?.where === 'band') {
      const bandHit = pointerHit.band;
      claimTableCellSessionPointerDown();
      // 🔴 ADR-739 §27.15 — και η **χειρονομία** δηλώνεται: χωρίς αυτό, το body-drag του
      // ADR-560 armάρει στα 3px και η σύρση επιλογής θα μετακινούσε τον πίνακα.
      claimTableCellPointerGesture();
      // §27.14 — το δεξί σταματά **εδώ**: δήλωσε και παραδώσου. Τα υπόλοιπα (άνοιγμα
      // μενού ζώνης) τα κάνει ο δρομολογητής στο `contextmenu`, που τώρα βρίσκει
      // ζωντανό δρομέα.
      if (!primary) return;
      // 🔴 §27.16 Ε2 — `Shift+κλικ` σε δεύτερο γράμμα/αριθμό: **επέκταση**, όχι νέα επιλογή.
      // Δοκιμάζεται πρώτη γιατί είναι η πιο **ειδική** ερώτηση· όταν δεν ισχύει (καμία
      // επιλογή, ή επιλογή άλλου είδους) επιστρέφει `null` και το πάτημα συνεχίζει στον
      // κανονικό δρόμο — δηλαδή γίνεται σκέτο κλικ, χωρίς καμία εφεύρεση.
      const shiftAnchor = event.shiftKey
        ? extendWholeAxis(entity, bandHit, cursor.selection)
        : null;
      if (shiftAnchor) {
        startTableCellDrag({
          anchor: shiftAnchor,
          kind: bandHit.axis,
          container,
          resolveAt: (moveEvent) => axisEndAt(moveEvent, entity, container, transformRef, bandHit.axis),
        });
        return;
      }
      // Η ζώνη μετακινεί το ενεργό κελί στην αρχή του άξονα, άρα ισχύει το ίδιο συμβόλαιο
      // με το απλό κλικ: ό,τι γράφεται δεσμεύεται πρώτα.
      onCommitPending();
      const axisAnchor = selectWholeAxis(entity, bandHit);
      // Σύρση **πάνω στα γράμματα/αριθμούς** = πολλές ολόκληρες στήλες/γραμμές (Excel).
      // Η άγκυρα είναι η αρχή του άξονα· το κινούμενο άκρο ακολουθεί μόνο τη θέση κατά
      // μήκος του άξονα, γι' αυτό και το `tableAxisTickAtFrame` αγνοεί τη ζώνη.
      if (axisAnchor) {
        startTableCellDrag({
          anchor: axisAnchor,
          kind: bandHit.axis,
          container,
          resolveAt: (moveEvent) => axisEndAt(moveEvent, entity, container, transformRef, bandHit.axis),
        });
      }
      return;
    }

    // Το κλικ πρέπει να πέσει μέσα στο πλέγμα **αυτού** του πίνακα.
    //
    // 🔴 ADR-739 §29 — **ΤΟ ΣΧΟΛΙΟ ΕΔΩ ΕΛΕΓΕ ΤΟ ΑΝΤΙΘΕΤΟ ΚΑΙ ΗΤΑΝ ΣΩΣΤΟ ΤΟΤΕ.** Έγραφε:
    // «έξω από αυτό — αλλού στον καμβά, ή στα περιθώρια του πίνακα — δεν μας αφορά: ο
    // καμβάς θα κάνει ό,τι κάνει πάντα, και η συνεδρία θα κλείσει μόνη της από τον φύλακα
    // εστίασης». Αυτή ήταν η μισή προδιαγραφή του §26.15, ρητά επαληθευμένη ζωντανά. Ο
    // ιδιοκτήτης την **άλλαξε**: το κλικ έξω δεν είναι πια τρόπος εξόδου.
    //
    // Η αλλαγή **δεν** έγινε εδώ, και ο λόγος είναι δομικός: αυτός ο ακροατής ζει στο
    // δοχείο και τρέχει **μετά** από τους ακροατές σύλληψης του `document`, ενώ η επιλογή
    // οντότητας γεννιέται στο `mouseup` — δηλαδή σε συμβάν που αυτό το αρχείο δεν ακούει
    // καθόλου. Το «έξω» το κόβει πλέον ο φύλακας του §29, **πριν** φτάσει οπουδήποτε.
    // Εδώ μένει η αρχική, ακέραιη σημασία: «δεν είναι δικό μου, δεν το αγγίζω».
    if (pointerHit === null) return;
    const hit = pointerHit.cell;

    // ADR-739 §26.15 — από εδώ και κάτω το πάτημα **είναι** της συνεδρίας. Η δήλωση
    // γίνεται ΠΡΙΝ από κάθε εγγραφή, ώστε να ισχύει και για τους δύο δρόμους που
    // ακολουθούν: και το `Shift+κλικ` (που δεν μετακινεί δρομέα) πρέπει να κρατήσει το
    // πληκτρολόγιο, αλλιώς φτιάχνεις περιοχή και μένεις χωρίς πίνακα.
    claimTableCellSessionPointerDown();
    // §27.15 — δες το δίδυμο σχόλιο στη ζώνη: η οντότητα δεν μετακινείται από πάτημα που
    // σημαδεύει κελί.
    claimTableCellPointerGesture();

    // §27.14 — ίδιος κανόνας μέσα στο πλέγμα: το δεξί κρατά τη συνεδρία ζωντανή αλλά
    // **δεν αγγίζει τίποτα**. Το μενού οντότητας που θα ανοίξει αφορά τον πίνακα ως
    // αντικείμενο· χωρίς τη δήλωση θα άφηνε πίσω του «επιλεγμένος πίνακας χωρίς δρομέα»,
    // δηλαδή ακριβώς την κατάσταση-φάντασμα που κατέγραψε το §27.10.
    if (!primary) return;

    if (event.shiftKey) {
      // ΚΑΜΙΑ δέσμευση εδώ, ακριβώς όπως στο `Shift+βέλος` (`case 'extend'`): η επέκταση
      // περιοχής είναι κατάσταση **διεπαφής** και δεν αγγίζει το μοντέλο.
      onSelectTo({ rowId: hit.rowId, colId: hit.colId });
      return;
    }
    onCommitPending();
    // Απλό κλικ: **νέα** στήλη αγκύρωσης (`tableCursorAt`) — ένα κλικ ξεκινά καινούρια
    // σειρά καταχώρισης, άρα το επόμενο `Enter` επιστρέφει ΕΔΩ. Κατάσταση `nav`: έδειξες
    // κελί, δεν άρχισες να γράφεις· η γραφή ξεκινά με τον πρώτο χαρακτήρα (Excel).
    setTableCellCursor(entity.id, tableCursorAt(hit.rowId, hit.colId), 'nav');

    // 🔴 ADR-739 §27.15 — από εδώ αρχίζει η **σύρση**. Καμία επιλογή δεν γράφεται τώρα:
    // ένα σκέτο κλικ πρέπει να μείνει σκέτο κλικ («καμία επιλογή ≠ επιλογή 1×1», ρητή
    // απόφαση του βήματος 8 που ο Giorgio επιβεβαίωσε στις 02/08). Η πρώτη επιλογή
    // γεννιέται μόνο όταν το χέρι φτάσει σε **άλλο** κελί — γι' αυτό η άγκυρα του
    // `startTableCellDrag` είναι κι αυτή ο φύλακας «άλλαξε κελί;».
    //
    // 🔴 §27.16 Ε6 — **αυτή η σύρση επιβιώνει πλέον των δικών της εγγραφών**: ο ακροατής
    // δεν ξαναγράφεται σε κάθε αλλαγή δρομέα, άρα το cleanup δεν τη σκοτώνει στη γέννα.
    startTableCellDrag({
      anchor: { rowId: hit.rowId, colId: hit.colId },
      kind: 'range',
      // §27.16 Ε1 — το ίδιο δοχείο που δίνει τη γεωμετρία δίνει και την **άκρη**: μία
      // μέτρηση, δύο ερωτήσεις («πού είμαι στον κόσμο;» / «πόσο κοντά στην άκρη;»).
      container,
      resolveAt: (moveEvent) => cellEndAt(moveEvent, entity, container, transformRef),
    });
  });

  /**
   * 🔴 §27.16 Ε6 — **η ΥΠΑΡΞΗ της συνεδρίας, όχι το περιεχόμενό της.**
   *
   * Η εξάρτηση είναι σκόπιμα **δυαδική**: αλλάζει μόνο όταν ανοίγει ή κλείνει η λειτουργία
   * πίνακα — δηλαδή δύο φορές ανά συνεδρία — και **ποτέ** από τις εκατοντάδες εγγραφές
   * δρομέα/επιλογής που παράγει η ίδια η σύρση. Έτσι διατηρείται ακέραια η αρχική πρόθεση
   * («καμία διαρροή ακροατή όταν δεν χρειάζεται») χωρίς να επιστρέφει το σφάλμα.
   */
  const hasSession = Boolean(cursor && entity);

  useEffect(() => {
    if (!hasSession) return;
    const container = containerRef.current;
    if (!container) return;

    // Φάση **σύλληψης**: ο δρομέας μετακινείται πριν ο καμβάς ερμηνεύσει τη χειρονομία, ώστε
    // ο ζωγράφος να δει τη νέα θέση στο ίδιο καρέ. Καμία κατανάλωση του συμβάντος — δες την
    // κεφαλίδα.
    container.addEventListener('mousedown', handleMouseDown, { capture: true });
    return () => {
      container.removeEventListener('mousedown', handleMouseDown, { capture: true });
      // §27.15 — η συνεδρία έκλεισε (ή άλλαξε πίνακας) με το κουμπί ακόμα κάτω: οι ακροατές
      // της σύρσης ζουν στο `document` και **δεν** θα έφευγαν μόνοι τους.
      endTableCellDrag();
    };
  }, [hasSession, containerRef, handleMouseDown]);
}

/** Το κινούμενο άκρο μιας σύρσης **κελιών**· `null` έξω από το πλέγμα (η επιλογή μένει). */
function cellEndAt(
  event: MouseEvent,
  entity: TableEntity,
  container: HTMLElement,
  transformRef: RefObject<ViewTransform>,
): TableCellRef | null {
  const world = tableEventWorldPoint(event, container, transformRef.current);
  if (!world) return null;
  const hit = tableCellAtWorld(entity, world, computeTableEntityGeometryLive(entity));
  return hit ? { rowId: hit.rowId, colId: hit.colId } : null;
}

/**
 * Το κινούμενο άκρο μιας σύρσης **άξονα** (πάνω στα γράμματα ή στους αριθμούς).
 *
 * Η θέση κατά μήκος του άξονα είναι το μόνο που μετράει — όπως στο Excel, όπου η σύρση
 * `B → D` συνεχίζει να επιλέγει στήλες ακόμα κι αν το χέρι ξεφύγει κατακόρυφα από τη
 * λωρίδα. Το άλλο άκρο καρφώνεται στο **τέλος** του πλέγματος, ώστε η στήλη/γραμμή να
 * μένει **ολόκληρη** σε κάθε καρέ της σύρσης.
 *
 * 🔴 §27.16 Ε2 — το «τέλος του πλέγματος» **δεν ξαναγράφεται εδώ**: είναι το `to` της
 * {@link wholeAxisSelection}, δηλαδή η ίδια έκφραση που δίνει και το σκέτο κλικ. Πριν
 * υπήρχε δεύτερη φορά, λίγες γραμμές πιο κάτω — δύο αντίγραφα που κανένα εργαλείο δεν
 * θα έπιανε και που θα απέκλιναν στην πρώτη αλλαγή.
 */
function axisEndAt(
  event: MouseEvent,
  entity: TableEntity,
  container: HTMLElement,
  transformRef: RefObject<ViewTransform>,
  axis: 'column' | 'row',
): TableCellRef | null {
  const tick = axisTickAt(event, entity, container, transformRef, axis);
  return tick ? (wholeAxisSelection(entity.model, tick)?.to ?? null) : null;
}

/** Σε ποια στήλη/γραμμή δείχνει το συμβάν **κατά μήκος** του άξονα· `null` έξω από αυτόν. */
function axisTickAt(
  event: MouseEvent,
  entity: TableEntity,
  container: HTMLElement,
  transformRef: RefObject<ViewTransform>,
  axis: 'column' | 'row',
): TableIndicatorHit | null {
  const world = tableEventWorldPoint(event, container, transformRef.current);
  if (!world) return null;
  const geometry = computeTableEntityGeometryLive(entity);
  const frame = tableWorldToFrame(entity, world, geometry.mmToWorld);
  return tableAxisTickAtFrame(geometry.layout, frame, axis);
}

/**
 * Επιλογή **ολόκληρης** στήλης ή γραμμής.
 *
 * Δεν χρειάζεται νέος τύπος επιλογής: η περιοχή είναι ήδη «δύο γωνίες», και μια ολόκληρη
 * στήλη είναι απλώς η γωνία (πρώτη γραμμή, αυτή η στήλη) ως την (τελευταία γραμμή, αυτή η
 * στήλη). Το ενεργό κελί πάει στην **αρχή** του άξονα, όπως στο Excel: εκεί αρχίζει η
 * πληκτρολόγηση αν συνεχίσεις να γράφεις.
 *
 * Η σειρά μετράει: το `setTableCellCursor` **διαλύει** κάθε υπάρχουσα περιοχή (τεκμηριωμένο
 * στο store), οπότε η επιλογή γράφεται μετά — αλλιώς θα έσβηνε τη στιγμή που γεννιέται.
 *
 * Επιστρέφει την **άγκυρα** (τη γωνία που μένει) για τη σύρση που μπορεί να ακολουθήσει·
 * `null` σε πίνακα χωρίς γραμμές ή χωρίς στήλες.
 */
function selectWholeAxis(entity: TableEntity, hit: TableIndicatorHit): TableCellRef | null {
  // 🔴 ADR-739 §27.15/§27.16 — η πρόθεση ταξιδεύει μαζί με τις γωνίες, και τις **τρεις** τις
  // παράγει ο ΕΝΑΣ ορισμός. Ο άξονας **δεν κουμπώνει** σε συγχωνεύσεις: ο πίνακας της
  // σκηνής έχει τίτλο συγχωνευμένο σε όλες τις στήλες, και χωρίς αυτή τη λέξη το «κλικ στο
  // B» μάρκαρε **ολόκληρο τον πίνακα** (Giorgio, 02/08).
  const selection = wholeAxisSelection(entity.model, hit);
  if (!selection) return null;

  setTableCellCursor(entity.id, tableCursorAt(selection.from.rowId, selection.from.colId), 'nav');
  setTableCellSelection(selection);
  return selection.from;
}

/**
 * 🔴 ADR-739 §27.16 Ε2 — **`Shift+κλικ` σε δεύτερο γράμμα/αριθμό**.
 *
 * Excel: κλικ στο «A», `Shift+κλικ` στο «C» ⇒ **τρεις ολόκληρες στήλες**. Επιστρέφει την
 * **άγκυρα** που μένει (για τη σύρση που μπορεί να ακολουθήσει), ή `null` όταν αυτό το
 * πάτημα **δεν** είναι επέκταση και πρέπει να το χειριστεί ο κανονικός δρόμος.
 *
 * ## Επεκτείνει ΜΟΝΟ όταν η τρέχουσα επιλογή είναι του ΙΔΙΟΥ άξονα — και γιατί
 * Αν η τρέχουσα επιλογή είναι **περιοχή** (ή ο άλλος άξονας) και ο χρήστης κάνει
 * `Shift+κλικ` σε γράμμα στήλης, δεν υπάρχει σωστό `kind` για το αποτέλεσμα: κάθε επιλογή
 * θα ήταν **εφεύρεση**. Το §27.15 έβγαλε ρητά την προεπιλογή από το `kind` ακριβώς για να
 * μην μπορεί να συμβεί σιωπηλά αυτό. Άρα το πάτημα πέφτει πίσω στη συμπεριφορά του σκέτου
 * κλικ — **νέα** επιλογή άξονα, ακριβώς αυτό που βλέπει ο χρήστης σε κάθε φύλλο υπολογισμού
 * όταν αλλάζει είδος επιλογής.
 *
 * ## Καμία δέσμευση προχείρου — και είναι κανόνας, όχι παράλειψη
 * Ο κανόνας που ισχύει παντού στη συνεδρία: **δεσμεύεις μόνο όταν κουνιέται το ενεργό
 * κελί**. Η επέκταση δεν το κουνά (ίδια σύμβαση με `Shift+βέλος` και `Shift+κλικ` σε κελί).
 */
function extendWholeAxis(
  entity: TableEntity,
  hit: TableIndicatorHit,
  selection: TableSelectionSpan | null | undefined,
): TableCellRef | null {
  if (!selection || selection.kind !== hit.axis) return null;
  const target = wholeAxisSelection(entity.model, hit);
  if (!target) return null;
  // Ο ΕΝΑΣ επεκτατής — ο ίδιος που εξυπηρετεί το `Shift+βέλος` (§27.16 Ε2).
  const extended = extendTableSelectionTo(selection, target.to);
  setTableCellSelection(extended);
  return extended.from;
}
