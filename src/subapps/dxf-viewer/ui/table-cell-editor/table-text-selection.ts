'use client';

/**
 * 🔴 ADR-753 Φ4 — **η επιλογή χαρακτήρων, ΠΑΓΩΜΕΝΗ**: ό,τι μάρκαρε ο χρήστης τη στιγμή του
 * δεξιού κλικ, μαζί με την απόδειξη ότι εξακολουθεί να ισχύει.
 *
 * ## 🔴 ΓΙΑΤΙ ΠΑΓΩΝΕΙ — και γιατί δεν διαβάζεται τη στιγμή του πατήματος
 * Η γραμμή εργαλείων παίρνει την **εστίαση** μόλις την πατήσεις. Τη στιγμή που ο χειριστής του
 * «Β» τρέχει, το πεδίο κειμένου έχει ήδη χάσει το πληκτρολόγιο — και μια ανάγνωση
 * `selectionStart` εκείνη τη στιγμή απαντά για **άλλη κατάσταση** από αυτήν που έβλεπε ο
 * χρήστης όταν έκανε δεξί κλικ. Δεν είναι θεωρητικό: είναι ο λόγος που η μορφοποίηση θα
 * έβαφε είτε τίποτα είτε λάθος γράμματα.
 *
 * Το πάγωμα γίνεται **μία** φορά, στο άνοιγμα, και ζει όσο η γραμμή: η μορφοποίηση είναι
 * κατεξοχήν επαναλαμβανόμενη πράξη («έντονα, μετά πλάγια, μετά ένα μέγεθος πάνω», §28.13) και
 * τα **τρία** πατήματα οφείλουν να δείχνουν στα **ίδια** γράμματα.
 *
 * ## 🔴 ΤΟ ΚΕΙΜΕΝΟ ΤΑΞΙΔΕΥΕΙ ΜΑΖΙ ΜΕ ΤΟΥΣ ΔΕΙΚΤΕΣ — αλλιώς δεν υπάρχει «μπαγιάτικο»
 * Δύο αριθμοί δεν μπορούν να πουν αν εξακολουθούν να δείχνουν στα ίδια γράμματα: το `[2,5)`
 * είναι εξίσου έγκυρο πριν και μετά από μια πληκτρολόγηση, και **δείχνει αλλού**. Ο μόνος
 * τρόπος να μαθευτεί είναι το κείμενο πάνω στο οποίο μετρήθηκαν. Ίδια αρχή με το
 * compare-and-swap του ADR-769: **η βάση σύγκρισης ταξιδεύει με το αίτημα.**
 *
 * ⚠️ Η μορφοποίηση **δεν αγγίζει** το κείμενο, οπότε στη συνήθη ροή η επιλογή δεν παλιώνει
 * ποτέ ανάμεσα σε δύο πατήματα. Ο έλεγχος υπάρχει για την ασυνήθιστη: `Ctrl+Z` από
 * συντόμευση, ή ο χρήστης που ξαναπιάνει το πεδίο και πληκτρολογεί ενώ η γραμμή είναι ακόμη
 * ανοιχτή.
 *
 * ## Τι ΔΕΝ ξαναγράφτηκε
 * Το §67 είχε επίσης `selectedTableText` / `replaceTableTextSelection`, για εντολές
 * προχείρου που **διαγράφηκαν** στο §67.10 (ζουν στα `Ctrl+X`/`C`/`V` του browser). Δεν
 * επιστρέφουν: μια συνάρτηση χωρίς καλούντα είναι νεκρός κώδικας με πράσινα tests από πάνω της.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-text-selection
 * @see ui/table-cell-editor/use-table-text-toolbar.ts — ποιος την παγώνει και πότε τη ρωτά
 * @see bim/table/table-cell-run-ops.ts — τι σημαίνουν οι δείκτες στο μοντέλο
 */

import type { TableTextField } from '../components/table-text-menu/table-text-toolbar-types';
import type { TableTextAnchoredRange } from '../../bim/table/table-cell-run-ops';
// 🔴 ADR-753 §28 — οι τρεις πράξεις που κάνουν ένα πεδίο «πεδίο». Το κελί έγινε
// `contenteditable` ώστε η μορφοποίηση να φαίνεται όσο γράφεις· **αυτό** το αρχείο δεν
// άλλαξε σημασιολογία, μόνο ποιος απαντά τις ερωτήσεις του.
import {
  setTableTextFieldSelection,
  tableTextFieldSelection,
  tableTextFieldValue,
} from './table-text-field-ops';

/**
 * Ό,τι μάρκαρε ο χρήστης, **κανονικοποιημένο** και με τη βάση σύγκρισής του.
 *
 * Τα άκρα είναι πάντα σε σειρά (`start <= end`), ώστε κανένας καταναλωτής να μη χρειάζεται να
 * θυμάται την **ανάποδη σύρση** — το DOM δίνει `selectionStart <= selectionEnd` και ξεχωριστά
 * το `selectionDirection`, αλλά η μορφοποίηση δεν έχει φορά.
 *
 * ## 🔴 ADR-753 §25 — ΕΙΝΑΙ ο τύπος του καθαρού επιπέδου, όχι δίδυμός του
 * Το «δείκτες + η βάση τους» δηλωνόταν **δύο** φορές: εδώ (ανάγνωση από το DOM) και, άγραφα,
 * στον στόχο-γράμματα του `table-format-scope.ts`. Δύο δηλώσεις της ίδιας τριάδας είναι δύο
 * ευκαιρίες να ταξιδέψει η μία χωρίς την άλλη — και ταξίδεψε (§25). Ένα ψευδώνυμο και όχι
 * `extends`: δεν προστίθεται **τίποτα** εδώ, και μια κενή επέκταση θα δήλωνε ότι προστίθεται.
 */
export type TableTextSelection = TableTextAnchoredRange;

/**
 * Η τρέχουσα επιλογή του πεδίου.
 *
 * ⚠️ Το `selectionStart` / `selectionEnd` είναι `number | null` στον τύπο του DOM (είναι
 * `null` για τύπους `input` που δεν υποστηρίζουν επιλογή, π.χ. `email`). Και τα δύο πεδία της
 * συνεδρίας είναι `textarea` / `input[type=text]`, οπότε στην πράξη δεν είναι ποτέ — αλλά η
 * πτώση στο **τέλος του κειμένου** είναι η ίδια σύμβαση με το `useTableCellCaret` («απόν
 * ⇒ τέλος»), όχι εφευρημένο μηδέν που θα έβαφε την αρχή του κελιού.
 */
export function readTableTextSelection(field: TableTextField): TableTextSelection {
  const { start, end } = tableTextFieldSelection(field);
  return { start, end, text: tableTextFieldValue(field) };
}

/** Μάρκαρε ο χρήστης **έστω έναν** χαρακτήρα; Σκέτος δρομέας ⇒ `false`. */
export function hasTableTextSelection(selection: TableTextSelection): boolean {
  return selection.end > selection.start;
}

/**
 * Δείχνει ακόμη η παγωμένη επιλογή στα **ίδια γράμματα**;
 *
 * Σύγκριση του **κειμένου**, όχι των ορίων: δείκτες μέσα στο μήκος είναι πάντα «έγκυροι» και
 * αυτό ακριβώς είναι η παγίδα — μια πληκτρολόγηση αφήνει το `[2,5)` έγκυρο και το κάνει να
 * δείχνει σε άλλα γράμματα, σιωπηλά.
 */
export function isStaleTableTextSelection(
  selection: TableTextSelection,
  field: TableTextField,
): boolean {
  return tableTextFieldValue(field) !== selection.text;
}

/**
 * 🔴 Ξαναδηλώνει την επιλογή στο πεδίο.
 *
 * ## ⚠️ ADR-753 §28 — ΑΠΟ «belt-and-suspenders» ΕΓΙΝΕ **Ο ΜΗΧΑΝΙΣΜΟΣ**
 * Εδώ έγραφε ότι είναι δίχτυ ασφαλείας (N.7.2 #4) και **ήταν**, όσο το κελί ήταν `textarea`:
 * οι browsers διατηρούν `selectionStart`/`selectionEnd` όταν ένα πεδίο χάνει την εστίαση και
 * τα ξαναδείχνουν όταν την ξαναπάρει, οπότε στη συνήθη ροή δεν χρειαζόταν τίποτα.
 *
 * Ο **πλούσιος** επεξεργαστής δεν έχει δικά του άκρα να θυμηθεί: η επιλογή ενός
 * `contenteditable` ζει στο **έγγραφο**, και το έγγραφο έχει μία — μόλις η γραμμή εργαλείων
 * πάρει την εστίαση, τα γράμματα ξεμαρκάρονται. Άρα από το §28 και μετά αυτή η κλήση **είναι**
 * ο λόγος που ο χρήστης βλέπει τα «ΩΡ» ακόμη μαρκαρισμένα μετά το τρίτο πάτημα, όπως στο Excel.
 *
 * Το πάγωμα του Φ4 (`selectionRef`) ήταν ήδη η σωστή απόφαση για άλλον λόγο· τώρα είναι και η
 * **μόνη** πηγή που ξέρει τι μάρκαρε ο χρήστης. Καμία γραμμή δεν άλλαξε γι' αυτό — αλλά αν
 * κάποιος σβήσει αυτή την κλήση «γιατί είναι περιττή», η επιλογή θα χάνεται στο πρώτο πάτημα.
 *
 * ## ⚠️ ΔΥΟ φρουροί, και ο καθένας αποτρέπει διαφορετική βλάβη
 * 1. **Εστιασμένο πεδίο ⇒ σιωπή.** Αν ο χρήστης ξαναπήρε μόνος του το πληκτρολόγιο και
 *    μετακίνησε τον δρομέα, μια επιβολή θα **πάλευε μαζί του** — ακριβώς ο λόγος που το
 *    `restoreFocus` του ιδιοκτήτη γυρίζει την εστίαση μόνο αν την είχε η γραμμή.
 * 2. **Μπαγιάτικο κείμενο ⇒ σιωπή.** Δείκτες πάνω σε άλλο κείμενο δεν είναι «σχεδόν σωστοί»·
 *    δείχνουν αλλού.
 *
 * **Δεν** αγγίζει την εστίαση: αυτή είναι δουλειά **ενός** μηχανισμού, και υπάρχει ήδη.
 */
export function restoreTableTextSelection(
  field: TableTextField,
  selection: TableTextSelection,
): void {
  if (typeof document !== 'undefined' && document.activeElement === field) return;
  if (isStaleTableTextSelection(selection, field)) return;
  setTableTextFieldSelection(field, selection.start, selection.end);
}
