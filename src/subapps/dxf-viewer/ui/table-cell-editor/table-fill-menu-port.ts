'use client';

/**
 * 🔴 ADR-828 §7.2 — **η θύρα του μενού δεξιού συρσίματος της λαβής**.
 *
 * ## 🔴 ΓΙΑΤΙ ΘΥΡΑ ΚΑΙ ΟΧΙ ΠΕΡΑΣΜΑ ΑΠΟ ΤΟΝ ΔΡΟΜΟΛΟΓΗΤΗ ΔΕΞΙΟΥ ΚΛΙΚ
 * Ο `useCanvasContextMenu` **καταπνίγει ρητά** κάθε μενού που ακολουθεί δεξί σύρσιμο πάνω από
 * 5px (`rightDragMoved` ⇒ `preventDefault()` και τέλος), γιατί εκεί το δεξί σύρσιμο σημαίνει
 * **pan** — υβριδική συμπεριφορά BricsCAD, και σωστή για τον καμβά. Η ίδια χειρονομία πάνω
 * στη λαβή συμπλήρωσης σημαίνει κάτι εντελώς άλλο.
 *
 * Δεν «χαλαρώνει» ο δρομολογητής: μια εξαίρεση εκεί θα σήμαινε ότι ο κανόνας «δεξί σύρσιμο =
 * pan, χωρίς μενού» αποκτά κρυφό αστερίσκο που κανείς δεν βλέπει διαβάζοντάς τον. Αντ' αυτού
 * η χειρονομία **δεν περνά καθόλου** από εκεί: το `mouseup` της λαβής ανοίγει το μενού μόνο
 * του, και ο δρομολογητής συνεχίζει να καταπνίγει —σωστά— το `contextmenu` που ακολουθεί.
 *
 * ## Γιατί ο στόχος φέρνει μαζί του την **πράξη**
 * Οι αδελφές θύρες (`table-range-menu-port`, `table-header-menu-port`) δίνουν συντεταγμένες
 * και το μενού βρίσκει μόνο του τι εννοούν. Εδώ ο στόχος **δεν είναι σημείο**: είναι μια
 * χειρονομία που ήδη τελείωσε — πηγή, στόχος και η **μία** διαδρομή εγγραφής μοντέλου που ο
 * φρουρός της λαβής κρατά ήδη στα χέρια του (`press.commit`). Ένα μενού που τα ξαναβρίσκει
 * μόνο του θα χρειαζόταν **δεύτερη** διαδρομή εγγραφής και **δεύτερη** ανάγνωση της σκηνής —
 * δηλαδή δύο ευκαιρίες να διαφωνήσει με τη σύρση που μόλις είδε ο χρήστης.
 *
 * ⚠️ Το {@link TableFillMenuTarget.apply} διαβάζει τη σκηνή **τη στιγμή του πατήματος**, όχι
 * τη στιγμή του ανοίγματος (ADR-040 κανόνας #2): ανάμεσα στα δύο χωρά `Ctrl+Z`.
 *
 * @module subapps/dxf-viewer/ui/table-cell-editor/table-fill-menu-port
 * @see ui/table-cell-editor/table-fill-handle-drag.ts — ποιος το ανοίγει
 * @see ui/components/TableFillOptionsMenu.tsx — ποιος το σερβίρει
 * @see docs/centralized-systems/reference/adrs/ADR-828-table-autofill-series.md §7.2
 */

import type { TableFillMenuOffer, TableFillMode } from '../../bim/table/table-fill-plan';

/** Ό,τι ξέρει το μενού για τη σύρση που μόλις τελείωσε — **παγωμένο στο άνοιγμα**. */
export interface TableFillMenuTarget {
  /** Ποιες εντολές έχουν νόημα, από τη **μία** ανίχνευση που έτρεξε ήδη. */
  readonly offer: TableFillMenuOffer;
  /**
   * Εκτέλεσε το γέμισμα με αυτή την πρόθεση. Κλειστό πάνω στη **μία** διαδρομή εγγραφής της
   * χειρονομίας — ένα βήμα undo, όπως και το αριστερό σύρσιμο.
   */
  readonly apply: (mode: TableFillMode) => void;
  /**
   * 🔴 ADR-828 Φ4β — τα **κείμενα της πηγής**, πρόταση για το «Σειρά…».
   *
   * Παγωμένα στο άνοιγμα όπως όλα τα άλλα εδώ, και για τον ίδιο λόγο: όταν ο άνθρωπος πατά
   * το item, το μενού **κλείνει** και η επιλογή έχει ήδη αλλάξει. Ένας ξενιστής που τα
   * ρωτούσε μόνος του θα διάβαζε ό,τι υπάρχει **μετά** — δηλαδή τίποτα.
   */
  readonly seeds: readonly string[];
}

interface TableFillMenuPort {
  /** Άνοιξε το μενού στο σημείο **απελευθέρωσης**, με τον στόχο παγωμένο. */
  readonly open: (clientX: number, clientY: number, target: TableFillMenuTarget) => void;
}

let port: TableFillMenuPort | null = null;

/** Ο κάτοχος του μενού δηλώνεται όσο είναι μονταρισμένος· `null` τον αποσύρει. */
export function setTableFillMenuPort(next: TableFillMenuPort | null): void {
  port = next;
}

/**
 * Ανάγνωση τη στιγμή του συμβάντος — ποτέ στιγμιότυπο σε κλείσιμο.
 *
 * `null` σημαίνει «κανείς δεν σερβίρει»: τότε η δεξιά σύρση **δεν γράφει τίποτα**, που είναι
 * η σωστή σιωπή. Η εναλλακτική («αφού δεν υπάρχει μενού, κάνε το προεπιλεγμένο») θα έγραφε
 * μοντέλο για χειρονομία της οποίας όλο το νόημα είναι ότι ο άνθρωπος **δεν έχει ακόμη
 * διαλέξει**.
 */
export function getTableFillMenuPort(): TableFillMenuPort | null {
  return port;
}
