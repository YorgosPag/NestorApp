'use client';

/**
 * ADR-739 §29 + §30 + §39 — **ΤΙ ΑΚΟΥΕΙ Ο ΚΑΜΒΑΣ ΟΣΟ ΥΠΑΡΧΕΙ ΠΙΝΑΚΑΣ**: το κλείδωμα του
 * ποντικιού και ο hover των λωρίδων δείκτη. Καθαρή σύνδεση — μηδέν δική του κατάσταση,
 * μηδέν γεωμετρία, μηδέν απόφαση· τις παίρνουν τα δύο hooks που καλεί.
 *
 * ## Γιατί υπάρχει ως ξεχωριστό module
 * Γεννήθηκε ως **εξαγωγή** από το `useTableCellDoubleClickEditor.ts` τη στιγμή που εκείνο
 * ξαναχτύπησε τις 500 γραμμές (N.7.1) — για **τέταρτη** φορά. Δεν διαλέχτηκε επειδή ήταν το
 * μεγαλύτερο κομμάτι, αλλά επειδή ήταν **αυτό που μεγάλωσε**: το §39 πρόσθεσε εδώ τον
 * επιλυτή επιλεγμένου πίνακα και άλλαξε τη συνθήκη ενεργοποίησης. Ό,τι μεγαλώνει, φεύγει.
 *
 * Ο διαχωρισμός είναι σημασιολογικός και όχι αριθμητικός: ο γονιός απαντά «**ποιο κελί,
 * πού, με τι όψη**» (μοντέλο + DOM του επεξεργαστή)· εδώ ζει «**τι επιτρέπεται στον καμβά
 * από κάτω**» — δύο ερωτήσεις που τυχαίνει να μοιράζονται τη ζωντανή οντότητα, τίποτα άλλο.
 *
 * 🔑 **Οι δύο συνθήκες ΔΕΝ είναι η ίδια τιμή, και αυτό είναι το νόημα** — δες τα σχόλια
 * στις δύο κλήσεις παρακάτω. Ζουν μαζί ακριβώς για να φαίνεται η διαφορά τους δίπλα-δίπλα.
 *
 * @see ui/table-cell-editor/use-table-canvas-lockdown.ts — §29, το κλείδωμα
 * @see ui/table-cell-editor/use-table-indicator-hover.ts — §30 + §39, ο hover + το ⊕
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §29, §30, §39
 */

import { useCallback } from 'react';
import type React from 'react';
import { resolveSelectedTable, resolveTableAtWorld } from './table-entity-lookup';
// ADR-739 §29 — το δίδυμο του modal keyboard scope για το ποντίκι: όσο ζει η λειτουργία
// πίνακα, ο καμβάς δεν επιλέγει, δεν σέρνει και δεν κάνει hover σε οντότητες.
import { useTableCanvasLockdown } from './use-table-canvas-lockdown';
// ADR-739 §30 — ο hover των λωρίδων δείκτη (Excel). Παθητικός ακροατής `mousemove`, ο μόνος
// που το κλείδωμα του §29 αφήνει να περάσει (το pan ζει πάνω του).
import { useTableIndicatorHover } from './use-table-indicator-hover';
// ADR-739 §39 — το **πάτημα** του ⊕, δίδυμο του hover με αντίθετη σύμβαση συμβάντος.
import { useTableInsertControlClick } from './use-table-insert-control-click';
// 🔴 ADR-739 §42 — το ⊖ της διαγραφής: ίδια διαδρομή συμβάντος, άλλο store, άλλη πράξη.
import { useTableDeleteControlClick } from './use-table-delete-control-click';
// 🔴 ADR-768 Βήμα 5 — το **βάψιμο**: ίδια διαδρομή συμβάντος με ⊕/⊖, άλλο store, άλλη πράξη.
import { useTableFormatPainterClick } from './use-table-format-painter-click';
// 🔴 ADR-833 Φάση 3 — η **αλλαγή φύλλου**: ίδια διαδρομή συμβάντος με ⊕/⊖/πινέλο, άλλη πράξη.
import { useTableWorksheetTabClick } from './use-table-worksheet-tab-click';
import type { TableEntity } from '../../types/table-entity';
import type { LevelManagerLike } from '../../hooks/canvas/canvas-click-types';
import type { Point2D, ViewTransform } from '../../rendering/types/Types';

export interface UseTableModeCanvasWiringParams {
  /**
   * Η **ζωντανή** οντότητα του δρομέα· `null` όταν δεν υπάρχει δρομέας ή ο πίνακας χάθηκε
   * από κάτω του. Δίνεται από τον γονιό και δεν ξαναδιαβάζεται εδώ: μια δεύτερη ανάγνωση
   * σκηνής θα μπορούσε να δει άλλο (ή σβησμένο) πίνακα μέσα στο **ίδιο** render.
   */
  readonly entity: TableEntity | null;
  readonly levelManager: LevelManagerLike;
  readonly getSelectedEntityIds: () => readonly string[];
  readonly containerRef: React.RefObject<HTMLDivElement | null>;
  readonly transformRef: React.RefObject<ViewTransform>;
}

/**
 * Προσαρτά τους δύο ακροατές καμβά της λειτουργίας πίνακα. Δεν επιστρέφει τίποτα: ό,τι
 * παράγουν γράφεται σε stores που διαβάζει ο ζωγράφος, όχι σε React state.
 */
export function useTableModeCanvasWiring(params: UseTableModeCanvasWiringParams): void {
  const { entity, levelManager, getSelectedEntityIds, containerRef, transformRef } = params;

  /**
   * 🔴 §39 — ο **επιλεγμένος** πίνακας, διαβασμένος τη στιγμή της κλήσης.
   *
   * §40.9 — είχε **δύο** καταναλωτές με διαφορετικό ρυθμό· τώρα έχει **έναν**, και είναι ο
   * σωστός: ο ακροατής κίνησης, **ανά συμβάν**. Ο δεύτερος (το `active`, ανά **απόδοση**) ήταν
   * το ίδιο το ελάττωμα — δες το μπλοκ παρακάτω.
   */
  const resolveSelectedTableEntity = useCallback(
    () => resolveSelectedTable(levelManager, getSelectedEntityIds),
    [levelManager, getSelectedEntityIds],
  );

  /**
   * 🔴 ADR-768 Βήμα 5 — ο πίνακας **κάτω από το χέρι**, όποιος κι αν είναι.
   *
   * Τρίτος resolver δίπλα στους δύο υπάρχοντες, και ο μόνος που ξεκινά από **σημείο** αντί από
   * ταυτότητα ή επιλογή. Υπάρχει επειδή το πινέλο βάφει **από πίνακα σε πίνακα** (§2.2), οπότε
   * «ο πίνακας του δρομέα» δεν είναι απάντηση στο «πού στοχεύω».
   *
   * ⚠️ Ο hover τον καλεί **μόνο** με οπλισμένο πινέλο: κοστίζει σάρωση σκηνής **και** υπολογισμό
   * διάταξης ανά πίνακα, δηλαδή κάτι που δεν επιτρέπεται να πληρώνεται σε κάθε κίνηση ποντικιού.
   */
  const resolvePaintTable = useCallback(
    (world: Point2D, viewScale: number) => resolveTableAtWorld(levelManager, world, viewScale),
    [levelManager],
  );

  /**
   * 🔴🔴 §40.9 — **ΕΔΩ ΖΟΥΣΕ Η ΑΙΤΙΑ, ΚΑΙ ΤΟ ΕΠΙΧΕΙΡΗΜΑ ΟΡΘΟΤΗΤΑΣ ΗΤΑΝ ΣΩΣΤΟ ΩΣ ΤΟ ΤΕΛΟΣ.**
   *
   * Μέχρι τις 04/08 εδώ υπολογιζόταν:
   *
   * ```ts
   * const isTableModeActive = hasEditorOverlay || resolveSelectedTableEntity() !== null;
   * ```
   *
   * και περνιόταν και στους τρεις ακροατές, με ρητό επιχείρημα: «*μία συνθήκη, καμία δυνατότητα
   * να γίνει πατήσιμο κάτι που δεν βάφεται*». **Το επιχείρημα ήταν σωστό· ο τόπος ήταν λάθος.**
   *
   * Η έκφραση αποτιμάται **την ώρα της απόδοσης**, και ο κάτοχός της είναι ο `CanvasSection` —
   * ο οποίος **δεν αποδίδει ποτέ σε αλλαγή επιλογής**. Δεν είναι παράλειψη· είναι ρητή, μετρημένη
   * απόφαση, δηλωμένη σε **τρία** ανεξάρτητα σημεία:
   *
   * - `CanvasSection.tsx` — «*ADR-532 B4 — NON-reactive selection facade: no re-render on
   *   dxf-entity selection*»
   * - `SelectionSystem.tsx` — «*the host component does NOT re-render on dxf-entity selection
   *   changes*»
   * - `use-selection-cycling.ts` — «*no `useSyncExternalStore`, so CanvasSection never re-renders*»
   *
   * ⇒ Επιλογή πίνακα από καθαρή αρχή ⇒ **καμία απόδοση** ⇒ το `active` έμενε `false` ⇒ **δεν
   * γεννιόταν ούτε ακροατής κίνησης**. Το ⊕ δεν ήταν «άφταστο» όπως στο §40.8· ήταν **αόρατο**,
   * ενώ και οι πέντε στρώσεις από κάτω (γεωμετρία, σάρωση, hover, ζωγράφος, πάτημα) υποστηρίζουν
   * ρητά την κατάσταση `'selection'` από το §40.
   *
   * ## 🔑 Γιατί οι δύο αναφορές του ιδιοκτήτη έμοιαζαν αντιφατικές — και ήταν η ΙΔΙΑ αιτία
   * Το §40.8 κατέγραψε «*δουλεύει μόνον **έξω** από το edit mode*»· το §40.9 «*πρέπει να **μπω**
   * σε edit mode*». Και τα δύο βγαίνουν από αυτή τη γραμμή: ο δρομέας **είναι** συνδρομή
   * (`useTableCellCursor`), άρα το **κλείσιμό** του προκαλεί απόδοση — και σε εκείνη την απόδοση
   * το `resolveSelectedTableEntity()` βρίσκει τον πίνακα ακόμα επιλεγμένο και μανταλώνει
   * `active = true`. Δηλαδή η απλή επιλογή δούλευε **μόνο ως υπόλειμμα** μιας συνεδρίας που μόλις
   * έκλεισε. Πρώτη επιλογή σε καθαρή σελίδα: τίποτα.
   *
   * ## Η θεραπεία: η συνθήκη δεν διαγράφηκε — ΜΕΤΑΚΟΜΙΣΕ ΕΚΕΙ ΠΟΥ ΕΧΕΙ ΑΠΑΝΤΗΣΗ
   * Και οι τρεις ακροατές λύνουν **ήδη** τα πάντα με getter τη στιγμή του συμβάντος: ο hover με
   * `entity ?? resolveSelected()`, το κλικ με `resolveArmed()` + `resolveTableById()`. Είναι ο
   * ρητός κανόνας 2 του ADR-040 («*event handlers MUST receive getters, not snapshot values*»),
   * και το `active` ήταν ακριβώς το στιγμιότυπο που ο κανόνας απαγορεύει — μεταμφιεσμένο σε
   * φρουρό απόδοσης.
   *
   * ⚠️ **ΜΗΝ το «διορθώσεις» με συνδρομή στην επιλογή** (`useSyncExternalStore` εδώ ή στον
   * γονιό). Θα ξανάφερνε την απόδοση του `CanvasSection` σε **κάθε κλικ** — ακριβώς αυτό που το
   * ADR-532 B6 αφαίρεσε μετρημένα. Η σωστή απάντηση δεν είναι «κάν' το αντιδραστικό», είναι
   * «**σταμάτα να το φωτογραφίζεις**».
   *
   * @see ui/table-cell-editor/use-table-indicator-hover.ts — η πύλη, σε χρόνο συμβάντος
   * @see ui/table-cell-editor/use-table-armed-control-click.ts — η δεύτερη πύλη (`resolveArmed`)
   */

  /**
   * 🔴 ADR-739 §29 — **το δίδυμο του modal keyboard scope, για το ΠΟΝΤΙΚΙ.**
   *
   * Ο ιδιοκτήτης (2026-08-02): «όταν μπαίνω σε edit mode στους πίνακες, να μην μπορώ να
   * κάνω κλικ έξω από τους πίνακες μέσα στον καμβά για να επιλέξω και να τροποποιήσω
   * οντότητες, αν πρώτα δεν βγω με κάποιον τρόπο από το edit». Μέχρι εκείνο το σημείο ο
   * καμβάς εξακολουθούσε να κάνει hover, να επιλέγει στο κλικ, και να **σκοτώνει τη
   * συνεδρία** με την ίδια κίνηση.
   *
   * 🔴 **§29.15 — ΑΛΛΗ ΣΥΝΘΗΚΗ ΑΠΟ ΤΟ ΠΛΗΚΤΡΟΛΟΓΙΟ, ΚΑΙ ΕΙΝΑΙ ΤΟ ΝΟΗΜΑ.**
   *
   * Μέχρι τις 03/08 περνιόταν εδώ το **ίδιο** `overlay !== null` που κρατά το πληκτρολόγιο,
   * με το επιχείρημα «μία τιμή οδηγεί και τα δύο». Μετρήθηκε ζωντανά ότι η τιμή είναι λάθος
   * για το ποντίκι: κλικ στη λωρίδα μιας στήλης που καλύπτεται από τον **συγχωνευμένο
   * τίτλο** βάζει τον δρομέα σε κελί **χωρίς δικό του ορθογώνιο** ⇒ `overlay` → `null` ⇒ ο
   * καμβάς ξεκλείδωνε **μέσα στο ίδιο `mousedown`** και το `mouseup` γεννούσε πλαίσιο
   * επιλογής, ενώ ο χρήστης έβλεπε ολοκάθαρα ότι είναι μέσα στον πίνακα.
   *
   * Το πληκτρολόγιο ρωτά «υπάρχει πεδίο που κατέχει τα πλήκτρα;» — και σωστά κρατά το
   * `overlay`. Το ποντίκι ρωτά «είναι ο χρήστης μέσα στη λειτουργία;» — και η απάντηση
   * είναι ο **ζωντανός πίνακας**. Το hook τη διαβάζει **μόνο** του από το `entity`: δεν
   * υπάρχει `active` να δοθεί λάθος. Πλήρες σκεπτικό στην κεφαλίδα εκείνου του module.
   */
  useTableCanvasLockdown({ entity, containerRef, transformRef });

  useTableIndicatorHover({
    entity,
    resolveSelected: resolveSelectedTableEntity,
    resolvePaintTable,
    containerRef,
    transformRef,
  });

  /**
   * 🔴 §39 — το **πάτημα** του ⊕. Ζει δίπλα στον hover και όχι μέσα του, επειδή ο hover είναι
   * ρητά **παθητικός** ακροατής (δες την κεφαλίδα του: το pan ζει πάνω στο `mousemove` και ένα
   * `preventDefault` εκεί θα το σκότωνε). Το κλικ, αντίθετα, **πρέπει** να καταναλώνει —
   * δηλαδή είναι η ακριβώς αντίθετη σύμβαση, και δύο αντίθετες συμβάσεις δεν χωρούν σε έναν
   * ακροατή. Η **ίδια** συνθήκη ζωής, ώστε να μη γίνεται ποτέ πατήσιμο κάτι που δεν βάφεται.
   */
  useTableInsertControlClick({
    containerRef,
    levelManager,
  });

  /**
   * 🔴 §42 — το **πάτημα** του ⊖. Δίπλα στο ⊕ και όχι μέσα του: είναι δύο διαφορετικά stores
   * και δύο διαφορετικές πράξεις — μοιράζονται μόνο τη **διαδρομή του συμβάντος**, που ζει
   * ήδη σε ένα σημείο (`useTableArmedControlClick`).
   *
   * §40.9 — **δεν έχει πια συνθήκη προσάρτησης, και για το ⊖ το διακύβευμα είναι μεγαλύτερο.**
   * Ο φόβος «*ακροατής που σβήνει στήλες όταν δεν υπάρχει λειτουργία πίνακα*» δεν λύνεται από
   * φρουρό απόδοσης: λύνεται από το `resolveArmed()`, που επιστρέφει `null` όποτε δεν υπάρχει
   * **οπλισμένο** ⊖ — και το ⊖ οπλίζεται μόνο μέσα στη ζώνη, η οποία υπάρχει μόνο σε λειτουργία
   * πίνακα (`tableIndicatorProbeAtWorld`: `remove` είναι `null` όταν `mode !== 'table-mode'`).
   * Δηλαδή ο φρουρός που μετράει ήταν πάντα **δύο στρώσεις πιο κάτω**, στη γεωμετρία.
   */
  useTableDeleteControlClick({
    containerRef,
    levelManager,
  });

  /**
   * 🔴 ADR-768 Βήμα 5 — το **βάψιμο**. Τρίτος καταναλωτής του `useTableArmedControlClick`, και ο
   * πρώτος που δεν είναι «χειριστήριο»: το οπλισμένο πράγμα δεν είναι σχήμα πάνω στον πίνακα,
   * είναι **εργαλείο**. Ο κοινός ακροατής δεν χρειάστηκε ούτε μία αλλαγή — το πινέλο απλώς γράφει
   * τον στόχο του εκεί που γράφουν τον δικό τους το ⊕ και το ⊖ (πέμπτο κανάλι της ίδιας σάρωσης).
   *
   * ⚠️ Καμία συνθήκη προσάρτησης, ίδιος λόγος με τα δύο από πάνω (§40.9): ο φρουρός που μετράει
   * είναι το `resolveArmed()`, που απαντά `null` όποτε δεν υπάρχει **και** οπλισμένο πινέλο
   * **και** στόχος γραμμένος από τον hover — δύο συνθήκες που δεν μπορούν να ισχύσουν χωρίς
   * ζωντανό πίνακα κάτω από το χέρι.
   */
  useTableFormatPainterClick({
    containerRef,
    levelManager,
  });

  /**
   * 🔴 ADR-833 Φάση 3 — το **πάτημα** μιας καρτέλας φύλλου. Τέταρτος καταναλωτής του
   * `useTableArmedControlClick`, με το ίδιο σχήμα και τους ίδιους δύο λόγους:
   *
   * - **Καμία συνθήκη προσάρτησης** (§40.9): ο φρουρός που μετράει είναι το `resolveArmed()`,
   *   που απαντά `null` όποτε ο hover δεν έχει γράψει καρτέλα — και ο hover δεν γράφει καρτέλα
   *   χωρίς ζωντανό ή επιλεγμένο πίνακα κάτω από το χέρι. Δηλαδή ο φρουρός ήταν ήδη δύο
   *   στρώσεις πιο κάτω, στη γεωμετρία.
   * - **Χωριστά από τον hover**, όχι μέσα του: ο hover είναι ρητά **παθητικός** (το pan ζει
   *   πάνω στο `mousemove`), το κλικ **πρέπει** να καταναλώνει. Δύο αντίθετες συμβάσεις δεν
   *   χωρούν σε έναν ακροατή.
   *
   * ⚠️ Η λωρίδα ζει και σε **απλή επιλογή**, όχι μόνο σε λειτουργία πίνακα — γι' αυτό ο
   * ακροατής ζει **εδώ**, δίπλα στους τρεις που έχουν ήδη αυτή την ιδιότητα, και όχι στον
   * `use-table-cell-pointer` που ζει μόνο όσο υπάρχει δρομέας.
   */
  useTableWorksheetTabClick({
    containerRef,
    levelManager,
  });
}
