'use client';

/**
 * ADR-739 §29 + §30 + §39 — **ΤΙ ΑΚΟΥΕΙ Ο ΚΑΜΒΑΣ ΟΣΟ ΥΠΑΡΧΕΙ ΠΙΝΑΚΑΣ**: το κλείδωμα του
 * ποντικιού και ο hover των λωρίδων δείκτη. Καθαρή σύνδεση — μηδέν δική του κατάσταση,
 * μηδέν γεωμετρία, μηδέν απόφαση· τις παίρνουν τα δύο hooks που καλεί.
 *
 * ## Γιατί υπάρχει ως ξεχωριστό module
 * Γεννήθηκε ως **εξαγωγή** από το `useTableCellDoubleClickEditor.ts` τη στιγμή που εκείνο
 * ξαναχτύπησε τις 500 γραμμές (N.7.1) — για **τέταρτη** φορά. Δεν διαλέχτηκε επειδή ήταν το
 * μεγαλύτερο κομμάτι, αλλά επειδή ήταν **αυτό που μεγάλωσε**: το §39 πρόσθεσε εδώ τον
 * επιλυτή επιλεγμένου πίνακα και άλλαξε τη συνθήκη ενεργοποίησης. Ό,τι μεγαλώνει, φεύγει.
 *
 * Ο διαχωρισμός είναι σημασιολογικός και όχι αριθμητικός: ο γονιός απαντά «**ποιο κελί,
 * πού, με τι όψη**» (μοντέλο + DOM του επεξεργαστή)· εδώ ζει «**τι επιτρέπεται στον καμβά
 * από κάτω**» — δύο ερωτήσεις που τυχαίνει να μοιράζονται τη ζωντανή οντότητα, τίποτα άλλο.
 *
 * 🔑 **Οι δύο συνθήκες ΔΕΝ είναι η ίδια τιμή, και αυτό είναι το νόημα** — δες τα σχόλια
 * στις δύο κλήσεις παρακάτω. Ζουν μαζί ακριβώς για να φαίνεται η διαφορά τους δίπλα-δίπλα.
 *
 * @see ui/table-cell-editor/use-table-canvas-lockdown.ts — §29, το κλείδωμα
 * @see ui/table-cell-editor/use-table-indicator-hover.ts — §30 + §39, ο hover + το ⊕
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §29, §30, §39
 */

import { useCallback } from 'react';
import type React from 'react';
import { resolveSelectedTable } from './table-entity-lookup';
// ADR-739 §29 — το δίδυμο του modal keyboard scope για το ποντίκι: όσο ζει η λειτουργία
// πίνακα, ο καμβάς δεν επιλέγει, δεν σέρνει και δεν κάνει hover σε οντότητες.
import { useTableCanvasLockdown } from './use-table-canvas-lockdown';
// ADR-739 §30 — ο hover των λωρίδων δείκτη (Excel). Παθητικός ακροατής `mousemove`, ο μόνος
// που το κλείδωμα του §29 αφήνει να περάσει (το pan ζει πάνω του).
import { useTableIndicatorHover } from './use-table-indicator-hover';
// ADR-739 §39 — το **πάτημα** του ⊕, δίδυμο του hover με αντίθετη σύμβαση συμβάντος.
import { useTableInsertControlClick } from './use-table-insert-control-click';
// 🔴 ADR-739 §42 — το ⊖ της διαγραφής: ίδια διαδρομή συμβάντος, άλλο store, άλλη πράξη.
import { useTableDeleteControlClick } from './use-table-delete-control-click';
import type { TableEntity } from '../../types/table-entity';
import type { LevelManagerLike } from '../../hooks/canvas/canvas-click-types';
import type { ViewTransform } from '../../rendering/types/Types';

export interface UseTableModeCanvasWiringParams {
  /**
   * Η **ζωντανή** οντότητα του δρομέα· `null` όταν δεν υπάρχει δρομέας ή ο πίνακας χάθηκε
   * από κάτω του. Δίνεται από τον γονιό και δεν ξαναδιαβάζεται εδώ: μια δεύτερη ανάγνωση
   * σκηνής θα μπορούσε να δει άλλο (ή σβησμένο) πίνακα μέσα στο **ίδιο** render.
   */
  readonly entity: TableEntity | null;
  /** `overlay !== null` του γονιού — «υπάρχει εστιασμένο `<input>` που κατέχει τα πλήκτρα». */
  readonly hasEditorOverlay: boolean;
  readonly levelManager: LevelManagerLike;
  readonly getSelectedEntityIds: () => readonly string[];
  readonly containerRef: React.RefObject<HTMLDivElement | null>;
  readonly transformRef: React.RefObject<ViewTransform>;
}

/**
 * Προσαρτά τους δύο ακροατές καμβά της λειτουργίας πίνακα. Δεν επιστρέφει τίποτα: ό,τι
 * παράγουν γράφεται σε stores που διαβάζει ο ζωγράφος, όχι σε React state.
 */
export function useTableModeCanvasWiring(params: UseTableModeCanvasWiringParams): void {
  const {
    entity,
    hasEditorOverlay,
    levelManager,
    getSelectedEntityIds,
    containerRef,
    transformRef,
  } = params;

  /**
   * 🔴 §39 — ο **επιλεγμένος** πίνακας, διαβασμένος τη στιγμή της κλήσης.
   *
   * Ο ίδιος getter εξυπηρετεί δύο ερωτήσεις με διαφορετικό ρυθμό: το `active` παρακάτω τον
   * ρωτά **ανά απόδοση** (χρειάζεται μόνο «υπάρχει;»), ο ακροατής κίνησης **ανά συμβάν**
   * (χρειάζεται τη ζωντανή οντότητα). Μία πηγή, καμία δυνατότητα να διαφωνήσουν.
   */
  const resolveSelectedTableEntity = useCallback(
    () => resolveSelectedTable(levelManager, getSelectedEntityIds),
    [levelManager, getSelectedEntityIds],
  );

  /**
   * 🔴 §39 — **Η ΣΥΝΘΗΚΗ ΖΩΗΣ ΤΟΥ ⊕, ΓΡΑΜΜΕΝΗ ΜΙΑ ΦΟΡΑ.**
   *
   * Τη μοιράζονται ο hover (τι **βάφεται**) και το κλικ (τι **πατιέται**), και η ταύτιση
   * είναι το επιχείρημα ορθότητας: δεν επιτρέπεται να γίνει ποτέ πατήσιμο κάτι που δεν
   * ζωγραφίζεται, ούτε να ζωγραφιστεί κάτι που δεν πατιέται. Δύο αντίγραφα της έκφρασης θα
   * μπορούσαν να αποκλίνουν σε μία μόνο επεξεργασία — γι' αυτό ζει σε μεταβλητή, όχι σε δύο
   * κλήσεις.
   */
  const isTableModeActive = hasEditorOverlay || resolveSelectedTableEntity() !== null;

  /**
   * 🔴 ADR-739 §29 — **το δίδυμο του modal keyboard scope, για το ΠΟΝΤΙΚΙ.**
   *
   * Ο ιδιοκτήτης (2026-08-02): «όταν μπαίνω σε edit mode στους πίνακες, να μην μπορώ να
   * κάνω κλικ έξω από τους πίνακες μέσα στον καμβά για να επιλέξω και να τροποποιήσω
   * οντότητες, αν πρώτα δεν βγω με κάποιον τρόπο από το edit». Μέχρι εκείνο το σημείο ο
   * καμβάς εξακολουθούσε να κάνει hover, να επιλέγει στο κλικ, και να **σκοτώνει τη
   * συνεδρία** με την ίδια κίνηση.
   *
   * 🔴 **§29.15 — ΑΛΛΗ ΣΥΝΘΗΚΗ ΑΠΟ ΤΟ ΠΛΗΚΤΡΟΛΟΓΙΟ, ΚΑΙ ΕΙΝΑΙ ΤΟ ΝΟΗΜΑ.**
   *
   * Μέχρι τις 03/08 περνιόταν εδώ το **ίδιο** `overlay !== null` που κρατά το πληκτρολόγιο,
   * με το επιχείρημα «μία τιμή οδηγεί και τα δύο». Μετρήθηκε ζωντανά ότι η τιμή είναι λάθος
   * για το ποντίκι: κλικ στη λωρίδα μιας στήλης που καλύπτεται από τον **συγχωνευμένο
   * τίτλο** βάζει τον δρομέα σε κελί **χωρίς δικό του ορθογώνιο** ⇒ `overlay` → `null` ⇒ ο
   * καμβάς ξεκλείδωνε **μέσα στο ίδιο `mousedown`** και το `mouseup` γεννούσε πλαίσιο
   * επιλογής, ενώ ο χρήστης έβλεπε ολοκάθαρα ότι είναι μέσα στον πίνακα.
   *
   * Το πληκτρολόγιο ρωτά «υπάρχει πεδίο που κατέχει τα πλήκτρα;» — και σωστά κρατά το
   * `overlay`. Το ποντίκι ρωτά «είναι ο χρήστης μέσα στη λειτουργία;» — και η απάντηση
   * είναι ο **ζωντανός πίνακας**. Το hook τη διαβάζει **μόνο** του από το `entity`: δεν
   * υπάρχει `active` να δοθεί λάθος. Πλήρες σκεπτικό στην κεφαλίδα εκείνου του module.
   */
  useTableCanvasLockdown({ entity, containerRef, transformRef });

  useTableIndicatorHover({
    /**
     * 🔴 §39 — **ΕΔΩ Η ΤΙΜΗ ΑΠΟΚΛΙΝΕΙ ΑΠΟ ΤΟ ΠΛΗΚΤΡΟΛΟΓΙΟ, ΚΑΙ ΕΙΝΑΙ ΤΟ ΝΟΗΜΑ.**
     *
     * Μέχρι το §39 εδώ περνιόταν σκέτο `overlay !== null`, με το επιχείρημα «ο δείκτης
     * ζωγραφίζεται μόνο όσο υπάρχει δρομέας, οπότε hover εκτός αυτής της συνθήκης θα ήταν
     * κατάσταση που κανείς δεν αποδίδει». Ίσχυε ακέραιο **μέχρι** να αποκτήσει ο πίνακας
     * χειριστήριο που ζωγραφίζεται και **χωρίς** δρομέα: το ⊕ της εισαγωγής. Ο κανόνας δεν
     * χαλάρωσε — η προϋπόθεσή του άλλαξε, όπως ακριβώς είχε συμβεί με το `row-resize` του §31.
     *
     * ⚠️ Ο έλεγχος είναι **μηδενικού κόστους στη συνηθισμένη περίπτωση**: το
     * `resolveSelectedTable` βγαίνει αμέσως όταν τα επιλεγμένα δεν είναι ακριβώς ένα.
     */
    active: isTableModeActive,
    entity,
    resolveSelected: resolveSelectedTableEntity,
    containerRef,
    transformRef,
  });

  /**
   * 🔴 §39 — το **πάτημα** του ⊕. Ζει δίπλα στον hover και όχι μέσα του, επειδή ο hover είναι
   * ρητά **παθητικός** ακροατής (δες την κεφαλίδα του: το pan ζει πάνω στο `mousemove` και ένα
   * `preventDefault` εκεί θα το σκότωνε). Το κλικ, αντίθετα, **πρέπει** να καταναλώνει —
   * δηλαδή είναι η ακριβώς αντίθετη σύμβαση, και δύο αντίθετες συμβάσεις δεν χωρούν σε έναν
   * ακροατή. Η **ίδια** συνθήκη ζωής, ώστε να μη γίνεται ποτέ πατήσιμο κάτι που δεν βάφεται.
   */
  useTableInsertControlClick({
    active: isTableModeActive,
    containerRef,
    levelManager,
  });

  /**
   * 🔴 §42 — το **πάτημα** του ⊖. Δίπλα στο ⊕ και όχι μέσα του: είναι δύο διαφορετικά stores
   * και δύο διαφορετικές πράξεις — μοιράζονται μόνο τη **διαδρομή του συμβάντος**, που ζει
   * ήδη σε ένα σημείο (`useTableArmedControlClick`).
   *
   * Η **ίδια** συνθήκη ζωής με τον hover και το ⊕, ώστε να μη γίνεται ποτέ πατήσιμο κάτι που
   * δεν βάφεται — και, εδώ ειδικά, να μην υπάρχει ακροατής που σβήνει στήλες όταν δεν υπάρχει
   * λειτουργία πίνακα.
   */
  useTableDeleteControlClick({
    active: isTableModeActive,
    containerRef,
    levelManager,
  });
}
