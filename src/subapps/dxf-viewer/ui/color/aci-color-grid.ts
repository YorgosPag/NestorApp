/**
 * ADR-739 Φ.Ε/Φ4 — **το πλέγμα χρωμάτων σε σχήμα Excel, με περιεχόμενο AutoCAD.**
 *
 * 13 στήλες × 6 σειρές, όπως το μενού «Χρώμα γραμματοσειράς» του Excel — αλλά **καμία απόχρωση
 * δεν υπολογίζεται**: διαβάζονται από την ίδια την `ACI_PALETTE` (`settings/standards/aci.ts`).
 *
 * ## 🔴 Γιατί ΔΕΝ παράγουμε αποχρώσεις όπως το Excel
 * Το Excel φτιάχνει τις 5 παραλλαγές κάθε χρώματος θέματος με `lumMod`/`lumOff` πάνω σε ένα
 * θέμα που ζει **μέσα στο αρχείο** (`theme1.xml`). Το DXF **δεν έχει θέμα εγγράφου** — η έννοια
 * δεν υπάρχει στη μορφή. Ένα παραγόμενο χρώμα θα ήταν αυθαίρετο *και* θα ισοπεδωνόταν στην
 * εξαγωγή προς ACI.
 *
 * Η παλέτα ACI όμως **είναι ήδη** οργανωμένη ως απόχρωση × φωτεινότητα: κάθε δεκάδα 10-249
 * είναι μία οικογένεια με 5 στάθμες κορεσμένες (άρτιοι δείκτες) και 5 ξεπλυμένες (περιττοί):
 *
 * ```
 *   οικογένεια h:  h+1 (ανοιχτό) · h+0 (βάση) · h+2 · h+4 · h+6 · h+8
 *   π.χ. κόκκινο:  #ff7f7f      · #ff0000    · #cc0000 · #990000 · #7f0000 · #4c0000
 * ```
 *
 * Έξι σκαλιά, έτοιμα. Άρα **77 από τα 78 δείγματα είναι ακριβείς τιμές ACI** ⇒ επιβιώνουν
 * ακέραια **και** στο DXF group 420 (αληθινό χρώμα) **και** στο 62 (δείκτης), χωρίς κβάντιση.
 * Το Excel δεν μπορεί να δώσει τέτοια εγγύηση για κανένα από τα δικά του δείγματα.
 *
 * Δεύτερο κέρδος: οι στήλες **δεν μετακινούνται ποτέ**. Στο Excel το πλέγμα αναδιατάσσεται όταν
 * αλλάξει το θέμα, δηλαδή η μνήμη χεριού σπάει ανά έγγραφο· εδώ το «τρίτο από αριστερά, δεύτερη
 * σειρά» είναι το ίδιο χρώμα σε κάθε σχέδιο, για πάντα.
 *
 * ## 🔴 ΤΟ ΜΑΥΡΟ ΔΕΝ ΕΙΝΑΙ ACI — και το ACI 7 είναι παγίδα
 * Η παλέτα **δεν έχει καθαρό μαύρο**: `ACI_PALETTE[7] = '#FFFFFF'` («White»), και το AutoCAD το
 * ζωγραφίζει μαύρο σε λευκό φόντο κατά σύμβαση — σύμβαση που το `config/print-color-policy.ts`
 * ήδη κωδικοποιεί (ACI 7 → μαύρο μελάνι). Εδώ όμως το χρώμα ταξιδεύει ως **κυριολεκτικό hex**
 * μέχρι τον ζωγράφο: ένα «ACI 7» θα έβαφε `#ffffff`, δηλαδή **λευκό κείμενο σε λευκό φύλλο**.
 *
 * Γι' αυτό (α) το ACI 7 **δεν εμφανίζεται ποτέ** στο πλέγμα **μελανιού** και (β) το μαύρο μπαίνει
 * ως αληθινό χρώμα `#000000`, το **μοναδικό** δείγμα του εκεί χωρίς {@link AciGridSwatch.aci}.
 * Χωρίς αυτόν τον κανόνα, «διάλεξα μαύρο» θα έγραφε «λευκό» στο αρχείο — σιωπηλά.
 *
 * ## 🔴🔴 ΔΥΟ ΠΛΕΓΜΑΤΑ, ΜΙΑ ΜΗΧΑΝΗ — και γιατί το γέμισμα ΔΕΝ μπορεί να είναι καθαρό ACI
 * (ADR-739 Φ.Ε/Φ4β)
 *
 * Ο κανόνας «κοντά στο λευκό → μαύρο» είναι κανόνας **ορατότητας μελανιού**, και το
 * `print-color-policy.ts` το λέει ήδη ρητά για τον ρόλο `'fill'`: εκεί ο ίδιος κανόνας είναι
 * **καταστροφικός**. Άρα το πλέγμα γεμίσματος οφείλει να δείχνει το λευκό.
 *
 * 🔴 **Το πραγματικό πρόβλημα όμως δεν είναι το λευκό — είναι ολόκληρη η ανοιχτή ζώνη.**
 * Μετρήθηκαν και οι 255 δείκτες: τα **μόνα** χρώματα με σκοτεινότερο κανάλι ≥ `0xD0` είναι τα
 * 7 και 255, και τα δύο σκέτο `#FFFFFF`· το αμέσως ανοιχτότερο οτιδήποτε είναι `#C0C0C0`
 * (ACI 9) / `#BEBEBE` (ACI 254). Δηλαδή **η μπάντα όπου ζει ένα γέμισμα πίνακα — η λωρίδα
 * κεφαλίδας, `#F5F5F5`…`#DDDDDD` — δεν υπάρχει καθόλου στο ACI**, και το **δικό μας**
 * προεπιλεγμένο γέμισμα κεφαλίδας (`#EDEDED`, `table-style-presets.ts`) **δεν είναι εκφράσιμο**.
 * Ένα «πρόσθεσε και το λευκό» δεν λύνει τίποτα: προσθέτει το ένα άκρο και αφήνει τη ζώνη κενή.
 *
 * ⚠️ **Και δεν χρειάζεται να είναι ACI.** Η εγγύηση «ακριβής τιμή ACI ⇒ lossless σε 420 **και**
 * 62» είναι εγγύηση **μελανιού**. Το γέμισμα βγαίνει ως `SOLID` με **αληθινό χρώμα** — μετρημένο
 * μέσα στον ίδιο τον κώδικα, στο αρχείο του ιδιοκτήτη: `neutral-primitive-factory.ts` σημειώνει
 * `420 = 15592941` (= ακριβώς `#EDEDED`). Άρα οποιοδήποτε hex επιβιώνει ακέραιο στην εξαγωγή.
 *
 * Τα δύο ανοιχτά γκρι **δεν εφευρίσκονται**: είναι κυριολεκτικά τα «White, Background 1,
 * Darker 5% / 15%» του Excel. Όπου το ACI σιωπά, ακολουθούμε τη δική τους πρακτική — και μόνο
 * η **ουδέτερη** στήλη το κάνει· οι 12 στήλες αποχρώσεων μένουν 100% ACI, γιατί ένα `#ff7f7f`
 * είναι εξίσου καλό γέμισμα όσο και μελάνι.
 *
 * 🔑 Ένας builder, δύο σταθερές. Δεύτερο module «σαν κι αυτό» θα ήταν ακριβώς το sibling clone
 * που πιάνει το CHECK 3.28 (N.18) — και δύο σημεία που μπορούν κάποτε να μάθουν διαφορετική
 * σειρά στηλών, δηλαδή δύο διαφορετικές μνήμες χεριού για την ίδια παλέτα.
 *
 * @module subapps/dxf-viewer/ui/color/aci-color-grid
 * @see settings/standards/aci.ts — η ΜΙΑ πηγή της παλέτας (ADR-573)
 * @see config/print-color-policy.ts — `PlotColorRole`: ποιος ρόλος ανέχεται το λευκό
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §28.14, §35
 */

import { getAciColor } from '../../settings/standards/aci';
import { normalizeHexColor } from '../../config/color-math';
import type { PlotColorRole } from '../../config/print-color-policy';

/** Οι στήλες του πλέγματος — η **ουδέτερη πρώτη**, όπως στο Excel. */
export const ACI_GRID_HUE_KEYS = [
  'neutral',
  'red',
  'orange',
  'yellow',
  'chartreuse',
  'green',
  'springGreen',
  'cyan',
  'azure',
  'blue',
  'violet',
  'magenta',
  'rose',
] as const;

export type AciGridHueKey = (typeof ACI_GRID_HUE_KEYS)[number];

/** Οι σειρές — **ανοιχτό πάνω, σκούρο κάτω**, ίδια φορά σε κάθε στήλη (και στην ουδέτερη). */
export const ACI_GRID_SHADE_KEYS = ['light', 'base', 'dark1', 'dark2', 'dark3', 'dark4'] as const;

export type AciGridShadeKey = (typeof ACI_GRID_SHADE_KEYS)[number];

/** Ένα δείγμα του πλέγματος. Η ταυτότητα, όχι η ετικέτα — η ετικέτα είναι δουλειά του i18n. */
export interface AciGridSwatch {
  /** Κανονικοποιημένο `#rrggbb`, **πεζά** — δες {@link normalizeSwatchHex}. */
  readonly hex: string;
  /**
   * Ο δείκτης ACI. **Απών μόνο για το μαύρο**, που δεν υπάρχει στην παλέτα (βλ. κεφαλίδα).
   * Η απουσία του σημαίνει «αυτό επιβιώνει μόνο ως αληθινό χρώμα (420)· το 62 θα το
   * προσεγγίσει» — και είναι πληροφορία που ο μηχανικός δικαιούται να βλέπει.
   */
  readonly aci?: number;
  readonly hue: AciGridHueKey;
  readonly shade: AciGridShadeKey;
}

/** Μία στήλη — πάντα {@link ACI_GRID_SHADE_KEYS}.length δείγματα. */
export type AciGridColumn = readonly AciGridSwatch[];

/**
 * Η βάση κάθε οικογένειας ACI, ανά **30°** στον χρωματικό κύκλο.
 *
 * Οι 24 οικογένειες της παλέτας απέχουν 15°· κρατάμε τη μία στις δύο ώστε οι διπλανές στήλες να
 * ξεχωρίζουν με το μάτι. Η επιλογή **δεν είναι αισθητική**: περιέχει και τις έξι βάσεις των
 * ονομαστικών χρωμάτων ACI 1-6 (κόκκινο 10, κίτρινο 50, πράσινο 90, κυανό 130, μπλε 170,
 * ματζέντα 210), άρα ό,τι ζητά ονομαστικά ένας μηχανικός υπάρχει στο πλέγμα.
 */
const HUE_FAMILY_BASE: Readonly<Record<Exclude<AciGridHueKey, 'neutral'>, number>> = {
  red: 10,
  orange: 30,
  yellow: 50,
  chartreuse: 70,
  green: 90,
  springGreen: 110,
  cyan: 130,
  azure: 150,
  blue: 170,
  violet: 190,
  magenta: 210,
  rose: 230,
};

/**
 * Ποια μέλη της δεκάδας γίνονται οι 6 σειρές: το ξεπλυμένο `+1` για το «ανοιχτό», και μετά η
 * **κορεσμένη** ράμπα `+0 +2 +4 +6 +8`.
 *
 * Οι περιττοί δείκτες (`+3 +5 +7 +9`) μένουν έξω επίτηδες: είναι η ίδια φωτεινότητα με
 * μειωμένο κορεσμό, δηλαδή θα γέμιζαν τη στήλη με ζεύγη που δύσκολα ξεχωρίζουν σε δείγμα 16px.
 */
const FAMILY_MEMBER_OFFSETS = [1, 0, 2, 4, 6, 8] as const;

/** Το μοναδικό δείγμα του πλέγματος μελανιού εκτός παλέτας. Δες την κεφαλίδα για το γιατί. */
const PURE_BLACK_HEX = '#000000';

/**
 * Μία βαθμίδα της ουδέτερης στήλης: **δείκτης ACI** όταν η παλέτα έχει την τιμή, **ωμό hex**
 * όταν δεν την έχει.
 *
 * Ο τύπος είναι η ίδια η δήλωση του ορίου: ό,τι γράφεται ως αριθμός επιβιώνει και στο DXF
 * group 62, ό,τι γράφεται ως hex μόνο στο 420. Δεν χρειάζεται δεύτερη σημαία «είναι ACI;» —
 * θα ήταν δεύτερη πηγή αλήθειας για κάτι που ο ίδιος ο τύπος ήδη λέει.
 */
type NeutralStep = number | string;

/**
 * Η ουδέτερη στήλη **μελανιού**, ανοιχτό → σκούρο: τα πέντε γκρι της παλέτας (254→250) και στο
 * τέλος το αληθινό μαύρο.
 *
 * ⚠️ Το ACI 255 (`#FFFFFF`) λείπει για τον **ίδιο** λόγο με το ACI 7: λευκό κείμενο σε λευκό
 * φύλλο δεν είναι επιλογή, είναι υπόσχεση που σπάει στον εκτυπωτή.
 */
const NEUTRAL_INK_LADDER: readonly NeutralStep[] = [254, 253, 252, 251, 250, PURE_BLACK_HEX];

/**
 * Η ουδέτερη στήλη **γεμίσματος** — η μόνη θέση όπου το πλέγμα φεύγει από το ACI, και μόνο
 * επειδή το ACI δεν έχει τι να δώσει (δες την κεφαλίδα για τη μέτρηση).
 *
 * `#FFFFFF` (ACI 255) · `#F2F2F2` · `#D9D9D9` · `#BEBEBE` (ACI 254) · `#828282` (ACI 253) ·
 * `#000000`. Τα δύο μεσαία είναι τα «Darker 5% / 15%» του Excel — **τέσσερα από τα έξι**
 * κρατούν δείκτη ACI, και τα δύο που δεν κρατούν είναι ακριβώς εκείνα που το ACI δεν έχει.
 *
 * 🔑 Το `#000000` μένει και εδώ: μαύρη κεφαλίδα με λευκά γράμματα είναι κλασικός πίνακας, και
 * το ACI 250 (`#333333`) **δεν** είναι μαύρο — είναι σκούρο γκρι που φαίνεται ξεθωριασμένο
 * δίπλα στο πλαίσιο του σχεδίου.
 */
const NEUTRAL_FILL_LADDER: readonly NeutralStep[] = [
  255, '#f2f2f2', '#d9d9d9', 254, 253, PURE_BLACK_HEX,
];

function swatch(aci: number, hue: AciGridHueKey, shade: AciGridShadeKey): AciGridSwatch {
  return { hex: normalizeHexColor(getAciColor(aci)), aci, hue, shade };
}

function neutralColumn(ladder: readonly NeutralStep[]): AciGridColumn {
  return ladder.map((step, row) => {
    const shade = ACI_GRID_SHADE_KEYS[row];
    return typeof step === 'number'
      ? swatch(step, 'neutral', shade)
      : { hex: normalizeHexColor(step), hue: 'neutral' as const, shade };
  });
}

function hueColumn(hue: Exclude<AciGridHueKey, 'neutral'>): AciGridColumn {
  const base = HUE_FAMILY_BASE[hue];
  return FAMILY_MEMBER_OFFSETS.map((offset, row) =>
    swatch(base + offset, hue, ACI_GRID_SHADE_KEYS[row]),
  );
}

/**
 * Το πλέγμα, **υπολογισμένο μία φορά**. Είναι στατικά δεδομένα — μια συνάρτηση που το ξαναχτίζει
 * σε κάθε άνοιγμα μενού θα παρήγαγε 78 νέα αντικείμενα για μηδέν όφελος, και θα χάλαγε κάθε
 * memoization του καταναλωτή (νέα ταυτότητα ⇒ νέο render).
 */
function buildGrid(neutral: readonly NeutralStep[]): readonly AciGridColumn[] {
  return ACI_GRID_HUE_KEYS.map((hue) =>
    hue === 'neutral' ? neutralColumn(neutral) : hueColumn(hue),
  );
}

/** Το πλέγμα **μελανιού** — χρώμα κειμένου. Τίποτα λευκό ή σχεδόν λευκό. */
export const ACI_COLOR_GRID: readonly AciGridColumn[] = buildGrid(NEUTRAL_INK_LADDER);

/** Το πλέγμα **γεμίσματος** — ίδιες 12 στήλες αποχρώσεων, ουδέτερη στήλη λευκό → μαύρο. */
export const FILL_COLOR_GRID: readonly AciGridColumn[] = buildGrid(NEUTRAL_FILL_LADDER);

/**
 * Το πλέγμα που αντιστοιχεί σε έναν ρόλο χρώματος.
 *
 * Ο καταναλωτής (ένα μενού, δύο ρόλοι) ρωτά **εδώ** αντί να κρατά `role === 'fill' ? A : B`
 * στο JSX: η αντιστοίχιση ρόλου → πλέγμα είναι απόφαση της παλέτας, όχι της διεπαφής, και σε
 * δύο σημεία θα αποκλίνει την πρώτη φορά που θα προστεθεί τρίτος ρόλος.
 */
export function colorGridFor(role: PlotColorRole): readonly AciGridColumn[] {
  return role === 'fill' ? FILL_COLOR_GRID : ACI_COLOR_GRID;
}
