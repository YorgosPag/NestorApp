/**
 * 🛡️ ADR-714 §2.8 — «Ρητό άδειασμα»: ο ΧΡΗΣΤΗΣ έσβησε τη γεωμετρία σχεδίου, δεν τη ΧΑΣΑΜΕ.
 *
 * ## Το πρόβλημα
 *
 * Δύο φρουροί προστατεύουν το blob της σκηνής από καταστροφική εγγραφή:
 * `!isEmptyScene` (καμία εγγραφή σκηνής χωρίς οντότητες) και `isDxfWipe` (καμία εγγραφή που
 * μηδενίζει DXF που ήδη υπάρχει). Και οι δύο ρωτούν **«πόσα έμειναν;»** — ένας αριθμός δεν
 * ξέρει **γιατί** έμειναν τόσα. Έτσι μπλόκαραν σιωπηλά και το νόμιμο: Delete της τελευταίας
 * οντότητας ή Ctrl+Z μιας εισαγωγής σε άδειο όροφο ⇒ μετά την ανανέωση γύριζε το παλιό
 * (ADR-941 §8.3, αναπαράχθηκε ζωντανά 2026-11-14).
 *
 * ## Η απόφαση: πράξη, όχι αριθμός (Google Docs / Figma)
 *
 * Στα συστήματα με λειτουργίες (ops) το «διέγραψα τα πάντα» είναι **πράξη με πρόθεση** και
 * αποθηκεύεται· η άμυνα απέναντι στο σβήσιμο είναι ότι **κατάσταση που δεν προήλθε από
 * πράξη του χρήστη** δεν γράφεται. Εδώ το ίδιο: άδειασμα είναι ρητό **μόνο** όταν μια
 * `local-edit` μετάβαση πήρε σκηνή που **είχε** DXF στη μνήμη — δηλαδή γεωμετρία που ο
 * χρήστης έβλεπε — και την άφησε με **μηδέν**.
 *
 * Τα περιστατικά που προστατεύουν οι φρουροί **δεν** ικανοποιούν τον όρο:
 * - 2026-06-08 (αποτυχημένη φόρτωση ⇒ άδεια σκηνή): η μετάβαση είναι `load`, όχι `local-edit`.
 * - 2026-07-26 / Ρίζα 5 (σκηνή μόνο-BIM, τα DXF δεν κατέβηκαν ποτέ): η προηγούμενη σκηνή είχε
 *   **ήδη** μηδέν DXF ⇒ καμία μετάβαση δεν τα αφαίρεσε ⇒ ο `isDxfWipe` μπλοκάρει όπως πριν.
 */

import type { SceneModel } from '../../types/scene';
import type { SceneWriteOrigin } from './scene-write-origin';
import { countDxfEntities } from './scene-save-ticket';

/**
 * true όταν αυτή η εγγραφή είναι ο χρήστης που αφαιρεί την **τελευταία** γεωμετρία σχεδίου
 * που έβλεπε. Καθαρή συνάρτηση της μετάβασης `previous → next`.
 */
export function isExplicitDxfEmptying(
  previous: SceneModel | null | undefined,
  next: SceneModel,
  origin: SceneWriteOrigin,
): boolean {
  if (origin !== 'local-edit') return false;
  return countDxfEntities(previous) > 0 && countDxfEntities(next) === 0;
}

/**
 * Η πρόθεση **επιβιώνει** μέχρι να γραφτεί. Το debounce συγχωνεύει εγγραφές: μετά το
 * άδειασμα ο χρήστης μπορεί να προσθέσει κολόνα πριν περάσουν 2″ — η νέα μετάβαση έχει
 * προηγούμενη σκηνή με μηδέν DXF, άρα **δεν** είναι η ίδια άδειασμα, αλλά το ticket της
 * κουβαλά ακόμη τη σκηνή χωρίς DXF. Χωρίς μνήμη ο `isDxfWipe` θα την έκοβε.
 *
 * Επιστρέφει την επόμενη κατάσταση της μνήμης για το επίπεδο:
 * - `load` ⇒ `false`: νέα αλήθεια από τον δίσκο, η παλιά πρόθεση δεν ισχύει πια.
 * - σκηνή που ξαναπήρε DXF ⇒ `false`: δεν υπάρχει άδειασμα να προστατευθεί.
 * - ρητό άδειασμα ⇒ `true`· αλλιώς ό,τι ίσχυε.
 */
export function nextExplicitEmptying(
  latched: boolean,
  previous: SceneModel | null | undefined,
  next: SceneModel,
  origin: SceneWriteOrigin,
): boolean {
  if (origin === 'load') return false;
  if (countDxfEntities(next) > 0) return false;
  return latched || isExplicitDxfEmptying(previous, next, origin);
}
