/**
 * 🔴 ADR-771 Φ.2 — **Ο ΖΩΓΡΑΦΟΣ ΤΟΥ ΦΥΛΛΟΥ**: η αδιαφανής επιφάνεια κάτω από τον πίνακα.
 *
 * ## Τι άλλαξε, και τι ΔΕΝ άλλαξε
 * Μέχρι τη Φ.2 ο πίνακας **δεν ζωγράφιζε ποτέ φύλλο** — το `surfaceHex` ήταν αποκλειστικά
 * *είσοδος υπολογισμού* του αυτόματου μελανιού (επαληθευμένο: το μοναδικό `fillRect` σε όλο
 * τον φάκελο ήταν η υπογράμμιση κειμένου). Αυτό **μένει η προεπιλογή**: στην κατάσταση
 * «Καμβάς» εδώ δεν συμβαίνει τίποτα, και ό,τι είναι κάτω από τον πίνακα εξακολουθεί να
 * φαίνεται. Ο ζωγράφος ενεργοποιείται **μόνο** στις καταστάσεις «Φύλλο» / «Χαρτί».
 *
 * ## 🔴 ΠΟΛΥΓΩΝΟ, ΠΟΤΕ `fillRect` — και δεν το ανακαλύπτουμε εδώ
 * Ο πίνακας **περιστρέφεται** (λαβή `table-rotation`). Ένα `fillRect` σε px οθόνης θα έμενε
 * ίσιο μέσα σε γερμένο πλαίσιο: λευκή λωρίδα να ξεφεύγει από τη μια πλευρά και σκούρες
 * γωνίες κελιών να μένουν ακάλυπτες από την άλλη. Ο κανόνας είναι ήδη γραμμένος στο
 * `stamp-table-delete-control.ts` και το SSoT της διαδρομής υπάρχει ήδη: {@link traceRectMm},
 * που περνά και τις **τέσσερις** γωνίες χωριστά από το `toScreen`. Δεύτερη υλοποίηση εδώ θα
 * ήταν το sibling clone που πιάνει το CHECK 3.28 (N.18) — και μια τέταρτη ευκαιρία να
 * ξεχάσει κάποιος τη γωνία.
 *
 * ## Γιατί ΠΡΩΤΟΣ στο z-order
 * Είναι **φόντο**. Οτιδήποτε μετά (γεμίσματα κελιών, σκίαση επιλογής, πλέγμα, κείμενο)
 * κάθεται από πάνω. Ένα αδιαφανές στρώμα οπουδήποτε αλλού θα έσβηνε ό,τι είχε ήδη γραφτεί —
 * η ίδια σειρά «πλύσιμο → δίσκος» που τεκμηριώνει το `stampTableDeleteControl`.
 *
 * ## Ο φρουρός ζει ΕΔΩ, όχι στον καλούντα
 * Η πρώτη γραμμή είναι `if (!rc.surfacePaint) return;` — επίτηδες, όπως ο φρουρός χαρτιού του
 * `stampTableBoundState`. Ο `TableRenderer` καλεί **πάντα**, χωρίς συνθήκη: δεν υπάρχει
 * `if` στον καλούντα που να μπορεί να ξεχαστεί ή να αντιγραφεί λάθος σε δεύτερη διαδρομή.
 *
 * @module subapps/dxf-viewer/rendering/entities/table/stamp-table-sheet
 * @see bim/table/table-ink.ts — `liveTableSurface()`: ΠΟΙΟ χρώμα και ΠΟΙΟΣ το ζωγραφίζει
 * @see rendering/entities/table/stamp-table-layout.ts — `traceRectMm`, η ΜΙΑ διαδρομή ορθογωνίου
 * @see docs/centralized-systems/reference/adrs/ADR-771-table-surface-doctrine.md §4
 */

import { traceRectMm, type StampTableContext } from './stamp-table-layout';
import type { TableLayout } from '../../../bim/table/table-layout-types';

/**
 * Στρώνει την επιφάνεια του πίνακα — ολόκληρο το πλαίσιο, σε **sheet-mm**.
 *
 * ⚠️ **Ολόκληρος ο πίνακας, όχι το ορατό παράθυρο.** Οι γραμμές κόβονται στο παράθυρο για
 * να μη ζωγραφιστούν χιλιάδες κελιά· το φύλλο είναι **τέσσερις κορυφές** ό,τι κι αν κάνει ο
 * πίνακας, οπότε το κόψιμο δεν θα γλίτωνε τίποτα και θα άφηνε το φύλλο να «τελειώνει» στη
 * μέση σε κάθε κύλιση.
 *
 * @param rc     το πλαίσιο ζωγραφικής — κατέχει `surfaceHex`, `surfacePaint` και την προβολή
 * @param layout η διάταξη, **μόνο** για τις διαστάσεις του πλαισίου
 */
export function stampTableSheet(rc: StampTableContext, layout: TableLayout): void {
  // 🔴 Ο ΦΡΟΥΡΟΣ — δες την κεφαλίδα. Πρώτη γραμμή επίτηδες.
  if (!rc.surfacePaint) return;

  const { ctx } = rc;
  ctx.save();
  // Το χρώμα **δεν επιλέγεται εδώ**: είναι το ίδιο `surfaceHex` πάνω στο οποίο η διάταξη
  // μόλις υπολόγισε κάθε μελάνι. Δεύτερη πηγή χρώματος θα σήμαινε πίνακα που ζωγραφίζει
  // φύλλο διαφορετικό από αυτό που υπέθεσε όταν διάλεγε λευκά ή μαύρα γράμματα.
  ctx.fillStyle = rc.surfaceHex;
  traceRectMm(rc, { x: 0, y: 0, w: layout.widthMm, h: layout.heightMm });
  ctx.fill();
  ctx.restore();
}
