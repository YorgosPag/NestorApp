/**
 * ADR-739 Φ.Δ βήμα 2 — το ορθογώνιο του **τρέχοντος κελιού** (Excel cell cursor).
 *
 * ⚠️ **Ζωγραφίζεται ΠΑΝΤΑ τελευταίο και ΠΟΤΕ μέσα στο cached raster.** Ο καλών το
 * επιτρέπει μόνο στη φάση επιλογής/hover, δηλαδή στο overlay pass του
 * `dxf-canvas-interactive-overlays` — ADR-040 κανόνας #3. Αν έμπαινε στο bitmap cache,
 * κάθε `Tab` θα ακύρωνε ολόκληρο το raster της σκηνής.
 *
 * Οι τέσσερις γωνίες περνούν από το `toScreen` (και όχι ένα `strokeRect` πάνω σε δύο
 * σημεία): ο πίνακας μπορεί να είναι **περιστραμμένος**, και ένα ορθογώνιο σε άξονες
 * οθόνης θα κρεμόταν λοξά πάνω από το κελί. Ίδιος δρόμος με τα γεμίσματα.
 *
 * Δεν παίρνει `phaseColor`: ο δρομέας είναι δείκτης **διεπαφής**, όχι κατάσταση της
 * οντότητας — μια hovered επιλογή δεν αλλάζει ποιο κελί δέχεται την πληκτρολόγηση.
 */
export function stampTableCellCursor(rc: StampTableContext, rectMm: TableRectMm): void {
  strokeRectMm(rc, rectMm, TABLE_CELL_CURSOR.colorHex, TABLE_CELL_CURSOR.lineWidthPx, []);
}

/**
 * 🔴 ADR-739 Φ.Δ βήμα 8 / §41 — **η επιλεγμένη περιοχή**: ημιδιαφανής σκίαση πάνω στα κελιά
 * της, **τρύπα στο ενεργό κελί**, συμπαγές περίγραμμα γύρω από ολόκληρη.
 *
 * ## 🔴 §41 — ΤΟ ΕΝΕΡΓΟ ΚΕΛΙ ΔΕΝ ΒΑΦΕΤΑΙ. Αυτή **είναι** η προδιαγραφή.
 * Μετρημένο από στιγμιότυπο του Excel (04/08, επιλογή `B10:C13` με ενεργό το `B10`):
 *
 * ```
 *   ενεργό κελί B10 → #FFFFFF   (καθαρό φόντο φύλλου, σε ΟΛΟ το εσωτερικό του)
 *   κάθε άλλο κελί → #C6C6C6   (σκιασμένο)
 *   ακμή B10|C10   → #ADADAD   (γραμμή πλέγματος, ΟΧΙ δεύτερο περίγραμμα)
 * ```
 *
 * Η **τρίτη** μέτρηση είναι αυτή που κλείνει το θέμα: το Excel **δεν** ζωγραφίζει πλαίσιο
 * γύρω από το ενεργό κελί όσο η επιλογή είναι πολυκελιακή. Ο μόνος δείκτης του είναι η
 * **απουσία σκίασης** — και ακριβώς γι' αυτό η τρύπα δεν είναι διακόσμηση: αν βαφτεί, ο
 * χρήστης χάνει το «πού θα πάει ό,τι πληκτρολογήσω και πού επιστρέφει το `Enter`», που είναι
 * η μισή σημασία μιας επιλογής σε φύλλο.
 *
 * ## Γιατί `evenodd` και όχι δεύτερο γέμισμα «από πάνω»
 * Η προφανής εναλλακτική — ξαναβάψε το ενεργό κελί με το χρώμα της επιφάνειας — είναι
 * **λάθος** για τον ίδιο λόγο που η σκίαση είναι ημιδιαφανής: θα έσβηνε ό,τι υπάρχει από
 * κάτω (γέμισμα κελιού, γραμμές πλέγματος, διαγώνιος). Το `evenodd` σε **μία** διαδρομή δεν
 * βάφει ποτέ το εσωτερικό ορθογώνιο, άρα δεν έχει τίποτα να σβήσει· και κοστίζει **ένα**
 * `fill`, όπως πριν.
 *
 * ## Γιατί ζωγραφίζεται ως **ένα** ορθογώνιο και όχι κελί-κελί
 * Η περιοχή είναι ορθογώνια εξ ορισμού (και κουμπωμένη σε ολόκληρες συγχωνεύσεις), οπότε
 * ένα `fill` αρκεί για οποιοδήποτε μέγεθος. Ένα γέμισμα ανά κελί θα πλήρωνε O(εμβαδόν)
 * κλήσεις ανά καρέ για επιλογή 500 × 20 — το σχήμα που ο ADR-735 πλήρωσε σε παραγωγή. Και
 * θα έδειχνε **χειρότερα**: τα ημιδιαφανή γεμίσματα των γειτονικών κελιών επικαλύπτονται
 * στις κοινές ακμές και αφήνουν πιο σκούρες γραμμές, δηλαδή ένα φάντασμα πλέγμα.
 *
 * ⚠️ Ζωγραφίζεται **πριν** το κείμενο και τον δρομέα, όπως τα γεμίσματα κελιών: ένα
 * ημιδιαφανές στρώμα πάνω από τα γράμματα θα τα θόλωνε — και η επιλογή υπάρχει ακριβώς για
 * να **διαβάσεις** τι μάρκαρες.
 *
 * @param activeCellRectMm το ορθογώνιο του **ενεργού** κελιού (ολόκληρη η συγχώνευση, αν
 *   είναι συγχωνευμένο). Παραλείπεται μόνο όταν δεν υπάρχει — τότε σκιάζεται όλη η περιοχή.
 *   Όταν η επιλογή είναι 1×1 τα δύο ορθογώνια **ταυτίζονται** και η σκίαση μηδενίζεται από
 *   μόνη της: το μονοσύνολο δεν είναι ειδική περίπτωση, είναι το ίδιο ερώτημα με μία
 *   απάντηση — ακριβώς όπως στο Excel, όπου ένα επιλεγμένο κελί δείχνει μόνο περίγραμμα.
 */
export function stampTableSelection(
  rc: StampTableContext,
  rectMm: TableRectMm,
  activeCellRectMm?: TableRectMm,
): void {
  const { ctx } = rc;
  ctx.save();
  ctx.fillStyle = tableSelectionWashRgba(rc.surfaceHex);
  ctx.beginPath();
  appendRectSubpath(rc, rectMm);
  if (activeCellRectMm) appendRectSubpath(rc, activeCellRectMm);
  // `evenodd`: σημείο μέσα σε **δύο** υποδιαδρομές μένει άβαφο. Το ενεργό κελί είναι πάντα
  // μέσα στην περιοχή (το εγγυάται το `resolveTableSelectionBounds`), άρα η δεύτερη
  // υποδιαδρομή είναι πάντα τρύπα και ποτέ δεύτερο σχήμα.
  ctx.fill('evenodd');
  ctx.restore();
  strokeRectMm(
    rc,
    rectMm,
    TABLE_CELL_SELECTION.outlineHex,
    TABLE_CELL_SELECTION.outlineWidthPx,
    [],
  );
}

/**
 * ADR-739 Φ.Δ βήμα 4 — το περίγραμμα **ολόκληρου** του πίνακα όσο το πληκτρολόγιο του
 * ανήκει (λειτουργία πίνακα).
 *
 * ## Γιατί δεύτερος δείκτης και όχι «αρκεί ο δρομέας κελιού»
 * Ο δρομέας απαντά «ποιο κελί δέχεται ό,τι πληκτρολογήσω». Το ερώτημα του βήματος 4 είναι
 * **άλλο**: «γιατί έπαψε να δουλεύει το `L` για γραμμή;». Είναι δύο διαφορετικά επίπεδα —
 * κελί μέσα σε πίνακα, πίνακας μέσα σε καμβά — και ο χρήστης χρειάζεται να δει και τα δύο,
 * ακριβώς όπως το Figma δείχνει **και** το επιλεγμένο κείμενο **και** το πλαίσιο που έχεις
 * μπει μέσα του.
 *
 * ## Γιατί ίδιο χρώμα αλλά **διακεκομμένο**
 * Και οι δύο είναι δείκτες **διεπαφής**, άρα ανήκουν στο ίδιο λεξιλόγιο — ένα τέταρτο
 * χρώμα θα έσπαγε τη ρητή αιτιολόγηση του {@link TABLE_CELL_CURSOR}. Η **τάξη** τους όμως
 * διαφέρει, και η διακεκομμένη γραμμή είναι ο καθιερωμένος τρόπος να ειπωθεί «περιέχον
 * πλαίσιο» χωρίς νέο χρώμα: συμπαγές = εδώ πάει το πλήκτρο, διακεκομμένο = εδώ βρίσκεσαι.
 *
 * ## 🔴 §37 — ΔΕΝ κάθεται πάνω στο πλαίσιο· κάθεται **έξω** από αυτό
 * Μέχρι τις 04/08 το ορθογώνιο ήταν **ταυτόσημο** με το πλαίσιο του πίνακα, δηλαδή οι δύο
 * γραμμές μοιράζονταν διαδρομή. Όσο η περίμετρος ήταν 0,5 mm η επικάλυψη ήταν μερική· με
 * **0,13 mm** (ADR-750) ο δείκτης έγινε **παχύτερος από τη γραμμή που έκρυβε** σε κάθε
 * ρεαλιστικό zoom. Η μετατόπιση γεννιέται στο {@link tableModeOutlineRectMm} — εκεί ζει και
 * η πλήρης μέτρηση, μαζί με το γιατί δεν υπάρχει ταβάνι.
 *
 * ⚠️ Ισχύουν αυτούσιοι οι δύο κανόνες του {@link stampTableCellCursor}: overlay pass μόνο
 * (ADR-040 #3) και τέσσερις γωνίες από το `toScreen`, γιατί ο πίνακας περιστρέφεται.
 *
 * @param gridRectMm το ορθογώνιο του **πλέγματος** — ό,τι ζωγραφίζει ο πίνακας. Ο δείκτης
 *   κρατά απόσταση από αυτό· ο καλών δεν υπολογίζει τη μετατόπιση και δεν τη γνωρίζει.
 * @param perimeterPenMm το παχύτερο **ορατό** μολύβι της περιμέτρου
 *   (`TableRenderIndex.perimeterMaxWidthMm`) — αυτό ακριβώς που δεν επιτρέπεται να καλυφθεί.
 */
export function stampTableModeOutline(
  rc: StampTableContext,
  gridRectMm: TableRectMm,
  perimeterPenMm: number,
): void {
  strokeRectMm(
    rc,
    tableModeOutlineRectMm(gridRectMm, rc.pxPerMm, perimeterPenMm),
    TABLE_MODE_OUTLINE.colorHex,
    TABLE_MODE_OUTLINE.lineWidthPx,
    TABLE_MODE_OUTLINE.dashPx,
  );
}

/**
 * Ο **ένας** χάρακας ορθογωνίου σε συντεταγμένες φύλλου. Και οι δύο δείκτες περνούν από
 * εδώ: το CHECK 3.28 (jscpd, N.18) θα χαρακτήριζε δύο ταυτόσημα σώματα 15 γραμμών ως
 * sibling clone — σωστά, αφού διαφέρουν **μόνο** σε τρεις παραμέτρους στυλ.
 *
 * Οι τέσσερις γωνίες περνούν χωριστά από το `toScreen` (και όχι `strokeRect` σε δύο
 * σημεία) επειδή ο πίνακας μπορεί να είναι **περιστραμμένος** — δες {@link stampTableFills}.
 *
 * 🔴 ADR-739 §36 ΦΑΣΗ 3 — **έγινε δημόσιο** όταν απέκτησε τρίτο καταναλωτή (το φάντασμα
 * προορισμού, `stamp-table-range-ghost`). Δεν μετακόμισε: εδώ ζουν όλα τα ορθογώνια του
 * πίνακα και το `traceRectMm` που καταναλώνει. Ένα τέταρτο αντίγραφο του σώματος —
 * `save`/`strokeStyle`/`lineWidth`/`setLineDash`/`trace`/`stroke`/`restore` — είναι ακριβώς
 * το sibling clone που πιάνει το CHECK 3.28 (N.18), **ανεξάρτητα ονόματος**.
 */
export function strokeRectMm(
  rc: StampTableContext,
  rectMm: TableRectMm,
  colorHex: string,
  lineWidthPx: number,
  dashPx: readonly number[],
): void {
  const { ctx } = rc;
  ctx.save();
  ctx.strokeStyle = colorHex;
  ctx.lineWidth = lineWidthPx;
  // `slice()`: το `setLineDash` δέχεται μεταβλητό πίνακα, και η σταθερά είναι κοινή.
  ctx.setLineDash(dashPx.slice());
  traceRectMm(rc, rectMm);
  ctx.stroke();
  ctx.restore();
}

