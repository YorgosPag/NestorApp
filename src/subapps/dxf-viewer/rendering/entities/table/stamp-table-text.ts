/** Κάτω από αυτό το ύψος κεφαλαίου στην οθόνη, το κείμενο κελιού δεν ζωγραφίζεται. */
export const MIN_CELL_TEXT_SCREEN_PX = 5;

/**
 * Η λωρίδα αποκοπής ενός τμήματος, ως πολλαπλάσια του `em` γύρω από τη **γραμμή βάσης**.
 *
 * Γενναιόδωρα και προς τις δύο κατευθύνσεις (η ζώνη ανιούσας→κατιούσας είναι ~0,8/0,2·em):
 * η αποκοπή υπάρχει για να περιορίσει το **οριζόντιο** εύρος, και ένα στενό κάθετο όριο θα
 * έκοβε τόνους, ουρές ή πλάγια γραφή που ξεπερνά τη ζώνη — δηλαδή θα εισήγαγε ακριβώς το
 * οπτικό ελάττωμα που η αποκοπή υπάρχει για να αποφύγει.
 */
const LINK_CLIP_ABOVE_EM = 1.3;
const LINK_CLIP_BELOW_EM = 0.6;

/**
 * 🔴 ADR-739 Φ.Δ βήμα 3 — **Η ΜΙΑ γραμματοσειρά του κειμένου κελιού**, ως αλφαριθμητικό
 * που δέχονται **και** το `ctx.font` του καμβά **και** το CSS `font` shorthand του DOM.
 *
 * Ο in-cell επεξεργαστής είναι ένα `<input>` πάνω ακριβώς από το κελί. Αν χρησιμοποιούσε
 * *δική του* γραμματοσειρά, το κείμενο θα **αναπηδούσε** τη στιγμή του διπλού κλικ και ο
 * κέρσορας θα έπεφτε σε άλλο γράμμα από αυτό που δείχνει ο χρήστης — γιατί ο υπολογισμός
 * πλάτους θα γινόταν σε δύο διαφορετικές γραμματοσειρές. Με **κοινό** αλφαριθμητικό, οι
 * δύο μετρήσεις είναι κυριολεκτικά η **ίδια** μέτρηση της ίδιας μηχανής του browser.
 *
 * ## ✅ ADR-739 Φ.Ε (Α3) — το χρέος «πάντα Arial» ΕΚΛΕΙΣΕ
 * Μέχρι τη Φ.Ε το `'arial'` ήταν καρφωμένο εδώ ενώ ο **μετρητής** διάβαζε το
 * `TableCellStyle.fontFamily`: δύο απαντήσεις στην ίδια ερώτηση, με σύμπτωμα κείμενο που
 * κόβεται ή αφήνει κενό — ορατό μόνο σε όποιον δήλωνε άλλη οικογένεια, δηλαδή σε κανέναν,
 * μέχρι να βγει το χειριστήριο γραμματοσειράς. Τώρα η οικογένεια ταξιδεύει στο
 * `TableTextRun` και τη διαβάζουν και οι δύο.
 *
 * 🔴 **Γιατί ΟΧΙ το `paintTextRun` του text-engine** (η προφανής «κεντρικοποίηση» που θα
 * ήταν λάθος): εκείνο ζωγραφίζει **περιγράμματα glyph** μέσω opentype όταν βρει φορτωμένη
 * γραμματοσειρά CAD. Ο in-cell επεξεργαστής είναι `<input>` — **δεν μπορεί** να ζωγραφίσει
 * περιγράμματα. Θα ξαναγεννούσαμε ακριβώς την ασυμφωνία που αυτή η συνάρτηση υπάρχει για να
 * λείπει, μόνο που τώρα ανάμεσα σε καμβά και πεδίο. Το κοινό αλφαριθμητικό είναι η
 * **προϋπόθεση**, όχι η ευκολία — και το `measureTextAdvanceWorld` πέφτει στην ίδια
 * `buildUIFont` στη 2η βαθμίδα του, άρα μέτρηση και ζωγραφική μένουν η ίδια μηχανή.
 */
export function tableCellFont(
  fontPx: number,
  bold: boolean,
  italic = false,
  fontFamily?: string,
): string {
  // Το ίδιο default με το `baseAdvanceWorld` του text-engine (`style?.fontFamily || 'arial'`):
  // απούσα οικογένεια πρέπει να δίνει **μία** προεπιλογή, όχι μία εδώ και μία εκεί.
  return buildUIFont(fontPx, fontFamily || 'arial', bold ? 'bold' : 'normal', italic);
}

/**
 * 🔴 ADR-739 Φ.Δ βήμα 8 — **Ο ΕΝΑΣ ΣΤΑΜΠΑΔΟΡΟΣ ΚΕΙΜΕΝΟΥ ΤΟΥ ΠΙΝΑΚΑ**, γερμένος όπως ο
 * πίνακας. Τον καλούν **και** τα κείμενα των κελιών ({@link stampRun}) **και** οι ετικέτες
 * των ζωνών `A B C` / `1 2 3` (`stamp-table-indicator.ts`).
 *
 * ## Τι διόρθωσε (μετρημένο, 2026-08-01)
 * Ο πίνακας με `angleRad = 0.35` (≈20°) ζωγραφιζόταν **γερμένος** — πλέγμα, γεμίσματα,
 * δρομέας, ζώνες, όλα περνούσαν από το `toScreen`. Τα **γράμματα** όμως έμεναν **ίσια στην
 * οθόνη**, γιατί εδώ δεν υπήρχε καμία `ctx.rotate`. Στο εξαγόμενο DXF το ίδιο κείμενο
 * βγήκε με `rot = 20,053523°` (διαβάστηκε από το αρχείο, και τα τρία `halign`).
 *
 * Άρα **δεν ήταν τεκμηριωμένη επιλογή — ήταν ασυμφωνία**: τέσσερις μηχανές απαντούσαν στην
 * ίδια ερώτηση και **τρεις** συμφωνούσαν (εξαγωγή DXF, εξαγωγή PDF, επεξεργαστής κελιού με
 * `rotate(-0.35rad)`). Ο ζωγράφος του καμβά ήταν ο **ένας** που διαφωνούσε, και το
 * επιχείρημα της εξαγωγής («αλλιώς το κείμενο βγαίνει έξω από το κελί του») ισχύει
 * **ακριβώς το ίδιο** στην οθόνη — φαινόταν με γυμνό μάτι.
 *
 * ## Γιατί το ίδιο ισχύει και για τις ζώνες δείκτη
 * Θα μπορούσε να επιχειρηματολογήσει κανείς ότι οι ζώνες είναι **διεπαφή**, όχι σχέδιο,
 * και άρα οφείλουν να μένουν ευανάγνωστες. Το επιχείρημα καταρρέει σε ένα σημείο: τα
 * **ορθογώνια** των ζωνών ήδη γέρνουν (περνούν από το `toScreen`). Ένα ίσιο γράμμα μέσα σε
 * γερμένο κουτί δεν είναι «αναγνωσιμότητα» — είναι γράμμα που σε αρκετή γωνία **δραπετεύει
 * από το κουτί του**. Το να γέρνει και το κουτί και το γράμμα είναι το μόνο ζεύγος που
 * παραμένει συνεπές σε κάθε γωνία, και είναι ό,τι κάνει ήδη ο επεξεργαστής κελιού δίπλα
 * τους. Ένα ερώτημα, μία απάντηση, ένα σημείο αλλαγής.
 *
 * ## Τι ΔΕΝ κάνει: δεν «ορθώνει» ανάποδο κείμενο
 * Σε γωνία > 90° το κείμενο γέρνει πέρα από την κατακόρυφο — και στην οθόνη **και** στο
 * DXF, γιατί ο exporter γράφει το ωμό `rotationDeg` χωρίς αναστροφή. Μια «διόρθωση
 * αναγνωσιμότητας» μόνο εδώ θα ξαναγεννούσε **ακριβώς** την ασυμφωνία που αυτό το βήμα
 * έκλεισε. Αν κάποτε θελήσουμε όρθια γράμματα σε ανεστραμμένους πίνακες, ο κανόνας ανήκει
 * στη **διάταξη** (κοινή σε ζωγράφο και exporter), όχι στο μελάνι.
 *
 * @param anchorScreen το σημείο **οθόνης** που ήδη υπολόγισε ο καλών μέσω `toScreen`
 */
export function stampFrameText(
  rc: StampTableContext,
  anchorScreen: Point2D,
  text: string,
  underline?: TableUnderlineGeometry | null,
): void {
  const { ctx } = rc;
  // Μετάθεση **πρώτα**, στροφή **μετά**: η στροφή γίνεται γύρω από την άγκυρα του κειμένου
  // (τη γραμμή βάσης στη θέση στοίχισης), όχι γύρω από την αρχή του καμβά. Αντίστροφα, το
  // κείμενο θα εκτοξευόταν κατά `|anchor| · sin(γωνία)` px μακριά από το κελί του.
  ctx.translate(anchorScreen.x, anchorScreen.y);
  ctx.rotate(rc.textAngleRad);
  // Το `textAlign` / `textBaseline` που έθεσε ο καλών ισχύουν πλέον στο **στραμμένο**
  // σύστημα — δηλαδή «δεξιά στοίχιση» σημαίνει «δεξιά μέσα στο κελί», που είναι ακριβώς η
  // σημασία που ήδη ταξιδεύει στο DXF ως `halign` (μετρήθηκε: 0/1/2 για left/center/right).
  ctx.fillText(text, 0, 0);
  // ADR-739 Φ.Ε — η υπογράμμιση ζωγραφίζεται **μέσα στην ίδια στροφή**: έξω από αυτήν θα
  // έμενε οριζόντια κάτω από γερμένο κείμενο, δηλαδή το ίδιο ελάττωμα που το βήμα 8 έκλεισε
  // για τα ίδια τα γράμματα.
  if (underline) stampUnderline(ctx, underline);
}

/**
 * Η γραμμή της υπογράμμισης, στο **ήδη στραμμένο** σύστημα του {@link stampFrameText}.
 *
 * 🔴 **Ο καμβάς δεν αποφασίζει πια πού πέφτει η γραμμή — τη ρωτά.** Η γεωμετρία έρχεται
 * ολόκληρη από το `tableUnderlineGeometry` (ADR-739 Φ.Ε/Φ2 βήμα 4), το ΙΔΙΟ σημείο που
 * ρωτά και η γέφυρα εξαγωγής για PDF/DXF/ΤΕΚ. Μέχρι το βήμα 4 εδώ ζούσε δεύτερος
 * υπολογισμός — και ήταν **λάθος** κατά 0,2·em (το σκεπτικό, μετρημένο, στο ίδιο module).
 *
 * Το μόνο που μένει τοπικό είναι το **δάπεδο του ενός pixel**: είναι όρος **οθόνης** (μια
 * γραμμή λεπτότερη από ένα pixel εξαφανίζεται σε μεγάλη σμίκρυνση), όχι σχεδιαστική
 * ιδιότητα — σε χαρτί και σε DXF το πάχος οφείλει να μείνει το πραγματικό κλάσμα του `em`.
 */
function stampUnderline(ctx: CanvasRenderingContext2D, g: TableUnderlineGeometry): void {
  if (!(g.width > 0)) return;
  ctx.fillRect(g.x, g.y, g.width, Math.max(g.thickness, 1));
}

/** Ταυτότητα κελιού — το κλειδί με το οποίο ο καλών ζητά παράλειψη ζωγραφικής. */
export interface TableCellRef {
  readonly rowId: string;
  readonly colId: string;
}

/**
 * Τα κείμενα των κελιών. Το `run.position.y` είναι η **γραμμή βάσης** (σύμβαση
 * `TableTextRun` / `TextPrimitive`), γι' αυτό `textBaseline = 'alphabetic'` — η
 * προεπιλογή. Ρητό `'middle'` εδώ θα μετατόπιζε κάθε γραμμή κατά μισό ύψος κεφαλαίου:
 * ακριβώς το σφάλμα του 1,5mm που η Φ.Β πλήρωσε επειδή μπέρδεψε τη γραμμή
 * περιεχομένου με την ακμή.
 *
 * `skip` (ADR-739 Φ.Δ βήμα 3) = το κελί που έχει **ανοιχτή συνεδρία γραφής**: εκεί το
 * κείμενο το κατέχει το `<input>` του επεξεργαστή. Χωρίς αυτό, το δεσμευμένο κείμενο και
 * το πρόχειρο ζωγραφίζονται **ταυτόχρονα**, το ένα πάνω στο άλλο — το «διπλό κείμενο» που
 * φαινόταν στο στιγμιότυπο του Giorgio (2026-08-01). Στο Excel το κελί που επεξεργάζεσαι
 * δείχνει **μόνο** το πεδίο εισαγωγής.
 *
 * Επιστρέφει `false` όταν το LOD έκοψε το κείμενο — ο καλών το χρειάζεται για tests.
 */
export function stampTableText(
  rc: StampTableContext,
  cells: readonly TableCellLayout[],
  skip?: TableCellRef | null,
): boolean {
  const { ctx } = rc;
  let drewAny = false;
  for (const cell of cells) {
    const run = cell.text;
    if (!run) continue;
    if (skip && cell.rowId === skip.rowId && cell.colId === skip.colId) continue;
    const fontPx = run.heightMm * rc.pxPerMm;
    if (fontPx < MIN_CELL_TEXT_SCREEN_PX) continue;
    stampRun(ctx, rc, run, fontPx);
    drewAny = true;
  }
  return drewAny;
}

/**
 * ⚠️ **Το κείμενο ΔΕΝ δέχεται ποτέ το `phaseColor` — μετρημένο ελάττωμα, όχι προτίμηση.**
 *
 * Το χρώμα φάσης βάφει τη **σιλουέτα** (γεμίσματα + πλέγμα). Αν έβαφε και τα γράμματα, ένα
 * κελί **με γέμισμα** θα έπαιρνε το ίδιο χρώμα δύο φορές — φόντο και μελάνι — και το κείμενο
 * θα εξαφανιζόταν σε μονόχρωμο πλακάκι. Ακριβώς αυτό συνέβαινε: στο hover η **γραμμή
 * κεφαλίδων** (το μόνο μέρος με `fillColorHex`) έχανε τα «Α/Α · Περιγραφή · Ποσότητα», ενώ
 * οι σειρές δεδομένων — χωρίς γέμισμα, άρα με το σκούρο φόντο του καμβά από πίσω — κρατούσαν
 * τα γράμματά τους. Η ασυμμετρία ήταν το αποτύπωμα: **όποιο κελί έχει γέμισμα, χάνει το
 * κείμενο** (επαληθεύτηκε στην οθόνη, 2026-07-31, ADR-739 §19.8).
 *
 * Το κείμενο κρατά το `run.colorHex` του, οπότε η αντίθεση που σχεδίασε ο συγγραφέας του
 * στυλ επιβιώνει σε **κάθε** φάση. Ίδια αρχή με το AutoCAD: το highlight αλλάζει τη
 * σιλουέτα της οντότητας, δεν την κάνει δυσανάγνωστη.
 */
function stampRun(
  ctx: CanvasRenderingContext2D,
  rc: StampTableContext,
  run: TableTextRun,
  fontPx: number,
): void {
  const anchor = rc.toScreen(run.position.x, run.position.y);
  const whole = wholeRunLink(run);

  ctx.save();
  // ADR-751 — όταν ΟΛΟ το κελί είναι ο σύνδεσμος, το μελάνι ξεκινά μπλε και δεν χρειάζεται
  // κανένα δεύτερο πέρασμα: ίδιος αριθμός `fillText` με πριν, ίδια ακριβώς glyph.
  ctx.fillStyle = whole ? TABLE_CELL_LINK.colorHex : run.colorHex;
  ctx.font = tableCellFont(fontPx, run.bold, run.italic, run.fontFamily);
  ctx.textAlign = run.hAlign;
  ctx.textBaseline = 'alphabetic';
  // ADR-739 Φ.Δ βήμα 8 — γερμένο όπως ο πίνακας, όπως ήδη γέρνουν το DXF, το PDF και ο
  // επεξεργαστής κελιού. Δες το {@link stampFrameText} για το γιατί άλλαξε.
  //
  // ADR-739 Φ.Ε/Φ2 βήμα 4 — το πλάτος έρχεται από τη **διάταξη** (`advanceMm`), όχι από
  // δεύτερο `ctx.measureText` σε κάθε καρέ: η ίδια μέτρηση που αποφάσισε τα πλάτη στηλών και
  // την περικοπή ορίζει και την έκταση της γραμμής, σε καμβά **και** στην εξαγωγή.
  stampFrameText(rc, anchor, run.text, underlineOf(run, whole, fontPx, rc.pxPerMm));
  ctx.restore();

  // Μικτό κείμενο: τα τμήματα χρειάζονται δικό τους πέρασμα με αποκοπή. Δες την κεφαλίδα.
  if (!whole && run.links) stampLinkSpans(rc, anchor, run, fontPx);
}

/**
 * Η γεωμετρία υπογράμμισης ενός run σε **px οθόνης**, ή `null` όταν δεν υπογραμμίζεται.
 *
 * Δύο πηγές, με σαφή σειρά: η υπογράμμιση του **στυλ** (ένωση `TableTextRun` — μόλις
 * στενέψει στο `underline: true`, ο μεταγλωττιστής εγγυάται το `advanceMm`) και, όταν αυτή
 * λείπει, η υπογράμμιση που φέρνει ο **σύνδεσμος**. Δεν αθροίζονται: δύο γραμμές στο ίδιο
 * `y` είναι μία γραμμή, και το να ζωγραφιστεί δεύτερη φορά μόνο κόστος έχει.
 */
function underlineOf(
  run: TableTextRun,
  whole: TableTextLinkSpan | null,
  fontPx: number,
  pxPerMm: number,
): TableUnderlineGeometry | null {
  if (run.underline) return tableUnderlineGeometry(fontPx, run.advanceMm * pxPerMm, run.hAlign);
  if (whole) return tableUnderlineGeometry(fontPx, whole.advanceMm * pxPerMm, run.hAlign);
  return null;
}

/**
 * Τα τμήματα-σύνδεσμοι μέσα σε **μικτό** κείμενο: μπλε γράμματα + υπογράμμιση, μόνο στη
 * λωρίδα τους.
 *
 * Το κείμενο ζωγραφίζεται **ολόκληρο ξανά** μέσα σε αποκοπή αντί να ζωγραφιστεί το τμήμα
 * μόνο του — δες την ενότητα «γιατί με αποκοπή» στην κεφαλίδα του module. Η στροφή και η
 * στοίχιση επαναλαμβάνονται αυτούσιες, ώστε το δεύτερο πέρασμα να πέφτει **ακριβώς** πάνω
 * στο πρώτο· γι' αυτό και το `textAlign` παραμένει αυτό του run και το `x` του τμήματος
 * είναι ήδη εκφρασμένο ως προς την ίδια άγκυρα (`offsetMm`).
 */
function stampLinkSpans(
  rc: StampTableContext,
  anchorScreen: Point2D,
  run: TableTextRun,
  fontPx: number,
): void {
  const { ctx } = rc;
  const links = run.links;
  if (!links) return;

  ctx.save();
  ctx.translate(anchorScreen.x, anchorScreen.y);
  ctx.rotate(rc.textAngleRad);
  ctx.fillStyle = TABLE_CELL_LINK.colorHex;
  ctx.font = tableCellFont(fontPx, run.bold, run.italic, run.fontFamily);
  ctx.textAlign = run.hAlign;
  ctx.textBaseline = 'alphabetic';

  for (const span of links) {
    const xPx = span.offsetMm * rc.pxPerMm;
    const widthPx = span.advanceMm * rc.pxPerMm;
    if (!(widthPx > 0)) continue;

    ctx.save();
    ctx.beginPath();
    ctx.rect(xPx, -fontPx * LINK_CLIP_ABOVE_EM, widthPx, fontPx * (LINK_CLIP_ABOVE_EM + LINK_CLIP_BELOW_EM));
    ctx.clip();
    ctx.fillText(run.text, 0, 0);
    ctx.restore();

    // Η γραμμή ζητιέται με `'left'` — το `x` της στοίχισης το έχει ήδη λύσει το `offsetMm` —
    // και μετατοπίζεται εκεί. Ίδιο SSoT γεωμετρίας, ίδιος ζωγράφος, καμία δεύτερη απόφαση.
    const geometry = tableUnderlineGeometry(fontPx, widthPx, 'left');
    stampUnderline(ctx, { ...geometry, x: geometry.x + xPx });
  }

  ctx.restore();
}
