/**
 * ADR-739 Φάση Γ / ADR-751 — **το κείμενο των κελιών στον καμβά.**
 *
 * Εξήχθη από το `stamp-table-layout.ts` όταν εκείνο ξαναπλησίασε τις 500 γραμμές (N.7.1),
 * με τον **ίδιο** γνώμονα που είχε βγάλει πριν το πλέγμα (`stamp-table-borders.ts`, ADR-750
 * Φ5): εκείνο το αρχείο μιλά τη γλώσσα του **ορθογωνίου** — `toScreen`, γεμίσματα, δρομέας,
 * ζώνες, περιγράμματα — ενώ όλα εδώ μιλούν τη γλώσσα της **γραμματοσειράς**: `ctx.font`,
 * γραμμή βάσης, υπογράμμιση, LOD γραμμάτων. Δύο ευθύνες που έτυχε να μοιράζονται αρχείο.
 *
 * ## 🔴 ADR-751 — γιατί ο σύνδεσμος ζωγραφίζεται με ΑΠΟΚΟΠΗ και όχι με δεύτερο `fillText`
 *
 * Ο προφανής τρόπος να βαφτεί μπλε ένα κομμάτι της γραμμής είναι να ζωγραφιστεί το κομμάτι
 * μόνο του στη θέση του. **Μετακινεί τα γράμματα:** το `fillText('2310788493')` σε μια
 * υπολογισμένη θέση δεν παράγει τα ίδια pixel με το `fillText('Τηλ: 2310788493')`, γιατί
 * λείπει το ζεύγος kerning στο όριο και επειδή η στρογγυλοποίηση υπο-pixel γίνεται αλλού.
 * Το κείμενο θα «κουνιόταν» τη στιγμή που κάτι μέσα του γίνεται σύνδεσμος.
 *
 * Με αποκοπή, ζωγραφίζεται **δύο φορές το ίδιο ακριβώς string στην ίδια ακριβώς θέση**, και
 * η δεύτερη φορά περιορίζεται στη λωρίδα του τμήματος. Τα glyph είναι κυριολεκτικά τα ίδια·
 * αλλάζει μόνο ποιο χρώμα βγαίνει σε ποιο x. Είναι το ίδιο κόλπο που κάνει κάθε
 * επεξεργαστής κειμένου για τον τονισμό επιλογής.
 *
 * ⚠️ **Και ούτε αυτό πληρώνεται στην κύρια περίπτωση.** Όταν ολόκληρο το κελί είναι ο
 * σύνδεσμος — μια στήλη «E-mail», δηλαδή σχεδόν κάθε πραγματικό παράδειγμα — δεν υπάρχει
 * τμήμα να απομονωθεί: το `fillStyle` απλώς ξεκινά μπλε και η ζωγραφική είναι **ένα**
 * `fillText`, ταυτόσημη με πριν το ADR-751. Δες {@link wholeRunLink}.
 *
 * @module subapps/dxf-viewer/rendering/entities/table/stamp-table-text
 * @see bim/table/table-cell-link-spans.ts — πού κάθεται κάθε τμήμα (η μέτρηση)
 * @see bim/table/table-text-decoration.ts — πού κάθεται η γραμμή (η γεωμετρία)
 */

