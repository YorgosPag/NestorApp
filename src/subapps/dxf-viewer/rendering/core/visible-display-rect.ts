/**
 * «Τι κομμάτι του χαρτιού βλέπει αυτή τη στιγμή η οθόνη;» — μία ερώτηση, ένα σπίτι.
 *
 * ## Γιατί εξήχθη
 * Ο υπολογισμός ζούσε ιδιωτικός μέσα στον ζωγράφο του καννάβου ΕΓΣΑ (ADR-656 M11). Τη στιγμή
 * που ένας **δεύτερος** ζωγράφος χρειάστηκε την ίδια απάντηση — το υπόβαθρο χάρτη, που ρωτά
 * ακριβώς «ποια πλακίδια πέφτουν μέσα» — οι επιλογές ήταν δύο: αντιγραφή τεσσάρων γραμμών, ή
 * ένα σπίτι. Η αντιγραφή είναι ακριβώς το σχήμα που πιάνει το CHECK 3.28 (N.18), και το
 * αποθετήριο το έχει ήδη πληρώσει: η προβολή κόσμου→χαρτιού ήταν κάποτε αντιγραμμένη σε δύο
 * παραγωγούς και απούσα από τέσσερις (ADR-650 §M10f).
 *
 * ## ⚠️ Λέγεται DISPLAY, όχι WORLD — και το όνομα είναι το μισό της αξίας του
 * Το `screenToWorld` κάνει οθόνη → **σκηνή**, και η σκηνή είναι το χαρτί του κτιρίου. Σε
 * γεωαναφερμένο έργο, χαρτί και κόσμος (ΕΓΣΑ) απέχουν ~4·10⁸ mm. Το ADR-650 §M10f καταγράφει
 * ότι το να λέγεται αυτό το ορθογώνιο «world» ήταν **η αιτία** που ο κάνναβος τύπωνε τοπικές
 * συντεταγμένες με ετικέτα ΕΓΣΑ: το ερώτημα γινόταν σε λάθος σύστημα. Ο μετασχηματισμός προς
 * τον κόσμο γίνεται ρητά, από τον καλούντα, με `unprojectRectToWorld`.
 */

import { CoordinateTransforms as CT } from './CoordinateTransforms';
import type { ViewTransform, Viewport } from '../types/Types';
// ADR-794 — ΕΝΑ όνομα ανά ΧΩΡΟ. Το όνομα ήταν σωστό (χώρος+μονάδα) — αλλά ο χώρος είναι ο ΙΔΙΟΣ με του Bbox.
import type { Bbox } from '../../types/coordinate-space';

/**
 * Το ορατό ορθογώνιο σε **display** mm (τοπικές συντεταγμένες του σχεδίου), από τις δύο
 * αντιδιαμετρικές γωνίες της οθόνης.
 *
 * Δύο γωνίες αρκούν εδώ — σε αντίθεση με τη μετάβαση προς τον κόσμο, όπου χρειάζονται και οι
 * τέσσερις: η οθόνη και το χαρτί συνδέονται με μετασχηματισμό **χωρίς στροφή**, οπότε το
 * ορθογώνιο παραμένει ευθυγραμμισμένο με τους άξονες.
 */
export function visibleDisplayRect(transform: ViewTransform, viewport: Viewport): Bbox {
  const a = CT.screenToWorld({ x: 0, y: 0 }, transform, viewport);
  const b = CT.screenToWorld({ x: viewport.width, y: viewport.height }, transform, viewport);
  return {
    minX: Math.min(a.x, b.x), maxX: Math.max(a.x, b.x),
    minY: Math.min(a.y, b.y), maxY: Math.max(a.y, b.y),
  };
}
