/**
 * 🏢 ADR-735 — SSoT για την **πλευρά κελιού** ενός ομοιόμορφου πλέγματος.
 *
 * ## Η ερώτηση που απαντά, μία φορά
 *
 * «Πόσο μεγάλο πρέπει να είναι το κελί, ώστε το πλέγμα να είναι πλέγμα και όχι λίστα;»
 *
 * Η απάντηση **δεν είναι σταθερά**. Είναι συνάρτηση της **έκτασης** των δεδομένων και του
 * **πλήθους** τους — γιατί ένα σχέδιο σε μέτρα (έκταση ~30) και το ίδιο σχέδιο σε χιλιοστά
 * (έκταση ~30.000) είναι το ίδιο πρόβλημα με χίλιες φορές διαφορετικούς αριθμούς.
 *
 * ## 🔴 Γιατί υπάρχει αυτό το αρχείο (ADR-735 §2 — μετρημένο, όχι θεωρητικό)
 *
 * Το `DEFAULT_CONFIGS.SNAPPING` όριζε **`gridSize: 50` πάγιο** για τα ιδιωτικά ευρετήρια των 9
 * snap engines. Το 50 δεν έχει καμία σχέση με το aperture — και το aperture είναι σταθερό σε
 * **pixels οθόνης**, άρα σε **world units μεγαλώνει γραμμικά με το zoom-out**:
 *
 * ```
 * radius = pixelRadius × worldPerPixel      (SnapContextManager.worldRadiusForType)
 * κελιά  = (2 × radius / cellSize)²          (GridSpatialIndex.getItemCells)
 * ```
 *
 * Στην κλίμακα 1:2352 (worldPerPixel ≈ 622, snapDistance 10px) το `radius` γίνεται ~6.220 world
 * units και η ερώτηση σαρώνει **62.500 κελιά** — για να βρει 15-76 σημεία. Μετρημένο στην
 * παραγωγή 2026-07-30: **16-19ms ανά κλήση ανά engine**, 4 engines = 98% του χρόνου ανίχνευσης.
 *
 * Το κόστος ήταν **Ο(zoom²) με μηδενική εξάρτηση από τα δεδομένα** — ντετερμινιστικό benchmark:
 * 15 → 3.000 σημεία άλλαξε τον χρόνο 5,9 → 6,7ms, ενώ worldPerPixel 1 → 622 τον άλλαξε
 * 0,006 → 7,5ms.
 *
 * ## Η γνώση υπήρχε ήδη στο repo — απλά δεν είχε εφαρμοστεί παντού
 *
 * Ο κώδικας αυτός **μετακόμισε αυτούσιος** από το `snapping/orchestrator/snap-broad-phase.ts`
 * (ADR-728 Φ2), όπου ήταν `private`. Εκεί είχε ήδη γραφτεί το σωστό επιχείρημα — αλλά εφαρμόστηκε
 * μόνο στο **δέκατο** ευρετήριο (της Φ2) και ποτέ πίσω στα **εννέα** ιδιωτικά που έτρωγαν τον
 * χρόνο. N.0.2 (Boy Scout) πάνω σε γνώση που το ίδιο το έργο είχε ήδη κατακτήσει.
 *
 * @see ./GridSpatialIndex.ts — ο καταναλωτής· `getItemCells` είναι το κόστος που ρυθμίζεται εδώ
 * @see ../../snapping/orchestrator/snap-broad-phase.ts — ο αρχικός (και δεύτερος) καταναλωτής
 * @see ./PointHashGrid.ts — η **ίδια** αρχή («cell ≈ query radius»), για ωμές συντεταγμένες
 */

import { clamp } from '../../utils/scalar-math';
import type { SpatialBounds } from './ISpatialIndex';

/**
 * Στόχος πληρότητας κελιού ≈ **1 στοιχείο/κελί** — η κλασική ρύθμιση ομοιόμορφου πλέγματος.
 *
 * Πλευρά πλέγματος = ⌈√N⌉, φραγμένη ώστε ούτε σκηνή 10 στοιχείων να χτίζει 4.096 κελιά ούτε σκηνή
 * 100.000 να χτίζει 316 στήλες κλειδιών. Για N = 2.909 ⇒ πλευρά 54 ⇒ 2.916 κελιά.
 */
export const MIN_GRID_SIDE = 8;
export const MAX_GRID_SIDE = 128;

/**
 * Πλευρά κελιού = μεγαλύτερη διάσταση / ⌈√N⌉ — **κλιμακωτά ανεξάρτητη από τις μονάδες σχεδίου**.
 *
 * **Γιατί όχι πάγια σταθερά** (το προ-ADR-735 `gridSize: 50`): το 50 είναι συντονισμένο για
 * **σημεία σε γνωστή κλίμακα**. Σε σχέδιο σε μέτρα (έκταση ~30) δίνει **ένα** κελί ⇒ το ευρετήριο
 * εκφυλίζεται σε γραμμική σάρωση, δηλαδή **μηδέν κέρδος**· σε σχέδιο σε mm (έκταση ~300.000) δίνει
 * 6.000×6.000 κελιά ⇒ η ερώτηση σαρώνει δεκάδες χιλιάδες **άδεια** κελιά. Το προσαρμοστικό μέγεθος
 * δίνει και στις δύο περιπτώσεις ~1 στοιχείο/κελί, άρα η ερώτηση σαρώνει ~όσα στοιχεία θα
 * επιστρέψει — που είναι ο ορισμός του σωστού κόστους.
 *
 * **Γιατί όχι QuadTree:** το `QuadTreeSpatialIndex.getChildIndex` κατεβάζει item σε παιδί μόνο αν
 * το παιδί το περιέχει **πλήρως** — τα AABB που πατούν σε όριο κόμβου μένουν στον γονέα, και το
 * `queryBoundsRecursive` τα εξετάζει σε κάθε ερώτημα που τέμνει τον γονέα. Σε «σούπα» AABB αυτό
 * φορτώνει τη ρίζα. Το πλέγμα δεν έχει αυτόν τον εκφυλισμό (item = σε κάθε κελί που καλύπτει).
 *
 * @param bounds    η έκταση που θα καλύψει το πλέγμα
 * @param itemCount πόσα στοιχεία θα μπουν μέσα
 * @returns πλευρά κελιού, **πάντα > 0** (ποτέ 0/NaN/Infinity — ένα μη πεπερασμένο cell size κάνει
 *          κάθε συντεταγμένη να χασάρει σε ±Infinity και το ευρετήριο να απαντά σιωπηλά «τίποτα»)
 */
export function resolveGridSize(bounds: SpatialBounds, itemCount: number): number {
  const extent = Math.max(bounds.maxX - bounds.minX, bounds.maxY - bounds.minY);
  const side = clamp(Math.ceil(Math.sqrt(itemCount)), MIN_GRID_SIDE, MAX_GRID_SIDE);
  const size = extent / side;
  // Εκφυλισμένη έκταση (όλα τα στοιχεία σε ΕΝΑ σημείο, ή μη πεπερασμένα bounds): δεν υπάρχει
  // κλίμακα να συντονιστεί. Επιστρέφουμε θετικό μέγεθος ώστε ο κάνναβος να παραμείνει έγκυρος
  // (ένα κελί, γραμμική σάρωση) αντί να δηλητηριαστεί με 0/NaN.
  return Number.isFinite(size) && size > 0 ? size : 1;
}
