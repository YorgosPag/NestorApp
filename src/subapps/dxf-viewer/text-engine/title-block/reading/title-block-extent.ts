/**
 * @fileoverview Το **κατακόρυφο εύρος** ενός κελιού πινακίδας — χωρίς γραμματοσειρά (ADR-762).
 *
 * ## Το πρόβλημα σε μία γραμμή
 *
 * Το `y` ενός MTEXT είναι το σημείο **εισαγωγής**, και ο κωδ. 71 λέει **πού μέσα στο μπλοκ**
 * βρίσκεται αυτό το σημείο. Στο `G753_ergasia F.dxf` 18 κελιά λένε `TL` (το `y` είναι η κορυφή)
 * και **ένα** λέει `ML` (το `y` είναι το **κέντρο**). Σύγκριση σκέτων `y` συγκρίνει κορυφή με
 * κέντρο — και μόλις αλλάξει το πλήθος γραμμών του `ML` κελιού, το «κέντρο» μετακινείται χωρίς
 * να έχει κουνήσει τίποτα ο χρήστης.
 *
 * ## Γιατί ΔΕΝ καλείται το `layoutTextNode`
 *
 * Το `text-engine/layout/text-layout-engine.ts` δίνει ήδη `attachmentOffset {dx,dy}` — ακριβώς
 * αυτή την ποσότητα. Απαιτεί όμως **`font: Font`** (opentype.js), γιατί μετρά *μελάνι*: κάνει
 * αναδίπλωση με πλάτη glyph και αθροίζει `ascent + descent`. Τρεις λόγοι το αποκλείουν εδώ:
 *
 * 1. **Καθαρότητα.** Ο Λ1 είναι καθαρή συνάρτηση, μηδέν I/O — και το φυλάει πύλη.
 * 2. **Ντετερμινισμός.** Με γραμματοσειρές, το ίδιο αρχείο θα ζευγάρωνε **αλλιώς** ανάλογα με
 *    το ποιες φορτώθηκαν. Ένα σφάλμα ανάγνωσης που εξαρτάται από το τι πρόλαβε να κατέβει είναι
 *    το χειρότερο είδος σφάλματος.
 * 3. **Άλλη ερώτηση.** Ο renderer ρωτά «πόσο μελάνι»· εμείς ρωτάμε «πόσο **χώρο δήλωσε** ο
 *    συντάκτης». Οι δύο απαντήσεις διαφέρουν και **πρέπει** να διαφέρουν — δεν είναι διπλότυπο
 *    (N.18), είναι διαφορετικό ερώτημα με διαφορετική μονάδα.
 *
 * ## Και γιατί όχι ο κωδ. 43, που θα τα έλυνε όλα
 *
 * Το DXF **έχει** πεδίο «μετρημένο ύψος μπλοκ» (MTEXT κωδ. 43) και θα ήταν η ιδανική πηγή.
 * 🔴 **Μετρημένο 2026-08-06 στο πραγματικό αρχείο: οι κωδ. 42/43 ΑΠΟΥΣΙΑΖΟΥΝ και από τα 19
 * MTEXT.** Είναι προαιρετικοί/read-only και ο παραγωγός δεν τους έγραψε. Άρα το ύψος **πρέπει**
 * να παραχθεί — και παράγεται από ό,τι το κελί ήδη κουβαλά.
 *
 * ## Το μοντέλο
 *
 * ```
 *   ύψος μπλοκ = Σ(γραμμές) συντελεστής_ύψους × κωδ.40 × MTEXT_LINE_BOX_FACTOR
 * ```
 *
 * Οι γραμμές και οι σωρευτικοί συντελεστές έρχονται από τον **ίδιο** `mtextToSegments` που
 * διαβάζει και τα πρόσωπα — καμία δεύτερη μηχανή.
 *
 * @see ADR-762 — η ρίζα του «εξαφανίστηκε ο ΜΕΛΕΤΗΤΗΣ»
 * @see ADR-745 §5.3 — ο Λ1
 */

import {
  attachmentRowOf,
  DEFAULT_TEXT_JUSTIFICATION,
} from '@/types/dxf-text-justification';
import { mtextToSegments } from './mtext-segments';
import type { TitleBlockSourceCell } from './title-block-reading.types';

/**
 * Ύψος κουτιού γραμμής ÷ ονομαστικό ύψος χαρακτήρα = **5/3**.
 *
 * Είναι ο μονός διάστιχος του AutoCAD (*«single line spacing = 1.66 times the height of the
 * text characters»*) — και **δεν** τον διαλέξαμε από βιβλίο: τον **μετρήσαμε στο ίδιο το
 * αρχείο**. Η ετικέτα `ΜΕΛΕΤΗΤΗΣ` (κωδ. 40 = 1,2845, προσάρτηση `TL`) κάθεται έτσι ώστε το
 * κέντρο της να πέφτει πάνω στο σημείο εισαγωγής του `ML` κελιού των μελετητών:
 *
 * ```
 *   y(ετικέτα) − y(τιμή) = 1,0551      1,0551 / 1,2845 = 0,8213 ≈ 5/6 = (5/3) / 2
 * ```
 *
 * δηλαδή **ακριβώς μισό κουτί γραμμής**, με υπόλοιπο 0,0153 μονάδες σχεδίου — το χέρι του
 * συντάκτη. Ένας συντελεστής 1,0 θα άφηνε υπόλοιπο 0,413, δηλαδή **27 φορές** μεγαλύτερο.
 *
 * ⚠️ **ΜΗΝ τον «στρογγυλέψεις» σε 1,66.** Η ισότητα με το 5/6 είναι ο λόγος που η μέτρηση
 * κλείνει· το 1,66 δίνει 0,83 και χαλάει την απόδειξη χωρίς κανένα κέρδος.
 */
export const MTEXT_LINE_BOX_FACTOR = 5 / 3;

/** Το κατακόρυφο εύρος ενός κελιού σε συντεταγμένες σχεδίου (WCS, `y` προς τα **πάνω**). */
export interface CellVerticalSpan {
  /** Η κορυφή του μπλοκ κειμένου. */
  readonly top: number;
  /** Η βάση του μπλοκ κειμένου. */
  readonly bottom: number;
  /**
   * Το κατακόρυφο **μέσον** του μπλοκ — η ποσότητα που στοίχισε ο συντάκτης.
   *
   * Το μετρήσαμε: η ετικέτα `ΜΕΛΕΤΗΤΗΣ` και το κελί των μελετητών έχουν κέντρα που απέχουν
   * **0,0153** μονάδες σχεδίου, ενώ οι κορυφές τους απέχουν **2,296**. Η πινακίδα είναι
   * κεντραρισμένη μέσα στα κελιά του πλαισίου της, όπως κάθε πινακίδα.
   */
  readonly center: number;
  /** `top − bottom`. Μηδέν όταν το κελί δεν δηλώνει χρησιμοποιήσιμο ύψος. */
  readonly height: number;
}

/**
 * Το δηλωμένο ύψος του μπλοκ κειμένου, σε μονάδες σχεδίου.
 *
 * ⚠️ **Καμία αναδίπλωση.** Ο κωδ. 41 είναι πλάτος αναδίπλωσης, όχι μελανιού, και η αναδίπλωση
 * απαιτεί πλάτη glyph — δηλαδή γραμματοσειρά. Άρα εδώ μετρώνται **οι ρητές** γραμμές (`\P`,
 * `\N`). Η υποεκτίμηση είναι **ασφαλής κατεύθυνση** για τον σκοπό μας: το κριτήριο του ADR-762
 * ρωτά αν το σημείο της ετικέτας πέφτει **μέσα** στο εύρος της τιμής, και ένα εύρος που μόνο
 * μεγαλώνει δεν μπορεί να **χάσει** ένα σημείο που ήδη περιέχει (§4.2).
 */
export function declaredBlockHeight(cell: TitleBlockSourceCell): number {
  const unit = Number.isFinite(cell.height) && cell.height > 0 ? cell.height : 0;
  if (unit === 0) return 0;
  const totalFactor = mtextToSegments(cell.raw, unit).reduce(
    (sum, segment) => sum + (Number.isFinite(segment.heightFactor) ? segment.heightFactor : 0),
    0,
  );
  return totalFactor * unit * MTEXT_LINE_BOX_FACTOR;
}

/**
 * Το κελί ως **διάστημα**, τοποθετημένο σύμφωνα με το σημείο προσάρτησής του.
 *
 * `T` ⇒ το `y` είναι η κορυφή · `M` ⇒ το κέντρο · `B` ⇒ η βάση. Χωρίς δηλωμένη προσάρτηση
 * ισχύει η προεπιλογή του DXF (`TL`), οπότε το εύρος εκφυλίζεται στη σημερινή συμπεριφορά.
 */
export function cellVerticalSpan(cell: TitleBlockSourceCell): CellVerticalSpan {
  const height = declaredBlockHeight(cell);
  const row = attachmentRowOf(cell.attachment ?? DEFAULT_TEXT_JUSTIFICATION);
  const top = row === 'T' ? cell.y : row === 'M' ? cell.y + height / 2 : cell.y + height;
  return { top, bottom: top - height, center: top - height / 2, height };
}

/**
 * Πόσο **έξω** από το εύρος πέφτει ένα `y` — `0` όταν πέφτει μέσα.
 *
 * 🔑 **Ο λόγος ύπαρξης είναι η μονοτονία.** Όταν μεγαλώσει το κείμενο της τιμής, το εύρος της
 * μόνο **επεκτείνεται** — προς τα κάτω για `T`, προς τις δύο πλευρές για `M`, προς τα πάνω για
 * `B`. Άρα ένα σημείο που ήταν μέσα **μένει** μέσα, και ένα σημείο που ήταν έξω δεν
 * απομακρύνεται ποτέ. Αυτό δεν είναι ανοχή που ρυθμίζεται· είναι ιδιότητα που δεν σπάει.
 *
 * ⚠️ **Χρησιμεύει ως κριτήριο ΑΠΟΔΟΧΗΣ, ΠΟΤΕ ως κόστος** (ADR-762 §4.3). Ως κόστος μετρήθηκε
 * καταστροφικό: το κελί `Τ1` έχει ονομαστικό ύψος 2,936, δηλαδή κουτί **4,89** — αρκετά ψηλό
 * ώστε να **περιέχει** την ετικέτα `ΣΧΕΔΙΟ`, που ανήκει αλλού. Με κόστος `0` το `ΣΧΕΔΙΟ`
 * άρπαζε το `Τ1` και **δύο** πεδία κατέρρεαν μαζί. Η περιεκτικότητα λέει «είναι στην ίδια
 * σειρά», όχι «ταιριάζουν καλύτερα».
 */
export function verticalGapToSpan(y: number, span: CellVerticalSpan): number {
  if (y > span.top) return y - span.top;
  if (y < span.bottom) return span.bottom - y;
  return 0;
}
