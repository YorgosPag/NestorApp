/**
 * @fileoverview Ομαδοποίηση κελιών σε **πινακίδες** (ADR-745 §2.3 Παγίδα Δ).
 *
 * Το ίδιο layer μπορεί να φέρει περισσότερα από ένα πλαίσια. Στο πραγματικό
 * `G753_ergasia F.dxf` φέρει **δύο**: 17 κελιά στο `x≈408012–408038` και 2 στο
 * `x≈408069,7`. Χωρίς αυτό το βήμα, η ετικέτα του ενός πλαισίου βρίσκει «πλησιέστερη
 * δεξιά τιμή» **του άλλου** — και το λάθος δεν φαίνεται πουθενά.
 *
 * ## Γιατί το κατώφλι δεν είναι σταθερά
 *
 * Ένα «408060» θα δούλευε σε αυτό το αρχείο και μόνο σε αυτό. Ακόμη και ένα «30 μονάδες»
 * θα έσπαγε στο πρώτο σχέδιο σε χιλιοστά. Το κατώφλι εδώ **παράγεται από την ίδια τη
 * σελίδα**: μετριέται η κατανομή αποστάσεων πλησιέστερου γείτονα και το κατώφλι είναι
 * πολλαπλάσιο της **διαμέσου** της. Είναι η ιδέα του **Docstrum** (O'Gorman 1993), του
 * κλασικού αλγορίθμου ανάλυσης διάταξης σελίδας: η ίδια η σελίδα δηλώνει την κλίμακά της.
 * Ο διάμεσος (όχι ο μέσος όρος) είναι που το κάνει να αντέχει — τα λίγα ζεύγη που
 * γεφυρώνουν πινακίδες είναι ακριβώς οι ακραίες τιμές που θα δηλητηρίαζαν έναν μέσο όρο.
 *
 * **Μετρημένο περιθώριο στο G753** (χωρίς αυτό το σχόλιο ο επόμενος θα μαντεύει):
 * η ένωση της αριστερής πινακίδας χρειάζεται ακμή έως **13,55**· η κοντινότερη απόσταση
 * ανάμεσα στις δύο πινακίδες είναι **36,49**· ο διάμεσος πλησιέστερου γείτονα **4,48**.
 * Άρα κάθε συντελεστής στο **(3,02 – 8,14)** δίνει το σωστό αποτέλεσμα· το **5** κάθεται
 * γεωμετρικά στο κέντρο αυτού του παραθύρου. Το κατώφλι δεν είναι οριακό — είναι
 * βαθμονομημένο σε ΜΕΤΡΗΜΕΝΟ διάκενο σχεδόν 3× και ανεξάρτητο μονάδων και κλίμακας.
 *
 * ⚠️ Το layer φέρει και **7 LINE + 22 LWPOLYLINE** (το πλαίσιο). Θα ήταν άλλο σήμα
 * ομαδοποίησης, αλλά θα έδενε τον Λ1 με τη γεωμετρία και θα αχρήστευε το βήμα σε πινακίδες
 * χωρίς κλειστό πλαίσιο. Παραμένει ανοιχτή βελτίωση, όχι προϋπόθεση.
 *
 * @see ADR-745 §5.3 (Λ1) · ../../../utils/connected-components (ο κοινός union-find)
 */

import { groupIndicesByComponent, type ComponentEdge } from '../../../utils/connected-components';

/** Ό,τι χρειάζεται η ομαδοποίηση: πού κάθεται το κελί και πόσο μεγάλο γράφει. */
export interface PositionedCell {
  readonly x: number;
  readonly y: number;
  /** Ονομαστικό ύψος κειμένου (κωδ. 40) — η ανεξάρτητη εκτίμηση κλίμακας. */
  readonly height: number;
}

/**
 * Πόσες φορές τη διάμεσο απόστασης γείτονα απέχουν δύο κελιά της **ίδιας** πινακίδας.
 * Μετρημένο παράθυρο ασφαλείας στο G753: (3,02 – 8,14).
 */
export const NEIGHBOUR_GAP_FACTOR = 5;

/**
 * Δάπεδο του κατωφλιού, σε ύψη κειμένου.
 *
 * Χρειάζεται όταν η στατιστική γειτόνων **καταρρέει**: δύο κελιά στο ίδιο ακριβώς σημείο
 * δίνουν διάμεσο 0, άρα κατώφλι 0, άρα κάθε κελί δική του πινακίδα. Το ύψος κειμένου είναι
 * δεύτερη, ανεξάρτητη εκτίμηση της κλίμακας του σχεδίου και δεν μηδενίζεται ποτέ.
 * Στο G753 δεν ενεργοποιείται (7,3 έναντι 22,4) — είναι δίχτυ, όχι κύρια διαδρομή.
 */
export const HEIGHT_FLOOR_FACTOR = 8;

/** Η διάμεσος ενός μη κενού πίνακα (κάτω διάμεσος για άρτιο πλήθος — ντετερμινιστικό). */
function median(values: readonly number[]): number {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.floor((sorted.length - 1) / 2)];
}

/** Απόσταση σημείων εισαγωγής. */
function distance(a: PositionedCell, b: PositionedCell): number {
  return Math.hypot(a.x - b.x, a.y - b.y);
}

/** Η απόσταση κάθε κελιού από τον πλησιέστερο γείτονά του. */
function nearestNeighbourDistances(cells: readonly PositionedCell[]): number[] {
  return cells.map((cell, i) => {
    let best = Infinity;
    for (let j = 0; j < cells.length; j++) {
      if (i === j) continue;
      best = Math.min(best, distance(cell, cells[j]));
    }
    return best;
  });
}

/**
 * Το κατώφλι γειτνίασης, παραγμένο από τα ίδια τα κελιά.
 *
 * Εκτίθεται ώστε να μπορεί να **ελεγχθεί ο ίδιος ο βαθμονομητής** — αλλιώς η μόνη ορατή
 * συμπεριφορά θα ήταν το πλήθος ομάδων, και μια χαλασμένη βαθμονόμηση θα περνούσε
 * απαρατήρητη όσο το τελικό πλήθος τύχαινε να βγαίνει σωστό.
 */
export function proximityThreshold(cells: readonly PositionedCell[]): number {
  if (cells.length < 2) return 0;
  const fromNeighbours = NEIGHBOUR_GAP_FACTOR * median(nearestNeighbourDistances(cells));
  const fromHeights = HEIGHT_FLOOR_FACTOR * median(cells.map((c) => c.height));
  return Math.max(fromNeighbours, fromHeights);
}

/** Τα ζεύγη κελιών που απέχουν έως το κατώφλι — οι ακμές του γράφου γειτνίασης. */
function proximityEdges(cells: readonly PositionedCell[], threshold: number): ComponentEdge[] {
  const edges: ComponentEdge[] = [];
  for (let i = 0; i < cells.length; i++) {
    for (let j = i + 1; j < cells.length; j++) {
      if (distance(cells[i], cells[j]) <= threshold) edges.push({ a: i, b: j });
    }
  }
  return edges;
}

/**
 * Χωρίζει τα κελιά ενός layer σε πινακίδες (single-linkage επί του κατωφλιού).
 *
 * Η σειρά είναι ντετερμινιστική: οι ομάδες βγαίνουν με τη σειρά του πρώτου μέλους τους στην
 * είσοδο και μέσα τους διατηρείται η σειρά εισόδου. Κάθε ισχυρισμός πάνω στο αποτέλεσμα
 * είναι έτσι σταθερός, ανεξάρτητα από τη σειρά με την οποία ενώθηκαν οι συνιστώσες.
 *
 * Κόστος: O(n²) στα ζεύγη. Για layer πινακίδας (μετρημένα 19 κελιά) είναι αμελητέο και δεν
 * δικαιολογεί χωρικό ευρετήριο — ένα ακόμη χειρόγραφο πλέγμα θα κόστιζε παραπάνω απ' όσο
 * γλιτώνει (ADR-650 §M10e).
 */
export function groupIntoTitleBlocks<T extends PositionedCell>(cells: readonly T[]): T[][] {
  if (cells.length === 0) return [];
  const threshold = proximityThreshold(cells);
  const groups = groupIndicesByComponent(cells.length, proximityEdges(cells, threshold));
  return groups.map((indices) => indices.map((i) => cells[i]));
}
