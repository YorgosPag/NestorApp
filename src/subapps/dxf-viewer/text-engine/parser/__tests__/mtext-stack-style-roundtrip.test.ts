/**
 * ADR-737 §11-5 — Η ΣΤΟΙΒΑ `\S` ΕΚΠΕΜΠΕΙ ΟΛΟΚΛΗΡΗ ΤΗ ΔΙΑΦΟΡΑ ΣΤΥΛ, ΟΧΙ ΜΟΝΟ ΤΟ `\A`.
 *
 * Ο `serializeParagraph` έκανε `continue` για κάθε στοίβα, παρακάμπτοντας τον `serializeStyleDiff`.
 * Το §11-2 δεν το έλυσε — άνοιξε **δεύτερη** διαδρομή diff, που ήξερε μόνο το `\A`. Ό,τι ο parser
 * αποθηκεύει στο `TextStack.style` (`fontFamily`, `height`, `color`, `verticalAlign`) και δεν είναι
 * το `\A`, χανόταν στο export: η στοίβα κληρονομούσε στο επόμενο άνοιγμα το στυλ του ΠΡΟΗΓΟΥΜΕΝΟΥ
 * run αντί για το δικό της.
 *
 * 🔬 ΓΙΑΤΙ ΤΟ ΤΕΣΤ ΣΤΑΘΕΡΟΥ ΣΗΜΕΙΟΥ ΔΕΝ ΑΡΚΕΙ ΕΔΩ — και είναι σημαντικό:
 * η διαρροή είναι ιδεμπόδης **από το δεύτερο πέρασμα και μετά**. Το `\H0.42;` απλώς μετακινούνταν
 * ΜΕΤΑ τη στοίβα (`Ε\S…;\H0.6;…` αντί `Ε\H0.42;\S…;\H0.6;…`), οπότε το string σταθεροποιούνταν
 * αμέσως — με το ύψος της στοίβας ήδη χαμένο. Άρα το όργανο δεν είναι η σύγκριση **strings** αλλά
 * η σύγκριση του **AST** πριν/μετά: `stackStylesOf(pass1)` vs `stackStylesOf(pass2)`.
 * Το σταθερό σημείο μένει ως δεύτερος έλεγχος (πιάνει τον θόρυβο, όχι τη διαρροή).
 *
 * 🎯 Η ΑΠΩΛΕΙΑ ΕΙΝΑΙ ΟΡΑΤΗ, ΟΧΙ ΘΕΩΡΗΤΙΚΗ: ο ζωγράφος διαβάζει `child.style.height` και
 * `child.style.color` για τις στοίβες (`bim/text/text-layout-source.ts` → `pieceBaseOf`). Στην
 * πραγματική ετικέτα του `47_ergasia.dxf` η στοίβα ζει σε `\H0.7x;` — ένας κύκλος export→import
 * τη μεγάλωνε στο **143%** του σωστού ύψους.
 *
 * ⚠️ Τα δείγματα αποφεύγουν ΣΚΟΠΙΜΑ επιστροφή σε `ByLayer`/`ByBlock` μετά από `\C`: ο serializer
 * γράφει `\C256;`/`\C0;` αλλά ο tokenizer τα ξαναδιαβάζει ως `ACI 256`/`ACI 0` (→ ADR-737 §11-6,
 * ανοιχτό). Είναι ΑΛΛΗ ασυμμετρία, της ίδιας οικογένειας· δεν την κρύβουμε, την απομονώνουμε
 * ώστε αυτό το αρχείο να μετρά ΜΟΝΟ το §11-5.
 */

import {
  AREA_LABEL,
  parse,
  roundTrip,
  serialize,
  stackOf,
  stackStylesOf,
} from './mtext-roundtrip-harness';

describe('ADR-737 §11-5 — ο κωδικός στυλ γράφεται ΠΡΙΝ από τη στοίβα', () => {
  it('ύψος: το `\\H` προηγείται του `\\S`, δεν το ακολουθεί', () => {
    // Πριν τη διόρθωση: `Α\S1^2;\H5;Β` — η στοίβα ζωγραφιζόταν στο ύψος του «Α».
    expect(roundTrip('Α\\H5;\\S1^2;Β')).toMatch(/\\H5;\\S1\^2;/);
  });

  it('χρώμα: το `\\C` προηγείται του `\\S`', () => {
    expect(roundTrip('Α\\C1;\\S1^2;Β')).toMatch(/\\C1;\\S1\^2;/);
  });

  it('γραμματοσειρά: το `\\f` προηγείται του `\\S`', () => {
    const out = roundTrip('\\fArial|b0|i0|c0|p34;Α\\fTimes|b0|i0|c0|p34;\\S1^2;Β');
    expect(out).toMatch(/\\fTimes\|b0\|i0\|c0\|p34;\\S1\^2;/);
  });

  it('το bold/italic ΚΛΗΡΟΝΟΜΕΙΤΑΙ — η στοίβα δεν κουβαλά τα πεδία, άρα δεν τα σβήνει', () => {
    // Η στοίβα κρατά μόνο 4 πεδία. Αν το `\f` της τα έγραφε από την προεπιλογή αντί από την
    // ΚΑΤΑΣΤΑΣΗ, ένα `b1` που ίσχυε θα γινόταν σιωπηλά `b0` σε κάθε αλλαγή γραμματοσειράς.
    const out = roundTrip('\\fArial|b1|i0|c0|p34;Α\\fTimes|b1|i0|c0|p34;\\S1^2;Β');
    expect(out).toMatch(/\\fTimes\|b1\|/);
    expect(out).not.toMatch(/\\fTimes\|b0\|/);
  });

  it('ΜΗΔΕΝ ΘΟΡΥΒΟΣ: στοίβα σύμφωνη με την κατάσταση δεν γεννά ΚΑΝΕΝΑΝ κωδικό', () => {
    // Αρνητικό pin. Μια «λύση» που εκπέμπει το πλήρες στυλ της στοίβας από την ΠΡΟΕΠΙΛΟΓΗ αντί
    // από την κατάσταση περνά όλα τα παραπάνω και πέφτει εδώ: το στυλ κάτω κρατά υπογράμμιση και
    // bold — πεδία που η στοίβα ΔΕΝ κουβαλά, άρα κληρονομεί. Η μόνη σωστή απάντηση είναι να
    // κολλάει το `\S` πάνω στο «Α», χωρίς τίποτα ανάμεσα.
    const out = roundTrip('\\fArial|b1|i0|c0|p34;\\L\\H5;\\C1;Α\\S1^2;Β');
    expect(out).toMatch(/Α\\S1\^2;Β$/);
  });
});

describe('ADR-737 §11-5 — ΔΥΟ ΠΕΡΑΣΜΑΤΑ: το στυλ της στοίβας επιβιώνει', () => {
  it.each([
    ['η πραγματική ετικέτα εμβαδού', AREA_LABEL],
    ['ύψος που ανοίγει ΠΡΙΝ τη στοίβα', 'Α\\H5;\\S1^2;Β'],
    ['σχετικό ύψος (`x`) όπως το γράφει το AutoCAD', 'Α\\H0.5x;\\S1^2;\\H2x;Β'],
    ['χρώμα ACI', 'Α\\C1;\\S1^2;Β'],
    ['χρώμα true-color', 'Α\\c255;\\S1^2;Β'],
    ['γραμματοσειρά', '\\fArial|b0|i0|c0|p34;Α\\fTimes|b0|i0|c0|p34;\\S1^2;Β'],
    ['ύψος + χρώμα + στοίχιση μαζί', '\\A1;Α\\H0.7x;\\C7;\\S^ τίτλου;\\H1.4286x;Β'],
    ['δύο στοίβες με ΔΙΑΦΟΡΕΤΙΚΟ ύψος η καθεμία', 'Α\\H3;\\S1^2;\\H7;\\S3^4;Β'],
  ])('%s', (_label, raw) => {
    const first = parse(raw);
    const second = parse(serialize(first));
    expect(stackStylesOf(second)).toEqual(stackStylesOf(first));
  });

  it('ΣΤΑΘΕΡΟ ΣΗΜΕΙΟ: το τρίτο πέρασμα δίνει το ίδιο string με το δεύτερο', () => {
    const once = roundTrip(AREA_LABEL);
    expect(roundTrip(once)).toBe(once);
  });

  it('η πραγματική ετικέτα: η στοίβα κρατά το 0,7× ύψος και ΜΕΤΑ τον κύκλο export→import', () => {
    // 0,6 × 0,7 = 0,42. Πριν τη διόρθωση το δεύτερο πέρασμα έδινε 0,6 — δηλαδή +43%.
    expect(stackOf(parse(AREA_LABEL)).style.height).toBeCloseTo(0.42, 10);
    expect(stackOf(parse(roundTrip(AREA_LABEL))).style.height).toBeCloseTo(0.42, 10);
  });
});
