/**
 * **Casing αντίθεσης** — η διάσωση όταν το μελάνι *δεν μπορεί* να κρατήσει την υπόσχεσή του
 * (ADR-771 Φ.3).
 *
 * ## Τι λύνει
 * Η {@link InkVerdict} έκανε την αποτυχία **ρητή**· εδώ γίνεται **αναστρέψιμη**. Όταν η
 * επιφάνεια είναι μεσοτονική, **καμία** τιμή χρώματος δεν φτάνει το κατώφλι — το φράγμα δεν
 * είναι σχεδιαστικό, είναι αριθμητικό: το χειρότερο δυνατό γκρι δίνει **4,58:1** στο καλύτερό
 * του άκρο. Η μόνη διέξοδος είναι να **μη ρωτήσεις την επιφάνεια**: βάζεις δική σου, τοπικά.
 *
 * Μια φαρδύτερη πένα στο **αντίθετο άκρο**, κάτω από την κύρια, δίνει στη γραμμή φόντο που
 * ελέγχουμε ⇒ η τοπική αντίθεση γίνεται **21:1** ανεξάρτητα από το θέμα καμβά.
 *
 * ## 🔑 Τι κάνουν οι μεγάλοι — και γιατί εδώ πάμε **παραπέρα**
 * Η σύμβαση είναι της **χαρτογραφίας**, όχι του CAD: `text-halo-color` (Mapbox GL),
 * halo symbol (ArcGIS Pro), buffer (QGIS) — γιατί εκεί ακριβώς το φόντο είναι **αυθαίρετο**
 * (δορυφορική εικόνα). Το CAD δεν το έχει επειδή υποθέτει **ελεγχόμενο** φόντο — υπόθεση που
 * τα 9 θέματα καμβά + το `custom` χρώμα **σπάνε**.
 *
 * ⚠️ Αλλά το πρότυπο των μεγάλων **δεν απαντά στη δική μας ερώτηση**: και στα τρία, το χρώμα
 * του halo το διαλέγει **άνθρωπος, στατικά**, και η ίδια η τεκμηρίωση του Mapbox παραδέχεται
 * ότι σπάει *«when you can't be certain of what's in the background»*. Εμείς **ξέρουμε** την
 * επιφάνεια ακριβώς (δική μας είναι) **και** ξέρουμε το έλλειμμα, άρα το casing εδώ είναι
 * **υπολογισμένο** — αυστηρά καλύτερο από χειροκίνητη επιλογή.
 *
 * ## 🔴 Γιατί ΟΧΙ επαναχρήση του `bim-hover-halo.ts` / `paintPolygonHoverHalo`
 * Το έργο έχει ήδη «halo» — και είναι **άλλη ερώτηση**: εκείνο είναι **affordance** («αυτό
 * είναι κάτω από τον δείκτη / επιλεγμένο»), εφήμερο, χρωματικό, και ζωγραφίζεται **γύρω** από
 * το σχήμα ως λάμψη. Αυτό εδώ είναι **αναγνωσιμότητα**, μόνιμο όσο ζει το θέμα, αχρωματικό
 * εξ ορισμού, και ζωγραφίζεται **κάτω** από τη γραμμή. Κοινό όνομα, αντίθετη σημασιολογία:
 * μια κοινή υλοποίηση θα ανάγκαζε το ένα ερώτημα να δανειστεί τις παραμέτρους του άλλου.
 *
 * @see ../../config/adaptive-entity-color.ts — `InkVerdict`, `maxContrastInk`
 * @see docs/centralized-systems/reference/adrs/ADR-771-table-surface-doctrine.md §5
 */

import { maxContrastInk, type InkVerdict } from '../../config/adaptive-entity-color';

/**
 * Πόσο φαρδύτερο από την κύρια πένα είναι το casing, σε **pixel οθόνης**.
 *
 * `2` = ένα pixel σε κάθε πλευρά στην κλίμακα 1× — η ελάχιστη τιμή που παράγει ορατή λωρίδα
 * φόντου. Σκόπιμα **σταθερό σε px** και όχι σε mm: δεν είναι πάχος γραμμής του σχεδίου (ISO
 * 128), είναι **βοήθημα οθόνης**· ένα casing που μεγαλώνει με το zoom θα γινόταν δεύτερο,
 * παχύ περίγραμμα και θα άλλαζε το σχέδιο. Το Mapbox περιορίζει αντίστοιχα το `text-halo-width`
 * στο ¼ του μεγέθους γραμματοσειράς — ίδια αρχή: το halo βοηθά, δεν κυριαρχεί.
 */
export const CONTRAST_CASING_EXTRA_WIDTH_PX = 2;

/**
 * Το χρώμα του casing για μια ετυμηγορία, ή `null` όταν **δεν χρειάζεται διάσωση**.
 *
 * `null` σε **δύο** καταστάσεις, και οι δύο σωστές:
 *  - `sufficient` — η υπόσχεση κρατήθηκε· casing θα ήταν κόσμημα, δηλαδή αλλαγή σχεδίου.
 *  - `unmeasurable` — **δεν ξέρουμε**· να ζωγραφίσεις διάσωση εκεί που δεν μέτρησες είναι
 *    ψευδώς θετικό, και μάλιστα ορατό στην οθόνη του χρήστη.
 *
 * Το χρώμα προκύπτει από το **ίδιο** SSoT που διάλεξε το μελάνι ({@link maxContrastInk}, ACI 7):
 * το αντίθετο άκρο **του μελανιού**, όχι της επιφάνειας. Δεν είναι λεπτομέρεια — σε `shortfall`
 * το μελάνι *είναι* ήδη ένα από τα δύο άκρα, άρα η ερώτηση «τι ξεχωρίζει από αυτό;» έχει
 * ακριβώς μία απάντηση και τη δίνει η υπάρχουσα συνάρτηση. Μηδέν νέα μαθηματικά.
 */
export function contrastCasingInk(verdict: InkVerdict): string | null {
  return verdict.kind === 'shortfall' ? maxContrastInk(verdict.ink) : null;
}

/** Το ελάχιστο συμβόλαιο καμβά που χρειάζεται το casing (`CanvasRenderingContext2D` το πληροί). */
export interface ContrastCasingContext {
  save(): void;
  restore(): void;
  strokeStyle: CanvasRenderingContext2D['strokeStyle'];
  lineWidth: number;
}

/**
 * Εκτελεί το πέρασμα σχεδίασης **μία ή δύο φορές**: casing από κάτω (μόνο σε `shortfall`),
 * μετά το κανονικό μελάνι.
 *
 * @param verdict `null` ⇒ ο καλών **δεν** ορίζει προσαρμοστικό μελάνι εδώ (π.χ. κρατά το χρώμα
 *   φάσης μιας οπλισμένης επιλογής) ⇒ ένα σκέτο πέρασμα, **χωρίς** άγγιγμα του `strokeStyle`.
 *
 * ## ⚠️ Δύο πράγματα που ΔΕΝ είναι προφανή
 * 1. **Το `save()/restore()` ΔΕΝ επαναφέρει τη διαδρομή** — το ίδιο το `WallRenderer`
 *    τεκμηριώνει το γεγονός (ADR-396). Αυτό είναι ακριβώς ο λόγος που δουλεύει: ο καλών
 *    μπορεί να έχει ήδη χαράξει τη διαδρομή και το `strokePass` να είναι σκέτο `stroke()`,
 *    και τα **δύο** περάσματα βρίσκουν την **ίδια** διαδρομή.
 * 2. **Το `setLineDash` επιβιώνει** του casing περάσματος (είναι κατάσταση, σώζεται/επαναφέρεται)
 *    ⇒ ένας διάστικτος άξονας παίρνει **διάστικτο** casing. Ένα συμπαγές casing κάτω από
 *    διάστικτη γραμμή θα γέμιζε τα κενά και θα κατέστρεφε το ίδιο το μοτίβο — δηλαδή θα
 *    «διόρθωνε» την αντίθεση καταστρέφοντας την πληροφορία.
 *
 * **Μηδέν κόστος όταν δεν χρειάζεται**: σε `sufficient`/`unmeasurable` γίνεται ακριβώς μία
 * ανάθεση `strokeStyle` και ένα πέρασμα — δηλαδή ό,τι ακριβώς γινόταν πριν το ADR-771 Φ.3.
 */
export function strokeWithContrastCasing(
  ctx: ContrastCasingContext,
  verdict: InkVerdict | null,
  lineWidth: number,
  strokePass: () => void,
): void {
  const casing = verdict === null ? null : contrastCasingInk(verdict);
  if (casing !== null) {
    ctx.save();
    ctx.strokeStyle = casing;
    ctx.lineWidth = lineWidth + CONTRAST_CASING_EXTRA_WIDTH_PX;
    strokePass();
    ctx.restore();
  }
  if (verdict !== null) ctx.strokeStyle = verdict.ink;
  strokePass();
}
