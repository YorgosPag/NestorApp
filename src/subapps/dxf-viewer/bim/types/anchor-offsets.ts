/**
 * anchor-offsets — SSoT για το **9-θέσιο anchor** ενός ορθογώνιου ίχνους και τη
 * μετατόπισή του σε κλάσματα του πλαισίου οριοθέτησης.
 *
 * ```
 *   nw  n  ne
 *   w   c  e
 *   sw  s  se
 * ```
 *
 * **Γιατί υπάρχει (N.18 / CHECK 3.28):** ο πίνακας ζούσε **δύο φορές**, με το **ίδιο
 * όνομα** (`ANCHOR_OFFSETS`), σε `column-types.ts` και `foundation-types.ts` — και τα
 * ίδια τα σχόλια το **παραδέχονταν** («*mirror κολώνας*», «*mirror κολώνας
 * ANCHOR_OFFSETS*») χωρίς να το διορθώνουν. Δύο αντίγραφα με δεκάδες καταναλωτές το
 * καθένα: η πρώτη διόρθωση σε **ένα** από τα δύο θα τα έκανε να **αποκλίνουν σιωπηλά**,
 * και η βλάβη θα ήταν «το πέδιλο κάθεται λίγο αλλού από την κολόνα του» — δηλαδή
 * **γεωμετρική**, όχι σφάλμα μεταγλώττισης.
 *
 * ⚠️ Οι δύο τύποι ήταν **δομικά ταυτόσημοι** (ίδιες 9 τιμές, ίδια σειρά). Τα ονόματα
 * `ColumnAnchor` / `FoundationAnchor` **διατηρούνται ως ψευδώνυμα** στα αρχεία τους: ο
 * τομέας τα διαβάζει έτσι, και μια μαζική μετονομασία σε δεκάδες σημεία δεν θα πρόσθετε
 * τίποτα — η **τιμή** έπρεπε να γίνει μία, όχι το λεξιλόγιο.
 *
 * ⚠️ **ΜΗΝ** προσθέσεις εδώ σειρά κύκλου (Tab): οι δύο οντότητες κάνουν **διαφορετικό**
 * κύκλο (`ANCHOR_CYCLE_ORDER` vs `FOUNDATION_ANCHOR_CYCLE_ORDER`) και αυτό είναι
 * πραγματική διαφορά συμπεριφοράς — μένει στα δικά τους αρχεία.
 */

/** 9-θέσιο anchor ορθογώνιου ίχνους — ποιο σημείο εδράζεται στο `position`. */
export type BoxAnchor =
  | 'center'
  | 'n' | 's' | 'e' | 'w'
  | 'nw' | 'ne' | 'sw' | 'se';

/**
 * Anchor → κλασματική μετατόπιση μέσα στο πλαίσιο οριοθέτησης, **ΠΡΙΝ** την περιστροφή.
 * `dx`/`dy` ∈ {−0.5, 0, +0.5}. Ο αγωγός γεωμετρίας εφαρμόζει
 * `position − (dx × πλάτος, dy × βάθος)` ώστε το σημείο anchor να συμπέσει με το
 * `position` του κλικ.
 */
export const ANCHOR_OFFSETS: Readonly<Record<BoxAnchor, { dx: number; dy: number }>> = {
  'center': { dx:  0,    dy:  0    },
  'n':      { dx:  0,    dy:  0.5  },
  's':      { dx:  0,    dy: -0.5  },
  'e':      { dx:  0.5,  dy:  0    },
  'w':      { dx: -0.5,  dy:  0    },
  'nw':     { dx: -0.5,  dy:  0.5  },
  'ne':     { dx:  0.5,  dy:  0.5  },
  'sw':     { dx: -0.5,  dy: -0.5  },
  'se':     { dx:  0.5,  dy: -0.5  },
};
