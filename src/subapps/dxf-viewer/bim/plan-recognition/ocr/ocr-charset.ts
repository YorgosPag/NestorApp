/** Ένας χαρακτήρας από γραφή που γράφει μια κάτοψη. */
const PLAN_SCRIPT = /^[\p{Script=Latin}\p{Script=Greek}\p{Script=Common}\p{Script=Inherited}]+$/u;
/** Τα μπλοκ της Ανατολικής Ασίας που το Unicode κατατάσσει στα κοινά (`Common`): στίξη/σύμβολα CJK, πλήρες πλάτος. */
const EAST_ASIAN_BLOCK = /[⺀-⿿　-㏿豈-﫿︰-﹏＀-￯]/u;

/** Ο χαρακτήρας (κλάση του λεξικού) μπορεί να είναι κείμενο κάτοψης; */
export function isPlanTextChar(value: string): boolean {
  return PLAN_SCRIPT.test(value) && !EAST_ASIAN_BLOCK.test(value);
}

const masks = new WeakMap<readonly string[], Uint8Array>();

/**
 * Μάσκα των κλάσεων CTC (`recognitionClasses`): `1` = επιτρεπτή. Η κλάση `0` (blank) είναι **πάντα** επιτρεπτή, άρα κάθε
 * βήμα έχει νικητή. Υπολογίζεται μία φορά ανά λεξικό (ο πίνακας κλάσεων είναι σταθερός για όλη τη ζωή του αναγνώστη).
 */
export function planTextClassMask(classes: readonly string[]): Uint8Array {
  const cached = masks.get(classes);
  if (cached !== undefined) return cached;
  const mask = new Uint8Array(classes.length);
  for (let i = 0; i < classes.length; i++) mask[i] = i === 0 || isPlanTextChar(classes[i]) ? 1 : 0;
  masks.set(classes, mask);
  return mask;
}
