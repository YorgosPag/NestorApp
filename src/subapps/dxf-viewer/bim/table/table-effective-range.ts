/**
 * 🔑 **Η ΜΙΑ ΑΠΑΝΤΗΣΗ ΣΤΟ «ΠΟΙΑ ΠΕΡΙΟΧΗ ΕΝΝΟΕΙ Ο ΧΡΗΣΤΗΣ ΤΩΡΑ;»** — η επιλογή· χωρίς
 * επιλογή, το **ενεργό κελί**. Καθαρή γνώση μοντέλου: μηδέν DOM, μηδέν store, μηδέν React.
 *
 * ## 🔴 Γιατί υπάρχει ως δικό του module — **ΤΕΣΣΕΡΙΣ** ρωτούν, και ξεκίνησαν **ΔΥΟ**
 * Η ερώτηση γεννήθηκε στη λαβή συμπλήρωσης (ADR-754 §14) και ζούσε μέσα στο
 * `table-fill-handle.ts` ως `tableFillSourceBounds`. Εκεί ήταν σωστή όσο οι καταναλωτές της
 * ήταν τρεις και **όλοι** αφορούσαν τη λαβή: ο ζωγράφος της, ο φρουρός του πατήματός της, ο
 * δείκτης της.
 *
 * Ο **τέταρτος** δεν αφορά λαβή καθόλου: είναι η **μετακίνηση περιοχής** (ADR-739 §36) — το
 * ορθογώνιο του οποίου το περίγραμμα πιάνεται και σέρνεται. Μια συνάρτηση με «fill» στο όνομα,
 * καταναλωμένη από τη μετακίνηση, θα έλεγε στον επόμενο αναγνώστη ότι η μετακίνηση έχει σχέση
 * με συμπλήρωση — δηλαδή θα ήταν **όνομα που ψεύδεται**, το ίδιο είδος απόκλισης που όλη αυτή
 * η οικογένεια modules υπάρχει για να σβήσει. **Εξαγωγή, όχι δίδυμο** (N.18): ίδιο σχήμα με το
 * `table-range-merge-snap`, που βγήκε από το `table-cell-range` με το ίδιο ακριβώς επιχείρημα.
 *
 * ## 🔴 Η ΙΣΤΟΡΙΑ ΠΟΥ ΤΗΝ ΓΕΝΝΗΣΕ — ΤΡΕΙΣ ΡΩΤΟΥΣΑΝ, ΔΥΟ ΑΠΑΝΤΟΥΣΑΝ, ΚΑΙ ΔΙΑΦΟΡΕΤΙΚΑ
 * Ο ζωγράφος έγραφε `selectionBounds ?? ενεργό κελί`, ο φρουρός του πατήματος
 * `if (selection) return resolveTableSelectionBounds(...)`. Με **μπαγιάτικη** επιλογή (undo,
 * διαγραμμένη γραμμή) ο ένας ζωγράφιζε λαβή στο ενεργό κελί και ο άλλος **αρνιόταν να την
 * πιάσει**: «λαβή που φαίνεται αλλά δεν πιάνεται» — η αστοχία που το ADR-754 §13.5 απαγορεύει
 * ονομαστικά. Νικά η εκδοχή του ζωγράφου: μια επιλογή που **δεν λύνεται** είναι καμία επιλογή,
 * ενώ το ενεργό κελί υπάρχει πάντα.
 *
 * ⚠️ Δύο αντίγραφα των έξι tokens «`selection ?? ενεργό κελί`» **δεν** πιάνονται από το jscpd
 * (κάτω από τα 50 tokens του `.jscpdrc.json`) — ακριβώς το σχήμα που περιγράφει το ADR-754 §15
 * για το `cellPairIndices`. Ένα gate δεν θα τα έβρισκε ποτέ· μόνο ένα όνομα τα κρατά ενωμένα.
 *
 * @module subapps/dxf-viewer/bim/table/table-effective-range
 * @see bim/table/table-cell-range.ts — ο ΕΝΑΣ ορισμός του «ορθογώνιο κελιών»
 * @see bim/table/table-range-merge-snap.ts — ο ΜΗΧΑΝΙΣΜΟΣ του κουμπώματος
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §36
 * @see docs/centralized-systems/reference/adrs/ADR-754-table-point-mode.md §14
 */

import { rawTableCellRangeBounds, type TableCellRangeBounds, type TableCellRef } from './table-cell-range';
import { snapToWholeMerges } from './table-range-merge-snap';
import type { TableModel } from '../../types/table';

/**
 * 🔑 **Η ΤΡΕΧΟΥΣΑ ΕΜΒΕΛΕΙΑ ΤΟΥ ΧΡΗΣΤΗ**: τα όρια της επιλογής· χωρίς επιλογή —ή με
 * **μπαγιάτικη** επιλογή— το ενεργό κελί. `null` μόνο όταν ούτε το ίδιο το ενεργό κελί
 * υπάρχει πια στο μοντέλο.
 *
 * Τα όρια της επιλογής ζητούνται **ήδη λυμένα** και δεν λύνονται εδώ: ο ζωγράφος τα έχει
 * υπολογίσει για το περίγραμμα του **ίδιου καρέ**, και ένας δεύτερος υπολογισμός θα ήταν
 * δεύτερη απάντηση στο «τι μάρκαρε ο χρήστης» — δηλαδή χειριστήριο που κάθεται αλλού από το
 * περίγραμμα που υποτίθεται ότι συνοδεύει.
 *
 * ## 🔴 ΤΟ ΕΝΕΡΓΟ ΚΕΛΙ **ΚΟΥΜΠΩΝΕΙ** ΣΕ ΟΛΟΚΛΗΡΗ ΤΗ ΣΥΓΧΩΝΕΥΣΗ — ΕΔΩ ΗΤΑΝ ΤΟ ΕΛΑΤΤΩΜΑ
 * Εδώ έγραφε σκέτο `rawTableCellRangeBounds(model, active, active)`, δηλαδή **1×1 σε δείκτες**,
 * χωρίς κούμπωμα. Μετρήθηκε (2026-08-06, ADR-739 §36.9) πάνω στον πίνακα της σκηνής, που έχει
 * **συγχωνευμένη γραμμή τίτλου**: με ενεργό κελί την άγκυρα μιας συγχώνευσης `1×5`,
 *
 * - η **ζωγραφιά** του ενεργού κελιού (`activeCellRectOf` → `TableCellLayout.rect`, που
 *   «*καλύπτει ολόκληρο το εύρος της συγχώνευσης όταν το κελί είναι άγκυρα*») έδινε **100×8 mm**·
 * - αυτή εδώ έδινε **20×8 mm** — δηλαδή το **ένα πέμπτο**.
 *
 * Συνέπεια, ορατή στην οθόνη **σήμερα**: η λαβή συμπλήρωσης ζωγραφιζόταν και πιανόταν στο
 * **1/5 του πλάτους**, δηλαδή **μέσα** στο κελί, μακριά από τη γωνία που της αντιστοιχεί. Και,
 * με τη μετακίνηση του §36 από πάνω, το «περίγραμμα που πιάνεται» θα έπεφτε πάνω σε **γραμμή
 * που δεν ζωγραφίζεται πουθενά** — τρίτη παραβίαση του «*ο δείκτης δεν ψεύδεται*» (§31).
 *
 * 🔑 Το κούμπωμα **δεν** είναι νέα γνώση συγχωνεύσεων: είναι το ίδιο `snapToWholeMerges` που
 * εφαρμόζει ήδη το `resolveTableSelectionBounds` στον **άλλο** κλάδο αυτής της ίδιας συνάρτησης
 * (είδος `'range'`, ADR-739 §27.15). Χωρίς αυτό, οι δύο κλάδοι απαντούσαν με **διαφορετικό
 * κανόνα** στην ίδια ερώτηση: «επιλογή που αγγίζει συγχώνευση» μεγάλωνε, «ενεργό κελί **μέσα**
 * σε συγχώνευση» όχι.
 *
 * ⚠️ **ΔΕΝ αφορά τις αναφορές τύπων.** Το `=SUM(A1:B2)` διαβάζει **ακριβώς** τα κελιά που
 * ονομάζει και **δεν** κουμπώνει (δες την κεφαλίδα του {@link rawTableCellRangeBounds}) — γι'
 * αυτό εκείνος ο καλών εξακολουθεί να ρωτά την ακατέργαστη συνάρτηση απευθείας. Εδώ η ερώτηση
 * είναι άλλη: «τι **μάρκαρε ο χρήστης**», και ο χρήστης μαρκάρει ό,τι **βλέπει**.
 */
export function tableEffectiveRangeBounds(
  model: TableModel,
  active: TableCellRef,
  selectionBounds: TableCellRangeBounds | null,
): TableCellRangeBounds | null {
  if (selectionBounds) return selectionBounds;
  const cell = rawTableCellRangeBounds(model, active, active);
  return cell ? snapToWholeMerges(model, cell) : null;
}
