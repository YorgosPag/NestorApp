/**
 * ADR-750 Φάσεις 3+5 — **από πού έρχεται το μολύβι μιας εντολής περιγράμματος** (Α20 + Α23).
 *
 * Η Α15 κλείδωσε ότι το μολύβι είναι **παράμετρος** των πράξεων, ποτέ global — και άφησε ρητά
 * ανοιχτό **ποιος** το κρατά. Η απάντηση της Φ3 (Α20) ήταν: **κανείς δεν το κρατά**. Παράγεται
 * από το ενεργό στυλ του πίνακα, τη στιγμή της εντολής, από καθαρή συνάρτηση.
 *
 * ## 🔑 Φ5 (Α23) — η Α20 δεν καταργείται· γίνεται το «Αυτόματο»
 * Ο χρήστης απέκτησε χειριστήρια χρώματος / στυλ / πάχους / διπλής. Η προφανής ανάγνωση —
 * «άρα κάποιος πρέπει τώρα να κρατά το μολύβι» — είναι **λάθος διχοτόμηση**: αυτό που κρατιέται
 * είναι η **επιλογή** του χρήστη, όχι το μολύβι. Κάθε πεδίο της επιλογής είναι ανεξάρτητα
 * προαιρετικό, και το απόν σημαίνει «ρώτα το στυλ» — δηλαδή η Α20 εκτελείται αυτούσια για
 * όποιο πεδίο δεν άγγιξε ο χρήστης.
 *
 * Το ίδιο το Excel το ονομάζει έτσι στο δικό του χειριστήριο («Αυτόματο»), και είναι το
 * `ByLayer` του AutoCAD ξανά: **κληρονομιά ανά πεδίο**, όχι «όλα ή τίποτα». Ένα μολύβι που
 * κρατούσε *ολόκληρο* το προηγούμενο θα σήμαινε ότι μια επιλογή χρώματος παγώνει και το πάχος
 * — και ο πίνακας θα έπαυε σιωπηλά να ακολουθεί το στυλ του σχεδίου.
 *
 * ## 🔴 Γιατί ΟΧΙ «μαύρο 0.25», που είναι η απάντηση του Excel
 * Το Excel δεν έχει στυλ σχεδίου: κάθε εντολή περιγράμματος γράφει μαύρο λεπτό, πάντα. Σε φύλλο
 * υπολογισμού αυτό είναι αβλαβές. Σε **σχέδιο** δεν είναι: ένας πίνακας με αχνό γκρι πλέγμα
 * 0,15 mm θα αποκτούσε ξαφνικά μαύρες γραμμές που δεν ταιριάζουν με **καμία** άλλη γραμμή του
 * φύλλου. Ο χρήστης ζήτησε **παρουσία** γραμμής («βάλε κάτω περίγραμμα») και θα έπαιρνε αλλαγή
 * **εμφάνισης** που δεν ζήτησε.
 *
 * Δηλαδή είναι το `ByLayer` του AutoCAD και το «By Category» του Revit, εφαρμοσμένο στο μολύβι
 * αντί για την ορατότητα: η νέα γραμμή μοιάζει με τις γραμμές που **ήδη** έχει ο πίνακας.
 *
 * ## 🔑 Γιατί η ΕΣΩΤΕΡΙΚΗ γραμμή και όχι το πλαίσιο
 * Η βάση πρέπει να είναι η **λεπτή** πένα του στυλ, για δύο ανεξάρτητους λόγους:
 *
 * 1. Το `'thick'` του μητρώου είναι **σχετικό** — η επόμενη πένα ISO (λόγος 1:2 του ISO 128-20,
 *    {@link nearestIsoLineweight}). Με βάση το ήδη παχύ πλαίσιο, το «Παχιά εξωτερικά» θα έβγαινε
 *    **διπλά** παχύ, δηλαδή η κλίμακα θα έσπαγε στο πρώτο κιόλας πάτημα.
 * 2. Μετρημένη επιβεβαίωση στο `standard` preset: `insideH` = 0,25 mm και `STANDARD_FRAME_MM`
 *    = 0,5 mm. Το `thick` της εσωτερικής δίνει **ακριβώς** 0,5 — δηλαδή «Παχιά εξωτερικά
 *    περιγράμματα» αναπαράγει το πλαίσιο που το ίδιο το στυλ ορίζει, χωρίς να το ξέρει.
 *
 * ## Η κλάση `data` και όχι η γραμμή του χτυπήματος
 * Οι κλάσεις `title`/`header` είναι **εξαιρέσεις** (μεγαλύτερο κείμενο, γέμισμα, συχνά άλλο
 * πλαίσιο)· η `data` είναι το σώμα του πίνακα, δηλαδή «η κανονική γραμμή πλέγματος αυτού του
 * πίνακα». Μια επιλογή που πιάνει τίτλο **και** δεδομένα δεν έχει «την» κλάση της — και μια
 * εντολή που άλλαζε μολύβι ανάλογα με το πού ξεκινά η επιλογή θα ήταν κρυφός κανόνας.
 *
 * @module subapps/dxf-viewer/bim/table/table-border-pencil
 * @see bim/table/table-range-border-ops.ts — ο καταναλωτής (η παράμετρος `pencil`)
 * @see docs/centralized-systems/reference/adrs/ADR-750-table-cell-borders.md §5 (Α20) · §18
 */

import type { TableBorderSpec } from '../../types/table-edges';
import { nearestIsoLineweight } from '../../config/lineweight-iso-catalog';
import type { TableBorders, TableStyle } from './table-style';

/**
 * Η σειρά αναζήτησης μέσα στην κλάση, όταν η εσωτερική οριζόντια δεν έχει πένα.
 *
 * Δεν είναι προτίμηση αισθητικής — είναι **ντετερμινισμός**: ένα στυλ μπορεί να ορίζει μόνο
 * πλαίσιο (`detailSheet`: και οι έξι αόρατες· άλλα: μόνο περίμετρος). Χωρίς σταθερή σειρά, δύο
 * ισοδύναμες πλευρές θα έδιναν διαφορετικό μολύβι ανάλογα με τη σειρά απαρίθμησης αντικειμένου.
 * Οι εσωτερικές πρώτες, μετά η περίμετρος — από τη λεπτότερη πρόθεση προς την παχύτερη.
 */
const PENCIL_SEARCH_ORDER: readonly (keyof TableBorders)[] = [
  'insideH',
  'insideV',
  'top',
  'bottom',
  'left',
  'right',
];

/**
 * Η πένα που χρησιμοποιείται όταν το στυλ **δεν δηλώνει καμία** ορατή γραμμή.
 *
 * ⚠️ Δεν είναι αυθαίρετος αριθμός και δεν επιτρέπεται να γίνει: είναι η **λεπτή** πένα του
 * ζεύγους 0,25 : 0,50 του ISO 128-20 για A3/A4 — το ίδιο ζεύγος που ήδη επιλέγει ανεξάρτητα το
 * `standard` preset για πλέγμα και πλαίσιο. Η {@link assertIsoPen} το επαληθεύει στον κατάλογο
 * αντί να το εμπιστεύεται: μια τιμή εκτός κλίμακας θα έσπαγε σιωπηλά την εξαγωγή DXF (group 370).
 */
const FALLBACK_PEN_MM = 0.25;

/**
 * ADR-750 Φ5 (Α23) — **τι διάλεξε ο χρήστης**, ανά πεδίο.
 *
 * Καθαρά δεδομένα: μηδέν React, μηδέν store, μηδέν όνομα καταλόγου. Το `dashMm` φτάνει εδώ
 * **ήδη επιλυμένο** από τον καταναλωτή (`state/table-border-pencil-store.ts`), ώστε αυτό το
 * module να μένει ντετερμινιστικό — ένα `linetypeName` θα το ανάγκαζε να ρωτήσει το
 * `LinetypeRegistry`, δηλαδή να αποκτήσει κατάσταση εκτελέσιμη μόνο με στήσιμο.
 *
 * **Απόν πεδίο = «Αυτόματο»**, ρητά και ανά πεδίο. Δες την κεφαλίδα για το γιατί.
 */
export interface TableBorderPencilChoice {
  readonly colorHex?: string;
  /** Ελεύθερα χιλιοστά· κουμπώνουν στην κλίμακα ISO πριν χρησιμοποιηθούν. */
  readonly widthMm?: number;
  /** Μοτίβο σε **σύμβαση DXF** (θετικό = παύλα, αρνητικό = κενό)· κενό ⇒ συνεχής. */
  readonly dashMm?: readonly number[];
  readonly double?: boolean;
}

/**
 * Πόσο απέχουν οι δύο παράλληλες μιας διπλής γραμμής, **ως πολλαπλάσιο της πένας**.
 *
 * ⚠️ Δεν είναι προτίμηση αισθητικής, και δεν επιτρέπεται να γίνει απόλυτο χιλιοστό: με σταθερή
 * απόσταση, μια διπλή με πένα 0,13 mm και μια με 0,70 mm θα ήταν **η ίδια** — δηλαδή στη μία
 * οι γραμμές θα κολλούσαν και στην άλλη θα φαίνονταν δύο ξένες γραμμές. Το AutoCAD εκθέτει την
 * απόσταση ρητά («Spacing») ακριβώς επειδή είναι μέγεθος **σχεδίου**, όχι σταθερά ζωγράφου.
 *
 * Το `3` δίνει κενό `2 × πένα` ανάμεσα στις δύο — αρκετό ώστε το ζεύγος να διαβάζεται ως **ένα**
 * στοιχείο και όχι ως μουτζούρα — και συνολικό αποτύπωμα `4 × πένα`. Αυτό το τελευταίο είναι το
 * ουσιώδες: το ISO 128-20 ορίζει λεπτή:παχιά = **1:2**, άρα η «παχιά» πιάνει `2 × πένα`. Η
 * διπλή πιάνει `4 ×`, δηλαδή κάθεται **μία βαθμίδα πάνω από την παχιά** — που είναι ακριβώς ο
 * ρόλος της στη λογιστική σύμβαση την οποία αντιγράφουν οι εντολές έμφασης του Excel: παχιά
 * κάτω γραμμή = μερικό σύνολο, **διπλή** κάτω γραμμή = γενικό σύνολο.
 */
const DOUBLE_GAP_PEN_RATIO = 3;

/**
 * Η απόσταση κέντρου-προς-κέντρο μιας διπλής γραμμής για δεδομένη πένα, σε sheet-mm.
 *
 * Δημόσια επειδή τη χρειάζονται **δύο** ανεξάρτητοι καλούντες: το μολύβι του χρήστη (όταν
 * τσεκάρει «Διπλή γραμμή») και ο τροποποιητής `'double'` των δύο εντολών του μητρώου
 * (`table-range-border-ops.ts`) — που πρέπει να δίνει διπλή **ανεξάρτητα** από το τι έχει
 * τσεκάρει ο χρήστης, γιατί η εντολή *σημαίνει* διπλή. Δύο σταθερές θα ήταν δύο απαντήσεις.
 */
export function tableBorderDoubleGapMm(widthMm: number): number {
  return widthMm * DOUBLE_GAP_PEN_RATIO;
}

/**
 * Το τρέχον μολύβι για μια εντολή περιγράμματος: **η επιλογή του χρήστη πάνω στο στυλ**.
 *
 * Πάντα `visible: true`: το αόρατο μολύβι είναι η **εντολή** «Χωρίς περίγραμμα»
 * (`HIDDEN_TABLE_EDGE`, Α14), όχι η βάση των υπολοίπων. Ένα στυλ με αόρατο πλέγμα θα έκανε
 * αλλιώς το «Όλα τα περιγράμματα» να μην ζωγραφίζει τίποτα — δηλαδή σιωπηλό no-op σε εντολή που
 * ο χρήστης πάτησε ρητά.
 *
 * Τα προαιρετικά πεδία μπαίνουν με **υπό συνθήκη spread** και ποτέ ως ρητό `undefined`: το
 * σχήμα του αντικειμένου ταξιδεύει στο `sameBorderSpec`, στο diff του αρχείου και στα
 * χαρακτηρισμένα στιγμιότυπα — ένα `dashMm: undefined` θα άλλαζε και τα τρία για μηδενική
 * οπτική διαφορά (η ίδια αρχή με το `clipped` του `TableTextRun`).
 */
export function resolveTableBorderPencil(
  style: TableStyle,
  choice?: TableBorderPencilChoice,
): TableBorderSpec {
  const auto = resolveAutomaticPencil(style);
  if (!choice) return auto;

  const widthMm = choice.widthMm === undefined
    ? auto.widthMm
    : nearestIsoLineweight(choice.widthMm) ?? auto.widthMm;
  const dashMm = choice.dashMm !== undefined && choice.dashMm.length > 0
    ? choice.dashMm
    : auto.dashMm;

  return {
    visible: true,
    colorHex: choice.colorHex ?? auto.colorHex,
    widthMm,
    ...(dashMm && dashMm.length > 0 ? { dashMm } : {}),
    ...(choice.double ? { doubleGapMm: tableBorderDoubleGapMm(widthMm) } : {}),
  };
}

/**
 * **Η Α20 αυτούσια** — το μολύβι που ισχύει όταν ο χρήστης δεν έχει πει τίποτα.
 *
 * Ήταν το σώμα της {@link resolveTableBorderPencil} μέχρι τη Φ5 και δεν άλλαξε ούτε γραμμή:
 * ό,τι διαβάζεται πιο πάνω για το `ByLayer` / «By Category» περιγράφει **αυτή** τη συνάρτηση.
 */
function resolveAutomaticPencil(style: TableStyle): TableBorderSpec {
  const dataClass = style.rowClasses.data;

  for (const side of PENCIL_SEARCH_ORDER) {
    const candidate = dataClass.borders[side];
    if (!candidate.visible) continue;
    const pen = nearestIsoLineweight(candidate.widthMm);
    if (pen === undefined) continue;
    return { ...candidate, visible: true, widthMm: pen };
  }

  // Στυλ χωρίς καμία ορατή γραμμή (π.χ. `detailSheet`, ADR-622). Το μελάνι του **κειμένου** του
  // είναι η μόνη έντιμη πηγή χρώματος: είναι ό,τι ήδη βλέπει ο χρήστης ως «το χρώμα αυτού του
  // πίνακα». Ένα σταθερό `#000000` εδώ θα ήταν εφεύρεση σε στυλ που δηλώνει ρητά `#222222`.
  return {
    visible: true,
    colorHex: dataClass.textColorHex,
    widthMm: assertIsoPen(FALLBACK_PEN_MM),
  };
}

/**
 * Επιστρέφει την τιμή **αφού** την κουμπώσει στον κατάλογο — ο μόνος τρόπος να μην υπάρχει
 * δεύτερη κλίμακα πένας δίπλα στην υπάρχουσα SSoT (`config/lineweight-iso-catalog.ts`).
 *
 * Το `?? mm` δεν είναι δίχτυ που πιάνει σφάλμα: το `nearestIsoLineweight` επιστρέφει `undefined`
 * **μόνο** για μη πεπερασμένο ή μη θετικό πλάτος, και η {@link FALLBACK_PEN_MM} είναι σταθερά
 * θετική. Είναι η δήλωση ότι η σταθερά περνά από τον κατάλογο, όχι δίπλα του.
 */
function assertIsoPen(mm: number): number {
  return nearestIsoLineweight(mm) ?? mm;
}
