/**
 * 🔴 ADR-753 Φ3 — **τι ακριβώς ζωγραφίζεται για ένα κελί, και πού.** Ο ΕΝΑΣ τόπος όπου ένα
 * `TableTextRun` γίνεται λίστα από κλήσεις σχεδίασης.
 *
 * ## Γιατί υπάρχει: οι δύο ζωγράφοι δεν επιτρέπεται να απαντήσουν χωριστά
 *
 * Τη Φ3 τη χρειάζονται **δύο** σημεία κώδικα — ο καμβάς (`stamp-table-text.ts`) και η γέφυρα
 * primitives (`table-layout-to-primitives.ts`, από την οποία κρέμονται PDF, DXF, σκηνή και
 * ΤΕΚ). Και τα δύο πρέπει να απαντήσουν στην ίδια τριάδα ερωτήσεων:
 *
 * ```
 *   ποια κομμάτια;  →  σε ποιο mm το καθένα;  →  με ποια τυπογραφία;
 * ```
 *
 * Δύο σώματα που απαντούν την ίδια τριάδα είναι structural clone ανεξάρτητα ονομάτων (N.18 /
 * CHECK 3.28) — και, χειρότερα, δύο σημεία που μπορούν κάποτε να διαφωνήσουν για το πού
 * κάθεται ένα έντονο τμήμα, δηλαδή **οθόνη ≠ χαρτί**, ακριβώς η κατηγορία απόκλισης που
 * ολόκληρο το ADR-739 είναι χτισμένο για να μην μπορεί να συμβεί.
 *
 * ## 🔴 Η απόφαση της Φ3: το χρώμα ΔΕΝ ορίζει όριο τμηματοποίησης
 *
 * Ο σύνδεσμος που διασχίζει όριο στυλ ζωγραφίζεται με **αποκοπή μέσα στο τμήμα** — όχι ως
 * δικό του `fillText` στην τομή. Δεν είναι προτίμηση· είναι η ιεραρχία τμηματοποίησης που
 * ακολουθεί κάθε επαγγελματική στοίβα κειμένου:
 *
 * ```
 *   παράγραφος → ΣΤΥΛ → BiDi → itemization γραμματοσειράς → script → shaping
 * ```
 *
 * Το **στυλ** ορίζει όριο (και το shaping χάνεται πάνω του, αναπόφευκτα — ADR-753 §11). Το
 * **χρώμα** δεν ορίζει: ο Firefox ρητά **δεν** τμηματοποιεί στις αλλαγές χρώματος και βάφει
 * κομμάτια ligature με τεχνικές γραφικών, δηλαδή με αποκοπή. Ένα δεύτερο `fillText` στην τομή
 * θα έσπαγε το ζεύγος kerning του `Τηλ: |2310788493` **μέσα σε ομοιογενές τμήμα** — δηλαδή θα
 * ήταν παλινδρόμηση του ADR-751, όχι πρόοδος.
 *
 * Άρα ο σημερινός μηχανισμός **ποτέ δεν ήταν «αποκοπή πάνω στο string»**: ήταν **«αποκοπή
 * πάνω στη μονάδα shaping»**, και τυχαίνει σήμερα η μονάδα να είναι ολόκληρο το run. Η Φ3
 * γενικεύει τη μονάδα από `run` σε `span`. Με ένα κομμάτι, ο κώδικας είναι κυριολεκτικά ο
 * σημερινός.
 *
 * ## 🔒 Η αναλλοίωτη: χωρίς `spans` παράγεται **ένα** κομμάτι
 *
 * Και αυτό το κομμάτι είναι το ίδιο το run — ίδιο κείμενο, ίδια στοίχιση, μετατόπιση μηδέν.
 * Κάθε πίνακας που υπάρχει σήμερα στον δίσκο περνά από αυτόν τον κλάδο, οπότε καμβάς και
 * χαρτί κάνουν **τον ίδιο ακριβώς αριθμό κλήσεων με τα ίδια ακριβώς ορίσματα** όπως πριν τη
 * Φ3. Δεν είναι υπόσχεση — είναι εκφυλισμός του γενικού τύπου.
 *
 * @module subapps/dxf-viewer/bim/table/table-text-pieces
 * @see bim/table/table-cell-styled-spans.ts — πού γεννιούνται τα ομοιογενή τμήματα (Φ2)
 * @see bim/table/table-cell-link-spans.ts — το **άλλο** επίπεδο τμημάτων (χρώμα, μετρικά ουδέτερο)
 * @see docs/centralized-systems/reference/adrs/ADR-753-table-cell-rich-text.md §18
 */

import type { TextAlign } from '../structural/detail-sheet/detail-sheet-types';
import type { TableTextLinkSpan, TableTextRun } from './table-layout-types';
import { tableAnchorOffsetMm } from './table-text-decoration';
import { wholeRunLink } from './table-cell-link-spans';

/**
 * **Μία κλήση σχεδίασης**: ομοιογενής τυπογραφία, τοποθετημένη σχετικά με την άγκυρα του run.
 *
 * Είναι σκόπιμα το ίδιο λεξιλόγιο με το `TableTextStyleSpan` και το `TableTextLinkSpan`
 * (`text` + `offsetMm` + `advanceMm` + τυπογραφία): τρίτο λεξιλόγιο για το «πού κάθεται ένα
 * κομμάτι γραμμής» θα ήταν structural clone ανεξάρτητα ονομάτων.
 */
export interface TableTextPiece {
  /** Το κείμενο αυτής της κλήσης — υποσυμβολοσειρά του **ορατού** κειμένου του run. */
  readonly text: string;
  /**
   * 🔴 Από ποια μεριά του {@link offsetMm} απλώνονται τα γράμματα.
   *
   * `'left'` για κάθε κομμάτι που ήρθε από τμήμα (η θέση του **είναι** η αριστερή του ακμή),
   * αλλά η στοίχιση **του run** για το μονό κομμάτι.
   *
   * ⚠️ Η ασυμμετρία δεν είναι ευκολία — την **επιβάλλει** η αναλλοίωτη της Φ3. Για να
   * τοποθετηθεί το μονό κομμάτι αριστερά-αγκυρωμένο θα χρειαζόταν το συνολικό πλάτος του
   * κειμένου, που μετριέται σήμερα **μόνο** για υπογραμμισμένα κελιά (`TableTextRun.advanceMm`)
   * — άρα θα απαιτούσε **νέα μέτρηση στον ζωγράφο**. Η Φ3 δεν μετρά: η διάταξη έκλεισε στη Φ2
   * και ένας δεύτερος μετρητής στον ζωγράφο είναι ακριβώς η ασυμφωνία που η Φ.Ε πλήρωσε με το
   * καρφωτό Arial.
   */
  readonly align: TextAlign;
  /** Η οριζόντια θέση σε sheet-mm, **σχετικά με την άγκυρα** του run (αρνητική σε κέντρο/δεξιά). */
  readonly offsetMm: number;
  /**
   * Το μετρημένο πλάτος του κομματιού σε sheet-mm — **απόν όταν κανείς δεν το μέτρησε**.
   *
   * Πάντα παρόν σε κομμάτι από τμήμα (η Φ2 το μέτρησε ούτως ή άλλως)· στο μονό κομμάτι μόνο
   * όταν το run υπογραμμίζεται, γιατί εκεί και **μόνο** εκεί το ζήτησε κάποιος (ADR-739 Φ.Ε).
   */
  readonly advanceMm?: number;
  /**
   * 🔴 `true` όταν το κομμάτι είναι **ΟΛΟ** το ορατό κείμενο.
   *
   * Απαντά στη μία ερώτηση που ο ζωγράφος δεν μπορεί να συμπεράνει από τα υπόλοιπα πεδία:
   * **χρειάζεται η λωρίδα ενός συνδέσμου περιορισμό;** Όχι, όταν το κομμάτι είναι το σύνολο —
   * κάθε σύνδεσμος βρίσκεται εξ ορισμού μέσα του, και ο σημερινός δρόμος μένει byte-ίδιος.
   *
   * ⚠️ **Δεν συμπεραίνεται από το `advanceMm`.** Ένα υπογραμμισμένο κελί χωρίς τμήματα έχει
   * και τα δύο· ένα μη υπογραμμισμένο έχει μόνο το ένα. Αν ο περιορισμός κρεμόταν από την
   * παρουσία της μέτρησης, τα δύο θα ζωγραφίζονταν με **διαφορετικό** μηχανισμό για λόγο
   * άσχετο με τη ζωγραφική — σιωπηλή ασυμμετρία, ακριβώς το σχήμα που το §13 πλήρωσε.
   */
  readonly whole: boolean;
  /** Ύψος κεφαλαίου γράμματος σε sheet-mm. */
  readonly heightMm: number;
  /** 🔴 Εγγυημένα πραγματικό `#rrggbb` (ADR-739 §38 — το σεντινέλι πέθανε στο `placeCells`). */
  readonly colorHex: string;
  readonly bold: boolean;
  readonly italic: boolean;
  readonly underline: boolean;
  /** Απούσα ⇒ η προεπιλογή του μετρητή — ένα `undefined`, όχι δύο defaults. */
  readonly fontFamily?: string;
}

/** Μια οριζόντια λωρίδα σε sheet-mm, σχετικά με την άγκυρα του run. */
export interface TableTextStripMm {
  readonly offsetMm: number;
  readonly advanceMm: number;
}

/**
 * Το run σπασμένο στις κλήσεις σχεδίασης του, με τη σειρά που πρέπει να εκτελεστούν.
 *
 * **Ένα** κομμάτι όταν το κελί δεν έχει μορφοποίηση ανά χαρακτήρα — δηλαδή σε κάθε πίνακα
 * που υπάρχει σήμερα (δες την αναλλοίωτη στην κεφαλίδα).
 */
export function tableTextPieces(run: TableTextRun): readonly TableTextPiece[] {
  const spans = run.spans;
  if (spans === undefined || spans.length === 0) return [wholePiece(run)];

  // Η στοίχιση διπλώνεται **εδώ, μία φορά**, ακριβώς όπως ο `paintLayoutLines` του MTEXT την
  // εφαρμόζει μία φορά στο x της γραμμής και μετά αφήνει τα spans αριστερά-αγκυρωμένα. Το
  // `ctx.textAlign` ανά τμήμα θα στοίχιζε το καθένα χωριστά και θα τα έριχνε το ένα πάνω στο
  // άλλο.
  //
  // 🔴 Το συνολικό πλάτος διαβάζεται από το **τελευταίο** τμήμα και δεν ξανααθροίζεται: το
  // `offsetMm` **είναι** ήδη το τρέχον άθροισμα, και μια δεύτερη πρόσθεση των ίδιων αριθμών σε
  // άλλη σειρά μπορεί να δώσει άλλο τελευταίο bit — δηλαδή δύο απαντήσεις στο «πόσο πλατύ».
  const last = spans[spans.length - 1];
  const textStartMm = tableAnchorOffsetMm(run.hAlign, last.offsetMm + last.advanceMm);

  return spans.map((span) => ({
    text: span.text,
    align: 'left' as const,
    offsetMm: textStartMm + span.offsetMm,
    advanceMm: span.advanceMm,
    whole: false,
    heightMm: span.heightMm,
    colorHex: span.colorHex,
    bold: span.bold,
    italic: span.italic,
    underline: span.underline,
    ...(span.fontFamily !== undefined && { fontFamily: span.fontFamily }),
  }));
}

/**
 * 🔴 Το μελάνι με το οποίο ξεκινά ένα κομμάτι — **μπλε όταν ο σύνδεσμος το καλύπτει ολόκληρο**.
 *
 * Έτσι η συνηθέστερη περίπτωση με διαφορά — μια στήλη «E-mail», όπου ολόκληρο το κελί είναι η
 * διεύθυνση — δεν πληρώνει κανένα δεύτερο πέρασμα: το `fillStyle` απλώς ξεκινά μπλε και η
 * ζωγραφική είναι **μία** κλήση, ταυτόσημη με πριν το ADR-751.
 *
 * ⚠️ Το κριτήριο μένει **ισότητα κειμένου** (`wholeRunLink`) και δεν γενικεύεται σε σύγκριση
 * mm ανά κομμάτι. Ο λόγος δηλώνεται αντί να κρυφτεί: μια σύγκριση mm θα εισήγαγε **δεύτερο**
 * κριτήριο για το ίδιο ερώτημα, με ανοχή κινητής υποδιαστολής να συντηρείται — ενώ το κέρδος
 * θα ήταν να γλιτώσει ένα `clip()` σε κελί που έχει **ταυτόχρονα** μορφοποίηση ανά χαρακτήρα
 * **και** διεύθυνση. Ένα `clip()` του οποίου το ορθογώνιο ισούται με τη λωρίδα είναι οπτικά
 * ταυτόσημο· ένα δεύτερο κριτήριο δεν είναι ποτέ οπτικά ταυτόσημο με το πρώτο.
 */
export function tablePieceInkHex(
  run: TableTextRun,
  piece: TableTextPiece,
  linkColorHex: string,
): string {
  return piece.whole && wholeRunLink(run) !== null ? linkColorHex : piece.colorHex;
}

/**
 * Οι λωρίδες που πρέπει να βαφτούν **μπλε μέσα σε αυτό το κομμάτι** — η τομή των δύο επιπέδων.
 *
 * ## Γιατί η τομή γίνεται σε **mm** και όχι σε δείκτες
 * Το ADR-753 §16.6 έγραφε ότι το `TableTextStyleSpan` κουβαλά `start`/`end` «ώστε η τομή με το
 * `[start,end)` του link να μη χρειάζεται δεύτερη αναζήτηση θέσης». **Το `TableTextLinkSpan`
 * δεν κουβαλά δείκτες** — μόνο `offsetMm`/`advanceMm` — άρα η τομή σε χώρο δεικτών δεν είναι
 * καν εκφράσιμη. Και δεν χρειάζεται: αυτό που ζητά η αποκοπή είναι **λωρίδα**, δηλαδή ήδη mm.
 *
 * 🔒 Και είναι **ακριβής**, χωρίς ανοχή: πάνω σε όριο τμήματος το `styledPrefixWidthMm`
 * επιστρέφει το `span.offsetMm` **αυτούσιο** (ο κλάδος `index <= span.start`, που υπάρχει
 * ακριβώς για να μη ζητηθεί μέτρηση κενής συμβολοσειράς). Άρα οι δύο αριθμοί που συγκρίνονται
 * στο όριο είναι το **ίδιο** float, όχι δύο αθροίσματα που έτυχε να συμπέσουν.
 *
 * Επιστρέφει κενό όταν το κελί δεν έχει καμία διεύθυνση — δηλαδή στη συντριπτική πλειονότητα.
 */
export function tablePieceLinkStrips(
  run: TableTextRun,
  piece: TableTextPiece,
): readonly TableTextStripMm[] {
  const links = run.links;
  if (!links?.length) return [];

  const out: TableTextStripMm[] = [];
  for (const link of links) {
    const strip = clampStrip(link, piece);
    if (strip !== null) out.push(strip);
  }
  return out;
}

