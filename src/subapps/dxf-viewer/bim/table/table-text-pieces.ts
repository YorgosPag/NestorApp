/**
 * Το μονό κομμάτι ενός κελιού χωρίς μορφοποίηση ανά χαρακτήρα: **το ίδιο το run**.
 *
 * Το `advanceMm` περνά μόνο από το υπογραμμισμένο σκέλος της ένωσης `TableTextRun` — εκεί ο
 * μεταγλωττιστής το εγγυάται, και εκεί μόνο υπάρχει.
 */
function wholePiece(run: TableTextRun): TableTextPiece {
  return {
    text: run.text,
    align: run.hAlign,
    offsetMm: 0,
    ...(run.underline && { advanceMm: run.advanceMm }),
    whole: true,
    heightMm: run.heightMm,
    colorHex: run.colorHex,
    bold: run.bold,
    italic: run.italic,
    underline: run.underline,
    ...(run.fontFamily !== undefined && { fontFamily: run.fontFamily }),
  };
}

/**
 * Η λωρίδα ενός συνδέσμου περιορισμένη μέσα στο κομμάτι, ή `null` όταν δεν το αγγίζει.
 *
 * Το μονό κομμάτι **είναι** ολόκληρο το κείμενο, οπότε κάθε λωρίδα βρίσκεται ήδη μέσα του και
 * επιστρέφεται αυτούσια — η γραμμή που κρατά τον σημερινό δρόμο byte-ίδιο.
 */
function clampStrip(link: TableTextLinkSpan, piece: TableTextPiece): TableTextStripMm | null {
  if (piece.whole) return { offsetMm: link.offsetMm, advanceMm: link.advanceMm };

  // Το `advanceMm` είναι πάντα παρόν σε κομμάτι από τμήμα (βλ. τη σημείωση του πεδίου)· το
  // `?? 0` δεν είναι δίχτυ αλλά η τιμή που κάνει την τομή κενή αν κάποτε πάψει να ισχύει.
  const startMm = Math.max(link.offsetMm, piece.offsetMm);
  const endMm = Math.min(link.offsetMm + link.advanceMm, piece.offsetMm + (piece.advanceMm ?? 0));
  return endMm > startMm ? { offsetMm: startMm, advanceMm: endMm - startMm } : null;
}
