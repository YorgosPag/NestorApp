/**
 * 🔴 ADR-828 **Φ4α** — **ΤΟ ΚΟΥΜΠΙ «ΕΠΙΛΟΓΕΣ ΑΥΤΟΜΑΤΗΣ ΣΥΜΠΛΗΡΩΣΗΣ»**: πού κάθεται, πότε
 * πιάνεται, και **πότε είναι ακόμη αληθινό**. Καθαρή γεωμετρία — μηδέν DOM, μηδέν React.
 *
 * Στο Excel, **μετά** από αυτόματη συμπλήρωση εμφανίζεται ένα μικρό κουμπί κάτω από τη
 * γεμισμένη περιοχή. Το πάτημά του ανοίγει **το ίδιο** μενού που δίνει ήδη το δεξί σύρσιμο
 * (Φ3), ώστε ο άνθρωπος να **αλλάξει γνώμη χωρίς να ξανακάνει τη σύρση**.
 *
 * ## 🔴 Η ΣΥΓΚΡΟΥΣΗ ΤΗΣ ΓΩΝΙΑΣ — ΤΟ ΜΟΝΟ ΠΡΑΓΜΑ ΠΟΥ ΜΠΟΡΕΙ ΝΑ ΣΠΑΣΕΙ ΤΗ ΣΥΜΠΛΗΡΩΣΗ
 * Μετά το γέμισμα, μαρκαρισμένη μένει **ολόκληρη** η περιοχή (πηγή + γέμισμα, Excel parity —
 * δες `selectFilled`). Άρα η **λαβή** συμπλήρωσης κάθεται κεντραρισμένη στην **ίδια** κάτω
 * δεξιά κορυφή που διεκδικεί κι αυτό το κουμπί: τα δύο χειριστήρια είναι γείτονες εξ ορισμού.
 *
 * Η εξωτερική εμβέλεια της λαβής είναι `TABLE_FILL_HANDLE_PX / 2 +
 * TABLE_FILL_HANDLE_OUTWARD_APERTURE_PX` = **7 px** κάτω από την κορυφή (τεκμηριωμένο στο
 * `table-fill-handle.ts`, όπου η ασυμμετρία «μηδέν προς τα μέσα, πλήρης οπή προς τα έξω»
 * γεννήθηκε από μετρημένο ελάττωμα στην οθόνη). Αν αυτό το κουμπί ακουμπήσει έστω ένα από
 * εκείνα τα pixel, **κλέβει τα πατήματα της λαβής** — και η συμπλήρωση, που είναι η ίδια η
 * πράξη που γέννησε το κουμπί, σταματά να πιάνεται.
 *
 * 🔑 Γι' αυτό ο κανόνας είναι ο **ίδιος του Figma** που ήδη κωδικοποιεί ο γείτονας: *το
 * χειριστήριο που ήρθε δεύτερο δεν κλέβει ποτέ pixel από το πρώτο — μεγαλώνει μόνο προς το
 * κενό*. Το {@link TABLE_FILL_BADGE_GAP_PX} είναι **αυστηρά μεγαλύτερο** από τα 7 px, και η
 * ανισότητα είναι κλειδωμένη με test — όπως ακριβώς κλειδώνεται το `7 ≤ 9` της λαβής.
 *
 * ## Γιατί το μέγεθος είναι σε **px οθόνης**
 * Ίδιο επιχείρημα με τη λαβή, τις ζώνες του δείκτη και το ⊕ της εισαγωγής (ADR-739 §40):
 * είναι στοιχείο **διεπαφής**, όχι γεωμετρία σχεδίου. Σε sheet-mm θα γινόταν αόρατο σε
 * zoom-out και τεράστιο σε zoom-in.
 *
 * @module subapps/dxf-viewer/bim/table/table-fill-badge
 * @see bim/table/table-fill-handle.ts — ο γείτονας που διεκδικεί την ίδια γωνία
 * @see state/table-fill-badge-store.ts — ο κύκλος ζωής (σφραγίδα έκδοσης + φρουρός δρομέα)
 * @see rendering/entities/table/stamp-table-fill-badge.ts — ο ένας ζωγράφος
 * @see docs/centralized-systems/reference/adrs/ADR-828-table-autofill-series.md §8
 */

import { tableRangeRectMm, type TableCellRangeBounds } from './table-cell-range';
import {
  TABLE_FILL_HANDLE_OUTWARD_APERTURE_PX,
  TABLE_FILL_HANDLE_PX,
} from './table-fill-handle';
import type { TableLayout, TableRectMm } from './table-layout-types';
import type { TableFramePoint, TableEntity } from '../../types/table-entity';
import type { TableCellCursorState } from '../../state/table-cell-cursor-store';
import type { TableFillBadgeState } from '../../state/table-fill-badge-store';

/**
 * Η **πλευρά** του κουμπιού σε px οθόνης — 16, όσο και το smart tag του Excel.
 *
 * ## Γιατί ΔΕΝ υπάρχει οπή, σε καμία κατεύθυνση
 * Η λαβή από πάνω έχει οπή επειδή ζωγραφίζεται **6 px**: εκεί η ζωγραφιά είναι τόσο μικρή που
 * χωρίς οπή δεν πιάνεται (τεκμηριωμένο «*fill handle too hard to grab*» της Microsoft). Εδώ η
 * ζωγραφιά είναι **16 px**, δηλαδή ήδη στόχος — και η μόνη κατεύθυνση προς την οποία θα είχε
 * νόημα να μεγαλώσει (**πάνω**, προς τη γωνία) είναι ακριβώς εκείνη που ανήκει στη λαβή.
 *
 * ⚠️ Δηλαδή «ό,τι βλέπεις είναι το κουμπί» — η συμπεριφορά που έχουν ούτως ή άλλως
 * Handsontable και ag-Grid για κάθε χειριστήριο κελιού, εφαρμοσμένη εδώ επειδή το κόστος της
 * εναλλακτικής είναι μετρήσιμο και κακό.
 */
export const TABLE_FILL_BADGE_PX = 16;

/**
 * 🔴 **ΤΟ ΚΕΝΟ ΠΟΥ ΚΡΑΤΑ ΤΗ ΣΥΜΠΛΗΡΩΣΗ ΖΩΝΤΑΝΗ.** Πόσο **κάτω** από την κάτω δεξιά κορυφή
 * της γεμισμένης περιοχής ξεκινά το κουμπί, σε px οθόνης.
 *
 * Οφείλει να είναι **γνησίως μεγαλύτερο** από την εξωτερική εμβέλεια της λαβής (7 px), όχι
 * ίσο: στο `v` ακριβώς 7 px η {@link isOnTableFillHandle} απαντά ακόμη `true` (το όριό της
 * είναι κλειστό), και επειδή ο έλεγχος του κουμπιού τρέχει **πριν** από εκείνον της λαβής
 * (πιο ειδική περίπτωση), μια ισότητα θα έδινε στο κουμπί μια ολόκληρη γραμμή pixel που
 * ανήκει στη λαβή. Ένα pixel φτάνει: το ίδιο ADR-754 §13.8 τεκμηριώνει ότι ο χρήστης «*can't
 * be off by one pixel*».
 *
 * Το `8` αφήνει **1 px** νεκρή ζώνη ανάμεσα στα δύο. Δεν είναι σπατάλη: είναι η ρητή δήλωση
 * ότι κανένα από τα δύο χειριστήρια δεν ακουμπά το άλλο, και το μόνο σχήμα που παραμένει
 * σωστό όποια κι αν είναι η στρογγυλοποίηση της προβολής.
 *
 * ⚠️ Η ανισότητα **δεν** επιβάλλεται εδώ με runtime clamp, για τον ίδιο λόγο που δεν
 * επιβάλλεται ούτε στη λαβή: θα ήταν αριθμητική σε καθαρή γεωμετρία που κανείς δεν μπορεί να
 * διαβάσει. Επιβάλλεται με **test**.
 */
export const TABLE_FILL_BADGE_GAP_PX = 8;

/**
 * Η εξωτερική εμβέλεια της **λαβής** προς τα κάτω-δεξιά, σε px οθόνης — ο αριθμός που το
 * {@link TABLE_FILL_BADGE_GAP_PX} οφείλει να ξεπερνά.
 *
 * Εξάγεται ως **παράγωγο των δύο σταθερών της λαβής** και όχι ως γραμμένος αριθμός: μια
 * αντιγραμμένη τιμή `7` εδώ θα έμενε πίσω τη μέρα που αλλάξει η οπή, και το test θα
 * επιβεβαίωνε την ανισότητα πάνω σε αριθμό που δεν ισχύει πια.
 */
export const TABLE_FILL_HANDLE_OUTWARD_REACH_PX =
  TABLE_FILL_HANDLE_PX / 2 + TABLE_FILL_HANDLE_OUTWARD_APERTURE_PX;

/** Τι βρήκε η σάρωση πάνω στο κουμπί· `null` παντού αλλού. */
export interface TableFillBadgeHit {
  /** Το τετράγωνο που βρέθηκε — ο καλών δεν το ξαναϋπολογίζει για να το ζωγραφίσει. */
  readonly rectMm: TableRectMm;
}

/**
 * Το τετράγωνο του κουμπιού σε **sheet-mm του πλαισίου**, ή `null` όταν η γεμισμένη περιοχή
 * δεν τέμνει τη διάταξη (μπαγιάτικα όρια μετά από undo ή διαγραφή γραμμής).
 *
 * Κάθεται **κάτω από** την κάτω δεξιά κορυφή, με την **αριστερή** του ακμή στο `x` της
 * κορυφής — δηλαδή απλώνεται προς τα δεξιά, στο κενό. Είναι η θέση του Excel και είναι και η
 * μόνη που δεν σκεπάζει κελί: προς τα αριστερά ζουν τα δεδομένα που μόλις γράφτηκαν, και ένα
 * κουμπί από πάνω τους θα έκρυβε ακριβώς αυτό που ο χρήστης θέλει να επαληθεύσει πριν
 * αποφασίσει αν άλλαξε γνώμη.
 */
export function tableFillBadgeRectMm(
  layout: TableLayout,
  filled: TableCellRangeBounds,
  pxPerMm: number,
): TableRectMm | null {
  const rect = tableRangeRectMm(layout, filled);
  if (!rect || pxPerMm <= 0) return null;
  const sideMm = TABLE_FILL_BADGE_PX / pxPerMm;
  return {
    x: rect.x + rect.w,
    y: rect.y + rect.h + TABLE_FILL_BADGE_GAP_PX / pxPerMm,
    w: sideMm,
    h: sideMm,
  };
}

/**
 * Είναι το σημείο πάνω στο κουμπί; **Το ορθογώνιο αυτούσιο** — δες
 * {@link TABLE_FILL_BADGE_PX} για το γιατί δεν υπάρχει οπή.
 *
 * ⚠️ Γράφεται με τις **ακμές** του `rect` και όχι με δεύτερη έκφραση της θέσης, ίδια σύμβαση
 * με τη λαβή: το «πού κάθεται το κουμπί» ζει **μία** φορά, στην
 * {@link tableFillBadgeRectMm}.
 */
export function isOnTableFillBadge(
  point: { readonly u: number; readonly v: number },
  rect: TableRectMm,
): boolean {
  return (
    point.u >= rect.x &&
    point.u <= rect.x + rect.w &&
    point.v >= rect.y &&
    point.v <= rect.y + rect.h
  );
}

/**
 * 🔴 **ΕΠΕΣΕ ΤΟ ΧΕΡΙ ΠΑΝΩ ΣΤΟ ΚΟΥΜΠΙ;** — ο **ΕΝΑΣ** δρόμος, για τον δείκτη και για το πάτημα.
 *
 * Ίδιο σχήμα με το `tableFillHandleHitAtFrame`, και για τον ίδιο ρητό λόγο (ADR-739 §31 — *ο
 * δείκτης δεν ψεύδεται*): αν ο δείκτης ρωτούσε δική του γεωμετρία, θα υπήρχε ζώνη όπου το
 * βέλος υπόσχεται κουμπί και το πάτημα δεν πιάνει τίποτα. Η παραβίαση αυτού του κανόνα έχει
 * ήδη κοστίσει **μία φορά** μέσα σε αυτή την ίδια γωνία (ADR-754 §14.9.2).
 *
 * `filled === null` ⇒ **κανένα κουμπί**. Είναι η γραμμή που κωδικοποιεί το «το κουμπί ζει
 * μόνο μετά από συμπλήρωση, και μόνο όσο η συμπλήρωση είναι ακόμη το τελευταίο που έγινε»:
 * ο καλών δίνει `null` όταν η {@link resolveTableFillBadgeBounds} σιωπά, και δεν χρειάζεται
 * δεύτερος έλεγχος κατάστασης μέσα σε καθαρή γεωμετρία.
 */
export function tableFillBadgeHitAtFrame(
  layout: TableLayout,
  frame: TableFramePoint,
  pxPerMm: number,
  filled: TableCellRangeBounds | null,
): TableFillBadgeHit | null {
  if (!filled) return null;
  const rectMm = tableFillBadgeRectMm(layout, filled, pxPerMm);
  if (!rectMm || !isOnTableFillBadge(frame, rectMm)) return null;
  return { rectMm };
}

/**
 * 🔴 **ΕΙΝΑΙ ΤΟ ΚΟΥΜΠΙ ΑΚΟΜΗ ΑΛΗΘΙΝΟ;** — η **μία** κρίση, για τους **τρεις** που ρωτούν:
 * ο ζωγράφος (ζωγραφίζεται;), ο δείκτης/πάτημα (πιάνεται;) και το **πληκτρολόγιο** (ανοίγει
 * το `Alt+↓` μενού;).
 *
 * Τρεις σιωπές, με τη σειρά που στοιχίζουν σε αύξουσα ακρίβεια:
 *  1. **άλλος πίνακας** — δύο πίνακες στη σκηνή δεν μοιράζονται συμπλήρωση·
 *  2. **δεν είμαστε σε πλοήγηση** — όσο ο χρήστης πληκτρολογεί, το κουμπί δεν έχει νόημα και
 *     θα διεκδικούσε pixel δίπλα στο `<textarea>`. Ο **ίδιος** φρουρός με τη λαβή (§13.5)·
 *  3. 🔑 **μπαγιάτικη σφραγίδα έκδοσης** — δες παρακάτω.
 *
 * ## 🔴 ΓΙΑΤΙ Η ΣΥΓΚΡΙΣΗ ΕΙΝΑΙ **ΔΕΙΚΤΗΣ**, ΚΑΙ ΓΙΑΤΙ ΑΥΤΟ ΑΝΤΙΚΑΘΙΣΤΑ ΚΑΘΕ ΑΚΥΡΩΤΗ
 * Το έργο έχει τεκμηριωμένο δόγμα ότι *η ταυτότητα του μοντέλου **ΕΙΝΑΙ** η έκδοσή του*: το
 * `buildTableModelCommand` επιστρέφει `null` όταν το μοντέλο γύρισε ίδιο by-reference, δηλαδή
 * **νέα αναφορά ⇒ πραγματική αλλαγή**. Άρα «έγινε κάτι μετά τη συμπλήρωση;» είναι **μία
 * σύγκριση δείκτη** — και οι τέσσερις ακυρωτές που ζητά το Excel (επόμενη αναιρέσιμη πράξη ·
 * `Undo` · πληκτρολόγηση · διαγραφή) βγαίνουν **χωρίς καμία γραμμή σε καμία διαδρομή
 * εγγραφής**, ούτε στις σημερινές ούτε στις μελλοντικές.
 *
 * Είναι ακριβώς ο μηχανισμός που κρατά ήδη τα «μυρμήγκια» του προχείρου (ADR-739 §48), και
 * αντιγράφεται αυτούσιος επειδή απαντά την **ίδια** ερώτηση: *μεταβατική κατάσταση που
 * γεννήθηκε από μια πράξη και πρέπει να πεθάνει στην επόμενη*.
 *
 * ⚠️ **Απόκλιση από το Excel, ρητή**: εκεί το κουμπί φεύγει **οριστικά** μόλις αρχίσεις να
 * πληκτρολογείς· εδώ, αν πληκτρολογήσεις και **ακυρώσεις** με `Escape` χωρίς να δεσμεύσεις,
 * το μοντέλο δεν άλλαξε και το κουμπί επιστρέφει. Είναι συνειδητό: η ερώτηση που απαντά ο
 * φρουρός #2 είναι «*φαίνεται τώρα;*», ενώ ο #3 απαντά «*ισχύει ακόμη;*» — και μια ακυρωμένη
 * πληκτρολόγηση δεν άλλαξε τίποτα, οπότε μια οριστική εξαφάνιση θα ήταν τιμωρία για πράξη
 * που δεν έγινε.
 */
export function resolveTableFillBadgeBounds(
  entity: TableEntity,
  cursor: TableCellCursorState | null,
  badge: TableFillBadgeState | null,
): TableCellRangeBounds | null {
  if (!badge || badge.entityId !== entity.id) return null;
  if (cursor?.entityId !== entity.id || cursor.mode !== 'nav') return null;
  if (badge.modelRef !== entity.model) return null;
  return badge.filled;
}
