/**
 * 🔴 ADR-739 §31 — **ΤΙ ΥΠΟΣΧΕΤΑΙ Ο ΔΕΙΚΤΗΣ ΤΟΥ ΟΣ** σε αυτό το σημείο.
 *
 * Ο **αναλλοίωτος κανόνας**, που δεν άλλαξε ποτέ: κάθε ρόλος αντιστοιχεί σε ενέργεια που
 * **όντως** εκτελείται αν ο χρήστης πατήσει. Δες {@link tableIndicatorCursorRoleAtFrame} για
 * το γιατί λείπει —ακόμα— το προφανές `'row-resize'`.
 *
 * ## ⚠️ ΕΔΩ ΕΓΡΑΦΕ «τρεις ρόλοι, και ΚΑΝΕΝΑΣ ΤΕΤΑΡΤΟΣ». Η ΠΡΟΔΙΑΓΡΑΦΗ ΑΛΛΑΞΕ (§36)
 * Δεν ήταν λάθος τότε — ήταν φράχτης γύρω από τη **λωρίδα** του δείκτη, όπου όντως υπήρχαν
 * τρεις εντολές. Ο ιδιοκτήτης επέκτεινε το ερώτημα από τη λωρίδα σε **ολόκληρο τον πίνακα**:
 * «*μέσα σε κελί σταυρός, πάνω σε περίγραμμα σημάδι μετακίνησης*». Οι τρεις νέοι ρόλοι
 * περνούν τον **ίδιο** έλεγχο που απέκλεισε το `row-resize`: πίσω από κάθε έναν υπάρχει
 * χειρονομία που εκτελείται (§36), όχι εικονίδιο που παρηγορεί.
 *
 * | ρόλος | πού | τι γίνεται αν πατήσεις |
 * |---|---|---|
 * | `column-select` / `row-select` | λωρίδες γραμμάτων / αριθμών | επιλογή ολόκληρου άξονα |
 * | `column-resize` | διαχωριστικό στηλών | σύρσιμο πλάτους |
 * | `cell-select` | **μέσα** στο πλέγμα | επιλογή κελιού / σύρση περιοχής |
 * | `range-move` | **πάνω στο περίγραμμα** της επιλογής | μεταφορά της περιοχής |
 * | `range-copy` | το ίδιο, με `Ctrl` | αντιγραφή της περιοχής |
 *
 * ## 🔴 ΚΑΙ ΟΙ ΤΡΕΙΣ ΝΕΟΙ ΕΙΝΑΙ ΛΕΞΕΙΣ-ΚΛΕΙΔΙΑ CSS — ΜΗΔΕΝ ΡΑΣΤΕΡ
 * Το `cell-select` γίνεται `cursor: cell`, που η **προδιαγραφή** ορίζει κυριολεκτικά ως τον
 * παχύ σταυρό του φύλλου υπολογισμού· τα άλλα δύο γίνονται `move` / `copy`. Δηλαδή οι τρεις
 * ρόλοι που ζήτησε ο ιδιοκτήτης **δεν** πληρώνουν τίποτα από το τίμημα του
 * `table-indicator-cursor-image`: ούτε το όριο των 32 device-px, ούτε τη σιωπηλή απόρριψη
 * PNG, ούτε τον κίνδυνο τρεμοπαίγματος από νέο base64. Ο κανόνας «**native όπου υπάρχει**»
 * (γραμμένος στο `useCrosshairCursor`) εδώ πληρώνεται ολόκληρος.
 *
 * ## 🔴 §36 ΦΑΣΗ 3 — Ο ΕΒΔΟΜΟΣ ΡΟΛΟΣ ΔΕΝ ΓΕΝΝΙΕΤΑΙ ΕΔΩ, ΚΑΙ ΕΙΝΑΙ ΣΩΣΤΟ
 * Το `range-refuse` (`cursor: not-allowed`) **δεν** επιστρέφεται ποτέ από την
 * {@link tableIndicatorCursorRoleAtFrame}: η γεωμετρία ξέρει «*πού είμαι*», όχι «*τι θα γίνει
 * αν αφήσω*» — η δεύτερη ερώτηση απαιτεί ολόκληρο το **σχέδιο** μεταφοράς (πηγή, πρόθεση,
 * συγχωνεύσεις), δηλαδή γνώση που αυτό το module δεν έχει και δεν πρέπει να αποκτήσει. Τον
 * παράγει η **χειρονομία** (`table-range-transfer-drag`), που κρατά το σχέδιο του καρέ.
 *
 * Περνά όμως τον ίδιο έλεγχο με τους άλλους έξι: πίσω του υπάρχει πραγματικό γεγονός — η
 * απελευθέρωση εδώ **δεν κάνει τίποτα**. Ο δείκτης δεν ψεύδεται· το αντίθετο, είναι το μόνο
 * κανάλι που μιλά και όταν δεν υπάρχει ορθογώνιο να βαφτεί (χέρι **έξω** από το πλέγμα).
 */
export type TableIndicatorCursorRole =
  | 'column-select'
  | 'row-select'
  | 'column-resize'
  | 'row-resize'
  | 'cell-select'
  | 'range-move'
  | 'range-copy'
  | 'range-refuse'
  | 'insert-control'
  /**
   * 🔴 §42 — **το ⊖ της διαγραφής, οπλισμένο.** Ξεχωριστός ρόλος από το `insert-control` παρότι
   * και οι δύο δίνουν `pointer`: ο ρόλος ονομάζει **τι θα γίνει**, όχι τι σχήμα βγαίνει. Ένα
   * κοινό `insert-control` για τα δύο θα σήμαινε ότι το όργανο του §31.11 (`noteCursorProbe`)
   * δεν μπορεί να ξεχωρίσει «πήγα να προσθέσω» από «πήγα να **σβήσω**» σε ένα ίχνος — δηλαδή
   * θα έχανε τη διάκριση ακριβώς εκεί που έχει σημασία.
   */
  | 'delete-control'
  /**
   * 🔴 **ADR-754 §14 — Ο ΛΕΠΤΟΣ ΜΑΥΡΟΣ ΣΤΑΥΡΟΣ ΤΗΣ ΛΑΒΗΣ ΣΥΜΠΛΗΡΩΣΗΣ.**
   *
   * Το Excel έχει **δύο** σταυρούς πάνω από φύλλο, και η διαφορά τους είναι ολόκληρη η
   * λειτουργία: ο **παχύς λευκός** λέει «μαρκάρεις κελιά» (εδώ `cell-select`), ο **λεπτός
   * μαύρος** λέει «**συμπληρώνεις**». Χωρίς τον δεύτερο, η λαβή του §13 είναι ένα τετράγωνο
   * 6 px που ο χρήστης ανακαλύπτει μόνο κατά λάθος.
   *
   * ## 🔴 ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ `cursor: crosshair` — η παγίδα που ακυρώνει το «native όπου υπάρχει»
   * Η προφανής μετάφραση «λεπτός σταυρός ⇒ `crosshair`» είναι **αόρατη** εδώ, και ο λόγος
   * είναι δομικός: ο Νέστωρ δείχνει **ήδη** σταυρόνημα CAD ως δείκτη υλικού σε ολόκληρο τον
   * καμβά (ADR-549 Φ8), και το `null` αυτής της συνάρτησης σημαίνει ακριβώς «μένει το
   * σταυρόνημα». Ένα `crosshair` πάνω στη λαβή θα ήταν οπτικά **ταυτόσημο με το «κανένας
   * ρόλος»**: κώδικας που περνά κάθε test και δεν αλλάζει τίποτα στην οθόνη.
   *
   * Άρα είναι ο **τρίτος** ρόλος που πληρώνει ράστερ (μετά τα δύο βέλη επιλογής άξονα) — και
   * ο πρώτος που το πληρώνει επειδή η λέξη-κλειδί **υπάρχει αλλά είναι πιασμένη**, όχι επειδή
   * λείπει. Δες `systems/cursor/table-indicator-cursor-image.ts`.
   */
  | 'fill-handle'
  /**
   * 🔴 **ADR-739 §43 — ΤΟ ΤΕΤΡΑΓΩΝΑΚΙ ΤΗΣ ΓΩΝΙΑΣ**, δηλαδή το κουμπί «επιλογή όλων» του Excel.
   *
   * Ξεχωριστός ρόλος και όχι κοινός με τα δύο χειριστήρια από πάνω, παρότι και οι τρεις
   * καταλήγουν σε `pointer`: ο ρόλος ονομάζει **τι θα γίνει**, όχι τι σχήμα βγαίνει — το ίδιο
   * επιχείρημα που γέννησε το `delete-control` δίπλα στο `insert-control`, ώστε το όργανο του
   * §31.11 (`noteCursorProbe`) να ξεχωρίζει σε ένα ίχνος «πήγα να προσθέσω» από «πήγα να
   * σβήσω» από «πήγα να **μαρκάρω τα πάντα**».
   *
   * Περνά τον αναλλοίωτο έλεγχο του §31 χωρίς έκπτωση: πίσω του υπάρχει χειρονομία που
   * **όντως** εκτελείται — το ίδιο `selectAll()` που εκτελεί ήδη το `Ctrl+A`.
   */
  | 'select-all';

/**
 * 🔴 ADR-739 §31 — **ΠΟΙΟ ΣΧΗΜΑ ΔΕΙΚΤΗ ΟΦΕΙΛΕΤΑΙ ΕΔΩ**· `null` = κανένα (μένει το σταυρόνημα).
 *
 * Ο Giorgio το ζήτησε ως «όπως στο Excel, που δηλώνει ότι μπορείς να σύρεις τη διαχωριστική
 * γραμμή». Η μετάφραση **δεν** είναι μηχανική, και τα δύο σημεία που αποκλίνουν από το Excel
 * αποκλίνουν επειδή ο κώδικας από κάτω είναι διαφορετικός — όχι από παράλειψη:
 *
 * ## 🔴 1. Το `col-resize` ΔΕΝ ζει μέσα στη λωρίδα των γραμμάτων — ζει στην ακμή του πλέγματος
 * Στο Excel η λαβή πλάτους **είναι** η κάτω ακμή της κεφαλίδας, οπότε τα δύο συμπίπτουν. Εδώ η
 * λαβή `table-column-edge` κάθεται στο `v = 0` (`table-entity-grips`), και το §27.11 έβαλε
 * **επίτηδες** κενό (`TABLE_INDICATOR_GRIP_CLEARANCE_PX`) ανάμεσα στη λαβή και τη ζώνη,
 * ακριβώς για να μη διεκδικεί το ίδιο pixel και η λαβή και η επιλογή στήλης.
 *
 * Άρα ένα `col-resize` **μέσα** στη λωρίδα θα ήταν **ψέμα**: εκεί το πάτημα επιλέγει στήλη,
 * δεν σέρνει τίποτα. Ο δείκτης δείχνει `column-resize` **μόνο** πάνω στον δίσκο της λαβής —
 * δηλαδή ανακοινώνει έναν μηχανισμό που **υπάρχει ήδη** (§8) αντί να υπόσχεται νέο.
 *
 * ⚠️ Ο δίσκος δεν ξαναγράφεται εδώ: είναι το **ίδιο** `bands.gapMm`, δηλαδή η ίδια
 * `TABLE_INDICATOR_GRIP_CLEARANCE_PX` = `gripAperturePx(...)`. Αν αύριο μεγαλώσει η οπή,
 * μεγαλώνει μαζί και η ζώνη που την ανακοινώνει — δεν υπάρχει δεύτερος αριθμός να ξεχαστεί.
 *
 * ## ✅ 2. ΤΟ `'row-resize'` ΥΠΑΡΧΕΙ ΠΛΕΟΝ — και μπήκε ακριβώς με τον όρο που είχε γραφτεί
 * Εδώ έγραφε «ΔΕΝ υπάρχει `row-resize`, και είναι απόφαση όχι έλλειψη», με τον λόγο: δεν
 * υπήρχε **λαβή** ύψους γραμμής, οπότε ο δείκτης θα υποσχόταν ενέργεια που δεν εκτελείται —
 * και ο χρήστης θα το διάβαζε ως **σφάλμα της εφαρμογής**, χειρότερο από το να μη μάθει ποτέ
 * ότι υπάρχει. Η ίδια παράγραφος όριζε ρητά τον όρο άρσης: «*όταν αποκτήσει λαβή ύψους, ο
 * ρόλος προστίθεται εδώ και μόνο εδώ*».
 *
 * Αυτό ακριβώς έγινε (Giorgio 2026-08-04): υπάρχει `table-row-edge` στο `table-entity-grips`,
 * με φράγμα πλήθους αντί για απαγόρευση άξονα. Ο δείκτης **δεν** ψεύδεται — απλώς σταμάτησε
 * να σιωπά. Ο κανόνας δεν χαλάρωσε· η προϋπόθεσή του ικανοποιήθηκε.
 */
export function tableIndicatorCursorRoleAtFrame(
  layout: TableLayout,
  frame: TableFramePoint,
  bands: TableIndicatorBandsMm,
  // 🔴 §36 — το ορθογώνιο της **ενεργής επιλογής** σε sheet-mm· `null` = καμία επιλογή.
  //
  // Προαιρετικό **με πρόθεση**: η γεωμετρία της λωρίδας (§31) απαντά ακέραια χωρίς αυτό, και
  // οι δεκάδες υπάρχουσες κλήσεις/tests που ρωτούν μόνο για τη λωρίδα δεν χρειάζεται να
  // μάθουν τι είναι «επιλογή». Ο ένας καταναλωτής που **έχει** επιλογή τη δίνει.
  rangeRectMm: TableRectMm | null = null,
  intent: TableRangeDragIntent = PLAIN_TABLE_RANGE_DRAG,
  // 🔴 §40 — **το ⊕ της εισαγωγής, ήδη απαντημένο**. Έρχεται ως όρισμα και δεν υπολογίζεται
  // εδώ για τον ίδιο λόγο που έρχεται και η επιλογή: ο καλών το χρειάζεται ούτως ή άλλως (το
  // ζωγραφίζει), άρα μια δεύτερη σάρωση εδώ θα ήταν δεύτερος υπολογισμός **ανά κίνηση
  // ποντικιού** — και, χειρότερα, δεύτερη ευκαιρία να διαφωνήσει με αυτό που ζωγραφίστηκε.
  insert: TableInsertControlHit | null = null,
  // 🔴 §40 — σε ποια από τις δύο καταστάσεις ρωτάμε. Δες τη διακλάδωση παρακάτω: εκτός
  // λειτουργίας πίνακα **δεν υπάρχουν** ζώνες, δρομέας ούτε επιλογή κελιών — άρα ούτε ρόλοι.
  mode: TableInsertControlMode = 'table-mode',
  // 🔴 §42 — **το ⊖ της διαγραφής, ήδη απαντημένο**. Έρχεται ως όρισμα για τον ίδιο ακριβώς
  // λόγο με το ⊕ από πάνω: ο καλών το χρειάζεται ούτως ή άλλως (το ζωγραφίζει), άρα μια
  // δεύτερη σάρωση εδώ θα ήταν δεύτερος υπολογισμός **ανά κίνηση ποντικιού** — και δεύτερη
  // ευκαιρία να διαφωνήσει με αυτό που ζωγραφίστηκε.
  remove: TableDeleteControlHit | null = null,
  // 🔴 ADR-754 §14 — **η λαβή συμπλήρωσης, ήδη απαντημένη**. Τρίτο «έρχεται ως όρισμα» στη
  // σειρά, και ο λόγος είναι **διαφορετικός** από των δύο από πάνω: το ⊕ και το ⊖ τα υπολογίζει
  // ο καλών επειδή τα **ζωγραφίζει** ούτως ή άλλως· η λαβή έρχεται από έξω επειδή η ερώτησή της
  // απαιτεί **μοντέλο και δρομέα** (ποια περιοχή είναι μαρκαρισμένη, και γράφει ο χρήστης αυτή
  // τη στιγμή;) — γνώση που αυτό το module δηλώνει ρητά ότι δεν αποκτά. Ίδια σύμβαση με το
  // `rangeRectMm` από πάνω, μία στροφή πιο πέρα.
  fill: TableFillHandleHit | null = null,
): TableIndicatorCursorRole | null {
  // 🔴 §40 — **ΠΡΩΤΟ ΑΠ' ΟΛΑ, ΚΑΙ ΜΟΝΟ ΟΠΛΙΣΜΕΝΟ.** Το ⊕ ζει έξω από κάθε άλλη ζώνη (πάνω
  // από τον δείκτη σε λειτουργία, πάνω από την οπή λαβής σε επιλογή), οπότε η σειρά δεν λύνει
  // σύγκρουση — δηλώνει προτεραιότητα για την περίπτωση που κάποιος μεγαλώσει αύριο μια ζώνη
  // και οι δύο περιοχές ακουμπήσουν.
  //
  // ⚠️ Η φάση `nearby` **δεν** δίνει δείκτη κουμπιού: εκεί το ⊕ φαίνεται αλλά δεν πατιέται.
  // Ένα `pointer` σε ολόκληρη τη λωρίδα θα ήταν ακριβώς το ψέμα που ο §31 απαγορεύει — και το
  // χειρότερο είδος του, γιατί ο χρήστης θα πατούσε και δεν θα γινόταν τίποτα.
  if (insert?.phase === 'armed') return 'insert-control';

  // 🔴 §40 — **εκτός λειτουργίας πίνακα δεν οφείλεται τίποτε άλλο.** Σε απλή επιλογή ο πίνακας
  // είναι μια οντότητα σαν κάθε άλλη: κανένα κελί δεν επιλέγεται, καμία ζώνη δεν υπάρχει, και
  // ο δείκτης οφείλει να μείνει το σταυρόνημα του σχεδίου. Χωρίς αυτόν τον φύλακα, το
  // `cell-select` του §36 θα κατέκλυζε ολόκληρο τον πίνακα τη στιγμή που τον διαλέγεις,
  // υποσχόμενο επιλογή κελιού που δεν εκτελείται χωρίς διπλό κλικ.
  if (mode === 'selection') return null;

  // 🔴 §42 — **το ⊖ πριν από τη ζώνη, και μόνο οπλισμένο.**
  //
  // Η σειρά ως προς τα **διαχωριστικά** από κάτω δεν λύνει σύγκρουση και δεν μπορεί να τη
  // λύσει λάθος: το ⊖ είναι υποτελές στο `tableIndicatorHitAtFrame`, που παραιτείται ήδη πάνω
  // στα διαχωριστικά (§31.9) — άρα «οπλισμένο ⊖» συνεπάγεται δομικά «όχι πάνω σε λαβή
  // πλάτους». Η σειρά ως προς την **επιλογή άξονα** από κάτω, αντίθετα, είναι ουσιώδης: ο
  // δίσκος ζει **μέσα** στο κουτί του γράμματος, και χωρίς αυτή τη γραμμή ο δείκτης θα
  // υποσχόταν «επιλογή στήλης» πάνω από ένα κουμπί που **σβήνει** τη στήλη.
  //
  // ⚠️ Η φάση `nearby` **δεν** δίνει δείκτη κουμπιού: εκεί το ⊖ φαίνεται αλλά το πάτημα ανήκει
  // ακέραιο στη ζώνη (επιλογή άξονα). Ίδιος κανόνας με το ⊕, ίδιος λόγος: ο δείκτης δεν
  // ψεύδεται ποτέ (§31).
  if (remove?.phase === 'armed') return 'delete-control';

  // 🔴 ADR-754 §14 — **Η ΛΑΒΗ ΣΥΜΠΛΗΡΩΣΗΣ, ΠΡΙΝ ΑΠΟ ΚΑΘΕ ΖΩΝΗ ΚΑΙ ΠΡΙΝ ΑΠΟ ΤΟ ΠΛΕΓΜΑ.**
  //
  // Η θέση **αντιγράφει τη σειρά του πατήματος** (`use-table-cell-pointer`: ο φρουρός της λαβής
  // τρέχει αμέσως μετά την υπόδειξη, **πριν** από τα διαχωριστικά, τις ζώνες και το κελί), και
  // αυτό δεν είναι συμμετρία για την ομορφιά: ο §31 λέει ότι ο δείκτης δείχνει **ό,τι θα κάνει
  // το πάτημα**. Δύο διαφορετικές σειρές θα σήμαιναν pixel όπου ο δείκτης υπόσχεται ένα και το
  // κλικ κάνει άλλο.
  //
  // 🔴 Και ουσιωδώς **πάνω από τον φύλακα `insideGrid`**: η λαβή κάθεται **κεντραρισμένη** στην
  // κάτω-δεξιά κορυφή της επιλογής, δηλαδή **μισή έξω** από το πλέγμα εξ ορισμού — και όταν η
  // επιλογή αγγίζει την τελευταία στήλη ή γραμμή (η συνηθέστερη περίπτωση συμπλήρωσης), το μισό
  // αυτό πέφτει έξω από το `layout.widthMm/heightMm`. Κάτω από τον φύλακα, ο δείκτης θα σιωπούσε
  // ακριβώς στη μισή λαβή που το πάτημα **πιάνει κανονικά** (το `isOnTableFillHandle` δεν ρωτά
  // πλέγμα, και ούτε ο φρουρός του πατήματος).
  //
  // ⚠️ Η προτεραιότητα έναντι του `range-move` από κάτω είναι **πραγματική διεκδίκηση**, όχι
  // δήλωση: η λαβή ζει πάνω στην κορυφή του περιγράμματος, δηλαδή **μέσα** στη ζώνη σύλληψής
  // του. Χωρίς αυτή τη γραμμή, η γωνία θα έδινε `move` — και η λαβή θα έμενε τόσο αόρατη όσο
  // πριν, με τον δείκτη να λέει μάλιστα **λάθος** πράγμα.
  if (fill) return 'fill-handle';

  // 🔴 §31.9 — πρώτα το διαχωριστικό. Εδώ η σειρά **λύνει** πραγματική σύγκρουση: η ζώνη
  // ανοχής ζει **μέσα** στη λωρίδα των γραμμάτων, άρα τέμνει την περιοχή επιλογής στήλης. Το
  // `tableIndicatorHitAtFrame` παραιτείται στα ίδια pixel, ώστε ένα pixel να απαντά σε **μία**
  // ερώτηση (§27.11) — αλλά η σειρά γράφεται και εδώ, για όποιον διαβάσει μόνο αυτό.
  if (tableColumnEdgeAtFrame(layout, frame, bands) !== null) return 'column-resize';
  // Το κάτοπτρο, με την ίδια προτεραιότητα και για τον ίδιο λόγο (Giorgio 2026-08-04).
  if (tableRowEdgeAtFrame(layout, frame, bands) !== null) return 'row-resize';

  const hit = tableIndicatorHitAtFrame(layout, frame, bands);
  if (hit) return hit.axis === 'column' ? 'column-select' : 'row-select';

  // 🔴 §43 — **το τετραγωνάκι της γωνίας**, αμέσως μετά τις δύο ζώνες: είναι το τρίτο κομμάτι
  // του **ίδιου** χειριστηρίου (ο δείκτης του AutoCAD / η κεφαλίδα του Excel), όχι τέταρτο
  // χειριστήριο.
  //
  // ⚠️ **Υποχρεωτικά ΠΑΝΩ από τον φύλακα `insideGrid`** που ακολουθεί: η γωνία ζει σε
  // **αρνητικά** mm και στους δύο άξονες, δηλαδή ο φύλακας θα την έκοβε ολόκληρη και ο ρόλος
  // δεν θα επιστρεφόταν ποτέ — κώδικας που περνά κάθε test και δεν αλλάζει τίποτα στην οθόνη.
  //
  // Η σειρά ως προς τα διαχωριστικά και τις ζώνες από πάνω **δεν λύνει διεκδίκηση**: η γωνία
  // είναι ξένη προς όλα (η απόδειξη ζει στην κεφαλίδα του `table-select-all-corner`). Γράφεται
  // εδώ ως δήλωση προτεραιότητας, για την ημέρα που κάποιος μεγαλώσει μια ζώνη.
  if (isTableSelectAllCornerAtFrame(frame, bands)) return 'select-all';

  // 🔴 §36 — **ΑΠΟ ΕΔΩ ΚΑΙ ΚΑΤΩ ΕΙΜΑΣΤΕ ΜΕΣΑ ΣΤΟ ΠΛΕΓΜΑ, Ή ΠΟΥΘΕΝΑ.**
  //
  // Ο φύλακας είναι **δομικός**, όχι βελτιστοποίηση: στα αρνητικά mm ζουν οι ζώνες του δείκτη
  // και, στη λωρίδα του κενού, οι **λαβές** του πίνακα (§27.11 — «ένα pixel, μία ερώτηση»).
  // Χωρίς αυτόν, η εξωτερική εμβέλεια μιας επιλογής που ακουμπά την πάνω γραμμή θα έβγαινε σε
  // `v < 0` και θα διεκδικούσε τα **ίδια** pixel με τη λαβή `n` και τα γράμματα — δηλαδή θα
  // ξαναγεννούσε από την πίσω πόρτα ακριβώς τη σύγκρουση που το κενό ήρθε να σβήσει.
  const insideGrid =
    frame.u >= 0 && frame.u <= layout.widthMm && frame.v >= 0 && frame.v <= layout.heightMm;
  if (!insideGrid) return null;

  // Το **περίγραμμα** πριν το **σώμα**: η ζώνη του περιγράμματος ζει μέσα στο πλέγμα, οπότε
  // ένα `cell-select` που απαντούσε πρώτο θα την κατάπινε ολόκληρη. Ίδια αρχή «η πιο ειδική
  // ερώτηση πρώτη» με τη σειρά ζώνη→κελί του `tablePointerHitAtWorld`.
  //
  // ⚠️ Η ανοχή είναι **το ίδιο** `bands.gapMm` — δηλαδή η `gripAperturePx` του §27.16 Ε4.
  // Κανένας νέος αριθμός: η οπή σύλληψης του έργου είναι **μία**.
  if (rangeRectMm && isOnTableRangeBorder(rangeRectMm, frame, bands.gapMm)) {
    return intent.copy ? 'range-copy' : 'range-move';
  }

  // 🔴 §36 — **ΕΔΩ ΕΠΕΣΤΡΕΦΕ `null`**, δηλαδή «μένει το σταυρόνημα του σχεδίου». Ο ιδιοκτήτης
  // το άλλαξε ρητά: μέσα σε κελί θέλει τον **σταυρό του φύλλου υπολογισμού**. Δεν είναι
  // καλλωπισμός — είναι η δήλωση «*εδώ διαλέγεις κελιά, δεν σχεδιάζεις*», και είναι ακριβώς
  // η μισή από τις δύο καταστάσεις που ζητήθηκαν (η άλλη είναι το `range-move` από πάνω).
  return 'cell-select';
}
