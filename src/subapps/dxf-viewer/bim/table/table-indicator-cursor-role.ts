/**
 * ADR-739 §31 / §36 — **ΤΙ ΥΠΟΣΧΕΤΑΙ Ο ΔΕΙΚΤΗΣ ΤΟΥ ΠΟΝΤΙΚΙΟΥ** πάνω από τον πίνακα.
 *
 * Γεννήθηκε ως **εξαγωγή** από το `table-indicator-geometry` (2026-08-04, όριο N.7.1 στις 500
 * γραμμές), και η τομή δεν είναι αυθαίρετη — είναι η τομή που **ήδη** περιγράφει η κεφαλίδα
 * του γείτονα: εκείνο το module απαντά «**πού** κάθεται η ζώνη», αυτό εδώ «**τι οφείλεται**
 * σε αυτό το σημείο». Ίδιος διαχωρισμός με το `table-range-move-zone` (ο ΜΗΧΑΝΙΣΜΟΣ δίπλα, η
 * ΑΠΟΦΑΣΗ ξεχωριστά) — απλώς εφαρμοσμένος μία στροφή πιο έξω.
 *
 * ⚠️ Η εξάρτηση είναι **μονόδρομη και οφείλει να μείνει**: η απόφαση διαβάζει γεωμετρία, η
 * γεωμετρία δεν μαθαίνει ποτέ τι είναι «δείκτης». Γι' αυτό μετακόμισε εδώ **ολόκληρη** και η
 * εξάρτηση από το `table-range-move-zone`: η έννοια «επιλεγμένη περιοχή» δεν έχει καμία
 * δουλειά μέσα σε καθαρή γεωμετρία ζωνών.
 *
 * @module subapps/dxf-viewer/bim/table/table-indicator-cursor-role
 * @see bim/table/table-indicator-geometry.ts — ΠΟΥ κάθονται οι ζώνες (η γεωμετρία που καταναλώνει)
 * @see systems/cursor/useCrosshairCursor.ts — ο κανόνας «native όπου υπάρχει»
 * @see ui/table-cell-editor/table-range-transfer-drag.ts — ο έβδομος ρόλος (`range-refuse`)
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §31, §36
 */

import type { TableFramePoint } from '../../types/table-entity';
import {
  tableColumnEdgeAtFrame,
  tableIndicatorHitAtFrame,
  tableRowEdgeAtFrame,
  type TableIndicatorBandsMm,
} from './table-indicator-geometry';
import type { TableLayout, TableRectMm } from './table-layout-types';
// 🔴 ADR-739 §36 — η ζώνη του περιγράμματος ζει σε **δικό της** module: εδώ μένει η ερώτηση
// «ποιος ρόλος οφείλεται πού», εκεί η γεωμετρία «είμαι πάνω στη γραμμή;».
import {
  isOnTableRangeBorder,
  PLAIN_TABLE_RANGE_DRAG,
  type TableRangeDragIntent,
} from './table-range-move-zone';

/**
 * 🔴 ADR-739 §31 — **ΤΙ ΥΠΟΣΧΕΤΑΙ Ο ΔΕΙΚΤΗΣ ΤΟΥ ΟΣ** σε αυτό το σημείο.
 *
 * Ο **αναλλοίωτος κανόνας**, που δεν άλλαξε ποτέ: κάθε ρόλος αντιστοιχεί σε ενέργεια που
 * **όντως** εκτελείται αν ο χρήστης πατήσει. Δες {@link tableIndicatorCursorRoleAtFrame} για
 * το γιατί λείπει —ακόμα— το προφανές `'row-resize'`.
 *
 * ## ⚠️ ΕΔΩ ΕΓΡΑΦΕ «τρεις ρόλοι, και ΚΑΝΕΝΑΣ ΤΕΤΑΡΤΟΣ». Η ΠΡΟΔΙΑΓΡΑΦΗ ΑΛΛΑΞΕ (§36)
 * Δεν ήταν λάθος τότε — ήταν φράχτης γύρω από τη **λωρίδα** του δείκτη, όπου όντως υπήρχαν
 * τρεις εντολές. Ο ιδιοκτήτης επέκτεινε το ερώτημα από τη λωρίδα σε **ολόκληρο τον πίνακα**:
 * «*μέσα σε κελί σταυρός, πάνω σε περίγραμμα σημάδι μετακίνησης*». Οι τρεις νέοι ρόλοι
 * περνούν τον **ίδιο** έλεγχο που απέκλεισε το `row-resize`: πίσω από κάθε έναν υπάρχει
 * χειρονομία που εκτελείται (§36), όχι εικονίδιο που παρηγορεί.
 *
 * | ρόλος | πού | τι γίνεται αν πατήσεις |
 * |---|---|---|
 * | `column-select` / `row-select` | λωρίδες γραμμάτων / αριθμών | επιλογή ολόκληρου άξονα |
 * | `column-resize` | διαχωριστικό στηλών | σύρσιμο πλάτους |
 * | `cell-select` | **μέσα** στο πλέγμα | επιλογή κελιού / σύρση περιοχής |
 * | `range-move` | **πάνω στο περίγραμμα** της επιλογής | μεταφορά της περιοχής |
 * | `range-copy` | το ίδιο, με `Ctrl` | αντιγραφή της περιοχής |
 *
 * ## 🔴 ΚΑΙ ΟΙ ΤΡΕΙΣ ΝΕΟΙ ΕΙΝΑΙ ΛΕΞΕΙΣ-ΚΛΕΙΔΙΑ CSS — ΜΗΔΕΝ ΡΑΣΤΕΡ
 * Το `cell-select` γίνεται `cursor: cell`, που η **προδιαγραφή** ορίζει κυριολεκτικά ως τον
 * παχύ σταυρό του φύλλου υπολογισμού· τα άλλα δύο γίνονται `move` / `copy`. Δηλαδή οι τρεις
 * ρόλοι που ζήτησε ο ιδιοκτήτης **δεν** πληρώνουν τίποτα από το τίμημα του
 * `table-indicator-cursor-image`: ούτε το όριο των 32 device-px, ούτε τη σιωπηλή απόρριψη
 * PNG, ούτε τον κίνδυνο τρεμοπαίγματος από νέο base64. Ο κανόνας «**native όπου υπάρχει**»
 * (γραμμένος στο `useCrosshairCursor`) εδώ πληρώνεται ολόκληρος.
 *
 * ## 🔴 §36 ΦΑΣΗ 3 — Ο ΕΒΔΟΜΟΣ ΡΟΛΟΣ ΔΕΝ ΓΕΝΝΙΕΤΑΙ ΕΔΩ, ΚΑΙ ΕΙΝΑΙ ΣΩΣΤΟ
 * Το `range-refuse` (`cursor: not-allowed`) **δεν** επιστρέφεται ποτέ από την
 * {@link tableIndicatorCursorRoleAtFrame}: η γεωμετρία ξέρει «*πού είμαι*», όχι «*τι θα γίνει
 * αν αφήσω*» — η δεύτερη ερώτηση απαιτεί ολόκληρο το **σχέδιο** μεταφοράς (πηγή, πρόθεση,
 * συγχωνεύσεις), δηλαδή γνώση που αυτό το module δεν έχει και δεν πρέπει να αποκτήσει. Τον
 * παράγει η **χειρονομία** (`table-range-transfer-drag`), που κρατά το σχέδιο του καρέ.
 *
 * Περνά όμως τον ίδιο έλεγχο με τους άλλους έξι: πίσω του υπάρχει πραγματικό γεγονός — η
 * απελευθέρωση εδώ **δεν κάνει τίποτα**. Ο δείκτης δεν ψεύδεται· το αντίθετο, είναι το μόνο
 * κανάλι που μιλά και όταν δεν υπάρχει ορθογώνιο να βαφτεί (χέρι **έξω** από το πλέγμα).
 */
export type TableIndicatorCursorRole =
  | 'column-select'
  | 'row-select'
  | 'column-resize'
  | 'row-resize'
  | 'cell-select'
  | 'range-move'
  | 'range-copy'
  | 'range-refuse';

/**
 * 🔴 ADR-739 §31 — **ΠΟΙΟ ΣΧΗΜΑ ΔΕΙΚΤΗ ΟΦΕΙΛΕΤΑΙ ΕΔΩ**· `null` = κανένα (μένει το σταυρόνημα).
 *
 * Ο Giorgio το ζήτησε ως «όπως στο Excel, που δηλώνει ότι μπορείς να σύρεις τη διαχωριστική
 * γραμμή». Η μετάφραση **δεν** είναι μηχανική, και τα δύο σημεία που αποκλίνουν από το Excel
 * αποκλίνουν επειδή ο κώδικας από κάτω είναι διαφορετικός — όχι από παράλειψη:
 *
 * ## 🔴 1. Το `col-resize` ΔΕΝ ζει μέσα στη λωρίδα των γραμμάτων — ζει στην ακμή του πλέγματος
 * Στο Excel η λαβή πλάτους **είναι** η κάτω ακμή της κεφαλίδας, οπότε τα δύο συμπίπτουν. Εδώ η
 * λαβή `table-column-edge` κάθεται στο `v = 0` (`table-entity-grips`), και το §27.11 έβαλε
 * **επίτηδες** κενό (`TABLE_INDICATOR_GRIP_CLEARANCE_PX`) ανάμεσα στη λαβή και τη ζώνη,
 * ακριβώς για να μη διεκδικεί το ίδιο pixel και η λαβή και η επιλογή στήλης.
 *
 * Άρα ένα `col-resize` **μέσα** στη λωρίδα θα ήταν **ψέμα**: εκεί το πάτημα επιλέγει στήλη,
 * δεν σέρνει τίποτα. Ο δείκτης δείχνει `column-resize` **μόνο** πάνω στον δίσκο της λαβής —
 * δηλαδή ανακοινώνει έναν μηχανισμό που **υπάρχει ήδη** (§8) αντί να υπόσχεται νέο.
 *
 * ⚠️ Ο δίσκος δεν ξαναγράφεται εδώ: είναι το **ίδιο** `bands.gapMm`, δηλαδή η ίδια
 * `TABLE_INDICATOR_GRIP_CLEARANCE_PX` = `gripAperturePx(...)`. Αν αύριο μεγαλώσει η οπή,
 * μεγαλώνει μαζί και η ζώνη που την ανακοινώνει — δεν υπάρχει δεύτερος αριθμός να ξεχαστεί.
 *
 * ## ✅ 2. ΤΟ `'row-resize'` ΥΠΑΡΧΕΙ ΠΛΕΟΝ — και μπήκε ακριβώς με τον όρο που είχε γραφτεί
 * Εδώ έγραφε «ΔΕΝ υπάρχει `row-resize`, και είναι απόφαση όχι έλλειψη», με τον λόγο: δεν
 * υπήρχε **λαβή** ύψους γραμμής, οπότε ο δείκτης θα υποσχόταν ενέργεια που δεν εκτελείται —
 * και ο χρήστης θα το διάβαζε ως **σφάλμα της εφαρμογής**, χειρότερο από το να μη μάθει ποτέ
 * ότι υπάρχει. Η ίδια παράγραφος όριζε ρητά τον όρο άρσης: «*όταν αποκτήσει λαβή ύψους, ο
 * ρόλος προστίθεται εδώ και μόνο εδώ*».
 *
 * Αυτό ακριβώς έγινε (Giorgio 2026-08-04): υπάρχει `table-row-edge` στο `table-entity-grips`,
 * με φράγμα πλήθους αντί για απαγόρευση άξονα. Ο δείκτης **δεν** ψεύδεται — απλώς σταμάτησε
 * να σιωπά. Ο κανόνας δεν χαλάρωσε· η προϋπόθεσή του ικανοποιήθηκε.
 */
export function tableIndicatorCursorRoleAtFrame(
  layout: TableLayout,
  frame: TableFramePoint,
  bands: TableIndicatorBandsMm,
  // 🔴 §36 — το ορθογώνιο της **ενεργής επιλογής** σε sheet-mm· `null` = καμία επιλογή.
  //
  // Προαιρετικό **με πρόθεση**: η γεωμετρία της λωρίδας (§31) απαντά ακέραια χωρίς αυτό, και
  // οι δεκάδες υπάρχουσες κλήσεις/tests που ρωτούν μόνο για τη λωρίδα δεν χρειάζεται να
  // μάθουν τι είναι «επιλογή». Ο ένας καταναλωτής που **έχει** επιλογή τη δίνει.
  rangeRectMm: TableRectMm | null = null,
  intent: TableRangeDragIntent = PLAIN_TABLE_RANGE_DRAG,
): TableIndicatorCursorRole | null {
  // 🔴 §31.9 — πρώτα το διαχωριστικό. Εδώ η σειρά **λύνει** πραγματική σύγκρουση: η ζώνη
  // ανοχής ζει **μέσα** στη λωρίδα των γραμμάτων, άρα τέμνει την περιοχή επιλογής στήλης. Το
  // `tableIndicatorHitAtFrame` παραιτείται στα ίδια pixel, ώστε ένα pixel να απαντά σε **μία**
  // ερώτηση (§27.11) — αλλά η σειρά γράφεται και εδώ, για όποιον διαβάσει μόνο αυτό.
  if (tableColumnEdgeAtFrame(layout, frame, bands) !== null) return 'column-resize';
  // Το κάτοπτρο, με την ίδια προτεραιότητα και για τον ίδιο λόγο (Giorgio 2026-08-04).
  if (tableRowEdgeAtFrame(layout, frame, bands) !== null) return 'row-resize';

  const hit = tableIndicatorHitAtFrame(layout, frame, bands);
  if (hit) return hit.axis === 'column' ? 'column-select' : 'row-select';

  // 🔴 §36 — **ΑΠΟ ΕΔΩ ΚΑΙ ΚΑΤΩ ΕΙΜΑΣΤΕ ΜΕΣΑ ΣΤΟ ΠΛΕΓΜΑ, Ή ΠΟΥΘΕΝΑ.**
  //
  // Ο φύλακας είναι **δομικός**, όχι βελτιστοποίηση: στα αρνητικά mm ζουν οι ζώνες του δείκτη
  // και, στη λωρίδα του κενού, οι **λαβές** του πίνακα (§27.11 — «ένα pixel, μία ερώτηση»).
  // Χωρίς αυτόν, η εξωτερική εμβέλεια μιας επιλογής που ακουμπά την πάνω γραμμή θα έβγαινε σε
  // `v < 0` και θα διεκδικούσε τα **ίδια** pixel με τη λαβή `n` και τα γράμματα — δηλαδή θα
  // ξαναγεννούσε από την πίσω πόρτα ακριβώς τη σύγκρουση που το κενό ήρθε να σβήσει.
  const insideGrid =
    frame.u >= 0 && frame.u <= layout.widthMm && frame.v >= 0 && frame.v <= layout.heightMm;
  if (!insideGrid) return null;

  // Το **περίγραμμα** πριν το **σώμα**: η ζώνη του περιγράμματος ζει μέσα στο πλέγμα, οπότε
  // ένα `cell-select` που απαντούσε πρώτο θα την κατάπινε ολόκληρη. Ίδια αρχή «η πιο ειδική
  // ερώτηση πρώτη» με τη σειρά ζώνη→κελί του `tablePointerHitAtWorld`.
  //
  // ⚠️ Η ανοχή είναι **το ίδιο** `bands.gapMm` — δηλαδή η `gripAperturePx` του §27.16 Ε4.
  // Κανένας νέος αριθμός: η οπή σύλληψης του έργου είναι **μία**.
  if (rangeRectMm && isOnTableRangeBorder(rangeRectMm, frame, bands.gapMm)) {
    return intent.copy ? 'range-copy' : 'range-move';
  }

  // 🔴 §36 — **ΕΔΩ ΕΠΕΣΤΡΕΦΕ `null`**, δηλαδή «μένει το σταυρόνημα του σχεδίου». Ο ιδιοκτήτης
  // το άλλαξε ρητά: μέσα σε κελί θέλει τον **σταυρό του φύλλου υπολογισμού**. Δεν είναι
  // καλλωπισμός — είναι η δήλωση «*εδώ διαλέγεις κελιά, δεν σχεδιάζεις*», και είναι ακριβώς
  // η μισή από τις δύο καταστάσεις που ζητήθηκαν (η άλλη είναι το `range-move` από πάνω).
  return 'cell-select';
}
