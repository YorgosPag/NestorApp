/**
 * ADR-833 Φάση 4 — **ΟΙ ΠΡΑΞΕΙΣ ΤΩΝ ΦΥΛΛΩΝ**, ως καθαροί σχεδιαστές: προσθήκη, διαγραφή,
 * μετονομασία, αναδιάταξη — και η πολυφυλλική εισαγωγή που καταλήγει στις ίδιες δύο πράξεις.
 *
 * Καμία παρενέργεια, καμία ανάγνωση κατάστασης εφαρμογής: μπαίνει οντότητα + στόχος, βγαίνει
 * **ένα** σχέδιο. Ποιος το εκτελεί είναι δουλειά του καλούντος — και είναι **πάντα** εντολή
 * (`bim/table/table-worksheet-command.ts`), ποτέ ο γραφέας χωρίς ιστορικό.
 *
 * ## 🔴 ΓΙΑΤΙ ΕΝΤΟΛΗ, ΕΝΩ Η ΑΛΛΑΓΗ ΚΑΡΤΕΛΑΣ ΔΕΝ ΕΙΝΑΙ
 * Η Φάση 3 έκρινε ρητά ότι η **ενεργοποίηση** καρτέλας δεν είναι βήμα undo (Excel parity):
 * αλλάζει **ποιο** βλέπεις, όχι **τι** υπάρχει. Οι τέσσερις πράξεις εδώ είναι το αντίθετο —
 * μια διαγραμμένη καρτέλα παίρνει μαζί της κελιά, τύπους, δεσμό και μνήμη δρομέα. Κάθε μία
 * είναι `UpdateEntityCommand`, με τα υπάρχοντα πρότυπα του `table-cell-edit-session.ts`.
 *
 * ## 🔴 Η ΕΓΓΥΗΣΗ ΤΑΥΤΟΤΗΤΑΣ ΤΗΡΕΙΤΑΙ ΚΑΙ ΕΔΩ — `null` ΣΗΜΑΙΝΕΙ «ΤΙΠΟΤΑ»
 * Κάθε σχεδιαστής επιστρέφει `null` όταν η πράξη δεν αλλάζει τίποτα ή δεν επιτρέπεται
 * (άγνωστος στόχος, μοναδικό φύλλο, μετονομασία στο ίδιο όνομα, μετακίνηση στην ίδια θέση).
 * Είναι ο **ίδιος** φύλακας no-op που κρατά όλο το σύστημα πινάκων: «διάλεξα αυτό που είχα
 * ήδη» δεν γεννά βήμα αναίρεσης, και ο `Ctrl+Z` δεν «γεμίζει» με το τίποτα.
 *
 * ## 🔴 ΤΡΕΙΣ ΑΠΟΦΑΣΕΙΣ ΠΟΥ ΔΕΝ ΠΡΟΚΥΠΤΟΥΝ ΑΠΟ ΤΟΝ ΚΩΔΙΚΑ
 *
 * ### 1. Το νέο φύλλο μπαίνει **ΣΤΟ ΤΕΛΟΣ** — μία σημασιολογία, μία θέση
 * Το Excel έχει **δύο** εισαγωγές που δεν συμφωνούν: το ⊕ βάζει το νέο **δεξιά του ενεργού**,
 * ενώ το `Shift+F11` και το «Εισαγωγή…» του δεξιού κλικ το βάζουν **αριστερά** του. Δύο
 * χειρονομίες, δύο απαντήσεις στο «πού πάει το νέο φύλλο». Τα Google Sheets έχουν **μία**:
 * πάντα στο τέλος.
 *
 * Ακολουθούμε τη **μία** — και όχι για γούστο. Το προεπιλεγμένο όνομα είναι **συνάρτηση της
 * θέσης** (§3 του `types/table-worksheet.ts`), άρα μια εισαγωγή **στη μέση** μετονομάζει
 * σιωπηλά κάθε ανώνυμο φύλλο μετά από αυτήν. Στο τέλος δεν μετονομάζεται **κανένα**: η πιο
 * συχνή πράξη όλων γίνεται η μόνη που δεν αγγίζει τίποτα άλλο. Και η γεωμετρία της λωρίδας το
 * είχε ήδη γράψει ως δεδομένο («*τα φύλλα γεννιούνται προς τα δεξιά*»), χτίζοντας πάνω του το
 * παράθυρο υπερχείλισης.
 *
 * ### 2. Ο διάδοχος του διαγραμμένου ενεργού είναι το **δεξιά**, αλλιώς το αριστερά
 * Excel parity, και η επιλογή είναι **ρητή** επίτηδες. Το `activeWorksheet()` πέφτει
 * **σιωπηλά** στο πρώτο φύλλο όταν το `activeWorksheetId` δεν δείχνει πουθενά — ρητή ανοχή
 * για μπαγιάτικη **ανάγνωση**. Αν ο σχεδιαστής της διαγραφής άφηνε το `activeWorksheetId` να
 * δείχνει στο σβησμένο, η οθόνη **δεν θα έσκαγε**: θα έδειχνε το **πρώτο** φύλλο. Σφάλμα
 * **τιμής**, χωρίς εξαίρεση και χωρίς ίχνος — η κατηγορία που κυνήγησε ολόκληρη η Φάση 2.
 *
 * ### 3. Κενή μετονομασία **ΣΒΗΝΕΙ** το όνομα — δεν απορρίπτεται
 * Το Excel απορρίπτει το κενό όνομα με διάλογο σφάλματος, γιατί εκεί το όνομα είναι **πάντα**
 * αποθηκευμένο δεδομένο: δεν υπάρχει κατάσταση «χωρίς όνομα» να επιστρέψεις. Εμείς την έχουμε,
 * και είναι η **προεπιλογή που ακολουθεί τη ζωντανή γλώσσα** (§3 του `types/table-worksheet.ts`).
 *
 * Άρα το κενό δεν είναι σφάλμα — είναι η **μόνη** διαθέσιμη διατύπωση του «πάρε πίσω το όνομα
 * που έδωσα». Χωρίς αυτήν, η πρώτη μετονομασία θα **πάγωνε** τη γλώσσα του φύλλου για πάντα:
 * ακριβώς ο παραβάτης που το §5.2 απέρριψε για να μείνει το `name` προαιρετικό.
 *
 * ⚠️ Ο έλεγχος γίνεται στο **κενό μετά από trim**, η **ίδια** έκφραση με το
 * `worksheetDisplayName` («όνομα από κενά είναι καρτέλα χωρίς ετικέτα»). Δύο διαφορετικά
 * κατώφλια θα έδιναν φύλλο που το μοντέλο θεωρεί ονομασμένο και η οθόνη ανώνυμο.
 *
 * ## ✅ ΤΙ ΕΡΧΕΤΑΙ ΔΩΡΕΑΝ — και γι' αυτό δεν γράφεται εδώ ούτε μία γραμμή
 * - **Τύποι**: είναι σήμερα **ανά φύλλο** (το `sheetId` του `TableFormulaCellRef` είναι Φάση 7),
 *   άρα η διαγραφή φύλλου παίρνει μαζί της τους τύπους του και **δεν ορφανεύει τίποτα**. Καμία
 *   σημασιολογία `#REF!` δεν χρειάζεται.
 * - **Η μνήμη δρομέα** ταξιδεύει πάνω στο αντικείμενο του φύλλου ⇒ η αναδιάταξη τη σέρνει μαζί
 *   και η διαγραφή τη σβήνει μαζί με το φύλλο.
 * - **Το παράθυρο υπερχείλισης** της λωρίδας είναι **παράγωγο** του ενεργού δείκτη ⇒ ακολουθεί
 *   κάθε πράξη μόνο του.
 *
 * ## ⚠️ ΚΑΝΕΝΑ ΟΡΙΟ ΠΛΗΘΟΥΣ ΦΥΛΛΩΝ — δηλωμένο, όχι ξεχασμένο
 * Ο δεσμευτικός περιορισμός δεν είναι το **πλήθος φύλλων** αλλά το μέγεθος του **εγγράφου**
 * (Firestore: σκληρό όριο 1 MiB), και αυτό είναι **ένας** προϋπολογισμός για γραμμές × στήλες ×
 * φύλλα μαζί. Το ADR-833 §5.4 τον αναθέτει ρητά στη Φάση 5, με **μέτρηση πρώτα**. Ένας αριθμός
 * εδώ θα ήταν όριο που κανείς δεν μέτρησε — ακριβώς αυτό που το ίδιο ADR απαγορεύει.
 *
 * @module subapps/dxf-viewer/bim/table/table-worksheet-ops
 * @see bim/table/table-worksheet-write.ts — το μπάλωμα οντότητας (και ο καθαρισμός παλιάς μορφής)
 * @see bim/table/table-worksheet-activate.ts — η αδελφή πράξη που **δεν** είναι βήμα undo
 * @see bim/table/table-worksheet-command.ts — ο ΕΝΑΣ εκτελεστής αυτών των σχεδίων
 * @see docs/centralized-systems/reference/adrs/ADR-833-table-xlsx-import-and-worksheets.md §5.4
 */

