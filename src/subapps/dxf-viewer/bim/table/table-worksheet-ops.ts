/**
 * Το πρόθεμα του χώρου ονομάτων των φύλλων — **το ίδιο** που κουβαλά ήδη το
 * `FIRST_TABLE_WORKSHEET_ID` (`ws0`). Ζει εδώ, δίπλα στον μοναδικό γεννήτορα: δύο σπίτια θα
 * ήταν δύο ευκαιρίες να γεννηθεί `ws1` σε βιβλίο που έχει ήδη `ws1`.
 */
const WORKSHEET_ID_PREFIX = 'ws';

/**
 * Ό,τι παράγει μια πράξη φύλλου: **ένας** πίνακας φύλλων, και προαιρετικά το νέο ενεργό μαζί
 * με τη θέση όπου προσγειώνεται ο δρομέας.
 *
 * 🔑 **Τα τρία ταξιδεύουν μαζί επειδή απαγορεύεται να γραφτούν χωριστά** — το ίδιο ακριβώς
 * επιχείρημα με το ζεύγος `{model, binding}` του `buildTableBindingRefreshCommand` και με το
 * `TableWorksheetActivation` της Φάσης 3: δύο εντολές θα σήμαιναν ότι ένα `Ctrl+Z` επαναφέρει
 * το φύλλο αλλά αφήνει το ενεργό σε **ανύπαρκτη** ταυτότητα.
 */
export interface TableWorksheetPlan {
  readonly worksheets: readonly TableWorksheet[];
  /** Απόν ⇒ το ενεργό φύλλο **δεν** αλλάζει (μετονομασία, αναδιάταξη, διαγραφή ανενεργού). */
  readonly activeWorksheetId?: TableWorksheetId;
  /**
   * Πού προσγειώνεται ο δρομέας στο **νέο** ενεργό φύλλο· `null`/απόν ⇒ **μην** δημιουργήσεις
   * δρομέα. Ίδια σύμβαση —και ίδιος λόγος— με το `TableWorksheetActivation.restoreCursor`.
   */
  readonly restoreCursor?: TableCursorPosition | null;
  /**
   * 🔴 ADR-833 Φ5Β — πόσα φύλλα **δεν χώρεσαν** στο μερίδιο του πίνακα και κόπηκαν.
   *
   * Απόν/`0` ⇒ χώρεσαν όλα. Ταξιδεύει **μέσα στο σχέδιο** και δεν συνάγεται με αφαίρεση από
   * τον καλούντα: ο ίδιος κανόνας με το `TablePasteResult` — ό,τι χάθηκε το λέει εκείνος που
   * το έκοψε, γιατί μόνο αυτός ξέρει **γιατί**. Και δεν είναι θεωρητικό: μέχρι τη Φάση 5Β η
   * προσθήκη φύλλων ήταν η **μόνη αφύλαχτη πόρτα** — κάθε φύλλο ελεγχόταν μόνο του και
   * κανείς δεν ρωτούσε το άθροισμα, οπότε ένα βιβλίο 12 φύλλων έμπαινε με μία εντολή.
   */
  readonly droppedWorksheets?: number;
}

/**
 * Ένα φύλλο **πριν** αποκτήσει ταυτότητα — η μορφή που παραδίδει η εισαγωγή `.xlsx`.
 *
 * Χωριστός τύπος από το {@link TableWorksheet} επίτηδες: η ταυτότητα δεν είναι κάτι που
 * επιλέγει ο εισαγωγέας, είναι κάτι που **παράγεται** απέναντι στο υπάρχον βιβλίο. Ένα
 * `TableWorksheet` με «προσωρινό» id θα ήταν πρόσκληση να διαρρεύσει ένα `ws0` μέσα σε βιβλίο
 * που έχει ήδη `ws0`.
 */
export interface TableWorksheetDraft {
  readonly name?: string;
  readonly model: PersistedTableModel;
}

/** Η επόμενη ελεύθερη ταυτότητα φύλλου, απέναντι στα **ήδη υπάρχοντα**. */
function nextWorksheetId(worksheets: readonly TableWorksheet[]): TableWorksheetId {
  return tableWorksheetId(nextPrefixedId(worksheets.map((sheet) => sheet.id), WORKSHEET_ID_PREFIX));
}

/**
 * Προσχέδια → φύλλα με **φρέσκες, μη συγκρουόμενες** ταυτότητες.
 *
 * ⚠️ Το `seen` μεγαλώνει **μέσα** στον βρόχο και αυτό είναι το όλο θέμα: χωρίς αυτό, δώδεκα
 * φύλλα ενός βιβλίου θα έπαιρναν **δώδεκα φορές την ίδια** επόμενη ελεύθερη ταυτότητα, γιατί
 * ο γεννήτορας ρωτά πάντα το ίδιο σύνολο. Ο αραιός χάρτης κελιών δείχνει σε ταυτότητες — και
 * δώδεκα φύλλα με το ίδιο id είναι **ένα** φύλλο που το βλέπεις δώδεκα φορές.
 *
 * 🔑 **Το όνομα του Excel επιβιώνει αυτούσιο**, ακόμη κι αν συγκρούεται με υπάρχον. Το Excel
 * θα πρόσθετε `(2)` — υποχρεωμένο, γιατί εκεί οι τύποι δείχνουν σε φύλλα **κατά όνομα**.
 * Εμείς δείχνουμε **κατά ταυτότητα** (ADR-833 §5.4), άρα δύο φύλλα με το ίδιο όνομα δεν
 * σπάνε τίποτα — ενώ ένα σιωπηλό `(2)` θα ήταν **αλλοίωση δεδομένου χρήστη**, που το §5.2
 * απαγορεύει ονομαστικά. Το Excel λύνει δικό του πρόβλημα· εμείς δεν το έχουμε.
 */
function withFreshIds(
  existing: readonly TableWorksheet[],
  drafts: readonly TableWorksheetDraft[],
): readonly TableWorksheet[] {
  const seen = [...existing];
  const created: TableWorksheet[] = [];
  for (const draft of drafts) {
    const id = nextWorksheetId(seen);
    // Το `name` μπαίνει **μόνο όταν υπάρχει**: ένα `name: undefined` θα ήταν κλειδί με τιμή
    // `undefined` σε κάθε φύλλο — ο κίνδυνος που αποφεύγει ρητά το `pickTableRenderFields`
    // («ποτέ ως κλειδιά με τιμή `undefined` → Firestore-safe»).
    const sheet: TableWorksheet = draft.name
      ? { id, name: draft.name, model: draft.model }
      : { id, model: draft.model };
    seen.push(sheet);
    created.push(sheet);
  }
  return created;
}

/**
 * Τα φύλλα ενός **ολοκαίνουργιου** πίνακα, από τα φύλλα ενός βιβλίου.
 *
 * Χρησιμοποιείται όπου δεν υπάρχει βιβλίο να συγκρουστεί (νέα οντότητα, ή αντικατάσταση που
 * σβήνει τα πάντα), οπότε οι ταυτότητες ξεκινούν ντετερμινιστικά από το `ws0` — δες
 * `FIRST_TABLE_WORKSHEET_ID` για το γιατί ο ντετερμινισμός δεν είναι λεπτομέρεια.
 */
export function buildWorksheets(drafts: readonly TableWorksheetDraft[]): readonly TableWorksheet[] {
  return withFreshIds([], drafts);
}

/**
 * **ΠΡΟΣΘΗΚΗ**: ένα νέο, κενό φύλλο στο **τέλος** — και γίνεται αμέσως το ενεργό.
 *
 * Το «γίνεται ενεργό» δεν είναι ευγένεια: ο χρήστης που πάτησε «νέο φύλλο» θέλει να **γράψει**
 * σε αυτό. Excel, Sheets και Numbers συμφωνούν — και το κόστος του αντίθετου είναι ότι η μόνη
 * ορατή συνέπεια της πράξης θα ήταν μια καρτέλα παραπάνω, ίσως **έξω** από το παράθυρο
 * υπερχείλισης, δηλαδή μια πράξη που μοιάζει να μην έκανε τίποτα.
 *
 * ⚠️ **`restoreCursor: null`.** Η αλλαγή ενεργού φύλλου δεν είναι είσοδος σε λειτουργία
 * πίνακα — εκείνη ανοίγει με διπλό κλικ ή `Enter`/`F2`, και μόνο. Ίδια σύμβαση με το
 * `planWorksheetActivation`, όπου το `null` σημαίνει ρητά «μην δημιουργήσεις δρομέα».
 *
 * @param model Το (κενό) μοντέλο του νέου φύλλου. Έρχεται ως **όρισμα** ώστε ο σχεδιαστής να
 *   μένει δοκιμάσιμος με οποιοδήποτε πλέγμα· ο κανονικός καλών περνά το
 *   {@link newWorksheetModel}, που απαντά «πώς μοιάζει ένα νεογέννητο φύλλο **αυτού** του
 *   πίνακα».
 */
export function planWorksheetAdd(
  entity: TableEntity,
  model: PersistedTableModel,
): TableWorksheetPlan | null {
  const worksheets = resolveWorksheets(entity);
  const [created] = withFreshIds(worksheets, [{ model }]);
  const next = [...worksheets, created];

  // 🔴 ADR-833 Φ5Β — **ΑΡΝΗΣΗ, όχι κόψιμο**, και η ασυμμετρία με την εισαγωγή είναι σκόπιμη:
  // εδώ δεν υπάρχει τίποτα να σωθεί. Ένα κενό φύλλο είναι πράξη «όλα ή τίποτα» — μισό φύλλο
  // δεν υπάρχει — ενώ ένα βιβλίο 12 φύλλων κουβαλά δουλειά που αξίζει να μπει μερικώς.
  // Είναι η σημασιολογία των Google Sheets («this action **would increase** the number of
  // cells above the limit»): η απάντηση δίνεται πάνω στο **προβλεπόμενο** βιβλίο, πριν
  // γραφτεί οτιδήποτε.
  //
  // ⚠️ `null` σημαίνει «καμία εντολή», όπως ακριβώς και στους αδελφούς σχεδιαστές
  // (`planWorksheetDelete`, `planWorksheetMove`). Ο **καλών** είναι υπεύθυνος να το πει στον
  // άνθρωπο — δες `useTableWorksheetAdd`: μια σιωπηλά αδρανής πράξη θα ήταν ακριβώς η
  // «σιωπηλή απώλεια» που το §5.6.5 απαγόρευσε, με άλλο πρόσωπο.
  if (fitWorksheetsToShare(next).droppedWorksheets > 0) return null;

  return {
    worksheets: next,
    activeWorksheetId: created.id,
    restoreCursor: null,
  };
}

/**
 * 🔴 **ΠΩΣ ΜΟΙΑΖΕΙ ΕΝΑ ΝΕΟΓΕΝΝΗΤΟ ΦΥΛΛΟ ΑΥΤΟΥ ΤΟΥ ΠΙΝΑΚΑ**: κενό πλέγμα, με τις **ίδιες
 * στήλες** — σε πλήθος και σε διαστασιολόγηση — με το φύλλο που το γέννησε.
 *
 * ## Γιατί δεν είναι απλώς `buildTableModel({})`
 * Το πλάτος του πίνακα **δεν** είναι ιδιότητα της οντότητας: **παράγεται** από τις στήλες του
 * **ενεργού** φύλλου (`computeTableEntityGeometryLive`). Άρα ένα νέο φύλλο με προεπιλεγμένες
 * στήλες θα άλλαζε το **πλάτος του χαρτιού** τη στιγμή που πατιέται το ⊕ — ο πίνακας θα
 * «πηδούσε» μπροστά στα μάτια του χρήστη, και μαζί του η λωρίδα καρτελών που έχει το ίδιο
 * πλάτος. Δηλαδή η πράξη «πρόσθεσε φύλλο» θα είχε ορατή παρενέργεια «άλλαξε μέγεθος ο πίνακας».
 *
 * 🔑 Αντιγράφεται το `sizing` **κατά θέση**, όχι ολόκληρη η στήλη: οι **ταυτότητες** μένουν οι
 * φρέσκες του εργοστασιάρχη, γιατί σε αυτές δείχνει η **γραμμή τίτλου** (`buildTitleMerge`) του
 * ίδιου μοντέλου. Αντιγραφή ταυτοτήτων από πίνακα που έχει δεχθεί εισαγωγές/διαγραφές
 * (`c0, c3, c7`) θα άφηνε συγχώνευση να δείχνει σε στήλες που δεν υπάρχουν στο νέο φύλλο —
 * σιωπηλά, γιατί το `buildMergeIndex` παραλείπει τις άγνωστες αναφορές αντί να σκάσει.
 *
 * ⚠️ Τα **κελιά** δεν αντιγράφονται ποτέ: «νέο φύλλο» σημαίνει κενό. Αντιγραφή φύλλου είναι
 * **άλλη πράξη** — δεν υπάρχει στη Φάση 4, και δεν γεννιέται από την πίσω πόρτα.
 */
export function newWorksheetModel(entity: TableEntity): PersistedTableModel {
  const source = activeTableModel(entity);
  const fresh = buildTableModel({ columnCount: source.columns.length });
  return {
    ...fresh,
    columns: fresh.columns.map((column, index) => ({ ...column, sizing: source.columns[index].sizing })),
  };
}

/**
 * **ΔΙΑΓΡΑΦΗ**: το φύλλο φεύγει — και μαζί του κελιά, τύποι, δεσμός και μνήμη δρομέα.
 *
 * `null` σε δύο περιπτώσεις, και η δεύτερη είναι η σημαντική:
 *  1. **άγνωστος στόχος** — πράξη που προσγειώνεται αλλού από εκεί που δείχτηκε είναι
 *     χειρότερη από πράξη που δεν έγινε (ίδιος κανόνας με το `planWorksheetActivation`)·
 *  2. 🔴 **μοναδικό φύλλο** — ο φραγμός ζει στη **γεωμετρία της πράξης**, όχι στο μενού. Το
 *     `resolveWorksheets` **δεν επιστρέφει ποτέ κενό**: σε οντότητα χωρίς φύλλα κάνει
 *     `logger.error` και δίνει εφεδρικό κενό φύλλο. Δηλαδή ένας πίνακας με μηδέν φύλλα είναι
 *     **χαλασμένη οντότητα** κατά την ίδια τη σύμβαση του αναγνώστη — και μια πράξη που
 *     παράγει χαλασμένη οντότητα δεν επιτρέπεται να είναι εκφράσιμη. Το μενού γκριζάρει
 *     **επιπλέον** (belt-and-suspenders, N.7.2 #4), ποτέ **αντί**.
 *
 * @param cursor Ο δρομέας **αυτού** του πίνακα και του **ενεργού** του φύλλου, ή `null`.
 *   Έρχεται ως όρισμα με τη σύμβαση που κρατά καθαρό ολόκληρο το `bim/`: εδώ απαντιέται «τι
 *   πρέπει να γίνει», ποτέ «τι κατάσταση έχει η εφαρμογή».
 */
export function planWorksheetDelete(
  entity: TableEntity,
  targetId: TableWorksheetId,
  cursor: TableCursorPosition | null,
): TableWorksheetPlan | null {
  const worksheets = resolveWorksheets(entity);
  if (worksheets.length < 2) return null;
  const index = worksheets.findIndex((sheet) => sheet.id === targetId);
  if (index < 0) return null;

  // 🔴 ADR-833 Φάση 7 — **ο επαναϋπολογισμός μπαίνει ΜΕΣΑ στην πράξη**, με τον ίδιο λόγο που ο
  // ADR-764 έβαλε εκεί τον μετασχηματισμό: μία εντολή, **ένα** `Ctrl+Z`. Ένα `=Φύλλο2!A1` σε
  // άλλο φύλλο έχει από τώρα `#REF!` και στη **γραμμή τύπων** και στην **αποθηκευμένη τιμή** —
  // χωρίς αυτό, η δεύτερη θα έμενε ο παλιός αριθμός και θα ταξίδευε σε DXF και σε `.xlsx`.
  const remaining = worksheetsAfterRemoval(
    worksheets.filter((_, at) => at !== index),
    [targetId],
  );
  // Το φύλλο που φεύγει δεν είναι απαραίτητα το ενεργό: δεξί κλικ σε **άλλη** καρτέλα είναι η
  // συνηθισμένη περίπτωση, και τότε δεν αλλάζει τίποτα στο ενεργό.
  if (activeWorksheet(entity).id !== targetId) return { worksheets: remaining };

  // 🔴 Απόφαση 2 της κεφαλίδας: **το δεξιά**, αλλιώς το αριστερά. Μετά την αφαίρεση, «το
  // δεξιά» κάθεται στην **ίδια** θέση `index` — και η θέση αυτή υπάρχει εκτός αν σβήστηκε το
  // τελευταίο φύλλο, οπότε πέφτουμε στο τελευταίο επιζών.
  const successor = remaining[Math.min(index, remaining.length - 1)];
  return {
    worksheets: remaining,
    activeWorksheetId: successor.id,
    // Ίδια σύμβαση με την αλλαγή καρτέλας: ο δρομέας επαναφέρεται **μόνο** αν υπήρχε.
    restoreCursor: cursor ? worksheetLandingCursor(successor) : null,
  };
}

/**
 * **ΜΕΤΟΝΟΜΑΣΙΑ**: ρητό όνομα, ή **επιστροφή στην προεπιλογή** όταν το κείμενο είναι κενό.
 *
 * Δες την Απόφαση 3 της κεφαλίδας για το γιατί το κενό **σβήνει** αντί να απορρίπτεται — και
 * γιατί το Excel δεν μπορεί να κάνει το ίδιο.
 *
 * ⚠️ Το όνομα αποθηκεύεται **trimmed**: τα κενά στις άκρες δεν είναι ορατά στην καρτέλα, οπότε
 * «Κόστη» και «Κόστη » θα φαίνονταν ταυτόσημα ενώ το μοντέλο θα τα θεωρούσε διαφορετικά —
 * δηλαδή ένας φύλακας no-op που **ποτέ** δεν πιάνει.
 */
export function planWorksheetRename(
  entity: TableEntity,
  targetId: TableWorksheetId,
  name: string,
): TableWorksheetPlan | null {
  const worksheets = resolveWorksheets(entity);
  const target = worksheets.find((sheet) => sheet.id === targetId);
  if (!target) return null;

  const trimmed = name.trim();
  // Η **ίδια** έκφραση κενού με το `worksheetDisplayName`: το μοντέλο και η οθόνη δεν
  // επιτρέπεται να διαφωνούν για το τι είναι «ανώνυμο φύλλο».
  const current = target.name?.trim() ?? '';
  if (trimmed === current) return null;

  // Αποδόμηση και όχι `name: undefined`: ίδια σύμβαση παράλειψης με το
  // `worksheetsWithActiveModelAndBinding`, και κρατά **κάθε άλλο** πεδίο του φύλλου (μοντέλο,
  // δεσμό, μνήμη δρομέα) χωρίς χειρόγραφη απαρίθμηση που θα ξεχνούσε το επόμενο.
  const { name: _dropped, ...rest } = target;
  const renamed: TableWorksheet = trimmed ? { ...rest, name: trimmed } : rest;
  return { worksheets: worksheets.map((sheet) => (sheet === target ? renamed : sheet)) };
}

/**
 * **ΑΝΑΔΙΑΤΑΞΗ**: το φύλλο μετακομίζει στη θέση `toIndex`.
 *
 * 🔴 **Η ΑΝΑΔΙΑΤΑΞΗ ΜΕΤΟΝΟΜΑΖΕΙ ΤΑ ΑΝΩΝΥΜΑ ΦΥΛΛΑ — ΚΑΙ ΑΥΤΟ ΕΙΝΑΙ ΣΩΣΤΟ** (ADR-833 §5.4)
 *
 * Το προεπιλεγμένο όνομα είναι συνάρτηση της **θέσης** (`Φύλλο{index+1}`), άρα μια αναδιάταξη
 * αλλάζει το ορατό όνομα κάθε φύλλου που δεν έχει ρητό `name`. Η Φάση 4 το **επιβεβαιώνει
 * ρητά** — δεν το ανέχεται σιωπηλά:
 *
 * > *«το φύλλο στη δεύτερη θέση» είναι ακριβώς αυτό που το προεπιλεγμένο όνομα υπόσχεται.
 * > Το Excel λέει ψέματα εδώ (κρατά «Φύλλο1» στην τρίτη θέση).*
 *
 * Η **ανατροπή** έχει μετρημένο τίμημα: θα σήμαινε ότι η αναδιάταξη **υλοποιεί** (materialize)
 * τα ονόματα, δηλαδή η πρώτη μετακίνηση παγώνει τη γλώσσα του δημιουργού μέσα στα δεδομένα —
 * ακριβώς ο παραβάτης που το §5.2 απέρριψε για να μείνει το `name` προαιρετικό. Δεν
 * ξαναμπαίνει από την πίσω πόρτα.
 *
 * 🔑 Και η **διαγραφή** κάνει το ίδιο, για τον ίδιο λόγο. Ο χρήστης που θέλει σταθερό όνομα το
 * γράφει — και τότε δεν το αγγίζει καμία πράξη, ποτέ.
 *
 * ⚠️ Δέχεται **απόλυτη θέση** και όχι κατεύθυνση: «αριστερά/δεξιά» είναι δύο ονόματα της ίδιας
 * πράξης, και ένας σχεδιαστής που ξέρει μόνο «±1» δεν μπορεί να εξυπηρετήσει μεταφορά σε
 * αυθαίρετη θέση χωρίς δεύτερο σώμα.
 */
export function planWorksheetMove(
  entity: TableEntity,
  targetId: TableWorksheetId,
  toIndex: number,
): TableWorksheetPlan | null {
  const worksheets = resolveWorksheets(entity);
  const from = worksheets.findIndex((sheet) => sheet.id === targetId);
  if (from < 0) return null;
  // Εκτός ορίων ⇒ **τίποτα**, ποτέ σιωπηλό clamp: ένα «μετακίνηση δεξιά» στο τελευταίο φύλλο
  // που θα κατέληγε στην ίδια θέση είναι πράξη που δεν έγινε, και οφείλει να μη γεννήσει βήμα
  // αναίρεσης. Το μενού το γκριζάρει ήδη — αυτό εδώ είναι το δίχτυ (N.7.2 #4).
  if (toIndex < 0 || toIndex >= worksheets.length || toIndex === from) return null;

  const next = [...worksheets];
  const [moved] = next.splice(from, 1);
  next.splice(toIndex, 0, moved);
  return { worksheets: next };
}

/**
 * **ΠΟΛΥΦΥΛΛΙΚΗ ΕΙΣΑΓΩΓΗ — ΠΡΟΣΘΗΚΗ**: τα φύλλα του βιβλίου μπαίνουν στο **τέλος** αυτού του
 * πίνακα, και το **πρώτο τους** γίνεται το ενεργό.
 *
 * Είναι η σημασιολογία που η Φάση 1 είχε ήδη υποσχεθεί γραπτώς για την «Εισαγωγή αρχείου»
 * (*«νέα φύλλα εργασίας στον ίδιο πίνακα»*) και εξέφραζε προσωρινά ως «νέος πίνακας δίπλα»,
 * επειδή τα φύλλα δεν υπήρχαν ακόμη. **Καμία σιωπηλή απώλεια**: τίποτα υπάρχον δεν αγγίζεται,
 * γι' αυτό και η πράξη δεν ρωτά ποτέ.
 *
 * Το «ενεργό γίνεται το πρώτο εισαγόμενο» είναι ο ίδιος κανόνας με την προσθήκη: ο χρήστης που
 * έφερε δεδομένα θέλει να τα **δει**. Αλλιώς η μόνη ορατή συνέπεια θα ήταν καρτέλες πιθανώς
 * έξω από το παράθυρο υπερχείλισης.
 */
export function planWorksheetsAppend(
  entity: TableEntity,
  drafts: readonly TableWorksheetDraft[],
): TableWorksheetPlan | null {
  if (drafts.length === 0) return null;
  const worksheets = resolveWorksheets(entity);
  const created = withFreshIds(worksheets, drafts);

  // 🔴 ADR-833 Φ5Β — **ΚΟΨΙΜΟ, όχι άρνηση** (η αντίστροφη επιλογή από το `planWorksheetAdd`,
  // και για τον αντίστροφο λόγο): εδώ υπάρχει δουλειά του χρήστη μέσα στο αρχείο, και μια
  // ολική άρνηση θα την πετούσε όλη επειδή δεν χώρεσε το τελευταίο φύλλο. Το ADR-833 έχει
  // ήδη αυτό το λεξιλόγιο για την εισαγωγή (`tableXlsx.clipped`): **κόψε και πες το με
  // αριθμό**.
  const fitted = fitWorksheetsToShare([...worksheets, ...created]);

  // Τα υπάρχοντα φύλλα **δεν** κόβονται ποτέ: αν δεν χωρά ούτε ένα εισαγόμενο, το σχέδιο
  // παράγει το ίδιο βιβλίο και ο κατασκευαστής εντολής το κρίνει no-op. Το «τίποτα δεν
  // μπήκε» το λέει το `droppedWorksheets`, που φτάνει στον καλούντα **ακόμη κι όταν δεν
  // υπάρχει εντολή** — αλλιώς η αποτυχία θα ήταν αόρατη.
  //
  // 🔴 **Ο ΑΡΙΘΜΟΣ ΕΙΝΑΙ ΤΩΝ ΕΙΣΑΓΟΜΕΝΩΝ, ΟΧΙ ΤΟΥ ΚΟΨΙΜΑΤΟΣ** — και το βρήκε μετάλλαξη.
  // Το `fitWorksheetsToShare` κόβει από το τέλος μέχρι να χωρέσει· αν το **υπάρχον** βιβλίο
  // ξεπερνά ήδη το μερίδιο (πίνακας φτιαγμένος με τα παλιά όρια), κόβει και δικά του φύλλα
  // και το `droppedWorksheets` του γίνεται **6** ενώ ο χρήστης πρόσθεσε **ένα**. Το μήνυμα
  // θα κατηγορούσε την πράξη για απώλεια που δεν προκάλεσε.
  const accepted = Math.max(0, fitted.worksheets.length - worksheets.length);
  return {
    worksheets: accepted > 0 ? fitted.worksheets : worksheets,
    ...(accepted > 0 && { activeWorksheetId: created[0].id }),
    restoreCursor: null,
    droppedWorksheets: drafts.length - accepted,
  };
}

/**
 * **ΠΟΛΥΦΥΛΛΙΚΗ ΕΙΣΑΓΩΓΗ — ΑΝΤΙΚΑΤΑΣΤΑΣΗ**: ο πίνακας **γίνεται** το βιβλίο.
 *
 * ## 🔴 Αντικαθίστανται ΟΛΑ τα φύλλα, όχι μόνο το ενεργό
 * Μέχρι τη Φάση 4 η «Αντικατάσταση περιεχομένου» περνούσε από το `buildTableModelCommand`, που
 * γράφει το μοντέλο του **ενεργού** φύλλου. Με ένα φύλλο ήταν το ίδιο πράγμα· με βιβλίο δεν
 * είναι — και ο διάλογος υπόσχεται ήδη το σωστό: *«Το «{fileName}» θα γεμίσει τον πίνακα. Τα
 * δεδομένα που έχει τώρα θα αντικατασταθούν.»*
 *
 * ⚠️ **Συνέπεια που δηλώνεται, δεν κρύβεται**: φεύγουν μαζί και οι **δεσμοί** των φύλλων
 * (ADR-767/769). Είναι το σωστό — ένας πίνακας που έγινε το αρχείο δεν είναι πια δεμένος με
 * πηγή που δεν τον αφορά — αλλά είναι απώλεια, και ο χρήστης την έχει ήδη εγκρίνει ρητά μέσα
 * από τον διάλογο, με το `Ctrl+Z` γραμμένο δίπλα.
 *
 * Οι ταυτότητες ξεκινούν από το `ws0`: **κανένα** παλιό φύλλο δεν επιβιώνει, άρα δεν υπάρχει
 * τίποτα να συγκρουστεί — και ο ντετερμινισμός κρατά το JSON σταθερό για την ίδια εισαγωγή.
 */
export function planWorksheetsReplace(
  entity: TableEntity,
  drafts: readonly TableWorksheetDraft[],
): TableWorksheetPlan | null {
  if (drafts.length === 0) return null;
  // Ίδιο κόψιμο με την προσθήκη, και **πρέπει** να είναι το ίδιο: η «Αντικατάσταση» δεν είναι
  // άλλη ερώτηση χωρητικότητας, είναι η ίδια ερώτηση σε άδειο βιβλίο.
  const fitted = fitWorksheetsToShare(buildWorksheets(drafts));

  // 🔴 **ΕΛΑΤΤΩΜΑ ΠΟΥ ΒΡΗΚΕ ΜΕΤΑΛΛΑΞΗ (M42, Φ5Β).** Εδώ υπήρχε `if (…length === 0) return
  // null`. Το `null` όμως σημαίνει ταυτόχρονα «καμία εντολή» **και** «κανένα
  // `droppedWorksheets` να πει ο καλών» — δηλαδή ένα βιβλίο ενός φύλλου που δεν χωρά στο
  // μερίδιο απέτυχε **σιωπηλά**: ο χρήστης πατούσε «Αντικατάσταση περιεχομένου» και δεν
  // γινόταν απολύτως τίποτα, χωρίς μήνυμα. Είναι κατά λέξη η «σιωπηλή απώλεια» που το
  // §5.6.5 απαγόρευσε, μπαίνοντας από την πίσω πόρτα ενός κωδικού επιστροφής.
  //
  // Τώρα κρατά τα **υπάρχοντα** φύλλα (ο κατασκευαστής εντολής θα κρίνει σωστά no-op) και
  // αφήνει τον αριθμό να ταξιδέψει — ίδια δομή με το `planWorksheetsAppend`, και για τον
  // ίδιο λόγο.
  const accepted = fitted.worksheets.length;
  return {
    worksheets: accepted > 0 ? fitted.worksheets : resolveWorksheets(entity),
    ...(accepted > 0 && { activeWorksheetId: fitted.worksheets[0].id }),
    restoreCursor: null,
    droppedWorksheets: fitted.droppedWorksheets,
  };
}
