/**
 * 🔴 ADR-754 **Γ2** — **ο ΕΝΑΣ ιδιοκτήτης του `$`**: πού επιτρέπεται να κάθεται ένας
 * δείκτης απολυτότητας, τι σημαίνει, και πώς ξαναγράφεται. Καθαρό module: μηδέν React,
 * μηδέν DOM, μηδέν canvas, μηδέν store.
 *
 * ## Γιατί υπάρχει χωριστό αρχείο — και γιατί ΟΧΙ μέσα στο `table-cell-reference.ts`
 * Ο πειρασμός είναι να δεχτεί το `parseTableCellReference` το `$` κατευθείαν: μία γραμμή στο
 * regex του. Είναι λάθος, και ο λόγος είναι ο **κατάλογος των καταναλωτών του**. Εκείνο είναι
 * ο δηλωμένος **μοναδικός μεταφραστής** `A1` ⇄ ταυτότητες (ADR-739 §9.2) και τον ρωτούν η
 * γραμμή τύπων, η πλοήγηση, η επικόλληση και οι ζώνες του δείκτη — **κανένας** από αυτούς δεν
 * έχει έννοια απολυτότητας. Ένα `$` που περνούσε από εκεί θα σήμαινε ότι η πληκτρολογημένη
 * `$B$3` στη γραμμή τύπων **μετακινεί τον δρομέα**, δηλαδή ότι ένα σύμβολο των τύπων απέκτησε
 * σιωπηλά νόημα στην πλοήγηση.
 *
 * Άρα ο διαχωρισμός είναι: **εδώ** αποκολλάται ο δείκτης, **εκεί** λύνεται η διεύθυνση. Τρεις
 * καταναλωτές ρωτούν ήδη το ίδιο πράγμα (ο αναλυτής, η κατάσταση υπόδειξης, οι χρωματιστές
 * αναφορές) και ένα αντίγραφο σε καθέναν θα ήταν τρεις ορισμοί του «πού μπαίνει το δολάριο».
 *
 * ## 🔴 ΔΥΟ σημαίες, όχι μία — και γι' αυτό ΤΕΣΣΕΡΙΣ καταστάσεις
 * Το `$` δεν είναι διακόπτης «απόλυτη/σχετική»: το Excel έχει `A1`, `$A$1`, `A$1`, `$A1`.
 * Οι **μεικτές** μορφές είναι ο λόγος που υπάρχει το `F4` — ένας τύπος που συμπληρώνεται
 * δεξιά θέλει συχνά **κλειδωμένη στήλη και ελεύθερη γραμμή** (π.χ. ένα ποσοστό που ζει σε
 * μία στήλη). Μία σημαία θα έκανε τη μισή χρήση αδύνατη **να εκφραστεί**.
 *
 * ## Πού μετρά — και πού είναι σιωπηλό
 * Ο πίνακάς μας δένει τις αναφορές σε **ταυτότητες** (`rowId`/`colId`), οπότε η **μετακίνηση**
 * κελιού και η **εισαγωγή** γραμμής δεν κοιτούν καθόλου το `$`: η αναφορά ακολουθεί ή μένει
 * επειδή έτσι λέει η ταυτότητα, ακριβώς όπως το Excel (`table-formula-remap.ts`). Το `$`
 * έχει **ένα** σημείο όπου αλλάζει αποτέλεσμα: την **αντιγραφή** τύπου σε άλλο κελί
 * (`table-formula-offset.ts`) — δηλαδή τη λαβή συμπλήρωσης. Γι' αυτό τα δύο γράφτηκαν μαζί:
 * χωρίς το `$`, η συμπλήρωση θα μετατόπιζε **πάντα**, και το `$` μετά θα ήταν αλλαγή
 * σημασίας σε κώδικα που ήδη τρέχει.
 *
 * @module subapps/dxf-viewer/bim/table/formula/table-formula-absolute
 * @see ../table-cell-reference.ts — η ΜΙΑ μετάφραση διεύθυνσης· δεν ξέρει τίποτα από `$`
 * @see table-formula-offset.ts — το ΜΟΝΟ σημείο όπου το `$` αλλάζει αποτέλεσμα
 * @see docs/centralized-systems/reference/adrs/ADR-754-table-point-mode.md §12
 */

import type { TableModel } from '../../../types/table';
import type { TableFormulaCellRef } from '../../../types/table-formula';
import { parseTableCellReference } from '../table-cell-reference';

/** Ο δείκτης απολυτότητας — η σύμβαση κάθε φύλλου υπολογισμού και του `ACAD_TABLE`. */
export const ABSOLUTE_MARKER = '$';

/**
 * Ποιος άξονας είναι **κλειδωμένος** σε μια αναφορά.
 *
 * Και τα δύο πεδία είναι **προαιρετικά και μπαίνουν μόνο όταν είναι `true`**. Δεν είναι
 * στυλ: το `TableFormulaCellRef` ταξιδεύει σε `JSON.stringify` (αποθήκευση σκηνής, `deepClone`
 * για undo) και ένα `absoluteRow: false` σε **κάθε** αναφορά κάθε τύπου θα ήταν καθαρό βάρος
 * στο αρχείο, για πληροφορία που η απουσία εκφράζει ήδη.
 */
export interface TableFormulaAbsoluteFlags {
  readonly absoluteRow?: boolean;
  readonly absoluteCol?: boolean;
}

/** Μια αναφορά αποκολλημένη από τους δείκτες της: η σκέτη διεύθυνση, και τι ήταν κλειδωμένο. */
export interface SplitAbsoluteReference {
  /** Η διεύθυνση **χωρίς** `$` — ό,τι καταλαβαίνει ο μεταφραστής (`'A1'`). */
  readonly plain: string;
  /**
   * Τα δύο μέρη χωριστά (`'A'` και `'1'`) — για τον **επεξεργαστή**, που ξαναγράφει τη
   * διεύθυνση με άλλα δολάρια (`F4`) και οφείλει να την ξαναδώσει **αυτούσια**. Επιστρέφονται
   * ως κείμενο και όχι ως αριθμός επίτηδες: ένα `A007` που περνούσε από `parseInt` θα
   * ξαναγραφόταν `A7`, δηλαδή το `F4` θα άλλαζε σιωπηλά ό,τι πληκτρολόγησε ο χρήστης.
   */
  readonly letters: string;
  readonly digits: string;
  readonly absoluteRow: boolean;
  readonly absoluteCol: boolean;
}

/**
 * Οι **μόνες** νόμιμες θέσεις ενός δείκτη: πριν από τα γράμματα (στήλη) και πριν από τα
 * ψηφία (γραμμή).
 *
 * ⚠️ **Ναι, εδώ ξαναγράφεται το σχήμα «γράμματα + ψηφία» που ξέρει και ο μεταφραστής — και
 * είναι συνειδητό.** Η εναλλακτική ήταν να αποκολληθούν τα `$` «όπου κι αν βρίσκονται», που
 * θα δεχόταν το `A1$` ως `$A1`: δηλαδή θα άλλαζε **σιωπηλά τη σημασία** μιας πληκτρολόγησης
 * που δεν είναι αναφορά. Ο δείκτης απολυτότητας **ορίζεται** ως προς τα δύο μέρη της
 * διεύθυνσης· δεν μπορεί να ελεγχθεί χωρίς να ονομαστούν.
 *
 * Ο επιμερισμός των αρμοδιοτήτων μένει όμως ακέραιος: αυτό εδώ απαντά **μόνο** «είναι νόμιμη
 * η θέση του δολαρίου;». Το ποια στήλη είναι η `AA`, αν χωρά στο πλέγμα και αν τα πεζά
 * μετρούν, μένουν **ολόκληρα** στο `parseTableCellReference`. Το ανομολόγητο ρίσκο —να
 * αποκλίνουν τα δύο σχήματα— καρφώνεται με anchor test που περνά κάθε δεκτή διεύθυνση αυτού
 * του regex από τον μεταφραστή.
 */
const ABSOLUTE_REFERENCE = /^(\$?)([A-Za-z]+)(\$?)(\d+)$/u;

/**
 * `'$A$1'` → `{ plain: 'A1', absoluteCol: true, absoluteRow: true }`, ή `null` όταν το κείμενο
 * δεν έχει τη μορφή διεύθυνσης.
 *
 * 🔑 **Το `null` ΔΕΝ σημαίνει «δεν υπάρχει τέτοιο κελί»** — αυτό το ξέρει μόνο το μοντέλο.
 * Σημαίνει «αυτό δεν είναι καν γραμμένο σαν διεύθυνση». Ο καλών περνά μετά το `plain` από τον
 * μεταφραστή, που είναι εκείνος που κοιτά τα όρια του πλέγματος.
 */
export function splitAbsoluteReference(text: string): SplitAbsoluteReference | null {
  const match = ABSOLUTE_REFERENCE.exec(text);
  if (!match) return null;
  return {
    plain: match[2] + match[4],
    letters: match[2],
    digits: match[4],
    absoluteCol: match[1] === ABSOLUTE_MARKER,
    absoluteRow: match[3] === ABSOLUTE_MARKER,
  };
}

/**
 * Η αντίστροφη πράξη: γράμμα + αριθμός + σημαίες → `'$A$1'`. Το ένα σημείο που **γράφει**
 * δολάρια, ώστε ο εκτυπωτής και ο επεξεργαστής να μη μαντεύουν σειρά.
 *
 * Ο αριθμός γραμμής δίνεται ως **κείμενο** ώστε ο επεξεργαστής να μπορεί να ξαναγράψει
 * αυτούσιο ό,τι πληκτρολογήθηκε — δες {@link SplitAbsoluteReference.digits}.
 */
export function formatAbsoluteReference(
  letter: string,
  rowNumber: string,
  flags: TableFormulaAbsoluteFlags,
): string {
  const col = flags.absoluteCol ? ABSOLUTE_MARKER : '';
  const row = flags.absoluteRow ? ABSOLUTE_MARKER : '';
  return `${col}${letter}${row}${rowNumber}`;
}

/**
 * `'A1'` + νέες σημαίες → `'$A$1'`. Η **μία** ξαναγραφή δολαρίων πάνω σε κείμενο, για το `F4`.
 * `null` όταν το κείμενο δεν είναι διεύθυνση.
 */
export function rewriteAbsoluteReference(
  text: string,
  flags: TableFormulaAbsoluteFlags,
): string | null {
  const split = splitAbsoluteReference(text);
  return split === null ? null : formatAbsoluteReference(split.letters, split.digits, flags);
}

/**
 * Οι σημαίες ως αντικείμενο **προς αποθήκευση**: τα `false` παραλείπονται εντελώς.
 *
 * Υπάρχει ως συνάρτηση και όχι ως object literal στον καλούντα γιατί η σύμβαση «μόνο τα
 * `true` γράφονται» πρέπει να ισχύει σε **κάθε** παραγωγό αναφοράς — αλλιώς δύο τύποι με την
 * ίδια σημασία θα σειριοποιούνταν διαφορετικά, και η σύγκριση ταυτότητας του `remapNode` θα
 * έβλεπε αλλαγή εκεί που δεν υπάρχει.
 */
export function absoluteFlags(absoluteRow: boolean, absoluteCol: boolean): TableFormulaAbsoluteFlags {
  return {
    ...(absoluteRow ? { absoluteRow: true } : {}),
    ...(absoluteCol ? { absoluteCol: true } : {}),
  };
}

/**
 * 🔑 **Ο κύκλος του `F4`** — η σειρά είναι **του Excel**, όχι δική μας επιλογή:
 *
 * ```
 *   A1  →  $A$1  →  A$1  →  $A1  →  A1
 * ```
 *
 * Δηλαδή: σχετική → **και τα δύο** κλειδωμένα → μόνο **γραμμή** → μόνο **στήλη** → πίσω.
 *
 * ## Γιατί αντιγράφεται ο κατάλογος του Excel εδώ, ενώ αλλού αντιγράφηκε μόνο ο κανόνας
 * Στο §6 (ζώνες ⇒ `E1:E5` αντί `E:E`) και στο §11.5 (η παλέτα δεν ξεκινά με μπλε) η απόφαση
 * ήταν να δανειστούμε τον **κανόνα** και όχι τον κατάλογο, γιατί το πρότυπο έλυνε **δικό του**
 * πρόβλημα. Εδώ είναι το αντίστροφο: η σειρά **δεν λύνει** κανένα πρόβλημα, είναι καθαρή
 * σύμβαση μυϊκής μνήμης. Ένας μηχανικός που πατά `F4` δύο φορές περιμένει `A$1` επειδή έτσι
 * κάνει εδώ και τριάντα χρόνια· μια «πιο λογική» σειρά θα ήταν απλώς **λάθος** για εκείνον.
 */
export function cycleAbsoluteReference(flags: TableFormulaAbsoluteFlags): TableFormulaAbsoluteFlags {
  const row = flags.absoluteRow === true;
  const col = flags.absoluteCol === true;
  if (!row && !col) return absoluteFlags(true, true);
  if (row && col) return absoluteFlags(true, false);
  if (row) return absoluteFlags(false, true);
  return absoluteFlags(false, false);
}

/**
 * 🔑 **Η ΜΙΑ ανάγνωση μιας γραμμένης αναφοράς**: το κείμενο μιας λεκτικής μονάδας → κόμβος
 * δεμένος σε ταυτότητες, με τις σημαίες του. `null` όταν δεν είναι διεύθυνση ή δείχνει εκτός
 * πλέγματος — οι δύο περιπτώσεις είναι αδιάκριτες για τον καλούντα, και σωστά: και οι δύο
 * σημαίνουν «μη το χειριστείς ως αναφορά».
 *
 * ## Γιατί ζει εδώ, δίπλα στον αποκολλητή
 * Τη ρωτούν **τρεις**: ο αναλυτής (δέσιμο), η κατάσταση υπόδειξης (*«είναι το τελευταίο που
 * έγραψα διεύθυνση;»*) και οι χρωματιστές αναφορές (*«ποια κελιά διαβάζει;»*). Πριν από το
 * `$` ήταν μία γραμμή σε καθέναν (`parseTableCellReference`) και η επανάληψη ήταν αθώα. Με το
 * `$` γίνεται **τρία βήματα** — αποκόλληση, μετάφραση, σημαίες — και τρία αντίγραφά της θα
 * αποκλίνουν στην πρώτη μεικτή μορφή που θα ξεχάσει το ένα (N.18). Ένα από τα τρία θα ήταν
 * αυτό που καταλήγει στους τύπους.
 */
export function resolveWrittenCellRef(
  model: TableModel,
  text: string,
): TableFormulaCellRef | null {
  const split = splitAbsoluteReference(text);
  if (split === null) return null;

  const position = parseTableCellReference(model, split.plain);
  if (position === null) return null;

  return {
    rowId: position.rowId,
    colId: position.colId,
    ...absoluteFlags(split.absoluteRow, split.absoluteCol),
  };
}
