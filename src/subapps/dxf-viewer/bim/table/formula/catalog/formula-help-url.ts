/** Η βάση γνώσης του Office. Ένα σημείο αλλαγής αν ποτέ μετακομίσει. */
const OFFICE_HELP_SEARCH = 'https://support.microsoft.com/en-us/search';

/**
 * Η διεύθυνση τεκμηρίωσης για μια συνάρτηση.
 *
 * Το όνομα κωδικοποιείται (`CEILING.MATH` περιέχει τελεία, άλλες περιέχουν μόνο γράμματα) και
 * συνοδεύεται από τη λέξη `function`, ώστε το `IF` να μη φέρνει τα πάντα.
 */
export function formulaHelpUrl(name: string): string {
  if (name === '') return '';
  return `${OFFICE_HELP_SEARCH}?query=${encodeURIComponent(`Excel ${name} function`)}`;
}
