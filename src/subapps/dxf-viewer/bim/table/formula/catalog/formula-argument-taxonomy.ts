/**
 * ADR-763 §11 — **το λεξιλόγιο ενός ορίσματος**: τι είδος τιμής περιμένει, αν είναι
 * υποχρεωτικό, και αν επαναλαμβάνεται. Καθαρό type module + ένας αναλυτής συμπαγούς γραφής.
 *
 * ## 🔴 Γιατί ΤΡΙΤΟ επίπεδο δεδομένων, και όχι πεδία στο `FormulaCatalogEntry`
 * Ο κατάλογος (`formula-catalog-taxonomy.ts`) απαντά **«πώς τη βρίσκει ο άνθρωπος;»** — μία
 * γραμμή ανά συνάρτηση. Εδώ η ερώτηση είναι **«τι της δίνω;»** και η απάντηση είναι *λίστα*
 * μεταβλητού μήκους ανά συνάρτηση. Χωμένη μέσα στην εγγραφή καταλόγου, θα φόρτωνε 375
 * υπογραφές για να ζωγραφιστεί μια λίστα ονομάτων που δεν τις χρειάζεται καμία.
 *
 * ## 🔑 Η ΓΛΩΣΣΑ ΕΙΝΑΙ ΑΛΛΟΥ — ΚΑΙ ΕΙΝΑΙ ΗΔΗ ΓΡΑΜΜΕΝΗ
 * Τα **ονόματα** των ορισμάτων (`αριθμός1`, `lookup_value`) ζουν στο i18n από τη Φάση 1, σε
 * el **και** en, ως μία συμβολοσειρά ανά συνάρτηση. Αυτό το αρχείο κρατά **μόνο** ό,τι δεν
 * αλλάζει με τη γλώσσα: είδος, υποχρεωτικότητα, επανάληψη. Δεύτερο αντίγραφο των ονομάτων εδώ
 * θα ήταν 450 συμβολοσειρές που αποκλίνουν από τη μετάφραση την πρώτη φορά που κάποιος
 * διορθώσει τη μία (N.18 / CHECK 3.28).
 *
 * Η σύζευξη των δύο επαληθεύεται με test: το πλήθος των ειδών **πρέπει** να ισούται με το
 * πλήθος των ονομάτων, σε **αμφότερες** τις γλώσσες. Μια τυπογραφική αστοχία εδώ γίνεται
 * κόκκινο, όχι σιωπηλά μετατοπισμένη στήλη στον διάλογο.
 *
 * ## 🔴 ΤΡΕΙΣ καταστάσεις υποχρεωτικότητας, όχι δύο
 * Το Excel γράφει με **έντονα** τα υποχρεωτικά. Για να το κάνουμε κι εμείς πρέπει να ξέρουμε
 * ποια είναι — και για ένα μέρος του καταλόγου **δεν το ξέρουμε με βεβαιότητα**. Ένα boolean
 * θα μας ανάγκαζε να διαλέξουμε: «όλα υποχρεωτικά» (ψευδώς έντονα, ο χρήστης συμπληρώνει
 * όρισμα που δεν χρειαζόταν) ή «όλα προαιρετικά» (το «OK» δεν φρουρεί τίποτα). Και τα δύο
 * είναι **πληροφορία που δεν έχουμε, παρουσιασμένη ως βεβαιότητα**.
 *
 * Η τρίτη κατάσταση λέει την αλήθεια: **ούτε έντονο, ούτε φρουρός**. Είναι ο ίδιος κανόνας
 * που η Φ1 δεσμεύτηκε στο §3 («εφευρημένη υπογραφή είναι χειρότερη από την απουσία της»),
 * συνεχισμένος αντί για ξεχασμένος — και είναι **μετρήσιμος**: ένα test μετρά πόσες
 * συναρτήσεις έχουν πλήρως δηλωμένη υποχρεωτικότητα, όπως το `documented` μετρά την
 * τεκμηρίωση.
 *
 * @module subapps/dxf-viewer/bim/table/formula/catalog/formula-argument-taxonomy
 * @see formula-argument-data.ts — τα δεδομένα σε συμπαγή γραφή
 * @see formula-signature.ts — η σύζευξη με τα μεταφρασμένα ονόματα
 * @see docs/centralized-systems/reference/adrs/ADR-763-table-insert-function-dialog.md §11
 */

/**
 * Τι **περιμένει** ένα όρισμα — και τι γράφεται γκρι στα δεξιά του όσο το πεδίο είναι κενό.
 *
 * Είναι το λεξιλόγιο του **Excel**, όχι της μηχανής μας: ο αξιολογητής ξέρει `number | string
 * | boolean | list` και δεν ξεχωρίζει `reference` από `range` (και τα δύο φτάνουν ως
 * {@link TableFormulaArgument}). Η διάκριση υπάρχει επειδή ο **χρήστης** τη χρειάζεται:
 * «αναφορά» σημαίνει «δείξε μου ένα κελί», «εύρος» σημαίνει «σύρε πάνω σε πολλά».
 *
 * Το `any` δεν είναι διαφυγή — είναι η αλήθεια για ορίσματα σαν το `τιμή_αν_αληθές` της `IF`,
 * που δέχονται κυριολεκτικά οτιδήποτε.
 */
export type FormulaArgumentKind =
  | 'number'
  | 'text'
  | 'logical'
  | 'reference'
  | 'range'
  | 'any';

/** Τι ξέρουμε για το αν ένα όρισμα **πρέπει** να συμπληρωθεί. Δες την κεφαλίδα. */
export type FormulaArgumentRequirement = 'required' | 'optional' | 'unspecified';

/** Ένα όρισμα, όπως το ζωγραφίζει μια σειρά του διαλόγου. */
export interface FormulaArgumentSpec {
  /** Η μεταφρασμένη ετικέτα (`Κείμενο1`) — έρχεται από το i18n, όχι από εδώ. */
  readonly name: string;
  readonly kind: FormulaArgumentKind;
  readonly requirement: FormulaArgumentRequirement;
}

/**
 * 🔴 **Η επανάληψη είναι ΟΜΑΔΑ, όχι ένα όρισμα** — και η προφανής υλοποίηση είναι λάθος.
 *
 * Το `CONCATENATE` μεγαλώνει κατά **ένα** (`Κείμενο3`, `Κείμενο4`…), αλλά το `SUMIFS`
 * μεγαλώνει κατά **δύο** (`εύρος_κριτηρίων2` **και** `κριτήρια2` μαζί) — ένα κριτήριο χωρίς
 * το εύρος του δεν σημαίνει τίποτα, και το Excel δεν προσφέρει ποτέ το μισό ζεύγος. Με
 * σημαία `repeats` στο τελευταίο όρισμα, ο διάλογος θα πρόσθετε σκέτο `κριτήρια2` και ο
 * χρήστης θα έγραφε κριτήριο που δεν έχει πού να εφαρμοστεί ⇒ `#VALUE!` που μοιάζει δικό του
 * λάθος.
 *
 * Επτά συναρτήσεις επαναλαμβάνονται σε ζεύγη (`SUMIFS`, `COUNTIFS`, `AVERAGEIFS`, `MAXIFS`,
 * `MINIFS`, `IFS`, `SWITCH`) — αρκετές για να μην είναι ειδική περίπτωση.
 */
export interface FormulaRepeatSpec {
  /** Πόσα **τελευταία** ορίσματα επαναλαμβάνονται μαζί. `1` για τις περισσότερες. */
  readonly groupSize: number;
  /** Ανώτατο συνολικό πλήθος ορισμάτων. Το Excel σταματά στα 255 για τις περισσότερες. */
  readonly max: number;
}

/** Η πλήρης υπογραφή μιας συνάρτησης, έτοιμη για ζωγράφισμα. */
export interface FormulaSignatureSpec {
  readonly name: string;
  /** Οι σειρές που δείχνει ο διάλογος **αρχικά**. Κενό για `PI()`, `TRUE()`, `NA()`. */
  readonly args: readonly FormulaArgumentSpec[];
  /** `undefined` όταν το πλήθος ορισμάτων είναι σταθερό. */
  readonly repeat: FormulaRepeatSpec | undefined;
  /**
   * 🔴 `false` όταν τα ονόματα των ορισμάτων **δεν** είναι γνωστά και ο διάλογος πέφτει σε
   * γενικό `Όρισμα1, Όρισμα2…`. Οι 222 μη τεκμηριωμένες περνούν από εδώ — ο διάλογος
   * **ανοίγει** κανονικά και η ζωντανή προεπισκόπηση δουλεύει, που είναι η πραγματική
   * απάντηση στο «τι κάνει αυτό;», αντί για μια εφευρημένη ετικέτα.
   */
  readonly named: boolean;
}

/**
 * Ο **κωδικός ειδών**: ένας χαρακτήρας ανά όρισμα, με προαιρετικό `*` στο τέλος για
 * επανάληψη του τελευταίου.
 *
 * ## Γιατί κωδικός και όχι πίνακας από `'number' | 'text' | …`
 * Το αρχείο δεδομένων έχει **153 γραμμές** και ο άνθρωπος που το συντηρεί κάνει μία ερώτηση:
 * «συμφωνεί η σειρά των ειδών με τη σειρά των ονομάτων;». Με πλήρη ονόματα κάθε γραμμή
 * γίνεται τρεις και η σύγκριση απαιτεί κύλιση — δηλαδή η μορφή θα **έκρυβε** ακριβώς το λάθος
 * που πρέπει να φαίνεται. Ο κωδικός `'arnl'` διαβάζεται δίπλα στο
 * `τιμή_αναζήτησης;πίνακας;αριθμός_δείκτη_στήλης;εύρος_αναζήτησης` με μια ματιά.
 *
 * ⚠️ Η ασφάλεια δεν χάνεται: κάθε άγνωστος χαρακτήρας είναι **σφάλμα σε test**, και το μήκος
 * επαληθεύεται απέναντι στα πραγματικά μεταφρασμένα ονόματα.
 */
const KIND_CODES: Readonly<Record<string, FormulaArgumentKind>> = {
  n: 'number',
  t: 'text',
  l: 'logical',
  c: 'reference',
  r: 'range',
  a: 'any',
};

/**
 * Ο δείκτης επανάληψης: `*` (ομάδα ενός) ή `*N` (ομάδα `N` ορισμάτων). Δες
 * {@link FormulaRepeatSpec} για το γιατί το `N` δεν είναι πολυτέλεια.
 */
const REPEAT_PATTERN = /\*(\d*)$/;

/** Το αποτέλεσμα της ανάλυσης ενός κωδικού ειδών. */
export interface ParsedKindCode {
  readonly kinds: readonly FormulaArgumentKind[];
  /** `0` όταν δεν υπάρχει επανάληψη· αλλιώς πόσα τελευταία ορίσματα επαναλαμβάνονται. */
  readonly repeatGroup: number;
}

/**
 * Κωδικός → είδη. `null` για κάθε χαρακτήρα εκτός λεξιλογίου, ή για ομάδα επανάληψης που δεν
 * χωρά στα ορίσματα που δηλώθηκαν.
 *
 * Η άρνηση είναι **ρητή** και όχι σιωπηλή παράλειψη: ένας κωδικός με τυπογραφικό θα παρήγε
 * λιγότερα είδη από ονόματα, και ο διάλογος θα ζωγράφιζε σειρά χωρίς είδος — δηλαδή θα
 * έδειχνε λάθος γκρι τύπο δίπλα σε σωστό όνομα, που είναι χειρότερο από κενό.
 *
 * ⚠️ Ο **κενός** κωδικός είναι έγκυρος και σημαίνει «καμία παράμετρος»: το `PI()`, το
 * `TRUE()`, το `FALSE()` και το `NA()` είναι πραγματικές συναρτήσεις μηδενικής τάξης, και ο
 * διάλογος οφείλει να ανοίγει και γι' αυτές δείχνοντας μόνο το αποτέλεσμα.
 */
export function parseKindCode(code: string): ParsedKindCode | null {
  const match = REPEAT_PATTERN.exec(code);
  const letters = match === null ? code : code.slice(0, match.index);
  const repeatGroup = match === null ? 0 : Number(match[1] === '' ? '1' : match[1]);

  const kinds: FormulaArgumentKind[] = [];
  for (const letter of letters) {
    const kind = KIND_CODES[letter];
    if (kind === undefined) return null;
    kinds.push(kind);
  }
  // Μια ομάδα μεγαλύτερη από τα δηλωμένα ορίσματα δεν έχει τι να επαναλάβει — και θα έβγαινε
  // ως σειρές χωρίς πρότυπο ονόματος. Καλύτερα κόκκινο εδώ παρά κενές ετικέτες στην οθόνη.
  if (repeatGroup > kinds.length) return null;
  return { kinds, repeatGroup };
}

/** Τα γράμματα του λεξιλογίου — το test τα διαβάζει από εδώ, δεν τα ξαναγράφει. */
export const FORMULA_ARGUMENT_KIND_CODES: readonly string[] = Object.keys(KIND_CODES);
