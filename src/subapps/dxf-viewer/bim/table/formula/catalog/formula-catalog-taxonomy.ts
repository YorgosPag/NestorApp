/**
 * Οι δύο **εικονικές** επιλογές της λίστας κατηγοριών: δεν είναι οικογένειες συναρτήσεων,
 * είναι φίλτρα.
 *
 * - `recent` — «Πιο πρόσφατη χρήση», η **προεπιλογή του Excel**. Δεν είναι ιδιότητα της
 *   συνάρτησης αλλά του χρήστη· ζει στο `formula-mru-store.ts`.
 * - `all` — «Όλες».
 */
export type FormulaCategoryFilter = FormulaCategory | 'recent' | 'all';

/** Η σειρά του αναπτυσσόμενου, ολόκληρη — δες το στιγμιότυπο του Excel. */
export const FORMULA_CATEGORY_FILTERS: readonly FormulaCategoryFilter[] = [
  'recent',
  'all',
  ...FORMULA_CATEGORIES,
];

/** Μια εγγραφή του καταλόγου: πού ανήκει και αν έχει τεκμηρίωση. */
export interface FormulaCatalogEntry {
  /** Το όνομα που πληκτρολογεί ο χρήστης (`CEILING.MATH`, όχι `CEILINGMATH`). */
  readonly name: string;
  readonly category: FormulaCategory;
  /**
   * 🔴 `true` όταν υπάρχουν **υπογραφή ορισμάτων και περιγραφή** στα locale JSON.
   *
   * ## Γιατί σημαία και όχι «ρώτα το i18n και δες αν βρήκες»
   * Δύο λόγοι, και ο δεύτερος είναι ο δεσμευτικός:
   *  1. το `t()` με κλειδί που λείπει επιστρέφει **το ίδιο το κλειδί**, δηλαδή θα βάφαμε
   *     `table.insertFunction.help.AVEDEV` μέσα στον διάλογο — ωμό κλειδί στην οθόνη, ακριβώς
   *     ό,τι απαγορεύει ο N.11·
   *  2. η κάλυψη είναι **μετρήσιμο μέγεθος** αυτής της φάσης: ένα test μετρά πόσες είναι
   *     τεκμηριωμένες και ένα δεύτερο επιβεβαιώνει ότι για καθεμιά **υπάρχουν** τα δύο κλειδιά
   *     σε **αμφότερες** τις γλώσσες. Χωρίς τη σημαία δεν υπάρχει τι να μετρηθεί, και η
   *     «σταδιακή συμπλήρωση» θα ήταν ευχή αντί για αριθμό.
   */
  readonly documented: boolean;
}

/**
 * Όνομα συνάρτησης → τμήμα κλειδιού i18n.
 *
 * 🔴 Η τελεία **πρέπει** να φύγει: ο i18next τη διαβάζει ως διαχωριστή ένθεσης, οπότε το
 * κλειδί `help.CHISQ.DIST` θα έψαχνε αντικείμενο `CHISQ` με πεδίο `DIST` — και θα έβρισκε
 * `undefined` για **κάθε** συνάρτηση με τελεία στο όνομα, δηλαδή για 39 από αυτές. Ο
 * μετασχηματισμός ζει εδώ ώστε ο κατάλογος, ο διάλογος και τα tests να ρωτούν το ίδιο.
 */
export function formulaCatalogKey(name: string): string {
  return name.replace(/\./g, '_');
}
