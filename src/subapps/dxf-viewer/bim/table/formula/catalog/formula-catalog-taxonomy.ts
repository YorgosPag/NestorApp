/**
 * ADR-763 §2 — **το λεξιλόγιο του καταλόγου συναρτήσεων**: σε ποια οικογένεια ανήκει μια
 * συνάρτηση και τι σημαίνει «τεκμηριωμένη». Καθαρό type module, μηδέν runtime πέρα από τη
 * λίστα των κατηγοριών και τον μετασχηματισμό ονόματος→κλειδί.
 *
 * ## 🔴 Γιατί ΔΕΥΤΕΡΟ επίπεδο δεδομένων δίπλα στο §49
 * Το `formula-library-taxonomy.ts` απαντά **«επιτρέπεται να κληθεί;»** — ερώτηση της μηχανής
 * υπολογισμού, με οκτώ αιτίες απόρριψης και πύλη πληρότητας. Εδώ η ερώτηση είναι άλλη:
 * **«πώς τη βρίσκει ο άνθρωπος που δεν ξέρει το όνομά της;»**. Οι δύο δεν συγχωνεύονται:
 * το `shape: 'flat' | 'grid'` δεν λέει τίποτα στον χρήστη, και η κατηγορία «Κείμενο» δεν λέει
 * τίποτα στον αξιολογητή. Μια κοινή δομή θα ανάγκαζε κάθε αλλαγή διεπαφής να ακουμπήσει το
 * αρχείο από το οποίο κρέμεται ο επαναϋπολογισμός.
 *
 * Η **σύνδεση** των δύο γίνεται σε ένα σημείο ({@link module:.../formula-catalog}) και είναι
 * fail-closed προς την ίδια κατεύθυνση: ο κατάλογος δείχνει **μόνο** ό,τι είναι πράγματι
 * καλέσιμο, και μια καλέσιμη χωρίς κατηγορία είναι **κόκκινο σε test**, όχι σιωπηλή απουσία
 * από τη λίστα.
 *
 * @module subapps/dxf-viewer/bim/table/formula/catalog/formula-catalog-taxonomy
 * @see docs/centralized-systems/reference/adrs/ADR-763-table-insert-function-dialog.md §2
 */

/**
 * Οι οικογένειες του διαλόγου «Εισαγωγή συνάρτησης», με τα ονόματα του Excel.
 *
 * ## Γιατί ακριβώς αυτές και όχι δικές μας
 * Ο διάλογος υπάρχει για **parity**: ο μηχανικός που ξέρει ότι το `VLOOKUP` κάθεται στο
 * «Αναζήτηση & Αναφορά» πρέπει να το βρει εκεί. Μια «καλύτερη» ταξινόμηση (π.χ. «Ποσότητες»,
 * «Κόστη») θα ήταν σωστότερη για το έργο και **λάθος για τον χρήστη**: θα τον ανάγκαζε να
 * ξεμάθει κάτι που ήδη ξέρει.
 *
 * ## Τι λείπει από το Excel, και γιατί ΔΕΝ είναι παράλειψη
 * - **Κύβος** (`CUBEMEMBER`…) — απαιτεί σύνδεση OLAP· δεν υπάρχει τέτοια πηγή στο σχέδιο.
 * - **Web** (`WEBSERVICE`, `FILTERXML`) — δικτυακή κλήση μέσα σε κελί σημαίνει ότι το
 *   παραδοτέο αλλάζει τιμή όταν αλλάξει ένας τρίτος server. Ίδιο επιχείρημα με το `volatile`
 *   του §49, ενισχυμένο.
 * - **Ορισμένες από τον χρήστη** — δεν υπάρχει VBA.
 *
 * Το **«Συμβατότητα»** υπάρχει και δεν είναι διακοσμητικό: τα εννιά παλαιά ονόματα
 * (`STDEV`, `VAR`, `MODE`…) είναι ψευδώνυμα στην ίδια υλοποίηση (δες `LEGACY_EXCEL_ALIASES`),
 * και το Excel τα δείχνει **ακριβώς εκεί**.
 */
export type FormulaCategory =
  | 'financial'
  | 'dateTime'
  | 'mathTrig'
  | 'statistical'
  | 'lookup'
  | 'database'
  | 'text'
  | 'logical'
  | 'information'
  | 'engineering'
  | 'compatibility';

