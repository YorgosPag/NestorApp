/**
 * 🔴 ADR-739 §36 (ΦΑΣΗ 2) — **οι τύποι ακολουθούν τα κελιά που μετακόμισαν**.
 * Καθαρή συνάρτηση: μηδέν React, μηδέν DOM, μηδέν store.
 *
 * ## Ο κανόνας του Excel, σε μία πρόταση — και γιατί ΔΕΝ τον είχαμε δωρεάν
 * Μετρημένο, όχι εικασία (Microsoft Learn, `Range.Cut`): *«όταν μετακινείς μια επιλογή, το
 * Excel ενημερώνει τις αναφορές **προς** αυτήν, ανεξάρτητα από το αν είναι σχετικές ή
 * απόλυτες»* — ενώ *«αν μετακινείς μια επιλογή, το Excel **δεν** ενημερώνει τις αναφορές
 * **μέσα** στη μετακίνηση»*. Δηλαδή **ένας** κανόνας, ομοιόμορφος:
 *
 * > **Κάθε αναφορά που δείχνει σε κελί που μετακόμισε, ακολουθεί.
 * > Κάθε αναφορά σε κελί που έμεινε, μένει.**
 *
 * Το ADR-739 §9 έδωσε **το μισό** δωρεάν: οι αναφορές είναι δεμένες σε **ταυτότητες**
 * (`rowId`/`colId`), οπότε αναφορά σε κελί που δεν κουνήθηκε δεν έχει καν τι να αλλάξει —
 * ούτε λανθασμένη ολίσθηση μπορεί να συμβεί. Το **άλλο μισό** όμως ήταν δωρεάν **λάθος**:
 * στο δικό μας μοντέλο η ταυτότητα **μένει** και το **περιεχόμενο** μετακομίζει, οπότε μια
 * αναφορά στο κελί-πηγή θα έδειχνε, μετά τη μεταφορά, σε **άδειο κελί**. Το Excel σε αυτή
 * ακριβώς την περίπτωση ξαναγράφει τον τύπο.
 *
 * Αυτό το αρχείο είναι το άλλο μισό. Μετά από αυτό, η **μετακίνηση** έχει πλήρες parity —
 * και μάλιστα με μία μόνο απεικόνιση, γιατί ο κανόνας δεν ξεχωρίζει «μέσα» από «έξω»: η
 * απεικόνιση περιέχει **ό,τι μετακόμισε**, όπου κι αν ζούσε ο τύπος που το διαβάζει.
 *
 * ## 🔴 Η ΑΝΤΙΓΡΑΦΗ **ΔΕΝ** ΠΕΡΝΑ ΑΠΟ ΕΔΩ — ✅ ΚΑΙ ΤΩΡΑ ΕΧΕΙ ΔΙΚΟ ΤΗΣ ΣΠΙΤΙ (ADR-754 Γ1)
 * Στο Excel η **αντιγραφή** ολισθαίνει τις **σχετικές** αναφορές (`=B1` αντιγραμμένο μια
 * γραμμή κάτω γίνεται `=B2`) και αφήνει ακέραιες τις **απόλυτες** (`=$B$1`). Αυτή η γραμμή
 * έγραφε μέχρι το ADR-754 ότι «το `TableFormulaCellRef` **δεν έχει** τη διάκριση, άρα κάθε
 * αναφορά συμπεριφέρεται ως απόλυτη» — και προέβλεπε ρητά ότι η θεραπεία θα ήταν σημαία
 * απολυτότητας ανά άξονα, σε **δική της φάση**. Αυτό ακριβώς έγινε:
 *
 * - **Το `$` ζει τώρα στην αναφορά** (`absoluteRow`/`absoluteCol`, ADR-754 Γ2).
 * - **Η ολίσθηση ζει στο `table-formula-offset.ts`**, όχι εδώ — δες τον πίνακα των δύο
 *   ασύμβατων σημασιολογιών στο `table-formula-rewrite.ts`.
 * - **Εδώ το `$` παραμένει αδιάφορο**, και αυτό είναι Excel parity, όχι παράλειψη: *«όταν
 *   μετακινείς μια επιλογή, το Excel ενημερώνει τις αναφορές προς αυτήν, **ανεξάρτητα από το
 *   αν είναι σχετικές ή απόλυτες**»*. Η μόνη υποχρέωση αυτού του αρχείου απέναντι στο `$`
 *   είναι να **μην το σβήσει** — δες {@link remapRef}.
 *
 * @module subapps/dxf-viewer/bim/table/formula/table-formula-remap
 * @see table-formula-offset.ts — η ΑΛΛΗ πράξη: αντιγραφή, όπου το `$` αποφασίζει
 * @see bim/table/table-range-transfer.ts — ο μοναδικός καλών (η μεταφορά περιοχής)
 * @see types/table-formula.ts — γιατί δέντρο και όχι κείμενο
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §36
 */

import type { CellKey, PersistedTableModel } from '../../../types/table';
import type { TableFormulaCellRef, TableFormulaNode } from '../../../types/table-formula';
import { cellKey } from '../table-model-helpers';
import { mapTableFormulaTrees } from './table-formula-cells';
import { rewriteTableFormulaRefs } from './table-formula-rewrite';

/**
 * «Ποιο κελί πήγε πού» — κλειδί το κελί **πηγή**, τιμή ο **προορισμός**.
 *
 * `CellKey` στο κλειδί επειδή είναι η δηλωμένη μοναδική νόμιμη σύνθεση ταυτότητας κελιού σε
 * κλειδί χάρτη (`table-model-helpers.ts`)· `TableFormulaCellRef` στην τιμή επειδή αυτό
 * ακριβώς μπαίνει στο δέντρο, χωρίς δεύτερη μετάφραση.
 */
export type TableFormulaRefRelocation = ReadonlyMap<CellKey, TableFormulaCellRef>;

/**
 * Ξαναγράφει **κάθε** τύπο του πίνακα ώστε οι αναφορές του να ακολουθήσουν τα κελιά που
 * μετακόμισαν. Επιστρέφει το **ίδιο** μοντέλο by-reference όταν κανένα δέντρο δεν άλλαξε.
 *
 * Η εγγύηση ταυτότητας δεν είναι βελτιστοποίηση: η αλυσίδα `PersistedTableModel →
 * RESOLVED_MODEL_CACHE → TableModel → LAYOUT_CACHE` κλειδώνει σε ταυτότητα αντικειμένου, και
 * ένα νέο αντικείμενο χωρίς λόγο σημαίνει ακυρωμένη μνήμη **και** βήμα undo που δεν αναιρεί
 * τίποτα. Την ίδια εγγύηση δίνουν ήδη `setPersistedCellText`, `setTableEdges` και
 * `recalculateTableModel` — εδώ συνεχίζεται, δεν εφευρίσκεται.
 */
export function remapTableFormulaRefs(
  model: PersistedTableModel,
  moved: TableFormulaRefRelocation,
): PersistedTableModel {
  if (moved.size === 0) return model;

  // 🔴 N.18 — ο βρόχος «πέρασε τα κελιά τύπου, κράτα ταυτότητα» ζει σε **ένα** σπίτι: το
  // `jscpd` τον μέτρησε ως κλώνο με τη δομική θεραπεία (8 γρ. / 60 tokens). Εδώ μένει **μόνο**
  // η σημασιολογία της μετακόμισης, που είναι και το μόνο που διαφέρει.
  return mapTableFormulaTrees(model, (root) => remapNode(root, moved));
}

/**
 * Ο κόμβος με τις αναφορές του ενημερωμένες — **το ίδιο αντικείμενο** όταν τίποτα από κάτω
 * δεν άλλαξε.
 *
 * Η **κάθοδος** (και μαζί της η εγγύηση ταυτότητας) ζει από το ADR-754 Γ1 στο
 * `table-formula-rewrite.ts`: την ίδια ακριβώς αναδρομή τη χρειάστηκε και η **αντιγραφή**
 * τύπου, και δύο αντίγραφα θα ήταν ο structural clone του CHECK 3.28 — και δύο θέσεις όπου
 * ένα νέο είδος κόμβου μπορεί να ξεχαστεί στη μία. Εδώ μένει **μόνο** η σημασιολογία των
 * φύλλων, που είναι και το μόνο που διαφέρει ανάμεσα στις δύο πράξεις.
 */
function remapNode(node: TableFormulaNode, moved: TableFormulaRefRelocation): TableFormulaNode {
  return rewriteTableFormulaRefs(node, (leaf) =>
    leaf.kind === 'ref' ? remapRef(leaf, moved) : remapRange(leaf, moved),
  );
}

/**
 * 🔴 **Η μετακόμιση αλλάζει ΤΑΥΤΟΤΗΤΑ, όχι ΠΡΟΘΕΣΗ** — γι' αυτό οι σημαίες `$` επιβιώνουν.
 *
 * Η προηγούμενη γραφή ήταν `{ kind: 'ref', cell: next }`, δηλαδή **επίπεδη αντικατάσταση**:
 * κρατούσε ό,τι ήξερε το `TableFormulaRefRelocation` και **πετούσε σιωπηλά κάθε άλλο πεδίο**
 * της αναφοράς. Ήταν σωστό όσο η αναφορά ήταν σκέτο ζεύγος ταυτοτήτων· από τη στιγμή που
 * απέκτησε `absoluteRow`/`absoluteCol` (ADR-754 Γ2) θα σήμαινε ότι **κάθε** μετακίνηση
 * περιοχής, κάθε εισαγωγή γραμμής, ξεκλειδώνει τα δολάρια του χρήστη — και ο έλεγχος τύπων
 * **δεν το πιάνει** (προαιρετικά πεδία + δομικός τύπος: το `{rowId, colId}` είναι απολύτως
 * έγκυρο `TableFormulaCellRef`).
 *
 * Το `spread` το κάνει αδύνατο να εκφραστεί: ό,τι δεν ξέρει η απεικόνιση, μένει.
 */
function remapRef(
  node: Extract<TableFormulaNode, { kind: 'ref' }>,
  moved: TableFormulaRefRelocation,
): TableFormulaNode {
  if (isForeignRef(node.cell)) return node;
  const next = moved.get(cellKey(node.cell.rowId, node.cell.colId));
  return next === undefined ? node : { kind: 'ref', cell: { ...node.cell, ...next } };
}

/**
 * 🔴 ADR-833 Φάση 7 — **δείχνει αυτή η αναφορά σε ΑΛΛΟ φύλλο;**
 *
 * Η μετακόμιση είναι πράξη **ενός** πλέγματος: η απεικόνιση «ποιο πήγε πού» φτιάχτηκε από τα
 * κελιά **αυτού** του φύλλου, και τα κλειδιά της είναι σκέτα `rowId+colId`. Μια αναφορά προς
 * το Φύλλο2 έχει **τυχαία** το ίδιο ζεύγος ταυτοτήτων (κάθε φύλλο ξεκινά από τον ίδιο
 * κατασκευαστή, άρα `r0`/`c0` υπάρχουν παντού — ADR-833 §5.2) και θα ταίριαζε **κατά λάθος**:
 * μια μετακίνηση περιοχής στο Φύλλο1 θα μετακινούσε σιωπηλά και τις αναφορές **προς** το
 * Φύλλο2. Αριθμός που μοιάζει σωστός και δεν είναι — ακριβώς η κλάση του ADR-720.
 *
 * 🔑 Το κατηγόρημα δεν χρειάζεται βιβλίο επειδή ο **αναλυτής κανονικοποιεί**: `worksheetId`
 * παρόν σημαίνει **πάντα** ξένο φύλλο (δες `resolveAddress` στο `table-formula-parse.ts`).
 */
function isForeignRef(cell: TableFormulaCellRef): boolean {
  return cell.worksheetId !== undefined;
}

/**
 * 🔑 **Το εύρος ακολουθεί ΜΟΝΟ αν μετακόμισαν ΚΑΙ ΤΑ ΔΥΟ άκρα του** — και αυτό είναι Excel
 * parity, όχι συντηρητισμός.
 *
 * `=SUM(A1:A5)` όταν μετακινείς **μόνο** το `A3`: το Excel αφήνει το εύρος ακέραιο (και το
 * `A3` αδειάζει, οπότε το άθροισμα πέφτει). Αν ακολουθούσε το ένα άκρο, το εύρος θα
 * **παραμορφωνόταν** σε κάτι που κανείς δεν έγραψε — ένα `A1:D3` από ένα `A1:A5`, δηλαδή
 * αριθμός που μοιάζει σωστός και δεν είναι (ADR-720).
 *
 * Επειδή ο προορισμός είναι **σταθερή μετατόπιση** της πηγής, «και τα δύο άκρα μέσα στην
 * απεικόνιση» συνεπάγεται ότι το εύρος μετατοπίζεται **αυτούσιο**: ίδιο σχήμα, νέα θέση.
 * Τα άκρα **δεν** κανονικοποιούνται εδώ (δες `types/table-formula.ts`) — ό,τι έγραψε ο
 * χρήστης ως `B5:A1` παραμένει `B5:A1` μετακινημένο, όχι σιωπηλά αναποδογυρισμένο.
 */
function remapRange(
  node: Extract<TableFormulaNode, { kind: 'range' }>,
  moved: TableFormulaRefRelocation,
): TableFormulaNode {
  // Αρκεί **ένα** ξένο άκρο: ένα εύρος με άκρα σε δύο φύλλα δεν παράγεται από τον αναλυτή, και
  // ένα ξένο εύρος δεν αφορά καθόλου αυτή τη μετακόμιση. Δες {@link isForeignRef}.
  if (isForeignRef(node.from) || isForeignRef(node.to)) return node;
  const from = moved.get(cellKey(node.from.rowId, node.from.colId));
  const to = moved.get(cellKey(node.to.rowId, node.to.colId));
  if (from === undefined || to === undefined) return node;
  // `spread` και εδώ, για τον λόγο του {@link remapRef}: κάθε άκρο κρατά **τις δικές του**
  // σημαίες `$` — το `$A$1:B5` έχει κλειδωμένη μόνο την αρχή, και αυτό πρέπει να επιβιώσει.
  return { kind: 'range', from: { ...node.from, ...from }, to: { ...node.to, ...to } };
}
