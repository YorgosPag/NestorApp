/**
 * 🔴 ADR-760 — **Η ΜΙΑ ΕΠΟΧΗ**: σειριακός αριθμός Excel ⇄ ημερολογιακή ημερομηνία.
 *
 * ## Γιατί χωριστό αρχείο, και γιατί ΤΩΡΑ
 * Η εποχή και η μία κατεύθυνση ({@link excelSerialFromDate}) γεννήθηκαν στη Φ3 μέσα στο
 * `library/formula-library-bridge.ts`, και εκεί ήταν σωστές: μόνος καταναλωτής ήταν η γέφυρα.
 * Η **μορφοποίηση κελιού** (ADR-760) χρειάζεται την **αντίστροφη**, και ο μόνος τίμιος τόπος γι'
 * αυτήν είναι δίπλα στην εποχή που τη γεννά — μια δεύτερη `Date.UTC(1899, 11, 30)` γραμμένη
 * στο στρώμα εμφάνισης θα ήταν δύο απαντήσεις στο «ποια μέρα είναι το 46239», και θα
 * απέκλιναν την ημέρα που κάποιος διορθώσει τη μία.
 *
 * ⚠️ **Η εξαγωγή ΔΕΝ είναι καλλωπισμός αρχιτεκτονικής.** Η γέφυρα εισάγει το
 * `@formulajs/formulajs` — και το επιτρέπεται σε **ένα** αρχείο, με forbiddenPattern του
 * `.ssot-registry.json` να το επιβάλλει. Αν το στρώμα διάταξης εισήγαγε τη γέφυρα για να πάρει
 * μία συνάρτηση ημερομηνίας, θα έσερνε **ολόκληρη τη βιβλιοθήκη 350 συναρτήσεων** μέσα στη
 * διαδρομή που ζωγραφίζει κάθε καρέ. Εδώ δεν υπάρχει καμία εξάρτηση: καθαρή αριθμητική.
 *
 * @module subapps/dxf-viewer/bim/table/formula/excel-serial-date
 * @see bim/table/formula/library/formula-library-bridge.ts — ο πρώτος καταναλωτής (Φ3)
 * @see bim/table/table-cell-format.ts — ο δεύτερος (ADR-760, η εμφάνιση)
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §49.6.3
 */

const MS_PER_DAY = 86_400_000;
const SECONDS_PER_DAY = 86_400;

/**
 * Η εποχή των σειριακών αριθμών του Excel: **30 Δεκεμβρίου 1899**, σε UTC.
 *
 * Η μετατόπιση κατά μία μέρα από την «1η Ιανουαρίου 1900» δεν είναι λάθος — απορροφά το
 * ιστορικό σφάλμα του Excel που θεωρεί το 1900 δίσεκτο. Επαληθεύτηκε ότι η βιβλιοθήκη μετρά
 * με την **ίδια** εποχή: `YEAR(46239)`/`MONTH`/`DAY` δίνουν 2026 / 8 / 5.
 *
 * ⚠️ Ημερομηνίες πριν την 1η Μαρτίου 1900 αποκλίνουν κατά μία μέρα, όπως **και στο Excel**.
 * Καταγράφεται ρητά· δεν αφορά κανέναν πίνακα ποσοτήτων.
 */
const EXCEL_EPOCH_UTC = Date.UTC(1899, 11, 30);

/**
 * `Date` → σειριακός αριθμός Excel.
 *
 * 🔴 Ο υπολογισμός γίνεται από τα **ημερολογιακά μέρη** και όχι με αφαίρεση χιλιοστών του
 * δευτερολέπτου. Η διαφορά φαίνεται μόνο δύο φορές τον χρόνο και είναι καταστροφική: μια
 * τοπική «μεσάνυχτα» εκατέρωθεν της αλλαγής θερινής ώρας απέχει 23 ή 25 ώρες, οπότε η ωμή
 * αφαίρεση θα έδινε `46238,958` — δηλαδή **προηγούμενη μέρα** μετά τη στρογγυλοποίηση.
 */
export function excelSerialFromDate(date: Date): number {
  const midnightUtc = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
  const days = (midnightUtc - EXCEL_EPOCH_UTC) / MS_PER_DAY;
  const seconds = date.getHours() * 3600 + date.getMinutes() * 60 + date.getSeconds();
  return days + seconds / SECONDS_PER_DAY;
}

/**
 * 🔴 ADR-760 — σειριακός αριθμός Excel → `Date`, **σε UTC**. `null` για ό,τι δεν είναι ημερομηνία.
 *
 * ## Γιατί UTC και όχι τοπική ώρα
 * Η ημερομηνία που ταξιδεύει σε ένα σχέδιο δεν έχει ζώνη ώρας — είναι **ημερολογιακή**
 * («5 Αυγούστου 2026»), όχι στιγμή. Κατασκευασμένη ως τοπική, το ίδιο αρχείο ανοιγμένο σε
 * άλλη ζώνη θα έδειχνε **προηγούμενη μέρα**: το κλασικό off-by-one που κάνει τα «ημερομηνία
 * έκδοσης» να χορεύουν ανά υπολογιστή. Ο καταναλωτής οφείλει να διαβάσει με `timeZone: 'UTC'`
 * — το κάνει το `table-cell-format.ts`.
 *
 * ## Τι απορρίπτεται, και γιατί ρητά
 * - **Μη πεπερασμένο** (`NaN`, `Infinity`): το `new Date(NaN)` δίνει «Invalid Date», που κάθε
 *   `Intl` μετατρέπει σε **`"Invalid Date"` ως ορατό κείμενο μέσα στο κελί**. Ένα σχέδιο δεν
 *   τυπώνει αγγλικά μηνύματα σφάλματος σε στήλη ημερομηνιών.
 * - **Αρνητικό**: πριν την εποχή· το Excel το ίδιο αρνείται (`#####`).
 * - **Πάνω από 2.958.465** (31/12/9999): το όριο του ίδιου του Excel. Χωρίς αυτό, ένας
 *   σειριακός που είναι στην πραγματικότητα **τιμή σε ευρώ** (π.χ. 3.500.000) θα ζωγράφιζε
 *   μια ημερομηνία του έτους 11000 — αριθμός που *φαίνεται* έγκυρος, δηλαδή το χειρότερο είδος
 *   σφάλματος.
 */
export function dateFromExcelSerial(serial: number): Date | null {
  if (!Number.isFinite(serial) || serial < 0 || serial > MAX_EXCEL_SERIAL) return null;

  // Ο ακέραιος είναι η **μέρα**, το κλάσμα η ώρα. Χωριστά, ώστε η στρογγυλοποίηση του
  // κλάσματος να μη μπορεί ποτέ να μετακινήσει τη μέρα (δες την κεφαλίδα του αντιστρόφου).
  const days = Math.floor(serial);
  const seconds = Math.round((serial - days) * SECONDS_PER_DAY);
  return new Date(EXCEL_EPOCH_UTC + days * MS_PER_DAY + seconds * 1000);
}

/** 31 Δεκεμβρίου 9999 — το ανώτατο όριο ημερομηνίας του ίδιου του Excel. */
const MAX_EXCEL_SERIAL = 2_958_465;
