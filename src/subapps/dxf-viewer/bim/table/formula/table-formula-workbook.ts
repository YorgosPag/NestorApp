/**
 * 🔴 ADR-833 Φάση 7 — **ΤΟ ΒΙΒΛΙΟ ΠΟΥ ΒΛΕΠΕΙ ΕΝΑΣ ΤΥΠΟΣ**: ποια πλέγματα μπορεί να διαβάσει,
 * ποιο είναι το «δικό του», και πώς γράφονται τα ονόματά τους. Καθαρές συναρτήσεις: μηδέν
 * React, μηδέν DOM, μηδέν store, **μηδέν i18n**.
 *
 * ## Η ερώτηση που γέννησε το αρχείο
 * Μέχρι τη Φάση 6 ολόκληρη η αλυσίδα τύπων δούλευε πάνω σε **ένα** `TableModel`, και αυτό
 * ήταν σωστό γιατί ένας τύπος δεν μπορούσε να δει έξω από το φύλλο του. Με το `=Φύλλο2!A1` η
 * ερώτηση *«ποιο πλέγμα είναι αυτή η αναφορά;»* αποκτά **δύο** πιθανές απαντήσεις, και
 * χρειάζεται **έναν** ιδιοκτήτη — αλλιώς ο αξιολογητής, ο εκτυπωτής, ο γράφος, η μετατόπιση
 * και η δομική θεραπεία θα την απαντούσαν **πέντε φορές**, με πέντε ευκαιρίες να διαφωνήσουν.
 * Είναι η **ίδια** μορφή απόφασης με το ADR-764 §2 (*«ζει αυτή η ταυτότητα;» — ένα κατηγόρημα,
 * ένα σπίτι*), ένα επίπεδο πιο έξω.
 *
 * ## 🔑 ΓΙΑΤΙ ΤΟ ΣΠΙΤΙ ΔΙΝΕΤΑΙ ΞΕΧΩΡΙΣΤΑ ΚΑΙ ΔΕΝ ΔΙΑΒΑΖΕΤΑΙ ΑΠΟ ΤΑ ΦΥΛΛΑ
 * Την ώρα μιας πράξης (`writeCellInput` → `commitCellWrites`) το πλέγμα του σπιτιού είναι
 * **μισογραμμένο**: το `worksheets[home].model` κρατά ακόμη την **προηγούμενη** έκδοση. Ένα
 * βιβλίο που διάβαζε το σπίτι από τον πίνακα φύλλων θα αξιολογούσε τον νέο τύπο πάνω στο
 * **παλιό** πλέγμα — δηλαδή θα ξαναγεννούσε, ένα επίπεδο πιο πάνω, ακριβώς το «μπαγιάτικη
 * τιμή» του ADR-764. Γι' αυτό ο κατασκευαστής δέχεται το **ζωντανό** μοντέλο και το βάζει
 * πάνω από το αποθηκευμένο.
 *
 * ## ⚠️ Η ονοματοδοσία είναι ΠΑΡΑΜΕΤΡΟΣ, όπως η γραμματική
 * Το «πώς λέγεται αυτό το φύλλο» έχει **δύο** έγκυρες απαντήσεις, και δεν είναι διπλότυπο:
 * *«πώς λέγεται στην οθόνη»* (ζωντανή γλώσσα, `worksheetDisplayName`) και *«πώς λέγεται μέσα
 * σε αυτό το αρχείο»* (εξυγιασμένο, ≤31 χαρακτήρες). Δύο **διαφορετικές ερωτήσεις** — η ίδια
 * διάκριση που το ADR-833 §5.7.1 τράβηξε ανάμεσα σε *μηχανική* και *λεξιλόγιο*, και ο ίδιος
 * λόγος για τον οποίο η {@link TableFormulaGrammar} έρχεται απ' έξω αντί να διαβάζεται εδώ.
 * Έτσι αυτό το module μένει **καθαρό από i18n** και ο αναλυτής δεν μαθαίνει ποτέ γλώσσα.
 *
 * @module subapps/dxf-viewer/bim/table/formula/table-formula-workbook
 * @see bim/table/table-worksheet-book.ts — οι ΔΥΟ υλοποιήσεις ονοματοδοσίας
 * @see bim/table/formula/table-formula-ref-scope.ts — «ζει αυτή η αναφορά;», τώρα ανά βιβλίο
 * @see docs/centralized-systems/reference/adrs/ADR-833-table-xlsx-import-and-worksheets.md §5.9
 */

import type { TableModel } from '../../../types/table';
import type { TableFormulaCellRef } from '../../../types/table-formula';
import type { TableWorksheetId } from '../../../types/table-ids';
import { FIRST_TABLE_WORKSHEET_ID } from '../../../types/table-worksheet';
import { forEachTableFormulaRefLeaf } from './table-formula-rewrite';

/**
 * **Πώς γράφονται τα φύλλα** σε ένα σύνορο γραφής — και πώς διαβάζονται πίσω.
 *
 * Οι δύο κατευθύνσεις ζουν μαζί επειδή είναι **η ίδια αντιστοιχία**: ένα `nameOf` που δεν
 * είναι αντιστρέψιμο από το `idOf` σημαίνει ότι ο εκτυπωτής παράγει κείμενο που ο αναλυτής
 * δένει αλλού — δηλαδή ένας τύπος που ο χρήστης απλώς άνοιξε και έκλεισε αλλάζει φύλλο.
 * Ακριβώς το εύρημα του ADR-833 §5.9.1.
 */
export interface TableWorksheetNaming {
  /** Το γραμμένο όνομα ενός φύλλου, **μοναδικό μέσα στο βιβλίο**· `null` για άγνωστο φύλλο. */
  readonly nameOf: (id: TableWorksheetId) => string | null;
  /**
   * Η ταυτότητα πίσω από ένα γραμμένο όνομα· `null` όταν κανένα φύλλο δεν το λέγεται.
   *
   * ⚠️ **Χωρίς διάκριση πεζών/κεφαλαίων**, όπως το Excel: ο χρήστης που γράφει `κοστη!A1`
   * εννοεί το φύλλο «Κόστη». Η μοναδικοποίηση των ονομάτων γίνεται με τον **ίδιο** κανόνα
   * (`lib/spreadsheet/unique-sheet-names.ts`), οπότε οι δύο πλευρές δεν μπορούν να
   * διαφωνήσουν για το τι είναι «ίδιο όνομα».
   */
  readonly idOf: (name: string) => TableWorksheetId | null;
}

/**
 * Βιβλίο **χωρίς ονόματα** — για κάθε διαδρομή που δεν έχει φύλλα να ονομάσει: το μονόφυλλο
 * βιβλίο, ο ανιχνευτής γραμματικής, τα καθαρά tests.
 *
 * Δεν είναι «κενή υλοποίηση για να μεταγλωττίσει»: λέει την **αλήθεια** ότι εδώ δεν υπάρχει
 * λεξιλόγιο φύλλων, οπότε ένα πληκτρολογημένο `Φύλλο2!A1` δεν δένει (⇒ `#REF!`, όπως κάθε
 * αναφορά που δεν λύνεται) αντί να δεθεί σιωπηλά κάπου λάθος.
 */
export const NO_WORKSHEET_NAMING: TableWorksheetNaming = {
  nameOf: () => null,
  idOf: () => null,
};

/**
 * **Ο κόσμος ενός τύπου.** Το `sheets` περιέχει **και** το σπίτι, ώστε η επίλυση μιας
 * αναφοράς να είναι μία αναζήτηση χωρίς ειδική περίπτωση.
 */
export interface TableFormulaWorkbook {
  /** Το φύλλο που κρατά τον τύπο. Αναφορά **χωρίς** φύλλο εννοεί αυτό. */
  readonly homeId: TableWorksheetId;
  /** Κάθε φύλλο του βιβλίου κατά ταυτότητα — το σπίτι με το **ζωντανό** του πλέγμα. */
  readonly sheets: ReadonlyMap<TableWorksheetId, TableModel>;
  /** Πώς γράφονται τα φύλλα σε **αυτό** το σύνορο. */
  readonly naming: TableWorksheetNaming;
}

/**
 * **Βιβλίο ενός φύλλου** — ό,τι ακριβώς έβλεπε κάθε τύπος πριν από τη Φάση 7.
 *
 * 🔑 Υπάρχει ως **ρητή** κατασκευή και όχι ως προεπιλεγμένη παράμετρος: κάθε καλών του είναι
 * μια θέση που δηλώνει *«εδώ δεν υπάρχουν άλλα φύλλα»*, και είναι **greppable**. Μια σιωπηλή
 * προεπιλογή θα σήμαινε ότι μια διαδρομή που ξέχασε το βιβλίο δίνει `#REF!` **χωρίς να το πει
 * κανείς** — ακριβώς η «σιωπηλή απώλεια» που απαγορεύει το ADR-833 §5.6.5.
 */
export function soleWorksheetBook(
  model: TableModel,
  homeId: TableWorksheetId = FIRST_TABLE_WORKSHEET_ID,
): TableFormulaWorkbook {
  return { homeId, sheets: new Map([[homeId, model]]), naming: NO_WORKSHEET_NAMING };
}

/**
 * **Το πλέγμα μιας αναφοράς** — ο ΕΝΑΣ επιλυτής του «απόν φύλλο ⇒ το σπίτι μου».
 *
 * `null` όταν το φύλλο **δεν υπάρχει (πια)**: διαγράφηκε, ή κόπηκε από το μερίδιο χωρητικότητας
 * (§5.8). Ο καλών το μεταφράζει σε `#REF!` — δεν το κάνει εδώ, γιατί αυτό το module απαντά
 * *«ποιο πλέγμα;»* και όχι *«τι αξίζει;»* (δες `table-formula-ref-scope.ts`).
 */
export function gridOfRef(book: TableFormulaWorkbook, ref: TableFormulaCellRef): TableModel | null {
  return book.sheets.get(ref.worksheetId ?? book.homeId) ?? null;
}

/** Η **λυμένη** ταυτότητα φύλλου μιας αναφοράς: η δική της, ή του σπιτιού όταν λείπει. */
export function sheetIdOfRef(
  book: TableFormulaWorkbook,
  ref: TableFormulaCellRef,
): TableWorksheetId {
  return ref.worksheetId ?? book.homeId;
}

/**
 * True όταν τα **δύο άκρα** ενός εύρους ζουν στο ίδιο φύλλο.
 *
 * Ένα `Φύλλο2!A1:Φύλλο3!B5` δεν είναι εύρος — είναι δύο διευθύνσεις με `:` ανάμεσα. Το Excel
 * το απορρίπτει κι εκείνο (η τρισδιάστατη αναφορά έχει **άλλη** σύνταξη, `Φύλλο2:Φύλλο3!A1`,
 * και είναι δηλωμένο όριο του §5.9.4). Η σύγκριση γίνεται στη **λυμένη** ταυτότητα, ώστε
 * `A1:Φύλλο1!B5` μέσα στο Φύλλο1 να μετρά σωστά ως **ένα** φύλλο.
 */
export function sameSheetRefs(
  book: TableFormulaWorkbook,
  from: TableFormulaCellRef,
  to: TableFormulaCellRef,
): boolean {
  return sheetIdOfRef(book, from) === sheetIdOfRef(book, to);
}

/**
 * 🔴 **Ο ΦΡΟΥΡΟΣ ΤΟΥ ΚΑΘΟΛΙΚΟΥ ΓΡΑΦΟΥ** (ADR-833 §5.9.2): ποια **άλλα** φύλλα κατονομάζουν οι
 * τύποι αυτού του πλέγματος. Κενό σύνολο ⇒ το φύλλο δεν διαβάζει κανέναν έξω από τον εαυτό του.
 *
 * ## Γιατί αυτό είναι όλη η απόδοση της φάσης — με μετρημένους αριθμούς
 * Ο επαναϋπολογισμός σαρώνει **όλα** τα κελιά ενός φύλλου (`collectFormulaCells`). Καθολικός
 * γράφος σε βιβλίο 12 φύλλων = **12 σαρώσεις ανά `Enter`**. Μετρημένο σε πυκνό φύλλο στο
 * ταβάνι (31.250 κελιά): **34,4–51,5 ms** έναντι **7,1–8,4 ms** σήμερα, δηλαδή **×4–6**.
 * Με τον φρουρό απομνημονευμένο: **×1,0**.
 *
 * ## 🔑 Η μνήμη είναι δωρεάν ΕΔΩ επειδή το repo εγγυάται ταυτότητα-ως-έκδοση
 * Τα μοντέλα είναι **αμετάβλητα** και επιστρέφονται **by-reference** όταν τίποτα δεν άλλαξε
 * (η τέταρτη εγγύηση του `setPersistedCellText`, συνεχισμένη από `commitCellWrites` και τους
 * οκτώ φύλακες no-op της Φάσης 2). Άρα η ταυτότητα αντικειμένου **ΕΙΝΑΙ** έκδοση, και η
 * απάντηση δεν μπορεί ποτέ να παλιώσει — ίδιο ιδίωμα με `resolveTableModel`,
 * `resolveTableLayout`, `indexById`, `resolveWorksheets`.
 *
 * 🏆 Το Excel **δεν** μπορεί να το κάνει: το μοντέλο του είναι μεταβλητό, οπότε συντηρεί μόνιμη
 * *calculation chain* με ρητή σήμανση βρόμικων κελιών — **δεύτερη δομή** που πρέπει να μένει
 * συγχρονισμένη. Εδώ δεν κρατιέται καμία: η απάντηση **παράγεται** και το `WeakMap` απλώς τη
 * θυμάται, χωρίς καμία ευκαιρία να αποκλίνει και χωρίς συλλογή σκουπιδιών.
 *
 * ⚠️ Επιστρέφει τις ταυτότητες **όπως γράφτηκαν**, χωρίς να ξέρει ποιο φύλλο είναι το σπίτι:
 * το μοντέλο δεν κουβαλά τη δική του ταυτότητα (και δεν πρέπει — θα ήταν πεδίο-καθρέφτης του
 * `TableWorksheet.id`). Ο καλών συγκρίνει με το σπίτι του.
 */
export function namedWorksheetReads(model: TableModel): ReadonlySet<TableWorksheetId> {
  const cached = NAMED_READS_CACHE.get(model);
  if (cached) return cached;

  const ids = new Set<TableWorksheetId>();
  for (const [, cell] of model.cells) {
    if (cell.kind !== 'formula' || cell.formula === undefined) continue;
    forEachTableFormulaRefLeaf(cell.formula.root, (leaf) => {
      if (leaf.kind === 'ref') {
        if (leaf.cell.worksheetId !== undefined) ids.add(leaf.cell.worksheetId);
        return;
      }
      if (leaf.from.worksheetId !== undefined) ids.add(leaf.from.worksheetId);
      if (leaf.to.worksheetId !== undefined) ids.add(leaf.to.worksheetId);
    });
  }

  const frozen: ReadonlySet<TableWorksheetId> = ids;
  NAMED_READS_CACHE.set(model, frozen);
  return frozen;
}

/**
 * Η μνήμη του {@link namedWorksheetReads}. `WeakMap` και όχι `Map`: το κλειδί είναι το ίδιο το
 * μοντέλο, οπότε μια έκδοση που κανείς δεν κρατά πια φεύγει μαζί του — καμία διαρροή, καμία
 * λίστα να καθαριστεί.
 */
const NAMED_READS_CACHE = new WeakMap<TableModel, ReadonlySet<TableWorksheetId>>();

/**
 * 🔴 **ΤΟ ΙΔΙΟ ΒΙΒΛΙΟ, ΜΕ ΑΛΛΟ ΣΠΙΤΙ.** Το «σπίτι» δεν είναι ιδιότητα του βιβλίου — είναι
 * ιδιότητα του **τύπου που αξιολογείται**: ένα σκέτο `A1` γραμμένο στο Φύλλο2 σημαίνει
 * `Φύλλο2!A1`, όποιο φύλλο κι αν κοιτά ο χρήστης.
 *
 * Ο καθολικός γράφος (§5.9.2) αξιολογεί τύπους **πολλών** φύλλων στο ίδιο πέρασμα, οπότε
 * αλλάζει σπίτι ανά κόμβο. Χωρίς αυτό, ένα `=SUM(A1:A5)` του Φύλλου2 θα διάβαζε το πλέγμα
 * του Φύλλου1 — **σιωπηλά λάθος αριθμός**, η ακριβής κλάση του ADR-764.
 *
 * ⚠️ Επιστρέφει **το ίδιο αντικείμενο** όταν το σπίτι δεν αλλάζει: η εγγύηση ταυτότητας δεν
 * σταματά στα μοντέλα.
 */
export function bookAtSheet(
  book: TableFormulaWorkbook,
  homeId: TableWorksheetId,
): TableFormulaWorkbook {
  return homeId === book.homeId ? book : { ...book, homeId };
}

/**
 * 🔴 **ΤΟ ΙΔΙΟ ΒΙΒΛΙΟ, ΜΕ ΤΟ ΖΩΝΤΑΝΟ ΠΛΕΓΜΑ ΤΟΥ ΣΠΙΤΙΟΥ.**
 *
 * Κάθε πόρτα που **γράφει** (πληκτρολόγηση, επικόλληση, γέμισμα, ανανέωση δεσμού) κρατά ένα
 * μοντέλο **νεότερο** από αυτό που κάθεται στον πίνακα φύλλων. Αν το βιβλίο έμπαινε ως έχει,
 * ο τύπος που μόλις γράφτηκε θα αξιολογούνταν πάνω στο **προηγούμενο** πλέγμα — δηλαδή θα
 * ξαναγεννιόταν, ένα επίπεδο πιο πάνω, ακριβώς η «μπαγιάτικη τιμή» του ADR-764.
 *
 * 🔑 **Το εγκαθιστά η ίδια η πόρτα, όχι ο καλών.** Έτσι δεν υπάρχει τρόπος να δοθεί βιβλίο που
 * διαφωνεί με το μοντέλο: η συνέπεια είναι **δομική**, όχι σύμβαση που θυμάται ο καθένας.
 */
export function bookWithHome(
  book: TableFormulaWorkbook,
  home: TableModel,
): TableFormulaWorkbook {
  if (book.sheets.get(book.homeId) === home) return book;
  const sheets = new Map(book.sheets);
  sheets.set(book.homeId, home);
  return { ...book, sheets };
}

/**
 * 🔴 **ΠΟΙΑ ΦΥΛΛΑ ΑΓΓΙΖΕΙ ΜΙΑ ΑΛΛΑΓΗ** — ο φρουρός του §5.9.2, σε **ένα** σπίτι.
 *
 * Ένα φύλλο συμμετέχει αν **άλλαξε**, ή αν **διαβάζει** φύλλο που συμμετέχει. Το δεύτερο
 * σκέλος είναι **μεταβατικό** και πρέπει να είναι: το Φύλλο3 που διαβάζει το Φύλλο2 που
 * διαβάζει το Φύλλο1 γίνεται μπαγιάτικο από αλλαγή στο Φύλλο1 **χωρίς να το κατονομάζει
 * πουθενά**. Ένα μη μεταβατικό κλείσιμο θα άφηνε ακριβώς αυτή την αλυσίδα να σαπίσει σιωπηλά
 * — και θα εξαγόταν έτσι σε DXF και σε `.xlsx`.
 *
 * ## Γιατί είναι φθηνό — και γιατί ζει εδώ, δίπλα στη μνήμη
 * Η ερώτηση «ποια φύλλα κατονομάζει αυτό;» ({@link namedWorksheetReads}) απαντιέται **μία φορά
 * ανά έκδοση μοντέλου**. Το κλείσιμο είναι έπειτα αριθμητική συνόλων πάνω σε λίγα στοιχεία.
 * **Δύο** καταναλωτές τη ρωτούν — ο επαναϋπολογισμός και η πύλη του βιβλίου — και μια δεύτερη
 * υλοποίηση θα σήμαινε ότι η πύλη μπορεί να παραλείψει φύλλο που ο γράφος θα υπολόγιζε.
 *
 * ⚠️ **Ο βρόχος τερματίζει πάντα**: κάθε πέρασμα είτε μεγαλώνει σύνολο **φραγμένο** από το
 * πλήθος των φύλλων, είτε σταματά. Μετρητής ασφαλείας εδώ θα ήταν θεραπεία για πρόβλημα που
 * δεν μπορεί να υπάρξει — ίδιο σκεπτικό με το timeout που ο ανιχνευτής κύκλου δεν έχει.
 */
export function sheetsReading(
  book: TableFormulaWorkbook,
  seed: Iterable<TableWorksheetId>,
): ReadonlySet<TableWorksheetId> {
  const active = new Set<TableWorksheetId>(seed);
  for (let grew = true; grew; ) {
    grew = false;
    for (const [id, model] of book.sheets) {
      if (active.has(id)) continue;
      for (const read of namedWorksheetReads(model)) {
        if (!active.has(read)) continue;
        active.add(id);
        grew = true;
        break;
      }
    }
  }
  return active;
}
