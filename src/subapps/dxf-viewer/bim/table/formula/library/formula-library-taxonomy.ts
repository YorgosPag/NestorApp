/**
 * ADR-739 §49 — **το λεξιλόγιο της διαμέρισης**: τι σημαίνει «εγκεκριμένη» και τι σημαίνει
 * κάθε μία από τις οκτώ αιτίες απόρριψης. Καθαρό type module, μηδέν runtime πέρα από τους
 * ελέγχους ταυτότητας.
 *
 * ## 🔴 Γιατί **διαμέριση** και όχι σκέτη λίστα επιτρεπτών
 * Μια allow-list λέει τι μπαίνει. **Δεν λέει τίποτα για ό,τι λείπει** — και σε αναβάθμιση
 * της βιβλιοθήκης δεν υπάρχει τρόπος να ξεχωρίσεις το «απορρίφθηκε με σκεπτικό» από το
 * «ξεχάστηκε». Η πρώτη φορά που θα ξεχαστεί μια **μη ντετερμινιστική** συνάρτηση, ο πίνακας
 * ποσοτήτων θα αλλάζει μόνος του και κανένα αρχείο δεν θα δείχνει ποιος το αποφάσισε.
 *
 * Γι' αυτό **κάθε** εξαγωγή της βιβλιοθήκης παίρνει ετυμηγορία, και η πύλη απαιτεί η ένωση
 * εγκεκριμένων και απορριφθέντων να είναι **ακριβώς** η επιφάνειά της. Νέα συνάρτηση σε
 * μελλοντική έκδοση δεν ανήκει σε κανέναν κάδο ⇒ **κόκκινο**, δηλαδή αναγκαστική απόφαση.
 * Fail-closed και στα δύο επίπεδα: το μητρώο χτίζεται **μόνο** από τις εγκεκριμένες (χρόνος
 * εκτέλεσης), η πύλη ελέγχει την πληρότητα (χρόνος commit/CI).
 *
 * @module subapps/dxf-viewer/bim/table/formula/library/formula-library-taxonomy
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §49
 */

/**
 * Πώς φτάνει ένα εύρος στη συνάρτηση της βιβλιοθήκης.
 *
 * - `flat` — **η κανονική μορφή**. Το `A1:B5` γίνεται επίπεδος πίνακας δέκα τιμών. Αυτό
 *   περιμένουν σχεδόν όλες (`SUMIF`, `MEDIAN`, `LARGE`, `MATCH` — μετρημένο).
 * - `grid`  — 2Δ πίνακας γραμμών. Το ζητούν **μόνο** όσες έχουν έννοια «στήλης μέσα στην
 *   περιοχή»: `VLOOKUP`, `HLOOKUP`, `LOOKUP`, `INDEX` και οι δώδεκα συναρτήσεις βάσης
 *   δεδομένων. Μετρημένο: `VLOOKUP` πάνω σε **επίπεδο** πίνακα επιστρέφει `#N/A` — δηλαδή
 *   λάθος απάντηση χωρίς κανένα σφάλμα, ακριβώς το είδος που δεν φαίνεται σε παραδοτέο.
 */
export type FormulaLibraryShape = 'flat' | 'grid';

/**
 * Οι οκτώ αιτίες απόρριψης. Καθεμιά είναι **επιχείρημα**, όχι ετικέτα — και καθεμιά
 * αντιστοιχεί σε ένα ερώτημα που ένας άνθρωπος πρέπει να απαντήσει ξανά όταν αναβαθμιστεί η
 * βιβλιοθήκη.
 *
 * - `volatile` — δίνει **άλλη απάντηση κάθε φορά** (`NOW`, `TODAY`, `RAND`, `RANDBETWEEN`).
 *   Σε φύλλο υπολογισμού είναι χαρακτηριστικό· σε **σχέδιο** είναι ελάττωμα: το DXF είναι
 *   παραδοτέο έγγραφο, και κελί που αλλάζει μόνο του σημαίνει ότι δύο εκτυπώσεις του ίδιου
 *   πίνακα ποσοτήτων δεν συμφωνούν. Δομικά μάλιστα, όχι μόνο σημασιολογικά: ο
 *   επαναϋπολογισμός μας είναι **γράφος εξαρτήσεων**, και μια συνάρτηση χωρίς εισόδους που
 *   όμως αλλάζει τιμή είναι **αόρατη** στον γράφο. *(Το ίδιο το Excel τις ονομάζει
 *   «volatile» και τις ξαναϋπολογίζει σε κάθε αλλαγή· Revit και ArchiCAD απλώς δεν έχουν
 *   καμία τέτοια συνάρτηση.)*
 * - `graph-opaque` — η απάντησή της εξαρτάται από **θέση ή αναφορά** που ο γράφος μας δεν
 *   βλέπει (`ROW`, `ROWS`, `COLUMN`, `COLUMNS`). Δεν είναι θέμα υλοποίησης: ο γράφος χτίζεται
 *   από το **δέντρο**, οπότε μια εξάρτηση που δεν εκφράζεται ως κόμβος δεν μπορεί να
 *   πυροδοτήσει επαναϋπολογισμό — το κελί θα έμενε μπαγιάτικο για πάντα.
 * - `array-result` — επιστρέφει **πίνακα** (`TRANSPOSE`, `SORT`, `UNIQUE`, `LINEST`…). Το
 *   κελί μας κρατά **μία** τιμή· δεν υπάρχει μοντέλο «χυμένου» αποτελέσματος. Χωρίς αυτή την
 *   απόρριψη ο χρήστης θα έπαιρνε `#VALUE!` χωρίς να μάθει γιατί.
 * - `native` — την έχουμε **ήδη**, και η δική μας είναι πιο σωστή. Μετρημένο: `SUM("άλφα")`
 *   δίνει `0` στη βιβλιοθήκη και `#VALUE!` σε εμάς — και το **Excel συμφωνεί με εμάς**.
 * - `special-form` — δεν επιτρέπεται να αξιολογηθούν όλα τα ορίσματά της πριν την κλήση
 *   (`IF`, `IFS`, `CHOOSE`, `SWITCH`) ή πρέπει να **δει** το σφάλμα αντί να της διαδοθεί
 *   (`IFERROR`, `IFNA`). Μόνο ο αξιολογητής μπορεί να μην αξιολογήσει κάτι.
 * - `locale-unsafe` — διαβάζει ή γράφει αριθμό με **αγγλοσαξονική** σύμβαση (`VALUE`,
 *   `NUMBERVALUE`, `TEXT`, `FIXED`, `DOLLAR`, `DATEVALUE`, `TIMEVALUE`). Η ανάγνωση
 *   δεκαδικού είναι ήδη SSoT του ADR-576· δεύτερη ανάγνωση σημαίνει ότι το `1.200,50`
 *   διαβάζεται αλλιώς ανάλογα με το ποια διαδρομή το άγγιξε.
 * - `duplicate` — η **ίδια** συνάρτηση εκτεθειμένη δεύτερη φορά με ισοπεδωμένο όνομα
 *   (`COVARIANCEP` δίπλα στο `COVARIANCE.P`). Δύο κλειδιά για μία σημασία είναι δύο σημεία
 *   αλλαγής.
 * - `not-a-function` — η εξαγωγή **δεν είναι καλέσιμη**. Δεν είναι θεωρητικό: στην 4.6.1 τα
 *   `ERFPRECISE` και `ERFCPRECISE` είναι `undefined`, και τα `STDEV`/`MODE` είναι
 *   **αντικείμενα** χώρου ονομάτων. Αφελής αντιστοίχιση θα κατέγραφε μη-συνάρτηση στο μητρώο
 *   και θα κατέρρεε στην πρώτη κλήση.
 */
export type FormulaLibraryRejection =
  | 'volatile'
  | 'graph-opaque'
  | 'array-result'
  | 'native'
  | 'special-form'
  | 'locale-unsafe'
  | 'duplicate'
  | 'not-a-function';

/** Όλες οι αιτίες, για τον έλεγχο ταυτότητας και για την εξαντλητική τεκμηρίωση. */
export const FORMULA_LIBRARY_REJECTIONS: readonly FormulaLibraryRejection[] = [
  'volatile',
  'graph-opaque',
  'array-result',
  'native',
  'special-form',
  'locale-unsafe',
  'duplicate',
  'not-a-function',
];

/** Μια εγκεκριμένη εξαγωγή: πώς λέγεται για τον χρήστη και πώς της δίνονται τα ορίσματα. */
export interface FormulaLibraryAdmission {
  readonly kind: 'admit';
  /**
   * Το όνομα που **πληκτρολογεί** ο χρήστης, με τη γραφή του Excel. Συχνά διαφέρει από τη
   * διαδρομή στη βιβλιοθήκη: το `CEILING.MATH` του Excel εξάγεται ως `CEILINGMATH`.
   */
  readonly excel: string;
  readonly shape: FormulaLibraryShape;
}

/** Μια απορριφθείσα εξαγωγή, με το **γιατί** δίπλα της. */
export interface FormulaLibraryRefusal {
  readonly kind: 'reject';
  readonly reason: FormulaLibraryRejection;
  /** Το όνομα που θα πληκτρολογούσε ο χρήστης — αυτό ρωτά ο επεξεργαστής όταν εξηγεί. */
  readonly excel: string;
}

/** Η ετυμηγορία για **μία** εξαγωγή της βιβλιοθήκης. */
export type FormulaLibraryVerdict = FormulaLibraryAdmission | FormulaLibraryRefusal;
