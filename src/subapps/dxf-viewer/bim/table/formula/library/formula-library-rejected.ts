import type { FormulaLibraryRejection } from './formula-library-taxonomy';

/**
 * Οι διαδρομές που **δεν** μπαίνουν στο μητρώο, ανά αιτία.
 *
 * ⚠️ Ο πίνακας είναι `Record` πάνω στην ένωση των αιτιών **επίτηδες**: μια ένατη αιτία
 * σπάει τη μεταγλώττιση εδώ μέχρι να αποκτήσει λίστα, αντί να προστεθεί ως ετικέτα που
 * κανείς δεν χρησιμοποιεί.
 */
export const REJECTED_LIBRARY_PATHS: Readonly<
  Record<FormulaLibraryRejection, readonly string[]>
> = {
  /**
   * Άλλη απάντηση κάθε φορά. Το DXF είναι **παραδοτέο**: δύο εκτυπώσεις του ίδιου πίνακα
   * ποσοτήτων οφείλουν να συμφωνούν. Και δομικά — ο γράφος εξαρτήσεων δεν βλέπει συνάρτηση
   * χωρίς εισόδους που όμως αλλάζει τιμή.
   */
  volatile: ['NOW', 'TODAY', 'RAND', 'RANDBETWEEN'],

  /**
   * Απαντούν με βάση **θέση**, που ο γράφος μας δεν παρακολουθεί. Θα έμεναν μπαγιάτικες μετά
   * από εισαγωγή/διαγραφή γραμμής — δηλαδή λάθος αριθμός χωρίς κανένα σφάλμα.
   */
  'graph-opaque': ['ROW', 'ROWS', 'COLUMN', 'COLUMNS'],

  /**
   * Επιστρέφουν **πίνακα**. Το κελί κρατά μία τιμή· δεν υπάρχει μοντέλο «χυμένου»
   * αποτελέσματος (spill), και μια σιωπηλή «πρώτη τιμή» θα ήταν κατασκευασμένη απάντηση.
   *
   * ⚠️ Μετρημένο ότι η ίδια η βιβλιοθήκη τις χειρίζεται λάθος: `SORT([3,1,2])` επιστρέφει
   * `[[3,1,2]]` — **αταξινόμητο**. Ένας ακόμη λόγος να μην περάσουν.
   */
  'array-result': [
    'TRANSPOSE', 'UNIQUE', 'SORT', 'FREQUENCY', 'LINEST', 'LOGEST',
    'TREND', 'GROWTH', 'MUNIT', 'MMULT', 'MODE.MULT', 'HSTACK',
    'VSTACK', 'TAKE', 'DROP', 'EXPAND', 'CHOOSECOLS', 'CHOOSEROWS',
  ],

  /**
   * Τις έχουμε ήδη, **και η δική μας είναι πιο σωστή**.
   *
   * - Οι επτά αριθμητικές: μετρημένο ότι `SUM("άλφα")` δίνει `0` στη βιβλιοθήκη ενώ εμείς
   *   —και το Excel— λέμε `#VALUE!`. Αντικατάστασή τους θα ήταν **οπισθοδρόμηση**.
   * - Οι δώδεκα πληροφοριακές: 🔴 μετρημένο ότι η βιβλιοθήκη αναγνωρίζει τα σφάλματα **κατά
   *   ταυτότητα αντικειμένου** — `ISERROR(new Error('#DIV/0!'))` επιστρέφει **`false`**.
   *   Δηλαδή μια αφελής ανάθεση θα απαντούσε «όχι, δεν είναι σφάλμα» για κάθε σφάλμα του
   *   δικού μας πίνακα: σιωπηλά λάθος, στο ακριβώς χειρότερο σημείο. Άλλωστε το «τι είναι
   *   σφάλμα» είναι **ήδη** SSoT του `table-formula-value.ts`· ανάθεσή του σε ιδιωτικό
   *   πίνακα ξένης βιβλιοθήκης θα ήταν δεύτερος ορισμός ταυτότητας.
   */
  native: [
    'SUM', 'AVERAGE', 'COUNT', 'MIN', 'MAX', 'ABS', 'ROUND',
    'ISERROR', 'ISERR', 'ISNA', 'ISBLANK', 'ISLOGICAL', 'ISNONTEXT',
    'ISNUMBER', 'ISTEXT', 'TYPE', 'ERROR.TYPE', 'N', 'NA',
  ],

  /**
   * Ο αξιολογητής τις κατέχει: ή δεν επιτρέπεται να αξιολογηθούν όλα τα ορίσματα πριν την
   * κλήση (`IF`, `IFS`, `CHOOSE`, `SWITCH`), ή πρέπει να **δουν** το σφάλμα αντί να τους
   * διαδοθεί (`IFERROR`, `IFNA`).
   */
  'special-form': ['IF', 'IFS', 'IFERROR', 'IFNA', 'CHOOSE', 'SWITCH'],

  /**
   * Διαβάζουν ή γράφουν αριθμό με αγγλοσαξονική σύμβαση. Μετρημένο: `VALUE('1.200,50')`
   * δίνει `1.2005`. Η ανάγνωση δεκαδικού είναι SSoT του ADR-576 και μένει εκεί.
   */
  'locale-unsafe': ['VALUE', 'NUMBERVALUE', 'DATEVALUE', 'TIMEVALUE', 'TEXT', 'FIXED', 'DOLLAR'],

  /**
   * Η **ίδια** συνάρτηση, δεύτερη φορά με ισοπεδωμένο όνομα. Το κανονικό (με τελείες)
   * εγκρίνεται και κουβαλά το παλαιό όνομα του Excel ως **ψευδώνυμο** — δες
   * `LEGACY_EXCEL_ALIASES`. Έτσι το `=STDEV(...)` δουλεύει, χωρίς δύο κλειδιά στο μητρώο.
   */
  duplicate: [
    'COVARIANCEP', 'COVARIANCES', 'PERCENTILEEXC', 'PERCENTILEINC',
    'PERCENTRANKEXC', 'PERCENTRANKINC', 'QUARTILEEXC', 'QUARTILEINC',
    'RANKAVG', 'RANKEQ', 'MODEMULT', 'MODESNGL', 'STDEVS', 'VARS',
    'POISSONDIST', 'WEIBULLDIST', 'LOGNORMINV',
  ],

  /**
   * 🔴 Δεν είναι θεωρητικό: στην 4.6.1 τα δύο αυτά ονόματα εξάγονται ως `undefined`.
   * Χωρίς την πύλη, θα κατέληγαν στο μητρώο ως μη-συναρτήσεις.
   */
  'not-a-function': ['ERFPRECISE', 'ERFCPRECISE'],
};
