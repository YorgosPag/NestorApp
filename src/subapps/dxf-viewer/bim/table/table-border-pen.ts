/**
 * 🔴 ADR-739 §37 — **ΠΟΣΟ ΠΑΧΥ ΦΑΙΝΕΤΑΙ ΕΝΑ ΜΟΛΥΒΙ ΠΙΝΑΚΑ ΣΤΗΝ ΟΘΟΝΗ.** Μία απάντηση.
 *
 * Ο κανόνας ήταν γραμμένος **ιδιωτικά μέσα στον ζωγράφο** (`stamp-table-borders.ts`:
 * `Math.max(widthMm * pxPerMm, 0.5)`), δηλαδή ήταν προσβάσιμος μόνο σε όποιον βάφει. Τη
 * στιγμή που απέκτησε **δεύτερο** καταναλωτή — τη γεωμετρία που πρέπει να **αποφύγει** το
 * μολύβι ({@link tableModeOutlineRectMm}) — έπρεπε να βγει, για τον ίδιο ακριβώς λόγο που
 * βγήκε η γεωμετρία της ζώνης στο §27.11: **δύο αντίγραφα του ίδιου αριθμού αποκλίνουν, και
 * αποκλίνουν σιωπηλά.**
 *
 * Εδώ η απόκλιση θα ήταν η χειρότερη δυνατή: ο δείκτης λειτουργίας θα υπολόγιζε ότι
 * απομακρύνθηκε αρκετά από μια γραμμή που στην πραγματικότητα ζωγραφίζεται **παχύτερη** —
 * δηλαδή θα ξαναγεννιόταν ακριβώς το ελάττωμα που ο δείκτης μετακινήθηκε για να λύσει.
 *
 * ## Γιατί υπάρχει δάπεδο
 * Ένα μολύβι 0,13 mm σε σμίκρυνση δίνει κλάσμα του pixel. Ο καμβάς το ζωγραφίζει ως
 * ημιδιαφανή γραμμή που **σβήνει** — και ο πίνακας θα έχανε το πλέγμα του ακριβώς όταν
 * χρειάζεσαι να δεις πού είναι. Το δάπεδο είναι hairline: πάντα **κάτι**, ποτέ τίποτα.
 *
 * @module subapps/dxf-viewer/bim/table/table-border-pen
 * @see rendering/entities/table/stamp-table-borders.ts — ο ένας καταναλωτής (το μελάνι)
 * @see bim/table/table-indicator-geometry.ts — ο άλλος (η θέση που το αποφεύγει)
 */

/**
 * Ελάχιστο πάχος γραμμής πίνακα στην οθόνη — hairline αντί για αόρατη γραμμή.
 *
 * ⚠️ **Δεν είναι στρογγυλοποίηση σε ολόκληρο pixel.** Ο καμβάς ζωγραφίζει το μισό pixel ως
 * ημιδιαφανή γραμμή, που είναι ακριβώς το ζητούμενο σε σμίκρυνση: παρών αλλά διακριτικός.
 */
export const MIN_TABLE_BORDER_SCREEN_PX = 0.5;

/**
 * Το πάχος ενός μολυβιού πίνακα σε **px οθόνης**, στην τρέχουσα κλίμακα.
 *
 * `widthMm` είναι το πάχος σε **sheet-mm** (γεωμετρία σχεδίου, ταξιδεύει σε DXF/PDF/ΤΕΚ)·
 * το αποτέλεσμα είναι px οθόνης (μελάνι). Η μετάφραση ανάμεσά τους γίνεται **εδώ και μόνο**.
 */
export function tableBorderScreenPx(widthMm: number, pxPerMm: number): number {
  return Math.max(widthMm * pxPerMm, MIN_TABLE_BORDER_SCREEN_PX);
}
