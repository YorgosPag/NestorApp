/**
 * ADR-833 Φάση 4 — **Η ΕΠΟΜΕΝΗ ΕΛΕΥΘΕΡΗ ΤΑΥΤΟΤΗΤΑ ΜΕ ΠΡΟΘΕΜΑ**: ο ΕΝΑΣ γεννήτορας των
 * τοπικών ταυτοτήτων του πίνακα (`r0…rN`, `c0…cN`, `ws0…wsN`).
 *
 * ## Γιατί εξήχθη **τώρα**, και όχι όταν θα γίνονταν τρία αντίγραφα
 * Το μοτίβο «μέγιστο επίθεμα + 1, με βρόχο επαλήθευσης» γεννήθηκε στο `nextAxisId`
 * (`table-row-column-ops.ts`) και εξυπηρετούσε **δύο** άξονες μέσα από **ένα** σώμα. Η
 * προσθήκη φύλλου εργασίας είναι ο **τρίτος** καταναλωτής — και το ίδιο το
 * `types/table-worksheet.ts` το είχε **γράψει από πριν**:
 *
 * > *«Η παραγωγή της επόμενης ελεύθερης ταυτότητας ανήκει στη Φάση 4 […] όπου θα είναι το
 * > τρίτο αντίγραφο του μοτίβου “μέγιστο+1 με βρόχο επαλήθευσης” του `nextAxisId` […] και
 * > **τότε** θα εξαχθεί σε κοινό SSoT.»*
 *
 * Αυτό είναι το «τότε». Η εξαγωγή γίνεται **πριν** γραφτεί ο δεύτερος γραφέας, ακριβώς όπως
 * το `stamp-table-control-disc.ts` και το `stamp-table-chrome-rect.ts` — ώστε ο κλώνος να μη
 * γεννηθεί ποτέ (N.18 / CHECK 3.28), και όχι να πιαστεί αφού γεννηθεί.
 *
 * ## 🔴 ΤΟ ΑΚΡΙΒΟ ΔΕΝ ΕΙΝΑΙ ΟΙ ΓΡΑΜΜΕΣ — ΕΙΝΑΙ Ο ΒΡΟΧΟΣ ΕΠΑΛΗΘΕΥΣΗΣ
 * Το «μέγιστο+1» φαίνεται αυτονόητο και είναι, από μόνο του, **λάθος**: ένας πίνακας που
 * κουβαλά χειροποίητο `c9` **χωρίς** `c0…c8` δίνει μέγιστο 9 ⇒ επόμενο `c10`, σωστά· αλλά ένας
 * που κουβαλά **μόνο** `c9` δίνει μέγιστο... 9 και επόμενο `c10` — ενώ ένας που κουβαλά
 * ταυτότητες **εκτός μοτίβου** (τα `d0` του adapter του ADR-622) δίνει μέγιστο 0 ⇒ επόμενο
 * `c0`, που μπορεί κάλλιστα να **υπάρχει ήδη**. Ο τελικός βρόχος είναι εκείνος που κάνει τη
 * σύγκρουση **μη εκφράσιμη**, και είναι ακριβώς το κομμάτι που ξεχνά κάθε δεύτερο αντίγραφο.
 *
 * ## Ντετερμινιστικός, ποτέ `crypto`
 * Οι ταυτότητες είναι **τοπικές στον πίνακα** και ο κανόνας N.6 (enterprise IDs) δεν
 * εφαρμόζεται εδώ — δες `build-table-entity.ts` για το γιατί. Το κέρδος του ντετερμινισμού
 * είναι μετρήσιμο: σταθερό JSON για την ίδια ακολουθία πράξεων, δοκιμάσιμο χωρίς mock, και
 * «σχέδιο που μόνο διαβάστηκε μένει byte-identical» (δες {@link FIRST_TABLE_WORKSHEET_ID}).
 *
 * @module subapps/dxf-viewer/bim/table/table-next-id
 * @see bim/table/table-row-column-ops.ts — ο πρώτος καταναλωτής (γραμμές + στήλες)
 * @see bim/table/table-worksheet-ops.ts — ο δεύτερος (φύλλα εργασίας)
 * @see docs/centralized-systems/reference/adrs/ADR-833-table-xlsx-import-and-worksheets.md §5.4
 */

/**
 * Η επόμενη ελεύθερη ταυτότητα της μορφής `<prefix><αριθμός>` για το δοθέν σύνολο.
 *
 * Αγνοεί ό,τι δεν ακολουθεί το μοτίβο: δεν χρειάζεται να **κατανοήσει** ξένες ταυτότητες,
 * μόνο να **μη συγκρουστεί** μαζί τους — και γι' αυτό ο βρόχος επαλήθευσης δεν είναι
 * προαιρετικός (δες την κεφαλίδα).
 *
 * @param existingIds Όλες οι ταυτότητες που είναι ήδη πιασμένες στον **ίδιο** χώρο ονομάτων.
 * @param prefix Το πρόθεμα του χώρου (`'r'`, `'c'`, `'ws'`). Ο καλών το κρατά σταθερό —
 *   δύο προθέματα για τον ίδιο χώρο θα ήταν δύο ονόματα για το ίδιο πράγμα.
 */
export function nextPrefixedId(existingIds: readonly string[], prefix: string): string {
  const taken = new Set(existingIds);
  // `u` για ίδια σημασιολογία με τον πρώτο καταναλωτή· το πρόθεμα είναι σταθερά του κώδικα
  // (`r` / `c` / `ws`), ποτέ είσοδος χρήστη, άρα δεν υπάρχει τι να διαφύγει.
  const pattern = new RegExp(`^${prefix}(\\d+)$`, 'u');

  let next = 0;
  for (const id of existingIds) {
    const match = pattern.exec(id);
    if (match) next = Math.max(next, Number.parseInt(match[1], 10) + 1);
  }
  // 🔴 Δες την κεφαλίδα: **αυτός** ο βρόχος είναι η εξαγωγή. Χωρίς αυτόν, ένα σύνολο με
  // ταυτότητες εκτός μοτίβου (ή με χειροποίητο κενό) γεννά όνομα που ήδη υπάρχει — και ο
  // αραιός χάρτης κελιών θα έδειχνε τα κελιά του παλιού στοιχείου στο νέο.
  while (taken.has(`${prefix}${next}`)) next++;
  return `${prefix}${next}`;
}
