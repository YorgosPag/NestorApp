/**
 * 🔴 ADR-739 §48 — **Η ΦΑΣΗ ΤΩΝ «ΜΥΡΜΗΓΚΙΩΝ»**: πού βρίσκεται το διακεκομμένο μοτίβο τη
 * στιγμή `t`, και **προς ποια φορά** τρέχει.
 *
 * Καθαρή συνάρτηση του χρόνου, σε δικό της αρχείο, επειδή είναι το **μόνο** σημείο όπου
 * ζει αριθμητική — και επειδή είναι το μόνο σημείο που μπορεί να ελεγχθεί ντετερμινιστικά.
 * Ο ζωγράφος παίρνει έτοιμο αριθμό· ο παλμός δεν ξέρει τίποτα για μοτίβα.
 *
 * ## 🔴 ΓΙΑΤΙ ΑΡΝΗΤΙΚΟ OFFSET = ΔΕΞΙΟΣΤΡΟΦΗ ΚΙΝΗΣΗ (η μία μη προφανής γραμμή)
 *
 * Δύο ανεξάρτητα γεγονότα συνθέτουν την απάντηση, και κανένα από τα δύο δεν είναι διαίσθηση:
 *
 * 1. **Η φορά χάραξης είναι δεξιόστροφη στην οθόνη.** Το `appendRectSubpath`
 *    (`stamp-table-layout.ts`) χαράζει `(x,y) → (x+w,y) → (x+w,y+h) → (x,y+h)` σε **sheet-mm
 *    του πλαισίου**, και το `toScreen` κατέχει την αναστροφή του y. Άρα στην οθόνη η σειρά
 *    είναι πάνω-αριστερά → πάνω-δεξιά → κάτω-δεξιά → κάτω-αριστερά, δηλαδή **δεξιόστροφα**.
 *
 * 2. **Το `lineDashOffset` μετακινεί το μοτίβο ΑΝΤΙΘΕΤΑ στη φορά χάραξης.** Ορίζει «πόσο
 *    μέσα στο μοτίβο βρισκόμαστε όταν ξεκινά η διαδρομή»· αυξάνοντάς το, κάθε παύλα φαίνεται
 *    να **οπισθοχωρεί** κατά μήκος της διαδρομής.
 *
 * ⇒ Για κίνηση **κατά** τη φορά χάραξης, το offset πρέπει να **μειώνεται**. Γι' αυτό η
 * επιστροφή είναι στο διάστημα `(-period, 0]` και ποτέ θετική.
 *
 * ⚠️ Η φορά ακολουθεί το **πλαίσιο του πίνακα**, όχι την οθόνη: σε περιστραμμένο πίνακα τα
 * μυρμήγκια τρέχουν γύρω από τα **κελιά**, που είναι το σωστό — η αντιγραφή αφορά κελιά.
 *
 * @module subapps/dxf-viewer/bim/table/table-marching-ants
 * @see rendering/entities/table/stamp-table-copy-marquee.ts — ο ένας καταναλωτής
 * @see state/table-copy-marquee-pulse.ts — ποιος ζητά τα καρέ
 */

/**
 * Το μοτίβο σε **px οθόνης** — ίδια μονάδα και ίδιος λόγος με το `TABLE_MODE_OUTLINE.dashPx`:
 * ο δείκτης πρέπει να φαίνεται ίδιος σε κάθε zoom.
 *
 * ## 🔴 ΤΟ `[7,2]` ΕΙΝΑΙ ΜΕΤΡΗΜΕΝΟ ΑΠΟ ΤΟ ΙΔΙΟ ΤΟ EXCEL — δεν είναι γούστο
 *
 * Ανάγνωση εικονοστοιχείων από στιγμιότυπο του Excel (`2026-08-05 212519.jpg`, ένα κελί μετά
 * από `Ctrl+C`), με **υποεικονοστοιχειακά όρια στο 50% της μετάβασης μελάνι→χαρτί** στο κανάλι
 * R — όχι με το μάτι, και όχι με κατώφλι «πράσινο/όχι πράσινο» που διογκώνει την παύλα κατά το
 * μισό της ασάφειας του JPEG σε **κάθε** άκρη:
 *
 * ```
 *   παύλα   43,87 px εικόνας   (7 μετρήσεις: 43,62 43,83 43,97 43,99 43,86 43,94)
 *   κενό    11,96 px εικόνας   (11,75 12,12 11,93 11,93 11,96 12,00 12,01)
 *   πάχος    6,00 px εικόνας
 * ```
 *
 * Η βαθμονόμηση είναι το κρίσιμο σημείο, και γι' αυτό έγινε **δύο φορές ανεξάρτητα** μέσα στην
 * ίδια εικόνα — αν έπεφτε έξω, θα έπεφταν έξω και τα τρία νούμερα μαζί, γραμμικά:
 *
 * ```
 *   ύψος γραμμής   124,0 px εικόνας ÷ 20 px (προεπιλογή Excel)  ⇒ 6,20×
 *   πλάτος στήλης  401,0 px εικόνας ÷ 64 px (προεπιλογή Excel)  ⇒ 6,27×   ✔ συμφωνούν σε 1%
 * ```
 *
 * ⇒ **παύλα 7,04 · κενό 1,92 · πάχος 0,96** σε px οθόνης. Η περίοδος βγαίνει **8,96 ≈ 9** και
 * το πάχος **≈ 1** — δύο ακέραιοι που *δεν* επιβλήθηκαν: αν ο συντελεστής ήταν λάθος, θα
 * έβγαιναν άσχημοι αριθμοί. Αυτό είναι το τρίτο, σιωπηλό τεκμήριο ότι η βαθμονόμηση στέκει.
 *
 * ⚠️ **Γιατί δεν χρειάζεται να ξέρουμε το zoom του Excel ή την κλίμακα οθόνης**: η μεγέθυνση —
 * όποια κι αν είναι η πηγή της — μεγεθύνει **και** τη γραμμή **και** τα μυρμήγκια. Η μόνη
 * υπόθεση που θα την έσπαγε είναι «τα μυρμήγκια είναι αμετάβλητα στο zoom **και** η μεγέθυνση
 * ήρθε από το zoom», που αυτοαναιρείται: τότε το πραγματικό πάχος θα ήταν 6 px οθόνης, δηλαδή
 * **30% του ύψους ενός κελιού**. Δεν είναι.
 *
 * ## Γιατί `[7,2]` και όχι `[6,3]`
 * Το ίδιο **αποτύπωμα** παράγεται και από `[6,3]` με τετράγωνα άκρα (`lineCap = 'square'`, που
 * προεκτείνει κάθε παύλα κατά μισό πάχος σε κάθε άκρη ⇒ 6+1 / 3−1). Ο δικός μας χάρακας
 * (`strokeRectMm`) **δεν** αγγίζει το `lineCap`, άρα κληρονομεί το προεπιλεγμένο `'butt'` του
 * καμβά — και με `'butt'` το `[7,2]` δίνει **ακριβώς** το μετρημένο αποτύπωμα. Αντιγράφουμε ό,τι
 * **βλέπει** ο χρήστης, όχι μια εικασία για το τι έγραψε η Microsoft.
 *
 * ## Γιατί ξεχωρίζει από το `[6,4]` της λειτουργίας πίνακα
 * Τα δύο διακεκομμένα ζουν **ταυτόχρονα** γύρω από τα ίδια κελιά (δες §48 στο ADR). Η διάκριση
 * δεν στηρίζεται στα ίδια τα νούμερα αλλά στην **πυκνότητα μελανιού**: 7/9 = **78%** εδώ έναντι
 * 6/10 = **60%** εκεί, και επιπλέον **μισό πάχος** (1 px έναντι 2). Το πάχος είναι το κανάλι που
 * επιβιώνει στη σμίκρυνση, όπου δύο μοτίβα συγχέονται πρώτα.
 *
 * ℹ️ Για την ιστορία: το LibreOffice Calc — ανοιχτός κώδικας, άρα **αναγνώσιμη** πηγή αντί για
 * εικασία — δίνει `[4,4]` hairline (`ScOverlayDashedBorder` → `OverlayManager::getStripeLengthPixel()`,
 * με προεπιλογή `Drawinglayer/StripeLength = 4`). Δηλαδή το προηγούμενο `[4,4]` **δεν ήταν λάθος**·
 * ήταν το μοτίβο του *Calc*. Ο ιδιοκτήτης ζήτησε ρητά **Excel**, που είναι πυκνότερο και λεπτότερο.
 */
export const MARCHING_ANTS_EXCEL_DASH_PX = [7, 2] as const;

/**
 * 🔴 §48.10 — **Ο ΕΝΑΣ ΜΟΧΛΟΣ ΤΗΣ ΕΜΦΑΝΙΣΗΣ.** Πόσες φορές μεγαλύτερο από το μετρημένο
 * αποτύπωμα του Excel ζωγραφίζεται το μοτίβο εδώ.
 *
 * ── Γιατί υπάρχει καθόλου, αφού μετρήσαμε το Excel ──
 * Επειδή **η ισοδυναμία σε px δεν είναι ισοδυναμία στο μάτι όταν αλλάζει η γεωμετρία γύρω της.**
 * Στο Excel το κελί είναι σταθερά ~64×20 px, οπότε παύλα 7 px είναι ~11% της πλευράς και
 * διαβάζεται άνετα. Εδώ ο πίνακας είναι **σχέδιο σε καμβά**: το ίδιο κελί μπορεί να καλύπτει
 * εκατοντάδες px οθόνης σε μεγέθυνση, και τότε η ίδια παύλα 7 px γίνεται ~1% της πλευράς —
 * τυπικά **σωστή** και οπτικά **ψίχουλο**. Ο ιδιοκτήτης το είδε ζωντανά και το ανέφερε
 * (2026-08-05): «τα μυρμήγκια φαίνονται πολύ μικρά».
 *
 * ── 🔑 Γιατί ΚΛΙΜΑΚΑ και όχι νέο μοτίβο γραμμένο με το χέρι ──
 * Ένα χειρόγραφο `[14, 4]` θα ήταν **σβήσιμο της μέτρησης**: μετά από δύο εβδομάδες κανείς δεν
 * θα ήξερε αν προήλθε από το Excel ή από γούστο, και το §48.6 θα διάβαζε ψέματα. Έτσι η
 * μέτρηση μένει **ακέραιη και ελέγξιμη** ({@link MARCHING_ANTS_EXCEL_DASH_PX}), και η απόκλιση
 * από αυτήν είναι **ένας αριθμός με όνομα** — δηλώνει ρητά «ξέρουμε τι λέει το Excel, και
 * αποκλίνουμε συνειδητά τόσο».
 *
 * ⚠️ **ΔΟΚΙΜΑΣΤΙΚΗ ΤΙΜΗ** — αυτή είναι η **μόνη** γραμμή που αλλάζει σε μια δοκιμή μεγέθους.
 * Ο λόγος 7:2 (78% πυκνότητα μελανιού) και ο ρυθμός των 2,5 περιόδων/δευτ **επιβιώνουν
 * αυτόματα** σε κάθε τιμή, επειδή και τα δύο είναι παράγωγα και όχι αντίγραφα.
 */
export const MARCHING_ANTS_DASH_SCALE = 3;

/**
 * Το μοτίβο όπως φτάνει στον καμβά, σε px οθόνης — **παράγωγο**, ποτέ γραμμένο.
 */
export const MARCHING_ANTS_DASH_PX = MARCHING_ANTS_EXCEL_DASH_PX.map(
  (segment) => segment * MARCHING_ANTS_DASH_SCALE,
) as readonly number[];

/**
 * Το μετρημένο **πάχος** της γραμμής του Excel, σε px οθόνης: 6,00 px εικόνας ÷ 6,2 = **0,96**.
 * Δες §48.6 για τη μέθοδο — είναι η ίδια μέτρηση, στην ίδια εικόνα, με την ίδια βαθμονόμηση.
 */
export const MARCHING_ANTS_EXCEL_LINE_WIDTH_PX = 1;

/**
 * 🔴 §48.11 — Το πάχος **ακολουθεί την κλίμακα**, και αυτό διορθώνει σφάλμα του §48.6.
 *
 * ── Τι είχε γραφτεί λάθος ──
 * Το §48.6 τεκμηρίωσε ότι το πάχος **πρέπει** να πέσει στο 1 px, με επιχείρημα «το μετρημένο κενό
 * είναι 2 px, άρα πάνω σε γραμμή 2 px το μοτίβο διαβάζεται συμπαγές». Το επιχείρημα ήταν σωστό
 * **μόνο στην κλίμακα 1×**. Από τη στιγμή που μπήκε το {@link MARCHING_ANTS_DASH_SCALE}, το κενό
 * μεγαλώνει **μαζί** με το πάχος και ο περιορισμός **παύει να υπάρχει**: στο ×3 το κενό είναι 6 px
 * και μια γραμμή 3 px διαβάζεται άνετα ως διακεκομμένη.
 *
 * Ήταν, δηλαδή, συμπέρασμα δεμένο σε μια παραδοχή που η επόμενη αλλαγή κατέρριψε — και επέζησε
 * επειδή ήταν γραμμένο ως **κανόνας** αντί για **συνθήκη**. Ο ιδιοκτήτης το είδε ζωντανά:
 * «η γραμμή με τα μυρμήγκια είναι πολύ λεπτή» (2026-08-05).
 *
 * ── Γιατί παράγωγο και όχι δεύτερος μοχλός ──
 * Το ζητούμενο δεν είναι «μοτίβο του Excel + ένα πάχος που διαλέγουμε»· είναι **«το marquee του
 * Excel, N× μεγαλύτερο»**. Ο λόγος παύλα:κενό:πάχος = **7:2:1** είναι η ταυτότητά του, και μένει
 * αναλλοίωτος εξ ορισμού σε κάθε κλίμακα. Δύο ανεξάρτητοι μοχλοί θα επέτρεπαν συνδυασμούς που
 * **δεν είναι** το Excel σε καμία κλίμακα, χωρίς τίποτα να το δηλώνει.
 *
 * ⚠️ Στο ×2 επιστρέφει ακριβώς στα 2 px του {@link TABLE_CELL_CURSOR} — δηλαδή η «ρητή
 * παρέκκλιση» του §48.6 από το WCAG **εξαφανίζεται** για κάθε ακέραια κλίμακα ≥ 2.
 */
export const MARCHING_ANTS_LINE_WIDTH_PX =
  MARCHING_ANTS_EXCEL_LINE_WIDTH_PX * MARCHING_ANTS_DASH_SCALE;

/** Το μήκος μιας πλήρους επανάληψης του μοτίβου, σε px οθόνης. */
export const MARCHING_ANTS_PERIOD_PX =
  MARCHING_ANTS_DASH_PX.reduce((sum, segment) => sum + segment, 0);

/**
 * 🔴 Οι περίοδοι που διανύει το μοτίβο ανά δευτερόλεπτο — **η αναλλοίωτη ποσότητα** του §48,
 * και γι' αυτό η **πρωταρχική**: αυτό ακριβώς αντιλαμβάνεται το μάτι ως «ταχύτητα».
 *
 * 2,5 περίοδοι/δευτ: η κίνηση διαβάζεται ως «ζωντανό» χωρίς να τραβά το βλέμμα από το σχέδιο.
 * Ένα σχεδιαστικό εργαλείο δεν επιτρέπεται να έχει στοιχείο διεπαφής που ανταγωνίζεται το
 * περιεχόμενο.
 */
export const MARCHING_ANTS_CYCLES_PER_SEC = 2.5;

/**
 * Πόσα px οθόνης διανύει το μοτίβο ανά δευτερόλεπτο — **παράγωγο του ρυθμού**, με αυτή τη σειρά
 * και όχι την αντίστροφη.
 *
 * ── 🔴 Γιατί αντιστράφηκε η εξάρτηση (§48.10) ──
 * Μέχρι τις 2026-08-05 αυτή ήταν κυριολεκτική σταθερά (20, μετά 22,5) και ο ρυθμός έβγαινε ως
 * πηλίκο. Ήταν **αντεστραμμένο**: η ταχύτητα σε px/s δεν είναι μέγεθος που κάποιος αποφασίζει —
 * είναι αυτό που *προκύπτει*. Με τη σταθερά στη λάθος άκρη, **κάθε** αλλαγή μοτίβου άλλαζε
 * σιωπηλά τον ρυθμό, και η μόνη άμυνα ήταν να το θυμηθεί ο επόμενος (πήγε ήδη να συμβεί μία
 * φορά: περίοδος 8 → 9 θα είχε ρίξει τον ρυθμό κατά 11% χωρίς καμία γραμμή να το δηλώνει).
 *
 * Τώρα το λάθος είναι **μη εκφράσιμο**: αλλάζοντας το {@link MARCHING_ANTS_DASH_SCALE}, η
 * ταχύτητα ακολουθεί μόνη της και ο ρυθμός μένει 2,5 — δεν υπάρχει τίποτα να ξεχαστεί.
 */
export const MARCHING_ANTS_SPEED_PX_PER_SEC =
  MARCHING_ANTS_CYCLES_PER_SEC * MARCHING_ANTS_PERIOD_PX;

/**
 * Η φάση του μοτίβου μετά από `elapsedMs` χιλιοστά του δευτερολέπτου.
 *
 * Πάντα στο `(-MARCHING_ANTS_PERIOD_PX, 0]`: το τύλιγμα δεν είναι καλλωπισμός — χωρίς αυτό ο
 * αριθμός θα μεγάλωνε απεριόριστα και, μετά από αρκετή ώρα, θα έχανε ακρίβεια κινητής
 * υποδιαστολής ακριβώς στο μέγεθος του βήματος (~1,8 px ανά παλμό 80 ms), δηλαδή η κίνηση θα «κόλλαγε» σε
 * ένα περίγραμμα που έμεινε ανοιχτό όλη μέρα.
 *
 * Αρνητικός χρόνος δεν είναι εκφράσιμος στην πράξη (ο παλμός δίνει πάντα `now - startedAt`),
 * αλλά ο τελεστής `%` της JavaScript κρατά το πρόσημο του αριστερού μέλους — οπότε ο
 * περιορισμός γράφεται ρητά ώστε ένα μελλοντικό «γύρνα την κίνηση πίσω» να μη γεννήσει
 * θετικό offset, δηλαδή σιωπηλή αντιστροφή φοράς.
 */
export function marchingAntsDashOffsetPx(elapsedMs: number): number {
  const travelledPx = (Math.max(0, elapsedMs) / 1000) * MARCHING_ANTS_SPEED_PX_PER_SEC;
  const phasePx = travelledPx % MARCHING_ANTS_PERIOD_PX;
  // Ο ρητός κλάδος του μηδενός δεν είναι περιττός: το `-(0 % n)` είναι **`-0`**, που είναι
  // λειτουργικά ταυτόσημο για τον καμβά αλλά σπάει κάθε `toBe(0)` (`Object.is(-0, 0) === false`).
  // Μια συνάρτηση που επιστρέφει δύο διαφορετικά μηδενικά είναι συνάρτηση που δεν μπορεί να
  // ελεγχθεί καθαρά — και η φορά της κίνησης **είναι** ο έλεγχος του προσήμου.
  return phasePx === 0 ? 0 : -phasePx;
}
