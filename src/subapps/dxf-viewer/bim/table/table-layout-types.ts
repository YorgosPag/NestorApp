/**
 * Ένα κομμάτι κειμένου έτοιμο προς ζωγραφική. Το `position` είναι το **σημείο
 * αγκύρωσης** που ταιριάζει στο `hAlign` (αριστερή / μεσαία / δεξιά ακμή του κειμένου)
 * και το `y` είναι η **γραμμή βάσης** — ακριβώς η σύμβαση του `TextPrimitive`, ώστε η
 * μετατροπή σε `DetailPrimitive` να είναι αντιγραφή πεδίων.
 */
export interface TableTextRunBase {
  readonly position: Point2D;
  /**
   * Το **ορατό** κείμενο — ήδη περικομμένο στο όριο του κελιού (ADR-739 Φ.Δ βήμα 5,
   * `table-cell-overflow.ts`). **ΔΕΝ** είναι το κείμενο του μοντέλου: το `TableCell.value`
   * μένει ακέραιο και είναι αυτό που διαβάζει ο in-cell επεξεργαστής.
   */
  readonly text: string;
  /** Ύψος κεφαλαίου γράμματος σε sheet-mm. */
  readonly heightMm: number;
  /**
   * 🔴 ADR-739 §38 — **εγγυημένα πραγματικό `#rrggbb`.** Το αυτόματο μελάνι
   * (`AUTOMATIC_TABLE_INK`) ζει μόνο στο **στυλ** και επιλύεται στο `placeCells`, με την
   * επιφάνεια ως ρητό όρισμα ({@link TableLayoutOptions.surfaceHex}). Κάθε καταναλωτής αυτού
   * του πεδίου — `ctx.fillStyle`, `hexToTrueColor`, `applyPlotColor`, το CSS του επεξεργαστή —
   * θα δεχόταν το σεντινέλι **χωρίς να πετάξει σφάλμα**, με πέντε διαφορετικές σιωπηλές
   * συμπεριφορές. Η εγγύηση είναι δομική, όχι σύμβαση.
   */
  readonly colorHex: string;
  readonly hAlign: TextAlign;
  readonly bold: boolean;
  /** ADR-739 Φ.Ε — πλάγια γραφή. */
  readonly italic: boolean;
  /**
   * ADR-739 Φ.Ε (Α3) — η οικογένεια που **και** μετρήθηκε **και** ζωγραφίζεται. Απούσα ⇒ η
   * προεπιλογή του μετρητή.
   *
   * 🔴 Ταξιδεύει στο run και δεν ξαναδιαβάζεται από το στυλ στον ζωγράφο: μέχρι τη Φ.Ε ο
   * καμβάς ζωγράφιζε **καρφωτά** Arial ενώ η διάταξη μετρούσε ό,τι έλεγε το στυλ. Δύο
   * απαντήσεις στην ίδια ερώτηση σημαίνει κείμενο που κόβεται ή αφήνει κενό — και το πιο
   * ύπουλο, μόνο για όσους δηλώσουν άλλη γραμματοσειρά.
   */
  readonly fontFamily?: string;
  /**
   * `true` **μόνο** όταν το κείμενο δεν χώρεσε και κόπηκε· απόν αλλιώς.
   *
   * ## Γιατί προαιρετικό-όταν-αληθές και όχι `boolean`
   * Ίδιος λόγος με το `dashMm` του `borderPrimitive`: ένα ρητό `clipped: false` θα άλλαζε το
   * **σχήμα** κάθε μη-περικομμένου run και μαζί κάθε snapshot που ήδη κλειδώνει τη
   * συμπεριφορά των φύλλων οπλισμού (ADR-622 χαρακτηρισμός), χωρίς καμία οπτική διαφορά.
   *
   * ## Ποιος το χρειάζεται
   * Ο δείκτης («…» / «###») είναι **μέσα** στο `text` — άρα ο ζωγράφος δεν χρειάζεται αυτό
   * το πεδίο. Το χρειάζεται (α) το test που αποδεικνύει ότι και τα τέσσερα backends βλέπουν
   * την ίδια απόφαση, και (β) το **επόμενο** βήμα: ο επεξεργαστής που επεκτείνεται πέρα από
   * το κελί ρωτά ακριβώς αυτό — «κρύβει αυτό το κελί κείμενο;».
   */
  readonly clipped?: true;
  /**
   * 🔴 ADR-739 §59 Δ1 — η **γωνία του κειμένου μέσα στο κελί**, σε μοίρες, θετικές προς τα
   * πάνω. Απόν ⇒ οριζόντιο, δηλαδή σε **κάθε** πίνακα που υπάρχει σήμερα στον δίσκο.
   *
   * ## Είναι ΕΠΙΠΛΕΟΝ της γωνίας του πίνακα, ποτέ αντ' αυτής
   * Και τα τέσσερα backends γέρνουν ήδη ολόκληρο τον πίνακα (`TableEntity.angleRad`). Αυτό εδώ
   * **προστίθεται**: ο ζωγράφος του καμβά, η αποδόμηση εξαγωγής, το 3Δ και ο επεξεργαστής
   * κελιού αθροίζουν τα δύο. Ένα πεδίο που **αντικαθιστούσε** τη γωνία του πίνακα θα ίσιωνε
   * σιωπηλά κάθε γερμένο πίνακα τη στιγμή που κάποιος έγερνε ένα κελί του.
   *
   * ## Γιατί «απόν όταν είναι μηδέν», όπως το {@link clipped}
   * Ένα ρητό `rotationDeg: 0` θα άλλαζε το **σχήμα** κάθε run του έργου — και μαζί κάθε
   * χαρακτηρισμένο στιγμιότυπο των φύλλων οπλισμού (ADR-622) — για μηδέν οπτική διαφορά.
   */
  readonly rotationDeg?: number;
  /**
   * 🔴 ADR-751 — τα **τμήματα του κειμένου που είναι διευθύνσεις** (e-mail, ιστοσελίδα,
   * τηλέφωνο), τοποθετημένα. Απόν όταν το κελί δεν έχει καμία — δηλαδή στη συντριπτική
   * πλειονότητα των κελιών ενός πίνακα ποσοτήτων.
   *
   * ## Γιατί το ίδιο σχήμα «παρόν μόνο όταν υπάρχει» με το {@link clipped}
   * Ένα ρητό `links: []` σε κάθε κελί θα άλλαζε το σχήμα **κάθε** run και μαζί κάθε snapshot
   * που κλειδώνει σήμερα τα φύλλα οπλισμού, χωρίς καμία οπτική διαφορά.
   *
   * ## Ποιος αποφασίζει
   * Ο ανιχνευτής είναι το `@/lib/validation/text-link-segments` — το **ίδιο** που διαβάζει
   * τις πινακίδες DXF. Η τοποθέτηση (ποιο mm) γίνεται στο `table-cell-link-spans.ts` με τον
   * **ίδιο** `TableTextMeasurer` που αποφάσισε τα πλάτη στηλών και την περικοπή: αν τα
   * τμήματα μετριόνταν με δεύτερο όργανο, η μπλε υπογράμμιση θα κάθιζε δίπλα στα γράμματα
   * αντί από κάτω τους — ακριβώς το ελάττωμα που πλήρωσε η Φ.Ε με το `advanceMm`.
   */
  readonly links?: readonly TableTextLinkSpan[];
  /**
   * 🔴 ADR-753 Φ2 — τα **ομοιογενή τμήματα** του ορατού κειμένου, όταν το κελί έχει
   * μορφοποίηση ανά χαρακτήρα. Απόν όταν δεν έχει — δηλαδή σε **κάθε** πίνακα που υπάρχει
   * σήμερα στον δίσκο.
   *
   * ## 🔴 Γιατί ΔΕΝ είναι το ίδιο πράγμα με τα {@link links} — η διάκριση είναι μετρική
   * Και τα δύο περιγράφουν «ένα κομμάτι του κειμένου με δική του εμφάνιση», και όμως δεν
   * μπορούν να ενωθούν σε μία λίστα, γιατί απαντούν σε **διαφορετικό ερώτημα ζωγραφικής**:
   *
   * ```
   *   links →  αλλάζει ΧΡΩΜΑ            →  μετρικά ΟΥΔΕΤΕΡΟ  →  μία διάταξη glyph, N περάσματα
   *   spans →  αλλάζει ΓΡΑΜΜΑΤΟΣΕΙΡΑ    →  μετρικά ΚΑΘΟΡΙΣΤΙΚΟ → N διατάξεις glyph
   * ```
   *
   * Ο καμβάς ζωγραφίζει σήμερα τα μικτά links ξαναγράφοντας **ολόκληρο** το string μέσα σε
   * αποκοπή (`stamp-table-text.ts`): όλα τα περάσματα παράγουν **ταυτόσημες** θέσεις glyph,
   * άρα κανένα ζεύγος kerning δεν χάνεται και οι θέσεις των τμημάτων προκύπτουν σωστά από
   * **προθέματα του ίδιου string**. Το τέχνασμα δουλεύει **ακριβώς επειδή** το χρώμα δεν
   * αλλάζει πλάτος.
   *
   * Ένα span με άλλο βάρος ή μέγεθος το ακυρώνει: τα δύο περάσματα θα τοποθετούσαν τον ίδιο
   * χαρακτήρα σε **άλλο x**, οπότε η αποκοπή θα έκοβε στη μέση γράμματα. Άρα τα spans
   * ζωγραφίζονται **διαδοχικά**, και η θέση καθενός είναι το άθροισμα των προηγούμενων
   * advances — μετρημένων το καθένα με **το δικό του** στυλ.
   *
   * ## Η συνέπεια που κρατά το ADR-751 ανέπαφο
   * Χωρίς runs υπάρχει **ένα** τμήμα, άρα το άθροισμα είναι κενό και το πρόθεμα μετριέται
   * μέσα του με το στυλ του κελιού: **byte-για-byte** η σημερινή αριθμητική. Η υπογράμμιση
   * των συνδέσμων δεν μετακινείται ούτε κατά ένα mm.
   *
   * @see bim/table/table-cell-styled-spans.ts — πού γεννιούνται και πώς τοποθετούνται
   */
  readonly spans?: readonly TableTextStyleSpan[];
}

/**
 * 🔴 ADR-753 Φ2 — ένα **ομοιογενές τμήμα** του ορατού κειμένου ενός κελιού: μία γραμματοσειρά,
 * ένα βάρος, ένα μέγεθος, ένα χρώμα, άρα **μία** κλήση σχεδίασης.
 *
 * ## Γιατί το ίδιο λεξιλόγιο με το {@link TableTextLinkSpan}
 * `text` + `offsetMm` + `advanceMm` είναι ήδη η απάντηση του έργου στο «πού κάθεται ένα
 * κομμάτι γραμμής» — τη δίνουν το `TextLayoutSpan` του MTEXT και το ADR-751. Τρίτο λεξιλόγιο
 * θα ήταν structural clone ανεξάρτητα ονομάτων (N.18 / CHECK 3.28).
 *
 * ## Γιατί κουβαλά ΚΑΙ τους δείκτες, σε αντίθεση με το link span
 * Το `[start, end)` απαντά στο «πού είναι ο χαρακτήρας k» — το ερώτημα του
 * `styledPrefixWidthMm`, που εντοπίζει τον δείκτη στο τμήμα του και μετρά το πρόθεμα **μέσα
 * σε αυτό** με το στυλ του. Χωρίς δείκτες κάθε πρόθεμα θα απαιτούσε γραμμική αναζήτηση με
 * αθροίσματα μηκών, δηλαδή δεύτερη απάντηση στο ίδιο ερώτημα.
 *
 * 🔴 **Διόρθωση, ADR-753 Φ3 (μετρημένο).** Μέχρι τη Φ3 εδώ έγραφε ότι οι δείκτες υπάρχουν
 * «ώστε ο ζωγράφος να τμήσει τα δύο επίπεδα». **Δεν τους χρησιμοποιεί για αυτό, και δεν
 * μπορεί**: το {@link TableTextLinkSpan} **δεν κουβαλά δείκτες** — μόνο `offsetMm`/`advanceMm`
 * — άρα η τομή σε χώρο δεικτών δεν είναι καν εκφράσιμη. Η τομή γίνεται σε **mm**
 * (`tablePieceLinkStrips`), που είναι ούτως ή άλλως ό,τι ζητά η αποκοπή, και είναι ακριβής
 * χωρίς ανοχή: πάνω σε όριο τμήματος το `styledPrefixWidthMm` επιστρέφει το `offsetMm`
 * **αυτούσιο**. Οι δείκτες δικαιώνονται αλλού — απλώς όχι εκεί που έλεγε το σχόλιο.
 *
 * Οι δείκτες αναφέρονται στο **ορατό** κείμενο ({@link TableTextRunBase.text}), όχι στο
 * `TableCell.value`: μετά την περικοπή οι δύο δεν αντιστοιχούν, και η μόνη συμβολοσειρά που
 * ο ζωγράφος κρατά στα χέρια του είναι η ορατή.
 */
export interface TableTextStyleSpan {
  /** Το κείμενο του τμήματος — υποσυμβολοσειρά του **ορατού** κειμένου του run. */
  readonly text: string;
  /** Πρώτος χαρακτήρας στο **ορατό** κείμενο, συμπεριλαμβανόμενος. */
  readonly start: number;
  /** Τελευταίος χαρακτήρας, **μη** συμπεριλαμβανόμενος. */
  readonly end: number;
  /**
   * Η οριζόντια θέση της **αρχής** του τμήματος σε sheet-mm, **σχετικά με την αρχή του
   * κειμένου** — δηλαδή καθαρό άθροισμα των προηγούμενων advances, πάντα ≥ 0.
   *
   * 🔴 **ΔΕΝ είναι η σύμβαση του {@link TableTextLinkSpan.offsetMm}** (που είναι σχετική με
   * την **άγκυρα**, άρα αρνητική σε κέντρο/δεξιά στοίχιση). Μέχρι το ADR-753 Φ3 αυτό το
   * σχόλιο ισχυριζόταν το αντίθετο — «σχετικά με την άγκυρα … ώστε ο ζωγράφος να μη χρειαστεί
   * δεύτερο ternary». Ο **κώδικας** έλεγε πάντα αλλιώς (`resolveCellStyledSpans`: `offsetMm`
   * ξεκινά στο 0 και αθροίζει), και ο κώδικας είναι ο σωστός:
   *
   * ```
   *   styledPrefixWidthMm(spans, k)   →  ΠΛΑΤΟΣ προθέματος, μετρημένο από την αρχή
   *      └─ το τρώει ο resolveCellLinkSpans ως `prefixWidthMm` και προσθέτει ΤΟΤΕ τη στοίχιση
   * ```
   *
   * Αν η στοίχιση ήταν ήδη διπλωμένη εδώ, θα διπλωνόταν **δεύτερη φορά** στα link spans, και
   * το `styledSpansWidthMm` (= πλάτος υπογράμμισης) θα επέστρεφε το μισό σε κεντραρισμένο κελί.
   *
   * ⚠️ Το σχόλιο δεν ήταν αβλαβές: ένας ζωγράφος που το πίστευε θα τοποθετούσε κάθε τμήμα
   * **χωρίς** τη στοίχιση, και κάθε κεντραρισμένο ή δεξιά στοιχισμένο κελί με μορφοποίηση θα
   * ζωγραφιζόταν μετατοπισμένο. Η δίπλωση γίνεται **μία φορά**, στον
   * `tableTextPieces` — δες `bim/table/table-text-pieces.ts`.
   */
  readonly offsetMm: number;
  /** Το μετρημένο πλάτος του τμήματος **με το δικό του στυλ**. */
  readonly advanceMm: number;
  /** Ύψος κεφαλαίου γράμματος σε sheet-mm — μπορεί να διαφέρει ανά τμήμα. */
  readonly heightMm: number;
  /** 🔴 Εγγυημένα πραγματικό `#rrggbb`, με την ίδια αιτιολογία του {@link TableTextRunBase.colorHex}. */
  readonly colorHex: string;
  readonly bold: boolean;
  readonly italic: boolean;
  readonly underline: boolean;
  /** Απούσα ⇒ η προεπιλογή του μετρητή — ένα `undefined`, όχι δύο defaults. */
  readonly fontFamily?: string;
}

/**
 * 🔴 ADR-751 — ένα **τμήμα του κειμένου ενός κελιού που είναι διεύθυνση**, τοποθετημένο.
 *
 * ## Γιατί όχι νέο λεξιλόγιο
 * Τα ονόματα των πεδίων αντιγράφουν συνειδητά το {@link TableTextRun} (`text`, `advanceMm`)
 * και το `TextLayoutSpan` του MTEXT (`text` + offset + advance + χρώμα/decoration ανά
 * τμήμα): το έργο έχει **ήδη** απάντηση στο «πώς περιγράφεται ένα κομμάτι γραμμής με δική
 * του εμφάνιση», και μια δεύτερη με άλλα ονόματα θα ήταν structural clone — αυτό που πιάνει
 * το CHECK 3.28 ανεξάρτητα ονόματος (N.18).
 *
 * ## Γιατί ΔΕΝ κουβαλά χρώμα
 * Το μπλε των συνδέσμων είναι **ένα** για όλο το έργο, όχι ιδιότητα του κάθε τμήματος. Αν
 * ταξίδευε εδώ, κάθε αποθηκευμένη σκηνή θα κουβαλούσε ένα αντίγραφο και μια μελλοντική
 * αλλαγή θέματος θα άφηνε τα παλιά αρχεία στο παλιό χρώμα — το ίδιο σχήμα με το «η απόφαση
 * αντιγράφηκε τη στιγμή Χ» που το ADR-748 κατέγραψε ως ελάττωμα του ACC.
 */
export interface TableTextLinkSpan {
  /** Το κείμενο του τμήματος — υποσυμβολοσειρά του **ορατού** κειμένου του run. */
  readonly text: string;
  /** Τι είναι: καθορίζει τον προορισμό και το μενού, ποτέ την εμφάνιση. */
  readonly kind: TextLinkKind;
  /**
   * Ο προορισμός (`mailto:` / `tel:` / `https:`), από τον SSoT ανιχνευτή.
   *
   * ⚠️ Παράγεται από το **ακέραιο** κείμενο του κελιού, όχι από το ορατό: σε κομμένο κελί
   * ο χρήστης βλέπει `georgios.pag…` και πρέπει να φτάσει στο πλήρες e-mail — ό,τι κάνει
   * και το Excel, όπου η περικοπή είναι θέμα πλάτους στήλης και όχι θέμα περιεχομένου.
   */
  readonly href: string;
  /**
   * Η οριζόντια θέση της **αρχής** του τμήματος, σε sheet-mm **σχετικά με την άγκυρα** του
   * run — ίδια σύμβαση με το `x` του `TableUnderlineGeometry`, ώστε ο ζωγράφος να μη χρειαστεί
   * δεύτερο ternary για τη στοίχιση. Αρνητικό σε κεντρική/δεξιά στοίχιση.
   */
  readonly offsetMm: number;
  /** Το μετρημένο πλάτος του τμήματος σε sheet-mm — το μήκος της υπογράμμισης. */
  readonly advanceMm: number;
}

/**
 * 🔴 ADR-739 Φ.Ε/Φ2 βήμα 4 — **η υπογράμμιση και το πλάτος ταξιδεύουν μαζί — ή καθόλου.**
 *
 * Η γραμμή της υπογράμμισης είναι το μόνο μέρος της τυπογραφίας που χρειάζεται **μέτρηση**: χωρίς
 * το πλάτος του κειμένου δεν ορίζεται καν. Δύο **χωριστά προαιρετικά** πεδία (`underline: boolean` +
 * `advanceMm?: number`) θα σήμαιναν ότι ένα run μπορεί να πει «υπογραμμισμένο» χωρίς να πει πόσο
 * πλατύ — και **κάθε** καταναλωτής θα έπρεπε να αποφασίσει μόνος του τι κάνει τότε.
 * Η σιωπηλή παράλειψη της γραμμής είναι ακριβώς το σχήμα «τα δεδομένα ήταν όλα μέσα και τίποτα
 * δεν φαινόταν» που πλήρωσε η Φ1 (§28.9.8).
 *
 * Η ένωση το κάνει **ακατάλληλο να εκφραστεί**: ο μεταγλωττιστής απαιτεί το `advanceMm`
 * όπου `underline: true`, και το απαγορεύει όπου `false` — άρα κανένας καταναλωτής δεν
 * χρειάζεται να γράψει φύλακα για συνδυασμό που δεν μπορεί να υπάρξει.
 */
export type TableTextRun =
  | (TableTextRunBase & { readonly underline: false })
  | (TableTextRunBase & {
    readonly underline: true;
    /**
     * Το **μετρημένο πλάτος** του ορατού κειμένου σε sheet-mm.
     *
     * Μέχρι τη Φ2 ο καμβάς το ρωτούσε με δικό του `ctx.measureText` σε κάθε καρέ — δεύτερο
     * όργανο — ενώ τα άλλα τρία backends (PDF, DXF, ΤΕΚ) δεν έχουν καν όργανο να
     * ρωτήσουν: μια υπογράμμιση εκεί θα ήταν αδύνατη ή μαντεψιά. Εδώ το μετρά ο **ίδιος**
     * `TableTextMeasurer` που αποφάσισε τα πλάτη στηλών **και** την περικοπή.
     */
    readonly advanceMm: number;
  });

/**
 * Ένα **ορατό** κελί (τα καλυμμένα από συγχώνευση δεν εμφανίζονται καθόλου). Το `rect`
 * καλύπτει ολόκληρο το εύρος της συγχώνευσης όταν το κελί είναι άγκυρα.
 */
export interface TableCellLayout {
  readonly rowId: TableRowId;
  readonly colId: TableColumnId;
  /** Πλήρες ορθογώνιο του κελιού (μαζί με τα περιθώρια). */
  readonly rect: TableRectMm;
  /**
   * Το τελικό στυλ, με την παράκαμψη κελιού ήδη εφαρμοσμένη.
   *
   * 🔴 ADR-739 §38 — το `textColorHex` του είναι **εγγυημένα πραγματικό hex**, με την ίδια
   * αιτιολογία που ισχύει για το {@link TableTextRunBase.colorHex}: το `TableTextRun` γεννιέται
   * μόνο για **γεμάτα** κελιά, ενώ ο in-cell επεξεργαστής ανοίγει και σε **κενό** και διαβάζει
   * το χρώμα του από **εδώ**. Δύο πεδία, ένας κόμβος επίλυσης (`resolveTableCellStyleInk`).
   */
  readonly style: TableCellStyle;
  /**
   * Η **επιλυμένη** οριζόντια στοίχιση του κελιού (κελί → στήλη → κλάση γραμμής).
   *
   * Υπάρχει ξεχωριστά από το `text.hAlign` επειδή ένα **κενό** κελί δεν έχει καθόλου
   * `text`, και όμως έχει στοίχιση: ο in-cell επεξεργαστής (ADR-739 Φ.Δ βήμα 3) πρέπει να
   * στοιχίσει τον κέρσορα σε κελί που δεν έχει γράψει ακόμα τίποτα. Και τα δύο πεδία
   * γράφονται από την **ίδια** έκφραση στο `placeCells` — καμία δεύτερη απόφαση.
   */
  readonly hAlign: TextAlign;
  /**
   * 🔴 ADR-739 §59 Δ2 — η **εσοχή σε sheet-mm**, επιλυμένη: σκαλιά × 3 πλάτη κενού, και **0**
   * όταν δεν ισχύει (κεντραρισμένο κελί, ECMA-376 §18.8.1).
   *
   * ## Γιατί εδώ, δίπλα στο {@link hAlign}, και όχι μόνο μέσα στα `texts`
   * **Ακριβώς** ο λόγος που υπάρχει και το `hAlign`: ένα **κενό** κελί δεν έχει κανένα
   * `TableTextRun`, και όμως έχει εσοχή — ο in-cell επεξεργαστής (Φ.Δ βήμα 3) οφείλει να βάλει
   * τον κέρσορα εκεί που θα ξεκινούσαν τα γράμματα, αλλιώς ο πρώτος χαρακτήρας **πηδά** τη
   * στιγμή της πληκτρολόγησης. Στα `texts` η εσοχή είναι ήδη ψημένη μέσα στο `position`.
   *
   * ## Γιατί σε **mm** και όχι σκαλιά
   * Η μετατροπή σκαλιού→mm απαιτεί τον {@link TableTextMeasurer} (τρία πλάτη κενού **αυτής**
   * της γραμματοσειράς). Η διάταξη τον έχει· ο επεξεργαστής **δεν** τον έχει και δεν πρέπει να
   * αποκτήσει — θα ήταν δεύτερο όργανο μέτρησης δίπλα σε αυτό που αποφάσισε τα πλάτη στηλών
   * (N.18), δηλαδή κέρσορας που κάθεται αλλού από τα γράμματα.
   */
  readonly indentMm: number;
  /**
   * 🔴 ADR-739 §58 Γ2 — **οι οπτικές γραμμές** του κελιού, τοποθετημένες. **Κενός πίνακας**
   * όταν το κελί είναι κενό (κανένα glyph να ζωγραφιστεί), **ένα** στοιχείο για κάθε κελί που
   * δεν αναδιπλώνεται — δηλαδή για κάθε πίνακα που υπάρχει σήμερα στον δίσκο.
   *
   * ## Γιατί ΑΝΤΙΚΑΤΕΣΤΗΣΕ το `text?: TableTextRun` αντί να προστεθεί δίπλα του
   * Η εναλλακτική ήταν «`text` = πρώτη γραμμή, `extraLines?` = οι υπόλοιπες», και θα κόστιζε
   * μηδέν αλλαγές στους καταναλωτές. **Αυτό ακριβώς είναι το πρόβλημά της**: και οι τρεις
   * σημερινοί καταναλωτές (καμβάς, primitives, ευρετήριο συνδέσμων) θα συνέχιζαν να
   * μεταγλωττίζονται και να ζωγραφίζουν **μόνο την πρώτη γραμμή** — σιωπηλά, χωρίς κανένα
   * σφάλμα, σε ένα κελί που ο χρήστης ζήτησε ρητά να αναδιπλωθεί.
   *
   * Είναι το σχήμα «κανείς δεν κοίταξε» που το έργο έχει πληρώσει έξι φορές (N.11/N.12,
   * CHECK 3.34/3.35/3.36/3.40). Η αντικατάσταση κάνει τον **μεταγλωττιστή** τον φύλακα: κάθε
   * καταναλωτής σπάει, τον διαβάζει άνθρωπος, και δεν υπάρχει διαδρομή που «ξεχνά».
   *
   * Το όνομα είναι `texts` και όχι `lines` επειδή το `TableLayout` έχει ήδη `rows` και
   * `borders`: μια «γραμμή» μέσα σε πίνακα διαβάζεται ως γραμμή **πλέγματος** πριν
   * διαβαστεί ως γραμμή **κειμένου**.
   */
  readonly texts: readonly TableTextRun[];
  /** Πλήθος γραμμών/στηλών που καλύπτει (1×1 όταν δεν συμμετέχει σε συγχώνευση). */
  readonly rowSpan: number;
  readonly colSpan: number;
  /**
   * ADR-750 Φ5 (Α2) — οι **διαγώνιες** γραμμές του κελιού, ήδη σε sheet-mm του πλαισίου.
   * Απόν όταν το κελί δεν έχει καμία.
   *
   * ## 🔑 Γιατί στο ΚΕΛΙ και όχι στο `TableLayout.borders`
   * Δύο ανεξάρτητοι λόγοι, και ο δεύτερος είναι ελάττωμα που αποφεύγεται:
   *
   * 1. **Αποκοπή δωρεάν.** Τα κελιά είναι ήδη ευρετηριασμένα ανά γραμμή (`tableRenderIndex`)
   *    και κόβονται με δυαδική αναζήτηση στις ορατές γραμμές. Μια διαγώνιος στο `borders`
   *    θα ζωγραφιζόταν πάντα, σε κάθε καρέ, για κάθε κελί του πίνακα.
   * 2. **Ο ταξινομητής θα την έλεγε κατακόρυφη.** Το `tableRenderIndex` χωρίζει τα τμήματα
   *    με το κριτήριο `a.y === b.y ⇒ οριζόντιο, αλλιώς κατακόρυφο`. Μια διαγώνιος περνά τον
   *    δεύτερο κλάδο και θα κατέληγε στις «κατακόρυφες» — θα **ζωγραφιζόταν σωστά**, οπότε
   *    κανένα test εικόνας δεν θα το έβλεπε, ενώ η αποκοπή θα είχε σπάσει σιωπηλά.
   *
   * Το ότι είναι `TableBorderSegment` (και όχι δικό του σχήμα) δεν είναι αντίφαση: μια
   * διαγώνιος **είναι** ευθύγραμμο τμήμα με μολύβι. Χωριστό σχήμα θα ανάγκαζε καμβά, PDF,
   * DXF και ΤΕΚ να μάθουν δεύτερο είδος γραμμής για μηδέν διαφορά.
   */
  readonly diagonals?: readonly TableBorderSegment[];
}

/**
 * Ένα ευθύγραμμο τμήμα περιγράμματος. Παράγεται **μία φορά ανά ακμή**: δύο γειτονικά
 * κελιά μοιράζονται μία ακμή, οπότε αν το κάθε κελί έβγαζε τις δικές του τέσσερις, κάθε
 * εσωτερική γραμμή θα ζωγραφιζόταν δύο φορές — ορατό σε ημιδιαφανή μολύβια και διπλάσιο
 * κόστος σε PDF/DXF.
 */
export interface TableBorderSegment {
  readonly a: Point2D;
  readonly b: Point2D;
  readonly spec: TableBorderSpec;
}

/** Το πλήρες, απομνημονευμένο αποτέλεσμα της διάταξης. */
export interface TableLayout {
  /** Συνολικό πλάτος = άθροισμα πλατών στηλών. */
  readonly widthMm: number;
  /** Συνολικό ύψος = άθροισμα υψών γραμμών. */
  readonly heightMm: number;
  readonly columns: readonly TableColumnLayout[];
  readonly rows: readonly TableRowLayout[];
  readonly cells: readonly TableCellLayout[];
  readonly borders: readonly TableBorderSegment[];
}

/**
 * Πώς μετριέται το πλάτος ενός κειμένου — βλ. `table-layout-measure.ts`.
 *
 * Το σχήμα του `style` είναι **υποσύνολο** του `TextAdvanceStyle` του text-engine, ώστε ο
 * προεπιλεγμένος μετρητής να είναι πέρασμα πεδίων και όχι μεταφραστής.
 */
export interface TableTextMeasurer {
  (
    text: string,
    heightMm: number,
    style: {
      readonly fontFamily?: string;
      readonly bold?: boolean;
      readonly italic?: boolean;
    },
  ): number;
}

/** Ρυθμίσεις της μιας κλήσης διάταξης. */
export interface TableLayoutOptions {
  /**
   * Διαθέσιμο πλάτος σε sheet-mm. **Απαιτείται** όταν υπάρχει έστω μία `fill` στήλη —
   * χωρίς αυτό δεν ορίζεται τι σημαίνει «το υπόλοιπο». Απόν με μόνο `fixed`/`hug`
   * στήλες ⇒ ο πίνακας παίρνει το φυσικό του πλάτος.
   */
  readonly availableWidthMm?: number;
  /**
   * Μετρητής πλάτους κειμένου. Απών ⇒ `measureTextAdvanceWorld` (ADR-557), ο ΙΔΙΟΣ που
   * χρησιμοποιεί ο renderer — ώστε το πλάτος που υπολογίζει το `hug` να είναι το πλάτος
   * που τελικά ζωγραφίζεται. Η ένεση υπάρχει για ντετερμινιστικά tests, ΟΧΙ για δεύτερη
   * υλοποίηση μέτρησης (N.18).
   */
  readonly measureText?: TableTextMeasurer;
  /**
   * 🔴 ADR-739 §38 — **η επιφάνεια πάνω στην οποία θα εμφανιστεί αυτή η διάταξη**: φόντο καμβά
   * (οθόνη) ή `TABLE_PAPER_HEX` (κάθε εξαγωγή και κάθε raster εκτύπωση). Απούσα ⇒ **χαρτί**.
   *
   * ## Γιατί ΟΡΙΣΜΑ και όχι ανάγνωση μέσα στη μηχανή
   * Τρεις ανεξάρτητοι λόγοι, και ο τρίτος είναι ο αποφασιστικός:
   *
   * 1. **Καθαρότητα.** Το `layoutTable` είναι καθαρή συνάρτηση (ίδιες είσοδοι ⇒ ίδιο
   *    αποτέλεσμα) — προϋπόθεση για τα snapshot tests και για την απομνημόνευση.
   * 2. **Κόστος.** Το φόντο διαβάζεται με `getComputedStyle`· μια ανάγνωση μέσα στον βρόχο των
   *    κελιών είναι το O(zoom²) του ADR-735 ξανά.
   * 3. **Δοκιμασιμότητα.** Σε jsdom το `resolveDxfCanvasBackgroundHex()` επιστρέφει **πάντα** το
   *    σκούρο default. Μια μηχανή που ρωτούσε μόνη της θα δοκιμαζόταν μόνο στην κατεύθυνση
   *    «σκούρο → λευκό» και θα έμενε **πράσινη με σπασμένη** την «λευκό → μαύρο» — δηλαδή
   *    ακριβώς την κατεύθυνση που φεύγει στον πελάτη ως τυπωμένο χαρτί.
   *
   * Η προεπιλογή είναι το χαρτί επειδή αποτυγχάνει προς την **αναστρέψιμη** πλευρά: μαύρο σε
   * σκούρη οθόνη το βλέπει ο χρήστης αμέσως· λευκό σε λευκό χαρτί φεύγει και δεν αναιρείται.
   */
  readonly surfaceHex?: string;
}
