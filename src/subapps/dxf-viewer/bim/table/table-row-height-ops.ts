/**
 * 🔴 ADR-739 §58 Γ2 — **ΠΟΙΟΣ ΚΑΤΕΧΕΙ ΤΟ ΥΨΟΣ ΤΗΣ ΓΡΑΜΜΗΣ.** Καθαρό· μηδέν React, μηδέν DOM.
 *
 * Το {@link TableRow.heightMm} έχει **δύο** καταστάσεις γραμμένες με **ένα** πεδίο:
 * ```
 *   απών  ⇒ ΑΥΤΟΜΑΤΟ   — το ύψος προκύπτει από το περιεχόμενο (αναδιπλωμένες γραμμές)
 *   παρών ⇒ ΚΑΡΦΩΜΕΝΟ  — ο χρήστης το όρισε ρητά (σύρσιμο ορίου ή κουτιού)
 * ```
 * Ο δρόμος προς το «καρφωμένο» υπάρχει από το §31.9 ({@link resizeTableRowAboveEdge}) και είναι
 * μια **χειρονομία**. Ο δρόμος **πίσω** δεν υπήρχε καθόλου — και χωρίς αυτόν, η αναδίπλωση που
 * έφερε το §58 είναι μονίμως ανενεργή σε κάθε γραμμή που ο χρήστης έτυχε να σύρει κάποτε: το
 * κείμενο σπάει σε τρεις γραμμές, η γραμμή μένει στο ύψος της μίας, και **τίποτα στην οθόνη δεν
 * εξηγεί γιατί**.
 *
 * ## 🔴 ΤΙ ΚΑΝΟΥΝ ΟΙ ΜΕΓΑΛΟΙ — μετρημένο, ΟΧΙ αντιγραμμένο από την προηγούμενη διατύπωση
 * ⚠️ **ΔΙΟΡΘΩΣΗ (2026-08-07)**: το ADR-739 §58.1 και το handoff της Γ2 έγραφαν ότι το Excel
 * «δεν δίνει καμία εντολή επαναφοράς, μόνο διπλό κλικ στο όριο». **Ψευδές, επαληθεύτηκε**: το
 * Excel έχει *Home ▸ Cells ▸ Format ▸ AutoFit Row Height* (`Alt`+`H`,`O`,`A`), που επαναφέρει
 * ακριβώς αυτή την κατάσταση. Η διόρθωση δεν αναιρεί την πράξη — αναιρεί τον **λόγο** που
 * γραφόταν γι' αυτήν, και οι δύο δεν είναι το ίδιο πράγμα.
 *
 * Ό,τι μένει όρθιο μετά τη μέτρηση:
 * ```
 *   Excel    →  ΕΧΕΙ την εντολή, αλλά ΚΑΜΙΑ ένδειξη «είναι καρφωμένη αυτή η γραμμή;»
 *   AutoCAD  →  «cell height cannot be fixed» — η ερώτηση δεν υπάρχει καν
 *   Revit    →  τα ύψη «are not resizable» στον πίνακα, μόνο στο φύλλο
 *   ArchiCAD →  έχει και τα δύο, αλλά ανά ΣΤΗΛΗ
 *   ΝΕΣΤΩΡ   →  ΕΧΕΙ την εντολή ΚΑΙ λέει πότε έχει νόημα ({@link hasFixedTableRowHeight})
 * ```
 * 🏆 Το σημείο που περνά τους μεγάλους δεν είναι η **ύπαρξη** του κουμπιού — είναι ότι το
 * κουμπί **απαντά**: ενεργό μόνο όταν κάποια γραμμή του στόχου είναι όντως καρφωμένη. Στο Excel
 * το «AutoFit Row Height» είναι πάντα πατήσιμο και πάντα σιωπηλό, οπότε ο χρήστης δεν μπορεί να
 * μάθει από τη διεπαφή αν η γραμμή που βλέπει είναι αυτόματη ή όχι — μόνο να δοκιμάσει.
 *
 * ## Γιατί ΔΕΝ ζει στο `table-row-column-ops.ts`
 * Το σχόλιο του {@link ./table-overflow-ops} έδειχνε εκεί, και ήταν η σωστή **πρόθεση** (ίδιος
 * άξονας, ίδιο μοντέλο) με λάθος **μέγεθος**: εκείνο το αρχείο είναι 446/500 γραμμές (N.7.1) και
 * απαντά σε άλλη ερώτηση — «πόσες γραμμές υπάρχουν», όχι «ποιος ορίζει το ύψος τους». Εξαγωγή,
 * ποτέ trim.
 *
 * @module subapps/dxf-viewer/bim/table/table-row-height-ops
 * @see bim/table/table-overflow-ops.ts — το αδελφό SSoT («τι γίνεται όταν δεν χωράει»)
 * @see bim/table/table-layout-measure.ts — ΠΟΙΟΣ υπολογίζει το αυτόματο ύψος
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §58
 */

import type { PersistedTableModel, TableRow, TableRowId } from '../../types/table';

/**
 * Δηλώνει **οποιαδήποτε** από αυτές τις γραμμές ρητό ύψος; — η ερώτηση του κουμπιού.
 *
 * `some` και όχι `every`, με τον **ίδιο** λόγο που το τεκμηριώνει το `hasAnyAxisStyleOverride`:
 * η ερώτηση είναι «**υπάρχει τι να επαναφερθεί;**». Με τρεις γραμμές μαρκαρισμένες όπου μόνο η
 * μία είναι καρφωμένη, η απάντηση είναι **ναι** — και το πάτημα θα την ελευθερώσει. Ένα `every`
 * θα άφηνε το κουμπί σβηστό πάνω σε στόχο που έχει σαφώς κλειδωμένη γραμμή.
 */
export function hasFixedTableRowHeight(
  model: PersistedTableModel,
  rowIds: readonly TableRowId[],
): boolean {
  const targets = new Set(rowIds);
  return model.rows.some((row) => targets.has(row.id) && row.heightMm !== undefined);
}

/**
 * **«Αυτόματο ύψος γραμμής»**: σβήνει το ρητό `heightMm` από τις γραμμές του στόχου.
 *
 * 🔑 Δεν *υπολογίζει* ύψος και δεν *γράφει* ύψος — **αφαιρεί** τη δήλωση, και ο υπολογισμός
 * επιστρέφει εκεί που ανήκει: στο {@link resolveTableLayout}, που ήδη μετρά το περιεχόμενο σε
 * κάθε διάταξη. Η εναλλακτική («γράψε το ύψος που θα είχε τώρα») είναι ό,τι κάνει το OOXML με
 * το ζεύγος `ht` + `customHeight` και είναι **χειρότερη**: η γραμμή θα ξανα-καρφωνόταν στην ίδια
 * τιμή, οπότε η επόμενη πληκτρολόγηση δεν θα την ξανάφτιαχνε — δηλαδή το κουμπί θα «δούλευε»
 * μία φορά και μετά θα ήταν ψέμα.
 *
 * ⚠️ **Ίδιο αντικείμενο by-reference όταν δεν αλλάζει τίποτα** — η εγγύηση που κάνει το
 * `buildTableModelCommand` να μη γεννήσει εντολή για το τίποτα, δηλαδή κανένα `Ctrl+Z` που δεν
 * αναιρεί τίποτα ορατό (δες `setPersistedCellText`, εγγύηση 4). Άγνωστες ταυτότητες
 * προσπερνιούνται σιωπηλά, ίδια σύμβαση ανοχής με το `buildMergeIndex`.
 */
export function clearTableRowHeights(
  model: PersistedTableModel,
  rowIds: readonly TableRowId[],
): PersistedTableModel {
  if (!hasFixedTableRowHeight(model, rowIds)) return model;

  const targets = new Set(rowIds);
  const rows = model.rows.map((row) =>
    targets.has(row.id) && row.heightMm !== undefined ? withoutHeight(row) : row,
  );
  return { ...model, rows };
}

/**
 * Το πεδίο **φεύγει**, δεν γίνεται `undefined`.
 *
 * `delete` και όχι `{ ...row, heightMm: undefined }`, για τον ίδιο λόγο που το τεκμηριώνει ήδη
 * το `patchStyleOverride`: το `JSON.stringify` παραλείπει το `undefined`, αλλά το `'heightMm' in
 * row` το βλέπει — και το μοντέλο κρίνεται και με τα δύο (persist **και** σύγκριση ταυτότητας).
 * Ένα κλειδί που υπάρχει με τιμή `undefined` είναι η τρίτη κατάσταση που το §58.1 απέρριψε ρητά.
 */
function withoutHeight(row: TableRow): TableRow {
  const next: Record<string, unknown> = { ...row };
  delete next.heightMm;
  return next as TableRow;
}
