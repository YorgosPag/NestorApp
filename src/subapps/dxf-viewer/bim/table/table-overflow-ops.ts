/**
 * 🔴 ADR-739 §58 — **ΤΙ ΣΗΜΑΙΝΕΙ ΤΟ ΠΑΤΗΜΑ** στα δύο κουμπιά «τι γίνεται όταν δεν χωράει».
 * Καθαρό· μηδέν React, μηδέν DOM.
 *
 * Αδελφό του {@link ./table-align-ops} και του {@link ./table-number-format-ops}, με τον ίδιο
 * λόγο ύπαρξης: η γνώση έχει **δύο** επιφάνειες (mini toolbar + κορδέλα) και μια δεύτερη
 * γραφή της θα ήταν δύο ευκαιρίες να μάθει κάθε επιφάνεια άλλον κανόνα, με κάθε πλευρά να
 * «δουλεύει».
 *
 * ## 🔴 ΓΙΑΤΙ ΕΝΩΣΗ ΚΑΙ ΟΧΙ ΔΥΟ ΔΙΑΚΟΠΤΕΣ — η απόφαση είναι του Excel, όχι δική μας
 * Στο «Μορφοποίηση κελιών → Στοίχιση» του Excel τα «Αναδίπλωση κειμένου» και «Σμίκρυνση ώστε
 * να χωρά» είναι δύο κουτάκια που **ξετσεκάρουν το ένα το άλλο**. Δεν είναι περιορισμός
 * υλοποίησης: απαντούν στην **ίδια** ερώτηση με ασύμβατους τρόπους —
 * ```
 *   wrap    →  υποχωρεί το ΥΨΟΣ ΤΗΣ ΓΡΑΜΜΗΣ   (το κείμενο μένει στο μέγεθός του)
 *   shrink  →  υποχωρεί το ΜΕΓΕΘΟΣ ΤΟΥ ΚΕΙΜΕΝΟΥ (η γραμμή μένει στο ύψος της)
 * ```
 * Δύο ανεξάρτητα booleans θα επέτρεπαν στον μεταγλωττιστή να δεχτεί «και τα δύο», που δεν
 * σημαίνει τίποτα — και **κάθε** καταναλωτής (μηχανή, ζωγράφος, εξαγωγή, πινέλο) θα έπρεπε
 * να επινοήσει δική του σειρά προτεραιότητας. Η ένωση το κάνει μη εκφράσιμο.
 *
 * ## Το τρίτο κουμπί ζει αλλού — και σωστά
 * Το «Αυτόματο ύψος γραμμής» **δεν** είναι τιμή του {@link TableCellOverflow}: δεν απαντά στο
 * «τι γίνεται όταν δεν χωράει» αλλά στο «ποιος κατέχει το ύψος» — και γράφει σε **γραμμή**,
 * όχι σε κελί. Ζει στο **`table-row-height-ops.ts`** ({@link clearTableRowHeights}).
 *
 * ⚠️ **ΔΙΟΡΘΩΣΗ (§58 Γ2)**: εδώ έγραφε «ζει στο `table-row-column-ops.ts`». Η **πρόθεση** ήταν
 * σωστή (ίδιος άξονας, ίδιο μοντέλο), το **μέγεθος** όχι: εκείνο το αρχείο είναι 446/500 γραμμές
 * (N.7.1) και απαντά σε άλλη ερώτηση — «πόσες γραμμές υπάρχουν», όχι «ποιος ορίζει το ύψος τους».
 *
 * @module subapps/dxf-viewer/bim/table/table-overflow-ops
 * @see bim/table/table-cell-overflow.ts — τι **κάνει** η κάθε τιμή (η μηχανή)
 * @see bim/table/table-row-height-ops.ts — το αδελφό SSoT («ποιος κατέχει το ύψος»)
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §58
 */

import type { TableCellOverflow } from '../../types/table';
import { DEFAULT_TABLE_CELL_OVERFLOW } from './table-cell-overflow';

/**
 * Οι τιμές που έχουν **κουμπί**. Το `'clip'` λείπει επίτηδες: είναι η προεπιλογή στην οποία
 * επιστρέφεις ξεπατώνοντας, όχι κατάσταση που επιλέγεις — ακριβώς όπως στο Excel, όπου δεν
 * υπάρχει κουμπί «μην αναδιπλώνεις».
 */
export type TableOverflowChoice = Exclude<TableCellOverflow, 'clip'>;

/**
 * Η επιλογή εφαρμοσμένη πάνω στην τρέχουσα τιμή — **εναλλαγή**, όπως κάθε κουμπί μορφοποίησης.
 *
 * ```
 *   ίδια με την τρέχουσα  →  ΞΕΠΑΤΩΝΕΤΑΙ, πίσω στην προεπιλογή
 *   άλλη / ανάμεικτο      →  ΕΦΑΡΜΟΖΕΤΑΙ
 * ```
 *
 * 🔴 Το «άλλη ⇒ εφαρμόζεται» είναι που κάνει τα δύο κουμπιά αμοιβαία αποκλειόμενα **χωρίς
 * κανέναν ρητό έλεγχο**: πατώντας «σμίκρυνση» σε κελί που αναδιπλώνεται, η ένωση δεν έχει
 * τρόπο να κρατήσει και τα δύο. Ο περιορισμός είναι στον **τύπο**, όχι σε κώδικα που κάποιος
 * μπορεί να ξεχάσει να γράψει στη δεύτερη επιφάνεια.
 *
 * Ανάμεικτος στόχος (`null`) ⇒ **εφαρμογή**, ποτέ ξεπάτωμα: ο χρήστης που πατά κουμπί πάνω σε
 * ανάμεικτη επιλογή ζητά «κάνε τα όλα έτσι» — η ίδια σύμβαση με το `nextTableAlign` και με
 * κάθε toolbar του Office.
 */
export function nextTableOverflow(
  current: TableCellOverflow | null,
  choice: TableOverflowChoice,
): TableCellOverflow {
  return current === choice ? DEFAULT_TABLE_CELL_OVERFLOW : choice;
}

/**
 * Είναι **πατημένο** αυτό το κουμπί;
 *
 * Ανάμεικτος στόχος ⇒ **καμία** επιλογή τσεκαρισμένη: η ερώτηση «αναδιπλώνεται;» δεν έχει μία
 * απάντηση, και ένα πατημένο κουμπί θα έλεγε ψέματα για τα μισά κελιά. Ίδια σύμβαση με τα
 * `isTableAlignActive` / `isTableNumberFormatActive`.
 */
export function isTableOverflowActive(
  current: TableCellOverflow | null,
  choice: TableOverflowChoice,
): boolean {
  return current !== null && current === choice;
}
