/**
 * 🔴 ADR-786 — **Η ΜΙΑ ΑΠΑΝΤΗΣΗ ΣΤΟ «ΜΕ ΤΙ ΓΡΑΜΜΑΤΟΣΕΙΡΑ ΚΑΙ ΣΕ ΠΟΙΟ em ΖΩΓΡΑΦΙΖΕΤΑΙ ΑΥΤΟ
 * ΤΟ ΚΕΙΜΕΝΟ ΠΙΝΑΚΑ;»** — η ίδια ερώτηση που ήδη απαντά ο μετρητής, με το ίδιο σώμα.
 *
 * ## Το ελάττωμα που το γέννησε: ο πίνακας ΜΕΤΡΟΥΣΕ σε άλλη μονάδα από αυτήν που ΖΩΓΡΑΦΙΖΕ
 *
 * Το «ύψος κειμένου» ενός κελιού είναι **ύψος κεφαλαίου** — η σύμβαση του DXF (group code 40),
 * την οποία η βιβλιοθήκη-πρότυπο ezdxf διατυπώνει κατά λέξη: *«the text size is stored as
 * cap-height in the height attribute»*. Ο μετρητής της διάταξης το σέβεται (`text-advance.ts`
 * → `emSizeForTextHeight(h) = h / capHeightRatio`), και το ίδιο κάνει ο ζωγράφος των DXF TEXT
 * (`TextRenderer.ts`). Ο ζωγράφος **του πίνακα** όμως έδινε το ύψος **ωμό** ως CSS `font-size`,
 * δηλαδή ως **em**:
 *
 * ```
 *   μετρητής :  em = h / capRatio   ≈ 1,407 h      (Roboto: sCapHeight/upm ≈ 0,711)
 *   ζωγράφος :  em = h              = 1,000 h      ← ο ΜΟΝΟΣ αποκλίνων της εφαρμογής
 * ```
 *
 * Επί μήνες αυτό ήταν **αόρατο**, για έναν δομικό λόγο: χωρίς μορφοποίηση ανά χαρακτήρα ένα
 * κελί έχει **ένα** τμήμα στη θέση `offsetMm = 0`, οπότε η υπερ-μέτρηση δεν αθροίζεται πουθενά
 * — απλώς έκανε τις στήλες φαρδύτερες, που δεν ξεχωρίζει από «έτσι σχεδιάστηκε». Τη στιγμή που
 * το ADR-753 επέτρεψε να βαφτεί **μισή λέξη**, γεννήθηκαν δύο τμήματα, και το `offsetMm` του
 * δεύτερου — μετρημένο στα «φουσκωμένα» mm — το έριξε **ορατά δεξιότερα**: το κενό μέσα στη
 * λέξη «ΤΕ ΣΤ» που ανέφερε ο Giorgio (2026-08-20).
 *
 * ⚠️ **Το jsdom είναι ΔΟΜΙΚΑ τυφλό σε αυτή την κλάση, και δεν είναι αμέλεια — είναι το όργανο.**
 * Χωρίς φορτωμένη γραμματοσειρά ο μετρητής πέφτει στο tier CSS, όπου το {@link
 * emSizeForTextHeight} επιστρέφει το ύψος **αμετάβλητο** ⇒ μέτρηση ≡ ζωγραφική **αυτομάτως**.
 * Γι' αυτό οι άγκυρες αυτού του ADR εγκαθιστούν ρητά `installStubFont()` (cap/em = 0,8 ≠ 1):
 * μια άγκυρα που τρέχει στο tier CSS θα ήταν πράσινη **πριν και μετά** τη διόρθωση.
 *
 * ## 🔑 Οι ΤΡΕΙΣ ερωτήσεις είναι ΜΙΑ, και γι' αυτό απαντιούνται μαζί
 *
 * | | ερώτηση | καταναλωτής |
 * |---|---|---|
 * | face | ποια περιγράμματα glyph; | `paintTextRun` (καμβάς, tier 1) |
 * | em | ποιο `font-size`; | `ctx.font`, υπογράμμιση, λωρίδα αποκοπής |
 * | css | ποιο shorthand; | `ctx.measureText` **και το `<div contenteditable>`** |
 *
 * Ταξιδεύουν **μαζί** επειδή η καθεμία εξαρτάται από την προηγούμενη: άλλο face ⇒ άλλο
 * `capHeightRatio` ⇒ άλλο em για το **ίδιο** ύψος κεφαλαίου· και άλλο face ⇒ άλλο **όνομα
 * οικογένειας** στο CSS. Τρεις χωριστές κλήσεις θα ήταν τρία σημεία που κάθε καταναλωτής
 * **οφείλει να θυμηθεί** — και ο τρίτος δεν τα θυμάται ποτέ (μετρημένο μάθημα: CHECK 3.39,
 * όπου το `evaluateTranslucent` ήταν ξεχωριστή κλήση και ο τρίτος καταναλωτής **σιωπηλά**
 * κάλυπτε λιγότερα).
 *
 * ## Πού πάμε πάνω από τους μεγάλους
 * Το πρότυπο (HarfBuzz / Skia) λέει: **οι θέσεις παράγονται από τον shaper και ο ζωγράφος τις
 * καταναλώνει** — ποτέ δεύτερη μέτρηση με άλλο όργανο. Το `paintTextRun` **είναι** αυτός ο
 * κανόνας υλοποιημένος, και ήδη τον τηρούσαν τα DXF TEXT, ο 3D atlas και οι σύνθετοι τύποι
 * γραμμής. Ο πίνακας ήταν το μόνο υποσύστημα που τον παρέκαμπτε — και το **μόνο** που έχει
 * δεύτερη επιφάνεια (DOM) πάνω από την πρώτη, δηλαδή το μόνο όπου η απόκλιση **φαίνεται**.
 *
 * @module subapps/dxf-viewer/bim/table/table-text-font
 * @see text-engine/fonts/text-advance.ts — ο μετρητής· η **ίδια** διάκριση tier
 * @see text-engine/fonts/glyph-run-draw.ts — `paintTextRun`, ο ΕΝΑΣ ζωγράφος γραμμής
 * @see text-engine/fonts/css-font-registry.ts — γιατί το `cssFamily` υπάρχει ως CSS face
 */

import {
  emSizeForTextHeight,
  resolveEntityFont,
  type ResolvedFont,
} from '../../text-engine/fonts';
import { buildUIFont } from '../../config/text-rendering-config';

/**
 * Η προεπιλογή απούσας οικογένειας.
 *
 * ⚠️ **Δεν επιλέγεται εδώ**: είναι η ίδια που ήδη γράφει το `baseAdvanceWorld` του μετρητή
 * (`style?.fontFamily || 'arial'`). Μια δεύτερη τιμή εδώ θα έστελνε τον ζωγράφο σε άλλο face
 * από τον μετρητή για κάθε κελί που δεν δηλώνει γραμματοσειρά — δηλαδή για σχεδόν κάθε κελί.
 */
const DEFAULT_FAMILY = 'arial';

/**
 * Το face που θα ζωγραφίσει **πράγματι** αυτό το κείμενο — χωρίς καμία αναφορά σε μέγεθος.
 *
 * Χωρίζεται από το {@link TableTextFont} γιατί υπάρχει ένας καταναλωτής που **δεν έχει px**:
 * τα τμήματα του πλούσιου επεξεργαστή δηλώνουν το μέγεθός τους ως **λόγο** (ADR-753 §28,
 * ώστε το zoom να μη γεννά re-render), και ο λόγος αυτός χρειάζεται τα `capRatio` των **δύο**
 * face — του τμήματος και του κελιού — όχι px.
 */
export interface TableTextFace {
  /**
   * Το φορτωμένο opentype face, ή `null` ⇒ ο δρόμος CSS `fillText`.
   *
   * `null` και για **πλάγια** — δεν είναι έλλειψη αυτού του module αλλά δηλωμένη κατάσταση του
   * {@link resolveEntityFont} («italic faces are not bundled yet»). Ταξιδεύει ρητά ώστε ο
   * ζωγράφος να μη χρειαστεί ποτέ να ξαναρωτήσει.
   */
  readonly resolved: ResolvedFont | null;
  /**
   * Το όνομα οικογένειας **έτοιμο για CSS** (σε εισαγωγικά), δηλαδή αυτό που πρέπει να δει το
   * `ctx.font` και το DOM.
   *
   * 🔴 **Δεν είναι η αιτούμενη οικογένεια.** Όταν το face λύθηκε (tier 1) είναι το όνομα του
   * **υποκατάστατου** (`Liberation Sans`) — γιατί αυτό ακριβώς ζωγραφίζει ο καμβάς, και το
   * `css-font-registry` το έχει δηλώσει στο `document.fonts` από τα **ίδια bytes**. Ένα ωμό
   * `arial` εδώ θα έβαζε τον επεξεργαστή να ζωγραφίσει **Arial** πάνω από καμβά που ζωγραφίζει
   * **Roboto**: η αναλλοίωτη Α2 του §4, σπασμένη σιωπηλά και με τα δύο κείμενα «σωστά».
   */
  readonly cssFamily: string;
  /**
   * Πρέπει το CSS να ζητήσει **έντονα**;
   *
   * ⚠️ `false` όποτε το face λύθηκε, ακόμη κι αν ο χρήστης ζήτησε έντονα: τότε το ίδιο το face
   * **είναι** το έντονο (`Liberation Sans Bold`) και ο καμβάς ζωγραφίζει τα περιγράμματά του
   * αυτούσια. Ένα `bold` από πάνω θα ζητούσε από τον browser **συνθετικό** πάχυνση — δηλαδή
   * γράμματα πιο χοντρά από αυτά του καμβά, στην ίδια θέση.
   */
  readonly cssBold: boolean;
  /** Το ίδιο επιχείρημα με το {@link cssBold}, για τη συνθετική πλάγια γραφή (oblique). */
  readonly cssItalic: boolean;
  /**
   * Πόσα em είναι **ένα** ύψος κεφαλαίου για αυτό το face: ο καθαρός συντελεστής μετατροπής.
   *
   * 🔴 **Παράγεται από την ΙΔΙΑ συνάρτηση που κάνει τη μετατροπή** (`emSizeForTextHeight(1,
   * resolved)`) και **όχι** από το `capHeightRatio`. Δεν είναι λεπτομέρεια: οι δύο διαφωνούν
   * επίτηδες όταν δεν υπάρχει face — το `capHeightRatio` επιστρέφει την **ονομαστική** τιμή
   * (~0,7) ενώ το `emSizeForTextHeight` αφήνει το ύψος **αμετάβλητο** (συντελεστής 1), γιατί
   * στο tier CSS μετρητής και ζωγράφος συμφωνούν πάνω στο ύψος. Ένας λόγος υπολογισμένος από
   * το `capHeightRatio` θα ήταν σωστός στο tier 1 και **λάθος κατά ~43%** στο tier CSS, δηλαδή
   * λάθος ακριβώς στα **έντονα** και τα **πλάγια** τμήματα — τα μόνα που υπάρχουν σήμερα.
   */
  readonly emPerCap: number;
}

/**
 * Ό,τι χρειάζεται μια κλήση σχεδίασης κειμένου πίνακα για να πέσει **πάνω** στη μέτρησή της.
 */
export interface TableTextFont extends TableTextFace {
  /**
   * Το **em** — αυτό που δέχεται το `paintTextRun` και αυτό που μπαίνει στο `ctx.font`.
   *
   * ⚠️ **ΔΕΝ είναι το ύψος κειμένου.** Είναι το ύψος κεφαλαίου διαιρεμένο με τον λόγο cap/em
   * του face. Η ονομασία είναι ο φύλακας: το `fontPx` που υπήρχε πριν ήταν ύψος **κεφαλαίου**
   * με όνομα που έλεγε «μέγεθος γραμματοσειράς», και ακριβώς αυτή η ονομασία επέτρεψε να
   * περάσει ωμό στο `buildUIFont` χωρίς να ξενίσει κανέναν επί μήνες.
   *
   * ⚠️ **Το όνομα δεν φέρει μονάδα ΕΠΙΤΗΔΕΣ.** Η μετατροπή είναι γραμμική, άρα βγαίνει ό,τι
   * μονάδα μπήκε: **px** στον καμβά και στον επεξεργαστή, **sheet-mm** στη γέφυρα εξαγωγής
   * (`table-layout-to-primitives.ts`). Ένα `emPx` διαβασμένο σε σημείο που δουλεύει σε mm θα
   * ήταν ακριβώς το ίδιο ψέμα με το `fontPx` — μικρότερο, και γι' αυτό πιο επικίνδυνο.
   */
  readonly em: number;
  /**
   * Το πλήρες CSS shorthand — **ένα** αλφαριθμητικό, δεκτό από το `ctx.font` **και** από το
   * CSS `font` του DOM. Είναι η μορφή με την οποία μετρά ο επεξεργαστής κελιού και η μορφή
   * που ζωγραφίζει ο καμβάς στο tier CSS.
   */
  readonly css: string;
}

/**
 * Ένα όνομα οικογένειας ασφαλές για CSS shorthand.
 *
 * 🔴 Τα εισαγωγικά **δεν** είναι καλλωπισμός. Το όνομα φτάνει εδώ από **δεδομένα χρήστη** (το
 * `TableCellStyle.fontFamily`, ή το όνομα ενός ανεβασμένου εταιρικού αρχείου). Ένα όνομα που
 * αρχίζει με ψηφίο ή περιέχει σημείο στίξης παράγει **άκυρο** shorthand — και η ανάθεση ενός
 * άκυρου `ctx.font` **αγνοείται σιωπηλά** από τον καμβά, αφήνοντας την προηγούμενη
 * γραμματοσειρά: λάθος γράμματα, κανένα σφάλμα, πουθενά.
 */
function cssFamilyToken(name: string): string {
  return `"${name.replace(/["\\]/g, '')}"`;
}

/**
 * Ποιο face, ποιο όνομα CSS, ποιο `capRatio` — για δεδομένη τυπογραφία, χωρίς μέγεθος.
 */
export function tableTextFace(
  bold: boolean,
  italic: boolean,
  fontFamily?: string,
): TableTextFace {
  const requested = fontFamily || DEFAULT_FAMILY;
  const resolved = resolveEntityFont(requested, { bold, italic });
  return {
    resolved,
    cssFamily: cssFamilyToken(resolved ? resolved.cacheName : requested),
    cssBold: resolved ? false : bold,
    cssItalic: resolved ? false : italic,
    emPerCap: emSizeForTextHeight(1, resolved),
  };
}

/**
 * Το face, το em και το CSS shorthand για κείμενο πίνακα ύψους **κεφαλαίου** `capPx`.
 *
 * Στο tier CSS το {@link emSizeForTextHeight} επιστρέφει το ύψος **αμετάβλητο**, οπότε η ίδια
 * γραμμή κώδικα δίνει τη σωστή απάντηση **και στα δύο** tiers — χωρίς κλάδο, χωρίς σημαία.
 * Αυτό είναι το ουσιώδες: το `resolveEntityFont` επιστρέφει `null` για **πλάγια**, άρα ένα
 * πλάγιο τμήμα δίπλα σε όρθιο **αλλάζει tier μέσα στην ίδια λέξη**. Με ξεχωριστές αποφάσεις σε
 * μέτρηση και ζωγραφική το σφάλμα θα **άλλαζε πρόσημο** στο όριο· με μία, δεν υπάρχει.
 */
export function tableTextFont(
  /** Ύψος **κεφαλαίου** — px στον καμβά/επεξεργαστή, sheet-mm στην εξαγωγή. Δες {@link em}. */
  capHeight: number,
  bold: boolean,
  italic: boolean,
  fontFamily?: string,
): TableTextFont {
  const face = tableTextFace(bold, italic, fontFamily);
  const em = emSizeForTextHeight(capHeight, face.resolved);
  // Το `cssFamily` είναι **ήδη** σε εισαγωγικά, οπότε εδώ πάει κατευθείαν στον κατασκευαστή
  // και δεν περνά από το `tableCellFont` — εκείνο δέχεται **ωμό** όνομα και εισάγει τα
  // εισαγωγικά μόνο του. Δύο διαδρομές, **ένα** σημείο που ξέρει τη γραμματική του CSS.
  const weight = face.cssBold ? 'bold' : 'normal';
  return { ...face, em, css: buildUIFont(em, face.cssFamily, weight, face.cssItalic) };
}

/**
 * 🔴 ADR-739 Φ.Δ βήμα 3 — **Η ΜΙΑ γραμματοσειρά του κειμένου κελιού**, ως αλφαριθμητικό
 * που δέχονται **και** το `ctx.font` του καμβά **και** το CSS `font` shorthand του DOM.
 *
 * Ο in-cell επεξεργαστής κάθεται ακριβώς πάνω από το κελί. Αν χρησιμοποιούσε *δική του*
 * γραμματοσειρά, το κείμενο θα **αναπηδούσε** τη στιγμή του διπλού κλικ και ο κέρσορας θα
 * έπεφτε σε άλλο γράμμα από αυτό που δείχνει ο χρήστης — γιατί ο υπολογισμός πλάτους θα
 * γινόταν σε δύο διαφορετικές γραμματοσειρές. Με **κοινό** αλφαριθμητικό, οι δύο μετρήσεις
 * είναι κυριολεκτικά η **ίδια** μέτρηση της ίδιας μηχανής του browser.
 *
 * ⚠️ **Χαμηλού επιπέδου: δεν υποκαθιστά και δεν μετατρέπει.** Δέχεται **em** και **ωμό**
 * όνομα οικογένειας (τα εισαγωγικά τα βάζει μόνο του). Για κείμενο **κελιού** η σωστή είσοδος
 * είναι το {@link tableTextFont}, που έχει ήδη απαντήσει και το face και το em· απευθείας το
 * καλεί μόνο ο δείκτης ζωνών `A B C` / `1 2 3` (`stamp-table-indicator.ts`), που δουλεύει σε
 * **px οθόνης** και δεν έχει ύψος κεφαλαίου να μετατρέψει — εκεί ο δρόμος CSS **είναι** ο
 * σωστός, και η υποκατάσταση θα ήταν λάθος (είναι διακόσμηση διεπαφής, όχι κείμενο σχεδίου).
 */
export function tableCellFont(
  /**
   * 🔴 ADR-786 — **em σε px**, όχι ύψος κειμένου. Το CSS `font-size` ΕΙΝΑΙ το em· το ύψος
   * κεφαλαίου το μετατρέπει ο {@link tableTextFont}. Το όνομα άλλαξε επειδή το παλιό
   * (`fontPx`) ήταν ακριβώς αυτό που έκανε τη σύγχυση αόρατη.
   */
  emPx: number,
  bold: boolean,
  italic = false,
  /** **Ωμό** όνομα οικογένειας· απόν ⇒ η προεπιλογή του μετρητή ({@link DEFAULT_FAMILY}). */
  fontFamily?: string,
): string {
  const token = cssFamilyToken(fontFamily || DEFAULT_FAMILY);
  return buildUIFont(emPx, token, bold ? 'bold' : 'normal', italic);
}
