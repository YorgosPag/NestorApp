/**
 * ADR-833 Φάση 4 — **ΑΓΚΥΡΕΣ ΤΟΥ ΕΝΟΣ ΓΕΝΝΗΤΟΡΑ ΤΑΥΤΟΤΗΤΑΣ.**
 *
 * Η πρώτη ομάδα καρφώνει τον **βρόχο επαλήθευσης** — το κομμάτι που, σύμφωνα με το ίδιο το
 * ADR, ξεχνά κάθε δεύτερο αντίγραφο. Η δεύτερη καρφώνει ότι ο **πρώτος** καταναλωτής
 * (`nextAxisId`) εξακολουθεί να απαντά ακριβώς όπως πριν την εξαγωγή.
 *
 * @see ../table-next-id.ts
 */

import { nextPrefixedId } from '../table-next-id';
import { buildTableModel } from '../build-table-entity';
import { insertTableColumn, insertTableRow } from '../table-row-column-ops';

describe('nextPrefixedId — μέγιστο+1, με βρόχο επαλήθευσης', () => {
  it('δίνει το πρώτο όνομα σε κενό σύνολο', () => {
    expect(nextPrefixedId([], 'ws')).toBe('ws0');
  });

  it('δίνει μέγιστο+1, όχι πλήθος+1 (κενά στη σειρά ΔΕΝ ξαναχρησιμοποιούνται)', () => {
    // Δύο ταυτότητες, αλλά το μέγιστο είναι 7: ένα «πλήθος+1» θα έδινε `c2`, που **υπάρχει**;
    // όχι — και ακριβώς αυτό είναι το ύπουλο: θα δούλευε εδώ και θα έσπαγε αλλού.
    expect(nextPrefixedId(['c0', 'c7'], 'c')).toBe('c8');
  });

  it('αγνοεί ταυτότητες εκτός μοτίβου (τα `d0` του adapter του ADR-622)', () => {
    expect(nextPrefixedId(['c0', 'd0', 'd1'], 'c')).toBe('c1');
    expect(nextPrefixedId(['c0', 'c1', 'c2', 'x'], 'c')).toBe('c3');
  });

  /**
   * 🔴 Το μοτίβο είναι αγκυρωμένο **και στα δύο άκρα**: το `c12abc` **δεν** είναι στήλη 12.
   * Χωρίς το τελικό `$`, μια ταυτότητα με ουρά θα «δάνειζε» τον αριθμό της στον γεννήτορα —
   * δηλαδή θα προσπερνούσε ελεύθερα ονόματα με βάση κάτι που δεν είναι καν στήλη.
   */
  it('η ουρά μετά τα ψηφία ΔΕΝ ταιριάζει (τελικό anchor)', () => {
    expect(nextPrefixedId(['c12abc'], 'c')).toBe('c0');
  });

  /**
   * 🔴 «Μέγιστο+1» κατά **αριθμητική τιμή**, όχι κατά λεκτικό: το `c007` είναι η στήλη 7, άρα
   * η επόμενη είναι η 8. Ένας γεννήτορας που ξεκινούσε από το `max` (αντί για `max+1`) και
   * βασιζόταν στον βρόχο θα έδινε εδώ `c7` — ελεύθερο μεν, αλλά **αριθμητικά ασυνεπές** με
   * την ταυτότητα που ήδη υπάρχει.
   */
  it('τα αρχικά μηδενικά διαβάζονται ως αριθμός, όχι ως άλλο όνομα', () => {
    expect(nextPrefixedId(['c007'], 'c')).toBe('c8');
  });

  /**
   * 🔴 **Η ΜΕΤΑΣΥΝΘΗΚΗ — και ό,τι απέμεινε αγκυρωμένο από τον βρόχο επαλήθευσης.**
   *
   * Η μετάλλαξη της 2026-08-30 (απενεργοποίηση του `while`) έμεινε **9/9 πράσινη**: ο βρόχος
   * είναι δομικά ανέφικτος για κανονικές ταυτότητες, και η αιτιολόγηση που κουβαλούσε ήταν
   * ψευδής (δες την κεφαλίδα του `table-next-id.ts`). Άρα **δεν** αγκυρώνεται η γραμμή —
   * αγκυρώνεται αυτό που υπόσχεται η συνάρτηση, πάνω σε εχθρικά σύνολα.
   */
  it.each([
    [['c0', 'c1', 'c2']],
    [['c9']],
    [['c007', 'c8']],
    [['c0', 'c00', 'c000']],
    [['c01', 'c1']],
    [['d0', 'd1']],
    [[]],
  ])('η επιστρεφόμενη ταυτότητα ΔΕΝ είναι ποτέ πιασμένη: %j', (ids) => {
    expect(ids).not.toContain(nextPrefixedId(ids, 'c'));
  });

  it('τα προθέματα είναι ΞΕΝΟΙ χώροι ονομάτων — το `r` δεν βλέπει τα `c`', () => {
    expect(nextPrefixedId(['c0', 'c1', 'c2'], 'r')).toBe('r0');
  });

  it('το `ws1` δεν συγχέεται με το `ws10` (η αγκύρωση του μοτίβου είναι ολόκληρη)', () => {
    expect(nextPrefixedId(['ws10'], 'ws')).toBe('ws11');
  });

  it('αγνοεί ταυτότητες με το πρόθεμα αλλά χωρίς αριθμό', () => {
    expect(nextPrefixedId(['wsA', 'ws0'], 'ws')).toBe('ws1');
  });
});

describe('nextAxisId — ο πρώτος καταναλωτής, αμετάβλητος μετά την εξαγωγή', () => {
  it('η εισαγωγή στήλης δίνει το επόμενο `c<N>`, όχι διπλότυπο', () => {
    const model = buildTableModel({ columnCount: 3, dataRowCount: 1 });
    const next = insertTableColumn(model, 0);
    const ids = next.columns.map((column) => column.id);
    expect(new Set(ids).size).toBe(ids.length);
    expect(ids).toContain('c3');
  });

  it('η εισαγωγή γραμμής δίνει το επόμενο `r<N>`, όχι διπλότυπο', () => {
    const model = buildTableModel({ columnCount: 2, dataRowCount: 3 });
    const next = insertTableRow(model, 2);
    const ids = next.rows.map((row) => row.id);
    expect(new Set(ids).size).toBe(ids.length);
  });
});
