/**
 * table-capacity — **ΠΟΣΟ ΜΕΓΑΛΟΣ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΓΙΝΕΙ ΑΥΤΟΣ Ο ΠΙΝΑΚΑΣ;**
 *
 * ADR-833 Φάση 5Β — **ο καταναλωτής που έλειπε**. Η Φάση 5Α γέννησε το όργανο
 * (`table-document-cost`) και η Φάση 6 του έδωσε το νούμερο· το grep της 31/08 έδειξε ότι
 * το όργανο είχε **μηδέν** καταναλωτές στην παραγωγή. Μετρούσε σωστά και **δεν σταματούσε
 * τίποτα**. Αυτό το αρχείο είναι η απάντηση στο *«ποιος ρωτά, πότε, και τι γίνεται όταν η
 * απάντηση είναι όχι»*.
 *
 * ## 🔴 ΔΥΟ ΓΙΝΟΜΕΝΑ, ΔΥΟ ΙΔΙΟΚΤΗΤΕΣ — και ο δεύτερος δεν είχε εντοπιστεί ποτέ
 *
 * ```
 *   ΟΡΙΟ 1  ΑΛΛΗΛΕΠΙΔΡΑΣΗ, ανά ΦΥΛΛΟ     γραμμές × στήλες  ≤  MAX_TABLE_GRID_CELLS
 *   ΟΡΙΟ 2  ΕΓΓΡΑΦΟ, ανά ΠΙΝΑΚΑ          bytes όλων των φύλλων  ≤  TABLE_ENTITY_SHARE_BYTES
 * ```
 *
 * Ολόκληρη η Φάση 5 συζητούσε **ένα** ταβάνι: τα bytes. Αλλά το `placeCells` σαρώνει το
 * πλέγμα **πυκνά** — κατασκευάζει πλήρες `TableCellLayout` για **κάθε** κελί, γραμμένο ή
 * κενό — και το `layoutTable` ξαναχτίζεται σε **κάθε δεσμευμένη αλλαγή**. Μετρημένο
 * 2026-08-31 σε σταθερή κατάσταση: **~32 µs ανά πυκνό κελί, γραμμικά** από 5.000 έως
 * 256.000 κελιά, δηλαδή **8 δευτερόλεπτα παγώματος** στο τότε επιτρεπόμενο μέγιστο.
 *
 * 🔑 **Και η αραιότητα βοηθά ΜΟΝΟ τον έναν ιδιοκτήτη.** Ο ίδιος πίνακας 256×1000 στο 5%:
 *
 * ```
 *   αποθήκευση   48,4 MB → 2,47 MB    (×19,6 φθηνότερα — τα κενά κελιά δεν ταξιδεύουν)
 *   διάταξη      8.033 ms → 4.080 ms  (×1,97 — τα κενά κελιά περνούν ΚΙ ΕΚΕΙΝΑ από τον βρόχο)
 * ```
 *
 * Άρα **ένα** όριο δεν μπορεί να απαντήσει και στα δύο, όσο σωστά κι αν διαλεχτεί: το ένα
 * μετρά **γραμμένα** κελιά, το άλλο **πυκνά**.
 *
 * ## 🔑 ΚΑΘΕ ΟΡΙΟ ΕΙΝΑΙ ΠΗΛΙΚΟ — κανένας αριθμός δεν γράφεται ως αριθμός
 *
 * Ένα όριο γραμμένο ως σταθερά είναι όριο που «κάποιος διάλεξε». Εδώ κάθε όριο είναι
 * **δηλωμένος προϋπολογισμός διά μετρημένου ρυθμού**, ώστε για να αλλάξει να πρέπει να
 * αλλάξει είτε ο **λόγος** είτε η **μέτρηση** — και τα δύο έχουν όνομα και ημερομηνία.
 *
 * ## ⚠️ Η ΠΑΓΙΔΑ ΑΠΟΔΟΣΗΣ, ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΧΡΕΙΑΣΤΗΚΕ ΜΝΗΜΗ
 *
 * Η μέτρηση bytes κάνει `JSON.stringify` σε ολόκληρο το βιβλίο — καταστροφική σε θερμή
 * διαδρομή. Η λύση δεν είναι `WeakMap` αλλά **διαχωρισμός των ερωτήσεων**:
 *
 * ```
 *   ανά χειρονομία (γραμμή/στήλη/δημιουργία) → πυκνό γινόμενο  → τρεις αναγνώσεις `.length`
 *   ανά δέσμευση κελιού                       → μήκος κειμένου → μία σύγκριση
 *   σπάνια, μία φορά (φύλλα, εισαγωγή .xlsx)  → ΑΛΗΘΙΝΗ μέτρηση bytes → ένα `stringify`
 * ```
 *
 * Το ακριβό ερώτημα μπαίνει **μόνο** εκεί που η πράξη είναι σπάνια — κι εκεί ακριβώς
 * χρειάζεται να είναι αληθινό, γιατί η προσθήκη φύλλων είναι η πράξη που **πολλαπλασιάζει**
 * το έγγραφο. Η παγίδα δεν παρακάμφθηκε· **έπαψε να υπάρχει**.
 *
 * ## Ό,τι υπάρχει ήδη δεν σπάει
 *
 * Κάθε ερώτηση εδώ είναι *«επιτρέπεται να **ΜΕΓΑΛΩΣΕΙ**;»*, ποτέ *«είναι νόμιμος;»*. Ένας
 * πίνακας που ξεπερνά τα σημερινά όρια επειδή φτιάχτηκε με τα παλιά **ανοίγει,
 * ζωγραφίζεται και επεξεργάζεται** — απλώς δεν δέχεται νέα γραμμή. Όριο που καθιστά υπάρχον
 * έγγραφο μη ανοίξιμο δεν είναι όριο, είναι regression.
 *
 * @module subapps/dxf-viewer/bim/table/table-capacity
 * @see bim/table/table-document-cost — το όργανο (Φ5Α)· εδώ αποκτά καταναλωτές
 * @see bim/table/table-ooxml-limits — οι ράγες που **δεν** τις διαλέξαμε εμείς
 * @see docs/centralized-systems/reference/adrs/ADR-833-table-xlsx-import-and-worksheets.md §5.8
 */

