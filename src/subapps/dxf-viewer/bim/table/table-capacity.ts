/**
 * Πόσα **πυκνά** κελιά έχει αυτό το σχήμα. Γινόμενο, όχι πλήθος γραμμένων.
 *
 * ⚠️ Το όνομα λέει **πυκνά** επειδή αυτό μετρά, και επειδή στο ίδιο ADR ζει δίπλα του ένα
 * `cellCount` που μετρά τα **γραμμένα** (`TableDocumentCost.cellCount`). Δύο πλήθη κελιών με
 * το ίδιο όνομα θα ήταν η πρώτη ευκαιρία να απαντηθεί η μία ερώτηση με το νούμερο της άλλης.
 */
export function gridCellCount(rowCount: number, columnCount: number): number {
  return rowCount * columnCount;
}

/** Το πυκνό πλέγμα ενός υπάρχοντος μοντέλου. */
export function modelGridCellCount(model: PersistedTableModel): number {
  return gridCellCount(model.rows.length, model.columns.length);
}

/** Πόσες γραμμές/στήλες ζητά να προστεθούν μια πράξη. Απόν σκέλος ⇒ μηδέν. */
export interface TableGridGrowth {
  readonly rows?: number;
  readonly columns?: number;
}

/**
 * **Η ερώτηση της αυξητικής πράξης**: επιτρέπεται να μεγαλώσει τόσο;
 *
 * Είναι η διατύπωση των Google Sheets (*«this action **would increase** the number of cells
 * above the limit»*): η απάντηση δίνεται πάνω στο **προβλεπόμενο** σχήμα, **πριν**
 * κατασκευαστεί οτιδήποτε. Το εναλλακτικό — να χτιστεί και μετά να ελεγχθεί — σημαίνει ότι η
 * ακριβή κατασκευή έχει ήδη πληρωθεί τη στιγμή που λέμε «όχι».
 *
 * Κοστίζει **τρεις αναγνώσεις `.length`** και έναν πολλαπλασιασμό: γι' αυτό επιτρέπεται να
 * ζει σε διαδρομή που τρέχει ανά χειρονομία.
 */
export function canGrowTableGrid(model: PersistedTableModel, growth: TableGridGrowth): boolean {
  const rows = model.rows.length + (growth.rows ?? 0);
  const columns = model.columns.length + (growth.columns ?? 0);
  return fitsTableGrid(rows, columns);
}

/**
 * Χωράει αυτό το **απόλυτο** σχήμα; — και οι τρεις ράγες μαζί, σε μία απάντηση.
 *
 * Οι δύο ράγες του OOXML ελέγχονται **ξεχωριστά** από το γινόμενο επειδή δεσμεύουν σε
 * διαφορετική περίπτωση: το γινόμενο πιάνει τον μεγάλο πίνακα, οι ράγες πιάνουν τον
 * **εκφυλισμένο** (μία γραμμή × 20.000 στήλες περνά το γινόμενο και **δεν** εξάγεται).
 */
export function fitsTableGrid(rowCount: number, columnCount: number): boolean {
  return (
    rowCount <= MAX_TABLE_TOTAL_ROW_COUNT &&
    columnCount <= MAX_TABLE_COLUMN_COUNT &&
    gridCellCount(rowCount, columnCount) <= MAX_TABLE_GRID_CELLS
  );
}

/** Το σχήμα που **χώρεσε** από ένα προσφερόμενο πλέγμα. */
export interface FittedTableGrid {
  readonly rowCount: number;
  readonly columnCount: number;
}

/**
 * **Η ερώτηση της εισαγωγής**: τι χωράει από αυτό που προσφέρεται;
 *
 * Η εισαγωγή δεν αρνείται ποτέ συνολικά (θα πετούσε δουλειά που ο χρήστης έχει ήδη) — κόβει
 * και το **λέει με αριθμό**, μέσα από το υπάρχον λεξιλόγιο (`tableXlsx.clipped`).
 *
 * ## 🔑 Οι ΣΤΗΛΕΣ κρατιούνται, οι ΓΡΑΜΜΕΣ κόβονται — και δεν είναι αυθαίρετο
 * Ένα φύλλο υπολογισμού μεγαλώνει **προς τα κάτω**: οι στήλες είναι το **σχήμα** των
 * δεδομένων (τι είναι το καθένα), οι γραμμές είναι το **πλήθος** τους. Κόβοντας στήλες
 * χάνεται *ποια πληροφορία υπάρχει*· κόβοντας γραμμές χάνονται *μερικές εγγραφές*. Το
 * δεύτερο είναι εξηγήσιμο στον χρήστη σε μία πρόταση, το πρώτο όχι.
 *
 * Όταν όμως **ούτε οι στήλες μόνες τους** χωράνε (εκφυλισμένο φύλλο), κόβονται κι εκείνες:
 * η ιεραρχία είναι προτίμηση, όχι εγγύηση που δεν μπορεί να τηρηθεί.
 *
 * @param minRowCount Γραμμές που ο πίνακας θα έχει **ό,τι κι αν γίνει** (ο τίτλος και η
 *   κεφαλίδα του εργοστασιάρχη). Δες τον σχολιασμό μέσα στη συνάρτηση για το γιατί χωρίς
 *   αυτό το όριο **παραβιαζόταν από την ίδια τη συνάρτηση που το επιβάλλει**.
 */
export function fitTableGrid(
  offeredRows: number,
  offeredColumns: number,
  minRowCount = 0,
): FittedTableGrid {
  // ⚠️ **Εδώ υπήρχε `Math.max(0, minRowCount)` και ΑΦΑΙΡΕΘΗΚΕ** (μετάλλαξη M37, Φ5Β): η
  // μετάλλαξη «σβήσε τον φρουρό» έμενε πράσινη, και **δεν έφταιγε η άγκυρα** — τα μη θετικά
  // δάπεδα τα χειρίζει ήδη το `minRowCount > 0` δύο γραμμές πιο κάτω, και το `Math.max`
  // παρακάτω. Ήταν πλεονασμός δίπλα σε έλεγχο που ήδη τον κάλυπτε: **ίδια περίπτωση** με
  // τον νεκρό φρουρό που αφαίρεσε η Φάση 3, και **όχι** με τον βρόχο του `nextAxisId`
  // (§5.4.8), που ήταν η **μόνη** γραμμή που δήλωνε τη μετασυνθήκη του.
  //
  // 🔴 **ΟΙ ΣΤΗΛΕΣ ΚΟΒΟΝΤΑΙ ΑΠΕΝΑΝΤΙ ΣΤΙΣ ΑΝΑΠΟΦΕΥΚΤΕΣ ΓΡΑΜΜΕΣ, ΠΡΩΤΑ** — και το έπιασε
  // άγκυρα, πριν γίνει όριο. Χωρίς αυτό το βήμα, ένα αίτημα «500.000 στήλες» έδινε
  // `columnCount = 16.384` (ράγα OOXML) και `rowCount = 1`· ο εργοστασιάρχης όμως γεννά
  // **πάντα** τη γραμμή τίτλου και την κεφαλίδα, άρα ο πίνακας έβγαινε 16.384 × 2 =
  // **32.768** πυκνά κελιά — πάνω από το όριο που η ίδια αυτή συνάρτηση υποτίθεται ότι
  // επιβάλλει. Το ίδιο σχήμα με το `bytesPerCell` του §5.6.3: το όργανο παρήγαγε αριθμό που
  // παραβίαζε τον δικό του κανόνα, και το κοκκίνισμα ήρθε από τη μέτρηση, όχι από ανάγνωση.
  //
  // ⚠️ Το `minRowCount` **δεν** μαντεύεται εδώ: το δηλώνει ο καλών, γιατί το «πόσες γραμμές
  // θα υπάρχουν ό,τι κι αν γίνει» είναι γνώση **του εργοστασιάρχη** (`TABLE_FIXED_ROW_COUNT`)
  // και όχι της χωρητικότητας. Μια σταθερά `2` γραμμένη εδώ θα ήταν δεύτερη κατοικία του
  // «+1 τίτλος +1 κεφαλίδα» — ακριβώς το «δεύτερο +1+1» που απαγορεύει το `build-table-entity`.
  const columnCeiling =
    minRowCount > 0 ? Math.floor(MAX_TABLE_GRID_CELLS / minRowCount) : MAX_TABLE_GRID_CELLS;
  const columnCount = Math.max(
    0,
    Math.min(offeredColumns, MAX_TABLE_COLUMN_COUNT, columnCeiling),
  );
  if (columnCount === 0) return { rowCount: 0, columnCount: 0 };

  // ⚠️ **Η ράγα ΓΡΑΜΜΩΝ δεν ελέγχεται εδώ, και ΑΦΑΙΡΕΘΗΚΕ** (μετάλλαξη M50, Φ5Β): για να
  // δέσμευε, θα έπρεπε το `MAX_TABLE_GRID_CELLS / columnCount` να ξεπερνά το 1.048.576 —
  // δηλαδή `columnCount = 0`, που επιστρέφει **δύο γραμμές πιο πάνω**. Ήταν αυστηρά νεκρός
  // κώδικας. Η ράγα εξακολουθεί να ελέγχεται στο {@link fitsTableGrid}, όπου η μηδενική
  // στήλη είναι **προσιτή** είσοδος και η ράγα έχει τι να πει.
  const rowCount = Math.max(
    minRowCount,
    Math.min(offeredRows, Math.floor(MAX_TABLE_GRID_CELLS / columnCount)),
  );
  return { rowCount, columnCount };
}

/**
 * **Η ακριβή ερώτηση**, για τις σπάνιες πράξεις: χωράει αυτό το **βιβλίο** στο μερίδιό του;
 *
 * 🔴 Εδώ και **μόνο εδώ** τρέχει αληθινή μέτρηση (`JSON.stringify` όλων των φύλλων). Ο
 * λόγος είναι ότι αυτή είναι η ερώτηση της **προσθήκης φύλλων** — της μόνης πράξης που
 * μπορεί να πολλαπλασιάσει το έγγραφο με μία εντολή (ένα βιβλίο Excel 12 φύλλων), και
 * ακριβώς της πόρτας που μέχρι τη Φάση 5Β **δεν φυλασσόταν καθόλου**: κάθε φύλλο ελεγχόταν
 * **μόνο του**, και κανείς δεν ρωτούσε το άθροισμα.
 *
 * ⚠️ Επιστρέφει **ετυμηγορία με αριθμούς**, ποτέ σκέτο `boolean` — ίδιο σχήμα με το
 * `checkSizeFits` και για τον ίδιο λόγο: ο καλών οφείλει να μπορεί να πει **πόσο** ξεπερνά
 * χωρίς να ξαναμετρήσει. «Δεν χωράει» χωρίς αριθμό είναι μήνυμα που δεν λέει τι να κόψεις.
 */
export function checkWorksheetsFitShare(
  worksheets: readonly TableWorksheet[],
): SizeFitVerdict {
  return checkTableFits(measureTableDocumentCost(worksheets), TABLE_ENTITY_SHARE_BYTES);
}

/** Τι επιβίωσε από μια υποψήφια ακολουθία φύλλων, και τι δεν χώρεσε. */
export interface WorksheetsWithinShare {
  /** Τα φύλλα που **χωράνε** — πρόθεμα της υποψήφιας ακολουθίας, ποτέ αναδιαταγμένο. */
  readonly worksheets: readonly TableWorksheet[];
  /** Πόσα φύλλα κόπηκαν από το τέλος· `0` όταν χώρεσαν όλα. */
  readonly droppedWorksheets: number;
}

/**
 * **Το μεγαλύτερο πρόθεμα που χωράει στο μερίδιο** — μετρημένο, όχι εκτιμημένο.
 *
 * ## Γιατί βρόχος με πλήρη μέτρηση και όχι άθροισμα ανά φύλλο
 * Το άθροισμα των φύλλων **δεν είναι** το μέγεθος του βιβλίου: τα κόμματα και οι αγκύλες της
 * ακολουθίας γράφονται κι εκείνα (το λέει ρητά το `measureTableDocumentCost`). Ένα άθροισμα
 * θα ήταν **εκτίμηση**, και το `table-document-cost` υπάρχει ακριβώς για να μη χρειάζεται
 * κανείς να εκτιμά. Ο βρόχος μετρά το **πραγματικό** βιβλίο σε κάθε βήμα.
 *
 * ⚠️ Το κόστος είναι `O(N)` πλήρεις μετρήσεις στη χειρότερη περίπτωση — και είναι αποδεκτό
 * **μόνο** επειδή αυτή η ερώτηση ζει σε **σπάνια** πράξη (εισαγωγή βιβλίου, προσθήκη
 * φύλλου). Ποτέ σε θερμή διαδρομή· δες την κεφαλίδα του module για τον πίνακα συχνοτήτων.
 *
 * 🔑 **Κόβονται από το ΤΕΛΟΣ**, ποτέ διαλεκτικά «το μεγαλύτερο πρώτα»: η σειρά των φύλλων
 * είναι η σειρά του βιβλίου του χρήστη, και ένα κόψιμο που κρατά το 1ο, το 3ο και το 7ο θα
 * ήταν αδύνατο να εξηγηθεί σε μία πρόταση — ενώ το «τα τελευταία N δεν χώρεσαν» εξηγείται.
 */
export function fitWorksheetsToShare(
  candidate: readonly TableWorksheet[],
): WorksheetsWithinShare {
  let worksheets = candidate;
  while (worksheets.length > 0 && !checkWorksheetsFitShare(worksheets).fits) {
    worksheets = worksheets.slice(0, -1);
  }
  return { worksheets, droppedWorksheets: candidate.length - worksheets.length };
}
