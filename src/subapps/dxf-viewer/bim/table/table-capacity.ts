/**
 * Ο προϋπολογισμός: πόση ώρα επιτρέπεται να κρατήσει **μία** κατασκευή διάταξης.
 *
 * Το **όριο της ροής της σκέψης**: πάνω από ~1 δευτερόλεπτο ο χρήστης παύει να αισθάνεται
 * ότι χειρίζεται τα δεδομένα άμεσα και αρχίζει να περιμένει το μηχάνημα. Δεν είναι το όριο
 * του «στιγμιαίου» (~100 ms) επίτηδες: η κατασκευή διάταξης δεν τρέχει ανά πλήκτρο αλλά ανά
 * **δεσμευμένη** αλλαγή (`Enter`, `Tab`, επικόλληση, εισαγωγή γραμμής), δηλαδή σε στιγμές
 * όπου ο χρήστης έχει ήδη ολοκληρώσει μια πρόθεση.
 *
 * 🔴 **Η τιμή δεν γράφεται εδώ** — ζητιέται από το `DXF_TIMING` (CHECK 3.27). Ένας χρόνος
 * γραμμένος σε δύο αρχεία είναι δύο χρόνοι: ο επόμενος που θα αλλάξει τον προϋπολογισμό
 * στο κεντρικό αρχείο θα δει το όριο κελιών **να μην κουνιέται**, χωρίς να υπάρχει λάθος
 * πουθενά. Το τοπικό όνομα μένει γιατί εδώ η τιμή είναι **διαιρετέος**, όχι καθυστέρηση.
 */
export const TABLE_LAYOUT_BUDGET_MS = DXF_TIMING.lifecycle.TABLE_LAYOUT_BUDGET;

/**
 * Ο **μετρημένος** ρυθμός: µs ανά πυκνό κελί, στην κατασκευή διάταξης.
 *
 * ```
 *   μετρήθηκε 2026-08-31, σταθερή κατάσταση, ελληνικό δείγμα μηχανικού
 *    20 ×  250 =   5.000 κελιά →   161 ms → 32,15 µs
 *    40 ×  500 =  20.000 κελιά →   676 ms → 33,80 µs
 *   100 × 1000 = 100.000 κελιά → 3.183 ms → 31,83 µs
 *   256 × 1000 = 256.000 κελιά → 8.033 ms → 31,38 µs
 * ```
 *
 * ⚠️ **Το περιβάλλον δηλώνεται**: jsdom + ts-jest, όχι παραγωγικό build. Ο πραγματικός
 * browser είναι ταχύτερος, οπότε ο ρυθμός είναι **απαισιόδοξος** και το σφάλμα πέφτει προς
 * την ασφαλή πλευρά. Ένας αισιόδοξος ρυθμός θα παρήγαγε όριο που δεν προστατεύει.
 *
 * 🔴 **Δεν φυλάσσεται από χρονομέτρηση σε πύλη**, επίτηδες: ένας ισχυρισμός `≤ X ms` σε CI
 * είναι το κλασικό ασταθές test (μηχάνημα, φορτίο, GC). Ό,τι φυλάσσεται από άγκυρα είναι η
 * **παραγωγή** του ορίου από αυτόν τον ρυθμό — ώστε χειρόγραφη αλλαγή του πηλίκου να
 * κοκκινίζει, ακόμη κι αν κανείς δεν ξαναμετρήσει.
 */
export const TABLE_LAYOUT_US_PER_GRID_CELL = 32;

/**
 * 🔑 **ΤΟ ΟΡΙΟ 1**, ως **πηλίκο**: πόσα πυκνά κελιά χωράνε στον προϋπολογισμό χρόνου.
 *
 * ⚠️ Ο αριθμός βγαίνει **μη στρογγυλός** (31.250) και αυτό είναι το ζητούμενο: ένα «30.000»
 * θα διάβαζε ως επιλογή ανθρώπου, ενώ το `31.250` διαβάζεται ως αποτέλεσμα διαίρεσης — ο
 * επόμενος αναγνώστης ρωτά «ποιας;» αντί να ρωτήσει «ποιος;».
 *
 * **Είναι ανά ΦΥΛΛΟ, όχι ανά πίνακα**: η διάταξη χτίζεται μόνο για το **ενεργό** φύλλο
 * (`computeTableEntityGeometryLive`), άρα δέκα φύλλα δεν κοστίζουν δέκα διατάξεις. Το
 * άθροισμα των φύλλων το φυλάει το **ΟΡΙΟ 2**, που μετρά άλλο πράγμα.
 */
export const MAX_TABLE_GRID_CELLS = Math.floor(
  (TABLE_LAYOUT_BUDGET_MS * 1_000) / TABLE_LAYOUT_US_PER_GRID_CELL,
);

