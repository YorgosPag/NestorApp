/**
 * 🔴 ADR-739 §42 — **ΤΟ ΤΕΤΡΑΓΩΝΑΚΙ ΤΗΣ ΓΩΝΙΑΣ ΕΙΝΑΙ ΚΟΥΜΠΙ**: πού πιάνεται, και τι σχήμα
 * ζωγραφίζεται μέσα του. Καθαρή γεωμετρία — μηδέν DOM, μηδέν store, μηδέν React.
 *
 * ## 🔴 ΑΥΤΟ ΤΟ MODULE ΕΙΝΑΙ ΑΝΤΙΣΤΡΟΦΗ ΑΠΟΦΑΣΗΣ, ΟΧΙ ΠΡΟΣΘΗΚΗ
 * Μέχρι σήμερα (2026-08-04) το `table-indicator-geometry` έγραφε, ρητά, για τη γωνία:
 * «*εδώ μένει **κενό** και το hit-test επιστρέφει ρητά `null` γι' αυτό — **δεν υπάρχει τέτοια
 * εντολή, άρα δεν υπάρχει τέτοιο κλικ***», και το κλείδωνε με test. Η **αιτιολόγηση ήταν ήδη
 * λάθος τη στιγμή που γράφτηκε**: η εντολή υπήρχε από τότε και λέγεται `Ctrl+A`
 * ({@link tableWholeGridRange} → `selectAll()`). Αυτό που έλειπε δεν ήταν εντολή — ήταν
 * **δεύτερη πόρτα** προς αυτήν.
 *
 * Ο ιδιοκτήτης το μέτρησε στην οθόνη (04/08): «*στο Excel όταν κάνω κλικ επιλέγεται ολόκληρος
 * ο πίνακας· στον Νέστωρα δεν κάνει τίποτε*».
 *
 * ## 🔴 ΓΙΑΤΙ ΔΙΚΟ ΤΟΥ MODULE ΚΑΙ ΟΧΙ ΤΡΙΤΗ ΠΕΡΙΠΤΩΣΗ ΣΤΟ `TableIndicatorHit`
 * Ο πειρασμός είναι μια `{ axis: 'corner' }` δίπλα στο `'column'`/`'row'`. Θα ήταν λάθος για
 * λόγο **τύπου**, όχι αισθητικής: το `axis` είναι δανεικό λεξιλόγιο που μοιράζονται ήδη
 * τουλάχιστον **τέσσερα** άλλα σχήματα (`TableAxisTarget`, `TableSelectionKind`,
 * `table-axis-action-target`, το μενού κεφαλίδας), και το `table-cell-range` το δηλώνει: είναι
 * «**δομικά** το υποσύνολο του `TableIndicatorHit`». **Η γωνία δεν είναι άξονας.** Μια τρίτη
 * περίπτωση θα υποχρέωνε κάθε `switch` πάνω στο `axis` — μενού, resize, hover, εισαγωγή, στυλ —
 * να απαντήσει σε ερώτηση χωρίς νόημα («ποιο πλάτος έχει η γωνία;»), και ο tsc **δεν** θα
 * προστάτευε: τα περισσότερα είναι `if (axis === 'column') … else …`, δηλαδή το `else` θα
 * κατάπινε σιωπηλά τη γωνία **ως γραμμή**.
 *
 * Η γωνία είναι ό,τι το ⊕ και το ⊖: **χειριστήριο που δεν είναι ούτε κελί ούτε ζώνη**. Άρα
 * παίρνει ό,τι πήραν κι εκείνα — δικό της module, και δική της περίπτωση στο `where` του
 * `TablePointerHit`.
 *
 * ## Η σειρά ελέγχου ΔΕΝ λύνει διεκδίκηση — **μετρημένο, όχι μαντεμένο**
 * Η γωνία ζει σε `u ∈ [-(gap+rowBand), -gap)` **και** `v ∈ [-(gap+colBand), -gap)`. Οι γείτονές
 * της απαντούν εκεί `null` για δομικούς λόγους, όχι κατά τύχη:
 *
 *  - **οι ζώνες**: το `tableIndicatorHitAtFrame` απαιτεί `u ≥ 0` για την πάνω και `v ≥ 0` για
 *    την αριστερή — ένα κελί **είναι** μη αρνητικό·
 *  - **τα διαχωριστικά**: το `axisEdgeAtFrame` απαιτεί `|along − starts[i]| ≤ gap` με `i ≥ 1`,
 *    δηλαδή `starts[i] > 0`· στη γωνία `along < -gap`, άρα η διαφορά είναι **πάντα** > `gap`·
 *  - **το ⊕**: κάθεται έξω από το {@link TABLE_INDICATOR_OUTER_PX} πάνω σε **σύνορο** άξονα, και
 *    το πρώτο σύνορο κάθε άξονα είναι το `0` — δηλαδή δεξιά και κάτω από τη γωνία.
 *
 * Γι' αυτό η θέση της ερώτησης στη σειρά είναι **δήλωση προτεραιότητας** για την περίπτωση που
 * κάποιος μεγαλώσει αύριο μια ζώνη, όχι επίλυση σύγκρουσης σήμερα.
 *
 * @module subapps/dxf-viewer/bim/table/table-select-all-corner
 * @see bim/table/table-indicator-geometry.ts — ΠΟΥ κάθεται το κουτί (`tableIndicatorCornerRectMm`)
 * @see bim/table/table-cell-range.ts — ΤΙ επιλέγει (`tableWholeGridRange`, ο ΕΝΑΣ ορισμός)
 * @see rendering/entities/table/stamp-table-indicator.ts — ο ζωγράφος που καταναλώνει το τρίγωνο
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §42
 */

import type { TableFramePoint } from '../../types/table-entity';
import {
  tableIndicatorCornerRectMm,
  type TableIndicatorBandsMm,
} from './table-indicator-geometry';
import type { TableRectMm } from './table-layout-types';

/**
 * Πόσο **μέσα** από τις ακμές του κουτιού κάθεται το τρίγωνο, ως κλάσμα της μικρότερης
 * πλευράς του.
 *
 * ## Μετρημένο στο Excel, όχι διαλεγμένο
 * Στιγμιότυπο 2026-08-04 (Excel, zoom 265%): κουτί γωνίας `87 × 44 px`· ορθή γωνία του
 * τριγώνου στα `3-4 px` από τη δεξιά και την κάτω ακμή· κάθετες πλευρές `40 × 36 px`, δηλαδή
 * **ισοσκελές ορθογώνιο** μέσα στα όρια της μέτρησης. Άρα:
 *
 *     εσοχή / min(π,ύ) = 3,5 / 44 ≈ 0,08
 *     πλευρά / min(π,ύ) = 36 / 44 ≈ 0,82   →   0,82 + 2 × 0,08 ≈ 1 ✔
 *
 * Δηλαδή **μία** ποσότητα, όχι δύο: η πλευρά είναι ό,τι περισσεύει. Ένα δεύτερο κλάσμα για το
 * μέγεθος θα ήταν αριθμός που μπορεί να αποκλίνει από την εσοχή χωρίς κανείς να το δει.
 *
 * ⚠️ **Κλάσμα και όχι px**: το κουτί είναι ήδη σταθερό σε px οθόνης ({@link TABLE_INDICATOR}) —
 * ένα δεύτερο μέγεθος σε px θα ήταν δεύτερη μονάδα για την ίδια ερώτηση, ακριβώς το σφάλμα
 * «δύο λεξιλόγια της ίδιας ποσότητας» που κατέγραψε το §27.13.
 */
const TABLE_SELECT_ALL_INSET_RATIO = 0.08;

/**
 * 🔴 **ΠΑΤΗΘΗΚΕ ΤΟ ΚΟΥΜΠΙ «ΕΠΙΛΟΓΗ ΟΛΩΝ»;** — καθαρή ερώτηση περιοχής, τίποτα άλλο.
 *
 * Ο έλεγχος είναι **κουτί** και όχι σχήμα του τριγώνου, και είναι το ίδιο που κάνει το Excel:
 * ο στόχος είναι ολόκληρο το τετράγωνο της συμβολής, όχι τα ~50% pixel που καλύπτει το μελάνι.
 * Ένας έλεγχος «μέσα στο τρίγωνο» θα έκανε τη μισή επιφάνεια του κουμπιού νεκρή — και μάλιστα
 * τη **πάνω-αριστερή**, δηλαδή ακριβώς εκεί που φτάνει το χέρι ερχόμενο από έξω.
 *
 * ⚠️ **Δεν ρωτά LOD**: ο καλών έχει ήδη περάσει από το {@link isTableIndicatorVisible} για να
 * παραγάγει τα `bands` — ίδια υποτέλεια με το ⊖ (`table-delete-control`). Ένας δεύτερος
 * έλεγχος εδώ θα ήταν δεύτερο κατώφλι που μπορεί να αποκλίνει.
 *
 * Τα διαστήματα είναι **κλειστά** και στους δύο άξονες, όπως κάθε άλλη ερώτηση ορθογωνίου του
 * πίνακα: η γωνία δεν συνορεύει με τίποτα (δες την κεφαλίδα), άρα ένα κοινό pixel στην ακμή
 * δεν μπορεί να διεκδικηθεί από δεύτερη ερώτηση.
 */
export function isTableSelectAllCornerAtFrame(
  frame: TableFramePoint,
  bands: TableIndicatorBandsMm,
): boolean {
  const rect = tableIndicatorCornerRectMm(bands);
  return (
    frame.u >= rect.x
    && frame.u <= rect.x + rect.w
    && frame.v >= rect.y
    && frame.v <= rect.y + rect.h
  );
}

/**
 * 🔴 **ΤΟ ΤΡΙΓΩΝΟ**, σε sheet-mm του πλαισίου: ορθή γωνία **κάτω-δεξιά**, ισοσκελές, με εσοχή
 * {@link TABLE_SELECT_ALL_INSET_RATIO} από τις ακμές του κουτιού.
 *
 * Η φορά (◢) είναι του Excel και δεν είναι διακοσμητική: το τρίγωνο **δείχνει** προς το πλέγμα
 * — δηλαδή προς αυτό που θα επιλεγεί — και η υποτείνουσά του είναι παράλληλη στη διαγώνιο
 * «πάνω-δεξιά → κάτω-αριστερά», αφήνοντας ελεύθερη τη γωνία που ακουμπά τις δύο ζώνες. Η
 * αντίστροφη φορά θα έδειχνε **έξω** από τον πίνακα.
 *
 * Επιστρέφει τρία σημεία και όχι διαδρομή καμβά: το module είναι καθαρή γεωμετρία και δεν έχει
 * — ούτε επιτρέπεται να αποκτήσει — `CanvasRenderingContext2D`. Την περιστροφή του πίνακα την
 * εφαρμόζει ο ζωγράφος με το ίδιο `toScreen` που περνά κάθε άλλο σχήμα, ώστε το τρίγωνο να
 * **γέρνει μαζί** με τις ζώνες (Φ.Δ βήμα 8).
 */
export function tableSelectAllTriangleMm(
  bands: TableIndicatorBandsMm,
): readonly [TableFramePoint, TableFramePoint, TableFramePoint] {
  const rect: TableRectMm = tableIndicatorCornerRectMm(bands);
  const insetMm = Math.min(rect.w, rect.h) * TABLE_SELECT_ALL_INSET_RATIO;
  const legMm = Math.min(rect.w, rect.h) - 2 * insetMm;
  // Η ορθή γωνία: κάτω-δεξιά, μέσα κατά την εσοχή.
  const cornerU = rect.x + rect.w - insetMm;
  const cornerV = rect.y + rect.h - insetMm;
  return [
    { u: cornerU - legMm, v: cornerV },
    { u: cornerU, v: cornerV },
    { u: cornerU, v: cornerV - legMm },
  ];
}
