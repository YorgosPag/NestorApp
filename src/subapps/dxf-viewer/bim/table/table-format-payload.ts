/**
 * 🔴 ADR-768 Φ1 — **ΤΙ ΕΙΝΑΙ «Η ΜΟΡΦΗ ΕΝΟΣ ΚΕΛΙΟΥ».** Ο ΕΝΑΣ ορισμός, και οι όψεις του.
 *
 * Καθαρός τύπος: μηδέν ανάγνωση, μηδέν React, μηδέν DOM. Η ανάγνωση ζει στο
 * `table-format-read.ts`, η εγγραφή στο `table-format-paint.ts`.
 *
 * ## 🔴 ΓΙΑΤΙ ΔΕΝ ΑΡΚΕΙ ΤΟ `TableCellStyleKey`
 * Ο πειρασμός είναι να πει κανείς «η μορφή ενός κελιού **είναι** το {@link TableCellStyleKey}».
 * Είναι λάθος, και το λάθος είναι σιωπηλό: εκείνος ο τύπος είναι **τομή**
 * (`keyof TableAxisStyleOverride & keyof TableCellStyle`) και η τομή πετάει ακριβώς ό,τι
 * χρειάζεται ένα πινέλο μορφοποίησης:
 *
 * ```
 *   numberFormat  → ζει στο TableAxisStyleOverride αλλά ΟΧΙ στο TableCellStyle,
 *                   γιατί έχει ΔΙΚΗ ΤΟΥ αλυσίδα (ADR-760: κελί▸γραμμή▸στήλη▸valueType)
 *   overflow      → ζει ΜΟΝΟ στο TableCellStyleOverride (κελί▸στήλη)
 *   διαγώνιοι     → ζουν στο ΚΕΛΙ, εκτός στυλ εντελώς (ADR-750 §6.3)
 *   περιγράμματα  → ζουν σε ΤΡΙΤΟ μοντέλο (PersistedTableModel.edges + row.borderTop)
 * ```
 *
 * Δηλαδή «τι αντιγράφεται;» είναι ερώτηση πάνω σε **τέσσερα** μοντέλα με **τέσσερις**
 * ανεξάρτητες αλυσίδες κληρονομιάς. Ένας τύπος που απαριθμεί μόνο το πρώτο θα άφηνε το πινέλο
 * να μεταφέρει τα έντονα και **όχι** τα ευρώ — χωρίς κανένα σφάλμα πουθενά.
 *
 * ⚠️ **Κάθε πεδίο οφείλει να απαριθμείται εδώ.** Η ίδια προειδοποίηση που φοράει ήδη το
 * {@link isBlankCell}, και για τον ίδιο λόγο: ένα ξεχασμένο πεδίο **δεν** σπάει τη
 * μεταγλώττιση — απλώς δεν ταξιδεύει, και ο χρήστης βλέπει «το πινέλο δεν δούλεψε».
 *
 * ## 🔴 ΤΟ ΦΟΡΤΙΟ ΚΡΑΤΑ **ΕΠΙΛΥΜΕΝΕΣ** ΤΙΜΕΣ — ΟΧΙ ΠΑΡΑΚΑΜΨΕΙΣ
 * Κάθε πεδίο εδώ είναι **ολικό**: αυτό που *βλέπει* ο χρήστης στο κελί-πηγή, αφού τρέξουν και
 * τα τέσσερα επίπεδα. Καμία `undefined` «κληρονόμησε», κανένα `null` «ρητά κανένα».
 *
 * Δεν είναι στυλιστική επιλογή — είναι η προϋπόθεση της υπόσχεσης του εργαλείου. Ένα πινέλο
 * υπόσχεται «**κάνε αυτό να μοιάζει με εκείνο**». Αν το φορτίο κρατούσε παρακάμψεις, τότε
 * πηγή που είναι έντονη **επειδή το λέει η γραμμή της** θα ταξίδευε ως «τίποτα» και το βάψιμο
 * δεν θα άλλαζε **απολύτως τίποτα στην οθόνη** — το ακριβές σχήμα του «νεκρού κουμπιού».
 * (Είναι και η δηλωμένη απόκλιση της μεταφοράς περιοχής, §26 του `table-range-transfer`: εκεί
 * είναι **σωστή**, γιατί η μετακίνηση δεν υπόσχεται ομοιότητα· εδώ θα ήταν μοιραία.)
 *
 * 🔑 Τι γίνεται με την κληρονομιά του **στόχου** το αποφασίζει ο γραφέας, όχι αυτός ο τύπος —
 * δες `table-format-paint.ts` για την «ελάχιστη υλοποίηση».
 *
 * ## 🔴 ΓΙΑΤΙ ΛΕΙΠΟΥΝ ΤΑ `runs` (ADR-753) — ΡΗΤΗ ΑΠΟΦΑΣΗ, ΟΧΙ ΠΑΡΑΛΕΙΨΗ
 * Οι δείκτες ενός run δείχνουν σε θέσεις **του κειμένου του κελιού-πηγής** — και το κείμενο
 * είναι ακριβώς αυτό που το πινέλο **δεν** μεταφέρει (γραμμή 5 της προδιαγραφής). Ένα run
 * `[3,7)` προσγειωμένο σε κελί με τρεις χαρακτήρες δεν σημαίνει τίποτα.
 *
 * Άρα:
 * - **πηγή με runs** ⇒ αγνοούνται· ταξιδεύει η μορφή **του κελιού**. (Το ίδιο κάνει το Excel:
 *   ένα κελί με μισογραμμένα έντονα δεν έχει «μία» μορφή να δώσει.)
 * - **στόχος με runs** ⇒ τα πεδία που βάφονται **ισοπεδώνονται** μέσα στα runs του, ακριβώς
 *   όπως ήδη κάνει το {@link setRangeStyleField}. Αν δεν ισοπεδώνονταν, θα βάφαμε το κελί
 *   κόκκινο και ένα μισό του θα έμενε μπλε — γιατί τα runs **νικούν** το κελί στην επίλυση.
 *   Ζει στον γραφέα, όχι εδώ, γιατί εξαρτάται από **ποιες όψεις** ζήτησε ο χρήστης.
 *
 * @module subapps/dxf-viewer/bim/table/table-format-payload
 * @see bim/table/table-format-read.ts — από πού διαβάζεται
 * @see bim/table/table-format-paint.ts — πώς γράφεται (ελάχιστη υλοποίηση)
 * @see docs/centralized-systems/reference/adrs/ADR-768-table-format-painter.md
 */

