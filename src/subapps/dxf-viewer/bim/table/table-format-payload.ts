/**
 * Μια **όψη** της μορφής: η μονάδα που μπορεί ο χρήστης να ανάψει ή να σβήσει.
 *
 * Είναι το idiom του **AutoCAD MATCHPROP** (διάλογος *Property Settings*: «Basic» /
 * «Special»), και ο λόγος που ξεπερνά το Excel σε εργαλείο μηχανικού: το «θέλω μόνο τα
 * περιγράμματα, όχι τη γραμματοσειρά» είναι καθημερινό αίτημα σε πίνακα ποσοτήτων, και το
 * Excel **δεν μπορεί** να το εκφράσει — είναι όλα ή τίποτα.
 *
 * ## Γιατί έξι όψεις και όχι δώδεκα διακόπτες ανά πεδίο
 * Ένα checklist με «Έντονα / Πλάγια / Υπογράμμιση / Μέγεθος / Γραμματοσειρά / Χρώμα
 * κειμένου / …» είναι θόρυβος: κανείς δεν θέλει να μεταφέρει τα έντονα **χωρίς** το χρώμα
 * τους. Η ομαδοποίηση ακολουθεί τα τέσσερα υπο-μενού που ήδη έχει η γραμμή εργαλείων του
 * πίνακα, ώστε η λέξη «γραμματοσειρά» να σημαίνει το ίδιο στα δύο σημεία.
 */
export type TableFormatFacet =
  /** Τυπογραφία: έντονα, πλάγια, υπογράμμιση, μέγεθος, οικογένεια, χρώμα μελανιού. */
  | 'text'
  /** Στοίχιση (9 θέσεις) και ξεχείλισμα. */
  | 'alignment'
  /** Χρώμα γεμίσματος. */
  | 'fill'
  /** ADR-760 — πώς δείχνει ο αριθμός (νόμισμα, ποσοστό, δεκαδικά). */
  | 'numberFormat'
  /** ADR-750 — οι τέσσερις πλευρές και οι διαγώνιοι. */
  | 'borders';

/**
 * Οι όψεις σε **σταθερή** σειρά — αυτή που εμφανίζονται στο checklist.
 *
 * Παράγεται από αντικείμενο-σύνολο και όχι γραμμένη ως λίστα: ο τύπος
 * {@link TableFormatFacet} και η λίστα θα ήταν δύο χειρόγραφες απαριθμήσεις που μπορούν να
 * αποκλίνουν στην πρώτη προσθήκη — το ίδιο σχήμα με τις δύο λίστες namespace του CHECK 3.34.
 * Εδώ ο μεταγλωττιστής απαιτεί **ακριβώς** τα κλειδιά της ένωσης.
 */
const FACET_ORDER: Readonly<Record<TableFormatFacet, true>> = {
  text: true,
  alignment: true,
  fill: true,
  numberFormat: true,
  borders: true,
};

/** Οι όψεις ως πίνακας — μία φορά, από το σύνολο που ελέγχει ο μεταγλωττιστής. */
export const TABLE_FORMAT_FACETS = Object.keys(FACET_ORDER) as readonly TableFormatFacet[];

/**
 * 🔴 **Ποια όψη κουβαλά ποιο πεδίο στυλ** — και η απαρίθμηση είναι **υποχρεωτική**.
 *
 * `Record<TableCellStyleKey, …>` και όχι `Partial`: την ημέρα που το μοντέλο αποκτήσει
 * δέκατο πεδίο μορφοποίησης, **αυτό το αντικείμενο δεν μεταγλωττίζεται** μέχρι κάποιος να
 * απαντήσει «σε ποια όψη ανήκει;». Είναι ο μόνος τρόπος να μην ξεχαστεί ένα πεδίο σιωπηλά —
 * και το σιωπηλό ξέχασμα εδώ δεν δίνει σφάλμα, δίνει «το πινέλο δεν μεταφέρει το Χ».
 */
const FACET_BY_STYLE_KEY: Readonly<Record<TableCellStyleKey, TableFormatFacet>> = {
  textHeightMm: 'text',
  textColorHex: 'text',
  bold: 'text',
  italic: 'text',
  underline: 'text',
  fontFamily: 'text',
  align: 'alignment',
  // 🔴 ADR-739 §59 Δ2 — η **εσοχή** είναι εντολή στοίχισης, όχι τυπογραφίας: στο Excel τα δύο
  // κουμπιά της κάθονται στην ομάδα «Στοίχιση» και στο OOXML είναι attribute του **ίδιου**
  // στοιχείου `<alignment>` με το `horizontal`/`vertical`/`wrapText`. Δική της όψη θα ήταν
  // διακόπτης που κανείς δεν ζητά χωριστά — «μετάφερε τη στοίχιση αλλά όχι την εσοχή» δεν είναι
  // αίτημα που έχει διατυπωθεί ποτέ, σε κανένα από τα πέντε εργαλεία αναφοράς.
  indentLevel: 'alignment',
  // 🔴 ADR-739 §59 Δ1 — ο **προσανατολισμός**, στην ίδια όψη: στο Excel το κουμπί του κάθεται
  // στην ομάδα «Στοίχιση» και στο OOXML είναι attribute του **ίδιου** `<alignment>`. Δική του
  // όψη θα σήμαινε «μετάφερε τη στοίχιση αλλά όχι τη γωνία» — αίτημα που δεν υπάρχει.
  textRotationDeg: 'alignment',
  fillColorHex: 'fill',
};

// ADR-700 §4 (2026-08-24): tableFormatFacetOfStyleKey() ΔΙΑΓΡΑΦΗΚΕ — μηδέν καταναλωτές.
// Ο χάρτης FACET_BY_STYLE_KEY ΜΕΝΕΙ, τον χρησιμοποιούν άλλες συναρτήσεις του αρχείου.

/**
 * Τα πεδία στυλ **αυτής** της όψης, σε σταθερή σειρά.
 *
 * Παράγεται από τον ίδιο χάρτη αντί για δεύτερη λίστα ανά όψη: μια χειρόγραφη
 * `TEXT_KEYS = [...]` θα ήταν η δεύτερη απάντηση στο «τι είναι τυπογραφία;» και θα έμενε
 * πίσω ακριβώς όπως έμεινε η baseline του CHECK 3.18.
 */
export function tableFormatStyleKeysOfFacet(
  facet: TableFormatFacet,
): readonly TableCellStyleKey[] {
  const keys = Object.keys(FACET_BY_STYLE_KEY) as readonly TableCellStyleKey[];
  return keys.filter((key) => FACET_BY_STYLE_KEY[key] === facet);
}

/**
 * Ποιες όψεις είναι ενεργές. `ReadonlySet` και όχι πίνακας: η ερώτηση που κάνει ο γραφέας
 * είναι **πάντα** «περιέχεται;», μία φορά ανά πεδίο ανά κελί — γραμμική αναζήτηση εκεί θα
 * ήταν O(όψεις × πεδία × κελιά) σε βρόχο που τρέχει σε περιοχή 500 γραμμών.
 */
export type TableFormatFacetSet = ReadonlySet<TableFormatFacet>;

/** Όλες οι όψεις — η προεπιλογή, δηλαδή η συμπεριφορά του Excel («όλα ή τίποτα»). */
export const ALL_TABLE_FORMAT_FACETS: TableFormatFacetSet = new Set(TABLE_FORMAT_FACETS);

