/**
 * Τα πεδία στυλ όπως τα **βλέπει** ο χρήστης — υποσύνολο του {@link TableCellStyle}.
 *
 * `Pick` και όχι δικό του interface: το επιλυμένο στυλ **είναι** η πηγή αυτών των τιμών, και
 * ένα παράλληλο interface με τα ίδια οκτώ πεδία θα ήταν ακριβώς το δίδυμο που χαρακτηρίζει το
 * CHECK 3.28 (jscpd, N.18) — και, χειρότερα, θα μπορούσε κάποτε να αποκτήσει άλλον τύπο για
 * το ίδιο πεδίο.
 */
export type TableCellStyleSnapshot = Readonly<Pick<TableCellStyle, TableCellStyleKey>>;

/**
 * Οι τέσσερις πλευρές ενός κελιού.
 *
 * ⚠️ **Δεν** επαναχρησιμοποιείται το `TableBorderSide` του `table-range-border-ops`: εκείνο
 * απαριθμεί **έξι** τιμές (τις τέσσερις περιμετρικές **συν** `insideH` / `insideV`), γιατί
 * απαντά για **ορθογώνιο**. Ένα κελί δεν έχει «μέσα». Η επαναχρησιμοποίηση θα γεννούσε δύο
 * τιμές που δεν σημαίνουν τίποτα εδώ και θα ανάγκαζε κάθε αναγνώστη να τις προσπερνά.
 */
export type TableCellBorderSide = 'top' | 'right' | 'bottom' | 'left';

/** Οι τέσσερις πλευρές σε σταθερή σειρά — παράγεται, δεν γράφεται δεύτερη φορά. */
const CELL_BORDER_SIDE_ORDER: Readonly<Record<TableCellBorderSide, true>> = {
  top: true,
  right: true,
  bottom: true,
  left: true,
};

/** Οι τέσσερις πλευρές ως πίνακας — σειρά ρολογιού, όπως το CSS. */
export const TABLE_CELL_BORDER_SIDES = Object.keys(
  CELL_BORDER_SIDE_ORDER,
) as readonly TableCellBorderSide[];

/**
 * 🔴 **Η ΜΟΡΦΗ ΕΝΟΣ ΚΕΛΙΟΥ, ΕΠΙΛΥΜΕΝΗ** — ό,τι φορτώνει το πινέλο και τίποτε άλλο.
 *
 * Κάθε πεδίο είναι **ολικό**: δεν υπάρχει «δεν ξέρω». Δες την κεφαλίδα για το γιατί.
 */
export interface TableCellFormatPayload {
  /** Τα οκτώ πεδία τυπογραφίας/στοίχισης/γεμίσματος, επιλυμένα. */
  readonly style: TableCellStyleSnapshot;
  /** ADR-760 — η μορφή αριθμού που **ισχύει**, μαζί με τη σημασιολογική βάση της στήλης. */
  readonly numberFormat: TableCellFormat;
  /** Το ξεχείλισμα που **ισχύει** (κελί ▸ στήλη ▸ προεπιλογή). */
  readonly overflow: TableCellOverflow;
  /**
   * ADR-750 §6.3 — οι διαγώνιοι. **Καθαρά επιπέδου κελιού**: δεν κληρονομούνται από πουθενά,
   * άρα εδώ το `undefined` σημαίνει πραγματικά «καμία» και όχι «ρώτα παραπάνω».
   */
  readonly diagonal: TableCellDiagonals | undefined;
  /** ADR-750 — το μολύβι κάθε πλευράς, μετά και τα τέσσερα επίπεδα κληρονομιάς. */
  readonly borders: Readonly<Record<TableCellBorderSide, TableBorderSpec>>;
}

/**
 * 🔴 **Ποια όψη κουβαλά ποιο ΜΗ-ΣΤΥΛ μέλος** — η δεύτερη μισή απάντηση, εξίσου υποχρεωτική.
 *
 * Το {@link FACET_BY_STYLE_KEY} απαριθμεί μόνο τα οκτώ πεδία του επιλυμένου στυλ. Τα υπόλοιπα
 * τέσσερα μέλη του φορτίου ζουν σε **άλλα μοντέλα** (§κεφαλίδα) και θα έμεναν χωρίς όψη —
 * δηλαδή το checklist θα τα μετέφερε **πάντα**, αγνοώντας τον χρήστη, χωρίς κανένα σφάλμα.
 *
 * `Exclude<keyof TableCellFormatPayload, 'style'>` ⇒ ο μεταγλωττιστής απαιτεί απάντηση για
 * **κάθε** μελλοντικό μέλος του φορτίου. Ένα σχόλιο «το overflow ανήκει στη στοίχιση» δεν
 * είναι πύλη· είναι σχόλιο — το ίδιο μάθημα με το CHECK 3.36 («ένα anchor χωρίς gate είναι
 * σχόλιο»).
 */
const FACET_BY_PAYLOAD_MEMBER: Readonly<
  Record<Exclude<keyof TableCellFormatPayload, 'style'>, TableFormatFacet>
> = {
  numberFormat: 'numberFormat',
  // Το ξεχείλισμα είναι απόφαση **διάταξης του κειμένου μέσα στο κελί**, όπως η στοίχιση —
  // και είναι το αντίστοιχο του «Αναδίπλωση κειμένου» του Excel, που εκεί κάθεται στην ίδια
  // ομάδα της κορδέλας με τη στοίχιση. Δική του όψη θα ήταν διακόπτης που κανείς δεν ζητά
  // χωριστά.
  overflow: 'alignment',
  // Οι διαγώνιοι είναι γραμμές που ζωγραφίζονται **μέσα** στο κελί με μολύβι
  // ({@link TableBorderSpec}) — στο OOXML ζουν κυριολεκτικά μέσα στο `<border>`, δίπλα στις
  // τέσσερις πλευρές. Ξεχωριστή όψη θα ήταν διάσπαση που κανένα από τα πέντε εργαλεία
  // αναφοράς δεν κάνει.
  diagonal: 'borders',
  borders: 'borders',
};

// ADR-700 §4 (2026-08-24): tableFormatFacetOfPayloadMember() ΔΙΑΓΡΑΦΗΚΕ — μηδέν καταναλωτές.
// Ο χάρτης FACET_BY_PAYLOAD_MEMBER ΜΕΝΕΙ, τον χρησιμοποιούν άλλες συναρτήσεις του αρχείου.

/**
 * 🔴 **ΤΟ ΦΟΡΤΩΜΕΝΟ ΠΙΝΕΛΟ** — ένα ολόκληρο **στιγμιότυπο** της πηγής, αποκομμένο από το μοντέλο.
 *
 * ## Γιατί στιγμιότυπο και όχι αναφορά στην πηγή
 * Είναι η συμπεριφορά του Excel και του Revit: μόλις «ρουφήξεις», η πηγή μπορεί να αλλάξει,
 * να μετακινηθεί ή να **διαγραφεί** — το πινέλο εξακολουθεί να κρατά ό,τι ρούφηξε. Μια
 * αναφορά (`bounds` + μοντέλο) θα σήμαινε ότι ένα `Ctrl+Z` ανάμεσα στο φόρτωμα και το βάψιμο
 * αλλάζει σιωπηλά **τι** θα βαφτεί — ή σκοτώνει το πινέλο χωρίς να το πει.
 *
 * Είναι επίσης ο λόγος που εδώ ζουν {@link rows}/{@link columns} αντί για `bounds`: το
 * **σχήμα** είναι ό,τι χρειάζεται το άπλωμα ({@link TableTilePattern}), και το σχήμα επιβιώνει
 * της διαγραφής της πηγής — τα όρια όχι.
 *
 * ⚠️ `cells` **πάντα** μήκους `rows × columns`, σε σειρά **row-major**. Η εγγύηση παράγεται εκ
 * κατασκευής από τον μοναδικό παραγωγό (`captureTableFormatBrush`) και δεν επαναλαμβάνεται ως
 * έλεγχος σε κάθε καταναλωτή.
 */
export interface TableFormatBrush {
  readonly facets: TableFormatFacetSet;
  /** Ύψος του μοτίβου σε κελιά (≥1). */
  readonly rows: number;
  /** Πλάτος του μοτίβου σε κελιά (≥1). */
  readonly columns: number;
  /** Row-major· `cells[r * columns + c]`. */
  readonly cells: readonly TableCellFormatPayload[];
}

/** Το φορτίο στη θέση `(r, c)` του μοτίβου. Ολική — δες την εγγύηση μήκους παραπάνω. */
export function tableFormatBrushCellAt(
  brush: TableFormatBrush,
  patternRow: number,
  patternCol: number,
): TableCellFormatPayload {
  return brush.cells[patternRow * brush.columns + patternCol];
}
