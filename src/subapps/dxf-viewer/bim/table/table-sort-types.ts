import type { NameListCandidate } from '@/lib/string/name-list-match';
import type { TableCellRangeBounds } from './table-cell-range';

/**
 * Ένα επίπεδο ταξινόμησης: **ποια στήλη**, προς ποια φορά, και με ποιο λεξιλόγιο.
 *
 * 🔑 Η {@link byList} είναι όλος ο λόγος που η ταξινόμηση ζει σε αυτό το ADR: «Ιανουάριος,
 * Φεβρουάριος, Μάρτιος» **δεν** είναι αλφαβητική σειρά, και καμία σύγκριση κειμένου δεν
 * μπορεί να την ανακαλύψει. Είναι το ίδιο ερώτημα που απαντά η λαβή συμπλήρωσης — «ποια
 * είναι η διάταξη αυτών των ονομάτων;» — και η απάντηση είναι η **ίδια** λίστα. Γι' αυτό
 * λέγονται *Sort Lists* στο LibreOffice: η ταξινόμηση ήταν πάντα ο δεύτερος καταναλωτής τους.
 */
export interface TableSortCriterion {
  /** **Απόλυτος** δείκτης στήλης μέσα στο μοντέλο — όχι σχετικός με την περιοχή. */
  readonly columnIndex: number;
  readonly descending: boolean;
  /**
   * Λεξιλόγιο διάταξης· **απόν** ⇒ φυσική σειρά (αριθμοί, μετά κείμενο κατά `el`).
   *
   * ⚠️ Ό,τι **δεν** ανήκει στη λίστα δεν είναι σφάλμα και δεν πετιέται: πηγαίνει **μετά** από
   * κάθε μέλος της, ταξινομημένο μεταξύ του με τον φυσικό κανόνα. Ίδια συμπεριφορά με το
   * Excel, και η μόνη που δεν εξαφανίζει γραμμές του χρήστη.
   */
  readonly byList?: NameListCandidate;
}

/** Γιατί **δεν** ταξινομείται — κλειδιά, ποτέ ετικέτες (N.11). */
export type TableSortRefusal =
  /** Η περιοχή δείχνει σε γραμμή/στήλη που δεν υπάρχει (μπαγιάτικα όρια, μετά από undo). */
  | 'stale-range'
  /** Κανένα κριτήριο, ή κριτήριο σε στήλη **έξω** από την περιοχή. */
  | 'no-criteria'
  /**
   * Η περιοχή περιέχει συγχώνευση.
   *
   * Το Excel λέει *«This operation requires the merged cells to be identically sized»* και
   * αρνείται — γιατί μια συγχώνευση `1×3` σε αναδιάταξη γραμμών θα έπρεπε ή να σπάσει, ή να
   * σύρει μαζί της γραμμές που ο κανόνας ταξινόμησης τοποθέτησε αλλού. Και τα δύο είναι
   * απόφαση που **δεν** επιτρέπεται να παρθεί σιωπηλά για λογαριασμό του ανθρώπου.
   */
  | 'merged-range'
  /** Η ταξινομημένη σειρά ταυτίζεται με την τρέχουσα — καμία εντολή, κανένα βήμα undo. */
  | 'already-sorted';

/** Τι ζητήθηκε: ποια περιοχή, με ποια επίπεδα, και αν η πρώτη γραμμή είναι κεφαλίδα. */
export interface TableSortRequest {
  readonly range: TableCellRangeBounds;
  /**
   * Τα επίπεδα **με σειρά προτεραιότητας**: το δεύτερο κρίνει μόνο όπου το πρώτο ισοβαθμεί.
   *
   * Η σειρά είναι σημασιολογία, όχι διακόσμηση — και είναι η **μόνη** διαφορά ανάμεσα σε
   * «ταξινόμηση κατά όροφο, μετά κατά φάση» και το αντίστροφο.
   */
  readonly criteria: readonly TableSortCriterion[];
  /**
   * Η **πρώτη γραμμή της περιοχής** είναι τίτλοι και μένει ακίνητη.
   *
   * ⚠️ Δεν συμπεραίνεται. Το Excel το μαντεύει και **κάνει λάθος** αρκετά συχνά ώστε να
   * κρατά διακόπτη δίπλα· εδώ ο άνθρωπος το δηλώνει και το βλέπει.
   */
  readonly hasHeader: boolean;
}

/** Ναι με σχέδιο, ή όχι με λόγο — **ποτέ** σιωπηλό `null` που ο καλών πρέπει να ερμηνεύσει. */
export type TableSortOutcome<TPlan> =
  | { readonly ok: true; readonly plan: TPlan }
  | { readonly ok: false; readonly reason: TableSortRefusal };
