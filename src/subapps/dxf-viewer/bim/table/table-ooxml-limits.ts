/**
 * table-ooxml-limits — **ΤΑ ΟΡΙΑ ΠΟΥ ΔΕΝ ΤΑ ΔΙΑΛΕΞΑΜΕ ΕΜΕΙΣ**
 *
 * ADR-833 Φάση 5Β. Τρεις αριθμοί, **ένας** ιδιοκτήτης, και ο ιδιοκτήτης δεν είναι αυτό το
 * έργο: είναι το **Office Open XML** — το πρότυπο στο οποίο η Φάση 6 υποσχέθηκε ότι ο
 * πίνακας **εξάγεται** (`.xlsx`, §5.7). Από τη στιγμή που υπάρχει αυτή η υπόσχεση, ένας
 * πίνακας που την ξεπερνά δεν είναι «μεγάλος» — είναι **μη εξαγώγιμος**.
 *
 * ```
 *   στήλες           16.384      (η στήλη «XFD» του Excel)
 *   γραμμές       1.048.576
 *   χαρακτήρες
 *   ανά κελί         32.767      MS-OI29500 §18.3.1.96 — η τιμή κελιού είναι ST_Xstring
 *                                με ρητό ανώτατο μήκος· μεγαλύτερη ΔΕΝ γράφεται σε .xlsx
 * ```
 *
 * ## 🔴 Γιατί αυτοί οι αριθμοί ΔΕΝ είναι τα πραγματικά όρια του πίνακα
 *
 * Είναι **ράγες μορφής**, όχι προϋπολογισμός. Τα όρια που δεσμεύουν στην πράξη ζουν στο
 * {@link module:subapps/dxf-viewer/bim/table/table-capacity} και είναι **γινόμενα**
 * μετρημένου κόστους: το πυκνό πλέγμα (κόστος διάταξης) και τα bytes (κόστος εγγράφου).
 * Αυτό το αρχείο απαντά μόνο *«μπορεί αυτό να γραφτεί σε `.xlsx`;»* — μια ερώτηση με
 * **εξωτερική** αυθεντία, που γι' αυτό δεν επιτρέπεται να αναμειχθεί με τις δικές μας
 * μετρήσεις. Δύο ερωτήσεις, δύο αρχεία.
 *
 * ## ⚠️ Η ΑΙΤΙΟΛΟΓΗΣΗ ΠΟΥ ΑΠΟΣΥΡΘΗΚΕ, και δεν σβήστηκε
 *
 * Μέχρι τη Φάση 5Β τα άνω όρια ήταν **256 στήλες / 1.000 γραμμές**, με αιτιολόγηση το
 * **χαρτί**: *«256 στήλες × ελάχιστο πλάτος 4 mm = 1.024 mm, σχεδόν ολόκληρο το A0»*.
 * Η αιτιολόγηση **δεν επιβίωσε** δύο ελέγχους:
 *
 * 1. **Ίσχυε μόνο στο ελάχιστο πλάτος.** Με το προεπιλεγμένο πλάτος (40 mm) το A0
 *    ξεπερνιέται στις **30** στήλες — δηλαδή το όριο των 256 δεν φύλαγε ποτέ το χαρτί·
 *    φύλαγε την υποθετική περίπτωση όπου κάθε στήλη είναι η στενότερη δυνατή.
 * 2. **Ο πίνακας έπαψε να είναι μόνο σχέδιο.** Από τη Φάση 1 διαβάζει `.xlsx` και από τη
 *    Φάση 6 γράφει `.xlsx`: ένα πρόγραμμα οπλισμού 3.000 γραμμών είναι **δεδομένα** που
 *    τυπώνονται σε σελίδες, όχι γραφικό που πρέπει να χωρέσει σε ένα φύλλο.
 *
 * 🔑 Ό,τι **επιβίωσε** από το επιχείρημα του χαρτιού είναι το πλάτος **ανά στήλη**
 * (`MAX_TABLE_COLUMN_WIDTH_MM = 1189`, η μεγάλη πλευρά του A0) — εκεί το επιχείρημα είναι
 * ακέραιο: μια στήλη φαρδύτερη από ένα A0 δεν είναι στήλη. Μένει όπου ήταν.
 *
 * @module subapps/dxf-viewer/bim/table/table-ooxml-limits
 * @see bim/table/table-capacity — τα όρια που **μετρήθηκαν** (πυκνό πλέγμα, bytes)
 * @see bim/table/export — ο καταναλωτής της υπόσχεσης που κάνει αυτούς τους αριθμούς δεσμευτικούς
 * @see docs/centralized-systems/reference/adrs/ADR-833-table-xlsx-import-and-worksheets.md §5.8.5
 */

/**
 * Στήλες ανά φύλλο εργασίας, όπως τις ορίζει το Excel/OOXML (τελευταία στήλη: `XFD`).
 *
 * ⚠️ **Ράγα, όχι προϋπολογισμός**: στην πράξη δεσμεύει πρώτο το γινόμενο του
 * `MAX_TABLE_GRID_CELLS`. Δεσμεύει **μόνο** στην ακραία περίπτωση του πίνακα με μία γραμμή.
 */
export const MAX_TABLE_COLUMN_COUNT = 16_384;

/** Γραμμές ανά φύλλο εργασίας, όπως τις ορίζει το Excel/OOXML. Ίδια ιδιότητα ράγας. */
export const MAX_TABLE_TOTAL_ROW_COUNT = 1_048_576;

/**
 * Χαρακτήρες ανά κελί — **η μόνη ράγα που δεσμεύει σε ρεαλιστική χρήση**.
 *
 * ## 🔴 Η ΜΟΝΑΔΑ ΕΙΝΑΙ ΧΑΡΑΚΤΗΡΕΣ, ΟΧΙ BYTES — και δηλώνεται επειδή κόστισε αλλού
 * Το πρότυπο μετρά **χαρακτήρες**. Ένα όριο σε bytes θα έκοβε το ελληνικό κείμενο στο
 * **μισό** μήκος από το αγγλικό (×2 σε UTF-8, ADR-833 §5.6.2) για λόγο που **κανένα
 * πρότυπο δεν στηρίζει**, και ο χρήστης δεν θα είχε αρχή να επικαλεστεί. Το ίδιο ADR έχει
 * ήδη τιμωρήσει δύο πεδία με ασαφή μονάδα (§5.7.2 `widthHint`· ADR-716).
 *
 * ⚠️ Μετριέται με `String.length`, δηλαδή σε **μονάδες UTF-16** — και αυτό είναι το σωστό
 * εδώ, όχι αντίφαση με το `lib/serialized-size`: εκείνο απαντά *«πόσα bytes ανεβαίνουν;»*
 * (μονάδα του δικτύου), αυτό απαντά *«πόσους χαρακτήρες δέχεται το πρότυπο;»* (μονάδα του
 * προτύπου, που είναι κι αυτή UTF-16 στο XML). **Δύο ερωτήσεις, δύο μονάδες, καμία δεν
 * δανείζεται από την άλλη.**
 */
export const MAX_TABLE_CELL_CHARACTERS = 32_767;

/** Τι έμεινε από ένα κείμενο αφού περάσει τη ράγα του προτύπου. */
export interface ClippedCellText {
  /** Το κείμενο όπως επιτρέπεται να αποθηκευτεί. Ίδιο **by-reference** όταν χώραγε. */
  readonly text: string;
  /** Πόσοι χαρακτήρες κόπηκαν· `0` όταν δεν κόπηκε τίποτα. */
  readonly clippedCharacters: number;
}

/**
 * Κόβει ένα κείμενο κελιού στο όριο του προτύπου — **και λέει πόσο έκοψε**.
 *
 * ## Γιατί κόβει αντί να αρνείται
 * Η άρνηση ολόκληρης μιας επικόλλησης επειδή **ένα** κελί ήταν μακρύ πετά δουλειά που ο
 * χρήστης έχει ήδη κάνει. Το ADR-833 έχει ήδη λεξιλόγιο γι' αυτό (`tableXlsx.clipped`,
 * §4.3 «καμία σιωπηλή απώλεια»): **κόψε και πες το με αριθμό**. Ένα δεύτερο λεξιλόγιο για
 * την ίδια απώλεια θα ήταν ακριβώς η κατηγορία που το §5.7.5 απαγόρευσε.
 *
 * ⚠️ Το `clippedCharacters` **δεν** συνάγεται με αφαίρεση από τον καλούντα: ο ίδιος
 * κανόνας με το `TablePasteResult` — ό,τι χάθηκε το λέει εκείνος που το έκοψε, γιατί μόνο
 * αυτός ξέρει **γιατί**.
 *
 * ⚠️ **ΔΙΟΡΘΩΣΗ ΣΧΟΛΙΟΥ (μετάλλαξη M22, Φ5Β).** Εδώ έγραφε *«ίδια αναφορά όταν δεν κόπηκε
 * τίποτα»*. Η μετάλλαξη `return { text, … }` → `return { text: String(text), … }` έμεινε
 * **πράσινη**, και δεν φταίει η άγκυρα: στη JavaScript οι συμβολοσειρές είναι
 * **πρωτόγονες** και συγκρίνονται **κατά τιμή** — το `String(x)` πάνω σε πρωτόγονο
 * επιστρέφει το ίδιο πρωτόγονο, και **καμία** παρατήρηση δεν ξεχωρίζει «ίδια αναφορά» από
 * «ίση τιμή». Η αρχική διατύπωση περιέγραφε ιδιότητα που **δεν υπάρχει**.
 *
 * 🔑 Αυτό που **όντως** ισχύει, και είναι αγκυρωμένο ένα επίπεδο πιο πάνω: ο πρόωρος κλάδος
 * δεν κάνει **καμία δουλειά** (ούτε `slice`, ούτε αφαίρεση) σε διαδρομή που τρέχει σε κάθε
 * δέσμευση κελιού· και η **ταυτότητα του μοντέλου** by-reference — που είναι πραγματικά
 * παρατηρήσιμη — τη δίνει η τέταρτη εγγύηση του `setPersistedCellText`, με δική της άγκυρα
 * στο `table-capacity-doors.test.ts`.
 */
export function clipTableCellText(text: string): ClippedCellText {
  if (text.length <= MAX_TABLE_CELL_CHARACTERS) return { text, clippedCharacters: 0 };
  return {
    text: text.slice(0, MAX_TABLE_CELL_CHARACTERS),
    clippedCharacters: text.length - MAX_TABLE_CELL_CHARACTERS,
  };
}
