/**
 * 🔴 ADR-739 §63 — **ΤΙ ΣΗΜΑΙΝΕΙ «ΟΚ» ΣΕ ΔΙΑΛΟΓΟ ΠΟΥ ΕΠΙΒΙΩΝΕΙ ΤΗΣ ΣΥΝΕΔΡΙΑΣ ΤΟΥ.**
 *
 * Καθαρή συνάρτηση: μηδέν σκηνή, μηδέν store, μηδέν React, μηδέν εντολή. Απαντά **τι θα
 * γινόταν**, ώστε η ίδια απάντηση να δίνεται στον φρουρό της γραφής, στην οθόνη και στο test.
 * Ίδιο πρότυπο — και ίδια αιτιολόγηση — με το `table-write-back-plan.ts` (ADR-769) και το
 * `AssignTopoElevationCommand.fromPlan`: *«το πλάνο υπολογίζεται στο UI ώστε ο χρήστης να δει τι
 * θα γίνει πριν πατήσει, και εκτελείται αυτούσιο, ώστε αυτό που εγκρίθηκε να είναι ακριβώς αυτό
 * που γράφεται»*.
 *
 * ## 🔴 ΤΟ ΕΛΑΤΤΩΜΑ ΠΟΥ ΚΛΕΙΝΕΙ — μετρημένο στον κώδικα πριν γραφτεί γραμμή
 *
 * Ο διάλογος «Μορφοποίηση κελιών» έγινε **αιωρούμενος** (ADR-750 Φ6β) και κράτησε το «ΟΚ /
 * Άκυρο» του modal προκατόχου του. Το «ΟΚ» κατέληγε σε `TableFormatPort.commitModel`, που
 * ρωτούσε **τον πίνακα του δρομέα** (`cursorTable()`) — δηλαδή **ξαναμάντευε** πού γράφει, τη
 * στιγμή του πατήματος, από κατάσταση που ο διάλογος **δεν** ελέγχει:
 *
 * ```
 *   ο διάλογος ξέρει:      ποια κελιά   (target.scope, παγωμένα — κανόνας Α22)
 *   το commit μάντευε:     ποιος πίνακας (cursorTable(), ζωντανό)
 * ```
 *
 * **Δύο αλήθειες για το «πού γράφω»** — και όταν διαφωνούσαν δεν υπήρχε σφάλμα, υπήρχε
 * **σιωπή** (`if (!live) return`). Οι τρεις μετρημένες καταστάσεις:
 *
 * ```
 *   κανένας δρομέας (Escape με εστίαση έξω)  ⇒ σιωπηλό no-op· ο διάλογος έκλεινε σαν να έγραψε
 *   ο δρομέας σε ΑΛΛΟΝ πίνακα                ⇒ UpdateEntityCommand(Β.id, {model: προσχέδιο ΤΟΥ Α})
 *                                              — ο πίνακας Β γινόταν ο πίνακας Α
 *   ο δρομέας εδώ, μοντέλο ΑΛΛΑΓΜΕΝΟ         ⇒ lost update: το προσχέδιο έσβηνε ό,τι μεσολάβησε
 * ```
 *
 * Τέσσερις δυνατές καταστάσεις τη στιγμή του «ΟΚ», **μία** σωστή — και οι τρεις άλλες σιωπηλές.
 *
 * ## 🔑 ΓΙΑΤΙ Η ΘΕΡΑΠΕΙΑ ΔΕΝ ΕΙΝΑΙ «ΝΑ ΚΛΕΙΝΕΙ Ο ΔΙΑΛΟΓΟΣ ΜΑΖΙ ΜΕ ΤΗ ΣΥΝΕΔΡΙΑ»
 * Θα πετούσε τη δουλειά του χρήστη (οκτώ ρυθμίσεις, ένα άστοχο `Escape`, όλα χαμένα) και θα
 * ακύρωνε τον κανόνα Α22, που παγώνει τον στόχο **σκόπιμα**: ο στόχος ταξιδεύει με το αίτημα.
 * Το πρόβλημα δεν ήταν ότι ο στόχος παγώνει — ήταν ότι **πάγωνε μόνο ο μισός**.
 *
 * ## 🔑 Η ΒΑΣΗ ΣΥΓΚΡΙΣΗΣ ΥΠΗΡΧΕ ΗΔΗ — δεν προστίθεται πεδίο
 * Το `FormatTarget.model` **είναι** το μοντέλο τη στιγμή του ανοίγματος, δηλαδή κατά γράμμα το
 * «content last read» ενός compare-and-swap. Είναι η **δεύτερη** εμφάνιση του ίδιου σχήματος
 * στο ίδιο ADR: το ADR-769 βρήκε ότι το `sourceValue` **ήταν ήδη** η βάση του CAS και δεν
 * χρειάστηκε νέα κατάσταση. Ένα πρόσθετο `baseModelRef` εδώ θα ήταν **δεύτερη** αλήθεια για το
 * «τι διάβασε ο διάλογος», με μία ευκαιρία να αποκλίνει.
 *
 * ## 🔴 Η ΣΕΙΡΑ ΤΩΝ ΦΡΟΥΡΩΝ ΕΙΝΑΙ ΤΟ ΣΥΜΒΟΛΑΙΟ
 * ```
 *   1. στόχος  — υπάρχει ακόμη ο πίνακας που ρωτήθηκε;   (target-missing)
 *   2. βάση    — είναι ακόμη αυτό που διαβάστηκε;         (target-changed · compare-and-swap)
 *   3. αλλαγή  — άλλαξε πράγματι κάτι;                    (unchanged · ταυτοδυναμία, N.7.2 #3)
 * ```
 * Ο έλεγχος της **βάσης** προηγείται του ελέγχου **αλλαγής**, και αυτό δεν είναι στιλιστικό:
 * πάνω σε μπαγιάτικη βάση το «τίποτα δεν άλλαξε» είναι **σύμπτωση, όχι ησυχία** — το προσχέδιο
 * μπορεί να είναι ταυτόσημο με ό,τι διαβάστηκε **και** εντελώς άσχετο με ό,τι ισχύει τώρα. Η
 * ίδια διάταξη, με τον ίδιο λόγο, στο ADR-769 §4.
 *
 * @module subapps/dxf-viewer/bim/table/table-format-commit-plan
 * @see ui/table-cell-editor/table-format-snapshot.ts — ο `FormatTarget` που κουβαλά τη βάση
 * @see bim/table/table-write-back-plan.ts — το πρότυπο (ADR-769)
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §63
 */

import type { PersistedTableModel } from '../../types/table';

/**
 * Γιατί μια δέσμευση **δεν** γίνεται. Ρητός λόγος, ποτέ σιωπηλή απόρριψη: ο χρήστης πρέπει να
 * ξεχωρίζει «ο πίνακας **έφυγε**» από «ο πίνακας **άλλαξε**», γιατί η δική του επόμενη κίνηση
 * είναι άλλη — στο πρώτο δεν υπάρχει τίποτα να ξαναπροσπαθήσει, στο δεύτερο υπάρχει.
 *
 * - `target-missing` — ο πίνακας που ρωτήθηκε δεν υπάρχει πια στη σκηνή (διαγράφηκε, αναιρέθηκε
 *   η δημιουργία του, ή άλλαξε ο ενεργός όροφος).
 * - `target-changed` — ο πίνακας υπάρχει, αλλά το μοντέλο του **δεν** είναι εκείνο που διάβασε ο
 *   διάλογος: κάποιος έγραψε στο μεταξύ (πληκτρολόγηση κελιού, κουμπί κορδέλας, `Ctrl+Z`).
 *   Γράφοντας εδώ, το προσχέδιο θα **έσβηνε** εκείνη τη γραφή — και ο διάλογος δεν έχει τρόπο
 *   να το γνωρίζει, γιατί κρατά ολόκληρο μοντέλο, όχι λίστα αλλαγών.
 */
export type TableFormatCommitRefusal = 'target-missing' | 'target-changed';

/**
 * Ό,τι χρειάζεται η απόφαση, και **τίποτα** από τη σκηνή: ο καλών έχει ήδη ρωτήσει.
 */
export interface TableFormatCommitRequest {
  /**
   * Το μοντέλο του πίνακα-στόχου **τώρα**· `null` = ρωτήθηκε και **δεν υπάρχει**.
   *
   * ⚠️ Το `null` δηλώνει απουσία **οντότητας**, ποτέ «δεν ρώτησε κανείς» — ο καλών καλεί πάντα
   * `resolveTableById` πριν φτάσει εδώ. Η διάκριση έχει σημασία επειδή στο ADR-769 το
   * αντίστοιχο `undefined` σημαίνει το αντίθετο, και δύο πλάνα με ανάποδη σύμβαση για το ίδιο
   * κενό θα ήταν παγίδα για τον επόμενο αναγνώστη.
   */
  readonly liveModel: PersistedTableModel | null;
  /** Ό,τι διάβασε ο διάλογος στο άνοιγμα (`FormatTarget.model`) — η βάση του CAS. */
  readonly baseModel: PersistedTableModel;
  /** Το προσχέδιο που παραδίδει το «ΟΚ». */
  readonly draftModel: PersistedTableModel;
}

/**
 * Η απόφαση. Τρεις καταστάσεις, καμία σιωπηλή — και το `accepted` κουβαλά **το μοντέλο**, ώστε
 * ο εκτελεστής να γράφει το πλάνο **αυτούσιο** αντί να ξανασυνθέτει την απάντηση.
 */
export type TableFormatCommitPlan =
  | { readonly status: 'accepted'; readonly model: PersistedTableModel }
  | { readonly status: 'unchanged' }
  | { readonly status: 'refused'; readonly reason: TableFormatCommitRefusal };

/**
 * Το «ΟΚ» ενός αιωρούμενου διαλόγου → μία απόφαση.
 *
 * 🔑 Και οι δύο συγκρίσεις είναι **ταυτότητας** (`===`) και όχι περιεχομένου, και αυτό είναι η
 * ίδια εγγύηση που στηρίζει ήδη το `buildTableModelCommand`: κάθε γραφέας μορφοποίησης
 * επιστρέφει το **ίδιο** αντικείμενο by-reference όταν καμία τιμή δεν αλλάζει (ADR-739 Φ.Δ βήμα
 * 1, εγγύηση 4). Μια σύγκριση βάθους εδώ θα ήταν δεύτερη υλοποίηση της ισότητας μοντέλων — και
 * θα έλεγε «ίδια» για δύο αντικείμενα που το commit θεωρεί διαφορετικά.
 */
export function planTableFormatCommit(
  request: TableFormatCommitRequest,
): TableFormatCommitPlan {
  const { liveModel, baseModel, draftModel } = request;

  // 1. στόχος — ο πίνακας που ρωτήθηκε.
  if (liveModel === null) return { status: 'refused', reason: 'target-missing' };

  // 2. βάση — compare-and-swap. **Πριν** τον έλεγχο αλλαγής: δες την κεφαλίδα.
  if (liveModel !== baseModel) return { status: 'refused', reason: 'target-changed' };

  // 3. αλλαγή — «άνοιξα, πείραξα, το ξαναέφερα όπως ήταν, ΟΚ» δεν αφήνει ίχνος (§60).
  if (draftModel === baseModel) return { status: 'unchanged' };

  return { status: 'accepted', model: draftModel };
}
