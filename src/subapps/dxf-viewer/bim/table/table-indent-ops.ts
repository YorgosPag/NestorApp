/**
 * 🔴 ADR-739 §59 Δ2 — **ΤΙ ΣΗΜΑΙΝΕΙ ΤΟ ΠΑΤΗΜΑ** στα δύο κουμπιά εσοχής («Αύξηση» / «Μείωση»),
 * και **πόσο είναι ένα σκαλί σε mm**. Καθαρό· μηδέν React, μηδέν DOM.
 *
 * Αδελφό των {@link ./table-align-ops} · {@link ./table-number-format-ops} ·
 * {@link ./table-overflow-ops}, με τον ίδιο λόγο ύπαρξης: η γνώση έχει **δύο** επιφάνειες
 * (mini toolbar + κορδέλα) και μια δεύτερη γραφή της θα ήταν δύο ευκαιρίες να μάθει κάθε
 * επιφάνεια άλλον κανόνα, με κάθε πλευρά της να «δουλεύει».
 *
 * ## 🔴 ΔΥΟ ΕΡΩΤΗΣΕΙΣ ΣΕ ΕΝΑ ΑΡΧΕΙΟ, ΚΑΙ ΕΙΝΑΙ Η ΙΔΙΑ ΑΠΟΦΑΣΗ
 * «Πόσα σκαλιά;» (το κουμπί) και «πόσο μακριά είναι ένα σκαλί;» (η διάταξη) φαίνονται
 * διαφορετικές, αλλά δένονται από **μία** σταθερά — το {@link TABLE_INDENT_SPACES}. Χωρισμένες
 * σε δύο αρχεία, η μέρα που το σκαλί γίνει 2 ή 4 κενά θα άλλαζε το ένα και όχι το άλλο, και το
 * σύμπτωμα θα ήταν κουμπί που μετρά αλλιώς από όσο ζωγραφίζει.
 *
 * ## 🔬 Η ΜΟΝΑΔΑ ΕΙΝΑΙ ΤΟΥ EXCEL, ΕΠΑΛΗΘΕΥΜΕΝΗ ΣΤΗΝ ΠΡΟΔΙΑΓΡΑΦΗ
 * ECMA-376 §18.8.1 (`alignment/@indent`), **αυτολεξεί**: *«An integer value, where an increment
 * of 1 represents 3 spaces»*, με τον τύπο `Number of spaces to indent = @indent value * 3`.
 * Άρα το σκαλί **δεν** είναι mm ούτε em: είναι **τρία πλάτη κενού της γραμματοσειράς του
 * κελιού**. Γι' αυτό το μετρά ο {@link TableTextMeasurer} — ο **ίδιος** που αποφάσισε τα πλάτη
 * στηλών και την περικοπή. Ένα σταθερό `1,5mm` εδώ θα «ξεκόλλαγε» από τα γράμματα σε κάθε
 * αλλαγή ύψους κειμένου, δηλαδή θα ήταν δεύτερη τυπογραφική αυθεντία δίπλα στον μετρητή.
 *
 * ## 🔴 ΠΟΥ ΔΕΝ ΙΣΧΥΕΙ — και γιατί το επιβάλλει ο τύπος, όχι σχόλιο
 * Η ίδια προδιαγραφή: *«Only left, right, and distributed horizontal alignments are supported»*.
 * Σε **κεντραρισμένο** κελί η εσοχή δεν σημαίνει τίποτα — το κείμενο κάθεται στον άξονα του
 * κελιού, και μια μετατόπιση θα το ξεκεντράριζε χωρίς κανείς να τη ζητήσει. Το
 * {@link tableIndentOffsetMm} απαντά **0** εκεί, οπότε κανένας καταναλωτής δεν χρειάζεται να
 * θυμηθεί τον κανόνα: ούτε η άγκυρα, ούτε το ωφέλιμο πλάτος, ούτε η μέτρηση `hug`.
 *
 * *(Το `distributed` δεν υπάρχει στο δικό μας λεξιλόγιο στοίχισης — {@link TableCellAlign} έχει
 * τις **εννιά** θέσεις του `ACAD_TABLE`, όπου η οριζόντια συνιστώσα είναι αριστερά/κέντρο/δεξιά.
 * Δηλωμένο ρητά, όχι σιωπηλά απόν.)*
 *
 * @module subapps/dxf-viewer/bim/table/table-indent-ops
 * @see bim/table/table-style.ts — πού ζει το επιλυμένο `indentLevel` (και γιατί ΟΧΙ στα margins)
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §59
 */

import type { TextAlign } from '../structural/detail-sheet/detail-sheet-types';
import type { TableCellStyle } from './table-style';
import type { TableTextMeasurer } from './table-layout-types';

/**
 * Πόσα κενά είναι **ένα** σκαλί εσοχής — ECMA-376 §18.8.1, αυτούσιο.
 *
 * Δεν είναι δική μας επιλογή και δεν πρέπει να γίνει: το αίτημα του ιδιοκτήτη είναι «1:1 με τα
 * πλήκτρα του Excel», και ένα κελί που στο Excel ξεκινά στο τρίτο κενό οφείλει να ξεκινά στο
 * τρίτο κενό και εδώ.
 */
export const TABLE_INDENT_SPACES = 3;

/**
 * Το ανώτατο σκαλί. **Δικό μας όριο**, μικρότερο του Excel — και είναι απόφαση, όχι αντιγραφή.
 *
 * Το OOXML δηλώνει `unsignedInt` και το Excel δέχεται μέχρι **250** στον διάλογο «Μορφοποίηση
 * κελιών». Σε φύλλο υπολογισμού είναι ακίνδυνο: η στήλη δεν μεγαλώνει (το AutoFit του Excel
 * αγνοεί την εσοχή), οπότε το μόνο που παθαίνει ο χρήστης είναι ένα άδειο κελί.
 *
 * 🔴 **Εδώ ΔΕΝ είναι ακίνδυνο, ακριβώς επειδή η εσοχή συμμετέχει στο `hug` πλάτος** (η υπεροχή
 * του §59 Δ2): με 250 σκαλιά μια `hug` στήλη θα ζητούσε **750 πλάτη κενού** και θα έσπρωχνε
 * κάθε επόμενη στήλη έξω από το χαρτί. Το φράγμα είναι το τίμημα της υπεροχής, γραμμένο δίπλα
 * της. Δεκαπέντε σκαλιά = 45 κενά ≈ μισή στήλη κειμένου: πέρα από αυτό δεν υπάρχει ιεραρχία
 * να δείξεις, υπάρχει κελί που άδειασε.
 */
export const MAX_TABLE_INDENT_LEVEL = 15;

/** `+1` αυξάνει την εσοχή. Ίδιο σχήμα με το `TableDecimalStepDirection` του αριθμού. */
export type TableIndentStepDirection = 1 | -1;

/**
 * Ένα σκαλί πάνω/κάτω — `null` ⇒ **καμία εγγραφή**.
 *
 * ```
 *   αριθμός     →  γράψε αυτόν  (setField('indentLevel', value))
 *   undefined   →  ΣΒΗΣΕ το πεδίο ⇒ κληρονομιά (η επιστροφή στο μηδέν είναι ΞΕΠΑΤΩΜΑ)
 *   null        →  ΚΑΜΙΑ εγγραφή (είμαστε στο άκρο)
 * ```
 *
 * 🔑 **Το μηδέν σβήνει το πεδίο αντί να γράψει `0`** — και δεν είναι καλλωπισμός: ένα ρητό `0`
 * στο κελί θα **νικούσε** μια εσοχή δηλωμένη στη γραμμή ή τη στήλη, δηλαδή η «Μείωση εσοχής»
 * μέχρι το τέρμα θα άφηνε πίσω της κατάσταση που η «Επαναφορά μορφοποίησης» θα έπρεπε να
 * καθαρίσει. Ίδια σύμβαση με το `nextTableNumberFormat`, όπου το ξεπάτωμα γυρίζει στην
 * κληρονομιά αντί να γράψει την προεπιλογή.
 *
 * ⚠️ Ανάμεικτος στόχος (`null` είσοδος) διαβάζεται ως `0`: ο χρήστης που πατά «Αύξηση» πάνω σε
 * ανάμεικτη επιλογή ζητά «βάλ' τα όλα ένα σκαλί μέσα», και η ισοπέδωση προς την κατεύθυνση του
 * κουμπιού είναι η αρχή που ήδη εφαρμόζουν το `nextBooleanFormat` και το `nextTableAlign`.
 */
export function nextTableIndentLevel(
  current: number | null,
  direction: TableIndentStepDirection,
): number | undefined | null {
  const from = clampIndentLevel(current ?? 0);
  const next = from + direction;
  if (next < 0 || next > MAX_TABLE_INDENT_LEVEL) return null;
  return next === 0 ? undefined : next;
}

/**
 * Η εσοχή σε **sheet-mm**, ή `0` όταν δεν ισχύει.
 *
 * Επιστρέφει `0` και για τους **δύο** λόγους που η εσοχή μπορεί να μην ισχύει — μηδενικό σκαλί
 * και κεντραρισμένη στοίχιση — επίτηδες: ο καλών προσθέτει/αφαιρεί ένα μήκος και δεν χρειάζεται
 * να μάθει κανέναν κανόνα. Τρεις καταναλωτές (μέτρηση `hug` · ωφέλιμο πλάτος · άγκυρα) που
 * έπρεπε ο καθένας να θυμηθεί το «όχι στο κέντρο» θα ήταν τρεις ευκαιρίες να το ξεχάσει ένας.
 *
 * ⚠️ Μετριέται με τον **ίδιο** {@link TableTextMeasurer} που αποφάσισε τα πλάτη στηλών: η εσοχή
 * αφαιρείται από το ωφέλιμο πλάτος και προστίθεται στο `hug`, οπότε ένα δεύτερο όργανο εδώ θα
 * έδινε κελί που «κόβεται ενώ η στήλη είχε μετρηθεί αρκετά πλατιά» — ακριβώς η αστοχία που
 * προειδοποιεί το `resolveTableTextMeasurer`.
 */
export function tableIndentOffsetMm(
  style: TableCellStyle,
  hAlign: TextAlign,
  measure: TableTextMeasurer,
): number {
  const level = clampIndentLevel(style.indentLevel);
  if (level === 0 || hAlign === 'center') return 0;
  const stepMm = measure(' '.repeat(TABLE_INDENT_SPACES), style.textHeightMm, {
    fontFamily: style.fontFamily,
    bold: style.bold,
    italic: style.italic,
  });
  return stepMm * level;
}

/**
 * Το σκαλί μέσα στα όρια, ως **ακέραιος**.
 *
 * Ιδιωτικό και μοιρασμένο ανάμεσα στις δύο εξαγόμενες: το μοντέλο δέχεται `number` (ένα
 * `indentLevel: 2.5` ή `-1` είναι εκφράσιμο σε αποθηκευμένο αρχείο που έγραψε άλλη έκδοση), και
 * ο μόνος τρόπος να μην απαντήσουν οι δύο διαφορετικά είναι να ρωτούν την ίδια συνάρτηση.
 * Χωρίς το `Math.floor`, ένα κλασματικό σκαλί θα ζωγραφιζόταν κανονικά και **κανένα** κουμπί δεν
 * θα μπορούσε να το επαναφέρει στο μηδέν.
 */
function clampIndentLevel(level: number): number {
  if (!Number.isFinite(level)) return 0;
  return Math.min(Math.max(Math.floor(level), 0), MAX_TABLE_INDENT_LEVEL);
}
