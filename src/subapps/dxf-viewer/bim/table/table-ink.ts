/**
 * Η δεσμευμένη τιμή του `textColorHex` που σημαίνει «**υπολόγισέ με από το φόντο**».
 *
 * Σκόπιμα **όχι** `#rrggbb`: το `parseHex` το απορρίπτει, άρα κάθε καταναλωτής που το δει
 * ανεπίλυτο βρίσκεται σε λάθος — δεν υπάρχει «σχεδόν σωστή» ερμηνεία του.
 */
export const AUTOMATIC_TABLE_INK = 'auto';

/**
 * **Το χαρτί.** Κάθε εξαγωγή (PDF / DXF / ΤΕΚ) και κάθε raster εκτύπωση καταλήγει σε λευκή
 * σελίδα — ο offscreen καμβάς της εκτύπωσης μένει **διάφανος** επίτηδες, δηλαδή το σκούρο του
 * viewer **δεν** αναπαράγεται. Ρητή σταθερά ώστε η λέξη «χαρτί» να μη γραφτεί ως literal σε
 * τρία σημεία που μπορούν να αποκλίνουν.
 */
export const TABLE_PAPER_HEX = '#ffffff';

/**
 * 🔴 ADR-771 Φ.2 — **Το φύλλο**: ουδέτερη ανοιχτή, **αδιαφανής** επιφάνεια ανάγνωσης.
 *
 * ## Γιατί ΟΧΙ `#ffffff` — μετρημένο, όχι αισθητικό
 * Το `resolveTableBorderInk` κάνει **ρητό early-return** στο `TABLE_PAPER_HEX`: στο χαρτί ένα
 * ρητό χρώμα περιγράμματος μένει **αυτούσιο**, γιατί το έγγραφο σέβεται την απόφαση του
 * συντάκτη (§ «ΤΟ ΧΑΡΤΙ ΔΕΝ ΑΓΓΙΖΕΤΑΙ ΠΟΤΕ»). Αν το φύλλο ήταν κι αυτό `#ffffff`, οι δύο
 * καταστάσεις θα κατέρρεαν σε **μία** σε κάθε υπολογισμό. Με ξεχωριστή τιμή, το «Φύλλο»
 * συμπεριφέρεται ως **θέαση** (τα περιγράμματα προσαρμόζονται για να διαβάζονται) και το
 * «Χαρτί» ως **παραδοτέο** (τίποτα δεν αγγίζεται) — **χωρίς κανέναν νέο κλάδο**.
 *
 * ## Η επιλογή της τιμής, μετρημένη από την πηγή
 * ```
 * μελάνι (argmax):        ΜΑΥΡΟ            — όπως κάθε ανοιχτή επιφάνεια
 * πλέγμα #666666:         5,27:1  ✅ > 3,0 (MIN_ENTITY_CONTRAST)
 * έναντι χαρτιού:         1,090:1          — ⚠️ ΑΔΙΑΚΡΙΤΟ με το μάτι
 * έναντι καμβά #1d283a:  13,59:1
 * ```
 * ⚠️ Το `1,090:1` **δεν είναι ελάττωμα αυτής της τιμής — είναι ιδιότητα του άξονα**: κάθε
 * ουδέτερο ανοιχτό γκρι δίνει 1,09–1,23:1. Γι' αυτό ο φορέας της διάκρισης «Φύλλο vs Χαρτί»
 * **δεν είναι η απόχρωση**, είναι ο μόνιμα ορατός δείκτης κατάστασης (WCAG 1.4.1 — το ίδιο
 * μάθημα με τη Φ.1). Μην αλλάξεις αυτή την τιμή περιμένοντας να λύσει τη διάκριση.
 */
export const TABLE_SHEET_HEX = '#f5f5f5';

/** `true` όταν το χρώμα είναι το σεντινέλι — ποτέ σύγκριση με literal αλλού. */
export function isAutomaticTableInk(colorHex: string): boolean {
  return colorHex === AUTOMATIC_TABLE_INK;
}

/**
 * **Τι υπάρχει πίσω από το κείμενο του κελιού** — ο ΕΝΑΣ κανόνας, για τα τρία σύνορα.
 *
 * Το γέμισμα του κελιού νικά την επιφάνεια: ένα λευκό μελάνι πάνω σε ανοιχτό γέμισμα κεφαλίδας
 * είναι **το ίδιο ελάττωμα σε μικρογραφία** — και το έργο το έχει ήδη πληρώσει μία φορά
 * (ADR-739 §19.8: «όποιο κελί έχει γέμισμα, χάνει το κείμενο»).
 *
 * 🔴 **ΔΕΝ είναι νέα λογική.** Ο κανόνας ήταν ήδη γραμμένος, αυτούσιος, στο
 * `table-cell-editor-frame.ts` (`style.fillColorHex ?? backgroundHex`) και κλειδωμένος με 3
 * tests. Εξάγεται εδώ ώστε ο τρίτος και ο τέταρτος καταναλωτής να **μην** τον ξαναγράψουν —
 * αυτό ακριβώς που το CHECK 3.28 (jscpd) πιάνει ως sibling clone, ανεξάρτητα ονόματος.
 *
 * ⚠️ Το χρώμα **φάσης** (hover) δεν μπαίνει εδώ επίτηδες: ο ζωγράφος έχει ήδη αποφασίσει,
 * μετρημένα, ότι το κείμενο **δεν** παίρνει `phaseColor` ώστε «η αντίθεση που σχεδίασε ο
 * συγγραφέας του στυλ να επιβιώνει σε κάθε φάση» (`stamp-table-text.ts`). Το αυτόματο μελάνι
 * υπακούει στον ίδιο κανόνα — αλλιώς το κείμενο θα άλλαζε χρώμα στο πέρασμα του ποντικιού.
 *
 * @param fillColorHex το γέμισμα του κελιού· `null` = ρητά κανένα, `undefined` = δεν δηλώθηκε.
 * @param surfaceHex   η επιφάνεια από κάτω: φόντο καμβά (οθόνη) ή {@link TABLE_PAPER_HEX}.
 */
export function tableCellBackdrop(
  fillColorHex: string | null | undefined,
  surfaceHex: string,
): string {
  return fillColorHex ?? surfaceHex;
}

/**
 * Επιλύει το μελάνι ενός κελιού: το σεντινέλι γίνεται λευκό ή μαύρο κατά το `backdropHex`·
 * κάθε ρητό χρώμα επιστρέφεται **αυτούσιο**.
 *
 * Το `backdropHex` είναι **όρισμα**, ποτέ διαβασμένο μέσα: σε jsdom το
 * `resolveDxfCanvasBackgroundHex()` επιστρέφει πάντα το σκούρο default, οπότε μια συνάρτηση που
 * το ρωτούσε μόνη της θα δοκιμαζόταν **μόνο** στην κατεύθυνση «σκούρο → λευκό» και θα έμενε
 * πράσινη με σπασμένη την «λευκό → μαύρο».
 */
export function resolveTableInk(colorHex: string, backdropHex: string): string {
  return isAutomaticTableInk(colorHex) ? maxContrastInk(backdropHex) : colorHex;
}

/**
 * 🔴 **Ο ΕΝΑΣ κόμβος όπου το σεντινέλι παύει να υπάρχει.**
 *
 * Καλείται από το `placeCells` πάνω στο **επιλυμένο** στυλ κάθε κελιού, δηλαδή αφού έχουν ήδη
 * πέσει οι παρακάμψεις κελιού/γραμμής/στήλης. Από εκεί και πέρα **ούτε** το
 * `TableCellLayout.style.textColorHex` **ούτε** το `TableTextRun.colorHex` μπορούν να κρατούν
 * το {@link AUTOMATIC_TABLE_INK}.
 *
 * ## Γιατί στο ΣΤΥΛ και όχι μόνο στο run
 * Το `TableTextRun` γεννιέται μόνο για **γεμάτα** κελιά. Ο in-cell επεξεργαστής όμως ανοίγει και
 * σε **κενό** κελί, και διαβάζει το χρώμα του από το `TableCellLayout.style` — δηλαδή από άλλο
 * πεδίο. Επίλυση μόνο στο run θα άφηνε το σεντινέλι να φτάσει ως το CSS `color` του `<textarea>`,
 * όπου είναι **κληρονομούμενη** ιδιότητα και άρα δεν σπάει: το κείμενο θα έπαιρνε απλώς το χρώμα
 * του γονέα, χωρίς κανένα σφάλμα πουθενά. Ένα πεδίο, ένας κόμβος επίλυσης.
 *
 * Μη-σεντινέλι ⇒ επιστρέφεται **η ίδια αναφορά**: το `TableCellStyle` ταξιδεύει σε κάθε κελί
 * κάθε καρέ και ένα νέο αντικείμενο ανά κελί θα ήταν δέσμευση χωρίς αντίκρισμα.
 */
export function resolveTableCellStyleInk(
  style: TableCellStyle,
  surfaceHex: string,
): TableCellStyle {
  if (!isAutomaticTableInk(style.textColorHex)) return style;
  return {
    ...style,
    textColorHex: maxContrastInk(tableCellBackdrop(style.fillColorHex, surfaceHex)),
  };
}

/**
 * 🔴 **ΤΟ ΠΛΕΓΜΑ — και γιατί ΔΕΝ είναι το ίδιο πρόβλημα με το μελάνι** (ADR-739 §38.11).
 *
 * Το `STANDARD_GRID_HEX = '#666666'` μετρήθηκε **κάτω από το {@link MIN_ENTITY_CONTRAST}** σε
 * **5 από τις 10** επιφάνειες — χειρότερα στην **προεπιλογή** (`nestorApp1`, **2,58:1**) και στο
 * `cinema4d` (**1,18:1**). Ίδιο *σχήμα* ελαττώματος με το κείμενο· **αντίθετη λύση**.
 *
 * ## Γιατί ΟΧΙ το σεντινέλι {@link AUTOMATIC_TABLE_INK}
 * 1. **Σημασιολογικά λάθος.** Το σεντινέλι πάει στο **άκρο** (ACI 7: λευκό ή μαύρο). Ένα πλέγμα
 *    στο άκρο γίνεται **πιο δυνατό από το κείμενο που περιβάλλει** — αντιστροφή της
 *    τυπογραφικής ιεραρχίας (ISO 128: το πλέγμα είναι *υποτεταγμένο*, όχι περιεχόμενο). Το
 *    AutoCAD και το Revit **όντως** πηδούν στο άκρο· εδώ τους ξεπερνάμε επίτηδες.
 * 2. **Επικίνδυνο.** Το χρώμα ακμής **γράφεται στη βάση** (`isBorderSpec` δέχεται κάθε string,
 *    §38.3) και το `sameBorderSpec` θα ένωνε **μη αναστρέψιμα** δύο ακμές που το κρατούν.
 * 3. **Διπλότυπο.** Το «κάνε αυτό το χρώμα ορατό στο φόντο» **έχει ήδη SSoT** (ADR-509), που
 *    κάνει **ελάχιστη** ανάμειξη κρατώντας την απόχρωση. Δεύτερη υλοποίηση = sibling clone.
 *
 * Άρα: **καμία** αλλαγή στο μοντέλο, **καμία** εγγραφή στον δίσκο, **κανένα** σεντινέλι σε ακμή.
 * Ό,τι έγραψε ο χρήστης μένει αυτούσιο στο αρχείο· προσαρμόζεται **μόνο η ζωγραφική**, όπως ήδη
 * κάθε άλλη οντότητα DXF (`dxf-renderer-style-resolve.ts`) — ο πίνακας ήταν η εξαίρεση.
 *
 * ## Ελάχιστη, όχι μέγιστη — μετρημένα
 * ```
 *   #666666 σε #1d283a (προεπιλογή) → ≈#707070   — μόλις που αλλάζει, μένει υποτεταγμένο
 *   #666666 σε #5b5b5b (cinema4d)   → ≈#adadad   — ανοιχτό γκρι, ΟΧΙ λευκό
 * ```
 * Το κατώφλι είναι το **ίδιο** {@link MIN_ENTITY_CONTRAST} που το έργο επιβάλλει σε κάθε άλλη
 * γραμμή — όχι τρίτο νούμερο δίπλα στα δύο υπάρχοντα.
 *
 * ⚠️ **Ίδια αναφορά όταν δεν χρειάζεται αλλαγή.** Δεν είναι μικροβελτιστοποίηση: το `coalesce`
 * (`table-layout-borders.ts`) ενώνει με `sameBorderSpec`, που έχει fast-path `a === b`, και ένας
 * 8×500 πίνακας ρωτά ~8.500 ακμές **ανά αλλαγή μοντέλου** — δηλαδή ανά πληκτρολόγηση.
 *
 * ⚠️ Η επιφάνεια είναι η **γη του πίνακα**, όχι το γέμισμα του διπλανού κελιού: μια ακμή έχει
 * **δύο** κελιά από τις δύο πλευρές της, άρα «ποιο γέμισμα;» δεν έχει μία απάντηση. Το Word και
 * το Excel δεν προσαρμόζουν καθόλου το περίγραμμα στο γέμισμα — ούτε εμείς.
 *
 * ## 🔴🔴 ΤΟ ΧΑΡΤΙ ΔΕΝ ΑΓΓΙΖΕΤΑΙ ΠΟΤΕ — και το βρήκαν τα tests, όχι η σκέψη
 *
 * Η πρώτη γραφή προσάρμοζε **και** στο χαρτί. Κοκκίνισαν **4 tests** και είχαν δίκιο: το
 * `DETAIL_SHEET_RULE_HEX = '#999999'` του **πίνακα οπλισμών** μετρά **2,85:1** σε λευκή σελίδα,
 * οπότε «διορθωνόταν» σε `#949494` — δηλαδή **αλλάζαμε σιωπηλά τυπωμένο έγγραφο** που ο
 * συντάκτης του στυλ σχεδίασε επίτηδες ως λεπτή γραμμή. (Και μάλιστα στον έναν πίνακα που το
 * §38.8 είχε **ρητή εντολή** να μείνει ανέγγιχτος.)
 *
 * Δεν είναι συμβιβασμός· είναι το **δηλωμένο πεδίο εφαρμογής** του ίδιου του SSoT. Η ADR-509
 * γράφει στην κεφαλίδα της: *«**Render-time, 2D-canvas-specific** (ΟΧΙ μέσα στον κοινό
 * `resolveSubcategoryStyle`, που τον μοιράζονται 3D edges + print με **ΑΛΛΟ background**)»*.
 * Η προσαρμογή υπάρχει επειδή ο **καμβάς** έχει 10 αυθαίρετα θέματα· το **χαρτί είναι ένα και
 * γνωστό**, και ο συντάκτης του στυλ σχεδίασε ήδη γι' αυτό.
 *
 * ## Ο κανόνας σε μία γραμμή
 * | τι είπε ο συντάκτης | οθόνη | χαρτί |
 * |---|---|---|
 * | **σεντινέλι** {@link AUTOMATIC_TABLE_INK} («υπολόγισέ το») | υπολογίζεται | **υπολογίζεται** |
 * | **ρητό χρώμα** («ακριβώς αυτό») | προσαρμόζεται για να **διαβάζεται** | **αυτούσιο** |
 *
 * Δηλαδή: το **σεντινέλι** είναι εντολή και εκτελείται παντού· ένα **ρητό** χρώμα είναι απόφαση
 * και το έγγραφο τη σέβεται. Ίδιο σχήμα με AutoCAD (το ACI 7 λύνεται και στο plot· ένα ρητό RGB
 * τυπώνεται όπως δόθηκε) και με ArchiCAD (χωριστό pen set για την έξοδο).
 */
export function resolveTableBorderInk(
  spec: TableBorderSpec,
  surfaceHex: string,
): TableBorderSpec {
  if (!spec.visible) return spec;
  if (surfaceHex === TABLE_PAPER_HEX) return spec;
  const adapted = adaptColorForSurface(spec.colorHex, surfaceHex, MIN_ENTITY_CONTRAST);
  return adapted === spec.colorHex ? spec : { ...spec, colorHex: adapted };
}

/**
 * **Η επιφάνεια κάτω από τον πίνακα, τώρα** — φόντο καμβά, ή {@link TABLE_PAPER_HEX} όταν τρέχει
 * εκτύπωση.
 *
 * 🔴 Ο έλεγχος της πολιτικής εκτύπωσης **δεν είναι προαιρετικός**. Η raster εκτύπωση δεν έχει
 * δικό της ζωγράφο: ξαναχρησιμοποιεί το παραγωγικό pipeline (`capture-2d.ts` → `TableRenderer`)
 * πάνω σε **offscreen** καμβά που μένει επίτηδες **διάφανος** ⇒ η σελίδα βγαίνει λευκή, ενώ το
 * `getComputedStyle` του `:root` εξακολουθεί να λέει «σκούρο». Χωρίς αυτόν τον έλεγχο, ο χρήστης
 * θα τύπωνε **λευκά γράμματα σε λευκό χαρτί** — και θα το ανακάλυπτε στον πελάτη.
 *
 * ⚠️ **ΜΙΑ ανάγνωση ανά κλήση διάταξης, ποτέ ανά κελί.** Το
 * {@link resolveDxfCanvasBackgroundHex} είναι `getComputedStyle` (style recalc)· ανά κελί θα ήταν
 * ακριβώς το σχήμα O(zoom²) που ο ADR-735 πλήρωσε σε παραγωγή. Γι' αυτό η τιμή μπαίνει ως
 * **όρισμα** στη διάταξη και δεν διαβάζεται από μέσα της.
 */
export function liveTableSurfaceHex(): string {
  return liveTableSurface().hex;
}

/**
 * 🔴 ADR-771 Φ.2 — **Η ΕΠΙΦΑΝΕΙΑ ΩΣ ΕΝΑ ΠΡΑΓΜΑ**: τι χρώμα, και ποιος τη ζωγραφίζει.
 *
 * ⚠️ Το `paint` **δεν** σημαίνει «η επιφάνεια είναι αδιαφανής». Σημαίνει «**πρέπει ΕΓΩ να τη
 * ζωγραφίσω;**» — και η διαφορά είναι ολόκληρη η ορθότητα της πραγματικής εκτύπωσης (δες
 * {@link liveTableSurface}). Τα δύο πεδία **παράγονται μαζί, από μία απόφαση**, γι' αυτό δεν
 * μπορούν να αποκλίνουν· δύο ξεχωριστές ερωτήσεις θα ήταν δύο ευκαιρίες να απαντήσουν αλλιώς.
 */
export interface TableSurface {
  /** Το χρώμα κάτω από τον πίνακα — **είσοδος υπολογισμού** μελανιού, όπως πάντα. */
  readonly hex: string;
  /** `true` ⇒ ο ζωγράφος του πίνακα οφείλει να στρώσει ο ίδιος αυτή την επιφάνεια. */
  readonly paint: boolean;
}

/**
 * 🔴 ADR-771 Φ.2 — **η επιφάνεια κάθε ΠΑΡΑΔΟΤΕΟΥ**: λευκή σελίδα που **δεν τη ζωγραφίζουμε εμείς**.
 *
 * Η προεπιλογή του `computeTableEntityGeometry`, δηλαδή ό,τι βλέπουν η εξαγωγή
 * (`table-to-primitives`), το 3Δ υπόστρωμα και κάθε test. Ρητή σταθερά αντί για
 * `{ hex: TABLE_PAPER_HEX, paint: false }` γραμμένο σε τρία σημεία: το `paint: false` εδώ
 * είναι **απόφαση με λόγο** ({@link liveTableSurface}), όχι τιμή που «έτυχε».
 */
export const DELIVERABLE_PAPER_SURFACE: TableSurface = { hex: TABLE_PAPER_HEX, paint: false };

/**
 * 🔴 **«Ο ΠΙΝΑΚΑΣ ΠΑΡΟΥΣΙΑΖΕΤΑΙ ΩΣ ΠΑΡΑΔΟΤΕΟ;»** — μία ερώτηση, δύο αφορμές.
 *
 * Καλύπτει **και** την πραγματική εκτύπωση (`getPrintColorPolicy()`) **και** την επιλογή
 * «Χαρτί» του χρήστη. Κάθε βοήθημα οθόνης που δεν επιτρέπεται στο παραδοτέο ρωτά **αυτό**.
 *
 * ⚠️ **Δεν είναι δεύτερη σημαία** — είναι **υπερσύνολο**. Το
 * `table-bound-state-paper-isolation.test.ts` απαγορεύει ρητά δεύτερη απάντηση στο «είμαι
 * πάνω σε χαρτί;», και ο λόγος στέκει: δύο σημαίες θα σήμαιναν σημείο όπου το μελάνι και ο
 * δείκτης διαφωνούν. Εδώ η παλιά ερώτηση **περιέχεται** στη νέα, οπότε διαφωνία είναι δομικά
 * αδύνατη — και ο ζωγράφος των σημαδιών ζωντάνιας το ρωτά **αντί** για το `getPrintColorPolicy()`.
 * Χωρίς αυτό, η προεπισκόπηση «Χαρτί» θα έδειχνε δείκτες που **δεν τυπώνονται**, δηλαδή θα
 * έλεγε ψέματα ακριβώς εκεί που υπόσχεται ακρίβεια.
 *
 * ⚠️ Οι **άλλοι** καταναλωτές του `getPrintColorPolicy()` (`bim-line-weight-resolver`,
 * `dxf-renderer-style-resolve`, `lineweight-display-px`) ρωτούν **άλλο πράγμα** — «τρέχει
 * εκτύπωση, ώστε να εφαρμόσω plot styles και DPI;» — και μένουν **αμετάβλητοι**: η
 * προεπισκόπηση ενός πίνακα δεν αλλάζει τα πάχη γραμμών ολόκληρου του σχεδίου.
 */
export function tableSurfaceShowsPaper(): boolean {
  return getPrintColorPolicy() !== null || getTableSurfaceMode() === 'paper';
}

/**
 * 🔴 **Ο ΕΝΑΣ ΚΟΜΒΟΣ** όπου αποφασίζεται πάνω σε τι κάθεται ο πίνακας (ADR-771 §4).
 *
 * ## Γιατί η πραγματική εκτύπωση έχει `paint: false` — και γιατί ΔΕΝ είναι λεπτομέρεια
 * Στην raster εκτύπωση τη λευκή σελίδα **την παρέχει το μέσο**: ο offscreen καμβάς μένει
 * διάφανος και το PDF/χαρτί από κάτω είναι ήδη λευκό. Αν ζωγραφίζαμε κι εμείς φύλλο εκεί, ένα
 * αδιαφανές λευκό ορθογώνιο θα **έκρυβε τις γραμμές του σχεδίου κάτω από τον πίνακα** —
 * δηλαδή θα αλλάζαμε το **παραδοτέο**, ακριβώς αυτό που το ADR-771 §2.3 απαγορεύει.
 * Η προεπισκόπηση «Χαρτί» αντίθετα **οφείλει** να ζωγραφίσει: εκεί δεν υπάρχει χαρτί από
 * κάτω, υπάρχει σκοτεινός καμβάς, και η δουλειά της είναι να τον **προσομοιώσει**.
 *
 * Γι' αυτό η ίδια τιμή `hex` έρχεται με **διαφορετικό** `paint` στις δύο περιπτώσεις — και
 * γι' αυτό το `paint` δεν είναι παράγωγο του χρώματος, ούτε μπορεί να γίνει.
 *
 * ⚠️ **Σειρά προτεραιότητας**: η πραγματική εκτύπωση νικά **πάντα** την προτίμηση θέασης.
 * Αλλιώς ο χρήστης με «Καμβά» θα τύπωνε **λευκά γράμματα σε λευκό χαρτί** — ο λόγος που ο
 * έλεγχος πολιτικής εκτύπωσης δεν ήταν ποτέ προαιρετικός (δες {@link liveTableSurfaceHex}).
 */
export function liveTableSurface(): TableSurface {
  if (getPrintColorPolicy() !== null) return { hex: TABLE_PAPER_HEX, paint: false };
  switch (getTableSurfaceMode()) {
    case 'paper':
      return { hex: TABLE_PAPER_HEX, paint: true };
    case 'sheet':
      return { hex: TABLE_SHEET_HEX, paint: true };
    case 'canvas':
      return { hex: resolveDxfCanvasBackgroundHex(), paint: false };
  }
}

/**
 * 🔴 ADR-739 §41 — **Η ΣΚΙΑΣΗ ΤΗΣ ΕΠΙΛΕΓΜΕΝΗΣ ΠΕΡΙΟΧΗΣ** (Excel parity).
 *
 * Ουδέτερο ημιδιαφανές στρώμα — λευκό ή μαύρο κατά την επιφάνεια — με το ποσοστό
 * {@link TABLE_CELL_SELECTION.washAlpha} που μετρήθηκε από στιγμιότυπο του Excel.
 *
 * ## 🔴 Γιατί ΟΥΔΕΤΕΡΟ και όχι το `INDICATOR_BLUE` που ήταν μέχρι τις 04/08
 * Δεν είναι αισθητική επιλογή· είναι **λειτουργική**, και είναι ο λόγος που το Excel το κάνει
 * κι εκείνο (μετρημένο: `#C6C6C6` σε λευκό ⇒ `R = G = B` **ακριβώς**, δηλαδή μηδενική απόχρωση).
 *
 * Τα κελιά έχουν **δικό τους γέμισμα** (`TableCellStyle.fillColorHex`). Ένα *χρωματιστό*
 * στρώμα δεν σκιάζει το γέμισμα — το **βάφει άλλο χρώμα**: μπλε 22% πάνω σε κίτρινο κελί
 * δίνει πράσινο, και ο χρήστης χάνει την πληροφορία που ο ίδιος έβαλε στο κελί, ακριβώς τη
 * στιγμή που το μαρκάρει για να το επεξεργαστεί. Ουδέτερο στρώμα **μόνο σκουραίνει ή
 * φωτίζει**: κάθε γέμισμα παραμένει αναγνωρίσιμο ως ο εαυτός του.
 *
 * Είναι το **ίδιο** ελάττωμα που το §19.8 έχει ήδη πληρώσει μία φορά με το `phaseColor`
 * («όποιο κελί έχει γέμισμα, χάνει το κείμενο») — σε γέμισμα αντί σε μελάνι.
 *
 * ## Γιατί συνάρτηση και όχι σταθερά στο `color-config.ts`
 * Δύο λόγοι, και ο δεύτερος είναι δομικός:
 *  1. **Δεν υπάρχει μία απάντηση.** Μαύρο 22% σε χαρτί δίνει το `#C6C6C6` του Excel· το ίδιο
 *     μαύρο στο προεπιλεγμένο `#1d283a` του καμβά δίνει `#161f2d` — μια σκίαση **αόρατη**
 *     πάνω σε ήδη σκούρο φόντο, δηλαδή επιλογή που δεν φαίνεται. Η κατεύθυνση της σκίασης
 *     είναι **ερώτημα προς την επιφάνεια**, και το έργο έχει ήδη τον έναν κανόνα που το
 *     απαντά ({@link maxContrastInk}, ACI 7).
 *  2. **Κυκλική εξάρτηση.** Το `adaptive-entity-color.ts` εισάγει από το `color-config.ts`
 *     (`resolveDxfCanvasBackgroundHex`), οπότε το `color-config.ts` **δεν μπορεί** να καλέσει
 *     το `maxContrastInk`. Ο διαχωρισμός δεν είναι παράκαμψη — είναι ο ίδιος που ισχύει ήδη
 *     για τον δείκτη λειτουργίας: **το χρώμα** στο `color-config`, **ο υπολογισμός** δίπλα
 *     στα δεδομένα του (εκεί `tableModeOutlineRectMm`, εδώ η επιφάνεια).
 *
 * @param surfaceHex η επιφάνεια κάτω από τον πίνακα — `TableEntityGeometry.surfaceHex`, ποτέ
 *   δεύτερη ανάγνωση του {@link liveTableSurfaceHex}.
 */
export function tableSelectionWashRgba(surfaceHex: string): string {
  return hexToRgba(maxContrastInk(surfaceHex), TABLE_CELL_SELECTION.washAlpha);
}
