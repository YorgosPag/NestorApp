/**
 * ADR-739 §38 — **το αυτόματο μελάνι του κελιού**: μία δεσμευμένη τιμή, τρία σύνορα εξόδου.
 *
 * ## Το πρόβλημα, μετρημένο
 * Το προεπιλεγμένο μελάνι ήταν `#111111`. Ο καμβάς όμως **δεν είναι λευκός** — και δεν είναι
 * καν ένα χρώμα: το `--canvas-background-dxf` έχει **9 θέματα + `custom`** (`config/canvas-theme.ts`).
 * Στο προεπιλεγμένο `nestorApp1 (#1d283a)` η αντίθεση ήταν **1,27:1**, δηλαδή κάτω και από το
 * `MIN_ENTITY_CONTRAST = 3.0` που το ίδιο το έργο επιβάλλει σε **κάθε άλλη** οντότητα.
 *
 * Ένα ωμό `#ffffff` όμως θα διόρθωνε **έξι** θέματα και θα έσπαγε **τρία**: το θέμα `light`
 * (1,00:1), το `cinema4d` (3,64:1 — κάτω από το AA κειμένου) και **κάθε εξαγωγή σε χαρτί**
 * (1,00:1). Το πρόβλημα δεν είναι «οθόνη vs χαρτί» — είναι «**επιφάνεια vs επιφάνεια**».
 *
 * ## Η απάντηση των μεγάλων — και ποιον ακολουθούμε
 * - **AutoCAD ACI 7** («white/black»): ζωγραφίζεται **λευκό σε σκούρο φόντο, μαύρο σε λευκό**,
 *   αυτόματα. Δεν είναι RGB· είναι **δεσμευμένος δείκτης**. Αυτή τη σημασιολογία υιοθετούμε.
 * - **Word/Excel «Automatic»**: ίδιος κανόνας, τίμιο όνομα.
 * - **ArchiCAD Pen Sets**: σωστός διαχωρισμός ανά έξοδο, αλλά **χειροκίνητος** (αλλάζεις σετ).
 * - **Figma**: semantic tokens **επιλυμένα στον χρόνο σχεδίασης** — και το τεκμηριωμένο #1
 *   ελάττωμά τους («fills bound to *Primitive* variables → invisible in light mode») είναι
 *   **ακριβώς** το ωμό `#ffffff`.
 *
 * ## 🔴 Γιατί ΔΕΣΜΕΥΜΕΝΗ ΤΙΜΗ και όχι δεύτερο πεδίο
 * Το `types/table.ts` το έχει ήδη ψηφίσει για το γέμισμα: «*το AutoCAD λύνει το ίδιο πρόβλημα
 * με δεσμευμένες τιμές μέσα στο ίδιο πεδίο (62 → 256 = BYLAYER)… ένα πεδίο, τρεις απαντήσεις —
 * ποτέ δεύτερο παράλληλο boolean*». Το {@link AUTOMATIC_TABLE_INK} δεν είναι έγκυρο `#rrggbb`,
 * άρα δεν τρώει καμία τιμή από το πεδίο, και επιβιώνει στο `JSON.stringify`.
 *
 * ## 🔴🔴 ΠΟΥ ΕΠΙΛΥΕΤΑΙ — και γιατί ΟΧΙ στους ζωγράφους
 * Η επίλυση γίνεται **στη διάταξη** (`table-layout-place.ts`), ώστε το `TableTextRun.colorHex`
 * να είναι **εγγυημένα πραγματικό hex**. Δεν είναι προτίμηση· είναι ο μόνος τρόπος να μην
 * υπάρχουν τα παρακάτω, που **κανένα δεν πετάει σφάλμα**:
 *
 * | αν το σεντινέλι διέρρεε σε… | τι θα γινόταν |
 * |---|---|
 * | `ctx.fillStyle` | ο Canvas **αγνοεί** άκυρο χρώμα ⇒ κρατά το **προηγούμενο** μελάνι |
 * | CSS `color` | είναι **κληρονομούμενη** ιδιότητα ⇒ παίρνει το χρώμα του γονέα· `caret-color: auto` είναι μάλιστα **έγκυρο** |
 * | `hexToTrueColor` | `0` = μαύρο — και `0 != null`, άρα ο DXF writer το δέχεται ως έγκυρο |
 * | `applyPlotColor` | `#000000` σε κάθε ρόλο και κάθε plot style |
 * | `isBorderSpec` | δέχεται **κάθε** string ⇒ το σεντινέλι **γράφεται στη βάση** και επιβιώνει σε reload |
 *
 * Τρεις έξοδοι, τρεις διαφορετικές σιωπηλές συμπεριφορές, **μηδέν εξαιρέσεις**. Ένας φρουρός
 * ανά σημείο θα ήταν πέντε ευκαιρίες να ξεχαστεί ο έκτος· ο εγκλωβισμός στη διάταξη τις κάνει
 * **μη εκφράσιμες**.
 *
 * @module subapps/dxf-viewer/bim/table/table-ink
 * @see ../../config/adaptive-entity-color.ts — `maxContrastInk`: ο κανόνας ACI 7
 * @see ../../config/print-color-policy.ts — `PlotColorRole`: γιατί το γέμισμα ΔΕΝ αντιστρέφεται
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §38
 */

import { maxContrastInk } from '../../config/adaptive-entity-color';
import { resolveDxfCanvasBackgroundHex } from '../../config/color-config';
import { getPrintColorPolicy } from '../../config/print-color-policy';
import type { TableCellStyle } from './table-style';

/**
 * Η δεσμευμένη τιμή του `textColorHex` που σημαίνει «**υπολόγισέ με από το φόντο**».
 *
 * Σκόπιμα **όχι** `#rrggbb`: το `parseHex` το απορρίπτει, άρα κάθε καταναλωτής που το δει
 * ανεπίλυτο βρίσκεται σε λάθος — δεν υπάρχει «σχεδόν σωστή» ερμηνεία του.
 */
export const AUTOMATIC_TABLE_INK = 'auto';

/**
 * **Το χαρτί.** Κάθε εξαγωγή (PDF / DXF / ΤΕΚ) και κάθε raster εκτύπωση καταλήγει σε λευκή
 * σελίδα — ο offscreen καμβάς της εκτύπωσης μένει **διάφανος** επίτηδες, δηλαδή το σκούρο του
 * viewer **δεν** αναπαράγεται. Ρητή σταθερά ώστε η λέξη «χαρτί» να μη γραφτεί ως literal σε
 * τρία σημεία που μπορούν να αποκλίνουν.
 */
export const TABLE_PAPER_HEX = '#ffffff';

/** `true` όταν το χρώμα είναι το σεντινέλι — ποτέ σύγκριση με literal αλλού. */
export function isAutomaticTableInk(colorHex: string): boolean {
  return colorHex === AUTOMATIC_TABLE_INK;
}

/**
 * **Τι υπάρχει πίσω από το κείμενο του κελιού** — ο ΕΝΑΣ κανόνας, για τα τρία σύνορα.
 *
 * Το γέμισμα του κελιού νικά την επιφάνεια: ένα λευκό μελάνι πάνω σε ανοιχτό γέμισμα κεφαλίδας
 * είναι **το ίδιο ελάττωμα σε μικρογραφία** — και το έργο το έχει ήδη πληρώσει μία φορά
 * (ADR-739 §19.8: «όποιο κελί έχει γέμισμα, χάνει το κείμενο»).
 *
 * 🔴 **ΔΕΝ είναι νέα λογική.** Ο κανόνας ήταν ήδη γραμμένος, αυτούσιος, στο
 * `table-cell-editor-frame.ts` (`style.fillColorHex ?? backgroundHex`) και κλειδωμένος με 3
 * tests. Εξάγεται εδώ ώστε ο τρίτος και ο τέταρτος καταναλωτής να **μην** τον ξαναγράψουν —
 * αυτό ακριβώς που το CHECK 3.28 (jscpd) πιάνει ως sibling clone, ανεξάρτητα ονόματος.
 *
 * ⚠️ Το χρώμα **φάσης** (hover) δεν μπαίνει εδώ επίτηδες: ο ζωγράφος έχει ήδη αποφασίσει,
 * μετρημένα, ότι το κείμενο **δεν** παίρνει `phaseColor` ώστε «η αντίθεση που σχεδίασε ο
 * συγγραφέας του στυλ να επιβιώνει σε κάθε φάση» (`stamp-table-text.ts`). Το αυτόματο μελάνι
 * υπακούει στον ίδιο κανόνα — αλλιώς το κείμενο θα άλλαζε χρώμα στο πέρασμα του ποντικιού.
 *
 * @param fillColorHex το γέμισμα του κελιού· `null` = ρητά κανένα, `undefined` = δεν δηλώθηκε.
 * @param surfaceHex   η επιφάνεια από κάτω: φόντο καμβά (οθόνη) ή {@link TABLE_PAPER_HEX}.
 */
export function tableCellBackdrop(
  fillColorHex: string | null | undefined,
  surfaceHex: string,
): string {
  return fillColorHex ?? surfaceHex;
}

/**
 * Επιλύει το μελάνι ενός κελιού: το σεντινέλι γίνεται λευκό ή μαύρο κατά το `backdropHex`·
 * κάθε ρητό χρώμα επιστρέφεται **αυτούσιο**.
 *
 * Το `backdropHex` είναι **όρισμα**, ποτέ διαβασμένο μέσα: σε jsdom το
 * `resolveDxfCanvasBackgroundHex()` επιστρέφει πάντα το σκούρο default, οπότε μια συνάρτηση που
 * το ρωτούσε μόνη της θα δοκιμαζόταν **μόνο** στην κατεύθυνση «σκούρο → λευκό» και θα έμενε
 * πράσινη με σπασμένη την «λευκό → μαύρο».
 */
export function resolveTableInk(colorHex: string, backdropHex: string): string {
  return isAutomaticTableInk(colorHex) ? maxContrastInk(backdropHex) : colorHex;
}

/**
 * 🔴 **Ο ΕΝΑΣ κόμβος όπου το σεντινέλι παύει να υπάρχει.**
 *
 * Καλείται από το `placeCells` πάνω στο **επιλυμένο** στυλ κάθε κελιού, δηλαδή αφού έχουν ήδη
 * πέσει οι παρακάμψεις κελιού/γραμμής/στήλης. Από εκεί και πέρα **ούτε** το
 * `TableCellLayout.style.textColorHex` **ούτε** το `TableTextRun.colorHex` μπορούν να κρατούν
 * το {@link AUTOMATIC_TABLE_INK}.
 *
 * ## Γιατί στο ΣΤΥΛ και όχι μόνο στο run
 * Το `TableTextRun` γεννιέται μόνο για **γεμάτα** κελιά. Ο in-cell επεξεργαστής όμως ανοίγει και
 * σε **κενό** κελί, και διαβάζει το χρώμα του από το `TableCellLayout.style` — δηλαδή από άλλο
 * πεδίο. Επίλυση μόνο στο run θα άφηνε το σεντινέλι να φτάσει ως το CSS `color` του `<textarea>`,
 * όπου είναι **κληρονομούμενη** ιδιότητα και άρα δεν σπάει: το κείμενο θα έπαιρνε απλώς το χρώμα
 * του γονέα, χωρίς κανένα σφάλμα πουθενά. Ένα πεδίο, ένας κόμβος επίλυσης.
 *
 * Μη-σεντινέλι ⇒ επιστρέφεται **η ίδια αναφορά**: το `TableCellStyle` ταξιδεύει σε κάθε κελί
 * κάθε καρέ και ένα νέο αντικείμενο ανά κελί θα ήταν δέσμευση χωρίς αντίκρισμα.
 */
export function resolveTableCellStyleInk(
  style: TableCellStyle,
  surfaceHex: string,
): TableCellStyle {
  if (!isAutomaticTableInk(style.textColorHex)) return style;
  return {
    ...style,
    textColorHex: maxContrastInk(tableCellBackdrop(style.fillColorHex, surfaceHex)),
  };
}

/**
 * **Η επιφάνεια κάτω από τον πίνακα, τώρα** — φόντο καμβά, ή {@link TABLE_PAPER_HEX} όταν τρέχει
 * εκτύπωση.
 *
 * 🔴 Ο έλεγχος της πολιτικής εκτύπωσης **δεν είναι προαιρετικός**. Η raster εκτύπωση δεν έχει
 * δικό της ζωγράφο: ξαναχρησιμοποιεί το παραγωγικό pipeline (`capture-2d.ts` → `TableRenderer`)
 * πάνω σε **offscreen** καμβά που μένει επίτηδες **διάφανος** ⇒ η σελίδα βγαίνει λευκή, ενώ το
 * `getComputedStyle` του `:root` εξακολουθεί να λέει «σκούρο». Χωρίς αυτόν τον έλεγχο, ο χρήστης
 * θα τύπωνε **λευκά γράμματα σε λευκό χαρτί** — και θα το ανακάλυπτε στον πελάτη.
 *
 * ⚠️ **ΜΙΑ ανάγνωση ανά κλήση διάταξης, ποτέ ανά κελί.** Το
 * {@link resolveDxfCanvasBackgroundHex} είναι `getComputedStyle` (style recalc)· ανά κελί θα ήταν
 * ακριβώς το σχήμα O(zoom²) που ο ADR-735 πλήρωσε σε παραγωγή. Γι' αυτό η τιμή μπαίνει ως
 * **όρισμα** στη διάταξη και δεν διαβάζεται από μέσα της.
 */
export function liveTableSurfaceHex(): string {
  return getPrintColorPolicy() ? TABLE_PAPER_HEX : resolveDxfCanvasBackgroundHex();
}
