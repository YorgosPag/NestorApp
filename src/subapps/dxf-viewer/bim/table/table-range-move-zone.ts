/**
 * 🔴 ADR-739 §36 — **ΠΟΥ ΤΕΛΕΙΩΝΕΙ ΤΟ «ΜΕΣΑ ΣΤΟ ΚΕΛΙ» ΚΑΙ ΑΡΧΙΖΕΙ ΤΟ «ΠΑΝΩ ΣΤΟ
 * ΠΕΡΙΓΡΑΜΜΑ»**. Καθαρή γεωμετρία — μηδέν DOM, μηδέν store, μηδέν React.
 *
 * Ο ιδιοκτήτης το έθεσε ως parity: «*στο Excel, μέσα σε κελί ο κέρσορας γίνεται σταυρός,
 * πάνω σε περίγραμμα γίνεται σημάδι μετακίνησης — και πιάνω το περίγραμμα και μεταφέρω*».
 * Οι δύο καταστάσεις είναι **μία** ερώτηση με δύο απαντήσεις, και η ερώτηση είναι εδώ.
 *
 * ## 🔴 ΔΕΝ ΚΑΝΟΥΜΕ PARITY ΜΕ ΤΗ ΖΩΝΗ ΤΟΥ EXCEL — ΓΙΑΤΙ ΕΚΕΙ ΤΟ EXCEL ΕΙΝΑΙ ΣΠΑΣΜΕΝΟ
 * Μετρημένο, όχι εικασία: η ζώνη σύλληψης του Excel 365 είναι **~1 px**, και υπάρχει
 * **κλειδωμένο νήμα στη Microsoft Q&A** («*The cell border in Excel 365 is exceedingly thin;
 * it is almost impossible to change the pointer to the move pointer*») όπου χρήστες
 * αναφέρουν **30+ προσπάθειες** για να μετακινήσουν **ένα** κελί, και ότι στο Office 2010
 * η ζώνη ήταν «**10 φορές πλατύτερη**». Το νήμα έκλεισε **χωρίς λύση**.
 *
 * Άρα η «πιστή αντιγραφή» εδώ θα αντέγραφε ένα **ελάττωμα**. Η ζώνη μας είναι η
 * `gripAperturePx()` — η **ΜΙΑ** οπή σύλληψης του έργου (§27.16 Ε4). Δεν είναι νέος
 * αριθμός: φτάνει εδώ ως `bands.gapMm`, δηλαδή **ακριβώς** η ίδια έκφραση που ήδη ορίζει
 * το κενό των ζωνών και τον δίσκο του διαχωριστικού. Όποιος μεγαλώσει την οπή, τη μεγαλώνει
 * **παντού** — δεν υπάρχει δεύτερος αριθμός να ξεχαστεί.
 *
 * ## 🔴 ΓΙΑΤΙ Η ΖΩΝΗ ΔΕΝ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΦΑΕΙ ΤΟ ΕΣΩΤΕΡΙΚΟ — ΚΑΙ ΕΙΝΑΙ ΜΕΤΡΗΣΙΜΟ
 * Η οπή είναι σταθερή σε **px οθόνης**· το ορθογώνιο της επιλογής είναι σε **sheet-mm** και
 * μικραίνει με το zoom-out. Σε ένα κελί ύψους ~20 px, μια ζώνη 9 px από πάνω **και** 9 px
 * από κάτω αφήνει **2 px** εσωτερικό — δηλαδή πρακτικά **μηδέν**: ο δείκτης θα έλεγε
 * «μετακίνηση» σχεδόν παντού και το `cell-select` θα γινόταν **απλησίαστο**.
 *
 * Γι' αυτό η εμβέλεια φράσσεται στο {@link MAX_BORDER_REACH_FRACTION} της μικρότερης πλευράς.
 * Δεν είναι καλλωπισμός: χωρίς αυτό, η ίδια χειρονομία που ο ιδιοκτήτης ζήτησε (**σταυρός**
 * μέσα στο κελί) θα εξαφανιζόταν σε κάθε zoom-out. Η ζώνη **υποβαθμίζεται ομαλά** αντί να λέει
 * ψέματα — η ίδια αρχή με το LOD του δείκτη (`MIN_TABLE_SCREEN_PX`).
 *
 * ## 🔴 ΤΟ ΦΡΑΓΜΑ ΙΣΧΥΕΙ ΚΑΙ ΠΡΟΣ ΤΑ **ΕΞΩ** — ΕΔΩ ΕΓΡΑΦΕ ΤΟ ΑΝΤΙΘΕΤΟ, ΚΑΙ ΗΤΑΝ ΛΑΘΟΣ
 * Έγραφε: «*Το φράγμα ισχύει μόνο προς τα μέσα. Προς τα έξω η ζώνη κρατά ολόκληρη την οπή:
 * εκεί δεν υπάρχει τίποτα να καταπιεί — τα γειτονικά κελιά διαλέγονται από το σώμα τους, που
 * είναι ολόκληρο*». Η τελευταία πρόταση **μετρήθηκε** (2026-08-06, ADR-739 §36.9) και είναι
 * ψευδής: με σταθερή οπή **9 px** προς τα έξω, το ορθογώνιο διεκδικεί από τη γειτονική γραμμή
 *
 * | κλίμακα | ύψος γειτονικής γραμμής | διεκδικείται |
 * |---|---|---|
 * | 5 px/mm | 40 px | 8 px (20%) |
 * | 3 px/mm | 24 px | 9 px (38%) |
 * | 2 px/mm | 16 px | 9 px (**56%**) |
 * | 1 px/mm | 8 px | 8 px (**100%**) |
 *
 * Δηλαδή σε zoom-out το γειτονικό κελί **δεν έχει σώμα**: ολόκληρο είναι «περίγραμμα του
 * διπλανού», και το κλικ πάνω του ξεκινά **μεταφορά** αντί να το επιλέξει (`use-table-cell-pointer`,
 * ο κλάδος `tableRangeGrabAtWorld` κάνει `return` πριν φτάσει στο `setTableCellCursor`).
 *
 * 🔑 Μέχρι το §36.9 αυτό ήταν ανεκτό επειδή απαιτούσε **εκούσια** επιλογή περιοχής. Από τη
 * στιγμή που το **ενεργό κελί** αποκτά κι αυτό ορθογώνιο (§36.9 — ήταν το μισό αίτημα του
 * ιδιοκτήτη), το ορθογώνιο υπάρχει **πάντα** όσο ο πίνακας είναι ανοιχτός: η άλως θα γινόταν
 * μόνιμη και τα γειτονικά κελιά **απλησίαστα με κλικ**. Η λύση δεν είναι να μη γίνει η
 * μετακίνηση — είναι να πάψει η ζώνη να διεκδικεί pixel που δεν της ανήκουν.
 *
 * Είναι **ακριβώς** ο κανόνας που το ADR-754 §13.8 έγραψε ήδη για τη λαβή συμπλήρωσης
 * («*το χειριστήριο μεγαλώνει μόνο προς το κενό, ποτέ πάνω σε ό,τι ανήκει σε άλλον*»),
 * εφαρμοσμένος μία στροφή πιο έξω: εκεί «άλλος» ήταν η ζώνη μετακίνησης, εδώ το **γειτονικό
 * κελί**. Με το φράγμα, η διεκδίκηση μένει **≤ 25% σε κάθε κλίμακα**.
 *
 * ⚠️ **Το κλάσμα εφαρμόζεται στη ΔΙΚΗ μας μικρότερη πλευρά**, όχι στου γείτονα — που θα
 * απαιτούσε γνώση διάταξης μέσα σε καθαρή γεωμετρία. Σε πλέγμα οι γείτονες έχουν συγκρίσιμο
 * μέγεθος (ίδιες στήλες, ίδιες γραμμές), άρα είναι καλή προσέγγιση **και συντηρητική**. Ρητό
 * όριο: για **μεγάλη** επιλογή που ακουμπά **κοντή** γραμμή, το κλάσμα βγαίνει μεγαλύτερο από
 * την οπή και η εμβέλεια μένει τα 9 px — δηλαδή η σημερινή συμπεριφορά, **αμετάβλητη**. Το
 * φράγμα δαγκώνει εκεί ακριβώς που γεννήθηκε το πρόβλημα: στα **μικρά** ορθογώνια.
 *
 * ## 🔴 Η ΖΩΝΗ ΖΕΙ ΑΥΣΤΗΡΑ **ΜΕΣΑ** ΣΤΟ ΠΛΕΓΜΑ — §27.11 ΕΦΑΡΜΟΣΜΕΝΟ
 * Ο καλών ρωτά αυτό εδώ **μόνο** για σημεία με `u, v ≥ 0`. Ο λόγος είναι δομικός και ήδη
 * γραμμένος: στα **αρνητικά** mm ζουν οι ζώνες του δείκτη, και στη λωρίδα του κενού ζουν οι
 * **λαβές** (§27.11 — «ένα pixel, μία ερώτηση»). Μια επιλογή που ακουμπά την πάνω γραμμή θα
 * έσπρωχνε αλλιώς την εξωτερική της εμβέλεια πάνω στη λαβή `n` και στη ζώνη των γραμμάτων —
 * δηλαδή θα γεννούσε **ακριβώς** τη σύγκρουση που το κενό ήρθε να σβήσει, από την πίσω πόρτα.
 *
 * @module subapps/dxf-viewer/bim/table/table-range-move-zone
 * @see bim/table/table-cell-range.ts — `tableRangeRectMm`: ΠΟΙΟ είναι το ορθογώνιο
 * @see bim/table/table-indicator-geometry.ts — ΠΟΙΟΣ ρόλος δείκτη οφείλεται πού
 * @see config/grip-aperture.ts — η ΜΙΑ οπή σύλληψης του έργου
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §36
 */

import type { TableFramePoint } from '../../types/table-entity';
import type { TableRectMm } from './table-layout-types';

/**
 * Πόσο **από τη μικρότερη πλευρά** επιτρέπεται να καταλάβει η ζώνη — **προς κάθε κατεύθυνση**.
 *
 * Το ¼ δεν είναι γούστο — είναι το μεγαλύτερο κλάσμα που αφήνει το εσωτερικό **συνεκτικό**:
 * με ζώνη ¼ σε κάθε πλευρά, μένει το μεσαίο **μισό** για το `cell-select`. Στο ⅓ θα έμενε
 * το ένα τρίτο· στο ½ δεν θα έμενε **τίποτα** (οι δύο ζώνες θα εφάπτονταν στο κέντρο) και
 * το εσωτερικό θα εξαφανιζόταν σιωπηλά.
 *
 * 🔑 Ο **ίδιος** αριθμός φράσσει και τις δύο κατευθύνσεις, και δεν είναι σύμπτωση: προς τα
 * μέσα προστατεύει το **δικό μας** σώμα, προς τα έξω το σώμα του **γείτονα** — που σε πλέγμα
 * είναι το ίδιο μέγεθος. Δύο αριθμοί θα ήταν δύο ευκαιρίες να αποκλίνουν χωρίς λόγο. Δες την
 * κεφαλίδα για τη μέτρηση που πρόσθεσε τη δεύτερη κατεύθυνση.
 */
export const MAX_BORDER_REACH_FRACTION = 0.25;

/**
 * 🔴 §36 — **ΤΙ ΖΗΤΑ Ο ΧΡΗΣΤΗΣ ΜΕ ΤΑ ΠΛΗΚΤΡΑ ΤΟΥ**, τη στιγμή της χειρονομίας.
 *
 * ## Γιατί ΔΥΟ ανεξάρτητα boolean και όχι απαρίθμηση τεσσάρων καταστάσεων
 * Ο πειρασμός είναι `'move' | 'copy' | 'insert' | 'copy-insert'`. Θα ήταν **λάθος μοντέλο**:
 * στο Excel τα δύο πλήκτρα είναι όντως ανεξάρτητα — `Ctrl` απαντά «*αντιγραφή ή μετακίνηση;*»
 * και `Shift` απαντά «*αντικατάσταση ή εισαγωγή;*», και ο συνδυασμός τους (`Ctrl+Shift`)
 * είναι υπαρκτή, τεκμηριωμένη πράξη. Μια απαρίθμηση θα ανάγκαζε κάθε καταναλωτή να
 * ξε-πλέξει τον σύνθετο όρο, και η πρώτη παράλειψη θα ήταν σιωπηλή.
 *
 * Δύο ερωτήσεις, δύο πεδία: ο τύπος **δεν μπορεί** να εκφράσει κατάσταση που δεν υπάρχει.
 */
export interface TableRangeDragIntent {
  /** `Ctrl` (ή `Cmd`) — η πηγή **μένει**. */
  readonly copy: boolean;
  /** `Shift` — τα υπάρχοντα **ολισθαίνουν** αντί να αντικατασταθούν. */
  readonly insert: boolean;
}

/** Καμία τροποποίηση: σκέτη μετακίνηση με αντικατάσταση. Σταθερό — μηδέν κατανομή ανά κίνηση. */
export const PLAIN_TABLE_RANGE_DRAG: TableRangeDragIntent = { copy: false, insert: false };

/**
 * Τα πλήκτρα του συμβάντος → πρόθεση.
 *
 * ⚠️ Το `metaKey` δεν είναι ευγένεια προς macOS: ο **ίδιος** κώδικας τρέχει σε Mac, όπου το
 * `Ctrl+σύρσιμο` είναι χειρονομία του **λειτουργικού** (δευτερεύον κλικ) και δεν φτάνει ποτέ.
 * Χωρίς το `metaKey`, η αντιγραφή θα ήταν **αδύνατη** εκεί — και το σύμπτωμα θα ήταν
 * «λείπει λειτουργία», όχι «σφάλμα».
 */
export interface TableRangeIntentModifiers {
  readonly ctrlKey: boolean;
  /**
   * ⚠️ **ΠΡΟΑΙΡΕΤΙΚΟ, ΚΑΙ ΕΙΝΑΙ ΤΟ ΝΟΗΜΑ.** Ο κριτής παρακάτω το διαβάζει ως
   * `metaKey === true`, άρα «δεν ξέρω» ≡ «όχι». Έτσι μια πηγή που **έχει ήδη ενώσει**
   * το `Control` με το `Meta` (ο `CtrlKeyTracker`, γιατί εδώ είναι ισοδύναμα) μπορεί να
   * απαντήσει **χωρίς να πει ψέματα** για το ποιο φυσικό πλήκτρο πατήθηκε.
   *
   * Ήταν `Pick<MouseEvent, …>` σε **δύο** αρχεία — δηλαδή ο τύπος απαιτούσε πεδίο που
   * ο ίδιος ο κριτής θεωρεί προαιρετικό, και κάθε μη-ποντικίσια πηγή έπρεπε να
   * επινοήσει τιμή γι' αυτό.
   */
  readonly metaKey?: boolean;
  readonly shiftKey: boolean;
}

export function tableRangeDragIntentOf(modifiers: TableRangeIntentModifiers): TableRangeDragIntent {
  const copy = modifiers.ctrlKey || modifiers.metaKey === true;
  if (!copy && !modifiers.shiftKey) return PLAIN_TABLE_RANGE_DRAG;
  return { copy, insert: modifiers.shiftKey };
}

/**
 * Πόσο μακριά από το περίγραμμα φτάνει η ζώνη — **εκατέρωθεν**, σε sheet-mm. Δες
 * {@link MAX_BORDER_REACH_FRACTION} για το γιατί δεν είναι απλώς η οπή.
 *
 * `0` για εκφυλισμένο ορθογώνιο ή μη θετική οπή: τότε **δεν υπάρχει** περίγραμμα να πιαστεί,
 * και το να επιστραφεί οτιδήποτε άλλο θα ήταν υπόσχεση χωρίς αντίκρισμα.
 *
 * ⚠️ Ονομαζόταν `tableRangeBorderInsideReachMm` όσο ίσχυε **μόνο** προς τα μέσα. Το «Inside»
 * έφυγε από το όνομα μαζί με την ασυμμετρία (§36.9) — ένα όνομα που περιγράφει κατεύθυνση
 * την οποία η συνάρτηση δεν ξεχωρίζει πια θα ήταν το επόμενο πράγμα που ψεύδεται.
 */
export function tableRangeBorderReachMm(rectMm: TableRectMm, apertureMm: number): number {
  const minSideMm = Math.min(rectMm.w, rectMm.h);
  if (!(minSideMm > 0) || !(apertureMm > 0)) return 0;
  return Math.min(apertureMm, minSideMm * MAX_BORDER_REACH_FRACTION);
}

/**
 * Προσημασμένη απόσταση από το **περίγραμμα** του ορθογωνίου, σε sheet-mm:
 * **αρνητική μέσα**, `0` πάνω στη γραμμή, **θετική έξω**.
 *
 * ## Γιατί γράφτηκε εδώ και δεν επαναχρησιμοποιήθηκε κάτι
 * Ο audit (grep σε ολόκληρο το subapp για `nearRect` / `pointOnRect` / `rectEdgeHit` /
 * `distanceToRect` / `onRectBorder`) βρήκε **μηδέν** υποψήφιο. Το `rect-grip-engine`
 * (ADR-363/436/654) απαντά σε **άλλη** ερώτηση — «*πού πάει η αντίθετη γωνία όταν σέρνω
 * αυτήν*» — και δεν κατέχει κατηγόρημα εγγύτητας. Άρα αυτό είναι γνήσια νέα γεωμετρία, όχι
 * παράλειψη έρευνας· καταγράφεται ώστε ο επόμενος να μην ξαναψάξει.
 *
 * Κλασικό SDF ορθογωνίου: `dx`/`dy` είναι η υπέρβαση ανά άξονα (αρνητική όσο είμαστε μέσα).
 * Έξω μετρά η **ευκλείδεια** απόσταση, ώστε οι γωνίες να μην έχουν τετράγωνη «αύρα» που θα
 * έπιανε αισθητά μακρύτερα από τις πλευρές.
 */
export function signedDistanceToRectOutlineMm(rectMm: TableRectMm, u: number, v: number): number {
  const dx = Math.max(rectMm.x - u, u - (rectMm.x + rectMm.w));
  const dy = Math.max(rectMm.y - v, v - (rectMm.y + rectMm.h));
  // Έξω έστω κατά έναν άξονα ⇒ η απόσταση είναι η ευκλείδεια από την πλησιέστερη πλευρά/γωνία.
  if (dx > 0 || dy > 0) return Math.hypot(Math.max(dx, 0), Math.max(dy, 0));
  // Και οι δύο μη θετικοί ⇒ μέσα· η πλησιέστερη πλευρά είναι αυτή με τη **μικρότερη** εσοχή.
  return Math.max(dx, dy);
}

/**
 * 🔴 §36 — **ΕΙΜΑΙ ΠΑΝΩ ΣΤΟ ΠΕΡΙΓΡΑΜΜΑ ΤΗΣ ΕΠΙΛΟΓΗΣ;** Η μία ερώτηση, ο ένας ορισμός.
 *
 * Η ζώνη **διαστέλλεται εκατέρωθεν** της γραμμής, όπως στο Excel και στα Sheets: το χέρι
 * πλησιάζει το περίγραμμα από **έξω** (έρχεται από το γειτονικό κελί) ή από **μέσα** (έρχεται
 * από το σώμα της επιλογής), και οι δύο προσεγγίσεις πρέπει να πιάνουν. Μια ζώνη μόνο-μέσα
 * θα ήταν αόρατη στη μισή φυσική κίνηση του χεριού.
 *
 * 🔑 Οι δύο εμβέλειες είναι **ίσες**, και το ότι είναι ίσες είναι απόφαση: το φραγμένο κλάσμα
 * ισχύει και προς τις δύο, γιατί και προς τις δύο υπάρχει σώμα κελιού να προστατευτεί — δικό
 * μας μέσα, του γείτονα έξω. Δες την κεφαλίδα για τη μέτρηση που κατάργησε την ασυμμετρία.
 */
export function isOnTableRangeBorder(
  rectMm: TableRectMm,
  frame: TableFramePoint,
  apertureMm: number,
): boolean {
  if (!(apertureMm > 0)) return false;
  const distanceMm = Math.abs(signedDistanceToRectOutlineMm(rectMm, frame.u, frame.v));
  return distanceMm <= tableRangeBorderReachMm(rectMm, apertureMm);
}
