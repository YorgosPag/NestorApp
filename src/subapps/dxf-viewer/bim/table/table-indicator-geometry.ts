/**
 * Η ελάχιστη **ορατή** απόσταση ανάμεσα σε δύο γραμμές, σε px οθόνης.
 *
 * Δύο γραμμές που εφάπτονται διαβάζονται ως **μία παχύτερη** — δηλαδή η μία εξαφανίζεται
 * χωρίς να καλυφθεί. Ένα pixel είναι η μικρότερη διαφορά που ο καμβάς μπορεί να εκφράσει,
 * άρα και το μικρότερο «όχι, είναι δύο».
 */
const MODE_OUTLINE_MIN_SEPARATION_PX = 1;

/**
 * 🔴 ADR-739 §37 — **ΠΟΣΟ ΕΞΩ ΑΠΟ ΤΟ ΠΛΕΓΜΑ ΚΑΘΕΤΑΙ ΤΟ ΠΕΡΙΓΡΑΜΜΑ ΛΕΙΤΟΥΡΓΙΑΣ**, σε px οθόνης.
 *
 * ## Το ελάττωμα που γέννησε αυτή τη συνάρτηση (μετρημένο, 2026-08-04)
 * Ο δείκτης ζωγραφιζόταν στο **ταυτόσημο** ορθογώνιο με το πλαίσιο του πίνακα
 * (`{0, 0, widthMm, heightMm}`), και οι δύο γραμμές κεντραρισμένες στην **ίδια διαδρομή**.
 * Όσο η περίμετρος ήταν χοντρή πένα (0,5 mm) η επικάλυψη ήταν μερική· μόλις ισοπεδώθηκε στα
 * **0,13 mm** (ADR-750, λεπτότερη πένα ISO 128) η αριθμητική αντιστράφηκε:
 *
 *     περίμετρος = max(0,13 × pxPerMm · 0,5)  →  **1,3 px** στα 10 px/mm
 *     δείκτης    = 2 px σταθερά               →  **καλύπτει ολόκληρη τη γραμμή**
 *
 * Το ισοζύγιο γύριζε μόνο πάνω από **15,4 px/mm** — μεγέθυνση όπου ένας πίνακας 120 mm
 * πιάνει 1.850 px. Δηλαδή, πρακτικά, **πάντα**.
 *
 * ## 🔴 ADR-756 — γιατί η συνάρτηση έπαψε να δέχεται `pxPerMm`
 * Η παραπάνω αριθμητική είχε **δεύτερο** θύμα, που δεν φαινόταν εδώ: το πάχος της περιμέτρου
 * μεγάλωνε με το zoom, άρα ο δείκτης απομακρυνόταν όλο και περισσότερο όσο πλησίαζες. Από τη
 * στιγμή που το πάχος έγινε **σταθερό σε px** (κοινός κανόνας με κάθε γραμμή του σχεδίου,
 * `lineweightDisplayPx`), η μετατόπιση δεν έχει **κανέναν** όρο που να εξαρτάται από την
 * κλίμακα: και οι δύο όροι της ήταν ήδη σε px διεπαφής. Η παράμετρος έμενε ως ψεύτικη
 * εξάρτηση — δηλαδή ως πρόσκληση σε κάποιον να ξαναγράψει έναν όρο επί `pxPerMm`.
 *
 * ## Γιατί μετατόπιση και όχι κάτι άλλο
 * Είναι η απάντηση που έχει ήδη τυποποιηθεί: το CSS έχει `outline` **χωριστά** από το
 * `border` ακριβώς επειδή ο δείκτης δεν επιτρέπεται να πατά πάνω στο αντικείμενο, και το
 * WCAG 2.2 SC 2.4.13 τη συνιστά ρητά («*offsetting indicators slightly from the focused
 * component… can help make indicators more visible*»). Η εναλλακτική των Illustrator /
 * AutoCAD (`XFADECTL`) / Revit — **ξεθώριασε ό,τι είναι έξω** — δίνει μηδέν μελάνι πάνω στο
 * αντικείμενο, αλλά είναι λειτουργία στην οποία μπαίνεις **επίτηδες**· εδώ θα σήμαινε
 * «ξεθώριασε ολόκληρη την κάτοψη επειδή πάτησα ένα κελί».
 *
 * ## Οι δύο όροι, και γιατί ο δεύτερος λύνει την ΚΛΑΣΗ
 *  1. **Θέση ανάπαυσης = η μέση του δακτυλίου.** Ο δακτύλιος
 *     ({@link TABLE_INDICATOR_GRIP_CLEARANCE_PX}) έχει ήδη δύο ενοίκους: τη γεωμετρία από
 *     μέσα, το γκρι περίγραμμα της ζώνης από έξω. Η μέση είναι η **μοναδική** θέση που
 *     μεγιστοποιεί την απόσταση και από τους δύο. Κανένας νέος αριθμός.
 *  2. **Δάπεδο = η εσωτερική ακμή του δείκτη απέχει ≥1 px από την εξωτερική ακμή του
 *     **παχύτερου** μολυβιού της περιμέτρου.** Χωρίς αυτόν τον όρο θα διορθώναμε το
 *     **δείγμα** (0,13 mm) και όχι την **κλάση**: το μολύβι ανά ακμή (ADR-750 Φ5) επιτρέπει
 *     να ξαναπαχύνει η περίμετρος αύριο, και ο δείκτης θα καταπινόταν σιωπηλά — το ίδιο
 *     ελάττωμα αντεστραμμένο.
 *
 * ## ⚠️ ΚΑΝΕΝΑ ΤΑΒΑΝΙ — επίτηδες
 * Ένα ταβάνι («μη βγεις ποτέ πέρα από τη ζώνη γραμμάτων») θα ξαναγεννούσε ακριβώς το bug σε
 * παχιά περίμετρο. Η αναλλοίωτη είναι **απόλυτη**: ο δείκτης δεν ακουμπά ποτέ τη γεωμετρία.
 * Αν η γεωμετρία φουσκώσει τόσο ώστε να καταπιεί τον δακτύλιο, ο δείκτης βγαίνει μαζί της —
 * και τότε είναι η **περίμετρος** που έχει μπει στη ζώνη, όχι ο δείκτης που ξέφυγε.
 *
 * @param perimeterPenMm το πάχος του **παχύτερου ορατού** μολυβιού στην περίμετρο, σε
 *   sheet-mm (`TableRenderIndex.perimeterMaxWidthMm`). `0` όταν η περίμετρος είναι αόρατη —
 *   τότε νικά ούτως ή άλλως η θέση ανάπαυσης.
 */
export function tableModeOutlineOffsetPx(perimeterPenMm: number): number {
  const restingPx = TABLE_INDICATOR_GRIP_CLEARANCE_PX / 2;
  const clearingPx =
    lineweightDisplayPx(perimeterPenMm) / 2 +
    TABLE_MODE_OUTLINE.lineWidthPx / 2 +
    MODE_OUTLINE_MIN_SEPARATION_PX;
  return Math.max(restingPx, clearingPx);
}

/**
 * Το ορθογώνιο του περιγράμματος λειτουργίας: το πλέγμα **φουσκωμένο προς τα έξω** κατά
 * {@link tableModeOutlineOffsetPx}, μεταφρασμένο σε sheet-mm.
 *
 * Η μετατόπιση γεννιέται σε **px οθόνης** και μετατρέπεται σε mm εδώ — όχι το αντίστροφο:
 * είναι απόσταση **διεπαφής** (πρέπει να φαίνεται ίδια σε κάθε zoom), όπως το πάχος του
 * δείκτη και όπως οι ζώνες. Σε sheet-mm θα κατέρρεε πάνω στο πλαίσιο σε σμίκρυνση, δηλαδή
 * θα επέστρεφε το ίδιο ελάττωμα ακριβώς εκεί όπου είναι πιο έντονο.
 *
 * Εκφυλισμένη προβολή (μη θετικό `pxPerMm`, offscreen pass) ⇒ επιστρέφει το ορθογώνιο
 * **αυτούσιο**: μια διαίρεση με το μηδέν θα έδινε άπειρες συντεταγμένες και ο καμβάς θα
 * σταματούσε να ζωγραφίζει ολόκληρη τη διαδρομή. Ίδια επιλογή «ασφαλής απάντηση, όχι NaN» με
 * το `frameScreenAngleRad`.
 */
export function tableModeOutlineRectMm(
  gridRectMm: TableRectMm,
  pxPerMm: number,
  perimeterPenMm: number,
): TableRectMm {
  if (!(pxPerMm > 0) || !Number.isFinite(pxPerMm)) return gridRectMm;
  const offsetMm = tableModeOutlineOffsetPx(perimeterPenMm) / pxPerMm;
  return {
    x: gridRectMm.x - offsetMm,
    y: gridRectMm.y - offsetMm,
    w: gridRectMm.w + 2 * offsetMm,
    h: gridRectMm.h + 2 * offsetMm,
  };
}

/** Το πάχος των δύο ζωνών σε **sheet-mm**, στην τρέχουσα κλίμακα οθόνης. */
export interface TableIndicatorBandsMm {
  /** Ύψος της πάνω ζώνης (γράμματα). */
  readonly columnBandMm: number;
  /** Πλάτος της αριστερής ζώνης (αριθμοί) — πλατύτερη: χωρά τετραψήφια. */
  readonly rowBandMm: number;
  /** Το κενό ως προς την ακμή του πλέγματος — δες {@link TABLE_INDICATOR_GRIP_CLEARANCE_PX}. */
  readonly gapMm: number;
}

/**
 * Η **εξωτερική** ακμή της πάνω ζώνης (πιο αρνητικό `v`). Μία έκφραση, τρεις καταναλωτές:
 * το ορθογώνιο στήλης, το ορθογώνιο γωνίας και το hit-test.
 */
function columnBandTopMm(bands: TableIndicatorBandsMm): number {
  return -(bands.gapMm + bands.columnBandMm);
}

/** Η **εξωτερική** ακμή της αριστερής ζώνης (πιο αρνητικό `u`) — συμμετρικά. */
function rowBandLeftMm(bands: TableIndicatorBandsMm): number {
  return -(bands.gapMm + bands.rowBandMm);
}

/**
 * Η **μία** μετατροπή px→mm του δείκτη. Τα μεγέθη ζουν σε px οθόνης επίτηδες
 * ({@link TABLE_INDICATOR}): είναι στοιχείο διεπαφής, όχι γεωμετρία σχεδίου — μια ζώνη σε mm
 * χαρτιού θα γινόταν αδιάβαστη σε zoom-out και τεράστια σε zoom-in.
 */
export function tableIndicatorBandsMm(pxPerMm: number): TableIndicatorBandsMm {
  return {
    columnBandMm: TABLE_INDICATOR.columnBandPx / pxPerMm,
    rowBandMm: TABLE_INDICATOR.rowBandPx / pxPerMm,
    gapMm: TABLE_INDICATOR_GRIP_CLEARANCE_PX / pxPerMm,
  };
}

/** Φαίνεται ο δείκτης σε αυτό το μέγεθος; Η **μία** έκφραση του LOD — δες την κεφαλίδα. */
export function isTableIndicatorVisible(
  widthMm: number,
  heightMm: number,
  pxPerMm: number,
): boolean {
  return widthMm * pxPerMm >= MIN_TABLE_SCREEN_PX && heightMm * pxPerMm >= MIN_TABLE_SCREEN_PX;
}

/** Το ορθογώνιο μιας υποδιαίρεσης της **πάνω** ζώνης (γράμμα στήλης). */
export function tableColumnTickRectMm(
  tick: TableIndicatorTick,
  bands: TableIndicatorBandsMm,
): TableRectMm {
  return { x: tick.startMm, y: columnBandTopMm(bands), w: tick.sizeMm, h: bands.columnBandMm };
}

/** Το ορθογώνιο μιας υποδιαίρεσης της **αριστερής** ζώνης (αριθμός γραμμής). */
export function tableRowTickRectMm(
  tick: TableIndicatorTick,
  bands: TableIndicatorBandsMm,
): TableRectMm {
  return { x: rowBandLeftMm(bands), y: tick.startMm, w: bands.rowBandMm, h: tick.sizeMm };
}

/**
 * Το τετράγωνο πάνω-αριστερά που **ενώνει** τις δύο ζώνες.
 *
 * Χωρίς αυτό φαίνεται μια τρύπα ακριβώς εκεί που το μάτι περιμένει τη γωνία του πλέγματος.
 *
 * ## 🔴 2026-08-04 (ADR-739 §43) — ΕΔΩ ΕΓΡΑΦΕ ΟΤΙ Η ΓΩΝΙΑ ΕΙΝΑΙ ΚΕΝΗ. ΔΕΝ ΕΙΝΑΙ ΠΙΑ
 * Το κείμενο ήταν: «*Το Excel βάζει εκεί το γκρίζο τρίγωνο "επιλογή όλων"· εδώ μένει **κενό**
 * και το hit-test επιστρέφει ρητά `null` γι' αυτό — **δεν υπάρχει τέτοια εντολή, άρα δεν
 * υπάρχει τέτοιο κλικ***».
 *
 * 🔑 **Η αιτιολόγηση ήταν λάθος τη στιγμή που γράφτηκε.** Η εντολή υπήρχε ήδη και λέγεται
 * `Ctrl+A` ({@link tableWholeGridRange} → `selectAll()`)· αυτό που έλειπε ήταν **δεύτερη
 * πόρτα** προς αυτήν. Ο ιδιοκτήτης το μέτρησε στην οθόνη (04/08) και την ανέτρεψε.
 *
 * ⚠️ **Το `tableIndicatorHitAtFrame` εξακολουθεί να επιστρέφει `null` εδώ — και είναι σωστό.**
 * Ο λόγος όμως άλλαξε ριζικά: όχι «δεν υπάρχει εντολή», αλλά **λάθος τύπος**. Εκείνη η
 * συνάρτηση απαντά «*ποια **υποδιαίρεση άξονα**;*» και η γωνία **δεν είναι άξονας** — μια
 * τρίτη περίπτωση `{ axis: 'corner' }` θα υποχρέωνε κάθε `switch` πάνω στο `axis` να απαντήσει
 * «ποιο πλάτος έχει η γωνία;». Την ερώτηση «είμαι στη γωνία;» την απαντά το
 * `table-select-all-corner`, που είναι και ο κάτοχος ολόκληρης της έννοιας.
 *
 * @see bim/table/table-select-all-corner.ts — ΤΟ ΚΟΥΜΠΙ (hit-test + τρίγωνο), ADR-739 §43
 */
export function tableIndicatorCornerRectMm(bands: TableIndicatorBandsMm): TableRectMm {
  return {
    x: rowBandLeftMm(bands),
    y: columnBandTopMm(bands),
    w: bands.rowBandMm,
    h: bands.columnBandMm,
  };
}

