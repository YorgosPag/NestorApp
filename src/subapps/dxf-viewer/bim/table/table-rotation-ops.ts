/**
 * 🔴 ADR-739 §59 Δ1 — **Ο ΠΡΟΣΑΝΑΤΟΛΙΣΜΟΣ ΚΕΙΜΕΝΟΥ ΚΕΛΙΟΥ**: τι σημαίνει το πάτημα, και —
 * το βαρύ μισό — **πόσο χώρο θέλει** ένα γερμένο μπλοκ κειμένου. Καθαρό· μηδέν React/DOM.
 *
 * ## 🔴 ΤΟ ΚΟΣΤΟΣ ΔΕΝ ΕΙΝΑΙ Η ΣΤΡΟΦΗ — ΕΙΝΑΙ Η ΔΙΑΤΑΞΗ
 * Η μηχανή στροφής **υπήρχε ήδη** και σε τέσσερα σημεία: ο ζωγράφος του καμβά
 * (`stampFrameText`), η αποδόμηση εξαγωγής (`decomposeTable` → `rotationDeg`), ο επεξεργαστής
 * κελιού (`rotationRad`) και το 3Δ υπόστρωμα. Όλα γέρνουν ήδη **ολόκληρο** τον πίνακα. Αυτό
 * που δεν υπήρχε πουθενά είναι η απάντηση στο «**πόσο ψηλή** πρέπει να γίνει η γραμμή και
 * **πόσο πλατιά** η στήλη όταν το κείμενο γέρνει» — και εκεί ζει ολόκληρη αυτή η φάση.
 *
 * ```
 *   μπλοκ κειμένου:  μήκος L κατά μήκος της γραμμής βάσης
 *                    πάχος T κάθετα σε αυτήν  (ύψος + (n−1)×βήμα)
 *
 *   γερμένο κατά θ:  ΠΛΑΤΟΣ' = L·|cosθ| + T·|sinθ|
 *                    ΥΨΟΣ'   = L·|sinθ| + T·|cosθ|
 * ```
 * Με `θ = 0` δίνει `(L, T)` — **ταυτόσημα** με σήμερα, χωρίς κλάδο-εξαίρεση. Με `θ = ±90`
 * δίνει `(T, L)`: το «πλάτος» του κειμένου γίνεται **ύψος**, που είναι ακριβώς ο λόγος που μια
 * `hug` στήλη με κάθετο κείμενο βγαίνει **στενή** αντί για τεράστια.
 *
 * ## 🔴 Ο ΚΥΚΛΟΣ ΜΕ ΤΗΝ ΑΝΑΔΙΠΛΩΣΗ ΣΠΑΕΙ ΜΕ **ΣΕΙΡΑ**, ΟΠΩΣ ΣΤΟ §58 — ΟΧΙ ΜΕ ΕΠΑΝΑΛΗΨΗ
 * Η αναδίπλωση χρειάζεται ένα **πεπερασμένο μήκος** κατά μήκος της γραμμής βάσης για να ξέρει
 * πού να σπάσει. Σε γερμένο κείμενο, μήκος `L` που περιορίζεται από πλάτος κελιού `W` δίνει
 * `L ≤ W / |cosθ|` — και το §58 έχει ήδη αποφασίσει ότι **οι στήλες μετρώνται ΠΡΩΤΑ**, οπότε
 * το `W` είναι γνωστό.
 *
 * 🔑 **Στις ±90° το πηλίκο απειρίζεται, και αυτό είναι ΣΩΣΤΟ, όχι κενό.** Ο μόνος άλλος
 * περιορισμός εκεί θα ήταν το **ύψος της γραμμής** — δηλαδή ακριβώς το μέγεθος που η μέτρηση
 * **παράγει** από το αποτέλεσμα. Χρησιμοποιώντας το, ο κύκλος θα ξανάκλεινε. Η συνέπεια είναι
 * παρατηρήσιμη και ίδια με του Excel: κελί σε `wrap` στραμμένο 90° **δεν αναδιπλώνεται** και η
 * γραμμή ψηλώνει όσο και το κείμενο.
 *
 * ## 🏆 Πού ξεπερνάμε τους μεγάλους — με ονόματα και μετρήσεις
 * | | Στροφή ανά κελί | Εμβέλεια | Η διάταξη την τιμά |
 * |---|---|---|---|
 * | **Excel** | ναι | −90..+90 **+ στοιβαγμένο** | ύψος γραμμής **ναι**, πλάτος στήλης όχι αξιόπιστα |
 * | **AutoCAD** | ναι, `SetTextRotation` | **μόνο** `acDegrees000/090/180/270` — τέσσερις τιμές | — |
 * | **Revit** | **μόνο κεφαλίδες**, μόνο στο φύλλο, μόνο κατακόρυφα | 0 ή 90 | — |
 * | **ΝΕΣΤΩΡ** | ναι | **αυθαίρετη** −90..+90 | **ύψος γραμμής ΚΑΙ πλάτος στήλης**, από την ίδια οριοθέτηση |
 *
 * ⚠️ **Η γραμμή του AutoCAD επαληθεύτηκε πριν γραφτεί** (παγίδα #11 του handoff): το ίδιο το
 * handoff υπέθετε ότι το AutoCAD **δεν έχει** στροφή ανά κελί. **Έχει** — η μέθοδος
 * `AcadTable.SetTextRotation(row, col, rotation)` υπάρχει από παλιά. Αυτό που **δεν** έχει
 * είναι αυθαίρετη γωνία: η παράμετρος είναι το enum `AcRotationAngle` με **τέσσερις** τιμές.
 * Η υπεροχή είναι πραγματική, αλλά είναι άλλη από αυτήν που νόμιζε το handoff — και μια
 * τεκμηρίωση που έλεγε «το AutoCAD δεν το κάνει» θα ήταν ψευδής ισχυρισμός για τον ανταγωνιστή,
 * δηλαδή ακριβώς η αστοχία που κατέγραψε το §58 Γ2.
 *
 * @module subapps/dxf-viewer/bim/table/table-rotation-ops
 * @see bim/table/table-layout-measure.ts — ποιος καταναλώνει την οριοθέτηση
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §59
 */

import type { TableCellStyle } from './table-style';

/**
 * Το άκρο της εμβέλειας. **Ίδιο με του Excel** (±90°) — δες τον τύπο στο `types/table.ts` για
 * το γιατί αποθηκεύεται προσημασμένο αντί για το μη μονότονο `0-180` του OOXML.
 */
export const MAX_TABLE_TEXT_ROTATION_DEG = 90;

/**
 * 🔴 Οι **δύο** προεπιλογές που έχουν κουμπί — και γιατί μόνο αυτές.
 *
 * Το μενού «Προσανατολισμός» του Excel έχει **πέντε** προεπιλογές (γωνία αριστερόστροφα, γωνία
 * δεξιόστροφα, κατακόρυφο στοιβαγμένο, περιστροφή προς τα πάνω, περιστροφή προς τα κάτω) και
 * μετά *«Μορφοποίηση στοίχισης κελιού…»* για **ελεύθερη** γωνία. Εδώ αποκτούν κουμπί οι δύο
 * περιστροφές των **90°**, για τρεις μετρημένους λόγους:
 *
 * 1. **Το στοιβαγμένο δεν είναι στροφή** — είναι άλλη διάταξη glyph, και δηλώνεται ρητά εκτός
 *    εμβέλειας στο `types/table.ts`. Κουμπί που το προσποιείται θα ήταν υπόσχεση που δεν τηρείται.
 * 2. **Οι «γωνίες» του Excel είναι ±45°** και εξυπηρετούν φύλλα υπολογισμού· σε **σχέδιο** η
 *    χρήσιμη γωνία είναι η κατακόρυφη κεφαλίδα στενής στήλης, που είναι ακριβώς αυτές οι δύο.
 * 3. **Η ελεύθερη γωνία μένει εκφράσιμη στο μοντέλο** και ανήκει στην ίδια **τρίτη επιφάνεια**
 *    με τη μορφή αριθμού — τον διάλογο «Μορφοποίηση κελιών». Δηλωμένο κενό, όχι σιωπηλά απόν,
 *    και είναι **η ίδια** διαίρεση που κάνει το Excel: προεπιλογές στην κορδέλα, γωνία στον
 *    διάλογο.
 *
 * ⚠️ Δύο κουμπιά και όχι πτυσσόμενο: το `type: 'split'` είναι **δομικά αδύνατο** σε contextual
 * καρτέλα πίνακα (portal ⇒ ο φύλακας συνεδρίας δεν βρίσκει το `keepalive` σημάδι ⇒ η καρτέλα
 * εξαφανίζεται στο κλικ, §57).
 */
export type TableRotationPreset = 'up' | 'down';

/** Πόσες μοίρες είναι κάθε προεπιλογή. Χάρτης, ώστε ο μεταγλωττιστής να απαιτεί απάντηση. */
const PRESET_DEG: Readonly<Record<TableRotationPreset, number>> = {
  /** Διαβάζεται από **κάτω προς τα πάνω** — η κλασική κατακόρυφη κεφαλίδα. */
  up: 90,
  /** Διαβάζεται από **πάνω προς τα κάτω**. */
  down: -90,
};

/** Οι διαστάσεις ενός **γερμένου** μπλοκ κειμένου, σε άξονες παράλληλους στο κελί. */
export interface RotatedTextExtentMm {
  /** Οριζόντια απαίτηση — ό,τι χρειάζεται μια `hug` στήλη. */
  readonly widthMm: number;
  /** Κατακόρυφη απαίτηση — ό,τι χρειάζεται μια γραμμή αυτόματου ύψους. */
  readonly heightMm: number;
}

/**
 * Η **οριοθέτηση** ενός μπλοκ `lengthMm × thicknessMm` γερμένου κατά `deg`.
 *
 * Ο τύπος είναι η κλασική περιστροφή AABB και **δεν** έχει ειδική περίπτωση: με `deg = 0`
 * επιστρέφει τις εισόδους **αυτούσιες** (`cos=1`, `sin=0`), οπότε κάθε πίνακας που υπάρχει
 * σήμερα περνά από το ίδιο σώμα και βγάζει byte-ταυτόσημα μεγέθη.
 */
export function rotatedTextExtentMm(
  lengthMm: number,
  thicknessMm: number,
  deg: number,
): RotatedTextExtentMm {
  const { cos, sin } = trigOf(deg);
  return {
    widthMm: lengthMm * cos + thicknessMm * sin,
    heightMm: lengthMm * sin + thicknessMm * cos,
  };
}

/**
 * 🔴 Το **μέγιστο μήκος γραμμής** που επιτρέπει ένα οριζόντιο ωφέλιμο πλάτος, όταν το κείμενο
 * γέρνει κατά `deg` — `Infinity` όταν η γωνία είναι (πρακτικά) κατακόρυφη.
 *
 * ## Γιατί το άπειρο δεν είναι διαρροή αλλά **δήλωση**
 * Στις ±90° το κείμενο δεν καταναλώνει **καθόλου** οριζόντιο μήκος: το πλάτος του κελιού δεν
 * το περιορίζει με κανέναν τρόπο. Ο μόνος περιορισμός θα ήταν το ύψος της γραμμής — που η
 * μέτρηση **παράγει** από αυτό ακριβώς το αποτέλεσμα (δες την κεφαλίδα). Ένα `Infinity` το
 * λέει ρητά· ένα μεγάλο πεπερασμένο νούμερο θα ήταν σιωπηλό ψέμα που σπάει σε κάποιο μέγεθος
 * κειμένου που κανείς δεν δοκίμασε.
 *
 * ⚠️ Το κατώφλι είναι **γωνιακό** και όχι έλεγχος `=== 90`: το μοντέλο δέχεται `number`, οπότε
 * ένα `89,9999°` από παλιό αρχείο θα έδινε διαίρεση με ~1e-6 και μήκος γραμμής μερικών
 * **χιλιομέτρων** — αριθμός που θα ταξίδευε ως πλάτος στήλης χωρίς κανένα σφάλμα.
 */
export function maxLineLengthMm(usableWidthMm: number, deg: number): number {
  const { cos } = trigOf(deg);
  return cos <= VERTICAL_COS_EPSILON ? Number.POSITIVE_INFINITY : usableWidthMm / cos;
}

/**
 * Κάτω από αυτό το `|cos θ|` η γωνία θεωρείται κατακόρυφη.
 *
 * `1e-4` ⇒ ~89,994°: αρκετά κοντά ώστε καμία **ανθρώπινη** γωνία να μην το πιάνει κατά λάθος
 * (το χειριστήριο δίνει πολλαπλάσια των 15°), και αρκετά μακριά ώστε το πηλίκο να μη γίνει
 * ποτέ αστρονομικό (μέγιστη ενίσχυση ×10.000, όχι ×10⁹).
 */
const VERTICAL_COS_EPSILON = 1e-4;

/**
 * Η επιλογή εφαρμοσμένη πάνω στην τρέχουσα γωνία — **εναλλαγή**, όπως κάθε κουμπί μορφοποίησης.
 *
 * ```
 *   ίδια με την τρέχουσα  →  `undefined` = ΣΒΗΣΕ το πεδίο ⇒ πίσω στην κληρονομιά (οριζόντιο)
 *   άλλη / ανάμεικτο      →  η γωνία της προεπιλογής
 * ```
 *
 * 🔑 Το ξεπάτωμα γράφει **`undefined` και όχι ρητό `0`**, με τον ίδιο λόγο που το κάνουν η
 * εσοχή και η μορφή αριθμού: ένα ρητό `0` στο κελί θα **νικούσε** μια γωνία δηλωμένη στη γραμμή
 * ή στη στήλη, δηλαδή θα γεννούσε παράκαμψη που ο χρήστης δεν βλέπει και που ακυρώνει σιωπηλά
 * την κληρονομιά.
 *
 * 🔴 Η **αμοιβαία αποκλειστικότητα** των δύο κουμπιών δεν γράφεται πουθενά και δεν χρειάζεται:
 * το πεδίο είναι **ένας αριθμός**, οπότε «πάνω» πάνω σε «κάτω» απλώς γράφει `+90` — ίδια αρχή
 * με το `nextTableOverflow`, όπου τη δουλειά την κάνει ο τύπος αντί για κώδικα που κάποιος
 * μπορεί να ξεχάσει να γράψει στη δεύτερη επιφάνεια.
 */
export function nextTableTextRotation(
  current: number | null,
  preset: TableRotationPreset,
): number | undefined {
  return isTableTextRotationActive(current, preset) ? undefined : PRESET_DEG[preset];
}

/**
 * Είναι **πατημένο** αυτό το κουμπί;
 *
 * Ανάμεικτος στόχος (`null`) ⇒ **καμία** επιλογή τσεκαρισμένη: η ερώτηση «γέρνει;» δεν έχει
 * μία απάντηση, και ένα πατημένο κουμπί θα έλεγε ψέματα για τα μισά κελιά. Ίδια σύμβαση με τα
 * `isTableAlignActive` / `isTableOverflowActive` / `isTableNumberFormatActive`.
 */
export function isTableTextRotationActive(
  current: number | null,
  preset: TableRotationPreset,
): boolean {
  return current !== null && clampTableTextRotationDeg(current) === PRESET_DEG[preset];
}

/**
 * Η γωνία **αυτού** του στυλ, κανονικοποιημένη — ο ΕΝΑΣ δρόμος από το μοντέλο στη γεωμετρία.
 *
 * Κάθε καταναλωτής (μέτρηση · τοποθέτηση · ζωγράφος · εξαγωγή · επεξεργαστής) περνά από εδώ,
 * ώστε ένα εκτός ορίων `textRotationDeg` από αποθηκευμένο αρχείο άλλης έκδοσης να δίνει την
 * **ίδια** απάντηση σε όλους. Πέντε τοπικά `Math.min/max` θα ήταν πέντε ευκαιρίες να διαφωνήσουν
 * — και η διαφωνία θα ήταν κείμενο που ζωγραφίζεται σε άλλη γωνία από αυτήν που μετρήθηκε.
 */
export function tableTextRotationDeg(style: TableCellStyle): number {
  return clampTableTextRotationDeg(style.textRotationDeg);
}

/**
 * 🔴 ADR-739 §60 — **Η γωνία μέσα στα όρια**· μη πεπερασμένη ⇒ οριζόντιο (η ασφαλής, ορατή
 * απάντηση).
 *
 * Ήταν ιδιωτική (`clampRotationDeg`) και έγινε δημόσια όταν απέκτησε **δεύτερο είδος**
 * καταναλωτή: η **ελεύθερη γωνία** του διαλόγου «Μορφοποίηση κελιών». Μέχρι το §59 η μόνη πηγή
 * τιμής ήταν τα δύο preset, δηλαδή τιμές που ήταν **εξ ορισμού** εντός ορίων· ο διάλογος
 * δέχεται πληκτρολόγηση, άρα το κόψιμο πρέπει να είναι ερώτηση που μπορεί να κάνει και η
 * επιφάνεια.
 *
 * ⚠️ **ΔΕΝ στρογγυλοποιεί**, και είναι απόφαση: η ίδια συνάρτηση τροφοδοτεί τη **γεωμετρία**
 * ({@link tableTextRotationDeg} → μέτρηση, τοποθέτηση, ζωγράφος, εξαγωγή). Μια στρογγυλοποίηση
 * εδώ θα κβάντιζε σιωπηλά μια νόμιμη γωνία 45,5° σε **κάθε** διαδρομή απόδοσης. Το ακέραιο
 * βήμα είναι σύμβαση **του χειριστηρίου** και ζει εκεί.
 */
export function clampTableTextRotationDeg(deg: number): number {
  if (!Number.isFinite(deg)) return 0;
  return Math.min(Math.max(deg, -MAX_TABLE_TEXT_ROTATION_DEG), MAX_TABLE_TEXT_ROTATION_DEG);
}

