/**
 * `|cos|` και `|sin|` της γωνίας — **πάντα θετικά**, γιατί η οριοθέτηση δεν έχει πρόσημο.
 *
 * Μία συνάρτηση και όχι δύο κλήσεις ανά καταναλωτή: το ζεύγος πρέπει να προέρχεται από την
 * **ίδια** κανονικοποιημένη γωνία, αλλιώς μια αλλαγή στο κόψιμο θα εφαρμοζόταν στο ένα και όχι
 * στο άλλο — και το σύμπτωμα θα ήταν οριοθέτηση που δεν είναι ορθογώνιο.
 */
function trigOf(deg: number): { readonly cos: number; readonly sin: number } {
  const rad = (clampTableTextRotationDeg(deg) * Math.PI) / 180;
  return { cos: Math.abs(Math.cos(rad)), sin: Math.abs(Math.sin(rad)) };
}
