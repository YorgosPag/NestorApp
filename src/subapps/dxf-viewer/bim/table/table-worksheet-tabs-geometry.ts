/**
 * ADR-833 Φάση 3 — **ΠΟΥ ΚΑΘΟΝΤΑΙ ΟΙ ΚΑΡΤΕΛΕΣ ΦΥΛΛΩΝ**, σε sheet-mm του πλαισίου του πίνακα.
 *
 * Είναι το **κάτοπτρο** του {@link module:subapps/dxf-viewer/bim/table/table-indicator-geometry}
 * στην κάτω ακμή, και το λέμε ρητά ώστε να μη γεννηθεί δεύτερο ιδίωμα:
 *
 * ```
 *   ζώνη γραμμάτων :  v ∈ [-(gap + bandMm), -gap)        (πάνω από το πλέγμα)
 *   λωρίδα καρτελών:  v ∈ (heightMm + gap, heightMm + gap + bandMm]   (κάτω από το πλέγμα)
 * ```
 *
 * Ό,τι ισχύει εκεί ισχύει εδώ αυτούσιο: μέγεθος σε **px οθόνης** μέσω `pxPerMm`, πύλη **LOD**,
 * και **έξω** από το `hitTestTable` / `calculateTableBounds` — το συμβόλαιο marquee και
 * spatial-index μένει **αναλλοίωτο** (ADR-833 §5.3).
 *
 * ## 🔴 Η ΛΩΡΙΔΑ ΕΙΝΑΙ **ΧΡΩΜΙΟ ΔΙΕΠΑΦΗΣ, ΟΧΙ ΧΑΡΤΙ**
 * Δεν μπαίνει στο `layout.heightMm`. Θα άλλαζε το **τυπωμένο** αποτύπωμα του πίνακα και θα
 * παρέσυρε **κάθε** καταναλωτή του ύψους: εξαγωγή DXF/PDF, 3Δ υπόστρωμα, breaking, bbox,
 * marquee. Ίδια απόφαση —και ίδιο σκεπτικό— με τις ζώνες δείκτη, που ζουν σε **αρνητικό** `v`
 * ακριβώς για να μην αγγίξουν τη διάταξη.
 *
 * ## 🔴 ΤΟ ΚΕΝΟ: Η ΚΑΤΩ ΑΚΜΗ ΕΧΕΙ ΗΔΗ ΤΡΕΙΣ ΕΝΟΙΚΟΥΣ
 * Στο `v = heightMm` κάθονται ήδη:
 *
 * | ένοικος | πού | πότε |
 * |---|---|---|
 * | λαβή `table-edge-s` | μέσο κάτω ακμής (`TABLE_BOX_TARGETS`) | όταν φαίνονται τα midpoints |
 * | λαβές `table-corner-sw` / `-se` | κάτω γωνίες | πάντα σε επιλεγμένο |
 * | **λαβή συμπλήρωσης** | κάτω-δεξιά κορυφή της **ΕΠΙΛΕΓΜΕΝΗΣ ΠΕΡΙΟΧΗΣ** | **μόνο** όταν η επιλογή αγγίζει την τελευταία γραμμή |
 *
 * Είναι **ακριβώς** το περιστατικό του ADR-739 §27.11 (ζώνη κολλητά στο `v = 0`, μισή λαβή
 * μέσα στη ζώνη, ο χρήστης στόχευε πλάτος στήλης και έπαιρνε επιλογή στήλης) — με τη διαφορά
 * ότι εδώ η τρίτη περίπτωση είναι **υπό συνθήκη**, άρα το σφάλμα θα εμφανιζόταν μόνο σε
 * ορισμένες επιλογές: η χειρότερη εκδοχή, γιατί δεν αναπαράγεται όταν το ψάχνεις.
 *
 * 🔑 **Η ΛΥΣΗ ΕΙΝΑΙ ΗΔΗ ΓΡΑΜΜΕΝΗ ΚΑΙ ΕΧΕΙ ΟΝΟΜΑ**: {@link TABLE_INDICATOR_GRIP_CLEARANCE_PX}.
 * Αυτή η λωρίδα γίνεται ο **πέμπτος καταναλωτής** της, ποτέ η δεύτερη άποψη. Και δεν είναι
 * «ίδιος αριθμός για συνέπεια» — είναι ο αριθμός που κάνει τη σύγκρουση **μη εκφράσιμη**, με
 * απόδειξη που **υπάρχει ήδη**:
 *
 * ```
 *   εξωτερική εμβέλεια λαβής συμπλήρωσης = TABLE_FILL_HANDLE_PX/2 + OUTWARD_APERTURE = 7 px
 *   κενό της λωρίδας                     = TABLE_INDICATOR_GRIP_CLEARANCE_PX          = 9 px
 *   7 ≤ 9  ⇒ η λαβή τελειώνει ΠΡΙΝ αρχίσει η καρτέλα
 * ```
 *
 * Η ανισότητα `7 ≤ 9` είναι **ήδη** κλειδωμένη σε άγκυρα (`table-fill-handle.test.ts`,
 * «outerReachPx ≤ TABLE_INDICATOR_GRIP_CLEARANCE_PX») — γραμμένη για άλλο λόγο, και τώρα
 * κρατά **και** αυτό. Το ίδιο ισχύει για τις λαβές κουτιού: η οπή σύλληψής τους **είναι**
 * `gripAperturePx(...)`, δηλαδή ο ίδιος αριθμός, άρα η καρτέλα αρχίζει ακριβώς εκεί που η
 * λαβή σταματά να πιάνεται.
 *
 * ⚠️ Και η **παραίτηση**, ως δίχτυ (N.7.2 #4): όταν προηγείται λαβή, η καρτέλα υποχωρεί. Η
 * προτεραιότητα ανήκει στη λαβή (**δομική** πράξη), ποτέ στην καρτέλα (**πλοήγηση**) — και
 * η λαβή δεν έχει δεύτερο δρόμο, ενώ η καρτέλα έχει (η διπλανή της). Η σειρά ζει στον
 * `tableIndicatorProbeAtWorld`, όπου ζει ήδη η σειρά όλων των καναλιών.
 *
 * ## 🔴 ΥΠΕΡΧΕΙΛΙΣΗ — ΤΟ ΠΑΡΑΘΥΡΟ ΕΙΝΑΙ **ΠΑΡΑΓΩΓΟ**, ΟΧΙ ΑΠΟΘΗΚΕΥΜΕΝΗ ΘΕΣΗ ΚΥΛΙΣΗΣ
 *
 * Το πρόβλημα είναι **στενότερο** από των μεγάλων παικτών: η λωρίδα έχει το πλάτος **του
 * πίνακα**, όχι του παραθύρου — δηλαδή υπερχειλίζει πολύ νωρίτερα, και σε κάθε zoom-out.
 *
 * Τι κάνουν οι μεγάλοι (μετρημένο, 2026-08-30):
 * - **Excel**: βελάκια κύλισης + δεξί κλικ πάνω τους ⇒ διάλογος «Activate». Η θέση κύλισης
 *   είναι **αποθηκευμένη κατάσταση**, και τεκμηριωμένα πονάει: το ενεργό φύλλο **μπορεί να
 *   είναι εκτός οθόνης**, ενώ ο τροχός «*resets to current tab as soon as I stop scrolling*».
 * - **Sheets**: κύλιση + μενού «όλα τα φύλλα».
 * - **Numbers**: σμίκρυνση/κύλιση.
 *
 * 🔑 **Η δική μας απάντηση είναι αυστηρότερη, και δεν κρατά τίποτα**: το παράθυρο των ορατών
 * καρτελών είναι **καθαρή συνάρτηση** του `(πλήθος, ενεργός δείκτης, χωρητικότητα)` —
 * κεντραρισμένο στην ενεργή καρτέλα και κομμένο στα άκρα ({@link tableWorksheetTabWindow}).
 * Από αυτό βγαίνουν **δύο αναλλοίωτες που το Excel ΔΕΝ έχει**:
 *
 *  1. **Η ενεργή καρτέλα είναι ΠΑΝΤΑ ορατή** — εξ ορισμού, όχι κατά σύμπτωση.
 *  2. **Καμία δεύτερη αλήθεια**: η «θέση κύλισης» δεν υπάρχει ως δεδομένο, άρα δεν μπορεί να
 *     παλιώσει, να ξεχαστεί σε reset, ή να διαφωνήσει με το `activeWorksheetId`. Είναι ο ίδιος
 *     κανόνας που το ADR-833 §5.3 επιβάλλει για το ενεργό φύλλο («*⛔ ΜΗΝ φτιάξεις store*»),
 *     εφαρμοσμένος στο παράγωγό του.
 *
 * Και η **προσβασιμότητα δεν χάνεται**: πατώντας την ακριανή ορατή καρτέλα, το παράθυρο
 * ξανακεντράρεται και αποκαλύπτονται οι επόμενες — δηλαδή κάθε φύλλο είναι προσβάσιμο με
 * φραγμένο πλήθος κλικ, χωρίς βελάκια, χωρίς μενού, χωρίς κατάσταση.
 *
 * @module subapps/dxf-viewer/bim/table/table-worksheet-tabs-geometry
 * @see bim/table/table-indicator-geometry.ts — ΤΟ ΠΡΟΤΥΠΟ (και η πηγή του κενού + του LOD)
 * @see bim/table/table-worksheet-name.ts — ΠΩΣ λέγεται η κάθε καρτέλα (ονομασία SSoT)
 * @see rendering/entities/table/stamp-table-worksheet-tabs.ts — ο ζωγράφος που τα καταναλώνει
 * @see docs/centralized-systems/reference/adrs/ADR-833-table-xlsx-import-and-worksheets.md §5.3, §5.4
 */

