/**
 * Το πλάτος μιας καρτέλας σε **px οθόνης** — **ενιαίο**, ποτέ κατά περιεχόμενο.
 *
 * ## Γιατί ενιαίο και όχι «όσο χρειάζεται το όνομα», όπως στο Excel
 * Πλάτος κατά περιεχόμενο σημαίνει **μέτρηση κειμένου**, δηλαδή `ctx.measureText` — δηλαδή
 * **καμβάς μέσα στη γεωμετρία**. Αυτό το module είναι καθαρή γεωμετρία (μηδέν καμβάς, μηδέν
 * store, μηδέν React), ακριβώς όπως το αδελφό του δηλώνει για τον εαυτό του. Το τίμημα της
 * παραβίασης δεν θα ήταν αισθητικό: το **hit-test** θα έπρεπε να μετρήσει κι αυτό, με το ίδιο
 * `font`, στο ίδιο context — και η πρώτη φορά που οι δύο μετρήσεις θα διαφωνούσαν (άλλο DPR,
 * γραμματοσειρά που δεν φορτώθηκε ακόμη, offscreen pass) ο χρήστης θα πατούσε **διπλανή**
 * καρτέλα από αυτήν που βλέπει. Με ενιαίο πλάτος, «ό,τι πατιέται είναι ό,τι φαίνεται» είναι
 * **δομικό**.
 *
 * 🔑 Και το πλάτος κατά περιεχόμενο είναι **ο ίδιος ο λόγος** που το Excel χρειάζεται βελάκια
 * κύλισης: με άγνωστο πλάτος ανά καρτέλα, η χωρητικότητα δεν είναι υπολογίσιμη εκ των
 * προτέρων. Η ενιαία καρτέλα δίνει `χωρητικότητα = ⌊διαθέσιμο / πλάτος⌋` — και **αυτό** είναι
 * που επιτρέπει το παράγωγο παράθυρο της κεφαλίδας.
 *
 * ## Ο αριθμός, με την αριθμητική του
 * Η ετικέτα γράφεται στο ίδιο μέγεθος με τις ζώνες (`TABLE_INDICATOR.fontPx` = 11 px). Το
 * μακρύτερο **προεπιλεγμένο** όνομα για βιβλίο έως 99 φύλλα είναι `Φύλλο99` / `Sheet99` —
 * 7 χαρακτήρες, ≈ 0,55 em ο μέσος χαρακτήρας ⇒ ≈ 42 px, συν **2 × 8 px** εσωτερικό περιθώριο
 * ⇒ **58 px** (δες {@link TABLE_WORKSHEET_TAB_LABEL_PADDING_PX} — ο ίδιος αριθμός, ένα σπίτι).
 * Στρογγυλοποιείται στα **64** ώστε να μένει περιθώριο για ονόματα χρήστη πριν
 * χρειαστεί αποκοπή. Μεγαλύτερα ονόματα **κόβονται με «…»** στον ζωγράφο — εκεί ζει νόμιμα η
 * μέτρηση, γιατί η ετικέτα είναι **διακόσμηση** και το ορθογώνιο ο **στόχος** (ίδιος
 * διαχωρισμός με το `MIN_TICK_LABEL_PX` του δείκτη: η λωρίδα μένει, το γράμμα φεύγει).
 */
const TABLE_WORKSHEET_TAB_WIDTH_PX = 64;

/**
 * Το εσωτερικό περιθώριο της ετικέτας μέσα στην καρτέλα, **ανά πλευρά**, σε px οθόνης.
 *
 * Ζει **εδώ** και όχι στον ζωγράφο παρότι μόνο εκείνος το ζωγραφίζει: είναι ο **ίδιος**
 * αριθμός που παράγει το {@link TABLE_WORKSHEET_TAB_WIDTH_PX} (δες την αριθμητική του). Δύο
 * σπίτια θα σήμαιναν ότι κάποιος αυξάνει το περιθώριο, η καρτέλα δεν μεγαλώνει, και τα
 * ονόματα αρχίζουν να κόβονται χωρίς να το ζητήσει κανείς.
 */
export const TABLE_WORKSHEET_TAB_LABEL_PADDING_PX = 8;

/**
 * 🔴 **ΠΟΤΕ ΕΧΕΙ ΝΟΗΜΑ ΛΩΡΙΔΑ ΧΩΡΙΣ ΤΟ ⊕** — και γιατί ο αριθμός ΔΕΝ κατέβηκε απλώς στο 1.
 *
 * Το Excel δείχνει καρτέλα και με **ένα** φύλλο, δικαιολογημένα: η λωρίδα του κουβαλά **και**
 * το κουμπί «νέο φύλλο», δηλαδή έχει δουλειά ακόμα κι όταν δεν υπάρχει τίποτα να διαλέξεις.
 *
 * Η λωρίδα της **Φάσης 3** έκανε ακριβώς ένα πράγμα — άλλαζε ενεργό φύλλο — οπότε με ένα φύλλο
 * θα ήταν χειριστήριο που **υπόσχεται** αλληλεπίδραση χωρίς να την έχει, πάνω σε **κάθε**
 * πίνακα του σχεδίου. Γι αυτό ο αριθμός ήταν **2**, με γραμμένη την πρόβλεψη ότι η Φάση 4 θα
 * τον κατέβαζε στο 1 μόλις εμφανιζόταν το ⊕.
 *
 * 🔑 **Η πρόβλεψη ήταν σχεδόν σωστή.** Το ⊕ όντως δίνει στη λωρίδα δουλειά με ένα φύλλο — αλλά
 * **μόνο όταν χωράει**. Σε πολύ στενό πίνακα (ή σε αρκετό zoom-out) χωρά **μία** καρτέλα και
 * τίποτα άλλο· εκεί η λωρίδα ξαναγίνεται αυτό ακριβώς που ο αριθμός 2 απέτρεπε. Άρα ο αριθμός
 * **μένει 2** και αλλάζει η **ερώτηση** που απαντά:
 *
 * ```
 *   χωράει το ⊕      ⇒ η λωρίδα δρα πάντα (έστω και με ένα φύλλο)  ⇒ ο αριθμός δεν ρωτιέται
 *   ΔΕΝ χωράει το ⊕  ⇒ δρα μόνο αν υπάρχει άλλο φύλλο να διαλέξεις ⇒ χρειάζονται 2
 * ```
 *
 * Ο κανόνας του ADR-739 §31 («*ο δείκτης δεν ψεύδεται· ό,τι φαίνεται, δρα*») μένει ακέραιος και
 * στις δύο περιπτώσεις — που είναι όλο το νόημα του αριθμού, όχι η τιμή του.
 */
const MIN_TABLE_WORKSHEET_TAB_COUNT = 2;

/** Τα μεγέθη της λωρίδας σε **sheet-mm**, στην τρέχουσα κλίμακα οθόνης. */
interface TableWorksheetTabsMm {
  /** Πλάτος μιας καρτέλας. */
  readonly tabWidthMm: number;
  /**
   * Ύψος της λωρίδας — **η ίδια** σταθερά με το πάχος των ζωνών δείκτη
   * (`TABLE_INDICATOR.columnBandPx`), και αυτό είναι απόφαση: είναι χρώμιο της **ίδιας**
   * οικογένειας γύρω από τον **ίδιο** πίνακα, και ένα δεύτερο ύψος θα ήταν δεύτερη άποψη για
   * το «πόσο χοντρή είναι μια λωρίδα πίνακα». Κανένας νέος αριθμός.
   */
  readonly tabHeightMm: number;
  /** Το κενό ως προς την κάτω ακμή του πλέγματος — δες την κεφαλίδα (οι τρεις ένοικοι). */
  readonly gapMm: number;
}

/**
 * Η **μία** μετατροπή px→mm της λωρίδας. Τα μεγέθη ζουν σε px οθόνης επίτηδες: είναι στοιχείο
 * **διεπαφής**, όχι γεωμετρία σχεδίου — μια καρτέλα σε mm χαρτιού θα γινόταν αδιάβαστη σε
 * zoom-out και τεράστια σε zoom-in. Ίδιος λόγος, ίδια λέξη, με το `tableIndicatorBandsMm`.
 */
function tableWorksheetTabsMm(pxPerMm: number): TableWorksheetTabsMm {
  return {
    tabWidthMm: TABLE_WORKSHEET_TAB_WIDTH_PX / pxPerMm,
    tabHeightMm: TABLE_INDICATOR.columnBandPx / pxPerMm,
    gapMm: TABLE_INDICATOR_GRIP_CLEARANCE_PX / pxPerMm,
  };
}

/**
 * 🔴 **ADR-833 Φάση 4 — ΤΟ ΠΛΑΤΟΣ ΤΟΥ ⊕**: το **μισό** μιας καρτέλας.
 *
 * Παράγεται από το {@link TABLE_WORKSHEET_TAB_WIDTH_PX}, ποτέ ως τρίτος ανεξάρτητος αριθμός:
 * η καρτέλα είναι φαρδιά επειδή κουβαλά **ετικέτα** (η αριθμητική της είναι γραμμένη στη
 * δήλωσή της), ενώ το ⊕ κουβαλά **σύμβολο** — δεν έχει τι να χωρέσει. Ένα πλήρες πλάτος θα
 * ήταν κουμπί δύο φορές μεγαλύτερο από ό,τι χρειάζεται, που **τρώει μια ολόκληρη καρτέλα** από
 * το παράθυρο υπερχείλισης σε κάθε στενό πίνακα.
 *
 * ⚠️ Και δεν είναι «όποιο μισό»: επειδή είναι **κλάσμα**, μια μελλοντική αλλαγή του πλάτους
 * καρτέλας το παρασύρει μαζί της. Δύο ανεξάρτητοι αριθμοί θα άφηναν το ⊕ να ξεχειλίσει ή να
 * χαθεί την πρώτη φορά που κάποιος αλλάξει τον έναν.
 */
const TABLE_WORKSHEET_ADD_WIDTH_PX = TABLE_WORKSHEET_TAB_WIDTH_PX / 2;

/**
 * Πόσα px λωρίδας υπάρχουν, και **πόσες καρτέλες** χωρούν σε αυτά μαζί με το ⊕.
 *
 * Η διαθέσιμη λωρίδα είναι το πλάτος του **πλέγματος** — όχι του παραθύρου, όχι του καμβά.
 * Είναι ο περιορισμός που κάνει το πρόβλημα υπερχείλισης **στενότερο** από των μεγάλων
 * παικτών, και ο λόγος που η απάντηση δεν μπορεί να είναι «απλώς μεγάλωσε τη λωρίδα».
 *
 * 🔑 **Το ⊕ πληρώνεται ΠΡΩΤΟ, αλλά μόνο αν μένει χώρος για έστω μία καρτέλα.** Η εναλλακτική
 * («βάλε το ⊕ ό,τι κι αν γίνει») θα έδινε λωρίδα με **μόνο** ένα κουμπί προσθήκης πάνω σε
 * βιβλίο πολλών φύλλων — δηλαδή χειριστήριο που κρύβει ακριβώς αυτό που ο χρήστης κοιτάζει.
 */
function tableWorksheetStripSeats(
  widthMm: number,
  pxPerMm: number,
): { readonly tabSeats: number; readonly hasAdd: boolean } {
  if (!(pxPerMm > 0) || !Number.isFinite(pxPerMm)) return { tabSeats: 0, hasAdd: false };
  const availablePx = widthMm * pxPerMm;
  const hasAdd = availablePx >= TABLE_WORKSHEET_TAB_WIDTH_PX + TABLE_WORKSHEET_ADD_WIDTH_PX;
  const forTabsPx = hasAdd ? availablePx - TABLE_WORKSHEET_ADD_WIDTH_PX : availablePx;
  return { tabSeats: Math.floor(forTabsPx / TABLE_WORKSHEET_TAB_WIDTH_PX), hasAdd };
}

/** Ποιες θέσεις του πίνακα φύλλων είναι ορατές: `[start, start + length)`. */
interface TableWorksheetTabWindow {
  readonly start: number;
  readonly length: number;
}

/**
 * 🔴 **ΤΟ ΠΑΡΑΘΥΡΟ ΤΩΝ ΟΡΑΤΩΝ ΚΑΡΤΕΛΩΝ** — καθαρή συνάρτηση, μηδέν κατάσταση.
 *
 * Κεντραρισμένο στην **ενεργή** καρτέλα και κομμένο στα άκρα. Δες την κεφαλίδα για το γιατί
 * αυτό είναι αυστηρότερο από τη θέση κύλισης του Excel — και για τις δύο αναλλοίωτες που
 * κερδίζονται (η ενεργή είναι πάντα ορατή· δεν υπάρχει δεύτερη αλήθεια να παλιώσει).
 *
 * ⚠️ Το `Math.floor((capacity - 1) / 2)` βάζει την ενεργή **αριστερά του κέντρου** σε ζυγή
 * χωρητικότητα, δηλαδή αφήνει **περισσότερες** καρτέλες δεξιά. Είναι σκόπιμο: τα φύλλα
 * γεννιούνται προς τα δεξιά (η προσθήκη της Φάσης 4 βάζει το νέο **στο τέλος** — δες
 * `table-worksheet-ops.ts`, Απόφαση 1), άρα «μπροστά» είναι η κατεύθυνση που ο χρήστης εξερευνά.
 */
function tableWorksheetTabWindow(
  count: number,
  activeIndex: number,
  capacity: number,
): TableWorksheetTabWindow {
  const length = Math.min(count, Math.max(capacity, 0));
  if (length <= 0) return { start: 0, length: 0 };
  const centred = activeIndex - Math.floor((length - 1) / 2);
  // Στριμωγμένο **και από τις δύο** πλευρές: χωρίς το `Math.max(0, …)` ένα ενεργό φύλλο κοντά
  // στην αρχή θα έδινε αρνητική αφετηρία, δηλαδή κενές θέσεις πριν από το πρώτο φύλλο.
  const start = Math.max(0, Math.min(centred, count - length));
  return { start, length };
}

/**
 * Μία καρτέλα, **έτοιμη**: πού κάθεται, ποια είναι, και αν είναι η ενεργή.
 *
 * 🔑 Κουβαλά το ίδιο το φύλλο και τη **θέση του στον πίνακα φύλλων** (`index`), όχι τη θέση
 * του μέσα στη λωρίδα: το προεπιλεγμένο όνομα («Φύλλο3») είναι συνάρτηση της θέσης **στο
 * βιβλίο**, και μια λωρίδα που κύλησε δεν επιτρέπεται να μετονομάσει τα φύλλα.
 */
export interface TableWorksheetTabSlot {
  readonly index: number;
  readonly id: TableWorksheetId;
  readonly sheet: TableWorksheet;
  readonly active: boolean;
  readonly rectMm: TableRectMm;
}

/**
 * 🔴 **ADR-833 Φάση 4 — ΟΛΟΚΛΗΡΗ Η ΛΩΡΙΔΑ**: οι ορατές καρτέλες **και** το κουμπί προσθήκης.
 *
 * ## Γιατί ΕΝΑ αντικείμενο και όχι δύο συναρτήσεις
 * Η θέση του ⊕ είναι **παράγωγο του παραθύρου** (κάθεται αμέσως μετά την τελευταία ορατή
 * καρτέλα), και η χωρητικότητα των καρτελών είναι **παράγωγο του αν χωρά το ⊕**. Δύο
 * ανεξάρτητες συναρτήσεις θα υπολόγιζαν την ίδια αριθμητική δύο φορές — και η πρώτη φορά που θα
 * διαφωνούσαν, το ⊕ θα καθόταν **πάνω** σε καρτέλα ή θα άφηνε κενό στη μέση της λωρίδας.
 *
 * Είναι η ίδια αρχή που κρατά ήδη μαζί ζωγράφο και hit-test: **ένα** αντικείμενο, δύο
 * καταναλωτές, καμία σύμβαση να ξεχαστεί.
 */
export interface TableWorksheetStrip {
  readonly tabs: readonly TableWorksheetTabSlot[];
  /** Το ⊕ της προσθήκης· `null` όταν δεν χωρά (πολύ στενός πίνακας ή zoom-out). */
  readonly add: TableRectMm | null;
}

/** Καμία λωρίδα — **σταθερή** αναφορά, ίδιος λόγος με το `EMPTY_PROBE` του hover. */
const EMPTY_STRIP: TableWorksheetStrip = { tabs: [], add: null };

/**
 * 🔴 **Η ΜΙΑ ΔΙΑΤΑΞΗ ΤΗΣ ΛΩΡΙΔΑΣ** — κενή λωρίδα όταν δεν υπάρχει τίποτα να δείξει.
 *
 * ## Γιατί ΜΙΑ συνάρτηση και όχι «γεωμετρία + hit-test» χωριστά
 * Ο ζωγράφος και το πάτημα καταναλώνουν **το ίδιο αντικείμενο**, όχι δύο κλήσεις που τυχαίνει
 * να συμφωνούν. Το hit-test ({@link tableWorksheetStripAtFrame}) είναι σάρωση **πάνω σε αυτό
 * εδώ** — άρα «ό,τι πατιέται είναι ό,τι φαίνεται» δεν είναι σύμβαση που κάποιος μπορεί να
 * ξεχάσει, είναι **αδύνατο να παραβιαστεί**. Ο δείκτης ζωνών το πετυχαίνει με **δύο**
 * συναρτήσεις που μοιράζονται σταθερές· εδώ, επειδή η διάταξη έχει **παράθυρο** και **κουμπί**
 * (δηλαδή δύο αποφάσεις, όχι μόνο αριθμητική), η κοινή δομή είναι η μόνη ασφαλής τομή.
 *
 * Οι τρεις πύλες, με αυτή τη σειρά:
 *  1. **LOD του πίνακα** — η **ίδια** έκφραση με τον δείκτη (`isTableIndicatorVisible`): ένας
 *     πίνακας πολύ μικρός για να φορέσει ζώνες είναι πολύ μικρός και για καρτέλες, και δύο
 *     κατώφλια θα σήμαιναν κατάσταση όπου φαίνεται το ένα χρώμιο και όχι το άλλο·
 *  2. **χωρητικότητα** — δεν χωρά ούτε μία καρτέλα ⇒ **τίποτα**. «Φαίνεται αλλά δεν πιάνεται»
 *     (ή το αντίστροφο) είναι ψέμα της οθόνης· εδώ όλα πεθαίνουν μαζί, γιατί όλα ρωτούν
 *     **αυτή** τη συνάρτηση·
 *  3. **πλήθος** — δες {@link MIN_TABLE_WORKSHEET_TAB_COUNT}: ρωτιέται **μόνο** όταν δεν χωρά
 *     το ⊕, γιατί μόνο τότε μπορεί η λωρίδα να μείνει χωρίς δουλειά.
 */
export function tableWorksheetTabStrip(
  worksheets: readonly TableWorksheet[],
  activeWorksheetId: TableWorksheetId,
  widthMm: number,
  heightMm: number,
  pxPerMm: number,
): TableWorksheetStrip {
  if (!(pxPerMm > 0) || !Number.isFinite(pxPerMm)) return EMPTY_STRIP;
  if (!isTableIndicatorVisible(widthMm, heightMm, pxPerMm)) return EMPTY_STRIP;

  const { tabSeats, hasAdd } = tableWorksheetStripSeats(widthMm, pxPerMm);
  // Δες το {@link MIN_TABLE_WORKSHEET_TAB_COUNT}: με το ⊕ παρόν η λωρίδα δρα πάντα, οπότε ο
  // αριθμός δεν ρωτιέται· χωρίς αυτό, δρα μόνο αν υπάρχει **άλλο** φύλλο να διαλέξεις.
  if (!hasAdd && worksheets.length < MIN_TABLE_WORKSHEET_TAB_COUNT) return EMPTY_STRIP;

  // Ο ενεργός δείκτης πέφτει στο **πρώτο** φύλλο όταν το `activeWorksheetId` δεν δείχνει
  // πουθενά — η **ίδια** ρητή ανοχή που κάνει το `activeWorksheet`, και για τον ίδιο λόγο:
  // μια αναφορά σε διαγραμμένο φύλλο είναι φυσιολογικό ενδιάμεσο στάδιο (undo, χειροποίητο
  // JSON). Δύο διαφορετικές ανοχές θα σήμαιναν λωρίδα που φωτίζει άλλο φύλλο από αυτό που
  // ζωγραφίζει ο πίνακας.
  const found = worksheets.findIndex((sheet) => sheet.id === activeWorksheetId);
  const activeIndex = found >= 0 ? found : 0;
  // ⚠️ Καμία πύλη «μηδενικό παράθυρο» εδώ: με `length === 0` ο βρόχος **δεν τρέχει** και η
  // απάντηση είναι ήδη κενή. Μια ρητή `if (view.length <= 0) return []` γράφτηκε, **μετρήθηκε
  // νεκρή με μετάλλαξη** (η αφαίρεσή της άφησε 24/24 πράσινα) και αφαιρέθηκε: ένας φύλακας που
  // δεν μπορεί να κοκκινίσει είναι σχόλιο μεταμφιεσμένο σε κώδικα.
  const view = tableWorksheetTabWindow(worksheets.length, activeIndex, tabSeats);

  const tabs = tableWorksheetTabsMm(pxPerMm);
  const slots: TableWorksheetTabSlot[] = [];
  for (let seat = 0; seat < view.length; seat++) {
    const index = view.start + seat;
    const sheet = worksheets[index];
    slots.push({
      index,
      id: sheet.id,
      sheet,
      active: index === activeIndex,
      rectMm: {
        x: seat * tabs.tabWidthMm,
        y: heightMm + tabs.gapMm,
        w: tabs.tabWidthMm,
        h: tabs.tabHeightMm,
      },
    });
  }

  return {
    tabs: slots,
    // 🔑 **Αμέσως μετά την τελευταία ΟΡΑΤΗ καρτέλα**, ποτέ καρφωμένο στη δεξιά ακμή: το Sheets
    // το κάνει έτσι, και ο λόγος είναι λειτουργικός — το κουμπί ταξιδεύει με το τέλος του
    // βιβλίου, δηλαδή δηλώνει «εδώ προστίθεται το επόμενο». Καρφωμένο δεξιά, θα υποσχόταν
    // εισαγωγή σε θέση που η πράξη δεν χρησιμοποιεί ποτέ.
    add: hasAdd
      ? {
          x: view.length * tabs.tabWidthMm,
          y: heightMm + tabs.gapMm,
          w: TABLE_WORKSHEET_ADD_WIDTH_PX / pxPerMm,
          h: tabs.tabHeightMm,
        }
      : null,
  };
}

/**
 * 🔴 **ADR-833 Φάση 4 — ΤΙ ΒΡΙΣΚΕΤΑΙ ΚΑΤΩ ΑΠΟ ΤΟ ΣΗΜΕΙΟ**, μέσα στη λωρίδα.
 *
 * Διακριτή ένωση και όχι «καρτέλα ή `null`»: το ⊕ **δεν είναι φύλλο** — δεν έχει ταυτότητα,
 * δεν έχει θέση στο βιβλίο, δεν έχει όνομα. Ένα προσποιητό `TableWorksheetTabSlot` γι' αυτό θα
 * απαιτούσε ψεύτικες τιμές σε τρία πεδία, και το πρώτο σημείο που θα τις διάβαζε αφελώς θα
 * άλλαζε ενεργό φύλλο σε ταυτότητα που δεν υπάρχει. Ίδιο ακριβώς σκεπτικό με το γιατί η γωνία
 * «επιλογή όλων» δεν έγινε `{ axis: 'corner' }` (ADR-739 §43).
 */
export type TableWorksheetStripHit =
  | { readonly kind: 'tab'; readonly tab: TableWorksheetTabSlot }
  | { readonly kind: 'add' };

/**
 * Το σημείο πλαισίου → καρτέλα ή ⊕· `null` παντού αλλού.
 *
 * 🔴 Η **γνήσια** ανισότητα κοιτά προς το πλέγμα (`v > y`), όπως ακριβώς στον δείκτη: η
 * λωρίδα του κενού ανήκει στις **λαβές**, και η οπή τους είναι **κλειστός** δίσκος
 * (`distance <= tolerance`). Με `≥` και στις δύο πλευρές, το ένα pixel της ακμής θα
 * απαντούσε «ναι» σε αμφότερα — ακριβώς το σφάλμα που το κενό ήρθε να σβήσει (§27.11).
 *
 * ⚠️ Η **σειρά** (καρτέλες, μετά ⊕) δεν λύνει διεκδίκηση: τα ορθογώνια είναι **ξένα εξ
 * ορισμού** — το ⊕ ξεκινά ακριβώς εκεί που τελειώνει η τελευταία καρτέλα, από την ίδια
 * αριθμητική που τα παρήγαγε. Γράφεται σταθερή ώστε να μην εξαρτάται από αυτή την απόδειξη.
 *
 * Γραμμική σάρωση: το πλήθος είναι φραγμένο από τη **χωρητικότητα**, δηλαδή δεκάδες στη
 * χειρότερη περίπτωση, και τρέχει μία φορά ανά κίνηση ποντικιού.
 */
export function tableWorksheetStripAtFrame(
  strip: TableWorksheetStrip,
  frame: TableFramePoint,
): TableWorksheetStripHit | null {
  for (const tab of strip.tabs) {
    if (isInsideStripRect(tab.rectMm, frame)) return { kind: 'tab', tab };
  }
  if (strip.add && isInsideStripRect(strip.add, frame)) return { kind: 'add' };
  return null;
}

/** Η **μία** έκφραση του «μέσα στη λωρίδα», κοινή για καρτέλα και ⊕ — δες την ανισότητα πάνω. */
function isInsideStripRect(rectMm: TableRectMm, frame: TableFramePoint): boolean {
  return (
    frame.v > rectMm.y &&
    frame.v <= rectMm.y + rectMm.h &&
    frame.u >= rectMm.x &&
    frame.u <= rectMm.x + rectMm.w
  );
}
