/**
 * 🔴 **Η ΜΙΑ ΔΙΑΤΑΞΗ ΤΗΣ ΛΩΡΙΔΑΣ** — κενή λωρίδα όταν δεν υπάρχει τίποτα να δείξει.
 *
 * ## Γιατί ΜΙΑ συνάρτηση και όχι «γεωμετρία + hit-test» χωριστά
 * Ο ζωγράφος και το πάτημα καταναλώνουν **το ίδιο αντικείμενο**, όχι δύο κλήσεις που τυχαίνει
 * να συμφωνούν. Το hit-test ({@link tableWorksheetStripAtFrame}) είναι σάρωση **πάνω σε αυτό
 * εδώ** — άρα «ό,τι πατιέται είναι ό,τι φαίνεται» δεν είναι σύμβαση που κάποιος μπορεί να
 * ξεχάσει, είναι **αδύνατο να παραβιαστεί**. Ο δείκτης ζωνών το πετυχαίνει με **δύο**
 * συναρτήσεις που μοιράζονται σταθερές· εδώ, επειδή η διάταξη έχει **παράθυρο** και **κουμπί**
 * (δηλαδή δύο αποφάσεις, όχι μόνο αριθμητική), η κοινή δομή είναι η μόνη ασφαλής τομή.
 *
 * Οι τρεις πύλες, με αυτή τη σειρά:
 *  1. **LOD του πίνακα** — η **ίδια** έκφραση με τον δείκτη (`isTableIndicatorVisible`): ένας
 *     πίνακας πολύ μικρός για να φορέσει ζώνες είναι πολύ μικρός και για καρτέλες, και δύο
 *     κατώφλια θα σήμαιναν κατάσταση όπου φαίνεται το ένα χρώμιο και όχι το άλλο·
 *  2. **χωρητικότητα** — δεν χωρά ούτε μία καρτέλα ⇒ **τίποτα**. «Φαίνεται αλλά δεν πιάνεται»
 *     (ή το αντίστροφο) είναι ψέμα της οθόνης· εδώ όλα πεθαίνουν μαζί, γιατί όλα ρωτούν
 *     **αυτή** τη συνάρτηση·
 *  3. **πλήθος** — δες {@link MIN_TABLE_WORKSHEET_TAB_COUNT}: ρωτιέται **μόνο** όταν δεν χωρά
 *     το ⊕, γιατί μόνο τότε μπορεί η λωρίδα να μείνει χωρίς δουλειά.
 */
export function tableWorksheetTabStrip(
  worksheets: readonly TableWorksheet[],
  activeWorksheetId: TableWorksheetId,
  widthMm: number,
  heightMm: number,
  pxPerMm: number,
): TableWorksheetStrip {
  if (!(pxPerMm > 0) || !Number.isFinite(pxPerMm)) return EMPTY_STRIP;
  if (!isTableIndicatorVisible(widthMm, heightMm, pxPerMm)) return EMPTY_STRIP;

  const { tabSeats, hasAdd } = tableWorksheetStripSeats(widthMm, pxPerMm);
  // Δες το {@link MIN_TABLE_WORKSHEET_TAB_COUNT}: με το ⊕ παρόν η λωρίδα δρα πάντα, οπότε ο
  // αριθμός δεν ρωτιέται· χωρίς αυτό, δρα μόνο αν υπάρχει **άλλο** φύλλο να διαλέξεις.
  if (!hasAdd && worksheets.length < MIN_TABLE_WORKSHEET_TAB_COUNT) return EMPTY_STRIP;

  // Ο ενεργός δείκτης πέφτει στο **πρώτο** φύλλο όταν το `activeWorksheetId` δεν δείχνει
  // πουθενά — η **ίδια** ρητή ανοχή που κάνει το `activeWorksheet`, και για τον ίδιο λόγο:
  // μια αναφορά σε διαγραμμένο φύλλο είναι φυσιολογικό ενδιάμεσο στάδιο (undo, χειροποίητο
  // JSON). Δύο διαφορετικές ανοχές θα σήμαιναν λωρίδα που φωτίζει άλλο φύλλο από αυτό που
  // ζωγραφίζει ο πίνακας.
  const found = worksheets.findIndex((sheet) => sheet.id === activeWorksheetId);
  const activeIndex = found >= 0 ? found : 0;
  // ⚠️ Καμία πύλη «μηδενικό παράθυρο» εδώ: με `length === 0` ο βρόχος **δεν τρέχει** και η
  // απάντηση είναι ήδη κενή. Μια ρητή `if (view.length <= 0) return []` γράφτηκε, **μετρήθηκε
  // νεκρή με μετάλλαξη** (η αφαίρεσή της άφησε 24/24 πράσινα) και αφαιρέθηκε: ένας φύλακας που
  // δεν μπορεί να κοκκινίσει είναι σχόλιο μεταμφιεσμένο σε κώδικα.
  const view = tableWorksheetTabWindow(worksheets.length, activeIndex, tabSeats);

  const tabs = tableWorksheetTabsMm(pxPerMm);
  // 🔴 ADR-833 §5.4.11 #3 — **Η ΑΓΚΥΡΑ, ΜΙΑ ΦΟΡΑ ΓΙΑ ΟΛΗ ΤΗ ΛΩΡΙΔΑ.**
  //
  // Το `heightMm` **δεν** συμμετέχει, και αυτό είναι όλο το νόημα: κρεμασμένη από την κάτω
  // ακμή, η λωρίδα έφευγε κάτω από το χέρι μόλις άλλαζε το ενεργό φύλλο (δες την κεφαλίδα).
  // Η πάνω ακμή είναι αμετάβλητη **δομικά** — η αρχή του πλαισίου είναι εκεί.
  //
  // ⚠️ Παράγεται από το {@link tableWorksheetStripOuterPx}, ποτέ ως δεύτερη αριθμητική: η
  // δήλωση που διαβάζει η γραμμή τύπων και η θέση που ζωγραφίζεται **πρέπει** να είναι η ίδια
  // ποσότητα, αλλιώς είναι το §27.13 ξανά («δύο λεξιλόγια της ίδιας ποσότητας»).
  const stripTopMm = -tableWorksheetStripOuterPx() / pxPerMm;
  const slots: TableWorksheetTabSlot[] = [];
  for (let seat = 0; seat < view.length; seat++) {
    const index = view.start + seat;
    const sheet = worksheets[index];
    slots.push({
      index,
      id: sheet.id,
      sheet,
      active: index === activeIndex,
      rectMm: {
        x: seat * tabs.tabWidthMm,
        y: stripTopMm,
        w: tabs.tabWidthMm,
        h: tabs.tabHeightMm,
      },
    });
  }

  return {
    tabs: slots,
    // 🔑 **Αμέσως μετά την τελευταία ΟΡΑΤΗ καρτέλα**, ποτέ καρφωμένο στη δεξιά ακμή: το Sheets
    // το κάνει έτσι, και ο λόγος είναι λειτουργικός — το κουμπί ταξιδεύει με το τέλος του
    // βιβλίου, δηλαδή δηλώνει «εδώ προστίθεται το επόμενο». Καρφωμένο δεξιά, θα υποσχόταν
    // εισαγωγή σε θέση που η πράξη δεν χρησιμοποιεί ποτέ.
    add: hasAdd
      ? {
          x: view.length * tabs.tabWidthMm,
          y: stripTopMm,
          w: TABLE_WORKSHEET_ADD_WIDTH_PX / pxPerMm,
          h: tabs.tabHeightMm,
        }
      : null,
  };
}

/**
 * 🔴 **ADR-833 Φάση 4 — ΤΙ ΒΡΙΣΚΕΤΑΙ ΚΑΤΩ ΑΠΟ ΤΟ ΣΗΜΕΙΟ**, μέσα στη λωρίδα.
 *
 * Διακριτή ένωση και όχι «καρτέλα ή `null`»: το ⊕ **δεν είναι φύλλο** — δεν έχει ταυτότητα,
 * δεν έχει θέση στο βιβλίο, δεν έχει όνομα. Ένα προσποιητό `TableWorksheetTabSlot` γι' αυτό θα
 * απαιτούσε ψεύτικες τιμές σε τρία πεδία, και το πρώτο σημείο που θα τις διάβαζε αφελώς θα
 * άλλαζε ενεργό φύλλο σε ταυτότητα που δεν υπάρχει. Ίδιο ακριβώς σκεπτικό με το γιατί η γωνία
 * «επιλογή όλων» δεν έγινε `{ axis: 'corner' }` (ADR-739 §43).
 */
export type TableWorksheetStripHit =
  | { readonly kind: 'tab'; readonly tab: TableWorksheetTabSlot }
  | { readonly kind: 'add' };

/**
 * Το σημείο πλαισίου → καρτέλα ή ⊕· `null` παντού αλλού.
 *
 * 🔴 Η ασυμμετρία (`v > y` γνήσια, `v <= y + h` κλειστή) **έμεινε ακριβώς όπως ήταν** όταν η
 * λωρίδα μετακόμισε στην πάνω ακμή (ADR-833 §5.4.11 #3) — και αυτό είναι **απόφαση, όχι
 * παράλειψη**. Γράφτηκε για τη γειτονιά της κάτω ακμής, όπου το ένα pixel ανάμεσα στη λωρίδα
 * και στις **λαβές** έπρεπε να ανήκει στις λαβές (κλειστός δίσκος, §27.11). Στη νέα θέση δεν
 * υπάρχει **κανένας** διεκδικητής σε καμία από τις δύο πλευρές: προς το πλέγμα μεσολαβεί
 * ολόκληρο το κενό (`gapMm`) και μετά ο δίσκος του ⊕· προς τα έξω κάθεται η γραμμή τύπων, που
 * είναι επικάλυψη DOM και δεν περνά ποτέ από αυτό το hit-test.
 *
 * 🔑 Άρα η αλλαγή της θα ήταν **ρίσκο χωρίς κέρδος**: καμία συμπεριφορά δεν εξαρτάται από την
 * κατεύθυνσή της σήμερα, αλλά κάθε σημείο εξακολουθεί να ανήκει το πολύ σε **ένα** ορθογώνιο —
 * που είναι η μόνη ιδιότητα που το hit-test χρειάζεται.
 *
 * ⚠️ Η **σειρά** (καρτέλες, μετά ⊕) δεν λύνει διεκδίκηση: τα ορθογώνια είναι **ξένα εξ
 * ορισμού** — το ⊕ ξεκινά ακριβώς εκεί που τελειώνει η τελευταία καρτέλα, από την ίδια
 * αριθμητική που τα παρήγαγε. Γράφεται σταθερή ώστε να μην εξαρτάται από αυτή την απόδειξη.
 *
 * Γραμμική σάρωση: το πλήθος είναι φραγμένο από τη **χωρητικότητα**, δηλαδή δεκάδες στη
 * χειρότερη περίπτωση, και τρέχει μία φορά ανά κίνηση ποντικιού.
 */
export function tableWorksheetStripAtFrame(
  strip: TableWorksheetStrip,
  frame: TableFramePoint,
): TableWorksheetStripHit | null {
  for (const tab of strip.tabs) {
    if (isInsideStripRect(tab.rectMm, frame)) return { kind: 'tab', tab };
  }
  if (strip.add && isInsideStripRect(strip.add, frame)) return { kind: 'add' };
  return null;
}

/** Η **μία** έκφραση του «μέσα στη λωρίδα», κοινή για καρτέλα και ⊕ — δες την ανισότητα πάνω. */
function isInsideStripRect(rectMm: TableRectMm, frame: TableFramePoint): boolean {
  return (
    frame.v > rectMm.y &&
    frame.v <= rectMm.y + rectMm.h &&
    frame.u >= rectMm.x &&
    frame.u <= rectMm.x + rectMm.w
  );
}
