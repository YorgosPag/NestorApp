/**
 * 🔴 ADR-754 **Γ4** — **Η ΛΑΒΗ ΣΥΜΠΛΗΡΩΣΗΣ**: πού κάθεται, πότε πιάνεται, και **ποια περιοχή**
 * υπόσχεται η σύρση. Καθαρή γεωμετρία — μηδέν DOM, μηδέν store, μηδέν React.
 *
 * Το μικρό τετράγωνο στην **κάτω δεξιά γωνία** της επιλογής. Το πιάνεις, το σέρνεις, και ό,τι
 * υπάρχει στην επιλογή αντιγράφεται στα κελιά που διέσχισες — με τους τύπους να **ολισθαίνουν**
 * (`table-formula-offset.ts`) και τα `$` να μένουν.
 *
 * ## 🔴 ΕΝΑΣ ΑΞΟΝΑΣ, ΠΟΤΕ ΔΥΟ — και δεν είναι απλοποίηση
 * Στο Excel η σύρση της λαβής κλειδώνει σε **έναν** άξονα: τραβάς κάτω ⇒ γεμίζουν γραμμές,
 * τραβάς δεξιά ⇒ γεμίζουν στήλες. Διαγώνια σύρση **δεν** γεμίζει ορθογώνιο· διαλέγει τον άξονα
 * με τη μεγαλύτερη μετατόπιση.
 *
 * Ο λόγος είναι σημασιολογικός, όχι τεχνικός: η συμπλήρωση απαντά «**επανάλαβε αυτό το μοτίβο
 * προς τα εκεί**», και ένα μοτίβο έχει **κατεύθυνση**. Ένα διαγώνιο γέμισμα θα έπρεπε να
 * αποφασίσει αν το `=B2*C2` της γωνίας ολισθαίνει κατά γραμμή, κατά στήλη ή και τα δύο — τρεις
 * διαφορετικοί αριθμοί, καμία ένδειξη ποιον ήθελε ο χρήστης. Η επιλογή άξονα **είναι** η
 * απάντηση, και τη δίνει το χέρι του.
 *
 * ## Γιατί το μέγεθος είναι σε **px οθόνης**
 * Είναι στοιχείο **διεπαφής**, όχι γεωμετρία σχεδίου — ίδιο επιχείρημα με τις λαβές, τις ζώνες
 * του δείκτη και το ⊕ της εισαγωγής (ADR-739 §40): σε sheet-mm θα γινόταν αόρατο σε zoom-out
 * και τεράστιο σε zoom-in.
 *
 * @module subapps/dxf-viewer/bim/table/table-fill-handle
 * @see bim/table/table-fill-apply.ts — τι ΓΙΝΕΤΑΙ το μοντέλο όταν αφεθεί η λαβή
 * @see bim/table/table-cell-range.ts — ο ΕΝΑΣ ορισμός του «ορθογώνιο κελιών»
 * @see bim/table/table-indicator-cursor-role.ts — ο **11ος ρόλος** δείκτη, που ρωτά από εδώ
 * @see docs/centralized-systems/reference/adrs/ADR-754-table-point-mode.md §13, §14
 */

import type { TableCellRangeBounds, TableCellRef } from './table-cell-range';
import { rawTableCellRangeBounds, tableRangeRectMm } from './table-cell-range';
import type { TableLayout, TableRectMm } from './table-layout-types';
import type { TableModel } from '../../types/table';
import type { TableFramePoint } from '../../types/table-entity';

/**
 * Η **πλευρά** του τετραγώνου σε px οθόνης.
 *
 * Έξι px δίνουν στόχο 6×6 — ακριβώς όσο του Excel, και μικρότερο από κάθε λαβή του σχεδίου
 * επίτηδες: η λαβή συμπλήρωσης κάθεται **μέσα** στον πίνακα, όπου ο χρήστης δουλεύει, και ένα
 * μεγαλύτερο τετράγωνο θα σκέπαζε κείμενο κελιού.
 */
export const TABLE_FILL_HANDLE_PX = 6;

/**
 * 🔴 **ADR-754 §13.8 — Η ΟΠΗ ΜΕΓΑΛΩΝΕΙ ΜΟΝΟ ΠΡΟΣ ΤΑ ΕΞΩ.** Πόσο πιο γενναιόδωρη είναι η
 * **σύλληψη** από τη ζωγραφιά, **προς τα κάτω-δεξιά** — και μόνο εκεί.
 *
 * Ο λόγος που υπάρχει οπή είναι το WCAG 2.2 SC 2.5.8: ένας στόχος 6 px είναι κάτω από κάθε
 * κατώφλι, και η λύση **δεν** είναι να μεγαλώσει το τετράγωνο (θα έκρυβε κείμενο κελιού) αλλά
 * να μεγαλώσει η **οπή** — ίδια διάκριση «φαίνεται μικρό, πιάνεται εύκολα» που κάνουν ήδη οι
 * λαβές του σχεδίου με το `gripAperturePx` και το ⊕ της εισαγωγής με τις δύο φάσεις του.
 *
 * ## 🔴 ΓΙΑΤΙ ΟΝΟΜΑΖΕΤΑΙ `OUTWARD` — ΕΔΩ ΗΤΑΝ ΤΟ ΕΛΑΤΤΩΜΑ ΠΟΥ ΒΡΗΚΕ Η ΟΘΟΝΗ
 * Έγραφε `TABLE_FILL_HANDLE_APERTURE_PX` και η {@link isOnTableFillHandle} τη διάστελλε
 * **ομοιόμορφα** και στις τέσσερις κατευθύνσεις. Επειδή όμως η ζωγραφιά είναι **κεντραρισμένη**
 * στην κορυφή, η ομοιόμορφη οπή έφτιαχνε στόχο **14×14 px συμμετρικά γύρω από τη γωνία**: τα
 * **7 px προς τα μέσα** έπεφταν πάνω στη ζώνη του `isOnTableRangeBorder` (ADR-739 §36), δηλαδή
 * ακριβώς εκεί που ο χρήστης σημαδεύει για να **μετακινήσει** την περιοχή. Ο ιδιοκτήτης το
 * μέτρησε στην οθόνη: «*το fill handle συγκρούεται με τον σταυρό με τα βελάκια*» (04/08).
 *
 * 🔑 **Το λάθος ήταν το ΣΧΗΜΑ, όχι η σειρά.** Η προτεραιότητα `fill` πριν από `range-move`
 * (§14.4) είναι **σωστή** και δεν αντιστρέφεται: αντιγράφει τη σειρά του πατήματος, και χωρίς
 * αυτήν η γωνία θα έδειχνε `move` ενώ το κλικ θα έκανε **fill** — ο δείκτης θα ψευδόταν (§31).
 * Η θεραπεία είναι να πάψει η ζώνη να **διεκδικεί** pixel που δεν της ανήκουν.
 *
 * ## 🔴 Η ΕΡΕΥΝΑ: ΤΟ EXCEL ΔΕΝ ΛΥΝΕΙ ΑΥΤΟ ΤΟ PIXEL — ΤΟ ΕΧΕΙ **ΔΥΟ ΦΟΡΕΣ** ΣΠΑΣΜΕΝΟ
 * Δύο κλειδωμένα νήματα της Microsoft, **ίδια γωνία, αντίθετα συμπτώματα**:
 * 1. *«The cell border in Excel 365 is exceedingly thin; it is almost impossible to change the
 *    pointer to the move pointer»* — 30+ προσπάθειες για **ένα** κελί (ήδη καταγεγραμμένο στο
 *    `table-range-move-zone`, γι' αυτό η ζώνη μας είναι 9 px και όχι 1).
 * 2. *«Fill Handle too Hard to Grab»*: «*It is like there is only one pixel where the mouse
 *    needs to be… can't be off by one pixel*». Απάντηση Microsoft: «*it seems excel design
 *    limitation*» — **κανένα fix**, μόνο παρακάμψεις.
 *
 * Δηλαδή το Excel «λύνει» τη σύγκρουση κάνοντας **και τους δύο** στόχους τόσο λεπτούς ώστε να
 * μη συναντιούνται — και το τίμημα είναι ότι δεν πιάνεται **κανένας**. Parity εδώ θα αντέγραφε
 * **δύο** ελαττώματα. Το ίδιο ισχύει για κάθε άλλο πλέγμα που εξετάστηκε: στο **Handsontable**
 * η λαβή είναι ένα `<div>` πλάτους `--ht-cell-autofill-size`, κεντραρισμένο με
 * `cornerCenterPointOffset = -ceil(width/2)`, και η ζώνη σύλληψης **είναι το ίδιο το div** —
 * μηδέν οπή· στο **ag-Grid** ομοίως. **Κανένα** από αυτά δεν έχει ζώνη μετακίνησης στο
 * περίγραμμα, οπότε κανένα δεν πλήρωσε ποτέ αυτή τη σύγκρουση.
 *
 * ## 🔑 Η ΛΥΣΗ ΕΙΝΑΙ ΑΠΟ ΤΟ **Figma**, ΟΧΙ ΑΠΟ ΤΑ ΦΥΛΛΑ ΥΠΟΛΟΓΙΣΜΟΥ
 * Στα εργαλεία σχεδίασης η ίδια γωνία φιλοξενεί **δύο** χειριστήρια (κλίμακα και περιστροφή)
 * και ο διαχωρισμός είναι **αυστηρά χωρικός, χωρίς επικάλυψη**: πάνω στη λαβή ⇒ κλίμακα, **λίγο
 * πιο έξω** ⇒ περιστροφή. Το χειριστήριο που ήρθε δεύτερο **δεν** κλέβει ποτέ pixel από το
 * πρώτο — μεγαλώνει μόνο προς το **κενό**.
 *
 * Εδώ εφαρμόζεται αυτούσιο, με δύο κανόνες που δεν διαπραγματεύονται:
 * - **Προς τα μέσα: μηδέν οπή.** Πιάνεται **ακριβώς όσο βάφεται** — ό,τι βλέπεις μαύρο είναι
 *   λαβή, ό,τι βλέπεις γραμμή επιλογής είναι μετακίνηση. Είναι και η συμπεριφορά **όλης** της
 *   αγοράς (Handsontable / ag-Grid: η ζώνη **είναι** η ζωγραφιά), απλώς εφαρμοσμένη μόνο εκεί
 *   που κοστίζει.
 * - **Προς τα έξω: πλήρης οπή.** Εκεί δείχνει και η ίδια η πράξη («γέμισε προς τα εκεί»), και
 *   εκεί είμαστε **καλύτεροι** από τους μεγάλους: αυτοί δίνουν 0 px ανοχής και το πληρώνουν με
 *   το τεκμηριωμένο «*too hard to grab*».
 *
 * 🔑 **ΤΟ ΦΡΑΓΜΑ ΠΟΥ ΚΑΝΕΙ ΤΟΝ ΑΡΙΘΜΟ ΣΩΣΤΟ, ΚΑΙ ΟΧΙ ΓΟΥΣΤΟ**: η εξωτερική εμβέλεια της λαβής
 * είναι `TABLE_FILL_HANDLE_PX / 2 + αυτό` = **7 px**, και οφείλει να μένει **≤** την οπή του
 * περιγράμματος (`TABLE_INDICATOR_GRIP_CLEARANCE_PX` = **9 px**). Έτσι η λαβή δεν φτάνει ποτέ
 * πέρα από τη ζώνη μετακίνησης, δηλαδή **δεν αγγίζει ποτέ το σώμα του γειτονικού κελιού** —
 * που είναι ο τρόπος με τον οποίο επιλέγεται εκείνο (§36). Η ανισότητα είναι κλειδωμένη με test
 * και **δεν** επιβάλλεται εδώ με `import`: η οπή του περιγράμματος φτάνει στους καλούντες ως
 * `bands.gapMm`, δηλαδή τιμή που αυτή η καθαρή γεωμετρία **δεν** παραλαμβάνει — ένα runtime
 * clamp θα εξαρτούσε τη ζώνη από αριθμό που δεν της δόθηκε ποτέ.
 */
export const TABLE_FILL_HANDLE_OUTWARD_APERTURE_PX = 4;

/** Ποιον άξονα διάλεξε το χέρι, και προς τα πού. */
export type TableFillDirection = 'down' | 'up' | 'right' | 'left';

/** Τι υπόσχεται η σύρση: ποια κελιά θα γεμίσουν, και από ποια κατεύθυνση. */
export interface TableFillTarget {
  /** **Μόνο τα νέα** κελιά — η πηγή δεν περιλαμβάνεται ποτέ. */
  readonly bounds: TableCellRangeBounds;
  readonly direction: TableFillDirection;
}

/**
 * Το τετράγωνο της λαβής σε **sheet-mm του πλαισίου**, ή `null` όταν η περιοχή δεν τέμνει τη
 * διάταξη.
 *
 * Κάθεται **κεντραρισμένο** στην κάτω-δεξιά κορυφή της περιοχής, δηλαδή μισό μέσα και μισό
 * έξω. Είναι η θέση του Excel και είναι και η μόνη που δεν λέει ψέματα: η λαβή ανήκει
 * ταυτόχρονα στο τελευταίο κελί (από εκεί ξεκινά το μοτίβο) και στο κενό δίπλα του (προς τα
 * εκεί πάει).
 */
export function tableFillHandleRectMm(
  layout: TableLayout,
  bounds: TableCellRangeBounds,
  pxPerMm: number,
): TableRectMm | null {
  const rect = tableRangeRectMm(layout, bounds);
  if (!rect || pxPerMm <= 0) return null;
  const sideMm = TABLE_FILL_HANDLE_PX / pxPerMm;
  return {
    x: rect.x + rect.w - sideMm / 2,
    y: rect.y + rect.h - sideMm / 2,
    w: sideMm,
    h: sideMm,
  };
}

/**
 * 🔴 **ADR-754 §13.8 — ΕΙΝΑΙ ΤΟ ΣΗΜΕΙΟ ΠΑΝΩ ΣΤΗ ΛΑΒΗ;** Η **ΜΙΑ** συνάρτηση που ορίζει το σχήμα
 * της ζώνης, για τους **τρεις** που ρωτούν (δείκτης, πάτημα, και έμμεσα ο ζωγράφος μέσω του
 * κοινού ορθογωνίου).
 *
 * ## 🔴 Η ΖΩΝΗ ΕΙΝΑΙ **ΑΣΥΜΜΕΤΡΗ**, ΚΑΙ Η ΑΣΥΜΜΕΤΡΙΑ ΕΙΝΑΙ ΟΛΟΚΛΗΡΗ Η ΔΙΟΡΘΩΣΗ
 * - **Προς τα πάνω-αριστερά** (μέσα στην επιλογή): το όριο είναι το `rect` **αυτούσιο** —
 *   δηλαδή η ζωγραφιά, ούτε ένα pixel παραπάνω. Εκεί ζει η ζώνη μετακίνησης του ADR-739 §36
 *   και της ανήκει ολόκληρη.
 * - **Προς τα κάτω-δεξιά** (έξω, όπου δείχνει η ίδια η πράξη): το `rect` **συν** την οπή.
 *
 * Δες {@link TABLE_FILL_HANDLE_OUTWARD_APERTURE_PX} για την έρευνα, το φράγμα των 7 ≤ 9 px και
 * τον λόγο που το Excel **δεν** είναι εδώ οδηγός.
 *
 * ⚠️ Ο έλεγχος γράφεται με τις **ακμές** του `rect` και όχι με το κέντρο της γωνίας, ώστε να
 * μείνει μία και μόνη διατύπωση του «πού κάθεται η λαβή» — εκείνη ζει στην
 * {@link tableFillHandleRectMm}. Μια δεύτερη έκφραση `rect.x + rect.w / 2` εδώ θα ήταν δεύτερη
 * απάντηση στο ίδιο ερώτημα, και θα ξέμενε την ημέρα που αλλάξει το κεντράρισμα.
 */
export function isOnTableFillHandle(
  point: { readonly u: number; readonly v: number },
  rect: TableRectMm,
  pxPerMm: number,
): boolean {
  if (pxPerMm <= 0) return false;
  const outwardMm = TABLE_FILL_HANDLE_OUTWARD_APERTURE_PX / pxPerMm;
  return (
    point.u >= rect.x &&
    point.u <= rect.x + rect.w + outwardMm &&
    point.v >= rect.y &&
    point.v <= rect.y + rect.h + outwardMm
  );
}

/**
 * 🔑 **Η ΜΙΑ ΑΠΑΝΤΗΣΗ «ποια περιοχή έχει λαβή»**: η επιλογή· χωρίς επιλογή —ή με **μπαγιάτικη**
 * επιλογή— το ενεργό κελί. `null` μόνο όταν το ίδιο το ενεργό κελί δεν υπάρχει πια στο μοντέλο.
 *
 * ## 🔴 Γιατί βγήκε εδώ: ΤΡΕΙΣ ρωτούσαν, ΔΥΟ απαντούσαν — και διαφορετικά
 * Ο ζωγράφος (`stampTableFillHandleOverlay`) και ο φρουρός του πατήματος
 * (`tryTableFillHandleMouseDown`) έγραφαν ο καθένας τη δική του εκδοχή της ίδιας πρότασης, και
 * ο **δείκτης** θα ήταν ο τρίτος. Δύο αντίγραφα των έξι tokens «`selection ?? ενεργό κελί`»
 * **δεν** πιάνονται από το jscpd (κάτω από τα 50 tokens του `.jscpdrc.json`) — ακριβώς το σχήμα
 * που περιγράφει το §15 του ADR-754 για το `cellPairIndices`.
 *
 * ⚠️ **Και είχαν ήδη αποκλίνει.** Ο ζωγράφος έγραφε `selectionBounds ?? ενεργό κελί`, ο φρουρός
 * `if (selection) return resolveTableSelectionBounds(...)` — δηλαδή με **μπαγιάτικη** επιλογή
 * (undo / διαγραμμένη γραμμή) ο ένας ζωγράφιζε λαβή στο ενεργό κελί και ο άλλος **αρνιόταν να
 * την πιάσει**: «λαβή που φαίνεται αλλά δεν πιάνεται», η ακριβής αστοχία που το §13.5
 * απαγορεύει ονομαστικά. Νικά η εκδοχή του ζωγράφου — μια επιλογή που δεν λύνεται **είναι**
 * καμία επιλογή, ενώ το ενεργό κελί είναι πάντα υπαρκτό.
 *
 * Τα όρια της επιλογής ζητούνται **ήδη λυμένα** και δεν λύνονται εδώ: ο ζωγράφος τα έχει
 * υπολογίσει για το περίγραμμα του **ίδιου καρέ**, και ένας δεύτερος υπολογισμός θα ήταν
 * δεύτερη απάντηση στο «τι μάρκαρε ο χρήστης» — δηλαδή λαβή που κάθεται αλλού από το
 * περίγραμμα που υποτίθεται ότι συνοδεύει.
 */
export function tableFillSourceBounds(
  model: TableModel,
  active: TableCellRef,
  selectionBounds: TableCellRangeBounds | null,
): TableCellRangeBounds | null {
  return selectionBounds ?? rawTableCellRangeBounds(model, active, active);
}

/** Τι βρήκε η σάρωση πάνω στη λαβή· `null` παντού αλλού. */
export interface TableFillHandleHit {
  /** Το τετράγωνο που βρέθηκε — ο καλών δεν το ξαναϋπολογίζει για να το ζωγραφίσει. */
  readonly rectMm: TableRectMm;
}

/**
 * 🔴 **ΕΠΕΣΕ ΤΟ ΧΕΡΙ ΠΑΝΩ ΣΤΗ ΛΑΒΗ;** — ο **ΕΝΑΣ** δρόμος, για τον δείκτη και για το πάτημα.
 *
 * Ίδιο σχήμα με το `tableInsertControlAtFrame` (⊕) και το `tableDeleteControlAtFrame` (⊖): μια
 * σάρωση απαντά, και η **ίδια** απάντηση ταξιδεύει σε όποιον τη χρειάζεται. Ο λόγος είναι ο
 * ρητός κανόνας του ADR-739 §31 — *ο δείκτης δεν ψεύδεται*: αν ο δείκτης ρωτούσε δική του
 * γεωμετρία, θα υπήρχε ζώνη όπου το βέλος υπόσχεται συμπλήρωση και το πάτημα δεν πιάνει τίποτα.
 *
 * `source === null` ⇒ **καμία λαβή**. Είναι η γραμμή που κωδικοποιεί το «η λαβή σιωπά σε γραφή»
 * (§13.5): ο καλών δίνει `null` όσο ο χρήστης πληκτρολογεί, και δεν χρειάζεται δεύτερος έλεγχος
 * κατάστασης μέσα σε καθαρή γεωμετρία.
 */
export function tableFillHandleHitAtFrame(
  layout: TableLayout,
  frame: TableFramePoint,
  pxPerMm: number,
  source: TableCellRangeBounds | null,
): TableFillHandleHit | null {
  if (!source) return null;
  const rectMm = tableFillHandleRectMm(layout, source, pxPerMm);
  if (!rectMm || !isOnTableFillHandle(frame, rectMm, pxPerMm)) return null;
  return { rectMm };
}

/**
 * 🔑 **Ποια κελιά υπόσχεται η σύρση**, δεδομένου του κελιού κάτω από το χέρι.
 *
 * `null` όταν το χέρι είναι ακόμη **μέσα** στην πηγή: εκεί δεν υπάρχει τίποτα να γεμίσει, και
 * η σιωπή είναι η σωστή απάντηση — όχι «γέμισε την ίδια σου την επιλογή».
 *
 * ## Ο άξονας διαλέγεται από τη **μεγαλύτερη** υπέρβαση
 * Το χέρι σπάνια κινείται σε τέλεια ευθεία. Μετριέται πόσο βγήκε έξω από την πηγή σε κάθε
 * άξονα και κερδίζει ο μεγαλύτερος· στην **ισοπαλία** κερδίζει ο κατακόρυφος, γιατί η
 * συμπλήρωση προς τα κάτω είναι ασύγκριτα συχνότερη σε πίνακα ποσοτήτων (μια στήλη τιμών ανά
 * γραμμή εργασίας) και μια διαγώνια κίνηση 1×1 πιο πιθανά εννοεί «κάτω».
 */
export function resolveTableFillTarget(
  source: TableCellRangeBounds,
  at: { readonly row: number; readonly col: number },
): TableFillTarget | null {
  const rowOver = overshoot(at.row, source.firstRow, source.lastRow);
  const colOver = overshoot(at.col, source.firstCol, source.lastCol);
  if (rowOver === 0 && colOver === 0) return null;

  if (Math.abs(rowOver) >= Math.abs(colOver)) {
    return rowOver > 0
      ? { direction: 'down', bounds: { ...source, firstRow: source.lastRow + 1, lastRow: at.row } }
      : { direction: 'up', bounds: { ...source, firstRow: at.row, lastRow: source.firstRow - 1 } };
  }
  return colOver > 0
    ? { direction: 'right', bounds: { ...source, firstCol: source.lastCol + 1, lastCol: at.col } }
    : { direction: 'left', bounds: { ...source, firstCol: at.col, lastCol: source.lastCol - 1 } };
}

/** Πόσο βγήκε ο δείκτης έξω από το κλειστό διάστημα — `0` όσο είναι μέσα. */
function overshoot(value: number, first: number, last: number): number {
  if (value > last) return value - last;
  if (value < first) return value - first;
  return 0;
}

/**
 * Η **ένωση** πηγής και στόχου — το ορθογώνιο που δείχνει η προεπισκόπηση όσο σέρνεις.
 *
 * Υπάρχει ως συνάρτηση αντί για δύο `Math.min/max` στον καλούντα γιατί το ρωτούν **δύο**: ο
 * ζωγράφος της προεπισκόπησης και η επιλογή που μένει πίσω μετά το γέμισμα (Excel: μετά τη
 * συμπλήρωση είναι μαρκαρισμένη **ολόκληρη** η περιοχή, πηγή και γέμισμα μαζί).
 */
export function tableFillPreviewBounds(
  source: TableCellRangeBounds,
  target: TableFillTarget,
): TableCellRangeBounds {
  return {
    firstRow: Math.min(source.firstRow, target.bounds.firstRow),
    lastRow: Math.max(source.lastRow, target.bounds.lastRow),
    firstCol: Math.min(source.firstCol, target.bounds.firstCol),
    lastCol: Math.max(source.lastCol, target.bounds.lastCol),
  };
}
