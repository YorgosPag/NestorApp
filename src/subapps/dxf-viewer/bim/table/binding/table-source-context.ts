/**
 * 🔴 ADR-767 §11.2 — **Η ΓΕΦΥΡΑ**: το μοναδικό ακάθαρτο σημείο ολόκληρης της οικογένειας δεσμού.
 *
 * ## Γιατί υπάρχει χωριστό αρχείο για τρεις γραμμές
 * Ο resolver, ο συγκριτής και ο φραγμός είναι **καθαροί** επίτηδες: δέχονται
 * {@link TableSourceContext} και δεν ξέρουν από πού ήρθε. Κάποιος όμως πρέπει να ρωτήσει τη
 * σκηνή — και αν αυτή η ερώτηση γραφτεί στα **τρία** σημεία εισόδου (ανανέωση · έλεγχος
 * φρεσκάδας · φραγμός εξαγωγής), τα τρία μπορούν κάποτε να ρωτήσουν **άλλη** επιφάνεια. Τότε
 * ο φραγμός θα έκρινε με δεδομένα που ο πίνακας δεν είδε ποτέ, και **κανένα test δεν θα
 * έπεφτε**: κάθε πλευρά θα ήταν εσωτερικά συνεπής.
 *
 * Ίδια αιτιολόγηση με το `table-axis-boundary.ts` (ADR-739 §8390): **εξήχθη πριν γραφτεί ο
 * δεύτερος καταναλωτής**, όχι μετά.
 *
 * ## ⛔ ΚΑΜΙΑ ΔΕΥΤΕΡΗ ΠΗΓΗ ΣΗΜΕΙΩΝ
 * Τα σημεία της αποτύπωσης έχουν **έναν** ιδιοκτήτη (`systems/topography/TopoPointStore`) και
 * έναν υπάρχοντα καταναλωτή που το κάνει ήδη έτσι
 * (`systems/topography/deliverables/useSurveyExport.ts`). Εδώ **καλείται**, δεν αντιγράφεται.
 *
 * ## 🔴 `undefined` ≠ `[]` — η διάκριση που ο τύπος κρατά και η γέφυρα ΔΕΝ ισοπεδώνει
 * Το σχήμα του {@link TableSourceContext} ξεχωρίζει δύο πράγματα που μοιάζουν:
 *
 * | τιμή | σημαίνει | συνέπεια |
 * |---|---|---|
 * | `undefined` | «**κανείς δεν ρώτησε** τη σκηνή» | `source-unavailable` ⇒ **μπλοκάρει** την εξαγωγή |
 * | `[]` | «η αποτύπωση **δεν έχει** σημεία» | έγκυρος **άδειος** πίνακας, όχι σφάλμα |
 *
 * Η γέφυρα **πάντα** ρωτά, άρα επιστρέφει πάντα πίνακα — ενδεχομένως κενό. Αν επέστρεφε
 * `undefined` σε κενή αποτύπωση, ο φραγμός θα κραύγαζε σε **κάθε καθαρό έργο** και ο χρήστης
 * θα μάθαινε να τον προσπερνά — η ίδια αστοχία με το «QA που κραυγάζει» (ADR-720 §3.3).
 *
 * @module subapps/dxf-viewer/bim/table/binding/table-source-context
 * @see bim/table/binding/table-source-resolver.ts — ο καθαρός καταναλωτής
 * @see docs/centralized-systems/reference/adrs/ADR-767-table-bound-mode.md §11.2
 */

import { getTopoPoints } from '../../../systems/topography/TopoPointStore';
import type { TableSourceContext } from './table-source-resolver';

/**
 * Συναρμολογεί το context από τη **ζωντανή** σκηνή, τη στιγμή της κλήσης.
 *
 * Getter και όχι στιγμιότυπο (ADR-040 κανόνας #2): και η ανανέωση και ο φραγμός τρέχουν σε
 * **συμβάν** (πάτημα κουμπιού, υποβολή εξαγωγής), άρα οφείλουν να δουν τη σκηνή **εκείνης**
 * της στιγμής — όχι όπως ήταν στο τελευταίο render του ξενιστή τους.
 *
 * ⚠️ **Καμία αντιγραφή.** Η αναφορά του store περνά αυτούσια: ένα `[...points]` θα ήταν νέος
 * πίνακας σε κάθε κλήση, δηλαδή θα ακύρωνε κάθε μελλοντικό memo που κρέμεται από την
 * ταυτότητα των σημείων — και δεν θα προστάτευε τίποτα, γιατί ο τύπος είναι ήδη `readonly`.
 */
export function readTableSourceContext(): TableSourceContext {
  return { topoPoints: getTopoPoints() };
}
