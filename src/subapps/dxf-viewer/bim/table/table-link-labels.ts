/**
 * 🔴 ADR-751 Φ8 — **πώς λέγεται ένας σύνδεσμος**, σε ένα σημείο.
 *
 * Ο χάρτης είδους→ενέργεια γεννήθηκε στη Φ7 μέσα στο `TableCellLinkTooltip`. Η Φ8 προσθέτει
 * **τρεις** ακόμη επιφάνειες που λένε το ίδιο πράγμα — μενού δεξιού κλικ, λίστα εντοπισμένων
 * συνδέσμων, Mirror DOM. Τέσσερα αντίγραφα ενός `Record` δεν φτάνουν το κατώφλι των 50 tokens
 * του jscpd (N.18), άρα είναι ακριβώς το είδος διπλότυπου που **καμία πύλη δεν βλέπει** και
 * που αποκλίνει σιωπηλά την ημέρα που θα προστεθεί τέταρτο είδος συνδέσμου.
 *
 * ## Γιατί κλειδιά και όχι έτοιμο κείμενο
 * Το ίδιο το κείμενο χρειάζεται `t()`, που ζει σε React context — ενώ ο Mirror DOM renderer
 * είναι **σκέτο DOM** (μοτίβο `entity-dom-proxy-renderer`, χωρίς React επίτηδες). Μοιράζοντας
 * το **κλειδί** αντί για τη συμβολοσειρά, κάθε επιφάνεια μεταφράζει με τον δικό της τρόπο και
 * καμία δεν χρειάζεται να κουβαλήσει React για να πει «Κλήση».
 *
 * ## Γιατί `Record<TextLinkKind, …>` και όχι `switch` με `default`
 * Ο χάρτης είναι **κλειστός σε τύπο**: αν κάποτε προστεθεί τέταρτο είδος στον ανιχνευτή, ο
 * μεταγλωττιστής θα το ζητήσει **εδώ** — σε ένα σημείο — αντί να το αφήσει να πέσει σιωπηλά
 * σε γενικό κείμενο σε τέσσερα.
 *
 * @module subapps/dxf-viewer/bim/table/table-link-labels
 * @see lib/validation/text-link-segments.ts — από πού έρχεται το `TextLinkKind`
 */

import type { TextLinkKind } from '@/lib/validation/text-link-segments';

/**
 * Είδος συνδέσμου → κλειδί i18n της **ενέργειας** («Αποστολή e-mail», όχι «E-mail»).
 *
 * Η επιλογή του ρήματος είναι απόφαση της Φ7 (§12.2) και ισχύει παντού: ο χρήστης μαθαίνει
 * **τι θα συμβεί** χωρίς να χρειαστεί να το δοκιμάσει. Ένα μενού που έγραφε «Άνοιγμα
 * υπερσυνδέσμου» — όπως το Excel — θα έλεγε λιγότερα από όσα ξέρουμε.
 */
export const LINK_ACTION_KEY: Readonly<Record<TextLinkKind, string>> = {
  email: 'tableCellLink.email',
  url: 'tableCellLink.url',
  phone: 'tableCellLink.phone',
};

/**
 * Είδος συνδέσμου → κλειδί i18n της εντολής **αντιγραφής**.
 *
 * ## Γιατί τρεις ετικέτες και όχι μία «Αντιγραφή διεύθυνσης»
 * Είναι η πρακτική του **Chrome**, και είναι σωστή: σε `mailto:` το μενού λέει *«Αντιγραφή
 * διεύθυνσης e-mail»*, σε `tel:` *«Αντιγραφή αριθμού»*, σε ιστοσελίδα *«Αντιγραφή
 * διεύθυνσης»*. Ο λόγος δεν είναι φραστικός: **αλλάζει και το τι μπαίνει στο πρόχειρο**
 * ({@link linkClipboardText}). Μία γενική ετικέτα θα υποσχόταν το ίδιο πράγμα για τρεις
 * διαφορετικές συμπεριφορές.
 */
export const LINK_COPY_KEY: Readonly<Record<TextLinkKind, string>> = {
  email: 'tableCellLink.copyEmail',
  url: 'tableCellLink.copyUrl',
  phone: 'tableCellLink.copyPhone',
};

/**
 * Τι μπαίνει πραγματικά στο πρόχειρο — **το ωφέλιμο φορτίο, όχι το σχήμα**.
 *
 * ## 🔴 Γιατί το `mailto:` ΔΕΝ αντιγράφεται
 * Ο χρήστης που ζητά «αντιγραφή διεύθυνσης e-mail» θα το επικολλήσει σε πεδίο παραλήπτη.
 * Ένα `mailto:georgios@nestor.gr` εκεί είναι **σκουπίδι** — κάθε πελάτης αλληλογραφίας θα το
 * απορρίψει ή θα στείλει σε λάθος διεύθυνση. Το ίδιο ισχύει για το `tel:` σε τηλεφωνητή.
 * Το Chrome κάνει ακριβώς αυτό, και είναι ο λόγος που έχει **ξεχωριστές** εντολές ανά είδος
 * αντί για μία «Copy link address».
 *
 * Η ιστοσελίδα κρατά το σχήμα της: εκεί το `https://` **είναι** μέρος της διεύθυνσης, και
 * χωρίς αυτό η επικόλληση σε γραμμή διευθύνσεων ή σε έγγραφο παύει να είναι σύνδεσμος.
 *
 * ⚠️ Για το τηλέφωνο αντιγράφεται η **κανονικοποιημένη** μορφή του `href` (χωρίς κενά και
 * παρενθέσεις), όχι το κείμενο του κελιού: αυτό είναι που καλείται πραγματικά, και είναι το
 * μόνο που δουλεύει σε κάθε τηλεφωνητή.
 */
export function linkClipboardText(kind: TextLinkKind, href: string): string {
  if (kind === 'email') return stripScheme(href, 'mailto:');
  if (kind === 'phone') return stripScheme(href, 'tel:');
  return href;
}

function stripScheme(href: string, scheme: string): string {
  return href.startsWith(scheme) ? href.slice(scheme.length) : href;
}
