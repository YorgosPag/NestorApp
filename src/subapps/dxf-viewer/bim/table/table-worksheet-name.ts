/**
 * ADR-833 Φάση 3 — **ΠΩΣ ΛΕΓΕΤΑΙ ΜΙΑ ΚΑΡΤΕΛΑ**: ο ΕΝΑΣ επιλυτής ονόματος φύλλου εργασίας.
 *
 * Η Φάση 2 άφησε το `TableWorksheet.name` **προαιρετικό**, και αυτό ήταν απόφαση, όχι
 * παράλειψη (ADR-833 §5.2, `types/table-worksheet.ts` §3):
 *
 * ```
 *   name παρόν  ⇒  δεδομένο ΧΡΗΣΤΗ — ταξιδεύει αυτούσιο, ΠΟΤΕ δεν μεταφράζεται
 *   name απόν   ⇒  «το προεπιλεγμένο όνομα της θέσης μου» — το αποφασίζει Η ΠΑΡΟΥΣΙΑΣΗ
 * ```
 *
 * **Η Φάση 3 είναι η παρουσίαση.** Άρα εδώ, και μόνο εδώ, γεννιέται η δεύτερη γραμμή.
 *
 * ## 🔴 Ο ΚΑΜΒΑΣ ΔΕΝ ΕΧΕΙ `useTranslation` — ΚΑΙ ΔΕΝ ΤΟ ΧΡΕΙΑΖΕΤΑΙ
 *
 * Ο ζωγράφος του πίνακα είναι **imperative**: μηδέν React, μηδέν συνδρομές (ADR-040). Το
 * ερώτημα «*πώς κρατά ζωντανή γλώσσα χωρίς να γίνει React;*» έχει **ήδη** απάντηση μέσα σε
 * αυτόν τον φάκελο και δεν εφευρίσκεται εδώ δεύτερη: το `table-resize-readout.ts` (η ένδειξη
 * «Πλάτος: 14,14 (104 pixel)») διαβάζει το **singleton** `i18n` του έργου
 * **τη στιγμή της κλήσης** — ίδιο ιδίωμα με άλλα ~18 imperative σημεία του subapp
 * (`measurement-label.ts`, `area-label.ts`, τα `*-hud-spec-label.ts`).
 *
 * 🔑 **Γιατί αυτό ΕΙΝΑΙ «ζωντανή γλώσσα»**: η ανάγνωση γίνεται σε **χρόνο καρέ**, όχι σε
 * χρόνο κατασκευής. Δεν υπάρχει τιμή αποθηκευμένη κάπου που να μπορεί να παλιώσει — άρα δεν
 * υπάρχει και τίποτα να συγχρονιστεί. Είναι ο **ίδιος ακριβώς** κανόνας που ο ADR-040
 * επιβάλλει για τον δρομέα και τη μεταμόρφωση: *getter τη στιγμή του συμβάντος, ποτέ
 * στιγμιότυπο*. Η γλώσσα είναι απλώς άλλο ένα store που διαβάζεται με getter.
 *
 * ⚠️ **Μετρημένο όριο, δηλωμένο ρητά** (2026-08-30): στο subapp **δεν υπάρχει** ακροατής
 * `languageChanged` — καμία γραμμή σε ολόκληρο το `src/subapps/dxf-viewer`. Άρα μια αλλαγή
 * γλώσσας **δεν ζητά καρέ** από μόνη της: η νέα γλώσσα φαίνεται στο **επόμενο** καρέ που θα
 * ζητήσει οποιοσδήποτε άλλος. Για τη λωρίδα καρτελών αυτό είναι πρακτικά αόρατο — ζει μόνο σε
 * **επιλεγμένο** πίνακα, και η αλλαγή γλώσσας γίνεται από κορδέλα/μενού, δηλαδή με χειρονομίες
 * που παράγουν καρέ ούτως ή άλλως. Καταγράφεται ως **γνωστό όριο** και όχι ως σιωπή: η
 * θεραπεία του (ένας ακροατής που καλεί `markSystemsDirty`) είναι **καθολική** για τον καμβά
 * και αφορά και τις ~18 άλλες imperative ετικέτες — δηλαδή δεν ανήκει σε αυτό το ADR.
 *
 * ## Γιατί ΔΕΝ δέχεται `t` ως όρισμα
 * Ο πειρασμός είναι `worksheetDisplayName(sheet, index, t)`, ώστε το module να μείνει «καθαρό».
 * Θα ήταν καθαρότητα-βιτρίνα: ο **μόνος** καλών είναι ο ζωγράφος του καμβά, που δεν έχει `t`
 * και θα τον έφτιαχνε ρωτώντας το **ίδιο** singleton — δηλαδή θα ήταν παράμετρος με **μία**
 * δυνατή τιμή, που το ADR-833 §5.4 ονομάζει ρητά «νεκρή παράμετρος». Και θα άνοιγε τη μία
 * πόρτα που αυτό το αρχείο υπάρχει για να κλείσει: έναν δεύτερο καλούντα με **άλλο** `t`,
 * δηλαδή δύο απαντήσεις στο «πώς λέγεται η καρτέλα».
 *
 * @module subapps/dxf-viewer/bim/table/table-worksheet-name
 * @see types/table-worksheet.ts §3 — ΓΙΑΤΙ το όνομα είναι προαιρετικό
 * @see bim/table/table-resize-readout.ts — το ίδιο ιδίωμα i18n σε imperative μονοπάτι
 * @see docs/centralized-systems/reference/adrs/ADR-833-table-xlsx-import-and-worksheets.md §5.3
 */

import { i18n } from '@/i18n';
import type { TableWorksheet } from '../../types/table-worksheet';

const NS = 'dxf-viewer-shell';

/**
 * Το όνομα που **βλέπει ο άνθρωπος** πάνω στην καρτέλα.
 *
 * ⚠️ Το `index` είναι **θέση στον πίνακα φύλλων**, μηδενική βάση — και γίνεται `index + 1`
 * στο κλειδί, γιατί η αρίθμηση που βλέπει ο χρήστης ξεκινά από το **1** (όπως οι γραμμές του
 * δείκτη, όπως το «Φύλλο1» του Excel). Η μετατροπή ζει **εδώ**: δύο καλούντες που έκαναν ο
 * καθένας το `+1` του θα ήταν δύο ευκαιρίες να το ξεχάσει ο ένας.
 *
 * 🔴 **Η θέση ΔΕΝ είναι ταυτότητα.** Το προεπιλεγμένο όνομα ενός ανώνυμου φύλλου αλλάζει όταν
 * αναδιαταχθούν τα φύλλα (Φάση 4) — και αυτό είναι **σωστό**: «το φύλλο στη δεύτερη θέση»
 * είναι ακριβώς αυτό που το προεπιλεγμένο όνομα υπόσχεται. Το Excel λέει ψέματα εδώ (κρατά
 * «Φύλλο1» στην τρίτη θέση), γιατί εκεί το όνομα είναι **πάντα** αποθηκευμένο δεδομένο και
 * δεν έχει τρόπο να ξέρει αν ο χρήστης το εννοούσε.
 */
export function worksheetDisplayName(sheet: TableWorksheet, index: number): string {
  // Δεδομένο χρήστη ⇒ αυτούσιο. Ο έλεγχος είναι στο **κενό μετά από trim** και όχι σκέτο
  // `?? `: ένα όνομα από κενά είναι καρτέλα χωρίς ετικέτα, δηλαδή ακριβώς η περίπτωση όπου η
  // προεπιλογή είναι πιο ειλικρινής από το «σεβασμό στα δεδομένα».
  const explicit = sheet.name?.trim();
  if (explicit) return explicit;
  return i18n.t('table.worksheet.defaultName', { ns: NS, index: index + 1 });
}
