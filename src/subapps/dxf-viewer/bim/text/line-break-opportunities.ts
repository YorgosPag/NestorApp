/**
 * ENTERPRISE — **ΠΟΥ ΕΠΙΤΡΕΠΕΤΑΙ να σπάσει μια γραμμή**: ο ΕΝΑΣ κατάλογος ευκαιριών.
 *
 * ADR-739 §58 (Φάση Γ). Καθαρό module: μηδέν μέτρηση, μηδέν γεωμετρία, μηδέν React.
 * Απαντά **μόνο** στο «σε ποιους δείκτες του κειμένου *θα ήταν νόμιμο* να τελειώσει μια
 * γραμμή» — **όχι** στο «πού τελειώνει», που είναι ερώτηση πλάτους και ζει στο `text-fit.ts`.
 *
 * ## 🔴 Γιατί υπάρχει: το `indexOf(' ')` απαντά σε λάθος ερώτηση
 * Μέχρι το §58 η μοναδική ευκαιρία σπασίματος σε όλο το έργο ήταν ο **κενός χαρακτήρας
 * ASCII** (`fittingPrefixLengthByWord`). Σε πίνακα ποσοτήτων αυτό δεν είναι ατέλεια —
 * είναι αστοχία στα **συνηθισμένα** δεδομένα του χρήστη:
 *
 * ```
 *   «ΟΠΛΙΣΜΟΣ Φ12-Φ16»   -> «Φ12-Φ16» δεν σπάει ΠΟΤΕ  => κοπή στη μέση λέξης
 *   «m3/τεμ»             -> ούτε εδώ
 *   «ΣΚΥΡΟΔΕΜΑ C20/25»   -> ούτε εδώ
 * ```
 *
 * Το fallback χαρακτήρα του χάρακα **δεν** είναι δίχτυ ασφαλείας εδώ: παράγει σπασμένη
 * λέξη σε παραδοτέο σχέδιο, δηλαδή ακριβώς το «άχρηστο παραδοτέο» που περιγράφει το
 * `table-cell-overflow.ts`.
 *
 * ## 🔴 Γιατί ΟΧΙ βιβλιοθήκη UAX#14 — και τι ακριβώς θυσιάζεται
 * Το σωστό εργαλείο θα ήταν το `Intl.Segmenter` με `granularity: 'line'` (UAX#14). **Δεν
 * υπάρχει**: είναι πρόταση v2 του TC39 και το σκέλος γραμμοκοπής αφαιρέθηκε από την
 * τρέχουσα προδιαγραφή μετά από ένσταση (ο φόβος ήταν ότι θα ενθάρρυνε διάταξη
 * παραγράφου σε JS — που εδώ είναι ακριβώς η δουλειά μας, αφού ζωγραφίζουμε σε **καμβά**).
 *
 * Οι εναλλακτικές ήταν τρεις και η επιλογή είναι μετρημένη:
 *  1. **npm `linebreak`** (πλήρες UAX#14, MIT): ~40KB στο bundle ενός subapp που ήδη μετρά
 *     το i18n bootstrap του σε bytes (ADR-744, 295->184KB) — και **τρίτο** μονοπάτι γνώσης
 *     ορίων δίπλα στο `Intl` που ο browser ήδη κουβαλά.
 *  2. **Σκέτο κενό** (σημερινό): αστοχεί στα παραπάνω παραδείγματα.
 *  3. **ΑΥΤΟ**: `Intl.Segmenter('word')` (UAX#29, **Baseline** — Chrome 87 / Safari 14.1 /
 *     Firefox 125) για τα όρια που ένα regex **δεν μπορεί** να ξέρει (CJK, Ταϊλανδέζικα:
 *     γλώσσες χωρίς κενά), **συν** τους ρητούς κανόνες κλάσης BA/SY του UAX#14 για τα
 *     διαχωριστικά που εμφανίζονται σε τεχνικές περιγραφές.
 *
 * ⚠️ **Δηλωμένο όριο**: το UAX#29 (λέξεις) **δεν είναι** το UAX#14 (γραμμές). Δεν
 * καλύπτονται οι κλάσεις εισαγωγικών/παρενθέσεων στο σύνολό τους, ούτε τα ζεύγη CJK
 * (LB19-LB21). Καλύπτονται όσα εμφανίζονται σε **πίνακα ποσοτήτων ελληνικού τεχνικού
 * γραφείου** — και αυτό δηλώνεται, δεν υπονοείται.
 *
 * ⚠️ **Κάθε μη-ASCII χαρακτήρας εδώ γράφεται ως `\\uXXXX`, ποτέ κυριολεκτικά.** Δεν είναι
 * στυλ: ο μαλακός ενωτικός και το ZWSP είναι **αόρατοι** σε κάθε επεξεργαστή, και οι
 * U+2028/U+2029 τερματίζουν γραμμή μέσα σε literal — ένα regex που τους περιείχε ωμούς
 * απέτυχε να μεταγλωττιστεί με «Invalid regular expression», χωρίς κανείς να βλέπει γιατί.
 *
 * @module subapps/dxf-viewer/bim/text/line-break-opportunities
 * @see bim/text/text-fit.ts — ο ΕΝΑΣ χάρακας «πόσο χωρά» (ερώτηση **πλάτους**)
 * @see bim/text/text-wrap-lines.ts — ο ΕΝΑΣ βρόχος αναδίπλωσης (ο καταναλωτής)
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §58
 */

/**
 * Χαρακτήρες μετά τους οποίους **επιτρέπεται** αλλαγή γραμμής — κλάσεις `BA` (break after)
 * και `SY` του UAX#14, περιορισμένες σε όσους εμφανίζονται σε τεχνικές περιγραφές.
 *
 * 🔴 Ο **μαλακός** ενωτικός (U+00AD) και το ZWSP (U+200B) είναι εδώ επειδή αυτή ΕΙΝΑΙ όλη
 * τους η σημασία: ο συγγραφέας του κειμένου δήλωσε ρητά «εδώ μπορείς να σπάσεις». Ένα
 * σύστημα που τους αγνοεί κάνει τον χρήστη να πληκτρολογεί κάτι που δεν έχει κανένα
 * αποτέλεσμα — χειρότερο από το να μην τους υποστηρίζει καθόλου.
 */
const BREAK_AFTER: ReadonlySet<string> = new Set([
  '-',        // HYPHEN-MINUS       «Φ12-Φ16»
  '\u2010',   // HYPHEN
  '\u2012',   // FIGURE DASH
  '\u2013',   // EN DASH
  '\u2014',   // EM DASH
  '/',        // SOLIDUS            «m3/τεμ», «C20/25»
  '\u00AD',   // SOFT HYPHEN        ρητή δήλωση του συγγραφέα
  '\u200B',   // ZERO WIDTH SPACE   ρητή δήλωση του συγγραφέα
]);

/**
 * Χαρακτήρες που **δεν επιτρέπεται να ξεκινούν** γραμμή — κλάσεις `CL` / `CP` / `IS` / `NS`
 * του UAX#14. Μια ευκαιρία που θα άφηνε τελεία ή κλείσιμο παρένθεσης μόνη της στην αρχή
 * της επόμενης γραμμής **ακυρώνεται**.
 *
 * Χωρίς αυτό το φίλτρο ο `Intl.Segmenter` θα παρήγαγε ακριβώς τέτοιες ευκαιρίες σε
 * ιδεογραμματικό κείμενο, και η ισορρόπηση (`text-wrap-lines.ts`) θα τις **προτιμούσε** —
 * αφού δίνουν ομοιόμορφα πλάτη. Το αισθητικά «καλύτερο» θα ήταν τυπογραφικά λάθος.
 */
const NO_BREAK_BEFORE: ReadonlySet<string> = new Set([
  '.', ',', ';', ':', '!', '?', '·', '…',
  ')', ']', '}', '»', '”', '’',
  '%', '‰', '°',
]);

/**
 * Λευκός χώρος στον οποίο **σπάει** η γραμμή.
 *
 * 🔴 Το NBSP (U+00A0) λείπει **σκόπιμα**: είναι κλάση `GL` (glue) και ολόκληρος ο λόγος
 * ύπαρξής του είναι να **απαγορεύει** το σπάσιμο. Ένα «10 m2» γραμμένο με NBSP από τον
 * χρήστη οφείλει να μείνει ενωμένο — αλλιώς το σύστημα ακυρώνει σιωπηλά μια ρητή απόφασή
 * του, ίδιο σχήμα με τον μαλακό ενωτικό.
 */
const BREAKING_SPACE = /[ \t\u2028\u2029]/u;

/** `true` για δεκαδικό ψηφίο ASCII — αρκεί: οι τεχνικές περιγραφές δεν γράφουν άλλα ψηφία. */
function isDigit(ch: string | undefined): boolean {
  return ch !== undefined && ch >= '0' && ch <= '9';
}

/**
 * Ο κανόνας **LB25** του UAX#14, στο μέτρο που μας αφορά: δεν σπάμε ένωση/κάθετο όταν
 * **και οι δύο** πλευρές είναι ψηφία.
 *
 * 🔴 Δεν είναι λεπτομέρεια — είναι σφάλμα **τιμής** σε πίνακα ποσοτήτων, η κατηγορία των
 * ADR-712/713. Χωρίς αυτό:
 * ```
 *   «05/08/2026»  ->  «05/» / «08/2026»   ημερομηνία σπασμένη στα δύο
 *   «1/2»         ->  «1/» / «2»          κλάσμα που διαβάζεται ως δύο αριθμοί
 * ```
 * Ενώ το «Φ12-Φ16» **σπάει κανονικά**, γιατί δεξιά του ενωτικού είναι γράμμα: ο κανόνας
 * διακρίνει «εύρος αριθμών» από «σύνθετο κωδικό» χωρίς να χρειάζεται να ξέρει τι είναι.
 */
function isNumericSeparator(text: string, index: number): boolean {
  const ch = text[index];
  if (ch !== '-' && ch !== '/') return false;
  return isDigit(text[index - 1]) && isDigit(text[index + 1]);
}

/**
 * Τα όρια που **μόνο** ο `Intl.Segmenter` μπορεί να ξέρει: μεταξύ δύο γειτονικών
 * τμημάτων-λέξεων που **δεν** χωρίζονται από τίποτα.
 *
 * ## 🔴 Γιατί ΜΟΝΟ αυτά, και όχι κάθε όριο που επιστρέφει
 * Το UAX#29 δίνει όρια και γύρω από τη στίξη. Δεχόμενοι τα όλα, το «Φ12-Φ16» θα
 * αποκτούσε ευκαιρία **πριν** και **μετά** το ενωτικό, και το «(Α1)» ευκαιρία μετά την
 * ανοιχτή παρένθεση — δηλαδή θα σπάγαμε εκεί που καμία γλώσσα δεν σπάει.
 *
 * Δύο **γειτονικά** `isWordLike` τμήματα χωρίς ενδιάμεσο διαχωριστικό εμφανίζονται
 * πρακτικά μόνο σε γλώσσες **χωρίς κενά** (CJK, Ταϊλανδέζικα) — ακριβώς η γνώση που ένα
 * regex δεν έχει και ο browser έχει. Στα ελληνικά και τα λατινικά η συνθήκη δεν
 * ικανοποιείται ποτέ, άρα αυτό το σκέλος είναι **αόρατο** για το 100% των σημερινών
 * δεδομένων: μηδέν κίνδυνος οπισθοδρόμησης, θετικό μόνο κέρδος.
 *
 * `undefined` όταν το API λείπει (πολύ παλιό runtime, εξωτικό jsdom): ο καλών συνεχίζει με
 * τους ρητούς κανόνες. **Ποτέ εξαίρεση** — μια αναδίπλωση δεν επιτρέπεται να ρίξει τη σκηνή.
 */
function segmenterBoundaries(text: string): readonly number[] | undefined {
  const ctor = (Intl as { Segmenter?: typeof Intl.Segmenter }).Segmenter;
  if (typeof ctor !== 'function') return undefined;

  let previousWordEnd: number | undefined;
  const out: number[] = [];
  try {
    for (const segment of new ctor(undefined, { granularity: 'word' }).segment(text)) {
      if (segment.isWordLike !== true) {
        previousWordEnd = undefined;
        continue;
      }
      // Γειτονικά => δεν υπάρχει διαχωριστικός χαρακτήρας ανάμεσα => γλώσσα χωρίς κενά.
      if (previousWordEnd === segment.index) out.push(segment.index);
      previousWordEnd = segment.index + segment.segment.length;
    }
  } catch {
    return undefined;
  }
  return out;
}

/**
 * Οι ευκαιρίες από **λευκό χώρο**: μία στο τέλος κάθε ακολουθίας κενών.
 *
 * Στο τέλος και όχι στην αρχή, ώστε τα κενά να ανήκουν στη γραμμή που **τελειώνει** — η
 * σύμβαση που ήδη έχει το `fittingPrefixLengthByWord` («το επιστρεφόμενο μήκος
 * περιλαμβάνει το κενό») και που επιτρέπει στον καλούντα να τα κόψει και από τις δύο
 * πλευρές. Μία ευκαιρία ανά ακολουθία και όχι ανά χαρακτήρα: δύο διαδοχικά κενά δεν
 * είναι δύο σημεία απόφασης.
 */
function whitespaceOpportunities(text: string, out: number[]): void {
  for (let i = 0; i < text.length; i++) {
    if (!BREAKING_SPACE.test(text[i])) continue;
    while (i + 1 < text.length && BREAKING_SPACE.test(text[i + 1])) i++;
    out.push(i + 1);
  }
}

/** Οι ευκαιρίες από **διαχωριστικό χαρακτήρα** ({@link BREAK_AFTER}), με το LB25 φίλτρο. */
function separatorOpportunities(text: string, out: number[]): void {
  for (let i = 0; i < text.length; i++) {
    if (!BREAK_AFTER.has(text[i])) continue;
    if (isNumericSeparator(text, i)) continue;
    out.push(i + 1);
  }
}

/**
 * Οι **νόμιμοι** δείκτες τερματισμού γραμμής μέσα στο `text`, αύξοντες και μοναδικοί.
 *
 * Σύμβαση: ο δείκτης `k` σημαίνει «η γραμμή μπορεί να είναι `text.slice(0, k)` και η
 * επόμενη να ξεκινά στο `k`». Ποτέ `0` (κενή γραμμή δεν είναι απόφαση) και ποτέ
 * `text.length` (το τέλος του κειμένου δεν είναι *ευκαιρία*, είναι το πέρας — ο καλών το
 * ξέρει ούτως ή άλλως, και ένας δείκτης που σημαίνει «μη σπάσεις» θα ήταν παγίδα).
 *
 * Καθαρή και ντετερμινιστική: ίδιο κείμενο ⇒ ίδιοι δείκτες, πάντα. Προϋπόθεση για την
 * απομνημόνευση της διάταξης και για το bitmap cache του καμβά (ADR-040).
 */
export function lineBreakOpportunities(text: string): readonly number[] {
  if (text.length <= 1) return [];

  const raw: number[] = [];
  whitespaceOpportunities(text, raw);
  separatorOpportunities(text, raw);
  raw.push(...(segmenterBoundaries(text) ?? []));

  const seen = new Set<number>();
  const out: number[] = [];
  for (const k of raw.sort((a, b) => a - b)) {
    if (k <= 0 || k >= text.length || seen.has(k)) continue;
    // Το φίλτρο «τι ΞΕΚΙΝΑ την επόμενη γραμμή» — δες {@link NO_BREAK_BEFORE}.
    if (NO_BREAK_BEFORE.has(text[k])) continue;
    seen.add(k);
    out.push(k);
  }
  return out;
}
