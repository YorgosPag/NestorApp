/**
 * Ελάχιστο πλάτος στήλης σε sheet-mm που δέχεται το σύρσιμο λαβής ορίου. Κάτω από
 * αυτό η στήλη παύει να είναι στήλη — δεν χωρά ούτε ένας χαρακτήρας μαζί με τα
 * περιθώριά της.
 */
export const MIN_TABLE_COLUMN_WIDTH_MM = 4;

/** Ελάχιστο ύψος γραμμής σε sheet-mm — ένα κείμενο 2.5mm με μηδενικά περιθώρια. */
export const MIN_TABLE_ROW_HEIGHT_MM = 2.5;

/**
 * Η **εσοχή** (sheet-mm) του σταυρού μετακίνησης από την πάνω-**αριστερή** γωνία και του
 * τόξου περιστροφής από την πάνω-**δεξιά**, πάνω στην ΠΑΝΩ ακμή.
 *
 * Giorgio 2026-08-03: «λίγα πίξελς δεξιά από την αριστερή λαβή / λίγα πίξελς αριστερά από
 * την πάνω-δεξιά» — ακριβώς οι θέσεις του αρχικού σκίτσου, όπου ο σταυρός κάθεται κοντά
 * στην αριστερή γωνία και το τόξο κοντά στη δεξιά.
 *
 * ## Γιατί σε mm και όχι σε px, όπως ειπώθηκε
 * Το `getTableGrips` δεν **έχει** `viewScale` (§31.8) — δεν ξέρει τι είναι pixel. Και δεν
 * χρειάζεται: ο πίνακας είναι **annotative**, οπότε μια σταθερή απόσταση σε sheet-mm
 * μεγαλώνει και μικραίνει **μαζί** του και μένει οπτικά «λίγα pixels» σε κάθε zoom. Μια
 * απόσταση σε px θα ήταν αντίθετα αυτή που θα **μεταβαλλόταν** σχετικά με τον πίνακα.
 *
 * ## Δύο δώρα αυτής της τοποθέτησης
 * 1. Οι θέσεις παύουν να είναι **κλάσματα** του πλάτους, άρα δεν ακολουθούν πια τα όρια
 *    στηλών: με 4 ισοπλατείς στήλες (όρια στο 25/50/75%) ο σταυρός και το τόξο **δεν**
 *    συμπίπτουν πλέον με κανένα. Μένει γνωστή μόνο η σύμπτωση της μεσοπλευρικής `edge-n`
 *    με το μεσαίο όριο σε ζυγό πλήθος ισοπλατών στηλών — καρφωμένη σε test.
 * 2. Το `v` μένει **0** (πάνω στην ακμή), που είναι υποχρεωτικό: η οπή του §27.11 κρατά τη
 *    ζώνη γραμμάτων μακριά **μόνο** από λαβές πάνω στην ακμή.
 *
 * ⚠️ Φράσσεται σε **¼ του πλάτους** από το {@link tableHandleInsetMm}: σε στενό πίνακα οι
 * δύο λαβές θα διασταυρώνονταν (και θα προσπερνούσαν τη μεσοπλευρική στο μέσο).
 */
export const TABLE_HANDLE_INSET_MM = 6;

/**
 * Η πραγματική εσοχή για δεδομένο πλάτος: {@link TABLE_HANDLE_INSET_MM}, φραγμένη ώστε ο
 * σταυρός να μένει στο αριστερό τεταρτημόριο και το τόξο στο δεξί — άρα ποτέ ο ένας πέρα
 * από τον άλλο, ποτέ πάνω στη μεσοπλευρική του μέσου.
 */
export function tableHandleInsetMm(widthMm: number): number {
  return Math.min(TABLE_HANDLE_INSET_MM, widthMm / 4);
}

