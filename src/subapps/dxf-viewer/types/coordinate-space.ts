/**
 * **Ο ΧΩΡΟΣ ΣΥΝΤΕΤΑΓΜΕΝΩΝ ΖΕΙ ΣΤΟΝ ΤΥΠΟ — ΜΗΔΕΝ ΚΟΣΤΟΣ ΧΡΟΝΟΥ ΕΚΤΕΛΕΣΗΣ.**
 *
 * @module types/coordinate-space
 * @related ADR-794 · ADR-793 (η μονάδα στο ΟΝΟΜΑ) · ADR-792 (CHECK 3.59) · ADR-749
 *
 * ## Το πρόβλημα, μετρημένο
 *
 * Το σχήμα `{ minX, minY, maxX, maxY }` δηλωνόταν **42 φορές** σε αυτό το δέντρο
 * (24 exported + 18 τοπικές επαναδηλώσεις), και το όνομα `BoundingBox` δηλωνόταν
 * **10 φορές σε ΕΞΙ ασύμβατα σχήματα** — μεταξύ τους δύο φορές μέσα στον **ίδιο**
 * φάκελο (`rendering/core/IRenderContext.ts` βαθμωτά vs `rendering/types/Types.ts`
 * `{min,max}`) και δύο φορές μέσα στο **ίδιο αρχείο** (`systems/rulers-grid/config.ts`).
 *
 * ## 🏆 Τι κάνουν οι μεγάλοι — και είναι ομόφωνο
 *
 * | | ο κανόνας τους |
 * |---|---|
 * | **Revit** | `BoundingBoxXYZ` (3Δ μοντέλου) vs `BoundingBoxUV` (2Δ παραμετρικός) — **ένας τύπος ανά ΧΩΡΟ**, κοινός για *κάθε* element |
 * | **ArchiCAD** | `BoundingBox2D {xMin,yMin,xMax,yMax}` vs `API_Box3D` — ένας ανά **διάσταση**, κοινός για κάθε στοιχείο |
 * | **Qt** | `QRect` (ακέραιοι, device px) vs `QRectF` (float, λογικές) — ανά **αριθμητικό πεδίο**, όχι ανά widget |
 * | **Cinema 4D** | `GetRad()` τοπικό vs world matrix — ο χώρος στο όνομα **ΜΕΘΟΔΟΥ** |
 * | **Figma** | **ΕΝΑΣ** `Rect`· ο χώρος στο όνομα **ΙΔΙΟΤΗΤΑΣ** (`absoluteBoundingBox`) |
 * | **three.js** | `Box2` / `Box3` — ένας ο καθένας |
 *
 * 🔑 **Κανείς τους δεν δηλώνει τύπο κουτιού ανά ΑΝΤΙΚΕΙΜΕΝΟ.** Δεν υπάρχει `TableBBox`
 * στον Revit ούτε `HatchBounds` στον ArchiCAD. Ο άξονας είναι **χώρος**, ποτέ «τι
 * περικλείω». Εδώ **14 από τους 24** exported τύπους ονομάζονταν από το αντικείμενο.
 *
 * ## 🏆 Πού τους ξεπερνάμε, και γιατί ΧΡΕΙΑΖΕΤΑΙ
 *
 * **Η C# (Revit) και η C++ (ArchiCAD/Qt) είναι ΟΝΟΜΑΣΤΙΚΕΣ γλώσσες**: το `BoundingBoxUV`
 * **δεν** περνά εκεί που ζητείται `BoundingBoxXYZ`, δωρεάν, από τον μεταγλωττιστή.
 * **Η TypeScript είναι ΔΟΜΙΚΗ**: δύο τύποι με τα ίδια τέσσερα πεδία είναι **ο ίδιος
 * τύπος**, όσο διαφορετικά κι αν τους ονομάσεις. Άρα η αντιγραφή της ονοματοδοσίας τους
 * **χωρίς** brand μας δίνει την **οργάνωσή** τους με **μηδέν** από την **ασφάλειά** τους —
 * ένα `TileRange` (ακέραιοι δείκτες πλακιδίων) περνά αθόρυβα εκεί που ζητείται
 * ορθογώνιο σε **χιλιοστά**.
 *
 * Το phantom brand **επαναφέρει την ονομαστικότητα** που εκείνοι παίρνουν δωρεάν.
 * Ο μεταγλωττιστής το βλέπει· η JavaScript **ποτέ** (η ιδιότητα δεν ανατίθεται πουθενά,
 * και το κλειδί της είναι `unique symbol` — δεν εμφανίζεται σε `Object.keys`, σε spread,
 * ούτε σε `JSON.stringify`). **Κόστος χρόνου εκτέλεσης: μηδέν. Byte στο Firestore: μηδέν.**
 *
 * ## ⚠️ Γιατί ΟΧΙ η κίνηση του ADR-793 (η μονάδα στο όνομα ΠΕΔΙΟΥ)
 *
 * Το ADR-793 έλυσε τη σύγχυση μονάδων μετονομάζοντας `minZ` → `minZm`. Εδώ **δεν
 * γίνεται, και ο λόγος είναι μετρημένος**: τα τέσσερα πεδία είναι **ταυτόσημα σε όλους
 * τους χώρους**, και το `BlockGeometryBlob.boundsMm` **γράφεται στο Storage** με
 * `BLOCK_GEOMETRY_BLOB_VERSION`. Μετονομασία πεδίου ⇒ **μετανάστευση δεδομένων**.
 * Το brand είναι ο **μόνος** τρόπος να πάρουμε την εγγύηση με **μηδενική** μετανάστευση.
 * Δεν είναι δεύτερος μηχανισμός δίπλα στο ADR-793 — είναι **άλλο επίπεδο**: εκείνο
 * ονομάζει τη *μονάδα ενός αριθμού*, αυτό τον *χώρο ενός τύπου*.
 *
 * ## 🔶 ΔΗΛΩΜΕΝΟ ΟΡΙΟ — διάβασέ το πριν το επικαλεστείς ως εγγύηση
 *
 * Το brand είναι **προαιρετικό**, και αυτό είναι **επιλογή**:
 * - ✅ **Φυλάει τη ΡΟΗ**: τιμή τύπου `Bbox` **δεν** περνά όπου ζητείται `LocalRectMm`.
 *   Αυτή είναι η κατηγορία σφάλματος που ήταν **ζωντανή** (ADR-793 §2.1: το railing
 *   έγραφε χιλιοστά εκεί που όλοι έγραφαν μέτρα, σφάλμα **1000×**).
 * - ❌ **ΔΕΝ φυλάει την ΚΑΤΑΣΚΕΥΗ**: ένα ωμό `{ minX: 0, minY: 0, maxX: 1, maxY: 1 }`
 *   περνά σε **οποιονδήποτε** χώρο. Εκεί ο συγγραφέας γράφει ο ίδιος τους αριθμούς —
 *   ξέρει τι εννοεί. Ένα **υποχρεωτικό** brand θα απαιτούσε κατασκευαστές σε **42**
 *   σημεία και θα απαγόρευε τα object literals· μετρήθηκε ως δυσανάλογο.
 *
 * ⚠️ **ΜΗΝ κάνεις το brand υποχρεωτικό** χωρίς να ξαναμετρήσεις: η προαιρετικότητα είναι
 * ακριβώς αυτό που κάνει τη μετανάστευση **μηδενικού ρίσκου** — αμαρκάριστος τύπος με τα
 * ίδια τέσσερα πεδία παραμένει συμβατός **και προς τις δύο κατευθύνσεις**, οπότε το μόνο
 * που μπλοκάρει είναι η ροή ανάμεσα σε **δύο διαφορετικά** μαρκαρισμένα.
 *
 * ⚠️ **ΜΗΝ δηλώσεις νέο χώρο εδώ χωρίς μέτρηση.** Ένας χώρος που δεν συναντά ποτέ άλλον
 * είναι φρουρός που **δεν μπορεί να πυροδοτήσει** (ADR-749 §5 μετρά **606** τέτοιους).
 */

/**
 * Το κλειδί του phantom πεδίου. `unique symbol` ώστε να **μην μπορεί** να συγκρουστεί με
 * πραγματικό πεδίο δεδομένων και να μην εμφανιστεί ποτέ σε enumeration/serialisation.
 * `declare` ⇒ **δεν παράγεται καμία γραμμή JavaScript**.
 */
declare const COORDINATE_SPACE: unique symbol;

/**
 * Ο χώρος ενός γεωμετρικού τύπου, σε **επίπεδο τύπου μόνο**.
 *
 * @example
 * export interface Bbox extends InSpace<'plan-mm'> { readonly minX: number; ... }
 */
export interface InSpace<S extends CoordinateSpace> {
  readonly [COORDINATE_SPACE]?: S;
}

/**
 * **Το κλειστό σύνολο των χώρων** που συναντιούνται σε αυτό το subapp. Κάθε τιμή εδώ
 * τεκμηριώνεται από **μετρημένο σημείο επαφής** — όχι από πρόβλεψη. Η μέτρηση έγινε
 * διαβάζοντας **κάθε μία** από τις 42 δηλώσεις του σχήματος (ADR-794 §3).
 *
 * | χώρος | τι είναι | μετρημένη επαφή με `plan-mm` |
 * |---|---|---|
 * | `plan-mm` | XY κάτοψης, **κόσμος**, canonical mm (scene units) — **36 από τις 42** | — |
 * | `plan-m` | XY κάτοψης, **κόσμος**, **ΜΕΤΡΑ** (3Δ σκηνή / εισαγωγή Τέκτονα) | `scalePoints(verts, sceneUnitsToMeters(...))` |
 * | `local-mm` | canonical mm αλλά **ΤΟΠΙΚΑ ΣΤΟ ΣΤΟΙΧΕΙΟ** (base στο origin, ανεξάρτητο placement) | κάθε τοποθέτηση block· `LOCAL-mm → sheet-mm` fit |
 * | `tile-index` | **ΑΚΕΡΑΙΟΙ** δείκτες πλέγματος πλακιδίων, κλειστό διάστημα — δεν είναι μήκος καθόλου | ο basemap μετατρέπει σε **κάθε καρέ** |
 * | `screen-px` | **CLIENT px** της οθόνης, αρχή πάνω-αριστερά, **Y-DOWN** (ADR-795) | marquee 3Δ → επιλογή· **10 δομικά ταυτόσημοι** τύποι `{min:Point2D;max:Point2D}`, οι 9 σε κόσμο/κάτοψη |
 *
 * 🔴 **Ο `plan-m` ΔΕΝ είναι θεωρητικός.** Τα `bim-3d/converters/slab-rebar-3d.ts` και
 * `bim/structural/reinforcement/rebar-segments-3d-grid.ts` δηλώνονται ρητά «**mirror**»
 * το ένα του άλλου, είχαν **ταυτόσημο** τοπικό `interface Bbox` και **ταυτόσημο** τοπικό
 * `bboxOf` — και το πρώτο τρέχει σε **μέτρα** (`scalePoints` πριν την κλήση), το δεύτερο
 * σε **scene units** (`mmToSceneUnits` μετά). **Και τα δύο σωστά**· ο τύπος δεν έλεγε
 * **τίποτα**. Είναι η ίδια κατηγορία σφάλματος με το railing του ADR-793 §2.1 (**1000×**),
 * ένα βήμα πριν γίνει βλάβη.
 *
 * 🔑 **ΤΟ ΚΡΙΤΗΡΙΟ ΕΙΣΟΔΟΥ, ΔΙΑΤΥΠΩΜΕΝΟ ΜΙΑ ΦΟΡΑ** (και τα δύο επόμενα το εφαρμόζουν):
 * ένας χώρος παίρνει brand **μόνο αν ο μεταγλωττιστής ΔΕΝ τον ξεχωρίζει ήδη**. Αν το σχήμα
 * του είναι δομικά **ασύμβατο** με ό,τι συναντά, το brand θα ήταν φρουρός που δεν μπορεί
 * να πυροδοτήσει (ADR-749 §5: **606** τέτοιοι). Το `sheet-mm` κόπηκε σε αυτό ακριβώς·
 * το `screen-px` πέρασε σε αυτό ακριβώς. **Το ίδιο ερώτημα, δύο αντίθετες απαντήσεις.**
 *
 * 🔬 **ΥΠΟΨΗΦΙΟΣ ΜΕΤΡΗΘΗΚΕ ΚΑΙ ΑΠΟΡΡΙΦΘΗΚΕ — `sheet-mm` (χαρτί).** Ο χώρος
 * **υπάρχει** και είναι ο αρχέτυπος διαχωρισμός κάθε CAD (το `BoundingBoxUV` του Revit
 * απέναντι στο `BoundingBoxXYZ`)· ο μετασχηματισμός είναι ζωντανός στο
 * `column-detail-plan.ts` (`const s = 1 / denom; // sheet-mm per real-mm`). **Δεν πήρε
 * brand γιατί δεν το χρειάζεται**: το ορθογώνιο χαρτιού είναι ήδη το `RectMm` του
 * `print/config/paper-types`, σε σχήμα **`{x, y, w, h}`** — δομικά **ασύμβατο** με το
 * `{minX, minY, maxX, maxY}`, άρα ο μεταγλωττιστής τα ξεχωρίζει **ήδη**. Ένα
 * `SheetRectMm` σε μορφή min/max θα ήταν **δεύτερο** ορθογώνιο για τον ΙΔΙΟ χώρο,
 * δηλαδή ακριβώς το ελάττωμα που κλείνει αυτό το ADR — και **αδρανής φρουρός** από πάνω.
 *
 * ⚠️ **ΜΗΝ προσθέσεις χώρο χωρίς μετρημένη επαφή** (ADR-749 §5: **606** αδρανείς φρουροί).
 */
export type CoordinateSpace =
  | 'plan-mm'
  | 'plan-m'
  | 'local-mm'
  | 'tile-index'
  | 'screen-px';

// ─── Το ΣΧΗΜΑ, μία φορά· τα ΟΝΟΜΑΤΑ, ένα ανά χώρο ────────────────────────────

/**
 * **Το άξονο-ευθυγραμμισμένο ορθογώνιο, δηλωμένο ΜΙΑ φορά για ΟΛΟΥΣ τους χώρους.**
 *
 * 🏆 **Εδώ ξεπερνάμε ακόμη και τη δομή τους**: ο Revit γράφει `BoundingBoxUV` και
 * `BoundingBoxXYZ` ως **δύο ξεχωριστές κλάσεις με διπλογραμμένα μέλη**· η ArchiCAD
 * `Bbox` και `API_Box3D` το ίδιο· η Qt `QRect` και `QRectF` το ίδιο. Είναι το
 * τίμημα γλωσσών χωρίς τύπους-παραμέτρους σε αυτή τη θέση. Εδώ το σχήμα είναι **ένα**
 * και ο χώρος είναι **όρισμα τύπου** — μία δήλωση, πέντε εγγυήσεις, μηδέν αντιγραφή.
 *
 * ⚠️ **ΜΗΝ το χρησιμοποιήσεις ωμό** (`MinMaxRect<'plan-mm'>`) στις υπογραφές: κάθε χώρος έχει
 * **όνομα**, και το όνομα είναι αυτό που διαβάζει ο άνθρωπος.
 */
export interface MinMaxRect<S extends CoordinateSpace> extends InSpace<S> {
  readonly minX: number;
  readonly minY: number;
  readonly maxX: number;
  readonly maxY: number;
}

// ⚠️ Ο κυρίαρχος χώρος (`plan-mm`) έχει το **όνομά** του αλλού, και είναι επιλογή: το
// `Bbox` ζει στο `bim/geometry/shared/xy-bounds.ts` **μαζί με τις συναρτήσεις του**
// (`bboxOf` · `bboxOfAll` · `bboxOverlap` · `planBoundsOf`, ~30 importers). Ένα κουτί
// χωρίς τον βρόχο που το γεννά είναι μισό SSoT· τα παρακάτω **δεν έχουν** συναρτήσεις.

/**
 * **ΤΟ** άξονο-ευθυγραμμισμένο ορθογώνιο κάτοψης — XY, **κόσμος**, canonical mm.
 * Το z **δεν** συμμετέχει ποτέ.
 *
 * 🏆 **Ονομάζεται από τον ΧΩΡΟ, όχι από το αντικείμενο** — ο ομόφωνος κανόνας των μεγάλων
 * (Revit `BoundingBoxXYZ`/`BoundingBoxUV` · ArchiCAD `Bbox` · Qt `QRect`/`QRectF` ·
 * three.js `Box2`). **Κανείς** τους δεν έχει τύπο κουτιού ανά αντικείμενο: δεν υπάρχει
 * `TableBBox` στον Revit ούτε `HatchBounds` στον ArchiCAD. Εδώ το σχήμα ήταν γραμμένο
 * **42 φορές** σε **24 exported ονόματα**, τα **14** από αυτά ονομασμένα από το
 * αντικείμενο που περικλείουν (ADR-794).
 *
 * ⚠️ **ΜΗΝ δηλώσεις εικοστό πέμπτο.** Αν θέλεις όριο σε XY, **εισάγαγε αυτό** — από εδώ,
 * ή από το `bim/geometry/shared/xy-bounds` μαζί με τον `bboxOf` που το γεννά. Ο φρουρός
 * είναι το **CHECK 3.59** (`.point-vocabulary.json`): το όνομα `Bbox` επιτρέπεται σε
 * **ΑΚΡΙΒΩΣ ΕΝΑ** αρχείο, και είναι αυτό.
 *
 * ⚠️ **Ο χώρος ζει στον τύπο** ({@link MinMaxRect}, phantom, μηδέν κόστος): μια τιμή `Bbox`
 * **δεν** περνά εκεί που ζητείται `LocalRectMm` (τοπικό στο στοιχείο), `PlanRectM`
 * (μέτρα), `SheetRectMm` (χαρτί) ή `TileRange` (δείκτες πλακιδίων). Η TypeScript είναι
 * **δομική** — χωρίς αυτό, το όνομα θα ήταν **διακοσμητικό**.
 */
export type Bbox = MinMaxRect<'plan-mm'>;

/**
 * Ορθογώνιο κάτοψης σε **ΜΕΤΡΑ** — ο χώρος της 3Δ σκηνής και της εισαγωγής Τέκτονα.
 *
 * 🔴 **Η ύπαρξή του δεν είναι θεωρία**: `bim-3d/converters/slab-rebar-3d.ts` (μέτρα, μετά
 * από `scalePoints(verts, sceneUnitsToMeters(...))`) και
 * `bim/structural/reinforcement/rebar-segments-3d-grid.ts` (scene units) δηλώνονται ρητά
 * «**mirror**» ο ένας του άλλου και είχαν **byte-ταυτόσημο** τοπικό `interface Bbox` και
 * **byte-ταυτόσημο** τοπικό `bboxOf`. Ο ένας μετρά μέτρα, ο άλλος χιλιοστά, **και οι δύο
 * σωστά** — αλλά ο τύπος δεν έλεγε **τίποτα**. Τώρα το λέει.
 */
/**
 * Η **ΜΕΤΑΒΛΗΤΗ** μορφή του {@link MinMaxRect} — ο συσσωρευτής, όχι το αποτέλεσμα.
 *
 * Υπάρχει για **έναν μετρημένο λόγο**: το `InfinityBounds` του ADR-158 (8 αρχεία
 * καταναλωτές, `createInfinityBounds` · `expandInfinityBounds` · `isInfinityBounds`)
 * **γράφει** πάνω στα πεδία καθώς διατρέχει σημεία. Ήταν **ξεχωριστή δήλωση** του ίδιου
 * σχήματος· τώρα είναι ο **ίδιος** τύπος με σβησμένο το `readonly` — άρα ο χώρος
 * **επιβιώνει** και ένας συσσωρευτής `plan-mm` περνά ελεύθερα εκεί που ζητείται `Bbox`
 * (μεταβλητό → αμετάβλητο είναι πάντα νόμιμο), αλλά **όχι** εκεί που ζητείται άλλος χώρος.
 */
export type MutableMinMaxRect<S extends CoordinateSpace> = {
  -readonly [K in keyof MinMaxRect<S>]: MinMaxRect<S>[K];
};

export type PlanRectM = MinMaxRect<'plan-m'>;

/**
 * Ορθογώνιο σε canonical mm αλλά **ΤΟΠΙΚΑ ΣΤΟ ΣΤΟΙΧΕΙΟ** — base στο origin, ανεξάρτητο
 * placement. Ο χώρος της «οικογένειας» (Revit `.rfa` / ArchiCAD `.gsm`): ό,τι ισχύει για
 * τον **ορισμό**, όχι για το **στιγμιότυπο**.
 *
 * ⚠️ Συναντά τον `plan-mm` σε **κάθε** τοποθέτηση — και εκεί ακριβώς ένα λάθος είναι
 * αόρατο, γιατί οι δύο έχουν την **ίδια μονάδα** και το ίδιο σχήμα. Ήταν **τέσσερα**
 * ονόματα (`BlockBoundsMm` · `Extent` · `BBox` · αυτό).
 */
export type LocalRectMm = MinMaxRect<'local-mm'>;

/**
 * Ορθογώνιο στο πλέγμα **πλακιδίων** ενός επιπέδου: **ακέραιοι** δείκτες, **κλειστό**
 * διάστημα. **Δεν είναι μήκος** — ένα `maxX - minX` εδώ μετρά *πλακίδια*, όχι χιλιοστά.
 *
 * ⚠️ Ο πιο επικίνδυνος της οικογένειας ακριβώς επειδή είναι ο πιο **ξένος**: μοιράζεται
 * σχήμα με ένα κουτί σε mm, και ο basemap μετατρέπει προς/από αυτό σε **κάθε καρέ**.
 */
export type TileRange = MinMaxRect<'tile-index'>;

// ─── Η ΔΕΥΤΕΡΗ ΜΟΡΦΗ: ορθογώνιο από ΣΗΜΕΙΑ (ADR-795) ─────────────────────────

/**
 * **Το ίδιο ορθογώνιο, εκφρασμένο με ΣΗΜΕΙΑ αντί για βαθμωτά** — και ο **ίδιος** phantom
 * χώρος από πάνω.
 *
 * 🔑 **ΓΙΑΤΙ ΥΠΑΡΧΟΥΝ ΔΥΟ ΜΟΡΦΕΣ, ΚΑΙ ΓΙΑΤΙ ΑΥΤΟ ΔΕΝ ΕΙΝΑΙ «ΔΥΟ ΑΛΗΘΕΙΕΣ»** (ADR-749):
 * η διάκριση **δεν** είναι γούστο — είναι **σύνορο επιμονής**, και είναι **μετρημένο**:
 *
 * - **`{min, max}` με σημεία = Η ΑΠΟΘΗΚΕΥΜΕΝΗ ΜΟΡΦΗ.** Είναι το σχήμα που **ΕΙΝΑΙ ΗΔΗ
 *   ΓΡΑΜΜΕΝΟ** στο Firestore (`PlanBounds` για `floor-finish` · `thermal-space` ·
 *   `wall-covering` — οι **3 από 27** που επιμένουν το `geometry`· οι **24** το
 *   ξαναϋπολογίζουν) **και** στο Storage (`DxfSceneBounds`, δηλαδή
 *   `files/{id}.processedData.bounds` **και** το gzip JSON της σκηνής).
 * - **`{minX, minY, maxX, maxY}` βαθμωτά ({@link MinMaxRect}) = Η ΜΟΡΦΗ ΥΠΟΛΟΓΙΣΜΟΥ.**
 *   Μηδέν κατανομή αντικειμένων στους σφιχτούς βρόχους (`bboxOf` κ.λπ.).
 *
 * 🏆 **ΚΑΙ ΟΙ ΔΥΟ ΕΙΝΑΙ ΒΙΟΜΗΧΑΝΙΚΕΣ — δεν διαλέγει κανείς μία**: three.js `Box2`/`Box3`
 * (`min`/`max` ως `Vector2`/`Vector3`) · Revit `BoundingBoxXYZ` (`Min`/`Max` ως `XYZ`) ·
 * ArchiCAD `API_Box3D` κρατούν **σημεία**· η JTS `Envelope` κρατά **βαθμωτά**
 * (`minx`/`maxx`/`miny`/`maxy`). Η Qt δίνει **και τα δύο** (`QRect.topLeft()` δίπλα στο
 * `QRect.left()`) — αλλά ως **μεθόδους ενός** τύπου, πολυτέλεια που ένα plain-data
 * interface δεν έχει. **Άρα η ΝΕΣΤΩΡ κρατά δύο μορφές, όπως όλοι — με τη διαφορά ότι εδώ
 * ΚΑΙ ΟΙ ΔΥΟ κουβαλούν τον ΧΩΡΟ, που κανένας από τους παραπάνω δεν κάνει.**
 *
 * ⚠️ **ΜΗΝ «ενοποιήσεις» τις δύο μορφές σε μία.** Μετρήθηκε δύο φορές (ADR-793 §3.2,
 * ADR-795): η κατεύθυνση «όλα βαθμωτά» είναι **ΜΕΤΑΝΑΣΤΕΥΣΗ ΔΕΔΟΜΕΝΩΝ** σε ζωντανά
 * έγγραφα παραγωγής· η κατεύθυνση «όλα σημεία» πληρώνει κατανομή αντικειμένου σε κάθε
 * επανάληψη βρόχου. Το σύνορο **επιμονή ↔ υπολογισμός** είναι η σωστή γραμμή, και ήταν
 * ήδη γραμμένο σε πρόζα στο `bim/geometry/shared/xy-bounds.ts`. Εδώ γίνεται **τύπος**.
 */
export interface PointRect<S extends CoordinateSpace> extends InSpace<S> {
  readonly min: { readonly x: number; readonly y: number };
  readonly max: { readonly x: number; readonly y: number };
}

/**
 * Ορθογώνιο σε **ΕΙΚΟΝΟΣΤΟΙΧΕΙΑ ΟΘΟΝΗΣ** (CLIENT px, αρχή πάνω-αριστερά, Y-DOWN).
 *
 * 🔴 **Ο πέμπτος χώρος πέρασε το κριτήριο που ο `sheet-mm` ΔΕΝ πέρασε — και το κριτήριο
 * ήταν ήδη γραμμένο εδώ**: *«δεν πήρε brand γιατί δεν το χρειάζεται· είναι δομικά
 * ασύμβατο, ο μεταγλωττιστής τα ξεχωρίζει ήδη»*. Το `screen-px` είναι **το αντίθετο**:
 * μετρήθηκε (ADR-795) ότι **ΔΕΚΑ** τύποι του δέντρου έχουν **δομικά ΤΑΥΤΟΣΗΜΟ** σχήμα
 * `{ min: Point2D; max: Point2D }` — `BoundingBox` ×2 · `Bounds` · `Bounds2D` ·
 * `CrossingWindow` · `MinMax` · `ReviewFocusBounds` · `SceneBounds` · `WorldBounds` ·
 * και αυτό. Οι εννέα είναι **κόσμος/κάτοψη**· αυτό είναι **οθόνη**. Η TypeScript είναι
 * **ΔΟΜΙΚΗ** ⇒ μια τιμή σε px περνά **αθόρυβα** εκεί που ζητούνται χιλιοστά κόσμου.
 *
 * ⚠️ Είναι **χειρότερο** από το σφάλμα 1000× του railing (ADR-793 §2.1): εκεί η σχέση
 * ήταν **σταθερή** (mm↔m) και το λάθος υπολογίσιμο· εδώ ο λόγος px↔mm **αλλάζει με το
 * zoom**, άρα δεν υπάρχει καν συντελεστής να «διορθώσει» κανείς εκ των υστέρων.
 *
 * 🏆 Ο διαχωρισμός είναι ο αρχέτυπος κάθε CAD: Revit `BoundingBoxUV` (χαρτί/παραμετρικό)
 * απέναντι στο `BoundingBoxXYZ` (μοντέλο) · Qt `QRect` **ακέραιοι** (συσκευή) απέναντι
 * στο `QRectF` **πραγματικοί** (λογικός χώρος).
 */
export type ScreenRectPx = PointRect<'screen-px'>;
