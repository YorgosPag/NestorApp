/**
 * ADR-750 Φάση 1 — **η ταυτότητα μιας ακμής πλέγματος**, και το μολύβι της.
 *
 * Καθαρό type module (μηδέν runtime, μηδέν React/canvas). Η **μοναδική** νόμιμη κατασκευή
 * κλειδιού ζει στο `bim/table/table-edge-model.ts` — εδώ ζει μόνο το σχήμα.
 *
 * ## Το μοντέλο: κάθε ακμή είναι «η ΠΑΝΩ ή η ΑΡΙΣΤΕΡΗ πλευρά ενός κελιού»
 * ```
 *   H · <rowId> · <colId>   →  η ΠΑΝΩ ακμή του κελιού (rowId, colId)
 *   H · $end    · <colId>   →  η κάτω ακμή του ΠΙΝΑΚΑ, στη στήλη colId
 *   V · <rowId> · <colId>   →  η ΑΡΙΣΤΕΡΗ ακμή του κελιού (rowId, colId)
 *   V · <rowId> · $end      →  η δεξιά ακμή του ΠΙΝΑΚΑ, στη γραμμή rowId
 * ```
 *
 * **Γιατί μόνο πάνω+αριστερή και όχι και οι τέσσερις πλευρές**: αλλιώς κάθε εσωτερική ακμή
 * θα είχε **δύο** ονόματα (η κάτω του Α είναι η πάνω του Β) — δηλαδή θα ξαναγεννιόταν η
 * διφορούμενη ιδιοκτησία που είναι η γενεσιουργός αιτία **όλων** των παραπόνων του Excel
 * (ADR-750 §3.3): «ποιο κελί κατέχει τη γραμμή;», «το περίγραμμα δεν φεύγει», «δεν
 * εμφανίζονται με συνέπεια». Με ένα όνομα ανά ακμή, η σύγκρουση γίνεται **μη εκφράσιμη** —
 * δεν επιλύεται καλύτερα, απλώς δεν υπάρχει. Την ίδια επιλογή έκανε ανεξάρτητα και η ομάδα
 * του Handsontable.
 *
 * **Γιατί ταυτότητες και όχι δείκτες `(r, c)`**: τα ids είναι σταθερά στη ζωή του πίνακα,
 * άρα εισαγωγή ή διαγραφή γραμμής **δεν μπορεί** να μετακινήσει περίγραμμα σε λάθος θέση.
 * Αυτό εξαφανίζει δομικά το τεκμηριωμένο παράπονο Π5 του Excel, χωρίς καμία γραμμή κώδικα
 * συντήρησης. Είναι **σχεδιαστική απαίτηση**, όχι λεπτομέρεια υλοποίησης.
 *
 * @module subapps/dxf-viewer/types/table-edges
 * @see bim/table/table-edge-model.ts — ο μοναδικός κατασκευαστής κλειδιού
 * @see docs/centralized-systems/reference/adrs/ADR-750-table-cell-borders.md §6
 */

import type { TableColumnId, TableRowId } from './table-ids';

/**
 * Μία ακμή περιγράμματος. `visible: false` ⇒ δεν ζωγραφίζεται καθόλου (DXF: group code
 * 288 `borderVisible`), που είναι διαφορετικό από «ζωγραφίζεται με μηδενικό πάχος» — το
 * δεύτερο θα άφηνε hairline σε κάποια backends.
 *
 * Ζει **εδώ** και όχι στο στυλ επειδή το χρειάζονται τρεις ανεξάρτητοι κάτοχοι: το στυλ
 * για τις κλάσεις γραμμής, το μοντέλο για τη γραμμή-σύνολο (`TableRow.borderTop`) και ο
 * χάρτης ακμών για τη ρητή παράκαμψη. Ένας ορισμός· το `types/table.ts` και το
 * `bim/table/table-style.ts` τον επανεξάγουν, ώστε καμία υπάρχουσα διαδρομή εισαγωγής να
 * μην αλλάξει.
 */
export interface TableBorderSpec {
  readonly visible: boolean;
  readonly colorHex: string;
  /** Πάχος γραμμής σε sheet-mm (ISO πένες: 0.13 / 0.15 / 0.25 / 0.50). */
  readonly widthMm: number;
  /** Μοτίβο διακεκομμένης σε sheet-mm· απόν ⇒ συνεχής. */
  readonly dashMm?: readonly number[];
}

/**
 * Οριζόντια (`'H'`) ή κατακόρυφη (`'V'`) ακμή του πλέγματος.
 *
 * Το γράμμα είναι **ένας** χαρακτήρας επίτηδες: μπαίνει ως πρόθεμα στο κλειδί, οπότε ένα
 * σταθερού πλάτους πρόθεμα σημαίνει ότι ο προσανατολισμός δεν χρειάζεται δικό του
 * διαχωριστικό ούτε μπορεί ποτέ να συγχυθεί με ταυτότητα.
 */
export type TableEdgeOrientation = 'H' | 'V';

/**
 * Το sentinel του **τελευταίου συνόρου** — η μόνη ακμή που δεν είναι πλευρά κανενός κελιού
 * (δεν υπάρχει κελί κάτω από την τελευταία γραμμή, ούτε δεξιά της τελευταίας στήλης).
 *
 * `'$end'` και όχι π.χ. `''`: οι ταυτότητες παράγονται είτε από το `enterprise-id.service`
 * (`<prefix>_<UUID>`) είτε από τον γεννήτορα του `table-row-column-ops` (`r0…rN` / `c0…cN`),
 * άρα **καμία** από τις δύο πηγές δεν μπορεί να παραγάγει αλφαριθμητικό που ξεκινά με `$`.
 * Το sentinel είναι η **σταθερή άγκυρα του πλαισίου**: διαγραφή της τελευταίας γραμμής δεν
 * παίρνει μαζί της το κάτω περίγραμμα του πίνακα, επειδή εκείνο δεν ανήκε ποτέ σε γραμμή.
 */
export type TableEdgeEnd = '$end';

/** Πού αγκυρώνεται η ακμή στον άξονα των γραμμών — `$end` **μόνο** για οριζόντια. */
export type TableEdgeRowAnchor = TableRowId | TableEdgeEnd;

/** Πού αγκυρώνεται η ακμή στον άξονα των στηλών — `$end` **μόνο** για κατακόρυφη. */
export type TableEdgeColAnchor = TableColumnId | TableEdgeEnd;

/**
 * Κλειδί ακμής στον αραιό χάρτη {@link TableEdgeIndex}. **Branded**, ακριβώς όπως το
 * `CellKey`: η ΜΟΝΗ νόμιμη πηγή είναι το `tableEdgeKey()` του `table-edge-model.ts`, ώστε
 * να μην μπορεί ποτέ να μπει γυμνό string με λάθος σειρά σκελών ή με το sentinel στη λάθος
 * θέση.
 */
export type TableEdgeKey = string & { readonly __tableEdgeKeyBrand: unique symbol };

/**
 * Μία ρητή ακμή όπως **ταξιδεύει**: τετράδα `[προσανατολισμός, γραμμή, στήλη, μολύβι]`.
 *
 * ## 🔴 Γιατί αποσυντεθειμένη και ΟΧΙ `[TableEdgeKey, TableBorderSpec]`
 * Το κλειδί ενώνει τα σκέλη με `\u0000` — μη εκτυπώσιμο byte, επιλεγμένο ακριβώς επειδή
 * καμία ταυτότητα δεν το περιέχει. Αυτό δουλεύει **όσο το κλειδί μένει στη μνήμη**. Γραμμένο
 * στο αρχείο, θα σήμαινε τρία πράγματα, και τα τρία ανεπιθύμητα:
 *
 * 1. **Χαρακτήρας ελέγχου μέσα σε κάθε αποθηκευμένο σχέδιο** — σε JSON σκηνής, σε diff, σε
 *    ό,τι διαβάσει το αρχείο μετά από εμάς.
 * 2. **Η μορφή του κλειδιού γίνεται δέσμευση μορφής αρχείου.** Σήμερα είναι μυστικό ενός
 *    module· γραμμένη στον δίσκο, κάθε αλλαγή της γίνεται migration.
 * 3. **Ασυμμετρία με τα κελιά.** Το `TableCellEntry` είναι τριάδα `[γραμμή, στήλη, κελί]`
 *    ακριβώς γι' αυτόν τον λόγο (`table-model-helpers.ts`: το `splitCellKey` είναι
 *    «ιδιωτικό επίτηδες»). Δύο διαφορετικές συμβάσεις για το ίδιο ερώτημα «πώς ταξιδεύει
 *    ένα κλειδωμένο σε ταυτότητες αντικείμενο;» είναι δεύτερο λεξιλόγιο.
 *
 * Άρα: **λίστα τετράδων στο αρχείο, ευρετήριο στη μνήμη** — η «Λύση Α» του ADR-739 §19.2
 * όπως εφαρμόζεται ήδη στα κελιά, όχι όπως τη συνόψισε το ADR-750 §6.2.
 */
export type TableEdgeEntry = readonly [
  TableEdgeOrientation,
  TableEdgeRowAnchor,
  TableEdgeColAnchor,
  TableBorderSpec,
];

/**
 * Ο **αραιός** χάρτης ρητών ακμών στη μνήμη. Ένας πίνακας 8×500 έχει ~8.500 ακμές πλέγματος·
 * εδώ μπαίνουν **μόνο** όσες ο χρήστης όρισε ρητά. Ό,τι λείπει απαντιέται από τα επίπεδα
 * 2–4 της προτεραιότητας (`table-layout-borders.ts`), δηλαδή απουσία σημαίνει «κληρονόμησε»
 * — ποτέ «καμία γραμμή».
 */
export type TableEdgeIndex = ReadonlyMap<TableEdgeKey, TableBorderSpec>;
