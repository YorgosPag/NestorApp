/**
 * ADR-833 Φάση 2 — **Η ΜΙΑ ΚΑΤΟΙΚΙΑ ΤΗΣ ΠΑΛΙΑΣ ΜΟΡΦΗΣ ΤΟΥ ΠΙΝΑΚΑ.**
 *
 * Πριν από τη Φάση 2 ένα `TableEntity` κρατούσε **ένα** πλέγμα, κατευθείαν πάνω του:
 * `entity.model` + `entity.binding`. Κάθε σχέδιο που αποθηκεύτηκε ως τότε έχει **αυτή** τη
 * μορφή, και θα την έχει για πάντα — τα αρχεία δεν ξαναγράφονται μόνα τους.
 *
 * ## 🔴 ΓΙΑΤΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ ΥΠΑΡΧΕΙ — ΚΑΙ ΓΙΑΤΙ ΕΙΝΑΙ ΜΟΝΟ ΕΝΑ
 *
 * Ο προφανής δρόμος ήταν το **πεδίο-καθρέφτης**: *«το `model` κρατά το ενεργό φύλλο, το
 * `worksheets` τα υπόλοιπα»*. **ΑΠΟΡΡΙΦΘΗΚΕ** (ADR-833 §5.2) και ο λόγος δεν είναι καθαρότητα:
 *
 * ```
 *   ενεργοποίηση καρτέλας  ⇒  ΜΕΤΑΚΙΝΗΣΗ ΔΕΔΟΜΕΝΩΝ ανάμεσα σε δύο πεδία
 *   ένα Ctrl+Z άσχετης εντολής ⇒ κελιά προσγειώνονται σε ΛΑΘΟΣ σπίτι
 *   κάθε πράξη (reorder/duplicate/delete) ⇒ αποκτά κλάδο `index === 0 ? … : …`
 * ```
 *
 * Η συμβατότητα **χωρίς** καθρέφτη έχει ένα τίμημα και ένα μόνο: κάποιος πρέπει να ξέρει την
 * παλιά μορφή. **Αυτό το αρχείο είναι εκείνος ο κάποιος, και είναι ο μόνος.** Το
 * {@link PreWorksheetsTableEntity} το εισάγει **ΑΚΡΙΒΩΣ ΕΝΑ** μη-test module — το
 * `bim/table/table-worksheet-resolve.ts` — και υπάρχει άγκυρα που κοκκινίζει αν εμφανιστεί
 * δεύτερος. Χωρίς αυτόν τον περιορισμό, το νεκρό πεδίο θα αποκτούσε **αναγνώστες**, και κάθε
 * νέος αναγνώστης είναι μια δεύτερη απάντηση στο «πού είναι τα κελιά».
 *
 * ## 🔴 ΓΙΑΤΙ Η ΑΝΑΒΑΘΜΙΣΗ ΕΙΝΑΙ **ΤΕΜΠΕΛΙΚΗ** ΚΑΙ ΟΧΙ ΣΤΗ ΦΟΡΤΩΣΗ
 *
 * Το αδελφό `services/dxf-scene-migration.ts` (ADR-358) αναβαθμίζει **στη φόρτωση**: σωστό εκεί,
 * γιατί ένα legacy `SceneLayer` του **λείπουν** πεδία που όλο το σύστημα θεωρεί δεδομένα.
 * Εδώ δεν λείπει τίποτα — η πληροφορία είναι **πλήρης**, απλώς σε άλλο σχήμα. Άρα η αναβάθμιση
 * μπορεί να γίνει στο **σημείο επίλυσης**, και αυτό αγοράζει κάτι που η φόρτωση δεν μπορεί:
 *
 * > **Σχέδιο που μόνο ΔΙΑΒΑΣΤΗΚΕ παράγει byte-identical JSON.**
 *
 * Είναι η ίδια εγγύηση που ήδη προστατεύει τα `edges`/`rowLinks` στο `toPersistedTableModel`
 * (*«ένα κενό πεδίο θα ταξίδευε σε κάθε αποθηκευμένο πίνακα του κόσμου και θα εμφανιζόταν σε
 * κάθε diff ως αλλαγή»*), και το ίδιο ιδίωμα με το `normalizeCellEntries`: **αμυντική διαχείριση
 * legacy στο σημείο επίλυσης, ποτέ στη φόρτωση.** Η μετανάστευση γράφεται στον δίσκο **στην
 * πρώτη πραγματική εγγραφή** — τότε που ο χρήστης άλλαξε κάτι ούτως ή άλλως.
 *
 * @module subapps/dxf-viewer/types/table-entity-legacy
 * @see bim/table/table-worksheet-resolve.ts — ο ΜΟΝΑΔΙΚΟΣ καταναλωτής
 * @see docs/centralized-systems/reference/adrs/ADR-833-table-xlsx-import-and-worksheets.md §5.2
 */

import type { PersistedTableModel, TableBinding } from './table';
import { FIRST_TABLE_WORKSHEET_ID, type TableWorksheet } from './table-worksheet';

/**
 * Η οντότητα πίνακα **όπως γράφτηκε πριν από τη Φάση 2**: ένα πλέγμα και ο δεσμός του,
 * κατευθείαν πάνω στην οντότητα.
 *
 * ⚠️ Δηλώνεται ως **δικό της** σχήμα και όχι ως `Pick<TableEntity, …>`: τα πεδία **έφυγαν** από
 * το `TableEntity`, άρα ένα `Pick` δεν θα μεταγλωττιζόταν — και αυτό είναι το ζητούμενο, όχι
 * ενόχληση. Η παλιά μορφή δεν είναι υποσύνολο της νέας· είναι **άλλη** μορφή, που τη διαβάζουμε.
 */
export interface PreWorksheetsTableEntity {
  readonly model: PersistedTableModel;
  readonly binding?: TableBinding;
}

/**
 * Ο **ΕΝΑΣ** έλεγχος «είναι αυτό η παλιά μορφή;» — και η **ΜΟΝΗ** στένωση τύπου προς τα εκεί.
 *
 * Το `TableEntity` δηλώνει `worksheets` ως **υποχρεωτικό**, οπότε ο compiler δεν έχει λόγο να
 * υποψιαστεί ότι λείπει· ένα σχέδιο του δίσκου όμως **δεν διάβασε τη δήλωσή μας**. Αυτή η
 * ασυμφωνία ανάμεσα στον τύπο και στο σύρμα υπάρχει σε κάθε μετανάστευση σχήματος, και η μόνη
 * ερώτηση είναι **πού** ζει. Ζει εδώ, σε **μία** συνάρτηση, με **μία** στένωση — αντί να είναι
 * σκορπισμένη ως `as any` σε κάθε αναγνώστη (κανόνας N.2).
 *
 * `null` ⇒ *«δεν είναι παλιά μορφή»* — που περιλαμβάνει και το χαλασμένο JSON χωρίς κανένα από τα
 * δύο σχήματα. Ο καλών αποφασίζει τι κάνει με αυτό· εδώ δεν μαντεύουμε.
 */
export function readPreWorksheetsTable(entity: object): PreWorksheetsTableEntity | null {
  const raw = entity as { readonly model?: unknown; readonly binding?: unknown };
  if (raw.model === null || typeof raw.model !== 'object') return null;
  return raw as unknown as PreWorksheetsTableEntity;
}

/**
 * Παλιά μορφή → **ένα** φύλλο εργασίας. Καθαρή, ταυτοδύναμη, ντετερμινιστική.
 *
 * Ο επιστρεφόμενος τύπος είναι **πλειάδα ενός στοιχείου**, όχι πίνακας: η εγγύηση «ο πίνακας έχει
 * πάντα τουλάχιστον ένα φύλλο» γίνεται έτσι **δουλειά του compiler** αντί για σχόλιο.
 *
 * Το φύλλο **δεν παίρνει όνομα** — δες `types/table-worksheet.ts` §3. Ένας πίνακας γραμμένος πριν
 * υπάρξουν φύλλα δεν είχε ποτέ ονομασμένο φύλλο, και η αναβάθμιση δεν επιτρέπεται να **εφεύρει**
 * δεδομένο χρήστη που ο χρήστης δεν έγραψε ποτέ.
 *
 * Το `binding` **μετακομίζει** μέσα στο φύλλο, και παραλείπεται όταν λείπει (ποτέ
 * `binding: undefined` ως κλειδί — Firestore-safe, ίδια σύμβαση με το `pickTableRenderFields`).
 */
export function upgradePreWorksheetsTable(
  legacy: PreWorksheetsTableEntity,
): readonly [TableWorksheet] {
  return [{
    id: FIRST_TABLE_WORKSHEET_ID,
    model: legacy.model,
    ...(legacy.binding !== undefined ? { binding: legacy.binding } : {}),
  }];
}
