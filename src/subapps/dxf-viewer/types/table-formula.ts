/**
 * ADR-739 Φ.Ζ — **ο τύπος ενός κελιού, δεμένος σε ταυτότητες**. Καθαρό type module:
 * μηδέν runtime, μηδέν εξαρτήσεις πέρα από τις ταυτότητες.
 *
 * ```
 *   table-ids  →  table-formula  →  table
 *   (ποιος)       (τι υπολογίζει)    (το μοντέλο)
 * ```
 * Η ίδια αλυσίδα — και για τον ίδιο λόγο — με το `table-edges.ts`: το μοντέλο κρατά τύπους,
 * ο τύπος αγκυρώνεται σε `TableRowId`/`TableColumnId`. Ταυτότητες μέσα στο μοντέλο θα έκαναν
 * την εξάρτηση **κύκλο**.
 *
 * ## 🔴 Γιατί ΔΕΝΤΡΟ και όχι το κείμενο `'=SUM(A1:A5)'`
 * Η υπόσχεση του ADR-739 §11 #7 είναι «**εισαγωγή γραμμής δεν σπάει τύπους** — ούτε το
 * AutoCAD δεν το έχει». Ένα αποθηκευμένο `'=SUM(A1:A5)'` **δεν μπορεί** να την κρατήσει: το
 * `A1` είναι θέση, και μια νέα γραμμή στη μέση αλλάζει το τι σημαίνει. Η μόνη διόρθωση θα
 * ήταν να **ξαναγράφει** κάθε δομική πράξη όλους τους τύπους του πίνακα — δηλαδή μια
 * συνάρτηση που κάθε μελλοντική πράξη οφείλει να θυμηθεί να καλέσει, και που την πρώτη φορά
 * που θα ξεχαστεί θα δώσει **λάθος νούμερο σε παραδοτέο**, σιωπηλά.
 *
 * Εδώ η αναφορά **είναι** η ταυτότητα της γραμμής και της στήλης. Η εισαγωγή γραμμής δεν
 * την αγγίζει επειδή δεν έχει τίποτα να αγγίξει: το `A1` της γραμμής τύπων **παράγεται** από
 * τη θέση της ταυτότητας τη στιγμή που κάποιος ρωτά (`table-formula-print.ts`). Το ελάττωμα
 * δεν διορθώνεται — γίνεται **αδύνατο να εκφραστεί**.
 *
 * Δεύτερο κέρδος, μικρότερο αλλά πραγματικό: το δέντρο αποθηκεύεται **ήδη αναλυμένο**, οπότε
 * ο επαναϋπολογισμός δεν ξανα-αναλύει κείμενο σε κάθε καρέ.
 *
 * ## Επιβιώνει σε `JSON.stringify` — υποχρέωση, όχι ευκολία
 * Μόνο απλά αντικείμενα, πίνακες, αριθμοί και αλφαριθμητικά· κανένας `Map`, καμία κλάση,
 * κανένα `undefined` ως τιμή. Τρεις γενικοί μηχανισμοί της εφαρμογής περνούν κάθε οντότητα
 * από JSON round-trip (αποθήκευση σκηνής, `deepClone` για undo, διαγραφή+αναίρεση) — δες την
 * κεφαλίδα του `PersistedTableModel`, όπου ο `Map` έχανε **σιωπηλά** όλα τα κελιά.
 *
 * @module subapps/dxf-viewer/types/table-formula
 * @see bim/table/formula/table-formula-parse.ts — κείμενο → δέντρο (η μία μετάφραση)
 * @see bim/table/formula/table-formula-print.ts — δέντρο → κείμενο (η αντίστροφη)
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §9
 */

import type { TableColumnId, TableRowId, TableWorksheetId } from './table-ids';

/**
 * Οι κωδικοί σφάλματος — **δεδομένα μορφότυπου, όχι ετικέτες UI**.
 *
 * Γράφονται αυτούσιοι στο `TableCell.value`, ταξιδεύουν σε DXF και στο πρόχειρο, και είναι
 * η ίδια λέξη που δείχνουν Excel, Google Sheets και LibreOffice. Γι' αυτό **δεν** περνούν
 * από i18n (N.11): μια μεταφρασμένη τιμή θα σήμαινε ότι το ίδιο αρχείο διαβάζεται αλλιώς σε
 * άλλη γλώσσα — δηλαδή ότι η γλώσσα του χρήστη αλλάζει τα **περιεχόμενα** του σχεδίου.
 * *(Το Excel τους μεταφράζει στην οθόνη· το ίδιο θα ήταν εφικτό αργότερα ως στρώμα εμφάνισης,
 * ποτέ ως αποθηκευμένη τιμή.)*
 *
 * - `#DIV/0!`   — διαίρεση με μηδέν.
 * - `#VALUE!`   — τελεστής πάνω σε κάτι που δεν είναι αριθμός (π.χ. `="α"*2`).
 * - `#REF!`     — η αναφορά δείχνει σε γραμμή/στήλη που δεν υπάρχει (πια).
 * - `#NAME?`    — άγνωστο όνομα συνάρτησης.
 * - `#NUM!`     — έγκυρη πράξη, μη πεπερασμένο αποτέλεσμα (π.χ. `=10^999`).
 * - `#CIRCULAR!`— το κελί εξαρτάται, άμεσα ή έμμεσα, από τον εαυτό του (ADR-739 §9.2).
 *
 * ## Οι τρεις που προστέθηκαν με τη βιβλιοθήκη συναρτήσεων (ADR-739 §49)
 * Δεν είναι διακοσμητικοί: είναι κωδικοί που η βιβλιοθήκη **παράγει πραγματικά** (μετρημένο
 * στο `utils.errors` της 4.6.1) και που το Excel γράφει με το ίδιο ακριβώς κείμενο. Χωρίς
 * αυτούς, μια αστοχία `VLOOKUP` θα αποθηκευόταν ως **σκέτο κείμενο** `'#N/A'` — δηλαδή δεν θα
 * το αναγνώριζε ο {@link isFormulaError}, δεν θα διαδιδόταν σε άθροισμα, και ένας πίνακας
 * ποσοτήτων θα **αγνοούσε σιωπηλά** μια αποτυχημένη αναζήτηση.
 *
 * - `#N/A`      — η τιμή δεν βρέθηκε (`VLOOKUP`/`MATCH` χωρίς αντιστοιχία).
 * - `#NULL!`    — τομή περιοχών που δεν τέμνονται.
 * - `#CALC!`    — η πράξη δεν παράγει τιμή που χωρά σε ένα κελί.
 *
 * ⚠️ Τα `#GETTING_DATA` και `#ERROR!` της βιβλιοθήκης **δεν** μπαίνουν εδώ: το πρώτο είναι
 * μεταβατική **κατάσταση** και όχι τιμή, το δεύτερο δεν είναι κωδικός του Excel καθόλου.
 * Χαρτογραφούνται σε `#VALUE!` — δες `formula-library-bridge.ts`.
 */
export type TableFormulaErrorCode =
  | '#DIV/0!'
  | '#VALUE!'
  | '#REF!'
  | '#NAME?'
  | '#NUM!'
  | '#N/A'
  | '#NULL!'
  | '#CALC!'
  | '#CIRCULAR!';

/**
 * Μια αναφορά σε **ένα** κελί, ως ζεύγος ταυτοτήτων. Δεν είναι `CellKey`: το κλειδί είναι
 * αδιαφανές αλφαριθμητικό φτιαγμένο για ευρετήριο, ενώ εδώ χρειάζονται και τα **δύο** σκέλη
 * χωριστά (η στήλη για το γράμμα, η γραμμή για τον αριθμό, και τα δύο για την επέκταση
 * εύρους). Η αποδόμηση ενός branded κλειδιού σε κάθε χρήση θα ήταν η ίδια πληροφορία, μία
 * μετάφραση παρακάτω.
 */
export interface TableFormulaCellRef {
  readonly rowId: TableRowId;
  readonly colId: TableColumnId;
  /**
   * 🔴 ADR-833 Φάση 7 — «**σε ΠΟΙΟ ΦΥΛΛΟ** ζει αυτό το κελί». Παραλείπεται όταν είναι το
   * φύλλο που κρατά τον τύπο.
   *
   * ## Γιατί ταυτότητα και όχι όνομα — και γιατί το Excel **δεν μπορεί**
   * Το `=Φύλλο2!A1` που πληκτρολογεί ο χρήστης λύνεται σε **ταυτότητα** τη στιγμή της
   * ανάλυσης και το όνομα πετιέται — η **ίδια** πράξη που κάνει ήδη ο αναλυτής με το
   * `A1 → rowId/colId` (§11 #7). Συνέπεια: μια μετονομασία φύλλου **δεν αγγίζει κανέναν
   * τύπο**, ενώ Excel και Google Sheets υποχρεώνονται να ξαναγράψουν **κάθε** τύπο που
   * δείχνει στο φύλλο — γιατί εκεί το όνομα **είναι** η μόνη ταυτότητα. Είναι το μάθημα
   * του ADR-769 σε τρίτη εφαρμογή: *το Figma δένει με όνομα layer και γι' αυτό σπάει*.
   *
   * ## Γιατί ΠΡΟΑΙΡΕΤΙΚΟ — «απόν πεδίο ⇒ προεπιλογή», τρίτη φορά
   * Ίδια σύμβαση με τα {@link TableFormulaCellRef.absoluteRow}/`absoluteCol` (ADR-754 Γ2)
   * και με το `TableWorksheet.name` (ADR-833 §5.2): **απόν ⇒ το δικό μου φύλλο**. Το κέρδος
   * δεν είναι αισθητικό — κρατά **byte-identical** κάθε τύπο που γράφτηκε πριν υπάρξουν
   * δια-φυλλικές αναφορές, δηλαδή η Φάση 7 δεν χρειάστηκε **καμία** μετανάστευση δεδομένων.
   *
   * ⚠️ Η απάντηση «ποιο πλέγμα είναι αυτό;» **δεν διαβάζεται από εδώ κατευθείαν**: τη δίνει
   * ο ΕΝΑΣ επιλυτής `gridOfRef` (`formula/table-formula-workbook.ts`), γιατί το «απόν ⇒ το
   * σπίτι μου» χρειάζεται να ξέρει **ποιο** είναι το σπίτι — και δύο σημεία που το
   * απαντούσαν μόνα τους θα ήταν δύο ορισμοί του «πού δείχνει αυτή η αναφορά».
   */
  readonly worksheetId?: TableWorksheetId;
  /**
   * 🔴 ADR-754 Γ2 — «η **γραμμή** είναι κλειδωμένη» (`A$1`). Παραλείπεται όταν δεν είναι.
   *
   * ## Γιατί μπαίνει στην ταυτότητα, ενώ η ταυτότητα δεν μετατοπίζεται ποτέ
   * Φαίνεται αντίφαση: οι αναφορές μας είναι `rowId`/`colId`, άρα η **μετακίνηση** κελιού και
   * η **εισαγωγή** γραμμής δεν μπορούν καν να τις ολισθήσουν λάθος — η απολυτότητα μοιάζει
   * χωρίς αντικείμενο. Και ήταν, μέχρι να υπάρξει **αντιγραφή τύπου**: εκεί ο χρήστης λέει
   * «ξαναγράψε αυτόν τον τύπο μια γραμμή πιο κάτω», και η μόνη πληροφορία που μπορεί να
   * απαντήσει «ποιες αναφορές ακολουθούν;» είναι αυτή εδώ.
   *
   * Δηλαδή δεν είναι ιδιότητα **θέσης** (που θα ήταν πλεονασμός), είναι ιδιότητα **πρόθεσης**
   * του χρήστη, και επιβιώνει σε κάθε μετακίνηση για να είναι εκεί όταν γίνει η αντιγραφή.
   */
  readonly absoluteRow?: boolean;
  /** «Η **στήλη** είναι κλειδωμένη» (`$A1`). Δες το {@link TableFormulaCellRef.absoluteRow}. */
  readonly absoluteCol?: boolean;
}

/** Οι προθεματικοί τελεστές. Πρόσημο μόνο — καμία μεταβολή τιμής χωρίς σύμβολο. */
export type TableFormulaUnaryOp = '+' | '-';

/**
 * Οι δυαδικοί τελεστές, στη σειρά προτεραιότητας του Excel/AutoCAD:
 * `^` › `* /` › `+ -` › `&` › συγκρίσεις.
 *
 * Το `&` (συνένωση κειμένου) και οι συγκρίσεις υπάρχουν γιατί χωρίς αυτές η `IF` δεν έχει
 * τι να ρωτήσει — μια `IF` χωρίς σύγκριση είναι διακοσμητική.
 */
export type TableFormulaBinaryOp =
  | '^' | '*' | '/' | '+' | '-' | '&'
  | '=' | '<>' | '<' | '<=' | '>' | '>=';

/**
 * Ένας κόμβος του δέντρου. **Διακριτή ένωση** πάνω στο `kind`, ώστε ο μεταγλωττιστής να
 * απαιτεί εξαντλητικό χειρισμό σε κάθε καταναλωτή (αξιολογητή, εκτυπωτή, ανιχνευτή
 * εξαρτήσεων): ένας νέος τύπος κόμβου αύριο **σπάει τη μεταγλώττιση** και στα τρία σημεία
 * αντί να ξεχαστεί στο ένα.
 */
export type TableFormulaNode =
  /** Αριθμητικό κυριολεκτικό. Πάντα με `.` για δεκαδικό — δες `table-formula-lex.ts`. */
  | { readonly kind: 'number'; readonly value: number }
  /** Κυριολεκτικό κειμένου, χωρίς τα εισαγωγικά του. */
  | { readonly kind: 'text'; readonly value: string }
  /**
   * Κυριολεκτικό `TRUE` / `FALSE`, γραμμένο **χωρίς παρενθέσεις** (ADR-739 §49).
   *
   * ## Γιατί χρειάστηκε δικός του κόμβος
   * Ο λεξικογράφος βλέπει το `FALSE` ως σκέτο όνομα, και ο αναλυτής θεωρεί κάθε όνομα χωρίς
   * `(` **αναφορά κελιού** — άρα το `=VLOOKUP(x; εύρος; 2; FALSE)`, δηλαδή η **πιο συνηθισμένη
   * γραφή αναζήτησης στο Excel**, κατέληγε `#REF!`. Δεν ήταν θεωρητικό: το βρήκε η δοκιμή
   * conformance την πρώτη φορά που τρέξαμε πραγματική `VLOOKUP`.
   *
   * Οι εναλλακτικές ήταν χειρότερες: μετατροπή σε κλήση `TRUE()` θα άλλαζε **το κείμενο που
   * ξαναδιαβάζει ο χρήστης** (έγραψε `FALSE`, θα έβλεπε `FALSE()`), και μετατροπή σε κείμενο
   * θα έκανε το `=A1=TRUE` να συγκρίνει με τη **λέξη** «TRUE».
   *
   * ⚠️ Γράφεται πάντα με **κεφαλαία** όταν ξανατυπώνεται — ακριβώς ό,τι κάνει και το Excel.
   */
  | { readonly kind: 'boolean'; readonly value: boolean }
  /** Αναφορά σε ένα κελί: `A1`. */
  | { readonly kind: 'ref'; readonly cell: TableFormulaCellRef }
  /** Αναφορά σε ορθογώνιο εύρος: `A1:B5`. Τα άκρα **δεν** είναι κανονικοποιημένα. */
  | { readonly kind: 'range'; readonly from: TableFormulaCellRef; readonly to: TableFormulaCellRef }
  | { readonly kind: 'unary'; readonly op: TableFormulaUnaryOp; readonly operand: TableFormulaNode }
  | {
      readonly kind: 'binary';
      readonly op: TableFormulaBinaryOp;
      readonly left: TableFormulaNode;
      readonly right: TableFormulaNode;
    }
  /** Κλήση συνάρτησης· το `name` είναι **κανονικοποιημένο σε κεφαλαία** από τον αναλυτή. */
  | { readonly kind: 'call'; readonly name: string; readonly args: readonly TableFormulaNode[] }
  /**
   * 🔴 ADR-765 — **γυμνό όνομα που δεν ορίστηκε ποτέ**: το `ΣΩΣΤΟ` στο `=IF(A3>0;ΣΩΣΤΟ;ΛΑΘΟΣ)`.
   *
   * ## Γιατί χρειάστηκε δικός του κόμβος — και τι υπήρχε πριν
   * Ο αναλυτής δεχόταν ένα όνομα **μόνο** ως κλήση, κυριολεκτικό `TRUE`/`FALSE`, ή διεύθυνση.
   * Ό,τι άλλο έδινε `null`, και το `null` σημαίνει «δεν είναι τύπος» ⇒ **ολόκληρος** ο τύπος
   * αποθηκευόταν ως **ωμό κείμενο**. Ο ιδιοκτήτης συμπλήρωσε τον διάλογο «Ορίσματα
   * συνάρτησης», είδε **κενό** αποτέλεσμα, πάτησε «OK», και το κελί κράτησε
   * `=IF(A3>0;ΣΩΣΤΟ;ΛΑΘΟΣ)` ως κείμενο — που σε πίνακα ποσοτήτων **εκτυπώνεται αυτούσιο**.
   *
   * Excel, Google Sheets και LibreOffice κάνουν και τα τρία το **ίδιο**: το γυμνό όνομα είναι
   * *defined name* που δεν βρέθηκε, ο τύπος γίνεται **δεκτός**, και η τιμή είναι `#NAME?`.
   *
   * ## Ποιος αποφασίζει ότι είναι άγνωστο — ο ΑΞΙΟΛΟΓΗΤΗΣ
   * Ο κόμβος κρατά το όνομα **αυτούσιο** και δεν κρίνει. Το ADR-764 §2 έλυσε ακριβώς την ίδια
   * μορφή ερώτησης για το `#REF!` και κατέληξε εκεί: ο αναλυτής κρατά ό,τι έγραψε ο χρήστης,
   * ο αξιολογητής κρίνει. Αν ο αναλυτής πάγωνε `#NAME?`, η μέρα που θα αποκτούσαμε *ονόματα*
   * περιοχών θα ήταν η μέρα που κάθε παλιός τύπος θα είχε ήδη ξεχάσει τι έγραψε ο χρήστης.
   *
   * ## 🔴 ΔΕΝ καταπίνει διευθύνσεις
   * Η διάκριση «όνομα ή διεύθυνση» είναι **σχήματος**, όχι ύπαρξης: το `A99` σε πίνακα πέντε
   * γραμμών παραμένει `#REF!` (ADR-764), επειδή είναι *γραμμένο σαν* διεύθυνση. Μόνο ό,τι δεν
   * έχει καν σχήμα διεύθυνσης γίνεται όνομα — δες `table-formula-absolute.ts`.
   *
   * ⚠️ Γράφεται πίσω **αυτούσιο**, χωρίς κανονικοποίηση σε κεφαλαία (σε αντίθεση με το `call`):
   * δεν υπάρχει μητρώο να συμφωνήσει μαζί του, οπότε κάθε αλλαγή γραφής θα ήταν το εργαλείο
   * να ξαναγράφει ό,τι πληκτρολόγησε ο μηχανικός.
   */
  | { readonly kind: 'name'; readonly name: string }
  /**
   * 🔴 ADR-765 — **όρισμα που παραλείφθηκε**: το κενό ανάμεσα στα δύο `;` του `=IF(A1>10;;99)`.
   *
   * ## Δεν είναι «κενό κείμενο» — είναι απουσία, και η διαφορά φαίνεται
   * Αποτιμάται στην **ίδια διφορούμενη κενή τιμή** που δίνει ένα άδειο κελί: `0` σε
   * αριθμητική πράξη, `''` σε συνένωση (δες `finalize` στο `table-formula-eval.ts`). Ακριβώς
   * ό,τι κάνει το Excel με το `=IF(A1;;99)`. Ένα `{kind:'text', value:''}` θα ήταν **κείμενο**
   * και θα έδινε `0x` εκεί που πρέπει να δώσει `x`.
   *
   * ## Γιατί ΕΠΡΕΠΕ να υπάρχει
   * Ο ίδιος ο διάλογος **παράγει** αυτή τη γραφή: το `formula-call-text.ts` τεκμηριώνει ρητά
   * ότι «τα κενά **ενδιάμεσα** ορίσματα γράφονται», γιατί μια κοπή θα στοίβαζε το `99` στη
   * θέση του *τιμή αν αληθές*. Ο αναλυτής όμως το απέρριπτε ⇒ **η ίδια σιωπηλή υποβάθμιση σε
   * κείμενο**, από κώδικα που την είχε ήδη προβλέψει σωστά (ADR-763 §19.9).
   *
   * ⚠️ Παράγεται **μόνο** σε θέση ορίσματος κλήσης. Δεν υπάρχει γραφή που να το βάζει αλλού —
   * γι' αυτό ο εκτυπωτής μπορεί να το γράφει ως κενή συμβολοσειρά χωρίς να χάσει τίποτα.
   */
  | { readonly kind: 'blank' }
  /**
   * Ρητή παρένθεση του χρήστη. **Δεν** επηρεάζει τον υπολογισμό — η προτεραιότητα είναι ήδη
   * κωδικοποιημένη στο σχήμα του δέντρου.
   *
   * ## Γιατί υπάρχει, αφού δεν αλλάζει τίποτα
   * Ο ιδιοκτήτης γράφει `=(2*5)/2`. Χωρίς αυτόν τον κόμβο, ο εκτυπωτής θα του γύριζε
   * `=2*5/2`: **ίδιος αριθμός, άλλο κείμενο από αυτό που πληκτρολόγησε**. Το Excel και το
   * AutoCAD κρατούν τον τύπο ως συμβολοσειρά, οπότε δεν χάνουν ποτέ τις παρενθέσεις του
   * χρήστη· εμείς κρατάμε δέντρο (για να μη σπάνε οι αναφορές, §11 #7) και αυτός ο κόμβος
   * είναι το τίμημα που το κάνει **χωρίς** να χάσουμε τη γραφή του.
   *
   * Ένα εργαλείο που ξαναγράφει σιωπηλά ό,τι έγραψε ο μηχανικός τον κάνει να ελέγχει τον
   * εαυτό του κάθε φορά που ανοίγει το κελί. Οι περιττές παρενθέσεις **είναι** πληροφορία:
   * δηλώνουν πρόθεση ομαδοποίησης, ακόμη κι όταν η προτεραιότητα συμφωνεί.
   */
  | { readonly kind: 'group'; readonly inner: TableFormulaNode }
  /**
   * **Παγωμένο** σφάλμα δεσίματος: ο χρήστης έγραψε αναφορά που δεν αντιστοιχεί σε καμία
   * γραμμή/στήλη (`=A99` σε πίνακα πέντε γραμμών). Ζει στο δέντρο και όχι μόνο στην τιμή
   * γιατί το δέσιμο γίνεται **μία φορά**, στην πληκτρολόγηση: αν το αφήναμε στον αξιολογητή,
   * θα έπρεπε να κρατηθεί κάπου το ανεπίλυτο κείμενο — δηλαδή δεύτερη αναπαράσταση του ίδιου
   * τύπου, που μπορεί να διαφωνήσει με την πρώτη.
   *
   * ⚠️ **Συντακτικό** σφάλμα δεν φτάνει ποτέ εδώ: ένα `'=1+'` δεν γίνεται τύπος καθόλου —
   * μένει **κείμενο**, αυτούσιο όπως το πληκτρολογήθηκε, ώστε ο χρήστης να το βλέπει και να
   * το διορθώνει. Δες `table-formula-parse.ts`.
   */
  | { readonly kind: 'error'; readonly code: TableFormulaErrorCode };

/**
 * Ο αποθηκευμένος τύπος ενός κελιού — ό,τι κρατά το `TableCell.formula` όταν
 * `kind === 'formula'`.
 *
 * Είναι περιτύλιγμα και όχι σκέτος {@link TableFormulaNode} για δύο λόγους: (α) το `=` δεν
 * είναι μέρος της έκφρασης αλλά **δήλωση ότι πρόκειται για τύπο**, και ο εκτυπωτής πρέπει να
 * ξέρει να το ξαναβάλει· (β) μελλοντικά πεδία της ίδιας οντότητας (μορφή αριθμού,
 * `sourceRef` της Φ.Η) προσαρτώνται εδώ χωρίς να μεταλλαχθεί το σχήμα του δέντρου.
 */
export interface TableFormula {
  readonly root: TableFormulaNode;
}
