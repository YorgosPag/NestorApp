/**
 * ADR-833 Φάση 2 — **ΤΟ ΦΥΛΛΟ ΕΡΓΑΣΙΑΣ**: η μονάδα που κρατά *ένα* πλέγμα κελιών μέσα σε έναν
 * πίνακα που μπορεί να κρατά περισσότερα.
 *
 * Μέχρι τη Φάση 2 ένα `TableEntity` ήταν **ένα** πλέγμα (`entity.model`). Ο ιδιοκτήτης ζήτησε
 * *«αν υπάρχουν περισσότερα φύλλα εργασίας να εμφανίζονται όλα τα φύλλα με τα δεδομένα τους»* —
 * δηλαδή ο πίνακας παύει να είναι φύλλο και γίνεται **βιβλίο**.
 *
 * ## §1 — Ονοματολογία: `worksheet`, **ΠΟΤΕ** `sheet` (ADR-794, πύλες 3.59/3.73)
 * Η λέξη *sheet* είναι **πιασμένη**: στο ADR-771 σημαίνει η **χαρτένια επιφάνεια** πάνω στην
 * οποία ζωγραφίζεται ο πίνακας (`stamp-table-sheet.ts`, `surfaceHex`, `TABLE_PAPER_HEX`). Ο
 * κανόνας «ΕΝΑ όνομα ανά ΧΩΡΟ, ΠΟΤΕ ανά ΑΝΤΙΚΕΙΜΕΝΟ» είναι καρφωμένος στο
 * `bim/table/table-entity-hit.ts:31`. Άρα: `TableWorksheet` / `worksheets` / `activeWorksheetId`,
 * παντού και χωρίς εξαίρεση.
 *
 * ## §2 — 🔴 ΓΙΑΤΙ ΤΟ `binding` ΖΕΙ **ΕΔΩ** ΚΑΙ ΟΧΙ ΣΤΗΝ ΟΝΤΟΤΗΤΑ
 * Δεν είναι αισθητική επιλογή· **ο υπάρχων κώδικας το είχε ήδη αποδείξει**. Το
 * `buildTableBindingRefreshCommand` (`bim/table/table-cell-edit-session.ts`) γράφει
 * `{ model, binding }` **ατομικά, σε ΜΙΑ εντολή**, και η κεφαλίδα του εξηγεί γιατί απαγορεύεται
 * να χωριστούν: *«δύο εντολές θα σήμαιναν ότι ένα `Ctrl+Z` αναιρεί τα νούμερα αλλά αφήνει το νέο
 * αποτύπωμα»*. **Δύο πεδία που απαγορεύεται να γραφτούν χωριστά έχουν ΕΝΑΝ ιδιοκτήτη** — και
 * μόλις τα κελιά απέκτησαν σπίτι ανά φύλλο, ο ιδιοκτήτης είναι το φύλλο.
 *
 * Λειτουργικά το ίδιο: ένας δεσμός `mode:'live'` (ADR-767/769) αναγεννά **γραμμές**, και οι
 * γραμμές είναι ανά φύλλο. Το πραγματικό σενάριο του χρήστη είναι *«φύλλο 1 = ζωντανός πίνακας
 * κουφωμάτων, φύλλο 2 = χειρόγραφες σημειώσεις»* — με τον δεσμό στην οντότητα, η ανανέωση του
 * πρώτου θα ήταν ισχυρισμός για **ολόκληρο** τον πίνακα.
 *
 * ## §3 — 🔴 ΓΙΑΤΙ ΤΟ ΟΝΟΜΑ ΕΙΝΑΙ **ΠΡΟΑΙΡΕΤΙΚΟ** (και γιατί αυτό είναι *καλύτερο* από το Excel)
 * Το Excel/Sheets αποθηκεύουν **πάντα** ρητό όνομα («Φύλλο1», «Sheet1»), οπότε ένα βιβλίο
 * φτιαγμένο σε ελληνικό UI δείχνει «Φύλλο1» και σε αγγλικό. Εμείς έχουμε **δύο** γλώσσες στο ίδιο
 * προϊόν, άρα ένα υποχρεωτικό `name` θα μας ανάγκαζε σε **έναν από δύο** παραβάτες:
 *
 * ```
 *   name: 'Φύλλο1'   ⇒ σκληροκωδικωμένο ορατό κείμενο μέσα σε .ts   (κανόνας N.11)
 *   name: t('…')     ⇒ ΠΑΓΩΝΕΙ τη γλώσσα του δημιουργού μέσα στα δεδομένα, για πάντα
 * ```
 *
 * Η τρίτη επιλογή δεν έχει κανένα από τα δύο κόστη: **απουσία**. Απόν όνομα ⇒ *«το προεπιλεγμένο
 * όνομα της θέσης μου»*, που το αποφασίζει η **παρουσίαση** (Φάση 3) και ακολουθεί τη ζωντανή
 * γλώσσα. Η μετονομασία από τον χρήστη γράφει ρητό `name` και σταματά κάθε μαντεψιά — και τότε
 * το όνομα είναι **δεδομένο χρήστη**, που ταξιδεύει αυτούσιο και δεν μεταφράζεται ποτέ.
 *
 * Είναι η ίδια σύμβαση «απόν πεδίο ⇒ προεπιλογή» που ήδη κουβαλούν τα `absoluteRow?`/
 * `absoluteCol?` (ADR-754 Γ2) και τα παραλειπόμενα `edges`/`rowLinks` του
 * `toPersistedTableModel` — με το **επιπλέον** κέρδος ότι κρατά το JSON byte-identical για κάθε
 * πίνακα που γράφτηκε πριν υπάρξουν φύλλα.
 *
 * @module subapps/dxf-viewer/types/table-worksheet
 * @see types/table-entity.ts — η οντότητα που κρατά τα φύλλα
 * @see types/table-entity-legacy.ts — η **μία** κατοικία της παλιάς μορφής (`model`/`binding`)
 * @see bim/table/table-worksheet-resolve.ts — ο **ΕΝΑΣ** αναγνώστης
 * @see docs/centralized-systems/reference/adrs/ADR-833-table-xlsx-import-and-worksheets.md §5.2
 */

import type { PersistedTableModel, TableBinding } from './table';

/**
 * Σταθερή ταυτότητα φύλλου εργασίας — **branded**, με το ίδιο ιδίωμα και τον ίδιο λόγο με το
 * `CellKey` (`types/table-ids.ts`): η **μόνη** νόμιμη πηγή είναι το {@link tableWorksheetId},
 * ώστε να μην μπορεί να μπει γυμνό string που έτυχε να είναι `entityId` ή `rowId`.
 *
 * ⚠️ Επιβιώνει ακέραιη το JSON round-trip: το `JsonSafe` δοκιμάζει τα **πρωτόγονα πρώτα**,
 * ακριβώς για να μη θεωρηθεί ένα branded string αντικείμενο (δες `types/json-safe-entity.ts`).
 */
export type TableWorksheetId = string & { readonly __tableWorksheetIdBrand: unique symbol };

/**
 * Η **μόνη** νόμιμη πηγή ταυτότητας φύλλου. Καθαρή, μηδέν παρενέργειες.
 *
 * ⚠️ **Δεν παράγει** ταυτότητα — τη **βεβαιώνει**. Η παραγωγή της επόμενης ελεύθερης ταυτότητας
 * ανήκει στη Φάση 4 (προσθήκη φύλλου), όπου θα είναι το τρίτο αντίγραφο του μοτίβου
 * «μέγιστο+1 με βρόχο επαλήθευσης» του `nextAxisId` (`bim/table/table-row-column-ops.ts:85`) και
 * **τότε** θα εξαχθεί σε κοινό SSoT. Σήμερα ο πίνακας έχει **ένα** φύλλο με **σταθερή**
 * ταυτότητα ({@link FIRST_TABLE_WORKSHEET_ID}), άρα μια γεννήτρια θα ήταν υποδομή χωρίς
 * καταναλωτή — ακριβώς η «νεκρή παράμετρος» που το ADR-833 §5.4 αρνείται για το `sheetId`.
 */
export function tableWorksheetId(raw: string): TableWorksheetId {
  return raw as TableWorksheetId;
}

/**
 * Η ταυτότητα του **πρώτου** φύλλου κάθε πίνακα — και η ταυτότητα που παίρνει το μοναδικό φύλλο
 * κάθε πίνακα γραμμένου **πριν** υπάρξουν φύλλα.
 *
 * 🔴 **Ντετερμινιστική επίτηδες**, με το ίδιο σχήμα ονόματος που ήδη έχουν οι γραμμές (`r0`) και
 * οι στήλες (`c0`). Μια τυχαία ταυτότητα (`crypto.randomUUID`) θα σήμαινε ότι **η ίδια**
 * αποθηκευμένη οντότητα δίνει **διαφορετική** αναβάθμιση σε κάθε άνοιγμα — δηλαδή δύο αναγνώσεις
 * του ίδιου σχεδίου θα παρήγαγαν διαφορετικό JSON, και η εγγύηση «σχέδιο που μόνο διαβάστηκε
 * μένει byte-identical» θα έπεφτε στην πρώτη αποθήκευση.
 */
export const FIRST_TABLE_WORKSHEET_ID: TableWorksheetId = tableWorksheetId('ws0');

/**
 * Ένα φύλλο εργασίας: **όνομα, κελιά, και ο δεσμός τους**.
 *
 * Ό,τι είναι *ανά φύλλο* ζει εδώ· ό,τι είναι *ανά πίνακα* (θέση, γωνία, στυλ, breaking) μένει
 * στην οντότητα. Ο διαχωρισμός δεν είναι αυθαίρετος: το στυλ και η θέση είναι ιδιότητες του
 * **χαρτιού**, τα κελιά και ο δεσμός τους ιδιότητες του **περιεχομένου**.
 */
export interface TableWorksheet {
  readonly id: TableWorksheetId;

  /**
   * Το όνομα της καρτέλας **όπως το έγραψε ο χρήστης**. Απόν ⇒ το προεπιλεγμένο όνομα της θέσης
   * του, που παράγει η παρουσίαση στη **ζωντανή** γλώσσα — δες §3 της κεφαλίδας.
   *
   * ⚠️ Όταν υπάρχει, είναι **δεδομένο χρήστη**: ταξιδεύει αυτούσιο, δεν μεταφράζεται ποτέ, και
   * δεν το αγγίζει καμία αλλαγή γλώσσας.
   */
  readonly name?: string;

  /** Το **ΜΟΝΟ** σπίτι των κελιών αυτού του φύλλου. */
  readonly model: PersistedTableModel;

  /** Ο δεσμός **αυτού** του φύλλου με πηγή δεδομένων· απόν ⇒ `static` — δες §2 της κεφαλίδας. */
  readonly binding?: TableBinding;
}
