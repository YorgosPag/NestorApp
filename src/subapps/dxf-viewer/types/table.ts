/**
 * Οι τρεις κλάσεις γραμμής του AutoCAD TABLESTYLE. Καθορίζουν ΠΟΙΟ υποστυλ ισχύει
 * (γραμματοσειρά, γέμισμα, περιγράμματα) — δεν είναι διακοσμητική ετικέτα.
 */
export type TableRowClass = 'title' | 'header' | 'data';

export interface TableRow {
  readonly id: TableRowId;
  readonly rowClass: TableRowClass;
  /**
   * 🔴 ADR-739 §58 Γ2 — **η ΤΡΙΤΗ ΚΑΤΑΣΤΑΣΗ του ύψους, γραμμένη με ΕΝΑ πεδίο.**
   *
   * ```
   *   απών  ⇒ ΑΥΤΟΜΑΤΟ    — το ύψος προκύπτει από το περιεχόμενο (αναδιπλωμένες γραμμές),
   *                          με δάπεδο το `defaultRowHeightMm` της κλάσης γραμμής
   *   παρών ⇒ ΚΑΡΦΩΜΕΝΟ   — ο χρήστης το όρισε ρητά (σύρσιμο ορίου ή κουτιού)
   * ```
   *
   * ## Γιατί ΔΕΝ προστέθηκε δεύτερο πεδίο `autoHeight`
   * Το OOXML γράφει `ht` **και** `customHeight` — δύο πεδία για την ίδια απόφαση, άρα
   * **τέσσερις** συνδυασμοί από τους οποίους οι δύο δεν σημαίνουν τίποτα
   * (`customHeight` χωρίς `ht`· `ht` με `customHeight=false`). Η απουσία τιμής **είναι ήδη**
   * η δήλωση «δεν το αποφάσισα εγώ», και δεν μπορεί να διαφωνήσει με τον εαυτό της.
   *
   * ## 🏆 Πού ξεπερνά τους μεγάλους
   * | | Ύψος από περιεχόμενο | Κλείδωμα | Ορατή κατάσταση | Επαναφορά σε αυτόματο |
   * |---|---|---|---|---|
   * | **Excel** | ναι | ναι | **όχι** — σταματά σιωπηλά | μόνο διπλό κλικ στο όριο |
   * | **AutoCAD** | ναι | **όχι** — «cell height cannot be fixed» | — | — |
   * | **Revit** | ναι (μόνο στο φύλλο) | **όχι** — «not resizable» | — | — |
   * | **ArchiCAD** | ναι, **ανά στήλη** | ναι | ναι | διπλό κλικ / κουμπί |
   * | **ΝΕΣΤΩΡ** | ναι, **ανά κελί** | ναι | ναι | **ρητή εντολή** |
   *
   * Το λεξιλόγιο είναι σκόπιμα το ίδιο με το {@link TableColumnSizing} του **ίδιου** αρχείου
   * (`fixed` vs `hug`) — δηλαδή το μοντέλο της Figma, όπου η μετάβαση «αυτόματο → καρφωμένο»
   * είναι **ορατή κατάσταση** και όχι κρυφή παρενέργεια. Ο οριζόντιος άξονας το κάνει ήδη
   * σήμερα: μια `hug` στήλη **είναι** πλάτος που εξαρτάται από το περιεχόμενο.
   *
   * ⚠️ Ο κανόνας «ο πίνακας δεν μεγαλώνει μόνος του» (`table-range-clipboard.ts`) **δεν**
   * παραβιάζεται: εκείνος απαγορεύει τη σιωπηλή προσθήκη **γραμμών/στηλών** στο μοντέλο. Το
   * ύψος από αναδίπλωση δεν γράφει τίποτα στο μοντέλο — είναι **παράγωγο** της διάταξης,
   * ακριβώς όπως το `hug` πλάτος, και η γεωμετρία της οντότητας το ακολουθεί δομικά
   * (`computeTableEntityGeometry` χτίζει το bbox από το `layout.heightMm`).
   */
  readonly heightMm?: number;
  /**
   * Παράκαμψη της **πάνω** ακμής αυτής της γραμμής, σε όλο το πλάτος του πίνακα.
   *
   * Υπάρχει επειδή το row-class μοντέλο του AutoCAD δομικά **δεν μπορεί** να εκφράσει
   * «γραμμή πάνω από μία συγκεκριμένη γραμμή δεδομένων» — και αυτό ακριβώς είναι η
   * γραμμή-σύνολο, καθολικό μοτίβο κάθε πίνακα ποσοτήτων (το AutoCAD το λύνει με
   * per-cell border overrides· μία παράκαμψη ανά γραμμή είναι απλούστερη και αρκεί).
   * Απούσα ⇒ ισχύει ό,τι λέει η κλάση γραμμής.
   *
   * ADR-750 Φ1: **επίπεδο 2** της σειράς προτεραιότητας ακμών — νικιέται από τη ρητή ακμή
   * ({@link PersistedTableModel.edges}), που είναι η μόνη που μπορεί να μιλήσει για **ένα**
   * κελί αντί για ολόκληρο το πλάτος.
   */
  readonly borderTop?: TableBorderSpec;
  /**
   * ADR-739 Φ.Ε (Α2) — μορφοποίηση σε επίπεδο **γραμμής**. Επίπεδο 2 της σειράς
   * προτεραιότητας (§28.4): **νικά τη στήλη** (απόφαση Α6).
   *
   * Ο λόγος δεν είναι αυθαίρετος: η στήλη λέει «τι **είδους** δεδομένα είναι αυτά» (ποσό,
   * κωδικός, περιγραφή) και η γραμμή «τι **ρόλο** έχει αυτή η εγγραφή» (σύνολο, υποσύνολο,
   * επικεφαλίδα ομάδας). Όταν οι δύο διαφωνούν, ο ειδικότερος ρόλος είναι αυτός που ο
   * αναγνώστης του σχεδίου πρέπει να δει — μια γραμμή συνόλων μένει έντονη ακόμη κι όταν
   * περνά μέσα από στήλη που κανείς δεν έβαψε.
   */
  readonly styleOverride?: TableAxisStyleOverride;
}

