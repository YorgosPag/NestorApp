/**
 * Τι περιέχει ένα κελί. Στη Φάση Α **μόνο το `'text'` αξιολογείται**· τα υπόλοιπα
 * δηλώνονται από τώρα (το μοντέλο δεν αλλάζει σχήμα ανά φάση — αλλιώς κάθε φάση θα
 * ήταν breaking change για ό,τι έχει ήδη αποθηκευτεί) και η μηχανή τα περνά ως τιμή
 * χωρίς αξιολόγηση μέχρι να ανοίξει η φάση τους:
 * - `formula` → Φ.Ζ (`fast-formula-parser` πίσω από adapter, §9)
 * - `field`   → placeholders του text engine (ADR-344)
 * - `block` / `image` → DXF group codes 171=2 / 340 (§10)
 */
export type CellKind = 'text' | 'formula' | 'field' | 'block' | 'image';

export interface TableCell {
  readonly kind: CellKind;
  /** ΕΠΑΝΑΧΡΗΣΗ ADR-363 — `string | number | null`. */
  readonly value: ScheduleCellValue;
  /**
   * ADR-739 Φ.Ζ — ο τύπος του κελιού, **δεμένος σε ταυτότητες**. Μόνο όταν
   * `kind === 'formula'`· το {@link value} κρατά τότε το **αποτέλεσμα** (ή τον κωδικό
   * σφάλματος), ώστε ζωγράφος, μετρητής και εξαγωγή να μη μάθουν ποτέ ότι υπάρχουν τύποι.
   *
   * 🔴 **Δέντρο, όχι το κείμενο `'=SUM(C2:C9)'`** — όπως δήλωνε αυτή η γραμμή πριν γραφτεί η
   * φάση. Το `C2` είναι **θέση**: αποθηκευμένο ως κείμενο, μια εισαγωγή γραμμής στη μέση θα
   * άλλαζε σιωπηλά το τι σημαίνει, και η μόνη διόρθωση θα ήταν να ξαναγράφει κάθε δομική
   * πράξη όλους τους τύπους του πίνακα. Εδώ η αναφορά **είναι** το `rowId`/`colId`, και το
   * `C2` της γραμμής τύπων παράγεται κατ' απαίτηση — η υπόσχεση του §11 #7 γίνεται δομική
   * αντί για υποχρέωση που κάποιος πρέπει να θυμάται.
   */
  readonly formula?: TableFormula;
  /**
   * Παράκαμψη στυλ **αυτού** του κελιού πάνω από την κλάση γραμμής. Ο τύπος ζει στο
   * `bim/table/table-style.ts` και εισάγεται εκεί ως `Partial<TableCellStyle>` — εδώ
   * κρατιέται αδιαφανής ώστε το μοντέλο να μην εξαρτάται από το στυλ (το στυλ εξαρτάται
   * από το μοντέλο, όχι το αντίστροφο).
   */
  readonly styleOverride?: TableCellStyleOverride;
  /**
   * `live` mode (Φ.Η): κελί που **δεν** δέχεται write-back προς το μοντέλο της σκηνής
   * (π.χ. υπολογισμένο σύνολο). Ο χρήστης το βλέπει, δεν το γράφει.
   */
  readonly locked?: boolean;
  /**
   * ADR-750 Φ5 (Α2) — **οι διαγώνιες γραμμές** αυτού του κελιού.
   *
   * Ζουν **εδώ** και όχι στον χάρτη ακμών, και αυτό είναι κατηγορική διάκριση, όχι
   * προτίμηση αποθήκευσης (ADR-750 §6.3): μια διαγώνιος δεν μοιράζεται **ποτέ** με γείτονα,
   * άρα δεν έχει τη διφορούμενη ιδιοκτησία που γέννησε ολόκληρο το μοντέλο ακμών. Στον ίδιο
   * χάρτη θα της δινόταν σημασιολογία διαμοιρασμού που δεν έχει, και η μηχανή ένωσης
   * συνεχόμενων τμημάτων θα εξέταζε τμήματα που **δεν μπορούν** ποτέ να ενωθούν.
   */
  readonly diagonal?: TableCellDiagonals;
}

/**
 * ADR-750 Φ5 — οι δύο διαγώνιοι ενός κελιού, με τα ονόματα του OOXML (`diagonalUp` /
 * `diagonalDown`) ώστε η εισαγωγή/εξαγωγή `.xlsx` να μη χρειάζεται μεταφραστή.
 *
 * Καθεμία κρατά **δικό της** μολύβι, όπως στο Excel και στο OOXML: ένας διαγώνιος σταυρός με
 * λεπτή ↘ και παχιά ↗ είναι εκφράσιμος. Ένα κοινό μολύβι για τις δύο θα ήταν συμπίεση που
 * κανείς δεν ζήτησε και που η εισαγωγή ξένου αρχείου θα την έβλεπε αμέσως ως απώλεια.
 *
 * Και οι δύο **προαιρετικές**: το `{}` δεν είναι έγκυρη κατάσταση — η απουσία διαγωνίων
 * γράφεται ως απουσία **του πεδίου** (δες `clearTableRangeDiagonals`), ώστε ένας πίνακας
 * χωρίς διαγωνίους να παράγει byte-ταυτόσημο JSON με πριν.
 */
export interface TableCellDiagonals {
  /** ↗ — από την **κάτω-αριστερή** στην **πάνω-δεξιά** γωνία (OOXML `diagonalUp`). */
  readonly up?: TableBorderSpec;
  /** ↘ — από την **πάνω-αριστερή** στην **κάτω-δεξιά** γωνία (OOXML `diagonalDown`). */
  readonly down?: TableBorderSpec;
}

/**
 * Η παράκαμψη του **κελιού** — επίπεδο 1 της σειράς προτεραιότητας (§28.4), νικά τα πάντα.
 *
 * Είναι ο {@link TableAxisStyleOverride} **συν** το ξεχείλισμα: τα τυπογραφικά πεδία
 * δηλώνονται **μία φορά**, στη βάση. Ξαναγραμμένα εδώ θα ήταν το κλασικό sibling clone —
 * και, χειρότερα, ένα κελί θα μπορούσε κάποτε να αποκτήσει πεδίο που η στήλη δεν έχει, οπότε
 * το ίδιο merge θα έλεγε δύο διαφορετικά πράγματα ανάλογα με το επίπεδο.
 *
 * Δομικά ίδιο με `Partial<TableCellStyle>` (βλ. `bim/table/table-style.ts`), δηλωμένο
 * εδώ ώστε `types/table.ts` → `bim/table/table-style.ts` να μην γίνει κύκλος εισαγωγών.
 * Το στυλ αναφέρεται στο μοντέλο· το μοντέλο δεν αναφέρεται στο στυλ.
 *
 * ⚠️ **Μία ρητή εξαίρεση στο «δομικά ίδιο»** (ADR-739 Φ.Δ βήμα 5): το {@link overflow} ΔΕΝ
 * υπάρχει στο `TableCellStyle`. Το `TableCellStyle` είναι ό,τι χρειάζεται ο **ζωγράφος και ο
 * μετρητής** — και το ξεχείλισμα δεν είναι ούτε τυπογραφία ούτε χρώμα: είναι **απόφαση
 * διάταξης**, που καταναλώνεται μία φορά στο στάδιο `place` και δεν ταξιδεύει παρακάτω. Αν
 * μπορούσε να διαβαστεί από το `TableCellStyle`, κάθε backend θα μπορούσε να το ξαναρωτήσει
 * και να απαντήσει **αλλιώς** — ακριβώς η απόκλιση που το βήμα 5 υπάρχει για να κλείσει.
 * Η επίλυση (κελί → στήλη → προεπιλογή) ζει στο `table-layout-place.ts`, όπως και της
 * στοίχισης.
 */
export interface TableCellStyleOverride extends TableAxisStyleOverride {
  /** Παράκαμψη ξεχειλίσματος **αυτού** του κελιού· νικά το {@link TableColumn.overflow}. */
  readonly overflow?: TableCellOverflow;
}

/**
 * ADR-739 Φ.Ε (Α2) — μια **αραιή** παράκαμψη στυλ. **Ένας** τύπος για τους δύο άξονες
 * ({@link TableColumn.styleOverride} και {@link TableRow.styleOverride}) και βάση του
 * {@link TableCellStyleOverride}: δύο ταυτόσημα interfaces θα ήταν ακριβώς το σχήμα που
 * πιάνει το CHECK 3.28 (jscpd, N.18) και — το σοβαρό — δύο σημεία που μπορούν κάποτε να
 * αποκτήσουν διαφορετικό σύνολο πεδίων για την ίδια ακριβώς ερώτηση.
 *
 * ## 🔴 ΤΡΕΙΣ ΚΑΤΑΣΤΑΣΕΙΣ ΑΝΑ ΠΕΔΙΟ — η δοκτρίνα του CAD, χωρίς το ελάττωμά της
 *
 * ```
 *   πεδίο ΑΠΟΝ (undefined)  →  κληρονόμησε από το επόμενο επίπεδο
 *   πεδίο === null          →  ρητά ΚΑΝΕΝΑ / καθαρισμένο
 *   πεδίο === τιμή          →  ρητή τιμή
 * ```
 *
 * Το AutoCAD λύνει το ίδιο πρόβλημα με **δεσμευμένες τιμές μέσα στο ίδιο πεδίο**: DXF group
 * code 62 → `256` = BYLAYER (κληρονόμησε), `0` = BYBLOCK· lineweight → `-1` / `-2` / `-3`.
 * Δηλαδή η επαγγελματική δοκτρίνα είναι «**ένα** πεδίο, τρεις απαντήσεις» — ποτέ δεύτερο
 * παράλληλο boolean (`fillNone?`), που θα ήταν δεύτερη πηγή αλήθειας για την ίδια ερώτηση
 * και θα μπορούσε να αντιφάσκει με την πρώτη.
 *
 * Εδώ κρατάμε τη δοκτρίνα και **αφαιρούμε** το μειονέκτημά της: οι δεσμευμένες τιμές του
 * AutoCAD τρώνε από το πεδίο τιμών (χρώμα 256 δεν μπορεί να υπάρξει ποτέ). Το `null` δεν
 * συγκρούεται με καμία έγκυρη τιμή, **επιβιώνει** στο `JSON.stringify` — σε αντίθεση με το
 * `undefined`, που είναι ακριβώς ο λόγος που ο έλεγχος `in` απορρίφθηκε (βλ. `table-style.ts`)
 * — και ελέγχεται εξαντλητικά από τον μεταγλωττιστή.
 *
 * ## Ποιο πεδίο επιτρέπεται να είναι `null` — μηχανικός κανόνας, όχι κρίση
 *
 * **Ακριβώς** εκείνα που το επιλυμένο `TableCellStyle` δηλώνει **προαιρετικά**
 * (`fillColorHex`, `fontFamily`). Ένα πεδίο που ο ζωγράφος απαιτεί πάντα (ύψος, χρώμα
 * κειμένου, στοίχιση) δεν έχει «κανένα» να καθαριστεί σε — θα ήταν κατάσταση που κανείς δεν
 * μπορεί να αποδώσει.
 */
export interface TableAxisStyleOverride {
  readonly textHeightMm?: number;
  readonly textColorHex?: string;
  /** `null` ⇒ **ρητά χωρίς γέμισμα**, ακόμη κι όταν η κλάση γραμμής βάφει. */
  readonly fillColorHex?: string | null;
  readonly bold?: boolean;
  readonly italic?: boolean;
  readonly underline?: boolean;
  /** `null` ⇒ **ρητά η προεπιλογή του μετρητή**, ακόμη κι όταν η κλάση γραμμής δηλώνει άλλη. */
  readonly fontFamily?: string | null;
  /** 9 θέσεις (TL..BR) — DXF group code 170. */
  readonly align?: TableCellAlign;
}

/** Οι 9 θέσεις στοίχισης κελιού του `ACAD_TABLE` (group code 170). */
export type TableCellAlign =
  | 'TL' | 'TC' | 'TR'
  | 'ML' | 'MC' | 'MR'
  | 'BL' | 'BC' | 'BR';

// ──────────────────────────────────────────────────────────────────────────────
// Συγχωνεύσεις
// ──────────────────────────────────────────────────────────────────────────────

/**
 * Μια συγχώνευση κελιών. Η **άγκυρα** (πάνω-αριστερά κελί) κρατά το περιεχόμενο· τα
 * καλυμμένα κελιά δεν ζωγραφίζονται και τα εσωτερικά τους περιγράμματα παραλείπονται.
 * DXF: group codes 175 (πλάτος) / 176 (ύψος) στο κελί-άγκυρα.
 */
export interface CellSpan {
  readonly anchorRowId: TableRowId;
  readonly anchorColId: TableColumnId;
  /** Πλήθος γραμμών που καλύπτει, **μαζί** με την άγκυρα (≥1). */
  readonly rowSpan: number;
  /** Πλήθος στηλών που καλύπτει, **μαζί** με την άγκυρα (≥1). */
  readonly colSpan: number;
}

// ──────────────────────────────────────────────────────────────────────────────
// Το μοντέλο
// ──────────────────────────────────────────────────────────────────────────────

export interface TableModel {
  readonly columns: readonly TableColumn[];
  readonly rows: readonly TableRow[];
  /**
   * **Αραιός** χάρτης: μόνο τα μη-κενά / overridden κελιά. Ένας πίνακας 500×8 έχει
   * 4.000 θέσεις και σχεδόν όλες κενές· πυκνή αναπαράσταση θα σήμαινε 4.000
   * αντικείμενα σε **κάθε** στιγμιότυπο undo.
   */
  readonly cells: ReadonlyMap<CellKey, TableCell>;
  readonly merges: readonly CellSpan[];
  /**
   * ADR-750 Φ1 — το ευρετήριο των **ρητών** ακμών, παράγωγο του
   * {@link PersistedTableModel.edges}. Πάντα παρόν (ενδεχομένως κενό): ένα προαιρετικό
   * πεδίο εδώ θα σήμαινε ότι κάθε αναγνώστης πρέπει να θυμηθεί το `?.`, δηλαδή θα γεννούσε
   * δύο απαντήσεις στο «έχει ρητές ακμές;» — απούσα και κενή.
   */
  readonly edges: TableEdgeIndex;
}

// ──────────────────────────────────────────────────────────────────────────────
// Το σχήμα που ΤΑΞΙΔΕΥΕΙ (ADR-739 Φ.Δ — Λύση Α)
// ──────────────────────────────────────────────────────────────────────────────

/**
 * Ένα κελί όπως **ταξιδεύει**: τριάδα `[γραμμή, στήλη, κελί]`.
 *
 * Είναι το ΙΔΙΟ σχήμα που δέχεται ήδη το `CreateTableModelInput.cells` — απλώς
 * ονοματίστηκε. Νέο σχήμα εδώ θα σήμαινε τέταρτο λεξιλόγιο κελιού και μεταφραστές
 * παντού, ακριβώς η παγίδα που ο §3 απαγορεύει.
 */
export type TableCellEntry = readonly [TableRowId, TableColumnId, TableCell];

/**
 * Το **μοναδικό** σχήμα πίνακα που επιτρέπεται να διασχίσει `JSON.stringify` —
 * φωτοτυπία του {@link TableModel} με τα κελιά ως **ακολουθία** αντί για `Map`.
 *
 * ## Γιατί υπάρχει
 * Ο `Map` δεν επιβιώνει `JSON.stringify`: γίνεται `{}` **σιωπηλά**, χωρίς εξαίρεση και
 * χωρίς προειδοποίηση. Τρεις γενικοί μηχανισμοί της εφαρμογής περνούν κάθε οντότητα από
 * JSON round-trip (αποθήκευση σκηνής, `deepClone` για undo, διαγραφή+αναίρεση) — άρα ένας
 * πίνακας με `Map` έχανε **όλα** τα κελιά του σε καθέναν από αυτούς, δείχνοντας άδειο
 * πλέγμα μετά από reload ή undo. Το πρόχειρο (κλωνοποιεί με `structuredClone`, διατηρεί
 * τον `Map`) και η λανθάνουσα μνήμη ζωγραφικής (νεκρός κώδικας) δεν μετράνε — βλ.
 * `types/json-safe-entity.ts` για την πλήρη επαλήθευση.
 *
 * ## Γιατί ακολουθία και όχι αντικείμενο-λεξικό
 * Είναι το σχήμα που έχουν επιλέξει όλα τα σοβαρά φορμά πίνακα: το `ACAD_TABLE` γράφει
 * **ακολουθιακές εγγραφές κελιών** (group code 171 ανά κελί), το Kiwi της Figma δεν
 * διαθέτει καν τύπο χάρτη, το ίδιο ισχύει σε OOXML και Google Sheets. **Λίστα στο
 * αρχείο, ευρετήριο στη μνήμη.**
 *
 * Ο `TableModel` (με τον `Map`) παραμένει **αναλλοίωτος** και είναι ό,τι δέχονται η
 * μηχανή διάταξης και ο adapter· παράγεται κατ' απαίτηση και απομνημονευμένα από το
 * `resolveTableModel` (`bim/table/table-model-helpers.ts`) — παράγωγη μνήμη, ποτέ πηγή.
 */
export interface PersistedTableModel {
  readonly columns: readonly TableColumn[];
  readonly rows: readonly TableRow[];
  /** Μόνο τα μη-κενά κελιά, σε **ντετερμινιστική** σειρά γραμμής → στήλης (§4). */
  readonly cells: readonly TableCellEntry[];
  readonly merges: readonly CellSpan[];
  /**
   * ADR-750 Φ1 — οι **ρητές** ακμές περιγράμματος, σε ντετερμινιστική σειρά (ίδια αρχή με
   * τα κελιά). Ο χάρτης είναι αραιός: μόνο ό,τι όρισε ο χρήστης· τα υπόλοιπα προκύπτουν
   * από τη γραμμή-σύνολο και τις κλάσεις γραμμής.
   *
   * **Προαιρετικό επίτηδες**: κάθε ήδη αποθηκευμένος πίνακας παραμένει έγκυρος χωρίς
   * κανένα migration — η ρητή στρατηγική του σχολίου στο `TableCellOverflow` («απόν πεδίο
   * ⇒ προεπιλογή»). Δεν γράφεται καν όταν είναι κενό, ώστε πίνακας χωρίς ρητές ακμές να
   * παράγει **byte-ταυτόσημο** JSON με πριν.
   */
  readonly edges?: readonly TableEdgeEntry[];
}

