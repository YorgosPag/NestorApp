/**
 * Πώς αποφασίζεται το πλάτος μιας στήλης (§2.1 εύρημα 5 — το μοντέλο της Figma):
 * - `fixed` — ρητό πλάτος σε sheet-mm· ο χρήστης το κλείδωσε (drag λαβής ορίου).
 * - `hug`   — όσο χρειάζεται το **πλατύτερο περιεχόμενο** της στήλης (+ περιθώρια).
 * - `fill`  — μοιράζεται το υπόλοιπο πλάτος κατ' αναλογία `weight` προς τις άλλες `fill`.
 *
 * Το `frac` του ADR-622 είναι η φτωχή εκδοχή αυτού: εκφράζει **σημείο αγκύρωσης**, όχι
 * πλάτος — γι' αυτό ο σημερινός πίνακας δεν μπορεί να έχει κάθετες γραμμές.
 */
export type TableColumnSizing =
  | { readonly kind: 'fixed'; readonly widthMm: number }
  | { readonly kind: 'hug' }
  | { readonly kind: 'fill'; readonly weight: number };

/**
 * ADR-739 Φ.Δ βήμα 5 — **τι γίνεται όταν το κείμενο δεν χωρά στο κελί**.
 *
 * ## Γιατί είναι δεδομένο και όχι σταθερά κώδικα
 * Είναι το «Μορφοποίηση κελιών» του Excel και το «Format → Text wrapping» του Google Sheets
 * (Overflow / Wrap / Clip, **ανά κελί**). **Κανένα CAD δεν το δίνει ανά στήλη** — το AutoCAD
 * αναδιπλώνει πάντα και δεν έχει καν διακόπτη· το Revit αναδιπλώνει στο φύλλο αλλά όχι στην
 * όψη schedule. Είναι δηλαδή ένα από τα σημεία όπου ο ΝΕΣΤΩΡ **περνά** τους μεγάλους, με
 * μοντέλο δοκιμασμένο σε άλλο domain (Giorgio, 2026-08-01: «σταδιακά σε full parity Excel»).
 *
 * ## 🔴 Γιατί ΜΙΑ τιμή σήμερα, και όχι όλες οι μελλοντικές δηλωμένες από τώρα
 * Το `CellKind` δηλώνει από τη Φάση Α τιμές που δεν αξιολογούνται (`formula`/`field`/…) και
 * αυτό είναι σωστό εκεί: η μηχανή τις **περνά ως τιμή**, δηλαδή κάνει κάτι ορατά ουδέτερο.
 * Εδώ δεν ισχύει το ίδιο: ένα `'wrap'` που πέφτει σιωπηλά σε περικοπή θα ήταν **ψέμα του
 * τύπου** — ο χρήστης θα είχε ζητήσει αναδίπλωση και θα έβλεπε κομμένο κείμενο, χωρίς κανένα
 * σήμα. Κάθε νέα τιμή μπαίνει **μαζί** με τη μηχανή της. Η προσθήκη μέλους σε union δεν είναι
 * breaking change για ήδη αποθηκευμένους πίνακες (απόν πεδίο ⇒ προεπιλογή).
 *
 * ## Οι τιμές, και γιατί η καθεμιά μπήκε όταν μπήκε
 * - **`'clip'`** (Φ.Δ βήμα 5) — η προεπιλογή· κόβει με «…» ή «####».
 * - **`'shrink'`** (§58 Γ1, Excel *Shrink to Fit*) — **σμικρύνει** το κείμενο ώστε να χωρέσει
 *   σε **μία** γραμμή. Δεν αγγίζει το ύψος της γραμμής, άρα ούτε τη γεωμετρία της οντότητας:
 *   είναι καθαρά τυπογραφική πράξη μέσα στο ίδιο ορθογώνιο.
 * - **`'wrap'`** (§58 Γ2, AutoCAD/Excel) — **σπάει** το κείμενο σε γραμμές και αφήνει τη
 *   γραμμή να ψηλώσει· ο μόνος από τους τρεις που κλείνει βρόχο ανάδρασης
 *   `περιεχόμενο → ύψος → γεωμετρία οντότητας`.
 *
 * 🔴 **`'shrink'` και `'wrap'` είναι ΕΝΩΣΗ και όχι δύο σημαίες** — και αυτό δεν είναι
 * σχεδιαστική προτίμηση: στο «Μορφοποίηση κελιών» του Excel τα δύο κουτάκια είναι **αμοιβαία
 * αποκλειόμενα** (τσεκάροντας το ένα ξετσεκάρεται το άλλο), επειδή απαντούν στην **ίδια**
 * ερώτηση με ασύμβατους τρόπους: «όταν δεν χωρά, τι υποχωρεί — το **μέγεθος** ή το **ύψος**;»
 * Δύο booleans θα επέτρεπαν στον μεταγλωττιστή να δεχτεί «και τα δύο», που δεν σημαίνει
 * τίποτα, και κάθε καταναλωτής θα έπρεπε να επινοήσει δική του σειρά προτεραιότητας.
 *
 * Δηλωμένο εκτός εμβέλειας: **`'overflow'`** (ξεχείλισμα σε κενό γείτονα). Απορρίφθηκε ρητά
 * με τρία επιχειρήματα — δες `DEFAULT_TABLE_CELL_OVERFLOW` στο `table-cell-overflow.ts`.
 */
export type TableCellOverflow = 'clip' | 'shrink' | 'wrap';

export interface TableColumn {
  readonly id: TableColumnId;
  readonly sizing: TableColumnSizing;
  /** ΕΠΑΝΑΧΡΗΣΗ ADR-363 — οδηγεί μορφοποίηση αριθμών + στοίχιση εξαγωγής. */
  readonly valueType: ScheduleColumnValueType;
  readonly align: ScheduleColumnAlign;
  /**
   * Προεπιλογή ξεχειλίσματος για **όλα** τα κελιά της στήλης. Απούσα ⇒
   * `DEFAULT_TABLE_CELL_OVERFLOW`. Νικιέται από την παράκαμψη του κελιού — ίδια σειρά
   * προτεραιότητας με τη στοίχιση (`TableCellStyleOverride.align` → `TableColumn.align`).
   */
  readonly overflow?: TableCellOverflow;
  /**
   * ADR-739 Φ.Ε (Α2) — μορφοποίηση σε επίπεδο **στήλης**: ισχύει για κάθε κελί της, εκτός
   * όσων λένε κάτι δικό τους. Επίπεδο 3 της σειράς προτεραιότητας (§28.4).
   *
   * Ζει στη **στήλη** και όχι σε N αντίγραφα στα κελιά, ώστε μια νέα γραμμή να **κληρονομεί**
   * αυτόματα (ο κανόνας του Excel): αν η μορφοποίηση ήταν γραμμένη ανά κελί, κάθε νέα γραμμή
   * θα γεννιόταν άβαφη και ο χρήστης θα την ξαναέβαφε — δηλαδή ο λόγος ύπαρξης του μοντέλου
   * επιπέδου άξονα θα αναιρούνταν στο πιο ορατό σημείο.
   */
  readonly styleOverride?: TableAxisStyleOverride;
  /**
   * Κλειδί ανάγνωσης από `ExportableTableRow.cells` όταν ο πίνακας τρέφεται από
   * `ExportableTable` (`bound` / `live` mode). Σχεδιασμένο από τώρα κατά την
   * Απόφαση §14.2 («σχεδιάζεται στο μοντέλο, υλοποιείται στη φάση του»)· απών σε
   * `static` πίνακες που ο χρήστης πληκτρολογεί.
   */
  readonly sourceKey?: string;
}

