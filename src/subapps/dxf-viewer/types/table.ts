/**
 * Πόσο «ζωντανός» είναι ο πίνακας (§3 Αρχή 1):
 * - `static` — τα κελιά τα πληκτρολόγησε ο χρήστης (ανάλογο: AutoCAD TABLE).
 * - `bound`  — στιγμιότυπο από `ExportableTable`, με revision stamp ώστε να **δηλώνει**
 *   πότε είναι μπαγιάτικος (ανάλογο: AutoCAD Data Link — αλλά ο δικός μας δεσμός δείχνει
 *   στη ΣΚΗΝΗ, όχι σε εξωτερικό αρχείο Excel που μπορεί να μετακομίσει).
 * - `live`   — αναπαράγεται σε κάθε regen, με write-back (ανάλογο: Revit Schedule).
 */
export type TableBindingMode = 'static' | 'bound' | 'live';

export interface TableBinding {
  readonly mode: Exclude<TableBindingMode, 'static'>;
  /**
   * Τι παράγει τα δεδομένα: το τοπογραφικό παραδοτέο ή το schedule με τα φίλτρα του.
   *
   * 🔴 **ADR-767 Δ7 — ήταν `string` («αδιαφανές αναγνωριστικό»), έγινε διακριτή ένωση.**
   * Αδιαφανές σήμαινε ότι κάποιος θα έγραφε `'schedule:door?floor=FL01'`, και η δεύτερη πηγή
   * θα γεννούσε τον parser που θα το ξεδίπλωνε — μια δεύτερη γραμματική μέσα στο σύστημα.
   * Η αλλαγή ήταν ακίνδυνη επειδή το πεδίο **δεν είχε ούτε έναν αναγνώστη** όταν έγινε.
   */
  readonly sourceRef: TableSourceRef;
  /**
   * Αποτύπωμα των **δεδομένων που παρήγαγε ο resolver** την τελευταία ανανέωση. Διαφορά με
   * φρέσκια επίλυση ⇒ ο πίνακας είναι «μπαγιάτικος». Το ADR-720 έχει ήδη διδάξει ότι **ένα
   * κατασκευασμένο νούμερο σε παραδοτέο είναι μέτρηση που κανείς δεν πήρε** — παλιά νούμερα
   * χωρίς ένδειξη είναι σφάλμα **τιμής**, όχι εμφάνισης.
   *
   * 🔴 **ΠΕΡΙΕΧΟΜΕΝΟ, ποτέ ρολόι** (Δ5). Ούτε timestamp (Bazel: *«volatile statuses… would
   * make the cache useless»* — ένα refresh χωρίς πραγματική αλλαγή θα κοκκίνιζε τον πίνακα
   * άδικα), ούτε ο μετρητής του `SceneStore` (είναι **ανά level**: κάθε μετακίνηση τοίχου θα
   * κήρυσσε μπαγιάτικο τον πίνακα συντεταγμένων), ούτε το `generateSceneChecksum` (χασάρει
   * `entityCount+layerCount+bounds+units` — μια **κορυφή που μετακινήθηκε χωρίς να αλλάξουν
   * τα όρια είναι αόρατη σε αυτό**, δηλαδή αστοχεί ακριβώς στην περίπτωσή μας).
   *
   * ⚠️ Πεδίο **χωρίς συγκριτή δεν επιτρέπεται εδώ**: το ADR-745 αποθηκεύει
   * `TitleBlockBinding.snapshotValue` «για ανίχνευση απόκλισης» εδώ και μήνες και **κανείς
   * δεν το συγκρίνει ποτέ**. Ο συγκριτής αυτού του πεδίου είναι το
   * `bim/table/binding/table-binding-state.ts`, και γεννήθηκε μαζί του.
   */
  readonly revision: string;
}

/**
 * AutoCAD table breaking: όταν ο πίνακας ξεπερνά το `maxHeightMm`, σπάει σε τμήματα
 * δίπλα-δίπλα με επανάληψη κεφαλίδας. Δηλώνεται στο μοντέλο· υλοποιείται στη Φ.Γ μαζί
 * με τον renderer (εκεί υπάρχει ο καταναλωτής — όχι προληπτικά).
 */
export interface TableBreaking {
  readonly maxHeightMm: number;
  /** Οριζόντιο κενό ανάμεσα στα τμήματα (sheet-mm). */
  readonly gapMm: number;
  /** Επανάληψη των γραμμών `title`/`header` σε κάθε τμήμα (AutoCAD parity). */
  readonly repeatHeader: boolean;
}
