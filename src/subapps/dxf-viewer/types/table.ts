// Το σχήμα που ΤΑΞΙΔΕΥΕΙ (ADR-739 Φ.Δ — Λύση Α)
// ──────────────────────────────────────────────────────────────────────────────

/**
 * Ένα κελί όπως **ταξιδεύει**: τριάδα `[γραμμή, στήλη, κελί]`.
 *
 * Είναι το ΙΔΙΟ σχήμα που δέχεται ήδη το `CreateTableModelInput.cells` — απλώς
 * ονοματίστηκε. Νέο σχήμα εδώ θα σήμαινε τέταρτο λεξιλόγιο κελιού και μεταφραστές
 * παντού, ακριβώς η παγίδα που ο §3 απαγορεύει.
 */
export type TableCellEntry = readonly [TableRowId, TableColumnId, TableCell];

/**
 * Το **μοναδικό** σχήμα πίνακα που επιτρέπεται να διασχίσει `JSON.stringify` —
 * φωτοτυπία του {@link TableModel} με τα κελιά ως **ακολουθία** αντί για `Map`.
 *
 * ## Γιατί υπάρχει
 * Ο `Map` δεν επιβιώνει `JSON.stringify`: γίνεται `{}` **σιωπηλά**, χωρίς εξαίρεση και
 * χωρίς προειδοποίηση. Τρεις γενικοί μηχανισμοί της εφαρμογής περνούν κάθε οντότητα από
 * JSON round-trip (αποθήκευση σκηνής, `deepClone` για undo, διαγραφή+αναίρεση) — άρα ένας
 * πίνακας με `Map` έχανε **όλα** τα κελιά του σε καθέναν από αυτούς, δείχνοντας άδειο
 * πλέγμα μετά από reload ή undo. Το πρόχειρο (κλωνοποιεί με `structuredClone`, διατηρεί
 * τον `Map`) και η λανθάνουσα μνήμη ζωγραφικής (νεκρός κώδικας) δεν μετράνε — βλ.
 * `types/json-safe-entity.ts` για την πλήρη επαλήθευση.
 *
 * ## Γιατί ακολουθία και όχι αντικείμενο-λεξικό
 * Είναι το σχήμα που έχουν επιλέξει όλα τα σοβαρά φορμά πίνακα: το `ACAD_TABLE` γράφει
 * **ακολουθιακές εγγραφές κελιών** (group code 171 ανά κελί), το Kiwi της Figma δεν
 * διαθέτει καν τύπο χάρτη, το ίδιο ισχύει σε OOXML και Google Sheets. **Λίστα στο
 * αρχείο, ευρετήριο στη μνήμη.**
 *
 * Ο `TableModel` (με τον `Map`) παραμένει **αναλλοίωτος** και είναι ό,τι δέχονται η
 * μηχανή διάταξης και ο adapter· παράγεται κατ' απαίτηση και απομνημονευμένα από το
 * `resolveTableModel` (`bim/table/table-model-helpers.ts`) — παράγωγη μνήμη, ποτέ πηγή.
 */
export interface PersistedTableModel {
  readonly columns: readonly TableColumn[];
  readonly rows: readonly TableRow[];
  /** Μόνο τα μη-κενά κελιά, σε **ντετερμινιστική** σειρά γραμμής → στήλης (§4). */
  readonly cells: readonly TableCellEntry[];
  readonly merges: readonly CellSpan[];
  /**
   * ADR-750 Φ1 — οι **ρητές** ακμές περιγράμματος, σε ντετερμινιστική σειρά (ίδια αρχή με
   * τα κελιά). Ο χάρτης είναι αραιός: μόνο ό,τι όρισε ο χρήστης· τα υπόλοιπα προκύπτουν
   * από τη γραμμή-σύνολο και τις κλάσεις γραμμής.
   *
   * **Προαιρετικό επίτηδες**: κάθε ήδη αποθηκευμένος πίνακας παραμένει έγκυρος χωρίς
   * κανένα migration — η ρητή στρατηγική του σχολίου στο `TableCellOverflow` («απόν πεδίο
   * ⇒ προεπιλογή»). Δεν γράφεται καν όταν είναι κενό, ώστε πίνακας χωρίς ρητές ακμές να
   * παράγει **byte-ταυτόσημο** JSON με πριν.
   */
  readonly edges?: readonly TableEdgeEntry[];
  /**
   * ADR-739 Επίπεδο Β — οι δεσμοί γραμμής→οντότητες, σε ντετερμινιστική σειρά γραμμής
   * (ίδια αρχή με τα κελιά και τις ακμές). Ο χάρτης είναι αραιός: μόνο οι γραμμές που
   * δείχνουν κάπου.
   *
   * **Προαιρετικό επίτηδες**: κάθε ήδη αποθηκευμένος πίνακας παραμένει έγκυρος χωρίς κανένα
   * migration, και πίνακας χωρίς δεσμούς παράγει **byte-ταυτόσημο** JSON με πριν — δεν
   * γράφεται καν όταν είναι κενό. Ένα `rowLinks: []` θα ταξίδευε σε κάθε αποθηκευμένο
   * πίνακα του κόσμου, θα εμφανιζόταν σε κάθε diff ως «αλλαγή», και θα έσπαγε το
   * `persisted → runtime → persisted` ταυτοτικό για κάθε πίνακα γραμμένο πριν από τη φάση.
   */
  readonly rowLinks?: readonly TableRowLinkEntry[];
}

