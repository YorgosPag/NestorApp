/**
 * ADR-739 Φάση Δ — **ΦΡΟΥΡΟΣ 1 (τύπος)**: καμία οντότητα σκηνής δεν επιτρέπεται να γίνει
 * μη-σειριοποιήσιμη.
 *
 * ## Το σιωπηλό σφάλμα που γεννά αυτό το αρχείο
 * Ένας `Map` **δεν** επιβιώνει `JSON.stringify`: γίνεται `{}` — χωρίς εξαίρεση, χωρίς
 * προειδοποίηση, χωρίς σφάλμα τύπου. Τρεις **γενικοί** μηχανισμοί περνούν κάθε οντότητα
 * από JSON round-trip:
 *   1. αποθήκευση/επαναφόρτωση σκηνής (`services/dxf-firestore-storage.impl.ts`),
 *   2. αναίρεση (`UpdateEntityCommand` → `deepClone`),
 *   3. διαγραφή + αναίρεση (`DeleteEntityCommand`),
 * όπου `deepClone` **είναι** `JSON.parse(JSON.stringify())` (`src/lib/clone-utils.ts`).
 * Άρα μία οντότητα με `Map` (ή `Date`, ή συνάρτηση) δεν χαλάει σε ένα σημείο: χαλάει σε
 * **τρία**, και σε κανένα από αυτά δεν φωνάζει.
 *
 * Δύο ακόμη μηχανισμοί **έμοιαζαν** γενικοί αλλά ελέγχθηκαν ρητά και δεν είναι — γραμμένο
 * εδώ ρητά ώστε κανείς να μην αντιγράψει ξανά έναν αριθμό χωρίς να ανοίξει τα αρχεία:
 *   - `systems/clipboard/EntityClipboardStore.ts` (πρόχειρο): κλωνοποιεί με
 *     `structuredClone`, που **διατηρεί** τον `Map`· το `JSON.parse(JSON.stringify())`
 *     εκεί είναι fallback μόνο για runners χωρίς το global `structuredClone` — δεν
 *     συμβαίνει ούτε σε browser ούτε σε Node 20+.
 *   - `rendering/passes/EntityPass.ts` (`getCacheKey`, λανθάνουσα μνήμη ζωγραφικής):
 *     νεκρός κώδικας — το `RenderPipeline` που τον κατασκευάζει δεν καλείται από πουθενά
 *     στην παραγωγή, μόνο re-export από το barrel `rendering/passes/index.ts` (που ο
 *     ίδιος του ο τίτλος χαρακτηρίζει «DEADCODE»). Και ούτως ή άλλως το `JSON.stringify`
 *     εκεί είναι **κλειδί** μνήμης (cache key), όχι αποθήκευση δεδομένων· ένας `Map` που
 *     γίνεται `{}` δίνει μπαγιάτικο cache key, όχι απώλεια κελιών.
 *
 * ## Γιατί δεν αρκεί ένα συμβόλαιο «μόνο τύπου»
 * Το `TableEntity.model` άλλαξε σε `PersistedTableModel` (απλό JSON) και το πρόβλημα
 * **λύθηκε** — για τον πίνακα, σήμερα. Αυτό όμως είναι **συνήθεια**, όχι εγγύηση: ο
 * επόμενος που θα προσθέσει `cache: Map<...>` σε οποιαδήποτε οντότητα δεν θα συναντήσει
 * τίποτα να τον σταματήσει. Ακριβώς αυτό είναι το μάθημα του **ADR-650 §M10e**
 * (`services/dxf-scene-json.ts:52`): ο loader διάλεγε πεδία με το χέρι και **κάθε άλλο**
 * πεδίο της σκηνής χανόταν σιωπηλά· η διόρθωση δεν ήταν «πρόσθεσε τα τέσσερα πεδία που
 * λείπουν» αλλά spread-then-override, *«so no FUTURE field can regress this way either»*.
 * Το ίδιο σχήμα εδώ: δεν διορθώνουμε τον πίνακα — κάνουμε το σφάλμα **αδύνατο**.
 *
 * ## Δύο φρουροί, γιατί ο ένας δεν φτάνει
 * - **Εδώ (χρόνος μεταγλώττισης)**: ο compiler αρνείται τον τύπο.
 * - **`types/__tests__/entity-json-roundtrip-coverage.test.ts` (χρόνος εκτέλεσης)**:
 *   περνά κάθε ζωντανό `RENDERABLE_ENTITY_TYPE` από τον **πραγματικό** μηχανισμό και
 *   δείχνει το **ένοχο μονοπάτι**. Ο δεύτερος είναι ο ισχυρός: τρέχει.
 *
 * ⚠️ Αυτό το module είναι **μηδενικού χρόνου εκτέλεσης** πλην των βεβαιώσεων στο τέλος
 * (δύο `const` που υπάρχουν μόνο για να τις ελέγξει ο compiler — ίδιο μοτίβο με το
 * `_RENDERABLE_TYPES_ARE_ENTITY_TYPES` του `rendering/contract/renderable-entity-type.ts`).
 *
 * @module subapps/dxf-viewer/types/json-safe-entity
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §4, §18
 * @see types/__tests__/entity-json-roundtrip-coverage.test.ts — ο ζωντανός φρουρός
 * @see services/dxf-scene-json.ts — ADR-650 §M10e, το ίδιο μάθημα σε άλλο επίπεδο
 */

