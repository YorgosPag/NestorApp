/**
 * Η φωτοτυπία ενός τύπου **όπως επιβιώνει** ένα JSON round-trip. Ό,τι δεν επιβιώνει
 * γίνεται `never`, οπότε το αρχικό δεν είναι πια αναθέσιμο σε αυτό — και αυτή ακριβώς η
 * μη-αναθεσιμότητα είναι ο έλεγχος.
 *
 * Η σειρά των κλάδων **είναι** ο μηχανισμός:
 *  1. **Πρωτόγονα πρώτα** — αλλιώς ένα branded string (`CellKey = string & {…}`) θα
 *     θεωρούνταν αντικείμενο, θα χαρτογραφούνταν πάνω στα `keyof String` (μέθοδοι!) και
 *     θα απορριπτόταν ως συνάρτηση. Ψευδώς θετικό σε κάτι απολύτως νόμιμο.
 *  2. **Ό,τι χάνεται σιωπηλά** — `Map`/`Set` → `{}`, `Date` → string (δεν αναβιώνει ποτέ
 *     ως `Date`), `RegExp` → `{}`, `symbol`/συνάρτηση → το κλειδί **εξαφανίζεται**,
 *     `bigint` → **πετάει** (η μόνη περίπτωση που δεν είναι σιωπηλή).
 *     Ελέγχονται τα `ReadonlyMap`/`ReadonlySet` επίτηδες: ο `Map` τα επεκτείνει, οπότε
 *     πιάνονται και οι δύο γραφές με ένα σκέλος (το `TableModel.cells` είναι `ReadonlyMap`).
 *  3. **Πίνακες** πριν από αντικείμενα (ένας πίνακας *είναι* αντικείμενο).
 *  4. **Αντικείμενα** αναδρομικά. Ομομορφικό mapped type ⇒ τα προαιρετικά πεδία μένουν
 *     προαιρετικά και οι ενώσεις διανέμονται φυσιολογικά.
 *
 * `undefined` θεωρείται **ασφαλές**: το `JSON.stringify` απλώς παραλείπει το κλειδί, που
 * είναι ισοδύναμο με «απόν προαιρετικό πεδίο» — δεν χάνεται πληροφορία.
 */
type JsonSafe<T> =
  // 1. πρωτόγονα (και branded strings / ενώσεις κυριολεκτικών) — αυτούσια
  T extends string | number | boolean | null | undefined
    ? T
    // 2. ό,τι ΔΕΝ επιβιώνει το round-trip
    : T extends ReadonlyMap<unknown, unknown> | ReadonlySet<unknown> | Date | RegExp
      ? never
      : T extends symbol | bigint
        ? never
        : T extends (...args: never[]) => unknown
          ? never
          // 3. πίνακες (πριν τα αντικείμενα — ο πίνακας ΕΙΝΑΙ αντικείμενο)
          : T extends readonly (infer U)[]
            ? readonly JsonSafe<U>[]
            // 4. αντικείμενα, αναδρομικά
            : T extends object
              ? { readonly [K in keyof T]: JsonSafe<T[K]> }
              : T;

/**
 * `true` όταν ο τύπος επιβιώνει ακέραιος ένα JSON round-trip.
 *
 * Τα `[…]` δεν είναι διακοσμητικά: χωρίς αυτά η σύγκριση θα **διένεμε** πάνω σε κάθε
 * ένωση, οπότε ένα `Foo | undefined` θα απαντούσε «ναι» για το σκέλος `undefined` και
 * το αποτέλεσμα θα ήταν `true | false` — δηλαδή `boolean`, δηλαδή τίποτα.
 */
type IsJsonSafe<T> = [T] extends [JsonSafe<T>] ? true : false;

/**
 * **Διαγνωστικό**: τα ονόματα των πεδίων **πρώτου επιπέδου** που δεν επιβιώνουν. Το
 * hover πάνω σε `JsonUnsafeKeys<TableModel>` απαντά `'cells'` — δηλαδή λέει *ποιο* πεδίο
 * φταίει, όχι απλώς *ότι* κάτι φταίει.
 *
 * Επίτηδες **ρηχό**: το αναδρομικό μονοπάτι (`entity.model.cells → Map`) το δίνει ο
 * ανιχνευτής χρόνου εκτέλεσης του συνοδευτικού test, όπου είναι και χρήσιμο ως μήνυμα
 * αποτυχίας. Μια αναδρομική εκδοχή εδώ θα ήταν εύθραυστη σε βάθος στιγμιοτύπησης χωρίς
 * να προσθέτει τίποτα που δεν λέει ήδη ο φρουρός που τρέχει.
 */
export type JsonUnsafeKeys<T> = {
  [K in keyof T]-?: IsJsonSafe<T[K]> extends true ? never : K;
}[keyof T];

/**
 * Θετική βεβαίωση χρόνου-μεταγλώττισης. Χρήση:
 *
 * ```ts
 * const _PIN: AssertJsonSafe<MyEntity> = true;
 * ```
 *
 * Όσο ο τύπος είναι καθαρός, ο τύπος της βεβαίωσης είναι `true` και η ανάθεση περνά. Μόλις
 * μπει `Map`/`Set`/`Date`/συνάρτηση **οπουδήποτε μέσα του**, γίνεται `never` και η ανάθεση
 * **δεν μεταγλωττίζεται**. Δεν υπάρχει τρόπος να το «περάσεις» χωρίς να το προσέξεις.
 */
export type AssertJsonSafe<T> = IsJsonSafe<T> extends true ? true : never;

/**
 * Αρνητική βεβαίωση — η **απόδειξη ότι ο φρουρός δουλεύει**.
 *
 * Ένας έλεγχος που δεν έχει δείξει ποτέ κόκκινο δεν έχει αποδείξει τίποτα. Καρφώνοντας
 * έναν τύπο που *οφείλει* να απορρίπτεται, μια μελλοντική «απλοποίηση» του {@link JsonSafe}
 * που θα τον έκανε μονίμως πράσινο σπάει **εδώ**, αμέσως.
 */
type AssertNotJsonSafe<T> = IsJsonSafe<T> extends true ? never : true;

