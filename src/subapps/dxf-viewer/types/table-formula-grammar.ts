/**
 * 🔴 ADR-761 — **Η ΓΡΑΜΜΑΤΙΚΗ ΤΩΝ ΤΥΠΩΝ**: με τι χαρακτήρες *γράφεται* ένας τύπος, όχι τι
 * *σημαίνει*.
 *
 * Καθαρό type module (μηδέν runtime), αδελφό των `table-formula.ts` / `table-cell-format.ts`.
 * Ο επιλογέας ζει στο `bim/table/formula/table-formula-grammar.ts`.
 *
 * ## 🔴 Η ΔΙΑΚΡΙΣΗ ΠΟΥ ΕΛΕΙΠΕ: ΑΠΟΘΗΚΕΥΣΗ ≠ ΔΙΕΠΑΦΗ
 * Μέχρι το ADR-761 ο λεξικογράφος δεχόταν **μόνο** `,` ως διαχωριστή ορισμάτων, και το
 * επιχείρημα ήταν «αυτό γράφει το `ACAD_TABLE` στο DXF». Το επιχείρημα είναι σωστό και
 * **αφορά τη σειριοποίηση** — όχι το τι πληκτρολογεί ο άνθρωπος:
 *
 * | Εργαλείο | Τι έχει το **αρχείο** | Τι πληκτρολογεί ο **χρήστης** |
 * |---|---|---|
 * | **Excel / `.xlsx`** | *πάντα* αγγλικά ονόματα + `,` (τεκμηριωμένο: *«Formulae are always stored using English names and conventions; all the localisation happens in Excel»*) | `;` σε κάθε locale με δεκαδικό κόμμα |
 * | **Google Sheets** | κανονική μορφή | ό,τι λέει το locale **του εγγράφου** (File → Settings), όχι του χρήστη |
 * | **LibreOffice Calc** | κανονική μορφή | **ρητή ρύθμιση** (Tools → Options → Calc → Formula → Separators) |
 * | **AutoCAD** | `%lu4%pr2`, δεκαδικό πάντα `.` | ρύθμιση **του σχεδίου** (UNITS/DIMDSEP) |
 *
 * 🎯 **Η θέση του ΝΕΣΤΟΡΑ**: κανένας από αυτούς δεν έχει το πλεονέκτημά μας — **εμείς δεν
 * αποθηκεύουμε καν συμβολοσειρά**. Το `TableCell.formula` είναι **δέντρο** δεμένο σε
 * `rowId`/`colId` (ADR-739 §11 #7). Άρα η γραμματική δεν αγγίζει ούτε το μοντέλο, ούτε το
 * DXF, ούτε το `.xlsx`: είναι **αποκλειστικά** στρώμα διεπαφής, όπως το `cellDisplayText`
 * του ADR-760 είναι αποκλειστικά στρώμα εμφάνισης. Ίδιος κανόνας, δεύτερη εφαρμογή:
 * **τιμή ≠ γραφή**.
 *
 * ## 🔴 ΓΙΑΤΙ ΕΝΑ ΑΝΤΙΚΕΙΜΕΝΟ ΚΑΙ ΟΧΙ ΔΥΟ ΣΗΜΑΙΕΣ — οι κανόνες είναι ΣΥΖΕΥΓΜΕΝΟΙ
 * Στο ελληνικό Excel ισχύουν **μαζί** `;` για ορίσματα **και** `,` για δεκαδικό. Αν άλλαζε
 * μόνο ο διαχωριστής, το `=SUM(1,5; 2)` θα διαβαζόταν `SUM(1, 5, 2)` = **8 αντί για 3,5** —
 * σιωπηλά λάθος νούμερο σε πίνακα ποσοτήτων, δηλαδή σφάλμα **τιμής** και όχι εμφάνισης
 * (ADR-720). Δύο ανεξάρτητες ρυθμίσεις θα έκαναν αυτόν τον συνδυασμό **εκφράσιμο**· ένα
 * αντικείμενο με δύο έγκυρες τιμές τον κάνει **αδύνατο**.
 *
 * 🔑 Και από αυτό βγαίνει η αναλλοίωτη που κατοχυρώνει το test:
 * **σε κάθε έγκυρη γραμματική, ο διαχωριστής ΔΕΝ είναι ποτέ ο δεκαδικός.** Γι' αυτό ο
 * λεξικογράφος δεν χρειάζεται καμία διάκριση συμφραζομένων: ο ίδιος χαρακτήρας δεν μπορεί
 * να σημαίνει δύο πράγματα μέσα στην ίδια γραμματική.
 *
 * @module subapps/dxf-viewer/types/table-formula-grammar
 * @see bim/table/formula/table-formula-grammar.ts — ο επιλογέας (locale → γραμματική)
 * @see types/table-cell-format.ts — το locale του σχεδίου (ADR-760), η ΙΔΙΑ αυθεντία
 * @see docs/centralized-systems/reference/adrs/ADR-761-table-formula-grammar.md
 */

/** Ο χαρακτήρας που χωρίζει ορίσματα συνάρτησης. */
export type FormulaArgumentSeparator = ',' | ';';

/** Ο χαρακτήρας της δεκαδικής υποδιαστολής **μέσα σε τύπο**. */
export type FormulaDecimalSeparator = '.' | ',';

/**
 * **Πώς γράφεται ένας τύπος** — ένα αντικείμενο, δύο συζευγμένοι κανόνες.
 *
 * Καταναλώνεται από τον λεξικογράφο, τον αναλυτή, τον εκτυπωτή και την κατάσταση υπόδειξης.
 * Κανένα από τα τέσσερα δεν κρατά δικό του αντίγραφο χαρακτήρα (N.18).
 */
export interface TableFormulaGrammar {
  readonly argumentSeparator: FormulaArgumentSeparator;
  readonly decimalSeparator: FormulaDecimalSeparator;
}

/**
 * Η **κανονική** γραμματική: `,` ορίσματα, `.` δεκαδικό.
 *
 * Είναι αυτή που έχει το **αρχείο** — `.xlsx`, `ACAD_TABLE`, και κάθε φύλλο υπολογισμού στον
 * δίσκο του. Παραμένει πρώτης τάξεως πολίτης επειδή είναι η γραφή που φτάνει από αντιγραφή
 * αγγλόφωνου φύλλου, από τεκμηρίωση και από κάθε παράδειγμα στο διαδίκτυο.
 */
export const CANONICAL_FORMULA_GRAMMAR: TableFormulaGrammar = Object.freeze({
  argumentSeparator: ',',
  decimalSeparator: '.',
});

/**
 * Η γραμματική **του δεκαδικού κόμματος**: `;` ορίσματα, `,` δεκαδικό.
 *
 * Ελλάδα, Γερμανία, Ιταλία, Ισπανία, Γαλλία, Ολλανδία — παντού όπου το κόμμα είναι η
 * υποδιαστολή, ο διαχωριστής **οφείλει** να μετακινηθεί στο ερωτηματικό. Δεν είναι γούστο:
 * είναι η μόνη διέξοδος από το `=SUM(1,5;2)`.
 */
export const SEMICOLON_FORMULA_GRAMMAR: TableFormulaGrammar = Object.freeze({
  argumentSeparator: ';',
  decimalSeparator: ',',
});
