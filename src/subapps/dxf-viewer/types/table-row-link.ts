/**
 * ADR-739 Επίπεδο Β — **ο δεσμός μιας γραμμής πίνακα με οντότητες της σκηνής**.
 *
 * Καθαρό type module (μηδέν runtime, μηδέν React/canvas), στο ίδιο στρώμα με το
 * `table-edges.ts`. Η αλυσίδα εξαρτήσεων μένει αλυσίδα, ποτέ κύκλος:
 *
 * ```
 *   table-ids  →  table-row-link  →  table
 *   (ποιος)       (τι δείχνει)        (το μοντέλο)
 * ```
 *
 * ## 🔑 Γιατί ο δεσμός είναι ΡΗΤΟΣ — και γιατί αυτό δεν είναι υστέρηση
 * Στο Revit/ArchiCAD το schedule **ΕΙΝΑΙ query πάνω στα elements**: η γραμμή *είναι* το
 * στοιχείο, άρα το «Highlight in Model» δουλεύει χωρίς κανένα δέσιμο — δεν υπάρχει τίποτα
 * να δεθεί, η ταυτότητα είναι εγγενής. Ο Νέστωρ έχει **ελεύθερο spreadsheet** (ADR-739 §3):
 * ο χρήστης γράφει ό,τι θέλει σε ό,τι κελί θέλει. Η ταυτότητα **δεν** είναι εγγενής, άρα το
 * δέσιμο πρέπει να γίνει ρητό. Το βιομηχανικό πρότυπο για *ελεύθερο* παραδοτέο που δείχνει
 * σε *μοντέλο* είναι ακριβώς αυτό: Navisworks Quantification (model takeoff), Speckle →
 * Power BI («Object IDs — required for interactivity»), COBie `IFC_GUID`.
 *
 * ## 🔑 Γιατί ΔΥΟ είδη στόχου — το κενό που αφήνουν και οι δύο σχολές
 * Οι μεγάλοι έχουν **ή** το ένα **ή** το άλλο, ποτέ και τα δύο στον ίδιο πίνακα:
 *
 * | | Πώς δένει | Τι ΔΕΝ μπορεί |
 * |---|---|---|
 * | **ArchiCAD** Interactive Schedule | κριτήριο (Scheme Settings → Criteria) | «αυτά τα 3 συγκεκριμένα» |
 * | **Navisworks** Quantification | ρητή λίστα (selection set) | να επιβιώσει αλλαγή του μοντέλου |
 *
 * Το ίδιο το Navisworks παραδέχεται το κενό: δίπλα στα *selection sets* (στατική λίστα)
 * υπάρχουν τα *search sets* (αποθηκευμένο **κριτήριο**, αυτο-ενημερούμενο, εξαγώγιμο) —
 * και η βιομηχανική πρακτική θεωρεί τα δεύτερα ανώτερα ακριβώς επειδή δεν σπάνε σιωπηλά.
 *
 * Ένας πίνακας ποσοτήτων χρειάζεται **και τα δύο, ανά γραμμή**: η γραμμή «Εκσκαφή θεμελίων»
 * είναι κανόνας (ό,τι είναι θεμέλιο σε αυτόν τον όροφο), η επόμενη «Ειδικό τεμάχιο Χ» είναι
 * τρία συγκεκριμένα αντικείμενα που κανένα κριτήριο δεν περιγράφει. Ένα σχήμα που εκφράζει
 * μόνο το ένα αναγκάζει τον χρήστη να ψευτίσει το άλλο.
 *
 * ## 🔑 Γιατί ο ΣΤΟΧΟΣ είναι union και ΟΧΙ δύο προαιρετικά πεδία
 * `{ entityIds?, criteria? }` κάνει **τέσσερις** καταστάσεις εκφράσιμες, από τις οποίες οι
 * δύο είναι παράλογες (καμία, και οι δύο μαζί) — δηλαδή κάθε αναγνώστης θα έπρεπε να
 * αποφασίσει μόνος του τι σημαίνουν, και θα αποφάσιζε **διαφορετικά**. Με διακριτή ένωση οι
 * παράλογες καταστάσεις γίνονται **μη εκφράσιμες**: δεν επιλύονται καλύτερα, απλώς δεν
 * υπάρχουν. Ίδια αρχή με τη «μία ονομασία ανά ακμή» του {@link module:types/table-edges}.
 *
 * ## 🔴 Γιατί η ΚΑΤΑΣΤΑΣΗ (orphan κ.λπ.) ΔΕΝ ζει εδώ
 * Το «αυτός ο δεσμός δείχνει σε οντότητα που δεν υπάρχει πια» είναι **παράγωγο** — η
 * απάντηση αλλάζει κάθε φορά που αλλάζει η σκηνή, χωρίς να αγγιχτεί ο πίνακας. Αποθηκευμένο,
 * θα ήταν μπαγιάτικο σχεδόν πάντα: ακριβώς η παγίδα ADR-720 που το ίδιο το ADR-739 κατέγραψε
 * στο {@link TableBinding.revision} — *ένα κατασκευασμένο νούμερο σε παραδοτέο είναι μέτρηση
 * που κανείς δεν πήρε*. Η κατάσταση υπολογίζεται από τον resolver, τη στιγμή που ρωτιέται.
 *
 * @module subapps/dxf-viewer/types/table-row-link
 * @see bim/schedule/filters.ts — η ΥΠΑΡΧΟΥΣΑ μηχανή που εκτελεί το κριτήριο
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §7 επίπεδο Β
 */

import type { ScheduleFilterCriteria } from '../bim/schedule/types';
import type { TableRowId } from './table-ids';

/**
 * Ποιος γέννησε τον δεσμό.
 *
 * - `manual` — τον έφτιαξε **άνθρωπος** (επέλεξε στη σκηνή και ανέθεσε σε γραμμή). Ανάλογο:
 *   το *virtual takeoff* του Navisworks, που ρητά «cannot be refreshed» — και σωστά.
 * - `bound`  — τον παρήγαγε η μηχανή όταν ο πίνακας γεννήθηκε από `ExportableTable`.
 *
 * ## 🔴 Γιατί η διάκριση είναι απαραίτητη και όχι μεταδεδομένο πολυτελείας
 * Ο resolver της Φ.ΣΤ (`bound`/`live` regen) ξαναχτίζει γραμμές. Χωρίς αυτό το πεδίο θα
 * είχε **δύο** εξίσου εύλογες συμπεριφορές απέναντι σε έναν δεσμό που δεν αναπαράγεται από
 * την πηγή: να τον σβήσει (καθαρός regen) ή να τον κρατήσει (μη καταστροφικός). Θα διάλεγε
 * μία — σιωπηλά — και θα έτρωγε ανθρώπινη δουλειά. Με το `origin` η απάντηση είναι κανόνας,
 * όχι απόφαση: **ανθρώπινος δεσμός δεν σβήνεται ποτέ από μηχανή**· αν δεν επιβεβαιώνεται,
 * σημαδεύεται και **δείχνεται**.
 */
export type TableRowLinkOrigin = 'manual' | 'bound';

/**
 * **Ρητή λίστα** ταυτοτήτων — το selection set.
 *
 * `1:N` επίτηδες: μία γραμμή «Εκσκαφή θεμελίων» αντιστοιχεί σε Ν στοιχεία. Το ίδιο κάνει το
 * Navisworks (σέρνεις πολλά αντικείμενα σε **ένα** takeoff item).
 */
export interface TableRowLinkIds {
  readonly kind: 'ids';
  /**
   * Ταυτότητες `BimEntity.id`.
   *
   * ⚠️ **Ένα λεξιλόγιο, επαληθευμένο στον κώδικα**: το `schedule-builder.ts` γράφει
   * `entityId: entity.id`, ο `stampBimIdentity` γράφει `userData['bimId'] = <ίδιο id>`, και
   * το `Selection3DStore.selectedBimIds` κρατά τα ίδια. Άρα ο δεσμός ταξιδεύει από τον
   * πίνακα ως τον `BimSelectionHighlighter` **χωρίς μεταφραστή**. Δεύτερο λεξιλόγιο εδώ
   * (DXF entity id, `faceKey`) θα έδινε δεσμό που «αποθηκεύτηκε σωστά» και **δεν θα έβρισκε
   * ποτέ τίποτα**.
   */
  readonly entityIds: readonly string[];
}

/**
 * **Αποθηκευμένο κριτήριο** — το search set.
 *
 * ## 🔑 Μηδέν νέα μηχανή
 * Το {@link ScheduleFilterCriteria} και ο εκτελεστής του (`applyScheduleFilters`, 5 συνθετοί
 * άξονες με λογικό ΚΑΙ) **υπάρχουν ήδη** και είναι τεσταρισμένα από το ADR-363. Ο δεσμός δεν
 * φέρνει δική του γλώσσα ερωτημάτων· δείχνει σε αυτήν. Νέο λεξιλόγιο κριτηρίων εδώ θα ήταν
 * το δεύτερο, με μεταφραστές παντού — η παγίδα «2 λεξιλόγια ρόλων» του ADR-694, που το
 * `types/table.ts` έχει ήδη αποφύγει μία φορά επαναχρησιμοποιώντας το `ScheduleCellValue`.
 */
export interface TableRowLinkQuery {
  readonly kind: 'query';
  readonly criteria: ScheduleFilterCriteria;
}

/** Τι δείχνει η γραμμή — ρητή λίστα ή κανόνας. Ποτέ και τα δύο, ποτέ κανένα. */
export type TableRowLinkTarget = TableRowLinkIds | TableRowLinkQuery;

/** Ο δεσμός μιας γραμμής: τι δείχνει + ποιος τον γέννησε. */
export interface TableRowLink {
  readonly target: TableRowLinkTarget;
  readonly origin: TableRowLinkOrigin;
}

/**
 * Ένας δεσμός όπως **ταξιδεύει**: δυάδα `[γραμμή, δεσμός]`.
 *
 * **Λίστα στο αρχείο, ευρετήριο στη μνήμη** — η «Λύση Α» του ADR-739 §19.2, όπως εφαρμόζεται
 * ήδη στα κελιά ({@link TableCellEntry}) και στις ακμές ({@link TableEdgeEntry}). Ο `Map` δεν
 * επιβιώνει `JSON.stringify`: γίνεται `{}` **σιωπηλά**, και τρεις γενικοί μηχανισμοί της
 * εφαρμογής (αποθήκευση σκηνής, `deepClone` για undo, διαγραφή+αναίρεση) περνούν κάθε
 * οντότητα από JSON round-trip.
 */
export type TableRowLinkEntry = readonly [TableRowId, TableRowLink];

/**
 * Ο **αραιός** χάρτης δεσμών στη μνήμη: μόνο οι γραμμές που έχουν δεσμό.
 *
 * Απουσία γραμμής σημαίνει «αυτή η γραμμή δεν δείχνει πουθενά» — που είναι νόμιμη,
 * συνηθισμένη κατάσταση (γραμμή τίτλου, γραμμή συνόλου, ελεύθερο σχόλιο), όχι σφάλμα.
 */
export type TableRowLinkIndex = ReadonlyMap<TableRowId, TableRowLink>;
