/**
 * ΠΑΡΑΤΗΡΗΣΗ ΚΑΤΑΣΤΑΣΗΣ MODIFIERS — η πόρτα που **δεν μπορεί** να διεκδικήσει πλήκτρο.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΟ ΕΡΩΤΗΜΑ (ADR-711 §10)
 * ─────────────────────────────────────────────────────────────────────────────
 * Ο ratchet του ADR-711 ρωτά *«διεκδικεί αυτό το αρχείο πλήκτρο;»* και το μετρά
 * ψάχνοντας τη **συμβολοσειρά** `window.addEventListener('keydown'`. Είναι
 * **συντακτικό** κριτήριο για **σημασιολογική** ερώτηση, και γι' αυτό η λίστα
 * `BY_DESIGN` υπάρχει: κάθε φορά που κάποιος γράφει έναν **παθητικό παρατηρητή**,
 * προστίθεται μια γραμμή που **υπόσχεται σε πρόζα** ότι δεν διεκδικεί τίποτα.
 *
 * 🔑 **Μια υπόσχεση σε σχόλιο δεν είναι εγγύηση.** Τίποτα δεν εμποδίζει τον επόμενο
 * να γράψει `e.preventDefault()` μέσα σε έναν «παρατηρητή» — και τότε το `Tab`
 * ξαναπεθαίνει μέσα στα modals, με τη γραμμή της `BY_DESIGN` να λέει ότι όλα καλά.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * Η ΛΥΣΗ: ΙΚΑΝΟΤΗΤΑ ΜΕΣΩ ΤΥΠΟΥ
 * ─────────────────────────────────────────────────────────────────────────────
 * Ο παρατηρητής δέχεται **{@link ModifierSnapshot}**, ποτέ `KeyboardEvent`. Δεν
 * μπορεί να κάνει `preventDefault()` ούτε `stopPropagation()` επειδή **δεν κρατά
 * ποτέ το συμβάν**. Η παθητικότητα παύει να είναι υπόσχεση και γίνεται **δομή**.
 *
 * Ίδια αρχή με δύο φρουρούς που ήδη ζουν σε αυτό το repo:
 *   · `WorkspaceRef`  (CHECK 3.58) — «το ότι μπορείς να το κατασκευάσεις δεν σου
 *      δίνει άδεια»· η ικανότητα ταξιδεύει στον **τύπο**, όχι σε σύμβαση ονομάτων.
 *   · `InkVerdict`    (CHECK 3.45) — η αποτυχία είναι **λέξιμη**, γιατί ο τύπος
 *      επιστροφής αναγκάζει τον καλούντα να τη διαβάσει.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΜΗΔΕΝ ΝΕΟΙ ΑΚΡΟΑΤΕΣ — ΚΑΜΙΑ ΔΕΥΤΕΡΗ ΜΗΧΑΝΗ
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠️ Αυτό το αρχείο **δεν εγγράφει τίποτα**. Συνθέτει τους υπάρχοντες singletons
 * ({@link CtrlKeyTracker}, {@link ShiftKeyTracker}), που ήδη κατέχουν τον έναν
 * κύκλο ζωής (ADR-363) και έχουν **29 καταναλωτές**. Ένας δεύτερος ακροατής για
 * την ίδια ερώτηση θα ήταν ακριβώς το σχήμα του **ADR-749**: δύο μηχανές, μία
 * ερώτηση, και τελικά δύο απαντήσεις που αποκλίνουν.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΚΑΝΟΥΝ ΟΙ ΜΕΓΑΛΟΙ, ΚΑΙ ΠΟΥ ΤΟΥΣ ΞΕΠΕΡΝΑΜΕ
 * ─────────────────────────────────────────────────────────────────────────────
 * **VS Code** (`vs/base/browser/dom.ts`, `ModifierKeyEmitter`): ΕΝΑ singleton,
 * `keydown`/`keyup` σε capture στο `window`, επαναφορά στο `blur`, και — σωστά —
 * εκπέμπει **παράγωγο αντικείμενο κατάστασης** (`IModifierKeyStatus`) αντί για το
 * ωμό συμβάν. Το σχήμα εδώ είναι το ίδιο.
 *
 * **Figma** (μηχανικό ιστολόγιο, διεθνείς συντομεύσεις): οι συντομεύσεις είναι
 * **δεδομένα** — δηλώνονται σε JSON και περνούν από **έναν** matcher. Το
 * περιστατικό που περιγράφουν είναι το ίδιο μας σχήμα: η απόφαση «ποιος κατέχει το
 * πλήκτρο» παίρνεται σε **ένα** σημείο (`keydown`) και όλοι οι υπόλοιποι **υπακούν**.
 *
 * 🏆 **Ξεπερνάμε το VS Code σε δύο μετρημένα σημεία** — δες
 * {@link createModifierKeyTracker}: (α) η κατάσταση **ξαναδιαβάζεται** από κάθε
 * παρατηρούμενο συμβάν μέσω `getModifierState`, αντί να χτίζεται μόνο από
 * μεταβάσεις· (β) τρεις ακμές επαναφοράς (`blur` + `focus` + `visibilitychange`)
 * αντί για μία, γιατί το `blur` καλύπτει την αναχώρηση αλλά **όχι κάθε επιστροφή**.
 *
 * @see keyboard/createModifierKeyTracker.ts — ο ένας κύκλος ζωής
 * @see keyboard/global-shortcut-listener.ts — η ΑΛΛΗ πόρτα: εκεί ζουν οι accelerators
 * @see ADR-711 §10 · ADR-363
 */

import { CtrlKeyTracker } from './CtrlKeyTracker';
import { ShiftKeyTracker } from './ShiftKeyTracker';

/**
 * Ό,τι ξέρει το σύστημα για τα modifiers — **και τίποτε άλλο**.
 *
 * ⚠️ Το `ctrlKey` σημαίνει «Control **ή** Meta», γιατί έτσι το κρίνουν οι
 * καταναλωτές: σε Mac το `Meta` παίζει τον ρόλο του `Control`, και ένας κριτής που
 * τα ξεχώριζε θα έκανε την αντιγραφή **αδύνατη** εκεί. Η ισοδυναμία δηλώνεται μία
 * φορά, στο `match` του {@link CtrlKeyTracker}, και **δεν** ξαναγράφεται εδώ.
 *
 * Το σχήμα είναι σκόπιμα δομικά συμβατό με ό,τι διαβάζει ένας `MouseEvent`
 * καταναλωτής (`ctrlKey`/`shiftKey`), ώστε η μετανάστευση να μην αλλάζει κριτές.
 */
export interface ModifierSnapshot {
  /** Control **ή** Meta — ισοδύναμα κατά τον κριτή. */
  readonly ctrlKey: boolean;
  readonly shiftKey: boolean;
}

/** Στιγμιότυπο τώρα. Φθηνή ανάγνωση — καμία συνδρομή React. */
export function readModifierSnapshot(): ModifierSnapshot {
  return {
    ctrlKey: CtrlKeyTracker.getSnapshot(),
    shiftKey: ShiftKeyTracker.getSnapshot(),
  };
}

/**
 * 🔴 **Η ΣΕΙΡΑ ΕΙΝΑΙ ΔΗΛΩΜΕΝΗ, ΟΧΙ ΣΥΜΠΤΩΣΗ.**
 *
 * Πριν από αυτή την πόρτα, δύο παρατηρητές του **ίδιου** πλήκτρου συνυπήρχαν με
 * αντικρουόμενες ανάγκες: η μεταφορά περιοχής **γράφει** τον ενεργό δείκτη, ο
 * γραφέας του δείκτη τον **διαβάζει**. Η προτεραιότητα προέκυπτε από τη **φάση**
 * (σύλληψη έναντι αναπήδησης) — μηχανισμός που δούλευε, αλλά ήταν πλάγιος: ο λόγος
 * ζούσε σε δώδεκα γραμμές σχολίου, και το ελάττωμα που τον γέννησε το βρήκε **η
 * οθόνη** (§31: *ο δείκτης δεν επιτρέπεται να ψεύδεται*).
 *
 * ⚠️ Αν και οι δύο γίνουν απλοί συνδρομητές, η σειρά γίνεται **σειρά εγγραφής** —
 * και ο αναγνώστης προσαρτάται στη **μόνιμη** λειτουργία, δηλαδή **πρώτος**, ενώ ο
 * γραφέας γεννιέται με τη σύρση. Θα ήταν το ίδιο σφάλμα, ξαναγραμμένο ανάποδα.
 *
 * Ίδιο ιδίωμα με το `ESC_PRIORITY` του {@link EscapeCommandBus} (ADR-364), που
 * τεκμηριώνει **αυτολεξεί** την ίδια παγίδα: *«ο bus σπάει την ισοπαλία με σειρά
 * εγγραφής — δηλαδή με το ποιος προσαρτήθηκε πρώτος, που εδώ είναι σύμπτωση του
 * lazy loading και όχι απόφαση»*.
 */
export const MODIFIER_OBSERVER_PRIORITY = {
  /** P100 — **γράφει** κατάσταση που άλλοι παρατηρητές διαβάζουν στο ίδιο πέρασμα. */
  STATE_PRODUCER: 100,
  /** P200 — **διαβάζει** ό,τι έγραψε ο παραγωγός. Η προεπιλογή. */
  STATE_CONSUMER: 200,
} as const;

interface Observer {
  readonly priority: number;
  readonly onChange: (snapshot: ModifierSnapshot) => void;
}

const observers: Observer[] = [];
let unsubscribeTrackers: (() => void) | null = null;

/** Ένα πέρασμα, σε **αύξουσα** προτεραιότητα. Ισοπαλία ⇒ σειρά εγγραφής, όπως ο bus. */
function emitToAll(): void {
  const snapshot = readModifierSnapshot();
  // Αντίγραφο: ένας παρατηρητής επιτρέπεται να αποδεσμευτεί μέσα στο πέρασμα.
  for (const observer of [...observers]) observer.onChange(snapshot);
}

/**
 * Ειδοποιεί όταν **αλλάζει** η κατάσταση των modifiers.
 *
 * ⚠️ Ο καλών παίρνει **στιγμιότυπο**, όχι συμβάν — δες την κεφαλίδα. Αν χρειάζεσαι
 * το συμβάν, τότε δεν παρατηρείς: **διεκδικείς**, και η σωστή πόρτα είναι το
 * `registerGlobalShortcut` του {@link global-shortcut-listener}, που ρωτά «κατέχει
 * κάποιος άλλος το πληκτρολόγιο τώρα;» πριν σε αφήσει να τρέξεις.
 *
 * @returns αποδέσμευση.
 */
export function observeModifierSnapshot(
  onChange: (snapshot: ModifierSnapshot) => void,
  priority: number = MODIFIER_OBSERVER_PRIORITY.STATE_CONSUMER,
): () => void {
  const observer: Observer = { priority, onChange };
  // Σταθερή εισαγωγή: το `findIndex` βρίσκει τον **πρώτο** αυστηρά μεγαλύτερο, άρα
  // ίσες προτεραιότητες κρατούν σειρά εγγραφής.
  const at = observers.findIndex((other) => other.priority > priority);
  observers.splice(at === -1 ? observers.length : at, 0, observer);

  if (!unsubscribeTrackers) {
    // Το `subscribe` του κάθε tracker πυροδοτεί **μόνο σε αλλαγή** (`Object.is` στο
    // `createExternalStore`), οπότε δεν χρειάζεται δικό μας φίλτρο ισότητας.
    const stopCtrl = CtrlKeyTracker.subscribe(emitToAll);
    const stopShift = ShiftKeyTracker.subscribe(emitToAll);
    unsubscribeTrackers = () => {
      stopCtrl();
      stopShift();
    };
  }

  return () => {
    const index = observers.indexOf(observer);
    if (index !== -1) observers.splice(index, 1);
    if (observers.length === 0 && unsubscribeTrackers) {
      unsubscribeTrackers();
      unsubscribeTrackers = null;
    }
  };
}
