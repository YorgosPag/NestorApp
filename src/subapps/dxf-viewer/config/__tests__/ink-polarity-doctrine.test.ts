/**
 * ADR-771 Φ.4 — **η ΜΕΖΟΥΡΑ με την οποία διαλέγεται η πολικότητα του αυτόματου μελανιού.**
 *
 * ## Γιατί υπάρχει αυτό το αρχείο
 * Η Φ.4 σχεδίαζε μετάβαση σε **APCA (WCAG 3)**. Μετρήθηκε και **απορρίφθηκε** (ADR-771 §6).
 * Η απόρριψη όμως δεν αφήνει ίχνος στον κώδικα: το `maxContrastInk` φαίνεται *σήμερα* ίδιο
 * είτε τη σκεφτήκαμε είτε όχι. Χωρίς άγκυρα, ο επόμενος (ή ο ίδιος, σε έξι μήνες) την
 * ξαναπροτείνει από την αρχή — και, χειρότερα, μπορεί να την **εφαρμόσει** χωρίς να πέσει
 * τίποτα κόκκινο.
 *
 * ## 🔴 ΤΟ ΚΕΝΟ ΠΟΥ ΚΛΕΙΝΕΙ — και γιατί δεν το κάλυπτε το υπάρχον test
 * Το `bim/table/__tests__/table-ink.test.ts` έχει ήδη *«η επιλογή είναι ΠΑΝΤΑ ο νικητής της
 * αντίθεσης, σε όλο το φάσμα του γκρι»*. Είναι σωστό test για **άλλη** ερώτηση, και για αυτή
 * εδώ είναι **ταυτολογικό**: υπολογίζει τον αναμενόμενο νικητή καλώντας το **ίδιο**
 * `contrastRatio` που χρησιμοποιεί η υλοποίηση. Αν αύριο αλλάξει η **μεζούρα** — APCA, CIE L*,
 * οτιδήποτε — αλλάζουν **και τα δύο σκέλη μαζί** και το test μένει **πράσινο πάνω στην αλλαγή
 * που υποτίθεται ότι φυλάει**. Είναι το ίδιο σχήμα με τα 170 tests της Φ.1 και τα 67 της Φ.3:
 * *το test επιβεβαιώνει ότι ο κώδικας συμφωνεί με τον εαυτό του.*
 *
 * Γι' αυτό εδώ **κάθε αναμενόμενη τιμή είναι ΣΤΑΘΕΡΑ**, γραμμένη από τη μέτρηση — ποτέ
 * υπολογισμένη από τη συνάρτηση που κρίνεται.
 *
 * ## Οι τρεις μεζούρες και τα σύνορά τους (μετρημένα 2026-08-07, βήμα 1 στον άξονα του γκρι)
 * ```
 *   WCAG 2 (σημερινή)  λευκό μέχρι και το #757575          ← ΤΟ ΣΗΜΕΡΙΝΟ ΣΥΝΟΡΟ
 *   CIE L* (ISO 11664) λευκό μέχρι και το #767676   (+1)
 *   APCA   (WCAG 3)    λευκό μέχρι και το #a3a3a3   (+46)  ← 29,15% όλου του κύβου sRGB
 * ```
 * Τα δύο πρώτα διαφέρουν σε **μία** τιμή γκρι· η τρίτη σε **46**. Ένα test που κλειδώνει το
 * σύνορο στο `#757575`/`#767676` απορρίπτει **και τις δύο** εναλλακτικές, χωρίς να χρειάζεται
 * να τις υλοποιεί.
 *
 * ## Το πρότυπο της βιομηχανίας για ΤΗΝ ΙΔΙΑ ερώτηση
 * Το CSS `contrast-color()` (Baseline 04/2026) ορίζεται κατά λέξη ως ο δικός μας κανόνας:
 * *«returns a value of `white` or `black`, depending on which value has the **greatest
 * contrast** with the input color. If both … have the same contrast, **`white` is returned**»*
 * — argmax, ισοπαλία → λευκό, πάνω σε WCAG. Το `maxContrastInk` **είναι** αυτό.
 *
 * ⚠️ **Η ισοπαλία ΔΕΝ ελέγχεται εδώ, και δηλώνεται αντί να προσποιηθεί**: εξισώνεται σε
 * `L = √(1,05·0,05) − 0,05 ≈ 0,179129`, τιμή που **κανένα** από τα 16.777.216 χρώματα sRGB δεν
 * πετυχαίνει ακριβώς. Ένα test για αυτήν θα ήταν φρουρός που **δεν μπορεί να πυροδοτήσει**
 * (ADR-749 §5) — ακριβώς ό,τι το έργο μετρά ως «αδρανή φρουρό».
 *
 * @see ../adaptive-entity-color.ts — `maxContrastInk`: ο κανόνας ACI 7
 * @see ../../bim/table/table-ink.ts — ο καταναλωτής: το αυτόματο μελάνι κελιού
 * @see docs/centralized-systems/reference/adrs/ADR-771-table-surface-doctrine.md §6
 */

import {
  _clearAdaptiveColorCache,
  maxContrastInk,
} from '../adaptive-entity-color';
import { contrastRatio } from '../color-math';
import {
  AUTOMATIC_TABLE_INK,
  resolveTableCellStyleInk,
} from '../../bim/table/table-ink';
import type { TableCellStyle } from '../../bim/table/table-style';

/** Το τελευταίο γκρι που παίρνει **λευκό** μελάνι κατά WCAG 2. Σταθερά, όχι υπολογισμός. */
const LAST_WHITE_GREY = '#757575';
/** Το πρώτο γκρι που παίρνει **μαύρο**. Μαζί με το παραπάνω ορίζουν το σύνορο **ακριβώς**. */
const FIRST_BLACK_GREY = '#767676';

/**
 * Η χειρότερη δυνατή επιφάνεια σε **ολόκληρο** τον κύβο sRGB — βρέθηκε με εξαντλητική σάρωση
 * και **των 16.777.216** χρωμάτων, όχι με δείγμα. Η Φ.3 είχε αποδείξει το φράγμα μόνο για τα
 * 256 ουδέτερα γκρι· εδώ επεκτείνεται σε κάθε απόχρωση.
 */
const WORST_POSSIBLE_SURFACE = '#cf0dcc';

/**
 * 🔴 **ΔΥΟ ΑΡΙΘΜΟΙ, ΟΧΙ ΕΝΑΣ — και το πλήρωσε η πρώτη γραφή.**
 *
 * Είχαν γραφτεί ως **ένας**, στρογγυλεμένος στο `4,5826`, και χρησιμοποιήθηκε ταυτόχρονα ως
 * «η μέτρηση» **και** ως «το αυστηρό κάτω φράγμα». Η σάρωση τον έριξε αμέσως: το πραγματικό
 * ελάχιστο είναι `4,58259052`, δηλαδή **κάτω** από τον στρογγυλεμένο. Δύο σημασίες σε ένα
 * όνομα είναι ADR-749 σε μικρογραφία — εδώ σε δύο δεκαδικά.
 *
 * Η διαφορά τους **δεν** είναι θόρυβος: το θεωρητικό φράγμα προκύπτει από **συνεχές** `L`, ενώ
 * το πλέγμα των 8 bit δεν έχει χρώμα ακριβώς εκεί. Άρα το `8BIT` είναι πάντα **λίγο πάνω** —
 * και αυτό είναι το τεστ που δείχνει ότι μετράμε τον πραγματικό κόσμο, όχι τον τύπο.
 *
 * ⚠️ Και η **δεύτερη** γραφή τους μπέρδεψε: το `4,58259052` που είχε γραφτεί ως «η χειρότερη
 * περίπτωση» ήταν το ελάχιστο της **σάρωσης βήματος 8** — δηλαδή ενός *άλλου* χρώματος, γιατί
 * το `#cf0dcc` δεν είναι πολλαπλάσιο του 8 και δεν συμμετείχε καν. Δύο μετρήσεις με διαφορετικό
 * πληθυσμό δεν μοιράζονται όνομα.
 */
/** Κλειστός τύπος `√(1,05·0,05)/0,05` — το θεωρητικό ελάχιστο πάνω σε **συνεχές** `L`. */
const THEORETICAL_FLOOR = 4.582575694956;
/**
 * Το πραγματικό ελάχιστο στα 16.777.216 χρώματα των 8 bit, στο {@link WORST_POSSIBLE_SURFACE}.
 * Απέχει **1,2 × 10⁻⁷** από το θεωρητικό: το πλέγμα των 8 bit αγγίζει πρακτικά το όριο.
 */
const WORST_8BIT_BEST = 4.582575814942;
/** WCAG 2 AA για κείμενο. Το φράγμα είναι **πάνω** από αυτό — με περιθώριο +0,0826. */
const AA_TEXT = 4.5;

const cellStyle = (over: Partial<TableCellStyle> = {}): TableCellStyle => ({
  textHeightMm: 2.5,
  textColorHex: AUTOMATIC_TABLE_INK,
  bold: false,
  italic: false,
  underline: false,
  align: 'left',
  indentLevel: 0,
  margins: { leftMm: 1, rightMm: 1, topMm: 0.5, bottomMm: 0.5 },
  ...over,
});

const greyHex = (v: number): string => `#${v.toString(16).padStart(2, '0').repeat(3)}`;

beforeEach(() => {
  _clearAdaptiveColorCache();
});

// ─────────────────────────────────────────────────────────────────────────────
// Μ0 — ΒΑΘΜΟΝΟΜΗΣΗ. Καμία ετυμηγορία πριν από αυτήν.
// ─────────────────────────────────────────────────────────────────────────────

describe('Μ0 — βαθμονόμηση: το όργανο μετρά αυτό που νομίζουμε', () => {
  /**
   * Στη Φ.3 η βαθμονόμηση έπιασε **πραγματικό** σφάλμα στην πρώτη εκτέλεση: δύο SSoT με
   * αντίθετες συμβάσεις μονάδων (0..1 vs 0..255) απαντούσαν «20,9 για κάθε επιφάνεια», δηλαδή
   * «όλα εντάξει, πάντα». Χωρίς αυτόν τον έλεγχο, όλα τα παρακάτω μπορούν να είναι πράσινα
   * μετρώντας κάτι άλλο.
   */
  it('λευκό vs μαύρο = 21,00 — αλλιώς ΚΑΝΕΝΑ από τα υπόλοιπα δεν σημαίνει τίποτα', () => {
    expect(contrastRatio('#ffffff', '#000000')).toBeCloseTo(21, 6);
  });

  it('ταυτόσημα χρώματα = 1,00', () => {
    expect(contrastRatio('#4a7c2f', '#4a7c2f')).toBeCloseTo(1, 6);
  });
});

// ─────────────────────────────────────────────────────────────────────────────
// Α — ΤΟ ΣΥΝΟΡΟ, ΜΕ ΣΤΑΘΕΡΕΣ
// ─────────────────────────────────────────────────────────────────────────────

describe('Α — το σύνορο πολικότητας είναι ΤΟ WCAG 2, κλειδωμένο σε σταθερές', () => {
  it('🔴 #757575 → ΛΕΥΚΟ και #767676 → ΜΑΥΡΟ: το σύνορο, ακριβώς', () => {
    expect(maxContrastInk(LAST_WHITE_GREY)).toBe('#ffffff');
    expect(maxContrastInk(FIRST_BLACK_GREY)).toBe('#000000');
  });

  it('🔴 απορρίπτει το CIE L* — θα μετακινούσε το σύνορο κατά ΜΙΑ τιμή (#767676 → λευκό)', () => {
    // Το CIE L* γυρίζει στο 50 στο #767676 (μετρημένο L* = 50,03). Μια μεζούρα βασισμένη σε
    // ισοαπόσταση L* θα έδινε ΛΕΥΚΟ εκεί. Δίνουμε ΜΑΥΡΟ — και αυτό είναι η διαφορά.
    expect(maxContrastInk(FIRST_BLACK_GREY)).not.toBe('#ffffff');
  });

  it('🔴 απορρίπτει την APCA — θα μετακινούσε το σύνορο κατά 46 τιμές (μέχρι #a3a3a3)', () => {
    // Και τα τρία βρίσκονται ΜΕΣΑ στη ζώνη διαφωνίας WCAG 2 ↔ APCA. Η APCA δίνει ΛΕΥΚΟ και
    // στα τρία· εμείς ΜΑΥΡΟ. Αν κάποιο από αυτά γυρίσει σε λευκό, η μεζούρα άλλαξε.
    for (const midTone of ['#808080', '#909090', '#a0a0a0']) {
      expect(maxContrastInk(midTone)).toBe('#000000');
    }
  });

  it('🔴 και δίνει το ΣΩΣΤΟ: στο #a0a0a0 το μαύρο ξεχωρίζει 3× περισσότερο από το λευκό', () => {
    // Ο λόγος που η APCA απορρίφθηκε δεν είναι η άδεια — είναι ότι εδώ έχει άδικο ΓΙΑ ΕΜΑΣ:
    // ο πίνακας τυπώνεται, και σε χαρτί το λευκό στα 2,61:1 είναι πρακτικά αόρατο.
    expect(contrastRatio('#000000', '#a0a0a0')).toBeCloseTo(8.03, 1);
    expect(contrastRatio('#ffffff', '#a0a0a0')).toBeCloseTo(2.61, 1);
  });

  it('τα άκρα δεν είναι αμφίβολα: καθαρό μαύρο → λευκό, καθαρό λευκό → μαύρο', () => {
    expect(maxContrastInk('#000000')).toBe('#ffffff');
    expect(maxContrastInk('#ffffff')).toBe('#000000');
  });

  it('🔴 η μετάβαση συμβαίνει ΜΙΑ φορά — καμία δεύτερη εναλλαγή στον άξονα του γκρι', () => {
    // Μια μεζούρα με σφάλμα στρογγυλοποίησης ή με δύο κλάδους που αποκλίνουν θα έδειχνε
    // «λευκό, μαύρο, λευκό». Το argmax μιας μονότονης ποσότητας δεν μπορεί.
    let flips = 0;
    for (let v = 1; v <= 255; v += 1) {
      if (maxContrastInk(greyHex(v)) !== maxContrastInk(greyHex(v - 1))) flips += 1;
    }
    expect(flips).toBe(1);
  });
});

// ─────────────────────────────────────────────────────────────────────────────
// Β — ΤΟ ΦΡΑΓΜΑ: το αυτόματο μελάνι δεν πέφτει ΠΟΤΕ κάτω από το AA κειμένου
// ─────────────────────────────────────────────────────────────────────────────

describe('Β — το φράγμα, αποδεδειγμένο σε ΚΑΘΕ απόχρωση και όχι μόνο στα γκρι', () => {
  it('🔴 η χειρότερη ΔΥΝΑΤΗ επιφάνεια όλου του κύβου δίνει 4,58259:1 — πάνω από το AA 4,5', () => {
    // Βρέθηκε με εξαντλητική σάρωση 16.777.216 χρωμάτων. Συμφωνεί με τον κλειστό τύπο της
    // Φ.3 — και είναι ΛΙΓΟ πάνω του, όπως επιβάλλει το πλέγμα των 8 bit.
    const ink = maxContrastInk(WORST_POSSIBLE_SURFACE);
    const best = contrastRatio(ink, WORST_POSSIBLE_SURFACE);
    expect(best).toBeCloseTo(WORST_8BIT_BEST, 9);
    expect(best).toBeGreaterThan(THEORETICAL_FLOOR);
    expect(best).toBeGreaterThan(AA_TEXT);
  });

  it('🔴 ΚΑΜΙΑ επιφάνεια δεν πέφτει κάτω από το φράγμα — σάρωση 32.768 χρωμάτων', () => {
    // Βήμα 8 σε κάθε κανάλι. Δεν είναι δείγμα «για να περάσει»: το φράγμα είναι κλειστός τύπος
    // και η σάρωση το επιβεβαιώνει, δεν το ορίζει.
    let worst = Number.POSITIVE_INFINITY;
    for (let r = 0; r < 256; r += 8) {
      for (let g = 0; g < 256; g += 8) {
        for (let b = 0; b < 256; b += 8) {
          const hex = `#${[r, g, b].map((c) => c.toString(16).padStart(2, '0')).join('')}`;
          worst = Math.min(worst, contrastRatio(maxContrastInk(hex), hex));
        }
      }
    }
    expect(worst).toBeGreaterThan(THEORETICAL_FLOOR);
    expect(worst).toBeGreaterThanOrEqual(WORST_8BIT_BEST);
    expect(worst).toBeGreaterThan(AA_TEXT);
  });

  it('άκυρη επιφάνεια ⇒ μαύρο — αποτυγχάνουμε προς την ΑΝΑΣΤΡΕΨΙΜΗ πλευρά', () => {
    expect(maxContrastInk('όχι-χρώμα')).toBe('#000000');
    expect(maxContrastInk('')).toBe('#000000');
  });
});

// ─────────────────────────────────────────────────────────────────────────────
// Γ — Η Φ.4 ΚΛΕΙΔΩΜΕΝΗ ΩΣ «ΔΕΝ ΕΓΙΝΕ»
// ─────────────────────────────────────────────────────────────────────────────

describe('Γ — το μελάνι κελιού ΔΕΝ εξαρτάται από μέγεθος ή βάρος κειμένου', () => {
  /**
   * 🔑 **Αυτό είναι η Φ.4, κλειδωμένη.** Το μοναδικό πράγμα που θα πρόσφερε η APCA πάνω από
   * τον σημερινό κανόνα είναι κατώφλι **ευαίσθητο σε μέγεθος και βάρος**. Ο πίνακας όμως δεν
   * έχει κατώφλι κειμένου καθόλου — πάει στο άκρο (ACI 7). Άρα το `textHeightMm` και το `bold`
   * **δεν επιτρέπεται** να αγγίζουν το αποτέλεσμα.
   *
   * Αν κάποιος τα βάλει στην απόφαση, αυτό εδώ πέφτει — και είναι το **μόνο** test του έργου
   * που θα το κάνει.
   */
  it('🔴 ίδια επιφάνεια, 6 συνδυασμοί μεγέθους/βάρους ⇒ ΕΝΑ μελάνι', () => {
    for (const surface of ['#1d283a', '#ffffff', '#808080', '#a0a0a0']) {
      const inks = new Set<string>();
      for (const textHeightMm of [1.2, 2.5, 12]) {
        for (const bold of [false, true]) {
          inks.add(resolveTableCellStyleInk(cellStyle({ textHeightMm, bold }), surface).textColorHex);
        }
      }
      expect(inks.size).toBe(1);
    }
  });

  it('🔴 και το μελάνι είναι ΑΚΡΙΒΩΣ ο κανόνας του maxContrastInk πάνω στο γέμισμα', () => {
    // Το γέμισμα νικά την επιφάνεια· η πολικότητα κρίνεται ως προς ΑΥΤΟ.
    const resolved = resolveTableCellStyleInk(cellStyle({ fillColorHex: '#a0a0a0' }), '#1d283a');
    expect(resolved.textColorHex).toBe('#000000');
    expect(resolved.textColorHex).toBe(maxContrastInk('#a0a0a0'));
  });
});
