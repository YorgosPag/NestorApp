/**
 * 🔴 ADR-739 §27.16 Ε4 — **ΠΟΣΟ ΤΟΠΟ ΠΙΑΝΕΙ ΜΙΑ ΛΑΒΗ ΣΤΗΝ ΟΘΟΝΗ.** Μία απάντηση, δύο μορφές.
 *
 * ## Το πρόβλημα, μετρημένο
 * Ο τύπος `(gripSize ?? 5) × (dpiScale ?? 1) + 2` ήταν γραμμένος **τέσσερις** φορές
 * (`useUnifiedGripInteraction` ×3, `useLayerCanvasMouseMove` ×1) και ο φραγμός
 * `Math.max(…, GRIP_CONFIG.HIT_TOLERANCE)` **μόνο σε μία**. Δύο συνέπειες, και οι δύο
 * αόρατες σε κάθε test που τρέχει στις προεπιλογές:
 *
 * 1. **Φωτίζει αλλού, πιάνει αλλού.** Με `gripSize` μικρότερο από 6, ο ωμός τύπος πέφτει
 *    κάτω από το δάπεδο των 8 px. Ο χειριστής **αλληλεπίδρασης** το ανέβαζε στο δάπεδο· ο
 *    χειριστής **hover** του layer canvas όχι. Ο χρήστης βλέπει λαβή αναμμένη και το κλικ
 *    δεν την πιάνει — ή το αντίστροφο.
 * 2. **Ο πίνακας (§27.11) άφηνε σταθερό κενό 8 px** ενώ η ζωντανή οπή είναι **9** στις
 *    προεπιλογές (`GRIP_SIZE_DEFAULT = 7`). Το ίδιο το ADR-739 το κατέγραψε ως «ειλικρινές
 *    όριο» και έγραψε ρητά: «*θέλει η οπή να γίνει συνάρτηση SSoT που θα καταναλώνουν και
 *    οι δύο*». Αυτό είναι εκείνη η συνάρτηση.
 *
 * ## Γιατί ΔΥΟ συναρτήσεις και όχι μία
 * Είναι **δύο διαφορετικές ποσότητες**, και η σύγχυσή τους ήταν μέρος του προβλήματος:
 * το {@link gripSizePx} είναι το **σχήμα** (πόσο μεγάλο ζωγραφίζεται, πόσο μακρύ είναι το
 * μπράτσο του glyph μετακίνησης)· το {@link gripAperturePx} είναι η **ευαισθησία** (από πόσο
 * μακριά απαντά). Η δεύτερη είναι πάντα ≥ της πρώτης, ποτέ το ανάποδο.
 *
 * ## Γιατί στο `config/` και δίπλα στο `grip-size-default.ts`
 * Εκεί ζει ήδη η **τιμή** (`GRIP_SIZE_DEFAULT`, με δικό του anti-drift test). Εδώ ζει ο
 * **κανόνας** που τη χρησιμοποιεί. Καθαρές συναρτήσεις: μηδέν store, μηδέν React, μηδέν DOM —
 * ώστε να μπορούν να τις καλέσουν και ο ζωγράφος και το hit-test και η γεωμετρία του πίνακα
 * χωρίς καμία εξάρτηση.
 *
 * @module subapps/dxf-viewer/config/grip-aperture
 * @see config/tolerance-config.ts — η **τιμή** του δαπέδου (SSoT)
 * @see config/grip-size-default.ts — η **τιμή** της προεπιλογής (SSoT)
 * @see bim/table/table-indicator-geometry.ts — ο δεύτερος καταναλωτής (§27.11)
 */

import { TOLERANCE_CONFIG } from './tolerance-config';

/**
 * Οι μόνες δύο ρυθμίσεις που μετράνε εδώ. Δομικός τύπος (όχι `GripSettings`) ώστε να τον
 * ικανοποιεί **κάθε** καλών — ο ένας έχει ολόκληρο το `GripSettings`, ο άλλος μια φέτα του.
 */
export interface GripApertureSettings {
  readonly gripSize?: number;
  readonly dpiScale?: number;
}

/**
 * Οι προεπιλογές των **καλούντων**, όχι του εργοστασίου.
 *
 * ⚠️ Και τα τέσσερα αντίγραφα έγραφαν `?? 5` / `?? 1.0` — **όχι** το `GRIP_SIZE_DEFAULT = 7`.
 * Η διαφορά είναι σκόπιμα διατηρημένη: αυτό είναι το «τι κάνω όταν **δεν** μου έδωσαν
 * ρύθμιση», ενώ το `GRIP_SIZE_DEFAULT` είναι «τι γράφω στο εργοστασιακό προφίλ». Στην
 * πράξη ο ζωντανός δρόμος περνά πάντα τιμή· αλλάζοντας το `5` σε `7` εδώ θα μεγάλωνε
 * σιωπηλά κάθε ανοχή σε κάθε δρόμο που ξεχνά να περάσει ρύθμιση — αλλαγή συμπεριφοράς
 * μεταμφιεσμένη σε «καθαριότητα».
 */
const FALLBACK_GRIP_SIZE = 5;
const FALLBACK_DPI_SCALE = 1;

/** Το **μέγεθος** της λαβής σε px οθόνης: πόσο μεγάλη ζωγραφίζεται και πιάνεται ως σχήμα. */
export function gripSizePx(settings: GripApertureSettings = {}): number {
  return (settings.gripSize ?? FALLBACK_GRIP_SIZE) * (settings.dpiScale ?? FALLBACK_DPI_SCALE);
}

/**
 * Πόσο περιθώριο πέρα από το ίδιο το σχήμα απαντά η λαβή. **Δύο pixel** — όσο χρειάζεται
 * ώστε το χέρι να μη χρειάζεται ακρίβεια pixel, χωρίς να κλέβει τον γείτονα.
 */
const CAPTURE_MARGIN_PX = 2;

/**
 * 🔴 Η **ΟΠΗ ΣΥΛΛΗΨΗΣ**: από πόσο μακριά απαντά μια λαβή, σε px οθόνης.
 *
 * `max(μέγεθος + περιθώριο, δάπεδο)`. Το **δάπεδο** (`TOLERANCE_CONFIG.GRIP_APERTURE`, το ίδιο που διαβάζει και το `GRIP_CONFIG.HIT_TOLERANCE`) δεν είναι
 * διακοσμητικό: χωρίς αυτό, ένας χρήστης που κατεβάζει το `gripSize` στο 1 φτιάχνει λαβές
 * που πρακτικά δεν πιάνονται — και **τις βλέπει**, γιατί το ζωγραφισμένο σχήμα δεν
 * εξαφανίζεται. Ήταν ήδη γραμμένο, αλλά **μόνο σε έναν** από τους τέσσερις δρόμους.
 *
 * ⚠️ **Καταναλώνεται και από τη γεωμετρία του πίνακα** (§27.11): η ζώνη δείκτη αρχίζει
 * ακριβώς εκεί που η λαβή σταματά να πιάνεται. Πριν, το κενό ήταν σταθερά `8` και η οπή
 * `9` — 1 px επικάλυψη στις προεπιλογές, **αναλογικά μεγαλύτερη** σε κάθε αύξηση του
 * `gripSize`. Τώρα οι δύο πλευρές διαβάζουν την **ίδια** έκφραση, οπότε η επικάλυψη δεν
 * είναι πια εκφράσιμη.
 */
export function gripAperturePx(settings: GripApertureSettings = {}): number {
  return Math.max(gripSizePx(settings) + CAPTURE_MARGIN_PX, TOLERANCE_CONFIG.GRIP_APERTURE);
}
