/**
 * ADR-767 Δ6 — **η ΜΙΑ μηχανή αποτυπώματος** (`utils/fnv1a-hash.ts`).
 *
 * ## Γιατί αυτό το test υπάρχει πριν από τον κώδικα που το ικανοποιεί
 * Το ADR-767 Δ6 έγραφε *«το `fnv1aBase36` είναι **ιδιωτική** συνάρτηση ⇒ εξήγαγέ το σε κοινό
 * SSoT **ΠΡΙΝ** γραφτεί ο δεύτερος καταναλωτής»*. Το grep της υλοποίησης έδειξε ότι ο δεύτερος
 * **είχε ήδη γραφτεί**: ο ίδιος βρόχος FNV-1a ζούσε αυτούσιος σε δύο αρχεία
 * (`title-block-fingerprint.ts:44` → base36, `revisions/revision-snapshot.ts:52` → hex8), με
 * μόνη διαφορά την **κωδικοποίηση της εξόδου**. Η εξαγωγή δεν είναι λοιπόν προληπτική· είναι
 * η διόρθωση ενός υπαρκτού διπλότυπου (N.0.2).
 *
 * ## 🔴 Γιατί οι ΧΡΥΣΕΣ ΤΙΜΕΣ είναι η ουσία και όχι διακόσμηση
 * Και τα δύο hash **ταξιδεύουν σε αποθηκευμένα δεδομένα**: το base36 μέσα στο QR της
 * πινακίδας (`?v=…`, ADR-651 Φ.Λ) και το hex8 μέσα στις υπογραφές αναθεώρησης
 * (`revision-snapshot`). Μια «αθώα» αλλαγή στον αλγόριθμο ή στην κωδικοποίηση δεν θα έσπαγε
 * κανένα άλλο test — θα δήλωνε **κάθε ήδη αποθηκευμένη αναθεώρηση ως τροποποιημένη** και θα
 * έκανε κάθε τυπωμένο QR να δείχνει λάθος έκδοση. Οι σταθερές παρακάτω υπολογίστηκαν από τον
 * **υπάρχοντα** κώδικα πριν την εξαγωγή: είναι το συμβόλαιο ότι η μετακόμιση δεν άλλαξε τιμή.
 */

import { fnv1a32, fnv1aBase36, fnv1aHex8 } from '../fnv1a-hash';

/** Υπολογισμένα από τον ΠΡΟ-εξαγωγής κώδικα (και των δύο αρχείων) — μη τα «διορθώσεις». */
const GOLDEN: readonly (readonly [string, string, string])[] = [
  ['', 'ztntfp', '811c9dc5'],
  ['a', '1r9wi7g', 'e40c292c'],
  ['A-2', 'haguqb', '3e512d93'],
  ['proj_1|A-2|3', '139he9r', '8d82077f'],
  ['ΑΒΓ', '1s5e6wr', 'e7333f7b'],
];

describe('fnv1a-hash — το SSoT αποτύπωμα', () => {
  it('παράγει ΑΚΡΙΒΩΣ τις τιμές του κώδικα πριν την εξαγωγή (base36 + hex8)', () => {
    for (const [input, base36, hex8] of GOLDEN) {
      expect(fnv1aBase36(input)).toBe(base36);
      expect(fnv1aHex8(input)).toBe(hex8);
    }
  });

  it('είναι ντετερμινιστικό: ίδια είσοδος ⇒ ίδια έξοδος, κάθε φορά', () => {
    const input = 'το ίδιο κείμενο, δύο κλήσεις';
    expect(fnv1aBase36(input)).toBe(fnv1aBase36(input));
    expect(fnv1a32(input)).toBe(fnv1a32(input));
  });

  it('🔴 ΔΕΝ είναι αθροιστικό: η ΣΕΙΡΑ των χαρακτήρων μετράει', () => {
    // Το `CollaborationManager` χασάρει με `reduce((acc, c) => acc + c.charCodeAt(0))`:
    // εκεί το 'abc' και το 'cba' δίνουν το ΙΔΙΟ hash. Ένα αποτύπωμα περιεχομένου που δεν
    // ξεχωρίζει αναδιάταξη είναι τυφλό ακριβώς στην περίπτωση «οι ίδιες κορυφές, άλλη σειρά».
    expect(fnv1aBase36('abc')).not.toBe(fnv1aBase36('cba'));
    expect(fnv1aBase36('abc')).toBe('7aigaz');
    expect(fnv1aBase36('cba')).toBe('e9jdv');
  });

  it('αλλαγή ΕΝΟΣ χαρακτήρα αλλάζει το αποτύπωμα', () => {
    expect(fnv1aBase36('1000.0')).not.toBe(fnv1aBase36('1000.1'));
  });

  it('το hex8 έχει ΠΑΝΤΑ 8 χαρακτήρες — και όταν το hash είναι μικρό', () => {
    // Χωρίς `padStart` ένα hash με ηγετικά μηδενικά θα έβγαινε κοντύτερο και δύο υπογραφές
    // θα μπορούσαν να συγχέονται όταν ενωθούν με διαχωριστικό.
    expect(fnv1aHex8('cba')).toBe('016d9863');
    for (const [input] of GOLDEN) expect(fnv1aHex8(input)).toHaveLength(8);
  });

  it('το fnv1a32 επιστρέφει ΑΝΥΠΟΓΡΑΦΟ 32-bit — ποτέ αρνητικό', () => {
    // `Math.imul` δίνει προσημασμένο αποτέλεσμα· χωρίς το `>>> 0` το `toString(36)` θα
    // κολλούσε πρόσημο μείον μέσα σε token που ταξιδεύει σε URL.
    for (const [input] of GOLDEN) {
      const hash = fnv1a32(input);
      expect(hash).toBeGreaterThanOrEqual(0);
      expect(hash).toBeLessThanOrEqual(0xffffffff);
      expect(Number.isInteger(hash)).toBe(true);
    }
    expect(fnv1a32('cba')).toBe(0x016d9863);
  });
});
