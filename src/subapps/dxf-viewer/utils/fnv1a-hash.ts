/**
 * ADR-767 Δ6 — **η ΜΙΑ μηχανή αποτυπώματος περιεχομένου** του dxf-viewer.
 *
 * FNV-1a 32-bit: σύγχρονη, καθαρή, ντετερμινιστική, μηδέν I/O, μηδέν εξάρτηση. Είναι το
 * σωστό εργαλείο για την ερώτηση *«άλλαξε το **περιεχόμενο**;»* — και ρητά **όχι** το
 * SHA-256: εκείνο είναι ασύγχρονο (`crypto.subtle`), δουλεύει σε bytes αρχείων, και μια
 * τέταρτη κλήση του θα μεγάλωνε μια ήδη καταγεγραμμένη εκκρεμότητα (`foreign-asset-content-hash`,
 * `pending-ratchet-work.md` — ρητά cross-cutting ⇒ ΟΧΙ inline).
 *
 * ## 🔴 Γιατί εξήχθη — και γιατί ο «δεύτερος καταναλωτής» είχε ήδη γραφτεί
 * Το ADR-767 Δ6 ζητούσε την εξαγωγή *«πριν γραφτεί ο δεύτερος καταναλωτής»*, όπως έγινε με το
 * `table-axis-boundary.ts` (ADR-739 §40). Το grep της υλοποίησης έδειξε ότι ο δεύτερος
 * **υπήρχε ήδη**: ο ίδιος ακριβώς βρόχος ζούσε αυτούσιος σε δύο αρχεία —
 *
 * | Πού | Έξοδος | Πού ταξιδεύει |
 * |---|---|---|
 * | `text-engine/title-block/title-block-fingerprint.ts` | base36 | στο **QR** της πινακίδας (`?v=…`) |
 * | `text-engine/title-block/revisions/revision-snapshot.ts` | hex8 | στις **αποθηκευμένες υπογραφές** αναθεώρησης |
 *
 * Δύο σώματα, μία μηχανή, **δύο ευκαιρίες να αποκλίνουν σιωπηλά** — και η απόκλιση δεν θα
 * έριχνε κανένα test: θα δήλωνε κάθε αποθηκευμένη αναθεώρηση «τροποποιημένη» και κάθε τυπωμένο
 * QR «άλλης έκδοσης». Η κωδικοποίηση της εξόδου είναι το **μόνο** που διέφερε, οπότε ζει εδώ
 * ως δύο ονομασμένες όψεις της **ίδιας** συνάρτησης, όχι ως δύο αντίγραφά της.
 *
 * ## ⚠️ Τι ΔΕΝ απορροφά αυτό το module
 * Το `io/mesh3d-roundtrip/geometry-hash.ts` χρησιμοποιεί τις ίδιες σταθερές FNV αλλά χασάρει
 * **κβαντισμένους αριθμούς μέσα σε `Float64Array`** με πρόσθετο mixing — άλλη είσοδος, άλλη
 * ερώτηση («ίδιο σχήμα;» με ανοχή), όχι αντίγραφο αυτού εδώ. Μια βεβιασμένη ενοποίηση θα
 * περνούσε ολόκληρο πλέγμα από `String()` για να χωρέσει σε αυτή την υπογραφή.
 *
 * ## ⚠️ Δεν είναι κρυπτογραφικό
 * 32 bits ⇒ συγκρούσεις υπάρχουν και είναι κατασκευάσιμες. Νόμιμη χρήση: **ανίχνευση αλλαγής**
 * (αποτύπωμα έκδοσης, early cutoff). Παράνομη: υπογραφή, ακεραιότητα απέναντι σε επιτιθέμενο,
 * κλειδί ασφαλείας.
 *
 * @module subapps/dxf-viewer/utils/fnv1a-hash
 * @see text-engine/title-block/title-block-fingerprint.ts — αποτύπωμα έκδοσης πινακίδας (base36)
 * @see text-engine/title-block/revisions/revision-snapshot.ts — υπογραφές αναθεώρησης (hex8)
 * @see docs/centralized-systems/reference/adrs/ADR-767-table-bound-mode.md §4 Δ6
 */

const FNV_OFFSET_BASIS = 0x811c9dc5;
const FNV_PRIME = 0x01000193;

/**
 * FNV-1a 32-bit πάνω σε κωδικές μονάδες UTF-16 — **ανυπόγραφο** αποτέλεσμα.
 *
 * Το `>>> 0` δεν είναι καλλωπισμός: το `Math.imul` επιστρέφει **προσημασμένο** 32-bit, οπότε
 * χωρίς αυτό το `toString(36)` θα κολλούσε ένα `-` μέσα σε token που ταξιδεύει σε URL.
 */
export function fnv1a32(input: string): number {
  let hash = FNV_OFFSET_BASIS;
  for (let i = 0; i < input.length; i += 1) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, FNV_PRIME);
  }
  return hash >>> 0;
}

/** Το αποτύπωμα ως base36 — συμπαγές, ασφαλές σε URL. Η όψη που θέλει το QR της πινακίδας. */
export function fnv1aBase36(input: string): string {
  return fnv1a32(input).toString(36);
}

/**
 * Το αποτύπωμα ως **σταθερού πλάτους** 8 δεκαεξαδικά.
 *
 * Το σταθερό πλάτος είναι απαίτηση, όχι αισθητική: οι υπογραφές αναθεώρησης ενώνονται με
 * διαχωριστικό (`a:b:type`), και ένα hash με ηγετικά μηδενικά που «κονταίνει» θα άφηνε δύο
 * διαφορετικές τριάδες να παράγουν την ίδια συμβολοσειρά.
 */
export function fnv1aHex8(input: string): string {
  return fnv1a32(input).toString(16).padStart(8, '0');
}
