/**
 * ADR-724 Φ2 — Η **πλευρά αγκύρωσης** της κύριας παλέτας, ως καθαρός τύπος + επικυρωτής.
 *
 * Μηδέν React, μηδέν DOM, μηδέν localStorage — καθρέφτης του `workspace-dock-geometry.ts`
 * (εκεί ζουν οι αριθμοί, εδώ η απαρίθμηση). Πλήρως ελέγξιμο με jest χωρίς jsdom.
 *
 * ── ΓΙΑΤΙ ΔΥΟ ΤΙΜΕΣ ΚΑΙ ΟΧΙ ΤΡΕΙΣ ──
 *
 * Το ADR-724 §6.1 σχεδιάζει `docked | floating`. Το `'floating'` **δεν** μπαίνει εδώ στη Φ2:
 * η αιωρούμενη λειτουργία είναι η Φ3 (ADR-723 `FloatingPanel`), και μια τιμή που κανείς δεν
 * παράγει και κανείς δεν χειρίζεται είναι **νεκρός κλάδος** — ακριβώς ο λόγος που το `mode`
 * δεν μπήκε ήδη από τη Φ1 με μία μοναδική τιμή.
 *
 * Η επέκταση στη Φ3 είναι **ασφαλής χωρίς migration**: το {@link parseDockMode} απορρίπτει
 * κάθε άγνωστη τιμή, άρα ένα μελλοντικό `'floating'` στο localStorage διαβάζεται σήμερα ως
 * η προεπιλογή αντί να σπάσει — και αντίστροφα, το `:v1` κλειδί δεν χρειάζεται να αλλάξει.
 *
 * ── ΓΙΑΤΙ ΟΝΟΜΑΤΑ `docked-left` / `docked-right` ΚΑΙ ΟΧΙ `left` / `right` ──
 *
 * Το πρόθεμα κρατά το σχήμα ανοιχτό: όταν προστεθεί το `'floating'`, η ένωση παραμένει
 * αναγνώσιμη ως «κατάσταση αγκύρωσης», όχι ως «κατεύθυνση». Χωρίς το πρόθεμα, το
 * `'left' | 'right' | 'floating'` διαβάζεται σαν τρεις άσχετες έννοιες.
 */

/** Η κατάσταση αγκύρωσης της κύριας παλέτας. Φ3 προσθέτει `'floating'`. */
export type WorkspaceDockMode = 'docked-left' | 'docked-right';

/**
 * Η προεπιλογή είναι η **σημερινή** συμπεριφορά ⇒ μηδενική οπτική αλλαγή για όποιον δεν
 * άγγιξε ποτέ το μενού (ίδιο σκεπτικό με το `WIDTH_DEFAULT: 384`).
 */
export const DOCK_MODE_DEFAULT: WorkspaceDockMode = 'docked-left';

/**
 * Όλες οι έγκυρες τιμές, στη σειρά που εμφανίζονται στο μενού.
 *
 * Πηγή **και** για τον επικυρωτή **και** για το UI: μια νέα τιμή προστίθεται σε έναν τόπο και
 * εμφανίζεται αυτόματα στο μενού, αντί να ξεχαστεί στη μία από τις δύο λίστες.
 */
export const DOCK_MODES: readonly WorkspaceDockMode[] = ['docked-left', 'docked-right'] as const;

/**
 * Type guard για την ωμή αποθηκευμένη τιμή.
 *
 * Η αποθηκευμένη τιμή είναι **ιστορικό, όχι αλήθεια**: μπορεί να γράφτηκε από άλλη έκδοση του
 * app (π.χ. `'floating'` από μελλοντική Φ3, ή `'docked'` από πρόχειρη δοκιμή) ή να έχει
 * αλλοιωθεί χειροκίνητα. Ποτέ δεν χρησιμοποιείται ωμή — ίδια σύμβαση με το `parseDockWidth`.
 *
 * @returns η τιμή αν είναι γνωστή, αλλιώς `null` (ο καλών αποφασίζει το fallback)
 */
export function parseDockMode(raw: unknown): WorkspaceDockMode | null {
  return typeof raw === 'string' && (DOCK_MODES as readonly string[]).includes(raw)
    ? (raw as WorkspaceDockMode)
    : null;
}

/**
 * Είναι η παλέτα στα **δεξιά** του καμβά;
 *
 * Η **μία** ερώτηση που επιτρέπεται να κάνει το επίπεδο διάταξης. Κάθε άλλο σημείο του app
 * (καμβάς, hit-test, αγκύρωση σχεδίου) είναι σκόπιμα **αγνωστικό πλευράς**: το
 * `anchorTransformOnResize` μετρά την πραγματική αριστερή ακμή του container, ώστε να μην
 * υπάρχει `if (mode === …)` πουθενά στο μονοπάτι απόδοσης (ADR-724 §4.1).
 */
export function isDockedRight(mode: WorkspaceDockMode): boolean {
  return mode === 'docked-right';
}
