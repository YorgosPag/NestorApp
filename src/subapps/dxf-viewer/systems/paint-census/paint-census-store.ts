/**
 * 🔴 ADR-775 §13 — **Η απογραφή ζωγραφικής**: «ο ζωγράφος έτρεξε;», ρωτημένο στον ζωγράφο.
 *
 * ## Γιατί υπάρχει (μετρημένο 2026-08-08)
 * Το `data-testid="dxf-canvas-ready"` του δοκιμαστηρίου έμπαινε όταν φόρτωνε το **`scene`** —
 * μια συνθήκη για τα **δεδομένα**, ποτέ για τον **ζωγράφο**. Κάθε visual test συνέχιζε και
 * φωτογράφιζε άδειο κέλυφος, και **39 από 39** committed golden δεν περιείχαν ούτε μία γραμμή
 * σχεδίου. Ένα σήμα ετοιμότητας που βεβαιώνει **κάτι άλλο** από αυτό που φωτογραφίζει το test
 * δεν είναι ατελές — είναι **ψευδές**, και παράγει πράσινα που βεβαιώνουν τη βλάβη.
 *
 * Η θεραπεία δεν μπορεί να είναι «περίμενε λίγο ακόμα»: ο μόνος που ξέρει ότι ζωγραφίστηκε
 * καρέ είναι **ο βρόχος που το ζωγράφισε**. Άρα το σήμα **παράγεται από την πράξη**.
 *
 * ## Πρότυπο των μεγάλων
 * Ίδια κίνηση με το Chromium (`RenderFrameSubmissionObserver` — τα tests περιμένουν
 * **υποβληθέν καρέ**, όχι φορτωμένα δεδομένα) και με το Flutter (`SchedulerBinding` frame
 * callbacks). Η παρατηρησιμότητα του καρέ είναι **πρωτεύον** στοιχείο της μηχανής απόδοσης,
 * όχι βοήθημα δοκιμών κολλημένο απ' έξω.
 *
 * ## ⚠️ Γιατί η ειδοποίηση γίνεται ΜΟΝΟ στο πρώτο καρέ
 * Ο βρόχος ζωγραφίζει έως 60 φορές το δευτερόλεπτο. Ένας συνδρομητής που ειδοποιείται σε κάθε
 * καρέ θα ανάγκαζε React re-render σε κάθε καρέ — ακριβώς η βλάβη που απαγορεύει ο θεμελιώδης
 * κανόνας #1 του ADR-040. Το ερώτημα όμως είναι **μονότονο**: «ζωγράφισε **ποτέ**;» δεν
 * ξαναγίνεται «όχι». Άρα η ειδοποίηση είναι **μάνταλο**: πυροδοτεί στη μετάβαση 0→1 και μετά
 * ο κλάδος είναι ένα `if` που δεν μπαίνει ποτέ. Κόστος στο steady state: μία αύξηση ακεραίου.
 *
 * @module systems/paint-census/paint-census-store
 */

import { createExternalStore } from '@/lib/state/createExternalStore';

/**
 * Η ταυτότητα κάθε επιφάνειας που μπορεί να απογραφεί.
 *
 * Είναι **τα ίδια** αναγνωριστικά με του `UnifiedFrameScheduler` / `TRANSFORM_CANVAS_IDS`:
 * ένα δεύτερο λεξιλόγιο ονομάτων καμβά θα αποκλίνει σιωπηλά, και τότε η απογραφή θα μετρούσε
 * επιφάνεια που κανείς δεν φωτογραφίζει (σχήμα των δύο λιστών namespace του CHECK 3.34).
 */
export type PaintSurfaceId = 'dxf-canvas' | 'layer-canvas' | 'preview-canvas' | 'webgl-line-canvas';

/** Πόσα καρέ **ολοκλήρωσε** κάθε επιφάνεια. Ποτέ αρνητικό, ποτέ μειούμενο. */
const frames = new Map<PaintSurfaceId, number>();

/**
 * Το **σήμα** του πρώτου καρέ — βλ. «γιατί μόνο στο πρώτο καρέ» παραπάνω.
 *
 * ⚠️ **Version-signal πάνω στο SSoT** (`createExternalStore`, CHECK 3.7 / ADR-294), όχι
 * χειρόγραφο `Set<() => void>`: το ερώτημα είναι ανά **επιφάνεια** (`Map`), άρα η κατάσταση
 * που διαβάζει ο συνδρομητής **δεν** είναι μία τιμή· ο `Map` μένει **επιταχυντής μετάλλαξης**
 * και το store κουβαλά μόνο τον μετρητή μαντάλων — ακριβώς η κίνηση που το μητρώο ονομάζει
 * *version-signal* για registry/hot-path stores. Το `useSyncExternalStore` απαιτεί μόνο
 * «κάτι άλλαξε», και ο αναγνώστης (`useHasPainted`) ξαναρωτά το `hasPainted(surface)`.
 */
const firstPaintSignal = createExternalStore<number>(0);

/**
 * Καταγράφει **ολοκληρωμένο** καρέ.
 *
 * ⚠️ Καλείται στο **τέλος** της επιτυχούς διαδρομής ζωγραφικής, ποτέ στην αρχή και ποτέ έξω
 * από το `try`: ένα καρέ που πέταξε εξαίρεση στη μέση **δεν** είναι καρέ, και μια απογραφή
 * που το μετρούσε θα ξαναέλεγε το ίδιο ψέμα με άλλη διατύπωση.
 */
export function recordPaint(surface: PaintSurfaceId): void {
  const next = (frames.get(surface) ?? 0) + 1;
  frames.set(surface, next);
  // Μάνταλο: μόνο η μετάβαση 0→1 ειδοποιεί. Στο steady state αυτός ο κλάδος δεν μπαίνει.
  if (next === 1) {
    firstPaintSignal.set(firstPaintSignal.get() + 1);
  }
}

/** Πόσα καρέ ολοκλήρωσε η επιφάνεια — `0` αν δεν ζωγράφισε ποτέ. */
export function getPaintCount(surface: PaintSurfaceId): number {
  return frames.get(surface) ?? 0;
}

/** `true` μόλις η επιφάνεια ολοκληρώσει το **πρώτο** της καρέ. Μονότονο. */
export function hasPainted(surface: PaintSurfaceId): boolean {
  return getPaintCount(surface) > 0;
}

/**
 * Συνδρομή στο **πρώτο** καρέ οποιασδήποτε επιφάνειας.
 *
 * Συμβατή με `useSyncExternalStore`: επιστρέφει τη συνάρτηση αποσύνδεσης. Επειδή ειδοποιεί
 * μόνο στο μάνταλο, ένας React συνδρομητής ξαναρενδάρει **μία φορά** συνολικά.
 */
export function subscribeToFirstPaint(listener: () => void): () => void {
  return firstPaintSignal.subscribe(listener);
}

/**
 * Μηδενίζει την απογραφή — **μόνο** για tests που μοιράζονται το module registry του jest.
 *
 * Δεν καλείται από παραγωγικό κώδικα: η απογραφή είναι ανά φόρτωση σελίδας και ένα «reset»
 * στη μέση θα έκανε το μονότονο ερώτημα ξανά ψεύτικο.
 */
export function resetPaintCensus(): void {
  frames.clear();
  // `reset` του SSoT = επαναφορά τιμής **χωρίς** ειδοποίηση + απόρριψη κάθε συνδρομητή,
  // δηλαδή ακριβώς η σημασιολογία του παλιού `listeners.clear()`.
  firstPaintSignal.reset(0);
}
