'use client';

/**
 * 🔴 ADR-739 §27.16 Ε1 — **AUTO-PAN ΣΤΗΝ ΑΚΡΗ ΚΑΤΑ ΤΗ ΣΥΡΣΗ.**
 *
 * Σέρνεις επιλογή, φτάνεις στην άκρη του ορατού, και το κάδρο **συνεχίζει μόνο του**. Χωρίς
 * αυτό, μια περιοχή μεγαλύτερη από την οθόνη δεν μπορεί **καν να εκφραστεί** με σύρση.
 *
 * ## 🔴 ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΑΝΤΙΓΡΑΦΗ ΑΠΟ ΦΥΛΛΟ ΥΠΟΛΟΓΙΣΜΟΥ — **ο καμβάς μας ΜΕΤΑΚΙΝΕΙΤΑΙ, δεν κυλά**
 * Excel / Sheets / Handsontable (`DragToScroll`) κυλούν έναν container με scrollbars: το
 * `scrollTop` είναι δικό τους, κανείς άλλος δεν το γράφει. Εμείς έχουμε **ένα** view
 * transform (pan/zoom) που το διεκδικούν **οκτώ** διαδρομές πλοήγησης (ADR-728). Άρα εδώ
 * το «auto-scroll» είναι **auto-pan**, και η μόνη ασφαλής μορφή του είναι να **μιλήσει τη
 * γλώσσα που μιλούν ήδη οι υπόλοιποι** αντί να ανοίξει ένατη διαδρομή.
 *
 * ## Η έρευνα — και τι κρατήσαμε από τον καθένα (2026-08-02)
 * | Πηγή | Τι κάνει | Τι κρατήσαμε |
 * |---|---|---|
 * | **AutoCAD 2004+** | «automatic viewport pan» όταν το παράθυρο επιλογής βγαίνει εκτός οθόνης | **Την ίδια την ύπαρξη**: οι μεγάλοι CAD **το έχουν**, άρα δεν εφευρίσκουμε |
 * | **Konva** (`Scroll_By_Edge_Drag`) | ζώνη **100 px**, **σταθερά 2 px/tick**, `setInterval(1000/60)` | Τη **ζώνη** ως ιδέα· **όχι** τα νούμερα (βλ. παρακάτω) |
 * | **Handsontable** `DragToScroll` | container scroll, ενεργοποίηση **εκτός** πλέγματος | Την **αρχή**: η ενεργοποίηση ανήκει στην άκρη, όχι στην ταχύτητα του χεριού |
 * | **Excel** | σταθερό βήμα, ξεκινά έξω από το πλέγμα | Το **δάπεδο ταχύτητας** (ο χρήστης πρέπει να δει ότι ξεκίνησε) |
 *
 * 🔴 **Πού τους ξεπερνάμε, μετρημένα και όχι ρητορικά** — τρία σημεία:
 *
 * 1. **Το Konva είναι εξαρτημένο από το καρέ**: `2 px` ανά tick σημαίνει ότι σε μηχάνημα
 *    που πέφτει στα 30 fps το auto-scroll γίνεται **μισό**. Εδώ η ταχύτητα δηλώνεται σε
 *    **px ανά δευτερόλεπτο** και πολλαπλασιάζεται με τον πραγματικό `deltaTime` του καρέ —
 *    ίδια απόσταση σε 1×100 ms και σε 2×50 ms (υπάρχει test γι' αυτό ακριβώς).
 * 2. **Το Konva είναι σταθερής ταχύτητας**: μία και μόνη ταχύτητα δεν μπορεί να είναι
 *    ταυτόχρονα αρκετά αργή για ακρίβεια και αρκετά γρήγορη για 500 γραμμές. Εδώ η ταχύτητα
 *    είναι **τετραγωνική συνάρτηση του βάθους** μέσα στη ζώνη: μπαίνεις λίγο → σέρνεται·
 *    πας στην ακμή → πετά. Το χέρι είναι το γκάζι, χωρίς κανένα νέο χειριστήριο.
 * 3. **Το AutoCAD απαιτεί έξοδο από το παράθυρο**: εμείς ζούμε σε **ενσωματωμένο** δοχείο
 *    μέσα σε σελίδα, όπου «έξω από το παράθυρο» είναι απλησίαστο. Γι' αυτό η ζώνη είναι
 *    **μέσα** στην ακμή του δοχείου — και **παραμένει στο ταβάνι** όταν ο δείκτης βγει έξω,
 *    ώστε η συμπεριφορά να μη σπάει όταν το χέρι φύγει στην άλλη οθόνη.
 *
 * ## 🔴 ΜΗΔΕΝ ΝΕΟΙ ΓΡΑΦΕΙΣ TRANSFORM — ΚΑΙ ΜΗΔΕΝ ΔΙΚΟΣ ΜΑΣ rAF
 * Δύο απαγορεύσεις του ADR-040 τηρούνται **δομικά**, όχι με πειθαρχία:
 *
 * - **Γραφή**: εκπέμπεται `canvas-pan` — το **υπάρχον** κανάλι που ήδη καταναλώνει το
 *   `useCanvasPan` (πλοήγηση με βέλη) και καταλήγει στο `useViewportManager.setTransform`,
 *   δηλαδή σε **έναν από τους δύο επιτρεπόμενους γραφείς**. Αυτό το module **δεν εισάγει
 *   καν** το `ImmediateTransformStore`. Ούτε ένατη διαδρομή, ούτε δεύτερη σημασιολογία
 *   κατεύθυνσης: η σύμβαση προσήμων είναι **αυτούσια** του `canvas-pan`.
 * - **Καρέ**: εγγραφή στον `UnifiedFrameScheduler` (ο RAF orchestrator SSoT). Κανένα
 *   `requestAnimationFrame`, κανένα `setInterval` — το Konva χρησιμοποιεί το δεύτερο, που
 *   συνεχίζει να «χτυπά» και σε κρυμμένη καρτέλα.
 *
 * ## 🔴 Ο ΦΥΛΑΚΑΣ ΑΠΟΔΟΣΗΣ (ADR-735 · §27.15)
 * Η σύρση είναι 60-120 συμβάντα/δευτ. Το auto-pan **δεν** ζητά καρέ άνευ όρων: όσο ο
 * δείκτης είναι στη **νεκρή ζώνη** (δηλαδή σχεδόν πάντα), το καρέ κάνει μία αφαίρεση, δεν
 * εκπέμπει **τίποτα** και δεν ξυπνά κανέναν. Η εγγραφή στον scheduler ζει **μόνο** όσο η
 * χειρονομία.
 *
 * ## ⚠️ ΝΑΙ, ΜΕΤΡΑΕΙ ΩΣ «ΠΛΟΗΓΗΣΗ» — ΚΑΙ ΕΙΝΑΙ ΣΩΣΤΟ (ADR-728)
 * Το `NavigationGestureStore` **συνάγει** τη χειρονομία από την παρατηρούμενη αλλαγή του
 * transform· δεν υπάρχει write-site flag να παρακάμψουμε, **επίτηδες** (§ «γιατί συνάγεται»).
 * Άρα κατά το auto-pan η αναστολή snap ενεργοποιείται μόνη της. Η απόφαση είναι **ρητή και
 * θετική**: κατά το auto-pan το κάδρο **όντως** κινείται, ο δείκτης σαρώνει δεκάδες κελιά
 * ανά δευτερόλεπτο, και ένα snap υπολογισμένο σε καρέ που έχει ήδη προσπεράσει είναι
 * ακριβώς η «δουλειά ανάλογη της κίνησης» που ο ADR-735 πλήρωσε σε παραγωγή. Δεν καλείται
 * `endNavigationGesture()` στο τέλος: η αναστολή λήγει μόνη της, που είναι η ασφαλής
 * προεπιλογή του σχήματος.
 *
 * ## Γιατί ΓΕΝΙΚΟ module και όχι μέσα στη σύρση του πίνακα
 * Δεν ξέρει τίποτα για κελιά, πίνακες ή επιλογή: ξέρει **δείκτη, δοχείο, ταχύτητα**. Το
 * marquee, η μετακίνηση οντότητας και η σύρση λαβής έχουν **ακριβώς** το ίδιο κενό. Ένα
 * δεύτερο αντίγραφο σε καθένα θα ήταν ο structural clone που πιάνει το CHECK 3.28 (N.18).
 *
 * @module subapps/dxf-viewer/systems/navigation/drag-edge-autopan
 * @see hooks/canvas/useCanvasPan.ts — ο καταναλωτής του `canvas-pan`, η ΜΙΑ γραφή transform
 * @see systems/navigation/NavigationGestureStore.ts — γιατί το auto-pan μετράει ως πλοήγηση
 * @see ui/table-cell-editor/table-cell-drag-session.ts — ο πρώτος καταναλωτής
 */

import { EventBus } from '../events';
import { RENDER_PRIORITIES, registerRenderCallback } from '../../rendering/core/frame-scheduler-api';

/** Πού βρίσκεται ο δείκτης **μέσα στο δοχείο**, και πόσο μεγάλο είναι — όλα σε CSS px. */
export interface EdgeAutoPanSample {
  /** Οριζόντια θέση σε px δοχείου· μπορεί να είναι αρνητική ή > `width` (χέρι εκτός). */
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
}

/** Ταχύτητα κάδρου σε **px ανά δευτερόλεπτο**, στη σύμβαση προσήμων του `canvas-pan`. */
export interface EdgeAutoPanVelocity {
  readonly dx: number;
  readonly dy: number;
}

/**
 * 🔴 Οι **τρεις** αριθμοί που ορίζουν την αίσθηση. Ζουν εδώ και **μόνο** εδώ.
 *
 * - `bandPx` — **32**, όχι τα 100 του Konva. Η ζώνη είναι νεκρή περιοχή για τη σύρση: όσο
 *   πλατύτερη, τόσο μεγαλύτερο κομμάτι της οθόνης δεν μπορείς να μαρκάρεις **χωρίς** να
 *   φύγει το κάδρο. Στα 100 px, σε δοχείο 900 px, το **22%** του πλάτους γίνεται
 *   «ολισθηρό». Τα 32 px είναι περίπου μία γραμμή πίνακα σε τυπικό zoom — αρκετά για να
 *   στοχευτεί με το χέρι, αρκετά μικρά για να μη σε ξαφνιάζει.
 * - `minSpeedPxPerSec` — **60**. Το βήμα από «τίποτα» σε «κάτι» πρέπει να είναι **ορατό**:
 *   μια ταχύτητα που ξεκινά από το μηδέν δίνει μια ασαφή ζώνη όπου ο χρήστης δεν ξέρει αν
 *   ενεργοποιήθηκε. Excel: ξεκινά με σταθερό, καθαρά ορατό βήμα.
 * - `maxSpeedPxPerSec` — **1200**. Σε τυπικό ύψος γραμμής ~24 px οθόνης, είναι ~50
 *   γραμμές/δευτ.: ένας πίνακας 500 γραμμών διασχίζεται σε ~10 δευτ. **χωρίς** να χαθεί ο
 *   έλεγχος, γιατί αρκεί να τραβήξεις το χέρι λίγα px πίσω για να πέσει τετραγωνικά.
 */
export const DRAG_EDGE_AUTOPAN = {
  bandPx: 32,
  minSpeedPxPerSec: 60,
  maxSpeedPxPerSec: 1200,
} as const;

/**
 * Πόσο «βαθιά» είναι ο δείκτης μέσα σε **μία** άκρη: `0` στο εσωτερικό όριο της ζώνης,
 * `1` στην ακμή και **πέρα** από αυτήν.
 *
 * `distance` = απόσταση από την ακμή προς τα μέσα (αρνητική όταν το χέρι είναι έξω).
 */
function edgeDepth(distance: number, bandPx: number): number {
  if (distance >= bandPx) return 0;
  if (distance <= 0) return 1;
  return (bandPx - distance) / bandPx;
}

/**
 * Βάθος → ταχύτητα, με **τετραγωνική** ράμπα.
 *
 * Γιατί τετραγωνική και όχι γραμμική: η γραμμική δίνει το μισό ταβάνι στο μισό βάθος, που
 * είναι **πολύ** γρήγορο για μικρές διορθώσεις — και επειδή η ζώνη είναι μόνο 32 px, το
 * χρήσιμο εύρος του χεριού είναι λίγα px. Η τετραγωνική δίνει τα δύο τρίτα της ζώνης σε
 * αργές ταχύτητες και συμπυκνώνει την επιτάχυνση εκεί που ο χρήστης **ζητά** ταχύτητα:
 * σπρώχνοντας στην ακμή.
 */
function rampSpeed(depth: number): number {
  const { minSpeedPxPerSec, maxSpeedPxPerSec } = DRAG_EDGE_AUTOPAN;
  return minSpeedPxPerSec + (maxSpeedPxPerSec - minSpeedPxPerSec) * depth * depth;
}

/** Η ταχύτητα ενός άξονα: αρνητικό βάθος «πριν», θετικό «μετά» — ποτέ και τα δύο μαζί. */
function axisVelocity(near: number, far: number, bandPx: number): number {
  const nearDepth = edgeDepth(near, bandPx);
  if (nearDepth > 0) return rampSpeed(nearDepth);
  const farDepth = edgeDepth(far, bandPx);
  return farDepth > 0 ? -rampSpeed(farDepth) : 0;
}

/**
 * 🔴 Η **καθαρή** καρδιά: δείγμα → ταχύτητα κάδρου. Μηδέν DOM, μηδέν χρόνος, μηδέν store.
 *
 * ## Η σύμβαση προσήμων είναι **δανεική**, όχι νέα
 * Ακριβώς αυτή του `canvas-pan` (και του `useCanvasPan`, και των βελών):
 * `dx > 0` ⇒ **το περιεχόμενο μετακινείται δεξιά** ⇒ **το κάδρο κοιτά αριστερά**.
 * Άρα: δείκτης στην **αριστερή** άκρη ⇒ ο χρήστης θέλει να δει ό,τι είναι πιο αριστερά
 * ⇒ `dx > 0`. Συμμετρικά για τους άλλους τρεις. Καμία μετάφραση, κανένα δεύτερο λεξιλόγιο
 * κατεύθυνσης (§27.13: «δύο λεξιλόγια της ίδιας ποσότητας» είναι πάντα σφάλμα που περιμένει).
 *
 * ## Οι δύο άξονες είναι **ανεξάρτητοι** — και αυτό είναι η γωνία
 * Στη γωνία της οθόνης παράγονται **και οι δύο** ταχύτητες ταυτόχρονα, καθεμιά με το δικό
 * της βάθος. Καμία κανονικοποίηση διανύσματος: η διαγώνιος **πρέπει** να είναι πιο γρήγορη
 * από την κάθε πλευρά, γιατί ο χρήστης ζητά και τα δύο.
 */
export function edgeAutoPanVelocity(sample: EdgeAutoPanSample): EdgeAutoPanVelocity {
  const { bandPx } = DRAG_EDGE_AUTOPAN;
  return {
    dx: axisVelocity(sample.x, sample.width - sample.x, bandPx),
    dy: axisVelocity(sample.y, sample.height - sample.y, bandPx),
  };
}

/**
 * Συμβάν ποντικιού + δοχείο → δείγμα. Ο **ΕΝΑΣ** δρόμος, ώστε η μέτρηση «πού είμαι στο
 * δοχείο» να μη γραφτεί δεύτερη φορά σε κάθε μελλοντικό καταναλωτή.
 *
 * `null` σε δοχείο μηδενικών διαστάσεων: αποσυναρμολογημένο ή κρυμμένο — δεν υπάρχει άκρη
 * για να ακουμπήσεις, και κάθε «βάθος» θα ήταν διαίρεση με το μηδέν σε άλλη μορφή.
 */
export function edgeAutoPanSample(
  event: Pick<MouseEvent, 'clientX' | 'clientY'>,
  container: HTMLElement,
): EdgeAutoPanSample | null {
  const rect = container.getBoundingClientRect();
  if (rect.width <= 0 || rect.height <= 0) return null;
  return {
    x: event.clientX - rect.left,
    y: event.clientY - rect.top,
    width: rect.width,
    height: rect.height,
  };
}

/** Ό,τι χρειάζεται ο κύκλος ζωής. Καμία γνώση του τι επιλέγεται — τη δίνει ο καλών. */
export interface DragEdgeAutoPanStart {
  /**
   * «Πού είναι το χέρι **τώρα**;» — καλείται **μία φορά ανά καρέ**. `null` ⇒ σιωπή.
   *
   * Ζει στον καλούντα γιατί **μόνο εκείνος** ξέρει ποιο ήταν το τελευταίο συμβάν: ο δείκτης
   * μπορεί να μένει **ακίνητος** πάνω στην άκρη επ' άπειρον, οπότε δεν έρχεται κανένα νέο
   * `mousemove` — και ακριβώς τότε το auto-pan πρέπει να δουλεύει.
   */
  readonly sample: () => EdgeAutoPanSample | null;
  /**
   * 🔴 Κλήθηκε **ΜΕΤΑ** από κάθε πραγματική μετακίνηση κάδρου, στο **ίδιο** καρέ.
   *
   * Χωρίς αυτό το auto-pan θα ήταν **ψεύτικο**: ο κόσμος γλιστράει κάτω από έναν ακίνητο
   * δείκτη, άρα το κελί που «δείχνει» το χέρι αλλάζει — αλλά κανένα `mousemove` δεν το λέει
   * σε κανέναν. Το κάδρο θα κινούνταν και η επιλογή θα έμενε παγωμένη. Είναι η ίδια κλάση
   * σφάλματος με το «anchor που ελέγχει το store, όχι τον ζωγράφο» (§27.15).
   */
  readonly onPanned: () => void;
}

/** Ο καθαρισμός της τρέχουσας χειρονομίας· `null` όταν δεν τρέχει auto-pan. */
let activeTeardown: (() => void) | null = null;
/** Το ενεργό συμβόλαιο — κρατιέται ξεχωριστά ώστε το test hook να χτυπά **ένα** καρέ. */
let activeStart: DragEdgeAutoPanStart | null = null;

/** Ένα καρέ: δείγμα → ταχύτητα → (ίσως) μετακίνηση → ξαναρώτα τον καταναλωτή. */
function runFrame(deltaTimeMs: number): void {
  const start = activeStart;
  if (!start) return;
  const sample = start.sample();
  if (!sample) return;
  const velocity = edgeAutoPanVelocity(sample);
  // 🔴 Ο φύλακας: νεκρή ζώνη ⇒ **καμία** εκπομπή, άρα καμία γραφή transform, άρα κανένα
  // repaint και καμία ψευδής «χειρονομία πλοήγησης». Το κόστος του καρέ είναι μια αφαίρεση.
  if (velocity.dx === 0 && velocity.dy === 0) return;
  const seconds = deltaTimeMs / 1000;
  EventBus.emit('canvas-pan', { dx: velocity.dx * seconds, dy: velocity.dy * seconds });
  start.onPanned();
}

/**
 * Ξεκινά το auto-pan. Ιδεμποτής ως προς το προηγούμενο: μια νέα χειρονομία **κλείνει** την
 * προηγούμενη — δύο ταυτόχρονα auto-pan δεν υπάρχουν (ίδια σύμβαση με το
 * `startTableCellDrag`).
 */
export function startDragEdgeAutoPan(start: DragEdgeAutoPanStart): void {
  stopDragEdgeAutoPan();
  activeStart = start;
  // Προτεραιότητα `CRITICAL`: το auto-pan **παράγει** το transform που θα ζωγραφίσουν όλοι
  // οι υπόλοιποι μέσα στο ίδιο καρέ. Αν έτρεχε μετά τους καμβάδες, κάθε μετακίνηση θα
  // εμφανιζόταν ένα καρέ αργότερα — ορατό ως τρέμουλο σε 60 fps.
  const unregister = registerRenderCallback(
    'table-drag-edge-autopan',
    'Drag edge auto-pan',
    RENDER_PRIORITIES.CRITICAL,
    (deltaTime) => runFrame(deltaTime),
  );
  activeTeardown = (): void => {
    unregister();
  };
}

/** Σταματά το auto-pan **χωρίς** να αγγίξει το transform. Ιδεμποτής. */
export function stopDragEdgeAutoPan(): void {
  activeTeardown?.();
  activeTeardown = null;
  activeStart = null;
}

/** Τρέχει auto-pan αυτή τη στιγμή; Για tests και για φύλακες αποπροσάρτησης. */
export function isDragEdgeAutoPanActive(): boolean {
  return activeTeardown !== null;
}

/**
 * Μόνο για δοκιμές — εκτελεί **ένα** καρέ με δηλωμένο `deltaTime`, χωρίς να περιμένει τον
 * scheduler. Δεν υπάρχει άλλος τρόπος να ελεγχθεί η ταχύτητα ανά **δευτερόλεπτο**: με
 * πραγματικό rAF ο χρόνος του καρέ είναι ό,τι δώσει το μηχάνημα.
 */
export function __runDragEdgeAutoPanFrameForTest(deltaTimeMs: number): void {
  runFrame(deltaTimeMs);
}
