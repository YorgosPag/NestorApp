/**
 * scene-load-guard — ποιος κρατά τον φρουρό «φόρτωση σε εξέλιξη» του auto-save (ADR-913 §3.6).
 *
 * ## Το πρόβλημα
 *
 * Ο φρουρός (`setIsLoadingFromFirestore`) είναι ΕΝΑ boolean, και τον άναβε/έσβηνε η ίδια η
 * φόρτωση: `true` στην αρχή, `false` στο `finally` — **εκτός αν ακυρώθηκε**. Μια φόρτωση που
 * ακυρώνεται (αλλαγή επιπέδου στη μέση) περίμενε από την **επόμενη** να σβήσει τον φρουρό.
 * Όταν το επόμενο επίπεδο **δεν έχει αρχείο**, επόμενη φόρτωση δεν υπάρχει: ο φρουρός έμενε
 * αναμμένος για όλη τη συνεδρία και **καμία** αποθήκευση δεν προγραμματιζόταν — αθόρυβα.
 * Πριν το ADR-913 ήταν αόρατο (επίπεδο χωρίς αρχείο δεν έγραφε ποτέ)· μετά, είναι απώλεια
 * δουλειάς: F5 πάνω σε πρόχειρο ⇒ η προεπιλεγμένη κάτοψη αρχίζει να φορτώνει, η διεύθυνση
 * επαναφέρει το πρόχειρο, η φόρτωση ακυρώνεται, ο φρουρός μένει.
 *
 * ## Η αρχή: μίσθωση
 *
 * Κάθε φόρτωση **παίρνει** τον φρουρό και κρατά τη δική της απελευθέρωση. Η απελευθέρωση
 * ισχύει **μόνο αν η φόρτωση κρατά ακόμη τον φρουρό**: μια παλιά, καθυστερημένη απελευθέρωση
 * (π.χ. το `requestAnimationFrame` μιας φόρτωσης που τελείωσε) δεν σβήνει ποτέ τον φρουρό
 * μιας νεότερης. Και όποιος ακυρώνει τη φόρτωση **την απελευθερώνει ο ίδιος** — δεν περιμένει
 * διάδοχο που ίσως δεν έρθει.
 *
 * Pure: καμία πρόσβαση σε React/Firebase.
 *
 * @module subapps/dxf-viewer/systems/levels/scene-load-guard
 * @see docs/centralized-systems/reference/adrs/ADR-913-level-drawing-birth.md
 */

/** Απελευθερώνει τη μίσθωση. Idempotent· αδρανής αν ο φρουρός πέρασε σε νεότερη φόρτωση. */
export type ReleaseSceneLoad = () => void;

export interface SceneLoadGuard {
  /** Ανάβει τον φρουρό για νέα φόρτωση και επιστρέφει τη **δική της** απελευθέρωση. */
  begin(): ReleaseSceneLoad;
}

export function createSceneLoadGuard(setLoading: (loading: boolean) => void): SceneLoadGuard {
  let holder = 0;
  return {
    begin() {
      holder += 1;
      const lease = holder;
      setLoading(true);
      return () => {
        if (lease !== holder) return;
        holder += 1;
        setLoading(false);
      };
    },
  };
}
