/**
 * ADR-782 §23 (Φάση 2δ) — η **χειροκίνητη** τοποθέτηση του υποβάθρου, και **μόνο** αυτού.
 *
 * ## 🔴 Η κόκκινη γραμμή, γραμμένη ως δομή και όχι ως κανόνας
 * Αυτό το store κρατά έναν {@link GeoReference} που περιγράφει **πού κάθεται ο χάρτης κάτω από
 * το σχέδιο** — και **τίποτε άλλο**. Δεν είναι, και δεν επιτρέπεται ποτέ να γίνει, η γεωαναφορά
 * του έργου (απόφαση Giorgio 2026-08-10, ADR-782 §23.1): μια θέση που ο χρήστης εκτίμησε **με
 * το μάτι** πάνω σε χάρτη εθελοντικής χαρτογράφησης δεν έχει καμία δουλειά σε πίνακες
 * συντεταγμένων, εξαγωγή IFC ή τοπογραφικά παραδοτέα.
 *
 * ⚠️ Η προστασία **δεν** είναι ένα σχόλιο «μη γράψεις στο geo-reference-store»: αυτό το module
 * απλώς **δεν εισάγει** εκείνο το store, και το `basemap-frame` που το διαβάζει δίνει στη
 * χειροκίνητη τοποθέτηση **αυστηρά χαμηλότερη προτεραιότητα** από τη δηλωμένη γεωαναφορά. Άρα
 * ένα γεωαναφερμένο έργο **αγνοεί** ό,τι σύρθηκε ποτέ εδώ — δεν το σβήνει, δεν το τιμά, το
 * παρακάμπτει. Ένας κανόνας που κάποιος πρέπει να θυμηθεί θα είχε σπάσει· μια εξάρτηση που δεν
 * υπάρχει δεν σπάει.
 *
 * ## Γιατί ξεχωριστό store και όχι πεδίο της άγκυρας
 * Η άγκυρα απαντά «**πού** είναι το έργο πάνω στη Γη» (γεωγραφικό πλάτος/μήκος, με προέλευση).
 * Αυτό απαντά «**πώς** κάθεται ο χάρτης κάτω από αυτό το συγκεκριμένο σχέδιο» — και κουβαλά
 * **στροφή**, που η διεύθυνση δεν έχει καν έννοια να δώσει. Δύο ερωτήματα σε ένα κελί θα
 * σήμαινε ότι μια νέα ανάγνωση διεύθυνσης σβήνει σιωπηλά τη δουλειά του χρήστη.
 *
 * Μηδέν React (ADR-040): οι διεπαφές διαβάζουν με `useSyncExternalStore`, ο ζωγράφος με σκέτο
 * `get()` τη στιγμή του καρέ.
 *
 * ## §24 — η μονιμότητα, και γιατί ο **γραφέας ζει εδώ**
 * Ένα υπόβαθρο αναφοράς που το ξανατοποθετείς σε κάθε ανανέωση σελίδας δεν είναι εργαλείο. Η
 * αποθήκευση όμως **δεν** μπορεί να γίνει με μια εγγραφή στο store από έξω: ένας συνδρομητής δεν
 * ξέρει **γιατί** άλλαξε η τιμή, άρα θα έγραφε πίσω στη βάση ακριβώς ό,τι μόλις διάβασε από
 * αυτήν. Το «γιατί» το ξέρει **μόνο ο καλών**, και γι' αυτό υπάρχουν **τέσσερις** πόρτες με
 * διαφορετικό όνομα η καθεμία — πρότυπο `opening-tag-style-service` (ADR-376 Φ.Γ2):
 *
 * | πόρτα | ποιος | γράφει; | πατά εκκρεμή πρόθεση; |
 * |---|---|---|---|
 * | {@link setBasemapPlacement} | ο χρήστης τοποθετεί | ναι, με καθυστέρηση | — |
 * | {@link clearBasemapPlacement} | ο χρήστης πατά επαναφορά | ναι, `null` | — |
 * | {@link hydrateBasemapPlacement} | ο host, με ό,τι λέει το έγγραφο | **όχι** | **όχι** |
 * | {@link detachBasemapPlacement} | ο host, σε αλλαγή έργου | **όχι** | ναι |
 *
 * ⚠️ Η καθυστέρηση **δεν** είναι βελτιστοποίηση: το σύρσιμο παράγει δεκάδες τιμές ανά
 * δευτερόλεπτο και καθεμία είναι εξίσου «αληθινή». Χωρίς αυτήν, ένα σύρσιμο τριών δευτερολέπτων
 * θα ήταν ~180 εγγραφές Firestore για ένα αποτέλεσμα.
 *
 * @see ./basemap-frame.ts — η ΜΙΑ απόφαση που το σταθμίζει με τη γεωαναφορά
 * @see ./basemap-placement.ts — τα καθαρά μαθηματικά που παράγουν τις τιμές του
 * @see ./basemap-placement-persistence.ts — η πόρτα Firestore που συνδέεται ως γραφέας
 */

import { createExternalStore } from '@/lib/state/createExternalStore';
import { createModuleLogger } from '@/lib/telemetry';
import { DXF_TIMING } from '../../config/dxf-timing';
import type { GeoReference } from '../geo-referencing/geo-transform';

const logger = createModuleLogger('basemap-placement-store');

/** Ο γραφέας που συνδέει ο host· `null` = κανένα έργο, άρα πουθενά να γραφτεί. */
export type BasemapPlacementPersister = (geo: GeoReference | null) => Promise<void>;

/**
 * `null` = ο χρήστης δεν έχει τοποθετήσει τίποτα με το χέρι — **όχι** «τοποθέτησε στο μηδέν».
 * Η διάκριση είναι ορατή: χωρίς αυτήν, το `basemap-frame` δεν θα μπορούσε να ξεχωρίσει
 * «χρησιμοποίησε τη διεύθυνση» από «ο χρήστης το έσυρε ακριβώς εκεί».
 */
const store = createExternalStore<GeoReference | null>(null, {
  equals: (a, b) =>
    a === b ||
    (a !== null &&
      b !== null &&
      a.originWorld.x === b.originWorld.x &&
      a.originWorld.y === b.originWorld.y &&
      a.rotationDeg === b.rotationDeg),
});

let persister: BasemapPlacementPersister | null = null;
let debounceTimer: ReturnType<typeof setTimeout> | null = null;
/** `true` όσο υπάρχει πρόθεση χρήστη που **δεν** έχει ακόμη φύγει για τη βάση. */
let writePending = false;

/** Η ενεργή χειροκίνητη τοποθέτηση, ή `null`. Καθαρή ανάγνωση — ασφαλής και ως `getSnapshot`. */
export function getBasemapPlacement(): GeoReference | null {
  return store.get();
}

/**
 * Γράφει τη χειροκίνητη τοποθέτηση **ως πρόθεση χρήστη** — άρα προγραμματίζει και αποθήκευση.
 *
 * ⚠️ Ο έλεγχος ισότητας ζει στο store και **όχι** στον καλούντα: το σύρσιμο παράγει δεκάδες
 * ενημερώσεις ανά δευτερόλεπτο και οι περισσότερες τελειώνουν στην **ίδια** τιμή (ο δείκτης
 * κουνήθηκε λιγότερο από ένα χιλιοστό του σχεδίου). Χωρίς αυτόν, κάθε τέτοια ενημέρωση θα
 * ακύρωνε ολόκληρο το υπόβαθρο και θα ξανακατέβαζε πλακίδια που ήδη έχουμε.
 *
 * ⚠️ Και **η ίδια** ισότητα αποφασίζει αν αξίζει εγγραφή: ρωτιέται το store («άλλαξε;») αντί να
 * ξαναγραφτεί εδώ η σύγκριση. Δύο ορισμοί του «άλλαξε» θα απέκλιναν την ημέρα που κάποιος
 * πρόσθετε πεδίο στο {@link GeoReference}.
 */
export function setBasemapPlacement(geo: GeoReference): void {
  commitUserIntent(geo);
}

/**
 * Επαναφορά στην τοποθέτηση που προκύπτει από τη διεύθυνση — η πράξη «άκυρο, ξαναπιάσ' το από
 * την αρχή», **αίτημα του χρήστη**, άρα αποθηκεύεται κι αυτή.
 *
 * ⚠️ Χωρίς την εγγραφή, η επαναφορά θα φαινόταν να δουλεύει μέχρι την επόμενη ανανέωση σελίδας —
 * δηλαδή θα ήταν χειρότερη από το να μην υπάρχει καθόλου. **Δεν** είναι πια η ίδια πράξη με την
 * αλλαγή έργου: εκείνη είναι {@link detachBasemapPlacement} και **δεν** γράφει τίποτα.
 */
export function clearBasemapPlacement(): void {
  commitUserIntent(null);
}

/**
 * Η τιμή που λέει το **έγγραφο**. Ποτέ δεν γράφει — αλλιώς κάθε φόρτωση έργου θα ξανάγραφε στη
 * βάση ό,τι μόλις διάβασε από αυτήν.
 *
 * ⚠️ **Σέβεται εκκρεμή πρόθεση χρήστη**, και ο λόγος είναι μετρημένος και όχι θεωρητικός: η
 * άγκυρα διεύθυνσης και η τοποθέτηση διαβάζονται από **δύο** ανεξάρτητες αναγνώσεις του **ίδιου**
 * εγγράφου, χωρίς εγγυημένη σειρά. Αν η άγκυρα φτάσει πρώτη, το εργαλείο **ξεκλειδώνει** και ο
 * χρήστης μπορεί να σύρει πριν φτάσει η αποθηκευμένη τιμή — που τότε θα έσβηνε τη δουλειά του,
 * επαναφέροντας τον χάρτη μπροστά στα μάτια του.
 */
export function hydrateBasemapPlacement(geo: GeoReference | null): void {
  if (writePending) return;
  store.set(geo);
}

/**
 * Το έργο έφυγε. Ακυρώνει **και** την εκκρεμή εγγραφή: μια αποθήκευση που θα προσγειωνόταν μετά
 * την αλλαγή θα έγραφε την τοποθέτηση του **προηγούμενου** σχεδίου.
 */
export function detachBasemapPlacement(): void {
  cancelPendingWrite();
  store.set(null);
}

/**
 * Συνδέει (ή αποσυνδέει) τον γραφέα. Η αποσύνδεση **δεν** ακυρώνει εκκρεμή εγγραφή από μόνη της —
 * αυτό είναι δουλειά της {@link detachBasemapPlacement}, ώστε οι δύο πράξεις να μη μαντεύει η μία
 * την πρόθεση της άλλης.
 */
export function setBasemapPlacementPersister(next: BasemapPlacementPersister | null): void {
  persister = next;
}

/** Η κοινή διαδρομή των δύο προθέσεων χρήστη: άλλαξε ⇒ αποθηκεύεται. */
function commitUserIntent(geo: GeoReference | null): void {
  const before = store.get();
  store.set(geo);
  if (store.get() === before) return;
  if (debounceTimer !== null) clearTimeout(debounceTimer);
  writePending = true;
  debounceTimer = setTimeout(runPendingWrite, DXF_TIMING.ui.COMMIT_DEBOUNCE);
}

function cancelPendingWrite(): void {
  if (debounceTimer !== null) clearTimeout(debounceTimer);
  debounceTimer = null;
  writePending = false;
}

/**
 * Η **μία** εκτέλεση εγγραφής, από το χρονόμετρο ή από το {@link flushBasemapPlacementWrite}.
 *
 * ⚠️ Διαβάζει το store **τη στιγμή της εγγραφής** αντί να κουβαλά την τιμή που προγραμμάτισε τη
 * ρίψη: το store είναι η αλήθεια, και μια τιμή κλεισμένη σε closure θα ήταν δεύτερη — παλιά κατά
 * μία χειρονομία ακριβώς στην περίπτωση που κάποιος θα πρόσθετε δρόμο που αλλάζει τιμή χωρίς να
 * ξαναπρογραμματίζει.
 */
function runPendingWrite(): void {
  debounceTimer = null;
  writePending = false;
  const write = persister;
  if (!write) return;
  void write(store.get()).catch((error: unknown) => {
    // Η αποτυχία **δεν** αναιρεί την οθόνη: ο χάρτης κάθεται ήδη εκεί που τον άφησε ο χρήστης.
    // Μια επαναφορά εδώ θα του έπαιρνε πίσω δουλειά για λόγο που δεν αφορά τη δουλειά.
    logger.error('Αποθήκευση τοποθέτησης υποβάθρου απέτυχε', { error: String(error) });
  });
}

/** Άμεση εκτέλεση της εκκρεμούς εγγραφής — για άγκυρες, χωρίς πλαστά χρονόμετρα. */
export function flushBasemapPlacementWrite(): void {
  if (debounceTimer === null) return;
  clearTimeout(debounceTimer);
  runPendingWrite();
}

/** Εγγραφή σε αλλαγές· επιστρέφει την απεγγραφή (συμβατό με `useSyncExternalStore`). */
export function subscribeBasemapPlacement(listener: () => void): () => void {
  return store.subscribe(listener);
}

/**
 * Επαναφορά για απομόνωση δοκιμών (δεν ειδοποιεί — δες `ExternalStore.reset`).
 *
 * ⚠️ Καθαρίζει **και** τον γραφέα **και** την εκκρεμή εγγραφή. Χωρίς αυτό, ένα χρονόμετρο μιας
 * δοκιμής θα χτυπούσε μέσα στην **επόμενη**, καλώντας έναν γραφέα που εκείνη δεν έστησε — η
 * κλασική διαρροή που κάνει μια σουίτα να περνά ή να πέφτει ανάλογα με τη σειρά εκτέλεσης.
 */
export function resetBasemapPlacementStore(): void {
  cancelPendingWrite();
  persister = null;
  store.reset(null);
}
