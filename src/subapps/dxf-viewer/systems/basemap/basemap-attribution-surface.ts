/**
 * «Υπάρχει, **αυτή τη στιγμή**, επιφάνεια που δείχνει την απόδοση του παρόχου;»
 *
 * ## Γιατί υπάρχει αυτό το αρχείο
 * Η απόδοση δεν είναι λεπτομέρεια διεπαφής — είναι **όρος της άδειας**. Η οδηγία του OSMF το
 * θέτει ως προϋπόθεση χρήσης των δεδομένων, όχι ως σύσταση. Άρα το ερώτημα «ζωγραφίζουμε χάρτη;»
 * και το ερώτημα «δείχνουμε την απόδοση;» **δεν είναι δύο ανεξάρτητα ερωτήματα**: το πρώτο
 * επιτρέπεται να απαντηθεί «ναι» μόνο αν το δεύτερο έχει ήδη απαντηθεί «ναι».
 *
 * Ο συνηθισμένος τρόπος να το εξασφαλίσει κανείς είναι να **θυμηθεί** να προσαρτήσει το component
 * της απόδοσης δίπλα σε κάθε ζωγράφο. Αυτό είναι ανάθεση σε άνθρωπο, και σε αυτό το αποθετήριο
 * έχει αποτύχει μετρημένα (CHECK 3.34: δύο χειρόγραφες λίστες που απέκλιναν κατά 63· CHECK 3.37:
 * συγκεντρωτής που άκουγε 18 από 26 πύλες). Εδώ η ανάθεση **αντιστρέφεται**: ο ζωγράφος ρωτά το
 * μητρώο, και χωρίς εγγεγραμμένη επιφάνεια απλώς **δεν ζωγραφίζει**.
 *
 * ## 🔴 Η βλάβη που κλείνει ΔΕΝ είναι υποθετική
 * Ο `BasemapGroundLayer` κατασκευάζεται από τον `ThreeJsSceneManager`, δηλαδή σε **κάθε** σημείο
 * που προσαρτά `BimViewport3D` — και δύο από αυτά (`Bim3DReadOnlyOverlay` της καρτέλας ιδιοτήτων,
 * `/test-harness/bim-3d`) ζουν **έξω** από τον `CanvasLayerStack`, όπου δεν υπάρχει καμία μπάρα,
 * κανένα πάνελ και καμία απόδοση. Τα stores του υποβάθρου είναι module singletons: αν ο χρήστης
 * ανάψει τον χάρτη στον viewer και μετά ανοίξει την τρισδιάστατη προεπισκόπηση στις ιδιότητες,
 * ο χάρτης θα ζωγράφιζε εκεί **χωρίς καμία μνεία**. Αυτό είναι διανομή δεδομένων OSM εκτός των
 * όρων της άδειας.
 *
 * ## Τι ΔΕΝ κάνει — δηλωμένο όριο
 * Το μητρώο είναι **καθολικό**, όχι ανά viewport. Δύο ταυτόχρονα προσαρτημένες επιφάνειες
 * σχεδίασης, όπου **μόνο η μία** δείχνει απόδοση, θα ικανοποιούσαν τον έλεγχο και για τις δύο.
 * Σήμερα αυτό δεν συμβαίνει (οι δύο διαδρομές ζουν σε διαφορετικά routes και δεν συνυπάρχουν),
 * και η θεραπεία — context ανά viewport — θα κόστιζε διάδοση μέσα από τον `ThreeJsSceneManager`,
 * που είναι imperative και δεν βλέπει React. Γράφεται εδώ ώστε να μη διαβαστεί ως εγγύηση.
 *
 * Μηδέν React (ADR-040): εγγραφή/απεγγραφή σε `useEffect`, ανάγνωση με σκέτο `get()` τη στιγμή
 * του καρέ.
 */

import { createExternalStore } from '../../stores/createExternalStore';

/**
 * Τα αναγνωριστικά των επιφανειών που **αποδίδουν**. Σύνολο και όχι μετρητής: μια επιφάνεια που
 * προσαρτάται δύο φορές (StrictMode διπλό effect, HMR) δεν επιτρέπεται να αφήσει το μητρώο
 * «κατά ένα γεμάτο» μετά την αποπροσάρτηση — αυτό θα ήταν διαρροή που κρατά τον χάρτη ζωντανό
 * ακριβώς αφού έφυγε η μνεία του.
 */
const store = createExternalStore<ReadonlySet<string>>(new Set<string>());

/**
 * Δήλωση ότι αυτή η επιφάνεια δείχνει την απόδοση. Επιστρέφει την απεγγραφή, ώστε ο κύκλος ζωής
 * να είναι ο κύκλος ζωής του component (ίδιο σχήμα με `subscribe`).
 */
export function registerBasemapAttributionSurface(id: string): () => void {
  const next = new Set(store.get());
  next.add(id);
  store.set(next);

  return () => {
    const without = new Set(store.get());
    without.delete(id);
    store.set(without);
  };
}

/** `true` όταν τουλάχιστον μία επιφάνεια αναλαμβάνει να δείξει την απόδοση. */
export function hasBasemapAttributionSurface(): boolean {
  return store.get().size > 0;
}

/** Εγγραφή σε αλλαγές — ο ζωγράφος του 2Δ πρέπει να ξαναρωτήσει όταν φτάσει η επιφάνεια. */
export function subscribeBasemapAttributionSurface(listener: () => void): () => void {
  return store.subscribe(listener);
}

/** Επαναφορά για απομόνωση δοκιμών (δεν ειδοποιεί — δες `ExternalStore.reset`). */
export function resetBasemapAttributionSurfaces(): void {
  store.reset(new Set<string>());
}
