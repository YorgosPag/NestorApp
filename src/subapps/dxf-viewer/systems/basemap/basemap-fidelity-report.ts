/**
 * «Κρύφτηκε κάτι από τον χάρτη, και ο χρήστης μπορεί να το **μάθει**;» (ADR-782 §27.9)
 *
 * ## 🔴 Γιατί υπάρχει: μια σιωπηλή απόκρυψη διαβάζεται ως βλάβη
 * Ο επιλογέας πλακιδίων απορρίπτει όσα η ΕΓΣΑ'87 δεν αποδίδει εντός ανοχής. Χωρίς κανάλι προς την
 * οθόνη, η συνέπεια είναι υπόβαθρο που **λείπει σε μια περιοχή χωρίς κανένα σημάδι** — ακριβώς η
 * κλάση «αποτυχία που κανείς δεν μπορεί να μάθει» που γέννησε το CHECK 3.45, και ακριβώς η
 * συμπεριφορά που η επικεφαλίδα του `basemap-availability` απαγορεύει γραπτά: *«η άρνηση είναι
 * απάντηση, όχι σιωπή»*.
 *
 * ## Γιατί ΞΕΧΩΡΙΣΤΟ από τη διαθεσιμότητα — δύο ερωτήματα, δύο όργανα
 * Η `BasemapAvailability` απαντά «**πού** είναι το έργο πάνω στη Γη» — ιδιότητα του **έργου**,
 * σταθερή όσο κανείς δεν αλλάζει γεωαναφορά. Εδώ απαντιέται «μπορεί η προβολή να αποδώσει **αυτή
 * την όψη**» — ιδιότητα της **κάμερας**, που αλλάζει σε κάθε zoom. Συγχωνευμένα σε ένα πεδίο, ένα
 * zoom-out θα έσβηνε την ένδειξη προέλευσης της άγκυρας, και μια αλλαγή διεύθυνσης θα καθάριζε
 * την προειδοποίηση ζώνης. Ένα με «ή» θα ήταν λάθος και προς τις δύο κατευθύνσεις (CHECK 3.41).
 *
 * ## ⚠️ ΔΕΝ εγγράφεται στο `basemap-invalidation`
 * Εκείνο απαριθμεί τι **προκαλεί** ζωγραφική. Αυτό είναι **αποτέλεσμα** ζωγραφικής: βάζοντάς το
 * εκεί, κάθε καρέ θα σήκωνε σημαία που θα ζητούσε νέο καρέ — ατέρμων βρόχος με το πρόσωπο μιας
 * βελτίωσης ορατότητας. Οι επιφάνειες που το δείχνουν εγγράφονται **απευθείας** εδώ.
 *
 * ## Γιατί ανά επιφάνεια και όχι μία τιμή
 * Η κάτοψη και η τρισδιάστατη σκηνή έχουν **δικές τους** κάμερες και ζουν ταυτόχρονα. Μία κοινή
 * τιμή θα την ξανάγραφε όποια ζωγράφιζε τελευταία, δηλαδή η ένδειξη θα **τρεμόπαιζε** ανάλογα με
 * τη σειρά των καρέ — κατάσταση που φαίνεται τυχαία και κυνηγιέται σαν σφάλμα React.
 */

import { createExternalStore } from '@/lib/state/createExternalStore';

/** Ποια επιφάνεια αναφέρει — **κλειστό σύνολο**, όσες και οι κάμερες που ζωγραφίζουν υπόβαθρο. */
export type BasemapPaintSurface = 'plan' | 'scene';

/** Πόσα πλακίδια κρύβει κάθε επιφάνεια αυτή τη στιγμή. */
type FidelityReport = Readonly<Record<BasemapPaintSurface, number>>;

const EMPTY: FidelityReport = { plan: 0, scene: 0 };

/**
 * ⚠️ Με `equals` επίτηδες: ο ζωγράφος αναφέρει σε **κάθε καρέ**, δηλαδή ~60 φορές το δευτερόλεπτο
 * κατά το pan. Χωρίς φραγμό ταυτότητας κάθε καρέ θα ειδοποιούσε το React για τιμή που **δεν
 * άλλαξε** — 60 render/s σε ένα τσιπάκι κειμένου, η ακριβής κλάση βλάβης που φυλάει το ADR-040.
 */
const reportStore = createExternalStore<FidelityReport>(EMPTY, {
  equals: (a, b) => a.plan === b.plan && a.scene === b.scene,
});

/**
 * Ο **μοναδικός** γραφέας: ο ζωγράφος κάθε επιφάνειας, με το `droppedForFidelity` της επιλογής του.
 *
 * ⚠️ Δέχεται και το **μηδέν**, και αυτό είναι το μισό της αξίας του: όταν ο χρήστης ξανακάνει
 * μεγέθυνση, η ένδειξη οφείλει να **σβήσει**. Ένας γραφέας που καλείται μόνο «όταν υπάρχει
 * πρόβλημα» αφήνει την προειδοποίηση κολλημένη για πάντα.
 */
export function reportTileFidelity(surface: BasemapPaintSurface, droppedCount: number): void {
  const current = reportStore.get();
  // Ο φραγμός εδώ **δεν** είναι διπλός με το `equals` του store: εκείνο συγκρίνει *αφού* έχει
  // φτιαχτεί το νέο αντικείμενο. Αυτός γλιτώνει την ίδια την κατανομή, σε κάθε καρέ pan.
  if (current[surface] === droppedCount) return;
  reportStore.set({ ...current, [surface]: droppedCount });
}

/**
 * `true` όταν **κάποια** επιφάνεια κρύβει πλακίδια.
 *
 * Το πλήθος δεν φτάνει στην οθόνη επίτηδες: το «16 πλακίδια» δεν λέει τίποτα σε κανέναν, ενώ η
 * **αιτία** και η **θεραπεία** («κάνε μεγέθυνση») λένε τα πάντα — ίδια αρχή με τους ονομασμένους
 * λόγους άρνησης του `basemap-availability`, όπου η θεραπεία είναι το μόνο χρήσιμο.
 */
export function isBasemapTruncated(): boolean {
  const report = reportStore.get();
  return report.plan > 0 || report.scene > 0;
}

/** Το πλήθος ανά επιφάνεια — για άγκυρες και διαγνωστικά, **όχι** για την οθόνη. */
export function getTileFidelityReport(): FidelityReport {
  return reportStore.get();
}

/** Εγγραφή στην αλλαγή. Οι επιφάνειες που δείχνουν την ένδειξη καλούν **αυτό**, όχι το invalidation. */
export function subscribeTileFidelity(listener: () => void): () => void {
  return reportStore.subscribe(listener);
}

/** Καθαρισμός ανάμεσα σε δοκιμές — αλλιώς η αναφορά μιας άγκυρας διαρρέει στην επόμενη. */
export function resetTileFidelityReport(): void {
  reportStore.reset(EMPTY);
}
