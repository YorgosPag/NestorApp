/**
 * «Μπορεί αυτό το έργο να δείξει χάρτη — και **πόσο αξιόπιστα**;»
 *
 * ## Γιατί δεν αρκεί ένα boolean
 * Χωρίς γεωαναφορά, το σχέδιο ζει σε τοπικές συντεταγμένες γύρω από το μηδέν. Αν ο χάρτης
 * ζωγραφιζόταν έτσι, το ΕΓΣΑ'87 `(0, 0)` πέφτει **στον Ατλαντικό**, πεντακόσια χιλιόμετρα δυτικά
 * του κεντρικού μεσημβρινού πάνω στον ισημερινό. Ο χρήστης θα έβλεπε ωκεανό κάτω από το κτίριό
 * του και θα συμπέραινε ότι «ο χάρτης δεν δουλεύει» — ενώ ο χάρτης θα δούλευε τέλεια και θα
 * έλεγε την αλήθεια: **κανείς δεν έχει πει πού βρίσκεται αυτό το κτίριο**.
 *
 * Ένα `boolean` θα συγχώνευε δύο πράγματα που έχουν **διαφορετική θεραπεία**: «δεν ξέρω πού
 * είσαι» (τρέξε το εργαλείο ευθυγράμμισης) και «ξέρω κατά προσέγγιση» (δούλεψε, αλλά μη
 * βασιστείς στα εκατοστά). Γι' αυτό οι καταστάσεις είναι ονομασμένες.
 *
 * ⚠️ **Καμία σιωπηλή μαντεψιά**: η κατάσταση `approximate` υπάρχει ώστε μια κατά προσέγγιση θέση
 * να μπορεί να **δηλωθεί** ως τέτοια στην οθόνη. Δεν επιτρέπεται να παρουσιαστεί ως ακριβής, και
 * δεν γράφεται ποτέ ως γεωαναφορά του έργου: μια διεύθυνση δίνει ακρίβεια οικοδομικού
 * τετραγώνου και **καμία** πληροφορία στροφής.
 */

import { createExternalStore } from '../../stores/createExternalStore';
import { getGeoReference, subscribeGeoReference } from '../geo-referencing/geo-reference-store';
import { isIdentityGeoReference } from '../geo-referencing/geo-transform';

export type BasemapAvailability =
  /** Το έργο είναι γεωαναφερμένο — ο χάρτης κάθεται εκεί που πρέπει. */
  | 'exact'
  /** Γνωστή κατά προσέγγιση θέση (π.χ. από τη διεύθυνση) — απαιτεί ορατή ένδειξη. */
  | 'approximate'
  /** Καμία πληροφορία θέσης — ο χάρτης **δεν** ζωγραφίζεται. */
  | 'unknown';

/**
 * Προσωρινή άγκυρα, όταν υπάρχει: το κέντρο μιας κατά προσέγγιση θέσης σε WGS84.
 *
 * Ζει σε **δικό** της χώρο και **όχι** στο `geo-reference-store` επίτηδες. Εκείνο το store είναι
 * η δηλωμένη αλήθεια του έργου, την οποία διαβάζουν το τοπογραφικό, οι πίνακες συντεταγμένων και
 * η εξαγωγή IFC. Γράφοντας εκεί μια εικασία από διεύθυνση, η εικασία θα κατέληγε σε **νομικά
 * παραδοτέα** — η χειρότερη μορφή σιωπηλής μαντεψιάς που επιτρέπει αυτή η αρχιτεκτονική.
 */
export interface ApproximateAnchor {
  readonly lat: number;
  readonly lon: number;
  /** Από πού προήλθε — εμφανίζεται στον χρήστη ώστε να ξέρει τι εμπιστεύεται. */
  readonly originKey: string;
}

const anchorStore = createExternalStore<ApproximateAnchor | null>(null);

/** Δήλωση κατά προσέγγιση θέσης (π.χ. μετά από γεωκωδικοποίηση της διεύθυνσης του έργου). */
export function setApproximateAnchor(anchor: ApproximateAnchor | null): void {
  anchorStore.set(anchor);
}

/** Η ενεργή κατά προσέγγιση άγκυρα, αν υπάρχει. */
export function getApproximateAnchor(): ApproximateAnchor | null {
  return anchorStore.get();
}

/**
 * Η τρέχουσα κατάσταση διαθεσιμότητας.
 *
 * Η σειρά των ελέγχων είναι συμβόλαιο: η **ακριβής** γεωαναφορά υπερισχύει πάντα της κατά
 * προσέγγιση άγκυρας. Αντίστροφα, μια παλιά εικασία θα σκίαζε την αληθινή θέση μετά την
 * ευθυγράμμιση — δηλαδή η δουλειά του χρήστη δεν θα φαινόταν.
 */
export function getBasemapAvailability(): BasemapAvailability {
  if (!isIdentityGeoReference(getGeoReference())) return 'exact';
  if (anchorStore.get()) return 'approximate';
  return 'unknown';
}

/**
 * Εγγραφή σε αλλαγές της διαθεσιμότητας — **και στις δύο** πηγές που την καθορίζουν.
 *
 * ⚠️ Η διανομή σε δύο εγγραφές δεν είναι λεπτομέρεια υλοποίησης: η κατάσταση προκύπτει από τον
 * συνδυασμό τους, οπότε μια διεπαφή που άκουγε μόνο τη γεωαναφορά θα έμενε **σιωπηλά παγωμένη**
 * όταν έρχεται η κατά προσέγγιση άγκυρα — το κουμπί θα έμενε ανενεργό ενώ ο χάρτης θα είχε πια
 * πού να καθίσει, και κανένα μήνυμα δεν θα εξηγούσε γιατί.
 */
export function subscribeBasemapAvailability(listener: () => void): () => void {
  const unsubscribeGeo = subscribeGeoReference(listener);
  const unsubscribeAnchor = anchorStore.subscribe(listener);
  return () => {
    unsubscribeGeo();
    unsubscribeAnchor();
  };
}
