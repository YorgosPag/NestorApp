/**
 * ADR-665 M2.2 — το ΕΝΑ ημιεπίπεδο clip σε **βαθμωτό πεδίο**. Καθαρό, χωρίς store/THREE/TIN.
 *
 * ── Η ερώτηση που απαντά ────────────────────────────────────────────────────────────────────
 * «Κράτησε το μέρος ενός επίπεδου πολυγώνου όπου ένα βαθμωτό πεδίο `f` δεν αλλάζει πρόσημο.»
 * Είναι το εσωτερικό βήμα του Sutherland–Hodgman, αλλά **πάνω στο πεδίο** και όχι πάνω σε clip
 * edge: ένα clip πολύγωνο δεν μπορεί να εκφράσει «εκεί όπου το `f` αλλάζει πρόσημο».
 *
 * ── Γιατί ζει χωριστά (N.18 / ADR-584) ──────────────────────────────────────────────────────
 * Το έργο ρωτά αυτό το ίδιο ερώτημα σε **δύο** πεδία που δεν έχουν καμία σχέση μεταξύ τους:
 *   • `cut-fill-geometry` — πεδίο `Δz` (επιφάνεια − αναφορά): η «γραμμή daylight» του Civil 3D,
 *     που χωρίζει εκσκαφή από επίχωση μέσα σε ΕΝΑ τρίγωνο (ADR-650 M6).
 *   • `terrain-cut-cap-geometry` — πεδίο `z − levelZ`: η τομή του αναγλύφου στη στάθμη του
 *     ενεργού ορόφου (ADR-665 M2).
 * Ίδιος αλγόριθμος, άλλο πεδίο. Δεύτερο αντίγραφο θα ήταν ακριβώς ο structural clone που το
 * CHECK 3.28 (jscpd) υπάρχει για να κόβει — και, χειρότερα, δύο αντίγραφα μιας αριθμητικής
 * λεπτομέρειας (ποιος μένει όταν `f == 0`) που πρέπει να συμφωνούν για να μείνει η γεωμετρία
 * στεγανή.
 *
 * ── Η λεπτομέρεια που είναι ΟΛΟ το νόημα ────────────────────────────────────────────────────
 * Κορυφή **ακριβώς** στο μηδέν μπαίνει και στα ΔΥΟ μισά (`sign * f >= 0` και για τα δύο πρόσημα).
 * Αυτό είναι που κρατά τα δύο κομμάτια **στεγανά**: τα εμβαδά τους αθροίζουν πίσω στο αρχικό.
 * Χαλάρωσέ το σε `> 0` και ανοίγει σχισμή μηδενικού πλάτους — αόρατη στο μάτι, θανάσιμη στο
 * άθροισμα όγκων και στο anchor εμβαδού του M2.
 *
 * ── Γιατί generic με callbacks και όχι κοινός τύπος κορυφής ─────────────────────────────────
 * Ο cut/fill τρέχει αυτόν τον βρόχο **ανά τρίγωνο** πάνω σε ολόκληρη TIN. Ένας adapter που θα
 * έκανε `map()` σε κοινό σχήμα `{x, y, f}` θα κατένειμε 3 αντικείμενα ανά τρίγωνο ανά πρόσημο,
 * σκέτα για να ικανοποιήσει τον τύπο. Τα δύο callbacks μηδενίζουν κάθε ενδιάμεση κατανομή και
 * αφήνουν κάθε καλούντα να κρατήσει τη **δική** του σημασιολογική κορυφή (`dz` vs υψόμετρο).
 *
 * @see ./cut-fill-geometry.ts — καλών #1 (πεδίο Δz)
 * @see ./terrain-cut-cap-geometry.ts — καλών #2 (πεδίο z − levelZ)
 * @see ./marching-triangles.ts — `crossEdge`, η ΜΙΑ γραμμική παρεμβολή στο μηδέν
 */

import type { Point2D } from '../../rendering/types/Types';
import { crossEdge } from './marching-triangles';

/**
 * Κράτησε το μέρος του `polygon` όπου `sign · f ≥ 0`, εισάγοντας νέες κορυφές πάνω στο `f = 0`.
 *
 * Ένα πολύγωνο ολόκληρο στη μία πλευρά επιστρέφει **αυτούσιο** από εκείνη την πλευρά και **κενό**
 * από την άλλη — η συνηθισμένη περίπτωση, και κοστίζει έναν έλεγχο προσήμου ανά κορυφή.
 * Αποτέλεσμα με < 3 κορυφές (εκφυλισμένο) επιστρέφεται ως κενό: δεν είναι πολύγωνο.
 *
 * **Κυρτότητα:** το ημιεπίπεδο είναι κυρτό, άρα το clip ενός **κυρτού** πολυγώνου είναι κυρτό —
 * γι' αυτό ένα τρίγωνο δίνει πάντα 0, 3 ή 4 κορυφές και **δεν χρειάζεται επανατριγωνοποίηση**
 * (fan από την πρώτη κορυφή είναι εξ ορισμού σωστό). Για μη κυρτή είσοδο ισχύει η γενική
 * σημασιολογία του Sutherland–Hodgman.
 *
 * @param fieldOf     Το βαθμωτό πεδίο στην κορυφή. Μη-πεπερασμένη τιμή θεωρείται **εκτός**.
 * @param atCrossing  Χτίζει την κορυφή του καλούντα από το επίπεδο σημείο τομής (`f = 0` εκεί).
 */
export function clipPolygonAtScalarZero<TVertex>(
  polygon: readonly TVertex[],
  sign: 1 | -1,
  fieldOf: (vertex: TVertex) => number,
  atCrossing: (point: Point2D, previous: TVertex, current: TVertex) => TVertex,
): TVertex[] {
  const n = polygon.length;
  if (n < 3) return [];

  // Τα πεδία υπολογίζονται ΜΙΑ φορά, πριν από οτιδήποτε άλλο, για δύο λόγους. Ο δεύτερος είναι
  // ο σοβαρός: αν έστω μία κορυφή έχει μη-πεπερασμένο πεδίο, **ολόκληρο** το πολύγωνο
  // απορρίπτεται. Δεν αρκεί να τη θεωρήσουμε «έξω» — η ΑΚΜΗ που την ακουμπά θα ζητούσε
  // παρεμβολή μεταξύ πεπερασμένου και NaN, που δίνει NaN **συντεταγμένη**, δηλαδή διαρροή του
  // σφάλματος από το πεδίο στη ΓΕΩΜΕΤΡΙΑ. Και μία NaN κορυφή αρκεί για να γίνει NaN το `Box3`
  // της σκηνής και να σβήσει όλο το 3Δ (ADR-537). Άρνηση > σιωπηλή μόλυνση.
  const fields = new Array<number>(n);
  for (let i = 0; i < n; i++) {
    const field = fieldOf(polygon[i]!);
    if (!Number.isFinite(field)) return [];
    fields[i] = field;
  }

  const out: TVertex[] = [];
  for (let i = 0; i < n; i++) {
    const previousIndex = (i + n - 1) % n;
    const current = polygon[i]!;
    const previous = polygon[previousIndex]!;
    const currentField = fields[i]!;
    const previousField = fields[previousIndex]!;
    const currentInside = sign * currentField >= 0;
    const previousInside = sign * previousField >= 0;

    if (currentInside !== previousInside) {
      out.push(atCrossing(zeroCrossing(previous, previousField, current, currentField), previous, current));
    }
    if (currentInside) out.push(current);
  }
  return out.length >= 3 ? out : [];
}

/**
 * Το σημείο της ακμής a→b όπου `f = 0`, μέσω της γραμμικής τομής του εξαγωγέα ισοϋψών (SSoT):
 * είναι το ίδιο ερώτημα που κάνει το marching σε πεδίο υψομέτρου, σε άλλο πεδίο.
 */
function zeroCrossing<TVertex>(
  a: TVertex,
  fa: number,
  b: TVertex,
  fb: number,
): Point2D {
  return crossEdge(toPoint(a), fa, toPoint(b), fb, 0);
}

/**
 * Κάθε κορυφή καλούντα φέρει `x`/`y` — αυτό είναι το μόνο που ζητά το generic συμβόλαιο, και το
 * μόνο που χρειάζεται η παρεμβολή. Δηλωμένο μία φορά εδώ αντί για `TVertex extends Point2D`, ώστε
 * ο τύπος του καλούντα να μη χρειάζεται να είναι δομικά συμβατός με το `Point2D` (μπορεί να έχει
 * readonly πεδία, επιπλέον κλειδιά, ή να είναι tuple-like).
 */
function toPoint<TVertex>(vertex: TVertex): Point2D {
  const { x, y } = vertex as unknown as Point2D;
  return { x, y };
}
