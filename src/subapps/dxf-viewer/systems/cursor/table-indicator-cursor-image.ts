/**
 * ADR-739 §31 — **ΤΑ ΔΥΟ ΠΑΧΙΑ ΒΕΛΗ** του δείκτη πίνακα, ως δείκτες υλικού (⬇ και ➡).
 *
 * Το Excel δηλώνει «αυτή η στήλη επιλέγεται ολόκληρη» με ένα παχύ βέλος προς τα κάτω πάνω από
 * το γράμμα, και «αυτή η γραμμή» με βέλος προς τα δεξιά πάνω από τον αριθμό. Είναι το μοναδικό
 * κομμάτι του §31 που **δεν** υπάρχει ως λέξη-κλειδί CSS: το `col-resize` / `row-resize` τα
 * ζωγραφίζει ο ΟΣ, τα βέλη επιλογής **όχι**. Άρα ζωγραφίζονται εδώ.
 *
 * ## 🔴 PNG, ΟΧΙ SVG — και δεν είναι προτίμηση
 * Ο **Chrome απορρίπτει SVG data-URL δείκτες** (δουλεύουν σε Firefox· επαληθεύτηκε σε browser
 * 2026-06-29, ADR-549 Φ8). Ένας απορριφθείς δείκτης δεν κάνει fallback σε κάτι λογικό: πέφτει
 * **ολόκληρη** η δήλωση `cursor` και νικά η κλάση του element — που εδώ είναι `cursor-crosshair`.
 * Δηλαδή το σφάλμα δεν θα φαινόταν ως «άσχημο βέλος», αλλά ως «το βέλος δεν εμφανίστηκε ποτέ».
 * Ο **μόνος** τύπος που δέχονται όλοι οι browsers είναι PNG data-URL — γι' αυτό ζωγραφίζουμε σε
 * offscreen canvas, ακριβώς όπως το σταυρόνημα.
 *
 * ## 🔴 ΤΟ ΟΡΙΟ ΜΕΓΕΘΟΥΣ ΣΥΣΚΕΥΗΣ — η ίδια παγίδα, ίδια θεραπεία
 * Windows/Chrome απορρίπτουν **σιωπηλά** δείκτη με φυσικό μέγεθος πάνω από ~32px. Ένα 24px CSS
 * εικονίδιο σε dpr 1.5 είναι 36 device px ⇒ απόρριψη ⇒ κανένα βέλος. Γι' αυτό το CSS μέγεθος
 * **συρρικνώνεται** ώστε το φυσικό να μένει κάτω από το όριο σε **κάθε** dpr, και η ρασταροποίηση
 * γίνεται στο φυσικό μέγεθος μέσω `image-set(... Nx)` ώστε να μένει ευκρινές. Δες τη μονάδα του
 * σταυρονήματος για την πλήρη ιστορία — εδώ επαναλαμβάνεται η **αρχή**, όχι ο κώδικας.
 *
 * ## 🔴 ΤΟ ΣΗΜΕΙΟ ΕΝΕΡΓΕΙΑΣ ΕΙΝΑΙ ΤΟ ΚΕΝΤΡΟ, ΟΧΙ Η ΑΙΧΜΗ
 * Το προφανές θα ήταν να μπει στην **αιχμή** του βέλους — εκεί «δείχνει». Θα ήταν σφάλμα με
 * ορατό σύμπτωμα: το ίδιο pixel που **ανάβει** τον δείκτη είναι το σημείο ενέργειας, οπότε με
 * την αιχμή έξω από τη ζώνη ο δείκτης θα έβγαινε από τη ζώνη τη στιγμή που θα την άγγιζε ⇒ η
 * απαίτηση θα καθαριζόταν ⇒ πίσω στο σταυρόνημα ⇒ ξανά μέσα. **Τρεμόπαιγμα 60 φορές το
 * δευτερόλεπτο**, ακριβώς στο χείλος της λωρίδας. Με το κέντρο, το εικονίδιο και η ερώτηση
 * «είμαι μέσα;» μιλούν για το **ίδιο** σημείο. Το Excel κάνει το ίδιο.
 *
 * ## Γιατί μαύρο γέμισμα ΜΕ λευκό φωτοστέφανο
 * Η εφαρμογή έχει σκούρο θέμα, αλλά η **ζώνη** είναι ανοιχτόχρωμη (γκρι χάρακα) όταν είναι
 * ουδέτερη και **μπλε** όταν είναι ενεργή — και ο δείκτης περνά και από τις δύο, συν το
 * σκούρο κενό ανάμεσά τους. Ένα μονόχρωμο βέλος θα εξαφανιζόταν σε μία από τις τρεις. Το
 * περίγραμμα ζωγραφίζεται **πρώτο και πλατύτερο**, ώστε το γέμισμα να το κόψει στη μέση και να
 * μείνει φωτοστέφανο — η ίδια τεχνική που κάνει τους δείκτες του ΟΣ ορατούς σε κάθε φόντο.
 *
 * @module subapps/dxf-viewer/systems/cursor/table-indicator-cursor-image
 * @see systems/cursor/crosshair-cursor-image.ts — το πρότυπο (και η πλήρης ιστορία του ορίου)
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §31
 */

import { getDevicePixelRatio, toDevicePixels } from './utils';

/**
 * Μέγιστη πλευρά δείκτη σε **pixel συσκευής**. Πάνω από αυτό, Windows/Chrome απορρίπτουν
 * σιωπηλά τη δήλωση — δες την κεφαλίδα. Ίδια τιμή με το σταυρόνημα, ίδιος λόγος.
 */
const MAX_CURSOR_DEVICE_PX = 32;

/** Ζητούμενη πλευρά σε CSS px· συρρικνώνεται αυτόματα ώστε το φυσικό μέγεθος να μένει υπό όριο. */
const CURSOR_CSS_PX = 20;

/** Μικρότερη πλευρά που ζωγραφίζουμε ποτέ (κρατά το βέλος αναγνωρίσιμο σε ακραίο dpr). */
const MIN_CURSOR_CSS_PX = 10;

/** Πάχος φωτοστέφανου σε CSS px — δες την κεφαλίδα για το γιατί ζωγραφίζεται πρώτο. */
const OUTLINE_CSS_PX = 2;

/** Ο άξονας στον οποίο δείχνει το βέλος. Η γεωμετρία είναι **μία**· αλλάζει μόνο η προβολή. */
export type TableArrowDirection = 'down' | 'right';

/**
 * Το περίγραμμα του βέλους σε **κανονικοποιημένες** συντεταγμένες `[0..1]`, για κατεύθυνση
 * «κάτω». Κρατιέται αδιάστατο ώστε το ίδιο σχήμα να δουλεύει σε κάθε μέγεθος και dpr χωρίς
 * δεύτερο σύνολο αριθμών — και ώστε η στροφή για το «δεξιά» να είναι **αντιμετάθεση**, όχι
 * δεύτερο σχήμα που θα μπορούσε να αποκλίνει.
 *
 * Αναλογίες Excel: κοντό φαρδύ στέλεχος, κεφάλι σαφώς πλατύτερο, αιχμή που δεν φτάνει στην
 * άκρη (αφήνει χώρο στο φωτοστέφανο να μη κοπεί από το πλαίσιο της εικόνας).
 */
const ARROW_OUTLINE: readonly (readonly [number, number])[] = [
  [0.34, 0.14],
  [0.66, 0.14],
  [0.66, 0.55],
  [0.88, 0.55],
  [0.50, 0.90],
  [0.12, 0.55],
  [0.34, 0.55],
];

/** Χαράζει το περίγραμμα του βέλους σε πλέγμα `size`×`size`, στον ζητούμενο άξονα. */
function traceArrow(ctx: CanvasRenderingContext2D, size: number, direction: TableArrowDirection): void {
  ctx.beginPath();
  ARROW_OUTLINE.forEach(([nx, ny], index) => {
    // «Δεξιά» = το ίδιο σχήμα με εναλλαγμένους άξονες (ανάκλαση στη διαγώνιο). Μία γεωμετρία,
    // δύο προβολές — ένα δεύτερο πίνακας σημείων θα ήταν sibling clone (N.18).
    const x = (direction === 'down' ? nx : ny) * size;
    const y = (direction === 'down' ? ny : nx) * size;
    if (index === 0) ctx.moveTo(x, y);
    else ctx.lineTo(x, y);
  });
  ctx.closePath();
}

/**
 * Χτίζει τιμή CSS `cursor`: PNG του παχιού βέλους με σημείο ενέργειας στο **κέντρο** του, συν
 * λέξη-κλειδί εφεδρείας. Εφαρμογή: `element.style.cursor = buildTableArrowCursorValue('down')`.
 *
 * Επιστρέφει τη γυμνή λέξη-κλειδί όταν δεν υπάρχει canvas (SSR / περιβάλλον test): ο δείκτης
 * υποβαθμίζεται σε κάτι λογικό αντί να πετάξει.
 */
export function buildTableArrowCursorValue(direction: TableArrowDirection): string {
  // `pointer` ως εφεδρεία: δηλώνει «πατιέται», που είναι ακριβώς το μήνυμα του βέλους. Ένα
  // `default` θα έλεγε το αντίθετο, και είναι η τιμή που πραγματικά εμφανίζεται αν το PNG
  // απορριφθεί — δηλαδή η εφεδρεία ΔΕΝ είναι διακοσμητική.
  if (typeof document === 'undefined') return 'pointer';

  const dpr = getDevicePixelRatio();
  const maxCssForDevice = MAX_CURSOR_DEVICE_PX / dpr;
  const cssSize = Math.max(MIN_CURSOR_CSS_PX, Math.min(CURSOR_CSS_PX, maxCssForDevice));
  const devicePx = Math.min(toDevicePixels(cssSize, dpr), MAX_CURSOR_DEVICE_PX);

  const canvas = document.createElement('canvas');
  canvas.width = devicePx;
  canvas.height = devicePx;
  const ctx = canvas.getContext('2d');
  if (!ctx) return 'pointer';

  // Ζωγραφίζουμε σε συντεταγμένες CSS px πάνω σε φυσικό backing store → ευκρινές σε HiDPI.
  ctx.scale(devicePx / cssSize, devicePx / cssSize);
  traceArrow(ctx, cssSize, direction);
  // Φωτοστέφανο πρώτο και πλατύτερο· το γέμισμα από πάνω το κόβει στη μέση — δες την κεφαλίδα.
  ctx.lineJoin = 'round';
  ctx.lineCap = 'round';
  ctx.strokeStyle = '#ffffff';
  ctx.lineWidth = OUTLINE_CSS_PX;
  ctx.stroke();
  ctx.fillStyle = '#000000';
  ctx.fill();

  const dataUrl = canvas.toDataURL('image/png');
  // Το εμφανιζόμενο μέγεθος διαφέρει ανά διαδρομή εκπομπής, και το σημείο ενέργειας δηλώνεται σε
  // **εμφανιζόμενα** CSS px: με `image-set(... Nx)` το ράστερ δείχνεται στο `cssSize`, με σκέτο
  // `url()` δείχνεται 1:1 στο `devicePx`. Ίδια διόρθωση με το σταυρόνημα (ADR-549 Φ8, 2026-07-04)
  // — χωρίς αυτήν, σε dpr κάτω από 1 (σελίδα στο 80%) το σημείο ενέργειας ξεφεύγει από το κέντρο.
  const emittedCssSize = dpr > 1 ? cssSize : devicePx;
  const hot = Math.round(emittedCssSize / 2);

  return dpr > 1
    ? `image-set(url("${dataUrl}") ${dpr}x) ${hot} ${hot}, pointer`
    : `url("${dataUrl}") ${hot} ${hot}, pointer`;
}
