/**
 * ADR-739 §31 / ADR-754 §14 — **ΟΙ ΖΩΓΡΑΦΙΣΜΕΝΟΙ ΔΕΙΚΤΕΣ** του πίνακα, ως δείκτες υλικού:
 * τα δύο παχιά βέλη επιλογής άξονα (⬇ ➡) και ο **λεπτός μαύρος σταυρός** της λαβής
 * συμπλήρωσης (✛).
 *
 * Το Excel δηλώνει «αυτή η στήλη επιλέγεται ολόκληρη» με ένα παχύ βέλος προς τα κάτω πάνω από
 * το γράμμα, και «αυτή η γραμμή» με βέλος προς τα δεξιά πάνω από τον αριθμό. Είναι το μοναδικό
 * κομμάτι του §31 που **δεν** υπάρχει ως λέξη-κλειδί CSS: το `col-resize` / `row-resize` τα
 * ζωγραφίζει ο ΟΣ, τα βέλη επιλογής **όχι**. Άρα ζωγραφίζονται εδώ.
 *
 * ## 🔴 ADR-754 §14 — Ο ΤΡΙΤΟΣ ΕΝΟΙΚΟΣ ΜΠΗΚΕ ΓΙΑ ΑΛΛΟΝ ΛΟΓΟ ΑΠΟ ΤΟΥΣ ΔΥΟ ΠΡΩΤΟΥΣ
 * Τα βέλη ζωγραφίζονται επειδή **δεν υπάρχει** λέξη-κλειδί γι' αυτά σε καμία πλατφόρμα. Ο
 * σταυρός της λαβής ζωγραφίζεται επειδή η λέξη-κλειδί **υπάρχει και είναι πιασμένη**: το
 * `cursor: crosshair` θα ήταν οπτικά ταυτόσημο με το σταυρόνημα CAD που ο Νέστωρ δείχνει ήδη σε
 * ολόκληρο τον καμβά (ADR-549 Φ8), δηλαδή ταυτόσημο με το «κανένας ρόλος». Δύο διαφορετικοί
 * δρόμοι, ίδιο συμπέρασμα — και το τίμημα από κάτω πληρώνεται και για τους τρεις.
 *
 * ## 🔴 PNG, ΟΧΙ SVG — και δεν είναι προτίμηση
 * Ο **Chrome απορρίπτει SVG data-URL δείκτες** (δουλεύουν σε Firefox· επαληθεύτηκε σε browser
 * 2026-06-29, ADR-549 Φ8). Ένας απορριφθείς δείκτης δεν κάνει fallback σε κάτι λογικό: πέφτει
 * **ολόκληρη** η δήλωση `cursor` και νικά η κλάση του element — που εδώ είναι `cursor-crosshair`.
 * Δηλαδή το σφάλμα δεν θα φαινόταν ως «άσχημο βέλος», αλλά ως «το βέλος δεν εμφανίστηκε ποτέ».
 * Ο **μόνος** τύπος που δέχονται όλοι οι browsers είναι PNG data-URL — γι' αυτό ζωγραφίζουμε σε
 * offscreen canvas, ακριβώς όπως το σταυρόνημα.
 *
 * ## 🔴 ΤΟ ΟΡΙΟ ΜΕΓΕΘΟΥΣ ΣΥΣΚΕΥΗΣ — η ίδια παγίδα, ίδια θεραπεία
 * Windows/Chrome απορρίπτουν **σιωπηλά** δείκτη με φυσικό μέγεθος πάνω από ~32px. Ένα 24px CSS
 * εικονίδιο σε dpr 1.5 είναι 36 device px ⇒ απόρριψη ⇒ κανένα βέλος. Γι' αυτό το CSS μέγεθος
 * **συρρικνώνεται** ώστε το φυσικό να μένει κάτω από το όριο σε **κάθε** dpr, και η ρασταροποίηση
 * γίνεται στο φυσικό μέγεθος μέσω `image-set(... Nx)` ώστε να μένει ευκρινές. Δες τη μονάδα του
 * σταυρονήματος για την πλήρη ιστορία — εδώ επαναλαμβάνεται η **αρχή**, όχι ο κώδικας.
 *
 * ## 🔴 ΤΟ ΣΗΜΕΙΟ ΕΝΕΡΓΕΙΑΣ ΕΙΝΑΙ ΤΟ ΚΕΝΤΡΟ, ΟΧΙ Η ΑΙΧΜΗ
 * Το προφανές θα ήταν να μπει στην **αιχμή** του βέλους — εκεί «δείχνει». Θα ήταν σφάλμα με
 * ορατό σύμπτωμα: το ίδιο pixel που **ανάβει** τον δείκτη είναι το σημείο ενέργειας, οπότε με
 * την αιχμή έξω από τη ζώνη ο δείκτης θα έβγαινε από τη ζώνη τη στιγμή που θα την άγγιζε ⇒ η
 * απαίτηση θα καθαριζόταν ⇒ πίσω στο σταυρόνημα ⇒ ξανά μέσα. **Τρεμόπαιγμα 60 φορές το
 * δευτερόλεπτο**, ακριβώς στο χείλος της λωρίδας. Με το κέντρο, το εικονίδιο και η ερώτηση
 * «είμαι μέσα;» μιλούν για το **ίδιο** σημείο. Το Excel κάνει το ίδιο.
 *
 * ## Γιατί μαύρο γέμισμα ΜΕ λευκό φωτοστέφανο
 * Η εφαρμογή έχει σκούρο θέμα, αλλά η **ζώνη** είναι ανοιχτόχρωμη (γκρι χάρακα) όταν είναι
 * ουδέτερη και **μπλε** όταν είναι ενεργή — και ο δείκτης περνά και από τις δύο, συν το
 * σκούρο κενό ανάμεσά τους. Ένα μονόχρωμο βέλος θα εξαφανιζόταν σε μία από τις τρεις. Το
 * περίγραμμα ζωγραφίζεται **πρώτο και πλατύτερο**, ώστε το γέμισμα να το κόψει στη μέση και να
 * μείνει φωτοστέφανο — η ίδια τεχνική που κάνει τους δείκτες του ΟΣ ορατούς σε κάθε φόντο.
 *
 * @module subapps/dxf-viewer/systems/cursor/table-indicator-cursor-image
 * @see systems/cursor/crosshair-cursor-image.ts — το πρότυπο (και η πλήρης ιστορία του ορίου)
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §31
 */

import { getDevicePixelRatio, toDevicePixels } from './utils';
// 🔴 ADR-768 Βήμα 5 (N.7.1) — τα **σχήματα** μετακόμισαν όταν ο τέταρτος ένοικος πέρασε τις 500
// γραμμές. Η τομή είναι η ίδια που ήδη δηλώνει ο `rasterizeCursorValue`: εδώ το **τίμημα της
// συσκευής**, εκεί το **μελάνι**.
import {
  traceArrow,
  traceMoveCross,
  tracePaintGlyph,
  type TableArrowDirection,
} from './table-indicator-cursor-shapes';

// Το ίδιο δημόσιο πρόσωπο με πριν: ο τύπος γεννιέται πλέον δίπλα στη γεωμετρία του, αλλά οι
// καταναλωτές του builder δεν οφείλουν να μάθουν ότι υπάρχει δεύτερο αρχείο.
export type { TableArrowDirection };

/**
 * Μέγιστη πλευρά δείκτη σε **pixel συσκευής**. Πάνω από αυτό, Windows/Chrome απορρίπτουν
 * σιωπηλά τη δήλωση — δες την κεφαλίδα. Ίδια τιμή με το σταυρόνημα, ίδιος λόγος.
 */
const MAX_CURSOR_DEVICE_PX = 32;

/** Ζητούμενη πλευρά **του βέλους** σε CSS px· συρρικνώνεται ώστε το φυσικό να μένει υπό όριο. */
const ARROW_CSS_PX = 20;

/**
 * 🔑 **ADR-739 §36.10 — Η ΜΙΑ ΠΛΕΥΡΑ ΤΩΝ ΔΥΟ ΔΕΙΚΤΩΝ ΧΕΙΡΟΝΟΜΙΑΣ**: του σταυρού συμπλήρωσης (✛)
 * και του σταυρού μετακίνησης (✥).
 *
 * ## Γιατί ΕΝΑΣ αριθμός και όχι δύο
 * Ο ιδιοκτήτης το ζήτησε ρητά (2026-08-06): «*το σημαδάκι του σταυρού του fill handler κάν' το
 * λίγο πιο μεγάλο και μείωσε λίγο το σημάδι της μετακίνησης — **κάν' τα ισάξια σε μέγεθος**»*.
 * Η «ισαξία» **δεν** μπορεί να είναι δύο αριθμοί που τυχαίνει να συμπίπτουν: θα αποκλίνανε την
 * πρώτη φορά που κάποιος ρύθμιζε τον έναν. Είναι **ο ίδιος** αριθμός, και η ισότητα επιβιώνει
 * ακόμη και του φράγματος συσκευής — το `rasterizeCursorValue` συρρικνώνει και τους δύο με τον
 * **ίδιο** τύπο, άρα σε κάθε dpr βγαίνουν πάλι ίσοι.
 *
 * ## Γιατί **18** — και τι έχασε ο καθένας
 * - Ο σταυρός συμπλήρωσης ήταν **14**. Η παλιά αιτιολόγηση («ο σταυρός του Excel είναι ~13 px
 *   στο 100% και η μικρότητά του **είναι** το μήνυμα») παραμένει σωστή ως προς το **σχήμα** —
 *   είναι μία ράβδος ενός pixel, όχι παχύς σταυρός — αλλά το **μήκος** δεν την υπηρετεί: το
 *   «λεπτός» το λέει το πάχος, όχι η πλευρά.
 * - Ο σταυρός μετακίνησης δεν είχε μέγεθος καθόλου: ήταν η λέξη-κλειδί `move`, δηλαδή ο δείκτης
 *   **του λειτουργικού** (Windows: SIZEALL, γλυφή ~20 px μέσα σε κουτί 32). Στα 18 είναι
 *   «λίγο πιο μικρός» — ακριβώς το ζητούμενο.
 *
 * ⚠️ Το **βέλος** επιλογής άξονα μένει στα {@link ARROW_CSS_PX} και **δεν** μπαίνει εδώ: είναι
 * άλλη οικογένεια (ανακοινώνει *επιλογή άξονα*, όχι χειρονομία πάνω σε περιοχή) και η ισαξία
 * που ζητήθηκε αφορούσε ονομαστικά τα δύο που συναντιούνται στην **ίδια γωνία**.
 */
const GESTURE_CROSS_CSS_PX = 22;

/** Μικρότερη πλευρά που ζωγραφίζουμε ποτέ (κρατά το βέλος αναγνωρίσιμο σε ακραίο dpr). */
const MIN_CURSOR_CSS_PX = 10;

/** Πάχος φωτοστέφανου σε CSS px — δες την κεφαλίδα για το γιατί ζωγραφίζεται πρώτο. */
const OUTLINE_CSS_PX = 2;

/**
 * 🔴 **Ο ΕΝΑΣ ΡΑΣΤΑΡΟΠΟΙΗΤΗΣ** — και οι **τρεις** παγίδες της κεφαλίδας, γραμμένες μία φορά.
 *
 * Εξήχθη όταν γεννήθηκε ο **δεύτερος** καταναλωτής (ο σταυρός συμπλήρωσης, ADR-754 §14): η
 * αλληλουχία «dpr ⇒ συρρίκνωση CSS ⇒ φράγμα συσκευής ⇒ canvas ⇒ `toDataURL` ⇒ σημείο ενέργειας
 * ⇒ `image-set` ή `url`» είναι ~20 γραμμές που **δεν** επιτρέπεται να υπάρχουν δύο φορές: το
 * CHECK 3.28 (jscpd, N.18) τις χαρακτηρίζει sibling clone, και —πολύ χειρότερα— η μία θα
 * ξεχνούσε τη διόρθωση του `emittedCssSize` σε `dpr < 1` και ο δείκτης της θα διάβαζε λάθος
 * pixel, **σιωπηλά**.
 *
 * Ό,τι μένει στον καλούντα είναι **μόνο το μελάνι** — και ο μετασχηματισμός του, επίτηδες: το
 * βέλος θέλει συντεταγμένες **CSS px** (το πάχος του φωτοστέφανου είναι σχεδιαστικό μέγεθος),
 * ο σταυρός θέλει **pixel συσκευής** (η ευκρίνειά του είναι όλο του το νόημα). Ένας
 * επιβεβλημένος κοινός μετασχηματισμός θα ακύρωνε το ένα από τα δύο.
 */
function rasterizeCursorValue(
  requestedCssPx: number,
  fallback: string,
  draw: (ctx: CanvasRenderingContext2D, cssSize: number, devicePx: number, dpr: number) => void,
): string {
  // Χωρίς canvas (SSR / περιβάλλον test): ο δείκτης υποβαθμίζεται σε κάτι λογικό αντί να πετάξει.
  if (typeof document === 'undefined') return fallback;

  const dpr = getDevicePixelRatio();
  const maxCssForDevice = MAX_CURSOR_DEVICE_PX / dpr;
  const cssSize = Math.max(MIN_CURSOR_CSS_PX, Math.min(requestedCssPx, maxCssForDevice));
  const devicePx = Math.min(toDevicePixels(cssSize, dpr), MAX_CURSOR_DEVICE_PX);

  const canvas = document.createElement('canvas');
  canvas.width = devicePx;
  canvas.height = devicePx;
  const ctx = canvas.getContext('2d');
  if (!ctx) return fallback;

  draw(ctx, cssSize, devicePx, dpr);

  const dataUrl = canvas.toDataURL('image/png');
  // Το εμφανιζόμενο μέγεθος διαφέρει ανά διαδρομή εκπομπής, και το σημείο ενέργειας δηλώνεται σε
  // **εμφανιζόμενα** CSS px: με `image-set(... Nx)` το ράστερ δείχνεται στο `cssSize`, με σκέτο
  // `url()` δείχνεται 1:1 στο `devicePx`. Ίδια διόρθωση με το σταυρόνημα (ADR-549 Φ8, 2026-07-04)
  // — χωρίς αυτήν, σε dpr κάτω από 1 (σελίδα στο 80%) το σημείο ενέργειας ξεφεύγει από το κέντρο.
  const emittedCssSize = dpr > 1 ? cssSize : devicePx;
  const hot = Math.round(emittedCssSize / 2);

  return dpr > 1
    ? `image-set(url("${dataUrl}") ${dpr}x) ${hot} ${hot}, ${fallback}`
    : `url("${dataUrl}") ${hot} ${hot}, ${fallback}`;
}

/**
 * Χτίζει τιμή CSS `cursor`: PNG του παχιού βέλους με σημείο ενέργειας στο **κέντρο** του, συν
 * λέξη-κλειδί εφεδρείας. Εφαρμογή: `element.style.cursor = buildTableArrowCursorValue('down')`.
 */
export function buildTableArrowCursorValue(direction: TableArrowDirection): string {
  // `pointer` ως εφεδρεία: δηλώνει «πατιέται», που είναι ακριβώς το μήνυμα του βέλους. Ένα
  // `default` θα έλεγε το αντίθετο, και είναι η τιμή που πραγματικά εμφανίζεται αν το PNG
  // απορριφθεί — δηλαδή η εφεδρεία ΔΕΝ είναι διακοσμητική.
  return rasterizeCursorValue(ARROW_CSS_PX, 'pointer', (ctx, cssSize, devicePx) => {
    // Ζωγραφίζουμε σε συντεταγμένες CSS px πάνω σε φυσικό backing store → ευκρινές σε HiDPI.
    ctx.scale(devicePx / cssSize, devicePx / cssSize);
    traceArrow(ctx, cssSize, direction);
    // Φωτοστέφανο πρώτο και πλατύτερο· το γέμισμα από πάνω το κόβει στη μέση — δες την κεφαλίδα.
    ctx.lineJoin = 'round';
    ctx.lineCap = 'round';
    ctx.strokeStyle = '#ffffff';
    ctx.lineWidth = OUTLINE_CSS_PX;
    ctx.stroke();
    ctx.fillStyle = '#000000';
    ctx.fill();
  });
}

/**
 * 🔴 **ADR-739 §36.10 — Ο ΣΤΑΥΡΟΣ ΜΕ ΤΑ ΒΕΛΗ** της μετακίνησης περιοχής (✥).
 *
 * ## 🔴 Γιατί έπαψε να είναι η λέξη-κλειδί `move` — και τι κόστισε
 * Ο κανόνας του §31 είναι «**native όπου υπάρχει**», και το `range-move` ήταν το υποδειγματικό
 * του παράδειγμα: μηδέν ράστερ, μηδέν όριο 32 px, μηδέν ρίσκο σιωπηλής απόρριψης. Δύο λόγοι
 * τον υπερίσχυσαν, και ο πρώτος είναι **ρητή εντολή**:
 *
 * 1. **Ο ιδιοκτήτης ζήτησε ίσα μεγέθη** με τον σταυρό συμπλήρωσης (2026-08-06). Ο δείκτης του
 *    ΟΣ **δεν έχει μέγεθος που μπορούμε να ρυθμίσουμε** — είναι bitmap του λειτουργικού. Η
 *    ισαξία απαιτεί δικό μας ράστερ· δεν υπάρχει τρίτος δρόμος.
 * 2. **Το `move` δεν είναι το ίδιο σχήμα παντού** (μετρημένο, έρευνα 2026-08-06): Windows =
 *    σταυρός με τέσσερα βέλη (SIZEALL)· **macOS = ανοιχτή παλάμη** σε Firefox/WebKit. Δηλαδή η
 *    ίδια δήλωση CSS έλεγε **δύο διαφορετικά πράγματα**, και το ένα από τα δύο δεν είναι καν
 *    αυτό που ο ιδιοκτήτης ονομάζει «σταυρός με βέλη».
 *
 * 🔑 **Το τίμημα εδώ είναι το φθηνότερο ολόκληρης της οικογένειας**, και ο λόγος είναι η
 * **εφεδρεία**: `move`. Αν ο ΟΣ απορρίψει το PNG, εμφανίζεται **ακριβώς ό,τι έδειχνε μέχρι
 * σήμερα** — δηλαδή η χειρότερη περίπτωση είναι η σημερινή συμπεριφορά. Σύγκρινε με τον
 * σταυρό συμπλήρωσης, όπου η εφεδρεία (`crosshair`) είναι **οπτικά ταυτόσημη με το τίποτα**.
 *
 * ## 🔴 **ΑΣΠΡΟ ΣΩΜΑ, ΜΑΥΡΟ ΠΕΡΙΓΡΑΜΜΑ** — ανεστραμμένο ως προς το βέλος, και είναι εντολή
 * Η πρώτη γραφή αντέγραψε το βέλος επιλογής άξονα: **μαύρο** γέμισμα με λευκό φωτοστέφανο. Ο
 * ιδιοκτήτης το απέρριψε στην οθόνη: «*τώρα έγινε μικρό και **μαύρο** και δεν μου αρέσει· θέλω
 * **άσπρο** και σωστά τελειώματα*» (2026-08-06).
 *
 * Δεν είναι γούστο — είναι **αναγνωρισιμότητα**: ο δείκτης μετακίνησης **κάθε** λειτουργικού
 * (Windows SIZEALL, macOS, X11) είναι **λευκός με μαύρο περίγραμμα**, και αυτόν ακριβώς έβλεπε
 * ο χρήστης εδώ πριν το §36.10. Ένας μαύρος σταυρός στη θέση του διαβάζεται ως **άλλο**
 * εργαλείο. Το βέλος επιλογής άξονα μένει μαύρο επειδή αντιγράφει το **Excel**, όχι τον ΟΣ.
 *
 * ## 🔴 ΤΟ ΠΕΡΙΓΡΑΜΜΑ ΖΩΓΡΑΦΙΖΕΤΑΙ **ΠΡΟΣ ΤΑ ΜΕΣΑ** — εδώ ήταν οι «καθαρές γραμμές»
 * Ένα σκέτο `stroke()` κεντράρεται **πάνω** στη διαδρομή: η μισή του γραμμή πέφτει **έξω** από
 * το σχήμα, όπου δεν υπάρχει τίποτα να την κρατήσει — γι' αυτό χρειαζόταν περιθώριο `0,08`, και
 * γι' αυτό η αιχμή έβγαινε **θολή** (μισό pixel εξομάλυνσης πάνω σε διαφανές φόντο).
 *
 * Εδώ: γέμισμα λευκό, μετά **αποκοπή στο ίδιο το σχήμα** και περίγραμμα **διπλού** πάχους. Το
 * μισό που θα έβγαινε έξω κόβεται από το `clip()`, άρα μένει ακριβώς `OUTLINE_CSS_PX` **μέσα**
 * στο σχήμα, με **κοφτή** ακμή στο περίγραμμα. Δύο κέρδη με μία κίνηση: καθαρές γραμμές, και
 * αιχμές που φτάνουν στην **ακμή του κουτιού** (δες `MOVE_ARM` στο
 * `table-indicator-cursor-shapes`).
 *
 * ⚠️ `lineJoin: 'miter'`, **όχι** `'round'`: οι αιχμές του σταυρού είναι γωνίες ~68°, και το
 * `'round'` τις στρογγύλευε σε δείκτη 18 px — δηλαδή ακριβώς το «δεν έχει καθαρές γραμμές».
 */
export function buildTableMoveCursorValue(): string {
  return rasterizeCursorValue(GESTURE_CROSS_CSS_PX, 'move', (ctx, cssSize, devicePx) =>
    inkWhiteBodyBlackInnerOutline(ctx, cssSize, devicePx, traceMoveCross),
  );
}

/**
 * 🔴 **ΤΟ ΕΝΑ ΜΕΛΑΝΙ «λευκό σώμα, μαύρο περίγραμμα ΠΡΟΣ ΤΑ ΜΕΣΑ»** — δύο δείκτες, μία συνταγή.
 *
 * Εξήχθη όταν το CHECK 3.28 (jscpd, N.18) χαρακτήρισε **sibling clone** το σώμα του σταυρού
 * μετακίνησης και του πινέλου μορφοποίησης: 21 γραμμές / 70 tokens, ταυτόσημες εκτός από **ποια
 * διαδρομή χαράζεται**. Δεν ήταν σύμπτωση — είναι η ίδια σχεδιαστική απόφαση, εφαρμοσμένη δύο
 * φορές, και το δεύτερο αντίγραφο θα ήταν η πρώτη ευκαιρία να αποκλίνει το πάχος.
 *
 * ## 🔴 ΓΙΑΤΙ ΤΟ ΠΕΡΙΓΡΑΜΜΑ ΖΩΓΡΑΦΙΖΕΤΑΙ ΜΕ ΑΠΟΚΟΠΗ
 * Ένα σκέτο `stroke()` κεντράρεται **πάνω** στη διαδρομή: η μισή γραμμή πέφτει **έξω** από το
 * σχήμα, πάνω σε διαφανές φόντο, και βγαίνει θολή. Εδώ: γέμισμα λευκό, μετά `clip()` στο **ίδιο**
 * σχήμα και `stroke()` — το μισό που θα έβγαινε έξω κόβεται, άρα οι ακμές μένουν **κοφτές** και
 * οι αιχμές μπορούν να φτάσουν στην ακμή του κουτιού.
 *
 * ## 🔴 ΤΟ ΠΑΧΟΣ ΕΙΝΑΙ ΤΟ ΣΗΜΑΔΙ ΠΟΥ ΕΓΙΝΕ ΜΑΥΡΟ
 * Με `clip()`, το **ορατό** περίγραμμα είναι το **μισό** του `lineWidth` — άρα εδώ 1 CSS px προς
 * τα μέσα, ανά πλευρά. Έγραφε `OUTLINE_CSS_PX * 2` (= 4 ⇒ **2 px μέσα ανά πλευρά**) πάνω σε
 * στέλεχος πλάτους 2,7 px: τα δύο περιγράμματα **συναντιόντουσαν στο κέντρο** και το σχήμα
 * έβγαινε **ολόκληρο μαύρο**. Ο ιδιοκτήτης το είδε αμέσως («*είναι μαύρο το σημαδάκι, το θέλω
 * λευκό*», 06/08). Ο κανόνας: το περίγραμμα μένει **λεπτότερο από το μισό στέλεχος**.
 *
 * ⚠️ `lineJoin: 'miter'`, **όχι** `'round'`: οι αιχμές είναι γωνίες ~68°, και το `'round'` τις
 * στρογγύλευε σε δείκτη 18-24 px — δηλαδή ακριβώς το «δεν έχει καθαρές γραμμές».
 *
 * ⚠️ Το **βέλος** επιλογής άξονα **δεν** το χρησιμοποιεί, και δεν είναι παράλειψη: εκείνο είναι
 * **μαύρο με λευκό φωτοστέφανο έξω** (αντιγράφει το Excel), ενώ αυτά είναι **λευκά με μαύρο
 * περίγραμμα μέσα** (αντιγράφουν τον ΟΣ). Αντίθετα μελάνια, αντίθετη τεχνική.
 */
function inkWhiteBodyBlackInnerOutline(
  ctx: CanvasRenderingContext2D,
  cssSize: number,
  devicePx: number,
  trace: (target: CanvasRenderingContext2D, size: number) => void,
): void {
  ctx.scale(devicePx / cssSize, devicePx / cssSize);
  trace(ctx, cssSize);
  // Το σώμα πρώτο, λευκό.
  ctx.fillStyle = '#ffffff';
  ctx.fill();
  // Το περίγραμμα από πάνω, **αποκομμένο μέσα στο σχήμα**.
  ctx.save();
  ctx.clip();
  ctx.lineJoin = 'miter';
  ctx.lineCap = 'butt';
  ctx.strokeStyle = '#000000';
  ctx.lineWidth = OUTLINE_CSS_PX;
  ctx.stroke();
  ctx.restore();
}

/**
 * 🔴 **ADR-754 §14 — Ο ΛΕΠΤΟΣ ΜΑΥΡΟΣ ΣΤΑΥΡΟΣ ΤΗΣ ΛΑΒΗΣ ΣΥΜΠΛΗΡΩΣΗΣ** (Excel parity).
 *
 * ## 🔑 Γιατί ζωγραφίζεται σε **pixel συσκευής** και όχι σε CSS px — πιο ευκρινής κι από το Excel
 * Το βέλος από πάνω ζωγραφίζεται με `stroke()` σε CSS px, και του αρκεί: είναι παχύ σχήμα, όπου
 * μισό pixel εξομάλυνσης δεν φαίνεται. Ο σταυρός είναι το αντίθετο — **μία ράβδος πάχους ενός
 * pixel**. Μια γραμμή 1 CSS px κεντραρισμένη σε ακέραια συντεταγμένη απλώνεται σε **δύο**
 * pixel μισής έντασης: γκρίζος, θολός σταυρός, δηλαδή ακριβώς το αντίθετο του «λεπτός και
 * μαύρος».
 *
 * Γι' αυτό εδώ δεν υπάρχει `scale()` και δεν υπάρχει `stroke()`: οι ράβδοι είναι **γεμισμένα
 * ορθογώνια σε ακέραια pixel συσκευής**, με πάχος που μεγαλώνει κατά ένα ολόκληρο pixel ανά
 * βήμα dpr — ο ίδιος κανόνας που ακολουθούν οι δείκτες του ίδιου του λειτουργικού. Το
 * αποτέλεσμα είναι **απόλυτα ευκρινές σε κάθε dpr**, κάτι που ο δείκτης του Excel (σταθερό
 * bitmap που ο ΟΣ κλιμακώνει) δεν επιτυγχάνει σε μη ακέραιες κλιμακώσεις.
 *
 * ## Λευκό φωτοστέφανο, υποχρεωτικά
 * Ο ίδιος λόγος με το βέλος, αλλά **οξύτερος**: η λαβή είναι μπλε (`TABLE_FILL_HANDLE`) και
 * κάθεται πάνω στη μπλε γραμμή της επιλογής, μέσα σε σκούρο θέμα. Ένας σκέτος μαύρος σταυρός
 * εκεί πάνω θα ήταν αόρατος ακριβώς στο ένα pixel όπου πρέπει να φαίνεται.
 *
 * ## ⚠️ Η εφεδρεία είναι `crosshair`, και είναι δηλωμένος συμβιβασμός
 * Αν ο ΟΣ απορρίψει το PNG, εμφανίζεται η λέξη-κλειδί — και η **σημασιολογικά** σωστή είναι το
 * `crosshair` (έτσι το λύνουν και τα φύλλα υπολογισμού του ιστού). Στον Νέστορα όμως εκείνη
 * είναι οπτικά ταυτόσημη με το σταυρόνημα CAD, άρα η εφεδρεία **δεν διακρίνεται**. Δεν υπάρχει
 * καλύτερη: το `cell` είναι ο παχύς σταυρός της **επιλογής** και θα έλεγε λάθος πράγμα. Το ότι
 * το ράστερ έφτασε στην οθόνη το απαντά το όργανο του §31.11 (`fingerprintCursorValue`).
 */
export function buildTableFillCursorValue(): string {
  return rasterizeCursorValue(GESTURE_CROSS_CSS_PX, 'crosshair', (ctx, _cssSize, devicePx, dpr) => {
    // Πάχος **σε pixel συσκευής**: 1 στο 100%, 2 στο 200%, 3 στο 300%. Ποτέ κλάσμα — δες την
    // κεφαλίδα για το γιατί το κλάσμα είναι όλο το πρόβλημα.
    const bar = Math.max(1, Math.round(dpr));
    const halo = Math.max(1, Math.round(dpr));
    // Η αρχή της ράβδου, καρφωμένη στο πλέγμα της συσκευής. Το κέντρο της πέφτει στο κέντρο της
    // εικόνας — που είναι, εξ ορισμού του ρασταροποιητή, το **σημείο ενέργειας**.
    const start = Math.round((devicePx - bar) / 2);
    const thick = bar + 2 * halo;

    // Φωτοστέφανο πρώτο, από άκρη σε άκρη: έτσι σκεπάζει και τα **άκρα** των ράβδων, που αλλιώς
    // θα ακουμπούσαν γυμνά πάνω στο μπλε.
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(0, start - halo, devicePx, thick);
    ctx.fillRect(start - halo, 0, thick, devicePx);
    // Οι μαύρες ράβδοι από πάνω, κομμένες κατά `halo` σε κάθε άκρο ώστε το φωτοστέφανο να τις
    // κλείνει και στις τέσσερις αιχμές.
    ctx.fillStyle = '#000000';
    ctx.fillRect(halo, start, devicePx - 2 * halo, bar);
    ctx.fillRect(start, halo, bar, devicePx - 2 * halo);
  });
}

/**
 * 🔴 **ADR-768 Βήμα 5 — ΤΟ ΠΙΝΕΛΟ ΜΟΡΦΟΠΟΙΗΣΗΣ**: παχύς σταυρός **με πινέλο** (Excel parity).
 *
 * Ο **τέταρτος** ένοικος, και μπαίνει με τον ίδιο έλεγχο που πέρασαν οι τρεις πρώτοι: υπάρχει
 * λέξη-κλειδί που λέει αυτό που πρέπει; **Όχι** — και οι τρεις υποψήφιες είναι **πιασμένες**:
 * `copy` από το `range-copy` (αντιγραφή *περιεχομένου*), `cell` από το `cell-select` (η
 * κατάσταση **χωρίς** πινέλο), `crosshair` από το σταυρόνημα CAD. Ένας δείκτης οπτικά ταυτόσημος
 * με την κατάσταση που αντικαθιστά δεν ανακοινώνει τίποτα.
 *
 * ## Ζητούμενο μέγεθος: **δικός του αριθμός**, όχι ο {@link GESTURE_CROSS_CSS_PX}
 * Εκείνος δηλώνει ρητά ότι είναι «*η ΜΙΑ πλευρά των **δύο** δεικτών χειρονομίας*» — του σταυρού
 * συμπλήρωσης και του σταυρού μετακίνησης, που ο ιδιοκτήτης ζήτησε **ισάξιους** επειδή
 * συναντιούνται στην **ίδια γωνία**. Το πινέλο δεν συναντά κανέναν από τους δύο (όσο είναι
 * οπλισμένο, εκείνοι δεν εμφανίζονται) και κουβαλά **δύο** σχήματα αντί για ένα, άρα χρειάζεται
 * περισσότερο χώρο. Να το δέσουμε στον ίδιο αριθμό θα σήμαινε ότι μια μελλοντική ρύθμιση της
 * «ισαξίας» θα συρρίκνωνε σιωπηλά το πινέλο.
 *
 * ## 🔴 Η ΕΦΕΔΡΕΙΑ ΕΙΝΑΙ `copy`, ΚΑΙ **ΔΕΝ** ΣΥΓΚΡΟΥΕΤΑΙ ΜΕ ΤΟ `range-copy`
 * Είναι η μόνη οικογένεια όπου η εφεδρεία είναι **και** σημασιολογικά σωστή («αντιγράφεις») **και**
 * οπτικά **διακριτή** από την κατάσταση χωρίς εργαλείο — δηλαδή, αν το PNG απορριφθεί σιωπηλά, ο
 * χρήστης εξακολουθεί να βλέπει ότι κάτι άλλαξε. Σύγκρινε με τον σταυρό συμπλήρωσης, όπου η
 * εφεδρεία (`crosshair`) είναι δηλωμένος συμβιβασμός γιατί ισούται με «τίποτα».
 *
 * Η φαινομενική σύγκρουση με το `range-copy` δεν υπάρχει: όσο το πινέλο είναι **οπλισμένο**, ο
 * ρόλος `range-copy` **δεν επιστρέφεται ποτέ** — η {@link tableFormatPaintRoleOf} τον μεταφράζει
 * σε `format-paint`. Οι δύο δεν συνυπάρχουν εξ ορισμού.
 *
 * ## Λευκό σώμα, μαύρο περίγραμμα **προς τα μέσα** — το **ίδιο** μελάνι με τον σταυρό μετακίνησης
 * Η συνταγή ζει σε **ένα** σημείο ({@link inkWhiteBodyBlackInnerOutline}) μετά το CHECK 3.28: τα
 * δύο σώματα ήταν ταυτόσημα εκτός από τη διαδρομή που χαράζουν, και το jscpd τα χαρακτήρισε
 * sibling clones **μέσα στο ίδιο commit**. Και ο παχύς **λευκός** σταυρός είναι κυριολεκτικά
 * αυτό που δείχνει το Excel.
 */
const PAINT_CURSOR_CSS_PX = 24;

/** Χτίζει τιμή CSS `cursor` για το οπλισμένο πινέλο μορφοποίησης. Δες την κεφαλίδα από πάνω. */
export function buildTableFormatPaintCursorValue(): string {
  return rasterizeCursorValue(PAINT_CURSOR_CSS_PX, 'copy', (ctx, cssSize, devicePx) =>
    inkWhiteBodyBlackInnerOutline(ctx, cssSize, devicePx, tracePaintGlyph),
  );
}
