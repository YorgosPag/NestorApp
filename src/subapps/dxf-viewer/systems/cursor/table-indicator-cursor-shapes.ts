/**
 * ADR-739 §31 / §36.10 · ADR-754 §14 · ADR-768 Βήμα 5 — **ΤΑ ΣΧΗΜΑΤΑ ΤΩΝ ΖΩΓΡΑΦΙΣΜΕΝΩΝ ΔΕΙΚΤΩΝ**
 * του πίνακα: το βέλος επιλογής άξονα (⬇ ➡), ο σταυρός μετακίνησης (✥) και το πινέλο (🖌).
 *
 * ## Γιατί ξεχωριστό αρχείο
 * Εξαγωγή από το `table-indicator-cursor-image` τη στιγμή που ο **τέταρτος** ένοικος (το πινέλο
 * μορφοποίησης, ADR-768) το πέρασε στις **503** γραμμές (N.7.1). Εξαγωγή, όχι κόψιμο: καμία από
 * τις συναρτήσεις εδώ δεν χρειάζεται τίποτα από εκεί.
 *
 * 🔑 **Η τομή είναι σημασιολογική, όχι μετρική** — και είναι η τομή που ήδη περιγράφει η κεφαλίδα
 * του `rasterizeCursorValue`: *«ό,τι μένει στον καλούντα είναι **μόνο το μελάνι**»*. Εδώ ζει το
 * **σχήμα** (αδιάστατες συντεταγμένες, χάραξη διαδρομής)· εκεί ζει το **τίμημα της συσκευής**
 * (dpr, φράγμα 32 device-px, `toDataURL`, σημείο ενέργειας, `image-set`). Το πρώτο δεν ξέρει τι
 * είναι dpr και δεν πρέπει να μάθει· το δεύτερο δεν ξέρει πώς μοιάζει ένα βέλος.
 *
 * ⚠️ **Ούτε ένα χρώμα εδώ.** Το ποιο σχήμα είναι λευκό-με-μαύρο-περίγραμμα και ποιο το αντίστροφο
 * είναι **απόφαση** (ο σταυρός μετακίνησης αντιγράφει τον ΟΣ, το βέλος αντιγράφει το Excel) και
 * ζει δίπλα στην αιτιολόγησή της, στους δημόσιους builders.
 *
 * @module subapps/dxf-viewer/systems/cursor/table-indicator-cursor-shapes
 * @see systems/cursor/table-indicator-cursor-image.ts — η ρασταροποίηση και οι τρεις παγίδες της
 */

/** Ο άξονας στον οποίο δείχνει το βέλος. Η γεωμετρία είναι **μία**· αλλάζει μόνο η προβολή. */
export type TableArrowDirection = 'down' | 'right';

/**
 * Το περίγραμμα του βέλους σε **κανονικοποιημένες** συντεταγμένες `[0..1]`, για κατεύθυνση
 * «κάτω». Κρατιέται αδιάστατο ώστε το ίδιο σχήμα να δουλεύει σε κάθε μέγεθος και dpr χωρίς
 * δεύτερο σύνολο αριθμών — και ώστε η στροφή για το «δεξιά» να είναι **αντιμετάθεση**, όχι
 * δεύτερο σχήμα που θα μπορούσε να αποκλίνει.
 *
 * Αναλογίες Excel: κοντό φαρδύ στέλεχος, κεφάλι σαφώς πλατύτερο, αιχμή που δεν φτάνει στην
 * άκρη (αφήνει χώρο στο φωτοστέφανο να μη κοπεί από το πλαίσιο της εικόνας).
 */
const ARROW_OUTLINE: readonly (readonly [number, number])[] = [
  [0.34, 0.14],
  [0.66, 0.14],
  [0.66, 0.55],
  [0.88, 0.55],
  [0.50, 0.90],
  [0.12, 0.55],
  [0.34, 0.55],
];

/**
 * 🔴 **ADR-739 §36.10 — ΤΟ ΠΡΟΦΙΛ ΕΝΟΣ ΒΡΑΧΙΟΝΑ** του σταυρού μετακίνησης, σε συντεταγμένες
 * **κεντραρισμένες** στο `[-1, 1]`, για τον βραχίονα που δείχνει **πάνω**.
 *
 * Γράφεται **ένας** βραχίονας και περιστρέφεται τέσσερις φορές — ίδια αρχή με το βέλος από
 * πάνω («μία γεωμετρία, δύο προβολές»), εδώ σε τέσσερις. Ένας πίνακας 24 σημείων γραμμένος με
 * το χέρι θα ήταν η πρώτη ευκαιρία να βγει ένας βραχίονας μισό pixel πιο κοντός από τους
 * άλλους — ασυμμετρία που το μάτι πιάνει αμέσως σε δείκτη 18 px, και που **κανένα** test σε
 * jsdom δεν θα έβλεπε.
 *
 * ## 🔴 Η ΑΙΧΜΗ ΦΤΑΝΕΙ ΣΤΟ **1,00** — δηλαδή στην ακμή του κουτιού
 * Ο ιδιοκτήτης το μέτρησε στην οθόνη (2026-08-06): «*πρέπει να μεγαλώσεις ακόμη λίγο το σημάδι
 * της μετακίνησης, να είναι **ίδιο με το fill handle***». Τα δύο κουτιά ήταν **ήδη ίσα**
 * (`GESTURE_CROSS_CSS_PX`) — αυτό που διέφερε ήταν το **μελάνι**: ο σταυρός συμπλήρωσης
 * απλώνει τις ράβδους του **από άκρη σε άκρη**, ενώ οι βραχίονες εδώ σταματούσαν στο `0,92` για
 * να χωρέσει το περίγραμμα. Ίσα κουτιά, **άνισα σχήματα** — και το μάτι βλέπει το σχήμα.
 *
 * Η θεραπεία **δεν** ήταν να μεγαλώσει το κουτί (θα μεγάλωνε και ο σταυρός, ξαναγεννώντας τη
 * διαφορά) αλλά να πάψει το περίγραμμα να χρειάζεται περιθώριο: ζωγραφίζεται πλέον **προς τα
 * μέσα**, με αποκοπή στο ίδιο το σχήμα (δες `buildTableMoveCursorValue`). Έτσι η αιχμή
 * ακουμπά την ακμή, όπως ακριβώς οι ράβδοι του σταυρού.
 *
 * ## Αναλογίες: **λεπτό στέλεχος, ανέπαφα βέλη** — δύο ανεξάρτητες εντολές οθόνης
 * Στέλεχος `0,19` του μισού, κεφάλι `0,52`, βάση κεφαλιού `0,40`, αιχμή `1,00`.
 *
 * Το στέλεχος πάχυνε πρώτα (`0,15 → 0,24`) **αναγκαστικά**, για να χωρέσει λευκό πυρήνας δίπλα
 * στο περίγραμμα (§36.10.5), και μετά **λέπτυνε** (`0,24 → 0,19`) με ρητή εντολή: «*μπορείς να
 * κάνεις λίγο πιο λεπτές τις γραμμές του σταυρού μετακίνησης; **όχι τα βέλη***» (06/08). Τα δύο
 * νούμερα του **κεφαλιού** έμειναν άθικτα — αυτό ακριβώς ζήτησε ο διαχωρισμός.
 *
 * ⚠️ Το `0,19` είναι **το λεπτότερο που αντέχει ο φύλακας** του λευκού πυρήνα: με περίγραμμα
 * 1 px ανά πλευρά, μένει λευκό το ~52% του στελέχους. Λεπτότερο στέλεχος απαιτεί λεπτότερο
 * περίγραμμα, δηλαδή υπο-pixel γραμμή — που είναι ακριβώς το «*δεν έχει καθαρές γραμμές*» που
 * αυτή η φάση ήρθε να σβήσει.
 */
const MOVE_ARM: readonly (readonly [number, number])[] = [
  [0.19, -0.19],
  [0.19, -0.40],
  [0.52, -0.40],
  [0.00, -1.00],
  [-0.52, -0.40],
  [-0.19, -0.40],
  [-0.19, -0.19],
];

/**
 * 🔴 **ADR-768 Βήμα 5 — ΤΟ ΓΛΥΦΟ ΤΟΥ ΠΙΝΕΛΟΥ**: τρία πολύγωνα σε κανονικοποιημένες `[0..1]` —
 * ο σταυρός, το στειλιάρι, η κεφαλή.
 *
 * 🔴 **Ο σταυρός είναι κεντραρισμένος στο `0,5` και το πινέλο ζει ΕΞΩ από τους βραχίονές του.**
 * Δεν είναι αισθητική: ο ρασταροποιητής καρφώνει το **σημείο ενέργειας στο κέντρο της εικόνας**,
 * άρα ο σταυρός **οφείλει** να είναι κεντραρισμένος — αλλιώς ο χρήστης θα στόχευε με ένα σημείο
 * και θα έβαφε άλλο κελί. Το πινέλο μετακομίζει στην κάτω-δεξιά γωνία, τη μόνη που δεν
 * διεκδικεί κανένας βραχίονας.
 *
 * ⚠️ Η κεφαλή καταλήγει σε **αιχμή** και όχι σε ορθογώνιο: μόνο έτσι διαβάζεται ως πινέλο και
 * όχι ως δεύτερη ράβδος, στα ~10 pixel που της αναλογούν σε δείκτη 24 CSS px.
 */
const PAINT_GLYPH: readonly (readonly (readonly [number, number])[])[] = [
  // Ο σταυρός: άκρα στο ±0,40 από το κέντρο, μισό πάχος στελέχους 0,105.
  [
    [0.395, 0.10], [0.605, 0.10], [0.605, 0.395], [0.90, 0.395],
    [0.90, 0.605], [0.605, 0.605], [0.605, 0.90], [0.395, 0.90],
    [0.395, 0.605], [0.10, 0.605], [0.10, 0.395], [0.395, 0.395],
  ],
  // Το στειλιάρι: λεπτή λοξή ράβδος από την πάνω-δεξιά γωνία προς τα κάτω-αριστερά.
  [[0.94, 0.60], [1.00, 0.66], [0.86, 0.80], [0.80, 0.74]],
  // Η κεφαλή: πλατύτερη, με αιχμή προς τα κάτω-αριστερά.
  [[0.86, 0.80], [0.80, 0.74], [0.68, 0.88], [0.70, 1.00], [0.82, 0.98]],
];

/**
 * Στροφή κατά 90° που στέλνει το **τέλος** ενός βραχίονα στην **αρχή** του επόμενου.
 *
 * Δεν είναι αυθαίρετη επιλογή πρόσημου: με `(x, y) → (y, −x)` ισχύει `R(αρχή) = τέλος`, δηλαδή
 * οι τέσσερις βραχίονες **κουμπώνουν** χωρίς κενό και χωρίς διπλή γραμμή. Το αντίθετο πρόσημο
 * θα έδινε πολύγωνο που διασταυρώνεται με τον εαυτό του — και το `fill()` θα το ζωγράφιζε
 * **χωρίς να παραπονεθεί**, απλώς λάθος.
 */
function rotateQuarter([x, y]: readonly [number, number]): readonly [number, number] {
  return [y, -x];
}

/**
 * Χαράζει τον **σταυρό με τα βέλη** σε πλέγμα `size`×`size`: τέσσερις φορές ο ίδιος βραχίονας.
 *
 * Το πρώτο σημείο κάθε επόμενου βραχίονα παραλείπεται — ταυτίζεται με το τελευταίο του
 * προηγούμενου (δες {@link rotateQuarter}), και μια διπλή `lineTo` στο ίδιο σημείο θα άφηνε
 * ορατό κόμπο στο `lineJoin: 'round'` του φωτοστέφανου.
 */
export function traceMoveCross(ctx: CanvasRenderingContext2D, size: number): void {
  const half = size / 2;
  ctx.beginPath();
  let arm = MOVE_ARM;
  for (let quarter = 0; quarter < 4; quarter++) {
    arm.forEach((point, index) => {
      if (quarter > 0 && index === 0) return;
      const x = half + point[0] * half;
      const y = half + point[1] * half;
      if (quarter === 0 && index === 0) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    });
    arm = arm.map(rotateQuarter);
  }
  ctx.closePath();
}

/** Χαράζει το περίγραμμα του βέλους σε πλέγμα `size`×`size`, στον ζητούμενο άξονα. */
export function traceArrow(
  ctx: CanvasRenderingContext2D,
  size: number,
  direction: TableArrowDirection,
): void {
  ctx.beginPath();
  ARROW_OUTLINE.forEach(([nx, ny], index) => {
    // «Δεξιά» = το ίδιο σχήμα με εναλλαγμένους άξονες (ανάκλαση στη διαγώνιο). Μία γεωμετρία,
    // δύο προβολές — ένας δεύτερος πίνακας σημείων θα ήταν sibling clone (N.18).
    const x = (direction === 'down' ? nx : ny) * size;
    const y = (direction === 'down' ? ny : nx) * size;
    if (index === 0) ctx.moveTo(x, y);
    else ctx.lineTo(x, y);
  });
  ctx.closePath();
}

/** Χαράζει τα τρία πολύγωνα του γλυφού πινέλου σε πλέγμα `size`×`size`, ως **μία** διαδρομή. */
export function tracePaintGlyph(ctx: CanvasRenderingContext2D, size: number): void {
  ctx.beginPath();
  for (const polygon of PAINT_GLYPH) {
    polygon.forEach(([nx, ny], index) => {
      const x = nx * size;
      const y = ny * size;
      if (index === 0) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    });
    ctx.closePath();
  }
}
