/**
 * 🔴 ADR-751 Φ8.γ — **«αυτός ο πίνακας έχει διευθύνσεις»**, στην ανακοίνωση εστίασης.
 *
 * ## Γιατί ΕΔΩ και όχι σε Mirror DOM (η έρευνα ανέτρεψε τον σχεδιασμό)
 * Ο πρώτος σχεδιασμός ήταν το μοτίβο **Figma**: κρυφός κόμβος DOM ανά σύνδεσμο, εστιάσιμος
 * με `Tab` — ακριβώς αυτό που ήδη κάνει το `bim-3d/accessibility/entity-dom-proxy-renderer`
 * για τις τρισδιάστατες οντότητες. **Δεν μπορεί να δουλέψει στη δισδιάστατη όψη**, και ο
 * λόγος μετρήθηκε στον κώδικα:
 *
 * Το `use2DKeyboardFocus` κάνει **άνευ όρων `preventDefault()`** σε κάθε `Tab` όσο η όψη
 * είναι 2D, γιατί το `Tab` του **ανήκει**: κυκλώνει τις οντότητες του καμβά. Το
 * `shouldGlobalShortcutYield` δεν παραιτείται για `<button>` (το `Tab` δεν είναι πλοηγικό
 * πλήκτρο και ένα κουμπί δεν καταναλώνει χαρακτήρες), άρα ο φύλακας δεν σώζει τίποτα. Ένα
 * κρυφό δοχείο proxy θα ήταν **άφταστο** — χαρακτηριστικό μέσα σε δοχείο που δεν προσαρτάται
 * ποτέ, δηλαδή νεκρός κώδικας με εμφάνιση προσβασιμότητας.
 *
 * Το ίδιο το Figma το λέει καθαρά: *«το `Tab` αλλάζει τον **επιλεγμένο κόμβο** χωρίς να
 * αλλάξει η εστίαση συστήματος»* — δηλαδή η εφαρμογή **κατέχει** το `Tab` και ο καθρέφτης
 * **ακολουθεί**. Εδώ ο ιδιοκτήτης υπάρχει ήδη και είναι οι **οντότητες**. Άρα ο σωστός
 * καθρέφτης δεν είναι δεύτερη σειρά εστίασης, αλλά **πλουσιότερη ανακοίνωση της υπάρχουσας**.
 *
 * ## Τι μένει προσβάσιμο, και από πού
 * Η **αναγγελία** («υπάρχουν 12 διευθύνσεις εδώ») γίνεται στην υπάρχουσα `aria-live` περιοχή
 * του `Focus2DOverlay`. Η **πρόσβαση** και η **ενεργοποίηση** γίνονται από το `Ctrl+Shift+K`,
 * που ανοίγει **πραγματικό** διάλογο DOM με `listbox`, αναζήτηση και κανονική εστίαση — όχι
 * καθρέφτη. Ένας χρήστης αναγνώστη οθόνης ακούει ότι υπάρχουν, μαθαίνει πώς, και τους
 * φτάνει με αληθινό DOM.
 *
 * @module subapps/dxf-viewer/accessibility/focus-2d-link-note
 * @see hooks/state/use2DKeyboardFocus.ts — ο ιδιοκτήτης του `Tab` στη 2D όψη
 * @see ui/components/TableLinkPicker.tsx — όπου γίνεται η πραγματική πρόσβαση
 */

import { collectTableCellLinks } from '../bim/table/table-cell-link-index';
import { isTableEntity } from '../types/table-entity';
import type { Entity } from '../types/entities';

/**
 * Πόσες διευθύνσεις έχει η εστιασμένη οντότητα· `0` όταν δεν είναι πίνακας ή δεν έχει.
 *
 * Καθαρή συνάρτηση με ρητό `0` αντί για `null`: ο καλών ρωτά «να το πω;» με μία σύγκριση,
 * και δεν χρειάζεται να ξέρει αν το μηδέν σημαίνει «όχι πίνακας» ή «πίνακας χωρίς
 * διευθύνσεις» — για την ανακοίνωση οι δύο περιπτώσεις είναι **η ίδια σιωπή**.
 *
 * ⚠️ Καλείται **μόνο** σε αλλαγή εστίασης (πάτημα `Tab`), όχι ανά καρέ. Το κόστος είναι η
 * διάταξη του πίνακα, που είναι ήδη memoized ανά μοντέλο (`RESOLVED_MODEL_CACHE`) — αλλά η
 * συχνότητα είναι που το κάνει ασφαλές, και γι' αυτό γράφεται εδώ ρητά: μια μελλοντική
 * κλήση από ζωγράφο θα ήταν το λάθος του ADR-735 ξανά.
 */
export function focusedEntityLinkCount(
  entities: readonly Entity[] | undefined,
  focusedId: string | null,
): number {
  if (!entities || !focusedId) return 0;
  const entity = entities.find((e) => e.id === focusedId);
  if (!entity || !isTableEntity(entity)) return 0;
  return collectTableCellLinks(entity).length;
}
