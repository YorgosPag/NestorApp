'use client';

/**
 * 🔴 ADR-739 §48 — **Ο ΠΑΛΜΟΣ ΤΩΝ «ΜΥΡΜΗΓΚΙΩΝ» — ΚΑΙ ΓΙΑΤΙ ΕΙΝΑΙ ΤΑΥΤΟΧΡΟΝΑ Ο ΦΡΟΥΡΟΣ ΤΟΥΣ.**
 *
 * Ο καμβάς ξαναβάφει **μόνο** όταν του το ζητήσει κάποιος (ADR-040 / ADR-119). Ένα κινούμενο
 * περίγραμμα είναι το πρώτο στοιχείο του πίνακα που χρειάζεται καρέ **χωρίς** να έχει συμβεί
 * τίποτα — ούτε πλήκτρο, ούτε ποντίκι. Άρα χρειάζεται δικό του ρολόι.
 *
 * ## 🔑 Η μία σχεδιαστική απόφαση: το ρολόι ΕΙΝΑΙ ο φρουρός ζωής
 * Το marquee πρέπει να σβήνει σε **Esc**, σε **έξοδο** από τη λειτουργία και σε μετάβαση σε
 * **άλλον** πίνακα. Τρεις ακυρωτές σε τρία σημεία θα ήταν τρεις ευκαιρίες να ξεχαστεί ο ένας
 * — και ο ξεχασμένος δεν φαίνεται ποτέ σε test κατάστασης, μόνο ως μυρμήγκια που επιβιώνουν
 * σε πίνακα που δεν επεξεργάζεται πια κανείς.
 *
 * Εδώ υπάρχει ήδη κάτι που τρέχει περιοδικά. Του δίνεται **μία** ερώτηση ({@link
 * MarchingAntsPulseParams.shouldContinue}) και σταματά μόνο του όταν η απάντηση γίνει `false`.
 * Καμία εγγραφή δεν χρειάζεται να θυμάται τίποτα, και το «παλμός χωρίς marquee» γίνεται
 * **μη εκφράσιμο** αντί για κάτι που φυλάει η σύμβαση.
 *
 * ## Γιατί ~12 Hz και όχι 60
 * Το ζητούμενο είναι **κίνηση**, όχι ρευστότητα: με 20 px/s το βήμα των 80 ms είναι ~1,7 px,
 * δηλαδή ήδη κάτω από το κατώφλι όπου το μάτι βλέπει «σκαλοπάτια». Στα 60 Hz θα ζητούσαμε
 * **πενταπλάσια** καρέ για ταυτόσημη εικόνα — και ο ADR-040 δεν απαγορεύει τα καρέ, απαγορεύει
 * το να ζητούνται χωρίς λόγο.
 *
 * ⚠️ **Το `markSystemsDirty` δεν ακυρώνει το bitmap cache**: το marquee ζωγραφίζεται στο
 * overlay pass και **δεν** μετέχει στο κλειδί του cache (κανόνας #3 του ADR-040), οπότε κάθε
 * τικ κοστίζει blit + overlay, όχι ανακατασκευή N οντοτήτων. Αν κάποτε μπει στο normal-state
 * pass, αυτός ο παλμός γίνεται το χειρότερο πράγμα του viewer — γι' αυτό γράφεται εδώ.
 *
 * ## Γιατί δέχεται συναρτήσεις αντί να διαβάζει stores
 * Ώστε να μην ξέρει **τίποτα** για το marquee: ελέγχεται ντετερμινιστικά με ψεύτικο ρολόι,
 * και ο κύκλος εξαρτήσεων `store → παλμός → store` δεν υπάρχει καν ως δυνατότητα.
 *
 * @module subapps/dxf-viewer/state/table-copy-marquee-pulse
 * @see state/table-copy-marquee-store.ts — ο ένας οδηγός του
 * @see bim/table/table-marching-ants.ts — πού βρίσκεται το μοτίβο τη στιγμή `t`
 */

import { DXF_TIMING } from '../config/dxf-timing';

/**
 * Πόσο συχνά ζητείται καρέ. Δες την κεφαλίδα για το γιατί όχι 60 Hz.
 *
 * ⚠️ Η **τιμή** ζει στο `DXF_TIMING.animation` (ADR-516) — εδώ μένει μόνο το όνομα που
 * χρησιμοποιεί ο παλμός. Γραμμένη ως ωμός αριθμός θα ήταν το ~50ό αντίγραφο της ίδιας
 * κατηγορίας απόφασης· το CHECK 3.27 την πιάνει ακριβώς γι' αυτό.
 */
export const MARCHING_ANTS_TICK_MS = DXF_TIMING.animation.MARCHING_ANTS_TICK;

export interface MarchingAntsPulseParams {
  /** Ρωτιέται σε **κάθε** τικ· `false` ⇒ ο παλμός σταματά και καλείται το {@link onExpire}. */
  readonly shouldContinue: () => boolean;
  /** Ζήτα ένα καρέ. */
  readonly onTick: () => void;
  /** Ο φρουρός απάντησε «όχι»: σβήσε την κατάσταση που δεν έχει πια νόημα. */
  readonly onExpire: () => void;
}

/**
 * Ξεκινά τον παλμό και επιστρέφει την **ρητή** διακοπή του (για αντικατάσταση ή unmount).
 *
 * Ιδεμποτής ως προς τη διακοπή: δεύτερη κλήση δεν κάνει τίποτα. Δεν καλεί το `onExpire` —
 * εκείνο σημαίνει «έληξε από μόνο του», και μια ρητή διακοπή είναι το αντίθετο (ο καλών ξέρει
 * ήδη τι κάνει με την κατάσταση· ένα `onExpire` εκεί θα έσβηνε το **νέο** marquee που μόλις
 * αντικατέστησε το παλιό).
 */
export function startMarchingAntsPulse(params: MarchingAntsPulseParams): () => void {
  const { shouldContinue, onTick, onExpire } = params;
  let rafId: number | null = null;
  let lastTickMs = 0;
  let stopped = false;

  const stop = (): void => {
    if (stopped) return;
    stopped = true;
    if (rafId !== null) cancelAnimationFrame(rafId);
    rafId = null;
  };

  const frame = (timestamp: number): void => {
    if (stopped) return;
    if (!shouldContinue()) {
      stop();
      onExpire();
      return;
    }
    // Ο φρουρός ρωτιέται σε **κάθε** RAF, το καρέ ζητείται με ρυθμό. Δεν είναι ασυνέπεια: η
    // ερώτηση είναι μια σύγκριση δείκτη (μηδενικό κόστος) και θέλουμε το σβήσιμο να μοιάζει
    // ακαριαίο· η **επαναβαφή** είναι εκείνη που κοστίζει και γι' αυτό μόνο εκείνη ρυθμίζεται.
    if (timestamp - lastTickMs >= MARCHING_ANTS_TICK_MS) {
      lastTickMs = timestamp;
      onTick();
    }
    rafId = requestAnimationFrame(frame);
  };

  rafId = requestAnimationFrame(frame);
  return stop;
}
