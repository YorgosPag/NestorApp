'use client';

/**
 * 🔴 ADR-739 §69 — **ΤΙ ΣΕΡΝΕΤΑΙ ΑΥΤΗ ΤΗ ΣΤΙΓΜΗ**, και τίποτα άλλο.
 *
 * Το πλαίσιο ονόματος του Excel αλλάζει νόημα όσο κρατάς πατημένο: παύει να λέει «πού
 * είμαι» (`A1`) και λέει «**πόσο πιάνω**» (`2R x 2C`). Μόλις αφήσεις, επιστρέφει η
 * διεύθυνση. Αυτό το store είναι η **μία** πηγή για το «κρατάει κάποιος πατημένο, και ως
 * πού έχει φτάσει;» — η ερώτηση που κανείς δεν δημοσίευε.
 *
 * ## 🔴 ΓΙΑΤΙ ΔΕΝ ΚΡΑΤΑ ΜΕΓΕΘΟΣ
 * Ο πειρασμός είναι να κρατά `{ rows, cols }`, αφού αυτό δείχνει η οθόνη. Θα ήταν **δεύτερη
 * αλήθεια**: το μέγεθος μιας επιλογής είναι παράγωγο του **μοντέλου** (η περιοχή κουμπώνει
 * ώστε να περικλείει ολόκληρες τις συγχωνεύσεις — δες `resolveTableSelectionBounds`), και
 * ένας αποθηκευμένος αριθμός θα πάλιωνε στην πρώτη συγχώνευση/αποσυγχώνευση **κάτω από
 * ακίνητο χέρι**. Ίδια ακριβώς αρχή με τον δρομέα, που δεν κρατά το κείμενο του κελιού και
 * με το `TableCellCursorState.selection`, που κρατά **ταυτότητες** και όχι έτοιμο ορθογώνιο.
 *
 * Άρα εδώ ζει η **πρόθεση** (δύο γωνίες + είδος), και ο αναγνώστης — που έχει το μοντέλο —
 * τη μεταφράζει με το ΕΝΑ {@link tableSelectionSize}.
 *
 * ## Γιατί ΞΕΧΩΡΙΣΤΟ store και όχι πεδίο του δρομέα
 * Δύο λόγοι, και ο δεύτερος είναι ο ουσιώδης:
 *  1. **Ο κύκλος ζωής διαφέρει.** Η επιλογή του δρομέα επιβιώνει της χειρονομίας· αυτό εδώ
 *     ζει **ακριβώς** όσο το κουμπί είναι κάτω. Ένα πεδίο μέσα στον δρομέα θα υποχρέωνε
 *     κάθε έναν από τους έξι γραφείς του να θυμάται να το σβήνει.
 *  2. **Δεν είναι πάντα η επιλογή του δρομέα.** Από τις τέσσερις χειρονομίες που περνούν
 *     από τον έναν βρόχο σύρσης, **δύο δεν γράφουν επιλογή καθόλου**: η υπόδειξη μέσα σε
 *     τύπο γράφει χαρακτήρες (`=SUM(A1:B5`) και η λαβή συμπλήρωσης γράφει υπόσχεση
 *     γεμίσματος. Και οι δύο όμως **ανακοινώνουν μέγεθος**, γιατί ο χρήστης σέρνει και
 *     ρωτά «πόσο πιάνω;». Ένα πεδίο του δρομέα θα ήταν δομικά ανίκανο να τις εξυπηρετήσει.
 *
 * ## Ο γραφέας είναι ΕΝΑΣ
 * Μόνο το `table-cell-drag-session.ts`. Δεν εξάγεται setter για κανέναν άλλο: η ερώτηση
 * «σέρνεται κάτι;» έχει ήδη **έναν** ιδιοκτήτη, και ένας δεύτερος γραφέας θα σήμαινε
 * ένδειξη που μένει αναμμένη μετά το `mouseup` — δηλαδή πλαίσιο ονόματος που ψεύδεται.
 *
 * @module subapps/dxf-viewer/state/table-drag-span-store
 * @see ui/table-cell-editor/table-cell-drag-session.ts — ο ΕΝΑΣ γραφέας
 * @see ui/table-cell-editor/TableNameBox.tsx — ο ΕΝΑΣ αναγνώστης
 * @see bim/table/table-cell-range.ts — `tableSelectionSize`, η ΜΙΑ μετάφραση σε αριθμούς
 * @see state/table-resize-readout-store.ts — το αδελφό store ζωντανής ένδειξης
 */

import { useSyncExternalStore } from 'react';
import { createExternalStore } from '../stores/createExternalStore';
import type { TableSelectionSpan } from '../bim/table/table-cell-range';

/**
 * Σύγκριση **κατά τιμή**, ίδια με εκείνη του δρομέα και για τον ίδιο μετρημένο λόγο: κάθε
 * κίνηση του ποντικιού παράγει νέο αντικείμενο, οπότε μια σύγκριση αναφοράς θα δήλωνε
 * «άλλαξε» 60-120 φορές το δευτερόλεπτο ακόμα και μέσα στο ίδιο κελί.
 *
 * ⚠️ Ο φύλακας «γράψε μόνο όταν αλλάζει κελί» της σύρσης **δεν** καθιστά αυτό περιττό: το
 * `mousedown` γράφει ούτως ή άλλως, και μια δεύτερη χειρονομία που ξεκινά στο **ίδιο** κελί
 * με την προηγούμενη θα ήταν ισοδύναμη εγγραφή. Belt-and-suspenders (N.7.2 #4).
 */
const store = createExternalStore<TableSelectionSpan | null>(null, {
  equals: (a, b) =>
    a?.from.rowId === b?.from.rowId
    && a?.from.colId === b?.from.colId
    && a?.to.rowId === b?.to.rowId
    && a?.to.colId === b?.to.colId
    && a?.kind === b?.kind,
});

/**
 * Ανακοινώνει το ζωντανό εύρος της χειρονομίας· `null` το σβήνει.
 *
 * ⚠️ **Καμία κλήση σε `markSystemsDirty`**, σε αντίθεση με τον δρομέα: αυτό δεν ζωγραφίζεται
 * ποτέ στον καμβά — το διαβάζει **μόνο** ένα φύλλο του DOM, μέσω `useSyncExternalStore`. Ένα
 * αίτημα καρέ εδώ θα ήταν επαναβαφή ολόκληρης της σκηνής ανά κελί που διασχίζει το χέρι,
 * δηλαδή ακριβώς το κόστος που ο ADR-735 πλήρωσε σε παραγωγή, για ένα κείμενο έξι
 * χαρακτήρων.
 */
export function setTableDragSpan(span: TableSelectionSpan | null): void {
  store.set(span);
}

/** Event-time ανάγνωση (ADR-040: getter, ποτέ στιγμιότυπο). */
export function getTableDragSpan(): TableSelectionSpan | null {
  return store.get();
}

/** React binding — ο μόνος τρόπος που ο DOM κόσμος βλέπει τη ζωντανή σύρση. */
export function useTableDragSpan(): TableSelectionSpan | null {
  return useSyncExternalStore(store.subscribe, store.get, store.get);
}

/** Test helper — μηδενισμός μεταξύ tests, ίδιο μοτίβο με τα αδελφά stores. */
export function __resetTableDragSpanStoreForTests(): void {
  store.reset(null);
}
