'use client';

/**
 * 🔴 ADR-828 **Φ4α** — **ΤΙ ΜΟΛΙΣ ΣΥΜΠΛΗΡΩΘΗΚΕ, ΚΑΙ ΑΠΟ ΠΟΥ ΒΓΗΚΕ.**
 *
 * Η μεταβατική κατάσταση πίσω από το κουμπί «Επιλογές Αυτόματης Συμπλήρωσης»: η συμπλήρωση
 * έγινε, γράφτηκε **μία** φορά, και ο άνθρωπος έχει ακόμη το δικαίωμα να πει «*όχι έτσι*»
 * χωρίς να ξανακάνει τη σύρση.
 *
 * ## Γιατί store και όχι React state
 * Ο πρώτος καταναλωτής είναι ο **ζωγράφος του καμβά**, που δεν βλέπει React state — ακριβώς
 * το ίδιο επιχείρημα με το `table-cell-cursor-store` και το `table-copy-marquee-store`.
 * Διαβάζεται με getter τη στιγμή του καρέ (ADR-040).
 *
 * ## 🔴 ΓΙΑΤΙ ΚΡΑΤΑ ΤΗΝ ΑΝΑΦΟΡΑ ΤΟΥ ΜΟΝΤΕΛΟΥ — ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΥΠΑΡΧΟΥΝ ΑΚΥΡΩΤΕΣ
 * Το Excel σβήνει αυτό το κουμπί σε **τέσσερα** γεγονότα: επόμενη αναιρέσιμη πράξη · `Undo` ·
 * πληκτρολόγηση · `Esc`. Τρία από τα τέσσερα είναι το **ίδιο** γεγονός ιδωμένο από αλλού —
 * *«το μοντέλο δεν είναι πια αυτό που ήταν όταν γεννήθηκε το κουμπί»* — και το απαντά μία
 * σύγκριση δείκτη πάνω στο {@link TableFillBadgeState.modelRef}. Δες
 * `resolveTableFillBadgeBounds` για ολόκληρο το επιχείρημα.
 *
 * ⇒ **Καμία διαδρομή εγγραφής δεν χρειάζεται να μάθει ότι υπάρχει κουμπί**, ούτε οι σημερινές
 * ούτε οι μελλοντικές. Είναι η ίδια δομική λύση που κρατά τα «μυρμήγκια» του §48, και ο λόγος
 * που αυτό το αρχείο δεν έχει ούτε έναν `clearOnX`.
 *
 * ## 🔴 Ο ΤΕΤΑΡΤΟΣ: Ο ΦΡΟΥΡΟΣ ΖΩΗΣ — ΙΔΙΑ ΕΡΩΤΗΣΗ ΜΕ ΤΟ MARQUEE, ΧΩΡΙΣ ΡΟΛΟΪ
 * Το `Esc` δεν αγγίζει το μοντέλο: **βγάζει τον άνθρωπο από τον πίνακα**. Το marquee το
 * πιάνει ρωτώντας «*είναι ο δρομέας ακόμα σε ΑΥΤΟΝ τον πίνακα;*» σε κάθε παλμό των μυρμηγκιών
 * — έχει ήδη ρολόι, οπότε η ερώτηση είναι δωρεάν. Εδώ **δεν υπάρχει ρολόι**, και ένα ρολόι
 * γεννημένο μόνο και μόνο για να ρωτά θα ήταν καρέ ανά 80 ms για ένα κουμπί που δεν κινείται.
 *
 * Η **ίδια** ερώτηση απαντιέται με **συνδρομή στον ίδιο δρομέα**: η απάντηση αλλάζει μόνο όταν
 * αλλάξει ο δρομέας, οπότε ρωτιέται ακριβώς τότε — μηδέν polling, μηδέν καρέ. Απαντά μαζί σε
 * `Escape`, έξοδο από τη λειτουργία **και** μετάβαση σε άλλον πίνακα, δηλαδή σε τρεις
 * ακυρωτές με μία γραμμή.
 *
 * ⚠️ **Χρειάζεται ρητά**, δεν αρκεί η σιωπή του ζωγράφου: ο ζωγράφος σωπαίνει όσο λείπει ο
 * δρομέας, αλλά ο δρομέας **ξαναγεννιέται με τα ίδια δεδομένα** όταν ο χρήστης ξαναμπεί στον
 * πίνακα — και τότε ένα κουμπί από περασμένη συνεδρία θα **ανασταινόταν** πάνω από μια
 * συμπλήρωση που κανείς δεν θυμάται. Ο φρουρός το κάνει μη εκφράσιμο.
 *
 * ## Τι ΔΕΝ σβήνει το κουμπί
 * Η **επιλογή** από το ίδιο του το μενού. Excel parity, και σκόπιμο: μετά την εφαρμογή το
 * κουμπί **επαν-οπλίζεται** με τη νέα σφραγίδα έκδοσης, γιατί η ίδια `commitTableFill` που το
 * γέννησε είναι εκείνη που τρέχει ξανά. Δηλαδή ο άνθρωπος μπορεί να δοκιμάσει «σειρά», να δει
 * το αποτέλεσμα, και να γυρίσει σε «αντιγραφή» — χωρίς `Ctrl+Z`, όπως στο Excel. Δεν χρειάζεται
 * γραμμή κώδικα γι' αυτό· χρειάζεται να **μην** γραφτεί, και καταγράφεται εδώ ώστε να μην
 * «διορθωθεί» αργότερα ως παράλειψη.
 *
 * @module subapps/dxf-viewer/state/table-fill-badge-store
 * @see bim/table/table-fill-badge.ts — πού κάθεται, και πότε είναι ακόμη αληθινό
 * @see rendering/entities/table/stamp-table-fill-badge.ts — ο ένας ζωγράφος
 * @see docs/centralized-systems/reference/adrs/ADR-828-table-autofill-series.md §8
 */

import { createExternalStore } from '../stores/createExternalStore';
import { markSystemsDirty } from '../rendering/core/frame-scheduler-api';
import { getTableCellCursor, subscribeTableCellCursor } from './table-cell-cursor-store';
import type { TableCellRangeBounds } from '../bim/table/table-cell-range';
import type { TableFillTarget } from '../bim/table/table-fill-handle';
import type { TableEntity } from '../types/table-entity';

/**
 * 🔴 **ΜΟΝΟ ΔΕΔΟΜΕΝΑ — καμία συνάρτηση, κανένα closure.**
 *
 * Η πράξη («ξαναγράψε με άλλη πρόθεση») **δεν** ταξιδεύει εδώ μέσα, σε αντίθεση με το
 * `TableFillMenuTarget` της Φ3. Εκεί η πράξη ζει όσο μια χειρονομία που μόλις τελείωσε· εδώ
 * το κουμπί επιβιώνει αλληλεπιδράσεων, και ένα closure πάνω σε `press` θα κρατούσε ζωντανά
 * ένα `HTMLElement`, ένα `transformRef` και μια οντότητα από **περασμένο** καρέ — δηλαδή θα
 * έγραφε πάνω σε σκηνή που μπορεί να μην υπάρχει πια (ADR-040 κανόνας #2). Η πράξη
 * ξαναχτίζεται τη στιγμή του πατήματος, από τον ζωντανό κόσμο.
 */
export interface TableFillBadgeState {
  readonly entityId: string;
  /** Η **πηγή** του μοτίβου — ό,τι χρειάζεται η ανίχνευση για να ξαναπροσφέρει τις εντολές. */
  readonly source: TableCellRangeBounds;
  /** Ο **στόχος** της χειρονομίας: ποια νέα κελιά, και από ποια κατεύθυνση. */
  readonly target: TableFillTarget;
  /** Η **ένωση** πηγής και στόχου — το ορθογώνιο κάτω από το οποίο κάθεται το κουμπί. */
  readonly filled: TableCellRangeBounds;
  /** Η **σφραγίδα έκδοσης** του πίνακα τη στιγμή της συμπλήρωσης — δες την κεφαλίδα. */
  readonly modelRef: TableEntity['model'];
}

/** Ο ζωγράφος που πρέπει να μάθει ότι κάτι άλλαξε — ίδιο μοτίβο με τα αδελφά stores. */
const DXF_CANVAS_SYSTEM_ID = 'dxf-canvas';

const store = createExternalStore<TableFillBadgeState | null>(null);

/** Η ρητή διακοπή του τρέχοντος φρουρού· `null` όταν δεν υπάρχει κουμπί να φυλαχτεί. */
let stopWatch: (() => void) | null = null;

function requestFrame(): void {
  markSystemsDirty([DXF_CANVAS_SYSTEM_ID]);
}

/**
 * «Είναι ο άνθρωπος ακόμα μέσα σε **αυτόν** τον πίνακα;» — δες την κεφαλίδα για τους τρεις
 * ακυρωτές που απαντά μαζί.
 *
 * ⚠️ **Δεν** ρωτά για το μοντέλο, όπως δεν ρωτά ούτε ο αντίστοιχος φρουρός των μυρμηγκιών:
 * εκείνη η ερώτηση απαιτεί ανάγνωση σκηνής, την οποία ο ζωγράφος έχει **δωρεάν** στο χέρι του
 * κάθε καρέ. Κάθε ερώτηση εκεί όπου η απάντηση είναι φθηνή.
 */
function isBadgeAlive(): boolean {
  const badge = store.get();
  if (!badge) return false;
  return getTableCellCursor()?.entityId === badge.entityId;
}

function commit(next: TableFillBadgeState | null): void {
  stopWatch?.();
  stopWatch = null;
  store.set(next);
  requestFrame();
  if (!next) return;
  stopWatch = subscribeTableCellCursor(() => {
    // `clearTableFillBadge` και όχι `store.set(null)`: η λήξη οφείλει να περάσει από την
    // **ίδια** πόρτα με κάθε άλλο σβήσιμο, αλλιώς ο επόμενος που προσθέσει κάτι στο κλείσιμο
    // θα το προσθέσει σε μία από τις δύο.
    if (!isBadgeAlive()) clearTableFillBadge();
  });
}

/** Καθαρή ανάγνωση — ο getter που καλούν ο `TableRenderer`, το πάτημα και το πληκτρολόγιο. */
export function getTableFillBadge(): TableFillBadgeState | null {
  return store.get();
}

/**
 * Η συμπλήρωση εκτελέστηκε — όπλισε το κουμπί.
 *
 * Μια δεύτερη συμπλήρωση **αντικαθιστά** την πρώτη: υπάρχει πάντα το πολύ **ένα** κουμπί, και
 * απαντά για την **τελευταία** πράξη. Είναι η συμπεριφορά του Excel και η μόνη που δεν λέει
 * ψέματα — δύο κουμπιά θα υπόσχονταν ότι μπορείς να αλλάξεις γνώμη για μια συμπλήρωση που έχει
 * ήδη σκεπαστεί από την επόμενη.
 */
export function setTableFillBadge(next: TableFillBadgeState): void {
  commit(next);
}

/** Σβήνει το κουμπί και σταματά τον φρουρό. Ιδεμποτής. */
export function clearTableFillBadge(): void {
  if (store.get() === null) return;
  commit(null);
}

/** Test helper — μηδενισμός μεταξύ tests, μαζί με τον φρουρό που αλλιώς θα επιζούσε. */
export function __resetTableFillBadgeForTests(): void {
  stopWatch?.();
  stopWatch = null;
  store.reset(null);
}
