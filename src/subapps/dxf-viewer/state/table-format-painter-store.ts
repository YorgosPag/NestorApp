'use client';

/**
 * 🔴 ADR-768 Φ4 — **Η ΛΕΙΤΟΥΡΓΙΑ ΤΟΥ ΠΙΝΕΛΟΥ ΜΟΡΦΟΠΟΙΗΣΗΣ**: πότε είναι οπλισμένο, πότε
 * κλειδωμένο, και **ποιος** το σβήνει.
 *
 * Zero-React, πάνω στο SSoT εργοστάσιο `createExternalStore` — καμία νέα μηχανική pub/sub.
 * Πρότυπο: `systems/match-properties/match-brush-store.ts` (ADR-581), το **άλλο** πινέλο της
 * εφαρμογής. Δες §«Δύο πινέλα» παρακάτω για το γιατί είναι δύο και όχι ένα.
 *
 * ## Οι τρεις καταστάσεις
 * ```
 *   ανενεργό            →  κανένα φορτίο· το κουμπί σβηστό, ο δείκτης ανέγγιχτος
 *   οπλισμένο «μία χρήση»  →  το επόμενο βάψιμο το ΚΑΤΑΝΑΛΩΝΕΙ         (μονό κλικ, Α1)
 *   οπλισμένο «κλειδωμένο» →  βάφει όσες φορές θες, μέχρι Esc / 2ο κλικ (διπλό κλικ, Α1)
 * ```
 * Εκφράζονται ως `TableFormatPainterLoad | null` και **όχι** ως τρίτιμη σημαία δίπλα σε
 * προαιρετικό φορτίο: η κατάσταση «οπλισμένο **χωρίς** πηγή» δεν πρέπει να μπορεί καν να
 * γραφτεί. Είναι η δομική μορφή της απόφασης **Α6** («το `Esc` είναι ένα επίπεδο *επειδή* το
 * πινέλο οπλίζεται πάντα με πηγή»): ένας τύπος που την επιτρέπει είναι πρόσκληση για δεύτερο
 * επίπεδο `Esc` που κανείς δεν αποφάσισε.
 *
 * ## 🔴 ΓΙΑΤΙ ΔΕΝ ΚΡΑΤΑ ΤΑΥΤΟΤΗΤΑ ΠΗΓΗΣ — Η ΜΙΑ ΜΗ-ΠΡΟΦΑΝΗΣ ΑΠΟΦΑΣΗ ΕΔΩ
 * Το φορτίο είναι **στιγμιότυπο** ({@link TableFormatBrush}): αποκομμένο από το μοντέλο, με
 * `rows`/`columns` αντί για `bounds`, ακριβώς ώστε να επιβιώνει της διαγραφής της πηγής. Άρα
 * ένα `entityId` εδώ δεν θα φύλαγε **τίποτα** — θα ήταν όμως μόνιμη πρόσκληση για έναν
 * μελλοντικό φύλακα `φορτίο.entityId === δρομέας.entityId`, που θα σκότωνε **σιωπηλά** το
 * βάψιμο από πίνακα σε πίνακα.
 *
 * Και το βάψιμο σε **άλλον** πίνακα είναι ρητή απόφαση, όχι παράλειψη: το κάνουν και οι πέντε
 * μεγάλοι (Excel μεταξύ φύλλων **και** βιβλίων· Word/InDesign μεταξύ εγγράφων· AutoCAD
 * MATCHPROP μεταξύ ανοιχτών σχεδίων· Revit Match Type μεταξύ όψεων). Εμείς το κάνουμε
 * **καλύτερα και δωρεάν**: η «ελάχιστη υλοποίηση» (Α2) συγκρίνει με την κληρονομιά **του
 * στόχου**, οπότε κεφαλίδα-Α → κεφαλίδα-Β γράφει **μηδέν** παρακάμψεις και ο στόχος μένει
 * ζωντανός στο δικό του στυλ — ενώ το Excel θα τον κάρφωνε για πάντα.
 *
 * ## 🔴 Ο ΙΔΙΟΚΤΗΤΗΣ ΚΥΚΛΟΥ ΖΩΗΣ ΕΙΝΑΙ **ΑΥΤΟ ΤΟ MODULE** (N.7.2 #7)
 * Ο κανόνας: *το πινέλο ζει όσο ζει **ένας** δρομέας κελιού, οποιοσδήποτε.*
 * ```
 *   δρομέας → null         ⇒ ΣΒΗΝΕΙ   (καμία συνεδρία ⇒ κανένας στόχος να βαφτεί)
 *   δρομέας: πίνακας Α → Β ⇒ ΜΕΝΕΙ    (cross-table· δες παραπάνω)
 * ```
 * Ο φύλακας **εγκαθίσταται από το ίδιο το {@link armTableFormatPainter}** και αποδεσμεύεται
 * από το {@link disarmTableFormatPainter}. Δεν είναι καλλωπισμός — είναι η διόρθωση του
 * μετρημένου ελαττώματος του ADR-581: εκεί το `clearMatchBrushSource` καλείται **μόνο** σε
 * αλλαγή εργαλείου, δηλαδή ο καθαρισμός ζει **έξω** από το πινέλο και κάθε νέος δρόμος
 * εξόδου πρέπει να θυμηθεί να τον καλέσει. Εδώ **κανένα component δεν μπορεί να τον ξεχάσει**.
 *
 * ⚠️ Δεν είναι ιδιοκτήτης η **θύρα μορφοποίησης**, παρότι η κεφαλίδα της γράφει «`null` → θύρα
 * σημαίνει: η συνεδρία πίνακα ξεκίνησε». Μετρήθηκε 2026-08-07 και **δεν ισχύει**: το
 * `useTableFormatActions` καλείται **άνευ όρων** (`useCanvasSectionUI.ts:98`), άρα η θύρα
 * υπάρχει όσο ζει ο viewer. Ο **δρομέας** είναι το σήμα συνεδρίας — και μόνο αυτός.
 *
 * ## Δύο πινέλα, δύο επίπεδα της ίδιας δοκτρίνας — όχι δύο απαντήσεις
 * Το ADR-581 έχει ήδη πινέλο ιδιοτήτων **για οντότητες σχεδίου** (`systems/match-properties/`).
 * Η μηχανή του **δεν** επαναχρησιμοποιείται: οι descriptors του διαβάζουν `SceneEntity` και
 * γράφουν σε `scene`/`params` με `UpdateEntityCommand` — **ένα κελί δεν είναι οντότητα**. Ίδια
 * σχέση με το Revit, που έχει Match Type για στοιχεία και χωριστά εργαλεία **μέσα** στα
 * schedules.
 *
 * ## Γιατί ΚΑΝΕΝΑ `markSystemsDirty`
 * Τα αδέλφια stores του πίνακα ζητούν καρέ επειδή ο **καμβάς** τα ζωγραφίζει. Το πινέλο δεν
 * βάφει ούτε ένα pixel του καμβά: η κατάστασή του φαίνεται στο **κουμπί** (φύλλο React) και
 * στον **δείκτη** (ιδιότητα DOM, ADR-549 Φ8). Ένα καρέ εδώ θα ήταν επανασχεδίαση ολόκληρης
 * της σκηνής για κάτι που δεν αλλάζει τη σκηνή. *(Η ζωντανή προεπισκόπηση της Φ6 **θα**
 * χρειαστεί καρέ — και θα το ζητήσει το δικό της store, που ξέρει τι ζωγραφίζεται.)*
 *
 * @module subapps/dxf-viewer/state/table-format-painter-store
 * @see bim/table/table-format-paint.ts — η ΠΡΑΞΗ (καθαρή· φόρτωμα + βάψιμο)
 * @see bim/table/table-format-payload.ts — ΤΙ είναι το φορτίο
 * @see systems/match-properties/match-brush-store.ts — το πινέλο ΟΝΤΟΤΗΤΩΝ (ADR-581)
 * @see docs/centralized-systems/reference/adrs/ADR-768-table-format-painter.md
 */

import { createExternalStore } from '../stores/createExternalStore';
import { getTableCellCursor, subscribeTableCellCursor } from './table-cell-cursor-store';
import type { TableFormatBrush } from '../bim/table/table-format-payload';

/**
 * Πόσο ζει το φορτίο. Η χειρονομία που τα γεννά είναι του Excel (Α1): **μονό** κλικ στο
 * κουμπί ⇒ `once`, **διπλό** ⇒ `locked`. Η ίδια η χειρονομία ζει στο Βήμα 5 — εδώ μόνο το
 * αποτέλεσμά της, ώστε ο κανόνας «τι σημαίνει μία χρήση» να μην ξαναγραφτεί ανά καλούντα.
 */
export type TableFormatPainterMode = 'once' | 'locked';

/** Το οπλισμένο πινέλο: **πάντα** φορτίο **και** διάρκεια. Δες την κεφαλίδα (Α6). */
export interface TableFormatPainterLoad {
  readonly mode: TableFormatPainterMode;
  /** Το στιγμιότυπο της πηγής — αποκομμένο από το μοντέλο, επιβιώνει της διαγραφής της. */
  readonly brush: TableFormatBrush;
}

/**
 * Οι τρεις καταστάσεις ως **μία** λέξη, για όσους δείχνουν κατάσταση (κουμπί `aria-pressed`,
 * ρόλος δείκτη, ζωντανή περιοχή a11y).
 *
 * Παράγεται, **δεν αποθηκεύεται**: μια δεύτερη αποθηκευμένη σημαία δίπλα στο φορτίο θα ήταν
 * δεύτερη αλήθεια που μπορεί να αποκλίνει — και θα απέκλινε ακριβώς στην κατανάλωση, όπου
 * αλλάζουν και τα δύο.
 */
export type TableFormatPainterState = 'idle' | TableFormatPainterMode;

const store = createExternalStore<TableFormatPainterLoad | null>(null);

// ──────────────────────────────────────────────────────────────────────────────
// Ο φύλακας της συνεδρίας — δες την κεφαλίδα για το γιατί ζει ΕΔΩ
// ──────────────────────────────────────────────────────────────────────────────

/** Η αποδέσμευση της τρέχουσας παρακολούθησης· `null` όσο το πινέλο είναι ανενεργό. */
let releaseSessionWatch: (() => void) | null = null;

/**
 * Παρακολουθεί τον δρομέα όσο το πινέλο είναι οπλισμένο.
 *
 * Ο έλεγχος είναι **`=== null` και τίποτε άλλο**: κάθε άλλη μεταβολή του δρομέα (μετακίνηση
 * κελιού, αλλαγή κατάστασης, **αλλαγή πίνακα**) αφήνει το πινέλο ανέγγιχτο. Ένα σκέτο
 * «άλλαξε ο δρομέας ⇒ σβήσε» θα ήταν καταστροφικό: ο δρομέας γράφεται σε **κάθε πάτημα
 * πλήκτρου**, οπότε το πινέλο θα έσβηνε πριν προλάβει ο χρήστης να στοχεύσει.
 *
 * Ιδεμποτής: δεύτερο `arm` δεν εγκαθιστά δεύτερο ακροατή.
 */
function watchSession(): void {
  if (releaseSessionWatch !== null) return;
  releaseSessionWatch = subscribeTableCellCursor(() => {
    if (getTableCellCursor() === null) disarmTableFormatPainter();
  });
}

/** Αποδεσμεύει τον φύλακα. Ιδεμποτής — καλείται και από τον μηδενισμό των tests. */
function stopWatchingSession(): void {
  releaseSessionWatch?.();
  releaseSessionWatch = null;
}

// ──────────────────────────────────────────────────────────────────────────────
// Ανάγνωση — getters, ποτέ στιγμιότυπα (ADR-040 #2)
// ──────────────────────────────────────────────────────────────────────────────

/** Το οπλισμένο πινέλο **τη στιγμή της κλήσης**, ή `null`. */
export function getTableFormatPainter(): TableFormatPainterLoad | null {
  return store.get();
}

/** Οι τρεις καταστάσεις ως μία λέξη — δες {@link TableFormatPainterState}. */
export function getTableFormatPainterState(): TableFormatPainterState {
  return store.get()?.mode ?? 'idle';
}

/** `true` όσο υπάρχει φορτίο, σε οποιαδήποτε από τις δύο διάρκειες. */
export function isTableFormatPainterArmed(): boolean {
  return store.get() !== null;
}

/** Συνδρομή για **φύλλα** (κουμπί, δείκτης) — ποτέ σε orchestrator (ADR-040). */
export function subscribeTableFormatPainter(listener: () => void): () => void {
  return store.subscribe(listener);
}

// ──────────────────────────────────────────────────────────────────────────────
// Γραφή
// ──────────────────────────────────────────────────────────────────────────────

/**
 * Οπλίζει το πινέλο με ένα φορτωμένο στιγμιότυπο.
 *
 * **Αρνείται χωρίς ζωντανό δρομέα** και το λέει με την επιστροφή. Δεν είναι παράνοια: ένα
 * οπλισμένο πινέλο χωρίς συνεδρία είναι **κολλημένη διεπαφή** — πατημένο κουμπί και δείκτης
 * πινέλου πάνω από καμβά που δεν έχει κελιά, με μόνο δρόμο εξόδου το `Esc` που ο χρήστης δεν
 * ξέρει ότι χρειάζεται. Είναι το δομικό δίδυμο της Α6, μία στροφή πιο έξω: όπως δεν υπάρχει
 * «οπλισμένο χωρίς πηγή», δεν υπάρχει «οπλισμένο χωρίς στόχο».
 *
 * **ΔΕΝ είναι ιδεμποτής, και είναι σωστό**: δύο `arm` είναι δύο **προθέσεις** — ο χρήστης
 * ξαναρούφηξε από άλλο κελί. Το δεύτερο φορτίο νικά και οι συνδρομητές ειδοποιούνται.
 *
 * @returns `true` αν όντως οπλίστηκε.
 */
export function armTableFormatPainter(
  brush: TableFormatBrush,
  mode: TableFormatPainterMode,
): boolean {
  if (getTableCellCursor() === null) return false;
  store.set({ mode, brush });
  watchSession();
  return true;
}

/**
 * Σβήνει το πινέλο. **Ιδεμποτής**: η δεύτερη κλήση δεν ειδοποιεί κανέναν.
 *
 * Οι ρητοί καλούντες είναι τρεις (Βήμα 5): `Esc`, δεύτερο κλικ στο κουμπί, αλλαγή εργαλείου.
 * Ο τέταρτος δεν είναι καλών — είναι ο φύλακας από πάνω.
 */
export function disarmTableFormatPainter(): void {
  if (store.get() === null) return;
  store.set(null);
  stopWatchingSession();
}

/**
 * 🔴 **ΜΙΑ ΧΡΗΣΗ ΤΟΥ ΠΙΝΕΛΟΥ** — επιστρέφει το φορτίο και εφαρμόζει τον κανόνα της διάρκειας.
 *
 * ```
 *   once    →  επιστρέφει το φορτίο ΚΑΙ σβήνει   (η δεύτερη κλήση δίνει null)
 *   locked  →  επιστρέφει το φορτίο, μένει ως έχει, ΧΩΡΙΣ να ειδοποιήσει
 *   idle    →  null
 * ```
 *
 * ## Γιατί εδώ και όχι στον καλούντα
 * Το «μία χρήση» είναι **ένας** κανόνας. Στους καλούντες θα γραφόταν δύο φορές — το κλικ σε
 * κελί (Β5) και το σύρσιμο σε περιοχή (Β6) — δηλαδή δύο ευκαιρίες να αποκλίνει, με το
 * σύμπτωμα («το πινέλο έμεινε οπλισμένο μετά το σύρσιμο») να μη δείχνει ποτέ προς την αιτία.
 *
 * ## 🔴 ΚΑΤΑΝΑΛΩΝΕΙ ΑΝΕΞΑΡΤΗΤΑ ΑΠΟ ΤΟ ΑΝ ΤΟ ΒΑΨΙΜΟ ΑΛΛΑΞΕ ΚΑΤΙ
 * Η υπογραφή δεν δέχεται «πέτυχε;» — και δεν πρόκειται να δεχτεί. Είναι η δοκτρίνα του
 * ADR-739 §40.8: *η χειρονομία ανήκει στο εργαλείο επειδή το εργαλείο ήταν **οπλισμένο**, όχι
 * επειδή η πράξη πέτυχε.*
 *
 * ⚠️ Συνειδητή **απόκλιση** από το `hatch-select-mode-store`, που σε αστοχία μένει οπλισμένο
 * («forgiving — ξαναδοκιμάζεις»). Εκεί η αστοχία σημαίνει «*αστόχησες*»: το κλικ δεν βρήκε
 * γραμμοσκίαση, και η επόμενη προσπάθεια έχει νόημα. Εδώ **κάθε κελί είναι έγκυρος στόχος**,
 * άρα αστοχία σημαίνει «*το μοντέλο δεν είχε τίποτα να αλλάξει*» — και η επόμενη προσπάθεια
 * θα δώσει ακριβώς το ίδιο. Ένα πινέλο που μένει οπλισμένο μετά από άκαρπο κλικ αναπαράγει
 * τέλεια το «πάτησα και δεν έγινε τίποτα», που είναι το #1 παράπονο του Excel (Α4).
 */
export function consumeTableFormatPainterBrush(): TableFormatBrush | null {
  const load = store.get();
  if (load === null) return null;
  // Το «κλειδωμένο» δεν αλλάζει κατάσταση, άρα **δεν ειδοποιεί**: αλλιώς το κουμπί και ο
  // δείκτης θα ξανα-αποδίδονταν σε κάθε βάψιμο για μια κατάσταση που έμεινε ίδια.
  if (load.mode === 'once') disarmTableFormatPainter();
  return load.brush;
}

/**
 * Test helper — μηδενισμός μεταξύ tests, ίδιο μοτίβο με τα αδέλφια stores.
 *
 * ⚠️ Καθαρίζει **και** τον φύλακα: το `reset` του `createExternalStore` του δρομέα ρίχνει
 * όλους τους ακροατές του, οπότε ένας φύλακας που επιβίωνε εδώ θα ήταν κρατημένη αποδέσμευση
 * που δεν αποδεσμεύει τίποτα — και το επόμενο `arm` θα την έβλεπε ως «ήδη παρακολουθώ» και
 * **δεν θα εγκαθιστούσε ποτέ νέο φύλακα**.
 */
export function __resetTableFormatPainterForTests(): void {
  stopWatchingSession();
  store.reset(null);
}
