/**
 * ADR-739 Φ.Δ βήμα 2 — **ΤΙ ΛΕΕΙ Ο ΔΡΟΜΕΑΣ ΚΕΛΙΟΥ**: οι δηλώσεις του, με το «γιατί» της καθεμιάς.
 *
 * Καθαρό module δηλώσεων — μηδέν store, μηδέν React, μηδέν παρενέργειες. Ήταν η κεφαλή του
 * `state/table-cell-cursor-store.ts` και μετακόμισε **αυτούσια** εδώ.
 *
 * ## Γιατί χωριστό αρχείο — η ίδια τομή με το `table-ids.ts`
 * Η ADR-833 Φάση 2 πρόσθεσε στον δρομέα το `worksheetId` (ποιο **φύλλο**, όχι μόνο ποιος
 * πίνακας) και το αρχείο πέρασε τις 500 γραμμές (N.7.1). Η τομή είναι **σημασιολογική**, όχι
 * μετρική — ακριβώς όπως όταν ο δεύτερος γραφέας έσπρωξε το `table-model-helpers.ts` πάνω από
 * το όριο και γεννήθηκε το `table-cell-writer.ts`:
 *
 * ```
 *   εδώ           →  ΤΙ ΛΕΕΙ ο δρομέας   (καταστάσεις, πεδία, το «γιατί» τους)
 *   store         →  ΠΩΣ ΑΛΛΑΖΕΙ         (μηχανισμός, ισοδυναμία, καρέ)
 *   cursor-scope  →  ΣΕ ΠΟΙΟΝ ΑΝΗΚΕΙ     (ο φύλακας πίνακα + φύλλου)
 * ```
 *
 * ⚠️ Κανένας υπάρχων καλών δεν αλλάζει διαδρομή εισαγωγής: το `table-cell-cursor-store.ts`
 * **επανεξάγει** και τους τρεις τύπους, όπως ήδη κάνει το `types/table.ts` για το `table-ids.ts`.
 *
 * @module subapps/dxf-viewer/state/table-cell-cursor-state
 * @see state/table-cell-cursor-store.ts — ο μηχανισμός
 * @see state/table-cell-cursor-scope.ts — ο φύλακας «ποιος πίνακας, ποιο φύλλο»
 */

import type { TableCursorPosition } from '../bim/table/table-cell-navigation';
import type { TableSelectionSpan } from '../bim/table/table-cell-range';
import type { TableWorksheetId } from '../types/table-worksheet';

/** Οι τρεις καταστάσεις του Excel — ο πίνακας τους ζει στην κεφαλίδα του `table-cell-cursor-store.ts`. */
export type TableCellCursorMode = 'nav' | 'enter' | 'edit';

/** `null` ⇒ κανένα τρέχον κελί (ο πίνακας είναι το πολύ επιλεγμένος ως οντότητα). */
export interface TableCellCursorState {
  /** Η οντότητα πίνακα που φιλοξενεί τον δρομέα. */
  readonly entityId: string;

  /**
   * 🔴 ADR-833 Φάση 2 — **ΚΑΙ ΠΟΙΟ ΦΥΛΛΟ.** Χωρίς αυτό, η ταυτότητα του δρομέα είναι **μισή**.
   *
   * ## Το σφάλμα που κλείνει — και γιατί δεν είναι θεωρητικό
   * Το {@link position} κρατά `{rowId, colId}`. Μετά από αλλαγή καρτέλας, τα ίδια `r2`/`c1`
   * **υπάρχουν** και στο άλλο φύλλο (κάθε πίνακας ξεκινά με `r0…`/`c0…` από τον ίδιο
   * κατασκευαστή), οπότε η γραφή δεν θα αποτύγχανε: θα **προσγειωνόταν σε λάθος φύλλο**, στο
   * ομώνυμο κελί. Σφάλμα **τιμής**, χωρίς εξαίρεση, χωρίς μήνυμα — η χειρότερη κατηγορία.
   *
   * ⚠️ Ο φύλακας **δεν** επαναλαμβάνεται σε κάθε αναγνώστη: ζει σε **ένα** μέρος,
   * `state/table-cell-cursor-scope.ts`, και όλοι οι δρόμοι «δρομέας ↔ πίνακας» περνούν από εκεί.
   *
   * ✅ Το `table-copy-marquee-store` και το `table-fill-badge-store` **δεν** χρειάστηκαν τίποτα:
   * φρουρούν ήδη με `!== activeTableModel(entity)`, και δύο φύλλα έχουν εξ ορισμού διαφορετικό
   * μοντέλο — αυτοακυρώνονται στην αλλαγή καρτέλας **χωρίς καμία νέα λογική**.
   */
  readonly worksheetId: TableWorksheetId;

  readonly position: TableCursorPosition;
  readonly mode: TableCellCursorMode;
  /**
   * Αύξων αριθμός **συνεδρίας γραφής**. Αλλάζει μόνο όταν μια συνεδρία ακυρώνεται με
   * `Escape` **χωρίς** να αλλάξει κελί ({@link cancelTableCellCursorSession}).
   *
   * ── Γιατί χρειάζεται αριθμός και δεν αρκεί το κελί ──
   * Το `<input>` του επεξεργαστή ξαναστήνεται όταν αλλάζει το React `key`, και μαζί του
   * ο **φρουρός «μία φορά»** του `use-inline-editor-keys` (`settledRef`) και το πρόχειρο
   * κείμενο. Σε μετακίνηση αυτό συμβαίνει δωρεάν (αλλάζει το row/col στο key). Το
   * `Escape` όμως γυρίζει σε `nav` **στο ίδιο κελί**: χωρίς αυτόν τον αριθμό το `<input>`
   * θα επιβίωνε ήδη «κριμένο», και το επόμενο `Enter` **δεν θα δέσμευε ποτέ** — μια
   * σιωπηλή απώλεια πληκτρολόγησης που δεν θα φαινόταν σε κανένα test κατάστασης.
   */
  readonly sessionId: number;

  /**
   * 🔴 ADR-763 Φ2.4.1 — **«δέσμευσε ό,τι γράφεται και βγες σε πλοήγηση»**· αύξων, ποτέ
   * μηδενίζεται μέσα στη ζωή του store. `0` ⇒ κανείς δεν έχει ζητήσει τίποτα.
   *
   * ## Γιατί ΣΗΜΑ και όχι απευθείας κλήση
   * Η δέσμευση **δεν είναι γραφή στο store**: χτίζει εντολή αναίρεσης πάνω στη ζωντανή σκηνή
   * (`buildTableCellEditCommand` + `execute`), δηλαδή χρειάζεται τον `LevelManager` και τον
   * δίαυλο εντολών. Και τα δύο ζουν στη React, στο `useTableCellDoubleClickEditor`. Ένας
   * καλών εκτός React —εδώ το «OK» του διαλόγου ορισμάτων, που ζει σε portal— δεν τα έχει.
   *
   * Οι δύο εναλλακτικές είναι χειρότερες, και η δεύτερη επικίνδυνη:
   *  - **Prop drilling** μέχρι το portal ⇒ ο διάλογος παύει να είναι self-subscribing και
   *    αποκτά εξάρτηση από τη σκηνή για κάτι που δεν τον αφορά.
   *  - **Δεύτερη υλοποίηση δέσμευσης** μέσα στον διάλογο ⇒ δεύτερος τρόπος να γραφτεί κελί,
   *    δηλαδή δεύτερη άποψη για το τι είναι βήμα αναίρεσης (N.18).
   *
   * Το σήμα είναι **η ίδια μορφή** με το {@link sessionId} και το {@link caretRevision}: ο
   * αιτών δηλώνει **τι** πρέπει να γίνει, ο **ένας** ιδιοκτήτης το εκτελεί. Αύξων και ποτέ
   * μηδενιζόμενος για τον ίδιο λόγο με εκείνα — ένα μηδένισμα θα μπορούσε να συμπέσει με
   * αίτημα που έχει ήδη εξυπηρετηθεί, δηλαδή **διπλή δέσμευση** ή **καμία**.
   */
  readonly commitRequest: number;

  /**
   * Το **πρόχειρο** κείμενο της τρέχουσας συνεδρίας γραφής· `''` σε κατάσταση πλοήγησης.
   *
   * ── 🔴 ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΕ `useState` ΤΟΥ ΕΠΕΞΕΡΓΑΣΤΗ (μετρημένο, 2026-08-01) ──
   *
   * Ήταν τοπικό React state. Ζωντανά, με 1.427 οντότητες, η πληκτρολόγηση χανόταν
   * **διαλείπουσα**: ένα probe στα συμβάντα του DOM έδειξε `input value="7"` και αμέσως
   * μετά `focusout value="7"`, ενώ το επόμενο `Tab` έφτανε σε `<input>` με `value=""` —
   * δηλαδή ο επεξεργαστής **ξαναστηνόταν** ανάμεσα στον χαρακτήρα και το Tab, και το
   * `useState` ξανασπερνόταν από την αρχική τιμή του κελιού. Το commit που ακολουθούσε
   * έγραφε το **παλιό** κείμενο (`command built? false` — «τίποτα δεν άλλαξε»).
   *
   * Αιτία του ξαναστησίματος: το `getLevelScene` είναι σκηνή που ανανεώνεται ασύγχρονα
   * (autosave / εξωτερική ενημέρωση). Ο επεξεργαστής **δεν επιτρέπεται** να εξαρτά τη
   * δουλειά του χρήστη από το αν μια ανάγνωση σκηνής πέτυχε σε ένα συγκεκριμένο render.
   *
   * Η διόρθωση δεν είναι «κράτα και το προηγούμενο target»: αυτό θεραπεύει το σύμπτωμα.
   * Ιδιοκτήτης της συνεδρίας γραφής είναι ο **δρομέας**, όχι ένα DOM node που μπορεί να
   * ξεφορτωθεί. Με το πρόχειρο εδώ, ένα ξαναστήσιμο είναι **αβλαβές** εξ ορισμού.
   *
   * ⚠️ Αυτό ΔΕΝ αναιρεί το «το store δεν κρατά κείμενο κελιού»: το πρόχειρο **δεν είναι**
   * το κείμενο του κελιού — είναι ό,τι δεν έχει δεσμευτεί ακόμα. Το δεσμευμένο κείμενο
   * παραμένει παράγωγο της οντότητας, πάντα.
   */
  readonly draft: string;

  /**
   * ADR-739 Φ.Δ βήμα 3 — σε ποιον **χαρακτήρα** στήνεται ο κέρσορας όταν ανοίγει η
   * συνεδρία· `undefined` ⇒ στο τέλος του κειμένου.
   *
   * Το γεμίζει **μόνο** το διπλό κλικ **μέσα** στη λειτουργία πίνακα (ADR-739 §46), γιατί μόνο
   * εκείνο έχει σημείο **και** πρόθεση γραφής: το Excel βάζει τον κέρσορα εκεί που έδειξες,
   * όχι μονίμως στο τέλος. `Tab` / βέλη / `F2` δεν έχουν σημείο, και το διπλό κλικ **εισόδου**
   * δεν έχει πρόθεση γραφής — και τα δύο αφήνουν το πεδίο κενό· δεν είναι παράλειψη, είναι η
   * σωστή σημασιολογία.
   *
   * Καταναλώνεται στο στήσιμο του πεδίου **και** σε κάθε αλλαγή του
   * {@link caretRevision} — δες εκεί γιατί δεν αρκεί ο δείκτης μόνος του.
   */
  readonly caretIndex?: number;

  /**
   * 🔴 ADR-754 §4 — **πόσες φορές τοποθέτησε ο κώδικας τον κέρσορα**· αύξων, ποτέ μηδενίζεται
   * μέσα στη ζωή του store.
   *
   * ## Γιατί ΔΕΝ αρκεί το {@link caretIndex}
   * Ο δείκτης είναι **θέση**· εδώ χρειάζεται **γεγονός**. Δύο ανεξάρτητοι λόγοι, και ο
   * καθένας μόνος του αρκεί:
   *
   *  1. **Το `equals` του store απορρίπτει την ισοδύναμη εγγραφή.** Υπόδειξη στο `E4` και
   *     αμέσως ξανά στο `E4` δίνει **ίδιο** πρόχειρο και **ίδιο** δείκτη ⇒ «τίποτα δεν
   *     άλλαξε» ⇒ κανείς δεν ειδοποιείται. Σωστό για κατάσταση, λάθος για **εντολή**.
   *  2. **Ένα effect με εξάρτηση τον δείκτη δεν ξανατρέχει όταν ο δείκτης δεν αλλάζει** —
   *     ενώ το κείμενο από κάτω του άλλαξε, άρα ο browser έχει ήδη μετακινήσει τον κέρσορα
   *     στο τέλος. Δηλαδή ακριβώς η περίπτωση που πρέπει να διορθωθεί είναι εκείνη που το
   *     effect δεν θα έβλεπε.
   *
   * ## Γιατί ΔΕΝ ξαναχρησιμοποιείται το {@link sessionId}
   * Εκείνο ξαναστήνει το πεδίο (είναι μέρος του React `key`) — δηλαδή θα πλήρωνε remount του
   * `<textarea>` σε **κάθε κλικ υπόδειξης**, ακριβώς αυτό που το `preventDefault` του §3
   * υπάρχει για να αποφύγει. Δύο αριθμοί, δύο διαφορετικές συνέπειες: ο ένας λέει «καινούριο
   * πεδίο», ο άλλος «ίδιο πεδίο, άλλος κέρσορας».
   *
   * ⚠️ **Δεν αυξάνεται από την πληκτρολόγηση** ({@link setTableCellCursorDraft}): εκεί τον
   * κέρσορα τον κινεί ο ίδιος ο browser, στη σωστή θέση, και μια επιβολή θα τον πολεμούσε.
   */
  readonly caretRevision: number;

  /**
   * 🔴 ADR-739 Φ.Δ βήμα 8 — **η επιλεγμένη περιοχή**, ως δύο γωνίες· `null` ⇒ καμία περιοχή
   * (μόνο το ενεργό κελί).
   *
   * ## Γιατί ΕΔΩ και όχι μέσα στο `TableCursorPosition`
   * Η θέση είναι **καθαρή θέση**: την παράγουν τέσσερις ανεξάρτητοι δρόμοι, ένας από τους
   * οποίους είναι μια πληκτρολογημένη αναφορά `B3` στη γραμμή τύπων
   * (`parseTableCellReference`) που δεν έχει καμία σχέση με επιλογή. Αν η έκταση ζούσε
   * εκεί, και οι τέσσερις θα υποχρεώνονταν να αποφασίσουν γι' αυτήν. Δες την κεφαλίδα του
   * `table-cell-range.ts` για ολόκληρο το σκεπτικό.
   *
   * ## 🔴 Γιατί ΔΥΟ γωνίες και όχι «ενεργό κελί + το άλλο άκρο»
   * Ήταν η πρώτη σχεδίαση, και **το `Ctrl+A` τη διέψευσε**: στο Excel (και στα Sheets) η
   * «επιλογή όλων» επιλέγει ολόκληρο το πλέγμα και **αφήνει το ενεργό κελί εκεί που ήταν**.
   * Με ενεργό κελί το `C5`, η περιοχή είναι `A1:τέλος` — ένα ορθογώνιο που **δεν έχει το
   * ενεργό κελί σε καμία γωνία του**. Ένα μοντέλο «ενεργό κελί + άκρο» δεν μπορεί να το
   * εκφράσει, και η μόνη διέξοδός του θα ήταν να **μετακινήσει** τον δρομέα στο `A1` —
   * δηλαδή το `Ctrl+A` να πλοηγεί, ενώ πρέπει μόνο να επιλέγει.
   *
   * Άρα: η περιοχή είναι **ανεξάρτητη** από τη θέση. Στη συνήθη περίπτωση το `from`
   * **τυχαίνει** να είναι το ενεργό κελί (κάθε `Shift+…` ξεκινά από εκεί)· αυτό είναι
   * αποτέλεσμα, όχι αναλλοίωτο, και ο τύπος δεν το επιβάλλει.
   *
   * ## Γιατί ΤΑΥΤΟΤΗΤΕΣ κελιών και όχι έτοιμο ορθογώνιο
   * Το ορθογώνιο είναι **παράγωγο**: εξαρτάται από τις συγχωνεύσεις του μοντέλου (η περιοχή
   * «κουμπώνει» ώστε να τις περικλείει ολόκληρες). Ένα αποθηκευμένο ορθογώνιο θα ήταν
   * δεύτερη αλήθεια που παλιώνει σε κάθε συγχώνευση/αποσυγχώνευση — ακριβώς ο λόγος για τον
   * οποίο αυτό το store δεν κρατά ούτε το **κείμενο** του κελιού.
   *
   * ⚠️ **ΟΡΟΛΟΓΙΑ**: «ενεργό κελί» = {@link position}. Καμία από τις δύο γωνίες δεν λέγεται
   * «άγκυρα» — η λέξη ανήκει στις **συγχωνεύσεις** (`CellSpan.anchorRowId`).
   */
  readonly selection: TableCellSelection | null;
}

/**
 * Οι δύο γωνίες μιας επιλογής **και η πρόθεση που τις γέννησε**, σε αυθαίρετη σειρά — η
 * κανονικοποίηση και η ερμηνεία ζουν στο SSoT περιοχής.
 *
 * 🔴 ADR-739 §27.15 — το `kind` είναι **υποχρεωτικό**, χωρίς προεπιλογή. Μια σιωπηλή
 * προεπιλογή `'range'` θα ήταν ακριβώς το σφάλμα που διορθώνει: ο γραφέας που ξεχνά να
 * δηλώσει πρόθεση παίρνει κούμπωμα που δεν ζήτησε, και το μαθαίνει στην οθόνη. Τέσσερις
 * γραφείς υπάρχουν συνολικά — ο καθένας τους ξέρει τι διάλεξε ο χρήστης.
 */
export type TableCellSelection = TableSelectionSpan;
