'use client';

/**
 * 🔴 ADR-739 §57 — **Η ΜΝΗΜΗ ΤΟΥ ΕΣΩΤΕΡΙΚΟΥ ΠΡΟΧΕΙΡΟΥ**: τι κρατά η εφαρμογή από την τελευταία
 * αντιγραφή, πέρα από ό,τι έδωσε στο λειτουργικό.
 *
 * Zero-React, πάνω στο SSoT εργοστάσιο `createExternalStore` — καμία νέα μηχανική pub/sub.
 * Πρότυπο: `table-format-painter-store.ts` (ADR-768), το αδελφό store της ίδιας καρτέλας.
 *
 * ## 🔴 ΔΕΝ ΣΒΗΝΕΙ ΜΕ ΤΟΝ ΔΡΟΜΕΑ — η μία διαφορά από το πινέλο, και είναι σκόπιμη
 * Το πινέλο μορφοποίησης εγκαθιστά φύλακα που το σβήνει μόλις κλείσει η συνεδρία κελιού, με
 * ρητό επιχείρημα: *«οπλισμένο πινέλο χωρίς συνεδρία είναι κολλημένη διεπαφή — πατημένο κουμπί
 * και δείκτης πινέλου πάνω από καμβά που δεν έχει κελιά»*. Εδώ **δεν ισχύει τίποτα από αυτά**:
 * ένα γεμάτο πρόχειρο δεν αλλάζει τον δείκτη, δεν κρατά κουμπί πατημένο και δεν έχει κατάσταση
 * που να χρειάζεται έξοδο. Είναι απλώς **μνήμη**.
 *
 * Και το αντίθετο θα ήταν λάθος με τον χειρότερο τρόπο: αντιγράφεις, κλείνεις τον δρομέα για να
 * γυρίσεις σε άλλον πίνακα (ή απλώς πατάς `Esc`), και το πρόχειρο έχει **αδειάσει** — ενώ το
 * πρόχειρο του **συστήματος** εξακολουθεί να κρατά το κείμενό σου. Δύο πρόχειρα με διαφορετική
 * διάρκεια ζωής είναι δύο απαντήσεις στο «τι αντέγραψα».
 *
 * ## 🔑 Ο ΜΟΝΟΣ ΤΡΟΠΟΣ ΝΑ ΠΑΨΕΙ ΝΑ ΙΣΧΥΕΙ ΕΙΝΑΙ ΤΟ ΑΠΟΤΥΠΩΜΑ
 * Το φορτίο δεν λήγει με ρολόι, ούτε με ακροατή `clipboardchange` (που απαιτεί άδεια ή sticky
 * activation και δεν υπάρχει καθόλου σε Firefox/Safari). Λήγει **λογικά**: αν το πρόχειρο του
 * συστήματος δεν λέει πια το {@link TableClipboardPayload.text}, ο χρήστης αντέγραψε αλλού και
 * το φορτίο αγνοείται. Η απόφαση ζει στο `bim/table/table-clipboard-resolve.ts`, καθαρή και
 * ελεγχόμενη — εδώ μένει μόνο η αποθήκευση.
 *
 * ## Γιατί ΚΑΝΕΝΑ `markSystemsDirty` και καμία συνδρομή
 * Ίδιο επιχείρημα με το πινέλο, ένα σκαλί πιο κάτω: το πρόχειρο δεν βάφει ούτε ένα pixel του
 * καμβά **και** δεν αλλάζει τι δείχνει κανένα χειριστήριο. Το «Επικόλληση» δηλώνει ανέκαθεν
 * «μπορεί να **επιχειρηθεί**» και όχι «υπάρχει κάτι μέσα» (δες `TableMenuClipboardActions.
 * canPaste`) — άρα δεν υπάρχει φύλλο να ειδοποιηθεί. Ένα `subscribe` εδώ θα ήταν εξαγωγή που
 * κανείς δεν καλεί, δηλαδή ακριβώς αυτό που μετρά το CHECK 3.30.
 *
 * @module subapps/dxf-viewer/state/table-clipboard-store
 * @see bim/table/table-clipboard-payload.ts — ΤΙ κρατιέται
 * @see bim/table/table-clipboard-resolve.ts — ΠΟΤΕ ισχύει
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §57
 */

import { createExternalStore } from '../stores/createExternalStore';
import type { TableClipboardPayload } from '../bim/table/table-clipboard-payload';

const store = createExternalStore<TableClipboardPayload | null>(null);

/** Το φορτίο **τη στιγμή της κλήσης**, ή `null` αν δεν έχει αντιγραφεί τίποτα (ADR-040 #2). */
export function getTableClipboard(): TableClipboardPayload | null {
  return store.get();
}

/**
 * Καταγράφει τι μόλις αντιγράφηκε.
 *
 * **ΔΕΝ είναι ιδεμποτής, και είναι σωστό**: δύο αντιγραφές είναι δύο προθέσεις. Το δεύτερο
 * φορτίο νικά — όπως ακριβώς και στο πρόχειρο του λειτουργικού, που μόλις ξαναγράφτηκε.
 */
export function setTableClipboard(payload: TableClipboardPayload): void {
  store.set(payload);
}

/** Test helper — μηδενισμός μεταξύ tests, ίδιο μοτίβο με τα αδέλφια stores. */
export function __resetTableClipboardForTests(): void {
  store.reset(null);
}
