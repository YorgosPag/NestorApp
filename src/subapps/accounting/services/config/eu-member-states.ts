/**
 * @fileoverview **Κράτη μέλη της Ευρωπαϊκής Ένωσης — η ΜΙΑ ρίζα** (ADR-ACC-003 §22.5).
 * @module subapps/accounting/services/config/eu-member-states
 *
 * Το ερώτημα «είναι ο λήπτης στην ΕΕ;» κρίνει **τρία** πράγματα: τον τόπο παροχής υπηρεσιών (ν. 5144/2024 άρθρο 18
 * §2α / §15), τον τύπο παραστατικού myDATA (2.2 ενδοκοινοτικό ↔ 2.3 τρίτη χώρα — σφάλματα επικύρωσης 243/244 της
 * ΑΑΔΕ, myDATA REST API v2.0.1) και, αργότερα, τον ανακεφαλαιωτικό πίνακα VIES. Γι' αυτό η απάντηση ζει **μία** φορά.
 *
 * Πηγή: Ευρωπαϊκή Ένωση, «Χώρες της ΕΕ» (european-union.europa.eu) — 27 κράτη μέλη από 1/2/2020.
 *
 * ⚠️ **Κωδικοί ISO 3166-1 alpha-2, ΟΧΙ προθέματα ΑΦΜ ΦΠΑ**: η Ελλάδα είναι `GR` (όπως η αποθηκευμένη χώρα των
 * επαφών, `DEFAULT_STORED_COUNTRY_CODE`), ενώ το πρόθεμα του ΑΦΜ στο VIES είναι `EL`. Το `EL` **δεν** είναι χώρα.
 *
 * ⚠️ **Χώρα ≠ φορολογικό έδαφος ΦΠΑ**: περιοχές κρατών μελών εκτός του εδάφους ΦΠΑ της Ένωσης (π.χ. Άγιον Όρος,
 * Κανάριοι Νήσοι, Νήσοι Åland) **δεν** μοντελοποιούνται. Γι' αυτό ό,τι κρίνεται από εδώ φτάνει στον άνθρωπο ως
 * **πρόταση**, ποτέ ως απόφαση.
 */

export const EU_MEMBER_STATES = [
  'AT', 'BE', 'BG', 'CY', 'CZ', 'DE', 'DK', 'EE', 'ES', 'FI', 'FR', 'GR', 'HR', 'HU',
  'IE', 'IT', 'LT', 'LU', 'LV', 'MT', 'NL', 'PL', 'PT', 'RO', 'SE', 'SI', 'SK',
] as const;

/** Κωδικός κράτους μέλους — παραγόμενος από τη ρίζα, ποτέ γραμμένος με το χέρι. */
export type EuMemberState = (typeof EU_MEMBER_STATES)[number];

/** Στενευτής χωρίς `as`: αποθηκευμένος κωδικός χώρας (κεφαλαία) → κράτος μέλος, ή `false`. */
export function isEuMemberState(code: string | null | undefined): code is EuMemberState {
  return EU_MEMBER_STATES.some((state) => state === code);
}
