/**
 * **Κωδικός οντότητας** (ιδιότητα · ομάδα · οικογένεια · κατηγορία · οικογένεια μέτρησης ·
 * επιλογή · στήλη): πεζά λατινικά, αριθμοί, κάτω παύλα, ξεκινά με γράμμα, ≤ 64.
 *
 * 🔑 **Αμετάβλητος από τη δημιουργία** (Akeneo code · Revit shared-parameter GUID): είναι
 * η ταυτότητα που διαβάζουν εισαγωγές, εξαγωγές και αντιστοιχίσεις. Το όνομα που βλέπει ο
 * άνθρωπος είναι η **ετικέτα** και αλλάζει ελεύθερα.
 */
export const CATALOG_CODE_PATTERN = /^[a-z][a-z0-9_]{0,63}$/;

/** Κωδικός μονάδας μέτρησης — διατηρεί κεφαλαία (`kW` ≠ `KW` στην πράξη των μηχανικών). */
export const MEASUREMENT_UNIT_CODE_PATTERN = /^[A-Za-z][A-Za-z0-9_]{0,31}$/;

export function isCatalogCode(value: unknown): value is string {
  return typeof value === 'string' && CATALOG_CODE_PATTERN.test(value);
}
