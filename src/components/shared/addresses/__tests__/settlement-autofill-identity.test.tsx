/**
 * @fileoverview 🔴 **Η ΑΓΚΥΡΑ ΤΗΣ ΤΑΥΤΟΠΟΙΗΣΗΣ** — ADR-332 D27 Φάση Β′ (Ζ2 · Ζ4β · Ζ4γ).
 *
 * Ρωτά το μόνο πράγμα που κανένα test δεν ρωτούσε:
 *
 * > **«Όταν η μηχανή δίνει ΟΝΟΜΑ, δένουμε στη ΣΩΣΤΗ ταυτότητα — ή σε όποια τύχει πρώτη;»**
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΕΥΡΗΜΑ ΠΟΥ ΤΗΝ ΠΛΗΡΩΣΕ — **ΜΕΤΡΗΜΕΝΟ, 2026-09-12**
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * Το handoff δήλωνε ότι αυτή η διαδρομή *«δουλεύει»* και ότι έλειπε μόνο **κλήση** από τη
 * δεύτερη. Η μέτρηση πάνω στο **πραγματικό** μητρώο το ανέτρεψε:
 *
 * - **3.067 από τα 9.294** ονόματα οικισμών *(**33,0%**)* δένουν σε **ΑΛΛΟΝ** οικισμό.
 * - Αιτία: το `makeNameMatcher` απαντά `true` **και** για κοινό πρόθεμα 5 χαρακτήρων, και ο
 *   σαρωτής είναι `settlements.find(...)` — δηλαδή **σειρά αρχείου**. Η **ακριβής**
 *   αντιστοίχιση **δεν έχει προτεραιότητα**: νικά όποιος τυχαίνει πρώτος.
 * - **46,6%** των ονομάτων ζουν σε διφορούμενο κουβά prefix-5 *(μεγαλύτερος: **54** ονόματα)*.
 * - Και η αποσαφήνιση με Τ.Κ. — το σκαλί στο οποίο στηρίζεται το σχέδιο — βλέπει **μόνο
 *   949 από τους 13.272** οικισμούς *(**7,2%**)*.
 *
 * ⇒ Δεν έλειπε κλήση. **Η μηχανή που θα καλούσαμε ήταν χαλασμένη**, και η κλήση θα είχε
 * διαδώσει το σφάλμα σε **τρεις ακόμη** διαδρομές συρσίματος *(έργα · κτίρια · υποκατάστημα)*.
 *
 * 🔑 **ΓΙΑΤΙ «ΛΑΘΟΣ» ΕΙΝΑΙ ΧΕΙΡΟΤΕΡΟ ΑΠΟ «ΚΑΝΕΝΑ».** Το Ζ4γ κατήγγειλε ότι το υποκατάστημα
 * *«χάνει δήμο»* — κενή ιεραρχία. Αυτό εδώ δείχνει ότι η έδρα κρατά **σίγουρη λάθος
 * ταυτότητα**, που καμία οθόνη δεν ξεχωρίζει από σωστή. Το κενό ήταν το **λιγότερο** κακό.
 *
 * ⚠️ **Η ΑΓΚΥΡΑ ΤΡΕΧΕΙ ΤΟΝ ΠΡΑΓΜΑΤΙΚΟ HOOK ΠΑΝΩ ΣΤΟ ΠΡΑΓΜΑΤΙΚΟ ΑΡΧΕΙΟ** — το ίδιο
 * byte-προς-byte `public/data/administrative-hierarchy.json` που κατεβάζει ο φυλλομετρητής
 * *(πρότυπο: `utils/address/__tests__/administrative-hierarchy-data.test.ts`)*. Μεταγραφή του
 * αλγορίθμου μέσα στο test θα επαλήθευε **τη φαντασία μας**, όχι τον κώδικα *(N.18)* — και
 * είναι ακριβώς η παγίδα που το §4 του handoff ονομάζει *«ταυτολογία»*.
 *
 * @related lib/places/admin-identity (ο πυρήνας που αυτές οι άγκυρες απαιτούν)
 */

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { act, renderHook } from '@testing-library/react';

import { HIERARCHY_SOURCE } from '@/hooks/useAdministrativeHierarchy';
import { EMPTY_VALUE, type AddressWithHierarchyValue } from '../address-with-hierarchy-config';
import { useSettlementAutoFill } from '../use-settlement-autofill';

// =============================================================================
// ΤΟ ΜΗΤΡΩΟ — ΑΠΟ ΤΟΝ ΔΙΣΚΟ, ΑΠΟ ΤΗ ΔΗΜΟΣΙΑ ΔΙΑΔΡΟΜΗ
// =============================================================================

const HIERARCHY_FILE = JSON.parse(
  readFileSync(join(process.cwd(), 'public', 'data', 'administrative-hierarchy.json'), 'utf8'),
) as unknown;

beforeAll(async () => {
  global.fetch = jest.fn(async (input: RequestInfo | URL) => {
    const url = String(input);
    if (!url.endsWith('/data/administrative-hierarchy.json')) {
      throw new Error(`Απρόσμενο fetch: ${url}`);
    }
    return { json: async () => HIERARCHY_FILE } as Response;
  }) as typeof fetch;

  await HIERARCHY_SOURCE.load();
});

it('ο τεμπέλης φορτωτής γέμισε — αλλιώς κάθε επόμενο κριτήριο είναι κενό', () => {
  // ⚠️ Χωρίς αυτό, ένα μητρώο που δεν φόρτωσε θα έκανε τις άγκυρες **κόκκινες για λάθος
  //    λόγο** — ή, αν τις γυρίζαμε ανάποδα, **πράσινες χωρίς να κοιτάξει κανείς** (N.12).
  expect(HIERARCHY_SOURCE.peek()?.entities.size ?? 0).toBeGreaterThan(20_000);
});

// =============================================================================
// Ο ΟΔΗΓΟΣ — Ο ΠΡΑΓΜΑΤΙΚΟΣ HOOK, ΟΠΩΣ ΤΟΝ ΚΑΛΕΙ ΤΟ `AddressWithHierarchy`
// =============================================================================

/**
 * Τρέχει τον **δρόμο 2** (όνομα χωρίς ταυτότητα → πλήρης ιεραρχία) και επιστρέφει την
 * **τελευταία** τιμή που έφτασε στο `onChange` — δηλαδή ό,τι θα αποθηκευόταν.
 *
 * `null` = **ο hook δεν έγραψε τίποτα**, που είναι νόμιμη απάντηση («δεν ξέρω») και πρέπει
 * να ξεχωρίζει από «έγραψε κάτι λάθος».
 */
function autoFilled(seed: Partial<AddressWithHierarchyValue>): AddressWithHierarchyValue | null {
  const writes: AddressWithHierarchyValue[] = [];
  const current: AddressWithHierarchyValue = { ...EMPTY_VALUE, ...seed };

  renderHook(() =>
    useSettlementAutoFill({
      current,
      onChange: (next) => writes.push(next),
      disabled: false,
      isGreekAddress: true,
    }),
  );

  return writes.length > 0 ? writes[writes.length - 1] : null;
}

// =============================================================================
// Κ1 — Η ΑΚΡΙΒΗΣ ΑΝΤΙΣΤΟΙΧΙΣΗ ΝΙΚΑ ΠΑΝΤΑ
// =============================================================================

/**
 * 🔴 **Το δείγμα είναι πραγματικό και χειρότερο απ' ό,τι φαίνεται: οι δύο οικισμοί μοιράζονται
 * τον ΙΔΙΟ Τ.Κ.**, άρα ακόμη και η αποσαφήνιση «Τ.Κ. πρώτα» διαλέγει τον λάθος:
 *
 * | Όνομα | id | Τ.Κ. | θέση στο αρχείο | Δήμος |
 * |---|---|---|---|---|
 * | «Καλλίστη» | `settlement:0101020401` | **69100** | **33** | ΔΗΜΟΣ **ΚΟΜΟΤΗΝΗΣ** |
 * | «Καλλιθέα» | `settlement:0104020204` | **69100** | 164 | ΔΗΜΟΣ **ΜΑΡΩΝΕΙΑΣ - ΣΑΠΩΝ** |
 *
 * Το «καλλι» είναι κοινό στους 5 πρώτους χαρακτήρες, η «Καλλίστη» είναι **131 θέσεις
 * πιο πάνω**, και το `.find()` σταματά εκεί. Αποτέλεσμα: διεύθυνση στην **Καλλιθέα Ροδόπης**
 * αποθηκεύεται με **δήμο, δημοτική ενότητα και κοινότητα άλλου δήμου** — και το όνομα που
 * βλέπει ο άνθρωπος αλλάζει σιωπηλά σε «Καλλίστη».
 */
it('Κ1 · ακριβές όνομα + Τ.Κ. ⇒ Η ΑΚΡΙΒΗΣ οντότητα, όχι η πρώτη του αρχείου με κοινό πρόθεμα', () => {
  const filled = autoFilled({ settlementName: 'Καλλιθέα', postalCode: '69100' });

  expect(filled).not.toBeNull();
  expect(filled!.settlementName).toBe('Καλλιθέα');
  expect(filled!.settlementId).toBe('settlement:0104020204');
  expect(filled!.municipalityName).toContain('ΜΑΡΩΝΕΙΑΣ');
});

// =============================================================================
// Κ2 — ΔΙΦΟΡΟΥΜΕΝΟ ⇒ «ΔΕΝ ΞΕΡΩ». ΠΟΤΕ ΜΑΝΤΕΨΙΑ.
// =============================================================================
//
// ⚠️ **ΕΔΩ ΕΙΧΑ ΓΡΑΨΕΙ ΛΑΘΟΣ ΑΓΚΥΡΑ, ΚΑΙ ΤΗ ΣΒΗΝΩ ΕΠΙΤΗΔΕΣ ΜΕ ΣΗΜΕΙΩΣΗ.**
// Είχα βάλει κριτήριο που τάιζε «Δημοτική Ενότητα Θεσαλονίκης» σε **αυτόν** τον hook,
// υποθέτοντας ότι έτσι φτάνει η ετικέτα. **Μετρήθηκε ότι δεν φτάνει ποτέ**: το
// `app/api/geocoding/reverse/route.ts` περνά κάθε όνομα από `cleanPlaceName`, και
// `cleanPlaceName('Δημοτική Ενότητα Θεσαλονίκης')` → **`'Θεσαλονίκης'`**. Το πρόθεμα —
// δηλαδή **η δήλωση του επιπέδου** — σβήνεται **στον διακομιστή**.
//
// ⇒ Η ερώτηση «το πρόθεμα δηλώνει το επίπεδο;» είναι **αληθινή και κρίσιμη**, αλλά ζει
//   στο **σύνορο του route**, όχι εδώ. Άγκυρα: `lib/places/__tests__/admin-identity.test.ts`.
//   Μια άγκυρα που ταΐζει είσοδο **που η παραγωγή δεν παράγει** επικυρώνει τη φαντασία
//   μας — η ίδια παγίδα που το §4 του handoff ονομάζει «ταυτολογία».

// =============================================================================
// Κ3 — ΔΙΦΟΡΟΥΜΕΝΟ ⇒ «ΔΕΝ ΞΕΡΩ». ΠΟΤΕ ΜΑΝΤΕΨΙΑ.
// =============================================================================

/**
 * 🔴 **41 οικισμοί λέγονται «Καλλιθέα»** *(μετρημένο στο L8)*. Χωρίς Τ.Κ. **κανείς** δεν
 * μπορεί να πει ποιος — και σήμερα ο κώδικας **διαλέγει**: τον πρώτο του αρχείου με κοινό
 * πρόθεμα, δηλαδή τη «Καλλίστη» του ΔΗΜΟΥ ΚΟΜΟΤΗΝΗΣ.
 *
 * 🔑 Η σωστή απάντηση είναι **σιωπή στην ταυτότητα, όχι σιωπή στο όνομα**: το κείμενο που
 * έγραψε ο άνθρωπος μένει, η ταυτότητα δεν επινοείται, και τα οκτώ επίπεδα της φόρμας
 * περιμένουν τον άνθρωπο να αποσαφηνίσει. Ίδιο δόγμα με το `deepestContainingEntity`
 * (*«αντιφατικές αποδείξεις ⇒ `null`, δεν μαντεύουμε»*) και με το `NOT_STORED` του ADR-772.
 */
it('Κ3 · 41 ομώνυμες «Καλλιθέα» χωρίς Τ.Κ. ⇒ ΚΑΜΙΑ ταυτότητα — και ποτέ ξένο όνομα', () => {
  const filled = autoFilled({ settlementName: 'Καλλιθέα' });

  // Είτε δεν γράφτηκε τίποτα, είτε γράφτηκε **χωρίς** ταυτότητα — αλλά ποτέ άλλο όνομα.
  expect(filled?.settlementId ?? null).toBeNull();
  expect(filled?.settlementName ?? 'Καλλιθέα').toBe('Καλλιθέα');
  expect(filled?.municipalityName ?? '').not.toContain('ΚΟΜΟΤΗΝΗΣ');
});

// =============================================================================
// Κ4 — Η ΓΕΝΙΚΗ ΠΤΩΣΗ ΠΟΥ ΔΙΚΑΙΟΛΟΓΕΙ ΤΗ ΒΑΘΜΙΔΑ ΠΡΟΘΕΜΑΤΟΣ
// =============================================================================

/**
 * ⚠️ **Αυτή η άγκυρα φυλάει μια δυνατότητα που ΥΠΑΡΧΕΙ, ώστε η διόρθωση να μην τη σβήσει.**
 * Ο αρχικός λόγος του κανόνα «κοινό πρόθεμα» είναι γραμμένος στον κώδικα: το Nominatim
 * επιστρέφει **γενική** («Ελευθερίου») ενώ το μητρώο κρατά **ονομαστική** («Ελευθέριο»),
 * και η υποσυμβολοσειρά **αποτυγχάνει**. Ο κανόνας ήταν **σωστός στο κίνητρο** και
 * **επικίνδυνος στην εκτέλεση** — και η διόρθωση οφείλει να κρατήσει το πρώτο.
 */
it('Κ4 · γενική πτώση ΜΕΣΑ σε αποδεδειγμένο δήμο ⇒ δένει στην ονομαστική του μητρώου', () => {
  // 🔑 **Η εμβέλεια είναι το τίμημα της ασφάλειας, και είναι μετρημένο.** Ο παλιός κανόνας
  //    έτρεχε σε **όλη τη χώρα**, όπου **66,2%** των οικισμών μοιράζονται κουβά prefix-5 ⇒
  //    μάντευε. Μέσα σε δήμο η αμφισημία πέφτει στο **6,1%** και η πύλη μοναδικότητας αρκεί.
  //    Στη διαδρομή του συρσίματος ο δήμος αποδεικνύεται από τον διακομιστή (14/14), άρα η
  //    εμβέλεια **υπάρχει σχεδόν πάντα**.
  const filled = autoFilled({
    settlementName: 'Ελευθερίου Κορδελιού',
    municipalityId: 'municipality:0708',
  });

  expect(filled).not.toBeNull();
  expect(filled!.settlementId).toBe('settlement:0708020101');
  expect(filled!.settlementName).toBe('Ελευθέριο Κορδελιό');
  expect(filled!.municipalityName).toContain('ΚΟΡΔΕΛΙΟΥ');
});

it('🔒 Κ4β · η ΙΔΙΑ γενική ΧΩΡΙΣ εμβέλεια ⇒ καμία ταυτότητα (ποτέ μαντεψιά σε όλη τη χώρα)', () => {
  const filled = autoFilled({ settlementName: 'Ελευθερίου Κορδελιού', postalCode: '56334' });

  expect(filled?.settlementId ?? null).toBeNull();
});
