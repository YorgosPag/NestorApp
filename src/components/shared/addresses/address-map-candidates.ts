import type { ResolvedAddressFields } from '@/lib/geocoding/geocoding-types';

/** Μία γραμμή του καταλόγου, όπως τη ζωγραφίζει ο χάρτης. */
export interface AddressMapCandidate {
  /**
   * **Ταυτότητα** — αναλλοίωτη όσο ζει ο κατάλογος. Ο δεσμός λίστας⇄χάρτη ταξιδεύει
   * με αυτόν τον αριθμό.
   */
  readonly rank: number;
  /** **Σειρά στην οθόνη**, από το 1. Ο αριθμός που διαβάζει ο άνθρωπος πάνω στην πινέζα. */
  readonly position: number;
  readonly lat: number;
  readonly lng: number;
  /**
   * Η **σύντομη** ετικέτα της πινέζας — ο δήμος ή ο οικισμός, όχι ολόκληρη η γραμμή.
   *
   * ⚠️ Οι πραγματικές γραμμές του παρόχου έχουν **μετρημένα** 90-140 χαρακτήρες
   * *(«Αθηνάς, 1η Κοινότητα Περιστερίου, Δήμος Πετρούπολης, Περιφερειακή Ενότητα
   * Δυτικού Τομέα Αθηνών, Περιφέρεια Αττικής, …»)*. Πάνω σε χάρτη αυτό δεν είναι
   * ετικέτα — είναι **κουρτίνα** που σκεπάζει τις άλλες πινέζες.
   */
  readonly label: string;
  /** Ολόκληρη η γραμμή — για το `title`/`aria-label`, όπου το μήκος δεν κρύβει τίποτα. */
  readonly fullLabel: string;
  /** Απόσταση από την αφετηρία, σε μέτρα. `null` όταν δεν υπάρχει αφετηρία (D23). */
  readonly distanceM: number | null;
}

/**
 * Το ελάχιστο που χρειάζεται ο χάρτης από μια κατάταξη προτάσεων.
 *
 * Ταιριάζει **κατά κατασκευή** με το `SuggestionRanking` του συντάκτη, χωρίς να το
 * ονομάζει. Αν το `SuggestionRanking` αποκτήσει πεδία, εδώ δεν αλλάζει τίποτα· αν
 * **χάσει** κάποιο από αυτά, ο μεταγλωττιστής το λέει στο σημείο κλήσης.
 */
export interface RankedCandidateLike {
  readonly originalRank: number;
  readonly distanceFromCenterM: number | null;
  readonly candidate: {
    readonly lat: number;
    readonly lng: number;
    readonly displayName: string;
    readonly resolvedFields: ResolvedAddressFields;
  };
}

/**
 * Η **σύντομη** ετικέτα: ο πιο συγκεκριμένος τόπος που ξέρουμε.
 *
 * 🔑 Η σειρά προτίμησης δεν είναι αυθαίρετη — είναι από το **στενό προς το πλατύ**, γιατί
 * αυτό που ξεχωρίζει πέντε «Αθηνάς 5» μεταξύ τους είναι η **συνοικία** πριν από τον δήμο.
 * Τελευταία υποχώρηση είναι το πρώτο κομμάτι της γραμμής του παρόχου, που είναι η οδός:
 * άχρηστο για διάκριση, αλλά **ποτέ κενό** — και μια πινέζα χωρίς ετικέτα δεν λέει καν
 * ότι υπάρχει κάτι να διαβαστεί.
 */
function shortLabel(candidate: RankedCandidateLike['candidate']): string {
  const fields = candidate.resolvedFields;
  const preferred = fields.neighborhood?.trim()
    || fields.city?.trim()
    || fields.county?.trim()
    || fields.region?.trim();
  if (preferred) return preferred;
  const firstSegment = candidate.displayName.split(',')[0]?.trim();
  return firstSegment && firstSegment.length > 0 ? firstSegment : candidate.displayName;
}

/**
 * Οι υποψήφιοι όπως τους δείχνει ο χάρτης — **στη σειρά που τους δείχνει ο κατάλογος**.
 *
 * ⚠️ Ο καλών περνά τον πίνακα **ακριβώς όπως τον ζωγραφίζει το πάνελ**. Το `position`
 * παράγεται εδώ, από τη θέση στον πίνακα, ώστε ο αριθμός πάνω στην πινέζα και ο αριθμός
 * δίπλα στη γραμμή να **μην μπορούν** να διαφωνήσουν: είναι η ίδια πράξη, όχι δύο.
 *
 * ⛔ **Υποψήφιος χωρίς πεπερασμένη συντεταγμένη ΔΕΝ ζωγραφίζεται.** Δεν είναι αμυντικός
 * προγραμματισμός: το `NaN` σε `Marker` δεν ρίχνει τίποτα — τοποθετεί την πινέζα σε
 * **απροσδιόριστο** σημείο, δηλαδή δείχνει στον άνθρωπο μια διεύθυνση **κάπου**. Η
 * απουσία είναι τίμια· η τυχαία θέση όχι.
 */
export function toMapCandidates(
  rankings: readonly RankedCandidateLike[],
): AddressMapCandidate[] {
  const mapped: AddressMapCandidate[] = [];
  for (const ranking of rankings) {
    const { lat, lng } = ranking.candidate;
    if (!Number.isFinite(lat) || !Number.isFinite(lng)) continue;
    mapped.push({
      rank: ranking.originalRank,
      /*
        🔴 **ΜΕΤΡΑΕΙ ΟΣΑ ΜΠΗΚΑΝ, ΟΧΙ ΣΕ ΠΟΙΑ ΘΕΣΗ ΕΙΣΟΔΟΥ ΒΡΙΣΚΟΜΑΣΤΕ.** Ήταν
        `index + 1` και η άγκυρα το έπιασε: ένας απορριφθείς υποψήφιος άφηνε **κενό**
        στην αρίθμηση — η οθόνη θα έγραφε «2, 3» χωρίς «1», και ο άνθρωπος θα έψαχνε
        μια πινέζα «1» που δεν υπάρχει. Ο αριθμός εδώ είναι ό,τι **βλέπεις**, όχι ό,τι
        ήρθε.
      */
      position: mapped.length + 1,
      lat,
      lng,
      label: shortLabel(ranking.candidate),
      fullLabel: ranking.candidate.displayName,
      distanceM: ranking.distanceFromCenterM,
    });
  }
  return mapped;
}
