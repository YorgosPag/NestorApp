'use client';

/**
 * @fileoverview **ΤΟ ΣΗΜΑ ΚΑΙ ΤΟ ΒΕΛΟΣ ΤΟΥ** — η όψη των υποψηφίων, ADR-332 **D26**.
 * @related AddressMapCandidateLayer · lib/geo/offscreen-edge-indicator
 * @module components/shared/addresses/address-map-edge-indicator
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟ ΑΡΧΕΙΟ — ΚΑΙ ΓΙΑΤΙ ΑΥΤΟ ΕΙΝΑΙ Ο ΛΟΓΟΣ ΠΟΥ ΤΑ ΕΛΑΤΤΩΜΑΤΑ ΕΖΗΣΑΝ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο `AddressMapCandidateLayer` εισάγει `maplibre-gl`, που θέλει `URL.createObjectURL` —
 * **ανύπαρκτο στο jsdom**. Άρα ό,τι ζει μέσα του είναι **αδύνατο να αγκυρωθεί**, και
 * ακριβώς εκεί κρύφτηκαν δύο ελαττώματα που **524 πράσινες άγκυρες** δεν είδαν
 * *(μετρημένα ζωντανά 2026-09-05, βλ. παρακάτω)*.
 *
 * 🔑 **Η θεραπεία δεν είναι «γράψε κι άλλα test» — είναι να ΜΕΤΑΚΟΜΙΣΕΙ η απόφαση σε
 * μέρος όπου μπορεί να ερωτηθεί.** Εδώ μέσα δεν υπάρχει χάρτης: μόνο *«ποιο εικονίδιο»*,
 * *«με ποια χρώματα»*, *«πόσο χώρο δεσμεύει το κέλυφος»*. Και τα τρία ελέγχονται.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΕΛΑΤΤΩΜΑ 1 — ΤΟ ΒΕΛΟΣ ΕΔΕΙΧΝΕ **45° ΛΑΘΟΣ**, ΣΕ ΚΑΘΕ ΥΠΟΨΗΦΙΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `Navigation` του `lucide` **δεν δείχνει πάνω**: το πολύγωνό του είναι
 * `3 11 · 22 2 · 13 21 · 11 13`, με κορυφή στο **(22, 2)** και εγκοπή στο **(11, 13)** —
 * άξονας `(+11, −11)`, δηλαδή **βορειοανατολικά**. Με `rotate(angleDeg)` πάνω σε αυτό,
 * κάθε δείκτης έδειχνε **45° δεξιόστροφα** από τον στόχο του.
 *
 * Μετρημένο ζωντανά με `getScreenCTM()`, στην ίδια οθόνη, σε τέσσερις υποψηφίους:
 *
 * | Υποψήφιος | Σωστή φορά | Αποδόθηκε | Σφάλμα |
 * |---|---|---|---|
 * | Λάρισα *(ΒΔ)* | 328,2° | **13,2°** *(ΒΑ)* | +45,0° |
 * | Κύπρος *(ΑΝΑ)* | 110,1° | **155,1°** *(σχεδόν Ν)* | +45,0° |
 * | Καβάλα | 10,0° | 55,0° | +45,0° |
 * | Άνω Πόλη | 347,3° | 32,3° | +45,0° |
 *
 * ✅ **Η γεωμετρία ήταν σωστή· η ΟΨΗ ήταν λάθος.** Το `angleDeg` επαληθεύτηκε ανεξάρτητα
 * με προβολή Mercator *(Άγιοι Ανάργυροι: 168,2° υπολογισμένο vs 167,0° αποδοθέν)*.
 * Γι' αυτό καμία από τις 16 άγκυρες της γεωμετρίας δεν μπορούσε να το πιάσει: **έλεγχαν
 * τον αριθμό, και ο αριθμός ήταν σωστός.**
 *
 * Η διόρθωση είναι το `Navigation2` — πολύγωνο `12 2 · 19 21 · 12 17 · 5 21`, κορυφή
 * **(12, 2)** ακριβώς πάνω από την εγκοπή **(12, 17)**: άξονας **κατακόρυφος**. Δηλαδή
 * η σύμβαση που ο κώδικας **δήλωνε** ότι ίσχυε, γίνεται επιτέλους αληθινή.
 *
 * ⚠️ **ΚΑΙ ΓΙ' ΑΥΤΟ ΔΕΝ ΑΦΑΙΡΕΘΗΚΑΝ 45 ΜΟΙΡΕΣ.** Μια σταθερά αντιστάθμισης θα έδενε τη
 * σωστή εικόνα σε **αδήλωτο** χαρακτηριστικό ξένης βιβλιοθήκης: μια αναβάθμιση του
 * `lucide` που ισιώνει το εικονίδιο θα το χαλούσε **ξανά**, σιωπηλά. Το ερώτημα
 * *«δείχνει πάνω;»* το κάνει άγκυρα, διαβάζοντας το **ίδιο το πολύγωνο**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΕΛΑΤΤΩΜΑ 2 — ΤΟ ΒΕΛΟΣ ΗΤΑΝ **ΑΟΡΑΤΟ** ΣΤΟ ΣΚΟΤΕΙΝΟ ΘΕΜΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το βέλος ήταν `text-foreground/70` με `fill: none` — δηλαδή **περίγραμμα χωρίς
 * γέμισμα**, που δανείζεται φόντο από ό,τι βρεθεί από κάτω. Από κάτω του όμως δεν είναι
 * η εφαρμογή: είναι **ο χάρτης**, που είναι ανοιχτόχρωμος **και στα δύο θέματα**.
 *
 * Μετρημένο ζωντανά: `rgba(248, 250, 252, 0.7)` πάνω σε πλακίδιο OSM ⇒ λόγος αντίθεσης
 * **≈ 1,06 : 1**. Το WCAG 1.4.11 ζητά **≥ 3 : 1** για γραφικό που φέρει το νόημα — και
 * εδώ το βέλος **είναι** το νόημα. Σε φωτεινό θέμα ο ίδιος κανόνας δίνει ~6 : 1, γι'
 * αυτό το ελάττωμα ήταν αόρατο σε κάθε έλεγχο που δεν άλλαξε θέμα.
 *
 * 🔑 **Η ταμπέλα δίπλα του είχε ήδη τη λύση**: βάφει **δικό της** φόντο (`bg-background`).
 * Το βέλος όχι. Γι' αυτό εδώ τα δύο μοιράζονται **ΕΝΑ** δηλωμένο ζεύγος (`SIGN_PAINT`):
 * η απόκλιση δεν αποφεύγεται με προσοχή — **δεν μπορεί να γραφτεί**.
 */

import React from 'react';
import { Navigation2 } from 'lucide-react';
import { cn } from '@/lib/utils';
import {
  edgeIndicatorFor,
  type EdgeIndicator,
  type EdgeInsets,
  type ScreenPoint,
  type ScreenSize,
} from '@/lib/geo/offscreen-edge-indicator';

// =============================================================================
// ΤΟ ΧΡΩΜΑ — ένα ζεύγος, δύο επιφάνειες
// =============================================================================

/** Πώς βάφεται το σήμα σε μία κατάσταση: η ταμπέλα και το βέλος του, **μαζί**. */
export interface SignPaint {
  /** Ο αριθμημένος κύκλος. */
  readonly badge: string;
  /** Το βέλος — `fill-*` επειδή αλλιώς δεν έχει καθόλου επιφάνεια. */
  readonly arrow: string;
}

/**
 * Τα **δύο** δηλωμένα ζεύγη επιφάνειας/μελανιού του θέματος, και τίποτε άλλο.
 *
 * ⚠️ Οι κλάσεις είναι γραμμένες **ολόκληρες**, ποτέ συναρμολογημένες από κομμάτια: ο
 * Tailwind σαρώνει πηγαίο κείμενο, και μια κλάση που χτίζεται σε χρόνο εκτέλεσης
 * *(`` `bg-${token}` ``)* απλώς **δεν παράγεται** — θα έβγαινε άχρωμο σήμα.
 */
export const SIGN_PAINT: Readonly<Record<'resting' | 'highlighted', SignPaint>> = {
  resting: {
    badge: 'border-dashed border-foreground/70 bg-background text-foreground',
    arrow: 'fill-background text-foreground',
  },
  highlighted: {
    badge: 'border-solid border-background bg-foreground text-background',
    arrow: 'fill-foreground text-background',
  },
};

// =============================================================================
// Ο ΧΩΡΟΣ — τι δεσμεύει το κέλυφος του χάρτη
// =============================================================================

/**
 * Περιθώριο από την ακμή για την **ορατότητα**: μια πινέζα πιο μέσα από αυτό είναι
 * οπτικά κομμένη, άρα δεν την έχει δει κανείς. **Ο μισός δείκτης.**
 */
export const EDGE_INSET_PX = 24;

/**
 * Το «Δες όλες τις πιθανές τοποθεσίες», όπως **πράγματι** κάθεται: `bottom-3` και ύψος
 * 30 px *(`py-1.5` + `text-xs`)*, μετρημένο στην οθόνη.
 *
 * ⚠️ **Το πλάτος του λείπει επίτηδες**: εξαρτάται από τη μετάφραση *(213 px στα ελληνικά)*
 * και θα άλλαζε με τη γλώσσα. Η δέσμευση είναι **κατακόρυφη ζώνη**, άρα ισχύει σε κάθε
 * γλώσσα — και δεν χρειάζεται κανείς να θυμάται να την ξαναμετρήσει.
 */
export const FIT_BUTTON_BOX = { bottomPx: 12, heightPx: 30 } as const;

/** Το σήμα στη **μεγαλύτερη** κατάστασή του: `h-8` (32) με `scale-110` ⇒ ~36 px. */
export const SIGN_MAX_HEIGHT_PX = 36;

/** Ανάσα ανάμεσα στο σήμα και στο κουμπί — αρκετή ώστε να μη διαβάζονται ως ένα πράγμα. */
export const SIGN_CLEARANCE_PX = 6;

/**
 * Πού **επιτρέπεται να καθίσει** ο δείκτης. Η κάτω πλευρά δεσμεύεται ολόκληρη, επειδή
 * όλο το κέλυφος του χάρτη ζει εκεί: το «δες τα όλα» κεντρικά, το «Βρες τη θέση μου»
 * δεξιά, η απόδοση του OpenStreetMap δίπλα του.
 *
 * 🔑 **Υπολογίζεται, δεν γράφεται.** Ένα καρφωμένο `66` θα ξεχνούσε γιατί είναι 66 την
 * πρώτη φορά που κάποιος αλλάξει το `bottom-3` — και η άγκυρα ελέγχει την **ίδια σχέση**,
 * όχι τον αριθμό.
 */
export const EDGE_PLACEMENT_INSETS: EdgeInsets = {
  top: EDGE_INSET_PX,
  right: EDGE_INSET_PX,
  bottom:
    FIT_BUTTON_BOX.bottomPx +
    FIT_BUTTON_BOX.heightPx +
    SIGN_CLEARANCE_PX +
    SIGN_MAX_HEIGHT_PX / 2,
  left: EDGE_INSET_PX,
};

/**
 * Ο δείκτης ενός υποψήφιου — **με τα περιθώρια αυτής της οθόνης ήδη μέσα**.
 *
 * 🔴 **ΓΙΑΤΙ ΥΠΑΡΧΕΙ ΑΥΤΟ ΤΟ ΠΕΡΙΤΥΛΙΓΜΑ, ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΚΑΛΛΩΠΙΣΜΟΣ.** Χωρίς αυτό, ο
 * καλών έπρεπε να **θυμηθεί** να περάσει το `EDGE_PLACEMENT_INSETS` — δηλαδή ακριβώς η
 * παράμετρος που ο επόμενος ξεχνά *(D26, «ΜΗΝ» #4)*. Και το χειρότερο: η άγκυρα θα
 * δοκίμαζε τη **σταθερά**, ενώ ο `AddressMapCandidateLayer` — που **δεν εκτελείται σε
 * jsdom** — θα μπορούσε να την έχει σταματήσει να την περνά. Πράσινη άγκυρα σε σκέλος
 * που δεν τρέχει *(«ΜΗΝ» #2)*, μετρημένο σε **μετάλλαξη**: η παράλειψη έμενε πράσινη.
 *
 * Έτσι, η άγκυρα και η οθόνη καλούν **την ίδια συνάρτηση**.
 */
export function edgeIndicatorForCandidate(
  target: ScreenPoint,
  size: ScreenSize,
): EdgeIndicator | null {
  return edgeIndicatorFor(target, size, EDGE_INSET_PX, EDGE_PLACEMENT_INSETS);
}

