export interface CandidateBadgeProps {
  readonly position: number;
  readonly highlighted: boolean;
}

/**
 * Ο αριθμημένος κύκλος. **Διάστικτος** όσο είναι πρόταση· **συμπαγής και μεγαλύτερος**
 * όταν είναι η τονισμένη — δύο κανάλια πριν καν το χρώμα *(CHECK 3.41, WCAG 1.4.1)*.
 */
export function CandidateBadge({ position, highlighted }: CandidateBadgeProps) {
  return (
    <span
      className={cn(
        'flex items-center justify-center rounded-full font-semibold tabular-nums border-2',
        'transition-transform duration-150 shadow-md',
        highlighted ? 'h-8 w-8 text-sm scale-110' : 'h-6 w-6 text-xs',
        highlighted ? SIGN_PAINT.highlighted.badge : SIGN_PAINT.resting.badge,
      )}
    >
      {position}
    </span>
  );
}

export interface EdgeIndicatorArrowProps {
  /** Μοίρες **δεξιόστροφα από το πάνω** — η σύμβαση του `edgeIndicatorFor`. */
  readonly angleDeg: number;
  readonly highlighted: boolean;
}

/**
 * Το βέλος προς τον στόχο.
 *
 * ⚠️ **Η περιστροφή είναι ΑΜΕΣΗ, χωρίς αντιστάθμιση** — και αυτό είναι απαίτηση προς το
 * εικονίδιο, όχι υπόθεση: το `Navigation2` δείχνει **πάνω** στη φυσική του θέση, και το
 * φυλάει άγκυρα που διαβάζει το ίδιο του το πολύγωνο.
 */
export function EdgeIndicatorArrow({ angleDeg, highlighted }: EdgeIndicatorArrowProps) {
  return (
    <Navigation2
      aria-hidden="true"
      className={cn(
        'h-3.5 w-3.5 shrink-0 drop-shadow',
        highlighted ? SIGN_PAINT.highlighted.arrow : SIGN_PAINT.resting.arrow,
      )}
      /*
        🔑 **Η ΜΟΝΑΔΙΚΗ ΕΞΑΙΡΕΣΗ ΣΤΟΝ N.3, ΚΑΙ ΕΙΝΑΙ Η ΔΗΛΩΜΕΝΗ.** Η τιμή είναι γωνία
        παραγόμενη σε χρόνο εκτέλεσης από την προβολή του χάρτη· δεν υπάρχει κλάση
        Tailwind που να την εκφράζει, και μια γεννήτρια για 360 γωνίες θα ήταν χειρότερη
        από το πρόβλημα. Ίδιο precedent, ίδια αιτιολόγηση: `FloatingPanel.tsx:268`.
      */
      style={{ transform: `rotate(${angleDeg}deg)` }}
    />
  );
}
