import React from 'react';

import { useAuth } from '@/auth/hooks/useAuth';
import { useTranslation } from '@/i18n/hooks/useTranslation';
import type { ListingCustody } from '@/lib/owner-property/listing-custody';
import { hasOrganization } from '@/lib/routes/landing';

const NS = 'property-market';
const K = `${NS}:custody.personal`;

/**
 * **Η δήλωση χώρου** — ή `null` όταν δεν υπάρχει τίποτα να διευκρινιστεί.
 *
 * Δύο **ανεξάρτητες** συνθήκες, και οι δύο απαραίτητες:
 *
 * | συνθήκη | γιατί |
 * |---|---|
 * | `custody === 'personal'` | στη ροή **εντολής** η αγγελία ανήκει **όντως** στο γραφείο — η δήλωση θα ήταν **ψευδής** |
 * | `hasOrganization(…)` | ο πολίτης και ο **αυτόνομος** δεν έχουν δεύτερο χώρο — η δήλωση θα ήταν **θόρυβος** |
 *
 * ⚠️ **`aside` και όχι `div`**: είναι **παράπλευρη** πληροφορία για το κυρίως
 * περιεχόμενο *(τη φόρμα)*, όχι μέρος της ροής συμπλήρωσης — και ο αναγνώστης
 * οθόνης το ανακοινώνει ως complementary landmark, δηλαδή προσπερνιέται από όποιον
 * το έχει ήδη διαβάσει. Ένα `div` θα ήταν σωστό οπτικά και **βουβό** δομικά (N.4).
 *
 * @param custody Ο χώρος που θα γράψει **η πόρτα αυτής της φόρμας**. Δηλώνεται από
 *   τον καλούντα και είναι **υποχρεωτικός**: μια φόρμα που δεν ξέρει σε ποιον χώρο
 *   γράφει δεν επιτρέπεται να **μεταγλωττιστεί**, πόσο μάλλον να αποδοθεί.
 */
export function PersonalCustodyNotice({
  custody,
}: {
  readonly custody: ListingCustody['kind'];
}): React.ReactElement | null {
  const { t } = useTranslation([NS]);
  const { user } = useAuth();

  if (custody !== 'personal') return null;
  if (!hasOrganization({ companyId: user?.companyId })) return null;

  return (
    <aside className="flex flex-col gap-1 rounded-md border border-border bg-muted/30 p-4">
      <p className="text-sm font-semibold text-foreground">{t(`${K}.title`)}</p>
      <p className="text-sm text-muted-foreground">{t(`${K}.body`)}</p>
      <p className="text-sm text-muted-foreground">{t(`${K}.brokered`)}</p>
    </aside>
  );
}
