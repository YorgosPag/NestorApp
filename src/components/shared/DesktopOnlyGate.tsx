'use client';

/**
 * @fileoverview **Η ΠΥΛΗ ΤΗΣ Α8** — η σύνταξη δεν ταξιδεύει σε στενή οθόνη.
 * @related ADR-777 §7 (Α8 · Α19) · §11.6 · SPEC-777D · hooks/media/useViewportClass.ts
 * @module components/shared/DesktopOnlyGate
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 «ΜΟΝΟ DESKTOP» ΕΙΝΑΙ ΓΕΓΟΝΟΣ **BYTES**, ΟΧΙ ΚΑΝΟΝΑΣ CSS
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Τρία στρώματα, και **κανένα δεν είναι `hidden`**:
 *
 * 1. **Ξεχωριστή διαδρομή** (`/demands/new`, `/offers/new`). Το route-level code
 *    splitting του App Router είναι **αυτόματο** — τεκμηριωμένο: *«Next.js
 *    automatically creates a separate JavaScript bundle for each route … only the
 *    JavaScript required for that page is downloaded»*. Όποιος δεν την ανοίγει,
 *    **δεν κατεβάζει τίποτα**.
 * 2. **Δυναμική εισαγωγή** στον καλούντα. Ακόμη κι όποιος **ανοίξει** τη διαδρομή από
 *    κινητό (πληκτρολογημένη διεύθυνση · κοινοποιημένος σύνδεσμος) δεν κατεβάζει τη
 *    φόρμα: το `next/dynamic` τη ζητά **μόνο** όταν η μέτρηση πει `wide`.
 * 3. **Τρίτη κατάσταση στη μέτρηση** ({@link useViewportClass}). Χωρίς αυτήν, το
 *    στρώμα 2 θα ήταν **διακοσμητικό**: ένα `boolean` που ξεκινά `false` σημαίνει
 *    «ευρεία» στο πρώτο καρέ, η εισαγωγή ξεκινά, και **μια εισαγωγή που ξεκίνησε δεν
 *    ακυρώνεται**. Τα bytes θα είχαν φύγει πριν το `useEffect` πει «στενή».
 *
 * 🏆 **Το πρότυπο είναι το BIMx** (Α8, §18): ο θεατής είναι **ΑΛΛΟ ΠΡΟΪΟΝ**, όχι
 * απλοποιημένη έκδοση της σύνταξης. Άρα η στενή οθόνη **δεν** παίρνει μικρότερη
 * φόρμα — παίρνει **γραπτή εξήγηση** και τον δρόμο προς ό,τι *μπορεί* να κάνει εδώ.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΚΟΙΝΟ: **ΔΥΟ ΦΟΡΜΕΣ ΜΕ ΤΗΝ ΙΔΙΑ ΑΠΑΙΤΗΣΗ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η **Α9** (ζήτηση) και η **Α14** (προσφορά) υπακούν **και οι δύο** στην Α8. Ο
 * μηχανισμός —τρεις καταστάσεις, δυναμική εισαγωγή, ειδοποίηση— είναι **ταυτόσημος**·
 * διαφέρει **μόνο το κείμενο και ο δρόμος επιστροφής**. Δεύτερη γραφή θα ήταν κλώνος
 * που μπλοκάρει το **CHECK 3.28** (N.0.2 — *«πρώτα φτιάξε το SSoT»*).
 */

import React from 'react';
import Link from 'next/link';

import { useTranslation } from '@/i18n/hooks/useTranslation';
import { useViewportClass } from '@/hooks/media/useViewportClass';

const NS = 'property-market';

/**
 * Τι *μπορεί* να κάνει εδώ ο άνθρωπος με στενή οθόνη — **ποτέ σκέτη άρνηση**.
 *
 * ⚠️ Και τα τρία κείμενα είναι **υποχρεωτικά**: ένα «δεν γίνεται εδώ» χωρίς εξήγηση
 * και χωρίς έξοδο είναι αδιέξοδο. Η Α8 δεσμεύτηκε σε **γραπτή εξήγηση**.
 */
export function DesktopOnlyNotice({
  keyBase,
  backHref,
}: {
  /**
   * Η ρίζα του λεξιλογίου, π.χ. `demand` ή `offer`. Από αυτήν παράγονται **και τα
   * τέσσερα** κλειδιά (`title` · `body` · `what` · `back`).
   *
   * 🔴 **ΕΝΑ όρισμα και όχι τέσσερα, και το ζήτησε το CHECK 3.28.** Γραμμένα ως
   * τέσσερις συμβολοσειρές, οι δύο πύλες (ζήτηση · προσφορά) είχαν **ταυτόσημες 8
   * γραμμές** κλήσης — κλώνος που η πύλη μπλόκαρε **μέσα στο ίδιο commit**, ακριβώς
   * όπως στην Α9 με το `ToggleOption`.
   *
   * 🔑 Και είναι **καλύτερο ανεξάρτητα από την πύλη**: το «ποια τέσσερα κείμενα
   * χρειάζεται μια ειδοποίηση Α8» αποφασίζεται **εδώ**, μία φορά. Με τέσσερα
   * ορίσματα, μια πέμπτη πρόταση αύριο θα έπρεπε να τη θυμηθεί **κάθε** καλών.
   */
  keyBase: string;
  backHref: string;
}): React.ReactElement {
  const { t } = useTranslation([NS]);
  const K = `${NS}:${keyBase}.desktopOnly`;

  return (
    <section className="flex flex-col gap-3 rounded-md border border-border bg-card p-4">
      <h1 className="text-xl font-semibold text-foreground">{t(`${K}.title`)}</h1>
      <p className="text-sm text-foreground">{t(`${K}.body`)}</p>
      <p className="text-sm text-muted-foreground">{t(`${K}.what`)}</p>
      <nav>
        <Link
          href={backHref}
          className="inline-block rounded-md border border-border px-4 py-2 font-medium text-foreground"
        >
          {t(`${K}.back`)}
        </Link>
      </nav>
    </section>
  );
}

/**
 * **Η πύλη.** Ζωγραφίζει τη σύνταξη μόνο σε ευρεία οθόνη.
 *
 * ⚠️ **Το `wide` είναι ΣΥΝΑΡΤΗΣΗ, όχι στοιχείο**, και δεν είναι στιλιστικό: το
 * όρισμα αποτιμάται στον καλούντα, οπότε ένα έτοιμο στοιχείο θα σήμαινε ότι ο γονέας
 * **αγγίζει** το δυναμικά εισαγόμενο component σε κάθε απόδοση — και η μόνη εγγύηση
 * ότι δεν θα ζητηθεί ποτέ σε κινητό θα ήταν η συμπεριφορά της βιβλιοθήκης. Με θunk,
 * η εγγύηση είναι **ροή ελέγχου**.
 */
export function DesktopOnlyGate({
  wide,
  narrow,
}: {
  wide: () => React.ReactNode;
  narrow: React.ReactNode;
}): React.ReactElement {
  const viewport = useViewportClass();

  return (
    <main className="mx-auto flex w-full max-w-3xl flex-1 flex-col gap-4 p-6">
      {/*
        🔴 Το `measuring` ζωγραφίζει **τίποτα**, όχι τη φόρμα και όχι την ειδοποίηση.
        Και τα δύο θα ήταν ισχυρισμός για κάτι που ακόμη δεν ξέρουμε: το πρώτο στέλνει
        τα bytes, το δεύτερο λέει «δεν γίνεται» σε άνθρωπο με οθόνη 27 ιντσών. Η μία
        στιγμή κενού είναι ο **μόνος** ειλικρινής καρές.
      */}
      {viewport === 'wide' && wide()}
      {viewport === 'narrow' && narrow}
    </main>
  );
}
