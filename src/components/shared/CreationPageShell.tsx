'use client';

/**
 * @fileoverview **Η ΣΕΛΙΔΑ ΔΗΜΙΟΥΡΓΙΑΣ** — ένα κέλυφος για τις δύο φόρμες (ζήτηση · προσφορά), σε **κάθε** πλάτος.
 * @related ADR-900 §8 #3 · ADR-777 §7 (Α8 · Α9 · Α14 — η Α8 **περιορίστηκε** στη σύνταξη σχεδίου, 2026-10-02)
 * @module components/shared/CreationPageShell
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΑΝΤΙΚΑΤΕΣΤΗΣΕ ΤΟ `DesktopOnlyGate` (2026-10-02)
 * ────────────────────────────────────────────────────────────────────────────
 * Η Α8 γράφτηκε για τη **σύνταξη σχεδίου** (2D/3D, υλικά, διαμορφωτής) με πρότυπο το BIMx: ο θεατής στο
 * κινητό είναι **άλλο προϊόν**. Η Α14 τη μετέφερε στη φόρμα **προσφοράς** χωρίς δικό της επιχείρημα — και η
 * φόρμα είναι απλά πεδία, ένας χάρτης και φωτογραφίες. Οι μεγάλοι το κάνουν από το κινητό: η idealista
 * καταχωρίζει **από την εφαρμογή** (`publicar anuncio`), η Zillow δέχεται αγγελία ιδιοκτήτη από το app. Ο
 * αγοραστής ψάχνει κυρίως από κινητό — και η ζήτησή του ήταν η **μόνη** πράξη που του αρνιόμασταν εκεί.
 *
 * Άρα **μία** φόρμα, responsive, και κανένα «γίνεται από υπολογιστή». Τα **bytes** μένουν σωστά χωρίς την
 * πύλη: ξεχωριστή διαδρομή (route-level splitting του App Router) + δυναμική εισαγωγή της φόρμας στον
 * καλούντα — όποιος δεν ανοίγει τη σελίδα δεν κατεβάζει τίποτα.
 *
 * 📱 **Τα δύο κινητά ζητήματα λύθηκαν στη ρίζα τους, όχι εδώ**: ο χάρτης δεν κλέβει την κύλιση
 * (`lib/maps/use-cooperative-gestures.ts`, μέσα στο `PlaceMap`)· οι φωτογραφίες ανοίγουν το φύλλο του
 * λειτουργικού («Κάμερα / Συλλογή») με σκέτο `accept` — **χωρίς** `capture`, που θα **επέβαλλε** κάμερα και
 * θα έκοβε τη συλλογή, όπου ζουν οι φωτογραφίες του σπιτιού. **Καμία** συμπίεση στον πελάτη: το πρωτότυπο
 * ανεβαίνει με επανάληψη (resumable), τα παράγωγα τα φτιάχνει ο διακομιστής (ADR-899).
 */

import React from 'react';

import { useTranslation } from '@/i18n/hooks/useTranslation';
import { PageLoadingState } from '@/core/states';

/**
 * Η σελίδα. **Ένα** `<main>`: ό,τι ισχύει πριν τη φόρμα (`lead`, π.χ. «δείτε πρώτα αν υπάρχει ενδιαφέρον»)
 * ζει **μέσα** του — δεύτερο `main` δίπλα θα έσπαγε τα ορόσημα.
 *
 * 📱 `px-4` στο κινητό (ο κανόνας των 16px της εφαρμογής), `p-6` από `sm`: το περιθώριο της επιφάνειας
 * εργασίας στοιχίζει σε στενή οθόνη ~10% του πλάτους χωρίς να δίνει τίποτα.
 */
export function CreationPageShell({
  lead,
  children,
}: {
  readonly lead?: React.ReactNode;
  readonly children: React.ReactNode;
}): React.ReactElement {
  return (
    <main className="mx-auto flex w-full max-w-3xl flex-1 flex-col gap-4 px-4 py-6 sm:p-6">
      {lead}
      {children}
    </main>
  );
}

/**
 * Το καρέ όσο κατεβαίνει η φόρμα (`next/dynamic` → `loading`). Λέει **τι** περιμένουμε — όχι κενό, που στο
 * αργό δίκτυο κινητού διαβάζεται «χάλασε».
 */
export function CreationFormLoading(): React.ReactElement {
  const { t } = useTranslation('common');
  return <PageLoadingState message={t('loading.form')} layout="contained" />;
}
