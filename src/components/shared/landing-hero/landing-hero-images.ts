/**
 * @fileoverview **Οι εικόνες των ηρώων** — ένας πίνακας για τον κόμβο και τις ακτίνες του
 * (ADR-777 §8.79 · §8.82).
 * @module components/shared/landing-hero/landing-hero-images
 *
 * 🖼️ **Προδιαγραφή, κοινή για όλες:** 2400×1200 (2:1), το θέμα στο **δεξί** τρίτο
 * (`object-right`: στο κινητό μένει ορατό), ήρεμο το αριστερό όπου κάθονται τίτλος και
 * πλαίσιο, **καθόλου κείμενο** μέσα στην εικόνα. JPG mozjpeg q86 — το `next/image` παράγει
 * AVIF/WebP σε κάθε `deviceSizes`.
 *
 * ⚠️ **Διαδρομές, όχι στατικά imports — επίτηδες.** Όσο ένα αρχείο λείπει η σελίδα μένει
 *    **λειτουργική**: `alt=""` ⇒ κανένα σπασμένο εικονίδιο, και το `bg-muted` + το σκούρο
 *    στρώμα του ήρωα κρατούν το κάδρο και την αντίθεση του λευκού κειμένου.
 *
 * ⚠️ **Το `.gitignore` έχει `*.jpg`** (στιγμιότυπα οθόνης) — το `!public/**\/*.jpg` το
 *    αναιρεί. Κάθε νέο αρχείο: `git check-ignore -v <διαδρομή>` (§8.79.5).
 *
 * 🔑 **Ένας πίνακας, όχι σταθερά ανά σελίδα**: η αρχική μένει **κόμβος με ΜΙΑ εικόνα** —
 *    η καρτέλα είναι φίλτρο, όχι προορισμός (μετρημένο σε Spitogatos/idealista, §8.79).
 *    Νέα εικόνα σημαίνει νέα **ακτίνα**, και φαίνεται εδώ σε μία γραμμή.
 *
 * 🌗 **ΜΕΡΑ ΚΑΙ ΓΑΛΑΖΙΑ ΩΡΑ, ΑΝΑ ΘΕΜΑ (§8.81).** Ο ήρωας είναι **ατμόσφαιρα της διεπαφής**,
 *    όχι περιεχόμενο αγγελίας ⇒ επιτρέπεται να ακολουθεί το θέμα: `day` στο φωτεινό,
 *    `dusk` στο σκοτεινό. Η `dusk` είναι η **ίδια σκηνή, ίδιο κάδρο** — «έπεσε το βράδυ»,
 *    όχι «άλλαξε ιστότοπος». Γαλάζια ώρα, **ποτέ** μαύρη νύχτα.
 *    ⛔ **Οι φωτογραφίες ακινήτων ΔΕΝ αλλάζουν ποτέ με το θέμα** — είναι αυθεντικό περιεχόμενο.
 *    ⚠️ Απούσα `dusk` ⇒ η `day` και στα δύο θέματα (η ακτίνα μένει λειτουργική μέχρι να
 *    φτιαχτεί η βραδινή της).
 */
export interface LandingHeroImage {
  /** Φωτεινό θέμα. */
  readonly day: string;
  /** Σκοτεινό θέμα — η ίδια σκηνή στη γαλάζια ώρα. */
  readonly dusk?: string;
  /**
   * Πού κάθεται **κάθετα** το θέμα (κοινό για `day`/`dusk` — ίδιο κάδρο). Ο ήρωας είναι
   * φαρδύτερος από 2:1 σε μεγάλη οθόνη ⇒ το `object-cover` κόβει πάνω-κάτω· χωρίς δήλωση
   * κρατά το κέντρο. `'lower'` όταν το νόημα ζει χαμηλά (π.χ. σχέδια στο τραπέζι του `/pro`).
   */
  readonly focus?: 'center' | 'lower';
}

