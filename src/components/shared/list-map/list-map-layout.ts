/**
 * **Η γεωμετρία κάθε οθόνης λίστα ‖ χάρτης** (χαρτοφυλάκιο κατόχου `/offers`, κατάλογος επαγγελματιών
 * `/pro` — ADR-896· εξήχθη από το `owner-portfolio-layout.ts`): ένα σημείο για τον χάρτη, την κράτηση θέσης όσο φορτώνει και
 * τη διάταξη δίπλα-δίπλα (ADR-777 §8.71 · §8.75). Ξεχωριστό αρχείο **επίτηδες**: αν ζούσε στο
 * `OwnerPortfolioMap`, η κράτηση θέσης θα το εισήγαγε στατικά και θα κατέβαζε τη MapLibre πριν
 * ζητηθεί.
 *
 * 🔑 **Το ύψος το κατέχει ο ΠΕΡΙΕΚΤΗΣ, όχι ο χάρτης.** Χάρτης και κράτηση θέσης γεμίζουν (`h-full`)
 * το ίδιο κουτί — άρα η άφιξη του χάρτη δεν μετακινεί τίποτα (μηδέν CLS), σε όποια διάταξη κι αν
 * βρίσκεται. (Πριν από την §8.75 η κράτηση θέσης είχε μόνο το ύψος του `<figure>`, ενώ ο χάρτης
 * έφερνε από πάνω την υπόδειξη και από κάτω τη γραμμή «εκτός χάρτη»: μικρή μετατόπιση στην άφιξη.)
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΔΥΟ ΣΧΗΜΑΤΑ, ΜΙΑ ΑΥΘΕΝΤΙΑ ΓΕΩΜΕΤΡΙΑΣ (ADR-777 §8.84 · ADR-896 §4.5)
 * ────────────────────────────────────────────────────────────────────────────
 *
 * | | **σελίδα** — `ListMapSplit` (`/offers`, `/pro`) | **οθόνη** — `ListMapScreen` (`/search/results`) |
 * |---|---|---|
 * | τι κυλά | η **σελίδα**· ο χάρτης `sticky` | **τίποτα**: κάδρο κλειδωμένο στο παράθυρο, η λίστα κυλά στη στήλη της |
 * | ποιος κρίνει split | **JS**, στον **περιέκτη** (`LIST_MAP_SPLIT_MIN_REM`) | **CSS**, στο `md` (= `MOBILE_BREAKPOINT`) |
 * | αναλογία | πρωτεύουσα η **λίστα**: ≤ 55% (Redfin) | πρωτεύων ο **χάρτης**: λίστα ≤ 45% (Zillow) |
 * | στενό | καρτέλες Λίστα \| Χάρτης (`?view=map`) | **φύλλο πυθμένα 3 στάσεων** (SPEC-777D §26· το §26.1 απορρίπτει την εναλλαγή) |
 *
 * 🔑 **Δύο κατώφλια ≠ δύο απαντήσεις στο ίδιο ερώτημα (ADR-749).** Η σελίδα ζει **μέσα** σε κέλυφος
 * με πλαϊνή μπάρα, άρα «χωράω;» = πλάτος **περιέκτη**, που μόνο μετριέται. Η οθόνη δηλώνει
 * `data-shell-surface="bleed"`, άρα περιέκτης ≡ παράθυρο — και η ερώτηση απαντιέται **στο πρώτο
 * βάψιμο, από τον διακομιστή**, με CLS = 0 εκ κατασκευής (κεφαλή `ResultsSheet.tsx`). Μεταφορά της
 * οθόνης σε μέτρηση JS θα ξαναγεννούσε την αναδιάταξη «στήλες ⇄ επικάλυψη» μετά την ενυδάτωση.
 *
 * 🔑 **Δύο αναλογίες = δύο πρωταγωνιστές.** Στη σελίδα ο άνθρωπος **διαβάζει** τα δικά του (λίστα
 * πρώτα)· στην οθόνη αναζήτησης **εξερευνά** τον χώρο (χάρτης πρώτα). Ίδιες κλάσεις και στα δύο θα
 * έκαναν το ένα από τα δύο χειρότερο.
 */

/**
 * **Το κάδρο της οθόνης** (`ListMapScreen`): ένα DOM, δύο διατάξεις, **μόνο CSS**.
 * • στενό: χάρτης σε όλο το κουτί, η λίστα από πάνω ως φύλλο (`absolute inset-0` στο φύλλο).
 * • `md:` πλέγμα δύο στηλών, λίστα ‖ χάρτης.
 *
 * 🔴 `min-h-0 flex-1` και όχι ύψος παραθύρου: το κάδρο ζει **κάτω** από τη γραμμή φίλτρων, και
 * χωρίς `min-h-0` το flex item αρνείται να συρρικνωθεί ⇒ η εσωτερική κύλιση της λίστας σβήνει.
 * ⛔ Κανένα `grid-cols-1` / `lg:` (SPEC-777D §26.7 · άγκυρα `results-layout-authority` Α2): το
 * στενό **δεν** στοιβάζει, και το κατώφλι είναι **ένα**.
 */
export const LIST_MAP_SCREEN_FRAME =
  'relative min-h-0 flex-1 overflow-hidden md:grid md:grid-cols-[minmax(20rem,min(46rem,45%))_1fr]';

/**
 * **Το πάνελ του χάρτη στην οθόνη**: όλο το κουτί στο στενό (το φύλλο κάθεται από πάνω), στήλη στο `md`.
 *
 * `isolate`: ο χάρτης είναι **ξένος** κώδικας (Geo-Canvas/MapLibre) με δικά του εσωτερικά επίπεδα·
 * ένα δικό του στρώμα δεν επιτρέπεται να αναρριχηθεί πάνω από το φύλλο. Ο **περιορισμός** είναι
 * ανώτερος από το δάμασμα με αριθμό (CHECK 3.50) — ισχύει και μετά από αναβάθμιση της βιβλιοθήκης.
 */
export const LIST_MAP_SCREEN_MAP_PANE = 'absolute inset-0 isolate md:static';

/**
 * **Στοιβαγμένη διάταξη** (καρτέλα «Χάρτης»): αρκετό για να διαβάζονται σχέσεις μεταξύ σημαδιών,
 * ποτέ ολόκληρη η οθόνη — η σελίδα κυλά, και ένας χάρτης στο 100% θα «έπιανε» την κύλιση του τροχού.
 */
export const LIST_MAP_MAP_HEIGHT = 'h-[min(70vh,40rem)] min-h-80';

/**
 * **Το κατώφλι της διάταξης δίπλα-δίπλα, σε rem** — λίστα ≥ 28rem (η κάρτα του κατόχου — η φαρδύτερη από τις δύο — χωρά
 * εξώφυλλο + κείμενο) · κενό 1,5rem · χάρτης ≥ 22rem (αρκετός για σχέσεις μεταξύ σημαδιών).
 * Σε **rem**, ώστε να ακολουθεί το μέγεθος γραμματοσειράς του χρήστη (WCAG 1.4.4), και μετριέται
 * στον **περιέκτη**, όχι στο παράθυρο (`useContainerClass`).
 */
export const LIST_MAP_SPLIT_MIN_REM = 52;

/**
 * **Λίστα ‖ χάρτης.** Η λίστα κρατά το **ίδιο** μέτρο με τη στοιβαγμένη εκδοχή (το token
 * `--spacing-layout-measure-wide`, όχι δεύτερο «80ch»), αλλά ποτέ πάνω από το 55% — ώστε ο χάρτης
 * να μη στενεύει κάτω από το κατώφλι. Ο χάρτης παίρνει ό,τι περισσεύει (πρότυπο Redfin 55/45 ·
 * Airbnb ~50/50: λίστα αριστερά, χάρτης δεξιά).
 */
export const LIST_MAP_SPLIT_GRID =
  'grid grid-cols-[minmax(0,min(calc(var(--spacing-layout-measure-wide)*1ch),55%))_minmax(0,1fr)] items-start gap-6';

/**
 * **Το πάνελ του χάρτη στη διάταξη δίπλα-δίπλα**: κολλά στο παράθυρο ενώ κυλά η λίστα — το πρότυπο
 * Airbnb (`position: sticky`, κυλά **όλη** η σελίδα), που ταιριάζει στο κέλυφος χωρίς κλείδωμα
 * ύψους (`.shell-surface.json → viewportLocked`).
 *
 * ⚠️ Το `svh` εδώ **δεν** είναι «δεύτερη αυθεντία ύψους» (CHECK 3.63 Υ4): ένα sticky στοιχείο
 * αναφέρεται στην **περιοχή κύλισης**, όπως ένα `fixed` αναφέρεται στο παράθυρο. Η απόσταση από
 * τις άκρες είναι ο **ίδιος** κατακόρυφος ρυθμός του κελύφους (`--shell-block`), όχι νέος αριθμός.
 */
export const LIST_MAP_MAP_PANE =
  'sticky top-[var(--shell-block)] h-[calc(100svh_-_2_*_var(--shell-block))] min-h-80';

/**
 * **Η κράτηση θέσης της σελίδας όσο φορτώνει ο κατάλογος** (`ListMapPending`, ADR-896 §7Α.7).
 *
 * 🔴 **Μετρημένο στο `/pro` (CLS 0,0891):** στον πρώτο καρέ η θέση της λίστας ήταν μία γραμμή
 * «Φόρτωση…», οπότε το υποσέλιδο έκατσε μέσα στην οθόνη (y=842). Η άφιξη 4.000px καρτών το
 * έσπρωξε εκτός (y=4088) — και η μετατόπιση ορατού στοιχείου είναι ακριβώς ό,τι μετρά το CLS.
 *
 * 🔑 **ΤΟ ΙΔΙΟ ύψος με το πάνελ του χάρτη, όχι νέος αριθμός**: ό,τι φτάσει (διάταξη δίπλα-δίπλα,
 * καρτέλες ή μόνο λίστα) είναι τουλάχιστον τόσο ψηλό στην πρώτη οθόνη, άρα το υποσέλιδο ξεκινά
 * **ήδη** εκτός θέας και η άφιξη δεν μετακινεί τίποτα ορατό. Γραμμένο ως **ίδιο** literal με το
 * `LIST_MAP_MAP_PANE` — το Tailwind χρειάζεται ολόκληρη την κλάση στην πηγή, και ο κανόνας
 * «sticky ≡ περιοχή κύλισης» (CHECK 3.63 Υ4) ισχύει αυτούσιος: μία ερώτηση, «πόση πρώτη οθόνη;».
 * ⚠️ Μόνο **κράτηση**, ποτέ όριο: `min-h`, όχι `h` — η λίστα που φτάνει μπορεί να είναι ψηλότερη.
 */
export const LIST_MAP_PENDING = 'min-h-[calc(100svh_-_2_*_var(--shell-block))] overflow-hidden';

/**
 * **Οι ράγες του δείκτη άκρης** (ADR-777 §8.77): «η κάρτα που κοιτάς στον χάρτη είναι πιο πάνω /
 * πιο κάτω». Στην οθόνη 2 ο δείκτης κάθεται στο πλαίσιο του δοχείου κύλισης· εδώ κυλά **η σελίδα**,
 * άρα η άκρη είναι η άκρη του **παραθύρου** — μέσα στη στήλη της λίστας.
 *
 * 🔑 **Μηδενικό ύψος + `sticky`**: η ράγα κολλά στην άκρη του παραθύρου (στον **ίδιο** ρυθμό
 * `--shell-block` με το πάνελ του χάρτη) και ο δείκτης κρέμεται από αυτήν (`absolute`). Καταλαμβάνει
 * **μηδέν** χώρο στη ροή ⇒ η εμφάνισή του δεν μετακινεί καμία κάρτα (CLS 0), και το `sticky` τον
 * κρατά **μέσα στη στήλη** — χωρίς `fixed`, χωρίς μέτρηση πλάτους σε JavaScript.
 * `z-10`: η ίδια τοπική στρώση με τον δείκτη της οθόνης 2 — πάνω από τις κάρτες που ακολουθούν.
 */
export const LIST_MAP_EDGE_RAIL = {
  above: 'sticky top-[var(--shell-block)] z-10 h-0',
  below: 'sticky bottom-[var(--shell-block)] z-10 h-0',
} as const satisfies Record<'above' | 'below', string>;
