'use client';

import { ShellSurface } from '@/core/containers/ShellSurface';
import { useSemanticColors } from '@/ui-adapters/react/useSemanticColors';
import '@/lib/design-system';

interface MainContentBridgeProps {
  children: React.ReactNode;
}

/**
 * 🏛️ **Η ΕΠΙΦΑΝΕΙΑ ΤΟΥ ΠΕΡΙΕΧΟΜΕΝΟΥ** — ο ΕΝΑΣ ιδιοκτήτης του κενού (ADR-797).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΑΛΛΑΞΕ ΚΑΙ ΓΙΑΤΙ
 * ────────────────────────────────────────────────────────────────────────────
 * Μέχρι τις 2026-08-24 αυτό το `<main>` δήλωνε **μηδέν** οριζόντιο κενό — όπως
 * και οι τρεις κρίκοι από πάνω του. Μετρημένο: **86 από τις 104** σελίδες του
 * χώρου δεν δήλωναν κενό ούτε μόνες τους, οπότε το περιεχόμενο **ακουμπούσε**
 * την μπάρα. Δεν έλειπε κλάση — **έλειπε ο ιδιοκτήτης της ερώτησης**.
 *
 * Ο κανόνας που ακολουθούν όλα τα μεγάλα design systems είναι ο ίδιος:
 * *«outer spacing is a **layout** concern, not a component one»*, και ο layout
 * container είναι *«an **invisible** component … [that] controls the gutter
 * padding»* (Brad Frost). **Αυτό** είναι εκείνο το component.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ ΤΟ ΚΕΝΟ ΔΕΝ ΓΡΑΦΕΤΑΙ ΕΔΩ ΩΣ ΚΛΑΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 * Μια κλάση `px-6` θα ήταν **σκαλοπάτι**, και θα μετρούσε το **παράθυρο**. Η
 * μπάρα όμως διπλώνει `16rem → 3rem`: **208px** αλλαγή στο διαθέσιμο πλάτος
 * **με το παράθυρο ακίνητο**. Το κενό ζει στο `shell-surface.css` και
 * υπολογίζεται ρευστά πάνω στο **πραγματικό πλάτος αυτής της επιφάνειας** —
 * εκεί εξηγείται και γιατί **δεν** χρησιμοποιείται container query.
 *
 * Εδώ μένει **μόνο η δήλωση**: «αυτή είναι η επιφάνεια που παίρνει διάδρομο».
 *
 * ⚠️ **ΜΗΝ προσθέσεις `px-*`/`py-*` εδώ.** Θα ήταν δεύτερη αυθεντία δίπλα στην
 * πρώτη (ADR-749), και θα κέρδιζε κατά ειδικότητα χωρίς να το δει κανείς.
 *
 * ⚠️ **ΜΗΝ ξαναγράψεις το `data-shell-surface` εδώ με το χέρι** (ADR-797 ΦΑΣΗ Β).
 * Ο δείκτης ζει πλέον σε **ΕΝΑ** σημείο σε όλο το δέντρο — το
 * {@link ShellSurface} — και αυτό το component τον **παραδίδει** (`as="main"`).
 * Ήταν χειρόγραφος εδώ όσο ο μόνος καταναλωτής ήταν το κέλυφος· από τη στιγμή
 * που τον ζήτησαν **άλλες τέσσερις** γειτονιές, ένα attribute γραμμένο σε πέντε
 * αρχεία θα ήταν πέντε ευκαιρίες να ξεχαστεί — και η αστοχία του δεν σπάει
 * τίποτα ορατά: κάνει το κενό **σιωπηλά μηδέν**.
 *
 * ⚠️ **ΚΑΝΕΝΑ `measure` εδώ, και είναι απόφαση.** Το κέλυφος φιλοξενεί πίνακες,
 * λογιστική και τον καμβά DXF· ένα ταβάνι 80 χαρακτήρων θα τα κατέστρεφε. Το
 * μέτρο είναι **opt-in** ακριβώς γι' αυτόν τον λόγο.
 *
 * Σελίδα που θέλει **πλήρες πλάτος** (χάρτης, καμβάς) το δηλώνει η ίδια με
 * `data-shell-surface="bleed"` στη ρίζα της — δες `FullBleedSurface`.
 */
export function MainContentBridge({ children }: MainContentBridgeProps) {
  const colors = useSemanticColors();

  return (
    <ShellSurface
      as="main"
      className={`flex-1 overflow-y-auto overflow-x-hidden ${colors.bg.primary}/95 max-w-full`}
    >
      {children}
    </ShellSurface>
  );
}
