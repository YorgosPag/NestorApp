import type { MapRef } from 'react-map-gl/maplibre';

import { focusPresentation, type PlaceFocus } from '@/lib/geo/geocoding-focus';
import type { CameraFrame } from '@/types/geo/camera-frame';
import { useCameraFrame } from './use-camera-frame';

/**
 * **Η απάντηση του γεωκωδικοποιητή ως καρέ κάμερας** — και **μόνο** ως καρέ.
 *
 * ⚠️ Ο βαθμός βεβαιότητας συμμετέχει **έμμεσα**, μέσα από το `focusPresentation`: αυτός
 * επιλέγει το ζουμ όταν δεν υπάρχει έκταση. Το ίδιο το `uncertaintyMetres` **δεν
 * ταξιδεύει** — το φωτοστέφανο είναι δουλειά του `PlaceMap`, όχι της κάμερας.
 */
function frameOfFocus(focus: PlaceFocus | null): CameraFrame | null {
  if (focus === null) return null;
  const { frame } = focusPresentation(focus);
  return frame.kind === 'extent'
    ? { kind: 'extent', extent: frame.extent }
    : { kind: 'point', point: focus.point, zoom: frame.zoom };
}

/**
 * Κινεί την κάμερα όποτε αλλάζει η **απάντηση** — ποτέ σε κάθε απόδοση.
 *
 * @param mapRef — το `ref` του `<Map>`
 * @param ready — ο χάρτης φόρτωσε· πριν από αυτό κάθε `flyTo` πέφτει στο κενό
 * @param focus — η απάντηση του γεωκωδικοποιητή, ή `null` όταν δεν υπάρχει
 */
export function useFocusCamera(
  mapRef: React.RefObject<MapRef | null>,
  ready: boolean,
  focus: PlaceFocus | null,
): void {
  useCameraFrame(mapRef, ready, frameOfFocus(focus));
}
