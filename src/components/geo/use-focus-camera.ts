'use client';

/**
 * @fileoverview **Η ΚΑΜΕΡΑ ΑΚΟΛΟΥΘΕΙ ΤΗΝ ΑΠΑΝΤΗΣΗ** — το ένα σημείο που κινεί τον χάρτη.
 * @related lib/geo/geocoding-focus · components/geo/PlaceMap.tsx
 * @module components/geo/use-focus-camera
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Η ΒΛΑΒΗ ΠΟΥ ΤΟ ΓΕΝΝΗΣΕ — ΚΑΙ ΓΙΑΤΙ ΗΤΑΝ **ΑΟΡΑΤΗ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο άνθρωπος πάτησε «Εντοπισμός» για διεύθυνση **Θεσσαλονίκης** και ο χάρτης έδειχνε
 * **Πλατεία Ομονοίας** — μετρημένο 2026-09-02. Τρία ανεξάρτητα αίτια, στοιβαγμένα:
 *
 * 1. Ο εντοπισμός έγραφε το σημείο στη φόρμα και **δεν το έδινε σε κανέναν**.
 * 2. Το `center` του `PlaceChooser` υπήρχε ως prop και **κανείς δεν το περνούσε ποτέ**
 *    ⇒ έπεφτε πάντα στο `GEOGRAPHIC_CONFIG.DEFAULT_*` (37.9838, 23.7275 = Ομόνοια).
 * 3. 🔑 **ΚΑΙ ΑΝ ΚΑΠΟΙΟΣ ΤΟ ΕΠΕΡΝΕ, ΠΑΛΙ ΤΙΠΟΤΑ**: το `PlaceMap` το έδινε ως
 *    **`initialViewState`** — τιμή που το react-map-gl διαβάζει **μία φορά, στην
 *    προσάρτηση**. Ο χάρτης έχει ήδη γεννηθεί όταν πατιέται «Εντοπισμός».
 *
 * ⚠️ **Το (3) είναι το επικίνδυνο**, γιατί η προφανής διόρθωση του (1)+(2) — «πέρασε
 * το σημείο ως `center`» — θα ήταν **αλλαγή που μεταγλωττίζεται, περνά κάθε άγκυρα
 * απόδοσης, και δεν κάνει απολύτως τίποτα**. Γι' αυτό η κίνηση ζει σε **δικό της
 * αρχείο**: για να έχει όνομα, και να μπορεί να ελεγχθεί ότι **εκτελείται**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΤΟ ΠΡΟΤΥΠΟ, ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΓΝΩΜΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η τεκμηρίωση του react-map-gl λέει ρητά *«use `map.easeTo()` / `map.flyTo()` instead
 * of the older transition props»*, και ταυτόχρονα προειδοποιεί ότι οι **επιτακτικές**
 * κλήσεις αποκλίνουν από τα props. Η γραμμή εδώ είναι ρητή: **επιτακτική μόνο η
 * κίνηση της κάμερας** — μια πράξη με **διάρκεια**, που κανένα prop δεν εκφράζει —
 * και **δηλωτικό ό,τι ζωγραφίζεται** (πινέζα, κύκλος, περίγραμμα). Καμία γεωμετρία
 * δεν μπαίνει από εδώ.
 */

import { useEffect, useRef } from 'react';
import type { MapRef } from 'react-map-gl/maplibre';

import { focusPresentation, type PlaceFocus } from '@/lib/geo/geocoding-focus';

/**
 * Πόσο διαρκεί η μετάβαση.
 *
 * 🔑 **Κίνηση, όχι τηλεμεταφορά** — και ο λόγος είναι γνωστικός, όχι αισθητικός: ο
 * χάρτης που *πετάει* από την προηγούμενη θέση στη νέα διατηρεί τη **χωρική
 * συνέχεια**, ώστε ο άνθρωπος να καταλάβει ότι μετακινήθηκε **και πού**. Ένα ακαριαίο
 * πήδημα διαβάζεται ως «άλλαξε ο χάρτης», όχι ως «ταξίδεψα εκεί».
 */
const FLIGHT_MS = 900;

/**
 * Περιθώριο γύρω από την έκταση, σε εικονοστοιχεία — ώστε το αποτέλεσμα να μην
 * ακουμπά τα χείλη του πλαισίου.
 */
const FIT_PADDING = 48;

/**
 * **Το φρένο του `fitBounds`.**
 *
 * ⚠️ Χωρίς αυτό, μια πολύ **μικρή** έκταση (ένας δρόμος 40 μέτρων) θα ζουμάριζε στο
 * μέγιστο του χάρτη — προβολή που δείχνει **δύο κτίρια** και υπονοεί βεβαιότητα
 * κτιρίου, ενώ ο βαθμός λέει «δρόμος». Το όριο κρατά την προβολή **συνεπή με ό,τι
 * ισχυρίζεται η ένδειξη**: αν η ένδειξη είναι περιοχή, η κάμερα δεν πλησιάζει τόσο
 * ώστε να μοιάζει με σημείο. Η τεκμηρίωση του Nominatim δίνει το ίδιο ιδίωμα
 * (`maxzoom` δίπλα στο `fitBounds`).
 */
const AREA_MAX_ZOOM = 17;

/**
 * Κινεί την κάμερα όποτε αλλάζει η **απάντηση** — ποτέ σε κάθε απόδοση.
 *
 * @param mapRef — το `ref` του `<Map>`
 * @param ready — ο χάρτης φόρτωσε· πριν από αυτό κάθε `flyTo` πέφτει στο κενό
 * @param focus — η απάντηση του γεωκωδικοποιητή, ή `null` όταν δεν υπάρχει
 */
export function useFocusCamera(
  mapRef: React.RefObject<MapRef | null>,
  ready: boolean,
  focus: PlaceFocus | null,
): void {
  /**
   * 🔑 **ΓΙΑΤΙ ΤΑΥΤΟΤΗΤΑ ΚΑΤΑ ΤΙΜΗ, ΚΑΙ ΟΧΙ ΤΟ ΑΝΤΙΚΕΙΜΕΝΟ ΣΤΙΣ ΕΞΑΡΤΗΣΕΙΣ.**
   * Το `focus` είναι **νέο αντικείμενο σε κάθε απόδοση** του γονέα (χτίζεται από τιμές
   * της φόρμας). Στις εξαρτήσεις, θα ξανάτρεχε την πτήση σε **κάθε** πάτημα πλήκτρου —
   * ο χάρτης θα ζούσε σε μόνιμη κίνηση. Είναι το ίδιο σχήμα που ο `PlaceChooser`
   * τεκμηριώνει για το `settledRef` και που το `reference_firestore_reactivity_hub`
   * καταγράφει ως αιτία βρόχου (`selector ?? []`).
   *
   * ⚠️ Και **δεν αρκεί το σημείο**: δύο απαντήσεις μπορούν να μοιράζονται συντεταγμένες
   * και να διαφέρουν σε **βαθμό** (άρα σε προβολή *και* σε ένδειξη) — ίδιο σημείο,
   * άλλη αλήθεια.
   */
  const signature =
    focus === null
      ? null
      : `${focus.point.lat}:${focus.point.lng}:${focus.accuracy}:${
          focus.extent === undefined
            ? ''
            : `${focus.extent.south},${focus.extent.west},${focus.extent.north},${focus.extent.east}`
        }`;

  /**
   * ⚠️ **Η ΤΕΛΕΥΤΑΙΑ ΤΙΜΗ, ΔΙΑΒΑΣΜΕΝΗ ΤΗ ΣΤΙΓΜΗ ΤΗΣ ΠΤΗΣΗΣ.** Το `focus` λείπει
   * επίτηδες από τις εξαρτήσεις (δες παραπάνω)· ένα κλείσιμο πάνω σε παλιό αντικείμενο
   * θα πετούσε σε **προηγούμενη** απάντηση με τη σωστή υπογραφή — δηλαδή θα ήταν σωστό
   * και μπαγιάτικο ταυτόχρονα. Ίδιο ιδίωμα «*event-time read via getter, όχι snapshot*»
   * με τον κανόνα 2 της ADR-040.
   */
  const latest = useRef(focus);
  latest.current = focus;

  useEffect(() => {
    const map = mapRef.current;
    const current = latest.current;
    if (map === null || !ready || current === null) return;

    const presentation = focusPresentation(current);

    if (presentation.frame.kind === 'extent') {
      const { south, west, north, east } = presentation.frame.extent;
      // ⚠️ Το MapLibre θέλει **`[[δ, ν], [α, β]]`** — άλλη σειρά από του Nominatim.
      //    Η μετάφραση έγινε ήδη μία φορά στο σύνορο (`extractExtent`)· εδώ διαβάζονται
      //    **ονομαστικά** πεδία, ώστε καμία σιωπηρή σύμβαση σειράς να μη μεταφέρεται.
      map.fitBounds(
        [
          [west, south],
          [east, north],
        ],
        { padding: FIT_PADDING, maxZoom: AREA_MAX_ZOOM, duration: FLIGHT_MS },
      );
      return;
    }

    map.flyTo({
      center: [current.point.lng, current.point.lat],
      zoom: presentation.frame.zoom,
      duration: FLIGHT_MS,
    });
    // eslint-disable-next-line react-hooks/exhaustive-deps -- δες παραπάνω: ταυτότητα ΚΑΤΑ ΤΙΜΗ
  }, [signature, ready, mapRef]);
}
