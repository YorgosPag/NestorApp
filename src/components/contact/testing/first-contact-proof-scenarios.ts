import { ApiClientError } from '@/lib/api/enterprise-api-client';
import { FIRST_CONTACT_INVITATION_REFUSALS } from '@/types/first-contact-invitation';

/**
 * **Μία έκβαση της οθόνης απόδειξης.**
 *
 * 🔑 **Το `id` ΕΙΝΑΙ ΤΟ `invitationId`, και είναι σκόπιμο**: ο ψεύτικος μεταφορέας
 * είναι **ΕΝΑΣ** και δρομολογεί πάνω σε αυτό — ακριβώς όπως ένας handler του MSW
 * δρομολογεί πάνω στο αίτημα. Χωρίς αυτό, δώδεκα πάνελ θα μπάλωναν το **ίδιο**
 * καθολικό `apiClient.post` και θα πατούσε το ένα το άλλο.
 */
export interface ProofScenario {
  /** Ταυτότητα πρόσκλησης **και** κλειδί δρομολόγησης του ψεύτικου μεταφορέα. */
  readonly id: string;
  /**
   * Το σώμα άρνησης που θα «απαντήσει» η διαδρομή, **αυτούσιο**.
   *
   * ⚠️ `null` = **καμία κλήση δεν γίνεται ποτέ**: η οθόνη μένει παρθένα. Είναι η
   * κατάσταση του ανθρώπου του οποίου το email **δεν ήρθε** — καμία άρνηση, κανένα
   * μήνυμα σφάλματος, και μέχρι το ADR-844 §11 **καμία πράξη**.
   */
  readonly reply: Record<string, unknown> | null;
  /** Ο κωδικός HTTP που στέλνει όντως η διαδρομή. Δες {@link PROOF_SCENARIOS}. */
  readonly status: number;
}

/**
 * 🔴 **ΤΟ ΚΛΕΙΣΤΟ ΣΥΝΟΛΟ ΓΡΑΦΕΙ ΤΟΝ ΕΑΥΤΟ ΤΟΥ.** Η μεσαία γραμμή είναι όλο το επιχείρημα
 * του αρχείου: `FIRST_CONTACT_INVITATION_REFUSALS.map(...)`.
 *
 * ⚠️ **Οι κωδικοί κατάστασης είναι ΑΝΤΙΓΡΑΦΟ ΤΗΣ ΔΙΑΔΡΟΜΗΣ, όχι εικασία**
 * *(`api/first-contacts/guest/confirm/route.ts`)*: `LINK_REFUSED` → **422**,
 * `IDENTITY_REFUSED` → **403**, `WRITE_FAILED` → **503**. Δεν τους διαβάζει ο
 * `guestFailureOf` — τους κρατάμε γιατί μια γκαλερί που λέει ψέματα για το δίκτυο
 * παύει να είναι όργανο μέτρησης.
 *
 * ⚠️ **Το τελευταίο σκέλος είναι ΑΓΝΩΣΤΟΣ κωδικός επίτηδες**: αποδεικνύει ότι ο φρουρός
 * του `guestFailureOf` πέφτει στο `failed` αντί να αφήσει **ωμό κλειδί στην οθόνη** —
 * το ακριβές λάθος που ονομάζει το ADR-834 §6.5.ε.
 *
 * 🔴 **ΚΑΙ ΤΟ `failed` ΔΕΝ ΜΕΝΕΙ ΣΕ ΑΥΤΗ ΤΗΝ ΟΘΟΝΗ — ΤΟ ΕΜΑΘΕ Η ΓΚΑΛΕΡΙ ΤΡΕΧΟΝΤΑΣ.**
 * Το `settle()` του `first-contact-proof-state` επιστρέφει **πράξη** για το `failed`
 * *(όπως και για τα `refused`/`invalid`)*, δηλαδή **ανεβαίνει στον γονιό** και το
 * ζωγραφίζει ο `FirstContactOutcomeNotice` του διαλόγου. Το `ProofSetback` με
 * `kind: 'failed'` είναι **αμυντικό** σκέλος *(«κάποιος χάλασε το `settle`»)*, όχι
 * κατάσταση προϊόντος.
 *
 * ⛔ **ΓΙ' ΑΥΤΟ ΤΟ ΣΕΝΑΡΙΟ ΔΕΝ ΔΙΑΓΡΑΦΗΚΕ** όταν το πάνελ του βγήκε **οπτικά ταυτόσημο
 * με το `pristine`**: η σιωπηλή διαγραφή θα έκρυβε ένα **αληθινό γεγονός της
 * αρχιτεκτονικής**. Το πάνελ δείχνει πλέον *«φεύγει από αυτή την οθόνη»* — και αν
 * κάποιος αλλάξει το `settle` ώστε να το κρατά, η άγκυρα **Β2** κοκκινίζει.
 */
export const PROOF_SCENARIOS: readonly ProofScenario[] = [
  // Καμία άρνηση: η οθόνη όπως τη βλέπει ο άνθρωπος τη στιγμή που ανοίγει.
  { id: 'pristine', reply: null, status: 0 },

  // 🔑 ΕΔΩ ΕΙΝΑΙ Η ΕΞΑΝΤΛΗΤΙΚΟΤΗΤΑ — επτά σήμερα, οκτώ αύριο, χωρίς να το θυμηθεί κανείς.
  ...FIRST_CONTACT_INVITATION_REFUSALS.map((reason): ProofScenario => ({
    id: `link-${reason}`,
    reply: { error: 'LINK_REFUSED', reason },
    status: 422,
  })),

  { id: 'identity-refused', reply: { error: 'IDENTITY_REFUSED' }, status: 403 },
  { id: 'unavailable', reply: { error: 'WRITE_FAILED' }, status: 503 },
  { id: 'failed', reply: { error: 'A_CODE_THIS_CLIENT_HAS_NEVER_HEARD_OF' }, status: 500 },
];

/** Ο κωδικός που πληκτρολογεί η γκαλερί. **Η τιμή δεν κρίνεται ποτέ** — ο ψεύτικος
 *  μεταφορέας απαντά με βάση την ταυτότητα, όχι τα ψηφία. Υπάρχει μόνο επειδή η
 *  υποβολή γυρίζει νωρίς σε κενό πεδίο. */
export const HARNESS_CODE = '000000';

/**
 * **Το σφάλμα που θα είχε πετάξει ο μεταφορέας**, ταυτόσημο σε σχήμα.
 *
 * ⛔ **ΜΗΝ το αντικαταστήσεις με σκέτο `new Error(...)`**: ο `apiErrorBodyOf` απαιτεί
 * **`ApiClientError`** *(`instanceof`)* και διαβάζει **μόνο** το `errorBody`. Ένα απλό
 * `Error` θα γύριζε `null` ⇒ **κάθε** σενάριο θα κατέληγε `failed`, και η γκαλερί θα
 * έδειχνε δώδεκα φορές την ίδια οθόνη ενώ θα δήλωνε ότι δείχνει δώδεκα διαφορετικές.
 */
export function scriptedRejection(scenario: ProofScenario): ApiClientError {
  return new ApiClientError(
    `harness: scripted ${scenario.id}`,
    scenario.status,
    typeof scenario.reply?.error === 'string' ? scenario.reply.error : undefined,
    undefined,
    undefined,
    undefined,
    scenario.reply,
  );
}
