/**
 * Ανθρώπινη περιγραφή ενός OAuth scope — SSoT (ADR-738)
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟ ΑΡΧΕΙΟ ΓΙΑ ΕΝΑΝ ΤΡΙΤΕΝΙΚΟ ΤΕΛΕΣΤΗ
 * ─────────────────────────────────────────────────────────────────────────────
 * Η αντιστοίχιση «scope → τι σημαίνει στα ελληνικά» εμφανίζεται σε **δύο**
 * οθόνες που λένε το ίδιο πράγμα σε διαφορετικές στιγμές: η συγκατάθεση ρωτά
 * «να του το δώσω;», οι συνδεδεμένοι πράκτορες απαντούν «τι του έχω δώσει;».
 *
 * Γραμμένη δύο φορές, η αντιστοίχιση αποκλίνει με τον χειρότερο τρόπο: ο χρήστης
 * εγκρίνει *ένα* κείμενο και βλέπει αργότερα *άλλο* για την ίδια εξουσία — και
 * τότε δεν ξέρει ποιο από τα δύο ισχύει. Σε οθόνη που υπάρχει για να λέει
 * αλήθεια, αυτό δεν είναι θέμα συντήρησης.
 *
 * ⚠️ Νέο scope ⇒ **και** νέο `case` εδώ **και** κλειδί i18n σε `el` + `en`
 * (N.11). Χωρίς αυτό ο χρήστης βλέπει «Άγνωστο δικαίωμα: …» και καλείται να
 * εγκρίνει κάτι που το ίδιο το σύστημα δεν ξέρει να ονομάσει.
 *
 * @module components/oauth/oauth-scope-labels
 * @see ADR-738 §4.2
 */

import { OAUTH_SCOPES } from '@/lib/oauth/oauth-config';

/**
 * Ό,τι χρειάζεται η συνάρτηση από έναν μεταφραστή.
 *
 * Δομικός τύπος αντί για `TFunction`: οι δύο καταναλωτές παίρνουν το `t` από
 * διαφορετική πηγή (`react-i18next` και το hook του έργου), και μια ονομαστική
 * εξάρτηση θα ανάγκαζε τον έναν να προσαρμοστεί χωρίς λόγο.
 */
export type ScopeTranslator = (key: string, options?: { readonly scope: string }) => string;

/**
 * Ένα scope → η φράση που βλέπει ο άνθρωπος.
 *
 * Άγνωστο scope **δεν** αποκρύπτεται: εμφανίζεται αυτούσιο μέσα στο μήνυμα.
 * Σιωπηλή παράλειψη θα σήμαινε ότι ο χρήστης εγκρίνει εξουσία που δεν του
 * δείχτηκε ποτέ.
 */
export function describeOAuthScope(t: ScopeTranslator, scope: string): string {
  switch (scope) {
    case OAUTH_SCOPES.BOQ_READ:
      return t('auth:oauthConsent.scopeBoqRead');
    default:
      return t('auth:oauthConsent.scopeUnknown', { scope });
  }
}
