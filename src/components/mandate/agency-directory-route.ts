import { typedHref } from '@/lib/workspace/route-worlds';

/**
 * Η διαδρομή της βιτρίνας.
 *
 * ⚠️ **Ο σύνδεσμος περνά από το ΣΥΝΟΡΟ** (`@/lib/workspace/navigation`, CHECK 3.61)
 * και **όχι** από ωμό `next/link`: ο κριτής του συνόρου βλέπει ότι το `pro` είναι
 * δηλωμένο στο `OUTSIDE_WORKSPACE` και αφήνει τη διεύθυνση **άθικτη**. Με ωμό
 * `next/link` θα «δούλευε» σήμερα και θα έσπαγε τη στιγμή που κάποιος αφαιρούσε τη
 * δήλωση — δηλαδή ο έλεγχος θα ζούσε στο **τίποτα**.
 */
export const AGENCY_DIRECTORY_ROUTE = '/pro' as const;

/**
 * **Ο κατάλογος με τα φίλτρα του** — για τον `router.replace` του συνόρου.
 *
 * ⚠️ Το κενό `?` **δεν** γράφεται: δύο ταυτόσημες σελίδες με και χωρίς αυτό
 * είναι δύο διευθύνσεις για το ίδιο περιεχόμενο — ο ίδιος λόγος για τον οποίο
 * το `serializeShowcaseFilters` δεν γράφει κενά φίλτρα *(Φ2)*.
 *
 * 🔑 **`typedHref` επειδή ο router του συνόρου δέχεται branded διεύθυνση**
 * (CHECK 3.61): μια ωμή συμβολοσειρά **δεν μεταγλωττίζεται**, και αυτό είναι
 * ακριβώς ο φρουρός — καμία διαδρομή δεν φεύγει χωρίς να περάσει από εδώ.
 */
export function agencyDirectoryHref(query?: string | null) {
  if (query && query.length > 0) return typedHref(`${AGENCY_DIRECTORY_ROUTE}?${query}` as const);
  return typedHref(AGENCY_DIRECTORY_ROUTE);
}

/**
 * `/pro/<τμήμα>` — **με κωδικοποίηση, και είναι απαίτηση όχι κόσμημα**: το
 * ψευδώνυμο είναι δεδομένο χρήστη, και ένα `/` μέσα του θα γεννούσε **άλλη σελίδα**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΟ ΤΜΗΜΑ ΕΙΝΑΙ **ΨΕΥΔΩΝΥΜΟ Ή ΤΑΥΤΟΤΗΤΑ** — ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΑΝΟΧΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η παράμετρος λεγόταν `alias`, και το όνομα **έγινε ψέμα τη στιγμή που η κάρτα της
 * οθόνης 2 ζήτησε τη βιτρίνα** *(ADR-777 §8.58 · Φ7)*: η αγγελία κουβαλά
 * `agencyId` — δηλαδή `comp_<uuid>` — και **ποτέ** ψευδώνυμο. Ο ίδιος ο τύπος το
 * γράφει: *«ψευδώνυμο εδώ θα ήταν **τρίτο** αντίγραφο του `workspace_aliases` και θα
 * απαιτούσε αντίστροφη αναζήτηση που το `resolveAlias` αρνείται εξ ορισμού»*.
 *
 * 🔴 **ΚΑΙ Η ΑΝΤΙΣΤΡΟΦΗ ΑΝΑΖΗΤΗΣΗ ΔΕΝ ΧΡΕΙΑΖΕΤΑΙ: Ο ΑΝΑΓΝΩΣΤΗΣ ΕΙΝΑΙ ΗΔΗ ΥΒΡΙΔΙΚΟΣ.**
 * Το {@link module:lib/workspace/alias-registry.resolveAlias} κρίνει **πρώτα** τη
 * σταθερή ταυτότητα (`readsAsWorkspaceIdentity`) και επιστρέφει `found` **χωρίς να
 * αγγίξει τη βάση** — μηδέν αναγνώσεις, όπως και το `/o/me`. Άρα το
 * `/pro/comp_<uuid>` **λύνεται σήμερα**, χωρίς νέα σελίδα και χωρίς νέο ευρετήριο.
 *
 * ⚠️ **ΚΑΜΙΑ ΔΙΕΥΘΥΝΣΗ ΔΕΝ ΕΙΝΑΙ ΔΙΦΟΡΟΥΜΕΝΗ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΔΕΙΞΗ ΟΧΙ ΣΥΜΒΑΣΗ**
 * *(`lib/workspace/workspace-segment.ts`)*: το `ALIAS_PATTERN` απορρίπτει το `_`, και
 * **κάθε** enterprise ταυτότητα είναι `` `${πρόθεμα}_${uuid}` `` ⇒ έχει πάντα `_`. Η
 * τομή των δύο συνόλων είναι **κενή ως ιδιότητα των υπαρχουσών γραμματικών**.
 *
 * ⛔ **ΜΗΝ γράψεις δεύτερη συνάρτηση `…RouteById`.** Θα ήταν **δεύτερη γραφή της ίδιας
 * διεύθυνσης** — ακριβώς η απόκλιση που η κεφαλίδα αυτού του αρχείου καταγράφει ότι
 * πληρώθηκε ήδη μία φορά *(η σελίδα εντολής ξαναέγραψε `'/pro'` **χωρίς**
 * `encodeURIComponent`)*. Ένας δρόμος, δύο γραμματικές, **ένας** κριτής.
 */
export function agencyProfileRoute(segment: string): string {
  return `${AGENCY_DIRECTORY_ROUTE}/${encodeURIComponent(segment)}`;
}
