import { SHOWCASE_MARK_KINDS, type ShowcaseMarkKind } from '@/lib/agency/showcase-mark-kind';

/** Πώς κάθεται ένα σήμα μέσα στο τετράγωνό του. */
export interface ShowcaseMarkFrame {
  /** Η **στρογγυλότητα** του πλαισίου — κλάση Tailwind, στατική. */
  readonly shape: string;
  /** Πώς γεμίζει η εικόνα το πλαίσιο — `object-fit`, ως κλάση. */
  readonly fit: string;
  /**
   * **Η επιφάνεια κάτω από την εικόνα** *(Α21.15)*.
   *
   * 🔴 **Ήταν `bg-card` για όλα, και το λογότυπο εξαφανιζόταν στο σκοτεινό θέμα**:
   * μετρημένο στην παραγωγή, σκούρο navy «NESTOR» σε διαφανές φόντο πάνω σε `--card`
   * `217 33% 17%` ⇒ φαινόταν μόνο το μπλε εικονόσημο. Η υπόσχεση *«επιφάνεια για να
   * φανεί»* ίσχυε μόνο στο **φωτεινό** θέμα.
   *
   * 🏆 **Το λογότυπο παίρνει ΛΕΥΚΗ πλάκα και στα δύο θέματα** — ό,τι κάνουν LinkedIn,
   * Clutch, G2 στις λίστες τους: τα λογότυπα σχεδιάζονται **για λευκό χαρτί**. Και είναι
   * **συνεπές με το Α21.10.2**: *«διάφανο και λευκό είναι συσκευασία»* — ο καθαριστής
   * ήδη θεωρεί το λευκό **φόντο**, οπότε η πλάκα δεν λέει κάτι που δεν λέει ήδη ο τομέας.
   * ⚠️ **Δηλωμένο κόστος**: λογότυπο με **λευκό** μελάνι σε διαφανές θα χαθεί. Το βλέπει
   * ο άνθρωπος **πριν** δημοσιεύσει, γιατί η προεπισκόπηση φοράει την **ίδια** πλάκα.
   *
   * 🔑 **Το πορτρέτο κρατά `bg-card`**: το `object-cover` το γεμίζει ολόκληρο, η πλάκα
   * δεν φαίνεται ποτέ — λευκή θα ήταν μόνο φωτοστέφανο στη φόρτωση.
   */
  readonly surface: string;
}

/**
 * **Το πλαίσιο κάθε είδους** — δες την τεκμηρίωση στην κορυφή.
 *
 * 🔴 `Record<ShowcaseMarkKind, …>` πάνω στο **κλειστό σύνολο**: τρίτο είδος **δεν
 * μεταγλωττίζεται** μέχρι κάποιος να απαντήσει *«τι σχήμα έχει;»* — που είναι, για
 * αυτόν τον τομέα, η **πρώτη** ερώτηση και όχι λεπτομέρεια στιλ.
 */
export const SHOWCASE_MARK_FRAME: Readonly<Record<ShowcaseMarkKind, ShowcaseMarkFrame>> = {
  logo: { shape: 'rounded-lg', fit: 'object-contain', surface: 'bg-white ring-1 ring-border' },
  portrait: { shape: 'rounded-full', fit: 'object-cover', surface: 'bg-card' },
} as const;

/**
 * **Πόσο από το τετράγωνο επιβιώνει της κυκλικής μάσκας** — ως ποσοστό επιφάνειας.
 *
 * 🔴 **π/4 = 78,5%, ΚΑΙ Ο ΑΡΙΘΜΟΣ ΕΙΝΑΙ ΓΕΩΜΕΤΡΙΑ, ΟΧΙ ΓΟΥΣΤΟ.** Ο εγγεγραμμένος κύκλος
 * σε τετράγωνο πλευράς `s` έχει εμβαδόν `π(s/2)²`, δηλαδή `π/4` του τετραγώνου — και
 * **κάθε γωνία** χάνεται.
 *
 * ⚠️ **Δεν είναι το ίδιο με τη «ζώνη ασφαλείας» του ~70%** που συνιστούν οι οδηγοί
 * σχεδίασης: εκείνη είναι **συντηρητική σύσταση** για το πού να βάλεις το θέμα, αυτό
 * είναι **τι κόβεται**. Δύο διαφορετικά νούμερα για δύο διαφορετικά ερωτήματα, και το
 * handoff τα είχε συγχύσει.
 *
 * 🔑 Ζει εδώ επειδή είναι **ιδιότητα του πλαισίου**, και η οθόνη το χρειάζεται για να
 * πει στον άνθρωπο **τι θα κοπεί** πριν το κόψει.
 */
export const CIRCULAR_MASK_COVERAGE = Math.PI / 4;

/**
 * **Χρειάζεται αυτό το είδος προειδοποίηση περικοπής;**
 *
 * 🔑 **Κατηγόρημα πάνω στο σχήμα, ποτέ λίστα ειδών**: η ερώτηση είναι *«κόβει το
 * πλαίσιο;»*, και η απάντηση προκύπτει από το `rounded-full`. Ένα
 * `kind === 'portrait'` εδώ θα ήταν **δεύτερη** αυθεντία για το ποιο είδος είναι
 * κυκλικό — ελεύθερη να διαφωνήσει με τον πίνακα από πάνω την ημέρα που θα προστεθεί
 * τρίτο είδος.
 */
export function maskCrops(kind: ShowcaseMarkKind): boolean {
  return SHOWCASE_MARK_FRAME[kind].shape === 'rounded-full';
}

/**
 * Το πλαίσιο, **fail-closed** για τιμή που ήρθε από τον δίσκο ή από το σύρμα.
 *
 * ⚠️ Ένα σκέτο `SHOWCASE_MARK_FRAME[kind]` πάνω σε ιστορική τιμή δίνει `undefined`, και
 * το `undefined.shape` **ρίχνει ολόκληρη τη σελίδα** — για ένα σήμα μεγέθους νυχιού. Το
 * `logo` είναι η ασφαλής εφεδρεία: `contain` **δεν κόβει τίποτα**, οπότε ό,τι κι αν είναι
 * η εικόνα, φαίνεται ολόκληρη.
 */
export function frameOf(kind: string): ShowcaseMarkFrame {
  return (SHOWCASE_MARK_KINDS as readonly string[]).includes(kind)
    ? SHOWCASE_MARK_FRAME[kind as ShowcaseMarkKind]
    : SHOWCASE_MARK_FRAME.logo;
}
