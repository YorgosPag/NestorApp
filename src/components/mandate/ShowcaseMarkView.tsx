/**
 * 🔴 **ΣΤΑΤΙΚΗ ΟΚΤΑΔΑ, ΚΑΙ ΕΙΝΑΙ ΑΝΑΓΚΗ — ΟΧΙ ΠΡΟΤΙΜΗΣΗ.**
 *
 * Μια κλάση χτισμένη με παρεμβολή — `bg-[hsl(var(--chart-` **+ slot +** `))]` — **δεν
 * παράγει καμία γραμμή CSS**: ο Tailwind σαρώνει τον πηγαίο κώδικα **στατικά** και δεν
 * εκτελεί ποτέ το πρότυπο. Το αποτέλεσμα θα ήταν σήμα **χωρίς φόντο**: κείμενο σε χρώμα
 * `--card` πάνω σε `--card`, **εντελώς αόρατο**, **χωρίς κανένα σφάλμα πουθενά**.
 *
 * 🔴 **ΚΑΙ ΓΙ' ΑΥΤΟ ΤΟ ΠΑΡΑΠΑΝΩ ΑΝΤΙΠΑΡΑΔΕΙΓΜΑ ΕΙΝΑΙ ΣΠΑΣΜΕΝΟ ΣΕ ΤΡΙΑ ΚΟΜΜΑΤΙΑ.**
 * Η πρώτη γραφή αυτού του σχολίου το έγραφε **ακέραιο** — και **ΕΡΙΞΕ ΟΛΟ ΤΟ
 * STYLESHEET** (`HTTP 500`, *«Parsing CSS source code failed»*, μετρημένο στον
 * φυλλομετρητή). Ο Tailwind **δεν διαβάζει JavaScript**: ταιριάζει υποψήφιες κλάσεις
 * **οπουδήποτε στο αρχείο, σχόλια συμπεριλαμβανομένων**, και το `tailwind.config`
 * σαρώνει `./src/components/**`. Παρήγαγε τον επιλογέα
 * έναν επιλογέα με **αδιαπέραστο** `$` μέσα του, δηλαδή **άκυρο CSS**.
 *
 * ⚠️ Δηλαδή **η τεκμηρίωση της παγίδας αναπαρήγαγε την παγίδα** — και χειρότερα από το
 * πρωτότυπο: εκεί το σήμα θα ήταν αόρατο, εδώ έπεσε **ολόκληρη η εφαρμογή**. Άγκυρα
 * στο **ωμό** κείμενο του αρχείου το φυλάει· ένας έλεγχος που σβήνει πρώτα τα σχόλια
 * είναι **δομικά ανίκανος** να το δει, γιατί ο Tailwind δεν τα σβήνει.
 *
 * 🔴 **ΚΑΙ Η ΔΕΥΤΕΡΗ ΑΠΟΠΕΙΡΑ ΑΠΕΤΥΧΕ ΚΙ ΑΥΤΗ** — αξίζει να γραφτεί, γιατί είναι το
 * είδος του λάθους που ο επόμενος θα ξανακάνει: η «διόρθωση» έγραψε τον επιλογέα στην
 * **ξεφευγμένη** του μορφή *(με ανάποδες καθέτους πριν από κάθε αγκύλη)*, νομίζοντας
 * ότι έτσι δεν είναι πια κλάση. **Είναι**: ο Tailwind δέχεται ξεφευγμένους χαρακτήρες
 * μέσα σε ονόματα κλάσεων, οπότε παρήγαγε **ακριβώς τον ίδιο** άκυρο κανόνα — και τα
 * `grep` για την **απλή** μορφή δεν τον έβρισκαν, γιατί δεν ήταν εκεί.
 *
 * ⇒ Ο φρουρός δεν ρωτά *«υπάρχει αυτό το κείμενο;»* αλλά *«ακολουθεί κάθε `--chart-`
 * **ψηφίο**;»* — η μόνη διατύπωση που πιάνει **και τις δύο** μορφές.
 *
 * ⚠️ Η σειρά αντιστοιχεί **ένα προς ένα** στο `slot` (1-based) — δες `lettermarkOf`.
 */
const MARK_SURFACES = [
  'bg-[hsl(var(--chart-1))]',
  'bg-[hsl(var(--chart-2))]',
  'bg-[hsl(var(--chart-3))]',
  'bg-[hsl(var(--chart-4))]',
  'bg-[hsl(var(--chart-5))]',
  'bg-[hsl(var(--chart-6))]',
  'bg-[hsl(var(--chart-7))]',
  'bg-[hsl(var(--chart-8))]',
] as const;

/**
 * 🔴 **ΤΟ ΚΟΥΤΙ ΕΦΥΓΕ ΑΠΟ ΕΔΩ — ΔΕΝ ΕΙΝΑΙ ΠΙΑ ΣΥΝΑΡΤΗΣΗ ΜΟΝΟ ΤΟΥ ΜΕΓΕΘΟΥΣ** (Α21.9).
 *
 * Εδώ ζούσαν **δύο** πίνακες, `MARK_SIZES` και `MARK_SIZES_ATTR`, που έπρεπε να
 * συμφωνούν και **δεν** τους επαλήθευε μεταγλωττιστής *(το ίδιο τους το σχόλιο το
 * παραδεχόταν)*. Και οι δύο έδιναν **τετράγωνο** σε κάθε σήμα — δηλαδή σε λογότυπο 4:1
 * μελάνι **64×16**.
 *
 * Πλέον η απάντηση είναι **μία** και παράγεται από την **αναλογία της ίδιας της
 * εικόνας**: {@link module:components/mandate/showcase-mark-box}. Διαστάσεις και `sizes`
 * επιστρέφονται **μαζί**, γιατί είναι η ίδια απόφαση.
 */

/**
 * **Τι σήμα δείχνουμε** — δηλωμένο ή παραγόμενο, ποτέ και τα δύο.
 *
 * 🔴 **ΔΙΑΚΕΚΡΙΜΕΝΗ ΕΝΩΣΗ ΚΑΙ ΟΧΙ `declared?: … ; lettermark: …`.** Με δύο προαιρετικά
 * πεδία, το *«και τα δύο»* και το *«κανένα»* θα ήταν **εκφράσιμα** — δηλαδή κάποιος θα
 * έπρεπε να αποφασίσει σε χρόνο εκτέλεσης ποιο κερδίζει, και δύο καταναλωτές θα
 * μπορούσαν να απαντήσουν αλλιώς. **Ένα σήμα ανά επαγγελματία**: η κάρτα έχει **μία**
 * θέση για *«ποιος είσαι;»*, και ο τύπος το λέει.
 */
export type ShowcaseMarkSubject =
  | { readonly declared: DeclaredShowcaseMark }
  | { readonly lettermark: ShowcaseLettermark };

interface ShowcaseMarkViewProps {
  readonly mark: ShowcaseMarkSubject;
  readonly size: ShowcaseMarkSize;
}

/**
 * **Το σήμα.**
 *
 * ⇒ Δηλωμένη εικόνα ⇒ {@link DeclaredMarkImage}· αλλιώς το **παραγόμενο** πλακίδιο, που
 * **δεν αποτυγχάνει ποτέ**.
 */
export function ShowcaseMarkView({ mark, size }: ShowcaseMarkViewProps): React.JSX.Element {
  if ('declared' in mark) return <DeclaredMarkImage mark={mark.declared} size={size} />;
  return <Lettermark mark={mark.lettermark} size={size} />;
}

/**
 * **Η ΔΗΛΩΜΕΝΗ εικόνα** (ADR-841 §7 Α21, Φάση 2) — ο **τέταρτος** καταναλωτής του ενός
 * `srcset` builder.
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 🔴 ΕΔΩ ΤΟ `aria-hidden` ΑΝΤΙΣΤΡΕΦΕΤΑΙ — ΚΑΙ ΕΙΝΑΙ Η ΙΔΙΑ ΑΡΧΗ, ΟΧΙ ΕΞΑΙΡΕΣΗ
 * ════════════════════════════════════════════════════════════════════════════
 *
 * Το πλακίδιο κρύβεται γιατί **δεν λέει τίποτα** που να μην το λέει ο τίτλος δίπλα του:
 * «Π, Α» πριν από το «Παπαδόπουλος» είναι θόρυβος. Η **εικόνα** λέει κάτι που ο τίτλος
 * **δεν** λέει — *«λογότυπο γραφείου»* ή *«φωτογραφία προσώπου»*, που είναι διαφορετική
 * πληροφορία και όχι διαφορετική διατύπωση.
 *
 * ⇒ **Δύο διαφορετικές απαντήσεις στην ίδια οθόνη, και είναι σωστό.** Το ίδιο το αρχείο
 * το είχε προβλέψει από το Στάδιο 1: *«το δηλωμένο σήμα θα χρειαστεί `altKey`»*.
 *
 * ⚠️ **Το `altKey` ΤΑΞΙΔΕΥΕΙ ΩΣ ΤΙΜΗ** μέσα στην εικόνα — η οθόνη το περνά σε `t()`,
 * **δεν το επιλέγει**. Ένα `t(kind === 'logo' ? … : …)` εδώ θα ήταν **δεύτερος** κριτής
 * για το «τι είναι αυτά τα bytes», ελεύθερος να διαφωνήσει με τον γραφέα που τα έγραψε.
 *
 * ⛔ **Ποτέ `next/image`**: οι δημόσιες εικόνες πάνε με σκέτο `<img srcSet>`.
 */
function DeclaredMarkImage({
  mark,
  size,
}: {
  readonly mark: DeclaredShowcaseMark;
  readonly size: ShowcaseMarkSize;
}): React.JSX.Element {
  const { t } = useTranslation([SHOWCASE_NS]);
  const frame = frameOf(mark.kind);
  // 🔑 **Η ΑΝΑΛΟΓΙΑ ΕΡΧΕΤΑΙ ΑΠΟ ΤΑ ΙΔΙΑ ΤΑ BYTES** (Α21.9): το `width`/`height` το
  //    γράφει ο καθαριστής από το `sharp` με `fit: 'inside'`, άρα είναι οι **πραγματικές**
  //    διαστάσεις του παραγώγου — όχι υπόσχεση, μέτρηση. Καμία ερώτηση στον άνθρωπο.
  const box = markBox(size, {
    kind: mark.kind,
    width: mark.image.width,
    height: mark.image.height,
  });

  return (
    // eslint-disable-next-line @next/next/no-img-element
    <img
      src={mark.image.url}
      srcSet={listingImageSrcSet(mark.image)}
      sizes={box.sizesAttr}
      width={mark.image.width}
      height={mark.image.height}
      alt={t(mark.image.altKey)}
      // ⚠️ **`lazy`, και είναι σωστό ακόμη και στην πρώτη κάρτα**: το σήμα δεν είναι
      //    ποτέ το στοιχείο LCP — είναι 44 εικονοστοιχεία δίπλα σε επικεφαλίδα. Ένα
      //    `eager` εδώ θα ανταγωνιζόταν το πραγματικό LCP για εύρος ζώνης (Α2.4).
      loading="lazy"
      decoding="async"
      className={cn(
        // 🔑 **Επιφάνεια κάτω από την εικόνα, ΑΝΑ ΕΙΔΟΣ** (Α21.15): το ράφι διατηρεί τη
        //    διαφάνεια επίτηδες, και το `bg-card` που ήταν εδώ **έκρυβε** σκούρο λογότυπο
        //    στο σκοτεινό θέμα. Η πλάκα ζει στο πλαίσιο — δες `ShowcaseMarkFrame.surface`.
        'shrink-0',
        frame.surface,
        frame.shape,
        frame.fit,
        box.className,
        // 🔑 **Ο αέρας γύρω από ΤΡΙΜΜΕΝΟ μελάνι** (Α21.10): ο καθαριστής κόβει πλέον το
        //    λογότυπο στα όριά του, και μελάνι που ακουμπά την άκρη ενός `rounded-lg`
        //    **χάνει τις γωνίες του** στην ίδια την καμπύλη. Κενό για πορτρέτο.
        box.clearSpace,
      )}
    />
  );
}

/**
 * **Το παραγόμενο πλακίδιο** — η εφεδρεία που **δεν αποτυγχάνει ποτέ**.
 *
 * 🔑 **`aria-hidden`, και είναι απόφαση — όχι παράλειψη**: η επωνυμία βρίσκεται
 * **δίπλα**, στην ίδια `<article>`. Ένα σήμα που εκφωνεί «Π, Α» πριν από το
 * «Παπαδόπουλος» είναι **θόρυβος** για τον αναγνώστη οθόνης, όχι πληροφορία.
 *
 * ⚠️ **Κενά αρχικά είναι νόμιμα** *(επωνυμία χωρίς κανένα γράμμα)*: μένει το χρωματιστό
 * πλακίδιο. Είναι **λιγότερο** πληροφοριακό, αλλά **δεν είναι ανώνυμο** — και η
 * ανωνυμία ήταν η μετρημένη ποινή, όχι η έλλειψη γραμμάτων.
 */
function Lettermark({
  mark,
  size,
}: {
  readonly mark: ShowcaseLettermark;
  readonly size: ShowcaseMarkSize;
}): React.JSX.Element {
  // ⚠️ **Το πλακίδιο δεν έχει αναλογία** — είναι παραγόμενο, άρα **πάντα** τετράγωνο.
  //    Ο τύπος το λέει: το σκέλος `lettermark` δεν δέχεται καν διαστάσεις.
  const box = markBox(size, { kind: 'lettermark' });

  return (
    <span
      aria-hidden="true"
      className={cn(
        'flex shrink-0 select-none items-center justify-center rounded-lg font-bold leading-none tracking-tight',
        'text-[hsl(var(--card))]',
        MARK_SURFACES[mark.slot - 1],
        box.className,
        box.text,
      )}
    >
      {mark.initials}
    </span>
  );
}
