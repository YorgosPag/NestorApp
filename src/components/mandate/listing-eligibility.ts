/**
 * @fileoverview **ΤΟ ΦΙΛΤΡΟ ΚΑΙ Η ΥΠΟΣΧΕΣΗ ΤΟΥ, ΑΠΟ ΤΗΝ ΙΔΙΑ ΠΗΓΗ.**
 * @module components/mandate/listing-eligibility
 * @related ADR-834 §6.4.β · ADR-832 §4 · N.7.2 #5
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΓΕΝΝΗΘΗΚΕ: Η ΟΘΟΝΗ ΥΠΟΣΧΟΤΑΝ ΦΙΛΤΡΟ ΠΟΥ Ο ΚΩΔΙΚΑΣ ΕΙΧΕ ΑΦΑΙΡΕΣΕΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `listingHint` έλεγε *«Εμφανίζονται μόνο ακίνητα που είναι δικά σας, δημοσιευμένα
 * **και χωρίς εντολή σε άλλο γραφείο**»*. Ο επιλογέας φιλτράριζε **μόνο**
 * `lifecycle === 'listed'`: το ADR-832 είχε αφαιρέσει τον έλεγχο εντολής **σκόπιμα**
 * *(ακίνητο με απλή εντολή εξαφανιζόταν, και ο ιδιοκτήτης δεν μάθαινε ποτέ γιατί
 * λείπει το σπίτι του)*. **Το κείμενο έμεινε πίσω, και κανείς δεν το ρώτησε ποτέ.**
 *
 * 🔴 **Το τίμημα μετρήθηκε ζωντανά, ως ακολουθία πράξεων ανθρώπου** *(ADR-834 §6.4.β)*:
 * το ακίνητο **με** εντολή εμφανίστηκε· ο άνθρωπος διάβασε *«χωρίς εντολή»*, συμπέρανε
 * *«άρα είναι ελεύθερο»*, συμπλήρωσε είδος, αμοιβή, πράξη, δύο ημερομηνίες και ΑΦΜ —
 * και έμαθε στο **τέλος** ότι ήταν αδύνατο **από την αρχή**. Αντιδραστικό, όχι
 * προδραστικό *(N.7.2 #1)*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 Η ΑΡΧΗ: **ΕΝΑ ΚΛΕΙΣΤΟ ΣΥΝΟΛΟ ΚΡΙΤΗΡΙΩΝ ΠΟΥ ΚΑΙ ΦΙΛΤΡΑΡΕΙ ΚΑΙ ΜΙΛΑΕΙ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Κάθε γραμμή αυτού του πίνακα κουβαλά **και** το κατηγόρημα **και** τις λέξεις του.
 * Ο {@link assignableListings} φιλτράρει με τα κατηγορήματα· ο
 * {@link listingEligibilityHint} συνθέτει την πρόταση από τις λέξεις. ⇒ Κριτήριο που
 * **προστίθεται** μπαίνει στην πρόταση μόνο του, και κριτήριο που **αφαιρείται** —
 * ακριβώς ό,τι έκανε το ADR-832 — **φεύγει** από την πρόταση μόνο του.
 * **Η ασυμφωνία γίνεται δομικά αδύνατη, όχι απλώς ανιχνεύσιμη** *(N.7.2 #5)*.
 *
 * ⚠️ **ΤΟ ΕΡΕΥΝΗΘΗΚΕ ΤΟ ΚΟΣΤΟΣ ΠΡΙΝ ΓΡΑΦΤΕΙ, ΓΙΑΤΙ ΤΟ ΠΑΡΑΓΟΜΕΝΟ ΚΕΙΜΕΝΟ ΣΥΝΗΘΩΣ
 * ΣΠΑΕΙ ΤΗ ΓΛΩΣΣΑ.** Το τεκμηριωμένο *«word order problem»* λέει ότι πρόταση χτισμένη
 * με **συνένωση θραυσμάτων** αποτυγχάνει σε γλώσσες με άλλη σειρά λέξεων, γένος και
 * πτώση — και τα ελληνικά είναι ακριβώς τέτοια. Εδώ **δεν** ισχύει, και ο λόγος είναι
 * συγκεκριμένος:
 *
 *   1. Η **κεφαλή είναι σταθερή** *(«ακίνητα»: ουδέτερο, πληθυντικός)* και ζει μέσα
 *      στο **πλήρες** πρότυπο του `listingHint`. Άρα η συμφωνία κάθε κριτηρίου είναι
 *      **σταθερή**, όχι μεταβλητή — δεν υπάρχει η κλίση που σπάει.
 *   2. Τα κριτήρια είναι **μεταρρηματικοί προσδιορισμοί** μετά την κεφαλή, και η
 *      σειρά τους στα ελληνικά είναι **ελεύθερη**.
 *   3. Ο σύνδεσμος **δεν γράφεται και δεν μεταφράζεται**: τον ξέρει το
 *      `Intl.ListFormat` ανά γλώσσα *(βλ. `formatList`)*.
 *   4. Ο μεταφραστής κρατά **ολόκληρη** την πρόταση γύρω από το `{criteria}` — μπορεί
 *      να μετακινήσει τη λίστα όπου θέλει, ακόμη και στην αρχή.
 *
 * 🔑 **Και το κλείσιμο δεν είναι μόνο δομικό**: το `listing-eligibility.test.ts`
 * **εκτελεί** κάθε κατηγόρημα και αποδεικνύει ότι το σύνολο είναι **αναγκαίο**
 * *(κάθε κριτήριο φέρει βάρος)* **και επαρκές** *(δεν υπάρχει κρυφό φίλτρο)* — γιατί
 * η λέξη *«μόνο»* της πρότασης είναι **ισχυρισμός επάρκειας**, και μια πρόταση μπορεί
 * να ψεύδεται **με παράλειψη**.
 */

import { isPersonalCustody } from '@/lib/owner-property/listing-custody';
import { isLiveOwnerProperty, type OwnerProperty } from '@/types/owner-property';

/** Το πρόθεμα του χώρου ονομάτων — μία φορά, όπως στο `mandate-request-form-labels`. */
const NS = 'property-market:mandate.request.';

/**
 * **Ένα κριτήριο: το κατηγόρημα και οι λέξεις του, δεμένα.**
 *
 * ⚠️ Ένα κριτήριο **χωρίς** `holds` θα ήταν διακόσμηση — πρόταση που υπόσχεται φίλτρο
 * που δεν εκτελείται, δηλαδή ακριβώς το περιστατικό που γέννησε το αρχείο. Ένα
 * κριτήριο **χωρίς** `labelKey` θα ήταν το αντίστροφο: φίλτρο που ο άνθρωπος υφίσταται
 * χωρίς να του ειπωθεί ποτέ.
 */
export interface ListingEligibilityCriterion {
  /** Σταθερό αναγνωριστικό — επιβιώνει της μετάφρασης και της αναδιατύπωσης. */
  readonly id: string;
  /** Το πλήρες, **μεταφρασμένο** θραύσμα που συμφωνεί με την κεφαλή «ακίνητα». */
  readonly labelKey: string;
  /** Η **εκτελέσιμη** μορφή του ίδιου ισχυρισμού. */
  readonly holds: (property: OwnerProperty) => boolean;
}

/**
 * 🔑 **Ο ΕΝΑΣ ΠΙΝΑΚΑΣ.** Η σειρά είναι η σειρά ανάγνωσης της πρότασης.
 *
 * ⚠️ **ΜΗΝ ξαναβάλεις εδώ κριτήριο «καμία εντολή»** για να «ταιριάξει» με κάποιο παλιό
 * κείμενο: θα ήταν **επαναφορά** απόφασης του ADR-832 **με τεκμηριωμένο θύμα**. Ο
 * πραγματικός κριτής της σύγκρουσης χρειάζεται τους **όρους**, που εδώ δεν είναι
 * γνωστοί — τους κρίνει ο διακομιστής, και η άρνηση επιστρέφει **με όνομα**
 * *(`listing-conflicting-mandate`, με διέξοδο μέσα στην ίδια φόρμα)*.
 */
export const LISTING_ELIGIBILITY_CRITERIA = [
  {
    // 🔑 **Το «δικά σας» παύει να είναι κληρονομημένο και γίνεται εκτελεσμένο.** Το
    //    `useMyOwnerProperties` το εφαρμόζει ήδη· η επανάληψη εδώ είναι **αδρανής**
    //    (ιδιοτελής N.7.2 #3) και αγοράζει δύο πράγματα: ο ισχυρισμός της πρότασης
    //    αποκτά **δικό του** κατηγόρημα να εκτελεστεί, και ο επιλογέας παύει να
    //    εξαρτάται από το ποιος τον τροφοδοτεί (N.7.2 #4: δρόμος + δίχτυ).
    id: 'personalCustody',
    labelKey: `${NS}listingCriterionPersonal`,
    holds: isPersonalCustody,
  },
  {
    // ⚠️ **`isLiveOwnerProperty`, ποτέ `lifecycle === 'listed'` γραμμένο ξανά.** Η
    //    σύγκριση ήταν γραμμένη με το χέρι μέσα στον επιλογέα ενώ το λεξιλόγιο έχει
    //    **ήδη** τον έναν κριτή· την ημέρα που θα προστεθεί τρίτος κύκλος ζωής, η
    //    χειρόγραφη σύγκριση θα ήταν ο μόνος που δεν θα το μάθαινε.
    id: 'live',
    labelKey: `${NS}listingCriterionLive`,
    holds: isLiveOwnerProperty,
  },
] as const satisfies readonly ListingEligibilityCriterion[];

export type ListingEligibilityId = (typeof LISTING_ELIGIBILITY_CRITERIA)[number]['id'];

/**
 * Τα κλειδιά ως **πίνακας**, για τον φρουρό *«κάθε κείμενο υπάρχει σε δύο γλώσσες»*.
 *
 * ⚠️ **Παράγεται, δεν ξαναγράφεται**: δεύτερος χειρόγραφος πίνακας θα ήταν το ίδιο
 * ακριβώς σφάλμα σε μικρογραφία — δύο πηγές για ένα γεγονός.
 */
export const LISTING_ELIGIBILITY_I18N_KEYS = Object.fromEntries(
  LISTING_ELIGIBILITY_CRITERIA.map((criterion) => [criterion.id, criterion.labelKey]),
) as Record<ListingEligibilityId, string>;

/**
 * **Ο επιλογέας ακινήτου** — ό,τι μπορεί πράγματι να ζητηθεί, και **τίποτε άλλο**.
 *
 * 🔑 Η υλοποίηση είναι `every` πάνω στον πίνακα, **όχι** αλυσίδα από `&&`: μια αλυσίδα
 * θα μπορούσε να ξεχάσει κριτήριο ή να κρύψει ένα που δεν είναι στον πίνακα, και τότε
 * η πρόταση θα ψευδόταν **με παράλειψη** — το πιο δύσκολο ψέμα να παρατηρηθεί.
 */
export function assignableListings(
  properties: readonly OwnerProperty[],
): readonly OwnerProperty[] {
  return properties.filter((property) =>
    LISTING_ELIGIBILITY_CRITERIA.every((criterion) => criterion.holds(property)),
  );
}

/**
 * **Η ίδια απόφαση, σε λέξεις** — η υπόσχεση που διαβάζει ο άνθρωπος.
 *
 * @param t          ο μεταφραστής της οθόνης
 * @param joinParts  ο συνδετήρας της λίστας — ενίεται ώστε η άγκυρα να τον ελέγχει
 *                   χωρίς να χρειάζεται `Intl.ListFormat` δεμένο σε ζωντανή γλώσσα
 */
export function listingEligibilityHint(
  t: (key: string, values?: Record<string, string>) => string,
  joinParts: (parts: readonly string[]) => string,
): string {
  const criteria = joinParts(
    LISTING_ELIGIBILITY_CRITERIA.map((criterion) => t(criterion.labelKey)),
  );
  return t(`${NS}listingHint`, { criteria });
}
