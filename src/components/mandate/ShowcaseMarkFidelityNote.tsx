import React from 'react';

import { useTranslation } from '@/i18n/hooks/useTranslation';
import {
  SHOWCASE_MARK_ADVICE_KEYS,
  SHOWCASE_MARK_KEYS,
  SHOWCASE_NS,
} from '@/components/mandate/agency-showcase-labels';
import {
  judgeShowcaseMark,
  type ShowcaseMarkReach,
} from '@/lib/agency/showcase-mark-fidelity';
import type { DeclaredShowcaseMark } from '@/types/agency-profile';

/**
 * **Η σημείωση για το δημοσιευμένο σήμα** — ή **τίποτα**, όταν δεν υπάρχει τίποτα να πει.
 *
 * 🔑 **Κρίνει το `image`, όχι το αρχείο**: αυτές είναι οι διαστάσεις που έγραψε ο
 * καθαριστής **μετά** το τρίμμα, δηλαδή ό,τι πραγματικά κατεβάζει ο επισκέπτης.
 */
export function ShowcaseMarkFidelityNote({
  published,
}: {
  readonly published: DeclaredShowcaseMark;
}): React.JSX.Element | null {
  const { t } = useTranslation([SHOWCASE_NS]);
  const verdict = judgeShowcaseMark(published.image, published.kind);

  // 🔑 **Η σιωπή είναι απάντηση**: το σήμα καλύπτει κάθε επιφάνεια σε διπλή πυκνότητα.
  if (verdict.outcome === 'accepted') return null;

  return (
    <p className="m-0 text-xs text-muted-foreground">
      <BlurryReach reach={verdict.reach} />{' '}
      {/*
        🔑 **Η οδηγία διαλέγεται από το ΕΙΔΟΣ**, γιατί μόνο το λογότυπο τρίβεται — δες
        {@link SHOWCASE_MARK_ADVICE_KEYS}. Ένα κοινό κείμενο θα έλεγε στον άνθρωπο με τη
        φωτογραφία προσώπου να «αφαιρέσει το κενό γύρω της», που δεν ισχύει ποτέ.
      */}
      {t(SHOWCASE_MARK_ADVICE_KEYS[published.kind])}
    </p>
  );
}

/**
 * **ΠΟΥ ΑΚΡΙΒΩΣ ΘΑ ΦΑΝΕΙ ΘΟΛΟ** — δύο ζώνες, και το πλήθος τους είναι **θεώρημα**.
 *
 * 🔴 **Η ΠΡΩΤΗ ΓΡΑΦΗ ΕΙΧΕ ΔΥΟ ΚΛΑΔΟΥΣ ΚΑΙ ΕΛΕΓΕ ΨΕΜΑΤΑ**, μετρημένο: με
 * `coversCard ? blurryPage : blurryEverywhere`, κάθε εικόνα **128-255px** άκουγε *«θολό
 * στη σελίδα»* ενώ η σελίδα **καλυπτόταν**. Η **Α21.9** το διόρθωσε με **τρίτο** μήνυμα.
 *
 * 🔴 **ΚΑΙ ΤΟ ΤΡΙΤΟ ΗΤΑΝ ΝΕΚΡΟΣ ΚΛΑΔΟΣ ΑΠΟ ΤΗ ΓΕΝΝΗΣΗ ΤΟΥ** *(διαγράφηκε στην Α21.13)*: η
 * σελίδα είναι μεγαλύτερη από την κάρτα **και στις δύο** πλευρές, σε **κάθε** σχήμα, άρα
 * `coversPage` **συνεπάγεται** `coversCard`. Ο συνδυασμός *«καλύπτονται και τα δύο, αλλά
 * προειδοποίησε»* **δεν υπάρχει** — είναι η ίδια η αποδοχή, που δεν φτάνει ποτέ εδώ.
 *
 * 🔑 **Ο έλεγχος διαβάζει τα ΔΥΟ κατηγορήματα, ποτέ το ένα**: το `reach` απαντά χωριστά
 * *«καλύπτεται η κάρτα;»* και *«καλύπτεται η σελίδα;»* ακριβώς για να μη χρειάζεται
 * κανείς να μαντέψει το δεύτερο από το πρώτο.
 */
function BlurryReach({ reach }: { readonly reach: ShowcaseMarkReach }): React.JSX.Element {
  const { t } = useTranslation([SHOWCASE_NS]);

  // 🔴 **Το `ideal` είναι ΤΟΥ ΣΗΜΑΤΟΣ, όχι καθολικό** *(Α21.13)*: ένα wordmark 4:1 θέλει
  //    **128** στη μικρή του πλευρά, ένα πορτρέτο **192**. Το παλιό σταθερό `MARK_IDEAL_EDGE`
  //    ζητούσε από τον wordmark **50% παραπάνω απ' όσο χρειάζεται** — οδηγία που «λύνει» το
  //    πρόβλημα ζητώντας δουλειά που δεν χρειαζόταν.
  if (!reach.coversCard) {
    return <>{t(SHOWCASE_MARK_KEYS.blurryEverywhere, { shortest: reach.shortest, ideal: reach.needed })}</>;
  }

  return <>{t(SHOWCASE_MARK_KEYS.blurryPage, { shortest: reach.shortest, ideal: reach.needed })}</>;
}
