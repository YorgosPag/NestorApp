import React from 'react';

import { SearchableCombobox } from '@/components/ui/searchable-combobox';
import type { ComboboxOption } from '@/components/ui/searchable-combobox-types';
import { useTranslation } from '@/i18n/hooks/useTranslation';
import { ALL_OCCUPATIONS, type OccupationOption } from '@/lib/agency/showcase-filter';
import { AGENCY_PUBLIC_NS, DIRECTORY_KEYS } from './agency-directory-labels';

/**
 * 🔴 **ΜΗΔΕΝ ΚΑΘΥΣΤΕΡΗΣΗ — ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ, ΟΧΙ ΠΑΡΑΛΕΙΨΗ** *(ADR-841 §7 Α19.4α)*.
 *
 * Ο SSoT έχει `DEFAULT_DEBOUNCE_MS = 150` και **σωστά**: τον γέννησαν οι λίστες ΔΟΥ/ΚΑΔ,
 * **χιλιάδες** εγγραφές. Εδώ ο πληθυσμός είναι **23 στοιχεία ήδη στη μνήμη** — σάρωση
 * μικροδευτερολέπτων. Το debounce δεν προστατεύει **κανέναν** και ξοδεύει **ολόκληρο** το
 * budget: **150ms > 100ms**, δηλαδή πάνω από το όριο **και** του RAIL *(«complete a
 * transition initiated by user input within 100 ms»)* **και** του Nielsen *(«0.1 second is
 * about the limit for having the user feel that the system is reacting instantaneously»)*.
 *
 * 🔑 Οι μεγάλες πλατφόρμες το αντιγράφουν ομοιόμορφα επειδή **το δικό τους** type-ahead
 * είναι αίτημα δικτύου. Το δικό μας δεν είναι. **Παράμετρος, όχι fork** — οι άλλοι επτά
 * καταναλωτές κρατούν τα 150ms τους.
 */
const IN_MEMORY_NO_DEBOUNCE_MS = 0;

export interface OccupationSelectProps {
  /**
   * ESCO URI, ή `null` = **ΟΛΕΣ**.
   *
   * 🔑 Το sentinel `'all'` **δεν διαρρέει ποτέ** έξω από αυτό το αρχείο — ο καταναλωτής
   * μιλά μόνο σε `string | null`, όπως και το {@link ShowcaseFilters}. Δύο αναπαραστάσεις
   * του «όλα» σε δύο επίπεδα θα ήταν κάτι που κάθε αναγνώστης πρέπει να θυμάται να
   * μεταφράσει.
   */
  readonly value: string | null;
  /**
   * ⚠️ **Παράγονται από τον ΠΛΗΘΥΣΜΟ** *(`occupationOptions`)* — καμία λίστα, πουθενά.
   * Έτσι **καμία επιλογή δεν οδηγεί σε κενό αποτέλεσμα, εξ ορισμού**: Houzz και Thumbtack
   * προσφέρουν υπηρεσίες με **μηδέν** επαγγελματίες στην περιοχή σου.
   */
  readonly options: readonly OccupationOption[];
  /** Η γλώσσα της ετικέτας — από το {@link showcaseLocale}, ποτέ γραμμένη στο χέρι. */
  readonly locale: 'el' | 'en';
  readonly onChange: (occupation: string | null) => void;
}

export function OccupationSelect({
  value,
  options,
  locale,
  onChange,
}: OccupationSelectProps): React.ReactElement {
  const { t } = useTranslation([AGENCY_PUBLIC_NS]);

  /**
   * ⚠️ **Μεμονωμένος πίνακας ανά κατάσταση, όχι ανά απόδοση**: το `SearchableCombobox` έχει
   * το `options` στις εξαρτήσεις του effect συγχρονισμού. Ίδιο σχήμα με το `selector ?? []`
   * που έχει ήδη κοστίσει βρόχο σε αυτό το δέντρο.
   *
   * 🔑 **Το «Όλες οι ειδικότητες» είναι ΓΡΑΜΜΕΝΗ πρώτη γραμμή, όχι υπονοούμενο** *(Φ2)*:
   * το «καθάρισε το φίλτρο» πρέπει να είναι επιλογή που **βλέπεις** — ένα `×` στην άκρη
   * του πεδίου το ξέρει μόνο όποιος το ψάχνει.
   *
   * 🔴 **Το sentinel μένει `'all'`, ΠΟΤΕ `''`** *(CHECK 3.48)*. Το `Popover` δεν έχει τον
   * περιορισμό του Radix `Select`, αλλά το `'all'` **ήδη υπάρχει** στο `showcase-filter`
   * και το `parseShowcaseFilters` **ήδη** το μεταφράζει: δεύτερη αναπαράσταση θα ήταν
   * δεύτερο βιβλίο.
   */
  const comboOptions = React.useMemo<ComboboxOption[]>(
    () => [
      { value: ALL_OCCUPATIONS, label: t(DIRECTORY_KEYS.occupationAll) },
      ...options.map((option) => ({ value: option.escoUri, label: option.label[locale] })),
    ],
    [options, locale, t],
  );

  /*
   * 🔴 **ΤΟ ΤΑΒΑΝΙ ΠΛΑΤΟΥΣ ΤΟ ΒΡΗΚΕ ΤΟ ΠΕΡΠΑΤΗΜΑ, ΟΧΙ ΤΟ TEST** *(2026-09-04, Α4.5)*.
   * Ήταν σκέτο `min-w-56`. Οι ετικέτες ESCO κουβαλούν **και τα δύο γένη** —
   * *«ελαιοχρωματιστής οικοδομών/ελαιοχρωματίστρια οικοδομών»*, **54 χαρακτήρες** — και
   * το πεδίο μεγάλωνε όσο το κείμενο: στη ρίζα **έσπρωξε το κουμπί «Αναζήτηση» σε δεύτερη
   * γραμμή**, τη στιγμή ακριβώς που ο επισκέπτης έπρεπε να το πατήσει. Καμία πύλη δεν
   * ρωτά *«χωράει;»*. ⚠️ Η αιτία **δεν εξαφανίστηκε** επειδή άλλαξε το χειριστήριο — το
   * όριο μετακόμισε από τον πυροδότη στην ετικέτα, που κατέχει πλέον το κουτί.
   *
   * 🔑 **`<label>` που ΠΕΡΙΤΥΛΙΓΕΙ**: τώρα περιτυλίγει πραγματικό `<input>`, άρα η σύνδεση
   * ετικέτας-χειριστηρίου είναι **σιωπηρή** και δεν χρειάζεται `id` — ο SSoT δεν δέχεται.
   * *(Το `BrokeredMandateFields` αναγκάστηκε σε σκέτο `span`, δηλαδή σε χειριστήριο
   * **χωρίς προσβάσιμο όνομα**. Εδώ αποφεύγεται.)*
   */
  return (
    <label className="flex min-w-56 max-w-72 flex-col gap-1 text-sm">
      <span className="font-medium text-foreground">
        {t(DIRECTORY_KEYS.occupationFilterLabel)}
      </span>
      <SearchableCombobox
        value={value ?? ALL_OCCUPATIONS}
        options={comboOptions}
        placeholder={t(DIRECTORY_KEYS.occupationSearchPlaceholder)}
        emptyMessage={t(DIRECTORY_KEYS.occupationSearchEmpty)}
        debounceMs={IN_MEMORY_NO_DEBOUNCE_MS}
        // ⚠️ Η μετάφραση του sentinel γίνεται **εδώ ή στο `parseShowcaseFilters`**, ποτέ
        //    και στα δύο: δύο σημεία μετάφρασης είναι δύο ευκαιρίες να ξεχαστεί.
        //    Το `''` έρχεται από το `handleClear` (το `×`) και σημαίνει το ίδιο: **όλες**.
        onValueChange={(next) =>
          onChange(next === ALL_OCCUPATIONS || next === '' ? null : next)
        }
      />
    </label>
  );
}
