import { valuesOf, type ListingCriteria } from '@/lib/criteria/listing-criteria';
import {
  PRICE_AXIS_OF_OFFER_KIND,
  PRICE_CRITERION_KEYS,
  type PriceCriterionKey,
} from './criteria-filter-groups';

/**
 * Οι άξονες τιμής που **ρωτιούνται τώρα** — ποτέ και οι τρεις μαζί «για σιγουριά».
 *
 * Τρεις κανόνες, με **αυτή** τη σειρά:
 *
 * 1. **Η «Διάθεση» ονομάζει είδη** ⇒ οι αντίστοιχοι άξονες, στη σειρά του λεξιλογίου.
 * 2. **Δεν ονομάζει, αλλά κάποιος άξονας έχει ήδη τιμή** ⇒ αυτοί. 🔑 Ο άνθρωπος το
 *    ζήτησε — μια οθόνη που έκρυβε φίλτρο **ενεργό** θα το άφηνε να κόβει αποτελέσματα
 *    **αόρατα**, που είναι χειρότερο από το να λείπει.
 * 3. **Τίποτα από τα δύο** ⇒ **κανένας**, και η οθόνη ρωτά «διάλεξε διάθεση».
 *
 * ⚠️ **Η σειρά είναι πάντα του `PRICE_CRITERION_KEYS`**, ποτέ της επιλογής του ανθρώπου:
 * δύο ταυτόσημες αναζητήσεις οφείλουν να δίνουν την **ίδια** γραμμή φίλτρων.
 */
export function visiblePriceAxes(criteria: ListingCriteria): readonly PriceCriterionKey[] {
  const offerKinds = valuesOf(criteria, 'offerKind') ?? [];

  if (offerKinds.length > 0) {
    const wanted = new Set(
      offerKinds.map((kind) => PRICE_AXIS_OF_OFFER_KIND[kind]).filter((key) => key !== undefined),
    );
    return PRICE_CRITERION_KEYS.filter((key) => wanted.has(key));
  }

  return PRICE_CRITERION_KEYS.filter((key) => criteria[key] !== undefined);
}
