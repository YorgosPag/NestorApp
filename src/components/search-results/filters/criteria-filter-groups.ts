import {
  LISTING_ATTRIBUTE_GROUP,
  LISTING_ATTRIBUTE_GROUPS,
} from '@/lib/listings/listing-attribute-groups';
import {
  LISTING_CRITERION_KEYS,
  type CriterionKey,
} from '@/lib/criteria/listing-criterion-asking';
import {
  BESPOKE_CRITERION_GROUP,
  type CriterionGroup,
} from '@/lib/criteria/listing-criterion-labels';

/**
 * **Τα τέσσερα του πρώτου επιπέδου, στη σειρά που διαβάζονται.**
 *
 * ⚠️ **Τέσσερα και όχι έξι**: το Baymard λέει «5–10 χαρακτηριστικά μπροστά» για
 * καταλόγους με **δεκάδες** όψεις και πλατιά οθόνη· εδώ η γραμμή κάθεται πάνω από
 * χάρτη **και** λίστα, όπου κάθε σειρά που καταλαμβάνει είναι **χαμένη επιφάνεια
 * χάρτη** (το ίδιο επιχείρημα με το `data-shell-surface="bleed"`).
 *
 * 🔑 `satisfies readonly CriterionKey[]` ⇒ ένα κλειδί που παύει να είναι άξονας
 * **δεν μεταγλωττίζεται** εδώ. Η λίστα είναι **υποσύνολο με λόγο**, όχι δεύτερος
 * κατάλογος αξόνων.
 */
export const PRIMARY_CRITERION_KEYS = [
  'offerKind',
  'price',
  'type',
  'bedrooms',
] as const satisfies readonly CriterionKey[];

/** Μια ομάδα του πάνελ, **με τα μέλη της**. */
export interface CriteriaFilterGroup {
  readonly group: CriterionGroup;
  readonly keys: readonly CriterionKey[];
}

/**
 * **Οι έξι ομάδες του πάνελ, με τα μέλη καθεμιάς.**
 *
 * 🔴 **ΠΑΡΑΓΕΤΑΙ, ΔΕΝ ΓΡΑΦΕΤΑΙ.** Τα μέλη προκύπτουν από φιλτράρισμα των
 * {@link LISTING_CRITERION_KEYS} πάνω στο {@link LISTING_ATTRIBUTE_GROUP} — δηλαδή
 * **δύο υπάρχοντες** πίνακες, κανένας τρίτος. Μια χειρόγραφη λίστα εδώ θα ήταν η
 * **τέταρτη** δήλωση της ίδιας διάταξης, και θα έμενε πίσω την ημέρα που γεννιέται
 * νέο δημόσιο στοιχείο: ο μεταγλωττιστής θα το απαιτούσε στους τρεις πίνακες και
 * **όχι** εδώ, άρα θα έλειπε **σιωπηλά από την οθόνη**.
 *
 * ⚠️ **Η σειρά μέσα στην ομάδα είναι η σειρά του `LISTING_CRITERION_KEYS`**, που είναι
 * η σειρά του `LISTING_DISCLOSURE` — η **ίδια** σειρά με την οθόνη 3. Δύο οθόνες που
 * δείχνουν τα ίδια πεδία με άλλη σειρά είναι δύο διαφορετικά προϊόντα.
 *
 * 🔑 **Η έκτη ομάδα είναι ΤΕΛΕΥΤΑΙΑ**: οι ειδικοί άξονες *(διάθεση · τιμή · συγγραφή ·
 * φωτογραφίες)* περιγράφουν την **αγγελία**, όχι το **ακίνητο**. Ο άνθρωπος ψάχνει
 * σπίτι· η ταυτότητα της καταχώρησης είναι το τελευταίο που τον απασχολεί.
 */
export const CRITERIA_FILTER_GROUPS: readonly CriteriaFilterGroup[] = [
  ...LISTING_ATTRIBUTE_GROUPS.map((group) => ({
    group: group as CriterionGroup,
    keys: LISTING_CRITERION_KEYS.filter(
      (key) => LISTING_ATTRIBUTE_GROUP[key as keyof typeof LISTING_ATTRIBUTE_GROUP] === group
    ),
  })),
  {
    group: BESPOKE_CRITERION_GROUP,
    // Ό,τι **δεν** πήρε ομάδα από τον πίνακα των δημόσιων στοιχείων — δηλαδή ακριβώς
    // οι ειδικοί άξονες, με **αφαίρεση** και όχι με δεύτερη απαρίθμηση.
    keys: LISTING_CRITERION_KEYS.filter(
      (key) => LISTING_ATTRIBUTE_GROUP[key as keyof typeof LISTING_ATTRIBUTE_GROUP] === undefined
    ),
  },
];
