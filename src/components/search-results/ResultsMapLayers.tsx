'use client';

/**
 * # ΤΑ ΕΠΙΠΕΔΑ ΤΟΥ ΧΑΡΤΗ — **Η ΖΩΓΡΑΦΙΚΗ, ΧΩΡΙΣ ΤΗ ΣΥΜΠΕΡΙΦΟΡΑ** (ADR-777 §8.63)
 *
 * 🔴 **ΕΞΗΧΘΗ ΑΠΟ ΤΟ `ResultsMap.tsx` ΓΙΑΤΙ ΕΚΕΙΝΟ ΠΕΡΑΣΕ ΤΟ ΟΡΙΟ.** Με την προσθήκη
 * του ακροατή `moveend` το αρχείο έφτασε **564** γραμμές — πάνω από το όριο των 500
 * (N.7.1), που είναι **δεσμευτικό στο pre-commit**, όχι σύσταση.
 *
 * 🔑 **Η κοπή δεν είναι αριθμητική.** Ο `ResultsMap` απαντά *«τι κάνει ο χάρτης όταν
 * τον αγγίξεις»* — κλικ, δείκτης, κίνηση, καδράρισμα. Αυτό εδώ απαντά *«πώς μοιάζει
 * κάθε κατηγορία γνώσης»*, και είναι η **οπτική έκφραση της Α5**: ένα σχήμα ανά
 * σκαλί ακρίβειας, ποτέ πινέζα πάνω σε πόλη. Οι δύο ερωτήσεις αλλάζουν για
 * **διαφορετικούς** λόγους και σε διαφορετικές συνεδρίες.
 *
 * ⚠️ **ΤΑ `id` ΤΩΝ ΕΠΙΠΕΔΩΝ ΕΙΝΑΙ ΣΥΜΒΟΛΑΙΟ, ΟΧΙ ΔΙΑΚΟΣΜΗΣΗ.** Ο `ResultsMap` δένει
 * κλικ/δείκτη πάνω τους ονομαστικά (`CLICKABLE_LAYER_IDS`), και το
 * `queryRenderedFeatures` ρωτά **την ίδια** λίστα. Μετονομασία εδώ **χωρίς** εκεί
 * αφήνει τον χάρτη ζωντανό και **σιωπηλά αδιάφορο στο κλικ**.
 *
 * ⚠️ **Η σειρά των επιπέδων ΕΙΝΑΙ η σειρά του βαψίματος** (MapLibre: πρώτο = από
 * κάτω). Οι σκιασμένες περιοχές μπαίνουν **πρώτες** ώστε οι πινέζες να μη θάβονται
 * κάτω τους, και οι δύο δακτύλιοι επισήμανσης **τελευταίοι** ώστε να φαίνονται πάνω
 * από κάθε σχήμα.
 */

import React from 'react';
import { Layer } from '@/lib/maps/maplibre';
import type { ListingFocus } from '@/lib/listings/listing-focus';

/**
 * Ακτίνες σε **pixel**. **Κατηγορικά διακριτές**, όχι διαβαθμίσεις που μοιάζουν.
 *
 * 🔴 **ΓΝΩΣΤΗ ΑΠΟΚΛΙΣΗ, ΚΑΤΑΓΡΑΜΜΕΝΗ ΑΝΤΙ ΝΑ ΚΡΥΒΕΤΑΙ** *(ADR-777 §8.63)*: αυτοί οι
 * αριθμοί είναι **οθόνης**, ενώ ο `LISTING_UNCERTAINTY_KM` — που κρίνει πλέον ποια
 * αγγελία είναι «μέσα», «ίσως» ή «έξω» — είναι σε **μέτρα του κόσμου**. Συνέπεια: ο
 * κύκλος «συνοικία» των 34px καλύπτει δεκάδες χιλιόμετρα στο ζουμ 10 και λίγα μέτρα
 * στο ζουμ 18, δηλαδή **ο ίδιος ισχυρισμός αλλάζει μέγεθος με το ζουμ**.
 *
 * ⚠️ **Το ελάττωμα ΠΡΟΫΠΗΡΧΕ** — δεν το γέννησε το φιλτράρισμα· το φιλτράρισμα το
 * **έκανε ορατό**, δίνοντας για πρώτη φορά στην αβεβαιότητα μέγεθος ανεξάρτητο του
 * ζουμ. Η σωστή διόρθωση είναι **ο ζωγράφος να πλησιάσει τον κριτή**, ποτέ το
 * αντίστροφο. Καταγράφεται στο `.claude-rules/pending-ratchet-work.md`.
 *
 * 🔑 **Εξάγεται επειδή έχει ΔΕΥΤΕΡΟ καταναλωτή**: οι πινακίδες τιμών στοιχίζονται
 * πάνω από την πινέζα και χρειάζονται **την ίδια** ακτίνα (`pinRadiusPx`). Δύο
 * αντίγραφα του «7» θα ήταν δύο απαντήσεις στο *«πόσο μεγάλη είναι η πινέζα;»*, και
 * η μέρα που θα διαφωνούσαν θα εμφανιζόταν ως πινακίδα που ακουμπά το σχήμα της.
 */
export const RADIUS = { pin: 7, ring: 7, neighbourhood: 34, city: 90 } as const;

interface ResultsMapLayersProps {
  /** Το χρώμα σήμανσης, **ήδη λυμένο σε συγκεκριμένο χρώμα** — το MapLibre δεν δέχεται `hsl(var(--x))`. */
  readonly mark: string;
  /** Το χρώμα της επιφάνειας, για τα κενά κέντρα των δακτυλίων. */
  readonly surface: string;
  /** **Οι δύο ερωτήσεις της εστίασης** — «κοιτάζω» και «διάλεξα», ποτέ μία με «ή». */
  readonly focus: ListingFocus;
}

/**
 * Τα επτά επίπεδα σχημάτων + τα δύο επισήμανσης.
 *
 * ⚠️ **Αποδίδεται ΜΕΣΑ σε `<Source>`** — τα `<Layer>` του MapLibre χρειάζονται τη
 * γεωμετρία του γονιού τους. Έξω από αυτό δεν σπάει· απλώς **δεν ζωγραφίζει τίποτα**.
 */
export function ResultsMapLayers({ mark, surface, focus }: ResultsMapLayersProps) {
  return (
    <>
      {/* ΜΟΝΟ ΠΟΛΗ — σκιασμένη περιοχή. ΠΟΤΕ πινέζα (Α5). */}
      <Layer
        id="listing-city"
        type="circle"
        filter={['==', ['get', 'shape'], 'shaded-city']}
        paint={{ 'circle-radius': RADIUS.city, 'circle-color': mark, 'circle-opacity': 0.12,
                 'circle-stroke-width': 1, 'circle-stroke-color': mark, 'circle-stroke-opacity': 0.35 }}
      />
      {/* ΣΥΝΟΙΚΙΑ — μικρότερος σκιασμένος κύκλος (πρότυπο Airbnb). */}
      <Layer
        id="listing-neighbourhood"
        type="circle"
        filter={['==', ['get', 'shape'], 'shaded-circle']}
        paint={{ 'circle-radius': RADIUS.neighbourhood, 'circle-color': mark, 'circle-opacity': 0.18,
                 'circle-stroke-width': 1, 'circle-stroke-color': mark, 'circle-stroke-opacity': 0.5 }}
      />
      {/* ΜΕΤΡΗΜΕΝΟ ΠΕΡΙΓΡΑΜΜΑ — πραγματικό σχήμα, γεμάτο + περίγραμμα. */}
      <Layer
        id="listing-outline-fill"
        type="fill"
        filter={['==', ['get', 'shape'], 'outline']}
        paint={{ 'fill-color': mark, 'fill-opacity': 0.3 }}
      />
      <Layer
        id="listing-outline-line"
        type="line"
        filter={['==', ['get', 'shape'], 'outline']}
        paint={{ 'line-color': mark, 'line-width': 2 }}
      />
      {/* ΔΡΟΜΟΣ ΧΩΡΙΣ ΑΡΙΘΜΟ — πινέζα με ΔΑΚΤΥΛΙΟ: κενό κέντρο, παχύ περίγραμμα. */}
      <Layer
        id="listing-pin-ring"
        type="circle"
        filter={['==', ['get', 'shape'], 'pin-with-ring']}
        paint={{ 'circle-radius': RADIUS.ring, 'circle-color': surface, 'circle-opacity': 1,
                 'circle-stroke-width': 3, 'circle-stroke-color': mark }}
      />
      {/* ΑΚΡΙΒΗΣ ΔΙΕΥΘΥΝΣΗ — συμπαγής πινέζα. */}
      <Layer
        id="listing-pin"
        type="circle"
        filter={['==', ['get', 'shape'], 'pin']}
        paint={{ 'circle-radius': RADIUS.pin, 'circle-color': mark, 'circle-opacity': 1,
                 'circle-stroke-width': 2, 'circle-stroke-color': surface }}
      />
      {/*
        ────────────────────────────────────────────────────────────────────
        🔴 ΔΥΟ ΕΠΙΠΕΔΑ ΕΠΙΣΗΜΑΝΣΗΣ, ΓΙΑΤΙ ΥΠΑΡΧΟΥΝ ΔΥΟ ΕΡΩΤΗΣΕΙΣ
        ────────────────────────────────────────────────────────────────────

        Ήταν **ένα** (`listing-highlight`), τροφοδοτημένο από μία μεταβλητή που
        σήμαινε ταυτόχρονα «κοιτάζω» και «διάλεξα» — άρα ο χάρτης **δεν μπορούσε** να
        δείξει και τα δύο, και η επιλογή έσβηνε με το πρώτο πέρασμα του ποντικιού.

        🏆 Το **Revit** το λύνει έτσι εδώ και δεκαετίες: το *pre-highlight* και η
        *selection* έχουν **δικό τους** χρώμα, και ο μηχανικός βλέπει με μια ματιά τι
        **κοιτάζει** και τι **κρατά**. Το ίδιο κάνει το Airbnb όταν κρατά την επιλογή
        σου ορατή ενώ σαρώνεις αλλού τον χάρτη.

        ⚠️ **ΚΑΙ ΤΑ ΔΥΟ ΕΙΝΑΙ ΔΑΚΤΥΛΙΟΙ ΓΥΡΩ, ΠΟΤΕ ΑΛΛΑΓΗ ΤΟΥ ΣΧΗΜΑΤΟΣ.** Η
        επισήμανση απαντά «ποιο κοιτάς», η ακρίβεια «τι ξέρουμε» — δύο ερωτήματα, δύο
        κανάλια· αλλιώς το hover θα έλεγε ψέματα για τη γνώση μας (Α5).

        ⚠️ **Ξεχωρίζουν σε ΓΕΩΜΕΤΡΙΑ, όχι σε απόχρωση** (CHECK 3.41 / WCAG 1.4.1): ο
        εφήμερος δακτύλιος είναι **λεπτός και μικρότερος**, ο επίμονος **παχύς,
        μεγαλύτερος και με γέμισμα**. Η διαφορά επιβιώνει σε ασπρόμαυρη εκτύπωση.

        🔴 **ΤΟ ΣΗΜΕΙΟ ΑΝΑΦΟΡΑΣ «ΚΑΝΕΝΑ» ΗΤΑΝ ΚΥΡΙΟΛΕΚΤΙΚΑ ΕΝΑ NUL BYTE** — βρέθηκε
        εδώ, 2026-09-06. Το `?? ' '` που **φαινόταν** κενό διάστημα ήταν `U+0000`, και
        η συνέπεια δεν ήταν οπτική αλλά **εργαλειακή**: το git κατέτασσε ολόκληρο το
        αρχείο ως **δυαδικό** (`Binary file … matches`), δηλαδή **καμία σύγκριση,
        καμία συγχώνευση, καμία αναθεώρηση γραμμής**. Πλέον είναι το **κενό
        αλφαριθμητικό**, που καμία ταυτότητα δεν μπορεί να πάρει (ADR-017: τα
        enterprise IDs έχουν πρόθεμα, ποτέ δεν είναι κενά).
      */}
      <Layer
        id="listing-peek"
        type="circle"
        filter={['==', ['get', 'id'], focus.peeked ?? '']}
        paint={{ 'circle-radius': RADIUS.pin + 6, 'circle-color': mark, 'circle-opacity': 0,
                 'circle-stroke-width': 2, 'circle-stroke-color': mark, 'circle-stroke-opacity': 0.55 }}
      />
      <Layer
        id="listing-selected"
        type="circle"
        filter={['==', ['get', 'id'], focus.selected ?? '']}
        paint={{ 'circle-radius': RADIUS.pin + 11, 'circle-color': mark, 'circle-opacity': 0.12,
                 'circle-stroke-width': 4, 'circle-stroke-color': mark, 'circle-stroke-opacity': 1 }}
      />
    </>
  );
}
