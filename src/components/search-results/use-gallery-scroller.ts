'use client';

/**
 * @fileoverview **ΠΩΣ ΚΥΛΑ Ο ΚΥΛΙΝΔΡΟΣ** — η μηχανική της γκαλερί, χωρίς καθόλου όψη.
 * @related ADR-777 §8.57 · §8.58.7 · ADR-040 (κανόνας 2: ανάγνωση τη στιγμή του συμβάντος)
 * @module components/search-results/use-gallery-scroller
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 🔑 ΓΙΑΤΙ ΕΦΥΓΕ ΑΠΟ ΤΟ `ListingCardGallery` — ΚΑΙ ΓΙΑΤΙ **ΟΛΟΚΛΗΡΟ**
 * ════════════════════════════════════════════════════════════════════════════
 *
 * Το `ListingCardGallery.tsx` έφτασε **552 γραμμές** και η πύλη μεγεθών (N.7.1, CHECK 4)
 * το μπλόκαρε. Η θεραπεία ήταν **ΕΞΑΓΩΓΗ, ποτέ κόψιμο σχολίων**: κάθε γραμμή
 * τεκμηρίωσης εδώ ήρθε **αυτούσια** από εκεί, γιατί κάθε μία της καταγράφει **μέτρηση**
 * *(«γράφτηκε πρώτα με διπλό rAF και έμεινε κι αυτός νεκρός»)*. Ένα σχόλιο που λέει
 * γιατί απέτυχε η προηγούμενη γραφή είναι το **μόνο** πράγμα που εμποδίζει τον επόμενο
 * να την ξαναγράψει.
 *
 * 🔑 **Η ΤΟΜΗ ΔΕΝ ΕΙΝΑΙ ΑΥΘΑΙΡΕΤΗ**: εδώ ζει ό,τι απαντά *«πού βρίσκεται ο κύλινδρος
 * και πώς πάει αλλού»* — τρία effects και ένας μετακινητής. Στο component μένει ό,τι
 * απαντά *«τι βλέπει ο άνθρωπος»* — τα slides, τα βελάκια, οι τελείες. Καμία γραμμή δεν
 * χρειάστηκε να αλλάξει για να περάσει το σύνορο: αν χρειαζόταν, η τομή θα ήταν λάθος.
 *
 * ⚠️ **ΚΑΙ ΤΟ ΑΡΧΕΙΟ ΔΕΝ ΕΧΕΙ ΟΨΗ ΕΠΙΤΗΔΕΣ** — κανένα JSX, κανένα `t()`, κανένα
 * `className`. Ο έλεγχος *«ανήκει αυτό εδώ;»* είναι μηχανικός: αν χρειάζεσαι μετάφραση
 * ή κλάση, ανήκει στο component.
 */

import { useCallback, useEffect, useLayoutEffect, useRef, useState } from 'react';
import type { MutableRefObject } from 'react';

import { notePhotoPosition, forgetPhotoPosition } from '@/lib/listings/listing-photo-position';

/** Πόσο ορατό πρέπει να είναι ένα slide για να θεωρηθεί «αυτό που βλέπω». */
const VISIBLE_THRESHOLD = 0.6;

interface GalleryScrollerOptions {
  /** Πόσα slides υπάρχουν **τώρα** — ο κύλινδρος δεν ξέρει τι δείχνουν. */
  readonly total: number;
  /**
   * Ο **σπόρος** της θέσης (ADR-777 §8.58.7) — δες το `startAt` παρακάτω για το γιατί
   * παγώνει στην πρώτη απόδοση αντί να παρακολουθείται.
   */
  readonly initialIndex: number;
  /**
   * Η ταυτότητα με την οποία **δηλώνεται** η θέση, ή `undefined` για σιωπή.
   *
   * ⚠️ Το όνομα είναι ρητά **γραφέας** και όχι κοινό `listingId`: το ερώτημα *«ποιος
   * γράφει και ποιος διαβάζει;»* απαντιέται **στο σημείο κλήσης** (§8.58.7).
   */
  readonly reportPositionAs?: string;
}

interface GalleryScroller {
  /** Μπαίνει στο `<ul>` που κυλά — **αυτό** είναι η μία αλήθεια της θέσης. */
  readonly scrollerRef: MutableRefObject<HTMLUListElement | null>;
  /** Ο δείκτης **για την οθόνη** (τελείες, `aria-current`) — παράγωγο, ποτέ εντολή. */
  readonly index: number;
  /** Πήγαινε στο slide `next` — με **λούπα**, ποτέ ψαλίδισμα. */
  readonly goTo: (next: number) => void;
}

/**
 * Ο κύλινδρος της γκαλερί: πού είναι, πώς πάει αλλού, και τι δηλώνει φεύγοντας.
 */
export function useGalleryScroller({
  total,
  initialIndex,
  reportPositionAs,
}: GalleryScrollerOptions): GalleryScroller {
  const scrollerRef = useRef<HTMLUListElement | null>(null);
  /**
   * 🔑 **Η ΑΡΧΙΚΗ ΘΕΣΗ ΠΑΓΩΝΕΙ ΣΤΗΝ ΠΡΩΤΗ ΑΠΟΔΟΣΗ, ΚΑΙ ΤΟ `useRef` ΕΙΝΑΙ Ο ΜΗΧΑΝΙΣΜΟΣ.**
   *
   * Χωρίς αυτό, κάθε αλλαγή του `initialIndex` από τον γονέα θα ήταν **δεύτερος
   * γραφέας** — ακριβώς ο συγχρονισμός που το §8.58.7 απέρριψε. Με αυτό, το prop είναι
   * **σπόρος**, όχι εντολή: ό,τι γράφει μετά την προσάρτηση αγνοείται **δομικά**, όχι
   * κατά σύμβαση.
   */
  const startAt = useRef(initialIndex).current;
  const [index, setIndex] = useState(startAt);

  /*
    🔑 **Ο ΔΕΙΚΤΗΣ ΠΑΡΑΓΕΤΑΙ, ΔΕΝ ΔΗΛΩΝΕΤΑΙ.** Το `useState` εδώ **δεν είναι** η θέση:
    είναι **αντίγραφο για την οθόνη** αυτού που ήδη ισχύει στο DOM. Γι' αυτό ο μόνος
    γραφέας του είναι ο παρατηρητής — κανένα κουμπί δεν το γράφει απευθείας. Αν το
    έγραφαν και τα δύο, θα υπήρχαν **δύο** αλήθειες και θα απέκλιναν στην πρώτη
    διακοπτόμενη κύλιση (ο άνθρωπος σέρνει ενώ τρέχει το smooth scroll του κουμπιού).
  */
  /**
   * **Η ΚΛΗΡΟΝΟΜΙΑ ΑΡΧΙΚΗΣ ΘΕΣΗΣ** (ADR-777 §8.58.7) — ο άνθρωπος που ξεφύλλισε στην
   * κάρτα και πάτησε την πινέζα **δεν χάνει τη θέση του**.
   *
   * 🔴 **`useLayoutEffect` ΚΑΙ ΟΧΙ `useEffect`, ΓΙΑ ΔΥΟ ΑΝΕΞΑΡΤΗΤΟΥΣ ΛΟΓΟΥΣ:**
   *
   * 1. **Πριν τη βαφή.** Με `useEffect` ο άνθρωπος θα έβλεπε τη φωτογραφία 1 να
   *    **αναπηδά** στην 4η — δηλαδή θα φαινόταν σφάλμα, όχι συνέχεια.
   * 2. 🔑 **Πριν τον παρατηρητή.** Τα `useLayoutEffect` τρέχουν **πριν** από κάθε
   *    `useEffect`, και ο `IntersectionObserver` παρακάτω ζει σε `useEffect`. Αν η σειρά
   *    ήταν αντίστροφη, ο παρατηρητής θα έβλεπε πρώτα το slide 0, θα έγραφε `setIndex(0)`
   *    **και θα το δήλωνε στο store** — δηλαδή η κληρονομιά θα **έσβηνε την ίδια της την
   *    πηγή**.
   *
   * ⚠️ **`behavior: 'auto'` — ποτέ ομαλή κύλιση**: το `scroll-smooth` του δοχείου θα
   * ζωγράφιζε ταξίδι σε κάτι που ο άνθρωπος **δεν ζήτησε**. Και ⛔ **`scrollLeft`, ποτέ
   * `scrollIntoView`**: το δεύτερο κυλά **κάθε πρόγονο** μέχρι τη ρίζα — η μετρημένη
   * αιτία της εξαφάνισης του χάρτη στο §8.56.
   *
   * ⚠️ **Καμία άμυνα για `startAt` εκτός ορίων, επίτηδες**: ο περιηγητής ψαλιδίζει μόνος
   * του το `scrollLeft`, και ο παρατηρητής γράφει αμέσως μετά τον **αληθινό** δείκτη. Ο
   * ένας κριτής των ορίων ζει στο `photoPositionFor(id, total)` — δεύτερος εδώ θα ήταν
   * δεύτερη αλήθεια για το ίδιο ερώτημα.
   */
  useLayoutEffect(() => {
    const scroller = scrollerRef.current;
    if (scroller === null || startAt <= 0 || total < 2) return;

    // `clientWidth` **τη στιγμή του συμβάντος** (κανόνας 2 του ADR-040): η φούσκα του
    // χάρτη και η κάρτα της λίστας έχουν διαφορετικό πλάτος, και η κάρτα το αλλάζει με
    // το παράθυρο. Μηδέν πλάτος ⇒ το στοιχείο δεν έχει ακόμη διάταξη· τότε η σιωπή
    // είναι σωστή, γιατί η εναλλακτική θα ήταν κύλιση κατά **μηδέν**.
    const step = scroller.clientWidth;
    if (step > 0) scroller.scrollTo({ left: startAt * step, behavior: 'auto' });
  }, [startAt, total]);

  useEffect(() => {
    const scroller = scrollerRef.current;
    if (scroller === null || total < 2) return;

    const observer = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (!entry.isIntersecting) continue;
          const position = Number((entry.target as HTMLElement).dataset.slideIndex);
          if (!Number.isInteger(position)) continue;
          setIndex(position);
          /*
            **Ο ΕΝΑΣ ΓΡΑΦΕΑΣ ΤΟΥ SSoT** (ADR-777 §8.58.7) — και ζει **εδώ**, μέσα στον
            παρατηρητή, όχι σε ξεχωριστό effect πάνω στο `index`.

            🔑 Ο λόγος είναι ο κανόνας που ήδη διέπει αυτό το αρχείο: *«ο μόνος γραφέας
            του δείκτη είναι ο παρατηρητής»*. Ένα `useEffect(..., [index])` θα ήταν
            **δεύτερη διαδρομή** προς την ίδια δήλωση, που πυροδοτεί σε άλλη στιγμή.

            ⚠️ Καμία ειδοποίηση, κανένα re-render αλλού — δες την κεφαλίδα του store για
            το γιατί **δεν** έχει συνδρομητές.
          */
          if (reportPositionAs !== undefined) notePhotoPosition(reportPositionAs, position);
        }
      },
      { root: scroller, threshold: VISIBLE_THRESHOLD },
    );

    for (const slide of scroller.children) observer.observe(slide);
    return () => observer.disconnect();
  }, [total, reportPositionAs]);

  /**
   * ⚠️ **Η ΛΗΘΗ ΕΙΝΑΙ ΥΠΟΧΡΕΩΤΙΚΗ, ΚΑΙ ΞΕΧΩΡΙΣΤΗ ΑΠΟ ΤΟΝ ΠΑΡΑΤΗΡΗΤΗ.**
   *
   * Ζει σε **δικό της** effect γιατί έχει **άλλη ζωή**: ο παρατηρητής ξαναστήνεται σε
   * κάθε αλλαγή του `total` *(δηλαδή σβήνει και ξαναγράφει τη γραμμή στο store
   * ενδιάμεσα)*, ενώ η γραμμή πρέπει να σβήσει **μία φορά, όταν φύγει η κάρτα**. Μαζί
   * τους, μια απλή αλλαγή φωτογραφιών θα έσβηνε τη θέση που ο άνθρωπος μόλις διάλεξε.
   *
   * 🔴 Χωρίς αυτό, ο πίνακας μεγαλώνει με **κάθε** αγγελία που πέρασε ποτέ από την
   * οθόνη — διαρροή που καμία δοκιμή δεν βλέπει και μόνο η πραγματική χρήση μεγαλώνει.
   */
  useEffect(() => {
    if (reportPositionAs === undefined) return;
    return () => forgetPhotoPosition(reportPositionAs);
  }, [reportPositionAs]);

  /**
   * ⚠️ `scrollTo` **σε αυτό το στοιχείο**, με το πλάτος του ως βήμα — δες την κεφαλίδα
   * για το γιατί απαγορεύεται το `scrollIntoView`. Το `clientWidth` διαβάζεται **τη
   * στιγμή του συμβάντος**, γιατί η κάρτα αλλάζει πλάτος με το φύλλο/το παράθυρο
   * *(κανόνας 2 του ADR-040: τιμή από αναφορά, ποτέ παγωμένο στιγμιότυπο)*.
   */
  const goTo = useCallback((next: number) => {
    const scroller = scrollerRef.current;
    if (scroller === null) return;
    /*
      🔁 **ΛΟΥΠΑ, ΟΧΙ ΨΑΛΙΔΙΣΜΑ — ΚΑΙ Η ΑΠΟΦΑΣΗ ΕΙΝΑΙ ΤΕΧΝΙΚΗ, ΟΧΙ ΓΟΥΣΤΟ.**
      Η εναλλακτική *(κρύψιμο του βέλους στο άκρο, όπως Airbnb/Zillow)* έχει ελάττωμα
      που κανείς τους δεν λύνει: το κουμπί **εξαφανίζεται ενώ το πληκτρολόγιο βρίσκεται
      πάνω του** — ο άνθρωπος πατά `Enter` στην τελευταία φωτογραφία και η εστίαση πέφτει
      στο `body`, δηλαδή **χάνει τη θέση του μέσα σε λίστα 9 καρτών**. Με λούπα τα δύο
      βελάκια είναι **πάντα εκεί**: καμία αναπήδηση, καμία χαμένη εστίαση, καμία νεκρή
      περιοχή που «δεν κάνει τίποτα».

      🔑 Η γνωστή ένσταση κατά της λούπας *(«ο άνθρωπος δεν μαθαίνει ποτέ ότι τελείωσαν»)*
      **απαντιέται εδώ**: η βιβλιογραφία τη δέχεται ρητά *«εφόσον δείχνεις καθαρά την
      τρέχουσα θέση»*, και οι **τελείες** το κάνουν ακριβώς αυτό, μονίμως ορατές.

      ⚠️ Το `+ total` πριν το δεύτερο `%` είναι υποχρεωτικό: στη JavaScript το `-1 % 2`
      είναι **-1**, όχι 1 — χωρίς αυτό το «προηγούμενη» από την πρώτη θα έστελνε σε
      αρνητική θέση, δηλαδή πουθενά.
    */
    const slides = scroller.children.length;
    const wrapped = ((next % slides) + slides) % slides;
    /*
      🔴 **ΚΑΝΕΝΑ `behavior` ΕΔΩ — ΚΑΙ ΕΙΝΑΙ ΔΙΟΡΘΩΣΗ, ΟΧΙ ΠΑΡΑΛΕΙΨΗ.**
      Γράφτηκε πρώτα ως `scrollTo({ left, behavior: 'smooth' })` και **μετρήθηκε ζωντανά
      ότι ΔΕΝ ΚΙΝΕΙ ΤΙΠΟΤΑ**: ο handler εκτελούνταν σωστά (επαληθεύτηκε με περιτύλιξη
      του `scrollTo` — η κλήση κατέγραψε `{"left":362,"behavior":"smooth"}`), αλλά το
      `scrollLeft` έμενε **0**. Η ίδια κλήση με `behavior: 'auto'` πήγαινε στο **361**
      ακαριαία, και το ίδιο συνέβαινε **απευθείας από την κονσόλα** ⇒ το ελάττωμα δεν
      ήταν ο κώδικας, ήταν το `behavior: 'smooth'` σε αυτόν τον κύλινδρο.

      🔑 Η ομαλότητα μετακόμισε στο **CSS** (`scroll-smooth` + `motion-reduce:scroll-auto`
      στον κύλινδρο), και το σχήμα είναι **fail-safe**: αν η ομαλή κύλιση δεν είναι
      διαθέσιμη για οποιονδήποτε λόγο, το `scrollTo` γίνεται **ακαριαίο** — ο άνθρωπος
      πάει στη φωτογραφία **χωρίς animation**, αντί να μην πάει **καθόλου**. Η
      προηγούμενη γραφή απέτυχε **σιωπηλά και ολοκληρωτικά**· αυτή δεν μπορεί.

      ⚠️ Και το `prefers-reduced-motion` απαντιέται **καλύτερα** έτσι: το CSS media query
      αντιδρά σε αλλαγή της ρύθμισης **χωρίς επανα-απόδοση**, ενώ μια τιμή διαβασμένη σε
      JS παγώνει μέχρι το επόμενο render.
    */
    const target = wrapped * scroller.clientWidth;
    const startedAt = scroller.scrollLeft;
    scroller.scrollTo({ left: target });

    /*
      🔴 **ΦΡΟΥΡΟΣ: Η ΚΙΝΗΣΗ ΕΙΝΑΙ ΠΡΟΑΙΡΕΤΙΚΗ, Η ΜΕΤΑΒΑΣΗ ΥΠΟΧΡΕΩΤΙΚΗ.**
      Μετρήθηκε ζωντανά ότι η ομαλή κύλιση μπορεί να **μην κάνει απολύτως τίποτα**: με
      `scroll-behavior: smooth` το `scrollLeft` έμενε **0**, ενώ η **ίδια** κλήση με
      `auto` πήγαινε στο **361**. Επαληθεύτηκε ότι δεν έφταιγε ο handler (η περιτύλιξη
      του `scrollTo` κατέγραψε τη σωστή κλήση) ούτε το `prefers-reduced-motion`
      (μετρήθηκε `false`) — **η ρίζα ήταν `document.visibilityState === 'hidden'`**: ο
      Chrome παγώνει κάθε ομαλή κύλιση σε κρυμμένη καρτέλα.

      🔑 Δύο καρέ αργότερα ρωτάμε το **μόνο πράγμα που μετράει**: *κουνήθηκε;* Αν όχι,
      πηγαίνουμε ακαριαία. Ο άνθρωπος βλέπει τη φωτογραφία που ζήτησε — με ή χωρίς
      animation — και ποτέ «τίποτα». Belt-and-suspenders (N.7.2 #4).

      ⚠️ **`setTimeout` ΚΑΙ ΟΧΙ `requestAnimationFrame`, ΚΑΙ ΤΟ ΕΜΑΘΑ ΜΕ ΜΕΤΡΗΣΗ.** Ο
      φρουρός γράφτηκε πρώτα με διπλό `rAF` *(το ιδίωμα του §8.56.4)* και **έμεινε κι
      αυτός νεκρός**: τα animation frames παγώνουν στην **ίδια ακριβώς** συνθήκη που
      παγώνει το smooth scroll — δηλαδή ο φρουρός ήταν **δομικά ανίκανος** να πιάσει
      τη μόνη περίπτωση για την οποία γράφτηκε. Οι χρονομετρητές εξακολουθούν να
      τρέχουν *(με στραγγαλισμό)*, άρα ο έλεγχος συμβαίνει **πάντα**.

      ⚠️ Τα **120ms** δεν είναι στρογγυλοποίηση: είναι αρκετά ώστε ένα ζωντανό smooth
      scroll να έχει **ήδη ξεκινήσει** (άρα ο φρουρός μένει αδρανής), και αρκετά λίγα
      ώστε η διόρθωση να μη διαβάζεται ως καθυστέρηση.
    */
    window.setTimeout(() => {
      const moved = Math.abs(scroller.scrollLeft - startedAt) >= 1;
      const wanted = Math.abs(target - startedAt) >= 1;
      if (!wanted || moved) return;
      /*
        ⚠️ **Η ΠΑΡΑΚΑΜΨΗ ΤΟΥ `scroll-behavior` ΕΙΝΑΙ ΥΠΟΧΡΕΩΤΙΚΗ, ΚΑΙ ΤΟ ΕΜΑΘΑ ΜΕ
        ΜΕΤΡΗΣΗ.** Ο φρουρός δοκιμάστηκε ως σκέτο `scroller.scrollLeft = target` και
        **έμεινε κι αυτός στο 0**: το CSS `scroll-behavior: smooth` δεν αφορά μόνο το
        `scrollTo` — κάνει ομαλή **κάθε** προγραμματιστική κύλιση, **συμπεριλαμβανομένης
        της ανάθεσης** `scrollLeft`. Δηλαδή έπεφτε στην ίδια παγίδα που φτιάχτηκε να
        πιάσει. Η στιγμιαία απενεργοποίηση είναι ο **μόνος** τρόπος να εγγυηθεί κανείς
        τη μετάβαση.
      */
      const previous = scroller.style.scrollBehavior;
      scroller.style.scrollBehavior = 'auto';
      scroller.scrollLeft = target;
      scroller.style.scrollBehavior = previous;
    }, 120);
  }, []);

  return { scrollerRef, index, goTo };
}
