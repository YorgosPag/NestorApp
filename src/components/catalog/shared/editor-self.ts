/**
 * **«Είναι αυτή η εγγραφή ο ΕΑΥΤΟΣ του επεξεργαστή;»** — η μία απάντηση για κάθε έλεγχο «νέα/υπάρχουσα απέναντι στη
 * συλλογή» (διπλός κωδικός · ασάφεια κοινού), ADR-923 §5.11 «3δ» (ζωντανή επαλήθευση, Σ2).
 * @related use-definition-draft.ts (`created`: ό,τι έστειλε ο ίδιος ο επεξεργαστής) · catalog-actions.ts (`newEntityKey`)
 * @module components/catalog/shared/editor-self
 *
 * 🔴 **Γιατί υπάρχει** (μετρημένο ζωντανά, «MFP Λιανική»): μετά το «Αποθήκευση» μιας **νέας** λίστας η φόρμα έμενε «νέα»
 *    — όσο εκκρεμούσε το POST (η αισιόδοξη `new:<κωδικός>` ήταν ήδη στη συλλογή) **και** ώσπου να αλλάξει η διεύθυνση
 *    μετά την απάντηση (η αποθηκευμένη, με το id του διακομιστή) — και συγκρουόταν **με τον εαυτό της**:
 *    «Υπάρχει ήδη τιμοκατάλογος πώλησης για το ίδιο κοινό». Ο έλεγχος `other.id !== record?.id` δεν μπορεί να το δει:
 *    για νέα οντότητα το `record` είναι `null`.
 * 🔑 Υπάρχουσα ⇒ ίδιο id. Νέα ⇒ ίδιος **κωδικός** με αυτό που ο επεξεργαστής **έστειλε** (όχι με ό,τι γράφει τώρα): ο
 *    κωδικός ΕΙΝΑΙ η ταυτότητα — αισιόδοξο κλειδί `new:<κωδικός>`, id του διακομιστή ντετερμινιστικό από χώρο + κωδικό.
 *    Πριν από την αποστολή (`created === null`) τίποτα δεν είναι εαυτός ⇒ ο πραγματικός διπλός κωδικός πιάνεται κανονικά.
 */

interface Identified {
  readonly id: string;
  readonly code: string;
}

/** `record` = η αποθηκευμένη (`null` = νέα) · `created` = ό,τι έστειλε ο επεξεργαστής ως νέα (`null` = τίποτα ακόμη). */
export function isEditorSelf(
  other: Identified,
  record: { readonly id: string } | null,
  created: { readonly code: string } | null,
): boolean {
  if (record !== null) return other.id === record.id;
  return created !== null && other.code === created.code;
}
