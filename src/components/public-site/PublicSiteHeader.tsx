'use client';

/**
 * **Η κεφαλίδα του δημόσιου ιστότοπου** — τρεις πόρτες, μία πράξη, καμία υπόσχεση.
 *
 * @related ADR-777 §8.13 (η δημόσια ρίζα) · Α3 · CHECK 3.52
 * @module components/public-site/PublicSiteHeader
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ: ΚΑΝΕΝΑ ΑΚΡΟΑΤΗΡΙΟ ΔΕΝ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΧΑΣΕΙ ΤΗΝ ΠΟΡΤΑ ΤΟΥ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Πριν: το `/` σέρβιρε το ταμπλό ⇒ **ο επαγγελματίας είχε πόρτα** (σύνδεση) και **ο
 * ιδιώτης καμία**. Η αφελής ανταλλαγή —«κάνε το `/` δημόσιο»— απλώς **αντιστρέφει**
 * το ελάττωμα: ο επαγγελματίας που πληκτρολογεί nestorconstruct.gr δεν θα έβρισκε
 * τρόπο να μπει στον χώρο του. Η κεφαλίδα υπάρχει ώστε η μετακόμιση να είναι
 * **προσθήκη πόρτας**, όχι μετακίνησή της.
 *
 * ✅ **Η ΠΟΡΤΑ «ΖΗΤΩ» ΑΝΟΙΞΕ (2026-08-11).** Μέχρι τότε αυτό το σχόλιο έγραφε ότι
 * λείπει *«επίτηδες»*, γιατί η **Α9** δεν είχε ούτε διαδρομή ούτε οντότητα ⇒ σύνδεσμος
 * εκεί θα ήταν **404**, και *«μια πόρτα που δεν ανοίγει είναι χειρότερη από καμία
 * πόρτα»*. Πλέον υπάρχουν και τα δύο (`/demands`, `dmnd_*`), οπότε η σιωπή **έπαψε να
 * είναι αλήθεια** — και μια δηλωμένη σιωπή που δεν ενημερώνεται γίνεται το σχόλιο που
 * λέει ψέματα (σχήμα CHECK 3.47: *«το σχόλιο ΕΛΕΓΕ ΨΕΜΑΤΑ»*).
 *
 * ✅ **ΚΑΙ Η ΠΟΡΤΑ «ΠΡΟΣΦΕΡΩ» ΑΝΟΙΞΕ (2026-08-11, Α14).** Ο κανόνας δεν χαλάρωσε ποτέ:
 * απαιτούσε **διαδρομή** και **οντότητα**, και πλέον υπάρχουν και οι δύο (`/offers`,
 * `ownp_*`). Οι **δύο** πόρτες του ιδιώτη είναι πλέον συμμετρικές — «ζητώ» και
 * «προσφέρω» — και μαζί με τη «σύνδεση» του επαγγελματία καλύπτουν **και τα τρία**
 * ακροατήρια που περνούν από αυτή τη γραμμή.
 *
 * 🔑 **Η ΠΛΟΗΓΗΣΗ δείχνει σε καταλόγους· η ΠΡΑΞΗ δείχνει στη φόρμα.** Ο ανώνυμος που
 * θα πατούσε «Ζητώ» και θα προσγειωνόταν σε φόρμα δημιουργίας θα έπαιρνε
 * ανακατεύθυνση στη σύνδεση **και μετά** θα έπρεπε να ξαναβρεί τον δρόμο. Ο κατάλογος
 * δουλεύει και στις δύο περιπτώσεις — γι' αυτό οι **σύνδεσμοι** μένουν εκεί.
 *
 * ✅ **ΚΑΙ ΠΡΟΣΤΕΘΗΚΕ ΤΕΤΑΡΤΟ ΣΤΟΙΧΕΙΟ ΠΟΥ ΔΕΝ ΕΙΝΑΙ ΠΟΡΤΑ (2026-08-23, ADR-660
 * §5.11)**: το **CTA** «Καταχώριση αγγελίας», που δείχνει στη **φόρμα**. Δεν είναι
 * εξαίρεση στον παραπάνω κανόνα — είναι **άλλη κατηγορία**: πλοήγηση έναντι πράξης.
 * ⚠️ Έγινε δυνατό **μόνο** επειδή το §5.10 έβγαλε το `/offers/new` από τον
 * `ProtectedRoute`· πριν από αυτό θα ήταν κουμπί προς τοίχο σύνδεσης. Και σε στενή
 * οθόνη καταλήγει σε **εξήγηση με λειτουργική έξοδο** (Α8 + §5.11), όχι σε άρνηση.
 *
 * ⚠️ **ΔΕΝ είναι το `AppHeader`, και δεν επιτρέπεται να γίνει.** Το CHECK 3.52
 * φρουρεί ότι τα σύμβολα του κελύφους (`@/components/app-header`,
 * `@/components/app-sidebar`) εισάγονται **μόνο** από το `(app)/layout.tsx`. Αυτή η
 * κεφαλίδα δεν αγγίζει κανέναν από τους 9 βαρείς providers — αλλιώς θα ακύρωνε το
 * μετρημένο κέρδος **−41% έως −59%** SSR bytes των δημόσιων οθονών.
 */

import React from 'react';
import { Link } from '@/lib/workspace/navigation';
import { ShellUtilities } from '@/core/containers/ShellUtilities';
// ⚠️ ΟΧΙ από το `@/components/ui/sidebar`: εκείνο σέρνει `Sheet`/`Input`/`Separator`
//    σε κάθε δημόσια σελίδα του `(light)`, όπου στήλη δεν υπάρχει ποτέ (ADR-871 Υ2).
import { useOptionalSidebar } from '@/components/ui/sidebar-context';
import { SidebarTrigger } from '@/components/ui/sidebar-trigger';
import { useTranslation } from '@/i18n/hooks/useTranslation';
import { PRODUCT_NAME } from '@/constants/product-identity';
import { AUTH_ROUTES } from '@/lib/routes';
import { SEARCH_LANDING_ROUTE } from '@/lib/listings/listing-routes';
import { COLOR_BRIDGE } from '@/design-system/color-bridge';
import { PublicSiteMenu } from './PublicSiteMenu';
import { PUBLIC_SITE_DOORS, PUBLIC_SITE_PRIMARY_ACTION, PUBLIC_SITE_SPOKES } from './public-site-nav';

/** Οι σύνδεσμοι των ακτίνων (§8.82) — πλοήγηση, όχι πράξη: χωρίς πλαίσιο, από `lg` και πάνω. */
const SPOKE_LINK_CLASS =
  'hidden rounded-md px-2 py-1.5 text-sm font-medium text-muted-foreground hover:text-foreground lg:inline-flex';
/** Οι πόρτες του ιδιώτη — από `lg`· κάτω από αυτό ζουν στο συρτάρι (ADR-809 §9). */
const DOOR_LINK_CLASS =
  'hidden whitespace-nowrap rounded-md border border-border bg-card px-3 py-1.5 text-sm font-medium text-foreground lg:inline-flex';

export function PublicSiteHeader() {
  // ⚠️ Το `'search-results'` ήταν γραμμένο **τρεις φορές** στον ίδιο πίνακα — ο i18next
  //    φορτώνει ένα namespace μία φορά, άρα ήταν θόρυβος, όχι σφάλμα. Καθαρίστηκε
  //    επιτόπου (Boy Scout, N.0.2) αφού το αρχείο ανοίχτηκε για την ADR-857 Φ4.
  const { t } = useTranslation(['search-results', 'property-market']);
  /*
    🏛️ ADR-871 Ε2 / §10.3 Υ2 — **ΡΩΤΑ ΤΗΝ ΠΑΡΟΥΣΙΑ ΤΗΣ ΣΤΗΛΗΣ, ΟΧΙ ΤΗ ΔΙΑΔΡΟΜΗ.**
    Στο `(me)` ο `PrivateSpaceShell` τυλίγει αυτή την κεφαλίδα σε `SidebarProvider`·
    στο `(light)` όχι. Ο provider **είναι** η απάντηση — λίστα `pathname` εδώ θα ήταν
    ο `ConditionalAppShell` που διέγραψε το ADR-777 §8.12.
    Με στήλη: «Ζητώ»/«Προσφέρω» είναι ήδη στοιχεία της ⇒ δεν διπλασιάζονται· στο
    κινητό η στήλη είναι συρτάρι και η πόρτα της είναι το ☰. Το σήμα κρύβεται από
    `md` και πάνω, όπου το δείχνει ήδη η στήλη.
  */
  const hasSidebar = useOptionalSidebar() !== null;

  return (
    <header className="w-full border-b border-border bg-card">
      <nav
        aria-label={t('search-results:site.nav')}
        // Με στήλη η κεφαλίδα απλώνεται σε όλο το inset, όπως στο γραφείο: αλλιώς το ☰
        // κάθεται στη μέση της οθόνης, μακριά από τη στήλη που ελέγχει (ADR-871 §11).
        className={`flex w-full items-center justify-between gap-2 px-4 py-3 sm:px-6 md:gap-4${hasSidebar ? '' : ' mx-auto max-w-5xl'}`}
      >
        <div className="flex min-w-0 items-center gap-2">
        {/*
          📱 **ΜΙΑ ΘΕΣΗ ☰ ΣΕ ΟΛΗ ΤΗΝ ΕΦΑΡΜΟΓΗ** (ADR-809 §9): με στήλη, το ☰ της στήλης·
          χωρίς, το «☰ Μενού» του δημόσιου ιστότοπου — και τα δύο **αριστερά**, πριν το λογότυπο.
        */}
        {hasSidebar ? <SidebarTrigger /> : <PublicSiteMenu />}
        <Link
          href={SEARCH_LANDING_ROUTE}
          className={`shrink-0 whitespace-nowrap text-base font-semibold tracking-tight text-foreground${hasSidebar ? ' md:hidden' : ''}`}
          aria-label={t('search-results:site.home')}
        >
          {/*
            🔴 **ΕΔΩ ΗΤΑΝ Η ΑΠΟΔΕΙΞΗ ΤΗΣ ΑΠΟΚΛΙΣΗΣ** (ADR-857 Φ4): το κλειδί
            `search-results:site.brand` έλεγε **«Nestor»** — σκέτο — ενώ τα τρία αδέλφια
            του έλεγαν «Nestor App». Ένα όνομα προϊόντος σε catalog μετάφρασης είναι
            δομή που **επιτρέπει** απόκλιση, και αυτή εδώ **είχε ήδη συμβεί**, στη
            **δημόσια** κεφαλίδα. ⚠️ Η διόρθωση αλλάζει **ορατό** κείμενο: «Nestor» →
            «Nestor App». Καμία πύλη δεν πιάνει μετατόπιση κειμένου — δηλώνεται στο §7.
          */}
          {PRODUCT_NAME}
        </Link>
        {/*
          🖼️ **ΟΙ ΑΚΤΙΝΕΣ ΤΟΥ ΚΟΜΒΟΥ (ADR-777 §8.82).** Μια σελίδα-ακτίνα που φτάνεις μόνο
          από την καρτέλα της αρχικής είναι **ορφανή**: ο επισκέπτης του `/listing/…` ή του
          `/search/results` δεν τη βρίσκει ποτέ. Zillow («Find an agent») · Airbnb · idealista
          τις κρατούν στην κεφαλίδα. Ετικέτες = τα **ίδια** κλειδιά με τις καρτέλες του κόμβου
          ⇒ μία λέξη για μία έννοια, μηδέν νέα bytes στο κέλυφος (ADR-744).
          ⚠️ Από `md` και πάνω: στο κινητό τις ανοίγουν οι καρτέλες της αρχικής, και πέντε
          σύνδεσμοι + CTA σε 375px θα έσπαγαν τη γραμμή.
        */}
        {!hasSidebar &&
          PUBLIC_SITE_SPOKES.map((spoke) => (
            <Link key={spoke.id} href={spoke.href} className={SPOKE_LINK_CLASS}>
              {t(spoke.labelKey)}
            </Link>
          ))}
        </div>

        <div className="flex shrink-0 items-center gap-2">
          {/*
            🔑 **Η πόρτα του ιδιώτη.** Δείχνει στον **κατάλογο** (`/demands`), όχι στη
            φόρμα: ο `(me)/layout.tsx` ζητά ταυτότητα, οπότε ο ανώνυμος περνά από τη
            σύνδεση **μία** φορά και προσγειώνεται εκεί που θέλει — ενώ ένας σύνδεσμος
            προς `/demands/new` θα τον έστελνε, σε κινητό, σε οθόνη που λέει «όχι εδώ»
            (Α8). Η πόρτα οφείλει να ανοίγει σε **κάθε** συσκευή.
          */}
          {/*
            ✅ **Η ΤΡΙΤΗ ΠΟΡΤΑ — «ΠΡΟΣΦΕΡΩ» (2026-08-11, Α14).** Η δεύτερη προϋπόθεση
            εκπληρώθηκε: υπάρχουν πλέον **και διαδρομή** (`/offers`) **και οντότητα**
            (`ownp_*`), οπότε ο σύνδεσμος **ανοίγει** — δεν είναι 404. Ίδιος κανόνας
            με το «Ζητώ»: *«μια πόρτα που δεν ανοίγει είναι χειρότερη από καμία
            πόρτα»*.

            🔑 Δείχνει στον **κατάλογο**, ποτέ στη φόρμα: η δημιουργία είναι
            **αποκλειστικά desktop** (Α8), ενώ η πόρτα οφείλει να ανοίγει σε **κάθε**
            συσκευή.
          */}
          {/*
            📱 **ΑΠΟ `lg` ΚΑΙ ΠΑΝΩ** (ADR-809 §9): κάτω από αυτό οι πόρτες ζουν στο συρτάρι
            του «☰ Μενού» — ίδια λίστα (`PUBLIC_SITE_DOORS`), ίδιες ετικέτες, ίδιοι προορισμοί.
          */}
          {!hasSidebar &&
            PUBLIC_SITE_DOORS.map((door) => (
              <Link key={door.id} href={door.href} className={DOOR_LINK_CLASS}>
                {t(door.labelKey)}
              </Link>
            ))}

          {/*
            ✅ **ΤΟ CTA — Η ΚΥΡΙΑ ΠΡΑΞΗ (2026-08-23, ADR-660 §5.11 / §5.8 κενό Β).**

            🔴 **Μέχρι το §5.10 αυτό θα ΗΤΑΝ ΒΛΑΒΗ, όχι χαρακτηριστικό**: το
            `/offers/new` ζούσε πίσω από `ProtectedRoute`, άρα ένα κουμπί για ανώνυμο
            θα οδηγούσε σε **τοίχο σύνδεσης** — το ίδιο *dead-end* που κατάργησε το
            §5, σε νέα θέση. Ξεκλείδωσε μόνο αφού η φόρμα βγήκε στο `(light)`.

            🔑 **ΔΕΙΧΝΕΙ ΣΤΗ ΦΟΡΜΑ, ΚΑΙ ΕΙΝΑΙ Η ΜΟΝΗ ΠΟΡΤΑ ΠΟΥ ΤΟ ΚΑΝΕΙ.** Οι δύο
            σύνδεσμοι από πάνω δείχνουν σε **καταλόγους** επίτηδες — είναι *πλοήγηση*,
            και ζουν στο `(me)`. Αυτό είναι **πράξη**: ο άνθρωπος που το πατά δηλώνει
            ότι θέλει να καταχωρήσει **τώρα**, και η idealista κάνει ακριβώς αυτό
            (`/flow/publicar-anuncio`, κουμπί ξεχωριστό από τη πλοήγηση).

            ⚠️ **Σε στενή οθόνη καταλήγει σε εξήγηση, ΟΧΙ σε αδιέξοδο**: η φόρμα είναι
            desktop-only (Α8) και ο `DesktopOnlyNotice` λέει γιατί **και** δίνει έξοδο
            που ανοίγει για ανώνυμο (§5.11). Χωρίς εκείνη τη διόρθωση αυτό το κουμπί
            θα ήταν παγίδα στο κινητό.

            ⚠️ **Οπτικά ξεχωριστό με ΣΗΜΑΣΙΟΛΟΓΙΚΑ tokens** (`bg-foreground` /
            `text-background`): αντιστροφή, όχι δεύτερη παλέτα. Ένα ωμό χρώμα εδώ θα
            έσπαγε τις CHECK 3.26/3.38/3.42, και σε **σκοτεινό** θέμα το `text-primary`
            λύνεται ταυτόσημα με το `--card` (ADR-770) — δηλαδή αόρατο.
          */}
          {/* ADR-871 §11 (Giorgio 2026-09-21): με στήλη, από `md` και πάνω η πράξη ζει ήδη
              στην κορυφή της στήλης — δεύτερη φορά στην ίδια οθόνη θα ήταν θόρυβος. Στο
              κινητό η στήλη είναι συρτάρι, οπότε εδώ μένει η μόνη ορατή πόρτα. */}
          {/* 📱 Χωρίς στήλη, κάτω από `lg` η πράξη ζει στο συρτάρι: εκεί η φόρμα είναι ούτως ή
              άλλως desktop-only (Α8), και η μπάρα κρατά χώρο για την ταυτότητα (ADR-809 §9). */}
          <Link
            href={PUBLIC_SITE_PRIMARY_ACTION.href}
            className={`whitespace-nowrap rounded-md px-3 py-1.5 text-sm font-semibold ${COLOR_BRIDGE.action.primary}${hasSidebar ? ' md:hidden' : ' hidden lg:inline-flex'}`}
          >
            {t(PUBLIC_SITE_PRIMARY_ACTION.labelKey)}
          </Link>

          {/*
            ✅ **ΟΙ ΚΑΘΟΛΙΚΕΣ ΔΥΝΑΤΟΤΗΤΕΣ (2026-08-26, ADR-809 / CHECK 3.72).**

            🔴 **ΤΙ ΔΙΟΡΘΩΝΕΙ, ΚΑΙ ΕΙΝΑΙ ΔΥΟ ΑΝΕΞΑΡΤΗΤΑ ΕΛΑΤΤΩΜΑΤΑ:**

            **(Α) ΤΟ ΨΕΜΑ.** Η πόρτα «Σύνδεση» ζωγραφιζόταν **άνευ όρων**, άρα και
            σε **ΣΥΝΔΕΔΕΜΕΝΟ** άνθρωπο — σε **δύο** γειτονιές, όχι μία: στο `(me)`
            (`PrivateSpaceShell` → αυτή η κεφαλίδα), που φρουρείται από
            `ProtectedRoute` και άρα **κανείς ανώνυμος δεν τη βλέπει ΠΟΤΕ**, και στο
            `(light)`, όπου ο συνδεδεμένος επαγγελματίας περιηγείται στις δημόσιες
            αγγελίες. Πλέον η ίδια γωνία δείχνει **λογαριασμό** σε όποιον έχει
            ταυτότητα και **πόρτα** σε όποιον δεν έχει — η κρίση γίνεται **μία**
            φορά, μέσα στο `UserMenu` (ADR-749: ποτέ δεύτερη απάντηση).

            **(Β) Η ΑΠΟΥΣΙΑ.** Γλώσσα και θέμα δεν υπήρχαν **πουθενά** σε `(light)`
            και `(me)`. Η **κατάσταση** ήταν πάντα καθολική (οι `ThemeProvider` και
            `I18nProvider` ζουν στο ριζικό `layout.tsx:71-78`) — αυτό που έλειπε
            ήταν το **χειριστήριο**.

            ⚠️ **Ο σύνδεσμος μένει ΑΥΤΟΥΣΙΟΣ, απλώς μετακομίζει.** Δείχνει στη
            **σύνδεση** και όχι στο {@link AUTH_ROUTES}`.home`: ο ανώνυμος που θα
            πατούσε «ο χώρος μου» θα έπαιρνε ανακατεύθυνση πίσω στη σύνδεση — δύο
            βήματα για ένα, και μια ετικέτα που λέει κάτι που δεν συμβαίνει.

            ⚠️ **ΜΗΝ ξαναγράψεις εδώ `useAuth()`** για να κρίνεις τι θα δείξεις:
            το φυλά ο κανόνας **Κ3** του CHECK 3.72 (ιδιοκτησία συμβόλων), και η
            διπλή κρίση θα απέκλινε στο παράθυρο του `isLoggingOut`.

            ⚠️ **Μετρημένο κόστος** (2026-08-26, κλειστότητα πελάτη ανά **σελίδα**,
            όχι ανά component): **+8 αρχεία · +84,5 KB πηγής · +2,3%**, με **δύο**
            νέα πακέτα (`@radix-ui/react-avatar`, `react-tooltip`). Τα βαριά
            (`firebase`·`zod`·`qrcode`·`date-fns`) ήταν **ήδη** εκεί από το ριζικό
            layout, και το «−41% έως −59% SSR bytes» του `.shell-boundary.json`
            αφορά τους **9 βαρείς providers + sidebar** — που δεν αγγίζονται.
          */}
          <ShellUtilities
            collapsePreferences={!hasSidebar}
            signedOutAction={
              <Link
                href={AUTH_ROUTES.login}
                className="whitespace-nowrap rounded-md border border-border px-3 py-1.5 text-sm font-medium text-foreground"
              >
                {t('search-results:site.signIn')}
              </Link>
            }
          />
        </div>
      </nav>
    </header>
  );
}
