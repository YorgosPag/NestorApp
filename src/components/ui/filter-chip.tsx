import * as React from 'react';
import { X } from 'lucide-react';

import { Badge } from '@/components/ui/badge';
import { cn } from '@/lib/utils';

export interface FilterChipProps {
  /**
   * Το **ορατό** κείμενο — τι φιλτράρει, με λέξεις που διαβάζει άνθρωπος.
   *
   * ⛔ **Ποτέ ωμή ταυτότητα ή συντεταγμένη.** Ένα `municipality:0701` ή ένα
   * `40.6307, 22.9469` είναι κείμενο **χωρίς παραλήπτη**.
   */
  readonly label: string;
  /**
   * Το **προσβάσιμο όνομα** του `×`.
   *
   * 🔑 **ΟΦΕΙΛΕΙ ΝΑ ΠΕΡΙΕΧΕΙ ΤΟ ΟΡΑΤΟ ΚΕΙΜΕΝΟ** — όχι σκέτο «Αφαίρεση». Με πολλαπλά
   * σημάδια στη σειρά, N ταυτόσημα «Αφαίρεση» αφήνουν τον χρήστη αναγνώστη οθόνης να
   * **μαντεύει ποιο σβήνει τι**. Είναι η ρητή σύσταση της έρευνας *(«Remove Filter» +
   * το ορατό κείμενο)* και ταυτόχρονα ικανοποιεί το **WCAG 2.5.3 Label in Name**.
   */
  readonly removeLabel: string;
  /**
   * ⚠️ **Τρέχει ΠΡΙΝ φύγει ο κόμβος από το DOM** — άρα εδώ μέσα ο καταναλωτής
   * **οφείλει** να μετακινήσει την εστίαση σε γείτονα. Αν δεν το κάνει, ο χρήστης
   * πληκτρολογίου πέφτει στο `<body>` και χάνει τη θέση του στη σελίδα.
   */
  readonly onRemove: () => void;
  readonly className?: string;
}

/**
 * **Ένα ενεργό φίλτρο, ονομασμένο και αφαιρούμενο.**
 *
 * ⚠️ **Σημάδι ≠ σήμα** *(CMS: «when not to use»)*: αν το πράγμα **δεν αφαιρείται**, δεν
 * είναι `FilterChip` — είναι `Badge`. Ανάμειξη των δύο διδάσκει τον άνθρωπο ότι «τα
 * στρογγυλά κλείνουν», και μετά του δίνει στρογγυλά που δεν κλείνουν.
 */
export function FilterChip({
  label,
  removeLabel,
  onRemove,
  className,
}: FilterChipProps): React.ReactElement {
  return (
    <Badge variant="secondary" className={cn('gap-1.5 py-1 pl-2.5 pr-1', className)}>
      <span className="text-xs">{label}</span>
      {/*
        🔴 **`h-6 w-6` ΚΑΙ ΟΧΙ `p-0.5` ΓΥΡΩ ΑΠΟ `h-3 w-3`** — WCAG 2.2 SC 2.5.8 ζητά
        στόχο **≥ 24×24** CSS px. Το εικονίδιο μένει **οπτικά** 12 px· μεγαλώνει η
        **επιφάνεια αφής**, που είναι ακριβώς η διάκριση που κάνει το πρότυπο.
      */}
      <button
        type="button"
        onClick={onRemove}
        aria-label={removeLabel}
        className="ml-0.5 inline-flex h-6 w-6 items-center justify-center rounded-full transition-colors hover:bg-muted focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
      >
        <X className="h-3 w-3" aria-hidden="true" />
      </button>
    </Badge>
  );
}
