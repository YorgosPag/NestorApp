/**
 * **ΤΙ ΔΕΝ ΔΗΜΟΣΙΕΥΟΥΜΕ ΑΚΟΜΗ** — γραμμένο, όχι σιωπηλό.
 *
 * @related ADR-777 §7 (Α3 οθόνη 3 · Α7 · Α17) · lib/listings/listing-disclosure
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΑΥΤΟ ΤΟ ΚΟΥΤΙ ΥΠΑΡΧΕΙ ΚΑΙ ΔΕΝ ΕΙΝΑΙ «ΠΡΟΣΕΧΩΣ»
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η **Α3** υπόσχεται ότι η οθόνη 3 δείχνει *«κάτοψη, φάκελο, νομιμότητα»*. Κανένα από
 * τα τρία **δεν υπάρχει στον κώδικα** σήμερα. Οι δύο δρόμοι που **δεν** ακολουθούνται:
 *
 * 1. **Σιωπή.** Ένας επισκέπτης που δεν βλέπει νομιμότητα σε σελίδα ακινήτου
 *    συμπεραίνει *«δεν έχει»* — όχι *«δεν το δημοσιεύουν»*. Είναι **ψευδής**
 *    ισχυρισμός παραγμένος από απουσία, δηλαδή ακριβώς το σχήμα «**0 = κανείς δεν
 *    κοίταξε**» που κυνηγούν οι πύλες μας, στραμμένο προς τα έξω.
 * 2. **Επινόηση.** Μια «νομιμότητα» μαντεμένη από την οθόνη θα ήταν χειρότερη από
 *    την απουσία: η **Α17** υπάρχει επειδή η βεβαίωση μηχανικού είναι **υποχρεωτική
 *    στη μεταβίβαση** (άρθρο 83 ν. 4495/2017) — η εικασία δεν κρύβεται, **μετατίθεται**
 *    στη χειρότερη στιγμή, στο συμβολαιογραφείο.
 *
 * ⇒ Μένει ο τρίτος: **το λέμε**. Και επειδή το λέμε, η μέρα που θα υπάρξει η Α17 θα
 * είναι **αφαίρεση μιας γραμμής από εδώ**, όχι ανακάλυψη ότι κάτι έλειπε.
 *
 * 🏆 **Κανένα portal δεν το κάνει** — και δεν είναι επειδή δεν το σκέφτηκαν: ένα
 * κουτί «τι δεν ξέρουμε» μειώνει τη φαινομενική πληρότητα της αγγελίας. Είναι η ίδια
 * απόφαση με τη δήλωση κάλυψης της οθόνης 1 (`CoverageStatement`): προτιμάμε να
 * φανούμε λιγότερο πλήρεις παρά **περισσότερο βέβαιοι απ' όσο είμαστε**.
 */

import React from 'react';
import { useTranslation } from '@/i18n/hooks/useTranslation';
import { LISTING_OPEN_SUBJECTS } from '@/lib/listings/listing-disclosure';

export function ListingOpenSubjects() {
  const { t } = useTranslation(['search-results']);

  return (
    <section
      aria-labelledby="listing-open-heading"
      className="rounded-lg border border-dashed border-border bg-muted/40 p-4"
    >
      <h2 id="listing-open-heading" className="text-sm font-medium text-foreground">
        {t('search-results:detail.open.heading')}
      </h2>
      <p className="mt-1 text-xs text-muted-foreground">{t('search-results:detail.open.intro')}</p>

      {/*
        ⚠️ Ο κατάλογος έρχεται από το SSoT, **δεν γράφεται εδώ**: αλλιώς η μέρα που θα
        υλοποιηθεί η Α17 θα άφηνε τη γραμμή της να ζει σε ένα αρχείο που κανείς δεν
        θα σκεφτόταν να ανοίξει — και η σελίδα θα δήλωνε κενό που έχει ήδη κλείσει.
      */}
      <ul className="mt-3 space-y-2">
        {LISTING_OPEN_SUBJECTS.map((subject) => (
          <li key={subject} className="text-sm text-muted-foreground">
            {t(`search-results:detail.open.${subject}`)}
          </li>
        ))}
      </ul>
    </section>
  );
}
