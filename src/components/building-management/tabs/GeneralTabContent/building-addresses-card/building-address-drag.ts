import type { AddressWithHierarchyValue } from '@/components/shared/addresses/AddressWithHierarchy';
import { EMPTY_VALUE } from '@/components/shared/addresses/address-with-hierarchy-config';
import { applyProvedAdminLevels } from '@/components/shared/addresses/address-hierarchy-field-ops';
import type { ResolvedAddressFields } from '@/lib/geocoding/geocoding-types';

/**
 * Η ιεραρχία μιας διεύθυνσης κτιρίου μετά από «**Ναι, ενημέρωσε**»:
 * **γράψε ό,τι αποδείχθηκε, καθάρισε ό,τι ΔΕΝ αποδείχθηκε**.
 *
 * 🔴 **Εδώ μηδενιζόταν ΟΛΟ το σετ ΕΛΣΤΑΤ** — εννέα πεδία γραμμένα με το χέρι, με σχόλιο
 * *«clear ELSTAT hierarchy»*. Ήταν η **τέταρτη** από τις τέσσερις διαδρομές που έσβηναν
 * ιεραρχία χωρίς να ρωτήσουν κανέναν, και η **μόνη** που τη μηδένιζε ολόκληρη. Ο
 * μηδενισμός ήταν **σωστός όσο δεν είχαμε ταυτότητες** *(ADR-277: όνομα μιας περιοχής με
 * την ταυτότητα μιας άλλης)* — τώρα ο διακομιστής **αποδεικνύει** τον δήμο από τη
 * διοικητική αλυσίδα του Nominatim *(μετρημένο 14/14, και στους αστικούς πυρήνες)*.
 *
 * ⚠️ **Το `?? []` είναι απόφαση, όχι αμυντικός θόρυβος**: εδώ φτάνουμε **μόνο** όταν το
 * κείμενο **αντικαθίσταται**, οπότε «δεν ρωτήθηκε» και «ρωτήθηκα και δεν έμαθα» καταλήγουν
 * στο **ίδιο** — καμία απόδειξη για τη **νέα** διεύθυνση ⇒ **καθαρίζουμε**. Η κληρονομιά
 * της παλιάς ταυτότητας δίπλα σε νέα οδό είναι το ελάττωμα του ADR-277, **αόρατο** στην οθόνη.
 *
 * 🔴 **Η χώρα έλειπε από αυτόν τον γραφέα και ΧΑΝΟΤΑΝ σε κάθε σύρσιμο κτιρίου**
 * *(ADR-332 D27 Β9 · Φάση Α)*: ο τύπος την κουβαλούσε, η μεταφορά όχι. Το ίδιο σχήμα με
 * το `hierarchyToResolvedAddress`, που το είχε πληρώσει ήδη μία φορά.
 */
export function buildingHierarchyAfterDrag(
  previous: Partial<AddressWithHierarchyValue> | undefined,
  resolved: ResolvedAddressFields,
): AddressWithHierarchyValue {
  const updated: AddressWithHierarchyValue = {
    ...EMPTY_VALUE,
    ...previous,
    street: resolved.street ?? '',
    number: resolved.number ?? '',
    postalCode: resolved.postalCode ?? '',
    country: resolved.country ?? previous?.country ?? '',
  };

  // 1️⃣ **Πρώτα οι αποδείξεις**: ταυτότητες και ονόματα μητρώου· ό,τι δεν αποδείχθηκε καθαρίζει.
  applyProvedAdminLevels(updated, resolved.admin ?? []);

  // 2️⃣ **Μετά το κείμενο της μηχανής, ΜΟΝΟ σε ό,τι έμεινε κενό.**
  //
  // 🔴 **Η ΣΕΙΡΑ ΕΙΝΑΙ ΟΡΘΟΤΗΤΑ, ΚΑΙ ΤΗ ΒΡΗΚΑ ΓΡΑΦΟΝΤΑΣ ΤΗΝ ΑΝΑΠΟΔΑ.** Το λεξιλόγιο
  // **φόρμας** δεν έχει **κανένα** ελεύθερο πεδίο κειμένου: η συνοικία της μηχανής δεν έχει
  // πού να ζήσει παρά στο `communityName`, και η ετικέτα περιφέρειας παρά στο `regionName`
  // *(το `neighborhood` είναι ρητά `NOT_STORED` σε αυτό το δοχείο — ADR-772)*. Αν οι
  // αποδείξεις γράφονταν **δεύτερες**, θα έσβηναν κείμενο που είναι **ό,τι μόνο έχουμε**.
  //
  // ⚠️ Αυτή είναι η **ίδια** διάκριση με το `city` του `companyAddress`: άγνοια δικαιολογεί
  // σβήσιμο **ταυτότητας**, ποτέ σβήσιμο **κειμένου**. Εκεί το `region` έχει χωριστό ελεύθερο
  // πεδίο και ο κανόνας γράφεται αλλιώς· **εδώ δεν υπάρχει**, και γι' αυτό ο κανόνας είναι
  // «**συμπλήρωσε το κενό**» αντί «γράψε πάντα».
  updated.settlementName ||= resolved.city ?? '';
  updated.communityName ||= resolved.neighborhood ?? '';
  updated.regionName ||= resolved.region ?? '';

  return updated;
}
