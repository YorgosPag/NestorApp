'use client';

/**
 * ADR-748 Φάση 3.6 / **ΕΠΙΠΕΔΟ 2** — ο δείκτης **μέσα στο δοχείο**.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΠΡΟΒΛΗΜΑ ΠΟΥ ΛΥΝΕΙ, ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΑΠΛΟ BADGE
 *
 * Ο δείκτης της κεφαλίδας μετρά **κλάδους** (Ε14.ιβ). Τα υπο-στοιχεία που
 * κλαδεύονται μέσα σε **ΟΡΑΤΟΥΣ** γονείς — 7 στο `/reports`, 6 admin στο
 * `/settings` — δεν μετριούνται εκεί **επίτηδες**, γιατί ο χρήστης βλέπει τον
 * γονιό στη θέση του. Αλλά αν δεν αναφερθούν **πουθενά**, το **Α-3** *(ποτέ
 * σιωπηλή απόκρυψη)* δεν ικανοποιείται. Ο δείκτης τους ζει εδώ: στη μόνη θέση
 * όπου η πληροφορία είναι **τοπική και ακριβής**.
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔒 Ε14.ιγ — Ο ΚΑΝΟΝΑΣ ΘΕΣΗΣ ΠΟΥ ΕΜΠΟΔΙΖΕΙ ΤΗ ΣΥΓΚΡΟΥΣΗ ΝΟΗΜΑΤΟΣ
 *
 * Η εφαρμογή **ήδη** δείχνει αριθμό «μέσα σε δοχείο»: τα πλακίδια του dashboard
 * λένε «9 υπο-ενότητες» *(Λογιστικό)*, «11 υπο-ενότητες» *(CRM)*. Εκείνος
 * μετρά **πόσα έχει**· αυτός εδώ **πόσα λείπουν**. Ίδια οπτική θέση με δύο
 * νοήματα είναι **ακριβώς** το σχήμα ελαττώματος που πιάστηκε τρεις φορές σε
 * αυτό το ADR (Ε14.θ · Ε14.ια · Ε14.ιβ). Η διάκριση **δεν** αφήνεται στο χρώμα:
 *
 *   • ο **θετικός** αριθμός ζει στο **ΚΛΕΙΣΤΟ** δοχείο, ως υπότιτλος, χωρίς ρήμα
 *   • ο **αρνητικός** ζει **ΜΟΝΟ μέσα στο ΑΝΟΙΧΤΟ** δοχείο, ως γραμμή **με ρήμα
 *     και ενέργεια**
 *
 * Άρα δεν συνυπάρχουν ποτέ στο ίδιο καρέ, και ο δεύτερος **πάντα κάνει κάτι** —
 * δεν διαβάζεται ποτέ ως πλήθος περιεχομένου.
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΔΕΝ ΕΙΝΑΙ ΕΤΙΚΕΤΑ — ΕΙΝΑΙ ΚΟΥΜΠΙ, όπως το `HiddenItemsBadge`. Αριθμός που
 * δεν επαναφέρει τίποτα λέει στον χρήστη ότι έχασε κάτι και τον αφήνει να το
 * ψάχνει: η αδυναμία **Υ-2** του Revit (§8).
 *
 * ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟ ΑΡΧΕΙΟ: τον χρειάζονται **δύο** μονοπάτια render του
 * `sidebar-menu-item` — το ανοιχτό υπο-μενού **και** το popover του μαζεμένου
 * sidebar. Δύο αντίγραφα = sibling clone με δύο ευκαιρίες να αποκλίνουν
 * (κανόνας N.18 / CHECK 3.28). Ο καλών βάζει το δικό του περιτύλιγμα.
 *
 * CHECK 3.23: κανένα native `title=` — ο υποβοηθούμενος χρήστης δεν διαβάζει
 * tooltip, γι' αυτό ο αριθμός υπάρχει **και** στο `aria-label`.
 */

import React from 'react';
import { EyeOff } from 'lucide-react';
import { useTranslation } from '@/i18n';
import { cn } from '@/lib/utils';
import { useIconSizes } from '@/hooks/useIconSizes';

interface SidebarHiddenRowProps {
  /** Πόσα υπο-στοιχεία έκρυψε η ενεργή δουλειά **σε αυτό το δοχείο**. */
  count: number;
  /** Είσοδος στον τρόπο «Αποκάλυψη» (Επίπεδο 3). */
  onReveal: () => void;
  className?: string;
}

export function SidebarHiddenRow({ count, onReveal, className }: SidebarHiddenRowProps) {
  const { t } = useTranslation('navigation');
  const iconSizes = useIconSizes();

  // «0 κρυμμένα» θα ήταν θόρυβος: ο δείκτης υπάρχει μόνο όταν έχει νόημα.
  if (count <= 0) return null;

  return (
    <button
      type="button"
      onClick={onReveal}
      aria-label={t('jobs.reveal.showAriaLabel', { count })}
      className={cn(
        // ⚠️ **ΟΝΟΜΑΤΙΣΜΕΝΟ** group. Ανώνυμο `group` εδώ θα συγκρουόταν με το
        // `group` του ίδιου του `Sidebar` (που κουβαλά τα `data-collapsible`):
        // το Tailwind ταιριάζει **οποιονδήποτε** πρόγονο με `.group`, άρα το
        // υπογράμμισμα θα άναβε σε hover **οπουδήποτε** μέσα στο μενού.
        'group/hidden flex w-full items-center gap-2 rounded-md px-2 py-1.5 text-xs',
        'text-muted-foreground transition-colors',
        'hover:bg-accent hover:text-accent-foreground',
        className,
      )}
    >
      <EyeOff className={cn(iconSizes.sm, 'shrink-0')} aria-hidden />
      <span>{t('jobs.reveal.hiddenHere', { count })}</span>
      <span
        aria-hidden
        className="ml-auto font-medium underline-offset-2 group-hover/hidden:underline"
      >
        {t('jobs.reveal.show')}
      </span>
    </button>
  );
}
