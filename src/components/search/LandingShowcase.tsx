'use client';

/**
 * **Η ΑΠΟΔΕΙΞΗ ΤΗΣ ΟΘΟΝΗΣ 1** — το απόθεμα, ορατό (ADR-777 §8.49).
 *
 * @related ADR-777 §8.10 (η οθόνη αρνείται να υποσχεθεί) · §8.49 (…αλλά οφείλει να
 *          αποδείξει) · ADR-841 §7 Α2.4 (LCP) · §7 Α6 (η κάρτα χωρίς χάρτη)
 * @module components/search/LandingShowcase
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΠΡΟΒΛΗΜΑ, ΜΕΤΡΗΜΕΝΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η ρίζα είχε **8 αγγελίες**, τις **7 με πραγματική φωτογραφία**, τις **6 σε έξι
 * διαφορετικές ελληνικές πόλεις** — και έδειχνε **μηδέν**. Έλεγε *«8 αγγελίες»* πάνω από
 * ένα κουμπί που έλεγε *«δες τες»*. Το περιεχόμενο κατείχε **~10,3%** της οθόνης· στους
 * τέσσερις μεγάλους που μετρήθηκαν την ίδια ώρα, **72–95%**.
 *
 * 🔑 **ΚΑΙ Η ΘΕΡΑΠΕΙΑ ΔΕΝ ΕΙΝΑΙ ΚΙΝΗΣΗ.** Το ελάττωμα δεν ήταν ότι το τίποτα στεκόταν
 * ακίνητο — ήταν ότι η σελίδα **περιέγραφε** το απόθεμα αντί να το **δείξει**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΙΣΧΥΡΙΣΜΟΣ vs ΑΠΟΔΕΙΞΗ — ΓΙΑΤΙ ΑΥΤΟ **ΔΕΝ** ΑΝΑΙΡΕΙ ΤΟ §8.10
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το §8.10 απαγόρευσε την **υπόσχεση** *(κουτί «πού ψάχνεις;» που θα επέστρεφε μηδέν)*.
 * Δεν απαγόρευσε την **απόδειξη**, και δεν είναι το ίδιο πράγμα: το *«8 αγγελίες»* είναι
 * αριθμός που **μπορεί** να υποσχεθεί παραπάνω απ' όσα υπάρχουν, γιατί δεν δείχνει **τι**
 * είναι· έξι κάρτες με φωτογραφία, τιμή και εμβαδόν **δεν μπορούν** — δείχνουν ακριβώς
 * ό,τι υπάρχει. ⇒ Η απόδειξη είναι **αυστηρότερη** μορφή της ίδιας δοκτρίνης.
 *
 * 🏆 **ΚΑΙ ΕΔΩ Ο ΠΕΡΙΟΡΙΣΜΟΣ ΜΑΣ ΕΙΝΑΙ ΤΟ ΟΠΛΟ.** Και οι τέσσερις μεγάλοι λύνουν το
 * κενό με **stock φωτογραφία τρόπου ζωής** *(γυναίκα σε μπαλκόνι· παρέα σε βεράντα)* —
 * **καμία δεν είναι ακίνητό τους**. Το ADR-841 §25.5.2 μας το **απαγορεύει**. Άρα μας
 * μένει μόνο η τίμια εκδοχή: ήρωας = **το πραγματικό απόθεμα**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΤΡΙΤΟ ΑΝΤΙΓΡΑΦΟ ΤΗΣ ΛΙΣΤΑΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Υπάρχουν ήδη δύο `<ul>` που αποδίδουν {@link ListingCard}: η `ResultsList` *(στήλη
 * **δεμένη σε χάρτη** — hover · highlight · φίλτρα που ταξιδεύουν)* και το
 * `AgencyProfileContent` *(στήλη **χωρίς** χάρτη)*. Εδώ η διάταξη είναι **πλέγμα
 * πλήρους πλάτους**, και αυτό είναι **άλλη απόφαση**, όχι άλλη υλοποίηση: η **μηχανή**
 * *(κάρτα · σειρά · τιμή · εικόνες · LCP)* είναι **ολόκληρη κοινή** και δεν
 * ξαναγράφεται εδώ ούτε μία γραμμή της. Ίδιο σκεπτικό με το γιατί τα
 * `listing-showcase-order` και `agency-directory-order` γράφτηκαν **χωριστά επίτηδες**.
 *
 * ⚠️ **ΚΑΜΙΑ `sort()` ΚΑΙ ΚΑΜΙΑ `slice()` ΕΔΩ.** Και τα δύο ζουν στο
 * {@link landingShowcaseListings}, γιατί *«ποιες και πόσες βλέπει ο επισκέπτης»* είναι
 * απόφαση **με διεύθυνση και άγκυρα** — όχι λεπτομέρεια απόδοσης.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ `sizes` ΕΙΝΑΙ ΔΗΛΩΣΗ ΤΗΣ ΔΙΑΤΑΞΗΣ, ΚΑΙ ΓΙ' ΑΥΤΟ ΤΟ ΛΕΕΙ **ΑΥΤΟ** ΤΟ ΑΡΧΕΙΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η προεπιλογή της κάρτας *(`22rem` πάνω από 1024px)* περιγράφει τη **στήλη**. Εδώ οι
 * στήλες είναι **όσες χωρέσουν**, με κάθε κάρτα μεταξύ `18rem` και ~`24rem` — άρα η
 * προεπιλογή θα ήταν **ψευδής**, και ο περιηγητής θα κατέβαζε λάθος παράγωγο **χωρίς
 * κανένα ορατό σφάλμα**: θολό ή σπάταλο, σιωπηλά, χωρίς πύλη να ρωτήσει.
 *
 * ⚠️ **Ο αριθμός συμφωνεί με το `minmax` από κάτω — και οφείλει να συνεχίσει.** Αν
 * αλλάξει το ένα, αλλάζει και το άλλο· ο φρουρός Β4 τα δένει.
 */

import React, { useId } from 'react';
import { useTranslation } from '@/i18n/hooks/useTranslation';
import { ListingCard } from '@/components/search-results/ListingCard';
import { AgencyCard } from '@/components/mandate/AgencyCard';
import {
  landingPanelListings,
  landingProShowcase,
  type LandingMode,
} from '@/lib/landing/landing-modes';
import type { PublicListing } from '@/types/public-listing';
import type { PublicShowcase } from '@/types/agency-profile';

/**
 * Το πλάτος της κάρτας **σε αυτή τη διάταξη** — δες το docblock παραπάνω.
 *
 * ⚠️ Δεν υπάρχει σκέλος «πάνω από X px»: το πλέγμα κρατά την κάρτα **στο ίδιο μέγεθος**
 * όσο κι αν μεγαλώσει το παράθυρο *(προσθέτει **στήλες**, δεν φουσκώνει κάρτες)*. Ένα
 * breakpoint εδώ θα περιέγραφε διάταξη που **δεν συμβαίνει ποτέ**.
 */
const SHOWCASE_IMAGE_SIZES = '(min-width: 40rem) 20rem, 100vw';

interface LandingShowcaseProps {
  /**
   * **Η ενεργή λειτουργία — ή `null` όταν ΔΕΝ ΥΠΑΡΧΕΙ ΔΙΑΚΟΠΤΗΣ** στην οθόνη.
   *
   * ⛔ **Το `null` ΔΕΝ είναι «όλες οι λειτουργίες»** — είναι *«κανείς δεν ρώτησε»*.
   * Δες το {@link landingPanelListings}: εκεί ζει ο λόγος για τον οποίο τότε **δεν**
   * φιλτράρουμε, και είναι ο ίδιος κανόνας που κρατά τον διακόπτη κρυφό.
   */
  readonly mode: LandingMode | null;
  readonly listings: readonly PublicListing[];
  /**
   * ⚠️ **Ήδη ταξινομημένοι** από τον `usePublicAgencies` — η βιτρίνα **μόνο** κόβει
   * *({@link landingProShowcase})*. Μια `sort()` εδώ θα ήταν δεύτερη σειρά για το ίδιο
   * σύνολο, ελεύθερη να αποκλίνει από τον κατάλογο `/pro`.
   */
  readonly agencies: readonly PublicShowcase[];
  readonly loading: boolean;
  readonly error: string | null;
}

/**
 * ⚠️ **ΣΙΩΠΑ ΟΤΑΝ ΔΕΝ ΜΠΟΡΕΙΣ ΝΑ ΑΠΟΔΕΙΞΕΙΣ** — καμία θήκη-σκελετός, κανένα «φορτώνει».
 * Ένας σκελετός είναι **υπόσχεση για περιεχόμενο**, και σε `error` ή σε άδεια βάση είναι
 * υπόσχεση που δεν τηρείται ποτέ. Το *«τι συμβαίνει»* το λέει η `CoverageStatement`, με
 * αριθμούς — **μία** φωνή για την κατάσταση, ποτέ δύο.
 */
export function LandingShowcase({
  mode,
  listings,
  agencies,
  loading,
  error,
}: LandingShowcaseProps) {
  const { t } = useTranslation(['search-results']);
  const headingId = useId();

  // 🔴 **Η ΔΙΑΚΛΑΔΩΣΗ ΕΙΝΑΙ ΤΥΠΟΥ, ΟΧΙ ΣΥΝΘΗΚΗΣ** — ίδιο σχήμα με το `PlaceSearchBox`.
  //    Το `null` **δεν** το αποφασίζει αυτό το αρχείο ρωτώντας `mode === 'pros'`: το
  //    λέει το SSoT, επειδή **οι επαγγελματίες δεν είναι αγγελία** (Α5). Ένα
  //    `if (mode === 'pros')` εδώ θα ήταν **δεύτερος** τόπος που ξέρει ποια
  //    λειτουργία αποδεικνύεται με τι — ελεύθερος να αποκλίνει.
  const shownListings = landingPanelListings(mode, listings);
  const shownAgencies = shownListings === null ? landingProShowcase(agencies) : null;
  const count = shownListings?.length ?? shownAgencies?.length ?? 0;

  if (loading || error !== null || count === 0) return null;

  return (
    // `data-shell-span="full"` — ο **δηλωμένος** τρόπος να σπάσει έξω από το μέτρο
    // ανάγνωσης (`shell-surface.css` §4). ⛔ ΠΟΤΕ `max-w-*` ή `-mx-*` εδώ: το CHECK
    // 3.63 Κ5 το μπλοκάρει ως **δεύτερο άξονα πλάτους**.
    <section data-shell-span="full" aria-labelledby={headingId}>
      <h2 id={headingId} className="mb-3 text-lg font-semibold text-foreground">
        {/*
          ⚠️ **Ο ΤΙΤΛΟΣ ΑΚΟΛΟΥΘΕΙ ΤΟ ΠΕΡΙΕΧΟΜΕΝΟ, ΓΙΑΤΙ ΑΛΛΙΩΣ ΛΕΕΙ ΨΕΜΑΤΑ.** Το «Δες
          τι υπάρχει ήδη» πάνω από κάρτες **επαγγελματιών** θα διαβαζόταν ως «να τα
          ακίνητα» — δηλαδή η ίδια σύγχυση, μετακινημένη μία γραμμή πιο πάνω.
        */}
        {t(
          shownAgencies !== null
            ? 'search-results:landing.showcase.prosHeading'
            : 'search-results:landing.showcase.heading',
        )}
      </h2>

      {/*
        ⚠️ **ΕΝΑ ΠΛΕΓΜΑ, ΔΥΟ ΕΙΔΗ ΑΠΟΔΕΙΞΗΣ — ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ.** Ένα δεύτερο
        `<section>` + `<ul>` για τους επαγγελματίες θα ήταν **δίδυμος κλώνος** της
        ίδιας διάταξης *(N.18: ακριβώς το σχήμα που το `jscpd` πιάνει ανεξάρτητα
        ονόματος)*. Η **διάταξη** της βιτρίνας είναι μία· αλλάζει μόνο **η κάρτα**.
      */}
      <ul className="m-0 grid list-none grid-cols-[repeat(auto-fill,minmax(18rem,1fr))] gap-4 p-0">
        {shownListings !== null
          ? /* Μόνο η πρώτη κάρτα είναι LCP (ADR-841 §7 Α2.4): πολλές «υψηλής
               προτεραιότητας» εικόνες **ακυρώνουν η μία την άλλη**. */
            shownListings.map((listing, index) => (
              <ListingCard
                key={listing.id}
                listing={listing}
                priority={index === 0}
                imageSizes={SHOWCASE_IMAGE_SIZES}
              />
            ))
          : /* ⚠️ `headingLevel={3}`: η βιτρίνα έχει **ήδη** δική της `<h2>` από πάνω.
               Η προεπιλογή `2` της κάρτας είναι σωστή στον `/pro`, που έχει `<h1>`
               και καμία `<h2>` — γι' αυτό το επίπεδο **ρωτιέται**, δεν καρφώνεται. */
            (shownAgencies ?? []).map((profile) => (
              <AgencyCard key={profile.companyId} profile={profile} headingLevel={3} />
            ))}
      </ul>
    </section>
  );
}
