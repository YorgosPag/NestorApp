    //    τέκνο**, άρα το πάνελ οφείλει να κρέμεται κατευθείαν από την επιφάνεια που
    //    δηλώνει το μέτρο. Ένα δοχείο ανάμεσα θα έκοβε τη βιτρίνα στη στήλη ανάγνωσης
