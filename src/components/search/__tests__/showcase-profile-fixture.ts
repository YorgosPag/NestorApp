import type { PublicShowcase } from '@/types/agency-profile';

/**
 * Ένα προφίλ επαγγελματία, όσο χρειάζεται για να ζωγραφιστεί κάρτα.
 *
 * 🔴 **Το `mark: null` ΔΕΝ είναι γέμισμα** — δες την κεφαλίδα: χωρίς αυτό η κάρτα
 * ισχυρίζεται **δηλωμένο σήμα** που δεν υπάρχει, και η καρτέλα σκάει.
 */
export function showcaseProfile(companyId: string, displayName: string): PublicShowcase {
  return {
    companyId,
    displayName,
    alias: companyId,
    credentials: [],
    mark: null,
  } as unknown as PublicShowcase;
}
