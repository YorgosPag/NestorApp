/**
 * **Πρόταση** ψευδωνύμου από την επωνυμία — γεννήτορας, **ποτέ κριτής**.
 *
 * ⚠️ Η διάκριση δεν είναι λεπτολογία: εδώ **παράγεται** ένα υποψήφιο κείμενο,
 * και το αν επιτρέπεται το λέει **μόνο** ο διακομιστής. Γι' αυτό δεν κόβεται
 * τίποτα «για να περάσει» — π.χ. η μίξη αλφαβήτων **αφήνεται να φτάσει** στον
 * κριτή, ώστε ο άνθρωπος να πάρει τη σωστή εξήγηση (Ψ2) αντί για μια σιωπηλά
 * ακρωτηριασμένη πρόταση.
 *
 * ⚠️ Το `\p{Letter}` και `\p{Number}` αντικατοπτρίζουν το `ALIAS_PATTERN` επειδή
 * η **πρόταση** οφείλει να είναι συνήθως αποδεκτή — αλλά **δεν** το αντιγράφουν
 * ως κρίση: αν το πρότυπο αυστηροποιηθεί αύριο, εδώ βγαίνει απλώς μια πρόταση
 * που ο διακομιστής θα απορρίψει με **σωστό** λόγο.
 */
export function suggestAlias(displayName: string, maxLength: number): string {
  return displayName
    .normalize('NFC')
    .toLowerCase()
    .replace(/[^\p{Letter}\p{Number}]+/gu, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, maxLength)
    .replace(/-$/, '');
}
