/**
 * @fileoverview **ΤΟ ΠΛΑΙΣΙΟ ΜΙΑΣ ΕΙΚΟΝΑΣ ΜΕ ΕΠΙΚΑΛΥΨΗ** — το κουτί του `<figure>` είναι **ΑΚΡΙΒΩΣ** η εικόνα.
 * @related ADR-880 (σημείο εστίασης — πρώτη εμφάνιση, 24/09) · ADR-897 §6 (σημεία λήψης — δεύτερη, 01/10)
 * @module components/listings/image-overlay-frame
 *
 * Το ιδίωμα: `<img>` για τις φυσικές διαστάσεις + SVG/κουμπί `absolute inset-0` από πάνω, που μεταφράζει δείκτη
 * σε κλάσματα της εικόνας (`getScreenCTM` ή `getBoundingClientRect` του **κουτιού**). Αυτό είναι σωστό **μόνο** αν το
 * κουτί του `<figure>` συμπίπτει με την εικόνα.
 *
 * 🔴 **Το `inline-block` ΔΕΝ το εγγυάται**: μέσα σε flex/grid γονέα το στοιχείο μπλοκοποιείται και **τεντώνεται**
 * (`align-items: stretch`). Όταν η εικόνα περιορίζεται από το **ύψος** (`max-h-[..vh]`) — δηλαδή σε κάθε φαρδιά
 * οθόνη — το κουτί γίνεται φαρδύτερο από την εικόνα, το SVG κεντράρει το `viewBox` (`xMidYMid meet`), και:
 *   - **μετρημένο 01/10** (κάτοψη 1200×800, κουτί 1894 vs εικόνα 1176 CSS px): κλικ στο **κέντρο** της εικόνας
 *     γράφτηκε ως `x = 0,195`. Ο επεξεργαστής φαινόταν σωστός (σημάδι και κλικ μετατοπίζονταν **μαζί**)· η δημόσια
 *     σελίδα θα έδειχνε το σημείο σε **άλλο δωμάτιο** — σιωπηλή αλλοίωση δεδομένων.
 *   - **ADR-880, 24/09**: το ίδιο στον κάθετο άξονα (grid item, χαμηλή φωτογραφία) ⇒ κλικ σε λάθος `y`.
 *
 * ✅ `w-fit` (ρητό πλάτος ⇒ κανένα τέντωμα σε κανέναν γονέα) · `self-start` (κανένα κάθετο τέντωμα ως grid/flex item) ·
 *   `mx-auto` (κεντράρισμα χωρίς να μεγαλώσει το κουτί).
 * ⚠️ Το jsdom **δεν** έχει διάταξη: κανένα jest δεν βλέπει αυτό το σφάλμα. Γι' αυτό ζει σε **μία** σταθερά, και η
 *   σουίτα καρφώνει ότι κάθε επιφάνεια επικάλυψης τη φορά.
 */
export const IMAGE_OVERLAY_FRAME_CLASS = 'relative m-0 mx-auto w-fit self-start';
