'use client';

/**
 * @fileoverview **ΠΑΡΑΔΟΣΗ ΣΥΝΕΔΡΙΑΣ** — «μην αγγίζεις το token· ο διακομιστής το αντικαθιστά» (ADR-892 §13).
 * @related auth/issued-session (η υιοθέτηση του νέου κλειδιού) · use-claims-refresh (ο ακροατής που σωπαίνει)
 * @module auth/contexts/auth-context/session-handover
 *
 * 🔴 **Η ΚΟΥΡΣΑ ΠΟΥ ΚΛΕΙΝΕΙ**: όταν ο άνθρωπος αποχωρεί από τον **οικείο** του χώρο, ο διακομιστής γράφει νέα
 * claims (ανεβαίνει το `users/{uid}.claimsUpdatedAt`) και **ανακαλεί** τα refresh tokens — **μέσα** στο ίδιο
 * αίτημα, πριν απαντήσει με το κλειδί της νέας συνεδρίας. Ο `useClaimsRefresh` βλέπει το `claimsUpdatedAt` και
 * κάνει `getIdTokenResult(true)`: αν προλάβει την ανάκληση, στήνει συνεδρία με το **παλιό** `auth_time` (που η
 * σφραγίδα θα απορρίψει)· αν δεν προλάβει, η ανανέωση αποτυγχάνει και το Firebase SDK **αποσυνδέει** — και οι
 * φρουροί στέλνουν τον άνθρωπο στη σύνδεση πριν φτάσει το κλειδί. Και οι δύο δρόμοι σπάνε την παράδοση.
 *
 * 🔑 **Ένας κάτοχος**: όσο διαρκεί η παράδοση, ο ακροατής **σωπαίνει**. Την ολοκληρώνει όποιος την ξεκίνησε,
 * αφού υιοθετηθεί το νέο κλειδί και το `AuthContext` στήσει **και** χρήστη **και** cookie (`SessionPhase`).
 * ⚠️ **Μετρητής, όχι σημαία**: δύο παραδόσεις που επικαλύπτονται δεν ανοίγουν η μία την πόρτα της άλλης.
 * 🔶 Όριο: ένα **άλλο** αίτημα API που τύχει στο ίδιο παράθυρο μπορεί ακόμη να αποσυνδέσει (401 → αναγκαστική
 * ανανέωση). Τότε ο άνθρωπος καταλήγει στη σύνδεση — ασφαλές, απλώς όχι ομαλό (ADR-892 §13).
 */

let active = 0;

/** Ξεκινά παράδοση· επιστρέφει τη συνάρτηση που την τελειώνει (ιδεμποτική). */
export function beginSessionHandover(): () => void {
  active += 1;
  let ended = false;
  return () => {
    if (ended) return;
    ended = true;
    active -= 1;
  };
}

/** Τρέχει παράδοση; — ο ακροατής των claims δεν ανανεώνει όσο απαντά «ναι». */
export function isSessionHandoverActive(): boolean {
  return active > 0;
}
