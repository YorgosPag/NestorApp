/** Τα δύο πεδία που δηλώνει ο άνθρωπος — **ποτέ** το παραγόμενο `displayName`. */
export interface ProfileNames {
  readonly givenName: string;
  readonly familyName: string;
}

/**
 * **Το ονοματεπώνυμο προς εμφάνιση**, παραγόμενο από τα δύο.
 *
 * ⚠️ **Μερική συμπλήρωση παράγει κανονικά κείμενο** (`'Παγώνης'`), και είναι σκόπιμο:
 * αλλιώς δεν θα μπορούσε κανείς να αφαιρέσει **μόνο** το επώνυμό του. Το «τίποτα» το
 * κρίνει το {@link isNameDeclaration}, όχι αυτό.
 *
 * 🔴 **ΚΑΘΕ ΜΕΡΟΣ ΚΟΒΕΤΑΙ ΧΩΡΙΣΤΑ — ΤΟ ΒΡΗΚΕ ΑΓΚΥΡΑ, ΟΧΙ ΑΝΑΓΝΩΣΗ (2026-08-30).** Η
 * προηγούμενη γραφή ήταν `` `${g} ${f}`.trim() ``: κόβει μόνο τα **άκρα**, οπότε
 * `'  Γεώργιος '` + `' Παγώνης  '` έδινε **`'Γεώργιος   Παγώνης'`** — με τρία κενά.
 * Όσο ο μόνος καταναλωτής ήταν το Firebase Auth, ήταν καλαισθησία.
 *
 * ⚠️ **Με δεύτερο αποθετήριο γίνεται ασυνέπεια δεδομένων**: ο γραφέας του
 * `users/{uid}` αποθηκεύει τα δύο πεδία **κομμένα**, άρα το παραγόμενο θα διέφερε από
 * τη σύνθεσή τους — δηλαδή το έγγραφο θα κουβαλούσε **δύο εκδοχές** του ίδιου
 * ονόματος, και ο επόμενος αναγνώστης θα διάλεγε **όποια τύχει**.
 */
export function composedDisplayName(names: ProfileNames): string {
  return [names.givenName.trim(), names.familyName.trim()].filter((part) => part !== '').join(' ');
}

/**
 * **Δήλωσε όνομα ο άνθρωπος, ή απλώς πάτησε Αποθήκευση;**
 *
 * 🔑 Ο **ΕΝΑΣ** κριτής και για τα δύο αποθετήρια: ό,τι δεν είναι δήλωση **δεν
 * γράφεται πουθενά** — ούτε στο Firebase Auth, ούτε στο `users/{uid}`.
 */
export function isNameDeclaration(names: ProfileNames): boolean {
  return composedDisplayName(names).length > 0;
}
