// =============================================================================

/**
 * `workspace_aliases/{skeleton}` — **ο σκελετός ΕΙΝΑΙ το κλειδί εγγράφου.**
 *
 * ⚠️ **ΜΗΝ** προσθέσεις πεδίο `skeleton` εδώ: θα ήταν **δεύτερη αλήθεια** δίπλα
 * στο κλειδί, και οι δύο θα μπορούσαν να αποκλίνουν (ADR-749). Ο σκελετός
 * διαβάζεται από τη **διαδρομή**.
 */
export interface WorkspaceAliasRecord {
  /** Το αναγνωριστικό του χώρου — **αμετάβλητο**, σε αντίθεση με το ψευδώνυμο. */
  readonly companyId: string;

  /**
   * Το ψευδώνυμο **όπως το έγραψε ο άνθρωπος** (πεζό, αλλά με το σενάριο γραφής
   * του ακέραιο: `παγωνης`, όχι `pagonis`).
   */
  readonly alias: string;

  /**
   * `true` για το **τρέχον** ψευδώνυμο του χώρου· `false` για τα **παλιά**, που
   * εξακολουθούν να λύνονται και **δεν ελευθερώνονται ποτέ** (Ε-5 §8 γ).
   *
   * ⚠️ Ένας χώρος έχει **ακριβώς ένα** `current: true` και **οσαδήποτε** `false`.
   */
  readonly current: boolean;

  readonly createdAt: Date;

  /** Πότε έπαψε να είναι το τρέχον — `null` όσο είναι. */
  readonly retiredAt: Date | null;
}
