/**
 * «Πώς λέγεται αυτός ο χώρος στη διεύθυνση;» — το λεξιλόγιο, μία φορά
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΛΥΝΕΙ (ADR-787 §5.3 · Ε-5 §8)
 * ─────────────────────────────────────────────────────────────────────────────
 * Η **Φάση 3** βάζει τον χώρο στη διεύθυνση: `/o/<ψευδώνυμο>/…`. Το ψευδώνυμο
 * είναι **όνομα, όχι κλειδί** — ο χώρος έχει **αμετάβλητο** αναγνωριστικό
 * (`comp_…`), και το ψευδώνυμο μπορεί να αλλάξει.
 *
 * 🔑 **Τρία πράγματα που δεν είναι προφανή, και τα τρία είναι αποφάσεις:**
 *
 * 1. **Το παλιό ψευδώνυμο ΔΕΝ ελευθερώνεται ΠΟΤΕ** (Ε-5 §8 γ). Το GitHub
 *    ανακατευθύνει μετά από μετονομασία αλλά **αφήνει το παλιό όνομα ελεύθερο**·
 *    τότε η ανακατεύθυνση σταματά και ο **νέος κάτοχος κληρονομεί τους
 *    συνδέσμους**. Εδώ ένας σύνδεσμος προς μελέτη **δεν αλλάζει ποτέ ιδιοκτήτη**.
 *
 * 2. **Μοναδικός είναι ο ΣΚΕΛΕΤΟΣ, όχι το κείμενο.** Δύο ψευδώνυμα που *φαίνονται*
 *    ίδια δεν επιτρέπονται και τα δύο, ακόμα κι αν τα bytes διαφέρουν.
 *
 * 3. **Η μοναδικότητα είναι ιδιότητα της ΔΙΑΔΡΟΜΗΣ, όχι έλεγχος που θυμάσαι**:
 *    το έγγραφο ζει στο `workspace_aliases/{skeleton}`, δηλαδή **ο σκελετός είναι
 *    το κλειδί**. Δύο αιτήματα για οπτικά ταυτόσημα ονόματα συγκρούονται στο
 *    Firestore — δεν χρειάζεται κανείς να ρωτήσει. Ίδια πειθαρχία με το §5.1 γ
 *    (*«όνομα που δεν μπορεί να συγκρουστεί»*).
 *
 * ⛔ **ΔΕΝ αποφασίζεται εδώ ποιος διαλέγει το ψευδώνυμο ή πώς προτείνεται** —
 *    ανήκει στο **ADR-748**.
 *
 * @module types/workspace-alias
 */

