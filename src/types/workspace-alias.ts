/**
 * Ελάχιστο μήκος. **Τρεις** χαρακτήρες, όπως GitHub/Slack: με δύο, ο χώρος
 * ονομάτων εξαντλείται από squatting πριν προλάβει να τον χρησιμοποιήσει κανείς.
 */
export const ALIAS_MIN_LENGTH = 3;

/**
 * Μέγιστο μήκος. **63**, όσο ένα DNS label.
 *
 * ⚠️ Ο λόγος **δεν** είναι ότι το ψευδώνυμο είναι υποτομέας — το Ε-5 §7 απέρριψε
 * ρητά τους υποτομείς. Είναι ότι το όριο **κρατά τον δρόμο ανοιχτό**: αν κάποτε
 * επαληθευτεί το κόστος wildcard πιστοποιητικού, **κανένα υπάρχον ψευδώνυμο δεν
 * θα χρειαστεί να αλλάξει**. Ένα όριο που δεν κοστίζει τίποτα σήμερα και σώζει
 * μια μετανάστευση αύριο.
 */
export const ALIAS_MAX_LENGTH = 63;

/**
 * Οι επιτρεπτοί χαρακτήρες: **γράμματα** (λατινικά *ή* ελληνικά), **ψηφία**,
 * και **παύλα** ως διαχωριστής — ποτέ στην αρχή ή στο τέλος.
 *
 * ⚠️ Η εφαρμογή είναι **ελληνική**. Η λύση των μεγάλων (*«μόνο ASCII»* —
 * GitHub, Slack) είναι εδώ **μη λύση**: ένα γραφείο θέλει να λέγεται με το όνομά
 * του. Γι' αυτό ακριβώς υπάρχει ο σκελετός (Ψ1) και ο κανόνας ενός σεναρίου (Ψ2).
 */
export const ALIAS_PATTERN = /^[\p{Letter}\p{Number}](?:[\p{Letter}\p{Number}-]*[\p{Letter}\p{Number}])?$/u;

/**
 * Το **δεσμευμένο ψευδώνυμο του ιδιωτικού χώρου** (Ε-5 §5).
 *
 * ⚠️ Ο ιδιωτικός χώρος **δεν είναι φάκελος** — είναι τιμή ψευδωνύμου. Άρα δεν
 * μπορεί να ανακαλυφθεί σαρώνοντας το δέντρο, και **πρέπει** να δηλωθεί.
 * Είναι η **μοναδική** χειρόγραφη εγγραφή του Ψ3, και ο λόγος της είναι γραμμένος.
 */
export const PERSONAL_WORKSPACE_ALIAS = 'me';

// =============================================================================
// ΟΙ ΕΤΥΜΗΓΟΡΙΕΣ — ΡΗΤΕΣ, ΚΛΕΙΣΤΕΣ, FAIL-CLOSED
// =============================================================================

/**
 * Γιατί απορρίφθηκε ένα ψευδώνυμο — **κάθε αιτία έχει όνομα**.
 *
 * ⚠️ Οι δύο τελευταίες είναι **διαφορετικές** και δεν επιτρέπεται να ενωθούν:
 * το `already-taken` λέει *«αυτό ακριβώς το όνομα υπάρχει»*, το `look-alike-taken`
 * λέει *«υπάρχει άλλο που **φαίνεται** ίδιο»*. Ο άνθρωπος που παίρνει το δεύτερο
 * βλέπει ελεύθερο όνομα και απόρριψη — **οφείλει** να μάθει γιατί, αλλιώς
 * ξαναδοκιμάζει το ίδιο.
 */
export type AliasRejection =
  | 'too-short'
  | 'too-long'
  | 'invalid-characters'
  | 'mixed-script'
  | 'reserved'
  | 'already-taken'
  | 'look-alike-taken';

/** Η ετυμηγορία ενός υποψήφιου ψευδωνύμου. */
export type AliasVerdict =
  | { readonly ok: true; readonly alias: string; readonly skeleton: string }
  | { readonly ok: false; readonly reason: AliasRejection; readonly detail?: string };

