// 4. ΤΟ ΕΓΓΡΑΦΟ — ό,τι ξέρει ο ΔΙΑΚΟΜΙΣΤΗΣ
// =============================================================================

/** Το αίτημα, ολόκληρο. **Δεν φεύγει ποτέ από τον διακομιστή ως έχει.** */
export interface MandateRequest {
  /** `mreq_*` — ADR-017/N.6. */
  readonly id: string;
  /**
   * **ΔΕΙΚΤΗΣ, ποτέ αντίγραφο** (§8.2). Το γραφείο βλέπει τη **δημόσια προβολή** αυτής
   * της αγγελίας — ακριβώς ό,τι βλέπει ο κόσμος, ούτε ένα πεδίο παραπάνω.
   *
   * ⚠️ **Συνέπεια, δηλωμένη**: αγγελία σε `draft` **δεν** μπορεί να ανατεθεί. Δεν είναι
   * περιορισμός που προσθέτουμε· είναι η **απουσία** του εγγράφου που θα διάβαζε το
   * γραφείο.
   */
  readonly ownerPropertyId: string;
  /** Ο ιδιώτης. 🔴 **ΔΕΝ υπάρχει στο {@link MandateRequestForAgency}.** */
  readonly requestedByUserId: string;
  readonly agencyCompanyId: string;
  readonly initiatedBy: MandateRequestInitiator;
  readonly status: MandateRequestStatus;
  readonly terms: ProposedMandateTerms;
  readonly requestedAt: string;
  /** Το άνοιξε ο παραλήπτης — πρβλ. `viewedAt` της εντολής. `null` όσο δεν το είδε. */
  readonly seenAt: string | null;
  readonly decidedAt: string | null;
  /**
   * **Γεννιέται ΜΟΝΟ με την αποδοχή** (§8.4), στην ίδια ατομική πράξη. `null` όσο
   * εκκρεμεί, `null` για πάντα αν απορρίφθηκε.
   *
   * 🏆 Γι' αυτό το ερώτημα *«πόσο κρατά τα στοιχεία το γραφείο που αρνήθηκε;»*
   * **δεν γεννιέται**: δεν έλαβε ποτέ στοιχεία.
   */
  readonly clientContactId: string | null;
  /**
   * **Ποιο απορριφθέν αίτημα αναθεωρεί αυτό;** — `null` όταν είναι το πρώτο.
   *
   * 🏆 **ΔΑΝΕΙΟ ΑΠΟ ΤΟΝ AUTODESK CONSTRUCTION CLOUD, ΟΧΙ ΕΦΕΥΡΕΣΗ** (§9.17 δ). Εκεί
   * ένα submittal/RFI που απορρίφθηκε δεν ξαναστέλνεται ίδιο: γίνεται
   * *«Revise and Resubmit»*, και *«new log entries are created for resubmittals **and
   * linked to the original**»*. Η αλυσίδα είναι που κάνει την αναθεώρηση **αναγνώσιμη
   * ως αναθεώρηση** αντί για δεύτερο, ταυτόσημο ερώτημα.
   *
   * 🔑 **ΚΑΙ ΠΑΜΕ ΠΑΡΑΠΕΡΑ**: εκεί η αλυσίδα είναι **ροή εργασίας που κάποιος
   * διαχειρίζεται**· εδώ είναι **αμετάβλητο του εγγράφου** — γράφεται στη γέννηση, και
   * κανένας διαχειριστής δεν μπορεί να την παρακάμψει.
   *
   * ⚠️ **ΔΕΝ είναι στο {@link MandateRequestForAgency}, και είναι απόφαση.** Το τι
   * βλέπει το γραφείο όταν κρίνει είναι **απόφαση αποκάλυψης** (§8.2) και ανήκει στην
   * οθόνη του Σ2 — όχι σε πλάγια είσοδο από τη γέννηση. Το Σ1 το **γράφει**· ποιος το
   * **διαβάζει** αποφασίζεται ξεχωριστά.
   *
   * ⚠️ **Δείχνει ΜΟΝΟ σε `declined-revisable`.** Δύο αποκλεισμοί, δύο λόγοι:
   *
   * - Η **απόσυρση** (`withdrawn`) την έκανε ο ίδιος ο ιδιώτης· ταυτόσημο αίτημα μετά
   *   από **δική του** απόσυρση είναι *«το ξανασκέφτηκα»*, όχι αναθεώρηση κρίσης που
   *   έδωσε κάποιος άλλος. Ο κανόνας φυλά την **κρίση του γραφείου**, όχι την
   *   αναποφασιστικότητα του ιδιοκτήτη.
   * - Το **`declined-final`** δεν έχει διάδοχο **εξ ορισμού**: αν είχε, δεν θα ήταν
   *   τελικό. Ο δείκτης δεν «απαγορεύεται» να δείξει εκεί — **δεν γεννιέται ποτέ
   *   αίτημα** να τον κρατήσει, γιατί ο κριτής σταματά πριν.
   */
  readonly supersedesRequestId: string | null;
}

/**
 * **Το ΩΜΟ έγγραφο, όπως βγαίνει από τη Firestore** — ίδιο με το
 * {@link MandateRequest}, αλλά με **ανοιχτή** κατάσταση.
 *
 * 🔴 **Ο τύπος λέει την αλήθεια αντί να την υποθέτει.** Το ιδίωμα
 * `doc.data() as MandateRequest` είναι **ψέμα** για κάθε έγγραφο γραμμένο πριν το
 * §9.21: εκείνα έχουν `status: 'declined'`, τιμή που **δεν ανήκει** πια στο κλειστό
 * σύνολο. Ένας μεταγλωττιστής που πείστηκε ότι ανήκει δεν θα ζητήσει ποτέ από κανέναν
 * να τη μεταφράσει.
 *
 * ⚠️ **ΜΟΝΟ το `status` ανοίγει**, και είναι μέτρηση όχι φειδώ: είναι το **μόνο** πεδίο
 * που άλλαξε **νόημα**. Ένα καθολικό `Record<string, unknown>` θα απαιτούσε πλήρη
 * αναλυτή για **κάθε** πεδίο — δηλαδή δεύτερο σχήμα δίπλα στο πρώτο (ADR-749), για ένα
 * πρόβλημα που έχει **ένα** πεδίο.
 */
export type MandateRequestDocument = Omit<MandateRequest, 'status'> & {
  readonly status: string;
};

/**
 * **Ό,τι βγαίνει από τη βάση περνά ΑΠΟ ΕΔΩ.**
 *
 * 🔑 **Η μετάφραση ζει ΜΙΑ φορά, στον τύπο** — όχι σε κάθε αναγνώστη. Ο γραφέας του Σ1,
 * ο κατάλογος του Σ2 και η συναλλαγή του Σ3 ρωτούν **την ίδια** συνάρτηση· αλλιώς η
 * τρίτη διαδρομή που θα γραφόταν κάποτε θα ξεχνούσε το κληροδότημα και θα διάβαζε το
 * παλιό «όχι» ως **άγνωστο**.
 *
 * ⚠️ Η **διάγνωση** δεν επιστρέφεται εδώ επίτηδες: ο καλών που θέλει να την καταγράψει
 * ρωτά το {@link readStoredRequestStatus} με το ίδιο ωμό πεδίο. Είναι **καθαρή**
 * συνάρτηση — δύο ερωτητές, μία απάντηση, καμία δυνατότητα απόκλισης.
 */
export function mandateRequestFromStored(
  stored: MandateRequestDocument,
): MandateRequest {
  return { ...stored, status: readStoredRequestStatus(stored.status).status };
}

// =============================================================================
// 5. Η ΠΡΟΒΟΛΗ — ό,τι βλέπει το ΓΡΑΦΕΙΟ όσο κρίνει
// =============================================================================

/**
 * **Κλειστό σχήμα, ΧΩΡΙΣ πεδίο ταυτότητας.**
 *
 * 🔴 **Ο φρουρός είναι ΤΥΠΟΣ, όχι κανόνας** (§8.2): δεν «απαγορεύεται» να σταλεί όνομα
 * — **δεν υπάρχει πεδίο να μπει**. Ίδια άμυνα με το `MandateCompensation` που δεν
 * μπορεί να εκφραστεί στο `PublicListing`.
 */
export interface MandateRequestForAgency {
  readonly id: string;
  /** Η **δημόσια** προβολή της αγγελίας, τίποτα άλλο. */
  readonly listing: PublicListing;
  readonly terms: ProposedMandateTerms;
  readonly requestedAt: string;
  readonly initiatedBy: MandateRequestInitiator;

  // ───────────────────────────────────────────────────────────────────────────
  // 🔴 ΤΑ ΤΕΣΣΕΡΑ ΤΟΥ Σ2 — ΠΡΟΣΤΕΘΗΚΑΝ ΩΣ **ΑΠΟΦΑΣΗ ΑΠΟΚΑΛΥΨΗΣ** (§9.21)
  // ───────────────────────────────────────────────────────────────────────────
  //
  // 🔑 **Ο ΚΑΝΟΝΑΣ ΠΟΥ ΤΑ ΕΠΙΤΡΕΠΕΙ, ΓΡΑΜΜΕΝΟΣ ΩΣΤΕ ΝΑ ΚΡΙΝΕΙ ΚΑΙ ΤΟ ΕΠΟΜΕΝΟ**:
  //    περνούν **μόνο** πεδία που περιγράφουν **τι έκανε ΤΟ ΙΔΙΟ ΤΟ ΓΡΑΦΕΙΟ** ή **η
  //    ίδια του η αλυσίδα ερωτήσεων**. Κανένα δεν λέει τίποτα για **το πρόσωπο** —
  //    ούτε ποιος είναι, ούτε πόσα ακίνητα έχει, ούτε σε ποιους άλλους απευθύνθηκε.
  //
  // ⚠️ Το `requestedByUserId` **ΔΕΝ** μπήκε και **δεν πρόκειται**: εκεί ακριβώς περνά
  //    η γραμμή του §8.2. Ο φρουρός παραμένει **τύπος**, όχι κανόνας.

  /**
   * **Το άνοιξε κάποιος από το γραφείο;** — `null` όσο κανείς δεν το έχει δει.
   *
   * 🔑 Είναι **δικό του** γεγονός: το έγραψε ο ίδιος ο παραλήπτης ανοίγοντάς το.
   * Χωρίς αυτό, η οθόνη δεν μπορεί να ξεχωρίσει *«νέο»* από *«το είδα, δεν απάντησα
   * ακόμη»* — και ένα γραφείο με 20 αιτήματα δεν έχει τρόπο να δει τι είναι καινούριο.
   */
  readonly seenAt: string | null;

  /**
   * **Τι απάντησε το γραφείο** — ή `pending` όσο δεν απάντησε.
   *
   * ⚠️ **ΔΕΝ είναι διαρροή, είναι η ΙΔΙΑ του η πράξη**: ο κριτής βλέπει το δικό του
   * αρχείο. Χωρίς αυτό η οθόνη δεν μπορεί να δείξει *τι έχω ήδη κρίνει*, και το
   * γραφείο θα ξαναρωτούσε τον εαυτό του.
   */
  readonly status: MandateRequestStatus;

  /** Πότε το έκρινε — `null` όσο εκκρεμεί. Ίδιος λόγος με το {@link status}. */
  readonly decidedAt: string | null;

  /**
   * **Ποιο δικό του «όχι» αναθεωρεί αυτό;** — `null` όταν είναι η πρώτη ερώτηση.
   *
   * 🔴 **ΤΟ ADR ΤΟ ΕΙΧΕ ΑΦΗΣΕΙ ΡΗΤΑ ΑΝΟΙΧΤΟ, ΚΑΙ ΚΛΕΙΝΕΙ ΕΔΩ.** Το σχόλιο του
   * {@link MandateRequest.supersedesRequestId} λέει: *«το τι βλέπει το γραφείο όταν
   * κρίνει είναι απόφαση αποκάλυψης και ανήκει στην οθόνη του Σ2 — όχι σε πλάγια
   * είσοδο από τη γέννηση»*. Η απόφαση είναι **ναι**, για τον λόγο που γέννησε την
   * αλυσίδα: *«new log entries are created for resubmittals **and linked to the
   * original**»*. Η αλυσίδα είναι που κάνει την αναθεώρηση **αναγνώσιμη ως
   * αναθεώρηση** — αλλιώς ο μεσίτης βλέπει ό,τι μοιάζει με **δεύτερο, ταυτόσημο
   * ερώτημα** και το διαβάζει ως επιμονή.
   *
   * 🔑 **Και δεν αποκαλύπτει τίποτα καινούριο**: δείχνει σε αίτημα που **αυτός ο ίδιος
   * απέρριψε** και το οποίο βλέπει ήδη στον κατάλογό του.
   */
  readonly supersedesRequestId: string | null;
}

/**
 * Ο φρουρός του κλειστού σχήματος — ίδιο κόλπο με `PublicListingOpenGaps`.
 *
 * ⚠️ Κάθε προσθήκη πεδίου στο {@link MandateRequestForAgency} είναι **απόφαση
 * αποκάλυψης**, και διαβάζεται ως τέτοια στο diff.
 */
export type MandateRequestForAgencyOpenGaps = never;

/**
 * **Η ΜΙΑ ΣΥΝΘΕΣΗ ΤΗΣ ΠΡΟΒΟΛΗΣ** — καθαρή συνάρτηση, δίπλα στον τύπο που τη φυλά.
 *
 * 🔴 **ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΤΗΝ ΥΠΗΡΕΣΙΑ.** Η απομόνωση του §8.2 επιτυγχάνεται **με το
 * τι συντίθεται**. Αν η σύνθεση ζούσε στον αναγνώστη, κάθε **νέος** αναγνώστης *(η
 * λίστα, η λεπτομέρεια, μια μελλοντική ειδοποίηση)* θα την ξανάγραφε — και η δεύτερη
 * γραφή είναι που ξεχνά ένα πεδίο ή προσθέτει ένα. Εδώ, δίπλα στο κλειστό σχήμα, η
 * σύνθεση είναι **μία** και το diff της διαβάζεται ως **απόφαση αποκάλυψης**.
 *
 * 🔑 **ΔΕΝ κάνει `{...request}`, και είναι το όλο νόημα**: απαριθμεί **ονομαστικά** ό,τι
 * περνά. Ένα spread θα περνούσε το `requestedByUserId` **σιωπηλά** — και θα το έκανε
 * ξανά, μόνο του, την επόμενη φορά που κάποιος προσθέτει πεδίο στο έγγραφο.
 *
 * ⚠️ Το `listing` **δίνεται**, δεν διαβάζεται: αυτή η συνάρτηση είναι **καθαρή** ώστε
 * να δοκιμάζεται χωρίς Firestore — ίδιο ιδίωμα με το `judgeAgainstHistory`.
 */
export function mandateRequestForAgency(
  request: MandateRequest,
  listing: PublicListing,
): MandateRequestForAgency {
  return {
    id: request.id,
    listing,
    terms: request.terms,
    requestedAt: request.requestedAt,
    initiatedBy: request.initiatedBy,
    seenAt: request.seenAt,
    status: request.status,
    decidedAt: request.decidedAt,
    supersedesRequestId: request.supersedesRequestId,
  };
}

