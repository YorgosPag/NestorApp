// 2. Η ΚΑΤΑΣΤΑΣΗ — τέσσερις τιμές, καμία «λήξη»
// =============================================================================

/**
 * **Πού βρίσκεται το αίτημα.**
 *
 * 🔴 **ΔΕΝ ΥΠΑΡΧΕΙ `expired`, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ.** Ένα αίτημα «λήγει» όταν η **εντολή
 * που προτείνει** δεν μπορεί πια να ισχύσει — και αυτό **υπολογίζεται** από το
 * `terms.expiresAt` ({@link isRequestActionable}). Αποθηκευμένο `expired` θα απαιτούσε
 * **σαρωτή** που το γράφει, δηλαδή:
 *
 *   1. δεύτερο βιβλίο που μπορεί να **μη** τρέξει (ένα cron που σταμάτησε ⇒ αιτήματα
 *      που φαίνονται ζωντανά ενώ είναι νεκρά), και
 *   2. **δύο** απαντήσεις στο *«ισχύει ακόμη;»* — του πεδίου και του ρολογιού.
 *
 * Είναι το **ίδιο δόγμα** με το {@link disclosedTo} και με το `isMandateExpired`:
 * *η κατάσταση που αποφασίζει είναι η κατάσταση που απαντά*.
 *
 * ⚠️ Το `withdrawn` **δεν** είναι πολυτέλεια: χωρίς αυτό, αίτημα που κανείς δεν
 * απαντά κρατά την αγγελία δεσμευμένη χωρίς έξοδο — και η έξοδος του ιδιοκτήτη είναι
 * ακριβώς ό,τι φυλά το `agencyRevokedAt` από την άλλη πλευρά.
 */
export const MANDATE_REQUEST_STATUSES = [
  'pending',
  'accepted',
  'declined-revisable',
  'declined-final',
  'withdrawn',
] as const;

export type MandateRequestStatus = (typeof MANDATE_REQUEST_STATUSES)[number];

export function isMandateRequestStatus(value: unknown): value is MandateRequestStatus {
  return (
    typeof value === 'string' &&
    (MANDATE_REQUEST_STATUSES as readonly string[]).includes(value)
  );
}

// =============================================================================
// 2.1 🏆 ΤΑ ΔΥΟ «ΟΧΙ» — ΔΙΑΦΕΡΟΥΝ ΣΤΗΝ **ΕΞΟΥΣΙΑ**, ΟΧΙ ΣΤΟ ΥΦΟΣ
// =============================================================================

/**
 * **Τι μπορεί να απαντήσει το γραφείο.** Κλειστό σύνολο **τριών**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ADR ΕΛΕΓΕ ΟΤΙ Ο AUTODESK ΚΑΝΕΙ ΑΥΤΟ. **ΜΕΤΡΗΘΗΚΕ — ΔΕΝ ΤΟ ΚΑΝΕΙ.**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `§9.17 δ` έγραφε *«ο Autodesk έχει δύο είδη «όχι» — `Rejected` (**τέλος**) και
 * `Revise and Resubmit` (πρόσκληση)»*. Η τεκμηρίωσή του λέει το **αντίθετο**:
 *
 * > *«The "Create New Revision" option … is available if any of the items were
 * > assigned the statuses of **Rejected or Revise and Resubmit**»*
 *
 * ⇒ Εκεί **και τα δύο** «όχι» ξαναανοίγουν την πόρτα. Διαφέρουν σε **ύφος**, όχι σε
 * **εξουσία** — δηλαδή είναι **δύο ονόματα για ένα πράγμα**, και ο κανόνας που
 * υποτίθεται ότι αντικαθιστούν θα έμενε αναγκαίος.
 *
 * 🔑 **Το σωστό πρότυπο είναι παλαιότερο και καθαρότερο**: η διάκριση των μηχανών ροής
 * εργασίας (BPM) ανάμεσα σε **`Reject` = τερματικό** και **`Return` = επιστροφή για
 * διόρθωση**. Εκεί τα δύο «όχι» διαφέρουν σε **εξουσία** — το μόνο που έχει νόημα να
 * μοντελοποιηθεί, γιατί είναι το μόνο που αλλάζει **τι επιτρέπεται μετά**.
 *
 * | Απόφαση | Τι σημαίνει | Τι επιτρέπει μετά |
 * |---|---|---|
 * | `accepted` | ναι | το ζεύγος κλειδώνει — υπάρχει εντολή |
 * | `declined-revisable` | *«όχι έτσι — στείλε ξανά»* | **ΝΑΙ**, νέο αίτημα με **οποιουσδήποτε** όρους |
 * | `declined-final` | *«όχι»* | **ΟΧΙ**, όσο ζει **αυτή** η αγγελία |
 *
 * 🔑 **Το `declined-final` ΔΕΝ είναι μόνιμο βέτο** — εκείνο το είχε ήδη απορρίψει το
 * Δ4. Δένεται στη **ζωή της αγγελίας**, ακριβώς όπως το §8.5 δένει εκεί και τη
 * διατήρηση του απορριφθέντος αιτήματος. Ο ιδιοκτήτης που αποσύρει και ξαναδημοσιεύει
 * **ξαναρωτά** — γιατί άλλαξε το **αντικείμενο της κρίσης**, όχι επειδή επέμεινε.
 *
 * 🏆 **ΠΟΥ ΞΕΠΕΡΝΑΜΕ**: στον Autodesk η άδεια επανυποβολής είναι **ρύθμιση ροής που
 * διαχειρίζεται κάποιος**· εδώ είναι **αμετάβλητο του εγγράφου**. Η νέα υποβολή
 * ελέγχει το **ρητό δικαίωμα που έδωσε ο κριτής**, όχι μια υπολογισμένη διαφορά όρων
 * που κανείς δεν ζήτησε.
 *
 * ⚠️ **Ο τύπος επιβάλλει τη σχέση**: κάθε απόφαση **είναι** κατάσταση. Ένα τέταρτο
 * ρήμα που δεν αντιστοιχεί σε κατάσταση **δεν μεταγλωττίζεται**.
 */
export const MANDATE_REQUEST_DECISIONS = [
  'accepted',
  'declined-revisable',
  'declined-final',
] as const satisfies readonly MandateRequestStatus[];

export type MandateRequestDecision = (typeof MANDATE_REQUEST_DECISIONS)[number];

export function isMandateRequestDecision(
  value: unknown,
): value is MandateRequestDecision {
  return (
    typeof value === 'string' &&
    (MANDATE_REQUEST_DECISIONS as readonly string[]).includes(value)
  );
}

/**
 * **Επιτρέπει αυτή η κατάσταση νέο αίτημα για το ίδιο ζεύγος;**
 *
 * 🔑 **Η ΜΙΑ απάντηση, για δύο ερωτητές**: τον γραφέα του Σ1 (*«να το δεχτώ;»*) και
 * την οθόνη του ιδιώτη (*«μπορώ να ξαναστείλω;»*). Δύο ξεχωριστές γραφές θα ήταν δύο
 * κριτές στο **ίδιο** ερώτημα (ADR-749) — και η οθόνη θα πρόσφερε κουμπί που ο
 * διακομιστής απορρίπτει.
 */
export function allowsResubmission(status: MandateRequestStatus): boolean {
  return status === 'declined-revisable' || status === 'withdrawn';
}

