/**
 * **Είναι αυτή η ίδια ερώτηση;** — καθαρή σύγκριση των τριών όρων.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΤΟ ΜΟΝΤΕΛΟ ΕΙΝΑΙ ΤΟΥ STRIPE, ΚΑΙ ΤΟ ΔΑΝΕΙΖΟΜΑΣΤΕ ΡΗΤΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το idempotency layer του Stripe *«compares incoming parameters to those of the
 * original request and errors if they're not the same»*. Δηλαδή **η ταυτότητα μιας
 * πράξης ΕΙΝΑΙ οι παράμετροί της** — όχι ο χρόνος, όχι ένας μετρητής, όχι ένα κλειδί
 * που ο πελάτης θα μπορούσε να ξεχάσει να στείλει.
 *
 * 🔑 **ΚΑΙ ΠΑΜΕ ΠΑΡΑΠΕΡΑ**: το Stripe απαιτεί από τον πελάτη να **παράγει** UUID και
 * να το θυμάται· εδώ το κλειδί είναι **παραγόμενο από το ίδιο το νόημα** *(ακίνητο ×
 * γραφείο × όροι)*. Πελάτης που ξεχνά το κλειδί του Stripe χρεώνει δύο φορές· εδώ
 * **δεν υπάρχει κλειδί να ξεχαστεί**.
 *
 * ⚠️ **ΔΕΝ συγκρίνει ολόκληρο το αίτημα** — μόνο τους **όρους**. Το `requestedAt`
 * διαφέρει εξ ορισμού σε κάθε πάτημα, και ένα `JSON.stringify(request)` θα έκανε
 * **κάθε** αίτημα μοναδικό: ιδεμποτησία που δεν πυροδοτεί ποτέ, δηλαδή ο ορισμός του
 * αδρανούς φρουρού.
 *
 * ⛔ **ΜΗΝ το γράψεις ως `JSON.stringify(a) === JSON.stringify(b)`.** Η
 * {@link MandateCompensation} είναι **διακριτή ένωση**: δύο ισοδύναμες αμοιβές με
 * διαφορετική **σειρά κλειδιών** *(που η Firestore δεν εγγυάται ότι διατηρεί)* θα
 * έβγαιναν «άλλες», και ο ιδιοκτήτης θα μπορούσε να ξαναστείλει το **ταυτόσημο**
 * αίτημα απλώς επειδή ταξίδεψε από άλλη διαδρομή.
 */
export function sameProposedTerms(
  a: ProposedMandateTerms,
  b: ProposedMandateTerms,
): boolean {
  return (
    a.agreement === b.agreement &&
    a.expiresAt === b.expiresAt &&
    sameCompensation(a.compensation, b.compensation)
  );
}

/**
 * **Ίδια αμοιβή;** — ανά σκέλος της ένωσης, χωρίς `any` και χωρίς σειριοποίηση.
 *
 * 🔑 **Ο μεταγλωττιστής φυλά την πληρότητα**: τρίτο σκέλος στη
 * {@link MandateCompensation} *(π.χ. το δηλωμένα απόν `tiered`)* **δεν
 * μεταγλωττίζεται** μέχρι κάποιος να πει πότε δύο κλιμακωτές αμοιβές είναι ίδιες.
 * Ένα σιωπηλό `return false` στο τέλος θα έκανε **κάθε** νέο σκέλος «πάντα
 * διαφορετικό» — δηλαδή θα άνοιγε τη δίοδο επανάληψης που όλο αυτό κλείνει.
 */
function sameCompensation(a: MandateCompensation, b: MandateCompensation): boolean {
  if (a.type !== b.type) return false;
  if (a.vatIncluded !== b.vatIncluded) return false;

  if (a.type === 'percentage') {
    // ⚠️ Το `b` στενεύει από τον έλεγχο ισότητας παραπάνω — καμία δήλωση τύπου.
    return b.type === 'percentage' && a.percentage === b.percentage;
  }

  return b.type === 'fixed' && a.amountEUR === b.amountEUR;
}
