// 2.2 🔴 ΤΟ ΚΛΗΡΟΔΟΤΗΜΑ — ΤΟ ΠΑΛΙΟ `declined` ΔΙΑΒΑΖΕΤΑΙ ΩΣ **ΤΕΛΙΚΟ**
// =============================================================================

/**
 * Η **μία** τιμή που έγραφε το σχήμα πριν το §9.21, όταν το «όχι» ήταν **ένα**.
 *
 * ⚠️ **Δεν είναι στο {@link MANDATE_REQUEST_STATUSES}, και είναι απόφαση.** Το σύνολο
 * λέει *τι γράφουμε*· αυτή η σταθερά λέει *τι μπορεί να συναντήσουμε*. Αν έμπαινε στο
 * σύνολο, θα γινόταν **τέταρτη γραπτή κατάσταση** — δηλαδή το ίδιο ελάττωμα που η
 * διάσπαση θεραπεύει.
 */
const LEGACY_DECLINED_STATUS = 'declined';

/** Τι έγινε όταν διαβάσαμε την κατάσταση ενός **αποθηκευμένου** αιτήματος. */
export type StoredStatusRepair = 'none' | 'legacy-declined' | 'unreadable';

/** Η απάντηση του {@link readStoredRequestStatus} — τιμή **και** διάγνωση. */
export interface StoredStatusReading {
  readonly status: MandateRequestStatus;
  readonly repaired: StoredStatusRepair;
}

/**
 * **Η κατάσταση ενός αποθηκευμένου αιτήματος — ΠΑΝΤΑ με απάντηση.**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΤΟ ΑΓΝΩΣΤΟ ΓΙΝΕΤΑΙ `declined-final` ΚΑΙ ΟΧΙ `null`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η προφανής γραφή επιστρέφει `null` και ο καλών **πετά** το έγγραφο. Εδώ αυτό είναι
 * **fail-OPEN, όχι fail-closed**, και η ανατροπή είναι σιωπηλή: ο κριτής του Σ1
 * διαβάζει το **ιστορικό του ζεύγους** — ένα χαλασμένο έγγραφο που πέφτει έξω κάνει το
 * ιστορικό να φαίνεται **αδειανό**, δηλαδή ανοίγει την πόρτα που δεν ξέρουμε αν
 * έκλεισε.
 *
 * 🔑 Η ασφαλής μετάφραση του *«δεν ξέρω»* είναι **η πιο περιοριστική κατάσταση που
 * μπορεί να δικαιολογηθεί**, και κάθε συνέπειά της είναι η σωστή:
 *
 * | Ερωτά | Παίρνει | Είναι σωστό; |
 * |---|---|---|
 * | ο κριτής του Σ1 | «η πόρτα είναι κλειστή» | ✅ δεν γεννά αίτημα πάνω σε άγνωστο |
 * | το {@link disclosedTo} | «τίποτα του προσώπου» | ✅ δεν αποκαλύπτει από άγνοια |
 * | το {@link isRequestActionable} | «όχι» | ✅ δεν αποφασίζεται ό,τι δεν διαβάζεται |
 *
 * ⚠️ **Η διάγνωση ταξιδεύει μαζί** ({@link StoredStatusReading.repaired}) ώστε η
 * επισκευή να **λέγεται**, όχι να σιωπά. Μια επισκευή που κανείς δεν καταγράφει είναι
 * αλλοίωση — και ο επόμενος αναγνώστης θα έβλεπε «τελικό όχι» χωρίς να μάθει ποτέ ότι
 * το έγγραφο ήταν χαλασμένο.
 *
 * ⛔ **ΜΗΝ την κάνεις να πετά.** Το ερώτημα *«τι λέει αυτό το έγγραφο;»* έχει πάντα
 * απάντηση· ένα πέταγμα εδώ θα κατέβαζε **ολόκληρο** τον κατάλογο του γραφείου επειδή
 * **ένα** έγγραφο ήταν κακό.
 */
export function readStoredRequestStatus(value: unknown): StoredStatusReading {
  if (isMandateRequestStatus(value)) return { status: value, repaired: 'none' };
  if (value === LEGACY_DECLINED_STATUS) {
    return { status: 'declined-final', repaired: 'legacy-declined' };
  }
  return { status: 'declined-final', repaired: 'unreadable' };
}

