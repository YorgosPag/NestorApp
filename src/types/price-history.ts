import type { PriceRole } from '@/lib/properties/price-resolver';

/**
 * **Μία στιγμή της αγοράς**: από εκείνη τη στιγμή και μέχρι την επόμενη παρατήρηση,
 * ίσχυε αυτή η τιμή — ή η αγγελία ήταν **εκτός αγοράς**.
 *
 * 🔴 **`price: null` ΕΙΝΑΙ ΓΕΓΟΝΟΣ, ΟΧΙ ΑΠΟΥΣΙΑ ΔΕΔΟΜΕΝΩΝ.** Σημαίνει *«από εδώ και πέρα
 * η αγγελία δεν ήταν δημόσια»*. Χωρίς αυτό, μια τιμή 300.000 € που **αποσύρθηκε**
 * πριν έξι μήνες θα θεωρούνταν *«σε ισχύ»* όλο το διάστημα — και η επαναδημοσίευση σε
 * 280.000 € θα έβγαζε **ψεύτικο** «↓7%» για τιμή που κανείς δεν μπορούσε να αγοράσει.
 */
export interface PriceObservation {
  /** ISO στιγμή — η **ίδια** με το `projectedAt` του περάσματος που την κατέγραψε. */
  readonly at: string;
  /** Η τιμή που ίσχυε από το `at` και μετά — `null` = εκτός αγοράς. */
  readonly price: {
    readonly role: PriceRole;
    readonly amount: number;
  } | null;
}

/**
 * **Η μείωση τιμής, όπως τη βλέπει ο κόσμος.**
 *
 * 🏆 **Το `from` είναι η ΧΑΜΗΛΟΤΕΡΗ τιμή των 30 προηγούμενων ημερών, ΟΧΙ η αμέσως
 * προηγούμενη.** Είναι ο κανόνας της Οδηγίας Omnibus (Οδηγία ΕΕ 2019/2161 · άρθρο 6α
 * της Οδηγίας 98/6/ΕΚ · ν. 4933/2022 · ΔΕΕ C-330/23 *ALDI SÜD*, 2024), που νομικά
 * αφορά **αγαθά** και όχι ακίνητα — και **κανένα** portal (Zillow, Rightmove,
 * idealista) δεν τον εφαρμόζει. Εδώ εφαρμόζεται **εθελοντικά**, γιατί είναι ο μόνος
 * ορισμός που κάνει το κόλπο *«ανεβάζω την τιμή και την κατεβάζω για να σταλεί email»*
 * **δομικά άκαρπο**.
 */
export interface PriceReduction {
  /** Ο ρόλος της τιμής — μείωση ενοικίου **δεν** συγκρίνεται ποτέ με τιμή πώλησης. */
  readonly role: PriceRole;
  /** Η χαμηλότερη τιμή του ίδιου ρόλου που ίσχυε στις 30 ημέρες πριν από το `since`. */
  readonly from: number;
  /** Η τρέχουσα τιμή — **πάντα** ίση με την τιμή που δείχνει η αγγελία. */
  readonly to: number;
  /**
   * Η μείωση σε **μονάδες βάσης** (1% = 100) — ακέραιος, στρογγυλεμένος **προς τα
   * κάτω**, ώστε το κατώφλι να μην περνιέται ποτέ από στρογγύλευση.
   */
  readonly dropBasisPoints: number;
  /** ISO στιγμή που ίσχυσε η τρέχουσα τιμή. */
  readonly since: string;
}
