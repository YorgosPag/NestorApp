export type OwnerPropertyInvariant = (typeof OWNER_PROPERTY_INVARIANTS)[number];

/**
 * **Είναι αυτό παραβίαση που ξέρουμε;** — ο φρουρός του συνόρου (ADR-834 §6.5.ε).
 *
 * 🔴 Οι παραβιάσεις ταξιδεύουν **από τον διακομιστή** (422 `INVALID_LISTING`) και
 * καταλήγουν **κλειδιά** στο `TEXT_KEYS`. Ο πελάτης έκανε `Array.isArray(x)` και μετά
 * τυφλό `as OwnerPropertyInvariant[]` — δηλαδή **κάθε** πίνακας περνούσε, με **κάθε**
 * περιεχόμενο. Ένας άγνωστος κωδικός εκεί δεν είναι κενό μήνυμα: είναι **ωμό κλειδί**
 * ζωγραφισμένο στην οθόνη.
 *
 * ⚠️ Επικυρώνεται **στοιχείο-προς-στοιχείο**, ποτέ ο πίνακας συνολικά.
 */
export function isOwnerPropertyInvariant(value: unknown): value is OwnerPropertyInvariant {
  return (
    typeof value === 'string' &&
    (OWNER_PROPERTY_INVARIANTS as readonly string[]).includes(value)
  );
}

/** Θετικός, πεπερασμένος αριθμός. `null`/`0`/αρνητικό/`NaN` → όχι. */
function isPositive(value: number | null | undefined): boolean {
  return typeof value === 'number' && Number.isFinite(value) && value > 0;
}

/**
 * **Ποιοι κανόνες παραβιάζονται** — **ΟΛΟΙ**, ποτέ ο πρώτος.
 *
 * 🔴 **Η ίδια συνάρτηση κρίνει τη ΦΟΡΜΑ και την ΠΥΛΗ ΓΡΑΦΗΣ**, όπως ακριβώς το
 * `demandInvariantViolations`. Δεν είναι διπλός έλεγχος — είναι **ο ίδιος** έλεγχος σε
 * δύο σημεία, που είναι το ακριβώς αντίθετο από δύο ελέγχους: η φόρμα τον τρέχει για
 * να **δείξει** το σφάλμα, η πύλη γιατί **δεν εμπιστεύεται καμία φόρμα**.
 *
 * ⚠️ **Επιστρέφει ΟΛΕΣ τις παραβιάσεις** επειδή η **Α14 §17.2** δεσμεύτηκε ότι *«η
 * φόρμα μικραίνει όσο δίνεις περισσότερα»*: μια φόρμα που διορθώνεται ένα σφάλμα τη
 * φορά δεν επιτρέπει στον άνθρωπο να ξέρει **πόσο κοντά είναι**.
 *
 * 🔑 **ΠΕΝΤΕ από τους κανόνες ΔΕΝ γράφτηκαν εδώ** — δανείζονται από υπάρχοντα
 * SSoT: το `duplicate-offer-kind` από το {@link hasDuplicateLiveOfferKind} (Α20 §5),
 * και το `offer-amount-missing` + το εύρος του ποσοστού + τα **δύο όρια διαμονής**
 * (ADR-835) από το {@link liveOfferAmountGaps} (Α22 ανά **διάθεση**). Ένας δεύτερος
 * κριτής για το ίδιο ερώτημα θα απέκλινε στην πρώτη αλλαγή.
 */
export function ownerPropertyInvariantViolations(
  draft: OwnerPropertyDraft,
): OwnerPropertyInvariant[] {
  const found: OwnerPropertyInvariant[] = [];

  const live = draft.offers.filter(isLiveOffer);
  if (live.length === 0) found.push('no-live-offer');
  if (hasDuplicateLiveOfferKind(draft.offers)) found.push('duplicate-offer-kind');

  const gaps = liveOfferAmountGaps(draft.offers);
  if (gaps.missing.length > 0) found.push('offer-amount-missing');
  if (gaps.percentageOutOfRange.length > 0) {
    found.push('exchange-percentage-out-of-range');
  }
  // ⚠️ **Δανείζονται από τον ίδιο κριτή** ({@link liveOfferAmountGaps}), όπως τα δύο
  // από πάνω: ένας δεύτερος έλεγχος εδώ θα ήταν δεύτερη αλήθεια για το ίδιο κατώφλι.
  if (gaps.minNightsInvalid.length > 0) found.push('short-lease-min-nights-invalid');
  if (gaps.maxGuestsInvalid.length > 0) found.push('short-lease-max-guests-invalid');

  // ── Ποιες διαθέσεις έχουν νόημα για ΑΥΤΟ το είδος (ADR-842 §7.6.10) ──────────
  //
  // 🔑 **ΕΝΑΣ κριτής, ΔΥΟ μηνύματα.** Ο πίνακας `OFFER_KIND_CLASSES` απαντά «τι
  // επιτρέπεται»· οι δύο κωδικοί λένε «γιατί όχι» με λόγια που ο άνθρωπος μπορεί να
  // ακολουθήσει — και οι δύο κινήσεις είναι **αντίθετες** (*«διάλεξε γη»* έναντι
  // *«διάλεξε κατοικία»*). Μέχρι σήμερα ο κανόνας της αντιπαροχής ήταν γραμμένος
  // **στο σώμα** αυτής της συνάρτησης, και ο συμμετρικός του **δεν υπήρχε καθόλου**.
  //
  // 🔴 Κρίνονται **μόνο οι ΑΝΟΙΧΤΕΣ** (`isOpenOffer`), ποτέ οι «ζωντανές»
  // (`isLiveOffer`) — η διαφορά **δεν** είναι λεπτομέρεια, και την έπιασε η άγκυρα
  // Κ17: το `LIVE_OFFER_LIFECYCLES` περιλαμβάνει το **`closed`**, γιατί απαντά
  // *«μετράει για το τι είναι σήμερα το ακίνητο;»* — και ένα **πουλημένο** μετράει.
  // Με εκείνο, μια **ολοκληρωμένη** αντιπαροχή θα κοκκίνιζε για πάντα και το ακίνητο
  // θα γινόταν αδύνατο να ξαναποθηκευτεί, για πράξη που τελείωσε πριν χρόνια.
  //
  // ⚠️ Ο πίνακας απαντά **`true` σε άγνωστο/κενό είδος** επίτηδες: το κενό το πιάνει
  // ο δικός του κωδικός (`type-missing`) παρακάτω, που ξέρει να πει «διάλεξε είδος».
  const openKinds = new Set(
    draft.offers.filter(isOpenOffer).map((offer) => offer.kind),
  );
  if (openKinds.has('exchange') && !isOfferKindEligible('exchange', draft.type)) {
    found.push('exchange-requires-land');
  }
  if (openKinds.has('leaseShort') && !isOfferKindEligible('leaseShort', draft.type)) {
    found.push('short-lease-requires-dwelling');
  }

  if (typeof draft.type !== 'string' || draft.type.trim() === '') {
    found.push('type-missing');
  }
  if (!isPositive(draft.areaSqm)) found.push('area-not-positive');
  if (draft.title.trim() === '') found.push('title-missing');
  if (typeof draft.bedrooms === 'number' && draft.bedrooms < 0) {
    found.push('bedrooms-negative');
  }

  return found;
}
