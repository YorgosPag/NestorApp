/**
 * =============================================================================
 * SSoT: ΔΙΑΘΕΣΕΙΣ ΑΚΙΝΗΤΟΥ (Property Offers) — ADR-777 Α20
 * =============================================================================
 *
 * **«ΕΝΑ ακίνητο, ΠΟΛΛΕΣ διαθέσεις.»** Η αντιπαροχή είναι **διάσταση**, όχι όγδοη
 * τιμή του `COMMERCIAL_STATUSES`.
 *
 * ## Γιατί υπάρχει αυτό το αρχείο
 *
 * Το `PropertyCommercialData` βάζει **δύο είδη συναλλαγής σε ΕΝΑ αντικείμενο**:
 * `askingPrice` (πώληση) και `rentPrice` (ενοικίαση) συγκατοικούν, με **μία**
 * `saleDate` και **μία** `listedDate`. Συνέπειες, μετρημένες:
 *   - «πωλήθηκε» και «νοικιάστηκε» **δεν μπορούν να συνυπάρξουν**·
 *   - η **αντιπαροχή δεν έχει πού να γραφτεί** — υπάρχει μόνο ως *εκτελεσμένη*
 *     συμφωνία (`types/ownership-table.ts`, `Project.bartexPercentage`), ποτέ ως
 *     **προσφορά**.
 *
 * ## Δύο άξονες, ΠΟΤΕ ένας
 *
 * Το **είδος συναλλαγής** (`kind`) είναι **ορθογώνιο** προς τον **κύκλο ζωής**
 * (`lifecycle`). Είναι το πρότυπο **RESO** (`PropertyType` = οικογένειες
 * sale/lease · `StandardStatus` = *«the state of the contract»*) και το πρότυπο
 * **schema.org** (`businessFunction` ⊥ `availability`, με μια αγγελία να είναι
 * *«a listing that describes **one or more** real-estate Offers»*).
 *
 * 🔴 **Γιατί ΔΕΝ έγινε όγδοη τιμή στο `COMMERCIAL_STATUSES`** (ADR-777 §8.5): το
 * `for-sale-and-rent` **είναι ήδη** ο συνδυαστικός σύνθετος όρος, άρα τρίτο είδος
 * συναλλαγής θα έδινε **2³−1 = 7** listed τιμές αντί για 3 (**7 → 11** συνολικά).
 * Είναι ο ορισμός του *combinatorial explosion*: ανεξάρτητες αποφάσεις
 * συμπτύσσονται σε **μία** ιεραρχία.
 *
 * ## Πού ξεπερνάμε την αγορά
 *
 * Το «και προς πώληση **και** προς ενοικίαση» το λύνουν **όλοι** με **δύο
 * ξεχωριστές εγγραφές** — MLS · LoopNet · Crexi · **Sharetribe** (*«Each listing
 * may only be assigned to a **single** Listing type»*). Και η συνέπεια των δύο
 * εγγραφών επιβάλλεται με **προθεσμία σε κανονισμό**: Bright MLS απαιτεί σταυρωτή
 * αναφορά **στο πεδίο «Σχόλια Μεσίτη»**· CVR MLS §5.29 δίνει **5 ημέρες** για την
 * απόσυρση της άλλης. Εδώ η ίδια πράξη είναι **συνάρτηση** ({@link closeOffer}
 * στο `lib/offers/derive-commercial-status.ts`), όχι προθεσμία σε κανονισμό.
 *
 * ## Η αντιπαροχή
 *
 * Ερευνήθηκε (ADR-777 §8.5): η **πράξη** υπάρχει σε τρεις χώρες (🇯🇵 等価交換方式 ·
 * 🇮🇱 עסקת קומבינציה · 🇬🇷 αντιπαροχή) και μοντελοποιείται **παντού** μόνο ως δομή
 * συμβολαίου/φορολογία. Το **RESO** έχει 9 `PropertyType`, καμία ανταλλαγή· το
 * **schema.org `BusinessFunction`** έχει 8 τιμές, καμία `Exchange`/`Barter`.
 * ⚠️ Δηλωμένο όριο: αποδείχθηκε ότι **δεν εμφανίστηκε** σε καμία δημόσια
 * τεκμηρίωση, όχι ότι δεν υπάρχει πουθενά.
 *
 * **Layering**: leaf module — καμία εξάρτηση από components/hooks/services.
 *
 * @module types/property-offers
 * @enterprise ADR-777 Α20 — Η αντιπαροχή είναι ΔΙΑΣΤΑΣΗ, όχι κατάσταση
 */

import type { Timestamp } from 'firebase/firestore';

// =============================================================================
// 1. ΕΙΔΟΣ ΣΥΝΑΛΛΑΓΗΣ — ο πρώτος άξονας
// =============================================================================

/**
 * Τα είδη διάθεσης, σε φυσική σειρά.
 *
 * - `sell`       — πώληση· φέρει **τιμή**
 * - `leaseOut`   — εκμίσθωση· φέρει **μηνιαίο ενοίκιο**
 * - `exchange`   — **αντιπαροχή**· φέρει **ΠΟΣΟΣΤΟ**, ποτέ τιμή
 * - `leaseShort` — **βραχυχρόνια μίσθωση**· φέρει **τιμή ανά διανυκτέρευση** (ADR-835)
 *
 * Τα ονόματα `sell` / `leaseOut` είναι **κυριολεκτικά** οι τιμές του
 * `schema.org/BusinessFunction` — δεν επινοήθηκε λεξιλόγιο εκεί που υπάρχει
 * πρότυπο. Το `leaseShort` **δεν** έχει τιμή στο `BusinessFunction` (μετρήθηκε:
 * οκτώ τιμές, καμία για βραχυχρόνια διαμονή), οπότε το όνομα δηλώνει **τη σχέση
 * του με το `leaseOut`** — ίδια πράξη, άλλη διάρκεια — αντί να επινοήσει τρίτη ρίζα.
 *
 * ⚠️ **ΤΟ `leaseShort` ΔΕΝ ΕΙΝΑΙ ΤΟ `'short-term-rental'` ΤΟΥ
 * `constants/domains/property-status-core.ts`.** Εκείνο είναι τιμή του
 * `EnhancedPropertyStatus` — **άξονας ΚΑΤΑΣΤΑΣΗΣ**, με μοναδικούς καταναλωτές έναν
 * επιλογέα κατάστασης και μια σελίδα επίδειξης. Το να μπει η βραχυχρόνια εκεί θα
 * ήταν κατά λέξη το λάθος που ολόκληρο αυτό το αρχείο υπάρχει για να αποφύγει:
 * **είδος συναλλαγής μέσα σε κύκλο ζωής**. Οι δύο άξονες παραμένουν ορθογώνιοι.
 */
export const OFFER_KINDS = ['sell', 'leaseOut', 'exchange', 'leaseShort'] as const;

export type OfferKind = (typeof OFFER_KINDS)[number];

// =============================================================================
// 2. ΚΥΚΛΟΣ ΖΩΗΣ — ο δεύτερος άξονας
// =============================================================================

/**
 * Ο κύκλος ζωής **μιας** διάθεσης — ανεξάρτητος από το είδος της.
 *
 * - `active`    — στην αγορά, δέχεται ενδιαφέρον
 * - `reserved`  — δεσμευμένη (προκαταβολή), όχι ακόμη κλεισμένη
 * - `closed`    — ολοκληρώθηκε (πουλήθηκε / ενοικιάστηκε / υπογράφηκε αντιπαροχή)
 * - `withdrawn` — αποσύρθηκε **χωρίς** να ολοκληρωθεί
 *
 * ⚠️ **Δεν υπάρχει `draft`, και είναι σκόπιμο.** Δεν έχει αντίστοιχο στο σημερινό
 * `COMMERCIAL_STATUSES`, άρα θα ήταν κατάσταση που **καμία παραγωγή δεν μπορεί να
 * φτάσει** — φρουρός χωρίς απόδειξη ζωής (ADR-749 §5, 606 αδρανείς).
 */
export const OFFER_LIFECYCLES = [
  'active',
  'reserved',
  'closed',
  'withdrawn',
] as const;

export type OfferLifecycle = (typeof OFFER_LIFECYCLES)[number];

/**
 * Οι καταστάσεις που σημαίνουν «αυτή η διάθεση **μετράει** για το τι είναι σήμερα
 * το ακίνητο». Το `withdrawn` **δεν** ανήκει: μια αποσυρμένη διάθεση είναι
 * **ιστορικό**, και το ιστορικό δεν βάφει την οθόνη.
 */
export const LIVE_OFFER_LIFECYCLES = [
  'active',
  'reserved',
  'closed',
] as const satisfies readonly OfferLifecycle[];

/** `true` αν η διάθεση μετράει για την τρέχουσα κατάσταση του ακινήτου. */
export function isLiveOffer(offer: PropertyOffer): boolean {
  return (LIVE_OFFER_LIFECYCLES as readonly string[]).includes(offer.lifecycle);
}

/**
 * Οι καταστάσεις που σημαίνουν «αυτή η διάθεση **ζητείται ακόμη**».
 *
 * 🔴 **ΔΕΝ ΕΙΝΑΙ ΤΟ ΙΔΙΟ ΜΕ ΤΟ {@link LIVE_OFFER_LIFECYCLES}, ΚΑΙ Η ΔΙΑΦΟΡΑ ΕΙΝΑΙ ΤΟ
 * `closed`.** Εκείνο απαντά *«μετράει για το **τι είναι** σήμερα το ακίνητο;»* — και
 * ένα **πουλημένο** ακίνητο μετράει (η οθόνη λέει «Πωλήθηκε»). Αυτό απαντά *«το
 * **ζητάει** ακόμη ο κάτοχος;»* — και ένα πουλημένο **όχι**.
 *
 * ⚠️ **Η έννοια ΥΠΗΡΧΕ ΗΔΗ, ΧΩΡΙΣ ΟΝΟΜΑ** (ADR-777 §8.32): το `closeOffer` έγραφε
 * `offer.lifecycle === 'active' || offer.lifecycle === 'reserved'` **στο σώμα του**.
 * Ο δεύτερος καταναλωτής (το invariant «αντιπαροχή ⇒ γη») έφτασε να ρωτήσει την
 * **ίδια** ερώτηση, και η εύκολη λύση ήταν να την ξαναγράψει — δηλαδή **δύο αλήθειες
 * για το ίδιο πράγμα, και οι δύο ανώνυμες** (ADR-749). Μια τρίτη κατάσταση κύκλου
 * ζωής αύριο θα διόρθωνε **μία** από τις δύο.
 */
export const OPEN_OFFER_LIFECYCLES = [
  'active',
  'reserved',
] as const satisfies readonly OfferLifecycle[];

/** `true` αν η διάθεση **ζητείται ακόμη** — όχι κλεισμένη, όχι αποσυρμένη. */
export function isOpenOffer(offer: PropertyOffer): boolean {
  return (OPEN_OFFER_LIFECYCLES as readonly string[]).includes(offer.lifecycle);
}

// =============================================================================
// 3. Η ΔΙΑΘΕΣΗ — discriminated union στο `kind`
// =============================================================================

/**
 * Ό,τι είναι κοινό σε κάθε διάθεση, ανεξαρτήτως είδους.
 *
 * 🔴 Το `id` **δεν είναι διακοσμητικό**: είναι το υποκείμενο του «το κλείσιμο
 * μιας διάθεσης αποσύρει **τις άλλες**» (Α20 σημείο 4). Χωρίς σταθερή ταυτότητα,
 * το «οι άλλες» δεν ονομάζεται — και ο δείκτης θέσης σε πίνακα **δεν είναι**
 * ταυτότητα (αλλάζει σε κάθε αναδιάταξη).
 */
interface PropertyOfferBase {
  /** Enterprise id (`offr_*`) — N.6. Δίνεται **μία φορά**, στη γέννηση. */
  id: string;

  /** Πού βρίσκεται αυτή η διάθεση στον κύκλο της. */
  lifecycle: OfferLifecycle;

  /** Πότε μπήκε στην αγορά (για «ημέρες στην αγορά»). */
  listedDate?: Timestamp | null;

  /** Πότε έκλεισε ή αποσύρθηκε. `null` όσο είναι ζωντανή. */
  closedDate?: Timestamp | null;
}

/**
 * **Πώληση.** Η `askingPrice` είναι τι ζητά· η `finalPrice` τι εισπράχθηκε.
 *
 * ⚠️ Οι δύο **δεν** είναι εναλλάξιμες — ADR-777 Α21 μέτρησε **πέντε επιφάνειες με
 * τέσσερα κριτήρια** πάνω σε αυτό το ζεύγος. Η εμφάνιση διαλέγει μέσω του SSoT
 * `lib/properties/price-resolver.ts`· **ποτέ** με χειρόγραφο `??` στο σημείο χρήσης.
 */
export interface SellOffer extends PropertyOfferBase {
  kind: 'sell';
  /** Ζητούμενη τιμή (EUR). */
  askingPrice: number | null;
  /** Τελική τιμή πώλησης (EUR) — γράφεται στο συμβόλαιο. */
  finalPrice?: number | null;
}

/** **Εκμίσθωση.** Μηνιαίο ενοίκιο — ποτέ τιμή πώλησης. */
export interface LeaseOutOffer extends PropertyOfferBase {
  kind: 'leaseOut';
  /** Μηνιαίο ενοίκιο (EUR). */
  rentPrice: number | null;
}

/**
 * **Αντιπαροχή.** Φέρει **ΠΟΣΟΣΤΟ**, όχι τιμή — και αυτό είναι ο λόγος που η
 * ένωση είναι διακριτή αντί για ένα αντικείμενο με προαιρετικά πεδία: ένα
 * `percentage` πάνω σε πώληση είναι **αδύνατο να εκφραστεί**, όχι «απαγορευμένο
 * από σχόλιο».
 *
 * Το ποσοστό είναι **του οικοπεδούχου**, σε συμφωνία με το ήδη υπάρχον
 * `Project.bartexPercentage` (ADR-244) — **μία** σημασία, όχι δεύτερη.
 */
export interface ExchangeOffer extends PropertyOfferBase {
  kind: 'exchange';
  /** Ποσοστό οικοπεδούχου (0–100). */
  percentage: number | null;
}

/**
 * **Βραχυχρόνια μίσθωση** (ADR-835 §4.1). Φέρει **τιμή ανά διανυκτέρευση** — ποτέ
 * μηνιαίο ενοίκιο, ποτέ τιμή πώλησης.
 *
 * 🔴 **Γιατί ξεχωριστός κλάδος και όχι «`leaseOut` με άλλη περίοδο»**: ακριβώς ο
 * λόγος που το {@link ExchangeOffer} είναι ξεχωριστός. Ένα `nightlyRate` **δεν
 * μπορεί να διαβαστεί** ως μηνιαίο ενοίκιο, γιατί ζει σε άλλον κλάδο της ένωσης — η
 * σύγχυση γίνεται **αδύνατη να εκφραστεί**, όχι «απαγορευμένη από σχόλιο». Ένα πεδίο
 * `period: 'monthly' | 'nightly'` πάνω στο `LeaseOutOffer` θα άφηνε το «800» να
 * σημαίνει και τα δύο, και **κάθε** αναγνώστης θα έπρεπε να θυμηθεί να ρωτήσει.
 *
 * ⚠️ **Τα τρία πεδία ΔΕΝ είναι ισότιμα.** Το `nightlyRate` είναι **το ποσό** της
 * διάθεσης (χωρίς αυτό δεν δημοσιεύεται — Α22)· τα άλλα δύο είναι **όροι** που ο
 * κάτοχος μπορεί νόμιμα να μη δηλώσει. Γι' αυτό `null` σημαίνει *«δεν δηλώθηκε»* και
 * **ποτέ `0`**: μηδέν διανυκτερεύσεις δεν είναι διαμονή, και μηδέν επισκέπτες δεν
 * είναι κατάλυμα.
 *
 * ⛔ **Καμία ημερομηνία εδώ.** Το ημερολόγιο διαθεσιμότητας είναι **κατάληψη πόρου**
 * (ADR-835 §4.3) και ζει στον κριτή του ADR-832, όχι μέσα στη διάθεση. Μια λίστα
 * κρατήσεων σε αυτό το αντικείμενο θα ήταν δεύτερο βιβλίο (ADR-749).
 */
export interface ShortLeaseOffer extends PropertyOfferBase {
  kind: 'leaseShort';
  /** Τιμή **ανά διανυκτέρευση** (EUR). */
  nightlyRate: number | null;
  /** Ελάχιστες διανυκτερεύσεις. `null` = δεν δηλώθηκε· **ποτέ `0`**. */
  minNights: number | null;
  /** Μέγιστος αριθμός επισκεπτών. `null` = δεν δηλώθηκε· **ποτέ `0`**. */
  maxGuests: number | null;
}

/** Μια διάθεση — ένα από τα τέσσερα είδη. */
export type PropertyOffer =
  | SellOffer
  | LeaseOutOffer
  | ExchangeOffer
  | ShortLeaseOffer;

// =============================================================================
// 4. TYPE GUARDS
// =============================================================================

/** `true` αν το `value` είναι γνωστό είδος διάθεσης. */
export function isOfferKind(value: unknown): value is OfferKind {
  return (
    typeof value === 'string' && (OFFER_KINDS as readonly string[]).includes(value)
  );
}

/** `true` αν το `value` είναι γνωστός κύκλος ζωής διάθεσης. */
export function isOfferLifecycle(value: unknown): value is OfferLifecycle {
  return (
    typeof value === 'string' &&
    (OFFER_LIFECYCLES as readonly string[]).includes(value)
  );
}

