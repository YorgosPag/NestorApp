/**
 * **Ο χώρος ως αναγνωρίσιμη μονάδα.** Το ακίνητο **δεν** είναι πια το άτομο του πόρου.
 *
 * > **«Αν μισθώνεται διακριτά ένα δωμάτιο, χρειάζεται ξεχωριστός ΑΜΑ· και αν το ίδιο
 * > ακίνητο διατίθεται και ολόκληρο και τμηματικά, χρειάζεται ξεχωριστός ΑΜΑ για το
 * > σύνολο και για κάθε διακριτό χώρο.»** *(ΑΑΔΕ)*
 *
 * 🔑 **Αυτοτελής επίτηδες**: κουβαλά το `propertyId` του, ώστε να μπορεί να σταλεί
 * στον κριτή **χωρίς συμφραζόμενα**. Χωρίς αυτό, το `spaceId: null` («ολόκληρο») θα
 * ήταν μπαλαντέρ **χωρίς σύνορο** και δύο διαφορετικά ακίνητα θα συγκρούονταν.
 *
 * 🔴 **ΕΙΝΑΙ ΠΛΕΟΝ ΨΕΥΔΩΝΥΜΟ, ΟΧΙ ΔΕΥΤΕΡΗ ΔΗΛΩΣΗ** (ADR-838 §4.1). Το ίδιο ζεύγος
 * ζούσε **δύο φορές** — εδώ και μέσα στο `OccupancyResource` — και ο **κανόνας του
 * μπαλαντέρ** μόνο στο δεύτερο. Η **νομιμότητα** ρωτά τον ίδιο κανόνα χωρίς να έχει
 * `OfferKind`, οπότε το άτομο **εξήχθη** στο `lib/spaces/space-ref.ts` και οι τρεις
 * καταναλωτές το **ζητούν**. Το όνομα μένει: εδώ διαβάζεται *«ο χώρος μιας διαμονής»*.
 */
export type StaySpaceRef = SpaceRef;

/**
 * **Οι χώροι που καλύπτει μία καταχώριση** — ΠΑΝΤΑ σύνολο, ποτέ ένα.
 *
 * Ένα τριάρι που νοικιάζεται και ολόκληρο και κατά δωμάτιο έχει **τρεις**
 * καταχωρίσεις: `ΑΜΑ-1` (ολόκληρο) · `ΑΜΑ-2` (δωμ. Α) · `ΑΜΑ-3` (δωμ. Β) — και
 * **τρεις** Δηλώσεις Βραχυχρόνιας Διαμονής, με δικό της υπόχρεο η καθεμιά (§4.12).
 *
 * ✅ **Η ΥΠΟΣΧΕΣΗ ΤΗΡΗΘΗΚΕ (Φ4, ADR-838).** Το πεδίο έγραφε *«το `amaNumber` εδώ είναι
 * ΚΑΤΑΓΡΑΦΗ, όχι απόδειξη νομιμότητας… ένα σκέτο `string` κάπου θα ήταν η έβδομη
 * εμφάνιση του «το 0 σήμαινε ότι κανείς δεν κοίταξε» (§12 Κ5)»* — και **ήταν** σκέτο
 * `string | null`. Πλέον είναι **αξίωση με βαθμίδα και προέλευση**: το ίδιο το σχήμα
 * κάνει **αδύνατο** να γραφτεί αριθμός χωρίς να απαντηθεί *«ποιος το λέει;»*.
 */
export interface StayInventoryUnit {
  /**
   * **Ο ΑΜΑ ως αξίωση.** `null` = **δεν δηλώθηκε** — δεδομένο, όχι σιωπή.
   *
   * ⚠️ **Το είδος δεν είναι ελεύθερο**: οφείλει να είναι `'short-stay-registry'`, και
   * το υποκείμενό του οφείλει να **καλύπτει** το {@link covers}. Ο φρουρός ζει στο
   * `inventoryUnitLegalityIsWellFormed` — όχι σε σχόλιο, γιατί ένας ΑΜΑ **άλλου**
   * χώρου θα «νομιμοποιούσε» αυτόν εδώ, που είναι ακριβώς το λάθος που η ΑΑΔΕ κλείνει
   * απαιτώντας ξεχωριστό αριθμό ανά διακριτό χώρο.
   */
  readonly ama: LegalityClaim | null;
  readonly covers: readonly StaySpaceRef[];
}

/**
 * **Είναι ο ΑΜΑ αυτής της καταχώρισης καλά σχηματισμένος;**
 *
 * Τρία ερωτήματα, και το τρίτο είναι εκείνο που πιάνει το λάθος του §4.12:
 *
 * 1. σωστό **είδος** αξίωσης (`'short-stay-registry'`)
 * 2. **προέλευση** όπου την απαιτεί η βαθμίδα (`claimAuthorityIsWellFormed`)
 * 3. 🔴 **καλύπτει τους χώρους της καταχώρισης** — ασύμμετρα: ο ΑΜΑ του **δωματίου Α**
 *    δεν καλύπτει την καταχώριση «ολόκληρο», όσο κι αν οι δύο **τέμνονται**
 *
 * ⚠️ `ama: null` ⇒ **`true`**: «δεν δηλώθηκε» είναι **έγκυρη κατάσταση**, όχι
 * δυσμορφία. Η συνέπειά της (τι επιτρέπεται να δημοσιευτεί) κρίνεται αλλού, από τον
 * κανόνα του **είδους** — ποτέ από αυτόν τον φρουρό, που ρωτά μόνο *«είναι συνεπές;»*.
 */
export function inventoryUnitLegalityIsWellFormed(unit: StayInventoryUnit): boolean {
  if (unit.ama === null) return true;
  if (unit.ama.kind !== 'short-stay-registry') return false;
  if (!claimAuthorityIsWellFormed(unit.ama)) return false;
  return claimCovers(unit.ama, unit.covers);
}

