/**
 * **Ποιες κρατήσεις πιάνουν ημέρες** — το κάτοπτρο του `bindingMandates`.
 *
 * 🔴 **ΤΟ ΦΙΛΤΡΟ ΕΙΝΑΙ ΚΑΤΑΣΤΑΣΗΣ, ΠΟΤΕ ΧΡΟΝΟΥ.** Το ADR-832 §5.5 το πλήρωσε
 * μετρημένα: χρονικό φίλτρο **πριν** τον κριτή έκρυβε τις εγγραφές με χαλασμένο
 * διάστημα, δηλαδή το *«άγνωστο»* γινόταν *«κενό»* (N.12) — και ήταν **διπλός**
 * έλεγχος, αφού ο κριτής τον κάνει ήδη. Εδώ φιλτράρεται **μόνο** ό,τι κατέχει το
 * σχήμα: ποια κατάσταση καταλαμβάνει.
 */
export function occupyingStays(
  bookings: readonly StayBooking[],
): readonly StayBooking[] {
  return bookings.filter((booking) => occupiesStayCalendar(booking.lifecycle));
}

/**
 * **Χώροι διαμονής ως πόροι** του κριτή — η **μία** μετάφραση, για κράτηση **και** block
 * (`types/stay-calendar.ts`). Η πράξη είναι πάντα `'leaseShort'`.
 */
export function stayResourcesOf(
  covers: readonly StaySpaceRef[],
): readonly OccupancyResource[] {
  return covers.map((space) => ({
    propertyId: space.propertyId,
    spaceId: space.spaceId,
    kind: 'leaseShort' as const,
  }));
}

/**
 * **Η κράτηση ως κατάληψη πόρου** — το κάτοπτρο του `occupancyOf(mandate)`.
 *
 * 🔴 **`mode: 'exclusive'`, ΠΑΝΤΑ.** Δεν υπάρχει «κοινόχρηστη» κράτηση: δύο άνθρωποι
 * δεν κοιμούνται στο ίδιο δωμάτιο επειδή το σύστημα το βρήκε συμβατό. Ο πίνακας
 * shared/exclusive **δεν χρειάστηκε αλλαγή** για να το δεχτεί — οι κρατήσεις ζουν
 * ολόκληρες στο κάτω δεξιά κελί του.
 *
 * 🔑 **`occupancyId: booking.id`, και είναι απαραίτητο.** Με πολιτική
 * `sameHolder: 'conflicts'`, μια κράτηση που βρεθεί και στο σύνολο των υπαρχουσών θα
 * συγκρουόταν **με τον εαυτό της**. Η εντολή δεν έχει αυτό το πρόβλημα γιατί δεν έχει
 * ταυτότητα — και δεν τη χρειάζεται, αφού η πολιτική της είναι `'replaces'`.
 */
export function stayOccupancyOf(booking: StayBooking): Occupancy<StayBooking> {
  return {
    occupancyId: booking.id,
    holderId: stayHolderId(booking),
    mode: 'exclusive',
    resources: stayResourcesOf(booking.covers),
    startsAt: booking.checkIn,
    expiresAt: booking.checkOut,
    source: booking,
  };
}
