/**
 * **Από πού ήρθε η κράτηση** — ADR-835 §20 (Στάδιο Α).
 *
 * - `direct`: ο οικοδεσπότης την καταχώρισε ο ίδιος (τηλέφωνο, φίλος, επαναλαμβανόμενος πελάτης)
 * - `platform`: ζητήθηκε από επισκέπτη μέσα από τη Nestor (Στάδιο Δ)
 *
 * ⚠️ Οι κρατήσεις **άλλων καναλιών** (Airbnb/Booking μέσω iCal) **ΔΕΝ** είναι κρατήσεις
 * εδώ: το iCal δεν μεταφέρει επισκέπτη, μόνο «πιασμένο». Γίνονται `StayBlock` με
 * `source: 'external'` (Στάδιο Γ) — κράτηση χωρίς κάτοχο θα ήταν ψέμα του σχήματος.
 */
export const STAY_BOOKING_CHANNELS = ['direct', 'platform'] as const;

export type StayBookingChannel = (typeof STAY_BOOKING_CHANNELS)[number];

/** `true` αν το `value` είναι γνωστό κανάλι κράτησης. */
export function isStayBookingChannel(value: unknown): value is StayBookingChannel {
  return (
    typeof value === 'string' &&
    (STAY_BOOKING_CHANNELS as readonly string[]).includes(value)
  );
}

/**
 * **Ποιος κρατά** — διακριτή ένωση, ποτέ `holderUserId: string | null`.
 *
 * 🔴 Ο επισκέπτης μιας χειροκίνητης κράτησης **δεν έχει λογαριασμό**. Ένα `null` uid θα
 * έκανε δύο διαφορετικούς ανθρώπους «τον ίδιο κάτοχο» για τον κριτή (N.12)· ένα κενό
 * string θα ήταν ψεύτικη ταυτότητα. Το `label` είναι **ιδιωτική σημείωση του
 * οικοδεσπότη** («κ. Παπαδόπουλος, τηλ.») — δεν φεύγει ποτέ προς τρίτους.
 *
 * 🔑 **Ο κάτοχος-λογαριασμός κουβαλά `displayName`** (Στάδιο Δ): **στιγμιότυπο** του ονόματος τη
 * στιγμή του αιτήματος — αυτό που βλέπει ο οικοδεσπότης δίπλα στο αίτημα (όπως το μικρό όνομα στο
 * Airbnb). Στιγμιότυπο και όχι ζωντανή ανάγνωση: το αίτημα λέει **ποιος ζήτησε**, και αυτό δεν
 * αλλάζει αν ο λογαριασμός αλλάξει όνομα αύριο. ⛔ **Ποτέ κριτής ταυτότητας** — αυτό είναι το `userId`.
 * 🔴 `null` = ο λογαριασμός **δεν έχει** όνομα — και **ποτέ** εφεδρεία το email: θα έφτανε στον
 * οικοδεσπότη διεύθυνση που ο επισκέπτης δεν του έδωσε (η οθόνη γράφει «Επισκέπτης»).
 */
export type StayBookingHolder =
  | { readonly kind: 'user'; readonly userId: string; readonly displayName: string | null }
  | { readonly kind: 'offline'; readonly label: string };

/**
 * **Η ταυτότητα κατόχου για τον κριτή.** Ο offline κάτοχος παίρνει ταυτότητα **ανά
 * κράτηση**: δύο χειροκίνητες κρατήσεις δεν είναι «ο ίδιος άνθρωπος» επειδή κανείς δεν
 * έχει λογαριασμό. Με `sameHolder: 'conflicts'` η τιμή δεν αλλάζει ετυμηγορία — αλλάζει
 * το αν η απάντηση **λέει αλήθεια** για το ποιος είναι ποιος.
 */
export function stayHolderId(booking: Pick<StayBooking, 'id' | 'holder'>): string {
  return booking.holder.kind === 'user'
    ? booking.holder.userId
    : `offline:${booking.id}`;
}

/**
 * **Η προθεσμία ενός αιτήματος** (hold TTL, §23.3) — υπολογίζεται **μία φορά**, στη γέννηση του
 * αιτήματος, και **αποθηκεύεται**.
 *
 * 🔑 Αποθηκευμένη, ποτέ ξαναϋπολογισμένη: αν ο οικοδεσπότης αλλάξει αργότερα τις ώρες απόκρισης, οι
 * προθεσμίες που **ήδη υποσχεθήκαμε** σε επισκέπτες δεν μετακινούνται. Η βαθμίδα και το ταβάνι που
 * κέρδισε γράφονται μαζί, ώστε το ίχνος να λέει **γιατί** αυτή η ώρα.
 */
export interface StayHold {
  /** ISO — η στιγμή που το αίτημα **παύει** να καταλαμβάνει (ημι-ανοιχτό, §23.1). */
  readonly expiresAt: string;
  readonly tier: StayHoldTier;
  readonly bound: StayHoldBound;
  /**
   * **Ποιος οφείλει την απάντηση** (§4.11 #4) — uid. Σήμερα ο κάτοχος της αγγελίας· το Στάδιο Ε
   * (`StayManagementGrant`) αλλάζει **μόνο** το ποιος γράφεται εδώ.
   */
  readonly respondentUserId: string;
}

/** Οι λόγοι λήξης — `expired` **με λόγο**, όπως το §4.11 #3. */
export const STAY_EXPIRY_REASONS = ['no-answer'] as const;
export type StayExpiryReason = (typeof STAY_EXPIRY_REASONS)[number];

/**
 * **Πώς έκλεισε ένα αίτημα που δεν έγινε κράτηση** — γεγονός, με στιγμή.
 *
 * 🔑 Διακριτή ένωση κατά κατάσταση: ο λόγος της λήξης **δεν** είναι ο λόγος της απόσυρσης. Ένα
 * σκέτο `reason: string` θα επέτρεπε «απόσυρση επειδή κανείς δεν απάντησε» — ψέμα του σχήματος.
 */
export type StayResolution =
  | { readonly lifecycle: 'declined'; readonly at: string }
  | { readonly lifecycle: 'expired'; readonly at: string; readonly reason: StayExpiryReason }
  | { readonly lifecycle: 'withdrawn'; readonly at: string };

/**
 * **Μια κράτηση βραχυχρόνιας διαμονής.** Enterprise id `stay_*` (N.6).
 *
 * ⚠️ **ΤΟ ΔΙΑΣΤΗΜΑ ΕΙΝΑΙ ΗΜΙ-ΑΝΟΙΧΤΟ `[checkIn, checkOut)` — ΜΗΝ ΤΟ ΑΓΓΙΞΕΙΣ.** Η
 * μέρα αναχώρησης **είναι** μέρα άφιξης του επόμενου. Ένα κλειστό διάστημα θα έκανε
 * τη **διαδοχή** σύγκρουση, δηλαδή θα υποχρέωνε τον οικοδεσπότη να αφήνει κενή νύχτα
 * ανάμεσα σε δύο κρατήσεις **χωρίς να μάθει ποτέ γιατί**.
 */
export interface StayBooking {
  readonly id: string;
  /**
   * **Πεδίο-ευρετήριο**, με το ιδίωμα του `mandatesExpireAt` (ADR-832 §5.4): υπάρχει
   * για να βρίσκονται οι κρατήσεις ενός ακινήτου με ένα `where`.
   *
   * ⛔ **ΠΟΤΕ ΚΡΙΤΗΣ.** Το ερώτημα *«τι ακριβώς πιάνει αυτή η κράτηση;»* το απαντά
   * **μόνο** το {@link StayBooking.covers}. Κριτής χτισμένος εδώ θα έλεγε ότι η
   * κράτηση ενός δωματίου πιάνει ολόκληρο το ακίνητο — ή, χειρότερα, ότι η κράτηση
   * ολόκληρου **δεν** πιάνει τα δωμάτια.
   */
  readonly propertyId: string;
  /** Η πράξη. **Πάντα** `'leaseShort'` — γραμμένο, όχι υπονοούμενο. */
  readonly offerKind: Extract<OfferKind, 'leaseShort'>;
  /**
   * **Ποιους χώρους κρατά** (§4.12). Ένα στοιχείο με `spaceId: null` = ολόκληρο.
   *
   * ⚠️ **Κενό σύνολο δεν καταλαμβάνει τίποτα** — έγκυρη κατάσταση για τον κριτή,
   * **αδιανόητη** για κράτηση. Ο φρουρός ανήκει στη ροή αιτήματος (Φ5), όχι εδώ: ένα
   * `throw` σε αρχείο τύπων θα ήταν κανόνας κρυμμένος σε λάθος στρώμα.
   */
  readonly covers: readonly StaySpaceRef[];
  /**
   * ISO `YYYY-MM-DD` — η **άφιξη**. Ανήκει στο διάστημα.
   *
   * 🔴 **`checkIn === checkOut` (ΜΗΔΕΝ νύχτες) κρίνεται ΑΣΥΝΕΠΩΣ — ΜΕΤΡΗΜΕΝΟ, όχι
   * υπόθεση.** Ο τελεστής `intervalsOverlap` απαντά για το κενό διάστημα `[12,12)`:
   *
   * | Έναντι | Απάντηση |
   * |---|---|
   * | `[10,17)` — **μέσα** του | **`true`** *(συγκρούεται)* |
   * | `[12,17)` — στην **αρχή** του | `false` |
   * | `[10,12)` — στο **τέλος** του | `false` |
   *
   * Δηλαδή η ίδια μηδενική διαμονή **συγκρούεται ή όχι ανάλογα με το πού πέφτει**. Ο
   * τύπος `aFrom < bTo ∧ bFrom < aTo` είναι **ακριβής για μη κενά** διαστήματα και
   * απροσδιόριστος για το κενό — που, κατά τη **γραμμένη διδαχή του ίδιου του
   * τελεστή**, είναι *«δεδομένο που δεν περιγράφει διάστημα και δεν πρέπει να κριθεί
   * σιωπηλά»* (⇒ θα άρμοζε `null`, όπως στο **ανάποδο** διάστημα).
   *
   * ⛔ **ΔΕΝ διορθώθηκε στη Φ2, επίτηδες**: ο τελεστής ανήκει στο ADR-832 §5.2 και το
   * handoff της Φ2 λέει ρητά *«ΜΗΝ το αγγίξεις»*. Καταγράφεται ως **εύρημα**
   * (ADR-835 §16 · ADR-832 changelog), και ο φρουρός `checkOut > checkIn` ανήκει
   * ούτως ή άλλως στη ροή αιτήματος (**Φ5**): μηδέν νύχτες δεν είναι διαμονή.
   */
  readonly checkIn: string;
  /** ISO `YYYY-MM-DD` — η **αναχώρηση**. **ΔΕΝ** ανήκει στο διάστημα. */
  readonly checkOut: string;
  /** Ποιος κρατά — λογαριασμός ή άνθρωπος εκτός πλατφόρμας. Δες {@link StayBookingHolder}. */
  readonly holder: StayBookingHolder;
  /** Από πού ήρθε η κράτηση. Δες {@link STAY_BOOKING_CHANNELS}. */
  readonly channel: StayBookingChannel;
  /**
   * **Ο συντάκτης της αγγελίας** — αντίγραφο του `OwnerProperty.authorUserId`.
   *
   * 🔑 Υπάρχει **μόνο** για τον κανόνα ανάγνωσης Firestore (ίδιος άξονας με το
   * `owner_properties`, `tenant-config.ts`). Ποιος **διαχειρίζεται** το κρίνει πάντα
   * το `mayAdminister(custodyOf(property))` — ποτέ αυτό το πεδίο (CHECK 3.56).
   */
  readonly authorUserId: string;
  readonly guests: number;
  readonly lifecycle: StayBookingLifecycle;
  /**
   * **Πότε ειπώθηκε στον επισκέπτη ότι το ακίνητο πωλείται.** `null` = δεν ίσχυε.
   *
   * 🔑 **ΓΕΓΟΝΟΣ, όχι κείμενο οθόνης** (§4.7 — απόφαση Giorgio 2026-08-31). Η
   * συνύπαρξη πώλησης και κρατήσεων είναι **ποτέ φράχτης, πάντα όνομα**: το σύστημα
   * δεν απαγορεύει, **αποκαλύπτει** — και η αποκάλυψη πρέπει να είναι αποδείξιμη.
   */
  readonly riskDisclosedAt: string | null;
  /**
   * **Η προθεσμία του αιτήματος.** Υπάρχει **αν και μόνο αν** η κράτηση γεννήθηκε ως αίτημα
   * επισκέπτη (`channel: 'platform'`). Μένει και μετά την απάντηση: είναι το ίχνος *«ως πότε
   * κρατήθηκαν οι μέρες»*. ⛔ `requested` χωρίς hold **δεν διαβάζεται** (fail-closed, ο αναγνώστης).
   */
  readonly hold: StayHold | null;
  /** Πώς έκλεισε, αν έκλεισε χωρίς να γίνει διαμονή. `null` για κάθε άλλη κατάσταση. */
  readonly resolution: StayResolution | null;
  /**
   * **Ο επισκέπτης ως επίπεδο πεδίο-ευρετήριο** — το `holder.userId` όταν `holder.kind === 'user'`,
   * αλλιώς `null`. Κάτοπτρο του {@link StayBooking.authorUserId}: υπάρχει **μόνο** για τον κανόνα
   * ανάγνωσης Firestore και για το ερώτημα «τα αιτήματά μου». Ποτέ κριτής ταυτότητας.
   */
  readonly guestUserId: string | null;
  readonly createdAt: string;
  readonly updatedAt: string;
}

/** Το `guestUserId` που **οφείλει** να έχει μια κράτηση — από τον κάτοχο, ποτέ δεύτερη πηγή. */
export function stayGuestUserIdOf(holder: StayBookingHolder): string | null {
  return holder.kind === 'user' ? holder.userId : null;
}

