/**
 * **Μια κράτηση βραχυχρόνιας διαμονής.** Enterprise id `stay_*` (N.6).
 *
 * ⚠️ **ΤΟ ΔΙΑΣΤΗΜΑ ΕΙΝΑΙ ΗΜΙ-ΑΝΟΙΧΤΟ `[checkIn, checkOut)` — ΜΗΝ ΤΟ ΑΓΓΙΞΕΙΣ.** Η
 * μέρα αναχώρησης **είναι** μέρα άφιξης του επόμενου. Ένα κλειστό διάστημα θα έκανε
 * τη **διαδοχή** σύγκρουση, δηλαδή θα υποχρέωνε τον οικοδεσπότη να αφήνει κενή νύχτα
 * ανάμεσα σε δύο κρατήσεις **χωρίς να μάθει ποτέ γιατί**.
 */
export interface StayBooking {
  readonly id: string;
  /**
   * **Πεδίο-ευρετήριο**, με το ιδίωμα του `mandatesExpireAt` (ADR-832 §5.4): υπάρχει
   * για να βρίσκονται οι κρατήσεις ενός ακινήτου με ένα `where`.
   *
   * ⛔ **ΠΟΤΕ ΚΡΙΤΗΣ.** Το ερώτημα *«τι ακριβώς πιάνει αυτή η κράτηση;»* το απαντά
   * **μόνο** το {@link StayBooking.covers}. Κριτής χτισμένος εδώ θα έλεγε ότι η
   * κράτηση ενός δωματίου πιάνει ολόκληρο το ακίνητο — ή, χειρότερα, ότι η κράτηση
   * ολόκληρου **δεν** πιάνει τα δωμάτια.
   */
  readonly propertyId: string;
  /** Η πράξη. **Πάντα** `'leaseShort'` — γραμμένο, όχι υπονοούμενο. */
  readonly offerKind: Extract<OfferKind, 'leaseShort'>;
  /**
   * **Ποιους χώρους κρατά** (§4.12). Ένα στοιχείο με `spaceId: null` = ολόκληρο.
   *
   * ⚠️ **Κενό σύνολο δεν καταλαμβάνει τίποτα** — έγκυρη κατάσταση για τον κριτή,
   * **αδιανόητη** για κράτηση. Ο φρουρός ανήκει στη ροή αιτήματος (Φ5), όχι εδώ: ένα
   * `throw` σε αρχείο τύπων θα ήταν κανόνας κρυμμένος σε λάθος στρώμα.
   */
  readonly covers: readonly StaySpaceRef[];
  /**
   * ISO `YYYY-MM-DD` — η **άφιξη**. Ανήκει στο διάστημα.
   *
   * 🔴 **`checkIn === checkOut` (ΜΗΔΕΝ νύχτες) κρίνεται ΑΣΥΝΕΠΩΣ — ΜΕΤΡΗΜΕΝΟ, όχι
   * υπόθεση.** Ο τελεστής `intervalsOverlap` απαντά για το κενό διάστημα `[12,12)`:
   *
   * | Έναντι | Απάντηση |
   * |---|---|
   * | `[10,17)` — **μέσα** του | **`true`** *(συγκρούεται)* |
   * | `[12,17)` — στην **αρχή** του | `false` |
   * | `[10,12)` — στο **τέλος** του | `false` |
   *
   * Δηλαδή η ίδια μηδενική διαμονή **συγκρούεται ή όχι ανάλογα με το πού πέφτει**. Ο
   * τύπος `aFrom < bTo ∧ bFrom < aTo` είναι **ακριβής για μη κενά** διαστήματα και
   * απροσδιόριστος για το κενό — που, κατά τη **γραμμένη διδαχή του ίδιου του
   * τελεστή**, είναι *«δεδομένο που δεν περιγράφει διάστημα και δεν πρέπει να κριθεί
   * σιωπηλά»* (⇒ θα άρμοζε `null`, όπως στο **ανάποδο** διάστημα).
   *
   * ⛔ **ΔΕΝ διορθώθηκε στη Φ2, επίτηδες**: ο τελεστής ανήκει στο ADR-832 §5.2 και το
   * handoff της Φ2 λέει ρητά *«ΜΗΝ το αγγίξεις»*. Καταγράφεται ως **εύρημα**
   * (ADR-835 §16 · ADR-832 changelog), και ο φρουρός `checkOut > checkIn` ανήκει
   * ούτως ή άλλως στη ροή αιτήματος (**Φ5**): μηδέν νύχτες δεν είναι διαμονή.
   */
  readonly checkIn: string;
  /** ISO `YYYY-MM-DD` — η **αναχώρηση**. **ΔΕΝ** ανήκει στο διάστημα. */
  readonly checkOut: string;
  /** Ποιος κρατά. **uid**, ποτέ όνομα — η οθόνη το λύνει (ιδίωμα ADR-832). */
  readonly holderUserId: string;
  readonly guests: number;
  readonly lifecycle: StayBookingLifecycle;
  /**
   * **Πότε ειπώθηκε στον επισκέπτη ότι το ακίνητο πωλείται.** `null` = δεν ίσχυε.
   *
   * 🔑 **ΓΕΓΟΝΟΣ, όχι κείμενο οθόνης** (§4.7 — απόφαση Giorgio 2026-08-31). Η
   * συνύπαρξη πώλησης και κρατήσεων είναι **ποτέ φράχτης, πάντα όνομα**: το σύστημα
   * δεν απαγορεύει, **αποκαλύπτει** — και η αποκάλυψη πρέπει να είναι αποδείξιμη.
   */
  readonly riskDisclosedAt: string | null;
  readonly createdAt: string;
  readonly updatedAt: string;
}

