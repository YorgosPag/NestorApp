/**
 * @fileoverview **Η ΕΝΤΟΛΗ** — ποιανού είναι αυτό που έγραψα, και ποιος το ενέκρινε.
 * @related ADR-777 §7 (Α9 · Α12 · Α14) · §8.33 · types/property-demand.ts · types/owner-property-mandate.ts
 * @module types/mandate
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΕΝΑ ΑΡΧΕΙΟ ΓΙΑ ΔΥΟ ΟΝΤΟΤΗΤΕΣ — **ΕΙΝΑΙ Η ΙΔΙΑ ΕΡΩΤΗΣΗ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η **Α9** έλυσε το *«ποιανού είναι η ζήτηση;»* με **δύο ταυτότητες**: όποιος γράφει
 * και όποιος κατέχει είναι **δύο ερωτήσεις**, και μια υλοποίηση που τις ενώνει σε μία
 * δεν μπορεί να εκφράσει τον μεσίτη (ADR-769, το ίδιο μάθημα σε άλλο τομέα).
 *
 * Η **Α14** έχει **ακριβώς** την ίδια ερώτηση για την **προσφορά** — και μέχρι το
 * §8.33 την είχε **αναπάντητη**: το `types/owner-property.ts` δήλωνε ρητά *«ο κάτοχος
 * είναι **πάντα** ο ίδιος ο άνθρωπος — γι' αυτό δεν υπάρχει καν πεδίο `mandate`»*.
 *
 * 🔑 **Δύο τόποι που απαντούν το ίδιο ερώτημα με δικό του λεξιλόγιο ο καθένας είναι,
 * κατά γράμμα, το σχήμα του ADR-749.** Γι' αυτό οι **καταστάσεις έγκρισης** και ο
 * **πυρήνας της εντολής** ζουν **εδώ**, μία φορά, και τα δύο μοντέλα τα καταναλώνουν.
 *
 * ⚠️ **Ό,τι ΔΙΑΦΕΡΕΙ μένει έξω, επίτηδες.** Η **διάρκεια** και η **προέλευση της
 * έγκρισης** ζουν στο {@link ../owner-property-mandate}, γιατί απαντούν ερώτηση που η
 * ζήτηση **δεν έχει**: μια ζήτηση δεν εκτίθεται δημόσια ονομαστικά, οπότε δεν υπάρχει
 * «μέχρι πότε επιτρέπεται να τη διαφημίζω». Ένα κοινό πεδίο που η μία πλευρά αφήνει
 * μονίμως `null` θα ήταν φρουρός που **δεν μπορεί να πυροδοτήσει** (ADR-749 §5).
 *
 * 🔴 **ΜΕΤΡΗΜΕΝΟ ΠΡΙΝ ΤΗΝ ΕΞΑΓΩΓΗ (2026-08-20):** το `property_demands` και το
 * `owner_properties` έχουν **0 έγγραφα** στη ζωντανή βάση. Η ενοποίηση του λεξιλογίου
 * κοστίζει **μηδέν μετανάστευση** — και το ξέρουμε επειδή ρωτήθηκε **η βάση**, όχι ο
 * τύπος.
 *
 * **Layering**: leaf — καθαροί τύποι + μία καθαρή συνάρτηση. Καμία εξάρτηση.
 */

// =============================================================================
// 1. Η ΕΓΚΡΙΣΗ — τρεις καταστάσεις, καμία δεν συμπτύσσεται
// =============================================================================

/**
 * Κατάσταση έγκρισης από τον άνθρωπο για λογαριασμό του οποίου γράφτηκε η εγγραφή.
 *
 * 🔴 **Η έγκριση δεν είναι τυπικότητα — είναι ο φρουρός του Ε2.** Χωρίς αυτήν, ένας
 * μεσίτης μπορεί να **φουσκώσει τον θερμοχάρτη** γράφοντας δέκα ζητήσεις, και το
 * προϊόν που πουλάμε στον εργολάβο μετράει **φαντάσματα**. Άρα:
 *
 *   > **`pending` και `declined` ΔΕΝ μετρούν ΠΟΤΕ στο επίπεδο Γ.**
 *
 * Ζουν κανονικά στο επίπεδο Β του μεσίτη — *είναι* ο κατάλογός του, από την πρώτη
 * στιγμή — αλλά **δεν** μετατρέπονται σε δημόσιο αριθμό μέχρι να μιλήσει ο άνθρωπος
 * που υποτίθεται ότι ψάχνει.
 *
 * ⚠️ Το `declined` **δεν διαγράφει**: ο μεσίτης έχει δικαίωμα να κρατά το ότι μίλησε
 * με κάποιον. Απλώς η εγγραφή παύει να είναι **ισχυρισμός για τον πελάτη** — δηλαδή
 * βγαίνει από το άθροισμα, όπως και το `pending`.
 *
 * 🔑 **Δεν υπάρχει τέταρτη κατάσταση «έληξε»**, και είναι σκόπιμο: η λήξη είναι
 * ιδιότητα της **διάρκειας** της εντολής, όχι της **απάντησης** του ανθρώπου. Ένας
 * άνθρωπος που είπε «ναι» **είπε ναι**, ακόμη κι όταν η προθεσμία που ενέκρινε
 * πέρασε. Το να τα ενώναμε θα έσβηνε τη διαφορά ανάμεσα σε *«αρνήθηκε»* και *«πέρασε
 * ο χρόνος»* — δύο πολύ διαφορετικά πράγματα για τον ίδιο και για εμάς.
 * Δες `isMandateExpired` στο {@link ../owner-property-mandate}.
 *
 * *(Μετακόμισε εδώ από το `types/property-demand.ts` στο §8.33, αυτούσιο. Ήταν
 * `DEMAND_CONFIRMATIONS` και το ίδιο ερώτημα γεννήθηκε δεύτερη φορά στην προσφορά.)*
 */
export const MANDATE_CONFIRMATIONS = ['pending', 'confirmed', 'declined'] as const;

export type MandateConfirmation = (typeof MANDATE_CONFIRMATIONS)[number];

// =============================================================================
// 2. Ο ΠΥΡΗΝΑΣ ΤΗΣ ΕΝΤΟΛΗΣ
// =============================================================================

/**
 * Ό,τι κουβαλά **κάθε** εγγραφή γραμμένη για λογαριασμό τρίτου.
 *
 * ⚠️ Ο πελάτης δηλώνεται ως **επαφή** (`cont_*`) και **όχι** ως χρήστης: ένας
 * αγοραστής — και εξίσου ένας οικοπεδούχος — **δεν έχει λογαριασμό** τη στιγμή που ο
 * επαγγελματίας γράφει το αίτημά του, και ένα υποχρεωτικό uid θα έκανε τη ροή
 * **αδύνατη ακριβώς εκεί όπου συμβαίνει**.
 */
export interface BrokeredMandateCore {
  /** FK → `contacts` (`cont_*`) — ο πελάτης, όπως τον ξέρει ο επαγγελματίας. */
  readonly clientContactId: string;
  readonly confirmation: MandateConfirmation;
  /**
   * Το uid του πελάτη, **μόνο** όταν έχει λογαριασμό **και** επιβεβαίωσε ο ίδιος
   * συνδεδεμένος.
   *
   * ⚠️ **`null` ΔΕΝ σημαίνει «δεν ενέκρινε».** Ο συνηθισμένος πελάτης απαντά από
   * **σύνδεσμο σε email** χωρίς ποτέ να αποκτήσει λογαριασμό — και εκείνη η απάντηση
   * είναι **εξίσου** έγκυρη. Το «πότε» το κρατά η εντολή που έχει χρόνο
   * ({@link ../owner-property-mandate}), όχι αυτό το πεδίο.
   */
  readonly confirmedByUserId: string | null;
}

/**
 * **Ποιανού είναι** — η δομική μορφή, κοινή σε ζήτηση και προσφορά.
 *
 * 🔑 **Δομικός τύπος, ΟΧΙ κληρονομιά.** Κάθε οντότητα δηλώνει τη **δική της** εντολή
 * με ό,τι επιπλέον χρειάζεται, και περνά από τον **ίδιο** κριτή
 * ({@link isMandateAttributable}) επειδή **ταιριάζει δομικά**. Είναι η ίδια κίνηση με
 * το `ProjectableProperty` της προβολής: *πολλές πηγές, μία κρίση*.
 */
export type MandateLike =
  /** Ο ίδιος ο άνθρωπος έγραψε την εγγραφή του. Μετράει αμέσως. */
  | { readonly kind: 'self' }
  /** Επαγγελματίας κατέγραψε την εγγραφή πελάτη του. */
  | ({ readonly kind: 'brokered' } & BrokeredMandateCore);

// =============================================================================
// 3. Ο ΚΡΙΤΗΣ — μία υλοποίηση, δύο καταναλωτές
// =============================================================================

/**
 * **Μιλά αυτή η εγγραφή για τον άνθρωπο που δηλώνει ότι εκπροσωπεί;**
 *
 * `true` όταν την έγραψε ο ίδιος, **ή** όταν ο πελάτης έχει πει «ναι».
 *
 * 🔴 **Είναι ο ΜΟΝΟΣ τόπος όπου γράφεται αυτός ο κανόνας.** Ένας δεύτερος —
 * π.χ. ένα `mandate.confirmation === 'confirmed'` γραμμένο στο χέρι κάπου αλλού —
 * θα ξεχνούσε το σκέλος `self` και θα έκρυβε **κάθε** αγγελία ιδιώτη, ή θα ξεχνούσε
 * το `declined` και θα δημοσίευε ό,τι κάποιος αρνήθηκε. Και τα δύο θα «δούλευαν»
 * στη δοκιμή του πρώτου παραδείγματος.
 */
export function isMandateAttributable(mandate: MandateLike): boolean {
  return mandate.kind === 'self' || mandate.confirmation === 'confirmed';
}
