/**
 * @fileoverview Το συμβόλαιο ανάγνωσης του **σώματος** του σχεδίου — η έξοδος του Λ1β
 *               (ADR-759 §4.6, Άξονας Α).
 *
 * ## Γιατί δεύτερος αναγνώστης και όχι επέκταση του Λ1 της πινακίδας
 *
 * Η πινακίδα είναι **πλέγμα**: κελιά σε θέσεις, ζεύγη ετικέτα→τιμή, τυπογραφική ιεραρχία `\H`.
 * Ο Λ1 τη διαβάζει με **γεωμετρία** (`title-block-pairing.ts` — στοίχιση γραμμής/στήλης).
 *
 * Το σώμα είναι **πρόζα μέσα σε ΕΝΑ MTEXT**: 5.640 χαρακτήρες, 47 γραμμές, στηλοθέτες αντί για
 * κελιά. Μετρημένο στο `G753_ergasia F.dxf`. Η γεωμετρία εκεί δεν λέει τίποτα — υπάρχει **ένα**
 * σημείο εισαγωγής για ολόκληρο το έγγραφο. Η ίδια μηχανή πάνω στα δύο υλικά είναι ο ορισμός του
 * λάθους εργαλείου, και γι' αυτό η §4.6 δίνει στις δύο αναγνώσεις **διαφορετική αξιοπιστία**
 * (`sourceKind`) αντί να τις ενώσει.
 *
 * 🔑 **Ό,τι ΜΠΟΡΕΙ να μοιραστεί, μοιράζεται**: το ξεγύμνωμα των κωδικών MTEXT (`mtextToSegments`),
 * η σύγκριση λέξη-προς-λέξη (`@/utils/greek-text`), ο σκελετός πρότασης (`proposal-base`), η
 * κατασκευή πρότασης προς τοπογραφικό (`buildSurveyProposal`) και ο **κατάλογος πεδίων**
 * (`survey-bindable-fields`). Ο Λ1β προσθέτει **μόνο** το κομμάτι που δεν υπήρχε: πώς βρίσκεις
 * μια τιμή μέσα σε πρόζα.
 *
 * ## 🔴 Το κρίσιμο: ο Λ1β είναι ΕΝΤΟΠΙΣΤΗΣ, όχι αναλυτής
 *
 * Επιστρέφει **ωμά κομμάτια κειμένου** (`rawValue`), ποτέ τιμές τύπου. Η μετατροπή
 * «κείμενο → τιμή» ζει **μία** φορά, στο `SURVEY_BINDING_SPECS[field].parse` — το ίδιο σημείο
 * που τη ζει και για την πινακίδα. Δύο αναλυτές για το ίδιο πεδίο σημαίνει ότι την ημέρα που
 * αλλάξει ο κανόνας, οι δύο διαδρομές θα γράφουν **διαφορετική τιμή για το ίδιο σχέδιο**.
 *
 * @see ADR-759 §2β.2 — η μετρημένη δομή Α–Ι
 * @module types/document-body-reading
 */

import { BINDABLE_SURVEY_FIELDS } from '@/config/survey-bindable-fields';

// ── Λεξιλόγιο πεδίων (SSoT) ───────────────────────────────────────────────────

/**
 * Ό,τι διαβάζει το σώμα και **δεν** πάει στο τοπογραφικό.
 *
 * 🔑 Ένα μέλος σήμερα, και είναι ο λόγος που το λεξιλόγιο δεν ταυτίζεται απλώς με το
 * `BINDABLE_SURVEY_FIELDS`: η Περιφερειακή Ενότητα είναι ιδιότητα της **διεύθυνσης του
 * έργου** (ADR-745 §7), και είναι επίσης η τιμή που **σήμερα δεν γράφεται ποτέ** — η πινακίδα
 * δίνει μόνο το διφορούμενο «Π.Ε. 39» (ADR-759 §2β.3).
 */
export const DOCUMENT_BODY_ONLY_KEYS = ['regionalUnit'] as const;

/**
 * Τι μπορεί να **πει** το σώμα του σχεδίου.
 *
 * 🔴 **ΠΑΡΑΓΕΤΑΙ, δεν ξαναγράφεται — και η πρώτη γραφή του ήταν λάθος.** Είχε γραφτεί ως
 * χειρόγραφη λίστα 27 ονομάτων «γιατί ο αναγνώστης ονομάζει από τη σκοπιά του σχεδίου». Ο
 * token-based έλεγχος (N.18 / CHECK 3.28) έδειξε ότι **26 από τα 27 ήταν κατά λέξη** το
 * `BINDABLE_SURVEY_FIELDS` — δηλαδή το επιχείρημα ήταν φιλολογικό και η πραγματικότητα δίδυμο.
 *
 * Η αλήθεια είναι απλούστερη: **το σώμα διαβάζει ό,τι μπορεί να δεχτεί η καρτέλα, συν όσα πάνε
 * αλλού** — σήμερα μόνο η Περιφερειακή Ενότητα, που ανήκει στη **διεύθυνση του έργου**. Έτσι
 * γραμμένο, νέο πεδίο καρτέλας γίνεται αυτόματα αναγνώσιμο **μόλις γραφτεί ο κανόνας του**
 * (το επιβάλλει η πύλη ισότητας), και δεν υπάρχει δεύτερη λίστα να ξεχαστεί.
 *
 * ⚠️ Η **σειρά** των δύο μερών δεν είναι αδιάφορη: το `regionalUnit` μπαίνει τελευταίο ώστε
 * η σειρά του λεξιλογίου να παραμένει η σειρά της τυπωμένης φόρμας Α–Ι.
 */
export const DOCUMENT_BODY_FIELD_KEYS = [
  ...BINDABLE_SURVEY_FIELDS,
  ...DOCUMENT_BODY_ONLY_KEYS,
] as const;

export type DocumentBodyFieldKey = (typeof DOCUMENT_BODY_FIELD_KEYS)[number];

