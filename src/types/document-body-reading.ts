  /** «ΣΤΟΙΧΕΙΑ ΕΡΕΥΝΑΣ ΙΔΙΩΤΗ ΜΗΧΑΝΙΚΟΥ» — η τυποποιημένη φόρμα με ενότητες Α–Ι. */
  'private-engineer-survey',
  /** «ΔΗΛΩΣΗ ΤΟΥ Ν.651/77» — η υπεύθυνη δήλωση του μηχανικού, με τόπο και **ημερομηνία**. */
  'law651-declaration',
  /** «ΔΗΛΩΣΗ ΙΔΙΟΚΤΗΤΗ (Ν. 4030/11)» — τα όρια όπως τα υπέδειξε ο ιδιοκτήτης. */
