/**
 * Οι **επτά** απαντήσεις στο *«επιτρέπεται ο Χ να ενεργήσει στον χώρο Ω;»*.
 *
 * Κλειστό σύνολο: ο απαντητής **δεν επιστρέφει ποτέ** τιμή εκτός αυτού, και
 * άγνωστη κατάσταση **ρίχνει με όνομα** (`fail-closed`).
 *
 * | Ετυμηγορία | Αναγνώσεις | Από ποια απόφαση |
 * |---|---|---|
 * | `home` | **0** | Ε-5 §2 — το υπογεγραμμένο token **είναι** η απόδειξη |
 * | `self` | **0** | Ε-3 §2/§3 — ο ιδιωτικός χώρος υπάρχει επειδή υπάρχει ο άνθρωπος |
 * | `platform-bypass` | **0** | ονομασμένη εξαίρεση· κρατά ακέραιο τον `CompanySwitcher` |
 * | `member` | 1 | Κ-2 — υπάρχει εγγραφή με `status: 'active'` |
 * | `not-a-member` | 1 | Ε-5 §4 #1 — προς τα έξω **«δεν υπάρχει»** |
 * | `suspended` | 1 | Ε-2 §5 — η ανάκληση είναι **ειπωμένη** |
 * | `unknown` | 1 | **N.12** — άγνωστο **δεν** είναι «δεν είσαι μέλος» |
 */
export type MembershipVerdict =
  | 'home'
  | 'self'
  | 'platform-bypass'
  | 'member'
  | 'not-a-member'
  | 'suspended'
  | 'unknown';

/**
 * Οι ετυμηγορίες που **επιτρέπουν**.
 *
 * ⚠️ Το `unknown` **ΔΕΝ** είναι εδώ — και δεν είναι εδώ ούτε ως «προσωρινή
 * ανοχή». Μια αποτυχία αναζήτησης που διαβάζεται ως άδεια είναι διαρροή· μια
 * που διαβάζεται ως *«δεν είσαι μέλος»* είναι ψέμα στον χρήστη (ADR-787 Ε-5
 * §4 #3). Είναι **δική του κατάσταση** ακριβώς για να μη γίνει τίποτα από τα δύο.
 */
export const ALLOWING_VERDICTS: readonly MembershipVerdict[] = [
  'home',
  'self',
  'platform-bypass',
  'member',
] as const;

/** Επιτρέπει αυτή η ετυμηγορία την πράξη; */
export function isAllowed(verdict: MembershipVerdict): boolean {
  return ALLOWING_VERDICTS.includes(verdict);
}

/**
 * Το αποτέλεσμα του απαντητή: **η ετυμηγορία μαζί με τον χώρο που κρίθηκε**.
 *
 * ⚠️ Ο χώρος επιστρέφεται **ρητά** ώστε ο καλών να μη χρειάζεται να θυμάται τι
 * ρώτησε — και ώστε ένα «ναι» να μην μπορεί ποτέ να εφαρμοστεί σε **άλλον**
 * χώρο από αυτόν που κρίθηκε.
 */
export interface MembershipDecision {
  readonly verdict: MembershipVerdict;
  readonly workspace: WorkspaceRef;
  /** Η εγγραφή, **μόνο** όταν διαβάστηκε (`member` · `suspended`). */
  readonly membership?: WorkspaceMembership;
}
