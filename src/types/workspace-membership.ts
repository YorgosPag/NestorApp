// Ο ΧΩΡΟΣ — ΔΥΟ ΕΙΔΗ, ΠΟΤΕ ΕΝΑ
// ============================================================================

/**
 * Ο **χώρος του γραφείου / της εταιρείας**.
 *
 * Το `companyId` είναι ο **άξονας απομόνωσης** όλης της πλατφόρμας (ADR-063 ·
 * ADR-702 · ADR-742 · ADR-747). Η **αρχή Α1** του ADR-787 αποφάσισε ρητά ότι
 * το *κλειδί* μένει `companyId` — αλλάζει η **γλώσσα της οθόνης**, όχι το
 * μοντέλο δεδομένων.
 */
export interface OrgWorkspaceRef {
  readonly kind: 'org';
  readonly companyId: string;
}

/**
 * Ο **ιδιωτικός χώρος του ανθρώπου**.
 *
 * 🔴 **ΔΕΝ έχει — και δεν επιτρέπεται να αποκτήσει — `companyId`.**
 *
 * Υπάρχει **από την πρώτη στιγμή, για όλους, και δεν ζητείται ποτέ**
 * (ADR-787 Ε-3 §2): δεν είναι δυνατότητα που ενεργοποιείς, είναι η **βάση**.
 * Γι' αυτό **δεν αποθηκεύεται πουθενά** — **παράγεται** από την ταυτότητα του
 * ανθρώπου. Ένα έγγραφο θα ήταν πράγμα που μπορεί να λείπει.
 */
export interface PersonalWorkspaceRef {
  readonly kind: 'personal';
  readonly userId: string;
}

/**
 * Ο χώρος, ως **αίτημα**: *«ποιον χώρο ζητάω;»* (ADR-787 Ε-5).
 *
 * ⚠️ Είναι **είσοδος χρήστη**, άρα **εξ ορισμού αναξιόπιστη**. Το ότι μπορείς
 * να κατασκευάσεις ένα `WorkspaceRef` **δεν σου δίνει καμία άδεια** — την άδεια
 * την απαντά μόνο ο διακομιστής (`src/lib/auth/workspace-membership.ts`).
 */
export type WorkspaceRef = OrgWorkspaceRef | PersonalWorkspaceRef;

// ============================================================================
// ΚΑΤΑΣΚΕΥΑΣΤΕΣ + ΚΛΕΙΔΙ
// ============================================================================

/** Ο χώρος ενός γραφείου, από το αναγνωριστικό του. */
export function orgWorkspace(companyId: string): OrgWorkspaceRef {
  return { kind: 'org', companyId };
}

/**
 * Ο ιδιωτικός χώρος ενός ανθρώπου, από το `uid` του.
 *
 * ⚠️ **Δεν διαβάζει τίποτα και δεν γράφει τίποτα** — ο ιδιωτικός χώρος
 * *υπάρχει* επειδή υπάρχει ο άνθρωπος (Ε-3 §2).
 */
export function personalWorkspace(userId: string): PersonalWorkspaceRef {
  return { kind: 'personal', userId };
}

/**
 * Κλειδί **προβολής** — ανά-αίτημα απομνημόνευση, καταγραφή, και το `id` του
 * `Workspace` που ταξιδεύει προς την οθόνη. **Τίποτε άλλο.**
 *
 * ⛔ **ΜΗΝ το αποθηκεύσεις σε έγγραφο Firestore, ΜΗΝ το κάνεις τμήμα
 *    διεύθυνσης, ΜΗΝ γράψεις συνάρτηση που το ξαναδιαβάζει σε `WorkspaceRef`.**
 *    Τη στιγμή που κάποιος γράψει τον αντίστροφο αναλυτή, η ένωση έχει
 *    ισοπεδωθεί ξανά σε συμβολοσειρά και όλη η προστασία του αρχείου έχει
 *    παρακαμφθεί από την πίσω πόρτα. Το ψευδώνυμο της διεύθυνσης είναι **άλλο
 *    πράγμα** και έχει δικούς του κανόνες (ADR-787 Ε-5 §8).
 */
export function workspaceRefKey(ref: WorkspaceRef): string {
  return ref.kind === 'org' ? `org:${ref.companyId}` : `personal:${ref.userId}`;
}

// ============================================================================
// ΤΟ ΕΓΓΡΑΦΟ ΜΕΛΟΥΣ
// ============================================================================

/**
 * Η κατάσταση της συμμετοχής.
 *
 * ⚠️ Το `suspended` **δεν είναι το ίδιο** με «δεν υπάρχει εγγραφή»: ο
 * ανακληθείς **ξέρει** ότι ο χώρος υπάρχει, άρα του χρωστάμε **άλλη** απάντηση
 * (ADR-787 Ε-2 §5 — *η ανάκληση είναι άμεση **και ειπωμένη***).
 */
export type WorkspaceMembershipStatus = 'active' | 'suspended' | 'pending';

/**
 * Η **μία** εγγραφή που απαντά *«είναι ο Χ μέλος του χώρου Ω;»*.
 *
 * Ζει στο `companies/{companyId}/workspace_members/{uid}`.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΤΟ ΚΛΕΙΔΙ ΤΟΥ ΕΓΓΡΑΦΟΥ ΕΙΝΑΙ ΤΟ `uid` ΚΑΙ ΟΧΙ ENTERPRISE ID
 * ─────────────────────────────────────────────────────────────────────────────
 * Είναι **δομική επιλογή, όχι παράλειψη**: με κλειδί το `uid`, η **διπλή
 * συμμετοχή του ίδιου ανθρώπου στον ίδιο χώρο γίνεται αδύνατη** — δεν
 * χρειάζεται κανένας έλεγχος μοναδικότητας που κάποιος μπορεί να ξεχάσει.
 * Είναι η ίδια επιλογή που κάνει ήδη το `set-user-claims/claims-handler.ts`
 * (`.doc(uid)`), και η τεκμηριωμένη πρακτική για μοντέλα μελών σε Firestore.
 *
 * ✅ Ο κανόνας **N.6** τηρείται: η εγγραφή γίνεται με `set()` και **ρητό**
 *    αναγνωριστικό — ποτέ `addDoc()` ή αυτόματο id.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΤΟ ΟΝΟΜΑ ΤΗΣ ΣΥΛΛΟΓΗΣ ΕΙΝΑΙ ΜΗΧΑΝΙΣΜΟΣ, ΟΧΙ ΓΟΥΣΤΟ
 * ─────────────────────────────────────────────────────────────────────────────
 * Λέγεται `workspace_members` και **όχι** `members`, επειδή τα μέλη **έργου**
 * ζουν σε `companies/{W}/projects/{P}/members/{…}`. Το Firestore απαντά την
 * αντίστροφη ερώτηση (*«σε ποιους χώρους ανήκω;»*) με **collection group
 * query**, που σαρώνει **κατά όνομα συλλογής** — δύο συλλογές με το ίδιο όνομα
 * επιστρέφονται **μαζί**.
 *
 * ⇒ Με το όνομα `members` και στα δύο, ένας συνεργάτης καλεσμένος σε **ένα
 * έργο** θα εμφανιζόταν ως **μέλος ολόκληρου του γραφείου**, σιωπηλά. Το
 * διαφορετικό όνομα το κάνει **αδύνατο**, χωρίς φίλτρο που πρέπει να θυμάσαι
 * (ADR-787 §5.1 β).
 */
export interface WorkspaceMembership {
  /** Ο άνθρωπος. Ίδιο με το κλειδί του εγγράφου — σκόπιμα διπλό, ώστε να είναι **πεδίο** για το collection group query. */
  readonly uid: string;

  /** Ο ρόλος του μέσα σε αυτόν τον χώρο (λεξιλόγιο `src/lib/auth/roles.ts`). */
  readonly globalRole: string;

  /** Ενεργό / ανασταλμένο / εκκρεμές. */
  readonly status: WorkspaceMembershipStatus;

  /** Σύνολα δικαιωμάτων μέσα στον χώρο (ADR-244). */
  readonly permissionSetIds: readonly string[];

  /** Πότε μπήκε. ISO ή Firestore `Timestamp` κατά την ανάγνωση. */
  readonly joinedAt?: unknown;

  /** Ποιος τον έβαλε — το ίχνος του ADR-787 Α4 #3. */
  readonly addedBy: string | null;

  /** Τελευταία μεταβολή. */
  readonly updatedAt?: unknown;
}

