/**
 * «Ποιος είναι μέλος ποιου χώρου;» — το λεξιλόγιο, μία φορά
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΛΥΝΕΙ (ADR-787 §5.1, μετρημένο 2026-08-22)
 * ─────────────────────────────────────────────────────────────────────────────
 * Η ερώτηση *«σε ποιον χώρο ανήκει αυτός ο άνθρωπος;»* είχε **τρία ράφια και
 * κανένα βιβλίο**:
 *
 * | Ράφι | Τι είχε μέσα |
 * |---|---|
 * | συλλογή `workspaces` | **δεν υπάρχει στη βάση** |
 * | συλλογή `workspace_members` (top-level) | **δεν υπάρχει· 0 καταναλωτές· 0 κανόνες** |
 * | `companies/{W}/members/{uid}` | **0 έγγραφα**, παρότι 6 σημεία κώδικα γράφουν εκεί |
 *
 * Η **μοναδική** ζωντανή εγγραφή ήταν το σκαλάρ `users/{uid}.companyId`, που
 * χωράει **έναν** χώρο — ενώ η **αρχή Α2** του ADR-787 απαιτεί *«ένας άνθρωπος
 * → **πολλοί** χώροι»*.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ Ο ΤΥΠΟΣ ΕΙΝΑΙ ΕΝΩΣΗ ΚΑΙ ΟΧΙ ΣΥΜΒΟΛΟΣΕΙΡΑ — Η ΚΑΡΔΙΑ ΤΟΥ ΑΡΧΕΙΟΥ
 * ─────────────────────────────────────────────────────────────────────────────
 * Το **ADR-787 Ε-3 §3** απαγορεύει ρητά το `companyId` στα δεδομένα του
 * ιδιωτικού χώρου: ένα `companyId` εκεί θα έδινε **σιωπηλά** στον διαχειριστή
 * ενός γραφείου πρόσβαση στο ψάξιμο σπιτιού ενός ανθρώπου — και θα ήταν
 * **πράσινο σε κάθε πύλη**, γιατί το `companyId` είναι ακριβώς ό,τι ψάχνουν.
 *
 * Το §2.7 δ ονομάζει μάλιστα **πού** θα ζητηθεί η παράβαση: στη λίστα χώρων,
 * *«για να φαίνεται ο ιδιωτικός»*.
 *
 * Μέχρι σήμερα αυτό ήταν **κανόνας που πρέπει να θυμάσαι**. Εδώ παύει να είναι:
 * ο κλάδος `personal` **δεν έχει πεδίο `companyId`**, οπότε η παράβαση δεν είναι
 * κακή πρακτική — **δεν χτίζει**.
 *
 * 🔑 Ίδιο σχήμα με το **ADR-789** (`PlanarPoint` — *«ο θάνατος του z:0»*): δύο
 * πράγματα που μπερδεύονταν, δύο **τύποι**, σύγχυση **αδύνατη**. Και ταιριάζει
 * με ό,τι ήδη δηλώνει το `tenant-config.ts` (`mode: 'companyId' | 'userId'`) —
 * δεν εφευρίσκεται λεξιλόγιο, ονοματίζεται το υπάρχον.
 *
 * ⛔ **ΜΗΝ προσθέσεις `companyId?: string` στον κλάδο `personal`** «για
 *    ομοιομορφία» ή «για να περνά η πύλη 3.35». Είναι **άξονας απομόνωσης**,
 *    όχι ετικέτα (ADR-787 Ε-3 §8).
 * ⛔ **ΜΗΝ ισοπεδώσεις την ένωση σε ένα `workspaceId: string`.** Μια
 *    συμβολοσειρά που σημαίνει δύο πράγματα είναι ακριβώς η βλάβη που το
 *    **ADR-749** πλήρωσε με τέσσερις μηχανές και τρεις αριθμούς.
 *
 * @module types/workspace-membership
 * @see docs/centralized-systems/reference/adrs/ADR-787-multi-organization-platform.md
 */

