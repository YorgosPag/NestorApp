/**
 * ============================================================================
 * Δηλωμένο επάγγελμα — το ΣΤΟΙΧΕΙΟ (ADR-798 Φάση 1)
 * ============================================================================
 *
 * Τα τέσσερα πεδία που καταγράφουν **ένα** δηλωμένο επάγγελμα, ταξινομημένο
 * κατά ESCO/ISCO-08 **όπου γίνεται** και ελεύθερο κείμενο όπου δεν γίνεται.
 *
 * 🔑 **ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟ ΑΡΧΕΙΟ, ΚΑΙ ΟΧΙ ΜΕΣΑ ΣΤΟ `types/contacts/`**
 * Το ίδιο σχήμα απαντά σε **δύο** ερωτήματα σε **δύο** τομείς:
 *   1. *«τι επάγγελμα έχει αυτή η **επαφή**»* — `IndividualContact` (ADR-132)
 *   2. *«τι **ΕΙΝΑΙ** ο κάτοχος αυτού του **λογαριασμού**»* — `users/{uid}` (ADR-798)
 * Αν ζούσε στο `types/contacts/`, ο τομέας της ταυτότητας θα εισήγαγε από το CRM
 * για να πει τι είναι ένας άνθρωπος. Ουδέτερο σπίτι ⇒ **κανένας από τους δύο δεν
 * εξαρτάται από τον άλλον**.
 *
 * 🔴 **ΓΙΑΤΙ ΤΟ ΟΝΟΜΑ ΔΕΝ ΛΕΕΙ «ESCO»** — *το όνομα δηλώνει τι **ΕΓΓΥΑΤΑΙ***
 * (μάθημα CHECK 3.59 / ADR-792: το `Point3D` που δεν εγγυόταν `z`). Αυτός ο τύπος
 * **ΔΕΝ** εγγυάται ESCO: το `profession` μπορεί να είναι σκέτο ελεύθερο κείμενο,
 * χωρίς `escoUri`, και αυτό είναι **σχεδιασμός** — η οπισθόδρομη συμβατότητα του
 * ADR-132 §1. Ένα όνομα `EscoOccupationRef` θα υποσχόταν ταξινόμηση που ο τύπος
 * δεν μπορεί να κρατήσει, και ο επόμενος θα έγραφε `escoUri!` πάνω σε `undefined`.
 *
 * ⚠️ **ΔΕΝ ΟΡΙΖΕΙ ΠΛΗΘΙΚΟΤΗΤΑ, ΕΠΙΤΗΔΕΣ.** Το ερώτημα *«ένα επάγγελμα ή N;»* είναι
 * **ανοιχτό** (ADR-798 §11, **Ο-2**) και αποφασίζεται στον **καταναλωτή**:
 * `extends DeclaredOccupation` για ένα · `occupations?: DeclaredOccupation[]` για N.
 * Το **στοιχείο** είναι το ίδιο και στις δύο περιπτώσεις — γι' αυτό η απόφαση δεν
 * μπλοκάρει τίποτα και δεν πληρώνεται δύο φορές.
 *
 * ⚠️ **ΔΕΝ ΟΡΙΖΕΙ ΕΠΑΛΗΘΕΥΣΗ.** Το *δηλωμένο ≠ επαληθευμένο* (`unknown` ·
 * `declared` · `verified`, **ποτέ boolean**) είναι **άλλο ερώτημα**, με δικό του
 * σχήμα και δική του φάση — ADR-798 §7.
 *
 * ⛔ **ΜΗΝ γράψεις δεύτερη δήλωση αυτών των τεσσάρων πεδίων.** Μέχρι τις 2026-08-24
 * υπήρχαν **ΔΥΟ** — `EscoPickerValue` *(ονομασμένο από το UI component που το
 * εκπέμπει)* και ενσωματωμένα πάνω στο `IndividualContact`, με το `contracts.ts`
 * να **μην εισάγει καθόλου** από το `esco-types.ts`. Ήταν το σχήμα του ADR-749,
 * ζωντανό. Μια **τρίτη** θα το επανέφερε.
 *
 * @module types/professional-identity
 * @see docs/centralized-systems/reference/adrs/ADR-798-person-professional-identity.md
 * @see docs/centralized-systems/reference/adrs/ADR-132-esco-professional-classification.md
 */

/**
 * **Ένα** δηλωμένο επάγγελμα — ταξινομημένο όπου γίνεται.
 *
 * Δύο νόμιμες καταστάσεις, και **καμία** από τις δύο δεν είναι σφάλμα:
 *
 * | Κατάσταση | `profession` | `escoUri` · `escoLabel` · `iscoCode` |
 * |---|---|---|
 * | **Ταξινομημένο** *(επιλογή από ESCO)* | η ετικέτα | **και τα τρία** |
 * | **Ελεύθερο κείμενο** *(ό,τι έγραψε ο άνθρωπος)* | το κείμενο | **κανένα** |
 *
 * ⚠️ **Τα τρία πεδία ESCO πάνε ΠΑΝΤΑ μαζί.** Δεν υπάρχει νόημα σε `escoUri` χωρίς
 * `iscoCode`: το ESCO εγγυάται ότι **κάθε** occupation ανήκει σε **ακριβώς μία**
 * ISCO-08 unit group. Ο τύπος δεν μπορεί να το επιβάλει *(τρία ανεξάρτητα
 * προαιρετικά)*· ο **γραφέας** οφείλει να τα γράψει μαζί.
 */
export interface DeclaredOccupation {
  /**
   * Το επάγγελμα σε **αναγνώσιμη μορφή** — η ετικέτα ESCO αν επιλέχθηκε από την
   * ταξινομία, αλλιώς ό,τι έγραψε ο άνθρωπος.
   *
   * ⚠️ Είναι η **μόνη** τιμή που εμφανίζεται πάντα στην οθόνη. Ένας καταναλωτής
   * που δείχνει `escoLabel` και πέφτει σε κενό όταν λείπει, δείχνει **τίποτα**
   * ακριβώς στην περίπτωση του ελεύθερου κειμένου — που είναι η **συνηθισμένη**.
   */
  profession?: string;

  /**
   * Το ESCO occupation URI — η **μηχανικά αναγνώσιμη ταυτότητα**
   * *(π.χ. `http://data.europa.eu/esco/occupation/…`)*.
   *
   * 🔑 Είναι η τιμή που ταξιδεύει **ακέραιη** στην εξαγωγή IFC, μέσα στο
   * `IfcClassificationReference.Location : IfcURIReference` — ADR-798 §6.2.
   */
  escoUri?: string;

  /** Η ετικέτα ESCO όπως ήταν τη στιγμή της επιλογής — **αντίγραφο για εμφάνιση**, όχι αυθεντία. Η αυθεντία είναι το `escoUri`. */
  escoLabel?: string;

  /**
   * Ο τετραψήφιος κωδικός ISCO-08 *(π.χ. `2165` τοπογράφος · `2611` δικηγόρος ·
   * `2619` συμβολαιογράφος · `3432` διακοσμητής)* — για ομαδοποίηση και φιλτράρισμα.
   *
   * ⚠️ **Η κατεύθυνση ESCO → ISCO είναι ολική· η αντίστροφη ΔΕΝ είναι.** Μία unit
   * group περιέχει **πολλά** ESCO occupations, οπότε από τον κωδικό **δεν**
   * ανακτάται το επάγγελμα. Μην γράψεις αντίστροφο επιλυτή: θα ήταν μαντεψιά με
   * πρόσωπο βεβαιότητας (ADR-798 §6.2).
   */
  iscoCode?: string;
}

