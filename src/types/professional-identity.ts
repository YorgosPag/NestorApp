/**
 * **Η ΑΠΟΔΕΙΞΗ ΕΙΝΑΙ ΖΕΥΓΟΣ `(αρχή, αριθμός)`** — ποτέ σκέτος αριθμός.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΓΙΑΤΙ ΔΙΑΚΡΙΤΗ ΕΝΩΣΗ ΚΑΙ ΟΧΙ ΠΡΟΑΙΡΕΤΙΚΟ `chapter`
 *
 * Με `chapter?: string` ένας αριθμός δικηγόρου **χωρίς** σύλλογο θα ήταν
 * συντακτικά έγκυρος, και η ορθότητα θα κρεμόταν από έναν κανόνα εγκυρότητας
 * που κάποιος πρέπει να **θυμηθεί** να καλέσει. Εδώ είναι **μη εκφράσιμος**: ο
 * μεταγλωττιστής απαιτεί `chapter` τη στιγμή που το `authority` είναι
 * `bar-association`. Η απόκλιση δεν γίνεται ανιχνεύσιμη — γίνεται **αδύνατη**
 * *(η ίδια αρχή που κρατά το CHECK 3.73 · ADR-812)*.
 * ═════════════════════════════════════════════════════════════════════════════
 * ⚠️ **ΤΟ `number` ΔΕΝ ΕΠΙΚΥΡΩΝΕΤΑΙ ΩΣ ΑΡΙΘΜΟΣ, ΕΠΙΤΗΔΕΣ.** Είναι `string`
 * γιατί τα μητρώα **δεν** συμφωνούν σε μορφή: το ΤΕΕ δίνει καθαρά ψηφία, το
 * ΓΕΜΗ δωδεκαψήφιο, οι σύλλογοι κατά περίπτωση. Ένα `/^\d+$/` εδώ θα απέκλειε
 * υπαρκτό επαγγελματία επειδή ο **δικός μας** κανόνας είναι στενότερος από της
 * αρχής — μαντεψιά με πρόσωπο βεβαιότητας.
 *
 * @see docs/centralized-systems/reference/adrs/ADR-841-public-listing-body-and-platform-verticals.md — Α9.1
 */
export type ProfessionalRegistration =
  | {
      /** Διακριτής: αρχή με **έναν** εκδότη πανελλαδικά. */
      readonly authorityKind: 'national';
      readonly authority: NationalRegistryId;
      /** Ο αριθμός μητρώου, **όπως τον έδωσε η αρχή**. */
      readonly number: string;
    }
  | {
      /** Διακριτής: αρχή με **πολλούς** εκδότες ⇒ το `chapter` είναι υποχρεωτικό. */
      readonly authorityKind: 'chapter';
      readonly authority: ChapteredRegistryId;
      /**
       * **Ποιος** εκδότης — «ΔΣΘ», «ΔΣ Πατρών», «Συμβ. Σύλλογος Εφετείου Αθηνών».
       *
       * ⚠️ **Ελεύθερο κείμενο, όχι κλειστό σύνολο.** Οι Δικηγορικοί Σύλλογοι
       * είναι **63**· ένα ημιτελές σύνολο θα απέκλειε υπαρκτό δικηγόρο επειδή
       * λείπει μια γραμμή. Δες `constants/professional-registries.ts`.
       */
      readonly chapter: string;
      readonly number: string;
    };

/**
 * **Δηλωμένο ≠ Επαληθευμένο** — τρεις καταστάσεις, **ποτέ boolean** (ADR-798 §7).
 *
 * Ένα `verified: boolean` θα είχε **δύο** τιμές για **τρεις** καταστάσεις, και το
 * `false` θα σήμαινε ταυτόχρονα *«ελέγχθηκε και δεν ισχύει»* και *«δεν ρώτησε
 * κανείς»* — το σχήμα **«0 = κανείς δεν κοίταξε»** που το έργο έχει πληρώσει
 * **οκτώ** μετρημένες φορές *(CHECK 3.35 · 3.39 · 3.40 · 3.43 · 3.45 · 3.46 ·
 * 3.51 · 3.57)*.
 *
 * | Τιμή | Σημαίνει | Στην οθόνη |
 * |---|---|---|
 * | `unknown` | **κανείς δεν δήλωσε τίποτα** | ουδέτερο· **ποτέ** ως «όχι» |
 * | `declared` | δήλωσε `(αρχή, αριθμό)`· **κανείς δεν το έλεγξε** | ορατό **ως δήλωση** |
 * | `verified` | ρωτήθηκε η αρχή | ορατό **ως επαληθευμένο** |
 *
 * 🔑 **Γιατί το `declared` αρκεί για να ανοίξει ο κατάλογος** *(ADR-841 Α9.2)*: ο
 * ψεύτικος αριθμός **εκθέτει** αυτόν που τον έγραψε — είναι ισχυρισμός που
 * **οποιοσδήποτε** διαψεύδει σε ένα τηλεφώνημα. Το «δικηγόρος» **χωρίς** αριθμό
 * δεν διαψεύδεται από κανέναν.
 *
 * ⛔ **ΚΑΜΙΑ ΤΕΤΑΡΤΗ ΤΙΜΗ.** Το *«αυτό το επάγγελμα δεν έχει καν μητρώο»*
 * *(ελαιοχρωματιστής · πλακάς)* **ΔΕΝ είναι κατάσταση του ανθρώπου** — είναι
 * ιδιότητα του **επαγγέλματος**, και ζει στο `config/isco-registry-authority.ts`.
 * Χωθμένο εδώ θα ισοπέδωνε δύο **ασύμβατα** πράγματα: τον ελαιοχρωματιστή που
 * **δεν έχει** πού να γραφτεί, και τον δικηγόρο που **έχει** και **σιωπά**.
 */
export type AttestationState = 'unknown' | 'declared' | 'verified';

/**
 * Τι κρατά το **έγγραφο** για την απόδειξη ενός ανθρώπου.
 *
 * ⚠️ **Το `state` ΔΕΝ αποθηκεύεται ανεξάρτητα από το `registration`.** Τα δύο
 * πεδία μαζί έχουν **μία** νόμιμη ανάγνωση, και η ένωση την επιβάλλει: δεν
 * υπάρχει `declared` χωρίς ζεύγος, ούτε ζεύγος με `unknown`. Δύο ανεξάρτητα
 * πεδία θα επέτρεπαν `{ state: 'verified', registration: null }` — «επαληθευμένο
 * τίποτα».
 */
export type ProfessionalAttestation =
  /** Κανείς δεν δήλωσε. **Σιωπή, όχι άρνηση.** */
  | { readonly state: 'unknown' }
  /** Δηλώθηκε ζεύγος· **καμία** επαλήθευση. Η **συνηθισμένη** κατάσταση σήμερα. */
  | { readonly state: 'declared'; readonly registration: ProfessionalRegistration }
  /**
   * Ρωτήθηκε η αρχή.
   *
   * ⚠️ **ΥΠΟΔΟΧΗ, ΟΧΙ ΥΛΟΠΟΙΗΣΗ** *(ADR-841 Α9.3 · ADR-798 §7)*. Καμία αυτόματη
   * επαλήθευση σήμερα — καμία σύνδεση με ΤΕΕ/ΔΣΑ. Το σχήμα του attestation
   * *(εκδότης · λήξη · ανάκληση)* ακολουθεί **W3C VC 2.0 / EUDI QEAA** όταν έρθει.
   * ⛔ **ΜΗΝ** το γεμίσεις με χειροκίνητη έγκριση διαχειριστή: θα ήταν «κάποιος
   * το κοίταξε» ντυμένο ως «η αρχή το βεβαίωσε», και η οθόνη λέει το δεύτερο.
   */
  | { readonly state: 'verified'; readonly registration: ProfessionalRegistration };
