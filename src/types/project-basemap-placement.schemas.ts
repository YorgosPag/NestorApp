/**
 * ADR-782 §24 — Το **μόνιμο** σχήμα της χειροκίνητης τοποθέτησης υποβάθρου.
 *
 * ## 🔴 Γιατί ΞΕΧΩΡΙΣΤΟ αρχείο και όχι δίπλα στο `basePoint`
 * Το `project-elevation.schemas.ts` κρατά το **γεωδαιτικό** λεξιλόγιο του ADR-369 (survey point,
 * base point, north rotation) — πεδία που διαβάζονται από τοπογραφικά παραδοτέα, πίνακες
 * συντεταγμένων και εξαγωγή IFC. Η **απόφαση Giorgio 2026-08-10 (ADR-782 §23.1)** είναι ότι η
 * χειροκίνητη τοποθέτηση **ΠΟΤΕ** δεν γίνεται επίσημη γεωαναφορά: πιάνει μόνο για να κάθεται
 * σωστά ο χάρτης στην οθόνη.
 *
 * Ένα σχήμα γραμμένο δύο γραμμές κάτω από το `ProjectBasePointSchema`, με **ίδια ονόματα πεδίων**,
 * θα ήταν πρόσκληση: ο επόμενος που θα ήθελε «να το κάνει επίσημο» θα το έκανε με μια ανάθεση που
 * θα περνούσε τον μεταγλωττιστή. Εδώ **δεν** μπορεί: τα ονόματα (`eastingM`/`northingM`) δεν
 * ταιριάζουν με κανένα πεδίο του `ProjectBasePoint` (`x`/`y`/`z`), άρα η προαγωγή απαιτεί να
 * γραφτεί **ρητά** — και τότε φαίνεται.
 *
 * ## Μονάδες — ΜΕΤΡΑ στο έγγραφο, canonical mm στο runtime
 * Ίδια σύμβαση με το ADR-369: γεωδαιτικές συντεταγμένες γράφονται σε μέτρα, όπως τις γράφει ο
 * τοπογράφος. Η μετατροπή ζει σε **καθαρό** module
 * (`subapps/dxf-viewer/systems/basemap/basemap-placement-schema.ts`), ποτέ στο I/O.
 *
 * ⚠️ Τα ονόματα κουβαλούν τη **μονάδα** (`…M`) επίτηδες. Το runtime `GeoReference` έχει
 * `originWorld.x/y` σε **χιλιοστά**· αν το έγγραφο χρησιμοποιούσε το ίδιο μονοπάτι με άλλη μονάδα,
 * μια ανάθεση χωρίς μετατροπή θα περνούσε σιωπηλά και θα τοποθετούσε τον χάρτη **1000× μακριά**.
 *
 * ## Πού επιβάλλεται
 * **Στην εγγραφή**, από το `ProjectUpdateSchema` του `PATCH /api/projects/{id}`. Εκείνο το σχήμα
 * είναι `.passthrough()`, άρα ένα αδήλωτο πεδίο θα περνούσε **χωρίς κανένα όριο και χωρίς ίχνος
 * στο συμβόλαιο** — ακριβώς αυτό που το ADR-759 Φ3 απαγόρευσε γραπτά στο ίδιο αρχείο.
 *
 * ⚠️ Στην **ανάγνωση** δεν επιβάλλεται, και είναι σκόπιμο: ένα κατεστραμμένο ή παλιό έγγραφο δεν
 * επιτρέπεται να ρίξει τον viewer. Ο αναγνώστης κάνει αμυντικούς ελέγχους και επιστρέφει `null`
 * (= «κανείς δεν τοποθέτησε τίποτα»), όπως ο δίδυμος `geoReferenceFromProject`.
 *
 * @see ../subapps/dxf-viewer/systems/basemap/basemap-placement-schema.ts — η καθαρή μετατροπή
 * @see ./project-elevation.schemas.ts — το γεωδαιτικό λεξιλόγιο που ΔΕΝ αγγίζεται από εδώ
 */

import { z } from 'zod';

/**
 * Λογικό φράγμα μεγέθους σε **μέτρα**. Το ΕΓΣΑ'87 τοποθετεί την Ελλάδα σε easting ~100–1.000 km
 * και northing ~3.800–4.700 km, άρα το ±10.000 km αφήνει τρεις τάξεις μεγέθους περιθώριο και
 * ταυτόχρονα αποκλείει τιμές που δεν είναι σημείο της Γης (π.χ. ένα σύρσιμο που ξέφυγε).
 *
 * ⚠️ Το `.finite()` από μόνο του δέχεται το `1e300`. Ένα πεδίο που περνά «γιατί δεν είναι NaN»
 * είναι το ίδιο σχήμα με το πεδίο που περνά «γιατί δεν το κοιτάζει κανείς».
 */
const MAX_ABS_METRES = 1e7;

/**
 * Η χειροκίνητη τοποθέτηση υποβάθρου, όπως ζει στο `projects/{id}.basemapPlacement`.
 *
 * Περιγράφει **πού κάθεται η τοπική αρχή (0,0) του σχεδίου πάνω στη Γη, για τον χάρτη** — και
 * τίποτε άλλο. Δεν είναι, και δεν επιτρέπεται ποτέ να γίνει, η γεωαναφορά του έργου.
 */
export const ProjectBasemapPlacementSchema = z
  .object({
    /** ΜΕΤΡΑ — ΕΓΣΑ'87 easting της τοπικής αρχής (0,0) του σχεδίου. */
    eastingM: z.number().finite().min(-MAX_ABS_METRES).max(MAX_ABS_METRES),
    /** ΜΕΤΡΑ — ΕΓΣΑ'87 northing της τοπικής αρχής (0,0) του σχεδίου. */
    northingM: z.number().finite().min(-MAX_ABS_METRES).max(MAX_ABS_METRES),
    /** ΜΟΙΡΕΣ — στροφή τοπικό → κόσμος, ίδια σύμβαση με το `northRotation` του ADR-369. */
    rotationDeg: z.number().finite().min(-360).max(360),
  })
  .strict();

export type ProjectBasemapPlacement = z.infer<typeof ProjectBasemapPlacementSchema>;
