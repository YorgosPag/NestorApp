/**
 * **Ποιος γράφει, και για λογαριασμό ποιου** — τα πεδία που **δεν** συντάσσει η φόρμα
 * του ακινήτου.
 *
 * 🔑 **Ίδιο σχήμα, ίδιο όνομα με το `DemandAuthorship`** της ζήτησης, και είναι
 * σκόπιμο: όταν δύο διαδρομές γραφής απαντούν την **ίδια** ερώτηση, ένα δεύτερο
 * λεξιλόγιο θα τις έκανε να μοιάζουν διαφορετικές ενώ δεν είναι.
 */
export interface OwnerPropertyAuthorship {
  readonly id: string;
  readonly authorUserId: string;
  readonly authorCompanyId: string | null;
  /** Δες {@link OwnerProperty.mandates} — κενός πίνακας = ο ιδιώτης μόνος του. */
  readonly mandates: readonly BrokeredListingMandate[];
}

/**
 * Προσχέδιο + **γραφέας** → έγγραφο.
 *
 * ⚠️ Ζει εδώ και όχι στην υπηρεσία, ώστε **τα πεδία που δεν είναι απαντήσεις του
 * ανθρώπου** (ταυτότητα · χρόνος · κύκλος ζωής) να γεννιούνται σε **ένα** σημείο.
 * Γραμμένο στη διαδρομή API, θα ξαναγραφόταν σε κάθε δεύτερο γραφέα — και οι δύο θα
 * «δούλευαν».
 *
 * 🔑 **`lifecycle: 'listed'` από τη γέννηση**, και είναι η **απόφαση Giorgio
 * 2026-08-11** σε μία λέξη: καμία ουρά, καμία ενδιάμεση κατάσταση. Ό,τι πέρασε τα
 * invariants **είναι** στην αγορά.
 *
 * ⚠️ **Και αυτό ΔΕΝ αλλάζει για τον μεσίτη.** Μια αγγελία γραφείου με εντολή σε
 * αναμονή γεννιέται κι εκείνη `listed` — απλώς **δεν φτάνει στον κόσμο**, γιατί το
 * {@link isOwnerPropertyOnTheMarket} λέει `false`. Μια δεύτερη κατάσταση κύκλου ζωής
 * («σε αναμονή έγκρισης») θα ήταν **δεύτερη απάντηση** στο «είναι δημόσιο;» — και το
 * §8.16 έχει ήδη μετρήσει και απορρίψει την ουρά έγκρισης.
 */
export function newOwnerProperty(
  draft: OwnerPropertyDraft,
  authorship: OwnerPropertyAuthorship,
): OwnerProperty {
  const now = nowISO();
  return {
    id: authorship.id,
    authorUserId: authorship.authorUserId,
    authorCompanyId: authorship.authorCompanyId,
    mandates: authorship.mandates,
    // ⚠️ **Παράγεται, ποτέ δεν δηλώνεται** — δες `OwnerProperty.mandatesExpireAt`.
    mandatesExpireAt: nextMandateExpiry(authorship.mandates),
    ...draft,
    lifecycle: 'listed',
    createdAt: now,
    updatedAt: now,
  };
}
