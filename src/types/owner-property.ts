/** `true` αν το `value` είναι γνωστός κύκλος ζωής καταχώρησης. */
export function isOwnerPropertyLifecycle(
  value: unknown,
): value is OwnerPropertyLifecycle {
  return (
    typeof value === 'string' &&
    (OWNER_PROPERTY_LIFECYCLES as readonly string[]).includes(value)
  );
}

/** `true` αν ο **κύκλος ζωής** της καταχώρησης δεν την έχει αποσύρει. */
export function isLiveOwnerProperty(property: OwnerProperty): boolean {
  return (LIVE_OWNER_PROPERTY_LIFECYCLES as readonly string[]).includes(
    property.lifecycle,
  );
}

/**
 * 🔴 **ΕΙΝΑΙ ΑΥΤΗ Η ΑΓΓΕΛΙΑ ΣΤΗΝ ΑΓΟΡΑ;** — οι **δύο** ερωτήσεις μαζί, μία φορά.
 *
 * Η καταχώρηση φτάνει στον κόσμο μόνο όταν **ο κάτοχος δεν την απέσυρε** *και* **η
 * εντολή επιτρέπει δημοσίευση** (ο ιδιοκτήτης είπε «ναι» και η εντολή δεν έχει λήξει).
 *
 * ⚠️ **Γι' αυτό γράφεται ΕΔΩ και όχι στον γραφέα της προβολής.** Το
 * `owner-property-projection.ts` δηλώνει ρητά ότι *«δύο τόποι που απαντούν «είναι
 * δημόσιο;» θα διαφωνούσαν»* — και ότι θα διαφωνούσαν **ακριβώς στην αντιπαροχή**. Ο
 * γραφέας συνεχίζει να μη ρωτά· απλώς παίρνει **καμία διάθεση** όταν η απάντηση εδώ
 * είναι `false`, και ο υπάρχων κώδικας σβήνει την προβολή μόνος του.
 *
 * @param nowISOValue — η **περασμένη** στιγμή του περάσματος προβολής, ποτέ ρολόι
 *   διαβασμένο εδώ μέσα (δες `isMandateExpired`).
 */
export function isOwnerPropertyOnTheMarket(
  property: OwnerProperty,
  nowISOValue: string,
): boolean {
  return (
    isLiveOwnerProperty(property) &&
    // 🔑 **Καμία εντολή = ο ιδιώτης μόνος του ⇒ δημοσιεύεται.** Ήταν το σκέλος `self`
    //    του `mandateAllowsPublication`, και η σημασιολογία μένει **ταυτόσημη**: μία
    //    τουλάχιστον ζωντανή εντολή, ή καμία καθόλου. Ό,τι έχει **μόνο** ληγμένες ή
    //    ανακληθείσες εξακολουθεί να **μην** φτάνει στον κόσμο.
    (mandatesOf(property).length === 0 || hasAnyActiveMandate(mandatesOf(property), nowISOValue))
  );
}

/**
 * **Ποιος δηλώνει αυτή την αγγελία, ως κλάση** — από την εντολή, ποτέ χειροκίνητα.
 *
 * 🔴 **Εδώ αποκτά ο πρώτος του καταναλωτή το {@link LISTING_AUTHORSHIPS}**, που από τις
 * 2026-08-11 ήταν **μοντελοποιημένο και ανενεργό**: μετρημένο στο §8.33, οι μόνες δύο
 * αναφορές του σε όλο το `src/` ήταν ο **ορισμός του** και ο τύπος του — *φρουρός
 * χωρίς απόδειξη ζωής* (ADR-749 §5).
 *
 * ⚠️ **ΠΑΡΑΓΩΓΟ, ΠΟΤΕ ΠΕΔΙΟ.** Ένα εγγράψιμο `authorship` δίπλα στο `mandate` θα ήταν
 * **δεύτερη αλήθεια** για το ίδιο γεγονός — και θα απέκλινε την πρώτη φορά που κάποιος
 * έγραφε το ένα χωρίς το άλλο. Ίδιο σκεπτικό με το `commercialStatus` της **Α20**.
 */
export function listingAuthorshipOf(
  mandates: readonly BrokeredListingMandate[],
): ListingAuthorship {
  // ⚠️ **ΟΠΟΙΑΔΗΠΟΤΕ εντολή, όχι μόνο ζωντανή** — και είναι η παλιά σημασιολογία
  //    αυτούσια (`kind === 'brokered'` δεν ρωτούσε λήξη). Το ερώτημα είναι *«ποιος
  //    **δηλώνει** αυτή την αγγελία»*: μια εντολή που έληξε χθες δεν κάνει την
  //    αγγελία ξαφνικά «γραμμένη από τον ιδιοκτήτη».
  return mandates.length > 0 ? 'agency' : 'owner-declared';
}

/** Τα **ζωντανά** είδη διάθεσης της καταχώρησης. */
export function ownerPropertyOfferKinds(
  property: Pick<OwnerProperty, 'offers'>,
): OfferKind[] {
  const kinds = new Set<OfferKind>();
  for (const offer of property.offers) {
    if (isLiveOffer(offer)) kinds.add(offer.kind);
  }
  return [...kinds].sort();
}

/** Τα πεδία που η φόρμα συντάσσει — **χωρίς** ταυτότητα, κάτοχο, ή χρόνο. */
export type OwnerPropertyDraft = Pick<
  OwnerProperty,
  'type' | 'areaSqm' | 'offers' | 'place' | 'floor' | 'bedrooms' | 'media' | 'title'
>;

