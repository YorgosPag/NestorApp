/**
 * **Το ακίνητο όπως το δηλώνει αυτός που το βάζει στην αγορά.** Επίπεδο Β, ιδιωτικό
 * **ανά άνθρωπο**.
 *
 * ⚠️ **Ό,τι φτάνει στον κόσμο είναι η ΠΡΟΒΟΛΗ** (`public_listings`), όχι αυτό το
 * έγγραφο. Το `label` της θέσης, το `authorUserId`, τα `media` **δεν** ταξιδεύουν —
 * γιατί δεν υπάρχουν στο κλειστό σχήμα της προβολής.
 */
export interface OwnerProperty {
  /** Enterprise id (`ownp_*`) — N.6, **ποτέ** `addDoc`. */
  readonly id: string;

  /**
   * Το uid που **έγραψε** την αγγελία. **ΑΜΕΤΑΒΛΗΤΟ** — κανόνας Firestore **και** τύπος.
   *
   * 🔴 **ΜΕΤΟΝΟΜΑΣΤΗΚΕ ΑΠΟ `ownerUserId` ΣΤΟ §8.33, ΚΑΙ ΗΤΑΝ ΔΙΟΡΘΩΣΗ ΨΕΜΑΤΟΣ.** Το
   * παλιό όνομα ήταν σωστό όσο ο μόνος γραφέας ήταν ο ίδιος ο ιδιοκτήτης. Από τη
   * στιγμή που **γράφει και ο μεσίτης**, «κάτοχος» θα σήμαινε τον υπάλληλο του
   * γραφείου — δηλαδή ένα πεδίο που λέει `owner` και δείχνει σε κάποιον που **δεν
   * κατέχει τίποτα**. Ποιανού είναι το ακίνητο το λέει πλέον το {@link OwnerProperty.mandate},
   * που είναι **η ερώτηση που πραγματικά ρωτούσε κανείς**.
   *
   * ⚠️ **Το `firestore-field-constants.ts` επιχειρηματολογούσε ΕΝΑΝΤΙΑ σε αυτή τη
   * μετονομασία**, και ο λόγος του ήταν *«ένα κοινό όνομα θα έκανε τη μελλοντική ροή
   * του μεσίτη να **μοιάζει ήδη λυμένη**»*. Ίσχυε — και **έπαψε να ισχύει τη μέρα που
   * η ροή λύθηκε**. Το κόστος μετρήθηκε πριν αλλάξει τίποτα: **0 έγγραφα** στο
   * `owner_properties` της ζωντανής βάσης ⇒ **καμία μετανάστευση**.
   *
   * 🔑 **Είναι το πεδίο απομόνωσης — και μένει ΕΝΑ.** Το `tenant-config.ts` γράφει
   * ρητά ότι *«δύο άξονες απομόνωσης για ένα έγγραφο σημαίνει **δύο απαντήσεις** στο
   * “ποιος το βλέπει;”»*. Το γραφείο **δεν** είναι δεύτερος άξονας· δες
   * {@link OwnerProperty.authorCompanyId}.
   */
  readonly authorUserId: string;

  /**
   * Η εταιρεία υπό την οποία ενήργησε ο συγγραφέας. `null` για ιδιώτη.
   *
   * ⚠️ **Δεν είναι δεύτερο πεδίο απομόνωσης. Είναι ΑΠΟΔΟΣΗ** — ίδια λέξη, ίδιος
   * λόγος με το `PropertyDemand.authorCompanyId`: απαντά *«ποιο γραφείο το
   * κατέγραψε»*, ώστε ο κατάλογος του γραφείου να **επιβιώνει όταν ο υπάλληλος
   * φύγει**.
   *
   * 🔑 **Και αυτό είναι ο κανόνας της ίδιας της αγοράς, όχι δική μας επιλογή:** στο
   * MLS *«listings belong to the **broker**, not the agent»* — όταν ο υπάλληλος
   * αλλάξει γραφείο, οι αγγελίες **μένουν**, και μόνο ο ιδιοκτήτης του γραφείου
   * μπορεί να τις μεταφέρει, **γραπτώς**.
   */
  readonly authorCompanyId: string | null;

  /**
   * **Ποιανού είναι** — και δεν είναι πάντα αυτός που την έγραψε.
   *
   * 🔴 **Εδώ κλείνει το δηλωμένο κενό #3** που αυτό το αρχείο κουβαλούσε από τις
   * 2026-08-11: *«ο μεσίτης… η ροή του είναι άλλη οθόνη… γι' αυτό δεν υπάρχει καν
   * πεδίο `mandate`: μια σταθερά σε πεδίο είναι φρουρός που δεν πυροδοτεί»*. Ο λόγος
   * ήταν σωστός **και προσωρινός**: πλέον το πεδίο **πυροδοτεί**, γιατί υπάρχει
   * διαδρομή που γράφει `brokered`.
   *
   * ────────────────────────────────────────────────────────────────────────
   * 🔴 ΠΛΗΘΥΝΤΙΚΟΣ, ΚΑΙ ΗΤΑΝ ΕΝΙΚΟΣ ΩΣ ΤΙΣ 2026-08-30 (ADR-832)
   * ────────────────────────────────────────────────────────────────────────
   *
   * Ο ενικός **δεν ήταν απλοποίηση — ήταν σιωπηλή απαγόρευση**. Το λεξιλόγιο του
   * RESO που το έργο υιοθέτησε περιέχει την **απλή εντολή** (`OPEN_LISTING`), που
   * ορίζεται *«σε οποιονδήποτε αριθμό γραφείων»*· με **ένα** πεδίο, η δεύτερη
   * ανάθεση ήταν **δομικά αδύνατη**, και ο μόνος έλεγχος
   * (`mandate.kind !== 'self'`) την απέρριπτε **χωρίς να ρωτήσει το είδος**. Η
   * λέξη «Απλή» στην οθόνη δεν είχε καμία συνέπεια.
   *
   * 🔑 **Κενός πίνακας ΕΙΝΑΙ το παλιό `self`** — καμία τιμή-φρουρός. Ο ιδιώτης που
   * γράφει το σπίτι του δεν έχει «εντολή τύπου εαυτός»· **δεν έχει εντολή**. Το
   * `{ kind: 'self' }` ήταν sentinel για κατάσταση που εκφράζεται με απουσία, και
   * η απουσία δεν χρειάζεται όνομα.
   *
   * ⚠️ **ΜΗΝ διαβάσεις αυτόν τον πίνακα ωμό.** Το *«ποια ισχύει τώρα»* το απαντούν
   * οι επιλογείς {@link activeMandates} / {@link activeMandateFor} — ζωντανή
   * σημαίνει **εγκεκριμένη ∧ άρχισε ∧ δεν έληξε ∧ το γραφείο επιτρέπεται**, και
   * χειρόγραφο `filter` σε σημείο χρήσης θα ξεχνούσε τα μισά.
   */
  readonly mandates: readonly BrokeredListingMandate[];

  /**
   * **Η πρώτη λήξη ανάμεσα στις δεσμευτικές εντολές** — `null` όταν δεν υπάρχει καμία.
   *
   * 🔴 **ΠΕΔΙΟ-ΕΥΡΕΤΗΡΙΟ, ΠΟΤΕ ΠΗΓΗ ΑΛΗΘΕΙΑΣ.** Υπάρχει **μόνο** επειδή το Firestore
   * δεν κάνει ανισότητα σε πεδίο μέσα σε πίνακα αντικειμένων, και ο σαρωτής λήξης
   * χρειάζεται να **βρει** τα έγγραφα. Παράγεται από το {@link nextMandateExpiry} και
   * γράφεται **στην ίδια συναλλαγή** με το {@link OwnerProperty.mandates} — ένας
   * γραφέας, καμία απόκλιση δυνατή.
   *
   * ⛔ **ΜΗΝ το ρωτήσεις «έληξε;»** — αυτό το απαντά το `isMandateExpired` πάνω στην
   * ίδια την εντολή. Δεύτερος κριτής εδώ θα ήταν, κατά γράμμα, ADR-749.
   */
  readonly mandatesExpireAt: string | null;

  // ── §25.6: ΕΙΔΟΣ + ΕΜΒΑΔΟΝ ────────────────────────────────────────────────
  readonly type: PropertyType;
  /** Μικτό εμβαδόν σε m². `null` = **δεν καταχωρήθηκε**, ποτέ `0` ως «άγνωστο». */
  readonly areaSqm: number | null;

  // ── §25.6: ΔΙΑΘΕΣΕΙΣ + ΤΙΜΗ (Α20 · Α22) ───────────────────────────────────
  /**
   * **Οι διαθέσεις — το ΥΠΑΡΧΟΝ SSoT, αυτούσιο.**
   *
   * 🔑 Η **αντιπαροχή δεν χρειάστηκε καμία επινόηση**: το `ExchangeOffer` υπάρχει ήδη
   * με **ΠΟΣΟΣΤΟ** (όχι τιμή), και το `OFFER_KINDS` την ονομάζει από την Α20. Ένα
   * τέταρτο λεξιλόγιο εδώ θα ήταν το σχήμα του ADR-749.
   *
   * ⚠️ Η **τιμή ζει μέσα στη διάθεση**, όχι δίπλα της: το `percentage` πάνω σε πώληση
   * είναι **αδύνατο να εκφραστεί**, όχι «απαγορευμένο από σχόλιο».
   */
  readonly offers: readonly PropertyOffer[];

  // ── §25.6: ΘΕΣΗ ───────────────────────────────────────────────────────────
  readonly place: OwnerPropertyPlace;

  // ── §25.6: +2 ΕΙΔΙΚΑ ──────────────────────────────────────────────────────
  /** Όροφος. `null` = δεν καταχωρήθηκε· **`0` είναι ισόγειο**, υπαρκτή τιμή. */
  readonly floor: number | null;
  /** Υπνοδωμάτια. `null` = δεν καταχωρήθηκε· **`0` = γκαρσονιέρα**, υπαρκτή τιμή. */
  readonly bedrooms: number | null;

  // ── §25.6: ΦΩΤΟΓΡΑΦΙΑ / ΚΑΤΟΨΗ ────────────────────────────────────────────
  readonly media: readonly OwnerPropertyMedia[];

  // ── ΤΙΤΛΟΣ ────────────────────────────────────────────────────────────────
  /** Κείμενο **του ανθρώπου** — όχι κλειδί i18n (N.11 εξαίρεση: δεδομένο, όχι διεπαφή). */
  readonly title: string;

  // ── ΚΥΚΛΟΣ ΖΩΗΣ ───────────────────────────────────────────────────────────
  readonly lifecycle: OwnerPropertyLifecycle;

  // ── ΧΡΟΝΟΣ ────────────────────────────────────────────────────────────────
  /**
   * **Τι απέγινε η δημόσια προβολή στην τελευταία γραφή** — γεγονός, όχι πρόβλεψη.
   *
   * 🔴 **Η ΥΠΟΣΧΕΣΗ ΗΤΑΝ ΓΡΑΜΜΕΝΗ ΚΑΙ ΔΕΝ ΤΗΝ ΤΗΡΟΥΣΕ ΚΑΝΕΙΣ.** Το
   * `publish-public-listing.ts` γράφει κατά λέξη ότι επιστρέφει `'failed'`
   * *«ονομαστικά **ώστε ο καλών να το καταγράψει** και η επανασύνθεση να το
   * διορθώσει — που είναι η διαφορά ανάμεσα σε «σιωπηλά μπαγιάτικο» και «γνωστά
   * εκκρεμές»»*. **Κανείς δεν το κατέγραφε** (μετρημένο 2026-08-27): κάθε αποτυχία
   * ζούσε **μόνο** σε μια γραμμή καταγραφής, ο κάτοχος έβλεπε «η αγγελία είναι στον
   * δημόσιο χάρτη» ενώ δεν ήταν, και **κανείς δεν μπορούσε να βρει ποιες
   * χρειάζονται επανασύνθεση**. Ίδια κλάση με το `as` του συνόρου: η **περιγραφή**
   * της εγγύησης υπήρχε, ο **μηχανισμός** όχι.
   *
   * 🔑 **ΓΙΑΤΙ ΔΕΝ ΑΡΚΕΙ Η ΚΑΘΑΡΗ ΣΥΝΑΡΤΗΣΗ.** Το {@link isPubliclyListed} απαντά
   * *«**ΔΙΚΑΙΟΥΤΑΙ** να είναι στον χάρτη;»* — **πρόβλεψη** από την οντότητα. Αυτό
   * απαντά *«**ΕΦΤΑΣΕ** εκεί;»* — **γεγονός** από τη γραφή. Συμπίπτουν σχεδόν
   * πάντα· όπου **διαφέρουν**, το γεγονός νικά. Δες `ownerListingVisibility`.
   *
   * ⚠️ **Προαιρετικό, και η απουσία έχει ΡΗΤΗ σημασία**: *«γράφτηκε πριν υπάρξει
   * αυτό το πεδίο»*, ποτέ *«δεν δημοσιεύτηκε»*. **Καμία** αγγελία που υπάρχει
   * σήμερα στη βάση δεν το έχει — ένα υποχρεωτικό πεδίο θα έλεγε ψέματα για τα
   * δεδομένα που όντως φτάνουν, και ο μεταγλωττιστής θα έκρυβε την περίπτωση.
   * *(Ίδιο σκεπτικό με το `globalRole: string` του `CapabilitySubject`, ADR-801.)*
   */
  readonly publication?: OwnerPropertyPublication;

  readonly createdAt: string;
  readonly updatedAt: string;
}

/**
 * **Το αποτύπωμα της τελευταίας απόπειρας δημοσίευσης.**
 *
 * ⚠️ **Κρατά τη στιγμή, και δεν είναι διακόσμηση**: χωρίς αυτήν, ένα `'failed'`
 * δεν ξεχωρίζει από `'failed'` **πριν από τρεις μήνες** — δηλαδή δεν μπορεί να
 * απαντήσει *«είναι ακόμη εκκρεμές;»* μετά από επανασύνθεση.
 */
export interface OwnerPropertyPublication {
  readonly outcome: PublishOutcome;
  /** ISO — **η ίδια στιγμή** που έφερε το `projectedAt` της προβολής. */
  readonly at: string;
}

/**
 * 🔶 **ΔΗΛΩΜΕΝΑ ΚΕΝΑ, ΜΕ ΟΝΟΜΑ ΚΑΙ ΛΟΓΟ ΓΙΑ ΤΟ ΚΑΘΕΝΑ.**
 *
 * | # | Τι λείπει | Γιατί ΔΕΝ γράφτηκε εδώ |
 * |---|---|---|
 * | 1 | **Νομιμότητα + προέλευση** (4ο βασικό του §25.6) | Η **Α17** την ορίζει ως *«κλίμακα με προέλευση»* — δικό της SSoT με δικό του λεξιλόγιο. Το `types/public-listing.ts` δηλώνει το **ίδιο** κενό με τα **ίδια** λόγια (*«ΜΗΝ το επινοήσεις εδώ»*), και μετρήθηκε ότι **δεν υπάρχει καθόλου** στον κώδικα. Δύο τόποι που το επινοούν = δύο κλίμακες |
 * | 2 | **Δημόσια θέαση των `media`** | **Κανόνας 31** (Α19): ο πρώτος καρές παράγεται από το **μοντέλο**, ποτέ από ανέβασμα. Το `PublicListing` έχει **μόνο** `coverImage` και **καμία** συλλογή εικόνων· προσθήκη πεδίου εκεί είναι **απόφαση δημοσιοποίησης** (γραμμένο στο ίδιο το αρχείο), όχι λεπτομέρεια υλοποίησης |
 * | ~~3~~ | ~~**Ο μεσίτης**~~ | ✅ **ΕΚΛΕΙΣΕ στο §8.33.** Η ροή είναι πράγματι **άλλη οθόνη**, στον χώρο του γραφείου· το μοντέλο της ζει στο {@link ./owner-property-mandate} και το πεδίο {@link OwnerProperty.mandate} **πυροδοτεί** πλέον |
 */
export type OwnerPropertyOpenGaps = never;

