/**
 * Πού είναι το ακίνητο, **όπως το απάντησε ο κάτοχος**.
 *
 * 🔴 **ΔΥΟ καταστάσεις, και η δεύτερη είναι ΕΓΚΥΡΗ ΑΠΑΝΤΗΣΗ — όχι κενό.** Η **Α5 §3**
 * λύνει την αντίφαση §21.4 ↔ §25.6 ακριβώς έτσι: η φόρμα **πάντα ρωτά** (άρα η θέση
 * είναι υποχρεωτικό πεδίο), και το «**δεν θέλω να το πω τώρα**» είναι απάντηση (άρα
 * το σκαλοπάτι 0 δεν είναι λάθος).
 *
 * ⚠️ **Χωρίς αυτή την ένωση, η διάκριση θα ήταν ΜΗ ΠΑΡΑΤΗΡΗΣΙΜΗ.** Το
 * `types/public-listing.ts` ξεχωρίζει `never-asked` (**δικό μας** χρέος) από
 * `owner-declined` (**επιλογή** του χρήστη) — και δηλώνει ρητά ότι *«κανένας γραφέας
 * δεν υπάρχει σήμερα»* για το δεύτερο. **Αυτός ο τύπος είναι ο γραφέας.** Μια φόρμα
 * που ρώτησε και μια φόρμα που δεν ρώτησε ποτέ θα κατέληγαν αλλιώς στο **ίδιο**
 * έγγραφο.
 *
 * 🔑 Η διάκριση **δεν είναι λεκτική**: το `never-asked` έχει **θεραπεία με ένα κλικ**
 * (Α5 §4.3 — *«το γέμισμα της θέσης είναι το δόλωμα, ποτέ το φράγμα»*)· το
 * `owner-declined` **δεν έχει**, και να ζητάς διόρθωση για κάτι που ο κάτοχος
 * **αποφάσισε** είναι παρενόχληση.
 */
export type OwnerPropertyPlace =
  | {
      readonly kind: 'declared';
      /** Το σημείο στον χάρτη. */
      readonly point: GeoPoint;
      /**
       * Το κείμενο που έδωσε ο άνθρωπος — **προς εμφάνιση στη δική του οθόνη**.
       *
       * ⛔ **ΔΕΝ ταξιδεύει στη δημόσια προβολή**: το κλειστό σχήμα του
       * `PublicListing` δεν έχει διεύθυνση, και *«ό,τι δεν είναι γραμμένο εκεί, δεν
       * φεύγει ποτέ»*. Μια διεύθυνση σε ελεύθερο κείμενο είναι, στην Ελλάδα,
       * συχνά **ταυτοποιήσιμο πρόσωπο**.
       */
      readonly label: string;
      /**
       * 🔑 **Η ΠΡΟΕΛΕΥΣΗ ΣΥΝΑΓΕΤΑΙ ΑΠΟ ΤΑ ΙΔΙΑ ΤΑ ΔΕΔΟΜΕΝΑ**, ίδιος κανόνας με το
       * `addressToPositionCandidate`: υπάρχει `accuracy` ⇒ **μηχανή** το συμπέρανε
       * από κείμενο (`geocoded`, και **κουβαλά την ακρίβειά της** — ολόκληρη η Α5)·
       * `null` ⇒ κάποιος **έβαλε** το σημείο (`manual`).
       *
       * ⚠️ **Το δεύτερο ΔΕΝ βαφτίζεται `geocoded` με `accuracy: 'center'`** — θα ήταν
       * εύκολο και θα ήταν **ψέμα προς την ασφαλή κατεύθυνση**: θα ζωγράφιζε σκιασμένη
       * πόλη εκεί που άνθρωπος έδειξε ακριβές σημείο, δηλαδή θα **έκρυβε** γνώση.
       */
      readonly accuracy: GeocodingAccuracy | null;
      /**
       * 🔴 **ΣΕ ΠΟΙΟ ΠΡΑΓΜΑ ΤΟΥ ΕΠΙΠΕΔΟΥ Α ΑΝΗΚΕΙ** — και αυτό είναι που κάνει τη
       * ζήτηση και την προσφορά να **συναντιούνται** (§14.5).
       *
       * ⚠️ **Ζει ΜΕΣΑ στον κλάδο `declared`, και η θέση του είναι σχεδίαση.** Ένα
       * `declined` που κουβαλούσε δεσμό θα ήταν **αντίφαση**: το να δείξεις δημόσιο
       * κτίριο **είναι** αποκάλυψη θέσης — ακριβέστερη μάλιστα από μια διεύθυνση.
       * Εδώ μέσα, ο συνδυασμός «*δεν λέω πού είναι*» + «*είναι αυτό το κτίριο*»
       * **δεν μεταγλωττίζεται**.
       *
       * ⚠️ **Ισχυρισμός, όχι επαληθευμένο γεγονός** (§14.3): *«μπορεί να κατέχει
       * ακίνητο **μέσα** σε αυτό — και αυτό είναι ισχυρισμός μέχρι να επαληθευτεί
       * (τίτλος/ΑΤΑΚ)»*. Μένει στο **επίπεδο Β** και **δεν** αγγίζει το κοινό Α: ο
       * κάτοχος δεν αποκτά κανένα δικαίωμα πάνω στο κτίριο επειδή έδειξε προς αυτό.
       */
      readonly link: PlaceRef | null;
    }
  | {
      readonly kind: 'declined';
    };

