/**
 * @fileoverview **Η ΠΡΟΣΦΟΡΑ ΤΟΥ ΙΔΙΩΤΗ** — το ακίνητο όπως το δηλώνει ο ίδιος ο κάτοχός του (Α14).
 * @related ADR-777 §7 (Α12 · Α14 · Α20 · Α22) · §8.16 · SPEC-777A §14.2 · types/property-demand.ts
 * @module types/owner-property
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΗ ΟΝΤΟΤΗΤΑ ΑΠΟ ΤΟ `properties` — **ΜΕΤΡΗΘΗΚΕ, ΔΕΝ ΠΡΟΤΙΜΗΘΗΚΕ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ερώτημα ήταν *«πού ζει η γραφή του ιδιώτη;»*, και είχε **τρεις** υποψήφιους
 * δρόμους. Μετρήθηκαν και οι τρεις **πριν** γραφτεί γραμμή:
 *
 * | Δρόμος | Τι λέει ο ΚΩΔΙΚΑΣ, όχι η προτίμηση |
 * |---|---|
 * | **ψευδο-εταιρεία ανά χρήστη** | Το `assertPropertyCreatePolicy` απαιτεί `projectId` **ΠΑΝΤΑ** (ADR-284 §3.1)· το `assertUpstreamChainExists` απαιτεί **Project → linkedCompanyId → Company** να **υπάρχουν**· και η οικογένεια Α (διαμέρισμα) απαιτεί επιπλέον `buildingId` + `floorId`. ⇒ **τέσσερα** συνθετικά έγγραφα για ένα διαμέρισμα, καθένα ορατό σε καταλόγους εταιρειών/έργων και στο `republishListingsForProject` |
 * | **δεύτερο πεδίο απομόνωσης στο `properties`** | Ο τύπος `TenantFieldConfig` έχει **ένα** `fieldName`, και το `tenant-config.ts` το γράφει ήδη ρητά: *«δύο άξονες απομόνωσης για ένα έγγραφο σημαίνει **δύο απαντήσεις** στο “ποιος το βλέπει;”»*. Επιπλέον ο κανόνας `read` του `properties` περνά από **αναζήτηση έργου → εταιρείας** ⇒ έγγραφο χωρίς έργο θα ήταν **αναγνώσιμο από κανέναν** |
 * | **ξεχωριστή συλλογή** ✅ | `mode: 'userId'` — **ακριβώς** ό,τι έλυσε η **Α9** για τη ζήτηση. Η ίδια απάντηση στο ίδιο ερώτημα |
 *
 * 🔑 **Και η απόφαση ήταν ΗΔΗ γραμμένη**: το SPEC-777A **§14.2** ορίζει το επίπεδο Β ως
 * *«αυστηρά ιδιωτικό ανά **εταιρεία/χρήστη**»*. Οι δύο λέξεις είναι οι **δύο** τιμές του
 * `TenantIsolationMode`. Ο επαγγελματίας γράφει σε `properties` (`companyId`), ο
 * ιδιώτης εδώ (`ownerUserId`) — **μία** οντότητα ανά ακροατήριο, όχι μία με δύο ψυχές.
 *
 * ⚠️ **ΔΕΝ είναι διπλότυπο του `properties`, και η απόδειξη είναι ΔΟΜΙΚΗ:** και τα δύο
 * τροφοδοτούν την **ίδια** μηχανή προβολής (`buildPublicListing`), που δέχεται
 * **δομικό** τύπο ({@link ProjectableProperty}) ακριβώς για να έχει **πολλές πηγές και
 * μία έξοδο**. Η κοινή κατανόηση ζει εκεί· εδώ ζει μόνο ό,τι διαφέρει — και διαφέρει
 * το **ουσιώδες**: το `properties` είναι *μονάδα μέσα σε κτίριο μέσα σε έργο μιας
 * εταιρείας*· αυτό είναι *πράγμα που κατέχει ένας άνθρωπος*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΑ ΠΕΔΙΑ ΕΙΝΑΙ ΤΟ §25.6, ΚΑΙ ΤΟ «ΠΟΤΕ ΠΕΡΙΣΣΟΤΕΡΑ» ΕΙΝΑΙ ΚΑΝΟΝΑΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * *«5 βασικά + 3 ειδικά, **ΠΟΤΕ περισσότερα**»*. Η **Α14 §17.2** το δένει με τρεις
 * δεσμευτικούς κανόνες: ρωτάμε **μόνο** ό,τι χρειάζεται το ταίριασμα · **ποτέ** ό,τι
 * μπορούμε να υπολογίσουμε · η φόρμα **μικραίνει** όσο δίνεις.
 *
 * | §25.6 | Πού ζει εδώ |
 * |---|---|
 * | **τιμή** | μέσα στη **διάθεση** ({@link PropertyOffer}) — `askingPrice` · `rentPrice` · `percentage` |
 * | **φωτογραφία/κάτοψη** | {@link OwnerProperty.media} |
 * | **είδος + εμβαδόν** | `type` · `areaSqm` |
 * | **νομιμότητα + προέλευση** | 🔶 **ΔΕΝ ΥΠΑΡΧΕΙ ΕΔΩ** — δες {@link OwnerPropertyOpenGaps} |
 * | **πώληση/ενοικίαση/αντιπαροχή** | `offers` — το **υπάρχον** `OFFER_KINDS` (Α20) |
 * | + **θέση** | `place` — «υποχρεωτικό ΕΡΩΤΗΜΑ, όχι υποχρεωτική ΑΠΑΝΤΗΣΗ» (Α5 §3) |
 * | + **όροφος** | `floor` |
 * | + **υπνοδωμάτια** | `bedrooms` |
 *
 * 🔑 **Ο ενισχυτικός λόγος που τα πεδία ΔΕΝ είναι γραφειοκρατία (§17.1):** ακίνητο
 * χωρίς πεδία είναι **αόρατο στη μηχανή ταιριάσματος** — δεν συναντά καμία από τις
 * Ζ1–Ζ8, κανένα φίλτρο, καμία βαθμίδα ζουμ. **Υπάρχει στη βάση και δεν συναντά ποτέ
 * τίποτα.** Η φόρμα **είναι** ο πυρήνας.
 */

