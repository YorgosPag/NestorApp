/**
 * =============================================================================
 * ΤΟ ΛΕΞΙΛΟΓΙΟ ΤΟΥ ΔΟΧΕΙΟΥ ΠΛΗΡΟΦΟΡΙΑΣ (ADR-862 Φ0 · ADR-787 Κ-4)
 * =============================================================================
 *
 * **Το ερώτημα**: *«Βλέπει **ΑΥΤΟΣ** ο άνθρωπος **ΑΥΤΟ** το αρχείο;»*
 *
 * ⚠️ **ΔΕΝ είναι το ερώτημα του `capability-authority.ts`.** Εκείνο ρωτά *«έχει την
 * **ικανότητα**;»* — εξουσιοδότηση ανεξάρτητη πόρου. Αυτό ρωτά *«φτάνει σε **αυτό το
 * δοχείο**, στην **κατάσταση** που βρίσκεται;»*. Η σειρά είναι: **πρώτα μέλος**
 * (ADR-787) · **μετά ικανός** (ADR-801) · **μετά φτάνει σε αυτό το δοχείο** (εδώ).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΧΡΕΙΑΣΤΗΚΕ — Η ΕΤΙΚΕΤΑ ΥΠΗΡΧΕ, Η ΠΟΡΤΑ ΟΧΙ
 * ─────────────────────────────────────────────────────────────────────────────
 * Το `cdeState` (ADR-373) ονομάζει τις τέσσερις καταστάσεις του ISO 19650 από τον
 * Μάιο του 2026. Μετρημένο 2026-09-16: **4 γραφείς**, **3 αναγνώστες** — και οι
 * τρεις **παρουσιαστικοί** (δέντρο αρχείων, οθόνη μεταδεδομένων, κόστος AI).
 * Εμφανίσεις σε `firestore.rules`: **0**. Σε `src/lib/auth/**`: **0**.
 *
 * Δηλαδή ένα αρχείο μπορούσε να λέει `WIP` και να το βλέπουν όλοι.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🌐 ΤΟ ΠΡΟΤΥΠΟ — ΤΡΕΙΣ ΟΡΘΟΓΩΝΙΟΙ ΑΞΟΝΕΣ, ΟΧΙ ΕΝΑΣ
 * ─────────────────────────────────────────────────────────────────────────────
 * Το ISO 19650 (UK BIM Framework, Guidance Part C §2.1 · §6.1) κρατά **χωριστά**:
 *
 *   • **κατάσταση**   — *ποιος βλέπει*   → `cdeState`        ← ΕΔΩ φρουρεί
 *   • **καταλληλότητα** — *permitted use* → `suitabilityCode` ← ΠΟΤΕ δεν φρουρεί
 *   • **αναθεώρηση**  — *ποια έκδοση*    → `revisionCode`
 *
 * Το WIP ορίζεται αυτολεξεί ως *«information being developed by its originator or
 * task team, **not visible to or accessible by anyone else**»*. Γι' αυτό η
 * ορατότητα κρίνεται από την **ομάδα**, όχι από τον ρόλο.
 *
 * ⚠️ **ΚΑΙ ΔΕΝ ΕΙΝΑΙ Η ΣΗΜΑΣΙΟΛΟΓΙΑ ΤΩΝ ΕΡΓΑΛΕΙΩΝ ΣΥΝΤΑΞΗΣ.** Στο Revit όλοι
 * **βλέπουν** τα worksets των άλλων και η ιδιοκτησία κλειδώνει την **επεξεργασία**·
 * στο Figma ένα branch το βλέπει όποιος έχει το κύριο αρχείο. Τα εργαλεία σύνταξης
 * φρουρούν το **γράψιμο**· το πρότυπο CDE φρουρεί την **ορατότητα**. Αν τα
 * μπερδέψουμε, χτίζουμε Revit αντί για CDE.
 *
 * @module types/container-access
 * @see ADR-862 §5.4.1 — ο πίνακας των τεσσάρων προτύπων
 * @see ADR-787 Α5 — ΡΟΛΟΣ × ΠΕΡΙΟΧΗ × ΚΑΤΑΣΤΑΣΗ, ποτέ ανά αρχείο
 * @see types/capability-authority — ο αδελφός («έχει την ικανότητα;»)
 */

import type { SuitabilityCode } from '@/config/iso19650-constants';
import type { CapabilitySubject } from '@/types/capability-authority';

// =============================================================================
// ΤΟ ΑΚΡΟΑΤΗΡΙΟ — ΤΟ ΚΛΕΙΣΤΟ ΣΥΝΟΛΟ ΤΟΥ ADR-862 §5.4.1
// =============================================================================

/**
 * Τα **τέσσερα** πρότυπα συμμετοχής. Κλειστό σύνολο — η τέταρτη τιμή (`client`)
 * μπήκε **χωρίς** νέο μηχανισμό (ADR-862 Ε-11), και αυτό είναι η απόδειξη ότι η
 * αρχή **Α6** του ADR-787 («ΕΝΑΣ μηχανισμός») κρατά.
 *
 * ⛔ **Πέμπτη τιμή ⇒ πρέπει να αποκτήσει γραμμή στον πίνακα εμβέλειας** του
 * κριτή. Ο μεταγλωττιστής το επιβάλλει με `Record<CdeAudience, …>` — ένα
 * ακροατήριο χωρίς δηλωμένη εμβέλεια **δεν χτίζει**.
 */
export type CdeAudience =
  /** Μελετητής — πολιτικός · μηχανολόγος · ηλεκτρολόγος · τοπογράφος … */
  | 'design'
  /** Συνεργείο · εργολάβος · τεχνίτης — βλέπει **μόνο** ό,τι δόθηκε «για κατασκευή». */
  | 'crew'
  /** Ο κύριος του έργου (ADR-862 §5.4.1.δ). */
  | 'client'
  /** Προμηθευτής — βλέπει **πακέτο**, ποτέ «ανά κατάσταση» (Φ3). */
  | 'supplier';

// =============================================================================
// Η ΚΑΤΑΣΤΑΣΗ, ΟΠΩΣ ΔΙΑΒΑΖΕΤΑΙ
// =============================================================================

/**
 * Η κατάσταση του δοχείου **όπως την κατάλαβε ο θεματοφύλακας**.
 *
 * 🔑 **Η ΑΠΟΥΣΙΑ ΚΑΙ Η ΒΛΑΒΗ ΕΙΝΑΙ ΟΝΟΜΑΣΜΕΝΕΣ ΚΑΤΑΣΤΑΣΕΙΣ, ΟΧΙ ΠΕΜΠΤΗ/ΕΚΤΗ ΤΙΜΗ
 * ΤΟΥ `CDE_STATES`.** Το λεξιλόγιο του ISO μένει **τέσσερα** — αυτό που
 * επεκτείνεται είναι η **ανάγνωση**, όχι το πρότυπο. Ίδιο ιδίωμα με το
 * `GlobalRoleClaim` (`lib/auth/identity-claims.ts`), όπου «απών» και «άκυρος»
 * είναι διακριτές καταστάσεις και ο μεταγλωττιστής δεν επιτρέπει να αγνοηθούν.
 */
export type ContainerState =
  /** Σε εξέλιξη — **μόνο** η ομάδα που το φτιάχνει (ISO 19650 task team). */
  | { readonly phase: 'WIP'; readonly teamId: string | null }
  /** Σε διαβούλευση — όλες οι ομάδες **μελέτης** του έργου. */
  | { readonly phase: 'SHARED'; readonly teamId: string | null }
  /** Εγκεκριμένο «για κατασκευή» — **δύο** ρητές πράξεις το γέννησαν. */
  | { readonly phase: 'PUBLISHED'; readonly teamId: string | null; readonly revision: number }
  /** Αντικαταστάθηκε — ιστορικό, **πίσω από ρητό διακόπτη**, ποτέ προεπιλογή. */
  | { readonly phase: 'SUPERSEDED'; readonly teamId: string | null }
  /**
   * 🔑 **Γραμμένο ΠΡΙΝ τη Φ0** — και σημαίνει **«όπως σήμερα»**.
   *
   * ⛔ **ΔΕΝ σημαίνει `WIP`** *(θα έκρυβε ό,τι φαίνεται σήμερα)* και **ΔΕΝ σημαίνει
   * `PUBLISHED`** *(θα το έδινε σε συνεργείο και πελάτη)*. Είναι μονόδρομο:
   * διατηρεί τη σημερινή ορατότητα μέσα στο γραφείο και **δεν αποκαλύπτει τίποτα**
   * προς τα έξω. Μετρημένο 2026-09-16: **35 από 35** ζωντανά αρχεία είναι εδώ.
   */
  | { readonly phase: 'pre-cde' }
  /**
   * 🔴 Το έγγραφο **δηλώνει** κατάσταση που οι πράξεις του **δεν στηρίζουν** —
   * ή τιμή εκτός λεξιλογίου. ⇒ **fail-closed**.
   *
   * Αυτό είναι που κάνει τη «δεύτερη αλήθεια» **μη κερδοφόρα**: χειρόγραφη αλλαγή
   * του πεδίου `cdeState` σε `'PUBLISHED'` **δεν** δίνει ορατότητα — δίνει άρνηση.
   */
  | { readonly phase: 'unreadable'; readonly why: string };

/** Οι φάσεις που **ονομάζει το ISO 19650** — χωρίς την απουσία και τη βλάβη. */
export type ContainerPhase = ContainerState['phase'];

// =============================================================================
// ΟΙ ΠΡΑΞΕΙΣ — «ΠΟΙΟΣ · ΠΟΤΕ · ΠΟΙΑ ΑΝΑΘΕΩΡΗΣΗ»
// =============================================================================

/**
 * Μία πράξη κατάστασης (ADR-862 §5.4.1.γ: *«ίχνος: ποιος · πότε · **ποια
 * αναθεώρηση**»*).
 *
 * 🔑 **ΤΟ `revision` ΔΕΝ ΕΙΝΑΙ ΔΙΑΚΟΣΜΗΤΙΚΟ** — είναι ο μηχανισμός που κάνει
 * **δομικά αδύνατη** τη μετάλλαξη (α) της άγκυρας Α17 *(«αυτόματη δημοσίευση της
 * τελευταίας έκδοσης»)*: σφραγίδα στην `P01` **δεν** ισχύει για την `P02` που
 * κανείς δεν είδε. Χωρίς αυτό, ο μηχανικός σφραγίζει μία φορά και κάθε επόμενη
 * αποθήκευση φεύγει «εγκεκριμένη» στο εργοτάξιο.
 */
export interface ContainerActRecord {
  /** Ποιος την έκανε — `uid`, ποτέ όνομα (το όνομα αλλάζει, το `uid` όχι). */
  readonly by: string;
  /** Πότε. Γράφεται από τον **διακομιστή**, ποτέ από ρολόι πελάτη. */
  readonly at: Date | string;
  /** Σε **ποια** αναθεώρηση του αρχείου. Δες παραπάνω γιατί είναι υποχρεωτικό. */
  readonly revision: number;
  /**
   * **Μόνο στη σφραγίδα**: το «permitted use» που δηλώνει ο **μελετητής**.
   * Ο άξονας της καταλληλότητας — ορθογώνιος, ποτέ φρουρός.
   */
  readonly suitabilityCode?: SuitabilityCode;
  /** **Μόνο στην απόσυρση**: γιατί αποσύρθηκε. */
  readonly reason?: string;
}

/**
 * Οι τέσσερις πράξεις ενός δοχείου, **όπως διαβάστηκαν**. `null` = δεν έγινε.
 *
 * ⚠️ Το `WIP` **δεν** έχει πράξη: είναι η κατάσταση **γέννησης**. Γι' αυτό η
 * διάκριση «δηλωμένο WIP» ↔ «ποτέ δεν δηλώθηκε» **δεν** παράγεται από τις πράξεις —
 * τη δίνει η **παρουσία** του πεδίου `cdeState`.
 */
export interface ContainerActs {
  readonly share: ContainerActRecord | null;
  readonly seal: ContainerActRecord | null;
  readonly release: ContainerActRecord | null;
  readonly withdrawal: ContainerActRecord | null;
}

// =============================================================================
// ΤΟ ΥΠΟΚΕΙΜΕΝΟ ΚΑΙ ΤΑ ΓΕΓΟΝΟΤΑ
// =============================================================================

/**
 * Η ταυτότητα του αναγνώστη — **επέκταση** του `CapabilitySubject`, όχι αντίγραφο.
 *
 * ⚠️ **Καμία ανάγνωση εδώ μέσα.** Τα τρία πρόσθετα πεδία τα γεμίζει ο **καλών**:
 * στον διακομιστή από το `resource-lookups`, στην οθόνη από ό,τι έχει ήδη
 * φορτωθεί. Αν ο κριτής χρειαζόταν να **διαβάσει** για να απαντήσει, θα γινόταν
 * `async` + `server-only` και ο πελάτης θα **έχανε** τον έναν PEP του
 * (`useCapability`, μέσα σε `useMemo`).
 */
export interface ContainerSubject extends CapabilitySubject {
  readonly uid: string;
  /**
   * Η ομάδα εργασίας του **μέσα σε αυτή την υπόθεση**.
   * `null` = δεν ανήκει σε ομάδα ⇒ **κανένα** WIP, ούτε δικό του.
   */
  readonly taskTeamId: string | null;
  /**
   * Το πρότυπο συμμετοχής του. `null` = **δεν συμμετέχει** στην υπόθεση.
   */
  readonly audience: CdeAudience | null;
  /**
   * Ζήτησε **ΡΗΤΑ** το ιστορικό; Ο «διακόπτης» του `SUPERSEDED`.
   *
   * ⛔ **ΠΟΤΕ προεπιλογή `true`**: το ADR-862 §5.4.1 ορίζει το αποσυρθέν ως
   * *«ιστορικό, πίσω από ρητό διακόπτη»*. Το πρότυπο *Current Drawings* του
   * Procore υπάρχει ακριβώς για να μην χτίζει το συνεργείο από παλιό φύλλο.
   */
  readonly historyRequested: boolean;
}

/**
 * Τα γεγονότα του πόρου — **ΗΔΗ ΦΟΡΤΩΜΕΝΑ**, ποτέ κλειδί προς ανάγνωση.
 * Τα παράγει ο θεματοφύλακας (`lib/files/file-record-read`).
 */
export interface ContainerFacts {
  readonly fileId: string;
  /** `null` = αρχείο χωρίς μισθωτή. **Το κενό δεν είναι tenant** (ADR-742 §4). */
  readonly companyId: string | null;
  /** Ο δημιουργός — η **νομική** ταυτότητα της σφραγίδας. */
  readonly createdBy: string;
  readonly state: ContainerState;
}

// =============================================================================
// ΟΙ ΕΤΥΜΗΓΟΡΙΕΣ — ΔΕΚΑΤΡΕΙΣ, ΟΝΟΜΑΣΜΕΝΕΣ, ΠΟΤΕ `boolean`
// =============================================================================

/**
 * ⚠️ **ΓΙΑΤΙ ΟΧΙ `boolean`**: ένα `false` δεν λέει **γιατί**, οπότε ο καλών ούτε να
 * το εξηγήσει μπορεί στον άνθρωπο ούτε να το ξεχωρίσει από σφάλμα. Ίδιο δόγμα με
 * το `CapabilityVerdict` και το `ResourceAccessVerdict`.
 */
export type ContainerAccessVerdict =
  // ── ΕΠΙΤΡΕΠΟΥΝ ────────────────────────────────────────────────────────────
  /** WIP **της δικής του** ομάδας — ο ISO 19650 task team. */
  | 'visible-own-wip'
  /** SHARED — κάθε ομάδα **μελέτης** της υπόθεσης. */
  | 'visible-shared-to-design'
  /** PUBLISHED — «για κατασκευή»: + συνεργείο + πελάτης. */
  | 'visible-published'
  /** SUPERSEDED, με **ρητό** διακόπτη και ικανότητα ιστορικού. */
  | 'visible-history'
  /** `pre-cde` — η **σημερινή** συμπεριφορά, με ημερομηνία λήξης (ratchet). */
  | 'visible-legacy-tenant'
  // ── ΑΡΝΟΥΝΤΑΙ ─────────────────────────────────────────────────────────────
  /** Καμία ταυτότητα (deny-by-default, OWASP). */
  | 'denied-unauthenticated'
  /** Δεν συμμετέχει **καθόλου** στην υπόθεση. */
  | 'denied-not-engaged'
  /** 🔑 Η **κανονική** άρνηση της άγκυρας Α10: WIP **ξένης** ομάδας. */
  | 'denied-foreign-wip'
  /** Το πρότυπό του **δεν φτάνει** σε αυτή την κατάσταση (συνεργείο μπροστά σε WIP/SHARED). */
  | 'denied-audience'
  /** Αποσυρθέν, **χωρίς** τον ρητό διακόπτη. */
  | 'denied-superseded-hidden'
  /** 🔴 Το έγγραφο δεν λέει τι είναι ⇒ **fail-closed**. */
  | 'denied-unknown-state'
  /** WIP χωρίς ομάδα, ή αιτών χωρίς ομάδα — **κανείς δεν κληρονομεί** ανώνυμο WIP. */
  | 'denied-teamless'
  /** Πέρασε το ακροατήριο· το έκοψε ο `decideCapability`. */
  | 'denied-capability';

/**
 * Οι ετυμηγορίες που **επιτρέπουν**.
 *
 * ⚠️ Καμία `denied-*` εδώ, **ούτε ως προσωρινή ανοχή**: μια αποτυχία που
 * διαβάζεται ως άδεια είναι διαρροή (πρότυπο `GRANTING_VERDICTS`, ADR-801).
 */
export const VISIBLE_VERDICTS: readonly ContainerAccessVerdict[] = [
  'visible-own-wip',
  'visible-shared-to-design',
  'visible-published',
  'visible-history',
  'visible-legacy-tenant',
] as const;

/** Επιτρέπει αυτή η ετυμηγορία την ανάγνωση; */
export function isContainerVisible(verdict: ContainerAccessVerdict): boolean {
  return VISIBLE_VERDICTS.includes(verdict);
}

/**
 * Η ετυμηγορία **μαζί με τον πόρο που κρίθηκε**.
 *
 * ⚠️ Το `fileId` επιστρέφεται **ρητά** ώστε ένα «ναι» να μην μπορεί ποτέ να
 * εφαρμοστεί σε **άλλο** αρχείο από αυτό που ρωτήθηκε — πρότυπο
 * `CapabilityDecision.action` και `MembershipDecision.workspace`.
 */
export interface ContainerAccessDecision {
  readonly verdict: ContainerAccessVerdict;
  readonly fileId: string;
  /** Η φάση που κρίθηκε — ώστε η οθόνη να **εξηγεί** χωρίς δεύτερη ανάγνωση. */
  readonly phase: ContainerPhase;
  /** Κλειδί i18n για το «γιατί όχι» — `null` όταν επιτρέπεται. Κλειδί, ποτέ κείμενο (N.11). */
  readonly reason: string | null;
}

