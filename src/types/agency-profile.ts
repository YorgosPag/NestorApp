/**
 * **Τι διαβάστηκε από το Firestore** — δύο εκβάσεις, και η δεύτερη **δεν είναι
 * σφάλμα του ανθρώπου**.
 *
 * ⚠️ Το `snapshot.data() as AgencyProfile` που υπήρχε σε **τρία** σημεία δεχόταν
 * ό,τι γράφτηκε ποτέ. Με credentials γίνεται επικίνδυνο: έγγραφο **χωρίς καμία
 * απόδειξη** θα ζωγραφιζόταν ως κάρτα — δηλαδή ακριβώς ο κατάλογος που το
 * §9.9 β ονομάζει *«επικίνδυνο αντί για χρήσιμο»*.
 *
 * 🔑 **Ο ΑΝΑΓΝΩΣΤΗΣ ΖΕΙ ΣΤΟ `lib/agency/showcase-read.ts`, ΟΧΙ ΕΔΩ** — και είναι
 * απόφαση, όχι τοποθέτηση: για να παραγάγει το `standing` πρέπει να ρωτήσει τον
 * `occupationNeedsCapability` *(`lib/professional/`)*, και **ένα `types/` που
 * εισάγει από `lib/` αντιστρέφει τη ροή εξαρτήσεων** — κάθε καταναλωτής του
 * τύπου θα κουβαλούσε τη μηχανή. Ο **τύπος** της εκβασης μένει εδώ, δίπλα στο
 * σχήμα που περιγράφει.
 */
export type ShowcaseRead =
  | { readonly outcome: 'showcase'; readonly showcase: PublicShowcase }
  /** ⚠️ Έγγραφο που δεν ταιριάζει πουθενά. **Παραλείπεται ΚΑΙ καταγράφεται.** */
  | { readonly outcome: 'unreadable'; readonly companyId: string };
