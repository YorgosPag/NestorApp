/**
 * **Η βιτρίνα.** Κλειδί εγγράφου: το `companyId`.
 *
 * ⚠️ **ΚΛΕΙΔΙ ΤΟ `companyId`, ΟΧΙ ΤΟ ΨΕΥΔΩΝΥΜΟ** — και είναι απόφαση, όχι ευκολία:
 *
 *   1. ψευδώνυμο ως κλειδί = **δεύτερο βιβλίο ψευδωνύμων** που μπορεί να διαφωνήσει με
 *      το `workspace_aliases` (**ADR-749**), και
 *   2. θα **έσπαγε** τους παλιούς συνδέσμους στη μετονομασία, ενώ το **Ε-5 §8**
 *      υπόσχεται ότι *κάθε παλιό ψευδώνυμο εξακολουθεί να λύνεται — για πάντα*.
 *
 * Η διαδρομή είναι `resolveAlias(alias)` → `agency_profiles/{companyId}`: **δύο
 * σημειακές αναγνώσεις, μηδέν σαρώσεις**.
 */
export interface AgencyProfile {
  /**
   * 🔴 **Η ΔΙΕΥΘΥΝΣΗ — και εδώ η ταυτότητα ΕΙΝΑΙ το περιεχόμενο.**
   *
   * Η ασυμμετρία με το `PublicListing` είναι όλη η απόφαση: εκεί η ταυτότητα είναι
   * **διαρροή** *(«κλειστό σχήμα ΧΩΡΙΣ καμία ταυτότητα πελάτη»)*· εδώ είναι ο **λόγος
   * ύπαρξης** του εγγράφου. Τα ξεχωρίζει **ποιος έγραψε ποιον**: εκεί ο πελάτης του
   * γραφείου δεν διάλεξε ποτέ να φανεί· εδώ ο **οργανισμός δημοσίευσε τον εαυτό του**.
   */
  readonly companyId: string;
  /**
   * Το ψευδώνυμο **τη στιγμή της δημοσίευσης** — για να χτίζεται ο σύνδεσμος χωρίς
   * αντίστροφη αναζήτηση *(που θα ήταν σάρωση — δες `resolveAlias`, όπου το
   * `canonicalAlias` επιστρέφει `null` ακριβώς γι' αυτόν τον λόγο)*.
   *
   * ⚠️ **Αντίγραφο, όχι αυθεντία.** Η αυθεντία μένει το `workspace_aliases`· αν
   * αποκλίνει, η σημειακή ανάγνωση κατά ψευδώνυμο εξακολουθεί να λύνει σωστά.
   */
  readonly alias: string;
  /** Η **επωνυμία**. Ίδια πηγή με το `PublicListing.agencyName`. */
  readonly displayName: string;
  /**
   * **Αριθμός ΓΕΜΗ** — από τη `BrokerageDeclaration` του ADR-824.
   *
   * ⚠️ Είναι δημόσιος **εκ του νόμου** *(και το **άρθρο 200 §2 Ν.4072/2012** τον απαιτεί
   * μέσα στη σύμβαση)*, αλλά *«δημόσιο αλλού»* **δεν σημαίνει** *«δημοσιευμένο από
   * εμάς»*: μπαίνει επειδή είναι η **απόδειξη ότι ο μεσίτης είναι υπαρκτός και
   * αδειοδοτημένος** — το μόνο που κάνει τον κατάλογο χρήσιμο αντί για επικίνδυνο.
   */
  readonly gemiNumber: string;
  /**
   * Πού δραστηριοποιείται — για **ουδέτερη γεωγραφική σειρά**.
   *
   * ⛔ **ΠΟΤΕ εμπορική σειρά.** Δες την απαγόρευση παρακάτω.
   */
  readonly place: PlaceRef | null;
  /** ISO — πότε δημοσιεύτηκε η βιτρίνα. */
  readonly publishedAt: string;
}

/**
 * 🔶 **Ο φρουρός του κλειστού σχήματος** — ίδιο κόλπο με `PublicListingOpenGaps`.
 *
 * ⛔ **ΤΡΙΑ ΠΟΥ ΔΕΝ ΜΠΑΙΝΟΥΝ ΠΟΤΕ, ΚΑΙ ΤΑ ΤΡΙΑ ΕΙΝΑΙ ΑΠΟΦΑΣΗ:**
 *
 * 1. **ΑΜΟΙΒΗ / ΠΡΟΜΗΘΕΙΑ · ΒΑΘΜΟΛΟΓΙΑ · ΚΑΤΑΤΑΞΗ · ΠΡΟΒΟΛΗ ΕΠΙ ΠΛΗΡΩΜΗ.** Ένας
 *    κατάλογος **ΓΡΑΦΕΙΩΝ** είναι **μεγαλύτερη** επιφάνεια *steering* από κατάλογο
 *    **ακινήτων**: αν η πλατφόρμα κατατάσσει γραφεία, κατευθύνει **δουλειά**. Το NAR
 *    Settlement (17/08/2024, **$418M**) αφορούσε ακριβώς αυτό. 🔑 Ο φρουρός είναι
 *    **δομικός**: πεδίο που δεν υπάρχει **δεν μπορεί** να ταξινομήσει κανείς — ούτε
 *    εμείς, ούτε ο πελάτης.
 *
 * 2. **ΚΑΝΑΛΙ ΕΠΙΚΟΙΝΩΝΙΑΣ** *(τηλέφωνο · email · διεύθυνση)*. 🏆 Το προφίλ **δεν είναι
 *    κατάλογος τηλεφώνων — είναι ΚΟΥΜΠΙ**: η μόνη πράξη που προσφέρει είναι το αίτημα
 *    ανάθεσης. Το **άρθρο 200 §1** ορίζει ότι η σύμβαση μεσιτείας *«καταρτίζεται
 *    **εγγράφως**»*· κατάλογος που δίνει τηλέφωνο παράγει **τηλεφώνημα**, πράξη από την
 *    οποία **καμία έγκυρη σύμβαση δεν γεννιέται**. Ο νόμος δεν επιβάλλεται με
 *    υπενθύμιση — επιβάλλεται από **το τι μπορεί να πατήσει ο άνθρωπος**.
 *
 * 3. **ΟΝΟΜΑ ΦΥΣΙΚΟΥ ΠΡΟΣΩΠΟΥ** — ούτε το `legalRepresentativeName` της
 *    `BrokerageDeclaration`. Ο κατάλογος αφορά **νομικά πρόσωπα** *(αιτιολογική σκέψη
 *    **14** GDPR: εκτός πεδίου)*, 🔴 **αλλά μεσίτης με ατομική επιχείρηση είναι φυσικό
 *    πρόσωπο** και η έδρα του μπορεί να είναι η **κατοικία** του. Γι' αυτό: **καμία
 *    αυτόματη αντιγραφή από το `companies/{id}`** — γράφεται ό,τι δήλωσε **ρητά** το
 *    γραφείο για δημοσίευση.
 */
export type AgencyProfileOpenGaps = never;

