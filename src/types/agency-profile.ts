/**
 * **Η βιτρίνα.** Κλειδί εγγράφου: το `companyId`.
 *
 * ⚠️ **ΚΛΕΙΔΙ ΤΟ `companyId`, ΟΧΙ ΤΟ ΨΕΥΔΩΝΥΜΟ** — και είναι απόφαση, όχι ευκολία:
 *
 *   1. ψευδώνυμο ως κλειδί = **δεύτερο βιβλίο ψευδωνύμων** που μπορεί να διαφωνήσει με
 *      το `workspace_aliases` (**ADR-749**), και
 *   2. θα **έσπαγε** τους παλιούς συνδέσμους στη μετονομασία, ενώ το **Ε-5 §8**
 *      υπόσχεται ότι *κάθε παλιό ψευδώνυμο εξακολουθεί να λύνεται — για πάντα*.
 *
 * Η διαδρομή είναι `resolveAlias(alias)` → `agency_profiles/{companyId}`: **δύο
 * σημειακές αναγνώσεις, μηδέν σαρώσεις**.
 */
export interface ClassifiedOccupation {
  /**
   * 🔑 **Η ΑΥΘΕΝΤΙΑ** — το ESCO occupation URI. Ό,τι ταξιδεύει και στο IFC
   * *(ADR-798 §6.2)*, και ο **μόνος** δείκτης που δεν παλιώνει.
   */
  readonly escoUri: string;
  /**
   * ⚠️ **ΔΙΓΛΩΣΣΟ, ΟΧΙ `string`** — και είναι μετρημένο εύρημα, όχι πρόβλεψη.
   *
   * Το `DeclaredOccupation.escoLabel` κρατά τη γλώσσα **της στιγμής επιλογής**
   * *(`EscoOccupationPicker:59` → `pickBilingualLabel(labels, lang)`)*. Σε
   * **δημόσιο, δίγλωσσο** κατάλογο αυτό σημαίνει ότι ο αγγλόφωνος επισκέπτης
   * βλέπει «Ελαιοχρωματιστής».
   *
   * 🔴 **Γράφεται από τον ΔΙΑΚΟΜΙΣΤΗ, από την ταξινομία** — ποτέ από το σύρμα.
   * **ΣΤΙΓΜΙΟΤΥΠΟ** *(Α1.6)*: απαντά *«πώς λεγόταν όταν δημοσιεύτηκε»*· η
   * αυθεντία μένει το `escoUri`, άρα το μπαγιάτικο είναι **επισκευάσιμο**.
   */
  readonly label: EscoBilingualText;
  /**
   * Ο κωδικός **ISCO-08**. Δύο καταναλωτές, και οι δύο υποχρεωτικοί:
   * `resolveRegistryAuthority()` *(ποια αρχή)* και η ομαδοποίηση του φίλτρου.
   *
   * ⚠️ **ΑΝΑΦΟΡΑ, όχι στιγμιότυπο**: το ESCO μπορεί να ξανα-αντιστοιχίσει. Ζει
   * δίπλα στο `escoUri` ⇒ επισκευάσιμο.
   */
  readonly iscoCode: string;
}

/**
 * **Ένα credential** — *«τι κάνω»* **και** *«η απόδειξή μου»*, μαζί.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΓΙΑΤΙ Η ΔΙΑΚΡΙΣΗ ΕΙΝΑΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΤΗ ΒΙΤΡΙΝΑ — ΔΥΟ ΑΠΑΙΤΗΣΕΙΣ ΠΟΥ ΕΜΟΙΑΖΑΝ
 * ΑΣΥΜΒΙΒΑΣΤΕΣ
 *
 *   **(α)** Το **μικτό γραφείο πρέπει να είναι εκφράσιμο.** Το **ADR-824 §4.1**
 *   απέρριψε ρητά ένα `companyType: 'brokerage' | 'architecture' | …` επειδή
 *   *«στην Ελλάδα είναι **συνηθέστατο** ένα τεχνικό γραφείο να κατέχει **και**
 *   μεσιτική άδεια»*, και η αναπόφευκτη θεραπεία ήταν ένα `'mixed'`. Ένα
 *   `kind: 'brokerage' | 'professional'` **στη βιτρίνα** θα ήταν το ίδιο
 *   απορριφθέν enum με άλλο καπέλο.
 *
 *   **(β)** Ο **μεσίτης πρέπει να έχει ΓΕΜΗ υποχρεωτικά.** Το προηγούμενο σχήμα
 *   το εγγυόταν με `readonly gemiNumber: string` *(ΟΧΙ `| null`)* — *«δεν
 *   μπαίνεις στον κατάλογο χωρίς αυτόν»*. Ένας πίνακας από `{occupation,
 *   attestation}` με **προαιρετικό** attestation θα το έχανε: η ορθότητα θα
 *   κρεμόταν από runtime `if`, δηλαδή από **κανόνα που κάποιος πρέπει να
 *   θυμηθεί**.
 *
 * ✅ **Ικανοποιούνται μαζί όταν η διάκριση μετακινηθεί ένα επίπεδο κάτω**: όχι
 * *«τι είδους βιτρίνα είναι αυτή;»* αλλά *«τι είδους **ισχυρισμός** είναι
 * αυτός;»*. Το μικτό γραφείο έχει **δύο** credentials — ένα `regulated` και ένα
 * `self-declared` — και ο μεταγλωττιστής απαιτεί απόδειξη **μόνο** στο πρώτο.
 *
 * ⚠️ **ΤΟ `standing` ΔΕΝ ΑΠΟΘΗΚΕΥΕΤΑΙ.** Στο Firestore ζει σκέτο
 * `{occupation, attestation}`· η παραλλαγή **παράγεται** στο σύνορο ανάγνωσης
 * *(δες {@link readShowcase})* από το `iscoCode`. Αποθηκευμένη σημαία θα
 * μπορούσε να **διαφωνήσει με το περιεχόμενο** — ακριβώς αυτό που απαγορεύει το
 * `isPublishedProfile` παρακάτω, δύο δεκάδες γραμμές μακριά.
 */
export type ShowcaseCredential =
  | {
      /**
       * **Ρυθμιζόμενη δραστηριότητα** — η ίδια η *διαφήμιση* απαιτεί άδεια.
       * Σήμερα: **μόνο η μεσιτεία** *(Ν.4072/2012)*, δηλαδή ISCO `3334` → ΓΕΜΗ.
       */
      readonly standing: 'regulated';
      readonly occupation: ClassifiedOccupation;
      /**
       * 🔒 **ΧΩΡΙΣ `unknown`** — ο μεταγλωττιστής κρατά την υπόσχεση *«δεν
       * μπαίνεις στον κατάλογο χωρίς αυτόν»* που έδινε το παλιό
       * `gemiNumber: string`.
       */
      readonly attestation: RegulatedAttestation;
    }
  | {
      /**
       * **Αυτο-δηλωμένη ιδιότητα** — η πλατφόρμα δεν έχει τίποτα να κρίνει
       * *(ADR-798 Α4: «ΠΟΤΕ δεν δίνει δικαίωμα»)*.
       */
      readonly standing: 'self-declared';
      readonly occupation: ClassifiedOccupation;
      /**
       * ✅ **Το `unknown` είναι ΝΟΜΙΜΟ και συνηθισμένο** — ο ελαιοχρωματιστής
       * **μπαίνει**, με την απουσία **ονομασμένη** *(Α9.3)*.
       */
      readonly attestation: ProfessionalAttestation;
    };

/**
 * Το attestation **χωρίς** το `unknown` — για εκεί που ο νόμος δεν το επιτρέπει.
 *
 * ⚠️ **Παράγεται** με `Exclude`, ποτέ ξαναγραμμένο: μια δεύτερη απαρίθμηση των
 * καταστάσεων θα ξεχνούσε την επόμενη *(ADR-798 §7 — τρεις, ακέραιες)*.
 */
type RegulatedAttestation = Exclude<ProfessionalAttestation, { state: 'unknown' }>;

/**
 * **Η βιτρίνα.** Κλειδί εγγράφου: το `companyId`.
 *
 * ⚠️ **ΤΟ ΟΝΟΜΑ ΑΛΛΑΞΕ ΣΤΗ Φ6-Β, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ**: ήταν `AgencyProfile`
 * *(«γραφείο»)*, ενώ πλέον κρατά **δικηγόρους, μηχανικούς, υδραυλικούς,
 * ελαιοχρωματιστές, διακοσμητές** — και μεσίτες. Όνομα στενότερο από το
 * περιεχόμενό του είναι χρέος που ο επόμενος πληρώνει σε λάθος υπόθεση.
 *
 * 🔑 **Η φυσική συλλογή μένει `agency_profiles`** *(`COLLECTIONS.AGENCY_PROFILES`)*:
 * μετονομασία συλλογής είναι **μετανάστευση δεδομένων** χωρίς κανένα όφελος για
 * τον άνθρωπο. Ίδιο πρότυπο με το ADR-841 Α6, *«η μηχανή μετακόμισε, η απόφαση
 * έμεινε»*.
 */

/**
 * 🔴 **ΤΟ ΤΑΒΑΝΙ ΤΗΣ ΑΠΟΔΕΔΕΙΓΜΕΝΗΣ ΠΑΡΟΥΣΙΑΣ** *(ADR-846 Φ5δ)* — και η **πολιτική
 * υπέρβασης, δηλωμένη**.
 *
 * ⚠️ **Άφραχτο `readonly GeoCircle[]` θα ήταν το `adminIds` του §4.2 από την πρώτη μέρα**:
 * ο κατάλογος κατεβάζει **ολόκληρο** τον πληθυσμό βιτρινών σε **κάθε ανώνυμο επισκέπτη**,
 * οπότε κάθε byte πολλαπλασιάζεται με τον αριθμό των γραφείων.
 *
 * 🔑 **Στην πράξη το ταβάνι δεν αγγίζεται, επειδή οι κύκλοι ΑΠΟΡΡΟΦΩΝΤΑΙ**: 40 ακίνητα σε
 * μία πόλη ⇒ **1** εγγραφή· 6 ακίνητα σε 5 πόλεις ⇒ **5**. Το 32 δεν είναι πρόβλεψη
 * χαρτοφυλακίου — είναι **φράγμα** ώστε ένα σπασμένο πέρασμα να μη γεννήσει έγγραφο που
 * το κατεβάζει κάθε επισκέπτης.
 *
 * 🏆 **Η ΠΟΛΙΤΙΚΗ ΥΠΕΡΒΑΣΗΣ ΕΙΝΑΙ FAIL-CLOSED ΣΤΟΝ ΙΣΧΥΡΙΣΜΟ**: κρατούνται οι **32 πρώτες
 * σε ντετερμινιστική σειρά** *(γεωγραφικό πλάτος, μετά μήκος)* και η υπέρβαση
 * **καταγράφεται**. Η συνέπεια είναι **ψευδώς αρνητικό** *(το γραφείο δεν εμφανίζεται
 * κάπου όπου δουλεύει)* — **ποτέ** ψευδώς θετικό. Η αντίστροφη επιλογή *(«κράτα τους
 * μεγαλύτερους κύκλους»)* θα ήταν χειρότερη: θα προτιμούσε συστηματικά τις **πιο αβέβαιες**
 * θέσεις, δηλαδή τις **λιγότερο αποδεδειγμένες**.
 */
export const MAX_PRESENCE_AREAS = 32;

export interface PublicShowcase {
  /**
   * 🔴 **Η ΔΙΕΥΘΥΝΣΗ — και εδώ η ταυτότητα ΕΙΝΑΙ το περιεχόμενο.**
   *
   * Η ασυμμετρία με το `PublicListing` είναι όλη η απόφαση: εκεί η ταυτότητα είναι
   * **διαρροή** *(«κλειστό σχήμα ΧΩΡΙΣ καμία ταυτότητα πελάτη»)*· εδώ είναι ο **λόγος
   * ύπαρξης** του εγγράφου. Τα ξεχωρίζει **ποιος έγραψε ποιον**: εκεί ο πελάτης του
   * γραφείου δεν διάλεξε ποτέ να φανεί· εδώ ο **οργανισμός δημοσίευσε τον εαυτό του**.
   */
  readonly companyId: string;
  /**
   * Το ψευδώνυμο **τη στιγμή της δημοσίευσης** — για να χτίζεται ο σύνδεσμος χωρίς
   * αντίστροφη αναζήτηση *(που θα ήταν σάρωση — δες `resolveAlias`, όπου το
   * `canonicalAlias` επιστρέφει `null` ακριβώς γι' αυτόν τον λόγο)*.
   *
   * ⚠️ **Αντίγραφο, όχι αυθεντία.** Η αυθεντία μένει το `workspace_aliases`· αν
   * αποκλίνει, η σημειακή ανάγνωση κατά ψευδώνυμο εξακολουθεί να λύνει σωστά.
   */
  readonly alias: string;
  /** Η **επωνυμία**. Ίδια πηγή με το `PublicListing.agencyName`. */
  readonly displayName: string;
  /**
   * **ΤΙ ΠΡΟΣΦΕΡΕΙ, ΚΑΙ Η ΑΠΟΔΕΙΞΗ ΤΟΥ.** Πίνακας — ώστε το **μικτό γραφείο** να
   * είναι **εκφράσιμο** αντί για ειδική περίπτωση *(ADR-824 §4.1)*.
   *
   * ⚠️ **Ποτέ κενός.** Ο γραφέας απορρίπτει βιτρίνα χωρίς credential: θα ήταν
   * κάρτα **χωρίς καμία απόδειξη**, δηλαδή ο κατάλογος που το `agency-profile.ts`
   * ονόμαζε *«επικίνδυνο αντί για χρήσιμο»*. Ο τύπος δεν το εκφράζει *(ένας
   * `readonly [T, ...T[]]` θα ταλαιπωρούσε κάθε αναγνώστη για να φυλάξει τον
   * **έναν** γραφέα)* — το φυλά ο γραφέας, με **ονομασμένη** απόρριψη.
   */
  readonly credentials: readonly ShowcaseCredential[];
  /**
   * Πού δραστηριοποιείται — **ΑΝΑΦΟΡΑ** στη γη, ώστε το {@link position} να είναι
   * επισκευάσιμο *(Α1.6)*.
   *
   * ⛔ **ΠΟΤΕ εμπορική σειρά.** Δες την απαγόρευση παρακάτω.
   */
  readonly place: PlaceRef | null;
  /**
   * 🔴 **ΑΠΟΚΑΝΟΝΙΚΟΠΟΙΗΜΕΝΗ ΓΕΩΜΕΤΡΙΑ — ΤΟ ΦΙΛΤΡΟ ΠΕΡΙΟΧΗΣ ΤΗΝ ΑΠΑΙΤΕΙ.**
   *
   * Το `place` είναι **ξένο κλειδί** σε `public_lands/{landId}`: φιλτράρισμα
   * πάνω του κοστίζει **μία ανάγνωση ανά γραμμή** σε **ανώνυμη, δημόσια** σάρωση.
   * Το `PublicListing` έλυσε το ίδιο πρόβλημα με τον ίδιο τρόπο — κουβαλά **ΚΑΙ**
   * `position` **ΚΑΙ** `place`. Δεύτερος καταναλωτής του προτύπου, καμία νέα ιδέα.
   *
   * ⚠️ `null` = *«δεν δήλωσε τόπο»*, **ΠΟΤΕ** `{lat:0,lng:0}` — σημείο στον
   * Ατλαντικό που κάθε χάρτης ζωγραφίζει **με απόλυτη σιγουριά**.
   *
   * 🔴 **ΑΠΑΝΤΑ «ΠΟΥ ΚΑΘΕΣΑΙ», ΟΧΙ «ΠΟΥ ΔΟΥΛΕΥΕΙΣ»** *(ADR-846)*. Το δεύτερο το λέει
   * πλέον το {@link PublicShowcase.coverage}, και τα δύο **δεν** συγχέονται: αυτό εδώ
   * είναι **επαληθεύσιμο** *(παράγεται από τη γη, `showcase-request.ts::locate`)* και
   * τροφοδοτεί τη **σειρά**· εκείνο είναι **δήλωση** και τροφοδοτεί **μόνο** το φίλτρο.
   *
   * ⛔ **ΚΑΜΙΑ ΑΚΤΙΝΑ ΕΞΥΠΗΡΕΤΗΣΗΣ ΓΥΡΩ ΑΠΟ **ΑΥΤΟ** ΤΟ ΣΗΜΕΙΟ** — και η Φάση 2 **δεν
   * το άλλαξε**: το `RadiusCoverage` έχει **δικό του** κέντρο, που ορίζει ο άνθρωπος και
   * μπορεί να είναι **αλλού από την έδρα** *(ο Θερμαίος που δουλεύει γύρω από τα Νέα
   * Μουδανιά)*. Μια ακτίνα καρφωμένη εδώ θα ήταν μαντεψιά για λογαριασμό του· δες #6.
   */
  readonly position: GeoPoint | null;
  /**
   * 🏆 **ΠΟΥ ΔΟΥΛΕΥΕΙ — Η ΔΗΛΩΜΕΝΗ ΕΜΒΕΛΕΙΑ** *(ADR-846)*.
   *
   * Σύνολο διοικητικών οντοτήτων σε **οποιοδήποτε** από τα 8 επίπεδα του Καλλικράτη, ή
   * *«όλη η Ελλάδα»*. `null` = **δεν δήλωσε** — τον βρίσκουν από την ειδικότητα, όχι από
   * τον τόπο.
   *
   * 🔴 **ΤΟ ΕΛΑΤΤΩΜΑ ΠΟΥ ΘΕΡΑΠΕΥΕΙ, ΜΕ ΟΝΟΜΑΤΑ**: ο μπετατζής με έδρα στη **Θέρμη** που
   * δουλεύει τη **Χαλκιδική** ήταν **δομικά** αόρατος σε επισκέπτη της Κασσάνδρας, όσο
   * το μόνο γεωγραφικό δεδομένο ήταν η έδρα του. Δεν ήταν σπάνια περίπτωση — σε κάθε
   * τεχνικό επάγγελμα είναι ο **κανόνας**.
   *
   * ⛔ **ΔΕΝ ΤΑΞΙΝΟΜΕΙ, ΠΟΤΕ.** Το `agency-directory-order.ts` δεν το διαβάζει, και
   * υπάρχει άγκυρα που το **μετρά** *(ίδια σειρά με και χωρίς `coverage`)*. Όποιος
   * δηλώσει «όλη η Ελλάδα» **δεν κερδίζει καμία θέση** — κατατάσσεται πάντα με την
   * **πραγματική** απόσταση της έδρας του, ή ισότιμα με όλους όταν δεν υπάρχει σημείο.
   *
   * @see {@link module:types/agency-coverage} για το σκεπτικό του σχήματος και το
   *   μετρημένο κόστος που απέρριψε την αποθηκευμένη επέκταση υποδέντρου.
   */
  readonly coverage: DeclaredCoverage | null;
  /**
   * 🏆 **ΠΟΥ ΕΧΕΙ ΑΠΟΔΕΔΕΙΓΜΕΝΑ ΑΚΙΝΗΤΟ** — η **δεύτερη μαρτυρία** *(ADR-846 Φ5δ, §8.8.15)*.
   *
   * ═════════════════════════════════════════════════════════════════════════════
   * 🔴 ΠΑΡΑΓΩΓΟ ΜΕ **ΕΝΑΝ** ΓΡΑΦΕΑ — **ΠΟΤΕ** ΠΗΓΗ ΑΛΗΘΕΙΑΣ
   * ═════════════════════════════════════════════════════════════════════════════
   *
   * Το §8.8.7 απορρίπτει ρητά *«αποθήκευση του `EvidencedCoverage` ως αλήθεια»*: δεύτερο
   * αντίγραφο ⇒ **ADR-749** γεννημένο εκ νέου. Αυτό εδώ **δεν** είναι εξαίρεση — είναι ο
   * όρος υπό τον οποίο επιτρέπεται: **ξαναχτίζεται από το μηδέν** από τις ζωντανές
   * αγγελίες, έχει **έναν** γραφέα *(`showcase-presence.service.ts`)*, και **κανείς** δεν
   * το διαβάζει ως πηγή — οι Φ5α/5β/5γ ρωτούν **πάντα** τις ίδιες τις αγγελίες.
   *
   * ⚠️ **Υπάρχει επειδή ο κατάλογος ΔΕΝ ΜΠΟΡΕΙ να τις ρωτήσει**: το `usePublicAgencies`
   * κάνει ωμό `onSnapshot(collection(…))` σε **κάθε ανώνυμο επισκέπτη** *(§4.2)*, και
   * ανάγνωση αγγελιών από πάνω πολλαπλασιάζει **ακριβώς** αυτό που το §4.2 απέρριψε.
   *
   * ═════════════════════════════════════════════════════════════════════════════
   * 🏆 ΚΥΚΛΟΙ ΚΑΙ ΟΧΙ ΣΗΜΕΙΑ — Η ΑΒΕΒΑΙΟΤΗΤΑ ΤΑΞΙΔΕΥΕΙ ΜΑΖΙ ΤΟΥΣ
   * ═════════════════════════════════════════════════════════════════════════════
   *
   * Κάθε στοιχείο είναι **ακριβώς** ό,τι επιστρέφει το `listingSearchArea` *(ADR-777
   * §8.63)*: *«πού **μπορεί** να βρίσκεται αυτή η αγγελία»*, **μαζί με το μέγεθος της
   * άγνοιάς μας** *(`pin`/`outline` = 0 · δρόμος = 0,25 · συνοικία = 1,5 · **μόνο πόλη =
   * 10 χλμ**)*.
   *
   * 🔴 **Σκέτο σημείο θα ήταν ισχυρισμός παρουσίας ΧΩΡΙΣ ΑΠΟΔΕΙΞΗ.** Αγγελία γνωστή μόνο
   * σε επίπεδο πόλης, αποθηκευμένη ως σημείο, θα εμφάνιζε το γραφείο σε **κάθε δήμο που
   * αγγίζει ο κύκλος** — σε **δημόσιο** κατάλογο, για λογαριασμό τρίτου. Το Zillow κάνει
   * ακριβώς αυτό *(σύγκριση ΤΚ με ΤΚ)*.
   *
   * 🔑 **Η ΑΣΥΜΜΕΤΡΙΑ ΕΙΝΑΙ ΤΟ ΝΟΗΜΑ**: στις Φ5α/5β/5γ η αβεβαιότητα **διευρύνει την
   * αμφιβολία** *(δεν κατηγορούμε τον επαγγελματία για δικό μας κενό)*· εδώ **δεν
   * επιτρέπεται να διευρύνει την παρουσία**. **Ίδια αρχή** *(«ποτέ ψεύτικος ισχυρισμός»)*,
   * **αντίθετη φορά** — γι' αυτό η ένωση απαιτεί `within`, ποτέ `intersects`.
   *
   * ═════════════════════════════════════════════════════════════════════════════
   * ⛔ ΣΥΝΟΛΟ, ΟΧΙ ΛΙΣΤΑ — ΚΑΙ ΕΙΝΑΙ ΑΝΤΙΜΟΝΟΠΩΛΙΑΚΟ, ΟΧΙ ΒΕΛΤΙΣΤΟΠΟΙΗΣΗ
   * ═════════════════════════════════════════════════════════════════════════════
   *
   * Οι κύκλοι είναι **απορροφημένοι**: ό,τι περιέχεται σε άλλον **φεύγει**. Άρα το πεδίο
   * λέει **πού**, και **δεν μπορεί** να πει **πόσα**. Μία εγγραφή ανά αγγελία θα κουβαλούσε
   * **πλήθος αποθέματος ανά περιοχή** — δηλαδή **έτοιμο διάνυσμα κατάταξης**, ακριβώς το
   * *«όποιος έχει αποδεδειγμένα τα περισσότερα, πρώτος»* που το §8.8.8 ονομάζει **NAR
   * σχήμα με το πιο πειστικό δυνατό πρόσωπο**. Δεύτερος φρουρός: το `'presence'` είναι
   * γραμμένο στη λίστα `forbidden` του `agency-directory-order.test.ts` **Α1**.
   *
   * ⚠️ **`[]` και ΟΧΙ `null`.** Το `coverage` χρησιμοποιεί `null` για *«ο άνθρωπος δεν
   * δήλωσε»* — **πράξη**. Εδώ δεν υπάρχει πράξη να λείψει: το κενό σύνολο σημαίνει
   * *«καμία απόδειξη»*, και είναι **μία** αναπαράσταση, όχι δύο.
   *
   * @see {@link MAX_PRESENCE_AREAS} για το ταβάνι και τη δηλωμένη πολιτική υπέρβασης.
   */
  readonly presence: readonly GeoCircle[];
  /**
   * 🏆 **ΤΟ ΔΗΛΩΜΕΝΟ ΣΗΜΑ** — λογότυπο ή πορτρέτο, ή `null` (ADR-841 §7 Α21, Στάδιο 2).
   *
   * ⚠️ **`null` δεν σημαίνει «ανώνυμος»**, και αυτό είναι ολόκληρη η Α21: όποιος δεν
   * δήλωσε παίρνει το **παραγόμενο** `lettermark` *(`lib/agency/showcase-mark`)*. Η
   * έρευνα μέτρησε ότι η **γενική γκρι σιλουέτα** είναι χειρότερη ακόμη και από άσχημη
   * εικόνα — άρα η εφεδρεία **δεν αποτυγχάνει ποτέ**, και το πεδίο μπορεί με ησυχία να
   * λείπει.
   *
   * ⛔ **ΚΑΜΙΑ ΑΥΤΟΜΑΤΗ ΑΝΤΙΓΡΑΦΗ** από `companies/{id}.logoURL` ή `users/{uid}` —
   * σκοπός Α σε δεδομένο συλλεγμένο για σκοπό Β *(δες #3 παρακάτω)*. Το
   * `company-branding-resolver` **τα διαβάζει**, αλλά για **εσωτερικό branding PDF**·
   * η δημοσίευση θέλει **ρητή** πράξη.
   *
   * ⛔ **ΚΑΜΙΑ ΣΦΡΑΓΙΔΑ «ΕΠΑΛΗΘΕΥΜΕΝΟ ΛΟΓΟΤΥΠΟ»** — Α9.2 · **DSA άρθ. 6(3)**: η
   * απαλλαγή του άρθ. 6 χάνεται όταν η **παρουσίαση** παραπλανά ως προς την
   * **προέλευση**. Το σήμα είναι **αυτο-δηλωμένος ισχυρισμός**, και μια σφραγίδα θα
   * απαιτούσε και διαδρομή **αναγγελίας** *(άρθ. 16)*.
   */
  readonly mark: DeclaredShowcaseMark | null;
  /** ISO — πότε δημοσιεύτηκε η βιτρίνα. */
  readonly publishedAt: string;
}

