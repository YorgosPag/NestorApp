/**
 * **Πόσο μακριά έφτασε η αναζήτηση** — τρεις τιμές, και η τρίτη **δεν** είναι η πρώτη.
 *
 * 🔴 **`not-published` και `unavailable` ΔΕΝ συγχωνεύονται** (N.12 · Ε-5 §4 #3):
 * *άγνωστο ≠ κενό*. Προς τα **έξω** και τα δύο δείχνουν «δεν υπάρχει» — αυτό είναι το
 * §9.4 — αλλά ο **κώδικας** οφείλει να τα ξεχωρίζει, αλλιώς μια βλάβη Firestore
 * καταγράφεται ως απόσυρση γραφείου και κανείς δεν το μαθαίνει ποτέ.
 */
export type PublicShowcaseLookup =
  | { readonly outcome: 'found'; readonly showcase: PublicShowcase }
  | { readonly outcome: 'not-published' }
  | { readonly outcome: 'unavailable' };

/**
 * **Είναι δημοσιευμένο;** — και η απάντηση είναι η **ύπαρξη**, όχι σημαία.
 *
 * ⛔ **ΚΑΝΕΝΑ πεδίο `isPublished` / `acceptsRequests`.** Θα ήταν σημαία που μπορεί να
 * διαφωνήσει με την ύπαρξη του εγγράφου — **ADR-749** σε δύο γραμμές απόσταση.
 * **Απόσυρση = διαγραφή του εγγράφου.**
 */
export function isPublishedProfile(lookup: PublicShowcaseLookup): boolean {
  return lookup.outcome === 'found';
}

