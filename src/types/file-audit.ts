/**
 * =============================================================================
 * ΤΟ ΛΕΞΙΛΟΓΙΟ ΤΟΥ ΙΧΝΟΥΣ ΑΡΧΕΙΟΥ — **ανεξάρτητο SDK** (ADR-191 · ADR-862 Φ0 Β6)
 * =============================================================================
 *
 * **Το ερώτημα**: *«Τι λέει μια γραμμή του `file_audit_log`;»* — και **μόνο** αυτό.
 * Ποιος τη γράφει (πελάτης ή διακομιστής) είναι **άλλο** ερώτημα, και ζει αλλού.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΧΡΕΙΑΣΤΗΚΕ — Ο ΤΥΠΟΣ ΗΤΑΝ ΔΕΜΕΝΟΣ ΣΤΟΝ ΠΕΛΑΤΗ (μετρημένο 2026-09-16)
 * ─────────────────────────────────────────────────────────────────────────────
 * Το `FileAuditEntry` ζούσε μέσα στο `services/file-audit.service.ts` και δήλωνε
 * `timestamp: ReturnType<typeof serverTimestamp>` — δηλαδή τον **`FieldValue` του
 * client SDK**. Ένας `server-only` γραφέας (Admin SDK) **δεν μπορεί** να τον
 * ικανοποιήσει: το `FieldValue` του `firebase-admin/firestore` είναι **άλλη κλάση**.
 *
 * ⇒ Ο τύπος ήταν **ακούσιο σύνορο**: όποιος έγραφε από τον διακομιστή δεν είχε πώς
 * να τον εισαγάγει, οπότε **δεν τον εισήγαγε**. Το αποτέλεσμα μετρήθηκε:
 *
 *   **ΠΕΝΤΕ** χειρόγραφα admin-side δίδυμα του `FileAuditService.log`, όλα
 *   `db.collection(FILE_AUDIT_LOG).doc(generateAuditId()).set({…})`:
 *     · `api/files/archive/route.ts:108`
 *     · `api/files/classify/classify-background.ts:150`
 *     · `api/files/gdpr-delete/route.ts:150`
 *     · `api/files/purge/route.ts:115`
 *     · `services/file-record/file-purge-helpers.ts:109`
 *
 * 🔴 **ΚΑΙ ΑΠΕΚΛΙΝΑΝ — ΔΥΟ ΤΥΠΟΙ ΣΤΟ ΙΔΙΟ ΠΕΔΙΟ**: τα πέντε γράφουν
 * `timestamp: nowISO()` (**συμβολοσειρά**), η υπηρεσία `serverTimestamp()`
 * (**Timestamp**) — ίδια συλλογή, ίδιο πεδίο, δύο τύποι.
 *
 * 🔴 **ΚΑΙ ΤΟ ΧΕΙΡΟΤΕΡΟ**: τα `archive` και `purge` **δεν γράφουν `companyId`**, ενώ ο
 * **μοναδικός** αναγνώστης (`FileAuditService.getFileHistory`) ρωτά
 * `where('companyId','==',…)`. Δηλαδή εκείνες οι γραμμές ίχνους είναι **δομικά
 * αόρατες σε κάθε άνθρωπο**: γράφονται, κοστίζουν, και κανείς δεν μπορεί ποτέ να τις
 * δει. Το σχήμα «`0` = κανείς δεν κοίταξε», **μέσα σε audit trail**.
 *
 * ⚠️ **Η θεραπεία των πέντε ΔΕΝ γίνεται εδώ** (N.0.2: 5 αρχεία, >1h ⇒ `pending-ratchet-work.md`).
 * Εδώ γεννιέται **το σύνορο που τους επιτρέπει να μεταναστεύσουν**.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΟ `timestamp` ΔΕΝ ΕΙΝΑΙ ΕΔΩ, ΚΑΙ ΕΙΝΑΙ Η ΟΛΗ ΑΠΟΦΑΣΗ
 * ─────────────────────────────────────────────────────────────────────────────
 * Αυτός ο τύπος περιγράφει ό,τι είναι **κοινό σε κάθε γραφέα**. Η χρονοσήμανση είναι
 * το **μόνο** πεδίο που δεν μπορεί να είναι κοινό — κάθε SDK έχει δικό του `FieldValue`.
 * Κάθε γραφέας επεκτείνει με τον **δικό του** τύπο χρόνου:
 *
 *   πελάτης    → `& { timestamp: ReturnType<typeof serverTimestamp> }`  (firebase/firestore)
 *   διακομιστής → `& { timestamp: FieldValue }`                          (firebase-admin)
 *
 * ⛔ **ΜΗΝ το «λύσεις» με `timestamp: unknown`**: θα δεχόταν `nowISO()` — ακριβώς την
 * απόκλιση που μετρήθηκε παραπάνω — και ο μεταγλωττιστής θα σιωπούσε.
 *
 * @module types/file-audit
 * @enterprise ADR-191 §3.1 — Enterprise Document Management (ίχνος αρχείων)
 * @compliance ISO 27001 §A.12.4 (Logging and Monitoring)
 * @see services/file-audit.service       — ο γραφέας/αναγνώστης του **πελάτη**
 * @see services/file-audit-admin.service — ο γραφέας του **διακομιστή** (Admin SDK)
 */

