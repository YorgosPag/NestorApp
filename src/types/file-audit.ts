/**
 * Το πρόσθετο πλαίσιο μιας εγγραφής — **επίπεδο**, ποτέ ένθετο.
 *
 * ⚠️ Το Firestore απορρίπτει `undefined`· επιτρέπεται `null`. Οι γραφείς **δεν**
 * βασίζονται σε καθαριστή: χτίζουν το αντικείμενο με conditional spread, ώστε η
 * απουσία να είναι **ιδιότητα της κατασκευής** και όχι παρενέργεια καθαρίσματος.
 */
export type FileAuditMetadata = Record<string, string | number | boolean | null>;

/**
 * Ό,τι είναι **κοινό σε κάθε γραφέα** του `file_audit_log`.
 *
 * 🔑 **Το `companyId` ΔΕΝ είναι διακοσμητικό — είναι το κλειδί ανάγνωσης.** Ο μοναδικός
 * αναγνώστης ρωτά `where('companyId','==',…)`· εγγραφή χωρίς αυτό **δεν μπορεί να
 * διαβαστεί ποτέ από κανέναν**. Μένει προαιρετικό στον **τύπο** επειδή ο σημερινός
 * πελάτης το επιλύει μόνος του όταν λείπει (`file-audit.service.ts:144-153`) — αλλά ο
 * γραφέας του διακομιστή **αρνείται** χωρίς αυτό, με το ίδιο σκεπτικό που ο
 * `EntityAuditService` αρνείται εγγραφή χωρίς κάτοχο βιβλίου (ADR-864 Φ1β).
 */
export interface FileAuditRecordFields {
  /** Το αρχείο που αφορά. */
  readonly fileId: string;
  /** Τι έγινε. */
  readonly action: FileAuditAction;
  /** Ποιος το έκανε — `uid`, ή ονομασμένος αυτοματισμός (π.χ. `'system:purge'`). */
  readonly performedBy: string;
  /** Ο μισθωτής. Δες παραπάνω γιατί η απουσία του είναι **αοράτη** εγγραφή. */
  readonly companyId?: string;
  /** Πρόσθετο πλαίσιο, επίπεδο. */
  readonly metadata?: FileAuditMetadata;
}
