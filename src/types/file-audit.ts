/**
 * Κάθε πράξη αρχείου που καταγράφεται.
 *
 * ⚠️ **ΤΟ `'share'` ΕΙΝΑΙ ΠΙΑΣΜΕΝΟ, ΚΑΙ ΣΗΜΑΙΝΕΙ ΑΛΛΟ ΠΡΑΓΜΑ** (μετρημένο 2026-09-16):
 * το γράφει το `file-share.service.ts:207` και σημαίνει **σύνδεσμο κοινοποίησης** —
 * καμία σχέση με την παράδοση `WIP → SHARED` του ISO 19650. Γι' αυτό οι τέσσερις
 * πράξεις του δοχείου (Β6) φέρουν **δικό τους πρόθεμα** `cde_`.
 *
 * 🔑 Χωρίς το πρόθεμα, το `AuditLogPanel` θα έδειχνε **δύο εντελώς διαφορετικά
 * γεγονότα** στην ίδια γραμμή, και ο άνθρωπος δεν θα είχε τρόπο να τα ξεχωρίσει.
 */
export type FileAuditAction =
  // ── Κύκλος ζωής αρχείου (ADR-191) ─────────────────────────────────────────
  | 'view'
  | 'download'
  | 'upload'
  | 'finalize'
  | 'rename'
  | 'description_update'
  | 'classify'
  | 'ai_classify'
  | 'delete'
  | 'restore'
  | 'archive'
  | 'version_create'
  | 'version_rollback'
  | 'link'
  | 'unlink'
  | 'batch_delete'
  | 'batch_download'
  | 'batch_classify'
  /** ⚠️ **Σύνδεσμος κοινοποίησης** (`file-share.service`) — ΟΧΙ η παράδοση του CDE. */
  | 'share'
  | 'hold_place'
  | 'hold_release'
  | 'approval_request'
  | 'approval_approve'
  | 'approval_reject'
  | 'approval_cancel'
  | 'comment'
  | 'move'
  // ── ΟΙ ΤΕΣΣΕΡΙΣ ΠΡΑΞΕΙΣ ΤΟΥ ΔΟΧΕΙΟΥ (ADR-862 Φ0 Β6 · ISO 19650 §10.2) ──────
  /** 📤 Η **παράδοση** `WIP → SHARED` (ADR-787 Α5: *η μετάβαση ΕΙΝΑΙ η παράδοση*). */
  | 'cde_share'
  /** ✍️ **Σκαλοπάτι 1** — η σφραγίδα του **δημιουργού**. Νομική πράξη (ADR-862 Ε-12). */
  | 'cde_seal'
  /** 🏗️ **Σκαλοπάτι 2** — η απελευθέρωση του **συντονιστή** ⇒ `PUBLISHED`. */
  | 'cde_release'
  /** ↩️ Η **απόσυρση** ⇒ `SUPERSEDED`. **ΠΟΤΕ** εξαφάνιση. */
  | 'cde_withdraw'
  /** 🔁 Η **αντικατάσταση** από νέα έκδοση ⇒ `SUPERSEDED` + αρχειοθέτηση (ADR-862 Φ0 Β10). */
  | 'cde_supersede';

