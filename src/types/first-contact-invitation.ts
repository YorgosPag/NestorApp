// 3. ΓΙΑΤΙ ΔΕΝ ΕΞΑΡΓΥΡΩΘΗΚΕ — ονομασμένοι λόγοι, ΠΟΤΕ `boolean`
// =============================================================================

/**
 * 🔑 **Ονομασμένοι λόγοι επειδή ο ΠΑΡΑΛΗΠΤΗΣ τους διαβάζει**, και καθένας τον
 * στέλνει σε **διαφορετική** ενέργεια: *«έληξε»* ⇒ ξαναζήτα · *«ήδη
 * χρησιμοποιήθηκε»* ⇒ **έγινε**, μην ξαναπροσπαθήσεις · *«λάθος κωδικός»* ⇒
 * ξαναδές το email · *«αντικαταστάθηκε»* ⇒ ψάξε το **νεότερο** μήνυμα.
 *
 * ⛔ Ένα κοινό «άκυρος σύνδεσμος» θα έλεγε σε αθώο άνθρωπο ότι κάποιος τον
 * εξαπατά, ενώ απλώς άργησε τρεις μέρες — ίδιο μάθημα με το
 * `lib/tokens/signed-token.ts`.
 */
export const FIRST_CONTACT_INVITATION_REFUSALS = [
  /** Η υπογραφή δεν στέκει, ή το κείμενο δεν είναι σύνδεσμός μας. */
  'link-invalid',
  /** Ο σύνδεσμος υπάρχει αλλά δεν βρέθηκε πρόσκληση — σβήστηκε ή δεν γράφτηκε ποτέ. */
  'invitation-unknown',
  'expired',
  /** **Επιτυχία στο παρελθόν**, όχι αποτυχία τώρα. Η οθόνη το λέει ήρεμα. */
  'already-used',
  'superseded',
  'code-wrong',
  /** Εξαντλήθηκαν οι δοκιμές· η πρόσκληση κλείδωσε. */
  'code-exhausted',
] as const;

export type FirstContactInvitationRefusal =
  (typeof FIRST_CONTACT_INVITATION_REFUSALS)[number];

export function isFirstContactInvitationRefusal(
  value: unknown,
): value is FirstContactInvitationRefusal {
  return typeof value === 'string'
    && (FIRST_CONTACT_INVITATION_REFUSALS as readonly string[]).includes(value);
}
