/**
 * @fileoverview **Η ΠΡΟΣΚΛΗΣΗ** — ό,τι δεν είναι ακόμη πράξη.
 * @related ADR-844 · ADR-843 §10.18 Η · types/first-contact.ts
 * @module types/first-contact-invitation
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ ΞΕΧΩΡΙΣΤΟ ΕΓΓΡΑΦΟ, ΚΑΙ ΟΧΙ ΤΡΙΤΗ ΚΑΤΑΣΤΑΣΗ ΣΤΗΝ ΠΡΑΞΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η προφανής σχεδίαση ήταν `lifecycle: 'pending-verification'` πάνω στο
 * {@link FirstContact}. **Είναι λάθος, και ο λόγος είναι αριθμητικός:**
 *
 * Η χωρητικότητα των **10 ανοιχτών** (ΠΕ5/Κ5/Κ9) μετρά με άξονα το
 * `seekerUserId` — πεδίο δηλωμένο **ΑΜΕΤΑΒΛΗΤΟ** *(«πράξη που αλλάζει
 * ιδιοκτήτη μεταφέρει ΚΑΙ τη θέση που καταλαμβάνει»)*. Τη στιγμή που ο
 * ανώνυμος πατά «αποστολή», **αυτός ο άνθρωπος δεν έχει ακόμη λογαριασμό**.
 *
 * ⇒ Μια «εκκρεμής πράξη» θα ήταν έγγραφο **με κενό τον άξονα που το μετρά**.
 * Δηλαδή: άπειρη χωρητικότητα — ακριβώς η παράκαμψη του ΠΕ5 *(«πατώντας
 * αποσύνδεση»)* που το ADR-843 §10.18 Η απέρριψε ονομαστικά.
 *
 * 🔑 **Εδώ παρκάρει η ΔΗΛΩΣΗ. Η ΠΡΑΞΗ γεννιέται μόνο μετά την απόδειξη**, από
 * τον **ίδιο** γραφέα (`openFirstContact`) με τον **ίδιο** κριτή
 * (`admitFirstContact`). Άρα: **1.000 προσκλήσεις ⇒ το πολύ 10 ανοιχτές πράξεις.**
 *
 * ⚠️ **ΚΑΙ ΓΙ' ΑΥΤΟ ΤΟ `types/first-contact.ts` ΔΕΝ ΑΛΛΑΖΕΙ ΟΥΤΕ ΚΑΤΑ ΕΝΑ ΠΕΔΙΟ.**
 * Ούτε οι δύο προβολές, ούτε το `readStoredLifecycle`, ούτε ο κανόνας Firestore,
 * ούτε καμία από τις άγκυρές του.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⏳ ΕΦΗΜΕΡΟ ΕΞ ΟΡΙΣΜΟΥ — ΤΟ ΑΝΤΙΘΕΤΟ ΤΗΣ ΠΡΑΞΗΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η πράξη **επιβιώνει της απόσυρσης** *(ΠΕ6: «ανακαλείται η ΣΧΕΣΗ, ποτέ η
 * ΙΣΤΟΡΙΑ»)*. Η πρόσκληση **όχι**, και δεν είναι ασυνέπεια: μια πρόσκληση που
 * δεν πατήθηκε ποτέ **δεν γέννησε σχέση** — ο ιδιοκτήτης δεν έμαθε ποτέ ότι
 * υπήρξε. Δεν υπάρχει ιστορία δύο ανθρώπων να προστατευτεί, γιατί **δεν
 * συναντήθηκαν ποτέ**. Λήγει και σβήνεται.
 *
 * **Layering**: leaf — καθαροί τύποι. Καμία εξάρτηση από Firestore/ρολόι/React.
 */

import type { FirstContactDeclaration } from '@/services/contact/first-contact-vocabulary';

// =============================================================================
// 1. Η ΚΑΤΑΣΤΑΣΗ
// =============================================================================

/**
 * ⚠️ **Ο ΠΙΝΑΚΑΣ ΕΙΝΑΙ Η ΑΥΘΕΝΤΙΑ, Ο ΤΥΠΟΣ ΠΑΡΑΓΕΤΑΙ** — ίδιο μοτίβο με τα
 * `FIRST_CONTACT_LIFECYCLES`, `GLOBAL_ROLES`, `USER_STATUSES`. **Ένα** μοτίβο
 * σε αυτό το δέντρο.
 */
export const FIRST_CONTACT_INVITATION_STATES = [
  /** Στάλθηκε το email· περιμένει απόδειξη. Η **μόνη** κατάσταση που εξαργυρώνεται. */
  'sent',
  /** Εξαργυρώθηκε — η πράξη γεννήθηκε. **Τελική.** */
  'redeemed',
  /** Πέρασε η ώρα της χωρίς να πατηθεί. **Τελική.** */
  'expired',
  /**
   * Ο **ίδιος** άνθρωπος ξαναϋπέβαλε για τον **ίδιο** στόχο ⇒ αυτή έπαψε.
   *
   * 🔑 Υπάρχει ώστε να **μην** κυκλοφορούν ποτέ δύο ζωντανοί σύνδεσμοι για την
   * ίδια επαφή: ο άνθρωπος που πατά τον **παλιό** (γιατί τον βρήκε πρώτο στα
   * εισερχόμενα) πρέπει να μάθει *«αυτός αντικαταστάθηκε»*, όχι *«άκυρος»* —
   * δύο εντελώς διαφορετικά επόμενα βήματα.
   */
  'superseded',
] as const;

export type FirstContactInvitationState = (typeof FIRST_CONTACT_INVITATION_STATES)[number];

export function isFirstContactInvitationState(
  value: unknown,
): value is FirstContactInvitationState {
  return typeof value === 'string'
    && (FIRST_CONTACT_INVITATION_STATES as readonly string[]).includes(value);
}

/**
 * **Ανάγνωση αποθηκευμένης κατάστασης — fail-closed προς `expired`.**
 *
 * 🔴 **Η ΚΑΤΕΥΘΥΝΣΗ ΤΗΣ ΑΣΤΟΧΙΑΣ ΖΥΓΙΣΤΗΚΕ** (ίδιο ιδίωμα με το
 * `readStoredLifecycle`, αντίθετο συμπέρασμα για τον ίδιο λόγο):
 *
 * | Αν διαβαστεί ως | Το λάθος είναι |
 * |---|---|
 * | `sent` | **εξαργυρώνεται έγγραφο που δεν καταλάβαμε** — γεννά πράξη, στέλνει στοιχεία ανθρώπου |
 * | `expired` | ο άνθρωπος ξαναπατά «αποστολή» και παίρνει **νέο** σύνδεσμο |
 *
 * ⇒ Διαβάζεται **`expired`**: αποκάλυψη στοιχείων εναντίον **μιας επιπλέον
 * υποβολής**. Δεν είναι ισοπαλία.
 */
export function readStoredInvitationState(value: unknown): FirstContactInvitationState {
  return isFirstContactInvitationState(value) ? value : 'expired';
}

// =============================================================================
// 2. ΤΟ ΕΓΓΡΑΦΟ
// =============================================================================

/**
 * **Η πρόσκληση, ολόκληρη.** ⛔ **Δεν φτάνει ποτέ σε πελάτη** — `firestore.rules`
 * λέει `read: false` **και** `write: false`, όπως το `first_contacts`.
 */
export interface FirstContactInvitation {
  /** `fcin_*` — από το `enterprise-id.service`, **ποτέ** χειρόγραφο (N.6). */
  readonly id: string;
  /**
   * **Η δήλωση, αυτούσια** — ό,τι θα δοθεί στον γραφέα όταν αποδειχθεί το κανάλι.
   *
   * 🔑 **Ολόκληρη και όχι κατά πεδίο**: ο τύπος είναι ο **ίδιος** που δέχεται το
   * `openFirstContact`. Μια δεύτερη κυριολεκτική λίστα πεδίων εδώ θα ήταν
   * δεύτερη απόφαση για το «τι είναι δήλωση», και θα **απέκλινε** στην πρώτη
   * προσθήκη — σιωπηλά, χάνοντας ό,τι μόλις προστέθηκε.
   */
  readonly declaration: FirstContactDeclaration;
  /**
   * **Το κανάλι που αποδεικνύεται** — πεζά, χωρίς κενά.
   *
   * ⚠️ **Ξεχωριστό πεδίο, παρότι ζει ΚΑΙ μέσα στο `declaration.disclosure`**, και
   * δεν είναι διπλότυπο: εκείνο είναι *«τι δήλωσε ο άνθρωπος»* (και μπορεί να
   * έχει κεφαλαία, κενά, ή να αλλάξει σε επόμενη υποβολή)· **αυτό** είναι *«σε
   * ποια διεύθυνση στείλαμε την απόδειξη»* — το κλειδί ιδεμποτησίας και ο
   * παραλήπτης. Δύο ερωτήσεις, δύο πεδία.
   */
  readonly channelEmail: string;
  /** Η ταυτότητα **αυτού** του συνδέσμου — υπογράφεται, δεν αποθηκεύεται ωμή αλλού. */
  readonly nonce: string;
  /**
   * **Ο κωδικός ΠΟΤΕ ωμός** — μόνο το αποτύπωμά του.
   *
   * 🔴 Έξι ψηφία είναι **ένα εκατομμύριο** συνδυασμοί. Αποθηκευμένος ωμός, μια
   * ανάγνωση της βάσης θα έδινε **άμεση** πρόσβαση σε κάθε εκκρεμή επαφή. Με
   * αποτύπωμα, η ίδια διαρροή δεν δίνει τίποτα εκμεταλλεύσιμο.
   */
  readonly codeHash: string;
  /**
   * Πόσες φορές δοκιμάστηκε **λάθος** κωδικός.
   *
   * ⚠️ **Ο ΜΟΝΟΣ ΦΡΟΥΡΟΣ ΑΠΕΝΑΝΤΙ ΣΤΗΝ ΩΜΗ ΒΙΑ ΠΟΥ ΕΙΝΑΙ ΑΝΑ ΠΡΟΣΚΛΗΣΗ.** Το
   * rate limit είναι ανά **IP** και ο επιτιθέμενος αλλάζει IP· αυτό εδώ είναι
   * ανά **στόχο** και δεν αλλάζει με τίποτα.
   */
  readonly attempts: number;
  readonly state: FirstContactInvitationState;
  readonly createdAt: string;
  readonly expiresAt: string;
  readonly redeemedAt: string | null;
}

/**
 * Το έγγραφο **όπως διαβάζεται από τη βάση** — η κατάσταση είναι `string`.
 *
 * ⚠️ Ο τύπος **δεν λέει ψέματα για την είσοδο**: ένα `FirstContactInvitationState`
 * εδώ θα υποσχόταν εγγύηση που **κανείς δεν επιβάλλει** στο Firestore. Ίδιο
 * ιδίωμα με το `FirstContactDocument`.
 */
export type FirstContactInvitationDocument =
  Omit<FirstContactInvitation, 'state'> & { readonly state: string };

