/**
 * Η **ήδη επαληθευμένη** ταυτότητα, στο ελάχιστο σχήμα που χρειάζεται η κρίση.
 *
 * ⚠️ **ΔΕΝ ΕΠΑΛΗΘΕΥΕΤΑΙ ΕΔΩ.** Ο κριτής δέχεται ταυτότητα που **έχει ήδη
 * αποφασιστεί** (custom claims επαληθευμένα από τον Admin SDK, ή `AuthContext`
 * του `withAuth`). Δεν διαβάζει κανάλι, δεν εμπιστεύεται είσοδο πελάτη — γι'
 * αυτό **δεν** είναι αναγνώστης καναλιού του CHECK 3.58.
 *
 * 🔑 **ΓΙΑΤΙ `globalRole: string` ΚΑΙ ΟΧΙ `GlobalRole`** — και είναι μέτρηση,
 * όχι χαλάρωση: στην παραγωγή **υπάρχει** έγγραφο με `'admin'`, τιμή εκτός της
 * ένωσης-τύπου. Ένας τύπος `GlobalRole` εδώ θα **έλεγε ψέματα** για τα δεδομένα
 * που όντως φτάνουν, και ο μεταγλωττιστής θα έκρυβε ακριβώς την περίπτωση που
 * το `denied-unknown-role` υπάρχει για να **ονομάσει**.
 *
 * ⚠️ **Και τα τρία πεδία δέχονται `null | undefined`**: ο πελάτης εκπροσωπεί την
 * απουσία με `undefined` (`FirebaseAuthUser.globalRole?: string`) ενώ το προφίλ
 * με `null` (`users/{uid}.globalRole: string | null`). Τύπος που δέχεται μόνο το
 * ένα αναγκάζει **κάθε** καλούντα σε δική του κανονικοποίηση — δηλαδή γεννά ξανά
 * τη σκορπισμένη απόφαση που αυτό το αρχείο μαζεύει.
 */
export interface CapabilitySubject {
  /** Το claim του ρόλου. Απόν ⇒ ταυτότητα χωρίς ρόλο (νόμιμη κατάσταση). */
  readonly globalRole?: string | null;
  /** Τα ρητά δοσμένα permissions του claim. */
  readonly permissions?: readonly string[] | null;
  /** Ο οργανισμός — **πληροφορία**, όχι κριτήριο εδώ (το κρίνει το ADR-787). */
  readonly companyId?: string | null;
}

