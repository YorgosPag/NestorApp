/**
 * Οι **επτά** ρητές ετυμηγορίες. Καμία σιωπηλή, καμία `boolean`.
 *
 * ⚠️ **ΓΙΑΤΙ ΟΧΙ `boolean`**: ένα `false` δεν λέει **γιατί**, οπότε ο καλών δεν
 * μπορεί ούτε να το εξηγήσει στον άνθρωπο ούτε να το ξεχωρίσει από σφάλμα. Το
 * `denyReason` υπήρχε **ήδη** στον πίνακα του DXF viewer
 * (`text-edit-capabilities.ts`) — εδώ γίνεται καθολικό.
 *
 * 🔶 **ΤΟ `break-glass` ΔΕΝ ΕΙΝΑΙ ΕΔΩ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ.** Ανήκει στη Φάση 2
 * (server-only, με audit). Γραμμένο **σήμερα** θα ήταν φρουρός με **μηδέν
 * πληθυσμό** — προσθήκη στους 606 αδρανείς του ADR-749 §5. Μπαίνει όταν
 * αποκτήσει καταναλωτή, όχι πριν.
 */
export type CapabilityVerdict =
  /** Ο ρόλος παρακάμπτει κάθε έλεγχο (`isBypass` — μόνο `super_admin`). */
  | 'granted-by-bypass'
  /** Το claim `permissions` περιέχει ρητά την ικανότητα. */
  | 'granted-by-permission'
  /** Ο ρόλος τη δίνει μέσω `PREDEFINED_ROLES`. */
  | 'granted-by-role'
  /** Δεν υπάρχει ταυτότητα — ανώνυμος. */
  | 'denied-unauthenticated'
  /** Υπάρχει ταυτότητα, δεν έχει την ικανότητα. Η **κανονική** άρνηση. */
  | 'denied-insufficient'
  /**
   * 🔴 Ο ρόλος **δεν υπάρχει στο λεξιλόγιο**.
   *
   * ⚠️ **ΔΕΝ είναι θεωρητική.** Μετρημένο στην παραγωγή 2026-08-24: το έγγραφο
   * `users/dev-admin` φέρει `globalRole: 'admin'` — τιμή που το
   * `isValidGlobalRole()` **απορρίπτει** και που δεν υπάρχει ούτε στα
   * `GLOBAL_ROLES` ούτε στα `PREDEFINED_ROLES`. Χωρίς **δική της** κατάσταση, η
   * περίπτωση θα έπεφτε σιωπηλά στο `denied-insufficient` και κανείς δεν θα
   * μάθαινε ποτέ ότι υπάρχει ταυτότητα που το σύστημα **δεν καταλαβαίνει**.
   */
  | 'denied-unknown-role'
  /**
   * 🔴 Η **ικανότητα** δεν υπάρχει στο μητρώο `PERMISSIONS` — fail-closed.
   *
   * ⚠️ **ΚΡΙΝΕΤΑΙ ΠΡΩΤΗ, ΠΡΙΝ ΑΚΟΜΑ ΚΑΙ ΑΠΟ ΤΟ `granted-by-bypass`**, και αυτό
   * είναι σημείο όπου ξεπερνάμε τον υπάρχοντα κώδικα: αν το τυπογραφικό
   * `'dfx:view'` περνούσε για τον `super_admin`, ο προγραμματιστής (που **είναι**
   * super_admin) θα το έβλεπε να δουλεύει και **κάθε άλλος χρήστης** θα έπαιρνε
   * άρνηση — το χειρότερο είδος σφάλματος, γιατί δουλεύει ακριβώς για όποιον
   * μπορεί να το διορθώσει.
   */
  | 'denied-unknown-action';

/**
 * Οι ετυμηγορίες που **επιτρέπουν**.
 *
 * ⚠️ Καμία `denied-*` δεν είναι εδώ, **ούτε ως προσωρινή ανοχή**. Πρότυπο
 * `ALLOWING_VERDICTS` του ADR-787: μια αποτυχία που διαβάζεται ως άδεια είναι
 * διαρροή.
 */
export const GRANTING_VERDICTS: readonly CapabilityVerdict[] = [
  'granted-by-bypass',
  'granted-by-permission',
  'granted-by-role',
] as const;

/** Επιτρέπει αυτή η ετυμηγορία την πράξη; */
export function isGranted(verdict: CapabilityVerdict): boolean {
  return GRANTING_VERDICTS.includes(verdict);
}

