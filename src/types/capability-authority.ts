/**
 * =============================================================================
 * ΤΟ ΛΕΞΙΛΟΓΙΟ ΤΗΣ ΕΞΟΥΣΙΟΔΟΤΗΣΗΣ (ADR-801 §3)
 * =============================================================================
 *
 * **Το ερώτημα**: *«Επιτρέπεται σε **ΑΥΤΟΝ** τον άνθρωπο **ΑΥΤΗ** η πράξη;»*
 *
 * ⚠️ **ΔΕΝ ΕΙΝΑΙ ΤΟ ΙΔΙΟ ΕΡΩΤΗΜΑ ΜΕ ΤΟ `workspace-membership.ts`.** Εκείνο ρωτά
 * *«είναι **μέλος** αυτού του χώρου;»* — **απομόνωση**. Αυτό ρωτά *«έχει την
 * **ικανότητα**;»* — **εξουσιοδότηση**. Ένωσή τους θα ανέφερε αποτυχία
 * ικανότητας ως αποτυχία απομόνωσης (το λάθος που απέφυγε ρητά το ADR-775).
 * Η σειρά είναι: **πρώτα μέλος** (ADR-787), **μετά ικανός** (εδώ).
 *
 * ⚠️ **ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΤΟ `services/agent-capability/`** — εκείνο απαντά *«τι
 * μπορεί να **εκτελέσει** ένας AI agent»* (8 σύμβολα `Capability*`, τομέας
 * ai-pipeline). Ονομαστική επαλήθευση πριν γραφτεί αυτό το αρχείο: **μηδέν**
 * σύγκρουση συμβόλων (CHECK 3.59).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🏛️ ΤΟ ΜΟΝΤΕΛΟ: OpenID AuthZEN 1.0 (Standards Track, 11 Μαρτίου 2026)
 * ─────────────────────────────────────────────────────────────────────────────
 * Διαχωρίζει τον **PDP** (ποιος **αποφασίζει**) από τον **PEP** (ποιος
 * **επιβάλλει**). Ένα ερώτημα — *«Can **who** do **what** on **which
 * resource**?»* — μία ετυμηγορία. Αυτό το αρχείο είναι το **λεξιλόγιο** του PDP·
 * ο κριτής ζει στο `lib/auth/authority.ts`.
 *
 * 🏆 **ΠΟΥ ΞΕΠΕΡΝΑΜΕ ΤΟΥΣ ΜΕΓΑΛΟΥΣ.** OPA · Cedar · OpenFGA · CASL δίνουν όλοι
 * τη **μηχανή**· κανένας δεν εγγυάται ότι δεν θα γεννηθεί **δεύτερη**. Η
 * βιομηχανία ονομάζει το πρόβλημα *policy drift* και το πιάνει **στο runtime,
 * εκ των υστέρων** — δηλαδή *μαθαίνεις ότι έσπασε*. Εδώ το πιάνει το **CHECK
 * 3.66** στο `git add`: κλειστό σύνολο δηλώσεων, με υποχρεωτικό λόγο.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΧΡΕΙΑΣΤΗΚΕ (μετρημένο στην ΠΑΡΑΓΩΓΗ, 2026-08-24)
 * ─────────────────────────────────────────────────────────────────────────────
 * Την ημέρα που γράφτηκε αυτό υπήρχαν **ΕΞΙ** ανεξάρτητες απαντήσεις στο
 * *«είναι διαχειριστής;»*, με **ασύμβατα** σύνολα τιμών, και **δύο** από αυτές
 * έκριναν με **λίστα email** (`NEXT_PUBLIC_ADMIN_EMAILS`) — η μία **μέσα στο
 * bundle του φυλλομετρητή**. Το OWASP το γράφει κατά λέξη: *«Developers must
 * **never** rely on client-side access control checks … they should never be
 * the decisive factor»*.
 *
 * @module types/capability-authority
 * @see ADR-801 — Ένας κριτής για το «επιτρέπεται;»
 * @see ADR-787 §5.1 — ο αδελφός απαντητής («είναι μέλος;»)
 */

