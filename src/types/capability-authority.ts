/**
 * Το ερώτημα προς τον κριτή — **subject × action**, μοντέλο AuthZEN.
 *
 * 🔶 Το `resource` του AuthZEN **δεν** υπάρχει ακόμη, και είναι δηλωμένο κενό:
 * σήμερα καμία από τις έξι απαντήσεις που αντικαθιστά δεν κρίνει **ανά πόρο**
 * (κρίνουν όλες *«είναι διαχειριστής;»*). Θα προστεθεί όταν αποκτήσει
 * καταναλωτή — ένα πεδίο που κανείς δεν συμπληρώνει είναι φρουρός που δεν
 * μπορεί να πυροδοτήσει.
 */
export interface CapabilityQuery {
  readonly subject: CapabilitySubject | null;
  readonly action: PermissionId;
}

/**
 * Η ετυμηγορία **μαζί με την ικανότητα που κρίθηκε**.
 *
 * ⚠️ Η `action` επιστρέφεται **ρητά** ώστε ένα «ναι» να μην μπορεί ποτέ να
 * εφαρμοστεί σε **άλλη** ικανότητα από αυτήν που ρωτήθηκε (πρότυπο
 * `MembershipDecision.workspace`, ADR-787).
 */
export interface CapabilityDecision {
  readonly verdict: CapabilityVerdict;
  readonly action: PermissionId;
  /**
   * Κλειδί i18n για το «γιατί όχι» — `null` όταν επιτρέπεται.
   *
   * ⚠️ **Κλειδί, ΠΟΤΕ κείμενο** (N.11). Τα κλειδιά μπαίνουν στα locales στη
   * Φάση 3, μαζί με τον πρώτο καταναλωτή UI· γραμμένα σήμερα θα ήταν
   * μεταφράσεις που δεν ζητά κανείς.
   */
  readonly reason: string | null;
}
