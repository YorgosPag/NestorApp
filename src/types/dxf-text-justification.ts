/**
 * @fileoverview Το 9-σημείο πλέγμα προσάρτησης του MTEXT (κωδ. 71) — **ένας** ορισμός.
 *
 * ## Γιατί ζει εδώ και όχι μέσα στο subapp
 *
 * Ο τύπος γεννήθηκε στο `subapps/dxf-viewer/text-engine/types/text-ast.types.ts`, που το root
 * `tsconfig.json` **εξαιρεί**. Από το ADR-762 όμως τον χρειάζεται και το `TitleBlockSourceCell`
 * (`@/types/title-block-reading`), που ζει **έξω** από το subapp επειδή τον διαβάζει ο Λ2.
 *
 * 🔴 **Δεύτερος ορισμός θα ήταν το χειρότερο αποτέλεσμα**: το ένα αντίγραφο θα ενημερωνόταν και
 * το άλλο όχι, και επειδή και τα δύο θα ήταν ενώσεις κυριολεκτικών συμβολοσειρών, η απόκλιση θα
 * περνούσε τον έλεγχο τύπων **σιωπηλά** μέχρι να λείψει μια τιμή. Ίδιο πρότυπο και ίδιος λόγος
 * με το `@/types/title-block-reading` (ADR-745 Φ3β) και το `@/utils/greek-text` (Φ2).
 *
 * Το `text-ast.types.ts` **επανεξάγει** από εδώ, ώστε οι ~18 καταναλωτές του subapp να μη
 * γνωρίζουν τη μετακόμιση.
 *
 * @see ADR-762 §3 — γιατί η προσάρτηση έγινε δεδομένο του κελιού
 * @see ADR-344 — 9-point attachment grid
 */

/**
 * Σημείο προσάρτησης MTEXT (DXF κωδ. 71 = 1..9), σε ονόματα.
 *
 * Πρώτο γράμμα = **κατακόρυφη σειρά** (`T`op / `M`iddle / `B`ottom), δεύτερο = **οριζόντια
 * στήλη** (`L`eft / `C`enter / `R`ight). Η σειρά είναι η μόνη πληροφορία που χρειάζεται η
 * κανονικοποίηση θέσης του ADR-762 — αλλά ο τύπος μένει πλήρης γιατί αυτό **δηλώνει** το αρχείο.
 */
export type TextJustification =
  | 'TL' | 'TC' | 'TR'
  | 'ML' | 'MC' | 'MR'
  | 'BL' | 'BC' | 'BR';

/**
 * Η κατακόρυφη σειρά του πλέγματος — **η** ερώτηση που απαντά η κανονικοποίηση.
 *
 * Απαντά «πού μέσα στο μπλοκ κειμένου βρίσκεται το σημείο εισαγωγής;»: στην κορυφή, στο κέντρο,
 * ή στη βάση. Χωρίς αυτή την απάντηση δύο κελιά με διαφορετική προσάρτηση **δεν είναι
 * συγκρίσιμα** ως προς το `y` τους (ADR-762 §2).
 */
export type TextAttachmentRow = 'T' | 'M' | 'B';

/**
 * Η προεπιλογή όταν το αρχείο δεν δηλώνει κωδ. 71.
 *
 * Είναι η προεπιλογή **του DXF** (κωδ. 71 = 1), όχι δική μας ευκολία: οντότητες φτιαγμένες με το
 * χέρι, σκέτα TEXT και παλιά στιγμιότυπα δεν φέρουν προσάρτηση, και το «πάνω-αριστερά» είναι
 * ακριβώς αυτό που εννοούν.
 */
export const DEFAULT_TEXT_JUSTIFICATION: TextJustification = 'TL';

/** Η κατακόρυφη σειρά ενός σημείου προσάρτησης — το πρώτο του γράμμα, τυποποιημένο. */
export function attachmentRowOf(justification: TextJustification): TextAttachmentRow {
  return justification[0] as TextAttachmentRow;
}
