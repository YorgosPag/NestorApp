export const COVERAGE_MAX_VERTICES = 100;

/**
 * **ΧΑΡΑΓΜΕΝΟ ΠΟΛΥΓΩΝΟ** — «δουλεύω **αυτό εδώ**», δείχνοντάς το.
 *
 * 🔑 **Ο ΙΔΙΟΣ {@link GeoOutline} με κάθε άλλο σχήμα του έργου** *(κλειστός δακτύλιος,
 * **χωρίς** επανάληψη της πρώτης κορυφής)*, άρα η ίδια μηχανή χάραξης *(`useOutlineDraft`)*,
 * η ίδια επικύρωση *(`isSimpleGeoOutline` · `geoOutlineAreaSqm`)* και η ίδια απόδοση
 * *(`PlaceMap`)*. **Καμία νέα γεωμετρία δεν γράφτηκε για τη Φάση 3.**
 *
 * ⚠️ **ΕΝΑΣ δακτύλιος, όχι πολλοί — και είναι απόφαση.** Ένα «αρχιπέλαγος δήλωσης»
 * *(δύο ασύνδετες περιοχές)* εκφράζεται **ήδη**, καλύτερα, από το
 * {@link AdministrativeCoverage} *(λίστα οντοτήτων)* ή από δύο χαράξεις — και οι τρύπες
 * δεν έχουν νόημα σε δήλωση εργασίας. Πολλαπλοί δακτύλιοι θα ζητούσαν από τον άνθρωπο
 * να μάθει τοπολογία για να πει «δουλεύω εδώ».
 */
export interface OutlineCoverage {
  readonly outline: GeoOutline;
}

/** **Ποιο σκέλος;** — παρουσία πεδίου, ίδιο ιδίωμα με το {@link isNationwide}. */
export function isOutlineCoverage(coverage: DeclaredCoverage): coverage is OutlineCoverage {
  return 'outline' in coverage;
}

