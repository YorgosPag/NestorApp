/**
 * **ΠΟΥ ΨΑΧΝΕΙ Ο ΕΠΙΣΚΕΠΤΗΣ — ΜΙΑ ΕΡΩΤΗΣΗ, ΔΥΟ ΠΗΓΕΣ** *(ADR-846)*.
 *
 * 🔑 **ΓΙΑΤΙ ΜΕΤΑΚΟΜΙΣΕ ΕΔΩ ΑΠΟ ΤΟ `showcase-filter.ts`** *(Φάση 2)*: ο **κριτής**
 * *(`lib/agency/coverage-match.ts`)* χρειάζεται πλέον να ξέρει **ποιο είδος ερωτήματος**
 * κρίνει — και το `showcase-filter` **εισάγει** τον κριτή. Ένας δεύτερος, πανομοιότυπος
 * τύπος μέσα στον κριτή θα ήταν **δίδυμο** *(N.18 / CHECK 3.28)* που το `ssot:discover`
 * **δεν** θα έβλεπε *(διαφορετικό όνομα, ίδιο σχήμα)*. Άρα ο τύπος κατεβαίνει στο
 * **φύλλο** που τον χρειάζονται και οι δύο· το `showcase-filter` τον **επανεξάγει**,
 * ώστε κανένας υπάρχων καταναλωτής να μην αγγιχτεί.
 *
 * ⚠️ **Δεν είναι το ίδιο με το {@link DeclaredCoverage}, και ΠΟΤΕ δεν ενοποιούνται.**
 * Εδώ ρωτά ο **επισκέπτης** *(«πού ψάχνω;»)*· εκεί δηλώνει ο **επαγγελματίας** *(«πού
 * δουλεύω;»)*. Το ότι το ένα σκέλος μοιάζει *(κύκλος και τα δύο)* είναι σύμπτωση της
 * γεωμετρίας, όχι της σημασίας: το ερώτημα δέχεται **οποιαδήποτε** ακτίνα, η δήλωση
 * **τέσσερις**.
 */
export type ShowcaseWhere =
  /**
   * **Διοικητική οντότητα** — ό,τι διάλεξε ο επισκέπτης από το κλειστό λεξιλόγιο του
   * Καλλικράτη *(ADR-772)*, σε οποιοδήποτε από τα 8 επίπεδα.
   *
   * ⚠️ **Κανένα σημείο εδώ — και από τη Φ2.5 είναι ΕΠΙΛΟΓΗ, όχι αδυναμία.** Μέχρι τότε
   * δεν υπήρχε γεωμετρία ορίων, άρα δεν **μπορούσε** να παραχθεί κέντρο. Πλέον υπάρχει
   * *(`GeoFootprint.center`, `lib/geo/admin-footprints.ts`)*, και **παρ' όλα αυτά δεν
   * μπαίνει εδώ**: η σειρά του καταλόγου για διοικητικό ερώτημα μένει **ισότιμη**
   * *(`orderAgencies` με `from === null`)*.
   *
   * 🔑 **Γιατί μένει έτσι**: το κεντροειδές κορυφών **δεν υπόσχεται ότι είναι μέσα** στο
   * σχήμα *(δήμος-αρχιπέλαγος ⇒ κέντρο στη θάλασσα)*. Μια κατάταξη χτισμένη πάνω του θα
   * ήταν **αυθαίρετη ενώ θα έμοιαζε με αρχή** — ακριβώς το σχήμα που ο Κ13 κυνηγά. Το
   * αποτύπωμα υπάρχει για να **αποδεικνύει εγκλεισμούς**, όχι για να ταξινομεί.
   */
  | { readonly adminId: string }
  /** **Σημείο + ακτίνα** — ο ΙΔΙΟΣ `GeoCircle` με το `ListingFilters.near`. */
  | { readonly circle: GeoCircle };

/** **Ποιο σκέλος;** — διάκριση με **παρουσία πεδίου**, ίδιο ιδίωμα με το `isBoundingBox`. */
export function isAdministrativeWhere(
  where: ShowcaseWhere,
): where is { readonly adminId: string } {
  return 'adminId' in where;
}
