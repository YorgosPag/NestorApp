/**
 * @fileoverview **ΠΟΥ ΔΟΥΛΕΥΕΙ Ο ΕΠΑΓΓΕΛΜΑΤΙΑΣ** — το λεξιλόγιο της δηλωμένης εμβέλειας.
 * @related ADR-846 · ADR-841 §7 Α6 · ADR-772 (διοικητική ιεραρχία) · ADR-777 §8.63
 * @module types/agency-coverage
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΜΕΤΡΗΜΕΝΟ ΕΛΑΤΤΩΜΑ: ΕΝΑ ΣΗΜΕΙΟ ΑΠΑΝΤΑ «ΠΟΥ ΚΑΘΕΣΑΙ», ΟΧΙ «ΠΟΥ ΔΟΥΛΕΥΕΙΣ»
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Μέχρι το ADR-846 ο επαγγελματίας δήλωνε **ένα σημείο** — την έδρα του
 * *(`PublicShowcase.position`, παραγόμενη από το `place`)* — και ο επισκέπτης δήλωνε
 * **ακτίνα γύρω από τον εαυτό του**. Ο μπετατζής με έδρα στη **Θέρμη** που δουλεύει
 * όλη τη **Χαλκιδική** δεν βρισκόταν **ποτέ** από επισκέπτη της Κασσάνδρας: ψευδώς
 * αρνητικό **δομικό**, όχι σπάνιο — σε κάθε τεχνικό επάγγελμα είναι ο **κανόνας**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ ΚΑΙ ΓΙΑΤΙ ΤΟ ΙΔΙΟ ΑΡΧΕΙΟ ΤΟ ΑΠΑΓΟΡΕΥΕ ΜΕΧΡΙ ΧΘΕΣ — Η ΑΝΑΤΡΟΠΗ ΕΧΕΙ **ΔΥΟ** ΣΚΕΛΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `agency-profile.ts` απαγόρευε ως #6 την *«ΑΚΤΙΝΑ ΕΞΥΠΗΡΕΤΗΣΗΣ»* με σκεπτικό
 * **δύο** προτάσεων, και **καμία** δεν ανατρέπεται από την άλλη:
 *
 * 1. *«**κατάταξη ντυμένη ως γεωγραφία** — όποιος δηλώσει μεγαλύτερη ακτίνα εμφανίζεται
 *    σε περισσότερες αναζητήσεις»* → 🏆 **ΑΝΑΤΡΑΠΗΚΕ, ΚΑΙ ΕΠΑΛΗΘΕΥΕΤΑΙ ΣΤΟΝ ΚΩΔΙΚΑ**:
 *    το `agency-directory-order.ts` διαβάζει **μόνο** `viewpoint.from` εναντίον
 *    `showcase.position`, και το tie-break **μόνο** `companyId`. Η εμβέλεια **δεν έχει
 *    διαδρομή** προς τη σειρά. Και όταν το ερώτημα είναι **διοικητικό** δεν υπάρχει καν
 *    σημείο ⇒ `from === null` ⇒ **όλοι ισότιμοι**. Η υπερδήλωση μπορεί μόνο να **μη σε
 *    αποκλείει** — **ποτέ** να σε ανεβάσει.
 *
 * 2. *«**ισχυρισμός που κανείς δεν ελέγχει**»* → ⚠️ **ΔΕΝ ανατράπηκε — ΠΕΡΙΟΡΙΣΤΗΚΕ.**
 *    Κανείς δεν επαληθεύει ούτε το `occupation`, και είναι αποδεκτό επειδή το λεξιλόγιο
 *    είναι **κλειστό** *(ESCO)*. Το ίδιο εδώ: η ιεραρχία του Καλλικράτη είναι **κλειστή
 *    και φραγμένη**, με ανώτατο όριο *(«όλη η Ελλάδα»)* **αυτο-φανερό στον επισκέπτη**.
 *    🔴 **Η ακτίνα σε χιλιόμετρα ΔΕΝ είναι**: είναι *dial* χωρίς ταβάνι, όπου το «500 χλμ»
 *    είναι συντακτικά νόμιμο και **οπτικά αόρατο**. ⇒ Όποιος προσθέσει σκέλος ακτίνας
 *    εδώ χρειάζεται **δικό του** σκεπτικό· αυτό **δεν κληρονομείται**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΚΑΝΟΝΙΚΟΠΟΙΗΣΗ ΑΝΤΙ ΓΙΑ ΠΛΑΦΟΝ — ΕΔΩ ΞΕΠΕΡΝΑΜΕ ΤΟΥΣ ΜΕΓΑΛΟΥΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το **Google Business Profile** δίνει **20 επίπεδες** περιοχές *(πόλεις ή ΤΚ)* και
 * βάζει από πάνω **ανιχνευτή spam** για όποιον τις γεμίσει με άσχετα. Το πλαφόν είναι
 * αναγκαίο **επειδή η λίστα είναι επίπεδη**: χωρίς ιεραρχία, «όλη η Αττική» γράφεται
 * μόνο ως 66 δήμοι.
 *
 * 🔑 Εδώ η λίστα είναι **ιεραρχική**, οπότε το πλαφόν είναι περιττό: κάθε id που έχει
 * **πρόγονο** ήδη μέσα στη δήλωση **απορροφάται** *(δηλώνεις «Δήμος Θέρμης» + «Περιφέρεια
 * Κεντρικής Μακεδονίας» ⇒ μένει η περιφέρεια)*. Η λίστα μένει μικρή **φυσικά**, η πράξη
 * είναι **ιδεμποτής** *(N.7.2 #3)*, και δεν χρειάζεται καμία αυθαίρετη οροφή.
 *
 * ⚠️ **Ούτε ανιχνευτής spam χρειάζεται**, και αυτό είναι το σκέλος 1 πάλι: όταν η
 * δήλωση **δεν κατατάσσει**, το κίνητρο για υπερδήλωση **δεν υπάρχει**. Η Google
 * χρειάζεται ανιχνευτή επειδή εκεί η περιοχή **ταΐζει** το local pack.
 */

import type { GeoCircle, GeoOutline, GeoPoint } from '@/types/geo/coordinates';

/**
 * **ΠΟΥ ΔΟΥΛΕΥΕΙ** — κλειστή ένωση **τεσσάρων** σκελών, με διάκριση από **παρουσία πεδίου**
 * *(ίδιο ιδίωμα με το `isBoundingBox` του `lib/geo/geo-area.ts` — τα δύο μέλη δεν
 * μοιράζονται κανένα όνομα, οπότε ο μεταγλωττιστής στενεύει μόνος του)*.
 *
 * ⚠️ **ΔΕΝ είναι `GeoArea`, και δεν πρέπει να γίνει.** Το `GeoArea` απαντά ρητά
 * *«πού **ψάχνω**;»* — ερώτημα **επισκέπτη**. Αυτό απαντά *«πού **δουλεύω**;»* —
 * δήλωση **επαγγελματία**. Δύο ερωτήσεις, δύο τύποι· ένας κοινός τύπος θα άφηνε τον
 * επόμενο να ρωτά *«αυτό το σχήμα είναι ερώτημα ή δήλωση;»* χωρίς να μπορεί να απαντήσει.
 */
export type DeclaredCoverage =
  | NationwideCoverage
  | AdministrativeCoverage
  | RadiusCoverage
  | OutlineCoverage;

/**
 * **ΟΛΗ Η ΕΛΛΑΔΑ** — και είναι sentinel **από ανάγκη**, όχι από γούστο.
 *
 * 🔴 **Η χώρα ΔΕΝ έχει id στην ιεραρχία.** Το επίπεδο 1 του
 * `data/administrative-hierarchy.json` έχει **πέντε ανεξάρτητες ρίζες** — ΒΟΡΕΙΑ
 * ΕΛΛΑΔΑ · ΚΕΝΤΡΙΚΗ ΕΛΛΑΔΑ · ΑΤΤΙΚΗ · ΝΗΣΙΑ · ΑΓΙΟ ΟΡΟΣ *(αυτοδιοίκητο)*. Χωρίς αυτό
 * το μέλος, η **πρώτη** επιλογή που ζητά ο κόσμος *(«δραστηριοποιούμαι σε όλη την
 * Ελλάδα»)* θα ήταν **μη εκφράσιμη** — ή, χειρότερα, θα γραφόταν ως «οι πέντε ρίζες»
 * και ο επόμενος που θα πρόσθετε έκτη ρίζα θα έσπαγε **σιωπηλά** κάθε τέτοια δήλωση.
 */
export interface NationwideCoverage {
  readonly nationwide: true;
}

/**
 * **ΣΥΝΟΛΟ ΔΙΟΙΚΗΤΙΚΩΝ ΟΝΤΟΤΗΤΩΝ** — σε **οποιοδήποτε** από τα 8 επίπεδα, ανακατεμένα.
 *
 * 🔑 **Ανακατεμένα επίπεδα είναι ΧΑΡΑΚΤΗΡΙΣΤΙΚΟ, όχι ατέλεια**: ο μπετατζής της Θέρμης
 * δηλώνει *«Δήμος Θέρμης»* **και** *«Περιφερειακή Ενότητα Χαλκιδικής»* — δύο επίπεδα,
 * μία αλήθεια. Ένα σχήμα «ένα επίπεδο για όλους» θα τον ανάγκαζε να ανέβει στην
 * Περιφέρεια Κεντρικής Μακεδονίας, δηλαδή **η ίδια η σχεδίαση θα παρήγαγε υπερδήλωση**.
 *
 * 🔴 **ΜΟΝΟ Ο,ΤΙ ΕΚΛΙΚΑΡΕ Ο ΑΝΘΡΩΠΟΣ — ΚΑΜΙΑ ΑΠΟΘΗΚΕΥΜΕΝΗ ΕΠΕΚΤΑΣΗ, ΜΕΤΡΗΜΕΝΟ.**
 * Η προφανής εναλλακτική *(«άπλωσε το υποδέντρο και ρώτα με `array-contains`»)*
 * μετρήθηκε πάνω στο πραγματικό αρχείο:
 *
 * | Δήλωση | Απόγονοι | Μόνο τα ids |
 * |---|---|---|
 * | Περιφέρεια Κεντρικής Μακεδονίας | **1.850** | ~42 KB |
 * | «Όλη η Ελλάδα» | **19.535** | **~449 KB** |
 *
 * Δεν σπάει το όριο του 1 MiB — χτυπάει **αλλού, χειρότερα**: το `usePublicAgencies`
 * κάνει **ωμό `onSnapshot(collection(…))`** και κατεβάζει **ολόκληρη** τη συλλογή σε
 * **κάθε ανώνυμο επισκέπτη** του `/pro`. Μερικές δεκάδες βιτρίνες με δήλωση περιφέρειας
 * = **δεκάδες MB** ανά φόρτωση, σε σελίδα που δικαιολογεί το ωμό `onSnapshot` ρητά
 * *«για το τρέχον μέγεθος πληθυσμού»* — όχι για έγγραφα μισού MB.
 *
 * ✅ Η επέκταση γίνεται **στη μεριά του ερωτήματος**, στη μνήμη, με τους **προγόνους του
 * επισκέπτη** *(≤8, βλ. `lib/agency/coverage-match.ts`)*.
 *
 * ⚠️ **ΔΕΝ είναι δοχείο διεύθυνσης — και γι' αυτό ΔΕΝ το βλέπει το CHECK 3.44**
 * *(ADR-772 §10.2)*. Εκείνη η πύλη μετρά δοχεία με **ζεύγη `<επίπεδο>Name`/`<επίπεδο>Id`
 * ανά βαθμίδα**, και προστατεύει από **σιωπηλή απώλεια βαθμίδας** σε μετατροπέα
 * διευθύνσεων *(μετρημένα 6/8, 5/8, 2/8)*. Εδώ υπάρχει **ένα** πεδίο-πίνακας με
 * **ανεξάρτητες** επιλογές σε ανακατεμένα επίπεδα: **δεν υπάρχει βαθμίδα να ξεχαστεί**.
 * Η σιωπή της πύλης είναι **σωστή σημασιολογικά**, όχι διαφυγή.
 *
 * ⛔ **ΜΗΝ προσθέσεις `adminNames: string[]` δίπλα.** Θα ήταν ακριβώς το σχήμα
 * «ταυτότητα + όνομα ανά επίπεδο» που κυνηγά το 3.44, θα γινόταν **δεύτερη αυθεντία**
 * για ονόματα που ήδη ζουν στο JSON, και θα **πάλιωνε** στην πρώτη μετονομασία δήμου.
 * Τα ονόματα λύνονται **κατά την εμφάνιση**, από το `useAdministrativeHierarchy`.
 */
export interface AdministrativeCoverage {
  /**
   * Ταυτότητες της μορφής `<είδος>:<κωδικός>` *(π.χ. `municipality:6301`)*, όπως τις
   * παράγει το `data/administrative-hierarchy.json`.
   *
   * ⚠️ **Ποτέ κενός πίνακας.** Κενή δήλωση **δεν είναι** «όλη η Ελλάδα» — είναι «δεν
   * δήλωσα», και εκφράζεται με `coverage: null` στη βιτρίνα. Δύο αναπαραστάσεις της
   * ίδιας απουσίας θα ήταν το σχήμα που κάθε αναγνώστης πρέπει να θυμάται να ελέγξει
   * δύο φορές. Το επιβάλλει ο γραφέας *(`showcase-request.ts`)*, ονομαστικά.
   */
  readonly adminIds: readonly string[];
}

/**
 * **Διάκριση με παρουσία πεδίου** — η ίδια πράξη με το `isBoundingBox`.
 *
 * 🔑 Γράφεται **εδώ, μία φορά**: ένα `'nationwide' in coverage` σκορπισμένο σε κάθε
 * καταναλωτή είναι το είδος του ελέγχου που κάποιος θα γράψει ανάποδα.
 */
export function isNationwide(coverage: DeclaredCoverage): coverage is NationwideCoverage {
  return 'nationwide' in coverage;
}

