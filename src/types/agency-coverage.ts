/**
 * 🔴🔴 **ΤΟ ΣΚΕΠΤΙΚΟ ΠΟΥ ΧΡΩΣΤΟΥΣΕ Η ΑΚΤΙΝΑ — ΔΕΝ ΚΛΗΡΟΝΟΜΗΘΗΚΕ, ΓΡΑΦΤΗΚΕ**
 *
 * Η απαγόρευση #6 του `types/agency-profile.ts` είχε **δύο** σκέλη, και η Φάση 1
 * ανέτρεψε **μόνο** το ένα *(«κατάταξη ντυμένη ως γεωγραφία»)*. Το άλλο —
 * *«ισχυρισμός που κανείς δεν ελέγχει»* — περιορίστηκε με επιχείρημα που ισχύει **μόνο**
 * για κλειστό, φραγμένο λεξιλόγιο:
 *
 * > Η ιεραρχία έχει **αυτο-φανερό ανώτατο όριο** *(«όλη η Ελλάδα»)*, ορατό στην κάρτα.
 * > Η **ακτίνα σε χλμ είναι dial χωρίς ταβάνι**: το «500 χλμ» είναι συντακτικά νόμιμο
 * > και **οπτικά αόρατο**.
 *
 * ⇒ Η ακτίνα χρειαζόταν **δικό της** αντεπιχείρημα. Είναι **δύο προτάσεις**, και καμία
 * δεν είναι «εμπιστευόμαστε τον χρήστη»:
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * **1️⃣ ΤΟ ΤΑΒΑΝΙ ΕΙΝΑΙ ΤΥΠΟΣ, ΟΧΙ ΕΛΕΓΧΟΣ.**
 *
 * Το {@link COVERAGE_RADIUS_STEPS} είναι **κλειστό σύνολο τεσσάρων τιμών**. Το «500»
 * δεν απορρίπτεται από κάποιον φύλακα που κάποιος μπορεί να ξεχάσει να καλέσει — είναι
 * **ασύντακτο**. Ίδιο ιδίωμα με το `GeoPolyline` *(«το "τουλάχιστον δύο κορυφές" είναι
 * ΤΥΠΟΣ, όχι έλεγχος»)* και με το `allowFreeText: false` του `AreaCombobox` *(«η μόνη
 * τιμή που φεύγει είναι `option.value`»)*.
 *
 * 🔑 **Άρα το λεξιλόγιο της ακτίνας είναι εξίσου κλειστό και φραγμένο με του
 * Καλλικράτη** — και το επιχείρημα της Φάσης 1 **γίνεται** εφαρμόσιμο, αντί να
 * κλαπεί. Το ανώτατο *(50 χλμ)* είναι **μικρότερο** από κάθε περιφέρεια: κανείς δεν
 * μπορεί να δηλώσει με ακτίνα κάτι ευρύτερο απ' ό,τι θα δήλωνε με **μία** επιλογή
 * ιεραρχίας.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * **2️⃣ Η ΑΚΤΙΝΑ ΓΙΝΕΤΑΙ ΟΡΑΤΗ ΜΕ ΤΟΝ ΙΔΙΟ ΤΡΟΠΟ ΠΟΥ ΕΙΝΑΙ ΟΡΑΤΗ Η ΙΕΡΑΡΧΙΑ.**
 *
 * Η ένσταση δεν ήταν «μεγάλο νούμερο» — ήταν *«**οπτικά αόρατο**»*: ο επισκέπτης βλέπει
 * «Δήμος Θέρμης» και ξέρει τι σημαίνει· ένα «50 χλμ» δεν το ξέρει. ⇒ Η κάρτα **γράφει
 * την ακτίνα με λέξεις** *(«έως 30 χλμ από …»)*, ακριβώς όπως γράφει τα ονόματα των
 * διοικητικών οντοτήτων. Η δήλωση μένει **λογοδοτήσιμη στον άνθρωπο που τη διαβάζει**,
 * που ήταν ολόκληρο το επιχείρημα του §2.2.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⛔ **ΚΑΙ ΤΟ ΣΚΕΛΟΣ 1 ΤΗΣ #6 ΜΕΝΕΙ ΑΝΑΤΡΑΜΜΕΝΟ ΧΩΡΙΣ ΝΕΑ ΕΡΓΑΣΙΑ**: το
 * `agency-directory-order.ts` δεν διαβάζει `coverage` *(άγκυρα antitrust, `coverage`
 * στη λίστα `forbidden`)*. Ακτίνα 50 χλμ **δεν ανεβάζει καμία θέση** — μπορεί μόνο να
 * μη σε αποκλείει.
 */
export const COVERAGE_RADIUS_STEPS = [10, 20, 30, 50] as const;

/**
 * **Οι μόνες επιτρεπτές ακτίνες.** Ό,τι άλλο δεν μεταγλωττίζεται.
 *
 * ⚠️ Ο τύπος φυλάει τον **κώδικα**· τα σύνορα εισόδου *(διακομιστής, URL, Firestore)*
 * δέχονται `number` και περνούν από το {@link asCoverageRadiusKm}. Ένας τύπος δεν
 * επιβιώνει ενός `JSON.parse` — γι' αυτό υπάρχουν **και τα δύο**.
 */
export type CoverageRadiusKm = (typeof COVERAGE_RADIUS_STEPS)[number];

/**
 * **Το σύνορο εισόδου** — ωμός αριθμός → βήμα, ή `null`.
 *
 * 🔑 Γράφεται **εδώ, μία φορά**: ένα `STEPS.includes(x)` σκορπισμένο στον γραφέα και
 * στον αναγνώστη είναι δύο τόποι που μπορούν να αποκλίνουν όταν προστεθεί πέμπτο βήμα.
 */
export function asCoverageRadiusKm(value: number): CoverageRadiusKm | null {
  return COVERAGE_RADIUS_STEPS.find((step) => step === value) ?? null;
}

/**
 * **ΑΚΤΙΝΑ ΓΥΡΩ ΑΠΟ ΣΗΜΕΙΟ ΠΟΥ ΟΡΙΖΕΙ Ο ΙΔΙΟΣ** — «δουλεύω 30 χλμ γύρω από εδώ».
 *
 * ⚠️ **Το κέντρο ΔΕΝ είναι η έδρα, και δεν πρέπει να γίνει.** Το
 * `PublicShowcase.position` απαντά *«πού κάθομαι»* και **παράγεται από τη γη**
 * *(επαληθεύσιμο)*· αυτό εδώ απαντά *«γύρω από πού δουλεύω»* και είναι **δήλωση**. Ο
 * μπετατζής της Θέρμης μπορεί να δουλεύει 20 χλμ γύρω από τη **Νέα Μουδανιά**. Μια
 * σιωπηλή προεπιλογή «= η έδρα σου» θα ήταν μαντεψιά για λογαριασμό του ανθρώπου.
 *
 * 🔑 **Δομικά συμβατό με το `GeoCircle`** *(στενότερο `radiusKm`)*, άρα ταξιδεύει
 * αυτούσιο στο `areaRelation` — καμία μετατροπή, κανένα δεύτερο σχήμα κύκλου.
 */
export interface RadiusCoverage {
  readonly circle: {
    readonly center: GeoPoint;
    readonly radiusKm: CoverageRadiusKm;
  };
}

/** **Ποιο σκέλος;** — παρουσία πεδίου, ίδιο ιδίωμα με το {@link isNationwide}. */
export function isRadiusCoverage(coverage: DeclaredCoverage): coverage is RadiusCoverage {
  return 'circle' in coverage;
}

