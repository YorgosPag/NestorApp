/**
 * Η «φρεσκάδα» μιας όψης που **παράγεται στον server** (ADR-901 §14.8) — γενικό σχήμα, κανένας τομέας.
 *
 * - `revision` — η αναθεώρηση του σήματος της όψης, διαβασμένη **πριν** παραχθεί η όψη (ή μέσα στη συναλλαγή της
 *   πράξης που την επέστρεψε). Ο client ξαναρωτά **μόνο** όταν το σήμα την ξεπεράσει.
 * - `freshUntil` — ISO· η στιγμή που η όψη μπαγιατεύει **χωρίς** καμία εγγραφή (π.χ. αλλαγή ημέρας για τις λήξεις):
 *   ο client ξαναρωτά ακριβώς τότε, αντί για polling.
 *
 * @module types/server-view
 */
export interface ViewFreshness {
  readonly revision: number;
  readonly freshUntil: string;
}
