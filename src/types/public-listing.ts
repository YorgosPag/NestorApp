/**
 * **Γιατί δεν ξέρουμε πότε μπήκε** — και οι δύο τιμές **δεν** είναι εναλλάξιμες.
 *
 * Ίδιο ιδίωμα με το {@link UnknownPositionReason}, και για τον ίδιο λόγο: δύο
 * καταστάσεις που *μοιάζουν ίδιες και δεν είναι*.
 *
 * | Κατάσταση | Τι συνέβη | Τι οφείλει να πει η οθόνη |
 * |---|---|---|
 * | `predates-record` | ήταν **ήδη** στην αγορά πριν αρχίσουμε να καταγράφουμε | «*δεν καταγράφηκε πότε μπήκε*» |
 * | `not-recorded` | η σφραγίδα **δεν ευδοκίμησε** — δικό μας σφάλμα, όχι ιστορία | «*δεν καταγράφηκε πότε μπήκε*» |
 *
 * 🔑 Η οθόνη λέει σήμερα το **ίδιο** και για τις δύο, και αυτό είναι σωστό: ο
 * επισκέπτης δεν έχει τίποτα να κάνει με τη διαφορά. Η διάκριση υπάρχει για **εμάς** —
 * η δεύτερη είναι **βλάβη προς διόρθωση** και μετριέται· η πρώτη είναι **οριστική**.
 * Συγχωνευμένες σε μία τιμή, ένα σπασμένο CAS θα κρυβόταν μέσα στο κανονικό ιστορικό.
 */
export type UnknownListedAtReason = 'predates-record' | 'not-recorded';

/**
 * **Πότε μπήκε αυτό το ακίνητο στην αγορά** — γράφεται **ΜΙΑ** φορά και δεν ξαναγράφεται.
 *
 * 🔴 **ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΤΟ {@link PublicListing.projectedAt}.** Εκείνο είναι η ώρα της
 * τελευταίας **ανακατασκευής** — μετρήθηκε (2026-09-01) ότι μετά από μία
 * `rebuildAllPublicListings` **όλα** τα έγγραφα το πήραν μέσα στο ίδιο δευτερόλεπτο.
 * Ταξινόμηση εκεί θα ήταν **σχεδόν ισοπαλία παντού**, δηλαδή θα επέστρεφε στην τύχη ενώ
 * θα **φαινόταν** χρονολογική: *ψέμα που μοιάζει με πληροφορία*.
 *
 * 🏆 **ΓΙΑΤΙ ΕΙΝΑΙ ΠΙΟ ΑΞΙΟΠΙΣΤΟ ΑΠΟ ΤΟ ΠΡΟΤΥΠΟ ΤΟΥ ΚΛΑΔΟΥ.** Το RESO Data Dictionary
 * 1.7 έχει **δύο** πεδία, και **και τα δύο** χειραγωγούνται:
 *
 * | Πεδίο RESO | Διαδρομή χειραγώγησης |
 * |---|---|
 * | `OnMarketDate` | *«η ημερομηνία που **εισήγαγε ο πράκτορας**»* — την πληκτρολογεί άνθρωπος |
 * | `OriginalEntryTimestamp` | αυτόματο, αλλά δεμένο στην **εγγραφή αγγελίας**: ακύρωση + επαναδημοσίευση = **νέα** εγγραφή = νέα σφραγίδα |
 *
 * Το αντίμετρο του κλάδου (CDOM) είναι **κατώφλι** — το CRMLS μηδενίζει αν η αγγελία
 * λείψει >30 μέρες — δηλαδή **παρακάμπτεται με αναμονή**.
 *
 * 🔑 **Η δική μας σφραγίδα δένεται στο ΑΚΙΝΗΤΟ, όχι στην αγγελία.** Το
 * `properties/{id}` **επιβιώνει** της απόσυρσης (η απόσυρση σβήνει μόνο **αυτή** την
 * προβολή). ⇒ καμία πληκτρολόγηση, καμία επαναδημιουργία, **κανένα κατώφλι να
 * περιμένεις**. Η χειραγώγηση δεν είναι απαγορευμένη — είναι **δομικά αδύνατη**, ίδιο
 * ιδίωμα με το `listing-map-shape.ts` (*«δεν υπάρχει διαδρομή από το ένα στο άλλο μέσα
 * σε αυτό το αρχείο»*).
 *
 * ⚠️ **ΔΥΟ καταστάσεις εδώ, ΤΡΕΙΣ στο έγγραφο πηγής.** Στην προβολή το πεδίο είναι
 * **πάντα** παρόν. Στο `properties` / `owner_properties` υπάρχει και η **απουσία**, που
 * σημαίνει *«δεν πέρασε ΠΟΤΕ από τη σφραγίδα»* — και είναι η τιμή που επιτρέπει στη
 * σφραγίδα να ξεχωρίσει «πρώτη δημοσίευση» από «παλιό ακίνητο». Χωρίς αυτή τη
 * διάκριση, ένα write-once «γράψε αν λείπει» θα έδινε στα **ήδη** δημοσιευμένα τη
 * **σημερινή** ημερομηνία — δηλαδή θα γεννούσε ψεύτικη ιστορία στο ίδιο σημείο που
 * φτιάχνει το κανάλι ειλικρίνειας.
 */
export type ListedAt =
  | { readonly kind: 'known'; readonly at: string }
  | { readonly kind: 'unknown'; readonly reason: UnknownListedAtReason };

