/**
 * **Γιατί δεν ξέρουμε πού είναι** — και οι δύο τιμές **δεν** είναι εναλλάξιμες.
 *
 * Είναι η διάκριση της **Α5 §3**, η οποία υπάρχει επειδή σήμερα οι δύο καταστάσεις
 * *μοιάζουν ίδιες και δεν είναι*:
 *
 * | Κατάσταση | Ποιος τη δημιούργησε | Τι οφείλει να πει η οθόνη |
 * |---|---|---|
 * | `never-asked` | **εμείς** — δικό μας χρέος | «*η θέση δεν έχει καταχωρηθεί ακόμη*» |
 * | `owner-declined` | **ο χρήστης** — επιλογή του | «*ο ιδιοκτήτης δεν έχει δηλώσει θέση*» |
 *
 * 🔑 Η διάκριση **δεν είναι λεκτική**: η πρώτη έχει **θεραπεία** με ένα κλικ (Α5 §4.3
 * — *«το γέμισμα της θέσης είναι το δόλωμα, ποτέ το φράγμα»*)· η δεύτερη **δεν έχει**,
 * και το να ζητήσουμε διόρθωση για κάτι που ο κάτοχος **αποφάσισε** είναι παρενόχληση.
 *
 * ⚠️ Χωρίς αυτό το πεδίο, το «*υποχρεωτικό ΕΡΩΤΗΜΑ, όχι υποχρεωτική ΑΠΑΝΤΗΣΗ*» της Α5
 * θα ήταν **μη παρατηρήσιμο**: μια φόρμα που ρώτησε και μια φόρμα που δεν ρώτησε ποτέ
 * θα κατέληγαν στο **ίδιο** έγγραφο.
 */
export type UnknownPositionReason = 'never-asked' | 'owner-declined';

/**
 * Πού είναι η αγγελία — **η {@link PlacePosition} με μία μόνο προσθήκη**.
 *
 * 🔴 **Δεν είναι δεύτερο λεξιλόγιο θέσης, και αυτό είναι σκόπιμο** (ADR-749: τέσσερις
 * μηχανές σε πέντε διαλέκτους, τρεις αριθμοί για το ίδιο δέντρο). Οι **γνωστές**
 * καταστάσεις επαναχρησιμοποιούνται **αυτούσιες** — μαζί με το νομικό όριο του ODbL,
 * που παραμένει **σφάλμα μεταγλώττισης** και εδώ (`outline?: never` στον κλάδο `osm`).
 *
 * Διαφέρει **μόνο** στο `unknown`, και ο λόγος είναι ότι το ερώτημα **είναι** άλλο: μια
 * **γη** δεν «αρνείται να πει» πού βρίσκεται· ένας **κάτοχος αγγελίας** μπορεί.
 */
export type ListingPosition =
  | { readonly kind: 'unknown'; readonly reason: UnknownPositionReason }
  | Extract<PlacePosition, { kind: 'known' }>;

// ============================================================================
// Η ΑΓΓΕΛΙΑ — κλειστό σχήμα
// ============================================================================

/**
 * Εικόνα εξωφύλλου.
 *
 * ⚠️ **`width`/`height` υποχρεωτικά** — δεν είναι πληρότητα: χωρίς αυτά ο περιηγητής
 * δεν μπορεί να κρατήσει τον χώρο πριν φορτώσει η εικόνα, και οι κάρτες «πηδάνε» ενώ ο
 * χρήστης πάει να πατήσει μία. Είναι το **CLS < 0,1** που η Α19 δεσμεύτηκε **αριθμητικά**.
 */
export interface ListingImage {
  readonly url: string;
  readonly width: number;
  readonly height: number;
  /** Κείμενο εναλλακτικής περιγραφής — **κλειδί i18n**, ποτέ ωμό κείμενο (N.11). */
  readonly altKey: string;
}

/**
 * **Ό,τι βλέπει ο κόσμος για ένα ακίνητο.** Γράφεται **μόνο** από τον διακομιστή.
 *
 * Τα πεδία είναι **ακριβώς** τα «5 βασικά + 3 ειδικά» του §25.6 — και το *«ΠΟΤΕ
 * περισσότερα»* εκεί δεν είναι ύφος: κάθε επιπλέον πεδίο στην κάρτα μετρήθηκε ότι
 * μειώνει τη σάρωση, και εδώ **επιπλέον** δημοσιοποιεί.
 */
export interface PublicListing {
  /**
   * **Ίδιο με το `propertyId`** — σχέση 1:1, ταυτότητα **παραγόμενη**, όχι νέα.
   *
   * 🔑 Άρα **δεν χρειάζεται νέα γεννήτρια** (N.6): δεν γεννιέται ταυτότητα, καθρεφτίζεται.
   * Ίδιο ιδίωμα με το `search_documents/{entityType}_{entityId}` (ADR-029). Και είναι
   * αυτό που κάνει τον γραφέα **idempotent**: ίδια είσοδος ⇒ ίδιο έγγραφο, πάντα.
   */
  readonly id: string;

  // ── 1. ΤΙΜΗ ───────────────────────────────────────────────────────────────
  /**
   * ⚠️ **Ωμοί αριθμοί, ΟΧΙ λυμένη τιμή — και είναι απόφαση κατά της διπλασίασης.**
   *
   * Το σχήμα ικανοποιεί **δομικά** το `PricedPropertyLike`, οπότε η οθόνη καλεί τον
   * **υπάρχοντα** SSoT (`lib/properties/price-resolver.ts`, 23 καταναλωτές). Αν η
   * τιμή λυνόταν εδώ, θα υπήρχε **δεύτερη** μηχανή τιμής μέσα στο `functions/` — και
   * η μέρα που θα διαφωνούσαν με την οθόνη είναι ερώτημα **πότε**, όχι **αν**.
   */
  readonly commercialStatus: CommercialStatus;
  readonly commercial: {
    readonly askingPrice: number | null;
    readonly finalPrice: number | null;
    readonly rentPrice: number | null;
  };

  // ── 2. ΕΙΚΟΝΑ ─────────────────────────────────────────────────────────────
  /**
   * `null` = **δεν υπάρχει**, και η οθόνη οφείλει να το πει.
   *
   * ⛔ **Ποτέ εξωτερικό placeholder.** Μετρήθηκε (§25.5.2) ότι μια κάρτα με ξένη
   * εικόνα-θέσης διαβάζεται ως **αληθινή φωτογραφία που δεν δείχνει αυτό το ακίνητο**
   * — χειρότερο από την απουσία, γιατί λέει ψέματα αντί να σιωπά.
   */
  readonly coverImage: ListingImage | null;

  // ── 3. ΕΙΔΟΣ + ΕΜΒΑΔΟΝ ────────────────────────────────────────────────────
  readonly type: PropertyType;
  /** Μικτό εμβαδόν σε m². `null` = δεν καταχωρήθηκε — **ποτέ** `0` ως «άγνωστο». */
  readonly areaSqm: number | null;

  // ── 4. ΔΙΑΘΕΣΕΙΣ (Α20) ────────────────────────────────────────────────────
  /**
   * 🔑 **Ο άξονας όπου δεν χάνεται τίποτα.** Το `commercialStatus` είναι **ρητά lossy**:
   * ένα ακίνητο **μόνο προς αντιπαροχή** προβάλλεται σε `'unavailable'` — αληθές για το
   * παλιό λεξιλόγιο, αλλά θα το έκανε **αόρατο**. Κάθε οθόνη ρωτά **αυτό**.
   */
  readonly offerKinds: readonly OfferKind[];

  // ── 5. ΘΕΣΗ (Α1 · Α5) ─────────────────────────────────────────────────────
  /** Λυμένη στον διακομιστή με `outranksForLocation` — **πάντα** με προέλευση. */
  readonly position: ListingPosition;

  /**
   * 🔴 **ΣΕ ΠΟΙΟΝ ΤΟΠΟ ΤΟΥ ΕΠΙΠΕΔΟΥ Α ΑΝΗΚΕΙ** — ή `null` όταν δεν το ξέρουμε.
   *
   * Αυτό το πεδίο **είναι** ολόκληρο το §14.5: *«μία ταυτότητα ανά φυσικό κτίριο …
   * το ταίριασμα γίνεται δυνατό **επειδή** το Α είναι ένα»*. Χωρίς αυτό, μια ζήτηση
   * **Ζ3/Ζ5** («*αυτό το κτίριο*») δεν έχει με τι να συγκρίνει την αγγελία, και η
   * μηχανή απαντά ειλικρινά `place-unresolved` — που ήταν η κατάσταση μέχρι σήμερα.
   *
   * ⚠️ **Η προσθήκη σε αυτό το κλειστό σχήμα είναι ΑΠΟΦΑΣΗ ΑΠΟΚΑΛΥΨΗΣ**, όπως λέει
   * ρητά το `demand-answer.ts`: *«ό,τι δεν είναι γραμμένο εδώ, δεν φεύγει ποτέ»*.
   * Είναι ασφαλής για **δομικό** λόγο και όχι επειδή «δεν φαίνεται κάτι»: τα
   * `land_*` / `pbld_*` δείχνουν στο **κοινό** επίπεδο Α, που ο κανόνας Firestore
   * δίνει σε **κάθε** επισκέπτη (`read: if true`). Δεν αποκαλύπτεται τίποτα που ο
   * επισκέπτης δεν μπορούσε ήδη να διαβάσει — και **καμία** ταυτότητα πελάτη,
   * χρήστη ή έργου δεν μπαίνει εδώ (§14.4 κανόνας 4).
   *
   * ⚠️ **Ισχυρισμός, όχι επαληθευμένο γεγονός** (§14.3, τελευταία παράγραφος):
   * *«μπορεί να κατέχει **ακίνητο μέσα** σε αυτό — και αυτό είναι ισχυρισμός μέχρι
   * να επαληθευτεί»*. Ζει στο **επίπεδο Β** του κατόχου και δεν αγγίζει το κοινό Α.
   */
  readonly place: PlaceRef | null;

  // ── +2 ΕΙΔΙΚΑ ─────────────────────────────────────────────────────────────
  /**
   * **Ο ΟΡΟΦΟΣ** — το ένα πράγμα που προσθέτει το ακίνητο πάνω στο κτίριο (Α1).
   * `null` = δεν καταχωρήθηκε· `0` είναι **ισόγειο**, υπαρκτή τιμή.
   */
  readonly floor: number | null;
  /** Υπνοδωμάτια. `null` = δεν καταχωρήθηκε· `0` = studio, υπαρκτή τιμή. */
  readonly bedrooms: number | null;

  // ── ΜΕΤΑΔΕΔΟΜΕΝΑ ΠΡΟΒΟΛΗΣ ─────────────────────────────────────────────────
  /** Τίτλος προς εμφάνιση. Κείμενο του κατόχου — **όχι** κλειδί i18n. */
  readonly title: string;
  /** ISO timestamp της τελευταίας **ανακατασκευής** αυτής της προβολής. */
  readonly projectedAt: string;
}

/**
 * 🔶 **ΔΗΛΩΜΕΝΟ ΚΕΝΟ, με όνομα:** λείπει το 4ο βασικό πεδίο του §25.6 — **νομιμότητα +
 * προέλευση** (**Α17**). Μετρήθηκε ότι **δεν υπάρχει καθόλου** στον κώδικα σήμερα (grep
 * σε `types/` · `lib/` · `constants/` ⇒ μηδέν).
 *
 * **ΜΗΝ το επινοήσεις εδώ.** Η Α17 το ορίζει ως *«κλίμακα με προέλευση»* — δηλαδή SSoT
 * με δικό του λεξιλόγιο· γεννημένο μέσα σε ένα αρχείο **προβολής** θα ήταν ο ορισμός
 * του «δεύτερη αλήθεια σε λάθος στρώμα». Η προσθήκη του αργότερα είναι **επαυξητική**:
 * ένα πεδίο παραπάνω, κανένας καταναλωτής δεν σπάει.
 */
export type PublicListingOpenGaps = never;

