/**
 * **«14 ακίνητα · 11 στον χάρτη · 3 χωρίς δηλωμένη θέση»** — *πάντα*, ακόμη και στο μηδέν.
 *
 * 🔑 **Είναι η δική μας αποδεδειγμένη πρακτική των πυλών, μεταφερμένη στην οθόνη**
 * (CHECK 3.39 · 3.42 · 3.44 · 3.46 · 3.47 · 3.48: *κλειστή λογιστική, fail-closed, το «0»
 * τυπώνεται ακόμη κι όταν είναι 0*). **Δεν βρέθηκε portal ακινήτων που να το κάνει.**
 *
 * Μια λίστα που δείχνει 14 και ένας χάρτης που δείχνει 11 **χωρίς να το πει** είναι το
 * ίδιο ψέμα με πύλη που τυπώνει «0 παραβιάσεις» επειδή δεν κοίταξε.
 *
 * ⚠️ **Τα δύο μέρη είναι ξεχωριστά πεδία, ΟΧΙ ένα με αφαίρεση.** Ένας καταναλωτής που
 * υπολογίζει `total - mapped` θα έχει δίκιο μέχρι την πρώτη φορά που κάποιος προσθέσει
 * τρίτη κατηγορία — και τότε το άθροισμα θα κλείνει **λάθος, σιωπηλά**. Το
 * {@link ledgerBalances} το κάνει **λέξιμο**.
 */
export interface ListingLedger {
  /** Πόσα απάντησαν στο ερώτημα. */
  readonly total: number;
  /** Πόσα από αυτά έχουν σχήμα στον χάρτη. */
  readonly mapped: number;
  /** Πόσα **δεν** έχουν — και **δεν** εξαφανίζονται (Α5 §4.1). */
  readonly unmapped: number;
}

/**
 * Κλείνει το άθροισμα;
 *
 * 🔴 **Υπάρχει για να αποτύχει θορυβωδώς, όχι για να επιβεβαιώνει.** Το ίδιο εργαλείο
 * που οι πύλες μας ονομάζουν *fail-closed*: αν κάποτε προστεθεί κατάσταση που δεν
 * μετριέται σε κανέναν από τους δύο κάδους, το εύρημα εμφανίζεται **εδώ**, αμέσως — και
 * όχι ως χάρτης που δείχνει λιγότερα από τη λίστα χωρίς να το πει κανείς.
 */
export function ledgerBalances(ledger: ListingLedger): boolean {
  return ledger.mapped + ledger.unmapped === ledger.total;
}

/**
 * **Η ΔΕΥΤΕΡΗ ΡΗΤΡΑ ΤΟΥ ΙΔΙΟΥ ΚΑΝΟΝΑ** (ADR-777 §8.62) — *«καλύπτει η λογιστική ό,τι
 * ΠΡΑΓΜΑΤΙΚΑ ζωγραφίστηκε;»*
 *
 * 🔴 **ΓΙΑΤΙ ΔΕΝ ΑΡΚΟΥΣΕ ΤΟ {@link ledgerBalances}.** Εκείνο ελέγχει ότι η λογιστική
 * κλείνει **μέσα της** (`mapped + unmapped === total`) — και θα έκλεινε **μια χαρά**
 * ενώ η λίστα δίπλα ζωγράφιζε **οκτώ** κάρτες. Το άθροισμα ήταν σωστό· ο αριθμός
 * ήταν **άλλου συνόλου**. Δηλαδή ο μετρητής μπορούσε να είναι ταυτόχρονα **συνεπής
 * και ψεύτης**, και κανένα από τα δύο δεν το έβλεπε κανείς.
 *
 * ⚠️ **Ως σήμερα τα δύο σύνολα συνέπιπταν ΚΑΤΑ ΚΑΤΑΣΚΕΥΗ, όχι κατά δήλωση**: η οθόνη
 * έτρεφε τη λογιστική με το `visible` και τη λίστα με τη διαμέριση **του ίδιου**
 * `visible`. Κανείς δεν τα είχε δέσει — απλώς κανείς δεν είχε κόψει ακόμη. Το Βήμα 3
 * (φιλτράρισμα από το οπτικό πεδίο του χάρτη) **θα** κόψει, και τότε η σύμπτωση
 * σταματά **σιωπηλά**. Αυτή η συνάρτηση είναι ο λόγος που δεν θα σταματήσει σιωπηλά.
 *
 * 🔑 **Ο ΣΥΝΑΓΕΡΜΟΣ ΕΙΝΑΙ Ο ΙΔΙΟΣ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ**: με τον Δρόμο Α (ADR-777 §8.62)
 * **τίποτα δεν κρύβεται σκόπιμα** — καμία σελιδοποίηση, κανένα ταβάνι, καμία κάρτα
 * εκτός DOM. Άρα μια απόκλιση **δεν είναι κατάσταση προς ανακοίνωση, είναι σφάλμα**,
 * και το υπάρχον `search-results:ledger.imbalanced` («*αυτό είναι σφάλμα, όχι
 * κατάσταση*») το λέει ήδη κυριολεκτικά. Την ημέρα που κάποιο βήμα θα κρύψει κάτι
 * **επίτηδες**, αυτός ο συναγερμός χτυπά και **απαιτεί** να γραφτεί τότε το ρητό
 * κείμενο «δείχνουμε N από M» — αντί να το προεξοφλήσουμε σήμερα για συνθήκη που δεν
 * υπάρχει. *(Και το κείμενο δεν χωρούσε: το namespace είχε **57 bytes** περιθώριο.)*
 */
export function ledgerCoversRendered(ledger: ListingLedger, renderedCount: number): boolean {
  return ledger.total === renderedCount;
}
