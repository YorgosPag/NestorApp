/**
 * Εικόνα εξωφύλλου.
 *
 * ⚠️ **`width`/`height` υποχρεωτικά** — δεν είναι πληρότητα: χωρίς αυτά ο περιηγητής
 * δεν μπορεί να κρατήσει τον χώρο πριν φορτώσει η εικόνα, και οι κάρτες «πηδάνε» ενώ ο
 * χρήστης πάει να πατήσει μία. Είναι το **CLS < 0,1** που η Α19 δεσμεύτηκε **αριθμητικά**.
 */
export interface ListingImage {
  readonly url: string;
  readonly width: number;
  readonly height: number;
  /** Κείμενο εναλλακτικής περιγραφής — **κλειδί i18n**, ποτέ ωμό κείμενο (N.11). */
  readonly altKey: string;
}

/**
 * **ΟΙ ΟΡΟΙ ΔΙΑΜΟΝΗΣ** — τρία πεδία, **κανένα ημερολόγιο** (ADR-835 §4.5).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ ΓΙΑΤΙ ΔΕΝ ΥΠΑΡΧΕΙ ΕΔΩ ΗΜΕΡΟΛΟΓΙΟ — ΤΡΕΙΣ ΛΟΓΟΙ, ΟΛΟΙ ΔΕΣΜΕΥΤΙΚΟΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * 1. **Είναι απόφαση δημοσιοποίησης** — το πλήρες ημερολόγιο αποκαλύπτει *πόσο
 *    γεμάτος* είναι ο οικοδεσπότης, δηλαδή **επιχειρηματικό δεδομένο τρίτου**.
 * 2. **Μέγεθος** — 365 εγγραφές ανά ακίνητο σε έγγραφο που διαβάζει **κάθε** ανώνυμος
 *    σκοντάφτει στην **Α19** (πρώτος καρές· `CLS < 0,1` δεσμευμένο **αριθμητικά**).
 * 3. **Ακυρότητα** — αλλάζει σε **κάθε** κράτηση, άρα η προβολή θα ξαναγραφόταν
 *    συνεχώς και θα ήταν **μπαγιάτικη ανάμεσα**.
 *
 * ⇒ Η διαθεσιμότητα απαντιέται με **ερώτημα στον διακομιστή**, ποτέ με προ-φόρτωση.
 * Ο τύπος της απάντησης ζει στο `lib/stay/stay-availability-vocabulary.ts` και **δεν
 * αγγίζει αυτό το σχήμα** — γι' αυτό ακριβώς είναι ξεχωριστός.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΑ ΤΡΙΑ ΠΕΔΙΑ ΔΕΝ ΕΙΝΑΙ ΙΣΟΤΙΜΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Τα δύο πρώτα είναι **σταθεροί όροι** που δηλώνει ο κάτοχος μία φορά — δεν
 * μπαγιατεύουν, δεν αποκαλύπτουν πληρότητα, και **απαντούν** σε ερώτηση που ο
 * επισκέπτης όντως κάνει («*χωράμε τέσσερις;*»). Το τρίτο είναι **παράγωγο του
 * ημερολογίου**, και είναι το **μοναδικό** ψήγμα του που επιτρέπεται να φύγει: **ένα**
 * σημείο, ποτέ σειρά — δες το σχόλιό του.
 */
export interface PublicListingStay {
  /**
   * Ελάχιστες νύχτες που δέχεται ο κάτοχος. `null` = **δεν δήλωσε ελάχιστο**.
   *
   * ⚠️ **`null` ΔΕΝ είναι `1`.** «Δεν δήλωσε» και «δέχεται μία νύχτα» είναι δύο
   * δηλώσεις, και μόνο η δεύτερη είναι υπόσχεση. Ένα `?? 1` εδώ θα έκανε τη μηχανή να
   * υπόσχεται εκ μέρους του κατόχου — το ίδιο σχήμα που η Α5 απαγορεύει για τη θέση.
   */
  readonly minNights: number | null;
  /**
   * Πόσα άτομα χωράει. `null` = **δεν δήλωσε χωρητικότητα**.
   *
   * 🔴 Το `null` παράγει **δικό του** όνομα στην απάντηση (`terms-unknown`), ποτέ
   * σιωπηλό «χωράει» ή «δεν χωράει» (N.12). Η θεραπεία ανήκει στον **κάτοχο**.
   */
  readonly maxGuests: number | null;
  /**
   * **Η επόμενη ελεύθερη ημερομηνία** — ISO `YYYY-MM-DD`. `null` = δεν το ξέρουμε.
   *
   * 🔴 **ΕΝΑ ΣΗΜΕΙΟ, ΠΟΤΕ ΗΜΕΡΟΛΟΓΙΟ — και ΠΟΤΕ ΚΡΙΤΗΣ ΔΙΑΘΕΣΙΜΟΤΗΤΑΣ.** Είναι
   * ένδειξη για τον επισκέπτη που **δεν** έδωσε ημερομηνίες, και **τίποτα άλλο**.
   *
   * ⚠️ **ΛΕΕΙ ΨΕΜΑΤΑ ΓΙΑ ΤΑ ΚΕΝΑ, ΚΑΙ ΕΙΝΑΙ ΜΕΤΡΗΜΕΝΟ**: με κρατήσεις 12–14/08 και
   * ελεύθερα 05–12/08, το πεδίο γράφει `05/08`. Ένα φίλτρο που ρωτούσε
   * *«`nextAvailableFrom <= checkIn`;»* θα απαντούσε **«ναι, ελεύθερο»** για το
   * 12–14/08 — δηλαδή **overbooking με τη σφραγίδα μας από κάτω**. Γι' αυτό η
   * διαθεσιμότητα κρίνεται **αποκλειστικά** από τον κριτή κατάληψης, στον διακομιστή.
   *
   * 🏆 **Και έχει δεύτερο καταναλωτή που κανείς δεν έχει** (§4.7 #2): μπαίνει στην
   * αγγελία **ΠΩΛΗΣΗΣ** του ίδιου ακινήτου ως *«ελεύθερο από …»*. Σήμερα η αγορά
   * βγάζει αυτή την πληροφορία **μετά** το «το παίρνω» — τη χειρότερη δυνατή στιγμή.
   */
  readonly nextAvailableFrom: string | null;
}

/**
 * **Ό,τι βλέπει ο κόσμος για ένα ακίνητο.** Γράφεται **μόνο** από τον διακομιστή.
 *
 * Τα πεδία είναι **ακριβώς** τα «5 βασικά + 3 ειδικά» του §25.6 — και το *«ΠΟΤΕ
 * περισσότερα»* εκεί δεν είναι ύφος: κάθε επιπλέον πεδίο στην κάρτα μετρήθηκε ότι
 * μειώνει τη σάρωση, και εδώ **επιπλέον** δημοσιοποιεί.
 */
export interface PublicListing {
  /**
   * **Ίδιο με το `propertyId`** — σχέση 1:1, ταυτότητα **παραγόμενη**, όχι νέα.
   *
   * 🔑 Άρα **δεν χρειάζεται νέα γεννήτρια** (N.6): δεν γεννιέται ταυτότητα, καθρεφτίζεται.
   * Ίδιο ιδίωμα με το `search_documents/{entityType}_{entityId}` (ADR-029). Και είναι
   * αυτό που κάνει τον γραφέα **idempotent**: ίδια είσοδος ⇒ ίδιο έγγραφο, πάντα.
   */
  readonly id: string;

  // ── 1. ΤΙΜΗ ───────────────────────────────────────────────────────────────
  /**
   * ⚠️ **Ωμοί αριθμοί, ΟΧΙ λυμένη τιμή — και είναι απόφαση κατά της διπλασίασης.**
   *
   * Το σχήμα ικανοποιεί **δομικά** το `PricedPropertyLike`, οπότε η οθόνη καλεί τον
   * **υπάρχοντα** SSoT (`lib/properties/price-resolver.ts`, 23 καταναλωτές). Αν η
   * τιμή λυνόταν εδώ, θα υπήρχε **δεύτερη** μηχανή τιμής μέσα στο `functions/` — και
   * η μέρα που θα διαφωνούσαν με την οθόνη είναι ερώτημα **πότε**, όχι **αν**.
   */
  readonly commercialStatus: CommercialStatus;
  readonly commercial: {
    readonly askingPrice: number | null;
    readonly finalPrice: number | null;
    readonly rentPrice: number | null;
    /**
     * Τιμή **ανά διανυκτέρευση** (ADR-835 §4.4 · §4.5).
     *
     * 🔴 **Η προσθήκη σε κλειστό σχήμα είναι ΑΠΟΦΑΣΗ ΑΠΟΚΑΛΥΨΗΣ, και εδώ είναι
     * τετριμμένη**: είναι η **ζητούμενη τιμή** μιας διάθεσης — ό,τι ακριβώς είναι ήδη
     * το `askingPrice` και το `rentPrice`. Ένα κατάλυμα που δεν λέει πόσο κοστίζει η
     * βραδιά δεν είναι κατάλυμα στην αγορά (Α22).
     *
     * ⛔ **ΚΑΙ ΕΙΝΑΙ ΤΟ ΜΟΝΟ ΠΟΥ ΤΑΞΙΔΕΥΕΙ ΑΠΟ ΤΗ ΒΡΑΧΥΧΡΟΝΙΑ, ΠΡΟΣ ΤΟ ΠΑΡΟΝ.** Οι
     * όροι διαμονής (`minNights`/`maxGuests`) και η **επόμενη ελεύθερη ημερομηνία**
     * ζουν στο `stay` του §4.5, που είναι **Φ3** — και ολόκληρο ημερολόγιο **ΠΟΤΕ**:
     * αποκαλύπτει πόσο γεμάτος είναι ο οικοδεσπότης, ξεπερνά το βάρος της Α19 και
     * μπαγιατεύει σε **κάθε** κράτηση.
     */
    readonly nightlyRate: number | null;
  };

  // ── 1β. ΟΙ ΟΡΟΙ ΔΙΑΜΟΝΗΣ (ADR-835 §4.5) ───────────────────────────────────
  /**
   * `null` όταν το {@link PublicListing.offerKinds} **δεν** περιέχει `'leaseShort'`.
   *
   * 🔴 **`null` ΚΑΙ ΟΧΙ αντικείμενο με μηδενικά — η διάκριση είναι ελέγξιμη.** Ένα
   * `{ minNights: null, maxGuests: null, nextAvailableFrom: null }` σε ακίνητο προς
   * **πώληση** θα σήμαινε *«κατάλυμα που δεν δήλωσε τίποτα»*, δηλαδή θα το έβαζε στον
   * κάδο `terms-unknown` της αναζήτησης και θα κατηγορούσε τον κάτοχο για πεδίο που
   * **δεν του ζητήθηκε ποτέ**. Άγκυρα **και προς τις δύο κατευθύνσεις**: με
   * `leaseShort` **υπάρχει**, χωρίς `leaseShort` είναι **`null`**.
   */
  readonly stay: PublicListingStay | null;

  // ── 2. ΕΙΚΟΝΑ ─────────────────────────────────────────────────────────────
  /**
   * `null` = **δεν υπάρχει**, και η οθόνη οφείλει να το πει.
   *
   * ⛔ **Ποτέ εξωτερικό placeholder.** Μετρήθηκε (§25.5.2) ότι μια κάρτα με ξένη
   * εικόνα-θέσης διαβάζεται ως **αληθινή φωτογραφία που δεν δείχνει αυτό το ακίνητο**
   * — χειρότερο από την απουσία, γιατί λέει ψέματα αντί να σιωπά.
   */
  readonly coverImage: ListingImage | null;

  // ── 3. ΕΙΔΟΣ + ΕΜΒΑΔΟΝ ────────────────────────────────────────────────────
  readonly type: PropertyType;
  /** Μικτό εμβαδόν σε m². `null` = δεν καταχωρήθηκε — **ποτέ** `0` ως «άγνωστο». */
  readonly areaSqm: number | null;

  // ── 4. ΔΙΑΘΕΣΕΙΣ (Α20) ────────────────────────────────────────────────────
  /**
   * 🔑 **Ο άξονας όπου δεν χάνεται τίποτα.** Το `commercialStatus` είναι **ρητά lossy**:
   * ένα ακίνητο **μόνο προς αντιπαροχή** προβάλλεται σε `'unavailable'` — αληθές για το
   * παλιό λεξιλόγιο, αλλά θα το έκανε **αόρατο**. Κάθε οθόνη ρωτά **αυτό**.
   */
  readonly offerKinds: readonly OfferKind[];

  // ── 5. ΘΕΣΗ (Α1 · Α5) ─────────────────────────────────────────────────────
  /** Λυμένη στον διακομιστή με `outranksForLocation` — **πάντα** με προέλευση. */
  readonly position: ListingPosition;

  /**
   * 🔴 **ΣΕ ΠΟΙΟΝ ΤΟΠΟ ΤΟΥ ΕΠΙΠΕΔΟΥ Α ΑΝΗΚΕΙ** — ή `null` όταν δεν το ξέρουμε.
   *
   * Αυτό το πεδίο **είναι** ολόκληρο το §14.5: *«μία ταυτότητα ανά φυσικό κτίριο …
   * το ταίριασμα γίνεται δυνατό **επειδή** το Α είναι ένα»*. Χωρίς αυτό, μια ζήτηση
   * **Ζ3/Ζ5** («*αυτό το κτίριο*») δεν έχει με τι να συγκρίνει την αγγελία, και η
   * μηχανή απαντά ειλικρινά `place-unresolved` — που ήταν η κατάσταση μέχρι σήμερα.
   *
   * ⚠️ **Η προσθήκη σε αυτό το κλειστό σχήμα είναι ΑΠΟΦΑΣΗ ΑΠΟΚΑΛΥΨΗΣ**, όπως λέει
   * ρητά το `demand-answer.ts`: *«ό,τι δεν είναι γραμμένο εδώ, δεν φεύγει ποτέ»*.
   * Είναι ασφαλής για **δομικό** λόγο και όχι επειδή «δεν φαίνεται κάτι»: τα
   * `land_*` / `pbld_*` δείχνουν στο **κοινό** επίπεδο Α, που ο κανόνας Firestore
   * δίνει σε **κάθε** επισκέπτη (`read: if true`). Δεν αποκαλύπτεται τίποτα που ο
   * επισκέπτης δεν μπορούσε ήδη να διαβάσει — και **καμία** ταυτότητα πελάτη,
   * χρήστη ή έργου δεν μπαίνει εδώ (§14.4 κανόνας 4).
   *
   * ⚠️ **Ισχυρισμός, όχι επαληθευμένο γεγονός** (§14.3, τελευταία παράγραφος):
   * *«μπορεί να κατέχει **ακίνητο μέσα** σε αυτό — και αυτό είναι ισχυρισμός μέχρι
   * να επαληθευτεί»*. Ζει στο **επίπεδο Β** του κατόχου και δεν αγγίζει το κοινό Α.
   */
  readonly place: PlaceRef | null;

  // ── +2 ΕΙΔΙΚΑ ─────────────────────────────────────────────────────────────
  /**
   * **Ο ΟΡΟΦΟΣ** — το ένα πράγμα που προσθέτει το ακίνητο πάνω στο κτίριο (Α1).
   * `null` = δεν καταχωρήθηκε· `0` είναι **ισόγειο**, υπαρκτή τιμή.
   */
  readonly floor: number | null;
  /** Υπνοδωμάτια. `null` = δεν καταχωρήθηκε· `0` = studio, υπαρκτή τιμή. */
  readonly bedrooms: number | null;

  // ── ΝΟΜΙΜΟΤΗΤΑ (Α17 · ADR-838) ────────────────────────────────────────────
  /**
   * 🔴 **ΤΟ 4ο ΒΑΣΙΚΟ ΠΕΔΙΟ ΤΟΥ §25.6 — ΚΑΙ ΕΠΙ ΤΡΕΙΣ ΕΒΔΟΜΑΔΕΣ ΗΤΑΝ ΔΗΛΩΜΕΝΟ ΚΕΝΟ.**
   *
   * Ό,τι ξέρουμε για τη νομιμότητα, **ως κλίμακα με προέλευση** — ποτέ ως ναι/όχι, και
   * ποτέ ως «νόμιμο». Μία γραμμή ανά **είδος αξίωσης** που σηκώνουν οι διαθέσεις αυτού
   * του ακινήτου, **συν** τις γραμμές `not-applicable` για όσα δεν σηκώνονται.
   *
   * ⛔ **ΚΑΝΕΝΑ ΕΓΓΡΑΦΟ, ΠΟΤΕ — ΚΑΙ ΤΟ ΕΠΙΒΑΛΛΕΙ Ο ΤΥΠΟΣ.** Το `LegalitySignal` δεν
   * **έχει** πεδίο εγγράφου: η μόνη τιμή που ταξιδεύει είναι το `value`, και εκείνο
   * περνά από τη μία πύλη του `legalitySignalFor` (είδη `'withheld'` το μηδενίζουν).
   *
   * 🔑 **ΓΙΑΤΙ ΤΟ ΙΔΙΟ ΛΕΞΙΛΟΓΙΟ ΜΕ ΤΟ `lib/legality/` ΚΑΙ ΟΧΙ ΔΙΚΟ ΤΟΥ**: μια δεύτερη
   * «δημόσια» εκδοχή θα ήταν δεύτερη αλήθεια — και θα έπρεπε κάποιος να θυμάται να τη
   * συγχρονίζει **ακριβώς** στο σημείο όπου η αστοχία λέγεται «δημοσιεύσαμε ό,τι δεν
   * έπρεπε». Το σχήμα είναι **ήδη** δημοσιεύσιμο εξ ορισμού (βαθμίδα = **κλάση**, όχι
   * ταυτότητα — ίδιο επιχείρημα με το {@link authorship}).
   *
   * ⚠️ **Κενός πίνακας = «κανείς δεν ρώτησε», και ΔΕΝ πρέπει να συμβαίνει**: ο γραφέας
   * γράφει γραμμή για **κάθε** είδος. Η άγκυρα το ελέγχει με τον πλήρη παρονομαστή,
   * επειδή η Φ3 μέτρησε **δύο ελλιπείς λίστες που επιβεβαίωναν η μία την άλλη**.
   */
  readonly legality: readonly LegalitySignal[];

  // ── ΠΡΟΕΛΕΥΣΗ ΤΗΣ ΑΓΓΕΛΙΑΣ (§8.33) ────────────────────────────────────────
  /**
   * 🔴 **ΠΟΙΟΣ ΤΗ ΔΗΛΩΝΕΙ, ΩΣ ΚΛΑΣΗ** — και είναι η δεύτερη μισή μιας απόφασης που
   * ήταν γραμμένη από τις 2026-08-11 και **δεν είχε κανέναν καταναλωτή**.
   *
   * Το `LISTING_AUTHORSHIPS` το τεκμηριώνει: *«μια αγγελία γραφείου και μια αγγελία
   * αγνώστου θα φαίνονταν **ταυτόσημες**, δηλαδή θα λέγαμε στον επισκέπτη ότι ξέρουμε
   * κάτι που δεν ξέρουμε»*. Μέχρι το §8.33 το πεδίο υπήρχε **μόνο ως τύπος**.
   *
   * ⚠️ **ΚΛΑΣΗ, ΟΧΙ ΤΑΥΤΟΤΗΤΑ** — γι' αυτό επιτρέπεται να δημοσιευτεί. Ένα
   * `'owner-declared'` δεν λέει **ποιος**· λέει **τι είδους γνώση** είναι αυτή η
   * γραμμή.
   */
  readonly authorship: ListingAuthorship;
  /**
   * Η **επωνυμία του γραφείου**, όταν η αγγελία προέρχεται από γραφείο. `null` αλλιώς.
   *
   * 🔴 **ΕΙΝΑΙ Η ΜΟΝΗ ΕΠΩΝΥΜΙΑ ΠΟΥ ΦΕΥΓΕΙ ΠΟΤΕ ΑΠΟ ΑΥΤΟ ΤΟ ΣΧΗΜΑ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ
   * ΤΟΥ GIORGIO (2026-08-20)**, όχι λεπτομέρεια υλοποίησης. Το ερώτημα ήταν *«τι λέει
   * η αγγελία στον εργολάβο για το ποιος τη δημοσίευσε;»* και η απάντηση ήταν **με την
   * επωνυμία**: ένα γραφείο ανεβάζει αγγελίες **για να φαίνεται**.
   *
   * ⚠️ **Επωνυμία ΕΠΙΧΕΙΡΗΣΗΣ, ποτέ όνομα ΠΡΟΣΩΠΟΥ.** Ο ιδιώτης δεν φαίνεται ποτέ: για
   * εκείνον το `authorship` είναι `'owner-declared'` και εδώ υπάρχει **μόνο** `null` —
   * δεν υπάρχει καν τιμή να διαρρεύσει. Ούτε ο **πελάτης** του γραφείου φαίνεται: η
   * εντολή είναι επίπεδο Β.
   *
   * 🔶 **ΔΗΛΩΜΕΝΟ ΚΕΝΟ**: οι αγγελίες **έργων** (`properties`) γράφουν σήμερα `null`.
   * Δεν είναι παράλειψη — είναι ότι η επωνυμία τους θα απαιτούσε **μία ανάγνωση
   * εταιρείας ανά ακίνητο** μέσα στον βρόχο ανακατασκευής (`republishListingsForProject`),
   * δηλαδή απόφαση **απο-κανονικοποίησης** που δεν πάρθηκε. Η προσθήκη είναι
   * επαυξητική: ένα πεδίο γεμίζει, κανένας καταναλωτής δεν σπάει.
   */
  readonly agencyName: string | null;

  // ── ΜΕΤΑΔΕΔΟΜΕΝΑ ΠΡΟΒΟΛΗΣ ─────────────────────────────────────────────────
  /** Τίτλος προς εμφάνιση. Κείμενο του κατόχου — **όχι** κλειδί i18n. */
  readonly title: string;
  /** ISO timestamp της τελευταίας **ανακατασκευής** αυτής της προβολής. */
  readonly projectedAt: string;
}

/**
 * ✅ **ΤΟ ΚΕΝΟ ΕΚΛΕΙΣΕ — ΚΑΙ ΕΚΛΕΙΣΕ ΟΠΩΣ ΤΟ ΕΓΡΑΦΕ** (2026-08-31, **ADR-838**).
 *
 * Εδώ έγραφε: *«λείπει το 4ο βασικό πεδίο του §25.6 — **νομιμότητα + προέλευση**
 * (**Α17**)… **ΜΗΝ το επινοήσεις εδώ**… SSoT με δικό του λεξιλόγιο· γεννημένο μέσα σε
 * ένα αρχείο **προβολής** θα ήταν ο ορισμός του «δεύτερη αλήθεια σε λάθος στρώμα». Η
 * προσθήκη του αργότερα είναι **επαυξητική**: ένα πεδίο παραπάνω, κανένας καταναλωτής
 * δεν σπάει.»*
 *
 * 🔑 **Και οι τρεις προβλέψεις επαληθεύτηκαν**: το λεξιλόγιο γεννήθηκε στο
 * `lib/legality/` (**οριζόντιο** — η βεβαίωση μηχανικού αφορά τη **μεταβίβαση**, όχι τη
 * βραχυχρόνια)· εδώ μπήκε **ένα** πεδίο ({@link PublicListing.legality})· και κανένας
 * καταναλωτής δεν άλλαξε συμπεριφορά — μόνο ο **γραφέας** και η **οθόνη** έμαθαν κάτι
 * παραπάνω να πουν.
 *
 * ⚠️ **Ο τύπος μένει `never` και ΔΕΝ διαγράφεται**: είναι το σημείο όπου δηλώνεται
 * *«τι λείπει ακόμη από αυτό το σχήμα»*, και σήμερα η απάντηση είναι **τίποτα από τα
 * βασικά**. Ένα διαγραμμένο `never` θα σήμαινε ότι κανείς δεν κρατά πια τον
 * λογαριασμό — δηλαδή το κενό θα ξαναγεννιόταν **σιωπηλό**. Επόμενο κενό ⇒ γράφεται
 * **εδώ**, με όνομα και λόγο.
 */
export type PublicListingOpenGaps = never;

