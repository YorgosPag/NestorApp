/**
 * Ποιος **δηλώνει** αυτή την αγγελία, ως **κλάση** — ποτέ ως ταυτότητα.
 *
 * 🔴 **Είναι η δεύτερη μισή της απόφασης «δημοσιεύεται αμέσως».** Η απόφαση ήταν
 * *«αμέσως **+ σήμα προέλευσης**»*, και χωρίς το σήμα θα ήταν μισή: μια αγγελία
 * γραφείου και μια αγγελία αγνώστου θα φαίνονταν **ταυτόσημες**, δηλαδή θα λέγαμε στον
 * επισκέπτη ότι ξέρουμε κάτι που δεν ξέρουμε.
 *
 * 🔑 **Και είναι το ίδιο σχήμα που το έργο έχει ήδη αποφασίσει ΔΥΟ φορές**: το
 * SPEC-777A **§14.3** (*«ο χρήστης δεν αλλάζει το κοινό — **προτείνει**· η πρόταση ζει
 * στο δικό του επίπεδο Β με σήμα **δηλωμένο, μη επαληθευμένο**»*) και η **Α17** (η
 * νομιμότητα ως **κλίμακα με προέλευση**, όπου το σκαλοπάτι 1 λέγεται
 * `self-declared`). Εδώ δεν επινοείται τρίτο λεξιλόγιο — **αναγνωρίζεται το ίδιο
 * ερώτημα** σε άλλο γνώρισμα.
 *
 * ⚠️ **ΚΛΑΣΗ, ΟΧΙ ΤΑΥΤΟΤΗΤΑ — και γι' αυτό επιτρέπεται να δημοσιευτεί.** Το
 * `types/public-listing.ts` δηλώνει ότι το σχήμα *«δεν περιέχει καμία ταυτότητα
 * πελάτη»*. Ένα `'owner-declared'` δεν λέει **ποιος**· λέει **τι είδους γνώση** είναι
 * αυτή η γραμμή. Η διαφορά είναι ακριβώς ό,τι κάνει το `provenance` της θέσης
 * δημοσιεύσιμο ενώ το `createdBy` όχι.
 */
export const LISTING_AUTHORSHIPS = ['agency', 'owner-declared'] as const;

export type ListingAuthorship = (typeof LISTING_AUTHORSHIPS)[number];

/**
 * **Η ταυτότητα του γραφείου όπως ταξιδεύει προς δημόσια προβολή — ΔΥΟ πεδία σε ΕΝΑ
 * ΑΝΤΙΚΕΙΜΕΝΟ, επίτηδες** (ADR-841 Α1.6).
 *
 * 🔴 **Γιατί δεν είναι δύο ορίσματα**: `(agencyId, agencyName)` είναι δύο γειτονικά
 * `string | null` — ο τύπος **δεν** μπορεί να εμποδίσει να ταξιδέψει το όνομα της
 * εταιρείας Α με την ταυτότητα της Β. Δεμένα σε **μία** τιμή που παράγεται από **μία**
 * ανάγνωση, η ασυμφωνία γίνεται **δομικά αδύνατη** αντί για «απίθανη».
 *
 * 🔑 Ίδιο ιδίωμα με το `PlaceKnowledge`, που δένει `candidates` + `ref` επειδή *«τα
 * λύνει ο ίδιος καλών με το ίδιο ανέβασμα»*: δύο ερωτήσεις, **μία** πηγή.
 *
 * ⚠️ **`{ id: null, name: null }` σημαίνει «δεν προέρχεται από γραφείο»**, όχι
 * «αποτυχία». Ένα `id` **με** `name: null` είναι νόμιμο και ονομάζει την ακριβή
 * κατάσταση *«γραφείο χωρίς επωνυμία»*, που η οθόνη ήδη ξέρει να πει
 * (`listing.authorship.agencyAnonymous`).
 */
export interface PublicAgencyIdentity {
  /** Το `companyId` του γραφείου, ή `null`. **Ποτέ ψευδώνυμο** — δες `agencyId`. */
  readonly id: string | null;
  /** Η επωνυμία, ή `null`. **Επωνυμία επιχείρησης, ποτέ όνομα προσώπου.** */
  readonly name: string | null;
}

