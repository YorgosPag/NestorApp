/**
 * Εικόνα της αγγελίας.
 *
 * ⚠️ **`width`/`height` υποχρεωτικά** — δεν είναι πληρότητα: χωρίς αυτά ο περιηγητής
 * δεν μπορεί να κρατήσει τον χώρο πριν φορτώσει η εικόνα, και οι κάρτες «πηδάνε» ενώ ο
 * χρήστης πάει να πατήσει μία. Είναι το **CLS < 0,1** που η Α19 δεσμεύτηκε **αριθμητικά**.
 */
export interface ListingImage {
  /** Το **κανονικό** (μεγαλύτερο διαθέσιμο) παράγωγο — ο έσχατος στόχος του `src`. */
  readonly url: string;
  readonly width: number;
  readonly height: number;
  /** Κείμενο εναλλακτικής περιγραφής — **κλειδί i18n**, ποτέ ωμό κείμενο (N.11). */
  readonly altKey: string;
  /**
   * 🏆 **ΤΑ ΠΑΡΑΓΩΓΑ, ΚΑΙ ΓΙ' ΑΥΤΟ ΑΥΤΟ ΤΟ ΕΓΓΡΑΦΟ ΕΙΝΑΙ MANIFEST** (ADR-841 §7 Α2.2).
   *
   * Το ράφι είναι **content-addressed**: άλλο πλάτος ⇒ άλλα bytes ⇒ **άλλο κλειδί**. Η
   * **σύνδεσή** τους δεν μπορεί να ζει στο όνομα του αρχείου — ζει **εδώ, μία φορά**, όπως ένα
   * OCI manifest δένει blobs που καθένα έχει δική του διεύθυνση.
   *
   * ⚠️ **Περιέχει ΜΟΝΟ ό,τι ΥΠΑΡΧΕΙ** — κάθε γραμμή γεννήθηκε από bytes που ανέβηκαν.
   * Δεν είναι κατασκευάσιμο από τον πελάτη *(το πρότυπο της Zillow, όπου η διάσταση ζει στο
   * μονοπάτι)*, άρα **δεν υπάρχει 404 παραγώγου**.
   *
   * 🔑 Ταξινομημένο κατά **αύξον πλάτος**, ποτέ κενό: το τελευταίο στοιχείο είναι
   * το ίδιο με το {@link url}. Μικρό πρωτότυπο ⇒ λιγότερα στοιχεία, γιατί τα ταυτόσημα
   * παράγωγα παίρνουν το **ίδιο κλειδί** και συγχωνεύονται **μόνα τους**.
   */
  readonly sources: readonly ListingImageSource[];
}

