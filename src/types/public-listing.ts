/**
 * **«14 ακίνητα · 11 στον χάρτη · 3 χωρίς δηλωμένη θέση»** — *πάντα*, ακόμη και στο μηδέν.
 *
 * 🔑 **Είναι η δική μας αποδεδειγμένη πρακτική των πυλών, μεταφερμένη στην οθόνη**
 * (CHECK 3.39 · 3.42 · 3.44 · 3.46 · 3.47 · 3.48: *κλειστή λογιστική, fail-closed, το «0»
 * τυπώνεται ακόμη κι όταν είναι 0*). **Δεν βρέθηκε portal ακινήτων που να το κάνει.**
 *
 * Μια λίστα που δείχνει 14 και ένας χάρτης που δείχνει 11 **χωρίς να το πει** είναι το
 * ίδιο ψέμα με πύλη που τυπώνει «0 παραβιάσεις» επειδή δεν κοίταξε.
 *
 * ⚠️ **Τα δύο μέρη είναι ξεχωριστά πεδία, ΟΧΙ ένα με αφαίρεση.** Ένας καταναλωτής που
 * υπολογίζει `total - mapped` θα έχει δίκιο μέχρι την πρώτη φορά που κάποιος προσθέσει
 * τρίτη κατηγορία — και τότε το άθροισμα θα κλείνει **λάθος, σιωπηλά**. Το
 * {@link ledgerBalances} το κάνει **λέξιμο**.
 */
export interface ListingLedger {
  /** Πόσα απάντησαν στο ερώτημα. */
  readonly total: number;
  /** Πόσα από αυτά έχουν σχήμα στον χάρτη. */
  readonly mapped: number;
  /** Πόσα **δεν** έχουν — και **δεν** εξαφανίζονται (Α5 §4.1). */
  readonly unmapped: number;
}

/**
 * Κλείνει το άθροισμα;
 *
 * 🔴 **Υπάρχει για να αποτύχει θορυβωδώς, όχι για να επιβεβαιώνει.** Το ίδιο εργαλείο
 * που οι πύλες μας ονομάζουν *fail-closed*: αν κάποτε προστεθεί κατάσταση που δεν
 * μετριέται σε κανέναν από τους δύο κάδους, το εύρημα εμφανίζεται **εδώ**, αμέσως — και
 * όχι ως χάρτης που δείχνει λιγότερα από τη λίστα χωρίς να το πει κανείς.
 */
export function ledgerBalances(ledger: ListingLedger): boolean {
  return ledger.mapped + ledger.unmapped === ledger.total;
}
