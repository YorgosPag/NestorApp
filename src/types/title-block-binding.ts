/**
 * Ο δηλωμένος κατάλογος **επιφυλάξεων**: «μπορεί να γραφτεί — να τι δεν ξέρουμε».
 *
 * 🔴 **Γιατί χρειάστηκε τρίτη κατάσταση, δίπλα σε «προτείνεται» και «μπλοκαρισμένο»
 * (ADR-759 Φ3γ).** Το `ambiguous-abbreviation` ζούσε ως **φραγμός**, και ο φραγμός ήταν
 * λάθος εργαλείο για τη δουλειά του: το `Π.Ε. 39` έχει **γνωστό** πεδίο υποδοχής
 * (`SurveyRecord.settlement.implementationAct.number` — το έλεγε γραπτά ο ίδιος ο resolver)
 * και ο **μηχανικός που κοιτάζει το σχέδιο** ξέρει τι είναι. Ένας φραγμός του έλεγε «δεν
 * γίνεται» για κάτι που **γίνεται** — αδιέξοδο χωρίς ενέργεια, δηλαδή το κάτοπτρο του
 * `resolver-gap` που «υπόσχεται διόρθωση που κανείς δεν μπορεί να κάνει».
 *
 * ⇒ Η πρόταση **παράγεται**, και κουβαλά τον λόγο της αβεβαιότητας. Η βεβαιότητα παραμένει
 * **η μαρτυρία** (ADR-745 §6.2): δεν υπάρχει σκορ και δεν μπαίνει· υπάρχει **πρόταση με
 * δηλωμένη επιφύλαξη**, που ο άνθρωπος αίρει διαβάζοντας — και που ο αναγνώστης του σώματος
 * θα αίρει μόνος του όταν βρει το «ΠΡΑΞΗ ΕΦΑΡΜΟΓΗΣ 39» ολογράφως (ADR-759 §2β.3).
 *
 * 🔑 Ίδιο πρότυπο πίνακα με τα {@link BINDING_EVIDENCE_KINDS} / {@link BINDING_BLOCK_REASONS}
 * — και **με την ίδια πύλη**: το `binding-reason-coverage.test.ts` απαιτεί ισότητα συνόλων
 * ανάμεσα σε αυτόν τον πίνακα και σε ό,τι όντως παράγει ο Λ2. Μια επιφύλαξη χωρίς παραγωγό
 * είναι το ίδιο νεκρό λεξιλόγιο με μια αιτία χωρίς παραγωγό.
 */
export const BINDING_CAUTIONS = [
  /**
   * Η **ίδια συντομογραφία σημαίνει ≥2 πράγματα στο ίδιο σχέδιο**.
   *
   * Η ADR-759 §2β.3 μέτρησε **τρεις** σημασίες του «Π.Ε.» στο **ίδιο** αρχείο (Πράξη
   * Εφαρμογής · Περιφερειακή Ενότητα · λεζάντα εικόνας), και το ίδιο το κείμενο δηλώνει τις
   * πολεοδομικές ενότητες ρητά ως **16 και 17** — άρα το 39 δεν είναι καμία από αυτές.
   *
   * ⚠️ **Η μορφή εξακολουθεί να ΜΗΝ αποφασίζει** — αυτό δεν άλλαξε και δεν πρέπει. Αυτό που
   * άλλαξε είναι **ποιος** αποφασίζει: ο άνθρωπος, με τη διφορούμενη ανάγνωση μπροστά του,
   * αντί για ένα μήνυμα που του έλεγε να περιμένει μια φάση.
   */
  'ambiguous-abbreviation',
  /**
   * Διαβάστηκε **λιγότερη ακρίβεια από όση θέλει το πεδίο**.
   *
   * Μετρημένο: η πινακίδα γράφει «ΙΟΥΛΙΟΣ 2026» και το `surveyDate` είναι ISO `YYYY-MM-DD`.
   * Η τιμή αποθηκεύεται ως `value: null` + `rawText` ακέραιο — τίμια, εμφανίσιμη, και
   * **αναβαθμίσιμη**: το σώμα του ίδιου σχεδίου γράφει «Θεσσαλονίκη 30/7/2026».
   */
  'partial-value',
] as const;

/**
 * Γιατί μια πρόταση **που μπορεί να εγκριθεί** χρειάζεται δεύτερη ματιά.
 *
 * Ποτέ μαζί με `blockedBy`: εκείνο σημαίνει «δεν υπάρχει υποψήφιος», αυτό «υπάρχει, με
 * αστερίσκο». Δύο διαφορετικές προτάσεις προς τον άνθρωπο, δύο διαφορετικές ενέργειες.
 */
export type BindingCaution = (typeof BINDING_CAUTIONS)[number];

export interface BindingProposal {
  readonly fieldKey: ProposalFieldKey;
  /** Ποια πινακίδα του layer — ένα layer φέρει μετρημένα δύο (§2.3 Παγίδα Δ). */
  readonly titleBlockIndex: number;
  /**
   * Το κελί της **τιμής** (id οντότητας σκηνής).
   *
   * 🔴 **ΔΕΝ μπαίνει στο ντετερμινιστικό κλειδί — δεν είναι μοναδικό** (μετρημένο 2026-08-05).
   * Παρά το όνομά του δεν είναι DXF handle: `scene-title-block-cells.ts:96` δίνει `entity.id`, που
   * παράγεται ως `` `${idPrefix}_${index}` `` (`dxf-text-converters.ts:221`) από **δύο ανεξάρτητους
   * μετρητές** — top-level (`dxf-scene-builder.ts:272→314`) και block-flattened (`:265` `idSeq`
   * → `dxf-block-expander.ts:203`) — που **καταλήγουν στην ίδια σκηνή** (`:310`). Πινακίδα μέσα σε
   * BLOCK δίνει έτσι **δύο `mtext_7`** στο ίδιο layer. Χρήσιμο για το overlay της Φ4· **θανατηφόρο**
   * ως ταυτότητα. Το κλειδί χρησιμοποιεί το {@link BindingProposal.at} — δες `lib/title-block-binding-id`.
   */
  readonly sourceHandle: string;
  /** Το κελί της **ετικέτας** — το overlay της Φ4 πρέπει να καλύψει και τα δύο (§6.1). */
  readonly labelHandle: string;
  /**
   * Το **σημείο εισαγωγής** του κελιού της τιμής (WCS) — η **ταυτότητα** του κελιού.
   *
   * 🔑 Σταθερό ανά αρχείο (ίδιο DXF ⇒ ίδιες συντεταγμένες), μοναδικό ανά κελί (δύο MTEXT στο ίδιο
   * σημείο είναι εκφυλισμένο σχέδιο), και **ανεξάρτητο** και από τους δύο μετρητές id και από το
   * κατώφλι ομαδοποίησης. Γι' αυτό το κλειδί χτίζεται από **γεωμετρία**, όχι από μετρητή.
   */
  readonly at: { readonly x: number; readonly y: number };
  /** Τι έγραφε η πινακίδα τη στιγμή της ανάγνωσης. */
  readonly snapshotValue: string;
  /** Το πρόσωπο του κελιού μελετητών, όταν η πρόταση αφορά πρόσωπο. */
  readonly personName?: string;
  /** Ταξινομημένοι· 0 = τίποτα, 1 = βέβαιο, >1 = διφορούμενο (η βεβαιότητα είναι το πλήθος). */
  readonly candidates: readonly BindingCandidate[];
  /** Παρόν **μόνο** όταν `candidates` είναι κενό. */
  readonly blockedBy?: BindingBlockReason;
  /**
   * Παρόν **μόνο** όταν υπάρχει υποψήφιος — αλλιώς θα ήταν δεύτερος τρόπος να πεις «όχι».
   * Δες {@link BINDING_CAUTIONS}.
   */
  readonly caution?: BindingCaution;
  /**
   * Ποιος αναγνώστης την παρήγαγε. **Απόν ⇒ `'title-block'`**, που είναι όλος ο σημερινός Λ2.
   *
   * Προαιρετικό επίτηδες: ένα υποχρεωτικό πεδίο θα ανάγκαζε κάθε υπάρχοντα παραγωγό να
   * δηλώσει το προφανές, και το `exactOptionalPropertyTypes` θα το έκανε θόρυβο σε **επτά**
   * σημεία χωρίς να προσθέσει καμία πληροφορία.
   */
  readonly sourceKind?: BindingSourceKind;
  /**
   * Πόσα **ανεξάρτητα έγγραφα** του ίδιου σχεδίου λένε το ίδιο πράγμα (Φ4).
   *
   * 🔴 **Δεν είναι σκορ βεβαιότητας** — η βεβαιότητα παραμένει η μαρτυρία (§6.2). Είναι
   * μετρημένο γεγονός: στο `G753_ergasia F.dxf` το εμβαδόν του οικοπέδου δηλώνεται **τρεις**
   * φορές, σε τρία αυτοτελή έγγραφα («ΣΤ. ΕΜΒΑΔΟΝ ΟΙΚΟΠΕΔΟΥ Ε = 1.364,05» · «κατά την
   * καταμέτρηση 1364,05» · «ΕΜΒΑΔΟΝ ΓΕΩΤΕΜΑΧΙΟΥ Ε = 1.364,05»), και οι τρεις συμφωνούν.
   *
   * Χωρίς αυτό, οι τρεις δηλώσεις θα ήταν **τρεις πανομοιότυπες γραμμές** — θόρυβος που
   * εκπαιδεύει τον μηχανικό να πατά Έγκριση χωρίς να διαβάζει. Με αυτό, είναι **μία** γραμμή
   * που λέει πόσοι μάρτυρες συμφωνούν. Απόν ⇒ ένας μάρτυρας, που είναι κάθε πρόταση πινακίδας.
   *
   * ⚠️ Όταν οι μάρτυρες **διαφωνούν** δεν συγχωνεύονται: παράγονται χωριστές προτάσεις και
   * διαλέγει ο άνθρωπος. Συγχώνευση διαφωνούντων θα ήταν σιωπηλή επιλογή νικητή.
   */
  readonly corroboration?: number;
  /**
   * Σε ποιο layer βρέθηκε — **μόνο** όταν δεν το ξέρει ο καλών.
   *
   * 🔑 Η παλέτα εξετάζει **ένα** layer πινακίδας τη φορά, οπότε το όνομα είναι ιδιότητα της
   * οθόνης και περνά ως prop. Τα έγγραφα του σώματος όμως ζουν σε **περισσότερα από ένα**
   * layers στο ίδιο φύλλο (μετρημένα: `ΠΕΡΙΓΡΑΦΗ` και `Περίγραμμα`), άρα η πρόταση πρέπει να
   * κουβαλά η ίδια την προέλευσή της — αλλιώς η αποθηκευμένη σύνδεση θα δήλωνε **λάθος layer**.
   */
  readonly layerName?: string;
}

