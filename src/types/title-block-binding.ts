/**
 * Πού μπορεί να προσγειωθεί μια τιμή της πινακίδας.
 *
 * 🔴 **Δεν υπάρχει `{ kind: 'project-field'; field: 'client' }` και δεν πρόκειται να υπάρξει.**
 * Το `Project.client` τυπώνεται σε PDF προβολής ως «Πελάτης», και ο «ΕΡΓΟΔΟΤΗΣ» της πινακίδας
 * είναι η **ιδιοκτήτρια/πωλήτρια** — όχι ο πελάτης (§9 Q1, απόφαση 2026-08-04). Γράφοντάς τον
 * εκεί, ο Νέστωρ θα διαφήμιζε την αντισυμβαλλόμενη ως πελάτισσα.
 */
export type BindingTarget =
  | { readonly kind: 'contact'; readonly contactId: string; readonly role: ProjectRole; readonly projectId: string }
  | {
      readonly kind: 'landowner';
      readonly projectId: string;
      readonly contactId: string;
      readonly acquisitionStatus: AcquisitionStatus;
    }
  | {
      readonly kind: 'project-address';
      readonly projectId: string;
      readonly field: BindableAddressField;
      readonly value: string;
    }
  | {
      readonly kind: 'project-field';
      readonly projectId: string;
      readonly field: BindableProjectField;
      readonly value: string;
    }
  /**
   * Ο **6ος στόχος** (ADR-759 Φ3γ): μια δήλωση του τοπογράφου, μέσα στην εγγραφή που τη
   * μεταγράφει.
   *
   * 🔴 **Το `recordId` είναι ΜΕΡΟΣ ΤΟΥ ΣΤΟΧΟΥ, όχι κάτι που λύνεται τη στιγμή του κλικ.**
   * Ένα έργο αποκτά **περισσότερα από ένα** τοπογραφικά στη ζωή του (αγοράς → εφαρμογής),
   * και το ADR-759 Q1 απαγορεύει ρητά να προκύπτει το ενεργό από ταξινόμηση. Αν ο στόχος
   * έλεγε μόνο «στο τοπογραφικό», ο άνθρωπος θα ενέκρινε **χωρίς να ξέρει σε ποιο** — και
   * ανεβάζοντας παλιό τοπογραφικό θα άλλαζε αναδρομικά το νόημα εγκρίσεων που έχουν ήδη
   * γίνει. Εδώ ο προορισμός είναι ονομαστικός, φαίνεται στη γραμμή, και μπαίνει στο
   * ντετερμινιστικό κλειδί (`targetRef`).
   *
   * 🔑 Η **προέλευση** δεν είναι πεδίο αυτού του τύπου: το `Sourced<T>` της εγγραφής την
   * κουβαλά ήδη (`provenance: 'survey'` + `rawText`). Δεύτερος μηχανισμός προέλευσης θα
   * ήταν ακριβώς η διπλή αλήθεια που το ADR-759 §4.1 υπάρχει για να αποτρέψει.
   */
  | {
      readonly kind: 'survey-record';
      readonly projectId: string;
      /** Σε **ποια** εγγραφή τοπογραφικού — πάντα ονομαστικά. */
      readonly recordId: string;
      readonly field: BindableSurveyField;
      /**
       * Η **αναλυμένη** τιμή, με τον τύπο της δηλωμένο πάνω της· `value: null` όταν το
       * κείμενο δεν αναλύεται.
       *
       * ⚠️ Το `null` **δεν** ακυρώνει την έγκριση — αποθηκεύεται ως `Sourced.value = null`
       * με ακέραιο `rawText` («ΙΟΥΛΙΟΣ 2026»). Είναι η μόνη τίμια απάντηση όταν το σχέδιο
       * λέει μήνα και το πεδίο θέλει ημερομηνία.
       *
       * 🔑 Η **ετικέτα τύπου** (Φ4) δεν είναι πλεονασμός: τα πεδία του σώματος είναι
       * αριθμοί, λογικές τιμές και λίστες, και ο writer πρέπει να διαλέξει τη σωστή `write`.
       * Χωρίς αυτήν θα το έκανε με `typeof`, δηλαδή θα **πετούσε σιωπηλά** ό,τι δεν ταιριάζει.
       */
      readonly value: SurveyParsedValue;
    }
  /**
   * Ο **7ος στόχος** (ADR-759 Φ4β): μια **γραμμή** επαναλαμβανόμενης ενότητας — θεσμική
   * πράξη, έγκριση ή τίτλος ιδιοκτησίας.
   *
   * 🔴 **Γιατί χωριστό είδος και όχι `field` του `survey-record`.** Το βαθμωτό γράφεται σε
   * πεδίο με **όνομα**, οπότε η επανάληψη της έγκρισης είναι αβλαβής. Μια γραμμή δεν έχει
   * όνομα: χωρίς ένα, το δεύτερο κλικ στο **ίδιο** ΦΕΚ προσθέτει **δεύτερη** πράξη. Άρα ο
   * στόχος κουβαλά το `rowId` — ταυτότητα παραγόμενη από το ίδιο το σχέδιο — και ο writer
   * κάνει upsert. Το «ίδια δήλωση ⇒ ίδια γραμμή» είναι **μέρος του στόχου**, όχι σύμβαση
   * του writer (N.7.2 ερώτημα 3).
   *
   * 🔑 Και γι' αυτό δεν υπάρχει `index`: η θέση αλλάζει όταν ο μηχανικός σβήσει μια γραμμή
   * στην καρτέλα, η ταυτότητα όχι.
   */
  | {
      readonly kind: 'survey-record-row';
      readonly projectId: string;
      readonly recordId: string;
      readonly list: DocumentBodyListKey;
      /** Ντετερμινιστική ταυτότητα της δήλωσης — δες `surveyRowKey`. */
      readonly rowId: string;
      /**
       * Τα μέρη, **ήδη αναλυμένα**.
       *
       * Ίδιο δόγμα με το `survey-record`: η ανάλυση έγινε **μία** φορά, στον Λ2, και το
       * αποτέλεσμά της φάνηκε στην οθόνη **πριν** το κλικ. Δεύτερη ανάλυση τη στιγμή της
       * εγγραφής θα σήμαινε ότι την ημέρα που αλλάξει ο κανόνας, το σύστημα γράφει **άλλο**
       * από αυτό που ενέκρινε ο μηχανικός.
       */
      readonly parts: readonly SurveyRowPartValue[];
    }
  | {
      readonly kind: 'drawing-meta';
      readonly levelId: string;
      /**
       * 🔴 **Προστέθηκε στη Φ3 και ΔΕΝ είναι διακοσμητικό.**
       *
       * Το `TitleBlockBinding.projectId` είναι **υποχρεωτικό** επειδή το διαβάζει ο καταρράκτης
       * διαγραφής έργου (`config/deletion-registry.ts:441`) — το `target` είναι ένωση και το
       * Firestore **δεν ερωτά μέσα σε ένωση**. Όσο το `drawing-meta` δεν είχε έργο, η έγκρισή
       * του ήταν **δομικά αδύνατη** (`title-block-apply/index.ts:44` → `NOT_YET_WRITABLE`), κι
       * αυτό ήταν σωστό: provenance που δεν πεθαίνει μαζί με το έργο του είναι **ορφανή
       * απόδειξη, χειρότερη από καμία**.
       *
       * ⇒ Η Φ3 **δεν χαλαρώνει** τον κανόνα· του δίνει το έργο που η παλέτα ήδη κρατά. Σχέδιο
       * χωρίς έργο ⇒ `no-project` (ορατό, με ενέργεια), **ποτέ** εγγραφή χωρίς προέλευση.
       */
      readonly projectId: string;
      readonly field: BindableDrawingField;
      readonly value: string;
    };

export type BindingTargetKind = BindingTarget['kind'];

