import type { GeoPoint } from './coordinates';

/**
 * **Πού είναι και πόσο μεγάλη είναι μια διοικητική οντότητα** — παράγωγο, όχι πηγή.
 *
 * ⚠️ **Τα δύο μεγέθη είναι σε ΧΙΛΙΟΜΕΤΡΑ**, ίδια μονάδα με το `GeoCircle.radiusKm`, ώστε
 * να μη χρειάζεται καμία μετατροπή στο σημείο της κρίσης — εκεί που θα γινόταν το λάθος.
 */
export interface AdminFootprint {
  /**
   * Το **αντιπροσωπευτικό σημείο** της οντότητας.
   *
   * ⚠️ **Δεν είναι το «κέντρο βάρους» με την αφελή έννοια**: για δήμο με νησιά ή
   * κοίλο σχήμα, το κεντροειδές μπορεί να πέφτει **έξω** από το πολύγωνο. Το μόνο που
   * υπόσχεται αυτό το πεδίο είναι ότι είναι το **κοινό κέντρο** των δύο κύκλων — η
   * ορθότητα των συμπερασμάτων στηρίζεται **μόνο** στους δύο εγκλεισμούς, ποτέ στο ότι
   * το σημείο «είναι μέσα».
   */
  readonly center: GeoPoint;

  /**
   * **Περιγεγραμμένη ακτίνα** — το πολύγωνο **χωράει ολόκληρο** μέσα σε αυτόν τον κύκλο.
   * Πάντα `>= innerKm`.
   */
  readonly outerKm: number;

  /**
   * **Εγγεγραμμένη ακτίνα** — αυτός ο κύκλος **χωράει ολόκληρος** μέσα στο πολύγωνο.
   *
   * ⚠️ **Μπορεί να είναι `0`**, και είναι νόμιμο: για οντότητα-αρχιπέλαγος ή για πολύ
   * λεπτό σχήμα δεν υπάρχει κύκλος γύρω από το κέντρο που να χωράει μέσα. Τότε το
   * σκέλος «αποδεδειγμένο `intersects`» απλώς **δεν ενεργοποιείται** και η απάντηση
   * πέφτει, σωστά, στο `unknown`.
   */
  readonly innerKm: number;
}

/**
 * **Η γεωμετρία μπαίνει με ΕΝΕΣΗ** — ίδιο ιδίωμα με το `LineageResolver`.
 *
 * 🔑 Ο κριτής *(`lib/agency/coverage-match.ts`)* είναι **καθαρό φύλλο**: δεν επιτρέπεται
 * να εισάγει hook ούτε να ξέρει αν τα δεδομένα ήρθαν από αρχείο, από cache ή από test.
 *
 * ⚠️ **`null` = «δεν ξέρω», ΠΟΤΕ «δεν υπάρχει».** Συμβαίνει όταν το παράγωγο αρχείο
 * δεν έχει φορτώσει, δεν έχει παραχθεί ακόμη, ή η οντότητα λείπει από αυτό. Και στις
 * τρεις περιπτώσεις η **σωστή** συμπεριφορά είναι η ίδια: ο κριτής απαντά `unknown` και
 * **δεν κόβει κανέναν**.
 */
export type FootprintResolver = (adminId: string) => AdminFootprint | null;

/**
 * **Ο αναγνώστης που δεν ξέρει τίποτα** — γραμμένος **μία** φορά.
 *
 * 🔑 Υπάρχει ώστε κανένας καλών να μη γράψει `() => null` μόνος του: είναι το ίδιο
 * μοτίβο με το `EMPTY_SNAPSHOT` του `useAdministrativeHierarchy` — **η άγνοια είναι
 * κατάσταση με όνομα**, όχι σιωπηλή παράλειψη. Και όταν το παράγωγο αρχείο υπάρξει, το
 * `grep` βρίσκει σε **ένα** σημείο ποιοι δεν το ζητούν ακόμη.
 */
export const NO_FOOTPRINTS: FootprintResolver = () => null;
