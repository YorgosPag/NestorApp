/**
 * **Δείχνει σε έναν τόπο του επιπέδου Α.**
 *
 * 🔴 **Είναι ο λόγος που το επίπεδο Α υπάρχει** (§14.5): *«μία ταυτότητα ανά φυσικό
 * κτίριο … το ταίριασμα γίνεται δυνατό **επειδή** το Α είναι ένα»*. Η ζήτηση δείχνει
 * εδώ, η προσφορά δείχνει εδώ, και **γι' αυτό συναντιούνται**.
 *
 * ⚠️ **Ένας τύπος, επειδή το σχήμα ήταν ήδη γραμμένο ΤΡΕΙΣ φορές** (μετρημένο
 * 2026-08-11): ως `ListingPlaceLink` στο `demand-match-vocabulary.ts`, **inline** μέσα
 * στον κλάδο `place` του `DemandPlace`, και ξανά στην απάντηση του γραφέα. Τρία
 * ονόματα για ένα ζεύγος κλειδιών είναι το σχήμα του ADR-749 — και εδώ θα ήταν
 * ιδιαίτερα επικίνδυνο, γιατί η **σύγκριση** αυτών των δύο πεδίων **είναι** η μηχανή
 * ταιριάσματος.
 *
 * ⚠️ Το `buildingId` είναι προαιρετικό γιατί **η γη αρκεί**: *«ζητώ οικόπεδο για
 * αντιπαροχή σε αυτό το τετράγωνο»* δεν έχει κτίριο και **δεν πρέπει** να αναγκαστεί
 * να επινοήσει ένα.
 */
export interface PlaceRef {
  /** FK → {@link PublicLand} (`land_*`). **Υποχρεωτικό** — η γη κρατά τη θέση (Α1). */
  readonly landId: string;
  /** FK → {@link PublicBuilding} (`pbld_*`), όταν το αίτημα αφορά το κτίριο. */
  readonly buildingId: string | null;
}

// ============================================================================
// ΓΗ — η ρίζα· αυτό κρατά τη θέση (Α1)
// ============================================================================

/**
 * **ΓΗ** — ένα κομμάτι γης, άδειο ή κτισμένο. **Το μόνο πράγμα που κρατά θέση.**
 *
 * Α1, επικυρωμένη 2026-08-09: *«το τοπογραφικό είναι το Ευαγγέλιο»* ⇒ αυτό που κρατά
 * τη θέση είναι η **γη**, και το τοπογραφικό είναι το πιστοποιητικό γέννησής της.
 *
 * ⚠️ **Δεν έχει `companyId` και δεν πρόκειται να αποκτήσει.** Είναι κοινή σε όλους,
 * υπάρχει **πριν** τη διεκδικήσει οποιοσδήποτε, και γράφεται **μόνο από τον
 * διακομιστή** (§14.4). Ο πελάτης τη διαβάζει· ποτέ δεν τη γράφει.
 */
export interface PublicLand {
  /** Enterprise id, `land_*` (N.6). **Ποτέ** OSM id, **ποτέ** `addDoc`. */
  readonly id: string;
  /** Πού είναι — ή ρητά «δεν ξέρουμε». */
  readonly position: PlacePosition;
  /**
   * Διεύθυνση όπως τη λύσαμε. Επιτρέπεται από το ODbL («names, addresses»).
   * `null` = δεν έχει λυθεί· **όχι** κενή συμβολοσειρά (που διαβάζεται ως «λύθηκε
   * και είναι κενή»).
   */
  readonly displayAddress: string | null;
  /** Εμβαδόν σε m², όταν το ξέρουμε από πηγή. */
  readonly areaSqm: Attested<number> | null;
  /** ISO timestamp δημιουργίας — από τον διακομιστή. */
  readonly createdAt: string;
  /** ISO timestamp τελευταίας αλλαγής **οποιουδήποτε** πεδίου. */
  readonly updatedAt: string;
}

// ============================================================================
// ΚΤΙΡΙΟ — δημόσιο, κανενός (Α11)
// ============================================================================

/**
 * **ΚΤΙΡΙΟ του κόσμου** — δημόσια οντότητα χωρίς ιδιοκτήτη (Α11).
 *
 * 🔴 **Δεν είναι το `Building` του `types/building/contracts.ts`.** Εκείνο έχει
 * `projectId` + `companyId` + πρόοδο + αξία: είναι **εμπορικό**, επίπεδο Β, και ζει
 * μέσα σε ένα έργο ενός πελάτη. Αυτό εδώ είναι το **φυσικό γεγονός** — το ίδιο
 * κτίριο που βλέπουν όλοι, ακόμη κι αν κανείς δεν το πουλά.
 *
 * Η σύνδεση των δύο (ο πελάτης λέει «το `Building` μου **είναι** αυτό») είναι πράξη
 * του **επιπέδου Β** και ζει εκεί — ποτέ εδώ. Καμία διαδρομή από το Α προς το Β
 * (§14.4 κανόνας 4): αυτή η οντότητα **δεν κουβαλά ποτέ** εμπορικό δεδομένο.
 *
 * 🔑 **Το κτίριο δεν κρατά δική του θέση — την κληρονομεί από τη γη.** Αυτό είναι
 * ολόκληρη η Α1 σε μία γραμμή: αν κρατούσε δική του, θα υπήρχαν **δύο** αλήθειες για
 * το πού είναι, και η αντιπαροχή — όπου η γη αλλάζει χέρια αλλά το κτίριο δεν υπάρχει
 * ακόμη — θα ήταν δομικά ανέκφραστη.
 */
export interface PublicBuilding {
  /** Enterprise id, `pbld_*` (N.6). **Ποτέ** OSM id. */
  readonly id: string;
  /** FK → {@link PublicLand}. **Η θέση διαβάζεται από εκεί.** */
  readonly landId: string;
  /**
   * Το περίγραμμα του **κτιρίου** μέσα στη γη, όταν το ξέρουμε από επιτρεπτή πηγή.
   *
   * ⚠️ Ξεχωριστό από το περίγραμμα της **γης**: ένα οικόπεδο δεν είναι το κτίριο του.
   * Δηλώνεται ως {@link PlacePosition} ώστε να **ξαναχρησιμοποιεί το ίδιο νομικό
   * όριο** — ένα `outline` με προέλευση `osm` παραμένει αδύνατο και εδώ.
   */
  readonly footprint: PlacePosition;
  /** Αριθμός ορόφων πάνω από το έδαφος. */
  readonly floorsAboveGround: Attested<number> | null;
  /** Έτος κατασκευής. */
  readonly constructionYear: Attested<number> | null;
  /** Χρήση, ως κωδικός λεξιλογίου — **ποτέ** ελεύθερο κείμενο προς εμφάνιση (N.11). */
  readonly useCode: Attested<string> | null;
  readonly createdAt: string;
  readonly updatedAt: string;
}
