/**
 * @fileoverview Το ΚΟΙΝΟ επίπεδο Α — ΓΗ και ΚΤΙΡΙΟ, δημόσια, χωρίς ιδιοκτήτη.
 * @related ADR-777 · SPEC-777A §13 (Α11) · §14 (Α12) · §21 (Α1, επικυρώθηκε 2026-08-09)
 * @module types/geo/public-place
 *
 * ────────────────────────────────────────────────────────────────────────────
 * Η ΑΛΥΣΙΔΑ (Α1 — επικυρωμένη πρόταση «(γ)», §21.7)
 * ────────────────────────────────────────────────────────────────────────────
 *
 *   ΓΗ (κρατά τη ΘΕΣΗ· το τοπογραφικό είναι το χαρτί της)
 *    └── ΚΤΙΡΙΟ   = γη που έχει κτιστεί  (κληρονομεί θέση, προσθέτει ορόφους)
 *         └── ΑΚΙΝΗΤΟ = μονάδα μέσα στο κτίριο (κληρονομεί θέση, προσθέτει ΟΡΟΦΟ)
 *
 * Το **ΑΚΙΝΗΤΟ δεν ζει εδώ**: είναι εμπορικό, ανά κάτοχο ⇒ **επίπεδο Β** (§14.2).
 * Εδώ ζουν μόνο τα δύο πράγματα που θα ήταν αληθή **ακόμη κι αν έσβηναν όλοι οι
 * λογαριασμοί** (§14.1) — η γη και το κτίριο πάνω της.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΡΙΑ ΠΡΑΓΜΑΤΑ ΠΟΥ Ο ΤΥΠΟΣ ΚΑΝΕΙ **ΑΔΥΝΑΤΑ**, ΑΝΤΙ ΝΑ ΤΑ ΑΠΑΓΟΡΕΥΕΙ ΜΕ ΣΧΟΛΙΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * 1. **Δεν υπάρχει `companyId`.** Δεν είναι «ξεχασμένο» — είναι η Α11. Ένα έγγραφο
 *    που *τυχαίνει* να μην έχει `companyId` σπάει τις CHECK 3.10/3.35 ή, χειρότερα,
 *    περνά ως παράβλεψη (§13.1). Η κατηγορία δηλώνεται **ρητά** στο
 *    `services/firestore/tenant-config.ts`.
 *
 * 2. **Η ταυτότητα δεν είναι ποτέ OSM id** (§13.2). Το `id` είναι δικό μας
 *    (`enterprise-id.service`, N.6)· το OSM ζει σε **αναφορά** που μπορεί να πεθάνει
 *    χωρίς να πάρει μαζί της τη ζήτηση κανενός.
 *
 * 3. **Το περίγραμμα του OSM ΔΕΝ αποθηκεύεται** (§13.4 — ODbL). Δεν είναι σύσταση:
 *    βλ. {@link PlacePosition}, όπου ο κλάδος `osm` δηλώνει `outline?: never`.
 *    Ένα `outline` δίπλα σε `provenance: 'osm'` **δεν μεταγλωττίζεται**.
 */

import type { LocationProvenance, Attested } from '@/lib/location/location-provenance';
import type { GeocodingAccuracy } from '@/lib/geocoding/geocoding-types';
import type { GeoPoint, GeoOutline } from './coordinates';

// ============================================================================
// ΑΝΑΦΟΡΑ OSM — δείχνει, ποτέ δεν ΕΙΝΑΙ
// ============================================================================

/** Τύπος στοιχείου OpenStreetMap. Κλειστό σύνολο — το OSM δεν έχει άλλους. */
export type OsmElementType = 'node' | 'way' | 'relation';

/**
 * Αναφορά προς ένα στοιχείο OSM.
 *
 * 🔴 **Είναι δείκτης, όχι ταυτότητα** (§13.2). Τα OSM id **αλλάζουν**: εθελοντές
 * διαγράφουν, ξανασχεδιάζουν και συγχωνεύουν κτίρια. Αν οι ζητήσεις κρέμονταν εδώ,
 * μια επεξεργασία τρίτου θα **εξαφάνιζε σιωπηλά** τη ζήτηση κάποιου.
 *
 * ⚠️ **Κάθε πεδίο εδώ μπορεί να πάψει να ισχύει χωρίς να το μάθουμε.** Γι' αυτό η
 * επανεύρεση γίνεται από τη **θέση** ({@link PublicLand.position}), που δεν εξαρτάται
 * από κανέναν τρίτο — αυτή είναι η «γεωμετρική άγκυρα» του §13.2.
 */
export interface OsmReference {
  readonly elementType: OsmElementType;
  /** Το αριθμητικό id ως **συμβολοσειρά** — δεν κάνουμε ποτέ αριθμητική πάνω του. */
  readonly elementId: string;
  /** ISO timestamp της τελευταίας φοράς που το είδαμε ζωντανό. */
  readonly seenAt: string;
}

// ============================================================================
// ΘΕΣΗ — και το νομικό όριο ως ΤΥΠΟΣ
// ============================================================================

/** Κοινά πεδία κάθε γνωστής θέσης. */
interface KnownPositionBase {
  /** Το αντιπροσωπευτικό σημείο. **Πάντα** υπάρχει όταν η θέση είναι γνωστή. */
  readonly point: GeoPoint;
  /** ISO timestamp — πότε καθορίστηκε αυτή η θέση από αυτή την πηγή. */
  readonly locatedAt: string;
}

/**
 * Πού είναι αυτό το πράγμα — **διακριτή ένωση πάνω στην προέλευση**.
 *
 * 🔑 **Εδώ ζει το νομικό όριο του §13.4.** Το OSMF Geocoding Guideline επιτρέπει
 * αποθήκευση «**names, addresses, and/or latitude/longitude**»· το **περίγραμμα δεν
 * αναφέρεται** σε εκείνη τη λίστα. Άρα η γεωμετρία OSM δείχνεται **ζωντανά** και δεν
 * αποθηκεύεται ποτέ.
 *
 * Αυτό θα μπορούσε να είναι σχόλιο. **Δεν είναι:** ο κλάδος `osm` δηλώνει
 * `outline?: never`, οπότε η παραβίαση είναι **σφάλμα μεταγλώττισης** στο σημείο που
 * γράφεται — όχι εύρημα σε νομικό έλεγχο δύο χρόνια αργότερα. Το ίδιο ισχύει για
 * `geocoded`/`manual`, που **δομικά** δεν παράγουν σχήμα (ένα σημείο δεν έχει
 * περίγραμμα· ένα `outline` εκεί θα ήταν ψέμα για το τι ξέρουμε).
 *
 * ⚠️ **Η ρητή κατάσταση `unknown` δεν είναι διακοσμητική** (Α5): «δεν ξέρουμε πού
 * είναι» πρέπει να είναι **λέξιμο**, αλλιώς εκφράζεται ως `lat: 0, lng: 0` — σημείο
 * στον Ατλαντικό, που κάθε χάρτης θα ζωγραφίσει **με απόλυτη σιγουριά**.
 */
export type PlacePosition =
  | { readonly kind: 'unknown' }
  | (KnownPositionBase & {
      readonly kind: 'known';
      readonly provenance: 'osm';
      /** ⛔ **ODbL** — το περίγραμμα OSM δεν αποθηκεύεται. Ζωντανή άντληση μόνο. */
      readonly outline?: never;
      readonly osmRef: OsmReference;
    })
  | (KnownPositionBase & {
      readonly kind: 'known';
      readonly provenance: 'geocoded';
      /** ⛔ Σημείο χωρίς σχήμα — δεν υπάρχει περίγραμμα να αποθηκευτεί. */
      readonly outline?: never;
      /**
       * 🔴 **ΥΠΟΧΡΕΩΤΙΚΟ — και αυτός ο τύπος υπάρχει για να το κάνει υποχρεωτικό.**
       *
       * Ο geocoder **πάντα** επιστρέφει σημείο· η `determineAccuracy()`
       * (`lib/geocoding/geocoding-engine-helpers.ts:74`) γυρίζει `'center'` ως
       * **fallback**, δηλαδή σκέτο «Θεσσαλονίκη» παράγει σημείο **εξίσου βέβαιο στη
       * μορφή** με το «Εγνατίας 147». Και μετρήθηκε (ADR-777 Α5) ότι ο `AddressMap`
       * **δεν διαβάζει καθόλου** το `accuracy` — grep **0** — άρα οι δύο ζωγραφίζονται
       * **οπτικά ταυτόσημες**: η CHECK 3.41 (WCAG 1.4.1) σε πινέζες χάρτη.
       *
       * Ένα γεωκωδικοποιημένο σημείο **χωρίς** την ακρίβειά του είναι αριθμός χωρίς
       * προέλευση — ακριβώς ό,τι απαγορεύει ο κανόνας 18. Εδώ δεν είναι σύσταση: αν
       * λείπει, **δεν μεταγλωττίζεται**.
       */
      readonly accuracy: GeocodingAccuracy;
    })
  | (KnownPositionBase & {
      readonly kind: 'known';
      /**
       * Πινέζα ανθρώπου. **Δεν έχει `accuracy` — και η απουσία είναι σχεδίαση:** η
       * ακρίβεια είναι ιδιότητα ενός **συμπεράσματος** μηχανής από κείμενο. Όταν
       * άνθρωπος δείχνει σημείο, το σημείο **είναι** η απάντηση· ένα «κατά προσέγγιση
       * χειροκίνητο» θα ήταν δεύτερη κλίμακα για το ίδιο πράγμα.
       */
      readonly provenance: 'manual';
      /** ⛔ Σημείο χωρίς σχήμα — δεν υπάρχει περίγραμμα να αποθηκευτεί. */
      readonly outline?: never;
    })
  | (KnownPositionBase & {
      readonly kind: 'known';
      /** Δικά μας δεδομένα ή δεδομένα που έδωσε ο χρήστης ⇒ **επιτρέπεται** σχήμα. */
      readonly provenance: 'drawn' | 'survey' | 'bim';
      /** Το περίγραμμα, όταν η πηγή το παρήγαγε. */
      readonly outline?: GeoOutline;
    });

/**
 * Η προέλευση μιας θέσης, ή `null` όταν είναι άγνωστη.
 *
 * Στενό βοήθημα ώστε οι καταναλωτές να μη γράφουν παντού το ίδιο `kind` narrowing —
 * και, κυρίως, ώστε να τροφοδοτούν σωστά το `outranksForLocation` / `locationKnowledgeStep`.
 */
export function positionProvenance(position: PlacePosition): LocationProvenance | null {
  return position.kind === 'unknown' ? null : position.provenance;
}

