/**
 * @fileoverview **ΤΟ ΕΝΑ ΛΕΞΙΛΟΓΙΟ ΤΟΥ «ΚΟΙΤΑ ΕΔΩ»** — ADR-846 Φάση 4.
 * @related components/geo/use-camera-frame · lib/geo/geocoding-focus · lib/agency/coverage-camera
 * @module types/geo/camera-frame
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ ΞΕΧΩΡΙΣΤΑ ΑΠΟ ΤΟ `FocusFrame`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Δύο **εντελώς διαφορετικές** ερωτήσεις ζητούν την **ίδια ακριβώς** κίνηση κάμερας:
 *
 * | ποιος ρωτά | τι εννοεί | κουβαλά αβεβαιότητα; |
 * |---|---|---|
 * | ο **γεωκωδικοποιητής** *(`PlaceFocus`)* | «βρήκα αυτό, με **τόση** σιγουριά» | **ναι** — και τη **ζωγραφίζει** |
 * | η **δηλωμένη εμβέλεια** *(ADR-846)* | «ο άνθρωπος **είπε** ότι δουλεύει εδώ» | **όχι, και δεν επιτρέπεται** |
 *
 * ⛔ **Γι' αυτό η εμβέλεια ΔΕΝ δανείζεται το `PlaceFocus`.** Το `focusPresentation`
 * παράγει `uncertaintyMetres` και το `PlaceMap` το **ζωγραφίζει ως φωτοστέφανο**: μια
 * δήλωση ανθρώπου θα αποκτούσε οπτικά «περιθώριο σφάλματος» που **δεν υπάρχει**. Δεν
 * είναι θέμα καθαρότητας τύπων — είναι **ψέμα στην οθόνη**.
 *
 * 🔑 **Και γι' αυτό δεν γράφτηκε δεύτερη μηχανή κίνησης** *(N.18)*: η πτήση έχει
 * **τέσσερις** αποφάσεις πληρωμένες με περιστατικό *(διάρκεια, περιθώριο, ταβάνι ζουμ,
 * ταυτότητα κατά τιμή)*. Δύο αντίγραφά τους θα απέκλιναν σιωπηλά — ο ένας χάρτης θα
 * πετούσε και ο άλλος θα πηδούσε. **Μία κίνηση, δύο μεταφραστές από πάνω.**
 */

import type { GeoBoundingBox, GeoPoint } from './coordinates';

/**
 * **Πού πρέπει να κοιτάζει η κάμερα** — αυτοτελές, χωρίς καμία έννοια βεβαιότητας.
 *
 * ⚠️ **Ο κλάδος `point` κουβαλά ΚΑΙ το σημείο**, σε αντίθεση με το `FocusFrame` που
 * κρατούσε μόνο το ζουμ και έπαιρνε το κέντρο από αλλού. Χωρίς αυτό, ο μεταφραστής θα
 * ήταν υποχρεωμένος να στέλνει **δύο** πράγματα που πρέπει να ταιριάζουν — και ο
 * καλών θα μπορούσε να ζητήσει ζουμ ενός σχήματος πάνω στο κέντρο **άλλου**.
 */
export type CameraFrame =
  | { readonly kind: 'extent'; readonly extent: GeoBoundingBox }
  | { readonly kind: 'point'; readonly point: GeoPoint; readonly zoom: number };

/**
 * **Η ταυτότητα ενός καρέ ΚΑΤΑ ΤΙΜΗ** — το κλειδί που κρίνει «άξιζε νέα πτήση;».
 *
 * 🔴 **Ήταν το ελάττωμα #3 του `use-focus-camera`, και επιστρέφει σε κάθε καταναλωτή**:
 * το καρέ χτίζεται μέσα σε render, άρα είναι **νέο αντικείμενο κάθε φορά**. Σε λίστα
 * εξαρτήσεων `useEffect` θα ξανάτρεχε την πτήση σε **κάθε πάτημα πλήκτρου** — ο χάρτης
 * σε μόνιμη κίνηση. Γράφεται **εδώ, μία φορά**, ώστε κανένας καταναλωτής να μη χρειάζεται
 * να το θυμάται.
 */
export function cameraFrameSignature(frame: CameraFrame | null): string | null {
  if (frame === null) return null;
  if (frame.kind === 'extent') {
    const { south, west, north, east } = frame.extent;
    return `extent:${south},${west},${north},${east}`;
  }
  return `point:${frame.point.lat},${frame.point.lng},${frame.zoom}`;
}
