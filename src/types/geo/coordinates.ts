/**
 * Σημείο σε WGS84 — το σύστημα που μιλούν ο χάρτης, το OSM και ο geocoder.
 *
 * ⚠️ **Δεν είναι ΕΓΣΑ87.** Η μετατροπή από το ελληνικό προβολικό σύστημα ζει —
 * και μένει — στο `subapps/dxf-viewer/systems/geo-referencing/egsa87-projection.ts`.
 * Ένα σημείο που φτάνει εδώ έχει **ήδη** περάσει από εκεί.
 */
export interface GeoPoint {
  /** Γεωγραφικό πλάτος, μοίρες. */
  readonly lat: number;
  /** Γεωγραφικό μήκος, μοίρες. */
  readonly lng: number;
}

/**
 * Κλειστό περίγραμμα — δακτύλιος κορυφών.
 *
 * 🔑 **Δεν επαναλαμβάνεται η πρώτη κορυφή στο τέλος.** Το κλείσιμο είναι ιδιότητα
 * του **τύπου**, όχι σύμβαση δεδομένων: μια σύμβαση που ζητά από κάθε γραφέα να
 * θυμηθεί να ξαναγράψει την πρώτη κορυφή είναι σύμβαση που **κάποιος θα ξεχάσει**,
 * και το σφάλμα εμφανίζεται ως τρύπα στο σχήμα πολύ αργότερα.
 *
 * ⚠️ Σκόπιμα **όχι GeoJSON**: το GeoJSON `Polygon` είναι `number[][][]` — τρία
 * επίπεδα ανώνυμων αριθμών όπου το `[lng, lat]` έχει **αντίστροφη** σειρά από την
 * ανθρώπινη ανάγνωση, και είναι ακριβώς ο τύπος όπου ένα μπερδεμένο ζεύγος
 * τοποθετεί το κτίριο σε άλλη ήπειρο χωρίς να το πει κανείς. Η μετατροπή προς
 * GeoJSON γίνεται στο σύνορο εξόδου, όπου τη ζητά ο χάρτης.
 */
export type GeoOutline = readonly GeoPoint[];

/**
 * **Ανοιχτή** πολυγραμμή — άξονας, όχι σχήμα. Ο δρόμος, όχι το οικόπεδο.
 *
 * 🔑 **Το «τουλάχιστον δύο κορυφές» είναι ΤΥΠΟΣ, όχι έλεγχος.** Μία κορυφή δεν ορίζει
 * **διεύθυνση**, και χωρίς διεύθυνση οι λέξεις «αριστερά» και «δεξιά» **δεν έχουν
 * νόημα** — δηλαδή ολόκληρη η έννοια του μετώπου καταρρέει. Ένας τύπος
 * `readonly GeoPoint[]` θα το επέτρεπε και θα ζητούσε από **κάθε** καταναλωτή να
 * θυμηθεί τον έλεγχο· η μεταβλητή πλειάδα το κάνει **ασύντακτο**. Ίδιο ιδίωμα με το
 * {@link GeoOutline}, όπου το κλείσιμο είναι ιδιότητα του τύπου.
 *
 * ⚠️ **Διαφέρει από το {@link GeoOutline} στη ΣΗΜΑΣΙΑ, όχι μόνο στο σχήμα**: ο
 * δακτύλιος **περικλείει** (η ερώτηση είναι «μέσα;»), η πολυγραμμή **χωρίζει** (η
 * ερώτηση είναι «ποια πλευρά;»). Δύο διαφορετικά ερωτήματα ⇒ δύο τύποι, ώστε να μην
 * περάσει ποτέ άξονας εκεί που περιμένουν σχήμα.
 *
 * ⛔ **ODbL — ΠΟΤΕ αντιγραμμένη από OSM** (SPEC-777A §13.4). Το επιτρεπτό από το OSMF
 * Geocoding Guideline είναι *«names, addresses, and/or latitude/longitude»* — η
 * **γεωμετρία δεν αναφέρεται**. Άξονας δρόμου αντλημένος από OSM δείχνεται **ζωντανά**
 * και δεν αποθηκεύεται· άξονας που **έδειξε άνθρωπος** είναι δικό μας δεδομένο και
 * αποθηκεύεται ελεύθερα (ίδια γραμμή με το `provenance: 'drawn'` του `PlacePosition`).
 */
export type GeoPolyline = readonly [GeoPoint, GeoPoint, ...GeoPoint[]];

/**
 * **Κύκλος αναζήτησης** — σημείο και ακτίνα. Η απάντηση στο *«πού, και πόσο γύρω;»*.
 *
 * 🔑 **Γιατί ζει ΕΔΩ και όχι στα φίλτρα** *(ADR-777 §8.53, 2026-09-06)*: ο όρος μιλιόταν
 * σε **πέντε** σημεία και **ένα μόνο** τον είχε ονομάσει — το `ListingGeoFilter` του
 * `lib/listings/listing-filters.ts`. Τα υπόλοιπα τέσσερα τον έγραφαν ανώνυμα, και **δύο
 * από αυτά τρύπησαν μέσα στον τύπο του φίλτρου** για να τον δανειστούν:
 *
 * ```
 * lib/demand/demand-listing-filters.ts:164   type ProjectedGeo = ListingFilters['near']
 * lib/demand/demand-similarity.ts:96         areasIntersect(a: ListingFilters['near'], …)
 * ```
 *
 * Δηλαδή ο τομέας της **ζήτησης** εξαρτιόταν δομικά από τον τομέα των **αγγελιών** για
 * μια καθαρά **γεωμετρική** έννοια — λάθος κατεύθυνση εξάρτησης, και το κλασικό σύμπτωμα
 * ενός SSoT που λείπει: όταν δεν υπάρχει όνομα, ο κόσμος **δείχνει** αντί να ονομάσει.
 *
 * 🏆 **Shared Kernel** *(Evans, DDD)* — *«κώδικας από τον οποίο μπορεί να εξαρτηθεί
 * οποιοδήποτε module, αρκεί η εξάρτηση να μην αυξάνει τη σύζευξη»*. Αυτό το αρχείο έχει
 * **μηδέν imports** — είναι καθαρό φύλλο, άρα η προϋπόθεση ισχύει δομικά, όχι κατά
 * σύμβαση. Το `lib/geo/*` **δεν** ήταν η σωστή θέση: εκεί ζει η **συμπεριφορά**
 * (συναρτήσεις), εδώ το **λεξιλόγιο** — μαζί με τα {@link GeoPoint}, {@link GeoOutline},
 * {@link GeoPolyline}, {@link GeoBoundingBox}.
 *
 * ⚠️ **Η ακτίνα είναι σε ΧΙΛΙΟΜΕΤΡΑ, και είναι πάντα > 0.** Το `0` **δεν** σημαίνει
 * «παντού» — σημαίνει «πουθενά», και φιλτράρει **τα πάντα**. Ο τύπος δεν μπορεί να το
 * επιβάλει, γι' αυτό το επιβάλλουν **δύο** ανεξάρτητοι φύλακες στα σύνορα εισόδου:
 * ο `readGeoFilter` απορρίπτει `radiusKm <= 0` *(επιστρέφει `null` = «όπου να 'ναι»)*,
 * και ο `geoOutlineBoundingCircle` κρατά κατώτατο όριο `MIN_BOUNDING_RADIUS_KM` ώστε
 * εκφυλισμένος δακτύλιος να μη γεννήσει ποτέ μηδενικό κύκλο.
 *
 * ⚠️ **Αντικείμενο, ΠΟΤΕ δύο επίπεδα πεδία** — ίδιο ιδίωμα με το `ListingStayWindow`:
 * ένα κέντρο χωρίς ακτίνα δεν είναι «μισή ερώτηση», είναι **μη ερώτηση**. Δύο
 * ανεξάρτητα προαιρετικά πεδία θα επέτρεπαν στον τύπο να εκφράσει τη μισή, και κάθε
 * καταναλωτής θα έπρεπε να θυμάται τον έλεγχο — δηλαδή κάποιος θα τον ξεχνούσε.
 */
export interface GeoCircle {
  /** Το κέντρο της αναζήτησης. */
  readonly center: GeoPoint;
  /** Ακτίνα σε **χιλιόμετρα**. Πάντα > 0 — το 0 δεν είναι «παντού», είναι «πουθενά». */
  readonly radiusKm: number;
}

/**
 * Ορθογώνιο περίβλημα — για ερωτήματα «τι υπάρχει σε αυτή την περιοχή».
 *
 * Η μοναδική δομή που επιτρέπεται να ταξιδέψει προς το Overpass ως **αίτημα**
 * (§13.5: ταυτότητα κατ' απαίτηση, ποτέ μαζική άντληση).
 */
export interface GeoBoundingBox {
  readonly south: number;
  readonly west: number;
  readonly north: number;
  readonly east: number;
}

/**
 * **ΜΙΑ ΠΕΡΙΟΧΗ ΣΤΟΝ ΧΑΡΤΗ — ΚΥΚΛΟΣ Ή ΟΡΘΟΓΩΝΙΟ, ΚΛΕΙΣΤΗ ΕΝΩΣΗ** *(ADR-777 §8.63)*.
 *
 * 🔑 **Γιατί ΕΝΑ όνομα και όχι δύο πεδία δίπλα-δίπλα.** Το έργο έχει **δύο** πηγές
 * περιοχής και **μία** ερώτηση: ο επισκέπτης γράφει *«Κολωνάκι»* και ο geocoder
 * απαντά **κύκλο** ({@link GeoCircle})· ο επισκέπτης **σέρνει τον χάρτη** και η
 * οθόνη απαντά **ορθογώνιο** ({@link GeoBoundingBox}). Και τα δύο απαντούν το ίδιο:
 * *«πού ψάχνω;»*.
 *
 * ⚠️ **Δύο ξεχωριστά πεδία θα ήταν ΔΕΥΤΕΡΟ γεωγραφικό φίλτρο** — δηλαδή δύο
 * απαντήσεις στο ίδιο ερώτημα, που μια μέρα διαφωνούν *(ADR-749: δύο μηχανές, τρεις
 * αριθμοί)*. Με **ένα** πεδίο κλειστής ένωσης, το σύρσιμο του χάρτη
 * **αντικαθιστά** την προηγούμενη περιοχή αντί να την ανταγωνίζεται, και κάθε
 * καταναλωτής **αναγκάζεται** από τον μεταγλωττιστή να απαντήσει και για τα δύο
 * σχήματα.
 *
 * ⚠️ **Ένα σχήμα δεν αρκεί για να απαντηθεί «είναι μέσα;»** — χρειάζεται και το
 * **δεύτερο** σχήμα, εκείνο της ίδιας της αγγελίας. Η σχέση των δύο ζει στο
 * `lib/geo/geo-area.ts` και έχει **τρεις** τιμές, όχι δύο.
 *
 * 🔑 **ΤΡΙΤΟ ΣΚΕΛΟΣ: ΤΟ ΟΡΙΟ ΜΙΑΣ ΔΙΟΙΚΗΤΙΚΗΣ ΠΕΡΙΟΧΗΣ** *(ADR-883)* — ο επισκέπτης γράφει
 * *«Κορδελιού-Ευόσμου»* και ο χάρτης δείχνει **τον δήμο**, όχι έναν κύκλο γύρω από το
 * κέντρο του. Το σύρσιμο του χάρτη ή η «Αφαίρεση ορίου» το **αντικαθιστούν**, όπως
 * ακριβώς ο κύκλος αντικαθίσταται από το ορθογώνιο.
 *
 * 🔑 **ΤΕΤΑΡΤΟ ΣΚΕΛΟΣ: ΤΟ ΣΧΗΜΑ ΠΟΥ ΣΧΕΔΙΑΣΕ Ο ΙΔΙΟΣ** *(ADR-885)* — ο επισκέπτης πατά
 * «Σχεδίασε» και τραβά γραμμή γύρω από τις γειτονιές που θέλει. Ίδιος χειρισμός με το
 * όριο: η «Αφαίρεση ορίου» το αντικαθιστά.
 */
export type GeoArea = GeoCircle | GeoBoundingBox | GeoRegion | GeoDrawnArea;

/**
 * **Η περιοχή που σχεδίασε ο επισκέπτης** — ένα ή περισσότερα σχήματα *(ADR-885)*.
 *
 * 🔴 **ΔΕΝ είναι {@link GeoRegion} χωρίς ταυτότητα.** Εκείνο κρίνεται με **περιττό
 * πλήθος** (even–odd: ο δακτύλιος μέσα σε δακτύλιο είναι **τρύπα**). Εδώ τα σχήματα
 * είναι **ένωση**: δύο επικαλυπτόμενα σχήματα λένε *«και εδώ, και εδώ»*, και με
 * even–odd η επικάλυψή τους θα γινόταν **κενό** ακριβώς εκεί όπου ο άνθρωπος
 * σχεδίασε δύο φορές.
 *
 * 🔒 **Κάθε σχήμα είναι ΑΠΛΟ** (χωρίς αυτοτομή) και **κβαντισμένο** στην ακρίβεια της
 * διεύθυνσης — δηλαδή το σχήμα στη μνήμη **είναι** το σχήμα του συνδέσμου. Γι' αυτό
 * δεν κουβαλά ανοχή: δεν υπάρχει «αληθινό» σύνορο από το οποίο να αποκλίνει.
 */
export interface GeoDrawnArea {
  readonly shapes: readonly GeoOutline[];
  /** Το ορθογώνιο της **ένωσης** των σχημάτων. */
  readonly bbox: GeoBoundingBox;
}

/**
 * **Το όριο μιας διοικητικής περιοχής, ΕΠΙΛΥΜΕΝΟ σε γεωμετρία** *(ADR-883)*.
 *
 * 🔑 **Κουβαλά την ταυτότητά του (`adminId`)** επειδή η διεύθυνση γράφει **ποιος** δήμος,
 * ποτέ τα πολύγωνά του (`area=municipality:0708`). Ένα όριο χωρίς ταυτότητα δεν θα
 * μπορούσε να ξαναγραφτεί στη διεύθυνση — δηλαδή ο σύνδεσμος θα το έχανε.
 *
 * 🔒 **Η ανοχή είναι μέρος του σχήματος**: οι δακτύλιοι είναι απλοποιημένοι με
 * εγγυημένη μέγιστη απόκλιση `toleranceM` από το αληθινό σύνορο. Ο κριτής τη χρειάζεται
 * για να πει «ίσως» — όχι «μέσα» ή «έξω» — όπου το σύνορο είναι θολό.
 */
export interface GeoRegion {
  readonly adminId: string;
  /** Κάθε δακτύλιος — εξωτερικοί **και** τρύπες. Κρίνονται με περιττό πλήθος (even–odd). */
  readonly rings: readonly GeoOutline[];
  /** Το ορθογώνιο της **αληθινής** γεωμετρίας — ποτέ μικρότερο από αυτήν. */
  readonly bbox: GeoBoundingBox;
  /** Εγγυημένη μέγιστη απόκλιση των δακτυλίων από το αληθινό σύνορο, σε μέτρα. */
  readonly toleranceM: number;
}

/**
 * **Η ΑΝΕΠΙΛΥΤΗ αναφορά σε διοικητική περιοχή** — ό,τι ξέρει η διεύθυνση πριν φορτώσει
 * το όριο. Ίδιο σχήμα με το διοικητικό σκέλος του `ShowcaseWhere` *(ADR-846)*.
 */
export interface GeoRegionRef {
  readonly adminId: string;
}
