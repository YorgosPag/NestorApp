/**
 * **Η πρόσκληση όπως τη βλέπει ο διαχειριστής** (ADR-853 §5 #5 — κατάσταση παράδοσης).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⛔ ΤΟ `nonceHash` ΔΕΝ ΕΙΝΑΙ ΕΔΩ, ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΠΑΡΑΛΕΙΨΗ
 * ─────────────────────────────────────────────────────────────────────────────
 * Είναι το **μισό κλειδί** της πόρτας. Δεν αρκεί μόνο του *(θέλει και το μυστικό του
 * διακομιστή)*, αλλά μια όψη που το κουβαλά το στέλνει σε **κάθε** φυλλομετρητή
 * διαχειριστή, σε κάθε ανανέωση σελίδας — δηλαδή πολλαπλασιάζει τα σημεία διαρροής για
 * **μηδέν** όφελος: καμία οθόνη δεν έχει τι να το κάνει. Ίδια πειθαρχία με το
 * `WorkspaceAccessRequestView`, που δεν κουβαλά ποτέ εσωτερικά πεδία.
 *
 * ⛔ **ΚΑΙ ΔΕΝ ΥΠΑΡΧΕΙ ΠΕΔΙΟ «ΛΗΓΕΙ ΣΕ Ν ΜΕΡΕΣ»**, παρότι το §5 #5 το ζητά στην οθόνη: θα
 * ήταν **στιγμιότυπο που παλιώνει στο σύρμα** — «λήγει σε 2 μέρες» είναι λάθος μετά από
 * δύο μέρες στην ίδια ανοιχτή καρτέλα. Ταξιδεύει το `expiresAt` *(απόλυτη στιγμή)* και το
 * «σε Ν» το υπολογίζει η οθόνη τη στιγμή που ζωγραφίζει.
 */
export interface WorkspaceInvitationView {
  readonly id: string;
  /**
   * ⚠️ **Ταξιδεύει παρότι η λίστα είναι ήδη ενός χώρου** — και είναι απόφαση: μια όψη που
   * δεν λέει σε **ποιον** ανήκει δεν μπορεί να μπει ποτέ σε απάντηση πολλών χώρων χωρίς να
   * γίνει διφορούμενη. Ίδιο ιδίωμα με το `WorkspaceAccessRequestView.companyId`.
   */
  readonly companyId: string;
  readonly inviteeEmail: string;
  readonly role: InvitableRole;
  /**
   * 🔴 **ΠΑΡΑΓΟΜΕΝΗ, ΟΧΙ ΑΝΤΙΓΡΑΦΟ ΤΟΥ ΕΓΓΡΑΦΟΥ** — δες τον αναγνώστη.
   *
   * Μια `pending` της οποίας η ώρα πέρασε ταξιδεύει ως `expired`: **κανείς δεν σκουπίζει**
   * τις ληγμένες σε πραγματικό χρόνο (γι' αυτό και η εξαργύρωση ελέγχει τη λήξη **δύο**
   * φορές, άγκυρα Τ2). Αλλιώς ο διαχειριστής βλέπει «σε αναμονή» για σύνδεσμο **που δεν
   * δουλεύει** και περιμένει άνθρωπο που δεν μπορεί να απαντήσει.
   */
  readonly state: WorkspaceInvitationState;
  readonly invitedByUid: string;
  readonly createdAt: string;
  readonly expiresAt: string;
  /** ⚠️ **Ένδειξη, όχι απόδειξη** (§6 #3): οι πελάτες email προ-φορτώνουν συνδέσμους. */
  readonly openedAt: string | null;
  readonly resolvedAt: string | null;
  readonly resolvedByUid: string | null;
}

/**
 * **Τι βλέπει ο ΠΡΟΣΚΕΚΛΗΜΕΝΟΣ πριν αποφασίσει** (ADR-853 §5 #4).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ ΚΑΘΟΛΟΥ — ΚΑΙ ΓΙΑΤΙ ΕΙΝΑΙ ΑΝΤΙ-PHISHING, ΟΧΙ ΕΥΚΟΛΙΑ
 * ─────────────────────────────────────────────────────────────────────────────
 * Ο παραλήπτης φτάνει από **email**, πριν από κάθε ταυτότητα: περνά από `/login` και
 * επιστρέφει (§6 #2). Χωρίς αυτή την όψη, η οθόνη θα του ζητούσε να **συνδεθεί σε κάτι
 * που δεν ξέρει τι είναι** — ακριβώς η συνθήκη στην οποία δουλεύει το phishing. Βλέπει
 * **πρώτα** ποιος τον καλεί και για τι θέση, **μετά** αποφασίζει.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⛔ ΤΙ ΔΕΝ ΕΙΝΑΙ ΕΔΩ, ΚΑΙ ΚΑΘΕ ΑΠΟΥΣΙΑ ΕΙΝΑΙ ΑΠΟΦΑΣΗ
 * ─────────────────────────────────────────────────────────────────────────────
 * · **Το email του παραλήπτη**: η όψη δίνεται σε **όποιον κρατά τον σύνδεσμο**, χωρίς
 *   ταυτότητα. Να το επιστρέψουμε σημαίνει ότι ένας προωθημένος σύνδεσμος αποκαλύπτει
 *   **σε τρίτον** τη διεύθυνση ενός ανθρώπου. Η **δέσμευση** στο email παραμένει
 *   ακέραιη — κρίνεται στην εξαργύρωση (§7.5) — απλώς δεν **ανακοινώνεται**.
 * · **Το `companyId`**: αναγνωριστικό μισθωτή σε ανώνυμη επιφάνεια. Ο άνθρωπος
 *   χρειάζεται το **όνομα**· το id δεν του λέει τίποτα και σε άλλον λέει πολλά.
 * · **Το `invitationId`**: δεν χρειάζεται να ταξιδέψει — η πράξη στέλνει πίσω το
 *   **token**, που το κουβαλά υπογεγραμμένο.
 */
export interface WorkspaceInvitationPreview {
  /**
   * Το όνομα του χώρου, από τον **ΕΝΑ** αναγνώστη (`readWorkspaceName`).
   *
   * ⚠️ **Κενό σημαίνει «το γραφείο δεν έχει δηλώσει όνομα»**, ποτέ «δεν υπάρχει»: την
   * ετικέτα για αυτή την περίπτωση τη διαλέγει η οθόνη από τα locales (N.11) — ο
   * διακομιστής δεν στέλνει ωμό `comp_*`, που θα ζητούσε από άνθρωπο να μπει σε
   * οργανισμό που δεν ξέρει να ονομάσει.
   */
  readonly workspaceName: string;
  readonly role: InvitableRole;
  /** Απόλυτη στιγμή — το «λήγει σε Ν» το υπολογίζει η οθόνη (δες {@link WorkspaceInvitationView}). */
  readonly expiresAt: string;
  /**
   * 🔑 **«ΔΗΛΩΜΕΝΗ, ΟΧΙ ΕΠΑΛΗΘΕΥΜΕΝΗ» — ΣΤΟ ΣΥΡΜΑ, ΟΧΙ ΜΟΝΟ ΣΤΟ ΣΧΕΔΙΟ** (§5 #4).
   *
   * Σήμερα έχει **μία** τιμή, γιατί το §6 #4 δηλώνει ρητά *«καμία επαλήθευση ΓΕΜΗ/ΑΦΜ σε
   * αυτή τη φάση»*. ⚠️ **Και δεν είναι περιττό**: ένα πεδίο που η οθόνη πρέπει να
   * διαβάσει δεν την αφήνει να **ξεχάσει** την ετικέτα, και τη μέρα που έρθει η
   * επαλήθευση (ADR-787 **Κ-8** / ADR-798 §7 — **τρεις** καταστάσεις, ποτέ boolean) ο
   * τύπος θα αποκτήσει δεύτερη τιμή και **κάθε** `switch` πάνω του θα σταματήσει να
   * μεταγλωττίζεται μέχρι κάποιος να πει τι σημαίνει η διαφορά.
   *
   * ⛔ ΜΗΝ το κάνεις `boolean` «για απλότητα»: *«δεν επαληθεύτηκε»* και *«δεν κοιτάξαμε»*
   *    δεν είναι το ίδιο πράγμα, και ένα `false` τα ισοπεδώνει.
   */
  readonly identityAssurance: 'declared';
}
