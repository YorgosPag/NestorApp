/**
 * @fileoverview **Η ΠΡΟΣΚΛΗΣΗ ΣΕ ΧΩΡΟ ΕΡΓΑΣΙΑΣ** — ο χώρος ξεκινά τη σχέση (ADR-853 Α1).
 * @related ADR-853 §7 · ADR-787 Α2/Ε-1 · ADR-844 (δόγμα token) · ADR-801 §4 (ο κριτής)
 * @module types/workspace-invitation
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΗ ΟΝΤΟΤΗΤΑ ΚΑΙ ΟΧΙ ΠΕΔΙΟ ΣΤΟ ΜΕΛΟΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η προφανής σχεδίαση ήταν `workspace_members/{uid}` με `status: 'invited'`. **Είναι
 * αδύνατη, και ο λόγος είναι η ταυτότητα**: το έγγραφο μέλους έχει κλειδί το `uid`, και
 * τη στιγμή της πρόσκλησης **δεν υπάρχει uid** — η πρόσκληση φτάνει σε **email**
 * (ADR-853 §6 #2· το `claims-handler.ts` απαιτεί **υπαρκτό** χρήστη Firebase).
 *
 * ⇒ Ένα «μέλος σε αναμονή» θα ήταν έγγραφο **με κενό το κλειδί του**. Και χειρότερα: το
 * `listMemberWorkspaces` κάνει collection-group στο `workspace_members` με
 * `status == 'active'` — ένα ημιτελές μέλος εκεί μέσα είναι μια σειρά στην απάντηση
 * *«σε ποιους χώρους ανήκει ο Χ;»* για άνθρωπο που **δεν δέχτηκε ποτέ**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΙ ΚΟΥΒΑΛΑ ΚΑΙ ΤΙ ΔΕΝ ΚΟΥΒΑΛΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * **Κουβαλά** τον χώρο (`companyId`). Αυτό είναι το **Κ7 του ADR-853**: η πρόσκληση
 * **ΦΕΡΝΕΙ** την εταιρεία μέσα στο έγγραφό της — δεν τη **διαβάζει** από τον πελάτη. Γι'
 * αυτό δεν προστίθεται τέταρτο κανάλι χώρου (CHECK 3.58, κλειστό σύνολο **τριών**).
 *
 * **ΔΕΝ κουβαλά** το όνομα της εταιρείας. Ένα στιγμιότυπο ονόματος θα ήταν **δεύτερη
 * αυθεντία** που παλιώνει σιωπηλά: το γραφείο μετονομάζεται, και ο προσκεκλημένος βλέπει
 * στην οθόνη αποδοχής όνομα που **δεν υπάρχει πια**. Το όνομα διαβάζεται τη στιγμή της
 * εμφάνισης, από τη **μία** διαδρομή (ADR-853 Φ5).
 *
 * **Layering**: leaf — καθαροί τύποι. Κανένα Firestore, κανένα ρολόι, κανένα React.
 */

