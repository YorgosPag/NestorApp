/**
 * 🔑 **Ονομασμένοι λόγοι επειδή ο ΑΝΘΡΩΠΟΣ τους διαβάζει**, και καθένας τον στέλνει σε
 * **διαφορετική** ενέργεια. Η αγορά δίνει γενικό *«invitation not valid»* (§5 #7)· εδώ
 * κάθε άρνηση ξέρει τι να πει.
 */
export const WORKSPACE_INVITATION_REFUSALS = [
  /** Η υπογραφή δεν στέκει, ή το κείμενο δεν είναι σύνδεσμός μας. */
  'link-invalid',
  /** Ο σύνδεσμος είναι έγκυρος αλλά το έγγραφο δεν υπάρχει — σβήστηκε ή δεν γράφτηκε ποτέ. */
  'invitation-unknown',
  /** ⚠️ Κρίνεται **δύο φορές**: στο token **και** στο έγγραφο (ο χρόνος ζει σε δύο μέρη). */
  'expired',
  /** **Επιτυχία στο παρελθόν**, όχι αποτυχία τώρα. Η οθόνη το λέει ήρεμα. */
  'already-used',
  /** Ανακλήθηκε από τον χώρο, ή αντικαταστάθηκε από νεότερη. */
  'revoked',
  /**
   * 🔴 Ο συνδεδεμένος άνθρωπος **δεν είναι** ο παραλήπτης.
   *
   * Χωρίς αυτό, ένα προωθημένο email θα έδινε σε **τρίτον** τη θέση που προοριζόταν για
   * άλλον — και το γραφείο δεν θα το μάθαινε ποτέ.
   */
  'wrong-recipient',
  /**
   * 🔴 Ο άνθρωπος είναι ο **σωστός**, αλλά το email του **δεν έχει επαληθευτεί**.
   *
   * ⚠️ **ΞΕΧΩΡΙΣΤΟ ΑΠΟ ΤΟ `wrong-recipient`, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ ΟΧΙ ΛΕΠΤΟΛΟΓΙΑ.** Το
   * ADR-853 §7.5 απαιτεί **επαληθευμένο** email, όχι απλώς ίδιο κείμενο: χωρίς
   * επαλήθευση, οποιοσδήποτε δηλώνει το email του στόχου και δέχεται τη θέση του. Αλλά
   * το να πει κανείς *«δεν είσαι ο παραλήπτης»* σε άνθρωπο που **είναι** ο παραλήπτης
   * είναι **ψέμα που τον στέλνει σε λάθος ενέργεια**: εκείνος πρέπει να επιβεβαιώσει το
   * γραμματοκιβώτιό του, όχι να ψάξει άλλον λογαριασμό.
   *
   * 🔑 Ίδιο δόγμα με τους ονομασμένους λόγους του `signed-token.ts`: *«ο σύνδεσμος
   * έληξε» και «ο σύνδεσμος δεν είναι έγκυρος» στέλνουν τον παραλήπτη σε ΕΝΤΕΛΩΣ
   * διαφορετική ενέργεια»*.
   */
  'email-unverified',
  /** Είναι **ήδη** μέλος αυτού του χώρου· η πρόσκληση δεν έχει τι να δώσει. */
  'already-member',
  /** Ο ρόλος της πρόσκλησης είναι **πάνω** από τον προσκαλούντα (Α3 — ceilings only subtract). */
  'role-above-inviter',
] as const;

export type WorkspaceInvitationRefusal = (typeof WORKSPACE_INVITATION_REFUSALS)[number];

export function isWorkspaceInvitationRefusal(
  value: unknown,
): value is WorkspaceInvitationRefusal {
  return typeof value === 'string'
    && (WORKSPACE_INVITATION_REFUSALS as readonly string[]).includes(value);
}
