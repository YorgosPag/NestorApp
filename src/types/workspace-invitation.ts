/**
 * Οι ρόλοι που **επιτρέπεται** να δοθούν με πρόσκληση (ADR-853 Α3).
 *
 * ⛔ **ΤΟ `super_admin` ΛΕΙΠΕΙ ΕΠΙΤΗΔΕΣ, ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΠΑΡΑΛΕΙΨΗ**: είναι **break-glass**,
 * όχι βαθμίδα ιεραρχίας — η δύναμή του είναι το `isBypass`, δηλαδή «παρακάμπτει **κάθε**
 * έλεγχο». Ένας ρόλος που παρακάμπτει τους ελέγχους δεν δίνεται με **email**.
 *
 * ⚠️ **ΚΑΙ ΔΕΝ ΑΡΚΕΙ ΤΟ ΤΑΒΑΝΙ ΤΟΥ `compareRoleLevels` ΓΙΑ ΝΑ ΤΟΝ ΚΟΨΕΙ.** Σήμερα ο
 * `super_admin` είναι `level: 0`, άρα θα έπεφτε ούτως ή άλλως στο ταβάνι *για όλους* —
 * και γι' αυτό ακριβώς ο ρητός αποκλεισμός **μοιάζει** περιττός. Δεν είναι: τη μέρα που
 * προστεθεί **δεύτερος** bypass ρόλος σε άλλο level, το ταβάνι θα τον επέτρεπε σιωπηλά.
 * Δύο ανεξάρτητοι κανόνες, ποτέ ένας με «ή» — το μάθημα του CHECK 3.41.
 */
export const INVITABLE_ROLES = [
  'company_admin',
  'internal_user',
  'external_user',
] as const satisfies readonly GlobalRole[];

export type InvitableRole = (typeof INVITABLE_ROLES)[number];

export function isInvitableRole(value: unknown): value is InvitableRole {
  return typeof value === 'string' && (INVITABLE_ROLES as readonly string[]).includes(value);
}

