/** Η εντολή προς το γραφείο, με ό,τι της λείπει από τον κοινό πυρήνα. */
export interface BrokeredListingMandate extends BrokeredMandateCore {
  readonly kind: 'brokered';
  readonly proof: MandateProof;
  /**
   * **Τι είδους εντολή** — το `ListingAgreement` του RESO (ADR-827 §3.1).
   *
   * 🔑 **Υποχρεωτικό, ΟΧΙ προαιρετικό**, και το κόστος μετρήθηκε πριν αποφασιστεί:
   * **0** εντολές `brokered` στη ζωντανή βάση ⇒ **καμία** μετανάστευση. Ένα `?:` εδώ
   * θα σήμαινε **σιωπηλή προεπιλογή** — δηλαδή ο ιδιοκτήτης να δεσμεύεται σε όρο που
   * κανείς δεν του έδειξε, στο ακριβώς αντίθετο πνεύμα από το `MandateProof`.
   *
   * ⚠️ Το ερώτημα «μπορεί να δώσει και σε **δεύτερο** γραφείο;» το απαντά το
   * `allowsOtherAgencies`, όχι η ανάγνωση αυτού του πεδίου με το χέρι.
   */
  readonly agreement: ListingAgreement;
  /**
   * **Οι όροι αμοιβής.** Δες {@link MandateCompensation} για το γιατί ζει εδώ και
   * **ποτέ** στη δημόσια προβολή.
   */
  readonly compensation: MandateCompensation;
  /**
   * ISO — **πότε μίλησε ο άνθρωπος**, όποιον δρόμο κι αν πήρε η απάντηση.
   *
   * ⚠️ **Δεν είναι το `attestedAt`.** Εκείνο λέει πότε το **γραφείο** ισχυρίστηκε·
   * αυτό πότε ο **ιδιοκτήτης** αποφάσισε. Στη βεβαίωση τα δύο είναι διαφορετικά και
   * το δεύτερο μένει `null` — που είναι **η αλήθεια**, όχι έλλειψη.
   */
  readonly decidedAt: string | null;
  /**
   * ISO — πότε **του το είπαμε**. `null` = δεν στάλθηκε ποτέ μήνυμα.
   *
   * 🔴 **Είναι το πεδίο που μας ξεχωρίζει από κάθε MLS, και πρέπει να μπορεί να είναι
   * `null`.** Μια επαφή μπορεί να μην έχει καθόλου email. Ένα `notifiedAt` που
   * γεννιόταν πάντα γεμάτο θα έλεγε *«τον ειδοποιήσαμε»* για ανθρώπους που **δεν
   * ειδοποιήθηκαν** — και θα το έλεγε με ημερομηνία, δηλαδή πειστικά.
   */
  readonly notifiedAt: string | null;
  /**
   * ISO — πότε **άνοιξε ο ίδιος τον σύνδεσμο**. `null` = δεν τον άνοιξε ποτέ.
   *
   * 🔑 **Είναι το `delivered` του DocuSign, και ήταν το ΜΟΝΟ βήμα που μας έλειπε.** Η
   * τεκμηρίωσή του το ορίζει κατά λέξη: *«Delivered means that all recipients have
   * viewed the documents, meaning they **clicked on the link** to access the documents,
   * but did not sign them»*. Χωρίς αυτό, «του στείλαμε και σιωπά» και «το διάβασε και
   * το σκέφτεται» είναι **η ίδια γραμμή** στον κατάλογο — και είναι δύο εντελώς
   * διαφορετικά τηλεφωνήματα.
   *
   * 🏆 **Μαζί με το {@link notifiedAt} φτιάχνουν χωνί ΤΡΙΩΝ βημάτων που κανείς δεν
   * έχει ολόκληρο**: *του το είπαμε;* → *το άνοιξε;* → *απάντησε;*. Το DocuSign έχει
   * τα δύο τελευταία και **δομικά δεν μπορεί** να έχει το πρώτο (φάκελος χωρίς
   * διεύθυνση παραλήπτη **δεν γεννιέται**)· το MLS δεν έχει κανένα, γιατί δεν
   * παρακολουθεί καθόλου την έγκριση του ιδιοκτήτη.
   *
   * ⚠️ **Γράφεται ΜΙΑ φορά — «πότε το είδε ΠΡΩΤΗ φορά», όχι «πότε το είδε τελευταία».**
   * Η πρώτη ματιά είναι το γεγονός που αλλάζει την ερμηνεία της σιωπής· η δέκατη δεν
   * προσθέτει τίποτα και θα έκανε κάθε φόρτωση σελίδας **εγγραφή στη βάση**.
   */
  readonly viewedAt: string | null;
  /**
   * 🔴 **ΠΟΤΕ ΑΝΑΚΛΗΘΗΚΕ Η ΜΕΣΙΤΙΚΗ ΑΔΕΙΑ ΤΟΥ ΓΡΑΦΕΙΟΥ** (ADR-824 §8 Κ6) — `null` όσο
   * το γραφείο επιτρέπεται.
   *
   * ⚠️ **ΔΕΝ είναι «ο ιδιοκτήτης ανακάλεσε την εντολή»** — εκείνο είναι το
   * `confirmation: 'declined'`, **άλλο γεγονός με άλλον δράστη**. Εδώ ο δράστης είναι
   * ο **ρυθμιστής** (υπερδιαχειριστής), και το υποκείμενο το **γραφείο**, όχι αυτή η
   * αγγελία. Κοινό πεδίο θα έλεγε στον ιδιοκτήτη ότι κάποιος αντιλέγει στη δική του
   * συγκατάθεση, ενώ κανείς δεν αντιλέγει.
   *
   * 🔑 **ΓΙΑΤΙ ΓΡΑΦΕΤΑΙ ΣΤΗΝ ΟΝΤΟΤΗΤΑ ΚΑΙ ΔΕΝ ΡΩΤΙΕΤΑΙ Η ΕΤΑΙΡΕΙΑ.** Το «είναι στον
   * δημόσιο χάρτη;» το απαντά **καθαρή συνάρτηση** πάνω στην αγγελία — και το τρέχει
   * **και η οθόνη του κατόχου** (`OwnerPropertyCard`), που **δεν μπορεί** να διαβάσει
   * το `companies/{id}` του γραφείου. Μια ανάγνωση εταιρείας μέσα στον κριτή θα
   * γεννούσε **δεύτερο** κριτή για τους πελάτες που δεν μπορούν να τη ζητήσουν —
   * δηλαδή ακριβώς το σχήμα του ADR-749. Το γεγονός **ταξιδεύει** στην αγγελία μία
   * φορά, τη στιγμή της ανάκλησης, και ο ΕΝΑΣ κριτής το διαβάζει από παντού δωρεάν.
   *
   * ⚠️ **Αντιστρέψιμο**: η επανέγκριση το ξαναγράφει `null` και η αγγελία επανέρχεται
   * — γι' αυτό είναι **στιγμή** και όχι σβήσιμο της εντολής. Η συμφωνημένη διάρκεια
   * (`expiresAt`) **δεν πειράζεται ποτέ**: θα ήταν απώλεια δεδομένου για να εκφραστεί
   * γεγονός που έχει δικό του πεδίο.
   */
  readonly agencyRevokedAt?: string | null;
  /**
   * Η ταυτότητα του **ζωντανού συνδέσμου συγκατάθεσης**. `null` = κανένας σύνδεσμος
   * δεν ισχύει αυτή τη στιγμή.
   *
   * 🔴 **ΕΔΩ ΖΕΙ Η ΑΝΑΚΛΗΣΗ, ΚΑΙ ΓΙ' ΑΥΤΟ ΔΕΝ ΧΡΕΙΑΣΤΗΚΕ ΣΥΛΛΟΓΗ.** Η πύλη
   * προμηθευτή κρατά τα ακυρωμένα `nonce` σε **δεύτερη συλλογή**
   * (`vendor_invite_tokens`) — δηλαδή δεύτερο βιβλίο που πρέπει να συμφωνεί με το
   * πρώτο. Εδώ η **κατάσταση που αποφασίζει είναι η κατάσταση που απαντά**: ο
   * σύνδεσμος ισχύει όσο το `nonce` του **είναι** αυτό που γράφει η εντολή. Νέα
   * αποστολή γράφει νέο· ανάκληση γράφει `null`. Καμία απόκλιση δυνατή, γιατί δεν
   * υπάρχει δεύτερο βιβλίο (ADR-749).
   *
   * ⚠️ **Δεν είναι μυστικό που προστατεύει από πλαστογραφία** — αυτό το κάνει η
   * υπογραφή. Είναι **η ταυτότητα της συγκεκριμένης πρόσκλησης**, ώστε ένας παλιός
   * σύνδεσμος να μη μιλά για λογαριασμό μιας πρόσκλησης που αντικαταστάθηκε.
   */
  readonly consentNonce: string | null;
  /**
   * ISO — **η συμβατική λήξη** της εντολής. Το `ExpirationDate` του RESO.
   *
   * ⚠️ **Είναι ημερομηνία ΣΥΜΦΩΝΙΑΣ, όχι ρολόι συστήματος** (RESO, κατά λέξη). Δεν
   * ενημερώνεται όταν κάποιος πατήσει «αποθήκευση»· αλλάζει **μόνο** όταν αλλάξει η
   * συμφωνία.
   */
  readonly expiresAt: string;
}

/**
 * **Ποιανού είναι η αγγελία.**
 *
 * ⚠️ Το σκέλος `self` **δεν έχει κανένα πεδίο**, και είναι σκόπιμο: ο ιδιώτης που
 * γράφει το δικό του σπίτι δεν δίνει εντολή σε κανέναν, δεν εγκρίνει τίποτα και δεν
 * λήγει ποτέ. Πεδία γεμάτα `null` για τη μισή συλλογή θα ήταν φρουροί που **δεν
 * μπορούν να πυροδοτήσουν**.
 */
export type OwnerPropertyMandate = { readonly kind: 'self' } | BrokeredListingMandate;

// =============================================================================
// 4. ΟΙ ΚΡΙΤΕΣ — «επιτρέπεται να φτάσει στον κόσμο;»
// =============================================================================

/**
 * **Πέρασε η συμβατική λήξη;** `self` ⇒ ποτέ.
 *
 * @param nowISOValue — η **περασμένη** στιγμή, ποτέ `new Date()` εδώ μέσα: ο κριτής
 *   πρέπει να δίνει την ίδια απάντηση σε όλο το πέρασμα προβολής, και ένα ρολόι
 *   διαβασμένο μέσα στη συνάρτηση κάνει το ίδιο πέρασμα να διαφωνεί με τον εαυτό του.
 */
export function isMandateExpired(
  mandate: OwnerPropertyMandate,
  nowISOValue: string,
): boolean {
  if (mandate.kind === 'self') return false;
  return Date.parse(mandate.expiresAt) <= Date.parse(nowISOValue);
}

/**
 * 🔴 **Ο ΕΝΑΣ ΚΡΙΤΗΣ: επιτρέπεται αυτή η αγγελία να φτάσει στον κόσμο;**
 *
 * `true` για τον ιδιώτη πάντα· για το γραφείο **μόνο** όταν ο ιδιοκτήτης έχει πει
 * «ναι» **και** η εντολή δεν έχει λήξει.
 *
 * ⚠️ **ΔΕΝ είναι δεύτερο κριτήριο δημοσίευσης** — και ο τρόπος που καταναλώνεται είναι
 * ο λόγος. Το `owner-property-projection.ts` **δεν** ρωτά «δημοσιεύεται;» (αυτό
 * απαντιέται **μία** φορά, στο `isPubliclyListed`)· λέει την αλήθεια **στη γλώσσα της
 * Α20**: μια αγγελία χωρίς ζωντανή εντολή **δεν έχει καμία διάθεση στην αγορά**. Από
 * εκεί και πέρα ο υπάρχων κώδικας βγάζει μόνος του `unavailable` + `[]` και **σβήνει**
 * την προβολή. Είναι **ακριβώς** ο μηχανισμός που χρησιμοποιεί ήδη η απόσυρση.
 *
 * 🔑 Γι' αυτό η **λήξη δεν χρειάζεται δικό της μηχανισμό εξαφάνισης**: την επόμενη
 * φορά που η αγγελία συντίθεται, φεύγει μόνη της. Το μόνο που μένει είναι **κάποιος
 * να σκανδαλίσει** τη σύνθεση — δουλειά ενός περάσματος, όχι νέας αρχής.
 */
export function mandateAllowsPublication(
  mandate: OwnerPropertyMandate,
  nowISOValue: string,
): boolean {
  return (
    isMandateAttributable(mandate) &&
    !isMandateExpired(mandate, nowISOValue) &&
    // 🔴 **Η ΑΔΕΙΑ ΤΟΥ ΓΡΑΦΕΙΟΥ** (ADR-824 §8 Κ6). Χωρίς αυτόν τον όρο, η ανάκληση
    //    μεσιτικής ικανότητας **δεν άγγιζε** τις ήδη δημοσιευμένες αγγελίες: το
    //    γραφείο έχανε το δικαίωμα να καταχωρεί **νέες** και κρατούσε στον δημόσιο
    //    χάρτη **όσες πρόλαβε** — δηλαδή ο φρουρός θα φύλαγε μόνο το μέλλον.
    !isAgencyRevoked(mandate)
  );
}

/**
 * Έχει ανακληθεί η μεσιτική άδεια του γραφείου που κρατά αυτή την εντολή;
 *
 * 🔴 **`?? null` ΚΑΙ ΟΧΙ `!== null` ΣΚΕΤΟ — ΤΟ ΒΡΗΚΕ ΑΓΚΥΡΑ, ΟΧΙ ΑΝΑΓΝΩΣΗ.** Το πεδίο
 * είναι **προαιρετικό** γιατί **καμία** εντολή που υπάρχει σήμερα δεν το έχει. Με
 * σκέτο `!== null`, το `undefined` κάθε υπάρχοντος εγγράφου θα διαβαζόταν ως
 * **ανακληθείσα άδεια** ⇒ **όλες** οι brokered αγγελίες θα εξαφανίζονταν από τον
 * δημόσιο χάρτη σιωπηλά — ακριβώς η κλάση βλάβης του ADR-777 §8.45.
 *
 * 🔑 **Η απουσία σημαίνει «δεν ανακλήθηκε», και είναι η σωστή κατεύθυνση**: ο
 * φρουρός της **γέννησης** νέων brokered αγγελιών είναι ο τύπος
 * `BrokerageAuthority` (ADR-824 §6) και δεν εξαρτάται από αυτό το πεδίο. Εδώ
 * κρίνεται μόνο *«ανακλήθηκε **μετά**;»* — και η απάντηση για έγγραφο που γράφτηκε
 * πριν υπάρξει το πεδίο είναι **όχι**.
 */
export function isAgencyRevoked(mandate: OwnerPropertyMandate): boolean {
  return mandate.kind === 'brokered' && (mandate.agencyRevokedAt ?? null) !== null;
}

/**
 * Οι παραβιάσεις της εντολής, ως **κλειστό σύνολο κωδικών** — ίδιο ιδίωμα με τα
 * `OWNER_PROPERTY_INVARIANTS`: κωδικός εδώ, μήνυμα στα locale (N.11).
 */
export const MANDATE_INVARIANTS = [
  /** Εντολή χωρίς πελάτη: το γραφείο δεν λέει **για ποιον** γράφει. */
  'mandate-client-missing',
  /** Λήξη που λείπει ή δεν είναι αναγνώσιμη ημερομηνία. */
  'mandate-expiry-invalid',
  /**
   * Λήξη **στο παρελθόν** τη στιγμή της καταχώρησης.
   *
   * 🔑 Ξεχωριστός κωδικός από το `mandate-expiry-invalid` επίτηδες: «δεν είναι
   * ημερομηνία» και «είναι χθες» έχουν **διαφορετική θεραπεία** στην οθόνη, και ένας
   * κοινός κωδικός θα έλεγε στον άνθρωπο να διορθώσει τη μορφή ενός σωστά
   * μορφοποιημένου πεδίου.
   */
  'mandate-expiry-past',
  /**
   * **Βεβαίωση γραφείου χωρίς έγκριση.**
   *
   * ⚠️ Η βεβαίωση **είναι** ο ισχυρισμός ότι η εντολή υπάρχει ήδη υπογεγραμμένη —
   * οπότε μια βεβαίωση που γεννιέται `pending` δεν βεβαιώνει τίποτα. Η μόνη νόμιμη
   * μετάβαση από εκεί είναι προς τα **κάτω** (ο ιδιοκτήτης αντιλέγει ⇒ `declined`).
   */
  'mandate-attestation-not-confirmed',
  /**
   * 🔴 **Η ΣΥΜΦΩΝΗΜΕΝΗ ΔΙΑΡΚΕΙΑ ΞΕΠΕΡΝΑ ΤΟ ΝΟΜΙΜΟ ΑΝΩΤΑΤΟ** του είδους εντολής
   * (`exceedsStatutoryTerm` · **άρθρο 200 §3/§4 Ν.4072/2012**).
   *
   * ⚠️ **Ξεχωριστός κωδικός από το `mandate-expiry-past`, και δεν είναι λεπτολογία**:
   * εκείνο λέει *«έβαλες χθες»* — τυπογραφικό. Αυτό λέει *«αυτός ο όρος είναι
   * **άκυρος**»* — και η θεραπεία δεν είναι «διόρθωσε την ημερομηνία» αλλά **«διάλεξε
   * μικρότερη διάρκεια Ή άλλο είδος εντολής»**, γιατί το όριο **εξαρτάται από το
   * είδος**. Ένας κοινός κωδικός θα έστελνε τον μεσίτη να αλλάζει ημερομηνίες σε
   * ατέρμονο βρόχο χωρίς να μάθει ποτέ ότι το πρόβλημα είναι η **αποκλειστικότητα**.
   *
   * 🏆 Το μήνυμα οφείλει να μεταφέρει **τον αριθμό ΚΑΙ τη διάταξη** — και τα δύο
   * ταξιδεύουν μαζί στο `StatutoryTermLimit`, ώστε να μην μπορούν να αποκλίνουν.
   */
  'mandate-term-exceeds-statute',
  /**
   * 🔴 **ΤΟ ΕΙΔΟΣ ΤΗΣ ΕΝΤΟΛΗΣ ΛΕΙΠΕΙ Ή ΔΕΝ ΑΝΑΓΝΩΡΙΖΕΤΑΙ.**
   *
   * ⚠️ **Δεν είναι θεωρητικός κωδικός**: το `agreement` έγινε υποχρεωτικό στη **Φάση
   * Α (2026-08-28)**, άρα κάθε εντολή γραμμένη πριν από εκείνη τη μέρα το έχει
   * `undefined` στο Firestore. Χωρίς αυτόν τον κωδικό, τέτοιο έγγραφο θα περνούσε
   * **χωρίς κανέναν έλεγχο διάρκειας** *(fail-open — ακριβώς ό,τι δεν θέλουμε σε
   * φρουρό νομιμότητας)*.
   *
   * 🔑 **Ξεχωριστός από το `mandate-term-exceeds-statute` γιατί το ΝΟΗΜΑ διαφέρει**:
   * εκείνο λέει *«ξέρω τι είδους είναι και είναι πολύ μεγάλη»*, αυτό λέει *«**δεν
   * ξέρω** τι είδους είναι, άρα δεν ξέρω ούτε τι όριο ισχύει»*. Ίδιο δόγμα με τη
   * διάκριση `not-a-member` / `unknown` του ADR-787 Ε-5 §4: **άγνωστο ≠ κενό**.
   */
  'mandate-agreement-invalid',
] as const;

export type MandateInvariant = (typeof MANDATE_INVARIANTS)[number];

/** Τι πρέπει να ισχύει για να γεννηθεί εντολή. **Όλες** οι παραβιάσεις, ποτέ η πρώτη. */
export function mandateInvariantViolations(
  mandate: OwnerPropertyMandate,
  nowISOValue: string,
): MandateInvariant[] {
  if (mandate.kind === 'self') return [];

  const found: MandateInvariant[] = [];
  if (mandate.clientContactId.trim() === '') found.push('mandate-client-missing');

  const expiry = Date.parse(mandate.expiresAt);
  if (Number.isNaN(expiry)) found.push('mandate-expiry-invalid');
  else if (expiry <= Date.parse(nowISOValue)) found.push('mandate-expiry-past');

  // 🔴 **Το νόμιμο ανώτατο μετριέται ΑΠΟ ΤΗ ΣΤΙΓΜΗ ΤΗΣ ΚΡΙΣΗΣ**, γιατί αυτή είναι η
  //    στιγμή που η συμφωνία γράφεται — δηλαδή η αφετηρία της σύμβασης. Δεν υπάρχει
  //    πεδίο «έναρξης» στην εντολή, και **σωστά δεν υπάρχει**: μια εντολή που δεν
  //    έχει ακόμη γραφτεί δεν έχει έναρξη, και μια που γράφτηκε έχει το `createdAt`
  //    της αγγελίας — που είναι **άλλο γεγονός** (η αγγελία προϋπάρχει της εντολής,
  //    ADR-827 §1).
  //
  // ⚠️ Ελέγχεται ΜΟΝΟ όταν η λήξη είναι στο μέλλον: ληγμένη εντολή δίνει αρνητική
  //    διάρκεια και δεν μπορεί να «ξεπερνά» τίποτα. Δύο κωδικοί για το ίδιο πεδίο
  //    ταυτόχρονα είναι θόρυβος, όχι πληροφορία.
  if (!isListingAgreement(mandate.agreement)) {
    found.push('mandate-agreement-invalid');
  } else if (
    !Number.isNaN(expiry) &&
    expiry > Date.parse(nowISOValue) &&
    exceedsStatutoryTerm(mandate.agreement, nowISOValue, mandate.expiresAt)
  ) {
    found.push('mandate-term-exceeds-statute');
  }

  if (mandate.proof.via === AGENCY_ATTESTATION && mandate.confirmation !== 'confirmed') {
    found.push('mandate-attestation-not-confirmed');
  }

  return found;
}

/** Η κατάσταση έγκρισης με την οποία **γεννιέται** μια εντολή, ανά δρόμο απόδειξης. */
export function initialConfirmationFor(via: MandateProofVia): MandateConfirmation {
  return via === AGENCY_ATTESTATION ? 'confirmed' : 'pending';
}
