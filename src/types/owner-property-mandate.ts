/**
 * **Η προεπιλεγμένη λήξη** — το νόμιμο ανώτατο **του συγκεκριμένου είδους** εντολής.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΑΝΤΙΚΑΤΕΣΤΗΣΕ ΤΟ `MANDATE_DEFAULT_DURATION_DAYS = 365`, ΠΟΥ ΗΤΑΝ **ΑΚΥΡΟ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η σταθερά των 365 ημερών ήρθε από την **§3** του άρθρου 200 *(«δώδεκα μήνες»)* και
 * εφαρμοζόταν σε **κάθε** είδος εντολής — μαζί με το `EXCLUSIVE_AGENCY`, που είναι η
 * **προεπιλογή** μας. Αλλά η **§4** του **ίδιου άρθρου** λέει ότι η αποκλειστική
 * *«**δεν μπορεί** να έχει διάρκεια πάνω από **οκτώ (8) μήνες**»*.
 *
 * ⇒ Η φόρμα προσυμπλήρωνε, ως προεπιλογή, **αποκλειστική εντολή δώδεκα μηνών** —
 * δηλαδή όρο που ο νόμος **απαγορεύει**. *Δύο παράγραφοι του ίδιου άρθρου, διαβασμένη
 * η μία* (ADR-827 §8.9 α).
 *
 * 🔑 **Και το παλιό σχόλιο ήταν λάθος, όχι ελλιπές.** Έγραφε *«προεπιλογή, ΟΧΙ όριο·
 * ένα σκληρό πλαφόν θα απαγόρευε νόμιμη συμφωνία που τα δύο μέρη έκαναν»*. Για τη
 * **μη** αποκλειστική ισχύει. Για την αποκλειστική **δεν υπάρχει** νόμιμη δωδεκάμηνη
 * συμφωνία να απαγορευτεί: η ελευθερία των μερών **σταματά** εκεί που ο νόμος λέει
 * «δεν μπορεί».
 *
 * ⚠️ **Δεν είναι σταθερά — είναι ΣΥΝΑΡΤΗΣΗ του είδους**, γιατί το όριο είναι ιδιότητα
 * του είδους (`types/listing-agreement.ts`, ο τόπος που ήδη ξέρει τι σημαίνει
 * «αποκλειστικό»). Δεύτερος τόπος θα ήταν, κατά γράμμα, το σχήμα του **ADR-749**.
 *
 * @param fromISO — η **περασμένη** αφετηρία· ποτέ ρολόι διαβασμένο εδώ μέσα.
 * @returns ISO στιγμή, ή `null` αν η αφετηρία δεν διαβάζεται.
 */
export function defaultExpiryFor(
  agreement: ListingAgreement,
  fromISO: string,
): string | null {
  return addMonthsUTC(fromISO, statutoryTermLimitFor(agreement).maxMonths);
}

/**
 * **Ξεπερνά αυτή η συμφωνία το νόμιμο ανώτατο;**
 *
 * 🔴 **Η ΣΥΓΚΡΙΣΗ ΓΙΝΕΤΑΙ ΣΕ ΗΜΕΡΟΛΟΓΙΑΚΟΥΣ ΜΗΝΕΣ, ΟΧΙ ΣΕ ΗΜΕΡΕΣ.** Ένα
 * `expiresAt - from > 8 * 30 * MS_PER_DAY` θα απέρριπτε **νόμιμες** οκτάμηνες εντολές
 * (οκτώ ημερολογιακοί μήνες είναι 242-245 ημέρες, όχι 240) και θα δεχόταν παράνομες
 * σε άλλες περιόδους. Ο νόμος μετρά **μήνες**· ο έλεγχος οφείλει να μετρά το ίδιο
 * πράγμα με τον νόμο, αλλιώς φυλά **άλλο** όριο από αυτό που επικαλείται.
 *
 * ⚠️ **Ανεκτικό στο `null`**: αφετηρία ή λήξη που δεν διαβάζεται **δεν** είναι
 * υπέρβαση ορίου — είναι **άλλη** παραβίαση, με **δικό της** κωδικό
 * (`mandate-expiry-invalid`). Δύο σφάλματα σε έναν κωδικό θα έστελναν τον άνθρωπο να
 * διορθώσει τη διάρκεια ενός πεδίου που δεν είναι καν ημερομηνία.
 */
export function exceedsStatutoryTerm(
  agreement: ListingAgreement,
  fromISO: string,
  untilISO: string,
): boolean {
  // 🔴 **ΔΕΝ ΕΜΠΙΣΤΕΥΕΤΑΙ ΤΟΝ ΤΥΠΟ, ΚΑΙ ΕΙΝΑΙ ΜΕΤΡΗΜΕΝΟΣ ΚΙΝΔΥΝΟΣ ΠΑΡΑΓΩΓΗΣ.**
  //    Το `agreement` έγινε υποχρεωτικό στη **Φάση Α (2026-08-28)**· κάθε εντολή
  //    γραμμένη **πριν** από εκείνη τη μέρα το έχει `undefined` στο Firestore. Ένα
  //    σκέτο `STATUTORY_TERM_LIMITS[agreement].maxMonths` πετά **TypeError** πάνω σε
  //    τέτοιο έγγραφο — δηλαδή ο φρουρός της νομιμότητας θα **έριχνε** τη διαδρομή
  //    αντί να την κρίνει. Ο τύπος περιγράφει τι **πρέπει** να έρθει· η βάση κρατά
  //    ό,τι **ήρθε**.
  //
  // ⚠️ Η άγνωστη τιμή απαντιέται με `false` **εδώ** και με δικό της κωδικό
  //    (`mandate-agreement-invalid`) στον καλούντα: *άγνωστο ≠ παράβαση ορίου*. Ένα
  //    `true` εδώ θα έλεγε στον μεσίτη «μίκρυνε τη διάρκεια» για εντολή της οποίας
  //    το πρόβλημα είναι ότι **δεν ξέρουμε τι είδους είναι**.
  if (!isListingAgreement(agreement)) return false;

  const latest = defaultExpiryFor(agreement, fromISO);
  const until = Date.parse(untilISO);
  if (latest === null || Number.isNaN(until)) return false;

  // 🔴🔴 **ΤΟ ΟΡΙΟ ΕΙΝΑΙ ΤΟ ΤΕΛΟΣ ΤΗΣ ΗΜΕΡΑΣ, ΚΑΙ ΤΟ ΛΕΕΙ Ο ΝΟΜΟΣ — ΑΚ 243:**
  //    *«προθεσμία σε μήνες λήγει **με την παρέλευση** της ημέρας του τελευταίου μήνα
  //    που αντιστοιχεί κατά αριθμό»*. «Με την παρέλευση **της ημέρας**» = στο τέλος
  //    της, όχι στην ώρα που έτυχε να αρχίσει.
  //
  // 🔴 **ΤΟ ΕΛΑΤΤΩΜΑ ΠΟΥ ΔΙΟΡΘΩΝΕΙ (ADR-827 §9.18, μετρημένο 2026-08-29):** το
  //    `defaultExpiryFor` επιστρέφει **στιγμή** που κουβαλά την **ώρα της αφετηρίας**
  //    (`addMonthsUTC` μετακινεί μόνο τον μήνα). Άρα η προεπιλογή της φόρμας —
  //    `defaultExpiryFor` → `slice(0,10)` → `endOfDay` — κρινόταν **ΠΑΡΑΝΟΜΗ ΑΠΟ ΤΟΝ
  //    ΙΔΙΟ ΤΗΣ ΤΟΝ ΚΡΙΤΗ**: ο μεσίτης άνοιγε τη φόρμα, δεν άγγιζε τίποτα, και έβλεπε
  //    `mandate-term-illegal`. Μετρημένη υπέρβαση σε πραγματικό άνοιγμα:
  //    **32.263.238 ms** — ακριβώς οι ώρες που είχαν περάσει εκείνη τη μέρα.
  //
  // ⚠️ **ΔΕΝ χαλαρώνει το όριο** — το κάνει να λέει αυτό που λέει ο νόμος. Η **μόνη**
  //    ετυμηγορία που αλλάζει είναι για λήξη **μέσα στην τελευταία νόμιμη ημέρα**·
  //    οτιδήποτε πέφτει την **επόμενη** ημέρα εξακολουθεί να ξεπερνά.
  //
  // ⛔ **ΜΗΝ το «λύσεις» κάνοντας το `defaultExpiryFor` να επιστρέφει τέλος ημέρας**:
  //    εκείνο εξυπηρετεί **δύο** ερωτήματα (*«τι προσυμπληρώνω;»* · *«ποιο είναι το
  //    ανώτατο;»*) και μόνο το δεύτερο είναι του νόμου. Ο τεμαχισμός γίνεται **εδώ**,
  //    στον κριτή, με την **ίδια** γραφή που χρησιμοποιεί η φόρμα (ADR-749).
  return until > Date.parse(endOfDay(toDateInputValue(latest)));
}

