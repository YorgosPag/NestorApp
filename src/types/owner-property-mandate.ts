/** Ο ίδιος ο ιδιοκτήτης απάντησε — ο δρόμος που αναγνωρίζει ρητά το άρθρο 200. */
export const OWNER_CONSENT = 'owner-consent';

/** Το γραφείο **βεβαιώνει** υπογεγραμμένη εντολή που κρατά το ίδιο. */
export const AGENCY_ATTESTATION = 'agency-attestation';

/**
 * **Πώς απέκτησε το γραφείο το δικαίωμα να διαφημίσει αυτό το ακίνητο.**
 *
 * 🔴 **Δύο ρητές τιμές, ΠΟΤΕ ένα `boolean` «εγκρίθηκε».** Η απόφαση Giorgio
 * (2026-08-20) ήταν *«και τα δύο, διαλέγει ο μεσίτης»* — και **ακριβώς γι' αυτό** η
 * προέλευση πρέπει να είναι **δεδομένο**: όταν δύο δρόμοι οδηγούν στην ίδια λέξη
 * («εγκεκριμένη») και ο ένας είναι **απόδειξη** ενώ ο άλλος **ισχυρισμός**, μια κοινή
 * τιμή θα έλεγε ψέματα για τον μισό κατάλογο — και θα το έλεγε **σιωπηλά**.
 *
 * 🔑 **Είναι το ίδιο σχήμα που το έργο έχει ήδη αποφασίσει τρεις φορές**: το
 * `provenance` της θέσης (Α5) · η **Α17** (νομιμότητα ως *«κλίμακα με προέλευση»*) ·
 * το `LISTING_AUTHORSHIPS` (*«δηλωμένο, μη επαληθευμένο»*). Δεν επινοείται τέταρτο
 * λεξιλόγιο — **αναγνωρίζεται το ίδιο ερώτημα** σε άλλο γνώρισμα.
 *
 * ⚠️ **Η βεβαίωση ΔΕΝ είναι «χαλαρότερος έλεγχος», είναι ΑΛΛΟΣ ισχυρισμός.** Ο
 * μεσίτης που τη δίνει **ονοματίζεται** ({@link AgencyAttestation.attestedByUserId})
 * και **χρονοσημαίνεται**. Το MLS δεν κρατά ούτε αυτό.
 */
export const MANDATE_PROOF_VIAS = [OWNER_CONSENT, AGENCY_ATTESTATION] as const;

export type MandateProofVia = (typeof MANDATE_PROOF_VIAS)[number];

/**
 * Η βεβαίωση του γραφείου.
 *
 * ⚠️ **Το `documentPath` είναι ΠΡΟΑΙΡΕΤΙΚΟ, και μετρήθηκε γιατί.** Υποχρεωτικό
 * ανέβασμα θα ήταν **αυστηρότερο από κάθε MLS** — και θα σταματούσε νόμιμο μεσίτη
 * στις έντεκα το βράδυ επειδή το σαρωμένο χαρτί είναι στο άλλο γραφείο. Ο φρουρός
 * δεν είναι το αρχείο· είναι ότι **υπάρχει όνομα και ώρα**, και ότι ο ιδιοκτήτης
 * **ειδοποιείται** και μπορεί να πει «όχι» ανά πάσα στιγμή.
 */
export interface AgencyAttestation {
  readonly via: typeof AGENCY_ATTESTATION;
  /** Το uid του υπαλλήλου που **υπογράφει** τη βεβαίωση. Ποτέ `null`. */
  readonly attestedByUserId: string;
  /** ISO — πότε δόθηκε η βεβαίωση. */
  readonly attestedAt: string;
  /** Μονοπάτι του σαρωμένου εγγράφου, όταν υπάρχει. */
  readonly documentPath: string | null;
}

/**
 * **Η απόδειξη**, ως κλειστή ένωση.
 *
 * 🔑 **Τα πεδία της βεβαίωσης ζουν ΜΕΣΑ στο σκέλος της**, όχι δίπλα με `null`. Έτσι
 * «βεβαίωση χωρίς υπογράφοντα» είναι **αδύνατο να εκφραστεί**, όχι «απαγορευμένο από
 * σχόλιο» — η ίδια άμυνα που κάνει το `percentage` πάνω σε πώληση αδύνατο
 * ({@link ../property-offers}).
 */
export type MandateProof = { readonly via: typeof OWNER_CONSENT } | AgencyAttestation;

