/**
 * **Πέρασε η συμβατική λήξη;** `self` ⇒ ποτέ.
 *
 * @param nowISOValue — η **περασμένη** στιγμή, ποτέ `new Date()` εδώ μέσα: ο κριτής
 *   πρέπει να δίνει την ίδια απάντηση σε όλο το πέρασμα προβολής, και ένα ρολόι
 *   διαβασμένο μέσα στη συνάρτηση κάνει το ίδιο πέρασμα να διαφωνεί με τον εαυτό του.
 */
export function isMandateExpired(
  mandate: OwnerPropertyMandate,
  nowISOValue: string,
): boolean {
  if (mandate.kind === 'self') return false;
  return Date.parse(mandate.expiresAt) <= Date.parse(nowISOValue);
}

/**
 * 🔴 **Ο ΕΝΑΣ ΚΡΙΤΗΣ: επιτρέπεται αυτή η αγγελία να φτάσει στον κόσμο;**
 *
 * `true` για τον ιδιώτη πάντα· για το γραφείο **μόνο** όταν ο ιδιοκτήτης έχει πει
 * «ναι» **και** η εντολή δεν έχει λήξει.
 *
 * ⚠️ **ΔΕΝ είναι δεύτερο κριτήριο δημοσίευσης** — και ο τρόπος που καταναλώνεται είναι
 * ο λόγος. Το `owner-property-projection.ts` **δεν** ρωτά «δημοσιεύεται;» (αυτό
 * απαντιέται **μία** φορά, στο `isPubliclyListed`)· λέει την αλήθεια **στη γλώσσα της
 * Α20**: μια αγγελία χωρίς ζωντανή εντολή **δεν έχει καμία διάθεση στην αγορά**. Από
 * εκεί και πέρα ο υπάρχων κώδικας βγάζει μόνος του `unavailable` + `[]` και **σβήνει**
 * την προβολή. Είναι **ακριβώς** ο μηχανισμός που χρησιμοποιεί ήδη η απόσυρση.
 *
 * 🔑 Γι' αυτό η **λήξη δεν χρειάζεται δικό της μηχανισμό εξαφάνισης**: την επόμενη
 * φορά που η αγγελία συντίθεται, φεύγει μόνη της. Το μόνο που μένει είναι **κάποιος
 * να σκανδαλίσει** τη σύνθεση — δουλειά ενός περάσματος, όχι νέας αρχής.
 */
export function mandateAllowsPublication(
  mandate: OwnerPropertyMandate,
  nowISOValue: string,
): boolean {
  return isMandateAttributable(mandate) && !isMandateExpired(mandate, nowISOValue);
}

/**
 * Οι παραβιάσεις της εντολής, ως **κλειστό σύνολο κωδικών** — ίδιο ιδίωμα με τα
 * `OWNER_PROPERTY_INVARIANTS`: κωδικός εδώ, μήνυμα στα locale (N.11).
 */
export const MANDATE_INVARIANTS = [
  /** Εντολή χωρίς πελάτη: το γραφείο δεν λέει **για ποιον** γράφει. */
  'mandate-client-missing',
  /** Λήξη που λείπει ή δεν είναι αναγνώσιμη ημερομηνία. */
  'mandate-expiry-invalid',
  /**
   * Λήξη **στο παρελθόν** τη στιγμή της καταχώρησης.
   *
   * 🔑 Ξεχωριστός κωδικός από το `mandate-expiry-invalid` επίτηδες: «δεν είναι
   * ημερομηνία» και «είναι χθες» έχουν **διαφορετική θεραπεία** στην οθόνη, και ένας
   * κοινός κωδικός θα έλεγε στον άνθρωπο να διορθώσει τη μορφή ενός σωστά
   * μορφοποιημένου πεδίου.
   */
  'mandate-expiry-past',
  /**
   * **Βεβαίωση γραφείου χωρίς έγκριση.**
   *
   * ⚠️ Η βεβαίωση **είναι** ο ισχυρισμός ότι η εντολή υπάρχει ήδη υπογεγραμμένη —
   * οπότε μια βεβαίωση που γεννιέται `pending` δεν βεβαιώνει τίποτα. Η μόνη νόμιμη
   * μετάβαση από εκεί είναι προς τα **κάτω** (ο ιδιοκτήτης αντιλέγει ⇒ `declined`).
   */
  'mandate-attestation-not-confirmed',
] as const;

export type MandateInvariant = (typeof MANDATE_INVARIANTS)[number];

/** Τι πρέπει να ισχύει για να γεννηθεί εντολή. **Όλες** οι παραβιάσεις, ποτέ η πρώτη. */
export function mandateInvariantViolations(
  mandate: OwnerPropertyMandate,
  nowISOValue: string,
): MandateInvariant[] {
  if (mandate.kind === 'self') return [];

  const found: MandateInvariant[] = [];
  if (mandate.clientContactId.trim() === '') found.push('mandate-client-missing');

  const expiry = Date.parse(mandate.expiresAt);
  if (Number.isNaN(expiry)) found.push('mandate-expiry-invalid');
  else if (expiry <= Date.parse(nowISOValue)) found.push('mandate-expiry-past');

  if (mandate.proof.via === AGENCY_ATTESTATION && mandate.confirmation !== 'confirmed') {
    found.push('mandate-attestation-not-confirmed');
  }

  return found;
}

/** Η κατάσταση έγκρισης με την οποία **γεννιέται** μια εντολή, ανά δρόμο απόδειξης. */
export function initialConfirmationFor(via: MandateProofVia): MandateConfirmation {
  return via === AGENCY_ATTESTATION ? 'confirmed' : 'pending';
}
