/** **Έφυγε.** Το μήνυμα μπήκε στην ουρά με διεύθυνση παραλήπτη. */
export const NOTIFY_SENT = 'sent';

/** **Η επαφή δεν έχει email.** Κατάσταση του κόσμου, όχι σφάλμα μας. */
export const NOTIFY_NO_ADDRESS = 'no-address';

/** **Ο γραφέας απέτυχε.** Δικό μας πρόβλημα — τα δεδομένα της επαφής είναι εντάξει. */
export const NOTIFY_FAILED = 'failed';

/**
 * Οι **τρεις** εκβάσεις μιας απόπειρας ειδοποίησης — κλειστό σύνολο.
 *
 * ⚠️ **Η σειρά ΔΕΝ είναι συμβόλαιο εδώ** (σε αντίθεση με τα `MANDATE_STANDINGS`, όπου
 * είναι ταξινόμηση τριάζ). Εδώ είναι απλή απαρίθμηση για τον αναγνωριστή τύπου.
 */
export const MANDATE_NOTIFY_OUTCOMES = [NOTIFY_SENT, NOTIFY_NO_ADDRESS, NOTIFY_FAILED] as const;

/**
 * 🔴 **ΤΟ ΛΕΞΙΛΟΓΙΟ ΤΗΣ ΕΚΒΑΣΗΣ ΖΕΙ ΕΔΩ, ΚΑΙ ΟΧΙ ΣΤΟΝ ΓΡΑΦΕΑ** (ADR-834 §6.5.δ).
 *
 * Το `NotifyOutcome` του `mandate-invitation.service` είναι **η απάντηση της στιγμής**
 * — διακριτή ένωση με `to` πάνω στο `sent`, και ζει σε `server-only` module. Αυτό εδώ
 * είναι **το γεγονός που αποθηκεύεται και που διαβάζει η οθόνη**. Δύο διαφορετικά
 * πράγματα, **ένα** λεξιλόγιο: ο γραφέας **εισάγει** αυτές τις σταθερές αντί να
 * ξαναγράψει τα τρία αλφαριθμητικά — αλλιώς μια τέταρτη έκβαση θα γεννιόταν στη μία
 * πλευρά και η άλλη δεν θα το μάθαινε ποτέ (N.12 · N.18).
 *
 * ⛔ **ΜΗΝ το κάνεις να ζει στο `server-only`**: η οθόνη του καταλόγου πρέπει να το
 * διαβάσει, και ένα `import type` από απαγορευμένο αρχείο «δουλεύει» (ο τύπος
 * σβήνεται) αλλά **δηλώνει λάθος πράγμα για το ποιος ανήκει πού** — το ίδιο σκεπτικό
 * που έβγαλε το `MandateActionRejection` από τον `mandate-actions.service`.
 */
export type MandateNotifyOutcome = (typeof MANDATE_NOTIFY_OUTCOMES)[number];

/**
 * **Είναι αυτό καταγεγραμμένη έκβαση;** — ο φρουρός ανάμεσα στη βάση και τον τύπο.
 *
 * 🔴 **Υπάρχει επειδή το Firestore δεν ξέρει τους τύπους μας.** Κάθε εντολή γραμμένη
 * πριν από το §6.5.δ **δεν έχει καθόλου** το πεδίο, και μια χαλασμένη μπορεί να έχει
 * ό,τι να 'ναι. Ένας ισχυρισμός `as MandateNotifyOutcome` θα έλεγε στην οθόνη
 * *«η επαφή δεν είχε email»* για τιμή που **κανείς δεν έγραψε**.
 */
export function isMandateNotifyOutcome(value: unknown): value is MandateNotifyOutcome {
  return (
    typeof value === 'string' &&
    (MANDATE_NOTIFY_OUTCOMES as readonly string[]).includes(value)
  );
}

