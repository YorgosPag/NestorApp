/**
 * **Είναι αυτό παραβίαση εντολής που ξέρουμε;** — ο φρουρός του συνόρου (ADR-834 §6.5.ε).
 *
 * 🔴 **Ξεχωριστός από τον {@link isOwnerPropertyInvariant}, και ο λόγος είναι μετρημένος**:
 * το `_shared/respond.ts` στέλνει το **ίδιο** πεδίο `violations` για **δύο** λεξιλόγια —
 * `INVALID_LISTING` (παραβιάσεις **αγγελίας**) και `INVALID_MANDATE` (παραβιάσεις
 * **εντολής**). Ένας κοινός φρουρός θα δεχόταν κωδικό εντολής εκεί που η οθόνη περιμένει
 * κωδικό αγγελίας — **σωστά δεδομένα, λάθος θεραπεία**.
 */
export function isMandateInvariant(value: unknown): value is MandateInvariant {
  return (
    typeof value === 'string' && (MANDATE_INVARIANTS as readonly string[]).includes(value)
  );
}

/** Τι πρέπει να ισχύει για να γεννηθεί εντολή. **Όλες** οι παραβιάσεις, ποτέ η πρώτη. */
export function mandateInvariantViolations(
  mandate: OwnerPropertyMandate,
  nowISOValue: string,
): MandateInvariant[] {
  if (mandate.kind === 'self') return [];

  const found: MandateInvariant[] = [];
  if (mandate.clientContactId.trim() === '') found.push('mandate-client-missing');

  const expiry = Date.parse(mandate.expiresAt);
  if (Number.isNaN(expiry)) found.push('mandate-expiry-invalid');
  else if (expiry <= Date.parse(nowISOValue)) found.push('mandate-expiry-past');

  // 🔴 **ΤΟ ΣΧΗΜΑ ΤΟΥ ΔΙΑΣΤΗΜΑΤΟΣ** (ADR-832 · ADR-835 Ε-10). Έναρξη που δεν
  //    διαβάζεται — ή που βρίσκεται **μετά** τη λήξη — δεν περιγράφει διάστημα· και ο
  //    κριτής σύγκρουσης απαντά `undetermined` σε τέτοιο δεδομένο αντί να το κρίνει
  //    σιωπηλά. Καλύτερα να μη γεννηθεί καθόλου.
  //
  // 🔴 **ΤΟ `empty` ΕΧΕΙ ΔΙΚΟ ΤΟΥ ΚΩΔΙΚΑ, ΚΑΙ ΕΙΝΑΙ ΕΥΡΗΜΑ ΤΗΣ ΦΑΣΗΣ Φ2 (ADR-835
  //    §16.3β)**: ως 2026-08-31 ο έλεγχος ήταν `expiry < start` — **αυστηρός** — άρα
  //    εντολή που **αρχίζει και λήγει την ίδια στιγμή** περνούσε ως έγκυρη. Είναι
  //    αποκλειστικότητα που **δεν καλύπτει καμία μέρα**: αποθηκευόταν, εμφανιζόταν
  //    «ενεργή», και δεν εμπόδιζε κανέναν. Ξεχωριστός κωδικός γιατί η **θεραπεία**
  //    είναι άλλη — *«πρόσθεσε διάρκεια»*, όχι *«αντίστρεψε τα άκρα»*.
  //
  // ⚠️ `switch` **χωρίς `default`**: κλειστό σύνολο, ώστε πέμπτο σχήμα να μη
  //    μεταγλωττίζεται μέχρι κάποιος να απαντήσει «και αυτό;».
  const termShape = intervalShape(mandate.startsAt, mandate.expiresAt);
  switch (termShape) {
    case 'proper':
      break;
    case 'empty':
      found.push('mandate-term-empty');
      break;
    case 'reversed':
      found.push('mandate-start-invalid');
      break;
    case 'unreadable':
      // ⚠️ **Μη αναγνώσιμη ΛΗΞΗ έχει ήδη τον δικό της κωδικό** δύο γραμμές πάνω. Εδώ
      //    κατηγορούμε την **έναρξη** μόνο όταν φταίει εκείνη — αλλιώς ένα χαλασμένο
      //    πεδίο θα παρήγαγε **δύο** κατηγορίες και ο άνθρωπος θα κυνηγούσε λάθος
      //    πεδίο. Το `null` ρωτά **μόνο** για την αρχή (ανοιχτό τέλος = έγκυρο).
      if (intervalShape(mandate.startsAt, null) === 'unreadable') {
        found.push('mandate-start-invalid');
      }
      break;
  }

  // ⚠️ **Κενό `scope` = εντολή για καμία πράξη.** Δες τον κωδικό για το γιατί δεν
  //    ισοπεδώνεται σε «όλες».
  if (mandate.scope.length === 0) found.push('mandate-scope-empty');

  // 🔴 **ΤΟ ΝΟΜΙΜΟ ΑΝΩΤΑΤΟ ΜΕΤΡΙΕΤΑΙ ΑΠΟ ΤΗΝ ΕΝΑΡΞΗ ΤΗΣ ΕΝΤΟΛΗΣ** — και ως τις
  //    2026-08-30 μετριόταν από τη **στιγμή της κρίσης**. Τότε ήταν σωστό: η εντολή
  //    γεννιόταν πάντα ενεργή, οπότε «τώρα» **ήταν** η αφετηρία της σύμβασης.
  //
  // ⚠️ **Με ΠΡΟΓΡΑΜΜΑΤΙΣΜΕΝΗ εντολή παύει να είναι**, και το λάθος θα ήταν σιωπηλό:
  //    οκτάμηνη αποκλειστική που αρχίζει σε έξι μήνες μετριέται από «τώρα» ως
  //    **δεκατετράμηνη** και απορρίπτεται — δηλαδή ο φρουρός του νόμου θα εμπόδιζε
  //    απολύτως **νόμιμη** συμφωνία. Ο νόμος μετρά τη **διάρκεια της σύμβασης**, όχι
  //    την απόσταση από σήμερα.
  //
  // ⚠️ Ελέγχεται ΜΟΝΟ όταν η λήξη είναι στο μέλλον και η έναρξη διαβάζεται: ληγμένη ή
  //    ανάποδη εντολή έχει **δικό της** κωδικό. Δύο κωδικοί για το ίδιο πεδίο
  //    ταυτόχρονα είναι θόρυβος, όχι πληροφορία.
  if (!isListingAgreement(mandate.agreement)) {
    found.push('mandate-agreement-invalid');
  } else if (
    // 🔑 **Μόνο σε ΓΝΗΣΙΟ διάστημα** — ένα όνομα αντί για τρεις χειρόγραφους ελέγχους
    //    (`!isNaN(expiry) && !isNaN(start) && expiry >= start`). Ταυτόσημη σημασία:
    //    μηδενική διάρκεια **ποτέ** δεν ξεπερνά όριο, και έχει ήδη δικό της κωδικό.
    termShape === 'proper' &&
    expiry > Date.parse(nowISOValue) &&
    exceedsStatutoryTerm(mandate.agreement, mandate.startsAt, mandate.expiresAt)
  ) {
    found.push('mandate-term-exceeds-statute');
  }

  if (mandate.proof.via === AGENCY_ATTESTATION && mandate.confirmation !== 'confirmed') {
    found.push('mandate-attestation-not-confirmed');
  }

  return found;
}

/** Η κατάσταση έγκρισης με την οποία **γεννιέται** μια εντολή, ανά δρόμο απόδειξης. */
/**
 * **ΑΛΛΑΞΕ Η ΣΥΜΦΩΝΙΑ**, ή απλώς αγγίχθηκε το έγγραφο;
 *
 * Η συμφωνία είναι το ζεύγος *(τι είδους εντολή, μέχρι πότε)* — τα **δύο** πεδία που ο
 * νόμος δένει μεταξύ τους (άρθρο 200 §3/§4: το ανώτατο **εξαρτάται** από το είδος).
 *
 * 🔑 **Η μετάβαση `self → brokered` μετράει ως αλλαγή**: όταν το προηγούμενο σκέλος
 * είναι `self`, **δεν υπάρχει** προηγούμενη συμφωνία — άρα ό,τι γράφεται είναι **νέα**
 * σύμβαση εξ ορισμού. Αυτή είναι ακριβώς η διαδρομή της Φάσης Β (ADR-827 §7 Φ.Β).
 *
 * ⚠️ **Η αντίστροφη μετάβαση (`brokered → self`) ΔΕΝ κρίνεται**: είναι **ανάκληση**,
 * και το σκέλος `self` δεν έχει όρους να παραβιάσει. Μια κρίση εκεί θα εμπόδιζε τον
 * ιδιοκτήτη να **βγει**.
 */
export function mandateTermsChanged(
  before: OwnerPropertyMandate,
  after: OwnerPropertyMandate,
): boolean {
  if (after.kind === 'self') return false;
  if (before.kind === 'self') return true;
  return before.agreement !== after.agreement || before.expiresAt !== after.expiresAt;
}

/**
 * **ΤΙ ΕΙΝΑΙ ΛΑΘΟΣ ΣΕ ΑΥΤΗ ΤΗ ΜΕΤΑΒΑΣΗ ΕΝΤΟΛΗΣ;** — κενός πίνακας σημαίνει «τίποτα».
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΕΞΗΧΘΗ ΕΠΕΙΔΗ Ο ΔΕΥΤΕΡΟΣ ΚΑΛΩΝ ΔΕΝ ΧΩΡΑΕΙ ΣΤΟΝ ΠΡΩΤΟ (ADR-827 §9.21)
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο δηλωμένος **μοναδικός γραφέας** της εντολής (`setOwnerPropertyMandate`) δέχεται
 * `adminDb` και κάνει **τη δική του ανάγνωση** — άρα **δεν καλείται από μέσα σε
 * συναλλαγή**. Και η αποδοχή του Σ3 *πρέπει* να είναι συναλλαγή: γεννά επαφή, γράφει
 * εντολή και κλείνει αίτημα σε **μία** ατομική πράξη.
 *
 * ⛔ **Η ΛΑΘΟΣ ΘΕΡΑΠΕΙΑ ΘΑ ΗΤΑΝ ΔΕΥΤΕΡΟΣ ΓΡΑΦΕΑΣ** (ADR-749): δύο μηχανές που γράφουν
 * το ίδιο πεδίο, με τη μία να κρίνει και την άλλη όχι — δηλαδή ένα
 * `mandate-term-exceeds-statute` που ισχύει **στη μία από τις δύο διαδρομές**, που
 * είναι κατά γράμμα ο *αδρανής φρουρός* του §5.
 *
 * ✅ **Η ΣΩΣΤΗ ΕΙΝΑΙ ΝΑ ΦΥΓΕΙ Ο ΚΡΙΤΗΣ ΑΠΟ ΤΟΝ ΓΡΑΦΕΑ.** Εδώ είναι **καθαρός**: καμία
 * ανάγνωση, κανένα ρολόι δικό του. Τον καλούν **και οι δύο** — ο υπάρχων γραφέας
 * **και** η συναλλαγή της αποδοχής — και δεν μπορούν να αποκλίνουν.
 *
 * 🔑 **ΚΡΙΝΕΤΑΙ Ο,ΤΙ ΑΛΛΑΖΕΙ, ΟΧΙ Ο,ΤΙ ΓΡΑΦΕΤΑΙ**, και η διαφορά είναι λειτουργική: ο
 * σαρωτής λήξης ξαναγράφει την **ίδια** εντολή για να ανανεώσει τη δημόσια προβολή
 * μιας **ληγμένης** αγγελίας. Αν κρίναμε κάθε γραφή, θα κοκκίνιζε στο
 * `mandate-expiry-past` και οι ληγμένες αγγελίες θα **έμεναν δημοσιευμένες** —
 * χειρότερο από το πρόβλημα που λύνουμε.
 */
export function mandateTransitionViolations(
  before: OwnerPropertyMandate,
  after: OwnerPropertyMandate,
  nowISOValue: string,
): readonly MandateInvariant[] {
  if (!mandateTermsChanged(before, after)) return [];
  return mandateInvariantViolations(after, nowISOValue);
}

/**
 * **Η ΕΤΥΜΗΓΟΡΙΑ ΤΗΣ ΓΡΑΦΗΣ** — παραβιάσεις **και** συγκρούσεις, μαζί (ADR-832).
 *
 * 🔑 **Δύο σύνολα και όχι ένα, γιατί είναι δύο ειδών πληροφορία.** Οι `violations`
 * είναι **κωδικοί** που γίνονται κλειδιά i18n (N.11)· οι `conflicts` είναι
 * **δεδομένα** — ποιο γραφείο, ποια πράξη, ως πότε — που η οθόνη χρειάζεται για να
 * πει *«ο Χ κρατά αποκλειστική πώλησης ως τις 12/03»* αντί για «δεν γίνεται».
 * Χωμένα σε έναν πίνακα κωδικών, το «ποιος» θα χανόταν.
 */
export interface MandateWriteVerdict {
  readonly violations: readonly MandateInvariant[];
  readonly conflicts: readonly MandateConflict[];
}

/** Άλλαξαν οι όροι που **δεσμεύουν** — δες {@link mandateTermsChanged} για το γιατί. */
function occupancyTermsChanged(
  before: BrokeredListingMandate | null,
  after: BrokeredListingMandate,
): boolean {
  if (before === null) return true;
  return (
    before.agreement !== after.agreement ||
    before.expiresAt !== after.expiresAt ||
    before.startsAt !== after.startsAt ||
    before.scope.length !== after.scope.length ||
    !before.scope.every((kind) => after.scope.includes(kind))
  );
}

/**
 * **ΜΠΟΡΕΙ ΝΑ ΓΡΑΦΤΕΙ ΑΥΤΗ Η ΕΝΤΟΛΗ, ΔΙΠΛΑ ΣΕ ΕΚΕΙΝΕΣ;**
 *
 * Ο **ΕΝΑΣ** κριτής της γραφής: τον καλούν και ο γραφέας (`setOwnerPropertyMandate`)
 * και η **συναλλαγή της αποδοχής**, ώστε να μην μπορούν να αποκλίνουν — ίδιο σκεπτικό
 * και ίδια ιστορία με το {@link mandateTransitionViolations} (ADR-827 §9.21).
 *
 * @param candidate — η εντολή που γράφεται.
 * @param existing — **όλες** οι αποθηκευμένες εντολές της αγγελίας, αφιλτράριστες. Η
 *   επιλογή «ποιες μετρούν» γίνεται **εδώ** ({@link isMandateLive}), όχι στον καλούντα:
 *   δύο τόποι που αποφασίζουν «ζωντανή» θα απέκλιναν στην πρώτη ανάκληση.
 *
 * 🔑 **ΚΡΙΝΕΤΑΙ Ο,ΤΙ ΑΛΛΑΖΕΙ.** Ο σαρωτής λήξης ξαναγράφει **ληγμένες** εντολές
 * αυτούσιες για να ανανεώσει την προβολή· αν κρίναμε κάθε γραφή θα κοκκίνιζε στο
 * `mandate-expiry-past` και οι ληγμένες αγγελίες θα **έμεναν δημοσιευμένες**.
 *
 * ⚠️ **Η προηγούμενη εντολή ΤΟΥ ΙΔΙΟΥ γραφείου δεν είναι αντίπαλος** — είναι ο εαυτός
 * της υπό νέους όρους. Το `mandateConflicts` το γνωρίζει και την αγνοεί· εδώ
 * χρησιμοποιείται μόνο για να απαντηθεί *«άλλαξε κάτι;»*.
 */
export function mandateWriteVerdict(
  candidate: BrokeredListingMandate,
  existing: readonly BrokeredListingMandate[],
  nowISOValue: string,
): MandateWriteVerdict {
  const previous =
    existing.find((mandate) => mandate.agencyCompanyId === candidate.agencyCompanyId) ?? null;

  if (!occupancyTermsChanged(previous, candidate)) {
    return { violations: [], conflicts: [] };
  }

  const violations = [...mandateInvariantViolations(candidate, nowISOValue)];

  // ⚠️ Ο έλεγχος σύγκρουσης τρέχει **ακόμη κι όταν** υπάρχουν παραβιάσεις: ο άνθρωπος
  //    που έγραψε λάθος ημερομηνία **και** συγκρούεται με άλλο γραφείο πρέπει να τα
  //    μάθει **και τα δύο** — αλλιώς διορθώνει το ένα και συναντά το επόμενο.
  // ⚠️ **`bindingMandates`, ΠΟΤΕ `activeMandates`** — δες εκεί για τους δύο λόγους:
  //    ο χρόνος ανήκει στον κριτή (διπλό φίλτρο = ADR-749), και το χρονικό φίλτρο
  //    έκρυβε τις χαλασμένες εντολές αντί να τις καταγγείλει (N.12).
  const verdict = mandateConflicts(
    occupancyOf(candidate),
    bindingMandates(existing).map(occupancyOf),
  );

  if (verdict.kind === 'conflicts') {
    violations.push('mandate-conflicts-existing');
    return { violations, conflicts: verdict.conflicts };
  }
  if (verdict.kind === 'undetermined') {
    violations.push('mandate-conflict-undetermined');
  }

  return { violations, conflicts: [] };
}

export function initialConfirmationFor(via: MandateProofVia): MandateConfirmation {
  return via === AGENCY_ATTESTATION ? 'confirmed' : 'pending';
}
