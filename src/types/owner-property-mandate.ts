/** Η εντολή προς το γραφείο, με ό,τι της λείπει από τον κοινό πυρήνα. */
export interface BrokeredListingMandate extends BrokeredMandateCore {
  readonly kind: 'brokered';
  readonly proof: MandateProof;
  /**
   * ISO — **πότε μίλησε ο άνθρωπος**, όποιον δρόμο κι αν πήρε η απάντηση.
   *
   * ⚠️ **Δεν είναι το `attestedAt`.** Εκείνο λέει πότε το **γραφείο** ισχυρίστηκε·
   * αυτό πότε ο **ιδιοκτήτης** αποφάσισε. Στη βεβαίωση τα δύο είναι διαφορετικά και
   * το δεύτερο μένει `null` — που είναι **η αλήθεια**, όχι έλλειψη.
   */
  readonly decidedAt: string | null;
  /**
   * ISO — πότε **του το είπαμε**. `null` = δεν στάλθηκε ποτέ μήνυμα.
   *
   * 🔴 **Είναι το πεδίο που μας ξεχωρίζει από κάθε MLS, και πρέπει να μπορεί να είναι
   * `null`.** Μια επαφή μπορεί να μην έχει καθόλου email. Ένα `notifiedAt` που
   * γεννιόταν πάντα γεμάτο θα έλεγε *«τον ειδοποιήσαμε»* για ανθρώπους που **δεν
   * ειδοποιήθηκαν** — και θα το έλεγε με ημερομηνία, δηλαδή πειστικά.
   */
  readonly notifiedAt: string | null;
  /**
   * ISO — πότε **άνοιξε ο ίδιος τον σύνδεσμο**. `null` = δεν τον άνοιξε ποτέ.
   *
   * 🔑 **Είναι το `delivered` του DocuSign, και ήταν το ΜΟΝΟ βήμα που μας έλειπε.** Η
   * τεκμηρίωσή του το ορίζει κατά λέξη: *«Delivered means that all recipients have
   * viewed the documents, meaning they **clicked on the link** to access the documents,
   * but did not sign them»*. Χωρίς αυτό, «του στείλαμε και σιωπά» και «το διάβασε και
   * το σκέφτεται» είναι **η ίδια γραμμή** στον κατάλογο — και είναι δύο εντελώς
   * διαφορετικά τηλεφωνήματα.
   *
   * 🏆 **Μαζί με το {@link notifiedAt} φτιάχνουν χωνί ΤΡΙΩΝ βημάτων που κανείς δεν
   * έχει ολόκληρο**: *του το είπαμε;* → *το άνοιξε;* → *απάντησε;*. Το DocuSign έχει
   * τα δύο τελευταία και **δομικά δεν μπορεί** να έχει το πρώτο (φάκελος χωρίς
   * διεύθυνση παραλήπτη **δεν γεννιέται**)· το MLS δεν έχει κανένα, γιατί δεν
   * παρακολουθεί καθόλου την έγκριση του ιδιοκτήτη.
   *
   * ⚠️ **Γράφεται ΜΙΑ φορά — «πότε το είδε ΠΡΩΤΗ φορά», όχι «πότε το είδε τελευταία».**
   * Η πρώτη ματιά είναι το γεγονός που αλλάζει την ερμηνεία της σιωπής· η δέκατη δεν
   * προσθέτει τίποτα και θα έκανε κάθε φόρτωση σελίδας **εγγραφή στη βάση**.
   */
  readonly viewedAt: string | null;
  /**
   * Η ταυτότητα του **ζωντανού συνδέσμου συγκατάθεσης**. `null` = κανένας σύνδεσμος
   * δεν ισχύει αυτή τη στιγμή.
   *
   * 🔴 **ΕΔΩ ΖΕΙ Η ΑΝΑΚΛΗΣΗ, ΚΑΙ ΓΙ' ΑΥΤΟ ΔΕΝ ΧΡΕΙΑΣΤΗΚΕ ΣΥΛΛΟΓΗ.** Η πύλη
   * προμηθευτή κρατά τα ακυρωμένα `nonce` σε **δεύτερη συλλογή**
   * (`vendor_invite_tokens`) — δηλαδή δεύτερο βιβλίο που πρέπει να συμφωνεί με το
   * πρώτο. Εδώ η **κατάσταση που αποφασίζει είναι η κατάσταση που απαντά**: ο
   * σύνδεσμος ισχύει όσο το `nonce` του **είναι** αυτό που γράφει η εντολή. Νέα
   * αποστολή γράφει νέο· ανάκληση γράφει `null`. Καμία απόκλιση δυνατή, γιατί δεν
   * υπάρχει δεύτερο βιβλίο (ADR-749).
   *
   * ⚠️ **Δεν είναι μυστικό που προστατεύει από πλαστογραφία** — αυτό το κάνει η
   * υπογραφή. Είναι **η ταυτότητα της συγκεκριμένης πρόσκλησης**, ώστε ένας παλιός
   * σύνδεσμος να μη μιλά για λογαριασμό μιας πρόσκλησης που αντικαταστάθηκε.
   */
  readonly consentNonce: string | null;
  /**
   * ISO — **η συμβατική λήξη** της εντολής. Το `ExpirationDate` του RESO.
   *
   * ⚠️ **Είναι ημερομηνία ΣΥΜΦΩΝΙΑΣ, όχι ρολόι συστήματος** (RESO, κατά λέξη). Δεν
   * ενημερώνεται όταν κάποιος πατήσει «αποθήκευση»· αλλάζει **μόνο** όταν αλλάξει η
   * συμφωνία.
   */
  readonly expiresAt: string;
}

/**
 * **Ποιανού είναι η αγγελία.**
 *
 * ⚠️ Το σκέλος `self` **δεν έχει κανένα πεδίο**, και είναι σκόπιμο: ο ιδιώτης που
 * γράφει το δικό του σπίτι δεν δίνει εντολή σε κανέναν, δεν εγκρίνει τίποτα και δεν
 * λήγει ποτέ. Πεδία γεμάτα `null` για τη μισή συλλογή θα ήταν φρουροί που **δεν
 * μπορούν να πυροδοτήσουν**.
 */
export type OwnerPropertyMandate = { readonly kind: 'self' } | BrokeredListingMandate;

