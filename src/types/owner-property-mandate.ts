/** Η εντολή προς το γραφείο, με ό,τι της λείπει από τον κοινό πυρήνα. */
export interface BrokeredListingMandate extends BrokeredMandateCore {
  readonly kind: 'brokered';
  readonly proof: MandateProof;
  /**
   * **Τι είδους εντολή** — το `ListingAgreement` του RESO (ADR-827 §3.1).
   *
   * 🔑 **Υποχρεωτικό, ΟΧΙ προαιρετικό**, και το κόστος μετρήθηκε πριν αποφασιστεί:
   * **0** εντολές `brokered` στη ζωντανή βάση ⇒ **καμία** μετανάστευση. Ένα `?:` εδώ
   * θα σήμαινε **σιωπηλή προεπιλογή** — δηλαδή ο ιδιοκτήτης να δεσμεύεται σε όρο που
   * κανείς δεν του έδειξε, στο ακριβώς αντίθετο πνεύμα από το `MandateProof`.
   *
   * ⚠️ Το ερώτημα «μπορεί να δώσει και σε **δεύτερο** γραφείο;» το απαντά το
   * `allowsOtherAgencies`, όχι η ανάγνωση αυτού του πεδίου με το χέρι.
   */
  readonly agreement: ListingAgreement;
  /**
   * **Οι όροι αμοιβής.** Δες {@link MandateCompensation} για το γιατί ζει εδώ και
   * **ποτέ** στη δημόσια προβολή.
   */
  readonly compensation: MandateCompensation;
  /**
   * ISO — **πότε μίλησε ο άνθρωπος**, όποιον δρόμο κι αν πήρε η απάντηση.
   *
   * ⚠️ **Δεν είναι το `attestedAt`.** Εκείνο λέει πότε το **γραφείο** ισχυρίστηκε·
   * αυτό πότε ο **ιδιοκτήτης** αποφάσισε. Στη βεβαίωση τα δύο είναι διαφορετικά και
   * το δεύτερο μένει `null` — που είναι **η αλήθεια**, όχι έλλειψη.
   */
  readonly decidedAt: string | null;
  /**
   * ISO — πότε **του το είπαμε**. `null` = δεν στάλθηκε ποτέ μήνυμα.
   *
   * 🔴 **Είναι το πεδίο που μας ξεχωρίζει από κάθε MLS, και πρέπει να μπορεί να είναι
   * `null`.** Μια επαφή μπορεί να μην έχει καθόλου email. Ένα `notifiedAt` που
   * γεννιόταν πάντα γεμάτο θα έλεγε *«τον ειδοποιήσαμε»* για ανθρώπους που **δεν
   * ειδοποιήθηκαν** — και θα το έλεγε με ημερομηνία, δηλαδή πειστικά.
   */
  readonly notifiedAt: string | null;
  /**
   * 🔴 **ΠΩΣ ΠΗΓΕ Η ΤΕΛΕΥΤΑΙΑ ΑΠΟΠΕΙΡΑ ΕΙΔΟΠΟΙΗΣΗΣ** — `null` = **καμία δεν
   * καταγράφηκε** (ADR-834 §6.5.δ).
   *
   * ────────────────────────────────────────────────────────────────────────
   * 🔑 ΓΙΑΤΙ ΥΠΑΡΧΕΙ: ΕΝΑ BIT ΓΙΑ ΤΡΕΙΣ ΚΟΣΜΟΥΣ
   * ────────────────────────────────────────────────────────────────────────
   *
   * Ο γραφέας επιστρέφει **τρεις ονομαστικές** εκβάσεις ({@link MandateNotifyOutcome})
   * και ως το §6.5.δ **καμία δεν αποθηκευόταν**: στη βάση έμενε **ένα bit** —
   * {@link notifiedAt} `=== null` — για *«η επαφή δεν έχει email»*, *«ο γραφέας
   * απέτυχε»* και *«δεν προσπαθήσαμε ποτέ»*. Η οθόνη **υποχρεωνόταν** να μαντέψει,
   * μάντεψε τον έναν, και έστελνε τον μεσίτη να διορθώσει **σωστά δεδομένα**
   * (μετρημένο ζωντανά 2026-08-31, §6.5.α #14).
   *
   * 🏆 **Το πρότυπο το λέει ρητά**: το DocuSign δεν κρατά μόνο `status:
   * 'autoresponded'` — κρατά και `autoRespondedReason` *(«The email account that you
   * tried to reach does not exist»)*. **Ονομασμένη έκβαση + αιτία, πάνω στον
   * παραλήπτη.** Εδώ η αιτία **είναι** η ονομασμένη έκβαση, γιατί το κλειστό σύνολο
   * των τριών την εξαντλεί.
   *
   * ⚠️ **ΔΕΝ αντικαθιστά το {@link notifiedAt}, ούτε το επικαλύπτει.** Εκείνο λέει
   * *«πότε»*· αυτό λέει *«πώς πήγε»*. Γράφονται στην **ΙΔΙΑ** γραφή — ίδιο δόγμα με
   * το `consentNonce`: *«η κατάσταση που αποφασίζει είναι η κατάσταση που απαντά»*.
   *
   * ⚠️ **`null` ΕΙΝΑΙ ΤΡΙΤΗ ΚΑΤΑΣΤΑΣΗ, ΟΧΙ ΣΙΩΠΗΛΗ ΠΡΟΕΠΙΛΟΓΗ.** Το διαβάζουν δύο
   * νόμιμοι κόσμοι: εντολή γραμμένη **πριν** από αυτό το πεδίο, και εντολή που
   * γεννήθηκε **χωρίς να επιχειρηθεί** ειδοποίηση (η αποδοχή αιτήματος του Σ3). Και
   * στους δύο η αλήθεια είναι *«δεν ξέρουμε γιατί»* — ίδιο μάθημα με το
   * `undetermined` του κριτή κατάληψης: **άγνωστο ≠ κενό**.
   *
   * 🔑 **Διαβάζεται ΜΟΝΟ μέσω {@link notifyOutcomeOf}** — ο τύπος λέει
   * `MandateNotifyOutcome | null`, το Firestore λέει «λείπει».
   */
  readonly notifyOutcome: MandateNotifyOutcome | null;
  /**
   * ISO — πότε **άνοιξε ο ίδιος τον σύνδεσμο**. `null` = δεν τον άνοιξε ποτέ.
   *
   * 🔑 **Είναι το `delivered` του DocuSign, και ήταν το ΜΟΝΟ βήμα που μας έλειπε.** Η
   * τεκμηρίωσή του το ορίζει κατά λέξη: *«Delivered means that all recipients have
   * viewed the documents, meaning they **clicked on the link** to access the documents,
   * but did not sign them»*. Χωρίς αυτό, «του στείλαμε και σιωπά» και «το διάβασε και
   * το σκέφτεται» είναι **η ίδια γραμμή** στον κατάλογο — και είναι δύο εντελώς
   * διαφορετικά τηλεφωνήματα.
   *
   * 🏆 **Μαζί με το {@link notifiedAt} φτιάχνουν χωνί ΤΡΙΩΝ βημάτων που κανείς δεν
   * έχει ολόκληρο**: *του το είπαμε;* → *το άνοιξε;* → *απάντησε;*. Το DocuSign έχει
   * τα δύο τελευταία και **δομικά δεν μπορεί** να έχει το πρώτο (φάκελος χωρίς
   * διεύθυνση παραλήπτη **δεν γεννιέται**)· το MLS δεν έχει κανένα, γιατί δεν
   * παρακολουθεί καθόλου την έγκριση του ιδιοκτήτη.
   *
   * ⚠️ **Γράφεται ΜΙΑ φορά — «πότε το είδε ΠΡΩΤΗ φορά», όχι «πότε το είδε τελευταία».**
   * Η πρώτη ματιά είναι το γεγονός που αλλάζει την ερμηνεία της σιωπής· η δέκατη δεν
   * προσθέτει τίποτα και θα έκανε κάθε φόρτωση σελίδας **εγγραφή στη βάση**.
   */
  readonly viewedAt: string | null;
  /**
   * 🔴 **ΠΟΤΕ ΑΝΑΚΛΗΘΗΚΕ Η ΜΕΣΙΤΙΚΗ ΑΔΕΙΑ ΤΟΥ ΓΡΑΦΕΙΟΥ** (ADR-824 §8 Κ6) — `null` όσο
   * το γραφείο επιτρέπεται.
   *
   * ⚠️ **ΔΕΝ είναι «ο ιδιοκτήτης ανακάλεσε την εντολή»** — εκείνο είναι το
   * `confirmation: 'declined'`, **άλλο γεγονός με άλλον δράστη**. Εδώ ο δράστης είναι
   * ο **ρυθμιστής** (υπερδιαχειριστής), και το υποκείμενο το **γραφείο**, όχι αυτή η
   * αγγελία. Κοινό πεδίο θα έλεγε στον ιδιοκτήτη ότι κάποιος αντιλέγει στη δική του
   * συγκατάθεση, ενώ κανείς δεν αντιλέγει.
   *
   * 🔑 **ΓΙΑΤΙ ΓΡΑΦΕΤΑΙ ΣΤΗΝ ΟΝΤΟΤΗΤΑ ΚΑΙ ΔΕΝ ΡΩΤΙΕΤΑΙ Η ΕΤΑΙΡΕΙΑ.** Το «είναι στον
   * δημόσιο χάρτη;» το απαντά **καθαρή συνάρτηση** πάνω στην αγγελία — και το τρέχει
   * **και η οθόνη του κατόχου** (`OwnerPropertyCard`), που **δεν μπορεί** να διαβάσει
   * το `companies/{id}` του γραφείου. Μια ανάγνωση εταιρείας μέσα στον κριτή θα
   * γεννούσε **δεύτερο** κριτή για τους πελάτες που δεν μπορούν να τη ζητήσουν —
   * δηλαδή ακριβώς το σχήμα του ADR-749. Το γεγονός **ταξιδεύει** στην αγγελία μία
   * φορά, τη στιγμή της ανάκλησης, και ο ΕΝΑΣ κριτής το διαβάζει από παντού δωρεάν.
   *
   * ⚠️ **Αντιστρέψιμο**: η επανέγκριση το ξαναγράφει `null` και η αγγελία επανέρχεται
   * — γι' αυτό είναι **στιγμή** και όχι σβήσιμο της εντολής. Η συμφωνημένη διάρκεια
   * (`expiresAt`) **δεν πειράζεται ποτέ**: θα ήταν απώλεια δεδομένου για να εκφραστεί
   * γεγονός που έχει δικό του πεδίο.
   */
  readonly agencyRevokedAt?: string | null;
  /**
   * Η ταυτότητα του **ζωντανού συνδέσμου συγκατάθεσης**. `null` = κανένας σύνδεσμος
   * δεν ισχύει αυτή τη στιγμή.
   *
   * 🔴 **ΕΔΩ ΖΕΙ Η ΑΝΑΚΛΗΣΗ, ΚΑΙ ΓΙ' ΑΥΤΟ ΔΕΝ ΧΡΕΙΑΣΤΗΚΕ ΣΥΛΛΟΓΗ.** Η πύλη
   * προμηθευτή κρατά τα ακυρωμένα `nonce` σε **δεύτερη συλλογή**
   * (`vendor_invite_tokens`) — δηλαδή δεύτερο βιβλίο που πρέπει να συμφωνεί με το
   * πρώτο. Εδώ η **κατάσταση που αποφασίζει είναι η κατάσταση που απαντά**: ο
   * σύνδεσμος ισχύει όσο το `nonce` του **είναι** αυτό που γράφει η εντολή. Νέα
   * αποστολή γράφει νέο· ανάκληση γράφει `null`. Καμία απόκλιση δυνατή, γιατί δεν
   * υπάρχει δεύτερο βιβλίο (ADR-749).
   *
   * ⚠️ **Δεν είναι μυστικό που προστατεύει από πλαστογραφία** — αυτό το κάνει η
   * υπογραφή. Είναι **η ταυτότητα της συγκεκριμένης πρόσκλησης**, ώστε ένας παλιός
   * σύνδεσμος να μη μιλά για λογαριασμό μιας πρόσκλησης που αντικαταστάθηκε.
   */
  readonly consentNonce: string | null;
  /**
   * ISO — **η συμβατική λήξη** της εντολής. Το `ExpirationDate` του RESO.
   *
   * ⚠️ **Είναι ημερομηνία ΣΥΜΦΩΝΙΑΣ, όχι ρολόι συστήματος** (RESO, κατά λέξη). Δεν
   * ενημερώνεται όταν κάποιος πατήσει «αποθήκευση»· αλλάζει **μόνο** όταν αλλάξει η
   * συμφωνία.
   */
  readonly expiresAt: string;

  // ── ΤΑ ΤΡΙΑ ΤΗΣ ΚΑΤΑΛΗΨΗΣ (ADR-832) ───────────────────────────────────────
  //
  // 🔑 Χωρίς αυτά η αγγελία δεν μπορεί να κρατήσει **δεύτερη** εντολή: δεν ξέρει
  //    ποιος κρατά ποια, πότε αρχίζει, ούτε για ποια πράξη. Δες
  //    `lib/mandate/mandate-conflict.ts` για το γιατί τα τρία μαζί ορίζουν σύγκρουση.

  /**
   * 🔴 **ΠΟΙΟ ΓΡΑΦΕΙΟ ΚΡΑΤΑ ΑΥΤΗ ΤΗΝ ΕΝΤΟΛΗ** — και γιατί δεν αρκούσε το
   * `OwnerProperty.authorCompanyId`.
   *
   * Εκείνο απαντά *«ποιο γραφείο **κατέγραψε** την αγγελία»* — **απόδοση**, ένα πεδίο
   * ανά έγγραφο, και σωστά ένα: η αγγελία γράφτηκε μία φορά από έναν. Αυτό εδώ απαντά
   * *«ποιος **κρατά δικαίωμα** τώρα»* — και από τη στιγμή που οι εντολές είναι
   * **πολλές**, η απάντηση είναι **ανά εντολή**. Με ένα κοινό πεδίο, δύο απλές εντολές
   * σε δύο γραφεία θα ήταν **δομικά ανώνυμες**: το σύστημα θα ήξερε ότι υπάρχουν, και
   * **δεν θα μπορούσε να πει ποιανού είναι** — ούτε να απαντήσει «συγκρούεσαι με
   * ποιον;».
   *
   * ⚠️ **ΔΕΝ αντικαθιστά το `authorCompanyId` και δεν είναι διπλότυπο** (N.0.2): οι
   * δύο τιμές **αποκλίνουν νόμιμα** — αγγελία ιδιώτη (`authorCompanyId: null`) που
   * αναθέτει σε γραφείο έχει κάτοχο εντολής **χωρίς** να έχει συγγραφέα-εταιρεία.
   *
   * ⚠️ **Δεν είναι πεδίο μισθωτή.** Ο άξονας απομόνωσης της συλλογής μένει ο
   * `authorUserId` — δες `OwnerProperty.authorUserId`, και **CHECK 3.35**.
   */
  readonly agencyCompanyId: string;

  /**
   * ISO — **πότε αρχίζει να ισχύει** η εντολή.
   *
   * 🔴 **ΤΟ ΣΧΟΛΙΟ ΠΟΥ ΕΛΕΓΕ «ΣΩΣΤΑ ΔΕΝ ΥΠΑΡΧΕΙ» ΠΑΡΑΜΕΝΕΙ ΣΩΣΤΟ — ΓΙΑ ΤΗΝ ΤΡΕΧΟΥΣΑ
   * ΕΝΤΟΛΗ.** Έγραφε *«μια εντολή που δεν έχει ακόμη γραφτεί δεν έχει έναρξη, και μια
   * που γράφτηκε έχει το `createdAt` της αγγελίας — που είναι άλλο γεγονός»*
   * ({@link mandateInvariantViolations}). Ακριβές: όσο η εντολή γεννιόταν **πάντα
   * ενεργή**, η έναρξη ήταν η στιγμή της γραφής και το πεδίο θα ήταν θόρυβος.
   *
   * 🏆 **Αυτό που άλλαξε είναι ότι υπάρχει πλέον ΠΡΟΓΡΑΜΜΑΤΙΣΜΕΝΗ εντολή** — και
   * είναι η δυνατότητα που **κανένα MLS δεν προσφέρει**: *«η αποκλειστική του άλλου
   * γραφείου λήγει 12/03· κλείσε εντολή που αρχίζει 13/03»*. Χωρίς ρητή έναρξη, ο
   * ιδιοκτήτης θα έπρεπε να **θυμηθεί** να ξαναμπεί τη σωστή μέρα — δηλαδή η
   * πλατφόρμα θα του έλεγε «όχι» σε κάτι απολύτως νόμιμο.
   *
   * ⚠️ **Ο νόμος μετριέται ΑΠΟ ΕΔΩ.** Το ανώτατο όριο διάρκειας (άρθρο 200 §3/§4)
   * είναι διάστημα, και το διάστημα έχει αρχή. Ο κριτής {@link exceedsStatutoryTerm}
   * μετρούσε από «τώρα» επειδή «τώρα» **ήταν** η αρχή· με προγραμματισμένη εντολή δεν
   * είναι, και μια οκτάμηνη που αρχίζει σε έξι μήνες θα περνούσε ως **δεκατετράμηνη**.
   */
  readonly startsAt: string;

  /**
   * **Ποιες πράξεις καλύπτει** — το «**ίδιο περιεχόμενο**» του άρθρου 200 §4.
   *
   * 🔑 **Δανείζεται το ΥΠΑΡΧΟΝ λεξιλόγιο** (`OFFER_KINDS`: `sell` · `leaseOut` ·
   * `exchange`), και δεν επινοεί δεύτερο. Ο νόμος δεν απαγορεύει «άλλη εντολή» —
   * απαγορεύει άλλη εντολή **με το ίδιο περιεχόμενο**. Το RESO λέει το ίδιο με άλλα
   * λόγια, ξεχωρίζοντας `Exclusive Right To Sell` από `…To Lease`: δεν είναι δύο
   * γεύσεις μιας ιδέας, είναι **δύο πόροι**.
   *
   * ⇒ Αποκλειστική **πώλησης** στο γραφείο Α **δεν** εμποδίζει εντολή **εκμίσθωσης**
   * στο Β. Πριν το εμπόδιζε — και ήταν λάθος που κόστιζε **νόμιμες** συμφωνίες.
   *
   * ⚠️ **Κενός πίνακας δεν καταλαμβάνει τίποτα** ⇒ είναι invariant παραβίαση
   * (`mandate-scope-empty`), όχι σιωπηλό «όλα». Ένα `?? OFFER_KINDS` εδώ θα έδινε στο
   * γραφείο **περισσότερα δικαιώματα από όσα ζήτησε**, σιωπηλά.
   */
  readonly scope: readonly OfferKind[];
}

/**
 * **Ποιανού είναι η αγγελία.**
 *
 * ⚠️ Το σκέλος `self` **δεν έχει κανένα πεδίο**, και είναι σκόπιμο: ο ιδιώτης που
 * γράφει το δικό του σπίτι δεν δίνει εντολή σε κανέναν, δεν εγκρίνει τίποτα και δεν
 * λήγει ποτέ. Πεδία γεμάτα `null` για τη μισή συλλογή θα ήταν φρουροί που **δεν
 * μπορούν να πυροδοτήσουν**.
 */
export type OwnerPropertyMandate = { readonly kind: 'self' } | BrokeredListingMandate;

// =============================================================================
// 4. ΟΙ ΚΡΙΤΕΣ — «επιτρέπεται να φτάσει στον κόσμο;»
// =============================================================================

/**
 * **Πέρασε η συμβατική λήξη;** `self` ⇒ ποτέ.
 *
 * @param nowISOValue — η **περασμένη** στιγμή, ποτέ `new Date()` εδώ μέσα: ο κριτής
 *   πρέπει να δίνει την ίδια απάντηση σε όλο το πέρασμα προβολής, και ένα ρολόι
 *   διαβασμένο μέσα στη συνάρτηση κάνει το ίδιο πέρασμα να διαφωνεί με τον εαυτό του.
 */
export function isMandateExpired(
  mandate: OwnerPropertyMandate,
  nowISOValue: string,
): boolean {
  if (mandate.kind === 'self') return false;
  return Date.parse(mandate.expiresAt) <= Date.parse(nowISOValue);
}

/**
 * 🔴 **Ο ΕΝΑΣ ΚΡΙΤΗΣ: επιτρέπεται αυτή η αγγελία να φτάσει στον κόσμο;**
 *
 * `true` για τον ιδιώτη πάντα· για το γραφείο **μόνο** όταν ο ιδιοκτήτης έχει πει
 * «ναι» **και** η εντολή δεν έχει λήξει.
 *
 * ⚠️ **ΔΕΝ είναι δεύτερο κριτήριο δημοσίευσης** — και ο τρόπος που καταναλώνεται είναι
 * ο λόγος. Το `owner-property-projection.ts` **δεν** ρωτά «δημοσιεύεται;» (αυτό
 * απαντιέται **μία** φορά, στο `isPubliclyListed`)· λέει την αλήθεια **στη γλώσσα της
 * Α20**: μια αγγελία χωρίς ζωντανή εντολή **δεν έχει καμία διάθεση στην αγορά**. Από
 * εκεί και πέρα ο υπάρχων κώδικας βγάζει μόνος του `unavailable` + `[]` και **σβήνει**
 * την προβολή. Είναι **ακριβώς** ο μηχανισμός που χρησιμοποιεί ήδη η απόσυρση.
 *
 * 🔑 Γι' αυτό η **λήξη δεν χρειάζεται δικό της μηχανισμό εξαφάνισης**: την επόμενη
 * φορά που η αγγελία συντίθεται, φεύγει μόνη της. Το μόνο που μένει είναι **κάποιος
 * να σκανδαλίσει** τη σύνθεση — δουλειά ενός περάσματος, όχι νέας αρχής.
 */
export function mandateAllowsPublication(
  mandate: OwnerPropertyMandate,
  nowISOValue: string,
): boolean {
  return (
    isMandateAttributable(mandate) &&
    !isMandateExpired(mandate, nowISOValue) &&
    // 🔴 **Η ΑΔΕΙΑ ΤΟΥ ΓΡΑΦΕΙΟΥ** (ADR-824 §8 Κ6). Χωρίς αυτόν τον όρο, η ανάκληση
    //    μεσιτικής ικανότητας **δεν άγγιζε** τις ήδη δημοσιευμένες αγγελίες: το
    //    γραφείο έχανε το δικαίωμα να καταχωρεί **νέες** και κρατούσε στον δημόσιο
    //    χάρτη **όσες πρόλαβε** — δηλαδή ο φρουρός θα φύλαγε μόνο το μέλλον.
    !isAgencyRevoked(mandate)
  );
}

/**
 * Έχει ανακληθεί η μεσιτική άδεια του γραφείου που κρατά αυτή την εντολή;
 *
 * 🔴 **`?? null` ΚΑΙ ΟΧΙ `!== null` ΣΚΕΤΟ — ΤΟ ΒΡΗΚΕ ΑΓΚΥΡΑ, ΟΧΙ ΑΝΑΓΝΩΣΗ.** Το πεδίο
 * είναι **προαιρετικό** γιατί **καμία** εντολή που υπάρχει σήμερα δεν το έχει. Με
 * σκέτο `!== null`, το `undefined` κάθε υπάρχοντος εγγράφου θα διαβαζόταν ως
 * **ανακληθείσα άδεια** ⇒ **όλες** οι brokered αγγελίες θα εξαφανίζονταν από τον
 * δημόσιο χάρτη σιωπηλά — ακριβώς η κλάση βλάβης του ADR-777 §8.45.
 *
 * 🔑 **Η απουσία σημαίνει «δεν ανακλήθηκε», και είναι η σωστή κατεύθυνση**: ο
 * φρουρός της **γέννησης** νέων brokered αγγελιών είναι ο τύπος
 * `BrokerageAuthority` (ADR-824 §6) και δεν εξαρτάται από αυτό το πεδίο. Εδώ
 * κρίνεται μόνο *«ανακλήθηκε **μετά**;»* — και η απάντηση για έγγραφο που γράφτηκε
 * πριν υπάρξει το πεδίο είναι **όχι**.
 */
export function isAgencyRevoked(mandate: OwnerPropertyMandate): boolean {
  return mandate.kind === 'brokered' && (mandate.agencyRevokedAt ?? null) !== null;
}

/**
 * 🔴 **ΓΙΑΤΙ ΔΕΝ ΕΦΤΑΣΕ ΤΟ ΜΗΝΥΜΑ — ή `null` όταν ΔΕΝ ΞΕΡΟΥΜΕ** (ADR-834 §6.5.δ).
 *
 * Η **μία** πόρτα προς το {@link BrokeredListingMandate.notifyOutcome}, και είναι
 * πόρτα και όχι απευθείας ανάγνωση για **έναν** λόγο: ο τύπος υπόσχεται
 * `MandateNotifyOutcome | null`, αλλά η βάση κρατά έγγραφα **παλαιότερα από το
 * πεδίο**, όπου η τιμή είναι `undefined`. Ένα `mandate.notifyOutcome` σκέτο θα
 * περνούσε εκείνο το `undefined` σε `Record` ευρετηρίαση και η οθόνη θα τύπωνε
 * **κενό** — δηλαδή η άγνοια θα ξαναγινόταν αόρατη, ακριβώς η κλάση που το §6.5.δ
 * κλείνει.
 *
 * ⚠️ **Επιστρέφει `null` και για ΑΓΝΩΣΤΗ τιμή**, όχι μόνο για απούσα: μια χαλασμένη
 * εγγραφή δεν δικαιούται να ονομάσει αιτία που κανείς δεν κατέγραψε.
 */
export function notifyOutcomeOf(mandate: OwnerPropertyMandate): MandateNotifyOutcome | null {
  if (mandate.kind === 'self') return null;
  const recorded: unknown = mandate.notifyOutcome;
  return isMandateNotifyOutcome(recorded) ? recorded : null;
}

// =============================================================================
// 3β. ΟΙ ΕΠΙΛΟΓΕΙΣ — η ΜΙΑ πόρτα προς «ποια εντολή ισχύει» (ADR-832)
// =============================================================================

/**
 * **Έχει ΑΡΧΙΣΕΙ να ισχύει αυτή η εντολή;**
 *
 * 🔑 Ξεχωριστό από το {@link isMandateExpired}: μια **προγραμματισμένη** εντολή δεν
 * έχει λήξει **και** δεν ισχύει. Πριν το `startsAt` οι δύο καταστάσεις ήταν μία, γιατί
 * κάθε εντολή γεννιόταν ενεργή.
 */
export function hasMandateStarted(
  mandate: OwnerPropertyMandate,
  nowISOValue: string,
): boolean {
  if (mandate.kind === 'self') return true;
  return Date.parse(mandate.startsAt) <= Date.parse(nowISOValue);
}

/**
 * 🔴 **ΚΑΤΑΛΑΜΒΑΝΕΙ ΑΥΤΗ Η ΕΝΤΟΛΗ ΤΟΝ ΠΟΡΟ ΤΗΣ ΤΩΡΑ;** — ο ορισμός του «ζωντανή».
 *
 * Τέσσερα σκέλη, και κανένα περιττό: **εγκεκριμένη** (ο ιδιοκτήτης είπε ναι) ∧
 * **άρχισε** ∧ **δεν έληξε** ∧ **το γραφείο επιτρέπεται ακόμη**.
 *
 * ⚠️ **ΔΕΝ είναι το {@link mandateAllowsPublication}, και η διαφορά έχει όνομα.**
 * Εκείνο ρωτά *«φτάνει αυτή η αγγελία στον κόσμο;»* — ερώτημα **προβολής**, που
 * δέχεται και το `self`. Αυτό ρωτά *«ποιος κρατά δικαίωμα;»* — ερώτημα **σύμβασης**,
 * όπου το `self` δεν κρατά τίποτα. Ένας κοινός κριτής θα σήμαινε ότι ο ιδιοκτήτης
 * που γράφει το σπίτι του **εμποδίζει τον εαυτό του** να καλέσει γραφείο.
 *
 * 🔶 **ΓΝΩΣΤΟ ΚΕΝΟ, ΓΡΑΜΜΕΝΟ**: εντολή `pending` **δεν** καταλαμβάνει — άρα δύο
 * ταυτόχρονα *αιτήματα* αποκλειστικής προς **διαφορετικά** γραφεία περνούν και τα δύο,
 * και η σύγκρουση εμφανίζεται στη **δεύτερη αποδοχή** (όπου και μπλοκάρεται). Αυτό
 * είναι **σκόπιμο**: αίτημα δεν είναι σύμβαση, και μια πλατφόρμα που δέσμευε τον πόρο
 * σε κάθε *ερώτηση* θα άφηνε τον ιδιοκτήτη όμηρο ενός γραφείου που δεν απαντά ποτέ.
 */
export function isMandateLive(
  mandate: OwnerPropertyMandate,
  nowISOValue: string,
): boolean {
  if (mandate.kind === 'self') return false;
  return (
    isMandateAttributable(mandate) &&
    hasMandateStarted(mandate, nowISOValue) &&
    !isMandateExpired(mandate, nowISOValue) &&
    !isAgencyRevoked(mandate)
  );
}

/**
 * **Ποιες εντολές ισχύουν αυτή τη στιγμή.** Η μία πόρτα — κανείς δεν φιλτράρει μόνος.
 *
 * ⚠️ Χειρόγραφο `mandates.filter(m => !isMandateExpired(m, now))` σε σημείο χρήσης θα
 * ήταν **δεύτερος ορισμός** του «ζωντανή» — και θα ξεχνούσε την ανάκληση ή την
 * έναρξη. Το έργο έχει μετρημένο ιστορικό αυτού ακριβώς του σχήματος (ADR-749).
 */
export function activeMandates(
  mandates: readonly BrokeredListingMandate[],
  nowISOValue: string,
): readonly BrokeredListingMandate[] {
  return mandates.filter((mandate) => isMandateLive(mandate, nowISOValue));
}

/**
 * **Ποιο γραφείο κρατά ΑΥΤΗ ΤΗΝ ΠΡΑΞΗ τώρα;** — `null` όταν κανένα.
 *
 * 🔑 Απαντά **ανά πράξη**, γιατί ο πόρος είναι `(ακίνητο × πράξη)`: το ίδιο ακίνητο
 * μπορεί να έχει αποκλειστική **πώλησης** στο Α και εντολή **εκμίσθωσης** στο Β.
 *
 * ⚠️ **Επιστρέφει την ΠΡΩΤΗ ζωντανή, και σε ΑΠΟΚΛΕΙΣΤΙΚΗ πράξη είναι το πολύ μία** —
 * ο κριτής (`lib/mandate/mandate-conflict.ts`) το εγγυάται στη γραφή. Σε **απλή**
 * εντολή μπορεί να είναι πολλές· εκεί ο καλών θέλει το {@link activeMandates}
 * φιλτραρισμένο, όχι «την πρώτη». Δηλωμένο εδώ ώστε κανείς να μην το υποθέσει λάθος.
 */
export function activeMandateFor(
  mandates: readonly BrokeredListingMandate[],
  offerKind: OfferKind,
  nowISOValue: string,
): BrokeredListingMandate | null {
  return (
    activeMandates(mandates, nowISOValue).find((mandate) =>
      mandate.scope.includes(offerKind),
    ) ?? null
  );
}

/**
 * 🔴 **ΟΣΕΣ ΜΠΟΡΕΙ ΝΑ ΔΕΣΜΕΥΟΥΝ** — εγκεκριμένες ∧ μη ανακληθείσες, **ΧΩΡΙΣ χρονικό
 * φίλτρο**. Η είσοδος του κριτή σύγκρουσης, και **όχι** το {@link activeMandates}.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΧΩΡΙΣΤΗ ΣΥΝΑΡΤΗΣΗ — ΔΥΟ ΛΟΓΟΙ, ΚΑΙ ΟΙ ΔΥΟ ΜΕΤΡΗΜΕΝΟΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * **1. Διπλός χρονικός έλεγχος = ADR-749.** Ο κριτής (`mandateConflicts`) **κάνει ήδη**
 * τη σύγκριση διαστημάτων, και τη χρειάζεται ολόκληρη: μια εντολή που δεν ισχύει
 * **σήμερα** μπορεί κάλλιστα να επικαλύπτεται με μια **προγραμματισμένη**. Ένα
 * προ-φιλτράρισμα με «ζωντανή τώρα» θα έκρυβε ακριβώς τις εντολές που η νέα
 * δυνατότητα υπάρχει για να σεβαστεί.
 *
 * **2. Το άγνωστο γινόταν κενό (N.12).** Το {@link hasMandateStarted} απαντά `false`
 * σε **μη αναγνώσιμη** έναρξη — σωστό για «φτάνει στον κόσμο;», **καταστροφικό** για
 * «ποιος κρατά δικαίωμα;»: η χαλασμένη εντολή **εξαφανιζόταν σιωπηλά** από τον έλεγχο
 * και η δεύτερη αποκλειστική περνούσε. Εδώ φτάνει στον κριτή, που απαντά
 * `undetermined` — δηλαδή *«δεν ξέρω»*, όχι *«καθαρό»*.
 *
 * ⚠️ **Η έγκριση και η ανάκληση ΜΕΝΟΥΝ φίλτρα εδώ**, γιατί δεν είναι χρονικές: εντολή
 * που ο ιδιοκτήτης **απέρριψε** δεν δεσμεύει τίποτα, ποτέ, και δεν έχει νόημα να
 * φτάσει στον κριτή διαστημάτων.
 */
/**
 * 🔴 **ΟΙ ΕΝΤΟΛΕΣ ΟΠΩΣ ΤΙΣ ΚΡΑΤΑ Η ΒΑΣΗ** — η μία πόρτα ανάγνωσης (ADR-832).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ Ο ΤΥΠΟΣ ΠΕΡΙΓΡΑΦΕΙ ΤΙ **ΠΡΕΠΕΙ** ΝΑ ΕΡΘΕΙ· Η ΒΑΣΗ ΚΡΑΤΑ Ο,ΤΙ **ΗΡΘΕ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ως τις 2026-08-30 το πεδίο ήταν **ενικό** (`mandate: { kind: 'self' } | Brokered`).
 * Το ADR-827 μέτρησε **0 έγγραφα `brokered`** ⇒ καμία μετανάστευση συμβάσεων. **Αλλά
 * τα έγγραφα `self` υπάρχουν**, και κανένα τους δεν έχει `mandates`: ένα σκέτο
 * `property.mandates.length` πάνω τους πετά **TypeError** — δηλαδή η αγγελία κάθε
 * ιδιώτη θα **έριχνε** τη διαδρομή αντί να κριθεί.
 *
 * 🔑 Ίδιο δόγμα, ίδιο αρχείο, με το `isAgencyRevoked` (*«`?? null` και όχι `!== null`
 * σκέτο — το βρήκε άγκυρα, όχι ανάγνωση»*) και με το `exceedsStatutoryTerm`
 * (*«κάθε εντολή γραμμένη πριν τη Φάση Α έχει `agreement: undefined`»*).
 *
 * ⚠️ **Το παλιό `{ kind: 'self' }` γίνεται ΚΕΝΟΣ ΠΙΝΑΚΑΣ**, που είναι ακριβώς η νέα
 * του σημασία: ο ιδιώτης δεν έχει εντολή. Παλιό `brokered` (δεν υπάρχει σήμερα, αλλά
 * ο κώδικας δεν στοιχηματίζει) γίνεται πίνακας ενός — με τα τρία νέα πεδία **κενά**,
 * που τα invariants θα καταγγείλουν κανονικά αντί να τα υποθέσουν.
 */
export function mandatesOf(source: {
  readonly mandates?: readonly BrokeredListingMandate[];
  readonly mandate?: OwnerPropertyMandate;
}): readonly BrokeredListingMandate[] {
  if (Array.isArray(source.mandates)) return source.mandates;

  const legacy = source.mandate;
  if (legacy === undefined || legacy.kind === 'self') return [];
  return [legacy];
}

export function bindingMandates(
  mandates: readonly BrokeredListingMandate[],
): readonly BrokeredListingMandate[] {
  return mandates.filter(
    (mandate) => isMandateAttributable(mandate) && !isAgencyRevoked(mandate),
  );
}

/**
 * 🔴 **Η ΕΠΟΜΕΝΗ ΛΗΞΗ** — το πεδίο-**ευρετήριο** που κάνει τον σαρωτή δυνατό (ADR-832).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΠΑΡΑΓΩΓΟ ΠΕΔΙΟ, ΚΑΙ ΤΟ ΞΕΡΟΥΜΕ — ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΔΕΥΤΕΡΗ ΑΛΗΘΕΙΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο σαρωτής λήξης έβρισκε τις ληγμένες με **μία ανισότητα**:
 * `where('mandate.expiresAt', '<=', now)`. Το Firestore **δεν υποστηρίζει ανισότητα σε
 * πεδίο μέσα σε πίνακα αντικειμένων** ⇒ με τον πληθυντικό το ερώτημα δεν σπάει με
 * σφάλμα, **επιστρέφει τίποτα**: οι ληγμένες αγγελίες θα έμεναν στον δημόσιο χάρτη για
 * πάντα, και **κανένα test δεν θα κοκκίνιζε**. Ακριβώς το σχήμα «`0` = κανείς δεν
 * κοίταξε» των N.11/N.12.
 *
 * 🔑 **Οι εναλλακτικές μετρήθηκαν**: `array-contains` δεν κάνει ανισότητα· σάρωση όλης
 * της συλλογής μεγαλώνει με ακίνητα **που δεν λήγουν ποτέ** (το ακριβές κόστος που το
 * υπάρχον σχόλιο του σαρωτή γιόρταζε ότι απέφυγε). Το denormalized πεδίο είναι το
 * κανονικό πρότυπο του Firestore γι' αυτό, και είναι **ασφαλές εδώ** επειδή ο γραφέας
 * του `mandates` είναι **ΕΝΑΣ** — το γράφει μαζί, στην ίδια συναλλαγή.
 *
 * ⚠️ **Είναι ΕΥΡΕΤΗΡΙΟ, ΟΧΙ ΑΛΗΘΕΙΑ.** Κανένας κριτής δεν επιτρέπεται να το διαβάσει
 * για να απαντήσει «έληξε;» — αυτό το λέει το {@link isMandateExpired} πάνω στην ίδια
 * την εντολή. Χρησιμεύει **μόνο** για να βρεθεί το έγγραφο.
 *
 * @param afterISO — προαιρετικό κατώφλι: επιστρέφεται η πρώτη λήξη **γνησίως μετά**
 *   από αυτό. 🔴 **Είναι ο μηχανισμός που κάνει τον σαρωτή τερματίσιμο**: χωρίς αυτό,
 *   μια ληγμένη εντολή θα έμενε για πάντα «η πρώτη» και το έγγραφο θα ξαναβρισκόταν
 *   σε **κάθε** πέρασμα, για πάντα. Με αυτό, ο σαρωτής γράφει την **επόμενη**
 *   μελλοντική — ή `null`, και το έγγραφο φεύγει από το ερώτημα οριστικά.
 *
 * @returns Η **πρώτη** τέτοια λήξη, ή `null`. Η πρώτη και όχι η τελευταία: μόλις
 *   **μία** λήξει, η προβολή έχει αλλάξει και το έγγραφο πρέπει να ξαναχτιστεί.
 */
export function nextMandateExpiry(
  mandates: readonly BrokeredListingMandate[],
  afterISO?: string,
): string | null {
  const threshold = afterISO === undefined ? null : Date.parse(afterISO);

  const instants = bindingMandates(mandates)
    .map((mandate) => mandate.expiresAt)
    .filter((iso) => {
      const at = Date.parse(iso);
      if (Number.isNaN(at)) return false;
      if (threshold === null || Number.isNaN(threshold)) return true;
      // ⚠️ **Γνησίως μετά**: λήξη ακριβώς στο κατώφλι έχει ήδη επεξεργαστεί από αυτό
      //    το πέρασμα (το ερώτημα του σαρωτή είναι `<=`), και θα το ξαναέφερνε.
      return at > threshold;
    })
    .sort();

  return instants[0] ?? null;
}

/** **Κρατά κανείς κάτι;** — το ερώτημα που αντικαθιστά το παλιό `mandate.kind !== 'self'`. */
export function hasAnyActiveMandate(
  mandates: readonly BrokeredListingMandate[],
  nowISOValue: string,
): boolean {
  return activeMandates(mandates, nowISOValue).length > 0;
}

/**
 * **Η ΓΕΦΥΡΑ προς τον κριτή σύγκρουσης** — εντολή → κατάληψη.
 *
 * 🔑 Υπάρχει ώστε ο κριτής (`lib/mandate/mandate-conflict.ts`) να μένει **αγνωστικός
 * στο σχήμα της εντολής**: εκείνος ξέρει από πόρους, διαστήματα και τρόπους, όχι από
 * `consentNonce` και `viewedAt`. Η μετάφραση ζει **εδώ**, μία φορά — αλλιώς κάθε
 * καλών θα την έγραφε μόνος, με τα δικά του πεδία και τα δικά του λάθη.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΑ ΤΡΙΑ `??` ΚΛΕΙΝΟΥΝ **ΖΩΝΤΑΝΟ CRASH** — ΜΕΤΡΗΜΕΝΟ 2026-08-30
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το **μοναδικό** έγγραφο εντολής της ζωντανής βάσης (`owner_properties/ownp_bc548607…`)
 * γράφτηκε **πριν** το ADR-832 και **δεν έχει** `agencyCompanyId`, `scope`, `startsAt`.
 * Αυτή η γέφυρα τα αντέγραφε `undefined`, και το `sharedResources` του κριτή καλεί
 * `other.scope.includes(…)` ⇒ **`TypeError`** ⇒ **λευκή οθόνη** στη φόρμα αιτήματος
 * ανάθεσης, μόλις ο ιδιοκτήτης διάλεγε **το δικό του** ακίνητο.
 *
 * 🔑 **Και οι τρεις τιμές είναι η ΣΩΣΤΗ απάντηση, όχι κατευνασμός** — το ίδιο το
 * {@link mandatesOf} το είχε ήδη υποσχεθεί: *«παλιό `brokered` γίνεται πίνακας ενός —
 * με τα τρία νέα πεδία **κενά**»*:
 *
 * | Πεδίο | Κενό σημαίνει | Ποιος το λέει |
 * |---|---|---|
 * | `scope: []` | **δεν καταλαμβάνει τίποτα** | {@link MandateOccupancy.scope} — «έγκυρη κατάσταση» |
 * | `startsAt: ''` | **μη αναγνώσιμο διάστημα** ⇒ `undetermined` | N.12: *άγνωστο ≠ κενό* |
 * | `agencyCompanyId: ''` | κενή ταυτότητα **δεν ταιριάζει με καμία πραγματική** | ίδιο ιδίωμα με CHECK 3.35 |
 *
 * ⛔ **ΜΗΝ «διορθώσεις» το `startsAt` σε `decidedAt` ή σε «σήμερα»**: θα παρήγαγε
 * **επινοημένο** διάστημα και ο κριτής θα απαντούσε `clear` ή `conflicts` με βεβαιότητα
 * που **κανείς δεν έχει**. Το `undetermined` λέει την αλήθεια, και η οθόνη το δείχνει.
 */
export function occupancyOf(mandate: BrokeredListingMandate): MandateOccupancy {
  return {
    agencyCompanyId: mandate.agencyCompanyId ?? '',
    agreement: mandate.agreement,
    scope: mandate.scope ?? [],
    startsAt: mandate.startsAt ?? '',
    expiresAt: mandate.expiresAt,
  };
}

