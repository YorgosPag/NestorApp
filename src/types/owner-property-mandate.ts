/**
 * **Οι όροι αμοιβής της εντολής** (ADR-827 Α5).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΕΔΩ ΚΑΙ **ΠΟΤΕ** ΣΤΟ `public-listing.ts`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το **NAR Settlement** (ισχύς 17/08/2024, διακανονισμός **$418M** σε αγωγή antitrust)
 * υποχρέωσε κάθε MLS να *«**eliminate all broker compensation fields** and compensation
 * information»* — και απαγόρευσε το **φιλτράρισμα** αγγελιών κατά προμήθεια. Η αμοιβή
 * εξακολουθεί να συμφωνείται· απλώς **όχι στην κοινή επιφάνεια**.
 *
 * 🏆 **Και εδώ τους ξεπερνάμε δομικά, όχι με πολιτική.** Εκείνοι χρειάστηκαν αγωγή για
 * να **βγάλουν** τα πεδία· εδώ δεν υπάρχει τίποτα να βγει: το `types/public-listing.ts`
 * είναι **κλειστό σχήμα** και η αμοιβή **δεν μπορεί να εκφραστεί** εκεί. Η ίδια άμυνα
 * που κάνει αδύνατη τη διαρροή `companyId` — *δομικά αδύνατη, όχι κανόνας που κάποιος
 * οφείλει να θυμάται*.
 *
 * ⚠️ **Και ΜΕΣΑ στην εντολή είναι υποχρεωτική, όχι προαιρετική.** Το άρθρο 200
 * Ν.4072/2012 κάνει τον έγγραφο τύπο **συστατικό**: χωρίς έγγραφη συμφωνία ο μεσίτης
 * **δεν δικαιούται αμοιβή**. Άρα η αμοιβή είναι όρος που ο ιδιοκτήτης οφείλει να
 * **δει πριν** πει «ναι» — ταξιδεύει μέσα στο μήνυμα που εγκρίνει, όπως ήδη η
 * {@link BrokeredListingMandate.expiresAt}.
 *
 * 🔑 **Διακριτή ένωση, ΟΧΙ πεδία με `null`.** «Ποσοστό χωρίς ποσοστό» και «σταθερό
 * χωρίς ποσό» είναι **αδύνατο να εκφραστούν** — η ίδια άμυνα με το {@link MandateProof}.
 * *(Το `types/brokerage.ts` του ADR-230 τα κρατά ως nullable πεδία δίπλα-δίπλα· εκείνο
 * είναι παλαιότερο σχήμα και **δεν αντιγράφεται**.)*
 *
 * ⚠️ **Το `tiered` του {@link CommissionType} ΔΕΝ έχει σκέλος εδώ**, και είναι δηλωμένη
 * απουσία: κλιμακωτή αμοιβή απαιτεί **κατάλογο κλιμάκων** — μηχανισμό που δεν υπάρχει.
 * Τιμή χωρίς μηχανισμό είναι υπόσχεση που κανείς δεν τηρεί (ίδιο σκεπτικό με το
 * *Exclusive Right With Exception* στο `types/listing-agreement.ts`).
 */
export type MandateCompensation =
  | {
      readonly type: Extract<CommissionType, 'percentage'>;
      /** Επί της τιμής πώλησης/μίσθωσης. π.χ. `2` = 2%. */
      readonly percentage: number;
      readonly vatIncluded: boolean;
    }
  | {
      readonly type: Extract<CommissionType, 'fixed'>;
      readonly amountEUR: number;
      readonly vatIncluded: boolean;
    };

/**
 * **Η εθιμική αμοιβή της ελληνικής αγοράς** — 2% επί της τιμής, **πλέον** ΦΠΑ.
 *
 * ⚠️ **Εθιμική, ΟΧΙ νόμιμη.** Ο Ν.4072/2012 **δεν** ορίζει κατώτατο ή ανώτατο: η
 * αμοιβή είναι **ελεύθερα διαπραγματεύσιμη**. Άρα αυτό είναι **αρχική τιμή φόρμας**,
 * ποτέ όριο — ίδιο σκεπτικό με το {@link MANDATE_DEFAULT_DURATION_DAYS}.
 *
 * ⛔ **Και ΔΕΝ επιβάλλεται σε κανένα γραφείο.** Μια πλατφόρμα που θα *«συνιστούσε»*
 * ενιαίο ποσοστό σε ανταγωνιστές είναι ακριβώς η συμπεριφορά που κόστισε στο NAR
 * $418M. Είναι προσυμπληρωμένο πεδίο που ο μεσίτης αλλάζει ελεύθερα, τίποτα άλλο.
 */
export const CUSTOMARY_COMMISSION_PERCENTAGE = 2;

