/**
 * **ΠΟΥ ΣΤΕΛΝΩ ΤΟΝ ΑΝΘΡΩΠΟ ΤΩΡΑ** — και είναι ο **φρουρός της κλάσης**, όχι διακόσμηση.
 *
 * 🔴 **ΤΟ ΜΑΘΗΜΑ ΕΙΝΑΙ ΜΕΤΡΗΜΕΝΟ, ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΔΙΚΟ ΜΑΣ ΓΙΑ ΠΡΩΤΗ ΦΟΡΑ** (ADR-844):
 * εκεί η άρνηση **δεν είχε πού** να κουβαλήσει διέξοδο, άρα **καμία** οθόνη δεν μπορούσε
 * να τη δείξει — και ο άνθρωπος έμενε σε **λευκή σελίδα χωρίς κουμπί**. Το ελάττωμα δεν
 * ήταν ενός σκέλους· ήταν **σχήματος**.
 *
 * ⇒ Ως **υποχρεωτικό** πεδίο κάθε αποτυχίας, το ερώτημα γίνεται ερώτημα της
 * **μεταγλώττισης**, όχι της επιθεώρησης: νέα άρνηση **δεν μεταγλωττίζεται** μέχρι κάποιος
 * να πει πού οδηγεί.
 *
 * 🔑 **ΟΝΟΜΑ, ΟΧΙ ΔΙΕΥΘΥΝΣΗ.** Μια συμβολοσειρά `href` εδώ θα έβαζε **δρομολόγηση** μέσα σε
 * αρχείο τύπων και θα παρέκαμπτε το σύνορο πλοήγησης (CHECK 3.61). Η οθόνη μεταφράζει το
 * όνομα σε σύνδεσμο με **κυριολεκτικό** πίνακα.
 */
export type WorkspaceInviteExitName =
  /** *«Συνδέσου για να συνεχίσεις»* — υπάρχει πράξη, λείπει μόνο η ταυτότητα. */
  | 'sign-in'
  /** *«Δεν υπάρχει τίποτα να κάνεις εδώ»* — η αρχική είναι η τίμια διέξοδος. */
  | 'home';

export interface WorkspaceInviteExit {
  readonly exit: WorkspaceInviteExitName;
}

/**
 * **Ό,τι ΑΚΡΙΒΩΣ ζωγραφίζεται** — και τίποτα άλλο δεν φεύγει από τον διακομιστή.
 *
 * ⛔ **ΤΟ `invitationId` ΕΙΝΑΙ ΡΗΤΑ ΑΠΟΝ.** Η έκβαση της υπηρεσίας το κουβαλά *(το
 * χρειάζεται η σήμανση «ανοίχτηκε»)*, αλλά δεν έχει **καμία** δουλειά σε ανώνυμο
 * φυλλομετρητή — ό,τι περνά σε client component **γράφεται μέσα στο HTML**. Το ίδιο και το
 * `companyId` και το email του παραλήπτη: η όψη δίνεται σε **όποιον κρατά τον σύνδεσμο**.
 */
export type WorkspaceInvitationLinkView =
  | {
      readonly kind: 'preview';
      /** Όνομα χώρου · ρόλος · λήξη · δηλωμένη ταυτότητα — από τον **ΕΝΑ** αναγνώστη. */
      readonly preview: WorkspaceInvitationPreview;
      /**
       * ⚠️ **ΔΙΑΠΙΣΤΕΥΤΗΡΙΟ ΜΕΣΑ ΣΕ HTML, ΚΑΙ ΕΙΝΑΙ ΖΥΓΙΣΜΕΝΟ** — ίδιο ιδίωμα με το
       * `customToken` του ADR-844.
       *
       * Η πράξη (`POST …/redeem`) στέλνει το token σε **σώμα**, άρα η οθόνη **πρέπει** να
       * το κρατά. Και δεν δίνουμε τίποτα νέο: **ο κάτοχος αυτού του HTML είναι ήδη ο
       * κάτοχος του συνδέσμου** — το token **είναι** η διεύθυνση που μόλις άνοιξε. Η
       * σελίδα είναι `noindex` και `force-dynamic`, ώστε κανένα ενδιάμεσο να μην το
       * αποθηκεύσει.
       *
       * 🔑 Και η έκθεση είναι **ακίνδυνη από μόνη της**: η όψη **δεν καταναλώνει** και η
       * δέσμευση στο **επαληθευμένο** email κρίνεται στην εξαργύρωση (§7.5). Διαρροή της
       * διεύθυνσης δίνει **όψη**, ποτέ ένταξη.
       */
      readonly token: string;
      /**
       * **ΜΠΟΡΕΙ ΝΑ ΑΠΑΝΤΗΣΕΙ ΤΩΡΑ, Η ΠΡΕΠΕΙ ΠΡΩΤΑ ΝΑ ΣΥΝΔΕΘΕΙ;**
       *
       * 🔴 **ΓΙΑΤΙ Η ΟΨΗ ΔΕΙΧΝΕΤΑΙ ΚΑΙ ΣΕ ΑΝΩΝΥΜΟ** (§5 #4): ο άνθρωπος φτάνει από email
       * **πριν** από κάθε ταυτότητα. Να τον στείλουμε κατευθείαν στη σύνδεση θα του ζητούσε
       * να **συνδεθεί σε κάτι που δεν ξέρει τι είναι** — ακριβώς η συνθήκη στην οποία
       * δουλεύει το phishing. Βλέπει **πρώτα** ποιος τον καλεί, **μετά** αποφασίζει.
       *
       * 🔑 **ΔΙΑΚΡΙΤΗ ΕΝΩΣΗ, ΟΧΙ `canRespond: boolean` + ΠΡΟΑΙΡΕΤΙΚΟ href**: έτσι η
       * κατάσταση «πρέπει να συνδεθεί» **δεν μπορεί να υπάρξει χωρίς διεύθυνση
       * επιστροφής** — ο μεταγλωττιστής το απαγορεύει. Ένα ζευγάρι boolean+optional θα
       * επέτρεπε κουμπί «Σύνδεση» που χάνει τη διαδρομή πίσω, δηλαδή ακριβώς το αδιέξοδο
       * του ADR-844 με άλλο πρόσωπο.
       */
      readonly respond:
        | { readonly kind: 'ready' }
        | {
            readonly kind: 'sign-in';
            /** `loginHref(...)` **από τον διακομιστή** — περνά από τον φρουρό `safeReturnPath`. */
            readonly href: string;
          }
        /**
         * 🔑 **ΣΥΝΔΕΔΕΜΕΝΟΣ ΜΕ ΑΛΛΟΝ ΛΟΓΑΡΙΑΣΜΟ** (ADR-853 §13 ε.δ) — λέγεται **πριν** το
         * κλικ, όχι ως άρνηση μετά (Google/Slack: «signed in as…» + «αλλαγή λογαριασμού»).
         *
         * ⚠️ Το `signedInAs` είναι το email του **θεατή** — δικό του, όχι του παραλήπτη, που
         * δεν ταξιδεύει ποτέ. ⚠️ **Υπόδειξη**: η δέσμευση κρίνεται ξανά στην εξαργύρωση.
         */
        | { readonly kind: 'other-account'; readonly signedInAs: string };
      /**
       * **Η σύνδεση με επιστροφή σε ΑΥΤΗ την πρόσκληση** — `loginHref(...)` από τον διακομιστή.
       * Το χρειάζεται η «Αλλαγή λογαριασμού», και στην όψη **και** όταν το `wrong-recipient`
       * έρθει από την πράξη (ταυτότητα που άλλαξε ανάμεσα σε όψη και κλικ).
       */
      readonly switchAccountHref: string;
    }
  | (WorkspaceInviteExit & (
      /**
       * Ο ονομασμένος λόγος **ταξιδεύει**: «έληξε» · «ανακλήθηκε» · «δεν είναι σύνδεσμός
       * μας» στέλνουν τον άνθρωπο σε **τρεις διαφορετικές** ενέργειες — η αγορά δίνει ένα
       * γενικό *«invitation not valid»* (§5 #7).
       */
      | { readonly kind: 'refused'; readonly reason: WorkspaceInvitationRefusal }
      /**
       * ⚠️ **Χωρίς λόγο, επίτηδες.** Το «λείπει το μυστικό μας» μιλά για **εμάς**, όχι για
       * τον άνθρωπο — και καμία ενέργειά του δεν το διορθώνει. Να το πούμε «πλαστός
       * σύνδεσμος» θα ήταν **ψέμα που τον στέλνει σε λάθος ενέργεια**.
       */
      | { readonly kind: 'unavailable' }
    ));

/** Ό,τι **δεν** είναι όψη — δηλαδή ό,τι **οφείλει** να έχει διέξοδο. */
export type WorkspaceInviteSetback = Exclude<WorkspaceInvitationLinkView, { kind: 'preview' }>;
