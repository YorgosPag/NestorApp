/**
 * **ΟΙ ΑΓΚΥΡΕΣ ΤΩΝ ΑΡΧΙΚΩΝ** — ADR-841 §7 Α21.1 (α).
 *
 * 🔴 **Γιατί υπάρχουν**: το `getInitials` ήταν δηλωμένος SSoT από το **ADR-209 Φάση 8**
 * και είχε **τρεις ζωντανούς παραβάτες** που έδιναν **άλλη απάντηση** στο ίδιο όνομα.
 * Ένας δηλωμένος SSoT **χωρίς άγκυρα** είναι σχόλιο, όχι συμβόλαιο.
 */

import { getInitials, getContactInitials } from '../helpers';
import type { CompanyContact } from '../contracts';

describe('Α21.1 — τα δύο μετρημένα ελαττώματα ΔΕΝ επιστρέφουν', () => {
  it('🔴 το εμπορικό «και» ΔΕΝ γίνεται σήμα μάρκας', () => {
    // Η παλιά γραφή `split(' ')` έδινε «Π&» — μετρημένο, όχι υποθετικό.
    expect(getInitials('Παπαδόπουλος & Υιοί ΟΕ')).toBe('ΠΥ');
  });

  it('🔴 το μονολεκτικό όνομα δίνει ΔΥΟ γράμματα, όχι ένα', () => {
    // Ένα γράμμα συγκρούεται για κάθε Παπαδόπουλο/Παπαδάκη/Παύλου — η διάκριση
    // ΕΙΝΑΙ η δουλειά ενός σήματος ταυτότητας.
    expect(getInitials('Παπαδόπουλος')).toBe('ΠΑ');
  });
});

describe('Α21.1 — ελληνική τυπογραφία: στα κεφαλαία ο τόνος ΔΕΝ γράφεται', () => {
  it.each([
    ['Άλφα Τεχνική', 'ΑΤ'],
    ['Όμικρον', 'ΟΜ'],
    ['Ήφαιστος Δομικά', 'ΗΔ'],
  ])('%p → %p', (input, expected) => {
    expect(getInitials(input)).toBe(expected);
  });

  it('🔑 η ίδια η JS ΔΕΝ το κάνει — και γι αυτό υπάρχει το βήμα', () => {
    // Αν κάποιος αφαιρέσει το NFD/strip, αυτή η γραμμή δείχνει τι θα έβλεπε ο χρήστης.
    expect('ά'.toUpperCase()).toBe('Ά');
    expect(getInitials('άλφα')).not.toContain('Ά');
  });
});

describe('Α21.1 — η στίξη δεν είναι λέξη', () => {
  it.each([
    ['Α.Ε. Δομικά', 'ΑΕ'],
    ['Παγώνης   Νέστωρ', 'ΠΝ'],
    ['Acme Corp', 'AC'],
    ['ΟΕ', 'ΟΕ'],
    ['Ω', 'Ω'],
  ])('%p → %p', (input, expected) => {
    expect(getInitials(input)).toBe(expected);
  });
});

describe('Α21.1 — η απουσία γράμματος είναι ΚΕΝΟ, ποτέ σκάσιμο', () => {
  it.each(['', '   ', '123', '—', '&&&'])('%p → κενή συμβολοσειρά', (input) => {
    expect(getInitials(input)).toBe('');
  });

  it('🔑 το κενό επιτρέπει στον καλούντα να διαλέξει ΤΗ ΔΙΚΗ ΤΟΥ εφεδρεία', () => {
    // Αυτό ακριβώς κάνουν οι τρεις καταναλωτές: `getInitials(x) || '??'` και
    // `getInitials(x) || email.slice(0,2)`. Ένα «??» μέσα στον SSoT θα τους το
    // επέβαλλε και στους τρεις.
    expect(getInitials('') || '??').toBe('??');
  });
});

describe('Α21.1 — ο περιτυλιγμένος καταναλωτής ρωτά ΤΟΝ ΙΔΙΟ', () => {
  it('το getContactInitials δεν έχει δική του απάντηση', () => {
    const contact = {
      id: 'c1',
      type: 'company',
      companyName: 'Παπαδόπουλος & Υιοί ΟΕ',
    } as unknown as CompanyContact;

    expect(getContactInitials(contact)).toBe(getInitials('Παπαδόπουλος & Υιοί ΟΕ'));
  });
});
