/**
 * **Κλειστό σύνολο. Μία τιμή σήμερα — και η δεύτερη θα χρειαστεί ΛΟΓΟ.**
 *
 * ⚠️ **Least privilege, γραμμένο** *(Stripe Connect: «only request the capabilities
 * that your accounts need — requesting more means the onboarding flow must verify
 * more information»)*. Μια ικανότητα χωρίς **ρυθμιστικό** αντίκρισμα δεν ανήκει εδώ:
 * αυτό το αρχείο δεν είναι σάκος σημαιών — γι' αυτό ακριβώς **απορρίφθηκε** το
 * υπάρχον `settings.features` (ADR-824 §4.3).
 */
export const ORGANIZATION_CAPABILITIES = ['brokerage_listings'] as const;

export type OrganizationCapability = (typeof ORGANIZATION_CAPABILITIES)[number];

export function isOrganizationCapability(value: unknown): value is OrganizationCapability {
  return (ORGANIZATION_CAPABILITIES as readonly unknown[]).includes(value);
}

// =============================================================================
// Ο ΚΥΚΛΟΣ ΖΩΗΣ — τέσσερις καταστάσεις, καμία σιωπηλή
// =============================================================================

/**
 * **Κλειστό σύνολο, χωρίς σιωπηλό `default`** — πέμπτη κατάσταση **δεν
 * μεταγλωττίζεται** μέχρι κάποιος να αποφασίσει τι σημαίνει.
 *
 * | Κατάσταση | Τι σημαίνει | Επιτρέπεται η πράξη; |
 * |---|---|---|
 * | `unrequested` | κανείς δεν ζήτησε — **η προεπιλογή κάθε χώρου** | ❌ |
 * | `pending` | δηλώθηκε, εκκρεμεί η έγκριση | ❌ **— και αυτό είναι όλο το νόημα** |
 * | `active` | εγκρίθηκε | ✅ |
 * | `revoked` | ανακλήθηκε, **με γραμμένο λόγο** | ❌ |
 *
 * 🔴 **`revoked` ΚΑΙ ΟΧΙ επιστροφή σε `unrequested`.** *«Δεν ζήτησε ποτέ»* και *«του
 * το πήραμε»* είναι **διαφορετικά γεγονότα** με **διαφορετική θεραπεία στην οθόνη** —
 * ίδιο σκεπτικό με τη διάκριση `never-asked` ⇄ `owner-declined` του ADR-777 Α5 και
 * με το `mandate-expiry-invalid` ⇄ `mandate-expiry-past` του §8.33.
 *
 * ⛔ **ΜΗΝ το κάνεις `boolean`** (ADR-824 §4.2): ένα `isBrokerage` **δεν μπορεί να
 * εκφράσει** *«ζήτησε αλλά δεν απέδειξε»* — και εκεί ζει ο μισός πραγματικός κόσμος
 * (ο ιδρυτής δηλώνει τη Δευτέρα, η έγκριση έρχεται την Τετάρτη). Με boolean, οι δύο
 * μέρες είναι είτε **ψέμα** (`true` πριν την απόδειξη) είτε **σιωπή** (`false` χωρίς
 * εξήγηση). Ούτε απαντά *«γιατί μου το πήρατε;»*.
 */
export const CAPABILITY_STATUSES = ['unrequested', 'pending', 'active', 'revoked'] as const;

export type CapabilityStatus = (typeof CAPABILITY_STATUSES)[number];

/**
 * **Είναι αυτή η τιμή κατάσταση ικανότητας;** — ο κριτής για ό,τι έρχεται **απ' έξω**.
 *
 * 🔑 **Γιατί χρειάζεται, ενώ ο τύπος «το εγγυάται»**: ο τύπος εγγυάται μόνο ό,τι
 * γεννιέται **μέσα** στη μεταγλώττιση. Η κατάσταση ταξιδεύει και στο **σύρμα** —
 * το 403 του {@link ../lib/auth/brokerage-gate!BrokerageDeniedResponse} τη στέλνει ως
 * `string` — και εκεί είναι **είσοδος**, όχι δεδομένο μας. Ίδιο σκεπτικό με το
 * `encodeURIComponent` της βιτρίνας: ο περιορισμός ζει στην **εγγραφή**, ενώ εδώ
 * φτάνει ό,τι κι αν απάντησε ο διακομιστής *(π.χ. παλιότερη έκδοση που δεν στέλνει
 * ακόμη το πεδίο)*.
 *
 * ⚠️ **Ο δίδυμος του {@link isOrganizationCapability}, επίτηδες** — ίδιο σχήμα, ίδιο
 * αρχείο, ίδιο κλειστό σύνολο. Ένας δεύτερος κριτής γραμμένος στον πελάτη θα ήταν
 * **δεύτερο βιβλίο** για το ίδιο σύνολο (ADR-749), και θα απέκλινε τη μέρα που
 * προστεθεί πέμπτη κατάσταση.
 */
export function isCapabilityStatus(value: unknown): value is CapabilityStatus {
  return (CAPABILITY_STATUSES as readonly unknown[]).includes(value);
}

/**
 * **Η ΜΟΝΗ κατάσταση που επιτρέπει την πράξη.**
 *
 * 🔴 **Γραμμένη ΘΕΤΙΚΑ (`=== 'active'`), ποτέ αρνητικά.** Ένα `!== 'unrequested'` θα
 * άφηνε να περάσουν **και** το `pending` **και** το `revoked` — δηλαδή ακριβώς τις
 * δύο καταστάσεις που υπάρχουν για να **αρνούνται**. Η άγκυρα Κ3 του ADR-824 §8
 * κοκκινίζει σε **αυτή ακριβώς** τη μετάλλαξη.
 */
export function isCapabilityActive(status: CapabilityStatus): status is 'active' {
  return status === 'active';
}

/**
 * **ΞΕΡΕΙ ΗΔΗ Ο ΟΡΓΑΝΙΣΜΟΣ ΟΤΙ ΑΥΤΗ Η ΙΚΑΝΟΤΗΤΑ ΥΠΑΡΧΕΙ;**
 *
 * ⛔ **ΔΕΝ ΕΙΝΑΙ ΦΡΟΥΡΟΣ, ΚΑΙ ΔΕΝ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΓΙΝΕΙ.** Ο φρουρός είναι το
 * {@link isCapabilityActive} — και *μόνο* εκείνο. Αυτό εδώ απαντά **άλλο**
 * ερώτημα: *«να ζωγραφίσω πόρτα προς αυτή τη δουλειά;»*. Ένα `true` εδώ σημαίνει
 * **«δείξε την πόρτα»**, ποτέ **«πέρνα»**: και το `pending` και το `revoked`
 * επιστρέφουν `true` ενώ η πράξη τους είναι **403**.
 *
 * 🔴 **ΓΙ' ΑΥΤΟ ΕΙΝΑΙ `switch` ΚΑΙ ΟΧΙ `!== 'unrequested'`.** Οι δύο συναρτήσεις
 * θα ήταν τότε **οπτικά ταυτόσημες με τη μετάλλαξη Κ3 του ADR-824 §8** — εκείνη
 * που κοκκινίζει όταν κάποιος «απλοποιεί» τον φρουρό σε αρνητικό έλεγχο. Ένας
 * μελλοντικός αναγνώστης που έβλεπε `!== 'unrequested'` σε **δύο** αρχεία θα
 * συμπέραινε ότι είναι το ίδιο πράγμα γραμμένο δύο φορές, και θα «κεντρικοποιούσε»
 * τον φρουρό πάνω στην **ορατότητα**. Η απαρίθμηση κάνει τη διαφορά **δομική**:
 * εδώ απαντάμε **τέσσερις ξεχωριστές ερωτήσεις**, όχι μία άρνηση.
 *
 * 🔑 **Και μια πέμπτη κατάσταση ΔΕΝ θα μεταγλωττιστεί** χωρίς να απαντηθεί εδώ —
 * που είναι ακριβώς η στιγμή που κάποιος πρέπει να αποφασίσει αν διαφημίζεται.
 *
 * **Ο κανόνας του τομέα** *(Giorgio, 2026-08-28)*: κρύβεται **μόνο** όποιος δεν
 * ζήτησε ποτέ. Σε αρχιτέκτονα που δεν ζήτησε μεσιτική ιδιότητα, μια πόρτα με
 * «δήλωσε για να ξεκλειδώσεις» θα **διαφήμιζε ρυθμιζόμενη δραστηριότητα** που ο
 * Ν. 4072/2012 του απαγορεύει — και που ίσως δεν δικαιούται ποτέ. Αντίθετα, όποιος
 * **δήλωσε** ή **του αφαιρέθηκε** ξέρει ήδη ότι υπάρχει: σιωπή απέναντί του δεν
 * είναι διακριτικότητα, είναι **εξαφάνιση χωρίς εξήγηση**.
 */
export function isCapabilityKnownToOrganization(status: CapabilityStatus): boolean {
  switch (status) {
    // Κανείς δεν ζήτησε ⇒ **μην το διαφημίσεις**.
    case 'unrequested':
      return false;
    // Δήλωσε και περιμένει ⇒ οφείλουμε να του πούμε **ότι εκκρεμεί**.
    case 'pending':
    // Του αφαιρέθηκε ⇒ οφείλουμε να του πούμε **τον λόγο**.
    case 'revoked':
    // Εγκεκριμένο ⇒ δουλεύει κανονικά.
    case 'active':
      return true;
  }
}

