/**
 * =============================================================================
 * ΤΟ ΛΕΞΙΛΟΓΙΟ ΤΗΣ ΙΚΑΝΟΤΗΤΑΣ ΟΡΓΑΝΙΣΜΟΥ (ADR-824 §5)
 * =============================================================================
 *
 * **Το ερώτημα**: *«Επιτρέπεται σε **ΑΥΤΟΝ ΤΟΝ ΟΡΓΑΝΙΣΜΟ** αυτή η **ρυθμιζόμενη**
 * δραστηριότητα — και ποιος το αποφάσισε;»*
 *
 * ⚠️ **ΕΙΝΑΙ ΤΟ ΤΕΤΑΡΤΟ ΔΙΑΚΡΙΤΟ ΕΡΩΤΗΜΑ**, και τα άλλα τρία έχουν ήδη ιδιοκτήτες:
 *
 * | Ερώτημα | Υποκείμενο | Ιδιοκτήτης |
 * |---|---|---|
 * | «είναι **μέλος** αυτού του χώρου;» | άνθρωπος ⇄ χώρος | ADR-787 §5.1 |
 * | «έχει **αυτός ο άνθρωπος** την ικανότητα;» | claims ανθρώπου | ADR-801 · `lib/auth/authority.ts` |
 * | «ποιος **διαχειρίζεται** αυτή την αγγελία;» | πόρος ⇄ χώρος | `listing-custody.ts` (CHECK 3.56) |
 * | **«επιτρέπεται σε αυτόν τον ΟΡΓΑΝΙΣΜΟ;»** | **οργανισμός** | **εδώ** |
 *
 * 🔑 **Γιατί ΔΕΝ είναι το ADR-801 ξανά.** Εκείνο κρίνει **στιγμιαία**, από claims που
 * η ταυτότητα **ήδη έχει**. Εδώ η ικανότητα έχει **κύκλο ζωής** *(ζητήθηκε → εκκρεμεί
 * → ενεργή → ανακλήθηκε)* και **προϋποθέσεις που κάποιος πρέπει να αποδείξει**. Ο
 * κριτής του «επιτρέπεται;» μένει **ένας**· αυτό το αρχείο ορίζει **τι του δίνεται
 * ως είσοδος**.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚖️ Ο ΚΑΝΟΝΑΣ ΔΕΝ ΕΙΝΑΙ ΠΡΟΤΙΜΗΣΗ ΠΡΟΪΟΝΤΟΣ — Ν. 4072/2012, άρθρα 197-204
 * ─────────────────────────────────────────────────────────────────────────────
 * Η «υπηρεσία μεσιτείας» ορίζεται ως *«η υπόδειξη ευκαιριών ή η **μεσολάβηση** για τη
 * σύναψη συμβάσεων σχετικών με ακίνητα και ιδίως συμβάσεων **πώλησης, ανταλλαγής,
 * μίσθωσης** … ή **αντιπαροχής**»*, και απαιτεί εγγραφή στο **Επιμελητήριο** και στο
 * **ΓΕΜΗ**. Για **νομικό πρόσωπο** η μεσιτεία πρέπει να είναι στον **καταστατικό
 * σκοπό**.
 *
 * 🔴 Η οθόνη `/o/<ψευδώνυμο>/listings/mandates/new` κάνει **ακριβώς** αυτό που ο
 * νόμος ονομάζει μεσιτεία. Και η εφαρμογή **ήδη ήξερε τον νόμο, στο λάθος μισό**: η
 * ίδια φόρμα γράφει *«Ο νόμος δίνει δώδεκα μήνες όταν δεν συμφωνηθεί άλλη διάρκεια»*
 * — σωστό, είναι το άρθρο 200. Τηρήσαμε τη **διάρκεια** της εντολής και αγνοήσαμε
 * **ποιος επιτρέπεται να τη συνάψει**.
 *
 * @module types/organization-capability
 * @see ADR-824 — Η ικανότητα ανήκει στον οργανισμό, όχι στο επάγγελμα
 * @see ADR-801 — ο ΕΝΑΣ κριτής του «επιτρέπεται;» (αυτό είναι **είσοδός** του)
 */

