// Η ΕΓΓΡΑΦΗ — τι κρατά ο οργανισμός για κάθε ικανότητα
// =============================================================================

/**
 * **Τι λείπει, ονομαστικά** — ώστε η οθόνη να το πει στον άνθρωπο.
 *
 * 🔑 **Το πρότυπο είναι το `requirements` της Stripe Connect** (`currently_due` ·
 * `disabled_reason`): *«A capability **must be active** for a connected account to
 * perform actions associated with that capability»*, και δίπλα του **τι λείπει**.
 *
 * ⚠️ **Κλειδιά i18n, ΠΟΤΕ κείμενο** (N.11) — ίδιο ιδίωμα με το `denyReason` του
 * ADR-801. Η φωνή της εφαρμογής είναι **ήδη** αυτή: η φόρμα αγγελίας λέει *«Η
 * καταχώρηση δεν αποθηκεύεται ακόμη: Δώσε έναν τίτλο… Συμπλήρωσε εμβαδόν…»*. Αυτό
 * είναι η **ίδια πρόταση**, ένα επίπεδο πιο πάνω.
 */
export interface CapabilityRequirement {
  /** Κλειδί i18n που ονομάζει τι εκκρεμεί. */
  readonly key: string;
}

/**
 * Η **δήλωση** που κατέθεσε ο οργανισμός — τα στοιχεία που ο νόμος απαιτεί.
 *
 * ⚠️ **ΔΕΝ επαληθεύεται αυτόματα σήμερα, και είναι δηλωμένο κενό** (ADR-824 §5.3):
 * **δεν** επιβεβαιώθηκε ότι υπάρχει διαθέσιμη δημόσια υπηρεσία ΓΕΜΗ, οπότε δεν
 * μπαίνει στη Φάση 1. Το σχήμα το δέχεται **χωρίς αλλαγή**: η αυτόματη επαλήθευση
 * απλώς μετακινεί το `pending → active` από **άνθρωπο** σε **μηχανή**.
 */
export interface BrokerageDeclaration {
  /** Αριθμός ΓΕΜΗ. */
  readonly gemiNumber: string;
  /** Αριθμός μητρώου του οικείου Επιμελητηρίου. */
  readonly chamberRegistryNumber: string;
  /** Ο νόμιμος εκπρόσωπος που πληροί τις ατομικές προϋποθέσεις. */
  readonly legalRepresentativeName: string;
  /** ISO — πότε κατατέθηκε. */
  readonly declaredAt: string;
  /** Ποιος τη δήλωσε. */
  readonly declaredByUserId: string;
}

/**
 * **Η κατάσταση μιας ικανότητας για έναν οργανισμό** — με τον κύκλο ζωής της.
 *
 * ⚠️ **Η απόφαση φέρει ΟΝΟΜΑ ΚΑΙ ΣΤΙΓΜΗ.** Χωρίς αυτά, το `revoked` δεν μπορεί να
 * απαντήσει *«ποιος και πότε;»* — που είναι ακριβώς η ερώτηση που κάνει ένα
 * ρυθμιζόμενο δικαίωμα διαφορετικό από σημαία σε `Record<string, boolean>`.
 */
export interface OrganizationCapabilityRecord {
  readonly status: CapabilityStatus;
  /** Τι εκκρεμεί — **κενό** όταν δεν εκκρεμεί τίποτα. */
  readonly requirements: readonly CapabilityRequirement[];
  /** Η δήλωση, όταν έχει κατατεθεί. */
  readonly declaration: BrokerageDeclaration | null;
  /** Ποιος αποφάσισε (`super_admin`) — `null` όσο δεν έχει αποφασίσει κανείς. */
  readonly decidedByUserId: string | null;
  /** ISO — πότε αποφασίστηκε. */
  readonly decidedAt: string | null;
  /**
   * **Γιατί ανακλήθηκε** — κλειδί i18n ή ελεύθερο κείμενο του διαχειριστή.
   *
   * ⚠️ Υπάρχει επειδή το `revoked` **οφείλει** να απαντά *«γιατί μου το πήρατε;»*.
   * Μια ανάκληση χωρίς λόγο είναι σιωπή που ο άνθρωπος δεν μπορεί να διορθώσει.
   */
  readonly revocationReason: string | null;
}

/** Ό,τι κρατά μια εταιρεία: **μερικός** χάρτης — ό,τι λείπει είναι `unrequested`. */
export type OrganizationCapabilities = Partial<
  Record<OrganizationCapability, OrganizationCapabilityRecord>
>;

/**
 * **Η κατάσταση μιας ικανότητας, με ρητή προεπιλογή.**
 *
 * 🔑 **Η ΑΠΟΥΣΙΑ ΕΧΕΙ ΟΝΟΜΑ: `unrequested`.** Χωρίς αυτή τη συνάρτηση κάθε καλών θα
 * έγραφε δικό του `?? something` — δηλαδή θα γεννιόταν ξανά η σκορπισμένη απόφαση
 * που το ADR-801 μάζεψε. Και η προεπιλογή **δεν** είναι `revoked`: *«κανείς δεν
 * ζήτησε»* δεν είναι *«του το πήραμε»*.
 */
export function capabilityStatusOf(
  capabilities: OrganizationCapabilities | undefined,
  capability: OrganizationCapability,
): CapabilityStatus {
  return capabilities?.[capability]?.status ?? 'unrequested';
}
