/**
 * Οι παραβιάσεις που **δεν** μπορεί να πιάσει ο μεταγλωττιστής.
 *
 * Κλειστό σύνολο, ονομασμένο: ένας κωδικός εδώ γίνεται κλειδί i18n στη φόρμα (N.11),
 * ώστε το «γιατί δεν αποθηκεύεται» να λέγεται στον χρήστη με **τη δική του γλώσσα**
 * και **όχι** με μια γενική «σφάλμα επικύρωσης».
 */
export const DEMAND_INVARIANTS = [
  /** `seeks` κενό — «ζητώ, αλλά δεν ξέρω τι είδους συναλλαγή» ταιριάζει με τα πάντα. */
  'seeks-empty',
  /** Το ίδιο είδος δηλωμένο δύο φορές — δύο αλήθειες για ένα πράγμα. */
  'seeks-duplicated',
  /** Ζ2 με το τέλος πριν την αρχή. */
  'window-inverted',
  /** Εύρος τιμής/εμβαδού/ορόφου με το κάτω πάνω από το πάνω. */
  'range-inverted',
  /** Ακτίνα ≤ 0 — δεν είναι «εδώ ακριβώς», είναι «πουθενά». */
  'radius-not-positive',
  /** Πολύγωνο με λιγότερες από 3 κορυφές — δεν περικλείει τίποτα. */
  'outline-degenerate',
  /** Απαίτηση γειτονιάς με απόσταση ≤ 0. */
  'proximity-not-positive',
  /** Το ίδιο είδος γειτονιάς δηλωμένο δύο φορές με άλλη απόσταση. */
  'proximity-duplicated',
] as const;

export type DemandInvariant = (typeof DEMAND_INVARIANTS)[number];

/** Ελέγχει ένα εύρος `[min, max]`· `true` όταν είναι αντεστραμμένο. */
function rangeInverted(min: number | null, max: number | null): boolean {
  return min !== null && max !== null && min > max;
}

/** Οι παραβιάσεις εγκυρότητας του χωρικού άξονα. */
function placeInvariants(place: DemandPlace): DemandInvariant[] {
  if (place.kind === 'near' && !(place.radiusKm > 0)) return ['radius-not-positive'];
  if (place.kind === 'area' && place.outline.length < 3) return ['outline-degenerate'];
  return [];
}

/** Οι παραβιάσεις εγκυρότητας των αριθμητικών ευρών. */
function featureInvariants(features: DemandFeatures): DemandInvariant[] {
  const inverted =
    rangeInverted(features.priceMin, features.priceMax) ||
    rangeInverted(features.areaMin, features.areaMax) ||
    rangeInverted(features.floorMin, features.floorMax);
  return inverted ? ['range-inverted'] : [];
}

/** Οι παραβιάσεις εγκυρότητας των απαιτήσεων γειτονιάς. */
function proximityInvariants(proximity: readonly DemandProximity[]): DemandInvariant[] {
  const found: DemandInvariant[] = [];
  if (proximity.some((p) => !(p.maxMetres > 0))) found.push('proximity-not-positive');
  if (new Set(proximity.map((p) => p.kind)).size !== proximity.length) {
    found.push('proximity-duplicated');
  }
  return found;
}

/**
 * Όλες οι παραβιάσεις μιας ζήτησης, **ονομασμένες**.
 *
 * 🔑 **Επιστρέφει ΟΛΕΣ, όχι την πρώτη.** Μια φόρμα που διορθώνεται ένα σφάλμα τη φορά
 * είναι η φόρμα που η Α14 §17.2 δεσμεύτηκε να μη φτιάξει — και ο χρήστης δεν μπορεί
 * να ξέρει πόσο κοντά είναι αν του λέμε ένα-ένα.
 */
export function demandInvariantViolations(
  demand: Pick<PropertyDemand, 'seeks' | 'place' | 'timing' | 'features' | 'proximity'>,
): DemandInvariant[] {
  const found: DemandInvariant[] = [];

  if (demand.seeks.length === 0) found.push('seeks-empty');
  if (new Set(demand.seeks).size !== demand.seeks.length) found.push('seeks-duplicated');
  if (demand.timing.kind === 'window' && demand.timing.fromDate > demand.timing.toDate) {
    found.push('window-inverted');
  }

  found.push(...placeInvariants(demand.place));
  found.push(...featureInvariants(demand.features));
  found.push(...proximityInvariants(demand.proximity));

  return found;
}
