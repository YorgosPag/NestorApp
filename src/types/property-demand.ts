// =============================================================================

/**
 * **Μια ανοιχτή εντολή στην αγορά ακινήτων.**
 *
 * Το ανάλογο του *limit order*: μια δήλωση που **κάθεται και περιμένει** μέχρι να
 * εμφανιστεί το ταίριασμα (§12.2) — και, σε αντίθεση με κάθε portal, μπορεί να
 * περιμένει **προσφορά που δεν υπάρχει ακόμη** (§12.3).
 */
export interface PropertyDemand {
  /** Enterprise id (`dmnd_*`) — N.6. **Ποτέ** `addDoc`. */
  readonly id: string;

  // ── ΠΟΙΟΥ ΕΙΝΑΙ ────────────────────────────────────────────────────────────
  /**
   * Το uid που **έγραψε** την εγγραφή. **Το πεδίο απομόνωσης μισθωτή**
   * (`tenant-config.ts`, `mode: 'userId'`) — δηλαδή ένα ερώτημα χωρίς αυτό
   * μπλοκάρεται από τη CHECK 3.35, όχι από τη μνήμη κάποιου.
   */
  readonly authorUserId: string;
  /**
   * Η εταιρεία υπό την οποία ενήργησε ο συγγραφέας, όταν ενήργησε ως επαγγελματίας.
   * `null` για ιδιώτη.
   *
   * ⚠️ **Δεν είναι δεύτερο πεδίο απομόνωσης.** Είναι **απόδοση**: απαντά «*ποιος
   * γραφείο το κατέγραψε*», ώστε ο κατάλογος του γραφείου να επιβιώνει όταν ο
   * υπάλληλος φύγει. Η απομόνωση μένει **μία** — ο χρήστης.
   */
  readonly authorCompanyId: string | null;
  readonly mandate: DemandMandate;

  // ── ΟΙ ΤΕΣΣΕΡΙΣ ΑΞΟΝΕΣ ─────────────────────────────────────────────────────
  /**
   * **Τι είδους διάθεση ζητά** — `schema.org/Demand`: *«the very same properties used
   * for Offer apply»*.
   *
   * - `sell`     → θέλει να **αγοράσει**
   * - `leaseOut` → θέλει να **νοικιάσει** (ζητά κάποιον που εκμισθώνει)
   * - `exchange` → **αντιπαροχή**· εδώ ο ζητών είναι ο **εργολάβος** που ψάχνει γη
   *   (ο οικοπεδούχος που προσφέρει γη έχει `ExchangeOffer`, όχι ζήτηση)
   *
   * ⚠️ **Κενός πίνακας ΔΕΝ επιτρέπεται σημασιολογικά.** «Ζητώ, αλλά δεν ξέρω τι
   * είδους συναλλαγή» δεν είναι αίτημα — και θα ταίριαζε με **τα πάντα**, δηλαδή θα
   * γέμιζε τον θερμοχάρτη με θόρυβο. Επιβάλλεται στην πύλη γραφής
   * ({@link demandInvariantViolations}).
   */
  readonly seeks: readonly OfferKind[];
  readonly place: DemandPlace;
  readonly timing: DemandTiming;
  readonly features: DemandFeatures;
  /** **Ζ6**. Κενό = καμία απαίτηση γειτονιάς. */
  readonly proximity: readonly DemandProximity[];

  // ── Ζ7 — ΔΗΛΩΜΕΝΟ, ΠΟΤΕ ΚΡΙΤΗΡΙΟ ──────────────────────────────────────────
  readonly lifeContext: DemandLifeContext | null;

  // ── ΚΑΤΑΣΤΑΣΗ ──────────────────────────────────────────────────────────────
  readonly lifecycle: DemandLifecycle;
  /**
   * 🔴 **Η ΤΕΛΕΥΤΑΙΑ ΦΟΡΑ ΠΟΥ Ο ΑΝΘΡΩΠΟΣ ΕΙΠΕ «ΨΑΧΝΩ ΑΚΟΜΗ»** — ISO timestamp.
   *
   * **Δεν είναι `updatedAt`.** Το `updatedAt` αλλάζει και όταν ο μεσίτης διορθώσει ένα
   * τηλέφωνο· αυτό αλλάζει **μόνο** όταν κάποιος επιβεβαιώσει την **πρόθεση**. Δύο
   * ερωτήσεις, δύο πεδία — αλλιώς κάθε διοικητική αλλαγή θα «φρεσκάριζε» ψεύτικα μια
   * νεκρή ζήτηση.
   *
   * Μετά από {@link DEMAND_AFFIRMATION_TTL_DAYS} ημέρες σιωπής η ζήτηση **βγαίνει από
   * το ανώνυμο άθροισμα** (επίπεδο Γ) — και **μόνο** από εκεί. Δεν σβήνεται, δεν
   * κρύβεται από τον κάτοχό της, και **ξαναμπαίνει με ένα κλικ**.
   */
  readonly affirmedAt: string;

  // ── ΜΕΤΑΔΕΔΟΜΕΝΑ ───────────────────────────────────────────────────────────
  readonly createdAt: string;
  readonly updatedAt: string;
}

/**
 * 🔴 **Πόση σιωπή πριν πάψει να μετράει στο επίπεδο Γ.**
 *
 * **Απόφαση Giorgio (2026-08-11): 3 μήνες.** Ο λόγος είναι η διάρκεια της ίδιας της
 * πράξης — στην Ελλάδα μια αγοραπωλησία κλείνει τυπικά σε 2–4 μήνες, άρα στους 3 οι
 * περισσότεροι έχουν κριθεί προς τη μία ή την άλλη κατεύθυνση.
 *
 * ⚠️ **Ο αριθμός αφορά ΜΟΝΟ το άθροισμα.** Η ζήτηση του χρήστη είναι δική του για
 * πάντα· αυτό που παλιώνει είναι ο **ισχυρισμός μας προς τρίτους** ότι κάποιος
 * ψάχνει. Ένα προϊόν (Ε2) που μετρά ζητήσεις δύο ετών δεν είναι αισιόδοξο — **λέει
 * ψέματα** στον εργολάβο που πάνω του χτίζει.
 */
export const DEMAND_AFFIRMATION_TTL_DAYS = 90;

