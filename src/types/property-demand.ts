/** `true` αν το `value` είναι γνωστός κύκλος ζωής ζήτησης. */
export function isDemandLifecycle(value: unknown): value is DemandLifecycle {
  return (
    typeof value === 'string' && (DEMAND_LIFECYCLES as readonly string[]).includes(value)
  );
}

/** `true` αν το `value` είναι γνωστό πλαίσιο ζωής. */
export function isDemandLifeContext(value: unknown): value is DemandLifeContext {
  return (
    typeof value === 'string' &&
    (DEMAND_LIFE_CONTEXTS as readonly string[]).includes(value)
  );
}

/** `true` αν η εντολή ψάχνει ενεργά **αυτή τη στιγμή** (ανεξάρτητα από φρεσκάδα). */
export function isLiveDemand(demand: PropertyDemand): boolean {
  return (LIVE_DEMAND_LIFECYCLES as readonly string[]).includes(demand.lifecycle);
}

/**
 * `true` αν η εντολή είναι **ισχυρισμός για πραγματικό άνθρωπο** — δηλαδή είτε την
 * έγραψε ο ίδιος, είτε την **επιβεβαίωσε**.
 *
 * 🔴 Ο μοναδικός φρουρός του Ε2 απέναντι στο φούσκωμα του θερμοχάρτη. Εξάγεται ώστε
 * να μη γραφτεί δεύτερη φορά ως `mandate.kind === 'self' || …` στο σημείο χρήσης.
 */
export function isAttributableDemand(demand: PropertyDemand): boolean {
  return demand.mandate.kind === 'self' || demand.mandate.confirmation === 'confirmed';
}

