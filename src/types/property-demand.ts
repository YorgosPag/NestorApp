/**
 * **Πότε** το θέλει — ο άξονας που **δεν υπάρχει σε κανένα portal** (§12.3).
 *
 * 🏆 Εδώ ξεπερνάμε το πρότυπο με μετρημένο τρόπο: το `SavedSearch` του RESO έχει
 * `OriginalEntryTimestamp` και `ModificationTimestamp` — **πότε γράφτηκε η αναζήτηση**
 * — και **κανένα** πεδίο για το **πότε χρειάζεται το ακίνητο**. Οι δύο ερωτήσεις
 * μοιάζουν συγγενικές και είναι **άσχετες**: η πρώτη είναι μεταδεδομένο εγγραφής, η
 * δεύτερη είναι **ο όρος του ταιριάσματος**.
 */
export type DemandTiming =
  /** **Ζ1** — «τώρα». Ταιριάζει με ό,τι είναι διαθέσιμο σήμερα. */
  | { readonly kind: 'now' }
  /**
   * **Ζ2** — «*ενοικίαση από Μάρτιο 2027 έως Ιούνιο 2028*».
   *
   * ⚠️ **Ημερομηνίες ISO (`YYYY-MM-DD`), όχι `Timestamp`.** Το παράθυρο είναι
   * **πρόθεση ανθρώπου σε ημερολόγιο**, όχι στιγμή σε ρολόι: το «Μάρτιος 2027»
   * δεν έχει ώρα και δεν έχει ζώνη ώρας, και ένα `Timestamp` θα του **επινοούσε**
   * και τα δύο — με το αποτέλεσμα να αλλάζει μέρα ανάλογα με το πού στέκεται ο
   * αναγνώστης.
   */
  | { readonly kind: 'window'; readonly fromDate: string; readonly toDate: string }
  /**
   * **Ζ3** — «*όποτε κι αν βγει*».
   *
   * 🔴 **Αυτή η τιμή είναι ο λόγος που η ζήτηση ΔΕΝ ΕΧΕΙ ημερομηνία λήξης.** Μια
   * υποχρεωτική λήξη θα έκανε τη Ζ3 **δομικά ανέκφραστη**. Το πρόβλημα της
   * μπαγιάτικης ζήτησης λύνεται **αλλού και αλλιώς** — βλ.
   * {@link PropertyDemand.affirmedAt}: η ζήτηση **δεν λήγει ποτέ**· παύει μόνο να
   * **μετράει στο ανώνυμο άθροισμα**.
   */
  | { readonly kind: 'whenever' };

