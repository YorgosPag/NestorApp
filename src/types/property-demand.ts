export type DemandInvariant = (typeof DEMAND_INVARIANTS)[number];

/** Ελέγχει ένα εύρος `[min, max]`· `true` όταν είναι αντεστραμμένο. */
function rangeInverted(min: number | null, max: number | null): boolean {
  return min !== null && max !== null && min > max;
}

/** Οι παραβιάσεις εγκυρότητας του χωρικού άξονα. */
function placeInvariants(place: DemandPlace): DemandInvariant[] {
  if (place.kind === 'near' && !(place.radiusKm > 0)) return ['radius-not-positive'];
  if (place.kind === 'area' && place.outline.length < 3) return ['outline-degenerate'];
  if (place.kind === 'frontage') return frontageInvariants(place);
  return [];
}

/**
 * Οι δύο τρόποι που ένα μέτωπο είναι **μη κρίσιμο**.
 *
 * 🔑 **Και οι δύο επιστρέφονται μαζί, όχι ο πρώτος που βρέθηκε.** Ένας άξονας χωρίς
 * φορά **και** μηδενικό βάθος είναι δύο ανεξάρτητα λάθη· λέγοντας μόνο το ένα, ο
 * χρήστης το διορθώνει και ξαναχτυπά τοίχο. Ο κλάδος `near`/`area` παραπάνω επιστρέφει
 * έναν κωδικό επειδή **έχει** έναν, όχι επειδή αρκεί ένας.
 */
function frontageInvariants(place: Extract<DemandPlace, { kind: 'frontage' }>): DemandInvariant[] {
  const violations: DemandInvariant[] = [];

  // Ο τύπος εγγυάται ≥2 κορυφές· εδώ κρίνεται αν ορίζουν **διεύθυνση**.
  const [origin] = place.axis;
  const hasDirection = place.axis.some(
    (vertex) => vertex.lat !== origin.lat || vertex.lng !== origin.lng,
  );
  if (!hasDirection) violations.push('axis-degenerate');

  if (!(place.depthMetres > 0)) violations.push('depth-not-positive');

  return violations;
}

/**
 * Οι παραβιάσεις εγκυρότητας των αριθμητικών ευρών — εμβαδόν, όροφος **και** το ποσό **κάθε**
 * εναλλακτικής (ADR-777 §8.60.15: η τιμή ζει πια στο {@link DemandSeek}, όχι στα χαρακτηριστικά).
 */
function rangeInvariants(features: DemandFeatures, seeks: readonly DemandSeek[]): DemandInvariant[] {
  const inverted =
    seeks.filter(isPricedSeek).some((seek) => rangeInverted(seek.price.min, seek.price.max)) ||
    seeks.filter(isShortStaySeek).some((seek) => rangeInverted(seek.nights.min, seek.nights.max)) ||
    rangeInverted(features.areaMin, features.areaMax) ||
    rangeInverted(features.floorMin, features.floorMax);
  return inverted ? ['range-inverted'] : [];
}

/** Οι παραβιάσεις εγκυρότητας των απαιτήσεων γειτονιάς. */
function proximityInvariants(proximity: readonly DemandProximity[]): DemandInvariant[] {
  const found: DemandInvariant[] = [];
  if (proximity.some((p) => !(p.maxMetres > 0))) found.push('proximity-not-positive');
  if (new Set(proximity.map((p) => p.kind)).size !== proximity.length) {
    found.push('proximity-duplicated');
  }
  return found;
}

/**
 * Όλες οι παραβιάσεις μιας ζήτησης, **ονομασμένες**.
 *
 * 🔑 **Επιστρέφει ΟΛΕΣ, όχι την πρώτη.** Μια φόρμα που διορθώνεται ένα σφάλμα τη φορά
 * είναι η φόρμα που η Α14 §17.2 δεσμεύτηκε να μη φτιάξει — και ο χρήστης δεν μπορεί
 * να ξέρει πόσο κοντά είναι αν του λέμε ένα-ένα.
 */
export function demandInvariantViolations(
  demand: Pick<PropertyDemand, 'seeks' | 'place' | 'timing' | 'features' | 'proximity'>,
): DemandInvariant[] {
  const found: DemandInvariant[] = [];

  if (demand.seeks.length === 0) found.push('seeks-empty');
  // 🔴 Σύνολο πάνω στα **ΕΙΔΗ**, ποτέ στα στοιχεία: με αντικείμενα κάθε `Set` είναι μοναδικό
  //    ⇒ το `seeks-duplicated` θα σώπαινε **για πάντα**, χωρίς κανένα κόκκινο (ADR-777 §8.60.15).
  const kinds = seekKindsOf(demand.seeks);
  if (new Set(kinds).size !== kinds.length) found.push('seeks-duplicated');
  if (demand.timing.kind === 'window' && demand.timing.fromDate > demand.timing.toDate) {
    found.push('window-inverted');
  }

  found.push(...placeInvariants(demand.place));
  found.push(...rangeInvariants(demand.features, demand.seeks));
  found.push(...proximityInvariants(demand.proximity));
  const outOfRange = demand.seeks
    .filter(isExchangeSeek)
    .some((seek) => seek.landownerShareMax !== null && !isLandownerShareInRange(seek.landownerShareMax));
  if (outOfRange) found.push('exchange-share-out-of-range');
  found.push(...stayInvariants(demand.seeks, demand.timing));

  return found;
}

/** Ένας αριθμός ανθρώπων που **μπορεί** να είναι μηδέν (παιδιά · βρέφη) — ακέραιος, όχι αρνητικός. */
function isHeadcountPart(value: number): boolean {
  return Number.isInteger(value) && value >= 0;
}

/**
 * Οι παραβιάσεις των όρων διαμονής (ADR-777 §8.60.19) — **όλες**, όχι η πρώτη.
 *
 * 🔑 Το παράθυρο μετρά **νύχτες** ως ημι-ανοιχτό `[από, έως)` — η σύμβαση του `ListingStayWindow`
 * (η μέρα αναχώρησης **δεν** είναι νύχτα διαμονής).
 */
function stayInvariants(seeks: readonly DemandSeek[], timing: DemandTiming): DemandInvariant[] {
  const found: DemandInvariant[] = [];
  const stay = seeks.find(isShortStaySeek);
  if (stay === undefined) return found;

  const { min, max } = stay.nights;
  if ([min, max].some((value) => value !== null && !isWholeStayCount(value))) {
    found.push('stay-nights-invalid');
  }
  if (min !== null && timing.kind === 'window') {
    const windowNights = daysBetweenDateKeys(timing.fromDate, timing.toDate);
    if (windowNights !== null && windowNights >= 0 && min > windowNights) {
      found.push('stay-nights-exceed-window');
    }
  }

  const { party } = stay;
  const partyValid =
    party === null ||
    (isWholeStayCount(party.adults) &&
      isHeadcountPart(party.children) &&
      isHeadcountPart(party.infants) &&
      // ADR-777 §8.60.21 — 0 (κανένα) ή ακέραιος 1..5, το ίδιο ταβάνι με τον κάτοχο.
      (party.pets === 0 || isWholePetCount(party.pets)));
  if (!partyValid) found.push('stay-party-invalid');

  return found;
}
