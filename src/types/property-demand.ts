/**
 * @fileoverview **Η ΖΗΤΗΣΗ** — ισότιμη με την προσφορά, οντότητα πρώτης τάξεως (Α9).
 * @related ADR-777 §7 (Α9 · Α12 · Α14 · Α20) · SPEC-777B §12 · SPEC-777A §14.2
 * @module types/property-demand
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΙ ΔΕΝ ΕΙΝΑΙ ΑΥΤΟ — και το πρότυπο του κλάδου είναι ΑΚΡΙΒΩΣ αυτό που αποφεύγουμε
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το **RESO Data Dictionary 2.0** — το παγκόσμιο πρότυπο ακινήτων, **41 πόροι** και
 * πάνω από **1.700 πεδία** — **δεν έχει οντότητα ζήτησης**. Έχει δύο πράγματα, και τα
 * δύο είναι η άρνησή της (μετρημένο στο `dd.reso.org/DD2.0`, 2026-08-11):
 *
 *   - `SavedSearch` (**27** πεδία), όπου τα κριτήρια ζουν σε **μία συμβολοσειρά
 *     OData** (`SearchQuery` · `SearchQueryHumanReadable`) — δηλαδή **αδιαφανές
 *     κείμενο**, όχι μοντέλο·
 *   - `Prospecting`, που ορίζεται κατά λέξη ως *«automatic email connecting Contacts
 *     and SavedSearch resources to send results matching saved search criteria»*.
 *
 * Δηλαδή: **η ζήτηση είναι αποθηκευμένο φίλτρο δεμένο σε ρομπότ αλληλογραφίας.**
 * Αυτό είναι, λέξη προς λέξη, το πράγμα που το SPEC-777B §12.2 απαγορεύει:
 * *«**ανοιχτή εντολή** σε αγορά … όχι ερώτημα αναζήτησης που εκτελείται όταν κάποιος
 * πατήσει κουμπί»*.
 *
 * Και οι συνέπειες είναι **μετρήσιμες, όχι υφολογικές** — στο `SavedSearch` λείπουν:
 *
 * | Μορφή | Τι λείπει από το πρότυπο |
 * |---|---|
 * | **Ζ2** μελλοντικό παράθυρο | κανένα πεδίο για το **πότε** χρειάζεται το ακίνητο |
 * | **Ζ4** σχεδιασμένη περιοχή | καμία γεωμετρία / πολύγωνο |
 * | **Ζ6** γειτονιά | καμία απαίτηση εγγύτητας σε σημεία ενδιαφέροντος |
 *
 * 🔑 **Και υπάρχει βαθύτερος λόγος από τα τρία κενά:** μια **συμβολοσειρά ερωτήματος
 * αποτιμάται· δεν κρατιέται.** Ένα `SavedSearch` **δομικά δεν μπορεί** να συναντήσει
 * προσφορά που θα υπάρξει τον Σεπτέμβριο 2027, γιατί τρέχει σήμερα πάνω σε ό,τι
 * υπάρχει σήμερα. Το §12.3 ζητά **ακριβώς** το αντίθετο.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ✅ ΤΟ ΠΡΟΤΥΠΟ ΠΟΥ ΑΚΟΛΟΥΘΕΙΤΑΙ: `schema.org/Demand`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το schema.org **έχει** την οντότητα, ως ισότιμη του `Offer`, και τη δηλώνει έτσι:
 *
 *   > *«A demand entity represents the public, not necessarily binding, not
 *   > necessarily exclusive, announcement by an organization or person to seek a
 *   > certain type of goods or services. **For describing demand using this type, the
 *   > very same properties used for Offer apply.**»*
 *
 * Αυτό **δεν είναι διακοσμητική παραπομπή — καθορίζει τον πρώτο άξονα**. Επειδή τα
 * ίδια χαρακτηριστικά ισχύουν, η ζήτηση **δεν αποκτά δικό της λεξιλόγιο συναλλαγής**:
 * ζητά {@link OfferKind}, το **ίδιο** κλειστό σύνολο που δηλώνει η προσφορά (βλ.
 * {@link PropertyDemand.seeks}). Ένα καθρεφτισμένο λεξιλόγιο (`buy`/`leaseIn`/…) θα
 * ήταν **δεύτερη αλήθεια για τον ίδιο άξονα** — το σχήμα του ADR-749 — και θα
 * απαιτούσε πίνακα μετάφρασης που **μπορεί να αποκλίνει**. Εδώ το ταίριασμα είναι
 * τομή συνόλων, δηλαδή **δεν υπάρχει τι να αποκλίνει**.
 *
 * *(Το ίδιο πρότυπο διάλεξε ήδη το `types/property-offers.ts` για τα `sell`/`leaseOut`:
 * είναι κυριολεκτικά τιμές του `schema.org/BusinessFunction`. Και η σχέση
 * προσώπου→ζήτησης λέγεται εκεί **`seeks`** — εξ ου και το όνομα του πεδίου.)*
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΟΙ ΟΚΤΩ ΜΟΡΦΕΣ ΔΕΝ ΕΙΝΑΙ ΟΚΤΩ ΠΕΔΙΑ — ΕΙΝΑΙ **ΤΕΣΣΕΡΙΣ ΑΞΟΝΕΣ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ίδιο το §12.2 ονομάζει την τομή: `ΧΩΡΟΣ ∩ ΧΡΟΝΟΣ ∩ ΧΑΡΑΚΤΗΡΙΣΤΙΚΑ ∩ ΓΕΙΤΟΝΙΑ`.
 * Οι Ζ1–Ζ8 **αποσυντίθενται** πάνω σε αυτούς — δεν αντιστοιχίζονται ένα προς ένα:
 *
 * | Μορφή | ΧΩΡΟΣ | ΧΡΟΝΟΣ | ΧΑΡΑΚΤ. | ΓΕΙΤΟΝΙΑ |
 * |---|---|---|---|---|
 * | **Ζ1** τωρινή            | `near`     | `now`      | — | — |
 * | **Ζ2** παράθυρο          | `near`     | `window`   | — | — |
 * | **Ζ3** «όποτε κι αν βγει»| `place`    | `whenever` | — | — |
 * | **Ζ4** τμήμα δρόμου      | `area`     | —          | — | — |
 * | **Ζ5** οικοδομή & όροφος | `place`    | —          | `floor` | — |
 * | **Ζ6** γειτονιά          | —          | —          | — | ✅ |
 * | **Ζ8** χαρακτηριστικά    | —          | —          | ✅ | — |
 *
 * Δηλαδή **Ζ1 και Ζ2 είναι δύο τιμές ΕΝΟΣ άξονα**, και **Ζ3/Ζ5 είναι συνδυασμοί
 * δύο**. Οκτώ οντότητες — ή οκτώ σημαίες — θα ήταν το λάθος που η **Α20** πλήρωσε ήδη
 * μία φορά (§8.5: τρίτο είδος συναλλαγής ως όγδοη κατάσταση ⇒ **2³−1 = 7** listed
 * τιμές αντί για 3). Και θα ήταν αδύνατο να εκφραστεί το προφανές: «*αυτό το κτίριο,
 * 3ος όροφος, από τον Μάρτιο, κοντά σε σχολείο*» είναι **ένα** αίτημα και αγγίζει
 * **και τους τέσσερις** άξονες ταυτόχρονα.
 *
 * ⚠️ **Η Ζ7 ΔΕΝ ΕΙΝΑΙ ΠΕΜΠΤΟΣ ΑΞΟΝΑΣ — βλ. {@link DemandLifeContext}.**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΠΟΥ ΖΕΙ ΑΥΤΟ ΤΟ ΕΓΓΡΑΦΟ: **ΕΠΙΠΕΔΟ Β** (Α12 / SPEC-777A §14.2)
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το §14.2 ονομάζει τη ζήτηση **ρητά** στο επίπεδο Β: *«τι πουλά/νοικιάζει ο καθένας,
 * τιμές, όροι, πελάτες, **ζητήσεις** — αυστηρά ιδιωτικό ανά εταιρεία/χρήστη»*. Άρα:
 *
 * - **Δεν είναι `public-world`**: υπάρχει επειδή κάποιος το αποφάσισε, όχι επειδή
 *   είναι αληθές ανεξάρτητα από κάθε λογαριασμό (§14.1).
 * - **Δεν είναι `published-projection`**: κανείς δεν το «δημοσιεύει». Ό,τι φτάνει σε
 *   τρίτους είναι το **επίπεδο Γ** — το **ανώνυμο άθροισμα**, που **παράγεται** και
 *   δεν γράφεται (`lib/demand/demand-aggregate.ts`).
 * - Άρα είναι **tenant-scoped σε ΧΡΗΣΤΗ** (`mode: 'userId'`), όπως ήδη τα
 *   `NOTIFICATIONS` — και **όχι** σε εταιρεία: μια ζήτηση ανήκει σε **άνθρωπο**.
 *
 * 🔴 **Το προϊόν Ε2 πουλά το επίπεδο Γ, ΟΧΙ αυτό το έγγραφο.** Το SPEC-777-RESEARCH
 * §15.5 το γράφει ονομαστικά: *«Ε2 — η ζήτηση (**επίπεδο Γ, §14.2**) ως προϊόν»*.
 * Καμία διαδρομή δεν δίνει σε τρίτο ένα {@link PropertyDemand}.
 *
 * **Layering**: leaf module — καμία εξάρτηση από components/hooks/services.
 *
 * @enterprise ADR-777 Α9 — η ζήτηση είναι ισότιμη με την προσφορά
 */

