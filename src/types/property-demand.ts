/**
 * **Πού** ψάχνει — διακριτή ένωση, ποτέ επίπεδο αντικείμενο με προαιρετικά πεδία.
 *
 * 🔑 **Ο λόγος είναι ο ίδιος με το {@link PlacePosition}**: ένα `outline` δίπλα σε ένα
 * `radiusKm` δίπλα σε ένα `buildingId` είναι **τρεις αμοιβαία αποκλειόμενες**
 * απαντήσεις που ο τύπος επιτρέπει να συνυπάρξουν — και τότε κάθε καταναλωτής
 * αποφασίζει **μόνος του** ποια νικά. Εδώ η σύγκρουση **δεν μεταγλωττίζεται**.
 *
 * ⚠️ Το `anywhere` **δεν είναι απουσία, είναι απάντηση**: «*δεν με νοιάζει πού, με
 * νοιάζει τι*» είναι νόμιμη ζήτηση (καθαρή **Ζ8**), και είναι **διαφορετική** από
 * «*δεν με ρώτησε κανείς*». Η δεύτερη δεν μπορεί να υπάρξει: το πεδίο είναι
 * υποχρεωτικό, δηλαδή η ερώτηση **τίθεται πάντα** — ίδιο συμβόλαιο με το
 * *«υποχρεωτικό ΕΡΩΤΗΜΑ, όχι υποχρεωτική ΑΠΑΝΤΗΣΗ»* της Α5.
 */
export type DemandPlace =
  /** Καθαρή Ζ8 — τα χαρακτηριστικά μετράνε, η θέση όχι. */
  | { readonly kind: 'anywhere' }
  /**
   * **Ζ1/Ζ2** — σημείο και ακτίνα.
   *
   * 🔑 **Η «ταυτότητα» είναι πλέον ΤΥΠΟΣ, όχι σχόλιο** *(ADR-777 §8.53)*. Αυτή η
   * γραμμή έγραφε *«το **ίδιο** σχήμα με το `ListingGeoFilter`»* και το ξανάγραφε με
   * το χέρι — δηλαδή η υπόσχεση ζούσε σε **πρόζα** που τίποτα δεν επαλήθευε, και θα
   * έσπαγε σιωπηλά την πρώτη φορά που η μία πλευρά αποκτούσε τρίτο πεδίο. Τώρα είναι
   * **το ίδιο** {@link GeoCircle}, άρα η προβολή προς τα φίλτρα είναι ταυτότητα
   * **επειδή δεν μπορεί να μην είναι**.
   */
  | ({ readonly kind: 'near' } & GeoCircle)
  /**
   * **Ζ4** — «*Μεγάλου Αλεξάνδρου, αλλά **μόνο αυτό το κομμάτι** της*». Το περίγραμμα
   * το σχεδιάζει ο άνθρωπος με το **υπάρχον** σύστημα πολυγώνων του Geo-Canvas.
   *
   * ⚠️ Προέλευση **πάντα** ανθρώπινη ⇒ επιτρέπεται αποθήκευση σχήματος. Περίγραμμα
   * **αντλημένο από OSM δεν επιτρέπεται να καταλήξει εδώ** (ODbL, SPEC-777A §13.4):
   * ο τύπος δεν μπορεί να το εμποδίσει, ο **γραφέας** οφείλει.
   */
  | { readonly kind: 'area'; readonly outline: GeoOutline }
  /**
   * **Ζ3/Ζ5** — «*αυτή η πολυκατοικία*» / «*το κατάστημα στη γωνία*».
   *
   * 🔴 **Δείχνει στο ΕΠΙΠΕΔΟ Α, και αυτός είναι όλος ο λόγος που το επίπεδο Α
   * υπάρχει** (SPEC-777A §14.5: *«μία ταυτότητα ανά φυσικό κτίριο … το ταίριασμα
   * γίνεται δυνατό **επειδή** το Α είναι ένα»*).
   *
   * ⚠️ **ΠΟΤΕ OSM id** (§13.2): τα OSM id αλλάζουν όταν εθελοντές ξανασχεδιάζουν, και
   * μια ζήτηση κρεμασμένη εκεί **εξαφανίζεται σιωπηλά**.
   *
   * ⚠️ Το `buildingId` είναι προαιρετικό γιατί η **γη** αρκεί: «*ζητώ οικόπεδο για
   * αντιπαροχή σε αυτό το τετράγωνο*» δεν έχει κτίριο, και **δεν πρέπει** να αναγκαστεί
   * να επινοήσει ένα.
   */
  | {
      readonly kind: 'place';
      /** FK → `PublicLand` (`land_*`). **Υποχρεωτικό** — η γη κρατά τη θέση (Α1). */
      readonly landId: string;
      /** FK → `PublicBuilding` (`pbld_*`), όταν το αίτημα αφορά το κτίριο. */
      readonly buildingId: string | null;
    }
  /**
   * **Ζ4 δομημένη** — «*η νότια πλευρά της Μεγάλου Αλεξάνδρου, μόνο αυτά τα 200 μέτρα*».
   *
   * 🔴 **ΓΙΑΤΙ ΔΕΝ ΑΡΚΕΙ ΤΟ `area`, ΕΝΩ ΤΟ ΣΧΗΜΑ ΤΟ ΕΠΙΤΡΕΠΕΙ.** Ένα λεπτό πολύγωνο
   * κολλημένο στη μία πλευρά **μοιάζει** να απαντά, και γι' αυτό είναι επικίνδυνο: ο
   * δακτύλιος απαντά «*μέσα;*», ενώ η ερώτηση εδώ είναι «*ποια πλευρά;*». Οι δύο
   * ερωτήσεις συμπίπτουν **μόνο** όσο το σχέδιο είναι ακριβέστερο από το πλάτος του
   * δρόμου — δηλαδή **ποτέ** σε πραγματικά δεδομένα (δρόμος 8–20 μ., γεωκωδικοποίηση
   * χειρότερη). Ζωγραφισμένο πολύγωνο θα έκρινε **τυχαία, και σιωπηλά**.
   *
   * Εδώ η πλευρά είναι **δηλωμένο πεδίο**, άρα η μηχανή μπορεί να πει «*δεν ξέρω*»
   * (`side-unresolved`) αντί να μαντέψει — και αυτή η δυνατότητα είναι όλος ο λόγος
   * που η μορφή υπάρχει χωριστά (Α5: **ποτέ άγνοια μεταμφιεσμένη σε ισχυρισμό**).
   *
   * ⚠️ Το `area` **δεν καταργείται**: παραμένει η απάντηση για «*αυτό το τετράγωνο*»,
   * «*πίσω από το πάρκο*» — σχήματα που **δεν** είναι μέτωπο δρόμου.
   */
  | {
      readonly kind: 'frontage';
      /**
       * Το όνομα της οδού, όπως το είπε ο άνθρωπος. **Ποτέ αυθεντία** — ετικέτα για
       * την οθόνη. Ο άξονας κρίνει, το όνομα εξηγεί. `null` όταν δεν το έδωσε: ένας
       * δρόμος χωρίς όνομα εξακολουθεί να είναι δρόμος.
       *
       * ✅ Επιτρέπεται ρητά από το OSMF Geocoding Guideline (*«names, addresses…»*).
       */
      readonly streetName: string | null;
      /**
       * Ο άξονας του τμήματος — **ανθρώπινη χειρονομία**, ποτέ αντλημένος από OSM
       * (§13.4). Δίνει ταυτόχρονα **πού αρχίζει**, **πού τελειώνει** και **προς τα πού
       * κοιτά** — τα τρία που χρειάζεται η έννοια «πλευρά».
       */
      readonly axis: GeoPolyline;
      /**
       * 🔑 **ΑΡΙΣΤΕΡΑ/ΔΕΞΙΑ ΩΣ ΠΡΟΣ ΤΗ ΦΟΡΑ ΤΟΥ ΑΞΟΝΑ — ΠΟΤΕ «ΝΟΤΙΑ».**
       *
       * Η πυξίδα μοιάζει φυσικότερη και **είναι λάθος**: δρόμος 2 χλμ. στρίβει, και η
       * «νότια πλευρά» αλλάζει νόημα στη μέση του — δηλαδή το αποθηκευμένο πεδίο θα
       * περιέγραφε **δύο διαφορετικά πράγματα** στα δύο άκρα της ίδιας ζήτησης. Η
       * χειρονομία («πάτησα *εκεί*») είναι μονοσήμαντη σε **κάθε** σημείο του άξονα.
       *
       * Η λέξη «νότια» **παράγεται** από τη διόπτευση για την οθόνη. Το μάθημα είναι
       * του ADR-769: το δέσιμο με την **ανθρώπινη ονομασία** είναι ο λόγος που σπάει.
       */
      readonly side: FrontageSide;
      /**
       * Πόσο **βαθιά** από τον άξονα μετράει ακόμη ως «πάνω στον δρόμο», σε μέτρα.
       *
       * ⚠️ **Δεν είναι διακοσμητικό**: χωρίς βάθος, «πάνω στον δρόμο» θα σήμαινε
       * «πάνω στη γραμμή», και **κάθε** κτίριο θα ήταν εκτός. Το κατάστημα θέλει 20 μ.,
       * το οικόπεδο για αντιπαροχή ίσως 80 — γι' αυτό το ορίζει ο άνθρωπος.
       */
      readonly depthMetres: number;
    };

/**
 * Ποια πλευρά του άξονα ζητά ο άνθρωπος.
 *
 * ⚠️ **Δεν είναι το ίδιο σύνολο με τη γεωμετρική απάντηση.** Η γεωμετρία απαντά
 * `'left' | 'right' | 'on'` για ένα **σημείο** (γεγονός). Εδώ δηλώνεται **αίτημα**,
 * και το `'both'` είναι νόμιμο αίτημα («*όλο το μέτωπο, και οι δύο πλευρές*») ενώ δεν
 * είναι ποτέ γεγονός. Ένα κοινό enum για τα δύο θα επέτρεπε σε αίτημα να εμφανιστεί
 * ως μέτρηση — το σχήμα που ο {@link DemandPlace} υπάρχει για να απαγορεύει.
 */
export const FRONTAGE_SIDES = ['left', 'right', 'both'] as const;

export type FrontageSide = (typeof FRONTAGE_SIDES)[number];

