/**
 * Πού βρίσκεται η εντολή.
 *
 * ⚠️ **Δεν υπάρχει `expired`, και είναι σκόπιμο** — για τον **ίδιο** λόγο που το
 * `OFFER_LIFECYCLES` δεν έχει `draft`: καμία διαδρομή δεν μπορεί να το παραγάγει.
 * Η **Ζ3** («όποτε κι αν βγει») απαγορεύει τη λήξη, οπότε μια κατάσταση «έληξε» θα
 * ήταν φρουρός που **δεν μπορεί να πυροδοτήσει**. Η παλαίωση εκφράζεται ως
 * **φρεσκάδα** ({@link PropertyDemand.affirmedAt}), που είναι **αναστρέψιμη με ένα
 * κλικ** — και αυτό είναι διαφορετικό πράγμα από κατάσταση κύκλου ζωής.
 */
export const DEMAND_LIFECYCLES = ['active', 'paused', 'fulfilled', 'withdrawn'] as const;

export type DemandLifecycle = (typeof DEMAND_LIFECYCLES)[number];

/**
 * Οι καταστάσεις όπου η εντολή **ψάχνει ενεργά**.
 *
 * `paused` = «σταμάτα να μου στέλνεις, αλλά κράτα την» — ρητή επιλογή του ανθρώπου,
 * και **γι' αυτό** δεν είναι το ίδιο με τη σιωπή που μετρά το {@link affirmedAt}.
 */
export const LIVE_DEMAND_LIFECYCLES = ['active'] as const satisfies readonly DemandLifecycle[];

