/**
 * **Ζ7** — «οικογένεια / μόνος για εργασία / φοιτητής».
 *
 * 🔴 **ΔΕΝ ΕΙΝΑΙ ΠΕΜΠΤΟΣ ΑΞΟΝΑΣ, ΚΑΙ ΤΟ ΤΑΙΡΙΑΣΜΑ ΔΕΝ ΤΟ ΚΟΙΤΑΖΕΙ ΠΟΤΕ.**
 *
 * Δοκιμάστηκε ως άξονας και **απορρίφθηκε με επιχείρημα, όχι με γούστο**: μια
 * *οικογένεια* σημαίνει «≥2 υπνοδωμάτια, κοντά σε σχολείο»· ένας *φοιτητής* σημαίνει
 * «μικρό, φθηνό, κοντά σε στάση». Δηλαδή το πλαίσιο ζωής είναι **συμπίεση με απώλειες
 * των άλλων τεσσάρων αξόνων**. Αν γινόταν κριτήριο ταιριάσματος, θα υπήρχαν **δύο
 * αρχές** που απαντούν «*ταιριάζει;*» — μία ρητή (τα πεδία) και μία υπονοούμενη (η
 * ετικέτα) — και θα διαφωνούσαν στην πρώτη οικογένεια που θέλει γκαρσονιέρα.
 * Είναι, κατά γράμμα, το σχήμα του **ADR-749**.
 *
 * ✅ **Ο πραγματικός του ρόλος είναι Α14 §17.2 κανόνας 3**: *«η φόρμα **μικραίνει**
 * όσο δίνεις περισσότερα»*. Το πλαίσιο ζωής **προτείνει** τιμές για τους τέσσερις
 * άξονες, ο άνθρωπος τις **βλέπει και τις αλλάζει**, και ό,τι μείνει είναι **ρητό**.
 * Δεύτερος ρόλος: τροφοδοτεί το **επίπεδο Γ** («*ποιος ψάχνει εδώ*»), που είναι
 * πληροφορία για τον εργολάβο και **όχι** όρος για την αγγελία.
 *
 * ⚠️ `null` = δεν το δήλωσε. **Δεν υπάρχει τιμή «άλλο»** — θα ήταν κάδος που δεν
 * προτείνει τίποτα και δεν λέει τίποτα, δηλαδή πεδίο χωρίς καταναλωτή.
 */
export const DEMAND_LIFE_CONTEXTS = ['family', 'workRelocation', 'student'] as const;

export type DemandLifeContext = (typeof DEMAND_LIFE_CONTEXTS)[number];

