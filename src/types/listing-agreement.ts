/**
 * @fileoverview **ΤΙ ΕΙΔΟΥΣ ΕΝΤΟΛΗ** — τι επιτρέπει ο ιδιοκτήτης, και σε πόσους.
 * @related ADR-827 §3.1 · types/owner-property-mandate.ts · types/brokerage.ts
 * @module types/listing-agreement
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΔΕΝ ΔΑΝΕΙΣΤΗΚΕ ΤΟ `ExclusivityType` ΤΟΥ ADR-230 — **ΜΕΤΡΗΜΕΝΟ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο κανόνας N.0.2 λέει «ψάξε πρώτα». Ψάχτηκε, και βρέθηκε: το `types/brokerage.ts`
 * (ADR-230) έχει ήδη `ExclusivityType = 'exclusive' | 'non_exclusive' |
 * 'semi_exclusive'`, με **14 αρχεία καταναλωτών** και UI **mounted**
 * (`config/project-tabs-config.ts` · `SalesSidebar`).
 *
 * ⛔ **Και απορρίφθηκε, με λόγο που δεν είναι προτίμηση:** καμία από τις τρεις τιμές
 * **δεν αντιστοιχεί σε πρότυπο**. Το πεδίο `ListingAgreement` του **RESO Data
 * Dictionary 1.7** — το λεξιλόγιο που μιλούν όλα τα MLS — έχει **επτά** τιμές, και το
 * *«semi_exclusive»* **δεν είναι καμία από αυτές**. Δανεισμός του θα κλείδωνε
 * αυθαίρετο λεξιλόγιο σε πεδίο που ταξιδεύει προς **δημόσια** επιφάνεια.
 *
 * 🔑 **Το κόστος της μη-χρήσης μετρήθηκε πριν αποφασιστεί**: `brokerage_agreements` =
 * **0 έγγραφα** στη ζωντανή βάση. Άρα το ADR-230 μπορεί να μεταναστεύσει **εδώ**
 * αργότερα με **μηδέν** μετανάστευση — και όσο δεν το κάνει, τα δύο λεξιλόγια
 * περιγράφουν **διαφορετικά υποκείμενα**: εκείνο εταιρεία → μεσίτη-**επαφή** σε
 * **έργο**, αυτό ιδιώτη → **οργανισμό** σε **αγγελία**.
 *
 * ⚠️ **Το `CommissionType` του ίδιου αρχείου ΔΑΝΕΙΖΕΤΑΙ κανονικά** — δες
 * `types/owner-property-mandate.ts`. Εκείνο είναι γενικό λεξιλόγιο **υπολογισμού**
 * (`percentage | fixed | tiered`) και δεν έχει πρότυπο να παραβιάσει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΕΣΣΕΡΙΣ ΑΠΟ ΤΙΣ ΕΠΤΑ — ΚΑΙ ΟΙ ΤΡΕΙΣ ΠΟΥ ΛΕΙΠΟΥΝ ΕΧΟΥΝ ΟΝΟΜΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * | RESO | Υιοθέτηση | Εδώ; |
 * |---|---|---|
 * | Exclusive Agency | **39%** | ✅ {@link EXCLUSIVE_AGENCY} |
 * | Exclusive Right To Sell | 33% | ✅ {@link EXCLUSIVE_RIGHT_TO_SELL} |
 * | Exclusive Right To Lease | 13% | ✅ {@link EXCLUSIVE_RIGHT_TO_LEASE} |
 * | Open | 8% | ✅ {@link OPEN_LISTING} |
 * | Exclusive Right With Exception | 7% | ⛔ απαιτεί **ονομαστικό κατάλογο εξαιρέσεων** — μηχανισμός που δεν υπάρχει· τιμή χωρίς μηχανισμό είναι υπόσχεση που κανείς δεν τηρεί |
 * | Probate | 3% | ⛔ δένει με τον **US probate code**· δεν έχει ελληνικό αντίστοιχο |
 * | Net | 2% | ⛔ *«**illegal** in some states»* κατά την ίδια την τεκμηρίωση του RESO |
 *
 * 🏆 **Η #1 τιμή της αγοράς είναι ΑΚΡΙΒΩΣ η περίπτωση του ιδιώτη μας.** Το *Exclusive
 * Agency* σημαίνει «αποκλειστικός μεσίτης, **αλλά ο ιδιοκτήτης μπορεί να ενεργήσει
 * μόνος**» — δηλαδή η απόφαση Giorgio ότι ο ιδιώτης κρατά τα δικαιώματά του δεν είναι
 * παρέκκλιση από την αγορά: είναι **το πιο συνηθισμένο συμβόλαιο** που υπάρχει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΙ ΕΦΥΓΕ ΑΠΟ ΕΔΩ ΣΤΗ Φ2 ΤΟΥ ADR-835 — ΚΑΙ ΤΙ ΕΜΕΙΝΕ, ΜΕ ΛΟΓΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το κλειστό σύνολο `shared | exclusive` και ο πίνακας συμβατότητάς του
 * (`MANDATE_LOCK_MODES` · `modesCompatible`) **μετακόμισαν** στο
 * `lib/occupancy/occupancy-mode.ts`: είναι το **τρίτο σκέλος του κριτή κατάληψης**,
 * και ο κριτής απέκτησε **δεύτερο** καταναλωτή (τις κρατήσεις). Το όνομα
 * `MandateLockMode` έγινε ψευδές τη στιγμή που μια **κράτηση** άρχισε να κλειδώνει
 * `exclusive` με ακριβώς τον ίδιο τρόπο χωρίς να είναι εντολή.
 *
 * ✅ **Έμεινε εδώ η ΑΝΤΙΣΤΟΙΧΙΣΗ** — {@link LISTING_AGREEMENT_LOCK_MODES} και
 * {@link lockModeFor}: *«η αποκλειστική πώλησης κλειδώνει»* είναι γνώση **αυτού** του
 * τομέα, και ο γενικός κριτής δεν την έχει ούτε πρέπει να την αποκτήσει.
 *
 * **Layering**: leaf — καθαροί τύποι + καθαρές συναρτήσεις.
 */

import type { OccupancyMode } from '@/lib/occupancy/occupancy-mode';

// =============================================================================
// 1. ΤΟ ΛΕΞΙΛΟΓΙΟ
// =============================================================================

/**
 * Αποκλειστική εντολή, **αλλά ο ιδιοκτήτης διατηρεί το δικαίωμα να ενεργήσει μόνος**
 * χωρίς να οφείλει αμοιβή.
 *
 * 🔑 Η **πιο διαδεδομένη** μορφή (39%) — και η προεπιλογή μας, γιατί είναι η μόνη που
 * περιγράφει ειλικρινά τι κάνει ο ιδιώτης της πλατφόρμας: **είχε ήδη δική του
 * αγγελία** πριν καλέσει γραφείο.
 */
export const EXCLUSIVE_AGENCY = 'exclusive-agency';

/** Αποκλειστική εντολή πώλησης: αμοιβή **όποιος κι αν** βρει αγοραστή. */
export const EXCLUSIVE_RIGHT_TO_SELL = 'exclusive-right-to-sell';

/** Το ίδιο, για **εκμίσθωση**. Ξεχωριστή τιμή στο RESO, ξεχωριστή και εδώ. */
export const EXCLUSIVE_RIGHT_TO_LEASE = 'exclusive-right-to-lease';

/**
 * Απλή εντολή: **σε οποιονδήποτε αριθμό** γραφείων, αμοιβή μόνο σε όποιον φέρει το
 * αποτέλεσμα.
 *
 * ⚠️ **Η ΜΟΝΗ τιμή που επιτρέπει δεύτερο γραφείο** — δες {@link allowsOtherAgencies}.
 */
export const OPEN_LISTING = 'open';

/**
 * **Κλειστό σύνολο.** Πέμπτη τιμή δεν μεταγλωττίζεται — και δεν πρέπει να προστεθεί
 * χωρίς αντιστοιχία σε τιμή του RESO **και** μηχανισμό που την επιβάλλει.
 */
export const LISTING_AGREEMENTS = [
  EXCLUSIVE_AGENCY,
  EXCLUSIVE_RIGHT_TO_SELL,
  EXCLUSIVE_RIGHT_TO_LEASE,
  OPEN_LISTING,
] as const;

export type ListingAgreement = (typeof LISTING_AGREEMENTS)[number];

/**
 * **Η προεπιλογή** — η μορφή που κρατά στον ιδιοκτήτη ό,τι είχε πριν καλέσει γραφείο.
 *
 * ⚠️ **Προεπιλογή, ΟΧΙ επιβολή**: τα δύο μέρη συμφωνούν ό,τι θέλουν, και η επιλογή
 * ταξιδεύει **μέσα στο μήνυμα που εγκρίνει ο ιδιοκτήτης**. Ίδιο σκεπτικό με το
 * `MANDATE_DEFAULT_DURATION_DAYS`.
 */
export const DEFAULT_LISTING_AGREEMENT: ListingAgreement = EXCLUSIVE_AGENCY;

// =============================================================================
// 2. ΤΙ ΣΗΜΑΙΝΕΙ — δύο ερωτήσεις που το enum οφείλει να απαντά
// =============================================================================

/**
 * **Μπορεί ο ιδιοκτήτης να κλείσει μόνος του, χωρίς να οφείλει αμοιβή;**
 *
 * 🔴 **Υπάρχει για να μην είναι το enum διακοσμητικό.** Μια τιμή που κανείς δεν ρωτά
 * είναι ετικέτα, όχι κανόνας — και το έργο έχει μετρημένα **606 αδρανείς φρουρούς**
 * (ADR-749 §5) ακριβώς αυτής της μορφής. Εδώ η διαφορά **εκτελείται**.
 *
 * ⚠️ **ΔΕΝ απαντά «μπορεί να επεξεργαστεί την αγγελία;»** — εκείνο το απαντά το
 * `lib/owner-property/listing-permissions.ts`, και είναι **άλλη** ερώτηση: αυτή εδώ
 * είναι όρος της **σύμβασης** (οφείλεται αμοιβή;), εκείνη είναι **εξουσιοδότηση**
 * (ποιος πατά το κουμπί;). Ένας ιδιοκτήτης με `EXCLUSIVE_RIGHT_TO_SELL` εξακολουθεί
 * να διορθώνει τις φωτογραφίες του — απλώς οφείλει αμοιβή αν πουλήσει μόνος.
 */
export function ownerMayTransactAlone(agreement: ListingAgreement): boolean {
  return agreement === EXCLUSIVE_AGENCY || agreement === OPEN_LISTING;
}

// =============================================================================
// 2β. Ο ΤΡΟΠΟΣ ΚΑΤΑΛΗΨΗΣ — η αποκλειστικότητα ως **ΚΛΕΙΔΩΜΑ**, όχι ως ετικέτα
// =============================================================================

/**
 * **Πώς κλειδώνει το κάθε είδος εντολής.**
 *
 * 🔑 `Record` πάνω σε κλειστό σύνολο — **πέμπτη τιμή δεν μεταγλωττίζεται** μέχρι
 * κάποιος να απαντήσει *«και αυτή, αποκλείει ή μοιράζεται;»*. Ίδιος φρουρός με το
 * {@link STATUTORY_TERM_LIMITS}: ένα `?? 'exclusive'` θα σήμαινε **σιωπηλή απόφαση**
 * στο ακριβώς λάθος σημείο — και θα ήταν η αυστηρότερη δυνατή, δηλαδή θα απαγόρευε
 * νόμιμες συμφωνίες χωρίς κανείς να το ζητήσει.
 */
export const LISTING_AGREEMENT_LOCK_MODES: Readonly<
  Record<ListingAgreement, OccupancyMode>
> = {
  [EXCLUSIVE_AGENCY]: 'exclusive',
  [EXCLUSIVE_RIGHT_TO_SELL]: 'exclusive',
  [EXCLUSIVE_RIGHT_TO_LEASE]: 'exclusive',
  // 🔑 Η **μόνη** που μοιράζεται — και είναι ολόκληρος ο λόγος ύπαρξης του λεξιλογίου.
  [OPEN_LISTING]: 'shared',
};

/** **Πώς κλειδώνει αυτή η εντολή;** — η μία πόρτα προς τον τρόπο. */
export function lockModeFor(agreement: ListingAgreement): OccupancyMode {
  return LISTING_AGREEMENT_LOCK_MODES[agreement];
}

/**
 * **Επιτρέπει αυτή η εντολή ταυτόχρονη εντολή σε ΑΛΛΟ γραφείο;**
 *
 * ⚠️ **ΠΑΡΑΓΩΓΟ του {@link lockModeFor}, ΚΑΙ ΟΧΙ ΠΙΑ ΔΕΥΤΕΡΟΣ ΟΡΙΣΜΟΣ.** Έγραφε
 * `agreement === OPEN_LISTING` — δηλαδή **δεύτερη** διατύπωση του «ποια μοιράζεται»,
 * που θα απέκλινε την ημέρα που θα προστίθετο πέμπτο είδος. Τώρα υπάρχει **ένας**
 * τόπος που το ξέρει, και αυτή η συνάρτηση τον **ρωτά**.
 *
 * 🔴 **ΙΣΤΟΡΙΚΟ — ΗΤΑΝ ΑΔΡΑΝΗΣ ΦΡΟΥΡΟΣ ΕΠΙ ΜΗΝΕΣ.** Το σχόλιό της έγραφε *«ο φρουρός
 * για το σε πόσα γραφεία μπορώ να δώσω»* ενώ **κανείς δεν την καλούσε** (μετρημένο:
 * 0 καλούντες σε όλο το `src/`). Η λέξη «αποκλειστική» ήταν πράγματι **κείμενο στην
 * οθόνη και τίποτα άλλο** — ακριβώς ό,τι το σχόλιο προειδοποιούσε ότι θα συνέβαινε.
 * Ο πραγματικός έλεγχος ήταν `mandate.kind !== 'self'`, που **δεν ρωτούσε το είδος**:
 * απαγόρευε και την **απλή** εντολή σε δεύτερο γραφείο, δηλαδή το μόνο είδος που
 * υπάρχει **για να επιτρέπεται**.
 *
 * ⚠️ **Απαντά για ΕΝΑ είδος, όχι για ζεύγος.** Για την πραγματική ερώτηση
 * *«συγκρούονται αυτές οι δύο;»* υπάρχει το `lib/mandate/mandate-conflict.ts` — που
 * ρωτά **και** τον πόρο **και** τον χρόνο. Αυτή εδώ είναι χρήσιμη μόνο για να πει
 * στην οθόνη *«αυτό το είδος δέχεται και άλλα γραφεία»*.
 */
export function allowsOtherAgencies(agreement: ListingAgreement): boolean {
  return lockModeFor(agreement) === 'shared';
}

