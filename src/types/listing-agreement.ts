// 3. ΠΟΣΟ ΜΠΟΡΕΙ ΝΑ ΚΡΑΤΗΣΕΙ — ο νόμος ως **ΔΕΔΟΜΕΝΟ**, όχι ως σχόλιο
// =============================================================================

/**
 * Η δικαιοδοσία που **παράγει** το όριο.
 *
 * 🔴 **Κλειστό σύνολο ΜΙΑΣ τιμής, και είναι σκόπιμο.** Το «οκτώ μήνες» **δεν είναι
 * ιδιότητα της αποκλειστικής μεσιτείας** — είναι ιδιότητα της αποκλειστικής μεσιτείας
 * **στην Ελλάδα**. Γραμμένο ως σκέτος αριθμός, την ημέρα που η εφαρμογή δεχτεί
 * κυπριακό ή γερμανικό γραφείο θα λέει **ψέματα σιωπηλά**. Δηλωμένο έτσι, η επέκταση
 * **δεν μεταγλωττίζεται** μέχρι κάποιος να απαντήσει «και εκεί;».
 */
export const STATUTE_JURISDICTIONS = ['GR'] as const;

export type StatuteJurisdiction = (typeof STATUTE_JURISDICTIONS)[number];

/**
 * **Το νόμιμο ανώτατο όριο διάρκειας** μιας εντολής — μαζί με **το ποιος το λέει**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΓΙΑΤΙ Ο ΝΟΜΟΣ ΕΙΝΑΙ **ΠΕΔΙΟ** ΚΑΙ ΟΧΙ ΣΧΟΛΙΟ — ΕΔΩ ΞΕΠΕΡΝΑΜΕ ΤΑ MLS
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Τα MLS λύνουν το ίδιο πρόβλημα με **local business rules**: ρυθμίσεις σε ξεχωριστό
 * σύστημα, ανά αγορά. Και το τίμημα το πληρώνει ο άνθρωπος στην οθόνη — η άρνηση που
 * βλέπει είναι *«Invalid expiration date»*. **Δεν μαθαίνει ποτέ ποιος τον περιορίζει.**
 *
 * Εδώ το {@link authority} ταξιδεύει **μαζί με τον αριθμό**, οπότε το μήνυμα
 * *«μέγιστο 8 μήνες — άρθρο 200 §4 Ν.4072/2012»* **παράγεται από το ίδιο δεδομένο που
 * επιβάλλει το όριο**. Δεν υπάρχει δεύτερος τόπος να αποκλίνει: αν αλλάξει ο νόμος και
 * αλλάξει μόνο ο αριθμός, το κείμενο **δείχνει λάθος διάταξη και φαίνεται**.
 *
 * ⚠️ **Το `authority` ΔΕΝ περνά από i18n, και είναι εξαίρεση με λόγο** (N.11): είναι
 * **παραπομπή σε νομοθεσία**, όχι κείμενο διεπαφής. Το «άρθρο 200 §4 Ν.4072/2012»
 * είναι το ίδιο σε κάθε γλώσσα — μια «μετάφρασή» του θα ήταν παραπομπή σε **ανύπαρκτη**
 * διάταξη. Το i18n κλειδί περιβάλλει τον αριθμό και την παραπομπή· δεν τα παράγει.
 */
export interface StatutoryTermLimit {
  /** Ανώτατη **αρχική** διάρκεια, σε μήνες. */
  readonly maxMonths: number;
  /**
   * Πόσο επιπλέον επιτρέπει ο νόμος **με μεταγενέστερη πράξη**.
   *
   * ⚠️ **ΔΕΝ προστίθεται στο {@link maxMonths} κατά τη σύναψη.** Το άρθρο 200 δίνει
   * την παράταση *«ύστερα από **μονομερή έγγραφη δήλωση του εντολέα**»* — δηλαδή είναι
   * **δεύτερη πράξη του ιδιοκτήτη**, όχι όρος που το γραφείο γράφει από την αρχή. Μια
   * σύμβαση που ορίζει εξαρχής 12 μήνες αποκλειστικότητας **δεν είναι παρατεταμένη
   * οκτάμηνη· είναι άκυρη δωδεκάμηνη**. Ζει εδώ γιατί η διαδρομή παράτασης θα το
   * χρειαστεί (ADR-827 §7 #4) και ο αριθμός δεν πρέπει να γεννηθεί δεύτερη φορά.
   */
  readonly renewalMonths: number;
  readonly jurisdiction: StatuteJurisdiction;
  /** Η διάταξη, αυτολεξεί όπως παραπέμπεται. Δες το σχόλιο του τύπου. */
  readonly authority: string;
}

/**
 * **Ποιο όριο ισχύει για κάθε είδος εντολής.**
 *
 * 🔑 **`Record` πάνω σε κλειστό σύνολο — ο ίδιος μεταγλωττιστής-φρουρός με το
 * `ListingPermissions`.** Πέμπτη τιμή στο {@link LISTING_AGREEMENTS} **δεν
 * μεταγλωττίζεται** μέχρι κάποιος να απαντήσει *«και αυτή πόσο κρατά;»*. Ένα
 * `Partial` ή ένα `?? DEFAULT` θα σήμαινε σιωπηλά «απεριόριστη» — δηλαδή απόφαση που
 * **κανείς δεν πήρε**, στο ακριβώς λάθος σημείο.
 */
export const STATUTORY_TERM_LIMITS: Readonly<
  Record<ListingAgreement, StatutoryTermLimit>
> = {
  // ⚠️ Και οι τρεις αποκλειστικές μοιράζονται το ίδιο όριο επειδή ο νόμος μιλά για
  //    «σύμβαση **αποκλειστικής** μεσιτείας» — δεν ξεχωρίζει πώληση από εκμίσθωση.
  [EXCLUSIVE_AGENCY]: {
    maxMonths: 8,
    renewalMonths: 4,
    jurisdiction: 'GR',
    authority: 'άρθρο 200 §4 Ν.4072/2012',
  },
  [EXCLUSIVE_RIGHT_TO_SELL]: {
    maxMonths: 8,
    renewalMonths: 4,
    jurisdiction: 'GR',
    authority: 'άρθρο 200 §4 Ν.4072/2012',
  },
  [EXCLUSIVE_RIGHT_TO_LEASE]: {
    maxMonths: 8,
    renewalMonths: 4,
    jurisdiction: 'GR',
    authority: 'άρθρο 200 §4 Ν.4072/2012',
  },
  // 🔑 Η **μη** αποκλειστική έχει το γενικό όριο της §3 — **12 μήνες**, παράταση 6.
  //    Δεν είναι «απεριόριστη»: η §3 ορίζει διάρκεια για **κάθε** μεσιτική σύμβαση.
  [OPEN_LISTING]: {
    maxMonths: 12,
    renewalMonths: 6,
    jurisdiction: 'GR',
    authority: 'άρθρο 200 §3 Ν.4072/2012',
  },
};

/**
 * **Πόσο μπορεί να κρατήσει αυτή η εντολή;** — η μία πόρτα προς το όριο.
 *
 * 🔴 Υπάρχει ώστε κανείς να μη γράψει `STATUTORY_TERM_LIMITS[x]` με ωμό κλειδί: ο
 * τύπος {@link ListingAgreement} κάνει **αδύνατο** να ζητηθεί όριο για είδος που δεν
 * υπάρχει. Ίδια κίνηση με το `mayPerform` έναντι του `permissionsOn(...)['withdraw']`.
 */
export function statutoryTermLimitFor(
  agreement: ListingAgreement,
): StatutoryTermLimit {
  return STATUTORY_TERM_LIMITS[agreement];
}

/**
 * **Είναι έγκυρη τιμή;** — για ό,τι φτάνει από το δίκτυο.
 *
 * ⚠️ Ωμή συμβολοσειρά που καταλήγει σε `switch` χωρίς `default` είναι λευκή οθόνη·
 * εδώ γίνεται **άρνηση με όνομα**. Ίδιο δόγμα με το `decisionFrom` της
 * `api/mandate/[token]`.
 */
export function isListingAgreement(value: unknown): value is ListingAgreement {
  return (
    typeof value === 'string' &&
    (LISTING_AGREEMENTS as readonly string[]).includes(value)
  );
}
