// =============================================================================
// 1. ΤΟ ΛΕΞΙΛΟΓΙΟ
// =============================================================================

/**
 * Αποκλειστική εντολή, **αλλά ο ιδιοκτήτης διατηρεί το δικαίωμα να ενεργήσει μόνος**
 * χωρίς να οφείλει αμοιβή.
 *
 * 🔑 Η **πιο διαδεδομένη** μορφή (39%) — και η προεπιλογή μας, γιατί είναι η μόνη που
 * περιγράφει ειλικρινά τι κάνει ο ιδιώτης της πλατφόρμας: **είχε ήδη δική του
 * αγγελία** πριν καλέσει γραφείο.
 */
export const EXCLUSIVE_AGENCY = 'exclusive-agency';

/** Αποκλειστική εντολή πώλησης: αμοιβή **όποιος κι αν** βρει αγοραστή. */
export const EXCLUSIVE_RIGHT_TO_SELL = 'exclusive-right-to-sell';

/** Το ίδιο, για **εκμίσθωση**. Ξεχωριστή τιμή στο RESO, ξεχωριστή και εδώ. */
export const EXCLUSIVE_RIGHT_TO_LEASE = 'exclusive-right-to-lease';

/**
 * Απλή εντολή: **σε οποιονδήποτε αριθμό** γραφείων, αμοιβή μόνο σε όποιον φέρει το
 * αποτέλεσμα.
 *
 * ⚠️ **Η ΜΟΝΗ τιμή που επιτρέπει δεύτερο γραφείο** — δες {@link allowsOtherAgencies}.
 */
export const OPEN_LISTING = 'open';

/**
 * **Κλειστό σύνολο.** Πέμπτη τιμή δεν μεταγλωττίζεται — και δεν πρέπει να προστεθεί
 * χωρίς αντιστοιχία σε τιμή του RESO **και** μηχανισμό που την επιβάλλει.
 */
export const LISTING_AGREEMENTS = [
  EXCLUSIVE_AGENCY,
  EXCLUSIVE_RIGHT_TO_SELL,
  EXCLUSIVE_RIGHT_TO_LEASE,
  OPEN_LISTING,
] as const;

export type ListingAgreement = (typeof LISTING_AGREEMENTS)[number];

/**
 * **Η προεπιλογή** — η μορφή που κρατά στον ιδιοκτήτη ό,τι είχε πριν καλέσει γραφείο.
 *
 * ⚠️ **Προεπιλογή, ΟΧΙ επιβολή**: τα δύο μέρη συμφωνούν ό,τι θέλουν, και η επιλογή
 * ταξιδεύει **μέσα στο μήνυμα που εγκρίνει ο ιδιοκτήτης**. Ίδιο σκεπτικό με το
 * `MANDATE_DEFAULT_DURATION_DAYS`.
 */
export const DEFAULT_LISTING_AGREEMENT: ListingAgreement = EXCLUSIVE_AGENCY;

// =============================================================================
// 2. ΤΙ ΣΗΜΑΙΝΕΙ — δύο ερωτήσεις που το enum οφείλει να απαντά
// =============================================================================

/**
 * **Μπορεί ο ιδιοκτήτης να κλείσει μόνος του, χωρίς να οφείλει αμοιβή;**
 *
 * 🔴 **Υπάρχει για να μην είναι το enum διακοσμητικό.** Μια τιμή που κανείς δεν ρωτά
 * είναι ετικέτα, όχι κανόνας — και το έργο έχει μετρημένα **606 αδρανείς φρουρούς**
 * (ADR-749 §5) ακριβώς αυτής της μορφής. Εδώ η διαφορά **εκτελείται**.
 *
 * ⚠️ **ΔΕΝ απαντά «μπορεί να επεξεργαστεί την αγγελία;»** — εκείνο το απαντά το
 * `lib/owner-property/listing-permissions.ts`, και είναι **άλλη** ερώτηση: αυτή εδώ
 * είναι όρος της **σύμβασης** (οφείλεται αμοιβή;), εκείνη είναι **εξουσιοδότηση**
 * (ποιος πατά το κουμπί;). Ένας ιδιοκτήτης με `EXCLUSIVE_RIGHT_TO_SELL` εξακολουθεί
 * να διορθώνει τις φωτογραφίες του — απλώς οφείλει αμοιβή αν πουλήσει μόνος.
 */
export function ownerMayTransactAlone(agreement: ListingAgreement): boolean {
  return agreement === EXCLUSIVE_AGENCY || agreement === OPEN_LISTING;
}

/**
 * **Επιτρέπει αυτή η εντολή ταυτόχρονη εντολή σε ΑΛΛΟ γραφείο;**
 *
 * 🔑 Ο φρουρός για το «σε πόσα γραφεία μπορώ να δώσω». Χωρίς αυτόν, η λέξη
 * «αποκλειστική» θα ήταν **κείμενο στην οθόνη** και τίποτα άλλο — και ο ιδιώτης θα
 * μπορούσε να υπογράψει δύο αποκλειστικές, δηλαδή να αθετήσει την πρώτη **μέσα από τη
 * δική μας οθόνη**.
 */
export function allowsOtherAgencies(agreement: ListingAgreement): boolean {
  return agreement === OPEN_LISTING;
}

/**
 * **Είναι έγκυρη τιμή;** — για ό,τι φτάνει από το δίκτυο.
 *
 * ⚠️ Ωμή συμβολοσειρά που καταλήγει σε `switch` χωρίς `default` είναι λευκή οθόνη·
 * εδώ γίνεται **άρνηση με όνομα**. Ίδιο δόγμα με το `decisionFrom` της
 * `api/mandate/[token]`.
 */
export function isListingAgreement(value: unknown): value is ListingAgreement {
  return (
    typeof value === 'string' &&
    (LISTING_AGREEMENTS as readonly string[]).includes(value)
  );
}
