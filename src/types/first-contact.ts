// 6. 🏆 Η ΑΠΟΚΑΛΥΨΗ — ΚΑΘΑΡΗ ΣΥΝΑΡΤΗΣΗ, ΔΥΟ ΕΡΩΤΗΤΕΣ, ΜΙΑ ΑΠΑΝΤΗΣΗ
// =============================================================================

/**
 * **Τι βλέπει ο προσφέρων.** Ό,τι λείπει από εδώ **δεν φεύγει ποτέ**.
 *
 * ⚠️ **Καμία** ταυτότητα χρήστη, **κανένα** `dmnd_*`, **κανένα** μέγεθος απόκλισης,
 * **καμία** άλλη πράξη του ίδιου ανθρώπου.
 */
export interface FirstContactForOfferer {
  readonly id: string;
  readonly target: FirstContactTarget;
  /** `null` όταν η πράξη έχει αποσυρθεί — δες {@link disclosedToOfferer}. */
  readonly disclosure: SeekerDisclosure | null;
  readonly matchReason: MatchReason | null;
  readonly requestedAt: string;
  readonly lifecycle: FirstContactLifecycle;
  readonly withdrawnAt: string | null;
}

/**
 * **Τι βλέπει ο ζητών** — η δική του πράξη, με το **υπόλοιπο** της χωρητικότητας.
 *
 * ⚠️ Το υπόλοιπο **δεν** ζει εδώ: υπολογίζεται από το σύνολο των πράξεων
 * (`lib/contact/first-contact-capacity.ts`). Πεδίο «θέσεις που έμειναν» **μέσα** σε ένα
 * έγγραφο θα ήταν αντίγραφο μεγέθους που ανήκει στο **σύνολο** — και θα παλιώνε.
 */
export interface FirstContactForSeeker {
  readonly id: string;
  readonly target: FirstContactTarget;
  readonly matchReason: MatchReason | null;
  readonly createdAt: string;
  readonly lifecycle: FirstContactLifecycle;
  readonly withdrawnAt: string | null;
  /** Το είδε ο άλλος; Ο ζητών **δικαιούται** να ξέρει τι έφτασε (Κ10). */
  readonly seenAt: string | null;
}

/**
 * **Τι έχει φτάσει στον προσφέροντα** — η **μία** απάντηση για **δύο** ερωτητές.
 *
 * | Ερωτά | Παίρνει |
 * |---|---|
 * | ο **διακομιστής**, όταν συνθέτει το {@link FirstContactForOfferer} | τι **επιτρέπεται** να μπει |
 * | ο **ζητών**, στην οθόνη της απόσυρσης | τι **βλέπει** ακόμη ο άλλος |
 *
 * 🔴 **ΥΠΟΛΟΓΙΖΕΤΑΙ, ΔΕΝ ΚΑΤΑΓΡΑΦΕΤΑΙ.** Το **ISO/IEC TS 27560:2023** ζητά *record* +
 * *receipt* — δηλαδή **δεύτερο βιβλίο**, που μπορεί να **αποκλίνει** από το τι όντως
 * αποκαλύφθηκε. Σε τομέα όπου η απόκλιση λέγεται **ψευδής διαβεβαίωση**, αυτό είναι το
 * σχήμα του ADR-749. Ίδιο συμβόλαιο με το `disclosedTo()` του `mandate-request.ts`, και
 * **ρητή απαγόρευση** κάθε `disclosure_log` (ADR-827 §8.6).
 *
 * 🔑 **Η ΑΠΟΣΥΡΣΗ ΕΙΝΑΙ ΤΟ ΜΟΝΟ ΓΕΓΟΝΟΣ ΠΟΥ ΜΕΤΑΚΙΝΕΙ ΤΗ ΓΡΑΜΜΗ** — και μετακινεί
 * **μόνο** τα στοιχεία. Ο **στόχος**, ο **χρόνος** και το **γεγονός** μένουν, γιατί
 * *«ανακαλείται η ΣΧΕΣΗ, ποτέ η ΙΣΤΟΡΙΑ»*: το ίχνος **δεν είναι δικό μας, είναι των
 * δύο** — αν αύριο ο ένας πει *«με παρενόχλησε»* ή ο άλλος *«συμφωνήσαμε και το
 * αρνήθηκε»*, το σβήσιμο αφήνει **και τους δύο** χωρίς τίποτα να δείξουν.
 *
 * ⛔ **ΚΑΙ Η ΟΘΟΝΗ ΔΕΝ ΛΕΕΙ «ΔΙΑΓΡΑΦΟΝΤΑΙ ΤΑ ΣΤΟΙΧΕΙΑ ΣΟΥ»** (Κ10). Δεν υπάρχει κουμπί
 * που κάνει άνθρωπο να ξεχάσει: ο προσφέρων μπορεί να έχει το τηλέφωνο σε χαρτί, στις
 * επαφές του, δοσμένο αλλού. Λέει **«σταματά η πρόσβαση από εδώ — ό,τι είδε, το
 * είδε»**. *Μια υπόσχεση που δεν μπορούμε να κρατήσουμε είναι **χειρότερη** από καμία*:
 * ο άνθρωπος που πίστεψε ότι σβήστηκε παίρνει **λάθος απόφαση με σιγουριά**.
 * ⚠️ Το Figma έχει **τεκμηριωμένη** αστοχία εδώ (παράπονα για *«misleading wording»* στο
 * «Anyone with the link») — δηλαδή ο Κ10 είναι ζωντανός σε εργαλείο αυτού του επιπέδου.
 */
export function disclosedToOfferer(contact: FirstContact): FirstContactForOfferer {
  const open = contact.lifecycle === 'open';
  return {
    id: contact.id,
    target: contact.target,
    disclosure: open ? contact.disclosure : null,
    matchReason: open ? contact.matchReason : null,
    requestedAt: contact.createdAt,
    lifecycle: contact.lifecycle,
    withdrawnAt: contact.withdrawnAt,
  };
}

/** Η όψη του ζητούντος — **πάντα** πλήρης, είναι δική του πράξη. */
export function shownToSeeker(contact: FirstContact): FirstContactForSeeker {
  return {
    id: contact.id,
    target: contact.target,
    matchReason: contact.matchReason,
    createdAt: contact.createdAt,
    lifecycle: contact.lifecycle,
    withdrawnAt: contact.withdrawnAt,
    seenAt: contact.seenAt,
  };
}

/**
 * **Βλέπει ακόμη ο άλλος τα στοιχεία μου;** — για την οθόνη, ώστε να μη γράψει δεύτερη
 * λογική πάνω στο `lifecycle`. *(Δεύτερος έλεγχος = δεύτερη αλήθεια, ADR-749.)*
 */
export function contactDetailsStillVisible(contact: FirstContact): boolean {
  return disclosedToOfferer(contact).disclosure !== null;
}

