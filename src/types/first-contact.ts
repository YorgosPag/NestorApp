/**
 * **Η πράξη, ολόκληρη.** ⛔ **Δεν φτάνει ποτέ σε πελάτη** — `firestore.rules` λέει
 * `read: false` **και** `write: false`. Και οι δύο πλευρές διαβάζουν **προβολή**.
 */
export interface FirstContact {
  /** `fcon_*` — από το `enterprise-id.service`, **ποτέ** χειρόγραφο (N.6). */
  readonly id: string;
  /**
   * Ο άνθρωπος που έκανε την κίνηση.
   *
   * ⚠️ **ΑΜΕΤΑΒΛΗΤΟ.** Είναι ο άξονας απομόνωσης (`tenant-config.ts`) **και** το
   * υποκείμενο της χωρητικότητας: πράξη που αλλάζει ιδιοκτήτη μεταφέρει **και** τη
   * θέση που καταλαμβάνει — δηλαδή θα «χάριζε» χωρητικότητα.
   */
  readonly seekerUserId: string;
  readonly target: FirstContactTarget;
  /**
   * Η ζήτηση από την οποία γεννήθηκε η πράξη (`dmnd_*`), **αν υπάρχει**.
   *
   * 🔑 **`null` είναι ΚΑΝΟΝΙΚΟ, όχι ελάττωμα**: η αγγελία είναι **δημόσια** και ο
   * καθένας πατά το κουμπί — χωρίς να έχει δηλώσει ποτέ ζήτηση. Τότε δεν υπάρχει
   * «γιατί ταιριάζει», και η οθόνη οφείλει να πει *«δεν το ξέρουμε»* αντί
   * *«ταιριάζει σε όλα»*. Οι δύο απαντήσεις **δεν** είναι η ίδια.
   *
   * ⛔ **ΔΕΝ φτάνει ποτέ στον προσφέροντα.** Η ταυτότητα της ζήτησης είναι κλειδί προς
   * το **επίπεδο Β** — και το SPEC-777A §12.7(α) απαγορεύει κάθε διαδρομή που το κάνει
   * **εργαλείο πίεσης**. Ό,τι περνά είναι το {@link MatchReason}, χωρίς μεγέθη.
   */
  readonly demandId: string | null;
  readonly disclosure: SeekerDisclosure;
  /**
   * Το «γιατί ταιριάζει», υπολογισμένο **τη στιγμή της πράξης**.
   *
   * ⚠️ **Στιγμιότυπο επίτηδες, ΟΧΙ ζωντανός υπολογισμός**: η πράξη είναι **γεγονός του
   * παρελθόντος** με ημερομηνία (άρθρο 200 §1). Αν ο ζητών αλλάξει αύριο τα κριτήριά
   * του, το «γιατί σε πλησίασα **τότε**» δεν αλλάζει — αλλιώς ο προσφέρων θα έβλεπε
   * αναδρομικά διαφορετικό λόγο για την ίδια κίνηση.
   */
  readonly matchReason: MatchReason | null;
  readonly lifecycle: FirstContactLifecycle;
  readonly createdAt: string;
  /** Πότε αποσύρθηκε. `null` όσο είναι ανοιχτή. Το ΠΕ6 κρατά **ότι** και **πότε**. */
  readonly withdrawnAt: string | null;
  /**
   * Πότε το **είδε** ο παραλήπτης. `null` = δεν το άνοιξε ακόμη.
   *
   * 🔑 Δεν είναι μετρική· είναι **ο πυρήνας του Κ10**. Η οθόνη της απόσυρσης λέει
   * *«ό,τι είδε, το είδε»* — και αυτό το πεδίο είναι ο **μόνος** τρόπος να ξέρουμε αν
   * είδε **κάτι**. Χωρίς αυτό, η πιο τίμια διατύπωση που έχουμε θα ήταν εικασία.
   */
  readonly seenAt: string | null;
}

/**
 * Το έγγραφο **όπως ζει στο Firestore** — η κατάσταση ως ωμό `string`.
 *
 * ⚠️ Ο τύπος **δεν λέει ψέματα για την είσοδο**: ένα `FirstContactLifecycle` εδώ θα
 * ισχυριζόταν ότι η βάση **εγγυάται** το κλειστό σύνολο. Δεν το εγγυάται κανείς — γι'
 * αυτό υπάρχει το {@link readStoredLifecycle}.
 */
export type FirstContactDocument = Omit<FirstContact, 'lifecycle'> & {
  readonly lifecycle: string;
};

/** Αποθηκευμένο → πεδίο, με τη διάγνωση **δίπλα** αντί να χαθεί. */
export function firstContactFromStored(
  stored: FirstContactDocument,
): { readonly contact: FirstContact; readonly repaired: StoredLifecycleRepair } {
  const reading = readStoredLifecycle(stored.lifecycle);
  return {
    contact: { ...stored, lifecycle: reading.lifecycle },
    repaired: reading.repaired,
  };
}

