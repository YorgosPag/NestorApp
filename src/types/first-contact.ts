// 3. ΤΙ ΑΠΟΚΑΛΥΠΤΕΙ Ο ΖΗΤΩΝ ΓΙΑ ΤΟΝ ΕΑΥΤΟ ΤΟΥ
// =============================================================================

/**
 * **Τα στοιχεία του ζητούντος — όσα ΕΚΕΙΝΟΣ διάλεξε.**
 *
 * 🔑 **Γιατί είναι επιλογή και όχι υποχρεωτικό τηλέφωνο** (ΠΕ4): πολλοί άνθρωποι **δεν
 * θέλουν να δώσουν το κινητό τους σε άγνωστο** στην πρώτη επαφή. Χωρίς επιλογή, η
 * εναλλακτική τους είναι *«δώσε τηλέφωνο ή μη μιλήσεις»* — δηλαδή **η ίδια η
 * ιδιωτικότητα γίνεται εμπόδιο στη συνάντηση**, ακριβώς αυτό που η Α12 υποσχέθηκε να λύσει.
 *
 * ⚠️ **Αυτή η απόκρυψη ΔΕΝ συγκρούεται με την Α13** (*«καμία απόκρυψη στοιχείων
 * επικοινωνίας»*), και η διάκριση είναι το §6 #2: ό,τι κρύβεται εδώ, κρύβεται για
 * **ιδιωτικότητα προσώπου** — **ποτέ** για εμπορικό λόγο. Εμείς δεν κρύβουμε τίποτα
 * που μας δόθηκε· ο άνθρωπος **δεν το έδωσε**.
 *
 * ⛔ Ο φρουρός **Κ7 #1** ισχύει πάνω σε αυτό: ό,τι υπάρχει εδώ φαίνεται **ΔΙΠΛΑ** στον
 * χώρο συνομιλίας, **πάντα, χωρίς κλικ** — όχι «πίσω από κουμπί», όχι «μετά από Χ μηνύματα».
 */
export interface SeekerDisclosure {
  /** Πώς θέλει να τον λένε. **Πάντα** παρόν — πράξη χωρίς όνομα είναι ανώνυμο χτύπημα. */
  readonly displayName: string;
  readonly email: string | null;
  readonly phone: string | null;
  /**
   * Δέχεται μηνύματα **μέσα** στην πλατφόρμα (ΠΕ4).
   *
   * ⚠️ Ο χώρος υλοποιείται σε **ξεχωριστό στάδιο**· μέχρι τότε αυτό μένει `false` και
   * η πράξη στηρίζεται σε email/τηλέφωνο. Το πεδίο υπάρχει **από τώρα** ώστε η άφιξη
   * του χώρου να **μην** αλλάξει το σχήμα ενός εγγράφου που θα έχει ήδη γραφτεί.
   */
  readonly acceptsPlatformMessages: boolean;
}

