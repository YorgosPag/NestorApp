// 2. Ο ΚΥΚΛΟΣ ΖΩΗΣ — ΔΥΟ καταστάσεις, και η δεύτερη είναι ΜΙΑ πράξη για δύο σκοπούς
// =============================================================================

/**
 * **Ανοιχτή ή αποσυρμένη. Τίποτε άλλο.**
 *
 * 🔑 **Το «κλείνω για να ελευθερώσω θέση» (ΠΕ5) και το «αποσύρω» (ΠΕ6) είναι Η ΙΔΙΑ
 * ΠΡΑΞΗ**, και υλοποιούνται **μία φορά**: *«δεν με ενδιαφέρει πια»* **είναι** ο λόγος
 * που ελευθερώνει τη θέση **και** ο λόγος που κλείνει τη σχέση.
 *
 * ⛔ **ΜΗΝ προσθέσεις τρίτη κατάσταση** τύπου `closed-but-reachable`. Δύο καταστάσεις
 * για τον ίδιο άξονα θα ήταν **δεύτερη αλήθεια** (ADR-749) και θα ξαναγεννούσαν
 * **ακριβώς** το φάντασμα που το ΠΕ5 εξαφάνισε: πράξη που **δείχνει** κλειστή και
 * **συμπεριφέρεται** ανοιχτή — δηλαδή ο προσφέρων να περιμένει απάντηση που δεν έρχεται.
 *
 * 🔶 **Δηλωμένο κόστος**: όποιος κλείνει για να ελευθερώσει θέση **χάνει και τον χώρο
 * συνομιλίας** (ΠΕ4). Είναι **αποδεκτό** γιατί οι δύο έχουν ήδη τα στοιχεία τους — το
 * κανάλι μας ήταν **διευκόλυνση, ποτέ ο μόνος δρόμος** (ΠΕ4, φρουρός #3).
 */
export const FIRST_CONTACT_LIFECYCLES = ['open', 'withdrawn'] as const;

export type FirstContactLifecycle = (typeof FIRST_CONTACT_LIFECYCLES)[number];

export function isFirstContactLifecycle(value: unknown): value is FirstContactLifecycle {
  return typeof value === 'string'
    && (FIRST_CONTACT_LIFECYCLES as readonly string[]).includes(value);
}

/** Πώς διαβάστηκε μια αποθηκευμένη κατάσταση. */
export type StoredLifecycleRepair = 'none' | 'unreadable';

export interface StoredLifecycleReading {
  readonly lifecycle: FirstContactLifecycle;
  readonly repaired: StoredLifecycleRepair;
}

/**
 * **Ανάγνωση αποθηκευμένης κατάστασης — fail-closed προς `withdrawn`.**
 *
 * 🔴 **Η κατεύθυνση της αστοχίας ΖΥΓΙΣΤΗΚΕ, δεν επιλέχθηκε από συνήθεια.** Ένα έγγραφο
 * με άγνωστη κατάσταση μπορεί να διαβαστεί με δύο τρόπους, και τα δύο κοστίζουν:
 *
 * | Αν διαβαστεί ως | Το λάθος είναι |
 * |---|---|
 * | `open` | **αποκαλύπτουμε στοιχεία ανθρώπου** χωρίς να ξέρουμε αν ισχύει η πράξη |
 * | `withdrawn` | ο άνθρωπος κερδίζει **μία** θέση χωρητικότητας που δεν του ανήκε |
 *
 * ⇒ Διαβάζεται **`withdrawn`**: παραβίαση ιδιωτικότητας εναντίον ενός σφάλματος
 * μέτρησης κατά **ένα**. Δεν είναι ισοπαλία.
 *
 * ⚠️ Το `repaired` **δεν** είναι διακοσμητικό: μια πράξη που διαβάστηκε ως αποσυρμένη
 * **επειδή δεν καταλάβαμε το έγγραφο** είναι **διαφορετικός ισχυρισμός** από μια που
 * ο άνθρωπος απέσυρε. Χωρίς το πεδίο, ο πιο αδύναμος θα φορούσε τη βεβαιότητα του πιο
 * δυνατού — το μοτίβο του `never-asked` ⇄ `owner-declined` της Α5.
 */
export function readStoredLifecycle(value: unknown): StoredLifecycleReading {
  return isFirstContactLifecycle(value)
    ? { lifecycle: value, repaired: 'none' }
    : { lifecycle: 'withdrawn', repaired: 'unreadable' };
}

