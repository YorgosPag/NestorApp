/**
 * **Προς ποιον στρέφεται η πράξη.**
 *
 * 🔑 **Διακριτή ένωση, και ΟΧΙ δύο συλλογές** — ο λόγος είναι το **ΠΕ5**: η
 * χωρητικότητα των ανοιχτών πράξεων είναι **ΕΝΑΣ** μετρητής. Δύο σχήματα θα σήμαιναν
 * δύο ερωτήματα, δύο αθροίσματα και **δύο νούμερα** — δηλαδή δύο σημεία όπου ο **Κ9**
 * (*«πλήρωσε για περισσότερα»*) θα μπορούσε να χτυπήσει, και δύο μηνύματα «γέμισε».
 *
 * ⚠️ Και υπάρχει **μετρημένος** λόγος να μην είναι δύο νούμερα: το ADR-843 **Θ-5**
 * στήριξε το όριο σε **δύο ανεξάρτητους δείκτες** (NAR ~7 σπίτια · Upwork 10). Για
 * δεύτερο νούμερο **δεν υπάρχει δεδομένο** — θα ήταν η μαντεψιά που ο Giorgio αρνήθηκε.
 *
 * 🔑 **Και η χωρητικότητα ΥΠΟΚΑΘΙΣΤΑ το fan-out**: αν ο άνθρωπος έχει δέκα θέσεις και
 * διαλέξει έξι επαγγελματίες, ξόδεψε έξι. Δηλαδή **μία** σταθερά φράζει ΚΑΙ το ΠΕ5
 * ΚΑΙ τον **Κ5** (*«η πράξη γίνεται μαζική αποστολή»*), χωρίς δεύτερο όριο ανά αίτημα
 * όπως το Bark (5 επαγγελματίες/ζήτηση).
 */
export type FirstContactTarget =
  | {
      readonly kind: 'listing';
      /** Η αγγελία του ιδιώτη (`ownp_*`) — η **ίδια** ταυτότητα με τη δημόσια προβολή. */
      readonly listingId: string;
      readonly agencyCompanyId?: never;
    }
  | {
      readonly kind: 'professional';
      /**
       * Το γραφείο/ο επαγγελματίας που δημοσίευσε **βιτρίνα** (`agency_profiles`).
       *
       * ⚠️ **ΔΕΝ είναι άξονας απομόνωσης** — είναι πεδίο **απόδοσης**. Δες
       * `tenant-config.ts`: ο άξονας είναι το `seekerUserId`, γιατί είναι ο **μόνος**
       * που υπάρχει σε **κάθε** έγγραφο.
       */
      readonly agencyCompanyId: string;
      readonly listingId?: never;
    };

/** Τα δύο είδη στόχου, ως κλειστό σύνολο για εξαντλητικούς ελέγχους. */
export const FIRST_CONTACT_TARGET_KINDS = ['listing', 'professional'] as const;

export type FirstContactTargetKind = (typeof FIRST_CONTACT_TARGET_KINDS)[number];

