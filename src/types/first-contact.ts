// 4. 🏆 ΤΟ «ΓΙΑΤΙ ΤΑΙΡΙΑΖΕΙ» — ΚΑΙ ΤΟ ΟΡΙΟ ΤΟΥ
// =============================================================================

/**
 * **Γιατί αυτός ο άνθρωπος πλησίασε αυτό το ακίνητο** — οι **άξονες**, ποτέ οι αριθμοί.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΠΟΥ ΞΕΠΕΡΝΑΜΕ ΤΟΥΣ ΜΕΓΑΛΟΥΣ — **μετρημένο, όχι ισχυρισμός**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Έρευνα 03/09/2026: το *reverse buyer match* **υπάρχει** στην αγορά — αλλά **μόνο σε
 * CRM μεσίτη** (Rex Software), και ο **δηλωμένος** σκοπός του είναι *«δείξε στον πωλητή
 * ότι είσαι ο μόνος μεσίτης για εκείνον»*. Δηλαδή **όπλο για να κερδίσει την εντολή**,
 * ποτέ υπηρεσία στον ιδιοκτήτη. **Καμία** πύλη ακινήτων δεν λέει στον ιδιοκτήτη
 * **γιατί** τον πλησίασαν. Εδώ το λέει, και ο ιδιοκτήτης απαντά **ενημερωμένος** —
 * άρα **λιγότερες άκαρπες επαφές**, που εξυπηρετεί το πνεύμα του ΠΕ2.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΟΡΙΟ, ΚΑΙ ΕΙΝΑΙ ΤΟ ΣΟΒΑΡΟΤΕΡΟ ΠΡΑΓΜΑ ΣΕ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `DemandGaps` (`lib/demand/demand-match-vocabulary.ts`) κρατά **ακριβή μεγέθη**:
 * `priceOverBy` · `areaShortBy` · `bedroomsShortBy` · `distanceOverMetres`.
 *
 * ⛔ **ΚΑΝΕΝΑ ΑΠΟ ΑΥΤΑ ΔΕΝ ΤΑΞΙΔΕΥΕΙ ΠΟΤΕ, ΚΑΙ Ο ΛΟΓΟΣ ΕΙΝΑΙ ΑΡΙΘΜΗΤΙΚΗ:**
 *
 *   ο προσφέρων **ξέρει τη δική του τιμή**  ⇒  `τιμή − priceOverBy` = **η οροφή
 *   προϋπολογισμού του ζητούντος**, στο ευρώ.
 *
 * 🔑 **Ο ζητών διάλεξε να αποκαλύψει ΠΟΙΟΣ ΕΙΝΑΙ, ΟΧΙ ΠΟΣΟ ΜΠΟΡΕΙ ΝΑ ΔΩΣΕΙ.** Η τιμή
 * επιφύλαξης είναι **διαπραγματευτική θέση**, όχι στοιχείο επαφής — και μια πλατφόρμα
 * που τη χαρίζει στην άλλη πλευρά **δεν φέρνει τους δύο σε επαφή· βάζει τον ένα σε
 * μειονεκτική θέση** χωρίς να το ζητήσει κανείς και χωρίς να το μάθει ποτέ.
 *
 * ✅ **Οι άξονες ΤΑΞΙΔΕΥΟΥΝ**: το `price-above` λέει *«η τιμή είναι πάνω από ό,τι
 * ψάχνει»* — χρήσιμο και **συμμετρικό** (ο ιδιοκτήτης μαθαίνει ότι υπάρχει αγοραστής
 * αν υποχωρήσει), χωρίς να δίνει **πόσο**. Και ο ζητών **δεν θα μπορούσε να το κρύψει
 * ούτως ή άλλως**: πλησίασε αγγελία πάνω από τα μέτρα του, με τη θέλησή του.
 *
 * ⚠️ **Ο φρουρός είναι Η ΑΠΟΥΣΙΑ ΠΕΔΙΟΥ**, όχι κανόνας: αυτός ο τύπος **δεν έχει θέση**
 * για μέγεθος. Πεδίο που δεν υπάρχει δεν το στέλνει κανείς — τέταρτη εφαρμογή του
 * κόλπου (ΠΕ2 · ΠΕ4 · ΠΕ5 · ADR-827 §9.9).
 */
export interface MatchReason {
  /**
   * Οι άξονες που **αστοχούν** — **ονόματα, χωρίς μεγέθη**.
   *
   * **Κενό** σημαίνει «ταιριάζει σε όλα όσα δήλωσε», που είναι **υπαρκτή και
   * διαφορετική** απάντηση από το «δεν ξέρουμε» ({@link MatchReason} `null` στην προβολή).
   */
  readonly unmetAxes: readonly DemandBlocker[];
  /**
   * Πόσους άξονες δήλωσε συνολικά ο ζητών.
   *
   * 🔑 Χωρίς αυτό, το «αστοχεί σε 1» είναι **αδιάβαστο**: 1 από 2 και 1 από 9 είναι
   * δύο πολύ διαφορετικά μηνύματα, και η οθόνη οφείλει να τα ξεχωρίζει. **Πλήθος, όχι
   * περιεχόμενο** — δεν λέει *ποια* κριτήρια, μόνο *πόσα*.
   */
  readonly declaredAxes: number;
}

