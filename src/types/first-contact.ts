/**
 * ⚠️ **Ονόματα, όχι μηνύματα** (§5.16 του `mandate-requests/route.ts`): ο γραφέας
 * απαντά *«αυτή η πράξη δεν έχει τρόπο να απαντηθεί»* με **όνομα** που γίνεται κλειδί
 * i18n. Ένα `MALFORMED_BODY` στη θέση τους θα έκανε τους ονομαστικούς λόγους
 * **ανεκτέλεστους** — και **κάλυψη σε νεκρό κλάδο δεν είναι κάλυψη**.
 */
export const FIRST_CONTACT_INVARIANTS = [
  /** Η πράξη πρέπει να έχει **τρόπο να απαντηθεί** — αλλιώς είναι αδιέξοδο, όχι επαφή. */
  'contact-no-channel',
  /** Όνομα κενό: ανώνυμο χτύπημα, όχι γνωριμία. */
  'contact-no-name',
  /** `withdrawn` χωρίς `withdrawnAt`, ή `open` **με** — το ΠΕ6 κρατά **πότε**. */
  'contact-withdrawal-timeless',
  /** Ταυτότητα χωρίς το πρόθεμα του ADR-843 ⇒ δεν ήρθε από τη μόνη πηγή (N.6). */
  'contact-foreign-id',
  /**
   * `matchReason` χωρίς `demandId`.
   *
   * 🔑 Λόγος **χωρίς πηγή** είναι ισχυρισμός που κανείς δεν μπορεί να ελέγξει — και θα
   * τον έβλεπε ο προσφέρων ως γεγονός.
   */
  'contact-reason-without-demand',
] as const;

export type FirstContactInvariant = (typeof FIRST_CONTACT_INVARIANTS)[number];

/** Έχει τρόπο να απαντηθεί; **Ένας** αρκεί — ο άνθρωπος διαλέγει ποιος (ΠΕ4). */
function hasReplyChannel(disclosure: SeekerDisclosure): boolean {
  return disclosure.email !== null
    || disclosure.phone !== null
    || disclosure.acceptsPlatformMessages;
}

/** Συμφωνεί η κατάσταση με τον χρόνο της; */
function withdrawalIsTimestamped(contact: FirstContact): boolean {
  return contact.lifecycle === 'withdrawn'
    ? contact.withdrawnAt !== null
    : contact.withdrawnAt === null;
}

/**
 * **Ποια αμετάβλητα παραβιάζονται.** Κενό = έγκυρη πράξη.
 *
 * ⚠️ Τρέχει **ΠΡΙΝ** τη γραφή. Άκυρο έγγραφο που γράφτηκε δεν το βλέπει κανείς
 * (`read: false`), αλλά **μετράει** στη χωρητικότητα — δηλαδή θα έκλεβε θέση από τον
 * άνθρωπο σιωπηλά.
 */
export function firstContactInvariantViolations(
  contact: FirstContact,
): readonly FirstContactInvariant[] {
  const violations: FirstContactInvariant[] = [];

  if (!hasReplyChannel(contact.disclosure)) violations.push('contact-no-channel');
  if (contact.disclosure.displayName.trim() === '') violations.push('contact-no-name');
  if (!withdrawalIsTimestamped(contact)) violations.push('contact-withdrawal-timeless');
  if (!contact.id.startsWith('fcon_')) violations.push('contact-foreign-id');
  if (contact.matchReason !== null && contact.demandId === null) {
    violations.push('contact-reason-without-demand');
  }

  return violations;
}
