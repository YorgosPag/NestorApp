import { useAgencyShowcase } from '@/hooks/mandate/useAgencyShowcase';
import type { DeclaredCoverage } from '@/types/agency-coverage';

export interface MyDeclaredCoverage {
  /**
   * Η δήλωση, ή `null`.
   *
   * ⚠️ **Το `null` ΔΕΝ ξεχωρίζει «δεν δήλωσε» από «δεν μπόρεσα να ρωτήσω» — επίτηδες.**
   * Ο μοναδικός καταναλωτής *(`reachVoiceOf`)* **σιωπά** και στις δύο, και η σιωπή είναι
   * η σωστή πράξη για την καθεμία: δεν κατηγορούμε άνθρωπο για κανόνα που δεν έθεσε,
   * ούτε για βλάβη δική μας. Μια διάκριση χωρίς διαφορετική συνέπεια θα ήταν κατάσταση
   * που κάθε αναγνώστης πρέπει να θυμάται να ελέγξει **χωρίς λόγο**.
   */
  readonly coverage: DeclaredCoverage | null;
  /**
   * `true` **μόνο** όσο το έγγραφο δεν έχει απαντήσει ακόμη.
   *
   * 🔑 **Φρουρός λόγου, όχι ορθότητας** *(ίδιο ιδίωμα με το `useCoverageResolvers`)*: η
   * κρίση είναι ήδη ασφαλής με `coverage: null` — σιωπά. Αυτό υπάρχει ώστε καμία οθόνη
   * να μην πει *«εκτός των περιοχών σου»* στο **παράθυρο πριν φτάσει η δήλωση**, όπου η
   * απάντηση θα ήταν σωστή για τα δεδομένα και **ψευδής** για τον άνθρωπο.
   */
  readonly isLoading: boolean;
}

/** Η δηλωμένη κάλυψη του **δικού μου** γραφείου — προβολή του {@link useAgencyShowcase}. */
export function useMyDeclaredCoverage(): MyDeclaredCoverage {
  const { state } = useAgencyShowcase();

  return {
    coverage: state.phase === 'published' ? state.profile.coverage : null,
    isLoading: state.phase === 'loading',
  };
}
