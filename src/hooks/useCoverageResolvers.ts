import { useMemo } from 'react';

import { useAdminFootprints } from '@/hooks/useAdminFootprints';
import { lineageIdsOf } from '@/hooks/useAdministrativeHierarchy';
import type { CoverageResolvers } from '@/lib/agency/coverage-match';

interface UseCoverageResolversReturn {
  /** Οι δύο αναγνώστες, με **σταθερή** ταυτότητα ανά στιγμιότυπο αποτυπωμάτων. */
  readonly resolvers: CoverageResolvers;
  /**
   * `true` όσο τα **αποτυπώματα** δεν έχουν φτάσει.
   *
   * ⚠️ **Δεν είναι φρουρός ορθότητας** — ο κριτής απαντά ήδη `'unknown'` όταν λείπει
   * αποτύπωμα, δηλαδή *«δεν ξέρω»* και ποτέ *«δεν καλύπτει»*. Είναι φρουρός **λόγου**:
   * υπάρχει ώστε μια οθόνη να μπορεί να πει *«περίμενε»* αντί να δείξει σιωπή που
   * διαβάζεται ως *«τίποτα δεν ταιριάζει»* — η διάκριση που φυλάει το `areaPending`.
   */
  readonly isLoading: boolean;
}

/** Οι αναγνώστες του {@link CoverageResolvers} για μια οθόνη — **ένα** στιγμιότυπο. */
export function useCoverageResolvers(): UseCoverageResolversReturn {
  const { isLoading, footprintOf } = useAdminFootprints();

  const resolvers = useMemo<CoverageResolvers>(
    () => ({ lineageOf: lineageIdsOf, footprintOf }),
    [footprintOf],
  );

  return { resolvers, isLoading };
}
