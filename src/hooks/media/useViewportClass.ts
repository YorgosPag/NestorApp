'use client';

/**
 * @fileoverview **ΤΡΕΙΣ καταστάσεις πλάτους** — και η τρίτη είναι ο λόγος που υπάρχει.
 * @related ADR-777 §7 (Α8 · Α19) · SPEC-777D · hooks/useMobile.tsx
 * @module hooks/media/useViewportClass
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΤΟ `useIsMobile` — ΜΕΤΡΗΜΕΝΟ, ΟΧΙ ΠΡΟΤΙΜΗΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `useIsMobile` (`src/hooks/useMobile.tsx`) κρατά `boolean | undefined` και
 * **επιστρέφει `!!isMobile`** — δηλαδή συμπτύσσει το «δεν μέτρησα ακόμη» στο
 * **«ευρεία οθόνη»**. Για τους 5+ σημερινούς καταναλωτές του αυτό είναι σωστό: όλοι
 * ρωτούν *«να δείξω τη στενή διάταξη;»*, και η απάντηση «όχι ακόμη» είναι ακίνδυνη —
 * το χειρότερο που συμβαίνει είναι μια αναπήδηση διάταξης.
 *
 * 🔴 **Εδώ η ίδια σύμπτυξη είναι το ελάττωμα.** Η ερώτηση της **Α8** δεν είναι «τι
 * διάταξη;» αλλά **«να ΚΑΤΕΒΑΣΩ τη φόρμα;»**. Ένα `false` στο πρώτο καρέ σημαίνει ότι
 * σε **κάθε κινητό** ξεκινά η δυναμική εισαγωγή — και μια εισαγωγή που ξεκίνησε
 * **δεν ακυρώνεται**. Το βάρος θα είχε ήδη ταξιδέψει όταν το `useEffect` έλεγε «στενή».
 *
 * Δηλαδή το «μόνο desktop» θα ήταν **δήλωση προθέσεων**: η οθόνη δεν θα φαινόταν, και
 * τα bytes θα είχαν φύγει. Το §2.3 του handoff το ονομάζει: *«μια οθόνη που αποδίδεται
 * και μετά κρύβεται είναι οθόνη που στάλθηκε»*. Η **Α19** (πρώτος καρές) και το §11.6
 * (φθηνή συσκευή, κινητό δίκτυο) ζητούν το αντίθετο.
 *
 * ⚠️ **ΔΕΝ αντικαθιστά το `useIsMobile`, και δεν πρέπει.** Απαντούν **διαφορετικές
 * ερωτήσεις**: εκείνο «ποια διάταξη», αυτό «τι επιτρέπεται να ταξιδέψει». Μια
 * συγχώνευση θα ανάγκαζε τους 5 υπάρχοντες καταναλωτές να χειριστούν κατάσταση που
 * δεν τους αφορά — και το τίμημα θα ήταν αναπηδήσεις διάταξης παντού.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΤΟ ΠΡΟΤΥΠΟ: **BIMx** — ο θεατής είναι ΑΛΛΟ ΠΡΟΪΟΝ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η **Α8** το ονομάζει ρητά ως πρότυπο του διαχωρισμού, και η έρευνα το επιβεβαιώνει:
 * το BIMx της Graphisoft είναι **θεατής σε κάθε πλατφόρμα** — οι δυνατότητες
 * σύνταξης μένουν στο Archicad, στον υπολογιστή. Δεν είναι «απλοποιημένη έκδοση» της
 * σύνταξης: είναι **άλλο πρόγραμμα**. Εδώ γίνεται το ίδιο σε μία εφαρμογή: η
 * δημιουργία ζει σε **δική της διαδρομή**, και το κινητό παίρνει **γραπτή εξήγηση**
 * αντί για μισή φόρμα.
 */

import { useEffect, useState } from 'react';

import { MOBILE_BREAKPOINT } from '@/constants/layout';

/**
 * Τι ξέρουμε για το πλάτος. **Ποτέ `boolean`.**
 *
 * ⚠️ Το `measuring` **δεν** είναι «φόρτωση»: είναι η μόνη ειλικρινής απάντηση στον
 * διακομιστή και στο πρώτο καρέ, όπου **δεν υπάρχει παράθυρο**. Κάθε καταναλωτής
 * οφείλει να το χειριστεί ρητά — και ο μεταγλωττιστής το επιβάλλει.
 */
export type ViewportClass = 'measuring' | 'narrow' | 'wide';

/**
 * **Το πλάτος ως τρεις καταστάσεις.**
 *
 * 🔑 **Το κατώφλι είναι το ΙΔΙΟ `MOBILE_BREAKPOINT` (768)** που χρησιμοποιεί όλη η
 * εφαρμογή. Ένας δεύτερος αριθμός εδώ θα σήμαινε ότι «στενή οθόνη» ορίζεται αλλιώς
 * ανάλογα με το ποιο χαρακτηριστικό ρωτά — δηλαδή δύο απαντήσεις σε ένα ερώτημα.
 */
export function useViewportClass(): ViewportClass {
  const [viewport, setViewport] = useState<ViewportClass>('measuring');

  useEffect(() => {
    const query = window.matchMedia(`(max-width: ${MOBILE_BREAKPOINT - 1}px)`);
    const sync = (): void => setViewport(query.matches ? 'narrow' : 'wide');

    sync();
    query.addEventListener('change', sync);
    return () => query.removeEventListener('change', sync);
  }, []);

  return viewport;
}
