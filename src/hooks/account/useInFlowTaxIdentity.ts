'use client';

/**
 * @fileoverview **ΤΟ ΑΦΜ ΜΕΣΑ ΣΕ ΜΙΑ ΡΟΗ** — η πολιτική, όχι το πεδίο.
 * @related ADR-827 §9.20 β · §9.21 ι #1 · lib/forms/draft-identity.ts · components/account/TaxIdentityField.tsx
 * @module hooks/account/useInFlowTaxIdentity
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΙ ΕΙΝΑΙ ΑΥΤΟ ΚΑΙ ΤΙ **ΔΕΝ** ΕΙΝΑΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το {@link TaxIdentityField} είναι **η εμφάνιση** — ελεγχόμενο, χωρίς γραφέα.
 * Αυτό εδώ είναι **η πολιτική**: *πότε γράφεται, τι σημαίνει το κενό, πότε δεν
 * φεύγει αίτημα, και πότε η φόρμα δεν επιτρέπεται να υποβληθεί.*
 *
 * ⚠️ Χωρίζονται επίτηδες. Το προφίλ θέλει **το πεδίο χωρίς αυτή την πολιτική** *(εκεί
 * γράφει το ένα κουμπί «Αποθήκευση», μαζί με ονόματα και επάγγελμα, και εκεί το κενό
 * **είναι** ανάκληση)*. Ένα ενιαίο component με σημαία `when="blur" | "submit"` θα
 * ήταν δύο συμπεριφορές κρυμμένες σε μία — το σχήμα που ο N.18 πληρώνει αργότερα.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ Η ΓΡΑΦΗ ΓΙΝΕΤΑΙ ΣΤΟ **BLUR** ΚΑΙ ΟΧΙ ΣΤΗΝ ΥΠΟΒΟΛΗ (N.7.2 #2 · #7)
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο εναλλακτικός σχεδιασμός — *«στο submit, γράψε ΑΦΜ και μετά POST»* — βάζει **δύο
 * πόρτες σε έναν χειριστή**, με **σειρά που μετράει**: αν η πρώτη αργήσει ή αποτύχει,
 * η δεύτερη είτε φεύγει με μπαγιάτικη ταυτότητα είτε δεν φεύγει καθόλου, και ο
 * άνθρωπος δεν μαθαίνει **ποιο από τα δύο** συνέβη.
 *
 * ✅ Έτσι η σειρά γίνεται **δομική**, όχι προσεκτική:
 *
 * > το κουμπί είναι ανενεργό όσο ζει το εμπόδιο → το εμπόδιο διαβάζει το **context**
 * > → το context τίθεται από ό,τι **γράφτηκε πραγματικά** στον διακομιστή.
 *
 * ⇒ Ο χειριστής υποβολής κάνει **μία** γραφή, και αγώνας δρόμου ανάμεσα στις δύο
 * πόρτες **δεν εκφράζεται**. *(Είναι το ίδιο δόγμα με το `ProfileAvatarField`: μια
 * ροή που κατέχει τη δική της κατάσταση δεν κρέμεται από το κουμπί της διπλανής.)*
 *
 * 🔬 **Και η επιλογή του blur δεν είναι γούστο**: η σύγκλιση της έρευνας
 * προσβασιμότητας είναι *«επικύρωση στο blur, ποτέ σε κάθε πλήκτρο»* — αναγνώστης
 * οθόνης που ανακοινώνει σφάλμα στο **τρίτο** από τα εννιά ψηφία λέει ψέματα σε
 * κάποιον που απλώς δεν τελείωσε (WCAG 4.1.3).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ ΤΙ ΔΕΝ ΚΑΝΕΙ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * - **Δεν επικυρώνει.** Ο mod-11 ζει στη **γραφή** (`judgeVatNumber`, πίσω από τη μία
 *   πόρτα). Δεύτερος επικυρωτής εδώ θα απέκλινε στην πρώτη αλλαγή, και ο άνθρωπος θα
 *   έβλεπε «εντάξει» πριν και «άκυρο» μετά — το χειρότερο δυνατό ζεύγος μηνυμάτων.
 * - **Δεν γράφει απευθείας.** Ο γραφέας είναι **ένας**: `useAuth().updateVatNumber`
 *   → `PATCH /api/account/vat-number`. Το πεδίο είναι `serverOwnedUserFields()` στα
 *   `firestore.rules`, **ήδη deployed** — `setDoc` από εδώ θα απορριπτόταν, σωστά.
 * - **Δεν φρουρεί.** Ο φρουρός είναι το **δίχτυ του Σ3** (`identity-incomplete`),
 *   που **μένει**. Αυτό εδώ μετακινεί τη **γνώση** στον μόνο άνθρωπο που μπορεί να
 *   διορθώσει το κενό — δεν αντικαθιστά καμία άμυνα.
 */

import React from 'react';

import { useAuth } from '@/auth/hooks/useAuth';
import { vatIssueKey } from '@/components/account/tax-identity-labels';
import { taxIdentityBlockers, type TaxIdentityBlocker } from '@/lib/forms/draft-identity';

/** Ό,τι χρειάζεται μια φόρμα για να δείξει **και** να κρίνει το ΑΦΜ. */
export interface InFlowTaxIdentity {
  /** Η τιμή του πεδίου — δίνεται αυτούσια στο `TaxIdentityField`. */
  readonly value: string;
  /** Κάθε πληκτρολόγηση. Καθαρίζει σιωπηλά την προηγούμενη ένσταση. */
  readonly onChange: (next: string) => void;
  /** Το πεδίο έχασε την εστίαση με περικομμένη τιμή ⇒ **εδώ γράφεται**. */
  readonly onCommit: (trimmed: string) => void;
  /** Κλειδί i18n της τρέχουσας ένστασης, ή `null`. */
  readonly issueKey: string | null;
  /**
   * Το εμπόδιο για τη λίστα του `FormIssues`.
   *
   * ⚠️ **Σταθερή ταυτότητα όσο δεν αλλάζει το ΑΦΜ** — ο `withExtraBlockers`
   * στηρίζεται σε αυτήν για να επιστρέψει το **ίδιο** αντικείμενο επικύρωσης όταν
   * δεν άλλαξε τίποτα *(η τεκμηρίωσή του: «κενή λίστα ⇒ ΤΟ ΙΔΙΟ αντικείμενο»)*.
   */
  readonly blockers: readonly TaxIdentityBlocker[];
}

export function useInFlowTaxIdentity(): InFlowTaxIdentity {
  // 🔑 **Το ΑΦΜ είναι ΗΔΗ στο context** (`auth-context-profile.ts:33`): ο
  //    `syncUserProfileToFirestore` το διαβάζει από το έγγραφο που **ήδη** ανοίγει σε
  //    κάθε σύνδεση. ⛔ **ΜΗΝ γράψεις hook που κάνει `getDoc` για να το βρει** — θα
  //    ήταν I/O σε κάθε σελίδα, η ρητή προειδοποίηση του `auth-context-profile.ts`.
  const { vatNumber, updateVatNumber } = useAuth();

  const [value, setValue] = React.useState(vatNumber ?? '');
  const [issueKey, setIssueKey] = React.useState<string | null>(null);

  // Το προφίλ φτάνει **αργότερα** από την πρώτη απόδοση (μετά το
  // `onAuthStateChanged`), οπότε σκέτος αρχικός `useState` θα πάγωνε σε κενό και θα
  // καλούσε να ξαναγράψει κάποιον που **έχει ήδη δηλώσει**. Ίδιο σφάλμα εξαρτήσεων
  // που το ADR-798 §15 μέτρησε ζωντανά στα πεδία ονόματος — **καμία πύλη δεν το
  // πιάνει**, μόνο το άνοιγμα της σελίδας.
  //
  // ⚠️ Εξάρτηση η **τιμή**, ποτέ το αντικείμενο του χρήστη: η ταυτότητά του αλλάζει
  // σε κάθε ανανέωση συνεδρίας, και effect πάνω της θα **έσβηνε ό,τι πληκτρολογεί**
  // ο άνθρωπος τη στιγμή που θα συνέβαινε η ανανέωση.
  React.useEffect(() => {
    setValue(vatNumber ?? '');
  }, [vatNumber]);

  const onChange = React.useCallback((next: string): void => {
    setValue(next);
    // Η προηγούμενη ένσταση αφορούσε τον **προηγούμενο** αριθμό.
    setIssueKey(null);
  }, []);

  const commit = React.useCallback(
    async (trimmed: string): Promise<void> => {
      // 🔴 **ΤΟ ΚΕΝΟ ΕΔΩ ΔΕΝ ΕΙΝΑΙ ΑΝΑΚΛΗΣΗ** — η σημαντικότερη γραμμή του αρχείου.
      //
      //    Στην **πόρτα**, κενό σώμα **σβήνει** το ΑΦΜ, και σωστά: είναι δικαίωμα του
      //    ανθρώπου (§9.20, GDPR 5§1ε). Μέσα σε **ροή ανάθεσης** όμως το κενό σημαίνει
      //    *«δεν το έγραψα ακόμη»* — κάποιος που σβήνει το πεδίο για να το ξαναγράψει
      //    και αλλάζει παράθυρο θα **έχανε αποθηκευμένο φορολογικό στοιχείο, χωρίς
      //    ποτέ να το ζητήσει**. Η ανάκληση είναι **πράξη**, και η πράξη ζει στο
      //    προφίλ, όπου ο άνθρωπος πήγε **για να τη διαχειριστεί**.
      //
      // 🔑 Και η οθόνη **δεν λέει ψέματα**: επαναφέρει τον αποθηκευμένο αριθμό, ώστε
      //    το πεδίο να δείχνει **αυτό που θα ταξιδέψει** στη σύμβαση — ποτέ κενό ενώ
      //    ο διακομιστής κρατά τιμή.
      if (trimmed === '') {
        setIssueKey(null);
        setValue(vatNumber ?? '');
        return;
      }

      // **Ιδεμποτεντ** (N.7.2 #3): ίδιος αριθμός ⇒ **κανένα** αίτημα δικτύου. Το blur
      // πυροδοτείται και όταν ο άνθρωπος απλώς πέρασε από το πεδίο.
      if (trimmed === vatNumber) {
        setIssueKey(null);
        return;
      }

      // 🔑 Η κατάσταση τίθεται από ό,τι **απάντησε ο διακομιστής**, ποτέ από ό,τι
      //    πληκτρολογήθηκε: ο γραφέας **κανονικοποιεί**, και το context ενημερώνεται
      //    από το `updateVatNumber` με την **αποθηκευμένη** τιμή — οπότε το effect
      //    παραπάνω ξαναγράφει το πεδίο με την αλήθεια.
      setIssueKey(vatIssueKey(await updateVatNumber(trimmed)));
    },
    [vatNumber, updateVatNumber],
  );

  const onCommit = React.useCallback(
    (trimmed: string): void => {
      // ⚠️ `void`, και είναι ρητό: ο χειριστής ενός `onBlur` **δεν** επιστρέφει
      //    υπόσχεση. Η ορθότητα δεν κρέμεται από την αναμονή — κρέμεται από το ότι το
      //    κουμπί μένει ανενεργό μέχρι το **context** να δείξει αποθηκευμένο ΑΦΜ.
      void commit(trimmed);
    },
    [commit],
  );

  /**
   * 🔴 **ΤΟ ΑΝΟΙΧΤΟ ΖΗΤΗΜΑ ΝΙΚΑΕΙ ΤΗΝ ΑΠΟΥΣΙΑ, ΚΑΙ Η ΣΕΙΡΑ ΕΙΝΑΙ ΣΥΜΒΟΛΑΙΟ.**
   *
   * Όσο υπάρχει `issueKey`, το πεδίο δείχνει έναν αριθμό που ο διακομιστής
   * **απέρριψε** — άρα **διαφορετικό** από αυτόν που θα ταξιδέψει. Η φόρμα δεν
   * επιτρέπεται να φύγει σε αυτή την κατάσταση, ακόμη κι όταν το context κρατά
   * τέλεια έγκυρο ΑΦΜ *(που είναι ακριβώς η περίπτωση που ξέφυγε)*.
   *
   * ⚠️ **Ένα εμπόδιο τη φορά, ποτέ δύο**: αν έλειπε **και** το ΑΦΜ **και** υπήρχε
   * ένσταση, δύο μηνύματα θα έλεγαν το ίδιο πράγμα με άλλα λόγια. Το ανοιχτό
   * ζήτημα είναι το **πιο πρόσφατο γεγονός**, άρα αυτό που ο άνθρωπος αναγνωρίζει.
   */
  const blockers = React.useMemo<readonly TaxIdentityBlocker[]>(
    () => (issueKey !== null ? ['tax-identity-unsaved'] : taxIdentityBlockers(vatNumber)),
    [issueKey, vatNumber],
  );

  return { value, onChange, onCommit, issueKey, blockers };
}
