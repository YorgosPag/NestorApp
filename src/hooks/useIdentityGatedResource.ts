import { useCallback, useEffect, useState } from 'react';

import { useAuth } from '@/auth/hooks/useAuth';

export interface IdentityGatedResource<T> {
  /** Το αποτέλεσμα, ή `null` όσο **δεν ξέρουμε ακόμη** — που είναι «φορτώνει». */
  readonly value: T | null;
  /** Ξαναρώτα. **Σταθερή αναφορά**, ώστε να μπορεί να μπει σε `useCallback` αλλού. */
  readonly reload: () => void;
}

/**
 * **Διάβασε κάτι, αλλά μόνο αφού λυθεί η ταυτότητα.**
 *
 * @param fetcher — τι διαβάζεται. ⚠️ **Πρέπει να είναι σταθερός** (`useCallback` στο
 *   σημείο κλήσης): αλλιώς το effect ξανατρέχει σε **κάθε απόδοση**, δηλαδή διαβάζει σε
 *   βρόχο. Ίδιος κανόνας με το `reload` του {@link useMandateRowActions}.
 * @param whenNobody — τι σημαίνει *«λύθηκε η ταυτότητα και δεν υπάρχει κανείς»* για
 *   **αυτή** την οθόνη. 🔑 **Δεν σιωπά**: αλλιώς η οθόνη θα γύριζε για πάντα
 *   (`useInboxApi`, ίδια απόφαση: *«User not authenticated - clear loading and set
 *   error»*).
 */
export function useIdentityGatedResource<T>(
  fetcher: () => Promise<T>,
  whenNobody: T,
): IdentityGatedResource<T> {
  const [value, setValue] = useState<T | null>(null);
  const [epoch, setEpoch] = useState(0);

  const { user, loading: authLoading } = useAuth();
  // ⚠️ **Πρωτογενής εξάρτηση, όχι το αντικείμενο**: το `user` του context
  // ανακατασκευάζεται και θα ξανάτρεχε το effect σε κάθε απόδοση — δηλαδή θα
  // ξαναδιάβαζε σε βρόχο.
  const userId = user?.uid ?? null;

  useEffect(() => {
    // Όσο δεν ξέρουμε **ποιος** ρωτά, η οθόνη μένει «φορτώνει» — που είναι η αλήθεια.
    if (authLoading) return;

    let alive = true;
    setValue(null);

    if (userId === null) {
      setValue(whenNobody);
      return;
    }

    void fetcher().then((loaded) => {
      if (alive) setValue(loaded);
    });

    return () => {
      alive = false;
    };
    // ⚠️ Το `whenNobody` **εξαιρείται επίτηδες**: είναι σταθερά περιγραφής, όχι είσοδος
    //    ανάγνωσης. Στη λίστα θα ανάγκαζε κάθε καλούντα να τη μνημονεύσει, αλλιώς
    //    **κάθε απόδοση** θα ξανάτρεχε την ανάγνωση — ακριβώς ο βρόχος που ο έλεγχος
    //    του `userId` παραπάνω αποφεύγει.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [epoch, authLoading, userId, fetcher]);

  const reload = useCallback(() => setEpoch((current) => current + 1), []);

  return { value, reload };
}
