import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  PLURAL_CATEGORIES_IN_USE,
  declaredCategoriesMatchCldr,
  pluralize,
} from '@/server/comms/email-plural';

/** Οι ίδιες λέξεις που στέλνει ο `interest-notifier` — γραμμένες μία φορά. */
const LOOKING = {
  one: '# άνθρωπος ψάχνει ακίνητο σαν το δικό σας',
  other: '# άνθρωποι ψάχνουν ακίνητο σαν το δικό σας',
} as const;

// =============================================================================
// Π — ΤΟ ΠΕΡΙΣΤΑΤΙΚΟ, ΚΑΙ Η ΜΕΤΑΛΛΑΞΗ ΠΟΥ ΓΥΡΙΖΕΙ ΤΗΝ ΕΤΥΜΗΓΟΡΙΑ
// =============================================================================

describe('Π — «1 άτομα» δεν ξαναγράφεται', () => {
  it('Π1 🔴 ΤΟ ΠΕΡΙΣΤΑΤΙΚΟ — το 1 παίρνει ΕΝΙΚΟ', () => {
    expect(pluralize('el', 1, LOOKING)).toBe('1 άνθρωπος ψάχνει ακίνητο σαν το δικό σας');
  });

  it('Π2 🔴 ΜΕΤΑΛΛΑΞΗ ΕΙΣΟΔΟΥ — το 2 παίρνει ΠΛΗΘΥΝΤΙΚΟ (η ετυμηγορία ΓΥΡΙΖΕΙ)', () => {
    expect(pluralize('el', 2, LOOKING)).toBe('2 άνθρωποι ψάχνουν ακίνητο σαν το δικό σας');
  });

  it('Π3 🔑 — το ΜΗΔΕΝ είναι πληθυντικό στα ελληνικά (CLDR), όχι ενικό', () => {
    // Ένας χειρόγραφος `count === 1 ? … : …` θα το πετύχαινε κι αυτό — αλλά μόνο
    // κατά τύχη. Εδώ το απαντά το CLDR, όπως και στην οθόνη.
    expect(pluralize('el', 0, LOOKING)).toBe('0 άνθρωποι ψάχνουν ακίνητο σαν το δικό σας');
  });

  it('Π4 — ο αριθμός μορφοποιείται ΚΑΤΑ ΤΗ ΓΛΩΣΣΑ, όπως το `#` του ICU', () => {
    // Η παλιά παρεμβολή `${count}` έγραφε «1000»· η οθόνη έγραφε «1.000».
    expect(pluralize('el', 1000, LOOKING)).toContain('1.000');
    expect(pluralize('en', 1000, { one: '# person', other: '# people' })).toContain('1,000');
  });

  it('Π5 🔴 ΜΕΤΑΛΛΑΞΗ ΓΛΩΣΣΑΣ — αγγλικά και ελληνικά δίνουν ΔΙΑΦΟΡΕΤΙΚΟ αποτέλεσμα', () => {
    const el = pluralize('el', 1, LOOKING);
    const en = pluralize('en', 1, { one: '# person is looking', other: '# people are looking' });
    expect(el).not.toBe(en);
    expect(en).toBe('1 person is looking');
  });

  it('Π6 — κάθε `#` αντικαθίσταται, όχι μόνο το πρώτο', () => {
    expect(pluralize('el', 3, { one: '# από #', other: '# από #' })).toBe('3 από 3');
  });
});

// =============================================================================
// Κ — Η ΔΗΛΩΣΗ ΕΛΕΓΧΕΤΑΙ ΑΠΟ ΤΟ ΙΔΙΟ ΤΟ CLDR
// =============================================================================

describe('Κ — η χειρόγραφη λίστα συμφωνεί με την πηγή', () => {
  it('Κ1 🔑 — οι δηλωμένες κατηγορίες είναι ΑΚΡΙΒΩΣ αυτές που λέει το `Intl`', () => {
    expect(declaredCategoriesMatchCldr()).toBe(true);
  });

  it('Κ2 🔴 — ο φρουρός ΜΠΟΡΕΙ να πυροδοτήσει (αλλιώς είναι σχόλιο, όχι άγκυρα)', () => {
    // Η ίδια σύγκριση, με **λάθος** δήλωση: αν αυτό περνούσε, το Κ1 δεν θα απεδείκνυε
    // τίποτα. Μάθημα CHECK 3.54: «μπορεί αυτό το test να κοκκινίσει κάτι;»
    const wrong = ['one', 'few', 'other'].sort();
    const actual = [...new Intl.PluralRules('el').resolvedOptions().pluralCategories].sort();
    expect(wrong).not.toEqual(actual);
  });

  it('Κ3 — μια γλώσσα με `few` ΥΠΑΡΧΕΙ πραγματικά (ο λόγος που δεν αρκεί τριαδικός)', () => {
    // Η αιτιολόγηση του module είναι **μετρημένη**, όχι υποθετική.
    expect(new Intl.PluralRules('pl').resolvedOptions().pluralCategories).toContain('few');
    expect(PLURAL_CATEGORIES_IN_USE.el).not.toContain('few');
  });
});

// =============================================================================
// Σ — ΕΝΑ ΛΕΞΙΛΟΓΙΟ: ΤΟ EMAIL ΚΑΙ Η ΟΘΟΝΗ ΛΕΝΕ ΤΙΣ ΙΔΙΕΣ ΛΕΞΕΙΣ
// =============================================================================

describe('Σ — η οθόνη και το email δεν αποκλίνουν', () => {
  it('Σ1 🔑 — οι λέξεις του email υπάρχουν αυτούσιες στο locale key της οθόνης', () => {
    // 🔴 Αυτή ήταν η **δεύτερη** μισή του σφάλματος, και πέρασε απαρατήρητη: η οθόνη
    //    έλεγε «άνθρωπος/άνθρωποι», το email «άτομα». Ίδιο γεγονός, άλλη λέξη.
    const el = JSON.parse(
      readFileSync(join(process.cwd(), 'src/i18n/locales/el/common-shared.json'), 'utf8'),
    ) as { demandInterest: { notificationTitle: string } };

    const screen = el.demandInterest.notificationTitle;
    expect(screen).toContain('# άνθρωπος ψάχνει');
    expect(screen).toContain('# άνθρωποι ψάχνουν');

    const source = readFileSync(
      join(process.cwd(), 'src/services/demand/interest-notifier.service.ts'),
      'utf8',
    );
    expect(source).toContain('# άνθρωπος ψάχνει');
    expect(source).toContain('# άνθρωποι ψάχνουν');
    // 🔑 **Και ο ΚΡΙΤΗΣ, όχι μόνο οι λέξεις.** Θετική δήλωση επίτηδες: μια αρνητική
    //    («να μην περιέχει τη νεκρή διατύπωση») κοκκίνισε στην πρώτη εκτέλεση,
    //    επειδή έπιανε το **σχόλιο** που τεκμηριώνει το περιστατικό. Αν κάποιος
    //    ξαναγράψει χειρόγραφο πληθυντικό, **αυτή** η κλήση εξαφανίζεται.
    expect(source).toContain("pluralize('el', count, {");
  });
});
