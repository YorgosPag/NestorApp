/**
 * =============================================================================
 * ΤΑ ΛΟΓΙΑ ΕΝΟΣ ΑΥΤΟΜΑΤΟΥ EMAIL — ΑΝΑ ΓΛΩΣΣΑ (ADR-777 §8.29)
 * =============================================================================
 *
 * **Καθαρά δεδομένα. Καμία Firestore, κανένα δίκτυο, κανένα ρολόι, κανένα i18next.**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΓΙΑΤΙ **ΟΧΙ** `t()` ΚΑΙ **ΟΧΙ** locale JSON — ΤΟ ΕΧΟΥΜΕ ΞΑΝΑΠΑΝΤΗΣΕΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `t()` απαιτεί **ενεργή γλώσσα i18next**, δηλαδή ένα αρχικοποιημένο στιγμιότυπο
 * με φορτωμένα namespaces. Αυτά τα κείμενα γράφονται από **cron**: χωρίς αίτημα
 * χρήστη, χωρίς πρόγραμμα περιήγησης, χωρίς κύκλο ζωής React. Δεν υπάρχει «τρέχουσα
 * γλώσσα» να ρωτηθεί — υπάρχει **η γλώσσα του παραλήπτη**, και είναι **παράμετρος**.
 *
 * 🔑 **Η διαφορά είναι δομική, όχι προτίμηση.** Ένα i18next στον διακομιστή θα ήταν
 * *καθολική* κατάσταση σε διεργασία που εξυπηρετεί **πολλούς** παραλήπτες μέσα στο
 * ίδιο πέρασμα: μια σύνοψη στα αγγλικά και η επόμενη στα ελληνικά θα απαιτούσαν
 * `changeLanguage` **ανάμεσα** σε δύο επαναλήψεις βρόχου. Αυτό είναι κοινή
 * μεταβλητή κατάστασης πάνω από ασύγχρονο κώδικα — δηλαδή συνθήκη αγώνα με
 * αποτέλεσμα «λάθος γλώσσα σε λάθος άνθρωπο», που **κανένα** test δεν πιάνει επειδή
 * τα tests στέλνουν ένα email τη φορά. Ένας πίνακας με παράμετρο δεν έχει κατάσταση.
 *
 * Είναι το ίδιο πρότυπο με το `REMINDER_TEXTS` (`onboarding-reminder.job.ts`), με τη
 * διαφορά ότι εκείνο έχει **μία** στήλη. Εδώ οι στήλες είναι όσες και οι γλώσσες.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΜΕΣΑ ΣΤΟΝ ΚΑΘΕ ΚΑΤΑΝΑΛΩΤΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το «Ειδοποίηση» — το θέμα ενός email που δεν έφερε δικό του — ήταν γραμμένο
 * **τρεις φορές**, μετρημένο: `orchestrator.ts` (γραμμή 245), `outbound-email-flush.job.ts`
 * (δύο σημεία). Τρία αντίγραφα σημαίνουν ότι η μετάφραση θα έφτανε σε **ένα** από τα
 * τρία και ο παραλήπτης θα έπαιρνε αγγλικό σώμα με ελληνικό θέμα, χωρίς τίποτα να
 * κοκκινίσει.
 *
 * @module server/comms/email-texts
 * @see ADR-777 §8.29
 * @see i18n/languages — ποιες γλώσσες υπάρχουν, και γιατί όχι το `pseudo`
 */

import { HUMAN_LANGUAGES, resolveHumanLanguage, type HumanLanguage } from '@/i18n/languages';

/** Τα λόγια που χρειάζεται ένα αυτόματο email, σε **μία** γλώσσα. */
export interface EmailWording {
  /**
   * Το θέμα όταν το μήνυμα δεν έφερε δικό του.
   *
   * ⚠️ Δεν είναι διακοσμητικό: ένα email **χωρίς** θέμα καταλήγει συχνότερα σε
   * ανεπιθύμητα, και ο παραλήπτης δεν έχει τίποτα να διαβάσει στη λίστα του.
   */
  readonly fallbackSubject: string;
  /**
   * **Το αποτύπωμα του αποστολέα στο θέμα** — «ΝΕΣΤΩΡ», «Nestor».
   *
   * ⚠️ **Είναι το ΟΝΟΜΑ, όχι το επίθεμα.** Το πώς κολλάει στο θέμα (παύλα; κενά;
   * παρένθεση;) το αποφασίζει το {@link brandedSubject}, σε **ένα** σημείο. Αν το
   * επίθεμα ζούσε εδώ ολόκληρο («— ΝΕΣΤΩΡ»), μια αλλαγή στίξης θα ήταν αλλαγή σε
   * **κάθε** γλώσσα — δηλαδή η ίδια απόφαση, γραμμένη όσες φορές και οι στήλες.
   */
  readonly brand: string;
  readonly digest: {
    /** ⚠️ **Πάντα πληθυντικός** — η σύνοψη είναι εξ ορισμού ≥2 (`MIN_DIGEST_SIZE`). */
    readonly subject: (count: number) => string;
    readonly intro: (count: number) => string;
    readonly footer: string;
  };
  /** ADR-848 — τα λόγια των συνδέσμων του φακέλου. */
  readonly links: {
    /**
     * Το κουμπί του μεμονωμένου email. **Περιγράφει τον προορισμό** (WebAIM) —
     * ποτέ «πάτα εδώ»: ο αναγνώστης οθόνης διαβάζει τους συνδέσμους εκτός πλαισίου.
     */
    readonly open: string;
    /** Το πρόθεμα του πλήρους URL στο **απλό κείμενο**. */
    readonly openPlain: string;
    /** «Γιατί το λαμβάνω;» — ακριβώς πάνω από τον σύνδεσμο διαχείρισης. */
    readonly whyReceived: string;
    /** Ο σύνδεσμος της σελίδας προτιμήσεων email (με token, **χωρίς** σύνδεση). */
    readonly manage: string;
    /**
     * ADR-849 — ο ίδιος σύνδεσμος στο **μεμονωμένο** email ενός τύπου, που ανοίγει τη
     * σελίδα με **αυτόν** τον τύπο μπροστά (LinkedIn/Zillow: «this type of email, only»).
     * ⚠️ Δεν ονομάζει τον τύπο: τα ονόματα ζουν στα locale της οθόνης, όχι σε δεύτερο αντίγραφο εδώ.
     */
    readonly manageType: string;
  };
}

/**
 * Ο πίνακας.
 *
 * ⚠️ **`Record<HumanLanguage, …>`, ΠΟΤΕ `Partial`.** Ο μεταγλωττιστής **απαιτεί**
 * στήλη για κάθε γλώσσα: μια τρίτη γλώσσα δεν μπορεί να προστεθεί στο
 * `SUPPORTED_LANGUAGES` και να αφήσει τα email της κενά. Με `Partial` η απουσία θα
 * ήταν έγκυρη και θα φαινόταν μόνο στα εισερχόμενα του παραλήπτη.
 *
 * ⚠️ **Η προσθήκη γλώσσας ΔΕΝ είναι μόνο εδώ**: το `LANGUAGE_DISPLAY` του επιλογέα
 * κεφαλίδας έχει τον ίδιο φρουρό τύπου, για τον ίδιο λόγο.
 */
const EMAIL_TEXTS: Readonly<Record<HumanLanguage, EmailWording>> = {
  el: {
    fallbackSubject: 'Ειδοποίηση',
    brand: 'ΝΕΣΤΩΡ',
    digest: {
      subject: (count) => `${count} νέες ειδοποιήσεις`,
      intro: (count) => `Έχετε ${count} νέες ειδοποιήσεις:`,
      footer: 'Αυτό το μήνυμα στάλθηκε αυτόματα από το Nestor.',
    },
    links: {
      open: 'Άνοιγμα στον Νέστορα',
      openPlain: 'Άνοιγμα',
      whyReceived: 'Λαμβάνετε αυτό το email επειδή έχετε ενεργές τις ειδοποιήσεις email στον Νέστορα.',
      manage: 'Διαχείριση ειδοποιήσεων email',
      manageType: 'Να μη λαμβάνω τέτοια email',
    },
  },
  en: {
    fallbackSubject: 'Notification',
    brand: 'Nestor',
    digest: {
      subject: (count) => `${count} new notifications`,
      intro: (count) => `You have ${count} new notifications:`,
      footer: 'This message was sent automatically by Nestor.',
    },
    links: {
      open: 'Open in Nestor',
      openPlain: 'Open',
      whyReceived: 'You are receiving this email because email notifications are turned on in Nestor.',
      manage: 'Manage email notifications',
      manageType: 'Stop emails like this',
    },
  },
};

/**
 * **Τα λόγια για αυτόν τον παραλήπτη.**
 *
 * Δέχεται `unknown` επίτηδες — η γλώσσα έρχεται από **έγγραφο Firestore**, δηλαδή
 * από δεδομένα. Άγνωστη τιμή πέφτει στην προεπιλογή αντί να επιστρέψει `undefined`
 * και να στείλει email με θέμα `"undefined"`.
 */
export function emailTextsFor(language: unknown): EmailWording {
  return EMAIL_TEXTS[resolveHumanLanguage(language)];
}

/**
 * **ΤΟ ΘΕΜΑ, ΣΦΡΑΓΙΣΜΕΝΟ ΑΠΟ ΤΟΝ ΑΠΟΣΤΟΛΕΑ** (ADR-777 §8.54).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΠΕΡΙΣΤΑΤΙΚΟ: ΤΕΣΣΕΡΙΣ ΠΑΡΑΓΩΓΟΙ, ΤΕΣΣΕΡΙΣ ΑΠΟΦΑΣΕΙΣ, ΤΡΕΙΣ ΙΔΙΕΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το «— ΝΕΣΤΩΡ» ήταν γραμμένο με το χέρι σε **6 σημεία, 3 αρχεία**
 * (`interest-notifier` · `listing-match-notifier` · `mandate-request-notifier`) και
 * **έλειπε** από το τέταρτο (`mandate-decision-notifier`, **6** προτάσεις). Μετρημένο
 * στα εισερχόμενα του ανθρώπου, 2026-09-05: τρεις γραμμές το είχαν, μία όχι.
 *
 * 🔴 **Και ήταν σε λάθος στρώση, όχι μόνο σε πολλά αντίγραφα.** Μέσα σε **σύνοψη**
 * το επίθεμα επαναλαμβανόταν **σε κάθε γραμμή**, κάτω από ένα θέμα που ήδη έλεγε
 * ποιος στέλνει. Ο παραγωγός ενός γεγονότος **δεν ξέρει** αν το κείμενό του θα γίνει
 * θέμα email ή γραμμή λίστας — άρα δεν μπορεί να απαντήσει «χρειάζεται υπογραφή;».
 * Ο αποστολέας ξέρει, γιατί **αυτός** φτιάχνει τον φάκελο.
 *
 * 🏆 **Ίδια πρακτική με Zillow / Airbnb / GitHub**: το αποτύπωμα της μάρκας ανήκει
 * στο **επίπεδο παράδοσης** (όνομα αποστολέα + θέμα), ποτέ στον παραγωγό του
 * συμβάντος. Το κερδισμένο εδώ είναι ότι το επίθεμα ακολουθεί πλέον **τη γλώσσα του
 * παραλήπτη**: κανένας από τους 4 παραγωγούς δεν το έκανε αυτό — έγραφαν ελληνικά
 * σε κάθε παραλήπτη.
 *
 * ⚠️ **ΕΙΝΑΙ ΑΜΕΤΑΒΛΗΤΗ ΠΡΑΞΗ (N.7.2 #3), ΚΑΙ ΧΡΕΙΑΖΕΤΑΙ ΝΑ ΕΙΝΑΙ.** Την ίδια ουρά
 * μοιράζονται μηνύματα που **δεν** είναι ειδοποιήσεις — οι επώνυμες κοινοποιήσεις
 * ακινήτων φέρνουν **δικό τους** θέμα από το `email-templates`. Χωρίς τον έλεγχο, ένα
 * θέμα που ήδη υπογράφει θα υπέγραφε **δύο φορές**. Και τα ήδη γραμμένα `pending`
 * έγγραφα της ουράς κουβαλούν το παλιό, χειρόγραφο επίθεμα **για πάντα**.
 */
export function brandedSubject(language: unknown, subject: string): string {
  const { brand } = emailTextsFor(language);
  const trimmed = subject.trim();
  // ⚠️ Ο έλεγχος γίνεται στο **όνομα**, όχι στο πλήρες επίθεμα: το χειρόγραφο
  // παρελθόν έγραφε «— ΝΕΣΤΩΡ» με παύλα em, αλλά ένα μελλοντικό (ή ξένο) θέμα
  // μπορεί να υπογράφει αλλιώς. Η ερώτηση είναι «υπογράφει ήδη;», όχι «υπογράφει
  // ΜΕ ΤΟΝ ΔΙΚΟ ΜΑΣ ΤΡΟΠΟ;».
  if (trimmed.endsWith(brand)) return trimmed;
  return `${trimmed} — ${brand}`;
}

/**
 * **Έχει κάθε γλώσσα τα λόγια της;**
 *
 * Υπάρχει **για να αποτύχει θορυβωδώς** σε άγκυρα. Ο τύπος `Record` το εγγυάται σε
 * χρόνο μεταγλώττισης — αλλά ο κανόνας N.17 απαγορεύει στον πράκτορα να τρέξει
 * `tsc`, οπότε **στη ροή εργασίας μας ο μεταγλωττιστής δεν είναι φρουρός που
 * εκτελείται**: τρέχει αργότερα, από τον άνθρωπο ή από το pre-commit. Αυτό εδώ
 * εκτελείται με τα tests.
 */
export function everyLanguageHasWording(): boolean {
  return HUMAN_LANGUAGES.every((language) => {
    const wording = EMAIL_TEXTS[language];
    return (
      typeof wording?.fallbackSubject === 'string' &&
      wording.fallbackSubject.length > 0 &&
      typeof wording.brand === 'string' &&
      wording.brand.length > 0 &&
      typeof wording.digest?.footer === 'string' &&
      wording.digest.footer.length > 0 &&
      typeof wording.digest.subject(2) === 'string' &&
      typeof wording.digest.intro(2) === 'string' &&
      // ADR-848 — ένα email με κουμπί χωρίς ετικέτα είναι χειρότερο από email χωρίς κουμπί.
      [
        wording.links?.open,
        wording.links?.openPlain,
        wording.links?.whyReceived,
        wording.links?.manage,
        wording.links?.manageType,
      ]
        .every((text) => typeof text === 'string' && text.length > 0)
    );
  });
}
