'use client';

/**
 * =============================================================================
 * **Η ΚΑΡΤΑ ΠΟΥ ΦΟΡΤΩΝΕΙ** — μία φορά, για κάθε κάρτα (ADR-229)
 * =============================================================================
 *
 * 🔴 **ΓΕΝΝΗΘΗΚΕ ΑΠΟ ΜΕΤΡΗΣΗ ΤΟΥ CHECK 3.28, ΟΧΙ ΑΠΟ ΓΟΥΣΤΟ.** Το ίδιο ακριβώς
 * μπλοκ — `<Card><CardContent className="flex items-center justify-center py-12">
 * <Spinner size="large" /></CardContent></Card>` — μετρήθηκε αυτούσιο σε **οκτώ**
 * αρχεία *(ΙΚΑ · λογιστική · προμήθειες)*, και η πύλη το έπιασε τη στιγμή που δύο
 * από αυτά στάλθηκαν μαζί.
 *
 * ⚠️ **ΔΕΝ αντικαθιστά το {@link PageLoadingState}, και η διαφορά δεν είναι μέγεθος.**
 * Εκείνο απαντά *«η **σελίδα** δεν έχει τίποτα να δείξει ακόμη»* — κρατά ολόκληρο το
 * ύψος και **μιλάει** *(υποχρεωτικό `message`)*. Αυτό εδώ απαντά *«**μια κάρτα** μέσα σε
 * σελίδα που ήδη έχει περιεχόμενο περιμένει»* — κρατά τη **θέση** της κάρτας ώστε η
 * διάταξη γύρω της να μην αναπηδήσει, και **σιωπά**: ένα «Φόρτωση…» ανά κάρτα σε οθόνη
 * με τέσσερις κάρτες είναι θόρυβος, όχι πληροφορία.
 *
 * 🔑 **`aria-busy` στο δοχείο, όχι κείμενο για αναγνώστη οθόνης**: η κάρτα **υπάρχει
 * ήδη** στο δέντρο προσβασιμότητας· αυτό που αλλάζει είναι η **κατάστασή** της. Ένα
 * `role="status"` εδώ θα ανακοίνωνε «φόρτωση» τέσσερις φορές σε μία οθόνη.
 *
 * @module core/states/CardLoadingState
 */

import { Card, CardContent } from '@/components/ui/card';
import { Spinner } from '@/components/ui/spinner';

export interface CardLoadingStateProps {
  /**
   * Προαιρετική περιγραφή για αναγνώστες οθόνης, **όταν η κάρτα είναι η ΜΟΝΗ**
   * που φορτώνει στην οθόνη. ⚠️ Άφησέ το κενό σε πλέγμα καρτών.
   */
  readonly label?: string;
}

/**
 * Κράτα τη θέση της κάρτας όσο περιμένει.
 *
 * @example
 * if (isLoading) return <CardLoadingState />;
 */
export function CardLoadingState({ label }: CardLoadingStateProps = {}) {
  return (
    <Card aria-busy aria-label={label}>
      <CardContent className="flex items-center justify-center py-12">
        <Spinner size="large" />
      </CardContent>
    </Card>
  );
}
