'use client';

import * as React from 'react';

import { cn } from '@/lib/utils';

/**
 * 🖼️ **Η ΔΗΛΩΣΗ «ΑΥΤΗ Η ΣΕΛΙΔΑ ΔΕΝ ΘΕΛΕΙ ΔΙΑΔΡΟΜΟ»** (ADR-797).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΤΟ ΕΡΩΤΗΜΑ ΠΟΥ ΑΠΑΝΤΑ — ΚΑΙ ΓΙΑΤΙ ΕΙΝΑΙ ΔΕΥΤΕΡΟ, ΟΧΙ ΤΟ ΙΔΙΟ
 * ────────────────────────────────────────────────────────────────────────────
 * Το κέλυφος απαντά **«πόσο κενό;»** ρευστά, από το πλάτος της επιφάνειας.
 * Αυτό εδώ απαντά **«κενό καθόλου;»** — και είναι **άλλη** ερώτηση, με άλλη
 * θεραπεία. Ένας μηχανισμός με «ή» θα ήταν πράσινος **και προς τις δύο**
 * κατευθύνσεις: ο χάρτης θα έπαιρνε «λίγο» κενό αντί για κανένα, και μια φόρμα
 * θα μπορούσε να πέσει στο μηδέν χωρίς να το δηλώσει κανείς (μάθημα CHECK 3.41).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΠΟΤΕ ΤΟ ΧΡΗΣΙΜΟΠΟΙΕΙΣ
 * ────────────────────────────────────────────────────────────────────────────
 * **Μόνο** όταν η επιφάνεια είναι *καμβάς*: χάρτης, σχέδιο DXF, τρισδιάστατη
 * σκηνή, viewer που γεμίζει το παράθυρο. Εκεί ο διάδρομος δεν είναι αισθητική
 * επιλογή — είναι **χαμένη επιφάνεια σχεδίασης**.
 *
 * ⛔ **ΔΕΝ** το χρησιμοποιείς για «θέλω λίγο πιο φαρδιά». Ο διάδρομος είναι
 * ρευστός: σε φαρδιά οθόνη μεγαλώνει, σε στενή μικραίνει. Αν σου φαίνεται
 * λάθος, το λάθος είναι στους **πόλους** (`design-tokens.json` →
 * `spacing.layout`), και η διόρθωση αφορά **όλη** την εφαρμογή.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΠΩΣ ΔΟΥΛΕΥΕΙ
 * ────────────────────────────────────────────────────────────────────────────
 * Βάζει `data-shell-surface="bleed"`. Το κέλυφος το βλέπει με `:has()` και
 * μηδενίζει τον **δικό του** διάδρομο. Μηδέν context, μηδέν prop drilling,
 * μηδέν React state — τα δύο μέρη **δεν γνωρίζονται**.
 *
 * ⚠️ Το `--shell-gutter` παραμένει **αναγνώσιμο** μέσα σε αυτή την επιφάνεια:
 * ένα πλωτό πάνελ πάνω στον καμβά μπορεί να ευθυγραμμιστεί με τον διάδρομο
 * των **άλλων** σελίδων γράφοντας `var(--shell-gutter)`, αντί να ξαναβρεί τον
 * αριθμό μόνο του.
 *
 * ⚠️ **Πρέπει να είναι απόγονος του κελύφους** (`(app)` route group). Σε
 * `(light)`/`(auth)` δεν υπάρχει διάδρομος να ακυρωθεί, οπότε δεν κάνει τίποτα.
 *
 * @example
 * export default function MapPage() {
 *   return (
 *     <FullBleedSurface className="h-full">
 *       <InteractiveMap />
 *     </FullBleedSurface>
 *   );
 * }
 */
export interface FullBleedSurfaceProps {
  readonly children: React.ReactNode;
  readonly className?: string;
  /**
   * Ετικέτα προσιτότητας. Η επιφάνεια είναι `<section>`, και μια ανώνυμη
   * περιοχή δεν λέει τίποτα στον αναγνώστη οθόνης.
   */
  readonly ariaLabel?: string;
}

export function FullBleedSurface({
  children,
  className,
  ariaLabel,
}: FullBleedSurfaceProps): React.ReactElement {
  return (
    <section
      data-shell-surface="bleed"
      aria-label={ariaLabel}
      className={cn('w-full', className)}
    >
      {children}
    </section>
  );
}
