/**
 * **ΟΙ ΚΑΘΟΛΙΚΕΣ ΔΥΝΑΤΟΤΗΤΕΣ** — ό,τι υπόσχεται το κέλυφος σε **κάθε** οθόνη.
 *
 * @related ADR-809 (CHECK 3.72) · ADR-777 §8.12 (CHECK 3.52) · ADR-797 (CHECK 3.63)
 * @module core/containers/ShellUtilities
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΜΕΤΡΗΜΕΝΟ ΕΛΑΤΤΩΜΑ (2026-08-26, ΠΡΙΝ γραφτεί αυτό το αρχείο)
 * ────────────────────────────────────────────────────────────────────────────
 * **Πέντε γειτονιές, πέντε διαφορετικά κελύφη**, και καμία αρχή που να λέει τι
 * οφείλει να προσφέρει η καθεμία:
 *
 * | γειτονιά | κέλυφος            | γλώσσα | θέμα | λογαριασμός |
 * |----------|--------------------|:------:|:----:|:-----------:|
 * | `(app)`  | `AppHeader`        |   ✅   |  ✅  |     ✅      |
 * | `(auth)` | `AuthScreenChrome` |   ✅   |  ✅  |     ❌      |
 * | `(light)`| `PublicSiteHeader` |   ❌   |  ❌  |     ❌      |
 * | `(me)`   | `PublicSiteHeader` |   ❌   |  ❌  |     ❌      |
 * | `(bare)` | —                  |   ❌   |  ❌  |     ❌      |
 *
 * ⇒ **2 στις 5** έδιναν γλώσσα+θέμα· **1 στις 5** έδινε λογαριασμό. Οι τρεις
 * διακόπτες **υπήρχαν ήδη** ως components — αυτό που έλειπε ήταν **ιδιοκτήτης**:
 * κάθε κέλυφος ξανα-αποφάσιζε μόνο του, δηλαδή το σχήμα «N λίστες που
 * αποκλίνουν» που το repo έχει πληρώσει **μετρημένα πέντε φορές** (CHECK 3.34
 * απόκλιση 63 · 3.37 18 vs 26 · 3.49 60 · 3.57 19/20 · ο `ConditionalAppShell`
 * του 3.52).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 Η ΤΑΥΤΟΤΗΤΑ ΚΡΙΝΕΤΑΙ **ΜΙΑ** ΦΟΡΑ, ΚΑΙ ΟΧΙ ΕΔΩ
 * ────────────────────────────────────────────────────────────────────────────
 * Το {@link UserMenu} κάνει ήδη `if (!user && !isLoggingOut) return null`
 * (`user-menu.tsx:68`). Άρα αποδίδεται **άνευ όρων** και **αυτοκρύβεται** όταν
 * δεν υπάρχει άνθρωπος.
 *
 * ⛔ **ΜΗΝ προσθέσεις εδώ `useAuth()` για να «αποφασίσεις αν να τον δείξεις».**
 * Θα ήταν **δεύτερη απάντηση στο «υπάρχει άνθρωπος;»** — το σχήμα του ADR-749,
 * και οι δύο απαντήσεις θα μπορούσαν να αποκλίνουν (π.χ. στο παράθυρο του
 * `isLoggingOut`, όπου το μενού **επίτηδες** μένει ορατό).
 *
 * 🔑 **Γι' αυτό το `(auth)` είναι σωστό ΧΩΡΙΣ καμία δήλωση**: εκεί δεν υπάρχει
 * ταυτότητα, άρα ο λογαριασμός δεν αποδίδεται — **δομικά**, όχι κατόπιν
 * ρύθμισης. Μια σημαία `account={false}` θα ήταν δεύτερη αλήθεια δίπλα στο
 * κλειστό σύνολο, και θα αποκλίνει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΟ `signedOutAction` ΕΙΝΑΙ Η ΓΩΝΙΑ ΤΟΥ **ΚΟΣΜΟΥ**, ΟΧΙ ΤΟΥ ΚΕΛΥΦΟΥΣ
 * ────────────────────────────────────────────────────────────────────────────
 * «Τι βλέπει ο **ανώνυμος** στη θέση του λογαριασμού;» **δεν** έχει καθολική
 * απάντηση, και η μέτρηση το δείχνει: ο δημόσιος ιστότοπος οφείλει να δίνει
 * πόρτα «Σύνδεση»· η **ίδια η οθόνη σύνδεσης** οφείλει να **μη** δίνει (θα ήταν
 * σύνδεσμος προς τον εαυτό της)· το `(app)` δεν έχει ποτέ ανώνυμο.
 *
 * Άρα το **καθολικό** μισό (γλώσσα · θέμα · λογαριασμός) το κατέχει αυτό το
 * αρχείο, και το **κοσμικό** μισό το περνά ο καλών. Η ταυτότητα κρίνεται μία
 * φορά — εδώ — και **και τα δύο** μισά την ακολουθούν.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΤΟ ΜΕΤΡΗΜΕΝΟ ΚΟΣΤΟΣ, ΚΑΙ Ο ΠΑΡΟΝΟΜΑΣΤΗΣ ΠΟΥ ΤΟ ΕΚΑΝΕ ΜΙΚΡΟ
 * ────────────────────────────────────────────────────────────────────────────
 * Η πρώτη μέτρηση έδινε **+3.157 KB** και ήταν **ψευδής**: μετρούσε την
 * κλειστότητα του `PublicSiteHeader` **μόνου του**. Και τα τέσσερα βαριά πακέτα
 * (`firebase` · `zod` · `qrcode` · `date-fns`) μπαίνουν από **έναν** κόμβο —
 * το `auth/contexts/AuthContext.tsx` — που ζει στο **ΡΙΖΙΚΟ** `layout.tsx:81`,
 * άρα είναι **ήδη** στην κλειστότητα κάθε σελίδας. Ο παρονομαστής είναι η
 * **σελίδα**, όχι το component.
 *
 * Με σωστό παρονομαστή (ριζικό layout + layout γειτονιάς + σελίδα):
 * **+8 αρχεία · +84,5 KB πηγής · +2,3%**, και **δύο** νέα πακέτα
 * (`@radix-ui/react-avatar`, `@radix-ui/react-tooltip`). Το «−41% έως −59% SSR
 * bytes» που επικαλείται η δήλωση του `.shell-boundary.json` αφορά τους **9
 * βαρείς providers + sidebar** — που αυτό **δεν** αγγίζει.
 *
 * ⚠️ **ΔΕΝ αποδίδει `<nav>`**: ο καλών το τοποθετεί ήδη **μέσα** στο δικό του
 * `<header>`/`<nav>`, και ένα εμφωλευμένο landmark πλοήγησης θα πρόσθετε δεύτερη
 * είσοδο στη λίστα του αναγνώστη οθόνης για την **ίδια** ομάδα χειριστηρίων.
 */

import React from 'react';

import { LanguageSwitcher } from '@/components/header/language-switcher';
import { ThemeToggle } from '@/components/header/theme-toggle';
import { UserMenu } from '@/components/header/user-menu';
import { TooltipProvider } from '@/components/ui/tooltip';

/**
 * @param signedOutAction Τι μπαίνει στη θέση του λογαριασμού όταν **δεν**
 *   υπάρχει ταυτότητα. Παραλείπεται όπου δεν έχει νόημα (`(auth)`, `(app)`).
 * @param className Επιπλέον κλάσεις **διάταξης** του καλούντος — ποτέ χρώματος.
 */
export function ShellUtilities({
  signedOutAction,
  className,
}: Readonly<{
  signedOutAction?: React.ReactNode;
  className?: string;
}>): React.ReactElement {
  return (
    /*
      🔴 **Ο ΙΔΙΟΚΤΗΤΗΣ ΕΓΓΥΑΤΑΙ ΤΙΣ ΠΡΟΫΠΟΘΕΣΕΙΣ ΤΟΥ** — ζωντανή βλάβη, 26/08.

      Το `UserMenu` αποδίδει `DeclaredOccupationBadge`, που χρησιμοποιεί Radix
      `Tooltip`. Οι γειτονιές `(app)` · `(auth)` · `(bare)` έχουν `TooltipProvider`
      στο layout τους· οι **`(light)` και `(me)` ΟΧΙ** — και ακριβώς εκεί τα
      έβαλε το ADR-809 ⇒ «`Tooltip` must be used within `TooltipProvider`» ⇒
      **ολόκληρη η διαδρομή έπεφτε στο `global-error`**.

      ⚠️ **ΓΙΑΤΙ ΟΙ ΑΓΚΥΡΕΣ ΤΟΥ ADR-809 ΗΤΑΝ ΠΡΑΣΙΝΕΣ**: το `<Tooltip>` ζει
      **μόνο** στον κλάδο «δηλωμένο επάγγελμα» του badge, και οι άγκυρες
      έτρεχαν με **αδήλωτο**. Κάλυπταν την περίπτωση που **δεν** σπάει.
      Ο `Κ8` κλείνει ακριβώς αυτό.

      ⚠️ **ΔΕΝ διορθώθηκε προσθέτοντας provider στα δύο layouts**: θα ήταν
      **τέταρτο και πέμπτο** αντίγραφο της ίδιας απόφασης, και η **έκτη**
      γειτονιά θα το ξανάσπαγε. Το repo έχει ήδη τη σύμβαση γραμμένη —
      `TableFormatToolbar.tsx:240` *«Δικός του TooltipProvider, όχι εξάρτηση
      από τον περιβάλλοντα»* — απλώς κανείς δεν την επέβαλλε εδώ.

      ⚠️ Το ένθετο `TooltipProvider` μέσα σε υπάρχον είναι **νόμιμο** στο Radix
      και το `delayDuration={300}` είναι **ταυτόσημο** με των τριών layouts, άρα
      μηδέν αλλαγή συμπεριφοράς εκεί που ήδη υπήρχε.
    */
    <TooltipProvider delayDuration={300}>
    <div className={className ? `flex items-center gap-2 ${className}` : 'flex items-center gap-2'}>
      {/*
        ⚠️ **Η ΣΕΙΡΑ ΕΙΝΑΙ ΣΥΜΒΟΛΑΙΟ, ΚΑΙ ΕΙΝΑΙ ΚΑΝΟΝΙΣΤΙΚΗ.** Το **WCAG 2.2
        SC 3.2.3 Consistent Navigation** (επίπεδο **AA**) απαιτεί οι
        επαναλαμβανόμενοι μηχανισμοί πλοήγησης να εμφανίζονται «*in the **same
        relative order** each time they are repeated*».

        🔑 Και αυτό είναι **ΟΛΟ** όσο δίνει το πρότυπο: το αδελφό **SC 3.2.6**
        λέει ρητά ότι «*the **absence** of a help mechanism on certain pages
        within a set **does not constitute a violation***». Δηλαδή το WCAG φυλά
        τη **ΣΕΙΡΑ**, ποτέ την **ΠΑΡΟΥΣΙΑ** — και η σειρά ήταν **ήδη** συνεπής
        (γλώσσα → θέμα, και στους δύο παλιούς συναρμολογητές).

        ⚠️ **Άρα ΜΗΝ επικαλεστείς το WCAG ως λόγο ύπαρξης αυτού του αρχείου.**
        Η παρουσία είναι **απόφαση προϊόντος**· εδώ γίνεται μηχανικά ελέγξιμη.
      */}
      <LanguageSwitcher />
      <ThemeToggle />
      {/*
        🔑 **Ο λογαριασμός Ή η πόρτα του ανωνύμου — ΠΟΤΕ ΚΑΙ ΤΑ ΔΥΟ, και ο
        διαχωρισμός γίνεται ΜΕΣΑ στο `UserMenu`.**

        🔴 Η πρώτη γραφή αυτού του αρχείου απέδιδε το `signedOutAction` **δίπλα**
        στο μενού, άνευ όρων ⇒ ο **συνδεδεμένος** θα έβλεπε μενού **ΚΑΙ**
        «Σύνδεση»: το ίδιο ακριβώς ψέμα που το αρχείο γράφτηκε να σβήσει, σε νέα
        θέση. Το έπιασε η ανάγνωση της **ίδιας** μου της γραμμής, όχι κάποια πύλη.

        Η θεραπεία **δεν** ήταν δεύτερος έλεγχος ταυτότητας εδώ — ήταν να πάει το
        `signedOut` **εκεί όπου η ταυτότητα κρίνεται ήδη** (`user-menu.tsx:68`).
        Μία ανάγνωση, δύο κλάδοι, μηδέν πιθανότητα απόκλισης.
      */}
      <UserMenu signedOut={signedOutAction} />
    </div>
    </TooltipProvider>
  );
}
