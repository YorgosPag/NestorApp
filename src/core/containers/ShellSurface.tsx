/**
 * Ο ρόλος του **μέτρου** — πλάτος γραμμής σε **χαρακτήρες**, από το
 * `design-tokens.json → spacing.layout.measure`.
 *
 * ⚠️ **ΜΗΝ** προσθέσεις ρόλο εδώ χωρίς να τον προσθέσεις **πρώτα** στα tokens:
 * ένα άγνωστο όνομα δεν αφήνει το `--shell-measure` κενό — το αφήνει
 * **αόριστο**, οπότε το `min(var(--shell-measure), 100%)` γίνεται *invalid at
 * computed-value time* και η στήλη πέφτει σε **auto**. Δηλαδή το ταβάνι
 * εξαφανίζεται **σιωπηλά**, χωρίς να σπάσει τίποτα ορατά.
 */
export type ShellMeasure = 'prose' | 'wide';

export interface ShellSurfaceProps {
  readonly children: React.ReactNode;
  /**
   * Το στοιχείο που αποδίδεται. **Προεπιλογή `div`** — δες την τρίτη
   * απαγόρευση παραπάνω. Το `main` το ζητά **μόνο** ο ιδιοκτήτης του κελύφους,
   * όπου η σελίδα *δεν* αποδίδει δικό της.
   */
  readonly as?: 'div' | 'main';
  /**
   * Το ταβάνι πλάτους της γραμμής. **Παραλείπεται** όταν η επιφάνεια είναι
   * εργαλείο πυκνών δεδομένων (πίνακες, καμβάς, λογιστική).
   */
  readonly measure?: ShellMeasure;
  readonly className?: string;
  /**
   * Ετικέτα προσιτότητας — έχει νόημα **μόνο** με `as="main"`. Σε `div` το
   * `aria-label` χωρίς ρόλο δεν ανακοινώνεται πουθενά.
   */
  readonly ariaLabel?: string;
}

export function ShellSurface({
  children,
  as = 'div',
  measure,
  className,
  ariaLabel,
}: ShellSurfaceProps): React.ReactElement {
  const Tag = as;

  return (
    <Tag
      data-shell-surface=""
      data-shell-measure={measure}
      aria-label={as === 'main' ? ariaLabel : undefined}
      className={cn('w-full', className)}
    >
      {children}
    </Tag>
  );
}
