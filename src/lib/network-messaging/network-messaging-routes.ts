/** **Τα μηνύματά μου** — ο κατάλογος των νημάτων του ανθρώπου. */
export const MY_MESSAGES_ROUTE = '/messages' as const;

/**
 * **Μία συνομιλία** — η κανονική της διεύθυνση, στον ιδιωτικό χώρο **κάθε** αναγνώστη.
 *
 * ⚠️ `encodeURIComponent`: το `threadId` έρχεται από δεδομένα (θέμα νήματος, ειδοποίηση), ποτέ από
 * σταθερά — ίδιο ιδίωμα με το `offerThreadHref`.
 */
export function threadHref(threadId: string): string {
  return `${MY_MESSAGES_ROUTE}/${encodeURIComponent(threadId)}`;
}
