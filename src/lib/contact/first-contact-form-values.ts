import { isValidEmail } from '@/lib/validation/email-validation';
import { isValidPhone } from '@/lib/validation/phone-validation';

/** Ό,τι πληκτρολογεί ο άνθρωπος — **συμβολοσειρές**, όπως τις δίνει το `<input>`. */
export interface FirstContactFormValues {
  readonly name: string;
  readonly email: string;
  readonly phone: string;
}

/**
 * **Τι εμποδίζει την αποστολή** — κλειστό σύνολο, κάθε κωδικός γίνεται κλειδί i18n.
 *
 * 🔑 Η σειρά **είναι** η σειρά εμφάνισης στη σύνοψη σφαλμάτων, και ταιριάζει με τη
 * σειρά των πεδίων στην οθόνη *(GOV.UK: η σύνοψη ακολουθεί την οπτική σειρά, αλλιώς ο
 * σύνδεσμος «πήγαινε στο πεδίο» πετά τον άνθρωπο πάνω-κάτω)*.
 */
export const FIRST_CONTACT_FORM_BLOCKERS = [
  /** Κενό όνομα. Ο διακομιστής θα το έλεγε `contact-no-name` — εδώ προλαβαίνουμε. */
  'contact-name-unset',
  /**
   * **Κενό email.**
   *
   * 🔴 **ΑΝΤΙΚΑΤΕΣΤΗΣΕ ΤΟ `contact-channel-unset` ΣΤΙΣ 2026-09-05 (ADR-844), ΚΑΙ ΔΕΝ
   * ΠΡΟΣΤΕΘΗΚΕ ΔΙΠΛΑ ΤΟΥ.** Ο παλιός κωδικός έλεγε *«ούτε email ούτε τηλέφωνο»* — μία
   * ερώτηση για **δύο** πεδία, σωστή όσο η απαίτηση ήταν *«άφησε **έναν** τρόπο, εσύ
   * διαλέγεις ποιον»* (ΠΕ4).
   *
   * Η απόφαση #3 του ADR-844 *(«κανένα ανεπαλήθευτο κανάλι»)* την άλλαξε: το κανάλι που
   * **μπορούμε να αποδείξουμε** είναι **ένα**, και η πράξη δεν φεύγει μέχρι να
   * αποδειχθεί. Άρα το email γίνεται **απαιτούμενο** και το τηλέφωνο μένει
   * **προαιρετικό πρόσθετο** (απόφαση #5).
   *
   * ⚠️ **ΓΙΑΤΙ ΑΝΤΙΚΑΤΑΣΤΑΣΗ ΚΑΙ ΟΧΙ ΠΡΟΣΘΗΚΗ**: με το email απαιτούμενο, το *«ούτε
   * το ένα ούτε το άλλο»* είναι **αυστηρά ασθενέστερο** από το *«λείπει το email»* —
   * κενή φόρμα θα κοκκίνιζε **δύο** γραμμές σύνοψης για **ένα** πεδίο, και ο σύνδεσμος
   * και των δύο θα έδειχνε στο **ίδιο** `<input>`. Το πρότυπο GOV.UK ζητά **μία**
   * γραμμή ανά διορθώσιμο πράγμα.
   *
   * ⚠️ **Ο διακομιστής ΔΕΝ άλλαξε**: το αμετάβλητο `contact-no-channel` μένει αυτούσιο
   * και εξακολουθεί να δέχεται πράξη με **μόνο** τηλέφωνο — γιατί κρίνει την **πράξη**,
   * και υπάρχουν πράξεις που δεν γεννήθηκαν από αυτή τη φόρμα. *Ίδιο λεξιλόγιο, άλλη
   * στιγμή, άλλη φωνή* — το δόγμα της κεφαλίδας, ανέπαφο.
   */
  'contact-email-unset',
  /**
   * Το email δεν στέκει ως email.
   *
   * 🔑 **Ξεχωριστό από το `channel-unset`**: *«δεν έδωσες τίποτα»* και *«έδωσες κάτι
   * που δεν διαβάζεται»* στέλνουν τον άνθρωπο σε **διαφορετική** πράξη — ίδιο δόγμα
   * με το ζεύγος `expiry-unset` / `expiry-past` του γειτονικού υποσυστήματος.
   */
  'contact-email-malformed',
  /** Το τηλέφωνο δεν στέκει — ελληνικό ή διεθνές, το κρίνει το SSoT. */
  'contact-phone-malformed',
] as const;

export type FirstContactFormBlocker = (typeof FIRST_CONTACT_FORM_BLOCKERS)[number];

/**
 * **Ποιο πεδίο φταίει** — ώστε ο σύνδεσμος της σύνοψης να έχει πού να πάει.
 *
 * 🔴 **ΠΛΗΡΗΣ `Record`, ΟΧΙ `Partial`**: ένα εμπόδιο **χωρίς πεδίο** θα ήταν γραμμή
 * σύνοψης που **δεν πηγαίνει πουθενά** — δηλαδή ακριβώς η αποτυχία που το πρότυπο
 * GOV.UK υπάρχει για να αποτρέψει. Ο πέμπτος κωδικός **δεν μεταγλωττίζεται** χωρίς
 * απάντηση στο *«πού στέκεται ο άνθρωπος για να το διορθώσει;»*.
 */
export const BLOCKER_FIELD: Record<FirstContactFormBlocker, keyof FirstContactFormValues> = {
  'contact-name-unset': 'name',
  'contact-email-unset': 'email',
  'contact-email-malformed': 'email',
  'contact-phone-malformed': 'phone',
};

/**
 * **Τι λείπει. ΟΛΑ, ποτέ το πρώτο.**
 *
 * 🔑 Η επιστροφή είναι **πίνακας**, όχι «πρώτο σφάλμα»: ο άνθρωπος που διορθώνει ένα
 * τη φορά και ξαναπατά κάνει **τρεις** γύρους για τρία λάθη. Το πρότυπο GOV.UK απαιτεί
 * **όλα μαζί**, μία φορά.
 *
 * ⚠️ **Το κενό ΤΗΛΕΦΩΝΟ δεν είναι κακοσχηματισμένο.** Το τηλέφωνο είναι **προαιρετικό
 * πρόσθετο** (ADR-844, απόφαση #5) — ο έλεγχος μορφής τρέχει **μόνο** πάνω σε ό,τι ο
 * άνθρωπος **έγραψε**. Αλλιώς η οθόνη θα το απαιτούσε σιωπηλά.
 *
 * ⚠️ **Το κενό EMAIL βγάζει ΜΟΝΟ `contact-email-unset`, ποτέ ΚΑΙ `-malformed`.** Το
 * *«δεν έδωσες τίποτα»* και το *«έδωσες κάτι που δεν διαβάζεται»* στέλνουν σε
 * **διαφορετική** πράξη, και οι δύο μαζί θα ήταν δύο γραμμές για ένα πεδίο.
 */
export function firstContactFormBlockers(
  values: FirstContactFormValues,
): readonly FirstContactFormBlocker[] {
  const found: FirstContactFormBlocker[] = [];

  const email = values.email.trim();
  const phone = values.phone.trim();

  if (values.name.trim() === '') found.push('contact-name-unset');
  if (email === '') found.push('contact-email-unset');
  else if (!isValidEmail(email)) found.push('contact-email-malformed');
  if (phone !== '' && !isValidPhone(phone)) found.push('contact-phone-malformed');

  return found;
}

/**
 * **Ό,τι φεύγει στο σύρμα** — και το `null` είναι **σημασία**, όχι καθάρισμα.
 *
 * 🔴 Το `hasReplyChannel` του διακομιστή ρωτά `email !== null`. Ένα κενό string θα
 * περνούσε αυτόν τον έλεγχο και θα γραφόταν πράξη με **κανάλι που δεν υπάρχει** —
 * αδιέξοδο με ημερομηνία. Η μετατροπή γίνεται **εδώ, μία φορά**, ώστε καμία οθόνη να
 * μην την ξαναθυμηθεί.
 */
export function disclosureChannelOf(raw: string): string | null {
  const trimmed = raw.trim();
  return trimmed === '' ? null : trimmed;
}
