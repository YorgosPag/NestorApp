import type { FirstContact, FirstContactLifecycle } from '@/types/first-contact';
import { OPEN_CONTACT_CAPACITY } from './first-contact-limits';

/**
 * **Η κατάσταση της χωρητικότητας ενός ανθρώπου.**
 *
 * ⚠️ **Δεν αποθηκεύεται πουθενά** — υπολογίζεται από το σύνολο των πράξεων. Πεδίο
 * «θέσεις που έμειναν» μέσα σε έγγραφο θα ήταν αντίγραφο μεγέθους που ανήκει στο
 * **σύνολο**, και θα **παλιώνε** τη στιγμή που κάποιος αποσύρει μια πράξη.
 */
export interface ContactCapacity {
  /** Πόσες είναι **ανοιχτές** τώρα. */
  readonly open: number;
  /** Πόσες ακόμη χωράνε. **Ποτέ αρνητικό** — δες {@link contactCapacityOf}. */
  readonly remaining: number;
  /** Το όριο που εφαρμόστηκε, ώστε η οθόνη να **μην το ξαναγράψει** (Κ9). */
  readonly capacity: number;
  /** Γέμισε; Η **μία** ερώτηση που κάνει ο γραφέας πριν δεχτεί νέα πράξη. */
  readonly full: boolean;
}

/** Μετρά μόνο τις ανοιχτές. Η απόσυρση **ελευθερώνει** — αυτό είναι το ΠΕ5/ΠΕ6. */
function isOpen(lifecycle: FirstContactLifecycle): boolean {
  return lifecycle === 'open';
}

/**
 * **Πόσο χώρο έχει αυτός ο άνθρωπος.**
 *
 * @param contacts — **όλες** οι πράξεις του ζητούντος *(ανοιχτές και αποσυρμένες)*.
 *   Ο καλών φιλτράρει κατά `seekerUserId`· εδώ δεν γίνεται δεύτερος έλεγχος
 *   ιδιοκτησίας, γιατί θα ήταν **δεύτερος κριτής** (ADR-749) πάνω σε ερώτημα που
 *   έχει ήδη απαντηθεί από την απομόνωση.
 *
 * 🔴 **Το `Math.max(0, …)` ΔΕΝ είναι διακοσμητικό.** Το όριο μπορεί κάποτε να
 * **κατέβει** *(το ΠΕ5 λέει ρητά ότι ο αριθμός αλλάζει αν το τεστ αποτύχει)*, και τότε
 * υπάρχουν άνθρωποι **πάνω** από αυτό. Ένα αρνητικό «απομένουν» θα τύπωνε *«απομένουν
 * −3»* σε μια οθόνη — δηλαδή θα ζητούσε από τον άνθρωπο να καταλάβει τη μετάβασή μας.
 * Βλέπει `0` και *«γέμισε»*, που είναι **αληθές** και **ενεργήσιμο**.
 *
 * ⚠️ Και γι' αυτόν ακριβώς τον λόγο το `full` κρίνεται με **`>=`** και όχι `===`:
 * ο άνθρωπος με 12 ανοιχτές σε όριο 10 είναι γεμάτος, όχι «εκτός περίπτωσης».
 */
export function contactCapacityOf(
  contacts: readonly FirstContact[],
): ContactCapacity {
  const open = contacts.filter((contact) => isOpen(contact.lifecycle)).length;

  return {
    open,
    remaining: Math.max(0, OPEN_CONTACT_CAPACITY - open),
    capacity: OPEN_CONTACT_CAPACITY,
    full: open >= OPEN_CONTACT_CAPACITY,
  };
}

/**
 * **Χωράει άλλη μία;** — η μία ερώτηση που κάνει ο γραφέας.
 *
 * 🔑 Εξάγεται **ξεχωριστά** ώστε να μην ξαναγραφτεί ως `capacity.remaining > 0` σε δύο
 * σημεία: δύο διατυπώσεις του ίδιου ερωτήματος είναι δύο σημεία που μπορούν να
 * **αποκλίνουν**, και η μία θα αποκλίνει προς την πλευρά που δέχεται την ενδέκατη.
 */
export function canOpenAnotherContact(
  contacts: readonly FirstContact[],
): boolean {
  return !contactCapacityOf(contacts).full;
}
