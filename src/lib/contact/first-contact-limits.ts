/**
 * **Πόσες πράξεις πρώτης επαφής μπορεί να έχει ΑΝΟΙΧΤΕΣ ΤΑΥΤΟΧΡΟΝΑ ένας άνθρωπος.**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΧΩΡΗΤΙΚΟΤΗΤΑ, ΟΧΙ ΠΟΣΟΣΤΩΣΗ — και η διαφορά είναι όλη η απόφαση (ΠΕ5)
 * ────────────────────────────────────────────────────────────────────────────
 *
 * 🔑 *«Η ποσόστωση μετρά την **ΠΡΑΞΗ**· η χωρητικότητα μετρά την **ΠΡΟΣΟΧΗ**.»*
 * Ένα όριο **ανά ημέρα** επιβραβεύει την υπομονή: ο επιπόλαιος φτάνει στα 200, αργά.
 * Η χωρητικότητα **δεν έχει αναμονή που να τη λύσει** — αν θες ενδέκατο, κάτι πρέπει
 * να φύγει.
 *
 * 🏆 **Και το κλείσιμο παράγει ΣΗΜΑ ΑΝΤΙ ΓΙΑ ΣΙΩΠΗ** — κέρδος που δεν ζητήθηκε: χωρίς
 * όριο, ένα ενδιαφέρον που **έσβησε** και ένα που **ζει** είναι αδιάκριτα, και ο
 * ιδιοκτήτης περιμένει. Με τη χωρητικότητα ο ζητών **έχει λόγο να κλείσει** ό,τι δεν
 * τον ενδιαφέρει πλέον, και ο προσφέρων **μαθαίνει ότι τελείωσε**. Η επιβολή του ορίου
 * **παράγει την πληροφορία που λείπει**, αντί να κοστίζει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ Ο ΦΡΟΥΡΟΣ **Κ9** — ΤΟ ΣΟΒΑΡΟΤΕΡΟ ΤΟΥ ADR-843
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Κάθε όριο γεννά αμέσως την ιδέα *«πλήρωσε για περισσότερα»*. Είναι το πιο φυσικό
 * πράγμα στον κόσμο, και **κάθε πλατφόρμα το κάνει** — τα **Upwork Connects** είναι
 * κυριολεκτικά αυτό (10 δωρεάν/μήνα → **100** με συνδρομή).
 *
 * > ⛔ **ΑΠΑΓΟΡΕΥΕΤΑΙ ΑΠΟΛΥΤΩΣ.** Το όριο **ΔΕΝ ΑΓΟΡΑΖΕΤΑΙ** — ούτε με συνδρομή, ούτε
 * > με πακέτο, ούτε «για επαγγελματίες». Η **Α13** λέει ότι ο ζητών πληρώνει **μηδέν**,
 * > απόλυτο· χρέωση για άρση ορίου είναι **χρέωση του ζητούντος με άλλο όνομα** — και
 * > **χειρότερη από την απλή**, γιατί **εμείς θα ελέγχαμε το νούμερο**: όσο πιο σφιχτό
 * > το θέταμε, τόσο περισσότερα θα βγάζαμε. *Ένα όριο που πουλιέται παύει να είναι
 * > προστασία και γίνεται προϊόν.*
 *
 * 🔑 **Ο φρουρός είναι ΔΟΜΙΚΟΣ**: αυτή είναι **σταθερά module**, ίδια για όλους.
 * **Ούτε πεδίο στον χρήστη, ούτε πεδίο στο πακέτο, ούτε πεδίο πουθενά** — και ειδικά
 * **όχι** στο `companies/{id}.capabilities`. *Πεδίο που δεν υπάρχει δεν το πουλάει
 * κανείς* (ΠΕ2 · ΠΕ4 · ΠΕ5 · ADR-827 §9.9).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΤΟ ΝΟΥΜΕΡΟ — ΔΥΟ ΑΝΕΞΑΡΤΗΤΟΙ ΔΕΙΚΤΕΣ, ΟΧΙ ΜΑΝΤΕΨΙΑ (Θ-5)
 * ────────────────────────────────────────────────────────────────────────────
 *
 * | Δείκτης | Τι λέει |
 * |---|---|
 * | **NAR** — ο τυπικός αγοραστής βλέπει **~7 σπίτια** πριν αγοράσει | αφήνει **~40%** περιθώριο πάνω από τον τυπικό |
 * | **Upwork** — **10** στη δωρεάν βαθμίδα | ανεξάρτητη σύγκλιση στο **ίδιο** νούμερο |
 * | Το περιστατικό που γέννησε το όριο: **40 σε ένα απόγευμα** | σταματά **στο πρώτο απόγευμα** |
 *
 * 🔑 **ΤΟ ΚΡΙΤΗΡΙΟ ΔΕΝ ΕΙΝΑΙ Ο ΑΡΙΘΜΟΣ — ΕΙΝΑΙ ΤΟ ΤΕΣΤ**: *«ο σοβαρός άνθρωπος **δεν
 * πρέπει να συναντήσει ΠΟΤΕ** αυτό το μήνυμα»*. Αν αρχίσουν να το βλέπουν κανονικοί
 * αγοραστές, **ο αριθμός ανεβαίνει** — και **η αρχή δεν ξανασυζητιέται**.
 *
 * 🔶 **Δηλωμένη απόκλιση από τον κλάδο**: στα ακίνητα **δεν βρέθηκε κανένα δημοσιευμένο
 * όριο** στον ζητούντα (Rightmove · Zillow). Στέκει επειδή ο **παραλήπτης** τους είναι
 * **γραφείο που ΠΛΗΡΩΣΕ** για ροή, ενώ ο δικός μας είναι **ιδιώτης που δεν πλήρωσε
 * τίποτα**: το γραφείο που πνίγεται στα 17 ερωτήματα/ακίνητο **χάνει λεφτά**· ο ιδιώτης
 * **φεύγει**.
 */
export const OPEN_CONTACT_CAPACITY = 10;

/**
 * **Πόσο πιο μακριά από τον πλησιέστερο μετράει κάποιος ακόμη ως ΙΣΟΠΑΛΟΣ** (ΠΕ7, Θ-6).
 *
 * `0.25` σημαίνει: ισόπαλοι όσοι είναι έως **πλησιέστερος × 1,25**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΣΧΕΤΙΚΟ, ΚΑΙ ΓΙΑΤΙ ΣΤΑΘΕΡΑ ΧΙΛΙΟΜΕΤΡΑ ΕΙΝΑΙ **ΔΟΜΙΚΑ** ΛΑΘΟΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το **ίδιο** απόλυτο κατώφλι δίνει **αντίθετο** αποτέλεσμα σε δύο μέρη της ίδιας χώρας:
 *
 * | Πού | «5 χλμ.» σημαίνει | Αποτέλεσμα |
 * |---|---|---|
 * | **Θεσσαλονίκη** | μισή πόλη | **όλοι** ισόπαλοι ⇒ η απόσταση **έπαψε να μετράει** |
 * | **Χαλκιδική** | ο διπλανός | **κανείς** ισόπαλος ⇒ ο πρώτος **τα παίρνει όλα** |
 *
 * ✅ Το σχετικό **ρυθμίζεται μόνο του**: πλησιέστερος στα 2 χλμ. ⇒ ισόπαλοι ως 2,5 χλμ.
 * *(οι τέσσερις της γειτονιάς)*· πλησιέστερος στα 20 ⇒ ως 25 *(οι γειτονικοί της περιοχής)*.
 *
 * 🏆 **Τρίτη φορά που το έργο διαλέγει ΣΧΕΤΙΚΟ αντί για ΑΠΟΛΥΤΟ** — οι δύο πρώτες είναι
 * γραμμένες: οι **ζώνες ειδοποίησης** (`demand-announcement.ts`, γεωμετρική κλιμάκωση)
 * και η **υποχώρηση τιμής** (`demand-concessions.ts`, σχετική 15%). **Δεν είναι
 * προτίμηση — είναι το ιδίωμα του έργου.**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ Ο ΦΡΟΥΡΟΣ **Κ13**: ΤΙ ΛΥΝΕΙ, ΚΑΙ ΤΙ ΔΕΝ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΛΥΣΕΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Στην πυκνή πόλη και οι έξι είναι «κοντά» *(1,8 · 2,1 · 2,3 χλμ.)*: η σειρά γίνεται
 * **αυθαίρετη ενώ ΜΟΙΑΖΕΙ με αρχή** — χειρότερο από το τυχαίο, γιατί **κανείς δεν το
 * ελέγχει**. Μέσα στη ζώνη, λοιπόν, η σειρά λύνεται **τυχαία αλλά ΣΤΑΘΕΡΑ ανά άνθρωπο**.
 *
 * ⚠️ **Η ζώνη ΔΕΝ είναι δεύτερο κριτήριο κατάταξης** (Κ12). Είναι **άρνηση** να
 * διακρίνουμε εκεί όπου η διάκριση δεν έχει νόημα. Στη σειρά μπαίνει **μόνο** η
 * απόσταση: **καμία** βαθμολογία, **κανένα** «ενεργός πρόσφατα», **καμία** προβολή επί
 * πληρωμή. *Αν η σειρά δεν εξηγείται με **μία φράση**, δεν είναι ουδέτερη.*
 */
export const PROXIMITY_TIE_MARGIN = 0.25;
