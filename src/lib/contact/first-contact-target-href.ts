import { listingDetailHref } from '@/lib/listings/listing-routes';
import type { FirstContactTarget } from '@/types/first-contact';

/**
 * Η δημόσια σελίδα του στόχου — **ή `null` όταν δεν υπάρχει**.
 *
 * 🔴 **ΤΟ `null` ΤΟΥ `professional` ΕΙΝΑΙ ΑΠΑΝΤΗΣΗ, ΟΧΙ ΠΑΡΑΛΕΙΨΗ** *(ADR-844 §7.1)*:
 * ο στόχος κρατά `agencyCompanyId`, ενώ η **βιτρίνα** ζει σε `/pro/<alias>` — και το
 * `alias` **δεν υπάρχει μέσα στον στόχο**. Θα απαιτούσε ανάγνωση `agency_profiles`,
 * δηλαδή ερώτημα στη βάση για να ζωγραφιστεί **ένα κουμπί**.
 *
 * ⛔ **ΜΗΝ το «λύσεις» μαντεύοντας** `/pro/${agencyCompanyId}`: το `companyId` **δεν
 * είναι** alias, και ο σύνδεσμος θα οδηγούσε σε **404** — χειρότερο από την απουσία
 * του, γιατί ο άνθρωπος θα νόμιζε ότι έφταιξε αυτός. Ο καλών δίνει τότε τη **γενική**
 * διέξοδο.
 *
 * 🔑 **Δεν παίρνει `null` στόχο επίτηδες**: *«δεν υπάρχει στόχος»* και *«ο στόχος δεν
 * έχει διεύθυνση»* είναι **δύο** γεγονότα, και μόνο το δεύτερο ανήκει εδώ. Ο καλών
 * που δεν ξέρει στόχο δεν έχει τίποτα να ρωτήσει.
 */
export function firstContactTargetHref(target: FirstContactTarget) {
  return target.kind === 'listing' ? listingDetailHref(target.listingId) : null;
}
