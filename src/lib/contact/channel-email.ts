/**
 * **Πεζά, χωρίς κενά** — η μορφή στην οποία μια διεύθυνση **ταυτίζεται με τον εαυτό της**.
 *
 * ⚠️ **ΔΕΝ επικυρώνει.** Το *«είναι email;»* το απαντά το `isValidEmail`
 * (`lib/validation/email-validation.ts`), και είναι **άλλη** ερώτηση: αυτό εδώ δέχεται
 * ό,τι του δώσεις και το φέρνει σε κανονική μορφή. Ένας κανονικοποιητής που **κρίνει**
 * θα ήταν δεύτερος ορισμός του τι είναι email.
 *
 * ⚠️ **Μόνο πεζά, ΚΑΜΙΑ αφαίρεση τελειών ή `+tag`.** Το `maria.k+spiti@gmail.com` και το
 * `mariak@gmail.com` είναι το **ίδιο κουτί** στη Gmail — αλλά η «εξυπνάδα» αυτή είναι
 * **προμηθευτο-ειδική** και **λάθος** για τους περισσότερους διακομιστές. Θα σήμαινε ότι
 * δύο ανθρώποι με νόμιμα διαφορετικές διευθύνσεις μοιράζονται πρόσκληση.
 */
export function normaliseChannelEmail(raw: string): string {
  return raw.trim().toLowerCase();
}

/**
 * **Είναι η ίδια διεύθυνση;** — η σύγκριση, ποτέ χειρόγραφη.
 *
 * 🔑 Το κενό **δεν ταυτίζεται με τίποτα, ούτε με άλλο κενό**: ένας λογαριασμός χωρίς
 * email *(σύνδεση με τηλέφωνο)* θα «ταίριαζε» με κενή φόρμα, και ο φρουρός θα έλεγε
 * *«αποδεδειγμένο»* για κανάλι που **δεν υπάρχει**.
 */
export function sameChannelEmail(a: string | null | undefined, b: string | null | undefined): boolean {
  const left = normaliseChannelEmail(a ?? '');
  const right = normaliseChannelEmail(b ?? '');
  return left !== '' && left === right;
}

/**
 * **Κρύβει το μεσαίο** — `μ***α@gmail.com`. Ο ΕΝΑΣ τρόπος να **δείξεις** διεύθυνση χωρίς να τη **δώσεις**.
 *
 * 🔑 **Γιατί δείχνεται καν**: ο άνθρωπος αναγνωρίζει **το δικό του** κουτί (πρώτο/τελευταίο γράμμα + domain) και
 * καταλαβαίνει αμέσως αν κάτι πήγε σε λάθος διεύθυνση — ενώ όποιος κρατά ξένο σύνδεσμο δεν μαθαίνει τη διεύθυνση.
 * Καταναλωτές: η επιβεβαίωση πρώτης επαφής (`/api/first-contacts/guest`, εκεί γεννήθηκε 2026-09) και το βήμα
 * λογαριασμού των σελίδων πρόσκλησης (ADR-915 §39 · 2026-11-14) — δεύτερος καταναλωτής ⇒ ζει εδώ.
 */
export function maskEmail(email: string): string {
  const at = email.indexOf('@');
  if (at <= 0) return '***';
  const local = email.slice(0, at);
  const domain = email.slice(at);
  if (local.length <= 2) return `${local.slice(0, 1)}***${domain}`;
  return `${local.slice(0, 1)}***${local.slice(-1)}${domain}`;
}
