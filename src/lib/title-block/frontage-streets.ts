/**
 * @fileoverview Η πρόταση «Οδός Α, Β, Γ & Δ» → τα **ονόματα** των προσώπων του οικοπέδου.
 *
 * ADR-759 §2.2 γρ. 8 / Φ3β. Καθαρή συνάρτηση, καμία γνώση της βάσης — γι' αυτό ζει χωριστά από
 * το `resolve-location`: το ίδιο ερώτημα θα το ξανακάνει ο reader της Φ4 όταν τα προσγειώσει σε
 * `PlotFrontage[]` + διευθύνσεις τύπου `frontage`, και δύο αντίγραφα του τεμαχισμού θα ήταν
 * sibling clone (N.18) πάνω σε λογική που **αλλάζει** (νέοι διαχωριστές).
 *
 * 🔑 **Ο τεμαχισμός ΔΕΝ γράφει τίποτα, και αυτό είναι σκόπιμο.** Η Φ3β παράγει
 * `resolver-gap` — «το πεδίο υπάρχει, λείπει η σύνδεση». Ο λόγος που η σύνδεση δεν γίνεται εδώ
 * δεν είναι έλλειψη χρόνου: το `PlotFrontage` δείχνει σε `ProjectAddress` μέσω `addressId`, και
 * το `ProjectAddress` **απαιτεί** `city` / `postalCode` / `country` που η πινακίδα **δεν δίνει**.
 * Δημιουργώντας τις τέσσερις διευθύνσεις τώρα, θα γεννούσαμε τρία εφευρημένα πεδία η καθεμία —
 * δηλαδή ακριβώς το «ψέμα με σωστή μορφή» του ADR-745 §8.1, τετραπλασιασμένο. Η κληρονομιά
 * πόλης/Τ.Κ. από την κύρια διεύθυνση είναι **απόφαση**, και ανήκει στη φάση που έχει το σώμα
 * του σχεδίου να τη διασταυρώσει.
 *
 * @module lib/title-block/frontage-streets
 */

import { normalizeForLabelMatch } from '@/utils/greek-text';

/**
 * Οι διαχωριστές, ως **χαρακτήρες**.
 *
 * ⚠️ Η παύλα λείπει **επίτηδες**. Στο κελί ΘΕΣΗ η ` - ` χωρίζει *ενότητες* (ΔΗΜΟΣ · ΠΕΡΙΟΧΗ ·
 * Ο.Τ. · ΟΙΚ. · Οδός) — αλλά εδώ έχουμε ήδη **μέσα** στην ενότητα των οδών, όπου η παύλα είναι
 * συνηθισμένη μέσα σε ελληνικά οδωνύμια («Παύλου Μελά - Καραολή»). Κόβοντάς την, ένα όνομα θα
 * γινόταν δύο πρόσωπα και το πλήθος θα έπαυε να συμφωνεί με το `frontagesCount`.
 */
const STREET_SEPARATORS = /[,&+·;]|\/(?!\d)/u;

/**
 * Ο σύνδεσμος «και» ως **λέξη**, ποτέ ως υποσυμβολοσειρά.
 *
 * Χωρίς το όριο λέξης, το «Καισαρείας» θα κοβόταν στη μέση. Το ίδιο μάθημα με το
 * `matchesWordSequenceAt` του Λ1 (`ΧΡΟΝΟΣ ΜΕΛΕΤΗΣ` ≠ `ΜΕΛΕΤΗ`), σε άλλο επίπεδο.
 */
const GREEK_AND_WORD = 'και';

/** Ένα κομμάτι που έμεινε χωρίς γράμματα/ψηφία (σκέτο «&», κενό) δεν είναι όνομα οδού. */
const isNameLike = (text: string): boolean => normalizeForLabelMatch(text).length > 0;

/** Σπάει στα «και» που στέκονται **μόνα τους** ως λέξεις. */
function splitOnGreekAnd(chunk: string): string[] {
  const words = chunk.split(/\s+/u);
  const parts: string[] = [];
  let current: string[] = [];
  for (const word of words) {
    if (normalizeForLabelMatch(word) === GREEK_AND_WORD) {
      parts.push(current.join(' '));
      current = [];
      continue;
    }
    current.push(word);
  }
  parts.push(current.join(' '));
  return parts;
}

/**
 * Τα ονόματα οδών μιας πρότασης «Οδός …», με τη σειρά που γράφτηκαν.
 *
 * Επιστρέφει **κενό πίνακα** όταν δεν μένει τίποτα ονοματίσιμο — ο καλών τότε δεν παράγει
 * γραμμή, αντί να παράγει γραμμή που δείχνει κενό.
 *
 * @example splitFrontageStreets('Προέκταση Σμύρνης, Δημ. Κολοκυθά, Ξενοκράτη & Αναγεννήσεως')
 *   → ['Προέκταση Σμύρνης', 'Δημ. Κολοκυθά', 'Ξενοκράτη', 'Αναγεννήσεως']
 */
export function splitFrontageStreets(text: string): string[] {
  return text
    .split(STREET_SEPARATORS)
    .flatMap(splitOnGreekAnd)
    .map((part) => part.trim())
    .filter(isNameLike);
}
