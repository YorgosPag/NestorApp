/**
 * @fileoverview Ο τεμαχισμός των προσώπων οικοπέδου (ADR-759 Φ3β).
 *
 * Το πλήθος **δεν είναι λεπτομέρεια**: πρέπει να συμφωνεί με το `frontagesCount` του ADR-186,
 * αλλιώς η προσγείωση της Φ4 θα δέσει λάθος οδό σε λάθος πρόσωπο — τιμή εύλογη στη μορφή,
 * λάθος στην ουσία.
 */

/* global describe, it, expect */
import { splitFrontageStreets } from '../frontage-streets';

describe('splitFrontageStreets — το πραγματικό G753', () => {
  it('🔴 δίνει ΑΚΡΙΒΩΣ 4 ονόματα — όσα και τα μετρημένα πρόσωπα (ADR-745 §7)', () => {
    expect(
      splitFrontageStreets('Προέκταση Σμύρνης, Δημ. Κολοκυθά, Ξενοκράτη & Αναγεννήσεως'),
    ).toEqual(['Προέκταση Σμύρνης', 'Δημ. Κολοκυθά', 'Ξενοκράτη', 'Αναγεννήσεως']);
  });

  it('η τελεία μέσα σε συντομογραφία ΔΕΝ κόβει («Δημ. Κολοκυθά» = ένα όνομα)', () => {
    expect(splitFrontageStreets('Δημ. Κολοκυθά')).toEqual(['Δημ. Κολοκυθά']);
  });
});

describe('splitFrontageStreets — διαχωριστές', () => {
  it('κόβει στο «και» ως ΛΕΞΗ', () => {
    expect(splitFrontageStreets('Αναγεννήσεως και Ξενοκράτη')).toEqual([
      'Αναγεννήσεως',
      'Ξενοκράτη',
    ]);
  });

  it('🔴 ΔΕΝ κόβει το «και» μέσα σε λέξη — «Καισαρείας» μένει ακέραιο', () => {
    // Χωρίς όριο λέξης, ένα οδώνυμο γίνεται δύο πρόσωπα και το πλήθος παύει να συμφωνεί.
    expect(splitFrontageStreets('Καισαρείας')).toEqual(['Καισαρείας']);
    expect(splitFrontageStreets('Καισαρείας & Θράκης')).toEqual(['Καισαρείας', 'Θράκης']);
  });

  it('🔴 ΔΕΝ κόβει στην παύλα — τα ελληνικά οδώνυμα τη χρησιμοποιούν', () => {
    // Η ` - ` χωρίζει *ενότητες* στο κελί ΘΕΣΗ, αλλά εδώ είμαστε ήδη ΜΕΣΑ στην ενότητα οδών.
    expect(splitFrontageStreets('Παύλου Μελά - Καραολή')).toEqual(['Παύλου Μελά - Καραολή']);
  });

  it('σκέτο διαχωριστικό δεν γεννά κενό όνομα', () => {
    expect(splitFrontageStreets('Σμύρνης, , & Θράκης')).toEqual(['Σμύρνης', 'Θράκης']);
  });

  it('κενή/άσχετη είσοδος δίνει κενό — ο καλών δεν παράγει γραμμή που δείχνει τίποτα', () => {
    expect(splitFrontageStreets('')).toEqual([]);
    expect(splitFrontageStreets('  &  ')).toEqual([]);
  });

  it('μία μόνο οδός μένει μία — ο τεμαχισμός δεν είναι υποχρεωτικός', () => {
    expect(splitFrontageStreets('Σαμοθράκης')).toEqual(['Σαμοθράκης']);
  });
});
