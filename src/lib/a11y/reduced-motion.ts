/**
 * Έχει ζητήσει ο άνθρωπος **λιγότερη κίνηση**;
 *
 * ⚠️ **`false` στον διακομιστή, επίτηδες.** Δεν υπάρχει `window` για να ρωτηθεί, και η
 * απάντηση χρησιμοποιείται **μόνο** τη στιγμή μιας πράξης του χρήστη — που συμβαίνει
 * εξ ορισμού στον περιηγητή. Καμία απόφαση απόδοσης δεν κρέμεται από αυτό, άρα δεν
 * υπάρχει αναντιστοιχία ενυδάτωσης να αποφευχθεί.
 *
 * ⚠️ **`matchMedia` σε `try`**: το jsdom δεν το υλοποιεί, και μια δοκιμή που πέφτει
 * επειδή ρώτησε για προσβασιμότητα θα δίδασκε το χειρότερο δυνατό μάθημα.
 */
export function prefersReducedMotion(): boolean {
  if (typeof window === 'undefined' || typeof window.matchMedia !== 'function') return false;
  try {
    return window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  } catch {
    return false;
  }
}

/**
 * Η συμπεριφορά κύλισης που **επιτρέπεται** για μια πράξη που θα ήθελε να είναι ομαλή.
 *
 * 🔑 Ένα όνομα αντί για τριαδικό σε κάθε καταναλωτή: η γραφή
 * `prefersReducedMotion() ? 'auto' : 'smooth'` επαναλαμβανόμενη σε 23 αρχεία **είναι**
 * το διπλότυπο, ακόμη κι αν κάθε αντίγραφο είναι σωστό.
 */
export function motionSafeScrollBehavior(): ScrollBehavior {
  return prefersReducedMotion() ? 'auto' : 'smooth';
}
