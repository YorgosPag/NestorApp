/**
 * ADR-739 §70 — **ΠΟΙΟΣ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΠΑΡΕΙ ΤΟ ΠΛΗΚΤΡΟΛΟΓΙΟ ΑΠΟ ΑΝΟΙΧΤΟ ΠΕΔΙΟ.**
 *
 * Framework-free, με τον ίδιο λόγο που είναι και το {@link module:lib/a11y/keyboard-scope}:
 * το εισάγουν και η κορδέλα του `dxf-viewer` και η μπάρα κατάστασης και τα κοινά combobox.
 * Καμία εξάρτηση από React, **και καμία γνώση για πίνακες** — δες «Η ΠΑΓΙΔΑ» παρακάτω.
 *
 * ── ΤΟ ΜΕΤΡΗΜΕΝΟ ΕΛΑΤΤΩΜΑ ΠΟΥ ΚΛΕΙΝΕΙ (αναφορά ιδιοκτήτη, 2026-08-29) ──
 *
 * Ο πίνακας είναι σε συνεδρία κελιού. Ο χρήστης πατά το βελάκι **αναίρεσης** στη μπάρα
 * καρτελών της κορδέλας. Η αναίρεση γίνεται σωστά — **και η συνεδρία πεθαίνει**:
 *
 * ```
 *   mousedown στο κουμπί
 *     → ο browser μεταφέρει την εστίαση στο <button>   ← ΠΡΟΕΠΙΛΕΓΜΕΝΗ ΕΝΕΡΓΕΙΑ
 *     → το πεδίο κάνει blur
 *     → ο φύλακας βλέπει «μη-μέλος» ⇒ closeTableCellCursor()
 *     → ... και ΜΟΝΟ ΜΕΤΑ εκδίδεται το click που κάνει την αναίρεση
 * ```
 *
 * Το `Ctrl+Z` κάνει **την ίδια** εντολή και **δεν** περνά από τίποτα από αυτά. Δύο δρόμοι
 * για μία εντολή, δύο αποτελέσματα: αυτό είναι το συμβόλαιο που έσπασε.
 *
 * 🔴 **Και ήταν ΚΛΑΣΗ, όχι δείγμα.** Μηδέν χειριστήριο της μπάρας καρτελών προστατευόταν
 * (μετρημένο με grep, 2026-08-29: **καμία** αναφορά φρουρού μέσα στο `ui/ribbon/`), ενώ
 * **κανένα** από τα χειριστήριά της δεν σημαίνει «φεύγω από τον πίνακα»: αναίρεση,
 * επανάληψη, σύμπτυξη κορδέλας, εναλλαγή καρτέλας. Είναι **χρώμιο**.
 *
 * ── ⚠️ Η ΠΑΓΙΔΑ: ΓΙΑΤΙ Η ΕΡΩΤΗΣΗ ΕΙΝΑΙ ΚΑΘΟΛΙΚΗ ΚΑΙ ΟΧΙ «ΑΝΗΚΩ ΣΤΗ ΣΥΝΕΔΡΙΑ» ──
 *
 * Η προφανής θεραπεία ήταν να φορέσει η κορδέλα το σημάδι μέλους της συνεδρίας κελιού
 * (`TABLE_CELL_SESSION_MARKER`). **Είναι λάθος, και ο λόγος είναι αρχιτεκτονικός**: η
 * κορδέλα ζει πάνω από ολόκληρη την εφαρμογή και **δεν επιτρέπεται να ξέρει τι είναι
 * πίνακας**. Ένα σημάδι που λέει ψέματα («είμαι μέλος») θα κρατούσε τη συνεδρία ζωντανή σε
 * καταστάσεις που κανείς δεν σκέφτηκε, και θα γεννούσε **δεύτερο** ορισμό του «μέλος».
 *
 * Η σωστή ερώτηση δεν αναφέρει πίνακες καθόλου:
 *
 * > **«Θα κλέψει αυτό το πάτημα το πληκτρολόγιο από κάποιον που γράφει;»**
 *
 * και έχει **ήδη έναν ορισμό** — την Ερώτηση 1 του `keyboard-scope` πάνω στο τρέχον focus
 * ({@link isTextEntryFocused}). Η συνεδρία του πίνακα επιβιώνει ως **συνέπεια**, όχι ως
 * ειδική περίπτωση: το πεδίο του κελιού είναι `contenteditable` και εστιασμένο σε **κάθε**
 * κατάσταση δρομέα (πλοήγηση **και** γραφή) — αυτό ακριβώς είναι που κάνει τους 43 window
 * listeners να παραιτούνται. Άρα το ίδιο κατηγόρημα που τους σταματά, τη σώζει.
 *
 * ── ΓΙΑΤΙ ΤΟ ΠΑΤΗΜΑ ΚΑΙ ΟΧΙ ΤΟ ΚΛΙΚ ──
 *
 * Η μεταφορά της εστίασης είναι η *προεπιλεγμένη ενέργεια* του `mousedown`: μέχρι να
 * εκδοθεί το `click` έχει ήδη συμβεί. Κάθε «διόρθωση μετά» — επανεστίαση μέσα στον χειριστή
 * του `click` — είναι **δομικά αργοπορημένη**, γιατί ο φύλακας της συνεδρίας αποφασίζει σε
 * `requestAnimationFrame` που σε κράτημα >16ms τρέχει **πριν** από το `click`.
 *
 * ── 🔑 ΠΟΥ ΠΑΜΕ ΠΑΝΩ ΑΠΟ ΤΟΥΣ ΜΕΓΑΛΟΥΣ ──
 *
 * ProseMirror, Quill και Slate βάζουν **άνευ όρων** `preventDefault` στο `mousedown` της
 * εργαλειοθήκης τους. Αυτό είναι μετρήσιμα λάθος σε **τρεις** περιπτώσεις, και οι τρεις
 * ζουν εδώ ως ρητοί κλάδοι του {@link pressMayMoveKeyboard}:
 *
 *  1. **δεν γράφει κανείς** ⇒ δεν υπάρχει εστίαση να διατηρηθεί, και η άνευ όρου αποτροπή
 *     αφήνει το κουμπί **μη εστιάσιμο με ποντίκι** — αφαιρεί άγκυρα από χρήστη αναγνώστη
 *     οθόνης χωρίς κανένα αντάλλαγμα (WAI-ARIA APG)·
 *  2. **ο στόχος είναι ο ίδιος πεδίο κειμένου** ⇒ ο χρήστης πάει να γράψει **εκεί**· η
 *     άνευ όρου αποτροπή θα έκανε το πεδίο μη εστιάσιμο και το κείμενό του μη επιλέξιμο·
 *  3. **ο στόχος είναι πηγή εγγενούς σύρσης** (`draggable="true"`) ⇒ το `preventDefault`
 *     στο `mousedown` είναι ο **κατά πρότυπο** τρόπος να ακυρωθεί το drag-and-drop, και οι
 *     browsers διαφωνούν στο πόσο πιστά το εφαρμόζουν. Άνευ όρου αποτροπή = **σιωπηλά
 *     νεκρή** αναδιάταξη καρτελών, σε άλλον browser από αυτόν που δοκίμασες.
 *
 * Και ο τέταρτος, που είναι δικός μας: ο φρουρός **δεν ξαναεστιάζει ποτέ**. Το
 * *capture-and-restore* των μεγάλων (`preventDefault()` … `setTimeout(() => view.focus())`)
 * πληρώνει τρία πράγματα που εδώ δεν υπάρχουν — αγώνα δρόμου με ό,τι άλλο εστιάζει στο ίδιο
 * καρέ, **επιλογή** μέσα στο πεδίο που δεν επιβιώνει ενός `focus()`, και κόμβο που μπορεί
 * να έχει ξεμοντάρει. Η εστίαση **δεν φεύγει ποτέ**, άρα δεν υπάρχει τίποτα να επιστραφεί.
 *
 * ── ⚠️ ΤΙ ΔΕΝ ΕΙΝΑΙ ΑΥΤΟ ──
 *
 * **Δεν** είναι «η κορδέλα δεν κλείνει ποτέ τη συνεδρία». Το «Αρχική → Γραμμή» **οφείλει**
 * να την κλείσει: πατώντας εργαλείο σχεδίασης ο χρήστης **φεύγει** από τον πίνακα, και μια
 * καθολική εξαίρεση θα τον κρατούσε κλειδωμένο. Γι' αυτό το {@link NON_ACTIVATING_SURFACE}
 * μπαίνει **μόνο** σε επιφάνειες-χρώμιο, δηλωτικά, ποτέ στη ρίζα της κορδέλας.
 *
 * @module lib/a11y/non-activating-surface
 * @see src/lib/a11y/keyboard-scope.ts — η Ερώτηση 1 («γράφει ο χρήστης;»), ο ΕΝΑΣ ορισμός
 * @see src/subapps/dxf-viewer/ui/table-cell-editor/table-cell-keyboard-ownership.ts — η
 *   **στενή** εμβέλεια της ίδιας ερώτησης, για επιφάνειες που ξέρουν τι είναι συνεδρία
 * @see docs/centralized-systems/reference/adrs/specs/SPEC-739D-excel-parity.md §70
 */

import { isTextEntryFocused, isTextEntryTarget } from './keyboard-scope';

/**
 * Ό,τι χρειάζεται ο φρουρός από ένα πάτημα — και **τίποτα** παραπάνω.
 *
 * Δομικός τύπος και όχι `React.MouseEvent`: ο ίδιος φρουρός πρέπει να μπορεί να μπει και σε
 * ωμό ακροατή του DOM, και μια δήλωση δεμένη με το React θα γεννούσε **δεύτερη** εκδοχή του
 * για εκείνη τη διαδρομή. Το `target` είναι **προαιρετικό** επίτηδες: όταν λείπει, ο κανόνας
 * απαντά χωρίς τις εξαιρέσεις στόχου — δηλαδή στην αυστηρότερη, όχι στη χαλαρότερη πλευρά.
 */
export interface SurfacePressEvent {
  preventDefault(): void;
  readonly target?: EventTarget | null;
}

/** Το γνώρισμα που κάνει ένα στοιχείο πηγή **εγγενούς** σύρσης του HTML. */
const NATIVE_DRAG_SOURCE_SELECTOR = '[draggable="true"]';

/**
 * Βρίσκεται το πάτημα μέσα σε πηγή εγγενούς σύρσης;
 *
 * `closest()` και όχι έλεγχος του ίδιου του στόχου: το `draggable` μπαίνει στο **δοχείο**
 * (η καρτέλα της κορδέλας), ενώ ο στόχος του `mousedown` είναι το εικονίδιο ή η ετικέτα
 * **μέσα** του. Έλεγχος μόνο του στόχου θα απαντούσε «όχι» ακριβώς στην περίπτωση που
 * υπάρχει, δηλαδή θα ήταν φρουρός που δεν φρουρεί.
 */
function isNativeDragSource(el: Element): boolean {
  return el.closest(NATIVE_DRAG_SOURCE_SELECTOR) !== null;
}

/**
 * 🔴 **Ο ΚΑΝΟΝΑΣ, ως καθαρή συνάρτηση.** Μία ερώτηση, τέσσερις κλάδοι, κανένας σιωπηλός.
 *
 * Ζει χωριστά από τον φρουρό ώστε να ελέγχεται **χωρίς DOM συμβάν**: ένα test που στήνει
 * `MouseEvent` ελέγχει τη συρραφή· αυτό εδώ ελέγχει την **απόφαση**. Δύο ερωτήσεις, δύο
 * άγκυρες — και η δεύτερη είναι που μένει σωστή όταν αλλάξει το framework.
 *
 * @param target ο στόχος του πατήματος (`event.target`), ή `null`/`undefined` αν λείπει
 * @param someoneIsWriting κατέχει **πεδίο κειμένου** το πληκτρολόγιο αυτή τη στιγμή;
 *   Παράμετρος και όχι ανάγνωση του `document`: είναι ακριβώς η **εμβέλεια** που ο καλών
 *   δηλώνει — καθολική εδώ, στενή στον `table-cell-keyboard-ownership`. Ίδιος κανόνας, δύο
 *   εμβέλειες, ένας ορισμός· το ίδιο σχήμα με το `isTableCellSessionElement` vs
 *   `isInsideTableCellSession`.
 * @returns `true` = **άσε** τον browser να μετακινήσει το πληκτρολόγιο (καμία επέμβαση)
 */
export function pressMayMoveKeyboard(
  target: EventTarget | null | undefined,
  someoneIsWriting: boolean,
): boolean {
  // (1) Δεν γράφει κανείς ⇒ δεν υπάρχει τι να διατηρηθεί, και το χειριστήριο **οφείλει** να
  //     εστιαστεί κανονικά. Είναι ο κλάδος που κρατά ακέραιη την προσβασιμότητα ~700
  //     κουμπιών για χάρη μιας συνεδρίας που τις περισσότερες φορές δεν υπάρχει.
  if (!someoneIsWriting) return true;
  if (!(target instanceof Element)) return false;
  // (2) Ο στόχος είναι ο ίδιος πεδίο κειμένου ⇒ ο χρήστης πάει να γράψει **εκεί**. Χωρίς
  //     αυτόν τον κλάδο, ένα πεδίο μέσα σε δηλωμένη επιφάνεια θα γινόταν μη εστιάσιμο και
  //     το κείμενό του μη επιλέξιμο με το ποντίκι.
  if (isTextEntryTarget(target)) return true;
  // (3) Πηγή εγγενούς σύρσης ⇒ το `preventDefault` του `mousedown` είναι ο κατά πρότυπο
  //     τρόπος ακύρωσης του drag-and-drop. Δες την ανάλυση στην κεφαλίδα.
  if (isNativeDragSource(target)) return true;
  // (4) Καθετί άλλο μέσα σε δηλωμένη επιφάνεια-χρώμιο: **δεν παίρνει** το πληκτρολόγιο.
  return false;
}

/**
 * Ο φρουρός, με τον καλούντα να δηλώνει την **εμβέλεια** της ερώτησης.
 *
 * ⚠️ **Δεν** κάνει `stopPropagation`: το πάτημα οφείλει να φτάσει σε όποιον παρακολουθεί τη
 * **χειρονομία** (λήξεις δηλώσεων, φύλακες «κλικ έξω»). Ο φρουρός αφαιρεί **μία**
 * προεπιλεγμένη ενέργεια — δεν καταπίνει το συμβάν.
 */
export function keepKeyboardOnSurface(
  event: SurfacePressEvent,
  someoneIsWriting: boolean,
): void {
  if (pressMayMoveKeyboard(event.target, someoneIsWriting)) return;
  event.preventDefault();
}

/**
 * 🔴 Ο φρουρός στην **καθολική** του εμβέλεια: «γράφει *κάποιος*;», χωρίς καμία γνώση για
 * το ποιος.
 *
 * Αυτός είναι ο φρουρός των επιφανειών που **δεν επιτρέπεται** να ξέρουν τι είναι πίνακας —
 * η κορδέλα, η μπάρα κατάστασης, τα combobox.
 */
export function keepKeyboardOnNonActivatingSurface(event: SurfacePressEvent): void {
  keepKeyboardOnSurface(event, isTextEntryFocused());
}

/**
 * 🔴 **Η ΔΗΛΩΣΗ: «αυτή η επιφάνεια είναι ΜΗ-ΕΝΕΡΓΟΠΟΙΗΤΙΚΗ.»**
 *
 * ## Γιατί ΕΝΑΣ ανά επιφάνεια και ΠΟΤΕ ένας ανά κουμπί
 * Το `mousedown` αναδύεται, και η μεταφορά εστίασης ακυρώνεται από `preventDefault` σε
 * **οποιαδήποτε** φάση της αποστολής. Άρα μία δήλωση στο δοχείο καλύπτει κάθε **σημερινό
 * και μελλοντικό** χειριστήριο μέσα του. Ένας ανά κουμπί είναι ακριβώς το σχήμα που γέννησε
 * αυτό το ελάττωμα: τρία ταυτόσημα `preventBlur` one-liners σε τρία αρχεία, **κάτω από το
 * όριο των 50 tokens του jscpd** — δηλαδή αόρατα σε κάθε εργαλείο, ελεύθερα να αποκλίνουν.
 *
 * ## 🔴 Γιατί **σύλληψη** (`onMouseDownCapture`) και όχι ανάδυση
 * Στην ανάδυση, οποιοσδήποτε εσωτερικός χειριστής καλέσει `stopPropagation()` — και τα
 * Radix primitives το κάνουν συχνά — **σβήνει σιωπηλά** τον φρουρό: το κουμπί θα φαινόταν
 * καλυμμένο και δεν θα ήταν. Στη σύλληψη ο φρουρός τρέχει **πριν** από κάθε απόγονο, άρα
 * η κάλυψη είναι ιδιότητα της **δήλωσης**, όχι της συμπεριφοράς των παιδιών.
 *
 * ## ⚠️ ΠΟΥ **ΔΕΝ** ΜΠΑΙΝΕΙ
 *  - **Στη ρίζα της κορδέλας.** Τα panels εντολών περιέχουν χειριστήρια που σημαίνουν
 *    «φεύγω από τον πίνακα» (εργαλεία σχεδίασης) — εκεί το κλείσιμο της συνεδρίας είναι η
 *    **προδιαγραφή**, όχι το ελάττωμα.
 *  - **Πάνω σε πεδία.** Ένα πεδίο καλύπτεται από τον κλάδο (2) του κανόνα ούτως ή άλλως·
 *    μια δήλωση εκεί απλώς θα έκρυβε την πρόθεση.
 */
export const NON_ACTIVATING_SURFACE = {
  onMouseDownCapture: keepKeyboardOnNonActivatingSurface,
} as const;
