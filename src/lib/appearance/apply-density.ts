/**
 * Διάβασε την αποθηκευμένη προτίμηση και φόρεσέ τη στο `<html>`.
 *
 * @param storageKey κλειδί στο `localStorage`
 * @param attribute  το attribute του `<html>` (π.χ. `data-density`)
 * @param roles      οι **έγκυροι** ρόλοι — ό,τι δεν είναι εδώ αγνοείται
 * @param fallback   ο ρόλος για όποιον δεν διάλεξε ποτέ
 * @returns ο ρόλος που όντως εφαρμόστηκε
 */
export function applyDensity(
  storageKey: string,
  attribute: string,
  roles: readonly string[],
  fallback: string,
): string {
  let value = fallback;
  try {
    const stored = window.localStorage.getItem(storageKey);
    // ⚠️ Η επικύρωση ΔΕΝ είναι πολυτέλεια: το `localStorage` είναι εγγράψιμο από
    // τον χρήστη και επιβιώνει αναβαθμίσεων. Ένας ρόλος που καταργήθηκε θα
    // έγραφε attribute που ΚΑΝΕΝΑΣ κανόνας CSS δεν ταιριάζει ⇒ ο διάδρομος θα
    // έπεφτε σιωπηλά στο fallback ενώ η οθόνη προτιμήσεων θα έδειχνε κενό.
    if (stored !== null && roles.indexOf(stored) !== -1) {
      value = stored;
    }
  } catch (e) {
    // Ιδιωτική περιήγηση / αποκλεισμένα cookies. Η προεπιλογή είναι σωστή
    // απάντηση· η σιωπή εδώ είναι ΣΚΟΠΙΜΗ (τρέχουμε πριν από κάθε logger).
  }
  document.documentElement.setAttribute(attribute, value);
  return value;
}
