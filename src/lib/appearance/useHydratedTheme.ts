'use client';

/**
 * =============================================================================
 * Η ΑΣΦΑΛΗΣ ΑΝΑΓΝΩΣΗ ΤΟΥ ΘΕΜΑΤΟΣ — **ΕΝΑΣ** ιδιοκτήτης, όχι τρία `mounted`
 * =============================================================================
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΠΡΟΒΛΗΜΑ ΕΙΝΑΙ ΠΡΑΓΜΑΤΙΚΟ — ΚΑΙ Η ΠΑΛΙΑ ΛΥΣΗ ΤΟ ΕΚΑΝΕ ΧΕΙΡΟΤΕΡΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `next-themes` αρχικοποιεί την κατάστασή του με `useState(() => getTheme(...))`,
 * και το `getTheme` διαβάζει `localStorage`. Στον **διακομιστή** δεν υπάρχει
 * `localStorage` ⇒ επιστρέφει την προεπιλογή· στον **πελάτη** επιστρέφει την
 * αποθηκευμένη τιμή. Άρα κάθε component που αποδίδει **με βάση το θέμα** παράγει
 * διαφορετικό HTML στις δύο πλευρές. Πραγματική ασυμφωνία ενυδάτωσης.
 *
 * Η προηγούμενη θεραπεία ήταν να τυλιχτεί **ΟΛΟΚΛΗΡΗ Η ΕΦΑΡΜΟΓΗ** σε
 * `<div className="invisible">` μέχρι το πρώτο `useEffect`. Μετρημένο ζωντανά
 * (ADR-815): **459-1655 ms** ολικής αορατότητας, και — χειρότερα — ο
 * `NextThemesProvider` **δεν αποδιδόταν καθόλου στον διακομιστή**, οπότε το
 * **inline script του δεν ταξίδευε ποτέ**. Δηλαδή η πύλη `mounted` **προκαλούσε**
 * το flash που μετά έκρυβε, και ακύρωνε τον λόγο ύπαρξης της βιβλιοθήκης.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 Η ΘΕΡΑΠΕΙΑ ΕΙΝΑΙ ΑΥΤΗ ΠΟΥ ΓΡΑΦΕΙ ΤΟ ΙΔΙΟ ΤΟ README ΤΟΥ ΠΑΚΕΤΟΥ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * *«You should delay rendering any theme toggling **UI** until mounted on the
 * client»* — για το **component που δείχνει** το θέμα, **ΠΟΤΕ** για τον provider.
 * Το `PreferencesPageContent` είχε μάλιστα **ακριβώς** το δείγμα που το README
 * σημειώνει «**Do NOT use this!**» (`<Select value={theme}>`), και δεν έσκαγε
 * **μόνο** επειδή η πύλη έκρυβε τα πάντα: δύο ελαττώματα που κρατούσαν το ένα
 * το άλλο όρθιο.
 *
 * ⚠️ **ΓΙΑΤΙ HOOK ΚΑΙ ΟΧΙ `mounted` ΣΕ ΚΑΘΕ ΚΑΤΑΝΑΛΩΤΗ**: οι καταναλωτές είναι
 * **τρεις** σήμερα. Γραμμένο τρεις φορές, ο τέταρτος θα ξεχνούσε — ακριβώς το
 * σχήμα που το `useLanguagePreference` (ADR-777 §8.29) υπάρχει για να μην
 * ξανασυμβεί. Εδώ η ασφάλεια είναι **η προεπιλογή**: όποιος καλέσει αυτό το
 * hook παίρνει `undefined` πριν την ενυδάτωση **χωρίς να το ξέρει**.
 *
 * ⚠️ **ΜΗΝ** το χρησιμοποιήσεις για να **κρύψεις** περιεχόμενο. Επιστρέφει
 * `undefined`, όχι «περίμενε»: ο καταναλωτής αποδίδει την **ουδέτερη** μορφή
 * (placeholder, φωτεινό) και τη διορθώνει. Το κρύψιμο είναι ό,τι μόλις έφυγε.
 *
 * @module lib/appearance/useHydratedTheme
 * @see ADR-815
 */

import { useTheme } from 'next-themes';
import { useEffect, useState } from 'react';

export interface HydratedTheme {
  /** Η επιλογή του χρήστη (`light` · `dark` · `system`) — `undefined` πριν την ενυδάτωση. */
  readonly theme: string | undefined;
  /** Το θέμα που **όντως βάφει** (το `system` έχει ήδη λυθεί) — `undefined` πριν την ενυδάτωση. */
  readonly resolvedTheme: string | undefined;
  /** Άλλαξε θέμα. Ασφαλές πάντα — δεν αποδίδει τίποτα. */
  readonly setTheme: (theme: string) => void;
  /** Έχει γίνει η ενυδάτωση; Για καταναλωτές που θέλουν ρητό κλάδο. */
  readonly hydrated: boolean;
}

export function useHydratedTheme(): HydratedTheme {
  const { theme, resolvedTheme, setTheme } = useTheme();
  const [hydrated, setHydrated] = useState(false);

  useEffect(() => {
    setHydrated(true);
  }, []);

  return {
    // Ο διακομιστής και το **πρώτο** render του πελάτη δίνουν και τα δύο
    // `undefined` ⇒ ταυτόσημο HTML ⇒ καμία ασυμφωνία. Μετά διορθώνεται.
    theme: hydrated ? theme : undefined,
    resolvedTheme: hydrated ? resolvedTheme : undefined,
    setTheme,
    hydrated,
  };
}
