/**
 * @fileoverview **Ο ΧΩΡΟΣ ΩΣ ΑΤΟΜΟ** — και οι **δύο** σχέσεις πάνω του, που δεν είναι μία.
 * @related ADR-838 §4.1 · ADR-835 §4.12 · lib/occupancy/occupancy-resource.ts ·
 *   types/stay-booking.ts
 * @module lib/spaces/space-ref
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΓΕΝΝΙΕΤΑΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΤΟ `occupancy-resource.ts` Ή ΣΤΟ `stay-booking.ts`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ζεύγος `(propertyId, spaceId)` ήταν **δηλωμένο δύο φορές** — μετρημένο:
 *
 * | Πού | Πώς | Τι ήξερε |
 * |---|---|---|
 * | `OccupancyResource` (ADR-832/835 Φ2) | `+ kind: OfferKind` | τη **σύγκρουση** |
 * | `StaySpaceRef` (ADR-835 §4.12) | σκέτο | τίποτα — μόνο σχήμα |
 *
 * Και ο **κανόνας του μπαλαντέρ** (`spaceId: null` = ΟΛΟΚΛΗΡΟ) ζούσε **μόνο** μέσα
 * στο `resourcesIntersect`, δεμένος με το `kind`. Η νομιμότητα (ADR-838) ρωτά τον
 * **ίδιο ακριβώς** κανόνα χωρίς να έχει `kind`: *«καλύπτει η βεβαίωση του ακινήτου το
 * δωμάτιο Α;»*. Οι τρεις δρόμοι ήταν:
 *
 * 1. **Αντιγραφή του κανόνα** στη νομιμότητα ⇒ **ADR-749** («τέσσερις μηχανές, πέντε
 *    διάλεκτοι»), με τη διαφορά ότι εδώ η απόκλιση λέγεται *«νόμιμο»*.
 * 2. **Εισαγωγή από το `occupancy`** ⇒ «η νομιμότητα ενός κτιρίου **προς ΠΩΛΗΣΗ**
 *    εκφράζεται στο λεξιλόγιο των κρατήσεων». Λάθος σπίτι, ίδιο επιχείρημα με το
 *    γιατί η Α17 δεν γράφεται μέσα στο ADR-835.
 * 3. ✅ **Εξαγωγή** του ατόμου εδώ, και οι δύο υπάρχοντες το **ζητούν**.
 *
 * ⚠️ **ΕΞΑΓΩΓΗ, ΟΧΙ ΠΕΡΙΚΟΠΗ**: κανένας υπάρχων καταναλωτής δεν αλλάζει συμπεριφορά —
 * το `resourcesIntersect` **αναθέτει** εδώ, δεν ξαναγράφεται.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΤΟ ΕΥΡΗΜΑ ΤΟΥ ΑΡΧΕΙΟΥ: **Η ΤΟΜΗ ΚΑΙ Η ΚΑΛΥΨΗ ΕΙΝΑΙ ΔΥΟ ΣΧΕΣΕΙΣ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο κριτής κατάληψης ρωτά **συμμετρικά**: *«πατάνε το ίδιο χώμα;»* — και η απάντηση
 * είναι η ίδια όποιον ρωτήσεις πρώτο. Η νομιμότητα ρωτά **ασύμμετρα**: *«αυτό το
 * χαρτί, καλύπτει **εκείνο** τον χώρο;»* — και η σειρά είναι **τα πάντα**:
 *
 * | Ερώτηση | {@link spacesIntersect} | {@link spaceCovers} |
 * |---|---|---|
 * | ολόκληρο ↔ δωμ. Α | `true` (σωστό: διπλοκράτηση) | `covers(ολόκληρο, δωμ.Α) = true` |
 * | δωμ. Α → ολόκληρο | `true` (σωστό: **ίδια** σύγκρουση) | 🔴 **`false`** |
 *
 * 🔴 **Αν η νομιμότητα χρησιμοποιούσε την τομή, ο ΑΜΑ ΕΝΟΣ ΔΩΜΑΤΙΟΥ θα «νομιμοποιούσε»
 * ΟΛΟΚΛΗΡΟ ΤΟ ΔΙΑΜΕΡΙΣΜΑ** — δηλαδή ακριβώς το λάθος που η ΑΑΔΕ κλείνει απαιτώντας
 * *«ξεχωριστό ΑΜΑ για το σύνολο **και** για κάθε διακριτό χώρο»*. Μία συνάρτηση για
 * τα δύο ερωτήματα θα ήταν πράσινη και **ψευδής**.
 *
 * **Layering**: leaf — καθαροί τύποι + καθαρές συναρτήσεις, μηδέν I/O, μηδέν ρολόι.
 */

// =============================================================================
// 1. ΤΟ ΑΤΟΜΟ
// =============================================================================

/**
 * **Ένας χώρος, με το σύνορό του.**
 *
 * ⚠️ **Το `propertyId` ΔΕΝ είναι διακοσμητικό**: το `spaceId: null` σημαίνει *«κάθε
 * χώρος»*, και ένα μπαλαντέρ **χωρίς σύνορο** θα έκανε δύο **διαφορετικά** ακίνητα να
 * τέμνονται. Ο περιέκτης είναι μέρος της ταυτότητας, όχι συμφραζόμενο.
 */
export interface SpaceRef {
  /** Το ακίνητο. **Ο περιέκτης**, ποτέ το άτομο. */
  readonly propertyId: string;
  /**
   * Ο χώρος μέσα του. **`null` = ΟΛΟΚΛΗΡΟ το ακίνητο** — καλύπτει **κάθε** χώρο του.
   *
   * 🔑 Το «ολόκληρο» **δεν είναι ξεχωριστή τιμή δίπλα στα δωμάτια**: είναι το **πλήρες
   * σύνολο**, εκφρασμένο ως μπαλαντέρ ώστε ο κριτής να μη χρειάζεται να **ξέρει**
   * ποιοι είναι οι χώροι (θα ήταν ανάγνωση — δεν είναι leaf).
   */
  readonly spaceId: string | null;
}

/**
 * **Ολόκληρο το ακίνητο** — η συνήθης περίπτωση, γραμμένη **μία** φορά.
 *
 * Υπάρχει ώστε κανείς να μη γράψει `{ propertyId, spaceId: null }` στο χέρι: κάθε
 * τέτοιο σημείο είναι σημείο όπου κάποιος μπορεί να ξεχάσει το `null` και να πει
 * «κανένας χώρος» εννοώντας «όλοι».
 */
export function wholePropertySpace(propertyId: string): SpaceRef {
  return { propertyId, spaceId: null };
}

/**
 * **Ταυτότητα ως κείμενο** — μόνο για **αποδιπλασιασμό**.
 *
 * ⛔ **ΠΟΤΕ ως κριτήριο σχέσης.** Δύο χώροι με **διαφορετικό** κλειδί μπορεί κάλλιστα
 * να τέμνονται (`ολόκληρο` vs `δωμάτιο Α`) — η σχέση **δεν είναι ισοδυναμία**.
 */
export function spaceRefKey(space: SpaceRef): string {
  // `|` ως διαχωριστής: δεν εμφανίζεται σε enterprise id, άρα δύο διαφορετικά ζεύγη
  // δεν μπορούν να παραγάγουν το ίδιο κλειδί.
  return `${space.propertyId}|${space.spaceId ?? '*'}`;
}

// =============================================================================
// 2. Η ΣΥΜΜΕΤΡΙΚΗ ΣΧΕΣΗ — «πατάνε το ίδιο χώμα;»
// =============================================================================

/**
 * **Τέμνονται;** — συμμετρικό: `intersect(a,b) === intersect(b,a)`, **πάντα**.
 *
 * Ο καταναλωτής είναι ο **κριτής κατάληψης**: μια κράτηση ολόκληρου κλείνει τα
 * δωμάτια, και μια κράτηση δωματίου κλείνει το ολόκληρο — **η ίδια** σύγκρουση,
 * ιδωμένη από τις δύο πλευρές.
 */
export function spacesIntersect(a: SpaceRef, b: SpaceRef): boolean {
  if (a.propertyId !== b.propertyId) return false;
  return a.spaceId === null || b.spaceId === null || a.spaceId === b.spaceId;
}

/**
 * **Τέμνεται κάποιος με κάποιον;** — η ίδια ερώτηση σε δύο **σύνολα**.
 *
 * ⚠️ **Κενό σύνολο ⇒ `false`**, και είναι ο **ίδιος** κανόνας με το κενό διάστημα του
 * ADR-835 §17: *«τίποτα δεν τέμνει τίποτα»*. Ένα `true` εδώ («τίποτα δεν αποκλείει,
 * άρα όλα») θα ήταν η σιωπή που μεταμφιέζεται σε απάντηση.
 */
export function spaceSetsIntersect(
  a: readonly SpaceRef[],
  b: readonly SpaceRef[],
): boolean {
  return a.some((left) => b.some((right) => spacesIntersect(left, right)));
}

// =============================================================================
// 3. Η ΑΣΥΜΜΕΤΡΗ ΣΧΕΣΗ — «καλύπτει;»
// =============================================================================

/**
 * **Καλύπτει ο `outer` τον `inner`;** — 🔴 **ΑΣΥΜΜΕΤΡΟ. Η σειρά είναι τα πάντα.**
 *
 * *«Η βεβαίωση για ΟΛΟΚΛΗΡΟ το ακίνητο καλύπτει το δωμάτιο Α»* ✅
 * *«Ο ΑΜΑ του δωματίου Α καλύπτει ολόκληρο το ακίνητο»* ⛔ — δες την κεφαλίδα.
 */
export function spaceCovers(outer: SpaceRef, inner: SpaceRef): boolean {
  if (outer.propertyId !== inner.propertyId) return false;
  return outer.spaceId === null || outer.spaceId === inner.spaceId;
}

/**
 * **Καλύπτει το σύνολο `outer` ΚΑΘΕ χώρο του `inner`;**
 *
 * 🔴 **`every`, όχι `some` — και η διαφορά είναι η ίδια η υπόσχεση.** Ένα `some` θα
 * απαντούσε *«ναι, νόμιμο»* για ένα διαμέρισμα όπου **ένα** από τα τρία δωμάτια έχει
 * ΑΜΑ. Η αξίωση καλύπτει ό,τι καλύπτει· **δεν** επεκτείνεται με πλειοψηφία.
 *
 * ⚠️ **Κενό `inner` ⇒ `true`** (κενή σύζευξη, ο κανόνας των μαθηματικών) — αλλά
 * **κανένας καταναλωτής δεν επιτρέπεται να ρωτήσει με κενό `inner`**: «καλύπτεται το
 * τίποτα;» δεν είναι ερώτηση νομιμότητας. Ο φρουρός ζει στον καλούντα
 * ({@link legalitySignalFor}), όπου το κενό έχει **όνομα**, όχι εδώ, όπου θα ήταν
 * ψευδής άλγεβρα. Ίδια διάκριση με το ADR-835 §17: **άλγεβρα** ≠ **λεξιλόγιο**.
 */
export function spaceSetCovers(
  outer: readonly SpaceRef[],
  inner: readonly SpaceRef[],
): boolean {
  return inner.every((target) => outer.some((source) => spaceCovers(source, target)));
}
