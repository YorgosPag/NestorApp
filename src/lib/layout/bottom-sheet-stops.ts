/**
 * @fileoverview **Οι τρεις στάσεις του φύλλου πυθμένα** — ονόματα και σειρά, **ποτέ αριθμοί**.
 * @related ADR-777 §7 (Α3 · Α8) · SPEC-777D §26.3 κανόνας 1 · §26.7
 * @module lib/layout/bottom-sheet-stops
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ ΕΔΩ ΔΕΝ ΥΠΑΡΧΕΙ ΟΥΤΕ ΕΝΑ ΠΟΣΟΣΤΟ — ΕΙΝΑΙ ΑΠΟΦΑΣΗ, ΟΧΙ ΠΑΡΑΛΕΙΨΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το **πόσο ψηλά** κάθεται κάθε στάση είναι **γεωμετρία**, και η γεωμετρία ζει στο
 * `bottom-sheet.module.css` ως **τρεις** custom properties (`--sheet-peek`/`-half`/`-full`).
 * Κάθε άλλη τιμή —το διάκενο, το ύψος του φύλλου, η θέση κάθε άγκυρας— **παράγεται από
 * αυτές με `calc()`**, δηλαδή τη λύνει ο περιηγητής.
 *
 * Αν οι ίδιοι αριθμοί ζούσαν **και** εδώ, θα ήταν **δύο απαντήσεις σε ένα ερώτημα**
 * (ADR-749): μια αλλαγή στο CSS θα άφηνε τον ελεγκτή να στέλνει το φύλλο σε θέση που
 * **δεν είναι στάση**, και η `scroll-snap` θα το ξανατραβούσε πίσω — δηλαδή αναπήδηση,
 * με **και τα δύο αρχεία να φαίνονται σωστά**.
 *
 * 🏆 **Ο ελεγκτής ρωτά τον ΔΙΣΚΟ, όχι έναν πίνακα**: κάθε στάση έχει μια άγκυρα 1px στο
 * DOM, και η θέση της είναι το `offsetTop` της. Είναι η **ίδια** κίνηση με το CHECK 3.42
 * (ρωτά το Tailwind τι χρώμα είναι μια κλάση, αντί να κρατά χάρτη κλάσης→hex): η αυθεντία
 * απαντά **και** «πού είναι» **και** «είναι στάση;», και ένα μελλοντικό `calc()` το μαθαίνει
 * **δωρεάν**.
 */

/**
 * **Σειρά: από τον περισσότερο χάρτη προς τη λιγότερη λίστα.**
 *
 * ⚠️ Η σειρά **είναι** ο μηχανισμός — το `stepStop` δεν την επινοεί, τη διαβάζει. Και είναι
 * η ίδια σειρά με το DOM: οι άγκυρες παρατάσσονται με αύξον `offsetTop`, άρα «επόμενη
 * στάση» σημαίνει **και** «πιο κάτω στο κύλισμα» **και** «περισσότερη λίστα». Μια
 * αναδιάταξη εδώ χωρίς αναδιάταξη εκεί θα έκανε το κουμπί «Μεγαλύτερη λίστα» να μικραίνει
 * τη λίστα, με τον μεταγλωττιστή **σιωπηλό**.
 */
export const BOTTOM_SHEET_STOPS = ['peek', 'half', 'full'] as const;

export type BottomSheetStop = (typeof BOTTOM_SHEET_STOPS)[number];

/**
 * Η στάση ηρεμίας. **Είναι το `scrollTop = 0` του δοχείου** — όχι επιλογή που επιβάλλει
 * κώδικας: το διάκενο πάνω από το φύλλο έχει ύψος `100% - --sheet-peek`, οπότε ο
 * περιηγητής ξεκινά **ήδη** στη ματιά. Καμία αρχική κύλιση, κανένα «πρώτο καρέ» που
 * διορθώνεται μετά (Α19: `CLS < 0,1`).
 */
export const BOTTOM_SHEET_RESTING_STOP: BottomSheetStop = 'peek';

/**
 * **Η ελάχιστη στάση ΔΕΝ είναι «κλειστό».** Το φύλλο δεν εξαφανίζεται ποτέ, γιατί η λίστα
 * κουβαλά τη **λογιστική** (ADR-777 Α5, κανόνας 27): οι «χωρίς σχήμα» αγγελίες ζουν μέσα
 * της, και μια επιφάνεια που κλείνει θα τις έκρυβε **σιωπηλά** — ακριβώς ο ισχυρισμός που
 * η Α5 §4.1 απαγορεύει. Άρα «κλείσιμο» (NN/g κανόνας 3 · πίσω κουμπί, κανόνας 4) σημαίνει
 * **επιστροφή στη ματιά**, και αυτό είναι το πλήρες νόημα του ρήματος εδώ.
 */
export const BOTTOM_SHEET_DISMISS_STOP: BottomSheetStop = BOTTOM_SHEET_RESTING_STOP;

/** Προς τα πού κινείται ο άνθρωπος: `1` = περισσότερη λίστα, `-1` = περισσότερος χάρτης. */
export type BottomSheetStep = 1 | -1;

/**
 * Η επόμενη στάση προς την κατεύθυνση — **`null` στα άκρα**, ποτέ κυκλικά.
 *
 * ⚠️ Το `null` **δεν** είναι αποτυχία: είναι η απάντηση που απενεργοποιεί το κουμπί. Ένα
 * κυκλικό βήμα θα έστελνε τον άνθρωπο από «πλήρες» σε «ματιά» με το κουμπί που λέει
 * *«Μεγαλύτερη λίστα»* — υπόσχεση που η ίδια της η ετικέτα αθετεί.
 */
export function stepStop(from: BottomSheetStop, step: BottomSheetStep): BottomSheetStop | null {
  const next = BOTTOM_SHEET_STOPS.indexOf(from) + step;
  return BOTTOM_SHEET_STOPS[next] ?? null;
}

/** Το γνώρισμα DOM που φέρει κάθε άγκυρα — **η ίδια συμβολοσειρά** που διαβάζει ο ελεγκτής. */
export const BOTTOM_SHEET_STOP_ATTRIBUTE = 'data-sheet-stop';

/** Ο επιλογέας μιας συγκεκριμένης άγκυρας μέσα στο δοχείο κύλισης. */
export function stopAnchorSelector(stop: BottomSheetStop): string {
  return `[${BOTTOM_SHEET_STOP_ATTRIBUTE}="${stop}"]`;
}
