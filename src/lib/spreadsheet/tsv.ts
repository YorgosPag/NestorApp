/**
 * **SSoT: το πρόχειρο των φύλλων υπολογισμού** — `text/plain` σε μορφή TSV, προς και από
 * ορθογώνιο πλέγμα κειμένου.
 *
 * ## Γιατί TSV και όχι κάτι δικό μας (ερευνήθηκε 2026-08-01, ADR-739 §26)
 * Όταν αντιγράφεις κελιά στο **Excel**, το λειτουργικό πρόχειρο γεμίζει με **δύο** μορφές
 * ταυτόχρονα: `text/html` (ολόκληρος ο πίνακας με μορφοποίηση) και `text/plain` (**TSV**).
 * Τα **Google Sheets**, το **LibreOffice Calc** και το **Numbers** κάνουν το ίδιο, και όλα
 * διαβάζουν TSV κατά την επικόλληση. Άρα το TSV **είναι** το lingua franca του πρόχειρου
 * φύλλου υπολογισμού: διαλέγοντάς το, η αντιγραφή από τον ΝΕΣΤΩΡ επικολλάται στο Excel και
 * αντίστροφα, χωρίς κανέναν μετατροπέα.
 *
 * ## 🔴 Γιατί ΔΕΝ γίνεται με `split('\t')` — το quoting είναι υποχρεωτικό
 * Ο πειρασμός είναι δύο γραμμές: `text.split('\n').map(l => l.split('\t'))`. Είναι **λάθος**,
 * και το Excel το αποδεικνύει μόνο του: ένα κελί που περιέχει **στηλοθέτη ή αλλαγή γραμμής**
 * γράφεται από το Excel σε **εισαγωγικά**, με τα εσωτερικά εισαγωγικά διπλασιασμένα — η
 * σύμβαση του RFC 4180, με στηλοθέτη αντί για κόμμα. Με αφελές `split`, **μία** τέτοια
 * κυψέλη μετατοπίζει όλες τις υπόλοιπες στήλες της γραμμής και σπάει **ολόκληρο** το πλέγμα.
 * Το ίδιο σφάλμα ζει ήδη δύο φορές στο repo — δες παρακάτω.
 *
 * ## Τι ΔΕΝ ενοποιείται εδώ (και γιατί δεν είναι παράλειψη)
 * Υπάρχουν **δύο** υφιστάμενοι διαχωριστές CSV: `DataImportService.parseCSVLine` και
 * `csv-import-service.splitCSVLine`. Είναι structural clones μεταξύ τους, **αλλά απαντούν
 * άλλη ερώτηση**: δουλεύουν **ανά γραμμή** (`lines[i]`), άρα είναι δομικά ανίκανοι να
 * εκφράσουν κελί με **ενσωματωμένη αλλαγή γραμμής** — που είναι ακριβώς η περίπτωση που
 * κάνει το quoting απαραίτητο. Αυτό εδώ σαρώνει **ολόκληρο το έγγραφο** ως ένα ρεύμα
 * χαρακτήρων και γι' αυτό μπορεί. Δεν είναι δίδυμο· είναι η **σωστή** εκδοχή, και οι δύο
 * παλιές είναι καταγεγραμμένο χρέος (`.claude-rules/pending-ratchet-work.md`).
 *
 * @module lib/spreadsheet/tsv
 * @see lib/spreadsheet/column-letter.ts — ο αδελφός SSoT του ίδιου φακέλου
 * @see docs/centralized-systems/reference/adrs/ADR-739-canvas-table-system.md §26
 */

/** Ο διαχωριστής στήλης. Στηλοθέτης — η σύμβαση του πρόχειρου κάθε φύλλου υπολογισμού. */
const COLUMN_SEPARATOR = '\t';

/**
 * Ο τερματιστής γραμμής **στην έξοδο**. `\r\n` επειδή αυτό γράφει το Excel, και επειδή τα
 * Windows Notepad-class καταναλωτές σπάνε με σκέτο `\n`. Η **είσοδος** δέχεται και τα τρία
 * (`\r\n`, `\n`, `\r`) — γενναιόδωρη στο διάβασμα, αυστηρή στο γράψιμο.
 */
const ROW_SEPARATOR = '\r\n';

const QUOTE = '"';

/** Ένα ορθογώνιο πλέγμα κειμένου — η ουδέτερη μορφή που ταξιδεύει από/προς το πρόχειρο. */
export type TsvGrid = readonly (readonly string[])[];

/**
 * Χρειάζεται αυτό το κελί εισαγωγικά;
 *
 * Ακριβώς οι τέσσερις χαρακτήρες που θα κατέστρεφαν τη δομή αν έμεναν γυμνοί: ο
 * διαχωριστής στήλης, οι δύο τερματιστές γραμμής, και το ίδιο το εισαγωγικό (που αλλιώς θα
 * διαβαζόταν ως αρχή περιτυλίγματος).
 */
function needsQuoting(cell: string): boolean {
  return (
    cell.includes(COLUMN_SEPARATOR) ||
    cell.includes('\n') ||
    cell.includes('\r') ||
    cell.includes(QUOTE)
  );
}

/** RFC 4180: περιτύλιξε σε εισαγωγικά και **διπλασίασε** τα εσωτερικά εισαγωγικά. */
function quoteCell(cell: string): string {
  return `${QUOTE}${cell.split(QUOTE).join(QUOTE + QUOTE)}${QUOTE}`;
}

/**
 * Πλέγμα → TSV για το πρόχειρο του λειτουργικού.
 *
 * Κάθε γραμμή γράφεται με **όσα κελιά έχει**: το ισομήκες το εγγυάται ο καλών (η επιλογή
 * είναι ορθογώνια εξ ορισμού), και ένα σιωπηλό γέμισμα εδώ θα έκρυβε το σφάλμα ενός
 * καλούντος που δεν είναι.
 *
 * **Χωρίς** τερματιστή στο τέλος: το Excel τον προσθέτει, αλλά τότε κάθε επικόλληση σε
 * απλό πεδίο κειμένου κουβαλά μια κενή γραμμή. Ο αναγνώστης παρακάτω δέχεται και τα δύο.
 */
export function formatTsv(grid: TsvGrid): string {
  return grid
    .map((row) => row.map((cell) => (needsQuoting(cell) ? quoteCell(cell) : cell)).join(COLUMN_SEPARATOR))
    .join(ROW_SEPARATOR);
}

/**
 * TSV από το πρόχειρο → πλέγμα.
 *
 * Σαρώνει **ολόκληρο το κείμενο** ως ρεύμα χαρακτήρων (όχι ανά γραμμή), γιατί ένα κελί σε
 * εισαγωγικά μπορεί να **περιέχει** αλλαγές γραμμής. Δες την κεφαλίδα.
 *
 * Κανόνες, με τη σειρά που τους εφαρμόζει ο βρόχος:
 * - `"` στην **αρχή** κελιού ⇒ ανοίγει περιτύλιγμα· `""` μέσα του ⇒ κυριολεκτικό `"`.
 * - `\r\n` μετράει ως **ένας** τερματιστής, αλλιώς κάθε γραμμή από Windows θα γεννούσε μια
 *   κενή από κάτω της.
 * - Ένας **τελικός** τερματιστής αγνοείται: το Excel τον γράφει, και χωρίς αυτόν τον κανόνα
 *   κάθε επικόλληση από Excel θα κουβαλούσε μια φάντασμα κενή γραμμή στο τέλος.
 *
 * Κενό ή αμιγώς κενό κείμενο ⇒ **κενό πλέγμα**, όχι πλέγμα με ένα κενό κελί: «δεν
 * αντιγράφηκε τίποτα» δεν είναι το ίδιο με «αντιγράφηκε ένα κενό κελί», και ο καλών
 * χρειάζεται να τα ξεχωρίσει για να μη σβήσει δεδομένα με μια άδεια επικόλληση.
 */
export function parseTsv(text: string): TsvGrid {
  if (text === '') return [];

  const rows: string[][] = [];
  let row: string[] = [];
  let cell = '';
  let quoted = false;

  for (let i = 0; i < text.length; i++) {
    const char = text[i];

    if (quoted) {
      if (char !== QUOTE) {
        cell += char;
      } else if (text[i + 1] === QUOTE) {
        cell += QUOTE;
        i++; // Το δεύτερο εισαγωγικό του ζεύγους καταναλώθηκε.
      } else {
        quoted = false;
      }
      continue;
    }

    if (char === QUOTE && cell === '') {
      quoted = true;
    } else if (char === COLUMN_SEPARATOR) {
      row.push(cell);
      cell = '';
    } else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[i + 1] === '\n') i++;
      row.push(cell);
      rows.push(row);
      row = [];
      cell = '';
    } else {
      cell += char;
    }
  }

  // Η τελευταία γραμμή κλείνει μόνη της **μόνο** αν δεν τερμάτισε ήδη με αλλαγή γραμμής.
  // Το `cell !== ''` δεν αρκεί ως κριτήριο: μια γραμμή «a\t» τελειώνει με κενό κελί που
  // είναι **υπαρκτό**, ενώ ένα τελικό `\n` δεν πρέπει να γεννήσει τίποτα.
  if (cell !== '' || row.length > 0) {
    row.push(cell);
    rows.push(row);
  }

  return rows;
}

/**
 * Το πλέγμα «ορθογωνισμένο»: κάθε γραμμή γεμίζει με κενά ως το **πλάτος της πλατύτερης**.
 *
 * Το χρειάζεται η **επικόλληση**, όχι η αντιγραφή: κείμενο από τον έξω κόσμο δεν έχει καμία
 * υποχρέωση να είναι ορθογώνιο (ένας χρήστης μπορεί να αντιγράψει τρεις γραμμές κειμένου
 * χωρίς κανέναν στηλοθέτη). Χωρίς αυτό, ο γραφέας θα έπρεπε να ελέγχει όρια σε κάθε κελί —
 * δηλαδή να ξέρει για ακανόνιστα πλέγματα, γνώση που δεν του ανήκει.
 */
export function rectangularizeTsvGrid(grid: TsvGrid): TsvGrid {
  const width = grid.reduce((max, row) => Math.max(max, row.length), 0);
  if (width === 0) return [];
  return grid.map((row) =>
    row.length === width ? row : [...row, ...Array<string>(width - row.length).fill('')],
  );
}
