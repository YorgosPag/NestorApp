/**
 * **SSoT πρόχειρου φύλλου υπολογισμού** — `lib/spreadsheet/tsv.ts` (ADR-739 Φ.Δ βήμα 8).
 *
 * Το επίκεντρο δεν είναι το «σπάσε στο tab» — αυτό δουλεύει και με δύο γραμμές κώδικα.
 * Είναι το **quoting**: η μία περίπτωση όπου η αφελής υλοποίηση δεν βγάζει ελαφρώς λάθος
 * αποτέλεσμα αλλά **μετατοπίζει όλες τις επόμενες στήλες**, δηλαδή καταστρέφει τα δεδομένα
 * σιωπηλά. Ένα κελί από Excel με στηλοθέτη μέσα του αρκεί.
 */

import { formatTsv, parseTsv, rectangularizeTsvGrid, type TsvGrid } from '../tsv';

describe('parseTsv — το πλέγμα που έρχεται από το πρόχειρο', () => {
  it('απλό πλέγμα, γραμμές × στήλες', () => {
    expect(parseTsv('a\tb\tc\r\nd\te\tf')).toEqual([
      ['a', 'b', 'c'],
      ['d', 'e', 'f'],
    ]);
  });

  it('δέχεται και τους τρεις τερματιστές γραμμής — CRLF, LF, CR', () => {
    const expected = [['a'], ['b']];
    expect(parseTsv('a\r\nb')).toEqual(expected);
    expect(parseTsv('a\nb')).toEqual(expected);
    expect(parseTsv('a\rb')).toEqual(expected);
  });

  it('🔴 το CRLF είναι ΕΝΑΣ τερματιστής — αλλιώς κάθε γραμμή από Windows γεννά μια κενή', () => {
    expect(parseTsv('a\r\nb\r\nc')).toHaveLength(3);
  });

  it('🔴 ο ΤΕΛΙΚΟΣ τερματιστής αγνοείται — το Excel τον γράφει πάντα', () => {
    expect(parseTsv('a\tb\r\n')).toEqual([['a', 'b']]);
    expect(parseTsv('a\tb\n')).toEqual([['a', 'b']]);
  });

  it('κενό κείμενο ⇒ ΚΕΝΟ πλέγμα, όχι πλέγμα με ένα κενό κελί', () => {
    // «Δεν αντιγράφηκε τίποτα» ≠ «αντιγράφηκε ένα κενό κελί»: το δεύτερο θα **έσβηνε**
    // το κελί προορισμού σε μια επικόλληση.
    expect(parseTsv('')).toEqual([]);
  });

  it('κενά κελιά στη μέση και στο τέλος διατηρούνται — είναι υπαρκτά', () => {
    expect(parseTsv('a\t\tc\t')).toEqual([['a', '', 'c', '']]);
  });

  // ── Το quoting: η μία περίπτωση που σκοτώνει την αφελή υλοποίηση ──────────

  it('🔴 κελί σε εισαγωγικά με ΣΤΗΛΟΘΕΤΗ μέσα δεν σπάει τη γραμμή', () => {
    // Αφελές `split('\t')` ⇒ 3 κελιά αντί για 2, και κάθε επόμενη στήλη μετατοπισμένη.
    expect(parseTsv('"a\tb"\tc')).toEqual([['a\tb', 'c']]);
  });

  it('🔴 κελί σε εισαγωγικά με ΑΛΛΑΓΗ ΓΡΑΜΜΗΣ δεν σπάει το πλέγμα', () => {
    // Αφελές `split('\n')` ⇒ 2 γραμμές αντί για 1 — και η δεύτερη με λάθος πλήθος στηλών.
    expect(parseTsv('"γραμμή1\nγραμμή2"\tδίπλα')).toEqual([['γραμμή1\nγραμμή2', 'δίπλα']]);
  });

  it('🔴 διπλό εισαγωγικό μέσα σε περιτύλιγμα ⇒ ΕΝΑ κυριολεκτικό εισαγωγικό (RFC 4180)', () => {
    expect(parseTsv('"λέει ""γεια"" σου"\tx')).toEqual([['λέει "γεια" σου', 'x']]);
  });

  it('εισαγωγικό στη ΜΕΣΗ κελιού είναι απλός χαρακτήρας — δεν ανοίγει περιτύλιγμα', () => {
    expect(parseTsv('12"\tx')).toEqual([['12"', 'x']]);
  });

  it('κενό περιτύλιγμα ⇒ κενό κελί', () => {
    expect(parseTsv('""\tx')).toEqual([['', 'x']]);
  });
});

describe('formatTsv — το πλέγμα που φεύγει προς το πρόχειρο', () => {
  it('απλό πλέγμα, στηλοθέτες και CRLF (η μορφή που γράφει το Excel)', () => {
    expect(formatTsv([['a', 'b'], ['c', 'd']])).toBe('a\tb\r\nc\td');
  });

  it('ΧΩΡΙΣ τερματιστή στο τέλος — αλλιώς κάθε επικόλληση κουβαλά κενή γραμμή', () => {
    expect(formatTsv([['a']])).toBe('a');
  });

  it.each([
    ['στηλοθέτης', 'a\tb', '"a\tb"'],
    ['αλλαγή γραμμής', 'a\nb', '"a\nb"'],
    ['επιστροφή δρομέα', 'a\rb', '"a\rb"'],
    ['εισαγωγικό', 'λέει "γεια"', '"λέει ""γεια"""'],
  ])('βάζει εισαγωγικά όταν το κελί περιέχει %s', (_name, cell, expected) => {
    expect(formatTsv([[cell]])).toBe(expected);
  });

  it('ΔΕΝ βάζει εισαγωγικά όταν δεν χρειάζονται — θόρυβος στο Excel του χρήστη', () => {
    expect(formatTsv([['145,75', 'Πλάκα Π3']])).toBe('145,75\tΠλάκα Π3');
  });
});

describe('🔴 ΚΥΚΛΟΣ — ό,τι γράφτηκε, διαβάζεται ξανά ταυτόσημο', () => {
  it.each<TsvGrid>([
    [['a', 'b'], ['c', 'd']],
    [['με\tστηλοθέτη', 'απλό']],
    [['με "εισαγωγικά"', 'και\nαλλαγή']],
    [['', '', '']],
    [['Α/Α', 'Περιγραφή', 'Ποσότητα'], ['1', 'Πλάκα Π3', '145,75']],
  ])('%#', (...rows) => {
    const grid = rows as unknown as TsvGrid;
    expect(parseTsv(formatTsv(grid))).toEqual(grid);
  });
});

describe('rectangularizeTsvGrid — κείμενο από τον έξω κόσμο δεν είναι ορθογώνιο', () => {
  it('γεμίζει τις κοντές γραμμές με κενά ως το πλάτος της πλατύτερης', () => {
    expect(rectangularizeTsvGrid([['a'], ['b', 'c', 'd'], ['e', 'f']])).toEqual([
      ['a', '', ''],
      ['b', 'c', 'd'],
      ['e', 'f', ''],
    ]);
  });

  it('ήδη ορθογώνιο ⇒ ίδιες γραμμές by-reference (μηδέν περιττή δέσμευση)', () => {
    const row = ['a', 'b'];
    expect(rectangularizeTsvGrid([row])[0]).toBe(row);
  });

  it('κενό πλέγμα ⇒ κενό πλέγμα', () => {
    expect(rectangularizeTsvGrid([])).toEqual([]);
  });
});
