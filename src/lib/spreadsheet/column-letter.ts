/** Πλήθος γραμμάτων του λατινικού αλφαβήτου — η βάση του συστήματος. */
const ALPHABET_SIZE = 26;

/** Ο κωδικός του `'A'`, η αρχή της αρίθμησης. */
const CODE_A = 65;

/**
 * Ο δείκτης στήλης (0-based) ως γράμμα φύλλου υπολογισμού.
 *
 * Αρνητικός ή μη-ακέραιος δείκτης ⇒ κενό αλφαριθμητικό: δεν υπάρχει «στήλη −1», και μια
 * σιωπηλή στρογγυλοποίηση θα έδινε **λάθος αναφορά** σε τύπο — δηλαδή λάθος αριθμό σε
 * παραδοτέο, που είναι σφάλμα τιμής και όχι εμφάνισης.
 */
export function columnLetter(index: number): string {
  if (!Number.isInteger(index) || index < 0) return '';
  let letters = '';
  let n = index;
  while (n >= 0) {
    letters = String.fromCharCode((n % ALPHABET_SIZE) + CODE_A) + letters;
    n = Math.floor(n / ALPHABET_SIZE) - 1;
  }
  return letters;
}

/**
 * Η αντίστροφη διαδρομή: `'A' → 0`, `'AA' → 26`. `null` για ο,τιδήποτε δεν είναι έγκυρο
 * γράμμα στήλης.
 *
 * Υπάρχει επειδή η ονοματολογία πρέπει να είναι **αμφιμονοσήμαντη**: η γραμμή τύπων γράφει
 * `B3`, το πλαίσιο ονόματος το διαβάζει πίσω, και ο μελλοντικός adapter τύπων (ADR-739 §9.2)
 * μεταφράζει `=SUM(B2:B7)` σε ταυτότητες στηλών. Μια μονόδρομη μετατροπή θα σήμαινε ότι ο
 * αναλυτής τύπων θα έγραφε **δεύτερη**, ανεξάρτητη αντιστροφή — το ίδιο διπλότυπο, μια φάση
 * αργότερα.
 *
 * Πεζά γίνονται δεκτά (`'b3'` ≡ `'B3'`): κάθε φύλλο υπολογισμού τα δέχεται, και ο χρήστης
 * που πληκτρολογεί αναφορά δεν έχει λόγο να σκεφτεί το `Caps Lock`.
 */
export function columnIndexFromLetter(letters: string): number | null {
  if (!/^[A-Za-z]+$/u.test(letters)) return null;
  let index = 0;
  for (const char of letters.toUpperCase()) {
    index = index * ALPHABET_SIZE + (char.charCodeAt(0) - CODE_A + 1);
  }
  // Ο βρόχος μετρά 1-based (`A = 1`), γιατί έτσι δουλεύει η bijective βάση· ο κόσμος έξω
  // από αυτό το αρχείο μιλά **δείκτες πίνακα**, άρα 0-based. Η αφαίρεση ζει εδώ, μία φορά.
  return index - 1;
}
