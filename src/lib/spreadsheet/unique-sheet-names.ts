/**
 * 🔴 ADR-833 §5.9.1 — **Η ΜΙΑ ΜΟΝΑΔΙΚΟΠΟΙΗΣΗ ΟΝΟΜΑΤΩΝ ΦΥΛΛΟΥ**: `Όνομα` → `Όνομα (2)` →
 * `Όνομα (3)`. Καθαρή συνάρτηση· μηδέν React/DOM, μηδέν i18n, μηδέν εξάρτηση.
 *
 * ## Η ερώτηση που την έφερε εδώ — και γιατί έχει **δύο** πελάτες, όχι έναν
 * Ο πίνακας του ADR-739 επιτρέπει **ρητά** δύο φύλλα με το ίδιο όνομα (ADR-833 §5.4.4):
 * εκεί η ταυτότητα είναι το `id`, όχι το όνομα, και ένα σιωπηλό `(2)` μέσα στα δεδομένα θα
 * ήταν **αλλοίωση δεδομένου χρήστη** (§5.2). Δύο **σύνορα γραφής** όμως δεν έχουν αυτή την
 * πολυτέλεια, γιατί και τα δύο παράγουν κείμενο που **κάποιος θα ξαναδιαβάσει**:
 *
 * ```
 *   .xlsx          το OOXML δείχνει φύλλα ΚΑΤΑ ΟΝΟΜΑ  ⇒ 'Φύλλο (2)'!A1   (Φάση 6)
 *   γραμμή τύπων   το ίδιο κείμενο ξαναδιαβάζεται      ⇒ 'Φύλλο (2)'!A1   (Φάση 7)
 * ```
 *
 * Η **Φάση 7** ανακάλυψε το δεύτερο: ένας εκτυπωτής που γράφει σκέτο `=Κόστη!A1` για **δύο**
 * ομώνυμα φύλλα παράγει κείμενο που ξαναδιαβάζεται στο **πρώτο** — δηλαδή ένας τύπος που ο
 * χρήστης απλώς **άνοιξε και έκλεισε** θα άλλαζε σιωπηλά φύλλο. Σε πίνακα ποσοτήτων αυτό
 * είναι **σφάλμα τιμής σε παραδοτέο**, η ίδια κλάση με το ADR-764.
 *
 * 👉 Ο κανόνας, σε μία πρόταση:
 * > **Τα ονόματα φύλλων μοναδικοποιούνται σε κάθε σύνορο ΓΡΑΦΗΣ — της οθόνης και του
 * > αρχείου — και ΠΟΤΕ στα δεδομένα.**
 *
 * ## ⚠️ Η ΕΞΥΓΙΑΝΣΗ ΔΕΝ ΖΕΙ ΕΔΩ — και είναι η μόνη διαφορά των δύο πελατών
 * Οι απαγορευμένοι χαρακτήρες (`* ? : \ / [ ]`) και το ταβάνι των 31 χαρακτήρων είναι όροι
 * **του μορφότυπου** `.xlsx` και δεν αφορούν την οθόνη: μια καρτέλα λέγεται όπως θέλει ο
 * χρήστης. Άρα ο πελάτης του αρχείου εξυγιαίνει **πριν** και περνά το `maxLength`· ο πελάτης
 * της οθόνης δεν κάνει τίποτα από τα δύο. **Ένα** SSoT, μία δηλωμένη διαφορά.
 *
 * ## Γιατί το `(2)` ΔΕΝ περνά από i18n (N.11)
 * Είναι **σύμβαση μορφότυπου**, όχι ετικέτα: το Excel γράφει `(2)` σε κάθε γλώσσα, και το ίδιο
 * κείμενο πρέπει να ξαναδιαβαστεί από τον αναλυτή μας **και** από το Excel. Μεταφρασμένο
 * επίθεμα θα σήμαινε ότι το ίδιο βιβλίο διαβάζεται αλλιώς σε άλλη γλώσσα — ακριβώς το
 * σκεπτικό με το οποίο το `types/table-formula.ts` κρατά τους κωδικούς `#REF!` εκτός i18n.
 *
 * @module lib/spreadsheet/unique-sheet-names
 * @see subapps/dxf-viewer/bim/schedule/exporters/xlsx-workbook.ts — ο πελάτης του **αρχείου**
 * @see subapps/dxf-viewer/bim/table/table-worksheet-book.ts — ο πελάτης της **οθόνης**
 * @see docs/centralized-systems/reference/adrs/ADR-833-table-xlsx-import-and-worksheets.md §5.9.1
 */

/**
 * Τα ίδια ονόματα, **στη σειρά τους**, μοναδικά — με τη σύμβαση `(2)`, `(3)`, … του Excel.
 *
 * 🔴 **Η σύγκριση είναι case-insensitive, ΑΥΣΤΗΡΟΤΕΡΑ από τον `exceljs`.** Ο `exceljs`
 * συγκρίνει με `===` και θα δεχόταν `Φύλλο` + `φύλλο`· το **Excel** τα θεωρεί το ίδιο όνομα
 * και θα αρνιόταν να ανοίξει το βιβλίο. Και στη γραμμή τύπων ισχύει το ίδιο για τον δικό μας
 * αναλυτή, που λύνει το γραμμένο όνομα **χωρίς** διάκριση πεζών/κεφαλαίων, όπως το Excel.
 *
 * ⚠️ **Όταν το επίθεμα δεν χωρά στο `maxLength`, κόβεται η ΒΑΣΗ, όχι το επίθεμα**: ένα όνομα
 * που τελειώνει σε `(2` δεν είναι απλώς άσχημο — δεν λέει πια «το δεύτερο», και δύο τέτοια
 * θα ξανασυγκρούονταν.
 *
 * @param rawNames Τα ονόματα όπως τα θέλει ο καλών. Η **εξυγίανση** είναι δική του δουλειά —
 *   δες την κεφαλίδα για το γιατί.
 * @param maxLength Ταβάνι μήκους του **μορφότυπου**· απόν ⇒ κανένα ταβάνι (οθόνη).
 */
export function uniqueSheetNames(
  rawNames: readonly string[],
  maxLength: number = Number.POSITIVE_INFINITY,
): readonly string[] {
  const taken = new Set<string>();
  return rawNames.map((base) => {
    let candidate = base;
    let attempt = 2;
    while (taken.has(candidate.toLowerCase())) {
      const suffix = ` (${attempt})`;
      // Το `slice` με άπειρο `maxLength` επιστρέφει ολόκληρη τη βάση — άρα ο κλάδος «χωρίς
      // ταβάνι» δεν χρειάζεται δική του γραμμή, και δεν υπάρχει δεύτερο σώμα να αποκλίνει.
      candidate = base.slice(0, maxLength - suffix.length) + suffix;
      attempt += 1;
    }
    taken.add(candidate.toLowerCase());
    return candidate;
  });
}
