/**
 * **SSoT: οι μονάδες του φύλλου Excel ⇄ χιλιοστά** — πλάτος στήλης (χαρακτήρες) και ύψος
 * γραμμής (στιγμές).
 *
 * ## 🔴 Γιατί υπάρχει: ένα πεδίο κουβαλούσε ΔΥΟ μονάδες (ADR-833 §5.7.2)
 * Το `ScheduleColumnDef` δήλωνε `widthHint?: number` με σχόλιο *«chars OR mm —
 * exporter-specific»*: **η ίδια τιμή σήμαινε δύο πράγματα** και ποιο ίσχυε το ήξερε μόνο ο
 * καταναλωτής. Είναι το σχήμα που το **ADR-716** έχει ήδη τιμωρήσει, και ο πίνακας (που μετρά
 * τα πάντα σε **sheet-mm**) ετοιμαζόταν να γίνει ο τρίτος καταναλωτής της ασάφειας. Η μονάδα
 * ζει πλέον στο **όνομα** (`widthChars`), και η **μετάφραση** ζει εδώ, μία φορά.
 *
 * ## 🔬 Ο τύπος του πλάτους — ECMA-376 §18.3.1.13, όχι διαίσθηση
 * Το `.xlsx` **δεν** αποθηκεύει πλάτος στηλών σε φυσική μονάδα. Αποθηκεύει «χαρακτήρες» της
 * **προεπιλεγμένης γραμματοσειράς του βιβλίου**, σε βήματα 1/256:
 *
 * ```
 *   width = Truncate( (Nχαρ × MDW + PP) / MDW × 256 ) / 256
 *   MDW = Max Digit Width — το πλάτος του πλατύτερου ψηφίου 0-9, ΣΕ ΕΙΚΟΝΟΣΤΟΙΧΕΙΑ
 *   PP  = 2 × ceil(MDW/4) + 1   (2px περιθώριο ανά πλευρά + 1px γραμμή πλέγματος)
 * ```
 *
 * Άρα `px = Nχαρ × MDW + PP`, και `mm = px × 25,4 / 96` (η ονομαστική ανάλυση του OOXML).
 *
 * 🔑 **Έλεγχος με ΓΝΩΣΤΟ νούμερο, όχι με εντύπωση**: το προεπιλεγμένο πλάτος στήλης του Excel
 * είναι `8,43` χαρακτήρες ⇒ `8,43 × 7 + 5 = 64,0 px` ⇒ **16,9 mm** — και το ίδιο το Excel
 * δηλώνει «1,69 cm» στο *Column Width*. Ο τύπος επαληθεύεται από τα **δικά του** νούμερα.
 *
 * ## 🔴 Η ΕΞΑΡΤΗΣΗ ΑΠΟ ΤΗ ΓΡΑΜΜΑΤΟΣΕΙΡΑ ΕΙΝΑΙ ΠΑΡΑΜΕΤΡΟΣ, ΟΧΙ ΚΡΥΜΜΕΝΗ ΣΤΑΘΕΡΑ
 * Το `MDW = 7` ισχύει για **Calibri 11 στα 96 DPI**. Άλλη προεπιλεγμένη γραμματοσειρά ⇒ άλλο
 * MDW ⇒ **άλλα χιλιοστά για τον ίδιο αριθμό**. Στην **εξαγωγή** η υπόθεση είναι αληθής εξ
 * κατασκευής (εμείς γράφουμε το βιβλίο και δεν δηλώνουμε γραμματοσειρά)· στην **εισαγωγή**
 * είναι υπόθεση. Γι' αυτό περνά ως όρισμα με δηλωμένη προεπιλογή: την ημέρα που θα διαβάζουμε
 * τη γραμματοσειρά του βιβλίου, αλλάζει **ένα** όρισμα — όχι μια αναζήτηση σε όλο το δέντρο.
 *
 * ## Γιατί το ύψος ζει στο ΙΔΙΟ αρχείο παρότι ΔΕΝ περνά από το MDW
 * Το OOXML γράφει το ύψος γραμμής σε **στιγμές** (`1 pt = 25,4/72 mm`) — ήδη φυσική μονάδα,
 * καμία γραμματοσειρά. Δύο αρχεία όμως θα ήταν **δύο μέρη να ψάξεις** για την ίδια ερώτηση:
 * *«σε τι μονάδα το λέει το Excel εδώ, και πόσα χιλιοστά είναι;»* Ένα αρχείο, δύο άξονες.
 *
 * @module lib/spreadsheet/excel-sheet-units
 * @see subapps/dxf-viewer/bim/table/import/xlsx-worksheet-format.ts — ο αναγνώστης
 * @see subapps/dxf-viewer/bim/table/export/table-to-xlsx.ts — ο γραφέας
 * @see docs/centralized-systems/reference/adrs/ADR-833-table-xlsx-import-and-worksheets.md §5.7.3
 */

/**
 * Η ονομαστική ανάλυση του OOXML: **96 εικονοστοιχεία ανά ίντσα**.
 *
 * Δεν είναι η ανάλυση της οθόνης του χρήστη και δεν πρέπει να γίνει: το αρχείο περιγράφει τον
 * εαυτό του με αυτή, οπότε ένα «έξυπνο» `devicePixelRatio` εδώ θα σήμαινε ότι το **ίδιο**
 * αρχείο δίνει άλλο πλάτος σε άλλη οθόνη — δηλαδή σφάλμα **τιμής** σε παραδοτέο.
 */
const OOXML_DPI = 96;

/** `25,4 mm` ανά ίντσα — ο ορισμός της ίντσας, όχι συντελεστής προσέγγισης. */
const MM_PER_INCH = 25.4;

/** Χιλιοστά ανά εικονοστοιχείο στην ονομαστική ανάλυση του OOXML. */
const MM_PER_PIXEL = MM_PER_INCH / OOXML_DPI;

/** Στιγμές ανά ίντσα — ο τυπογραφικός ορισμός (`1 pt = 1/72"`). */
const POINTS_PER_INCH = 72;

/** Χιλιοστά ανά στιγμή. */
const MM_PER_POINT = MM_PER_INCH / POINTS_PER_INCH;

/**
 * **Max Digit Width** της Calibri 11 στα 96 DPI, σε εικονοστοιχεία.
 *
 * Η προεπιλεγμένη γραμματοσειρά κάθε βιβλίου που γράφει το Excel από το 2007 και μετά — και,
 * επειδή ο δικός μας γραφέας δεν δηλώνει γραμματοσειρά βιβλίου, η προεπιλογή **και των δικών
 * μας** αρχείων.
 */
export const CALIBRI_11_MAX_DIGIT_WIDTH_PX = 7;

/**
 * Το σταθερό «γέμισμα» κάθε στήλης σε εικονοστοιχεία: `2 × ceil(MDW/4) + 1`.
 *
 * Τα δύο περιθώρια (αριστερά/δεξιά) **συν** τη γραμμή πλέγματος. Παράγεται από το MDW αντί να
 * γραφτεί `5`, γιατί το `5` είναι σωστό **μόνο** για MDW 5-8 — και η μέρα που το MDW γίνεται
 * παράμετρος είναι σήμερα.
 */
export function excelColumnPaddingPx(maxDigitWidthPx: number): number {
  return 2 * Math.ceil(maxDigitWidthPx / 4) + 1;
}

/**
 * Πλάτος στήλης του Excel (**χαρακτήρες**) → **χιλιοστά**.
 *
 * Μη πεπερασμένο ή αρνητικό ⇒ `0`: «καμία δηλωμένη στήλη» δεν είναι «στήλη αρνητικού πλάτους»,
 * και ένα `NaN` που ταξιδεύει σε γεωμετρία δηλητηριάζει τα όρια **ολόκληρης** της σκηνής
 * (`build-table-entity.ts`, το ίδιο μάθημα).
 */
export function excelCharsToMm(
  chars: number,
  maxDigitWidthPx: number = CALIBRI_11_MAX_DIGIT_WIDTH_PX,
): number {
  if (!Number.isFinite(chars) || chars <= 0) return 0;
  const px = chars * maxDigitWidthPx + excelColumnPaddingPx(maxDigitWidthPx);
  return px * MM_PER_PIXEL;
}

/**
 * **Χιλιοστά** → πλάτος στήλης του Excel (**χαρακτήρες**). Ο αντίστροφος του
 * {@link excelCharsToMm}, γραμμένος δίπλα του για τον λόγο του `parseCellToStore`: δύο
 * κατευθύνσεις σε δύο αρχεία είναι δύο λίστες που κάποτε αποκλίνουν.
 *
 * ⚠️ Πλάτος **μικρότερο από το γέμισμα** δίνει `0` και όχι αρνητικό: μια στήλη 1 mm δεν χωρά
 * ούτε τα περιθώριά της, και το Excel δεν έχει τρόπο να το εκφράσει παρά ως «κρυμμένη».
 */
export function mmToExcelChars(
  mm: number,
  maxDigitWidthPx: number = CALIBRI_11_MAX_DIGIT_WIDTH_PX,
): number {
  if (!Number.isFinite(mm) || mm <= 0) return 0;
  const px = mm / MM_PER_PIXEL;
  const chars = (px - excelColumnPaddingPx(maxDigitWidthPx)) / maxDigitWidthPx;
  return chars > 0 ? chars : 0;
}

/**
 * Ύψος γραμμής του Excel (**στιγμές**) → **χιλιοστά**. Καμία εξάρτηση από γραμματοσειρά — δες
 * την κεφαλίδα.
 */
export function excelPointsToMm(points: number): number {
  if (!Number.isFinite(points) || points <= 0) return 0;
  return points * MM_PER_POINT;
}

/** **Χιλιοστά** → ύψος γραμμής του Excel (**στιγμές**). */
export function mmToExcelPoints(mm: number): number {
  if (!Number.isFinite(mm) || mm <= 0) return 0;
  return mm / MM_PER_POINT;
}
