/**
 * @fileoverview **ΕΠΙΚΑΛΥΨΗ ΔΥΟ ΑΠΛΩΝ ΠΟΛΥΓΩΝΩΝ** (ADR-884 §4.14 Γ3β) — ο κριτής του Revit «Room overlaps», με ανοχή.
 *
 * Το ζητούμενο είναι η **διάκριση**: κοινός τοίχος / κοινή νοητή γραμμή / τρεμούλιασμα μισού pixel ⇒ ΟΧΙ· πάνω στον γείτονα,
 * εγκλεισμός, διασταύρωση, ταυτόσημοι ⇒ ΝΑΙ. Και η απάντηση **συμμετρική** — ο κριτής δεν εξαρτάται από τη σειρά.
 */

import { polygonsOverlap } from '../planar-polygon-overlap';

const TOL = 0.05;
const rect = (x0: number, y0: number, x1: number, y1: number) => [{ x: x0, y: y0 }, { x: x1, y: y0 }, { x: x1, y: y1 }, { x: x0, y: y1 }];
const both = (a: ReturnType<typeof rect>, b: ReturnType<typeof rect>) => [polygonsOverlap(a, b, TOL), polygonsOverlap(b, a, TOL)];

describe('polygonsOverlap', () => {
  const room = rect(0, 0, 4, 3);

  it.each([
    ['κοινός τοίχος (ίδιο μήκος)', rect(4, 0, 8, 3)],
    ['κοινός τοίχος (μερικός, σκαλωτός)', rect(4, 1, 8, 5)],
    ['μόνο γωνία', rect(4, 3, 6, 5)],
    ['τρεμούλιασμα 2 cm πάνω στον γείτονα', rect(3.98, 0, 8, 3)],
    ['μακριά', rect(10, 10, 12, 12)],
    ['απόσταση 1 cm (μέσα στην ανοχή του κουτιού)', rect(4.01, 0, 8, 3)],
  ])('%s ⇒ ΟΧΙ επικάλυψη', (_label, other) => {
    expect(both(room, other)).toEqual([false, false]);
  });

  it.each([
    ['30 cm πάνω στον γείτονα', rect(3.7, 0, 8, 3)],
    ['εγκλεισμός (ντουλάπι μέσα στο δωμάτιο)', rect(1, 1, 2, 2)],
    ['εγκλεισμός που ακουμπά τον τοίχο', rect(0, 0, 2, 3)],
    ['ταυτόσημοι', rect(0, 0, 4, 3)],
    ['ταυτόσημοι με τρεμούλιασμα 1 cm', rect(0.01, 0, 4, 3.01)],
    ['σταυρός (καμία κορυφή μέσα στην άλλη)', rect(-1, 1, 5, 2)],
    // Τα μέσα ΟΛΩΝ των ακμών πέφτουν πάνω στο σύνορο ή έξω — τη λωρίδα τη βρίσκει μόνο το σπάσιμο στα σημεία τομής.
    ['λωρίδα που διασχίζει, με μέσα ακμών στο σύνορο', rect(0.5, -10, 1.5, 10)],
  ])('%s ⇒ επικάλυψη', (_label, other) => {
    expect(both(room, other)).toEqual([true, true]);
  });

  it('Γ που «αγκαλιάζει» το δωμάτιο στον κοινό του τοίχο ⇒ ΟΧΙ · Γ που μπαίνει 1 m μέσα ⇒ ΝΑΙ', () => {
    const hug = [{ x: 4, y: 0 }, { x: 6, y: 0 }, { x: 6, y: 5 }, { x: 0, y: 5 }, { x: 0, y: 3 }, { x: 4, y: 3 }];
    expect(both(room, hug)).toEqual([false, false]);
    const bite = [{ x: 3, y: 0 }, { x: 6, y: 0 }, { x: 6, y: 5 }, { x: 0, y: 5 }, { x: 0, y: 3 }, { x: 3, y: 3 }];
    expect(both(room, bite)).toEqual([true, true]);
  });

  it('εκφυλισμένη είσοδος (< 3 κορυφές) ⇒ ΟΧΙ — τη σφαλίζει ο καλών, ο κριτής δεν πετά', () => {
    expect(polygonsOverlap(room, [{ x: 1, y: 1 }, { x: 2, y: 2 }], TOL)).toBe(false);
  });
});
