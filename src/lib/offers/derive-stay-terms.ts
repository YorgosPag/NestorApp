import { isLiveOffer, type PropertyOffer } from '@/types/property-offers';

/**
 * **Οι όροι διαμονής μιας ζωντανής βραχυχρόνιας διάθεσης.**
 *
 * 🔑 **Δομικό σχήμα, όχι εισαγωγή του `PublicListingStay`** — και δεν είναι ύφος: το
 * `PublicListingStay` έχει **τρία** πεδία, και το τρίτο (`nextAvailableFrom`) είναι
 * **παράγωγο του ημερολογίου**, το οποίο αυτό το αρχείο **δεν βλέπει ποτέ** (§4.5: το
 * ημερολόγιο δεν ζει στην προβολή). Επιστροφή του πλήρους τύπου θα υποχρέωνε εδώ ένα
 * `nextAvailableFrom: null` — δηλαδή αυτό το αρχείο θα **δήλωνε** ότι δεν ξέρουμε
 * επόμενη ελεύθερη ημερομηνία, ενώ απλώς **δεν είναι η δουλειά του να ξέρει**.
 */
export interface DerivedStayTerms {
  readonly minNights: number | null;
  readonly maxGuests: number | null;
}

/**
 * Διαθέσεις → **οι όροι διαμονής**, ή `null` αν δεν υπάρχει ζωντανή βραχυχρόνια.
 *
 * 🔴 **`null` ΚΑΙ ΟΧΙ `{ minNights: null, maxGuests: null }` — η διάκριση είναι
 * ολόκληρος ένας κάδος της αναζήτησης.** Το πρώτο σημαίνει *«δεν είναι κατάλυμα»*
 * (`not-a-stay`)· το δεύτερο σημαίνει *«είναι κατάλυμα που δεν δήλωσε τίποτα»*
 * (`terms-unknown`). Ένα αντικείμενο με μηδενικά για ακίνητο **προς πώληση** θα
 * κατηγορούσε τον κάτοχο για πεδία που **δεν του ζητήθηκαν ποτέ**.
 *
 * ⚠️ **Ίδιο δόγμα με το `deriveCommercialAmounts`**: μόνο **ζωντανές** διαθέσεις
 * ({@link isLiveOffer}). Μια **αποσυρμένη** βραχυχρόνια δεν δίνει όρους — αλλιώς η
 * κάρτα θα έλεγε «ελάχιστο 3 νύχτες» για κατάλυμα που **δεν νοικιάζεται πια**.
 *
 * 🔑 **Η τελευταία ζωντανή νικά, όπως και στα ποσά.** Ο φρουρός που εγγυάται ότι
 * υπάρχει **μία** είναι το `hasDuplicateLiveOfferKind` (§6.3), και ζει **στα
 * invariants** — όχι εδώ: μια ανάγνωση δεν είναι η θέση όπου επιβάλλεται μοναδικότητα.
 */
export function deriveStayTerms(
  offers: readonly PropertyOffer[] | null | undefined,
): DerivedStayTerms | null {
  let terms: DerivedStayTerms | null = null;

  for (const offer of offers ?? []) {
    if (!isLiveOffer(offer)) continue;
    if (offer.kind !== 'leaseShort') continue;
    terms = {
      minNights: offer.minNights ?? null,
      maxGuests: offer.maxGuests ?? null,
    };
  }

  return terms;
}
