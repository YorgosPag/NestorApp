/**
 * 🔴 ADR-828 §1 — **ΠΡΟΣΘΕΣΗ ΜΗΝΩΝ ΚΑΙ ΕΤΩΝ ΠΟΥ ΔΕΝ ΞΕΦΕΥΓΕΙ ΑΠΟ ΤΟΝ ΜΗΝΑ.**
 *
 * ## Το ερώτημα που απαντά: «31 Ιανουαρίου συν έναν μήνα — πότε;»
 * Η αφελής απάντηση (`setUTCMonth(m + 1)`) δίνει **3 Μαρτίου**, γιατί η 31η Φεβρουαρίου δεν
 * υπάρχει και ο `Date` την κυλά σιωπηλά μπροστά. Είναι η **σωστή** συμπεριφορά για έναν
 * μετρητή χιλιοστών του δευτερολέπτου και η **λάθος** για ημερολόγιο: ο άνθρωπος που έγραψε
 * «31/1» και τράβηξε τη λαβή εννοεί «το τέλος του επόμενου μήνα», ποτέ «τρεις μέρες μέσα σε
 * αυτόν που ακολουθεί». Το Excel το ψαλιδίζει· το ψαλιδίζουμε.
 *
 * ## Γιατί υπάρχει ως ξεχωριστό αρχείο και όχι μέσα στη σειρά
 * Ο κανόνας ήταν **ήδη γραμμένος** — ιδιωτικός, στο `lib/survey-record/survey-date.ts`, με το
 * σχόλιο «ώστε η *31/02* να **μην** γίνει σιωπηλά 3 Μαρτίου». Δεύτερο αντίγραφο της ίδιας
 * γραμμής σε άλλο φάκελο είναι δύο σημεία που μπορούν να μάθουν διαφορετικό ψαλίδισμα, και
 * το ψαλίδισμα είναι **τιμή**, όχι μορφή: η διαφορά φαίνεται στο κελί, όχι στην οθόνη.
 *
 * ## Όλα σε UTC, χωρίς εξαίρεση
 * Μια ημερομηνία εγγράφου **δεν έχει ώρα**, άρα δεν έχει και ζώνη. Η τοπική ζώνη θα έφερνε
 * μια ολίσθηση μιας ημέρας που εμφανίζεται μόνο σε κάποιους χρήστες και μόνο κάποιους μήνες
 * — δηλαδή σφάλμα που δεν αναπαράγεται στον υπολογιστή που το ψάχνει. Ίδιος κανόνας, ίδιος
 * λόγος με τον σειριακό αριθμό του Excel ({@link module:subapps/dxf-viewer/bim/table/formula/excel-serial-date}).
 *
 * @module lib/date/calendar-arithmetic
 * @see docs/centralized-systems/reference/adrs/ADR-828-table-autofill-series.md §1
 */

/**
 * Πόσες μέρες έχει ο μήνας — ώστε η «31/02» να **μην** γίνει σιωπηλά 3 Μαρτίου.
 *
 * ⚠️ Ο `month` είναι **1-based** (Ιανουάριος = 1), σε αντίθεση με τον `Date`. Δεν είναι
 * ασυνέπεια: το `Date.UTC(y, m, 0)` σημαίνει «η μηδενική μέρα του μήνα με 0-based δείκτη
 * `m`» = «η **τελευταία** μέρα του προηγούμενου», και ο προηγούμενος του 0-based `m` είναι
 * ο 1-based `m`. Το ότι το κόλπο διαβάζεται φυσικά με 1-based είσοδο είναι ο λόγος που
 * γράφεται έτσι — η εναλλακτική θα ήταν `Date.UTC(y, m + 1, 0)`, που ζητά από τον αναγνώστη
 * να κρατά δύο μετατοπίσεις στο μυαλό του ταυτόχρονα.
 */
export function daysInMonth(year: number, month: number): number {
  return new Date(Date.UTC(year, month, 0)).getUTCDate();
}

/**
 * Ημερομηνία UTC από συνιστώσες, **ανθεκτική στα διψήφια έτη**.
 *
 * ⚠️ Το `Date.UTC(99, 0, 1)` δίνει **1999**, όχι 99 — κληρονομιά που η προδιαγραφή κρατά για
 * συμβατότητα. Δεν αφορά τους σημερινούς καλούντες (οι σειριακοί του Excel ξεκινούν από το
 * 1900), αλλά ένα «δεν αφορά σήμερα» μέσα σε κοινό βοήθημα είναι υπόσχεση που κάποιος θα
 * σπάσει· το `setUTCFullYear` την κλείνει με ένα κόστος που δεν μετριέται.
 */
function utcDate(year: number, monthIndex: number, day: number): Date {
  const date = new Date(Date.UTC(2000, monthIndex, day));
  date.setUTCFullYear(year);
  return date;
}

/**
 * `date` **συν** `months` μήνες, με την ημέρα **ψαλιδισμένη** στο τέλος του μήνα προορισμού.
 *
 * `31/1 + 1` ⇒ `28/2` (ή `29/2` σε δίσεκτο). `31/5 − 1` ⇒ `30/4`.
 *
 * 🔑 **Λειτουργεί και προς τα πίσω χωρίς κλάδο.** Το `Math.floor` πάνω στους συνολικούς μήνες
 * κρατά το υπόλοιπο θετικό ακόμη και για αρνητικό `months`, οπότε η αφαίρεση είναι η ίδια
 * γραμμή με την πρόσθεση. Ένας κλάδος «αν αρνητικό» θα ήταν δεύτερο σημείο που μπορεί να
 * μάθει διαφορετικό ψαλίδισμα — και η ανάστροφη σύρση της λαβής τον θα χτυπούσε **πρώτη**.
 */
export function addMonthsClampedUtc(date: Date, months: number): Date {
  const totalMonths = date.getUTCFullYear() * 12 + date.getUTCMonth() + months;
  const year = Math.floor(totalMonths / 12);
  const monthIndex = totalMonths - year * 12;
  const day = Math.min(date.getUTCDate(), daysInMonth(year, monthIndex + 1));
  return utcDate(year, monthIndex, day);
}

/**
 * `date` **συν** `years` έτη, με την 29η Φεβρουαρίου να ψαλιδίζεται σε 28η όταν το έτος
 * προορισμού δεν είναι δίσεκτο.
 *
 * 🔑 **Δεν είναι δεύτερη μηχανή** — είναι η ίδια, ρωτημένη σε δωδεκάδες. Ένα ξεχωριστό
 * `setUTCFullYear` θα ήταν ένας ακόμη τόπος όπου το ψαλίδισμα μπορεί να ξεχαστεί, και θα
 * ξεχνιόταν ακριβώς στη μία μέρα στις 1.461 που κανείς δεν δοκιμάζει.
 */
export function addYearsClampedUtc(date: Date, years: number): Date {
  return addMonthsClampedUtc(date, years * 12);
}
