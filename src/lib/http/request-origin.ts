// ΤΟ ΔΗΜΟΣΙΟ ORIGIN
// ============================================================================

/** Το ελάχιστο που χρειάζεται αυτό το module από ένα αίτημα. */
interface RequestLike {
  readonly headers: Headers;
}

/** Το origin όπως το **ισχυρίζεται ο πελάτης** — εφεδρεία, ποτέ αυθεντία. */
function originFromHeaders(headers: Headers): string | null {
  const host = headers.get('x-forwarded-host') ?? headers.get('host');
  if (!host || isUnroutableHost(host)) return null;

  const proto = headers.get('x-forwarded-proto')?.split(',')[0]?.trim() || 'https';
  return `${proto}://${host}`;
}

/**
 * **Η δημόσια διεύθυνση αυτής της εγκατάστασης**, ή `null` αν δεν μπορούμε να
 * την ονομάσουμε.
 *
 * 🔑 **Το `null` είναι απάντηση, όχι αποτυχία.** Ο καλών οφείλει να έχει έξοδο:
 * ένα `null` που γίνεται σιωπηλά `'http://localhost:3000'` παράγει σύνδεσμο που
 * **μοιάζει** έγκυρος μέσα σε email και δεν ανοίγει ποτέ — δηλαδή μετατρέπει
 * θόρυβο ρύθμισης σε **σιωπηλή απώλεια**.
 *
 * ⛔ **ΜΗΝ προσθέσεις εδώ `request.url` ως εφεδρεία.** Είναι η ΑΙΤΙΑ του
 * περιστατικού, όχι λύση του: επιστρέφει το `HOSTNAME` του container.
 */
export function requestOrigin(request: RequestLike): string | null {
  return publicOrigin() ?? originFromHeaders(request.headers);
}

/**
 * Το ίδιο, για τους καλούντες που **δεν έχουν νόημα χωρίς διεύθυνση** — ένα PDF
 * με σύνδεσμο `https://null/…` μέσα του είναι χειρότερο από απουσία PDF.
 *
 * ⚠️ **Το `throw` είναι η υπηρεσία, όχι η αποτυχία**: γεννά 500 με **ονομαστική
 * αιτία** στα ίχνη, αντί για αρχείο που φεύγει στον πελάτη και σπάει αργότερα,
 * αλλού, χωρίς κανένα νήμα πίσω σε αυτή τη ρύθμιση.
 */
export function requestOriginOrThrow(request: RequestLike): string {
  const origin = requestOrigin(request);
  if (origin === null) {
    throw new Error(
      '[request-origin] Δεν υπάρχει δημόσια διεύθυνση: ούτε NEXT_PUBLIC_APP_URL ' +
        'ούτε δρομολογήσιμο host header. Ρύθμισε το NEXT_PUBLIC_APP_URL.',
    );
  }
  return origin;
}

/**
 * Απόλυτο URL πάνω στο δημόσιο origin — **μόνο** για ό,τι φεύγει από τον
 * φυλλομετρητή *(email · QR · PDF)*.
 *
 * Για ανακατεύθυνση χρησιμοποίησε το {@link redirectTo}: εκεί το απόλυτο URL δεν
 * είναι απλώς περιττό, είναι **η ίδια η ρίζα του σφάλματος**.
 */
export function absoluteUrl(request: RequestLike, path: string): string | null {
  const origin = requestOrigin(request);
  return origin === null ? null : joinOrigin(origin, path);
}

