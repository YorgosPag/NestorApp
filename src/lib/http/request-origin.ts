/**
 * Οι μόνοι κωδικοί ανακατεύθυνσης που χρησιμοποιεί το έργο.
 *
 * ⚠️ **Το `308` υπάρχει στον τύπο αλλά δεν είναι προεπιλογή**: ο
 * `app/home/route.ts` το έχει ήδη γραμμένο — *«307, ποτέ 308: ο προορισμός
 * εξαρτάται από το ποιος ρωτά· ένα 308 είναι cacheable ⇒ ο φυλλομετρητής θα
 * κλείδωνε `/home → <ο χώρος του Α>` και θα το σέρβιρε στον Β»*.
 */
export type RedirectStatus = 302 | 303 | 307 | 308;

/**
 * **Ανακατεύθυνση χωρίς να δηλώσουμε ποιοι είμαστε** — η προεπιλογή **στο Node**.
 *
 * ⛔ **ΜΗΝ το γυρίσεις σε `NextResponse.redirect(new URL(path, request.url))`.**
 * Αυτή ακριβώς η γραφή έστειλε άνθρωπο στο `https://0.0.0.0:3000/o/…` και τον
 * υποδέχτηκε προειδοποίηση phishing. Το `NextResponse.redirect` **απαιτεί**
 * απόλυτο URL — γι' αυτό εδώ χτίζεται ωμή απόκριση: η μόνη οδός προς σχετικό
 * `Location`.
 *
 * 🔴 **ΚΑΙ ΜΗΝ ΤΟ ΚΑΛΕΣΕΙΣ ΑΠΟ ΤΟ `src/middleware.ts`** — δες
 * {@link redirectFromMiddleware}. Το Edge **δεν ανέχεται** σχετικό `Location`:
 * μετρημένο 500 στην παραγωγή, 2026-09-12.
 *
 * @param location σχετική διαδρομή, **πάντα** με αρχικό `/`
 */
export function redirectTo(
  location: string,
  status: RedirectStatus = 307,
): NextResponse {
  return new NextResponse(null, { status, headers: { Location: location } });
}

/**
 * **Ανακατεύθυνση από το middleware** — η **μόνη** μεταφορά που μας υποχρεώνει να
 * ονομάσουμε το σπίτι μας.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΜΕΤΡΗΜΕΝΟ ΠΕΡΙΣΤΑΤΙΚΟ (2026-09-12, στην παραγωγή)
 * ────────────────────────────────────────────────────────────────────────────
 * Κάθε `/o/me/*` απαντούσε **500**. Όχι η σελίδα — **το ίδιο το middleware πετούσε**
 * (το απέδειξε η **απουσία** των `SECURITY_HEADERS`, που μπαίνουν στο τέλος του).
 *
 * Ο προσαρμογέας του Edge περνά **κάθε** κεφαλίδα `Location` μέσα από τον `NextURL`
 * **χωρίς base** — `next/dist/server/web/adapter.js:340`:
 *
 * ```js
 * const redirectURL = new NextURL(redirect, { forceLocale: false, headers, nextConfig });
 * ```
 *
 * και ο `parseURL` (`next-url.js:17`) είναι σκέτο `new URL(input, base)`. Εκτελεσμένο
 * στην **ίδια** έκδοση που τρέχει (Next 15.5.22):
 *
 * ```
 * new NextURL('/offers', …)                           → TypeError: Invalid URL
 * new NextURL('https://nestorconstruct.gr/offers', …) → OK
 * ```
 *
 * Το σχετικό `Location` είναι **σωστό κατά RFC 9110 §10.2.2** — η **μεταφορά** το
 * απαγορεύει, όχι το πρωτόκολλο. Upstream: **vercel/next.js#73989** (ανοιχτό).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ ΓΙΑΤΙ Η ΕΠΙΣΗΜΗ ΣΥΝΤΑΓΗ ΤΟΥ NEXT ΕΙΝΑΙ **ΛΑΘΟΣ ΕΔΩ**
 * ────────────────────────────────────────────────────────────────────────────
 * Το `nextjs.org/docs/messages/middleware-relative-urls` λέει *«use
 * `new URL('/dest', request.url)`»*. **Αυτό ξαναγεννά το περιστατικό του ADR-819.**
 * Στο `adapter.js:105` το `requestURL` χτίζεται από το `request.url` — πίσω από τον
 * proxy του Netcup host `0.0.0.0:3000` (`Dockerfile:21`) — και στη γραμμή **351** ο
 * adapter **ξαναγράφει** το `Location` **μόνο όταν τα hosts συμπίπτουν**. Με τη
 * συνταγή του Next συμπίπτουν ⇒ ο άνθρωπος καταλήγει ξανά στο `https://0.0.0.0:3000/…`.
 *
 * 🔑 Χτίζοντας πάνω στη **δηλωμένη** ταυτότητα, το host **διαφέρει** από το εσωτερικό
 * ⇒ ο adapter **δεν αγγίζει** ό,τι γράψαμε. Η ίδια πράξη μας σώζει **δύο** φορές.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΓΙΑΤΙ ΔΕΝ ΡΩΤΑΜΕ ΚΑΘΟΛΟΥ ΤΟΝ ΠΕΛΑΤΗ (αυστηρότερα από Django/Rails/ASP.NET)
 * ────────────────────────────────────────────────────────────────────────────
 * Εδώ το origin μπαίνει σε **κεφαλίδα ανακατεύθυνσης**: πλαστό host δεν είναι απλώς
 * λάθος σύνδεσμος — είναι **open redirect**. Οι μεγάλοι **επικυρώνουν** τον ισχυρισμό
 * του πελάτη με λίστα επιτρεπομένων (`ALLOWED_HOSTS` · `config.hosts` ·
 * `HostFiltering`). Ο {@link requestOrigin} πάει ένα βήμα παραπέρα: **η δηλωμένη
 * ταυτότητα προηγείται πάντα** (`NEXT_PUBLIC_APP_URL`, ψημένη στο build —
 * `docker-build.yml`), και η κεφαλίδα είναι εφεδρεία **με φρουρό**
 * ({@link isUnroutableHost}).
 *
 * ⚠️ **Και αν δεν ξέρουμε ποιοι είμαστε, ΑΡΝΟΥΜΑΣΤΕ** — `404`, ποτέ μαντεψιά. Μια
 * ανακατεύθυνση προς μαντεμένο origin είναι ακριβώς το σφάλμα που κλείνει αυτό το
 * αρχείο. Το `404` κρατά τον **σκοπό** του καλούντος (*«αυτή η διεύθυνση δεν
 * ανοίγει»*) χωρίς να ονομάσει σπίτι που δεν ξέρει.
 *
 * @param path σχετική διαδρομή προορισμού, **πάντα** με αρχικό `/`
 */
export function redirectFromMiddleware(
  request: RequestLike,
  path: string,
  status: RedirectStatus = 307,
): NextResponse {
  const origin = requestOrigin(request);
  if (origin === null) return new NextResponse(null, { status: 404 });

  return new NextResponse(null, {
    status,
    headers: { Location: joinOrigin(origin, path) },
  });
}
