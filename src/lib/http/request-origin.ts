/**
 * Hosts που **δεν είναι δημόσια ταυτότητα** — ακριβώς η κλάση του περιστατικού.
 *
 * ⚠️ Δεν είναι λίστα «κακών»· είναι λίστα **διευθύνσεων ακρόασης**. Καθεμία
 * σημαίνει κάτι σωστό *μέσα* στον διακομιστή και **τίποτα** έξω από αυτόν: το
 * `0.0.0.0` του θύματος δεν είναι το `0.0.0.0` μας.
 */
const UNROUTABLE_HOSTS: ReadonlySet<string> = new Set([
  '0.0.0.0',
  '127.0.0.1',
  'localhost',
  '::',
  '::1',
  '[::]',
  '[::1]',
]);

/**
 * *«Είναι αυτό το host δημόσια διεύθυνση;»* — μία ερώτηση, ένας κριτής.
 *
 * ⚠️ **Αφαιρεί τη θύρα πριν κρίνει**: το host που φτάνει είναι `0.0.0.0:3000`,
 * όχι `0.0.0.0`. Χωρίς αυτό ο έλεγχος θα ήταν **μονίμως πράσινος** — δηλαδή θα
 * άφηνε να περάσει ακριβώς το URL που τον γέννησε.
 */
export function isUnroutableHost(host: string): boolean {
  const trimmed = host.trim().toLowerCase();
  if (trimmed.length === 0) return true;

  // IPv6 σε αγκύλες (`[::1]:3000`) ⇒ κόψε μετά την αγκύλη· αλλιώς στο πρώτο `:`.
  const bare = trimmed.startsWith('[')
    ? trimmed.slice(0, trimmed.indexOf(']') + 1)
    : (trimmed.split(':')[0] ?? '');

  return UNROUTABLE_HOSTS.has(bare);
}

