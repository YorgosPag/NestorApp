/**
 * **Πόσο ισχυρά ξέρουμε αυτή την αξίωση** — από την πιο αδύναμη στην πιο ισχυρή.
 *
 * 🔴 **Η ΣΕΙΡΑ ΤΟΥ ΠΙΝΑΚΑ ΕΙΝΑΙ ΤΟ ΝΟΗΜΑ**, όχι σύμβαση παρουσίασης. Το
 * {@link LEGALITY_TIER_RANKS} την αντιγράφει σε αριθμούς και ένα anchor τα κρατά
 * κλειδωμένα — αλλιώς μια αναδιάταξη «για ευκολία» θα άλλαγε σιωπηλά κάθε σύγκριση.
 *
 * | # | Τιμή | Τι υπάρχει | Ποιος είναι υπόλογος |
 * |---|---|---|---|
 * | 0 | `self-declared` | ο άνθρωπος το **είπε** | **αυτός**, και κανείς άλλος |
 * | 1 | `document-provided` | υπάρχει **έγγραφο** στην κατοχή μας | ο υπογράφων — **που δεν τον ταυτοποιήσαμε** |
 * | 2 | `professional-attested` | **υπόλογος επαγγελματίας** υπέγραψε, και τον ξέρουμε | ο επαγγελματίας, με **αριθμό μητρώου** |
 * | 3 | `registry-verified` | ο αριθμός **βρέθηκε** στο μητρώο που τον εκδίδει | ο **φορέας** |
 *
 * 🔑 **Γιατί `document-provided` ΚΑΙ `professional-attested` και όχι ένα**: είναι η
 * **ίδια** βεβαίωση σε δύο στιγμές — *«ανέβηκε»* και *«κάποιος την άνοιξε»*. Η ADR-835
 * §7 ονόμασε την πρώτη (*«ανέβασε έγγραφο — κανείς δεν το άνοιξε»*), η SPEC-777 §24.5
 * τη δεύτερη (*«πιστοποιημένο από μηχανικό»* + **ημερομηνία**). Χωρίς τη διάκριση, ένα
 * ανοιχτό PDF θα φορούσε τη στολή της υπογραφής.
 *
 * ⚠️ **`professional-attested`, όχι `engineer-certified`** — γενίκευση **με μέτρηση**,
 * όχι καλλωπισμός: ο **Ν.5170/2025** (προδιαγραφές βραχυχρόνιας, ισχύς 1/10/2025)
 * απαιτεί **υπεύθυνη δήλωση ηλεκτρολόγου εγκαταστάτη** και **πιστοποιητικό μυοκτονίας /
 * απεντόμωσης** — υπόλογοι επαγγελματίες που **δεν είναι μηχανικοί**. Το όνομα
 * `engineer-certified` της SPEC-777 §24.5 είναι **αυτή ακριβώς η βαθμίδα** για το είδος
 * `building-identity`· **ποιος** ο επαγγελματίας το λέει το **είδος**, όχι η κλίμακα.
 */
export const LEGALITY_TIERS = [
  'self-declared',
  'document-provided',
  'professional-attested',
  'registry-verified',
] as const;

export type LegalityTier = (typeof LEGALITY_TIERS)[number];

/**
 * **Η σειρά ως αριθμός** — η **μία** πηγή κάθε σύγκρισης.
 *
 * 🔑 **`Record` πάνω σε κλειστό σύνολο**: πέμπτη βαθμίδα **δεν μεταγλωττίζεται** μέχρι
 * κάποιος να απαντήσει *«και αυτή, πιο πάνω ή πιο κάτω από ποια;»*. Ένα `indexOf` πάνω
 * στον πίνακα θα ήταν πιο σύντομο και θα επέστρεφε **`-1`** για άγνωστη τιμή — δηλαδή
 * «ασθενέστερη από την ασθενέστερη», μια απάντηση που **κανείς δεν έδωσε**.
 */
export const LEGALITY_TIER_RANKS: Readonly<Record<LegalityTier, number>> = {
  'self-declared': 0,
  'document-provided': 1,
  'professional-attested': 2,
  'registry-verified': 3,
};

/**
 * **Πόσο ψηλά;** — η μία πόρτα προς τη σειρά.
 *
 * Υπάρχει ώστε κανείς να μη γράψει `LEGALITY_TIER_RANKS[x]` με ωμό κλειδί: ο τύπος
 * κάνει **αδύνατο** να ζητηθεί σειρά για βαθμίδα που δεν υπάρχει. Ίδια κίνηση με το
 * `statutoryTermLimitFor` του ADR-832.
 */
export function legalityTierRank(tier: LegalityTier): number {
  return LEGALITY_TIER_RANKS[tier];
}

/**
 * **Η ισχυρότερη από τις δύο.** Ισοπαλία ⇒ η πρώτη (είναι η ίδια τιμή).
 *
 * ⚠️ **Χρησιμοποιείται όταν ΔΥΟ αξιώσεις του ΙΔΙΟΥ είδους καλύπτουν τον ίδιο χώρο** —
 * π.χ. ο κάτοχος δήλωσε ΑΜΑ **και** εμείς τον επαληθεύσαμε. Η προβολή δείχνει **μία**
 * γραμμή, και η γραμμή οφείλει να λέει ό,τι **ισχυρότερο** ξέρουμε.
 */
export function strongerTier(a: LegalityTier, b: LegalityTier): LegalityTier {
  return legalityTierRank(b) > legalityTierRank(a) ? b : a;
}

/**
 * **Φτάνει αυτή η βαθμίδα το κατώφλι;**
 *
 * 🔴 **`>=`, και το ίσον είναι ΜΕΣΑ.** Το κατώφλι ονομάζει το **ελάχιστο αποδεκτό**·
 * ένα `>` θα απέρριπτε **ακριβώς** τη βαθμίδα που ζητήθηκε. Η παγίδα είναι μετρημένη
 * στο έργο (ADR-835 Φ3, φρουρός με αυστηρή ανισότητα σε **δύο** αρχεία) και έχει δικό
 * της anchor εδώ.
 */
export function isAtLeastTier(tier: LegalityTier, floor: LegalityTier): boolean {
  return legalityTierRank(tier) >= legalityTierRank(floor);
}
