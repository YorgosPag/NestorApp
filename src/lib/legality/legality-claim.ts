/**
 * **Μία αξίωση νομιμότητας** — *αυτό* βεβαιώνεται, για *αυτούς* τους χώρους, *έτσι* το
 * ξέρουμε, *αυτός* το λέει, *τότε* το είπε.
 *
 * 🔴 **ΔΕΝ ΥΠΑΡΧΕΙ ΠΕΔΙΟ «ΕΓΓΡΑΦΟ», ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ.** Η Φ4 δεν αναρτά και δεν
 * διαβάζει έγγραφα (ADR-838 §9). Ένα `documentUrl` εδώ θα ήταν η πόρτα από την οποία
 * μπαίνει η δημοσίευση εγγράφου **χωρίς κανείς να την αποφασίσει** — και το §4.5 του
 * ADR-835 έχει ήδη μετρήσει τι κοστίζει μια τέτοια σιωπηλή πόρτα.
 */
export interface LegalityClaim {
  readonly kind: LegalityClaimKind;
  /**
   * **Οι χώροι που καλύπτει** — ΠΑΝΤΑ σύνολο, ποτέ ένας.
   *
   * ⚠️ Κενό σύνολο = **αξίωση που δεν καλύπτει τίποτα**, δηλαδή δυσμορφία — δες
   * {@link claimSubjectIsWellFormed}. **Δεν** είναι «ολόκληρο»: το «ολόκληρο»
   * γράφεται `[{ propertyId, spaceId: null }]`, και η διαφορά τους είναι όλη η φάση.
   */
  readonly subject: readonly SpaceRef[];
  readonly tier: LegalityTier;
  /**
   * Ο αριθμός/κωδικός της αξίωσης (ΑΜΑ, ενεργειακή κατηγορία). `null` = **δεν δόθηκε**.
   *
   * ⚠️ **`null` ΔΕΝ σημαίνει «δεν υπάρχει αξίωση»** — σημαίνει ότι η αξίωση υπάρχει
   * χωρίς αναγνωριστικό (π.χ. `self-declared` *«είναι τακτοποιημένο»*). Η **απουσία**
   * αξίωσης εκφράζεται με **απουσία στοιχείου**, ποτέ με `null` πεδίο.
   */
  readonly value: string | null;
  /**
   * **ΠΟΙΟΣ το βεβαιώνει** — ποτέ ανώνυμο πάνω από `self-declared`.
   *
   * `null` επιτρέπεται **μόνο** στο `self-declared` (ο δηλών **είναι** ο κάτοχος, και
   * η αναγραφή του ονόματός του θα ήταν **ταυτότητα προσώπου** σε δημοσιεύσιμο πεδίο).
   * Ο φρουρός ζει στο {@link claimAuthorityIsWellFormed}.
   */
  readonly authority: string | null;
  /** ISO — **πότε** ειπώθηκε. */
  readonly assertedAt: string;
  /**
   * ISO — ως πότε ισχύει. `null` = **δεν λήγει** ή **δεν το ξέρουμε**.
   *
   * 🔴 Τα δύο **δεν** διακρίνονται εδώ επίτηδες, και η διάκριση ζει στο
   * {@link LegalityClaimKindSpec.expires}: αν το είδος **δεν λήγει**, το `null` είναι
   * η αλήθεια· αν **λήγει**, ένα `null` είναι **δηλωμένη άγνοια** και η απάντηση το
   * λέει με **δικό της όνομα**, αντί να υποθέσει «ισχύει».
   */
  readonly validUntil: string | null;
}

