/**
 * **Είναι το υποκείμενο συμβατό με το είδος;**
 *
 * Απορρίπτει: **κενό** σύνολο · *«ταυτότητα κτιρίου **του δωματίου Α**»* (είδος
 * `'whole-property'` με ονομασμένο χώρο).
 */
export function claimSubjectIsWellFormed(claim: LegalityClaim): boolean {
  if (claim.subject.length === 0) return false;
  if (legalityKindSpec(claim.kind).subjectScope === 'space-set') return true;
  return claim.subject.every((space) => space.spaceId === null);
}

/**
 * **Ξέρουμε ποιος το λέει, όταν ο ισχυρισμός το απαιτεί;**
 *
 * 🔴 Πάνω από `self-declared` ένα `authority: null` θα ήταν *«κάποιος πιστοποίησε, δεν
 * θυμόμαστε ποιος»* — δηλαδή **ετικέτα χωρίς προέλευση**, που η SPEC-777 §24.3
 * ονόμασε **ισχυρισμό** και απέρριψε ρητά.
 */
export function claimAuthorityIsWellFormed(claim: LegalityClaim): boolean {
  return claim.tier === 'self-declared' || claim.authority !== null;
}

/**
 * **Καλύπτει αυτή η αξίωση αυτούς τους χώρους;** — ασύμμετρα, δες `spaceSetCovers`.
 */
export function claimCovers(
  claim: LegalityClaim,
  spaces: readonly SpaceRef[],
): boolean {
  return spaceSetCovers(claim.subject, spaces);
}
