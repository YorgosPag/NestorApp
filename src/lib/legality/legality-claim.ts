/**
 * @fileoverview **Η ΑΞΙΩΣΗ ΝΟΜΙΜΟΤΗΤΑΣ** — τι βεβαιώνεται, για ποιους χώρους, με ποια πηγή.
 * @related ADR-838 §4.3/§4.4 · ADR-777 §7 (Α17) · ADR-835 §7 · §4.12 ·
 *   lib/spaces/space-ref.ts · lib/legality/legality-tier.ts
 * @module lib/legality/legality-claim
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Η ΑΠΑΝΤΗΣΗ ΣΤΟ ΕΡΩΤΗΜΑ ΤΗΣ ΦΑΣΗΣ: **ΤΙΝΟΣ ΙΔΙΟΤΗΤΑ ΕΙΝΑΙ Η ΝΟΜΙΜΟΤΗΤΑ;**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ερώτημα ήταν *«του **ΑΚΙΝΗΤΟΥ**, της **ΔΙΑΘΕΣΗΣ**, ή της **ΚΑΤΑΧΩΡΙΣΗΣ**;»* — και
 * τα τρία δίνουν μοντέλο που **σπάει σε μετρημένη περίπτωση**:
 *
 * | Αν το υποκείμενο είναι… | Τι γίνεται **ανέκφραστο** | Μέτρηση |
 * |---|---|---|
 * | **ακίνητο** | οι **τρεις ΑΜΑ** ενός τριαριού (ΑΑΔΕ, ADR-835 §4.12) | το `StayInventoryUnit.covers` **ήδη** κρατά διακριτά σύνολα |
 * | **καταχώριση** | η βεβαίωση μηχανικού ζητιέται **τρεις φορές** για **ένα** κτίριο | άρθρο 83 ν.4495/2017: ανά **δικαιοπραξία ακινήτου**, όχι ανά δωμάτιο |
 * | **διάθεση** | η **ίδια** ταυτότητα κτιρίου γίνεται **δύο αλήθειες** σε ακίνητο που είναι και προς πώληση και προς εκμίσθωση | το `offerKinds` είναι **πίνακας**, όχι μονή τιμή |
 *
 * ✅ **ΑΠΟΦΑΣΗ: ΚΑΝΕΝΑ ΑΠΟ ΤΑ ΤΡΙΑ — ΤΟ ΥΠΟΚΕΙΜΕΝΟ ΕΙΝΑΙ ΣΥΝΟΛΟ ΧΩΡΩΝ.**
 *
 * Και τα τρία υποψήφια είναι **εκφυλισμοί** του:
 *
 * - **ακίνητο** = `[{ propertyId, spaceId: null }]` — το **πλήρες** σύνολο
 * - **καταχώριση** = το `covers` της (τρεις καταχωρίσεις ⇒ τρία σύνολα ⇒ τρεις ΑΜΑ)
 * - **διάθεση** = 🔴 **δεν είναι υποκείμενο — είναι ο ΕΡΩΤΩΝ.** Ποιες αξιώσεις
 *   *σηκώνει* μια διάθεση ζει στο `legality-offer-matrix.ts`, ξεχωριστά. Η σύγχυση
 *   «ποιος ρωτά» με «για ποιον ισχύει» είναι ακριβώς πώς γεννιέται δεύτερη αλήθεια.
 *
 * 🏆 **ΚΑΙ ΤΟ ΚΕΡΔΟΣ ΕΙΝΑΙ ΟΤΙ Η ΜΗΧΑΝΗ ΥΠΑΡΧΕΙ ΗΔΗ**: το «καλύπτει;» είναι ο κανόνας
 * χώρου του ADR-835 §4.12, γραμμένος και δοκιμασμένος στη Φ2 και εξαγμένος στο
 * `lib/spaces/space-ref.ts`. **Καμία δεύτερη μηχανή** (ADR-749) — και σύνολο **ενός**
 * στοιχείου συμπεριφέρεται όπως θα συμπεριφερόταν ένα σκέτο `propertyId`, άρα
 * **κανένας υπάρχων καταναλωτής δεν σπάει**.
 *
 * **Layering**: leaf — καθαροί τύποι + καθαρές συναρτήσεις, μηδέν I/O, μηδέν ρολόι.
 */

