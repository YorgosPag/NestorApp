/**
 * **Το είδος της αξίωσης** — *τι* βεβαιώνεται, ποτέ *πόσο ισχυρά*.
 *
 * 🔑 Ο δεύτερος άξονας της συμφιλίωσης του {@link LegalityTier}: οι καταστάσεις **2**
 * και **3** της SPEC-777 §24.5 είχαν την **ίδια** προέλευση και διέφεραν **εδώ**.
 */
export const LEGALITY_CLAIM_KINDS = [
  /** **ΑΜΑ** — Αριθμός Μητρώου Ακινήτου βραχυχρόνιας διαμονής (ΑΑΔΕ). */
  'short-stay-registry',
  /** **Ηλεκτρονική Ταυτότητα Κτιρίου** ή βεβαίωση μηχανικού (άρθρο 83 ν.4495/2017). */
  'building-identity',
  /** **Τακτοποίηση** αυθαιρέτου (ν.4495/2017) — 🔴 **θετικό**, ποτέ προειδοποίηση. */
  'arbitrary-settlement',
  /** **ΠΕΑ** — Πιστοποιητικό Ενεργειακής Απόδοσης (ν.4122/2013). */
  'energy-performance',
] as const;

export type LegalityClaimKind = (typeof LEGALITY_CLAIM_KINDS)[number];

// =============================================================================
// 2. ΟΙ ΤΕΣΣΕΡΙΣ ΙΔΙΟΤΗΤΕΣ ΤΟΥ ΕΙΔΟΥΣ — καθεμιά με ΠΗΓΗ
// =============================================================================

/**
 * **Πόσο ψιλά μπορεί να δείξει η αξίωση;**
 *
 * - `'space-set'`      — μπορεί να ονομάσει **διακριτό χώρο** (ένα δωμάτιο)
 * - `'whole-property'` — **μόνο** ολόκληρο το ακίνητο
 *
 * 🔴 Δεν είναι διακοσμητικό: μια «ταυτότητα κτιρίου **του δωματίου Α**» είναι
 * **ανύπαρκτο έγγραφο**, και ο {@link claimSubjectIsWellFormed} το **απορρίπτει**.
 * Χωρίς αυτό, η απόφαση «το υποκείμενο είναι σύνολο χώρων» θα ήταν σωστή **και
 * ασύδοτη**.
 */
export type LegalitySubjectScope = 'space-set' | 'whole-property';

/**
 * **Εμποδίζει η απουσία της αξίωσης τη δημοσίευση;**
 *
 * 🔴 **ΕΙΝΑΙ ΙΔΙΟΤΗΤΑ ΤΟΥ ΕΙΔΟΥΣ, ΟΧΙ ΚΑΘΟΛΙΚΟΣ ΚΑΝΟΝΑΣ — και ένα `boolean` κάπου θα
 * είχε κάνει το ένα από τα δύο ΨΕΥΔΕΣ:**
 *
 * | Είδος | Κανόνας | Ποιος το λέει |
 * |---|---|---|
 * | `building-identity` | **`'disclosed-only'`** — *«επιλογή, ποτέ προϋπόθεση»* | **ADR-777 §7 #4**, απόφαση Giorgio 2026-08-08 |
 * | `short-stay-registry` | **`'blocks-publication'`** — η πλατφόρμα **οφείλει** να μη δημοσιεύσει καταχώριση χωρίς αριθμό | **Καν. (ΕΕ) 2024/1028**, εφαρμογή από **20/05/2026** |
 *
 * ⚠️ **ΤΟ `'blocks-publication'` ΕΙΝΑΙ ΛΕΞΙΛΟΓΙΟ, ΟΧΙ ΕΝΕΡΓΗ ΑΡΝΗΣΗ ΣΗΜΕΡΑ.** Η Φ4
 * **δηλώνει** τον κανόνα με την πηγή του και τον κάνει **ερωτήσιμο**
 * ({@link publicationBlockingKinds})· η **σύνδεσή** του με τον γραφέα της προβολής
 * αλλάζει **τι φεύγει στον κόσμο** για υπάρχουσες αγγελίες — απόφαση δημοσιοποίησης,
 * δηλαδή του Giorgio, όχι παρενέργεια αυτού του αρχείου (ADR-838 §9).
 */
export type LegalityPublicationRule = 'blocks-publication' | 'disclosed-only';

/**
 * **Δημοσιεύεται η ΤΙΜΗ της αξίωσης, ή μόνο η βαθμίδα της;**
 *
 * 🔴 **ΕΝΑ ΚΑΘΟΛΙΚΟ «ΠΟΤΕ ΤΗΝ ΤΙΜΗ» ΘΑ ΕΙΧΕ ΠΑΡΑΒΕΙ ΤΟΝ ΝΟΜΟ.** Ο **ΑΜΑ**
 * *«αναγράφεται υποχρεωτικά σε εμφανές σημείο κατά την ανάρτηση στις ψηφιακές
 * πλατφόρμες και σε κάθε μέσο προβολής»* — η **απόκρυψή** του είναι η παράβαση, με
 * πρόστιμο που ξεκινά από **5.000 €**. Το ίδιο και η **ενεργειακή κατηγορία** (άρθρο
 * 12 ν.4122/2013: σε **κάθε εμπορική αγγελία**).
 *
 * 🔑 **Η αρχή του ADR-835 §7 μένει ακέραιη**: *«δημοσιεύεται η ΒΑΘΜΙΔΑ, ποτέ το
 * ΕΓΓΡΑΦΟ»*. Ένας **αριθμός μητρώου δεν είναι έγγραφο** — είναι δημόσιος δείκτης προς
 * μητρώο, ίδια κλάση με το `authorship` (*«κλάση, όχι ταυτότητα»*). Το `'withheld'`
 * φυλάει τα **έγγραφα**· το `'published'` υπακούει στον νόμο που **απαιτεί** τον δείκτη.
 */
export type LegalityValueDisclosure = 'published' | 'withheld';

/**
 * **Ό,τι ισχύει για ΚΑΘΕ αξίωση αυτού του είδους** — τέσσερις απαντήσεις, μία πηγή.
 *
 * ⚠️ **Το `statute` ΔΕΝ περνά από i18n, και είναι εξαίρεση με λόγο** (N.11): είναι
 * **παραπομπή σε νομοθεσία**, όχι κείμενο διεπαφής — *«άρθρο 83 ν. 4495/2017»* είναι
 * το ίδιο σε κάθε γλώσσα, και μια «μετάφρασή» του θα παρέπεμπε σε **ανύπαρκτη**
 * διάταξη. Ίδιο ιδίωμα, κατά λέξη, με το `StatutoryTermLimit.authority` (ADR-832).
 */
export interface LegalityClaimKindSpec {
  readonly subjectScope: LegalitySubjectScope;
  readonly publication: LegalityPublicationRule;
  readonly valueDisclosure: LegalityValueDisclosure;
  /**
   * **Λήγει;** — `true` όταν το ίδιο το έγγραφο έχει διάρκεια ισχύος.
   *
   * 🔴 Δεν είναι υποθετικό: η **βεβαίωση μηχανικού** του άρθρου 83 ισχύει **δύο
   * μήνες** — δηλαδή μια αξίωση περασμένης ισχύος **δεν είναι** «καμία αξίωση» και
   * **δεν είναι** έγκυρη αξίωση. Είναι **τρίτη κατάσταση με όνομα**, ίδιος κανόνας με
   * το `conditional` του ADR-835 §4.7 και το κενό διάστημα του §17.
   */
  readonly expires: boolean;
  /** Η διάταξη, αυτολεξεί όπως παραπέμπεται. Δες το σχόλιο του τύπου. */
  readonly statute: string;
}

/**
 * **Ποιοι κανόνες ισχύουν για κάθε είδος.**
 *
 * 🔑 **`Record` πάνω σε κλειστό σύνολο** — πέμπτο είδος **δεν μεταγλωττίζεται** μέχρι
 * κάποιος να απαντήσει και τα τέσσερα ερωτήματα **με πηγή**. Ένα `Partial` ή ένα
 * `?? DEFAULT` θα σήμαινε σιωπηλά «ολόκληρο ακίνητο, δεν μπλοκάρει, μην το δείξεις,
 * δεν λήγει» — τέσσερις αποφάσεις που **κανείς δεν πήρε**, για κάτι που κρίνεται με
 * πρόστιμο.
 */
export const LEGALITY_CLAIM_KIND_SPECS: Readonly<
  Record<LegalityClaimKind, LegalityClaimKindSpec>
> = {
  // 🔑 Το ΜΟΝΟ είδος με `'space-set'`: η ΑΑΔΕ απαιτεί «ξεχωριστό ΑΜΑ **για το σύνολο**
  //    και **για κάθε διακριτό χώρο**» ⇒ τρεις χώροι, τρεις ΑΜΑ (ADR-835 §4.12).
  'short-stay-registry': {
    subjectScope: 'space-set',
    publication: 'blocks-publication',
    valueDisclosure: 'published',
    expires: false,
    statute: 'άρθρο 46 Ν.4179/2013 · Καν. (ΕΕ) 2024/1028',
  },
  // ⚠️ `expires: true` — η βεβαίωση του άρθρου 83 ισχύει **δύο μήνες**.
  'building-identity': {
    subjectScope: 'whole-property',
    publication: 'disclosed-only',
    valueDisclosure: 'withheld',
    expires: true,
    statute: 'άρθρο 83 Ν.4495/2017',
  },
  // 🔴 **ΠΟΤΕ ως προειδοποίηση** (SPEC-777 §24.4): η νόμιμα τακτοποιημένη αυθαιρεσία
  //    είναι η **κανονική** κατάσταση του ελληνικού αποθέματος. Οθόνη που τη δείχνει
  //    ως ελάττωμα λέει ψέματα για την αγορά **και** σπρώχνει τους κατόχους να μη
  //    δηλώνουν — σκοτώνοντας το ίδιο το δεδομένο που θέλουμε.
  'arbitrary-settlement': {
    subjectScope: 'whole-property',
    publication: 'disclosed-only',
    valueDisclosure: 'withheld',
    expires: false,
    statute: 'Ν.4495/2017',
  },
  // 🔑 `'published'`: το άρθρο 12 απαιτεί την **ενεργειακή κατηγορία** σε **κάθε**
  //    εμπορική αγγελία. Δημοσιεύεται η **κατηγορία** (η τιμή), όχι το πιστοποιητικό.
  'energy-performance': {
    subjectScope: 'whole-property',
    publication: 'disclosed-only',
    valueDisclosure: 'published',
    expires: true,
    statute: 'άρθρο 12 Ν.4122/2013',
  },
};

/**
 * **Οι κανόνες αυτού του είδους** — η μία πόρτα.
 *
 * Υπάρχει ώστε κανείς να μη γράψει `LEGALITY_CLAIM_KIND_SPECS[x]` με ωμό κλειδί: ο
 * τύπος κάνει **αδύνατο** να ζητηθούν κανόνες για είδος που δεν υπάρχει.
 */
export function legalityKindSpec(kind: LegalityClaimKind): LegalityClaimKindSpec {
  return LEGALITY_CLAIM_KIND_SPECS[kind];
}

/**
 * **Ποια είδη εμποδίζουν τη δημοσίευση όταν λείπουν.** **Παράγεται** από τον πίνακα —
 * μια δεύτερη γραμμένη λίστα θα ήταν ελεύθερη να αποκλίνει σιωπηλά.
 */
export function publicationBlockingKinds(): readonly LegalityClaimKind[] {
  return LEGALITY_CLAIM_KINDS.filter(
    (kind) => LEGALITY_CLAIM_KIND_SPECS[kind].publication === 'blocks-publication'
  );
}

