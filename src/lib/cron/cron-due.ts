/**
 * =============================================================================
 * CRON DUE — «οφείλεται αυτή η εργασία τώρα;» (ADR-739)
 * =============================================================================
 *
 * **Καθαρή συνάρτηση, μηδέν εξαρτήσεις πλην του `croner`.** Χωρίς Firestore, χωρίς
 * Sentry, χωρίς δίκτυο, χωρίς `new Date()` εσωτερικά — η στιγμή δίνεται πάντα ως όρισμα.
 *
 * Ζει χωριστά από τον dispatcher επίτηδες: είναι η μόνη λογική εδώ που μπορεί να είναι
 * **λάθος με τρόπο που δεν φαίνεται**. Ένα off-by-one στο παράθυρο του λεπτού σημαίνει
 * ότι μια εργασία δεν τρέχει ποτέ στην ώρα της· ένα λάθος στη ζώνη ώρας τη μετακινεί
 * τρεις ώρες. Απομονωμένη, δοκιμάζεται εξαντλητικά με σταθερές ημερομηνίες.
 *
 * @module lib/cron/cron-due
 * @see ADR-739
 */

import { Cron } from 'croner';

/**
 * Πόσο πίσω κοιτά το catch-up (ώρες).
 *
 * 25 ώρες: λίγο πάνω από τον ημερήσιο κύκλο, ώστε μια χαμένη εκτέλεση να προλαβαίνει να
 * καλυφθεί. Μεγαλύτερο παράθυρο **δεν** θα έτρεχε την εργασία περισσότερες φορές (ο
 * έλεγχος είναι «η προηγούμενη στιγμή είναι μετά την τελευταία επιτυχία»), αλλά θα
 * ξυπνούσε εργασίες που έμειναν σκόπιμα σταματημένες για συντήρηση.
 */
export const CATCHUP_GRACE_HOURS = 25;

/** Γιατί κρίθηκε οφειλόμενη — μόνο για logging/διάγνωση. */
export type CronDueReason = 'scheduled' | 'catch-up';

export interface CronDueVerdict {
  readonly due: boolean;
  readonly reason: CronDueReason | null;
}

const NOT_DUE: CronDueVerdict = { due: false, reason: null };

/**
 * Η πρώτη προγραμματισμένη στιγμή **αυστηρά μετά** το `after`, ή `null`.
 *
 * ⚠️ Χρησιμοποιεί `nextRuns(1, …)` και **όχι** `previousRun()`. Το `previousRun()` του
 * croner επιστρέφει την τελευταία στιγμή που **εκτέλεσε το ίδιο το αντικείμενο** — για
 * ένα `Cron` που δημιουργήθηκε μόνο για υπολογισμό επιστρέφει πάντα `null`. Είναι
 * ακριβώς το είδος API που «δουλεύει» σιωπηλά λάθος: καμία εξαίρεση, απλώς καμία
 * εργασία δεν θα κρινόταν ποτέ οφειλόμενη. (Επαληθευμένο με το croner 10.0.1.)
 */
function firstRunAfter(schedule: string, timezone: string, after: Date): Date | null {
  const [next] = new Cron(schedule, { timezone }).nextRuns(1, after);
  return next ?? null;
}

/**
 * Αποφασίζει αν μια εργασία οφείλεται στο τρέχον λεπτό.
 *
 * Δύο ανεξάρτητοι λόγοι:
 *
 * 1. **`scheduled`** — μια προγραμματισμένη στιγμή πέφτει **μέσα** στο τρέχον λεπτό.
 * 2. **`catch-up`** — υπάρχει στιγμή που πέρασε **μετά** την τελευταία επιτυχία και μέσα
 *    στο παράθυρο χάριτος (π.χ. ο container έκανε επανεκκίνηση στις 04:00). Χωρίς αυτό,
 *    μια επανεκκίνηση ενός λεπτού κοστίζει ένα ολόκληρο ημερήσιο αντίγραφο ασφαλείας —
 *    και κανείς δεν το μαθαίνει μέχρι να το χρειαστεί.
 *
 * Ο έλεγχος του catch-up είναι **μία** ερώτηση: «υπάρχει έστω μία στιγμή μετά το
 * σημείο εκκίνησης του παραθύρου;». Δεν χρειάζεται απαρίθμηση των χαμένων στιγμών,
 * επειδή η απάντηση είναι ούτως ή άλλως «τρέξε **μία** φορά» — μια εργασία που έχασε
 * τρεις μέρες δεν πρέπει να τρέξει τρεις φορές.
 *
 * @param tick Η στιγμή του χτυπήματος. Τα δευτερόλεπτα αγνοούνται· ανάλυση = λεπτό.
 * @param lastSuccessAt ISO της τελευταίας **επιτυχούς** ολοκλήρωσης, ή `null`.
 */
export function isJobDue(
  schedule: string,
  timezone: string,
  tick: Date,
  lastSuccessAt: string | null
): CronDueVerdict {
  const startOfMinute = new Date(tick.getTime());
  startOfMinute.setSeconds(0, 0);
  // Ημιάνοιχτο διάστημα [startOfMinute, nextMinute). Ρητά **αποκλειστικό** άνω άκρο
  // αντί για `+ 59_999`: το δεύτερο θα ήταν σωστό μόνο επειδή οι στιγμές cron πέφτουν
  // πάντα σε ακέραιο λεπτό — δηλαδή σωστό κατά σύμπτωση, και αόρατα λάθος αν κάποτε
  // μπει έκφραση 6 πεδίων με δευτερόλεπτα.
  const nextMinute = new Date(startOfMinute.getTime() + 60_000);

  // ── 1. Κανονική εκτέλεση ──
  // Από 1ms πριν την αρχή του λεπτού: το `nextRuns` είναι **αυστηρά μετά**, οπότε μια
  // στιγμή ακριβώς στο :00.000 θα χανόταν αν ρωτούσαμε από την ίδια την αρχή. Αυτό το
  // off-by-one θα σήμαινε ότι καμία εργασία δεν τρέχει ποτέ στην ώρα της — θα
  // εμφανιζόταν μόνο ως μόνιμο catch-up ένα λεπτό αργότερα.
  const inThisMinute = firstRunAfter(schedule, timezone, new Date(startOfMinute.getTime() - 1));
  if (inThisMinute && inThisMinute.getTime() < nextMinute.getTime()) {
    return { due: true, reason: 'scheduled' };
  }

  // ── 2. Catch-up ──
  const graceStartMs = tick.getTime() - CATCHUP_GRACE_HOURS * 3_600_000;
  const lastSuccessMs = lastSuccessAt ? Date.parse(lastSuccessAt) : Number.NaN;

  // Το παράθυρο ξεκινά από το **πιο πρόσφατο** από τα δύο: δεν ξανατρέχουμε ό,τι ήδη
  // πέτυχε, ούτε ξυπνάμε εργασίες σταματημένες για μέρες («καταιγίδα επανεκκίνησης»).
  const windowStartMs = Number.isFinite(lastSuccessMs)
    ? Math.max(lastSuccessMs, graceStartMs)
    : graceStartMs;

  // Το `firstRunAfter` μπορεί να δείξει και στο **μέλλον** (καμία χαμένη στιγμή, η
  // επόμενη είναι αύριο) — γι' αυτό χρειάζεται το άνω όριο.
  //
  // ℹ️ Το `<` έναντι `<=` είναι εδώ **αποδείξιμα ισοδύναμο**, όχι ακάλυπτο: για να
  // ίσχυε `missed === startOfMinute` θα έπρεπε να υπάρχει στιγμή ακριβώς στην αρχή
  // αυτού του λεπτού — οπότε το σκέλος 1 θα είχε ήδη επιστρέψει `scheduled` και αυτή
  // η γραμμή δεν εκτελείται. Καταγράφεται ρητά ώστε ο επόμενος να μην ψάχνει το test
  // που «λείπει» (ADR-739 §Μετάλλαξη: 32 σκοτωμένες, 1 ισοδύναμη).
  const missed = firstRunAfter(schedule, timezone, new Date(windowStartMs));
  if (missed && missed.getTime() < startOfMinute.getTime()) {
    return { due: true, reason: 'catch-up' };
  }

  return NOT_DUE;
}
