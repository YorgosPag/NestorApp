/**
 * =============================================================================
 * JOB: demand-interest-announce — **ΠΟΙΟΣ ΤΡΑΒΑ ΤΗ ΣΚΑΝΔΑΛΗ** (ADR-777 §8.23)
 * =============================================================================
 *
 * Ο ειδοποιητής (`announceInterestToOwners`) ήταν γραμμένος, δοκιμασμένος και
 * idempotent από τις 2026-08-12 — και είχε **μηδέν καταναλωτές**. Δηλαδή η επιλογή
 * του Giorgio («email που τον ξυπνά») είχε *προετοιμαστεί*, όχι *υλοποιηθεί*: ένας
 * ακόμη αδρανής φρουρός (ADR-749 §5). Αυτό το αρχείο είναι η σκανδάλη.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ **ΕΔΩ** ΚΑΙ ΟΧΙ ΣΕ FIRESTORE TRIGGER — μετρημένο, όχι προτιμώμενο
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το handoff πρότεινε trigger στο `functions/` που θα χτυπούσε webhook στο Next.
 * Η μέτρηση έδειξε ότι αυτό θα ήταν **νέα υποδομή για πρόβλημα ήδη λυμένο**:
 *
 * | Τι χρειαζόταν | Τι υπήρχε ήδη (ADR-740) |
 * |---|---|
 * | περιοδική εκτέλεση | `CRON_SCHEDULE` + `dispatchCronTick`, 10 εργασίες σε παραγωγή |
 * | ταυτότητα μηχανής→μηχανής | `verifyCronAuthorization` (`CRON_SECRET`) — **SSoT, υπάρχει** |
 * | «μην τρέξεις δύο φορές μαζί» | `acquireCronLease` ανά slug |
 * | συναγερμός όταν **δεν** τρέξει | `runWithMonitor` → Sentry, από τα **ίδια** πεδία |
 * | επανάληψη μετά από restart | catch-up του dispatcher (`CATCHUP_GRACE_HOURS`) |
 *
 * Ο δρόμος του trigger θα απαιτούσε **deploy του `functions/`**, **νέο σύνορο
 * ταυτότητας** και **δεύτερο** μονοπάτι εκτέλεσης — για να δώσει ό,τι δίνει ήδη μια
 * γραμμή στο `CRON_SCHEDULE`. Και το `functions/` δεν εισάγει τίποτα από το `src/`
 * (μετρημένο: **0** εισαγωγές), άρα κάθε τι εκεί ζει μακριά από τη μηχανή που κρίνει.
 *
 * ⚠️ **Το «γρήγορα» ΔΕΝ θυσιάστηκε — μετακινήθηκε στο σωστό στρώμα.** Η σάρωση
 * τρέχει **ωριαία**· *πότε φτάνει στον άνθρωπο* το αποφασίζει η **δική του**
 * ρύθμιση (`emailFrequency`, `quietHours`) στον orchestrator. Ο ρυθμός του
 * σαρωτή είναι **ανώτατο όριο φρεσκάδας**, όχι πολιτική παράδοσης.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΤΡΙΑ ΑΝΕΞΑΡΤΗΤΑ ΣΤΡΩΜΑΤΑ ΣΥΓΚΡΑΤΗΣΗΣ — εδώ ξεπερνάμε τους μεγάλους
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Οι πλατφόρμες ειδοποιήσεων (Courier · Braze · Knock · Novu · SuprSend) έχουν
 * **δύο** μοχλούς: παράθυρο χρόνου (batching/digest) και ώρες ησυχίας. Και τα δύο
 * απαντούν στο ερώτημα «**πόσο συχνά** διακόπτω;».
 *
 * Εμείς έχουμε **τρία**, και το τρίτο απαντά **άλλο** ερώτημα:
 *
 * 1. **Ζώνη** (`ANNOUNCEMENT_BANDS = 1·3·8·20·50`) — «**αξίζει καν** διακοπή;»
 *    Δύο άνθρωποι που ψάχνουν σήμερα δεν είναι δύο ειδήσεις· είναι **μία** («σε
 *    ψάχνουν»). Η δεύτερη είδηση γεννιέται στους **τρεις**. Αυτό είναι συνάθροιση
 *    κατά **σημασία**, όχι κατά ρολόι — και είναι δομικά ανώτερη, γιατί ένα
 *    παράθυρο 15 λεπτών εξακολουθεί να στέλνει 20 μηνύματα σε 20 ώρες για κάτι
 *    που δεν άλλαξε ουσιαστικά.
 * 2. **Ρυθμός** (`emailFrequency`) — «πόσο συχνά **παραδίδω**;»
 * 3. **Ησυχία** (`quietHours`) — «**πότε επιτρέπεται** να διακόψω;»
 *
 * Τα (2) και (3) ζουν στον orchestrator, γιατί αφορούν **κάθε** ειδοποίηση της
 * εφαρμογής — όχι μόνο αυτή. Το (1) ζει στο `lib/demand/demand-announcement.ts`.
 *
 * ⚠️ **Και τα τρία είναι ανεξάρτητα, ΠΟΤΕ ένα με «ή».** Ένα κατέβασμα του ενός
 * δεν πρέπει να ανοίγει τον δρόμο στα άλλα δύο.
 *
 * @module lib/cron/jobs/demand-interest-announce
 * @see ADR-777 §8.23 — «η ειδοποίηση φτάνει σε άνθρωπο»
 * @see ADR-740 — το πρόγραμμα ζει στο src/config/cron-schedule.ts
 */

import 'server-only';

import { getAdminFirestore } from '@/lib/firebaseAdmin';
import {
  announceInterestToOwners,
  type AnnouncementReport,
} from '@/services/demand/interest-notifier.service';
import type { CronJobResult } from '@/types/cron-schedule';

/**
 * Η αναφορά ως μετρήσιμα μεγέθη.
 *
 * ⚠️ **Κάθε κάδος εκπέμπεται, ΚΑΙ ΟΤΑΝ ΕΙΝΑΙ ΜΗΔΕΝ.** Ένα `announced` που λείπει
 * από τα metrics διαβάζεται ως «δεν στάλθηκε τίποτα» — αλλά διαβάζεται **εξίσου**
 * ως «δεν μέτρησε κανείς». Η διάκριση είναι ακριβώς το σχήμα που κυνηγά όλο το
 * ADR-777, και δεν επιτρέπεται να χαθεί στο τελευταίο βήμα, στη γραμμή του log.
 *
 * Το `truncated` ταξιδεύει ως **0/1** και όχι ως boolean, γιατί το συμβόλαιο
 * `metrics` είναι `Record<string, number>` — και ένα σιωπηλά παραλειπόμενο πεδίο
 * θα έκρυβε ακριβώς την περίπτωση όπου **ιδιοκτήτες δεν εξετάστηκαν ποτέ**.
 */
function announcementMetrics(report: AnnouncementReport): Record<string, number> {
  return {
    announced: report.announced,
    alreadyKnown: report.alreadyKnown,
    noNews: report.noNews,
    optedOut: report.optedOut,
    considered: report.considered,
    truncated: report.truncated ? 1 : 0,
  };
}

/**
 * Ένα πέρασμα: «πες σε κάθε ιδιοκτήτη ό,τι είναι είδηση για εκείνον».
 *
 * ⚠️ **Δεν πιάνει σφάλματα, σκόπιμα.** Ο dispatcher τα πιάνει, τα καταγράφει στο
 * Sentry monitor του slug και ελευθερώνει το lease. Ένα `try/catch` εδώ θα έκανε
 * μια αποτυχημένη σάρωση να **φαίνεται επιτυχημένη** — και το `announceInterestToOwners`
 * πετά **επίτηδες** όταν δεν κλείνει η λογιστική του, ακριβώς για να ακουστεί.
 */
export async function runDemandInterestAnnounce(): Promise<CronJobResult> {
  const report = await announceInterestToOwners(getAdminFirestore());

  return {
    summary:
      `announced ${report.announced}, already-known ${report.alreadyKnown}, ` +
      `no-news ${report.noNews}, opted-out ${report.optedOut} ` +
      `(considered ${report.considered}${report.truncated ? ', TRUNCATED' : ''})`,
    metrics: announcementMetrics(report),
  };
}
