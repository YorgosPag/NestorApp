/**
 * =============================================================================
 * Η ΤΑΥΤΟΤΗΤΑ ΔΙΑΔΟΧΗΣ — «είναι αυτά τα δύο αρχεία ΤΟ ΙΔΙΟ δοχείο σε δύο στιγμές;»
 * =============================================================================
 *
 * **Το ερώτημα**: πριν ο διακομιστής δεχτεί ότι το `B` **αντικαθιστά** το `A`, πρέπει να
 * μπορεί να το **αποδείξει** από τα ίδια τα έγγραφα — όχι να το πιστέψει επειδή το είπε ο
 * πελάτης (ADR-862 Φ0 Β10).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🌐 ΠΩΣ ΤΟ ΚΑΝΟΥΝ ΟΙ ΜΕΓΑΛΟΙ — ΚΑΙ ΠΟΥ ΣΠΑΕΙ
 * ─────────────────────────────────────────────────────────────────────────────
 *   Autodesk Docs  → ίδιο **όνομα** + επέκταση στον ίδιο φάκελο ⇒ νέα έκδοση
 *   Procore        → ίδιος **αριθμός σχεδίου** ⇒ νέα αναθεώρηση
 *   Oracle Aconex  → ίδιος **αριθμός εγγράφου** ⇒ «supersede»
 *
 * Και τα τρία δένουν με **κείμενο που γράφει άνθρωπος**: μια διόρθωση τυπογραφικού μετατρέπει
 * την **έκδοση** σε **νέο έγγραφο** — το λάθος που το ADR-769 ονομάζει για το Figma («δένει
 * με όνομα layer, και γι' αυτό σπάει»). Εδώ η ταυτότητα είναι **δομική**: ή η ρητή ταυτότητα
 * δημοσίευσης που γράφει ο παραγωγός, ή η **θέση** του αρχείου στο μοντέλο οντοτήτων.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 «ΔΕΝ ΞΕΡΩ» ≠ «ΕΙΝΑΙ ΤΟ ΙΔΙΟ»
 * ─────────────────────────────────────────────────────────────────────────────
 * Ελλιπής θέση ⇒ `null` ⇒ ο κριτής **αρνείται** τη διαδοχή. Ποτέ συμπλήρωση με προεπιλογή:
 * δύο αρχεία που **και τα δύο** λένε «standalone» δεν είναι το ίδιο έγγραφο — είναι δύο
 * έγγραφα που **κανείς δεν τοποθέτησε**. Ίδιο δόγμα με το `publicationIdentity`
 * (`types/file-record.ts`: «απουσία ⇒ ΠΟΤΕ συγχώνευση»).
 *
 * ⚠️ **ΚΑΘΑΡΟ, ΧΩΡΙΣ ΔΙΣΚΟ** — το εκτελεί ο κριτής του διακομιστή **και** η άγκυρα με ωμό
 * αντικείμενο, ώστε το πράσινο να λέει ποιο από τα δύο δούλεψε.
 *
 * @module lib/files/succession-identity
 * @see lib/listings/model-publication-identity — ο παραγωγός της ρητής ταυτότητας μοντέλων
 * @see services/iso19650/container-succession-policy — ο **κριτής** που το ρωτά
 */

import { trimmedStringOrNull as text } from '@/lib/type-guards';

/** Το πρόθεμα της δομικής ταυτότητας — διακριτό από το `model` των μοντέλων. */
export const SLOT_IDENTITY_PREFIX = 'slot';

/**
 * Η τιμή που ο γραφέας σκηνών DXF βάζει όταν **δεν** ξέρει όροφο/κτίριο
 * (`api/cad-files/dual-write-to-files.ts` → `resolveEntityId`). Σημαίνει «ατοποθέτητο»,
 * άρα **δεν** αποτελεί θέση.
 */
const UNPLACED_ENTITY_ID = 'standalone';

/** Τα σκέλη της θέσης, **με σταθερή σειρά** — ποτέ `Object.values` (η σειρά κλειδιών δεν είναι συμβόλαιο). */
const SLOT_FIELDS = ['entityType', 'entityId', 'domain', 'category'] as const;

/**
 * Η **θέση** του αρχείου: οντότητα · τομέας · κατηγορία · σκοπός · επίπεδο.
 *
 * 🔑 Ο σκοπός και το επίπεδο είναι **προαιρετικά σκέλη με ρητή απουσία** (`-`): ένα αρχείο
 * χωρίς σκοπό είναι **άλλη** θέση από ένα με σκοπό, όχι «μπαλαντέρ».
 */
function slotKeyOf(raw: Record<string, unknown>): string | null {
  const required: string[] = [];
  for (const field of SLOT_FIELDS) {
    const value = text(raw[field]);
    if (value === null) return null;
    required.push(value);
  }
  if (required[1] === UNPLACED_ENTITY_ID) return null;

  const purpose = text(raw.purpose) ?? '-';
  const levelFloorId = text(raw.levelFloorId) ?? '-';
  return [SLOT_IDENTITY_PREFIX, ...required, purpose, levelFloorId].join('/');
}

/**
 * **Η ταυτότητα διαδοχής ενός αποθηκευμένου αρχείου**, ή `null` όταν δεν είναι γνωστή.
 *
 * ⚠️ Η **ρητή** ταυτότητα δημοσίευσης νικά τη δομική: ο παραγωγός που την έγραψε ήξερε **τι**
 * δημοσίευε (μοντέλο «μετρημένο · ενεργός όροφος · ως κατασκευάστηκε»), κάτι που η θέση δεν
 * μπορεί να διακρίνει.
 *
 * @param raw Το έγγραφο **όπως βγήκε από τη βάση**, ποτέ στενεμένο.
 */
export function successionIdentityOf(raw: Record<string, unknown>): string | null {
  return text(raw.publicationIdentity) ?? slotKeyOf(raw);
}
