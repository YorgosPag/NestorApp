import { fnv1a32 } from '@/lib/hash/fnv1a';

/** Το αποτύπωμα (8 δεκαεξαδικά) των μελών, με τη σειρά που δόθηκαν. */
export function alertSetDigest(members: readonly string[]): string {
  return fnv1a32(members.join('|')).toString(16).padStart(8, '0');
}
