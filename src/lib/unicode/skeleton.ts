/**
 * «Μοιάζουν ίδια;» — η οπτική ταυτότητα ενός ονόματος, μία φορά
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΛΥΝΕΙ (ADR-787 §5.3 δ · Ε-5 §8)
 * ─────────────────────────────────────────────────────────────────────────────
 * Το ελληνικό `Ν` (U+039D) και το λατινικό `N` (U+004E) είναι **διαφορετικοί
 * χαρακτήρες με ταυτόσημο σχήμα**. Το ίδιο ισχύει για `Α Β Ε Ζ Η Ι Κ Μ Ο Ρ Τ Υ Χ`
 * και για τα πεζά `ο ν α ε ρ ι`. Σε πλατφόρμα όπου ανταλλάσσονται **μελέτες και
 * συμβόλαια**, ένα γραφείο με ψευδώνυμο που *φαίνεται* ίδιο με άλλου δεν είναι
 * θεωρητικό — είναι διαδρομή προς λάθος παραλήπτη.
 *
 * Το **UTS #39** ορίζει τη συνάρτηση `skeleton`: κάθε χαρακτήρας αντικαθίσταται
 * με τον αντιπρόσωπο της οπτικής του οικογένειας. **Δύο ονόματα με τον ίδιο
 * σκελετό είναι οπτικά ταυτόσημα.**
 *
 * ⚠️ Το ίδιο το πρότυπο γράφει ότι ο σκελετός *«is intended only for internal use
 * for testing confusability… not suitable for display to users»*. **ΜΗΝ τον
 * δείξεις ποτέ σε άνθρωπο** — είναι κλειδί σύγκρισης, όχι κείμενο.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 Η ΣΕΙΡΑ ΕΙΝΑΙ ΣΥΜΒΟΛΑΙΟ: ΤΟ CASE FOLDING ΜΠΑΙΝΕΙ **ΜΕΤΑ**, ΟΧΙ ΠΡΙΝ
 * ─────────────────────────────────────────────────────────────────────────────
 * Είναι αντι-διαισθητικό, και γι' αυτό γράφεται εδώ με τον αριθμό του: το
 * πρότυπο ορίζει τον σκελετό **χωρίς** case folding, και ο πίνακάς του στέλνει
 * το ψηφίο `0` στο **κεφαλαίο** `O`. Άρα:
 *
 * | Διάταξη | «nestor» vs «nest0r» |
 * |---|---|
 * | lowercase **πριν** | `nestor` vs `nest`**`O`**`r` ⇒ 🔴 **ΔΙΑΦΕΥΓΕΙ** |
 * | lowercase **μετά** | `nestor` vs `nestor` ⇒ ✅ πιάνεται |
 *
 * Μετρημένο σε 88 ρεαλιστικά ψευδώνυμα (ελληνικά + λατινικά) και 10 πραγματικές
 * επιθέσεις: **«μετά» = 10/10 επιθέσεις**, **«πριν» = 9/10**, με **ταυτόσημο**
 * ποσοστό ψευδώς θετικών. ⛔ **ΜΗΝ το «διορθώσεις» σε lowercase-πριν.**
 *
 * ⚠️ Η μοναδική σύγκρουση του δείγματος ήταν `rn-tech ≡ m-tech` — και **δεν είναι
 * ψευδώς θετικό**: το `rn` όντως διαβάζεται ως `m`. Ο πίνακας το λέει ρητά
 * (`m → rn`), και η σύλληψη είναι **σωστή**.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΓΙΑΤΙ `server-only`
 * ─────────────────────────────────────────────────────────────────────────────
 * Ο πίνακας είναι **~80 KB**. Η κρίση *«μοιάζουν ίδια;»* συμβαίνει όταν
 * **γεννιέται** ένα ψευδώνυμο — πράξη του διακομιστή. Ο πελάτης δεν τη χρειάζεται
 * ποτέ, και δεν πρέπει να πληρώνει το bundle.
 *
 * @module lib/unicode/skeleton
 */

import 'server-only';

import table from './generated/confusable-skeleton.json';

/**
 * Ο πίνακας αντιστοιχιών του UTS #39, παραγόμενος από το επίσημο
 * `confusables.txt` — **ποτέ χειρόγραφος**.
 */
const CONFUSABLE_MAP: Readonly<Record<string, string>> = table.map;

/** Η έκδοση Unicode από την οποία παρήχθη ο πίνακας — για διαγνωστικά. */
export const UNICODE_VERSION: string = table._unicodeVersion;

/**
 * Ο **σκελετός** ενός ονόματος κατά UTS #39, με case folding **μετά**.
 *
 * ⚠️ Η διάσπαση γίνεται με `[...s]`, **όχι** `s.split('')`: το δεύτερο κόβει τα
 * ζεύγη υποκατάστασης στη μέση, οπότε κάθε χαρακτήρας εκτός BMP θα γινόταν δύο
 * μισοί που δεν αντιστοιχίζονται σε τίποτα — **σιωπηλή απουσία κάλυψης**
 * ακριβώς στους χαρακτήρες που ένας επιτιθέμενος θα διάλεγε.
 *
 * @param input το ωμό κείμενο, όπως το έγραψε ο άνθρωπος
 * @returns κλειδί σύγκρισης — **ποτέ** προς εμφάνιση
 */
export function skeleton(input: string): string {
  const decomposed = input.normalize('NFD');
  const mapped = [...decomposed].map((ch) => CONFUSABLE_MAP[ch] ?? ch).join('');
  return mapped.normalize('NFD').toLowerCase();
}

/**
 * Δύο ονόματα είναι **οπτικά ταυτόσημα**;
 *
 * ⚠️ Δεν ρωτά «είναι ίδια;» — αυτό το απαντά ο `===`. Ρωτά *«θα τα ξεχώριζε
 * άνθρωπος που κοιτάζει έναν σύνδεσμο;»*, και η απάντηση είναι **όχι** όταν
 * ο σκελετός συμπίπτει.
 */
export function looksIdentical(a: string, b: string): boolean {
  return skeleton(a) === skeleton(b);
}
