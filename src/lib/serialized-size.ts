/**
 * serialized-size — **Η ΜΙΑ ΑΠΑΝΤΗΣΗ ΣΤΟ «ΠΟΣΑ BYTES ΠΙΑΝΕΙ ΑΥΤΟ ΟΤΑΝ ΓΡΑΦΤΕΙ;»**
 *
 * ADR-833 Φάση 5Α. Κάθε όριο αποθήκευσης της εφαρμογής (claim της Firebase, αντικείμενο
 * του Cloud Storage, έγγραφο Firestore) μετριέται σε **bytes UTF-8** — γιατί αυτό
 * ακριβώς ανεβαίνει στο δίκτυο. Το `String.length` μετρά **μονάδες UTF-16** και είναι
 * άλλο νούμερο.
 *
 * ## 🔴 Γιατί υπάρχει: το repo είχε ΠΕΝΤΕ απαντήσεις στην ίδια ερώτηση
 *
 * Μετρημένο 2026-08-31, με το ίδιο ερώτημα σε πέντε σημεία:
 *
 * ```
 *   lib/auth/claim-payload.ts:154        Buffer.byteLength(json, 'utf8')          ✅ σωστό
 *   services/floorplans/*.ts (×2)        TextEncoder().encode(json).length        ✅ σωστό
 *   dxf-viewer/services/…storage.impl    TextEncoder().encode(json).length        ✅ (ανέβασμα)
 *   dxf-viewer/services/…storage.impl:96 JSON.stringify(scene).length             ❌ UTF-16
 *   dxf-viewer/systems/topography/…:152  JSON.stringify(surfaces).length          ❌ UTF-16
 *   dxf-viewer/settings/io/IndexedDbDriver:295  JSON.stringify(r).length * 2      ❌ ούτε το ένα ούτε το άλλο
 * ```
 *
 * Και το **ίδιο αρχείο** κρατούσε δύο από αυτές: το `saveToStorageImpl` κωδικοποιεί τα
 * πραγματικά bytes για το ανέβασμα (γρ. 170) και τα δίνει στον επικυρωτή — αλλά ο
 * επικυρωτής, όταν κληθεί **χωρίς** αυτά, ξαναμετρά με `.length`. Δηλαδή η **ίδια**
 * σκηνή έβγαζε δύο μεγέθη ανάλογα με το ποιος ρώτησε.
 *
 * ## Πόσο κοστίζει το λάθος: ×1,45 στα ελληνικά, μετρημένο
 *
 * Το δόγμα ήταν **ήδη γραμμένο** στο `lib/auth/claim-payload.ts` — σε άλλον τομέα, με
 * περιστατικό: το CHECK 3.34 §8.43 πλήρωσε **163.749 αντί για 240.521**. Ένα ελληνικό
 * γράμμα είναι **μία** μονάδα UTF-16 και **δύο** bytes UTF-8. Ο ΝΕΣΤΩΡ γράφει ελληνικά
 * σε κάθε κελί πίνακα, σε κάθε όνομα φύλλου, σε κάθε ετικέτα.
 *
 * 🔑 Το ύπουλο δεν είναι ότι το νούμερο βγαίνει λάθος — είναι ότι βγαίνει **μικρότερο**.
 * Ένα όριο που μετριέται με `.length` δεν μπλοκάρει ποτέ όταν πρέπει· απλώς αφήνει το
 * αρχείο να φτάσει στο δίκτυο και να απορριφθεί **εκεί**, όπου το μήνυμα δεν λέει τι
 * να κόψεις.
 *
 * ## Γιατί `TextEncoder` και όχι `Buffer`
 *
 * Το `Buffer` είναι Node. Οι μετρήσεις του πίνακα τρέχουν στον **πελάτη** (ο καμβάς
 * ρωτά «χωράει;» πριν στείλει). Το `TextEncoder` είναι καθολικό και στα δύο, και δίνει
 * **ταυτόσημο** αποτέλεσμα με το `Buffer.byteLength(s, 'utf8')`.
 *
 * @module lib/serialized-size
 * @see lib/auth/claim-payload.ts — το ιδίωμα «ετυμηγορία με αριθμούς» που καθρεφτίζεται εδώ
 * @see docs/centralized-systems/reference/adrs/ADR-833-table-xlsx-import-and-worksheets.md §5.6
 */

/**
 * Ο **ένας** κωδικοποιητής. Η κατασκευή του δεν είναι δωρεάν και η μέτρηση καλείται σε
 * βρόχους (ένα φύλλο τη φορά, ένα κελί τη φορά στις εκτιμήσεις) — ένα στιγμιότυπο αρκεί,
 * γιατί το `TextEncoder` είναι **ακατάστατο**: δεν κρατά τίποτα ανάμεσα σε κλήσεις.
 */
const encoder = new TextEncoder();

/**
 * Πόσα bytes πιάνει αυτό το κείμενο **όπως όντως γράφεται**.
 *
 * @param text Το κείμενο.
 * @returns Μέγεθος σε bytes UTF-8.
 */
export function utf8ByteLength(text: string): number {
  return encoder.encode(text).length;
}

/**
 * Πόσα bytes πιάνει αυτή η τιμή **όπως όντως αποθηκεύεται** — σειριοποιημένη σε JSON
 * χωρίς μορφοποίηση, μετρημένη σε UTF-8.
 *
 * Είναι ο **ίδιος** υπολογισμός που κάνει η διαδρομή αποθήκευσης πριν το ανέβασμα:
 * `JSON.stringify(x)` → `TextEncoder().encode(...)`. Γι' αυτό η απάντηση δεν είναι
 * εκτίμηση — είναι το νούμερο.
 *
 * ⚠️ **`Map` και `Set` σειριοποιούνται σε `{}`** — σιωπηλά, όπως τα ορίζει το JSON.
 * Δηλαδή ένα runtime μοντέλο με `Map` κελιών θα αναφέρει σχεδόν **μηδέν**. Δώσε πάντα
 * το σχήμα **που ταξιδεύει** (στον πίνακα: `PersistedTableModel`, ποτέ `TableModel`).
 * Το `types/json-safe-entity.ts` του dxf-viewer κρατά τους τύπους που το επιβάλλουν σε
 * χρόνο μεταγλώττισης· εδώ δεν γίνεται έλεγχος, γιατί η μέτρηση **δεν κρίνει** την
 * είσοδο — αναφέρει τι θα γραφτεί.
 *
 * @param value Ό,τι πρόκειται να αποθηκευτεί.
 * @returns Μέγεθος σε bytes UTF-8. `undefined` (που το JSON δεν γράφει) δίνει `0`.
 */
export function serializedByteLength(value: unknown): number {
  const json = JSON.stringify(value);
  // `JSON.stringify(undefined)` επιστρέφει `undefined`, όχι κείμενο — και το ίδιο ισχύει
  // για συναρτήσεις και σύμβολα. Δεν γράφεται τίποτα, άρα δεν κοστίζει τίποτα.
  //
  // ⚠️ **ΔΗΛΩΜΕΝΟΣ ΩΣ ΜΗ ΑΓΚΥΡΩΜΕΝΟΣ** (ADR-833 Φ5Α, ίδια στάση με τον βρόχο του
  // `nextAxisId` στο §5.4.8): η μετάλλαξη «βγάλε τον φρουρό» **έμεινε πράσινη**, και η
  // άγκυρα δεν φταίει — η μετάλλαξη είναι **ισοδύναμη**. Το `TextEncoder.prototype.encode`
  // δηλώνεται στο WebIDL με `optional USVString input = ""`, άρα `encode(undefined)`
  // κωδικοποιεί το **κενό** κείμενο και δίνει κι αυτό `0` (επαληθεύτηκε εκτελώντας το).
  // Καμία είσοδος δεν ξεχωρίζει τους δύο κλάδους.
  //
  // **Μένει** γιατί κάνει τη σύμβαση **ρητή** αντί να την κληρονομεί από μια προεπιλογή
  // προδιαγραφής που ο επόμενος αναγνώστης δεν έχει λόγο να ξέρει — και γιατί παύει να
  // ισχύει την ημέρα που κάποιος αντικαταστήσει τον κωδικοποιητή.
  return json === undefined ? 0 : utf8ByteLength(json);
}

/**
 * Η απάντηση στο «χωράει;» — **με τους αριθμούς μέσα, ώστε να λέει τι να κόψεις**.
 *
 * 🔑 Το σχήμα είναι σκόπιμα ταυτόσημο με το `ClaimFitVerdict` του
 * `lib/auth/claim-payload.ts`: είναι η **ίδια ερώτηση** σε άλλο όριο, και δύο σχήματα
 * για την ίδια ερώτηση είναι δύο ευκαιρίες να διαφωνήσουν. Ένα σκέτο `boolean` θα
 * ανάγκαζε κάθε καλούντα να ξαναμετρήσει για να συνθέσει μήνυμα.
 */
export interface SizeFitVerdict {
  readonly fits: boolean;
  readonly bytes: number;
  readonly limit: number;
  /** Πόσα bytes περισσεύουν· `0` όταν χωράει. */
  readonly overBy: number;
}

/**
 * Χωράει αυτό το μέγεθος σε αυτό το όριο;
 *
 * @param bytes Μετρημένο μέγεθος (από {@link serializedByteLength}).
 * @param limit Το όριο, σε bytes. **Δίνεται πάντα ρητά** — αυτό το module δεν κατέχει
 *   κανένα όριο, γιατί κάθε αποθήκη έχει δικό της και ο ιδιοκτήτης του ορίου είναι
 *   εκείνη, όχι ο μετρητής.
 * @returns Ετυμηγορία με αριθμούς, ποτέ σκέτο `boolean`.
 */
export function checkSizeFits(bytes: number, limit: number): SizeFitVerdict {
  return {
    fits: bytes <= limit,
    bytes,
    limit,
    overBy: Math.max(0, bytes - limit),
  };
}
