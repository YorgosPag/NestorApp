/**
 * @fileoverview **Η ΥΠΟΔΟΧΗ: από πού μαθαίνει το σύρμα ποιον χώρο ζητά ο πελάτης.**
 * @related ADR-787 §5.3 ζ · ADR-849 Β1 · `services/firestore/super-admin-active-company`
 * @module lib/api/workspace-scope-source
 *
 * 🔑 **Πηγή, όχι τιμή.** Ο `enterprise-api-client` κρατούσε **πεδίο** που «έσπρωχνε» ένα
 * effect του React — δεύτερο αντίγραφο της απάντησης, που **έμενε πίσω** από τη διεύθυνση:
 * η οθόνη έλεγε μία εταιρεία, το αίτημα ζητούσε άλλη. Τώρα το σύρμα **ρωτά** τη ΜΙΑ
 * απάντηση (`requestedWorkspace`) τη στιγμή του αιτήματος.
 *
 * ⚠️ **Γιατί υποδοχή και όχι απευθείας εισαγωγή**: το `lib/` δεν εισάγει από το `services/`
 * — ανάποδο στρώμα, που μετρημένα έσπασε τρεις σουίτες (βλ. `services/firestore/auth-context.ts`).
 * Το store **εγγράφεται** εδώ (σωστή κατεύθυνση).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΙ ΑΛΛΑΞΕ 2026-09-12 — ΜΕΤΑΦΕΡΕΙ **ΚΑΤΑΣΤΑΣΗ**, ΟΧΙ ΕΤΑΙΡΕΙΑ
 * ─────────────────────────────────────────────────────────────────────────────
 * Το αρχείο λεγόταν `company-scope-source` και η πηγή του επέστρεφε `string | null`. Άρα
 * ο **ιδιωτικός** χώρος και το «η διεύθυνση δεν ονομάζει χώρο» κατέληγαν **στην ίδια
 * τιμή** (`null`), και η παλιά κεφαλίδα δεν έφευγε καθόλου. Ο διακομιστής διάβαζε την
 * απουσία ως «κρίνε μόνος σου» — που για super-admin σημαίνει **καθολική όψη**: το
 * `/o/me/projects` έδειξε ζωντανά **7 έργα** (ADR-787 §9, γραμμή (γ)).
 *
 * ⇒ Η πηγή επιστρέφει πλέον {@link RequestedWorkspace}: **τρεις ρητές καταστάσεις**, και
 * το σύρμα δηλώνει **πάντα** μία από αυτές.
 *
 * ⚠️ **Η ΠΡΟΕΠΙΛΟΓΗ ΠΡΙΝ ΤΗΝ ΕΓΓΡΑΦΗ ΕΙΝΑΙ `default`, ΚΑΙ ΕΙΝΑΙ ΣΚΟΠΙΜΟ**: σημαίνει
 * *«κανείς δεν δήλωσε χώρο»*, δηλαδή **ακριβώς** τη σημερινή συμπεριφορά του διακομιστή —
 * ποτέ σιωπηλή εταιρεία, ποτέ ψεύτικο `personal` που θα αρνιόταν αιτήματα σελίδων που
 * δουλεύουν. Το store εγγράφεται από το root layout (μέσω `SuperAdminCompanyContext`) και
 * από τον φύλακα του χώρου, **πριν** από κάθε αίτημα συστατικού.
 *
 * **Layering**: leaf — μόνο ο τύπος του λεξιλογίου.
 */

import type { RequestedWorkspace } from '@/types/workspace-membership';

const UNDECLARED: RequestedWorkspace = { kind: 'default' };

let source: () => RequestedWorkspace = () => UNDECLARED;

/** Εγγράφει την πηγή — **μία** φορά, από το store του ενεργού χώρου. */
export function registerWorkspaceScopeSource(next: () => RequestedWorkspace): void {
  source = next;
}

/** Ποιον χώρο ζητά ο πελάτης **τώρα** — πάντα μία από τις τρεις ρητές καταστάσεις. */
export function requestedWorkspaceScope(): RequestedWorkspace {
  return source();
}
