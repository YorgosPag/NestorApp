import 'server-only';

import { NextResponse } from 'next/server';
import type { NextRequest } from 'next/server';
import type { z } from 'zod';

/**
 * Το σώμα, κριμένο: **ή** τα δεδομένα **ή** η έτοιμη απόρριψη — ποτέ και τα δύο,
 * ποτέ κανένα. Ο καλών κάνει `if ('rejected' in parsed) return parsed.rejected;`.
 */
export type JsonBody<T> =
  | { readonly data: T }
  | { readonly rejected: NextResponse };

/**
 * **Διάβασε το σώμα και κρίνε το με αυτό το σχήμα.**
 *
 * ⚠️ **Το `catch(() => null)` δεν είναι απροσεξία**: ένα αίτημα με σκουπίδια αντί
 * για JSON είναι **κακό σώμα** (400), όχι δικό μας σφάλμα (500). Το `null`
 * αποτυγχάνει στο σχήμα σαν κάθε άλλη λάθος τιμή, άρα υπάρχει **μία** διαδρομή
 * απόρριψης και όχι δύο που μπορούν να αποκλίνουν.
 */
export async function readJsonBody<TSchema extends z.ZodTypeAny>(
  request: NextRequest,
  schema: TSchema,
): Promise<JsonBody<z.infer<TSchema>>> {
  const body: unknown = await request.json().catch(() => null);
  const parsed = schema.safeParse(body);

  if (parsed.success) return { data: parsed.data as z.infer<TSchema> };

  return {
    rejected: NextResponse.json(
      {
        error: 'MALFORMED_BODY',
        malformed: [...new Set(parsed.error.issues.map((issue) => issue.path.join('.')))],
      },
      { status: 400 },
    ),
  };
}
