// Ο μεταφραστής της ζώνης δεν χρειάζεται ζωντανό i18n — μόνο γλώσσα.
jest.mock('@/lib/intl-utils', () => ({ getCurrentLocale: () => 'el' }));

import { endOfDay, formatTermDay, startOfDay, toDateInputValue } from '../mandate-term-window';

/** Η ημέρα που συμφώνησε ο άνθρωπος στο ζωντανό έγγραφο (ADR-834 §6.4). */
const AGREED_DAY = '2027-04-30';

/** Πώς θα διαβαζόταν η ίδια στιγμή σε ρητή ζώνη — ο **αντίπαλος** της μέτρησης. */
function inZone(isoInstant: string, timeZone: string): string {
  return new Intl.DateTimeFormat('el', {
    timeZone,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(new Date(isoInstant));
}

describe('🔑 Ζ — ο ΠΑΡΟΝΟΜΑΣΤΗΣ: το ερώτημα είναι ΠΡΑΓΜΑΤΙΚΟ εδώ', () => {
  it('🔴 Ζ0 — το περιβάλλον ΜΠΟΡΕΙ να εκφράσει το ελάττωμα (αλλιώς κοκκινίζει)', () => {
    // 🔴 **Η ΠΡΟΫΠΟΘΕΣΗ, ΕΚΤΕΛΕΣΜΕΝΗ.** Η στιγμή που γράφει ο `endOfDay` οφείλει να
    //    πέφτει σε **άλλη ημέρα** τοπικά· μόνο τότε μπορεί η απώλεια του `timeZone`
    //    να παρατηρηθεί. Σε UTC αυτό είναι `false` και η σουίτα **οφείλει** να
    //    κοκκινίσει: πράσινο εκεί δεν θα σήμαινε «σωστό», θα σήμαινε «τυφλό».
    const boundary = new Date(endOfDay(AGREED_DAY));
    expect([
      Intl.DateTimeFormat().resolvedOptions().timeZone,
      boundary.getDate() !== boundary.getUTCDate(),
    ]).toEqual([Intl.DateTimeFormat().resolvedOptions().timeZone, true]);
  });

  it('🔴 Ζ1 — και η ΣΤΙΓΜΗ του τέλους ημέρας ΟΝΤΩΣ μετακινείται εκτός UTC', () => {
    // Χωρίς αυτό, όλα τα παρακάτω θα μπορούσαν να είναι πράσινα επειδή η επιλεγμένη
    // ημερομηνία τυχαίνει να μην περνά μεσάνυχτα σε καμία ζώνη.
    const boundary = endOfDay(AGREED_DAY);
    expect(inZone(boundary, 'Europe/Athens')).not.toBe(inZone(boundary, 'UTC'));
  });
});

describe('🔴 Η — η λήξη ονομάζει την ΗΜΕΡΑ ΠΟΥ ΓΡΑΦΤΗΚΕ, όχι την επόμενη', () => {
  it('Η1 — `endOfDay(30/04)` διαβάζεται ως 30/04', () => {
    const shown = formatTermDay(endOfDay(AGREED_DAY));
    expect(shown).toBe(inZone(endOfDay(AGREED_DAY), 'UTC'));
    expect(shown).toContain('30');
    expect(shown).toContain('04');
  });

  it('🔑 Η2 — και ΔΕΝ διαβάζεται όπως θα το διάβαζε η τοπική ζώνη', () => {
    // 🔴 **Αυτή η γραμμή είναι ολόκληρο το περιστατικό**: το καθολικό `formatDate`
    //    έδινε ακριβώς τη δεξιά πλευρά, και ο ιδιοκτήτης υπέγραφε άλλη ημέρα.
    const boundary = endOfDay(AGREED_DAY);
    expect(formatTermDay(boundary)).not.toBe(inZone(boundary, 'Europe/Athens'));
  });

  it('Η3 — η ΕΝΑΡΞΗ διαβάζεται με την ΙΔΙΑ σύμβαση (η ασυμμετρία της παύλας)', () => {
    // ⚠️ Το `startOfDay` γράφει `T00:00:00.000Z`: **δυτικά** του UTC μετακινείται προς
    //    τα πίσω. Πριν, οι δύο άκρες της ίδιας περιόδου διαβάζονταν με δύο συμβάσεις.
    expect(formatTermDay(startOfDay(AGREED_DAY))).toBe(formatTermDay(endOfDay(AGREED_DAY)));
  });

  it('Η4 — ό,τι ονομάζει το `formatTermDay` είναι Η ΑΠΟΘΗΚΕΥΜΕΝΗ ημέρα', () => {
    // Ο δεσμός με τον **γραφέα**: το `toDateInputValue` είναι ο τεμαχισμός σε UTC που
    // η φόρμα ξαναδίνει στον άνθρωπο. Οι δύο αναγνώστες δεν επιτρέπεται να διαφωνούν.
    for (const day of ['2026-01-01', '2026-06-15', AGREED_DAY, '2027-12-31']) {
      const [year, month, dayOfMonth] = toDateInputValue(endOfDay(day)).split('-');
      const shown = formatTermDay(endOfDay(day));
      expect([day, shown.includes(dayOfMonth) && shown.includes(month) && shown.includes(year)])
        .toEqual([day, true]);
    }
  });
});

describe('Θ — η απουσία λέγεται, δεν επινοείται', () => {
  it('Θ1 — `null` ⇒ κενό, ποτέ «Invalid Date»', () => {
    expect(formatTermDay(null)).toBe('');
  });

  it('Θ2 — σκέτο `yyyy-mm-dd` γίνεται δεκτό (το `nextDay` δίνει τέτοιο)', () => {
    expect(formatTermDay(AGREED_DAY)).toBe(formatTermDay(endOfDay(AGREED_DAY)));
  });

  it('Θ3 — αδιάβαστη είσοδος επιστρέφει ό,τι ξέρει, ποτέ σκουπίδι', () => {
    const junk = 'όχι-ημερομηνία';
    expect(formatTermDay(junk)).toBe(toDateInputValue(junk));
  });
});
