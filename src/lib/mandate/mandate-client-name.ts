/**
 * @fileoverview **ΠΩΣ ΛΕΓΕΤΑΙ Ο ΠΕΛΑΤΗΣ — ή ΓΙΑΤΙ ΔΕΝ ΛΕΓΕΤΑΙ.** Τρεις κόσμοι, τρία ονόματα.
 * @related ADR-834 §6.5.δ · services/mandate/mandate-catalog.service.ts · types/contacts/helpers.ts
 * @module lib/mandate/mandate-client-name
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΓΕΝΝΗΘΗΚΕ: «Η ΕΠΑΦΗ ΔΕΝ ΒΡΕΘΗΚΕ» ΓΙΑ ΕΠΑΦΗ ΠΟΥ ΒΡΕΘΗΚΕ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο κατάλογος εντολών έγραφε *«Πελάτης: Η επαφή δεν βρέθηκε»* για επαφή που **υπάρχει
 * στη βάση** — απλώς δεν έχει αναγνώσιμο όνομα (μετρημένο ζωντανά 2026-08-31,
 * ADR-834 §6.5.γ #3). Και η υπηρεσία **ήξερε ήδη** τη διαφορά: ο αναγνώστης ονομάτων
 * κάνει `continue` και στις **δύο** περιπτώσεις — «δεν υπάρχει έγγραφο» και «υπάρχει
 * χωρίς όνομα» — οπότε η πληροφορία **υπήρχε ένα επίπεδο πιο κάτω** και ισοπεδωνόταν
 * στην έξοδο. Ίδιο σχήμα με το `notifyOutcome`: **ένα κενό για δύο κόσμους**.
 *
 * 🔑 **Οι δύο θεραπείες είναι ΔΙΑΦΟΡΕΤΙΚΕΣ, και αυτό δικαιολογεί τη διάκριση.**
 * *«Δεν βρέθηκε»* σημαίνει **σπασμένος δεσμός** — η εντολή δείχνει σε επαφή που
 * διαγράφηκε, και κάποιος πρέπει να ξαναδέσει τον πελάτη. *«Χωρίς όνομα»* σημαίνει
 * **ελλιπής καρτέλα** — ο πελάτης είναι εκεί, ανοίγεις την επαφή και συμπληρώνεις. Ένα
 * κοινό μήνυμα στέλνει τον μεσίτη να ψάξει διαγραμμένη επαφή που **δεν διαγράφηκε**.
 *
 * ⚠️ **ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΤΗΝ ΥΠΗΡΕΣΙΑ.** Το λεξιλόγιο το γράφει ο διακομιστής και το
 * **διαβάζει η οθόνη** (`Record` κλειδιών i18n). Ένα `server-only` module σαν τόπος του
 * θα ανάγκαζε τον κατάλογο να κάνει `import type` από αρχείο που **δεν επιτρέπεται**
 * να φορτώσει — δουλεύει (ο τύπος σβήνεται), αλλά δηλώνει λάθος πράγμα για το ποιος
 * ανήκει πού. Ίδιο σκεπτικό με το `MandateActionRejection` (`lib/mandate/mandate-actions`).
 *
 * ⛔ **ΜΗΝ βάλεις εφεδρεία «Ανώνυμος πελάτης» στον κριτή ταυτότητας** — το ADR-834 §8
 * το απαγορεύει ονομαστικά: **σκεπάζει** μετρημένη απώλεια δεδομένων. Η άγνοια
 * **ονομάζεται**, δεν μεταμφιέζεται.
 */

/** Η επαφή βρέθηκε **και έχει όνομα**. */
export const CLIENT_NAME_KNOWN = 'known';

/** Η επαφή **βρέθηκε**, αλλά κανένα αναγνώσιμο όνομα δεν προκύπτει από την καρτέλα της. */
export const CLIENT_NAME_UNNAMED = 'unnamed';

/** **Δεν υπάρχει έγγραφο επαφής** για το `clientContactId` της εντολής — σπασμένος δεσμός. */
export const CLIENT_NAME_MISSING = 'missing';

/**
 * **Το όνομα του πελάτη, ή η ονομασμένη άγνοιά μας.**
 *
 * 🔑 Διακριτή ένωση και όχι `string | null`, γιατί ακριβώς αυτό ήταν το ελάττωμα: το
 * `null` κουβαλούσε **δύο** νοήματα και η οθόνη διάλεγε το ένα.
 */
export type MandateClientName =
  | { readonly kind: typeof CLIENT_NAME_KNOWN; readonly name: string }
  | { readonly kind: typeof CLIENT_NAME_UNNAMED }
  | { readonly kind: typeof CLIENT_NAME_MISSING };

/** Σταθερά, ώστε οι δύο άγνοιες να μη γεννιούνται με `{}` σε κάθε σημείο κλήσης. */
export const CLIENT_NAME_IS_UNNAMED: MandateClientName = { kind: CLIENT_NAME_UNNAMED };

/** Σταθερά — δες {@link CLIENT_NAME_IS_UNNAMED}. */
export const CLIENT_NAME_IS_MISSING: MandateClientName = { kind: CLIENT_NAME_MISSING };

/**
 * **Ο ΕΝΑΣ κριτής**: τι είναι αυτό που επέστρεψε ο υπολογιστής ονόματος;
 *
 * ⚠️ Δέχεται `unknown` επίτηδες. Το `getContactDisplayName` δηλώνει `: string` και το
 * τηρεί για **καλά σχηματισμένη** `Contact` — αλλά ο καλών του δίνει **ωμό έγγραφο
 * βάσης** μέσω ισχυρισμού τύπου, όπου ο διακριτής `type` μπορεί να λείπει· τότε
 * επιστρέφει `undefined` και ένα σκέτο `.trim()` **ρίχνει ολόκληρο τον κατάλογο** για
 * μία χαλασμένη επαφή. Ο ισχυρισμός είναι δικός μας, άρα και η ευθύνη.
 *
 * 🔑 **Ο έλεγχος ΜΕΝΕΙ· αλλάζει μόνο ΤΙ ΕΠΙΣΤΡΕΦΕΤΑΙ** — ήταν `continue` (η επαφή
 * εξαφανιζόταν και γινόταν «δεν βρέθηκε»), τώρα είναι **ονομασμένη κατάσταση**.
 */
export function clientNameFrom(displayName: unknown): MandateClientName {
  if (typeof displayName !== 'string') return CLIENT_NAME_IS_UNNAMED;
  const trimmed = displayName.trim();
  return trimmed === ''
    ? CLIENT_NAME_IS_UNNAMED
    : { kind: CLIENT_NAME_KNOWN, name: trimmed };
}

/**
 * **Η ΔΙΕΥΘΥΝΣΗ ΗΛΕΚΤΡΟΝΙΚΟΥ ΤΑΧΥΔΡΟΜΕΙΟΥ ΕΙΝΑΙ ΟΝΟΜΑ** (ADR-841 §7 **Α18.13**).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΠΕΡΙΣΤΑΤΙΚΟ: Η ΕΙΔΟΠΟΙΗΣΗ ΕΛΕΓΕ ΣΕ ΑΝΘΡΩΠΟ ΕΝΑ **UUID**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Γραμμένο **ζωντανά** στη βάση, 2026-09-05, αυτολεξεί:
 *
 * > *«Ο/Η **cont_da84f8c4-2344-4f0f-b161-d1f795d25d2f** ενέκρινε την εντολή για
 * > «TEST-3…»»*
 *
 * Η επαφή **υπήρχε**, με κενό όνομα και **μόνο email** ⇒ κατάσταση
 * {@link CLIENT_NAME_UNNAMED}. Ο ειδοποιητής ρωτούσε τον σωστό κριτή και μετά
 * **πετούσε την απάντησή του**, ισοπεδώνοντας **και τις δύο** άγνοιες στο ωμό
 * αναγνωριστικό.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 📚 Η ΠΡΑΚΤΙΚΗ ΤΗΣ ΑΓΟΡΑΣ — ΟΜΟΦΩΝΗ, ΚΑΙ ΠΑΛΑΙΟΤΕΡΗ ΑΠΟ ΕΜΑΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ερώτημα *«πώς λες ποιος είναι κάποιος που δεν έχει όνομα;»* το έλυσε το
 * **ηλεκτρονικό ταχυδρομείο**: το RFC 5322 δέχεται ρητά `mailbox` **χωρίς**
 * `display-name` *(σκέτο `addr-spec`)*, και κάθε πελάτης — Gmail, Outlook, Apple Mail —
 * αποδίδει τότε **τη διεύθυνση**: *«if a sender does not include their name with their
 * email address, then you will only see the email address»*.
 *
 * ⇒ **Η διεύθυνση δεν είναι εφεδρεία· είναι ταυτότητα** — και γι' αυτό η συνάρτηση
 * λέγεται *προαγωγή* και όχι *fallback*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΚΑΜΙΑ ΝΕΑ ΤΑΞΙΝΟΜΙΑ — ΕΠΙΣΤΡΕΦΕΙ ΤΟΝ **ΙΔΙΟ** ΤΥΠΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Θα ήταν εύκολο να γεννηθεί ένα `MandateClientLabel` με τρεις δικές του τιμές. Θα ήταν
 * **δεύτερο λεξιλόγιο για το ίδιο ερώτημα** — το σχήμα του ADR-749. Εδώ η πράξη είναι
 * κυριολεκτικά **προαγωγή μέσα στο υπάρχον σύνολο**: `unnamed` **με** email γίνεται
 * `known`, με το email ως όνομα. Οι τρεις κόσμοι μένουν τρεις.
 *
 * ⛔ **ΚΑΜΙΑ εφεδρεία «Ανώνυμος πελάτης»** *(ADR-834 §8, ονομαστικά)*: σκεπάζει
 * μετρημένη απώλεια δεδομένων. Και οι δύο άγνοιες που **επιβιώνουν** δεν μοιράζονται
 * κείμενο, γιατί **δεν μοιράζονται δουλειά**: `unnamed` ⇒ *άνοιξε την επαφή και
 * συμπλήρωσε*· `missing` ⇒ *ξαναδέσε τον πελάτη*.
 *
 * 🏆 **ΠΟΥ ΞΕΠΕΡΝΑΜΕ ΤΟ GMAIL**: εκείνο δείχνει τη διεύθυνση και **σταματά** — δεν λέει
 * ποτέ ότι η καρτέλα είναι ελλιπής. Εδώ η **ειδοποίηση** ταυτοποιεί *(email)* και η
 * **οθόνη προορισμού** λέει ότι λείπει το όνομα *(`CLIENT_NAME_KEYS`, ήδη γραμμένο στο
 * `RowFacts`)*. Δύο επιφάνειες, δύο δουλειές, μηδέν διπλό κείμενο.
 *
 * @param email — από το **υπάρχον** {@link getPrimaryEmail}, ποτέ χειρόγραφο
 *   `emails[0].email`: εκείνο ξέρει τι σημαίνει «πρωτεύον» και το ξέρει σε ένα σημείο.
 */
export function withEmailAsName(
  name: MandateClientName,
  email: string | null | undefined,
): MandateClientName {
  if (name.kind !== CLIENT_NAME_UNNAMED) return name;

  // ⚠️ **Ο ΙΔΙΟΣ κριτής, ξανά** — ένα email που είναι κενό ή σκέτα κενά **δεν** είναι
  //    όνομα, και το «τι μετράει ως όνομα» απαντιέται σε **ένα** σημείο.
  return clientNameFrom(email);
}
