import { getCurrentLocale } from '@/lib/intl-utils';

/**
 * `yyyy-mm-dd` → **τέλος** εκείνης της ημέρας, ως ISO στιγμή.
 *
 * 🔑 **ΤΕΛΟΣ, ΟΧΙ ΑΡΧΗ — ΚΑΙ ΕΙΝΑΙ Η ΠΡΟΘΕΣΗ ΤΟΥ ΑΝΘΡΩΠΟΥ.** Όποιος γράφει «μέχρι 31
 * Δεκεμβρίου» εννοεί ότι η 31η **μετράει**. Ένα σκέτο `T00:00:00Z` θα έληγε την εντολή
 * **ένα ολόκληρο εικοσιτετράωρο νωρίτερα** από τη συμφωνία — και η αγγελία θα
 * κατέβαινε μόνη της, με το σύστημα να «λειτουργεί σωστά».
 *
 * ⚠️ **Καθαρή συνάρτηση, κανένα ρολόι.** Η στιγμή παράγεται **μόνο** από την είσοδο,
 * ώστε ο κριτής και ο αποστολέας να μπορούν να δοκιμαστούν στα άκρα χωρίς να
 * ταξιδεύουν στον χρόνο.
 *
 * ⚠️ **Είσοδος που δεν είναι ημερομηνία ΔΕΝ ελέγχεται εδώ.** Η συνάρτηση παράγει
 * συμβολοσειρά· το *«αυτό δεν διαβάζεται ως ημερομηνία»* έχει **δικό του** κωδικό σε
 * **δύο** ήδη υπαρκτούς κριτές (`mandate-expiry-unset` στη φόρμα ·
 * `request-expiry-invalid` στο αίτημα). Τρίτος έλεγχος εδώ θα ήταν τρίτη απάντηση στο
 * ίδιο ερώτημα, και θα έκανε τους δύο πρώτους **ανεκτέλεστους** σε αυτό το μονοπάτι.
 */
export function endOfDay(yyyyMmDd: string): string {
  return `${yyyyMmDd}T23:59:59.999Z`;
}

/**
 * `yyyy-mm-dd` → **αρχή** εκείνης της ημέρας, ως ISO στιγμή (ADR-832).
 *
 * 🔑 **ΤΟ ΣΥΜΜΕΤΡΙΚΟ ΤΟΥ {@link endOfDay}, ΚΑΙ ΓΙΑ ΤΟΝ ΑΝΤΙΣΤΡΟΦΟ ΛΟΓΟ.** Όποιος
 * γράφει «ισχύει από 13 Μαρτίου» εννοεί ότι η 13η **μετράει ολόκληρη**. Ένα
 * `endOfDay` χρησιμοποιημένο και για τα δύο άκρα θα έκανε την εντολή να αρχίζει
 * στις 23:59 — δηλαδή θα της έτρωγε σχεδόν ολόκληρη την πρώτη της μέρα, σιωπηλά.
 *
 * 🔴 **ΚΑΙ ΤΟ ΚΟΣΤΟΣ ΔΕΝ ΕΙΝΑΙ ΜΟΝΟ ΑΙΣΘΗΤΙΚΟ**: η **διαδοχική** εντολή (ADR-832 §4
 * #3) στηρίζεται στο ότι το διάστημα είναι **ημι-ανοιχτό** `[από, ως)`. Με έναρξη
 * στις 23:59 της ίδιας μέρας που η προηγούμενη λήγει στις 23:59.999, τα δύο
 * διαστήματα θα **επικαλύπτονταν** κατά ένα δευτερόλεπτο — και ο προγραμματισμός θα
 * απορριπτόταν για λόγο που κανείς δεν θα μπορούσε να δει στην οθόνη.
 *
 * ⚠️ **Καθαρή συνάρτηση, κανένα ρολόι, κανένας έλεγχος** — για τους ίδιους τρεις
 * λόγους που τους απαγορεύει το {@link endOfDay}.
 */
export function startOfDay(yyyyMmDd: string): string {
  return `${yyyyMmDd}T00:00:00.000Z`;
}

/**
 * ISO στιγμή → `yyyy-mm-dd`, η μορφή που δέχεται το `<input type="date">`.
 *
 * 🔑 **Η ΑΝΤΙΣΤΡΟΦΗ ΤΟΥ {@link endOfDay}, ΚΑΙ ΖΕΙ ΔΙΠΛΑ ΤΟΥ ΕΠΙΤΗΔΕΣ.** Η φόρμα
 * προσυμπληρώνει τη λήξη από το `defaultExpiryFor`, που επιστρέφει **ISO στιγμή** —
 * άρα κάποιος πρέπει να την κόψει. Ο τεμαχισμός γραμμένος στην οθόνη θα ήταν το
 * **ίδιο** διπλότυπο, μια στροφή πιο κάτω: η γραμμή `until?.slice(0, 10) ?? ''` υπάρχει
 * **ήδη** στο `emptyMandateForm`, και η φόρμα του ιδιώτη θα την έγραφε δεύτερη φορά.
 *
 * ⚠️ **ΤΕΜΑΧΙΣΜΟΣ, ΚΑΙ ΠΟΤΕ ΤΟΠΙΚΟ ΗΜΕΡΟΛΟΓΙΟ** — `getFullYear()` / `getMonth()` /
 * `getDate()` / `toLocaleDateString()` διαβάζουν τη **ζώνη του φυλλομετρητή** και
 * μετακινούν την ημερομηνία κατά **μία ημέρα** για κάθε χρήστη ανατολικά ή δυτικά του
 * UTC. Στην Ελλάδα (UTC+3 θέρους) μια λήξη `…T23:30:00Z` θα εμφανιζόταν ως η
 * **επόμενη** ημέρα — δηλαδή η οθόνη θα έδειχνε εντολή που ξεπερνά το νόμιμο ανώτατο.
 *
 * 🔑 **Το `new Date(iso).toISOString().slice(0,10)` ΔΕΝ είναι το λάθος** — το
 * `toISOString` κανονικοποιεί σε UTC και δίνει **ταυτόσημο** αποτέλεσμα. *(Μετρήθηκε:
 * βγήκε **ισοδύναμη μετάλλαξη**, όχι κενό της άγκυρας. Η πρώτη γραφή αυτού του σχολίου
 * το κατηγορούσε λανθασμένα — και το βρήκε η μετάλλαξη, όχι η ανάγνωση.)* Είναι απλώς
 * **περιττό**: δύο μετατροπές για μια πράξη που είναι κυριολεκτικά τεμαχισμός.
 *
 * @returns `''` όταν η είσοδος είναι `null` — *«δεν υπολογίστηκε»*, ποτέ σιωπηλή
 *   σημερινή. Η φόρμα οφείλει να **σταματήσει**, όχι να προτείνει ημερομηνία που
 *   κανείς δεν παρήγαγε.
 */
export function toDateInputValue(isoInstant: string | null): string {
  return isoInstant?.slice(0, 10) ?? '';
}

/**
 * **Η ΗΜΕΡΑ ΠΟΥ ΟΝΟΜΑΖΕΙ ΕΝΑ ΑΚΡΟ ΕΝΤΟΛΗΣ**, όπως τη διαβάζει άνθρωπος (ADR-834 §6.5).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΔΕΝ ΑΡΚΕΙ ΤΟ ΚΑΘΟΛΙΚΟ `formatDate`, ΚΑΙ ΓΙΑΤΙ ΤΟ ΤΙΜΗΜΑ ΗΤΑΝ ΝΟΜΙΚΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Τα άκρα της εντολής **δεν είναι στιγμές — είναι ΠΟΛΙΤΙΚΕΣ ΗΜΕΡΕΣ** κωδικοποιημένες
 * ως στιγμές: το {@link endOfDay} γράφει `…T23:59:59.999Z` **σε UTC**, επειδή αυτό που
 * συμφώνησε ο άνθρωπος ήταν *«η 30ή Απριλίου μετράει ολόκληρη»*. Το καθολικό
 * `formatDate` μορφοποιεί στη **ζώνη του φυλλομετρητή**: στην Ελλάδα (UTC+3 θέρους) η
 * ίδια στιγμή είναι **01/05 στις 02:59**.
 *
 * 🔴 **ΜΕΤΡΗΜΕΝΟ ΣΕ ΤΡΕΙΣ ΟΘΟΝΕΣ** — και η μία είναι η οθόνη **συγκατάθεσης**, δηλαδή
 * **νομικό κείμενο**: ο ιδιοκτήτης συμφωνούσε «ως 30/04/2027» και του παρουσιαζόταν
 * «01/05/2027». Στο `OwnerMandatePanel` η ασυμμετρία ήταν ακόμη πιο ορατή, γιατί η
 * **έναρξη** γράφεται `T00:00:00.000Z` ⇒ εμφανιζόταν **σωστά** και μόνο η λήξη
 * μετακινιόταν: η ίδια περίοδος διαβαζόταν με **δύο** συμβάσεις μέσα στην ίδια παύλα.
 *
 * 🔑 **ΚΑΙ ΤΟ ΨΕΜΑ ΗΤΑΝ ΓΡΑΜΜΕΝΟ**: το `expiresHint` υπόσχεται *«Η ημέρα που δηλώνετε
 * μετράει ολόκληρη»*. Οθόνη που δείχνει **άλλη** ημέρα από τη δηλωμένη κάνει την
 * υπόσχεση **ψευδή** — ίδια κλάση με το §6.4.β, δεύτερο μέλος.
 *
 * ⚠️ **ΤΟ ΟΡΙΟ, ΡΗΤΑ: αυτό ΔΕΝ είναι για στιγμές.** Το `decidedAt` *(«πότε πάτησε ο
 * άνθρωπος»)* είναι **πραγματική στιγμή** και οφείλει να διαβάζεται στη **δική του**
 * ζώνη — εκεί το `formatDate` είναι το σωστό. Ο ίδιος τύπος (`string`), δύο σημασίες:
 * γι' αυτό η διάκριση χρειάζεται **όνομα**, όχι σχόλιο στο σημείο κλήσης.
 *
 * @param boundary  ISO στιγμή **ή** σκέτο `yyyy-mm-dd`· `null` ⇒ `''`
 */
export function formatTermDay(boundary: string | null): string {
  if (boundary === null || boundary === '') return '';

  // 🔴 **Η ΩΜΗ ΣΤΙΓΜΗ ΜΟΡΦΟΠΟΙΕΙΤΑΙ, ΠΟΤΕ ΑΝΑΚΑΤΑΣΚΕΥΑΣΜΕΝΑ ΜΕΣΑΝΥΧΤΑ.** Η πρώτη
  //    γραφή τεμάχιζε σε `yyyy-mm-dd` και ξανάχτιζε `Date.UTC(…)` — δηλαδή **μεσάνυχτα
  //    UTC**. Το αποτέλεσμα ήταν σωστό, αλλά **η ΑΠΟΔΕΙΞΗ γινόταν αδύνατη**: μεσάνυχτα
  //    UTC δεν μετακινούνται ανατολικά του UTC, οπότε η αφαίρεση του `timeZone` παρακάτω
  //    **δεν άλλαζε τίποτα** και η άγκυρα έμενε πράσινη πάνω στο ίδιο το περιστατικό
  //    (μετρημένο: 2 μεταλλάξεις επέζησαν). Με την **ωμή** στιγμή `…T23:59:59.999Z`, η
  //    αφαίρεση ουρλιάζει σε κάθε ζώνη ανατολικά — δηλαδή **εκεί που ζει το προϊόν**.
  const at = new Date(boundary.length === 10 ? `${boundary}T00:00:00.000Z` : boundary);
  if (Number.isNaN(at.getTime())) return toDateInputValue(boundary);

  // ⚠️ `timeZone: 'UTC'` είναι **ολόκληρη η διόρθωση**. Χωρίς αυτό, η ίδια γραμμή
  //    ξαναγράφει το σφάλμα με καλύτερη μορφοποίηση.
  return new Intl.DateTimeFormat(getCurrentLocale(), {
    timeZone: 'UTC',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(at);
}
