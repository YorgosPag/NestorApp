/**
 * @fileoverview **ΤΙ ΒΡΗΚΕ Η ΑΝΑΖΗΤΗΣΗ ΜΙΑΣ ΕΝΤΟΛΗΣ** — τέσσερα ονόματα, κανένα `null`.
 * @related ADR-841 §7 Α18.12 · services/mandate/mandate-detail.service.ts
 * @module lib/mandate/mandate-detail-outcome
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΤΗΝ ΥΠΗΡΕΣΙΑ — ΤΟ ΙΔΙΟ ΣΚΕΠΤΙΚΟ ΜΕ ΤΟΥΣ ΔΥΟ ΓΕΙΤΟΝΕΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το λεξιλόγιο το **γράφει ο διακομιστής** και το **διαβάζει η οθόνη** — και στη μέση
 * το διαβάζει και ο **πελάτης δικτύου**, για να ξεχωρίσει το *«δεν υπάρχει»* από το
 * *«δεν σε ακούσαμε»*.
 *
 * Σπίτι του η υπηρεσία θα σήμαινε `import` από module με `'server-only'`: για τον
 * **τύπο** δουλεύει *(σβήνεται στη μεταγλώττιση)*, για τις **σταθερές** όμως **όχι** —
 * είναι τιμές χρόνου εκτέλεσης, και το bundle του πελάτη θα έσπαγε. Ίδιο ακριβώς
 * σκεπτικό, ήδη γραμμένο, στο {@link ./mandate-client-name} και στο
 * {@link ./mandate-actions}.
 *
 * ⛔ **ΜΗΝ γράψεις σκέτο `'missing'` σε σημείο κλήσης.** Οι σταθερές υπάρχουν ώστε η
 * τέταρτη έκβαση να μην μπορεί να γεννηθεί με τυπογραφικό — και ο τύπος να **αρνείται
 * να μεταγλωττιστεί** αν κάποιος προσθέσει πέμπτη χωρίς να αποφασίσει τι σημαίνει.
 *
 * **Layering**: leaf — μόνο σταθερές και τύποι.
 */

import type { MandateCatalogRow } from '@/lib/mandate/mandate-catalog-row';

/** Η εντολή βρέθηκε, και η γραμμή της είναι έτοιμη. */
export const MANDATE_FOUND = 'found';

/**
 * **Δεν υπάρχει έγγραφο** με αυτή την ταυτότητα — *ή δεν είναι δικό σου*.
 *
 * 🔴 **ΟΙ ΔΥΟ ΚΟΣΜΟΙ ΕΝΩΝΟΝΤΑΙ ΕΠΙΤΗΔΕΣ ΣΤΟ ΣΥΡΜΑ, ΚΑΙ ΜΟΝΟ ΕΚΕΙ.** Ο διακομιστής
 * ξεχωρίζει το {@link MANDATE_NOT_YOURS} και το **καταγράφει**· η απόκριση τα λέει
 * **ταυτόσημα**. Αν διέφεραν, η διαδρομή θα γινόταν **μετρητής ύπαρξης**: ρωτάς 1.000
 * ταυτότητες και μαθαίνεις ποιες υπάρχουν σε *κάποιο* γραφείο.
 *
 * ⚠️ Είναι το **ίδιο** δόγμα που ήδη γράφει ο πίνακας του `respondToAction` για το
 * `absent`: *«403 θα επιβεβαίωνε ξένο έγγραφο»*.
 */
export const MANDATE_MISSING = 'missing';

/**
 * Υπάρχει, αλλά **ανήκει σε άλλο γραφείο**.
 *
 * ⛔ **ΔΕΝ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΦΤΑΣΕΙ ΣΕ ΠΕΛΑΤΗ.** Ζει για τα **ίχνη του διακομιστή**, όπου
 * η διάκριση έχει αξία *(«κάποιος ζήτησε εντολή εκτός εμβέλειας»)*. Ο τύπος της
 * απόκρισης το αποκλείει **δομικά** — δες `MandateDetailResponse`.
 */
export const MANDATE_NOT_YOURS = 'not-yours';

/**
 * Υπάρχει, είναι δικό μας, αλλά **δεν φέρει εντολή**.
 *
 * 🔑 **ΔΕΝ είναι απουσία — είναι πληροφορία**, και γι' αυτό ταξιδεύει με `200`: η
 * αγγελία μπορεί να είναι απλή καταχώρηση, ή η εντολή να **ανακλήθηκε**. Δύο υπαρκτές
 * κουβέντες, καμία από τις οποίες είναι «δεν βρέθηκε».
 */
export const MANDATE_NOT_A_MANDATE = 'not-a-mandate';

/**
 * **Τι απάντησε η ανάγνωση** — κλειστό σύνολο, καμία σιωπηλή περίπτωση.
 *
 * 🔑 Διακριτή ένωση και όχι `MandateCatalogRow | null`, γιατί ακριβώς αυτό θα ήταν το
 * ελάττωμα: ένα `null` θα κουβαλούσε **τρεις** κόσμους και η οθόνη θα διάλεγε έναν —
 * το ίδιο σχήμα που το ADR-834 §6.5.δ πλήρωσε ήδη μία φορά με το `clientName`.
 */
export type MandateDetailOutcome =
  | { readonly kind: typeof MANDATE_FOUND; readonly row: MandateCatalogRow }
  | { readonly kind: typeof MANDATE_MISSING }
  | { readonly kind: typeof MANDATE_NOT_YOURS }
  | { readonly kind: typeof MANDATE_NOT_A_MANDATE };

/**
 * **Ό,τι επιτρέπεται να φύγει στο σύρμα** — τρεις από τις τέσσερις.
 *
 * 🔴 Το `Extract`/`Exclude` δεν είναι κομψότητα: κάνει την παράλειψη του
 * {@link MANDATE_NOT_YOURS} **δομική**. Μια μελλοντική πέμπτη έκβαση θα μπει εδώ
 * **μόνο αν κάποιος το γράψει** — δεν κληρονομείται σιωπηλά.
 */
export type MandateDetailResponse = Exclude<
  MandateDetailOutcome,
  { readonly kind: typeof MANDATE_NOT_YOURS }
>;

/**
 * **Μετράει αυτό το σώμα ως «δεν βρέθηκε»;** — ο ΕΝΑΣ κριτής, για τον πελάτη δικτύου.
 *
 * ⚠️ Δέχεται `unknown` επίτηδες: ο καλών του δίνει **ωμό σώμα σφάλματος** από το
 * δίκτυο, που κανείς δεν επαλήθευσε. Ένα σκέτο `body.kind === 'missing'` θα ήταν
 * ισχυρισμός τύπου πάνω σε ό,τι έτυχε να γυρίσει ο διακομιστής.
 */
export function isMandateMissingBody(body: unknown): boolean {
  return (
    typeof body === 'object' &&
    body !== null &&
    (body as { kind?: unknown }).kind === MANDATE_MISSING
  );
}
