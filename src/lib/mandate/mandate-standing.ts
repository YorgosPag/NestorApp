/**
 * @fileoverview **ΠΟΥ ΣΤΕΚΕΤΑΙ Η ΕΝΤΟΛΗ** — το λεξιλόγιο του καταλόγου του γραφείου.
 * @related ADR-777 §8.34 · types/owner-property-mandate.ts · lib/mandate/mandate-form-values.ts
 * @module lib/mandate/mandate-standing
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΙ ΕΙΝΑΙ ΑΥΤΟ, ΚΑΙ — ΠΙΟ ΣΗΜΑΝΤΙΚΟ — ΤΙ ΔΕΝ ΕΙΝΑΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * **ΔΕΝ είναι δεύτερος κριτής δημοσίευσης.** Το «φτάνει αυτή η αγγελία στον κόσμο;»
 * απαντιέται **μία** φορά, από το {@link mandateAllowsPublication} — και ένας δεύτερος
 * τόπος που απαντά το ίδιο ερώτημα με δικό του λεξιλόγιο είναι, κατά γράμμα, το σχήμα
 * του **ADR-749**. Εδώ απαντιέται **άλλο** ερώτημα, που κανείς δεν είχε ρωτήσει:
 *
 * > **«Τι πρέπει να κάνει το γραφείο ΤΩΡΑ με αυτή τη γραμμή;»**
 *
 * Είναι **τριάζ**, όχι πύλη. Καμία τιμή του δεν εμποδίζει τίποτα· κάθε τιμή του
 * **ονομάζει μια δουλειά**. Γι' αυτό η συνάρτηση είναι καθαρή, δέχεται τον χρόνο ως
 * όρισμα και δεν αγγίζει δίκτυο.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Η ΕΡΕΥΝΑ ΠΟΥ ΟΡΙΣΕ ΤΙΣ ΚΑΤΑΣΤΑΣΕΙΣ — ΤΟ DOCUSIGN ΚΑΙ ΤΟ MLS, ΜΕΤΡΗΜΕΝΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ερώτημα *«έστειλα κάτι για έγκριση — τι απέγινε;»* το έχει λύσει **το DocuSign**,
 * και το λεξιλόγιό του είναι η αυθεντία της αγοράς:
 *
 * | DocuSign | Τι σημαίνει (κατά λέξη από την τεκμηρίωσή του) | Εδώ |
 * |---|---|---|
 * | `Sent` | στάλθηκε | {@link BrokeredListingMandate.notifiedAt} |
 * | `Delivered` | *«all recipients have **viewed** the documents… clicked on the link… but did not sign»* | {@link BrokeredListingMandate.viewedAt} |
 * | `Completed` | υπεγράφη | `confirmation: 'confirmed'` |
 * | `Declined` | *«a **terminal** state — the envelope can no longer be voided»* | `confirmation: 'declined'` |
 * | `Voided` | *«only… still in-process: Created, Sent, or Delivered»* | `consentNonce: null` |
 *
 * Και οι **ομάδες** της αρχικής του οθόνης — *Action Required · Waiting for Others ·
 * Expiring Soon · Completed* — είναι ακριβώς οι ομάδες που χρειάζεται ένα μεσιτικό
 * γραφείο, με **μία** μετάφραση: το «Action Required» του DocuSign σημαίνει *«πρέπει
 * να **υπογράψεις** εσύ»*· εδώ σημαίνει *«ο πελάτης **δεν μπορεί** να απαντήσει μέχρι
 * να κάνεις κάτι εσύ»*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΠΟΥ ΤΟΥΣ ΞΕΠΕΡΝΑΜΕ — ΔΥΟ ΚΑΤΑΣΤΑΣΕΙΣ ΠΟΥ ΔΕΝ ΜΠΟΡΟΥΝ ΝΑ ΕΚΦΡΑΣΟΥΝ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * 1. **{@link NEVER_NOTIFIED} — «δεν του το είπαμε ποτέ».** Στο DocuSign είναι
 *    **δομικά αδύνατο**: φάκελος χωρίς διεύθυνση παραλήπτη δεν γεννιέται. Στο MLS
 *    είναι αδύνατο γιατί η έγκριση του ιδιοκτήτη **δεν παρακολουθείται καθόλου** — το
 *    χαρτί μένει *«a broker's responsibility»* στο ντοσιέ. Εδώ γεννιέται φυσιολογικά:
 *    **επαφή χωρίς email**. Είναι η **σιωπηλά χαμένη** εντολή — αυτή που ο μεσίτης
 *    νομίζει ότι περιμένει απάντηση, ενώ δεν ρώτησε ποτέ κανέναν.
 *
 * 2. **{@link UNANNOUNCED_LIVE} — «διαφημίζεται και ο ιδιοκτήτης δεν το έμαθε».**
 *    Γεννιέται **μόνο** στον δρόμο της βεβαίωσης γραφείου: η εντολή είναι `confirmed`
 *    από τη γέννησή της, άρα η αγγελία **είναι ήδη στον χάρτη**, αλλά η ειδοποίηση
 *    αντίρρησης δεν έφυγε ποτέ. 🔴 **Είναι ο μόνος τρόπος να πέσει η δικαιολόγηση
 *    ολόκληρου του δρόμου της βεβαίωσης**: το {@link ../../types/owner-property-mandate}
 *    δέχτηκε τη βεβαίωση χωρίς υποχρεωτικό έγγραφο ρητά επειδή *«ο ιδιοκτήτης
 *    **ειδοποιείται** και μπορεί να πει “όχι” ανά πάσα στιγμή»*. Αν δεν ειδοποιήθηκε,
 *    ο φρουρός δεν χαλάρωσε — **δεν υπάρχει**.
 *
 * ⚠️ **Οι δύο ΔΕΝ είναι μία κατάσταση με δύο ονόματα.** Και οι δύο λένε
 * «`notifiedAt === null`», αλλά στη μία **τίποτα δεν είναι δημόσιο** και στην άλλη
 * **όλα είναι**. Ένα κοινό όνομα θα ισοπέδωνε ένα ζήτημα συμμόρφωσης με μια
 * εκκρεμότητα γραμματείας.
 *
 * **Layering**: leaf — καθαροί τύποι + καθαρές συναρτήσεις. Καμία εξάρτηση από δίκτυο,
 * κανένα ρολόι διαβασμένο μέσα (ίδιος κανόνας με το `isMandateExpired`).
 */

import type { BrokeredListingMandate } from '@/types/owner-property-mandate';

