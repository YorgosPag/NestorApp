/**
 * **Δεκατέσσερις μέρες** — πόσο πριν τη λήξη η εντολή αρχίζει να ζητά προσοχή.
 *
 * 🔴 **Ο αριθμός βγήκε από μέτρηση της αγοράς, ΟΧΙ από προτίμηση**, και το συγκρίσιμο
 * αντικείμενο **δεν είναι ο φάκελος υπογραφής**:
 *
 * | Πηγή | Παράθυρο | Τι αφορά |
 * |---|---|---|
 * | DocuSign «Expiring Soon» | **6 μέρες** | **φάκελο υπογραφής** — ζει μέρες |
 * | Paragon MLS (widget ημερολογίου) | **7 μέρες** | **εντολή πώλησης** |
 * | connectMLS (Bulletins/Updates) | **14 μέρες** | **εντολή πώλησης** |
 *
 * Η δική μας εντολή ζει **δώδεκα μήνες** και η ανανέωσή της απαιτεί **νέο έγγραφο**
 * (άρθρο 200 Ν.4072/2012 — δεν παρατείνεται με ένα κλικ). Άρα το συγκρίσιμο είναι η
 * **εντολή**, όχι ο φάκελος, και μέσα στο εύρος 7–14 κρατιέται το **μεγαλύτερο**: το
 * μικρότερο θα ειδοποιούσε το γραφείο όταν πια δεν προλαβαίνει να κλείσει ραντεβού.
 *
 * ⚠️ **ΔΕΝ είναι όριο και δεν εμποδίζει τίποτα.** Μια εντολή που λήγει σε 15 μέρες
 * είναι εξίσου έγκυρη με μία που λήγει σε 13· αλλάζει μόνο **σε ποια ομάδα κάθεται**
 * στην οθόνη.
 */
export const MANDATE_EXPIRY_HORIZON_DAYS = 14;

const MILLISECONDS_PER_DAY = 24 * 60 * 60 * 1000;

// =============================================================================
// 2. ΟΙ ΚΑΤΑΣΤΑΣΕΙΣ — κλειστό σύνολο, καμία σιωπηλή
// =============================================================================

/** Ο ιδιοκτήτης είπε **όχι**. Τερματική, όπως το `Declined` του DocuSign. */
export const DECLINED = 'declined';

/** Ήταν ζωντανή και **έληξε**. Η κουβέντα είναι **ανανέωση**. */
export const EXPIRED = 'expired';

/** Έληξε **χωρίς να απαντήσει ποτέ** κανείς. Η κουβέντα είναι **από την αρχή**. */
export const EXPIRED_UNANSWERED = 'expired-unanswered';

/** 🔴 **Διαφημίζεται, και ο ιδιοκτήτης δεν το έμαθε ποτέ.** Ζήτημα συμμόρφωσης. */
export const UNANNOUNCED_LIVE = 'unannounced-live';

/** 🔴 **Δεν του το είπαμε ποτέ** — και περιμένουμε απάντηση που δεν ζητήθηκε. */
export const NEVER_NOTIFIED = 'never-notified';

/** Ο σύνδεσμος **ανακλήθηκε** ενώ η απάντηση εκκρεμεί ⇒ δεν μπορεί πια να απαντήσει. */
export const LINK_REVOKED = 'link-revoked';

/** Του στάλθηκε και **δεν το άνοιξε**. Το `Sent` του DocuSign που δεν έγινε `Delivered`. */
export const AWAITING_VIEW = 'awaiting-view';

/** **Το άνοιξε και δεν απάντησε.** Το `Delivered` του DocuSign. */
export const AWAITING_DECISION = 'awaiting-decision';

/** Ενεργή, αλλά **λήγει μέσα στον ορίζοντα**. */
export const EXPIRING_SOON = 'expiring-soon';

/** Ενεργή, με χρόνο μπροστά της. Τίποτα να γίνει. */
export const LIVE = 'live';

/**
 * **Οι δέκα καταστάσεις**, σε σειρά **επείγοντος** — και η σειρά είναι συμβόλαιο.
 *
 * 🔑 Ο κατάλογος ταξινομείται με αυτήν, όχι με ημερομηνία: μια οθόνη τριάζ που
 * ξεκινά από «τι έγινε τελευταίο» απαντά σε ερώτηση που κανείς δεν έκανε. Το πρώτο
 * πράγμα που βλέπει ο μεσίτης οφείλει να είναι το πρώτο που πρέπει να κάνει.
 *
 * ⚠️ **Ο πίνακας είναι Η αυθεντία της σειράς** — καμία δεύτερη λίστα βαρών κάπου
 * αλλού (θα απέκλινε στην πρώτη προσθήκη, το σχήμα των δύο λιστών namespace της
 * CHECK 3.34).
 */
export const MANDATE_STANDINGS = [
  UNANNOUNCED_LIVE,
  NEVER_NOTIFIED,
  LINK_REVOKED,
  EXPIRING_SOON,
  AWAITING_DECISION,
  AWAITING_VIEW,
  DECLINED,
  EXPIRED,
  EXPIRED_UNANSWERED,
  LIVE,
] as const;

export type MandateStanding = (typeof MANDATE_STANDINGS)[number];

// =============================================================================
// 3. ΟΙ ΟΜΑΔΕΣ — τέσσερις κάδοι, όπως η αρχική του DocuSign
// =============================================================================

/** ⛔ **Ο πελάτης ΔΕΝ ΜΠΟΡΕΙ να προχωρήσει μέχρι να κάνει κάτι το γραφείο.** */
export const NEEDS_US = 'needs-us';

/** Η μπάλα είναι στον πελάτη. Το `Waiting for Others` του DocuSign. */
export const WAITING_CLIENT = 'waiting-client';

/** Ζωντανή και μετρά αντίστροφα. Το `Expiring Soon`. */
export const EXPIRING = 'expiring';

/** Ζωντανή, ήσυχη. */
export const SETTLED = 'settled';

/** Τέλειωσε — με «όχι» ή με τον χρόνο. */
export const CLOSED = 'closed';

export const MANDATE_STANDING_GROUPS = [
  NEEDS_US,
  WAITING_CLIENT,
  EXPIRING,
  SETTLED,
  CLOSED,
] as const;

export type MandateStandingGroup = (typeof MANDATE_STANDING_GROUPS)[number];

/**
 * **Ποια κατάσταση σε ποιον κάδο** — ρητά, χωρίς `default`.
 *
 * ⚠️ Ένδεκατη κατάσταση **δεν μεταγλωττίζεται** μέχρι κάποιος να αποφασίσει σε ποια
 * ομάδα ανήκει. Είναι το ίδιο ιδίωμα με το `respondToWrite`.
 */
export function groupOfStanding(standing: MandateStanding): MandateStandingGroup {
  switch (standing) {
    case UNANNOUNCED_LIVE:
    case NEVER_NOTIFIED:
    case LINK_REVOKED:
      return NEEDS_US;
    case AWAITING_VIEW:
    case AWAITING_DECISION:
      return WAITING_CLIENT;
    case EXPIRING_SOON:
      return EXPIRING;
    case LIVE:
      return SETTLED;
    case DECLINED:
    case EXPIRED:
    case EXPIRED_UNANSWERED:
      return CLOSED;
  }
}

