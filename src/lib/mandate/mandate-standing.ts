// 4. Ο ΤΑΞΙΝΟΜΗΤΗΣ
// =============================================================================

/**
 * **Πού στέκεται αυτή η εντολή**, τη στιγμή `nowISOValue`.
 *
 * 🔴 **Η ΣΕΙΡΑ ΤΩΝ ΕΡΩΤΗΣΕΩΝ ΕΙΝΑΙ ΤΟ ΣΥΜΒΟΛΑΙΟ**, και κάθε βήμα δικαιολογείται:
 *
 * 1. **`declined` πρώτα, ακόμη κι αν έχει λήξει.** Ο άνθρωπος **μίλησε**· το ότι
 *    πέρασε από τότε ένας χρόνος δεν αλλάζει την απάντησή του. Το DocuSign λέει το
 *    ίδιο: `Declined` είναι **τερματική**.
 * 2. **Η λήξη πριν από όλα τα υπόλοιπα.** Ληγμένη εντολή δεν «περιμένει απάντηση» —
 *    δεν υπάρχει απάντηση που να τη σώζει. Ο διαχωρισμός σε {@link EXPIRED} και
 *    {@link EXPIRED_UNANSWERED} γίνεται εδώ γιατί οδηγεί σε **διαφορετική κουβέντα**.
 * 3. **`notifiedAt === null` πριν από τη διάκριση «άνοιξε/δεν άνοιξε»** — αλλιώς μια
 *    εντολή που δεν στάλθηκε ποτέ θα εμφανιζόταν ως «δεν την άνοιξε», δηλαδή θα
 *    κατηγορούσε τον πελάτη για δική μας παράλειψη.
 * 4. **Η ανάκληση συνδέσμου κρίνεται ΜΟΝΟ σε εκκρεμή εντολή.** Σε `confirmed` το
 *    `consentNonce` δεν αλλάζει καμία επόμενη δουλειά, και η ίδια η ενέργεια
 *    ανάκλησης απαγορεύεται εκεί ({@link ../../services/mandate/mandate-actions.service}).
 *
 * @param nowISOValue — η **περασμένη** στιγμή, ποτέ `new Date()` εδώ μέσα: όλος ο
 *   κατάλογος πρέπει να κριθεί με **ένα** ρολόι, αλλιώς δύο γραμμές του ίδιου πίνακα
 *   μπορούν να διαφωνήσουν για το αν σήμερα είναι η μέρα της λήξης.
 */
export function mandateStandingOf(
  mandate: BrokeredListingMandate,
  nowISOValue: string,
): MandateStanding {
  if (mandate.confirmation === 'declined') return DECLINED;

  const now = Date.parse(nowISOValue);
  const expiry = Date.parse(mandate.expiresAt);

  // ⚠️ Μη αναγνώσιμη λήξη ⇒ **ληγμένη**, όχι «ζωντανή». Το ίδιο κάνει και ο κριτής
  // δημοσίευσης (`Date.parse` → `NaN` ⇒ `NaN <= now` είναι `false`… γι' αυτό εδώ
  // ρωτιέται **ρητά**): μια εντολή που δεν ξέρουμε πότε λήγει δεν επιτρέπεται να
  // κάθεται σιωπηλά στο «όλα καλά».
  const expired = Number.isNaN(expiry) || expiry <= now;
  if (expired) {
    return mandate.confirmation === 'confirmed' ? EXPIRED : EXPIRED_UNANSWERED;
  }

  if (mandate.notifiedAt === null) {
    return mandate.confirmation === 'confirmed' ? UNANNOUNCED_LIVE : NEVER_NOTIFIED;
  }

  if (mandate.confirmation === 'pending') {
    if (mandate.consentNonce === null) return LINK_REVOKED;
    return mandate.viewedAt === null ? AWAITING_VIEW : AWAITING_DECISION;
  }

  return expiry - now <= MANDATE_EXPIRY_HORIZON_DAYS * MILLISECONDS_PER_DAY
    ? EXPIRING_SOON
    : LIVE;
}

/**
 * **Πόσες μέρες μένουν** μέχρι τη λήξη — στρογγυλοποιημένες **προς τα πάνω**.
 *
 * ⚠️ **Προς τα πάνω, και είναι απόφαση**: «λήγει σε 0 μέρες» για μια εντολή που ισχύει
 * ακόμη τρεις ώρες είναι **ψέμα προς τα κάτω** — ο μεσίτης θα υπέθετε ότι χάθηκε και
 * δεν θα τηλεφωνούσε. `null` όταν η λήξη δεν διαβάζεται ή έχει ήδη περάσει: εκεί ο
 * αριθμός δεν έχει νόημα και η κατάσταση το λέει ήδη.
 */
export function daysUntilExpiry(
  mandate: BrokeredListingMandate,
  nowISOValue: string,
): number | null {
  const expiry = Date.parse(mandate.expiresAt);
  const now = Date.parse(nowISOValue);
  if (Number.isNaN(expiry) || Number.isNaN(now) || expiry <= now) return null;
  return Math.ceil((expiry - now) / MILLISECONDS_PER_DAY);
}
