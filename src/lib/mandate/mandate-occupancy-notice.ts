/**
 * @fileoverview **ΤΙ ΒΛΕΠΕΙ Ο ΙΔΙΟΚΤΗΤΗΣ ΠΡΙΝ ΠΡΟΣΠΑΘΗΣΕΙ** — η κατάληψη, με όνομα.
 * @related ADR-832 §4 · lib/mandate/mandate-conflict.ts · types/owner-property-mandate.ts
 * @module lib/mandate/mandate-occupancy-notice
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΕΔΩ ΞΕΠΕΡΝΑΜΕ ΤΗΝ ΑΓΟΡΑ, ΚΑΙ ΤΟ ΠΡΟΤΥΠΟ ΕΙΝΑΙ ΤΟ REVIT — ΟΧΙ ΤΑ MLS
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Τα MLS λύνουν την αποκλειστικότητα με **δήλωση του μεσίτη** και **αφαίρεση εκ των
 * υστέρων**: ο άνθρωπος στέλνει, περιμένει, και μαθαίνει *«Invalid»* — χωρίς ποτέ να
 * μάθει **ποιος** τον εμποδίζει ούτε **τι μπορεί** να κάνει.
 *
 * Το **Revit** λύνει το ίδιο ακριβώς πρόβλημα αλλιώς, και εδώ το δανειζόμαστε: τα
 * *worksets* δείχνουν την **ιδιοκτησία στοιχείου ΠΡΙΝ** προσπαθήσεις να το πειράξεις —
 * ποιος το κρατά, και τι σε αφήνει να κάνεις. Η αποτυχία δεν είναι έκπληξη· είναι
 * **προβλέψιμη**, γιατί είναι **ορατή**.
 *
 * 🏆 **ΚΑΙ ΠΑΜΕ ΕΝΑ ΒΗΜΑ ΠΑΡΑΠΕΡΑ ΑΠΟ ΤΟ REVIT**: εκεί, το «κρατημένο» είναι
 * κατάσταση χωρίς **ορίζοντα** — περιμένεις τον συνάδελφο να το αφήσει, χωρίς να
 * ξέρεις πότε. Η εντολή **έχει λήξη**, άρα το εμπόδιο έχει **ημερομηνία**. Το
 * {@link MandateOccupancyNotice} τη λέει, και το `availableFrom` την κάνει
 * **ενέργεια**: *«κλείσε εντολή που αρχίζει 13/03»*. Κανένα MLS δεν το προσφέρει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ ΤΙ ΔΕΝ ΕΙΝΑΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * ⛔ **Δεν είναι δεύτερος κριτής.** Ο κανόνας ζει στο `mandate-conflict.ts` και
 * καλείται **αυτούσιος**· εδώ γίνεται μόνο η **παρουσίαση**: ποια είναι η νωρίτερη
 * ελεύθερη στιγμή, και ποιες καταλήψεις αξίζει να δει ο άνθρωπος. Ένας δεύτερος
 * κανόνας εδώ θα ήταν οθόνη που **διαφωνεί** με τον διακομιστή — το χειρότερο είδος
 * σφάλματος, γιατί ο άνθρωπος βλέπει «εντάξει» και εισπράττει «όχι».
 *
 * ⛔ **Δεν είναι φρουρός.** Ο διακομιστής κρίνει ξανά, με τα φρέσκα (N.7.2 #4). Αυτό
 * εδώ υπάρχει ώστε ο άνθρωπος να **μη φτάσει** στην άρνηση, όχι για να την
 * αντικαταστήσει.
 *
 * ⛔ **Δεν διαβάζει ρολόι και δεν αγγίζει Firestore.** Καθαρές συναρτήσεις — γι' αυτό
 * ολόκληρος ο πίνακας δοκιμάζεται στα άκρα χωρίς να ταξιδέψει κανείς στον χρόνο.
 *
 * **Layering**: leaf.
 */

import { earliestFreeStart } from '@/lib/occupancy/occupancy-horizon';
import {
  mandateConflicts,
  type MandateConflict,
  type MandateOccupancy,
} from '@/lib/mandate/mandate-conflict';
import {
  bindingMandates,
  isMandateExpired,
  occupancyOf,
  type BrokeredListingMandate,
} from '@/types/owner-property-mandate';

// =============================================================================
// 1. Η ΕΙΚΟΝΑ ΤΗΣ ΚΑΤΑΛΗΨΗΣ
// =============================================================================

/**
 * **Τι ξέρει η οθόνη για τον πόρο.** Κλειστό σύνολο — ποτέ `boolean` + λίστα.
 *
 * ⚠️ **Το `occupied` ΔΕΝ είναι «μπλοκαρισμένο», και η διάκριση είναι όλο το νόημα**:
 * ακίνητο με **απλή** εντολή σε δύο γραφεία είναι κατειλημμένο και **απολύτως
 * διαθέσιμο** για τρίτο. Ένα κοινό σκέλος θα ξανάφερνε το ελάττωμα του ADR-832 §1 —
 * *«έχει γραφείο; τέλος»* — στην οθόνη αυτή τη φορά, όπου καμία πύλη δεν το βλέπει.
 */
export type MandateOccupancyNotice =
  /** Κανείς δεν κρατά τίποτα δεσμευτικό σε αυτό το ακίνητο. */
  | { readonly kind: 'free' }
  /**
   * Κάποιος κρατά — αλλά οι **προτεινόμενοι** όροι στέκουν δίπλα του. Η οθόνη το
   * λέει ως **πληροφορία**, ποτέ ως εμπόδιο.
   */
  | { readonly kind: 'occupied'; readonly held: readonly MandateOccupancy[] }
  /**
   * Οι όροι **δεν** στέκουν. Ταξιδεύουν **όλες** οι συγκρούσεις, και η νωρίτερη
   * στιγμή που ο πόρος ελευθερώνεται.
   */
  | {
      readonly kind: 'blocked';
      readonly conflicts: readonly MandateConflict[];
      /**
       * 🏆 **Η ΔΙΕΞΟΔΟΣ, ΩΣ ΗΜΕΡΟΜΗΝΙΑ.** `null` όταν δεν υπάρχει — είτε γιατί μια
       * κατάληψη είναι **ανοιχτής διάρκειας**, είτε γιατί η σύγκρουση δεν λύνεται με
       * αναμονή (ο **υποψήφιος** είναι ο αποκλειστικός: τότε ο άνθρωπος αλλάζει
       * **είδος**, δεν περιμένει).
       */
      readonly availableFrom: string | null;
    }
  /**
   * 🔴 **Δεν μπορέσαμε να κρίνουμε** — χαλασμένο διάστημα σε υπάρχουσα εντολή.
   * Ποτέ ίδιο με «ελεύθερο» (N.12): η οθόνη οφείλει να πει *«δεν ξέρω»*, γιατί ένα
   * σιωπηλό «ελεύθερο» θα έστελνε τον άνθρωπο σε άρνηση που του υποσχεθήκαμε ότι
   * δεν θα συναντήσει.
   */
  | { readonly kind: 'undetermined'; readonly unreadable: readonly MandateOccupancy[] };

// =============================================================================
// 2. Ο ΥΠΟΛΟΓΙΣΜΟΣ
// =============================================================================

/**
 * **Οι καταλήψεις που αξίζει να δει ο άνθρωπος** — δεσμευτικές και **όχι ληγμένες**.
 *
 * 🔑 **Δεν είναι το `activeMandates`, και δεν είναι λάθος.** Το `activeMandates`
 * κόβει και ό,τι **δεν έχει αρχίσει** — αλλά μια εντολή που αρχίζει σε δύο μήνες
 * **είναι** ό,τι πιο χρήσιμο μπορεί να μάθει ο ιδιοκτήτης πριν προτείνει όρους. Το
 * μόνο που δεν αξίζει να δει είναι ό,τι **τελείωσε**.
 *
 * ⚠️ **`bindingMandates` πρώτα**, ποτέ ωμό φιλτράρισμα: η ανάκληση άδειας
 * (`agencyRevokedAt`) και η μη εγκεκριμένη εντολή κρίνονται **εκεί**, μία φορά.
 */
export function visibleOccupancies(
  mandates: readonly BrokeredListingMandate[],
  nowISOValue: string,
): readonly MandateOccupancy[] {
  return bindingMandates(mandates)
    .filter((mandate) => !isMandateExpired(mandate, nowISOValue))
    .map(occupancyOf);
}

/**
 * 🏆 **ΑΠΟ ΠΟΤΕ ΕΙΝΑΙ ΕΛΕΥΘΕΡΟΣ Ο ΠΟΡΟΣ;** — **ΕΠΑΝΕΞΑΓΩΓΗ**, όχι δεύτερη γραφή.
 *
 * 🔴 **ΜΕΤΑΚΟΜΙΣΕ στο `lib/occupancy/occupancy-horizon.ts` (ADR-835 Φ3), και ο λόγος
 * είναι ότι ΠΟΤΕ ΔΕΝ ΗΤΑΝ ΤΩΝ ΕΝΤΟΛΩΝ.** Διάβαζε `conflict.reason` και
 * `conflict.with.expiresAt` — **δύο πεδία του ίδιου του κριτή**, μηδέν από τον τομέα
 * της μεσιτείας. Ήταν δεμένο εδώ μόνο από τον **τύπο** του, δηλαδή κατά λάθος.
 *
 * Ο **δεύτερος** καταναλωτής (η βραχυχρόνια: *«κρατημένο ως 14/08»*) το ζήτησε
 * αυτούσιο. Μια δεύτερη γραφή εκεί θα ήταν **δίδυμο αόρατο στο `ssot:discover`**
 * (name-based) — ακριβώς το σχήμα που το N.18 υπάρχει για να πιάσει.
 *
 * ⚠️ Επανεξάγεται ώστε **καμία** υπάρχουσα εισαγωγή και **καμία** υπάρχουσα άγκυρα
 * (`mandate-occupancy-notice.test.ts` Ξ) να μη χρειαστεί να αλλάξει: μετακινήθηκε ο
 * **ορισμός**, όχι οι καταναλωτές (κανόνας 19).
 */
export { earliestFreeStart };

/**
 * **Η εικόνα που δείχνει η οθόνη** — μία κλήση, μία απάντηση.
 *
 * @param mandates — οι εντολές του **επιλεγμένου** ακινήτου, ωμές όπως ήρθαν.
 * @param candidate — οι όροι που πληκτρολογεί ο άνθρωπος **αυτή τη στιγμή**, ή `null`
 *   όσο δεν έχει διαλέξει ακόμη πράξεις. Με `null` η οθόνη λέει μόνο *«ποιος κρατά»* —
 *   και είναι σωστό: χωρίς όρους **δεν υπάρχει ερώτημα σύγκρουσης** να απαντηθεί.
 * @param nowISOValue — η **περασμένη** στιγμή· κανένα ρολόι εδώ μέσα.
 */
export function occupancyNotice(
  mandates: readonly BrokeredListingMandate[],
  candidate: MandateOccupancy | null,
  nowISOValue: string,
): MandateOccupancyNotice {
  const held = visibleOccupancies(mandates, nowISOValue);
  if (held.length === 0) return { kind: 'free' };
  if (candidate === null) return { kind: 'occupied', held };

  // 🔑 **Ο ΚΑΝΟΝΑΣ ΚΑΛΕΙΤΑΙ ΑΥΤΟΥΣΙΟΣ** — ο ίδιος που θα τρέξει ο διακομιστής.
  const verdict = mandateConflicts(candidate, held);

  switch (verdict.kind) {
    case 'conflicts':
      return {
        kind: 'blocked',
        conflicts: verdict.conflicts,
        availableFrom: earliestFreeStart(verdict.conflicts),
      };
    case 'undetermined':
      return { kind: 'undetermined', unreadable: verdict.unreadable };
    case 'clear':
      return { kind: 'occupied', held };
  }
}
