/**
 * **Ο πίνακας με το στοιχείο του κλειδιού ΣΤΗΝ ΚΟΡΥΦΗ — ή `null` αν δεν υπάρχει.**
 *
 * 🔴 **ΤΟ `null` ΕΙΝΑΙ ΤΟ ΝΟΗΜΑ ΤΗΣ ΕΞΑΓΩΓΗΣ, ΟΧΙ ΠΑΡΕΝΕΡΓΕΙΑ** (ADR-841 §7 Α14.7.4).
 *
 * Οι δύο καταναλωτές θέλουν την **ίδια** μετακίνηση και **αντίθετη** πολιτική για το
 * απόν κλειδί:
 *
 * | Καταναλωτής | Απόν κλειδί ⇒ | Γιατί |
 * |---|---|---|
 * | `withOwnerMediaFirst` | **ο ίδιος πίνακας** | ο πίνακάς του **είναι** η συμμετοχή — προσθήκη θα δημοσίευε αρχείο που κανείς δεν ζήτησε |
 * | `withDeclaredFirst` | **μπροστά** | η δήλωσή του **δεν** είναι συμμετοχή — η προσθήκη **είναι** η πράξη |
 *
 * Μια παράμετρος `onMissing` θα έκρυβε αυτή τη διαφορά **μέσα** στη μηχανή, όπου κανείς
 * δεν τη διαβάζει. Επιστρέφοντας `null`, η μηχανή **αναγκάζει** κάθε πλευρά να γράψει
 * την πολιτική της στο **σημείο κλήσης** — μία γραμμή, ορατή δίπλα στον λόγο της.
 *
 * ⚠️ **Ταιριάζει η ΠΡΩΤΗ εμφάνιση**, και τα υπόλοιπα διατηρούν τη σχετική τους σειρά:
 * η μετακίνηση οφείλει να είναι **μετάθεση**, ποτέ φιλτράρισμα.
 */
export function promoteToFront<T>(
  items: readonly T[],
  keyOf: (item: T) => string,
  key: string,
): readonly T[] | null {
  const index = items.findIndex((item) => keyOf(item) === key);
  if (index === -1) return null;

  return [items[index], ...items.slice(0, index), ...items.slice(index + 1)];
}

/**
 * **«Να μπει πρώτο»** πάνω σε **δήλωση σειράς** — ο πίνακας κλειδιών, με αυτό μπροστά.
 *
 * 🔑 **Απόν κλειδί ⇒ μπαίνει μπροστά**, και είναι ακριβώς η πράξη: η δήλωση είναι
 * **αραιή** *(τα περισσότερα κλειδιά δεν είναι ποτέ σε αυτήν)*, άρα η πρώτη φορά που ο
 * άνθρωπος λέει *«αυτό πρώτο»* είναι **πάντα** για κλειδί που λείπει. Ένα `?? declared`
 * εδώ θα έκανε την πράξη **να μην κάνει τίποτα** ακριβώς στην περίπτωση για την οποία
 * υπάρχει.
 *
 * ⚠️ **Ιδempotent**: δεύτερη κλήση με το ίδιο κλειδί δίνει **τον ίδιο** πίνακα *(είναι
 * ήδη στη θέση 0)*, και ο διπλότυπος **δεν** γεννιέται — η {@link promoteToFront}
 * μεταθέτει, δεν αντιγράφει.
 */
export function withDeclaredFirst(
  declared: readonly string[],
  key: string,
): readonly string[] {
  return promoteToFront(declared, (entry) => entry, key) ?? [key, ...declared];
}

/**
 * **Η ΟΛΙΚΗ ΣΕΙΡΑ: δηλωμένο πρόθεμα, μετά η ντετερμινιστική ουρά.**
 *
 * 🔴 **ΟΛΙΚΗ ΚΑΙ ΝΤΕΤΕΡΜΙΝΙΣΤΙΚΗ ΣΕ ΚΑΘΕ ΕΙΣΟΔΟ — και δεν είναι καλλωπισμός**
 * (ADR-841 §7 Α14.7.3): ο καταναλωτής της συμφιλιώνει **δημόσια bytes** σε κάθε
 * επανασύνθεση. Ασταθής σειρά ⇒ άλλο περιεχόμενο κάθε πέρασμα ⇒ αρχεία που
 * **αναβοσβήνουν** χωρίς να έχει αλλάξει τίποτα.
 *
 * | Είσοδος | Συμπεριφορά |
 * |---|---|
 * | Κενή δήλωση | **Ταυτόσημη** με σκέτο `compareRest` |
 * | Κλειδί που δεν αντιστοιχεί σε στοιχείο | Αγνοείται — **καμία τρύπα** |
 * | Διπλότυπο κλειδί στη δήλωση | Μετρά η **πρώτη** εμφάνιση |
 * | Δύο στοιχεία με **ίδιο** κλειδί | Πρώτο δηλωμένο = η **πρώτη** εμφάνιση· το δεύτερο πέφτει στην ουρά *(μένει, δεν χάνεται)* |
 *
 * ⚠️ **Δεν μεταβάλλει την είσοδο.** Η `sort()` του JavaScript είναι **επιτόπια** και τα
 * `items` έρχονται τυπικά από ανάγνωση που ανήκει σε άλλον — αντιγράφεται πρώτα.
 *
 * ⚠️ **Το `compareRest` εφαρμόζεται ΜΟΝΟ στην ουρά, επίτηδες.** Ταξινόμηση ολόκληρου του
 * συνόλου και «ανέβασμα» μετά θα ήταν δύο περάσματα με το **ίδιο** αποτέλεσμα και μία
 * επιπλέον ευκαιρία να αποκλίνουν.
 */
export function orderByDeclaration<T>(
  items: readonly T[],
  keyOf: (item: T) => string,
  declared: readonly string[],
  compareRest: (a: T, b: T) => number,
): readonly T[] {
  if (declared.length === 0) return [...items].sort(compareRest);

  // 🔑 Ένα πέρασμα για το ευρετήριο· η **πρώτη** εμφάνιση κερδίζει το κλειδί, ώστε δύο
  //    στοιχεία με ίδιο κλειδί να μην ανταλλάσσουν θέση ανάλογα με τη σειρά άφιξης.
  const byKey = new Map<string, T>();
  for (const item of items) {
    const key = keyOf(item);
    if (!byKey.has(key)) byKey.set(key, item);
  }

  const pinned: T[] = [];
  const taken = new Set<T>();
  for (const key of declared) {
    const item = byKey.get(key);
    if (item === undefined || taken.has(item)) continue;
    taken.add(item);
    pinned.push(item);
  }

  const rest = items.filter((item) => !taken.has(item)).sort(compareRest);
  return [...pinned, ...rest];
}
