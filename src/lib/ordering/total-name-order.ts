/**
 * **Ο συγκριτής ανθρώπινων ονομάτων** — ελληνικό collation, χωρίς ευαισθησία σε τόνους.
 *
 * ⚠️ `sensitivity: 'base'` επίτηδες: ο ελληνικός τηλεφωνικός κατάλογος **αγνοεί
 * τόνους**, και ένας άνθρωπος που ψάχνει «Αγγελόπουλος» δεν περιμένει να βρει το
 * «ΑΓΓΕΛΟΠΟΥΛΟΣ» δέκα θέσεις μακριά. Η ισοπαλία που γεννά **λύνεται** από τον
 * τερματισμό του {@link compareByNameThenId}.
 *
 * ⚠️ `numeric: true`: «Γραφείο 2» πριν από «Γραφείο 10», όχι μετά.
 *
 * 🔶 **Η ετικέτα `'el'` ΔΕΝ σηκώνει βάρος — μετρημένο, και γράφεται για να μην το
 *    ξαναψάξει ο επόμενος.** Μετάλλαξη `'el' → 'en'` βγήκε **ΠΡΑΣΙΝΗ** σε όλες τις
 *    άγκυρες, και ο λόγος είναι πραγματικός: η σειρά του ελληνικού αλφαβήτου έρχεται
 *    από το **DUCET**, που είναι κοινό σε κάθε locale — το CLDR **δεν** έχει ελληνική
 *    προσαρμογή collation. Μετρήθηκαν **11** ζεύγη *(τελικό σίγμα, διαλυτικά, τόνοι,
 *    Ω/Ψ)*: **0 διαφορές**. Μένει επειδή δηλώνει **πρόθεση** και κοστίζει μηδέν —
 *    αλλά **μην** γράψεις άγκυρα που υποτίθεται ότι τη φυλά: θα ήταν σχόλιο που
 *    μοιάζει με έλεγχο.
 *
 * ⚠️ **Ένας collator, module-level.** Η κατασκευή `Intl.Collator` είναι ακριβή και θα
 * γινόταν **μία φορά ανά σύγκριση** μέσα στη `sort` — δηλαδή `O(n log n)` κατασκευές
 * για λίστα που αλλάζει σε κάθε καρέ της συνδρομής.
 */
export const HUMAN_NAME_COLLATOR = new Intl.Collator('el', {
  sensitivity: 'base',
  numeric: true,
});

/**
 * **Ολική σύγκριση: όνομα, μετά ταυτότητα.**
 *
 * ⚠️ **Ο τερματισμός δεν είναι διακοσμητικός.** Δύο εγγραφές **μπορούν** να έχουν το
 * ίδιο ανθρώπινο όνομα. Με σύγκριση **μόνο** στο όνομα, η σειρά τους θα καθοριζόταν
 * από τη σειρά άφιξης του `onSnapshot` — δηλαδή θα **άλλαζε** ανάμεσα σε δύο φορτώσεις
 * της ίδιας σελίδας. Χωρίς αυτόν, η «ουδετερότητα» θα ήταν *«κανείς δεν διάλεξε»*,
 * που είναι **τυχαιότητα**, όχι ουδετερότητα.
 *
 * ⚠️ Η ταυτότητα συγκρίνεται σε **κωδικοσημεία**, όχι με collation: δεν είναι ανθρώπινο
 * κείμενο, άρα το collation εδώ θα ήταν λάθος εργαλείο (και πιο αργό).
 */
export function compareByNameThenId(
  aName: string,
  aId: string,
  bName: string,
  bId: string,
): number {
  const byName = HUMAN_NAME_COLLATOR.compare(aName, bName);
  if (byName !== 0) return byName;

  return aId < bId ? -1 : aId > bId ? 1 : 0;
}
