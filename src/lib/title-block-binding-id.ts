/**
 * @fileoverview Το ντετερμινιστικό κλειδί μιας εγκεκριμένης σύνδεσης πινακίδας (ADR-745 §6.2).
 *
 * Καθαρό, μηδέν I/O. Το ερώτημα που απαντά είναι ένα: **ποιο έγγραφο είναι «αυτό το κελί αυτού
 * του σχεδίου δείχνει σε αυτή την οντότητα»**, ώστε η επανάληψη της έγκρισης να μη διπλασιάζει
 * και η διόρθωση να μη σβήνει.
 *
 * ```
 * tbb_{fileRecordId}_{levelId}_{cellRef}_{fieldKey}_{slot}_{targetRef}
 * ```
 *
 * 🔴 **Το ADR §6.2 πρότεινε `${fileRecordId}:${fieldKey}` — ΑΝΕΠΑΡΚΕΣ, μετρημένα.** Σπάει σε
 * τέσσερα σημεία: δύο πινακίδες στο ίδιο layer (§2.3 Παγίδα Δ), δύο πρόσωπα από **ένα** κελί
 * μελετητών, τρεις ενότητες από **ένα** κελί θέσης, και το ίδιο αρχείο σε δύο levels.
 *
 * 🔑 **Γιατί ΓΕΩΜΕΤΡΙΑ και όχι `sourceHandle` — το πιο ακριβό μάθημα αυτής της φάσης.**
 * Το `sourceHandle` **δεν είναι DXF handle**: `scene-title-block-cells.ts:96` δίνει `entity.id`,
 * που παράγεται ως `` `${idPrefix}_${index}` `` (`dxf-text-converters.ts:221`) από **δύο
 * ανεξάρτητους μετρητές** — τον top-level (`dxf-scene-builder.ts:272` → `:314`) και τον
 * block-flattened (`:265` `idSeq` → `dxf-block-expander.ts:203`) — **που καταλήγουν στην ίδια
 * σκηνή** (`:310`). Πινακίδα μέσα σε BLOCK, η κλασική περίπτωση AutoCAD, δίνει έτσι **δύο
 * `mtext_7`** στο ίδιο layer. Το σημείο εισαγωγής, αντίθετα, είναι **σταθερό ανά αρχείο**,
 * **μοναδικό ανά κελί**, και ανεξάρτητο και από τους δύο μετρητές **και** από το κατώφλι
 * ομαδοποίησης του Λ1 — που είναι ο λόγος που ούτε ο `titleBlockIndex` κάνει για κλειδί.
 *
 * @module lib/title-block-binding-id
 */

import { titleBlockBindingKey } from '@/services/enterprise-id-composite-keys';
import type { BindingProposal, BindingTarget } from '@/types/title-block-binding';

/**
 * Δεκαδικά του `cellRef`.
 *
 * Τρία αρκούν με τεράστιο περιθώριο: στο δείγμα G753 τα **γειτονικά** κελιά απέχουν ≳1,6 μονάδες
 * και οι δύο πινακίδες 36,49 (ADR §5.4α). Περισσότερα δεκαδικά θα έκαναν το κλειδί ευάλωτο σε
 * θόρυβο τελευταίου bit· λιγότερα θα συγχώνευαν κελιά.
 */
const CELL_DECIMALS = 3;

/**
 * Συντεταγμένη → σταθερό κομμάτι κλειδιού.
 *
 * ⚠️ Το `-0` εξομαλύνεται σε `0`: το `(-0.0001).toFixed(3)` δίνει `'-0.000'` ενώ το `(0).toFixed(3)`
 * δίνει `'0.000'` — **δύο κλειδιά για το ίδιο σημείο**. Χωρίς αυτή τη γραμμή, ένα κελί ακριβώς
 * πάνω στον άξονα θα έδινε άλλοτε το ένα κι άλλοτε το άλλο, ανάλογα με το προηγούμενο bit.
 */
function coordSegment(value: number): string {
  if (!Number.isFinite(value)) {
    throw new Error(`title-block-binding-id: non-finite coordinate (${value})`);
  }
  const factor = 10 ** CELL_DECIMALS;
  const rounded = Math.round(value * factor) / factor;
  const normalized = Object.is(rounded, -0) ? 0 : rounded;
  return normalized.toFixed(CELL_DECIMALS).replace('-', 'n').replace('.', 'p');
}

/** Η **ταυτότητα του κελιού**: το σημείο εισαγωγής της τιμής, όχι ο μετρητής της σκηνής. */
export function cellRef(at: { readonly x: number; readonly y: number }): string {
  return `x${coordSegment(at.x)}y${coordSegment(at.y)}`;
}

/**
 * Πόσα τμήματα προηγούνται του `cellRef` μέσα στο κλειδί: `tbb` · αρχείο · επίπεδο.
 *
 * Δηλωμένο δίπλα στο `buildTitleBlockBindingKey`, που είναι το **μόνο** σημείο που συνθέτει τη
 * σειρά — δύο τόποι για μία διάταξη θα απέκλιναν στην πρώτη προσθήκη τμήματος.
 */
const CELL_REF_SEGMENT_INDEX = 3;

/**
 * Το `cellRef` **ενός ήδη αποθηκευμένου** κλειδιού — ή `null` όταν το κλειδί δεν έχει αυτή τη
 * μορφή.
 *
 * 🔴 **ΓΙΑΤΙ ΥΠΑΡΧΕΙ: το «ίδιο slot» είχε ΔΥΟ ορισμούς** (ADR-759 §4.9 εύρημα 3, §Θ.2).
 *
 * Το **κλειδί** ταυτοποιεί το κελί με τη **γεωμετρία** (`cellRef`), για τον μετρημένο λόγο που
 * εξηγεί το docblock του αρχείου: το `sourceHandle` **δεν είναι DXF handle** αλλά `entity.id`
 * από **δύο ανεξάρτητους μετρητές** που καταλήγουν στην ίδια σκηνή, άρα πινακίδα μέσα σε BLOCK
 * δίνει **δύο `mtext_7`**. Το `findSameSlotActive` όμως ταυτοποιούσε το κελί με το
 * **`sourceHandle`** — δηλαδή με ακριβώς το πράγμα που κρίθηκε ακατάλληλο.
 *
 * Συνέπεια: δύο πινακίδες στο ίδιο σχέδιο ⇒ η έγκριση στη **δεύτερη** μαρκάρει `superseded` τη
 * σύνδεση της **πρώτης**, σιωπηλά — ίδιο σχήμα με το ελάττωμα α που γέννησε το `bindingSlot`,
 * σε άξονα που τότε δεν υπήρχε.
 *
 * 🔑 **Και δεν χρειάζεται αλλαγή σχήματος**: το `cellRef` **είναι ήδη μέσα σε κάθε
 * αποθηκευμένο `bindingId`**, γιατί το `buildTitleBlockBindingKey` το έβαλε εκεί. Νέο πεδίο
 * στη συλλογή θα ήταν **δεύτερη** γραφή της ίδιας πληροφορίας — και θα διόρθωνε μόνο ό,τι
 * γράφεται από εδώ και πέρα, αφήνοντας κάθε υπάρχουσα σύνδεση εκτεθειμένη.
 *
 * ⚠️ Η ανάγνωση κατά **θέση** και όχι από το τέλος είναι υποχρεωτική: το `targetRef` περιέχει
 * enterprise ids (`contact-cont_abc-surveyor`), δηλαδή **κάτω παύλες**. Τα τρία πρώτα τμήματα
 * αντίθετα είναι εγγυημένα χωρίς `_` — το `encodeKeySegment` το κωδικοποιεί ρητά *«είναι ο
 * διαχωριστής μας»* — και το `cellRef` παράγει μόνο `x`/`y`/`n`/`p`/ψηφία.
 */
export function cellRefOfBindingId(bindingId: string): string | null {
  const segments = bindingId.split('_');
  const found = segments[CELL_REF_SEGMENT_INDEX];
  // Ο έλεγχος μορφής δεν είναι διακοσμητικός: χωρίς αυτόν, κλειδί άλλης οικογένειας θα
  // επέστρεφε **κάποιο** τμήμα και δύο άσχετες συνδέσεις θα «μοιράζονταν κελί». Το σχήμα είναι
  // ακριβώς ό,τι παράγει το `coordSegment`: προαιρετικό `n` για το πρόσημο, `p` για την υποδιαστολή.
  return found !== undefined && /^xn?\d+p\d+yn?\d+p\d+$/.test(found) ? found : null;
}

/**
 * Ελεύθερο κείμενο → **αντιστρεπτό** τμήμα κλειδιού.
 *
 * 🔴 **Η αντιστρεψιμότητα ΔΕΝ είναι σχολαστικισμός — είναι ο φύλακας.** Μια «καθαρίστρια»
 * κανονικοποίηση που αντικαθιστά κάθε ύποπτο χαρακτήρα με `-` θα έστελνε το `ΠΑΠΠΑΣ Α/Β` και το
 * `ΠΑΠΠΑΣ Α Β` στο **ίδιο** slot ⇒ η έγκριση του δεύτερου θα μαρκάριζε `superseded` τον πρώτο,
 * **σιωπηλά**. Το percent-encoding είναι 1:1, άρα δύο διαφορετικά ονόματα δεν συγχωνεύονται ποτέ.
 *
 * Το `/` είναι **πραγματικό** εδώ, όχι υποθετικό: το `resolve-landowner.ts` περνά **ωμό κείμενο
 * κελιού** ως `personName`, και το δείγμα G753 γράφει «ΜΑΥΡΟΜΙΧΑΛΗΣ ΚΩΝ/ΝΟΣ» — και το `/` είναι
 * **παράνομος χαρακτήρας σε Firestore document id**.
 *
 * Το `_` κωδικοποιείται κι αυτό: είναι ο διαχωριστής μας, και ένα `_` μέσα σε τμήμα θα έκανε τα
 * όρια των τμημάτων διφορούμενα για όποιον κοιτάξει ποτέ το κλειδί.
 */
export function encodeKeySegment(raw: string): string {
  const normalized = raw.normalize('NFC').trim().replace(/\s+/g, ' ');
  if (!normalized) throw new Error('title-block-binding-id: empty key segment');
  return encodeURIComponent(normalized).replace(/[_.!~*'()]/g, (c) =>
    `%${c.charCodeAt(0).toString(16).toUpperCase()}`,
  );
}

/** Πού δείχνει ένας στόχος, ως τμήμα κλειδιού. */
export function targetRef(target: BindingTarget): string {
  switch (target.kind) {
    case 'contact':
      // 🔑 Ο ΡΟΛΟΣ είναι μέρος της ταυτότητας, γιατί είναι μέρος του id του ίδιου του συνδέσμου
      // (`lib/contact-link-id.ts:31-35`). Χωρίς αυτόν, «λάθος ρόλος → σωστός ρόλος» παράγει
      // **το ίδιο ακριβώς bindingId** ⇒ το `setDoc` **επιγράφει** το πρώτο, χωρίς supersede και
      // χωρίς ιστορικό. Μαζί του χάνεται ο **παλιός ρόλος**, που είναι το μόνο πράγμα από το
      // οποίο ξαναχτίζεται ο παλιός `linkId` — άρα ο προηγούμενος σύνδεσμος μένει ενεργός και
      // πλέον **μη αποσύρσιμος** (δες `services/title-block-apply/withdraw-superseded.ts`).
      //
      // ⚠️ ΔΙΟΡΘΩΣΗ 2026-08-05: εδώ έγραφε ότι *«το `unlinkContact()` απαιτεί `linkId` που δεν
      // ξαναχτίζεται»*. **Ψευδές** — το `buildContactLinkKey` είναι καθαρά ντετερμινιστικό. Το
      // λάθος επιχείρημα ήταν επικίνδυνο ακριβώς επειδή στήριζε **σωστή** απόφαση: ο επόμενος
      // που θα το έλεγχε θα «απλοποιούσε» βγάζοντας τον ρόλο από το κλειδί.
      return `contact-${target.contactId}-${target.role}`;
    case 'landowner':
      return `landowner-${target.contactId}`;
    case 'project-address':
      return `addr-${target.field}`;
    case 'project-field':
      return `pfield-${target.field}`;
    case 'drawing-meta':
      return `meta-${target.field}`;
    case 'survey-record':
      // 🔑 Το `recordId` είναι **μέρος της ταυτότητας**, με το ίδιο σκεπτικό που ο ρόλος
      // είναι μέρος της ταυτότητας μιας επαφής: «ίδιο κελί → άλλο τοπογραφικό» είναι
      // **άλλος** σύνδεσμος. Χωρίς αυτό, η έγκριση στη νέα εγγραφή θα παρήγαγε το ίδιο
      // ακριβώς `bindingId` και το `setDoc` θα **επέγραφε** την προηγούμενη — χάνοντας ποιο
      // τοπογραφικό είχε δηλωθεί τότε — όλο το νόημα μιας χρονολογημένης βεβαίωσης.
      return `srec-${target.recordId}-${target.field}`;
    case 'survey-record-row':
      // 🔑 Η **γραμμή** είναι ο στόχος, και το `rowId` είναι ήδη ντετερμινιστικό από το
      // σχέδιο (`surveyRowKey`). Το `recordId` μένει μέρος της ταυτότητας για τον ίδιο λόγο
      // με το `srec-`: «ίδια δήλωση → άλλο τοπογραφικό» είναι **άλλος** σύνδεσμος.
      return `srow-${target.recordId}-${target.rowId}`;
  }
}

/**
 * Ποια **θέση πρότασης μέσα στο κελί** — ο άξονας που ούτε το `fieldKey` ούτε το `cellRef` βλέπουν.
 *
 * 🔴 Χωρίς αυτόν, το supersede θα είχε εμβέλεια **κελιού** και η έγκριση του μελετητή #2 θα
 * μαρκάριζε `superseded` τον #1 — **δύο νόμιμες συνδέσεις από το ίδιο κελί**, η μία σβησμένη
 * χωρίς να το ζητήσει κανείς. Το `ΘΕΣΗ` έχει το ίδιο σχήμα με τρεις ενότητες.
 *
 * 🔴 **ΤΟ ΕΙΔΟΣ ΣΤΟΧΟΥ ΑΠΟΦΑΣΙΖΕΙ ΠΡΩΤΟ — διορθώθηκε 2026-08-06 (ADR-759 §4.9).**
 *
 * Εδώ έγραφε `if (proposal.personName) return encodeKeySegment(proposal.personName);` **πάνω**
 * από το `switch`, δηλαδή το πρόσωπο σκίαζε τον προορισμό. Άρα «ο Μαυρομιχάλης → επαφή έργου»
 * και «ο Μαυρομιχάλης → **τοπογράφος αυτού** του τοπογραφικού» — δύο ταυτόχρονα αληθείς
 * δηλώσεις — μοιράζονταν slot, και η δεύτερη έγκριση αποσύρει **σιωπηλά** την πρώτη.
 *
 * Είναι η **ίδια** βλάβη που γέννησε αυτή τη συνάρτηση, στον συμπληρωματικό άξονα: εκεί άλλαζε
 * το πρόσωπο με σταθερό προορισμό, εδώ ο προορισμός με σταθερό πρόσωπο. Ο δεύτερος έμεινε
 * ακάλυπτος γιατί μέχρι τη Φ3γ **δεν υπήρχε** δεύτερος προορισμός για πρόσωπο.
 *
 * ⚠️ **Η θεραπεία είναι ΠΡΟΣΘΕΤΙΚΗ, και είναι μετρημένο γιατί.** Το slot ζει μέσα σε
 * αποθηκευμένα `bindingId`· αλλάζοντάς το για υπάρχον είδος, κάθε εγκεκριμένη σύνδεση θα
 * αποκτούσε νέο κλειδί και το επόμενο φόρτωμα δεν θα την ξανάβρισκε. Το `personName`
 * παράγεται από **ακριβώς δύο** σημεία (`resolve-people.ts:152`, `resolve-landowner.ts:67`)
 * και **και τα δύο** δίνουν στόχο προσώπου ⇒ ο κλάδος `contact`/`landowner` επιστρέφει ό,τι
 * ακριβώς επέστρεφε πριν, και **κανένα αποθηκευμένο κλειδί δεν αλλάζει**. Το φυλάει ρητός
 * έλεγχος στο `title-block-binding-id.test.ts`.
 */
export function bindingSlot(proposal: BindingProposal, target: BindingTarget): string {
  switch (target.kind) {
    // ── Στόχοι προσώπου ──────────────────────────────────────────────────────
    // Εδώ ο άξονας που ξεχωρίζει τις προτάσεις **είναι το πρόσωπο**: ένα κελί μελετητών δίνει
    // δύο νόμιμες συνδέσεις που πρέπει να συνυπάρξουν.
    //
    // Πρόσωπο χωρίς `personName` δεν παράγεται από τον Λ2, αλλά ένα κλειδί δεν επιτρέπεται να
    // εξαρτάται από αυτό: η επαφή/ο οικοπεδούχος ταυτοποιείται ήδη μοναδικά στο `targetRef`.
    case 'contact':
    case 'landowner':
      return proposal.personName ? encodeKeySegment(proposal.personName) : target.contactId;

    // ── Στόχοι δεδομένων ─────────────────────────────────────────────────────
    // 🔴 **Το `survey-record` κάθεται ΕΔΩ, και αυτό είναι σημασιολογική απόφαση.** Το κελί
    // «ΧΡΟΝΟΣ ΜΕΛΕΤΗΣ» δίνει **δύο** νόμιμες προτάσεις: μεταδεδομένο του φύλλου
    // (`studyDate`) και δήλωση του τοπογράφου (`surveyDate`). Επειδή το slot είναι το
    // **πεδίο** και τα δύο ονόματα διαφέρουν, οι δύο εγκρίσεις **συνυπάρχουν** — που είναι
    // το σωστό: η μία δεν αναιρεί την άλλη. Αν το slot ήταν το κελί, η δεύτερη έγκριση θα
    // μαρκάριζε `superseded` την πρώτη, σιωπηλά — ίδιο σχήμα με τους δύο μελετητές του ενός
    // κελιού, που είναι ο λόγος που υπάρχει αυτή η συνάρτηση.
    case 'project-address':
    case 'project-field':
    case 'drawing-meta':
    case 'survey-record':
      return target.field;

    // ── Στόχος ΓΡΑΜΜΗΣ ───────────────────────────────────────────────────────
    // 🔴 **Εδώ το `cellRef` ΔΕΝ ξεχωρίζει τίποτα, και αυτό είναι το όλο θέμα.** Τα τέσσερα
    // έγγραφα του σώματος είναι **ένα MTEXT το καθένα**: όλες οι γραμμές μιας φόρμας —
    // πέντε πράξεις, δύο εγκρίσεις, τρεις τίτλοι — μοιράζονται **το ίδιο** σημείο εισαγωγής.
    // Με slot το πεδίο (όπως τα βαθμωτά), και οι δέκα θα καταλάμβαναν την ίδια θέση και η
    // κάθε έγκριση θα μαρκάριζε `superseded` την προηγούμενη — δηλαδή θα επιβίωνε **μία**.
    // Το slot είναι επομένως η **ταυτότητα της γραμμής**, που είναι ακριβώς ο άξονας κατά
    // μήκος του οποίου οι δηλώσεις συνυπάρχουν νόμιμα.
    case 'survey-record-row':
      return target.rowId;
  }
}

export interface TitleBlockBindingKeyParts {
  readonly fileRecordId: string;
  readonly levelId: string;
  readonly proposal: BindingProposal;
  readonly target: BindingTarget;
}

/**
 * Το κλειδί μιας έγκρισης.
 *
 * @throws αν λείπει `fileRecordId` ή `levelId` — **ποτέ `?? ''`**. Ένα κενό τμήμα θα γεννούσε
 *   κλειδί που το επόμενο φόρτωμα δεν ξαναβρίσκει, άρα **δεύτερο έγγραφο για την ίδια σύνδεση**
 *   (ADR-745 §Γ2: το `fileRecordId` φτάνει **αργότερα** από την πρώτη απόδοση). Η σιωπηλή
 *   ανοχή εδώ ήταν ο τελευταίος φραγμός του κλικ στο §13(ι) — `user?.uid ?? ''`.
 */
export function buildTitleBlockBindingKey(parts: TitleBlockBindingKeyParts): string {
  const { fileRecordId, levelId, proposal, target } = parts;
  if (!fileRecordId) throw new Error('buildTitleBlockBindingKey: fileRecordId is required');
  if (!levelId) throw new Error('buildTitleBlockBindingKey: levelId is required');

  return titleBlockBindingKey([
    encodeKeySegment(fileRecordId),
    encodeKeySegment(levelId),
    cellRef(proposal.at),
    proposal.fieldKey,
    bindingSlot(proposal, target),
    targetRef(target),
  ]);
}

/**
 * Η **εμβέλεια του supersede**: όλα όσα καταλαμβάνουν την ίδια θέση, ό,τι κι αν δείχνουν.
 *
 * Ίδιο πρόθεμα κλειδιού μέχρι και το `slot`, **χωρίς** το `targetRef`. Παράγεται από την ίδια
 * συνάρτηση με το κλειδί ώστε τα δύο να **μην μπορούν** να αποκλίνουν: μια χειρόγραφη δεύτερη
 * συναρμολόγηση είναι ακριβώς το είδος διπλότυπου που ξεσυγχρονίζεται μήνες αργότερα.
 */
export function bindingSlotScope(parts: TitleBlockBindingKeyParts): string {
  const full = buildTitleBlockBindingKey(parts);
  const suffix = `_${targetRef(parts.target)}`;
  return full.slice(0, full.length - suffix.length);
}
