/**
 * **Οι αγγελίες που αποδεικνύουν ΑΥΤΗ τη λειτουργία** — ή `null` όταν η λειτουργία
 * **δεν αποδεικνύεται με αγγελίες** *(οι επαγγελματίες· Α5 ⇒ δες {@link landingProShowcase})*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΕΛΑΤΤΩΜΑ ΠΟΥ ΕΚΛΕΙΣΕ ΕΔΩ — ΤΟ ΒΡΗΚΕ ΜΑΤΙ ΣΕ ΣΤΙΓΜΙΟΤΥΠΟ, ΜΕ 20/20 ΠΡΑΣΙΝΕΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο διακόπτης άλλαζε **μόνο** τον προορισμό της υποβολής: πατούσες «Αγορά» και η
 * βιτρίνα από κάτω έδειχνε **ενοικιάσεις**. Η **Α4.1.4** είχε δεσμευτεί ότι *«αλλάζει
 * ο ΠΡΟΟΡΙΣΜΟΣ»* — και ξέχασε ότι κάτω από τον διακόπτη **υπάρχει ήδη περιεχόμενο**.
 *
 * 🔑 **Και η αιτία δεν ήταν αμέλεια**: οι εννέα πλατφόρμες του §4 δεν έχουν αυτό το
 * πρόβλημα γιατί **το πάνελ τους είναι η φόρμα** *(το Rightmove εναλλάσσει τρεις
 * μπάρες)*. Εμείς κρατήσαμε **ένα πεδίο** *(ADR-777 Α3)* ⇒ ο διακόπτης έμεινε **χωρίς
 * πάνελ**, και το μάτι υιοθέτησε τη βιτρίνα ως πάνελ. **Σωστά.**
 *
 * ⚠️ **ΤΟ ΦΙΛΤΡΟ ΤΡΕΧΕΙ ΠΡΙΝ ΤΟ ΚΟΨΙΜΟ, ΚΑΙ ΕΙΝΑΙ Η ΜΙΣΗ ΑΠΟΦΑΣΗ.** Με «πάρε 6, μετά
 * φιλτράρισε» η «Ενοικίαση» θα έδειχνε **2 από 4** — και το έλλειμμα θα ήταν **αόρατο**:
 * κάρτες υπάρχουν, απλώς οι μισές είναι λάθος λειτουργίας. Ίδιο σχήμα με το «slice πριν
 * το sort» που το {@link landingShowcaseListings} ήδη απαγορεύει γραμμένο.
 *
 * ⛔ **ΚΑΜΙΑ ΔΕΥΤΕΡΗ ΜΗΧΑΝΗ**: το κριτήριο είναι το **ίδιο** `matchesListingFilters` που
 * τρέχει και η οθόνη 2 *(`SearchResultsContent`)*. Ένα `listing.offerKinds.includes(…)`
 * γραμμένο εδώ ή σε component θα ήταν **δεύτερο κριτήριο ελεύθερο να αποκλίνει** — το
 * ακριβές σχήμα του **ADR-749**.
 */
export function landingPanelListings(
  mode: LandingMode | null,
  listings: readonly PublicListing[],
): readonly PublicListing[] | null {
  // 🔴 **`mode === null` ΣΗΜΑΙΝΕΙ «ΔΕΝ ΥΠΑΡΧΕΙ ΔΙΑΚΟΠΤΗΣ», ΚΑΙ ΤΟΤΕ ΔΕΝ ΦΙΛΤΡΑΡΟΥΜΕ.**
  //
  // Η ρίζα αποδίδει τον διακόπτη **μόνο** όταν η κάλυψη επιτρέπει την ερώτηση
  // *(`coverageAnswersWhere`)*. Στην κατάσταση `no-location` υπάρχουν αγγελίες αλλά
  // **κανένας διακόπτης** — και ένα φιλτράρισμα εκεί θα ήταν **σιωπηλός περιορισμός
  // χωρίς χειριστήριο**: ο επισκέπτης θα έβλεπε λιγότερα, χωρίς να υπάρχει τίποτα
  // στην οθόνη που να εξηγεί γιατί, και **χωρίς τρόπο να το αναιρέσει**.
  //
  // ⚠️ Είναι **χειρότερο** από το ελάττωμα που η Α4.3 ήρθε να κλείσει: εκεί ο
  //    επισκέπτης έβλεπε **παραπάνω** απ' όσα ζήτησε *(θόρυβος)*· εδώ θα έβλεπε
  //    **λιγότερα** απ' όσα υπάρχουν *(απώλεια, αόρατη)*.
  if (mode === null) return landingShowcaseListings(listings);

  const filters = landingModeFilters(mode);
  if (filters === null) return null;

  return landingShowcaseListings(applyListingFilters(listings, filters));
}

/**
 * **Οι επαγγελματίες που αποδεικνύουν τη λειτουργία «Επαγγελματίες»** *(απόφαση
 * Giorgio 2026-09-04)*.
 *
 * 🔑 **Η ΣΕΙΡΑ ΔΕΝ ΓΕΝΝΙΕΤΑΙ ΕΔΩ**: ο `usePublicAgencies` έχει **ήδη** ταξινομήσει
 * *(`orderAgencies`)*, όπως ακριβώς και ο κατάλογος `/pro` — εδώ **μόνο** κόβουμε.
 * Μια δεύτερη `sort()` θα ήταν δύο σειρές για το ίδιο σύνολο.
 *
 * ⚠️ **ΤΟ ΙΔΙΟ ΤΑΒΑΝΙ** *({@link LANDING_SHOWCASE_LIMIT})* με τις αγγελίες, και είναι
 * απόφαση: το *«πόσα δείχνει η βιτρίνα»* είναι ιδιότητα **της βιτρίνας**, όχι του
 * είδους του περιεχομένου. Ένας δεύτερος αριθμός εδώ θα σήμαινε ότι «δείγμα» έχει
 * **δύο** μεγέθη ανάλογα με το κουμπί που πάτησες, χωρίς κανείς να το μάθει.
 *
 * ⛔ **ΚΑΜΙΑ `slice()` σε component** — ίδιος κανόνας με το `landingShowcaseListings`.
 */
export function landingProShowcase(
  agencies: readonly PublicShowcase[],
): readonly PublicShowcase[] {
  return agencies.slice(0, LANDING_SHOWCASE_LIMIT);
}

/**
 * **Ψάχνει ΠΡΟΣΩΠΟ ή ΑΚΙΝΗΤΟ;** — η ερώτηση που κρίνει **κάθε** έξοδο της ρίζας.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΕΡΩΤΗΜΑ ΤΟΥ GIORGIO ΠΟΥ ΤΗ ΓΕΝΝΗΣΕ: *«θέλω υδραυλικό — τι κάνω;»*
 * ────────────────────────────────────────────────────────────────────────────
 *
 * **Μετρήθηκε ότι δεν υπήρχε καμία διαδρομή.** Στο tab «Επαγγελματίες» το κουμπί
 * «Αναζήτηση» είναι **απενεργοποιημένο** όσο το πεδίο τόπου είναι κενό
 * *(`PlaceSearchBox`: `disabled={busy || query.trim() === ''}`)*, και οι κάρτες της
 * βιτρίνας οδηγούν σε **ένα** προφίλ — ποτέ στον κατάλογο. Δηλαδή *«επαγγελματίες
 * οπουδήποτε»* ήταν **αδύνατο**, ενώ *«όλες οι αγγελίες»* είχε πόρτα από την πρώτη μέρα.
 *
 * 🔑 **ΚΑΙ Η ΘΕΡΑΠΕΙΑ ΔΕΝ ΕΙΝΑΙ ΤΕΤΑΡΤΟ ΚΟΥΜΠΙ.** Η πόρτα υπήρχε· απαντούσε **πάντα**
 * για ακίνητα, ακόμη κι όταν ο επισκέπτης μόλις είχε πει ότι ψάχνει **πρόσωπο**. Είναι
 * **ακριβώς** η ασυνέπεια που έκλεισε η Α4.3 για τη βιτρίνα, μία γραμμή πιο κάτω.
 *
 * ⚠️ **`null` ⇒ `false`, και είναι σωστό**: χωρίς διακόπτη κανείς δεν δήλωσε ότι ψάχνει
 * πρόσωπο, και η ιστορική πόρτα *(«δες όλες τις αγγελίες»)* μένει ως έχει.
 *
 * ⛔ **ΜΗΝ γραφτεί ως `mode === 'pros'`**: θα ήταν η **τέταρτη** διατύπωση του κανόνα
 * της **Α5** *(οι άλλες τρεις: {@link isListingMode} · {@link landingModeFilters} ·
 * `destinationFor`)*. Ο κανόνας είναι **ένας**, και ζει στον τύπο.
 */
export function landingModeSeeksPeople(mode: LandingMode | null): boolean {
  return mode !== null && landingModeFilters(mode) === null;
}
