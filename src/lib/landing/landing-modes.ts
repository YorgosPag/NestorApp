/**
 * **Πόσα έχει να δείξει η κάθε λειτουργία σήμερα.**
 *
 * ⚠️ **Μία διέλευση, όχι τέσσερις**: ο κατάλογος διαβάζεται **μία** φορά. Τέσσερα
 * χωριστά `filter().length` θα ήταν τέσσερις διελεύσεις πάνω στην **ίδια** συνδρομή,
 * και — χειρότερα — τέσσερα σημεία όπου το κριτήριο μπορεί να αποκλίνει.
 *
 * ⚠️ **Μία αγγελία μετρά σε ΠΟΛΛΕΣ λειτουργίες, και αυτό είναι το πλεονέκτημα**: το
 * `offerKinds` είναι **πίνακας** *(«πουλάω, και μέχρι να πουληθεί το βγάζω
 * βραχυχρόνια»)* ⇒ η ίδια καταχώρηση εμφανίζεται σε δύο λειτουργίες, με την κατάλληλη
 * όψη σε καθεμία. **Η Zillow δεν μπορεί καν να το εκφράσει** — δεν έχει βραχυχρόνια.
 * ⛔ Άρα το άθροισμα των μετρητών **ΔΕΝ** ισούται με το πλήθος των αγγελιών, και μια
 * άγκυρα που το απαιτούσε θα ήταν λάθος.
 */
export function countLandingModes(
  listings: readonly PublicListing[],
  showcaseCount: number,
): Record<LandingMode, number> {
  const counts: Record<LandingMode, number> = {
    buy: 0,
    rent: 0,
    stay: 0,
    pros: Math.max(0, showcaseCount),
  };

  for (const listing of listings) {
    for (const mode of LANDING_MODES) {
      if (!isListingMode(mode)) continue;
      if (listing.offerKinds.includes(LANDING_MODE_OFFER[mode])) counts[mode] += 1;
    }
  }

  return counts;
}

/**
 * **Ποιες λειτουργίες επιτρέπεται να εμφανιστούν.**
 *
 * 🔑 Το κατώφλι είναι **ένα**, όχι «αρκετά»: με μία αγγελία η λειτουργία **έχει τι να
 * δείξει**, και το *πόσο λίγα* το λέει ήδη η πρόταση κάλυψης. Ένα αυθαίρετο «≥ 5» θα
 * ήταν κρίση πληρότητας που **κανείς δεν μπορεί να δικαιολογήσει με αριθμό**.
 *
 * ⚠️ **Διατηρεί τη σειρά του {@link LANDING_MODES}** — ο διακόπτης δεν αναδιατάσσεται
 * όταν αλλάξουν τα δεδομένα. Μια σειρά κατά πλήθος θα έκανε τα κουμπιά να
 * **μετακινούνται κάτω από το δάχτυλο** του επισκέπτη.
 */
export function availableLandingModes(
  counts: Record<LandingMode, number>,
): readonly LandingMode[] {
  return LANDING_MODES.filter((mode) => counts[mode] > 0);
}

/**
 * **Ποια λειτουργία είναι ενεργή όταν δεν έχει διαλέξει κανείς.**
 *
 * ⚠️ **Η πρώτη ΔΙΑΘΕΣΙΜΗ, ποτέ σκέτο `'buy'`**: αν κάποτε δεν υπάρχει καμία αγγελία
 * προς πώληση, ένα καρφωμένο `'buy'` θα άνοιγε τη σελίδα σε λειτουργία που **το ίδιο
 * το αρχείο μόλις έκρινε ότι δεν μπορεί να εμφανιστεί**.
 *
 * Επιστρέφει `null` όταν **καμία** δεν μπορεί — και τότε ο διακόπτης δεν αποδίδεται
 * καθόλου. *(Η οθόνη δεν μένει άφωνη: η `CoverageStatement` λέει τι συμβαίνει.)*
 */
export function defaultLandingMode(
  available: readonly LandingMode[],
): LandingMode | null {
  return available[0] ?? null;
}

/**
 * **Αποδίδεται ο διακόπτης;** — *«έχει ο άνθρωπος **χειριστήριο** για αυτόν τον άξονα;»*
 *
 * ⚠️ **ΕΝΑΣ διακόπτης με ΕΝΑ κουμπί δεν είναι επιλογή** — είναι ετικέτα που μοιάζει με
 * επιλογή, και ο επισκέπτης θα πατούσε περιμένοντας αλλαγή.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΤΟ ΚΡΙΤΗΡΙΟ ΕΦΥΓΕ ΑΠΟ ΤΟ COMPONENT (Α4.3)
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ζούσε **μόνο** μέσα στο `LandingModeSwitch` ως `modes.length < 2 ⇒ null`. Όσο ο
 * διακόπτης δεν είχε **πάνελ**, ένας τόπος αρκούσε. Με την **Α4.3** το περιεχόμενο
 * κάτω από αυτόν εξαρτάται από την ίδια ερώτηση ⇒ **δύο** τόποι θα την απαντούσαν,
 * ελεύθεροι να αποκλίνουν *(N.0.2 · ADR-749)*.
 *
 * 🔴 **ΚΑΙ Η ΑΠΟΚΛΙΣΗ ΕΧΕΙ ΟΝΟΜΑ**: με **ένα** μόνο διαθέσιμο κουμπί ο διακόπτης
 * κρύβεται, αλλά η βιτρίνα θα **φιλτράριζε** — δηλαδή ο επισκέπτης θα έβλεπε
 * **λιγότερα από όσα υπάρχουν**, χωρίς τίποτα στην οθόνη που να το εξηγεί και **χωρίς
 * τρόπο να το αναιρέσει**. *(Συμβαίνει: 5 προς πώληση + 1 μόνο αντιπαροχή, μηδέν
 * ενοικιάσεις, μηδέν επαγγελματίες ⇒ η αντιπαροχή εξαφανίζεται σιωπηλά.)*
 */
export function landingSwitchIsVisible(available: readonly LandingMode[]): boolean {
  return available.length >= 2;
}

