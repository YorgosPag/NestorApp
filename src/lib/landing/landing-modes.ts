/**
 * @fileoverview **ΟΙ ΛΕΙΤΟΥΡΓΙΕΣ ΤΗΣ ΡΙΖΑΣ** — «μία είσοδος, τέσσερα κουμπιά».
 * @related ADR-841 §7 Α4 (η απόφαση) · Α5 (οι επαγγελματίες δεν είναι αγγελία)
 *          · ADR-777 §8.10 (η οθόνη αρνείται να υποσχεθεί) · §8.49 (…οφείλει να αποδείξει)
 * @module lib/landing/landing-modes
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 Η ΑΠΟΦΑΣΗ ΗΤΑΝ ΗΔΗ ΓΡΑΜΜΕΝΗ — ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ ΤΗΝ ΕΚΤΕΛΕΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η **Α4** όρισε τέσσερις λειτουργίες και **γιατί** χωρίζονται έτσι (§4.1):
 *
 * | Λειτουργία | Τι ρωτά | Γιατί χωριστά |
 * |---|---|---|
 * | **Αγορά** ⇄ **Ενοικίαση** | περιοχή | *ίδια δεδομένα, άλλη όψη* ⇒ **δίδυμα** |
 * | **Διαμονή** | περιοχή + **άφιξη/αναχώρηση** | *ασύμβατη φόρμα* |
 * | **Επαγγελματίες** | **ειδικότητα** + περιοχή | *άλλο mental model* |
 *
 * ⛔ **ΜΗΝ γίνει «πιο έξυπνο» από ρητό διακόπτη.** Η Airbnb αντικατέστησε τον διακόπτη
 * με «έξυπνες» Categories το 2022 και **τις κατάργησε τον Σεπτ. 2025** — hosts με
 * λιγότερες κρατήσεις, δημόσια αιτήματα επιστροφής (§4.2). Δοκιμασμένο από τον
 * μεγαλύτερο παίκτη, με τρία χρόνια δεδομένων, **και αναιρέθηκε**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΚΟΥΜΠΙ ΕΜΦΑΝΙΖΕΤΑΙ ΜΟΝΟ ΟΤΑΝ Η ΛΕΙΤΟΥΡΓΙΑ ΜΠΟΡΕΙ ΝΑ ΤΗΡΗΣΕΙ ΤΗΝ ΥΠΟΣΧΕΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Είναι ο **ίδιος** κανόνας που το §8.10 εφάρμοσε στο κουτί αναζήτησης, τώρα **ανά
 * άξονα**. Μετρημένο ζωντανά (2026-09-04): `sell` **6** · `leaseOut` **4** ·
 * `leaseShort` **0** ⇒ ένα κουμπί «Διαμονή» θα οδηγούσε σε **μηδέν για κάθε πιθανή
 * είσοδο** — ακριβώς το *«γράφει «Πάτρα», παίρνει μηδέν, φεύγει για πάντα»* που το
 * **Ο-6** του ADR-841 έχει ήδη καταγράψει: *«η Α4 **σχεδιάζει** τη λειτουργία· δεν την
 * **τροφοδοτεί**»*.
 *
 * 🏆 **ΚΑΙ ΕΔΩ ΞΕΠΕΡΝΑΜΕ ΤΟΥΣ ΜΕΓΑΛΟΥΣ.** Το xe.gr δείχνει «Οχήματα» με δύο κατηγορίες
 * και «Εργασία» πάντα, ασχέτως αποθέματος — ένα κουμπί που **δεν μπορεί να αδειάσει**,
 * γιατί κανείς δεν το ρωτά. Εδώ η διαθεσιμότητα **παράγεται από τα ίδια τα δεδομένα**,
 * άρα δεν μπορεί να αποκλίνει· και η «Διαμονή» **επιστρέφει μόνη της** μόλις υπάρξει η
 * πρώτη αγγελία, **χωρίς αλλαγή κώδικα** — ίδιο σχήμα με το κουτί του §8.10.
 *
 * ⚠️ **ΔΕΝ ΕΙΝΑΙ ΑΠΟΚΡΥΨΗ ΧΑΡΑΚΤΗΡΙΣΤΙΚΟΥ.** Ένα γκριζαρισμένο «Διαμονή» θα έλεγε
 * *«δεν σου επιτρέπεται»*, ενώ η αλήθεια είναι *«δεν έχουμε ακόμη τι να σου δείξουμε»* —
 * η ίδια απόρριψη που το §8.10 έκανε ρητά για το πεδίο αναζήτησης.
 */

import type { PublicListing } from '@/types/public-listing';
import type { OfferKind } from '@/types/property-offers';
import type { GeoPoint } from '@/types/geo/coordinates';
import {
  EMPTY_LISTING_FILTERS,
  DEFAULT_SEARCH_RADIUS_KM,
  type ListingFilters,
} from '@/lib/listings/listing-filters';

// ============================================================================
// ΤΟ ΛΕΞΙΛΟΓΙΟ — κλειστό σύνολο
// ============================================================================

/**
 * **Οι τέσσερις λειτουργίες**, στη σειρά που εμφανίζονται.
 *
 * 🔑 Η σειρά **είναι** απόφαση: «Αγορά · Ενοικίαση» πρώτα γιατί είναι τα δίδυμα με τα
 * περισσότερα δεδομένα· «Επαγγελματίες» τελευταίο γιατί απαντά **άλλο** ερώτημα *(δεν
 * ψάχνεις ακίνητο, ψάχνεις πρόσωπο — Α5)*.
 *
 * ⛔ **Η αντιπαροχή (`exchange`) ΔΕΝ έχει κουμπί, και είναι απόφαση**: το **Α20** την
 * όρισε ως **ΔΙΑΣΤΑΣΗ**, όχι κατάσταση. Ένα πέμπτο κουμπί θα την ξανάκανε «είδος
 * αγγελίας» — ακριβώς αυτό που εκείνη η απόφαση αναίρεσε.
 */
export const LANDING_MODES = ['buy', 'rent', 'stay', 'pros'] as const;

export type LandingMode = (typeof LANDING_MODES)[number];

/**
 * **Ποια διάθεση τροφοδοτεί ποια λειτουργία.**
 *
 * ⚠️ Το `pros` λείπει **επίτηδες** και ο τύπος το επιβάλλει: οι επαγγελματίες **δεν
 * είναι αγγελία** (Α5). Ένα `pros: null` εδώ θα έκανε τον μεταγλωττιστή να δεχτεί
 * ερώτημα *«ποιο `OfferKind` έχουν οι επαγγελματίες;»* — ερώτημα χωρίς νόημα.
 */
export const LANDING_MODE_OFFER: Record<Exclude<LandingMode, 'pros'>, OfferKind> = {
  buy: 'sell',
  rent: 'leaseOut',
  stay: 'leaseShort',
};

/** Είναι λειτουργία αγγελιών (άρα έχει `OfferKind`); — φρουρός τύπου, όχι ευκολία. */
export function isListingMode(mode: LandingMode): mode is Exclude<LandingMode, 'pros'> {
  return mode !== 'pros';
}

// ============================================================================
// Η ΜΕΤΡΗΣΗ
// ============================================================================

/**
 * **Πόσα έχει να δείξει η κάθε λειτουργία σήμερα.**
 *
 * ⚠️ **Μία διέλευση, όχι τέσσερις**: ο κατάλογος διαβάζεται **μία** φορά. Τέσσερα
 * χωριστά `filter().length` θα ήταν τέσσερις διελεύσεις πάνω στην **ίδια** συνδρομή,
 * και — χειρότερα — τέσσερα σημεία όπου το κριτήριο μπορεί να αποκλίνει.
 *
 * ⚠️ **Μία αγγελία μετρά σε ΠΟΛΛΕΣ λειτουργίες, και αυτό είναι το πλεονέκτημα**: το
 * `offerKinds` είναι **πίνακας** *(«πουλάω, και μέχρι να πουληθεί το βγάζω
 * βραχυχρόνια»)* ⇒ η ίδια καταχώρηση εμφανίζεται σε δύο λειτουργίες, με την κατάλληλη
 * όψη σε καθεμία. **Η Zillow δεν μπορεί καν να το εκφράσει** — δεν έχει βραχυχρόνια.
 * ⛔ Άρα το άθροισμα των μετρητών **ΔΕΝ** ισούται με το πλήθος των αγγελιών, και μια
 * άγκυρα που το απαιτούσε θα ήταν λάθος.
 */
export function countLandingModes(
  listings: readonly PublicListing[],
  showcaseCount: number,
): Record<LandingMode, number> {
  const counts: Record<LandingMode, number> = {
    buy: 0,
    rent: 0,
    stay: 0,
    pros: Math.max(0, showcaseCount),
  };

  for (const listing of listings) {
    for (const mode of LANDING_MODES) {
      if (!isListingMode(mode)) continue;
      if (listing.offerKinds.includes(LANDING_MODE_OFFER[mode])) counts[mode] += 1;
    }
  }

  return counts;
}

/**
 * **Ποιες λειτουργίες επιτρέπεται να εμφανιστούν.**
 *
 * 🔑 Το κατώφλι είναι **ένα**, όχι «αρκετά»: με μία αγγελία η λειτουργία **έχει τι να
 * δείξει**, και το *πόσο λίγα* το λέει ήδη η πρόταση κάλυψης. Ένα αυθαίρετο «≥ 5» θα
 * ήταν κρίση πληρότητας που **κανείς δεν μπορεί να δικαιολογήσει με αριθμό**.
 *
 * ⚠️ **Διατηρεί τη σειρά του {@link LANDING_MODES}** — ο διακόπτης δεν αναδιατάσσεται
 * όταν αλλάξουν τα δεδομένα. Μια σειρά κατά πλήθος θα έκανε τα κουμπιά να
 * **μετακινούνται κάτω από το δάχτυλο** του επισκέπτη.
 */
export function availableLandingModes(
  counts: Record<LandingMode, number>,
): readonly LandingMode[] {
  return LANDING_MODES.filter((mode) => counts[mode] > 0);
}

/**
 * **Ποια λειτουργία είναι ενεργή όταν δεν έχει διαλέξει κανείς.**
 *
 * ⚠️ **Η πρώτη ΔΙΑΘΕΣΙΜΗ, ποτέ σκέτο `'buy'`**: αν κάποτε δεν υπάρχει καμία αγγελία
 * προς πώληση, ένα καρφωμένο `'buy'` θα άνοιγε τη σελίδα σε λειτουργία που **το ίδιο
 * το αρχείο μόλις έκρινε ότι δεν μπορεί να εμφανιστεί**.
 *
 * Επιστρέφει `null` όταν **καμία** δεν μπορεί — και τότε ο διακόπτης δεν αποδίδεται
 * καθόλου. *(Η οθόνη δεν μένει άφωνη: η `CoverageStatement` λέει τι συμβαίνει.)*
 */
export function defaultLandingMode(
  available: readonly LandingMode[],
): LandingMode | null {
  return available[0] ?? null;
}

// ============================================================================
// Ο ΠΡΟΟΡΙΣΜΟΣ — τι ταξιδεύει μαζί με τον επισκέπτη
// ============================================================================

/**
 * **Τα φίλτρα με τα οποία φτάνει ο επισκέπτης στην οθόνη 2** — ή `null` όταν η
 * λειτουργία **δεν οδηγεί σε αγγελίες**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ Ο ΔΙΑΚΟΠΤΗΣ ΑΛΛΑΖΕΙ ΤΟΝ **ΠΡΟΟΡΙΣΜΟ** ΚΑΙ ΟΧΙ ΤΟΝ ΑΡΙΘΜΟ ΤΩΝ ΠΕΔΙΩΝ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το **ADR-777 Α3** το δεσμεύει αριθμητικά: *«Οθόνη 1 — **ένα** κουτί … Desktop: **ένα
 * πεδίο**. Κινητό: **ίδιο**»*. Άρα και οι τέσσερις λειτουργίες ρωτούν **περιοχή**, και
 * ό,τι άλλο χρειάζεται η καθεμία ζει στην **οθόνη 2**, όπου **υπάρχει ήδη**:
 * `StayFilterFields` *(άφιξη/αναχώρηση)* · `AgencyDirectoryFilters` *(ειδικότητα ESCO +
 * ακτίνα)*.
 *
 * 🔑 **Και αυτό ΔΕΝ είναι έκπτωση — είναι ο κανόνας N.0.2.** Ένα δεύτερο πεδίο
 * ειδικότητας εδώ θα ήταν **διπλότυπο** του `AgencyDirectoryFilters`, που χτίζει τις
 * επιλογές του από τα **ίδια τα προφίλ** (`occupationOptions`). Θα σήμαινε ότι η ρίζα
 * φορτώνει 22 προφίλ **μόνο για να γεμίσει ένα dropdown** — και ότι δύο οθόνες
 * απαντούν *«ποιες ειδικότητες υπάρχουν;»*, ελεύθερες να αποκλίνουν.
 *
 * ⚠️ **Η ακτίνα είναι η ΙΔΙΑ σταθερά** *(`DEFAULT_SEARCH_RADIUS_KM`)* και για τις
 * τέσσερις. Μια δεύτερη τιμή εδώ θα σήμαινε ότι «κοντά μου» έχει **δύο** σημασίες
 * ανάλογα με το κουμπί που πάτησες — χωρίς ο επισκέπτης να το μάθει ποτέ.
 */
export function landingModeFilters(
  mode: LandingMode,
  center: GeoPoint,
): ListingFilters | null {
  if (!isListingMode(mode)) return null;

  return {
    ...EMPTY_LISTING_FILTERS,
    // ⚠️ **Ένα** είδος, όχι πολλά: ο επισκέπτης πάτησε **ένα** κουμπί. Ένα δεύτερο
    //    `OfferKind` εδώ θα του έδινε αποτελέσματα που **δεν ζήτησε** — και θα
    //    ακύρωνε τον λόγο ύπαρξης του διακόπτη.
    offerKinds: [LANDING_MODE_OFFER[mode]],
    near: { center, radiusKm: DEFAULT_SEARCH_RADIUS_KM },
  };
}
