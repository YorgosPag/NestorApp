/**
 * **Οι τέσσερις λειτουργίες**, στη σειρά που εμφανίζονται.
 *
 * 🔑 Η σειρά **είναι** απόφαση: «Αγορά · Ενοικίαση» πρώτα γιατί είναι τα δίδυμα με τα
 * περισσότερα δεδομένα· «Επαγγελματίες» τελευταίο γιατί απαντά **άλλο** ερώτημα *(δεν
 * ψάχνεις ακίνητο, ψάχνεις πρόσωπο — Α5)*.
 *
 * ⛔ **Η αντιπαροχή (`exchange`) ΔΕΝ έχει κουμπί, και είναι απόφαση**: το **Α20** την
 * όρισε ως **ΔΙΑΣΤΑΣΗ**, όχι κατάσταση. Ένα πέμπτο κουμπί θα την ξανάκανε «είδος
 * αγγελίας» — ακριβώς αυτό που εκείνη η απόφαση αναίρεσε.
 */
export const LANDING_MODES = ['buy', 'rent', 'stay', 'pros'] as const;

export type LandingMode = (typeof LANDING_MODES)[number];

/**
 * **Ποια διάθεση τροφοδοτεί ποια λειτουργία.**
 *
 * ⚠️ Το `pros` λείπει **επίτηδες** και ο τύπος το επιβάλλει: οι επαγγελματίες **δεν
 * είναι αγγελία** (Α5). Ένα `pros: null` εδώ θα έκανε τον μεταγλωττιστή να δεχτεί
 * ερώτημα *«ποιο `OfferKind` έχουν οι επαγγελματίες;»* — ερώτημα χωρίς νόημα.
 */
export const LANDING_MODE_OFFER: Record<Exclude<LandingMode, 'pros'>, OfferKind> = {
  buy: 'sell',
  rent: 'leaseOut',
  stay: 'leaseShort',
};

/** Είναι λειτουργία αγγελιών (άρα έχει `OfferKind`); — φρουρός τύπου, όχι ευκολία. */
export function isListingMode(mode: LandingMode): mode is Exclude<LandingMode, 'pros'> {
  return mode !== 'pros';
}

