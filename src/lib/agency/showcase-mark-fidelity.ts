import { SHOWCASE_SHELF } from '@/services/upload/utils/public-shelf-kinds';
import type { ShowcaseMarkKind } from '@/lib/agency/showcase-mark-kind';
import {
  markRenderScale,
  markSurfaces,
  MARK_GUARANTEED_DENSITY,
} from '@/lib/agency/showcase-mark-surfaces';

/**
 * **Οι διαστάσεις μιας εικόνας** — είτε όπως τις διάβασε ο περιηγητής *(είσοδος)*, είτε
 * όπως τις έγραψε ο καθαριστής στο δημοσιευμένο έγγραφο *(έξοδος)*.
 *
 * ⚠️ Και οι δύο, όχι μόνο η μικρότερη: το κουτί κάθε επιφάνειας έχει **δύο** πλευρές, και
 * ποια από τις δύο «δεσμεύει» εξαρτάται από την αναλογία. Μια εικόνα 1000×80 έχει άφθονα
 * pixel και είναι **άχρηστη** ως τετράγωνο σήμα — και μόνο και οι δύο διαστάσεις μαζί το
 * λένε.
 */
export interface ImageDimensions {
  readonly width: number;
  readonly height: number;
}

/**
 * Τι απαντά ο κριτής.
 *
 * 🔴 **Το `warned` ΔΕΝ είναι είδος άρνησης** — είναι **αποδοχή** που κουβαλά κάτι να
 * ειπωθεί. Ενωμένο με το `tooSmall`, η οθόνη θα έπρεπε να ρωτήσει *«είναι από αυτά που
 * μπλοκάρουν;»* σε κάθε σημείο χρήσης — και η πρώτη φορά που κάποιος θα ξεχνούσε να
 * ρωτήσει, ο άνθρωπος θα κοίταζε κουμπί που δεν κάνει τίποτα.
 *
 * ⚠️ **Το `tooSmall` κουβαλά ΚΑΙ `reach`** *(Α21.13)*, και δεν είναι πλεονασμός: στην
 * **έξοδο** η άρνηση **δεν υπάρχει** — το σήμα είναι ήδη δημοσιευμένο, και το μόνο που
 * μένει είναι να ειπωθεί **πού** φαίνεται θολό. Χωρίς αυτό, η οθόνη της εξόδου θα
 * χρειαζόταν **δεύτερο** λεξιλόγιο για την ίδια ακριβώς κατάσταση.
 */
export type ShowcaseMarkVerdict =
  | { readonly outcome: 'accepted' }
  /** Δεκτή, αλλά **δεν φτάνει** για κάθε επιφάνεια — δες {@link ShowcaseMarkReach}. */
  | { readonly outcome: 'warned'; readonly reach: ShowcaseMarkReach }
  /** Κάτω από τη **μικρότερη** βαθμίδα του ραφιού: δεν υπάρχει παράγωγο να παραχθεί. */
  | { readonly outcome: 'tooSmall'; readonly reach: ShowcaseMarkReach; readonly required: number };

/**
 * **Πού φτάνει καθαρά αυτή η εικόνα, και πού όχι** — σε **επιφάνειες**, όχι σε pixel.
 *
 * 🔑 Ο άνθρωπος δεν ξέρει τι είναι «256 λογικά εικονοστοιχεία». Ξέρει *«η κάρτα μου»* και
 * *«η σελίδα μου»*.
 */
export interface ShowcaseMarkReach {
  /** Η **μικρότερη** πλευρά που έδωσε, ως έχει — το μόνο νούμερο που δείχνουμε. */
  readonly shortest: number;
  /**
   * 🏆 **Πόσο θα ΕΠΡΕΠΕ να είναι η μικρή πλευρά** ώστε να σωπάσει η προειδοποίηση —
   * **γι' αυτή** την εικόνα, στην **αναλογία της**.
   *
   * 🔴 **Αντικατέστησε ένα καθολικό `MARK_IDEAL_EDGE = 192`** *(Α21.13)*, που ήταν σωστό
   * μόνο για τετράγωνο κουτί: ένα wordmark 4:1 χρειάζεται **128** στη μικρή του πλευρά
   * *(ζώνη 240×64)*, και το σταθερό νούμερο του ζητούσε **50% παραπάνω**.
   *
   * ⚠️ Ίσο με το {@link shortest} **στρογγυλεμένο προς τα πάνω** επί το έλλειμμα — άρα
   * πάντα `> shortest` όσο υπάρχει προειδοποίηση, ποτέ ίσο.
   */
  readonly needed: number;
  /** Φτάνει για την κάρτα του καταλόγου σε οθόνη υψηλής πυκνότητας; */
  readonly coversCard: boolean;
  /**
   * Φτάνει για τη σελίδα προφίλ σε οθόνη υψηλής πυκνότητας;
   *
   * 🔑 **`coversPage` ⇒ `coversCard`, ΠΑΝΤΑ** — η σελίδα είναι μεγαλύτερη **και στις δύο**
   * πλευρές από την κάρτα, σε **κάθε** σχήμα *(τετράγωνο 96×96 ή ζώνη 240×64 έναντι
   * 44×44)*, και η κλίμακα του `contain`/`cover` είναι μονότονη ως προς το κουτί. Γι' αυτό
   * οι ζώνες είναι **δύο** και όχι τρεις — άγκυρα το φυλάει.
   */
  readonly coversPage: boolean;
}

/**
 * Οι βαθμίδες του ραφιού, **ταξινομημένες** — η σειρά της δήλωσης δεν είναι συμβόλαιο.
 *
 * ⚠️ Αντιγράφεται σε **τοπικό** πίνακα πριν το `sort`: το `readonly` του τύπου δεν
 * εμποδίζει το `Array.prototype.sort` να **αναδιατάξει το ίδιο το `encoding.widths`** σε
 * χρόνο εκτέλεσης — δηλαδή αυτό το αρχείο θα άλλαζε σιωπηλά τη διαμόρφωση του **γραφέα**.
 */
const SHELF_WIDTHS: readonly number[] = [...SHOWCASE_SHELF.encoding.widths].sort((a, b) => a - b);

/**
 * **Η μικρότερη βαθμίδα** — κάτω από αυτήν δεν υπάρχει τίποτα να παραχθεί.
 *
 * 🔑 Το ράφι θα «τα κατάφερνε» ούτως ή άλλως — θα **μεγέθυνε**. Και αυτό είναι ακριβώς ο
 * λόγος της άρνησης: ένα παράγωγο 64px φτιαγμένο από εικόνα 30px είναι **ψέμα** που
 * κοστίζει bytes και δεν δείχνει τίποτα.
 */
export const MARK_MIN_EDGE = SHELF_WIDTHS[0] ?? 64;

/**
 * **Ανοχή κινητής υποδιαστολής στη σύγκριση της κλίμακας.**
 *
 * ⚠️ Οι οριακές τιμές είναι **ακριβείς** *(44/88 και 96/192 δίνουν ακριβώς 0,5)*, αλλά μια
 * μελλοντική επιφάνεια με μη-δυαδικές διαστάσεις θα έδινε `1.0000000000000002` — δηλαδή
 * *«θολό»* για εικόνα που καλύπτει **ακριβώς**. Το κατώφλι είναι **συμπεριληπτικό**, και
 * μια άγκυρα δεν μπορεί να προβλέψει ποια διαίρεση θα σπάσει.
 */
const SCALE_EPSILON = 1e-9;

/**
 * **Είναι αυτή η εικόνα αρκετή;**
 *
 * @param dimensions Ό,τι διάβασε ο περιηγητής *(είσοδος)* ή ό,τι έγραψε ο καθαριστής
 *   *(έξοδος)*. `0`, αρνητικό ή μη πεπερασμένο ⇒ `tooSmall` — μια εικόνα χωρίς διαστάσεις
 *   δεν είναι εικόνα.
 * @param kind Το είδος που **δήλωσε ο άνθρωπος**. ⚠️ **Απαιτητικό, όχι προαιρετικό**: το
 *   σχήμα του κουτιού —και άρα η απάντηση— εξαρτάται από αυτό, και μια προεπιλογή θα
 *   έκρινε το πορτρέτο με το κουτί του λογοτύπου **σιωπηλά**.
 */
export function judgeShowcaseMark(
  dimensions: ImageDimensions,
  kind: ShowcaseMarkKind,
): ShowcaseMarkVerdict {
  const reach = markReach(dimensions, kind);

  if (reach.shortest < MARK_MIN_EDGE) {
    return { outcome: 'tooSmall', reach, required: MARK_MIN_EDGE };
  }

  if (reach.coversCard && reach.coversPage) return { outcome: 'accepted' };

  return { outcome: 'warned', reach };
}

/**
 * **Πού φτάνει αυτή η εικόνα** — η μέτρηση, χωρίς την κρίση.
 *
 * 🔑 **Εξαγόμενη**, ώστε η οθόνη της **εξόδου** να μπορεί να μιλήσει και για σήμα που
 * έπεσε κάτω από το ελάχιστο: εκεί η άρνηση **δεν υπάρχει** *(είναι ήδη δημοσιευμένο)*,
 * και το μόνο που έχει νόημα είναι το *«πού φαίνεται θολό»*.
 */
export function markReach(dimensions: ImageDimensions, kind: ShowcaseMarkKind): ShowcaseMarkReach {
  // 🔴 **ΚΑΙ ΟΙ ΔΥΟ ΔΙΑΣΤΑΣΕΙΣ ΚΡΙΝΟΝΤΑΙ, ΟΧΙ Η ΜΙΚΡΟΤΕΡΗ.** Ένα `Math.min(Infinity, 100)`
  //    δίνει **100** — δηλαδή εικόνα με άπειρο πλάτος θα περνούσε την άρνηση και θα
  //    ανακοίνωνε *«έχεις 100, χρειάζονται 64»*: **ασυνάρτητη** πρόταση, από τιμή που δεν
  //    είναι εικόνα. Fail-closed: ό,τι δεν είναι δύο πεπερασμένοι θετικοί αριθμοί είναι `0`.
  const { width, height } = dimensions;
  const usable = Number.isFinite(width) && Number.isFinite(height) && width > 0 && height > 0;
  const shortest = usable ? Math.floor(Math.min(width, height)) : 0;

  const surfaces = markSurfaces({ kind, width: dimensions.width, height: dimensions.height });
  const demand = new Map(
    surfaces.map((surface) => {
      const needs = markRenderScale(dimensions, surface) * MARK_GUARANTEED_DENSITY;
      return [surface.name, needs] as const;
    }),
  );

  // 🔑 **Το χειρότερο έλλειμμα ορίζει την απαίτηση**: αν η σελίδα ζητά ×1,4 και η κάρτα
  //    ×0,6, η εικόνα πρέπει να μεγαλώσει ×1,4 — και τότε **και οι δύο** καλύπτονται.
  const worst = Math.max(...demand.values());

  return {
    shortest,
    // ⚠️ `ceil` και όχι `round`: ένα «χρειάζονται 127» για εικόνα που θέλει 127,2 θα ήταν
    //    οδηγία που **δεν λύνει το πρόβλημα** — ο άνθρωπος θα ξαναδοκίμαζε και θα ξανάβλεπε
    //    το ίδιο μήνυμα.
    needed: Number.isFinite(worst) ? Math.ceil(shortest * worst) : MARK_MIN_EDGE,
    coversCard: isCovered(demand.get('card')),
    coversPage: isCovered(demand.get('page')),
  };
}

/** Καλύπτεται μια επιφάνεια; — `undefined` *(επιφάνεια που δεν ρωτήθηκε)* σημαίνει **όχι**. */
function isCovered(demand: number | undefined): boolean {
  return demand !== undefined && demand <= 1 + SCALE_EPSILON;
}
