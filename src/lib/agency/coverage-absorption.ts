//
// ⚠️ Και ήταν **ήδη** το σωστό σπίτι: ο μοναδικός εσωτερικός καλών ζούσε δύο γραμμές πιο
//    κάτω, και η επικεφαλίδα αυτού του αρχείου **περιέγραφε ήδη** τη συνάρτηση.

/**
 * **ΚΑΝΟΝΙΚΟΠΟΙΗΣΗ — Η ΔΗΛΩΣΗ ΧΩΡΙΣ ΤΑ ΠΕΡΙΤΤΑ ΤΗΣ.**
 *
 * Αφαιρεί (α) τα διπλότυπα και (β) κάθε ταυτότητα που έχει **γνήσιο πρόγονο** ήδη μέσα
 * στη δήλωση: *«Δήμος Θέρμης» + «Περιφέρεια Κεντρικής Μακεδονίας» ⇒ μένει η περιφέρεια*,
 * γιατί ο δήμος **δεν προσθέτει τίποτα** — ήδη καλύπτεται.
 *
 * 🏆 **Αυτό αντικαθιστά το πλαφόν**, και είναι η θέση όπου ξεπερνάμε το Google Business
 * Profile: εκεί οι περιοχές είναι **επίπεδες**, οπότε χρειάζεται αυθαίρετη οροφή *(20)*
 * και **ανιχνευτής spam**. Με ιεραρχία, η λίστα **συμπτύσσεται μόνη της**.
 *
 * ⚠️ **Ιδεμποτής** *(N.7.2 #3)*: `normalize(normalize(x)) === normalize(x)`.
 * ⚠️ **Διατηρεί τη σειρά** της πρώτης εμφάνισης — ο άνθρωπος βλέπει τη λίστα του με τη
 * σειρά που την έχτισε, όχι αναδιαταγμένη από μηχανή.
 * ⚠️ **Άγνωστη ταυτότητα** *(κενή γενεαλογία)* **διατηρείται**: ο κριτής της
 * εγκυρότητας είναι ο γραφέας *(`showcase-request.ts`)*, όχι αυτή η συνάρτηση — μια
 * σιωπηλή απόρριψη εδώ θα έσβηνε δήλωση ανθρώπου επειδή δεν είχε φορτώσει ένα αρχείο.
 */
export function normalizeCoverageIds(
  adminIds: readonly string[],
  lineageOf: LineageResolver,
): readonly string[] {
  const unique = [...new Set(adminIds)];
  const declared = new Set(unique);

  return unique.filter((id) => {
    // Η γενεαλογία **χωρίς τον εαυτό** = οι γνήσιοι πρόγονοι.
    const strictAncestors = lineageOf(id).filter((ancestorId) => ancestorId !== id);
    return !strictAncestors.some((ancestorId) => declared.has(ancestorId));
  });
}

/** Το αποτέλεσμα μιας προσθήκης: η **νέα λίστα**, και τι **πρέπει να ειπωθεί**. */
export interface AbsorptionOutcome {
  readonly adminIds: readonly string[];
  readonly absorption: Absorption | null;
}

/**
 * **Πρόσθεσε μια περιοχή, και πες τι έγινε.**
 *
 * @param current — οι ήδη δηλωμένες ταυτότητες
 * @param added — αυτή που μόλις πάτησε ο άνθρωπος
 * @param lineageOf — ποιος περιέχει ποιον *(ο ίδιος αναγνώστης με τον κριτή)*
 * @param nameOf — πώς λέγεται μια ταυτότητα **στην οθόνη**
 */
export function absorbArea(
  current: readonly string[],
  added: string,
  lineageOf: LineageResolver,
  nameOf: (adminId: string) => string,
): AbsorptionOutcome {
  const adminIds = normalizeCoverageIds([...current, added], lineageOf);

  // 🔑 **Δύο κατευθύνσεις, και οι δύο ανακοινώνονται.** Αν ο νέος έφυγε, τον κατάπιε
  //    πρόγονος· αν έφυγαν άλλοι, τους κατάπιε ο νέος.
  if (!adminIds.includes(added)) {
    // Ο νέος καταπίνεται από **έναν** πρόγονο — το πλήθος είναι εξ ορισμού 1.
    const swallower = current.find((id) => lineageOf(added).includes(id));
    return {
      adminIds,
      absorption: { narrow: nameOf(added), wide: nameOf(swallower ?? added), count: 1 },
    };
  }

  const swallowed = current.filter((id) => !adminIds.includes(id));
  return {
    adminIds,
    absorption:
      swallowed.length === 0
        ? null
        : { narrow: nameOf(swallowed[0]), wide: nameOf(added), count: swallowed.length },
  };
}
