/** Μία επιλογή του χειριστηρίου ειδικότητας. */
export interface OccupationOption {
  readonly escoUri: string;
  readonly label: EscoBilingualText;
}

/**
 * **Σε ποια από τις δύο γλώσσες διαβάζεται μια δίγλωσση ετικέτα** — μία γραφή.
 *
 * 🔴 **ΓΙΑΤΙ ΜΠΑΙΝΕΙ ΕΔΩ ΚΑΙ ΟΧΙ ΤΡΙΤΗ ΦΟΡΑ ΣΤΗ ΣΕΛΙΔΑ** *(N.0.2, ADR-841 §7 Α4.5)*: η
 * στένωση ζούσε γραμμένη στο χέρι μέσα στο `AgencyDirectoryContent`, και η **ρίζα** τη
 * χρειάστηκε ως **δεύτερος** αναγνώστης. Δύο αντίγραφα ενός `?:` δεν είναι κόστος
 * σήμερα — είναι δύο σημεία που μπορούν να αποκλίνουν όταν προστεθεί τρίτη γλώσσα, και
 * τότε η μία οθόνη θα ταξινομούσε αλλιώς από την άλλη **χωρίς κανένα σφάλμα**.
 *
 * ⚠️ **ΔΕΝ ΕΙΝΑΙ ΔΙΠΛΟΤΥΠΟ ΤΟΥ `resolveEscoLang`** *(`components/shared/esco/esco-label`)*:
 * εκείνο απαντά **δύο** ερωτήσεις *(ενεργή **και** δευτερεύουσα γλώσσα, για τον διπλό
 * τίτλο των picker)* και ζει σε φάκελο **components** — μια εισαγωγή από το `lib/` προς τα
 * εκεί θα ήταν αντιστροφή στρώσης. Εδώ η ερώτηση είναι **μία**, και ο αναγνώστης της είναι
 * το `label[locale]` αυτού του αρχείου.
 *
 * @param i18nLanguage Το ωμό `i18n.language` — μπορεί να είναι `'el-GR'`, `'pseudo'`, ή ό,τι
 *   έχει ρυθμίσει ο άνθρωπος. Ό,τι δεν είναι ελληνικά διαβάζεται **αγγλικά**.
 */
export function showcaseLocale(i18nLanguage: string): 'el' | 'en' {
  return i18nLanguage === 'el' ? 'el' : 'en';
}

/**
 * **Οι επιλογές ΕΙΝΑΙ ο πληθυσμός** — καμία λίστα, πουθενά.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🏆 ΓΙΑΤΙ ΑΥΤΟ ΕΙΝΑΙ ΚΑΛΥΤΕΡΟ ΑΠΟ ΟΣΑ ΚΑΝΟΥΝ ΟΙ ΜΕΓΑΛΟΙ — ΟΧΙ ΑΠΛΩΣ ΦΘΗΝΟΤΕΡΟ
 *
 * 1. ⛔ **ΚΑΝΕΝΑ ΔΕΚΑΤΟ ΛΕΞΙΛΟΓΙΟ** *(ADR-798 Α2 · ADR-749)*. Οι εναλλακτικές
 *    μετρήθηκαν και απορρίφθηκαν: **2.942** ESCO occupations σε dropdown είναι
 *    αδύνατο· **ISCO μείζων** *(1 ψηφίο)* βάζει δικηγόρο και μηχανικό στο ίδιο
 *    `2`· **ISCO υπο-μείζων** *(43 ομάδες)* διακρίνει σωστά αλλά απαιτεί **43
 *    επίσημους τίτλους ILO × 2 γλώσσες γραμμένους στο χέρι**. Εδώ οι τιμές είναι
 *    τα `escoUri` που **ήδη ζουν** στα έγγραφα και οι ετικέτες το
 *    `occupation.label` που **ήδη ταξιδεύει δίγλωσσο**. **Μηδέν νέο κλειδί i18n.**
 *
 * 2. 🔑 **ΚΑΜΙΑ ΕΠΙΛΟΓΗ ΔΕΝ ΟΔΗΓΕΙ ΣΕ ΚΕΝΟ, ΕΞ ΟΡΙΣΜΟΥ.** Houzz και Thumbtack
 *    προσφέρουν trades με **μηδέν** επαγγελματίες στην περιοχή σου —
 *    *κατάλογος που υπόσχεται πληθυσμό που δεν έχει*. Εδώ είναι **δομικά
 *    αδύνατο**: κάθε επιλογή προήλθε από βιτρίνα που υπάρχει.
 *
 * 3. ✅ **Η ΣΕΙΡΑ ΤΩΝ ΕΠΙΛΟΓΩΝ ΕΙΝΑΙ ΚΙ ΑΥΤΗ ΟΥΔΕΤΕΡΗ**: αλφαβητικά κατά ετικέτα,
 *    tie-break στο URI ⇒ **ολική**. ⛔ **ΠΟΤΕ «κατά πλήθος»** — θα ήταν κατάταξη
 *    **ΕΠΑΓΓΕΛΜΑΤΩΝ** μέσα στο ίδιο το χειριστήριο, δηλαδή ο Φ1 παραβιασμένος
 *    στο σημείο που κανείς δεν κοιτά.
 *
 * 🔶 **ΔΗΛΩΜΕΝΟ ΟΡΙΟ** *(αναθεωρημένο 2026-09-04, ADR-841 §7 Α19)*: όταν οι διακριτές
 * ειδικότητες ξεπεράσουν όσες μπορεί κανείς να **βρει** στο χειριστήριο, χρειάζεται
 * δεύτερο επίπεδο *(ISCO υπο-μείζων)*. Οι 43 τίτλοι τότε **ΕΙΣΑΓΟΝΤΑΙ** από την πηγή,
 * όπως εισήχθησαν τα 2.942 — ⛔ **ποτέ πληκτρολογημένοι**.
 *
 * ⚠️ **Η γραμμή έλεγε «όσες χωρά ένα `<Select>`» — το χειριστήριο ΔΕΝ είναι πια `<Select>`**:
 * η Α19 το έκανε **combobox με πληκτρολόγηση**, άρα το όριο **μετακινήθηκε πολύ πιο έξω**
 * *(δεν κυλάς 200 γραμμές — γράφεις τρία γράμματα)*. Το όριο δεν καταργήθηκε· **έπαψε να
 * είναι το ύψος μιας λίστας** και έγινε *«πόσα διαφορετικά πράγματα σημαίνει η ίδια λέξη»*.
 * Μέχρι τότε δεν πληρώνεται.
 *
 * @param locale Η γλώσσα της σειράς — η αλφαβητική σειρά είναι **ανά γλώσσα**.
 */
export function occupationOptions(
  showcases: readonly PublicShowcase[],
  locale: 'el' | 'en',
): readonly OccupationOption[] {
  const byUri = new Map<string, EscoBilingualText>();
  for (const showcase of showcases) {
    for (const credential of showcase.credentials) {
      // ⚠️ Πρώτη γραφή νικά — οι ετικέτες είναι στιγμιότυπα της ταξινομίας και
      //    δύο βιτρίνες μπορεί να τις έχουν πάρει σε διαφορετικές στιγμές. Η
      //    διαφορά είναι αδιάφορη για την επιλογή· η **σταθερότητα** δεν είναι.
      if (!byUri.has(credential.occupation.escoUri)) {
        byUri.set(credential.occupation.escoUri, credential.occupation.label);
      }
    }
  }

  return [...byUri.entries()]
    .map(([escoUri, label]) => ({ escoUri, label }))
    .sort((a, b) => {
      const byLabel = a.label[locale].localeCompare(b.label[locale], locale);
      // 🔑 Tie-break στην **ταυτότητα** ⇒ ολική σειρά. Δύο ειδικότητες με
      //    ταυτόσημη ετικέτα δεν θα εναλλάσσονταν ανά φόρτωση.
      return byLabel !== 0 ? byLabel : a.escoUri.localeCompare(b.escoUri);
    });
}
