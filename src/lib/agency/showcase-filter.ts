/**
 * ADR-841 **Φ6-Β** — **Ο ΚΑΝΟΝΑΣ Φ: ΦΙΛΤΡΟ ≠ ΚΑΤΑΤΑΞΗ.**
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΤΟ ΣΧΟΛΙΟ ΠΟΥ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ ΑΝΑΤΡΕΠΕΙ — ΚΑΙ ΓΙΑΤΙ ΗΤΑΝ ΣΩΣΤΟ
 *
 * Το `app/(light)/pro/page.tsx` έγραφε: *«ο κατάλογος **δεν έχει φίλτρα
 * επίτηδες**: ένας **επιλογέας ταξινόμησης** είναι η υποδοχή που περιμένει το
 * εμπορικό κριτήριο (§9.9 α)»*.
 *
 * Η **προκείμενη** αφορά **ταξινόμηση** και είναι σωστή — **και παραμένει
 * σωστή**. Το **συμπέρασμα** αφορά **φιλτράρισμα**, και **δεν έπεται**:
 *
 *   • **Φίλτρο** απαντά *«τι ψάχνω;»* — ο **επισκέπτης** δηλώνει πρόθεση.
 *   • **Ταξινόμηση** απαντά *«ποιος πρώτος;»* — η **πλατφόρμα** δηλώνει προτίμηση.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🏆 ΚΑΙ ΤΟ ΦΙΛΤΡΟ ΔΕΝ ΕΙΝΑΙ ΑΝΕΚΤΟ — ΕΙΝΑΙ **ΘΕΡΑΠΕΙΑ**, ΜΕ ΜΕΤΡΗΣΗ ΤΟΥ ΙΔΙΟΥ ΜΑΣ
 * ΤΟΥ ΔΕΝΤΡΟΥ
 *
 * Το `agency-directory-order.ts` **έχει ήδη γράψει**:
 *
 *   *«Η αλφαβητική σειρά ευνοεί **συστηματικά** τα ονόματα σε `Α`/`Β` — φαινόμενο
 *   τόσο γνωστό που γέννησε ολόκληρη πρακτική ονοματοδοσίας («AAA …»)… ουδέτερη
 *   ως προς **εμάς** αλλά **όχι ουδέτερη ως προς τα γραφεία**.»*
 *
 * Όσο ο πληθυσμός ήταν **μόνο** μεσιτικά γραφεία, αυτό ήταν ανεκτό κόστος. Με
 * ελαιοχρωματιστές, δικηγόρους, μηχανικούς **και** μεσίτες στον **ίδιο** πίνακα,
 * ο επισκέπτης που ψάχνει δικηγόρο διαβάζει **τα πάντα** με σειρά που το ίδιο το
 * repo παραδέχεται μεροληπτική. ⇒ **Κατάλογος χωρίς φίλτρο κάνει αυτή τη
 * μετρημένη μεροληψία τον ΜΟΝΟ μηχανισμό εύρεσης.**
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 ΤΟ ΣΥΝΟΡΟ, ΑΚΡΙΒΩΣ: **ΠΟΙΟΣ ΕΓΡΑΨΕ ΤΟ ΔΕΔΟΜΕΝΟ ΠΑΝΩ ΣΤΟ ΟΠΟΙΟ ΚΟΒΕΙ Ο ΑΞΟΝΑΣ**
 *
 * Δεν είναι *«ποιος πατάει το κουμπί»* — αυτό το πατάει πάντα ο επισκέπτης, και
 * θα δικαιολογούσε τα πάντα.
 *
 * ┌────────────────────────────────────────────────────────────────────────────┐
 * │ Φ1 — Ο ΑΞΟΝΑΣ ΕΙΝΑΙ **ΔΗΛΩΣΗ ΤΟΥ ΙΔΙΟΥ ΤΟΥ ΕΠΑΓΓΕΛΜΑΤΙΑ**, ποτέ μέτρηση    │
 * │      της πλατφόρμας γι' αυτόν. ⛔ αγγελίες · χρόνος απόκρισης · βαθμολογία  │
 * │      · «πληρότητα προφίλ» · **ΕΠΑΛΗΘΕΥΣΗ**.                                │
 * │      🔴 Το τελευταίο είναι το **πιο ύπουλο**: έχει άψογη διατύπωση πρόθεσης │
 * │      («θέλω μόνο επαληθευμένους») και **ΕΞΑΦΑΝΙΖΕΙ τον ελαιοχρωματιστή** —  │
 * │      δηλαδή κάνει την **απουσία μητρώου ΠΟΙΝΗ**, ακριβώς ό,τι απαγορεύει η  │
 * │      Α9.3. Και δεν υποβιβάζει: **εξαφανίζει**.                             │
 * │                                                                            │
 * │ Φ2 — Η ΠΡΟΕΠΙΛΟΓΗ ΕΙΝΑΙ «ΟΛΑ», ρητά, και επιστρέφεται με **ΜΙΑ** ενέργεια. │
 * │      Προεπιλογή που δεν είναι «όλα» είναι **προτίμηση της πλατφόρμας με     │
 * │      ρούχα του χρήστη**.                                                   │
 * │                                                                            │
 * │ Φ3 — Η ΣΕΙΡΑ ΜΕΣΑ ΣΤΟ ΑΠΟΤΕΛΕΣΜΑ **ΔΕΝ ΕΞΑΡΤΑΤΑΙ** ΑΠΟ ΤΟ ΦΙΛΤΡΟ: το       │
 * │      φιλτραρισμένο είναι **ΥΠΑΚΟΛΟΥΘΙΑ** του ταξινομημένου. Καμία           │
 * │      «συνάφεια», κανένα «best match» — εκεί μπαίνει η κατάταξη χωρίς να τη  │
 * │      δει κανείς.                                                           │
 * │                                                                            │
 * │ Φ4 — Η ΑΦΑΙΡΕΣΗ ΕΙΝΑΙ **ΟΡΑΤΗ ΚΑΙ ΑΝΑΣΤΡΕΨΙΜΗ**: «7 από 34». Φίλτρο που    │
 * │      κρύβει το μέγεθος όσων έκρυψε **συρρικνώνει τον κόσμο σιωπηλά**.      │
 * └────────────────────────────────────────────────────────────────────────────┘
 *
 * ⚠️ **ΚΑΝΕΝΑΣ ΑΠΟ ΤΟΥΣ ΤΕΣΣΕΡΙΣ ΔΕΝ ΕΠΕΤΑΙ ΑΠΟ ΤΟΥΣ ΑΛΛΟΥΣ.** Ένα φίλτρο μπορεί
 * να τηρεί τους τρεις και να παραβιάζει τον τέταρτο.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * ⛔ ΓΙΑΤΙ **ΞΕΧΩΡΙΣΤΟ ΑΡΧΕΙΟ** ΑΠΟ ΤΟ `agency-directory-order.ts`
 *
 * Εκείνο είναι το **ονομασμένο σημείο του antitrust** και το ίδιο του το σχόλιο
 * απαγορεύει *«δεύτερο κριτήριο»*. Το φίλτρο είναι επιλογή **του επισκέπτη**,
 * όχι κατάταξη της πλατφόρμας — και μπαίνει αλλού ώστε η διάκριση να είναι
 * **δομική**, ορατή στο δέντρο αρχείων και όχι μόνο σε σχόλιο.
 * ⛔ Ούτε `.filter()` μέσα στο component: απόφαση **χωρίς διεύθυνση** δεν έχει
 * άγκυρα που να τη μεταλλάξει.
 *
 * @module lib/agency/showcase-filter
 * @see lib/agency/agency-directory-order.ts — η ΣΕΙΡΑ, που δεν αγγίζεται από εδώ
 * @see lib/listings/listing-filters.ts — η μηχανή «σημείο + ακτίνα», δεύτερος καταναλωτής
 */

import { distanceMeters } from '@/lib/geo/geo-distance';
import { readGeoFilter, type ListingGeoFilter } from '@/lib/listings/listing-filters';
import type { PublicShowcase } from '@/types/agency-profile';
import type { EscoBilingualText } from '@/types/contacts/esco-types';

// =============================================================================
// Η ΚΑΤΑΣΤΑΣΗ — δύο άξονες, κλειστό σχήμα
// =============================================================================

/**
 * **Το sentinel του «όλα»** — ΠΟΤΕ `value=""`.
 *
 * ⚠️ Το Radix Select **δεσμεύει** το κενό string: ένα `<SelectItem value="">`
 * πετά σε χρόνο εκτέλεσης και **ρίχνει ΟΛΟΚΛΗΡΗ την επιφάνεια** *(CHECK 3.48)*.
 *
 * 🔑 Και **δεν διαρρέει ποτέ** στο {@link ShowcaseFilters}: εκεί το «όλα» είναι
 * `null`. Δύο αναπαραστάσεις της ίδιας έννοιας σε δύο επίπεδα θα ήταν το σχήμα
 * που κάθε καταναλωτής πρέπει να θυμάται να μεταφράσει.
 */
export const ALL_OCCUPATIONS = 'all' as const;

/**
 * **Κλειστό σχήμα ΔΥΟ αξόνων.**
 *
 * ⚠️ **Τρίτος άξονας ⇒ ξαναδιάβασε τον Φ1.** Και τα δύο πεδία κόβουν πάνω σε
 * δεδομένο που **δήλωσε ο ίδιος ο επαγγελματίας** *(ειδικότητα · τόπος)*, ποτέ
 * πάνω σε μέτρηση της πλατφόρμας γι' αυτόν. Υπάρχει άγκυρα που μετρά **τα
 * κλειδιά αυτού του αντικειμένου** — δηλαδή ένα `verifiedOnly` κοκκινίζει τη
 * σουίτα πριν προλάβει να φτάσει σε οθόνη.
 */
export interface ShowcaseFilters {
  /** ESCO URI, ή `null` = **ΟΛΕΣ**. Το sentinel `'all'` δεν φτάνει ποτέ εδώ. */
  readonly occupation: string | null;
  /** `null` = **όπου να 'ναι**. Ίδιο σχήμα με το `ListingFilters.near`. */
  readonly near: ListingGeoFilter | null;
}

/** Η **προεπιλογή είναι «όλα»** — Φ2, ρητά και σε ένα σημείο. */
export const EMPTY_SHOWCASE_FILTERS: ShowcaseFilters = {
  occupation: null,
  near: null,
};

/** Το όνομα της παραμέτρου της ειδικότητας στη διεύθυνση. */
const OCCUPATION_PARAM = 'occupation';

// =============================================================================
// ΔΙΕΥΘΥΝΣΗ ⇄ ΚΑΤΑΣΤΑΣΗ
// =============================================================================

/**
 * Διεύθυνση → φίλτρα. **Ό,τι δεν διαβάζεται, δεν φιλτράρει** *(Φ2)*.
 *
 * 🔑 **Πλήρες ESCO URI, όχι το uuid του**. Το uuid θα ήταν κοντύτερο και θα ήταν
 * **δεύτερο όνομα** για την ίδια ταυτότητα — δηλαδή δύο βιβλία, με τον επόμενο
 * να πρέπει να θυμάται σε ποιο βρίσκεται.
 */
export function parseShowcaseFilters(params: URLSearchParams): ShowcaseFilters {
  const raw = params.get(OCCUPATION_PARAM)?.trim() ?? '';
  return {
    // ⚠️ Το sentinel μεταφράζεται ΕΔΩ, μία φορά, στο σύνορο.
    occupation: raw === '' || raw === ALL_OCCUPATIONS ? null : raw,
    // 🔑 ΜΗΔΕΝ ΔΙΠΛΟΤΥΠΟ: η ίδια συνάρτηση που διαβάζει το γεωγραφικό φίλτρο των
    //    αγγελιών. Δεύτερη υλοποίηση θα ξεχνούσε τον έλεγχο `|lat| > 90`.
    near: readGeoFilter(params),
  };
}

/** Κατάσταση → διεύθυνση. **Τα κενά φίλτρα ΔΕΝ γράφονται** *(μία διεύθυνση ανά ερώτημα)*. */
export function serializeShowcaseFilters(filters: ShowcaseFilters): URLSearchParams {
  const params = new URLSearchParams();
  if (filters.occupation !== null) params.set(OCCUPATION_PARAM, filters.occupation);
  // ⚠️ Τα τρία γεωγραφικά **μαζί ή καθόλου** — ίδιος κανόνας με το
  //    `serializeListingFilters`: μισό ζεύγος δεν είναι μερικώς χρήσιμο.
  if (filters.near !== null) {
    params.set('lat', String(filters.near.center.lat));
    params.set('lng', String(filters.near.center.lng));
    params.set('r', String(filters.near.radiusKm));
  }
  return params;
}

/** Υπάρχει έστω ένας ενεργός άξονας; — για το «Καθαρισμός» *(Φ4)*. */
export function hasActiveFilters(filters: ShowcaseFilters): boolean {
  return filters.occupation !== null || filters.near !== null;
}

// =============================================================================
// Η ΠΡΑΞΗ
// =============================================================================

/**
 * **`filter`, ΠΟΤΕ `sort`** — η έξοδος είναι **ΥΠΑΚΟΛΟΥΘΙΑ** της εισόδου *(Φ3)*.
 *
 * ⚠️ Μια `sort()` εδώ θα ήταν **δεύτερη απάντηση** στο ερώτημα του
 * `agency-directory-order.ts` — και η επόμενη, εμπορική, θα έμπαινε δίπλα της
 * χωρίς να τη δει κανείς. Υπάρχει άγκυρα που ελέγχει τη **σειρά**, όχι μόνο το
 * σύνολο.
 *
 * @param ordered Ο **ήδη ταξινομημένος** πίνακας — από το `usePublicAgencies`.
 */
export function applyShowcaseFilters(
  ordered: readonly PublicShowcase[],
  filters: ShowcaseFilters,
): readonly PublicShowcase[] {
  if (!hasActiveFilters(filters)) return ordered;
  return ordered.filter((showcase) => matchesFilters(showcase, filters));
}

function matchesFilters(showcase: PublicShowcase, filters: ShowcaseFilters): boolean {
  if (filters.occupation !== null) {
    // 🔑 **ΚΑΘΕ credential μετρά**: το μικτό γραφείο βρίσκεται ΚΑΙ ως μεσίτης ΚΑΙ
    //    ως τεχνικό. Ένα `credentials[0]` θα έκρυβε τη μισή του ταυτότητα.
    const offers = showcase.credentials.some(
      (credential) => credential.occupation.escoUri === filters.occupation,
    );
    if (!offers) return false;
  }

  if (filters.near !== null) {
    // ⚠️ **Χωρίς δηλωμένο τόπο, ΔΕΝ ταιριάζει** — και δεν είναι ποινή: ο άξονας
    //    ρωτά «πού είσαι;» και η βιτρίνα δεν το λέει. Η εναλλακτική («να
    //    εμφανίζεται παντού») θα έδινε σε όποιον ΔΕΝ δηλώνει τόπο **καθολική
    //    ορατότητα** — δηλαδή θα αντάμειβε τη σιωπή.
    if (showcase.position === null) return false;
    const metres = distanceMeters(filters.near.center, showcase.position);
    if (metres > filters.near.radiusKm * 1000) return false;
  }

  return true;
}

// =============================================================================
// ΟΙ ΕΠΙΛΟΓΕΣ — παράγονται από τον ΠΛΗΘΥΣΜΟ, δεν απαριθμούνται πουθενά
// =============================================================================

/** Μία επιλογή του χειριστηρίου ειδικότητας. */
export interface OccupationOption {
  readonly escoUri: string;
  readonly label: EscoBilingualText;
}

/**
 * **Οι επιλογές ΕΙΝΑΙ ο πληθυσμός** — καμία λίστα, πουθενά.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🏆 ΓΙΑΤΙ ΑΥΤΟ ΕΙΝΑΙ ΚΑΛΥΤΕΡΟ ΑΠΟ ΟΣΑ ΚΑΝΟΥΝ ΟΙ ΜΕΓΑΛΟΙ — ΟΧΙ ΑΠΛΩΣ ΦΘΗΝΟΤΕΡΟ
 *
 * 1. ⛔ **ΚΑΝΕΝΑ ΔΕΚΑΤΟ ΛΕΞΙΛΟΓΙΟ** *(ADR-798 Α2 · ADR-749)*. Οι εναλλακτικές
 *    μετρήθηκαν και απορρίφθηκαν: **2.942** ESCO occupations σε dropdown είναι
 *    αδύνατο· **ISCO μείζων** *(1 ψηφίο)* βάζει δικηγόρο και μηχανικό στο ίδιο
 *    `2`· **ISCO υπο-μείζων** *(43 ομάδες)* διακρίνει σωστά αλλά απαιτεί **43
 *    επίσημους τίτλους ILO × 2 γλώσσες γραμμένους στο χέρι**. Εδώ οι τιμές είναι
 *    τα `escoUri` που **ήδη ζουν** στα έγγραφα και οι ετικέτες το
 *    `occupation.label` που **ήδη ταξιδεύει δίγλωσσο**. **Μηδέν νέο κλειδί i18n.**
 *
 * 2. 🔑 **ΚΑΜΙΑ ΕΠΙΛΟΓΗ ΔΕΝ ΟΔΗΓΕΙ ΣΕ ΚΕΝΟ, ΕΞ ΟΡΙΣΜΟΥ.** Houzz και Thumbtack
 *    προσφέρουν trades με **μηδέν** επαγγελματίες στην περιοχή σου —
 *    *κατάλογος που υπόσχεται πληθυσμό που δεν έχει*. Εδώ είναι **δομικά
 *    αδύνατο**: κάθε επιλογή προήλθε από βιτρίνα που υπάρχει.
 *
 * 3. ✅ **Η ΣΕΙΡΑ ΤΩΝ ΕΠΙΛΟΓΩΝ ΕΙΝΑΙ ΚΙ ΑΥΤΗ ΟΥΔΕΤΕΡΗ**: αλφαβητικά κατά ετικέτα,
 *    tie-break στο URI ⇒ **ολική**. ⛔ **ΠΟΤΕ «κατά πλήθος»** — θα ήταν κατάταξη
 *    **ΕΠΑΓΓΕΛΜΑΤΩΝ** μέσα στο ίδιο το χειριστήριο, δηλαδή ο Φ1 παραβιασμένος
 *    στο σημείο που κανείς δεν κοιτά.
 *
 * 🔶 **ΔΗΛΩΜΕΝΟ ΟΡΙΟ**: όταν οι διακριτές ειδικότητες ξεπεράσουν όσες χωρά ένα
 * `<Select>`, χρειάζεται δεύτερο επίπεδο *(ISCO υπο-μείζων)*. Οι 43 τίτλοι τότε
 * **ΕΙΣΑΓΟΝΤΑΙ** από την πηγή, όπως εισήχθησαν τα 2.942 — ⛔ **ποτέ
 * πληκτρολογημένοι**. Μέχρι τότε δεν πληρώνεται.
 *
 * @param locale Η γλώσσα της σειράς — η αλφαβητική σειρά είναι **ανά γλώσσα**.
 */
export function occupationOptions(
  showcases: readonly PublicShowcase[],
  locale: 'el' | 'en',
): readonly OccupationOption[] {
  const byUri = new Map<string, EscoBilingualText>();
  for (const showcase of showcases) {
    for (const credential of showcase.credentials) {
      // ⚠️ Πρώτη γραφή νικά — οι ετικέτες είναι στιγμιότυπα της ταξινομίας και
      //    δύο βιτρίνες μπορεί να τις έχουν πάρει σε διαφορετικές στιγμές. Η
      //    διαφορά είναι αδιάφορη για την επιλογή· η **σταθερότητα** δεν είναι.
      if (!byUri.has(credential.occupation.escoUri)) {
        byUri.set(credential.occupation.escoUri, credential.occupation.label);
      }
    }
  }

  return [...byUri.entries()]
    .map(([escoUri, label]) => ({ escoUri, label }))
    .sort((a, b) => {
      const byLabel = a.label[locale].localeCompare(b.label[locale], locale);
      // 🔑 Tie-break στην **ταυτότητα** ⇒ ολική σειρά. Δύο ειδικότητες με
      //    ταυτόσημη ετικέτα δεν θα εναλλάσσονταν ανά φόρτωση.
      return byLabel !== 0 ? byLabel : a.escoUri.localeCompare(b.escoUri);
    });
}
