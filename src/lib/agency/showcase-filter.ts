/**
 * **`filter`, ΠΟΤΕ `sort`** — η έξοδος είναι **ΥΠΑΚΟΛΟΥΘΙΑ** της εισόδου *(Φ3)*.
 *
 * ⚠️ Μια `sort()` εδώ θα ήταν **δεύτερη απάντηση** στο ερώτημα του
 * `agency-directory-order.ts` — και η επόμενη, εμπορική, θα έμπαινε δίπλα της
 * χωρίς να τη δει κανείς. Υπάρχει άγκυρα που ελέγχει τη **σειρά**, όχι μόνο το
 * σύνολο.
 *
 * @param ordered Ο **ήδη ταξινομημένος** πίνακας — από το `usePublicAgencies`.
 */
export function applyShowcaseFilters(
  ordered: readonly PublicShowcase[],
  filters: ShowcaseFilters,
  resolvers: CoverageResolvers,
): readonly PublicShowcase[] {
  if (!hasActiveFilters(filters)) return ordered;
  return ordered.filter((showcase) => matchesFilters(showcase, filters, resolvers));
}

function matchesFilters(
  showcase: PublicShowcase,
  filters: ShowcaseFilters,
  resolvers: CoverageResolvers,
): boolean {
  if (filters.occupation !== null) {
    // 🔑 **ΚΑΘΕ credential μετρά**: το μικτό γραφείο βρίσκεται ΚΑΙ ως μεσίτης ΚΑΙ
    //    ως τεχνικό. Ένα `credentials[0]` θα έκρυβε τη μισή του ταυτότητα.
    const offers = showcase.credentials.some(
      (credential) => credential.occupation.escoUri === filters.occupation,
    );
    if (!offers) return false;
  }

  if (filters.where !== null) {
    // ═══════════════════════════════════════════════════════════════════════
    // 🔴 **ΤΟ ΕΛΑΤΤΩΜΑ ΤΟΥ ADR-846 ΕΠΙΒΙΩΝΕ ΑΚΕΡΑΙΟ ΣΤΟΝ ΕΝΑΝ ΑΞΟΝΑ** (Φάση 2).
    //
    // Μέχρι εδώ, το **διοικητικό** σκέλος έκρινε τη **δήλωση** («πού δουλεύω»),
    // ενώ το **κυκλικό** έκρινε την **έδρα** («πού κάθομαι»). Δηλαδή ο επισκέπτης
    // που ρωτά «20 χλμ γύρω μου» — η **προεπιλεγμένη** ερώτηση του καταλόγου —
    // εξακολουθούσε να βρίσκει με βάση το πού **κάθεται** ο επαγγελματίας: ο
    // Θερμαίος μπετατζής που δηλώνει Χαλκιδική έμενε **αόρατος** σε επισκέπτη της
    // Κασσάνδρας, ακριβώς το σενάριο που το ADR-846 ονόμασε και θεράπευσε — στη
    // **μισή** του εφαρμογή.
    //
    // ✅ Πλέον **και τα δύο σκέλη ρωτούν τη ΔΗΛΩΣΗ**, μέσα από τον **έναν** κριτή.
    // ⚠️ Η **έδρα μένει ως το «δεν δήλωσε»**: όποιος δεν έχει `coverage` κρίνεται
    //    όπως πριν, ώστε η Φάση 2 να μην **εξαφανίσει** κανέναν υπάρχοντα.
    // ⚠️ «Δεν ξέρω» *(κενή γενεαλογία · αποτύπωμα που λείπει)* **δεν κόβει** — το
    //    `coverageMatches` το μεταφράζει σε «ταιριάζει», και η κάρτα το **λέει**.
    // ═══════════════════════════════════════════════════════════════════════
    // ═══════════════════════════════════════════════════════════════════════
    // 🏆 **ΦΑΣΗ 5δ — ΕΝΩΣΗ, ΟΧΙ ΑΝΤΙΚΑΤΑΣΤΑΣΗ** *(ADR-846 §8.8.15)*.
    //
    // Ως τη Φ5δ αυτό το `if` ήταν **μοναδικός κριτής**, και γι' αυτό η ίδια η θεραπεία
    // του ADR-846 γεννούσε το ψευδώς αρνητικό που θεράπευε: ο μεσίτης που δηλώνει
    // εμβέλεια **χωρίς** τις περιοχές των ήδη δημοσιευμένων ακινήτων του
    // **εξαφανιζόταν από εκεί όπου αποδεδειγμένα δουλεύει** *(§8.8.1, αποτέλεσμα Α)*.
    //
    // 🔑 **Δύο μαρτυρίες, όχι δύο κριτές**: εμφανίζεται **είτε** επειδή το **δήλωσε**
    //    *(λόγος ανθρώπου)* **είτε** επειδή έχει εκεί **ζωντανό ακίνητο** *(γεγονός)*.
    //    Αυτό είναι το Zillow — **χωρίς την αδιαφάνειά του**: η κάρτα λέει **ποια** από
    //    τις δύο, και το `AgencyCard` δεν έχει άδεια να σιωπήσει.
    //
    // ⛔ **ΚΑΙ ΟΙ ΔΥΟ ΜΟΝΟ ΕΠΙΤΡΕΠΟΥΝ — ΚΑΜΙΑ ΔΕΝ ΚΑΤΑΤΑΣΣΕΙ.** Η σειρά μένει άθικτη
    //    *(`agency-directory-order.ts`: εγγύτητα έδρας ή ισοτιμία)*, και το `presence`
    //    είναι γραμμένο στη λίστα `forbidden` του `Α1`. Η απόδειξη μπορεί μόνο να **μη
    //    σε αποκλείει** — **ποτέ** να σε ανεβάσει *(ADR-827 §9.9 α, NAR $418M)*.
    //
    // ⚠️ **Το `presence` ρωτιέται ΔΕΥΤΕΡΟ, και είναι φθηνότερο έτσι**: η δήλωση απαντά
    //    χωρίς γεωμετρία στις πιο συχνές περιπτώσεις *(`nationwide` ⇒ `within` στην
    //    πρώτη γραμμή)*, ενώ η απόδειξη διατρέχει κύκλους. Και σήμερα το `presence`
    //    είναι **κενό για όλους** *(6 ακίνητα · 0 στον χάρτη, §8.8.5 α)*, άρα ο δεύτερος
    //    όρος κοστίζει **μηδέν** μέχρι να υπάρξουν θέσεις.
    // ═══════════════════════════════════════════════════════════════════════
    if (presenceMatches(showcase.presence, filters.where, resolvers)) {
      // Αποδεδειγμένη παρουσία ⇒ **περνά**, ό,τι κι αν λέει η δήλωση. Δεν είναι
      // παράκαμψη του κριτή: είναι η **δεύτερη** μαρτυρία, και ο κριτής της είναι
      // αυστηρότερος (`within`, ποτέ `intersects` — δες `showcase-presence.ts`).
    } else if (showcase.coverage !== null) {
      if (!coverageMatches(showcase.coverage, filters.where, resolvers)) return false;
    } else if (isAdministrativeWhere(filters.where)) {
      // Δεν δήλωσε εμβέλεια και το ερώτημα είναι διοικητικό: δεν υπάρχει τίποτα να
      // κριθεί. Η έδρα **δεν** υποκαθιστά — δεν έχουμε γεωμετρία ορίων για να τη
      // ρωτήσουμε, και μια μαντεψιά εδώ θα ήταν αόρατη στον άνθρωπο.
      return false;
    } else {
      // ⚠️ **Χωρίς δηλωμένη έδρα, ΔΕΝ ταιριάζει** — και δεν είναι ποινή: ο άξονας
      //    ρωτά «πού είσαι;» και η βιτρίνα δεν το λέει. Η εναλλακτική («να
      //    εμφανίζεται παντού») θα έδινε σε όποιον ΔΕΝ δηλώνει τόπο **καθολική
      //    ορατότητα** — δηλαδή θα αντάμειβε τη σιωπή.
      if (showcase.position === null) return false;
      const metres = distanceMeters(filters.where.circle.center, showcase.position);
      if (metres > filters.where.circle.radiusKm * 1000) return false;
    }
  }

  return true;
}

