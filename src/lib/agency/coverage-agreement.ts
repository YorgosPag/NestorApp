import { isBoundingBox } from '@/lib/geo/geo-area';
import { listingSearchArea } from '@/lib/listings/listing-map-shape';
import type { DeclaredCoverage } from '@/types/agency-coverage';
import type { PublicListing } from '@/types/public-listing';

// ============================================================================
// ΟΙ ΤΕΣΣΕΡΙΣ ΚΑΤΑΣΤΑΣΕΙΣ — κλειστό σύνολο, με ΔΙΑΦΟΡΕΤΙΚΗ θεραπεία η καθεμία
