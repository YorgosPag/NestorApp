/**
 * @fileoverview **Η ΔΗΛΩΣΗ ΕΝΑΝΤΙΟΝ ΤΗΣ ΠΡΟΣΦΟΡΑΣ** — συμφωνεί το «πού δουλεύω» με το
 * «πού έχω ακίνητα»;
 * @related ADR-846 §8.8 (Φάση 5) · ADR-777 §8.63 (αβεβαιότητα με μέγεθος) · ADR-827 §9.9 α
 * @module lib/agency/coverage-agreement
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΜΕΤΡΗΜΕΝΟ ΕΛΑΤΤΩΜΑ: ΔΥΟ ΥΠΟΣΥΣΤΗΜΑΤΑ ΠΟΥ ΔΕΝ ΓΝΩΡΙΖΟΝΤΑΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Μέχρι σήμερα το `showcase-filter.ts` έκρινε **μόνο** τη δήλωση και το
 * `listing-geo-query.ts` **μόνο** τη θέση της αγγελίας. **Καμία γραμμή στο δέντρο δεν
 * συγκρίνει τα δύο** *(επαληθεύτηκε: μόνο δύο αρχεία εισάγουν και τα δύο λεξιλόγια, και
 * κανένα δεν κάνει σύγκριση)*.
 *
 * ⇒ Ο μεσίτης που δηλώνει εμβέλεια **χωρίς** τις περιοχές των ήδη δημοσιευμένων
 * ακινήτων του **εξαφανίζεται από εκεί όπου αποδεδειγμένα δουλεύει** — το ψευδώς
 * αρνητικό που γέννησε ολόκληρο το ADR-846, προκαλούμενο πλέον **από την ίδια τη
 * θεραπεία**. Και η δημοσίευση είναι **σιωπηλά καταστροφική**: κανείς δεν του λέει τι
 * μόλις έσπασε.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 Η ΑΒΕΒΑΙΟΤΗΤΑ ΜΠΑΙΝΕΙ ΣΤΗΝ ΚΡΙΣΗ — ΚΑΙ ΕΔΩ ΞΕΠΕΡΝΑΜΕ ΤΟΥΣ ΜΕΓΑΛΟΥΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το **Zillow** συγκρίνει *ταχυδρομικό κώδικα με ταχυδρομικό κώδικα*: μια αγγελία
 * γεωκωδικοποιημένη σε **κέντρο πόλης** μετράει εκεί **σαν να ξέραμε τη διεύθυνσή της**.
 *
 * 🔑 Εδώ **δεν** κρίνουμε σημείο. Κρίνουμε **{@link listingSearchArea}** — την περιοχή
 * *«πού μπορεί να βρίσκεται αυτή η αγγελία»*, με ακτίνα από το `LISTING_UNCERTAINTY_KM`
 * *(`pin` = 0 · δρόμος = 0,25 · συνοικία = 1,5 · **μόνο πόλη = 10**)*. ⇒ Για μια αγγελία
 * που ξέρουμε **μόνο σε επίπεδο πόλης** ο κριτής απαντά **«δεν ξέρω»**, και **δεν** λέμε
 * ποτέ στον άνθρωπο *«αυτό το ακίνητο είναι εκτός της δήλωσής σου»* όταν **δεν ξέρουμε
 * πού είναι**.
 *
 * ⚠️ **Και δεν χρειάστηκε νέα γεωμετρία**: το `listingSearchArea` υπήρχε ήδη *(ADR-777
 * §8.63)*, ο `coverageRelation` δέχεται ήδη κύκλο, και το «δεν ξέρω» είναι ήδη **τέταρτη
 * τιμή** του `CoverageRelation` *(Φάση 2)*. Τρία κομμάτια που γράφτηκαν χωριστά
 * κούμπωσαν χωρίς μετατροπέα — δες ADR-846 §8.8.4.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΚΑΜΙΑ ΔΕΥΤΕΡΗ ΛΟΓΙΣΤΙΚΗ, ΚΑΝΕΝΑΣ ΔΕΥΤΕΡΟΣ ΚΡΙΤΗΣ — ΤΟ ΚΥΡΙΟ ΣΧΕΔΙΑΣΤΙΚΟ ΟΡΙΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Αυτό το αρχείο **δεν** ξαναρωτά «πού είναι η αγγελία;» *(το κάνει το
 * `listingSearchArea`)*, **δεν** ξαναρωτά «καλύπτει η δήλωση;» *(το κάνει ο
 * `coverageRelation`)* και **δεν** κρατά δικό του μετρητή αγγελιών. Κάνει **ΜΙΑ**
 * πράξη: **συσσωρεύει τις ετυμηγορίες**. Ένας δεύτερος κριτής εδώ θα ήταν το σχήμα του
 * **ADR-749** *(τέσσερις μηχανές, τρεις αριθμοί για το ίδιο δέντρο)* γεννημένο μέσα στο
 * αρχείο που το επικαλείται.
 */

