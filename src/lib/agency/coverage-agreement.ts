/**
 * **Συμφωνεί η δήλωση με την προσφορά;**
 *
 * 🔑 **Κλειστή ένωση, όχι `boolean`** — ίδιο ιδίωμα με το `CoverageState` και το
 * `CoverageRelation`, και για τον ίδιο λόγο: κάθε κατάσταση έχει **άλλη θεραπεία** και
 * **άλλο κείμενο**. Ένα `isConsistent: boolean` θα συγχώνευε *«δεν έχει αγγελίες»* με
 * *«δεν ξέρουμε πού είναι οι αγγελίες του»* — δύο πραγματικά διαφορετικές σιωπές.
 *
 * | Κατάσταση | Τι ισχύει | Τι οφείλει να κάνει η οθόνη |
 * |---|---|---|
 * | `agreed` | κάθε **εντοπίσιμη** αγγελία μέσα στη δήλωση | **τίποτα** — ο έπαινος για το αναμενόμενο είναι θόρυβος |
 * | `understated` | υπάρχουν αγγελίες **αποδεδειγμένα έξω** | να το πει **πριν** τη δημοσίευση, και να προτείνει επέκταση |
 * | `unproven` | **καμία** αγγελία — η δήλωση δεν αντικρούεται από τίποτα | **τίποτα**, και ποτέ υπόνοια: ο νέος επαγγελματίας δεν είναι ύποπτος |
 * | `unknown` | υπάρχουν αγγελίες, **καμία** εντοπίσιμη | **σιωπή** — ποτέ ετυμηγορία από δικό μας κενό |
 *
 * ⚠️ **Το `unproven` ΔΕΝ τιμωρείται, και εκεί χωρίζουμε από την Google.** Στο Business
 * Profile η αναπόδεικτη περιοχή είναι **ύποπτη** *(flag / suspension)*, γιατί εκεί η
 * περιοχή **ταΐζει το local pack**. Εδώ η δήλωση **δεν κατατάσσει** *(ADR-846 §2.1)*,
 * άρα δεν υπάρχει κίνητρο υπερδήλωσης — και ο μεσίτης που **ξεκινά** σε νέα περιοχή, ή
 * δουλεύει **αγοραστές** χωρίς δικό του απόθεμα, είναι απολύτως νόμιμος.
 */
export type CoverageAgreement = 'agreed' | 'understated' | 'unproven' | 'unknown';

/**
 * **Η μαρτυρία της προσφοράς** — λογιστική **και** ετυμηγορία, στην ίδια τιμή.
 *
 * ⚠️ Το `agreement` **δεν** είναι ανεξάρτητο δεδομένο: παράγεται **ντετετμινιστικά** από
 * τους τρεις μετρητές μέσω του {@link agreementOf}. Αποθηκεύεται ως πεδίο μόνο ώστε ο
 * καταναλωτής να μην το ξαναρωτά — **ποτέ** ώστε να μπορεί να τεθεί ανεξάρτητα.
 *
 * 🔴 **`total === inside + outside + indeterminate`, πάντα.** Είναι το ίδιο συμβόλαιο με
 * το `ledgerBalances` του `ListingLedger`, και υπάρχει άγκυρα που το **εκτελεί**: μια
 * λογιστική που δεν κλείνει σημαίνει ότι μια αγγελία δεν μετρήθηκε **σε κανέναν κάδο**,
 * δηλαδή εξαφανίστηκε σιωπηλά από την κρίση.
 */
export interface CoverageEvidence {
  /** Πόσες αγγελίες κρίθηκαν συνολικά. */
  readonly total: number;
  /** **Αποδεδειγμένα** μέσα: **μόνο** `within` — δες τη μετάφραση στο {@link verdictForListing}. */
  readonly inside: number;
  /** **Αποδεδειγμένα** έξω (`disjoint`) — αυτές γεννούν το `understated`. */
  readonly outside: number;
  /** Δεν ξέρουμε: χωρίς θέση, ή θέση **πολύ αβέβαιη** για ετυμηγορία. */
  readonly indeterminate: number;
  /** Η ετυμηγορία πάνω στους τρεις μετρητές. */
  readonly agreement: CoverageAgreement;
}

// ============================================================================
// Η ΚΡΙΣΗ ΑΝΑ ΑΓΓΕΛΙΑ — μία ερώτηση, τρεις δυνατές απαντήσεις
// ============================================================================

/**
 * **Πού πέφτει αυτή η αγγελία σε σχέση με τη δήλωση;**
 *
 * 🔑 **Οι δύο πηγές του `'indeterminate'` είναι ΔΙΑΦΟΡΕΤΙΚΕΣ και συγχωνεύονται εδώ
 * επίτηδες**: *(α)* η αγγελία **δεν έχει θέση** *(`listingSearchArea` → `null`)* και
 * *(β)* έχει θέση **πολύ αβέβαιη** *(ο `coverageRelation` απαντά `'unknown'`)*. Για
 * **εμάς** η διαφορά μετριέται αλλού *(`ListingLedger.unmapped`, που ήδη υπάρχει)*· για
 * **τον άνθρωπο** που ρωτά *«συμφωνεί η δήλωσή μου;»* και οι δύο σημαίνουν το ίδιο
 * πράγμα: **δεν μπορούμε να απαντήσουμε, και δεν θα μαντέψουμε**.
 *
 * ⚠️ **Ένα `GeoBoundingBox` ΔΕΝ κρίνεται — και δεν σιωπά.** Το `listingSearchArea`
 * επιστρέφει σήμερα **πάντα** κύκλο, οπότε ο κλάδος είναι δομικά ανέφικτος· γι' αυτό
 * μετρά ως `'indeterminate'` **αντί** να πέσει σε ήσυχο `false`. Τη μέρα που κάποιος
 * επιστρέψει ορθογώνιο, η απάντηση θα είναι *«δεν ξέρω»* — **τίμια** — και όχι μια
 * σιωπηλή ετυμηγορία χτισμένη σε σχήμα που ο κριτής δεν δέχεται.
 */
export type ListingCoverageVerdict = 'inside' | 'outside' | 'indeterminate';

export function verdictForListing(
  coverage: DeclaredCoverage | null,
  listing: PublicListing,
  resolvers: CoverageResolvers,
): ListingCoverageVerdict {
  const area = listingSearchArea(listing.position);
  if (area === null || isBoundingBox(area)) return 'indeterminate';

  // ═══════════════════════════════════════════════════════════════════════════
  // 🔴 Η ΜΕΤΑΦΡΑΣΗ ΤΟΥ `intersects` ΕΙΝΑΙ ΑΝΤΙΣΤΡΟΦΗ ΑΠΟ ΤΟΥ ΚΑΤΑΛΟΓΟΥ — ΕΠΙΤΗΔΕΣ.
  //
  // Ο `coverageMatches` δέχεται **οτιδήποτε ≠ `disjoint`**, και έχει δίκιο: εκεί η
  // ερώτηση είναι *«υπάρχει επικάλυψη ανάμεσα στη δήλωση και σε ό,τι ρωτά ο
  // επισκέπτης;»* — και μια επικάλυψη **είναι** απάντηση «ναι».
  //
  // Εδώ η ερώτηση είναι **άλλη**: *«βρίσκεται **ΑΥΤΟ ΤΟ ΑΚΙΝΗΤΟ** μέσα στη δήλωση;»*.
  // Το `intersects` σημαίνει *«ο κύκλος αβεβαιότητάς του **αγγίζει** τη δήλωση»* —
  // δηλαδή **μπορεί** να είναι μέσα, **μπορεί** και έξω. Μεταφρασμένο σε `inside` θα
  // ήταν **ισχυρισμός χωρίς απόδειξη**· μεταφρασμένο σε `outside` θα κατηγορούσε τον
  // άνθρωπο για δικό μας κενό. Η μόνη τίμια απάντηση είναι **«δεν ξέρω»**.
  //
  // 🔑 **ΤΟ ΕΠΙΑΣΕ Η ΑΓΚΥΡΑ Γ2, ΟΧΙ Η ΚΡΙΣΗ ΜΟΥ** *(2026-09-08)*: ακίνητο γνωστό μόνο
  //    σε επίπεδο **πόλης** *(±10 χλμ)*, **24 χλμ** μακριά από δήλωση **20 χλμ**,
  //    επέστρεφε `inside` — δηλαδή η μηχανή **βεβαίωνε** κάτι που κανείς δεν ήξερε.
  //    Ίδια οικογένεια με το ελάττωμα που γέννησε το `listingSearchArea`: *«δύο
  //    απαντήσεις στο πού είναι αυτό, μία τίμια και μία που μαντεύει»*.
  //
  // ⚠️ **Άρα η ΙΔΙΑ σχέση έχει ΔΥΟ μεταφράσεις, γιατί οι ερωτήσεις είναι δύο.** Ένας
  //    κοινός μεταφραστής θα ήταν λάθος στη μία από τις δύο — σιωπηλά.
  // ═══════════════════════════════════════════════════════════════════════════
  const relation = coverageOverCircle(coverage, area, resolvers);
  if (relation === 'within') return 'inside';
  if (relation === 'disjoint') return 'outside';
  return 'indeterminate';
}

// ============================================================================
// Η ΕΤΥΜΗΓΟΡΙΑ — καθαρή, εξαντλητική, χωρίς προεπιλογή
// ============================================================================

/**
 * Μετρητές → κατάσταση. **Η σειρά των ελέγχων ΕΙΝΑΙ συμβόλαιο.**
 *
 * 1. **«καμία αγγελία»** κρίνεται **πρώτο**. Χωρίς αυτό, ένα άδειο χαρτοφυλάκιο θα
 *    περνούσε ως `unknown` και η οθόνη θα έλεγε *«δεν ξέρουμε πού είναι τα ακίνητά
 *    σου»* — αληθές αριθμητικά, **παραπλανητικό** στην ουσία: δεν υπάρχουν ακίνητα.
 *    Ίδιο ακριβώς ιδίωμα με το `coverageStateOf` *(`no-supply` πριν από `no-location`)*.
 * 2. **«έστω μία αποδεδειγμένα έξω»** κρίνεται **δεύτερο**, πριν από κάθε σιωπή: μία
 *    αγγελία εκτός δήλωσης είναι **γεγονός**, και δεν ακυρώνεται επειδή δίπλα της
 *    υπάρχουν δέκα άγνωστες.
 * 3. **«καμία εντοπίσιμη»** ⇒ `unknown`. Σήμερα αυτή είναι η **πιο συχνή** απάντηση, όχι
 *    η ακραία: μετρημένο **6 ακίνητα · 0 στον χάρτη** *(2026-08-10, ADR-846 §8.8.5)*.
 *
 * ⚠️ Οτιδήποτε άλλο ⇒ `agreed`: υπάρχει τουλάχιστον μία **αποδεδειγμένα μέσα** και
 * **καμία** έξω.
 */
export function agreementOf(
  counts: Pick<CoverageEvidence, 'total' | 'outside' | 'indeterminate'>,
): CoverageAgreement {
  if (counts.total === 0) return 'unproven';
  if (counts.outside > 0) return 'understated';
  if (counts.indeterminate === counts.total) return 'unknown';
  return 'agreed';
}

/**
 * **Αγγελίες + δήλωση → μαρτυρία.** Η μοναδική είσοδος αυτού του module.
 *
 * ⚠️ **Το `coverage === null` ΔΕΝ είναι ειδική περίπτωση εδώ.** Ο `coverageRelation`
 * απαντά ήδη `'disjoint'` για κενή δήλωση, οπότε *«δεν δήλωσε τίποτα και έχει δέκα
 * ακίνητα»* βγαίνει **σωστά** ως `understated` — δηλαδή *«η δήλωσή σου λέει λιγότερα από
 * όσα κάνεις»*, που είναι **ακριβώς** η αλήθεια για κάποιον που δεν δήλωσε καθόλου.
 */
export function coverageEvidenceOf(
  coverage: DeclaredCoverage | null,
  listings: readonly PublicListing[],
  resolvers: CoverageResolvers,
): CoverageEvidence {
  let inside = 0;
  let outside = 0;

  for (const listing of listings) {
    const verdict = verdictForListing(coverage, listing, resolvers);
    if (verdict === 'inside') inside += 1;
    else if (verdict === 'outside') outside += 1;
  }

  const total = listings.length;
  const indeterminate = total - inside - outside;

  return { total, inside, outside, indeterminate, agreement: agreementOf({ total, outside, indeterminate }) };
}

/**
 * **Ποιες ακριβώς είναι έξω** — για την πρόταση επέκτασης.
 *
 * 🔑 **Ξεχωριστό πέρασμα, όχι δεύτερο κριτήριο.** Καλεί την **ίδια**
 * {@link verdictForListing}, οπότε είναι **αδύνατο** να διαφωνήσει με το
 * `coverageEvidenceOf.outside` — και η άγκυρα το εκτελεί αντί να το δηλώνει.
 *
 * ⚠️ **Δεν επιστρέφει ονόματα περιοχών, και δεν μπορεί**: σημείο → `AdminEntity.id`
 * **δεν λύνεται** *(ADR-846 §9 #1)*. Επιστρέφει τις **αγγελίες**· ό,τι λέει η οθόνη για
 * το «πού» το αντλεί από τα δικά τους πεδία, όχι από συμπέρασμα δικό μας.
 */
export function listingsOutsideCoverage(
  coverage: DeclaredCoverage | null,
  listings: readonly PublicListing[],
  resolvers: CoverageResolvers,
): readonly PublicListing[] {
  return listings.filter((l) => verdictForListing(coverage, l, resolvers) === 'outside');
}
