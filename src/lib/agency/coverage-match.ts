/**
 * **Η γραμμή μιας οντότητας προς τη ρίζα, ΜΕ ΤΟΝ ΕΑΥΤΟ ΤΗΣ ΜΕΣΑ.**
 *
 * 🔑 **Το όνομα λέει «γενεαλογία», όχι «πρόγονοι», επίτηδες**: οι «πρόγονοι» **δεν**
 * περιλαμβάνουν τον εαυτό, και ο έλεγχος *«είναι ο Χ πρόγονος **ή ίδιος** με τον Υ;»*
 * θα χρειαζόταν **δύο** πράξεις σε κάθε καλούντα — δηλαδή κάποιος θα ξεχνούσε τη μία.
 * Με τον εαυτό μέσα, ο έλεγχος είναι **μία** `includes`.
 *
 * ⚠️ **Κενός πίνακας = «ΔΕΝ ΞΕΡΩ»**, ποτέ «καμία σχέση». Συμβαίνει σε **δύο**
 * περιπτώσεις — η ιεραρχία δεν έχει φορτώσει ακόμη *(4,1 MB, τεμπέλικη φόρτωση)*, ή το
 * id δεν υπάρχει. Και στις δύο η **σωστή** συμπεριφορά είναι η ίδια: **μην κόψεις
 * κανέναν με βάση αυτό που δεν ξέρεις** — δες {@link coverageRelation}.
 */
export type LineageResolver = (entityId: string) => readonly string[];

/**
 * **ΤΕΤΑΡΤΗ ΤΙΜΗ: «ΔΕΝ ΞΕΡΩ» — ΚΑΙ ΗΤΑΝ ΠΡΟΒΛΕΨΗ ΑΥΤΟΥ ΤΟΥ ΑΡΧΕΙΟΥ** *(Φάση 2)*.
 *
 * Το {@link coverageMatches} γράφτηκε στη Φάση 1 με ρητή αιτιολογία *«την ημέρα που
 * προστεθεί τέταρτη τιμή, όλοι εκείνοι οι έλεγχοι θα ήταν σιωπηλά λάθος»*. Η μέρα ήρθε.
 *
 * 🔴 **Γιατί ΔΕΝ αρκεί το `disjoint` για το «δεν ξέρω», όπως αρκούσε στη Φάση 1.** Εκεί
 * η άγνοια ήταν **καθολική** *(η ιεραρχία των 4 MB δεν είχε φορτώσει)* και ο **καλών**
 * μπορούσε να μην εφαρμόσει καθόλου τον άξονα *(`areaPending`)*. Εδώ η άγνοια είναι
 * **ανά ζεύγος**: αυτή η βιτρίνα δήλωσε ακτίνα, αυτό το ερώτημα είναι δήμος, και το
 * αποτύπωμα του δήμου λείπει. Ο καλών **δεν έχει καθολική απάντηση** να δώσει.
 *
 * ⚠️ **Και το `unknown` ΔΕΝ κόβει** *(δες {@link coverageMatches})*: εξαφανίζοντας
 * άνθρωπο επειδή **εμείς** δεν έχουμε δεδομένα, θα τιμωρούσαμε τη δήλωσή του για δικό
 * μας κενό. Εμφανίζεται, με ετικέτα που **το λέει**.
 */
export type CoverageRelation = AreaRelation | 'unknown';

/**
 * **Ό,τι χρειάζεται ο κριτής από τον έξω κόσμο** — ένα αντικείμενο, όχι δύο ορίσματα.
 *
 * 🔑 Δύο παράλληλες παράμετροι θα ήταν το σχήμα όπου ο τρίτος καλών περνά τη μία και
 * ξεχνά την άλλη· με **ένα** αντικείμενο, η παράλειψη **δεν μεταγλωττίζεται**.
 */
export interface CoverageResolvers {
  readonly lineageOf: LineageResolver;
  readonly footprintOf: FootprintResolver;
}

/**
 * 🏆 **ΤΟ ΕΝΑ ΚΕΛΙ ΠΟΥ ΕΓΙΝΕ ΟΛΑ ΤΑ ΚΕΛΙΑ** — δύο αποτυπώματα, τέσσερις απαντήσεις.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * ΗΤΑΝ ΔΥΟ ΣΥΝΑΡΤΗΣΕΙΣ ΜΕ ΑΝΤΙΚΑΤΟΠΤΡΙΣΜΕΝΕΣ ΣΥΝΘΗΚΕΣ *(ADR-846 Φ3)*
 *
 * Μέχρι τη Φάση 3 τα δύο «μεικτά» κελιά είχαν **χωριστό** κώδικα — `radiusOverArea`
 * *(δήλωση κύκλος, ερώτημα περιοχή)* και το σώμα του `areasOverCircle` *(το ανάποδο)* —
 * με τις **ίδιες** τρεις συγκρίσεις γραμμένες **καθρεφτισμένα**. Δύο τόποι όπου το
 * ίδιο λάθος έπρεπε να αποφευχθεί δύο φορές.
 *
 * 🔑 **Η αναγωγή που τα ένωσε**: ένας κύκλος **είναι** αποτύπωμα με
 * `innerKm === outerKm === radiusKm` *(`lib/geo/geo-footprint.ts`)*. Με αυτό, και τα
 * δύο κελιά είναι **η ίδια ερώτηση**, και η ισοδυναμία επαληθεύτηκε **όρο προς όρο**
 * πριν σβηστεί οτιδήποτε *(άγκυρα: `coverage-footprint-match.test.ts`)*.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * ⚠️ **ΤΑ `innerKm > 0` ΔΕΝ ΕΙΝΑΙ ΜΙΚΡΟΒΕΛΤΙΩΣΕΙΣ**
 *
 * Το `center` ενός αποτυπώματος **δεν υπόσχεται ότι είναι μέσα στο σχήμα**
 * *(δήμος-αρχιπέλαγος, κοίλο σχήμα)*. Με `innerKm === 0` ο «εγγεγραμμένος κύκλος» είναι
 * **σημείο που μπορεί να είναι έξω** — άρα κάθε συμπέρασμα χτισμένο πάνω του θα ήταν
 * ισχυρισμός **χωρίς απόδειξη**, δηλαδή ακριβώς το ψέμα που όλο αυτό το σχήμα αποφεύγει.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴🔴 **ΤΑ ΟΡΙΣΜΑΤΑ ΛΕΓΟΝΤΑΙ `declared`/`asked` ΚΑΙ ΟΧΙ `subject`/`query` — ΕΠΙΤΗΔΕΣ**
 *
 * Το `areaRelation` του `lib/geo/geo-area.ts` δίνει `within` όταν **subject ⊆ query**·
 * αυτή εδώ δίνει `within` όταν **asked ⊆ declared** — δηλαδή η **αντίθετη** φορά, γιατί
 * εδώ το `within` σημαίνει *«η δήλωση καλύπτει ΟΛΟ ό,τι ρωτήθηκε»*.
 *
 * ⇒ Δύο συναρτήσεις με ορίσματα ονομασμένα `subject`/`query` και **αντίστροφη**
 * σημασία θα ήταν η παγίδα του {@link coverageRelation} **διπλασιασμένη**: και οι δύο
 * σειρές είναι νόμιμες, άρα η λάθος **δεν πετά τίποτα** — γράφει απλώς «μέρος» όπου
 * έπρεπε «όλη». Με ονόματα που **λένε ποιος είναι ποιος**, η αντιστροφή δεν γράφεται.
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * @param declared **η δήλωση** — «πού δουλεύω»
 * @param asked **το ερώτημα** — «πού ψάχνω»
 */
export function footprintRelation(declared: GeoFootprint, asked: GeoFootprint): CoverageRelation {
  const gapKm = distanceMeters(declared.center, asked.center) / 1000;

  // ερώτημα ⊆ εξωτερικός(ερωτήματος) ⊆ εγγεγραμμένος(δήλωσης) ⊆ δήλωση
  if (declared.innerKm > 0 && gapKm + asked.outerKm <= declared.innerKm) return 'within';
  // οι δύο εξωτερικοί δεν αγγίζονται ⇒ ούτε τα σχήματα μέσα τους
  if (gapKm > declared.outerKm + asked.outerKm) return 'disjoint';
  // οι δύο **εγγεγραμμένοι** τέμνονται ⇒ τα σχήματα **αποδεδειγμένα** τέμνονται
  if (declared.innerKm > 0 && asked.innerKm > 0 && gapKm <= declared.innerKm + asked.innerKm) {
    return 'intersects';
  }

  return 'unknown';
}

/**
 * 🏆 **ΔΗΛΩΜΕΝΟ ΠΟΛΥΓΩΝΟ ΕΝΑΝΤΙΟΝ ΑΠΟΤΥΠΩΜΑΤΟΣ** — και **δεν είναι τέταρτο σκέλος
 * λογικής**: είναι το ίδιο ερώτημα με το {@link footprintRelation}, με τη **δήλωση σε
 * πλήρη ακρίβεια** αντί για δύο κύκλους.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΓΙΑΤΙ ΟΧΙ ΣΚΕΤΗ ΑΝΑΓΩΓΗ — **ΜΕΤΡΗΘΗΚΕ, ΔΕΝ ΥΠΟΤΕΘΗΚΕ** *(2026-09-08)*
 *
 * Η προφανής λύση ήταν *«ανάγαγε και το πολύγωνο σε δύο κύκλους και κάλεσε το
 * {@link footprintRelation}»* — μηδέν νέα γεωμετρία. **Μετρήθηκε** πάνω σε **326
 * πραγματικά ελληνικά σχήματα** αραιωμένα στις ~15 κορυφές *(= ό,τι χαράζει άνθρωπος)*
 * εναντίον **10.432** κύκλων-ερωτημάτων:
 *
 * | | «δεν ξέρω» | λάθος ετικέτες |
 * |---|---|---|
 * | **σκέτη αναγωγή** *(2 κύκλοι)* | **23,2 %** — και **31,0 %** σε λεπτά/κοίλα σχήματα | **152** *(είπε «μέρος» ενώ ήταν «όλη»)* |
 * | 🏆 **αυτή η συνάρτηση** | **0,0 %** | **0** |
 *
 * ⇒ Ένας στους τέσσερις επισκέπτες θα έβλεπε *«μπορεί να καλύπτει»* για δήλωση που
 * **ξέρουμε ακριβώς**, επειδή το χαραγμένο σχήμα είναι **λεπτό και κοίλο** — δηλαδή
 * ακριβώς επειδή ο άνθρωπος χάραξε κάτι συγκεκριμένο αντί να πει «ο δήμος μου».
 *
 * 🔑 **ΚΑΙ ΤΟ ΜΗΔΕΝ ΕΙΝΑΙ ΔΩΡΕΑΝ, ΟΧΙ ΕΞΥΠΝΟ**: όταν το ερώτημα είναι **κύκλος**, το
 * αποτύπωμά του έχει `innerKm === outerKm`, οπότε οι τρεις έλεγχοι παρακάτω γίνονται
 * **ακριβείς και εξαντλητικοί** — δεν μένει γκρίζα ζώνη να δηλωθεί. Όταν το ερώτημα
 * είναι **διοικητική οντότητα** *(όπου έχουμε μόνο τους δύο κύκλους της, by design —
 * τα 120 MB πολυγώνων δεν διανέμονται)*, το `unknown` επιβιώνει· **μετρημένο: 29,7 %
 * αντί 38,8 %** της σκέτης αναγωγής, με **μηδέν** ψευδείς ισχυρισμούς.
 *
 * ⚠️ **Καμία νέα γεωμετρία δεν γράφτηκε** — τα δύο πρωτογενή *(«είμαι μέσα;» και «πόσο
 * μακριά είναι το σύνορο;»)* **εξήχθησαν** από το `geoRingsInscribedRadius`, όπου ήδη ζούσαν.
 */
export function outlineOverFootprint(
  declared: readonly GeoOutline[],
  asked: GeoFootprint,
): CoverageRelation {
  const edgeKm = geoRingsNearestEdgeMetres(asked.center, declared) / 1000;
  const centreInside = isPointInGeoRings(asked.center, declared);

  // ολόκληρος ο **εξωτερικός** του ερωτήματος χωράει μέσα ⇒ «σε καλύπτω ολόκληρο»
  if (centreInside && edgeKm >= asked.outerKm) return 'within';
  // ούτε ο **εξωτερικός** δεν αγγίζει το σχήμα ⇒ ούτε το ερώτημα το αγγίζει
  if (!centreInside && edgeKm > asked.outerKm) return 'disjoint';
  // ο **εγγεγραμμένος** του ερωτήματος αγγίζει το σχήμα ⇒ αποδεδειγμένη επαφή
  if (asked.innerKm > 0 && (centreInside || edgeKm <= asked.innerKm)) return 'intersects';

  return 'unknown';
}

/**
 * **Δηλωμένες ΔΙΟΙΚΗΤΙΚΕΣ οντότητες εναντίον ΚΥΚΛΙΚΟΥ ερωτήματος** — το μεικτό κελί
 * όπου η **δήλωση είναι λίστα**, άρα χρειάζεται συσσώρευση.
 *
 * ⚠️ **Η ένωση των δηλώσεων δεν υπολογίζεται, και δεν χρειάζεται**: αρκεί **μία**
 * οντότητα να αποδείξει `within`, ή **μία** να αποδείξει επαφή. Το `disjoint` όμως
 * απαιτεί **όλες** να το αποδείξουν — γι' αυτό το `unknown` επιβιώνει μέχρι το τέλος
 * του βρόχου αντί να επιστρέψει νωρίς.
 *
 * 🔑 **Η κρίση ανά οντότητα έφυγε στο {@link footprintRelation}** — εδώ μένει **μόνο**
 * η συσσώρευση, που είναι η μόνη πράξη που ανήκει πραγματικά σε αυτό το κελί.
 */
function areasOverCircle(
  adminIds: readonly string[],
  asked: GeoFootprint,
  footprintOf: FootprintResolver,
): CoverageRelation {
  let touches = false;
  let uncertain = false;

  for (const adminId of adminIds) {
    const footprint = footprintOf(adminId);
    if (footprint === null) {
      uncertain = true;
      continue;
    }

    switch (footprintRelation(footprint, asked)) {
      case 'within':
        return 'within';
      case 'intersects':
        touches = true;
        break;
      case 'unknown':
        uncertain = true;
        break;
      case 'disjoint':
        break;
    }
  }

  if (touches) return 'intersects';
  return uncertain ? 'unknown' : 'disjoint';
}

/** Το σκέλος της Φάσης 1, αυτούσιο — δήλωση και ερώτημα **και τα δύο** διοικητικά. */
function areasOverArea(
  adminIds: readonly string[],
  queryId: string,
  lineageOf: LineageResolver,
): AreaRelation {
  const queryLineage = lineageOf(queryId);
  // ⚠️ «Δεν ξέρω» ⇒ **δεν αποφασίζω**. Ο καλών (το φίλτρο) δεν εφαρμόζει τον άξονα.
  if (queryLineage.length === 0) return 'disjoint';

  // 1️⃣ Η δήλωση **περιέχει** την περιοχή του επισκέπτη — «σε καλύπτω ολόκληρο».
  for (const declaredId of adminIds) {
    if (queryLineage.includes(declaredId)) return 'within';
  }

  // 2️⃣ Η δήλωση **βρίσκεται μέσα** στην περιοχή του επισκέπτη — «καλύπτω μέρος σου».
  //    ⚠️ Ελέγχεται **δεύτερο**: αν τα δύο ταυτίζονται, η σωστή απάντηση είναι `within`,
  //    και οι τιμές πρέπει να μένουν **αμοιβαία αποκλειόμενες** (κανόνας του
  //    `geo-area.ts` — μία αγγελία σε **ακριβώς έναν** κάδο).
  for (const declaredId of adminIds) {
    if (lineageOf(declaredId).includes(queryId)) return 'intersects';
  }

  return 'disjoint';
}

/**
 * **Η σχέση της δήλωσης προς την περιοχή που ρώτησε ο επισκέπτης.**
 *
 * @param coverage Τι δήλωσε ο επαγγελματίας. `null` = **δεν δήλωσε τίποτα**.
 * @param where Τι ρώτησε ο επισκέπτης — διοικητική οντότητα **ή** κύκλος.
 * @param resolvers Η ιεραρχία και τα αποτυπώματα, με **ένεση**.
 *
 * ⚠️ **`null` δήλωση ⇒ `disjoint`, και ΔΕΝ είναι ποινή** — είναι η ίδια απόφαση με το
 * `showcase.position === null` του υπάρχοντος φίλτρου: ο άξονας ρωτά *«πού δουλεύεις;»*
 * και η βιτρίνα **δεν το λέει**. Η εναλλακτική *(«να εμφανίζεται παντού»)* θα έδινε σε
 * όποιον **δεν** δηλώνει **καθολική ορατότητα** — δηλαδή θα αντάμειβε τη σιωπή, ακριβώς
 * το αντίστροφο του κινήτρου που θέλουμε.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴🔴 **Η ΠΑΓΙΔΑ ΤΗΣ ΣΕΙΡΑΣ ΤΩΝ ΟΡΙΣΜΑΤΩΝ — ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΥΠΑΡΧΕΙ ΠΛΕΟΝ ΕΔΩ**
 *
 * Μέχρι τη Φάση 3 αυτή η συνάρτηση καλούσε `areaRelation(where.circle, coverage.circle)`
 * — με τη **δήλωση δεύτερη**, που είναι αντίστροφο της διαίσθησης. Ο λόγος: το `within`
 * του `geo-area.ts` σημαίνει **subject ⊆ query** *(μετρημένο στον κώδικα:
 * `circleToCircle` ⇒ `gap + subjectM <= queryM`)*, όπου `subject` = *«πού μπορεί να
 * βρίσκεται το ακίνητο»* και `query` = *«πού κοιτάει ο άνθρωπος»*.
 *
 * ⚠️ **Η λάθος σειρά δεν πετούσε τίποτα** — και οι δύο τιμές είναι νόμιμες, οπότε η
 * κάρτα απλώς έγραφε «μέρος» όπου έπρεπε «όλη».
 *
 * 🏆 **Η Φάση 3 έβγαλε την παγίδα από τη ρίζα της**: κάθε κλήση περνά πλέον από
 * {@link footprintRelation} / {@link outlineOverFootprint}, όπου τα ορίσματα λέγονται
 * **`declared` και `asked`**. Δεν υπάρχει σειρά να θυμάται κανείς — υπάρχουν **ονόματα**.
 * Άγκυρα: `coverage-match.test.ts`, ομάδα «η σειρά των ορισμάτων».
 * ═════════════════════════════════════════════════════════════════════════════
 */
/**
 * **ΤΟ ΕΡΩΤΗΜΑ ΤΟΥ ΕΠΙΣΚΕΠΤΗ ΩΣ ΑΠΟΤΥΠΩΜΑ** — και οι δύο μορφές του, μία απάντηση.
 *
 * 🔑 **Εξήχθη στη Φ5δ επειδή απέκτησε ΔΕΥΤΕΡΟ καλούντα** *({@link areaOverWhere})*. Όσο
 * ζούσε ως τρεις γραμμές μέσα στον {@link coverageRelation}, ο δεύτερος **θα τις
 * αντέγραφε** — και θα ήταν το σχήμα που ο **N.18** ονομάζει *«κεντρικοποιείς το Α,
 * γράφεις Β ως δίδυμο»*, με το επιβαρυντικό ότι το δίδυμο θα γεννιόταν **στο ίδιο αρχείο**.
 *
 * ⚠️ **Το `null` σημαίνει ΜΟΝΟ «δεν ξέρω»** *(το αποτύπωμα της οντότητας δεν έχει φορτώσει,
 * ή λείπει από το μητρώο)* — **ποτέ** «δεν ταιριάζει». Κάθε καλών οφείλει να το μεταφράσει
 * σε `'unknown'`, όχι σε `'disjoint'`.
 */
export function askedFootprint(
  where: ShowcaseWhere,
  resolvers: CoverageResolvers,
): GeoFootprint | null {
  return isAdministrativeWhere(where)
    ? resolvers.footprintOf(where.adminId)
    : circleFootprint(where.circle);
}

export function coverageRelation(
  coverage: DeclaredCoverage | null,
  where: ShowcaseWhere,
  resolvers: CoverageResolvers,
): CoverageRelation {
  if (coverage === null) return 'disjoint';

  // 🔑 «Όλη η Ελλάδα» περιέχει **κάθε** περιοχή — καμία αναζήτηση σε ιεραρχία ή
  //    γεωμετρία, και καμία εξάρτηση από το αν έχουν φορτώσει.
  if (isNationwide(coverage)) return 'within';

  // 🏆 **ΤΟ ΕΡΩΤΗΜΑ ΓΙΝΕΤΑΙ ΑΠΟΤΥΠΩΜΑ ΜΙΑ ΦΟΡΑ** — δες {@link askedFootprint}.
  const query = askedFootprint(where, resolvers);

  if (isOutlineCoverage(coverage)) {
    // ⚠️ Το `[outline]` είναι **ένας** δακτύλιος — δες `types/agency-coverage.ts`:
    //    η δήλωση εμβέλειας δεν έχει τρύπες ούτε πολλαπλά μέρη, επίτηδες.
    return query === null ? 'unknown' : outlineOverFootprint([coverage.outline], query);
  }

  if (isRadiusCoverage(coverage)) {
    return query === null ? 'unknown' : footprintRelation(circleFootprint(coverage.circle), query);
  }

  // Δηλωμένες **διοικητικές οντότητες**: όταν το ερώτημα είναι κι αυτό διοικητικό, η
  // απάντηση βγαίνει από την **ιεραρχία** — κανένα αποτύπωμα, καμία γεωμετρία.
  return isAdministrativeWhere(where)
    ? areasOverArea(coverage.adminIds, where.adminId, resolvers.lineageOf)
    : areasOverCircle(coverage.adminIds, circleFootprint(where.circle), resolvers.footprintOf);
}

/**
 * **Ταιριάζει;** — η δυαδική ερώτηση, γραμμένη **μία** φορά.
 *
 * 🔑 Υπάρχει ώστε κανένας καλών να μη γράψει `relation !== 'disjoint'` μόνος του — και
 * **η πρόβλεψη επαληθεύτηκε**: η Φάση 2 πρόσθεσε το `'unknown'`, και **επειδή** όλοι
 * περνούν από εδώ, η σωστή συμπεριφορά *(«δεν ξέρω ⇒ ΔΕΝ κόβω»)* γράφτηκε σε **ένα**
 * σημείο αντί να ξεχαστεί σε τρία.
 */
export function coverageMatches(
  coverage: DeclaredCoverage | null,
  where: ShowcaseWhere,
  resolvers: CoverageResolvers,
): boolean {
  return coverageRelation(coverage, where, resolvers) !== 'disjoint';
}

/**
 * **Η ΔΗΛΩΣΗ ΕΝΑΝΤΙΟΝ ΜΙΑΣ ΓΝΩΣΤΗΣ ΠΕΡΙΟΧΗΣ ΤΟΥ ΚΟΣΜΟΥ** — όχι ερώτημα επισκέπτη.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟ ΟΝΟΜΑ ΓΙΑ ΤΡΕΙΣ ΓΡΑΜΜΕΣ ΠΟΥ ΔΕΝ ΚΑΝΟΥΝ ΤΙΠΟΤΑ ΝΕΟ
 *
 * Ο {@link coverageRelation} απαντά *«καλύπτει η δήλωση **αυτό που ρωτά ο
 * επισκέπτης**;»* — και το `ShowcaseWhere` **το λέει στο όνομά του**. Από τη Φάση 5
 * *(ADR-846 §8.8)* η ίδια μηχανή χρειάζεται για **άλλη** ερώτηση: *«πέφτει **αυτό το
 * ακίνητο** μέσα στη δήλωση;»*. Το ακίνητο **δεν είναι επισκέπτης**, και ένα σκέτο
 * `coverageRelation(coverage, { circle: area }, …)` στον καλούντα θα διάβαζε *«η αγγελία
 * ψάχνει»* — δηλαδή ο τύπος θα ήταν σωστός και **η πρόταση ψέμα**.
 *
 * 🔑 **Ίδιο ιδίωμα με τα `declared`/`asked` του {@link footprintRelation}**: εκεί τα
 * ονόματα εμποδίζουν την **αντιστροφή**· εδώ το όνομα εμποδίζει τη **σύγχυση ρόλου**.
 * Καμία γραμμή λογικής δεν αντιγράφεται — αν αντιγραφόταν, θα ήταν το σχήμα ADR-749.
 *
 * ⚠️ **Το `radiusKm === 0` είναι ΝΟΜΙΜΟ εδώ, και είναι ο συνήθης κλάδος.** Το
 * `LISTING_UNCERTAINTY_KM` δίνει **0** για `pin`/`outline` *(«ξέρουμε ακριβώς»)*, οπότε
 * το αποτύπωμα γίνεται `inner === outer === 0`. Τότε το `intersects`
 * **αυτο-αποκλείεται** — και οι δύο κλάδοι που το παράγουν απαιτούν `asked.innerKm > 0` —
 * και αυτό είναι **σημασιολογικά σωστό**: ένα σημείο δεν τέμνει· είναι μέσα, έξω, ή
 * άγνωστο. Ο τύπος **δεν χρειάστηκε νέα τιμή**, και αυτό είναι απόδειξη ότι η τετράδα
 * της Φάσης 2 ήταν σωστή, όχι σύμπτωση.
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * @param coverage **η δήλωση** — «πού δουλεύω»
 * @param area **η περιοχή του κόσμου** — π.χ. το `listingSearchArea` μιας αγγελίας,
 *   δηλαδή *«πού μπορεί να βρίσκεται»* **μαζί με την αβεβαιότητά του**
 */
export function coverageOverCircle(
  coverage: DeclaredCoverage | null,
  area: GeoCircle,
  resolvers: CoverageResolvers,
): CoverageRelation {
  return coverageRelation(coverage, { circle: area }, resolvers);
}

/**
 * **ΜΙΑ ΓΝΩΣΤΗ ΠΕΡΙΟΧΗ ΤΟΥ ΚΟΣΜΟΥ ΕΝΑΝΤΙΟΝ ΤΟΥ ΕΡΩΤΗΜΑΤΟΣ ΤΟΥ ΕΠΙΣΚΕΠΤΗ** *(ADR-846 Φ5δ)*.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 ΤΡΕΙΣ ΕΡΩΤΗΣΕΙΣ, ΜΙΑ ΜΗΧΑΝΗ, ΤΡΙΑ ΟΝΟΜΑΤΑ — ΚΑΙ ΤΟ ΤΡΙΤΟ ΓΕΝΝΗΘΗΚΕ ΕΔΩ
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * | Συνάρτηση | Ρωτά |
 * |---|---|
 * | {@link coverageRelation} | *«καλύπτει **η δήλωση** αυτό που ρωτά ο επισκέπτης;»* |
 * | {@link coverageOverCircle} | *«πέφτει **αυτό το ακίνητο** μέσα στη δήλωση;»* *(Φ5α)* |
 * | **αυτή** | *«πέφτει **αυτό το ακίνητο** μέσα σε ό,τι ρωτά ο επισκέπτης;»* *(Φ5δ)* |
 *
 * Και οι τρεις καταλήγουν στον **ίδιο** {@link footprintRelation}. Ένα σκέτο
 * `coverageRelation({ circle: area }, where, …)` στον καλούντα θα διάβαζε *«η αγγελία
 * **δηλώνει** εμβέλεια»* — ο τύπος σωστός, **η πρόταση ψέμα**. Ίδιο ακριβώς σκεπτικό με
 * τη γέννηση του {@link coverageOverCircle}, και με τα `declared`/`asked` του
 * {@link footprintRelation}: τα ονόματα εμποδίζουν τη **σύγχυση ρόλου**.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΚΑΙ Η ΜΕΤΑΦΡΑΣΗ ΤΟΥ ΑΠΟΤΕΛΕΣΜΑΤΟΣ ΕΙΝΑΙ Η **ΤΡΙΤΗ** ΣΤΟ ΔΕΝΤΡΟ, ΚΑΙ Η ΑΥΣΤΗΡΟΤΕΡΗ
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * | Ερώτηση | `intersects` σημαίνει |
 * |---|---|
 * | *«υπάρχει επικάλυψη δήλωσης και ερωτήματος;»* — {@link coverageMatches} | ✅ **ναι, εμφανίσου** |
 * | *«είναι αυτό το ακίνητο μέσα στη δήλωση;»* — `verdictForListing` *(Φ5α)* | 🔑 **δεν ξέρω** |
 * | *«έχει **αποδεδειγμένα** ακίνητο εδώ;»* — `presenceMatches` *(Φ5δ)* | ⛔ **ΟΧΙ — δεν αποδεικνύεται** |
 *
 * ⚠️ **Η συνάρτηση επιστρέφει τη ΣΧΕΣΗ, όχι την κρίση** — τη μετάφραση την κάνει ο
 * `showcase-presence.ts`, όπου ζει και το σκεπτικό της. Ένας κοινός μεταφραστής θα ήταν
 * **λάθος στις δύο από τις τρεις**, σιωπηλά.
 *
 * @param area **η περιοχή της αγγελίας** — `listingSearchArea`, δηλαδή *«πού μπορεί να
 *   βρίσκεται»* **μαζί με την αβεβαιότητά της**
 * @param where **πού ψάχνει ο επισκέπτης**
 */
export function areaOverWhere(
  area: GeoCircle,
  where: ShowcaseWhere,
  resolvers: CoverageResolvers,
): CoverageRelation {
  const query = askedFootprint(where, resolvers);
  if (query === null) return 'unknown';

  // ═══════════════════════════════════════════════════════════════════════════
  // 🔴🔴 **ΟΙ ΡΟΛΟΙ ΕΙΝΑΙ ΑΝΤΕΣΤΡΑΜΜΕΝΟΙ ΕΔΩ — ΚΑΙ ΤΟ ΕΠΙΑΣΕ Η ΑΓΚΥΡΑ, ΟΧΙ Η ΚΡΙΣΗ ΜΟΥ**
  //    *(2026-09-09, άγκυρες `Κ1`–`Κ4` του `showcase-presence.test.ts`)*.
  //
  // Ο {@link footprintRelation} δίνει `within` όταν **`asked ⊆ declared`** — δηλαδή
  // *«ο ΠΡΩΤΟΣ περιέχει τον ΔΕΥΤΕΡΟ»*. Στις άλλες δύο ερωτήσεις ο περιέχων είναι **η
  // δήλωση**, οπότε το `coverage` πάει πρώτο και διαβάζεται φυσικά.
  //
  // 🔑 **Εδώ ο περιέχων είναι ΤΟ ΕΡΩΤΗΜΑ ΤΟΥ ΕΠΙΣΚΕΠΤΗ**: ρωτάμε *«χωράει ολόκληρος ο
  //    κύκλος αβεβαιότητας της αγγελίας μέσα στην περιοχή που ρώτησε;»*. Άρα το `query`
  //    πάει **πρώτο**, και η αγγελία **δεύτερη**.
  //
  // ⚠️ **Η πρώτη γραφή τα είχε ανάποδα**, και ήταν **ακριβώς** η παγίδα του §8.2.6: και
  //    οι δύο σειρές είναι **νόμιμες**, οπότε τίποτα δεν πετούσε — απλώς η απάντηση
  //    γινόταν *«είναι το ερώτημα μέσα στην αγγελία;»*, που είναι **άλλη ερώτηση** και
  //    σχεδόν πάντα `false`. Τα ονόματα `declared`/`asked` εμποδίζουν την αντιστροφή
  //    **μέσα στο λεξιλόγιο της δήλωσης** — αλλά αυτή η τρίτη ερώτηση **βγαίνει από
  //    εκείνο το λεξιλόγιο**, και εκεί το όνομα δεν φυλάει πια. **Η άγκυρα φυλάει.**
  // ═══════════════════════════════════════════════════════════════════════════
  return footprintRelation(query, circleFootprint(area));
}
