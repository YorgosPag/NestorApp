/**
 * @fileoverview **ΤΑΙΡΙΑΖΕΙ Η ΔΗΛΩΣΗ ΜΕ ΤΟ ΕΡΩΤΗΜΑ;** — ο κριτής της δηλωμένης εμβέλειας.
 * @related ADR-846 · ADR-777 §8.63 (`AreaRelation`) · ADR-772 (η ιεραρχία)
 * @module lib/agency/coverage-match
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΤΟ ΛΕΞΙΛΟΓΙΟ ΔΕΝ ΕΙΝΑΙ ΚΑΙΝΟΥΡΓΙΟ — ΕΙΝΑΙ ΤΟ ΗΔΗ ΥΠΑΡΧΟΝ, ΣΕ ΑΛΛΟ ΧΩΡΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ερώτημα *«είναι αυτό εδώ;»* έχει **τρεις** τίμιες απαντήσεις όταν και τα δύο μέρη
 * είναι **περιοχές** — και το `lib/geo/geo-area.ts` τις έχει ήδη ονομάσει για τη
 * **γεωμετρία** *(DE-9IM: `within` · `intersects` · `disjoint`)*. Εδώ ρωτιέται
 * **ακριβώς το ίδιο**, σε **διοικητικό** αντί για ευκλείδειο χώρο:
 *
 * | Σχέση | Στη γεωμετρία | Στην ιεραρχία |
 * |---|---|---|
 * | `within` | το σχήμα του ερωτήματος **μέσα** στο σχήμα του υποκειμένου | η δήλωση είναι **πρόγονος ή ίδια** με την περιοχή του επισκέπτη |
 * | `intersects` | τέμνονται **χωρίς** να περιέχεται | η δήλωση είναι **απόγονος** της περιοχής του επισκέπτη |
 * | `disjoint` | καμία επαφή | καμία σχέση προγόνου προς καμία κατεύθυνση |
 *
 * 🔑 **Δεύτερος τύπος με τις ίδιες τρεις τιμές θα ήταν δίδυμο** *(N.18 / CHECK 3.28)*,
 * και ο επόμενος θα έπρεπε να θυμάται ποιο `'within'` διαβάζει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΔΙ-ΚΑΤΕΥΘΥΝΤΙΚΟΣ — ΤΟ ΜΟΝΟΚΑΤΕΥΘΥΝΤΙΚΟ ΧΑΝΕΙ ΤΟΝ ΜΙΣΟ ΚΟΣΜΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο προφανής έλεγχος *(«είναι η δήλωση μέσα στους προγόνους του επισκέπτη;»)* απαντά
 * σωστά **μόνο** όταν ο επισκέπτης ρωτά **στενότερα** από τη δήλωση:
 *
 * ```
 * δήλωση «Περιφέρεια Κ. Μακεδονίας» · ερώτημα «Δήμος Θέρμης»   → ✅ βρίσκεται
 * δήλωση «Δήμος Θέρμης» · ερώτημα «Περιφέρεια Κ. Μακεδονίας»   → ❌ ΧΑΝΕΤΑΙ
 * ```
 *
 * Το δεύτερο είναι **λάθος**: ο Θερμαίος μπετατζής **όντως** δουλεύει μέσα στην
 * Κεντρική Μακεδονία, και ο επισκέπτης που ρώτησε χονδρικά **τον θέλει**. Άρα ο έλεγχος
 * τρέχει **και προς τις δύο κατευθύνσεις**, και η κατεύθυνση που πέτυχε **είναι** η
 * απάντηση — γι' αυτό δεν επιστρέφεται `boolean`.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ Η ΣΧΕΣΗ ΦΙΛΤΡΑΡΕΙ ΚΑΙ ΠΕΡΙΓΡΑΦΕΙ — **ΠΟΤΕ ΔΕΝ ΤΑΞΙΝΟΜΕΙ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο πειρασμός είναι προφανής: *«όποιος καλύπτει **ολόκληρη** την περιοχή σου, πριν από
 * όποιον καλύπτει **μέρος** της»*. Αυτό θα ήταν **κατάταξη παραγόμενη από δήλωση του
 * ίδιου του επαγγελματία** — δηλαδή ακριβώς το *«κατάταξη ντυμένη ως γεωγραφία»* που
 * απαγόρευε το `agency-profile.ts` #6, ανασταινόμενο με άλλο όνομα. Η σχέση φτάνει στην
 * οθόνη **μόνο** ως ετικέτα *(«καλύπτει όλη την περιοχή»)*: πληροφορία στον άνθρωπο.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις, **καμία** εξάρτηση από React ή Firestore.
 * Η ιεραρχία μπαίνει με **ένεση** ({@link LineageResolver}), ποτέ με import hook.
 */

