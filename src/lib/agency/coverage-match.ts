/**
 * @fileoverview **ΤΑΙΡΙΑΖΕΙ Η ΔΗΛΩΣΗ ΜΕ ΤΟ ΕΡΩΤΗΜΑ;** — ο κριτής της δηλωμένης εμβέλειας.
 * @related ADR-846 · ADR-777 §8.63 (`AreaRelation`) · ADR-772 (η ιεραρχία)
 * @module lib/agency/coverage-match
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΤΟ ΛΕΞΙΛΟΓΙΟ ΔΕΝ ΕΙΝΑΙ ΚΑΙΝΟΥΡΓΙΟ — ΕΙΝΑΙ ΤΟ ΗΔΗ ΥΠΑΡΧΟΝ, ΣΕ ΑΛΛΟ ΧΩΡΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ερώτημα *«είναι αυτό εδώ;»* έχει **τρεις** τίμιες απαντήσεις όταν και τα δύο μέρη
 * είναι **περιοχές** — και το `lib/geo/geo-area.ts` τις έχει ήδη ονομάσει για τη
 * **γεωμετρία** *(DE-9IM: `within` · `intersects` · `disjoint`)*. Εδώ ρωτιέται
 * **ακριβώς το ίδιο**, σε **διοικητικό** αντί για ευκλείδειο χώρο:
 *
 * | Σχέση | Στη γεωμετρία | Στην ιεραρχία |
 * |---|---|---|
 * | `within` | το σχήμα του ερωτήματος **μέσα** στο σχήμα του υποκειμένου | η δήλωση είναι **πρόγονος ή ίδια** με την περιοχή του επισκέπτη |
 * | `intersects` | τέμνονται **χωρίς** να περιέχεται | η δήλωση είναι **απόγονος** της περιοχής του επισκέπτη |
 * | `disjoint` | καμία επαφή | καμία σχέση προγόνου προς καμία κατεύθυνση |
 *
 * 🔑 **Δεύτερος τύπος με τις ίδιες τρεις τιμές θα ήταν δίδυμο** *(N.18 / CHECK 3.28)*,
 * και ο επόμενος θα έπρεπε να θυμάται ποιο `'within'` διαβάζει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΔΙ-ΚΑΤΕΥΘΥΝΤΙΚΟΣ — ΤΟ ΜΟΝΟΚΑΤΕΥΘΥΝΤΙΚΟ ΧΑΝΕΙ ΤΟΝ ΜΙΣΟ ΚΟΣΜΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο προφανής έλεγχος *(«είναι η δήλωση μέσα στους προγόνους του επισκέπτη;»)* απαντά
 * σωστά **μόνο** όταν ο επισκέπτης ρωτά **στενότερα** από τη δήλωση:
 *
 * ```
 * δήλωση «Περιφέρεια Κ. Μακεδονίας» · ερώτημα «Δήμος Θέρμης»   → ✅ βρίσκεται
 * δήλωση «Δήμος Θέρμης» · ερώτημα «Περιφέρεια Κ. Μακεδονίας»   → ❌ ΧΑΝΕΤΑΙ
 * ```
 *
 * Το δεύτερο είναι **λάθος**: ο Θερμαίος μπετατζής **όντως** δουλεύει μέσα στην
 * Κεντρική Μακεδονία, και ο επισκέπτης που ρώτησε χονδρικά **τον θέλει**. Άρα ο έλεγχος
 * τρέχει **και προς τις δύο κατευθύνσεις**, και η κατεύθυνση που πέτυχε **είναι** η
 * απάντηση — γι' αυτό δεν επιστρέφεται `boolean`.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ Η ΣΧΕΣΗ ΦΙΛΤΡΑΡΕΙ ΚΑΙ ΠΕΡΙΓΡΑΦΕΙ — **ΠΟΤΕ ΔΕΝ ΤΑΞΙΝΟΜΕΙ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο πειρασμός είναι προφανής: *«όποιος καλύπτει **ολόκληρη** την περιοχή σου, πριν από
 * όποιον καλύπτει **μέρος** της»*. Αυτό θα ήταν **κατάταξη παραγόμενη από δήλωση του
 * ίδιου του επαγγελματία** — δηλαδή ακριβώς το *«κατάταξη ντυμένη ως γεωγραφία»* που
 * απαγόρευε το `agency-profile.ts` #6, ανασταινόμενο με άλλο όνομα. Η σχέση φτάνει στην
 * οθόνη **μόνο** ως ετικέτα *(«καλύπτει όλη την περιοχή»)*: πληροφορία στον άνθρωπο.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις, **καμία** εξάρτηση από React ή Firestore.
 * Η ιεραρχία μπαίνει με **ένεση** ({@link LineageResolver}), ποτέ με import hook.
 */

import type { AreaRelation } from '@/lib/geo/geo-area';
import { isNationwide, type DeclaredCoverage } from '@/types/agency-coverage';

/**
 * **Η γραμμή μιας οντότητας προς τη ρίζα, ΜΕ ΤΟΝ ΕΑΥΤΟ ΤΗΣ ΜΕΣΑ.**
 *
 * 🔑 **Το όνομα λέει «γενεαλογία», όχι «πρόγονοι», επίτηδες**: οι «πρόγονοι» **δεν**
 * περιλαμβάνουν τον εαυτό, και ο έλεγχος *«είναι ο Χ πρόγονος **ή ίδιος** με τον Υ;»*
 * θα χρειαζόταν **δύο** πράξεις σε κάθε καλούντα — δηλαδή κάποιος θα ξεχνούσε τη μία.
 * Με τον εαυτό μέσα, ο έλεγχος είναι **μία** `includes`.
 *
 * ⚠️ **Κενός πίνακας = «ΔΕΝ ΞΕΡΩ»**, ποτέ «καμία σχέση». Συμβαίνει σε **δύο**
 * περιπτώσεις — η ιεραρχία δεν έχει φορτώσει ακόμη *(4,1 MB, τεμπέλικη φόρτωση)*, ή το
 * id δεν υπάρχει. Και στις δύο η **σωστή** συμπεριφορά είναι η ίδια: **μην κόψεις
 * κανέναν με βάση αυτό που δεν ξέρεις** — δες {@link coverageRelation}.
 */
export type LineageResolver = (entityId: string) => readonly string[];

/**
 * **Η σχέση της δήλωσης προς την περιοχή που ρώτησε ο επισκέπτης.**
 *
 * @param coverage Τι δήλωσε ο επαγγελματίας. `null` = **δεν δήλωσε τίποτα**.
 * @param queryId Η διοικητική οντότητα που διάλεξε ο επισκέπτης.
 * @param lineageOf Η ιεραρχία, με ένεση.
 *
 * ⚠️ **`null` δήλωση ⇒ `disjoint`, και ΔΕΝ είναι ποινή** — είναι η ίδια απόφαση με το
 * `showcase.position === null` του υπάρχοντος φίλτρου: ο άξονας ρωτά *«πού δουλεύεις;»*
 * και η βιτρίνα **δεν το λέει**. Η εναλλακτική *(«να εμφανίζεται παντού»)* θα έδινε σε
 * όποιον **δεν** δηλώνει **καθολική ορατότητα** — δηλαδή θα αντάμειβε τη σιωπή, ακριβώς
 * το αντίστροφο του κινήτρου που θέλουμε.
 */
export function coverageRelation(
  coverage: DeclaredCoverage | null,
  queryId: string,
  lineageOf: LineageResolver,
): AreaRelation {
  if (coverage === null) return 'disjoint';

  // 🔑 «Όλη η Ελλάδα» περιέχει **κάθε** περιοχή — καμία αναζήτηση στην ιεραρχία, και
  //    καμία εξάρτηση από το αν έχει φορτώσει.
  if (isNationwide(coverage)) return 'within';

  const queryLineage = lineageOf(queryId);
  // ⚠️ «Δεν ξέρω» ⇒ **δεν αποφασίζω**. Ο καλών (το φίλτρο) δεν εφαρμόζει τον άξονα.
  if (queryLineage.length === 0) return 'disjoint';

  // 1️⃣ Η δήλωση **περιέχει** την περιοχή του επισκέπτη — «σε καλύπτω ολόκληρο».
  for (const declaredId of coverage.adminIds) {
    if (queryLineage.includes(declaredId)) return 'within';
  }

  // 2️⃣ Η δήλωση **βρίσκεται μέσα** στην περιοχή του επισκέπτη — «καλύπτω μέρος σου».
  //    ⚠️ Ελέγχεται **δεύτερο**: αν τα δύο ταυτίζονται, η σωστή απάντηση είναι `within`,
  //    και οι τρεις τιμές πρέπει να μένουν **αμοιβαία αποκλειόμενες** (κανόνας του
  //    `geo-area.ts` — μία αγγελία σε **ακριβώς έναν** κάδο).
  for (const declaredId of coverage.adminIds) {
    if (lineageOf(declaredId).includes(queryId)) return 'intersects';
  }

  return 'disjoint';
}

/**
 * **Ταιριάζει;** — η δυαδική ερώτηση, γραμμένη **μία** φορά.
 *
 * 🔑 Υπάρχει ώστε κανένας καλών να μη γράψει `relation !== 'disjoint'` μόνος του: την
 * ημέρα που προστεθεί τέταρτη τιμή, όλοι εκείνοι οι έλεγχοι θα ήταν **σιωπηλά** λάθος.
 */
export function coverageMatches(
  coverage: DeclaredCoverage | null,
  queryId: string,
  lineageOf: LineageResolver,
): boolean {
  return coverageRelation(coverage, queryId, lineageOf) !== 'disjoint';
}

/**
 * **ΚΑΝΟΝΙΚΟΠΟΙΗΣΗ — Η ΔΗΛΩΣΗ ΧΩΡΙΣ ΤΑ ΠΕΡΙΤΤΑ ΤΗΣ.**
 *
 * Αφαιρεί (α) τα διπλότυπα και (β) κάθε ταυτότητα που έχει **γνήσιο πρόγονο** ήδη μέσα
 * στη δήλωση: *«Δήμος Θέρμης» + «Περιφέρεια Κεντρικής Μακεδονίας» ⇒ μένει η περιφέρεια*,
 * γιατί ο δήμος **δεν προσθέτει τίποτα** — ήδη καλύπτεται.
 *
 * 🏆 **Αυτό αντικαθιστά το πλαφόν**, και είναι η θέση όπου ξεπερνάμε το Google Business
 * Profile: εκεί οι περιοχές είναι **επίπεδες**, οπότε χρειάζεται αυθαίρετη οροφή *(20)*
 * και **ανιχνευτής spam**. Με ιεραρχία, η λίστα **συμπτύσσεται μόνη της**.
 *
 * ⚠️ **Ιδεμποτής** *(N.7.2 #3)*: `normalize(normalize(x)) === normalize(x)`.
 * ⚠️ **Διατηρεί τη σειρά** της πρώτης εμφάνισης — ο άνθρωπος βλέπει τη λίστα του με τη
 * σειρά που την έχτισε, όχι αναδιαταγμένη από μηχανή.
 * ⚠️ **Άγνωστη ταυτότητα** *(κενή γενεαλογία)* **διατηρείται**: ο κριτής της
 * εγκυρότητας είναι ο γραφέας *(`showcase-request.ts`)*, όχι αυτή η συνάρτηση — μια
 * σιωπηλή απόρριψη εδώ θα έσβηνε δήλωση ανθρώπου επειδή δεν είχε φορτώσει ένα αρχείο.
 */
export function normalizeCoverageIds(
  adminIds: readonly string[],
  lineageOf: LineageResolver,
): readonly string[] {
  const unique = [...new Set(adminIds)];
  const declared = new Set(unique);

  return unique.filter((id) => {
    // Η γενεαλογία **χωρίς τον εαυτό** = οι γνήσιοι πρόγονοι.
    const strictAncestors = lineageOf(id).filter((ancestorId) => ancestorId !== id);
    return !strictAncestors.some((ancestorId) => declared.has(ancestorId));
  });
}
