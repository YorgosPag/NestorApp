import type { PlaceRef } from '@/types/geo/public-place';

/**
 * **Ένα credential, όπως το στέλνει ο φυλλομετρητής.**
 *
 * 🔴 **ΜΟΝΟ `escoUri` ΑΠΟ ΤΗΝ ΤΑΞΙΝΟΜΙΑ** — καμία ετικέτα, κανένας `iscoCode`.
 * Ετικέτα από το σύρμα θα επέτρεπε «Δικηγόρος» πάνω σε URI υδραυλικού: **σωστό
 * φίλτρο, ψεύτικη κάρτα**. Ο διακομιστής διαβάζει την ταξινομία μία φορά ανά
 * γραφή και γράφει **και τις δύο** ετικέτες.
 *
 * ⚠️ **Καμία `authority` επίσης**: την ονομάζει το **επάγγελμα**
 * *(`resolveRegistryAuthority`)*. Αν ερχόταν από εδώ, ένας διακοσμητής θα
 * δήλωνε αριθμό **ΓΕΜΗ** — ισχυρισμό μεσιτείας χωρίς τον φρουρό της.
 */
export interface ShowcaseCredentialWire {
  readonly escoUri: string;
  /** Ό,τι πληκτρολόγησε ο άνθρωπος. Απόν/κενό = *«δεν δηλώνω»* — **νόμιμο** (Α9.2). */
  readonly registrationNumber?: string;
  /** **Ποιος** εκδότης — υποχρεωτικό μόνο σε αρχή με παραρτήματα («ΔΣΘ»). */
  readonly registrationChapter?: string;
}

/** **Ό,τι στέλνει η οθόνη «Θέλω να με βρίσκουν»**, και τίποτα άλλο. */
/**
 * **Το σήμα, όπως το στέλνει ο φυλλομετρητής** (ADR-841 §7 Α21, Στάδιο 2).
 *
 * 🔴 **ΜΟΝΟΠΑΤΙ ΙΔΙΩΤΙΚΟΥ ΚΑΔΟΥ — ΠΟΤΕ bytes, ΠΟΤΕ URL.** Ο διακομιστής κατεβάζει το
 * πρωτότυπο **ο ίδιος**, ώστε ο καθαρισμός EXIF/GPS να μην μπορεί να παρακαμφθεί από τον
 * πελάτη *(Α12.7)*. Ένα URL από εδώ θα σήμαινε ότι η πλατφόρμα **αναδημοσιεύει** ό,τι
 * της δείξεις.
 *
 * ⚠️ **ΚΑΙ ΤΟ ΜΟΝΟΠΑΤΙ ΔΕΝ ΕΙΝΑΙ ΕΞΟΥΣΙΟΔΟΤΗΣΗ**: ο διακομιστής επαληθεύει ότι ζει στον
 * χώρο **της δικής σου** εταιρείας πριν το αγγίξει — δες `markSourceForCompany`. Χωρίς
 * εκείνον τον φρουρό, αυτό το πεδίο θα ήταν μηχανή εξαγωγής **ξένων** αρχείων.
 *
 * 🔑 **Το `kind` το δηλώνει ο άνθρωπος**, δεν μαντεύεται: λογότυπο θέλει τετράγωνο
 * πλαίσιο *(κυκλική περικοπή κόβει γράμματα)*, πορτρέτο θέλει κύκλο.
 */
export interface ShowcaseMarkWire {
  readonly kind: string;
  readonly privateStoragePath: string;
}

export interface ShowcaseWireDeclaration {
  readonly alias: string;
  readonly displayName: string;
  /** ≥1 — το επιβάλλει ο **γραφέας**, ονομαστικά, ποτέ το σχήμα (ένας κριτής ανά ερώτημα). */
  readonly credentials: readonly ShowcaseCredentialWire[];
  /**
   * **Ο δεσμός με τον τόπο** — και **μόνο** αυτός.
   *
   * 🔴 **ΚΑΜΙΑ ΓΕΩΜΕΤΡΙΑ ΕΔΩ, ΕΠΙΤΗΔΕΣ.** Το `position` της βιτρίνας το
   * **παράγει ο διακομιστής** από τη γη *(`readLandPosition`)*, με το ίδιο
   * δόγμα που ο `resolveListingPosition` παράγει εκείνο της αγγελίας. Σημείο
   * από το σύρμα θα επέτρεπε `place` στη Θεσσαλονίκη με σημείο στην Αθήνα:
   * **σωστή κάρτα, ψεύτικο φίλτρο** — δηλαδή προβολή σε αγορά που ο
   * επαγγελματίας δεν υπηρετεί.
   */
  readonly place?: PlaceRef | null;
  /**
   * ⛔ **ΚΑΝΕΝΑ `mark` ΕΔΩ — ΤΑΞΙΔΕΥΕΙ ΣΕ ΔΙΚΟ ΤΟΥ ΣΥΡΜΑ** (ADR-841 §7 Α21, Φάση 2).
   *
   * ────────────────────────────────────────────────────────────────────────
   * 🔴 ΥΠΗΡΞΕ ΕΔΩ, ΚΑΙ ΗΤΑΝ ΥΠΟΣΧΕΣΗ ΠΟΥ Ο ΠΕΛΑΤΗΣ ΔΕΝ ΜΠΟΡΟΥΣΕ ΝΑ ΤΗΡΗΣΕΙ
   * ────────────────────────────────────────────────────────────────────────
   *
   * Το πεδίο ζητούσε `privateStoragePath` σε **κάθε** δήλωση, γιατί η δήλωση είναι
   * **ολόκληρη η βιτρίνα** — άρα απόν σήμαινε *«σβήσ' το»*. Σωστό για κάθε άλλο πεδίο,
   * και **αδύνατο** γι' αυτό: η οθόνη διαβάζει πίσω το **ίδιο έγγραφο με τον κόσμο**,
   * όπου το σήμα ζει ως **δημόσιο URL**. Το ιδιωτικό μονοπάτι δεν επιστρέφει ποτέ, και
   * **δεν επιτρέπεται** να επιστρέψει: θα έδειχνε την εσωτερική δομή αποθήκευσης σε κάθε
   * **ανώνυμο** επισκέπτη.
   *
   * ⇒ Ο πελάτης δεν *«ξεχνούσε»* να το ξαναστείλει — **δεν είχε από πού να το πάρει**,
   * και κάθε αλλαγή επωνυμίας έσβηνε το λογότυπο.
   *
   * 🔑 Το {@link ShowcaseMarkWire} **μένει**: ταξιδεύει τώρα ολόκληρο και μόνο του, στο
   * `POST /api/agency-profile/mark` — το καθολικό πρότυπο *(GitHub · Slack · LinkedIn)*
   * όπου **το avatar δεν έχει «Αποθήκευση»**.
   */
}
