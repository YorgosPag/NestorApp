/**
 * @fileoverview **ΤΙ ΕΙΔΟΥΣ ΣΗΜΑ ΔΗΛΩΣΕ Ο ΕΠΑΓΓΕΛΜΑΤΙΑΣ** — λογότυπο ή πορτρέτο (ADR-841 §7 Α21).
 * @related ADR-841 §7 Α21.2 · Α21.6 · lib/agency/showcase-mark · lib/listings/listing-material
 * @module lib/agency/showcase-mark-kind
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΧΩΡΙΣΤΟ ΑΠΟ ΤΟ `showcase-mark.ts`, ΚΑΙ Η ΔΙΑΦΟΡΑ ΕΙΝΑΙ ΟΛΟΚΛΗΡΗ Η Α21
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `showcase-mark` δηλώνει ρητά *«**παραγόμενο**, ποτέ αποθηκευμένο · ΜΗΝ το προσθέσεις
 * στο `PublicShowcase`»* — είναι η **εφεδρεία που δεν αποτυγχάνει ποτέ** *(αρχικά +
 * χρώμα, συνάρτηση της ταυτότητας)*.
 *
 * Αυτό εδώ είναι το **αντίθετο**: **δηλωμένο** από άνθρωπο, άρα **πράξη**, άρα
 * **αποθηκεύεται**. Δύο ερωτήσεις που τυχαίνει να δίνουν και οι δύο «σήμα» — ίδιο
 * σκεπτικό με το ζεύγος `listing-authorship` *(«τίνος;»)* ⇄ `listing-material` *(«τι;»)*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΓΙΑΤΙ ΤΟ ΕΙΔΟΣ ΤΟ ΔΗΛΩΝΕΙ Ο ΑΝΘΡΩΠΟΣ — ΚΑΙ ΔΕΝ ΤΟ ΜΑΝΤΕΥΟΥΜΕ ΠΟΤΕ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Τα δύο είδη θέλουν **αντίθετο πλαίσιο**, και η επιλογή δεν είναι διακοσμητική:
 *
 * | | σχήμα | γέμισμα | γιατί |
 * |---|---|---|---|
 * | `logo` | τετράγωνο | `contain` | κυκλική περικοπή **κόβει γράμματα** — το λογότυπο γίνεται αγνώριστο |
 * | `portrait` | κύκλος | `cover` | το πρότυπο κάθε πλατφόρμας για **πρόσωπο**, και η έρευνα της Α21.1 β μετρά ότι το πρόσωπο χτίζει εμπιστοσύνη |
 *
 * ⛔ **ΑΠΟΡΡΙΦΘΗΚΕ: «βγάλ' το από τη νομική μορφή»** *(εταιρεία ⇒ λογότυπο, ατομική ⇒
 * πρόσωπο)*. Μοιάζει έξυπνο και **πέφτει έξω και στις δύο κατευθύνσεις**: ατομική
 * επιχείρηση με φτιαγμένο λογότυπο, και Α.Ε. όπου η αγορά ξέρει **το πρόσωπο** του
 * ιδιοκτήτη. Ο άνθρωπος δεν θα είχε **κανέναν τρόπο** να το διορθώσει — μαντεψιά
 * **χωρίς πόρτα εξόδου**, που είναι η χειρότερη μορφή της.
 *
 * ⛔ **ΑΠΟΡΡΙΦΘΗΚΕ ΚΑΙ: «κατάλαβέ το από την εικόνα»** *(διαφάνεια ⇒ λογότυπο)*. Η
 * διαφάνεια δεν λέει **τίποτα**: ένα σκαναρισμένο λογότυπο σε λευκό φόντο δεν έχει
 * κανάλι alpha, και μια φωτογραφία με αφαιρεμένο φόντο έχει.
 *
 * 🔑 **ΕΝΑ σήμα ανά επαγγελματία, όχι δύο** *(απόφαση Giorgio, 2026-09-07)*. Η κάρτα του
 * καταλόγου έχει **μία** θέση για *«ποιος είσαι;»*· δεύτερη εικόνα θα ήταν σχεδιαστική
 * απόφαση χωρίς αίτημα. ⚠️ Και η **προσθήκη** δεύτερου μένει εύκολη· η **αφαίρεση** δεν
 * θα ήταν.
 */

/**
 * Τα είδη σήματος που μπορεί να **δηλώσει** ο επαγγελματίας.
 *
 * ⚠️ **Η λίστα είναι η πηγή, ο τύπος ΠΑΡΑΓΕΤΑΙ** — ίδιο ιδίωμα με το
 * `LISTING_MATERIAL_KINDS`. Νέο είδος μπαίνει **εδώ**, και ο εξαντλητικός `Record` του
 * {@link SHOWCASE_MARK_ALT_KEYS} **σπάει τη μεταγλώττιση** μέχρι να απαντηθεί *«πώς
 * περιγράφεται σε όποιον δεν βλέπει;»*.
 *
 * ⛔ **ΔΕΝ επεκτείνει το `ListingMaterial`.** Εκείνο απαντά *«φωτογραφία ή κάτοψη;»* για
 * **αγγελία**· ένα `'logo'` εκεί μέσα θα ανάγκαζε το `withPublishedGallery` να χειριστεί
 * **αδύνατες** περιπτώσεις — κάτοψη-λογότυπο, πορτρέτο-ακινήτου. Δύο λεξιλόγια επειδή
 * είναι δύο **τομείς**, όχι επειδή είναι δύο λέξεις.
 */
export const SHOWCASE_MARK_KINDS = ['logo', 'portrait'] as const;

/** Δες {@link SHOWCASE_MARK_KINDS}. **Κλειστή ένωση, ποτέ `string`.** */
export type ShowcaseMarkKind = (typeof SHOWCASE_MARK_KINDS)[number];

/**
 * **Τι είναι αυτά τα bytes**, στη γλώσσα του δημόσιου ραφιού.
 *
 * 🔑 **Δοχείο και όχι σκέτο `ShowcaseMarkKind`**, παρότι σήμερα έχει ένα πεδίο: το ράφι
 * κουβαλά το υλικό **αδιαφανώς** *(`PublicShelfSource<M>`)*, και το `ListingMaterial`
 * απέδειξε γιατί το δοχείο κερδίζει — η κάτοψη χρειάστηκε **δεύτερο** πεδίο (`at`), και
 * ένα σκέτο `kind` θα το είχε αποκλείσει. Ίδια πόρτα, ανοιχτή, χωρίς κόστος σήμερα.
 */
export interface ShowcaseMarkMaterial {
  readonly kind: ShowcaseMarkKind;
}

/** Είναι αυτή η τιμή δηλωμένο είδος σήματος; — ο **ένας** έλεγχος στο σύνορο του σύρματος. */
export function isShowcaseMarkKind(value: unknown): value is ShowcaseMarkKind {
  return typeof value === 'string' && (SHOWCASE_MARK_KINDS as readonly string[]).includes(value);
}

/**
 * **ΠΩΣ ΠΕΡΙΓΡΑΦΕΤΑΙ ΤΟ ΣΗΜΑ ΣΕ ΟΠΟΙΟΝ ΔΕΝ ΤΟ ΒΛΕΠΕΙ** (ADR-841 §7 Α21 · Ο-18).
 *
 * 🔴 **`Record<ShowcaseMarkKind, …>` ΚΑΙ ΟΧΙ ΕΝΑ ΚΛΕΙΔΙ ΓΙΑ ΤΑ ΔΥΟ.** Ένα κοινό *«σήμα
 * του επαγγελματία»* θα ήταν αληθές και **άχρηστο**: ο άνθρωπος που ακούει την οθόνη
 * χρειάζεται να ξέρει αν κοιτά **λογότυπο εταιρείας** ή **το πρόσωπο κάποιου** — είναι
 * διαφορετική πληροφορία, όχι διαφορετική διατύπωση.
 *
 * ⚠️ **Το μάθημα του Ο-18** *(«το alt που λέει ψέμα»)*: το εναλλακτικό κείμενο είναι
 * **ισχυρισμός**, και ένας λάθος ισχυρισμός σε γραμμή που **κανείς βλέπων δεν διαβάζει**
 * είναι το ιδανικό μέρος για να ζήσει ένα ψέμα χρόνια.
 *
 * 🔑 **Με πρόθεμα namespace**, όπως τα `DIRECTORY_KEYS`: τα κλειδιά **ταξιδεύουν ως
 * τιμές** μέσα στο `ListingImage.altKey` και καταλήγουν αυτούσια σε `t()`.
 */
export const SHOWCASE_MARK_ALT_KEYS: Readonly<Record<ShowcaseMarkKind, string>> = {
  logo: 'property-market:mandate.mark.logoAlt',
  portrait: 'property-market:mandate.mark.portraitAlt',
} as const;
