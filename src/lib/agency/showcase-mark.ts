import { fnv1a32 } from '@/lib/hash/fnv1a';
import { getInitials } from '@/types/contacts/helpers';

/**
 * Πόσα διακριτά χρώματα έχει το σήμα.
 *
 * 🔑 **Ο αριθμός ΔΕΝ είναι διακοσμητικός — είναι η κατηγορική παλέτα `--chart-1..8`**,
 * την οποία το **CHECK 3.32** επικυρώνει **και στα δύο θέματα** με έξι ελέγχους. Ένας
 * από αυτούς είναι **ακριβώς** ο δικός μας: `contrast ≥ 3:1` **απέναντι στο `--card`**,
 * που είναι η επιφάνεια πάνω στην οποία κάθεται η κάρτα. Συν **CVD ΔE≥8** (Machado 2009),
 * ώστε δύο γειτονικές κάρτες να ξεχωρίζουν και για δαλτωνικό επισκέπτη.
 *
 * ⛔ **ΜΗΝ τον αλλάξεις χωρίς να αλλάξει η παλέτα** — και ⛔ **ΜΗΝ γεννήσεις χρώμα με
 * αριθμητική HSL από το hash**: αυτό ακριβώς υπάρχουν να σταματούν τα CHECK 3.42/3.43,
 * και θα έδινε χρώματα που **κανείς δεν μέτρησε** σε κανένα από τα δύο θέματα.
 */
export const SHOWCASE_MARK_SLOTS = 8;

/** **Το παραγόμενο σήμα** — γράμματα και θέση στην παλέτα. */
export interface ShowcaseLettermark {
  /**
   * 1-2 κεφαλαία γράμματα, **ή κενό**.
   *
   * ⚠️ Το κενό είναι **νόμιμο** *(επωνυμία χωρίς κανένα γράμμα)* και η **οθόνη** το
   * χειρίζεται — εδώ δεν μπαίνει «??», γιατί θα ήταν απόφαση παρουσίασης μέσα σε
   * καθαρή συνάρτηση.
   */
  readonly initials: string;
  /** Θέση στην παλέτα, **1 έως {@link SHOWCASE_MARK_SLOTS}** — ποτέ 0. */
  readonly slot: number;
}

/**
 * **Το σήμα ενός επαγγελματία που δεν δήλωσε εικόνα.**
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 🔑 ΧΑΣΑΡΕΤΑΙ ΤΟ `companyId`, ΟΧΙ Η ΕΠΩΝΥΜΙΑ — ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ
 * ════════════════════════════════════════════════════════════════════════════
 *
 * Το `companyId` **δεν αλλάζει ποτέ**· η επωνυμία αλλάζει. Αν το χρώμα κρεμόταν από
 * την επωνυμία, μια μετονομασία θα άλλαζε το σήμα — και **η αναγνωρισιμότητα είναι
 * όλη η δουλειά ενός λογοτύπου**. Ο ίδιος επαγγελματίας έχει **πάντα** το ίδιο χρώμα,
 * σε κάθε οθόνη, για κάθε επισκέπτη, για πάντα. Η επωνυμία δίνει **μόνο τα γράμματα**.
 *
 * ⚠️ **ΧΩΡΙΣ ΤΟΝ ΣΠΟΡΟ ΤΟΥ ΕΠΙΣΚΕΠΤΗ** — και εδώ είναι η διαφορά από τον γείτονα:
 * το `lotOf` του `agency-directory-order.ts` χασάρει `σπόρος + ταυτότητα` **επειδή
 * θέλει διαφορετική σειρά ανά επισκέπτη** *(κανένα γραφείο δεν ευνοείται)*. Εδώ η
 * απαίτηση είναι **αντίθετη**: ίδιο σήμα για όλους. **Ίδια μηχανή, αντίθετη απαίτηση**
 * — γι' αυτό οι δύο συναρτήσεις μοιράζονται το {@link fnv1a32} και τίποτε άλλο.
 *
 * ⚠️ **Και το `companyId` ΕΙΝΑΙ δημόσιο εδώ**: το `agency_profiles/{companyId}` το
 * διαβάζει ανώνυμος *(`firestore.rules:1079`)*, και ο τύπος το λέει ρητά — *«εδώ η
 * ταυτότητα ΕΙΝΑΙ το περιεχόμενο»*. Δεν διαρρέει τίποτα που δεν έχει ήδη διεύθυνση.
 */
export function lettermarkOf(companyId: string, displayName: string): ShowcaseLettermark {
  return {
    initials: getInitials(displayName),
    // `% N` σε **μη προσημασμένο** (το `fnv1a32` το εγγυάται) ⇒ 0…N-1· το `+1`
    // ευθυγραμμίζει με τα ονόματα των token, που αριθμούνται από το **1**.
    slot: (fnv1a32(companyId) % SHOWCASE_MARK_SLOTS) + 1,
  };
}
