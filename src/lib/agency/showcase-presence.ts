import { areaOverWhere, type CoverageResolvers } from '@/lib/agency/coverage-match';
import { distanceMeters } from '@/lib/geo/geo-distance';
import { isBoundingBox } from '@/lib/geo/geo-area';
import { listingSearchArea } from '@/lib/listings/listing-map-shape';
import { MAX_PRESENCE_AREAS } from '@/types/agency-profile';
import type { ShowcaseWhere } from '@/types/agency-coverage';
import type { GeoCircle } from '@/types/geo/coordinates';
import type { PublicListing } from '@/types/public-listing';

const METRES_PER_KM = 1000;

// ============================================================================
// Ο ΠΑΡΑΓΩΓΟΣ — ΑΓΓΕΛΙΕΣ → ΣΥΝΟΛΟ ΠΕΡΙΟΧΩΝ
// ============================================================================

/**
 * **Περιέχεται ο Α ολόκληρος μέσα στον Β;** — `dist(κέντρων) + rΑ ≤ rΒ`.
 *
 * ⚠️ **Ταυτόσημοι κύκλοι περιέχονται αμοιβαία** *(απόσταση 0, ίσες ακτίνες)*. Ο
 * {@link absorbCircles} το λύνει με **σειρά**: ο πρώτος μένει, ο δεύτερος βρίσκεται
 * περιεχόμενος και φεύγει. Χωρίς αυτό, δύο ταυτόσημοι θα **αλληλοδιαγράφονταν** — η
 * κλασική παγίδα της αμοιβαίας σχέσης, και θα έσβηνε **αληθινή** απόδειξη.
 */
function contains(outer: GeoCircle, inner: GeoCircle): boolean {
  const gapKm = distanceMeters(outer.center, inner.center) / METRES_PER_KM;
  return gapKm + inner.radiusKm <= outer.radiusKm;
}

/**
 * **ΜΟΝΟ ΑΠΟΡΡΟΦΗΣΗ, ΠΟΤΕ ΔΙΕΥΡΥΝΣΗ** — το σύνολο των **μεγιστοτικών** κύκλων.
 *
 * 🔴 **Ο πειρασμός είναι να «συγχωνεύσεις» δύο τεμνόμενους σε έναν που τους σκεπάζει.
 * Είναι ΨΕΥΤΙΚΟΣ ΙΣΧΥΡΙΣΜΟΣ**: ο περιβάλλων κύκλος καλύπτει **τόπους όπου δεν υπάρχει
 * κανένα ακίνητο**, και αυτό το αρχείο υπάρχει ακριβώς για να μην ειπωθεί κάτι τέτοιο.
 * Δύο τεμνόμενοι **μένουν και οι δύο**.
 *
 * 🔑 **Το αποτέλεσμα είναι ανεξάρτητο σειράς** *(εκτός της αμοιβαίας περίπτωσης, που τη
 * σπάει η ταξινόμηση)*: είναι τα **μέγιστα** στοιχεία της σχέσης ⊆. Ίδιο ιδίωμα με το
 * `normalizeCoverageIds` — **απορρόφηση, όχι σύνθεση** — μόνο που εκεί ο μερικός διάταξη
 * είναι η **ιεραρχία** και εδώ η **γεωμετρία**.
 */
function absorbCircles(circles: readonly GeoCircle[]): GeoCircle[] {
  const kept: GeoCircle[] = [];

  for (const candidate of circles) {
    if (kept.some((k) => contains(k, candidate))) continue;
    // Ο υποψήφιος επιβιώνει ⇒ ό,τι κρατημένο τον χωράει **δεν** υπάρχει· ό,τι χωράει
    // **εκείνος** φεύγει τώρα.
    for (let i = kept.length - 1; i >= 0; i -= 1) {
      if (contains(candidate, kept[i])) kept.splice(i, 1);
    }
    kept.push(candidate);
  }

  return kept;
}

/**
 * **Ντετερμινιστική, ΓΕΩΓΡΑΦΙΚΑ ΟΥΔΕΤΕΡΗ σειρά** — πλάτος, μήκος, μετά ακτίνα.
 *
 * ⚠️ **ΟΧΙ «οι μεγαλύτεροι πρώτοι».** Θα ήταν βολικό για την απορρόφηση, αλλά η σειρά
 * είναι **και** η πολιτική υπέρβασης του ταβανιού *(δες {@link presenceFromListings})*:
 * «μεγαλύτεροι πρώτοι» σημαίνει *«κράτα τις πιο **αβέβαιες** θέσεις»* — δηλαδή τις
 * **λιγότερο αποδεδειγμένες**, ακριβώς αντίθετα από τον σκοπό του αρχείου.
 */
function inGeographicOrder(a: GeoCircle, b: GeoCircle): number {
  return (
    a.center.lat - b.center.lat || a.center.lng - b.center.lng || a.radiusKm - b.radiusKm
  );
}

/**
 * **ΟΙ ΑΓΓΕΛΙΕΣ ΕΝΟΣ ΓΡΑΦΕΙΟΥ → ΤΟ ΣΥΝΟΛΟ ΤΩΝ ΠΕΡΙΟΧΩΝ ΤΟΥ.**
 *
 * 🔑 **Καμία νέα γεωμετρία**: κάθε στοιχείο είναι **ακριβώς** ό,τι επιστρέφει το
 * {@link listingSearchArea} *(ADR-777 §8.63)* — *«πού μπορεί να βρίσκεται αυτή η
 * αγγελία»*, **μαζί με το μέγεθος της άγνοιάς μας**.
 *
 * 🔴 **ΣΥΝΟΛΟ, ΟΧΙ ΛΙΣΤΑ — ΚΑΙ ΕΙΝΑΙ ΑΝΤΙΜΟΝΟΠΩΛΙΑΚΟ, ΟΧΙ ΒΕΛΤΙΣΤΟΠΟΙΗΣΗ.** Μία εγγραφή
 * ανά αγγελία θα κουβαλούσε **πλήθος αποθέματος ανά περιοχή** — δηλαδή **έτοιμο διάνυσμα
 * κατάταξης**, ακριβώς το *«όποιος έχει αποδεδειγμένα τα περισσότερα, πρώτος»* που το
 * §8.8.8 ονομάζει **NAR σχήμα με το πιο πειστικό δυνατό πρόσωπο** *($418M, 17/08/2024)*.
 * Μετά την απορρόφηση το πεδίο λέει **πού**, και **δεν μπορεί** να πει **πόσα**.
 *
 * ⚠️ **Το ταβάνι κόβει με ΨΕΥΔΩΣ ΑΡΝΗΤΙΚΟ, ποτέ ψευδώς θετικό** *(fail-closed στον
 * ισχυρισμό)*: πάνω από `MAX_PRESENCE_AREAS` κρατούνται οι πρώτες σε **γεωγραφική** σειρά.
 * Το γραφείο μπορεί να μην εμφανιστεί κάπου όπου δουλεύει — **ποτέ** το αντίστροφο.
 *
 * ⚠️ **Αγγελία χωρίς θέση δεν παράγει τίποτα**, και είναι η **σημερινή πλειοψηφία**
 * *(μετρημένο: 6 ακίνητα · 0 στον χάρτη, §8.8.5 α)*. Ένα κενό σύνολο σημαίνει *«καμία
 * απόδειξη»* — και ο κατάλογος το διαβάζει σωστά: **δεν προσθέτει τίποτα στην ένωση**.
 */
export function presenceFromListings(listings: readonly PublicListing[]): readonly GeoCircle[] {
  const areas: GeoCircle[] = [];

  for (const listing of listings) {
    const area = listingSearchArea(listing.position);
    // ⚠️ Ορθογώνιο δεν κρίνεται — δομικά ανέφικτο σήμερα, αλλά η σιωπή είναι **τίμια**:
    //    ίδιο ιδίωμα με τον φρουρό του `verdictForListing`.
    if (area === null || isBoundingBox(area)) continue;
    areas.push(area);
  }

  const ordered = [...areas].sort(inGeographicOrder);
  return absorbCircles(ordered).slice(0, MAX_PRESENCE_AREAS);
}

// ============================================================================
// Ο ΚΡΙΤΗΣ — Η ΤΡΙΤΗ ΜΕΤΑΦΡΑΣΗ ΤΟΥ `intersects`, ΚΑΙ Η ΑΥΣΤΗΡΟΤΕΡΗ
// ============================================================================

/**
 * **Έχει αποδεδειγμένα ακίνητο εκεί που ρωτά ο επισκέπτης;**
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 **ΜΟΝΟ `within`. ΤΟ `intersects` ΕΙΝΑΙ «ΟΧΙ», ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ.**
 *
 * | Ερώτηση | Ποιος ρωτά | `intersects` |
 * |---|---|---|
 * | *«υπάρχει επικάλυψη **δήλωσης** και ερωτήματος;»* | `coverageMatches` | ✅ **ναι, εμφανίσου** |
 * | *«είναι **αυτό το ακίνητο** μέσα στη δήλωση;»* | `verdictForListing` *(Φ5α)* | 🔑 **δεν ξέρω** |
 * | *«έχει **αποδεδειγμένα** ακίνητο εδώ;»* | **αυτή** *(Φ5δ)* | ⛔ **ΟΧΙ — δεν αποδεικνύεται** |
 *
 * **Το μετρημένο παράδειγμα**: αγγελία γεωκωδικοποιημένη σε **κέντρο Θεσσαλονίκης**
 * *(ακρίβεια `center` ⇒ κύκλος **±10 χλμ**)*.
 *
 * · Ερώτημα **«Δήμος Θέρμης»** ⇒ ο κύκλος **τέμνει** τον δήμο αλλά **δεν χωράει** μέσα του
 *   ⇒ **ΟΧΙ**. Δεν ξέρουμε αν το ακίνητο είναι στη Θέρμη ή στο κέντρο· ένα «ναι» θα ήταν
 *   ισχυρισμός παρουσίας **χωρίς απόδειξη**, σε **δημόσιο** κατάλογο, για λογαριασμό
 *   τρίτου. **Εδώ ξεπερνάμε το Zillow**, που συγκρίνει ΤΚ με ΤΚ και θα έλεγε «ναι».
 * · Ερώτημα **«Περιφέρεια Κεντρικής Μακεδονίας»** ⇒ ο **ίδιος** κύκλος **χωράει
 *   ολόκληρος** ⇒ **ΝΑΙ**. Η χονδρική θέση είναι **επαρκής απόδειξη για χονδρικό
 *   ερώτημα** — η αβεβαιότητα δεν πετιέται, **μετριέται**.
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * ⚠️ **Το `'unknown'` μετράει ως ΟΧΙ, και δεν είναι το ίδιο λάθος με τον κατάλογο.** Εκεί
 * *«δεν ξέρω ⇒ ΔΕΝ κόβω»* είναι σωστό, γιατί η άγνοια δεν επιτρέπεται να **αποκλείσει**
 * κάποιον. Εδώ η άγνοια δεν επιτρέπεται να **προσθέσει** κάποιον — και η ένωση είναι
 * **fail-open από τη μεριά της δήλωσης**, οπότε κανείς δεν χάνεται: το χειρότερο που
 * κάνει ένα `'unknown'` εδώ είναι να **μην προσθέσει** μια δεύτερη αιτία εμφάνισης.
 */
export function presenceMatches(
  presence: readonly GeoCircle[],
  where: ShowcaseWhere,
  resolvers: CoverageResolvers,
): boolean {
  return presence.some((area) => areaOverWhere(area, where, resolvers) === 'within');
}
