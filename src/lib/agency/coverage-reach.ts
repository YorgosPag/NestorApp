import { verdictForPosition } from '@/lib/agency/coverage-agreement';
import type { CoverageResolvers } from '@/lib/agency/coverage-match';
import {
  containingEntityOfPoint,
  type FootprintEntries,
} from '@/lib/agency/presence-admin-ids';
import type { DeclaredCoverage } from '@/types/agency-coverage';
import type { ListingPosition } from '@/types/public-listing';

/**
 * **Τι πρέπει να ειπωθεί** για τη διεύθυνση που γράφεται αυτή τη στιγμή.
 *
 * 🔴 **ΔΥΟ ΣΚΕΛΗ, ΚΑΙ ΤΟ ΕΝΑ ΕΙΝΑΙ Η ΣΙΩΠΗ — ΡΗΤΑ, ΟΧΙ ΩΣ `null`.** Ένα `null` θα
 * σήμαινε *«δεν υπολογίστηκε»* **και** *«υπολογίστηκε, δεν υπάρχει κάτι να πω»* με την
 * ίδια τιμή. Οι δύο καταστάσεις είναι διαφορετικές για κάθε άγκυρα που θα ήθελε να
 * αποδείξει ότι η **σιωπή είναι απόφαση** και όχι παράλειψη.
 */
export type ReachVoice =
  | { readonly kind: 'silent' }
  | {
      readonly kind: 'outside';
      /**
       * Πώς λέγεται ο τόπος — ή `null` όταν **δεν έχει αποδειχθεί** διοικητικό κελί.
       *
       * ⚠️ **`null` δεν αναιρεί το εύρημα.** Η ετυμηγορία «εκτός» βγήκε από τη
       * **γεωμετρία της δήλωσης**· το όνομα είναι **επιπλέον ευγένεια** που απαιτεί τα
       * αποτυπώματα. Ακτογραμμή, μικρό νησί, αποτυπώματα που δεν φόρτωσαν ⇒ μιλάμε
       * **χωρίς** όνομα, ποτέ με ωμό `municipality:0701` και ποτέ με συντεταγμένες.
       */
      readonly areaName: string | null;
    };

/** Η **μοναδική** σιωπηλή τιμή — μία ταυτότητα, ώστε οι συγκρίσεις να μη λένε ψέματα. */
const SILENT: ReachVoice = { kind: 'silent' };

/** Ό,τι χρειάζεται η κρίση, και **τίποτα** παραπάνω. */
export interface ReachInput {
  /** Η δήλωση του γραφείου — `null` όταν **δεν έχει δηλώσει** ή δεν έχει φορτώσει. */
  readonly coverage: DeclaredCoverage | null;
  /** Πού είναι η υπό καταχώριση διεύθυνση — `null` όσο δεν έχει λυθεί. */
  readonly position: ListingPosition | null;
  /** Οι ίδιοι αναγνώστες με τον κριτή *(`useCoverageResolvers`)*. */
  readonly resolvers: CoverageResolvers;
  /** Τα αποτυπώματα, **για την ονομασία μόνο**. Κενός χάρτης = «δεν ρώτησα». */
  readonly footprints: FootprintEntries;
  /** Ταυτότητα → όνομα οθόνης. `null` όταν η ιεραρχία δεν έχει φορτώσει. */
  readonly nameOf: (adminId: string) => string | null;
}

/**
 * **Η ΜΙΑ ΠΡΑΞΗ ΑΥΤΟΥ ΤΟΥ MODULE.**
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 **Η ΣΙΩΠΗ ΕΧΕΙ ΤΕΣΣΕΡΙΣ ΑΙΤΙΕΣ, ΚΑΙ Η ΔΕΥΤΕΡΗ ΕΙΝΑΙ Η ΠΙΟ ΕΠΙΚΙΝΔΥΝΗ ΝΑ ΞΕΧΑΣΤΕΙ**
 *
 * 1. **Δεν υπάρχει θέση** ⇒ δεν υπάρχει ερώτηση. Ο άνθρωπος **ακόμη πληκτρολογεί**, και
 *    η φόρμα σβήνει το σημείο σε κάθε αλλαγή κειμένου — άρα μιλάμε **μόνο** πάνω σε
 *    διεύθυνση που **σταθεροποιήθηκε**. Είναι η ίδια αρχή με το *«validation on blur»*
 *    της NN/g: πρόωρη επικύρωση **διαβάζεται ως κατηγορία**.
 *
 * 2. 🔴 **ΔΕΝ ΥΠΑΡΧΕΙ ΔΗΛΩΣΗ** ⇒ **ΣΙΩΠΗ — ΚΑΙ ΕΙΝΑΙ Η ΑΝΤΙΘΕΤΗ ΑΠΟΦΑΣΗ ΑΠΟ ΤΗ ΒΙΤΡΙΝΑ.**
 *
 *    Ο `coverageRelation` απαντά `'disjoint'` για κενή δήλωση, και το
 *    `coverageEvidenceOf` **στηρίζεται σε αυτό** επίτηδες: εκεί η ερώτηση είναι *«συμφωνεί
 *    η δήλωσή σου με το χαρτοφυλάκιό σου;»* και *«δεν δήλωσα τίποτα κι έχω δέκα
 *    ακίνητα»* είναι **γνήσιο** `understated`.
 *
 *    ⛔ **Εδώ η ίδια τιμή θα ήταν καταστροφή**: κάθε μεσίτης χωρίς βιτρίνα θα έβλεπε
 *    *«αυτό είναι εκτός της περιοχής σου»* σε **κάθε** καταχώριση — κατηγορία για
 *    παράβαση κανόνα **που δεν έθεσε ποτέ**. Και η τιμωρία θα ήταν διπλή: ο άνθρωπος
 *    μαθαίνει μέσα σε δύο καταχωρίσεις να **προσπερνά** αυτό το πλαίσιο, οπότε τη μέρα
 *    που θα έχει κάτι αληθινό να πει, **δεν θα το διαβάσει κανείς**.
 *
 *    🔑 **Η ΙΔΙΑ ΣΥΝΑΡΤΗΣΗ, ΔΥΟ ΣΗΜΑΣΙΕΣ, ΓΙΑΤΙ ΟΙ ΕΡΩΤΗΣΕΙΣ ΕΙΝΑΙ ΔΥΟ** — ακριβώς το
 *    ιδίωμα που ο `verdictForPosition` ήδη τεκμηριώνει για το `intersects`. Ο φρουρός
 *    μπαίνει **εδώ**, στον καλούντα που ξέρει την ερώτησή του, **ποτέ** μέσα στον κριτή:
 *    εκεί θα άλλαζε την απάντηση **και για τη βιτρίνα**, σιωπηλά.
 *
 * 3. **Η ετυμηγορία δεν είναι `'outside'`** ⇒ σιωπή, και **περιλαμβάνει το `'inside'`**.
 *    Μια γραμμή *«✓ εντός της περιοχής σου»* λέει το **αναμενόμενο**, και το ίδιο αυτό
 *    αρχείο-οθόνη το έχει ήδη κρίνει: *«μια γραμμή που λέει το αυτονόητο εκπαιδεύει τον
 *    αναγνώστη να προσπερνά **όλες** τις γραμμές αυτού του πλαισίου»*.
 *
 * 4. **`'indeterminate'`** ⇒ σιωπή, και είναι η **πιο συχνή** απάντηση. Διεύθυνση που ο
 *    γεωκωδικοποιητής έλυσε **μόνο σε επίπεδο πόλης** κουβαλά ±10 χλμ αβεβαιότητας
 *    *(`LISTING_UNCERTAINTY_KM`)*: **δεν ξέρουμε** πού είναι, άρα δεν κατηγορούμε. Το
 *    **Zillow** συγκρίνει ταχυδρομικό κώδικα με ταχυδρομικό κώδικα *σαν να ήξερε τη
 *    διεύθυνση* — αυτή η γραμμή είναι όλη η διαφορά.
 * ═════════════════════════════════════════════════════════════════════════════
 */
export function reachVoiceOf({
  coverage,
  position,
  resolvers,
  footprints,
  nameOf,
}: ReachInput): ReachVoice {
  // Αιτία 1 — και το `kind !== 'known'` **δεν** είναι πλεονασμός του κριτή: είναι το
  // στένεμα που δίνει `point` παρακάτω, γραμμένο εκεί που ο μεταγλωττιστής το διαβάζει.
  if (position === null || position.kind !== 'known') return SILENT;

  // Αιτία 2 — ο φρουρός που δεν επιτρέπεται να μετακομίσει μέσα στον κριτή.
  if (coverage === null) return SILENT;

  // Αιτίες 3 και 4 — **ένας** κριτής, ο ίδιος με τη βιτρίνα.
  if (verdictForPosition(coverage, position, resolvers) !== 'outside') return SILENT;

  // ═══════════════════════════════════════════════════════════════════════════
  // 🏆 ΤΟ ΟΝΟΜΑ — ΚΑΙ ΕΙΝΑΙ **ΜΕΤΡΗΜΕΝΟ**, ΟΧΙ ΥΠΟΤΕΘΕΝ (§9 #12)
  //
  // ⛔ **Δεν είναι αντίστροφη γεωκωδικοποίηση**, και ο φραγμός του §9 #1 μένει ακέραιος:
  //    το `api/geocoding/reverse` επιστρέφει **ελεύθερα strings Nominatim**, όχι
  //    `AdminEntity.id`. Ο δρόμος εδώ είναι **γεωμετρικός** — point-in-shape πάνω στα
  //    ίδια πολύγωνα Καλλικράτη που χρησιμοποιεί ο κριτής δύο γραμμές πιο πάνω.
  //
  // 🔴 **ΚΑΙ ΓΙ' ΑΥΤΟ ΤΟ ΟΝΟΜΑ ΔΕΝ ΓΡΑΦΕΤΑΙ ΠΟΤΕ ΜΕ ΤΟ ΧΕΡΙ**: το σημείο
  //    `(40,6643 · 22,8976)` ταξίδεψε ως *«Σταυρούπολη»* από handoff σε ADR σε άγκυρα,
  //    και είναι **ΔΗΜΟΣ ΚΟΡΔΕΛΙΟΥ - ΕΥΟΣΜΟΥ**. Το πολύγωνο το ήξερε από την αρχή.
  // ═══════════════════════════════════════════════════════════════════════════
  const adminId = containingEntityOfPoint(position.point, footprints, resolvers.lineageOf);

  return { kind: 'outside', areaName: adminId === null ? null : nameOf(adminId) };
}
