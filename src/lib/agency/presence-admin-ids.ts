import type { LineageResolver } from './coverage-match';
import { distanceMeters } from '@/lib/geo/geo-distance';
import { circleFootprint } from '@/lib/geo/geo-footprint';
import { footprintRelation } from '@/lib/geo/geo-shape-relation';
import type { GeoFootprint } from '@/types/geo/admin-footprint';
import type { GeoCircle } from '@/types/geo/coordinates';

/**
 * `id` διοικητικής οντότητας → το αποτύπωμά της.
 *
 * ⚠️ **Κενός χάρτης = «δεν ρώτησα»**, ποτέ «καμία οντότητα». Ο καλών που δεν μπόρεσε να
 * φορτώσει τα αποτυπώματα **δεν επιτρέπεται** να περάσει κενό χάρτη και να γράψει το
 * αποτέλεσμα — δες {@link presenceAdminIdsOf}.
 */
export type FootprintEntries = ReadonlyMap<string, GeoFootprint>;

/**
 * **Ποιοι περιέχουν τον κύκλο, αποδεδειγμένα;** — το γεωμετρικό μισό, χωριστά.
 *
 * 🔴 **Η ΣΕΙΡΑ ΤΩΝ ΟΡΙΣΜΑΤΩΝ ΕΙΝΑΙ ΤΟ ΛΑΘΟΣ ΠΟΥ ΔΕΝ ΠΕΤΑΕΙ.** Το
 * {@link footprintRelation} δίνει `within` όταν **`asked ⊆ declared`**, δηλαδή ο
 * **ΠΡΩΤΟΣ** είναι ο περιέχων. Εδώ ο περιέχων είναι το **αποτύπωμα** και το ερωτώμενο
 * ο **κύκλος**. Η αντίστροφη σειρά είναι **εξίσου νόμιμη τυπικά** — δεν πετά τίποτα,
 * απλώς απαντά σε **άλλο ερώτημα**. Έχει χτυπήσει **δύο** φορές.
 */
function provenContainersOf(circle: GeoCircle, footprints: FootprintEntries): readonly string[] {
  const asked = circleFootprint(circle);
  const containers: string[] = [];
  for (const [adminId, footprint] of footprints) {
    if (!couldContain(footprint, circle)) continue;
    if (footprintRelation(footprint, asked) === 'within') containers.push(adminId);
  }
  return containers;
}

/**
 * **Το φθηνό «ούτε κατά διάνοια»** — μία απόσταση αντί για έως 24.
 *
 * 🔒 **ΑΝΑΓΚΑΙΑ ΣΥΝΘΗΚΗ, ΟΧΙ ΕΥΡΕΤΙΚΗ — και η διάκριση είναι όλο το νόημα.** Αν ο
 * κύκλος είναι μέσα στο **σχήμα**, είναι κατ' ανάγκη μέσα και στον **περιγεγραμμένο**
 * του κύκλο, άρα `απόσταση + ακτίνα ≤ outerKm`. Ένα αποτύπωμα που **παραβιάζει** την
 * ανισότητα **δεν μπορεί** να τον περιέχει — και το παραλείπουμε **χωρίς να χάσουμε
 * καμία απάντηση**. ∎
 *
 * ⚠️ **Το αντίστροφο ΔΕΝ ισχύει** *(γι' αυτό δεν είναι απάντηση, μόνο φίλτρο)*: ο
 * περιγεγραμμένος περιέχει άφθονο χώρο **εκτός** του σχήματος. Η απόφαση μένει στο
 * {@link footprintRelation}, που ρωτά το **εσωτερικό κάλυμμα**.
 *
 * 🔬 **Γιατί μετράει**: ο γραφέας σαρώνει **7.440** αποτυπώματα **ανά κύκλο**, έως
 * **32** κύκλους — και τρέχει **μέσα** στη δημοσίευση αγγελίας, που ο άνθρωπος
 * περιμένει. Χωρίς το φίλτρο, κάθε αποτύπωμα πλήρωνε τη σάρωση **όλων** των δίσκων του.
 */
function couldContain(footprint: GeoFootprint, circle: GeoCircle): boolean {
  return (
    distanceMeters(footprint.center, circle.center) / 1000 + circle.radiusKm <= footprint.outerKm
  );
}

/**
 * **Το βαθύτερο διοικητικό κελί που περιέχει αποδεδειγμένα τον κύκλο** — ή `null`.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 **Ο ΝΙΚΗΤΗΣ ΔΕΝ ΕΙΝΑΙ «Ο ΠΙΟ ΒΑΘΥΣ» — ΕΙΝΑΙ «ΑΥΤΟΣ ΠΟΥ ΕΞΗΓΕΙ ΟΛΟΥΣ ΤΟΥΣ ΑΛΛΟΥΣ»**
 *
 * Το προφανές κριτήριο *«μέγιστο βάθος»* **υποθέτει** την εμφώλευση. Αυτό εδώ την
 * **επαληθεύει**: νικητής είναι ο υποψήφιος του οποίου η **γενεαλογία περιέχει κάθε
 * άλλον** αποδεδειγμένο περιέκτη. Σε υγιή δεδομένα τα δύο κριτήρια δίνουν **το ίδιο**
 * *(ο βαθύτερος μιας αλυσίδας περιέχει όλη την αλυσίδα)*· σε **χαλασμένα** —
 * επικαλυπτόμενες οντότητες ίδιου επιπέδου, σπασμένος γονέας μετά από διοικητική
 * μεταρρύθμιση — το πρώτο διαλέγει **αυθαίρετα** και το δεύτερο απαντά `null`.
 *
 * ⇒ Η υπόθεση πάνω στην οποία στέκεται **ολόκληρη** η φάση *(«οι πρόγονοι είναι
 * δωρεάν»)* **ελέγχεται σε κάθε κλήση**, αντί να θεωρείται δεδομένη. Χωρίς αυτό, ένα
 * μισο-ενημερωμένο αρχείο ιεραρχίας θα παρήγαγε **σιωπηλά λάθος** προγόνους — δηλαδή
 * ψευδώς **θετικό** ισχυρισμό παρουσίας, σε δημόσιο κατάλογο, για λογαριασμό τρίτου.
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * ⚠️ **`null` σημαίνει «καμία απόδειξη», ΠΟΤΕ «πουθενά»** *(N.12)*.
 *
 * @param circle ο κύκλος παρουσίας — ό,τι επιστρέφει το `listingSearchArea`
 * @param footprints το στιγμιότυπο των αποτυπωμάτων
 * @param lineageOf η γενεαλογία, **με τον εαυτό πρώτο** *(ίδια σύμβαση στις δύο πλευρές)*
 */
export function deepestContainingEntity(
  circle: GeoCircle,
  footprints: FootprintEntries,
  lineageOf: LineageResolver,
): string | null {
  const containers = provenContainersOf(circle, footprints);
  if (containers.length === 0) return null;

  // 🔑 **Καμία ειδική περίπτωση για «ένας υποψήφιος».** Με ένα στοιχείο, ο κανόνας
  //    *«εξηγεί όλους τους άλλους»* γίνεται *«εξηγεί τον εαυτό του»* — δηλαδή
  //    **απαιτεί γνωστή ταυτότητα**. Μια πρόωρη έξοδος εδώ θα επέστρεφε ταυτότητα που
  //    η ιεραρχία **δεν αναγνωρίζει**, και ο κριτής θα σιωπούσε για πάντα χωρίς ίχνος.
  for (const candidate of containers) {
    const lineage = lineageOf(candidate);
    // Άγνωστη ταυτότητα ⇒ δεν εξηγεί ούτε τον εαυτό της. Κενός πίνακας = «δεν ξέρω».
    if (lineage.length === 0) continue;
    if (containers.every((other) => lineage.includes(other))) return candidate;
  }

  // Αντιφατικές αποδείξεις — δύο περιέκτες που δεν εμφωλεύονται. **Δεν μαντεύουμε.**
  return null;
}

/**
 * **Οι κύκλοι παρουσίας → σύνολο διοικητικών ταυτοτήτων**, απορροφημένο.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΣΥΝΟΛΟ, ΟΧΙ ΛΙΣΤΑ — ΚΑΙ ΕΙΝΑΙ **ΑΝΤΙΜΟΝΟΠΩΛΙΑΚΟ**, ΟΧΙ ΒΕΛΤΙΣΤΟΠΟΙΗΣΗ
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * Ίδιος ακριβώς λόγος με το `absorbCircles` του `presence` *(§8.8.15)*: **πέφτει κάθε
 * ταυτότητα που είναι ΠΡΟΓΟΝΟΣ κάποιας άλλης**, γιατί η γενεαλογία του απογόνου την
 * **συνεπάγεται** στο ερώτημα. Άρα το πεδίο λέει **ΠΟΥ**, και **δεν μπορεί** να πει
 * **ΠΟΣΑ** — μία εγγραφή ανά αγγελία θα κουβαλούσε **πλήθος αποθέματος ανά περιοχή**,
 * δηλαδή **έτοιμο διάνυσμα κατάταξης** *(NAR $418M, §8.8.8)*.
 *
 * 🔒 **Η απορρόφηση είναι ΑΝΩΔΥΝΗ, αποδεδειγμένα**: αν ο κύκλος Α αποδεικνύει
 * `municipality:0701` και ο Β μόνο `regional_unit:07`, τότε η ρίψη του `regional_unit:07`
 * **δεν χάνει καμία απάντηση** — κάθε ερώτημα που θα το έπιανε, το πιάνει από τη
 * γενεαλογία του `0701`· και ερώτημα **αδελφού** δήμου δεν θα το έπιανε ούτως ή άλλως,
 * γιατί ο Β **δεν** τον απέδειξε.
 *
 * ⚠️ **ΚΕΝΟΣ ΠΙΝΑΚΑΣ ΣΗΜΑΙΝΕΙ «ΚΑΜΙΑ ΑΠΟΔΕΙΞΗ» — ΚΑΙ Ο ΚΑΛΩΝ ΟΦΕΙΛΕΙ ΝΑ ΞΕΡΕΙ ΤΗ
 * ΔΙΑΦΟΡΑ.** Αν τα αποτυπώματα **δεν φορτώθηκαν**, αυτή η συνάρτηση θα επέστρεφε
 * επίσης `[]` — και η γραφή του θα ήταν **«πράσινο που σημαίνει “κανείς δεν κοίταξε”»**
 * *(N.11 · N.12)*. Γι' αυτό ο γραφέας **δεν καλεί καθόλου** όταν δεν έχει δεδομένα,
 * αντί να ερμηνεύσει το αποτέλεσμα.
 */
export function presenceAdminIdsOf(
  presence: readonly GeoCircle[],
  footprints: FootprintEntries,
  lineageOf: LineageResolver,
): readonly string[] {
  const resolved = new Set<string>();
  for (const circle of presence) {
    const adminId = deepestContainingEntity(circle, footprints, lineageOf);
    if (adminId !== null) resolved.add(adminId);
  }
  return absorbAdminIds([...resolved], lineageOf);
}

/** Πέφτει κάθε ταυτότητα που είναι **πρόγονος** κάποιας άλλης του συνόλου. */
function absorbAdminIds(
  adminIds: readonly string[],
  lineageOf: LineageResolver,
): readonly string[] {
  const ancestors = new Set<string>();
  for (const adminId of adminIds) {
    // 🔑 **Ο εαυτός εξαιρείται**: το `lineageIdsOf` ξεκινά από τον εαυτό, και χωρίς
    //    αυτό το `slice(1)` **κάθε** ταυτότητα θα απορροφούσε τον εαυτό της ⇒ κενό σύνολο.
    for (const ancestor of lineageOf(adminId).slice(1)) ancestors.add(ancestor);
  }
  return adminIds.filter((adminId) => !ancestors.has(adminId));
}
