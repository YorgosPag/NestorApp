/**
 * @fileoverview **Η ΣΕΙΡΑ ΤΟΥ ΚΑΤΑΛΟΓΟΥ ΓΡΑΦΕΙΩΝ** — ουδέτερη, δηλωμένη, ολική.
 * @related ADR-827 §9.9 α (antitrust) · §9.4 · types/agency-profile.ts
 * @module lib/agency/agency-directory-order
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ Η ΣΕΙΡΑ ΕΧΕΙ ΔΙΚΟ ΤΗΣ ΑΡΧΕΙΟ — ΚΑΙ ΟΧΙ ΜΙΑ ΓΡΑΜΜΗ ΜΕΣΑ ΣΤΟ HOOK
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το §9.9 α δεν είναι προτίμηση παρουσίασης· είναι **κόκκινη γραμμή με τιμή**:
 * *«ένας κατάλογος ΓΡΑΦΕΙΩΝ είναι μεγαλύτερη επιφάνεια steering από κατάλογο
 * ΑΚΙΝΗΤΩΝ — αν η πλατφόρμα κατατάσσει γραφεία, κατευθύνει ΔΟΥΛΕΙΑ»* (NAR
 * Settlement 17/08/2024, **$418M**).
 *
 * 🔑 **Ο πρώτος φρουρός είναι ΔΟΜΙΚΟΣ και δεν ζει εδώ**: το {@link AgencyProfile}
 * **δεν έχει** πεδίο αμοιβής, βαθμολογίας, κατάταξης ή προβολής επί πληρωμή. Πεδίο
 * που δεν υπάρχει **δεν μπορεί** να ταξινομήσει κανείς. Αυτό το αρχείο είναι ο
 * **δεύτερος** φρουρός: ένα **ονομασμένο σημείο** που η άγκυρα μπορεί να
 * μεταλλάξει. Μια `sort()` σκορπισμένη μέσα σε component θα ήταν απόφαση χωρίς
 * διεύθυνση — και η επόμενη, εμπορική, θα έμπαινε δίπλα της χωρίς να το δει κανείς.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ Η ΣΕΙΡΑ ΕΙΝΑΙ **ΟΛΙΚΗ**, ΟΧΙ ΑΠΛΩΣ «ΑΛΦΑΒΗΤΙΚΗ»
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Δύο γραφεία **μπορούν** να έχουν την ίδια επωνυμία *(διαφορετικοί οργανισμοί,
 * ίδιο εμπορικό όνομα — συμβαίνει)*. Με σύγκριση **μόνο** στην επωνυμία η σειρά
 * τους θα καθοριζόταν από τη σειρά άφιξης του `onSnapshot`, δηλαδή θα **άλλαζε**
 * ανάμεσα σε δύο φορτώσεις της ίδιας σελίδας. Το tie-break στο `companyId` κάνει
 * τη σχέση **ολική**: για δεδομένο σύνολο υπάρχει **ακριβώς μία** σειρά,
 * ανεξάρτητα από τη σειρά εισόδου και από τη σταθερότητα του `Array#sort`.
 *
 * ⚠️ **Ο τερματισμός δεν είναι διακοσμητικός.** Χωρίς αυτόν, η «ουδετερότητα» θα
 * ήταν *«κανείς δεν διάλεξε»* — που είναι **τυχαιότητα**, όχι ουδετερότητα, και
 * ένα γραφείο θα εμφανιζόταν πρώτο ή τελευταίο κατά τύχη σε κάθε φόρτωση.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔶 ΔΗΛΩΜΕΝΟ ΑΝΟΙΧΤΟ: Η ΑΛΦΑΒΗΤΙΚΗ ΣΕΙΡΑ **ΕΧΕΙ** ΜΕΡΟΛΗΨΙΑ, ΚΑΙ ΤΟ ΞΕΡΟΥΜΕ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η αλφαβητική σειρά ευνοεί συστηματικά τα ονόματα σε `Α`/`Β` — φαινόμενο τόσο
 * γνωστό που γέννησε ολόκληρη πρακτική ονοματοδοσίας *(«AAA …» στους έντυπους
 * καταλόγους)*. Δηλαδή είναι **ουδέτερη ως προς εμάς** *(δεν πουλάμε θέση)* αλλά
 * **όχι ουδέτερη ως προς τα γραφεία**.
 *
 * Η πλήρης θεραπεία είναι **περιστροφή ανά επισκέπτη** — σταθερή μέσα στη
 * συνεδρία, ώστε κάθε γραφείο να παίρνει την πρώτη θέση εξίσου συχνά. **ΔΕΝ
 * μπαίνει τώρα**, με λόγο: το §9.9 α ονομάζει ρητά το «αλφαβητικά» ως αποδεκτό,
 * και η περιστροφή κάνει τη σελίδα **μη ντετερμινιστική** — δηλαδή αδοκίμαστη με
 * άγκυρα και αδιάγνωστη σε αναφορά χρήστη *(«εμένα μου βγαίνει άλλη σειρά»)*.
 * Μπαίνει όταν ο πληθυσμός πάψει να χωρά σε μία οθόνη, μαζί με τη σελιδοποίηση
 * του §9.12 #11 — **και οι δύο** αλλάζουν την ίδια απόφαση.
 *
 * ⛔ **ΜΗΝ προσθέσεις εδώ δεύτερο κριτήριο** *(«πρώτα τα κοντινά», «πρώτα τα
 * πρόσφατα», «πρώτα τα πλήρη»)*. Καθένα από αυτά είναι **κατάταξη** — και η
 * απόσταση από «πρώτα τα πλήρη προφίλ» ως «πρώτα τα προφίλ που πλήρωσαν» είναι
 * μία γραμμή κώδικα.
 */

import type { AgencyProfile } from '@/types/agency-profile';
import { compareByNameThenId } from '@/lib/ordering/total-name-order';

/**
 * **Ουδέτερη, ολική σειρά για τον δημόσιο κατάλογο** (ADR-827 §9.9 α).
 *
 * Επιστρέφει **νέο** πίνακα — η είσοδος έρχεται από `onSnapshot` και είναι
 * `readonly`· μια επιτόπια `sort()` θα μετέβαλλε δεδομένα που ανήκουν στη
 * συνδρομή.
 */
export function orderAgencies(
  profiles: readonly AgencyProfile[],
): readonly AgencyProfile[] {
  return [...profiles].sort(compareAgencies);
}

/**
 * **Η ΜΙΑ σύγκριση.** Εξάγεται ώστε η άγκυρα να τη μεταλλάξει **χωρίς** πίνακα:
 * ένας συγκριτής που δοκιμάζεται μόνο μέσω `sort` κρύβει το tie-break του πίσω
 * από τη σταθερότητα του `Array#sort` — δηλαδή θα φαινόταν σωστός **και** αν
 * έλειπε *(μάθημα: «tie-break σκέλος = εμφάνιση, ΟΧΙ απόδειξη»)*.
 *
 * 🔑 **Η ΜΗΧΑΝΗ ΜΕΤΑΚΟΜΙΣΕ, Η ΑΠΟΦΑΣΗ ΕΜΕΙΝΕ** (2026-09-01, ADR-841 §7 Α6). Το
 * collation και ο τερματισμός ζουν πλέον στο {@link compareByNameThenId}, γιατί
 * απέκτησαν **δεύτερο** καταναλωτή *(οι αγγελίες μιας βιτρίνας)* και δύο αντίγραφα
 * θα ήταν δύο απαντήσεις στο «τι σημαίνει αλφαβητικά;». **Αυτή** η συνάρτηση μένει
 * επειδή είναι το **ονομασμένο σημείο του antitrust**: εδώ φαίνεται, σε μία γραμμή,
 * ότι ο κατάλογος διαβάζει **επωνυμία και ταυτότητα, τίποτε άλλο**.
 */
export function compareAgencies(a: AgencyProfile, b: AgencyProfile): number {
  return compareByNameThenId(a.displayName, a.companyId, b.displayName, b.companyId);
}
