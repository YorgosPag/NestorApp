import { PROXIMITY_TIE_MARGIN } from '@/lib/contact/first-contact-limits';
import { distanceMeters } from '@/lib/geo/geo-distance';
import type { GeoPoint } from '@/types/geo/coordinates';
import type { PublicShowcase } from '@/types/agency-profile';

/**
 * **Από πού κοιτάζει ο άνθρωπος** — και ποιος είναι, για τη σταθερότητα της ισοπαλίας.
 *
 * ⚠️ **Δύο πεδία, καμία σημαία.** Ένα `{ sortByDistance: boolean }` θα ήταν διακόπτης
 * που κάποιος μπορεί να ξεχάσει· εδώ η **απουσία αφετηρίας** είναι η ίδια η κατάσταση
 * *«δεν ξέρουμε πού είσαι»*, και ο τύπος την κάνει αδύνατο να αγνοηθεί.
 */
export interface DirectoryViewpoint {
  /**
   * Η αφετηρία. **`null` = δεν ξέρουμε πού είναι ο άνθρωπος** ⇒ **όλοι ισότιμοι**.
   *
   * 🔑 Και τότε η σειρά είναι **η ζώνη ισοπαλίας σε όλο τον πληθυσμό**: τυχαία,
   * σταθερή ανά άνθρωπο. ⛔ **ΜΗΝ γυρίσεις στο αλφαβητικά ως «ασφαλή προεπιλογή»** —
   * θα ξαναγεννούσε τη μεροληψία «ΑΑΑ…» ακριβώς για τους επισκέπτες που δεν μας
   * είπαν πού είναι, δηλαδή για **τους περισσότερους**.
   */
  readonly from: GeoPoint | null;
  /**
   * Ο σπόρος της ισοπαλίας — το `uid` του συνδεδεμένου, ή ταυτότητα **συνεδρίας** για
   * τον ανώνυμο.
   *
   * ⚠️ **Σταθερός ανά ΑΝΘΡΩΠΟ, όχι ανά φόρτωση.** Σπόρος που αλλάζει σε κάθε render
   * θα έκανε τη σελίδα **μη ντετερμινιστική**: αδοκίμαστη με άγκυρα και αδιάγνωστη σε
   * αναφορά χρήστη *(«εμένα μου βγαίνει άλλη σειρά»)*.
   */
  readonly seed: string;
}

/**
 * **Ουδέτερη, ολική σειρά για τον δημόσιο κατάλογο** — ο πιο κοντινός πρώτος (ΠΕ7).
 *
 * Επιστρέφει **νέο** πίνακα — η είσοδος έρχεται από `onSnapshot` και είναι `readonly`·
 * μια επιτόπια `sort()` θα μετέβαλλε δεδομένα που ανήκουν στη συνδρομή.
 *
 * ⚠️ **Όποιος ΔΕΝ δήλωσε τόπο πηγαίνει ΤΕΛΕΥΤΑΙΟΣ, και δεν είναι ποινή**: ο άξονας
 * ρωτά *«πόσο κοντά είσαι;»* και η βιτρίνα **δεν το λέει**. Η εναλλακτική *(να
 * μπαίνουν πρώτοι ή ανακατεμένοι)* θα έδινε σε όποιον **δεν** δηλώνει τόπο θέση που
 * δεν κέρδισε — δηλαδή θα **αντάμειβε τη σιωπή**, ίδιο σκεπτικό με το φίλτρο
 * (`showcase-filter.ts`). Μεταξύ τους μένουν **ισότιμοι**.
 */
export function orderAgencies(
  profiles: readonly PublicShowcase[],
  viewpoint: DirectoryViewpoint,
): readonly PublicShowcase[] {
  if (viewpoint.from === null) return tiedOrder(profiles, viewpoint.seed);

  const located: ProximityRank[] = [];
  const unlocated: PublicShowcase[] = [];
  for (const showcase of profiles) {
    if (showcase.position === null) unlocated.push(showcase);
    else located.push({ showcase, metres: distanceMeters(viewpoint.from, showcase.position) });
  }

  return [...bandedByProximity(located, viewpoint.seed), ...tiedOrder(unlocated, viewpoint.seed)];
}

/** Μια βιτρίνα με τη μετρημένη της απόσταση — εφήμερο, ποτέ αποθηκευμένο. */
interface ProximityRank {
  readonly showcase: PublicShowcase;
  readonly metres: number;
}

/**
 * **Ζώνες ισοπαλίας, απληστία από τον πλησιέστερο.**
 *
 * Ο πλησιέστερος ορίζει την οροφή της ζώνης του *(× 1 + περιθώριο)*· όσοι χωράνε είναι
 * **ισότιμοι** και ανακατεύονται με τον σπόρο. Ο πρώτος που δεν χωρά ανοίγει **νέα**
 * ζώνη, με **δική του** οροφή — γι' αυτό το περιθώριο ρυθμίζεται μόνο του: 2 χλμ. ⇒
 * ισόπαλοι ως 2,5· 20 χλμ. ⇒ ως 25.
 *
 * ⚠️ **Η οροφή υπολογίζεται από τον πλησιέστερο ΤΗΣ ΖΩΝΗΣ, όχι από τον απόλυτα
 * πλησιέστερο.** Μια μοναδική οροφή για όλους θα ήταν πάλι **απόλυτο** κατώφλι με άλλο
 * όνομα — ακριβώς αυτό που το Θ-6 απέρριψε.
 */
function bandedByProximity(
  ranked: readonly ProximityRank[],
  seed: string,
): readonly PublicShowcase[] {
  const queue = [...ranked].sort(
    (a, b) => a.metres - b.metres || compareWithinBand(seed, a.showcase, b.showcase),
  );

  const ordered: PublicShowcase[] = [];
  let index = 0;
  while (index < queue.length) {
    const ceiling = queue[index].metres * (1 + PROXIMITY_TIE_MARGIN);
    let end = index;
    while (end < queue.length && queue[end].metres <= ceiling) end += 1;

    const band = queue.slice(index, end).map((entry) => entry.showcase);
    ordered.push(...tiedOrder(band, seed));
    index = end;
  }

  return ordered;
}

/** Όλοι ισότιμοι — η **μία** διατύπωση της ισοπαλίας, ώστε να μη γραφτεί δεύτερη. */
function tiedOrder(
  profiles: readonly PublicShowcase[],
  seed: string,
): readonly PublicShowcase[] {
  return [...profiles].sort((a, b) => compareWithinBand(seed, a, b));
}

/**
 * **Η ΜΙΑ σύγκριση της ισοπαλίας.** Εξάγεται ώστε η άγκυρα να τη μεταλλάξει **χωρίς**
 * πίνακα: ένας συγκριτής που δοκιμάζεται μόνο μέσω `sort` κρύβει τον τερματισμό του
 * πίσω από τη σταθερότητα του `Array#sort` — δηλαδή θα φαινόταν σωστός **και** αν
 * έλειπε *(μάθημα: «tie-break σκέλος = εμφάνιση, ΟΧΙ απόδειξη»)*.
 *
 * 🔴 **ΔΙΑΒΑΖΕΙ ΜΟΝΟ ΤΟ `companyId`** — καμία επωνυμία, καμία απόδειξη, καμία
 * ημερομηνία. Είναι το **ονομασμένο σημείο του antitrust**: εδώ φαίνεται, σε δύο
 * γραμμές, ότι μέσα στη ζώνη **δεν αποφασίζει κανένα χαρακτηριστικό του γραφείου**.
 *
 * ⚠️ Το `companyId` ως τελευταίο σκέλος **δεν είναι δεύτερο κριτήριο**: δεν έχει
 * σημασία στον κόσμο *(κανείς δεν διαλέγει ταυτότητα για να βγει πρώτος — και αν
 * προσπαθούσε, ο σπόρος του κάθε επισκέπτη θα του έδινε άλλη θέση)*. Υπάρχει **μόνο**
 * για να είναι η σχέση **ολική**, δηλαδή για να μη διαλέγει η `sort`.
 */
export function compareWithinBand(seed: string, a: PublicShowcase, b: PublicShowcase): number {
  const byLot = lotOf(seed, a.companyId) - lotOf(seed, b.companyId);
  if (byLot !== 0) return byLot;
  if (a.companyId === b.companyId) return 0;
  return a.companyId < b.companyId ? -1 : 1;
}

/**
 * **Ο κλήρος** — ντετερμινιστικός, χωρίς εξάρτηση, χωρίς ρολόι.
 *
 * FNV-1a 32 bit πάνω στο `σπόρος + ταυτότητα`. ⚠️ **Δεν είναι κρυπτογραφικός και δεν
 * χρειάζεται να είναι**: το ζητούμενο δεν είναι να μη μαντεύεται, αλλά να **μην
 * ευνοεί συστηματικά** κανένα γραφείο. Ο ίδιος άνθρωπος βλέπει **πάντα** την ίδια
 * σειρά· δύο άνθρωποι βλέπουν **διαφορετική**.
 */
function lotOf(seed: string, companyId: string): number {
  const material = `${seed}:${companyId}`;
  let hash = 0x811c9dc5;
  for (let index = 0; index < material.length; index += 1) {
    hash ^= material.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash;
}
