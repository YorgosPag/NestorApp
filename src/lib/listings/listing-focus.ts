/**
 * **Πόσο έντονα** αφορά μια συγκεκριμένη αγγελία την τρέχουσα εστίαση.
 *
 * ⚠️ Είναι **σειρά**, όχι σύνολο: `selected` υπερισχύει του `peeked`. Μια αγγελία που
 * είναι **και** επιλεγμένη **και** κάτω από τον δείκτη δεν είναι «διπλά επισημασμένη»
 * — είναι επιλεγμένη, και ο δείκτης δεν προσθέτει τίποτα που δεν λέει ήδη η επιλογή.
 */
export type ListingFocusStrength = 'none' | 'peeked' | 'selected';

/**
 * Η εστίαση της οθόνης 2, **ολόκληρη**.
 *
 * 🔑 **Δύο πεδία, όχι διακριτή ένωση με «κατάσταση»**: οι δύο αιτίες συνυπάρχουν
 * νόμιμα. Ο άνθρωπος διαλέγει ένα ακίνητο στη Θεσσαλονίκη (`selected`) και μετά σαρώνει
 * με το ποντίκι την Πάτρα (`peeked`) — και οφείλει να βλέπει **και τα δύο**, αλλιώς η
 * σάρωση **σβήνει** τη δουλειά που μόλις έκανε. Είναι το ίδιο εύρημα με το πρότυπο του
 * Airbnb: *«κρατά την επιλογή σου επισημασμένη ακόμη κι όταν κάνεις zoom out»*.
 */
export interface ListingFocus {
  /** **Εφήμερο** — «ο δείκτης είναι τώρα από πάνω». Σβήνει μόνο του. */
  readonly peeked: string | null;
  /** **Επίμονο** — «αυτό διάλεξα». Σβήνει μόνο με νέα επιλογή ή ρητή ακύρωση. */
  readonly selected: string | null;
}

export const NO_LISTING_FOCUS: ListingFocus = { peeked: null, selected: null };

/** Πόσο έντονα αφορά η εστίαση **αυτή** την αγγελία. */
export function listingFocusStrength(focus: ListingFocus, id: string): ListingFocusStrength {
  if (focus.selected === id) return 'selected';
  if (focus.peeked === id) return 'peeked';
  return 'none';
}

/**
 * **Ποια αγγελία αφορά η εστίαση τώρα** — μία απάντηση, για όποιον χωρά μόνο μία.
 *
 * ⚠️ **Το `peeked` προηγείται εδώ, αντίστροφα από την ένταση.** Δεν είναι αντίφαση:
 * η ένταση απαντά *«πώς να το βάψω;»* (η επιλογή είναι ισχυρότερη), αυτό απαντά
 * *«ποιο κοιτάζει αυτή τη στιγμή;»* — και η απάντηση είναι πάντα το **πιο πρόσφατο**,
 * δηλαδή αυτό που βρίσκεται κάτω από τον δείκτη.
 *
 * 🔑 Ο καταναλωτής του είναι ο **δείκτης άκρης** και το `aria-activedescendant`: και οι
 * δύο ρωτούν *«πού να στρέψω την προσοχή;»*, όχι *«τι είναι σημαντικό;»*.
 */
export function focusedListingId(focus: ListingFocus): string | null {
  return focus.peeked ?? focus.selected;
}

/** Αφορά η εστίαση **οτιδήποτε**; */
export function hasListingFocus(focus: ListingFocus): boolean {
  return focus.peeked !== null || focus.selected !== null;
}
