/**
 * **Ονόματα αρχείων που δήλωσε άνθρωπος** — ταυτότητες `FileRecord.id`, στη σειρά που
 * τις έγραψε.
 *
 * ⚠️ **Η σημασία της σειράς ανήκει στον καταναλωτή.** Για τη δήλωση σειράς είναι
 * *«πρώτο, δεύτερο…»*· για τη δήλωση κατόψεων είναι απλώς *«αυτές»*. Ο τύπος δεν
 * υπόσχεται νόημα που δεν έχει.
 */
export type DeclaredFileIds = readonly string[];

/** Καμία δήλωση — μοιράζεται, γιατί είναι αμετάβλητη και κενή. */
export const NO_DECLARED_FILE_IDS: DeclaredFileIds = [];

/**
 * **Η ΜΙΑ ΑΝΑΓΝΩΣΗ ΤΟΥ ΩΜΟΥ ΠΕΔΙΟΥ.**
 *
 * ⚠️ **Δεν πετά ποτέ, και δεν «διορθώνει»**: ό,τι δεν είναι πίνακας ⇒ *καμία δήλωση*.
 * Μια εξαίρεση εδώ θα ακύρωνε τη **δημοσίευση ολόκληρης** της αγγελίας επειδή κάποιος
 * έγραψε σκουπίδι σε ένα **προαιρετικό** πεδίο.
 *
 * ⚠️ **ΚΑΝΕΝΑ ΚΟΨΙΜΟ ΣΕ ΟΡΙΟ ΕΔΩ, ΕΠΙΤΗΔΕΣ.** Θα ήταν εύλογο και θα ήταν **λάθος**: η
 * δήλωση περιέχει και ταυτότητες που **δεν** ταιριάζουν πια σε δημοσιεύσιμο αρχείο, άρα
 * ένα κόψιμο στη θέση N μπορεί να πετάξει ταυτότητα που **ταιριάζει**. Το όριο
 * επιβάλλεται εκεί που είναι αληθές — στο **αποτέλεσμα** — και το μήκος της εισόδου το
 * φράζει η **πόρτα**.
 */
export function declaredFileIds(value: unknown): DeclaredFileIds {
  if (!Array.isArray(value)) return NO_DECLARED_FILE_IDS;

  const ids = value.filter(
    (entry): entry is string => typeof entry === 'string' && entry.trim() !== '',
  );
  return ids.length === 0 ? NO_DECLARED_FILE_IDS : ids;
}
