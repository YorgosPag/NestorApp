/**
 * @fileoverview **ΤΙ ΕΓΓΡΑΦΟ `files` ΓΕΝΝΑ Η ΔΗΜΟΣΙΕΥΣΗ ΕΝΟΣ ΜΟΝΤΕΛΟΥ** — μία απάντηση.
 * @related ADR-845 §9 (Ο-13) · ADR-841 §7 Α17.7 · services/listings/agency-media-publication
 * @module lib/listings/model-file-record
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ — Η ΡΑΦΗ ΗΤΑΝ ΑΔΟΚΙΜΑΣΤΗ, ΚΑΙ ΕΣΠΑΣΕ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το **Ο-13** μετρήθηκε ζωντανά: `POST …/model` → **200**, έγγραφο `ready` **122.636 bytes**,
 * επαναδημοσίευση `balanced: true` — και **`models: []`**, με **καμία** από τις τέσσερις
 * ονομασμένες αρνήσεις στο ημερολόγιο. Το μοντέλο δεν απορρίφθηκε· **δεν έφτασε**.
 *
 * 🔑 **Η ΑΙΤΙΑ ΔΕΝ ΗΤΑΝ ΣΕ ΚΑΝΕΝΑΝ ΑΠΟ ΤΟΥΣ ΔΥΟ ΩΜΟΥΣ, ΑΛΛΑ ΑΝΑΜΕΣΑ ΤΟΥΣ**: ο **γραφέας**
 * παρήγαγε έγγραφο **χωρίς `classification`**, και ο **αναγνώστης** απαιτεί —σωστά— ρητό
 * `'public'`. Και οι δύο πλευρές ήταν, χωριστά, σωστές· η **ραφή** τους δεν ήταν ποτέ ερώτηση.
 *
 * 🔴 **ΚΑΙ ΓΙ' ΑΥΤΟ Η ΑΓΚΥΡΑ ΤΟΥ Ο-9 ΗΤΑΝ ΠΡΑΣΙΝΗ ΟΣΟ Η ΠΑΡΑΓΩΓΗ ΗΤΑΝ ΣΠΑΣΜΕΝΗ**: το
 * fixture της έγραφε `classification: 'public'` **με το χέρι** — σχήμα που ο γραφέας **δεν
 * παράγει ποτέ**. Ένα fixture που περιγράφει έγγραφο το οποίο κανείς δεν γράφει δεν είναι
 * κάλυψη· είναι **ευχή**. Το repo το έχει ονομάσει: *«πράσινα tests δεν αποδεικνύουν εγγραφή»*.
 *
 * ⇒ Αυτό το module υπάρχει ώστε η ερώτηση *«τι έγγραφο γεννιέται;»* να έχει **ΕΝΑ** σώμα, το
 * οποίο **εκτελούν και οι δύο**: η πόρτα του ανεβάσματος και η άγκυρα. Μια άγκυρα που
 * ξανάγραφε τα ορίσματα θα δοκίμαζε **δίδυμο**, και το δίδυμο θα έμενε πράσινο ακριβώς όπως
 * έμεινε το προηγούμενο.
 *
 * ⛔ **ΜΗΝ καλέσεις εδώ το `buildPendingFileRecordData` από αλλού για μοντέλα.** Δεύτερος
 * καλών σημαίνει δεύτερη απάντηση στο *«είναι δημόσιο;»* — και η μία από τις δύο θα είναι,
 * κάποια στιγμή, η λάθος.
 */

import {
  ENTITY_TYPES,
  FILE_CATEGORIES,
  FILE_CLASSIFICATIONS,
  FILE_DOMAINS,
} from '@/config/domain-constants';
import {
  buildPendingFileRecordData,
  type BuildPendingFileRecordResult,
} from '@/services/file-record';
import type { ModelPublicationDeclaration } from './listing-model-declaration';
import { modelPublicationIdentityKey } from './model-publication-identity';

/**
 * Η επέκταση της κανονικής διαδρομής — **χωρίς τελεία**, όπως τη θέλει το `buildStoragePath`.
 *
 * ⚠️ Ζει **εδώ** και όχι στην πόρτα: είναι ιδιότητα του **εγγράφου** που γεννιέται, και η
 * άγκυρα πρέπει να ρωτά το ίδιο μονοπάτι που θα γραφτεί — όχι ένα που της μοιάζει.
 */
export const MODEL_FILE_EXT = 'glb';

/** Ό,τι ξέρει η πόρτα τη στιγμή που γεννά το έγγραφο — και ούτε πεδίο παραπάνω. */
export interface PublishedModelFileRequest {
  readonly companyId: string;
  readonly propertyId: string;
  readonly contentType: string;
  readonly originalFilename: string;
  readonly createdBy: string;
  /**
   * **Η δήλωση που ταξιδεύει δίπλα στα bytes** — από εδώ **παράγεται** η ταυτότητα (Ο-27).
   *
   * 🔴 **ΟΛΟΚΛΗΡΗ, ΟΧΙ ΤΡΙΑ ΣΚΕΛΗ.** Ο πειρασμός ήταν να δεχτεί
   * `{ provenance, scope, state }` — δηλαδή **ήδη** την ταυτότητα. Θα ήταν δεύτερη ευκαιρία
   * να αποκλίνει από ό,τι ψήνεται στο αρχείο: ο καλών θα μπορούσε να γράψει `as-built` εδώ
   * και `proposal` στα custom metadata, και **καμία** πύλη δεν θα το έβλεπε. Με τη δήλωση
   * ολόκληρη, η ταυτότητα είναι **συνάρτηση** εκείνου που ταξιδεύει — δεν μπορούν να
   * διαφωνήσουν, γιατί δεν είναι δύο πράγματα.
   */
  readonly declaration: ModelPublicationDeclaration;
}

/**
 * 🏆 **ΤΟ ΕΓΓΡΑΦΟ ΤΟΥ ΔΗΜΟΣΙΕΥΟΜΕΝΟΥ ΜΟΝΤΕΛΟΥ** — σε αναμονή, όπως κάθε ανέβασμα.
 *
 * 🔑 **`CONSTRUCTION`, όχι `SALES`**: το μοντέλο είναι **παραδοτέο της μελέτης** — φέρει
 * σήμανση κατάστασης και υπογράφοντα μηχανικό. Το ότι *καταλήγει* σε αγγελία δεν το κάνει
 * υλικό πώλησης, όπως δεν το κάνει ούτε την κάτοψη.
 *
 * ⚠️ **`PENDING` και όχι `READY`** — τον κύκλο ζωής τον κλείνει η πόρτα **αφού** γραφτούν τα
 * bytes (`buildFinalizeFileRecordUpdate`). Ένα ημιτελές ανέβασμα οφείλει να είναι **αόρατο**
 * στον αναγνώστη της δημοσίευσης, όχι επικίνδυνο.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 `classification: 'public'` — Η ΘΕΡΑΠΕΙΑ ΤΟΥ Ο-13, ΚΑΙ **ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΧΑΛΑΡΩΣΗ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο φρουρός #1 του αναγνώστη *(«επιτρέπεται να φύγει από την εταιρεία;»)* μένει **ανέγγιχτος**
 * και εξακολουθεί να ρωτά `=== 'public'`. Αυτό που άλλαξε είναι ότι η **ανθρώπινη πράξη
 * αφήνει πλέον ίχνος**: ως το Ο-13 ο άνθρωπος διάλεγε ακίνητο-στόχο, σήμαινε κατάσταση και
 * υπέγραφε στον διάλογο «Δημοσίευση 3D» — και **τίποτα από αυτά δεν γραφόταν** στο πεδίο που
 * ρωτά ο αναγνώστης. Η εξουσιοδότηση **συνέβαινε** και ήταν **αόρατη**.
 *
 * 🔑 **Η ΠΡΑΞΗ ΕΙΝΑΙ ΕΔΩ ΑΥΣΤΗΡΟΤΕΡΗ ΑΠΟ ΤΗΣ ΦΩΤΟΓΡΑΦΙΑΣ, ΟΧΙ ΧΑΛΑΡΟΤΕΡΗ.** Η φωτογραφία
 * γίνεται δημόσια με **μία** μαζική σήμανση στον διαχειριστή αρχείων. Το μοντέλο περνά από
 * διαδρομή που **απαιτεί** ονομαστικό στόχο, σήμανση κατάστασης και **υπογράφοντα** πριν
 * γραφτεί ένα byte *(Α-3 · Α-4)*. Το ίδιο επιχείρημα γράφει ήδη ο `agencyMediaMaterial` για
 * τον λόγο που το μοντέλο δεν ζητά **δεύτερη** ονομαστική δήλωση.
 *
 * ⛔ **ΜΗΝ το κάνεις παράμετρο «για ευελιξία».** Αυτή η διαδρομή **είναι** η δημοσίευση —
 * δεν υπάρχει σήμερα άλλος καλών, και ένα ανέβασμα μοντέλου *χωρίς* πρόθεση δημοσίευσης
 * θα ήταν **άλλη** πόρτα με **δική της** ανθρώπινη πράξη, όχι σημαία εδώ.
 */
export function buildPublishedModelFileRecord(
  request: PublishedModelFileRequest,
): BuildPendingFileRecordResult {
  return buildPendingFileRecordData({
    companyId: request.companyId,
    entityType: ENTITY_TYPES.PROPERTY,
    entityId: request.propertyId,
    domain: FILE_DOMAINS.CONSTRUCTION,
    category: FILE_CATEGORIES.MODELS,
    contentType: request.contentType,
    originalFilename: request.originalFilename,
    createdBy: request.createdBy,
    ext: MODEL_FILE_EXT,
    classification: FILE_CLASSIFICATIONS.PUBLIC,
    publicationIdentity: modelPublicationIdentityKey({
      // 🔴 **`'measured'` ΣΤΑΘΕΡΑ ΕΔΩ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΔΕΙΞΗ — ΟΧΙ ΠΑΡΑΔΟΧΗ.** **Αυτή** η πόρτα
      //    είναι ο αγωγός του εργολάβου: τα bytes ψήνονται από τη σκηνή του DXF viewer, και το
      //    `attribute-provenance` ορίζει το `measured` ως *«υπολογισμένο από DXF/BIM»*. Η ίδια
      //    σταθερά γράφεται **ήδη** στο `withPublishedModels`, από την ίδια αιτία.
      //    ⛔ **ΜΗΝ την κάνεις παράμετρο «για ευελιξία»**: το μοντέλο του αρχιτέκτονα ιδιώτη
      //    (`declared`, Φ4β) θα έρθει από **άλλη πόρτα** με **δική της** ανθρώπινη πράξη — και
      //    τότε η προέλευση θα είναι ιδιότητα **εκείνης**, όχι σημαία εδώ. Ίδιο επιχείρημα με
      //    το `classification` από πάνω.
      provenance: 'measured',
      scope: request.declaration.scope,
      state: request.declaration.state,
    }),
  });
}
