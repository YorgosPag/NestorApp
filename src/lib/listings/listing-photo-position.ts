/**
 * Ο πίνακας των **προσαρτημένων** καρτών, όχι όσων είδε ποτέ ο άνθρωπος.
 *
 * 🔴 **ΕΙΝΑΙ ΦΡΑΓΜΕΝΟΣ ΕΠΕΙΔΗ ΚΑΘΕ ΓΡΑΦΕΑΣ ΣΒΗΝΕΙ ΤΗ ΓΡΑΜΜΗ ΤΟΥ ΣΤΟ UNMOUNT** — δες
 * {@link forgetPhotoPosition}. Χωρίς αυτό, ένα `Map` σε άπειρη κύλιση μεγαλώνει με κάθε
 * αγγελία που πέρασε ποτέ από την οθόνη: διαρροή που **δεν φαίνεται ποτέ σε δοκιμή**
 * και μεγαλώνει μόνο σε πραγματική χρήση.
 */
const visiblePhotoByListing = new Map<string, number>();

/**
 * **Η κάρτα δηλώνει τι βλέπει.** Καλείται από τον `IntersectionObserver` της γκαλερί —
 * δηλαδή ~μία φορά ανά φωτογραφία, **όχι** σε ρυθμό καρέ.
 *
 * ⚠️ **Καμία ειδοποίηση, κανένα re-render.** Αυτό είναι εγγραφή σε πίνακα, όχι εκπομπή
 * γεγονότος — και γι' αυτό είναι ασφαλές να την καλεί ένας παρατηρητής κύλισης.
 */
export function notePhotoPosition(listingId: string, index: number): void {
  visiblePhotoByListing.set(listingId, index);
}

/**
 * **Η κάρτα φεύγει από την οθόνη.** Υποχρεωτικό στην καθαριότητα του `useEffect`.
 *
 * ⚠️ **Το «ξέχασε» ΔΕΝ είναι απώλεια πληροφορίας**: αν η κάρτα δεν είναι στο DOM, δεν
 * υπάρχει «τι κοίταζε ο άνθρωπος **μόλις τώρα**» — υπάρχει «τι κοίταζε κάποτε», που
 * είναι **άλλη ερώτηση** και θα ήταν χειρότερη απάντηση από το τίμιο «δεν ξέρω».
 */
export function forgetPhotoPosition(listingId: string): void {
  visiblePhotoByListing.delete(listingId);
}

/**
 * **«Από ποια φωτογραφία ξεκινώ;»** — η ερώτηση της φούσκας, τη στιγμή που γεννιέται.
 *
 * Επιστρέφει **`0` όταν δεν ξέρει**, και αυτό δεν είναι προεπιλογή από τεμπελιά: το `0`
 * *(«η πρώτη»)* είναι **ακριβώς** η σωστή απάντηση όταν η κάρτα δεν υπάρχει, δεν
 * ξεφυλλίστηκε ποτέ, ή είναι εκτός οθόνης. Ένα `null` θα υποχρέωνε **κάθε** καλούντα να
 * ξαναγράψει το ίδιο `?? 0`.
 *
 * ⚠️ **Το `total` είναι ΥΠΟΧΡΕΩΤΙΚΟ, και δεν είναι αμυντική προγραμματιστική συνήθεια.**
 * Ο κατάλογος είναι **ζωντανός** (`usePublicListings`): μια αγγελία μπορεί να χάσει
 * φωτογραφίες **ενώ η κάρτα της είναι στην οθόνη**. Χωρίς το ψαλίδισμα, η φούσκα θα
 * ζητούσε να κυλήσει σε slide **που δεν υπάρχει** — και θα έμενε λευκή.
 */
export function photoPositionFor(listingId: string, total: number): number {
  if (total <= 0) return 0;

  const noted = visiblePhotoByListing.get(listingId);
  if (noted === undefined || !Number.isInteger(noted) || noted < 0) return 0;

  return noted < total ? noted : 0;
}
