/**
 * @fileoverview SSoT — **πώς γίνεται ερώτημα βάσης μια περιοχή**, και τι ομολογεί η οθόνη.
 * @related ADR-777 §8.65 · lib/geo/geo-area.ts · lib/listings/listing-map-shape.ts
 * @module lib/listings/listing-geo-query
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΜΕΤΡΗΜΕΝΟ ΕΛΑΤΤΩΜΑ: Η ΟΘΟΝΗ 2 ΚΑΤΕΒΑΖΕ **ΟΛΗ** ΤΗ ΣΥΛΛΟΓΗ, ΖΩΝΤΑΝΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * ```ts
 * const q = collection(db, COLLECTIONS.PUBLIC_LISTINGS);   // καμία where, καμία limit
 * return subscribeToPublicListings(q, …);                  // onSnapshot — realtime
 * ```
 *
 * Σωστή απόφαση **για εννέα αγγελίες**, και γραμμένη ρητά ως τέτοια. Σε 60.000 είναι
 * σελίδα που δεν ανοίγει. Η **Α0** δεσμεύει *«μοντέλο για την τελική κλίμακα»*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΓΙΑΤΙ **ΟΧΙ GEOHASH** — ΚΑΙ Ο ΛΟΓΟΣ ΕΙΝΑΙ ΜΕΤΡΗΜΕΝΟΣ, ΟΧΙ ΓΟΥΣΤΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η «κανονική» απάντηση για γεωχωρικά ερωτήματα στο Firestore είναι **geohash**
 * (`geofire-common`, επίσημη βιβλιοθήκη της Firebase): πεδίο-ευρετήριο, `geohashQueryBounds`,
 * **4-9 ξεχωριστά ερωτήματα**, φιλτράρισμα ψευδώς θετικών στον πελάτη. Είναι η λύση
 * που προβλέπει κατά λέξη και το δικό μας `services/places/public-place-lookup.ts`.
 *
 * 🔴 **Έπαψε να είναι η σωστή απάντηση τον Μάρτιο του 2024.** Από τότε το Firestore
 * δέχεται **εύρη σε πολλά πεδία ταυτόχρονα** *(multi-field inequalities)*, δηλαδή ένα
 * ορθογώνιο γίνεται **ΕΝΑ** ερώτημα. Ο επικεφαλής της Firebase το μέτρησε:
 *
 * | Προσέγγιση | Περιττά έγγραφα | Κόστος / 1.000 χρήστες |
 * |---|---|---|
 * | geohash | **5,4×** | 34,20 $ |
 * | εύρη σε πολλά πεδία | **1,3×** | 7,80 $ |
 *
 * 🏆 **Και σε εμάς είναι ακόμη καλύτερο από το 1,3×.** Εκείνο το 1,3 περιέχει τη
 * διαφορά **τετραγώνου προς εγγεγραμμένο κύκλο** (21,5%), επειδή η μέτρηση ρωτούσε
 * *κύκλο*. Η οθόνη 2 ρωτά **εξαρχής ορθογώνιο** — το κάδρο του χάρτη — άρα το φθηνό
 * φίλτρο και η ερώτηση **ταυτίζονται γεωμετρικά**.
 *
 * ⚠️ **ΚΑΙ ΛΥΝΕΙ ΚΑΙ ΤΟ ΔΙΛΗΜΜΑ «ΚΥΚΛΟΣ ή ΟΡΘΟΓΩΝΙΟ»**: το `geohashQueryBounds`
 * δέχεται **μόνο ακτίνα**, ενώ το `ListingFilters.near` είναι `GeoArea` — κύκλος **ή**
 * ορθογώνιο (§8.63). Με εύρη σε δύο πεδία δεν υπάρχει δίλημμα: **και τα δύο** σχήματα
 * περιγράφονται από ορθογώνιο, και ο ακριβής κριτής τρέχει μετά, στη μνήμη.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις, **καμία** εξάρτηση από Firestore.
 */

import {
  areaBoundingBox,
  expandBoundingBox,
  isBoundingBox,
  matchGeoArea,
} from '@/lib/geo/geo-area';
import { drawnAreaKey } from '@/lib/listings/listing-drawn-area';
import type { GeoArea, GeoBoundingBox } from '@/types/geo/coordinates';

import { LISTING_UNCERTAINTY_KM } from './listing-map-shape';

/**
 * **Οι διαδρομές των πεδίων στο αποθηκευμένο έγγραφο** — αλφαριθμητικά που το Firestore
 * δεν ελέγχει.
 *
 * 🔴 **Γραμμένα ΕΔΩ, μία φορά, γιατί ένα λάθος εδώ είναι ΣΙΩΠΗΛΟ.** Ερώτημα σε
 * ανύπαρκτο πεδίο δεν σκάει — επιστρέφει **μηδέν έγγραφα**, δηλαδή «δεν υπάρχει τίποτα
 * σε αυτή την περιοχή» για μια αγορά γεμάτη ακίνητα. Είναι το ίδιο σχήμα αποτυχίας με
 * το `['get']` του MapLibre (ADR-777 §8.64) και με τον `source` που έλειπε (§8.63):
 * **η οθόνη μοιάζει σωστή**.
 *
 * ⚠️ Η δομή τους δηλώνεται από το `resolveListingPosition` *(`position.point.lat`)*, και
 * το `listing-geo-query.test.ts` την επαληθεύει πάνω σε **πραγματική** προβολή — όχι
 * πάνω σε αντιγραμμένο αλφαριθμητικό.
 */
export const LISTING_POINT_FIELD = {
  lat: 'position.point.lat',
  lng: 'position.point.lng',
} as const;

/**
 * **Η μεγαλύτερη αβεβαιότητα που μπορεί να έχει αγγελία** — παραγόμενη, ποτέ γραμμένη.
 *
 * 🔑 Ένα σκληρό `10` εδώ θα ήταν **δεύτερη δήλωση** της αβεβαιότητας: τη μέρα που
 * κάποιος προσθέσει σκαλί με μεγαλύτερη ακτίνα, το ορθογώνιο ανάγνωσης θα έμενε πίσω
 * και η «τρίτη κατηγορία» θα άρχιζε να **χάνει** αγγελίες — σιωπηλά, και μόνο για το
 * νέο σκαλί.
 */
export const MAX_LISTING_UNCERTAINTY_KM: number = Math.max(
  ...Object.values(LISTING_UNCERTAINTY_KM).filter((km): km is number => km !== null)
);

/**
 * **Πόσες αγγελίες κατεβάζουμε το πολύ.**
 *
 * ⚠️ **Δεν είναι «όσες χωράνε στην οθόνη» — είναι το σημείο όπου η απάντηση παύει να
 * είναι απάντηση.** Πάνω από αυτό, ο επισκέπτης δεν διαβάζει αποτελέσματα· χρειάζεται
 * **στένωση**. Το ίδιο κάνουν Zillow και Redfin, με το ίδιο μήνυμα *(«ζουμάρετε»)*.
 *
 * 🔴 **ΚΑΙ ΤΟ ΚΟΜΜΕΝΟ ΥΠΟΣΥΝΟΛΟ ΔΕΝ ΕΙΝΑΙ ΚΑΤΑΤΑΞΗ — ΓΙ' ΑΥΤΟ Η ΟΘΟΝΗ ΛΕΕΙ
 * «ΖΟΥΜΑΡΕΤΕ» ΚΑΙ ΟΧΙ «ΤΑ ΚΑΛΥΤΕΡΑ 500».** Με εύρη σε πολλά πεδία, το Firestore
 * απαιτεί το πρώτο `orderBy` να είναι **πεδίο ανισότητας**, άρα το κόψιμο γίνεται κατά
 * **γεωγραφικό πλάτος** — κριτήριο που δεν σημαίνει τίποτα για άνθρωπο. Μια οθόνη που
 * παρουσίαζε αυτό το υποσύνολο ως επιλογή θα έλεγε ψέμα **με τη σειρά της**, όχι με
 * τον αριθμό της: ακριβώς το σχήμα που έπιασε το §8.62 στον μετρητή.
 */
export const LISTING_READ_CAP = 500;

/**
 * **Το ορθογώνιο που ΚΑΤΕΒΑΖΟΥΜΕ** — η περιοχή, διευρυμένη κατά τη μέγιστη αβεβαιότητα.
 *
 * 🔴 **Η ΔΙΕΥΡΥΝΣΗ ΕΙΝΑΙ Ο ΛΟΓΟΣ ΠΟΥ ΕΠΙΖΕΙ Η «ΤΡΙΤΗ ΚΑΤΗΓΟΡΙΑ» ΤΟΥ §8.63.** Μια
 * αγγελία που ξέρουμε μόνο *«κάπου στην πόλη»* έχει **σημείο** έξω από την οθόνη και
 * **περιοχή** που την τέμνει: ο `listingAreaVerdict` θα την έλεγε *«ίσως»*, αλλά ένα
 * ερώτημα πάνω στο σημείο **δεν θα την κατέβαζε ποτέ**.
 *
 * ⚠️ **Χωρίς αυτή τη γραμμή, το Βήμα 4 θα ΑΚΥΡΩΝΕ σιωπηλά το Βήμα 3** — και δεν θα
 * φαινόταν πουθενά: καμία γραμμή του κριτή δεν θα άλλαζε, καμία άγκυρα του κριτή δεν
 * θα κοκκίνιζε. Θα εξαφανιζόταν απλώς ένας ολόκληρος κάδος της λογιστικής.
 */
export function listingReadBox(area: GeoArea): GeoBoundingBox {
  return expandBoundingBox(areaBoundingBox(area), MAX_LISTING_UNCERTAINTY_KM);
}

/**
 * **Τι ρωτάμε τη βάση** — δύο ρητές καταστάσεις, ποτέ `null` με νόημα.
 *
 * ⚠️ Το `'everywhere'` **δεν** σημαίνει «χωρίς όριο»: σημαίνει «χωρίς **γεωγραφικό**
 * όριο». Το {@link LISTING_READ_CAP} ισχύει **πάντα**, γιατί το μετρημένο ελάττωμα δεν
 * ήταν η απουσία περιοχής — ήταν η απουσία **οποιουδήποτε** ορίου.
 */
export type ListingReadPlan =
  | { readonly kind: 'everywhere' }
  | { readonly kind: 'within'; readonly box: GeoBoundingBox };

/** Η δηλωμένη περιοχή → σχέδιο ανάγνωσης. */
export function listingReadPlan(near: GeoArea | null): ListingReadPlan {
  return near === null ? { kind: 'everywhere' } : { kind: 'within', box: listingReadBox(near) };
}

/**
 * **ΤΙ ΟΜΟΛΟΓΕΙ Η ΟΘΟΝΗ** — κοίταξα παντού, ή κόπηκα;
 *
 * 🔑 **Το λεξιλόγιο δεν είναι νέο: αντιγράφεται από το `public-place-lookup.ts`**, που
 * το γράφει ήδη για την ίδια ερώτηση: *«αν το όριο ανάγνωσης εξαντληθεί, η ειλικρινής
 * απάντηση **δεν είναι «δεν βρέθηκε»** — είναι «δεν κοίταξα όλα»»*. Τρίτο λεξιλόγιο
 * για την ίδια ομολογία θα ήταν το σχήμα ADR-749.
 *
 * ⚠️ **Το `total: null` ΔΕΝ είναι παράλειψη — είναι η δεύτερη τίμια απάντηση.** Όταν η
 * δηλωμένη περιοχή είναι **κύκλος**, το ερώτημα καταμέτρησης τρέχει πάνω στο
 * περιγεγραμμένο ορθογώνιο, που είναι έως **21,5%** μεγαλύτερο. Ένας ακριβής αριθμός
 * εκεί θα ήταν **ψεύτικος με τρία ψηφία ακρίβειας** — χειρότερος από την ειλικρινή
 * σιωπή *«περισσότερες από όσες δείχνουμε»*. Όταν η περιοχή είναι **ορθογώνιο** *(το
 * κάδρο του χάρτη — η κυρίαρχη διαδρομή)* ή δεν υπάρχει καθόλου, ο αριθμός είναι
 * **ακριβής** και δίνεται.
 */
export type ListingReadCoverage =
  | { readonly kind: 'complete' }
  | { readonly kind: 'capped'; readonly shown: number; readonly total: number | null };

/**
 * **ΤΟ ΚΟΜΜΕΝΟ ΥΠΟΣΥΝΟΛΟ + Η ΟΜΟΛΟΓΙΑ** — από τα `CAP + 1` που ζητήθηκαν.
 *
 * 🔑 **Το «ένα παραπάνω» είναι ολόκληρος ο μηχανισμός.** Αν γύρισαν `CAP + 1`, ξέρουμε
 * ότι υπάρχουν κι άλλες **χωρίς** δεύτερο ερώτημα. Ένα σκέτο `limit(CAP)` που γυρίζει
 * ακριβώς `CAP` είναι **αμφίσημο** — και η αμφισημία θα γινόταν οθόνη που άλλοτε λέει
 * «ζουμάρετε» και άλλοτε όχι, στα **ίδια** δεδομένα.
 *
 * ⚠️ **Γενική ως προς το στοιχείο, επίτηδες.** Δεν ξέρει τι είναι αγγελία — ξέρει μόνο
 * «πόσα ζήτησα, πόσα κρατάω, τι ομολογώ». Έτσι ζει στο **καθαρό** επίπεδο μαζί με το
 * όριο που επιβάλλει, αντί να είναι θαμμένη μέσα σε hook όπου καμία άγκυρα δεν τη φτάνει.
 *
 * @param total Ο ακριβής συνολικός αριθμός, ή `null` όταν δεν μπορεί να ειπωθεί τίμια.
 */
export function capListingReads<T>(
  fetched: readonly T[],
  total: number | null
): { readonly items: readonly T[]; readonly coverage: ListingReadCoverage } {
  if (fetched.length <= LISTING_READ_CAP) {
    return { items: fetched, coverage: { kind: 'complete' } };
  }
  const items = fetched.slice(0, LISTING_READ_CAP);
  return { items, coverage: { kind: 'capped', shown: items.length, total } };
}

/**
 * Μπορεί να δοθεί **ακριβής** συνολικός αριθμός για αυτή την περιοχή;
 *
 * 🔑 Ναι όταν το ερώτημα καταμέτρησης ρωτά **ακριβώς** ό,τι ρωτά ο άνθρωπος: καθόλου
 * περιοχή *(όλη η αγορά)*, ή ορθογώνιο *(το ορθογώνιο **είναι** η ερώτηση)*. Όχι για
 * κύκλο — δες {@link ListingReadCoverage}. Ούτε για **όριο** *(ADR-883)*: το ερώτημα
 * καταμέτρησης μετρά το **ορθογώνιό** του, που περιέχει και γειτονικούς δήμους.
 */
export function countIsExactFor(near: GeoArea | null): boolean {
  return near === null || isBoundingBox(near);
}

/**
 * Το ορθογώνιο της **καταμέτρησης** — η ερώτηση του ανθρώπου, **αδιεύρυντη**.
 *
 * 🔴 **ΔΕΝ είναι το {@link listingReadBox}, και η διαφορά είναι όλη η ειλικρίνεια.** Το
 * ορθογώνιο ανάγνωσης είναι διευρυμένο κατά 10 χλμ ώστε να μη χαθεί το «ίσως»·
 * μετρημένο, θα έδινε αριθμό που περιλαμβάνει αγγελίες τις οποίες ο κριτής **απορρίπτει
 * ρητά**. Ο μετρητής θα ήταν πάλι *«συνεπής και ψεύτης»* — το ακριβές εύρημα του §8.62.
 */
export function listingCountBox(area: GeoArea): GeoBoundingBox {
  return areaBoundingBox(area);
}

/**
 * **Η ΤΑΥΤΟΤΗΤΑ μιας περιοχής** — σταθερό αλφαριθμητικό για την ίδια γεωγραφία.
 *
 * 🔴 **ΔΕΝ είναι βελτιστοποίηση — είναι ο φραγμός του βρόχου.** Τα φίλτρα ξαναγεννιούνται
 * σε κάθε απόδοση, οπότε το `near` είναι **νέο αντικείμενο** κάθε φορά ακόμη κι όταν η
 * γεωγραφία δεν άλλαξε. Ένα `useEffect` που εξαρτάται από την **αναφορά** θα ακύρωνε και
 * θα ξανάνοιγε τη συνδρομή σε **κάθε απόδοση**: το ίδιο σχήμα με το `selector ?? []`
 * *(νέος πίνακας ⇒ βρόχος)* που έχει ήδη πληρωθεί σε αυτό το δέντρο.
 *
 * ⚠️ **Δεν χρησιμοποιείται `JSON.stringify`**: η σειρά κλειδιών ενός αντικειμένου είναι
 * σειρά **γραφής**, όχι σημασία — δύο ισοδύναμα ορθογώνια φτιαγμένα από διαφορετικούς
 * καλούντες θα έδιναν διαφορετικό αλφαριθμητικό, δηλαδή σιωπηλή επανασυνδρομή.
 *
 * ⚠️ **ΤΟ ΠΡΟΘΕΜΑ ΟΝΟΜΑΖΕΙ ΤΟ ΣΧΗΜΑ, ΚΑΙ ΕΙΝΑΙ ΖΩΝΗ ΑΣΦΑΛΕΙΑΣ — ΟΧΙ ΣΗΜΕΡΙΝΗ ΑΝΑΓΚΗ.**
 * Μετρημένο με μετάλλαξη *(V08, 2026-09-07)*: αν και τα δύο σχήματα έγραφαν `box:`, οι
 * μορφές θα παρέμεναν **αδύνατο** να συγκρουστούν, γιατί ο κύκλος δίνει **τέσσερα**
 * τμήματα και το ορθογώνιο **πέντε**. Η μετάλλαξη είναι δηλαδή **ισοδύναμη σήμερα** —
 * καταγράφεται ως τέτοια αντί να εφευρεθεί test που θα την «έπιανε» ψεύτικα.
 *
 * 🔑 **Μένει επειδή η αριθμητική ισοδυναμία είναι ΤΥΧΗ, όχι εγγύηση**: την ημέρα που ο
 * κύκλος αποκτήσει τέταρτο συστατικό *(π.χ. μονάδα ή έλλειψη)*, τα δύο σχήματα θα
 * μοιράζονταν χώρο ονομάτων — και το σφάλμα θα εμφανιζόταν ως χάρτης που **δεν
 * ξαναδιαβάζει** όταν αλλάζεις από κύκλο σε ορθογώνιο ίδιων αριθμών.
 */
export function listingAreaKey(area: GeoArea | null): string {
  if (area === null) return 'everywhere';
  return matchGeoArea(area, {
    // ADR-883: η ταυτότητα του ορίου **είναι** η γεωγραφία του — ίδιος δήμος, ίδια ανάγνωση.
    region: (region) => `region:${region.adminId}`,
    // ADR-885: η ταυτότητα του σχεδίου είναι το κείμενο του συνδέσμου του.
    drawn: (drawn) => `drawn:${drawnAreaKey(drawn)}`,
    box: (box) => `box:${box.south}:${box.west}:${box.north}:${box.east}`,
    circle: (circle) => `circle:${circle.center.lat}:${circle.center.lng}:${circle.radiusKm}`,
  });
}
