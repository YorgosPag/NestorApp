/**
 * @fileoverview **ΤΟ ΣΧΗΜΑ ΕΙΝΑΙ Η ΑΚΡΙΒΕΙΑ** — η μία μετάφραση θέσης → σχήμα χάρτη.
 * @related ADR-777 §7 (Α5, κανόνας 27) · SPEC-777-RESEARCH §28.6 · CHECK 3.41
 * @module lib/listings/listing-map-shape
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΕΛΑΤΤΩΜΑ ΠΟΥ ΓΕΝΝΗΣΕ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ — μετρημένο, όχι υποθετικό
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η `determineAccuracy()` (`lib/geocoding/geocoding-engine-helpers.ts:74`) επιστρέφει
 * `'center'` ως **fallback**. Άρα σκέτο «Θεσσαλονίκη» παράγει **κανονικό σημείο**, και
 * ο `AddressMap` **δεν διαβάζει καθόλου** το `accuracy` (**grep = 0**).
 *
 * ⇒ Μια «Θεσσαλονίκη» και μια «Εγνατίας 147» ζωγραφίζονται **οπτικά ταυτόσημες**.
 *
 * Είναι **ακριβώς** το ελάττωμα που κυνηγά η δική μας **CHECK 3.41** (WCAG 1.4.1, *Use
 * of Color*) — δύο καταστάσεις που ξεχωρίζουν **μόνο** από μια ιδιότητα που ο χρήστης
 * δεν βλέπει — εδώ σε **πινέζες χάρτη** αντί για κελιά πίνακα.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΠΟΥ ΞΕΠΕΡΝΑΜΕ ΤΟΥΣ ΜΕΓΑΛΟΥΣ, ΚΑΙ ΕΙΝΑΙ ΔΟΜΙΚΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Τα portals ζωγραφίζουν **την ίδια πινέζα** και για τα δύο. Το Airbnb εισήγαγε τον
 * σκιασμένο κύκλο, αλλά **για ιδιωτικότητα** — απόκρυψη γνωστής θέσης — όχι για
 * **άγνοια**. Εδώ η διαφορά είναι **σχήματος** και παράγεται από την **προέλευση**,
 * οπότε ο χάρτης είναι **δομικά ανίκανος** να ζωγραφίσει πινέζα εκεί που δεν έχουμε
 * πινέζα: δεν υπάρχει διαδρομή από `'center'` στο `'pin'` μέσα σε αυτό το αρχείο.
 *
 * ⚠️ **ΕΝΑ ΣΗΜΕΙΟ ΟΠΟΥ ΑΠΟΚΛΙΝΩ ΑΠΟ ΤΟΝ ΠΙΝΑΚΑ ΤΗΣ Α5 — ρητά, με λόγο.**
 * Ο πίνακας του §28.6 δίνει «**περίγραμμα**» σε ολόκληρη τη ζώνη `survey · osm · drawn`.
 * Αλλά το περίγραμμα είναι **δεδομένο**, όχι κατηγορία: το `outline` είναι
 * **προαιρετικό** στους κλάδους `drawn`/`survey`/`bim`, και στο `osm` είναι **δομικά
 * απαγορευμένο** να αποθηκευτεί (ODbL — `outline?: never`, `types/geo/public-place.ts`).
 * Άρα η κατηγορία **υπόσχεται** σχήμα που η εγγραφή μπορεί να **μην έχει**.
 *
 * ⇒ Το σχήμα εδώ ακολουθεί **ό,τι κρατάμε**, όχι ό,τι υπόσχεται η κατηγορία. Ένα
 * `survey` χωρίς αποθηκευμένο περίγραμμα δίνει **πινέζα** — που είναι αλήθεια — αντί
 * για περίγραμμα που θα έπρεπε να **επινοηθεί**. Αν το ζωγραφίζαμε ως περίγραμμα, θα
 * αναπαράγαμε το ίδιο ελάττωμα που το αρχείο υπάρχει για να λύσει, μία βαθμίδα ψηλότερα.
 */

import type { GeoOutline } from '@/types/geo/coordinates';
import type { ListingPosition } from '@/types/public-listing';

/**
 * Τα **έξι** σχήματα της Α5. Κλειστή ένωση — νέα κατάσταση **σπάει τη μεταγλώττιση**
 * σε κάθε καταναλωτή, αντί να πέσει σιωπηλά σε προεπιλογή.
 */
export type ListingMapShape =
  /** Πραγματικό σχήμα — το κρατάμε, δεν το συμπεραίνουμε. */
  | 'outline'
  /** Ακριβές σημείο: διεύθυνση με αριθμό, ή πινέζα ανθρώπου. */
  | 'pin'
  /** Δρόμος χωρίς αριθμό — ξέρουμε τον δρόμο, όχι το κτίριο. */
  | 'pin-with-ring'
  /** Συνοικία — ξέρουμε περιοχή. */
  | 'shaded-circle'
  /** 🔴 Μόνο πόλη — **ΠΟΤΕ πινέζα**. Σκιάζεται η **πόλη**. */
  | 'shaded-city'
  /** Τίποτα. **Δεν εξαφανίζεται — μπαίνει στον μετρητή** (Α5 §4.1). */
  | 'none';

/**
 * Θέση → σχήμα. **Η μοναδική μετάφραση.**
 *
 * @param position   Η θέση της αγγελίας, όπως τη λύσε ο διακομιστής.
 * @param liveOutline Περίγραμμα που **αντλήθηκε ζωντανά** αυτή τη στιγμή (OSM). Είναι
 *   παράμετρος και **όχι** πεδίο της θέσης **επειδή ακριβώς δεν επιτρέπεται να
 *   αποθηκευτεί** (§13.4, ODbL): ζει όσο ζει το καρέ. Έτσι το νομικό όριο παραμένει
 *   εκεί που το έβαλε ο τύπος, και ο χάρτης εξακολουθεί να μπορεί να δείξει το
 *   πραγματικό σχήμα όταν το έχει μπροστά του.
 */
export function listingMapShape(
  position: ListingPosition,
  liveOutline?: GeoOutline | null
): ListingMapShape {
  if (position.kind === 'unknown') return 'none';

  // Ό,τι ΚΡΑΤΑΜΕ προηγείται της κατηγορίας — βλ. την απόκλιση στην κεφαλίδα.
  if (liveOutline && liveOutline.length > 0) return 'outline';

  switch (position.provenance) {
    case 'osm':
      // Το σημείο είναι το **κέντρο πραγματικού κτιρίου**, όχι συμπέρασμα από κείμενο:
      // δείχνει το κτίριο, άρα η πινέζα λέει αλήθεια. Το περίγραμμα, όταν αντληθεί
      // ζωντανά, το αναβαθμίζει σε `outline` από τον έλεγχο παραπάνω.
      return 'pin';

    case 'drawn':
    case 'survey':
    case 'bim':
      // Οι μόνοι κλάδοι που ΕΠΙΤΡΕΠΕΤΑΙ να κουβαλούν αποθηκευμένο σχήμα.
      return position.outline && position.outline.length > 0 ? 'outline' : 'pin';

    case 'manual':
      // Άνθρωπος έδειξε σημείο. Το σημείο **είναι** η απάντηση — καμία κλίμακα ακρίβειας.
      return 'pin';

    case 'geocoded':
      return shapeOfAccuracy(position.accuracy);

    default:
      return assertNeverShape(position);
  }
}

/**
 * Η κλίμακα ακρίβειας του geocoder → σχήμα.
 *
 * ⚠️ Ξεχωριστή συνάρτηση **επίτηδες**: είναι η **μόνη** διαδρομή όπου ένα σημείο
 * γεννιέται από **κείμενο** αντί από μέτρηση, και είναι εκεί που το `'center'` έμπαινε
 * μεταμφιεσμένο σε διεύθυνση.
 */
function shapeOfAccuracy(accuracy: Extract<ListingPosition, { provenance: 'geocoded' }>['accuracy']): ListingMapShape {
  switch (accuracy) {
    case 'exact':
      return 'pin';
    case 'interpolated':
      return 'pin-with-ring';
    case 'approximate':
      return 'shaded-circle';
    case 'center':
      // 🔴 Το κρίσιμο σκαλί. Πινέζα εδώ **είναι** το ψέμα που ζωγραφίζει σήμερα ο
      // `AddressMap`. Σκιάζεται η πόλη ⇒ η δήλωση γίνεται **αδύνατο** να διαβαστεί
      // ως διεύθυνση.
      return 'shaded-city';
    default:
      return assertNeverAccuracy(accuracy);
  }
}

/**
 * Έχει αυτή η αγγελία σχήμα στον χάρτη;
 *
 * 🔑 **Η λογιστική της Α5 και ο χάρτης διαβάζουν ΤΗΝ ΙΔΙΑ συνάρτηση — γι' αυτό δεν
 * μπορούν να διαφωνήσουν.** Αν ο μετρητής είχε δικό του κριτήριο («έχει
 * συντεταγμένες;») θα υπήρχαν **δύο** απαντήσεις στο ίδιο ερώτημα, και η μέρα που θα
 * διαφωνούσαν θα εμφανιζόταν ως «*η λίστα λέει 11, ο χάρτης δείχνει 10*» — δηλαδή
 * **ακριβώς** το ψέμα που ο κανόνας 27 απαγορεύει. Είναι το μάθημα του ADR-749
 * (δύο μηχανές, τρεις αριθμοί) εφαρμοσμένο **πριν** γεννηθεί η δεύτερη.
 */
export function isMappedShape(shape: ListingMapShape): boolean {
  return shape !== 'none';
}

