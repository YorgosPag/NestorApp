/**
 * ⚠️ **Δεν επιστρέφει σιωπηλά `'none'`.** Ένα άγνωστο σκαλί που πέφτει σε «κανένα
 * σχήμα» θα ζωγραφιζόταν ως *«χωρίς δηλωμένη θέση»* — δηλαδή το σφάλμα θα φορούσε τη
 * στολή μιας **έγκυρης** κατάστασης και θα μετριόταν στον μετρητή σαν να ήταν αληθινό.
 * Το ίδιο πρότυπο με τις πύλες μας: άγνωστη κατάσταση ⇒ `throw` **με όνομα**.
 */
function assertNeverShape(position: never): never {
  // Μήνυμα προγραμματιστή, όχι οθόνης (σύμβαση src/lib + N.11): δεν φτάνει ποτέ σε χρήστη.
  throw new Error(`listingMapShape: unknown position provenance — ${JSON.stringify(position)}`);
}

function assertNeverAccuracy(accuracy: never): never {
  throw new Error(`listingMapShape: unknown geocoder accuracy — ${JSON.stringify(accuracy)}`);
}
