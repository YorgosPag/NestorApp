/**
 * @fileoverview **ΠΟΙΕΣ ΑΓΓΕΛΙΕΣ ΔΕΙΧΝΟΥΝ ΤΙΜΗ ΠΑΝΩ ΣΤΟΝ ΧΑΡΤΗ** — και πού ακριβώς.
 * @related ADR-777 §8.60 (Ε2) · lib/listings/listings-geojson.ts · lib/properties/price-resolver.ts
 * @module lib/listings/listing-price-markers
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΙΜΕΣ **ΚΑΙ** ΚΟΥΚΙΔΕΣ — ΠΟΤΕ ΤΙΜΕΣ **ΑΝΤΙ ΓΙΑ** ΚΟΥΚΙΔΕΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ερώτημα ήταν *«αντί για μπλε κουκίδες, τιμές;»*. Η απάντηση είναι **όχι αντί**:
 * τα σχήματα του `listingsToGeoJson` μένουν **ακέραια** σε `circle`/`fill` layers — μία
 * πηγή GeoJSON που η ίδια η τεκμηρίωση του MapLibre μετρά σε **100.000 σημεία κάτω από
 * 16ms**. Αυτό το αρχείο δεν αφαιρεί τίποτα· **προσθέτει ετικέτα** σε ένα **φραγμένο**
 * υποσύνολο.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΤΟ ΕΥΡΗΜΑ ΠΟΥ ΚΑΝΕΙ ΤΟΥΣ ΚΟΜΒΟΥΣ DOM ΝΟΜΙΜΟΥΣ ΞΑΝΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `listings-geojson.ts` γράφει ρητά γιατί έφυγε από τους `<Marker>`: *«ένα στοιχείο
 * DOM ανά ακίνητο… **δεν** κλιμακώνεται σε κατάλογο»*. Η αντίρρηση είναι σωστή — και
 * **δεν παραβιάζεται εδώ, ικανοποιείται**: το **Airbnb** μέτρησε ότι κατεβάζοντας τις
 * ορατές πινακίδες από **200+ σε 30-50** *(οι υπόλοιπες μένουν κουκίδες)* **αυξήθηκαν**
 * οι κρατήσεις και η ικανοποίηση. Με το {@link PRICE_MARKER_LIMIT} το πλήθος των κόμβων
 * DOM παύει να είναι συνάρτηση **των δεδομένων** και γίνεται **σχεδιαστική σταθερά**:
 * ο κατάλογος μπορεί να δεκαπλασιαστεί χωρίς να προστεθεί ούτε ένας κόμβος.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ Η ΘΕΣΗ ΕΡΧΕΤΑΙ ΑΠΟ ΤΟ GeoJSON ΚΑΙ ΟΧΙ ΑΠΟ ΤΗΝ ΑΓΓΕΛΙΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `listings-geojson.ts` δηλώνει για τη μετατροπή σε `[lng, lat]`: *«Η μετατροπή
 * γίνεται **εδώ και μόνο εδώ**»* — γιατί *«ένα μπερδεμένο ζεύγος τοποθετεί το κτίριο σε
 * άλλη ήπειρο χωρίς να το πει κανείς»*. Ένα `listing.position.point.lng` γραμμένο εδώ
 * θα ήταν **δεύτερη** μετατροπή, δηλαδή δεύτερη ευκαιρία να αντιστραφεί το ζεύγος.
 * ⇒ Η πινακίδα κάθεται **ακριβώς** πάνω στο σχήμα που ζωγραφίστηκε, **εξ ορισμού**:
 * διαβάζουν την ίδια συντεταγμένη, όχι δύο που «πρέπει» να συμφωνούν.
 */

import type { ListingGeoJson } from './listings-geojson';
import type { ListingMapEntry } from './listing-map-entry';
import { PRICE_ROLE_ORDER, type PriceRole } from '@/lib/properties/price-resolver';

/**
 * **ΠΟΣΕΣ ΠΙΝΑΚΙΔΕΣ ΤΟ ΠΟΛΥ** — σχεδιαστική απόφαση, όχι όριο απόδοσης.
 *
 * Το εύρος **30-50** είναι το μετρημένο αποτέλεσμα του Airbnb· το **40** είναι το μέσο
 * του. ⚠️ **Δεν κρύβει αγγελίες**: όποια δεν πάρει πινακίδα εξακολουθεί να έχει το
 * **σχήμα** της στον χάρτη, τη **γραμμή** της στη λίστα και τη **φούσκα** της στο κλικ.
 * Το όριο αφορά την **ετικέτα**, όχι την ύπαρξη — γι' αυτό δεν χρειάζεται ανακοίνωση
 * «δείχνονται 40 από 120»: τίποτα δεν λείπει για να ανακοινωθεί.
 */
export const PRICE_MARKER_LIMIT = 40;

/** Μία πινακίδα τιμής: **πού**, **πόσο**, και **ποιανού**. */
export interface ListingPriceMarker {
  readonly id: string;
  /** Ο τίτλος της αγγελίας — για το **προσβάσιμο όνομα**, ποτέ για την όψη. */
  readonly title: string;
  readonly lng: number;
  readonly lat: number;
  /**
   * Το ποσό της **κύριας** τιμής, όπως το έκρινε ο `resolveDisplayPrice`.
   *
   * 🔑 **Είναι ταυτόχρονα το κλειδί διάταξης, και αυτό ΔΕΝ είναι σύμπτωση**: το
   * `priceSortKey` ορίζεται ως `getEffectivePrice(input)?.amount`, και το
   * `getEffectivePrice` είναι *«thin projection of resolveDisplayPrice»* που επιστρέφει
   * ακριβώς το `headline.amount`. Δεύτερο κλειδί **δεν γεννιέται**· και ότι δεν
   * γεννήθηκε κατά λάθος το **εκτελεί** άγκυρα σε κάθε commit (Κ5).
   */
  readonly amount: number;
  /**
   * **Τι είδους ποσό** — πώληση, μηνιαίο μίσθωμα ή τιμή ανά νύχτα.
   *
   * 🔴 Χωρίς αυτό η πινακίδα έγραφε «50 €» δίπλα σε «170.000 €» με την ίδια όψη
   * (ADR-835 §4.4). Ταξιδεύει ως **ρόλος**, όχι ως έτοιμο κείμενο: η μορφοποίηση ανήκει
   * στο `listing-price-label.ts`, η επιλογή εδώ.
   */
  readonly role: PriceRole;
}

/**
 * Οι αγγελίες που **δικαιούνται** πινακίδα τιμής, με σειρά και φραγμό.
 *
 * ΟΙ ΤΡΕΙΣ ΚΑΝΟΝΕΣ, και ο καθένας απαντά σε **διαφορετικό** ψέμα:
 *
 * 1. **Αβεβαιότητα θέσης ≤ {@link PLAQUE_MAX_UNCERTAINTY_M}** — ξέρουμε **ΠΟΥ**, στην
 *    κλίμακα που ο κλάδος θεωρεί αρκετή για τιμή. Μια πινακίδα «500 €» πάνω σε
 *    σκιασμένη **συνοικία** (1,5 χλμ) ή **πόλη** (10 χλμ) δηλώνει ακριβή τιμή σε θέση
 *    που μπορεί να απέχει χιλιόμετρα. Βλ. τη σταθερά για το **γιατί 1 χλμ**.
 *
 * 2. **`kind === 'priced'`** — ξέρουμε **ΠΟΣΟ**. Ο κριτής επιστρέφει
 *    `{ kind: 'missing', reason }` όταν δεν υπάρχει αριθμός· ένα «0 €» θα ήταν ψέμα και
 *    ένα «—» θόρυβος. ✅ Η σωστή μορφή είναι η **mini-pin** του Airbnb: **κουκίδα**,
 *    που ήδη υπάρχει. Το υβρίδιο δεν είναι συμβιβασμός — είναι η μόνη ειλικρινής μορφή.
 *
 * 3. **{@link PRICE_MARKER_LIMIT}** — φραγμένο πλήθος, ώστε ο DOM να μη μεγαλώνει με
 *    τα δεδομένα.
 *
 * @param entries  Ο κατάλογος ως **γραμμές** (`ListingMapEntry`), με **όποια** σειρά τον έδωσε η
 *                 επιφάνεια. 🔑 Όχι `PublicListing` (ADR-777 §8.77): ο κριτής ρωτά μόνο «ποια,
 *                 πόσο» — έτσι ο **ίδιος** κρίνει τη δημόσια αναζήτηση (`publicListingEntry`) και
 *                 το χαρτοφυλάκιο του κατόχου (`ownerListingEntry`), χωρίς δεύτερο αντίγραφο.
 * @param geoJson  Η έξοδος του `listingsToGeoJson` — **η μία** πηγή θέσης/σχήματος.
 * @param limit    Ανώτατο πλήθος πινακίδων. `0` ή αρνητικό ⇒ **καμία**.
 */
export function listingPriceMarkers(
  entries: readonly ListingMapEntry[],
  geoJson: ListingGeoJson,
  limit: number = PRICE_MARKER_LIMIT,
): readonly ListingPriceMarker[] {
  if (limit <= 0) return [];

  const anchors = plaqueAnchors(geoJson);
  const candidates: ListingPriceMarker[] = [];

  for (const { id, title, price } of entries) {
    const anchor = anchors.get(id);
    if (anchor === undefined) continue;              // κανόνας 1 — δεν ξέρουμε ΠΟΥ
    if (price.kind !== 'priced') continue;           // κανόνας 2 — δεν ξέρουμε ΠΟΣΟ

    candidates.push({
      id,
      title,
      lng: anchor[0],
      lat: anchor[1],
      amount: price.headline.amount,
      role: price.headline.role,
    });
  }

  return fairOrder(candidates).slice(0, limit);     // κανόνας 3 — φραγμένο πλήθος
}

/**
 * **Η ΜΕΓΙΣΤΗ αβεβαιότητα θέσης που σηκώνει πινακίδα τιμής, σε μέτρα.**
 *
 * 🔴 **ΑΝΤΙΚΑΤΕΣΤΗΣΕ ΤΟΝ ΚΑΝΟΝΑ `shape === 'pin'` (2026-09-17), ΚΑΙ Ο ΛΟΓΟΣ ΕΙΝΑΙ
 * ΜΕΤΡΗΣΗ ΤΟΥ ΚΛΑΔΟΥ, ΟΧΙ ΓΟΥΣΤΟ.** Ο παλιός κανόνας απέκλειε και το `pin-with-ring`
 * (αβεβαιότητα **250 μ.**, «ξέρουμε τον δρόμο») — και έκρυβε έτσι την τιμή κάθε
 * γεωκωδικοποιημένης διεύθυνσης χωρίς αριθμό. Όμως το **Airbnb**, ο κλάδος που ζει από
 * πινακίδες τιμής, **δεν δείχνει ΚΑΜΙΑ ακριβή θέση πριν την κράτηση**: η «γενική
 * τοποθεσία» είναι ακτίνα *«λιγότερο από 1 χλμ»* από τη διεύθυνση, και **κάθε** τέτοια
 * πινέζα φέρει τιμή. Ήμασταν **τέσσερις φορές αυστηρότεροι** από το πρότυπο — και το
 * πλήρωσε κατάλυμα που δεν φαινόταν ποτέ με τιμή.
 *
 * 🏆 **Γιατί ΑΡΙΘΜΟΣ και όχι λίστα σχημάτων**: η ερώτηση είναι *«πόσο μακριά μπορεί να
 * είναι;»*, και την απαντά ήδη το `uncertaintyM` του feature — το **ίδιο** πεδίο που
 * ζωγραφίζει τον κύκλο (`LISTING_UNCERTAINTY_KM`). Αν αλλάξει η αβεβαιότητα ενός
 * σχήματος, η πινακίδα **ακολουθεί** χωρίς να θυμηθεί κανείς αυτό το αρχείο. Και
 * ξεπερνάμε το Airbnb σε κάτι που εκείνο δεν κάνει: ο **δακτύλιος μένει κάτω από την
 * πινακίδα** — η αβεβαιότητα **φαίνεται**, δεν κρύβεται πίσω από την τιμή.
 *
 * ⚠️ **ΜΗΝ το ανεβάσεις πάνω από 1.000 χωρίς νέα μέτρηση**: η «συνοικία» (1.500 μ.) θα
 * περνούσε, δηλαδή τιμή σε θέση πέρα από ό,τι δέχεται ο ίδιος ο κλάδος.
 */
export const PLAQUE_MAX_UNCERTAINTY_M = 1000;

/**
 * `id` → `[lng, lat]`, **μόνο** για σημεία με αβεβαιότητα μέσα στο {@link PLAQUE_MAX_UNCERTAINTY_M}.
 *
 * ⚠️ Ο έλεγχος `type !== 'Point'` είναι **κανόνας, όχι μόνο στένωση τύπου**: το
 * `'outline'` ζωγραφίζεται ως `Polygon` και **δεν** έχει ένα σημείο να καθίσει πινακίδα
 * (μηδενική αβεβαιότητα, αλλά καμία άγκυρα). Άγκυρα τον εκτελεί και με παραμορφωμένο
 * feature (Κ4) — αλλιώς θα ήταν ισχυρισμός χωρίς απόδειξη.
 */
function plaqueAnchors(geoJson: ListingGeoJson): ReadonlyMap<string, readonly [number, number]> {
  const anchors = new Map<string, readonly [number, number]>();

  for (const feature of geoJson.features) {
    if (feature.properties.uncertaintyM > PLAQUE_MAX_UNCERTAINTY_M) continue;
    if (feature.geometry.type !== 'Point') continue;

    const [lng, lat] = feature.geometry.coordinates;
    anchors.set(feature.properties.id, [lng, lat]);
  }

  return anchors;
}

/**
 * **Η ΣΕΙΡΑ ΣΥΓΚΡΙΝΕΙ ΜΟΝΟ ΟΜΟΕΙΔΗ ΠΟΣΑ.**
 *
 * Ο φραγμός των 40 πρέπει να διαλέξει· το ερώτημα είναι **με ποιο δικαίωμα**.
 *
 * - ❌ **«Τα πρώτα 40 της λίστας»** — η αλλαγή ταξινόμησης της **λίστας** θα άλλαζε
 *   **ποιες πινέζες** έχουν πινακίδα, για λόγο **άσχετο με τον χάρτη**.
 * - ❌ **«Τα ακριβότερα»** — μεροληψία πολυτελείας, και μάλιστα αόρατη.
 * - ❌ **«Αύξουσα τιμή» σε ΕΝΑ άξονα** *(η εκδοχή ως 2026-09-17)* — σε χάρτη που
 *   ανακατεύει πώληση, μίσθωμα και διανυκτέρευση, το «50 €/νύχτα < 900 €/μήνα <
 *   170.000 €» **δεν είναι σύγκριση**: με πολλές αγγελίες, οι 40 θέσεις θα γέμιζαν
 *   **μόνο** με διανυκτερεύσεις και οι πωλήσεις θα έμεναν κουκίδες — για λόγο μονάδας.
 * - ✅ **Κατάταξη ΜΕΣΑ στον ρόλο, εναλλάξ ανάμεσα στους ρόλους**: η φθηνότερη πώληση,
 *   το φθηνότερο μίσθωμα και η φθηνότερη διανυκτέρευση μοιράζονται τις πρώτες θέσεις,
 *   μετά οι δεύτερες κ.ο.κ. Κάθε είδος παίρνει ίσο μερίδιο ως να εξαντληθεί, και
 *   μέσα σε κάθε είδος ισχύει η ορατή διάταξη «τιμή ↑».
 *
 * ⚠️ **Το `id` ως τελευταίο σκέλος είναι ΥΠΟΧΡΕΩΤΙΚΟ.** Χωρίς σταθερή διάλυση ισοπαλίας
 * το υποσύνολο θα μπορούσε να **αλλάζει μεταξύ αποδόσεων** με τα ίδια δεδομένα.
 */
function fairOrder(candidates: readonly ListingPriceMarker[]): readonly ListingPriceMarker[] {
  const rank = new Map<string, number>();
  const byRole = new Map<PriceRole, ListingPriceMarker[]>();

  for (const candidate of candidates) {
    const group = byRole.get(candidate.role) ?? [];
    group.push(candidate);
    byRole.set(candidate.role, group);
  }
  for (const group of byRole.values()) {
    group.sort(byAmountThenId).forEach((marker, index) => rank.set(marker.id, index));
  }

  return [...candidates].sort((a, b) =>
    (rank.get(a.id) ?? 0) - (rank.get(b.id) ?? 0)
    || PRICE_ROLE_ORDER[a.role] - PRICE_ROLE_ORDER[b.role]
    || byAmountThenId(a, b));
}

function byAmountThenId(a: ListingPriceMarker, b: ListingPriceMarker): number {
  if (a.amount !== b.amount) return a.amount - b.amount;
  return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
}
