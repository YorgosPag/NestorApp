/**
 * @fileoverview **ΠΩΣ ΔΙΑΒΑΖΟΝΤΑΙ ΟΙ ΕΙΚΟΝΕΣ ΜΙΑΣ ΑΓΓΕΛΙΑΣ** — μία φορά, για κάθε οθόνη.
 * @related ADR-841 §7 (Α2.4 · Α2.5 · Α2.6) · ADR-777 §7 (Α19 κανόνας 31)
 * @module lib/listings/listing-images
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΣΥΝΟΡΟ ΤΟΥ ΚΑΝΟΝΑ 31 ΖΕΙ ΕΔΩ, ΣΕ **ΜΙΑ** ΣΥΝΑΡΤΗΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο κανόνας 31 *(ADR-777 Α19)* λέει ότι ο **πρώτος καρές** παράγεται **από το μοντέλο**,
 * *«ποτέ από ανέβασμα χρήστη — αλλιώς μπορεί να πει ψέματα»*. Το σχήμα τον τηρεί κατά
 * γράμμα: το `coverImage` το γεμίζει **μόνο** ο ψήστης της Φ4, και μέχρι τότε είναι `null`.
 *
 * Αλλά η οθόνη πρέπει να δείξει **κάτι**. Αν η απάντηση *«ποια εικόνα μπαίνει πάνω;»*
 * γραφόταν σε **κάθε** οθόνη χωριστά *(κάρτα · σελίδα · βιτρίνα)*, θα ήταν τρεις
 * απαντήσεις ελεύθερες να αποκλίνουν — και η Φ4 θα έπρεπε να τις βρει **και τις τρεις**.
 *
 * 🔑 Γι' αυτό η προτίμηση ζει **εδώ**: `coverImage ?? gallery[0]`. Όταν η Φ4 παραγάγει
 * τον καρέ, **καμία οθόνη δεν αλλάζει γραμμή** — αλλάζει η απάντηση αυτής της συνάρτησης.
 *
 * ⚠️ **Αυτό ΔΕΝ είναι «η φωτογραφία του χρήστη έγινε εξώφυλλο».** Το **πεδίο** μένει
 * άθικτο· η οθόνη δείχνει **την πρώτη διαθέσιμη εικόνα**, και το `altKey` της λέει ρητά
 * **τίνος υλικό είναι** (Α2.5). Η διαφορά είναι ακριβώς η διαφορά ανάμεσα στο *«αυτό
 * είναι το κτίριο»* και στο *«αυτό δείχνει ο κάτοχος»*.
 *
 * 🔑 **ΚΑΙ ΤΟ «ΤΙΝΟΣ» ΔΕΝ ΑΠΑΝΤΙΕΤΑΙ ΕΔΩ** (Α15). Αυτό το module κατέχει *«ποια εικόνα
 * και με ποια παράγωγα»*· η προέλευση είναι **άλλη ερώτηση** και ζει στον έναν τόπο που
 * την κατέχει: `LISTING_MATERIAL_KEYS` *(`lib/listings/listing-authorship`)*. Μέχρι την
 * **Α14** υπήρχε **ΕΝΑΣ** παραγωγός συλλογής *(ο ιδιώτης)*, άρα μία σταθερά εδώ ήταν
 * αρκετή — και έγινε **ψευδής** τη μέρα που το γραφείο απέκτησε συλλογή.
 */

import type { ListingImage, ListingImageSource, PublicListing } from '@/types/public-listing';

/**
 * **Η πρώτη διαθέσιμη εικόνα της αγγελίας, ή `null`.**
 *
 * Ο **ένας** κριτής για κάρτα, σελίδα και βιτρίνα. Δες το σκεπτικό του module.
 */
export function listingLeadImage(listing: PublicListing): ListingImage | null {
  return listing.coverImage ?? listing.gallery[0] ?? null;
}

/**
 * **ΟΛΕΣ οι εικόνες της αγγελίας, με τη σειρά που τις βλέπει ο άνθρωπος.**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Η ΛΟΓΙΚΗ ΥΠΗΡΧΕ ΗΔΗ — ΧΕΙΡΟΓΡΑΦΗ, ΣΕ ΜΙΑ ΟΘΟΝΗ
 * ────────────────────────────────────────────────────────────────────────────
 * Το `ListingGallery` της **οθόνης 3** έγραφε
 * `listing.gallery.filter((i) => i.url !== lead.url)` **μέσα στο JSX του** — δηλαδή η
 * απάντηση στο *«ποιες είναι οι υπόλοιπες;»* ζούσε σε μία μόνο οθόνη, ενώ η αδελφή της
 * (*«ποια είναι η πρώτη;»*) είχε **ήδη** σπίτι εδώ, δύο γραμμές πιο πάνω. Το ίδιο ερώτημα,
 * μοιρασμένο σε δύο μέρη — και το δεύτερο κομμάτι ήταν αόρατο σε όποιον διάβαζε **αυτό**
 * το module για να μάθει πώς διαβάζονται οι εικόνες.
 *
 * ⇒ Η κάρτα της λίστας απέκτησε περιήγηση φωτογραφιών, δηλαδή **δεύτερος** καταναλωτής
 * ρώτησε το ίδιο. Ο κανόνας του Προσκόπου (N.0.2): η απάντηση δεν αντιγράφεται — **παίρνει
 * σπίτι**, και η οθόνη 3 γίνεται καταναλωτής της.
 *
 * ⚠️ **Η ΤΑΥΤΟΤΗΤΑ ΕΙΝΑΙ ΤΟ `url`, ΟΧΙ Η ΘΕΣΗ.** Σήμερα το `coverImage` είναι **παντού
 * `null`** *(μετρημένο στη Firestore, 9/9 αγγελίες)*, οπότε η πρώτη είναι η `gallery[0]`
 * και ένα `slice(1)` θα έδινε το ίδιο αποτέλεσμα — **σήμερα**. Όταν η Φ4 παραγάγει
 * κανονικό εξώφυλλο (κανόνας 31: *ο πρώτος καρές βγαίνει από το μοντέλο*), η πρώτη
 * **δεν** θα είναι πια η `gallery[0]`: το `slice(1)` θα έκοβε **σιωπηλά μια αληθινή
 * φωτογραφία** και θα κρατούσε το εξώφυλλο **δύο φορές**. Η σύγκριση κατά `url` απαντά
 * σωστά **και στις δύο** εποχές — και είναι ακριβώς το κριτήριο που έγραφε ήδη η οθόνη 3.
 *
 * 🔑 **Ποτέ διπλότυπο, ποτέ κενό στοιχείο**: η επιστροφή είναι ασφαλής για `key={url}` και
 * για μετρητή *«N από M»* — τα δύο πράγματα που ζητά κάθε καταναλωτής της.
 */
export function listingGalleryImages(listing: PublicListing): readonly ListingImage[] {
  const lead = listingLeadImage(listing);
  if (lead === null) return [];
  return [lead, ...listing.gallery.filter((image) => image.url !== lead.url)];
}

/**
 * **`srcset` από τα παράγωγα** — ή `undefined` όταν δεν υπάρχει τίποτα να διαλέξει.
 *
 * ⚠️ **`undefined` και όχι κενή συμβολοσειρά**: ένα `srcset=""` είναι έγκυρο HTML που
 * λέει στον περιηγητή *«δεν υπάρχει καμία υποψήφια»* — δηλαδή θα μπορούσε να ακυρώσει
 * και το `src`. Το `undefined` αφαιρεί το χαρακτηριστικό εντελώς.
 *
 * 🔑 Ένα μόνο παράγωγο ⇒ **κανένα `srcset`**: δεν υπάρχει επιλογή να κάνει ο περιηγητής,
 * και ένα `srcset` με μία γραμμή απλώς μεγαλώνει το HTML.
 */
export function listingImageSrcSet(image: ListingImage): string | undefined {
  if (image.sources.length < 2) return undefined;
  return image.sources.map((source: ListingImageSource) => `${source.url} ${source.width}w`).join(', ');
}
