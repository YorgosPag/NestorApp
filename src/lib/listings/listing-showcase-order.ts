import type { PublicListing } from '@/types/public-listing';
import { compareByNameThenId } from '@/lib/ordering/total-name-order';

/**
 * **Ντετερμινιστική, ολική σειρά για τη βιτρίνα ενός γραφείου** (ADR-841 §7 Α6).
 *
 * Επιστρέφει **νέο** πίνακα — η είσοδος έρχεται από `onSnapshot` και είναι `readonly`·
 * μια επιτόπια `sort()` θα μετέβαλλε δεδομένα που ανήκουν στη συνδρομή.
 */
export function orderShowcaseListings(
  listings: readonly PublicListing[],
): readonly PublicListing[] {
  return [...listings].sort(compareShowcaseListings);
}

/**
 * **Η ΜΙΑ σύγκριση.** Εξάγεται ώστε η άγκυρα να τη μεταλλάξει **χωρίς** πίνακα: ένας
 * συγκριτής που δοκιμάζεται μόνο μέσω `sort` κρύβει το tie-break του πίσω από τη
 * σταθερότητα του `Array#sort` — θα φαινόταν σωστός **και** αν έλειπε.
 *
 * ⚠️ **Ο τίτλος μπορεί να είναι κενός** *(`(property.name ?? '').trim()` στη μηχανή
 * προβολής)*. Δεν είναι ειδική περίπτωση εδώ: το collation βάζει τα κενά πρώτα και ο
 * τερματισμός τα διατάσσει σταθερά μεταξύ τους. Η **οθόνη** είναι που οφείλει να πει
 * ότι λείπει τίτλος — όχι η σειρά.
 */
export function compareShowcaseListings(a: PublicListing, b: PublicListing): number {
  return compareByNameThenId(a.title, a.id, b.title, b.id);
}
