/**
 * @fileoverview **Τι μπορεί να απαντήσει η οθόνη 1 σήμερα** — και τι όχι, ρητά.
 * @related ADR-777 §7 (Α3 · Α5 κανόνας 27 · Α9) · SPEC-777-RESEARCH §25.7 · §25.8
 * @module lib/listings/listing-coverage
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΠΡΟΒΛΗΜΑ ΠΟΥ ΛΥΝΕΙ, ΜΕΤΡΗΜΕΝΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το §25.7 έγραψε: *«Οθόνη 1 που ρωτά "πού στην Ελλάδα;" με 2 ακίνητα είναι υπόσχεση
 * που η βάση δεν μπορεί να τηρήσει. Ο χρήστης γράφει «Πάτρα», παίρνει μηδέν, και
 * **φεύγει για πάντα** — και το μηδέν **δεν** θα σημαίνει «δεν υπάρχει», θα σημαίνει
 * «δεν φτάσαμε ακόμα εκεί».»*
 *
 * **Μετρήθηκε ζωντανά (2026-08-10, οθόνη 2):** `6 ακίνητα · 0 στον χάρτη · 6 χωρίς
 * δηλωμένη θέση`. Δηλαδή η πραγματικότητα είναι **χειρότερη** από την υπόθεση του
 * §25.7: δεν είναι ότι έχουμε λίγες πόλεις — **δεν έχουμε καμία θέση**.
 *
 * 🔴 **Και υπάρχει δεύτερο, δομικό:** το {@link PublicListing} **δεν κουβαλά καμία
 * λέξη τόπου**. Κουβαλά `position` (σημείο + προέλευση + ακρίβεια) και `title`
 * (κείμενο του κατόχου). Άρα η φράση «η κάλυψή μας σήμερα: **Θεσσαλονίκη**» είναι
 * **ανέκφραστη** χωρίς νέο πεδίο — και ένα νέο πεδίο εκεί είναι **απόφαση
 * δημοσιοποίησης** (ο κανόνας του `types/public-listing.ts`), όχι λεπτομέρεια αυτής
 * της οθόνης.
 *
 * ⛔ **Γι' αυτό η κάλυψη ΔΕΝ εκφράζεται με ονόματα τόπων.** Εκφράζεται με το **μόνο
 * πράγμα που ξέρουμε χωρίς να επινοήσουμε τίποτα**: τη **λογιστική** — πόσα ακίνητα
 * απαντούν, και πόσα από αυτά μπορούν να απαντήσουν στο *«πού;»*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΓΙΑΤΙ ΑΥΤΟ ΞΕΠΕΡΝΑ ΤΗΝ ΠΡΑΚΤΙΚΗ ΤΗΣ ΑΓΟΡΑΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Zillow · Idealista · Spitogatos δηλώνουν κάλυψη με **χειρόγραφο κείμενο
 * μάρκετινγκ** («σε όλη την Ελλάδα»). Ένα τέτοιο κείμενο **δεν μπορεί να είναι
 * λάθος**, γιατί τίποτα δεν το συγκρίνει με τα δεδομένα — είναι η ίδια κατηγορία με
 * τις δύο λίστες namespace της CHECK 3.34 που **απέκλιναν κατά 63** χωρίς καμία πύλη
 * να τις ρωτήσει.
 *
 * Εδώ η κάλυψη **παράγεται από τη ζωντανή προσφορά**. Δεν μπορεί να αποκλίνει, γιατί
 * δεν υπάρχει δεύτερο αντίγραφο να αποκλίνει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΚΑΜΙΑ ΔΕΥΤΕΡΗ ΛΟΓΙΣΤΙΚΗ — ΚΑΙ ΑΥΤΟ ΕΙΝΑΙ ΤΟ ΚΥΡΙΟ ΣΧΕΔΙΑΣΤΙΚΟ ΟΡΙΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το {@link ListingCoverage} **περιέχει** το {@link ListingLedger} — δεν το
 * ξαναϋπολογίζει, δεν το αντιγράφει, δεν κρατά δικά του `total`/`mapped`. Ένας
 * δεύτερος μετρητής εδώ θα ήταν το σχήμα του **ADR-749** (τέσσερις μηχανές, τρεις
 * αριθμοί για το ίδιο δέντρο) γεννημένο **μέσα** στο αρχείο που το επικαλείται.
 *
 * Ομοίως το κριτήριο *«έχει θέση;»* **δεν ξαναγράφεται**: περνά από το
 * `isMappedShape(listingMapShape(...))`, την ίδια συνάρτηση που διαβάζουν ο χάρτης
 * και η λίστα της οθόνης 2. Επαληθεύτηκε ότι για **κάθε** κλάδο `known` το σχήμα
 * είναι ≠ `'none'` — άρα ένα φαινομενικά ισοδύναμο `position.kind === 'known'` θα
 * ήταν **δεύτερη απάντηση στο ίδιο ερώτημα**, σωστή σήμερα και ελεύθερη να
 * αποκλίνει αύριο.
 */

import type { PublicListing, ListingLedger } from '@/types/public-listing';
import { computeListingLedger } from '@/services/realtime/hooks/usePublicListings';

// ============================================================================
// ΟΙ ΤΡΕΙΣ ΚΑΤΑΣΤΑΣΕΙΣ — κλειστό σύνολο, fail-closed
// ============================================================================

/**
 * **Τι επιτρέπεται να υποσχεθεί η οθόνη 1.**
 *
 * 🔑 Κλειστή ένωση, με το ίδιο σκεπτικό που οι πύλες μας δηλώνουν **ρητές
 * καταστάσεις** αντί για ένα `boolean`: κάθε μία έχει **διαφορετική θεραπεία** και
 * **διαφορετικό κείμενο**, και ένα `canSearch: boolean` θα συγχώνευε δύο πραγματικά
 * διαφορετικές αποτυχίες σε μία σιωπηλή.
 *
 * | Κατάσταση | Τι ισχύει | Τι οφείλει να κάνει η οθόνη |
 * |---|---|---|
 * | `no-supply` | καμία αγγελία **καθόλου** | να μην υποσχεθεί τίποτα· **μόνο** ζήτηση (Α9) |
 * | `no-location` | υπάρχουν αγγελίες, **καμία** με θέση | να πει ότι το «πού» **δεν φιλτράρει ακόμη**, και να δώσει και τους δύο δρόμους |
 * | `partial` | υπάρχουν αγγελίες **με** θέση | το «πού» λειτουργεί — **με ρητό αριθμό** όσων θα λείπουν |
 *
 * ⚠️ **Δεν υπάρχει κατάσταση `full`, και η απουσία είναι σχεδίαση.** «Πλήρης
 * κάλυψη» θα ήταν ισχυρισμός για τον **κόσμο** («τα ξέρουμε όλα τα ακίνητα»), όχι
 * για τα δεδομένα μας — δηλαδή ακριβώς το χειρόγραφο μάρκετινγκ που το αρχείο
 * αρνείται. Ακόμη και με 100% θέσεις, η σωστή δήλωση παραμένει «τόσα ξέρουμε».
 */
export type CoverageState = 'no-supply' | 'no-location' | 'partial';

/**
 * **Η κάλυψη ως τιμή** — η λογιστική, συν την ετυμηγορία πάνω της.
 *
 * ⚠️ Το `state` **δεν** είναι ανεξάρτητο δεδομένο: παράγεται **ντετερμινιστικά** από
 * το `ledger` μέσω του {@link coverageStateOf}. Είναι αποθηκευμένο ως πεδίο μόνο
 * ώστε ο καταναλωτής να μη χρειάζεται να το ξαναρωτήσει — **ποτέ** ώστε να μπορεί
 * να τεθεί ανεξάρτητα. Η άγκυρα `coverageStateOf(c.ledger) === c.state` το κλειδώνει.
 */
export interface ListingCoverage {
  /** Η **υπάρχουσα** κλειστή λογιστική (κανόνας 27). Ποτέ ξαναϋπολογισμένη εδώ. */
  readonly ledger: ListingLedger;
  /** Τι επιτρέπεται να υποσχεθεί η οθόνη, δεδομένης αυτής της λογιστικής. */
  readonly state: CoverageState;
}

// ============================================================================
// Η ΚΡΙΣΗ
// ============================================================================

/**
 * Λογιστική → κατάσταση κάλυψης. **Καθαρή, εξαντλητική, χωρίς προεπιλογή.**
 *
 * 🔑 Η σειρά των ελέγχων **είναι** συμβόλαιο: «καμία προσφορά» κρίνεται **πριν**
 * ρωτηθεί αν υπάρχει θέση. Χωρίς αυτή τη σειρά, μια άδεια βάση (`total = 0`) θα
 * περνούσε ως `no-location` και η οθόνη θα έλεγε *«καμία δεν έχει δηλωμένη θέση»* —
 * αληθές αριθμητικά, **παραπλανητικό** στην ουσία: το πρόβλημα δεν είναι η θέση,
 * είναι ότι δεν υπάρχει τίποτα.
 */
export function coverageStateOf(ledger: ListingLedger): CoverageState {
  if (ledger.total === 0) return 'no-supply';
  if (ledger.mapped === 0) return 'no-location';
  return 'partial';
}

/**
 * Αγγελίες → κάλυψη.
 *
 * ⚠️ Η λογιστική έρχεται από το {@link computeListingLedger}, το **ίδιο** που
 * τροφοδοτεί τη μπάρα της οθόνης 2. Οι δύο οθόνες **δεν μπορούν** να δώσουν
 * διαφορετικό αριθμό, γιατί δεν υπάρχουν δύο αριθμοί.
 */
export function computeListingCoverage(listings: readonly PublicListing[]): ListingCoverage {
  const ledger = computeListingLedger(listings);
  return { ledger, state: coverageStateOf(ledger) };
}

/**
 * Έχει νόημα να φιλτράρει ο επισκέπτης **γεωγραφικά**;
 *
 * 🔴 **Υπάρχει για να επιτρέψει στην οθόνη να ΜΗΝ υποσχεθεί** — όχι για να κρύψει
 * το κουτί. Η Α3 δεσμεύτηκε ότι η οθόνη 1 ζητά **ένα** πράγμα· ένα κουτί που
 * εξαφανίζεται όταν η βάση είναι αδύναμη θα ήταν **δεύτερη διάταξη** για την ίδια
 * οθόνη, και ο επισκέπτης δεν θα μάθαινε ποτέ γιατί.
 */
export function coverageAnswersWhere(coverage: ListingCoverage): boolean {
  return coverage.state === 'partial';
}
