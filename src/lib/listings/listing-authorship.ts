/**
 * @fileoverview **Η ΥΠΟΓΡΑΦΗ ΤΗΣ ΑΓΓΕΛΙΑΣ ΩΣ ΜΙΑ ΑΠΟΦΑΣΗ** — *«ποιος τη δηλώνει;»*,
 * απαντημένο σε **ένα** σημείο για **δύο** οθόνες (ADR-841 Α13.2).
 * @related ADR-841 §7 Α13 · §7 Α1.5 (ΔΕΕ C-146/16) · types/public-listing (§8.33)
 * @module lib/listings/listing-authorship
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ — Η ΔΕΥΤΕΡΗ ΑΛΗΘΕΙΑ ΠΟΥ ΔΕΝ ΕΓΙΝΕ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Μέχρι το **Ο-9** η υπογραφή ζωγραφιζόταν σε **ένα** αρχείο *(`ListingCard.tsx`)*, και
 * η προφανής κίνηση ήταν να αντιγραφεί ο τριαδικός στη σελίδα λεπτομέρειας. Δεν είναι
 * μία συμβολοσειρά — είναι **τριπλός κλάδος** *(κλάση → επωνυμία → όνομα)*, δηλαδή
 * **λογική**.
 *
 * 🔑 **Και η αντιγραφή λογικής είναι χειρότερη από την αντιγραφή κειμένου**: τα διπλά
 * κλειδιά τα φρουρεί το **CHECK 3.8**· τον διπλό κλάδο **τίποτα**. Δύο οθόνες θα
 * μπορούσαν να διαφωνήσουν για το *ποιος δημοσίευσε* — και η μία από τις δύο είναι
 * **νομική υποχρέωση** *(Α1.5)*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΤΡΕΙΣ ΦΩΝΕΣ, ΟΧΙ ΔΥΟ — ΚΑΙ ΔΕΝ ΣΥΜΠΤΥΣΣΟΝΤΑΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `LISTING_AUTHORSHIPS` έχει **δύο** τιμές (`'agency'` · `'owner-declared'`), αλλά η
 * οθόνη έχει **τρεις** καταστάσεις: το *«γραφείο με επωνυμία»* και το *«γραφείο **χωρίς**
 * επωνυμία»* είναι διαφορετικές προτάσεις, και ένα κενό *«Από γραφείο: »* θα διαβαζόταν
 * ως **σπασμένη οθόνη**. Η τρίτη φωνή δεν είναι δικό μας κενό: είναι εταιρεία που **δεν
 * έχει δηλώσει** επωνυμία, ή ανάγνωση που **απέτυχε**. Η οθόνη **δεν αναπληρώνει** — το
 * λέει.
 */

import type { ListingAuthorship, PublicListing } from '@/types/public-listing';

/**
 * **Η φωνή της αγγελίας** — μία τιμή ανά *πρόταση που λέει η οθόνη*, όχι ανά πεδίο.
 *
 * ⚠️ **ΔΕΝ είναι το {@link ListingAuthorship} με άλλο όνομα.** Εκείνο είναι **κλάση
 * γνώσης** και ζει στο **σχήμα** *(δημοσιεύεται, ταξιδεύει, ελέγχεται από τους κανόνες)*·
 * αυτό είναι **επιλογή διατύπωσης** και ζει στην **οθόνη**. Η μία τιμή του σχήματος
 * (`'agency'`) γεννά **δύο** διατυπώσεις — γι' αυτό ένας τύπος δεν αρκεί για δύο
 * ερωτήσεις.
 */
export type ListingAuthorshipVoice = 'owner-declared' | 'agency-named' | 'agency-anonymous';

/**
 * **Η μοναδική απόφαση**: ποια από τις τρεις προτάσεις λέει αυτή η αγγελία.
 *
 * 🔑 **`Pick`, όχι ολόκληρο `PublicListing`, και είναι απόφαση**: η ερώτηση αφορά **δύο**
 * πεδία. Με ολόκληρο τον τύπο, κάθε δοκιμή θα ζητούσε πλήρες αντικείμενο 15 πεδίων για
 * να ρωτήσει κάτι που εξαρτάται από δύο — και τα fixture που **μεγαλώνουν χωρίς λόγο**
 * είναι ακριβώς αυτά που **παύουν να ενημερώνονται** *(μάθημα Α2.10: το fixture είχε το
 * πεδίο, τα ζωντανά έγγραφα όχι)*.
 *
 * 🔴 **`switch` ΧΩΡΙΣ `default`, ΕΠΙΤΗΔΕΣ.** Τρίτη τιμή στο `LISTING_AUTHORSHIPS`
 * **σπάει τη μεταγλώττιση εδώ** *(ο τύπος επιστροφής δεν καλύπτεται)* αντί να πέσει
 * σιωπηλά σε έναν κλάδο-μπαλαντέρ. Ίδιο ιδίωμα με το `coverageKey` του
 * `CoverageStatement.tsx`, και είναι ο λόγος που το πρόθεμα εκεί είναι ασφαλές.
 *
 * ⚠️ **Ο έλεγχος είναι `=== null` και ΔΕΝ γίνεται `trim()`.** Το *«τι μετράει ως
 * επωνυμία»* το απαντά **ένας** κανονικοποιητής — ο `companyPublicNameOf()`
 * *(`services/company/company-public-name.reader.ts`)*, που ήδη γυρίζει `null` για κενό
 * ή μόνο-κενά. Δεύτερος έλεγχος εδώ θα ήταν **δεύτερη αλήθεια για το ίδιο ερώτημα**, και
 * θα αποκλίνει τη μέρα που ο πρώτος αλλάξει.
 */
export function listingAuthorshipVoice(
  listing: Pick<PublicListing, 'authorship' | 'agencyName'>,
): ListingAuthorshipVoice {
  switch (listing.authorship) {
    case 'owner-declared':
      return 'owner-declared';
    case 'agency':
      return listing.agencyName === null ? 'agency-anonymous' : 'agency-named';
  }
}

/**
 * **Τα τρία κλειδιά, ονομαστικά** — ώστε η άγκυρα να μπορεί να ρωτήσει *«υπάρχουν και
 * τα τρία στα locale;»* με τον **πλήρη** παρονομαστή.
 *
 * ⛔ **ΔΕΝ διαβάζεται από την οθόνη**, και δεν είναι αντίφαση: η οθόνη γράφει τα κλειδιά
 * **κυριολεκτικά** επειδή ο γεννήτορας του **CHECK 3.34** αρνείται να εκπέμψει σε
 * δυναμικό `t()`. Αυτός ο πίνακας είναι **δεύτερη φωνή** *(ADR-587 §6.1)*: αν η οθόνη
 * και ο πίνακας αποκλίνουν, η άγκυρα το βλέπει — πράγμα που **δεν** θα μπορούσε αν η
 * οθόνη διάβαζε από εδώ.
 */
export const LISTING_AUTHORSHIP_KEYS: Readonly<Record<ListingAuthorshipVoice, string>> = {
  'owner-declared': 'listing.authorship.ownerDeclared',
  'agency-anonymous': 'listing.authorship.agencyAnonymous',
  'agency-named': 'listing.authorship.agency',
} as const;

/**
 * **Τα κλειδιά που λένε ΤΙΝΟΣ ΥΛΙΚΟ είναι μια φωτογραφία** — για το `alt` κάθε εικόνας
 * και για την ορατή σημείωση κάτω από τη συλλογή (ADR-841 Α15).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ Ο ΠΑΡΟΝΟΜΑΣΤΗΣ ΕΙΝΑΙ ΤΟ `ListingAuthorship` ΚΑΙ **ΟΧΙ** ΤΟ `…Voice`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το {@link ListingAuthorshipVoice} έχει τρεις τιμές επειδή η **υπογραφή** άλλοτε
 * **ονομάζει** το γραφείο κι άλλοτε όχι. Αυτές οι δύο προτάσεις **δεν ονομάζουν κανέναν**
 * — λένε *είδος* προέλευσης. Δρομολόγηση μέσω `Voice` θα εισήγαγε **ψεύτικη εξάρτηση από
 * το `agencyName`** *(πεδίο που εδώ δεν χρησιμοποιείται)* και **αυθαίρετη σύμπτυξη 3→2**
 * που θα έπρεπε να ξανα-δικαιολογηθεί κάθε φορά που το `Voice` μεγαλώνει.
 *
 * 🔑 **ΕΝΑ αντικείμενο με ΔΥΟ πεδία, ΟΧΙ δύο συναρτήσεις με δύο `switch`.** Ο φυσικός
 * δρόμος ήταν ένας εξαντλητικός κλάδος ανά κλειδί — **δομικά δίδυμα πάνω στο ίδιο union**,
 * ακριβώς η κλάση του **N.18**, και αυτοπροκαλούμενα. Εδώ η εξαντλητικότητα δεν χρειάζεται
 * κλάδο καθόλου: το `Record<ListingAuthorship, …>` **δεν τυπώνεται** αν προστεθεί τρίτη
 * κλάση στο `LISTING_AUTHORSHIPS`.
 *
 * ⚠️ **ΔΕΝ είναι δίδυμο του {@link LISTING_AUTHORSHIP_KEYS}, παρότι μοιάζουν.** Εκείνο
 * είναι **δεύτερη φωνή** *(καμία οθόνη δεν το διαβάζει· ελέγχει τα κυριολεκτικά κλειδιά
 * της `ListingAuthorshipLine`)*· αυτό είναι **παραγωγός** — ο γραφέας της προβολής το
 * διαβάζει και γράφει το `galleryAlt` **μέσα στο δημοσιευμένο έγγραφο**. Γι' αυτό, και
 * μόνο γι' αυτό, τα κλειδιά εδώ φέρουν **πρόθεμα namespace**: ταξιδεύουν ως τιμές και
 * καταλήγουν αυτούσια σε `t()`.
 *
 * ⛔ **ΚΑΙ ΔΕΝ ΣΥΝΘΕΤΟΝΤΑΙ ΜΕ ΣΥΝΕΝΩΣΗ** *(`` `…galleryAlt.${authorship}` ``)*, παρότι τα
 * φύλλα ονομάζονται **ακριβώς** όπως οι τιμές του σχήματος: ένα πρόθεμα δεν είναι
 * συμβόλαιο. Η ομοιότητα είναι ιδιότητα που **ελέγχει η άγκυρα**, όχι μηχανισμός που την
 * **προϋποθέτει**.
 */
export interface ListingMaterialKeys {
  /**
   * Το `alt` **κάθε** φωτογραφίας της συλλογής — σελίδα **και** κάρτα.
   *
   * 🔴 **ΟΧΙ `alt=""`**: το WCAG 1.1.1 ρωτά *«αν η εικόνα εξαφανιζόταν, τι θα έχανε ο
   * βλέπων;»*, και για φωτογραφία ακινήτου η απάντηση **δεν** είναι «τίποτα». Και **δεν
   * μαντεύει περιεχόμενο**: κανείς δεν έχει δει αυτή τη φωτογραφία — λέει **θέση +
   * προέλευση**, ό,τι πραγματικά ξέρουμε *(Α2.5)*.
   *
   * ⚠️ Οι παράμετροι `{index}`/`{total}` **δεν αποθηκεύονται**: είναι ιδιότητα της θέσης
   * στον πίνακα και τις δίνει η οθόνη τη στιγμή της απόδοσης. Αποθηκευμένες θα ήταν
   * δεύτερη αλήθεια που παλιώνει με την πρώτη αναδιάταξη.
   */
  readonly galleryAlt: string;
  /**
   * Η **ορατή** σημείωση κάτω από τη συλλογή — τη διαβάζει κάθε επισκέπτης.
   *
   * 🔑 Λέγεται `sourceNote` και **όχι** `ownerNote`: το παλιό όνομα **δήλωνε** ότι η
   * σημείωση ανήκει στον ιδιώτη, δηλαδή το ίδιο το λεξιλόγιο ξαναγεννούσε το λάθος που
   * η Α15 διόρθωσε.
   */
  readonly sourceNote: string;
}

