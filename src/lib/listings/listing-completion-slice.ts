/**
 * @fileoverview **Η ΔΗΜΟΣΙΑ ΑΓΓΕΛΙΑ → Η ΓΛΩΣΣΑ ΤΗΣ ΜΗΧΑΝΗΣ ΠΛΗΡΟΤΗΤΑΣ** (ADR-842 Φ5).
 * @related ADR-842 §5 (Α5) · §7 (Φ5) · §8 #1 · #2 · #3 · #7 · ADR-287 (η μηχανή)
 * @module lib/listings/listing-completion-slice
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΑΥΤΟ ΕΙΝΑΙ **ΜΕΤΑΦΡΑΣΤΗΣ**, ΟΧΙ ΜΗΧΑΝΗ — ΚΑΙ Η ΔΙΑΦΟΡΑ ΕΙΝΑΙ ΟΛΟ ΤΟ Α5
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ADR-842 **Α5** λέει: *«Καμία δεύτερη μηχανή πληρότητας… Ο ιδιώτης αποκτά
 * **adapter**, όχι μηχανή.»* Η μηχανή είναι το `constants/property-completion.ts`
 * (ADR-287): καθαρή, ντετερμινιστική, με βάρη ανά τύπο και buckets. Εδώ **δεν
 * υπολογίζεται τίποτα** — μόνο μεταφράζεται.
 *
 * 🔑 **Και το σχέδιο του ADR έλεγε άλλο πράγμα, που η μέτρηση ανέτρεψε.** Το §7
 * υποσχόταν *«Adapter `OwnerProperty` → `CompletionFormSlice`»*. Ο `OwnerProperty` έχει
 * **8** πεδία· μετά τη Φ3 το `PublicListing` έχει **27**, και **και οι δύο** οικογένειες
 * περνούν ήδη από **μία** προβολή. Μετρήθηκε (2026-09-02) ότι από τα **17**
 * `FIELD_KEYS` της μηχανής:
 *
 * | | Πλήθος | Ποια |
 * |---|---|---|
 * | ταυτόσημο όνομα στο `PublicListing` | **13** | `type` `bedrooms` `bathrooms` `orientations` `condition` `energyClass` `heatingType` `coolingType` `windowFrames` `glazing` `flooring` `interiorFeatures` `securityFeatures` |
 * | μετονομασία | **3** | `areaGross`→`areaSqm` · `areaNet`→`netAreaSqm` · `photos`→`gallery.length` |
 * | **δεν υπάρχει** | **1** | `floorplan` — δες §3 παρακάτω |
 *
 * ⇒ Ο μεταφραστής είναι **σχεδόν ταυτοτικός**, και η είσοδος είναι η **δημόσια
 * αγγελία** — που καλύπτει **και** τον ιδιώτη **και** την εταιρεία, με μία γραφή.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ §1 — ΤΙ **ΔΕΝ** ΚΑΝΕΙ: ΔΕΝ ΞΑΝΑΕΡΜΗΝΕΥΕΙ. ΚΑΙ ΕΙΝΑΙ Η ΔΥΣΚΟΛΗ ΑΠΟΦΑΣΗ.
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η Φ3 έδωσε στα σύνολα **τρεις** καταστάσεις: `null` = κανείς δεν ρώτησε · `[]` = ο
 * κάτοχος **απάντησε «καμία»** · `[…]` = οι τιμές. Η μηχανή του ADR-287 ξέρει **δύο**:
 * το `isArrayComplete` ρωτά `length > 0`, το `isPositiveNumber` ρωτά `> 0`. Άρα:
 *
 * | Δεδομένο | Η **λογιστική** της Φ3 | Η **βαθμολογία** του ADR-287 |
 * |---|---|---|
 * | `securityFeatures: []` | δηλωμένο ✅ | λείπει ❌ |
 * | `wc: 0` · `balconies: 0` · `bedrooms: 0` | δηλωμένο ✅ | λείπει ❌ |
 *
 * 🔴 **Ο ΠΕΙΡΑΣΜΟΣ ΗΤΑΝ ΝΑ ΤΟ «ΔΙΟΡΘΩΣΩ» ΕΔΩ, ΚΑΙ ΑΠΟΡΡΙΦΘΗΚΕ.** Η μονογραμμή λύση
 * ήταν να στέλνει ο μεταφραστής έναν **δείκτη-φάντασμα** για το `[]` (μη κενός πίνακας
 * που η μηχανή μετρά ως πλήρη, και του οποίου τα μέλη δεν διαβάζει ποτέ κανείς). Τρεις
 * λόγοι που δεν έγινε:
 *
 * 1. **Θα ήταν δεύτερη σημασιολογία πληρότητας, μπασμένη από την πίσω πόρτα** — δηλαδή
 *    ακριβώς το Α5, παραβιασμένο μέσω της **εισόδου** αντί μέσω νέου αρχείου.
 * 2. **Δεν γενικεύεται**: για το `wc: 0` **δεν υπάρχει** τίμιος δείκτης — κάθε αριθμός
 *    που θα έστελνα θα ήταν **ψέμα για την τιμή**. Θεραπεία που λύνει τη μισή κλάση
 *    είναι χειρότερη από καμία: αφήνει την άλλη μισή **αόρατη**.
 * 3. **Η ρίζα δεν είναι εδώ.** Είναι ότι το `isArrayComplete`/`isPositiveNumber`
 *    συγχέουν το *«απάντησε: καμία»* με το *«δεν ρωτήθηκε»* — και το κάνουν **εξίσου
 *    για την εταιρική διαδρομή**, από το ADR-287 και πριν από τη Φ5.
 *
 * ⚠️ **Και η προφανής διόρθωση στη μηχανή είναι ΕΠΙΚΙΝΔΥΝΗ, μετρημένα**: ένα
 * `isArrayComplete([]) === true` θα μετρούσε ως **πλήρες** κάθε **άθικτο** multi-select
 * της εταιρικής φόρμας, που αρχικοποιείται σε `[]`. Δηλαδή θα φούσκωνε το ποσοστό
 * **κάθε** ακινήτου της εταιρείας, αναδρομικά. ⇒ **Ξεχωριστή απόφαση με δικό της ADR**,
 * καταγεγραμμένη στο `.claude-rules/pending-ratchet-work.md` (N.0.2). Η λογιστική της
 * Φ3 μένει **άθικτη**: αυτό το αρχείο δεν την αγγίζει.
 *
 * 🔑 **Και οι δύο αριθμοί είναι σωστοί, γιατί απαντούν ΔΙΑΦΟΡΕΤΙΚΑ ΕΡΩΤΗΜΑΤΑ**: η
 * λογιστική λέει στον **αγοραστή** *«πόσα στοιχεία έχουν απάντηση»*· ο δείκτης λέει
 * στον **κάτοχο** *«πόσο εμπορεύσιμη είναι η αγγελία σου»*. Η διαφορά τους δηλώνεται
 * εδώ αντί να κρυφτεί — δες ADR-842 §7.5.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ §2 — Η ΚΑΤΟΨΗ ΕΙΝΑΙ ΠΑΝΤΑ ΜΗΔΕΝ, ΚΑΙ ΤΟ ΤΑΒΑΝΙ ΜΕΤΡΗΘΗΚΕ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `ListingImage` έχει `url` · `width` · `height` · `altKey` · `sources` — **κανένα
 * είδος**. Δηλαδή η δημόσια αγγελία **δεν μπορεί να ξεχωρίσει φωτογραφία από κάτοψη**,
 * που είναι το ανοιχτό θέμα **§8 #2**. Ο τίμιος αριθμός είναι **`0`**, όχι εικασία.
 *
 * 📐 **Και το κόστος είναι φραγμένο, μετρημένο**: η κάτοψη έχει βάρος **2**. Ο μέγιστος
 * εφικτός βαθμός γίνεται `21/23 = 91%` για διαμέρισμα και `7/9 = 78%` για αποθήκη —
 * **και τα δύο πάνω από το κατώφλι του πράσινου (71%)**. Άρα ο δείκτης παραμένει
 * **κερδίσιμος** χωρίς κάτοψη: δεν υπόσχεται κάτι που δεν υπάρχει, και δεν κλειδώνει
 * κανέναν έξω. *(Αν δεν ίσχυε αυτό, η σωστή κίνηση θα ήταν εξαίρεση — όχι σιωπή.)*
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 §3 — ΤΟ ΕΙΔΟΣ ΠΕΡΝΑ ΑΠΟ ΤΗΝ ΑΥΘΕΝΤΙΑ, ΚΑΙ ΕΙΝΑΙ ΤΟ ΑΝΟΙΧΤΟ ΘΕΜΑ §8 #3
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `PublicListing.type` είναι `PropertyType` — **υπερσύνολο** του κανονικού, με
 * παλαιές ελληνικές τιμές Firestore και `@deprecated` παραλλαγές. Δύο ερωτήματα, **μία**
 * αυθεντία (`normalizePropertyType`):
 *
 * 1. *«Μετράει το ίδιο το είδος ως δηλωμένο;»* — **μόνο αν είναι ονομάσιμο**. Ίδιο
 *    κριτήριο με το `isAttributeDeclared`: ένα είδος χωρίς ετικέτα δεν είναι γνώση.
 * 2. *«Ποιον πίνακα βαρών διαλέγει η μηχανή;»* — τον **κανονικό**.
 *
 * 🔴 **Χωρίς αυτό, ένα `'Αποθήκη'` βαθμολογούνταν με τον πίνακα του διαμερίσματος**:
 * παρονομαστής **23,0** αντί για **9,0** (+156%), με τα υπνοδωμάτια να ζητούνται ως
 * **κρίσιμα** από μια αποθήκη. Μετρήθηκε επίσης ότι σήμερα **κανένα** από τα 8 ζωντανά
 * έγγραφα δεν έχει μη κανονικό είδος — άρα το §8 #3 ήταν **λανθάνον, όχι ενεργό**, και
 * η θεραπεία αλλάζει **μηδέν** σημερινές βαθμολογίες.
 */

import {
  type AssessPropertyCompletionArgs,
  type CompletionFormSlice,
  type CompletionMediaCounts,
} from '@/constants/property-completion';
import { normalizePropertyType } from '@/constants/property-type-aliases';
import { operationalStatusForListing } from '@/lib/property/property-completion-stance';
import type { PublicListing } from '@/types/public-listing';

// ============================================================================
// ΟΙ ΜΙΚΡΟΙ ΜΕΤΑΤΡΟΠΕΙΣ — «κανείς δεν ρώτησε» στη γλώσσα της μηχανής
// ============================================================================

/**
 * `null` → `undefined`.
 *
 * ⚠️ **Δεν είναι καλλωπισμός τύπων.** Το σχήμα της αγγελίας λέει *«δεν δηλώθηκε»* με
 * `null`· η μηχανή του ADR-287 το λέει με **απουσία πεδίου**. Δύο λεξιλόγια για την
 * ίδια απουσία, και η μετάφραση γίνεται **εδώ, μία φορά** — αντί για `?? undefined`
 * σκορπισμένο σε δεκαέξι σημεία, όπου το δέκατο έβδομο θα ξεχνιόταν.
 */
function absent<T>(value: T | null): T | undefined {
  return value === null ? undefined : value;
}

/**
 * Ο **αριθμός επιπέδων** για τη βαθμολόγηση της κάτοψης.
 *
 * 🔑 **Το `?? 1` είναι απόφαση ΤΟΥ ΔΕΙΚΤΗ, όχι του σχήματος**: στο `PublicListing` το
 * `null` σημαίνει *«κανείς δεν ξέρει»* και **μένει** έτσι. Εδώ, «δεν ξέρω πόσα
 * επίπεδα» πρέπει να γίνει αριθμός για να υπάρξει παρονομαστής, και το **1** είναι η
 * συντηρητική επιλογή: ζητά **μία** κάτοψη, δηλαδή δεν χρεώνει τον κάτοχο για
 * επίπεδα που δεν ξέρουμε αν υπάρχουν. Ίδια προεπιλογή με τη μηχανή (`levelCount = 1`).
 *
 * 🔴 **ΚΑΙ ΕΔΩ ΚΛΕΙΝΕΙ ΤΟ §8 #7**: πριν τη Φ5 η μεζονέτα του `prop_2d612992` έδινε
 * `levels: null` → `1` → **μία** κάτοψη για **δύο** ορόφους, δηλαδή
 * `computeFloorplanScore(1, 1) = 1,0` αντί για `0,5`. Ένας **ολόκληρος βαθμός** που
 * δεν δικαιούταν, και coaching που **ποτέ** δεν ζητούσε την κάτοψη του δεύτερου
 * ορόφου. Τώρα ο γραφέας παράγει το `2` από τη δομή, με προέλευση `measured`.
 *
 * ⚠️ **Ο έλεγχος `>= 1` δεν είναι διακοσμητικός**: ένα `0` ή αρνητικό θα έκανε το
 * `count / levelCount` της μηχανής **άπειρο ή αρνητικό**, δηλαδή θα μόλυνε το ποσοστό.
 */
function levelCountOf(listing: PublicListing): number {
  const value = listing.levels?.value;
  return typeof value === 'number' && Number.isFinite(value) && value >= 1 ? value : 1;
}

// ============================================================================
// Ο ΜΕΤΑΦΡΑΣΤΗΣ
// ============================================================================

/**
 * Η **φέτα φόρμας** που περιμένει η μηχανή. Καθαρή συνάρτηση.
 *
 * ⚠️ **Δεκαέξι πεδία, καμία κρίση** — δες τη διάταξη του §1 της κεφαλίδας. Η μόνη
 * γραμμή με κρίση είναι το `type`, και ρωτά **υπάρχουσα** αυθεντία.
 */
function completionFormSlice(listing: PublicListing): CompletionFormSlice {
  return {
    // §3 — ονομάσιμο ή τίποτα. Το `''` κάνει τη μηχανή να πει «λείπει το είδος»,
    // που είναι **η ίδια απάντηση** με τη λογιστική της Φ3.
    type: normalizePropertyType(listing.type) ?? '',
    // §8 #1 — η απόφαση, όχι σιωπή. Δες `property-completion-stance.ts`.
    operationalStatus: operationalStatusForListing(listing.commercialStatus),

    areaGross: absent(listing.areaSqm),
    areaNet: absent(listing.netAreaSqm),
    bedrooms: absent(listing.bedrooms),
    bathrooms: absent(listing.bathrooms),

    orientations: absent(listing.orientations),
    condition: absent(listing.condition),
    energyClass: absent(listing.energyClass),
    heatingType: absent(listing.heatingType),
    coolingType: absent(listing.coolingType),
    windowFrames: absent(listing.windowFrames),
    glazing: absent(listing.glazing),
    flooring: absent(listing.flooring),
    interiorFeatures: absent(listing.interiorFeatures),
    securityFeatures: absent(listing.securityFeatures),
  };
}

/**
 * Τα **μέσα**, όπως τα ξέρει η δημόσια αγγελία.
 *
 * ⛔ **`floorplan: 0` ΠΑΝΤΑ** — δες §2 της κεφαλίδας. Δεν είναι παράλειψη: είναι το
 * ανοιχτό θέμα **§8 #2** (το `ListingImage` δεν έχει είδος), δηλωμένο αντί να
 * μαντευτεί, με μετρημένο ταβάνι που αφήνει το πράσινο εφικτό.
 */
function completionMediaCounts(listing: PublicListing): CompletionMediaCounts {
  return { photos: listing.gallery.length, floorplan: 0 };
}

/**
 * **Η δημόσια αγγελία, στη γλώσσα της μηχανής πληρότητας του ADR-287.**
 *
 * Το αποτέλεσμα δίνεται **αυτούσιο** στο `assessPropertyCompleteness`. Καθαρή
 * συνάρτηση: ίδια είσοδος ⇒ ίδια έξοδος, κανένα ρολόι, κανένα I/O.
 *
 * 🔑 **Δεν καλεί η ίδια τη μηχανή, επίτηδες.** Η σύνθεση *«μετάφρασε **και**
 * βαθμολόγησε»* θα έκανε αδύνατο να ελεγχθεί η μετάφραση χωρίς να ελεγχθεί και η
 * βαθμολόγηση — και θα έκρυβε ποιο από τα δύο έσπασε.
 */
export function listingCompletionArgs(listing: PublicListing): AssessPropertyCompletionArgs {
  return {
    formData: completionFormSlice(listing),
    mediaCounts: completionMediaCounts(listing),
    levelCount: levelCountOf(listing),
  };
}
