/**
 * 🏆 **ΠΟΙΟΣ ΥΠΟΓΡΑΦΕΙ ΤΗ ΜΕΛΕΤΗ** (ADR-841 §7 Α10 · απόφαση **Ε-3** του ADR-845).
 *
 * 🔑 **ΔΗΛΩΜΕΝΟΣ, ΟΧΙ ΕΠΑΛΗΘΕΥΜΕΝΟΣ — και η διάκριση είναι ολόκληρη η απόφαση.** Ο Ε-3
 * ξεμπλόκαρε τη φάση ακριβώς επειδή **δεν** περιμένει τα μητρώα *(Φ6)*: ο κάτοχος
 * **δηλώνει** τον μηχανικό, και η δήλωση ψήνεται στο artifact.
 *
 * ⛔ **ΚΑΙ Η ΥΠΟΔΟΧΗ ΓΙΑ ΕΠΑΛΗΘΕΥΣΗ ΜΕΝΕΙ ΑΝΟΙΧΤΗ, ΡΗΤΑ**: μια **δηλωμένη** υπογραφή
 * **δεν επιτρέπεται να μοιάζει επαληθευμένη** — αλλιώς η **Α9** γίνεται διακοσμητική.
 * Γι' αυτό **δεν** υπάρχει εδώ πεδίο `verified`: ένα `false` που κανείς δεν μπορεί να
 * κάνει `true` είναι υπόσχεση χωρίς μηχανισμό, και η Φ4.1 απέρριψε γραπτώς ακριβώς αυτό.
 * Η επαλήθευση θα έρθει ως **ξεχωριστή** δήλωση, από μηχανή που θα υπάρχει.
 */
export interface ModelSignatory {
  /** Το όνομα όπως το **δήλωσε άνθρωπος**. Κενό ⇒ δεν υπάρχει υπογράφων (άγκυρα Α-4). */
  readonly name: string;
  /** Ειδικότητα — *«αρχιτέκτονας»*, *«πολιτικός μηχανικός»*. Δηλωμένη, όπως το όνομα. */
  readonly discipline: string;
  /** Η ημερομηνία **της μελέτης**, όχι της δημοσίευσης. ISO 8601. */
  readonly studiedAt: string;
}

