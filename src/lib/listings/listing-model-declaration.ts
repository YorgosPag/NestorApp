/**
 * **Τα μεγέθη που δηλώνονται και ξαναμετριούνται** (§6.2.1).
 *
 * ⚠️ **ΤΟ ΟΡΙΑΚΟ ΚΟΥΤΙ ΔΕΝ ΕΙΝΑΙ ΞΕΧΩΡΙΣΤΟ ΠΕΔΙΟ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ.** Ζει **μέσα** στο
 * {@link fingerprint} *(`signature.sizeM`)*. Ένα δεύτερο πεδίο εδώ θα ήταν **δύο αριθμοί
 * για το ίδιο πράγμα**, ελεύθεροι να διαφωνήσουν — δηλαδή ακριβώς το σχήμα που η ίδια η
 * λογιστική υπάρχει για να καταγγέλλει, αυτοπροκαλούμενο.
 */
export interface ModelGeometryLedger {
  /** Πλήθος πλεγμάτων. Ένα THREE mesh → ένα glTF mesh. */
  readonly meshCount: number;
  /** Πλήθος τριγώνων, αθροιστικά. */
  readonly triangleCount: number;
  /** Πλήθος **διακριτών** υλικών. */
  readonly materialCount: number;
  /** Πλήθος **διακριτών** υφών. Μηδέν είναι νόμιμη απάντηση *(επίπεδα χρώματα)*. */
  readonly textureCount: number;
  /**
   * Το αποτύπωμα σχήματος — **ο κριτής, όχι ο αριθμός**. `null` όταν δεν υπάρχει
   * αξιοποιήσιμη γεωμετρία· ο {@link compareModelLedger} το θεωρεί **διαφωνία**
   * *(fail-closed: «δεν ξέρω» δεν σημαίνει ποτέ «ίδιο»)*.
   */
  readonly fingerprint: GeometryFingerprint | null;
}

/**
 * **Ό,τι ταξιδεύει δίπλα στα bytes** — η δήλωση του πελάτη, ολόκληρη.
 *
 * 🔑 **Τρία πράγματα, τρεις άγκυρες**: {@link state} → **Α-3**, {@link signatory} → **Α-4**,
 * {@link geometry} → **Α-6**. Κανένα δεν είναι προαιρετικό, και κανένα δεν έχει προεπιλογή:
 * μια προεπιλογή εδώ θα σήμαινε ότι ο πρώτος που θα ξεχάσει να απαντήσει **δημοσιεύει**.
 */
export interface ModelPublicationDeclaration {
  readonly state: ModelStateMark;
  readonly signatory: ModelSignatory;
  readonly geometry: ModelGeometryLedger;
}

/**
 * **Η ετυμηγορία** — και **ονομάζει** τη διαφωνία.
 *
 * 🔑 Ο λόγος που δεν είναι `boolean`: το **ADR-844 §1** διόρθωσε ακριβώς αυτή τη βλάβη σε
 * άλλο πεδίο — ο άνθρωπος πρέπει να μαθαίνει *«το αρχείο άλλαξε στη μεταφορά»*, όχι
 * *«κάτι πήγε στραβά»*. Ένα `false` δεν μπορεί να γίνει μήνυμα.
 */
export type ModelLedgerVerdict =
  | { readonly agrees: true }
  | { readonly agrees: false; readonly disagreement: ModelLedgerDisagreement };

/** Τι ακριβώς διαφώνησε — **ένα όνομα ανά ερώτηση**, ποτέ «σφάλμα». */
export type ModelLedgerDisagreement =
  | { readonly field: 'meshCount' | 'triangleCount' | 'materialCount' | 'textureCount'; readonly declared: number; readonly measured: number }
  | { readonly field: 'geometry'; readonly comparison: 'changed' };

/** Τα τέσσερα πλήθη, ονομασμένα **μία** φορά — ο βρόχος τα ρωτά, δεν τα απαριθμεί ξανά. */
const LEDGER_COUNTS = ['meshCount', 'triangleCount', 'materialCount', 'textureCount'] as const;

/**
 * 🏆 **ΣΥΜΦΩΝΕΙ Η ΔΗΛΩΣΗ ΜΕ ΤΗ ΜΕΤΡΗΣΗ;** — η άγκυρα **Α-6**, εκτελούμενη.
 *
 * ⚠️ **Τα πλήθη πρώτα, η γεωμετρία μετά**, και δεν είναι στιλ: ένα λάθος πλήθος δίνει
 * μήνυμα που ο άνθρωπος **καταλαβαίνει** *(«δήλωσες 3 πλέγματα, έφτασαν 4»)*, ενώ το
 * `changed` της γεωμετρίας είναι το **γενικότερο** «το σχήμα δεν είναι το ίδιο». Η πιο
 * **συγκεκριμένη** αιτία πρέπει να μιλήσει πρώτη.
 */
export function compareModelLedger(
  declared: ModelGeometryLedger,
  measured: ModelGeometryLedger,
): ModelLedgerVerdict {
  for (const field of LEDGER_COUNTS) {
    if (declared[field] !== measured[field]) {
      return {
        agrees: false,
        disagreement: { field, declared: declared[field], measured: measured[field] },
      };
    }
  }

  // 🔑 **Ο ΚΡΙΤΗΣ ΤΟΥ ADR-683, ΑΥΤΟΥΣΙΟΣ.** `identical` (ίδια bytes γεωμετρίας) και
  //    `equivalent` (θόρυβος float32 της εξαγωγής) είναι **και τα δύο** συμφωνία· μόνο
  //    το `changed` είναι διαφωνία. Ένα `!== 'identical'` εδώ θα απέρριπτε **κάθε**
  //    δημοσίευση, γιατί η μετάβαση float64→float32 αλλάζει **πάντα** το ακριβές hash.
  if (compareGeometry(declared.fingerprint, measured.fingerprint) === 'changed') {
    return { agrees: false, disagreement: { field: 'geometry', comparison: 'changed' } };
  }

  return { agrees: true };
}

/**
 * **Υπάρχει υπογράφων;** — η άγκυρα **Α-4**, ως μία ερώτηση.
 *
 * ⚠️ **`trim()` εδώ, και ΜΟΝΟ εδώ**: ένα όνομα από κενά είναι *«όποιος ανεβάσει»* με άλλη
 * μορφή, δηλαδή ο **Κανόνας 31 καμμένος σιωπηλά**. Ο έλεγχος ζει σε **ένα** σημείο ώστε
 * ο ψήστης να μη γεννήσει δεύτερη εκδοχή του *«τι μετράει ως υπογραφή»*.
 */
export function hasSignatory(signatory: ModelSignatory): boolean {
  return signatory.name.trim().length > 0 && signatory.discipline.trim().length > 0;
}

/** Είναι αυτή γνωστή σήμανση κατάστασης; — η άγκυρα **Α-3**, στο σύνορο. */
export function isModelStateMark(value: string): value is ModelStateMark {
  return (MODEL_STATE_MARKS as readonly string[]).includes(value);
}
