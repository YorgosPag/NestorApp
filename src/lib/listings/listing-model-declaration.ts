// Α11 — «ΜΕΛΕΤΗ Η ΠΡΑΓΜΑΤΙΚΟΤΗΤΑ;» ΕΙΝΑΙ ΚΑΤΑΣΤΑΣΗ ΜΕ ΟΝΟΜΑ
// ---------------------------------------------------------------------------

/**
 * 🏆 **Η ΣΗΜΑΝΣΗ ΚΑΤΑΣΤΑΣΗΣ** (ADR-841 §7 Α11) — **δεν** είναι μεταδεδομένο ευκολίας.
 *
 * - `as-built`  — **χτισμένο**: το μοντέλο δείχνει ό,τι υπάρχει.
 * - `proposal`  — **μελέτη**: δείχνει ό,τι θα υπάρξει. Η Α11 το δημοσιεύει **επίτηδες** —
 *   *«πωλείται με έτοιμη μελέτη»* είναι **αξία, όχι κίνδυνος**.
 * - `divergent` — **απόκλιση**: μελέτη που **δεν** ταυτίζεται πια με το χτισμένο.
 *
 * 🔴 **ΓΙΑΤΙ ΕΙΝΑΙ ΥΠΟΧΡΕΩΤΙΚΗ, ΚΑΙ ΓΙΑΤΙ ΨΗΝΕΤΑΙ ΣΤΟ ΑΡΧΕΙΟ** *(Α11.2, άγκυρα Α-3)*: ο
 * slider της Zillow ζει **μόνο στο δικό της UI** — ένα screenshot, μια αναδημοσίευση, ένα
 * syndication feed, και η σήμανση **έχει φύγει** ενώ η εικόνα μένει. Εμείς τη **ψήνουμε
 * μέσα στο artifact**, άρα **ταξιδεύει με το αρχείο**. Είναι το μόνο μέτρο που επιβιώνει
 * έξω από την οθόνη μας.
 *
 * ⚠️ Η έρευνα που το στήριξε έχει **πηγές και δόντια**: California **AB 723** *(ενεργός
 * 01/01/2026 — σήμανση **και η πρωτότυπη δίπλα**)* · **DMCC Act 2024** *(CMA: **10% τζίρου
 * ή £300k**, χωρίς δικαστήριο)*.
 */
export const MODEL_STATE_MARKS = ['as-built', 'proposal', 'divergent'] as const;

export type ModelStateMark = (typeof MODEL_STATE_MARKS)[number];

