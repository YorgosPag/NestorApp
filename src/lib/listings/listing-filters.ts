/**
 * Οι παράμετροι του **γεωγραφικού** άξονα.
 *
 * ⚠️ Των κριτηρίων ζουν στο `CRITERION_PARAM`, της ερώτησης διαμονής (`in` · `out` · `guests` ·
 * `pets`) στο `listing-stay-url.ts` — και **δεν αντιγράφονται εδώ**. Το ότι
 * κανένα από τα δύο σύνολα δεν συγκρούεται με το άλλο είναι **άγκυρα**, όχι σχόλιο:
 * δες `RESERVED_SEARCH_PARAMS`.
 */
const PARAM = {
  lat: 'lat',
  lng: 'lng',
  radiusKm: 'r',
} as const;

/**
 * Διεύθυνση → γεωγραφικό φίλτρο, ή `null`.
 *
 * ⚠️ **Απαιτούνται ΚΑΙ ΤΑ ΔΥΟ σκέλη της συντεταγμένης.** Ένα μισό ζεύγος (`lat` χωρίς
 * `lng`) δεν είναι «σχεδόν σωστό» — είναι σημείο πάνω σε μεσημβρινό μηδέν, δηλαδή
 * κάπου στον Ατλαντικό, και ο χάρτης θα το ζωγράφιζε **με απόλυτη σιγουριά**. Είναι
 * το ίδιο ελάττωμα που ο τύπος `PlacePosition` απαγορεύει με το ρητό `unknown`.
 *
 * ⚠️ **Ακτίνα ≤ 0 ⇒ αγνοείται ολόκληρο το φίλτρο**, δεν «διορθώνεται» σε 0 χλμ.:
 * ακτίνα μηδέν φιλτράρει **τα πάντα** και ο επισκέπτης θα έβλεπε άδεια οθόνη χωρίς
 * να ξέρει ότι έφταιγε μια παράμετρος στη διεύθυνση.
 *
 * 🔑 **ΕΞΑΓΕΤΑΙ ΑΠΟ ΤΗ Φ6-Β (ADR-841)** — δεύτερος καταναλωτής: το φίλτρο περιοχής
 * του δημόσιου καταλόγου επαγγελματιών *(`lib/agency/showcase-filter.ts`)*. Δύο
 * αναγνώστες των **ίδιων** τριών παραμέτρων θα ήταν δύο απαντήσεις στο *«τι
 * σημαίνει κοντά;»*, και ο δεύτερος θα ξεχνούσε τον έλεγχο `|lat| > 90`.
 *
 * ⛔ **ΜΗΝ αντιγράψεις αυτή τη λογική** — ούτε «απλοποιημένη». Οι τρεις έλεγχοι
 * *(μισό ζεύγος · εκτός ορίων · ακτίνα ≤ 0)* είναι ο λόγος ύπαρξής της.
 *
 * ✅ **ΛΥΘΗΚΕ (2026-09-06, ADR-777 §8.53)**: ο τύπος μετακόμισε — αλλά **όχι** στο
 * `lib/geo/` όπως προέβλεπε αυτή η σημείωση. Εκεί ζει η **συμπεριφορά**· το
 * **λεξιλόγιο** ζει στο `@/types/geo/coordinates`, δίπλα στα {@link GeoPoint},
 * `GeoOutline`, `GeoPolyline`, `GeoBoundingBox` — αρχείο με **μηδέν imports**, άρα
 * Shared Kernel *(Evans, DDD)* **δομικά** και όχι κατά σύμβαση. Το όνομα είναι
 * {@link GeoCircle}. Το {@link DEFAULT_SEARCH_RADIUS_KM} **μένει εδώ** επίτηδες: είναι
 * **πολιτική της οθόνης** *(«τι εννοεί ο επισκέπτης όταν δεν πει ακτίνα»)*, όχι
 * γεωμετρία — και η γεωμετρία δεν έχει προεπιλογές.
 */
export function readGeoFilter(params: URLSearchParams): GeoCircle | null {
  const lat = readFiniteNumber(params, PARAM.lat);
  const lng = readFiniteNumber(params, PARAM.lng);
  if (lat === null || lng === null) return null;
  if (Math.abs(lat) > 90 || Math.abs(lng) > 180) return null;

  const radiusKm = readFiniteNumber(params, PARAM.radiusKm) ?? DEFAULT_SEARCH_RADIUS_KM;
  if (radiusKm <= 0) return null;

  return { center: { lat, lng }, radiusKm };
}

/** Διεύθυνση → φίλτρα. **Άγνωστη τιμή αγνοείται**, ποτέ δεν σκάει η οθόνη. */
export function parseListingFilters(params: URLSearchParams): ListingFilters {
  return {
    criteria: parseListingCriteria(params),
    // 🔑 **Το ορθογώνιο ΠΡΟΗΓΕΙΤΑΙ του κύκλου, και η σειρά είναι σημασία, όχι τύχη.**
    // Ο κύκλος γεννιέται από **κείμενο** που έγραψε ο επισκέπτης· το ορθογώνιο από
    // **κίνηση** που έκανε ο ίδιος πάνω στον χάρτη — δηλαδή είναι η **νεότερη** και
    // πιο ρητή δήλωση για το πού κοιτάει. Ο σειριοποιητής γράφει πάντα **ένα** από
    // τα δύο, οπότε αυτή η προτεραιότητα κρίνει μόνο χειρόγραφες διευθύνσεις.
    near: readSearchAreaBox(params) ?? readGeoFilter(params),
    stayWindow: readListingStayWindow(params),
    guests: readListingGuests(params),
    pets: readListingPets(params),
  };
}

/**
 * Φίλτρα → διεύθυνση.
 *
 * ⚠️ **Τα κενά φίλτρα ΔΕΝ γράφονται.** Αλλιώς κάθε σύνδεσμος θα κουβαλούσε δεκάδες
 * κενές παραμέτρους, και δύο ταυτόσημες αναζητήσεις θα είχαν **διαφορετική**
 * διεύθυνση — που για μια μηχανή αναζήτησης σημαίνει δύο σελίδες με το ίδιο
 * περιεχόμενο.
 *
 * 🔑 **Ο χάρτης γράφεται ΠΡΩΤΟΣ και οι τρεις ειδικοί μετά**, μέσα στο **ίδιο**
 * αντικείμενο: μια συγχώνευση δύο `URLSearchParams` θα ήταν η θέση όπου κάποιος θα
 * ξεχνούσε ότι τα κλειδιά λεξιλογίου **επαναλαμβάνονται** (`append` ⇄ `set`).
 */
export function serializeListingFilters(filters: ListingFilters): URLSearchParams {
  const params = new URLSearchParams();
  writeListingCriteria(filters.criteria, params);

  // ⚠️ Τα τρία γεωγραφικά γράφονται **μαζί ή καθόλου**: μια διεύθυνση με `lat` χωρίς
  // `lng` δεν είναι μερικώς χρήσιμη, είναι μη αναγνώσιμη από το `readGeoFilter` — και
  // θα ταξίδευε σιωπηλά σε κάθε κοινοποιημένο σύνδεσμο.
  // ⚠️ **Ένα σχήμα ή το άλλο, ΠΟΤΕ και τα δύο.** Δύο γεωγραφικές δηλώσεις στην ίδια
  // διεύθυνση θα ήταν δύο απαντήσεις στο «πού ψάχνω;» — και ο αναγνώστης θα έπρεπε να
  // διαλέξει, δηλαδή κάποιος θα διάλεγε **αλλιώς**.
  if (filters.near !== null) {
    if (isBoundingBox(filters.near)) {
      params.set(SEARCH_AREA_PARAM, writeSearchAreaBox(filters.near));
    } else {
      params.set(PARAM.lat, String(filters.near.center.lat));
      params.set(PARAM.lng, String(filters.near.center.lng));
      params.set(PARAM.radiusKm, String(filters.near.radiusKm));
    }
  }
  // 🔑 Η ερώτηση διαμονής γράφεται από τους **καθρέφτες** των αναγνωστών της (ADR-777 §8.60.21.7):
  //    ό,τι δεν θα διαβαζόταν πίσω, δεν γράφεται. Ως τις 2026-09-22 εδώ ζούσε `guests !== null`,
  //    που έγραφε και `0` ή `2.5`, δηλαδή σύνδεσμο που ο αναγνώστης θα πετούσε.
  writeListingStayWindow(filters.stayWindow, params);
  writeListingGuests(filters.guests, params);
  writeListingPets(filters.pets, params);
  return params;
}

/**
 * **Ο ΜΟΝΑΔΙΚΟΣ ΚΑΤΑΣΚΕΥΑΣΤΗΣ ΤΟΥ ΧΡΟΝΙΚΟΥ ΕΡΩΤΗΜΑΤΟΣ** — φίλτρα → {@link StayQuery}.
 *
 * @returns το ερώτημα, ή `null` όταν ο επισκέπτης **δεν ρώτησε χρόνο**.
 *
 * 🔑 **Εδώ ενώνονται οι δύο ανεξάρτητοι άξονες** (παράθυρο · άτομα) στο σχήμα που
 * περιμένει η μηχανή διαθεσιμότητας. Ένας δεύτερος κατασκευαστής σε component θα ήταν
 * η θέση όπου κάποιος θα έγραφε `guests: filters.guests ?? 1` — δηλαδή θα υπόσχονταν
 * σιωπηλά «ένα άτομο» για κάθε αναζήτηση χωρίς αριθμό.
 *
 * ⚠️ **Χωρίς παράθυρο δεν υπάρχει ερώτημα, όσα άτομα κι αν δηλώθηκαν.** Η
 * διαθεσιμότητα είναι **ερώτηση χρόνου**· η χωρητικότητα μόνη της δεν την κάνει.
 */
export function stayQueryOf(filters: ListingFilters): StayQuery | null {
  if (filters.stayWindow === null) return null;
  return {
    checkIn: filters.stayWindow.checkIn,
    checkOut: filters.stayWindow.checkOut,
    guests: filters.guests,
    pets: filters.pets,
  };
}

