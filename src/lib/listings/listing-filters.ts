/**
 * **Κλειστό σχήμα — κάθε φίλτρο της οθόνης 2, και κανένα άλλο.**
 *
 * 🔑 **Ένας χάρτης και τρεις ειδικοί.** Ο χάρτης κρατά κάθε ομοιόμορφο άξονα *(εύρος
 * · λεξιλόγιο · ναι-όχι)* με τον τύπο του παραγόμενο από τον πίνακα σχημάτων· οι τρεις
 * ειδικοί μένουν επίπεδοι επειδή **δεν είναι τιμές**: γεωμετρία, ημι-ανοιχτό διάστημα
 * ημερών, και χωρητικότητα που κρίνεται αλλού. Ο λόγος καθενός γράφεται στο
 * `AXES_OUTSIDE_THE_CRITERIA_MAP` — **ονομασμένη εξαίρεση, ποτέ σιωπηλή**.
 */
export interface ListingFilters {
  /** Κάθε ομοιόμορφος άξονας. **Άξονας που λείπει = δεν ρωτήθηκε.** */
  readonly criteria: ListingCriteria;
  /**
   * `null` = «όπου να 'ναι» — καμία χωρική ερώτηση. Ο τύπος είναι {@link GeoArea},
   * του Shared Kernel: **κύκλος ή ορθογώνιο** *(ADR-777 §8.53 · §8.63)*.
   *
   * 🔑 **Γεωμετρία, ΠΟΤΕ όνομα τόπου.** Το {@link PublicListing} **δεν κουβαλά
   * καμία λέξη τόπου** (μετρημένο: κουβαλά `position` και `title`, τίποτα άλλο), οπότε
   * ένα φίλτρο «πόλη = Θεσσαλονίκη» θα έπρεπε είτε να ψάξει στον **τίτλο** — που είναι
   * κείμενο του κατόχου, όχι διεύθυνση — είτε να γεννήσει νέο πεδίο, που είναι
   * **απόφαση δημοσιοποίησης** και δεν ανήκει σε ένα αρχείο φίλτρων.
   *
   * Το κείμενο του επισκέπτη λύνεται σε **σημείο** από τον υπάρχοντα geocoder
   * (`/api/geocoding`, ανώνυμα προσβάσιμος) **πριν** φτάσει εδώ. Έτσι το φίλτρο
   * συγκρίνει **γεωμετρία με γεωμετρία** — το μόνο πράγμα που και οι δύο πλευρές
   * ξέρουν με βεβαιότητα.
   *
   * 🔴 **ΔΥΟ ΣΧΗΜΑΤΑ, ΕΝΑ ΠΕΔΙΟ** *(ADR-777 §8.63)*. Ήταν `GeoCircle | null` — και
   * τότε το οπτικό πεδίο του χάρτη, που είναι **ορθογώνιο**, δεν είχε πού να μπει.
   * Η προφανής κίνηση («βάλε δεύτερο πεδίο δίπλα») **απορρίπτεται**: θα ήταν δύο
   * απαντήσεις στο *«πού ψάχνω;»*, και η μέρα που θα διαφωνούσαν θα εμφανιζόταν ως
   * λίστα και χάρτης να δείχνουν άλλα πράγματα. Με **ένα** πεδίο κλειστής ένωσης,
   * το σύρσιμο του χάρτη **αντικαθιστά** την περιοχή αντί να την ανταγωνίζεται.
   */
  readonly near: GeoArea | null;
  /** `null` = «οποτεδήποτε» — καμία χρονική ερώτηση. Δες {@link ListingStayWindow}. */
  readonly stayWindow: ListingStayWindow | null;
  /**
   * Πόσα άτομα· `null` = **δεν ρωτήθηκε**, ποτέ «ένα».
   *
   * 🔑 **Ανεξάρτητο από το {@link ListingFilters.stayWindow}, επίτηδες**: ο επισκέπτης
   * μπορεί να ξέρει *πόσοι* είναι πριν ξέρει *πότε*, και το αντίστροφο. Δεμένο μέσα
   * στο παράθυρο, η μία ερώτηση θα ήταν **ανέκφραστη χωρίς την άλλη**.
   */
  readonly guests: number | null;
  /**
   * Πόσα κατοικίδια (ADR-777 §8.60.21)· `null` = **δεν ρωτήθηκε**, ποτέ «μηδέν».
   *
   * 🔑 Ανεξάρτητο από το παράθυρο, όπως τα άτομα — αλλά **κρίνεται μαζί του**, από τον ΙΔΙΟ
   * κριτή (`petsVerdict` μέσα στο `stayAvailabilityFor`): κανένα δεύτερο φίλτρο, καμία σιωπηλή
   * απόκρυψη — η λογιστική λέει πόσα δεν δέχονται.
   * ⛔ Ο σκύλος βοήθειας **δεν** δηλώνεται εδώ — δεν είναι κατοικίδιο.
   */
  readonly pets: number | null;
}

/** Προεπιλεγμένη ακτίνα όταν η διεύθυνση δεν τη δηλώνει. Πόλη-κλίμακα. */
export const DEFAULT_SEARCH_RADIUS_KM = 10;

export const EMPTY_LISTING_FILTERS: ListingFilters = {
  criteria: EMPTY_LISTING_CRITERIA,
  near: null,
  stayWindow: null,
  guests: null,
  pets: null,
};

