/**
 * **«8 εδώ · 3 ίσως · 6 εκτός περιοχής»** — *πάντα*, ακόμη και στο μηδέν.
 *
 * 🔑 **ΤΕΤΑΡΤΗ ΓΡΑΜΜΗ, ΟΧΙ ΕΠΕΚΤΑΣΗ ΤΗΣ ΠΡΩΤΗΣ.** Η οθόνη έχει ήδη τρεις κλειστές
 * λογιστικές — *«πού;»* (`ListingLedger`), *«πότε;»* (`StayLedger`), *«ταιριάζει;»*
 * (`CriteriaLedger`). Αυτή απαντά **τέταρτο** ερώτημα: *«σε σχέση με την περιοχή που
 * κοιτάω;»*. Χωμένη μέσα στην πρώτη, θα ανακάτευε *«ξέρουμε πού είναι;»* με *«είναι
 * εδώ;»* — δύο ερωτήσεις που μια αγγελία απαντά **ανεξάρτητα** (ξέρουμε ακριβώς πού
 * είναι **και** είναι αλλού).
 *
 * ⚠️ **Τα τρία μέρη είναι ξεχωριστά πεδία, ΟΧΙ δύο με αφαίρεση** — ίδιο ιδίωμα με το
 * `ListingLedger`: ένας καταναλωτής που υπολογίζει `total - inside` θα έχει δίκιο
 * μέχρι την πρώτη φορά που κάποιος διαβάσει το `maybe`.
 */
export interface ListingAreaLedger {
  /** Πόσα πέρασαν **όλα τα άλλα** φίλτρα — δηλαδή το σύνολο που η περιοχή κρίνει. */
  readonly total: number;
  /** Ξέρουμε ότι είναι **εδώ**. */
  readonly inside: number;
  /** **Ίσως** — η αβεβαιότητά τους αγγίζει την οθόνη, ή δεν ξέρουμε πού είναι. */
  readonly maybe: number;
  /** Ξέρουμε ότι **δεν** είναι εδώ. Τα μόνα που η οθόνη πράγματι έκοψε. */
  readonly outside: number;
}

/** Καμία ερώτηση περιοχής = **όλα εδώ**, μηδέν κομμένα. */
export const EMPTY_AREA_LEDGER: ListingAreaLedger = {
  total: 0,
  inside: 0,
  maybe: 0,
  outside: 0,
};

/**
 * Κλείνει το άθροισμα;
 *
 * 🔴 **Υπάρχει για να αποτύχει θορυβωδώς, όχι για να επιβεβαιώνει** — ίδιο εργαλείο
 * με το `ledgerBalances`, και ίδιος λόγος: αν κάποτε προστεθεί τέταρτη σχέση που δεν
 * μετριέται σε κανέναν κάδο, το εύρημα εμφανίζεται **εδώ**, αμέσως, αντί ως λίστα που
 * δείχνει λιγότερα από όσα υπόσχεται η γραμμή από πάνω της.
 */
export function areaLedgerBalances(ledger: ListingAreaLedger): boolean {
  return ledger.inside + ledger.maybe + ledger.outside === ledger.total;
}

/**
 * **Ο ΔΕΥΤΕΡΟΣ ΕΛΕΓΧΟΣ** — συμφωνεί η διαμέριση με το τι ΕΠΙΒΙΩΣΕ πράγματι;
 *
 * 🔑 Το {@link areaLedgerBalances} ελέγχει ότι η λογιστική κλείνει **μέσα της** — και
 * θα έκλεινε μια χαρά ενώ η λίστα δίπλα ζωγράφιζε άλλον αριθμό. Εδώ δηλώνεται η
 * σχέση με τον **κόσμο**: όσα δεν είναι `'outside'` είναι **ακριβώς** όσα περνούν τον
 * φιλτραριστή. Είναι η ίδια ρήτρα με το `ledgerCoversRendered` του §8.62, ένα σκαλί
 * πιο πάνω — και ο λόγος που μια μελλοντική «βελτιστοποίηση» του φίλτρου δεν μπορεί
 * να αποκλίνει από τον μετρητή **σιωπηλά**.
 */
export function areaLedgerMatchesVisible(
  ledger: ListingAreaLedger,
  visibleCount: number
): boolean {
  return ledger.inside + ledger.maybe === visibleCount;
}

/**
 * Διαμέριση ενός συνόλου ως προς την περιοχή.
 *
 * ⚠️ **Το `listings` πρέπει να είναι το σύνολο ΠΡΙΝ το γεωγραφικό φίλτρο και ΜΕΤΑ τα
 * υπόλοιπα** — δηλαδή `applyListingFilters(all, { ...filters, near: null })`.
 * Οτιδήποτε άλλο κάνει τη γραμμή να λέει ψέματα προς **γνωστή** κατεύθυνση: με το
 * ωμό σύνολο θα χρέωνε ως *«εκτός περιοχής»* σπίτια που αποκλείστηκαν για την τιμή
 * τους· με το φιλτραρισμένο θα έγραφε `outside: 0` σε **κάθε** αναζήτηση, για πάντα
 * — το ίδιο σχήμα με το *«`0` σημαίνει κανείς δεν κοίταξε»* που το repo έχει
 * πληρώσει τέσσερις φορές.
 *
 * 🔑 **Ίδια μηχανή, άλλη ερώτηση** — το ίδιο {@link listingAreaVerdict} που κρίνει
 * ποιες επιβιώνουν. Ένας δεύτερος κριτής εδώ θα ήταν δεύτερη αλήθεια για το *«είναι
 * μέσα;»*, δηλαδή ακριβώς ό,τι αποφεύγει το `listingMapShape`.
 */
export function computeAreaLedger(
  listings: readonly PublicListing[],
  area: GeoArea | null
): ListingAreaLedger {
  let inside = 0;
  let maybe = 0;
  let outside = 0;

  for (const listing of listings) {
    const verdict = listingAreaVerdict(listing, area);
    if (verdict === 'inside') inside += 1;
    else if (verdict === 'maybe') maybe += 1;
    else outside += 1;
  }
  return { total: listings.length, inside, maybe, outside };
}
