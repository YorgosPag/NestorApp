/**
 * # ΤΟ ΟΠΤΙΚΟ ΠΕΔΙΟ ΩΣ ΕΡΩΤΗΜΑ — **ΚΑΙ Η ΤΡΙΤΗ ΑΠΑΝΤΗΣΗ** (ADR-777 §8.63)
 *
 * Δύο ευθύνες, και οι δύο γύρω από **μία** έννοια — *«η περιοχή που ρωτά ο άνθρωπος»*:
 * η **ανάγνωση/γραφή** της στη διεύθυνση, και η **κρίση** μιας αγγελίας απέναντί της.
 *
 * ⚠️ **ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟ ΑΡΧΕΙΟ ΚΑΙ ΟΧΙ ΜΕΣΑ ΣΤΟ `listing-filters.ts`.** Εκείνο ήταν
 * ήδη **440** γραμμές· με αυτά εδώ θα περνούσε το όριο των 500 (N.7.1). Η κοπή δεν
 * είναι όμως αριθμητική: το `listing-filters` απαντά *«ποια φίλτρα ζητήθηκαν και
 * ποιες αγγελίες επιβιώνουν»*, ενώ αυτό απαντά *«τι σχέση έχει ΑΥΤΗ η αγγελία με
 * ΑΥΤΗ την περιοχή»* — ερώτηση καθαρά γεωμετρική, που δεν ξέρει τίποτα για κριτήρια,
 * ημερομηνίες ή άτομα.
 *
 * 🔑 **Και γι' αυτό ΔΕΝ εισάγει το `listing-filters`**: δέχεται την περιοχή ως
 * **όρισμα**, όχι ολόκληρα τα φίλτρα. Η αντίστροφη κατεύθυνση θα ήταν κύκλος
 * εξαρτήσεων — και θα έδινε στη γεωμετρία γνώση που δεν της χρειάζεται.
 *
 * ⛔ **Η ΛΕΞΗ `viewport` ΕΙΝΑΙ ΠΙΑΣΜΕΝΗ ΣΕ ΑΥΤΟ ΤΟ ΕΡΓΟ** και σημαίνει **πλάτος
 * οθόνης** (`ViewportClass` = `narrow` | `wide` | `measuring`). Το οπτικό πεδίο του
 * χάρτη λέγεται εδώ **`searchArea`** — δύο έννοιες δεν μοιράζονται ένα όνομα.
 */

import { areaRelation } from '@/lib/geo/geo-area';
import { listingSearchArea } from '@/lib/listings/listing-map-shape';
import type { GeoArea, GeoBoundingBox, GeoRegionRef } from '@/types/geo/coordinates';
import type { PublicListing } from '@/types/public-listing';

/**
 * **ΕΝΑ κλειδί διεύθυνσης, τέσσερις αριθμοί** — `box=<νότος>,<δύση>,<βορράς>,<ανατολή>`.
 *
 * 🔴 **ΓΙΑΤΙ ΕΝΑ ΚΛΕΙΔΙ ΚΑΙ ΟΧΙ ΤΕΣΣΕΡΑ — ΤΟ ΜΑΘΗΜΑ ΕΙΝΑΙ ΗΔΗ ΓΡΑΜΜΕΝΟ ΔΙΠΛΑ.** Το
 * `readGeoFilter` αφιερώνει παράγραφο στο ότι ένα **μισό ζεύγος** (`lat` χωρίς `lng`)
 * *«δεν είναι σχεδόν σωστό — είναι σημείο κάπου στον Ατλαντικό, και ο χάρτης θα το
 * ζωγράφιζε με απόλυτη σιγουριά»*, και ο σειριοποιητής χρειάζεται ρητό σχόλιο
 * *«μαζί ή καθόλου»* για να μην το ξεχάσει κάποιος. Με **ένα** κλειδί, το «μισό
 * ορθογώνιο» γίνεται **ανέκφραστο**: δεν υπάρχει κατάσταση να ξεχαστεί, άρα δεν
 * υπάρχει σύμβαση να τηρηθεί. Είναι το ίδιο ιδίωμα με το `ListingStayWindow`
 * *(αντικείμενο, ποτέ δύο επίπεδα πεδία)*, ένα σκαλί πιο κάτω.
 */
export const SEARCH_AREA_PARAM = 'box';

/** Πόσοι αριθμοί κάνουν ένα ορθογώνιο. Ούτε τρεις, ούτε πέντε. */
const BOX_PARTS = 4;

/**
 * Διεύθυνση → ορθογώνιο, ή `null`.
 *
 * ⚠️ **Fail-closed σε κάθε παραμόρφωση**: λάθος πλήθος αριθμών, μη πεπερασμένος
 * αριθμός, συντεταγμένη εκτός ορίων, ή **ανάποδο** ορθογώνιο (`north < south`)
 * αγνοούνται **ολόκληρα**. Ένα μερικώς έγκυρο ορθογώνιο δεν είναι μερικώς χρήσιμο:
 * θα φιλτράριζε **με σιγουριά** πάνω σε σκουπίδια, και ο επισκέπτης θα έβλεπε άδεια
 * οθόνη χωρίς να ξέρει ότι έφταιγε μια παράμετρος στη διεύθυνση.
 *
 * ⚠️ **Το εκφυλισμένο ορθογώνιο ΓΙΝΕΤΑΙ δεκτό** (`north === south`): σε αντίθεση με
 * την ακτίνα — όπου το `0` σημαίνει *«πουθενά»* και φιλτράρει τα πάντα — ένα
 * ορθογώνιο μηδενικού εμβαδού είναι **σημείο**, και ο χάρτης δεν παράγει ποτέ τέτοιο
 * από πραγματικό κάδρο. Ο τύπος το εκφράζει, η οθόνη δεν το γεννά, και μια
 * απόρριψη εδώ θα ήταν κανόνας που δεν προστατεύει από τίποτα.
 */
export function readSearchAreaBox(params: URLSearchParams): GeoBoundingBox | null {
  const raw = params.get(SEARCH_AREA_PARAM)?.trim() ?? '';
  if (raw === '') return null;

  const parts = raw.split(',').map((piece) => Number(piece));
  if (parts.length !== BOX_PARTS || !parts.every((value) => Number.isFinite(value))) return null;

  const [south, west, north, east] = parts as [number, number, number, number];
  if (Math.abs(south) > 90 || Math.abs(north) > 90) return null;
  if (Math.abs(west) > 180 || Math.abs(east) > 180) return null;
  if (north < south || east < west) return null;

  return { south, west, north, east };
}

/** Πόσα δεκαδικά ψηφία γράφονται — ~1 μέτρο, δηλαδή **πολύ** κάτω από κάθε αβεβαιότητα. */
const BOX_PRECISION = 5;

/**
 * Ορθογώνιο → η τιμή του **ενός** κλειδιού.
 *
 * ⚠️ **Στρογγυλοποιείται, και ο λόγος δεν είναι αισθητικός.** Ο χάρτης παράγει
 * δεκαπενταψήφια δεκαδικά· άκοπα, **κάθε εικονοστοιχείο σύρσιμο** θα γεννούσε
 * **διαφορετική** διεύθυνση για πρακτικά **την ίδια** περιοχή — δηλαδή άπειρες
 * διευθύνσεις με ίδιο περιεχόμενο *(αυτό που ο σειριοποιητής των φίλτρων ονομάζει
 * ρητά ελάττωμα για μηχανές αναζήτησης)*, και ένα ιστορικό πλοήγησης αχρηστευμένο.
 */
export function writeSearchAreaBox(box: GeoBoundingBox): string {
  return [box.south, box.west, box.north, box.east]
    .map((value) => Number(value.toFixed(BOX_PRECISION)))
    .join(',');
}

