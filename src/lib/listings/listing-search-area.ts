/**
 * `?area=municipality:0708` — **ποια** περιοχή, ποτέ τα πολύγωνά της.
 *
 * 🔑 **Ίδιο όνομα με τον κατάλογο επαγγελματιών** (`showcase-filter.ts`, ADR-846): στις δύο
 * οθόνες σημαίνει το ίδιο πράγμα — *«σε αυτή τη διοικητική περιοχή»*. Δύο ονόματα για
 * την ίδια έννοια θα έκαναν τον σύνδεσμο από τη μία οθόνη στην άλλη να χάνει τον τόπο.
 */
export const SEARCH_REGION_PARAM = 'area';

/**
 * Σχήμα `id` της ιεραρχίας: `<βαθμίδα>:<κωδικός>` (`municipality:0708`). Ό,τι άλλο
 * αγνοείται — ο αναγνώστης δεν ζητά αρχείο με αυθαίρετο όνομα από τη διεύθυνση.
 */
const REGION_ID = /^[a-z_]+:[0-9]+$/;

/** Διεύθυνση → αναφορά σε περιοχή, ή `null`. **Η γεωμετρία επιλύεται αλλού** (`useAdminBoundary`). */
export function readSearchRegion(params: URLSearchParams): GeoRegionRef | null {
  const raw = params.get(SEARCH_REGION_PARAM)?.trim() ?? '';
  return REGION_ID.test(raw) ? { adminId: raw } : null;
}

/**
 * **ΜΕΣΑ · ΙΣΩΣ · ΕΞΩ** — η θέση μιας αγγελίας απέναντι στην περιοχή που ρωτήθηκε.
 *
 * 🏆 **Η μεσαία τιμή είναι όλο το νόημα, και δεν την έχει κανένας από τους μεγάλους.**
 * Zillow, Redfin, Idealista και Rightmove απαντούν **δυαδικά** — και το κάνουν
 * κρίνοντας κάθε αγγελία ως **σημείο**, ακόμη κι όταν ξέρουν μόνο τη συνοικία της.
 * Δες `lib/geo/geo-area.ts` για το πρότυπο *(OGC DE-9IM)* και για το δημοσιευμένο
 * μέγεθος του προβλήματος.
 */
export type ListingAreaVerdict = 'inside' | 'maybe' | 'outside';

/**
 * **Είναι αυτή η αγγελία σε αυτή την περιοχή;** — τρεις απαντήσεις, ποτέ δύο.
 *
 * 🔴 **Η ΑΓΓΕΛΙΑ ΧΩΡΙΣ ΘΕΣΗ ΓΙΝΕΤΑΙ `'maybe'`, ΚΑΙ ΑΥΤΟ ΕΙΝΑΙ ΑΝΑΒΑΘΜΙΣΗ ΤΟΥ Α5 §4.1.**
 * Ο κανόνας έλεγε *«δεν μπορούμε να την αποκλείσουμε από περιοχή που δεν ξέρουμε αν
 * της ανήκει»*, και ο φιλτραριστής τον τηρούσε με ένα `if (kind === 'known')` — που
 * σήμαινε στην πράξη ότι η αγγελία περνούσε **σαν να ταίριαζε απόλυτα**. Δεν
 * ταιριάζει απόλυτα· **δεν ξέρουμε**. Η νέα τιμή λέει το ίδιο πράγμα χωρίς να
 * μαντεύει προς καμία κατεύθυνση, και **εξακολουθεί να μην αποκλείει** — άρα ο
 * κανόνας μένει ακέραιος και γίνεται, επιπλέον, **ορατός**.
 *
 * ⚠️ **Χωρίς ερώτηση, όλα είναι `'inside'`.** Το `null` δεν σημαίνει *«καμία
 * περιοχή»* αλλά *«κανείς δεν ρώτησε»* — και σε ερώτηση που δεν έγινε, η τίμια
 * απάντηση δεν είναι «ίσως», είναι ότι το ερώτημα δεν στενεύει τίποτα.
 */
export function listingAreaVerdict(
  listing: PublicListing,
  area: GeoArea | null
): ListingAreaVerdict {
  if (area === null) return 'inside';

  const subject = listingSearchArea(listing.position);
  if (subject === null) return 'maybe';

  switch (areaRelation(subject, area)) {
    case 'within':
      return 'inside';
    case 'disjoint':
      return 'outside';
    default:
      return 'maybe';
  }
}

