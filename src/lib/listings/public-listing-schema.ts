// ΟΙ ΠΡΟΕΠΙΛΟΓΕΣ, ΩΣ ΚΡΙΤΕΣ ΜΟΡΦΗΣ
// ============================================================================

/**
 * 🔑 **`.catch()` και όχι `??`** — η διαφορά είναι μετρήσιμη. Το `??` δέχεται
 * ό,τι δεν είναι `null`/`undefined`, άρα ένα `legality: "ναι"` γραμμένο από
 * σφάλμα θα περνούσε αυτούσιο και θα έσκαγε **στο ίδιο `.map`**. Το `.catch()`
 * ρωτά **μορφή** και πέφτει στην προεπιλογή όταν η απάντηση δεν στέκει.
 *
 * ⚠️ **Ο έλεγχος είναι ΡΗΧΟΣ, και είναι απόφαση.** Κρίνεται ότι το πεδίο είναι
 * *πίνακας από αντικείμενα*, όχι ότι κάθε σήμα είναι έγκυρο `LegalitySignal` — μια
 * βαθιά ένωση εδώ θα ήταν ο καθρέφτης που η κεφαλίδα απορρίπτει. Το βαθύ ερώτημα
 * το απαντά ο **γραφέας**, όπου ο μεταγλωττιστής μπορεί να το επιβάλει.
 */
const legalityArray = z.array(z.object({}).passthrough()).catch([]);

/** Το `stay` λείπει ⇒ `null`, που σημαίνει **«δεν είναι κατάλυμα»** (ADR-835 §4.5). */
const stayOrNull = z.object({}).passthrough().nullable().catch(null);

/** Ωμός αριθμός ή `null` — ποτέ `0` ως «άγνωστο» (κανόνας του σχήματος). */
const numberOrNull = z.number().finite().nullable().catch(null);

// ============================================================================
// Η ΑΛΥΣΙΔΑ
// ============================================================================

/**
 * **Οι κρίκοι, με τη σειρά που συνέβησαν.** Ο δείκτης `i` ανεβάζει `i+1 → i+2`.
 *
 * 🔴 **ΠΟΤΕ αναδιάταξη, ΠΟΤΕ διαγραφή, ΠΟΤΕ επεξεργασία** — δες την κεφαλίδα.
 */
export const LISTING_MIGRATIONS: readonly ListingMigration[] = [
  {
    to: 2,
    adr: 'ADR-835 §4.4/§4.5 · ADR-838 §6',
    adds: ['legality', 'stay', 'commercial.nightlyRate'],
    apply: (doc) => {
      const commercial =
        typeof doc.commercial === 'object' && doc.commercial !== null
          ? (doc.commercial as Readonly<Record<string, unknown>>)
          : {};

      return {
        ...doc,
        /**
         * 🔑 **Κενός πίνακας ΕΙΝΑΙ η σωστή απάντηση, όχι μπάλωμα.** Το ADR-838 λέει
         * ρητά ότι *«προτιμάμε να φανούμε λιγότερο πλήρεις παρά περισσότερο βέβαιοι
         * απ' όσο είμαστε»*: μια αγγελία που γράφτηκε πριν υπάρξει η ερώτηση δεν
         * έχει **αγνώστη** νομιμότητα — δεν της **τέθηκε** το ερώτημα. Η οθόνη
         * γνωρίζει ήδη να το πει.
         */
        legality: legalityArray.parse(doc.legality),
        stay: stayOrNull.parse(doc.stay),
        commercial: {
          ...commercial,
          nightlyRate: numberOrNull.parse(commercial.nightlyRate),
        },
      };
    },
  },
];

