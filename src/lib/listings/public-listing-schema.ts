/**
 * Η σφραγίδα του εγγράφου, ή {@link UNSTAMPED_SCHEMA_VERSION} όταν λείπει.
 *
 * ⚠️ Μια **μελλοντική** έκδοση (έγγραφο νεότερο από τον κώδικα που το διαβάζει)
 * επιστρέφεται αυτούσια. Συμβαίνει σε rolling deploy, όπου παλιά στιγμιότυπα
 * τρέχουν δίπλα σε νέα — και η σωστή συμπεριφορά είναι **να μην πειραχθεί**, όχι
 * να «υποβαθμιστεί»: τα άγνωστα πεδία απλώς αγνοούνται, ακριβώς όπως στο Protobuf.
 */
export function storedSchemaVersion(doc: StoredListingDocument): number {
  const stamped = doc.schemaVersion;
  return typeof stamped === 'number' && Number.isInteger(stamped) && stamped > 0
    ? stamped
    : UNSTAMPED_SCHEMA_VERSION;
}

/**
 * **Ανεβάζει ένα έγγραφο ως τη σημερινή έκδοση**, περνώντας κάθε κρίκο με τη σειρά.
 *
 * **Ιδιοδύναμη**: έγγραφο ήδη τρέχουσας έκδοσης δεν αγγίζεται· διπλή κλήση δίνει το
 * ίδιο αποτέλεσμα. Αυτό είναι που κάνει ασφαλή τη lazy migration του αναγνώστη.
 */
export function upgradeListingDocument(doc: StoredListingDocument): StoredListingDocument {
  const from = storedSchemaVersion(doc);
  if (from >= PUBLIC_LISTING_SCHEMA_VERSION) return doc;

  const upgraded = LISTING_MIGRATIONS.filter((migration) => migration.to > from).reduce(
    (current, migration) => migration.apply(current),
    doc
  );

  return { ...upgraded, schemaVersion: PUBLIC_LISTING_SCHEMA_VERSION };
}
