/**
 * **Τι ΕΙΝΑΙ αυτό το ποσό** — ζητούμενη, τελική, ενοίκιο, ή παλιό ενιαίο πεδίο.
 *
 * 🔴 **Δεν είναι διακόσμηση: είναι η Α21 σε λέξεις.** Ένα πωλημένο ακίνητο δείχνει
 * **δύο** αριθμούς (τελική μπροστά, ζητούμενη δίπλα) και ένα προς πώληση-και-ενοικίαση
 * επίσης δύο (πώληση + ενοίκιο). **Χωρίς ετικέτα ρόλου, τα δύο ζεύγη μοιάζουν ίδια
 * και σημαίνουν εντελώς διαφορετικά πράγματα** — «185.000 και 200.000» δεν λέει από
 * μόνο του αν το ακίνητο πουλήθηκε φθηνότερα ή αν κοστίζει τόσο και νοικιάζεται τόσο.
 *
 * Είναι ο κανόνας 18 (*«ένας αριθμός χωρίς προέλευση είναι ισχυρισμός, όχι γεγονός»*)
 * στην επιφάνεια όπου τον διαβάζει ο επισκέπτης, όχι μόνο ο προγραμματιστής.
 *
 * ⚠️ Το `legacy.price` **δεν** ονομάζεται «ζητούμενη»: το @deprecated ενιαίο πεδίο
 * δεν κουβαλά ρόλο, και το να του αποδώσουμε έναν θα ήταν εικασία με τη στολή
 * γεγονότος. Λέγεται **«καταχωρημένη τιμή»** — ακριβώς όσο ξέρουμε.
 */
