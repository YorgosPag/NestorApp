/**
 * @fileoverview **Ετυμηγορία τιμής → κλειδί i18n.** Μία φορά, για όλες τις δημόσιες οθόνες.
 * @related ADR-777 §7 (Α6 · Α21) · lib/properties/price-resolver.ts
 * @module lib/listings/listing-price-keys
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΓΙΑΤΙ ΥΠΑΡΧΕΙ — κανόνας N.0.2, πριν γεννηθεί το διπλότυπο
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο `price-resolver` επιστρέφει **ρητές καταστάσεις** (`MissingPriceReason`) και
 * **ρητή προέλευση** (`PriceSource`). Η κάρτα της οθόνης 2 είχε ήδη τον δικό της
 * μικρό πίνακα για την πρώτη· η σελίδα ακινήτου χρειάζεται **και τις δύο**.
 *
 * Δύο αντίγραφα του ίδιου πίνακα σε δύο φακέλους θα ήταν το γνώριμο σχήμα: μια μέρα
 * κάποιος αλλάζει το κείμενο στο ένα, και η **ίδια** αγγελία λέει διαφορετικά
 * πράγματα στη λίστα και στη σελίδα της — χωρίς τίποτα να τα συγκρίνει (CHECK 3.34,
 * δύο λίστες που απέκλιναν κατά 63).
 *
 * ⚠️ **`Record<…>` και όχι αντικείμενο με προαιρετικά κλειδιά**: μια νέα κατάσταση
 * στον `price-resolver` **σπάει τη μεταγλώττιση εδώ**, δηλαδή δεν μπορεί να φτάσει σε
 * οθόνη ως ωμό κλειδί. Ίδιο ιδίωμα με το `PROPERTY_TYPE_I18N_KEYS`.
 *
 * 🔑 Τα κλειδιά είναι **πλήρη, με namespace**. Και οι δύο καταναλωτές ζουν στο ίδιο
 * `search-results`, και ένα μισό κλειδί που το κάθε σημείο κλήσης συμπληρώνει μόνο
 * του είναι ακριβώς η δυναμική `t()` που οι πύλες i18n **δεν μπορούν να επιλύσουν**
 * (CHECK 3.34: ανεπίλυτη δυναμική `t()` ⇒ ο generator αρνείται να παράγει).
 */

import type { MissingPriceReason, PriceSource } from '@/lib/properties/price-resolver';

/**
 * **Γιατί δεν υπάρχει τιμή.** Οι καταστάσεις **δεν** είναι εναλλάξιμες: η πρώτη λέει
 * «δεν είναι στην αγορά» (σωστή απουσία), οι υπόλοιπες «είναι, αλλά κανείς δεν
 * καταχώρησε αριθμό» (κενό δεδομένων που ο κάτοχος μπορεί να κλείσει).
 */
export const MISSING_PRICE_KEY: Readonly<Record<MissingPriceReason, string>> = {
  'not-listed': 'search-results:card.priceMissing.notListed',
  'sale-price-missing': 'search-results:card.priceMissing.salePriceMissing',
  'rent-price-missing': 'search-results:card.priceMissing.rentPriceMissing',
  // ⚠️ **Δεν είναι συνώνυμο του `not-listed`, είναι το αντίθετό του** (ADR-835 §4.4):
  // το κατάλυμα **είναι** στην αγορά — απλώς σε άξονα που το επτάτιμο λεξιλόγιο δεν
  // ονομάζει. Κοινό κείμενο με το «δεν διατίθεται» θα έλεγε ψέματα στον επισκέπτη και
  // θα έκρυβε από τον κάτοχο ένα κενό που **μπορεί** να κλείσει.
  'nightly-rate-missing': 'search-results:card.priceMissing.nightlyRateMissing',
};

/**
 * **Τι ΕΙΝΑΙ αυτό το ποσό** — ζητούμενη, τελική, ενοίκιο, ή παλιό ενιαίο πεδίο.
 *
 * 🔴 **Δεν είναι διακόσμηση: είναι η Α21 σε λέξεις.** Ένα πωλημένο ακίνητο δείχνει
 * **δύο** αριθμούς (τελική μπροστά, ζητούμενη δίπλα) και ένα προς πώληση-και-ενοικίαση
 * επίσης δύο (πώληση + ενοίκιο). **Χωρίς ετικέτα ρόλου, τα δύο ζεύγη μοιάζουν ίδια
 * και σημαίνουν εντελώς διαφορετικά πράγματα** — «185.000 και 200.000» δεν λέει από
 * μόνο του αν το ακίνητο πουλήθηκε φθηνότερα ή αν κοστίζει τόσο και νοικιάζεται τόσο.
 *
 * Είναι ο κανόνας 18 (*«ένας αριθμός χωρίς προέλευση είναι ισχυρισμός, όχι γεγονός»*)
 * στην επιφάνεια όπου τον διαβάζει ο επισκέπτης, όχι μόνο ο προγραμματιστής.
 *
 * ⚠️ Το `legacy.price` **δεν** ονομάζεται «ζητούμενη»: το @deprecated ενιαίο πεδίο
 * δεν κουβαλά ρόλο, και το να του αποδώσουμε έναν θα ήταν εικασία με τη στολή
 * γεγονότος. Λέγεται **«καταχωρημένη τιμή»** — ακριβώς όσο ξέρουμε.
 */
export const PRICE_ROLE_KEY: Readonly<Record<PriceSource, string>> = {
  'commercial.askingPrice': 'search-results:detail.price.role.asking',
  'commercial.finalPrice': 'search-results:detail.price.role.final',
  'commercial.rentPrice': 'search-results:detail.price.role.rent',
  // 🔴 **Η ετικέτα ΕΙΝΑΙ η μονάδα, και εδώ είναι υποχρεωτική.** «65 €» δίπλα σε «650 €»
  // διαφέρουν κατά τριάντα φορές και μοιάζουν ίδια· ο ρόλος είναι το μόνο που τα
  // ξεχωρίζει. Ο σκόπελος γράφτηκε ρητά στο ADR-835 §4.4: *«η οθόνη δεν επιτρέπεται να
  // γράψει “65 €” με τη μορφή που γράφει τιμή πώλησης»*.
  'commercial.nightlyRate': 'search-results:detail.price.role.nightly',
  'legacy.price': 'search-results:detail.price.role.legacy',
};
