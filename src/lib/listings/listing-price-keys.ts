/**
 * @fileoverview **Ετυμηγορία τιμής → κλειδί i18n.** Μία φορά, για όλες τις δημόσιες οθόνες.
 * @related ADR-777 §7 (Α6 · Α21) · lib/properties/price-resolver.ts
 * @module lib/listings/listing-price-keys
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΓΙΑΤΙ ΥΠΑΡΧΕΙ — κανόνας N.0.2, πριν γεννηθεί το διπλότυπο
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο `price-resolver` επιστρέφει **ρητές καταστάσεις** (`MissingPriceReason`) και
 * **ρητή προέλευση** (`PriceSource`). Η κάρτα της οθόνης 2 είχε ήδη τον δικό της
 * μικρό πίνακα για την πρώτη· η σελίδα ακινήτου χρειάζεται **και τις δύο**.
 *
 * Δύο αντίγραφα του ίδιου πίνακα σε δύο φακέλους θα ήταν το γνώριμο σχήμα: μια μέρα
 * κάποιος αλλάζει το κείμενο στο ένα, και η **ίδια** αγγελία λέει διαφορετικά
 * πράγματα στη λίστα και στη σελίδα της — χωρίς τίποτα να τα συγκρίνει (CHECK 3.34,
 * δύο λίστες που απέκλιναν κατά 63).
 *
 * ⚠️ **`Record<…>` και όχι αντικείμενο με προαιρετικά κλειδιά**: μια νέα κατάσταση
 * στον `price-resolver` **σπάει τη μεταγλώττιση εδώ**, δηλαδή δεν μπορεί να φτάσει σε
 * οθόνη ως ωμό κλειδί. Ίδιο ιδίωμα με το `PROPERTY_TYPE_I18N_KEYS`.
 *
 * 🔑 Τα κλειδιά είναι **πλήρη, με namespace**. Και οι δύο καταναλωτές ζουν στο ίδιο
 * `search-results`, και ένα μισό κλειδί που το κάθε σημείο κλήσης συμπληρώνει μόνο
 * του είναι ακριβώς η δυναμική `t()` που οι πύλες i18n **δεν μπορούν να επιλύσουν**
 * (CHECK 3.34: ανεπίλυτη δυναμική `t()` ⇒ ο generator αρνείται να παράγει).
 */

