/**
 * **Το ποσό ΜΑΖΙ με τη μονάδα του** — «170.000 €», «900 €/μήνα», «50 €/νύχτα».
 *
 * 🔴 **Γιατί χρειάζεται και όταν υπάρχει ο {@link PRICE_ROLE_KEY}.** Εκείνος είναι
 * **ετικέτα δίπλα** στο ποσό και χωρά μόνο στη «σκάβω» βαθμίδα (σελίδα ακινήτου). Κάρτα,
 * φούσκα, δείκτης άκρης και πινακίδα χάρτη δεν έχουν χώρο για ετικέτα — και μέχρι
 * 2026-09-17 έγραφαν **σκέτο** `formatCurrency(amount)`: «50 €/νύχτα» και «170.000 €»
 * στον **ίδιο** χάρτη με την **ίδια** τυπογραφία (ADR-835 §4.4, ADR-777 §8.60).
 *
 * ⚠️ **Κλειδί ανά ΡΟΛΟ, όχι ανά προέλευση**: ζητούμενη, τελική και παλιό ενιαίο πεδίο
 * είναι όλες ποσά **χωρίς** περίοδο. Η μονάδα είναι ιδιότητα του ρόλου.
 *
 * 🔑 **Και η πώληση έχει κλειδί** (`{price}`), αντί για κλάδο «χωρίς μονάδα»: η θέση της
 * μονάδας είναι **γλωσσική απόφαση** (κάποια γλώσσα τη γράφει μπροστά), άρα ανήκει στα
 * locales — και ένας κλάδος στον κώδικα θα ήταν η μόνη διαδρομή που δεν περνά από αυτά.
 *
 * 📦 **Ζει στο `common`, όχι στο `search-results`, και ο λόγος είναι ΜΕΤΡΗΜΕΝΟΣ**
 * (2026-09-17): γραμμένα στο `search-results` ανέβασαν το namespace σε **15.255 bytes >
 * ταβάνι 15.200** (CHECK 3.34), και ο κανόνας του μητρώου είναι *«μετακόμιση, όχι
 * μεγαλύτερος αριθμός»*. Το `common` είναι και το **σωστό** σπίτι: «τιμή ανά μήνα» είναι
 * έννοια της πλατφόρμας — ζει ήδη σκόρπια ως `properties-detail:…rentValue`,
 * `properties-viewer:…perMonth` και `storage:…perMonth`, υποψήφιοι να τη ζητήσουν από εδώ.
 */
