import type { AttributeProvenance } from '@/lib/property/attribute-provenance';
import {
  MODEL_PUBLICATION_SCOPES,
  MODEL_STATE_MARKS,
  type ModelPublicationScope,
  type ModelStateMark,
} from './listing-model-declaration';

// ---------------------------------------------------------------------------
// Η ΤΑΥΤΟΤΗΤΑ — ΤΟ ΓΙΝΟΜΕΝΟ, ΠΟΤΕ ΤΑ ΛΕΞΙΛΟΓΙΑ
