/**
 * ⚠️ **ΤΑ ΔΥΟ ΑΠΟ ΤΑ ΤΡΙΑ ΛΕΞΙΛΟΓΙΑ ΔΕΝ ΖΟΥΝ ΕΔΩ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ.** Η σήμανση και το
 * εύρος είναι **δηλώσεις** — ταξιδεύουν δίπλα στα bytes, και ζουν στο
 * `listing-model-declaration` μαζί με τον υπογράφοντα. Η προέλευση είναι **ιεραρχία
 * αξιοπιστίας** και ζει στο `lib/property/attribute-provenance`, μία φορά για όλο το έργο.
 *
 * ⇒ Αυτό το αρχείο κατέχει **μόνο το γινόμενο** — δηλαδή την **ερώτηση** *«είναι αυτά τα δύο
 * μοντέλα το ίδιο πράγμα;»*. Ένα αντίγραφο λεξιλογίου εδώ θα ήταν τρίτη διατύπωση κάτι που
 * ήδη λέγεται δύο φορές σωστά.
 */

/**
 * **Η ΤΑΥΤΟΤΗΤΑ ΕΝΟΣ ΔΗΜΟΣΙΕΥΜΕΝΟΥ ΜΟΝΤΕΛΟΥ** — τρία σκέλη, κανένα προαιρετικό.
 *
 * ⚠️ **Ούτε ένα πεδίο παραπάνω.** Ο υπογράφων, η ημερομηνία μελέτης, η λογιστική γεωμετρίας
 * και το μέγεθος είναι **ιδιότητες** αυτού του μοντέλου — αλλάζοντάς τα δεν αλλάζει *ποιο
 * πράγμα* δημοσιεύεις. Ένα σκέλος παραπάνω εδώ σημαίνει διπλότυπη κάρτα στην αγγελία.
 */
export interface ModelPublicationIdentity {
  /** *«Ποιος παράγει;»* — **ποτέ** ποιος υπογράφει. Δες το σχόλιο του module. */
  readonly provenance: AttributeProvenance;
  /** *«Τι καλύπτει;»* — το `Volume/Level`. */
  readonly scope: ModelPublicationScope;
  /** *«Τι δηλώνει;»* — χτισμένο, μελέτη ή απόκλιση (Α11). */
  readonly state: ModelStateMark;
}

/**
 * Ο διαχωριστής των σκελών — **μία** φορά, ώστε ο αναλυτής να μη γεννηθεί ποτέ δεύτερος.
 *
 * ⚠️ **`/` και όχι `|` ή `:`**: καμία από τις τρεις τιμές δεν το περιέχει *(είναι κλειστά
 * λεξιλόγια, ελεγμένο από την άγκυρα)*, και το `:` είναι **ήδη** ο διαχωριστής του
 * προθέματος — δες {@link MODEL_IDENTITY_PREFIX}.
 */
const IDENTITY_SEPARATOR = '/';

/**
 * Το πρόθεμα είδους — **ίδιο ιδίωμα με το `LISTING_MODEL_SOURCE_REF = 'property-model:glb'`**.
 *
 * 🔑 Υπάρχει ώστε ένα **δεύτερο** είδος υλικού που θα θελήσει διαδοχή *(οι κατόψεις έχουν το
 * ίδιο πρόβλημα και το λύνουν σήμερα μόνο με πράξη πελάτη — Ο-16)* να μη μπορεί να συγκρουστεί
 * κατά λάθος: το πεδίο `publicationIdentity` του `FileRecord` είναι **γενικό**, οι παραγωγοί του
 * είναι ειδικοί.
 */
export const MODEL_IDENTITY_PREFIX = 'model';

/**
 * 🏆 **ΤΟ TAG** — η ταυτότητα ως **μία** συμβολοσειρά, συγκρίσιμη με `===`.
 *
 * 🔴 **ΓΙΑΤΙ ΚΛΕΙΔΙ ΚΑΙ ΟΧΙ ΣΥΓΚΡΙΣΗ ΤΡΙΩΝ ΠΕΔΙΩΝ.** Ένα
 * `a.scope === b.scope && a.state === b.state` που **ξέχασε** το τρίτο σκέλος είναι ακριβώς
 * το σφάλμα που ολόκληρο αυτό το αρχείο υπάρχει για να αποτρέψει — και θα ήταν **σιωπηλό**:
 * δύο μοντέλα θα συγχωνεύονταν λανθασμένα και η αγγελία θα έκρυβε ένα, χωρίς κανένα ίχνος.
 * Με **ένα** κλειδί, η παράλειψη σκέλους είναι **αδύνατη**: ή είναι μέσα στη συμβολοσειρά ή
 * η μεταγλώττιση σπάει.
 *
 * 🔑 **Και είναι αναγνώσιμο**: `model/measured/active-floor/as-built`. Ένας άνθρωπος που το
 * βλέπει στο Firestore καταλαβαίνει **αμέσως** τι δημοσιεύτηκε — σε αντίθεση με ένα hash, που
 * θα ήταν εξίσου σωστό και **αδιάγνωστο**.
 *
 * ⚠️ **Ντετερμινιστική σειρά σκελών**, ποτέ `Object.values`: η σειρά των κλειδιών ενός
 * αντικειμένου δεν είναι συμβόλαιο, και μια αλλαγή της θα άλλαζε **κάθε** αποθηκευμένο κλειδί
 * ⇒ όλα τα παλιά έγγραφα θα γίνονταν ξαφνικά «παραλλαγές» του εαυτού τους.
 */
export function modelPublicationIdentityKey(identity: ModelPublicationIdentity): string {
  return [
    MODEL_IDENTITY_PREFIX,
    identity.provenance,
    identity.scope,
    identity.state,
  ].join(IDENTITY_SEPARATOR);
}

/**
 * **Είναι αυτό κλειδί ταυτότητας ΜΟΝΤΕΛΟΥ;** — ο φρουρός της επιμέλειας.
 *
 * 🔑 **Ρωτιέται στον αναγνώστη πριν ομαδοποιήσει.** Ένα αρχείο χωρίς κλειδί *(κάθε μοντέλο
 * που δημοσιεύτηκε **πριν** από αυτή τη φάση — και υπάρχουν δύο, ζωντανά)* **δεν** επιτρέπεται
 * να συγχωνευθεί με τίποτα: *«δεν ξέρω τι είναι»* δεν σημαίνει ποτέ *«είναι το ίδιο»*.
 * Fail-open για την **προβολή**, fail-closed για τη **συγχώνευση** — η ίδια κατεύθυνση με το
 * `fingerprint: null` του `compareModelLedger`.
 */
export function isModelIdentityKey(value: unknown): value is string {
  return (
    typeof value === 'string' &&
    value.startsWith(`${MODEL_IDENTITY_PREFIX}${IDENTITY_SEPARATOR}`)
  );
}

/**
 * **Όλες οι δυνατές ταυτότητες** — παραγόμενες, ποτέ γραμμένες με το χέρι.
 *
 * ⚠️ Υπάρχει **για την άγκυρα**: το ερώτημα *«είναι κάθε κλειδί μοναδικό, και παραμένει
 * μοναδικό όταν μεγαλώσει κάποιο από τα τρία λεξιλόγια;»* δεν απαντιέται με δείγματα. Ο
 * παραγωγός τις απαριθμεί **όλες** — άρα την ημέρα που μπει τέταρτη σήμανση ή τρίτος
 * παραγωγός, η άγκυρα ελέγχει **και εκείνη**, χωρίς να την προσθέσει κανείς.
 *
 * 🔑 **Το `provenances` είναι όρισμα** και όχι εισαγωγή του `ATTRIBUTE_PROVENANCES`: μόνο
 * `measured` και `declared` **δημοσιεύουν** μοντέλο *(το `inferred` δεν έχει παραγωγό)*, και ο
 * κατάλογος του τι δημοσιεύεται δεν ανήκει σε αυτό το αρχείο.
 */
export function enumerateModelIdentities(
  provenances: readonly AttributeProvenance[],
): readonly ModelPublicationIdentity[] {
  return provenances.flatMap((provenance) =>
    MODEL_PUBLICATION_SCOPES.flatMap((scope) =>
      MODEL_STATE_MARKS.map((state) => ({ provenance, scope, state })),
    ),
  );
}
