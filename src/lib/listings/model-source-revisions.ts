/**
 * **Ένα σχέδιο, στην έκδοση που ήταν όταν παρήχθη το μοντέλο.**
 *
 * ⚠️ **`fileId` και όχι `levelId`, και είναι απόφαση.** Η γεωμετρία ζει στο **αρχείο σκηνής**
 * *(`.scene.json`, φορτώνεται με `loadFileV2`)*, όχι στο έγγραφο του επιπέδου — μετρημένο.
 * Ένα `levelId` θα έδειχνε σε έγγραφο που αλλάζει για **άσχετους** λόγους, και θα έσπαγε την
 * ημέρα που δύο επίπεδα δείξουν στο ίδιο αρχείο *(το «sticky fileId» του ADR-399, καταγγελμένο
 * στο `cross-floor-link`)*.
 */
export interface ModelSourceRevision {
  /** Το `files/{id}` του **αρχείου σκηνής** — το `sceneFileId` του επιπέδου. */
  readonly fileId: string;
  /** Το `revision` εκείνου του αρχείου **τη στιγμή της δημοσίευσης**. Μονότονο, ≥ 1. */
  readonly revision: number;
}

/**
 * **Γιατί δεν ξέρουμε αν ισχύει** — ονομαστικά, ποτέ σιωπηλό `false` *(ADR-844 §1)*.
 *
 * 🔑 **Τρεις απαντήσεις, όχι δύο.** Ένα `boolean` θα συγχώνευε το *«είναι μπαγιάτικο»* με το
 * *«δεν μπορώ να ξέρω»* — και η οθόνη θα έλεγε **ψέματα** στη δεύτερη περίπτωση: κάθε μοντέλο
 * που δημοσιεύτηκε **πριν** από αυτή τη φάση δεν έχει καταγραφή, και το να το βαφτίσουμε
 * «φρέσκο» θα ήταν ο **ίδιος** ισχυρισμός που το Ο-25 καταγγέλλει, ανάποδα.
 */
export type ModelFreshness =
  /** Κάθε καταγεγραμμένο σχέδιο είναι **ακριβώς** στην έκδοση που παρήγαγε το μοντέλο. */
  | { readonly state: 'current' }
  /** Τουλάχιστον ένα σχέδιο **προχώρησε** — ή **εξαφανίστηκε**. Με ονόματα, για το μήνυμα. */
  | { readonly state: 'stale'; readonly changed: readonly ModelSourceRevision[] }
  /** Δεν υπάρχει καταγραφή *(δημοσίευση πριν τη Φ Ο-25)*, ή δεν ρωτήθηκε η βάση. */
  | { readonly state: 'unknown' };

/** Ο σταθερός «δεν ξέρω» — μοιράζεται, γιατί είναι αμετάβλητος και άδειος. */
export const FRESHNESS_UNKNOWN: ModelFreshness = { state: 'unknown' };

/**
 * 🏆 **ΙΣΧΥΕΙ ΑΚΟΜΑ;** — **ακριβής ισότητα**, ποτέ σύγκριση χρόνων (Ο-25, άγκυρα **Α-16**).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΤΙ ΠΙΑΝΕΙ ΚΑΙ ΤΙ **ΔΕΝ** ΠΙΑΝΕΙ — δηλωμένο, όχι παρασταμένο λυμένο
 * ────────────────────────────────────────────────────────────────────────────
 *
 * - ✅ **ΠΙΑΝΕΙ**: αποθηκεύτηκε ξανά κάποιο από τα σχέδια που **παρήγαγαν** το μοντέλο
 *   *(`revision` προχώρησε)*.
 * - ✅ **ΠΙΑΝΕΙ**: σχέδιο **εξαφανίστηκε** *(διαγράφηκε, αντικαταστάθηκε, έχασε την κηδεμονία
 *   του)* — απουσία από τον χάρτη σημαίνει **μπαγιάτικο**, ποτέ «άρα δεν άλλαξε».
 * - ❌ **ΔΕΝ ΠΙΑΝΕΙ**: **νέο** επίπεδο που δεν υπήρχε τη στιγμή της δημοσίευσης, σε μοντέλο
 *   εύρους `all-floors`. Το μοντέλο πράγματι δεν το καλύπτει — αλλά αυτό απαιτεί να ξέρεις το
 *   **τρέχον σύνολο επιπέδων του κτιρίου**, που η καρτέλα του ακινήτου δεν έχει.
 *   ⚠️ **Δηλωμένο όριο, όχι παράλειψη**: ο άνθρωπος που μόλις **έφτιαξε** επίπεδο το ξέρει·
 *   το Ο-25 υπάρχει για ό,τι **ξέχασε**. Δες §9 του ADR-845.
 *
 * ⚠️ **Κενή καταγραφή ⇒ `unknown`, ΠΟΤΕ `current`.** Είναι η ίδια κατεύθυνση με το
 * `fingerprint: null` του `compareModelLedger` και με την **απουσία ταυτότητας** του Ο-27:
 * *«δεν ξέρω»* δεν σημαίνει ποτέ *«είναι εντάξει»*.
 *
 * 🔑 **Ο χάρτης δίνεται ως όρισμα** και δεν ρωτιέται εδώ: αυτό το module δηλώνει ότι είναι
 * **καθαρό**, και ο καλών κρατά τη δική του πολιτική κόστους — ίδιο ιδίωμα με τον
 * `AgencyMediaResolver`. Μία ανάγνωση ανά αρχείο, με **όλα** τα αρχεία μαζί.
 */
export function modelFreshness(
  recorded: readonly ModelSourceRevision[] | undefined,
  currentRevisionOf: ReadonlyMap<string, number>,
): ModelFreshness {
  if (recorded === undefined || recorded.length === 0) return FRESHNESS_UNKNOWN;

  const changed = recorded.filter((source) => currentRevisionOf.get(source.fileId) !== source.revision);

  return changed.length === 0 ? { state: 'current' } : { state: 'stale', changed };
}

/**
 * **Ποια αρχεία πρέπει να ρωτηθούν** για να απαντηθεί η παλαιότητα ενός συνόλου μοντέλων.
 *
 * 🔑 **Ένα πέρασμα, χωρίς διπλότυπα.** Δύο μοντέλα του ίδιου ακινήτου *(π.χ. `as-built` +
 * `proposal` — ο πληθυντικός που κρατά το Ο-27)* μοιράζονται συνήθως **τα ίδια** σχέδια· ένα
 * ερώτημα ανά μοντέλο θα πλήρωνε τις ίδιες αναγνώσεις δύο φορές.
 *
 * ⚠️ **Επιστρέφει πίνακα, όχι `Set`**: ο καλών το δίνει σε ερώτημα Firestore *(`in`, ή
 * `getAll`)*, και και τα δύο θέλουν πίνακα. Ένα `Set` θα ανάγκαζε κάθε καλούντα σε `[...]`.
 */
export function sourceFileIdsOf(
  records: readonly (readonly ModelSourceRevision[] | undefined)[],
): readonly string[] {
  const seen = new Set<string>();

  for (const recorded of records) {
    for (const source of recorded ?? []) seen.add(source.fileId);
  }

  return [...seen];
}
