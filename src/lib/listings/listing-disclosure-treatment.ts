/**
 * @fileoverview **ΟΙ ΡΟΛΟΙ ΑΠΟΚΑΛΥΨΗΣ** — το κλειστό λεξιλόγιο του *«με ποιον τρόπο γίνεται ορατό ένα πεδίο;»*.
 * @related ADR-777 §7 (Α3 · Α7) · §8.92 · lib/listings/listing-disclosure
 * @module lib/listings/listing-disclosure-treatment
 *
 * 🔑 **Εξήχθη από το `listing-disclosure.ts` (ADR-777 §8.92, N.7.1) — EXTRACT, όχι trim.** Ο πίνακας απαντά
 * *«ποιο πεδίο έχει ποιον ρόλο;»*· αυτό το αρχείο απαντά *«ποιοι ρόλοι υπάρχουν, και γιατί ο καθένας είναι
 * χωριστός;»*. Η τεκμηρίωση κάθε ρόλου μετακόμισε **αυτούσια**: είναι το μόνο σημείο που εξηγεί γιατί ένα πεδίο
 * **δεν** είναι `'attribute'` ή `'media'`, και ένας ρόλος χωρίς το «γιατί» του ξαναενώνεται στην επόμενη προσθήκη.
 *
 * **Layering**: leaf — μόνο τύπος, καμία εισαγωγή.
 */

/**
 * Ο **ρόλος** ενός δημοσιευμένου πεδίου στην οθόνη 3.
 *
 * Δεν είναι κατηγορίες διάταξης· είναι απαντήσεις στο *«με ποιον τρόπο γίνεται αυτό
 * το πεδίο ορατό;»*. Δύο πεδία με τον ίδιο ρόλο εμφανίζονται με τον ίδιο μηχανισμό.
 */
export type DisclosureTreatment =
  /** Η ταυτότητα **είναι** η διεύθυνση της σελίδας — δεν ζωγραφίζεται ως περιεχόμενο. */
  | 'identity'
  /** Ο τίτλος του κατόχου, στην κορυφή. */
  | 'headline'
  /**
   * Τροφοδοτεί τον **SSoT τιμής** (`lib/properties/price-resolver`).
   *
   * ⛔ **ΠΟΤΕ ζωγραφισμένο ωμό** — και ειδικά το `commercialStatus`, που η **Α20**
   * ορίζει **ρητά lossy**: ένα ακίνητο μόνο προς αντιπαροχή προβάλλεται εκεί σε
   * `'unavailable'`. Τυπωμένο αυτούσιο, θα έλεγε «μη διαθέσιμο» για κάτι που
   * **είναι** διαθέσιμο — με άλλον τρόπο.
   */
  | 'price'
  /**
   * **Φεύγει αρχείο στον κόσμο** — ή η απουσία του ονομάζεται: εξώφυλλο, συλλογή, κατόψεις, μοντέλα, βίντεο,
   * κάτοψη ορόφου.
   *
   * 🔑 Ο ρόλος απαντά **ένα** ερώτημα, *«φεύγει αρχείο;»* — και γι' αυτό τον μοιράζονται έξι κουτιά με διαφορετικό
   * παραγωγό και διαφορετικό θεατή. Ο **παραγωγός** (μοντέλο · κάτοχος · ψήστης) και το **«φαίνεται τώρα;»**
   * (`isPubliclyPresentable`) είναι ερωτήσεις του **σχήματος** και του κριτή του, όχι αυτού του πίνακα.
   */
  | 'media'
  /** Μετρήσιμο χαρακτηριστικό — δείχνεται **και όταν λείπει** (§25.6). */
  | 'attribute'
  /**
   * **Προσδιοριστής ιδιότητας** (ADR-900 §8 #2, 2β.2) — δεν είναι γραμμή μόνος του· ταξιδεύει **μαζί** με το
   * `'attribute'` που προσδιορίζει και αλλάζει **πώς** αποδίδεται (`floorKind` ⇒ «Πυλωτή» αντί για «Ισόγειο»).
   * ⛔ Ως `'attribute'` θα γινόταν δεύτερη γραμμή «είδος ορόφου» με δική του λογιστική «δηλωμένο;» — ενώ η
   * ερώτηση «δηλώθηκε ο όροφος;» είναι **μία**.
   */
  | 'attribute-qualifier'
  /**
   * **ΣΥΝΟΛΟ τιμών από κλειστό λεξιλόγιο** (ADR-842 Φ3) — παροχές, προσανατολισμοί,
   * δάπεδα.
   *
   * ⛔ **ΔΕΝ είναι `'attribute'`, και η διάκριση ΕΙΝΑΙ ο μηχανισμός** — ίδιο ακριβώς
   * σχήμα με τα `'stay-terms'` και `'legality'` που έφυγαν από εκεί πριν από αυτό.
   * Ένα σύνολο έχει **τρεις** καταστάσεις, όχι δύο:
   *
   * | Τιμή | Τι σημαίνει |
   * |---|---|
   * | `null` | **κανείς δεν ρώτησε** — δικό μας χρέος |
   * | `[]` | ρωτήθηκε, και η απάντηση ήταν **καμία** — **γεγονός του κατόχου** |
   * | `[…]` | ρωτήθηκε, και υπάρχουν |
   *
   * Ο ρόλος `'attribute'` ξέρει **δύο** ({@link isAttributeDeclared} επιστρέφει
   * `boolean`) και θα **έλιωνε** τις τρεις σε δύο — δηλαδή ένα ακίνητο που **δήλωσε**
   * ότι δεν έχει καμία παροχή θα φαινόταν ίδιο με ένα που **δεν ρωτήθηκε ποτέ**.
   *
   * 🏆 **Αυτή είναι η τρίτη κατάσταση που Zillow · idealista · Spitogatos δεν έχουν**:
   * εκεί και τα δύο καταλήγουν στην ίδια σιωπή. Είναι το ίδιο επιχείρημα με το
   * `never-asked` vs `owner-declined` της θέσης (Α5 §3) — και ο λόγος που ο τύπος
   * είναι `readonly X[] | null` και **ποτέ** `readonly X[]` με προεπιλογή `[]`.
   *
   * ⚠️ **Και ο ΤΡΟΠΟΣ εμφάνισης είναι πράγματι άλλος**: ετικέτες πολλαπλών τιμών, όχι
   * γραμμή ετικέτα/τιμή. Δύο πεδία με τον ίδιο ρόλο εμφανίζονται με τον ίδιο
   * μηχανισμό — αυτός ο κανόνας του πίνακα είναι που **απαιτεί** τον χωρισμό.
   */
  | 'feature-set'
  /** Οι διαθέσεις (Α20) — ο άξονας όπου δεν χάνεται τίποτα. */
  | 'offers'
  /** Η θέση: σχήμα στον χάρτη **και** η ακρίβειά του σε λέξεις (Α5). */
  | 'position'
  /** Πότε ανακατασκευάστηκε αυτή η προβολή — κανόνας 18 (προέλευση). */
  | 'provenance'
  /**
   * **Ο δεσμός προς το επίπεδο Α** (§14.5) — ταξιδεύει, **δεν ζωγραφίζεται**.
   *
   * Τροφοδοτεί τη μηχανή ταιριάσματος της ζήτησης (Ζ3/Ζ5: *«αυτό το κτίριο»*). Ένα
   * `land_*`/`pbld_*` τυπωμένο ωμό θα ήταν **ταυτότητα σε οθόνη ανθρώπου**.
   */
  | 'place-link'
  /**
   * **Ο δεσμός προς τη ΔΙΟΙΚΗΤΙΚΗ ΠΕΡΙΟΧΗ** (ADR-890 Φ0) — ταξιδεύει, **δεν ζωγραφίζεται**.
   *
   * Τροφοδοτεί τη σελίδα περιοχής και τη σύνοψη αγοράς (ADR-890 §5.2) με **ερώτημα**, όχι με
   * σημείο-σε-πολύγωνο κάθε νύχτα. ⛔ **ΔΕΝ είναι `'position'`**: εκείνο ζωγραφίζει σχήμα στον χάρτη
   * με την ακρίβειά του· αυτό είναι **παράγωγο** της θέσης, και ένα `municipality:0708` τυπωμένο
   * ωμό θα ήταν ταυτότητα σε οθόνη ανθρώπου — το όνομα το δίνει το ευρετήριο, όταν η Φ1 το δείξει.
   */
  | 'area-link'
  /**
   * **Ο δεσμός προς το ΓΡΑΦΕΙΟ** (ADR-841 Α1.6) — ταξιδεύει, **δεν ζωγραφίζεται**.
   *
   * Τροφοδοτεί δύο πράγματα που η συμβολοσειρά της επωνυμίας **δεν μπορεί**: τη
   * **βιτρίνα** *(Φ7: `agency_profiles/{companyId}`, σημειακή ανάγνωση)* και την
   * **επαλήθευση του αντιγράφου** *(«συμφωνεί η επωνυμία με την πηγή;»)*.
   *
   * ⛔ **ΞΕΧΩΡΙΣΤΟΣ ΡΟΛΟΣ ΑΠΟ ΤΟ `'authorship'`, ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΛΕΠΤΟΛΟΓΙΑ.** Εκείνος
   * υπόσχεται ότι τα πεδία του *«εμφανίζονται **μαζί ή καθόλου**»* — πρόταση που θα
   * γινόταν **ψευδής** την ώρα που ένα τρίτο, μη εμφανιζόμενο πεδίο έμπαινε από κάτω
   * της. Ένα `comp_*` τυπωμένο ωμό θα ήταν **ταυτότητα σε οθόνη ανθρώπου**, ακριβώς
   * ό,τι αποτρέπει το `'place-link'` για τα `land_*`/`pbld_*`.
   */
  | 'agency-link'
  /**
   * **Η υπογραφή της αγγελίας** (§8.33) — *ποιος τη δηλώνει, ως **κλάση***.
   *
   * ⚠️ Ένας ρόλος για **δύο** πεδία, και είναι σωστό: το `authorship` και το
   * `agencyName` εμφανίζονται **μαζί ή καθόλου** (η επωνυμία χωρίς την κλάση δεν λέει
   * τι είδους γνώση είναι· η κλάση `'agency'` χωρίς επωνυμία πέφτει στο
   * `agencyAnonymous`). Δύο ρόλοι θα επέτρεπαν να εμφανιστεί το ένα χωρίς το άλλο.
   */
  | 'authorship'
  /**
   * **Οι όροι διαμονής** (ADR-835 §4.5) — `null` όταν δεν είναι κατάλυμα.
   *
   * ⛔ **ΔΕΝ είναι `'attribute'`, και η διάκριση δεν είναι λεπτολογία**: οι ιδιότητες
   * δείχνονται *«και όταν λείπουν»* (§25.6), γιατί κάθε ακίνητο **σηκώνει** την
   * ερώτηση «πόσα τ.μ.;». Ένα ακίνητο **προς πώληση** δεν σηκώνει την ερώτηση «πόσες
   * ελάχιστες νύχτες;» — και ένα «Δεν έχει δηλωθεί» εκεί θα κατηγορούσε τον κάτοχο
   * για πεδίο που **δεν του ζητήθηκε ποτέ**. Ίδιο μάθημα με τη **γη που δεν κρίνεται
   * σε υπνοδωμάτια** (§8.32).
   */
  | 'stay-terms'
  /**
   * **Η νομιμότητα ως κλίμακα με προέλευση** (Α17 · ADR-838).
   *
   * ⛔ **ΔΕΝ είναι `'attribute'`, για τον ίδιο λόγο με το `'stay-terms'` και για έναν
   * βαρύτερο**: μια ιδιότητα που λείπει διαβάζεται *«ο κάτοχος δεν το συμπλήρωσε»* —
   * ουδέτερο για τα τετραγωνικά, **κατηγορία** για τη νομιμότητα. Η απουσία εδώ έχει
   * **δικό της όνομα και δική της σημείωση** (*«το κενό ανήκει στον κάτοχο — δεν
   * σημαίνει ότι υπάρχει πρόβλημα»*), και αυτό δεν χωρά σε γραμμή ιδιότητας.
   *
   * ⛔ **Και ΠΟΤΕ `'media'`**: το `'media'` υπονοεί αρχείο. Εδώ **δεν φεύγει έγγραφο**.
   */
  | 'legality'
  /**
   * **Πότε μπήκε στην αγορά** (ADR-777 §8.61) — και η εμφάνισή του είναι **ο κανόνας
   * σειράς**, όχι γραμμή στην κάρτα.
   *
   * ⛔ **ΔΕΝ είναι `'provenance'`**: εκείνο απαντά *«πότε ξαναχτίστηκε αυτή η προβολή»*
   * — δικό μας μεταδεδομένο. Αυτό είναι **γεγονός της αγοράς** που οδηγεί την
   * προεπιλεγμένη κατάταξη *(«νεότερες πρώτα»)*.
   *
   * ⛔ **ΚΑΙ ΔΕΝ είναι `'attribute'`**: μια ιδιότητα που λείπει διαβάζεται *«ο κάτοχος
   * δεν το συμπλήρωσε»* — εδώ η απουσία είναι **δικό μας** κενό (`predates-record`) ή
   * **δική μας βλάβη** (`not-recorded`), ποτέ σιωπή του ανθρώπου.
   *
   * 🔑 **Η απουσία δηλώνεται ΜΙΑ φορά, στον έλεγχο ταξινόμησης** *(«οι αγγελίες χωρίς
   * καταγεγραμμένη ημερομηνία εμφανίζονται τελευταίες»)*, και **όχι** ανά κάρτα: η
   * υποχρέωση διαφάνειας (Καν. ΕΕ 2019/1150 · Οδηγία ΕΕ 2019/2161) αφορά τα
   * **κριτήρια κατάταξης**, δηλαδή τον κανόνα.
   */
  | 'market-entry'
  /**
   * **Η μείωση τιμής σε ισχύ** (ADR-777 §8.69) — σήμανση δίπλα στην τιμή, **ποτέ** δική
   * της γραμμή.
   *
   * ⛔ **ΔΕΝ είναι `'price'`**: εκείνος ο ρόλος υπόσχεται ότι το πεδίο *«τροφοδοτεί τον
   * SSoT τιμής»*. Η μείωση **δεν** τον τροφοδοτεί — είναι **συμπέρασμα από ιστορικό**, με
   * δικό του κριτή (`lib/listings/price-history.ts`) και δική του λήξη (30 ημέρες). Δύο
   * πεδία με τον ίδιο ρόλο εμφανίζονται με τον ίδιο μηχανισμό, και εδώ ο μηχανισμός είναι
   * **άλλος**.
   *
   * ⛔ **ΚΑΙ ΔΕΝ είναι `'market-entry'`**: εκείνο οδηγεί **σειρά**· αυτό οδηγεί **σήμανση
   * και ειδοποίηση**.
   */
  | 'price-reduction'
  /**
   * **Ο όρος της αντιπαροχής** (ADR-777 §8.60.17) — το ποσοστό του **οικοπεδούχου**, `null` όταν η
   * αντιπαροχή δεν διατίθεται. Δείχνεται **δίπλα στη διάθεσή του** («Τι προσφέρεται»).
   *
   * ⛔ **ΔΕΝ είναι `'price'`**: δεν είναι ευρώ, και δεν τροφοδοτεί τον SSoT τιμής — ένα 40 εκεί θα
   * διαβαζόταν «40 €». ⛔ **ΚΑΙ ΔΕΝ είναι `'stay-terms'`**: ίδιος μηχανισμός (όρος δεμένος σε
   * διάθεση, `null` χωρίς αυτήν), **άλλη** διάθεση — ένας κοινός ρόλος θα έλεγε ότι ζωγραφίζονται
   * μαζί, ενώ ζουν σε άλλα σημεία της σελίδας.
   */
  | 'exchange-terms'
  /**
   * **Τα στοιχεία της αντικειμενικής αξίας που δήλωσε ο αγγελιοδότης** (ADR-898 Φ3β) — ή μόνο ότι επέλεξε απόκρυψη —
   * και το **μικτό ανά όροφο** πολυεπίπεδης κατοικίας (`levelAreas`, Φ3β-3β). Δεν ζωγραφίζονται ως γραμμή: **τροφοδοτούν** τον υπολογισμό κατά την ανάγνωση (`listingObjectiveValue`), και
   * η ενότητα της αντικειμενικής λέει δίπλα σε ό,τι μπήκε «δήλωση του αγγελιοδότη».
   *
   * ⛔ **ΔΕΝ είναι `'attribute'`**: θα έμπαινε στη λογιστική και στη λίστα χαρακτηριστικών — ένα «μικτά με
   * κοινόχρηστους: ναι» ως γραμμή δεν λέει τίποτα στον αγοραστή χωρίς τον υπολογισμό. ⛔ **ΚΑΙ ΔΕΝ είναι
   * `'price'`**: η αντικειμενική είναι φορολογικός κανόνας, όχι τιμή του ακινήτου (ADR-898 §6).
   */
  | 'valuation-basis'
  /**
   * **Η παρουσία περιήγησης 360°** (ADR-884 · ADR-777 §8.88) — *«υπάρχει περιήγηση που φαίνεται σε αυτή την
   * αγγελία;»*, ή `null`. Γίνεται ορατή ως **σήμα** στην κάρτα και ως **είσοδος** στη σελίδα· ρωτιέται **μόνο**
   * μέσω του κριτή `lib/listings/listing-spatial-media`.
   *
   * ⛔ **ΔΕΝ είναι `'media'`**: το `'media'` υπόσχεται ότι *φεύγει αρχείο*. Εδώ **δεν φεύγει κανένα** — το πεδίο
   * είναι **αντίγραφο μιας απάντησης** (αυθεντία: `readTourPresence`), και οι στάσεις της περιήγησης σερβίρονται
   * από δικό τους δρόμο, με δική τους ορατότητα. Ως `'media'` θα έλεγε ότι η προβολή **κουβαλά** την περιήγηση,
   * και ο επόμενος θα έψαχνε εδώ URL που δεν υπάρχει. Ίδιο μάθημα με το `'legality'` (*«ποτέ `'media'`»*).
   */
  | 'tour-presence';
