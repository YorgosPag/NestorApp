/**
 * @fileoverview **ΟΙ ΟΙΚΟΓΕΝΕΙΕΣ ΤΟΥ ΔΗΜΟΣΙΟΥ ΚΑΤΑΛΟΓΟΥ — ΚΛΕΙΣΤΟ ΣΥΝΟΛΟ, ΜΙΑ ΦΟΡΑ.**
 * @related ADR-843 §10.16 · ADR-841 §7 Α1 · ADR-777 Α14 · services/listings/rebuild-public-listings.service.ts
 * @module lib/listings/listing-families
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ: ΤΟ «ΔΥΟ ΟΙΚΟΓΕΝΕΙΕΣ» ΗΤΑΝ ΓΝΩΣΗ ΧΩΡΙΣ ΚΑΤΟΙΚΙΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `public_listings` τροφοδοτείται από **δύο** πηγές. Αυτό το ήξεραν —σωστά και
 * ονομαστικά— ο **ανακατασκευαστής** *(«ΟΙΚΟΓΕΝΕΙΑ Α» / «ΟΙΚΟΓΕΝΕΙΑ Β» σε σχόλια)*,
 * ο **γραφέας** και οι **κανόνες**. Το ήξεραν ως **πρόζα**, ο καθένας χωριστά.
 *
 * 🔴 **Και γι' αυτό ο κριτής της πρώτης επαφής ρωτούσε ΜΙΑ** (ADR-843 §10.15): κανένα
 * αρχείο δεν **δήλωνε** το σύνολο, άρα κανείς δεν μπορούσε να **ξεχάσει** μια
 * οικογένεια — γιατί δεν υπήρχε λίστα από την οποία να λείψει. Μετρημένο κόστος:
 * **6 στις 8** ζωντανές αγγελίες δέχονταν *«η αγγελία δεν υπάρχει»*.
 *
 * ⇒ Εδώ το σύνολο αποκτά **κατοικία**. Από τη στιγμή που υπάρχει, μια τρίτη
 * οικογένεια είναι **γραμμή σε πίνακα** — και ο μεταγλωττιστής απαιτεί αναγνώστη
 * γι' αυτήν *(δες `LISTING_FAMILY_READERS` στο `listing-resolver.ts`)*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 Η ΔΡΟΜΟΛΟΓΗΣΗ ΕΙΝΑΙ ΤΟ ΠΡΟΘΕΜΑ — ΔΑΝΕΙΟ ΑΠΟ ΤΟ STRIPE, ΟΧΙ ΕΦΕΥΡΕΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το Stripe δίνει σε κάθε αντικείμενο πρόθεμα τύπου (`cus_` · `inv_` · `sub_`) από
 * το 2012, και ο **δηλωμένος** λόγος είναι ακριβώς ο δικός μας: *«απορρίπτεις λάθος
 * ταυτότητα **αμέσως, χωρίς ερώτημα στη βάση**»*.
 *
 * 🔑 **Και εμείς δεν το εφευρίσκουμε — το έχουμε ήδη**: το `ENTERPRISE_ID_PREFIXES`
 * (N.6) ορίζει `prop` και `ownp`, και το `enterprise-id-prefixes.ts` **εξηγεί
 * ονομαστικά** γιατί είναι χωριστά: *«δύο πράγματα με διαφορετικό γραφέα,
 * διαφορετικό πεδίο απομόνωσης και διαφορετικούς κανόνες»*. Αυτό το αρχείο απλώς
 * **διαβάζει** εκείνη την απόφαση αντί να τη μαντέψει με `startsWith('prop_')`.
 *
 * ⚠️ **Η εναλλακτική «ρώτα και τις δύο συλλογές και κράτα όποια απαντήσει» απορρίφθηκε
 * μετρημένα**: πληρώνει **δύο** αναγνώσεις για κάθε πράξη, και —χειρότερα— κάνει το
 * *«δεν υπάρχει»* **αδιάκριτο** από το *«δεν ξέρω ποια οικογένεια είναι»*, που είναι
 * ακριβώς η διάκριση βλάβης/απουσίας που ο κριτής υπάρχει για να κρατά.
 *
 * **Layering**: καθαρό — μηδέν Firestore, μηδέν ρολόι, μηδέν `server-only`.
 */

import { COLLECTIONS } from '@/config/firestore-collections';
import { ENTERPRISE_ID_PREFIXES } from '@/services/enterprise-id-prefixes';

// =============================================================================
// 1. ΤΟ ΚΛΕΙΣΤΟ ΣΥΝΟΛΟ
// =============================================================================

/**
 * **Ποιες οικογένειες φτάνουν στον δημόσιο κατάλογο.**
 *
 * ⚠️ **Τα ονόματα ΔΕΝ είναι νέο λεξιλόγιο**: είναι οι δύο τιμές που ο δημόσιος τύπος
 * ήδη γράφει στο πεδίο `authorship` (`'agency'` · `'owner-declared'`), κομμένες στη
 * ρίζα τους. Ένα τρίτο ζεύγος ονομάτων για το ίδιο πράγμα θα ήταν το σχήμα του
 * ADR-749: δύο λεξιλόγια που «δουλεύουν» και αποκλίνουν στην πρώτη προσθήκη.
 */
export const LISTING_FAMILIES = ['agency', 'owner'] as const;

export type ListingFamily = (typeof LISTING_FAMILIES)[number];

/**
 * **Πού ζει μια οικογένεια, και πώς αναγνωρίζεται η ταυτότητά της.**
 *
 * 🔑 **Τα δύο πεδία ζουν ΜΑΖΙ επίτηδες.** Είναι οι δύο όψεις της ίδιας απόφασης
 * («αυτό το είδος αγγελίας»), και χωρισμένα σε δύο πίνακες θα μπορούσαν να
 * αποκλίνουν — πρόθεμα που δείχνει σε συλλογή που δεν το περιμένει είναι σφάλμα
 * **μη ανιχνεύσιμο**: κάθε ανάγνωση θα γύριζε ήσυχα `'absent'`.
 */
export interface ListingFamilyDeclaration {
  /** Η συλλογή Firestore όπου ζει το **ιδιωτικό** έγγραφο της αγγελίας. */
  readonly collection: string;
  /** Το πρόθεμα ταυτότητας του N.6 — **χωρίς** την κάτω παύλα. */
  readonly idPrefix: string;
}

/**
 * 🔴 **Η ΑΥΘΕΝΤΙΑ.** Ο ανακατασκευαστής σαρώνει **αυτές** τις συλλογές· ο επιλυτής
 * διαβάζει **αυτές**· και η άγκυρα του §10.16 συγκρίνει τα δύο σύνολα.
 *
 * ⚠️ **`Record<ListingFamily, …>` και όχι πίνακας**: ο τύπος **απαιτεί** γραμμή για
 * κάθε οικογένεια. Μια τρίτη προστίθεται στο {@link LISTING_FAMILIES} και ο
 * μεταγλωττιστής **σταματά** μέχρι να δηλωθεί πού ζει — αντί να «δουλέψει» σιωπηλά.
 */
export const LISTING_FAMILY: Record<ListingFamily, ListingFamilyDeclaration> = {
  /** Ο **επαγγελματίας**: μονάδα μέσα σε κτίριο μέσα σε έργο εταιρείας. */
  agency: {
    collection: COLLECTIONS.PROPERTIES,
    idPrefix: ENTERPRISE_ID_PREFIXES.PROPERTY,
  },
  /** Ο **ιδιώτης**: το ακίνητο όπως το δηλώνει ο ίδιος ο κάτοχός του (ADR-777 Α14). */
  owner: {
    collection: COLLECTIONS.OWNER_PROPERTIES,
    idPrefix: ENTERPRISE_ID_PREFIXES.OWNER_PROPERTY,
  },
};

/** Οι συλλογές, ως σύνολο — η μορφή που ρωτά η άγκυρα. */
export const LISTING_FAMILY_COLLECTIONS: readonly string[] = LISTING_FAMILIES.map(
  (family) => LISTING_FAMILY[family].collection,
);

// =============================================================================
// 2. Η ΔΡΟΜΟΛΟΓΗΣΗ — από την ταυτότητα, fail-closed
// =============================================================================

/**
 * **Ποιας οικογένειας είναι αυτή η ταυτότητα;** — `null` όταν **καμίας**.
 *
 * 🔑 **Το `null` είναι απάντηση, όχι αποτυχία**: σημαίνει *«αυτό δεν είναι ταυτότητα
 * αγγελίας»*. Ταυτότητα από άλλο σύμπαν (`cont_*`, `dmnd_*`, σκουπίδι από το δίκτυο)
 * απορρίπτεται **πριν** αγγίξει τη βάση — που είναι ολόκληρο το κέρδος του
 * προθέματος.
 *
 * ⚠️ **Ζητά την κάτω παύλα.** Χωρίς αυτήν, ένα υποθετικό μελλοντικό πρόθεμα `propx`
 * θα ταίριαζε με το `prop` και θα δρομολογούνταν σε **λάθος** συλλογή — σιωπηλά, με
 * απάντηση «δεν υπάρχει».
 */
export function familyOfListingId(listingId: string): ListingFamily | null {
  for (const family of LISTING_FAMILIES) {
    if (listingId.startsWith(`${LISTING_FAMILY[family].idPrefix}_`)) return family;
  }
  return null;
}
