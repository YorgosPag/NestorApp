/**
 * @fileoverview **Η ΛΟΓΙΣΤΙΚΗ ΑΠΟΚΑΛΥΨΗΣ** — κάθε δημοσιευμένο πεδίο ή φαίνεται, ή η
 * απουσία του ονομάζεται. Καμία τρίτη περίπτωση.
 * @related ADR-777 §7 (Α3 οθόνη 3 · Α7 προοδευτική αποκάλυψη · Α17) · SPEC-777-RESEARCH §25.6
 * @module lib/listings/listing-disclosure
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΕΥΡΗΜΑ ΠΟΥ ΟΡΙΣΕ ΤΗΝ ΟΘΟΝΗ 3 — μετρημένο, και ανατρέπει την προδιαγραφή
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η **Α3** περιγράφει την οθόνη 3 ως *«τα **υπόλοιπα** πεδία, κάτοψη, φάκελος,
 * νομιμότητα»*. Μετρήθηκε το κλειστό σχήμα του {@link PublicListing}: έχει **12**
 * πεδία, και η κάρτα της οθόνης 2 δείχνει ήδη **8** από αυτά. Τα «υπόλοιπα» είναι:
 * ο **τύπος** (5ο βασικό πεδίο του §25.6, που η κάρτα **δεν** δείχνει), η **προέλευση
 * της θέσης**, η **προέλευση της τιμής**, και η **στιγμή ανακατασκευής**.
 *
 * ⇒ Η οθόνη 3 **δεν έχει άλλα δεδομένα να δείξει.** Αν χτιζόταν ως «πιο πλούσια
 * κάρτα», θα ήταν η ίδια κάρτα με μεγαλύτερα γράμματα.
 *
 * **Άρα η οθόνη 3 δεν είναι περισσότερα ΠΕΔΙΑ — είναι περισσότερη ΑΛΗΘΕΙΑ για τα
 * ίδια πεδία:** από πού ξέρουμε ό,τι ξέρουμε, και τι δεν ξέρουμε καθόλου.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΓΙΑΤΙ ΑΥΤΟ ΞΕΠΕΡΝΑ ΤΗΝ ΠΡΑΚΤΙΚΗ ΤΗΣ ΑΓΟΡΑΣ, ΔΟΜΙΚΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Σε Zillow · Idealista · Spitogatos ένα πεδίο που λείπει **απλώς δεν εμφανίζεται**.
 * Ο αναγνώστης δεν μπορεί να ξεχωρίσει το *«δεν έχει όροφο»* από το *«κανείς δεν
 * καταχώρησε όροφο»* — και τα δύο μοιάζουν με σιωπή. Είναι **ακριβώς** το σχήμα που
 * κυνηγούν οι πύλες μας: **«0 = κανείς δεν κοίταξε»**, μεταφερμένο στην οθόνη.
 *
 * Εδώ η απουσία είναι **κατάσταση με όνομα**, όπως το `missing` του `price-resolver`
 * και οι τρεις καταστάσεις του `listing-coverage`.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 Η ΕΓΓΥΗΣΗ ΕΙΝΑΙ ΤΥΠΟΣ, ΟΧΙ ΣΥΜΒΑΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το {@link LISTING_DISCLOSURE} είναι `satisfies Record<keyof PublicListing, …>`.
 * Άρα **νέο πεδίο στην προβολή δεν μεταγλωττίζεται** μέχρι κάποιος να απαντήσει «πώς
 * το βλέπει ο κόσμος;». Ο κανόνας του `types/public-listing.ts` λέει ότι κάθε
 * προσθήκη πεδίου είναι **απόφαση δημοσιοποίησης**· εδώ η απόφαση αποκτά **δεύτερο
 * μισό** — δημοσιοποίηση χωρίς εμφάνιση είναι διαρροή χωρίς όφελος.
 *
 * ⚠️ **Και ο κατάλογος των ιδιοτήτων ΠΑΡΑΓΕΤΑΙ από τον ίδιο πίνακα**, δεν
 * ξαναγράφεται. Μια δεύτερη χειρόγραφη λίστα θα ήταν το σχήμα της CHECK 3.34 (δύο
 * λίστες namespace που **απέκλιναν κατά 63** χωρίς καμία πύλη να τις συγκρίνει).
 */

