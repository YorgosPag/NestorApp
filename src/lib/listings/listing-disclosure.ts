/**
 * Ο **ρόλος** ενός δημοσιευμένου πεδίου στην οθόνη 3.
 *
 * Δεν είναι κατηγορίες διάταξης· είναι απαντήσεις στο *«με ποιον τρόπο γίνεται αυτό
 * το πεδίο ορατό;»*. Δύο πεδία με τον ίδιο ρόλο εμφανίζονται με τον ίδιο μηχανισμό.
 */
export type DisclosureTreatment =
  /** Η ταυτότητα **είναι** η διεύθυνση της σελίδας — δεν ζωγραφίζεται ως περιεχόμενο. */
  | 'identity'
  /** Ο τίτλος του κατόχου, στην κορυφή. */
  | 'headline'
  /**
   * Τροφοδοτεί τον **SSoT τιμής** (`lib/properties/price-resolver`).
   *
   * ⛔ **ΠΟΤΕ ζωγραφισμένο ωμό** — και ειδικά το `commercialStatus`, που η **Α20**
   * ορίζει **ρητά lossy**: ένα ακίνητο μόνο προς αντιπαροχή προβάλλεται εκεί σε
   * `'unavailable'`. Τυπωμένο αυτούσιο, θα έλεγε «μη διαθέσιμο» για κάτι που
   * **είναι** διαθέσιμο — με άλλον τρόπο.
   */
  | 'price'
  /** Εικόνα εξωφύλλου, ή η ονομασμένη απουσία της. */
  | 'media'
  /** Μετρήσιμο χαρακτηριστικό — δείχνεται **και όταν λείπει** (§25.6). */
  | 'attribute'
  /** Οι διαθέσεις (Α20) — ο άξονας όπου δεν χάνεται τίποτα. */
  | 'offers'
  /** Η θέση: σχήμα στον χάρτη **και** η ακρίβειά του σε λέξεις (Α5). */
  | 'position'
  /** Πότε ανακατασκευάστηκε αυτή η προβολή — κανόνας 18 (προέλευση). */
  | 'provenance'
  /**
   * **Ο δεσμός προς το επίπεδο Α** (§14.5) — ταξιδεύει, **δεν ζωγραφίζεται**.
   *
   * Τροφοδοτεί τη μηχανή ταιριάσματος της ζήτησης (Ζ3/Ζ5: *«αυτό το κτίριο»*). Ένα
   * `land_*`/`pbld_*` τυπωμένο ωμό θα ήταν **ταυτότητα σε οθόνη ανθρώπου**.
   */
  | 'place-link'
  /**
   * **Ο δεσμός προς το ΓΡΑΦΕΙΟ** (ADR-841 Α1.6) — ταξιδεύει, **δεν ζωγραφίζεται**.
   *
   * Τροφοδοτεί δύο πράγματα που η συμβολοσειρά της επωνυμίας **δεν μπορεί**: τη
   * **βιτρίνα** *(Φ7: `agency_profiles/{companyId}`, σημειακή ανάγνωση)* και την
   * **επαλήθευση του αντιγράφου** *(«συμφωνεί η επωνυμία με την πηγή;»)*.
   *
   * ⛔ **ΞΕΧΩΡΙΣΤΟΣ ΡΟΛΟΣ ΑΠΟ ΤΟ `'authorship'`, ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΛΕΠΤΟΛΟΓΙΑ.** Εκείνος
   * υπόσχεται ότι τα πεδία του *«εμφανίζονται **μαζί ή καθόλου**»* — πρόταση που θα
   * γινόταν **ψευδής** την ώρα που ένα τρίτο, μη εμφανιζόμενο πεδίο έμπαινε από κάτω
   * της. Ένα `comp_*` τυπωμένο ωμό θα ήταν **ταυτότητα σε οθόνη ανθρώπου**, ακριβώς
   * ό,τι αποτρέπει το `'place-link'` για τα `land_*`/`pbld_*`.
   */
  | 'agency-link'
  /**
   * **Η υπογραφή της αγγελίας** (§8.33) — *ποιος τη δηλώνει, ως **κλάση***.
   *
   * ⚠️ Ένας ρόλος για **δύο** πεδία, και είναι σωστό: το `authorship` και το
   * `agencyName` εμφανίζονται **μαζί ή καθόλου** (η επωνυμία χωρίς την κλάση δεν λέει
   * τι είδους γνώση είναι· η κλάση `'agency'` χωρίς επωνυμία πέφτει στο
   * `agencyAnonymous`). Δύο ρόλοι θα επέτρεπαν να εμφανιστεί το ένα χωρίς το άλλο.
   */
  | 'authorship'
  /**
   * **Οι όροι διαμονής** (ADR-835 §4.5) — `null` όταν δεν είναι κατάλυμα.
   *
   * ⛔ **ΔΕΝ είναι `'attribute'`, και η διάκριση δεν είναι λεπτολογία**: οι ιδιότητες
   * δείχνονται *«και όταν λείπουν»* (§25.6), γιατί κάθε ακίνητο **σηκώνει** την
   * ερώτηση «πόσα τ.μ.;». Ένα ακίνητο **προς πώληση** δεν σηκώνει την ερώτηση «πόσες
   * ελάχιστες νύχτες;» — και ένα «Δεν έχει δηλωθεί» εκεί θα κατηγορούσε τον κάτοχο
   * για πεδίο που **δεν του ζητήθηκε ποτέ**. Ίδιο μάθημα με τη **γη που δεν κρίνεται
   * σε υπνοδωμάτια** (§8.32).
   */
  | 'stay-terms'
  /**
   * **Η νομιμότητα ως κλίμακα με προέλευση** (Α17 · ADR-838).
   *
   * ⛔ **ΔΕΝ είναι `'attribute'`, για τον ίδιο λόγο με το `'stay-terms'` και για έναν
   * βαρύτερο**: μια ιδιότητα που λείπει διαβάζεται *«ο κάτοχος δεν το συμπλήρωσε»* —
   * ουδέτερο για τα τετραγωνικά, **κατηγορία** για τη νομιμότητα. Η απουσία εδώ έχει
   * **δικό της όνομα και δική της σημείωση** (*«το κενό ανήκει στον κάτοχο — δεν
   * σημαίνει ότι υπάρχει πρόβλημα»*), και αυτό δεν χωρά σε γραμμή ιδιότητας.
   *
   * ⛔ **Και ΠΟΤΕ `'media'`**: το `'media'` υπονοεί αρχείο. Εδώ **δεν φεύγει έγγραφο**.
   */
  | 'legality';

