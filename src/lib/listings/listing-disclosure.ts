// 4. ΤΑ ΘΕΜΑΤΑ ΠΟΥ Η Α3 ΥΠΟΣΧΕΘΗΚΕ ΚΑΙ ΔΕΝ ΥΠΑΡΧΟΥΝ — δηλωμένα, όχι σιωπηλά
// ============================================================================

/**
 * **Τι υποσχέθηκε η Α3 για την οθόνη 3 και δεν υπάρχει στον κώδικα σήμερα.**
 *
 * 🔴 **Δεν είναι λίστα «μελλοντικών χαρακτηριστικών» — είναι μέρος της αποκάλυψης.**
 * Η **Α7** δεσμεύτηκε *«δεν θα κρύψουμε τίποτε»*· η σιωπή για ένα θέμα που ο
 * επισκέπτης **περιμένει** να βρει σε σελίδα ακινήτου (νομιμότητα, κάτοψη, φάκελος)
 * διαβάζεται ως *«δεν έχει»*, όχι ως *«δεν το δημοσιεύουμε ακόμη»*. Δύο πολύ
 * διαφορετικοί ισχυρισμοί, και ο πρώτος είναι **ψευδής**.
 *
 * | Θέμα | Γιατί λείπει | Πού ανήκει η θεραπεία |
 * |---|---|---|
 * | `legality` | **Α17**: κλίμακα 4 καταστάσεων με ρητή προέλευση· grep σε `types/` · `lib/` · `constants/` ⇒ **μηδέν** | δικό της SSoT, **ποτέ** μέσα στην προβολή |
 * | `floorplan` | **καμία** εγγραφή στο κλειστό σχήμα — δεν είναι «άδειο πεδίο», δεν υπάρχει πεδίο | παραγωγός artifact (Α19, κανόνας 31) |
 * | `dossier` | ο φάκελος εγγράφων ζει σε **tenant-scoped** συλλογές· δημοσιοποίηση = απόφαση, όχι σύνδεσμος | ξεχωριστή απόφαση δημοσιοποίησης |
 *
 * ⛔ **ΜΗΝ τα «λύσεις» επινοώντας τιμή στην οθόνη.** Μια νομιμότητα μαντεμένη από
 * μια σελίδα είναι **χειρότερη** από απούσα: η **Α17** υπάρχει επειδή η βεβαίωση
 * μηχανικού είναι **υποχρεωτική στη μεταβίβαση** (άρθρο 83 ν. 4495/2017) — ένας
 * επισκέπτης που διάβασε «νόμιμο» σε αγγελία και το βρήκε αλλιώς στο συμβολαιογραφείο
 * δεν έχασε ένα χαρακτηριστικό, έχασε την εμπιστοσύνη του στο σύνολο.
 */
export type ListingOpenSubject = 'legality' | 'floorplan' | 'dossier';

/** Κλειστός κατάλογος, στη σειρά προτεραιότητας της Α3 (νομιμότητα πρώτη). */
export const LISTING_OPEN_SUBJECTS: readonly ListingOpenSubject[] = [
  'legality',
  'floorplan',
  'dossier',
];

// ============================================================================
// ΕΞΑΝΤΛΗΤΙΚΟΤΗΤΑ — fail-closed, με ΟΝΟΜΑ
// ============================================================================

/**
 * ⚠️ **Δεν επιστρέφει σιωπηλά `false`.** Μια άγνωστη ιδιότητα που πέφτει σε «δεν
 * δηλώθηκε» θα εμφανιζόταν στην οθόνη ως **υπαρκτό κενό του κατόχου** — δηλαδή το
 * σφάλμα μας θα φορούσε τη στολή δικού του χρέους, και θα μετριόταν στη λογιστική
 * σαν να ήταν αληθινό. Ίδιο πρότυπο με το `listing-map-shape.ts`.
 */
function assertNeverAttribute(key: never): never {
  // Μήνυμα προγραμματιστή, όχι οθόνης (σύμβαση src/lib + N.11).
  throw new Error(`isAttributeDeclared: unknown listing attribute — ${JSON.stringify(key)}`);
}
