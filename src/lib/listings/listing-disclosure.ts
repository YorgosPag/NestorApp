/**
 * @fileoverview **Η ΛΟΓΙΣΤΙΚΗ ΑΠΟΚΑΛΥΨΗΣ** — κάθε δημοσιευμένο πεδίο ή φαίνεται, ή η
 * απουσία του ονομάζεται. Καμία τρίτη περίπτωση.
 * @related ADR-777 §7 (Α3 οθόνη 3 · Α7 προοδευτική αποκάλυψη · Α17) · SPEC-777-RESEARCH §25.6
 * @module lib/listings/listing-disclosure
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΕΥΡΗΜΑ ΠΟΥ ΟΡΙΣΕ ΤΗΝ ΟΘΟΝΗ 3 — μετρημένο, και ανατρέπει την προδιαγραφή
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η **Α3** περιγράφει την οθόνη 3 ως *«τα **υπόλοιπα** πεδία, κάτοψη, φάκελος,
 * νομιμότητα»*. Μετρήθηκε το κλειστό σχήμα του {@link PublicListing}: έχει **12**
 * πεδία, και η κάρτα της οθόνης 2 δείχνει ήδη **8** από αυτά. Τα «υπόλοιπα» είναι:
 * ο **τύπος** (5ο βασικό πεδίο του §25.6, που η κάρτα **δεν** δείχνει), η **προέλευση
 * της θέσης**, η **προέλευση της τιμής**, και η **στιγμή ανακατασκευής**.
 *
 * ⇒ Η οθόνη 3 **δεν έχει άλλα δεδομένα να δείξει.** Αν χτιζόταν ως «πιο πλούσια
 * κάρτα», θα ήταν η ίδια κάρτα με μεγαλύτερα γράμματα.
 *
 * **Άρα η οθόνη 3 δεν είναι περισσότερα ΠΕΔΙΑ — είναι περισσότερη ΑΛΗΘΕΙΑ για τα
 * ίδια πεδία:** από πού ξέρουμε ό,τι ξέρουμε, και τι δεν ξέρουμε καθόλου.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΓΙΑΤΙ ΑΥΤΟ ΞΕΠΕΡΝΑ ΤΗΝ ΠΡΑΚΤΙΚΗ ΤΗΣ ΑΓΟΡΑΣ, ΔΟΜΙΚΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Σε Zillow · Idealista · Spitogatos ένα πεδίο που λείπει **απλώς δεν εμφανίζεται**.
 * Ο αναγνώστης δεν μπορεί να ξεχωρίσει το *«δεν έχει όροφο»* από το *«κανείς δεν
 * καταχώρησε όροφο»* — και τα δύο μοιάζουν με σιωπή. Είναι **ακριβώς** το σχήμα που
 * κυνηγούν οι πύλες μας: **«0 = κανείς δεν κοίταξε»**, μεταφερμένο στην οθόνη.
 *
 * Εδώ η απουσία είναι **κατάσταση με όνομα**, όπως το `missing` του `price-resolver`
 * και οι τρεις καταστάσεις του `listing-coverage`.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 Η ΕΓΓΥΗΣΗ ΕΙΝΑΙ ΤΥΠΟΣ, ΟΧΙ ΣΥΜΒΑΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το {@link LISTING_DISCLOSURE} είναι `satisfies Record<keyof PublicListing, …>`.
 * Άρα **νέο πεδίο στην προβολή δεν μεταγλωττίζεται** μέχρι κάποιος να απαντήσει «πώς
 * το βλέπει ο κόσμος;». Ο κανόνας του `types/public-listing.ts` λέει ότι κάθε
 * προσθήκη πεδίου είναι **απόφαση δημοσιοποίησης**· εδώ η απόφαση αποκτά **δεύτερο
 * μισό** — δημοσιοποίηση χωρίς εμφάνιση είναι διαρροή χωρίς όφελος.
 *
 * ⚠️ **Και ο κατάλογος των ιδιοτήτων ΠΑΡΑΓΕΤΑΙ από τον ίδιο πίνακα**, δεν
 * ξαναγράφεται. Μια δεύτερη χειρόγραφη λίστα θα ήταν το σχήμα της CHECK 3.34 (δύο
 * λίστες namespace που **απέκλιναν κατά 63** χωρίς καμία πύλη να τις συγκρίνει).
 */

import type { PublicListing } from '@/types/public-listing';
import { normalizePropertyType } from '@/constants/property-type-aliases';

// ============================================================================
// 1. ΠΩΣ ΒΛΕΠΕΙ Ο ΚΟΣΜΟΣ ΚΑΘΕ ΠΕΔΙΟ — κλειστός πίνακας
// ============================================================================

/**
 * Ο **ρόλος** ενός δημοσιευμένου πεδίου στην οθόνη 3.
 *
 * Δεν είναι κατηγορίες διάταξης· είναι απαντήσεις στο *«με ποιον τρόπο γίνεται αυτό
 * το πεδίο ορατό;»*. Δύο πεδία με τον ίδιο ρόλο εμφανίζονται με τον ίδιο μηχανισμό.
 */
export type DisclosureTreatment =
  /** Η ταυτότητα **είναι** η διεύθυνση της σελίδας — δεν ζωγραφίζεται ως περιεχόμενο. */
  | 'identity'
  /** Ο τίτλος του κατόχου, στην κορυφή. */
  | 'headline'
  /**
   * Τροφοδοτεί τον **SSoT τιμής** (`lib/properties/price-resolver`).
   *
   * ⛔ **ΠΟΤΕ ζωγραφισμένο ωμό** — και ειδικά το `commercialStatus`, που η **Α20**
   * ορίζει **ρητά lossy**: ένα ακίνητο μόνο προς αντιπαροχή προβάλλεται εκεί σε
   * `'unavailable'`. Τυπωμένο αυτούσιο, θα έλεγε «μη διαθέσιμο» για κάτι που
   * **είναι** διαθέσιμο — με άλλον τρόπο.
   */
  | 'price'
  /** Εικόνα εξωφύλλου, ή η ονομασμένη απουσία της. */
  | 'media'
  /** Μετρήσιμο χαρακτηριστικό — δείχνεται **και όταν λείπει** (§25.6). */
  | 'attribute'
  /** Οι διαθέσεις (Α20) — ο άξονας όπου δεν χάνεται τίποτα. */
  | 'offers'
  /** Η θέση: σχήμα στον χάρτη **και** η ακρίβειά του σε λέξεις (Α5). */
  | 'position'
  /** Πότε ανακατασκευάστηκε αυτή η προβολή — κανόνας 18 (προέλευση). */
  | 'provenance';

/**
 * **Κάθε πεδίο της δημόσιας προβολής, και πώς γίνεται ορατό.**
 *
 * 🔑 Η **σειρά των κλειδιών είναι συμβόλαιο**: από αυτήν παράγεται η σειρά εμφάνισης
 * των ιδιοτήτων ({@link LISTING_ATTRIBUTE_KEYS}). Αλλαγή σειράς εδώ = αλλαγή οθόνης,
 * και διαβάζεται ως τέτοια στο diff.
 *
 * ⚠️ Το `satisfies` **δεν** αντικαθίσταται με σκέτο annotation: χρειαζόμαστε **και**
 * την εξαντλητικότητα (`Record<keyof PublicListing, …>`) **και** τους κυριολεκτικούς
 * τύπους, ώστε το {@link ListingAttributeKey} να παραχθεί από **αυτόν** τον πίνακα.
 */
export const LISTING_DISCLOSURE = {
  id: 'identity',
  title: 'headline',
  commercialStatus: 'price',
  commercial: 'price',
  coverImage: 'media',
  // ── Οι ιδιότητες, ΣΤΗ ΣΕΙΡΑ ΠΟΥ ΕΜΦΑΝΙΖΟΝΤΑΙ ────────────────────────────────
  type: 'attribute',
  areaSqm: 'attribute',
  floor: 'attribute',
  bedrooms: 'attribute',
  // ───────────────────────────────────────────────────────────────────────────
  offerKinds: 'offers',
  position: 'position',
  projectedAt: 'provenance',
} as const satisfies Record<keyof PublicListing, DisclosureTreatment>;

// ============================================================================
// 2. ΟΙ ΙΔΙΟΤΗΤΕΣ — παραγόμενες από τον πίνακα, ποτέ ξαναγραμμένες
// ============================================================================

/**
 * Τα πεδία με ρόλο `'attribute'` — **τύπος παραγόμενος από το ίδιο literal**.
 *
 * 🔑 Ένα νέο `'attribute'` πεδίο μπαίνει **αυτόματα** και στον τύπο και στον κατάλογο,
 * και ταυτόχρονα **σπάει** το εξαντλητικό `switch` του {@link isAttributeDeclared} —
 * δηλαδή δεν μπορεί να προστεθεί χωρίς να απαντηθεί «πότε θεωρείται δηλωμένο;».
 */
export type ListingAttributeKey = {
  [K in keyof typeof LISTING_DISCLOSURE]: (typeof LISTING_DISCLOSURE)[K] extends 'attribute'
    ? K
    : never;
}[keyof typeof LISTING_DISCLOSURE];

/**
 * Ο κατάλογος των ιδιοτήτων, **στη σειρά του πίνακα**.
 *
 * ⚠️ Παράγεται με `Object.keys`, που για κλειδιά-συμβολοσειρές διατηρεί τη **σειρά
 * εισαγωγής** (ECMAScript `OrdinaryOwnPropertyKeys`). Ίδιο ιδίωμα με το
 * `LOCATION_PROVENANCES` (`lib/location/location-provenance`), που παράγεται από τον
 * πίνακα κατάταξης αντί να ξαναγραφεί δίπλα του.
 */
export const LISTING_ATTRIBUTE_KEYS: readonly ListingAttributeKey[] = (
  Object.keys(LISTING_DISCLOSURE) as (keyof typeof LISTING_DISCLOSURE)[]
).filter(
  (key): key is ListingAttributeKey => LISTING_DISCLOSURE[key] === 'attribute'
);

/**
 * Έχει **δηλωθεί** αυτή η ιδιότητα για τη συγκεκριμένη αγγελία;
 *
 * 🔴 **`0` είναι ΤΙΜΗ, όχι απουσία** — και οι δύο περιπτώσεις είναι πραγματικές:
 * `floor: 0` είναι **ισόγειο**, `bedrooms: 0` είναι **studio**. Ένας έλεγχος
 * αληθοφάνειας (`if (listing.floor)`) θα έκρυβε ακριβώς τα ισόγεια — και το
 * `types/public-listing.ts` το δηλώνει ρητά σε **δύο** πεδία, επειδή είναι το πρώτο
 * πράγμα που κάνει λάθος όποιος τα διαβάζει βιαστικά.
 *
 * 🔴 **Και «δηλωμένο» σημαίνει ΟΝΟΜΑΣΙΜΟ, όχι «μη κενό».** Ο τύπος `PropertyType`
 * περιλαμβάνει **παλαιές ελληνικές** τιμές του Firestore και **@deprecated**
 * παραλλαγές· ένα `type` που ο `normalizePropertyType` δεν αναγνωρίζει **δεν έχει
 * ετικέτα** να ζωγραφιστεί. Αν το μετρούσαμε ως δηλωμένο, η λογιστική θα έλεγε «4
 * από 4» ενώ η οθόνη θα έδειχνε **τρεις γραμμές** — δηλαδή θα ήταν το ίδιο ψέμα με
 * τη λίστα που λέει 11 και τον χάρτη που δείχνει 10 (κανόνας 27).
 */
export function isAttributeDeclared(
  listing: PublicListing,
  key: ListingAttributeKey
): boolean {
  switch (key) {
    case 'type':
      return normalizePropertyType(listing.type) !== null;
    case 'areaSqm':
      return listing.areaSqm !== null;
    case 'floor':
      return listing.floor !== null;
    case 'bedrooms':
      return listing.bedrooms !== null;
    default:
      return assertNeverAttribute(key);
  }
}

// ============================================================================
// 3. ΚΛΕΙΣΤΗ ΛΟΓΙΣΤΙΚΗ ΙΔΙΟΤΗΤΩΝ (κανόνας 27, στο επίπεδο ΠΕΔΙΟΥ)
// ============================================================================

/**
 * **«3 από 4 στοιχεία δηλωμένα»** — *πάντα*, ακόμη και όταν είναι 4 από 4.
 *
 * 🔑 Είναι η {@link ListingLedger} της οθόνης 2, μια βαθμίδα πιο κάτω: εκείνη μετρά
 * **αγγελίες**, αυτή μετρά **πεδία μιας αγγελίας**. Ίδιος κανόνας, ίδιος λόγος —
 * ένας αναγνώστης που βλέπει τρεις γραμμές δεν ξέρει αν έλειπε μία ή δέκα.
 *
 * ⚠️ **Τα δύο μέρη είναι ξεχωριστά πεδία, ΟΧΙ ένα με αφαίρεση** (ίδια σχεδίαση με το
 * {@link ListingLedger}): ένας καταναλωτής που υπολογίζει `total - declared` θα έχει
 * δίκιο μέχρι την πρώτη τρίτη κατηγορία, και μετά θα κλείνει **λάθος, σιωπηλά**.
 */
export interface ListingAttributeLedger {
  readonly total: number;
  readonly declared: number;
  readonly undeclared: number;
}

/** Η λογιστική των ιδιοτήτων μιας αγγελίας. **Καθαρή συνάρτηση.** */
export function listingAttributeLedger(listing: PublicListing): ListingAttributeLedger {
  const declared = LISTING_ATTRIBUTE_KEYS.filter((key) =>
    isAttributeDeclared(listing, key)
  ).length;

  return {
    total: LISTING_ATTRIBUTE_KEYS.length,
    declared,
    undeclared: LISTING_ATTRIBUTE_KEYS.length - declared,
  };
}

/**
 * Κλείνει το άθροισμα;
 *
 * 🔴 **Υπάρχει για να αποτύχει θορυβωδώς**, όπως το `ledgerBalances` του
 * `types/public-listing.ts`. Ίδιο εργαλείο, ίδιο επιχείρημα: μια λογιστική που δεν
 * μπορεί να πέσει έξω δεν είναι λογιστική, είναι διακόσμηση.
 */
export function attributeLedgerBalances(ledger: ListingAttributeLedger): boolean {
  return ledger.declared + ledger.undeclared === ledger.total;
}

