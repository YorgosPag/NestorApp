/**
 * @fileoverview **Η ΚΛΕΙΣΤΗ ΛΟΓΙΣΤΙΚΗ ΣΤΟΝ ΧΡΟΝΟ** — η **δεύτερη** διαμέριση.
 * @related ADR-835 §4.6 · ADR-777 §7 (Α5 κανόνας 27) · types/public-listing.ts ·
 *   lib/stay/stay-availability-vocabulary.ts · lib/listings/listing-coverage.ts
 * @module lib/listings/stay-ledger
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ **ΔΕΥΤΕΡΗ** ΛΟΓΙΣΤΙΚΗ ΚΑΙ ΟΧΙ ΤΡΕΙΣ ΚΑΔΟΙ ΠΑΡΑΠΑΝΩ ΣΤΗΝ ΠΡΩΤΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το {@link ListingLedger} απαντά *«πόσα έχουν **θέση**;»* (`total = mapped + unmapped`).
 * Το ADR-835 §4.6 ζητά επιπλέον *«πόσα είναι **ελεύθερα** στις ημερομηνίες σου;»*.
 *
 * 🔴 **ΠΡΟΣΘΗΚΗ ΤΩΝ ΝΕΩΝ ΚΑΔΩΝ ΣΤΟΝ ΙΔΙΟ ΤΥΠΟ ΚΑΝΕΙ ΤΟ `ledgerBalances` ΨΕΥΔΕΣ.** Οι
 * δύο ερωτήσεις είναι **ανεξάρτητες διαμερίσεις του ΙΔΙΟΥ συνόλου**, όχι κάδοι της
 * μιας: ένα ακίνητο είναι **ταυτόχρονα** `mapped` **και** `occupied`. Έξι κάδοι σε ένα
 * άθροισμα θα μετρούσαν **κάθε αγγελία δύο φορές** — και ο έλεγχος που υπάρχει *«για
 * να αποτύχει θορυβωδώς»* θα **κοκκίνιζε μονίμως**, δηλαδή θα έπαυε να σημαίνει κάτι.
 *
 * ```
 *                 ┌──────────── ΤΟ ΙΔΙΟ ΣΥΝΟΛΟ (total) ────────────┐
 * διαμέριση Α:    │  mapped                      │  unmapped      │   ← «πού;»
 * διαμέριση Β:    │ free │ occupied │ unknown │ not-a-stay │ …    │   ← «πότε;»
 *                 └───────────────────────────────────────────────┘
 * ```
 *
 * ✅ **Δύο τύποι, δύο `balances()`, ΕΝΑ `total`** — και ο έλεγχος ότι κλείνουν **και οι
 * δύο στο ίδιο σύνολο** ({@link ledgersAgree}) είναι *«ακριβώς το είδος άγκυρας που το
 * έργο ζητά: υπάρχει για να αποτύχει θορυβωδώς»*.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΚΑΙ ΓΙΑΤΙ ΑΥΤΟ ΞΕΠΕΡΝΑ ΤΗΝ ΑΓΟΡΑ — ΜΕΤΡΗΜΕΝΟ, ΟΧΙ ΡΗΤΟΡΙΚΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η καταγεγραμμένη συμπεριφορά κάθε πλατφόρμας κρατήσεων είναι *«the search algorithm
 * **completely hides** unavailable listings»*. Δηλαδή ο επισκέπτης βλέπει **3
 * αποτελέσματα** και δεν μαθαίνει ποτέ ότι υπήρχαν **14**, ούτε **γιατί** έφυγαν τα 11.
 *
 * Εδώ ο αριθμός που λείπει **τυπώνεται**:
 *
 *   > *«14 αγγελίες · 9 ελεύθερα · 4 κρατημένα · 1 χωρίς δηλωμένο ημερολόγιο»*
 *
 * Είναι η δική μας αποδεδειγμένη πρακτική των πυλών (**fail-closed**, *«το 0 τυπώνεται
 * ακόμη κι όταν είναι 0»*) μεταφερμένη στην οθόνη — και ο λόγος που οι άλλοι δεν το
 * κάνουν είναι ότι **δεν τους συμφέρει**: ο αριθμός που λείπει είναι το χρέος τους.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις, μηδέν I/O, μηδέν ρολόι.
 */

import type { PublicListing, ListingLedger } from '@/types/public-listing';
import {
  STAY_AVAILABILITY_KINDS,
  type StayAvailabilityAnswer,
  type StayAvailabilityKind,
} from '@/lib/stay/stay-availability-vocabulary';

// ============================================================================
// Ο ΤΥΠΟΣ
// ============================================================================

/**
 * **Η δεύτερη διαμέριση**: πόσα σε κάθε κάδο διαθεσιμότητας, στο ίδιο `total`.
 *
 * 🔑 **`Record` πάνω σε κλειστό σύνολο, ποτέ εννέα ξεχωριστά πεδία**: μια **δέκατη**
 * απάντηση που θα προστεθεί στο λεξιλόγιο **δεν μεταγλωττίζεται** μέχρι να αποκτήσει
 * κάδο — ο ίδιος φρουρός με το `STAY_LIFECYCLE_OCCUPIES`. Εννέα χειρόγραφα πεδία θα
 * δέχονταν τη δέκατη **σιωπηλά**, και το άθροισμα θα έκλεινε λάθος.
 *
 * ⚠️ **Το `total` είναι ΞΕΧΩΡΙΣΤΟ πεδίο, όχι άθροισμα των κάδων** — ίδιο δόγμα με το
 * `ListingLedger`: *«ένας καταναλωτής που υπολογίζει `total - mapped` θα έχει
 * δίκιο μέχρι την πρώτη φορά που κάποιος προσθέσει τρίτη κατηγορία»*. Εδώ το `total`
 * είναι η **ανεξάρτητη μαρτυρία** που κάνει το {@link stayLedgerBalances} να μπορεί
 * να πει «όχι».
 */
export interface StayLedger {
  /** Πόσα απάντησαν στο ερώτημα. **Ίδιο** με το `ListingLedger.total`. */
  readonly total: number;
  /** Πόσα σε κάθε κάδο. Κάθε τιμή του λεξιλογίου έχει θέση, **και στο μηδέν**. */
  readonly byKind: Readonly<Record<StayAvailabilityKind, number>>;
}

/** Όλοι οι κάδοι στο μηδέν — η αφετηρία, και η απάντηση για **κενό** σύνολο. */
function emptyBuckets(): Record<StayAvailabilityKind, number> {
  const buckets = {} as Record<StayAvailabilityKind, number>;
  // ⚠️ Παράγεται από το **κλειστό σύνολο**, ποτέ γραμμένο στο χέρι: μια χειρόγραφη
  //    λίστα εδώ θα ήταν **δεύτερη διατύπωση** που αποκλίνει την ημέρα που προστίθεται
  //    δέκατη τιμή — ακριβώς το σχήμα που πλήρωσε το `allowsOtherAgencies` (832 §5.1).
  for (const kind of STAY_AVAILABILITY_KINDS) buckets[kind] = 0;
  return buckets;
}

// ============================================================================
// Ο ΕΛΕΓΧΟΣ — «υπάρχει για να αποτύχει θορυβωδώς»
// ============================================================================

/**
 * Κλείνει το άθροισμα των κάδων στο `total`;
 *
 * 🔴 **Υπάρχει για να αποτύχει θορυβωδώς, όχι για να επιβεβαιώνει** — ίδιο εργαλείο με
 * το `ledgerBalances` της πρώτης διαμέρισης. Αν κάποτε προστεθεί απάντηση που δεν μετριέται σε κανέναν
 * κάδο, το εύρημα εμφανίζεται **εδώ**, αμέσως — και όχι ως οθόνη που δείχνει «9
 * ελεύθερα» από «14» χωρίς να λέει πού πήγαν τα υπόλοιπα 5.
 */
export function stayLedgerBalances(ledger: StayLedger): boolean {
  const sum = STAY_AVAILABILITY_KINDS.reduce((acc, kind) => acc + ledger.byKind[kind], 0);
  return sum === ledger.total;
}

/**
 * 🔴 **ΚΛΕΙΝΟΥΝ ΚΑΙ ΟΙ ΔΥΟ ΣΤΟ ΙΔΙΟ ΣΥΝΟΛΟ;** — η άγκυρα των δύο διαμερίσεων.
 *
 * Δύο ανεξάρτητες διαμερίσεις του **ίδιου** συνόλου οφείλουν να συμφωνούν στο πλήθος.
 * Αν διαφωνήσουν, κάποια από τις δύο μέτρησε **άλλο σύνολο** — π.χ. επειδή κάποιος
 * πέρασε στη μία τις φιλτραρισμένες αγγελίες και στην άλλη όλες. Η οθόνη θα έδειχνε
 * δύο αριθμούς για το ίδιο πράγμα, **χωρίς κανείς να μπορεί να πει ποιος είναι σωστός**
 * — το ακριβές σχήμα του ADR-749 (*τέσσερις μηχανές, τρεις αριθμοί για ένα δέντρο*).
 *
 * ⚠️ **Ελέγχει και τα τρία σκέλη**, όχι μόνο την ισότητα των `total`: μια διαμέριση
 * που δεν κλείνει **μόνη της** είναι ήδη σφάλμα, ακόμη κι αν τα σύνολα συμπίπτουν.
 */
export function ledgersAgree(position: ListingLedger, stay: StayLedger): boolean {
  if (position.total !== stay.total) return false;
  if (position.mapped + position.unmapped !== position.total) return false;
  return stayLedgerBalances(stay);
}

// ============================================================================
// Ο ΥΠΟΛΟΓΙΣΜΟΣ
// ============================================================================

/**
 * Αγγελίες + απαντήσεις → η δεύτερη λογιστική.
 *
 * @param listings — **το ίδιο** σύνολο που τροφοδοτεί το `computeListingLedger`.
 * @param answerFor — η απάντηση **ανά αγγελία**. Δες την προειδοποίηση παρακάτω.
 *
 * 🔴 **ΑΓΓΕΛΙΑ ΧΩΡΙΣ ΑΠΑΝΤΗΣΗ ΜΕΤΡΙΕΤΑΙ ΩΣ `unknown`, ΠΟΤΕ ΔΕΝ ΠΑΡΑΛΕΙΠΕΤΑΙ.** Είναι
 * η **μία** γραμμή που κρατά την υπόσχεση «δεν κρύβουμε τίποτα»: μια παράλειψη εδώ θα
 * έκανε το άθροισμα να **μην κλείνει**, και η θεραπεία θα ήταν να «διορθωθεί» το
 * `total` — δηλαδή να εξαφανιστεί η αγγελία **και** ο μάρτυρας της εξαφάνισής της.
 *
 * ⚠️ Και είναι **ειλικρινές**: όσο ο διακομιστής της Φ5 δεν απαντά ακόμη, **κάθε**
 * κατάλυμα είναι `unknown` — και η οθόνη το λέει με αριθμό, αντί να δείξει άδεια λίστα.
 */
export function computeStayLedger(
  listings: readonly PublicListing[],
  answerFor: (listing: PublicListing) => StayAvailabilityAnswer | undefined,
): StayLedger {
  const byKind = emptyBuckets();
  for (const listing of listings) {
    const answer = answerFor(listing);
    byKind[answer?.kind ?? 'unknown'] += 1;
  }
  return { total: listings.length, byKind };
}
