/**
 * **Πώς λέγεται στον επισκέπτη η προέλευση μιας κάτοψης** (ADR-841 §7 Α17.3).
 *
 * 🔴 **`Record<AttributeProvenance, …>` ΚΑΙ ΟΧΙ τα δύο κλειδιά που χρησιμοποιούνται
 * σήμερα — ΕΙΝΑΙ Η ΑΚΡΙΒΩΣ ΙΔΙΑ ΠΑΓΙΔΑ ΠΟΥ ΕΚΛΕΙΣΕ Η Α15.** Σήμερα ο μόνος παραγωγός
 * γράφει `'declared'`, οπότε ο πειρασμός είναι **ένα** κλειδί. Αλλά η οθόνη διαλέγει
 * **από την τιμή** του εγγράφου: την ημέρα που ο παραγωγός της **Φ4** γράψει
 * `'measured'`, μια σταθερά θα έδειχνε *«Δηλωμένη»* σε **μετρημένη** κάτοψη — ψέμα σε
 * ορατή γραμμή — και ένα ελλιπές `Record` θα έδειχνε **ωμό κλειδί**.
 *
 * 🔑 **Ο τύπος το κάνει αδύνατο**: νέα προέλευση στο `ATTRIBUTE_PROVENANCE_RANK` **σπάει
 * τη μεταγλώττιση εδώ** μέχρι να απαντηθεί *«πώς λέγεται στον άνθρωπο;»*. Ίδιο ιδίωμα με
 * το `LISTING_MATERIAL_KEYS` και τον εξαντλητικό `switch` του `isPubliclyPresentable`.
 *
 * ⚠️ **ΠΡΟΣΟΧΗ ΣΤΗΝ ΠΑΡΑΠΟΜΠΗ — ΕΙΝΑΙ ΑΛΛΟ ΛΕΞΙΛΟΓΙΟ** *(2026-09-08, ADR-845 §2.2)*. Ο
 * `switch` του `isPubliclyPresentable` *(`lib/property/attribute-provenance.ts:183`)*
 * υπάρχει και είναι εξαντλητικός, αλλά τρέχει πάνω στο **`AttributeProvenance`**, **όχι**
 * στο `ListingMaterialKind`. Αυτή ακριβώς η γειτνίαση έπεισε τρεις αναγνώστες ότι το
 * λεξιλόγιο **από πάνω** φυλασσόταν κι αυτό — ενώ δεν φυλασσόταν **καθόλου**.
 *
 * ⚠️ **Με πρόθεμα namespace**, όπως το `LISTING_MATERIAL_KEYS`: τα κλειδιά **ταξιδεύουν
 * ως τιμές** και καταλήγουν αυτούσια σε `t()`.
 */
