/**
 * @fileoverview **«ΤΙ ΕΙΝΑΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ;»** — η μία απάντηση (ADR-841 §7 Α17).
 * @related ADR-841 §7 (Α17.2 · Α17.4) · lib/listings/listing-authorship · lib/property/attribute-provenance
 * @module lib/listings/listing-material
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΔΕΥΤΕΡΗ ΕΡΩΤΗΣΗ, ΟΧΙ ΔΕΥΤΕΡΗ ΑΠΑΝΤΗΣΗ ΣΤΗΝ ΠΡΩΤΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `listing-authorship` απαντά *«**ΤΙΝΟΣ** υλικό είναι αυτό;»* *(κατόχου ή γραφείου)*.
 * Αυτό εδώ απαντά *«**ΤΙ** υλικό είναι αυτό;»* *(φωτογραφία ή κάτοψη)*. Οι δύο ερωτήσεις
 * είναι **ορθογώνιες**: μια κάτοψη μπορεί να είναι του κατόχου **ή** του γραφείου, και η
 * απάντηση της μιας δεν περιορίζει την άλλη. Γι' αυτό είναι **δύο** αρχεία και όχι ένα
 * αντικείμενο με τέσσερις συνδυασμούς — που θα ήταν το σχήμα του ADR-749 σε λεξιλόγιο.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ ΤΟ ΛΕΞΙΛΟΓΙΟ ΤΑΞΙΔΕΥΕΙ **ΜΕ ΤΑ BYTES**, ΚΑΙ ΟΧΙ ΔΙΠΛΑ ΤΟΥΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο πειρασμός είναι να χωριστούν οι φωτογραφίες από τις κατόψεις **πριν** το δημόσιο
 * ράφι, και να συμφιλιωθούν χωριστά. **Μετρήθηκε ότι είναι λάθος, δύο φορές:**
 *
 *   1. Το `reconcilePublicShelf` **πετά** τις πηγές που δεν καθαρίστηκαν
 *      *(`addressed.filter(… !== null)`)* ⇒ η σειρά της εξόδου **δεν** αντιστοιχεί
 *      θέση-προς-θέση στη σειρά της εισόδου. Αντιστοίχιση με **δείκτη** θα γινόταν
 *      **σιωπηλά λάθος** την πρώτη φορά που μια εικόνα απορριφθεί.
 *   2. **Δύο** κλήσεις του ραφιού είναι χειρότερα: το πρόθεμα είναι **ένα ανά αγγελία**,
 *      άρα το `deleteExtra` της καθεμιάς θα έσβηνε τα αντικείμενα της **άλλης**.
 *
 * ⇒ Το {@link ListingMaterial} **κουβαλιέται** από το ράφι, όπως ήδη κουβαλιέται το
 * `sourceRef`. ⛔ **Το ράφι ΔΕΝ το ερμηνεύει ΠΟΤΕ** — δεν είναι δουλειά μιας μηχανής που
 * ξέρει μόνο από bytes να αποφασίζει τι σημαίνει «κάτοψη». Η **μία** ερμηνεία ζει στο
 * `withPublishedGallery`, εκεί όπου ζει ήδη η **μία** απόφαση αποκάλυψης του `altKey`.
 */

import type { AttributeProvenance } from '@/lib/property/attribute-provenance';

// ============================================================================
// 1. ΤΟ ΛΕΞΙΛΟΓΙΟ — η λίστα είναι η πηγή, ο τύπος ΠΑΡΑΓΕΤΑΙ
// ============================================================================

/**
 * Τα είδη υλικού που μπορεί να φύγουν δημόσια.
 *
 * ⚠️ **`'photo'` και ΟΧΙ `'photos'`**: εδώ περιγράφεται **ένα** αρχείο, ενώ το
 * `FILE_CATEGORIES.PHOTOS` ονομάζει έναν **κάδο** αρχείων. Δύο διαφορετικά πράγματα
 * — και η διαφορά του ενικού είναι ακριβώς αυτό που εμποδίζει κάποιον να τα θεωρήσει
 * το ίδιο λεξιλόγιο και να τα «ενοποιήσει».
 *
 * ⛔ **ΔΕΝ επεκτείνει το `FILE_CATEGORIES`** *(9 τιμές: `documents`, `invoices`,
 * `contracts`, `permits`…)*, παρότι δύο από τις τιμές του μοιάζουν. Εκείνο απαντά *«σε
 * ποιον φάκελο της εταιρείας ανήκει;»* — ερώτηση **εσωτερικής διαχείρισης**, με τιμές
 * που **καμία** δεν έχει νόημα σε δημόσια αγγελία. Ένα συμβόλαιο δεν είναι είδος
 * δημόσιου υλικού· είναι λόγος να **μην** δημοσιευτεί τίποτα.
 */
export const LISTING_MATERIAL_KINDS = ['photo', 'floorplan'] as const;

/** Δες {@link LISTING_MATERIAL_KINDS}. **Κλειστή ένωση, ποτέ `string`.** */
export type ListingMaterialKind = (typeof LISTING_MATERIAL_KINDS)[number];

// ============================================================================
// 2. ΤΟ ΔΟΧΕΙΟ — διακριτή ένωση, ώστε η ΚΑΤΟΨΗ να μη μπορεί να ξεχάσει τη στιγμή της
// ============================================================================

/**
 * **Τι είναι αυτά τα bytes** — ταξιδεύει αυτούσιο από τη δήλωση του ανθρώπου ως το
 * δημόσιο έγγραφο.
 *
 * 🔴 **ΔΙΑΚΡΙΤΗ ΕΝΩΣΗ ΚΑΙ ΟΧΙ `{ kind, at? }`, ΚΑΙ ΕΙΝΑΙ Ο ΜΗΧΑΝΙΣΜΟΣ.** Το `at` είναι
 * **υποχρεωτικό** στο σκέλος της κάτοψης επειδή το δημόσιο έγγραφο τη γράφει ως
 * `SourcedAttribute`, και **κάθε** `SourcedAttribute` οφείλει να πει *πότε το έμαθε
 * αυτή η πηγή*. Ένα προαιρετικό `at` θα σήμαινε ότι ο γραφέας θα έπρεπε να **μαντέψει**
 * — και ο μόνος διαθέσιμος μάντης εκεί είναι το **ρολόι του διακομιστή**, που απαντά
 * λάθος ερώτηση *(«πότε το πρόβαλα», όχι «πότε το είπε ο άνθρωπος»)*.
 *
 * ⛔ **ΚΑΝΕΝΑ πεδίο `provenance` ΕΔΩ, ΕΠΙΤΗΔΕΣ.** Σήμερα ο μόνος παραγωγός κάτοψης είναι
 * **άνθρωπος** *(Α17.5)*, άρα ένα τέτοιο πεδίο θα είχε **μία μόνιμη τιμή** — δηλαδή θα
 * ήταν ακριβώς η «πρόταση αληθής όσο υπάρχει ΕΝΑΣ παραγωγός» που έκλεισε η **Α15**. Η
 * προέλευση ζει στο **δημόσιο σχήμα** (`ListingFloorplan = SourcedAttribute<ListingImage>`),
 * όπου όντως θα πάρει δεύτερη τιμή όταν υπάρξει ο παραγωγός της **Φ4**.
 *
 * 🔑 **Και τότε δεν θα χρειαστεί να το θυμηθεί κανείς**: ο παραγωγός της Φ4 θα προσθέσει
 * σκέλος εδώ, και ο εξαντλητικός κλάδος του `withPublishedGallery` **θα σπάσει τη
 * μεταγλώττιση** μέχρι να απαντηθεί *«τι προέλευση γράφεται στο έγγραφο;»*.
 */
export type ListingMaterial =
  | { readonly kind: 'photo' }
  | {
      readonly kind: 'floorplan';
      /**
       * ISO στιγμή — **πότε το δήλωσε ο άνθρωπος**.
       *
       * ⚠️ Στην πράξη είναι το `uploadedAt` του αρχείου: η στιγμή που το υλικό μπήκε
       * στο σύστημα **από την πηγή**. ⛔ **Ποτέ ρολόι διαβασμένο στον γραφέα** — αυτό
       * θα έγραφε *«πότε το πρόβαλα»* σε πεδίο που ρωτά *«πότε το έμαθε η πηγή»*.
       */
      readonly at: string;
    };

/**
 * **Φωτογραφία** — η σταθερά γράφεται μία φορά ώστε να μην υπάρχουν N κυριολεκτικά
 * `{ kind: 'photo' }` σκορπισμένα στους παραγωγούς.
 */
export const PHOTO_MATERIAL: ListingMaterial = { kind: 'photo' } as const;

/** **Κάτοψη δηλωμένη από άνθρωπο**, με τη στιγμή της δήλωσης. */
export function declaredFloorplanMaterial(at: string): ListingMaterial {
  return { kind: 'floorplan', at };
}

/**
 * **Ήταν αυτό δήλωση κάτοψης;** — γραμμένο μία φορά, ώστε ο έλεγχος να μη γίνει
 * `kind === 'floorplan'` σε πέντε σημεία που αύριο θα διαφωνήσουν.
 */
export function isFloorplanMaterial(
  material: ListingMaterial,
): material is Extract<ListingMaterial, { kind: 'floorplan' }> {
  return material.kind === 'floorplan';
}

