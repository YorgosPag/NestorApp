/** Οι σειρές που **υπάρχουν**. Ό,τι δεν είναι εδώ, δεν προσφέρεται και δεν εκτελείται. */
export const LISTING_ORDERS = ['newest', 'priceAsc', 'priceDesc'] as const;

export type ListingOrder = (typeof LISTING_ORDERS)[number];

/**
 * **Η προεπιλογή: νεότερες πρώτα.**
 *
 * 🔑 Είναι η **μόνη τίμια** προεπιλογή για αγορά ακινήτων: απαντά *«τι είναι καινούριο;»*
 * χωρίς να προτιμά κανέναν πωλητή, καμία τιμή και καμία τάξη συντάκτη.
 *
 * ⚠️ **Και δεν κρύβει τίποτα όταν δεν ξέρει**: οι αγγελίες χωρίς καταγεγραμμένη
 * ημερομηνία **δεν** παίρνουν ψεύτικη — πάνε στο τέλος, και η οθόνη το **λέει**.
 */
export const DEFAULT_LISTING_ORDER: ListingOrder = 'newest';

// ============================================================================
// ΟΙ ΣΥΓΚΡΙΤΕΣ — εξαγόμενοι ΟΝΟΜΑΣΤΙΚΑ, επίτηδες
// ============================================================================

/**
 * Το κλειδί χρόνου μιας αγγελίας — `null` όταν **δεν το ξέρουμε**.
 *
 * 🔑 **`null`, ποτέ η αρχή του χρόνου.** Ένα `'1970-01-01'` θα έλεγε «παλαιότατη», που
 * είναι **ισχυρισμός**· το `null` λέει «άγνωστη», που είναι η αλήθεια — και το
 * {@link compareSortValues} το κρατά στο τέλος **και στις δύο** κατευθύνσεις.
 */
function listedAtKey(listing: PublicListing): string | null {
  return listing.listedAt.kind === 'known' ? listing.listedAt.at : null;
}

/**
 * **Νεότερες πρώτα.**
 *
 * ⚠️ **Οι ISO συμβολοσειρές συγκρίνονται ως κείμενο, και είναι σωστό**: το ISO 8601 με
 * μηδενικά μπροστά είναι σχεδιασμένο ώστε η λεξικογραφική σειρά να **ταυτίζεται** με τη
 * χρονολογική. Καμία μετατροπή σε `Date` — θα ήταν N αντικείμενα ανά ταξινόμηση για
 * μηδενικό κέρδος.
 */
export function compareListingsByListedAt(a: PublicListing, b: PublicListing): number {
  const byTime = compareSortValues(listedAtKey(a), listedAtKey(b), 'desc');
  return byTime !== 0 ? byTime : compareByNameThenId(a.title, a.id, b.title, b.id);
}

