import { compareSortValues, type SortDirection } from '@/lib/array-utils';
import { compareByNameThenId } from '@/lib/ordering/total-name-order';
import { priceSortKey } from '@/lib/properties/price-resolver';
import type { PublicListing } from '@/types/public-listing';

// ============================================================================
// ΤΟ ΚΛΕΙΣΤΟ ΛΕΞΙΛΟΓΙΟ
// ============================================================================

/** Οι σειρές που **υπάρχουν**. Ό,τι δεν είναι εδώ, δεν προσφέρεται και δεν εκτελείται. */
export const LISTING_ORDERS = ['newest', 'priceAsc', 'priceDesc'] as const;

export type ListingOrder = (typeof LISTING_ORDERS)[number];

/**
 * **Η προεπιλογή: νεότερες πρώτα.**
 *
 * 🔑 Είναι η **μόνη τίμια** προεπιλογή για αγορά ακινήτων: απαντά *«τι είναι καινούριο;»*
 * χωρίς να προτιμά κανέναν πωλητή, καμία τιμή και καμία τάξη συντάκτη.
 *
 * ⚠️ **Και δεν κρύβει τίποτα όταν δεν ξέρει**: οι αγγελίες χωρίς καταγεγραμμένη
 * ημερομηνία **δεν** παίρνουν ψεύτικη — πάνε στο τέλος, και η οθόνη το **λέει**.
 */
export const DEFAULT_LISTING_ORDER: ListingOrder = 'newest';

// ============================================================================
// ΟΙ ΣΥΓΚΡΙΤΕΣ — εξαγόμενοι ΟΝΟΜΑΣΤΙΚΑ, επίτηδες
// ============================================================================

/**
 * Το κλειδί χρόνου μιας αγγελίας — `null` όταν **δεν το ξέρουμε**.
 *
 * 🔑 **`null`, ποτέ η αρχή του χρόνου.** Ένα `'1970-01-01'` θα έλεγε «παλαιότατη», που
 * είναι **ισχυρισμός**· το `null` λέει «άγνωστη», που είναι η αλήθεια — και το
 * {@link compareSortValues} το κρατά στο τέλος **και στις δύο** κατευθύνσεις.
 */
function listedAtKey(listing: PublicListing): string | null {
  return listing.listedAt.kind === 'known' ? listing.listedAt.at : null;
}

/**
 * **Νεότερες πρώτα.**
 *
 * ⚠️ **Οι ISO συμβολοσειρές συγκρίνονται ως κείμενο, και είναι σωστό**: το ISO 8601 με
 * μηδενικά μπροστά είναι σχεδιασμένο ώστε η λεξικογραφική σειρά να **ταυτίζεται** με τη
 * χρονολογική. Καμία μετατροπή σε `Date` — θα ήταν N αντικείμενα ανά ταξινόμηση για
 * μηδενικό κέρδος.
 */
export function compareListingsByListedAt(a: PublicListing, b: PublicListing): number {
  const byTime = compareSortValues(listedAtKey(a), listedAtKey(b), 'desc');
  return byTime !== 0 ? byTime : compareByNameThenId(a.title, a.id, b.title, b.id);
}

/**
 * **Κατά τιμή**, στην κατεύθυνση που ζητήθηκε.
 *
 * 🔑 **Το κλειδί είναι το ΥΠΑΡΧΟΝ {@link priceSortKey}** — το ίδιο που διαλέγει ποιες
 * 40 πινέζες παίρνουν πινακίδα τιμής στον χάρτη (§8.60). Δεύτερο κλειδί τιμής **δεν
 * γεννιέται**: θα ήταν δύο απαντήσεις στο *«πόσο κάνει;»*, ελεύθερες να αποκλίνουν.
 *
 * ⚠️ **Χωρίς τιμή ⇒ στο τέλος, ΚΑΙ στις δύο κατευθύνσεις.** Ακίνητο χωρίς
 * καταγεγραμμένη τιμή δεν είναι «το φθηνότερο» — δεν είναι απάντηση σε καμία από τις
 * δύο ερωτήσεις. Το κάνει το {@link compareSortValues}, όχι κώδικας εδώ.
 */
export function compareListingsByPrice(
  a: PublicListing,
  b: PublicListing,
  direction: SortDirection,
): number {
  const byPrice = compareSortValues(priceSortKey(a), priceSortKey(b), direction);
  return byPrice !== 0 ? byPrice : compareByNameThenId(a.title, a.id, b.title, b.id);
}

/**
 * **Ο ΕΝΑΣ διανομέας**: σειρά → συγκριτής.
 *
 * ⚠️ **`Record` πάνω στο κλειστό λεξιλόγιο, ώστε μια νέα σειρά να ΜΗΝ ΜΕΤΑΓΛΩΤΤΙΖΕΤΑΙ
 * χωρίς συγκριτή.** Ένα `switch` με `default` θα δεχόταν σιωπηλά μια σειρά που κανείς
 * δεν υλοποίησε, και ο άνθρωπος θα την έβλεπε στο μενού να **μην κάνει τίποτα**.
 */
const COMPARATORS: Record<ListingOrder, (a: PublicListing, b: PublicListing) => number> = {
  newest: compareListingsByListedAt,
  priceAsc: (a, b) => compareListingsByPrice(a, b, 'asc'),
  priceDesc: (a, b) => compareListingsByPrice(a, b, 'desc'),
};

/**
 * **Ντετερμινιστική, ολική σειρά για τα αποτελέσματα της αναζήτησης.**
 *
 * Επιστρέφει **νέο** πίνακα — η είσοδος έρχεται από `onSnapshot` και είναι `readonly`·
 * μια επιτόπια `sort()` θα μετέβαλλε δεδομένα που ανήκουν στη συνδρομή.
 *
 * 🔴 **ΚΑΙ Η ΝΕΑ ΤΑΥΤΟΤΗΤΑ ΕΙΝΑΙ ΓΙΑ ΤΗ ΛΙΣΤΑ ΜΟΝΟ.** Ο χάρτης οφείλει να συνεχίσει να
 * παίρνει τον **αρχικό** πίνακα: νέα ταυτότητα πίνακα στον `ResultsMap` σημαίνει
 * επανα-αρχικοποίηση του MapLibre, δηλαδή **μαύρη οθόνη** σε κάθε αλλαγή σειράς. Δες
 * `SearchResultsContent`.
 */
export function orderResultsListings(
  listings: readonly PublicListing[],
  order: ListingOrder,
): readonly PublicListing[] {
  return [...listings].sort(COMPARATORS[order]);
}

