// Ο ΕΝΑΣ ΔΡΟΜΟΣ ΠΡΟΣ ΤΗ ΣΕΙΡΑ
// ============================================================================

/**
 * **Ντετερμινιστική, ολική σειρά για τα αποτελέσματα — ως ΑΚΟΛΟΥΘΙΑ ΚΛΑΣΕΩΝ.**
 *
 * 🔴 **ΕΠΙΣΤΡΕΦΕΙ ΤΜΗΜΑΤΑ, ΟΧΙ ΕΠΙΠΕΔΟ ΠΙΝΑΚΑ — ΚΑΙ ΕΙΝΑΙ Ο ΦΡΟΥΡΟΣ.** Ένας επίπεδος
 * πίνακας θα επέτρεπε σε οποιονδήποτε καλούντα να τον διαβάσει ως «ταξινομημένο κατά
 * τιμή» και να συγκρίνει το πρώτο με το τελευταίο στοιχείο — δηλαδή να ξανακάνει,
 * σιωπηλά, την πράξη που ο `listing-price-sections.ts` υπάρχει για να αποκλείσει. Ο
 * τύπος της εξόδου **δεν εκφράζει** ενιαία κατάταξη, άρα κανείς δεν μπορεί να την
 * υποθέσει. Ίδιο ιδίωμα με το `ListingCriteriaMatch` (*«δύο ξεχωριστά πεδία, όχι ένας
 * με φιλτράρισμα»*) και με το «Inconsistent units» του Revit: **το εργαλείο αρνείται
 * αντί να παραγάγει αριθμό**.
 *
 * Επιστρέφει **νέους** πίνακες — η είσοδος έρχεται από `onSnapshot` και είναι `readonly`·
 * μια επιτόπια `sort()` θα μετέβαλλε δεδομένα που ανήκουν στη συνδρομή.
 *
 * 🔴 **ΚΑΙ Η ΝΕΑ ΤΑΥΤΟΤΗΤΑ ΕΙΝΑΙ ΓΙΑ ΤΗ ΛΙΣΤΑ ΜΟΝΟ.** Ο χάρτης οφείλει να συνεχίσει να
 * παίρνει τον **αρχικό** πίνακα: νέα ταυτότητα πίνακα στον `ResultsMap` σημαίνει
 * επανα-αρχικοποίηση του MapLibre, δηλαδή **μαύρη οθόνη** σε κάθε αλλαγή σειράς. Δες
 * `SearchResultsContent`.
 */
export function orderResultsListings(
  listings: readonly PublicListing[],
  order: ListingOrder,
  context: ListingOrderContext = NO_ORDER_CONTEXT,
): ListingSections {
  if (listings.length === 0) return [];

  // ⚠️ **Ο χρόνος έχει ΜΙΑ μονάδα** — καμία διαμέριση, καμία επιγραφή. Οι επιγραφές
  //    ανήκουν στην **ερώτηση** («πόσο;»), όχι στη λίστα.
  if (order === 'newest') {
    return [{ heading: null, items: [...listings].sort(compareListingsByListedAt) }];
  }

  const direction: SortDirection = order === 'priceAsc' ? 'asc' : 'desc';
  return partitionListingsByPriceClass(listings, direction, context);
}

