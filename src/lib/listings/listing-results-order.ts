// ΔΙΕΥΘΥΝΣΗ ⇄ ΣΕΙΡΑ
// ============================================================================

/**
 * Το όνομα της παραμέτρου. Ζει **εδώ** και όχι στο `listing-filters.ts` επειδή η σειρά
 * **δεν είναι φίλτρο**: κάθε πεδίο του `ListingFilters` απαντά *«τι ρώτησε ο
 * επισκέπτης για τα ακίνητα;»*, ενώ αυτό απαντά *«πώς θέλει να τα δει;»*. Μέσα στον
 * ίδιο τύπο, το `EMPTY_LISTING_FILTERS` θα σήμαινε «καμία σειρά», που δεν υπάρχει.
 */
const ORDER_PARAM = 'sort';

function isListingOrder(value: string | null): value is ListingOrder {
  return value !== null && (LISTING_ORDERS as readonly string[]).includes(value);
}

/**
 * Διεύθυνση → σειρά. **Άγνωστη τιμή αγνοείται**, ποτέ δεν σκάει η οθόνη — ίδιος κανόνας
 * με το `parseListingFilters`.
 */
export function parseListingOrder(params: URLSearchParams): ListingOrder {
  const value = params.get(ORDER_PARAM);
  return isListingOrder(value) ? value : DEFAULT_LISTING_ORDER;
}

/**
 * Σειρά → διεύθυνση, **μέσα στις ίδιες** παραμέτρους με τα φίλτρα.
 *
 * ⚠️ **Η προεπιλογή ΔΕΝ γράφεται**, ίδιος κανόνας με τα κενά φίλτρα: δύο ταυτόσημες
 * αναζητήσεις οφείλουν να παράγουν **χαρακτήρα προς χαρακτήρα** την ίδια διεύθυνση,
 * αλλιώς μια μηχανή αναζήτησης βλέπει δύο σελίδες με ταυτόσημο περιεχόμενο.
 *
 * 🔑 **Μεταβάλλει τις παραμέτρους που του δίνουν** αντί να φτιάχνει δικές του: η
 * συγχώνευση δύο `URLSearchParams` είναι ακριβώς η θέση όπου κάποιος θα ξεχνούσε ότι τα
 * κλειδιά λεξιλογίου **επαναλαμβάνονται** (`append` ⇄ `set`) — το γράφει ήδη το
 * `serializeListingFilters`.
 */
export function writeListingOrder(order: ListingOrder, params: URLSearchParams): void {
  if (order === DEFAULT_LISTING_ORDER) {
    params.delete(ORDER_PARAM);
    return;
  }
  params.set(ORDER_PARAM, order);
}
