/**
 * Το περιβάλλον **ή `null` αν κανείς δεν το δήλωσε**.
 *
 * ⛔ **ΓΙΑΤΙ ΔΕΝ ΚΑΛΕΙ ΤΟ `getCurrentRuntimeEnvironment()` ΕΔΩ** (ADR-821 §2.3):
 * εκείνο επιστρέφει `'development'` ως *«safest fallback»* — και **είναι**, για
 * κάθε άλλο σημείο κλήσης *(cookie `secure`, rate limits, διαπιστευτήρια Admin
 * SDK: όλα ρωτούν `=== 'production'`, όπου η επιεική προεπιλογή δίνει **λιγότερα**
 * δικαιώματα)*. **Σε αυτό το σημείο κλήσης η σχέση αντιστρέφεται**: `development`
 * είναι ο κλάδος **παράκαμψης**, άρα η ίδια προεπιλογή γίνεται η **λιγότερο**
 * ασφαλής.
 *
 * ⛔ **ΚΑΙ ΓΙ' ΑΥΤΟ ΔΕΝ «ΔΙΟΡΘΩΝΕΤΑΙ» ΕΚΕΙΝΗ**: αλλαγή της σε `'production'` θα
 * έσπαγε τα σωστά σημεία κλήσης για να φτιάξει το ένα λάθος. Το πρόβλημα ήταν
 * **το σημείο κλήσης**, και λύνεται εδώ.
 */
function declaredEnvironment(): RuntimeEnvironment | null {
  switch (process.env.NODE_ENV as string | undefined) {
    case 'production':
      return 'production';
    case 'staging':
      return 'staging';
    case 'test':
      return 'test';
    case 'development':
      return 'development';
    default:
      // Κενό, απόν, ή λάθος γραμμένο — **δεν μαντεύουμε**.
      return null;
  }
}

/**
 * Τρέχει ο Firebase Auth Emulator;
 *
 * 🏆 **ΕΔΩ ΞΕΠΕΡΝΑΜΕ ΤΟΥΣ ΜΕΓΑΛΟΥΣ** (ADR-821 §3.1α). Clerk test mode, Auth0 dev
 * tenants, Django `loginas` — και οι πέντε ρωτούν *«επιτρέπεται χαλάρωση εδώ;»*.
 * **Κανείς δεν ρωτά «χρειάζεται;»**. Όταν τρέχει ο emulator, υπάρχουν πραγματικές
 * ταυτότητες με πραγματικά custom claims *(`scripts/emulator-seed-personas.ts`)*
 * ⇒ η κατασκευή είναι **περιττή**, και η παράκαμψη σβήνει **ακριβώς στο
 * περιβάλλον όπου γίνεται η ζωντανή επαλήθευση**.
 *
 * ⚠️ **ΔΕΝ ΕΙΝΑΙ ΝΕΟΣ ΔΙΑΚΟΠΤΗΣ.** Είναι η **τυπική μεταβλητή του ίδιου του
 * Firebase SDK**, ήδη ορισμένη από το `npm run dev:emulator`, και διαβάζεται ως
 * **γεγονός** *(«υπάρχουν αληθινές ταυτότητες»)*, όχι ως πολιτική. Δεύτερη
 * μεταβλητή-διακόπτης δίπλα στο `NODE_ENV` θα ήταν ακριβώς το λάθος που κλείνει
 * αυτό το ADR.
 */
function realCredentialsAvailable(): boolean {
  const host = process.env.FIREBASE_AUTH_EMULATOR_HOST;
  return typeof host === 'string' && host.trim().length > 0;
}

