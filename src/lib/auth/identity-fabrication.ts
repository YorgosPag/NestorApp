/** Άρνηση με τον λόγο της — ένα σημείο, ώστε κανένας κλάδος να μη μείνει άφωνος. */
function deny(
  verdict: Exclude<FabricationVerdict, 'granted-development-fallback'>,
): FabricationDecision {
  return { verdict, reason: REASON_BY_VERDICT[verdict] };
}

/**
 * **Επιτρέπεται να κατασκευάσω ταυτότητα εδώ;**
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 🔑 Η ΣΕΙΡΑ ΚΡΙΣΗΣ ΕΙΝΑΙ **ΣΥΜΒΟΛΑΙΟ**, ΟΧΙ ΥΦΟΣ (ADR-821 §4.2)
 *
 *   1. άγνωστο ΠΕΡΙΒΑΛΛΟΝ             ⇒ ⛔   (ΠΡΙΝ από την πολιτική)
 *   2. πολιτική allowDevBypass=false  ⇒ ⛔
 *   3. υπάρχουν ΑΛΗΘΙΝΑ πιστοποιητικά ⇒ ⛔
 *   4. τίποτα από τα παραπάνω         ⇒ ✅
 *
 * 🏆 **Η ΤΟΜΗ ΕΙΝΑΙ ΤΟ (1) — η ΥΠΑΡΞΗ του.** Χωρίς ρητό
 * `denied-unknown-environment`, το άγνωστο περιβάλλον θα έφτανε στην πολιτική, που
 * θα το **έλυνε** ως `development` *(η επιεικής προεπιλογή του §2.3)* και θα
 * απαντούσε `allowDevBypass: true` — **η ίδια τρύπα, μεταφερμένη ένα επίπεδο πιο
 * μέσα**, και πλέον **αόρατη**, γιατί θα έμοιαζε με σωστή ανάγνωση SSoT.
 *
 * ⚠️ **Η ΣΕΙΡΑ (1) ΕΝΑΝΤΙ (2) ΕΙΝΑΙ ΣΗΜΕΡΑ ΑΠΑΡΑΤΗΡΗΤΗ — ΜΕΤΡΗΜΕΝΟ.** Μετάλλαξη
 * που τις αντέστρεψε **επέζησε**: το άγνωστο `NODE_ENV` λύνεται σε `development`,
 * του οποίου το `allowDevBypass` είναι `true`, άρα η πολιτική δεν αρνείται εκεί
 * ποτέ. Γίνεται παρατηρήσιμη τη στιγμή που κάποιος γράψει
 * `development.allowDevBypass: false` — τότε η λάθος σειρά θα ανέφερε *«η πολιτική
 * το απαγορεύει»* ενώ η αλήθεια είναι *«δεν ξέρω πού τρέχω»*. Κλειδωμένη από τις
 * άγκυρες **Κ1.5/Κ1.6**, που στήνουν ακριβώς εκείνον τον κόσμο (ADR-821 §5.1).
 *
 * ⚠️ **ΤΟ (3) ΠΡΙΝ ΤΟ (4)**: το *«επιτρέπεται»* δεν συνεπάγεται *«χρειάζεται»*.
 * ═══════════════════════════════════════════════════════════════════════════
 */
export function decideIdentityFabrication(): FabricationDecision {
  const environment = declaredEnvironment();

  if (environment === null) {
    return deny('denied-unknown-environment');
  }

  // 🔑 Ο **αδρανής φρουρός ξυπνά**: το `allowDevBypass` δηλωνόταν σε **και τις
  //    τέσσερις** πολιτικές και είχε **μηδέν** καταναλωτές (ADR-821 §2.4, ADR-749
  //    §5). Η πολιτική **υπήρχε**· απλώς κανείς δεν τη ρωτούσε.
  if (!getCurrentSecurityPolicy().allowDevBypass) {
    return deny('denied-by-policy');
  }

  if (realCredentialsAvailable()) {
    return deny('denied-real-credentials-available');
  }

  return { verdict: 'granted-development-fallback', principal: FABRICATED_PRINCIPAL };
}
