/**
 * **Η ΑΥΘΕΝΤΙΑ ΤΗΣ ΚΑΤΑΣΚΕΥΑΣΜΕΝΗΣ ΤΑΥΤΟΤΗΤΑΣ** (ADR-821)
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΟ ΕΡΩΤΗΜΑ
 * ─────────────────────────────────────────────────────────────────────────────
 * *«Ποιος επιτρέπεται να **κατασκευάσει** ταυτότητα — και ποιος του το επέτρεψε;»*
 *
 * Το ADR-801 (`decideCapability`) απαντά *«επιτρέπεται αυτή η **ενέργεια**;»*.
 * Αυτό εδώ ρωτά τον **έναν όροφο πιο κάτω**: *«υπάρχει καν αυτός που ρωτά;»* —
 * αυθεντικοποίηση, όχι εξουσιοδότηση.
 *
 * ⛔ **ΕΙΝΑΙ ΚΡΙΤΗΣ, ΟΧΙ ΠΑΡΑΓΩΓΟΣ.** Δεν επιστρέφει `AuthContext`. Οι παραγωγοί
 * είναι και μένουν **δύο** (`buildRequestContext` · `readPageIdentity`) — τρίτος
 * θα ήταν τρίτη απάντηση σε ένα ερώτημα (ADR-749). Ίδιο σχήμα με τους αδελφούς
 * `decideCapability` και `decideMembership`: ο κριτής **κρίνει**, ο καλών
 * **συναρμολογεί**.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΓΕΝΝΗΘΗΚΕ — ΤΟ ΜΕΤΡΗΜΕΝΟ ΓΕΓΟΝΟΣ (ADR-821 §2)
 * ─────────────────────────────────────────────────────────────────────────────
 * **Έξι** σημεία κατασκεύαζαν ταυτότητα, το καθένα με **δικό του** κριτήριο, σε
 * **δύο** διαλέκτους που **αποκλίνουν**:
 *
 *   • `process.env.NODE_ENV === 'development'`        — **αυστηρό**
 *   • `getCurrentRuntimeEnvironment() === 'development'` — **επιεικές**: επιστρέφει
 *     `'development'` και για `NODE_ENV` **κενό ή λάθος γραμμένο** (§2.3)
 *
 * ⇒ Με `NODE_ENV=""` η **σελίδα** αποδιδόταν με κατασκευασμένη ταυτότητα ενώ η
 * **διαδρομή API** που καλούσε απαντούσε **401**.
 *
 * 🔴 **ΚΑΙ ΕΦΤΑΣΕ ΣΤΗΝ ΠΑΡΑΓΩΓΗ**: το `users/dev-admin` υπάρχει στη ζωντανή βάση
 * με `globalRole: 'super_admin'` και `authProvider: 'development-bypass'`, από
 * 2026-03-13. Ο φρουρός της διαδρομής που το έγραψε (`requiredGlobalRoles`) **δεν
 * παρακάμφθηκε — ΙΚΑΝΟΠΟΙΗΘΗΚΕ**, από ταυτότητα που κατασκεύασε το ίδιο το
 * σύστημα οκτώ αρχεία μακριά (ADR-821 §2.7).
 *
 * 🔑 **Μια κατασκευασμένη ταυτότητα δεν σπάει φρουρούς· τους περνά.**
 *
 * @module lib/auth/identity-fabrication
 * @see docs/centralized-systems/reference/adrs/ADR-821-fabricated-identity-authority.md
 */

import {
  getCurrentSecurityPolicy,
  type RuntimeEnvironment,
} from '@/config/environment-security-config';

// =============================================================================
// ΤΟ ΛΕΞΙΛΟΓΙΟ
// =============================================================================

/**
 * **ΤΕΣΣΕΡΙΣ ΡΗΤΕΣ ΕΤΥΜΗΓΟΡΙΕΣ, ΠΟΤΕ `boolean`** (πρότυπο ADR-801 §4.1).
 *
 * ⚠️ Ένα `false` δεν λέει **γιατί**. Ο προγραμματιστής που βλέπει `401` πρέπει να
 * ξεχωρίσει *«σύνδεσε τον emulator»* από *«όρισε NODE_ENV»* από *«αυτό είναι
 * staging»* — τρεις εντελώς διαφορετικές επόμενες κινήσεις.
 */
export type FabricationVerdict =
  /** Ο **μόνος** επιτρεπτικός. */
  | 'granted-development-fallback'
  /** Τρέχει ο Auth Emulator ⇒ υπάρχουν **αληθινές** ταυτότητες ⇒ η κατασκευή είναι περιττή. */
  | 'denied-real-credentials-available'
  /** Η πολιτική του περιβάλλοντος λέει `allowDevBypass: false`. */
  | 'denied-by-policy'
  /** `NODE_ENV` κενό, απόν ή άγνωστο — **ονομασμένη** κατάσταση, ποτέ σιωπηλή προεπιλογή. */
  | 'denied-unknown-environment';

/**
 * Η **ΜΙΑ** κατασκευασμένη αρχή — ένα πρόσωπο, ο **χαμηλότερος** ρόλος που κάνει
 * τη δουλειά.
 *
 * 🔴 **ΤΙ ΕΦΥΓΕ ΑΠΟ ΕΔΩ, ΚΑΙ ΓΙΑΤΙ** (ADR-821 §4.3):
 *
 * | έφυγε | γιατί |
 * |---|---|
 * | `uid: 'dev-admin'` | το **όνομα** εξαφανίζεται από τον κώδικα ⇒ κανείς δεν ξαναγράφει το έγγραφο της παραγωγής |
 * | `globalRole: 'admin'` | **εκτός** `GLOBAL_ROLES` — η ακριβής τιμή για την οποία υπάρχει το `denied-unknown-role` (ADR-801 §4.3) |
 * | `mfaEnrolled: true` | το `permissions.ts` κρίνει πάνω του· κατασκευασμένο `true` = δεύτερος παράγοντας **δηλωμένος από τον αιτούντα** |
 * | `super_admin` | **δεν κατασκευάζεται ποτέ, από κανένα σημείο** |
 *
 * ⚠️ **Δεν είναι ελάττωση για ασφάλεια — είναι αφαίρεση κλιμάκωσης.** Δίνει όσα
 * ακριβώς χρειάζεται μια τοπική **εταιρική** οθόνη, και τίποτα παραπάνω. Όποιος
 * χρειάζεται περισσότερα **συνδέεται** — ο emulator σπέρνει πραγματικές ταυτότητες.
 */
export const FABRICATED_PRINCIPAL = {
  uid: 'dev-user',
  email: 'dev@localhost',
  globalRole: 'company_admin',
  mfaEnrolled: false,
} as const;

/** Η απόφαση. Ο επιτρεπτικός κλάδος **κουβαλά** την αρχή· οι αρνητικοί έναν λόγο. */
export type FabricationDecision =
  | {
      readonly verdict: 'granted-development-fallback';
      readonly principal: typeof FABRICATED_PRINCIPAL;
    }
  | {
      readonly verdict: Exclude<FabricationVerdict, 'granted-development-fallback'>;
      readonly reason: string;
    };

/**
 * Ο λόγος κάθε άρνησης — **πληρότητα επιβαλλόμενη από τον μεταγλωττιστή**
 * (πρότυπο ADR-801 §4.4): πέμπτη ετυμηγορία **δεν μεταγλωττίζεται** μέχρι να
 * αποκτήσει λόγο. Άρνηση χωρίς εξήγηση είναι κενή οθόνη.
 */
const REASON_BY_VERDICT: Record<
  Exclude<FabricationVerdict, 'granted-development-fallback'>,
  string
> = {
  'denied-real-credentials-available':
    'Ο Auth Emulator τρέχει — συνδέσου με πραγματική ταυτότητα (npm run emulator:seed-personas).',
  'denied-by-policy':
    'Η πολιτική ασφαλείας αυτού του περιβάλλοντος δεν επιτρέπει κατασκευασμένη ταυτότητα.',
  'denied-unknown-environment':
    'Το NODE_ENV είναι κενό ή άγνωστο — όρισέ το ρητά σε "development".',
};

