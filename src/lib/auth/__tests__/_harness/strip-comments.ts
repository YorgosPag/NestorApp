/**
 * Ο κώδικας ενός αρχείου, **χωρίς** μπλοκ (`/* … *\/`) και γραμμές (`// …`).
 *
 * @param source Το ωμό περιεχόμενο του αρχείου.
 * @returns Το ίδιο περιεχόμενο με τα σχόλια αντικατεστημένα από κενό.
 */
export function stripComments(source: string): string {
  return source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}
