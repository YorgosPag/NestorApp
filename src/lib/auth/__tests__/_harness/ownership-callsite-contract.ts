import type { MockWriteRecord } from '@/test-utils/mock-firestore';

/**
 * Ποιον μισθωτή φέρει το έγγραφο-στόχος όταν στηθεί.
 *
 * `absent` ≠ `empty`: το πρώτο είναι «το πεδίο δεν υπάρχει» (ADR-232,
 * έγγραφα υπεργραφείου), το δεύτερο «υπάρχει και είναι κενό» (χαλασμένη
 * εγγραφή). Ο SSoT οφείλει να αρνείται **και τα δύο**.
 */
export type OwnerFixture =
  | { readonly kind: 'empty' }
  | { readonly kind: 'absent' }
  | { readonly kind: 'named'; readonly companyId: string };

/**
 * **Ό,τι δεν έπρεπε να συμβεί.** Κενό = ο φύλακας κράτησε.
 *
 * 🔴 Δεν είναι πάντα εγγραφή στη βάση. Η επιστροφή μιας διαδρομής
 * `Promise<void>` είναι **πάντα** `falsy`, άρα το «τι επέστρεψε» δεν διακρίνει
 * τίποτα· και σε διαδρομή **ανάγνωσης** η ζημιά είναι ότι ο κατάντη κώδικας
 * **έτρεξε** πάνω σε ξένο έγγραφο. Γι' αυτό κάθε σημείο ορίζει **το δικό του**
 * παρατηρήσιμο: ημερολόγιο εγγραφών, ή καταγραφή κατάντη κλήσεων.
 */
export interface SideEffectProbe {
  readonly effects: () => readonly unknown[];
}

/** Έτοιμος ανιχνευτής για διαδρομές που γράφουν: το ημερολόγιο του mock. */
export function writeJournalProbe(writes: () => readonly MockWriteRecord[]): SideEffectProbe {
  return { effects: writes };
}

/**
 * Έτοιμος ανιχνευτής για διαδρομές **ανάγνωσης**: οι κατάντη κλήσεις που
 * επιτρέπονται **μόνο** αφού ο φύλακας πει «ναι».
 */
export function downstreamCallProbe(...mocks: readonly jest.Mock[]): SideEffectProbe {
  return { effects: () => mocks.flatMap(m => m.mock.calls) };
}

/** Ένα σημείο κλήσης του SSoT, όπως το βλέπει η **δημόσια** διαδρομή του. */
export interface OwnershipCallSiteSpec {
  /**
   * Η διαδρομή αρχείου που περιέχει την κλήση, **σχετική με το `src/`** και με
   * `/` — π.χ. `'services/opportunities-server.service.ts'`.
   *
   * 🔑 Είναι ο **σύνδεσμος με τον anchor πληρότητας**: εκείνος σαρώνει το
   * δέντρο και απαιτεί κάθε αρχείο με κλήση να εμφανίζεται εδώ ή στον πίνακα
   * των ανάντη φυλασσόμενων. Διαδρομή, **όχι** αριθμός γραμμής: οι γραμμές
   * μετακινούνται σε κάθε edit και θα έκαναν τον anchor θορυβώδη ψεύτη.
   */
  readonly file: string;

  /** Ανθρώπινο όνομα της διαδρομής, π.χ. `'OpportunitiesServerService.update'`. */
  readonly name: string;

  /**
   * Στήνει το έγγραφο-στόχο με τον δοσμένο ιδιοκτήτη και επιστρέφει τον
   * ανιχνευτή παρενέργειας. Καλείται **πριν** από κάθε `act`.
   */
  readonly arrange: (owner: OwnerFixture) => SideEffectProbe;

  /** Εκτελεί τη **δημόσια** διαδρομή με τον δοσμένο καλούντα. */
  readonly act: (callerCompanyId: string) => Promise<unknown>;

  /**
   * Τι σημαίνει «αρνήθηκε» για **αυτή** τη διαδρομή. Κάθε πεδίο ορισμού έχει
   * το δικό του λεξιλόγιο (`null`, `[]`, `{ ok: false }`, `{ error }`) και η
   * ενοποίησή του θα ήταν **αλλαγή δόγματος αποκάλυψης**, όχι de-duplication
   * (ADR-742 μάθημα #4). Κοινός εδώ είναι ο **έλεγχος**, όχι το λεξιλόγιο.
   */
  readonly refused: (result: unknown) => boolean;
}

/** Ο μισθωτής που παίζει τον νόμιμο ιδιοκτήτη στον θετικό μάρτυρα. */
export const LEGITIMATE_TENANT = 'comp_001';

/**
 * Παράγει το τριπλό συμβόλαιο για κάθε σημείο.
 *
 * ⚠️ Ο πίνακας περνά **ολόκληρος** — μην τον κόψεις σε πολλαπλές κλήσεις ανά
 * αρχείο: ο anchor πληρότητας μετρά τα `file` του πίνακα, και ένας πίνακας
 * μοιρασμένος σε κομμάτια είναι ένα κομμάτι που κάποιος θα ξεχάσει.
 */
export function describeOwnershipCallSites(
  suiteTitle: string,
  sites: readonly OwnershipCallSiteSpec[],
): void {
  describe(suiteTitle, () => {
    describe.each(sites.map(s => [s.name, s] as const))('%s', (_name, site) => {
      test('🔴 αρνείται όταν ΚΑΝΕΝΑΣ από τους δύο δεν έχει μισθωτή (κενό ≠ μισθωτής)', async () => {
        const probe = site.arrange({ kind: 'empty' });

        const result = await site.act('');

        expect(site.refused(result)).toBe(true);
        expect(probe.effects()).toEqual([]);
      });

      test('🔴 αρνείται έγγραφο ΧΩΡΙΣ μισθωτή, ακόμη και σε κανονικό καλούντα (ADR-232)', async () => {
        const probe = site.arrange({ kind: 'absent' });

        const result = await site.act(LEGITIMATE_TENANT);

        expect(site.refused(result)).toBe(true);
        expect(probe.effects()).toEqual([]);
      });

      /**
       * ✅ Ο **θετικός μάρτυρας**. Χωρίς αυτόν, σπασμένο στήσιμο περνά και τα
       * δύο αρνητικά tests: μια διαδρομή που αρνείται **πάντα** (λάθος όνομα
       * συλλογής, mock που δεν επιστρέφει έγγραφο) είναι μη διακρίσιμη από
       * φύλακα που δουλεύει. Εδώ αποδεικνύεται ότι το `act` **φτάνει** στον
       * φύλακα και ότι ο φύλακας **αφήνει** να περάσει ό,τι πρέπει.
       */
      test('✅ ΔΕΝ αρνείται τον νόμιμο ιδιοκτήτη (μάρτυρας: η διαδρομή όντως φτάνει στον φύλακα)', async () => {
        site.arrange({ kind: 'named', companyId: LEGITIMATE_TENANT });

        const result = await site.act(LEGITIMATE_TENANT);

        expect(site.refused(result)).toBe(false);
      });
    });
  });
}

/**
 * Γράφει το πεδίο `companyId` σύμφωνα με το fixture — **η μία** μετάφραση
 * `OwnerFixture` → σχήμα εγγράφου. Χωρίς αυτήν, κάθε σημείο θα έγραφε το ίδιο
 * τριπλό `if` και ένα από αυτά θα απέκλινε.
 */
export function withOwner(
  base: Record<string, unknown>,
  owner: OwnerFixture,
): Record<string, unknown> {
  if (owner.kind === 'absent') {
    const { companyId: _dropped, ...rest } = base;
    void _dropped;
    return rest;
  }
  return { ...base, companyId: owner.kind === 'empty' ? '' : owner.companyId };
}
