const unreadablePaths: string[] = [];

function listTypeScriptFiles(dir: string): string[] {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    unreadablePaths.push(relative(dir));
    return [];
  }
  return entries.flatMap((entry) => {
    if (SKIP_DIRS.has(entry)) return [];
    const full = join(dir, entry);
    let isDir: boolean;
    try {
      isDir = statSync(full).isDirectory();
    } catch {
      // σπασμένος σύνδεσμος — δεν υπάρχει πηγαίος κώδικας να διαβαστεί, αλλά
      // η παράλειψη **καταγράφεται** (βλ. DECLARED_UNREADABLE_PATHS)
      unreadablePaths.push(relative(full));
      return [];
    }
    if (isDir) return listTypeScriptFiles(full);
    return (entry.endsWith('.ts') || entry.endsWith('.tsx')) && !entry.endsWith('.d.ts')
      ? [full]
      : [];
  });
}

const relative = (file: string): string =>
  file.slice(process.cwd().length + 1).split('\\').join('/');

