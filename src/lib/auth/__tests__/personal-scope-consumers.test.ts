/**
 * **Οι καταναλωτές της πόρτας αρχείων** (ADR-866 §2.6.9) — κλειστό σύνολο, όπως το `DECLARED`.
 *
 * 🔴 Η πόρτα είναι ΕΝΑ δηλωμένο αρχείο, αλλά ανοίγει τον πολίτη σε ΚΑΘΕ διαδρομή που την καλεί.
 * Χωρίς αυτή τη λίστα, μια τέταρτη διαδρομή θα δεχόταν πολίτη **χωρίς** να τη δει άνθρωπος — δηλαδή
 * το κλειστό σύνολο θα είχε μια πόρτα από την οποία περνά οποιοσδήποτε σιωπηλά.
 */
const DOOR_CONSUMERS: Readonly<Record<string, readonly string[]>> = {
  withFileCustodyAuth: [
    'src/app/api/download/route.ts',
    // 🗂️ ADR-866 2β.3β — οι **εκδόσεις** του προσωπικού αρχείου (Ε-Φ0-1: εκδόσεις ΝΑΙ, φάσεις ΟΧΙ).
    //    Και οι τρεις φορτώνουν με `personalFileResource` (`userId == uid`, **κανένα** bypass super
    //    admin) και **δεν** καλούν κριτή δοχείου για άνθρωπο: προσωπικό αρχείο δεν έχει φάση να κριθεί.
    'src/app/api/files/[fileId]/cde/route.ts',
    'src/app/api/files/[fileId]/download/route.ts',
    'src/app/api/files/[fileId]/versions/promote/route.ts',
    'src/app/api/files/[fileId]/versions/route.ts',
    'src/app/api/files/batch-download/route.ts',
  ],
  gdprSubjectRoute: [
    'src/app/api/files/gdpr-delete/route.ts',
    'src/app/api/files/gdpr-export/route.ts',
  ],
};

/** Οι διαδρομές που **όντως** καλούν το περιτύλιγμα — **tracked** αρχεία, όχι σκέτος δίσκος. */
function actualConsumers(): string[] {
  // 🔴 **ΤΟ ΜΟΤΙΒΟ ΚΡΙΝΕΙ ΤΗΝ ΚΛΗΣΗ, ΟΧΙ ΤΗΝ ΑΝΑΦΟΡΑ** — γεννήθηκε από μετάλλαξη που
  //    βγήκε ΠΡΑΣΙΝΗ (Μ7): με σκέτο το όνομα, αρχείο που **εισάγει** το περιτύλιγμα και
  //    **δεν το καλεί** μετριόταν ως καταναλωτής, οπότε η ορφανή δήλωση ήταν αόρατη.
  //    `withPersonalOrOrgAuth(` ή `withPersonalOrOrgAuth<` = **κλήση**· η γραμμή
  //    `import { withPersonalOrOrgAuth, ... }` δεν ταιριάζει.
  const out = execFileSync(
    'git',
    ['grep', '-lE', '-e', 'withPersonalOrOrgAuth[<(]', '--', 'src/app/api'],
    { cwd: REPO_ROOT, encoding: 'utf8' },
  );
  return out.split('\n').map((l) => l.trim()).filter(Boolean).sort();
}

describe('ADR-817 §5 — το κλειστό σύνολο των διαδρομών του πολίτη', () => {
  it('Κ1 — κάθε δήλωση φέρει ουσιαστικό λόγο (≥40 χαρακτήρες)', () => {
    for (const entry of DECLARED) {
      expect(entry.why.trim().length).toBeGreaterThanOrEqual(40);
    }
  });

  it('Κ2 — καμία ΑΔΗΛΩΤΗ διαδρομή δεν καλεί το withPersonalOrOrgAuth', () => {
    const declared = new Set(DECLARED.map((d) => d.route));
    const undeclared = actualConsumers().filter((r) => !declared.has(r));

    // ⛔ Αν αυτό κοκκινίσει: ΜΗΝ προσθέσεις απλώς γραμμή στο DECLARED. Ρώτα πρώτα
    //    «γιατί αυτή η διαδρομή δέχεται άνθρωπο χωρίς οργανισμό;» — η απάντηση ΕΙΝΑΙ
    //    ο λόγος που πρέπει να γραφτεί δίπλα της.
    expect(undeclared).toEqual([]);
  });

  it('Κ3 — καμία ΟΡΦΑΝΗ δήλωση: ό,τι δηλώνεται, καλεί όντως το περιτύλιγμα', () => {
    const actual = new Set(actualConsumers());
    const orphans = DECLARED.map((d) => d.route).filter((r) => !actual.has(r));

    // ⚠️ Χωρίς αυτό το σύνολο **σαπίζει σιωπηλά** (μάθημα CHECK 3.59 Κ2): μια δήλωση
    //    για διαδρομή που δεν υπάρχει πια δίνει ψεύτικη αίσθηση κάλυψης.
    expect(orphans).toEqual([]);
  });

  it.each(Object.entries(DOOR_CONSUMERS))('🔑 Κ4 — η πόρτα %s έχει ΑΚΡΙΒΩΣ τους δηλωμένους καταναλωτές', (door, declared) => {
    const consumers = execFileSync(
      'git',
      ['grep', '-lE', '-e', `${door}[<(]`, '--', 'src/app/api'],
      { cwd: REPO_ROOT, encoding: 'utf8' },
    )
      .split('\n')
      .map((l) => l.trim())
      .filter((l) => l.length > 0 && !l.includes('/_shared/'))
      .sort();

    // ⛔ Νέα διαδρομή εδώ ⇒ ΜΗΝ προσθέσεις απλώς γραμμή: ρώτα «γιατί ΑΥΤΗ η διαδρομή δέχεται
    //    πολίτη;». Και καμία δήλωση δεν μένει ορφανή.
    expect(consumers).toEqual([...declared].sort());
  });

  it('Π — Ο ΠΑΡΟΝΟΜΑΣΤΗΣ: το σύνολο ΔΕΝ είναι κενό', () => {
    // 🔴 Χωρίς αυτό, τα Κ2/Κ3 θα ήταν πράσινα σε δέντρο όπου **κανείς** δεν καλεί το
    //    περιτύλιγμα — δηλαδή «0 = κανείς δεν κοίταξε», το σχήμα που κυνηγάμε.
    // 5η διαδρομή: `api/workspaces` (2026-08-27). Ο αριθμός ΑΝΕΒΑΙΝΕΙ ΜΟΝΟ με
    // γραμμή στο DECLARED από άνθρωπο — αυτό ακριβώς κάνει το σύνολο «κλειστό».
    // 6η: `api/mandate-requests` (2026-08-29, ADR-827 Σ1). Η πύλη κοκκίνισε πρώτη,
    // πριν γραφτεί αυτή η γραμμή — δηλαδή έκανε ακριβώς τη δουλειά της.
    // 7η: `api/account/vat-number` (2026-08-29, ADR-827 §9.20 Φ1). **Ξανακοκκίνισε
    // πρώτη**, δεύτερη φορά στην ίδια μέρα. Ο λόγος είναι ο ίδιος με την 6η — ο
    // ιδιώτης **δεν έχει οργανισμό** — αλλά η διαδρομή υπάρχει για διαφορετικό
    // αίτιο: το πεδίο είναι `serverOwnedUserFields()` **επίτηδες**, γιατί ο mod-11
    // ελεγκτής ΑΦΜ δεν εκφράζεται σε κανόνα Firestore.
    // 8η: `api/account/professional-registration` (2026-09-02, ADR-841 Φ6-Β3). **Τρίτη
    // φορά ο ίδιος λόγος** — ο άνθρωπος χωρίς οργανισμό — και **τρίτη φορά
    // διαφορετικό αίτιο**: εδώ το πεδίο κλειδώθηκε server-owned **πριν υπάρξει**,
    // γιατί πελατική γραφή του `state` θα ισοπέδωνε το «δηλωμένο ≠ επαληθευμένο».
    // 9η-12η: `api/first-contacts` × 4 (2026-09-03, ADR-843 Φάση Β Στάδιο Β). **Τέταρτη
    // φορά ο ίδιος λόγος** — ο άνθρωπος χωρίς οργανισμό — και **τέταρτο διαφορετικό
    // αίτιο**: εδώ ο ιδιώτης δεν είναι μόνο ο ΑΠΟΣΤΟΛΕΑΣ αλλά **και ο ΠΑΡΑΛΗΠΤΗΣ**
    // (`inbox`), δηλαδή για πρώτη φορά και οι **δύο** πλευρές μιας συναλλαγής μπορεί
    // να είναι πολίτες. Οι τέσσερις μπήκαν **μαζί** επειδή είναι **μία** πράξη με
    // δύο ακροατήρια: χωρίς την `inbox` η πράξη δεν έχει παραλήπτη, και χωρίς τη
    // `mine` δεν έχει τρόπο να κλείσει — δηλαδή δεν είναι τέσσερις αποφάσεις.
    // 13η: `api/first-contacts/admission` (2026-09-05, ADR-843 §10.18). **Πέμπτη φορά ο
    // ίδιος λόγος** — ο άνθρωπος χωρίς οργανισμό — αλλά **δεν είναι πέμπτο αίτιο**: είναι
    // η **ίδια** πράξη με τις 9η-12η, ρωτημένη **πριν** αντί για **μετά**. Μπήκε ΜΟΝΗ
    // της, και όχι μαζί τους, επειδή γεννήθηκε από **μετρημένο ελάττωμα διεπαφής**: ο
    // ιδιοκτήτης συμπλήρωνε ολόκληρη φόρμα για να ακούσει `contact-own-target`.
    // 🔴 **ΚΑΙ Η ΠΥΛΗ ΞΑΝΑΚΟΚΚΙΝΙΣΕ ΠΡΩΤΗ** (τρίτη φορά συνολικά): αυτός ο αριθμός
    // έπεσε στο 13 **πριν** γραφτεί η γραμμή, όχι επειδή κάποιος θυμήθηκε.
    // 14η: `api/workspace-invitations/redeem` (2026-09-12, ADR-853 Φ4). **Έκτη φορά ο
    // ίδιος λόγος** — ο άνθρωπος χωρίς οργανισμό — και **έκτο διαφορετικό αίτιο**, το
    // πιο ουσιαστικό ως τώρα: σε ΚΑΘΕ προηγούμενη δήλωση ο πολίτης είναι άνθρωπος που
    // **θα μείνει** πολίτης (καταχωρεί, ζητά, πλησιάζει, δηλώνει ΑΦΜ). Εδώ είναι
    // άνθρωπος **σε μετάβαση**: μπαίνει χωρίς χώρο και βγαίνει **μέλος**. Γι' αυτό
    // είναι και η **μόνη** διαδρομή του συνόλου που γράφει claim — και μόνο σε όποιον
    // δεν είχε χώρο (Α2 · Μ1): αν έγραφε πάντα, μια πρόσκληση θα **μετακινούσε** μέλος
    // από γραφείο σε γραφείο, συμπεριφορά που το ADR-853 §11 απέρριψε ονομαστικά.
    // 15η: `api/audit-trail/[entityType]/[entityId]` (2026-09-16, ADR-864 Φ1β). **Πρώτη
    // διαδρομή ΑΝΑΓΝΩΣΗΣ ιστορικού** στο σύνολο, και ο λόγος είναι ο ίδιος άνθρωπος: ο ιδιώτης
    // έχει πλέον **προσωπικό βιβλίο** ιστορικού για την αγγελία του, και με `withAuth` το
    // «φόρτωσε περισσότερα» του δικού του ιστορικού θα γύριζε 401. ⚠️ Η διαφορά από τις 14:
    // η διαδρομή **υπήρχε** ήδη ως εταιρική· η εταιρική συμπεριφορά μένει **ταυτόσημη**
    // (προεπιλογή `ledger=company`, απαιτεί οργανισμό) και ο πολίτης διαβάζει **μόνο** το δικό
    // του (`userId == ctx.uid`). 🔴 Και εδώ η πύλη κοκκίνισε **πριν** γραφτεί αυτή η γραμμή.
    // 16η-17η: πόρτα αρχείων + πόρτα ΓΚΠΔ (2026-09-17, ADR-866 §2.6.9). **Πρώτη φορά πόρτες και
    // όχι διαδρομές**: κάθε `_shared/…` ανοίγει τον πολίτη σε ΠΟΛΛΕΣ διαδρομές, γι' αυτό οι
    // καταναλωτές τους είναι **δεύτερο** κλειστό σύνολο (Κ4). Οι δύο ΓΚΠΔ μοιράζονται πόρτα: διαγραφή
    // χωρίς εξαγωγή θα έσβηνε κάτι που ο άνθρωπος δεν μπορεί να δει.
    // ⚠️ Τα νέα αρχεία των πορτών μετρούν από το `git add` (δηλωμένο όριο της κεφαλίδας).
    // 🔴 Μετρημένο στο HEAD `ceadd529`: ήδη **18** (όχι 15) — τρεις διαδρομές `owner-properties/[id]/…`
    //    (`mandate-evidence` · `private-marketing` · `stay-calendar`) μπήκαν με commit **χωρίς** γραμμή
    //    στο `DECLARED` ⇒ η Κ2 ήταν κόκκινη πριν από αυτή την αλλαγή. Οι λόγοι τους ανήκουν σε όποιον
    //    τις έγραψε (ADR-864)· εδώ μετρώνται, δεν δηλώνονται. 18 + 2 = **20**.
    expect(actualConsumers().length).toBe(20);
  });

  it('Π2 — Ο ΠΑΡΟΝΟΜΑΣΤΗΣ ΤΗΣ ΠΡΟΕΠΙΛΟΓΗΣ: η συντριπτική πλειοψηφία μένει εταιρική', () => {
    // 🔑 Το κριτήριο του ADR-817 §3 είναι «ρητή συμμετοχή», και αποδεικνύεται μόνο αν
    //    φαίνεται ΠΟΣΟ μικρό είναι το σύνολο έναντι της προεπιλογής. Ένα κριτήριο που
    //    άνοιγε «όσους δεν αναφέρουν companyId» θα έδινε **126** (96,8% ψευδώς θετικά).
    const orgRoutes = execFileSync(
      'git',
      ['grep', '-l', '-e', 'withAuth', '--', 'src/app/api'],
      { cwd: REPO_ROOT, encoding: 'utf8' },
    )
      .split('\n')
      .filter((l) => l.trim().endsWith('route.ts'));

    expect(orgRoutes.length).toBeGreaterThan(300);
  });
});
