    route: 'src/app/api/files/_shared/gdpr-subject-route.ts',
    why:
      'Η ΠΟΡΤΑ ΤΩΝ ΔΙΑΔΡΟΜΩΝ ΓΚΠΔ (ADR-866 §2.6.9 Β6) — καταναλωτές gdpr-delete (άρθρο 17) και '
