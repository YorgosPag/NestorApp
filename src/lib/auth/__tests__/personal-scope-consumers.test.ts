import { execFileSync } from 'node:child_process';
import path from 'node:path';

const REPO_ROOT = path.resolve(__dirname, '../../../..');

/**
 * **ΤΟ ΔΗΛΩΜΕΝΟ ΣΥΝΟΛΟ** — κάθε εγγραφή με **υποχρεωτικό λόγο**.
 *
 * ⚠️ Ο λόγος δεν είναι διακοσμητικός (πρότυπο CHECK 3.35/3.50): μια δήλωση χωρίς λόγο
 * είναι **παράκαμψη με άλλο όνομα**.
 */
const DECLARED: ReadonlyArray<{ readonly route: string; readonly why: string }> = [
  {
    route: 'src/app/api/owner-properties/route.ts',
    why:
      'Η ΠΟΡΤΑ ΤΗΣ ΚΑΤΑΧΩΡΗΣΗΣ (ADR-777 Α14). Γράφει πάντα authorCompanyId: null, ' +
      'δηλαδή προσωπική θεματοφυλακή, και χρησιμοποιεί ΜΟΝΟ το uid. Το firestore.rules ' +
      'δίνει allow create: if false στο owner_properties ⇒ χωρίς αυτή τη διαδρομή ο ' +
      'ιδιώτης ΔΕΝ ΜΠΟΡΕΙ να καταχωρήσει με κανέναν τρόπο.',
  },
  {
    route: 'src/app/api/owner-properties/[ownerPropertyId]/route.ts',
    why:
      'Επεξεργασία και απόσυρση της ΙΔΙΑΣ ΤΟΥ αγγελίας. Η εξουσιοδότηση είναι το ' +
      'mayAdminister(custodyOf(...)) του listing-custody (CHECK 3.56), που για ' +
      "custody 'personal' κρίνει userId === uid — ταυτόσημα με πριν — και για " +
      "'company' απαιτεί hasTenant ΚΑΙ στις δύο πλευρές, άρα ο ιδιώτης δεν μπορεί " +
      'δομικά να αγγίξει εταιρική αγγελία.',
  },
  {
    route: 'src/app/api/demand/interest/route.ts',
    why:
      '«Πόσοι ζητούν το ακίνητό μου» — απευθύνεται στον ΙΔΙΟΚΤΗΤΗ, που κατά την Α14 ' +
      'είναι τυπικά ιδιώτης. GET, λογοκριμένο από το κατώφλι place-owner· η κατοχή ' +
      'κρίνεται από το ίδιο listing-custody μέσω lookupOwnedPlace.',
  },
  {
    route: 'src/app/api/demand/competition/route.ts',
    why:
      '«Πόσοι ανταγωνίζονται τη ζήτησή μου». Η ζήτηση ανήκει σε ΑΝΘΡΩΠΟ, ποτέ σε ' +
      "γραφείο (tenant-config: property_demands mode 'userId'), και ο φρουρός είναι " +
      'ρητός: demand.authorUserId !== uid ⇒ 404. Χρησιμοποιεί ΜΟΝΟ το uid.',
  },
];

/** Οι διαδρομές που **όντως** καλούν το περιτύλιγμα — **tracked** αρχεία, όχι σκέτος δίσκος. */
function actualConsumers(): string[] {
  // 🔴 **ΤΟ ΜΟΤΙΒΟ ΚΡΙΝΕΙ ΤΗΝ ΚΛΗΣΗ, ΟΧΙ ΤΗΝ ΑΝΑΦΟΡΑ** — γεννήθηκε από μετάλλαξη που
  //    βγήκε ΠΡΑΣΙΝΗ (Μ7): με σκέτο το όνομα, αρχείο που **εισάγει** το περιτύλιγμα και
  //    **δεν το καλεί** μετριόταν ως καταναλωτής, οπότε η ορφανή δήλωση ήταν αόρατη.
  //    `withPersonalOrOrgAuth(` ή `withPersonalOrOrgAuth<` = **κλήση**· η γραμμή
  //    `import { withPersonalOrOrgAuth, ... }` δεν ταιριάζει.
  const out = execFileSync(
    'git',
    ['grep', '-lE', '-e', 'withPersonalOrOrgAuth[<(]', '--', 'src/app/api'],
    { cwd: REPO_ROOT, encoding: 'utf8' },
  );
  return out.split('\n').map((l) => l.trim()).filter(Boolean).sort();
}

describe('ADR-817 §5 — το κλειστό σύνολο των διαδρομών του πολίτη', () => {
  it('Κ1 — κάθε δήλωση φέρει ουσιαστικό λόγο (≥40 χαρακτήρες)', () => {
    for (const entry of DECLARED) {
      expect(entry.why.trim().length).toBeGreaterThanOrEqual(40);
    }
  });

  it('Κ2 — καμία ΑΔΗΛΩΤΗ διαδρομή δεν καλεί το withPersonalOrOrgAuth', () => {
    const declared = new Set(DECLARED.map((d) => d.route));
    const undeclared = actualConsumers().filter((r) => !declared.has(r));

    // ⛔ Αν αυτό κοκκινίσει: ΜΗΝ προσθέσεις απλώς γραμμή στο DECLARED. Ρώτα πρώτα
    //    «γιατί αυτή η διαδρομή δέχεται άνθρωπο χωρίς οργανισμό;» — η απάντηση ΕΙΝΑΙ
    //    ο λόγος που πρέπει να γραφτεί δίπλα της.
    expect(undeclared).toEqual([]);
  });

  it('Κ3 — καμία ΟΡΦΑΝΗ δήλωση: ό,τι δηλώνεται, καλεί όντως το περιτύλιγμα', () => {
    const actual = new Set(actualConsumers());
    const orphans = DECLARED.map((d) => d.route).filter((r) => !actual.has(r));

    // ⚠️ Χωρίς αυτό το σύνολο **σαπίζει σιωπηλά** (μάθημα CHECK 3.59 Κ2): μια δήλωση
    //    για διαδρομή που δεν υπάρχει πια δίνει ψεύτικη αίσθηση κάλυψης.
    expect(orphans).toEqual([]);
  });

  it('Π — Ο ΠΑΡΟΝΟΜΑΣΤΗΣ: το σύνολο ΔΕΝ είναι κενό', () => {
    // 🔴 Χωρίς αυτό, τα Κ2/Κ3 θα ήταν πράσινα σε δέντρο όπου **κανείς** δεν καλεί το
    //    περιτύλιγμα — δηλαδή «0 = κανείς δεν κοίταξε», το σχήμα που κυνηγάμε.
    expect(actualConsumers().length).toBe(4);
  });

  it('Π2 — Ο ΠΑΡΟΝΟΜΑΣΤΗΣ ΤΗΣ ΠΡΟΕΠΙΛΟΓΗΣ: η συντριπτική πλειοψηφία μένει εταιρική', () => {
    // 🔑 Το κριτήριο του ADR-817 §3 είναι «ρητή συμμετοχή», και αποδεικνύεται μόνο αν
    //    φαίνεται ΠΟΣΟ μικρό είναι το σύνολο έναντι της προεπιλογής. Ένα κριτήριο που
    //    άνοιγε «όσους δεν αναφέρουν companyId» θα έδινε **126** (96,8% ψευδώς θετικά).
    const orgRoutes = execFileSync(
      'git',
      ['grep', '-l', '-e', 'withAuth', '--', 'src/app/api'],
      { cwd: REPO_ROOT, encoding: 'utf8' },
    )
      .split('\n')
      .filter((l) => l.trim().endsWith('route.ts'));

    expect(orgRoutes.length).toBeGreaterThan(300);
  });
});
