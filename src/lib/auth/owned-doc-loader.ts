/**
 * «ΤΟ έγγραφο — αν είναι δικό μου»: η **αλυσίδα**, μία φορά για κάθε πόρο
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΓΙΑΤΙ ΥΠΑΡΧΕΙ (N.18 · CHECK 3.28 · ADR-742 §7octies · μάθημα #7 των Ομάδων 1–3)
 * ─────────────────────────────────────────────────────────────────────────────
 * Η Ομάδα 3 κεντρικοποίησε την **ερώτηση** («δικό μου;») και ανακάλυψε αμέσως
 * ότι δεν αρκούσε: τα σημεία εξακολουθούσαν να γράφουν την ίδια **τετράδα**:
 *
 * ```ts
 * const ref = db.collection(COLLECTION).doc(id);
 * const snap = await ref.get();
 * if (!snap.exists) throw xNotFound();          // υπάρχει;
 * const data = snap.data();
 * requireXAccess({ xData: data, … });           // δικό μου;
 * ```
 *
 * Το `jscpd` τη μέτρησε ως κλώνο **μέσα** στο ίδιο commit. Η Ομάδα 3 την έλυσε
 * με `project-owned-doc.ts` — για τα **έργα**. Η Ομάδα 4 θα έγραφε
 * `contact-owned-doc.ts` με **δομικά ίδιο** σώμα: ακριβώς η αστοχία που
 * προβλέπει ο N.18 (*«κεντρικοποιείς το Α και γράφεις Β+Γ ως δίδυμα»*), απλώς
 * ένα επίπεδο ψηλότερα — **δίδυμα κεντρικοποιητή**.
 *
 * ⇒ Η αλυσίδα ζει **εδώ**, μία φορά. Κάθε πόρος δίνει μόνο ό,τι τον κάνει
 * διαφορετικό: συλλογή, εργοστάσιο «δεν βρέθηκε», φύλακας.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 Ο ΚΙΝΔΥΝΟΣ ΔΕΝ ΕΙΝΑΙ ΟΙ ΓΡΑΜΜΕΣ — ΕΙΝΑΙ Η **ΣΕΙΡΑ**
 * ─────────────────────────────────────────────────────────────────────────────
 * Αντίγραφο που φορτώνει, **δουλεύει**, και ρωτά «δικό μου;» στο τέλος απαντά
 * κανονικά· απλώς έχει ήδη διαβάσει ξένο έγγραφο. Η διαφορά **δεν φαίνεται
 * πουθενά**: κανένα test του φύλακα δεν την πιάνει, γιατί ο φύλακας *κλήθηκε* —
 * απλώς αργά. Ενώνοντας φόρτωση + απόφαση σε **μία** κλήση, η σειρά παύει να
 * είναι θέμα προσοχής και γίνεται **δομική** (ADR-742 §7.1).
 *
 * 🔴 **Ο έλεγχος ύπαρξης ΔΕΝ είναι πλεονασμός του φύλακα** (μάθημα #8): για
 * μη-bypass καλούντα συμπίπτουν, αλλά για τον **υπεργραφέα** ο φύλακας λέει
 * «πέρνα», οπότε **μόνο** ο έλεγχος ύπαρξης τον σταματά — αλλιώς κατεβαίνει
 * **φάντασμα εγγράφου** (`data: undefined`). Γι' αυτό το `!snap.exists`
 * προηγείται **πάντα** και δεν παραμετροποιείται.
 *
 * ⚠️ **Επιστρέφει το ωμό `snap.data()`, όχι στενεμένο τύπο**: ο τύπος υπόσχεται
 * πεδία που η βάση δεν εγγυάται (§7.5). Η στένωση γίνεται στον **καλούντα**,
 * ρητά και ορατά.
 *
 * @module lib/auth/owned-doc-loader
 * @see ADR-742 §7.1 (η ταυτότητα είναι δομική) · §7sexies · §7octies
 */

import 'server-only';

import type { DocumentData, DocumentReference, Firestore } from 'firebase-admin/firestore';
import { getAdminFirestore } from '@/lib/firebaseAdmin';
import { createModuleLogger } from '@/lib/telemetry';

const logger = createModuleLogger('OwnedDocLoader');

export interface LoadOwnedDocSpec {
  /** Η συλλογή του πόρου — πάντα από το `COLLECTIONS` SSoT του καλούντος. */
  readonly collection: string;
  readonly docId: string;
  /** Ποιο μονοπάτι ρώτησε — μπαίνει στα logs ασφαλείας. */
  readonly action: string;
  /**
   * Ανθρώπινο όνομα πόρου για τα logs (π.χ. `'Contact'`). **Μόνο** για logs:
   * ό,τι φεύγει στο σύρμα το παράγει το {@link LoadOwnedDocSpec.notFound}.
   */
  readonly resourceLabel: string;
  /**
   * Το εργοστάσιο «δεν βρέθηκε» του πεδίου ορισμού. Καλείται **μόνο** όταν το
   * έγγραφο όντως λείπει· την άρνηση ιδιοκτησίας τη ρίχνει ο
   * {@link LoadOwnedDocSpec.assertOwned}. Και τα δύο **πρέπει** να παράγουν
   * πανομοιότυπο σύρμα — γι' αυτό στα πεδία ορισμού είναι το **ίδιο**
   * εργοστάσιο (ADR-742 §7.1).
   */
  readonly notFound: () => Error;
  /**
   * Ο φύλακας του πεδίου ορισμού. Ρίχνει αν η πρόσβαση απορριφθεί, αλλιώς
   * επιστρέφει σιωπηλά. Ο καλών κλείνει μέσα του τον `caller` και το `action`,
   * ώστε αυτό το module να μη γνωρίζει τίποτα για ταυτότητες.
   */
  readonly assertOwned: (data: DocumentData | undefined) => void;
  /**
   * Η ήδη ανοιγμένη σύνδεση, όταν ο καλών τη χρειάζεται **και** μετά (π.χ. ο
   * χειριστής διαγραφής τη δίνει στη μηχανή soft-delete). Χωρίς αυτό θα
   * άνοιγαν δύο στιγμιότυπα για το ίδιο αίτημα.
   */
  readonly db?: Firestore;
}

/** Ό,τι έχει στα χέρια του ο καλών **αφού** ο φύλακας έχει αποφανθεί. */
export interface OwnedDoc {
  readonly id: string;
  /** Για τους χειριστές που γράφουν αμέσως μετά — δεν ξαναχτίζεται το path. */
  readonly ref: DocumentReference<DocumentData>;
  /** Το φορτίο **όπως βγήκε από τη βάση** — ποτέ στενεμένο εδώ (§7.5). */
  readonly data: DocumentData | undefined;
}

/**
 * Διαβάζει το έγγραφο και **αμέσως** το κρίνει. Και τα δύο «όχι» — γνήσια
 * απουσία **και** άρνηση ιδιοκτησίας — βγαίνουν από το εργοστάσιο του πεδίου
 * ορισμού, οπότε ο καλών δεν μπορεί να τα ξεχωρίσει σε κανένα πεδίο του σύρματος.
 */
export async function loadOwnedDoc(spec: LoadOwnedDocSpec): Promise<OwnedDoc> {
  const { collection, docId, action, resourceLabel } = spec;

  const ref = (spec.db ?? getAdminFirestore()).collection(collection).doc(docId);
  const snap = await ref.get();

  if (!snap.exists) {
    logger.info(`${resourceLabel} not found`, { action, docId });
    throw spec.notFound();
  }

  const data = snap.data();
  spec.assertOwned(data);

  return { id: snap.id, ref, data };
}
