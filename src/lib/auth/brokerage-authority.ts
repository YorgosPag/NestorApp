/**
 * **Ποιος επιτρέπεται να δημοσιεύσει ΒΙΤΡΙΝΑ** — και γιατί **δεν** είναι δεύτερο brand.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΕΡΩΤΗΜΑ ΕΙΝΑΙ ΑΛΛΟ ΑΠΟ ΕΚΕΙΝΟ ΤΟΥ {@link BrokerageAuthority}
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Εκείνο ρωτά *«να δημοσιεύσει αγγελία για **ΞΕΝΟ** ακίνητο;»* — πράξη που ο
 * **Ν.4072/2012** ρυθμίζει. Αυτό ρωτά *«να εμφανιστεί στον κατάλογο
 * επαγγελματιών;»* — και η απάντηση εξαρτάται από **το επάγγελμα**: ο
 * ελαιοχρωματιστής δεν ζητά δικαίωμα από κανέναν *(ADR-798 Α4: η επαγγελματική
 * ιδιότητα είναι αυτο-δηλωμένη και **ποτέ** δεν δίνει δικαίωμα)*, ο **μεσίτης**
 * ζητά — γιατί εκεί η ίδια η **διαφήμιση** είναι η ρυθμιζόμενη πράξη.
 *
 * ⛔ **ΚΑΝΕΝΑ ΔΕΥΤΕΡΟ `unique symbol`, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ.** Το brand υπάρχει
 * επειδή **ξεχασμένος φρουρός = σιωπηλή νομική παράβαση**. Στη μη ρυθμιζόμενη
 * παραλλαγή **δεν υπάρχει φρουρός να ξεχαστεί**, άρα ένα `ProfessionalAuthority`
 * με δικό του symbol θα ήταν **τελετουργικό**: τύπος που φυλάει το τίποτα, και
 * μαζί του εννέα αδελφά αρχεία *(N.18 — μετρημένα στο σχέδιο Φ6-Β)*.
 *
 * 🔑 **Ο κίνδυνος που ΜΕΝΕΙ εκφράσιμος είναι η ΥΠΟΒΑΘΜΙΣΗ**: κάποιος που έχει
 * απόδειξη και γράφει `unregulated` για να γλιτώσει τον φρουρό. Δεν τον λύνει
 * το brand — τον λύνει το ότι ο μεταγλωττιστής αναγκάζει τον καλούντα να
 * **ονομάσει** την παραλλαγή, και ο {@link gateShowcase} την παράγει από **το
 * επάγγελμα**, ποτέ από επιλογή του καλούντος.
 */
export type ShowcaseAuthority =
  /** Κάποιο credential είναι ρυθμιζόμενο ⇒ **κρίθηκε** από τον κριτή της ικανότητας. */
  | { readonly kind: 'regulated'; readonly proof: BrokerageAuthority }
  /** Κανένα ρυθμιζόμενο ⇒ αρκεί ότι ο άνθρωπος ανήκει σε **αυτόν** τον οργανισμό. */
  | { readonly kind: 'unregulated'; readonly companyId: string };

/**
 * **ΤΟ ΚΛΕΙΔΙ ΤΟΥ ΕΓΓΡΑΦΟΥ — ΜΙΑ ΠΗΓΗ, ΚΑΙ ΟΙ ΔΥΟ ΠΑΡΑΛΛΑΓΕΣ.**
 *
 * 🔴 Ο γραφέας γράφει **αποκλειστικά** ό,τι επιστρέφει αυτή η συνάρτηση, ποτέ
 * `companyId` από το σώμα. Έτσι *«κρίθηκε ο ένας, γράφτηκε ο άλλος»* παραμένει
 * **αδύνατο** και στις δύο παραλλαγές — όχι μόνο στη ρυθμιζόμενη, όπου το brand
 * το εγγυάται από μόνο του.
 *
 * ⚠️ Ένα `switch` στον καλούντα θα ήταν **δεύτερη απάντηση** στο *«ποιανού είναι
 * αυτή η βιτρίνα;»*, και η δεύτερη θα ξεχνούσε μια παραλλαγή σιωπηλά.
 */
export function showcaseOwnerId(authority: ShowcaseAuthority): string {
  return authority.kind === 'regulated' ? authority.proof.companyId : authority.companyId;
}
