import {
  capabilityStatusOf,
  isCapabilityActive,
  type CapabilityStatus,
  type OrganizationCapabilities,
} from '@/types/organization-capability';

// =============================================================================
// Η ΑΠΟΔΕΙΞΗ
// =============================================================================

/**
 * 🔴 **ΠΡΑΓΜΑΤΙΚΟ symbol, ΜΗ ΕΞΑΓΟΜΕΝΟ — και τα δύο είναι απαραίτητα.**
 *
 * *«Πραγματικό»*: ένα `declare const … : unique symbol` είναι **μόνο τύπος** και
 * σβήνεται στη μεταγλώττιση ⇒ το αντικείμενο δεν μπορεί καν να κατασκευαστεί
 * (`ReferenceError` — **μετρημένο**, όχι υποθετικό). *«Μη εξαγόμενο»*: όποιος δεν
 * βλέπει το κλειδί **δεν μπορεί** να γράψει αντικείμενο που να ικανοποιεί τον τύπο.
 *
 * ⚠️ Το `unique symbol` απαιτεί `const` με **άμεση** κλήση `Symbol()` — γι' αυτό η
 * δήλωση είναι ακριβώς αυτή και όχι κάτι πιο «καθαρό».
 */
const BROKERAGE_AUTHORITY: unique symbol = Symbol('BrokerageAuthority');

/**
 * **Η απόδειξη ότι αυτός ο οργανισμός ΕΠΙΤΡΕΠΕΤΑΙ να μεσιτεύει.**
 *
 * 🔴 **Αδιαπέραστος τύπος**: το `__brand` είναι `unique symbol` που **δεν
 * εξάγεται**, άρα **κανένα literal δεν τον ικανοποιεί** — ούτε `{} as
 * BrokerageAuthority`, γιατί ένας τέτοιος ισχυρισμός είναι πλέον **ορατός σε
 * αναθεώρηση** αντί για σιωπηλά απούσα κλήση.
 *
 * ⚠️ **Κουβαλά το `companyId` ΤΟΥ ΚΡΙΤΗ**, όχι του καλούντος. Ο γραφέας γράφει
 * `authorCompanyId` **από την απόδειξη** — άρα δεν υπάρχει τρόπος να κριθεί ο ένας
 * οργανισμός και να γραφτεί ο άλλος.
 */
export interface BrokerageAuthority {
  readonly [BROKERAGE_AUTHORITY]: true;
  readonly companyId: string;
}

/**
 * **Η άρνηση — με λόγο που ονομάζει τι εκκρεμεί.**
 *
 * ⚠️ **Ποτέ `null`, ποτέ `boolean`**: ένα «όχι» χωρίς λόγο δεν μπορεί ούτε να
 * εξηγηθεί στον άνθρωπο ούτε να ξεχωρίσει από σφάλμα. Ίδιο συμβόλαιο με το
 * `CapabilityDecision.reason` του ADR-801.
 */
export interface BrokerageDenial {
  readonly denied: true;
  /** Η κατάσταση **που πράγματι βρέθηκε** — η οθόνη δείχνει άλλο μήνυμα σε καθεμία. */
  readonly status: CapabilityStatus;
  /** Κλειδί i18n του «γιατί όχι». */
  readonly reason: string;
}

/**
 * Κλειδί i18n ανά κατάσταση **που αρνείται**.
 *
 * 🔑 **`Record<CapabilityStatus, …>` και ΟΧΙ χάρτης μερικών κλειδιών** — ίδιο ιδίωμα
 * με το `REASON_BY_VERDICT` του ADR-801: μια **πέμπτη** κατάσταση **δεν
 * μεταγλωττίζεται** μέχρι να αποκτήσει λόγο. Φρουρός που προστίθεται χωρίς εξήγηση
 * είναι άρνηση που ο χρήστης βλέπει ως κενή οθόνη.
 */
const REASON_BY_STATUS: Record<CapabilityStatus, string | null> = {
  active: null,
  unrequested: 'auth:brokerage.denyReason.unrequested',
  pending: 'auth:brokerage.denyReason.pending',
  revoked: 'auth:brokerage.denyReason.revoked',
};

export function isBrokerageDenial(
  value: BrokerageAuthority | BrokerageDenial,
): value is BrokerageDenial {
  return 'denied' in value;
}

