/**
 * **Επιτρέπεται σε αυτόν τον οργανισμό να δημοσιεύσει αγγελία τρίτου;**
 *
 * @param companyId Ο οργανισμός **από τα claims** (`ctx.companyId`), ποτέ από το σώμα.
 * @param capabilities Ό,τι κρατά το `companies/{id}` — `undefined` ⇒ `unrequested`.
 *
 * @returns Η **απόδειξη**, ή η άρνηση **με τον λόγο της**.
 *
 * ⚠️ **Δεν διαβάζει βάση.** Δέχεται την κατάσταση **έτοιμη**, όπως ο
 * `decideCapability` δέχεται claims: έτσι μένει **καθαρή συνάρτηση** και μπορεί να
 * δοκιμαστεί χωρίς Firestore — ακριβώς το κενό που έκανε την επανασύνθεση του
 * ADR-777 §8.45 αδοκίμαστη.
 *
 * 🔴 **Κενό `companyId` ⇒ ΑΡΝΗΣΗ, fail-closed** (πρότυπο `extractCustomClaims`,
 * ADR-657 §3.5): *«κενή συμβολοσειρά = **απουσία**, όχι μισθωτής»*. Ο **ιδιώτης**
 * δεν περνά ποτέ από εδώ — δες τον παρονομαστή παρακάτω.
 *
 * ⛔ **Ο ΙΔΙΩΤΗΣ ΔΕΝ ΑΓΓΙΖΕΤΑΙ** (ADR-824 §7 · άγκυρα Κ4). Η διαδρομή
 * `/offers/new` → `POST /api/owner-properties` γράφει `mandate: {kind:'self'}` και
 * `authorCompanyId: null`, και **παραμένει ανοιχτή σε κάθε συνδεδεμένο άνθρωπο**. Η
 * ρυθμιζόμενη πράξη είναι **αποκλειστικά** το `brokered` σκέλος — η διάκριση ήταν
 * **ήδη γραμμένη στον τύπο** (`OwnerPropertyMandate.kind`), γι' αυτό η αλλαγή χωρά
 * σε ένα σημείο και **καμία νέα έννοια δεν γεννιέται**.
 */
export function requireBrokerageCapability(
  companyId: string | null | undefined,
  capabilities: OrganizationCapabilities | undefined,
): BrokerageAuthority | BrokerageDenial {
  const status = capabilityStatusOf(capabilities, 'brokerage_listings');

  // 🔴 **ΘΕΤΙΚΟΣ έλεγχος.** Ένα `status !== 'unrequested'` θα άφηνε να περάσουν
  //    **και** το `pending` **και** το `revoked` — τις δύο καταστάσεις που υπάρχουν
  //    για να αρνούνται. Άγκυρα Κ3 του ADR-824 §8.
  if (!isCapabilityActive(status)) {
    return { denied: true, status, reason: REASON_BY_STATUS[status] ?? deniedFallback(status) };
  }

  const tenant = typeof companyId === 'string' ? companyId.trim() : '';
  if (tenant === '') {
    // Δομικά απίθανο (ενεργή ικανότητα χωρίς μισθωτή), και **γι' αυτό** δηλώνεται:
    // μια σιωπηλή διέλευση εδώ θα παρήγαγε απόδειξη **χωρίς υποκείμενο**.
    return { denied: true, status: 'unrequested', reason: REASON_BY_STATUS.unrequested ?? '' };
  }

  return { [BROKERAGE_AUTHORITY]: true, companyId: tenant };
}

/**
 * Δεν μπορεί να πυροδοτήσει με το σημερινό `Record` — υπάρχει ώστε η **προσθήκη**
 * κατάστασης χωρίς λόγο να μη σιωπά, αλλά να δίνει **ονομαστικό** κλειδί.
 */
function deniedFallback(status: CapabilityStatus): string {
  return `auth:brokerage.denyReason.${status}`;
}
