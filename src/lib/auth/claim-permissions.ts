import { isValidPermission, type PermissionId } from './types';

/**
 * Οι ικανότητες που **ρητά** κουβαλά το claim, επικυρωμένες.
 *
 * @param raw Η ωμή τιμή του claim `permissions`, όπως έρχεται από το token
 *            (`DecodedIdToken['permissions']` στον server,
 *            `IdTokenResult['claims'].permissions` στον πελάτη).
 * @returns Παγωμένος πίνακας γνωστών ικανοτήτων· `undefined` όταν το token
 *          **δεν φέρει** το κανάλι.
 *
 * @example
 * const permissions = readPermissionsClaim(token.permissions);
 * // ['admin_access']  ·  []  ·  undefined
 */
export function readPermissionsClaim(
  raw: unknown,
): readonly PermissionId[] | undefined {
  if (!Array.isArray(raw)) return undefined;

  const granted: PermissionId[] = [];
  for (const entry of raw) {
    // ⚠️ Ο έλεγχος τύπου είναι δικός μας: το claim έρχεται από το σύρμα και ένα
    //    `[42, null]` είναι απολύτως δυνατό. Το `isValidPermission` δέχεται
    //    `string` — χωρίς αυτόν τον φρουρό θα του δίναμε ό,τι να 'ναι.
    if (typeof entry !== 'string' || !isValidPermission(entry)) continue;

    // Το claim γράφεται ως **ένωση συνόλων** (`claims-handler.ts:159`), αλλά
    // παλαιότερα έγγραφα δεν το εγγυώνται. Κανονικοποιούμε ώστε η άγκυρα
    // ισοδυναμίας να συγκρίνει **κανονική** μορφή και στις δύο πλευρές.
    if (!granted.includes(entry)) granted.push(entry);
  }

  return Object.freeze(granted);
}
