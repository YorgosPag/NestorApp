/**
 * @fileoverview **ΙΔΙΑ ΕΠΩΝΥΜΙΑ;** — η σύγκριση δήλωσης ⇄ μητρώου (ADR-841 §7 Α23).
 * @module lib/company/legal-name-match
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ Η ΙΣΟΤΗΤΑ ΚΕΙΜΕΝΟΥ ΘΑ ΕΛΕΓΕ ΨΕΜΑΤΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το προφίλ του ζωντανού γραφείου γράφει *«ΠΑΓΩΝΗΣ Ενεργειακή Κατασκευαστική Α.Ε.»*· το ΓΕΜΗ
 * γράφει τις επωνυμίες **κεφαλαία, χωρίς τόνους, με τη νομική μορφή ολογράφως**. Σύγκριση
 * κειμένου θα έβγαζε «η επωνυμία διαφέρει από το ΓΕΜΗ» σε **σωστή** δήλωση — και ο άνθρωπος θα
 * άλλαζε την επωνυμία του για να ικανοποιήσει ένα λάθος του λογισμικού.
 *
 * | Διαφορά που ΔΕΝ αλλάζει την επωνυμία | Χειρισμός |
 * |---|---|
 * | τόνοι · διαλυτικά · πεζά/κεφαλαία · τελικό σίγμα | NFD + αφαίρεση σημείων + κεφαλαία |
 * | στίξη και κενά («Α.Ε.» ⇄ «ΑΕ») | διαχωρισμός σε λέξεις + συνένωση αρχικών |
 * | ολογράφως νομική μορφή («ΑΝΩΝΥΜΗ ΕΤΑΙΡΕΙΑ» ⇄ «ΑΕ») | πίνακας φράσεων |
 * | «& ΣΙΑ» ⇄ «ΚΑΙ ΣΙΑ» | πίνακας φράσεων |
 * | λατινικό Α που μοιάζει με ελληνικό | αναδίπλωση ομόγλυφων |
 *
 * ⛔ **Διαφορά που ΑΛΛΑΖΕΙ την επωνυμία μένει διαφορά**: άλλη λέξη, άλλη νομική μορφή
 * («ΑΕ» ≠ «ΕΠΕ»). Ό,τι δεν ταιριάζει δεν «διορθώνεται» σιωπηλά — η οθόνη προσφέρει **ρητή**
 * υιοθέτηση της επωνυμίας του μητρώου.
 *
 * **Layering**: καθαρή — πελάτης και διακομιστής.
 */

const COMBINING_MARKS = /\p{M}/gu;
const NON_ALPHANUMERIC = /[^\p{L}\p{N}]+/u;

/** Λατινικά κεφαλαία που **δεν ξεχωρίζουν οπτικά** από ελληνικά. */
const LATIN_HOMOGLYPHS: Readonly<Record<string, string>> = {
  A: 'Α', B: 'Β', E: 'Ε', Z: 'Ζ', H: 'Η', I: 'Ι', K: 'Κ',
  M: 'Μ', N: 'Ν', O: 'Ο', P: 'Ρ', T: 'Τ', Y: 'Υ', X: 'Χ',
};

/**
 * Ολογράφως ⇒ σύντομη μορφή. **Μακρύτερες φράσεις πρώτες**, ώστε το «ΜΟΝΟΠΡΟΣΩΠΗ ΙΚΕ» να μη
 * διαβαστεί «ΜΟΝΟΠΡΟΣΩΠΗ» + «ΙΚΕ».
 */
const EQUIVALENT_PHRASES: readonly (readonly [string, string])[] = [
  ['ΜΟΝΟΠΡΟΣΩΠΗ ΙΔΙΩΤΙΚΗ ΚΕΦΑΛΑΙΟΥΧΙΚΗ ΕΤΑΙΡΕΙΑ', 'ΜΙΚΕ'],
  ['ΜΟΝΟΠΡΟΣΩΠΗ ΕΤΑΙΡΕΙΑ ΠΕΡΙΟΡΙΣΜΕΝΗΣ ΕΥΘΥΝΗΣ', 'ΜΕΠΕ'],
  ['ΙΔΙΩΤΙΚΗ ΚΕΦΑΛΑΙΟΥΧΙΚΗ ΕΤΑΙΡΕΙΑ', 'ΙΚΕ'],
  ['ΕΤΑΙΡΕΙΑ ΠΕΡΙΟΡΙΣΜΕΝΗΣ ΕΥΘΥΝΗΣ', 'ΕΠΕ'],
  ['ΕΤΑΙΡΕΙΑ ΠΕΡΙΩΡΙΣΜΕΝΗΣ ΕΥΘΥΝΗΣ', 'ΕΠΕ'],
  ['ΑΝΩΝΥΜΗ ΕΤΑΙΡΕΙΑ', 'ΑΕ'],
  ['ΑΝΩΝΥΜΟΣ ΕΤΑΙΡΕΙΑ', 'ΑΕ'],
  ['ΟΜΟΡΡΥΘΜΗ ΕΤΑΙΡΕΙΑ', 'ΟΕ'],
  ['ΕΤΕΡΟΡΡΥΘΜΗ ΕΤΑΙΡΕΙΑ', 'ΕΕ'],
  ['ΜΟΝΟΠΡΟΣΩΠΗ ΙΚΕ', 'ΜΙΚΕ'],
  ['ΜΟΝΟΠΡΟΣΩΠΗ ΕΠΕ', 'ΜΕΠΕ'],
  ['ΚΑΙ ΣΙΑ', 'ΣΙΑ'],
];

/** Συνεχόμενα μονογράμματα γίνονται μία λέξη: «Α» «Ε» ⇒ «ΑΕ». */
function mergeInitials(tokens: readonly string[]): string[] {
  const merged: string[] = [];
  let initials = '';
  for (const token of tokens) {
    if ([...token].length === 1) {
      initials += token;
      continue;
    }
    if (initials !== '') merged.push(initials);
    initials = '';
    merged.push(token);
  }
  if (initials !== '') merged.push(initials);
  return merged;
}

/** Η κανονική μορφή σύγκρισης μιας επωνυμίας. **Όχι** για προβολή. */
export function normalizeLegalName(name: string): string {
  const folded = name
    .normalize('NFD')
    .replace(COMBINING_MARKS, '')
    .toUpperCase()
    .replace(/[A-Z]/g, (letter) => LATIN_HOMOGLYPHS[letter] ?? letter);
  const tokens = mergeInitials(folded.split(NON_ALPHANUMERIC).filter((token) => token !== ''));
  let padded = ` ${tokens.join(' ')} `;
  for (const [phrase, short] of EQUIVALENT_PHRASES) {
    padded = padded.split(` ${phrase} `).join(` ${short} `);
  }
  return padded.trim();
}

/** Ίδια επωνυμία; — `false` όταν **οποιαδήποτε** είναι κενή (δύο απουσίες δεν «ταιριάζουν»). */
export function sameLegalName(a: string | null | undefined, b: string | null | undefined): boolean {
  const left = normalizeLegalName(a ?? '');
  return left !== '' && left === normalizeLegalName(b ?? '');
}
