/**
 * @fileoverview Άγκυρες της **σύγκρισης επωνυμίας** δήλωσης ⇄ μητρώου — ADR-841 §7 Α23 (Φ2).
 *
 * 🔴 Δύο κατευθύνσεις, και η δεύτερη μετρά όσο η πρώτη: **σωστή** δήλωση δεν επιτρέπεται να
 * βγει «διαφορετική» (Ι) — και **άλλη** επωνυμία δεν επιτρέπεται να βγει «ίδια» (Δ).
 */

import { normalizeLegalName, sameLegalName } from '@/lib/company/legal-name-match';

describe('Ι — ίδια επωνυμία, άλλη γραφή', () => {
  it.each([
    ['Ι1 ζωντανό γραφείο', 'ΠΑΓΩΝΗΣ Ενεργειακή Κατασκευαστική Α.Ε.', 'ΠΑΓΩΝΗΣ ΕΝΕΡΓΕΙΑΚΗ ΚΑΤΑΣΚΕΥΑΣΤΙΚΗ ΑΝΩΝΥΜΗ ΕΤΑΙΡΕΙΑ'],
    ['Ι2 τόνοι και τελικό σίγμα', 'Παγώνης', 'ΠΑΓΩΝΗΣ'],
    ['Ι3 ΙΚΕ ολογράφως', 'ΑΛΦΑ Ι.Κ.Ε.', 'ΑΛΦΑ ΙΔΙΩΤΙΚΗ ΚΕΦΑΛΑΙΟΥΧΙΚΗ ΕΤΑΙΡΕΙΑ'],
    ['Ι4 «& ΣΙΑ»', 'Κ. ΠΑΠΑΔΟΠΟΥΛΟΣ & ΣΙΑ Ο.Ε.', 'Κ ΠΑΠΑΔΟΠΟΥΛΟΣ ΚΑΙ ΣΙΑ ΟΜΟΡΡΥΘΜΗ ΕΤΑΙΡΕΙΑ'],
    ['Ι5 λατινικά ομόγλυφα', 'AΛΦA AE', 'ΑΛΦΑ ΑΕ'],
    ['Ι6 μονοπρόσωπη', 'ΒΗΤΑ ΜΟΝΟΠΡΟΣΩΠΗ Ι.Κ.Ε.', 'ΒΗΤΑ Μ.Ι.Κ.Ε.'],
    ['Ι7 καθαρεύουσα', 'ΓΑΜΜΑ ΑΕ', 'ΓΑΜΜΑ ΑΝΩΝΥΜΟΣ ΕΤΑΙΡΕΙΑ'],
  ])('%s', (_label, declared, registry) => {
    expect(sameLegalName(declared, registry)).toBe(true);
  });
});

describe('Δ — διαφορετική επωνυμία μένει διαφορετική', () => {
  it('Δ1 — άλλη λέξη', () => {
    expect(sameLegalName('ΑΛΦΑ ΑΕ', 'ΒΗΤΑ ΑΕ')).toBe(false);
  });

  it('Δ2 — 🔴 άλλη νομική μορφή: ΑΕ ≠ ΕΠΕ', () => {
    expect(sameLegalName('ΑΛΦΑ Α.Ε.', 'ΑΛΦΑ ΕΤΑΙΡΕΙΑ ΠΕΡΙΟΡΙΣΜΕΝΗΣ ΕΥΘΥΝΗΣ')).toBe(false);
  });

  it('Δ3 — λέξη που λείπει', () => {
    expect(sameLegalName('ΠΑΓΩΝΗΣ ΑΕ', 'ΠΑΓΩΝΗΣ ΕΝΕΡΓΕΙΑΚΗ ΑΕ')).toBe(false);
  });

  it('Δ4 — 🔑 δύο απουσίες ΔΕΝ ταιριάζουν', () => {
    expect(sameLegalName('', '')).toBe(false);
    expect(sameLegalName(null, '   ')).toBe(false);
  });
});

describe('Κ — η κανονική μορφή', () => {
  it('Κ1 — συντομογραφία και ολόγραφο καταλήγουν στο ΙΔΙΟ κείμενο', () => {
    expect(normalizeLegalName('Παγώνης Α.Ε.')).toBe('ΠΑΓΩΝΗΣ ΑΕ');
    expect(normalizeLegalName('ΠΑΓΩΝΗΣ ΑΝΩΝΥΜΗ ΕΤΑΙΡΕΙΑ')).toBe('ΠΑΓΩΝΗΣ ΑΕ');
  });
});
