/**
 * @fileoverview **ΤΙ ΑΚΡΙΒΩΣ ΚΑΤΑΛΑΜΒΑΝΕΤΑΙ** — ο πόρος ως **σύνολο χώρων × πράξη**.
 * @related lib/occupancy/occupancy-conflict.ts · types/property-offers.ts
 * @module lib/occupancy/occupancy-resource
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Ο ΠΟΡΟΣ ΑΝΑΘΕΩΡΗΘΗΚΕ, ΚΑΙ Ο ΛΟΓΟΣ ΕΙΝΑΙ ΝΟΜΙΚΟΣ (ADR-835 §4.12)
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ADR-832 όρισε τον πόρο ως `(ακίνητο × πράξη)` και **δεν έκανε λάθος**: μια εντολή
 * πώλησης αφορά **πάντα** ολόκληρο το ακίνητο. Έγινε ανεπαρκής **μόνο** όταν
 * εμφανίστηκε πόρος που **περιέχει** άλλον.
 *
 * > **«Αν μισθώνεται διακριτά ένα δωμάτιο, χρειάζεται ξεχωριστός ΑΜΑ· και αν το ίδιο
 * > ακίνητο διατίθεται και ολόκληρο και τμηματικά, χρειάζεται ξεχωριστός ΑΜΑ για το
 * > σύνολο και για κάθε διακριτό χώρο.»** *(ΑΑΔΕ, βραχυχρόνια διαμονή)*
 *
 * Άρα `ΑΜΑ-1 ≠ ΑΜΑ-2`, και κριτής με **ισότητα** απαντούσε `clear` σε:
 *
 * > Κράτηση **ολόκληρου** 10–17/08 · Κράτηση **δωματίου Α** 12–14/08
 * > ⇒ **δύο οικογένειες στην πόρτα**.
 *
 * ⚠️ Είναι **ακριβώς** το σχήμα που το έργο κυνηγά: πύλη που λέει «καθαρό» επειδή
 * **ρώτησε λάθος ερώτηση** — όχι επειδή κοίταξε.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 Η ΜΗΧΑΝΗ ΤΟ ΕΚΑΝΕ ΣΧΕΔΟΝ ΗΔΗ — ΕΝΑ ΕΠΙΠΕΔΟ ΠΑΝΩ, ΟΧΙ ΔΕΥΤΕΡΗ ΜΗΧΑΝΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `sharedResources` του ADR-832 ήταν **ήδη τομή συνόλων**:
 *
 * ```ts
 * return a.scope.filter((kind) => b.scope.includes(kind));   // σύνολο ΠΡΑΞΕΩΝ
 * ```
 *
 * Η επέκταση από **σύνολο πράξεων** σε **σύνολο (χώρος × πράξη)** είναι η **ίδια
 * πράξη** ένα επίπεδο πάνω (ADR-749). Σύνολο ενός στοιχείου με `spaceId: null`
 * συμπεριφέρεται **ακριβώς** όπως πριν ⇒ κανένας υπάρχων καταναλωτής δεν σπάει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Η ΣΧΕΣΗ ΤΟΜΗΣ **ΔΕΝ ΕΙΝΑΙ ΙΣΟΔΥΝΑΜΙΑ** — ΜΗΝ ΤΗΝ «ΒΕΛΤΙΣΤΟΠΟΙΗΣΕΙΣ» ΜΕ `Set`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * `δωμάτιο Α ∩ ολόκληρο` ✅ · `ολόκληρο ∩ δωμάτιο Β` ✅ · **`δωμάτιο Α ∩ δωμάτιο Β` ❌**
 *
 * Δηλαδή η σχέση **δεν είναι μεταβατική**. Κάθε υλοποίηση που χτίζει `Set` από κλειδιά
 * και ρωτά `has()` επιβάλλει σιωπηλά **ισότητα** — δηλαδή ξαναφέρνει το ελάττωμα που
 * αυτό το αρχείο υπάρχει για να λύσει. Ο διπλός βρόχος είναι **ο κανόνας**, όχι
 * αφέλεια: τα σύνολα είναι μονοψήφια (χώροι ενός ακινήτου × 4 πράξεις).
 *
 * **Layering**: leaf — καθαρές συναρτήσεις, μηδέν I/O, μηδέν ρολόι.
 */

import type { OfferKind } from '@/types/property-offers';

// =============================================================================
// 1. ΤΟ ΑΤΟΜΟ ΤΟΥ ΠΟΡΟΥ
// =============================================================================

/**
 * **Ένας χώρος, σε μία πράξη** — το άτομο του πόρου.
 *
 * 🔑 **Το ακίνητο ΔΕΝ είναι πια το άτομο.** Είναι ο **περιέκτης**: το `propertyId`
 * οριοθετεί το σύμπαν μέσα στο οποίο έχει νόημα το `spaceId`, και το
 * {@link OccupancyResource.spaceId} λέει **ποιο μέρος του**.
 *
 * ⚠️ **Το `propertyId` ΔΕΝ είναι διακοσμητικό, και ο λόγος είναι μετρημένος**: το
 * `spaceId: null` σημαίνει *«κάθε χώρος»*. Χωρίς περιέκτη, **δύο διαφορετικά
 * ακίνητα** που καταλαμβάνονται ολόκληρα θα είχαν `null ∩ null` ⇒ **ψεύτικη
 * σύγκρουση** — και μάλιστα σε ολόκληρο τον κατάλογο. Το μπαλαντέρ **πρέπει** να έχει
 * σύνορο.
 */
export interface OccupancyResource {
  /** Το ακίνητο. **Ο περιέκτης**, ποτέ το άτομο. */
  readonly propertyId: string;
  /**
   * Ο χώρος μέσα του. **`null` = ΟΛΟΚΛΗΡΟ το ακίνητο** — καλύπτει **κάθε** χώρο του.
   *
   * 🔑 Το «ολόκληρο» **δεν είναι ξεχωριστή τιμή δίπλα στα δωμάτια**: είναι το
   * **πλήρες σύνολο** των χώρων, εκφρασμένο ως μπαλαντέρ ώστε ο κριτής να μη
   * χρειάζεται να **ξέρει** ποιοι είναι οι χώροι (θα ήταν ανάγνωση — δεν είναι leaf).
   */
  readonly spaceId: string | null;
  /** Η πράξη — το «ίδιο περιεχόμενο» του άρθρου 200 §4 Ν.4072/2012. */
  readonly kind: OfferKind;
}

// =============================================================================
// 2. Η ΤΟΜΗ
// =============================================================================

/**
 * **Ταυτότητα ενός πόρου ως κείμενο** — μόνο για **αποδιπλασιασμό αποτελεσμάτων**.
 *
 * ⛔ **ΠΟΤΕ ως κριτήριο σύγκρουσης.** Δύο πόροι με **διαφορετικό** κλειδί μπορεί
 * κάλλιστα να τέμνονται (`ολόκληρο` vs `δωμάτιο Α`). Δες την κεφαλίδα: η σχέση δεν
 * είναι ισοδυναμία, και το κλειδί δεν την εκφράζει.
 */
export function resourceKey(resource: OccupancyResource): string {
  // `|` ως διαχωριστής: δεν εμφανίζεται σε enterprise id ούτε σε `OfferKind`, άρα δύο
  // διαφορετικές τριάδες δεν μπορούν να παραγάγουν το ίδιο κλειδί.
  return `${resource.propertyId}|${resource.spaceId ?? '*'}|${resource.kind}`;
}

/**
 * **Τέμνονται αυτοί οι δύο πόροι;** — τα τρία ερωτήματα, με αυτή τη σειρά.
 *
 * 1. **Ίδια πράξη;** Αποκλειστική **πώλησης** και εντολή **εκμίσθωσης** είναι δύο
 *    πόροι (άρθρο 200 §4· και γι' αυτό το RESO ξεχωρίζει `Right To Sell` από `…To
 *    Lease`).
 * 2. **Ίδιο ακίνητο;** Το σύνορο του μπαλαντέρ.
 * 3. **Τέμνονται οι χώροι;** Μπαλαντέρ **σε οποιαδήποτε πλευρά** τέμνει τα πάντα
 *    μέσα στο ίδιο ακίνητο — αυτό ακριβώς κάνει την κράτηση ολόκληρου να **κλείνει
 *    μόνη της** τα δωμάτια, χωρίς σχέση «γονέας–παιδί» και χωρίς ρύθμιση χρήστη.
 */
export function resourcesIntersect(
  a: OccupancyResource,
  b: OccupancyResource,
): boolean {
  if (a.kind !== b.kind) return false;
  if (a.propertyId !== b.propertyId) return false;
  return a.spaceId === null || b.spaceId === null || a.spaceId === b.spaceId;
}

/**
 * **Ποιος από τους δύο είναι ο ΑΜΦΙΣΒΗΤΟΥΜΕΝΟΣ** — καλείται μόνο όταν τέμνονται.
 *
 * 🏆 **Ο στενότερος, και είναι απόφαση με συνέπεια.** Όταν συγκρούονται *«κράτηση
 * ολόκληρου»* και *«κράτηση δωματίου Α»*, το χρήσιμο μήνυμα είναι **«το δωμάτιο Α
 * είναι δεσμευμένο»** — όχι «το ακίνητο είναι δεσμευμένο». Το δεύτερο είναι αληθές
 * αλλά **ακατάλληλο**: ο άνθρωπος ζήτησε ένα δωμάτιο, και απάντηση για ολόκληρο το
 * ακίνητο τον αφήνει να μην ξέρει **τι ακριβώς** εμποδίστηκε.
 *
 * ⚠️ Ίδιο σκεπτικό με το `reasonFor` του κριτή: όταν αποκλείουν **και οι δύο**, η
 * απάντηση διαλέγει αυτήν που δίνει στον άνθρωπο **δρόμο**, όχι αυτήν που ήρθε πρώτη.
 */
export function contestedResource(
  a: OccupancyResource,
  b: OccupancyResource,
): OccupancyResource {
  return a.spaceId === null ? b : a;
}

/**
 * **Ποιους πόρους μοιράζονται αυτές οι δύο καταλήψεις.** Κενό ⇒ **άλλος πόρος**.
 *
 * Επιστρέφει τους **αμφισβητούμενους** πόρους (τους στενότερους κάθε τομής),
 * **αποδιπλασιασμένους** και με τη σειρά της πρώτης κατάληψης.
 *
 * ⚠️ **Ο αποδιπλασιασμός δεν είναι καλλωπισμός**: μια κράτηση ολόκληρου που τέμνει
 * **δύο** καταχωρίσεις δωματίων παράγει δύο **διαφορετικούς** αμφισβητούμενους χώρους
 * (σωστό — δύο γραμμές στην οθόνη), ενώ **δύο** μπαλαντέρ που τέμνουν τον **ίδιο**
 * αμφισβητούμενο χώρο θα παρήγαγαν την ίδια γραμμή δύο φορές (θόρυβος).
 */
export function sharedResources(
  a: readonly OccupancyResource[],
  b: readonly OccupancyResource[],
): readonly OccupancyResource[] {
  const contested: OccupancyResource[] = [];
  const seen = new Set<string>();

  for (const left of a) {
    for (const right of b) {
      if (!resourcesIntersect(left, right)) continue;

      const resource = contestedResource(left, right);
      const key = resourceKey(resource);
      if (seen.has(key)) continue;

      seen.add(key);
      contested.push(resource);
    }
  }

  return contested;
}

