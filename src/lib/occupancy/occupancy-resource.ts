/**
 * **Ολόκληρο το ακίνητο, σε αυτές τις πράξεις** — η συνήθης κατάληψη.
 *
 * 🔑 Υπάρχει ώστε το «ολόκληρο» να γράφεται **μία** φορά. Κάθε καταναλωτής που θα
 * έγραφε `{ propertyId, spaceId: null, kind }` στο χέρι θα ήταν ένα σημείο όπου
 * κάποιος μπορεί να ξεχάσει το `null` και να πει «κανένας χώρος» εννοώντας «όλοι».
 */
export function wholeProperty(
  propertyId: string,
  kinds: readonly OfferKind[],
): readonly OccupancyResource[] {
  return kinds.map((kind) => ({ propertyId, spaceId: null, kind }));
}
