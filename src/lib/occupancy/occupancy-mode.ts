/**
 * @fileoverview **ΜΕ ΠΟΙΟΝ ΤΡΟΠΟ ΚΑΤΑΛΑΜΒΑΝΕΙ** — το τρίτο σκέλος του κριτή.
 * @related lib/occupancy/occupancy-conflict.ts · types/listing-agreement.ts
 * @module lib/occupancy/occupancy-mode
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ ΜΕΤΑΚΟΜΙΣΕ ΕΔΩ (ADR-835 Φ2) — ΚΑΙ ΓΙΑΤΙ ΟΧΙ ΜΕ ΑΝΤΙΓΡΑΦΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το λεξιλόγιο `shared | exclusive` γεννήθηκε στο `types/listing-agreement.ts` ως
 * `MandateLockMode`, επειδή ο **πρώτος** καταναλωτής του ήταν η εντολή μεσιτείας. Με
 * τον **δεύτερο** καταναλωτή (τις κρατήσεις) το όνομα έγινε ψευδές: μια κράτηση
 * καταλαμβάνει `exclusive` με **ακριβώς τον ίδιο** τρόπο, χωρίς να είναι εντολή.
 *
 * ⚠️ **Δεν αντιγράφηκε, μετακόμισε — και ήταν μετρήσιμα φθηνό**: το παλιό ζεύγος
 * (`MANDATE_LOCK_MODES` · `modesCompatible`) είχε **δύο** αρχεία-καταναλωτές σε όλο το
 * `src/` (το ίδιο το `listing-agreement.ts` και ο κριτής), και τα δύο ξαναγράφτηκαν
 * στη Φ2. Ένα `export { … as MandateLockMode }` θα ήταν **δεύτερο όνομα για ένα
 * πράγμα** — ακριβώς το σχήμα που το έργο μετράει ως ελάττωμα (N.12, ADR-749).
 *
 * 🔑 **Ό,τι ΔΕΝ μετακόμισε, δεν είναι τυχαίο**: το `LISTING_AGREEMENT_LOCK_MODES` και
 * το `lockModeFor` **μένουν** στο λεξιλόγιο της εντολής. Είναι η **αντιστοίχιση ενός
 * τομέα** στον τρόπο (*«η αποκλειστική πώλησης κλειδώνει»*) — γνώση που ο γενικός
 * κριτής δεν έχει και δεν πρέπει να αποκτήσει. Εδώ ζει **μόνο** το κλειστό σύνολο και
 * η **σχέση** ανάμεσα σε δύο τιμές του.
 *
 * **Layering**: leaf — μηδέν imports, μηδέν I/O.
 */

/**
 * **Με ποιον τρόπο καταλαμβάνει μια κατάληψη τον πόρο της.**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΓΙΑΤΙ ΛΕΞΙΛΟΓΙΟ ΚΛΕΙΔΩΜΑΤΟΣ ΚΑΙ ΟΧΙ `boolean` — ΤΟ ΠΡΟΤΥΠΟ ΕΙΝΑΙ 50 ΕΤΩΝ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το ερώτημα *«χωράνε δύο μαζί;»* **δεν είναι** ιδιότητα της μίας — είναι **σχέση**
 * ανάμεσα σε δύο. Ένα `allowsOthers(x): boolean` το ρωτά λάθος: δίνει απάντηση
 * κοιτάζοντας **μόνο τη μία**, οπότε ο καλών πρέπει να θυμηθεί να ρωτήσει **και για
 * την άλλη** — και κάποια στιγμή δεν θα θυμηθεί.
 *
 * 🔑 Είναι **ακριβώς** ο πίνακας συμβατότητας shared/exclusive των βάσεων δεδομένων
 * (readers-writer lock), και το ίδιο σχήμα με το `EXCLUDE USING GIST (πόρος WITH =,
 * διάστημα WITH &&)` της PostgreSQL: **τομή** στον πόρο, **επικάλυψη** στον χρόνο,
 * **ασυμβατότητα** στον τρόπο. Τα τρία μαζί κάνουν σύγκρουση· κανένα μόνο του.
 *
 * ⚠️ **ΔΕΝ είναι κλείδωμα βάσης δεδομένων** — δεν σειριοποιεί συναλλαγές και δεν
 * απελευθερώνεται. Είναι ο **ίδιος πίνακας αποφάσεων** εφαρμοσμένος σε δικαίωμα που
 * διαρκεί μήνες (εντολή) ή νύχτες (κράτηση). Ο δανεισμός είναι του **σχήματος**.
 */
export const OCCUPANCY_MODES = ['shared', 'exclusive'] as const;

export type OccupancyMode = (typeof OCCUPANCY_MODES)[number];

/**
 * **Χωράνε αυτοί οι δύο τρόποι στον ΙΔΙΟ πόρο, ταυτόχρονα;**
 *
 * | | `shared` | `exclusive` |
 * |---|---|---|
 * | **`shared`** | ✅ | ❌ |
 * | **`exclusive`** | ❌ | ❌ |
 *
 * 🔴 **Ο πίνακας δεν είναι συμμετρικός κατά τύχη — είναι συμμετρικός κατά κατασκευή.**
 * Η ερώτηση *«μπορεί να μπει η Β όσο υπάρχει η Α;»* πρέπει να έχει **την ίδια**
 * απάντηση με το αντίστροφο· αλλιώς η σειρά υποβολής θα καθόριζε το δικαίωμα, και δύο
 * άνθρωποι με ίδια συμφωνία θα έπαιρναν διαφορετική απάντηση ανάλογα με το ποιος
 * πάτησε πρώτος. Η άγκυρα το **εκτελεί** και στις δύο κατευθύνσεις.
 *
 * 🔑 **Οι κρατήσεις ζουν ολόκληρες στο κάτω δεξιά κελί** (`exclusive`×`exclusive`) —
 * και γι' αυτό ακριβώς ο πίνακας **δεν** χρειάστηκε αλλαγή για να τις δεχτεί.
 */
export function modesCompatible(a: OccupancyMode, b: OccupancyMode): boolean {
  return a === 'shared' && b === 'shared';
}
