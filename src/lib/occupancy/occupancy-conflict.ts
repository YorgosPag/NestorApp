/**
 * **Ποιος από τους δύο αποκλείει.**
 *
 * 🏆 **ΕΔΩ ΞΕΠΕΡΝΑΜΕ ΤΑ MLS, ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΡΗΤΟΡΙΚΟ.** Το πρότυπο NAR λύνει το ίδιο
 * πρόβλημα με **δήλωση του μεσίτη** και **αφαίρεση εκ των υστέρων**· ο άνθρωπος που
 * απορρίπτεται βλέπει *«Invalid»* και **δεν μαθαίνει ποτέ τι μπορεί να κάνει**.
 *
 * Οι δύο λόγοι έχουν **διαφορετική θεραπεία**, και γι' αυτό είναι δύο:
 *
 * | Λόγος | Τι σημαίνει | Τι **μπορεί** ο άνθρωπος |
 * |---|---|---|
 * | {@link EXISTING_IS_EXCLUSIVE} | κάποιος **ήδη** κρατά αποκλειστικά | τίποτα ως τη λήξη — αλλά μπορεί να **προγραμματίσει** για μετά |
 * | {@link CANDIDATE_IS_EXCLUSIVE} | ζητά **αποκλειστικά** ενώ υπάρχουν κοινόχρηστες | να ζητήσει **απλή**, ή να αποσύρει τις υπάρχουσες |
 *
 * ⚠️ Ένας κοινός κωδικός θα έλεγε *«δεν γίνεται»* και στις δύο — δηλαδή θα έκρυβε
 * **δύο ανοιχτούς δρόμους**.
 *
 * 🔑 **Στις κρατήσεις παράγεται πάντα ο πρώτος**, επειδή και οι δύο πλευρές είναι
 * `exclusive`. Αυτό **δεν** κάνει τον δεύτερο νεκρό: τον παράγουν οι εντολές, και τον
 * φυλάει εκτελούμενη άγκυρα.
 */
export const EXISTING_IS_EXCLUSIVE = 'existing-is-exclusive';

/** Δες {@link EXISTING_IS_EXCLUSIVE} για το γιατί είναι δύο και όχι ένας. */
export const CANDIDATE_IS_EXCLUSIVE = 'candidate-is-exclusive';

export const OCCUPANCY_CONFLICT_REASONS = [
  EXISTING_IS_EXCLUSIVE,
  CANDIDATE_IS_EXCLUSIVE,
] as const;

export type OccupancyConflictReason = (typeof OCCUPANCY_CONFLICT_REASONS)[number];

/** **Μία συγκεκριμένη σύγκρουση** — με ποιον, σε ποιον χώρο, σε ποια πράξη, γιατί. */
export interface OccupancyConflict<TSource> {
  /** Η κατάληψη που εμποδίζει. Φέρνει μαζί της **λήξη** ⇒ η οθόνη λέει «ως πότε». */
  readonly with: Occupancy<TSource>;
  /**
   * **Ο αμφισβητούμενος πόρος** — ο **στενότερος** των δύο (δες `contestedResource`).
   *
   * Δύο πόροι ⇒ δύο εγγραφές, ποτέ μία «γενική»: ο άνθρωπος που εμποδίζεται στο
   * **δωμάτιο Α** αλλά όχι στο **Β** πρέπει να το μάθει.
   */
  readonly resource: OccupancyResource;
  readonly reason: OccupancyConflictReason;
}

/**
 * **Η ετυμηγορία** — κλειστό σύνολο, ποτέ `boolean`.
 *
 * 🔴 **Το `undetermined` ΔΕΝ είναι «καθαρό» και ΔΕΝ είναι «σύγκρουση»** (N.12: *άγνωστο
 * ≠ κενό*). Προκύπτει από **βλάβη δεδομένου** — ημερομηνία που δεν διαβάζεται,
 * διάστημα ανάποδο. Ένα `clear` εκεί θα **επέτρεπε** δεύτερη αποκλειστική επειδή δεν
 * μπορέσαμε να διαβάσουμε την πρώτη· ένα `conflicts` θα απέρριπτε νόμιμη συμφωνία
 * κατηγορώντας αθώο. Ο καλών **πρέπει** να αποφασίσει τι σημαίνει.
 *
 * ⚠️ Στις κρατήσεις η απόφαση είναι ήδη γραμμένη (ADR-835 §6.4): *«αν το ημερολόγιο
 * δεν διαβάστηκε, η απάντηση είναι `undetermined`, όχι ελεύθερο — γιατί ένα ελεύθερο
 * εκεί **είναι** το overbooking»*.
 */
export type OccupancyVerdict<TSource> =
  | { readonly kind: 'clear' }
  | {
      readonly kind: 'conflicts';
      readonly conflicts: readonly OccupancyConflict<TSource>[];
    }
  | {
      readonly kind: 'undetermined';
      readonly unreadable: readonly Occupancy<TSource>[];
    };

