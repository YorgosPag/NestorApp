// =============================================================================

/**
 * **Ποιος από τους δύο αποκλείει;** — καλείται **μόνο** όταν είναι ασύμβατοι.
 *
 * ⚠️ Η σειρά δεν είναι αυθαίρετη: η **υπάρχουσα** αποκλειστική προηγείται, γιατί
 * είναι το εμπόδιο που ο άνθρωπος **δεν μπορεί** να παρακάμψει. Όταν αποκλείουν και
 * οι δύο, το χρήσιμο μήνυμα είναι *«κάποιος ήδη κρατά»*, όχι *«ζητάς πολλά»*.
 */
function reasonFor(existingMode: OccupancyMode): OccupancyConflictReason {
  return existingMode === 'exclusive' ? EXISTING_IS_EXCLUSIVE : CANDIDATE_IS_EXCLUSIVE;
}

/**
 * **Μπορεί αυτή η κατάληψη να σταθεί δίπλα σε εκείνες;**
 *
 * @param candidate — η κατάληψη που ζητείται.
 * @param existing — οι καταλήψεις που **ισχύουν** στον ίδιο χώρο ταυτοτήτων. Το
 *   φιλτράρισμα (ληγμένες · ανακληθείσες · αιτήματα που δεν καταλαμβάνουν) ανήκει
 *   στον καλούντα — δες την κεφαλίδα.
 * @param policy — η **δηλωμένη** συμπεριφορά του είδους. Δες {@link SameHolderPolicy}.
 *
 * ⚠️ **ΟΛΕΣ οι συγκρούσεις, ποτέ η πρώτη.** Ο άνθρωπος που εμποδίζεται από τρεις
 * πρέπει να τους δει **και τους τρεις**· αλλιώς λύνει τον έναν, ξαναπροσπαθεί, και
 * συναντά τον επόμενο.
 */
export function occupancyConflicts<TSource>(
  candidate: Occupancy<TSource>,
  existing: readonly Occupancy<TSource>[],
  policy: OccupancyPolicy,
): OccupancyVerdict<TSource> {
  const conflicts: OccupancyConflict<TSource>[] = [];
  const unreadable: Occupancy<TSource>[] = [];

  for (const other of existing) {
    // 🔴 **Η ΙΔΙΑ ΕΓΓΡΑΦΗ ΔΕΝ ΣΥΓΚΡΟΥΕΤΑΙ ΜΕ ΤΟΝ ΕΑΥΤΟ ΤΗΣ.** Ταυτότητα, ΟΧΙ
    //    κάτοχος: δύο άγνωστες ταυτότητες (`null`) δεν είναι «η ίδια» (N.12).
    if (candidate.occupancyId !== null && candidate.occupancyId === other.occupancyId) {
      continue;
    }

    // 🔑 **Ο ΙΔΙΟΣ ΚΑΤΟΧΟΣ** — δηλωμένη πολιτική, ποτέ σιωπηλός κανόνας.
    //    `replaces` = ανανέωση όρων (εντολή) · `conflicts` = δύο διαμονές (κράτηση).
    if (policy.sameHolder === 'replaces' && other.holderId === candidate.holderId) {
      continue;
    }

    const shared = sharedResources(candidate.resources, other.resources);
    if (shared.length === 0) continue;

    const overlaps = intervalsOverlap(
      candidate.startsAt,
      candidate.expiresAt,
      other.startsAt,
      other.expiresAt,
    );

    // 🔴 «Δεν μπόρεσα να κρίνω» — συλλέγεται, **δεν** σιωπά. Δες τον τύπο.
    if (overlaps === null) {
      unreadable.push(other);
      continue;
    }
    if (!overlaps) continue;

    if (modesCompatible(candidate.mode, other.mode)) continue;

    // ⚠️ **Μία εγγραφή ανά αμφισβητούμενο πόρο**, όχι μία «γενική» ανά κάτοχο.
    for (const resource of shared) {
      conflicts.push({ with: other, resource, reason: reasonFor(other.mode) });
    }
  }

  // 🔴 **Η ΒΛΑΒΗ ΝΙΚΑ ΤΟ «ΚΑΘΑΡΟ», ΑΛΛΑ ΟΧΙ ΤΗ ΣΥΓΚΡΟΥΣΗ.** Αν βρέθηκε έστω μία
  //    πραγματική σύγκρουση, η απάντηση είναι **όχι** — και είναι απόδειξη, όχι
  //    εικασία· ό,τι κι αν έκρυβε το χαλασμένο έγγραφο δεν την ανατρέπει. Αν όμως
  //    **δεν** βρέθηκε καμία, δεν επιτρέπεται να πούμε «καθαρό» ενώ κάτι δεν
  //    διαβάστηκε: εκεί ακριβώς περνά η δεύτερη αποκλειστική — και η διπλοκράτηση.
  if (conflicts.length > 0) return { kind: 'conflicts', conflicts };
  if (unreadable.length > 0) return { kind: 'undetermined', unreadable };
  return { kind: 'clear' };
}
