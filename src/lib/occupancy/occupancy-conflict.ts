/**
 * **Ο ίδιος κάτοχος, δύο φορές: αντικαθιστά ή συγκρούεται;**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΗΤΑΝ ΣΙΩΠΗΛΟΣ ΚΑΝΟΝΑΣ ΜΕΣΑ ΣΤΟΝ ΒΡΟΧΟ, ΚΑΙ ΓΙ' ΑΥΤΟ ΗΤΑΝ ΕΠΙΚΙΝΔΥΝΟΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο κριτής των εντολών είχε γραμμένο:
 *
 * ```ts
 * if (other.agencyCompanyId === candidate.agencyCompanyId) continue;
 * ```
 *
 * **Σωστό για εντολές**: νέοι όροι προς γραφείο που ήδη κρατά εντολή είναι
 * **ανανέωση**, όχι δεύτερη κατάληψη — χωρίς αυτό, κάθε ανανέωση αποκλειστικής θα
 * μπλόκαρε στην **ίδια της την προηγούμενη**.
 *
 * 🔴 **Ψευδές για κρατήσεις**: ο ίδιος επισκέπτης με δύο επικαλυπτόμενες διαμονές
 * **συγκρούεται** — δεν «αντικαθιστά». Μια κράτηση είναι **γεγονός**, όχι σχέση: ο
 * ίδιος άνθρωπος μπορεί να έχει δέκα, αρκεί να μην πέφτουν η μία πάνω στην άλλη.
 *
 * ⚠️ **Γι' αυτό είναι ΔΗΛΩΜΕΝΗ παράμετρος και όχι `if` με σχόλιο**: ένας κανόνας που
 * ζει μέσα στον βρόχο δεν μπορεί να **διαφωνήσει** ανά τομέα, άρα ο δεύτερος
 * καταναλωτής τον κληρονομεί **αθόρυβα**. Η σιωπηλή κληρονομιά εδώ λέγεται
 * **διπλοκράτηση**.
 */
export const SAME_HOLDER_POLICIES = ['replaces', 'conflicts'] as const;

export type SameHolderPolicy = (typeof SAME_HOLDER_POLICIES)[number];

/**
 * **Η δηλωμένη συμπεριφορά ενός είδους κατάληψης.**
 *
 * ⚠️ **Ανά ΚΛΗΣΗ, όχι ανά κατάληψη — και είναι απόφαση.** Μια κλήση κρίνει καταλήψεις
 * **ενός** είδους (εντολές με εντολές, κρατήσεις με κρατήσεις): εκεί η πολιτική είναι
 * ιδιότητα του **ερωτήματος**. Πολιτική καρφωμένη σε κάθε αντικείμενο θα επέτρεπε
 * ανάμεικτο σύνολο όπου *«ο ίδιος κάτοχος»* θα σήμαινε **δύο πράγματα ταυτόχρονα** —
 * και ο κριτής θα έπρεπε να διαλέξει, δηλαδή να ξέρει τι κρίνει (δες την κεφαλίδα).
 *
 * 🔑 Το ερώτημα *«τι γίνεται αν μια κράτηση συναντήσει μια εντολή;»* είναι **άλλο
 * ερώτημα** (ADR-835 §4.7 — συνύπαρξη πώλησης και κρατήσεων: **ποτέ φράχτης, πάντα
 * όνομα**) και **δεν** λύνεται σιωπηλά εδώ.
 */
export interface OccupancyPolicy {
  readonly sameHolder: SameHolderPolicy;
}

// =============================================================================
// 2. ΤΙ ΚΑΤΑΛΑΜΒΑΝΕΙ ΤΙ
// =============================================================================

/**
 * **Μια κατάληψη**: ποιος κρατά ποιους χώρους, σε ποιες πράξεις, από πότε ως πότε.
 *
 * @typeParam TSource — το **δικό σου** αντικείμενο (εντολή · κράτηση · blackout). Ο
 *   κριτής δεν το διαβάζει **ποτέ**· σου το επιστρέφει αυτούσιο μέσα στη σύγκρουση.
 */
export interface Occupancy<TSource> {
  /**
   * Η ταυτότητα **αυτής της εγγραφής**, όταν έχει. `null` = δεν έχει.
   *
   * 🔴 **ΔΕΝ είναι ο κάτοχος, και η διάκριση είναι ολόκληρο το μάθημα της Φ2.** Με
   * `sameHolder: 'conflicts'`, μια εγγραφή που βρίσκεται και στο `existing` θα
   * συγκρουόταν **με τον εαυτό της** — η κράτηση που ξαναϋπολογίζεται (αλλαγή
   * ημερομηνιών, επανεπιβεβαίωση) θα απορριπτόταν επειδή **υπάρχει**.
   *
   * ⚠️ Ο έλεγχος γίνεται **μόνο** όταν και οι δύο πλευρές έχουν ταυτότητα: δύο `null`
   * σημαίνουν *«δεν ξέρω ποιες είναι»*, όχι *«είναι η ίδια»* (N.12).
   *
   * 🔑 Οι **εντολές** δεν έχουν ταυτότητα, και είναι σκόπιμο: είναι **πεδίο** μέσα
   * στο έγγραφο του ακινήτου — *«αλλάζει χέρια, όχι ταυτότητα»* (ADR-827 Α3). Εκεί
   * τον ρόλο τον παίζει η πολιτική `'replaces'`.
   */
  readonly occupancyId: string | null;
  /** Ποιος κρατά. **Ταυτότητα, ποτέ όνομα** — η οθόνη το λύνει. */
  readonly holderId: string;
  /** Με ποιον τρόπο κρατά. Οι κρατήσεις είναι **πάντα** `exclusive`. */
  readonly mode: OccupancyMode;
  /**
   * **Ποιους χώρους, σε ποιες πράξεις.**
   *
   * ⚠️ **Κενό σύνολο δεν καταλαμβάνει τίποτα**, και είναι έγκυρη κατάσταση: κατάληψη
   * που δεν λέει τι πιάνει δεν εμποδίζει καμία. Δεν είναι σφάλμα **εδώ** — είναι
   * invariant του μοντέλου, και κρίνεται εκεί.
   */
  readonly resources: readonly OccupancyResource[];
  /** ISO — πότε **αρχίζει** να ισχύει. */
  readonly startsAt: string;
  /** ISO — πότε **παύει**. `null` = ανοιχτή διάρκεια. */
  readonly expiresAt: string | null;
  /** Η **πηγή**. Αδιαφανής: ο κριτής δεν έχει τρόπο να τη ρωτήσει. */
  readonly source: TSource;
}

