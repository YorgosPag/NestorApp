/**
 * @fileoverview **ΣΥΓΚΡΟΥΟΝΤΑΙ ΑΥΤΕΣ ΟΙ ΔΥΟ ΚΑΤΑΛΗΨΕΙΣ;** — ο **ΕΝΑΣ** κριτής.
 * @related lib/occupancy/occupancy-resource.ts · lib/occupancy/occupancy-mode.ts ·
 *   lib/date-local.ts · lib/mandate/mandate-conflict.ts · lib/stay/stay-conflict.ts
 * @module lib/occupancy/occupancy-conflict
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΤΟ ΣΧΗΜΑ — ΤΡΙΑ ΣΚΕΛΗ, ΚΑΝΕΝΑ ΑΡΚΕΤΟ ΜΟΝΟ ΤΟΥ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * ```
 * σύγκρουση(Α,Β) = τέμνονται οι πόροι(Α,Β) ∧ επικάλυψη χρόνου(Α,Β) ∧ ¬συμβατοί τρόποι(Α,Β)
 * ```
 *
 * Είναι κατά λέξη το `EXCLUDE USING GIST (πόρος WITH &&, διάστημα WITH &&)` της
 * PostgreSQL — ο κανονικός τρόπος να εκφραστεί *«δύο συμβάσεις δεν επικαλύπτονται»* —
 * με **τρίτο** σκέλος τον πίνακα συμβατότητας shared/exclusive, που η PostgreSQL δεν
 * χρειάζεται επειδή τα κλειδώματά της είναι πάντα αποκλειστικά. Εμάς μας χρειάζεται:
 * η **απλή** εντολή υπάρχει ακριβώς για να μοιράζεται.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΜΕΤΑΚΟΜΙΣΕ ΕΔΩ (ADR-835 Φ2) — Ο ΔΕΥΤΕΡΟΣ ΚΑΤΑΝΑΛΩΤΗΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * ```
 * lib/mandate/mandate-conflict.ts  →  lib/occupancy/occupancy-conflict.ts
 *                                      ├── καταναλωτής 1: εντολές μεσίτη (ADR-832)
 *                                      └── καταναλωτής 2: κρατήσεις      (ADR-835)
 * ```
 *
 * **Δεν ήταν μετονομασία.** Η γενίκευση απαίτησε **δύο** αλλαγές ταυτόχρονα, και η
 * καθεμιά ήταν, σιωπηλά, **λάθος δεδομένα στην πόρτα ενός σπιτιού**:
 *
 * | # | Τι ήταν σιωπηλός κανόνας | Τι έγινε | Τι θα γινόταν χωρίς αυτό |
 * |---|---|---|---|
 * | Α | *«ίδιος κάτοχος ⇒ αντικατάσταση»*, γραμμένο **μέσα στον βρόχο** | {@link SameHolderPolicy}, **δηλωμένη** ιδιότητα | ο ίδιος επισκέπτης κρατά **δύο φορές** τις ίδιες μέρες |
 * | Β | πόρος με **ισότητα** | **τομή συνόλων** (χώρος × πράξη) | κράτηση **ολόκληρου** + κράτηση **δωματίου** ⇒ `clear` |
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 Ο ΚΡΙΤΗΣ ΔΕΝ ΞΕΡΕΙ ΤΙ ΚΡΙΝΕΙ — ΚΑΙ ΤΟ ΕΓΓΥΑΤΑΙ Ο ΤΥΠΟΣ, ΟΧΙ ΤΟ ΣΧΟΛΙΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η πηγή κάθε κατάληψης ταξιδεύει ως **αδιαφανής παράμετρος τύπου** `TSource`
 * ({@link Occupancy.source}). Ο κριτής **δεν μπορεί** να τη διαβάσει — δεν έχει κανένα
 * μέλος να ρωτήσει. Άρα η πρόταση *«δεν ξέρει τι είναι blackout, τι κράτηση, τι
 * εντολή»* δεν είναι ισχυρισμός σε σχόλιο: είναι **ιδιότητα της υπογραφής**.
 *
 * Ο **καλών** μεταφράζει το μοντέλο του σε `Occupancy` **πριν** φτάσει εδώ, και
 * παίρνει πίσω το δικό του αντικείμενο από το `conflict.with.source`. Ίδιο ιδίωμα με
 * το `SalesDisplayEligibilityInput` (*«agnostic σε data shape»*): ολόκληρος ο πίνακας
 * αποφάσεων ελέγχεται **χωρίς Firestore**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⛔ ΤΙ ΔΕΝ ΕΙΝΑΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * ⛔ **Δεν είναι η θεματοφυλακή** (`lib/owner-property/listing-custody.ts`). Εκείνη
 * απαντά *«ποιος **διαχειρίζεται** την αγγελία»* — εξουσιοδότηση, ερώτημα χώρου. Αυτό
 * απαντά *«ποιος κρατά **ποιον χώρο**, σε **ποια πράξη**, για **πόσο**»*.
 *
 * ⛔ **Δεν κρίνει διάρκεια.** Το νόμιμο ανώτατο της εντολής είναι το
 * `exceedsStatutoryTerm`· το όριο των **59 ημερών** της βραχυχρόνιας (Ν.5073/2023)
 * μπαίνει **στο όνομα της διάθεσης**, ποτέ στην πράξη (ADR-835 §4.9). Δεύτερο όριο
 * εδώ θα ήταν ADR-749.
 *
 * ⛔ **Δεν ξέρει ποια κατάληψη «μετράει».** Ληγμένες εντολές, ανακληθείσες,
 * **αιτήματα κράτησης που δεν καταλαμβάνουν** (`requested` — ADR-835 §6.1): τα
 * φιλτράρει ο **καλών**, που κατέχει το σχήμα. Εδώ φτάνουν **μόνο** καταλήψεις που
 * ισχύουν.
 *
 * ⛔ **Δεν κρατά ρολόι.** Παίρνει δεδομένα, δίνει ετυμηγορία — γι' αυτό τα άκρα
 * (ίδια στιγμή λήξης/έναρξης, ανάποδο διάστημα, κενό σύνολο πόρων) είναι δοκιμάσιμα
 * χωρίς να ταξιδέψει κανείς στον χρόνο.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις, μηδέν I/O, μηδέν ρολόι.
 */

