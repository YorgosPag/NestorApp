/** Οι κωδικοί HTTP που μπορεί να σημαίνει μια άρνηση — κανένας 5xx: βλάβη δεν είναι ποτέ άρνηση. */
export type DomainRefusalStatus = 400 | 403 | 404 | 409 | 422;

/** Βάση κάθε αποφασισμένης άρνησης του τομέα. Η υποκλάση δηλώνει τι **σημαίνει**, όχι πώς καταγράφεται. */
export abstract class DomainRefusal extends Error {
  /** Ο κωδικός HTTP που αντιστοιχεί στην άρνηση (πληροφοριακός — ο δρομολογητής αποφασίζει την απάντηση). */
  abstract readonly httpStatus: DomainRefusalStatus;
}

/** Είναι αυτό το σφάλμα αποφασισμένη άρνηση (όχι βλάβη); */
export function isDomainRefusal(error: unknown): error is DomainRefusal {
  return error instanceof DomainRefusal;
}
