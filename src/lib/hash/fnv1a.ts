/** Το `offset basis` του FNV-1a 32 bit (2166136261). */
const FNV_OFFSET_BASIS_32 = 0x811c9dc5;

/** Το `prime` του FNV-1a 32 bit (16777619). */
const FNV_PRIME_32 = 0x01000193;

/**
 * **FNV-1a 32 bit** πάνω στις μονάδες κώδικα UTF-16 της συμβολοσειράς.
 *
 * @returns Ακέραιος **χωρίς πρόσημο**, `0 … 2³²-1`.
 *
 * ⚠️ **Το `>>> 0` δεν είναι καλλωπισμός** — χωρίς αυτό ο `Math.imul` επιστρέφει
 * **προσημασμένο** 32-bit, οπότε ένα `hash % n` θα έδινε **αρνητικό** ευρετήριο για
 * τις μισές εισόδους. Ο καλών θα διάβαζε `undefined` από τον πίνακά του.
 *
 * 🔑 **Διαβάζει `charCodeAt`, όχι σημεία κώδικα**: ένα emoji ή ένα σπάνιο ιδεόγραμμα
 * μετρά ως **δύο** μονάδες. Για διαλογή κουβά αυτό είναι **αδιάφορο** (η κατανομή
 * μένει)· η συνάρτηση **δεν** υπόσχεται τίποτα για την Unicode σημασία της εισόδου.
 */
export function fnv1a32(material: string): number {
  let hash = FNV_OFFSET_BASIS_32;
  for (let index = 0; index < material.length; index += 1) {
    hash ^= material.charCodeAt(index);
    hash = Math.imul(hash, FNV_PRIME_32) >>> 0;
  }
  return hash;
}
