/**
 * **ΟΙ ΑΓΚΥΡΕΣ ΤΟΥ FNV-1a** — ADR-841 §7 Α21.1 (β).
 *
 * 🔴 **Τι φυλάνε**: ότι η **εξαγωγή** από το `agency-directory-order.ts` ήταν **αθώα**
 * (ίδιο αποτέλεσμα bit-προς-bit) και ότι η συνάρτηση είναι **όντως** FNV-1a — όχι
 * «κάτι που μοιάζει». Ένας hash χωρίς πρότυπα διανύσματα είναι αριθμός που κανείς δεν
 * μπορεί να επαληθεύσει.
 */

import { fnv1a32 } from '../fnv1a';

describe('Α21.1 — είναι ΟΝΤΩΣ FNV-1a 32 bit (πρότυπα διανύσματα)', () => {
  it.each([
    ['', 2166136261], // το offset basis, 0x811c9dc5 — η κενή είσοδος δεν το αλλάζει
    ['a', 3826002220], // 0xe40c292c
    ['foobar', 3214735720], // 0xbf9cf968
  ])('fnv1a32(%p) === %p', (input, expected) => {
    expect(fnv1a32(input)).toBe(expected);
  });
});

describe('Α21.1 — το `>>> 0` ΔΕΝ είναι καλλωπισμός', () => {
  it('🔴 καμία έξοδος δεν είναι αρνητική — αλλιώς το `% n` δίνει ΑΡΝΗΤΙΚΟ ευρετήριο', () => {
    // Χωρίς το `>>> 0` ο `Math.imul` επιστρέφει προσημασμένο 32-bit, οπότε ο καλών
    // θα διάβαζε `undefined` από τον πίνακά του για τις μισές εισόδους.
    for (let index = 0; index < 5_000; index += 1) {
      expect(fnv1a32(`comp_${index}`)).toBeGreaterThanOrEqual(0);
    }
  });

  it('μένει μέσα στα 32 bit', () => {
    for (let index = 0; index < 1_000; index += 1) {
      expect(fnv1a32(`x${index}`)).toBeLessThan(2 ** 32);
    }
  });
});

describe('Α21.1 — ντετερμινιστικό, χωρίς ρολόι και χωρίς κατάσταση', () => {
  it('ίδια είσοδος ⇒ ίδια έξοδος, όσες φορές κι αν κληθεί', () => {
    const material = 'σπόρος:comp_9c7c1a50';
    const first = fnv1a32(material);
    expect(fnv1a32(material)).toBe(first);
    expect(fnv1a32(material)).toBe(first);
  });

  it('δεν κρατά κατάσταση ανάμεσα σε κλήσεις', () => {
    const a = fnv1a32('α');
    fnv1a32('παρεμβολή');
    expect(fnv1a32('α')).toBe(a);
  });
});

describe('Α21.1 — η κατανομή δεν ευνοεί συστηματικά', () => {
  it('🔑 8 κουβάδες, 4.000 ταυτότητες: κανένας κουβάς δεν μένει κενός', () => {
    // Δεν είναι έλεγχος κρυπτογραφίας — είναι ο ΛΟΓΟΣ ΥΠΑΡΞΗΣ και των δύο
    // καταναλωτών: ο κλήρος δεν πρέπει να ευνοεί γραφείο, το σήμα δεν πρέπει να
    // δίνει σε όλους το ίδιο χρώμα.
    const buckets = new Array<number>(8).fill(0);
    for (let index = 0; index < 4_000; index += 1) {
      buckets[fnv1a32(`comp_${index}`) % 8] += 1;
    }
    expect(buckets.every((count) => count > 0)).toBe(true);
    // Χαλαρό όριο επίτηδες: φυλάει από «όλα σε έναν κουβά», όχι από στατιστικό θόρυβο.
    expect(Math.max(...buckets)).toBeLessThan(4_000 / 2);
  });
});
