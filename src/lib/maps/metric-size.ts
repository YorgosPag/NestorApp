/**
 * @fileoverview SSoT — **πόσα pixel οθόνης είναι N μέτρα του κόσμου**, σε γλώσσα MapLibre.
 * @related ADR-777 §8.64 · lib/listings/listing-map-shape.ts · lib/geo/geo-distance.ts
 * @module lib/maps/metric-size
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ — Ο ΖΩΓΡΑΦΟΣ ΜΙΛΟΥΣΕ ΑΛΛΗ ΓΛΩΣΣΑ ΑΠΟ ΤΟΝ ΚΡΙΤΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `LISTING_UNCERTAINTY_KM` αποφασίζει σε **μέτρα του κόσμου** ποια αγγελία είναι
 * «μέσα», «ίσως» ή «έξω». Ο χάρτης ζωγράφιζε την **ίδια** αβεβαιότητα σε **pixel
 * σταθερά** (`34` για τη συνοικία, `90` για την πόλη) — δηλαδή ο ίδιος ισχυρισμός
 * κάλυπτε δεκάδες χιλιόμετρα στο ζουμ 10 και λίγα μέτρα στο ζουμ 18.
 *
 * ⚠️ **Δεν είναι αισθητικό ζήτημα.** Η αβεβαιότητα που ζωγραφίζεται είναι η
 * αβεβαιότητα που **διαβάζει ο άνθρωπος**, και η βιβλιογραφία οπτικοποίησης
 * *(Deitrick & Edsall, 2006)* μετρά ότι ο τρόπος έκφρασής της **αλλάζει την
 * απόφαση**. Ένας κύκλος που λέει «κάπου εδώ γύρω» και μεγαλώνει όταν ζουμάρεις
 * **έξω** λέει το αντίθετο από την αλήθεια.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΠΟΥ ΞΕΠΕΡΝΑΜΕ ΤΗΝ ΠΡΑΚΤΙΚΗ ΤΩΝ ΜΕΓΑΛΩΝ — Η ΔΙΟΡΘΩΣΗ MERCATOR
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η συνιστώμενη λύση της κοινότητας MapLibre *(style-spec discussion #1373)* είναι
 * `['interpolate', ['exponential', 2], ['zoom'], …]` — και **σταματά εκεί**. Ο ίδιος
 * ο συντηρητής γράφει ότι η παραμόρφωση Mercator *«από πλευράς style δεν είναι αυτή
 * τη στιγμή δυνατή»*, γιατί το `['global-state', …]` κρατά **μία** τιμή για **όλα**
 * τα σχήματα της οθόνης.
 *
 * 🔑 **Αυτό ισχύει για κατάσταση της ΟΘΟΝΗΣ. Δεν ισχύει για ιδιότητα του FEATURE.**
 * Ο συντελεστής `1/cos(φ)` δεν είναι κατάσταση — είναι **ιδιότητα του σημείου**, και
 * το σημείο τη γνωρίζει τη στιγμή που γεννιέται το GeoJSON. Άρα υπολογίζεται **ανά
 * αγγελία** και διαβάζεται με `['get', …]`, οπότε **κάθε** σχήμα της οθόνης παίρνει
 * τον **δικό του** σωστό συντελεστή ταυτόχρονα — ακριβώς αυτό που δηλώθηκε αδύνατο.
 *
 * 🔴 **Και το σφάλμα δεν είναι θεωρητικό**: στο ελληνικό γεωγραφικό πλάτος (~38°) ο
 * συντελεστής είναι **1,269**, δηλαδή χωρίς αυτόν κάθε κύκλος αβεβαιότητας θα
 * ζωγραφιζόταν **21% μικρότερος από την αλήθεια** — υπόσχεση ακρίβειας που δεν έχουμε
 * (Α5). Στη Θεσσαλονίκη (40,6°) η υποτίμηση φτάνει το **24%**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΓΙΑΤΙ **ΔΕΝ** ΕΙΣΑΓΕΤΑΙ ΤΟ `EARTH_RADIUS_METERS`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `lib/geo/geo-distance.ts` δηλώνει `6 371 008,8` — τη **μέση σφαιρική** ακτίνα
 * WGS-84, που είναι η σωστή για **haversine**. Το Web Mercator **δεν** είναι σφαίρα
 * μέσης ακτίνας: η προβολή ορίζεται (EPSG:3857) πάνω στον **ισημερινό ημιάξονα**
 * `6 378 137`. Η διαφορά είναι **0,11%** — αμελητέα οπτικά, αλλά η εισαγωγή θα ήταν
 * **λάθος ταυτότητας**, όχι εξοικονόμηση: δύο διαφορετικές ερωτήσεις που τυχαίνει να
 * έχουν παρόμοια απάντηση.
 *
 * 🔑 Ίδιο σκεπτικό με το `LISTING_UNCERTAINTY_KM['shaded-city'] = 10`, που αρνείται
 * ρητά να εισαγάγει το ισάριθμο `DEFAULT_SEARCH_RADIUS_KM`: **κοινή σταθερά κλειδώνει
 * μαζί για πάντα δύο έννοιες που σήμερα συμπίπτουν**.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις, μόνο τύποι από το σύνορο του χάρτη.
 */

import type { CircleLayerSpecification } from './maplibre';

/** Ο τύπος που δέχεται πραγματικά το `circle-radius`, **παραγόμενος από τη βιβλιοθήκη**. */
export type CircleRadiusValue = NonNullable<CircleLayerSpecification['paint']>['circle-radius'];

/**
 * Ο **ισημερινός** ημιάξονας WGS-84, σε μέτρα — η σταθερά που ορίζει το EPSG:3857.
 *
 * ⚠️ **ΔΕΝ είναι το `EARTH_RADIUS_METERS`** του `geo-distance.ts` (μέση σφαιρική,
 * `6 371 008,8`). Δες την κεφαλίδα: διαφορετική ερώτηση, διαφορετική σταθερά.
 */
export const WEB_MERCATOR_EQUATORIAL_RADIUS_M = 6_378_137;

/**
 * Πλάκα (tile) του MapLibre σε pixel — **512**, όχι 256.
 *
 * ⚠️ **Ο αριθμός ορίζει τη ΣΗΜΑΣΙΑ του ζουμ, δεν είναι λεπτομέρεια δικτύου.** Ο παλιός
 * κόσμος των 256px δίνει ανάλυση εδάφους **διπλάσια** στο ίδιο ζουμ· γραμμένο λάθος
 * εδώ, κάθε κύκλος βγαίνει **στο μισό** και τίποτα δεν το φωνάζει.
 */
export const MAPLIBRE_TILE_SIZE_PX = 512;

/** Μέτρα ανά pixel στο ζουμ 0, **επί του ισημερινού** (≈ 78 271,5). */
export const METERS_PER_PIXEL_AT_ZOOM_0 =
  (2 * Math.PI * WEB_MERCATOR_EQUATORIAL_RADIUS_M) / MAPLIBRE_TILE_SIZE_PX;

/**
 * Το γεωγραφικό πλάτος όπου **τελειώνει** η προβολή Web Mercator (≈ 85,051129°).
 *
 * Πέρα από εκεί το `cos(φ)` τείνει στο μηδέν και ο συντελεστής στο άπειρο. Το όριο
 * **δεν είναι αυθαίρετο**: είναι το ίδιο σημείο όπου η προβολή γίνεται τετράγωνη και
 * όπου κόβουν τον κόσμο όλοι οι χάρτες πλακιδίων.
 */
export const WEB_MERCATOR_MAX_LATITUDE = 85.051129;

/**
 * Το ανώτατο ζουμ που καλύπτει η παρεμβολή.
 *
 * ⚠️ **Πέρα από το τελευταίο στάσιμο το MapLibre ΣΤΑΘΕΡΟΠΟΙΕΙ** (δεν προεκτείνει) —
 * άρα ένα χαμηλό όριο εδώ θα «πάγωνε» τον κύκλο σε μέγεθος οθόνης ακριβώς στο ζουμ
 * όπου η ακρίβεια μετράει περισσότερο. Το `24` είναι το μέγιστο που επιτρέπει η
 * προδιαγραφή στυλ, όχι το προεπιλεγμένο `22` του χάρτη: έτσι μια μελλοντική αύξηση
 * του `maxZoom` **δεν** γεννά σιωπηλό ελάττωμα.
 */
export const METRIC_SIZE_MAX_ZOOM = 24;

/**
 * **Ο συντελεστής παραμόρφωσης Mercator στο γεωγραφικό πλάτος φ** — `1 / cos(φ)`.
 *
 * Στο ζουμ z η ανάλυση εδάφους είναι `mpp₀ · cos(φ) / 2^z`, δηλαδή ένα μέτρο κοντά
 * στον πόλο πιάνει **περισσότερα** pixel από ένα μέτρο στον ισημερινό. Ο συντελεστής
 * είναι το αντίστροφο αυτής της συρρίκνωσης.
 *
 * @param latitude Γεωγραφικό πλάτος σε μοίρες. Ψαλιδίζεται στα όρια της προβολής.
 */
export function mercatorScaleAt(latitude: number): number {
  const clamped = Math.min(
    WEB_MERCATOR_MAX_LATITUDE,
    Math.max(-WEB_MERCATOR_MAX_LATITUDE, latitude)
  );
  return 1 / Math.cos((clamped * Math.PI) / 180);
}

/**
 * Πόσα pixel είναι `meters` μέτρα στο ζουμ `zoom`, στο πλάτος `latitude`.
 *
 * 🔑 **Υπάρχει ως συνάρτηση, όχι μόνο ως έκφραση MapLibre, επειδή έχει ΔΕΥΤΕΡΟ
 * καταναλωτή: τις ΑΓΚΥΡΕΣ.** Μια έκφραση στυλ είναι δεδομένα που εκτελεί ο χάρτης —
 * **καμία σουίτα δεν την αποδίδει** (το ακριβότερο μάθημα του Βήματος 3). Εδώ ζει η
 * ίδια αριθμητική σε μορφή που **μπορεί να κοκκινίσει**, και το `metric-size.test.ts`
 * επαληθεύει ότι τα στάσιμα της έκφρασης τη γεννούν πίσω.
 */
export function metersToPixels(meters: number, zoom: number, latitude: number): number {
  return (meters * mercatorScaleAt(latitude) * 2 ** zoom) / METERS_PER_PIXEL_AT_ZOOM_0;
}

/**
 * **Πού πέφτει ένα σημείο στον «κόσμο» του χάρτη στο ζουμ `zoom`**, σε pixel — η
 * προβολή Web Mercator της MapLibre (πλάκα {@link MAPLIBRE_TILE_SIZE_PX}).
 *
 * 🔑 Απαντά **«πόσο μακριά θα φαίνονται δύο σημεία σε ζουμ που ο χάρτης ΔΕΝ δείχνει
 * ακόμη»** — ερώτηση που το `map.project` δεν μπορεί να κάνει, γιατί ξέρει μόνο το
 * τρέχον ζουμ (ADR-777 §8.76: «θα χωρίσει το ζουμ αυτή την ομάδα;»).
 */
export function lngLatToWorldPixel(lng: number, lat: number, zoom: number): readonly [number, number] {
  const size = MAPLIBRE_TILE_SIZE_PX * 2 ** zoom;
  const clamped = Math.min(WEB_MERCATOR_MAX_LATITUDE, Math.max(-WEB_MERCATOR_MAX_LATITUDE, lat));
  const phi = (clamped * Math.PI) / 180;
  const x = ((lng + 180) / 360) * size;
  const y = (0.5 - Math.log((1 + Math.sin(phi)) / (1 - Math.sin(phi))) / (4 * Math.PI)) * size;
  return [x, y];
}

interface MetricCircleRadiusOptions {
  /** Το πεδίο του feature που κρατά την ακτίνα σε **μέτρα**. */
  readonly metersProperty: string;
  /** Το πεδίο του feature που κρατά τον συντελεστή {@link mercatorScaleAt}. */
  readonly scaleProperty: string;
  /**
   * Κάτω όριο σε pixel — **ώστε ο ισχυρισμός να μη γίνεται αόρατος**.
   *
   * ⚠️ Χωρίς αυτό, μια αγγελία «κάπου στη συνοικία» (1,5 χλμ) γίνεται **1,6 px** στο
   * ζουμ 6 και **εξαφανίζεται από τον χάρτη** — δεν έχει πινέζα να πέσει πίσω της. Το
   * ίδιο κάνει ο κύκλος ακρίβειας GPS του Google Maps, για τον ίδιο λόγο.
   */
  readonly minPx: number;
  /**
   * Άνω όριο σε pixel — **όριο ΑΠΟΔΟΣΗΣ, όχι αλλαγή ισχυρισμού**.
   *
   * ⚠️ Στο ζουμ 18 μια αβεβαιότητα 10 χλμ είναι ~42 500 px. Ο κύκλος του MapLibre
   * ζωγραφίζεται σε **τετράπλευρο του shader** και σε ακραίες ακτίνες αποκόπτεται —
   * δηλαδή το «τεράστιο» θα γινόταν **σπασμένο**. Στο ψαλίδι ο κύκλος καλύπτει ήδη
   * ολόκληρο το κάδρο, οπότε η εικόνα είναι **ταυτόσημη** με την ακρίβιστη.
   */
  readonly maxPx: number;
}

/**
 * Η ακτίνα σε pixel για **ένα** ζουμ, ως έκφραση οδηγούμενη από τα δεδομένα.
 *
 * `μέτρα × συντελεστήςMercator × 2^ζουμ / mpp₀`, ψαλιδισμένη και από τις δύο πλευρές.
 */
function clampedRadiusAtZoom(
  options: MetricCircleRadiusOptions,
  zoom: number
): readonly unknown[] {
  const { metersProperty, scaleProperty, minPx, maxPx } = options;
  const pixelsPerMetre = 2 ** zoom / METERS_PER_PIXEL_AT_ZOOM_0;

  return [
    'min',
    ['max', ['*', ['get', metersProperty], ['get', scaleProperty], pixelsPerMetre], minPx],
    maxPx,
  ];
}

/**
 * **Η έκφραση που δίνει σε έναν κύκλο σταθερό μέγεθος ΣΤΟΝ ΚΟΣΜΟ.**
 *
 * `pixels = clamp(μέτρα × συντελεστήςMercator × 2^ζουμ / mpp₀)`
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΕΝΑ ΣΤΑΣΙΜΟ ΑΝΑ ΖΟΥΜ ΚΑΙ ΟΧΙ ΔΥΟ — ΚΑΙ ΤΟ ΕΜΑΘΑ ΑΠΟ ΤΗΝ ΠΡΟΔΙΑΓΡΑΦΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η προφανής γραφή είναι `['min', ['max', ['*', …, ['interpolate', …, ['zoom'], …]]]]`
 * — **και είναι ΑΚΥΡΗ**. Η προδιαγραφή στυλ το λέει κατά λέξη: *«σε ιδιότητες layout
 * ή paint, το `["zoom"]` μπορεί να εμφανιστεί **μόνο** ως είσοδος **εξωτερικής**
 * `interpolate` ή `step`»*. Φωλιασμένο μέσα σε `*`/`min`, το στυλ **απορρίπτεται**
 * — και το MapLibre δεν σκάει: αφήνει το επίπεδο **σιωπηλά αζωγράφιστο**, δηλαδή
 * ακριβώς το σχήμα αποτυχίας που κόστισε το Βήμα 3 *(8 σφάλματα κονσόλας, οθόνη που
 * «έμοιαζε σωστή»)*.
 *
 * ⇒ Το `interpolate` ανεβαίνει **έξω** και το ψαλίδι κατεβαίνει **μέσα σε κάθε
 * έξοδο** — μορφή που η ίδια η προδιαγραφή δείχνει ως παράδειγμα *(«οι έξοδοι μιας
 * `interpolate` πάνω στο ζουμ μπορούν να χρησιμοποιούν `get`»)*.
 *
 * 🔑 **ΚΑΙ ΠΑΡΑΜΕΝΕΙ ΑΚΡΙΒΗΣ, ΔΕΝ ΕΙΝΑΙ ΠΡΟΣΕΓΓΙΣΗ.** Με βάση `2` και στάσιμα **ανά
 * έναν** βαθμό ζουμ ισχύει `out(k+1) = 2·out(k)`, οπότε ο τύπος της εκθετικής
 * παρεμβολής απλοποιείται αλγεβρικά:
 *
 * ```
 * out(z) = out(k) + (out(k+1) − out(k)) · (2^(z−k) − 1)/(2 − 1)
 *        = out(k) · 2^(z−k)                                  ⇒ ακριβώς A·2^z
 * ```
 *
 * ⚠️ **Με ΔΥΟ στάσιμα (0 και 24) αυτό ΚΑΤΑΡΡΕΕΙ μόλις μπει το ψαλίδι**, και όχι
 * λίγο: για αβεβαιότητα 1,5 χλμ η παρεμβολή ανάμεσα σε ψαλιδισμένο `6` και
 * ψαλιδισμένο `3000` δίνει στο ζουμ 10 **6,2 px** αντί για **24,9 px** — τετραπλάσιο
 * σφάλμα, σιωπηλό. Το ψαλίδι πρέπει να εφαρμόζεται **στην τιμή**, όχι στα άκρα.
 *
 * 🔴 **Το `['get']` ΔΕΝ είναι λεπτομέρεια υλοποίησης — είναι ο λόγος που δουλεύει.**
 * Και τα δύο μεγέθη ζουν στο **feature**, άρα κάθε αγγελία κουβαλά τη δική της
 * αβεβαιότητα και το δικό της πλάτος. Γραμμένα ως σταθερές του επιπέδου, ο χάρτης θα
 * είχε **μία** απάντηση για όλες — που είναι ακριβώς ο περιορισμός τον οποίο
 * καταγράφει ως αξεπέραστο η ίδια η MapLibre.
 */
export function metricCircleRadius(options: MetricCircleRadiusOptions): CircleRadiusValue {
  const stops: unknown[] = [];
  for (let zoom = 0; zoom <= METRIC_SIZE_MAX_ZOOM; zoom += 1) {
    stops.push(zoom, clampedRadiusAtZoom(options, zoom));
  }

  return ['interpolate', ['exponential', 2], ['zoom'], ...stops] as CircleRadiusValue;
}
