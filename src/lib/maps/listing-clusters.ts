/**
 * @fileoverview SSoT — **πώς ομαδοποιούνται οι αγγελίες, και τι ΕΠΙΤΡΕΠΕΤΑΙ να λέει η ομάδα**.
 * @related ADR-777 §8.66 · lib/listings/listings-geojson.ts · lib/maps/metric-size.ts
 * @module lib/maps/listing-clusters
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Ο ΚΑΝΟΝΑΣ: **ΠΛΗΘΟΣ, ΠΟΤΕ ΤΙΜΗ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `clusterProperties` του MapLibre επιτρέπει **οποιαδήποτε** συνάθροιση — μέση
 * τιμή, ελάχιστο, μέγιστο. Είναι **παγίδα, όχι δυνατότητα**: μια «μέση τιμή» πάνω σε
 * συσσωμάτωμα είναι αριθμός που **δεν αντιστοιχεί σε κανένα ακίνητο**, δηλαδή ακριβώς
 * το ψέμα που απαγορεύει η **Α5**. Το Redfin έχει clustering από το 2011 και δείχνει
 * **πλήθος**· το ίδιο η Zillow. Εδώ ο κανόνας γράφεται **σε κώδικα**, ώστε να μη
 * χρειάζεται να τον θυμάται ο επόμενος.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΠΟΥ ΞΕΠΕΡΝΑΜΕ ΤΟΥΣ ΜΕΓΑΛΟΥΣ — **ΤΟ ΣΥΣΣΩΜΑΤΩΜΑ ΟΜΟΛΟΓΕΙ ΤΙ ΔΕΝ ΞΕΡΕΙ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ένα συσσωμάτωμα «17» που περιέχει 5 αγγελίες τις οποίες ξέρουμε μόνο *«κάπου στην
 * πόλη»* **ισχυρίζεται εντοπισμό που δεν έχουμε**: ο επισκέπτης διαβάζει «17 εδώ» και
 * **δεν έχει κανέναν τρόπο** να μάθει ότι οι 5 μπορεί να είναι δέκα χιλιόμετρα μακριά.
 * Κανένας από τους μεγάλους δεν το διακρίνει — γιατί **κανείς τους δεν κρατά** την
 * αβεβαιότητα ως δεδομένο. Εμείς την κρατάμε ήδη (`LISTING_UNCERTAINTY_KM`), άρα η
 * ομάδα μπορεί να πει **δύο αριθμούς**: *«12 · +5≈»*.
 *
 * 🔑 **Δεν είναι διακόσμηση — είναι ο ΙΔΙΟΣ κανόνας με τη «τρίτη κατηγορία» του
 * §8.63**, στην κλίμακα του συσσωματώματος: ό,τι δεν ξέρουμε **λέγεται**, δεν
 * στρογγυλοποιείται μέσα στο σύνολο.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΤΟ ΚΕΙΜΕΝΟ ΕΙΝΑΙ ΑΡΙΘΜΟΙ ΚΑΙ ΣΥΜΒΟΛΑ — **ΚΑΜΙΑ ΛΕΞΗ**, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Μια ετικέτα MapLibre είναι **δεδομένα σε στυλ**: δεν περνά από `t()`, δεν έχει
 * `aria-label`, δεν διαβάζεται από αναγνώστη οθόνης. Λέξη εκεί μέσα θα ήταν
 * **hardcoded string σε δεύτερη γλώσσα** (N.11) ή prop που ταξιδεύει από τρία
 * επίπεδα ψηλότερα. Άρα η ομάδα δείχνει `12 · +5≈` — **γλωσσικά ουδέτερο**, όπως
 * κάνουν Zillow και Redfin — και το *τι σημαίνει το `≈`* ζει στη λεζάντα, όπου
 * υπάρχει κανονικό i18n **και** αναγνώσιμο κείμενο.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις + σταθερές, μόνο τύποι από το σύνορο του χάρτη.
 */

import type { CircleLayerSpecification, SymbolLayerSpecification } from './maplibre';

/** Ο τύπος που δέχεται το `circle-radius`, **παραγόμενος από τη βιβλιοθήκη**. */
type CircleRadius = NonNullable<CircleLayerSpecification['paint']>['circle-radius'];
/** Ο τύπος που δέχεται το `text-field`, **παραγόμενος από τη βιβλιοθήκη**. */
type TextField = NonNullable<SymbolLayerSpecification['layout']>['text-field'];

/**
 * **Τα ονόματα που προσθέτει ΜΟΝΟ ΤΟΥ το MapLibre** σε κάθε συσσωμάτωμα.
 *
 * 🔴 **Γραμμένα εδώ γιατί είναι σύμβαση της βιβλιοθήκης, όχι δική μας επιλογή** — και
 * ένα λάθος τους είναι **σιωπηλό**: το `['get', 'pointCount']` *(αντί `point_count`)*
 * δεν σκάει, δίνει `null`, και το συσσωμάτωμα ζωγραφίζεται **χωρίς αριθμό**.
 */
export const CLUSTER_KEY = {
  /** `true` στα συσσωματώματα — ο μόνος τρόπος να τα ξεχωρίσεις από μεμονωμένα σημεία. */
  isCluster: 'cluster',
  /** Πόσα **αρχικά** σημεία περιέχει. */
  pointCount: 'point_count',
} as const;

/**
 * **Το δικό μας πεδίο: πόσα από αυτά δεν τα ξέρουμε ακριβώς.**
 *
 * ⚠️ Πρόθεμα `nestor` επίτηδες: το `clusterProperties` γράφει σε **κοινό** χώρο
 * ονομάτων με τα αυτόματα πεδία της βιβλιοθήκης, και μια μελλοντική έκδοση που θα
 * πρόσθετε δικό της `uncertain` θα μας **σκίαζε σιωπηλά**.
 */
export const CLUSTER_UNCERTAIN_KEY = 'nestorUncertain';

/**
 * **Πόσο κοντά πρέπει να είναι δύο αγγελίες για να γίνουν μία κουκκίδα**, σε pixel.
 *
 * 🔑 **Το `50` είναι η προεπιλογή του supercluster, και το κρατάμε ΜΕ ΛΟΓΟ**: είναι
 * περίπου το πλάτος του δαχτύλου σε οθόνη αφής *(η καθιερωμένη τιμή στόχου ~44-48 px)*,
 * δηλαδή δύο σημεία που δεν χωρίζονται από το δάχτυλο **δεν πρέπει** να παριστάνουν
 * δύο ξεχωριστούς στόχους. Μικρότερη τιμή δίνει ομάδες που ξαναδιαλύονται σε κάθε
 * σύρσιμο· μεγαλύτερη καταπίνει γειτονιές ολόκληρες.
 */
export const CLUSTER_RADIUS_PX = 50;

/**
 * **Το ζουμ πάνω από το οποίο δεν ομαδοποιούμε πια.**
 *
 * ⚠️ **Δεν είναι «όσο πιο ψηλά τόσο καλύτερα».** Πάνω από αυτό ο επισκέπτης βλέπει
 * **κάθε** αγγελία χωριστά — που είναι το ζητούμενο σε επίπεδο δρόμου, αλλά σημαίνει
 * επίσης ότι οι πινακίδες τιμών ξαναρχίζουν να στοιβάζονται. Το `14` είναι το επίπεδο
 * όπου ένα κάδρο καλύπτει περίπου μια **συνοικία** — η κλίμακα στην οποία ο άνθρωπος
 * σταματά να ρωτά *«πού;»* και αρχίζει να ρωτά *«ποιο;»*.
 *
 * 🔴 **ΚΑΙ ΚΑΤΩ ΑΠΟ ΑΥΤΟ, Ο ΚΥΚΛΟΣ ΑΒΕΒΑΙΟΤΗΤΑΣ ΤΟΥ §8.64 ΔΕΝ ΖΩΓΡΑΦΙΖΕΤΑΙ — ΔΕΝ
 * ΧΑΝΕΤΑΙ, ΠΑΡΑΔΙΔΕΤΑΙ.** Μετρημένο ζωντανά *(ADR-777 §8.68.3 Β)*: με πέντε
 * `shaded-neighbourhood` καταπιωμένες σε συσσωμάτωμα, το επίπεδο
 * `listing-neighbourhood` αποδίδει **0** σχήματα — η ομολογία μεταφέρεται ολόκληρη
 * στο `+5≈` της ετικέτας.
 *
 * ⚠️ **Γράφεται εδώ γιατί ΔΕΝ είναι προφανές και μοιάζει με παλινδρόμηση**: ο επόμενος
 * που θα ζουμάρει σε συνοικία και δεν θα δει τους σκιασμένους κύκλους θα συμπεράνει
 * ότι «έσπασε το §8.64». Δεν έσπασε — **η ίδια αλήθεια αλλάζει φορέα** στο ζ≤14.
 */
export const CLUSTER_MAX_ZOOM = 14;

/**
 * **Οι επιλογές ομαδοποίησης της πηγής** — γραμμένες μία φορά, δοσμένες στο `<Source>`.
 *
 * 🔴 **Το `clusterProperties` εδώ μετρά ΠΛΗΘΟΣ ΥΠΟΣΥΝΟΛΟΥ, ποτέ τιμή.** Η μορφή είναι
 * `[τελεστής, έκφραση-ανά-σημείο]`: το `['+', …]` αθροίζει, και η έκφραση δίνει `1`
 * για κάθε αγγελία με αβεβαιότητα και `0` για τις υπόλοιπες. Δηλαδή **καταμέτρηση με
 * συνθήκη**, το μόνο πράγμα που ένα συσσωμάτωμα δικαιούται να συναθροίσει.
 *
 * ⚠️ **Η συνθήκη ρωτά το `uncertaintyM`, ΟΧΙ το `shape`** — και είναι η ίδια επιλογή
 * που έκανε το §8.64: το `shape` είναι **κατηγορία παρουσίασης** *(θα χρειαζόταν
 * απαρίθμηση που ξεχνιέται όταν προστεθεί σκαλί)*, ενώ το `uncertaintyM` είναι **το
 * μέγεθος που κρίνει ο κριτής**. Ένα σκαλί παραπάνω αύριο μπαίνει **μόνο του**.
 */
export const LISTING_CLUSTER_OPTIONS = {
  cluster: true,
  clusterRadius: CLUSTER_RADIUS_PX,
  clusterMaxZoom: CLUSTER_MAX_ZOOM,
  clusterProperties: {
    [CLUSTER_UNCERTAIN_KEY]: ['+', ['case', ['>', ['get', 'uncertaintyM'], 0], 1, 0]],
  },
} as const;

/**
 * **«Αυτό ΔΕΝ είναι συσσωμάτωμα»** — το φίλτρο που χρειάζεται **κάθε** επίπεδο σχήματος.
 *
 * ⚠️ **ΔΕΝ ΔΙΟΡΘΩΝΕΙ ΣΦΑΛΜΑ — ΚΑΝΕΙ ΡΗΤΗ ΜΙΑ ΑΣΦΑΛΕΙΑ ΠΟΥ ΣΗΜΕΡΑ ΕΙΝΑΙ ΠΑΡΕΝΕΡΓΕΙΑ.**
 * Ένα συσσωμάτωμα είναι σημείο **χωρίς** `shape`, οπότε το
 * `['==', ['get','shape'], 'pin']` το αφήνει ήδη έξω: το `['get']` σε πεδίο που λείπει
 * δίνει `null`, και `null !== 'pin'`. Δηλαδή **σήμερα τα φίλτρα σχήματος αρκούν**, και
 * θα ήταν ανέντιμο να γραφτεί εδώ ότι κάτι σπάει χωρίς αυτό.
 *
 * 🔑 **Υπάρχει επειδή η επάρκεια είναι ΤΥΧΑΙΑ, όχι δηλωμένη**: την ημέρα που ένα
 * επίπεδο θα φιλτράρει σε **αριθμητικό** πεδίο — π.χ. `['>', ['get','uncertaintyM'], 0]`,
 * που είναι η προφανής επόμενη γραφή — το `null` θα συγκριθεί ως `0` και το
 * συσσωμάτωμα θα **περάσει**, ζωγραφισμένο με ακτίνα `NaN` ⇒ σιωπηλά αζωγράφιστο. Το
 * φίλτρο κοστίζει μηδέν και κλείνει την κατηγορία **πριν** ανοίξει.
 *
 * 🔑 Ρωτά `!has`, όχι `== false`: το MapLibre **δεν προσθέτει** `cluster: false` στα
 * μεμονωμένα σημεία — απλώς δεν βάζει το πεδίο.
 */
export const NOT_A_CLUSTER: readonly unknown[] = ['!', ['has', CLUSTER_KEY.pointCount]];

/**
 * **Η ακτίνα του συσσωματώματος μεγαλώνει με το ΠΛΗΘΟΣ** — τρία σκαλιά, όχι συνεχές.
 *
 * 🔑 **Σκαλιά και όχι `interpolate`, επίτηδες.** Μια συνεχής συνάρτηση του πλήθους
 * καλεί τον αναγνώστη να **συγκρίνει εμβαδά** — κάτι που το ανθρώπινο μάτι κάνει
 * αποδεδειγμένα κακά *(ο κλασικός λόγος που τα bubble charts παραπλανούν)*. Τρία
 * διακριτά μεγέθη λένε **«λίγα / αρκετά / πολλά»** και αφήνουν τον **αριθμό** να πει
 * το ακριβές, που είναι ήδη γραμμένος πάνω τους.
 *
 * ⚠️ Τα σκαλιά είναι σε **pixel οθόνης**, και εδώ αυτό είναι **σωστό**: το
 * συσσωμάτωμα δεν ισχυρίζεται έκταση — είναι **στόχος για κλικ** (§8.64.5).
 */
export const CLUSTER_RADIUS: CircleRadius = [
  'step',
  ['get', CLUSTER_KEY.pointCount],
  16, // < 10
  10,
  22, // 10-49
  50,
  30, // 50+
] as CircleRadius;

/**
 * **ΤΟ ΚΕΙΜΕΝΟ ΤΗΣ ΟΜΑΔΑΣ — και οι δύο αριθμοί μόνο όταν υπάρχει δεύτερος.**
 *
 * ```
 * καμία αβεβαιότητα → «17»
 * με αβεβαιότητα    → «12 · +5≈»      (12 = ακριβείς, 5 = «κάπου στην περιοχή»)
 * ```
 *
 * 🔴 **Ο πρώτος αριθμός ΔΕΝ είναι το `point_count` — είναι η ΔΙΑΦΟΡΑ.** Αν έγραφε το
 * σύνολο, οι δύο αριθμοί θα **επικαλύπτονταν** *(«17 · +5»)* και ο αναγνώστης δεν θα
 * είχε τρόπο να ξέρει αν το 5 είναι **μέσα** στο 17 ή **επιπλέον**. Δύο αριθμοί που
 * αθροίζουν στο σύνολο είναι η **μόνη** ανάγνωση χωρίς οδηγίες.
 *
 * ⚠️ **Η μηδενική περίπτωση ΔΕΝ γράφεται ως «12 · +0≈».** Ένα σύμβολο αβεβαιότητας
 * που εμφανίζεται πάντα εκπαιδεύει τον αναγνώστη να το **αγνοεί** — ίδιο σκεπτικό με
 * την υποσημείωση του `AreaLedgerBar`, που εμφανίζεται **μόνο** όταν υπάρχει «ίσως».
 */
export const CLUSTER_TEXT: TextField = [
  'case',
  ['>', ['get', CLUSTER_UNCERTAIN_KEY], 0],
  [
    'concat',
    ['to-string', ['-', ['get', CLUSTER_KEY.pointCount], ['get', CLUSTER_UNCERTAIN_KEY]]],
    ' · +',
    ['to-string', ['get', CLUSTER_UNCERTAIN_KEY]],
    '≈',
  ],
  ['to-string', ['get', CLUSTER_KEY.pointCount]],
] as TextField;
