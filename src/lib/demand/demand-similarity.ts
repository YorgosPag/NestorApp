/**
 * @fileoverview **«ΠΟΣΟΙ ΑΛΛΟΙ ΖΗΤΟΥΝ ΤΟ ΙΔΙΟ»** — τι σημαίνει «το ίδιο».
 * @related ADR-777 §7 (Α9) · SPEC-777B §12.6 · lib/demand/demand-listing-filters.ts
 * @module lib/demand/demand-similarity
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΚΡΙΤΗΡΙΟ ΔΕΝ ΕΠΙΝΟΗΘΗΚΕ — **ΠΑΡΑΓΕΤΑΙ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το §12.6 ζητά *«**πόσοι άλλοι** ζητούν το ίδιο»*. Το «ίδιο» χρειάζεται ορισμό, και
 * η αφελής εκδοχή —«σύγκρινε πεδίο προς πεδίο»— είναι **λάθος με μετρήσιμο τρόπο**:
 * δύο άνθρωποι που ψάχνουν *«τριάρι ως 250.000 στη Θεσσαλονίκη»* και *«τριάρι ως
 * 260.000 στη Θεσσαλονίκη»* **ανταγωνίζονται για τα ίδια ακίνητα**, και ένα κριτήριο
 * ισότητας θα έλεγε «κανένας άλλος».
 *
 * 🔑 **Ο σωστός ορισμός είναι λειτουργικός, όχι συντακτικός:**
 *
 *   > δύο ζητήσεις είναι «το ίδιο» όταν **μπορεί να υπάρξει αγγελία που ικανοποιεί
 *   > και τις δύο** — δηλαδή όταν οι **προβολές** τους σε φίλτρα **τέμνονται**.
 *
 * Και επειδή η προβολή υπάρχει ήδη ({@link listingFiltersFromDemand}), εδώ **δεν
 * γεννιέται καμία νέα γνώση για τη ζήτηση**: μόνο τομή ευρών. Ένα ξεχωριστό λεξιλόγιο
 * ομοιότητας θα ήταν **δεύτερη ανάγνωση των ίδιων αξόνων**, που θα απέκλινε από τη
 * μηχανή ταιριάσματος στην πρώτη αλλαγή — και η απόκλιση θα φαινόταν μόνο ως αριθμός
 * που «δεν βγάζει νόημα».
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΤΟ ΚΡΙΤΗΡΙΟ ΕΙΝΑΙ ΣΚΟΠΙΜΑ **ΓΕΝΝΑΙΟΔΩΡΟ**, ΚΑΙ ΑΥΤΟ ΕΙΝΑΙ ΑΣΦΑΛΕΙΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ό,τι δεν ταξιδεύει στην προβολή (χρόνος · όροφος · γειτονιά · ταυτότητα ακινήτου)
 * **δεν στενεύει** την ομοιότητα. Άρα μετράμε **περισσότερους**, ποτέ λιγότερους.
 *
 * Και είναι η **σωστή** κατεύθυνση σφάλματος για δύο ανεξάρτητους λόγους: (α) ο
 * αριθμός λέει *«πόσοι ανταγωνίζεσαι»* — μια γενναιόδωρη εκτίμηση είναι ειλικρινής
 * προειδοποίηση, μια στενή είναι ψεύτικη ησυχία· (β) περνά **από το k-κατώφλι** του
 * `area-market`, οπότε ένα «μετράω παραπάνω» **δεν** μπορεί να μετατραπεί σε
 * αποκάλυψη λιγότερων ατόμων — το κατώφλι κρύβει, δεν αποκαλύπτει.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις. Καμία εξάρτηση από React/Firestore.
 */

import type { PropertyDemand } from '@/types/property-demand';
import type { ListingFilters } from '@/lib/listings/listing-filters';
import type { GeoArea } from '@/types/geo/coordinates';
import { rangeOf, valuesOf } from '@/lib/criteria/listing-criteria';
import { NO_RANGE, type CriterionRange } from '@/lib/criteria/criterion-vocabulary';
import { areasOverlap } from '@/lib/geo/geo-area';
import { listingFiltersFromDemand } from './demand-listing-filters';

// =============================================================================
// ΤΟΜΕΣ — ένα κατηγόρημα ανά άξονα
// =============================================================================

/**
 * Τέμνονται δύο σύνολα ετικετών; **Κενό σημαίνει «όλα»**, ποτέ «κανένα».
 *
 * ⚠️ Η σημασιολογία του κενού είναι **αντιγραμμένη από το `ListingFilters`**, όπου
 * *«κενό = όλες οι διαθέσεις, όχι καμία»*. Αν εδώ το κενό σήμαινε «κανένα», μια
 * ζήτηση χωρίς προτίμηση είδους θα ήταν όμοια με **καμία** — ενώ ανταγωνίζεται για
 * **τα πάντα**.
 */
function labelsIntersect(a: readonly string[], b: readonly string[]): boolean {
  if (a.length === 0 || b.length === 0) return true;
  return a.some((label) => b.includes(label));
}

/**
 * Τέμνονται δύο εύρη; `null` σε ένα άκρο σημαίνει **χωρίς όριο** προς εκείνη τη μεριά.
 *
 * ⚠️ **`null` δεν είναι 0 και δεν είναι άπειρο «κατά προσέγγιση»** — αντιμετωπίζεται
 * ρητά. Ένα `?? 0` στο κάτω άκρο θα ήταν σωστό· ένα `?? 0` στο **πάνω** θα έκανε κάθε
 * ζήτηση χωρίς οροφή να μην τέμνεται με **τίποτα**, δηλαδή το ακριβώς αντίθετο.
 */
function rangesIntersect(
  aMin: number | null,
  aMax: number | null,
  bMin: number | null,
  bMax: number | null,
): boolean {
  if (aMin !== null && bMax !== null && aMin > bMax) return false;
  if (bMin !== null && aMax !== null && bMin > aMax) return false;
  return true;
}

/**
 * Τέμνονται οι δύο περιοχές αναζήτησης;
 *
 * 🔑 **Δεν είναι «είναι το ίδιο σημείο»**: δύο άνθρωποι που ψάχνουν σε γειτονικές
 * γειτονιές με ακτίνα 10 χλμ. ο καθένας **βλέπουν τα ίδια ακίνητα** στη μέση.
 *
 * ✅ **Η ΓΕΩΜΕΤΡΙΑ ΕΦΥΓΕ ΑΠΟ ΕΔΩ** *(ADR-777 §8.63)*. Ζούσε γραμμένη στο χέρι
 * *(«απόσταση κέντρων ≤ άθροισμα ακτίνων»)* — σωστή, αλλά **δεύτερη**: το ίδιο
 * ερώτημα το απαντούσε ήδη ο γεωγραφικός φιλτραριστής των αγγελιών, με δικό του
 * κώδικα. Τώρα και οι δύο ρωτούν το {@link areasOverlap}, δηλαδή **μία** μηχανή —
 * και ως δώρο η ζήτηση απαντά πλέον σωστά και για **ορθογώνιες** περιοχές, που
 * χειρόγραφα δεν μπορούσε να εκφράσει.
 *
 * ⚠️ `null` (δηλαδή `anywhere`, ή `place` που δεν προβάλλεται) τέμνεται με **τα
 * πάντα** — είναι κυριολεκτικά «οπουδήποτε».
 */
function areasIntersect(a: GeoArea | null, b: GeoArea | null): boolean {
  if (a === null || b === null) return true;
  return areasOverlap(a, b);
}

// =============================================================================
// ΤΟ ΚΡΙΤΗΡΙΟ
// =============================================================================

/**
 * **Ζητούν αυτές οι δύο εντολές «το ίδιο»;**
 *
 * ⚠️ **Συμμετρικό εξ ορισμού** (κάθε κατηγόρημα είναι τομή), και αυτό είναι
 * συμβόλαιο: αν το «ο Α είναι όμοιος με τον Β» δεν συνεπαγόταν το αντίστροφο, δύο
 * άνθρωποι θα έβλεπαν **διαφορετικό** αριθμό ανταγωνιστών για την ίδια αγορά.
 *
 * ⚠️ **Δεν εξαιρεί τον εαυτό της.** Το κάνει ο καλών (`discloseCompetition`
 * φιλτράρει κατά ταυτότητα), γιατί «όμοια» και «άλλη» είναι **δύο ερωτήσεις** —
 * και μια ζήτηση είναι, προφανώς, όμοια με τον εαυτό της.
 */
export function demandsAreSimilar(a: PropertyDemand, b: PropertyDemand): boolean {
  const fa = listingFiltersFromDemand(a);
  const fb = listingFiltersFromDemand(b);

  return (
    labelsIntersect(labels(fa, 'offerKind'), labels(fb, 'offerKind')) &&
    labelsIntersect(labels(fa, 'type'), labels(fb, 'type')) &&
    // 🔴 **Η ΤΙΜΗ ΔΙΑΒΑΖΕΤΑΙ ΑΠΟ ΤΗ ΖΗΤΗΣΗ, ΟΧΙ ΑΠΟ ΤΗΝ ΠΡΟΒΟΛΗ** (μετρημένο 2026-09-18):
    //    από το §8.60.14 ο άξονας τιμής είναι **τρεις** (μονάδα ανά διάθεση) και η προβολή διαλέγει
    //    έναν. Το `span(…, 'price')` ρωτούσε άξονα **που δεν υπάρχει πια** ⇒ ουδέτερο εύρος ⇒ δύο
    //    ζητήσεις με **ασύμβατα** εύρη έβγαιναν «όμοιες», δηλαδή ο ανταγωνισμός μετριόταν λάθος.
    //    ⚠️ Εδώ η σύγκριση είναι **ζήτηση ↔ ζήτηση**: το εύρος είναι αμονάδιστο **και στις δύο**
    //    πλευρές, άρα συγκρίσιμο αυτούσιο. Η μονάδα χρειάζεται μόνο όταν μπαίνει **αγγελία**.
    rangesOverlap(demandPriceSpan(a), demandPriceSpan(b)) &&
    rangesOverlap(span(fa, 'areaSqm'), span(fb, 'areaSqm')) &&
    areasIntersect(fa.near, fb.near)
  );
}

/**
 * 🔴 **ΟΙ ΑΞΟΝΕΣ ΤΗΣ ΟΜΟΙΟΤΗΤΑΣ ΕΙΝΑΙ ΠΕΝΤΕ, ΚΑΙ ΔΕΝ ΜΕΓΑΛΩΣΑΝ ΜΕ ΤΟΝ ΟΡΟΦΟ.**
 *
 * Η προβολή ζήτησης → φίλτρα απέκτησε *(2026-09-04)* άξονα **ορόφου**. Η προφανής
 * κίνηση —«πρόσθεσέ τον κι εδώ, τώρα που ταξιδεύει»— **απορρίπτεται**: αυτή η
 * συνάρτηση απαντά *«ποιος **θα μπορούσε** να ανταγωνιστεί;»*, και η δηλωμένη της
 * πολιτική είναι **γενναιοδωρία** *(«μετράμε περισσότερους, ποτέ λιγότερους»)*.
 * Κάθε νέος άξονας εδώ **στενεύει** τον ανταγωνισμό — δηλαδή λέει στον άνθρωπο ότι
 * τον ψάχνουν λιγότεροι απ' όσους πραγματικά τον ψάχνουν.
 *
 * ⚠️ Άρα ο κατάλογος εδώ **δεν ακολουθεί** τη λίστα απωλειών: είναι δική του
 * απόφαση προϊόντος, και το γράφω ώστε η επόμενη προσθήκη άξονα να μη «διορθώσει»
 * σιωπηλά αυτή τη σιωπή.
 */
function labels(filters: ListingFilters, key: 'offerKind' | 'type'): readonly string[] {
  return valuesOf(filters.criteria, key) ?? [];
}

/** Το **δηλωμένο** εύρος τιμής της ζήτησης — χωρίς μονάδα, όπως ζει στο έγγραφο. */
function demandPriceSpan(demand: PropertyDemand): CriterionRange {
  return { min: demand.features.priceMin, max: demand.features.priceMax };
}

/** Το εύρος ενός άξονα, ή το ουδέτερο όταν δεν ρωτήθηκε. */
function span(filters: ListingFilters, key: 'areaSqm'): CriterionRange {
  return rangeOf(filters.criteria, key) ?? NO_RANGE;
}

/** Τα δύο εύρη, με τη σημασιολογία κενού που ήδη ίσχυε. */
function rangesOverlap(a: CriterionRange, b: CriterionRange): boolean {
  return rangesIntersect(a.min, a.max, b.min, b.max);
}

/**
 * Ποιες από τις υποψήφιες ζητούν «το ίδιο» με τη δεδομένη.
 *
 * 🔑 **Δεν αφαιρεί τη δεδομένη από το αποτέλεσμα** — για τον ίδιο λόγο που δεν το
 * κάνει το {@link demandsAreSimilar}. Ο μοναδικός καταναλωτής, το
 * `discloseCompetition`, αφαιρεί **κατά ταυτότητα** και κουβαλά τον γραμμένο λόγο:
 * *«ένα “1 άλλος ψάχνει το ίδιο” που στην πραγματικότητα είναι ο ίδιος ο χρήστης θα
 * ήταν η εφαρμογή να του μιλά για τον εαυτό του σε τρίτο πρόσωπο»*.
 */
export function selectSimilarDemands(
  demand: PropertyDemand,
  candidates: readonly PropertyDemand[],
): readonly PropertyDemand[] {
  return candidates.filter((candidate) => demandsAreSimilar(demand, candidate));
}
