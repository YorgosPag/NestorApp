/**
 * Η **απόσταση από την ικανοποίηση** σε κάθε άξονα με διάταξη.
 *
 * `null` = ο άξονας **δεν** εμποδίζει (είτε ικανοποιείται, είτε δεν δηλώθηκε).
 * Ποτέ `0` ως «δεν ξέρω»: το `0` εδώ θα σήμαινε «λείπει ακριβώς τίποτα», που είναι
 * υπαρκτή και **διαφορετική** απάντηση.
 */
export interface DemandGaps {
  /** Πόσα € πάνω από την οροφή. */
  readonly priceOverBy: number | null;
  /** Πόσα € κάτω από το κατώφλι. */
  readonly priceUnderBy: number | null;
  /**
   * **Μονάδες ποσοστού** πάνω από την οροφή οικοπεδούχου (ADR-777 §8.60.17).
   *
   * 🔴 **Χωριστό πεδίο από το `priceOverBy`, και είναι η ουσία**: «+5» στο `priceOverBy` θα
   * διαβαζόταν «+5 €». Ποσοστό και ποσό **δεν** μοιράζονται κενό — η μονάδα είναι κλάδος.
   */
  readonly shareOverBy: number | null;
  /**
   * **Νύχτες** που λείπουν ως το ελάχιστο του κατόχου (ADR-777 §8.60.19) — πάνω από το πάνω όριο νυχτών
   * του ζητούντα. Δική του μονάδα, ποτέ σε άλλο πεδίο.
   */
  readonly nightsShortBy: number | null;
  /** Πόσα m² λείπουν από το ελάχιστο. */
  readonly areaShortBy: number | null;
  /** Πόσα m² περισσεύουν από το μέγιστο. */
  readonly areaOverBy: number | null;
  /** Πόσα υπνοδωμάτια λείπουν. */
  readonly bedroomsShortBy: number | null;
  /**
   * Πόσα **μέτρα** έξω από τον χωρικό όρο — την ακτίνα (`outside-radius`) ή το
   * μέτωπο (`outside-frontage`). **Ένα** μέγεθος για **ένα** ερώτημα: ο άξονας χώρου
   * είναι ένας, όσα σχήματα ορίου κι αν αποκτήσει.
   */
  readonly distanceOverMetres: number | null;
}

/** Καμία απόσταση — η ουδέτερη τιμή, ώστε να μη γράφεται δεύτερη φορά. */
export const NO_GAPS: DemandGaps = {
  priceOverBy: null,
  priceUnderBy: null,
  shareOverBy: null,
  nightsShortBy: null,
  areaShortBy: null,
  areaOverBy: null,
  bedroomsShortBy: null,
  distanceOverMetres: null,
};

