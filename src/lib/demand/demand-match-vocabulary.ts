/**
 * Σε ποιο **φυσικό** ακίνητο αντιστοιχεί η αγγελία (επίπεδο Α).
 *
 * ✅ **ΤΟ ΚΕΝΟ ΕΚΛΕΙΣΕ (2026-08-11).** Μέχρι τότε εδώ στεκόταν μετρημένη άρνηση: το
 * `PublicListing` *«δεν κουβαλά **κανέναν** δεσμό … ένα `landId` στην προβολή θα ήταν
 * `null` σε **κάθε** έγγραφο — δηλαδή πεδίο που **κανείς δεν μπορεί να γεμίσει**, ο
 * ορισμός του αδρανούς φρουρού (ADR-749 §5)»*. Και έλεγε πότε θα άλλαζε: *«ο δεσμός
 * γεννιέται όταν γεννηθεί το επίπεδο Α»*.
 *
 * Γεννήθηκε. Το `PublicListing.place` υπάρχει, ο γραφέας του επιπέδου Α δίνει
 * ταυτότητες **κατ' απαίτηση**, και ο καλών (`useDemandAnswer`) γεμίζει τον χάρτη
 * **από τις ίδιες τις αγγελίες**.
 *
 * 🔑 **Ο τύπος ΔΕΝ ξαναγράφεται εδώ — εισάγεται.** Το ίδιο ζεύγος κλειδιών ζούσε σε
 * **τρία** σημεία (εδώ · inline στον κλάδο `place` του `DemandPlace` · στην απάντηση
 * του γραφέα)· τρία ονόματα για ένα πράγμα είναι το σχήμα του **ADR-749**, και εδώ θα
 * ήταν ιδιαίτερα επικίνδυνο γιατί η **σύγκριση** αυτών των δύο πεδίων **είναι** η
 * μηχανή ταιριάσματος. Κανονική θέση: `types/geo/public-place.ts`.
 */
export type ListingPlaceLink = PlaceRef;

/**
 * **Πότε** ελευθερώνεται η αγγελία — ο άξονας που κάνει τη Ζ2 δυνατή.
 *
 * 🔶 **ΔΗΛΩΜΕΝΟ ΚΕΝΟ, με όνομα.** Ούτε αυτό υπάρχει στο `PublicListing` σήμερα. Και
 * είναι το πιο **πολύτιμο** από τα δύο κενά: το §12.3 λέει ότι το πλεονέκτημά μας
 * είναι πως *«ξέρουμε τι χτίζεται»* — ένα διαμέρισμα που παραδίδεται τον Σεπτέμβριο
 * 2027 είναι **προσφορά με ημερομηνία διαθεσιμότητας**, και *«το μοντέλο του υπάρχει
 * ήδη στο BIM»*. Η άντληση αυτής της ημερομηνίας από το έργο είναι ξεχωριστή δουλειά·
 * η **μηχανή** είναι έτοιμη να τη δεχτεί.
 *
 * `null` και στα δύο άκρα = «*δεν ξέρουμε*», και η μηχανή το λέει **ονομαστικά**
 * (`availability-unknown`) αντί να υποθέσει «διαθέσιμο πάντα».
 */
export interface ListingAvailability {
  /** ISO `YYYY-MM-DD`. `null` = διαθέσιμο ήδη / άγνωστη αρχή. */
  readonly from: string | null;
  /** ISO `YYYY-MM-DD`. `null` = χωρίς λήξη διαθεσιμότητας. */
  readonly to: string | null;
}

/**
 * Ό,τι χρειάζεται η μηχανή **πέρα** από την ίδια την αγγελία.
 *
 * 🔑 **Ρητές είσοδοι αντί για άντληση μέσα στη μηχανή** — ίδιο ιδίωμα με το
 * `buildPublicListing(property, placeKnowledge)`. Έτσι η μηχανή μένει **καθαρή** (άρα
 * εξαντλητικά δοκιμάσιμη χωρίς δίκτυο) και τα δύο δηλωμένα κενά είναι **ορατά στην
 * υπογραφή** αντί να είναι κρυμμένα σε ένα `fetch` που κάποιος θα ανακαλύψει.
 */
export interface ListingMatchFacts {
  readonly listing: PublicListing;
  /** `null` = δεν ξέρουμε σε ποιο φυσικό ακίνητο ανήκει. */
  readonly place: ListingPlaceLink | null;
  /** `null` = δεν ξέρουμε καθόλου διαθεσιμότητα. */
  readonly availability: ListingAvailability | null;
  /**
   * **Ζ6** — μετρημένες αποστάσεις σε **μέτρα** ανά είδος γειτονιάς.
   *
   * Είδος που **λείπει** από τον χάρτη σημαίνει «*δεν το ρωτήσαμε*», και είναι
   * **διαφορετικό** από «*δεν υπάρχει κοντά*». Η μηχανή τα ξεχωρίζει
   * (`proximity-unknown` vs `proximity-too-far`) — ίδια διάκριση με το
   * `never-asked` / `owner-declined` της Α5.
   */
  readonly proximityMetres: Partial<Record<DemandProximityKind, number>>;
}

