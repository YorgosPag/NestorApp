export type DemandBlocker = (typeof DEMAND_BLOCKERS)[number];

/**
 * Τα εμπόδια που **δεν** έχουν «πόσο λείπει».
 *
 * ⚠️ **Ονομασμένη σταθερά, όχι σιωπηλό `else`** — ίδιο πρότυπο με το
 * `KINDS_WITHOUT_LEGACY_PROJECTION`: ένα **νέο** εμπόδιο που θα προστεθεί χωρίς να
 * χαρακτηριστεί θα λογιστεί σιωπηλά ως **μετρήσιμο**, και τότε το «κοντινό
 * αποτέλεσμα» θα δείχνει πράγματα που ο χρήστης δεν μπορεί να φτάσει.
 */
export const CATEGORICAL_BLOCKERS = [
  'offer-kind',
  'property-type',
  'other-place',
  'place-unresolved',
  'position-unknown',
  'availability-unknown',
  'proximity-unknown',
  'wrong-side',
] as const satisfies readonly DemandBlocker[];

/**
 * **Η ΤΡΙΤΗ ΤΑΞΗ: τα εμπόδια που δεν λένε «όχι», λένε «δεν ξέρουμε».**
 *
 * 🔴 **Γεννήθηκε από μέτρηση, όχι από συμμετρία.** Το `side-unresolved` ξεκίνησε
 * κατηγορικό — δίπλα στα αδέλφια του `place-unresolved`/`position-unknown` — και αυτό
 * θα ήταν **σιωπηλή καταστροφή του ίδιου του μετώπου**: ένα κατηγορικό εμπόδιο
 * αρκεί για `no-match` ({@link decideVerdict}), και το ADR-777 μετρά ότι **54% των
 * κτιρίων του κέντρου Θεσσαλονίκης δεν έχουν καν διεύθυνση στο OSM**. Δηλαδή η
 * άγνοια πλευράς δεν είναι ακραία περίπτωση — είναι **ο κανόνας**. Ο άνθρωπος που
 * ορίζει προσεκτικά «νότια πλευρά» θα έβλεπε **άδεια οθόνη**, με τον λόγο κρυμμένο.
 *
 * 🔑 **Η διάκριση είναι σημασιολογική, όχι βαθμού.** «Είναι ενοικίαση, ζητάς πώληση»
 * είναι **ιδιότητα της αγγελίας** — κλειστή υπόθεση. «Δεν ξέρουμε σε ποια πλευρά
 * είναι» είναι **ιδιότητα της γνώσης μας** — και η άγνοιά μας δεν είναι λόγος να
 * κρύψουμε από τον άνθρωπο κάτι που **μπορεί** να είναι ακριβώς αυτό που ζητά. Η Α5
 * απαγορεύει να μετατρέπουμε άγνοια σε ισχυρισμό· ένα `no-match` **είναι** ισχυρισμός.
 *
 * ⚠️ **Δεν είναι μετρήσιμο**: δεν υπάρχει «πόσο λείπει» σε μια άγνοια. Γι' αυτό οι
 * τρεις τάξεις είναι **ξένα σύνολα** και το {@link isMeasurableBlocker} τις αφαιρεί
 * **και τις δύο** — αλλιώς η οθόνη θα ζητούσε αριθμό που δεν υπάρχει.
 *
 * ⚠️ **ΜΗΝ μεταφέρεις εδώ τα υπόλοιπα `*-unknown` χωρίς μέτρηση.** Μπήκε **ένα**,
 * επειδή μετρήθηκε ότι για **αυτό** η άγνοια είναι η πλειοψηφία. Τα άλλα τρία
 * παραμένουν κατηγορικά μέχρι κάποιος να δείξει το ίδιο για εκείνα.
 */
export const UNCERTAIN_BLOCKERS = ['side-unresolved'] as const satisfies readonly DemandBlocker[];

/** `true` αν το εμπόδιο είναι **κλειστή υπόθεση** — ιδιότητα της αγγελίας, όχι της γνώσης μας. */
export function isCategoricalBlocker(blocker: DemandBlocker): boolean {
  return (CATEGORICAL_BLOCKERS as readonly string[]).includes(blocker);
}

/** `true` αν το εμπόδιο είναι **ομολογία άγνοιας** — βλ. {@link UNCERTAIN_BLOCKERS}. */
export function isUncertainBlocker(blocker: DemandBlocker): boolean {
  return (UNCERTAIN_BLOCKERS as readonly string[]).includes(blocker);
}

/**
 * `true` αν το εμπόδιο απαντά «πόσο λείπει».
 *
 * ⚠️ Ορίζεται με **αφαίρεση των δύο άλλων τάξεων**, ώστε ένα νέο εμπόδιο που θα
 * προστεθεί χωρίς να καταταγεί να λογίζεται **μετρήσιμο** και να φανεί αμέσως στην
 * οθόνη ως «λείπει αριθμός» — αντί να εξαφανίζεται σιωπηλά.
 */
export function isMeasurableBlocker(blocker: DemandBlocker): boolean {
  return !isCategoricalBlocker(blocker) && !isUncertainBlocker(blocker);
}

