/** Τρεις καταστάσεις — ποτέ δύο. */
export const DEMAND_VERDICTS = ['match', 'near-miss', 'no-match'] as const;

export type DemandVerdict = (typeof DEMAND_VERDICTS)[number];

/**
 * **Μια εναλλακτική της ζήτησης που η αγγελία ικανοποιεί ΠΛΗΡΩΣ** (ADR-777 §8.60.16) — την
 * **προσφέρει** και το ποσό της **χωρά** (ή η εναλλακτική δεν έθεσε όριο).
 *
 * 🔑 **Το περιθώριο είναι ο καθρέφτης του κενού**: το `priceOverBy`/`shareOverBy` λέει «πόσο
 * **έξω**», το `headroomBy` «πόσο **μέσα**» — στη μονάδα του **κλάδου**.
 *
 * 🔴 **Διακριτή ένωση, όχι `role: null`** (ADR-777 §8.60.17): η αντιπαροχή φέρει **ποσοστό**, όχι
 * ευρώ. Ένα κοινό `amount` θα άφηνε κάθε αναγνώστη να ξεχάσει να ρωτήσει τη μονάδα — το ίδιο δόγμα
 * «η μονάδα είναι κλάδος» του §8.60.15.
 */
export type DemandSeekMet = DemandSeekMetPriced | DemandSeekMetExchange;

/** Συναλλαγή **με ποσό** (€ · €/μήνα · €/νύχτα). */
export interface DemandSeekMetPriced {
  readonly kind: PricedSeekKind;
  readonly role: PriceRole;
  /** Το ποσό της αγγελίας **σε αυτόν τον ρόλο** — ο **ίδιος** αναγνώστης με την κρίση· `null` = δεν δηλώθηκε. */
  readonly amount: number | null;
  /** `max − amount` — `null` χωρίς ανώτατο όριο ή χωρίς ποσό. */
  readonly headroomBy: number | null;
}

/** Αντιπαροχή — **ποσοστό οικοπεδούχου**, ποτέ ευρώ. */
export interface DemandSeekMetExchange {
  readonly kind: 'exchange';
  /** Το ποσοστό οικοπεδούχου της αγγελίας· `null` = προς συζήτηση. */
  readonly landownerShare: number | null;
  /** `οροφή − ποσοστό`, σε **μονάδες ποσοστού** — `null` χωρίς οροφή ή χωρίς ποσοστό. */
  readonly headroomBy: number | null;
}

export interface DemandMatch {
  readonly verdict: DemandVerdict;
  /** **Πάντα κενό** όταν `verdict === 'match'`· **ποτέ** κενό αλλιώς. */
  readonly blockers: readonly DemandBlocker[];
  readonly gaps: DemandGaps;
  /**
   * **Σε ποια μονάδα κρίθηκε η τιμή** (ADR-777 §8.60.15) — ο ρόλος της εναλλακτικής που
   * ικανοποιήθηκε ή βρέθηκε πιο κοντά. `null` = καμία κρίση τιμής (κανένα όριο ποσού, ή
   * εναλλακτική χωρίς ποσό — αντιπαροχή).
   *
   * 🔑 Είναι η **μονάδα των `priceOverBy`/`priceUnderBy`**: «+100» δεν διαβάζεται χωρίς αυτήν
   * (€ πώλησης ή €/μήνα;).
   *
   * ⚠️ **ΔΕΝ** απαντά στο «ταιριάζει **ως τι**» — είναι **ένας** ρόλος, ενώ η αγγελία μπορεί να
   * ικανοποιεί **δύο** εναλλακτικές. Εκείνο το λέει το {@link metOn}.
   */
  readonly pricedAs: PriceRole | null;
  /**
   * **Ως τι ταιριάζει** (ADR-777 §8.60.16) — **όλες** οι εναλλακτικές που η αγγελία ικανοποιεί
   * πλήρως, με τη **σειρά του ανθρώπου**. **Ποτέ** κενό όταν `verdict === 'match'` (αναλλοίωτο
   * με `throw`, `demand-matching.ts`).
   */
  readonly metOn: readonly DemandSeekMet[];
}

/**
 * Πόσοι **μετρήσιμοι** άξονες επιτρέπεται να αστοχούν και να λέγεται ακόμη «κοντά».
 *
 * **Δύο**, και ο λόγος είναι το ίδιο το παράδειγμα του §12.6: *«με +20.000 € υπάρχουν
 * 6»* είναι **ένας** άξονας — μια πρόταση που ο άνθρωπος μπορεί να κρατήσει στο
 * μυαλό του. Δύο («λίγο ακριβότερο και λίγο μικρότερο») παραμένει πρόταση. Τρεις
 * είναι **άλλο ακίνητο**, και το να το λέμε «κοντινό» εκπαιδεύει τον χρήστη να
 * αγνοεί τη λέξη.
 *
 * ⚠️ Ο αριθμός είναι **ρυθμιζόμενη πολιτική**, όχι φυσικός νόμος — αλλά ζει **εδώ**,
 * μία φορά, ώστε να μην ξαναγραφτεί ως `< 3` σε κάποια οθόνη.
 */
export const NEAR_MISS_MAX_AXES = 2;
