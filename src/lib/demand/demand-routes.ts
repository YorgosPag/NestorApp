/**
 * **Οι ζητήσεις μου** — ο κατάλογος του ανθρώπου.
 *
 * 🔑 **Πληθυντικός, και είναι απόφαση μοντέλου**: η **Α9** επιτρέπει ρητά πολλές
 * ταυτόχρονες εντολές (*«ανοιχτή εντολή σε αγορά»*, §12.2 — ένας άνθρωπος μπορεί να
 * ψάχνει και γραφείο και σπίτι). Ενικός εδώ θα προδίκαζε **μία** ανά χρήστη, και θα
 * το ανακάλυπτε κανείς όταν ήταν αργά.
 */
import { typedHref } from '@/lib/workspace/route-worlds';
// ⚠️ ΜΟΝΟ τύπος: το αρχείο μένει φύλλο (το διαβάζει και η πλοήγηση). Ο έλεγχος τιμής ζει δίπλα στο
//    σύνολο, `isDemandTimingKind` στο `types/property-demand`.
import type { DemandTimingKind } from '@/types/property-demand';

export const MY_DEMANDS_ROUTE = '/demands' as const;

/**
 * **Δημιουργία ζήτησης** — η μόνη διαδρομή του χαρακτηριστικού που είναι
 * **αποκλειστικά desktop** (Α8).
 *
 * 🔑 **Ξεχωριστή διαδρομή, ΟΧΙ κατάσταση μέσα στον κατάλογο** — και ο λόγος είναι
 * **μετρημένος, όχι αισθητικός**: το route-level code splitting του App Router είναι
 * **αυτόματο** (τεκμηριωμένο: *«Next.js automatically creates a separate JavaScript
 * bundle for each route … only the JavaScript required for that page is downloaded»*).
 * Άρα το βάρος της φόρμας **δεν ταξιδεύει καν** προς όποιον δεν την άνοιξε.
 *
 * Ένα πάνελ δημιουργίας μέσα στο {@link MY_DEMANDS_ROUTE} θα ερχόταν στο **ίδιο**
 * bundle με τον κατάλογο — δηλαδή θα φορτωνόταν σε **κάθε** κινητό που ανοίγει τη
 * λίστα του, και το «μόνο desktop» θα ήταν δήλωση προθέσεων. Η **Α19** (πρώτος καρές)
 * και το §11.6 (φθηνή συσκευή, κινητό δίκτυο) ζητούν το αντίθετο.
 */
export const NEW_DEMAND_ROUTE = '/demands/new' as const;

/**
 * **ADR-900 — «Δες αν κάποιος ενδιαφέρεται για το ακίνητό σου».** Η πόρτα του ιδιοκτήτη που **δεν** έχει
 * καταχωρίσει ακόμη τίποτα. Ζει εδώ, στις διαδρομές της **ζήτησης**, γιατί αυτό ρωτά: πόση ζήτηση υπάρχει.
 * Στο `(me)` (ταυτότητα + `noindex` από το κέλυφος), και **λειτουργεί σε στενή οθόνη** — σε αντίθεση με
 * το `/offers/new` (Α8), δεν έχει βαριά φόρμα.
 */
export const INTEREST_CHECK_ROUTE = '/interest-check' as const;

/** Η βάση της **μίας** ζήτησης. Δυναμικό τμήμα: η ταυτότητα (`dmnd_*`). */
export const DEMAND_DETAIL_ROUTE_BASE = '/demands';

/**
 * Η σελίδα **μιας** ζήτησης — θέαση, επεξεργασία, και **η απάντηση του §12.6**.
 *
 * ⚠️ `encodeURIComponent` παρότι οι enterprise ταυτότητες είναι ασφαλείς χαρακτήρες:
 * η ταυτότητα έρχεται από **δεδομένα**, και μια διεύθυνση που σπάει σε ένα `#` θα
 * αστοχούσε σιωπηλά σε ένα μόνο έγγραφο — ίδιο σκεπτικό με το `listingDetailHref`.
 */
export function demandDetailHref(demandId: string) {
  return typedHref(`${DEMAND_DETAIL_ROUTE_BASE}/${encodeURIComponent(demandId)}`);
}

/**
 * ADR-888 — η παράμετρος που κουβαλά την **αναζήτηση** (το query του χάρτη αποτελεσμάτων) προς τη φόρμα.
 *
 * 🔑 **Ο σύνδεσμος είναι ο φορέας, όχι sessionStorage**: ανανέωση, νέα καρτέλα ή αποστολή του συνδέσμου
 * ανοίγουν την **ίδια** προσυμπληρωμένη φόρμα. Το περιεχόμενο είναι ακριβώς το `serializeListingFilters`.
 */
export const NEW_DEMAND_FROM_SEARCH_PARAM = 'from' as const;

/**
 * ADR-777 §8.98 — η απάντηση του **πρώτου βήματος** («Πότε το θέλεις;»). Ζει στον σύνδεσμο για τον
 * ίδιο λόγο με το `from`: με «πίσω», ανανέωση ή νέα καρτέλα ανοίγει το ίδιο βήμα. Χωρίς αυτήν, η σελίδα
 * δείχνει τον επιλογέα. Με αυτήν, δείχνει τη φόρμα με το «πότε» ήδη απαντημένο.
 */
export const NEW_DEMAND_TIMING_PARAM = 'when' as const;

/**
 * Το δεύτερο βήμα: η ίδια διεύθυνση με το `?when=` γραμμένο. Τυχόν `from` (ADR-888) **κρατιέται**,
 * ώστε η αναζήτηση από τον χάρτη να περνά και από την ερώτηση του χρόνου.
 */
export function newDemandWithTimingHref(timing: DemandTimingKind, currentQuery: string) {
  const params = new URLSearchParams(currentQuery);
  params.set(NEW_DEMAND_TIMING_PARAM, timing);
  return typedHref(`${NEW_DEMAND_ROUTE}?${params.toString()}`);
}

/** «Περισσότερες ρυθμίσεις» από το παράθυρο αποθήκευσης — η φόρμα, προσυμπληρωμένη από την αναζήτηση. */
export function newDemandFromSearchHref(searchQuery: string) {
  const params = new URLSearchParams({ [NEW_DEMAND_FROM_SEARCH_PARAM]: searchQuery });
  return typedHref(`${NEW_DEMAND_ROUTE}?${params.toString()}`);
}

/**
 * ADR-888 — «άνοιξε το παράθυρο αποθήκευσης» στη σελίδα αποτελεσμάτων. Επιβιώνει τη διαδρομή σύνδεσης
 * (`loginHref` κρατά το query), ώστε ο ανώνυμος που πάτησε «Αποθήκευση» να επιστρέψει **με ανοιχτό** το
 * παράθυρο. Δεν είναι φίλτρο: αφαιρείται πριν η αναζήτηση γίνει ζήτηση.
 */
export const SAVE_SEARCH_INTENT_PARAM = 'save' as const;
