/**
 * **Πόσα ξέρουμε για το τι θέλει να κάνει ο ιδιοκτήτης** — κλειστό σύνολο.
 *
 * 🔑 **Τρεις τιμές, και η τρίτη ΔΕΝ είναι για πληρότητα — είναι μετρημένη.** Ο
 * πειρασμός ήταν δύο (`offered` / `dormant`), αλλά ο **παλαιός** αγωγός μπορεί να
 * παραγάγει ακίνητο **χωρίς είδος διάθεσης** και **με τιμή**: το
 * `projectedOfferKinds` πέφτει πίσω στο `commercialStatus`, και ένα `unavailable`
 * δίνει `offerKinds: []` ενώ το `commercial.askingPrice` **επιβιώνει** από τα παλιά
 * πεδία (`types/property.ts` γρ. 117/120, μετανάστευση **ανοιχτή** — ADR-777 §8.5α α).
 *
 * ⚠️ Με δύο τιμές, εκείνο το ακίνητο θα λογιζόταν `dormant` και η τιμή του θα
 * **αγνοούνταν** — δηλαδή θα λέγαμε στον ιδιοκτήτη ότι τον ζητούν άνθρωποι που **δεν
 * φτάνουν** τα λεφτά που ο ίδιος έχει ήδη γράψει. Ο ισχυρισμός θα ήταν **ψευδής**, και
 * θα φαινόταν πιο γενναιόδωρος.
 */
export const INTEREST_STANCES = ['offered', 'partial', 'dormant'] as const;

export type InterestStance = (typeof INTEREST_STANCES)[number];

/**
 * **Ποια στάση έχει αυτό το ακίνητο** — ταξινομητής που **επιστρέφει όνομα**.
 *
 * ⚠️ **Ποτέ boolean.** Ένα `isDormant()` θα ένωνε το `partial` με τη μία ή την άλλη
 * πλευρά **σιωπηλά**, και η σιωπηλή ένωση είναι ακριβώς ο τρόπος που ένας κάδος
 * εξαφανίζεται χωρίς να το δει κανείς (μάθημα CHECK 3.44: *ταξινομητής που επιστρέφει
 * όνομα κάνει τη σιωπηλή απόρριψη **αδύνατη***).
 *
 * ⚠️ **Η τιμή ρωτιέται από τον ΥΠΑΡΧΟΝΤΑ SSoT** ({@link getEffectivePrice}, 23
 * καταναλωτές), ποτέ διαβάζοντας `commercial.askingPrice` κατευθείαν: εκείνος ξέρει
 * ήδη αν κοιτάζει πώληση ή ενοίκιο, και μια δεύτερη ανάγνωση εδώ θα ήταν **δεύτερη
 * μηχανή επιλογής τιμής** — ακριβώς αυτό που το `PublicListing` αρνήθηκε να γεννήσει.
 */
export function stanceOfListing(listing: PublicListing): InterestStance {
  if (listing.offerKinds.length > 0) return 'offered';
  return getEffectivePrice(listing)?.amount == null ? 'dormant' : 'partial';
}

/**
 * 🔴 **ΟΙ ΑΞΟΝΕΣ ΠΟΥ ΔΕΝ ΕΧΟΥΝ ΔΗΛΩΘΕΙ — κλειστό `Record`, ανά στάση.**
 *
 * Ένα εμπόδιο σε αυτή τη λίστα **δεν σημαίνει «δεν ταιριάζει»**· σημαίνει «*δεν το
 * έχει πει ακόμη κανείς*». Δεν αγνοείται — **λογίζεται** ονομαστικά
 * ({@link PlaceInterestCensus.undeclaredAxes}), ώστε η οθόνη να ξέρει **γιατί** ο
 * ισχυρισμός είναι πιο αδύναμος.
 *
 * 🔑 **`Record` πάνω στο κλειστό σύνολο, επίτηδες**: τέταρτη στάση **δεν
 * μεταγλωττίζεται** μέχρι κάποιος να αποφασίσει ρητά τι είναι δηλωμένο σε αυτήν. Ίδιο
 * ιδίωμα με το `DEMAND_DISCLOSURE` — και εκεί το σχόλιο το λέει: *«τρίτο ακροατήριο
 * δεν μεταγλωττίζεται μέχρι κάποιος να αποφασίσει ρητά τι μαθαίνει»*.
 *
 * ⚠️ **Το `partial` συγχωρεί ΜΟΝΟ το είδος διάθεσης.** Η τιμή του **υπάρχει**, άρα ένα
 * `price-above` εκεί είναι **αληθινή ασυμφωνία** και οφείλει να μετρήσει ως τέτοια.
 *
 * ⚠️ **Το `availability-unknown` ΔΕΝ είναι εδώ, σε καμία στάση — και είναι απόφαση.**
 * Είναι **ορθογώνιο** δηλωμένο κενό (`demand-match-vocabulary.ts`: η διαθεσιμότητα δεν
 * αντλείται ακόμη από το BIM) και ισχύει **εξίσου** για δημοσιευμένη αγγελία. Αν το
 * συγχωρούσαμε εδώ, το κενό θα φαινόταν κλειστό **μόνο** σε αυτή τη διαδρομή — δηλαδή
 * θα κρυβόταν, αντί να μετρηθεί. Συνέπεια, δηλωμένη: μια ζήτηση **Ζ2** («*από Μάρτιο
 * 2027*») **δεν** μετράει σε κανένα ακίνητο, και ο λόγος **φαίνεται** στη λογιστική.
 */
const UNDECLARED_AXES: Readonly<Record<InterestStance, readonly DemandBlocker[]>> = {
  offered: [],
  partial: ['offer-kind'],
  // 🔴 ADR-777 §8.52 — ΗΤΑΝ ΑΝΤΙΣΤΑΘΜΙΣΗ ΤΟΥ ΨΕΥΔΟΥΣ, ΚΑΙ ΕΠΑΨΕ ΝΑ ΧΡΕΙΑΖΕΤΑΙ.
  //    Έγραφε `price-above`/`price-below` επειδή η μηχανή έβγαζε **αυτά** για αγγελία
  //    **χωρίς τιμή** — δηλαδή αυτό το αρχείο **συγχωρούσε από κάτω** έναν ισχυρισμό
  //    που δεν έπρεπε να είχε γίνει από πάνω. Τώρα η ίδια αγγελία βγάζει
  //    `price-undeclared`, που λέει την αλήθεια, και η συγχώρεση γίνεται **ονομαστική**.
  //    ⚠️ Τα δύο παλιά ΑΦΑΙΡΕΘΗΚΑΝ και δεν είναι παράλειψη: μια `dormant` αγγελία
  //    (`getEffectivePrice() == null`) **δεν μπορεί πια** να παραγάγει `price-above` —
  //    θα ήταν νεκρές εγγραφές που κρύβουν την επόμενη παλινδρόμηση στο ίδιο σημείο.
  dormant: ['offer-kind', 'price-undeclared'],
};

/** `true` αν **κάθε** εμπόδιο οφείλεται σε άξονα που ο ιδιοκτήτης δεν έχει δηλώσει. */
function onlyUndeclared(blockers: readonly DemandBlocker[], stance: InterestStance): boolean {
  const undeclared = UNDECLARED_AXES[stance];
  return blockers.every((blocker) => undeclared.includes(blocker));
}

// =============================================================================
// 2. Η ΕΤΥΜΗΓΟΡΙΑ ΑΝΑ ΖΗΤΗΣΗ — ονομασμένη, ποτέ boolean
// =============================================================================

/**
 * Πού κατέληξε **κάθε** ζήτηση. Κλειστό σύνολο, εξαντλητικό.
 *
 * ⚠️ **Η ΣΕΙΡΑ ΤΑΞΙΝΟΜΗΣΗΣ ΕΙΝΑΙ ΣΥΜΒΟΛΑΙΟ, ΟΧΙ ΤΥΧΗ** — ίδιο πρότυπο με το
 * {@link demandExclusionReason}. Μια **αποσυρμένη** ζήτηση που *επίσης* δεν ταιριάζει
 * πρέπει να λογιστεί **`not-countable`**, όχι `mismatch`: αλλιώς η αναφορά θα έλεγε
 * στον ιδιοκτήτη *«δέκα άνθρωποι κοίταξαν και δεν το θέλησαν»* ενώ οι οκτώ **βρήκαν
 * σπίτι πριν μήνες**. Ο ίδιος αριθμός, δύο εντελώς διαφορετικά συμπεράσματα — και το
 * λάθος θα οδηγούσε τον άνθρωπο να ρίξει τιμή που δεν χρειάζεται.
 */
export const DEMAND_INTEREST_OUTCOMES = ['interested', 'not-countable', 'mismatch'] as const;

export type DemandInterestOutcome = (typeof DEMAND_INTEREST_OUTCOMES)[number];

/**
 * **Μία ζήτηση → μία ονομασμένη κατάληξη.**
 *
 * @param nowIso — για τη φρεσκάδα (επιβεβαίωση ≤ 90 ημερών)
 * @param todayDate — ISO `YYYY-MM-DD`, **μόνο** για τον χρονικό άξονα του ταιριάσματος
 */
export function classifyDemandInterest(
  demand: PropertyDemand,
  facts: ListingMatchFacts,
  stance: InterestStance,
  nowIso: string,
  todayDate: string,
): DemandInterestOutcome {
  // Πρώτα «μετράει καθόλου;», μετά «ταιριάζει;» — βλ. το συμβόλαιο σειράς παραπάνω.
  if (demandExclusionReason(demand, nowIso) !== null) return 'not-countable';

  const match = matchDemandAgainstListing(demand, facts, todayDate);
  if (match.verdict === 'match') return 'interested';

  return onlyUndeclared(match.blockers, stance) ? 'interested' : 'mismatch';
}

// =============================================================================
// 3. Η ΛΟΓΙΣΤΙΚΗ — κλειστή, fail-closed
// =============================================================================

/**
 * Πού πήγε **κάθε** ζήτηση που εξετάστηκε.
 *
 * 🔴 **Για ΕΜΑΣ, ποτέ για τον ιδιοκτήτη** — ίδιο συμβόλαιο με το `DemandCensus`: το
 * `interested` είναι ο **ωμός** αριθμός, ακριβώς αυτό που το κατώφλι υπάρχει για να
 * κρύψει όταν χρειάζεται. Ένα αντικείμενο λογιστικής που ταξιδεύει δίπλα σε λογοκριμένη
 * τιμή **ακυρώνει** τη λογοκρισία, και θα φαινόταν σωστό.
 *
 * ⚠️ **Κάθε κάδος υπάρχει ακόμη και στο μηδέν** (μάθημα CHECK 3.48 `Κ6`) — ο τύπος το
 * κάνει **αδύνατο** να λείψει.
 */
export interface PlaceInterestCensus {
  /** Πόσες μετρήθηκαν ως ενδιαφέρον. */
  readonly interested: number;
  /** Πόσες δεν μετράνε καθόλου (μη ζωντανές · ανεπιβεβαίωτες · μπαγιάτικες). */
  readonly notCountable: number;
  /** Πόσες είναι ζωντανές και **πραγματικά** δεν ταιριάζουν. */
  readonly mismatch: number;
  /** Πόσες εξετάστηκαν συνολικά. */
  readonly considered: number;
  /**
   * Οι άξονες που **συγχωρέθηκαν** επειδή δεν έχουν δηλωθεί — για **αυτή** τη στάση.
   *
   * 🔑 Χωρίς αυτό, το «3 ψάχνουν κάτι σαν αυτό» και το «3 ζητούν αυτό» θα ήταν
   * **αδιάκριτα** στον καταναλωτή, και ο αδύναμος ισχυρισμός θα φορούσε τη βεβαιότητα
   * του δυνατού. **Κενός πίνακας = τίποτα δεν συγχωρέθηκε = πλήρης κρίση.**
   */
  readonly undeclaredAxes: readonly DemandBlocker[];
}

/** Κλείνει το άθροισμα; Υπάρχει **για να αποτύχει θορυβωδώς**, όχι για να επιβεβαιώνει. */
export function placeInterestCensusBalances(census: PlaceInterestCensus): boolean {
  return (
    census.interested + census.notCountable + census.mismatch === census.considered
  );
}

