/**
 * **Ό,τι, και μόνο ό,τι, μαθαίνει ο ιδιοκτήτης.**
 *
 * ⚠️ **Καμία ταυτότητα, κανένα κριτήριο, καμία ημερομηνία, κανένα ποσό.** Το §12.7(α)
 * απαγορεύει κάθε διαδρομή που γίνεται **εργαλείο πίεσης**, και μια λίστα κριτηρίων
 * είναι ακριβώς αυτό στα χέρια ιδιοκτήτη που ξέρει τους γείτονές του.
 *
 * ⛔ **ΤΟ {@link PlaceInterestCensus} ΔΕΝ ΤΑΞΙΔΕΥΕΙ ΜΑΖΙ.** Δες την προειδοποίηση εκεί.
 */
export interface PlaceInterest {
  /** Πόσο δηλωμένο είναι το ακίνητο — **αλλάζει τι σημαίνει ο αριθμός**. */
  readonly stance: InterestStance;
  /**
   * Ο αριθμός, **ήδη λογοκριμένος** από το κατώφλι του `place-owner`.
   *
   * `count === null` σημαίνει *«δεν το λέμε»*, **όχι** *«κανένας»* — και η οθόνη
   * οφείλει να τα ξεχωρίζει.
   */
  readonly disclosure: DemandDisclosure;
}

/**
 * 🔴 **Η ΜΟΝΗ διαδρομή από τη ζήτηση προς τον ΙΔΙΟΚΤΗΤΗ ενός ακινήτου.**
 *
 * Ο κανόνας Firestore δίνει `read` στο `property_demands` **μόνο** στον
 * `authorUserId`· άρα, όπως και το `/api/demand/competition`, αυτό τρέχει
 * **αποκλειστικά στον διακομιστή**, πάνω σε δεδομένα που ο πελάτης **δομικά** δεν
 * βλέπει.
 *
 * 🔑 **Το κατώφλι εφαρμόζεται ΜΟΝΟ από το {@link discloseDemand}** — δεν
 * ξαναγράφεται εδώ ούτε ως `>= 1`. Η πολιτική (`DEMAND_DISCLOSURE['place-owner']`,
 * `minCount: 1`, με **γραπτή απόφαση Giorgio 2026-08-11**) είχε ως σήμερα **μηδέν
 * καταναλωτές**· αυτή η γραμμή είναι ο πρώτος (ADR-749 §5 — αδρανής φρουρός).
 *
 * @param facts — το ακίνητο του ιδιοκτήτη, **προβεβλημένο στη μνήμη** (βλ.
 *   `projectListingShape` — για κλειστό ακίνητο **δεν υπάρχει** δημόσια αγγελία)
 * @param demands — οι υποψήφιες ζητήσεις, ήδη επιλεγμένες από το ερώτημα του καλούντος
 * @param nowIso — η στιγμή αναφοράς· **ρητή παράμετρος**, κανείς δεν διαβάζει το ρολόι
 * @param todayDate — ISO `YYYY-MM-DD` για τον χρονικό άξονα
 */
export function discloseInterest(
  facts: ListingMatchFacts,
  demands: readonly PropertyDemand[],
  nowIso: string,
  todayDate: string,
): { readonly interest: PlaceInterest; readonly census: PlaceInterestCensus } {
  const stance = stanceOfListing(facts.listing);
  const { interested, census } = tallyInterest(facts, demands, stance, nowIso, todayDate);

  // 🔴 Άγνωστη κατάσταση ⇒ `throw` **με όνομα**. Είναι σφάλμα προγράμματος, όχι
  // αποτέλεσμα τομέα — και το repo έχει κανόνα γι' αυτό (CHECK 3.39 · 3.44 · 3.47).
  if (!placeInterestCensusBalances(census)) {
    throw new Error(
      `demand-interest: ασυνεπής λογιστική — ${census.interested}+${census.notCountable}+` +
        `${census.mismatch} ≠ ${census.considered}`,
    );
  }

  return {
    interest: {
      stance,
      // ⚠️ Οι ήδη ταξινομημένες περνούν **ξανά** από το `discloseDemand`, και είναι
      // σκόπιμο: το κατώφλι έχει **έναν** τόπο. Η δεύτερη απογραφή είναι ταυτοτική
      // (τα `not-countable` έχουν ήδη φύγει), άρα δεν υπάρχει διπλομέτρηση — υπάρχει
      // **ένας** κριτής.
      disclosure: discloseDemand(interested, 'place-owner', nowIso),
    },
    census,
  };
}

/**
 * Ο βρόχος που **ταξινομεί** — χωριστά από την αποκάλυψη που **λογοκρίνει**.
 *
 * 🔑 Επιστρέφει **και** τις ίδιες τις ζητήσεις **και** τη λογιστική: ο καλών χρειάζεται
 * τις πρώτες για το κατώφλι και τη δεύτερη για να **κλείσει το άθροισμα**. Μια εκδοχή
 * που επέστρεφε μόνο αριθμούς θα ανάγκαζε δεύτερο πέρασμα — δηλαδή **δεύτερο κριτή**
 * για ερώτηση που μόλις απαντήθηκε (ADR-749).
 */
function tallyInterest(
  facts: ListingMatchFacts,
  demands: readonly PropertyDemand[],
  stance: InterestStance,
  nowIso: string,
  todayDate: string,
): { readonly interested: readonly PropertyDemand[]; readonly census: PlaceInterestCensus } {
  const interested: PropertyDemand[] = [];
  let notCountable = 0;
  let mismatch = 0;

  for (const demand of demands) {
    const outcome = classifyDemandInterest(demand, facts, stance, nowIso, todayDate);
    if (outcome === 'interested') interested.push(demand);
    else if (outcome === 'not-countable') notCountable += 1;
    else mismatch += 1;
  }

  return {
    interested,
    census: {
      interested: interested.length,
      notCountable,
      mismatch,
      considered: demands.length,
      undeclaredAxes: UNDECLARED_AXES[stance],
    },
  };
}
