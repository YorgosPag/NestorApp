/**
 * @fileoverview **ΤΟ ΔΟΛΩΜΑ ΤΟΥ §12.6** — «12 άνθρωποι ζητούν το κατάστημά σας».
 * @related ADR-777 §7 (Α9 · Α12) · SPEC-777A §14.2 (επίπεδο Γ) · SPEC-777B §12.6 · §12.7
 * @module lib/demand/demand-interest
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΕΙΝΑΙ ΑΥΤΟ, ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΔΕΥΤΕΡΗ ΜΗΧΑΝΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `demand-matching.ts` απαντά *«ταιριάζει **αυτή η αγγελία** σε **αυτή τη
 * ζήτηση**;»* — **ένα ζευγάρι τη φορά**. Η οθόνη του ζητούντα το καλεί με **μία**
 * ζήτηση και **πολλές** αγγελίες. Ο ιδιοκτήτης ρωτά το **ίδιο ερώτημα ανάποδα**: μία
 * αγγελία, πολλές ζητήσεις.
 *
 * 🔑 **Άρα δεν χρειάζεται νέο κριτήριο — χρειάζεται ανάποδος βρόχος.** Το κατώφλι
 * αποκάλυψης το εφαρμόζει το **υπάρχον** {@link discloseDemand}· η ετυμηγορία έρχεται
 * από το **υπάρχον** {@link matchDemandAgainstListing}· η φρεσκάδα/απόδοση από το
 * **υπάρχον** {@link demandExclusionReason}. Αυτό το αρχείο προσθέτει **ένα** πράγμα,
 * και μόνο ένα: τη **στάση** του ακινήτου (§ παρακάτω).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΕΥΡΗΜΑ ΠΟΥ ΟΡΙΖΕΙ ΟΛΟ ΤΟ ΑΡΧΕΙΟ: Ο ΑΦΕΛΗΣ ΒΡΟΧΟΣ ΑΠΑΝΤΑ **ΠΑΝΤΑ 0**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το §12.6 ονομάζει το δόλωμα *«πολύ ισχυρότερο κάλεσμα από "ανεβάστε αγγελία"»* —
 * δηλαδή απευθύνεται **εξ ορισμού** σε ιδιοκτήτη που **δεν έχει ανεβάσει αγγελία**.
 * Και ακριβώς εκεί, ο βρόχος πάνω στην υπάρχουσα μηχανή είναι **δομικά τυφλός**
 * (μετρημένο 2026-08-12, `demand-match-axes.ts:47`):
 *
 *   κλειστό κατάστημα ⇒ καμία ζωντανή διάθεση ⇒ `offerKinds: []`
 *   ⇒ `categoryBlockers` → `'offer-kind'` ⇒ **κατηγορικό** ⇒ `no-match`
 *   ⇒ **για ΚΑΘΕ ζήτηση, πάντα** ⇒ «**0 άνθρωποι ζητούν το ακίνητό σας**».
 *
 * 🔑 **Και δεν θα φαινόταν σφάλμα.** Το μηδέν είναι εύλογο, η μηχανή σωστή, κάθε πύλη
 * πράσινη. Είναι το σχήμα «**0 = κανείς δεν κοίταξε**» που κυνηγούν οι CHECK 3.35 ·
 * 3.39 · 3.46 · 3.51 — και εδώ θα το **γράφαμε μόνοι μας**, στο ίδιο commit που
 * ενεργοποιεί τον μηχανισμό ενάντια στον οποίο υπάρχει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 Η ΛΥΣΗ: «**ΔΕΝ ΤΑΙΡΙΑΖΕΙ**» ΚΑΙ «**ΔΕΝ ΤΟ ΕΧΕΙ ΔΗΛΩΣΕΙ**» ΕΙΝΑΙ ΔΥΟ ΠΡΑΓΜΑΤΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ένα εμπόδιο `offer-kind` πάνω σε **αγγελία προς ενοικίαση** που ζητήθηκε **προς
 * πώληση** είναι **πραγματική ασυμφωνία**: ο ιδιοκτήτης δήλωσε, και δεν ταιριάζει.
 *
 * Το **ίδιο** εμπόδιο πάνω σε **κλειστό κατάστημα** δεν λέει τίποτα για την αγορά — λέει
 * ότι **δεν ρωτήθηκε κανείς**. Είναι, κατά γράμμα, η διάκριση `never-asked` ⇄
 * `owner-declined` της **Α5**, μεταφερμένη από τη θέση στη διάθεση.
 *
 * ⚠️ **Η διάκριση ζει στη ΣΤΑΣΗ, όχι σε `if` μέσα στον βρόχο** ({@link INTEREST_STANCES}).
 * Ένα `if (offerKinds.length === 0) skip` θα ήταν **σιωπηλή εξαίρεση**: η οθόνη θα
 * έλεγε την ίδια πρόταση για δύο **διαφορετικούς ισχυρισμούς**, και ο πιο αδύναμος θα
 * φορούσε τη βεβαιότητα του πιο δυνατού.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΠΟΥ ΞΕΠΕΡΝΑΜΕ ΤΟΥΣ ΜΕΓΑΛΟΥΣ — **μετρημένο, όχι ισχυρισμός**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Έρευνα 2026-08-12: **καμία** πύλη ακινήτων δεν λέει στον ιδιοκτήτη ότι τον ψάχνουν.
 * Το πλησιέστερο ανάλογο, το *Make Me Move* της Zillow, δούλευε **ανάποδα** (δήλωνε ο
 * **ιδιοκτήτης** τιμή που θα τον έπειθε) και **καταργήθηκε** — δηλαδή απαιτούσε από τον
 * άνθρωπο να κάνει την πρώτη κίνηση, που είναι ακριβώς το εμπόδιο. Το Rightmove
 * ειδοποιεί σε **μεταβολή που περνά κατώφλι** (μείωση τιμής ≥2%), όχι σε χρονοδιάγραμμα
 * — **σωστό ιδίωμα, λάθος κατεύθυνση**: ειδοποιεί τον **αγοραστή** για την προσφορά,
 * ποτέ τον **πωλητή** για τη ζήτηση.
 *
 * Εδώ η πρώτη κίνηση γίνεται από την **αγορά**, και ο ιδιοκτήτης απαντά.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις. Καμία εξάρτηση από React/Firestore/ρολόι.
 */

