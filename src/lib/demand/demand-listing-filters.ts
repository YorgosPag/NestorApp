import type { ListingFilters } from '@/lib/listings/listing-filters';
import { EMPTY_LISTING_FILTERS } from '@/lib/listings/listing-filters';
import { serializeListingFilters } from '@/lib/listings/listing-filters';
import { searchResultsHref } from '@/lib/listings/listing-routes';
import { geoOutlineBoundingCircle } from '@/lib/geo/geo-ring';
import { distanceMeters } from '@/lib/geo/geo-distance';
import type { GeoPoint } from '@/types/geo/coordinates';
import type { DemandPlace, PropertyDemand } from '@/types/property-demand';

// =============================================================================
// 1. ΟΙ ΑΠΩΛΕΙΕΣ — ονομασμένες, όχι σιωπηλές
// =============================================================================

/**
 * Οι άξονες της ζήτησης που **δεν χωράνε** στα φίλτρα της οθόνης 2.
 *
 * 🔑 **Κλειστό σύνολο, και είναι το συμβόλαιο ανάμεσα σε δύο αρχεία.** Η μηχανή
 * ταιριάσματος οφείλει να ελέγξει **ακριβώς αυτά** πέρα από τα φίλτρα· ένας νέος
 * άξονας που θα προστεθεί στη ζήτηση και **δεν** θα μπει εδώ θα ήταν άξονας που
 * **κανείς δεν ελέγχει** — και η μόνη ένδειξη θα ήταν αποτελέσματα που φαίνονται
 * λίγο πιο γενναιόδωρα απ' όσο πρέπει.
 *
 * ⚠️ Το **πλαίσιο ζωής** (Ζ7) **δεν είναι εδώ, και δεν πρόκειται να μπει.** Δεν
 * «χάνεται στην προβολή» — **δεν ήταν ποτέ κριτήριο** (βλ. `DemandLifeContext`). Αν
 * εμφανιζόταν σε αυτή τη λίστα, θα υπονοούσε ότι η μηχανή οφείλει να το ελέγξει.
 */
export const DEMAND_AXES_LOST_IN_FILTERS = [
  /** **Ζ2/Ζ3** — τα φίλτρα ρωτούν «τι υπάρχει», ποτέ «τι θα υπάρχει τότε». */
  'timing',
  /** **Ζ4** — το σχήμα γίνεται κύκλος· ο κύκλος περισσεύει. */
  'area-outline',
  /** **Ζ3/Ζ5** — «αυτό το κτίριο». Καμία παράμετρος διεύθυνσης δεν το εκφράζει. */
  'place-identity',
  /** **Ζ5** — ο όροφος. Το `ListingFilters` δεν έχει άξονα ορόφου (μετρημένο). */
  'floor-range',
  /** **Ζ6** — «σχολείο ≤ 500 μ.». Απαιτεί άντληση σημείων ενδιαφέροντος. */
  'proximity',
] as const;

export type DemandAxisLostInFilters = (typeof DEMAND_AXES_LOST_IN_FILTERS)[number];

/**
 * Ποιοι άξονες χάνονται **για αυτή τη συγκεκριμένη ζήτηση**.
 *
 * 🔑 **Μόνο όσοι είναι όντως δηλωμένοι.** Μια ζήτηση «τώρα, οπουδήποτε, ως 250.000»
 * δεν χάνει **τίποτα** — και το να της λέμε «τα αποτελέσματα αγνοούν τον χρόνο και τη
 * γειτονιά» θα ήταν **ψευδής προειδοποίηση**, δηλαδή θόρυβος που εκπαιδεύει τον
 * χρήστη να αγνοεί τις αληθινές.
 *
 * Ο καταναλωτής είναι η οθόνη: *«βλέπεις 12 αποτελέσματα — ο σύνδεσμος αγνοεί τον
 * **χρόνο** και τη **γειτονιά** που ζήτησες»*. Είναι η **κλειστή λογιστική** της Α5
 * («*14 ακίνητα · 11 στον χάρτη · 3 χωρίς θέση*») εφαρμοσμένη στα κριτήρια αντί για
 * τα αποτελέσματα.
 */
export function axesLostProjectingDemand(
  demand: Pick<PropertyDemand, 'place' | 'timing' | 'features' | 'proximity'>,
): DemandAxisLostInFilters[] {
  const lost: DemandAxisLostInFilters[] = [];

  if (demand.timing.kind !== 'now') lost.push('timing');
  if (demand.place.kind === 'area') lost.push('area-outline');
  if (demand.place.kind === 'place') lost.push('place-identity');
  if (demand.features.floorMin !== null || demand.features.floorMax !== null) {
    lost.push('floor-range');
  }
  if (demand.proximity.length > 0) lost.push('proximity');

  return lost;
}

// =============================================================================
// 2. Ο ΧΩΡΙΚΟΣ ΑΞΟΝΑΣ — το μόνο σημείο που χρειάζεται γεωμετρία
// =============================================================================

/** Ο τύπος του `near` μέσα στο {@link ListingFilters}, χωρίς να ξαναγραφτεί. */
type ProjectedGeo = ListingFilters['near'];

/** Απόσταση σε μέτρα, μέσω του **μοναδικού** SSoT απόστασης του έργου. */
function metresBetween(a: GeoPoint, b: GeoPoint): number {
  return distanceMeters(a, b);
}

/**
 * Χωρικός άξονας ζήτησης → γεωγραφικό φίλτρο οθόνης.
 *
 * ⚠️ **Το `place` δίνει `null`, δηλαδή «καμία γεωγραφική στένωση» — και είναι σωστό,
 * όχι παράλειψη.** Η θέση της γης ζει στο **επίπεδο Α**, σε άλλο έγγραφο· μια καθαρή
 * συνάρτηση πάνω στη ζήτηση **δεν την ξέρει**. Θα μπορούσε να τη δεχτεί ως παράμετρο,
 * αλλά τότε η προβολή θα **στένευε** με βάση δεδομένο που ο καλών μπορεί να μην έχει
 * — και μια στένωση που εξαρτάται από το αν κάποιος θυμήθηκε να περάσει κάτι είναι
 * ακριβώς η σιωπηλή απώλεια που το συμβόλαιο «υπερσύνολο» απαγορεύει. Η ταυτότητα του
 * ακινήτου κρίνεται στη **μηχανή**, όπου η λίστα απωλειών τη στέλνει.
 */
function projectPlace(place: DemandPlace): ProjectedGeo {
  switch (place.kind) {
    case 'anywhere':
    case 'place':
      return null;
    case 'near':
      return { center: place.center, radiusKm: place.radiusKm };
    case 'area':
      return geoOutlineBoundingCircle(place.outline, metresBetween);
  }
}

// =============================================================================
// 3. Η ΠΡΟΒΟΛΗ
// =============================================================================

/**
 * **Ζήτηση → φίλτρα οθόνης 2.**
 *
 * 🔑 **Ο άξονας διάθεσης είναι ΤΑΥΤΟΤΗΤΑ, όχι μετάφραση**: το `seeks` είναι ήδη
 * `OfferKind[]`, το **ίδιο** κλειστό σύνολο που φιλτράρει η οθόνη — επειδή το
 * `schema.org/Demand` ορίζει ότι *«the very same properties used for Offer apply»*.
 * Αν η ζήτηση είχε δικό της λεξιλόγιο, **εδώ** θα ζούσε ένας πίνακας μετάφρασης, και
 * εκεί θα γεννιόταν η επόμενη απόκλιση.
 *
 * ⚠️ **Ο όροφος ΔΕΝ γράφεται** — το `ListingFilters` δεν τον έχει. Δηλώνεται ως
 * `floor-range` στις απώλειες, ώστε να μην είναι σιωπηλή παράλειψη που κάποιος θα
 * ανακαλύψει βλέποντας ισόγεια σε αναζήτηση για 3ο όροφο.
 */
export function listingFiltersFromDemand(demand: PropertyDemand): ListingFilters {
  return {
    ...EMPTY_LISTING_FILTERS,
    offerKinds: demand.seeks,
    types: demand.features.types,
    priceMin: demand.features.priceMin,
    priceMax: demand.features.priceMax,
    areaMin: demand.features.areaMin,
    areaMax: demand.features.areaMax,
    bedroomsMin: demand.features.bedroomsMin,
    near: projectPlace(demand.place),
  };
}

/**
 * Η διεύθυνση της οθόνης 2 **για αυτή τη ζήτηση** — «*δες τι υπάρχει σήμερα*».
 *
 * 🔑 **Καμία νέα λογική διαδρομών.** Είναι σύνθεση τριών υπαρχόντων SSoT
 * ({@link listingFiltersFromDemand} → `serializeListingFilters` → `searchResultsHref`),
 * και γι' αυτό ο σύνδεσμος είναι **ταυτόσημος** με ό,τι θα παρήγαγε ο χρήστης
 * ρυθμίζοντας τα φίλτρα με το χέρι. Δύο διαδρομές προς την ίδια οθόνη που
 * παρήγαγαν διαφορετική διεύθυνση θα ήταν δύο σελίδες με το ίδιο περιεχόμενο.
 *
 * ⚠️ **Ο σύνδεσμος είναι ΠΙΟ ΠΛΑΤΥΣ από τη ζήτηση** όποτε το
 * {@link axesLostProjectingDemand} επιστρέφει κάτι. Η οθόνη που τον δείχνει
 * **οφείλει** να το πει — αλλιώς ο χρήστης διαβάζει τα αποτελέσματα ως απάντηση στο
 * αίτημά του, ενώ είναι απάντηση σε **χαλαρότερο** αίτημα.
 */
export function demandResultsHref(demand: PropertyDemand) {
  const filters = listingFiltersFromDemand(demand);
  return searchResultsHref(serializeListingFilters(filters).toString());
}
