/**
 * **Γιατί του το λέμε** — οι ζητήσεις του ίδιου ανθρώπου που ταιριάζουν στην ίδια αγγελία.
 *
 * 🔴 **Το εύρημα (ζωντανή δοκιμή 2026-09-15, §8.69.11 #1)**: δύο ζητήσεις του ίδιου χρήστη
 * ταίριαζαν στην ίδια αγγελία ⇒ κλειδί **ανά ζήτηση** ⇒ **δύο** ειδοποιήσεις για **μία**
 * μείωση, και η σύνοψη έδειξε την ίδια γραμμή δύο φορές. Τα portals (Zillow, Rightmove,
 * idealista) κάνουν ακριβώς αυτό — ένα μήνυμα ανά αποθηκευμένη αναζήτηση. Η υποδομή
 * ειδοποιήσεων (Knock, Novu) λέει το αντίθετο: **το θέμα είναι η ταυτότητα, οι αιτίες είναι
 * περιεχόμενο**. Εδώ οι ζητήσεις γίνονται **λόγοι μέσα** στην ειδοποίηση.
 *
 * ⚠️ `demandIds`, `seeks` και `names` είναι **παράλληλοι** πίνακες, ταξινομημένοι κατά ζήτηση.
 *
 * 🏆 **ADR-887 — `names`**: το όνομα κάθε ζήτησης (`demandDisplayName`), αποδοσμένο **τη στιγμή της
 * αποστολής** στη γλώσσα του παραλήπτη. Στιγμιότυπο, όπως ο τίτλος της αγγελίας: η ειδοποίηση είναι
 * ιστορικό γεγονός («ταίριαξε στο Χ τότε»). Κενός για θέμα **μόνο** αποθήκευσης (§8.74).
 *
 * 🔴 **ADR-777 §8.60.15 — ήταν `priceMaxes: (number | null)[]`**: ένα αμονάδιστο όριο ανά
 * ζήτηση ⇒ μείωση **ενοικίου** από 1.100 σε 950 €/μήνα κρινόταν απέναντι σε όριο **πώλησης**
 * 250.000 € και έβγαινε «εντός προϋπολογισμού». Τώρα κρατιούνται οι **εναλλακτικές**, και το όριο
 * διαλέγεται **στη μονάδα της μείωσης** ({@link strongestBudgetVerdict}).
 */
export interface AnnouncementReasons {
  readonly demandIds: readonly string[];
  readonly seeks: readonly (readonly DemandSeek[])[];
  readonly names: readonly string[];
}

/**
 * **Το κλειδί ταιριάσματος ανά (παραλήπτη, αγγελία).** Ο παραλήπτης μπαίνει ήδη στο
 * `dedupeKey` από τον orchestrator (`${type}:${recipient}:${eventId}`), άρα εδώ φτάνει η αγγελία.
 *
 * 🔑 **Δεν συγκρούεται ποτέ με το legacy {@link demandListingMatchEventId}**: εκείνο αρχίζει
 * από το `dmnd_…` της ζήτησης, αυτό από το σταθερό `listing:`.
 */
export function recipientListingMatchEventId(listingId: string): string {
  return `listing:${listingId}`;
}

/** **Το κλειδί μιας μείωσης ανά (παραλήπτη, αγγελία, μείωση)** — ποσό **και** στιγμή, όπως πριν. */
export function recipientPriceDropEventId(
  listingId: string,
  reduction: Pick<PriceReduction, 'to' | 'since'>,
): string {
  return `${recipientListingMatchEventId(listingId)}:price-drop:${reduction.to}@${reduction.since}`;
}

/** Η ετυμηγορία προϋπολογισμού για **όλους** τους λόγους μαζί. */
export type BudgetVerdict =
  /** `reasonIndex` — **ποιας** ζήτησης είναι το όριο (δείκτης στους παράλληλους πίνακες των λόγων, ADR-887). */
  | { readonly kind: 'into-budget'; readonly priceMax: number; readonly reasonIndex: number }
  | { readonly kind: 'within-budget' };

/**
 * **Ο ένας κριτής της διατύπωσης** — αν για **οποιαδήποτε** ζήτηση η μείωση είναι
 * `'into-budget'`, αυτή κερδίζει, με το **αυστηρότερο** (χαμηλότερο) όριο από όσα την κάνουν
 * `'into-budget'`. Το «πόσο κάτω από το όριο» λέγεται έτσι με τον **μικρότερο** αριθμό —
 * ποτέ υπόσχεση μεγαλύτερου περιθωρίου απ' ό,τι έχει ο άνθρωπος.
 */
export function strongestBudgetVerdict(
  seeksPerDemand: readonly (readonly DemandSeek[])[],
  reduction: Pick<PriceReduction, 'from' | 'to' | 'role'>,
): BudgetVerdict {
  let strictest: { priceMax: number; reasonIndex: number } | null = null;
  for (let reasonIndex = 0; reasonIndex < seeksPerDemand.length; reasonIndex += 1) {
    // 🔑 Το όριο **του ρόλου της μείωσης** — ζήτηση χωρίς εναλλακτική σε αυτή τη μονάδα δεν έχει όριο εδώ.
    const priceMax = amountRangeOfRole(seeksPerDemand[reasonIndex], reduction.role)?.max ?? null;
    if (priceMax === null || priceDropKind(priceMax, reduction) !== 'into-budget') continue;
    // Ισοπαλία ⇒ η πρώτη κατά σειρά λόγων: ντετερμινιστικό όνομα για ίδια είσοδο.
    if (strictest === null || priceMax < strictest.priceMax) strictest = { priceMax, reasonIndex };
  }
  return strictest === null ? { kind: 'within-budget' } : { kind: 'into-budget', ...strictest };
}

/**
 * **Τι ξέρει ήδη ο ζητών για αυτή την αγγελία** — από την **ήδη γραμμένη** ειδοποίηση
 * ταιριάσματος, ποτέ από δεύτερο πεδίο «πότε του το είπαμε» (§8.22.6).
 *
 * ⚠️ `atMs: null` = η ειδοποίηση **υπάρχει** αλλά η στιγμή της δεν διαβάζεται. Τότε η
 * κρίση πάει προς τη **σιωπή**: μια μείωση που ίσως είχε ήδη αναφερθεί δεν ξαναλέγεται.
 */
export type MatchHistory =
  | { readonly kind: 'never-announced' }
  | { readonly kind: 'announced'; readonly atMs: number | null };

/** Η ετυμηγορία για μια μείωση — ονομασμένη, ποτέ boolean. */
export type PriceDropVerdict = 'announce' | 'predates-match' | 'stale';

/**
 * **Αξίζει να πούμε αυτή τη μείωση;**
 *
 * | Κατάσταση | Ετυμηγορία | Γιατί |
 * |---|---|---|
 * | η σήμανση έληξε (30 ημέρες) | `stale` | παλιά είδηση δεν είναι είδηση |
 * | ο ζητών δεν έμαθε ποτέ για την αγγελία | `announce` | είναι η πρώτη του είδηση |
 * | το ταίριασμα ανακοινώθηκε **πριν** τη μείωση | `announce` | η τιμή που ξέρει **άλλαξε** |
 * | το ταίριασμα ανακοινώθηκε **μετά** τη μείωση | `predates-match` | το email ταιριάσματος **έδειξε ήδη** τη μειωμένη τιμή |
 */
export function priceDropVerdict(
  reduction: PriceReduction,
  match: MatchHistory,
  nowMs: number,
): PriceDropVerdict {
  if (!isReductionFresh(reduction, nowMs)) return 'stale';
  if (match.kind === 'never-announced') return 'announce';
  if (match.atMs === null) return 'predates-match';
  return Date.parse(reduction.since) > match.atMs ? 'announce' : 'predates-match';
}
