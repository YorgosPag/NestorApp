/**
 * @fileoverview **ΠΟΤΕ ΑΞΙΖΕΙ ΝΑ ΤΟ ΠΟΥΜΕ** — η είδηση, όχι η κατάσταση.
 * @related ADR-777 §7 (Α9) · SPEC-777B §12.6 · server/notifications/notification-orchestrator
 * @module lib/demand/demand-announcement
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΠΡΟΒΛΗΜΑ: «3 ΑΝΘΡΩΠΟΙ ΖΗΤΟΥΝ ΤΟ ΑΚΙΝΗΤΟ ΣΑΣ» ΕΙΝΑΙ **ΚΑΤΑΣΤΑΣΗ**, ΟΧΙ ΓΕΓΟΝΟΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο ιδιοκτήτης πρέπει να **ειδοποιηθεί**· ο αριθμός όμως αλλάζει συνέχεια. Οι τρεις
 * αφελείς πολιτικές αποτυγχάνουν, η καθεμία αλλιώς — και οι δύο πρώτες είναι ακριβώς
 * αυτό που κάνουν τα portal:
 *
 * | Πολιτική | Τι παράγει | Γιατί όχι |
 * |---|---|---|
 * | σε **κάθε νέα ζήτηση** | ένα email ανά καταχώρηση | ο ίδιος τίτλος δέκα φορές· ο άνθρωπος μαθαίνει να τα αγνοεί |
 * | **περιοδικά** (εβδομαδιαία σύνοψη) | email και όταν **δεν άλλαξε τίποτα** | «*ακόμη 3*» δεν είναι είδηση — είναι θόρυβος με πρόγραμμα |
 * | σε **κάθε μεταβολή** | 3→4→5 = τρία email | το +1 δεν αλλάζει καμία απόφαση |
 *
 * 🔑 **Το σωστό ερώτημα δεν είναι «άλλαξε;» αλλά «άλλαξε ΑΡΚΕΤΑ ώστε ο άνθρωπος να
 * κάνει κάτι διαφορετικό;»** Το `1` είναι είδηση («*υπάρχει κιόλας κάποιος*»). Το `12`
 * είναι **άλλη** είδηση («*υπάρχει αγορά*»). Το `4` μετά το `3` **δεν είναι είδηση**.
 *
 * 🏆 **Το ιδίωμα είναι του Rightmove, η κατεύθυνση δική μας.** Εκείνο στέλνει άμεση
 * ειδοποίηση όταν μια τιμή πέσει **≥2%** — κατώφλι πάνω στη **μεταβολή**, ποτέ
 * χρονοδιάγραμμα. Είναι σωστό και είναι **στραμμένο στον αγοραστή**: ειδοποιεί για την
 * **προσφορά**. Εδώ το ίδιο εργαλείο στρέφεται στη **ζήτηση**, που δεν το κάνει κανείς.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 Ο ΑΝΤΙ-SPAM ΜΗΧΑΝΙΣΜΟΣ **ΔΕΝ ΓΡΑΦΤΗΚΕ** — ΕΙΝΑΙ ΤΟ ΥΠΑΡΧΟΝ `dedupeKey`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο {@link dispatchNotification} χτίζει **ντετερμινιστικό** αναγνωριστικό εγγράφου από
 * `(eventType, recipientId, eventId)` και κάνει `create()` — που **αποτυγχάνει αν
 * υπάρχει**. Άρα: αν το `eventId` είναι η **ζώνη** και όχι ο αριθμός, η επανάληψη
 * γίνεται **δομικά αδύνατη**, χωρίς κανένα νέο πεδίο, χωρίς «last notified at», χωρίς
 * δεύτερη συλλογή που θα μπορούσε να παλιώσει.
 *
 * ⚠️ **Ένα «τελευταία ειδοποίηση» πεδίο θα ήταν ΔΕΥΤΕΡΗ ΑΛΗΘΕΙΑ** για κάτι που το
 * σύστημα ειδοποιήσεων **ήδη ξέρει** — το σχήμα του ADR-749, και με τη χειρότερη
 * συνέπεια: δύο γραφές που μπορούν να αποκλίνουν σημαίνει διπλό email ή **κανένα**.
 *
 * 🔶 **ΔΗΛΩΜΕΝΟ ΟΡΙΟ, με λόγο.** Αν η ζήτηση πέσει και **ξαναφτάσει** στην ίδια ζώνη,
 * δεν στέλνεται νέα ειδοποίηση: του το έχουμε ήδη πει, και είναι **το ίδιο γεγονός**.
 * Θεραπεία, αν ποτέ χρειαστεί: χονδρικός κάδος χρόνου στο `eventId` — **όχι** αφαίρεση
 * της ζώνης.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις. Καμία εξάρτηση από Firestore/δίκτυο/ρολόι.
 */

/**
 * 🔴 **ΟΙ ΖΩΝΕΣ — κάθε μία είναι ΑΛΛΗ ΕΙΔΗΣΗ, όχι μεγαλύτερος αριθμός.**
 *
 * Γεωμετρική κλιμάκωση (×~2–2,5): η ανθρώπινη αντίληψη πλήθους είναι **λογαριθμική**,
 * και το πρότυπο το εφαρμόζει ήδη ο ίδιος ο κλάδος (η αύξηση **ποσοστού** του
 * Rightmove, όχι απόλυτου ποσού· η **σχετική** υποχώρηση 15% του `demand-concessions.ts`).
 *
 * - **1** — *«υπάρχει κιόλας κάποιος»*: η **ισχυρότερη** είδηση όλων, γιατί μετατρέπει
 *   το «ίσως κάποτε» σε «τώρα». Είναι το κατώφλι που ο Giorgio διάλεξε ρητά
 *   (`DEMAND_DISCLOSURE['place-owner']`, *«από τον 1ο»*).
 * - **3** — *«δεν ήταν σύμπτωση»*.
 * - **8 · 20 · 50** — *«υπάρχει αγορά»* σε κλίμακες που αλλάζουν **τι θα κάνει**:
 *   κανείς δεν αποφασίζει διαφορετικά στο 21 απ' ό,τι στο 20.
 *
 * ⚠️ **Η σειρά ΕΙΝΑΙ ο μηχανισμός** — γνησίως αύξουσα, όπως η κλίμακα z-index του
 * CHECK 3.50. Δύο ίσες ζώνες θα ήταν δύο ονόματα για ένα σκαλί· φθίνουσα θα έσπαγε
 * το {@link announcementBand}. Ο αυτοέλεγχος παρακάτω το κάνει **αδύνατο σιωπηλά**.
 */
export const ANNOUNCEMENT_BANDS = [1, 3, 8, 20, 50] as const;

/**
 * 🔴 **Αυτοέλεγχος στη φόρτωση του module** — η κλίμακα ελέγχει τον εαυτό της.
 *
 * Μια μη αύξουσα λίστα θα έκανε το {@link announcementBand} να επιστρέφει **λάθος
 * ζώνη σιωπηλά**, δηλαδή θα έστελνε email σε λάθος στιγμές χωρίς κανένα σφάλμα. Ο
 * μεταγλωττιστής **δεν έχει γνώμη** για τη σειρά αριθμών σε πίνακα — ίδιο μάθημα με
 * τον αυτοέλεγχο διάταξης του CHECK 3.50.
 */
for (let index = 1; index < ANNOUNCEMENT_BANDS.length; index += 1) {
  if (ANNOUNCEMENT_BANDS[index] <= ANNOUNCEMENT_BANDS[index - 1]) {
    throw new Error(
      `demand-announcement: οι ζώνες ΠΡΕΠΕΙ να είναι γνησίως αύξουσες — ` +
        `${ANNOUNCEMENT_BANDS[index - 1]} → ${ANNOUNCEMENT_BANDS[index]}`,
    );
  }
}

export type AnnouncementBand = (typeof ANNOUNCEMENT_BANDS)[number];

/**
 * **Σε ποια ζώνη πέφτει αυτό το πλήθος** — ή `null` όταν δεν αξίζει να ειπωθεί.
 *
 * ⚠️ `null` σημαίνει *«καμία είδηση»*, **όχι** *«σφάλμα»*: πλήθος κάτω από την πρώτη
 * ζώνη είναι ακριβώς η σιωπή που το κατώφλι αποκάλυψης επιβάλλει ούτως ή άλλως.
 *
 * ⚠️ **Δέχεται `number | null`** — το `null` είναι η **λογοκριμένη** τιμή του
 * `DemandDisclosure.count`, και το να την αναγκάζαμε τον καλούντα να ξετυλίξει θα ήταν
 * η στιγμή που κάποιος θα έγραφε `count ?? 0` και θα ανακοίνωνε το μηδέν.
 */
export function announcementBand(count: number | null): AnnouncementBand | null {
  if (count === null) return null;

  let band: AnnouncementBand | null = null;
  for (const candidate of ANNOUNCEMENT_BANDS) {
    if (count >= candidate) band = candidate;
  }
  return band;
}

/**
 * **Το ταυτοτικό κλειδί του γεγονότος** — αυτό, και μόνο αυτό, κάνει την επανάληψη
 * αδύνατη.
 *
 * 🔑 **Ζώνη, ΠΟΤΕ ωμό πλήθος.** Με `${propertyId}:${count}` κάθε νέα ζήτηση θα ήταν νέο
 * «γεγονός» και ο μηχανισμός idempotency θα ήταν **πράσινος και ανενεργός**: θα
 * λειτουργούσε τέλεια και δεν θα εμπόδιζε **τίποτα**.
 */
export function announcementEventId(propertyId: string, band: AnnouncementBand): string {
  return `${propertyId}:demand-band:${band}`;
}

/**
 * **Το ταυτοτικό κλειδί της αντίθετης κατεύθυνσης** — «βγήκε αγγελία που ταιριάζει
 * στη ζήτησή μου» προς τον **ζητούντα**, όχι «πόσοι με ψάχνουν» προς τον ιδιοκτήτη.
 *
 * 🔴 **ΣΚΟΠΙΜΑ ΑΛΛΟ ΣΧΗΜΑ ΑΠΟ ΤΟ {@link announcementEventId} — ζεύγος ταυτότητας,
 * ΠΟΤΕ ζώνη πλήθους.** Η ζώνη απαντά *«πόσο άλλαξε το ενδιαφέρον;»* — σωστό όταν το
 * υποκείμενο είναι ένα **μέγεθος** (πόσοι ψάχνουν το ακίνητό σου). Εδώ το υποκείμενο
 * είναι μία **ταυτότητα**: μια ζήτηση «η νότια πλευρά αυτού του δρόμου» έχει πλήθος
 * ταιριασμάτων 0 ή 1 σχεδόν πάντα. Με ζώνες, η **πρώτη** αγγελία θα περνούσε τη ζώνη
 * `1` (email) — και η **δεύτερη**, 1→2, δεν διασχίζει καμία ζώνη ⇒ **σιωπή για
 * πάντα, ακόμη κι αν είναι εντελώς διαφορετική αγγελία.** Ο ζητών ρωτά *«ποια
 * αγγελία;»*, όχι *«πόσες;»* — και οι δύο ερωτήσεις χρειάζονται **διαφορετικό**
 * κλειδί idempotency, όχι το ίδιο με άλλη παράμετρο.
 *
 * Με το ζεύγος `(demandId, listingId)`, κάθε **νέα** αγγελία που ταιριάζει είναι
 * αναπόφευκτα **νέο** κλειδί ⇒ νέα ειδοποίηση· η **ίδια** αγγελία που ταιριάζει ξανά
 * (π.χ. μετά από επαναδημοσίευση) είναι το **ίδιο** κλειδί ⇒ το idempotent `create()`
 * του {@link dispatchNotification} τη σιωπά, όπως ακριβώς κάνει η ζώνη στην απέναντι
 * κατεύθυνση.
 */
export function demandListingMatchEventId(demandId: string, listingId: string): string {
  return `${demandId}:listing:${listingId}`;
}
