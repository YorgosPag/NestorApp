import {
  DEMAND_GAPS,
  NO_DEMAND_FEATURES,
  isDemandLifecycle,
  type DemandGap,
  type PropertyDemand,
} from '@/types/property-demand';

import { featuresWithoutLegacyPrice, readStoredSeeks } from './demand-seeks-read';

// =============================================================================
// 1. ΤΙ ΔΙΑΒΑΣΤΗΚΕ
// =============================================================================

/**
 * **Το αποτέλεσμα της ανάγνωσης** — δύο σκέλη, ποτέ «μισή οντότητα».
 *
 * 🔑 **Το `'incomplete'` κουβαλά ταυτότητα και λόγο, τίποτα άλλο.** Ο πειρασμός ήταν να
 * κουβαλά και «ό,τι πρόλαβε να διαβαστεί», ώστε η οθόνη να δείχνει κάτι. Απορρίφθηκε:
 * θα ήταν **δεύτερος, ασθενέστερος τύπος ζήτησης** που κάθε καταναλωτής θα έμπαινε
 * στον πειρασμό να χειριστεί «σχεδόν σαν κανονική» — δηλαδή η ίδια διαρροή ελλιπών
 * δεδομένων, από την πίσω πόρτα. Ο άνθρωπος χρειάζεται **τον λόγο** και **τον δρόμο
 * διόρθωσης**· και τα δύο χωράνε σε ταυτότητα + κενά.
 */
export type StoredDemandRead =
  | { readonly kind: 'complete'; readonly demand: PropertyDemand }
  | {
      readonly kind: 'incomplete';
      readonly id: string;
      /** **Ποια** πεδία δεν διαβάστηκαν — κλειστό λεξιλόγιο, κλειδιά i18n (N.11). */
      readonly gaps: readonly DemandGap[];
    };

// =============================================================================
// 2. Η ΠΑΡΟΥΣΙΑ — ένας κριτής ανά κενό, εξαντλητικά
// =============================================================================

/** Αντικείμενο με `kind` συμβολοσειρά — το σχήμα κάθε διακριτής ένωσης του τομέα. */
function isTagged(value: unknown): boolean {
  return (
    typeof value === 'object' &&
    value !== null &&
    !Array.isArray(value) &&
    typeof (value as { kind?: unknown }).kind === 'string'
  );
}

/**
 * **Ο κριτής κάθε κενού** — `Record` πάνω στο κλειστό σύνολο, άρα **εξαντλητικός**:
 * νέο `DemandGap` χωρίς κριτή **δεν μεταγλωττίζεται**.
 *
 * ⚠️ **Δεν κρίνει ΕΓΚΥΡΟΤΗΤΑ, μόνο ΑΝΑΓΝΩΣΙΜΟΤΗΤΑ.** Ένα `seeks: []` **περνά** από εδώ
 * (διαβάστηκε μια χαρά) και το πιάνει ο `demandInvariantViolations` με το δικό του
 * όνομα, `seeks-empty`. Δύο ερωτήσεις, δύο σπίτια — αλλιώς ο άνθρωπος θα έβλεπε
 * «λείπει» για κάτι που **υπάρχει και είναι λάθος**, ή το αντίστροφο.
 */
type Stored = Readonly<Record<string, unknown>>;

/**
 * 🔑 **ADR-777 §8.60.15** — το `seeks` κρίνεται από τον **έναν** αναγνώστη εναλλακτικών, που ξέρει
 * **και τα δύο** σχήματα. Άγνωστο είδος ή χαλασμένο ποσό ⇒ `seeks`· παλιό έγγραφο με πολλές
 * διαθέσεις και ένα αμονάδιστο εύρος ⇒ `seek-prices` (η μονάδα **δεν** μαντεύεται).
 */
const PRESENT: Readonly<Record<DemandGap, (stored: Stored) => boolean>> = {
  seeks: (stored) => readStoredSeeks(stored.seeks, stored.features).kind !== 'unreadable',
  'seek-prices': (stored) =>
    readStoredSeeks(stored.seeks, stored.features).kind !== 'ambiguous-price',
  place: (stored) => isTagged(stored.place),
  timing: (stored) => isTagged(stored.timing),
  mandate: (stored) => isTagged(stored.mandate),
  // 🔴 AIP-216: τιμή **εκτός** λεξιλογίου δεν είναι «κάτι άλλο», είναι **άγνωστη** — και
  //    το άγνωστο ονομάζεται, δεν βαφτίζεται `'active'`.
  lifecycle: (stored) => isDemandLifecycle(stored.lifecycle),
};

/** Τα κενά αυτού του εγγράφου, **με τη σειρά του λεξιλογίου** (σταθερή για την οθόνη). */
function gapsOf(stored: Stored): readonly DemandGap[] {
  return DEMAND_GAPS.filter((gap) => !PRESENT[gap](stored));
}

// =============================================================================
// 3. ΤΟ ΣΥΝΟΡΟ
// =============================================================================

/**
 * **Διαβάζει ένα αποθηκευμένο έγγραφο ως ζήτηση** — πλήρη, ελλιπή, ή `null`.
 *
 * `null` σημαίνει **«αυτό δεν είναι έγγραφο»**, και συμβαίνει σε ακριβώς μία περίπτωση:
 * τα δεδομένα δεν είναι καν αντικείμενο. **Δεν** επιστρέφεται `null` για ελλιπές πεδίο —
 * εκεί απαντά το σκέλος `'incomplete'`, γιατί μια ζήτηση που έχασε ένα πεδίο
 * **εξακολουθεί να είναι ζήτηση** και ο κάτοχός της δικαιούται να τη δει και να τη
 * διορθώσει (ίδιο συμβόλαιο με ADR-839 · ADR-842).
 *
 * ⚠️ **Η ΤΑΥΤΟΤΗΤΑ ΕΡΧΕΤΑΙ ΑΠΟ ΕΞΩ, ΚΑΙ ΝΙΚΑ** — το `id` του **εγγράφου** είναι η
 * αυθεντία, ποτέ ένα `id` γραμμένο μέσα στο περιεχόμενο: το δεύτερο είναι αντίγραφο
 * που μπορεί να αποκλίνει.
 *
 * ⚠️ **Τα `features` και `proximity` παίρνουν τη ΔΗΛΩΜΕΝΗ τους ουδέτερη τιμή** — και
 * είναι ακριβώς η περίπτωση που το **Avro** επιτρέπει: η προεπιλογή ζει **στο σχήμα**
 * ({@link NO_DEMAND_FEATURES} · *«κενό = καμία απαίτηση γειτονιάς»*), δεν εφευρίσκεται
 * εδώ. Γι' αυτό **δεν** είναι `DemandGap`.
 *
 * ⚠️ **Το `affirmedAt` ΔΕΝ είναι κενό, επίτηδες**: απόν ⇒ το `daysSince` δίνει
 * `Infinity` ⇒ η ζήτηση λογίζεται **`stale`** — εκτός αθροίσματος προς τρίτους,
 * **ορατή** στον κάτοχο, και επανέρχεται με **ένα κλικ** («Ψάχνω ακόμη»). Δηλαδή η
 * σημερινή συμπεριφορά είναι ήδη fail-closed **και** διορθώσιμη· ένα δεύτερο όνομα
 * γι' αυτήν θα ήταν δεύτερος κριτής για το ίδιο γεγονός.
 *
 * **Ιδιοδύναμη**: δεύτερη διέλευση δίνει το ίδιο αποτέλεσμα.
 */
export function readStoredDemand(raw: unknown, id: string): StoredDemandRead | null {
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) return null;

  const stored = raw as Stored;
  const gaps = gapsOf(stored);
  const seeks = readStoredSeeks(stored.seeks, stored.features);

  if (gaps.length > 0 || seeks.kind !== 'read') return { kind: 'incomplete', id, gaps };

  return {
    kind: 'complete',
    demand: {
      // 🔴 Ο ΕΝΑΣ ισχυρισμός — δες την κεφαλίδα. Το CHECK 3.74 απαγορεύει το
      //    `as PropertyDemand` οπουδήποτε αλλού στο repo.
      ...(stored as unknown as PropertyDemand),
      id,
      // 🔑 ADR-777 §8.60.15 — πάντα το **νέο** σχήμα στη μνήμη, όποιο κι αν είναι στον δίσκο.
      seeks: seeks.seeks,
      // ── Οι ΔΗΛΩΜΕΝΕΣ ουδέτερες τιμές (Avro), ποτέ εφευρημένες ──────────────
      features:
        (featuresWithoutLegacyPrice(stored.features) as PropertyDemand['features'] | undefined) ??
        NO_DEMAND_FEATURES,
      proximity: (stored.proximity as PropertyDemand['proximity']) ?? [],
      // `lifeContext` είναι ήδη `| null` στον τύπο: η απουσία **είναι** η τιμή.
      lifeContext: (stored.lifeContext as PropertyDemand['lifeContext']) ?? null,
    },
  };
}

/**
 * Η ίδια πράξη όταν ο καταναλωτής **δεν έχει τι να κάνει** με μια ελλιπή ζήτηση.
 *
 * 🔴 **Η ΚΑΡΑΝΤΙΝΑ ΖΕΙ ΕΔΩ** (RESO `Incomplete`): οι διαδρομές του **διακομιστή**
 * (άθροισμα επιπέδου Γ · ταίριασμα · φρουροί πρώτης επαφής) παίρνουν `null` και
 * **προσπερνούν** — καμία ελλιπής ζήτηση δεν γίνεται ποτέ ισχυρισμός προς τρίτον.
 *
 * ⚠️ **Ο κατάλογος του κατόχου ΔΕΝ το χρησιμοποιεί** — εκείνος ζητά
 * {@link readStoredDemand} και **δείχνει** το ελλιπές με τον λόγο του: η **Α5 §4.1**
 * απαγορεύει τη σιωπηλή εξαφάνιση, και ένα ακίνητο/ζήτηση που «χάθηκε από μόνο του»
 * είναι το χειρότερο που μπορεί να δει ο άνθρωπος.
 *
 * Λεπτό περιτύλιγμα — **ποτέ** δεύτερη υλοποίηση: delegate, όχι αντίγραφο.
 */
export function propertyDemandFromDocument(raw: unknown, id: string): PropertyDemand | null {
  const read = readStoredDemand(raw, id);
  return read !== null && read.kind === 'complete' ? read.demand : null;
}

/**
 * **Η ταυτότητα, ό,τι κι αν διαβάστηκε.**
 *
 * 🔑 Υπάρχει ώστε η οθόνη να μη ρωτά «ποιο σκέλος;» για κάτι τόσο απλό όσο ένα `key`
 * ή ένας σύνδεσμος. Γραμμένο δύο φορές (μία στον κατάλογο, μία στην κάρτα) θα ήταν
 * ακριβώς ο μικρός κλώνος που ο **N.0.2** ζητά να κλείνει **επιτόπου**.
 */
export function demandReadId(read: StoredDemandRead): string {
  return read.kind === 'complete' ? read.demand.id : read.id;
}
