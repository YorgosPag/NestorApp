/**
 * **Ό,τι, και μόνο ό,τι, μαθαίνει το ακροατήριο.**
 *
 * Ίδιος κανόνας με το `types/public-listing.ts`: *«ό,τι δεν είναι γραμμένο εδώ, δεν
 * φεύγει ποτέ»*. Κάθε προσθήκη πεδίου είναι **απόφαση αποκάλυψης**.
 *
 * ⚠️ **Καμία ταυτότητα, κανένα κριτήριο, καμία ημερομηνία.** Ούτε καν ανώνυμη λίστα
 * «τι ζητούν»: δύο κριτήρια μαζί (περιοχή + προϋπολογισμός + όροφος) περιγράφουν
 * **ένα πρόσωπο** σε μικρή γειτονιά. Το §12.7(α) απαγορεύει κάθε διαδρομή που γίνεται
 * **εργαλείο πίεσης** — και μια λίστα κριτηρίων είναι ακριβώς αυτό στα χέρια
 * ιδιοκτήτη που ξέρει τους γείτονές του.
 */
export interface DemandDisclosure {
  readonly audience: DemandAudience;
  /**
   * Πόσοι ζητούν. **`null` όταν είναι κάτω από το κατώφλι** — και το `null` εδώ
   * σημαίνει *«δεν το λέμε»*, **όχι** *«κανένας»*. Η οθόνη οφείλει να τα ξεχωρίζει,
   * όπως η Α5 ξεχωρίζει το `never-asked` από το `owner-declined`.
   */
  readonly count: number | null;
  /** Το κατώφλι που εφαρμόστηκε — ώστε η σιωπή να είναι **εξηγήσιμη**, όχι μυστήριο. */
  readonly minCount: number;
}

/**
 * Σύνολο ζητήσεων → **τι μαθαίνει αυτό το ακροατήριο**.
 *
 * 🔴 **Η ΜΟΝΗ επιτρεπτή έξοδος από το επίπεδο Β προς οποιονδήποτε τρίτο.** Κάθε άλλη
 * διαδρομή που δίνει σε μη-κάτοχο πληροφορία για ζητήσεις είναι, εξ ορισμού,
 * παράκαμψη της Α12 — και ο κανόνας Firestore το κάνει **δομικά αδύνατο** από τον
 * πελάτη (`property_demands`: `read` μόνο ο συγγραφέας). Αυτή η συνάρτηση τρέχει
 * **στον διακομιστή**, πάνω σε δεδομένα που ο πελάτης δεν μπορεί να δει.
 *
 * @param demands — οι υποψήφιες, **ήδη επιλεγμένες** από το ερώτημα του καλούντος
 *   (ίδιο ακίνητο για `place-owner` · ίδια περιοχή για `area-market`)
 * @param audience — ποιος ρωτά
 * @param nowIso — η στιγμή αναφοράς· **ρητή παράμετρος** ώστε η φρεσκάδα να είναι
 *   δοκιμάσιμη και να μη διαβάζει κανείς κρυφά το ρολόι
 */
export function discloseDemand(
  demands: readonly PropertyDemand[],
  audience: DemandAudience,
  nowIso: string,
): DemandDisclosure {
  const { minCount } = DEMAND_DISCLOSURE[audience];
  const { counted } = censusDemands(demands, nowIso);

  return {
    audience,
    count: counted >= minCount ? counted : null,
    minCount,
  };
}

