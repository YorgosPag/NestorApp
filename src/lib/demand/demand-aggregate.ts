/**
 * Γιατί μια ζήτηση δεν μπήκε στο άθροισμα. Κλειστό σύνολο.
 *
 * 🔴 **Το `incomplete` ΔΕΝ το παράγει το {@link demandExclusionReason}, και είναι σωστό.**
 * Εκείνο κρίνει **πλήρη** οντότητα — μια ζήτηση που δεν διαβάστηκε ολόκληρη δεν φτάνει
 * ποτέ ως εκεί: τη σταματά το **σύνορο ανάγνωσης**
 * (`lib/demand/property-demand-from-document.ts`), που είναι και το μόνο σημείο που
 * **ξέρει** τι έλειπε. Ο κάδος υπάρχει εδώ ώστε ο αριθμός να **λέγεται** αντί να
 * εξαφανίζεται: ένα σιωπηλό κόψιμο δίνει αριθμό που *μοιάζει* απάντηση και είναι
 * **δείγμα** — το σχήμα «0 = κανείς δεν κοίταξε» με άλλο νούμερο.
 *
 * 🔑 Ίδια στάση με το πρότυπο **RESO** (`StandardStatus: Incomplete` = *«δεν
 * συμπληρώθηκε, **δεν δημοσιεύεται** στο MLS»*): εκτός αγοράς, **ορατή στον κάτοχο**.
 */
export const DEMAND_EXCLUSIONS = ['not-live', 'unattributed', 'stale', 'incomplete'] as const;

export type DemandExclusion = (typeof DEMAND_EXCLUSIONS)[number];

/**
 * **Η ΛΟΓΙΣΤΙΚΗ — για ΕΜΑΣ, ποτέ για το ακροατήριο.**
 *
 * 🔴 **ΜΗΝ την επιστρέψεις μαζί με την αποκάλυψη.** Το `counted` είναι ο **ωμός
 * αριθμός** — ακριβώς αυτό που το κατώφλι υπάρχει για να κρύψει. Ένα «αντικείμενο
 * λογιστικής» που ταξιδεύει δίπλα σε μια κρυμμένη τιμή **ακυρώνει** την απόκρυψη, και
 * το χειρότερο είναι ότι θα φαινόταν σωστό: η πύλη θα έλεγε «suppressed: true» ενώ ο
 * αριθμός θα ήταν δύο πεδία παρακάτω.
 *
 * Υπάρχει για δοκιμές, για αναφορές διαχειριστή και για να **κλείνει το άθροισμα**.
 */
export interface DemandCensus {
  /** Πόσες μετρήθηκαν. */
  readonly counted: number;
  /** Πόσες αποκλείστηκαν, **ανά ονομασμένο λόγο**. */
  readonly excluded: Readonly<Record<DemandExclusion, number>>;
  /** Πόσες εξετάστηκαν συνολικά. */
  readonly considered: number;
}

/** Κλείνει το άθροισμα; Υπάρχει **για να αποτύχει θορυβωδώς**. */
export function censusBalances(census: DemandCensus): boolean {
  const excluded = DEMAND_EXCLUSIONS.reduce((sum, key) => sum + census.excluded[key], 0);
  return census.counted + excluded === census.considered;
}

/** Πόσες ημέρες πέρασαν από την τελευταία επιβεβαίωση. */
function daysSince(isoTimestamp: string, nowIso: string): number {
  const then = Date.parse(isoTimestamp);
  const now = Date.parse(nowIso);
  if (Number.isNaN(then) || Number.isNaN(now)) return Number.POSITIVE_INFINITY;
  return (now - then) / 86_400_000;
}

/**
 * Ο **πρώτος** λόγος αποκλεισμού, ή `null` αν μετράει.
 *
 * ⚠️ **Η σειρά είναι συμβόλαιο, όχι τύχη.** Μια αποσυρμένη ζήτηση που είναι *επίσης*
 * μπαγιάτικη πρέπει να λογιστεί **«αποσυρμένη»** — αλλιώς η αναφορά θα έλεγε ότι ο
 * κόσμος «ξεχνά να επιβεβαιώσει» ενώ στην πραγματικότητα **βρήκε σπίτι**, και θα
 * κυνηγούσαμε λάθος πρόβλημα. Ίδιο πρότυπο με τη σειρά ταξινόμησης του CHECK 3.47.
 */
export function demandExclusionReason(
  demand: PropertyDemand,
  nowIso: string,
): DemandExclusion | null {
  if (!isLiveDemand(demand)) return 'not-live';
  if (!isAttributableDemand(demand)) return 'unattributed';
  if (daysSince(demand.affirmedAt, nowIso) > DEMAND_AFFIRMATION_TTL_DAYS) return 'stale';
  return null;
}

/**
 * Απογραφή ενός συνόλου ζητήσεων.
 *
 * 🔑 **Κάθε κάδος τυπώνεται ακόμη και στο μηδέν** — μάθημα CHECK 3.48 (`Κ6`): *«ένα
 * «0» που δεν τυπώνεται διαβάζεται ως “δεν υπάρχει τέτοιος έλεγχος”»*. Ο τύπος
 * `Record<DemandExclusion, number>` το κάνει **αδύνατο** να λείψει κάδος.
 */
export function censusDemands(
  demands: readonly PropertyDemand[],
  nowIso: string,
): DemandCensus {
  const excluded: Record<DemandExclusion, number> = {
    'not-live': 0,
    unattributed: 0,
    stale: 0,
    // ⚠️ **Πάντα 0 ΕΔΩ, και δηλωμένα**: αυτή η συνάρτηση δέχεται ήδη διαβασμένες
    //    (άρα πλήρεις) ζητήσεις. Τις ελλιπείς τις μετρά ο **αναγνώστης**, που είναι ο
    //    μόνος που τις είδε — δες {@link DEMAND_EXCLUSIONS}. Ο κάδος τυπώνεται ακόμη
    //    και στο μηδέν (μάθημα CHECK 3.48): «0» που λείπει διαβάζεται ως «δεν υπάρχει
    //    τέτοιος έλεγχος».
    incomplete: 0,
  };
  let counted = 0;

  for (const demand of demands) {
    const reason = demandExclusionReason(demand, nowIso);
    if (reason === null) counted += 1;
    else excluded[reason] += 1;
  }

  return { counted, excluded, considered: demands.length };
}

