/**
 * Πόσοι **άλλοι** ζητούν κάτι παρόμοιο — η απάντηση προς τον **ίδιο τον ζητούντα**.
 *
 * Το §12.6 ζητά δύο πράγματα ώστε η ζήτηση να «αξίζει και όταν δεν ταιριάζει τίποτα»:
 * *«τι υπάρχει **κοντά** στο αίτημα»* (το δίνει η μηχανή ταιριάσματος με τα
 * `near-miss`) και *«**πόσοι άλλοι** ζητούν το ίδιο»* — αυτό εδώ.
 *
 * 🔑 **Ο ίδιος ο συγγραφέας ΔΕΝ μετράει τον εαυτό του**, και δεν είναι λεπτομέρεια:
 * ένα «1 άλλος ψάχνει το ίδιο» που στην πραγματικότητα είναι ο ίδιος ο χρήστης θα
 * ήταν η εφαρμογή να **του μιλά για τον εαυτό του σε τρίτο πρόσωπο**.
 *
 * ⚠️ Χρησιμοποιεί το κατώφλι του **`area-market`**: ο ζητών είναι κι αυτός τρίτος
 * απέναντι στους υπόλοιπους ζητούντες. Το ότι *αυτός* ψάχνει δεν του δίνει δικαίωμα
 * να μάθει ποιοι άλλοι.
 */
export function discloseCompetition(
  demand: PropertyDemand,
  similar: readonly PropertyDemand[],
  nowIso: string,
): DemandDisclosure {
  const others = similar.filter((candidate) => candidate.id !== demand.id);
  return discloseDemand(others, 'area-market', nowIso);
}
