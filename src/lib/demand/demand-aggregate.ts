/**
 * @fileoverview **ΕΠΙΠΕΔΟ Γ** — το ανώνυμο άθροισμα. Παράγεται· δεν γράφεται.
 * @related ADR-777 §7 (Α9 · Α12) · SPEC-777A §14.2 · SPEC-777B §12.6 · §12.7 · RESEARCH §15.5
 * @module lib/demand/demand-aggregate
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΕΙΝΑΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το SPEC-777A §14.2 ορίζει **τρία** επίπεδα και επιμένει στο τρίτο:
 *
 *   > *«Το **Γ είναι ρητή τρίτη κατηγορία, όχι υποπερίπτωση**. Αν δεν δηλωθεί, θα
 *   > προκύψει σιωπηλά από ερωτήματα πάνω στο Β — και τότε η ανωνυμία είναι **ελπίδα,
 *   > όχι ιδιότητα**.»*
 *
 * Αυτό το αρχείο **είναι** η δήλωση. Είναι η **μόνη** διαδρομή από τη ζήτηση προς
 * οποιονδήποτε δεν την έγραψε — και το SPEC-777-RESEARCH §15.5 ονομάζει αυτό, όχι το
 * έγγραφο, ως το προϊόν: *«**Ε2** — η ζήτηση (**επίπεδο Γ, §14.2**) ως προϊόν»*.
 *
 * ⚠️ **Καθαρή συνάρτηση, όχι συλλογή.** Δεν υπάρχει `demand_aggregates` στο Firestore,
 * και δεν πρέπει να υπάρξει προτού χρειαστεί για **απόδοση**: ένα αποθηκευμένο
 * άθροισμα είναι **αντίγραφο** που μπορεί να παλιώσει, και η φρεσκάδα είναι εδώ
 * ακριβώς το ζητούμενο. «Παράγεται, δεν γράφεται» (§14.2) — κατά γράμμα.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΡΕΙΣ ΛΟΓΟΙ ΠΟΥ ΜΙΑ ΖΗΤΗΣΗ **ΔΕΝ ΜΕΤΡΑΕΙ** — και κανένας δεν τη σβήνει
 * ────────────────────────────────────────────────────────────────────────────
 *
 * 1. **Δεν είναι ζωντανή** (`paused` / `fulfilled` / `withdrawn`). Ρητή επιλογή του
 *    ανθρώπου.
 * 2. **Δεν επιβεβαιώθηκε** — ο μεσίτης την κατέγραψε, ο πελάτης δεν μίλησε ακόμη.
 *    Χωρίς αυτό, δέκα εγγραφές ενός γραφείου **φουσκώνουν** τον θερμοχάρτη που
 *    πουλάμε στον εργολάβο (απόφαση Giorgio 2026-08-11: *«και τα δύο, αλλά ο πελάτης
 *    εγκρίνει»*).
 * 3. **Σιώπησε** πάνω από {@link DEMAND_AFFIRMATION_TTL_DAYS} ημέρες.
 *
 * 🔑 **Ο τρίτος είναι ο πιο λεπτός, και είναι μετρημένη απόφαση τομέα.** Η **Ζ3**
 * λέει *«όποτε κι αν βγει»*, άρα υποχρεωτική λήξη είναι **απαγορευμένη**. Αλλά ένα
 * άθροισμα που μετρά ζήτηση δύο ετών **λέει ψέματα** στον εργολάβο που πάνω του
 * χτίζει. Η λύση δεν είναι λήξη — είναι **φρεσκάδα**: η ζήτηση μένει του χρήστη για
 * πάντα και **ξαναμπαίνει με ένα κλικ**, αλλά παύει να είναι **δημόσιος ισχυρισμός**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΔΥΟ ΑΚΡΟΑΤΗΡΙΑ, ΔΥΟ ΚΑΤΩΦΛΙΑ — και η διαφορά ΔΕΝ είναι αυστηρότητα
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το πρότυπο *small-cell suppression* (k-anonymity) λέει: μην δημοσιεύεις μέγεθος που
 * περιγράφει λιγότερα από k άτομα. Τα κατώφλια της πράξης είναι **5 ή 10** (το CMS
 * απαγορεύει κελιά κάτω από **11**). Αν το εφαρμόζαμε παντού, η **Ζ3 θα πέθαινε**:
 * για **ένα** κατάστημα σπάνια μαζεύονται πέντε ενδιαφερόμενοι.
 *
 * 🔑 **Η διάκριση είναι ΠΟΙΟΣ ΕΙΝΑΙ ΤΟ ΥΠΟΚΕΙΜΕΝΟ, όχι πόσο φοβόμαστε.** Όταν
 * ειδοποιείται ο **ιδιοκτήτης** για το **δικό του** ακίνητο, το γεγονός «κάποιος σε
 * θέλει» είναι πληροφορία **γι' αυτόν** — και η ανωνυμία που οφείλουμε αφορά τον
 * **ενδιαφερόμενο**, η οποία προστατεύεται με **απόκρυψη ταυτότητας**, όχι με
 * απόκρυψη αριθμού. Όταν ένας **τρίτος** αγοράζει θερμοχάρτη, μαθαίνει για
 * **ανθρώπους που δεν τον ξέρουν** — εκεί το k-κατώφλι είναι το σωστό εργαλείο.
 *
 * 🏆 Δεν βρέθηκε πύλη ακινήτων που να δηλώνει **κατώφλι αποκάλυψης** καθόλου. Το
 * *Make Me Move* του Zillow — το πλησιέστερο ανάλογο — δούλευε **ανάποδα** (δήλωνε ο
 * ιδιοκτήτης) και **καταργήθηκε**.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις πάνω σε τύπους.
 */

import {
  DEMAND_AFFIRMATION_TTL_DAYS,
  isAttributableDemand,
  isLiveDemand,
  type PropertyDemand,
} from '@/types/property-demand';

