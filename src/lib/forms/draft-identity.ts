/**
 * @fileoverview **«Υπάρχει κάποιος για να σωθεί αυτό;»** — το εμπόδιο της ταυτότητας.
 * @related ADR-660 §5.9 · ADR-777 §7 (Α14 §17.2) · lib/forms/draft-validation.ts
 * @module lib/forms/draft-identity
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟ ΛΕΞΙΛΟΓΙΟ, ΚΑΙ ΟΧΙ ΓΡΑΜΜΗ ΣΤΟ `blockersOf` ΤΗΣ ΦΟΡΜΑΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `ownerPropertyFormBlockers(values)` — όπως και το `mandateFormBlockers(values)` —
 * βλέπει **μόνο ό,τι πληκτρολόγησε ο άνθρωπος**. Η ταυτότητα δεν είναι πεδίο της
 * φόρμας: δεν τη γράφει κανείς, **υπάρχει ή δεν υπάρχει**. Μια γραμμή εκεί θα
 * απαιτούσε να περάσει το `uid` μέσα στις τιμές της φόρμας — δηλαδή να γίνει το
 * `authorUserId` **πεδίο που στέλνει ο πελάτης**, ακριβώς αυτό που το
 * `ownerPropertyDraftSchema` αρνείται εξ ορισμού *(«ό,τι δεν είναι στο σχήμα δεν
 * μπορεί να σταλεί»)*.
 *
 * 🔑 **Ίδιο σχήμα με το `MANDATE_FORM_BLOCKERS`**: κάθε πηγή εμποδίων έχει το **δικό**
 * της λεξιλόγιο, και **όλα** καταλήγουν στην ίδια λίστα οθόνης μέσω του
 * {@link withExtraBlockers}. Δεν είναι δεύτερος μηχανισμός — είναι ο **ίδιος**,
 * με δεύτερη πηγή.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΟ ΕΜΠΟΔΙΟ ΕΙΝΑΙ «ΔΕΝ ΕΙΝΑΙ **ΑΚΟΜΗ**», ΟΧΙ «ΕΙΝΑΙ ΑΚΥΡΟ»
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο τύπος {@link DraftFormValidation} το λέει ρητά για τα `blockers`: *«λείπει βήμα
 * της φόρμας — δεν είναι άκυρο, δεν είναι **ακόμη**»*. Αυτό ακριβώς είναι ο
 * λογαριασμός στη ροή του **ADR-660 §5.9**: ο άνθρωπος συμπληρώνει ολόκληρη την
 * αγγελία **χωρίς** να τον ρωτήσει κανείς ποιος είναι, και η ταυτότητα ζητείται τη
 * στιγμή που χρειάζεται να **σωθεί** η δουλειά — όχι πριν δοθεί αξία.
 *
 * ⚠️ **ΔΕΝ είναι φρουρός ασφαλείας, και δεν επιτρέπεται να διαβαστεί ως τέτοιος.**
 * Ο φρουρός είναι το `withAuth` της πόρτας (`app/api/owner-properties/route.ts`) και
 * ο κανόνας του Storage (`owner_properties/{userId}/…` → `isOwner(userId)`). Αυτό
 * εδώ είναι **μήνυμα προς άνθρωπο**: λέει *τι λείπει*, δεν *εμποδίζει* τίποτα. Ένας
 * πελάτης που θα το παρέκαμπτε θα έπαιρνε **401**, όχι αγγελία.
 *
 * **Layering**: leaf — καθαρή συνάρτηση, καμία εξάρτηση από React, Firebase ή zod.
 */

/**
 * Τα εμπόδια ταυτότητας ενός προσχεδίου.
 *
 * ⚠️ **Ένα, και ο πληθυντικός είναι σκόπιμος**: το λεξιλόγιο είναι πίνακας ώστε ένα
 * δεύτερο *(π.χ. «ο λογαριασμός δεν έχει επαληθευμένο email»)* να προστεθεί χωρίς να
 * αλλάξει η υπογραφή κανενός καταναλωτή. Το ίδιο έκανε το `OWNER_PROPERTY_FORM_BLOCKERS`
 * όταν είχε επίσης ένα.
 */
export const DRAFT_IDENTITY_BLOCKERS = [
  /** Δεν υπάρχει συνδεδεμένος χρήστης — η δουλειά δεν έχει πού να σωθεί. */
  'account-required',
] as const;

export type DraftIdentityBlocker = (typeof DRAFT_IDENTITY_BLOCKERS)[number];

/**
 * **Λείπει ταυτότητα;** — η μόνη ερώτηση αυτού του αρχείου.
 *
 * ⚠️ **Δέχεται `string | null`, ΟΧΙ τον χρήστη**: ο τύπος του χρήστη σέρνει Firebase,
 * και αυτή η συνάρτηση δεν έχει καμία δουλειά να ξέρει από πού ήρθε η ταυτότητα.
 * Ίδιο ιδίωμα με το `authorUserId: string | null` του `useOwnerPropertyMedia` — μία
 * ερώτηση, ένα όρισμα.
 *
 * ⚠️ **Κενή συμβολοσειρά μετράει ως απουσία.** Ένα `uid` μήκους μηδέν δεν είναι
 * ταυτότητα· θα παρήγαγε διαδρομή `owner_properties//{id}/…` — δηλαδή διαδρομή με
 * λάθος πλήθος τμημάτων, που ο κανόνας του Storage **δεν ταιριάζει**, και η αποτυχία
 * θα λεγόταν «άρνηση δικαιωμάτων» για λόγο που δεν έχει σχέση με δικαιώματα.
 */
export function draftIdentityBlockers(authorUserId: string | null): DraftIdentityBlocker[] {
  return hasDraftIdentity(authorUserId) ? [] : ['account-required'];
}

/**
 * Η **ίδια** ερώτηση, σε σχήμα κατηγορήματος — για όποιον δεν φτιάχνει λίστα οθόνης.
 *
 * 🔑 **ΜΙΑ απάντηση, δύο σχήματα.** Ο καταναλωτής που ανεβάζει αρχεία
 * ({@link useOwnerPropertyMedia}) δεν θέλει λίστα εμποδίων· θέλει *ναι/όχι*. Αν
 * έγραφε δικό του `=== null`, θα υπήρχαν **δύο** κριτές για το «υπάρχει ταυτότητα;»
 * — και θα απέκλιναν την ημέρα που προστεθεί η κενή συμβολοσειρά σε **έναν** από τους
 * δύο (ο καθρέφτης του ADR-749).
 *
 * ⚠️ **Κατηγόρημα τύπου (`is string`), ΟΧΙ `boolean`** — και είναι απαίτηση N.2, όχι
 * κομψότητα: με σκέτο `boolean` ο καλών θα έπρεπε να γράψει `authorUserId as string`
 * για να φτιάξει τη διαδρομή, δηλαδή **χειροκίνητο ισχυρισμό** ακριβώς εκεί που ο
 * μεταγλωττιστής μπορεί να αποδείξει. Έτσι το «έλεγξα» και το «άρα είναι» είναι το
 * **ίδιο** γεγονός, και δεν μπορούν να αποκλίνουν.
 */
export function hasDraftIdentity(authorUserId: string | null): authorUserId is string {
  return typeof authorUserId === 'string' && authorUserId !== '';
}

