/**
 * **«Ξέρουμε ποιος υπογράφει;»** — το εμπόδιο του ΑΦΜ.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ **ΔΕΥΤΕΡΟΣ ΠΙΝΑΚΑΣ** ΚΑΙ ΟΧΙ ΓΡΑΜΜΗ ΣΤΟ `DRAFT_IDENTITY_BLOCKERS`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η κεφαλίδα του `DRAFT_IDENTITY_BLOCKERS` **προσκαλεί** ρητά δεύτερη τιμή
 * *(«ώστε ένα δεύτερο να προστεθεί χωρίς να αλλάξει η υπογραφή κανενός
 * καταναλωτή»)*. Η πρόσκληση **δοκιμάστηκε και απορρίφθηκε, με μέτρηση**:
 *
 * > Το `offer-form-labels.ts:37` δηλώνει
 * > `OfferBlocker = OwnerPropertyFormBlocker | MandateFormBlocker | DraftIdentityBlocker`
 * > και στη γρ.43 `TEXT_KEYS: Record<DraftFormSlot | OfferBlocker | OfferViolation, string>`.
 *
 * ⇒ Μια τιμή παραπάνω στο **πρώτο** λεξιλόγιο **σταματά να μεταγλωττίζει τη φόρμα
 * προσφοράς** μέχρι κάποιος να της δώσει κλειδί i18n — για μήνυμα που εκείνη
 * **δεν μπορεί να δείξει ποτέ**, γιατί δεν καλεί ποτέ αυτόν τον κριτή. Θα ήταν
 * **αδρανής φρουρός** (ADR-749 §5) **και** δύο νεκρά κλειδιά locale, δηλαδή
 * ακριβώς το σχήμα *«κάλυψη σε νεκρό κλάδο»* που το ADR-827 §9.20 απέρριψε ήδη
 * μία φορά στο σχήμα της πόρτας.
 *
 * 🔑 **Και η σωστή απάντηση είναι γραμμένη στην κεφαλίδα αυτού του αρχείου**:
 * *«κάθε πηγή εμποδίων έχει το **δικό** της λεξιλόγιο, και **όλα** καταλήγουν
 * στην ίδια λίστα οθόνης μέσω του {@link withExtraBlockers}»*. Δύο πίνακες, μία
 * λίστα. **Πληρώνει μόνο ο καταναλωτής που κάνει την ερώτηση.**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΕΙΝΑΙ «ΔΕΝ ΕΙΝΑΙ **ΑΚΟΜΗ**» ΚΑΙ ΟΧΙ ΦΡΟΥΡΟΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ισχύει **κατά λέξη** ό,τι λέει η κεφαλίδα για τον λογαριασμό: αυτό **δεν
 * εμποδίζει** τίποτα — το λέει. Ο πραγματικός φρουρός είναι το **δίχτυ του Σ3**
 * (`mandate-acceptance-prepare.ts`, άρνηση `identity-incomplete`), που **μένει**
 * και **δεν επιτρέπεται να αφαιρεθεί**: παράγει νομικό κείμενο (άρθρο 200 §2
 * Ν.4072/2012) και είναι η μόνη άμυνα απέναντι σε πελάτη που παρακάμπτει τη φόρμα.
 *
 * 🔑 **Αυτό εδώ μετακινεί τη ΓΝΩΣΗ, όχι την άμυνα** (§9.20 β, just-in-time): πριν,
 * το κενό ΑΦΜ το ανακάλυπτε **το γραφείο** πατώντας «Αποδοχή» — σε αδιέξοδο που
 * **μόνο ο ιδιώτης** μπορούσε να λύσει και **δεν το έβλεπε**. Τώρα το μαθαίνει
 * αυτός που μπορεί να το διορθώσει, τη στιγμή που μπορεί να το διορθώσει.
 *
 * ⚠️ **Ένα, και ο πληθυντικός είναι σκόπιμος** — ίδιος λόγος με τον αδελφό πίνακα.
 */
export const TAX_IDENTITY_BLOCKERS = [
  /** Δεν έχει δηλωθεί ΑΦΜ — η σύμβαση που θα γεννηθεί δεν μπορεί να τον ονομάσει. */
  'tax-identity-required',
] as const;

export type TaxIdentityBlocker = (typeof TAX_IDENTITY_BLOCKERS)[number];

/**
 * **Λείπει φορολογική ταυτότητα;** — η μόνη ερώτηση.
 *
 * ⚠️ **ΚΑΝΕΝΑΣ mod-11 ΕΔΩ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ ΤΟΥ ΔΕΝΤΡΟΥ.** Ο `readVatNumber`
 * (`auth-context-profile.ts`) το έχει ήδη γράψει για τον **αναγνώστη**: *«Χωρίς
 * mod-11 εδώ: ο ελεγκτής ανήκει στη **γραφή**»* — και εκεί **εκτελείται**, στον
 * `judgeVatNumber` του `tax-identity.service.ts`, πίσω από τη μία πόρτα.
 *
 * 🔑 Δεύτερος έλεγχος ψηφίου εδώ θα ήταν **δεύτερος επικυρωτής** (§9 του handoff:
 * ρητή απαγόρευση) και θα απέκλινε την ημέρα που αλλάξει ο ένας από τους δύο. Το
 * context παραδίδει ήδη **μόνο** εννιαψήφια συμβολοσειρά ή `null`.
 *
 * ⚠️ **Δέχεται `string | null`, ΟΧΙ τον χρήστη** — ίδιο ιδίωμα με τον αδελφό του:
 * μία ερώτηση, ένα όρισμα, καμία εξάρτηση από Firebase.
 */
export function taxIdentityBlockers(vatNumber: string | null): TaxIdentityBlocker[] {
  return hasTaxIdentity(vatNumber) ? [] : ['tax-identity-required'];
}

/**
 * Η **ίδια** ερώτηση σε σχήμα κατηγορήματος — ίδιος λόγος με το {@link hasDraftIdentity}.
 *
 * ⚠️ **Η κενή συμβολοσειρά μετράει ως απουσία.** Ο γραφέας δεν τη γεννά ποτέ *(το
 * κενό είναι **ανάκληση** και γράφει `null`)*, αλλά ο αναγνώστης δεν στηρίζεται σε
 * αυτό: έγγραφο από παλιά μετανάστευση ή import μπορεί να την κουβαλά, και ένα ΑΦΜ
 * μήκους μηδέν σε σύμβαση είναι **άκυρο στοιχείο** που κανείς δεν θα δει μέχρι να
 * το ζητήσει η εφορία.
 */
export function hasTaxIdentity(vatNumber: string | null): vatNumber is string {
  return typeof vatNumber === 'string' && vatNumber !== '';
}
