import { z } from 'zod';

import type { GeoPoint } from '@/types/geo/coordinates';

/**
 * Αριθμός ή «δεν το έθεσε».
 *
 * 🔑 **Το κενό πεδίο γίνεται `null`, ΠΟΤΕ `0`** — δες την κεφαλίδα για τους δύο
 * υπαρκτούς μάρτυρες (ισόγειο · γκαρσονιέρα). Δέχεται και `string`, γιατί αυτό
 * ακριβώς παραδίδει ένα `<input type="number">` που ο άνθρωπος άδειασε.
 *
 * Μη-πεπερασμένη τιμή (`NaN`, `Infinity`) γίνεται επίσης `null`: «δεν το έθεσε» και
 * «έγραψε κάτι που δεν είναι αριθμός» έχουν την **ίδια** σωστή απάντηση προς τα
 * κάτω — ό,τι μένει είναι δουλειά των blockers, όχι του σχήματος.
 */
export const optionalNumberSchema = z
  .union([z.number(), z.string(), z.null(), z.undefined()])
  .transform((raw) => {
    if (raw === null || raw === undefined) return null;
    if (typeof raw === 'number') return Number.isFinite(raw) ? raw : null;
    const trimmed = raw.trim();
    if (trimmed === '') return null;
    const parsed = Number(trimmed);
    return Number.isFinite(parsed) ? parsed : null;
  });

/**
 * Σημείο στη Γη ή «δεν δείχτηκε».
 *
 * ⚠️ Ο ρητός τύπος `z.ZodType<GeoPoint | null>` **μένει**: δένει το σχήμα με τον
 * κανονικό τύπο του αποθετηρίου, ώστε μια μελλοντική προσθήκη πεδίου στο
 * {@link GeoPoint} να **μη μεταγλωττίζεται** εδώ αντί να περάσει σιωπηλά ως
 * ανώνυμο αντικείμενο με δύο αριθμούς.
 */
export const geoPointSchema: z.ZodType<GeoPoint | null> = z
  .object({ lat: z.number(), lng: z.number() })
  .nullable();
