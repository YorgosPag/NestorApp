/**
 * @fileoverview **ΤΑ ΚΕΙΜΕΝΑ ΤΗΣ ΦΟΡΜΑΣ ΩΣ ΔΕΔΟΜΕΝΟ** — στατικοί descriptors, όχι `keyBase`.
 * @related ADR-744 §15 · ADR-827 §9.14 · CLAUDE.md N.11 · CHECK 3.8 · CHECK 3.34
 * @module lib/forms/draft-form-labels
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΜΕΤΡΗΜΕΝΟ ΓΕΓΟΝΟΣ ΠΟΥ ΤΟ ΓΕΝΝΗΣΕ (2026-08-29)
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `DraftFormShell` δεχόταν **`keyBase: string`** και **έχτιζε** τα κλειδιά του:
 *
 * ```ts
 * const K = `${NS}:${keyBase}.form`;   // keyBase = PROP ⇒ άλυτο στατικά
 * t(`${K}.title`) · t(`${K}.lead`) · t(`${K}.cancel`) …
 * ```
 *
 * Επειδή το `keyBase` είναι **prop**, καμία εμβέλεια δεν το λύνει. Η θεραπεία που
 * είχε επιλεγεί ήταν **`dynamicKeyPolicy` με προθέματα** — και είχε **μετρημένο
 * τίμημα, γραμμένο στην ίδια τη δήλωση**: *«η διαδρομή της προσφοράς κουβαλά και το
 * λεξιλόγιο της ζήτησης»*.
 *
 * 🔴 **ΤΟ ΤΙΜΗΜΑ ΕΓΙΝΕ ΦΡΑΓΜΟΣ**: η πολιτική ζει **ανά ΑΡΧΕΙΟ**, και τα δύο αρχεία
 * είναι **κοινά** ⇒ **κάθε** διαδρομή που αποδίδει φόρμα κουβαλούσε **και τις δύο**
 * βάσεις. Μετρημένο στη `/listings/mandates/new`: **6.072 bytes `demand.*`** σε σελίδα
 * που αποδίδει `keyBase="offer"` — **30%** του slice της, για λεξιλόγιο που **κανείς
 * δεν εμφανίζει εκεί**. Όταν η Φάση Α/β του **ADR-827** πρόσθεσε τα νόμιμα πεδία της
 * εντολής, η διαδρομή ξεπέρασε το δηλωμένο ταβάνι της (**CHECK 3.34**).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 Η ΛΥΣΗ ΕΙΝΑΙ Η ΠΡΑΚΤΙΚΗ ΤΩΝ ΜΕΓΑΛΩΝ, ΟΧΙ ΑΝΥΨΩΣΗ ΤΑΒΑΝΙΟΥ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Δύο ανεξάρτητες πηγές συμφωνούν, και καμία δεν λέει «ανέβασε το όριο»:
 *
 * 1. **Performance budgets** *(web.dev · Angular CLI · size-limit · Lighthouse)*: η
 *    ανύψωση ταβανιού είναι ρητά **προσωρινό μέτρο**· η κανονική πράξη είναι
 *    **μείωση πρώτα**. Το ίδιο λέει και το **Κ2** του καταστίχου: *«ΜΗΝ το ανεβάσεις
 *    για να γίνει πράσινο»*.
 * 2. **FormatJS / react-intl**: τα **δυναμικά message ids αποθαρρύνονται**· ο
 *    κανονικός τρόπος είναι **στατικά message descriptors**, δηλωμένα σε module
 *    εμβέλεια και **περασμένα ως props** — ακριβώς ώστε ο εξαγωγέας να τα βλέπει.
 *
 * ⇒ Το `keyBase` **καταργήθηκε**. Κάθε βάση έχει το **δικό της** αρχείο, όπου τα
 * κλειδιά είναι **σταθερές module** και το `t()` λύνεται από μόνο του. Το κοινό
 * κέλυφος δέχεται **κείμενο**, όχι κλειδιά.
 *
 * 🔑 **ΤΡΙΑ ΚΕΡΔΗ, ΚΑΙ ΤΟ ΔΕΥΤΕΡΟ ΕΙΝΑΙ ΤΟ ΣΗΜΑΝΤΙΚΟΤΕΡΟ:**
 *
 * | # | Τι κερδίζεται |
 * |---|---|
 * | 1 | **−6.072 bytes** στις διαδρομές προσφοράς *(και συμμετρικά στη ζήτηση)*: η διαδρομή ξαναμπαίνει **κάτω** από το ταβάνι **χωρίς** να το αγγίξει κανείς |
 * | 2 | 🔴 **Η ΕΞΑΙΡΕΣΗ ΕΞΑΦΑΝΙΖΕΤΑΙ ΑΝΤΙ ΝΑ ΔΙΑΧΕΙΡΙΖΕΤΑΙ**: οι δύο εγγραφές `dynamicKeyPolicy` **διαγράφονται**. Ήταν δηλωμένο τυφλό σημείο **και της CHECK 3.8** — τα κλειδιά ήταν αόρατα σε **κάθε** πύλη i18n |
 * | 3 | **Ο μεταγλωττιστής φυλά την πληρότητα**: `Record<…>` πάνω στα κλειστά σύνολα ⇒ νέος κωδικός **δεν χτίζει** χωρίς κείμενο |
 *
 * ⚠️ **Ο πίνακας ΔΕΝ αντικαθιστά τις άγκυρες.** Ο μεταγλωττιστής βεβαιώνει ότι κάθε
 * κωδικός **έχει κλειδί**· ότι το κλειδί **έχει λέξεις σε δύο γλώσσες** το βεβαιώνει
 * **μόνο** το `form-issue-keys.test.ts`. Πίνακας που δείχνει σε ανύπαρκτο κλειδί
 * μεταγλωττίζεται μια χαρά.
 */

/**
 * **Οι θέσεις κειμένου του κελύφους** — κλειστό σύνολο.
 *
 * 🔴 **ΕΝΑ ΛΕΞΙΛΟΓΙΟ ΘΕΣΕΩΝ ΑΝΤΙ ΓΙΑ ΟΚΤΩ ΠΕΔΙΑ, ΚΑΙ ΤΟ ΕΠΙΒΑΛΕ Η CHECK 3.28.** Η
 * πρώτη γραφή είχε `interface DraftFormLabels` με οκτώ πεδία, που σήμαινε **οκτώ
 * χωριστές κλήσεις `t()` σε κάθε αρχείο βάσης** — και τα δύο αρχεία βγήκαν **δομικά
 * δίδυμα** *(24 γραμμές, το μπλόκαρε το jscpd στο ίδιο commit)*. Ήταν το ακριβές
 * σχήμα του **N.18**: *«κεντρικοποιείς το Α, γράφεις Β+Γ ως δίδυμα»*.
 *
 * ⚠️ **Και ΔΕΝ λύνεται με κοινή συνάρτηση**: ένα `useLabels(keys)` θα έκανε το `t()`
 * να δέχεται **παράμετρο**, δηλαδή θα ξαναγύριζε στο άλυτο κλειδί που όλο αυτό
 * θεραπεύει. Η λύση είναι **λιγότερος κώδικας, όχι κοινός**: κάθε βάση δηλώνει
 * **δεδομένα** (`Record`) και **μία** γραμμή ευρετηρίασης ανά ερώτημα.
 */
export const DRAFT_FORM_SLOTS = [
  'title',
  'editTitle',
  'lead',
  'failed',
  'saving',
  'save',
  'submit',
  'cancel',
  /** Η επικεφαλίδα της λίστας ελλείψεων — **ίδιο** λεξιλόγιο, ίδιος μεταφραστής. */
  'issuesHeading',
] as const;

export type DraftFormSlot = (typeof DRAFT_FORM_SLOTS)[number];

/**
 * **Ο μεταφραστής μιας βάσης** — **ΜΙΑ** συνάρτηση, ένα λεξιλόγιο.
 *
 * 🔴 **ΤΡΕΙΣ ΜΕΘΟΔΟΙ ΕΓΙΝΑΝ ΜΙΑ, ΚΑΙ ΤΟ ΕΠΙΒΑΛΕ Η CHECK 3.28 — ΔΕΥΤΕΡΗ ΦΟΡΑ.** Ακόμη
 * και μετά τη συμπύκνωση σε `Record`, τα δύο αρχεία βάσης είχαν **επτά γραμμές
 * ταυτόσημου σώματος** *(`label` · `blocker` · `invariant`)* — πάνω από το κατώφλι των
 * **50 tokens**, δηλαδή **δίδυμα**.
 *
 * ⚠️ **Ο περιορισμός ΕΙΝΑΙ ΠΡΑΓΜΑΤΙΚΟΣ, όχι αδεξιότητα**: η στατική εξαγωγή απαιτεί το
 * `t()` να βλέπει **σταθερά module** στο **ίδιο** αρχείο· κοινή συνάρτηση με πίνακα ως
 * **παράμετρο** ξαναφέρνει το άλυτο κλειδί **και** την πολιτική που διαρρέει. Είναι το
 * ίδιο τίμημα που πληρώνει το `defineMessages` του FormatJS ανά module.
 *
 * ⇒ Η θεραπεία δεν ήταν παράκαμψη — ήταν **λιγότερος κώδικας**: τα τρία λεξιλόγια
 * ενώνονται σε **έναν** πίνακα, και ο μεταφραστής γίνεται **μία γραμμή**.
 *
 * 🔑 **Η συγχώνευση είναι ασφαλής επειδή τη φυλά άγκυρα**: αν ποτέ μια θέση κελύφους
 * αποκτήσει το **ίδιο όνομα** με κωδικό έλλειψης, ο ένας θα έσβηνε σιωπηλά τον άλλο.
 * Το `form-issue-keys.test.ts` μετρά ότι το πλήθος του ενωμένου πίνακα ισούται με το
 * **άθροισμα** των τριών — σύγκρουση **κοκκινίζει**.
 */
export type DraftFormText<TBlocker extends string, TViolation extends string> = (
  id: DraftFormSlot | TBlocker | TViolation,
) => string;
