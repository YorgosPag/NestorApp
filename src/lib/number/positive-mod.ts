/**
 * Υπόλοιπο **πάντα θετικό** — `positiveMod(-1, 12) === 11`, όχι `-1`.
 *
 * ⚠️ Το `((v % m) + m) % m` και **όχι** `(v % m) + m`: το δεύτερο `% m` δεν είναι περιττό.
 * Χωρίς αυτό, ένα ήδη θετικό `v` θα γινόταν `v + m`, δηλαδή θα έβγαινε **εκτός** του
 * διαστήματος από την άλλη πλευρά — σφάλμα που εμφανίζεται μόνο στη μισή είσοδο και γι'
 * αυτό επιβιώνει σε πρόχειρο έλεγχο.
 *
 * ⚠️ Ο **καλών** εγγυάται `modulus > 0`. Δεν ελέγχεται εδώ επίτηδες: ένας φρουρός θα έπρεπε
 * να επιστρέψει κάτι, και κάθε «κάτι» (0; NaN; το `value`;) είναι μια σιωπηλή απόφαση για
 * λογαριασμό κάποιου που έχει ήδη σφάλμα αλλού. Οι δύο καλούντες κρατούν τον φρουρό στη
 * δική τους στάθμη, όπου το «μηδενικό μήκος» έχει **νόημα** και απαντιέται με «κανένα κελί»
 * / «καμία εγγραφή» αντί με αριθμό.
 */
export function positiveMod(value: number, modulus: number): number {
  return ((value % modulus) + modulus) % modulus;
}
