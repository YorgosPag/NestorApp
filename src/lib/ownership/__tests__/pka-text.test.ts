/**
 * ADR-900 §3.8 — άγκυρα της ανάγνωσης κειμένου ΠΚΑ.
 *
 * ⚠️ **ΣΥΝΘΕΤΙΚΟ κείμενο** — ονόματα και ΑΦΜ επινοημένα (έγκυρα mod-11, κανενός ανθρώπου).
 * Πραγματικό ΠΚΑ **δεν** μπαίνει ποτέ σε fixture (προσωπικά δεδομένα).
 *
 * Τ1 ΚΑΕΚ μέσω του SSoT · Τ2 δικαιούχοι = γραμμή με ΕΓΚΥΡΟ ΑΦΜ · Τ3 άκυρος ΑΦΜ δεν γεννά δικαιούχο ·
 * Τ4 κωδικός επαλήθευσης · Τ5 κενό/σαρωμένο ⇒ κενή ανάγνωση, ποτέ μαντεψιά.
 */
import { readPkaText } from '../pka-text';

const VALID_A = '123456709';
const VALID_B = '123535891';

const SYNTHETIC_PKA = [
  [
    'ΕΛΛΗΝΙΚΟ ΚΤΗΜΑΤΟΛΟΓΙΟ',
    'ΠΙΣΤΟΠΟΙΗΤΙΚΟ ΚΤΗΜΑΤΟΓΡΑΦΟΥΜΕΝΟΥ ΑΚΙΝΗΤΟΥ',
    'ΚΑΕΚ: 050681726003/0/1',
    'Αριθμός πρωτοκόλλου: 2026123456789',
    `ΔΙΚΑΙΟΥΧΟΣ: ΠΑΠΑΔΟΠΟΥΛΟΣ ΚΩΝΣΤΑΝΤΙΝΟΣ ΤΟΥ ΙΩΑΝΝΗ  ΑΦΜ: ${VALID_A}  ΠΟΣΟΣΤΟ 50%`,
    `ΔΙΚΑΙΟΥΧΟΣ: ΠΑΠΑΔΟΠΟΥΛΟΥ ΜΑΡΙΑ ΤΟΥ ΓΕΩΡΓΙΟΥ  ΑΦΜ: ${VALID_B}  ΠΟΣΟΣΤΟ 50%`,
    'Κωδικός επαλήθευσης: AB12-CD34-EF56',
  ].join('\n'),
];

describe('Τ1 — ΚΑΕΚ', () => {
  it('μέσω του ΕΝΟΣ SSoT, κανονικοποιημένος', () => {
    expect(readPkaText(SYNTHETIC_PKA).kaekCodes).toEqual(['050681726003/0/1']);
  });
});

describe('Τ2 — δικαιούχοι', () => {
  it('γραμμή με έγκυρο ΑΦΜ ⇒ ένας δικαιούχος, χωρίς ετικέτες στο όνομα', () => {
    expect(readPkaText(SYNTHETIC_PKA).beneficiaries).toEqual([
      { name: 'ΠΑΠΑΔΟΠΟΥΛΟΣ ΚΩΝΣΤΑΝΤΙΝΟΣ ΙΩΑΝΝΗ', taxId: VALID_A },
      { name: 'ΠΑΠΑΔΟΠΟΥΛΟΥ ΜΑΡΙΑ ΓΕΩΡΓΙΟΥ', taxId: VALID_B },
    ]);
  });

  it('ο ίδιος ΑΦΜ σε δύο σελίδες ⇒ ένας δικαιούχος', () => {
    expect(readPkaText([...SYNTHETIC_PKA, SYNTHETIC_PKA[0]]).beneficiaries).toHaveLength(2);
  });
});

describe('Τ3 — άκυρος ΑΦΜ', () => {
  it('🔴 εννιά ψηφία με λάθος ψηφίο ελέγχου ΔΕΝ γεννούν δικαιούχο', () => {
    expect(readPkaText(['ΔΙΚΑΙΟΥΧΟΣ: ΓΕΩΡΓΙΟΥ ΝΙΚΟΛΑΟΣ ΑΦΜ: 123456789']).beneficiaries).toEqual([]);
  });

  it('ΑΦΜ χωρίς όνομα στη γραμμή ⇒ κανένας δικαιούχος (όχι «ανώνυμος»)', () => {
    expect(readPkaText([`ΑΦΜ: ${VALID_A}`]).beneficiaries).toEqual([]);
  });
});

describe('Τ4 — κωδικός επαλήθευσης', () => {
  it('μετά την ετικέτα, με ή χωρίς τόνους', () => {
    expect(readPkaText(SYNTHETIC_PKA).verificationCode).toBe('AB12-CD34-EF56');
    expect(readPkaText(['ΚΩΔΙΚΟΣ ΕΠΙΒΕΒΑΙΩΣΗΣ XY987654']).verificationCode).toBe('XY987654');
  });
});

describe('Τ5 — κενό κείμενο', () => {
  it('σαρωμένο PDF (χωρίς κείμενο) ⇒ κενή ανάγνωση', () => {
    expect(readPkaText([''])).toEqual({ kaekCodes: [], beneficiaries: [], verificationCode: null });
  });
});
