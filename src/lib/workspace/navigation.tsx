/**
 * Η διαδρομή **χωρίς** τον χώρο — η κατεύθυνση που ξεχνιέται.
 *
 * 🔑 Κάθε σύγκριση διαδρομής (`pathname === …`, `startsWith(…)`, πίνακες ενεργών
 * καρτελών) μιλά τη γλώσσα **χωρίς** χώρο. Με το πρόθεμα μπροστά γίνονται σιωπηλά
 * `false`: το sidebar δεν φωτίζει τίποτα, το breadcrumb χάνει τη θέση του, και
 * **καμία πύλη δεν το βλέπει** — το μόνο σύμπτωμα είναι μια οθόνη «που κάτι έχει».
 *
 * ⚠️ Διαδρομή **χωρίς** πρόθεμα επιστρέφεται αναλλοίωτη, άρα είναι ασφαλές να μπει
 * **παντού** — κανείς δεν χρειάζεται να ξεχωρίσει «ποιες συγκρίσεις είναι μέσα σε
 * χώρο». Ένας κανόνας που πρέπει να θυμάσαι είναι το σχήμα που έχει αποτύχει
 * μετρημένα τέσσερις φορές (CHECK 3.34 · 3.37 · 3.49 · 3.57).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΕΖΗΣΕ ΓΙΑ ΛΙΓΟ ΣΕ ΔΙΚΟ ΤΟΥ ΑΡΧΕΙΟ, ΚΑΙ Η ΙΣΤΟΡΙΑ ΕΧΕΙ ΜΑΘΗΜΑ
 * ─────────────────────────────────────────────────────────────────────────────
 * Όσο το `useWorkspaceAlias` έπεφτε πίσω στο `useAuth`, αυτό το module έσερνε
 * `@firebase/auth` σε **κάθε** component που απλώς συγκρίνει διαδρομή — μετρημένο
 * ζωντανά (`route-tabs.test.tsx`, `fetch is not defined`). Η πρώτη θεραπεία ήταν
 * να **χωριστεί** το αρχείο.
 *
 * ⚠️ **Ήταν θεραπεία του συμπτώματος.** Η αιτία ήταν ότι το σύνορο **μάντευε** τον
 * χώρο από claim αντί να τον αφήσει στον διακομιστή που τον **κρίνει**. Μόλις
 * έφυγε η μαντεψιά, έφυγε και η ακμή — και ο διαχωρισμός έμεινε **χωρίς λόγο**.
 * Ένα αρχείο που δικαιολογείται από εξάρτηση η οποία δεν υπάρχει πια είναι
 * τεκμηρίωση που **λέει ψέματα**· γι' αυτό ξαναενώθηκε.
 *
 * ⛔ **ΜΗΝ το ξαναχωρίσεις χωρίς να ξαναφέρεις πρώτα την αιτία.** Αν κάποτε αυτό
 * το module αποκτήσει βαριά εξάρτηση, το φυλά η άγκυρα `Λ2` — και **τότε** ο
 * διαχωρισμός θα έχει ξανά λόγο.
 *
 * ⚠️ Επιστρέφει `''` όταν το Next δεν έχει ακόμη διαδρομή, όπως και το πρωτότυπο.
 */
export function usePathname(): string {
  const pathname = useNextPathname();
  return pathname ? stripWorkspace(pathname) : '';
}
