'use client';

/**
 * ΤΟ ΣΥΝΟΡΟ ΤΗΣ ΠΛΟΗΓΗΣΗΣ — ένα σημείο βάζει τον χώρο στη διεύθυνση
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΛΥΝΕΙ (ADR-787 §5.3 θ)
 * ─────────────────────────────────────────────────────────────────────────────
 * Η Φάση 3 μετακίνησε 180+ σελίδες κάτω από `/o/[workspace]` και **τίποτε άλλο**:
 * κάθε `/dashboard`, `/properties`, `/contacts` έγινε **404**. Το `workspacePath`
 * υπήρχε ήδη, με **μηδέν καταναλωτές**, και το docblock του μετρούσε **285
 * σημεία** — ο συγγραφέας ήξερε το μέγεθος και σταμάτησε.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ **ΕΝΑ ΣΥΝΟΡΟ** ΚΑΙ ΟΧΙ «ΤΑ ΜΗΤΡΩΑ ΜΑΘΑΙΝΟΥΝ ΤΟ ΠΡΟΘΕΜΑ»
 * ─────────────────────────────────────────────────────────────────────────────
 * Τα μητρώα είναι `const` αντικείμενα **χωρίς πρόσβαση στον ενεργό χώρο** — ο
 * χώρος είναι **ανά αίτημα**. «Να μάθουν το πρόθεμα» σημαίνει να γίνουν
 * συναρτήσεις που δέχονται `alias`, δηλαδή **και τα 276 σημεία πλοήγησης πρέπει
 * να θυμούνται να τον δώσουν**. Είναι το σχήμα «κανόνας που πρέπει να θυμάσαι»,
 * που σε αυτό το repo έχει αποτύχει **μετρημένα τέσσερις φορές** (CHECK 3.34
 * απόκλιση 63 · 3.37 «18 vs 26» · 3.49 «60» · 3.57 «19/20»).
 *
 * Εδώ τα 276 σημεία **δεν αλλάζουν**: εξακολουθούν να γράφουν `/projects`.
 *
 * 🏆 **Το πρότυπο, και πού πάμε ένα σκαλί πάνω.** Το **next-intl** λύνει
 * *δομικά ταυτόσημο* πρόβλημα (υποχρεωτικό δυναμικό πρόθεμα σε κάθε εσωτερική
 * διεύθυνση): το `createNavigation()` δίνει `Link`/`useRouter` που **προσθέτουν**
 * και `usePathname` που **αφαιρεί** — *«when the user is on `/en`, this will be
 * `/`»*. Είναι **ακριβώς** οι δύο κατευθύνσεις που το `workspace-path.ts` είχε
 * ήδη γράψει. Το next-intl όμως στηρίζεται στο να **θυμάσαι** να εισάγεις από
 * το δικό του module (η κοινότητα προτείνει ESLint `no-restricted-imports` —
 * δηλαδή **lint**, που εδώ είναι «σχόλιο χωρίς πύλη», CHECK 3.36). Εδώ την
 * παράκαμψη τη φυλά **πύλη με κλειστό σύνολο και υποχρεωτικό λόγο** (CHECK 3.61).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔶 ΔΗΛΩΜΕΝΟ ΟΡΙΟ — ΤΟ ΣΥΝΟΡΟ ΕΙΝΑΙ ΤΟΥ **ΠΕΛΑΤΗ**
 * ─────────────────────────────────────────────────────────────────────────────
 * Ο ενεργός χώρος διαβάζεται με hooks, άρα αυτό το module είναι `'use client'`.
 * Ένα **Server Component** έχει τον χώρο **αυτούσιο** στο `params.workspace` και
 * καλεί απευθείας το {@link workspacePath} — ίδια διάκριση που κάνει και το
 * next-intl, όπου το `redirect` απαιτεί **ρητό** locale.
 * *(Μετρήθηκε ότι το κενό είναι ~μηδενικό: μόλις **2** αρχεία σε όλο το `src/`
 * εισάγουν `next/link` χωρίς `'use client'`, και το ένα είναι το `/debug`, που
 * ζει **εκτός** χώρου εξ ορισμού.)*
 *
 * @module lib/workspace/navigation
 */

import NextLink from 'next/link';
import { usePathname as useNextPathname, useRouter as useNextRouter } from 'next/navigation';
import type { AnchorHTMLAttributes, ForwardedRef } from 'react';
import { forwardRef, useCallback, useMemo } from 'react';

import { extractWorkspaceSegment, stripWorkspace, workspacePath } from './workspace-path';
import type { AppHref } from './route-worlds';
import { isInsideWorkspace } from './workspace-scope';

// =============================================================================
// 1. ΠΟΙΟΣ ΕΙΝΑΙ Ο ΕΝΕΡΓΟΣ ΧΩΡΟΣ
// =============================================================================

/**
 * **Ο χώρος που ονομάζει η ΤΡΕΧΟΥΣΑ ΔΙΕΥΘΥΝΣΗ** — ή `null` αν δεν ονομάζει κανέναν.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔑 ΜΙΑ ΠΗΓΗ, ΚΑΙ ΤΟ `null` ΔΕΝ ΕΙΝΑΙ ΕΛΛΕΙΨΗ — ΕΙΝΑΙ ΑΝΑΘΕΣΗ
 * ─────────────────────────────────────────────────────────────────────────────
 * Η διεύθυνση είναι το **ρητό αίτημα** του ανθρώπου, και **διατηρείται αυτούσια**:
 * αν βρίσκεται στο `/o/comp_…/projects`, οι σύνδεσμοί του μένουν στη μορφή
 * **ταυτότητας** και δεν πηδούν σιωπηλά σε ψευδώνυμο. Μια διεύθυνση που αλλάζει
 * μορφή στο πάτημα ενός συνδέσμου σπάει το «γύρω πίσω» και τους σελιδοδείκτες.
 *
 * 🔴 **ΓΙΑΤΙ ΔΕΝ ΥΠΑΡΧΕΙ ΔΕΥΤΕΡΗ ΠΗΓΗ — ΚΑΙ ΤΟ ΠΛΗΡΩΣΑΜΕ ΓΙΑ ΝΑ ΤΟ ΜΑΘΟΥΜΕ.**
 * Η πρώτη γραφή έπεφτε πίσω στα claims (`useAuth`). Δύο μετρημένα ελαττώματα:
 *
 * 1. **ΓΡΑΦΟΣ**: έσερνε `useAuth → AuthContext → @firebase/auth` σε **κάθε έναν**
 *    από τους 133 καταναλωτές. Ζωντανή απόδειξη: η σουίτα του
 *    `ContactQuotesSection` έσπασε με `ReferenceError: fetch is not defined`
 *    **πριν τρέξει test**. Το ίδιο βάρος ταξιδεύει και στο **bundle**.
 * 2. **ΟΡΘΟΤΗΤΑ**: ο πελάτης **μάντευε** τον χώρο από ένα claim. Ο διακομιστής
 *    τον **επαληθεύει** (`decideMembership`). Ένα claim που έχει ανακληθεί δίνει
 *    σύνδεσμο προς γραφείο όπου ο άνθρωπος **δεν είναι πια μέλος**.
 *
 * ⇒ Όταν η διεύθυνση δεν ονομάζει χώρο, ο σύνδεσμος **μένει ωμός** και τον
 * αναλαμβάνει το **δίχτυ** (`(app)/[...unprefixed]`), που αποφασίζει με
 * **κριμένη** ταυτότητα. Κόστος: **μία** ανακατεύθυνση, και **μόνο** στη σπάνια
 * μετάβαση από δημόσια/ουδέτερη οθόνη προς τα μέσα — όχι στην πλοήγηση εντός
 * εφαρμογής, όπου η διεύθυνση **πάντα** ονομάζει χώρο.
 *
 * ⚠️ **ΔΕΝ είναι απόδειξη, είναι αίτημα** (Ε-5 §2): χρησιμεύει **μόνο** για να
 * κατασκευαστεί διεύθυνση. Την άδεια την κρίνει αποκλειστικά ο διακομιστής.
 *
 * ⛔ **ΜΗΝ ξαναφέρεις εδώ `useAuth` ούτε κανένα claim.** Το φυλά η άγκυρα `Λ2`.
 */
export function useWorkspaceAlias(): string | null {
  const pathname = useNextPathname();
  return pathname ? extractWorkspaceSegment(pathname) : null;
}

// =============================================================================
// 2. Η ΚΑΤΑΣΚΕΥΗ ΤΗΣ ΔΙΕΥΘΥΝΣΗΣ
// =============================================================================

/**
 * **Βάζει τον χώρο σε μια διεύθυνση — αν και μόνο αν της ανήκει.**
 *
 * Καθαρή συνάρτηση: ο κριτής είναι το {@link isInsideWorkspace}, η πράξη το
 * {@link workspacePath}. Εδώ **δεν κρίνεται τίποτα** — γι' αυτό μπορεί να
 * δοκιμαστεί χωρίς React.
 *
 * ⚠️ **`alias === null` ⇒ ο σύνδεσμος μένει ΩΜΟΣ, επίτηδες.** Σημαίνει «η
 * τρέχουσα διεύθυνση δεν ονομάζει χώρο, άρα δεν ξέρω — και **δεν μαντεύω**».
 * Την απάντηση τη δίνει το **δίχτυ** στον διακομιστή, με κριμένη ταυτότητα.
 * Ένα `?? PERSONAL_WORKSPACE_ALIAS` εδώ θα έστελνε κάθε μέλος οργανισμού στον
 * **ιδιωτικό** του χώρο — σιωπηλά, και σε λάθος δεδομένα.
 */
export function workspaceHref(href: string, alias: string | null): string {
  if (alias === null) return href;
  return isInsideWorkspace(href) ? workspacePath(alias, href) : href;
}

/** Το {@link workspaceHref} με τον ενεργό χώρο ήδη λυμένο. */
export function useWorkspaceHref(): (href: string) => string {
  const alias = useWorkspaceAlias();
  return useCallback((href: string) => workspaceHref(href, alias), [alias]);
}

