/**
 * **Ο χώρος που ονομάζει η ΤΡΕΧΟΥΣΑ ΔΙΕΥΘΥΝΣΗ** — ή `null` αν δεν ονομάζει κανέναν.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔑 ΜΙΑ ΠΗΓΗ, ΚΑΙ ΤΟ `null` ΔΕΝ ΕΙΝΑΙ ΕΛΛΕΙΨΗ — ΕΙΝΑΙ ΑΝΑΘΕΣΗ
 * ─────────────────────────────────────────────────────────────────────────────
 * Η διεύθυνση είναι το **ρητό αίτημα** του ανθρώπου, και **διατηρείται αυτούσια**:
 * αν βρίσκεται στο `/o/comp_…/projects`, οι σύνδεσμοί του μένουν στη μορφή
 * **ταυτότητας** και δεν πηδούν σιωπηλά σε ψευδώνυμο. Μια διεύθυνση που αλλάζει
 * μορφή στο πάτημα ενός συνδέσμου σπάει το «γύρω πίσω» και τους σελιδοδείκτες.
 *
 * 🔴 **ΓΙΑΤΙ ΔΕΝ ΥΠΑΡΧΕΙ ΔΕΥΤΕΡΗ ΠΗΓΗ — ΚΑΙ ΤΟ ΠΛΗΡΩΣΑΜΕ ΓΙΑ ΝΑ ΤΟ ΜΑΘΟΥΜΕ.**
 * Η πρώτη γραφή έπεφτε πίσω στα claims (`useAuth`). Δύο μετρημένα ελαττώματα:
 *
 * 1. **ΓΡΑΦΟΣ**: έσερνε `useAuth → AuthContext → @firebase/auth` σε **κάθε έναν**
 *    από τους 133 καταναλωτές. Ζωντανή απόδειξη: η σουίτα του
 *    `ContactQuotesSection` έσπασε με `ReferenceError: fetch is not defined`
 *    **πριν τρέξει test**. Το ίδιο βάρος ταξιδεύει και στο **bundle**.
 * 2. **ΟΡΘΟΤΗΤΑ**: ο πελάτης **μάντευε** τον χώρο από ένα claim. Ο διακομιστής
 *    τον **επαληθεύει** (`decideMembership`). Ένα claim που έχει ανακληθεί δίνει
 *    σύνδεσμο προς γραφείο όπου ο άνθρωπος **δεν είναι πια μέλος**.
 *
 * ⇒ Όταν η διεύθυνση δεν ονομάζει χώρο, ο σύνδεσμος **μένει ωμός** και τον
 * αναλαμβάνει το **δίχτυ** (`(app)/[...unprefixed]`), που αποφασίζει με
 * **κριμένη** ταυτότητα. Κόστος: **μία** ανακατεύθυνση, και **μόνο** στη σπάνια
 * μετάβαση από δημόσια/ουδέτερη οθόνη προς τα μέσα — όχι στην πλοήγηση εντός
 * εφαρμογής, όπου η διεύθυνση **πάντα** ονομάζει χώρο.
 *
 * ⚠️ **ΔΕΝ είναι απόδειξη, είναι αίτημα** (Ε-5 §2): χρησιμεύει **μόνο** για να
 * κατασκευαστεί διεύθυνση. Την άδεια την κρίνει αποκλειστικά ο διακομιστής.
 *
 * ⛔ **ΜΗΝ ξαναφέρεις εδώ `useAuth` ούτε κανένα claim.** Το φυλά η άγκυρα `Λ2`.
 */
export function useWorkspaceAlias(): string | null {
  const pathname = useNextPathname();
  return pathname ? extractWorkspaceSegment(pathname) : null;
}

