/**
 * «Επιτρέπεται αυτό το ψευδώνυμο;» — οι τρεις κανόνες, μία φορά
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΛΥΝΕΙ (ADR-787 §5.3 δ · Ε-5 §8)
 * ─────────────────────────────────────────────────────────────────────────────
 * **Ψ1** — μοναδικός είναι ο **σκελετός**, όχι το κείμενο (UTS #39).
 * **Ψ2** — **ένα σενάριο γραφής** ανά ψευδώνυμο· καμία μίξη.
 * **Ψ3** — **κλειστό σύνολο** δεσμευμένων λέξεων.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΤΡΕΙΣ ΚΑΝΟΝΕΣ ΚΑΙ ΟΧΙ ΕΝΑΣ ΜΕ «Ή»
 * ─────────────────────────────────────────────────────────────────────────────
 * Έχουν **διαφορετική θεραπεία** (μάθημα CHECK 3.41):
 *
 * | | τι λέει στον άνθρωπο |
 * |---|---|
 * | **Ψ1** | *«υπάρχει άλλο που **φαίνεται** ίδιο»* ⇒ **διάλεξε άλλο όνομα** |
 * | **Ψ2** | *«ανακάτεψες αλφάβητα»* ⇒ **γράψ' το ξανά σε ένα** |
 * | **Ψ3** | *«αυτή η λέξη ανήκει στο σύστημα»* ⇒ **δεν θα ελευθερωθεί ποτέ** |
 *
 * Ένας κανόνας με «ή» θα έλεγε *«μη έγκυρο»* και στις τρεις περιπτώσεις, και ο
 * άνθρωπος θα ξαναδοκίμαζε **το ίδιο πράγμα**.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠️ Ο Ψ2 ΕΙΝΑΙ ΑΥΤΟΣ ΠΟΥ ΚΑΝΕΙ ΤΑ ΕΛΛΗΝΙΚΑ ΕΦΙΚΤΑ
 * ─────────────────────────────────────────────────────────────────────────────
 * Χωρίς αυτόν, το `Νestor` (ελληνικό `Ν` + λατινικά) θα ήταν *γραμματικά* έγκυρο
 * και θα το έπιανε **μόνο** ο Ψ1 — δηλαδή μόνο **αν** υπήρχε ήδη το `Nestor`.
 * Με τον Ψ2, η μίξη απορρίπτεται **πάντα**, ακόμα και σε άδειο μητρώο. Είναι το
 * προφίλ *«Highly Restrictive»* του UTS #39, και το ίδιο κάνουν οι φυλλομετρητές:
 * ο Firefox *«never permits Latin to mix with Cyrillic or Greek in the same
 * label»*.
 *
 * ⛔ **ΜΗΝ** χαλαρώσεις τον Ψ2 για να «περάσει» ένα όνομα με ελληνικά και λατινικά
 *    μαζί (π.χ. `παγωνης-sa`): η θεραπεία είναι να γραφτεί σε **ένα** αλφάβητο.
 *
 * @module lib/workspace/alias-rules
 */

import 'server-only';

import {
  ALIAS_MAX_LENGTH,
  ALIAS_MIN_LENGTH,
  ALIAS_PATTERN,
  PERSONAL_WORKSPACE_ALIAS,
  type AliasVerdict,
} from '@/types/workspace-alias';
import { skeleton } from '@/lib/unicode/skeleton';

// =============================================================================
// Ψ3 — ΤΟ ΚΛΕΙΣΤΟ ΣΥΝΟΛΟ ΔΕΣΜΕΥΜΕΝΩΝ ΛΕΞΕΩΝ
// =============================================================================

/**
 * Λέξεις που **δεν** μπορεί να πάρει γραφείο, γιατί το σύστημα τις χρησιμοποιεί
 * **στο ίδιο επίπεδο διαδρομής** με τα ψευδώνυμα (δηλαδή αμέσως μετά το `/o/`).
 *
 * 🔑 **ΓΙΑΤΙ ΕΙΝΑΙ ΤΟΣΟ ΜΙΚΡΟ ΤΟ ΣΥΝΟΛΟ — ΚΑΙ ΓΙΑΤΙ ΑΥΤΟ ΕΙΝΑΙ ΤΟ ΚΕΡΔΟΣ ΤΟΥ ΔΕΙΚΤΗ.**
 * Αν το ψευδώνυμο ζούσε στη **ρίζα** (μοντέλο GitHub), οι δεσμευμένες λέξεις θα
 * ήταν **99**, από **τέσσερις ασύνδετες πηγές** που κανείς δεν συγχρονίζει:
 * 45 πρώτα segments σελίδων · 35 `SCANNER_PATHS` του `src/middleware.ts` ·
 * 81 φάκελοι `/api` · 17 εγγραφές `public/` *(μετρημένο, ADR-787 §5.3 α)*.
 * Πίσω από τον δείκτη `/o/`, ο χώρος ονομάτων είναι **δικός μας και άδειος**.
 *
 * ⚠️ **Η ΣΥΓΚΡΟΥΣΗ ΕΧΕΙ ΗΔΗ ΣΥΜΒΕΙ ΜΙΑ ΦΟΡΑ ΣΤΟ REPO**: το `/debug` είναι **και**
 * υπαρκτή σελίδα **και** `SCANNER_PATH`, άρα απαντά **404 σε κάθε περιβάλλον** —
 * δύο σελίδες που δεν ανοίγουν ποτέ. Ένα γραφείο ονόματι `shell` ή `backup` θα
 * εξαφανιζόταν με τον **ίδιο** μηχανισμό.
 *
 * ⛔ **ΜΗΝ γράψεις εδώ λέξεις «για σιγουριά»** *(`admin`, `settings`, `api`…)*:
 *    ζουν **κάτω** από το `/o/<ψευδώνυμο>/`, όχι **δίπλα** του, άρα δεν
 *    συγκρούονται — και μια δεσμευμένη λέξη χωρίς σύγκρουση αφαιρεί από τον
 *    χρήστη ένα όνομα **χωρίς λόγο**.
 *
 * ⚠️ **Η συμφωνία με το δέντρο ΔΕΝ φυλάσσεται από εδώ.** Αν κάποτε γεννηθεί
 *    `src/app/(app)/o/new/page.tsx`, η λέξη `new` πρέπει να μπει εδώ — και αυτό
 *    το επιβάλλει η **πύλη** (ADR-787 §5.3 ζ). Μια σταθερά που ελέγχει τον εαυτό
 *    της δεν είναι φρουρός.
 */
const RESERVED_ALIASES: ReadonlyMap<string, string> = new Map([
  [
    PERSONAL_WORKSPACE_ALIAS,
    'Ο ΙΔΙΩΤΙΚΟΣ ΧΩΡΟΣ (ADR-787 Ε-5 §5). Δεν είναι φάκελος — είναι τιμή ψευδωνύμου, άρα δεν μπορεί να ανακαλυφθεί σαρώνοντας το δέντρο και ΠΡΕΠΕΙ να δηλωθεί. Γραφείο με αυτό το όνομα θα έκρυβε τον ιδιωτικό χώρο ΚΑΘΕ ανθρώπου.',
  ],
]);

/** Ο λόγος για τον οποίο μια λέξη είναι δεσμευμένη — `null` αν δεν είναι. */
export function reservedReason(candidate: string): string | null {
  return RESERVED_ALIASES.get(candidate.toLowerCase()) ?? null;
}

/** Το κλειστό σύνολο, για την πύλη και τις άγκυρες. */
export function reservedAliases(): readonly string[] {
  return [...RESERVED_ALIASES.keys()];
}

// =============================================================================
// Ψ2 — ΕΝΑ ΣΕΝΑΡΙΟ ΓΡΑΦΗΣ
// =============================================================================

/**
 * Τα σενάρια που αναγνωρίζουμε ρητά. Ό,τι δεν είναι γράμμα *(ψηφίο, παύλα)*
 * είναι **Common** και δεν μετράει ως σενάριο — αλλιώς κάθε `a1-domi` θα ήταν
 * «μικτό».
 */
const SCRIPTS: ReadonlyArray<readonly [name: string, test: RegExp]> = [
  ['Latin', /\p{Script=Latin}/u],
  ['Greek', /\p{Script=Greek}/u],
];

/**
 * Ποια σενάρια γραφής εμφανίζονται· `null` σε **άγνωστο** σενάριο.
 *
 * ⚠️ **Fail-closed**: ένα γράμμα που δεν είναι ούτε λατινικό ούτε ελληνικό
 * (κυριλλικό `а`, αρμενικό `օ` — και τα δύο **οπτικά ταυτόσημα** με λατινικά)
 * επιστρέφει `null`, δηλαδή **απόρριψη**. Η εναλλακτική *«αγνόησέ το»* θα άφηνε
 * να περάσει ακριβώς η κατηγορία χαρακτήρων που κανείς δεν περιμένει.
 */
function scriptsOf(value: string): ReadonlySet<string> | null {
  const found = new Set<string>();
  for (const ch of value) {
    if (!/\p{Letter}/u.test(ch)) continue; // ψηφίο ή παύλα — Common
    const hit = SCRIPTS.find(([, test]) => test.test(ch));
    if (!hit) return null;
    found.add(hit[0]);
  }
  return found;
}

// =============================================================================
// Η ΚΡΙΣΗ — ΣΕΙΡΑ ΣΥΜΒΟΛΑΙΟ
// =============================================================================

/**
 * Κρίνει τη **μορφή** ενός υποψήφιου ψευδωνύμου (Ψ2 + Ψ3 + γραμματική).
 *
 * ⚠️ **Ο Ψ1 ΔΕΝ ΚΡΙΝΕΤΑΙ ΕΔΩ**, και είναι σκόπιμο: η μοναδικότητα του σκελετού
 * απαιτεί **ανάγνωση της βάσης**, ενώ όλα τα παραπάνω απαντιούνται από το ίδιο
 * το κείμενο. Ο διαχωρισμός επιτρέπει στον πελάτη να πάρει άμεση απάντηση για
 * τη μορφή, **χωρίς** να μάθει ποια ψευδώνυμα υπάρχουν — που θα ήταν
 * **απαρίθμηση**, απαγορευμένη από το Ε-5 §4 #1.
 *
 * ⚠️ **Η ΣΕΙΡΑ ΕΙΝΑΙ ΣΥΜΒΟΛΑΙΟ**: δεσμευμένη → μήκος → χαρακτήρες → σενάριο.
 *
 * 🔴 **ΤΟ «ΔΕΣΜΕΥΜΕΝΗ» ΚΡΙΝΕΤΑΙ ΠΡΩΤΟ, ΚΑΙ ΤΟ ΒΡΗΚΕ ΑΓΚΥΡΑ.** Η πρώτη γραφή το
 * είχε **τελευταίο** — και τότε το `me`, που έχει **δύο** χαρακτήρες ενώ το
 * ελάχιστο είναι **τρεις**, έπεφτε στο `too-short` και **ο έλεγχος δέσμευσης δεν
 * φτανόταν ΠΟΤΕ**. Ο άνθρωπος θα διάβαζε *«πολύ κοντό»* για λέξη που **δεν
 * πρόκειται να ελευθερωθεί σε κανένα μήκος**, και θα δοκίμαζε ξανά.
 *
 * ⚠️ Η δέσμευση κρίνεται με **ακριβή ισότητα** (μετά από trim + lowercase), όχι
 * με πρόθεμα — γι' αυτό το `ME!` εξακολουθεί να αναφέρει σωστά
 * *«invalid-characters»*: δεν **είναι** η δεσμευμένη λέξη, μοιάζει με αυτήν.
 */
export function judgeAliasShape(candidate: string): AliasVerdict {
  const alias = candidate.normalize('NFC').trim().toLowerCase();

  const reserved = reservedReason(alias);
  if (reserved) return { ok: false, reason: 'reserved', detail: reserved };

  if (alias.length < ALIAS_MIN_LENGTH) {
    return { ok: false, reason: 'too-short', detail: `ελάχιστο ${ALIAS_MIN_LENGTH} χαρακτήρες` };
  }
  if (alias.length > ALIAS_MAX_LENGTH) {
    return { ok: false, reason: 'too-long', detail: `μέγιστο ${ALIAS_MAX_LENGTH} χαρακτήρες` };
  }
  if (!ALIAS_PATTERN.test(alias)) {
    return {
      ok: false,
      reason: 'invalid-characters',
      detail: 'επιτρέπονται γράμματα, ψηφία και παύλα — η παύλα όχι στην αρχή ή στο τέλος',
    };
  }

  const scripts = scriptsOf(alias);
  if (scripts === null) {
    return { ok: false, reason: 'mixed-script', detail: 'άγνωστο σενάριο γραφής' };
  }
  if (scripts.size > 1) {
    return {
      ok: false,
      reason: 'mixed-script',
      detail: `ανακατεύει ${[...scripts].join(' + ')} — γράψ' το σε ένα αλφάβητο`,
    };
  }

  return { ok: true, alias, skeleton: skeleton(alias) };
}
