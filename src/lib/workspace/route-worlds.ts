/**
 * **Οι δύο κόσμοι διαδρομών** — ο μεταγλωττιστής τους κρατά χωριστά
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΛΥΝΕΙ (ADR-787 §5.3 κ.4 — ο **φρουρός #4**, «κατάλογος διαδρομών»)
 * ─────────────────────────────────────────────────────────────────────────────
 * Μετά το Β3.1 η εφαρμογή έχει **δύο** κόσμους διευθύνσεων:
 *
 * ```
 *   ΜΕΣΑ ΣΕ ΧΩΡΟ                     ΕΚΤΟΣ ΧΩΡΟΥ
 *   /o/[workspace]/projects          /login
 *   /o/[workspace]/contacts/[id]     /terms  ·  /listing/[id]
 * ```
 *
 * Δεν είναι προτίμηση ούτε σύμβαση: είναι **γεγονός του δίσκου**, και το
 * `next typegen` το έχει ήδη γράψει σε ένωση κυριολεκτικών. Εδώ απλώς **ρωτάμε**.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΔΥΟ ΕΡΩΤΗΜΑΤΑ — ΟΧΙ ΔΥΟ ΑΥΘΕΝΤΙΕΣ (ADR-749)
 * ─────────────────────────────────────────────────────────────────────────────
 * Δίπλα ζει το {@link module:lib/workspace/workspace-scope}, με το
 * `isInsideWorkspace(href)`. **Δεν είναι διπλότυπο**, και η διαφορά είναι
 * μετρημένη, όχι αισθητική:
 *
 * | | ρωτά | για | πότε |
 * |---|---|---|---|
 * | **εδώ** | *«ποιες διαδρομές **υπάρχουν**, και σε ποιον κόσμο ανήκει η καθεμία;»* | τα **κυριολεκτικά** σημεία κλήσης | **μεταγλώττιση** |
 * | `isInsideWorkspace` | *«αυτή η συμβολοσειρά που κρατάω **τώρα**, μπαίνει σε χώρο;»* | τα **δυναμικά** *(μετρημένα **190**)* | **χρόνος εκτέλεσης** |
 *
 * Ο μεταγλωττιστής **δεν μπορεί** να δει μια συμβολοσειρά που χτίζεται από
 * δεδομένα· ο κριτής χρόνου εκτέλεσης **δεν μπορεί** να αποτρέψει ένα λάθος πριν
 * προσγειωθεί. Χρειάζονται **και τα δύο**.
 *
 * 🔑 **Επιτρέπεται να υπάρχουν· ΔΕΝ επιτρέπεται να διαφωνήσουν.** Το κλειδώνει
 * το `__tests__/route-catalogue-anchor.test.ts`, που τρέχει τον κριτή πάνω σε
 * **κάθε** πραγματική διαδρομή του `src/app` — όχι σε δείγμα.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔶 ΤΙ ΔΕΝ ΚΑΝΕΙ ΑΚΟΜΑ — δηλωμένο, όχι ξεχασμένο
 * ─────────────────────────────────────────────────────────────────────────────
 * Ο `Link` του συνόρου δέχεται σήμερα `href: string`. Όσο μένει έτσι, το άναμμα
 * του `typedRoutes` **(Γ5)** θα βρει σφάλμα **μόνο μέσα στο wrapper** — και η
 * θεραπεία «βάλε ένα `as Route` εκεί» θα έκανε **κάθε** σημείο κλήσης αόρατο
 * στον μεταγλωττιστή. Το Γ5 θα έβγαινε πράσινο και θα σήμαινε **«κανείς δεν
 * κοίταξε»**. Το {@link AppHref} υπάρχει ώστε το Γ5 να έχει τι να σφίξει.
 *
 * @module lib/workspace/route-worlds
 */

import type { AppRoutes, ParamMap } from '@/types/app-routes';

/** Το πρόθεμα όπως εμφανίζεται **στον κατάλογο** — με το δυναμικό τμήμα άλυτο. */
type WorkspacePrefix = `/o/[workspace]`;

// ─────────────────────────────────────────────────────────────────────────────
// 0. ΣΕΡΒΙΡΕΤΑΙ ≠ ΕΙΝΑΙ ΠΡΟΟΡΙΣΜΟΣ — ΤΟ ΔΙΧΤΥ ΒΓΑΙΝΕΙ ΑΠΟ ΤΟΝ ΚΑΤΑΛΟΓΟ
// ─────────────────────────────────────────────────────────────────────────────

/**
 * **Διαδρομές που το framework σερβίρει αλλά ΚΑΝΕΙΣ δεν επιτρέπεται να τις
 * ζητήσει ως προορισμό** — κλειστό σύνολο, **υποχρεωτικός λόγος** ανά εγγραφή.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΧΩΡΙΣ ΑΥΤΟ Ο ΤΥΠΟΣ ΓΕΝΝΙΕΤΑΙ ΔΙΑΚΟΣΜΗΤΙΚΟΣ — ΜΕΤΡΗΜΕΝΟ, ΟΧΙ ΦΟΒΟΣ
 * ─────────────────────────────────────────────────────────────────────────────
 * Το `/[...unprefixed]` είναι catch-all **στη ρίζα**. Ο ίδιος ο γεννήτορας του
 * Next *(`next/dist/server/lib/router-utils/typegen.js`, `formatRouteToRouteType`)*
 * το μεταφράζει σε **`` `/${CatchAllSlug<T>}` ``** — δηλαδή σε πρότυπο που
 * ταιριάζει με **ΚΑΘΕ** συμβολοσειρά που αρχίζει με `/` και δεν φέρει `?`/`#`.
 * Μπαίνοντας στο σύνολο των δυναμικών, ο κλάδος
 * `T extends \`${DynamicAppHref<infer _>}${Suffix}\`` γίνεται **πάντα αληθής**:
 * κάθε διεύθυνση περνά, ο τύπος βγαίνει **πράσινος**, και σημαίνει **«κανείς δεν
 * κοίταξε»** — το σχήμα που αυτό το repo έχει πληρώσει **οκτώ** φορές.
 *
 * 🔑 Δεν είναι θεωρία: το **ίδιο δίχτυ** είχε ήδη τυφλώσει τον **απαριθμητή**
 * του φρουρού #4 *(ADR-787 §5.3 μ: «κάθε μονοτμηματική διεύθυνση υπαρκτή»,
 * 0 νεκροί με το δίχτυ έναντι 1 χωρίς)*. **Ίδια αιτία, τρίτο όργανο.** Και η
 * κοινότητα του Next το αναφέρει ανεξάρτητα ως λόγο εγκατάλειψης του
 * `typedRoutes` *(Discussion #83182: «too permissive, essentially disabling type
 * safety»)* — εκεί όμως **παραιτούνται**· εδώ αφαιρείται **η αιτία**.
 *
 * ⚠️ **Η ΣΗΜΑΣΙΟΛΟΓΙΑ ΗΤΑΝ ΗΔΗ ΓΡΑΜΜΕΝΗ, ΕΛΕΙΠΕ Η ΕΚΤΕΛΕΣΗ.** Το docblock του
 * ίδιου του διχτυού *(`app/(app)/[...unprefixed]/page.tsx`)* λέει κατά λέξη
 * **«ΕΙΝΑΙ ΔΙΧΤΥ, ΟΧΙ ΜΗΧΑΝΙΣΜΟΣ»** και ότι κίνηση από **μέσα** στην εφαρμογή
 * προς τα εκεί **είναι εύρημα**. Εδώ η πρόταση αυτή λέγεται στον **μεταγλωττιστή**
 * *(σχήμα CHECK 3.36: ένα anchor χωρίς gate είναι σχόλιο)*.
 *
 * ⛔ **ΜΗΝ προσθέσεις εγγραφή για να «περάσει» κάτι.** Μια διαδρομή που κάποιος
 * θέλει να ζητήσει **είναι** προορισμός· αν λείπει από τον κατάλογο, λείπει η
 * **σελίδα**.
 *
 * ⚠️ Το `/api/storage/file/[...path]` **δεν** μπαίνει εδώ, και η διαφορά είναι
 * μετρημένη: το πρόθεμά του είναι κυριολεκτικό, άρα το πρότυπό του δεσμεύεται
 * σε **δικό του υπόδεντρο** και δεν καταπίνει τίποτε άλλο.
 */
export const NON_DESTINATION_ROUTES = {
  '/[...unprefixed]':
    'ΤΟ ΔΙΧΤΥ. Πιάνει ό,τι ΔΕΝ είχε προορισμό και το ξαναστέλνει με κριμένη ταυτότητα. ' +
    'Κανείς δεν πλοηγεί ΠΡΟΣ αυτό — και ως catch-all ΣΤΗ ΡΙΖΑ ταιριάζει με κάθε ' +
    'διεύθυνση, δηλαδή θα ξέπλενε ΟΛΟΚΛΗΡΟ τον έλεγχο.',
} as const;

/** Το όνομα κάθε μη-προορισμού — η γλώσσα των τύπων για το πιο πάνω σύνολο. */
type NonDestinationRoute = keyof typeof NON_DESTINATION_ROUTES;

/**
 * Ο κατάλογος **αφού** βγουν οι μη-προορισμοί.
 *
 * 🔑 Είναι η **μόνη** ρίζα που διαβάζουν τα παρακάτω: αν κάποιος ρωτήσει
 * απευθείας το `AppRoutes`, ξαναφέρνει το δηλητήριο **σιωπηλά**.
 */
type DestinationRoute = Exclude<AppRoutes, NonDestinationRoute>;

/**
 * Οι διαδρομές που ζουν **μέσα** σε χώρο, όπως τις ονομάζει ο κατάλογος
 * *(δηλαδή με `[workspace]`, όχι με ψευδώνυμο)*.
 */
export type WorkspaceRoute = Extract<DestinationRoute, `${WorkspacePrefix}${string}`>;

/**
 * Η διαδρομή **χωρίς** τον χώρο — η γλώσσα που μιλά ο εσωτερικός κώδικας.
 *
 * 🔑 Αυτό είναι που δέχεται ένας σύνδεσμος **μέσα** σε χώρο: `/projects`, όχι
 * `/o/nikos/projects`. Το πρόθεμα το βάζει το **σύνορο**, μία φορά — γι' αυτό
 * κανένα σημείο κλήσης δεν χρειάζεται να ξέρει το ψευδώνυμο.
 */
export type InWorkspacePath =
  WorkspaceRoute extends `${WorkspacePrefix}${infer Tail}` ? Tail : never;

/**
 * Οι διαδρομές που ζουν **εκτός** χώρου — σύνδεση, νομικές οθόνες, δημόσιες
 * αγγελίες. Ένα πρόθεμα εδώ θα γεννούσε **404**.
 */
export type GlobalRoute = Exclude<DestinationRoute, `${WorkspacePrefix}${string}`>;

/**
 * Ό,τι μπορεί νόμιμα να δεχτεί το σύνορο ως **κυριολεκτική** διεύθυνση.
 *
 * ⚠️ Δεν είναι `string`: μια διεύθυνση που δεν αντιστοιχεί σε **καμία** σελίδα
 * του `src/app` δεν ανήκει σε κανέναν από τους δύο κόσμους — και ο κατάλογος το
 * ξέρει, γιατί τον έγραψε το framework διαβάζοντας τον δίσκο.
 */
export type AppHref = InWorkspacePath | GlobalRoute;

// ─────────────────────────────────────────────────────────────────────────────
// 2. Η ΜΟΡΦΗ ΜΙΑΣ ΓΡΑΜΜΕΝΗΣ ΔΙΕΥΘΥΝΣΗΣ — ΟΧΙ ΤΟΥ ΚΑΤΑΛΟΓΟΥ
// ─────────────────────────────────────────────────────────────────────────────

/**
 * 🔴 **Ο ΚΑΤΑΛΟΓΟΣ ΓΡΑΦΕΙ `/properties/[id]`. ΚΑΝΕΝΑΣ ΑΝΘΡΩΠΟΣ ΔΕΝ ΤΟ ΓΡΑΦΕΙ.**
 *
 * Το {@link AppHref} κρατά τις **αγκύλες**, γιατί έτσι ονομάζει τη σελίδα ο
 * δίσκος. Ένα σημείο κλήσης όμως γράφει `/properties/abc123`. ⇒ Ως τύπος
 * ορίσματος το `AppHref` είναι **δομικά ανίκανο** να δεχτεί δυναμική διεύθυνση
 * — **ακόμα και απολύτως σωστή**. Δεν λείπει αυστηρότητα· λείπει **μορφή**.
 *
 * 🏆 **ΤΟ ΙΔΙΩΜΑ ΕΙΝΑΙ ΤΟΥ NEXT, ΔΙΑΒΑΣΜΕΝΟ ΑΠΟ ΤΗΝ ΠΗΓΗ ΤΟΥ**
 * *(`next/dist/server/lib/router-utils/typegen.js`, `generateLinkTypesFile`,
 * v15.5.22)*: το `RouteImpl<T>` δέχεται στατικά · στατικά **με ερώτημα** · και
 * δυναμικά μέσω `T extends `${DynamicRoutes<infer _>}${Suffix}` ? T : never`
 * — γι' αυτό ο `Link` του είναι **γενικός**. Εδώ αναπαράγεται **ο ίδιος**
 * μηχανισμός, με **δύο** διαφορές που τον κάνουν αυστηρότερο:
 *
 * 1. **Ο κόσμος κρίνεται.** Το `AppHref` είναι `InWorkspacePath | GlobalRoute`,
 *    δηλαδή διαδρομή **χωρίς** πρόθεμα ή διαδρομή **εκτός** χώρου. Ένα
 *    χειρόγραφο `/o/nikos/projects` **δεν** ανήκει σε κανένα από τα δύο ⇒
 *    **σφάλμα μεταγλώττισης**. Το Next δεν έχει καν την έννοια «κόσμος».
 * 2. **Το δίχτυ έχει βγει** *(βλ. {@link NON_DESTINATION_ROUTES})*, αλλιώς όλα
 *    τα παραπάνω είναι διακοσμητικά.
 *
 * 🏆 **ΚΑΙ ΤΟ ΠΑΡΑΓΟΥΜΕ ΣΕ ΕΠΙΠΕΔΟ ΤΥΠΟΥ, ΟΧΙ ΜΕ ΓΕΝΝΗΤΟΡΑ.** Το Next γράφει τα
 * πρότυπα με **χειρισμό συμβολοσειρών σε χρόνο build** και τα αποθηκεύει σε
 * αρχείο — δηλαδή **δεύτερο artifact**, που μπορεί να μπαγιατέψει και θέλει
 * δική του πύλη φρεσκάδας *(το repo έχει ήδη τρεις τέτοιες: CHECK 3.33 · 3.34 ·
 * 3.57)*. Εδώ το {@link WithSlugs} κάνει την **ίδια** αντικατάσταση με αναδρομικό
 * conditional type πάνω στον **ίδιο** κατάλογο ⇒ **κανένα δεύτερο αρχείο, καμία
 * πύλη φρεσκάδας, μηδέν δυνατότητα απόκλισης**.
 */

/** Ό,τι μπορεί να ακολουθεί μια διαδρομή χωρίς να την αλλάζει. */
type SearchOrHash = `?${string}` | `#${string}`;

/** Το ερώτημα είναι **προαιρετικό** — `/projects` και `/projects?a=1` ισοδύναμα νόμιμα. */
type Suffix = '' | SearchOrHash;

/**
 * Ένα **και μόνο ένα** τμήμα διαδρομής.
 *
 * ⚠️ **Η άρνηση του `/` είναι όλο το νόημα**: χωρίς αυτήν, το `/properties/${string}`
 * θα δεχόταν και το `/properties/abc/λάθος/βαθιά` — δηλαδή το πρότυπο μιας
 * σελίδας θα κατάπινε **ολόκληρο** το υπόδεντρό της. Ίδια λογική με το
 * `SafeSlug` του Next, και **ο λόγος που ο τύπος πρέπει να είναι γενικός**:
 * η άρνηση κρίνεται πάνω στο **πραγματικό** κείμενο του σημείου κλήσης.
 */
type SafeSlug<S extends string> = S extends `${string}/${string}`
  ? never
  : S extends `${string}${SearchOrHash}`
    ? never
    : S extends ''
      ? never
      : S;

/** Ένα ή **περισσότερα** τμήματα — το `[...slug]`. Ο `/` επιτρέπεται· το `?`/`#` όχι. */
type CatchAllSlug<S extends string> = S extends `${string}${SearchOrHash}`
  ? never
  : S extends ''
    ? never
    : S;

/** Το `[[...slug]]` — όπως το πάνω, αλλά το **κενό** είναι νόμιμο. */
type OptionalCatchAllSlug<S extends string> = S extends `${string}${SearchOrHash}`
  ? never
  : S;

/**
 * Αντικαθιστά **κάθε** δυναμικό τμήμα του καταλόγου με το αντίστοιχο slug.
 *
 * `/projects/[id]/procurement/po/[poId]` ⇒
 * ``/projects/${SafeSlug<T>}/procurement/po/${SafeSlug<T>}``
 *
 * ⚠️ **Η ΣΕΙΡΑ ΤΩΝ ΚΛΑΔΩΝ ΕΙΝΑΙ ΣΥΜΒΟΛΑΙΟ**: το `[[...x]]` δοκιμάζεται **πριν**
 * το `[...x]`, και εκείνο πριν το `[x]` — αλλιώς το ευρύτερο πρότυπο ταιριάζει
 * πρώτο και το τμήμα κόβεται **στη μέση**, παράγοντας πρότυπο που δεν αντιστοιχεί
 * σε καμία διαδρομή. Η αστοχία θα ήταν **σιωπηλή**: ο τύπος θα υπήρχε και **δεν
 * θα δεχόταν τίποτα**.
 *
 * ⚠️ Είναι **distributive**: το `S` είναι γυμνή παράμετρος, άρα η ένωση των ~50
 * δυναμικών διαδρομών κατανέμεται αυτόματα, μία-μία.
 */
type WithSlugs<S extends string, T extends string> =
  S extends `${infer H}[[...${string}]]${infer R}`
    ? `${H}${OptionalCatchAllSlug<T>}${WithSlugs<R, T>}`
    : S extends `${infer H}[...${string}]${infer R}`
      ? `${H}${CatchAllSlug<T>}${WithSlugs<R, T>}`
      : S extends `${infer H}[${string}]${infer R}`
        ? `${H}${SafeSlug<T>}${WithSlugs<R, T>}`
        : S;

/** Οι διαδρομές **χωρίς** δυναμικό τμήμα — γράφονται αυτούσιες. */
export type StaticAppHref = Exclude<AppHref, `${string}[${string}`>;

/** Οι διαδρομές **με** δυναμικό τμήμα, ως **πρότυπα** που ταιριάζουν με γραμμένο κείμενο. */
export type DynamicAppHref<T extends string = string> = WithSlugs<
  Extract<AppHref, `${string}[${string}`>,
  T
>;

/**
 * **Ό,τι δέχεται νόμιμα το σύνορο πλοήγησης** — ο πλήρης τύπος του Γ5.
 *
 * ⚠️ **ΓΕΝΙΚΟΣ ΕΠΙΤΗΔΕΣ.** Το `T` δεν είναι διακοσμητικό: είναι το **πραγματικό
 * κείμενο** του σημείου κλήσης, και μόνο πάνω του μπορεί να κριθεί αν το slug
 * που γράφτηκε είναι **ένα** τμήμα ή κατά λάθος **τρία**. Ένα μη-γενικό
 * `/properties/${string}` θα δεχόταν ό,τι να ᾽ναι κάτω από το `/properties/`.
 *
 * ⛔ **ΜΗΝ προσθέσεις `| (string & {})` για να «περάσει» κάτι** — αυτό ήταν η
 * κατάσταση **πριν** το Γ5, και το επαναφέρει ολόκληρη.
 * ⛔ **ΜΗΝ προσθέσεις `| `${string}:${string}`` για εξωτερικούς συνδέσμους.**
 * Το Next το έχει *(`WithProtocol`)* επειδή είναι γενικό framework· εδώ
 * **μετρήθηκαν 0** εξωτερικά σημεία στο σύνορο — και τα **δύο** που υπάρχουν στο
 * `src/` είναι ωμά `<a target="_blank" rel="noopener">`, που είναι **ήδη η σωστή
 * απάντηση** *(ένα `Link` προς εξωτερικό URL δεν κάνει ούτως ή άλλως πλοήγηση
 * πελάτη)*. Ένας κλάδος ``${string}:${string}`` θα δεχόταν και το `"foo:bar"`:
 * **διέξοδος με μηδενικό πληθυσμό και πραγματικό κόστος**.
 */
export type WorkspaceHref<T extends string = string> =
  | StaticAppHref
  | `${StaticAppHref}${SearchOrHash}`
  | (T extends `${DynamicAppHref<infer _>}${Suffix}` ? T : never);


/**
 * **Ο ΜΟΝΟΣ κατασκευαστής διευθύνσεων σε όλο το σύστημα** — η SSoT απάντηση
 * στο ερώτημα *«πώς δηλώνει ένα μητρώο ότι η τιμή του είναι πράγματι
 * διεύθυνση;»* (ADR-787 §5.3 ξ, ΒΗΜΑ 2).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 Η ΑΙΤΙΑ ΠΟΥ ΧΡΕΙΑΖΕΤΑΙ — ΜΕΤΡΗΜΕΝΗ, ΟΧΙ ΘΕΩΡΙΑ
 * ─────────────────────────────────────────────────────────────────────────────
 * Επαληθεύτηκε **πειραματικά** με απομονωμένο `tsc`: μια συνάρτηση που
 * επιστρέφει template literal **χωρίς ρητό τύπο επιστροφής** φαρδαίνει **πάντα**
 * σε σκέτο `string` — ακόμα και όταν το σώμα της είναι
 * `/crm/tasks/$${id}`. Δεν είναι κάτι που «ξεχάστηκε»· είναι πώς
 * συμπεραίνει τύπους ο μεταγλωττιστής όταν δεν του πεις τη μορφή. Το `WorkspaceHref`
 * δεν μπορεί να ξεχωρίσει ένα φαρδυμένο `string` από ένα αυθαίρετο.
 *
 * 🔑 **ΓΙΑΤΙ ΜΙΑ ΣΥΝΑΡΤΗΣΗ, ΟΧΙ 15 ΧΕΙΡΟΓΡΑΦΑ ΤΥΠΩΜΕΝΑ RETURN**: επαληθεύτηκε
 * ότι το `typedHref` πιάνει **και** τα μονοτμηματικά δυναμικά (`/crm/leads/[id]`)
 * **και** τα πολυτμηματικά (`/projects/[id]/procurement/po/[poId]`) **και** τα
 * στατικά με ερώτημα (`/spaces/storage?storageId=…`) **και** τον συνδυασμό
 * (`/listing/[id]?ref=…`) — με **ΜΗΔΕΝ** ειδικές περιπτώσεις, επειδή ρωτά τον
 * **ίδιο** ενιαίο τύπο {@link WorkspaceHref} που κρίνει και το σύνορο. Δεύτερη
 * μηχανή κρίσης εδώ θα ήταν το σχήμα του ADR-749.
 *
 * ⚠️ **`T` ΣΥΜΠΕΡΑΙΝΕΤΑΙ ΑΠΟ ΤΟ ΟΡΙΣΜΑ, ΠΟΤΕ ΔΗΛΩΝΕΤΑΙ.** Κάθε χρήση γράφεται
 * `typedHref(`/properties/$${encodeURIComponent(id)}`)` — ΧΩΡΙΣ
 * `<T>` ρητό. Ένα ρητό `<string>` θα ξανάφερνε ακριβώς το πρόβλημα που η
 * συνάρτηση υπάρχει για να λύσει.
 *
 * ⛔ **ΔΕΝ ΕΙΝΑΙ `as Route` με άλλο όνομα.** Το `as` παρακάμπτει τον έλεγχο· το
 * `typedHref` **είναι** ο έλεγχος — μια κατασκευή που δεν ταιριάζει με κανέναν
 * κόσμο **αρνείται να μεταγλωττιστεί εδώ**, στο **ένα** σημείο ορισμού, πριν
 * καν φτάσει σε σημείο κλήσης.
 */
export function typedHref<T extends string>(href: WorkspaceHref<T>): WorkspaceHref<T> {
  return href;
}

/**
 * Στατική διεύθυνση **+ ερώτημα**, όταν η βάση είναι **γνωστή ρίζα** αλλά το
 * περιεχόμενο του ερωτήματος είναι δεδομένα χρόνου εκτέλεσης.
 *
 * 🔑 **Το `Base extends StaticAppHref` είναι όλο το κόλπο**: επειδή το `Base`
 * συμπεραίνεται από το **γραμμένο** όρισμα (π.χ. `'/spaces/storage'`), ο
 * μεταγλωττιστής το στενεύει στο **ΕΝΑ** συγκεκριμένο μέλος, όχι σε ολόκληρη
 * την ένωση — και **αυτό** είναι που κάνει την επιστροφή ελέγξιμη. Περνώντας
 * την ίδια βάση **ήδη φαρδυμένη** σε `string` (π.χ. μέσα από μεταβλητή χωρίς
 * `as const`) παράγει ξανά το πρόβλημα — επαληθεύτηκε πειραματικά.
 */
export function withQuery<Base extends StaticAppHref>(
  base: Base,
  query: string,
): `${Base}${SearchOrHash}` {
  return `${base}?${query}` as `${Base}${SearchOrHash}`;
}

/**
 * **Ο ΔΡΟΜΟΣ #3 — ΔΗΛΩΜΕΝΗ ΕΞΑΙΡΕΣΗ ΜΕ ΛΟΓΟ** (ADR-787 §5.3 ξ §2.γ).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΠΟΤΕ ΩΣ ΠΡΩΤΗ ΕΠΙΛΟΓΗ — ΜΟΝΟ ΟΤΑΝ ΟΙ ΔΥΟ ΑΛΛΟΙ ΔΡΟΜΟΙ ΓΝΗΣΙΑ ΔΕΝ ΙΣΧΥΟΥΝ
 * ─────────────────────────────────────────────────────────────────────────────
 * Το `typedHref`/`withQuery` αποδεικνύουν τη διεύθυνση **στο σημείο κατασκευής**,
 * γιατί εκεί η μορφή είναι ακόμη γραμμένη — μία φορά, με γνωστό σχήμα. Υπάρχουν
 * όμως **γνήσιες** περιπτώσεις όπου η διεύθυνση χτίζεται από **δεδομένα χρόνου
 * εκτέλεσης** με τρόπο που ο μεταγλωττιστής **δεν μπορεί, δομικά, να αποδείξει**
 * — π.χ. δυναμική επιλογή βάσης μέσα από πίνακα ρύθμισης (`ENTITY_ROUTES[type]`,
 * όπου το `type` είναι μεταβλητή), ή η τρέχουσα `usePathname()` με ανανεωμένο
 * ερώτημα (το path είναι ΗΔΗ η έγκυρη τρέχουσα σελίδα — δεν είναι νέος προορισμός).
 *
 * ⛔ **ΔΕΝ είναι `as Route` με άλλο όνομα, για τρεις λόγους**:
 * 1. **Υποχρεωτικός λόγος** — κάθε κλήση φέρει τεκμηρίωση, πρότυπο CHECK 3.35 /
 *    3.50 / 3.58 (*«μια εξαίρεση χωρίς λόγο είναι παράκαμψη με άλλο όνομα»*).
 * 2. **ΕΝΑ σημείο, ελέγξιμο με `grep`** — 15 σκόρπια `as Route` δεν αφήνουν ίχνος·
 *    το `declaredHref(` βρίσκει **κάθε** διαφυγή σε **μία** εντολή.
 * 3. **Runtime guard** — άδειος λόγος **ρίχνει**, δεν περνά σιωπηλά.
 *
 * ⚠️ **ΜΗΝ το χρησιμοποιήσεις όπου το `typedHref` αρκεί.** Αν ο μεταγλωττιστής
 * ΜΠΟΡΕΙ να αποδείξει τη διεύθυνση, η απόδειξη είναι πάντα καλύτερη από τον λόγο.
 */
export function declaredHref(reason: string, href: string): WorkspaceHref {
  if (!reason.trim()) {
    throw new Error(
      '[route-worlds] declaredHref: ο λόγος είναι ΥΠΟΧΡΕΩΤΙΚΟΣ — μια διαφυγή χωρίς ' +
        'λόγο είναι παράκαμψη με άλλο όνομα.',
    );
  }
  return href as WorkspaceHref;
}

/**
 * Τα params μιας διαδρομής χώρου, **χωρίς** το `workspace`.
 *
 * 🏆 Το `workspace` το δίνει το **σύνορο**, όχι ο καλών — άρα το να το ζητούσε ο
 * τύπος θα ήταν λάθος **συμβόλαιο**: θα ανάγκαζε κάθε σημείο κλήσης να ξέρει το
 * ψευδώνυμο, δηλαδή ακριβώς αυτό που το σύνορο υπάρχει για να μη συμβαίνει.
 *
 * ⚠️ Το `ParamMap` το παράγει το Next **από τον δίσκο**. Η αντίστοιχη δυνατότητα
 * του next-intl απαιτεί **χειρόγραφο** `pathnames` — λίστα που μπορεί να
 * αποκλίνει, το σχήμα που εδώ έχει αποτύχει μετρημένα τέσσερις φορές
 * *(CHECK 3.34 · 3.37 · 3.49 · 3.57)*.
 *
 * @example
 * ```ts
 * type P = InWorkspaceParams<'/projects/[id]'>;  // { id: string }  — χωρίς `workspace`
 * ```
 */
export type InWorkspaceParams<T extends InWorkspacePath> =
  `${WorkspacePrefix}${T}` extends keyof ParamMap
    ? Omit<ParamMap[`${WorkspacePrefix}${T}`], 'workspace'>
    : never;
