/**
 * ΑΓΚΥΡΑ — «κρίνει ο τύπος του συνόρου, ή είναι **διακοσμητικός**;»
 *
 * ADR-787 §5.3 ξ — το **Γ5**, ο φρουρός #1.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΔΥΟ ΚΡΙΤΕΣ ΣΕ ΕΝΑ ΑΡΧΕΙΟ — ΚΑΙ ΓΙΑΤΙ ΚΑΝΕΝΑΣ ΤΟΥΣ ΔΕΝ ΑΡΚΕΙ
 * ─────────────────────────────────────────────────────────────────────────────
 * Το Γ5 είναι **αποκλειστικά** αλλαγή τύπων ⇒ **αόρατη στο jest**. Ένα σκέτο
 * jest test εδώ θα ήταν πράσινο με τον τύπο σβηστό — το σχήμα «0 = κανείς δεν
 * κοίταξε», μέσα στο βήμα που υπάρχει για να το πιάνει. Γι' αυτό:
 *
 * | ομάδα | ποιος την κρίνει | τι αποδεικνύει |
 * |---|---|---|
 * | **Τ** — τα σύνορα του τύπου | ο **`tsc`** *(`npm run typecheck`)* | ο τύπος **απορρίπτει** ό,τι πρέπει |
 * | **Δ** — το κλειστό σύνολο | το **jest** *(`jest-suite.yml`, CHECK 3.54)* | το δηλητήριο **δεν μπορεί να επιστρέψει** |
 *
 * ⚠️ **ΤΟ `@ts-expect-error` ΔΕΝ ΕΙΝΑΙ `@ts-ignore`** *(που απαγορεύεται ρητά,
 * ENTERPRISE #4)*: το `@ts-ignore` **κρύβει** σφάλμα· το `@ts-expect-error` το
 * **ΑΠΑΙΤΕΙ** — αν το σφάλμα πάψει να συμβαίνει, ο `tsc` βγάζει *«Unused
 * '@ts-expect-error' directive»* και **κοκκινίζει**. Είναι ο **μοναδικός**
 * μηχανισμός της TypeScript όπου «δεν βρήκα τίποτα» **είναι αποτυχία** — δηλαδή
 * ακριβώς ο παρονομαστής που λείπει από κάθε πύλη που έχει μετρήσει «0» εδώ.
 *
 * ⚠️ **ΚΑΜΙΑ ΝΕΑ ΜΗΧΑΝΗ**: ο απαριθμητής είναι ο **ίδιος** `enumerateRoutes` του
 * χρησμού SSR (CHECK 3.51) που καταναλώνει ήδη και το
 * `route-catalogue-anchor.test.ts`. Τρίτος απαριθμητής θα ήταν τρίτη αλήθεια
 * (ADR-749).
 */

import path from 'path';

import type { WorkspaceHref } from '../route-worlds';
import { NON_DESTINATION_ROUTES } from '../route-worlds';

interface RouteRecord {
  readonly file: string;
  readonly url: string;
  readonly dynamic: boolean;
}

interface RouteOracle {
  readonly enumerateRoutes: (projectRoot: string, appDir?: string) => RouteRecord[];
}

// eslint-disable-next-line @typescript-eslint/no-var-requires
const oracle = require('scripts/lib/i18n-ssr/oracle') as RouteOracle;

const PROJECT_ROOT = path.resolve(__dirname, '..', '..', '..', '..');

/**
 * **Ποιο catch-all είναι δηλητήριο;** — και το κριτήριο είναι **μετρημένο**, όχι
 * «όλα τα catch-all».
 *
 * Ένα `[...x]` **στη ρίζα** μεταφράζεται σε `` `/${CatchAllSlug<T>}` `` και
 * ταιριάζει με **κάθε** διεύθυνση. Ένα `[...path]` **κάτω από κυριολεκτικό
 * πρόθεμα** *(`/api/storage/file/[...path]`)* δεσμεύεται στο **δικό του**
 * υπόδεντρο και δεν καταπίνει τίποτε άλλο. Κριτήριο «κάθε catch-all» θα
 * απαιτούσε δήλωση για το δεύτερο — **ψευδώς θετικό πάνω σε σωστό κώδικα**,
 * δηλαδή ο δρόμος προς την παράκαμψη.
 */
const ROOT_CATCH_ALL = /^\/\[\.\.\./;

describe('Γ5 · Δ — ΤΟ ΚΛΕΙΣΤΟ ΣΥΝΟΛΟ ΤΩΝ ΜΗ-ΠΡΟΟΡΙΣΜΩΝ (κρίνει το jest)', () => {
  const routes = oracle.enumerateRoutes(PROJECT_ROOT);
  const declared = Object.keys(NON_DESTINATION_ROUTES).sort();

  test('Δ1 — ΚΑΘΕ catch-all στη ρίζα είναι ΔΗΛΩΜΕΝΟΣ μη-προορισμός', () => {
    // 🔴 Ο ΦΡΟΥΡΟΣ ΤΟΥ ΔΗΛΗΤΗΡΙΟΥ. Ένα δεύτερο δίχτυ που προσγειώνεται χωρίς
    //    δήλωση ξαναφέρνει το `/${CatchAllSlug<T>}` στο σύνολο των δυναμικών ⇒
    //    ο τύπος δέχεται τα πάντα ⇒ το Γ5 γίνεται πράσινο σημαίνοντας «κανείς
    //    δεν κοίταξε». Το `Δ4` του route-catalogue-anchor κλειδώνει το ΠΛΗΘΟΣ·
    //    αυτό εδώ κλειδώνει ότι το πλήθος **έγινε γνωστό στον μεταγλωττιστή**.
    // ⚠️ ΤΟ ΚΡΙΤΗΡΙΟ ΒΓΑΙΝΕΙ ΑΠΟ ΤΟ `file`, ΠΟΤΕ ΑΠΟ ΤΟ `url` — μετρημένο:
    //    ο απαριθμητής δίνει στο δίχτυ **συνθετικό** url (`/ssr-probe`), γιατί
    //    τον έγραψε ο χρησμός SSR που χρειάζεται **διεύθυνση να ζητήσει**. Ένα
    //    φίλτρο πάνω στο `url` θα επέστρεφε **κενό** και το Δ1 θα ήταν πράσινο
    //    χωρίς να έχει δει το δίχτυ — μέσα στην άγκυρα που υπάρχει γι' αυτό.
    //    Το `file` είναι **γεγονός του δίσκου**· το `url` είναι αναπαραγωγή.
    const onDisk = routes
      .map(toRouteName)
      .filter((name) => ROOT_CATCH_ALL.test(name))
      .sort();

    expect(onDisk).toEqual(declared);
  });

  test('Δ2 — καμία ΟΡΦΑΝΗ δήλωση: ό,τι δηλώνεται, υπάρχει', () => {
    // Χωρίς αυτό το σύνολο σαπίζει σιωπηλά: μια δήλωση για διαδρομή που
    // διαγράφηκε δεν βλάπτει σήμερα, αλλά διδάσκει ότι το σύνολο είναι
    // διακοσμητικό — και ο επόμενος προσθέτει εγγραφή «για σιγουριά».
    const names = new Set(routes.map(toRouteName));
    expect(declared.filter((d) => !names.has(d))).toEqual([]);
  });

  test('Δ3 — κάθε δήλωση φέρει ΛΟΓΟ, όχι απλώς όνομα', () => {
    // Πρότυπο CHECK 3.35/3.50/3.58: δήλωση χωρίς λόγο είναι παράκαμψη με άλλο
    // όνομα. Το κατώφλι δεν είναι αισθητικό — «ok» δεν είναι λόγος.
    const MIN_REASON = 40;
    const thin = Object.entries(NON_DESTINATION_ROUTES).filter(
      ([, reason]) => reason.trim().length < MIN_REASON,
    );
    expect(thin).toEqual([]);
  });

  test('Δ4 — ο ΠΑΡΟΝΟΜΑΣΤΗΣ: ο απαριθμητής όντως βλέπει διαδρομές', () => {
    // 🔴 Χωρίς αυτό, ένας απαριθμητής που επιστρέφει [] κάνει τα Δ1/Δ2 πράσινα
    //    ΧΩΡΙΣ ΝΑ ΚΟΙΤΑΞΕΙ ΤΙΠΟΤΑ — και το κλειστό σύνολο θα ήταν ένα κενό
    //    άθροισμα που επικυρώνει τον εαυτό του.
    expect(routes.length).toBeGreaterThan(100);
    expect(declared.length).toBeGreaterThan(0);
  });
});

/** Το όνομα της διαδρομής όπως τη γράφει ο κατάλογος — με τις αγκύλες αυτούσιες. */
function toRouteName(record: RouteRecord): string {
  const fromFile = record.file
    .replace(/^src\/app/, '')
    .replace(/\/(page|route)\.tsx?$/, '')
    .replace(/\/\([^/]*\)/g, '');
  return fromFile === '' ? '/' : fromFile;
}

// ═════════════════════════════════════════════════════════════════════════════
// Τ — ΤΑ ΣΥΝΟΡΑ ΤΟΥ ΤΥΠΟΥ. Τα κρίνει ο `tsc`, ΟΧΙ το jest.
// ═════════════════════════════════════════════════════════════════════════════

/**
 * Μιμείται **ακριβώς** το σημείο κλήσης: γενική συνάρτηση που δέχεται
 * `WorkspaceHref<T>`, όπως ο `Link` και ο `router.push`.
 *
 * ⚠️ **Η γενικότητα ΔΕΝ είναι λεπτομέρεια.** Ένα μη-γενικό
 * `(href: WorkspaceHref) => void` θα δοκίμαζε το `WorkspaceHref<string>`, όπου
 * ο κλάδος των δυναμικών **δεν μπορεί να κρίνει τίποτα** — η άγκυρα θα ασκούσε
 * έναν τύπο που **κανείς δεν χρησιμοποιεί**.
 */
/**
 * Πόσα `accepts(...)` υπάρχουν — **και τα θετικά και τα `@ts-expect-error`**.
 *
 * ⛔ **ΜΗΝ τον «διορθώσεις» επειδή κοκκίνισε.** Αν έπεσε, κάποιος **έσβησε**
 * άγκυρα· αν ανέβηκε, πρόσθεσε — και τα δύο θέλουν να τα δει άνθρωπος.
 */
const ANCHOR_COUNT = 21;

const anchorLog: string[] = [];

function accepts<T extends string>(href: WorkspaceHref<T>): void {
  anchorLog.push(href);
}

/**
 * **Ο περιέκτης των Τ** — ο `tsc` τον κρίνει, το jest τον **εκτελεί**.
 *
 * ⚠️ **Ο ΠΕΡΙΕΚΤΗΣ ΕΙΝΑΙ ΑΝΑΓΚΗ, ΟΧΙ ΤΑΞΗ.** Η πρώτη γραφή είχε τα Τ σε
 * **εμβέλεια module** με `declare const router` — και το jest έσκασε με
 * `ReferenceError: router is not defined`, ρίχνοντας **ΟΛΟΚΛΗΡΗ** τη σουίτα:
 * `Tests: 0 total`, δηλαδή **και τα τέσσερα Δ σιωπηλά μη-εκτελεσμένα**. Είναι
 * ακριβώς το ψέμα που προειδοποιεί το handoff για τον μεταλλάκτη *(«μετάλλαξη
 * που ρίχνει τη σουίτα αναφέρεται ως πράσινη»)* — εδώ θα το γράφαμε μόνοι μας.
 *
 * ⚠️ **ΚΑΙ ΤΟ ΚΑΛΟΥΜΕ ΟΝΤΩΣ**: μια συνάρτηση που μόνο μεταγλωττίζεται αφήνει το
 * `Τ8` *(τα `back`/`forward`/`refresh` επιβίωσαν του `Omit`)* να είναι **μόνο**
 * ισχυρισμός τύπου. Η κλήση το κάνει **γεγονός**.
 */
function typeAnchors(router: import('../navigation').WorkspaceRouter): void {

  /* ── Τ1 · ΤΙ ΠΡΕΠΕΙ ΝΑ ΠΕΡΝΑΕΙ — ο ΠΑΡΟΝΟΜΑΣΤΗΣ ────────────────────────────
   * Χωρίς αυτά, ένας τύπος `never` θα έκανε **όλα** τα `@ts-expect-error`
   * παρακάτω να «πετύχουν», και το Γ5 θα ήταν πράσινο έχοντας σπάσει την
   * εφαρμογή. Ο παρονομαστής είναι το μισό της απόδειξης.                     */
  accepts('/projects'); //                    στατική, ΜΕΣΑ σε χώρο
  accepts('/login'); //                       στατική, ΕΚΤΟΣ χώρου
  accepts('/'); //                            η ρίζα — δημόσια οθόνη
  accepts('/properties/abc123'); //           δυναμική, ΕΝΑ slug
  accepts('/properties?view=floorplan'); //   στατική + ερώτημα
  accepts('/contacts?filter=%CE%91'); //      στατική + κωδικοποιημένο ερώτημα
  accepts('/properties/abc123?tab=docs'); //  δυναμική + ερώτημα
  accepts('/listing/xyz'); //                 δυναμική, ΕΚΤΟΣ χώρου

  /* ── Τ2 · ΤΟ ΔΙΧΤΥ ΕΧΕΙ ΒΓΕΙ — Η ΚΕΝΤΡΙΚΗ ΑΠΟΔΕΙΞΗ ─────────────────────────
   * 🔴 ΑΝ ΑΥΤΟ ΤΟ ΕΝΑ ΓΙΝΕΙ ΠΡΑΣΙΝΟ, ΟΛΟ ΤΟ Γ5 ΕΙΝΑΙ ΔΙΑΚΟΣΜΗΤΙΚΟ. Με το
   * `/[...unprefixed]` μέσα στον κατάλογο, κάθε συμβολοσειρά που αρχίζει με `/`
   * ταιριάζει με `` `/${CatchAllSlug<T>}` `` και ο έλεγχος εξαφανίζεται —
   * χωρίς κανένα κόκκινο πουθενά.                                             */
  // @ts-expect-error — αυθαίρετη διαδρομή: ΔΕΝ υπάρχει σελίδα γι' αυτήν
  accepts('/καμια-τετοια-σελιδα');
  // @ts-expect-error — μοιάζει υπαρκτή, δεν είναι
  accepts('/projectz');
  // @ts-expect-error — υπαρκτό πρώτο τμήμα, ανύπαρκτο δεύτερο
  accepts('/projects/list/extra/deep');

  /* ── Τ3 · Ο ΚΟΣΜΟΣ ΚΡΙΝΕΤΑΙ — αυτό δεν το κάνει το Next ────────────────────
   * Το πρόθεμα το βάζει το σύνορο. Ένα χειρόγραφο `/o/…` σημαίνει ότι κάποιος
   * το έβαλε δεύτερη φορά, ή μάντεψε ψευδώνυμο.                               */
  // @ts-expect-error — το πρόθεμα ανήκει ΜΟΝΟ στο σύνορο
  accepts('/o/nikos/projects');
  // @ts-expect-error — ούτε με ταυτότητα αντί για ψευδώνυμο
  accepts('/o/comp_123/dashboard');

  /* ── Τ4 · ΤΟ SLUG ΕΙΝΑΙ **ΕΝΑ** ΤΜΗΜΑ ──────────────────────────────────────
   * Αποδεικνύει ότι το `SafeSlug` λειτουργεί, δηλαδή ότι το `T` φτάνει ζωντανό
   * ως το κριτήριο. Χωρίς αυτό, το `/properties/${string}` θα κατάπινε
   * ολόκληρο το υπόδεντρο και ο έλεγχος θα ήταν κατ' όνομα.                   */
  // @ts-expect-error — δύο τμήματα εκεί που η σελίδα δέχεται ένα
  accepts('/properties/abc/def');

  /* ── Τ5 · ΚΑΜΙΑ ΔΙΕΞΟΔΟΣ ───────────────────────────────────────────────────*/
  // @ts-expect-error — σκέτο `string`: αυτή ΗΤΑΝ η κατάσταση πριν το Γ5
  accepts('' as string);
  // @ts-expect-error — εξωτερικοί σύνδεσμοι θέλουν ωμό <a>, όχι το σύνορο
  accepts('https://example.com');
  // @ts-expect-error — το `WithProtocol` του Next θα δεχόταν ΚΑΙ αυτό
  accepts('foo:bar');

  /* ── Τ6 · ΤΟ ΕΡΩΤΗΜΑ ΔΕΝ ΕΙΝΑΙ ΔΙΕΞΟΔΟΣ ────────────────────────────────────
   * Το ίδιο το Next δέχεται σκέτο `` `?${string}` `` ως διαδρομή (σχετικό
   * ερώτημα). Εδώ **δεν** το δεχόμαστε: το σύνορο θα το έστελνε ακέραιο στο
   * `isInsideWorkspace`, που θα απαντούσε «εκτός χώρου» ⇒ ο σύνδεσμος θα
   * έχανε σιωπηλά το πρόθεμα.                                                 */
  // @ts-expect-error — σχετικό ερώτημα χωρίς διαδρομή
  accepts('?tab=docs');
  // @ts-expect-error — ανύπαρκτη διαδρομή δεν σώζεται από το ερώτημα
  accepts('/καμια-τετοια?tab=docs');

  /* ── Τ7 · Ο ΔΡΟΜΟΛΟΓΗΤΗΣ ΚΡΙΝΕΙ ΤΟ ΙΔΙΟ — 164 από τα 218 σημεία ────────────
   * Ξεχωριστή άγκυρα επίτηδες: ο `useRouter` δήλωνε `ReturnType<typeof
   * useNextRouter>`, τύπο που **ξέπλενε** ό,τι έγραφαν οι μέθοδοί του. Μια
   * άγκυρα μόνο στον `Link` θα ήταν πράσινη πάνω σε ένα σύνορο που κρίνει το
   * **25%** των σημείων.                                                      */
  router.push('/projects');
  router.replace('/properties/abc123');
  router.prefetch('/procurement/quotes?status=open');
  // @ts-expect-error — ο δρομολογητής ΔΕΝ είναι πιο χαλαρός από τον σύνδεσμο
  router.push('/καμια-τετοια-σελιδα');
  // @ts-expect-error — ούτε εκείνος δέχεται χειρόγραφο πρόθεμα
  router.replace('/o/nikos/dashboard');

  /* ── Τ8 · ΤΑ ΥΠΟΛΟΙΠΑ ΤΟΥ ΔΡΟΜΟΛΟΓΗΤΗ ΕΠΙΒΙΩΝΟΥΝ ──────────────────────────
   * Το `Omit<…>` πάνω σε τρεις μεθόδους δεν επιτρέπεται να καταπιεί τις άλλες.
   * Χωρίς αυτό, μια θεραπεία τύπων θα έσπαγε **λειτουργία**.                  */
  router.back();
  router.forward();
  router.refresh();

  /* ── Τ9 · ΔΗΛΩΜΕΝΟ ΟΡΙΟ, ΓΡΑΜΜΕΝΟ ΩΣ ΑΓΚΥΡΑ ────────────────────────────────
   * Το τελικό `/` κάνει το slug να μοιάζει με «τμήμα + κενό», που το `SafeSlug`
   * **απορρίπτει** *(περιέχει `/`)*. Το ίδιο ισχύει και στο Next. Δεν είναι
   * ελάττωμα: το `trailingSlash` **δεν** ορίζεται σε αυτό το έργο, άρα οι δύο
   * μορφές δεν είναι ισοδύναμες ούτε στον δρομολογητή. Γράφεται εδώ ώστε, αν
   * κάποτε οριστεί, η αλλαγή να **κοκκινίσει** αντί να περάσει σιωπηλά.
   * ⚠️ Ούτε το στατικό πρόθεμα το σώζει: το `/procurement/rfqs` **υπάρχει**, αλλά
   * το `` `${StaticAppHref}${SearchOrHash}` `` δέχεται μόνο `?`/`#`, όχι `/`.  */
  // @ts-expect-error — τελικό `/`: το slug θα ήταν «τμήμα + κενό»
  accepts('/procurement/rfqs/rfq_9/');
  // @ts-expect-error — και σε στατική διαδρομή, για τον ίδιο λόγο
  accepts('/projects/');
}

describe('Γ5 · Τ — ΤΑ ΣΥΝΟΡΑ ΤΟΥ ΤΥΠΟΥ (κρίνει ο tsc· εδώ μόνο εκτελούνται)', () => {
  test('Τ0 — οι άγκυρες τύπου ΕΚΤΕΛΟΥΝΤΑΙ, άρα υπάρχουν όντως', () => {
    // 🔴 Ο ΠΑΡΟΝΟΜΑΣΤΗΣ ΤΩΝ Τ. Χωρίς αυτό, κάποιος που σβήνει το σώμα της
    //    `typeAnchors` αφήνει **μηδέν** ισχυρισμούς και **καμία** πύλη δεν το
    //    λέει: ο `tsc` βρίσκει άδειο αρχείο και είναι, ορθά, πράσινος.
    anchorLog.length = 0;
    const calls: string[] = [];
    const stub = {
      push: () => calls.push('push'),
      replace: () => calls.push('replace'),
      prefetch: () => calls.push('prefetch'),
      back: () => calls.push('back'),
      forward: () => calls.push('forward'),
      refresh: () => calls.push('refresh'),
    } as unknown as import('../navigation').WorkspaceRouter;

    typeAnchors(stub);

    expect(calls).toEqual([
      'push',
      'replace',
      'prefetch',
      'push',
      'replace',
      'back',
      'forward',
      'refresh',
    ]);

    // 🔴 ΚΑΙ ΤΑ `accepts` — ΤΟ ΕΠΙΑΣΕ ΜΕΤΑΛΛΑΞΗ, ΟΧΙ Η ΑΝΑΓΝΩΣΗ. Η πρώτη γραφή
    //    του Τ0 μετρούσε **μόνο** τις κλήσεις του δρομολογητή· σβήνοντας ένα
    //    `accepts(...)` η άγκυρα έμενε **ΠΡΑΣΙΝΗ** (μετάλλαξη Μ5), δηλαδή ο
    //    παρονομαστής φύλαγε τα Τ7/Τ8 και **άφηνε ακάλυπτα** τα Τ1-Τ6 — που
    //    είναι ακριβώς εκεί όπου ζει η απόδειξη του δηλητηρίου.
    //    ⚠️ Ο αριθμός μετρά **και** τα `@ts-expect-error`: εκείνα εκτελούνται
    //    κανονικά σε χρόνο εκτέλεσης — ο `tsc` κρίνει αν ΜΕΤΑΓΛΩΤΤΙΖΟΝΤΑΙ, το
    //    jest ότι **υπάρχουν**. Δύο ερωτήματα, δύο κριτές, ένα αρχείο.
    expect(anchorLog).toHaveLength(ANCHOR_COUNT);
  });
});
