/**
 * «Πού μέσα στη διεύθυνση ζει ο χώρος;» — μία φορά, και για τις δύο κατευθύνσεις
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ΤΙ ΛΥΝΕΙ (ADR-787 §5.3 α · Ε-5 §5)
 * ─────────────────────────────────────────────────────────────────────────────
 * `/o/<ψευδώνυμο>/projects/123`
 *  └┬┘└────┬────┘└─────┬─────┘
 *   │      │           └─ η **σελίδα** — ό,τι ήταν πάντα
 *   │      └───────────── ο **χώρος** — αίτημα, ποτέ απόδειξη (Ε-5 §2)
 *   └──────────────────── ο **δείκτης** — μία δεσμευμένη λέξη, αντί για 99
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΔΥΟ ΚΑΤΕΥΘΥΝΣΕΙΣ, ΚΑΙ ΤΟ ΝΑ ΤΙΣ ΠΕΙΣ ΜΙΑ ΕΙΝΑΙ ΤΟ ΛΑΘΟΣ
 * ─────────────────────────────────────────────────────────────────────────────
 * Μετρήθηκαν **285 συμβολοσειρές διαδρομών** στην παραγωγή (71 αρχεία, **42% σε
 * τρία**). Δεν θέλουν όλες την ίδια πράξη:
 *
 * | Είδος | Παράδειγμα | Θεραπεία |
 * |---|---|---|
 * | **σύνδεσμος** | `href="/projects"` · `router.push('/contacts')` | {@link workspacePath} — **πρόσθεση** |
 * | **σύγκριση** | `pathname === '/dxf/viewer'` | {@link stripWorkspace} — **αφαίρεση** |
 *
 * ⚠️ **Ένας μηχανισμός για τα δύο θα ήταν σωστός στο μισό.** Ζωντανό παράδειγμα:
 * το `src/app/(app)/layout.tsx` κλείνει τη μπάρα όταν `pathname === '/dxf/viewer'`,
 * και το σχόλιό του (ADR-726 §13.1) λέει ότι *«η μετρημένη γεωμετρία οφείλει να
 * είναι η παραδιδόμενη»*. Με πρόθεμα και **χωρίς** αφαίρεση, η σύγκριση γίνεται
 * σιωπηλά `false` και ο καμβάς μετράει **λάθος πλάτος** — καμία πύλη δεν το βλέπει.
 *
 * ⛔ **ΜΗΝ γράψεις το πρόθεμα ως συμβολοσειρά αλλού.** Αυτό είναι το SSoT.
 *
 * @module lib/workspace/workspace-path
 */

/**
 * Ο **δείκτης** του χώρου στη διεύθυνση.
 *
 * 🔑 **Γιατί υπάρχει καθόλου** — μετρημένο (ADR-787 §5.3 α): με το ψευδώνυμο στη
 * **ρίζα** (μοντέλο GitHub/Linear) οι δεσμευμένες λέξεις θα ήταν **99**, από
 * **τέσσερις** πηγές που κανείς δεν συγχρονίζει (45 σελίδες · 35 `SCANNER_PATHS`
 * · 81 `/api` · 17 `public/`), και το σύνολο **μεγαλώνει** με κάθε νέα σελίδα.
 * Πίσω από τον δείκτη είναι **μία**.
 *
 * ⚠️ Και η σύγκρουση **έχει ήδη συμβεί εδώ**: το `/debug` είναι ΚΑΙ σελίδα ΚΑΙ
 * `SCANNER_PATH` του `src/middleware.ts`, άρα απαντά **404 σε κάθε περιβάλλον**.
 */
export const WORKSPACE_PATH_PREFIX = 'o';

/** `/o` — το πρόθεμα ως τμήμα διαδρομής. */
const PREFIX_SEGMENT = `/${WORKSPACE_PATH_PREFIX}`;

/**
 * Το ψευδώνυμο του χώρου από μια διεύθυνση — `null` αν η διεύθυνση δεν ονομάζει χώρο.
 *
 * ⚠️ **`null` ΔΕΝ σημαίνει «λάθος»**: οι δημόσιες οθόνες, η σύνδεση και η εγγραφή
 * ζουν **εκτός** προθέματος εξ ορισμού (ADR-787 §5.3 γ). Ο καλών αποφασίζει τι
 * σημαίνει η απουσία — εδώ απαντιέται μόνο *«ονομάζει χώρο;»*.
 *
 * ⚠️ **Η ΓΡΑΜΜΑΤΙΚΗ ΔΕΝ ΚΡΙΝΕΤΑΙ ΕΔΩ.** Επιστρέφεται το **ωμό** τμήμα, ακόμα κι
 * αν είναι `!!!`. Ο έλεγχος ανήκει στον `judgeAliasShape`, και η διπλή κρίση θα
 * ήταν δεύτερο κριτήριο που μπορεί να αποκλίνει (ADR-749).
 */
export function extractWorkspaceSegment(pathname: string): string | null {
  const segments = pathname.split('/').filter(Boolean);
  if (segments[0] !== WORKSPACE_PATH_PREFIX) return null;
  return segments[1] ?? null;
}

/**
 * Χτίζει διεύθυνση **μέσα** σε χώρο: `('nikos', '/projects')` → `/o/nikos/projects`.
 *
 * ⚠️ Δέχεται διαδρομή **με ή χωρίς** αρχική κάθετο, γιατί και οι δύο μορφές
 * υπάρχουν ήδη στα 285 σημεία. Το να απαιτούσε μία θα σήμαινε 285 χειροκίνητες
 * διορθώσεις — δηλαδή 285 ευκαιρίες για λάθος.
 *
 * ⚠️ **Είναι idempotent**: διαδρομή που φέρει ήδη το πρόθεμα επιστρέφεται όπως
 * είναι. Χωρίς αυτό, μια διπλή κλήση θα έδινε `/o/nikos/o/nikos/projects` — και
 * θα φαινόταν μόνο στην οθόνη, όχι σε καμία πύλη.
 */
export function workspacePath(alias: string, path = '/'): string {
  const rest = path.startsWith('/') ? path : `/${path}`;
  if (extractWorkspaceSegment(rest) !== null) return rest;
  return rest === '/' ? `${PREFIX_SEGMENT}/${alias}` : `${PREFIX_SEGMENT}/${alias}${rest}`;
}

/**
 * Αφαιρεί το πρόθεμα χώρου: `/o/nikos/projects` → `/projects`.
 *
 * 🔑 **Αυτή είναι η κατεύθυνση που ξεχνιέται.** Κάθε σύγκριση διαδρομής στον
 * κώδικα (`pathname === …` · `startsWith(…)` · πίνακες ενεργών tabs) μιλά τη
 * γλώσσα **χωρίς** χώρο, και θα γινόταν σιωπηλά `false` με το πρόθεμα μπροστά.
 *
 * ⚠️ Διαδρομή **χωρίς** πρόθεμα επιστρέφεται αναλλοίωτη — άρα η συνάρτηση είναι
 * ασφαλής να μπει **παντού**, και δεν χρειάζεται κανείς να ξεχωρίσει «ποιες
 * συγκρίσεις είναι μέσα σε χώρο». Ένας κανόνας που πρέπει να θυμάσαι είναι το
 * σχήμα που έχει αποτύχει μετρημένα τέσσερις φορές (CHECK 3.34 · 3.37 · 3.49 · 3.57).
 */
export function stripWorkspace(pathname: string): string {
  if (extractWorkspaceSegment(pathname) === null) return pathname;
  const segments = pathname.split('/').filter(Boolean);
  const rest = segments.slice(2);
  return rest.length ? `/${rest.join('/')}` : '/';
}

/** Ονομάζει αυτή η διεύθυνση χώρο; */
export function hasWorkspacePrefix(pathname: string): boolean {
  return extractWorkspaceSegment(pathname) !== null;
}
