/**
 * **Δημιουργώ τον χώρο μου** (ADR-787 Κ-1).
 *
 * 🔑 **Ζει στο `(me)`, τον ιδιωτικό χώρο** — και η διεύθυνση δεν το δείχνει,
 * γιατί τα route groups δεν εμφανίζονται ποτέ στο URL. Ο πλήρης λόγος της
 * τοποθέτησης ζει στη σελίδα· εδώ αρκεί ότι απαιτεί **ταυτότητα** και ότι δεν
 * παίρνει πρόθεμα χώρου.
 *
 * ⚠️ **`/workspace/new` και όχι `/o/new`**: το δεύτερο θα ήταν **μέσα** στον
 * χώρο ονομάτων των ψευδωνύμων, άρα η λέξη `new` θα έπρεπε να μπει στις
 * δεσμευμένες του **Ψ3** (`alias-rules.ts`) — δηλαδή θα **αφαιρούσε** ένα
 * νόμιμο όνομα γραφείου από κάθε χρήστη, για πάντα, χωρίς κανένα αντάλλαγμα.
 * Το ίδιο το `alias-rules.ts` προειδοποιεί ρητά για αυτή την παγίδα.
 */
export const CREATE_WORKSPACE_ROUTE = '/workspace/new' as const;

