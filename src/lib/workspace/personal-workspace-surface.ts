import { PERSONAL_WORKSPACE_ALIAS } from '@/types/workspace-alias';
import { PRIVATE_SPACE_HOME } from '@/lib/routes/landing';
import { WORKSPACE_PATH_PREFIX } from './workspace-path';
import { firstPathSegment } from './workspace-scope';

/**
 * Οι διαδρομές που **προσφέρονται** μέσα στον ιδιωτικό χώρο — κλειδί = κορυφαίο τμήμα
 * (χωρίς το πρόθεμα χώρου), τιμή = **ο λόγος**.
 *
 * ⚠️ Κενό σήμερα (δες την κεφαλίδα του αρχείου). Το `Record` μένει ώστε η προσθήκη να είναι
 * **μία γραμμή με λόγο**, όχι νέος μηχανισμός.
 */
export const PERSONAL_WORKSPACE_SURFACE: Readonly<Record<string, string>> = {};

/**
 * Το πρόθεμα του **ιδιωτικού** χώρου στη διεύθυνση — `/o/me`.
 *
 * ⚠️ Το `WORKSPACE_PATH_PREFIX` είναι **τμήμα** (`'o'`), όχι διαδρομή: η αρχική γραφή χωρίς
 * την αρχική κάθετο έδινε `'o/me'` και ο κανόνας **δεν πυροδοτούσε ποτέ** — πράσινος
 * μηχανισμός που δεν κάνει τίποτα. Το έπιασε η άγκυρα `Λ`, όχι η ανάγνωση.
 */
const PERSONAL_WORKSPACE_PREFIX = `/${WORKSPACE_PATH_PREFIX}/${PERSONAL_WORKSPACE_ALIAS}`;

/**
 * **Προσφέρεται αυτή η διαδρομή μέσα στον ιδιωτικό χώρο;**
 *
 * ⚠️ Δέχεται διαδρομή **χωρίς** το πρόθεμα χώρου.
 */
export function isOfferedInPersonalWorkspace(path: string): boolean {
  const first = firstPathSegment(path);
  if (first === undefined) return false; // η ρίζα του χώρου — δεν έχει σελίδα ούτε σήμερα

  return first in PERSONAL_WORKSPACE_SURFACE;
}

/**
 * **Πού πρέπει να πάει αυτό το αίτημα, αν η διεύθυνση δεν ανοίγει στον ιδιωτικό χώρο;**
 *
 * @returns η διεύθυνση προσγείωσης, ή `null` όταν το αίτημα **δεν αφορά** (κάθε άλλη
 *          διαδρομή της εφαρμογής — ο εταιρικός χώρος περνά **ανέγγιχτος**).
 *
 * ⚠️ **Το ψευδώνυμο συγκρίνεται χωρίς πεζά/κεφαλαία**, ίδιο με τον `resolveWorkspaceFromPath`
 * (`segment.toLowerCase() === PERSONAL_WORKSPACE_ALIAS`). Αλλιώς το `/o/ME/projects` θα
 * γλίστραγε και θα άνοιγε ό,τι κλείνει εδώ.
 *
 * ⚠️ **Το ερώτημα ΔΕΝ μεταφέρεται** στην προσγείωση, επίτηδες: αλλάζουμε **επιφάνεια**, και
 * ένα `?filter=…` γραμμένο για κατάλογο γραφείου δεν σημαίνει τίποτα στον κατάλογο του
 * ιδιώτη. (Το δίχτυ του `[...unprefixed]` κρατά το ερώτημα γιατί εκεί η διαδρομή είναι **η
 * ίδια** — απλώς αποκτά πρόθεμα.)
 */
export function personalWorkspaceLanding(pathname: string): string | null {
  const lower = pathname.toLowerCase();
  const isPersonal =
    lower === PERSONAL_WORKSPACE_PREFIX || lower.startsWith(`${PERSONAL_WORKSPACE_PREFIX}/`);

  if (!isPersonal) return null;

  const withinWorkspace = pathname.slice(PERSONAL_WORKSPACE_PREFIX.length) || '/';
  return isOfferedInPersonalWorkspace(withinWorkspace) ? null : PRIVATE_SPACE_HOME;
}
