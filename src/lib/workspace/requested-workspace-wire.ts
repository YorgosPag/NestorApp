/**
 * Τι βρήκε ο αναλυτής — **τρεις** ρητές εκβάσεις, ποτέ `null` που σημαίνει δύο πράγματα.
 *
 * 🔴 Το `malformed` **δεν** είναι `absent`: «δεν δήλωσες» και «δήλωσες κάτι που δεν
 * καταλαβαίνω» έχουν **διαφορετική** θεραπεία (σημερινή συμπεριφορά έναντι άρνησης). Η
 * ισοπέδωσή τους είναι το σχήμα που το **N.12** υπάρχει για να αποτρέπει.
 */
export type RequestedWorkspaceReading =
  | { readonly outcome: 'declared'; readonly requested: RequestedWorkspace }
  | { readonly outcome: 'absent' }
  | { readonly outcome: 'malformed'; readonly detail: string };

/**
 * **Μορφή αναγνωριστικού εταιρείας στο σύρμα** — ποτέ ταυτότητα.
 *
 * ⛔ Απορρίπτονται τα ονόματα που το Firestore απαγορεύει ως id (`/`, `.`, `..`,
 * `__…__`) και ό,τι κρύβει κενό ή χαρακτήρα ελέγχου: μια τιμή που δεν μπορεί να είναι
 * έγγραφο **δεν έχει λόγο** να φτάσει σε αναζήτηση.
 */
/**
 * **«Δήλωσε καν κάτι αυτό το αίτημα;»** — η κοινή αρχή **των δύο** αναγνωστών.
 *
 * 🔴 **ΕΞΗΧΘΗ ΕΠΕΙΔΗ ΤΟ ΜΕΤΡΗΣΕ ΤΟ CHECK 3.28 (jscpd) ΜΕΣΑ ΣΤΟ ΙΔΙΟ COMMIT** (9 γραμμές /
 * 56 tokens, `194-202` ⇄ `225-232`): είχα γράψει τον αναλυτή της νέας κεφαλίδας και μετά τον
 * αναλυτή της αποσυρόμενης **ως δίδυμο** — ακριβώς το σχήμα που ονομάζει ο **N.18**
 * (*«κεντρικοποιείς το Α, γράφεις Β ως δίδυμο»*). Η απόκλιση θα ήταν **αόρατη**: και οι δύο
 * «δουλεύουν», αλλά ένας μελλοντικός κανόνας (π.χ. «κενή τιμή = malformed») θα έμπαινε στον
 * ένα και **όχι** στον άλλο, δηλαδή η απόσυρση θα άφηνε πίσω της **χαλαρότερη πόρτα**.
 *
 * @returns η **κουρεμένη** τιμή, ή `null` όταν δεν υπάρχει δήλωση (απουσία ή κενό).
 */
function declaredValue(raw: string | null | undefined): string | null {
  if (raw === null || raw === undefined) return null;

  const value = raw.trim();
  return value.length === 0 ? null : value;
}

function isWireCompanyId(value: string): boolean {
  if (value.length === 0 || value.length > MAX_COMPANY_ID_LENGTH) return false;
  if (value === '.' || value === '..') return false;
  if (value.includes('/')) return false;
  if (/^__.*__$/.test(value)) return false;
  return /^[\w.:@~+-]+$/.test(value);
}

/**
 * **Η δήλωση, από την τιμή της κεφαλίδας.** Fail-closed: ό,τι δεν αναγνωρίζεται
 * επιστρέφεται ως `malformed` — **ποτέ** σιωπηλή προεπιλογή.
 *
 * ⚠️ Το κενό/λευκό αλφαριθμητικό είναι **`absent`** και όχι `malformed`: μια κεφαλίδα
 * που ο ενδιάμεσος «καθάρισε» σε κενό δεν είναι απόπειρα δήλωσης, και μια άρνηση εκεί
 * θα έσπαγε αιτήματα για λόγο που ο πελάτης δεν έγραψε ποτέ.
 */
export function parseRequestedWorkspace(
  raw: string | null | undefined,
): RequestedWorkspaceReading {
  const value = declaredValue(raw);
  if (value === null) return { outcome: 'absent' };

  if (value === PERSONAL_TOKEN) return { outcome: 'declared', requested: { kind: 'personal' } };
  if (value === DEFAULT_TOKEN) return { outcome: 'declared', requested: { kind: 'default' } };

  if (!value.startsWith(ORG_PREFIX)) {
    return { outcome: 'malformed', detail: 'unknown-token' };
  }

  const companyId = value.slice(ORG_PREFIX.length);
  if (!isWireCompanyId(companyId)) {
    return { outcome: 'malformed', detail: 'invalid-company-id' };
  }

  return { outcome: 'declared', requested: { kind: 'org', companyId } };
}

/**
 * **Η παλιά κεφαλίδα, μεταφρασμένη στη νέα γραμματική** — ένα σημείο, όχι κλάδος στον
 * αναγνώστη.
 *
 * Η παλιά μετέφερε **μόνο** εταιρεία, άρα η μετάφραση είναι ολική: τιμή ⇒ `org:<τιμή>`,
 * απουσία ⇒ `absent`. Ό,τι δεν έχει μορφή αναγνωριστικού μένει `malformed`, **ίδιος**
 * κανόνας με τη νέα — αλλιώς η απόσυρση θα άφηνε πίσω της χαλαρότερη πόρτα.
 */
export function parseLegacyCompanyHeader(
  raw: string | null | undefined,
): RequestedWorkspaceReading {
  const value = declaredValue(raw);
  if (value === null) return { outcome: 'absent' };
  if (!isWireCompanyId(value)) return { outcome: 'malformed', detail: 'invalid-company-id' };

  return { outcome: 'declared', requested: { kind: 'org', companyId: value } };
}
