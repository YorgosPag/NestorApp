import 'server-only';

import { resolvePostLoginRoute } from '@/lib/routes/landing';
import { isInsideWorkspace } from './workspace-scope';
import { workspacePath } from './workspace-path';
import { workspaceSegmentFor, type WorkspaceOwner } from './workspace-segment';

/**
 * Η διεύθυνση όπου ανήκει αυτός ο άνθρωπος — ή `null` αν **δεν μπορούμε να την
 * ονομάσουμε**.
 *
 * Τρία βήματα, και **κανένα δεν είναι νέα κρίση**:
 *
 * | # | ερώτηση | ποιος απαντά |
 * |---|---|---|
 * | 1 | *«ποια οθόνη είναι η δική μου;»* | `resolvePostLoginRoute` — **ο ΕΝΑΣ** επιλυτής προσγείωσης (ADR-660 §5.4, **παγωμένος**) |
 * | 2 | *«ζει αυτή η οθόνη μέσα σε χώρο;»* | `isInsideWorkspace` — το κλειστό σύνολο |
 * | 3 | *«ποιο είναι το τμήμα διεύθυνσης του χώρου μου;»* | `workspaceSegmentFor` — η αυθεντία του ADR-819 |
 *
 * 🔑 **Το βήμα 2 δεν είναι λεπτομέρεια**: η προσγείωση του πολίτη είναι το
 * `/offers`, που ζει **εκτός** εμβέλειας χώρου. Πρόθεμα εκεί θα έδινε
 * `/o/me/offers` — διεύθυνση **χωρίς σελίδα**, δηλαδή το κουμπί «πήγαινε σπίτι»
 * θα οδηγούσε σε **νέο 404**. Είναι ακριβώς η παγίδα που έπιασε η άγκυρα Κ1 του
 * `route-catalogue-anchor` στο `/workspace/new`.
 *
 * @returns η διεύθυνση, ή `null` όταν ο χώρος **δεν έχει διεύθυνση**
 *          (`unaddressable` — χαλασμένη παροχή). Ο καλών **οφείλει** να έχει
 *          έξοδο και για αυτό· ένα `null` που γίνεται σιωπηλά `'/'` θα ήταν
 *          τρίτο αδιέξοδο.
 */
export async function workspaceHomeHref(owner: WorkspaceOwner): Promise<string | null> {
  // 1 — Ο ΕΝΑΣ επιλυτής προσγείωσης. ⛔ ΜΗΝ ξαναγράψεις εδώ τον έλεγχο
  //     `companyId`: θα ήταν **δεύτερη κρίση που μπορεί να αποκλίνει** (ADR-749),
  //     και θα απέκλινε ακριβώς στην κενή συμβολοσειρά — τη μόνη περίπτωση όπου
  //     η απάντηση δεν είναι προφανής (`landing.ts`, `hasOrganization`).
  const landing = resolvePostLoginRoute(
    owner.kind === 'organization' ? { companyId: owner.companyId } : {},
  );

  // 2 — Εκτός εμβέλειας χώρου ⇒ **καμία προθεματοποίηση**, και είναι η σωστή
  //     απάντηση, όχι παράλειψη: το `/offers` του πολίτη δεν ζει σε χώρο.
  if (!isInsideWorkspace(landing)) return landing;

  // 3 — Η αυθεντία του τμήματος διεύθυνσης (ADR-819 §4.1).
  const resolution = await workspaceSegmentFor(owner);
  if (resolution.outcome !== 'segment') return null;

  return workspacePath(resolution.segment, landing);
}
