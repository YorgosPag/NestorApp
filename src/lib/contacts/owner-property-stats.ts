// 2. ΤΟ ΛΕΞΙΛΟΓΙΟ ΤΩΝ ΚΑΔΩΝ — ΤΙΜΕΣ ΚΑΙ ΚΡΙΤΗΣ ΜΑΖΙ
// =============================================================================

/** Η τιμή «κανένα φίλτρο» — κοινή και στους δύο κάδους. */
export const ANY_BUCKET = 'all';

export const PROPERTIES_COUNT_BUCKETS = [ANY_BUCKET, '1-2', '3-5', '6+'] as const;
export type PropertiesCountBucket = (typeof PROPERTIES_COUNT_BUCKETS)[number];

export const TOTAL_AREA_BUCKETS = [ANY_BUCKET, '0-100', '101-300', '301+'] as const;
export type TotalAreaBucket = (typeof TOTAL_AREA_BUCKETS)[number];

/**
 * Ταιριάζει το πλήθος ιδιοκτησιών στον επιλεγμένο κάδο;
 *
 * ⚠️ Άγνωστη τιμή κάδου ⇒ `true` («μη φιλτράρεις»), ποτέ σφάλμα: η τιμή έρχεται από
 * το URL/κατάσταση φόρμας και ο άνθρωπος μπορεί να τη γράψει. Ένα σφάλμα εδώ θα
 * κατέβαζε τη λίστα για κακοδιατυπωμένη παράμετρο.
 */
export function matchesPropertiesCount(bucket: string, count: number): boolean {
  switch (bucket) {
    case '1-2': return count >= 1 && count <= 2;
    case '3-5': return count >= 3 && count <= 5;
    case '6+': return count >= 6;
    default: return true;
  }
}

/**
 * Ταιριάζει το συνολικό εμβαδόν στον επιλεγμένο κάδο;
 *
 * 🔴 **ΔΙΟΡΘΩΘΗΚΕ ΚΕΝΟ ΤΟΥ ΠΡΟΓΟΝΟΥ, ΚΑΙ ΔΗΛΩΝΕΤΑΙ**: ο νεκρός `useContactsState`
 * έγραφε `'0-100' → >0 && <=100` και `'101-300' → >=101 && <=300`, δηλαδή μια επαφή
 * με **100,5 τ.μ.** δεν ταίριαζε σε **κανέναν** κάδο και εξαφανιζόταν από κάθε
 * φίλτρο εμβαδού. Εδώ τα όρια είναι **συνεχή** (`>100` αντί `>=101`)· οι ετικέτες
 * μένουν ίδιες γιατί για ακέραια τ.μ. διαβάζονται σωστά.
 *
 * ⚠️ Το `>0` στον πρώτο κάδο είναι **σκόπιμο**: «0 τ.μ.» σημαίνει *δεν κατέχει* ή
 * *δεν καταχωρήθηκε εμβαδόν* — δεν είναι «μικρό ακίνητο» και δεν πρέπει να
 * εμφανίζεται σε φίλτρο επιφάνειας.
 */
export function matchesTotalArea(bucket: string, totalArea: number): boolean {
  switch (bucket) {
    case '0-100': return totalArea > 0 && totalArea <= 100;
    case '101-300': return totalArea > 100 && totalArea <= 300;
    case '301+': return totalArea > 300;
    default: return true;
  }
}
