import type { Property } from '@/types/property-viewer';

// =============================================================================
// 1. ΤΑ ΔΥΟ ΝΟΥΜΕΡΑ ΑΝΑ ΙΔΙΟΚΤΗΤΗ
// =============================================================================

/** Τι κατέχει μία επαφή — το μόνο που ταξιδεύει από τον διακομιστή. */
export interface OwnerPropertyStats {
  readonly propertiesCount: number;
  /** Άθροισμα καθαρού εμβαδού σε τ.μ.· ακίνητο χωρίς `area` συνεισφέρει 0. */
  readonly totalArea: number;
}

/** Ο πίνακας ιδιοκτητών — κλειδί το `contactId`. Σειριοποιείται αυτούσιος σε JSON. */
export type OwnerPropertyStatsByContact = Readonly<Record<string, OwnerPropertyStats>>;

/** Η ουδέτερη απάντηση για επαφή που δεν κατέχει τίποτα. */
export const EMPTY_OWNER_STATS: OwnerPropertyStats = { propertiesCount: 0, totalArea: 0 };

/**
 * **Ένα πέρασμα: πλήθος και εμβαδόν ανά ιδιοκτήτη.**
 *
 * 🔑 Δέχεται `Property[]` — δηλαδή την έξοδο του **ΕΝΟΣ** συνόρου ανάγνωσης
 * (`mapPropertyDoc`), ποτέ ωμά έγγραφα. Έτσι το «τι είναι ένα ακίνητο» απαντιέται
 * **πριν** φτάσει εδώ, και αυτό το αρχείο μένει καθαρή αριθμητική.
 *
 * ⚠️ Ακίνητο χωρίς `soldTo` **δεν** αγνοείται σιωπηλά — απλώς δεν έχει ιδιοκτήτη να
 * χρεωθεί. Η διάκριση έχει σημασία: «κανείς δεν το αγόρασε» δεν είναι «λείπουν
 * δεδομένα».
 */
export function summarizeByOwner(
  properties: readonly Property[],
): OwnerPropertyStatsByContact {
  const byOwner: Record<string, { propertiesCount: number; totalArea: number }> = {};

  for (const property of properties) {
    const ownerId = property.soldTo;
    if (!ownerId) continue;

    const current = byOwner[ownerId] ?? { propertiesCount: 0, totalArea: 0 };
    current.propertiesCount += 1;
    current.totalArea += typeof property.area === 'number' ? property.area : 0;
    byOwner[ownerId] = current;
  }

  return byOwner;
}

