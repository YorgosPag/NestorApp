/**
 * **Η ετυμηγορία για ΜΙΑ αγγελία, στις ημερομηνίες που ρωτήθηκαν.**
 *
 * ⚠️ **Κάθε τιμή είναι ΚΑΔΟΣ της λογιστικής** (`lib/listings/stay-ledger.ts`), και το
 * `balances()` απαιτεί να αθροίζουν στο **ίδιο σύνολο** με την υπάρχουσα λογιστική
 * θέσης. Δέκατη τιμή που θα προστεθεί χωρίς κάδο **δεν μεταγλωττίζεται** — ο ίδιος
 * φρουρός με το `STAY_LIFECYCLE_OCCUPIES`.
 */
export type StayAvailabilityAnswer =
  /**
   * **Δεν είναι κατάλυμα** — το `offerKinds` δεν έχει `leaseShort`.
   *
   * 🔑 **Δεν είναι αποτυχία, και γι' αυτό έχει δικό του όνομα.** Ο επισκέπτης που
   * ρωτά ημερομηνίες βλέπει επίσης ακίνητα προς **πώληση** στην ίδια περιοχή· αυτά
   * **δεν εξαφανίζονται** (θα ήταν σιωπηλό φίλτρο `offerKinds` που κανείς δεν ζήτησε)
   * και **δεν** λογίζονται «κρατημένα». Απλώς δεν απαντούν σε αυτή την ερώτηση.
   */
  | { readonly kind: 'not-a-stay' }
  /**
   * Κατάλυμα που **δεν δήλωσε χωρητικότητα**, ενώ ο επισκέπτης ρώτησε άτομα.
   *
   * ⚠️ **Ούτε «χωράει» ούτε «δεν χωράει»** (N.12). Ένα σιωπηλό «χωράει» στέλνει
   * τέσσερις ανθρώπους σε δυάρι· ένα σιωπηλό «δεν χωράει» σβήνει αγγελία που ίσως
   * ήταν η σωστή. Η θεραπεία ανήκει στον **κάτοχο**, και είναι ένα πεδίο.
   */
  | { readonly kind: 'terms-unknown' }
  /** Χωράει **λιγότερους**. **Μετρήσιμο** εμπόδιο: ο επισκέπτης ξέρει πόσο λείπει. */
  | { readonly kind: 'over-capacity'; readonly maxGuests: number; readonly asked: number }
  /**
   * Ο επισκέπτης φέρνει κατοικίδιο και ο κάτοχος **δεν δήλωσε** πολιτική (ADR-777 §8.60.21).
   * ⚠️ Ούτε «ναι» ούτε «όχι» — schema.org `petsAllowed`: χωρίς τιμή, **άγνωστο**.
   */
  | { readonly kind: 'pets-unknown' }
  /** Ο κάτοχος **δεν δέχεται** κατοικίδια. (Οι σκύλοι βοήθειας δεν κρίνονται εδώ.) */
  | { readonly kind: 'pets-not-allowed' }
  /** Δέχεται **λιγότερα** κατοικίδια. **Μετρήσιμο**, όπως το `over-capacity`. */
  | { readonly kind: 'over-pet-limit'; readonly maxPets: number; readonly asked: number }
  /**
   * Δέχεται **περισσότερες** νύχτες. Μετρήσιμο, με τον ίδιο ακριβώς λόγο.
   *
   * 🔑 Με δηλωμένο ημερολόγιο το ελάχιστο κρίνεται **ανά ημέρα άφιξης** και χαλαρώνει σε
   * ορφανό κενό (`minNightsForArrival`) — άρα το `minNights` εδώ είναι το **ισχύον** για
   * αυτή την άφιξη, όχι απαραίτητα ο όρος της αγγελίας.
   */
  | { readonly kind: 'below-min-nights'; readonly minNights: number; readonly asked: number }
  /** Δέχεται **λιγότερες** νύχτες από την άφιξη αυτή. Μετρήσιμο. */
  | { readonly kind: 'above-max-nights'; readonly maxNights: number; readonly asked: number }
  /**
   * **Πολύ κοντά** — ο οικοδεσπότης θέλει ειδοποίηση. Η διέξοδος είναι η νωρίτερη άφιξη.
   */
  | { readonly kind: 'advance-notice'; readonly earliestCheckIn: string }
  /**
   * **Πολύ μακριά** — πέρα από το παράθυρο κρατήσεων. Το `bookableUntil` είναι η πρώτη
   * **μη** διαθέσιμη νύχτα: η αναχώρηση πρέπει να είναι ως εκεί.
   */
  | { readonly kind: 'outside-window'; readonly bookableUntil: string }
  /**
   * **Δεν δέχεται άφιξη** αυτή τη μέρα (μέρα εβδομάδας ή CTA). 🏆 Η αγορά γκριζάρει· εμείς
   * λέμε **την κοντινότερη** επιτρεπτή άφιξη πριν και μετά.
   */
  | {
      readonly kind: 'arrival-not-allowed';
      readonly nearestBefore: string | null;
      readonly nearestAfter: string | null;
    }
  /** **Δεν δέχεται αναχώρηση** αυτή τη μέρα (μέρα εβδομάδας ή CTD), με την κοντινότερη. */
  | {
      readonly kind: 'departure-not-allowed';
      readonly nearestBefore: string | null;
      readonly nearestAfter: string | null;
    }
  /** **Κανείς δεν δήλωσε ημερολόγιο.** Δες την κεφαλίδα για το γιατί όχι `DemandBlocker`. */
  | { readonly kind: 'unknown' }
  /**
   * 🔴 **Το ημερολόγιο ΔΕΝ ΔΙΑΒΑΣΤΗΚΕ** — χαλασμένο διάστημα σε υπάρχουσα κατάληψη.
   *
   * Ποτέ ίδιο με `free` (§6.4): *«ένα ελεύθερο εκεί **είναι** το overbooking»*. Και
   * ποτέ ίδιο με {@link StayAvailabilityAnswer} `unknown`: εκείνο είναι **επιλογή του
   * κατόχου**, αυτό είναι **δικό μας χρέος** — ίδια διάκριση με `owner-declined` vs
   * `never-asked` (Α5), και μόνο το δεύτερο έχει θεραπεία που μας ανήκει.
   */
  | { readonly kind: 'unreadable' }
  /**
   * 🔴 **ΕΝΑ ΚΑΝΑΛΙ ΔΕΝ ΔΙΑΒΑΖΕΤΑΙ ΑΡΚΕΤΗ ΩΡΑ** (Στάδιο Γ) — «δεν επιβεβαιώνεται»,
   * ποτέ «ελεύθερο».
   *
   * 🏆 **Εδώ ξεπερνάμε την αγορά με το να λέμε ΛΙΓΟΤΕΡΑ**: κάθε πλατφόρμα σε σπασμένο
   * feed συνεχίζει να διαφημίζει «ελεύθερο» (η Guesty δείχνει προειδοποίηση **στον
   * host**, τίποτα στον επισκέπτη) — δηλαδή πουλά νύχτες που **δεν ξέρει** αν έχει.
   * Ο κάδος είναι δικός του γιατί η **θεραπεία** και ο **υπόχρεος** διαφέρουν από το
   * `unreadable`: εκεί φταίμε εμείς, εδώ ο σύνδεσμος του καναλιού.
   */
  | { readonly kind: 'unsynced' }
  /**
   * 🏆 **ΚΡΑΤΗΜΕΝΟ — ΚΑΙ ΛΕΜΕ ΤΙ ΑΠΟΜΕΝΕΙ.** Το σημείο όπου ξεπερνάμε την αγορά.
   *
   * Όλες οι πλατφόρμες **εξαφανίζουν** εδώ. Εμείς φέρνουμε **δύο** διεξόδους: το
   * `nextFreeFrom` (*«ελεύθερο από 14/08»* — το ίδιο εργαλείο με το `availableFrom`
   * του `MandateOccupancyNotice`) και τα `freeRuns` (*«χωράει 10–12/08 και
   * 15–17/08»*), που **κανείς** δεν προσφέρει: τα *split stays* της Airbnb ζευγαρώνουν
   * **δύο διαφορετικά** καταλύματα, ποτέ δεν κατατέμνουν το **ένα**.
   */
  | {
      readonly kind: 'occupied';
      /** Πότε ελευθερώνεται· `null` όταν η αναμονή δεν βοηθά (ανοιχτή διάρκεια). */
      readonly nextFreeFrom: string | null;
      /** Τα **μέγιστα συνεχή** ελεύθερα κομμάτια μέσα στο ζητούμενο. Μπορεί κενό. */
      readonly freeRuns: readonly StayNightRun[];
    }
  /**
   * 🏆 **ΣΕ ΑΝΑΜΟΝΗ — ΚΑΙ ΛΕΜΕ ΩΣ ΠΟΤΕ** (Στάδιο Δ, §23.5). Κάθε σύγκρουση είναι **ζωντανό αίτημα**
   * άλλου επισκέπτη· αν ο οικοδεσπότης δεν απαντήσει, οι νύχτες **ελευθερώνονται μόνες τους** στο
   * `until`.
   *
   * 🔑 **Ποτέ ισοπεδωμένο σε `occupied`**: η θεραπεία είναι άλλη («ξαναδοκίμασε μετά τις 14:00»,
   * όχι «δες άλλες μέρες»). Η αγορά δείχνει σκέτο γκρι — και το Airbnb κρατά τις μέρες κλειστές
   * **και μετά** τη λήξη. Αν έστω και **μία** σύγκρουση είναι σκληρή, η απάντηση είναι `occupied`.
   */
  | { readonly kind: 'held'; readonly until: string }
  /**
   * **Ελεύθερο, ΑΛΛΑ το ακίνητο πωλείται** (§4.7).
   *
   * 🔴 **ΠΟΤΕ ισοπεδωμένο**: σε `free` είναι *«ψέμα προς τον επισκέπτη»*· σε
   * `occupied` είναι *«κλεμμένο εισόδημα από τον κάτοχο»*. Και η προειδοποίηση είναι
   * **γεγονός της κράτησης** (`StayBooking.riskDisclosedAt`), όχι κείμενο οθόνης.
   */
  | { readonly kind: 'conditional'; readonly conditionalFrom: string | null }
  /**
   * **Ελεύθερο — και το κατοικίδιο κατόπιν συνεννόησης** (ADR-777 §8.60.21).
   *
   * 🔑 **Stayable, και ΜΟΝΟ υποβάθμιση του `free`**: κρίνεται **μετά** το ημερολόγιο, ώστε ένα
   * `occupied` να μένει `occupied` με τη διέξοδό του. Αν έκοβε νωρίς (όπως τα εμπόδια), η
   * «συνεννόηση» θα έκρυβε ότι οι ημερομηνίες είναι πιασμένες. Ονομασμένη αβεβαιότητα: «ρώτα».
   */
  | { readonly kind: 'pets-on-request' }
  /** Ελεύθερο, καμία επιφύλαξη. */
  | { readonly kind: 'free' };

/** Το **όνομα** μιας απάντησης — ο κάδος στον οποίο μετριέται. */
export type StayAvailabilityKind = StayAvailabilityAnswer['kind'];

/**
 * **Το κλειστό σύνολο των κάδων**, στη σειρά που τα κρίνει η μηχανή.
 *
 * ⚠️ **Η σειρά ΕΙΝΑΙ συμβόλαιο**, όπως στο `coverageStateOf`: τα φθηνά και σταθερά
 * (είδος · χωρητικότητα) κρίνονται **πριν** το ημερολόγιο, γιατί ένα *«δεν χωράει 6
 * άτομα»* είναι χρησιμότερο από ένα *«δεν ξέρω το ημερολόγιο»*. Με δηλωμένο ημερολόγιο
 * ακολουθούν: ειδοποίηση · παράθυρο · άφιξη · αναχώρηση · **κριτής** · μέγιστες ·
 * ελάχιστες. Οι νύχτες κρίνονται **μετά** τον κριτή, επειδή το ελάχιστο εξαρτάται από
 * το κενό γύρω από την άφιξη (ορφανό κενό). Χωρίς ημερολόγιο, ο όρος `minNights` της
 * αγγελίας κρίνεται **πριν** το `unknown` — όπως ως το Στάδιο Α.
 */
export const STAY_AVAILABILITY_KINDS = [
  'not-a-stay',
  'terms-unknown',
  'over-capacity',
  'pets-unknown',
  'pets-not-allowed',
  'over-pet-limit',
  'unknown',
  'unreadable',
  'unsynced',
  'advance-notice',
  'outside-window',
  'arrival-not-allowed',
  'departure-not-allowed',
  'occupied',
  'held',
  'above-max-nights',
  'below-min-nights',
  'conditional',
  'pets-on-request',
  'free',
] as const satisfies readonly StayAvailabilityKind[];

/**
 * Οι κάδοι που σημαίνουν **«μπορείς να μείνεις»** — έστω και με επιφύλαξη.
 *
 * ⚠️ **Ονομασμένη σταθερά, όχι σιωπηλό `!==`** — ίδιο πρότυπο με το
 * `CATEGORICAL_BLOCKERS` και το `KINDS_WITHOUT_LEGACY_PROJECTION`: μια **δέκατη**
 * τιμή που θα προστεθεί χωρίς να χαρακτηριστεί θα λογιστεί σιωπηλά ως «όχι», και η
 * οθόνη θα κρύψει κατάλυμα που είναι διαθέσιμο.
 */
export const STAYABLE_AVAILABILITY_KINDS = [
  'conditional',
  'pets-on-request',
  'free',
] as const satisfies readonly StayAvailabilityKind[];

/** `true` αν η τιμή είναι γνωστός κάδος — ο αναλυτής του σύρματος (Στάδιο Δ). */
export function isStayAvailabilityKind(value: unknown): value is StayAvailabilityKind {
  return typeof value === 'string' && (STAY_AVAILABILITY_KINDS as readonly string[]).includes(value);
}

/** `true` αν αυτή η απάντηση επιτρέπει διαμονή στις ζητούμενες ημερομηνίες. */
export function isStayable(kind: StayAvailabilityKind): boolean {
  return (STAYABLE_AVAILABILITY_KINDS as readonly string[]).includes(kind);
}
