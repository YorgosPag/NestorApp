/**
 * **Το ημερολόγιο ως ΡΗΤΗ ΕΙΣΟΔΟΣ** — και αυτός ο τύπος **είναι** η απόφαση του §3.2.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΕΙΣΟΔΟΣ ΚΑΙ ΟΧΙ ΑΝΑΓΝΩΣΗ ΜΕΣΑ ΣΤΗ ΜΗΧΑΝΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το §4.5 απαγορεύει **ρητά** ημερολόγιο μέσα στο `PublicListing` (τρεις δεσμευτικοί
 * λόγοι). Οι κρατήσεις είναι **ιδιωτικές** και ο ανώνυμος **δεν** τις διαβάζει. Άρα ο
 * κριτής **δεν μπορεί** να τρέξει στον πελάτη πάνω σε δικά του δεδομένα — τρέχει στον
 * **διακομιστή**, και το αποτέλεσμα φτάνει εδώ ως **απάντηση**.
 *
 * 🔑 **Ίδιο ιδίωμα με το `ListingMatchFacts`**: *«ρητές είσοδοι αντί για άντληση μέσα
 * στη μηχανή… τα δηλωμένα κενά είναι **ορατά στην υπογραφή** αντί να είναι κρυμμένα σε
 * ένα `fetch` που κάποιος θα ανακαλύψει»*. Και ίδιο με τον κριτή: *«ο **καλών**
 * μεταφράζει το μοντέλο του σε `Occupancy` **πριν** φτάσει εδώ»*.
 *
 * ⚠️ **Το `'undeclared'` ΔΕΝ είναι κενός πίνακας καταλήψεων, και η σύγχυση των δύο
 * είναι το overbooking σε μορφή οθόνης.** Κενός πίνακας = *«ρωτήσαμε, δεν κρατά
 * κανείς»*. `undeclared` = *«κανείς δεν συνέδεσε ημερολόγιο»*. Ένα
 * `occupied: readonly Occupancy[]` και για τα δύο θα έλεγε **«ελεύθερο»** στη δεύτερη
 * περίπτωση — ακριβώς το *«το 0 σήμαινε ότι κανείς δεν κοίταξε»*.
 *
 * @typeParam TSource — η πηγή κάθε κατάληψης, **αδιαφανής** όπως στον κριτή. Στη Φ5
 *   θα είναι `StayBooking`· η μηχανή δεν το ξέρει και δεν πρέπει.
 */
export type StayCalendar<TSource> =
  /** **Κανείς δεν δήλωσε ημερολόγιο** για αυτό το κατάλυμα. Δεν είναι «ελεύθερο». */
  | { readonly kind: 'undeclared' }
  /**
   * 🔴 **Δηλωμένο, αλλά ΔΕΝ διαβάστηκε** (χαλασμένη κεφαλή, κανόνες ή μήνας — ADR-835 §21).
   * Ποτέ «ελεύθερο» και ποτέ «αδήλωτο»: είναι **δικό μας** χρέος.
   */
  | { readonly kind: 'unreadable' }
  /**
   * Δηλωμένο ημερολόγιο. Οι καταλήψεις είναι **ήδη φιλτραρισμένες** από τον καλούντα
   * (`stayCalendarOccupancies`): αιτήματα που δεν καταλαμβάνουν **δεν** φτάνουν εδώ
   * (§6.1), και οι νύχτες **προετοιμασίας** είναι ήδη μέσα ως καταλήψεις.
   *
   * 🔑 **Οι κανόνες ταξιδεύουν ΜΑΖΙ με το ημερολόγιο** (Στάδιο Β): χωρίς δηλωμένο
   * ημερολόγιο δεν υπάρχουν ούτε κανόνες ανά ημέρα — άρα δεν χωράει «μισή» είσοδος.
   */
  | {
      readonly kind: 'declared';
      readonly occupied: readonly Occupancy<TSource>[];
      readonly rules: StayRulesInput;
      /** Μιλούν τα κανάλια; Δες {@link StayChannelTrust} — Στάδιο Γ, §22. */
      readonly channels: StayChannelTrust;
      /**
       * **Είναι αυτή η κατάληψη ΖΩΝΤΑΝΟ ΑΙΤΗΜΑ; Ως πότε;** (Στάδιο Δ, §23.5) — `null` = σκληρή κατάληψη.
       *
       * 🔑 Η μηχανή είναι αδιαφανής ως προς την πηγή (`TSource`), άρα **δεν μπορεί** να κοιτάξει
       * μέσα της· η ερώτηση ταξιδεύει ως **συνάρτηση** από την **ΜΙΑ** σύνθεση (`stayCalendarOf`).
       * 🔴 **Υποχρεωτικό**, όπως το `channels`: προαιρετικό θα έκανε κάθε νέο καλούντα να λέει
       * σιωπηλά «όλα σκληρά» — δηλαδή «κλειστό» αντί για «σε αναμονή ως 14:00».
       */
      readonly heldUntilOf: (source: TSource) => string | null;
    };

/**
 * **Μιλούν τα κανάλια αυτού του καταλύματος;** (ADR-835 §22, Στάδιο Γ)
 *
 * 🔴 **ΥΠΟΧΡΕΩΤΙΚΟ ΠΕΔΙΟ, ΟΧΙ ΠΡΟΑΙΡΕΤΙΚΟ — ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ.** Ένα
 * `channels?: StayChannelTrust` θα σήμαινε ότι ο επόμενος καλών που το ξεχνά παράγει
 * **υπόσχεση** («όλα συγχρονισμένα») χωρίς να το ξέρει — fail-**open** στο ακριβώς λάθος
 * σημείο. Με υποχρεωτικό πεδίο, η απάντηση στο *«ρώτησες τα κανάλια;»* είναι **ορατή
 * στην υπογραφή**, όπως τα δηλωμένα κενά του `ListingMatchFacts`.
 *
 * - `synced`: κάθε πηγή διαβάστηκε μέσα στο όριο εμπιστοσύνης (ή δεν υπάρχει πηγή).
 * - `stale`: **τουλάχιστον μία** πηγή σώπασε πάνω από το όριο ⇒ ό,τι θα λέγαμε
 *   «ελεύθερο» γίνεται `unsynced`· ό,τι ξέρουμε πιασμένο **μένει** πιασμένο.
 */
export type StayChannelTrust = 'synced' | 'stale';

/**
 * **Η ΤΡΙΤΗ ΚΑΤΑΣΤΑΣΗ, ΩΣ ΕΙΣΟΔΟΣ** (§4.7 — απόφαση Giorgio 2026-08-31).
 *
 * 🔑 **Δεν χρειάζεται νέο πεδίο για να το ξέρουμε**: το `offerKinds` περιέχει **ήδη**
 * `sell` δίπλα στο `leaseShort`, άρα η συνύπαρξη είναι **δομικά** γνωστή. Αυτό εδώ
 * κουβαλά μόνο το ένα πράγμα που **δεν** προκύπτει από το σχήμα: **από πότε**.
 *
 * ⚠️ **`conditionalFrom: null` σημαίνει «από την αρχή», ΟΧΙ «καμία αίρεση».** Η
 * απουσία ημερομηνίας παράδοσης δεν κάνει την πώληση να μην υπάρχει — κάνει την
 * αίρεση **ευρύτερη**. Ένα `null` που διαβαζόταν ως «χωρίς αίρεση» θα ισοπέδωνε το
 * `conditional` σε `free`, που το §4.7 ονομάζει *«ψέμα προς τον επισκέπτη»*.
 */
export interface StaySaleExposure {
  /**
   * ISO `YYYY-MM-DD` — από πότε η διαμονή τελεί υπό αίρεση (ημερομηνία παράδοσης
   * δεσμευμένης πώλησης). `null` = **δεν ξέρουμε ημερομηνία** ⇒ όλο το παράθυρο.
   */
  readonly conditionalFrom: string | null;
}

