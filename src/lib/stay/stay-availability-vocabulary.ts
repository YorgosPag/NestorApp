/**
 * **Τι ρώτησε ο άνθρωπος.** Ημι-ανοιχτό `[checkIn, checkOut)` — δες `StayBooking`.
 *
 * ⚠️ **Και τα τρία υποχρεωτικά μαζί, ή κανένα.** Ένα παράθυρο χωρίς ημερομηνία λήξης
 * δεν είναι «σχεδόν ερώτηση»: το {@link StayQuery} κατασκευάζεται **μόνο** από
 * φίλτρα που έχουν **και** τα δύο άκρα, και ο κωδικοποιητής της διεύθυνσης το
 * επιβάλλει (ίδιο ιδίωμα με το `lat`/`lng` του `GeoCircle`: *«μισό ζεύγος δεν
 * είναι σχεδόν σωστό»*).
 *
 * 🔑 **Το `guests` είναι `null` όταν ΔΕΝ ρωτήθηκε** — και τότε η χωρητικότητα **δεν
 * κρίνεται καθόλου**. Ένα `?? 1` εδώ θα σήμαινε ότι κάθε αναζήτηση χωρίς άτομα ρωτά
 * σιωπηλά «ένα άτομο», δηλαδή σιωπηλή απόφαση στο ακριβώς λάθος σημείο.
 */
export interface StayQuery {
  /** ISO `YYYY-MM-DD` — η **άφιξη**. Ανήκει στο διάστημα. */
  readonly checkIn: string;
  /** ISO `YYYY-MM-DD` — η **αναχώρηση**. **ΔΕΝ** ανήκει στο διάστημα. */
  readonly checkOut: string;
  /** Πόσα άτομα· `null` = **δεν ρωτήθηκε**, ποτέ «ένα». */
  readonly guests: number | null;
  /**
   * Πόσα κατοικίδια φέρνει (ADR-777 §8.60.21). Απόν / `null` / `0` = **δεν ρωτήθηκε** — ο όρος
   * κατοικιδίων δεν κρίνεται. Προαιρετικό **επειδή η απουσία έχει ήδη τη σωστή σημασία**
   * («χωρίς κατοικίδιο»)· δεν υπάρχει σιωπηλή απάντηση να κρυφτεί πίσω του.
   *
   * ⛔ Ο σκύλος βοήθειας **δεν μετριέται εδώ** — δεν είναι κατοικίδιο.
   */
  readonly pets?: number | null;
}

