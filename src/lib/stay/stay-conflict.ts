import {
  occupancyConflicts,
  type OccupancyPolicy,
  type OccupancyVerdict,
} from '@/lib/occupancy/occupancy-conflict';
import { stayOccupancyOf, type StayBooking } from '@/types/stay-booking';

/**
 * **Ο ίδιος κάτοχος ⇒ ΣΥΓΚΡΟΥΣΗ** — η δηλωμένη πολιτική της κράτησης.
 *
 * 🔴 **Το ΑΝΤΙΘΕΤΟ του `MANDATE_OCCUPANCY_POLICY`, και εκεί είναι όλο το μάθημα.** Μια
 * εντολή είναι **σχέση** που ανανεώνεται (νέοι όροι προς το ίδιο γραφείο =
 * αντικατάσταση). Μια κράτηση είναι **γεγονός**: ο ίδιος άνθρωπος μπορεί να έχει δέκα
 * διαμονές, αρκεί να μην πέφτουν η μία πάνω στην άλλη. Δύο διαμονές είναι **δύο
 * διαμονές** — και δύο κλειδιά στην ίδια πόρτα την ίδια νύχτα δεν γίνονται ένα επειδή
 * τα ζήτησε ο ίδιος άνθρωπος.
 *
 * ⚠️ Όσο ο κανόνας ζούσε ως `if` μέσα στον βρόχο του κριτή, αυτός εδώ ο καταναλωτής θα
 * τον κληρονομούσε **αθόρυβα**. Η σιωπηλή κληρονομιά λέγεται **διπλοκράτηση**.
 */
export const STAY_OCCUPANCY_POLICY: OccupancyPolicy = { sameHolder: 'conflicts' };

/** Η ετυμηγορία, με τις **κρατήσεις** ως πηγή. Δες `OccupancyVerdict`. */
export type StayConflictVerdict = OccupancyVerdict<StayBooking>;

/**
 * **Χωράει αυτή η κράτηση δίπλα σε εκείνες;**
 *
 * @param candidate — η κράτηση που ζητείται ή επιβεβαιώνεται.
 * @param existing — οι κρατήσεις που **καταλαμβάνουν** τον ίδιο χώρο ταυτοτήτων.
 *   Πέρνα τις μέσα από {@link occupyingStays} — δες την κεφαλίδα.
 *
 * 🔑 **Η ίδια η υποψήφια μπορεί να βρίσκεται μέσα στο `existing` χωρίς πρόβλημα**: ο
 * κριτής την αναγνωρίζει από το `occupancyId` και **δεν** τη συγκρίνει με τον εαυτό
 * της. Αυτό κάνει την επανεπιβεβαίωση και την αλλαγή ημερομηνιών **ασφαλείς χωρίς
 * χειρόγραφο φιλτράρισμα** στον καλούντα — δηλαδή χωρίς ένα ακόμη σημείο που κάποιος
 * μπορεί να ξεχάσει.
 *
 * ⚠️ **`undetermined` ΔΕΝ σημαίνει «ελεύθερο»** (§6.4): *«ένα ελεύθερο εκεί **είναι**
 * το overbooking»*. Ο καλών πρέπει να αποφασίσει τι σημαίνει — και για τις κρατήσεις
 * η απόφαση είναι ήδη γραμμένη: **άρνηση με λόγο**, ποτέ σιωπηλή αποδοχή.
 */
export function stayConflicts(
  candidate: StayBooking,
  existing: readonly StayBooking[],
): StayConflictVerdict {
  return occupancyConflicts(
    stayOccupancyOf(candidate),
    existing.map(stayOccupancyOf),
    STAY_OCCUPANCY_POLICY,
  );
}
