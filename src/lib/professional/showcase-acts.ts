import {
  resolveShowcaseActs,
  type DeclaredShowcaseAct,
  type ShowcaseAct,
} from '@/config/isco-showcase-acts';
import type { ShowcaseCredential } from '@/types/agency-profile';

/**
 * Η πράξη που **δεν κερδίζεται** — δες το docblock του πίνακα *(fail-open)*.
 *
 * 🔑 Κάθε **δημοσιευμένος** επαγγελματίας είναι προσεγγίσιμος. Η δημοσίευση είναι
 * ήδη η απόφασή του *(ADR-841 §9.4)*· μια δεύτερη κρίση εδώ θα μπορούσε να
 * **διαφωνήσει** μαζί της και να τον κάνει αόρατο ενώ ζήτησε να φαίνεται.
 */
const UNIVERSAL_ACT: ShowcaseAct = 'contact';

/**
 * *«Τι μπορεί να ζητήσει ο επισκέπτης από αυτή τη βιτρίνα;»*
 *
 * @param credentials Τα credentials της **δημοσιευμένης** βιτρίνας.
 * @returns Σύνολο πράξεων — **πάντα** περιέχει το `'contact'`.
 *
 * ⚠️ **`Set` και όχι πίνακας**: ο καταναλωτής ρωτά *«περιέχει;»*, ποτέ *«ποια
 * είναι η πρώτη;»*. Ένας πίνακας θα καλούσε σε `acts[0]`, δηλαδή σε **σειρά** που
 * κανείς δεν αποφάσισε — και η σειρά των κουμπιών είναι απόφαση **της οθόνης**.
 */
export function actsFor(credentials: readonly ShowcaseCredential[]): ReadonlySet<ShowcaseAct> {
  const acts = new Set<ShowcaseAct>([UNIVERSAL_ACT]);
  for (const credential of credentials) {
    for (const act of resolveShowcaseActs(credential.occupation.iscoCode)) {
      acts.add(act);
    }
  }
  return acts;
}

/**
 * *«Επιτρέπεται να ζητηθεί από αυτή τη βιτρίνα **εντολή μεσιτείας**;»*
 *
 * 🔑 **Υπάρχει επειδή το ρωτούν ΤΡΕΙΣ**: η βιτρίνα *(τι δείχνω)*, η σελίδα της
 * φόρμας *(ανοίγω;)* και ο γραφέας του αιτήματος *(δέχομαι;)*. Χωρίς όνομα, το
 * `actsFor(…).has('mandate')` θα γραφόταν τρεις φορές — και η μία θα ξεχνούσε.
 *
 * ⚠️ **Ο τελευταίος από τους τρεις είναι ο ΜΟΝΟΣ φρουρός**: οι δύο πρώτοι κρύβουν
 * κουμπί, δηλαδή δεν φυλάνε τίποτα *(`brokerage-authority.ts:24` — «ΤΟ ΜΕΝΟΥ ΔΕΝ
 * ΕΙΝΑΙ ΦΡΟΥΡΟΣ»)*.
 */
export function acceptsMandate(credentials: readonly ShowcaseCredential[]): boolean {
  return actsFor(credentials).has('mandate');
}

export type { DeclaredShowcaseAct, ShowcaseAct };
