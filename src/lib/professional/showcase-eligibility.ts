/**
 * ADR-841 **Φ6-Β** — *«ΑΠΑΙΤΕΙ ΑΥΤΟ ΤΟ ΕΠΑΓΓΕΛΜΑ ΑΔΕΙΑ ΤΗΣ ΠΛΑΤΦΟΡΜΑΣ;»*
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΤΟ ΕΡΩΤΗΜΑ ΠΟΥ ΑΠΑΝΤΗΘΗΚΕ ΠΡΙΝ ΓΡΑΦΤΕΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ
 *
 * Η Φ6-Β ξεκίνησε με τη χαρτογράφηση να καταλήγει σε **δεύτερη οργανωσιακή
 * ικανότητα** και **εννέα αδελφά αρχεία** — δηλαδή ~1.500 γραμμές σχεδόν
 * ταυτόσημου κώδικα, ακριβώς το σχήμα που απαγορεύουν το **N.18** και το
 * **ADR-749**. Το ερώτημα που δεν είχε τεθεί ήταν: *χρειάζεται καθόλου;*
 *
 * ⛔ **ΟΧΙ — και το γράφει ο ίδιος ο κώδικας**, σε τέσσερα ανεξάρτητα σημεία:
 *
 *   `types/organization-capability.ts:51-57`
 *     *«**Μια ικανότητα χωρίς ρυθμιστικό αντίκρισμα δεν ανήκει εδώ**: αυτό το
 *     αρχείο δεν είναι σάκος σημαιών»* · *«η δεύτερη θα χρειαστεί **ΛΟΓΟ**»*
 *   `lib/auth/brokerage-authority.ts:6-7`
 *     το ερώτημα δεν είναι *«να δημοσιεύσει βιτρίνα;»* αλλά *«να δημοσιεύσει
 *     αγγελία για **ΞΕΝΟ ακίνητο**;»*
 *   `services/mandate/agency-profile.service.ts:10-14`
 *     *«Η **ικανότητα** είναι απόφαση της **πλατφόρμας**… Η **δημοσίευση** είναι
 *     απόφαση του **γραφείου**»* — οι δύο έννοιες ήταν **ήδη χωρισμένες**
 *   `organization-capability.ts:147-152`
 *     πόρτα σε αρχιτέκτονα θα *«διαφήμιζε ρυθμιζόμενη δραστηριότητα που ο
 *     Ν.4072/2012 του απαγορεύει»*
 *
 * 🔑 Και το **λειτουργικό** επιχείρημα που έκλεισε τη συζήτηση: η ικανότητα έχει
 * `pending`, δηλαδή **άνθρωπο-εγκριτή**. Δεύτερη ικανότητα σημαίνει *super-admin
 * ανά ελαιοχρωματιστή* — και, χειρότερα, σημαίνει ότι η πλατφόρμα
 * **ισχυρίζεται ότι έλεγξε**, που είναι ακριβώς αυτό που η **Α9.2** απαγορεύει.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * ✅ Η ΘΕΡΑΠΕΙΑ: **ΔΕΥΤΕΡΟΣ ΚΑΤΑΝΑΛΩΤΗΣ ΤΗΣ ΥΠΑΡΧΟΥΣΑΣ**, ΟΧΙ ΝΕΑ ΙΚΑΝΟΤΗΤΑ
 *
 * Ένα επάγγελμα **όντως** χρειάζεται φρουρό — η **μεσιτεία**, γιατί εκεί η ίδια
 * η *διαφήμιση* είναι η ρυθμιζόμενη πράξη. Χωρίς φρουρό, οποιοσδήποτε θα δήλωνε
 * «μεσίτης» και θα εμφανιζόταν στο `/pro` δίπλα στα ελεγμένα γραφεία:
 * **παλινδρόμηση εγγύησης που σήμερα υπάρχει**.
 *
 * Και το θεμέλιο της Φ6-Α τον έχει **ήδη** κατασκευάσει:
 *
 *   `isco-registry-authority.ts` → `'3334': { authority: 'gemi', … }`
 *
 * ⇒ *«αυτό το επάγγελμα οδηγεί σε ΓΕΜΗ»* **είναι** *«αυτό το επάγγελμα απαιτεί
 * `brokerage_listings === 'active'`»*. **Μία ερώτηση πάνω σε υπάρχουσα καθαρή
 * συνάρτηση.** Καμία νέα ικανότητα, καμία νέα αρχή, κανένας νέος εγκριτής.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * ⚠️ ΓΙΑΤΙ ΚΑΘΑΡΟ LEAF ΚΑΙ ΟΧΙ HOOK
 *
 * Το ρωτούν **δύο** καταναλωτές με ασύμβατα περιβάλλοντα: το **route** *(server,
 * πριν τη γραφή)* και η **φόρμα δημοσίευσης** *(client, για να δείξει ή να
 * κρύψει πεδία)*. Ένα hook θα ήταν άχρηστο στον πρώτο· μια συνάρτηση μέσα στο
 * service θα ήταν αόρατη στον δεύτερο. Ίδιος ακριβώς λόγος και ίδια μορφή με το
 * `lib/agency/agency-door.ts`, που το **CHECK 3.34 επέβαλε** να βγει από hook σε
 * leaf *(ADR-841 Α6.4)*.
 *
 * @module lib/professional/showcase-eligibility
 * @see docs/centralized-systems/reference/adrs/ADR-841-public-listing-body-and-platform-verticals.md — Α9
 * @see docs/centralized-systems/reference/adrs/ADR-824-organization-capability.md — η ικανότητα
 */

import { resolveRegistryAuthority } from '@/config/isco-registry-authority';

/**
 * Η **μία** αρχή που σημαίνει *«η πλατφόρμα οφείλει να ρωτήσει πρώτα»*.
 *
 * 🔑 **ΓΙΑΤΙ ΑΡΧΗ ΚΑΙ ΟΧΙ ΔΕΥΤΕΡΗ ΛΙΣΤΑ ISCO**: μια λίστα `['3334', …]` εδώ θα
 * ήταν **δεύτερο βιβλίο** δίπλα στο `ISCO_REGISTRY_AUTHORITY` — και τα δύο θα
 * απαντούσαν για το ίδιο επάγγελμα, με το δεύτερο να ξεχνά την επόμενη γραμμή.
 * Το `'gemi'` **είναι ήδη** ο δείκτης: στον πίνακα, ο **μόνος** κωδικός που
 * δείχνει εκεί είναι το `3334` *(real estate agents)*.
 *
 * ⚠️ **ΚΑΙ ΘΑ ΣΠΑΣΕΙ ΣΩΣΤΑ ΑΝ ΑΛΛΑΞΕΙ**: αν κάποτε δηλωθεί δεύτερος κωδικός με
 * `authority: 'gemi'` που **δεν** ασκεί μεσιτεία, το ερώτημα εδώ θα του ζητούσε
 * ικανότητα που δεν του αναλογεί — και η **άγκυρα του παρονομαστή** *(«ο
 * ελαιοχρωματιστής δημοσιεύει χωρίς καμία ικανότητα»)* δεν αρκεί για να το
 * πιάσει. Ο φρουρός είναι η **ίδια η στενότητα του πίνακα**: το ΓΕΜΗ μπήκε εκεί
 * ρητά ως *«η απόδειξη ότι ο μεσίτης είναι υπαρκτός και αδειοδοτημένος»*.
 */
const CAPABILITY_GATED_AUTHORITY = 'gemi' as const;

/**
 * *«Απαιτεί αυτό το επάγγελμα άδεια της πλατφόρμας για να δημοσιευτεί;»*
 *
 * @param iscoCode Ο κωδικός ISCO-08 της **δηλωμένης ειδικότητας**.
 * @returns `true` **μόνο** για τη ρυθμιζόμενη δραστηριότητα *(μεσιτεία)*.
 *
 * ⚠️ **Το `false` δεν σημαίνει «ελεύθερος»** — σημαίνει *«η πλατφόρμα δεν έχει
 * τίποτα να κρίνει»*. Ο φρουρός απέναντι στην **ψευδή δήλωση** είναι αλλού, και
 * είναι το ίδιο το σχήμα: `declared` ≠ `verified`, με την οθόνη να λέει **ποια
 * από τις δύο** ισχύει *(ADR-798 §7)*. Ένα `pending` εδώ θα αντικαθιστούσε μια
 * **τίμια** διάκριση με μια **ανθρώπινη έγκριση που κανείς δεν θα έκανε**.
 */
export function occupationNeedsCapability(iscoCode: string | null | undefined): boolean {
  const verdict = resolveRegistryAuthority(iscoCode);
  return verdict.kind === 'authority' && verdict.authority === CAPABILITY_GATED_AUTHORITY;
}
