/**
 * @fileoverview **Η ΣΤΑΣΗ ΤΟΥ ΑΡΙΘΜΟΥ** — «το είπε ο άνθρωπος» δεν είναι «το ξέρουμε».
 * @related ADR-777 §7 (Α5) · SPEC-777A §13.3 · lib/geocoding/geocoding-types
 * @module lib/geocoding/house-number-standing
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΚΕΝΟ ΠΟΥ ΚΛΕΙΝΕΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο άνθρωπος γράφει **«Σαμοθράκης 16»**· ο πάροχος απαντά **«Σαμοθράκης»**, χωρίς
 * αριθμό. Μέχρι σήμερα η οθόνη είχε **μία** λέξη γι' αυτό — τον βαθμό ακρίβειας
 * (`interpolated`, «δρόμος χωρίς αριθμό») — που περιγράφει **την απάντηση** και
 * αποσιωπά **την ερώτηση**. Ο άνθρωπος έβλεπε «δρόμος χωρίς αριθμό» ενώ **είχε δώσει
 * αριθμό**, και δεν μάθαινε ποτέ τι απέγινε.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΟ ΠΡΟΤΥΠΟ: Η GOOGLE ΞΕΧΩΡΙΖΕΙ «ΤΙ ΕΔΩΣΕ» ΑΠΟ «ΤΙ ΕΠΑΛΗΘΕΥΣΑ»
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το Address Validation API επιστρέφει `inputGranularity` **και**
 * `validationGranularity`, και ανά συστατικό ένα `confirmationLevel` με τιμή που εδώ
 * περιγράφει **ακριβώς** την ελληνική πραγματικότητα:
 *
 * > **`UNCONFIRMED_BUT_PLAUSIBLE`** — *«This component could not be confirmed, but it
 * > is plausible that it exists. For example, **a street number within a known valid
 * > range of numbers on a street where specific house numbers are not known**.»*
 *
 * Αυτό είναι, κατά λέξη, η κάλυψη **46 %** των ελληνικών κτιρίων σε `addr:housenumber`
 * (μέτρηση του έργου, κέντρο Θεσσαλονίκης): ο αριθμός **υπάρχει στον κόσμο** και **δεν
 * υπάρχει στα δεδομένα**. Η ειλικρινής απάντηση δεν είναι ούτε «ακριβές» ούτε
 * «δεν ξέρω πού είσαι» — είναι **«το είπες, δεν μπόρεσα να το επιβεβαιώσω»**.
 *
 * 🏆 **Τα portals δεν το λένε**: Zillow / Redfin / Idealista δέχονται ό,τι επιστρέψει ο
 * γεωκωδικοποιητής και ζητούν από τον χρήστη **να σύρει την πινέζα** — δηλαδή
 * μεταφέρουν σε αυτόν μια αβεβαιότητα που ποτέ δεν του ονόμασαν.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΚΑΜΙΑ ΝΕΑ ΜΕΤΡΗΣΗ — ΜΟΝΟ ΟΝΟΜΑ ΣΕ ΤΙΜΗ ΠΟΥ ΗΔΗ ΥΠΑΡΧΕΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η κρίση **δεν** υπολογίζεται εδώ: το `reasoning.fieldMatches.number` του
 * `buildFieldMatches` την κάνει ήδη, στον διακομιστή, με κανονικοποίηση ελληνικών.
 * Αυτό το αρχείο είναι **μετάφραση**, όχι δεύτερος κριτής — μια δεύτερη σύγκριση
 * αριθμών θα ήταν ακριβώς το σχήμα «δύο απαντήσεις για το ίδιο ερώτημα».
 *
 * 🔴 Και γι' αυτό η στάση ήταν **δομικά ανέφικτη** πριν από το
 * {@link addressLineToQuery}: όσο ο αριθμός ταξίδευε μέσα στο `city`, το
 * `fieldMatches.number` ήταν **πάντα** `'not-provided'`.
 */

import type { FieldMatchKind } from './geocoding-types';

/**
 * Πού στέκεται ο αριθμός της διεύθυνσης — **δηλωμένος** ⇄ **επιβεβαιωμένος**.
 *
 * Τέσσερις τιμές, καμία περιττή: κάθε μία οδηγεί **διαφορετική** πρόταση στην οθόνη,
 * και δύο από αυτές είναι σήμερα αδιάκριτες στον χρήστη.
 */
export type HouseNumberStanding =
  /** Ο άνθρωπος **δεν** έδωσε αριθμό. Δεν λείπει τίποτα — δεν ζητήθηκε. */
  | 'absent'
  /** Δόθηκε **και** τον επιβεβαιώνει ο πάροχος ⇒ ξέρουμε το κτίριο. */
  | 'confirmed'
  /**
   * Δόθηκε, και ο πάροχος **δεν τον ξέρει**. Google: `UNCONFIRMED_BUT_PLAUSIBLE`.
   *
   * ⚠️ **ΔΕΝ σημαίνει λάθος.** Σημαίνει ότι τα δεδομένα του χάρτη δεν φτάνουν ως εκεί —
   * η συνηθέστερη περίπτωση στην Ελλάδα. Ο βαθμός ακρίβειας μένει `interpolated` και ο
   * **δακτύλιος αβεβαιότητας** της Α5 είναι η σωστή ζωγραφιά, όχι υποβάθμιση.
   */
  | 'unconfirmed'
  /**
   * Δόθηκε, και ο πάροχος επιστρέφει **άλλον**. Google: `UNCONFIRMED_AND_SUSPICIOUS`.
   *
   * 🔑 Η μόνη από τις τέσσερις που δικαιολογεί να **ρωτήσουμε ξανά** τον άνθρωπο: δεν
   * είναι κενό δεδομένων, είναι **διαφωνία** — ή τυπογραφικό δικό του, ή ο πάροχος
   * κόλλησε σε γειτονικό κτίριο.
   */
  | 'contradicted';

/**
 * Μεταφράζει την ετυμηγορία πεδίου του διακομιστή σε **στάση**.
 *
 * ⚠️ **Το `undefined` είναι `'absent'`, όχι σφάλμα**: παλιές απαντήσεις από τη μνήμη
 * (και οι εναλλακτικές) μπορεί να μην κουβαλούν πίνακα ταιριάσματος, και μια εξαίρεση
 * εκεί θα έριχνε την οθόνη για πληροφορία που είναι **διακοσμητική**.
 */
export function houseNumberStanding(match: FieldMatchKind | undefined): HouseNumberStanding {
  switch (match) {
    case 'match':
      return 'confirmed';
    case 'unknown':
      return 'unconfirmed';
    case 'mismatch':
      return 'contradicted';
    default:
      return 'absent';
  }
}
