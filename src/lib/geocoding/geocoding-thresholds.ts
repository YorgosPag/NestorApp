/**
 * Οι βαθμοί ακρίβειας που εντοπίζουν **συγκεκριμένο σημείο** και όχι το κέντρο μιας περιοχής.
 *
 * 🔑 Η διάκριση δεν είναι λεπτομέρεια ποιότητας — είναι διαφορά **τάξης μεγέθους**. Ένα
 * `'center'` σημαίνει «δεν βρήκα τη διεύθυνση, σου δίνω το κέντρο του οικισμού»: απόκλιση
 * χιλιομέτρων, με αποτέλεσμα που **μοιάζει απόλυτα σωστό** σε κάθε επιφάνεια που το δείχνει.
 * Οι υπόλοιποι τρεις βαθμοί εντοπίζουν κτίριο, παρεμβολή επί του οδικού άξονα, ή κοντινό σημείο —
 * όλα εντός του «οικοδομικού τετραγώνου» που είναι η δηλωμένη ακρίβεια μιας διεύθυνσης.
 *
 * ⚠️ Είναι **σύνολο επιτρεπτών** και όχι «όλα εκτός από `center`» επίτηδες: αν αύριο προστεθεί
 * βαθμός στην ταξινομία, ο μεταγλωττιστής **δεν** θα είχε γνώμη για ένα «όχι center», και ο νέος
 * βαθμός θα περνούσε σιωπηλά ως αποδεκτός χωρίς κανείς να το αποφασίσει.
 */
export const POINT_LEVEL_ACCURACIES: ReadonlySet<GeocodingAccuracy> = new Set<GeocodingAccuracy>([
  'exact',
  'interpolated',
  'approximate',
]);
