import { parseAddressLine } from '@/utils/address/address-parse';
import type { GeocodingRequestBody } from './geocoding-types';

/**
 * Μεταφράζει μια **γραμμή που πληκτρολόγησε άνθρωπος** σε ερώτημα προς τη μηχανή.
 *
 * ⚠️ **Τα ονόματα των πεδίων ΔΕΝ συμπίπτουν τυχαία** με το {@link GeocodingRequestBody}:
 * η {@link parseAddressLine} γράφει το ίδιο λεξιλόγιο επίτηδες, ώστε η μετάφραση να
 * είναι **αντιγραφή πεδίων** και όχι χάρτης — ένας χάρτης θα ήταν το σημείο όπου δύο
 * λεξιλόγια αποκλίνουν σιωπηλά.
 *
 * ⚠️ **Η χώρα ΔΕΝ συμπληρώνεται εδώ.** Το `country` ενεργοποιεί τον περιορισμό
 * `countrycodes` στη μηχανή, και μια σιωπηλή «Ελλάδα» θα έκανε **αδύνατη** τη
 * διεύθυνση εκτός Ελλάδας — απόφαση που ανήκει στον καλούντα, όχι στον μεταφραστή.
 */
export function addressLineToQuery(raw: string): GeocodingRequestBody {
  const parsed = parseAddressLine(raw);
  return {
    street: parsed.street,
    number: parsed.number,
    postalCode: parsed.postalCode,
    city: parsed.city,
  };
}
