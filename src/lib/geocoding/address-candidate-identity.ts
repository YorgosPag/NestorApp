import { distanceMeters } from '@/lib/geo/geo-distance';
import { normalizeGreekText } from '@/utils/greek-text';
import type { ResolvedAddressFields } from './geocoding-types';

/**
 * Ακτίνα μέσα στην οποία **ο ίδιος αριθμός στον ίδιο δρόμο** είναι η ίδια πόρτα,
 * γραμμένη δύο φορές στο OSM.
 *
 * **150 m ≈ ένα οικοδομικό τετράγωνο** ελληνικής πόλης. Δεν είναι στρογγυλό νούμερο
 * από διαίσθηση — είναι το κατώφλι που η μέτρηση της 02/09 απαιτεί και **μόλις** που
 * φτάνει και στις δύο κατευθύνσεις:
 *
 * - **πρέπει να καταρρέει**: Τσιμισκή 43 → 4 POI σε **57 m** · Αγ. Δημητρίου 55
 *   (Θεσσαλονίκη) → 2 σειρές σε **100 m** · Ερμού 10 / Πατησίων 76 → **7 m**
 * - **πρέπει να ΜΗΝ καταρρέει**: Κύπρου 12 Καλαμαριά ↔ Συκιές → **7 km** ·
 *   Αθηνάς 5 σε πέντε πόλεις → **212-349 km**
 *
 * Το πλησιέστερο ζεύγος που **οφείλει** να μείνει χωριστό απέχει **1,6 km** (Ελευθερίας 10,
 * Αμαρούσιο ↔ Νέα Ιωνία) — δηλαδή υπάρχει **μία τάξη μεγέθους** περιθώριο πάνω από το
 * κατώφλι και **μία τάξη μεγέθους** κάτω από την πρώτη γνήσια διάκριση.
 */
export const SAME_DOOR_RADIUS_M = 150;

/**
 * Το ελάχιστο που χρειάζεται για να κριθεί αν δύο υποψήφιοι είναι η ίδια επιλογή.
 *
 * Δηλωμένο **δομικά** (όχι `GeocodingApiResponse`) ώστε να δέχεται και το πλήρες
 * αποτέλεσμα και τη «ρηχή» εναλλακτική (`GeocodingAlternative`) **χωρίς** μετατροπή —
 * μια μετατροπή θα ήταν ακριβώς το σημείο όπου οι δύο πλευρές αποκλίνουν.
 */
export interface AddressChoiceLike {
  readonly lat: number;
  readonly lng: number;
  /** Η γραμμή που **διαβάζει ο άνθρωπος**. */
  readonly displayName: string;
  readonly resolvedFields: ResolvedAddressFields;
}

/** Κενό, `'∅'` και «μόνο κενά» είναι το ίδιο πράγμα: **δεν ειπώθηκε**. */
function normalized(value: string | undefined): string | null {
  if (!value) return null;
  const trimmed = normalizeGreekText(value).trim().replace(/\s+/g, ' ');
  return trimmed === '' ? null : trimmed;
}

/**
 * Είναι αυτά τα δύο **η ίδια ερώτηση** προς τον άνθρωπο;
 *
 * Δύο ρήτρες, καμία διακοσμητική:
 *
 * 1. **Ίδια ορατή γραμμή** ⇒ ίδια επιλογή. Ένας κατάλογος δεν μπορεί να ζητήσει από
 *    κάποιον να διαλέξει ανάμεσα σε δύο **ταυτόσημες** σειρές· ό,τι κι αν λένε τα
 *    δεδομένα από κάτω, η επιλογή του δεν θα σήμαινε τίποτα.
 * 2. **Ίδια πόρτα** ⇒ ίδια επιλογή: ίδιος αριθμός *(ή απών και στα δύο)*, ίδια οδός,
 *    και απόσταση κάτω από το {@link SAME_DOOR_RADIUS_M}. Αυτό είναι το σκέλος που
 *    καταρρέει τα POI — «Μασούτης, 43 Τσιμισκή» και «43 Τσιμισκή» είναι **η πόρτα και
 *    το μαγαζί πίσω της**.
 *
 * ⚠️ Ο **απών** αριθμός και στους δύο υποψήφιους ταιριάζει επίτηδες: δύο τμήματα του
 * ίδιου δρόμου χωρίς αριθμό είναι η ίδια απάντηση «βρήκα τον δρόμο, όχι το κτίριο»
 * (μετρημένο: «Αγ. Δημητρίου 55, Θεσσαλονίκη» → **5** τμήματα `highway/secondary`,
 * κανένα με αριθμό). Αλλά **μόνο** μαζί με την ακτίνα — δύο άκρες δρόμου 991 m μακριά
 * μένουν χωριστές, γιατί εκεί η επιλογή **έχει** νόημα.
 */
export function sameAddressChoice(a: AddressChoiceLike, b: AddressChoiceLike): boolean {
  if (normalized(a.displayName) === normalized(b.displayName)) return true;

  const streetA = normalized(a.resolvedFields.street);
  const streetB = normalized(b.resolvedFields.street);
  if (streetA === null || streetB === null || streetA !== streetB) return false;

  if (normalized(a.resolvedFields.number) !== normalized(b.resolvedFields.number)) return false;

  return distanceMeters(a, b) <= SAME_DOOR_RADIUS_M;
}

/**
 * Κρατά **τον πρώτο** κάθε ομάδας ταυτόσημων επιλογών, στη σειρά που τους έδωσε ο πάροχος.
 *
 * 🔑 **«Ο πρώτος» δεν είναι αυθαίρετος**: ο Nominatim κατατάσσει κατά `importance`, οπότε
 * ο πρώτος εκπρόσωπος μιας πόρτας είναι ο **πιο αναγνωρίσιμος** — «Γενικό Προξενείο των
 * ΗΠΑ, 43 Τσιμισκή» αντί για «43 Τσιμισκή». Ο άνθρωπος αναγνωρίζει το κτίριο πιο γρήγορα
 * από τη διεύθυνσή του, και η **σειρά** του παρόχου το ξέρει ήδη· δεν την ξαναεφευρίσκουμε.
 *
 * ⚠️ **Τετραγωνικό επίτηδες**: το «ίδια πόρτα» **δεν είναι σχέση ισοδυναμίας** (η
 * απόσταση δεν είναι μεταβατική — Α~Β και Β~Γ δεν σημαίνει Α~Γ), άρα ένα `Map` κλειδιών
 * θα έδινε **λάθος** ομαδοποίηση εξαρτημένη από τη σειρά διάσχισης. Το πλήθος υποψηφίων
 * είναι φραγμένο από το `NOMINATIM_RESULT_LIMIT` (**5**) ⇒ το πολύ **10** συγκρίσεις.
 */
export function distinctAddressChoices<T extends AddressChoiceLike>(
  candidates: readonly T[],
): T[] {
  const kept: T[] = [];
  for (const candidate of candidates) {
    if (!kept.some((seen) => sameAddressChoice(seen, candidate))) kept.push(candidate);
  }
  return kept;
}
