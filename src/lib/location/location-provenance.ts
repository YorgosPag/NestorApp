// Η ΣΚΑΛΑ ΤΟΥ §21.4 — «τι μας έδωσε ο άνθρωπος», ΟΧΙ αξιοπιστία
// ============================================================================

/**
 * Σκαλοπάτι της κλίμακας γνώσης του §21.4.
 *
 * `0` **δεν είναι σκαλοπάτι** — είναι το κάτω άκρο: «άγνωστη θέση», ρητή κατάσταση,
 * ποτέ σιωπηλή εξαφάνιση (Α5). Τα σκαλοπάτια είναι τα **1–6**.
 *
 * ⚠️ **ΜΗΝ το χρησιμοποιήσεις για να αποφασίσεις ποια πηγή νικά.** Γι' αυτό υπάρχει
 * το {@link outranksForLocation}. Ο λόγος είναι μετρημένος και γραμμένος στην κορυφή
 * αυτού του αρχείου: το σκαλοπάτι **5 δίνει μηδέν θέση** ενώ το **4 δίνει σχήμα**.
 */
export type LocationKnowledgeStep = 0 | 1 | 2 | 3 | 4 | 5 | 6;

/**
 * Το σκαλοπάτι που αντιστοιχεί σε κάθε προέλευση **θέσης**.
 *
 * Το `bim` μοιράζεται το σκαλοπάτι **6** με το `survey`: και τα δύο είναι
 * *μετρημένα από σχέδιο*, και η σκάλα ρωτά «τι μας έδωσες», όχι «με ποιο εργαλείο».
 * Ο διαχωρισμός τους ζει στην **προέλευση**, που είναι και το μόνο σημείο που τον
 * χρειάζεται (§13.3: η καρτέλα δείχνει την πηγή).
 */
const STEP_OF_PROVENANCE: Readonly<Record<LocationProvenance, LocationKnowledgeStep>> = {
  geocoded: 1,
  manual: 2,
  drawn: 3,
  osm: 4,
  survey: 6,
  bim: 6,
};

/** Το σκαλοπάτι που «ξεκλειδώνει» ένα ανεβασμένο τοπογραφικό χωρίς αναγνώσιμη θέση. */
const DOCUMENT_ONLY_STEP: LocationKnowledgeStep = 5;

/**
 * Πόσο ψηλά στη σκάλα του §21.4 έφτασε αυτή η εγγραφή.
 *
 * Επιστρέφει το **ψηλότερο** από όσα έδωσε ο άνθρωπος — γιατί η σκάλα μετρά
 * *συνεισφορά*, και ένας μηχανικός που ανέβασε τοπογραφικό **και** έχει σημείο από
 * διεύθυνση έχει δώσει και τα δύο. Το ότι το ένα δεν βοηθά τον χάρτη δεν το κάνει
 * λιγότερο πραγματικό (§21.5).
 *
 * @param provenance προέλευση της θέσης· `null` = δεν ξέρουμε θέση (Α5)
 * @param hasSurveyDocument υπάρχει τοπογραφικό στον φάκελο (PDF/εικόνα/σχέδιο)
 */
export function locationKnowledgeStep(
  provenance: LocationProvenance | null,
  hasSurveyDocument: boolean
): LocationKnowledgeStep {
  const fromPosition: LocationKnowledgeStep = provenance === null ? 0 : STEP_OF_PROVENANCE[provenance];
  const fromDocument: LocationKnowledgeStep = hasSurveyDocument ? DOCUMENT_ONLY_STEP : 0;
  return fromPosition >= fromDocument ? fromPosition : fromDocument;
}

