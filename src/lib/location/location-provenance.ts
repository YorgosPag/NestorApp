/**
 * Από πού ήρθε η **θέση** (σημείο ή περίγραμμα) ενός δημόσιου πράγματος.
 *
 * 🔴 **Κλειστή ένωση, ποτέ `string`.** Η προέλευση αποφασίζει αν μια τιμή
 * επιτρέπεται να **αντικαταστήσει** το κοινό επίπεδο Α (§14.3). Ένα τυπογραφικό
 * λάθος εκεί δεν είναι εμφάνιση — είναι λάθος δικαίωμα εγγραφής.
 *
 * ⚠️ **Το `document-only` ΔΕΝ ανήκει εδώ** και η απουσία του είναι σχεδίαση:
 * «ανέβασα τοπογραφικό PDF» **δεν είναι θέση**, είναι έγγραφο. Εκφράζεται ως
 * `provenance: null` + έγγραφο στον φάκελο. Βλ. {@link locationKnowledgeStep}.
 */
export type LocationProvenance =
  /** Από διεύθυνση, μέσω geocoder — **κατά προσέγγιση**. §21.4 σκαλοπάτι 1. */
  | 'geocoded'
  /** Πινέζα που έβαλε άνθρωπος — δηλωμένο σημείο. §21.4 σκαλοπάτι 2. */
  | 'manual'
  /** Περίγραμμα που ζωγράφισε άνθρωπος στο Geo-Canvas. §21.4 σκαλοπάτι 3· §13.3. */
  | 'drawn'
  /** Δημόσιος χάρτης (OpenStreetMap). §21.4 σκαλοπάτι 4· §13.3. */
  | 'osm'
  /** Μετρημένο τοπογραφικό (DXF/`.tek` → ΕΓΣΑ87 → lat/lon). §21.4 σκαλοπάτι 6. */
  | 'survey'
  /** Μετρημένο από **δικό μας** σχέδιο BIM. §13.3. */
  | 'bim';

/**
 * Παρουσία σε **χρόνο εκτέλεσης**. Ο τύπος `Record<LocationProvenance, ...>` είναι
 * σκόπιμος: νέα τιμή στην ένωση **σπάει τη μεταγλώττιση εδώ**, άρα δεν μπορεί να
 * υπάρξει προέλευση χωρίς δηλωμένη κατάταξη. Ίδιο ιδίωμα με το
 * `PROVENANCE_ACTIVITY_PRESENCE` (`types/vqe/envelope.ts`) και το `BOQ_STATUS_RANK`.
 *
 * 🔑 **Η κατάταξη ΕΙΝΑΙ ο κανόνας του §14.3**, γραμμένος μία φορά:
 *
 *     μετρημένο από σχέδιο  >  δημόσιος χάρτης (OSM)  >  δηλωμένο από χρήστη
 *
 * Το `geocoded` παίρνει **δική του, χαμηλότερη** βαθμίδα και **δεν** είναι «δηλωμένο»:
 * κανένας άνθρωπος δεν δήλωσε αυτό το σημείο — το **συμπέρανε** μηχανή από κείμενο,
 * και το ίδιο το §21.4 το ονομάζει «κατά προσέγγιση». Αν έμπαινε μαζί με το `manual`,
 * μια αυτόματη γεωκωδικοποίηση θα μπορούσε να **σβήσει** πινέζα ανθρώπου.
 */
const LOCATION_PROVENANCE_RANK: Readonly<Record<LocationProvenance, number>> = {
  survey: 4,
  bim: 4,
  osm: 3,
  drawn: 2,
  manual: 2,
  geocoded: 1,
};

/** Κατάλογος προελεύσεων — **παράγεται**, δεν ξαναγράφεται. */
export const LOCATION_PROVENANCES: readonly LocationProvenance[] =
  Object.keys(LOCATION_PROVENANCE_RANK) as LocationProvenance[];

/**
 * Η βαθμίδα αξιοπιστίας μιας προέλευσης (μεγαλύτερο = ισχυρότερη πηγή).
 *
 * ⚠️ Οι **τιμές** δεν έχουν νόημα από μόνες τους και δεν αποθηκεύονται ποτέ —
 * μόνο η **σύγκρισή** τους. Βλ. {@link outranksForLocation}.
 */
export function locationProvenanceRank(provenance: LocationProvenance): number {
  return LOCATION_PROVENANCE_RANK[provenance];
}

/**
 * Ο κανόνας συγχώνευσης του §14.3: **επιτρέπεται** στο `candidate` να αντικαταστήσει
 * το `current` στο κοινό επίπεδο Α;
 *
 * 🔴 **Ισοβαθμία ⇒ ΟΧΙ.** Δύο τοπογραφικά της ίδιας βαθμίδας που διαφωνούν είναι
 * **σύγκρουση προς επίλυση από άνθρωπο**, όχι «το τελευταίο νικά». Το «τελευταίο
 * νικά» σε **κοινό** επίπεδο σημαίνει ότι ο τελευταίος που πάτησε αποθήκευση
 * ξαναγράφει την πραγματικότητα για **όλους** (§14.4). Η ρητή απόρριψη είναι αυτό
 * που κάνει τη σύγκρουση **ορατή** αντί για σιωπηλή.
 *
 * 🔑 `current === null` σημαίνει «δεν ξέραμε θέση» ⇒ **κάθε** προέλευση ανεβαίνει.
 * Το «άγνωστο» είναι ρητή κατάσταση (Α5), όχι τιμή που συναγωνίζεται.
 */
export function outranksForLocation(
  candidate: LocationProvenance,
  current: LocationProvenance | null
): boolean {
  if (current === null) return true;
  return locationProvenanceRank(candidate) > locationProvenanceRank(current);
}

