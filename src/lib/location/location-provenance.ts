// ΠΡΟΕΛΕΥΣΗ ΓΕΓΟΝΟΤΟΣ — για τα ΥΠΟΛΟΙΠΑ πεδία του επιπέδου Α (§14.3)
// ============================================================================

/**
 * Από πού ήρθε ένα **γεγονός** του επιπέδου Α που δεν είναι θέση — όροφοι, έτος,
 * χρήση (§14.2).
 *
 * 🔑 **Είναι υπερσύνολο της {@link LocationProvenance}, όχι δεύτερο λεξιλόγιο.** Οι
 * ίδιες πηγές παράγουν και θέση και γεγονότα: το OSM δίνει `building:levels`, το
 * δικό μας BIM δίνει ορόφους, το τοπογραφικό δίνει εμβαδόν. Ένα ξεχωριστό λεξιλόγιο
 * θα σήμαινε δύο ονόματα για την ίδια πηγή, και μία μέρα θα διαφωνούσαν.
 *
 * Προστίθεται **ένα** σκαλί που δεν υπάρχει στη θέση: το `'declared'` — «το
 * πληκτρολόγησε άνθρωπος». Δεν αντιστοιχεί σε καμία **χειρονομία θέσης** (γι' αυτό
 * λείπει από τη {@link LocationProvenance}), αλλά είναι ο **συνηθέστερος** τρόπος να
 * μάθουμε ότι το κτίριο έχει τέσσερις ορόφους.
 */
export type PlaceFactSource = LocationProvenance | 'declared';

/**
 * Βαθμίδα αξιοπιστίας ενός γεγονότος.
 *
 * Το `'declared'` παίρνει τη βαθμίδα **«δηλωμένο από χρήστη»** του §14.3 — την ίδια
 * με τα `manual`/`drawn`, γιατί είναι **ακριβώς** αυτό. Ό,τι είναι μετρημένο ή
 * δημόσιο εξακολουθεί να το ξεπερνά.
 */
export function placeFactRank(source: PlaceFactSource): number {
  return source === 'declared' ? 2 : locationProvenanceRank(source);
}

/**
 * Ο κανόνας του §14.3 για γεγονότα: επιτρέπεται στο `candidate` να αντικαταστήσει;
 *
 * Ίδια σημασιολογία με το {@link outranksForLocation}, **συμπεριλαμβανομένης της
 * ισοβαθμίας**: ισοβαθμία ⇒ όχι. Ένας χρήστης που δηλώνει «5 όροφοι» δεν σβήνει τη
 * δήλωση άλλου χρήστη για «4 όροφοι» — η διαφωνία μένει **ορατή** και ζει στο δικό
 * του επίπεδο Β με σήμα «δηλωμένο, μη επαληθευμένο» (§14.3).
 */
export function outranksForFact(
  candidate: PlaceFactSource,
  current: PlaceFactSource | null
): boolean {
  if (current === null) return true;
  return placeFactRank(candidate) > placeFactRank(current);
}

/**
 * Ένα γεγονός του επιπέδου Α που κουβαλά **την προέλευσή του**.
 *
 * §14.3: *«Το επίπεδο Α δεν δέχεται γνώμες, δέχεται πηγές, και κάθε πεδίο κουβαλά
 * προέλευση.»* Ο τύπος το κάνει **αδύνατο να παραλειφθεί** — δεν υπάρχει τρόπος να
 * γραφτεί τιμή στο κοινό επίπεδο χωρίς να ειπωθεί από πού ήρθε.
 */
export interface Attested<T> {
  readonly value: T;
  readonly source: PlaceFactSource;
  /** ISO timestamp — πότε το επιβεβαίωσε αυτή η πηγή. */
  readonly attestedAt: string;
}

/**
 * Ξέρουμε πού είναι αυτό το πράγμα;
 *
 * Ρητή ερώτηση αντί για `step > 0`, **ακριβώς επειδή** το σκαλοπάτι 5 απαντά «ναι»
 * στο «έδωσε κάτι;» και «όχι» στο «ξέρουμε πού είναι;». Ένας καταναλωτής που θέλει
 * να ζωγραφίσει πινέζα πρέπει να ρωτήσει **αυτό**.
 */
export function hasKnownPosition(provenance: LocationProvenance | null): boolean {
  return provenance !== null;
}
