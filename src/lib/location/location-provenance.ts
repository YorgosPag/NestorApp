/**
 * @fileoverview SSoT — από πού ξέρουμε τη ΘΕΣΗ ενός πράγματος, και ποια πηγή νικά.
 * @related ADR-777 · SPEC-777A §13.3 (προελεύσεις) · §14.3 (ιεραρχία πηγών) · §21.4 (η σκάλα)
 * @module lib/location/location-provenance
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΔΥΟ ΕΡΩΤΗΜΑΤΑ ΠΟΥ ΜΟΙΑΖΟΥΝ ΕΝΑ — ΚΑΙ Η ΣΥΓΧΥΣΗ ΤΟΥΣ ΕΙΝΑΙ ΤΟ ΣΦΑΛΜΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το SPEC-777A γράφει δύο λίστες που *φαίνονται* η ίδια:
 *
 *   §13.3 → `bim` | `osm` | `drawn`            («από ποια πηγή ήρθε το σχήμα;»)
 *   §21.4 → μια σκάλα 0–6 με σκαλοπάτια        («τι μας έδωσε ο χρήστης;»)
 *
 * **Δεν είναι η ίδια, και η μέτρηση το αποδεικνύει στο σκαλοπάτι 5.** Το §21.4
 * γράφει για το σκαλοπάτι 5 (τοπογραφικό σε PDF/εικόνα), κατά λέξη:
 *
 *     «**έγγραφο ναι, θέση όχι**»
 *
 * Άρα το σκαλοπάτι **5 δίνει ΜΗΔΕΝ θέση**, ενώ το σκαλοπάτι **4 (OSM) δίνει σχήμα**.
 * Αν ο αριθμός του πίνακα διαβαστεί ως *αξιοπιστία θέσης*, τότε το `document-only`
 * **ξεπερνά** το `osm` — και ο κανόνας συγχώνευσης του §14.3 («ανεβαίνει στο Α μόνο
 * αν επαληθευτεί από **ισχυρότερη** πηγή») θα άφηνε ένα **ανύπαρκτο** στοιχείο θέσης
 * να σβήσει ένα **υπαρκτό**. Σιωπηλά, και για **όλους** τους χρήστες ταυτόχρονα (§14.4).
 *
 * Γι' αυτό εδώ μοντελοποιούνται **ξεχωριστά**:
 *
 * | Ερώτημα | Τύπος | Χρήση |
 * |---|---|---|
 * | «Από πού ήρθε η **θέση**;» | {@link LocationProvenance} + {@link locationProvenanceRank} | ο **κανόνας συγχώνευσης** του §14.3 |
 * | «Πόσο ψηλά στη **σκάλα** έφτασε ο χρήστης;» | {@link LocationKnowledgeStep} | **μόνο** η οθόνη του §21.4 |
 *
 * ⚠️ **Η σκάλα ΔΕΝ είναι σειρά αξιοπιστίας και δεν επιτρέπεται να χρησιμοποιηθεί ως
 * τέτοια.** Είναι «τι μας έδωσε ο άνθρωπος», και το σκαλοπάτι 5 είναι πολύτιμο για
 * λόγο **άσχετο με τον χάρτη** (§21.5: ο φάκελος που θα του ζητήσουν ούτως ή άλλως
 * δικηγόρος, συμβολαιογράφος, μηχανικός).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΤΕΤΑΡΤΟ ΛΕΞΙΛΟΓΙΟ ΠΡΟΕΛΕΥΣΗΣ
 * ────────────────────────────────────────────────────────────────────────────
 * Το έργο έχει ήδη **τρία**, και το καθένα απαντά **άλλο** ερώτημα:
 *   - `FieldProvenance` (`types/project-building-code.ts`) — από πού ήρθε ένας **όρος δόμησης**
 *   - `SurveyFieldProvenance` (`types/project-survey-record.ts`) — ποιος έγραψε ένα **πεδίο καρτέλας**
 *   - `ProvenanceActivity` (`types/vqe/envelope.ts`) — ποιος **υπολογισμός** παρήγαγε έναν αριθμό
 * Κανένα δεν απαντά «από πού ήρθε η **θέση**». Η επέκταση οποιουδήποτε από αυτά θα
 * έδινε σε μια συλλογή δύο νοήματα — το σχήμα του ADR-749.
 */

