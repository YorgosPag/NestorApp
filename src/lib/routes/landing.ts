/**
 * =============================================================================
 * Η ΠΡΟΣΓΕΙΩΣΗ — ποια είναι η αρχική **ΑΥΤΟΥ** του ανθρώπου (ADR-660)
 * =============================================================================
 *
 * **Το ερώτημα**: μετά τη σύνδεση, πού προσγειώνεται ο άνθρωπος;
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΣΥΝΑΡΤΗΣΗ ΚΑΙ ΟΧΙ ΣΤΑΘΕΡΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `AUTH_ROUTES.home` τεκμηριώνεται ως *«η αρχική του **ΣΥΝΔΕΔΕΜΕΝΟΥ**»* και είναι
 * **μία σταθερά**. Αυτό ήταν σωστό όσο υπήρχε **ένα** είδος συνδεδεμένου. Από τη
 * στιγμή που ο Νέστωρ έχει **δύο** — τον επαγγελματία (χώρος εργασίας `(app)`) και
 * τον πολίτη (ιδιωτικός χώρος `(me)`) — μια σταθερά είναι **δομικά ανίκανη** να
 * απαντήσει.
 *
 * 🔑 Είναι ο **καθρέφτης** του ADR-749: εκεί δύο απαντήσεις σε ένα ερώτημα· εδώ
 * **μία** απάντηση σε ερώτημα που έχει **δύο**. Και η συνέπεια ήταν μετρημένη — ο
 * πολίτης προσγειωνόταν στο `/dashboard`, το `dashboard/page.tsx` έβλεπε ότι δεν
 * έχει `companyId`, και τον πετούσε στην οθόνη *«εκκρεμεί έγκριση»*: **η πρώτη
 * οθόνη του ανθρώπου μετά την εγγραφή ήταν ένας τοίχος**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΤΙ **ΔΕΝ** ΚΑΝΕΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ — ΚΑΙ ΕΙΝΑΙ ΤΟ ΣΗΜΑΝΤΙΚΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * **ΔΕΝ αποφασίζει ταυτότητα.** Δεν ρωτά «είναι μέλος;», δεν διαβάζει κανάλι, δεν
 * εμπιστεύεται είσοδο πελάτη. Παίρνει ταυτότητα **ήδη αποφασισμένη** από τον έναν
 * απαντητή (`lib/auth/workspace-membership.ts`, ADR-787 §5.1) — όπως έφτασε στα
 * claims — και τη **χαρτογραφεί σε διεύθυνση**. Είναι χαρτογράφηση, όχι κρίση.
 *
 * ⛔ Γι' αυτό **δεν** είναι αναγνώστης καναλιού του CHECK 3.58 και **δεν** μπαίνει
 * στο `.workspace-authority.json`: ένα «κανάλι» είναι ο τρόπος με τον οποίο ο
 * **πελάτης λέει στον διακομιστή** σε ποιον χώρο θέλει να ενεργήσει. Εδώ ο πελάτης
 * δεν λέει τίποτα σε κανέναν — διαβάζει το **δικό του** επαληθευμένο claim για να
 * διαλέξει σε ποια σελίδα να πάει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🎁 ΓΙΑΤΙ ΑΥΤΟ ΕΙΝΑΙ ΔΩΡΟ ΓΙΑ ΤΗ ΦΑΣΗ 3 ΤΟΥ ADR-787
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η Φάση 3 βάζει τον χώρο **στη διεύθυνση**. Όταν γίνει, η προσγείωση αλλάζει —
 * και θα αλλάξει **αυτή η μία συνάρτηση**, όχι N σημεία κλήσης σκορπισμένα σε
 * σελίδες. Πριν από αυτό το αρχείο υπήρχαν **δύο** σελίδες που αποφάσιζαν η καθεμία
 * μόνη της (`dashboard` · `pending-approval`), με **ωμή** συμβολοσειρά η μία.
 *
 * **Layering**: leaf — μόνο σταθερές διαδρομών και μία καθαρή συνάρτηση. Καμία
 * εισαγωγή από `auth/`, ώστε να δοκιμάζεται χωρίς περιβάλλον.
 *
 * @module lib/routes/landing
 * @enterprise ADR-660 — Ο πολίτης δεν περιμένει έγκριση για να υπάρχει
 * @see ADR-787 Ε-3 (ο ιδιωτικός χώρος υπάρχει από την πρώτη στιγμή, για όλους)
 * @see ADR-777 Α14 (`(me)` — ο ιδιωτικός χώρος του ιδιώτη)
 */

import { MY_OFFERS_ROUTE } from '@/lib/owner-property/owner-property-routes';

import { ACCOUNT_ROUTES, PRIVATE_PROFILE_ROUTE } from './accountRoutes';
import { AUTH_ROUTES } from './authRoutes';

/**
 * **Η αρχική του ΙΔΙΩΤΙΚΟΥ χώρου.**
 *
 * 🔑 **Ονομασία, ΟΧΙ διπλότυπο**: η διεύθυνση παραμένει ιδιοκτησία του
 * `lib/owner-property/owner-property-routes.ts`. Εδώ αποκτά **ρόλο** — «πού
 * προσγειώνεται ο πολίτης» — και ο ρόλος είναι άλλο πράγμα από τη διεύθυνση.
 * Ωμό `'/offers'` εδώ θα ήταν δεύτερη αυθεντία (ADR-749).
 *
 * ⚠️ **Γιατί ο κατάλογος και όχι μια νέα αρχική του `(me)`**: ο
 * `MyOwnerPropertiesContent` **έχει ήδη** άδεια κατάσταση με κάλεσμα προς
 * `NEW_OFFER_ROUTE`, δηλαδή ο άνθρωπος χωρίς ακίνητα προσγειώνεται σε *χρήσιμη
 * οθόνη με πράξη* — ακριβώς αυτό που η βιβλιογραφία του onboarding αντιπαραθέτει
 * στο *dead-end confirmation*. Μια νέα σελίδα-ευρετήριο θα ήταν **νέα επιφάνεια
 * προϊόντος** χωρίς μετρημένο κέρδος.
 *
 * 🔶 Αν αύριο αποκτήσει το `(me)` δικό του ευρετήριο, αλλάζει **αυτή η γραμμή**.
 */
export const PRIVATE_SPACE_HOME = MY_OFFERS_ROUTE;

/**
 * Το ελάχιστο σχήμα ταυτότητας που χρειάζεται η προσγείωση.
 *
 * ⚠️ **`string | null | undefined` και τα τρία**: ο πελάτης εκπροσωπεί την απουσία
 * με `undefined` (`AuthUser.companyId?: string`) ενώ το προφίλ με `null`
 * (`UserProfile.companyId: string | null`). Ένας τύπος που δέχεται μόνο το ένα θα
 * ανάγκαζε **κάθε** καλούντα σε δική του κανονικοποίηση — δηλαδή θα γεννούσε ξανά
 * ακριβώς τη σκορπισμένη απόφαση που αυτό το αρχείο μαζεύει.
 */
export interface LandingIdentity {
  /** Το claim του οργανισμού. Απόν ⇒ ο άνθρωπος ενεργεί στον **δικό του** χώρο. */
  readonly companyId?: string | null;
}

/**
 * **Πού προσγειώνεται αυτός ο άνθρωπος μετά τη σύνδεση.**
 *
 * @param identity Ταυτότητα **ήδη αποφασισμένη** (claims). Δεν επαληθεύεται εδώ.
 * @returns Η διεύθυνση προσγείωσης — ποτέ κενή.
 *
 * @example
 * router.replace(resolvePostLoginRoute(user));
 */
export function resolvePostLoginRoute(identity: LandingIdentity) {
  return hasOrganization(identity) ? AUTH_ROUTES.home : PRIVATE_SPACE_HOME;
}

/**
 * **ΠΟΙΑ ΟΘΟΝΗ ΛΟΓΑΡΙΑΣΜΟΥ ΕΙΝΑΙ Η ΔΙΚΗ ΤΟΥ.**
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΕΛΑΤΤΩΜΑ ΠΟΥ ΤΟΝ ΓΕΝΝΗΣΕ — ΜΕΤΡΗΜΕΝΟ 2026-08-30
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `UserMenu` έστελνε **πάντα** στο `ACCOUNT_ROUTES.root` (`/account`), και
 * αποδίδεται **και στους πέντε κόσμους** μέσα από το `ShellUtilities`
 * (ADR-809 · CHECK 3.72). Για τον **ιδιώτη** το ψευδώνυμο είναι `null`, άρα ο
 * `workspaceHref` αφήνει τη διεύθυνση **άθικτη** ⇒ `/account` — και σελίδα εκεί
 * **δεν υπάρχει**: ο κατάλογος `account/` ζει **αποκλειστικά** κάτω από
 * `app/(app)/o/[workspace]/`. Δηλαδή το κουμπί «Λογαριασμός» οδηγούσε κάθε ιδιώτη
 * σε **404**.
 *
 * ⚠️ **Ταυτόσημο σχήμα με τρία καταγεγραμμένα περιστατικά** — `/unauthorized`
 * (ADR-787 §5.3 ξ) · `/workspace/new` (άγκυρα Κ1) · `/home` (ADR-819 §8): σύνδεσμος
 * που δείχνει σε διεύθυνση χωρίς σελίδα, επειδή **κανείς δεν ρώτησε** ποιος τον πατά.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΚΑΜΙΑ ΝΕΑ ΚΡΙΣΗ — Ο ΙΔΙΟΣ `hasOrganization`
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ζει **δίπλα** στο {@link resolvePostLoginRoute} και ρωτά **το ίδιο** πράγμα ένα βήμα
 * παρακάτω: *«ενεργεί σε οργανισμό;»*. ⛔ **ΜΗΝ γράψεις έλεγχο `companyId` στο μενού**
 * — θα ήταν **δεύτερη κρίση που μπορεί να αποκλίνει** (ADR-749), και θα απέκλινε
 * ακριβώς στην κενή συμβολοσειρά, τη μόνη περίπτωση όπου η απάντηση δεν είναι προφανής.
 * ⛔ Και **ΜΗΝ** τη λύσεις με φρουρό/λίστα `pathname` μέσα στο component: θα ήταν
 * ακριβώς ο `ConditionalAppShell` που **διέγραψε** το ADR-777 §8.12 — σωστός σήμερα,
 * ξεχασμένος στην επόμενη οθόνη, **αόρατος** σε κάθε πύλη.
 *
 * @param identity Ταυτότητα **ήδη αποφασισμένη** (claims). Δεν επαληθεύεται εδώ.
 * @returns Ο κόμβος λογαριασμού του γραφείου *(προθεματοποιείται από το σύνορο)*, ή η
 *          σελίδα προφίλ του ιδιώτη *(εκτός προθέματος)* — **ποτέ κενή**.
 */
export function resolveAccountRoute(identity: LandingIdentity) {
  return hasOrganization(identity) ? ACCOUNT_ROUTES.root : PRIVATE_PROFILE_ROUTE;
}

/**
 * **Ανήκει αυτός ο άνθρωπος σε οργανισμό;**
 *
 * ⚠️ **Κενή συμβολοσειρά = απουσία.** Το `extractCustomClaims`
 * (`lib/auth/auth-context.ts`) απορρίπτει fail-closed το `companyId.length === 0`
 * ως *«δεν είναι ταυτότητα που μπορούμε να εξουσιοδοτήσουμε»*. Ένας έλεγχος
 * `!= null` εδώ θα έστελνε στον χώρο εργασίας κάποιον που ο **διακομιστής**
 * θεωρεί χωρίς οργανισμό — δηλαδή σε σελίδα όπου κάθε κλήση δεδομένων 401άρει.
 * Η προσγείωση οφείλει να συμφωνεί με τον server, όχι απλώς να είναι αληθής.
 *
 * 🔑 **Εξήχθη 2026-08-23 (ADR-787 §5.3 θ) — ονομασία, όχι διεύρυνση.** Το σύνορο
 * πλοήγησης ρωτά *«σε ποιον χώρο ενεργεί αυτός ο άνθρωπος;»*, που είναι **η ίδια
 * ερώτηση ένα βήμα παρακάτω**: οργανισμός ⇒ ο χώρος του, αλλιώς ο **ιδιωτικός**.
 * Ένας δεύτερος έλεγχος `companyId` στο σύνορο θα ήταν **δεύτερη κρίση που μπορεί
 * να αποκλίνει** (ADR-749) — και θα απέκλινε ακριβώς στην κενή συμβολοσειρά, που
 * είναι η μόνη περίπτωση όπου η απάντηση δεν είναι προφανής.
 */
export function hasOrganization(identity: LandingIdentity): boolean {
  return typeof identity.companyId === 'string' && identity.companyId.length > 0;
}
