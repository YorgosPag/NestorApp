/**
 * Ο **γενικός πυρήνας πινακοειδούς εισαγωγής** (ADR-923 §5.5 · ADR-650 M2) — οι τύποι.
 *
 * Το μοτίβο του Civil 3D «Format Manager», γενικευμένο: ένα αρχείο είναι **πίνακας άτυπων κελιών**, μια
 * **αντιστοίχιση** δηλώνει ποια στήλη παίζει ποιον ρόλο, και μόνο ο καταναλωτής ξέρει τι σημαίνει ο ρόλος.
 *
 *   αρχείο (CSV/TXT/Excel) → RawTable → [ColumnMapping<ρόλος>] → ό,τι χτίζει ο καταναλωτής
 *
 * Δύο καταναλωτές, ένας πυρήνας: η τοπογραφία (`x` · `y` · `z` · …) και ο κατάλογος (ιδιότητα · τιμή · κωδικός).
 * Χωρίς λογική (τύποι μόνο).
 * @module lib/tabular-import/tabular-types
 */

/**
 * Ένα αρχείο διαβασμένο, ακόμη άτυπο. Το παράγουν ο `delimited-reader` και ο `excel-reader` με το ίδιο σχήμα, ώστε
 * ο αντιστοιχιστής να μη μαθαίνει ποτέ από ποια μορφή ήρθαν τα κελιά.
 */
export interface RawTable {
  /** Οι ετικέτες στηλών όταν το αρχείο έχει γραμμή επικεφαλίδας· κενό όταν δεν έχει. */
  readonly headers: readonly string[];
  /** Οι γραμμές δεδομένων (χωρίς την επικεφαλίδα). Ανόμοιο μήκος επιτρέπεται — το κρίνει ο αντιστοιχιστής. */
  readonly rows: readonly (readonly string[])[];
  /** Ο διαχωριστής που εντοπίστηκε (πληροφοριακό). */
  readonly delimiter?: string;
}

/**
 * Δείκτης στήλης → ρόλος, για ρόλο που διαλέγει ο καταναλωτής. Ο δείκτης είναι θέση με βάση το 0 στο `rows[i]`.
 */
export type TabularMapping<TRole> = readonly TRole[];

/** Λέξεις-κλειδιά επικεφαλίδας ανά ρόλο, με σειρά προτεραιότητας. */
export type HeaderHints<TRole> = ReadonlyArray<readonly [TRole, readonly string[]]>;
