/**
 * 🔴 ADR-828 Φ4β — άγκυρες του **ταιριάσματος σε λίστες ονομάτων**.
 *
 * Κάθε ισχυρισμός εδώ, αν σπάσει, βγάζει **λάθος λέξη σε κελί χρήστη** — όχι εξαίρεση, όχι
 * κόκκινο στην οθόνη. Η προτεραιότητα ειδικά είναι αόρατη σε κάθε πρόχειρο έλεγχο: φαίνεται
 * μόνο όταν μια λέξη ανήκει σε **δύο** λίστες, που είναι ακριβώς η περίπτωση που ο άνθρωπος
 * έγραψε τη δική του εκδοχή των μηνών.
 */

import { matchNameList, type NameListCandidate } from '../name-list-match';

const FLOORS: NameListCandidate = {
  key: 'user:όροφοι',
  entries: ['Ισόγειο', 'Α΄ όροφος', 'Β΄ όροφος', 'Γ΄ όροφος'],
};

const PHASES: NameListCandidate = {
  key: 'user:φάσεις',
  entries: ['Εκσκαφή', 'Θεμελίωση', 'Φέρων οργανισμός'],
};

describe('πού είναι η λέξη', () => {
  it('βρίσκει τη θέση μέσα στη λίστα', () => {
    expect(matchNameList('Β΄ όροφος', [FLOORS])).toMatchObject({
      key: 'user:όροφοι',
      index: 2,
    });
  });

  it('η πρώτη λίστα που ταιριάζει κερδίζει — και μαζί της τα ονόματά της', () => {
    const match = matchNameList('Εκσκαφή', [FLOORS, PHASES]);
    expect(match!.key).toBe('user:φάσεις');
    expect(match!.entries).toBe(PHASES.entries);
  });

  it('ό,τι δεν ανήκει πουθενά δίνει null — δηλαδή τα περισσότερα κελιά', () => {
    expect(matchNameList('12,50', [FLOORS, PHASES])).toBeNull();
    expect(matchNameList('Σκυρόδεμα', [FLOORS])).toBeNull();
  });

  it('χωρίς υποψήφιες δεν ταιριάζει τίποτα, χωρίς να πετάξει', () => {
    expect(matchNameList('Ισόγειο', [])).toBeNull();
  });
});

describe('πώς συγκρίνονται οι λέξεις', () => {
  /**
   * Ο **ίδιος** κανόνας κανονικοποίησης με το λεξιλόγιο ημερολογίου: αλλιώς το «ΙΣΟΓΕΙΟ»
   * που γράφει ο άνθρωπος σε κεφαλαία δεν θα έβρισκε το «Ισόγειο» που δήλωσε ο ίδιος.
   */
  it('🔑 αγνοεί κεφαλαία/πεζά και τόνους — ο άνθρωπος γράφει όπως γράφει', () => {
    expect(matchNameList('ΙΣΟΓΕΙΟ', [FLOORS])).toMatchObject({ index: 0 });
    expect(matchNameList('ισόγειο', [FLOORS])).toMatchObject({ index: 0 });
  });

  it('τα κενά στις άκρες δεν κάνουν τη λέξη ξένη', () => {
    expect(matchNameList('  Θεμελίωση  ', [PHASES])).toMatchObject({ index: 1 });
  });

  it('η κενή λέξη δεν ταιριάζει — ένα κενό κελί δεν είναι μέλος καμίας λίστας', () => {
    expect(matchNameList('', [FLOORS])).toBeNull();
    expect(matchNameList('   ', [FLOORS])).toBeNull();
  });
});

describe('διπλή εγγραφή μέσα στην ίδια λίστα', () => {
  /**
   * Μια λίστα «Α, Β, Α» είναι **νόμιμη** — απλώς δεν έχει μονοσήμαντη «θέση» για το Α. Η
   * επιλογή της πρώτης εμφάνισης δεν είναι σωστότερη από τη δεύτερη· είναι **ντετερμινιστική**,
   * που είναι το μόνο που μπορεί να υποσχεθεί κανείς εδώ. Καρφώνεται ώστε η συνέχεια ενός
   * τέτοιου γεμίσματος να μην αλλάξει σιωπηλά αν κάποτε αλλάξει η υλοποίηση της αναζήτησης.
   */
  it('κερδίζει η πρώτη εμφάνιση, σταθερά', () => {
    const repeated: NameListCandidate = { key: 'user:επαναλαμβανόμενη', entries: ['Α', 'Β', 'Α'] };
    expect(matchNameList('Α', [repeated])).toMatchObject({ index: 0 });
  });
});
