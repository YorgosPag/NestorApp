/**
 * 🔴 ADR-828 Φ4β — **«ΠΟΥ ΜΕΣΑ ΣΕ ΑΥΤΕΣ ΤΙΣ ΛΙΣΤΕΣ ΕΙΝΑΙ ΑΥΤΗ Η ΛΕΞΗ;»** — μία ερώτηση,
 * καμία γνώση για το τι σημαίνουν οι λίστες.
 *
 * ## Γιατί δεν ζει μέσα στο λεξιλόγιο ημερολογίου
 * Το {@link module:lib/date/calendar-name-vocabulary} είναι ρητά **κλειστό, δεδομένα-μόνο και
 * ντετερμινιστικό** (ADR-828 §3) — γι' αυτό μπορεί να το εισάγει και ο αναγνώστης πινακίδων
 * του {@link module:lib/survey-record/survey-date}. Οι λίστες που γράφει ο άνθρωπος στις
 * ρυθμίσεις του είναι **δεδομένα χρόνου εκτέλεσης**: μια ένεσή τους εκεί θα ακύρωνε **και τις
 * τρεις** ιδιότητες, και μαζί τον λόγο που το λεξιλόγιο εξήχθη έξω από το subapp.
 *
 * Άρα η ερώτηση χωρίζεται στα δύο, όπως χωρίζεται φυσικά: **τα ονόματα** τα δίνει ο καλών,
 * **το ταίριασμα** το κάνει αυτό το module — και δεν ξέρει αν κοιτά μήνες, ορόφους ή φάσεις έργου.
 *
 * ## Γιατί γραμμικό και όχι προϋπολογισμένος πίνακας
 * Ο πίνακας του λεξιλογίου χτίζεται **μία φορά στη φόρτωση** επειδή τα δεδομένα του είναι
 * σταθερά. Οι λίστες του χρήστη **αλλάζουν όσο τρέχει η εφαρμογή**, οπότε ένας πίνακας θα
 * χρειαζόταν ακύρωση — δηλαδή δεύτερη κατάσταση που μπορεί να πάει πίσω από την αλήθεια.
 * Το μέγεθος το επιτρέπει με άνεση: το ανώτατο είναι **20 λίστες × 200 εγγραφές** (δες
 * `AUTO_FILL_LIST_LIMITS`), και η ερώτηση γίνεται **μία φορά ανά λωρίδα γεμίσματος**, όχι ανά κελί.
 *
 * @module lib/string/name-list-match
 * @see lib/date/calendar-name-vocabulary.ts — ο **άλλος** καλών, με σταθερά δεδομένα και δικό του πίνακα
 * @see docs/centralized-systems/reference/adrs/ADR-828-table-autofill-series.md §4
 */

import { normalizeForLabelMatch } from '@/utils/greek-text';

/**
 * Μια λίστα ονομάτων έτοιμη να ερωτηθεί.
 *
 * 🔑 Το `key` είναι **ταυτότητα σύγκρισης**, όχι ετικέτα προς εμφάνιση: δύο σπόροι ανήκουν
 * στην ίδια σειρά μόνο αν βγήκαν από την **ίδια** λίστα, και η σύγκριση συμβολοσειρών είναι
 * ο ένας τρόπος να το ρωτήσεις χωρίς να κρατάς αναφορές αντικειμένων ζωντανές.
 *
 * ⚠️ **Μη-κενή πλειάδα** στο `entries`: η αναδίπλωση κατεβαίνει σε `positiveMod`, όπου το
 * μηδενικό μήκος δεν έχει απάντηση που να μην εφευρίσκει.
 */
export interface NameListCandidate {
  readonly key: string;
  readonly entries: readonly [string, ...string[]];
}

/** Πού βρέθηκε μια λέξη: σε ποια λίστα και σε ποια **θέση** μέσα της. */
export interface NameListMatch {
  readonly key: string;
  readonly entries: readonly [string, ...string[]];
  /** **0-based** θέση μέσα στο {@link NameListCandidate.entries}. */
  readonly index: number;
}

/**
 * Η **πρώτη** λίστα που περιέχει τη λέξη, και πού μέσα της.
 *
 * 🔑 **Η σειρά των υποψηφίων ΕΙΝΑΙ η προτεραιότητα** — δεν υπάρχει δεύτερος κανόνας
 * διαιτησίας, επίτηδες. Όταν το «Ιανουάριος» ανήκει και σε ενσωματωμένη λίστα και σε λίστα
 * που έγραψε ο άνθρωπος, κερδίζει όποια ρωτήθηκε πρώτη — και ο καλών ρωτά **πρώτα του
 * ανθρώπου**, γιατί εκείνος τη δήλωσε ρητά ενώ η ενσωματωμένη είναι προεπιλογή. Ένας
 * ξεχωριστός κανόνας «ποιος κερδίζει» θα ήταν δεύτερη αλήθεια δίπλα στη σειρά της λίστας.
 *
 * ⚠️ Η **πρώτη** εμφάνιση μέσα στην ίδια λίστα κερδίζει: μια λίστα με διπλή εγγραφή
 * («Α, Β, Α») δεν έχει μονοσήμαντη «θέση» για το Α, και η δεύτερη επιλογή θα ήταν εξίσου
 * αυθαίρετη. Δεν απαγορεύεται στην επικύρωση επειδή είναι νόμιμη λίστα — απλώς η συνέχειά
 * της ορίζεται από το πρώτο σημείο που ταίριαξε.
 *
 * Επιστρέφει `null` για ό,τι δεν ανήκει πουθενά — δηλαδή για τα περισσότερα κελιά ενός πίνακα.
 */
/**
 * ⚠️ Το `trim()` είναι **ρητό** και δεν βασίζεται στο ότι κάποιος αλλού καθάρισε ήδη: οι
 * εγγραφές έρχονται από πληκτρολόγιο ανθρώπου, και ένα κενό στην άκρη είναι το είδος
 * διαφοράς που ο άνθρωπος **δεν μπορεί να δει** — θα έβλεπε μόνο ότι «η λίστα δεν δουλεύει».
 * Το `normalizeForLabelMatch` διώχνει τόνους, κεφαλαία και στίξη, όχι όμως το περιθώριο.
 */
function normalizeKey(text: string): string {
  return normalizeForLabelMatch(text.trim());
}

export function matchNameList(
  word: string,
  candidates: readonly NameListCandidate[],
): NameListMatch | null {
  const needle = normalizeKey(word);
  if (needle === '') return null;

  for (const candidate of candidates) {
    const index = candidate.entries.findIndex((entry) => normalizeKey(entry) === needle);
    if (index !== -1) return { key: candidate.key, entries: candidate.entries, index };
  }
  return null;
}
