/**
 * `addMonthsUTC` — άγκυρα της ΜΙΑΣ υλοποίησης ψαλιδίσματος (ADR-915 Φ1 · N.0.2).
 *
 * Το `addMonthsUTC` αναθέτει πλέον στο `addMonthsClampedUtc` (`lib/date/calendar-arithmetic`) και
 * ξαναβάζει την ώρα της αφετηρίας. Οι περιπτώσεις εδώ κλειδώνουν ότι η ανάθεση **δεν** άλλαξε
 * τίποτα από όσα έβλεπαν οι καλούντες: ψαλίδισμα στο τέλος του μήνα, δίσεκτα, αρνητικοί μήνες,
 * ώρα της ημέρας, άκυρη είσοδος.
 */

import { addMonthsUTC } from '../date-local';

describe('addMonthsUTC', () => {
  it('31 Ιανουαρίου + 1 μήνας = 28 Φεβρουαρίου, ΠΟΤΕ 3 Μαρτίου', () => {
    expect(addMonthsUTC('2027-01-31T00:00:00.000Z', 1)).toBe('2027-02-28T00:00:00.000Z');
  });

  it('σε δίσεκτο έτος ψαλιδίζει στις 29', () => {
    expect(addMonthsUTC('2028-01-31T00:00:00.000Z', 1)).toBe('2028-02-29T00:00:00.000Z');
  });

  it('29 Φεβρουαρίου + 12 μήνες = 28 Φεβρουαρίου', () => {
    expect(addMonthsUTC('2028-02-29T00:00:00.000Z', 12)).toBe('2029-02-28T00:00:00.000Z');
  });

  it('αρνητικοί μήνες: 31 Μαρτίου − 1 = 28 Φεβρουαρίου · 31 Ιανουαρίου − 2 = 30 Νοεμβρίου προηγούμενου έτους', () => {
    expect(addMonthsUTC('2027-03-31T00:00:00.000Z', -1)).toBe('2027-02-28T00:00:00.000Z');
    expect(addMonthsUTC('2027-01-31T00:00:00.000Z', -2)).toBe('2026-11-30T00:00:00.000Z');
  });

  it('κρατά την ώρα της ημέρας της αφετηρίας', () => {
    expect(addMonthsUTC('2026-06-30T21:45:12.345Z', 8)).toBe('2027-02-28T21:45:12.345Z');
  });

  it('κρατά την ώρα και πριν από το 1970 (αρνητικά χιλιοστά)', () => {
    expect(addMonthsUTC('1969-12-31T23:00:00.000Z', 2)).toBe('1970-02-28T23:00:00.000Z');
  });

  it('μη ακέραιοι μήνες ή μη αναγνώσιμη αφετηρία ⇒ null', () => {
    expect(addMonthsUTC('2027-01-31T00:00:00.000Z', 1.5)).toBeNull();
    expect(addMonthsUTC('όχι ημερομηνία', 1)).toBeNull();
  });
});
