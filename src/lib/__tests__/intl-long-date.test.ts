/**
 * ΑΓΚΥΡΑ — **«διαβάζεται από άνθρωπο, ή είναι στιγμιότυπο μηχανής;»** *(ADR-827 §9.16 ε)*
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΓΕΓΟΝΟΣ ΠΟΥ ΤΗ ΓΕΝΝΗΣΕ — μετρημένο στην οθόνη, 2026-08-29
 * ─────────────────────────────────────────────────────────────────────────────
 * Δύο οθόνες βιτρίνας τύπωναν **ωμό ISO**: «Δημοσιεύτηκε `2026-08-29T14:00:48.842Z`».
 * **Καμία πύλη δεν το πιάνει** και δεν είναι παράλειψη καμιάς: η ετικέτα έρχεται από
 * `t()` *(άρα όχι hardcoded — N.11)*· δεν είναι γεωμετρία *(3.63)*· κανένα κλειδί δεν
 * λείπει *(3.8)*. **Το βρήκε μόνο το άνοιγμα της σελίδας** — ίδιο σχήμα με το §5.1.
 *
 * ⚠️ Και δεν είναι θέμα καλλωπισμού: το `Z` είναι **UTC**, άρα το κείμενο δήλωνε ώρα
 * **που δεν ήταν του αναγνώστη**.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΙ ΡΩΤΑΕΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ — και τι **επίτηδες δεν** ρωτάει
 * ─────────────────────────────────────────────────────────────────────────────
 * Ρωτάει τη **ΣΗΜΑΣΙΑ**: *ο μήνας είναι **λέξη**; υπάρχει ημέρα; υπάρχει έτος; έφυγε
 * το στιγμιότυπο μηχανής;* — **ΟΧΙ** μια συγκεκριμένη συμβολοσειρά.
 *
 * ⛔ **ΜΗΝ το ξαναγράψεις με `toBe('29 Αυγούστου 2026')`.** Θα ήταν άγκυρα δεμένη στα
 * δεδομένα CLDR του Node, δηλαδή κόκκινη σε κάθε αναβάθμιση **χωρίς να έχει σπάσει
 * τίποτα** — και ο επόμενος θα τη «διόρθωνε» ξαναγράφοντας την προσδοκία, οπότε θα
 * έπαυε να φυλά. Ίδιος λόγος που η Β3 παράγει την προσδοκία της **από την ίδια
 * τη μηχανή** αντί να τη γράφει: η **ζώνη ώρας** του μηχανήματος δεν είναι δεδομένη.
 */

import { formatDate, formatLongDate } from '@/lib/intl-formatting';

/** Μεσημέρι UTC: όποια ζώνη κι αν τρέχει η μηχανή, δεν είναι οριακό. */
const INSTANT = '2026-08-29T14:00:48.842Z';

/** Ό,τι προδίδει στιγμιότυπο μηχανής αντί για ημερομηνία ανθρώπου. */
const MACHINE_MARKS = ['T14', 'Z', '.842', ':48'];

describe('Α — Ο ΠΑΡΟΝΟΜΑΣΤΗΣ: το όργανο ΒΛΕΠΕΙ μορφοποίηση', () => {
  // Χωρίς αυτό, ένα σπασμένο import θα έκανε τα Β/Γ πράσινα για λάθος λόγο:
  // «δεν βρήκα λατινικό γράμμα» και «δεν έτρεξα» δίνουν το ίδιο αποτέλεσμα.
  it('Α1: το formatDate παράγει κάτι ΔΙΑΦΟΡΕΤΙΚΟ από την είσοδο', () => {
    const compact = formatDate(INSTANT);
    expect(compact).not.toBe(INSTANT);
    expect(compact.length).toBeGreaterThan(0);
  });

  it('Α2: η συμπαγής μορφή είναι ΑΡΙΘΜΗΤΙΚΗ — αλλιώς το Β1 δεν διακρίνει τίποτα', () => {
    // Αν το `formatDate` άρχιζε να γράφει τον μήνα ολογράφως, το Β1 θα ήταν πράσινο
    // ό,τι κι αν έκανε το `formatLongDate` — δηλαδή θα έπαυε να είναι έλεγχος.
    expect(formatDate(INSTANT)).not.toMatch(/\p{L}{3,}/u);
  });
});

/**
 * 🔑 ΜΕΤΡΗΜΕΝΟ, ΚΑΙ ΜΕ ΠΙΑΣΕ ΤΟ Μ3 ΠΡΙΝ ΤΟ ΓΡΑΨΩ ΕΤΣΙ *(2026-08-29 στ)*
 *
 * Οι μεταλλάξεις *«αφαίρεσε το `year`»* και *«αφαίρεσε το `day`»* από το
 * `formatLongDate` βγήκαν **ΠΡΑΣΙΝΕΣ**. Η πρώτη ανάγνωση —*«τα Β2/Β3 δεν φυλούν
 * τίποτα»*— ήταν **λάθος**: το `formatDate` δίνει `year: 'numeric'` και `day: '2-digit'`
 * από **προεπιλογή**, άρα η υπόσχεση έχει **ΔΥΟ ΑΝΕΞΑΡΤΗΤΑ ΕΠΙΠΕΔΑ** και η μονή
 * μετάλλαξη την **απορροφά** — belt-and-suspenders (N.7.2 #4), όχι πλεονασμός.
 *
 * ✅ **Η διπλή μετάλλαξη** *(αφαίρεση από **αμφότερα** τα επίπεδα)* βγήκε **2/2
 * ΚΟΚΚΙΝΗ**. ⇒ Τα Β2/Β3 φυλούν τη **σύνθετη** υπόσχεση, όχι το literal του ενός.
 *
 * ⛔ **ΜΗΝ «απλοποιήσεις» το `formatLongDate` σε `formatDate(date, { month: 'long' })`**
 * επειδή «τα άλλα δύο είναι προεπιλογή». Ρητά, η δημόσια επιφάνεια γίνεται **απρόσβλητη**
 * σε αλλαγή των προεπιλογών του `formatDate` *(τα δικά της options **νικούν** στο spread)*.
 * Σιωπηρά, θα κληρονομούσε μια απόφαση που πάρθηκε για **άλλες** οθόνες.
 */
describe('Β — Η ΑΠΟΦΑΣΗ: δημόσια επιφάνεια ⇒ ο μήνας είναι ΛΕΞΗ', () => {
  it('Β1: ο μήνας γράφεται ολογράφως', () => {
    // 🔴 ΜΕΤΑΛΛΑΞΗ ΠΟΥ ΠΡΕΠΕΙ ΝΑ ΚΟΚΚΙΝΙΣΕΙ: month: 'long' → '2-digit'.
    expect(formatLongDate(INSTANT)).toMatch(/\p{L}{3,}/u);
  });

  it('Β2: το έτος υπάρχει', () => {
    // 🔴 ΜΕΤΑΛΛΑΞΗ: αφαίρεσε το `year` από τις επιλογές.
    expect(formatLongDate(INSTANT)).toContain('2026');
  });

  it('Β3: η ημέρα υπάρχει — και η προσδοκία παράγεται στη ΖΩΝΗ ΤΗΣ ΜΗΧΑΝΗΣ', () => {
    // 🔴 ΜΕΤΑΛΛΑΞΗ: αφαίρεσε το `day`.
    // ⚠️ Η ημέρα ΔΕΝ γράφεται «29»: σε ζώνη UTC+14 το ίδιο instant είναι η 30ή. Τη
    //    ρωτάμε από την ίδια μηχανή που θα τη μορφοποιήσει, ώστε ο έλεγχος να κρίνει
    //    «μπήκε η ημέρα;» και όχι «πού τρέχει το CI;».
    const expectedDay = new Intl.DateTimeFormat('el', { day: 'numeric' }).format(
      new Date(INSTANT),
    );
    expect(formatLongDate(INSTANT)).toContain(expectedDay);
  });
});

describe('Γ — Η ΒΛΑΒΗ: κανένα ίχνος στιγμιότυπου μηχανής', () => {
  it.each(MACHINE_MARKS)('Γ1: δεν περιέχει %s', (mark) => {
    // 🔴 ΜΕΤΑΛΛΑΞΗ: επίστρεψε την είσοδο ως έχει — ακριβώς η βλάβη που μετρήθηκε.
    expect(formatLongDate(INSTANT)).not.toContain(mark);
  });

  it('Γ2: δέχεται και Date και αριθμό, με το ΙΔΙΟ αποτέλεσμα', () => {
    // Οι τρεις είσοδοι είναι το ίδιο instant· τρεις απαντήσεις θα σήμαιναν ότι η
    // μορφοποίηση εξαρτάται από το ΠΩΣ ήρθε η τιμή, όχι από το ΠΟΤΕ είναι.
    const asDate = new Date(INSTANT);
    expect(formatLongDate(asDate)).toBe(formatLongDate(INSTANT));
    expect(formatLongDate(asDate.getTime())).toBe(formatLongDate(INSTANT));
  });
});
