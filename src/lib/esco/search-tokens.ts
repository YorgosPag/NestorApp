/**
 * ADR-132 / ADR-798 — Ο **ΤΟΚΕΝΙΣΤΗΣ ΤΟΥ ESCO**, μία φορά, και για **τα δύο άκρα**.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ — ΠΕΝΤΕ ΑΝΤΙΓΡΑΦΑ, ΜΕΤΡΗΜΕΝΑ (2026-08-26)
 *
 * Η αναζήτηση ESCO είναι ένα **ευρετήριο προθεμάτων** πάνω σε Firestore
 * `array-contains`: ο **εισαγωγέας** γράφει τα `searchTokensEl/En` και η
 * **υπηρεσία** ρωτά με τα tokens του ερωτήματος. Το `array-contains` απαιτεί
 * **ακριβή** ισότητα στοιχείου. Άρα:
 *
 *   🔑 **αν οι δύο πλευρές κανονικοποιήσουν διαφορετικά, η αναζήτηση επιστρέφει**
 *   🔑 **ΜΗΔΕΝ ΑΠΟΤΕΛΕΣΜΑΤΑ — χωρίς σφάλμα, χωρίς log, χωρίς ένδειξη.**
 *
 * Ο ίδιος αλγόριθμος ζούσε σε **πέντε** τόπους, σε **δύο** άκρα του ίδιου
 * ευρετηρίου:
 *
 * | # | Τόπος | Πλευρά |
 * |---|---|---|
 * | 1 | `scripts/import-esco-occupations.ts` `generateSearchTokens` | **γραφή** |
 * | 2 | `scripts/import-esco-skills.ts` `generateSearchTokens` | **γραφή** *(δίδυμο του 1)* |
 * | 3 | `services/esco.service.ts` `normalizeForSearch` + `queryToTokens` | ανάγνωση |
 * | 4 | `services/esco-skill.service.ts` — **ταυτόσημο** με το 3 | ανάγνωση |
 * | 5 | `services/ai-pipeline/tools/esco-search-utils.ts` `normalizeEsco` | ανάγνωση *(server)* |
 *
 * Και τα **τρία** σχόλια που τα συνόδευαν έλεγαν *«Same algorithm as …»* — δηλαδή
 * **σχόλιο εκεί που έπρεπε να υπάρχει module**. Είναι το σχήμα του **ADR-749**
 * *(«δεύτερη αλήθεια»)*, εδώ με **πέντε** διαλέκτους αντί για τέσσερις, και με
 * την επιπλέον ιδιότητα ότι η απόκλιση **δεν κοκκινίζει τίποτα**: δίνει άδεια
 * λίστα, που μοιάζει με «δεν βρέθηκε επάγγελμα».
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 ΤΟ ΣΥΜΒΟΛΑΙΟ ΤΩΝ ΔΥΟ ΣΥΝΑΡΤΗΣΕΩΝ
 *
 * `escoIndexTokens` *(γραφή)* παράγει **κάθε πρόθεμα** κάθε λέξης από
 * `ESCO_MIN_TOKEN_LENGTH` χαρακτήρες και πάνω. `escoQueryTokens` *(ανάγνωση)*
 * παράγει **ολόκληρες λέξεις** του ερωτήματος. Η αναζήτηση δουλεύει **ακριβώς
 * επειδή** το σύνολο της δεύτερης είναι **υποσύνολο** αυτού που παράγει η πρώτη
 * για το ίδιο κείμενο — και αυτό είναι εφικτό μόνο αν η κανονικοποίηση
 * *(διακριτικά · πεζά · διαχωριστικά · ελάχιστο μήκος)* είναι **η ίδια
 * συνάρτηση**, όχι «ο ίδιος αλγόριθμος».
 *
 * ⛔ **ΜΗΝ** γράψεις τρίτη παραλλαγή. Αν χρειάζεσαι άλλη συμπεριφορά, άλλαξέ την
 * **εδώ** και τρέξε ξανά τον εισαγωγέα — αλλιώς το ευρετήριο και το ερώτημα
 * παύουν να μιλούν την ίδια γλώσσα.
 *
 * @module lib/esco/search-tokens
 * @see docs/centralized-systems/reference/adrs/ADR-132-esco-professional-classification.md
 */

import { stripAccents } from '@/utils/greek-text';

/**
 * Ελάχιστο μήκος token, **και** ελάχιστο μήκος ερωτήματος.
 *
 * Δύο χαρακτήρες: κάτω από αυτό το ευρετήριο θα εκρηγνυόταν *(κάθε πρώτο γράμμα
 * κάθε λέξης)* και το ερώτημα θα επέστρεφε σχεδόν τα πάντα.
 */
export const ESCO_MIN_TOKEN_LENGTH = 2;

/**
 * Τα διαχωριστικά λέξης. **Ίδια και στις δύο πλευρές** — μια τελεία που κόβει
 * λέξη στη γραφή αλλά όχι στην ανάγνωση αρκεί για να μη βρεθεί ποτέ ο όρος.
 */
const ESCO_WORD_SEPARATORS = /[\s,.\-/()]+/;

/**
 * Κανονικοποίηση κειμένου ESCO: **αφαίρεση τόνων → πεζά → κόψιμο άκρων**.
 *
 * ⚠️ Η **σειρά** διατηρήθηκε αυτούσια από τις πέντε προηγούμενες υλοποιήσεις.
 * Είναι κρίσιμη για τα ελληνικά: το ευρετήριο έχει ήδη γραφτεί με αυτήν, και
 * κάθε αλλαγή σειράς απαιτεί **επανεισαγωγή**, όχι απλώς νέα έκδοση κώδικα.
 */
export function normalizeEscoText(text: string): string {
  return stripAccents(text).toLowerCase().trim();
}

/**
 * **ΠΛΕΥΡΑ ΑΝΑΓΝΩΣΗΣ** — ολόκληρες λέξεις του ερωτήματος.
 *
 * Το αποτέλεσμα πηγαίνει σε `where('searchTokensEl', 'array-contains', token)`.
 */
export function escoQueryTokens(query: string): string[] {
  return normalizeEscoText(query)
    .split(ESCO_WORD_SEPARATORS)
    .filter((token) => token.length >= ESCO_MIN_TOKEN_LENGTH);
}

/**
 * **ΠΛΕΥΡΑ ΓΡΑΦΗΣ** — κάθε πρόθεμα κάθε λέξης, από `ESCO_MIN_TOKEN_LENGTH` και πάνω.
 *
 * Το `array-contains` του Firestore απαιτεί **ακριβή** ισότητα στοιχείου, άρα η
 * αυτόματη συμπλήρωση («φαρμ» → «φαρμακοποιός») είναι εφικτή **μόνο** αν τα
 * προθέματα έχουν αποθηκευτεί εκ των προτέρων. Παράδειγμα:
 * `"φαρμακοποιός"` → `["φα", "φαρ", "φαρμ", …, "φαρμακοποιος"]`.
 *
 * @param label - Η κύρια ετικέτα.
 * @param altLabels - Συνώνυμα· τα προθέματά τους μπαίνουν στο **ίδιο** σύνολο.
 */
export function escoIndexTokens(label: string, altLabels: readonly string[] = []): string[] {
  const words = normalizeEscoText([label, ...altLabels].join(' '))
    .split(ESCO_WORD_SEPARATORS)
    .filter((word) => word.length >= ESCO_MIN_TOKEN_LENGTH);

  const prefixes = new Set<string>();
  for (const word of words) {
    for (let length = ESCO_MIN_TOKEN_LENGTH; length <= word.length; length += 1) {
      prefixes.add(word.slice(0, length));
    }
  }

  return Array.from(prefixes);
}
