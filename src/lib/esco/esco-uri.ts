/**
 * Το **τελευταίο τμήμα** ενός ESCO URI — το αναγνωριστικό του εγγράφου στη μνήμη.
 *
 * `http://data.europa.eu/esco/occupation/8ec8df02-…` → `8ec8df02-…`
 *
 * ⚠️ **Δέχεται μόνο δεκαεξαδικά και παύλες**, όπως και η πρώτη γραφή: τα ESCO
 * occupation URI τελειώνουν σε UUID. Ένα χαλαρότερο `/([^/]+)$/` θα δεχόταν
 * *οτιδήποτε* μετά την τελευταία κάθετο — δηλαδή θα μετέτρεπε ένα λάθος URI σε
 * **αναζήτηση εγγράφου που δεν υπάρχει**, και το «δεν βρέθηκε» θα έκρυβε το
 * «δεν ήταν καν URI».
 *
 * @returns Το αναγνωριστικό, ή `null` όταν το κείμενο δεν είναι ESCO URI.
 */
export function escoDocIdOf(uri: string | null | undefined): string | null {
  if (typeof uri !== 'string') return null;
  const match = uri.trim().match(/\/([a-f0-9-]+)$/i);
  return match === null ? null : match[1];
}
