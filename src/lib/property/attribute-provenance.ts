/** Ό,τι κουβαλά **κάθε** χαρακτηριστικό, ανεξάρτητα από πηγή. */
interface AttributeFactBase {
  /**
   * ISO στιγμή — **πότε** το έμαθε αυτή η πηγή.
   *
   * ⚠️ **Περνιέται πάντα από τον καλούντα, ποτέ ρολόι διαβασμένο εδώ μέσα.** Ίδιος
   * κανόνας με το `isOwnerPropertyOnTheMarket(property, nowISOValue)` — μια καθαρή
   * συνάρτηση που κρυφά διαβάζει την ώρα δεν είναι καθαρή, και δεν ελέγχεται.
   */
  readonly at: string;
}

/**
 * Ένα χαρακτηριστικό ακινήτου που **κουβαλά την προέλευσή του**.
 *
 * 🔴 **Ο τύπος κάνει το ADR-842 Α7 ΑΔΥΝΑΤΟ να παραλειφθεί**: δεν υπάρχει τρόπος να
 * κατασκευαστεί `inferred` χωρίς να ειπωθεί **αν το ενέκρινε άνθρωπος**, γιατί το
 * `confirmedAt` **δεν είναι προαιρετικό** — είναι `string | null`, δηλαδή απάντηση
 * που πρέπει να δοθεί. *(Ίδια σχεδίαση με το `OwnerPropertyPlace`, όπου το «δεν θέλω
 * να το πω» είναι **έγκυρη απάντηση** και όχι κενό.)*
 *
 * @typeParam T — ο τύπος της τιμής (`EnergyClassType`, `number`, `readonly string[]`…).
 */
export type SourcedAttribute<T> =
  | (AttributeFactBase & {
      readonly provenance: 'measured';
      readonly value: T;
      /**
       * Δείκτης στο **σχέδιο** που το παρήγαγε.
       *
       * ⚠️ Είναι `string` και **όχι** δομημένη ταυτότητα, δηλωμένα: η ταυτότητα του
       * σχεδίου ανήκει στη Φ6 (ADR-842 §7) και θα ήταν **επινόηση** να οριστεί εδώ,
       * πριν υπάρξει ο παραγωγός. Δες ADR-842 §8.
       */
      readonly sourceRef: string;
    })
  | (AttributeFactBase & {
      readonly provenance: 'declared';
      readonly value: T;
    })
  | (AttributeFactBase & {
      readonly provenance: 'inferred';
      readonly value: T;
      /** 0..1 — πόσο σίγουρο είναι το μοντέλο. */
      readonly confidence: number;
      /** ISO στιγμή έγκρισης από άνθρωπο, ή `null` αν **δεν** έχει εγκριθεί. */
      readonly confirmedAt: string | null;
    });

// ============================================================================
// 3. Ο ΚΑΝΟΝΑΣ ΤΟΥ Α7 — σε εκτελέσιμη μορφή, μία φορά
// ============================================================================

function assertNeverProvenance(fact: never): never {
  throw new Error(
    `Άγνωστη προέλευση χαρακτηριστικού: ${JSON.stringify(fact)} — ` +
      'νέο σκέλος στο SourcedAttribute χωρίς απάντηση στο «φεύγει δημόσια;» (ADR-842 Α7).',
  );
}

/**
 * **Επιτρέπεται αυτό το χαρακτηριστικό να φτάσει στον αγοραστή;**
 *
 * 🔴 **Εδώ ζει το ADR-842 Α7, και ΜΟΝΟ εδώ.** Ένα χαρακτηριστικό που μάντεψε μοντέλο
 * μπορεί να **προταθεί** στον κάτοχο, αλλά **δεν φτάνει στον αγοραστή ως γεγονός**
 * μέχρι να το εγκρίνει άνθρωπος. Σε αυτό ο Νέστωρ είναι **αυστηρότερος** από τους
 * μεγάλους παίκτες, που δημοσιεύουν συμπεράσματα computer-vision αυτούσια.
 *
 * ⚠️ **Το `switch` είναι εξαντλητικό επίτηδες**: νέο σκέλος στο
 * {@link SourcedAttribute} **σπάει τη μεταγλώττιση εδώ** — δηλαδή δεν μπορεί να
 * προστεθεί προέλευση χωρίς να απαντηθεί *«φεύγει δημόσια;»*. Ίδιο ιδίωμα με το
 * `isAttributeDeclared` του `lib/listings/listing-disclosure.ts`.
 *
 * ⚠️ **ΜΗΝ το «απλοποιήσεις» σε `provenance !== 'inferred'`.** Θα έδινε σήμερα την
 * ίδια απάντηση και θα σταματούσε να ρωτά αύριο.
 */
export function isPubliclyPresentable<T>(fact: SourcedAttribute<T>): boolean {
  switch (fact.provenance) {
    case 'measured':
      // Μετρημένο από σχέδιο — δεν είναι γνώμη.
      return true;
    case 'declared':
      // Το είπε άνθρωπος και το υπογράφει· ο αγοραστής βλέπει ποιος δήλωσε.
      return true;
    case 'inferred':
      // 🔑 Ο πυρήνας του Α7: μάντεμα χωρίς ανθρώπινη έγκριση ΔΕΝ είναι γεγονός.
      return fact.confirmedAt !== null;
    default:
      return assertNeverProvenance(fact);
  }
}

/**
 * Ποια από τις δύο εκδοχές του **ίδιου** χαρακτηριστικού κρατάμε;
 *
 * Επιστρέφει την `incoming` μόνο αν η προέλευσή της **ξεπερνά** την υπάρχουσα
 * ({@link outranksForAttribute}) — αλλιώς την `current`, **αμετάβλητη**.
 *
 * 🔑 Γι' αυτό ζει εδώ και όχι στον καλούντα: δύο τόποι που απαντούν *«ποια νικά;»*
 * θα διαφωνούσαν, και θα διαφωνούσαν **σιωπηλά**.
 */
export function preferStrongerAttribute<T>(
  current: SourcedAttribute<T> | null,
  incoming: SourcedAttribute<T>,
): SourcedAttribute<T> {
  if (current === null) return incoming;
  return outranksForAttribute(incoming.provenance, current.provenance) ? incoming : current;
}
