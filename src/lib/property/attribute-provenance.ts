/**
 * Βαθμίδα αξιοπιστίας ανά προέλευση (μεγαλύτερο = ισχυρότερη πηγή).
 *
 * 🔑 **Η κατάταξη ΕΙΝΑΙ ο κανόνας, γραμμένος μία φορά:**
 *
 *     μετρημένο από σχέδιο  >  δηλωμένο από άνθρωπο  >  συμπερασμένο από μοντέλο
 *
 * ⚠️ **Οι αριθμοί δεν έχουν νόημα από μόνοι τους και ΔΕΝ αποθηκεύονται ποτέ** — μόνο
 * η **σύγκρισή** τους. Ίδια προειδοποίηση, ίδιος λόγος με το
 * `LOCATION_PROVENANCE_RANK`.
 *
 * 🔴 **Το `inferred` είναι ΚΑΤΩ από το `declared`, και είναι απόφαση.** Ένα μοντέλο
 * που «βλέπει» τζάκι σε φωτογραφία **δεν** επιτρέπεται να σβήσει τη δήλωση του
 * ιδιοκτήτη ότι δεν υπάρχει τζάκι. Το ίδιο σκεπτικό με το `geocoded` της θέσης, που
 * μπήκε **χαμηλότερα** από το `manual` ώστε μια αυτόματη γεωκωδικοποίηση να μη
 * σβήνει πινέζα ανθρώπου.
 */
const ATTRIBUTE_PROVENANCE_RANK = {
  measured: 3,
  declared: 2,
  inferred: 1,
} as const satisfies Readonly<Record<string, number>>;

/**
 * Από πού ξέρουμε ένα χαρακτηριστικό ακινήτου. **Κλειστή ένωση, ποτέ `string`.**
 *
 * - `measured` — **υπολογισμένο** από DXF/BIM. Βεβαιότητα, όχι πρόβλεψη: ένα εμβαδόν
 *   που προκύπτει από κλειστό περίγραμμα κάτοψης **δεν είναι γνώμη**. Αυτό είναι το
 *   *«ποτέ ό,τι μπορούμε να υπολογίσουμε»* της Α14 §17.2, εκτελεσμένο.
 * - `declared` — το δήλωσε **άνθρωπος** (ιδιοκτήτης ή μεσίτης).
 * - `inferred` — το **συμπέρανε** μοντέλο ή τα συμφραζόμενα. Πιθανολογικό.
 *
 * 🔑 **Παράγεται από την κατάταξη**, ώστε να μην υπάρχει προέλευση χωρίς δηλωμένη
 * βαθμίδα — ίδιο ιδίωμα με το ADR-842 Α4 (η λίστα είναι η πηγή, ο τύπος παράγεται).
 */
export type AttributeProvenance = keyof typeof ATTRIBUTE_PROVENANCE_RANK;

/** Ο κατάλογος των προελεύσεων — **παράγεται**, δεν ξαναγράφεται. */
export const ATTRIBUTE_PROVENANCES: readonly AttributeProvenance[] = Object.keys(
  ATTRIBUTE_PROVENANCE_RANK,
) as AttributeProvenance[];

/** Η βαθμίδα αξιοπιστίας μιας προέλευσης. Δες {@link ATTRIBUTE_PROVENANCE_RANK}. */
export function attributeProvenanceRank(provenance: AttributeProvenance): number {
  return ATTRIBUTE_PROVENANCE_RANK[provenance];
}

/**
 * Επιτρέπεται στο `candidate` να **αντικαταστήσει** το `current`;
 *
 * ⚠️ **Ισοβαθμία ⇒ ΟΧΙ**, και είναι η ίδια σημασιολογία με το `outranksForFact` της
 * θέσης: μια δεύτερη δήλωση ανθρώπου δεν σβήνει σιωπηλά την πρώτη. Η διαφωνία μένει
 * **ορατή** αντί να λύνεται με «ό,τι γράφτηκε τελευταίο».
 */
export function outranksForAttribute(
  candidate: AttributeProvenance,
  current: AttributeProvenance | null,
): boolean {
  if (current === null) return true;
  return attributeProvenanceRank(candidate) > attributeProvenanceRank(current);
}

