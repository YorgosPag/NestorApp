/**
 * 🔴 **ΟΙ ΑΞΟΝΕΣ ΠΟΥ ΕΝΑ ΟΙΚΟΠΕΔΟ ΔΕΝ ΜΠΟΡΕΙ ΝΑ ΑΠΑΝΤΗΣΕΙ — ΔΟΜΙΚΑ, ΟΧΙ ΑΠΟ ΑΜΕΛΕΙΑ.**
 *
 * Ο κανόνας υπήρχε ήδη, **καρφωμένος σε μία γραμμή** μέσα στον κριτή:
 *
 * ```
 * if (filters.bedroomsMin !== null && !isLandProperty(listing.type)) { … }
 * ```
 *
 * με τον λόγο γραμμένο δίπλα του *(ADR-777 §8.32: «η γη δεν κρίνεται σε
 * υπνοδωμάτια» — ο έλεγχος `null ⇒ έξω` **εξαφάνιζε ΚΑΘΕ οικόπεδο**, μετρημένο)*.
 *
 * ⚠️ **Το ελάττωμα δεν ήταν η γραμμή — ήταν ότι ήταν ΜΙΑ.** Το ίδιο ισχύει για
 * **είκοσι τέσσερις** άξονες: ένα οικόπεδο δεν έχει μπάνια, ούτε θέρμανση, ούτε
 * ενεργειακό πιστοποιητικό, ούτε κουφώματα. Αφημένος καρφωμένος, ο κανόνας θα
 * ξαναγραφόταν 24 φορές — ή, πιθανότερα, **23 φορές όχι**, και η ανακάλυψη θα γινόταν
 * όπως η πρώτη: από άνθρωπο που είδε άδεια οθόνη.
 *
 * 🔑 **Ο ίδιος κριτής, όχι δεύτερος**: η ερώτηση «είναι γη;» απαντιέται από το
 * `isLandProperty` *(`constants/property-classification`)*, τον **ΕΝΑ** κριτή που το
 * ADR-842 §7.6.11 γέννησε ακριβώς επειδή υπήρχαν δύο με διαφορετική δύναμη. Εδώ ζει
 * **μόνο η λίστα**, ποτέ ο κριτής.
 *
 * ⚠️ **ΜΗΝ προσθέσεις γραμμές για `commercial` χωρίς μέτρηση.** Μπήκε **μία** κλάση,
 * επειδή για αυτήν η απάντηση είναι ο **ορισμός** της λέξης *(γη = χωρίς κτίσμα ⇒
 * χωρίς τίποτα από όσα ανήκουν σε κτίσμα)*. Για το εμπορικό δεν υπάρχει τέτοιος
 * ορισμός — ένα κατάστημα **έχει** ενεργειακή κλάση και μπάνιο. Ίδια πειθαρχία με το
 * `UNCERTAIN_BLOCKERS`: *«μπήκε ένα, επειδή μετρήθηκε»*.
 *
 * 🔑 **Και ο `orientations` ΔΕΝ είναι εδώ, επίτηδες**: ένα οικόπεδο **έχει**
 * προσανατολισμό. Ούτε το `areaSqm`, ούτε το `type`, ούτε οι τέσσερις ειδικοί άξονες
 * — τιμή, διάθεση, συγγραφή και φωτογραφίες ισχύουν για κάθε είδος.
 */
export const LAND_CANNOT_ANSWER = [
  'floor',
  'bedrooms',
  'energyClass',
  'condition',
  'renovationYear',
  'bathrooms',
  'wc',
  'totalRooms',
  'levels',
  'balconies',
  'netAreaSqm',
  'balconyAreaSqm',
  'terraceAreaSqm',
  'gardenAreaSqm',
  'heatingType',
  'heatingFuel',
  'coolingType',
  'waterHeating',
  'windowFrames',
  'glazing',
  'flooring',
  'interiorFeatures',
  'securityFeatures',
  'amenities',
] as const satisfies readonly CriterionKey[];

/** Σηκώνει η **γη** αυτή την ερώτηση; */
export function landCanAnswer(key: CriterionKey): boolean {
  return !(LAND_CANNOT_ANSWER as readonly string[]).includes(key);
}
