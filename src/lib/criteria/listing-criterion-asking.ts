/**
 * 🔴 **ΟΙ ΤΡΕΙΣ ΑΞΟΝΕΣ ΠΟΥ ΜΕΝΟΥΝ ΕΞΩ ΑΠΟ ΤΟΝ ΧΑΡΤΗ ΚΡΙΤΗΡΙΩΝ — ΚΑΙ ΤΟ ΓΙΑΤΙ.**
 *
 * ⚠️ **Κλειστό σύνολο με λόγο, ποτέ σιωπηλή παράλειψη.** Ένας άξονας που έμενε έξω
 * χωρίς γραμμή εδώ θα ήταν αόρατος: κανείς δεν θα ήξερε αν λείπει επειδή αποφασίστηκε
 * ή επειδή ξεχάστηκε. Είναι το ίδιο ιδίωμα με το `DEMAND_AXES_LOST_IN_FILTERS`.
 *
 * | Άξονας | Γιατί δεν είναι κριτήριο του χάρτη |
 * |---|---|
 * | `near` | **γεωμετρία**, όχι τιμή: σημείο + ακτίνα, με τρεις δικούς του φρουρούς *(μισό ζεύγος · εκτός ορίων · ακτίνα ≤ 0)*. Έχει ήδη **τέσσερις** καταναλωτές και δικό του δρόμο προς το `lib/geo/`. |
 * | `stayWindow` | **ημι-ανοιχτό διάστημα ημερών** `[in, out)`, και δεν φιλτράρει καν — απαντιέται με **όνομα** στη λογιστική διαμονής *(ADR-835 §4.6: «ποτέ με εξαφάνιση»)*. |
 * | `guests` | **χωρητικότητα**, κριτής της διαθεσιμότητας· ανεξάρτητο από το παράθυρο **επίτηδες**. |
 *
 * 🔑 Και οι τρεις μένουν **επίπεδα πεδία** του `ListingFilters`. Το να τους χωθούν σε
 * ομοιόμορφο χάρτη θα απαιτούσε ένα πέμπτο σχήμα ανά άξονα — δηλαδή τρία σχήματα με
 * **από ένα μέλος**, που είναι ομοιομορφία στο όνομα και όχι στην ουσία.
 */
export const AXES_OUTSIDE_THE_CRITERIA_MAP = ['near', 'stayWindow', 'guests'] as const;

export type AxisOutsideTheCriteriaMap = (typeof AXES_OUTSIDE_THE_CRITERIA_MAP)[number];

