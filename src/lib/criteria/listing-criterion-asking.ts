/** **Κάθε άξονας του χάρτη κριτηρίων, και το σχήμα του.** */
export const LISTING_CRITERION_ASKING = {
  ...ATTRIBUTE_ASKING,
  ...BESPOKE_ASKING,
} as const;

type Asking = typeof LISTING_CRITERION_ASKING;

/** **Ο άξονας** — δημόσιο στοιχείο ή δηλωμένος ειδικός. */
export type CriterionKey = keyof Asking;

/**
 * Τα κλειδιά με δεδομένο σχήμα.
 *
 * 🔑 **Μία υλοποίηση για πέντε καταλόγους** — ίδιο ιδίωμα με το `KeysWithTreatment`
 * του `listing-disclosure`, και για τον ίδιο λόγο: πέντε αντίγραφα του ίδιου
 * μαπαρισμένου τύπου θα ήταν δίδυμοι κλώνοι **μέσα στο ίδιο αρχείο**, δηλαδή ακριβώς
 * ό,τι το `jscpd:diff` (N.18) υπάρχει για να πιάσει.
 */
type KeysWithShape<S extends CriterionShape> = {
  [K in keyof Asking]: Asking[K] extends S ? K : never;
}[keyof Asking];

/** Άξονες με αριθμητικό εύρος. */
export type RangeCriterionKey = KeysWithShape<'range'>;
/** Άξονες όπου η αγγελία έχει **μία** τιμή και ο άνθρωπος δέχεται πολλές. */
export type EnumCriterionKey = KeysWithShape<'enum-any'>;
/** Άξονες όπου αρκεί **τομή** των δύο συνόλων. */
export type SetAnyCriterionKey = KeysWithShape<'set-any'>;
/** Άξονες όπου χρειάζεται **εγκλεισμός** του ζητούμενου. */
export type SetAllCriterionKey = KeysWithShape<'set-all'>;
/** Άξονες ναι/όχι. */
export type FlagCriterionKey = KeysWithShape<'flag'>;

/**
 * Οι άξονες που ρωτιούνται με **σύνολο συμβολοσειρών** — δηλαδή τα τρία μη αριθμητικά
 * σχήματα μαζί. Ο χάρτης τιμών τους είναι **ένας**, γιατί η αποθήκευση είναι η ίδια·
 * η **κρίση** τους διαφέρει, και γίνεται στον κριτή.
 */
export type ValueSetCriterionKey =
  | EnumCriterionKey
  | SetAnyCriterionKey
  | SetAllCriterionKey;

/**
 * **Ο κατάλογος των αξόνων, στη σειρά δήλωσης.**
 *
 * ⚠️ Παράγεται με `Object.keys`, που για κλειδιά-συμβολοσειρές διατηρεί τη **σειρά
 * εισαγωγής** (ECMAScript `OrdinaryOwnPropertyKeys`) — ίδιο ιδίωμα με τα
 * `LISTING_ATTRIBUTE_KEYS` και `ORIENTATIONS`. Η σειρά είναι **οθόνη**.
 */
export const LISTING_CRITERION_KEYS: readonly CriterionKey[] = Object.keys(
  LISTING_CRITERION_ASKING
) as readonly CriterionKey[];

/** Οι άξονες με το δεδομένο σχήμα, **στη σειρά του πίνακα**. */
export function criterionKeysWithShape(shape: CriterionShape): readonly CriterionKey[] {
  return LISTING_CRITERION_KEYS.filter((key) => LISTING_CRITERION_ASKING[key] === shape);
}

