/**
 * 🏆 **ΤΙ ΑΠΑΝΤΑ ΕΝΑΣ ΑΞΟΝΑΣ ΓΙΑ ΜΙΑ ΑΓΓΕΛΙΑ — ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ `boolean`.**
 *
 * Το `matchesListingFilters` επέστρεφε `boolean`, δηλαδή **δύο** κάδους: μέσα, έξω.
 * Με 8 άξονες αυτό ήταν ανεκτό. Με **27** γίνεται ενεργό ψέμα, και ο αριθμός το
 * δείχνει: σήμερα δηλώνονται **12 από τα 27** στοιχεία *(`listingGroupLedger`)*, άρα
 * ένα φίλτρο «ενεργειακή κλάση» με `boolean` θα **εξαφάνιζε τις μισές αγγελίες χωρίς
 * να το πει** — μετατρέποντας το *«δεν ξέρουμε»* σε *«δεν είναι»*, που είναι
 * **διαφορετικός ισχυρισμός και ψευδής** (κανόνας Α5).
 *
 * 📐 **Και είναι το ΜΟΝΟ σημείο όπου δεν έχουμε πρότυπο να αντιγράψουμε.** Ρωτήθηκε
 * ρητά η έρευνα UI φίλτρων του Baymard *(Ιούλιος 2026)* για *«αντικείμενα που δεν
 * έχουν την ιδιότητα στην οποία φιλτράρεις»*: **δεν το πραγματεύεται**. Και η μελέτη
 * *Strategic under-disclosure in online property platforms* καταγράφει ότι οι ελλιπείς
 * αγγελίες είναι **ενδημικές**, όχι ακραία περίπτωση. Δηλαδή ο κλάδος έχει το
 * πρόβλημα και **δεν έχει απάντηση**· εμείς έχουμε ήδη το λεξιλόγιο
 * *(`ListingFeatureSetState`, `UnknownPositionReason`)* και μας έλειπε μόνο η **χρήση** του.
 *
 * ⚠️ **Ο `not-applicable` ΔΕΝ είναι κάδος αποτελέσματος** — είναι δήλωση ότι ο άξονας
 * σιωπά για αυτή την αγγελία. Δεν μετριέται πουθενά, γιατί δεν λέει τίποτα για την
 * αγγελία: λέει κάτι για την **ερώτηση**.
 */
export const CRITERION_OUTCOMES = [
  /** Απάντησε, και η απάντηση ικανοποιεί το αίτημα. */
  'satisfied',
  /** Απάντησε, και η απάντηση **δεν** ικανοποιεί το αίτημα. Κλειστή υπόθεση. */
  'excluded',
  /** **Δεν έχει δηλωθεί.** Ομολογία άγνοιας — ονομάζεται και μετριέται, ποτέ κρύβεται. */
  'undeclared',
  /** Η ερώτηση δεν σηκώνεται για αυτό το είδος πράγματος. Ο άξονας **αγνοείται**. */
  'not-applicable',
] as const;

export type CriterionOutcome = (typeof CRITERION_OUTCOMES)[number];

