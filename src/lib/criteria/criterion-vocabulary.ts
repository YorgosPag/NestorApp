// 2. Η ΑΠΑΝΤΗΣΗ ΤΗΣ ΑΓΓΕΛΙΑΣ — ΤΕΣΣΕΡΙΣ ΚΑΤΑΣΤΑΣΕΙΣ, ΟΧΙ ΔΥΟ
// =============================================================================

/**
 * 🏆 **ΤΕΣΣΕΡΙΣ ΚΑΤΑΣΤΑΣΕΙΣ ΑΠΟΥΣΙΑΣ — ΚΑΙ ΚΑΝΕΝΑ PORTAL ΔΕΝ ΕΧΕΙ ΟΥΤΕ ΔΥΟ.**
 *
 * | Κατάσταση | Τι σημαίνει | Ποιος τη δημιούργησε | Τι κάνει ο κριτής |
 * |---|---|---|---|
 * | `declared` | υπάρχει τιμή | ο κάτοχος | **κρίνει** |
 * | `declared-none` | ο κάτοχος απάντησε «καμία» | ο κάτοχος | **κρίνει** — είναι γεγονός |
 * | `never-asked` | κανείς δεν τον ρώτησε | **εμείς** — δικό μας χρέος | **ονομάζει**, δεν κρύβει |
 * | `not-applicable` | η ερώτηση δεν σηκώνεται | **το ίδιο το πράγμα** | **αγνοεί τον άξονα** |
 *
 * 🔴 **Η τέταρτη είναι η νέα, και είναι η γενίκευση ενός κανόνα που ΗΔΗ υπήρχε
 * καρφωμένος**: το `matchesListingFilters` έγραφε `!isLandProperty(listing.type)` για
 * τα υπνοδωμάτια, επειδή *«η γη δεν κρίνεται σε υπνοδωμάτια»* (ADR-777 §8.32). Αυτός
 * ο κανόνας **δεν είναι ιδιαιτερότητα των υπνοδωματίων** — είναι το πρώτο στιγμιότυπο
 * μιας οικογένειας **είκοσι τεσσάρων** αξόνων *(θέρμανση, μπάνια, ενεργειακή κλάση,
 * κουφώματα, …)* που ένα οικόπεδο **δομικά** δεν μπορεί να απαντήσει — ο κατάλογος
 * είναι το `LAND_CANNOT_ANSWER`, και το πλήθος του το **μετρά άγκυρα**. Αφημένος
 * καρφωμένος, θα ξαναγραφόταν 24 φορές — ή, πιθανότερα, **23 φορές όχι**.
 *
 * 🔑 **Γιατί `not-applicable` ≠ `never-asked`, και η διαφορά είναι ΟΡΑΤΗ στην οθόνη.**
 * Ένα οικόπεδο χωρίς όροφο **δεν** ανήκει στον κάδο *«3 δεν το δήλωσαν»*: κανείς δεν
 * του χρωστά δήλωση, και μια οθόνη που το μετρούσε εκεί θα ζητούσε από τον κάτοχο
 * γης να δηλώσει όροφο. Ο άξονας απλώς **δεν ισχύει** — και η αγγελία μένει στα
 * αποτελέσματα χωρίς επιφύλαξη.
 */

/**
 * Η απάντηση μιας αγγελίας σε **έναν** άξονα.
 *
 * ⚠️ **Διακριτή ένωση, ΠΟΤΕ `value: T | null` με χωριστό `state`.** Δύο πεδία θα
 * επέτρεπαν το `{ state: 'declared', value: null }` — δηλαδή τον τύπο να εκφράσει
 * «δηλωμένο τίποτα», που είναι ακριβώς η σύγχυση που όλο αυτό το αρχείο διαλύει.
 */
export type CriterionAnswer<T> =
  | { readonly state: 'declared'; readonly value: T }
  | { readonly state: 'declared-none' }
  | { readonly state: 'never-asked' }
  | { readonly state: 'not-applicable' };

/** Η αγγελία **απάντησε** σε αυτόν τον άξονα — με τιμή. */
export function declaredAnswer<T>(value: T): CriterionAnswer<T> {
  return { state: 'declared', value };
}

/** Οι τρεις απαντήσεις χωρίς τιμή, ως σταθερές — ώστε να μη γράφονται με το χέρι. */
export const DECLARED_NONE: CriterionAnswer<never> = { state: 'declared-none' };
export const NEVER_ASKED: CriterionAnswer<never> = { state: 'never-asked' };
export const NOT_APPLICABLE: CriterionAnswer<never> = { state: 'not-applicable' };

