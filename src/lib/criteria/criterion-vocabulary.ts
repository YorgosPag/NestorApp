/**
 * **Πώς ρωτιέται ένας άξονας** — κλειστό σύνολο, τέσσερα σχήματα.
 *
 * 🔑 **Η λίστα είναι η πηγή, ο τύπος παράγεται** — ίδιο ιδίωμα με τα
 * `LISTING_ATTRIBUTE_GROUPS` και `LOCATION_PROVENANCES`. Ένα χειρόγραφο
 * `type X = 'a' | 'b'` δίπλα σε χειρόγραφο `X[]` θα δεχόταν **υποσύνολο**, δηλαδή ένα
 * σχήμα θα μπορούσε να υπάρχει στον τύπο και **να μη φτάσει ποτέ** σε κανένα έλεγχο.
 *
 * 🔴 **ΥΠΑΡΧΟΥΝ ΔΥΟ ΣΧΗΜΑΤΑ ΓΙΑ ΣΥΝΟΛΑ, ΚΑΙ Η ΔΙΑΦΟΡΑ ΕΙΝΑΙ ΣΗΜΑΣΙΟΛΟΓΙΚΗ.**
 *
 * Ένα σύνολο επιλογών σημαίνει **δύο διαφορετικά πράγματα**, ανάλογα με το αν ο
 * άνθρωπος **περιγράφει** ή **απαιτεί**:
 *
 * | Ερώτηση | Τι εννοεί | Σχήμα |
 * |---|---|---|
 * | «πώληση **ή** ενοικίαση;» | *δέξου οποιοδήποτε από αυτά* | `set-any` |
 * | «τζάκι **και** ασανσέρ» | *πρέπει να έχει και τα δύο* | `set-all` |
 *
 * ⚠️ **Δεν συγχωνεύονται σε ένα με σημαία.** Το σχήμα καθορίζει **και** τι δείχνει η
 * οθόνη: τα `set-any` είναι εναλλακτικές *(ο χρήστης χαλαρώνει όσο τσεκάρει)*, τα
 * `set-all` είναι απαιτήσεις *(ο χρήστης στενεύει όσο τσεκάρει)* — δύο **αντίθετες**
 * κατευθύνσεις πάνω στο ίδιο χειριστήριο. Μία σημαία θα τις έκανε αόρατα
 * εναλλάξιμες, δηλαδή ο άνθρωπος δεν θα μπορούσε να ξέρει προς τα πού κινείται
 * τσεκάροντας το δεύτερο κουτάκι.
 *
 * 🔑 **Ο ρόλος `'feature-set'` του `LISTING_DISCLOSURE` ΔΕΝ απαντά αυτό το ερώτημα** —
 * και το γράφω επειδή είναι η προφανής, λανθασμένη συντόμευση. Και οι πέντε άξονες
 * συνόλου έχουν εκεί τον **ίδιο** ρόλο *(«πώς γίνεται ορατό;»)*, όμως το `flooring`
 * είναι **περιγραφή** και το `amenities` **απαίτηση**. Δύο ερωτήματα — η ανάθεση
 * γίνεται εδώ, ρητά, ανά άξονα.
 */
export const CRITERION_SHAPES = [
  /** Αριθμητικό εύρος: `{ min, max }`. Παράδειγμα: εμβαδόν, όροφος, έτος ανακαίνισης. */
  'range',
  /** Μία τιμή της αγγελίας ⇄ **σύνολο αποδεκτών**. Παράδειγμα: ενεργειακή κλάση. */
  'enum-any',
  /** Σύνολο της αγγελίας **τέμνει** το ζητούμενο. Παράδειγμα: διάθεση, προσανατολισμοί. */
  'set-any',
  /** Σύνολο της αγγελίας **περιέχει όλο** το ζητούμενο. Παράδειγμα: παροχές, τζάκι+ασανσέρ. */
  'set-all',
  /** Ναι/όχι· η απουσία του άξονα σημαίνει «δεν ρωτήθηκε». Παράδειγμα: «με φωτογραφίες». */
  'flag',
] as const;

export type CriterionShape = (typeof CRITERION_SHAPES)[number];

/**
 * Ένα αριθμητικό εύρος όπως το **ζητά ο άνθρωπος**.
 *
 * ⚠️ **Και τα δύο άκρα είναι προαιρετικά, ανεξάρτητα** — σε αντίθεση με το
 * `ListingStayWindow`, όπου το μισό παράθυρο είναι **μη ερώτηση**. Εδώ το «έως
 * 200.000» και το «από 80 τ.μ.» είναι **πλήρη** αιτήματα από μόνα τους, και ήταν ήδη
 * εκφράσιμα (`priceMax` χωρίς `priceMin`). Η διαφορά δεν είναι ασυνέπεια: εκεί τα δύο
 * άκρα ορίζουν **ένα** πράγμα (διάστημα νυχτών), εδώ ορίζουν **δύο** ανεξάρτητους
 * περιορισμούς.
 *
 * 🔴 **`{ min: null, max: null }` ΔΕΝ γράφεται ποτέ.** Ένα εύρος χωρίς άκρα δεν είναι
 * χαλαρό φίλτρο — είναι **καμία ερώτηση**, και θα ταξίδευε ως σκουπίδι σε κάθε
 * κοινοποιημένο σύνδεσμο. Ο φρουρός είναι το {@link isAskedRange}.
 */
export interface CriterionRange {
  readonly min: number | null;
  readonly max: number | null;
}

/** Το ουδέτερο εύρος — καμία ερώτηση, ώστε να μη γράφεται `{min:null,max:null}` αλλού. */
export const NO_RANGE: CriterionRange = { min: null, max: null };

/** Ρωτά κάτι αυτό το εύρος; **Κενό εύρος = όχι.** */
export function isAskedRange(range: CriterionRange | undefined): range is CriterionRange {
  return range !== undefined && (range.min !== null || range.max !== null);
}

