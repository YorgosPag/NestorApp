/**
 * @fileoverview **ΠΟΣΑ ΘΑ ΔΩ ΑΝ ΠΑΤΗΣΩ ΑΥΤΟ** — και **πόσα δεν το δήλωσαν**.
 * @related ADR-777 §8.51 (Στάδιο 3) · Baymard (πλήθη ανά επιλογή) · ./listing-criteria-judge
 * @module lib/criteria/criterion-option-counts
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🏆 ΤΟ ΣΗΜΕΙΟ ΟΠΟΥ ΤΟ ΜΕΤΡΗΜΕΝΟ «ΚΑΛΥΤΕΡΟ ΤΗΣ ΑΓΟΡΑΣ» ΓΙΝΕΤΑΙ ΔΙΚΟ ΜΑΣ, ΚΑΙ +1
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το Baymard ονομάζει τα πλήθη ανά επιλογή *«το μοναδικό υψηλότερης απόδοσης πράγμα σε
 * UI φίλτρων»*, και οι μεγάλοι τα δίνουν **προσεγγιστικά** επειδή μετρούν σε ευρετήριο
 * μακριά. Εμείς έχουμε **ολόκληρο τον κατάλογο στη μνήμη** — άρα τα δίνουμε **ακριβή**,
 * χωρίς καμία υποδομή.
 *
 * ⚠️ **ΚΑΙ ΔΙΝΟΥΜΕ ΔΕΥΤΕΡΟ ΑΡΙΘΜΟ ΠΟΥ ΚΑΝΕΙΣ ΔΕΝ ΔΙΝΕΙ.** Η καταγεγραμμένη σύμβαση των
 * μηχανών είναι ρητή: *«a conditional is added to eliminate any buckets that have zero
 * documents»* — δηλαδή μια επιλογή με μηδέν **εξαφανίζεται**, ή γράφει `(0)`. Και τα δύο
 * λένε στον άνθρωπο *«δεν υπάρχει τέτοιο σπίτι»*, που είναι **ψευδές**: υπάρχουν οκτώ,
 * και **κανείς δεν τους ζήτησε ποτέ να απαντήσουν**.
 *
 * ```
 *   Θέρμανση        ☐ Φυσικό αέριο   0 · 8 δεν το δήλωσαν     ← εδώ
 *   (οι μεγάλοι)    ☐ Φυσικό αέριο   (0)   ή   [εξαφανισμένο]
 * ```
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΓΙΑΤΙ Ο ΑΞΟΝΑΣ ΑΦΑΙΡΕΙΤΑΙ ΑΠΟ ΤΑ ΚΡΙΤΗΡΙΑ ΠΡΙΝ ΜΕΤΡΗΘΕΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Τα πλήθη απαντούν *«αν πατήσω **αυτό**, πόσα θα δω;»*. Αν ο άξονας έμενε μέσα, μια
 * ήδη επιλεγμένη τιμή θα έκοβε **όλες τις υπόλοιπες στο μηδέν** — και ο άνθρωπος που
 * έχει ήδη διαλέξει «Πετρέλαιο» θα διάβαζε *«Φυσικό αέριο (0)»* και θα συμπέραινε ότι
 * δεν υπάρχει, ενώ απλώς **δεν το έχει ζητήσει**. Είναι το πρότυπο των **διαζευκτικών
 * όψεων** (Elasticsearch · Algolia), και ο λόγος που το `without` έγινε δημόσιο.
 *
 * ⚠️ **ΤΑ ΥΠΟΛΟΙΠΑ ΦΙΛΤΡΑ ΜΕΝΟΥΝ.** Χωρίς αυτά, τα πλήθη θα ήταν πλήθη **του
 * καταλόγου**, όχι της αναζήτησης — δηλαδή θα υπόσχονταν 40 αποτελέσματα και θα
 * παρέδιδαν 3.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΤΟ ΚΟΣΤΟΣ, ΜΕΤΡΗΜΕΝΟ ΚΑΙ ΔΗΛΩΜΕΝΟ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * **Ένα πέρασμα ανά άξονα**, όχι ένα ανά επιλογή. Η αφελής γραφή *(«για κάθε επιλογή,
 * φίλτραρε τον κατάλογο»)* κάνει `επιλογές × αγγελίες` περάσματα — για τις ~200
 * επιλογές των 16 λεξιλογικών αξόνων και 2.000 αγγελίες είναι **400.000** κρίσεις **ανά
 * πάτημα πλήκτρου**. Εδώ η αγγελία κρίνεται **μία φορά** και προσαυξάνει όσους κάδους
 * της αναλογούν.
 *
 * ⚠️ **Καλείται ΑΝΑ ΟΡΑΤΟ ΑΞΟΝΑ, όχι για τους 31.** Ο καταναλωτής μετρά μόνο ό,τι
 * ζωγραφίζει· ένας άξονας κλειστός μέσα σε `accordion` δεν έχει επιλογές να δείξει,
 * άρα δεν έχει και τι να μετρήσει.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις. Καμία εξάρτηση από React ή Firestore.
 */

import type { PublicListing } from '@/types/public-listing';

import { CRITERION_VALUES } from './listing-criterion-values';
import { readValuesAnswer } from './listing-criterion-reading';
import { listingSurvivesCriteria } from './listing-criteria-judge';
import { without, type ListingCriteria } from './listing-criteria';
import type { ValueSetCriterionKey } from './listing-criterion-asking';

// =============================================================================
// 1. ΤΟ ΣΧΗΜΑ — ΔΥΟ ΑΡΙΘΜΟΙ, ΠΟΤΕ ΕΝΑΣ
// =============================================================================

/**
 * Τα δύο πλήθη μιας επιλογής.
 *
 * 🔴 **Δύο πεδία, ΟΧΙ ένα με φιλτράρισμα από τον καταναλωτή** — το ίδιο μάθημα με το
 * `ListingCriteriaMatch`: ένας καταναλωτής που έβγαζε μόνος του το «πόσοι σιωπούν» από
 * το «πόσοι ταιριάζουν» θα είχε δίκιο μέχρι την πρώτη τέταρτη έκβαση, και μετά θα
 * έκλεινε **λάθος, σιωπηλά**.
 */
export interface CriterionOptionCount {
  /** Αγγελίες που **δηλώνουν** αυτή την τιμή και επιβιώνουν των υπόλοιπων φίλτρων. */
  readonly matching: number;
  /**
   * Αγγελίες που επιβιώνουν των υπόλοιπων φίλτρων και **δεν δήλωσαν τίποτα** σε αυτόν
   * τον άξονα.
   *
   * ⚠️ **Είναι ο ΙΔΙΟΣ αριθμός για κάθε επιλογή του άξονα**, και δεν είναι σφάλμα: η
   * σιωπή είναι ιδιότητα του **άξονα**, όχι της τιμής. Μια αγγελία που δεν δήλωσε
   * θέρμανση σιωπά **εξίσου** για το φυσικό αέριο και για το πετρέλαιο. Ταξιδεύει ανά
   * επιλογή επειδή **εκεί διαβάζεται** — δίπλα στο τετραγωνίδιο, όχι σε υποσημείωση.
   */
  readonly undeclared: number;
}

/**
 * Τα πλήθη **όλων** των επιλογών ενός άξονα, **στη σειρά του λεξιλογίου**.
 *
 * ⚠️ **Πίνακας ζευγών και όχι `Record<string, …>`**: η σειρά είναι **οθόνη**
 * *(`CRITERION_VALUES`: «η σειρά είναι η σειρά της οθόνης»)*, και ένας χάρτης θα την
 * άφηνε στον καταναλωτή να την ξαναβρεί — δηλαδή θα ήταν **δεύτερη** δήλωση σειράς.
 */
export interface CriterionOptionTally {
  readonly value: string;
  readonly count: CriterionOptionCount;
}

// =============================================================================
// 2. Η ΜΕΤΡΗΣΗ
// =============================================================================

/**
 * **Πόσα θα δει ο άνθρωπος για κάθε επιλογή αυτού του άξονα.**
 *
 * 🔑 **Η αγγελία ρωτιέται με τον ΙΔΙΟ αναγνώστη που χρησιμοποιεί ο κριτής**
 * (`readValuesAnswer`), ποτέ με δικό μας `listing[key]`. Ένας δεύτερος αναγνώστης θα
 * έχανε τις τέσσερις καταστάσεις απουσίας — και θα μετρούσε ένα οικόπεδο ως
 * *«δεν δήλωσε θέρμανση»* αντί για *«δεν σηκώνει την ερώτηση»*, δηλαδή θα κατηγορούσε
 * τον κάτοχο για πεδίο που **δεν υπάρχει** στο ακίνητό του.
 *
 * ⚠️ **Το `not-applicable` δεν μετριέται ΠΟΥΘΕΝΑ, και είναι απόφαση.** Ένα οικόπεδο
 * δεν είναι ούτε «ταιριάζει» ούτε «δεν το δήλωσε» για τη θέρμανση: **δεν είναι στη
 * συζήτηση**. Αν μετριόταν ως σιωπή, το *«8 δεν το δήλωσαν»* θα κατηγορούσε δύο
 * οικόπεδα που δεν έχουν τι να δηλώσουν.
 */
export function criterionOptionTallies(
  listings: readonly PublicListing[],
  criteria: ListingCriteria,
  key: ValueSetCriterionKey
): readonly CriterionOptionTally[] {
  // 🔴 Ο ΙΔΙΟΣ Ο ΑΞΟΝΑΣ ΦΕΥΓΕΙ — δες την κεφαλίδα. Τα υπόλοιπα φίλτρα μένουν.
  const others = without(criteria, key);
  const values = CRITERION_VALUES[key];

  const matching = new Map<string, number>(values.map((value) => [value, 0]));
  let undeclared = 0;

  for (const listing of listings) {
    if (!listingSurvivesCriteria(listing, others)) continue;

    const answer = readValuesAnswer(listing, key);
    if (answer.state === 'not-applicable') continue;
    if (answer.state !== 'declared') {
      // `never-asked` και `declared-none` είναι **και τα δύο** σιωπή απέναντι σε μια
      // συγκεκριμένη τιμή: ούτε το «δεν ρώτησε κανείς» ούτε το «δήλωσε ότι δεν έχει
      // καμία» απαντούν *«έχει φυσικό αέριο;»* με ναι.
      undeclared += 1;
      continue;
    }

    for (const value of answer.value) {
      const current = matching.get(value);
      // ⚠️ Τιμή εκτός λεξιλογίου **αγνοείται σιωπηλά εδώ επίτηδες**: ο φρουρός της
      //    είναι το `keepKnownValues` στην πόρτα της διεύθυνσης, και μια δεύτερη
      //    πολιτική εδώ θα ήταν δεύτερη αλήθεια για το «τι είναι έγκυρη τιμή».
      if (current !== undefined) matching.set(value, current + 1);
    }
  }

  return values.map((value) => ({
    value,
    count: { matching: matching.get(value) ?? 0, undeclared },
  }));
}
