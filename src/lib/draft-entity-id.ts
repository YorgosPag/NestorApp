/** Η ψευδο-ταυτότητα μιας εγγραφής που ο άνθρωπος **συμπληρώνει** αλλά δεν αποθήκευσε. */
export const DRAFT_ENTITY_ID = '__new__';

/** Είναι αυτή η ταυτότητα ένα «Νέο» που δεν αποθηκεύτηκε ακόμη; */
export function isDraftEntityId(id: string | null | undefined): boolean {
  return id === DRAFT_ENTITY_ID;
}
