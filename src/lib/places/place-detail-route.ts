/**
 * @fileoverview **ΠΟΙΑ ΠΟΡΤΑ ΑΝΟΙΓΕΙ Ο ΚΑΤΟΧΟΣ ΑΥΤΟΥ ΤΟΥ ΑΚΙΝΗΤΟΥ** — μία απάντηση.
 * @related ADR-841 §7 Α18.9 · ADR-777 §8.23 (δύο μονοπάτια κατοχής) · §8.30 (η καρτέλα)
 * @module lib/places/place-detail-route
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ — **ΜΕΤΡΗΜΕΝΗ ΨΕΥΤΙΚΗ ΠΟΡΤΑ, ΟΧΙ ΠΡΟΛΗΠΤΙΚΗ ΑΦΑΙΡΕΣΗ**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο ειδοποιητής ζήτησης σαρώνει **δύο** συλλογές — τα ακίνητα του ιδιώτη
 * (`owner_properties`, `ownp_*`) και τις αγγελίες του γραφείου (`properties`,
 * `prop_*`) — και έστελνε **και τις δύο** στην ίδια οθόνη: το `/offers/<id>`,
 * που είναι **των δικών μου** ακινήτων.
 *
 * **Μετρημένο ζωντανά, κλειστά, σε 12 έγγραφα** (ADR-841 §7 Α18.8): τα **6**
 * `ownp_*` άνοιγαν· τα **6** `prop_*` απαντούσαν *«Αυτό το ακίνητο δεν υπάρχει —
 * ή δεν είναι δικό σου»*. Δηλαδή **οι μισές ειδοποιήσεις είχαν κουμπί που
 * οδηγούσε σε άρνηση**, και το κουμπί φαινόταν κανονικό.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 Η ΚΑΤΟΧΗ ΔΕΝ **ΣΥΝΑΓΕΤΑΙ** ΕΔΩ — **ΔΗΛΩΝΕΤΑΙ** ΑΠΟ ΟΠΟΙΟΝ ΔΙΑΒΑΣΕ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * ⛔ Μια ευρετική προθέματος (`id.startsWith('prop_')`) θα ήταν σωστή **σήμερα**
 * και θα ήταν **παρατήρηση** για κάτι που ο καλών **ξέρει**: ο σαρωτής μόλις
 * ρώτησε τη συλλογή. Η Α18.3 έχει ήδη απορρίψει ρητά τη λύση-με-ευρετική
 * (δίπλα στις δύο **αγγλικές** του `NotificationDrawer`, που καμία ελληνική
 * ειδοποίηση δεν πιάνει).
 *
 * ⛔ Και μια κρίση από το `tenantId` («μοιάζει με εταιρεία;») θα έδινε **δεύτερη
 * ερμηνεία** σε πεδίο που υπάρχει για **άλλο** λόγο (ο μισθωτής). Την ημέρα που
 * ένας ιδιώτης αποκτήσει `tenantId` εταιρείας, η **διεύθυνση** θα άλλαζε
 * σιωπηλά — το σχήμα του ADR-749.
 *
 * ⇒ Η κατοχή ταξιδεύει ως **{@link PlaceSource}**, το λεξιλόγιο που **υπήρχε
 * ήδη** για ακριβώς αυτό το ερώτημα (`place-interest.service.ts`).
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΤΙ **ΔΕΝ** ΓΡΑΦΕΤΑΙ ΕΔΩ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * **Καμία συμβολοσειρά διαδρομής.** Και οι δύο πόρτες έχουν ήδη μητρώο —
 * `owner-property-routes.ts` και `entityRoutes.ts` — και το δεύτερο έχει ήδη
 * **άγκυρες** που ρωτούν *«οδηγεί ο σύνδεσμος κάπου;»* (ADR-777 §8.30). Ένα
 * τρίτο `` `/properties/${id}` `` εδώ θα ήταν το ακριβές λάθος που το **Κ2** της
 * `notification-destination-custody` απαγορεύει: χάνει το `encodeURIComponent`
 * και αστοχεί **σιωπηλά σε ένα μόνο έγγραφο**.
 *
 * **Και κανένα πρόθεμα χώρου.** Το ωμό `/properties/<id>` το αναλαμβάνει το
 * δίχτυ `(app)/[...unprefixed]`, που αποφασίζει με **κριμένη** ταυτότητα στον
 * διακομιστή (ADR-787 §5.3 θ) — μετρημένο ζωντανά: κατέληξε σε
 * `/o/comp_…/properties/<id>`. Ένα cron **δεν έχει** τρέχουσα διεύθυνση, άρα
 * δεν έχει και ψευδώνυμο χώρου να δώσει: μαντεψιά εδώ θα έστελνε τον άνθρωπο σε
 * **ξένο** γραφείο.
 *
 * **Layering**: leaf — μόνο σύνθεση διευθύνσεων, καμία ανάγνωση.
 */

// ⚠️ **Απευθείας από το module, όχι από το barrel `@/lib/routes`**: αυτό το αρχείο
//    ταξιδεύει σε **cron**, και ένα `export *` θα έσερνε μαζί και τις διαδρομές
//    λογαριασμού/προσγείωσης που κανείς εκεί δεν χρειάζεται (ιδίωμα CHECK 3.30).
import { ENTITY_ROUTES } from '@/lib/routes/entityRoutes';
import { offerDetailHref } from '@/lib/owner-property/owner-property-routes';
import type { PlaceSource } from '@/services/demand/place-interest.service';

/**
 * **Η πόρτα κάθε κατοχής** — και ο τύπος είναι ο φρουρός.
 *
 * 🔑 `Record<PlaceSource, …>` **δεμένο στη ρίζα του λεξιλογίου** (ιδίωμα CHECK
 * 3.73): μια τρίτη κατοχή δεν μπορεί να προσγειωθεί «με προεπιλογή» — ο
 * μεταγλωττιστής απαιτεί να **αποφασίσει κάποιος** πού πάει ο άνθρωπός της.
 *
 * ⚠️ Οι δύο τιμές **δεν είναι δύο ονόματα του ίδιου πράγματος**: η πρώτη είναι η
 * καρτέλα **του ανθρώπου** (`(me)`, `noindex`), η δεύτερη η καρτέλα **του
 * γραφείου** (`(app)`, πίσω από τον χώρο). Και οι δύο κουβαλούν το πάνελ *«ποιοι
 * ψάχνουν κάτι τέτοιο»* — που είναι, μετρημένα, **το μόνο πράγμα που ανακοινώνει
 * η ειδοποίηση**. Η **δημόσια** αγγελία δεν το κουβαλά, γι' αυτό δεν είναι εδώ.
 */
const PLACE_DETAIL_HREF: Record<PlaceSource, (id: string) => string> = {
  'owner-property': offerDetailHref,
  'company-property': ENTITY_ROUTES.properties.withId,
};

/**
 * **Πού στέλνουμε τον κάτοχο αυτού του ακινήτου.**
 *
 * @param source — η κατοχή, **δηλωμένη** από όποιον διάβασε τη συλλογή
 * @param placeId — η ταυτότητα (`ownp_*` ή `prop_*`), όπως ήρθε από τα δεδομένα
 */
export function placeDetailHref(source: PlaceSource, placeId: string): string {
  return PLACE_DETAIL_HREF[source](placeId);
}
