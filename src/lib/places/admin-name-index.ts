/**
 * **Ο ΕΛΑΧΙΣΤΟΣ ΤΟΠΟΣ** — ό,τι χρειάζεται η ταυτοποίηση, και τίποτα άλλο.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 **ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΤΟ `AdminEntity` ΤΟΥ HOOK — ΕΙΝΑΙ ΟΡΘΟΤΗΤΑ, ΟΧΙ ΚΑΘΑΡΟΤΗΤΑ.**
 *
 * Ο **ίδιος** κριτής τρέχει σε **δύο** πλευρές του σύρματος: στον διακομιστή *(το
 * `api/geocoding/reverse`, όπου η ωμή αλυσίδα του Nominatim υπάρχει ακέραιη)* και στον
 * πελάτη *(η φόρμα, για όνομα που πληκτρολογεί ο άνθρωπος)*. Ένα `import` από
 * `@/hooks/**` μέσα σε API route είναι **λάθος στρώση** — σύρει React σε διαδρομή
 * διακομιστή.
 *
 * 🔑 Το `AdminEntity` του hook **ικανοποιεί δομικά** αυτό το σχήμα, άρα ο πελάτης περνά τις
 * οντότητές του **αυτούσιες**, χωρίς μετατροπέα *(που θα ήταν το πέμπτο χειρόγραφο
 * ζεύγος του ADR-772)*. Και ο διακομιστής διαβάζει **τέσσερα** πεδία από τα 3,7 MB αντί
 * για οκτώ — ίδια πειθαρχία με τον `administrative-hierarchy.reader`.
 * ═════════════════════════════════════════════════════════════════════════════
 */
export interface AdminPlace {
  readonly id: string;
  readonly name: string;
  readonly level: number;
  readonly parentId: string | null;
  /**
   * Ο Τ.Κ. — **μόνο σε οικισμούς, και μόνο σε 949 από τους 13.272** (**7,2%**).
   *
   * 🔑 Χρησιμεύει **αποκλειστικά** ως αποσαφηνιστής ανάμεσα σε **ΑΚΡΙΒΩΣ ομώνυμους**, όπου
   * είναι ασφαλής εξ ορισμού: το όνομα ταιριάζει ήδη απόλυτα, ο Τ.Κ. μόνο **στενεύει**.
   * ⛔ **ΠΟΤΕ πάνω σε ανεκτική αντιστοίχιση** — έτσι ήταν πριν, και «Καλλιθέα»/«Καλλίστη»
   * μοιράζονται τον **ίδιο** Τ.Κ. 69100, οπότε διάλεγε τη λάθος με σιγουριά.
   */
  readonly postalCode?: string;
}

/** Βαθμίδα → (διπλωμένο όνομα → οι τόποι που το φέρουν). */
export type AdminNameIndex = ReadonlyMap<number, ReadonlyMap<string, readonly AdminPlace[]>>;

/** Κενό ευρετήριο — **«δεν ρώτησα»**, ποτέ «δεν υπάρχει» (N.12). */
export const EMPTY_ADMIN_NAME_INDEX: AdminNameIndex = new Map();

/**
 * Χτίζει το ευρετήριο από το στιγμιότυπο της ιεραρχίας — **ένα** πέρασμα στις 20.720
 * οντότητες.
 *
 * ⚠️ **Ο πίνακας τιμών είναι ΛΙΣΤΑ, όχι μία οντότητα, και είναι ορθότητα**: **1.338**
 * ονόματα του επιπέδου 8 είναι **ομώνυμα** *(«Καλλιθέα» ×41)*. Ένα `Map.set` που κρατά
 * τον τελευταίο θα έκρυβε 40 οικισμούς — **το ίδιο σχήμα** με το περιστατικό των τριών
 * δήμων που έγιναν γεωγραφικά αόρατοι *(`administrative-hierarchy-data.test.ts`)*.
 */
export function buildAdminNameIndex(places: Iterable<AdminPlace>): AdminNameIndex {
  const index = new Map<number, Map<string, AdminPlace[]>>();

  for (const place of places) {
    let byName = index.get(place.level);
    if (!byName) {
      byName = new Map<string, AdminPlace[]>();
      index.set(place.level, byName);
    }
    const key = foldPlaceIdentity(place.name);
    const bucket = byName.get(key);
    if (bucket) bucket.push(place);
    else byName.set(key, [place]);
  }

  return index;
}

/**
 * **Ακριβής αντιστοίχιση ονόματος σε μία βαθμίδα.** Κενός πίνακας = κανένα ταίριασμα.
 *
 * Το πλήθος **δεν** φιλτράρεται εδώ: ο καλών πρέπει να δει «πέντε ομώνυμες» για να
 * αποφασίσει *αποσαφήνιση ή σιωπή* — ένα `?? null` εδώ θα έκρυβε τη διαφορά.
 */
export function exactNameMatches(
  index: AdminNameIndex,
  level: number,
  label: string,
): readonly AdminPlace[] {
  return index.get(level)?.get(foldPlaceIdentity(label)) ?? [];
}

/**
 * **Απόσταση Damerau-Levenshtein ≤ 1** — ένα πρόσθεση/διαγραφή/αντικατάσταση/μετάθεση.
 *
 * 🔑 Φραγμένος έλεγχος, **όχι** πίνακας δυναμικού προγραμματισμού: η ερώτηση είναι «≤1;»,
 * και η απάντηση βγαίνει σε **ένα** πέρασμα. Η πλήρης απόσταση θα ήταν υπολογισμός που
 * κανείς δεν ζήτησε — και θα καλούσε κάποιον να ανεβάσει το κατώφλι *(δες την
 * προειδοποίηση του `admin-identity`)*.
 *
 * ⚠️ **Και τα δύο ορίσματα οφείλουν να είναι ΗΔΗ διπλωμένα** *(`foldPlaceIdentity`)*.
 */
export function withinOneEdit(a: string, b: string): boolean {
  if (a === b) return true;
  const la = a.length;
  const lb = b.length;
  if (Math.abs(la - lb) > 1) return false;

  if (la === lb) return differsByOneOrTransposition(a, b, la);

  // Διαφορά μήκους 1 ⇒ μία παράλειψη: περπάτα μαζί, επιτρέπεται **ένα** πήδημα.
  const [short, long] = la < lb ? [a, b] : [b, a];
  let i = 0;
  let j = 0;
  let skipped = false;
  while (i < short.length && j < long.length) {
    if (short[i] === long[j]) {
      i += 1;
      j += 1;
      continue;
    }
    if (skipped) return false;
    skipped = true;
    j += 1;
  }
  return true;
}

/** Ίδιο μήκος: το πολύ **μία** διαφορά, ή **δύο γειτονικές** που είναι μετάθεση. */
function differsByOneOrTransposition(a: string, b: string, length: number): boolean {
  const differing: number[] = [];
  for (let i = 0; i < length; i += 1) {
    if (a[i] !== b[i]) {
      differing.push(i);
      if (differing.length > 2) return false;
    }
  }
  if (differing.length <= 1) return true;
  const [first, second] = differing;
  return second === first + 1 && a[first] === b[second] && a[second] === b[first];
}

/**
 * **Οντότητες της βαθμίδας σε απόσταση ≤1 από την ετικέτα, ΜΕΣΑ σε δεδομένη εμβέλεια.**
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 **Η ΕΜΒΕΛΕΙΑ ΕΙΝΑΙ ΥΠΟΧΡΕΩΤΙΚΗ, ΚΑΙ ΕΙΝΑΙ Ο ΜΟΝΟΣ ΦΡΟΥΡΟΣ ΠΟΥ ΔΟΥΛΕΥΕΙ.**
 *
 * Δοκίμασα ανοχή απόστασης 1 σε **πραγματικές** ετικέτες OSM, στο επίπεδο 8, **χωρίς**
 * εμβέλεια — με πύλη μοναδικότητας και φρουρό πρώτων χαρακτήρων:
 *
 * | ετικέτα | μοναδικό αποτέλεσμα |
 * |---|---|
 * | **Χαλάνδρι** *(προάστιο Αθήνας)* | «Χάλανδρα», **ΔΗΜΟΣ ΧΙΟΥ** |
 * | **Παγκράτι** | «Παγκράται», **ΔΗΜΟΣ ΣΟΥΛΙΟΥ** *(Θεσπρωτία)* |
 * | **Ιλίσια** | «Φιλίσια», **ΔΗΜΟΣ ΑΡΧΑΝΩΝ** *(Κρήτη)* |
 *
 * **Η μοναδικότητα ΔΕΝ είναι ορθότητα.** Για ετικέτα που **δεν υπάρχει** στο μητρώο —
 * κάθε συνοικία Αθήνας/Θεσσαλονίκης: Κολωνάκι · Εξάρχεια · Χαριλάου · Άνω Πόλη ·
 * Μεταξουργείο · Σεπόλια · Γουδή · Συκιές · Λαδάδικα, **μετρημένα όλα «απόν»** — η πύλη
 * μοναδικότητας είναι **ενεργά παραπλανητική**: δεν υπάρχει σωστή απάντηση για να
 * ανταγωνιστεί τη μία λάθος. Και **2.678 από 13.272** ονόματα *(**20,2%**)* είναι σε
 * αρχαΐζουσα μορφή *(«Χαλάνδριον», «Παγκράτιον»)*, οπότε η απόσταση 1 **δεν γεφυρώνει**
 * το `-ι → -ιον` αλλά **γεφυρώνει χαρούμενα σε άλλο νομό**.
 *
 * ⇒ Γι' αυτό το `within` είναι **όρισμα χωρίς προεπιλογή**: μια προεπιλογή «όλη η χώρα»
 * θα ήταν ακριβώς η μαντεψιά που αυτό το αρχείο υπάρχει για να αποκλείσει.
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * ⚠️ **Επιστρέφει ΟΛΕΣ τις ομάδες επίτηδες**, ώστε ο καλών να απαντά «δεν ξέρω» όταν
 * είναι παραπάνω από μία. Μια συνάρτηση που επέστρεφε «την καλύτερη» θα έκρυβε **ακριβώς**
 * την πληροφορία που κάνει την ανοχή ασφαλή.
 *
 * @param within Η εμβέλεια — **αποδεδειγμένη**, ποτέ υποτιθέμενη. Δες `admin-identity`.
 */
export function nearNameMatchesWithin(
  index: AdminNameIndex,
  level: number,
  label: string,
  within: (entity: AdminPlace) => boolean,
): readonly (readonly AdminPlace[])[] {
  return scopedMatches(index, level, label, within, withinOneEdit);
}

/**
 * **Η ΓΕΝΙΚΗ ΠΤΩΣΗ** — «Ελευθερίου Κορδελιού» ⇄ «Ελευθέριο Κορδελιό», **μέσα σε εμβέλεια**.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 **ΑΥΤΟ ΕΙΝΑΙ ΤΟ ΚΙΝΗΤΡΟ ΤΟΥ ΠΑΛΙΟΥ ΚΑΝΟΝΑ, ΚΡΑΤΗΜΕΝΟ.**
 *
 * Ο διαγραμμένος `makeNameMatcher` υπήρχε **γι' αυτό** και το έγραφε: το Nominatim δίνει
 * **γενική** ενώ το μητρώο κρατά **ονομαστική**, οπότε ούτε η υποσυμβολοσειρά ούτε η
 * απόσταση 1 γεφυρώνουν *(«ελευθεριου κορδελιου» ⇄ «ελευθεριο κορδελιο» = **δύο** αλλαγές)*.
 * Κοινό πρόθεμα **ανά λέξη** τα γεφυρώνει.
 *
 * 🔴 **Και ήταν επικίνδυνο μόνο επειδή έτρεχε ΣΕ ΟΛΗ ΤΗ ΧΩΡΑ**: μετρημένο, **8.786 από
 * 13.272** οικισμούς *(**66,2%**)* ζουν σε κουβά prefix-5 με **≥2** μέλη ⇒ χωρίς εμβέλεια μια
 * πύλη μοναδικότητας θα αρνιόταν τα δύο τρίτα και θα μάντευε στο υπόλοιπο. **Μέσα σε δήμο**
 * η αμφισημία πέφτει στο **6,1%**, και η πύλη μοναδικότητας αρκεί.
 *
 * ⚠️ **Το ίδιο πλήθος λέξεων, υποχρεωτικά** — αλλιώς το «Νέα Χώρα» ταιριάζει με το «Χώρα».
 * ⚠️ **Ελάχιστο μήκος λέξης 4**: κάτω από αυτό το «πρόθεμα 5» είναι ολόκληρη η λέξη.
 * ═════════════════════════════════════════════════════════════════════════════
 */
export function inflectedNameMatchesWithin(
  index: AdminNameIndex,
  level: number,
  label: string,
  within: (entity: AdminPlace) => boolean,
): readonly (readonly AdminPlace[])[] {
  return scopedMatches(index, level, label, within, sharesWordPrefixes);
}

/** Κοινό πρόθεμα **ανά λέξη**, με ίδιο πλήθος λέξεων. Και τα δύο ήδη διπλωμένα. */
function sharesWordPrefixes(a: string, b: string): boolean {
  const left = a.split(' ');
  const right = b.split(' ');
  if (left.length !== right.length) return false;

  return left.every((word, i) => {
    if (word.length < WORD_MIN_LENGTH || right[i].length < WORD_MIN_LENGTH) return word === right[i];
    const shared = Math.min(WORD_PREFIX_LENGTH, word.length, right[i].length);
    return word.slice(0, shared) === right[i].slice(0, shared);
  });
}

/** Πόσοι χαρακτήρες ανά λέξη θεωρούνται «ίδιο όνομα, άλλη πτώση». */
const WORD_PREFIX_LENGTH = 5;
/** Κάτω από αυτό, η σύγκριση γίνεται **ολόκληρη λέξη** — «Διου» δεν είναι πρόθεμα κανενός. */
const WORD_MIN_LENGTH = 4;

/** Ο κοινός σαρωτής: **μία** σάρωση της βαθμίδας, με το κριτήριο ως παράμετρο. */
function scopedMatches(
  index: AdminNameIndex,
  level: number,
  label: string,
  within: (entity: AdminPlace) => boolean,
  matches: (target: string, name: string) => boolean,
): readonly (readonly AdminPlace[])[] {
  const byName = index.get(level);
  if (!byName) return [];

  const target = foldPlaceIdentity(label);
  const groups: (readonly AdminPlace[])[] = [];

  byName.forEach((entities, name) => {
    if (name === target) return;
    if (!matches(target, name)) return;
    const scoped = entities.filter(within);
    if (scoped.length > 0) groups.push(scoped);
  });

  return groups;
}
