/**
 * @fileoverview **Η ΧΕΙΡΟΝΟΜΙΑ ΤΟΥ ΑΝΘΡΩΠΟΥ** — το μόνο πράγμα που ο πελάτης επιτρέπεται να πει.
 * @related ADR-777 · SPEC-777A §13.3 · §13.6 · §14.3 · §14.4 (κανόνας 2) · §21.4
 * @module lib/places/place-claim
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 Ο §14.4 ΚΑΝΟΝΑΣ 2 ΩΣ **ΤΥΠΟΣ**, ΟΧΙ ΩΣ ΕΛΕΓΧΟΣ ΠΟΥ ΚΑΠΟΙΟΣ ΘΥΜΑΤΑΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο κανόνας λέει: *«Γράφει **μόνο ο διακομιστής**, μετά από **επαλήθευση πηγής**.»*
 * Γραμμένος ως οδηγία, είναι κάτι που κάποιος θα παραλείψει. Εδώ γίνεται **σχήμα**:
 *
 * 🔑 **Ο πελάτης στέλνει ΧΕΙΡΟΝΟΜΙΕΣ, ποτέ ΣΥΜΠΕΡΑΣΜΑΤΑ.** Δεν υπάρχει τρόπος να
 * σταλεί `provenance` — **δεν είναι πεδίο**. Η προέλευση **συνάγεται** από το ποια
 * χειρονομία έγινε ({@link provenanceOfClaim}), και ο διακομιστής ξαναβγάζει μόνος του
 * ό,τι είναι **παράγωγο**: το σημείο ενός κτιρίου OSM το ρωτά από το Overpass, το
 * σημείο μιας διεύθυνσης το ρωτά από τον geocoder. Ένα «*σου λέω εγώ ότι αυτό το
 * σημείο είναι OSM*» **δεν εκφράζεται**.
 *
 * Είναι ο ίδιος κανόνας που το `addressToPositionCandidate` εφαρμόζει ήδη μία στάση
 * πιο κάτω (*«υπάρχει `accuracy` ⇒ **μηχανή** το συμπέρανε· δεν υπάρχει ⇒ κάποιος το
 * **έβαλε**»*) — εδώ ανεβαίνει στο **σύνορο του δικτύου**, όπου είναι και το μόνο
 * σημείο που μπορεί να επιβληθεί.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΤΕΣΣΕΡΙΣ ΧΕΙΡΟΝΟΜΙΕΣ, ΚΑΙ ΓΙΑΤΙ **ΟΧΙ** ΕΞΙ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η σκάλα του §21.4 έχει **έξι** σκαλοπάτια. Εδώ υπάρχουν **τέσσερα**, και η απουσία
 * των δύο είναι σχεδίαση — όχι έλλειψη:
 *
 * | Σκαλοπάτι | Χειρονομία | Γιατί (δεν) είναι εδώ |
 * |---|---|---|
 * | **1** γράφει διεύθυνση | `typed-address` | ✅ ο διακομιστής **γεωκωδικοποιεί** |
 * | **2** βάζει πινέζα | `dropped-pin` | ✅ το σημείο **είναι** η απάντηση |
 * | **3** ζωγραφίζει | `drew-outline` | ✅ §13.6 — η εναλλακτική για τα ελληνικά κενά |
 * | **4** διαλέγει κτίριο | `picked-osm-building` | ✅ ο διακομιστής **επαληθεύει** το στοιχείο |
 * | **5** ανεβάζει PDF | — | 🔴 *«έγγραφο ναι, **θέση όχι**»*: **δεν είναι χειρονομία θέσης** |
 * | **6** ανεβάζει DXF/`.tek` | — | δεν είναι χειρονομία **σε αυτή την οθόνη** — είναι αγωγός τοπογραφίας |
 *
 * 🔴 **Η απουσία του 5 είναι η Π1 του handoff, ως ΤΥΠΟΣ.** Το `document-only` παίρνει
 * τον **μεγαλύτερο** αριθμό στη σκάλα από το `osm`, και όποιος διαβάσει τον αριθμό ως
 * αξιοπιστία αφήνει **ανύπαρκτη** θέση να σβήσει **υπαρκτή** — για **όλους** τους
 * χρήστες ταυτόχρονα (§14.4). Εδώ δεν χρειάζεται κανείς να θυμηθεί τον κανόνα:
 * **δεν υπάρχει μέλος της ένωσης** που να το εκφράζει, άρα δεν υπάρχει τιμή να
 * περάσει στο `outranksForLocation`.
 *
 * **Layering**: leaf — τύποι + zod + καθαρές συναρτήσεις. Καμία εξάρτηση από
 * Firestore, React ή δίκτυο.
 */

import { z } from 'zod';

import type { LocationProvenance } from '@/lib/location/location-provenance';
import type { GeoOutline, GeoPoint } from '@/types/geo/coordinates';
import type { OsmElementType } from '@/types/geo/public-place';

// =============================================================================
// 1. ΤΙ ΔΕΙΧΝΕΙ Ο ΑΝΘΡΩΠΟΣ — γη ή κτίριο
// =============================================================================

/**
 * Σε **τι** αναφέρεται η χειρονομία.
 *
 * ⚠️ **Δεν συνάγεται από τη χειρονομία, και δεν πρέπει.** Ένα κλικ σε κτίριο OSM
 * *μοιάζει* να λέει «κτίριο», αλλά ένα σχεδιασμένο περίγραμμα μπορεί κάλλιστα να
 * είναι **οικόπεδο** — και το §13.x είναι ρητό ότι *«ζητώ οικόπεδο για αντιπαροχή σε
 * αυτό το τετράγωνο»* **δεν έχει κτίριο και δεν πρέπει να αναγκαστεί να επινοήσει
 * ένα»*. Η ερώτηση είναι **τομέα**, άρα τη λέει ο άνθρωπος.
 */
export const PLACE_TARGETS = ['land', 'building'] as const;
export type PlaceTarget = (typeof PLACE_TARGETS)[number];

// =============================================================================
// 2. Η ΧΕΙΡΟΝΟΜΙΑ — κλειστή ένωση
// =============================================================================

/** Τα ονόματα των χειρονομιών, ως κλειστό σύνολο (κάθε ένα γίνεται κλειδί i18n, N.11). */
export const PLACE_GESTURES = [
  'picked-osm-building',
  'dropped-pin',
  'drew-outline',
  'typed-address',
] as const;

export type PlaceGesture = (typeof PLACE_GESTURES)[number];

/**
 * **Ό,τι έκανε ο άνθρωπος** — και τίποτα παραπάνω.
 *
 * ⚠️ Ο διαχωριστής λέγεται `gesture` και όχι `kind`, επίτηδες: το `kind` περιγράφει
 * *τι είναι κάτι*, ενώ εδώ το ερώτημα είναι *τι έκανε κάποιος*. Το όνομα του πεδίου
 * είναι το μισό της τεκμηρίωσης αυτού του αρχείου.
 */
export type PlaceClaim =
  /** **Σκαλοπάτι 4** — διάλεξε κτίριο από τον χάρτη. Ο διακομιστής **το επαληθεύει**. */
  | {
      readonly gesture: 'picked-osm-building';
      readonly elementType: OsmElementType;
      /** Το OSM id ως **συμβολοσειρά** — ποτέ αριθμητική πάνω του (βλ. `OsmReference`). */
      readonly elementId: string;
    }
  /** **Σκαλοπάτι 2** — πινέζα με το δάχτυλο. */
  | { readonly gesture: 'dropped-pin'; readonly point: GeoPoint }
  /** **Σκαλοπάτι 3** — ζωγράφισε περίγραμμα (§13.6, η εναλλακτική στα κενά του OSM). */
  | { readonly gesture: 'drew-outline'; readonly outline: GeoOutline }
  /** **Σκαλοπάτι 1** — έγραψε διεύθυνση. Ο διακομιστής **γεωκωδικοποιεί**. */
  | { readonly gesture: 'typed-address'; readonly query: string };

// =============================================================================
// 3. Η ΠΡΟΕΛΕΥΣΗ — ΣΥΝΑΓΕΤΑΙ, ΠΟΤΕ ΔΕΝ ΣΤΕΛΝΕΤΑΙ
// =============================================================================

/**
 * Ποια προέλευση **γεννά** κάθε χειρονομία.
 *
 * `Record<PlaceGesture, …>` σκόπιμα: μια **νέα** χειρονομία σπάει τη μεταγλώττιση
 * **εδώ**, άρα δεν μπορεί να υπάρξει χειρονομία χωρίς δηλωμένη προέλευση — και η
 * προέλευση είναι αυτό που αποφασίζει **δικαίωμα εγγραφής** στο κοινό επίπεδο Α
 * (§14.3). Ίδιο ιδίωμα με το `LOCATION_PROVENANCE_RANK`.
 */
const PROVENANCE_OF_GESTURE: Readonly<Record<PlaceGesture, LocationProvenance>> = {
  'picked-osm-building': 'osm',
  'dropped-pin': 'manual',
  'drew-outline': 'drawn',
  'typed-address': 'geocoded',
};

/**
 * Η προέλευση που **γεννά** αυτή η χειρονομία.
 *
 * 🔑 Η ύπαρξη αυτής της συνάρτησης είναι ο λόγος που το `provenance` **δεν είναι
 * πεδίο** της {@link PlaceClaim}: η προέλευση είναι **συμπέρασμα του διακομιστή**, και
 * ένα πεδίο θα την έκανε **ισχυρισμό του πελάτη**.
 */
export function provenanceOfClaim(claim: PlaceClaim): LocationProvenance {
  return PROVENANCE_OF_GESTURE[claim.gesture];
}

// =============================================================================
// 4. ΤΟ ΣΥΝΟΡΟ ΤΟΥ ΔΙΚΤΥΟΥ — `unknown` → χειρονομία
// =============================================================================

/** Σημείο WGS84, ως σχήμα. Τα **όρια** τα κρίνει η επικύρωση, όχι το σχήμα. */
const geoPointSchema = z.object({
  lat: z.number().finite(),
  lng: z.number().finite(),
});

/**
 * Το OSM id ως **θετικός ακέραιος σε συμβολοσειρά**.
 *
 * ⚠️ Δεν γίνεται `z.number()`: τα OSM id ξεπερνούν ήδη το `2^31` και πλησιάζουν όρια
 * όπου η αναπαράσταση κινδυνεύει. Ο τύπος `OsmReference` το λέει κατά λέξη —
 * *«δεν κάνουμε ποτέ αριθμητική πάνω του»*.
 */
const osmElementIdSchema = z.string().regex(/^[1-9]\d{0,18}$/);

/**
 * Το σχήμα της χειρονομίας.
 *
 * ⚠️ `discriminatedUnion` και όχι `union` — ίδιος λόγος με το
 * `owner-property-draft-schema.ts`: το πρώτο διαλέγει κλάδο **από τον διαχωριστή** και
 * αναφέρει σφάλμα **του σωστού** κλάδου· το δεύτερο αναφέρει τέσσερα άσχετα σφάλματα
 * για ένα πεδίο. Η διαφορά φαίνεται μόνο όταν κάτι σπάσει.
 */
export const placeClaimSchema = z.discriminatedUnion('gesture', [
  z.object({
    gesture: z.literal('picked-osm-building'),
    elementType: z.enum(['node', 'way', 'relation']),
    elementId: osmElementIdSchema,
  }),
  z.object({
    gesture: z.literal('dropped-pin'),
    point: geoPointSchema,
  }),
  z.object({
    gesture: z.literal('drew-outline'),
    outline: z.array(geoPointSchema),
  }),
  z.object({
    gesture: z.literal('typed-address'),
    query: z.string(),
  }),
]);

/** Το πλήρες αίτημα εντοπισμού: **τι έκανε** ο άνθρωπος και **σε τι** αναφέρεται. */
export const placeResolveRequestSchema = z.object({
  claim: placeClaimSchema,
  target: z.enum(PLACE_TARGETS),
});

export interface PlaceResolveRequest {
  readonly claim: PlaceClaim;
  readonly target: PlaceTarget;
}

/**
 * `unknown` από το δίκτυο → αίτημα, ή **τα μονοπάτια που δεν διαβάστηκαν**.
 *
 * Ίδιο ιδίωμα με το `ownerPropertyDraftFromRequest`: ποτέ εξαίρεση ως ροή ελέγχου, και
 * τα μονοπάτια ταξιδεύουν ώστε η οθόνη να δείξει **ποιο** πεδίο.
 */
export function placeResolveRequestFrom(
  body: unknown,
): { readonly ok: true; readonly request: PlaceResolveRequest }
  | { readonly ok: false; readonly malformed: readonly string[] } {
  const parsed = placeResolveRequestSchema.safeParse(body);
  if (parsed.success) {
    return { ok: true, request: parsed.data as PlaceResolveRequest };
  }
  return {
    ok: false,
    malformed: parsed.error.issues.map((issue) => issue.path.join('.') || 'body'),
  };
}
