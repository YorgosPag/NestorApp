/**
 * @fileoverview **ΕΙΝΑΙ ΑΥΤΗ Η ΧΕΙΡΟΝΟΜΙΑ ΣΧΗΜΑ;** — η δομική μισή της επαλήθευσης πηγής.
 * @related ADR-777 · SPEC-777A §14.4 (κανόνας 2) · lib/places/place-claim.ts
 * @module lib/places/place-claim-validation
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΔΥΟ ΜΙΣΑ ΤΗΣ «ΕΠΑΛΗΘΕΥΣΗΣ ΠΗΓΗΣ», ΚΑΙ **ΠΟΤΕ** ΕΝΑ ΜΕ «Ή»
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο §14.4 κανόνας 2 ζητά *«επαλήθευση πηγής»*. Η επαλήθευση έχει **δύο ανεξάρτητα**
 * σκέλη, και η συγχώνευσή τους θα άφηνε τρύπα:
 *
 * | Σκέλος | Ερώτημα | Πού ζει |
 * |---|---|---|
 * | **δομικό** | *«είναι αυτό **σχήμα**;»* | **εδώ** — καθαρό, χωρίς δίκτυο |
 * | **πραγματολογικό** | *«υπάρχει αυτό το κτίριο **στ' αλήθεια**;»* | `lib/geo/osm/**` — ρωτά το Overpass |
 *
 * 🔑 **Το δομικό δεν είναι «άμυνα εισόδου» — είναι ΚΡΙΣΗ ΓΙΑ ΤΟ ΚΟΙΝΟ ΕΠΙΠΕΔΟ.** Το
 * §14.4 ανοίγει με τη διαφορά που τα αλλάζει όλα: *«Μέχρι σήμερα ένα λάθος έγραφε σε
 * **έναν** πελάτη. Το επίπεδο Α το βλέπουν **ΟΛΟΙ**.»* Ένας αυτοτεμνόμενος δακτύλιος
 * δεν είναι κακή είσοδος ενός χρήστη — είναι σχήμα που θα **λέει ψέματα** στο
 * `outside-area` **κάθε** ζήτησης που θα το συναντήσει.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ΤΟ ΣΥΝΟΡΟ ΤΗΣ ΠΕΡΙΟΧΗΣ ΕΙΝΑΙ **ΡΥΘΜΙΣΗ**, ΟΧΙ ΣΚΛΗΡΟΣ ΑΡΙΘΜΟΣ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `COUNTRY_BOUNDING_BOX` του `geographic-config.ts` οδηγείται από
 * `NEXT_PUBLIC_COUNTRY_BBOX_*`. Άρα η απάντηση στο *«σε ποια χώρα δουλεύουμε;»*
 * αλλάζει με **ρύθμιση**, όχι με έκδοση — και το ADR-777 είναι ρητά ελληνικό προϊόν
 * (αντιπαροχή · Ν. 4495/2017 · ΤΕΕ · «τα ελληνικά κενά του OSM» του §13.6).
 *
 * ⚠️ **Δεν υπάρχει ανώτατο όριο μεγέθους δακτυλίου, και είναι απόφαση.** Ένα «μέγιστο
 * εμβαδόν οικοπέδου» θα ήταν αριθμός που **κανείς δεν αποφάσισε** — και η ελληνική
 * αγροτική γη τον θα παραβίαζε νόμιμα. Το μόνο όριο που **προκύπτει από κάτι** είναι
 * η ίδια η περιοχή εξυπηρέτησης, και αυτό επιβάλλεται ήδη κορυφή-κορυφή.
 *
 * **Layering**: leaf — καθαρές συναρτήσεις. Καμία εξάρτηση από δίκτυο ή Firestore.
 */

import { GEOGRAPHIC_CONFIG } from '@/config/geographic-config';
import { geoOutlineAreaSqm, isSimpleGeoOutline } from '@/lib/geo/geo-ring';
import type { GeoOutline, GeoPoint } from '@/types/geo/coordinates';
import type { PlaceClaim } from './place-claim';

// =============================================================================
// 1. ΤΑ ΕΛΑΤΤΩΜΑΤΑ — κλειστό σύνολο, κάθε ένα κλειδί i18n (N.11)
// =============================================================================

/**
 * Γιατί αυτή η χειρονομία **δεν είναι σχήμα**.
 *
 * ⚠️ **Κλειστό σύνολο και κανένα «invalid».** Ένας γενικός κωδικός θα έστελνε τον
 * άνθρωπο να μαντέψει τι φταίει — και εδώ φταίει κάτι **συγκεκριμένο** που μπορεί να
 * ειπωθεί: *«το σχήμα τέμνει τον εαυτό του»* είναι οδηγία, *«άκυρη είσοδος»* όχι.
 */
export const PLACE_CLAIM_DEFECTS = [
  /** Συντεταγμένες που δεν υπάρχουν πάνω σε σφαίρα. */
  'point-off-earth',
  /** Έγκυρο σημείο, **εκτός** της περιοχής που εξυπηρετούμε. */
  'point-outside-served-area',
  /** Λιγότερες από 3 κορυφές — δεν περικλείουν τίποτα. */
  'outline-too-few-vertices',
  /** Κορυφή του δακτυλίου εκτός της περιοχής που εξυπηρετούμε. */
  'outline-outside-served-area',
  /** Εμβαδόν πρακτικά μηδέν: συνευθειακές κορυφές ή διπλό κλικ στο ίδιο σημείο. */
  'outline-degenerate',
  /** «Παπιγιόν» — ο δακτύλιος τέμνει τον εαυτό του, άρα το «μέσα» είναι διφορούμενο. */
  'outline-self-intersecting',
  /** Κενό κείμενο αναζήτησης. */
  'query-empty',
] as const;

export type PlaceClaimDefect = (typeof PLACE_CLAIM_DEFECTS)[number];

/**
 * **10 m²** — το κατώφλι κάτω από το οποίο ένας δακτύλιος δεν είναι σχήμα αλλά αστοχία
 * χειρονομίας.
 *
 * Δεν είναι αυθαίρετο: το μικρότερο πράγμα που το επίπεδο Α μοντελοποιεί είναι
 * **κτίριο ή οικόπεδο**, και δεν υπάρχει τέτοιο κάτω από ~10 m² (ένα περίπτερο είναι
 * ήδη μεγαλύτερο). Ό,τι πέφτει από κάτω προέκυψε από **διπλό κλικ** ή από τρεις
 * σχεδόν συνευθειακές κορυφές.
 *
 * ⚠️ **Είναι κατώφλι «δεν είναι σχήμα», ΟΧΙ κατώφλι «είναι μικρό».** Δεν υπάρχει
 * αντίστοιχο άνω όριο — δες την επικεφαλίδα.
 */
export const MIN_OUTLINE_AREA_SQM = 10;

// =============================================================================
// 2. ΣΗΜΕΙΟ
// =============================================================================

/** Υπάρχει αυτό το σημείο πάνω σε σφαίρα; */
function isOnEarth(point: GeoPoint): boolean {
  return (
    Number.isFinite(point.lat) &&
    Number.isFinite(point.lng) &&
    point.lat >= -90 &&
    point.lat <= 90 &&
    point.lng >= -180 &&
    point.lng <= 180
  );
}

/** Είναι μέσα στην περιοχή που εξυπηρετούμε (ρύθμιση, όχι σκληρός αριθμός); */
export function isWithinServedArea(point: GeoPoint): boolean {
  const box = GEOGRAPHIC_CONFIG.COUNTRY_BOUNDING_BOX;
  return (
    point.lat >= box.minLat &&
    point.lat <= box.maxLat &&
    point.lng >= box.minLng &&
    point.lng <= box.maxLng
  );
}

function pointDefect(point: GeoPoint): PlaceClaimDefect | null {
  if (!isOnEarth(point)) return 'point-off-earth';
  if (!isWithinServedArea(point)) return 'point-outside-served-area';
  return null;
}

// =============================================================================
// 3. ΔΑΚΤΥΛΙΟΣ
// =============================================================================

/**
 * ⚠️ **Η ΣΕΙΡΑ ΕΙΝΑΙ ΣΥΜΒΟΛΑΙΟ**, με τον ίδιο τρόπο που είναι στο `demandAnswerShape`
 * και στην ταξινόμηση του CHECK 3.47:
 *
 * 1. **Πλήθος κορυφών** πρώτα — με δύο σημεία, «εμβαδόν» και «αυτοτομή» δεν έχουν
 *    καν νόημα ως ερωτήσεις.
 * 2. **Συντεταγμένες** μετά — μια κορυφή στον Ατλαντικό κάνει το εμβαδόν τεράστιο και
 *    θα ανέφερε «εκφυλισμένο: όχι», δηλαδή **σωστή απάντηση σε λάθος ερώτηση**.
 * 3. **Εκφυλισμός** πριν την **αυτοτομή**: ένας δακτύλιος μηδενικού εμβαδού είναι
 *    συνευθειακός, και οι συνευθειακές κορυφές δεν τέμνονται **γνησίως** ⇒ ο έλεγχος
 *    αυτοτομής θα τον έλεγε «απλό» και το ελάττωμα θα διέφευγε.
 */
function outlineDefect(outline: GeoOutline): PlaceClaimDefect | null {
  if (outline.length < 3) return 'outline-too-few-vertices';

  for (const vertex of outline) {
    if (!isOnEarth(vertex)) return 'point-off-earth';
    if (!isWithinServedArea(vertex)) return 'outline-outside-served-area';
  }

  if (geoOutlineAreaSqm(outline) < MIN_OUTLINE_AREA_SQM) return 'outline-degenerate';
  if (!isSimpleGeoOutline(outline)) return 'outline-self-intersecting';

  return null;
}

// =============================================================================
// 4. Η ΚΡΙΣΗ
// =============================================================================

/**
 * Το **δομικό** ελάττωμα αυτής της χειρονομίας, ή `null` αν είναι σχήμα.
 *
 * ⚠️ **Επιστρέφει ΤΟ ΠΡΩΤΟ ελάττωμα, όχι λίστα** — και η διαφορά με το
 * `ownerPropertyInvariantViolations` (που επιστρέφει **όλα**) είναι σκόπιμη: εκεί ο
 * άνθρωπος συμπληρώνει **φόρμα με πολλά πεδία** και θέλει να τα δει όλα μαζί· εδώ
 * έκανε **μία** χειρονομία, και μια λίστα με τρεις λόγους για ένα κλικ είναι θόρυβος.
 *
 * ⚠️ **Καμία περίπτωση `default`** — μια πέμπτη χειρονομία **δεν μεταγλωττίζεται**
 * μέχρι κάποιος να αποφασίσει τι σημαίνει «σχήμα» για εκείνη.
 */
export function placeClaimDefect(claim: PlaceClaim): PlaceClaimDefect | null {
  switch (claim.gesture) {
    case 'picked-osm-building':
      // 🔑 **Καμία δομική κρίση εδώ, και δεν είναι παράλειψη.** Το σχήμα του id το
      // έκρινε ήδη το zod· το **αν υπάρχει** και **αν είναι κτίριο** δεν είναι
      // δομικό ερώτημα — το απαντά το Overpass, στο πραγματολογικό μισό. Ένας
      // ψεύτικος έλεγχος εδώ θα έδινε την **εντύπωση** επαλήθευσης.
      return null;

    case 'dropped-pin':
      return pointDefect(claim.point);

    case 'drew-outline':
      return outlineDefect(claim.outline);

    case 'typed-address':
      return claim.query.trim() === '' ? 'query-empty' : null;
  }
}
