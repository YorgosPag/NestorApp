/**
 * =============================================================================
 * ADR-841 §7 Α18.9 — **ΚΑΘΕ ΚΑΤΟΧΗ ΕΧΕΙ ΠΟΡΤΑ, ΚΑΙ ΔΕΝ ΕΙΝΑΙ Η ΙΔΙΑ**
 * =============================================================================
 *
 * Το ερώτημα: *«ο άνθρωπος που **κατέχει** αυτό το ακίνητο — πού τον στέλνουμε;»*
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ — Η ΨΕΥΤΙΚΗ ΠΟΡΤΑ ΗΤΑΝ **ΜΙΑ ΓΡΑΜΜΗ**, ΚΑΙ ΚΑΝΕΙΣ ΔΕΝ ΡΩΤΟΥΣΕ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ο ειδοποιητής ζήτησης σαρώνει **δύο** συλλογές και έγραφε
 * `offerDetailHref(propertyId)` **για τις δύο**. Μετρημένο ζωντανά, κλειστά, σε
 * **12** έγγραφα (ADR-841 §7 Α18.8): τα **6** `ownp_*` άνοιγαν· τα **6** `prop_*`
 * κατέληγαν σε *«Αυτό το ακίνητο δεν υπάρχει — ή δεν είναι δικό σου»*.
 *
 * 🔑 **ΚΑΙ Η ΥΠΑΡΧΟΥΣΑ ΑΓΚΥΡΑ ΗΤΑΝ ΠΡΑΣΙΝΗ ΠΑΝΩ ΣΤΟ ΕΛΑΤΤΩΜΑ, ΣΩΣΤΑ.** Η
 * `notification-destination-custody` ρωτά *«υπάρχει προορισμός;»* — και **υπήρχε**.
 * Το ερώτημα που έλειπε είναι *«είναι **ο σωστός** για **αυτόν** τον παραλήπτη;»*,
 * και δεν είναι το ίδιο ερώτημα. Δύο φρουροί, δύο ερωτήσεις.
 *
 * ⚠️ **Η άγκυρα ζει δίπλα στη ΣΥΝΑΡΤΗΣΗ, όχι στον ειδοποιητή**: το ερώτημα «ποια
 * πόρτα ανοίγει αυτή η κατοχή;» θα το ξαναρωτήσει ο **επόμενος** παραγωγός.
 */

import { placeDetailHref } from '@/lib/places/place-detail-route';
import { PLACE_SOURCES } from '@/services/demand/place-interest.service';

const PLACE_ID = 'prop_a0000003-7777-4aaa-8aaa-000000000003';

describe('ADR-841 §7 Α18.9 — η πόρτα ακολουθεί την κατοχή', () => {
  // ==========================================================================
  // Π0 — Ο ΠΑΡΟΝΟΜΑΣΤΗΣ
  // ==========================================================================

  /**
   * 🔴 **ΤΟ `0` ΣΗΜΑΙΝΕΙ «ΚΑΝΕΙΣ ΔΕΝ ΚΟΙΤΑΞΕ», ΟΧΙ «ΚΑΘΑΡΟ».** Χωρίς αυτή τη
   * γραμμή, ένα άδειο λεξιλόγιο θα έκανε τα Π1-Π3 **μονίμως πράσινα** χωρίς να
   * εκτελεστεί ούτε μία διαδρομή — το ακριβές σχήμα που το `CLAUDE.md`
   * καταγγέλλει στα CHECK 3.18 / 3.28.
   */
  it('Π0 🔴 — το λεξιλόγιο κατοχής ΔΕΝ είναι κενό, και ΚΑΘΕ μέλος του απαντά', () => {
    expect(PLACE_SOURCES.length).toBeGreaterThanOrEqual(2);

    for (const source of PLACE_SOURCES) {
      const href = placeDetailHref(source, PLACE_ID);
      expect(typeof href).toBe('string');
      expect(href.startsWith('/')).toBe(true);
      expect(href).toContain(PLACE_ID);
    }
  });

  // ==========================================================================
  // Π1 — ΔΥΟ ΚΑΤΟΧΕΣ, ΔΥΟ ΠΟΡΤΕΣ
  // ==========================================================================

  it('Π1 — κάθε κατοχή έχει ΔΙΚΗ ΤΗΣ πόρτα, μετρημένο από το ίδιο το λεξιλόγιο', () => {
    // ⚠️ Το πλήθος **δεν** γράφεται εδώ: παράγεται από το `PLACE_SOURCES`. Μια
    //    τρίτη κατοχή που θα κληρονομούσε σιωπηλά πόρτα υπάρχουσας **κοκκινίζει**.
    const doors = new Set(PLACE_SOURCES.map((source) => placeDetailHref(source, PLACE_ID)));

    expect(doors.size).toBe(PLACE_SOURCES.length);
  });

  it('Π1α — ο ιδιώτης πάει στην ΔΙΚΗ ΤΟΥ καταχώρηση', () => {
    expect(placeDetailHref('owner-property', 'ownp_42')).toBe('/offers/ownp_42');
  });

  it('Π1β — το γραφείο πάει στην ΚΑΡΤΕΛΑ ΤΟΥ ΓΡΑΦΕΙΟΥ', () => {
    // 🔑 Και **χωρίς** πρόθεμα χώρου: το δίχτυ `(app)/[...unprefixed]` το λύνει
    //    στον διακομιστή, με κριμένη ταυτότητα (ADR-787 §5.3 θ). Ένα cron δεν έχει
    //    τρέχουσα διεύθυνση, άρα ένα ψευδώνυμο εδώ θα ήταν **μαντεψιά**.
    expect(placeDetailHref('company-property', 'prop_7')).toBe('/properties/prop_7');
    expect(placeDetailHref('company-property', 'prop_7')).not.toContain('/o/');
  });

  // ==========================================================================
  // Π2 — Η ΤΑΥΤΟΤΗΤΑ ΕΡΧΕΤΑΙ ΑΠΟ ΔΕΔΟΜΕΝΑ
  // ==========================================================================

  it('Π2 — κωδικοποίηση σε ΚΑΘΕ κατοχή, όχι μόνο σε αυτήν που θυμήθηκε κάποιος', () => {
    // Μια ταυτότητα με `#` κόβει τη διεύθυνση **σε ένα μόνο έγγραφο** — το
    // χειρότερο είδος σφάλματος, γιατί τα υπόλοιπα δουλεύουν και μοιάζει με
    // «δεν υπάρχει».
    for (const source of PLACE_SOURCES) {
      expect(placeDetailHref(source, 'a#b')).toContain('a%23b');
      expect(placeDetailHref(source, 'a#b')).not.toContain('a#b');
    }
  });

  // ==========================================================================
  // Π3 — Η ΨΕΥΤΙΚΗ ΠΟΡΤΑ, ΓΡΑΜΜΕΝΗ ΩΣ ΑΡΝΗΣΗ
  // ==========================================================================

  /**
   * 🔴 **ΑΥΤΗ ΕΙΝΑΙ Η ΓΡΑΜΜΗ ΠΟΥ ΘΑ ΕΙΧΕ ΠΙΑΣΕΙ ΤΟ ΕΛΑΤΤΩΜΑ.** Το `/offers` είναι
   * ο κατάλογος **του ανθρώπου**: ο κανόνας Firestore δίνει `read` στον
   * `authorUserId` της καταχώρησης, και μια αγγελία γραφείου **δεν έχει** τέτοιον.
   * Το ελάττωμα δεν ήταν «λάθος συμβολοσειρά» — ήταν **σωστή συμβολοσειρά για
   * λάθος άνθρωπο**.
   */
  it('Π3 🔴 — η κατοχή γραφείου ΔΕΝ οδηγεί ΠΟΤΕ στον κατάλογο του ιδιώτη', () => {
    expect(placeDetailHref('company-property', PLACE_ID)).not.toMatch(/^\/offers\//);
  });
});
