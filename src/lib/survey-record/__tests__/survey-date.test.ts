/**
 * @fileoverview «ΙΟΥΛΙΟΣ 2026» ΔΕΝ είναι ημερομηνία (ADR-759 Φ3γ).
 *
 * 🔴 Η κρίσιμη ιδιότητα αυτού του αναλυτή **δεν είναι τι αναγνωρίζει — είναι τι ΑΡΝΕΙΤΑΙ**.
 * Ένας αναλυτής που «βοηθά» γεμίζοντας την 1η του μήνα παράγει ημερομηνία που δεν έγραψε
 * κανείς, μέσα σε πεδίο που τεκμηριώνεται ως *πότε συντάχθηκε το τοπογραφικό* — δηλαδή ψέμα
 * με σωστή μορφή, στο ακριβές σχήμα του ADR-745 §8.1.
 */

/* global describe, it, expect */
import { parseSurveyDate } from '../survey-date';

describe('🔴 μερική ακρίβεια ΔΕΝ γίνεται ημερομηνία', () => {
  it('«ΙΟΥΛΙΟΣ 2026» — το πραγματικό κείμενο του G753 — δίνει μήνα, ΟΧΙ ISO', () => {
    const parsed = parseSurveyDate('ΙΟΥΛΙΟΣ 2026');
    expect(parsed.precision).toBe('month');
    expect(parsed.year).toBe(2026);
    // 🔴 Το φέρον σκέλος: **καμία** εφευρημένη ημέρα.
    expect(parsed.iso).toBeNull();
  });

  it('σκέτο έτος δίνει έτος, όχι 1η Ιανουαρίου', () => {
    expect(parseSurveyDate('2026')).toEqual({ iso: null, precision: 'year', year: 2026 });
  });

  it('κείμενο χωρίς ημερομηνία δεν εικάζει τίποτα', () => {
    for (const text of ['', '   ', 'ΤΟΠΟΓΡΑΦΙΚΟ ΔΙΑΓΡΑΜΜΑ', 'Τ1']) {
      expect(parseSurveyDate(text)).toEqual({ iso: null, precision: 'none', year: null });
    }
  });
});

describe('πλήρης ημερομηνία — και μόνο τότε ISO', () => {
  it('🔑 «Θεσσαλονίκη 30/7/2026»: το κείμενο του ΣΩΜΑΤΟΣ που η πινακίδα δεν έχει (§2β.6)', () => {
    // Αυτή είναι ολόκληρη η αξία του Άξονα Α σε μία γραμμή: η **ίδια** συνάρτηση, χωρίς καμία
    // αλλαγή, αναβαθμίζει το «ΙΟΥΛΙΟΣ 2026» σε ακριβή ημερομηνία μόλις διαβαστεί το σώμα.
    expect(parseSurveyDate('Θεσσαλονίκη 30/7/2026').iso).toBe('2026-07-30');
  });

  it('δέχεται τους διαχωριστές που εμφανίζονται σε ελληνικά έγγραφα', () => {
    expect(parseSurveyDate('30-07-2026').iso).toBe('2026-07-30');
    expect(parseSurveyDate('30.7.2026').iso).toBe('2026-07-30');
  });

  it('🔴 το ISO διαβάζεται ΩΣ ISO — όχι ως «ημέρα 20, μήνας 26»', () => {
    // Η σειρά των μορφών στον αναλυτή είναι ο αλγόριθμος: αν το DMY δοκιμαζόταν πρώτο, το
    // `2026-07-30` θα έδινε **έγκυρη ημερομηνία σε λάθος χρονιά** — που κανείς δεν θα έβλεπε.
    expect(parseSurveyDate('2026-07-30').iso).toBe('2026-07-30');
  });

  it('λεκτικός μήνας με ημέρα, σε γενική και ονομαστική, με ή χωρίς τόνους', () => {
    expect(parseSurveyDate('30 Ιουλίου 2026').iso).toBe('2026-07-30');
    expect(parseSurveyDate('30 ΙΟΥΛΙΟΣ 2026').iso).toBe('2026-07-30');
    expect(parseSurveyDate('1 Μαΐου 2019').iso).toBe('2019-05-01');
  });
});

describe('🔴 ημερολογιακά αδύνατες τιμές δεν «διορθώνονται» σιωπηλά', () => {
  it('31 Φεβρουαρίου ΔΕΝ γίνεται 3 Μαρτίου', () => {
    // Το `new Date(2026, 1, 31)` κυλά στον επόμενο μήνα χωρίς να παραπονεθεί. Μια τέτοια
    // «διόρθωση» θα άλλαζε τον **μήνα** της μελέτης χωρίς κανένα ίχνος.
    expect(parseSurveyDate('31/2/2026').iso).toBeNull();
  });

  it('άκυρη ημέρα με έγκυρο λεκτικό μήνα ΥΠΟΒΑΘΜΙΖΕΤΑΙ σε μήνα, δεν πετιέται', () => {
    // Ο μήνας και το έτος διαβάστηκαν σωστά· μόνο η ημέρα δεν στέκει. Πετώντας τα όλα θα
    // χανόταν πληροφορία που **υπάρχει** — ο §8 κανόνας 3 ανάποδα.
    const parsed = parseSurveyDate('32 Ιουλίου 2026');
    expect(parsed.precision).toBe('month');
    expect(parsed.year).toBe(2026);
    expect(parsed.iso).toBeNull();
  });

  it('έτος εκτός ζώνης δεν γίνεται δεκτό', () => {
    expect(parseSurveyDate('30/7/3025').precision).toBe('none');
    expect(parseSurveyDate('30/7/1800').precision).toBe('none');
  });

  it('🔑 το κάτω όριο ΔΕΝ κόβει πραγματικά δεδομένα του δείγματος', () => {
    // Το G753 φέρει ΦΕΚ του 1992 και συμβόλαιο του 1993. Ένα «σύγχρονο» κατώφλι θα τα έκοβε.
    expect(parseSurveyDate('25-09-1992').iso).toBe('1992-09-25');
    expect(parseSurveyDate('18-01-1993').iso).toBe('1993-01-18');
  });
});
