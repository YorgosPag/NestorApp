/**
 * @related ADR-759 Φ3γ — **πώς ονομάζεται** ένα τοπογραφικό για τον άνθρωπο
 *
 * 🔑 SSoT με **δύο** καταναλωτές, γι' αυτό δεν ζει σε κανέναν από τους δύο: η καρτέλα το
 * χρησιμοποιεί για τη λίστα εγγραφών, και η παλέτα σύνδεσης για να πει **πού** θα γραφτούν
 * οι δηλώσεις του τοπογράφου. Δύο ιδιωτικές υλοποιήσεις θα αποκλίνανε — και η απόκλιση εδώ
 * είναι από τις χειρότερες: ο μηχανικός θα διάβαζε στην παλέτα ένα όνομα και θα έψαχνε άλλο
 * στην καρτέλα, για την **ίδια** εγγραφή.
 *
 * Καθαρό, χωρίς `t()`: το αποτέλεσμα είναι **δεδομένο του εγγράφου** (ημερομηνία, όνομα
 * αρχείου), όχι κείμενο διεπαφής. Ο καλών το τυλίγει στο δικό του `card.recordLabel`.
 */
import type { SurveyRecord } from '@/types/project-survey-record';

/**
 * Το πιο **αναγνωρίσιμο** πράγμα που ξέρουμε για την εγγραφή, με αυστηρή σειρά προτίμησης —
 * ή `null` όταν το έγγραφο δεν λέει ακόμη τίποτα αναγνωρίσιμο.
 *
 * ⚠️ Το `rawText` προηγείται της αναλυμένης τιμής **επίτηδες**. Είναι αντίθετο από το
 * ένστικτο, και είναι σωστό: αν το σχέδιο έγραφε «ΙΟΥΛΙΟΣ 2026», αυτό είναι που ο μηχανικός
 * έχει δει με τα μάτια του στην πινακίδα — ένα «2026-07-01» θα ήταν και **εφευρημένο** και
 * αγνώριστο. Όταν η ανάλυση πέτυχε, τα δύο συμφωνούν έτσι κι αλλιώς.
 *
 * 🔴 **Επέστρεφε `'—'` και αυτό ήταν λάθος στρώματος** (ADR-759 Φ4β). Καθαρό αρχείο χωρίς
 * `t()` δεν έχει δικαίωμα να επιλέξει τι διαβάζει ο άνθρωπος — και η παύλα ήταν **ακριβώς η
 * κατάσταση κάθε νέας καρτέλας**, όπου η παλέτα έγραφε «οι δηλώσεις του τοπογράφου γράφονται
 * στο: —». Το `null` είναι **κατάσταση**, ίδιο δόγμα με το `Sourced.value`, και το ντύνει
 * **μία** φράση στο `config/survey-record-labels.ts` — η ίδια και στις δύο οθόνες.
 *
 * ⚠️ Καμία υποχώρηση σε `createdAt`: εκείνο είναι *πότε το πληκτρολογήσαμε*, όχι *πότε
 * συντάχθηκε το τοπογραφικό*. Δες το σκεπτικό στο `survey-record-labels.ts`.
 */
export function surveyRecordLabel(record: SurveyRecord): string | null {
  const raw = record.surveyDate.rawText?.trim();
  if (raw) return raw;
  if (record.surveyDate.value) return record.surveyDate.value;
  if (record.sourceFileName) return record.sourceFileName;
  return null;
}
