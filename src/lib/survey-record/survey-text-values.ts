/**
 * @related ADR-759 Φ4 — κείμενο σχεδίου → **τιμή** πεδίου τοπογραφικού.
 *
 * Δύο ερωτήματα, και τα δύο απαντιούνται **μία** φορά για όλους τους αναγνώστες:
 * *«τι κρατάω από αυτό το κείμενο;»* και *«πού τελειώνει το ένα μέλος και αρχίζει το επόμενο;»*.
 *
 * ## 🔴 Γιατί εδώ γίνεται η αναδίπλωση ομόγλυφων και ΟΧΙ στον αναγνώστη
 *
 * Το πραγματικό σχέδιο γράφει «κατά **N**ΟΚ» με **λατινικό N** και «**E**ΜΒΑΔΟΝ» με λατινικό E
 * (μετρημένο στο `G753_ergasia F.dxf`, ίδια παγίδα με το «ΣΥΝΤΑΞ**H**» της πινακίδας). Αν
 * αποθηκευτεί έτσι, το πεδίο **δεν βρίσκεται ποτέ σε αναζήτηση** και δεν συγκρίνεται με τίποτα.
 *
 * ⚠️ Ο **αναγνώστης** δεν επιτρέπεται να το «διορθώσει»: ό,τι επιστρέφει εκείνος γίνεται
 * `rawText`, και το `rawText` είναι το **πρωτότυπο** — η μόνη απόδειξη του τι έλεγε το σχέδιο
 * (ADR-745 §8 κανόνας 3). Η αναδίπλωση ανήκει στην **τιμή**: `value` καθαρό, `rawText` άθικτο.
 *
 * @module lib/survey-record/survey-text-values
 */

import { normalizeGreekHomoglyphs } from '@/utils/greek-text';

/**
 * Κείμενο σχεδίου → τιμή κειμένου, ή `null` όταν δεν υπάρχει τίποτα.
 *
 * `null` σημαίνει «**δεν αναλύθηκε**», όχι «κενό»: το `Sourced` κρατά τότε το `rawText`
 * ακέραιο και η καρτέλα δείχνει τι έλεγε το σχέδιο.
 */
export function parseSurveyText(rawText: string): string | null {
  const value = normalizeGreekHomoglyphs(rawText).replace(/\s+/g, ' ').trim();
  return value.length > 0 ? value : null;
}

/**
 * Διαχωριστικά μελών λίστας, **όπως τα γράφει το σχέδιο**.
 *
 * Μετρημένα και τα τρία στο G753: `Α,Β,Γ,Δ,Α` (κόμμα) · `012431 & 012432` (και εμπορικό) ·
 * `Πολεοδομικών Ενοτήτων 16 **και** 17` (η λέξη).
 */
const LIST_SEPARATOR = /\s*[,&]\s*|\s+και\s+/;

/**
 * Κείμενο σχεδίου → μέλη λίστας.
 *
 * ⚠️ **Τα διπλά μέλη ΔΕΝ αφαιρούνται.** Το `Α,Β,Γ,Δ,Α` είναι **κλειστό** περίγραμμα: η
 * τελευταία κορυφή είναι η πρώτη, και το να «καθαριστεί» σε τέσσερα μέλη αλλάζει το σχήμα του
 * οικοπέδου από κλειστό σε ανοιχτό. Ό,τι μοιάζει με πλεονασμό είναι η γεωμετρία.
 */
export function parseSurveyTextList(rawText: string): readonly string[] | null {
  const items = normalizeGreekHomoglyphs(rawText)
    .split(LIST_SEPARATOR)
    .map((item) => item.trim())
    .filter((item) => item.length > 0);
  return items.length > 0 ? items : null;
}

/**
 * Δήλωση ύπαρξης → `true`.
 *
 * 🔴 **Ποτέ `false`.** Ο αναγνώστης παράγει το πεδίο **μόνο** όταν βρει τη δήλωση («ΕΝΤΟΣ
 * ΖΩΝΗΣ ΚΟΙΝΩΝΙΚΟΥ ΣΥΝΤΕΛΕΣΤΗ»)· ένα σχέδιο **εκτός** ζώνης απλώς δεν γράφει τίποτα. Το να
 * διαβαστεί η σιωπή ως «όχι» είναι εφεύρεση τιμής από απουσία — ακριβώς αυτό που ο κανόνας
 * «`null` είναι κατάσταση» απαγορεύει (ADR-759 §4.4, handoff Ζ.4).
 */
export function parseSurveyAffirmation(rawText: string): boolean | null {
  return rawText.trim().length > 0 ? true : null;
}
