/**
 * @related ADR-759 §2β.5 — η **αυστηρή** ανάγνωση αριθμού τοπογραφικού
 *
 * Μία ερώτηση: *«είναι αυτό το κείμενο, ολόκληρο, ένας αριθμός;»* — και η απάντηση
 * είναι `null` για οτιδήποτε άλλο.
 *
 * ## 🔑 Γιατί ΔΕΝ χρησιμοποιείται το `parseLocaleNumber`
 * Ο κεντρικός αναλυτής του `lib/number/locale-number.ts` **αφαιρεί πρώτα τον θόρυβο**
 * (`replace(/[^\d.,-]/g, '')`), γιατί το δικό του πεδίο είναι το **νόμισμα**: το
 * `«€ 12,50»` πρέπει να γίνει `12.5`. Εδώ το ίδιο συμβόλαιο θα ήταν **σφάλμα τιμής**:
 * το `«11 μ.»` θα γινόταν `11` και το `«κατά ΝΟΚ»` θα έμοιαζε συγκρίσιμο, οπότε η
 * καρτέλα θα πρόσφερε κουμπί «Υιοθέτηση» για νούμερο που **κανείς δεν δήλωσε έτσι**.
 * Ένας εύλογος αριθμός σε λάθος θέση είναι χειρότερος από κανέναν (ADR-759 §2β.5).
 *
 * Άρα καταναλώνεται το `normalizeDecimalString` — το **κομμάτι** του SSoT που κάνει
 * μόνο τη διάκριση υποδιαστολής/χιλιάδων — και η **άρνηση** μένει εδώ, ρητή.
 *
 * ## ⚠️ Τι διόρθωσε η κεντρικοποίηση (δεν είναι μόνο συμμόρφωση)
 * Και τα δύο σημεία που ενοποιεί έγραφαν `.replace(',', '.')`. Σε **ελληνική** γραφή
 * με χιλιάδες αυτό δίνει σκουπίδια: `«1.364,05»` → `«1.364.05»` → `NaN` ⇒ το εμβαδόν
 * του οικοπέδου εμφανιζόταν ως **μη συγκρίσιμο**. Και είναι ακριβώς η γραφή του
 * πραγματικού `G753` (1.364,05 τ.μ.). Το `normalizeDecimalString` το διαβάζει σωστά.
 *
 * @module lib/survey-record/survey-number
 */
import { normalizeDecimalString } from '@/lib/number/locale-number';

/**
 * Διάβασε αριθμό **μόνο** αν το κείμενο είναι εξ ολοκλήρου αριθμός.
 *
 * Δέχεται ελληνική υποδιαστολή και ομαδοποίηση χιλιάδων. Επιστρέφει `null` για κενό,
 * για πρόζα (`«κατά ΝΟΚ»`) και για αριθμό με μονάδα (`«11 μ.»`) — το κενό **δεν**
 * γίνεται ποτέ `0`.
 */
export function parseStrictDecimal(text: string | null | undefined): number | null {
  if (text === null || text === undefined) return null;

  const normalized = normalizeDecimalString(text);
  if (normalized === '') return null;

  const parsed = Number(normalized);
  return Number.isFinite(parsed) ? parsed : null;
}
