import 'server-only';

import type { Timestamp } from 'firebase-admin/firestore';

/**
 * Έχει περάσει το `expiresAt` του εγγράφου;
 *
 * ⚠️ Η σύγκριση είναι `<=`, όχι `<`: ένα έγγραφο που λήγει **ακριβώς** τώρα
 * θεωρείται ληγμένο. Στα όρια προτιμάμε την άρνηση.
 */
export function isExpiredDoc(data: FirebaseFirestore.DocumentData): boolean {
  return (data.expiresAt as Timestamp).toMillis() <= Date.now();
}
