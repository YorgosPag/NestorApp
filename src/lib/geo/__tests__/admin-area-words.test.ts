/**
 * @fileoverview Άγκυρα της «ίδιας λέξης» (ADR-883 §5.11) — κλίση = ίδιο θέμα + καταλήξεις του ΙΔΙΟΥ
 * κλιτικού παραδείγματος. Τα αρνητικά είναι μετρημένα: ο παλιός κανόνας («κόψε 2 γράμματα») τα
 * ταύτιζε όλα (6.129 ψευδή ζεύγη στο λεξιλόγιο του ευρετηρίου).
 */

import { formsOf, greekWords, inflectionStems, sameAdminName, sameWord, wordMatcher } from '../admin-area-words';

/** Η μορφή σύγκρισης μιας λέξης, όπως τη φτιάχνει η αναζήτηση. */
const w = (text: string) => greekWords(text)[0];

describe('sameWord — κλίση μέσα στο ίδιο κλιτικό παράδειγμα', () => {
  it.each([
    ['Ρόδος', 'Ρόδου'],
    ['Εύοσμος', 'Ευόσμου'],
    ['Κορδελιό', 'Κορδελιού'],
    ['Μεσολόγγι', 'Μεσολογγίου'],
    ['Χαλάνδρι', 'Χαλάνδριον'],
    ['Θεσσαλονίκη', 'Θεσσαλονίκης'],
    ['Ξυλόπολη', 'Ξυλοπόλεως'],
    ['Ξυλόπολις', 'Ξυλοπόλεως'],
    ['Δορκάς', 'Δορκάδα'],
    ['Λευκάδα', 'Λευκάδος'],
    ['Έδεσσα', 'Εδέσσης'],
    ['Ελασσόνα', 'Ελασσόνος'],
    ['Σαλαμίνα', 'Σαλαμίνος'],
    ['Λαγκαδάς', 'Λαγκαδά'],
    ['Καρτερές', 'Καρτερών'],
    ['Χίος', 'Χίου'],
    ['Λάρισα', 'Λαρισαίων'],
    ['Πάτρα', 'Πατρέων'],
    ['Κέρκυρα', 'Κερκυραίων'],
    ['Κόρινθος', 'Κορινθίων'],
    ['Ιωάννινα', 'Ιωαννιτών'],
    ['Ιωάννης', 'Ιωάννου'],
    ['Ανδρέας', 'Ανδρέου'],
    ['Σελινούς', 'Σελινούντος'],
    ['Λιμήν', 'Λιμένος'],
    ['Νικάνωρ', 'Νικάνορος'],
    ['Βώλαξ', 'Βώλακος'],
    ['Πειραιεύς', 'Πειραιώς'],
    ['Μέγας', 'Μεγάλου'],
    ['Δαφνές', 'Δαφνέ'],
    ['Λέπρεον', 'Λεπρέου'],
    ['Λεβάδεια', 'Λεβαδέων'],
    ['Νέα', 'Νέας'],
  ])('%s = %s (και ανάποδα)', (a, b) => {
    expect(sameWord(w(a), w(b))).toBe(true);
    expect(sameWord(w(b), w(a))).toBe(true);
  });

  it.each([
    ['Ξυλοπ', 'Ξυλοκάστρου', 'μισή λέξη δεν έχει κατάληξη ⇒ δεν γίνεται «θέμα Ξυλ-»'],
    ['Λευκάδας', 'Λευκός', 'άλλη λέξη'],
    ['Καλαμάτας', 'Κάλαμος', 'άλλη λέξη'],
    ['Βάρης', 'Βάρκα', 'άλλη λέξη'],
    ['Αγίου', 'Αγίας', 'άλλο γένος — Άγιος ≠ Αγία'],
    ['Νέα', 'Νέος', 'άλλο γένος'],
    ['Αγία', 'Αγίου', 'άλλο γένος — ο ουδέτερος πληθυντικός -α δεν είναι θηλυκό'],
    ['Νέας', 'Νέου', 'άλλο γένος'],
    ['Καλή', 'Καλό', 'άλλο γένος'],
    ['Πάτρα', 'Πάτμου', 'άλλο νησί'],
    ['Βόλος', 'Βόλβης', 'άλλη λίμνη'],
    ['Ερμιονίδας', 'Ερμιόνης', 'παράγωγο, όχι κλίση'],
    ['Θεσ', 'Θεσσαλονίκη', 'πρόθεμα, όχι λέξη'],
  ])('%s ≠ %s (%s)', (a, b) => {
    expect(sameWord(w(a), w(b))).toBe(false);
    expect(sameWord(w(b), w(a))).toBe(false);
  });

  it('greeklish: οι λατινικές καταλήξεις ΠΑΡΑΓΟΝΤΑΙ από τις ελληνικές (rodos = Ρόδου)', () => {
    const [, rodou] = formsOf(w('Ρόδου'));
    expect(sameWord('rodos', rodou)).toBe(true);
    const [, ioanniton] = formsOf(w('Ιωαννιτών'));
    expect(sameWord(formsOf(w('Ιωάννινα'))[1], ioanniton)).toBe(true);
  });
});

describe('λατινικές μορφές — δίψηφο που διπλώνεται σε μονόγραμμο δεν ενώνει γένη', () => {
  it('🔑 «samos» ≠ «sami»: το «-οι»→«i» του αρσενικού δεν γίνεται κατάληξη (θα ήταν = «-η»/«-ι»)', () => {
    const [, samos] = formsOf(w('Σάμος'));
    const [, sami] = formsOf(w('Σάμη'));
    expect(sameWord(samos, sami)).toBe(false);
    expect(sameWord(sami, samos)).toBe(false);
  });
});

describe('wordMatcher — ολόκληρη λέξη πάνω από πρόθεμα', () => {
  it('«Ξυλοπ» ⇒ πρόθεμα της Ξυλοπόλεως, τίποτα για το Ξυλόκαστρο', () => {
    const match = wordMatcher(w('Ξυλοπ'));
    expect(match(w('Ξυλοπόλεως'))).toBe('prefix');
    expect(match(w('Ξυλοκάστρου'))).toBeNull();
  });

  it('«Άργος» ⇒ ΛΕΞΗ για το Άργους, μόνο πρόθεμα για το Αργοστόλι', () => {
    const match = wordMatcher(w('Άργος'));
    expect(match(w('Άργους'))).toBe('word');
    expect(match(w('Αργοστολίου'))).toBe('prefix');
  });
});

describe('inflectionStems — τα θέματα για την ανοχή ορθογραφίας', () => {
  it('«Ξυλούπολη» ⇒ «ξυλουπολ» (κόβεται ΜΟΝΟ γνωστή κατάληξη)', () => {
    expect(inflectionStems(w('Ξυλούπολη'))).toContain('ξυλουπολ');
  });

  it('μισή λέξη χωρίς κατάληξη ⇒ κανένα θέμα', () => {
    expect(inflectionStems(w('Ξυλοπ'))).toEqual([]);
  });
});

describe('sameAdminName — ο γεννήτορας ρωτά το ίδιο', () => {
  it('«Δορκάς» = «Δορκάδα» · «Τοπική Κοινότητα Καρτερών» = «Καρτερές»', () => {
    expect(sameAdminName('Δορκάς', 'Δορκάδα')).toBe(true);
    expect(sameAdminName('Τοπική Κοινότητα Καρτερών', 'Καρτερές')).toBe(true);
  });

  it('«Νέα Χώρα» ≠ «Νέος Χώρος» — άλλο γένος σε κάθε λέξη', () => {
    expect(sameAdminName('Νέα Χώρα', 'Νέος Χώρος')).toBe(false);
  });
});
