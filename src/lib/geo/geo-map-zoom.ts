/**
 * @fileoverview **ΠΟΣΟ ΚΟΝΤΑ ΑΝΟΙΓΕΙ Ο ΧΑΡΤΗΣ ΓΙΑ ΝΑ ΧΩΡΕΣΕΙ ΑΥΤΟ** — μία φόρμουλα.
 * @related ADR-846 Φ2 (`CoverageRadiusPicker`) · Φ3 (χαραγμένο πολύγωνο, βιτρίνα)
 * @module lib/geo/geo-map-zoom
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΤΟ ΠΕΡΙΣΤΑΤΙΚΟ ΠΟΥ ΤΗ ΓΕΝΝΗΣΕ: ΣΧΗΜΑ ΠΟΥ ΖΩΓΡΑΦΙΖΕΤΑΙ ΚΑΙ ΔΕΝ ΤΟ ΒΛΕΠΕΙ ΚΑΝΕΙΣ
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * Ο `PlaceMap` ανοίγει σε `BUILDING_ZOOM = 18` — **επίπεδο κτιρίου**. Στη Φάση 2
 * μετρήθηκε ζωντανά ότι ένας κύκλος **10 χλμ** εκεί είναι **ολόκληρος εκτός οθόνης**,
 * δηλαδή το μισό επιχείρημα που επέτρεψε την ακτίνα *(«παύει να είναι οπτικά αόρατη»)*
 * **δεν πληρωνόταν**. Η θεραπεία ήταν ένας πίνακας τεσσάρων τιμών μέσα στον επιλογέα.
 *
 * 🔑 **Η Φάση 3 έφερε δύο ακόμη καταναλωτές** *(ο επιλογέας πολυγώνου και η **δημόσια
 * βιτρίνα**, που πρέπει να δείξει το χαραγμένο σχήμα σε **οποιοδήποτε** μέγεθος)*, και
 * ο πίνακας **δεν γενικεύεται**: το χαραγμένο σχήμα δεν έχει τέσσερα μεγέθη. Άρα ό,τι
 * ήταν πίνακας γίνεται **η φόρμουλα από την οποία ο πίνακας είχε προκύψει** — και ο
 * πίνακας σβήνει αντί να αποκτήσει τρίτο αντίγραφο.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 📐 Η ΠΑΡΑΓΩΓΗ — ΓΡΑΜΜΕΝΗ, ΩΣΤΕ Η ΕΠΟΜΕΝΗ ΤΙΜΗ ΝΑ ΜΗΝ ΜΑΝΤΕΥΤΕΙ
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * Στο Web Mercator η κλίμακα είναι `156.543 · cos(φ) / 2^z` **μέτρα ανά εικονοστοιχείο**.
 * Για γεωγραφικό πλάτος Ελλάδας *(φ ≈ 40°)* αυτό δίνει **119.900 / 2^z**. Για να χωρέσει
 * διάμετρος `2R` σε ύψος `h` εικονοστοιχείων:
 *
 * > `2R = 119.900 · h / 2^z`  ⟹  `z = log₂(119.900 · h / 2R)`
 *
 * ✅ **Αναπαράγει τον πίνακα της Φάσης 2** *(ύψος 256 px, δηλαδή `h-64`)*:
 * 10 χλμ → 10,58 *(ήταν 10,5)* · 20 → 9,58 *(9,5)* · 30 → 9,00 *(9)* · 50 → 8,26 *(8,2)*.
 * Οι παλιές τιμές ήταν η ίδια φόρμουλα, στρογγυλεμένη **προς τα κάτω με το χέρι**.
 *
 * ⚠️ **Το `heightPx` είναι ΟΡΙΣΜΑ, όχι σταθερά** — ο παλιός πίνακας ήταν σιωπηλά δεμένος
 * με το `h-64` του επιλογέα, και μια αλλαγή ύψους θα τον έκανε λάθος **χωρίς να το πει
 * κανείς**. Εδώ η εξάρτηση **δεν μεταγλωττίζεται** αν την ξεχάσεις.
 */

/** Πλάτος Web Mercator στο **επίπεδο 0**, για γεωγραφικό πλάτος Ελλάδας (φ ≈ 40°). */
const METRES_PER_PIXEL_AT_Z0 = 119_900;

/**
 * Πόσο κοντά πρέπει να ανοίξει ο χάρτης ώστε ένα σχήμα ακτίνας `radiusKm` να **χωράει
 * ολόκληρο** σε ύψος `heightPx`.
 *
 * ⚠️ **Φραγμένο στο `[0, 18]`**: το `18` είναι το `BUILDING_ZOOM` του `PlaceMap` — πιο
 * κοντά δεν έχει νόημα ούτε για κτίριο. Χωρίς το κάτω φράγμα, ένα εκφυλισμένο
 * `radiusKm` θα έδινε `Infinity` ή αρνητικό επίπεδο, δηλαδή **λευκή οθόνη** αντί για
 * χάρτη.
 */
export function mapZoomForRadiusKm(radiusKm: number, heightPx: number): number {
  const diameterMetres = 2 * radiusKm * 1000;
  if (!(diameterMetres > 0) || !(heightPx > 0)) return 18;

  const zoom = Math.log2((METRES_PER_PIXEL_AT_Z0 * heightPx) / diameterMetres);
  return Math.min(18, Math.max(0, zoom));
}
