import type { GeoPoint } from '@/types/geo/coordinates';

/**
 * Μέση ακτίνα της Γης κατά **WGS-84**, σε μέτρα.
 *
 * Επιλέχθηκε η τιμή των **δύο** υλοποιήσεων που τη δήλωναν ονομαστικά (και όχι το
 * στρογγυλεμένο `6 371 000` των άλλων δύο): είναι η τιμή που **κάποιος αποφάσισε**,
 * ενώ το στρογγυλεμένο είναι η τιμή που κάποιος **θυμήθηκε**.
 */
export const EARTH_RADIUS_METERS = 6_371_008.8;

function toRadians(degrees: number): number {
  return (degrees * Math.PI) / 180;
}

/**
 * Απόσταση **μεγίστου κύκλου** ανάμεσα σε δύο σημεία, σε **μέτρα** (Haversine).
 *
 * ⚠️ **Δεν είναι απόσταση διαδρομής.** Απαντά «πόσο απέχουν», ποτέ «πόσο θα
 * περπατήσεις» — και κάθε καταναλωτής της (ακτίνα ζήτησης · γειτονιά · geofence ·
 * πλησιέστερος αριθμός OSM) ρωτά **αυτό**.
 */
export function distanceMeters(a: GeoPoint, b: GeoPoint): number {
  const dLat = toRadians(b.lat - a.lat);
  const dLng = toRadians(b.lng - a.lng);

  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRadians(a.lat)) * Math.cos(toRadians(b.lat)) * Math.sin(dLng / 2) ** 2;

  return EARTH_RADIUS_METERS * 2 * Math.atan2(Math.sqrt(h), Math.sqrt(1 - h));
}
