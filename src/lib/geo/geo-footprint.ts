import type { GeoFootprint } from '@/types/geo/admin-footprint';
import type { GeoCircle, GeoOutline } from '@/types/geo/coordinates';

import { distanceMeters } from './geo-distance';
import { geoRingsBoundingCircle, geoRingsInscribedRadius } from './geo-ring';

/**
 * **Το αποτύπωμα ενός συνόλου δακτυλίων** — `null` όταν δεν υπάρχει σχήμα.
 *
 * @param rings — κάθε δακτύλιος: εξωτερικοί **και** τρύπες, όλων των μερών
 */
export function ringsFootprint(rings: readonly GeoOutline[]): GeoFootprint | null {
  const outer = geoRingsBoundingCircle(rings, distanceMeters);
  if (outer === null) return null;

  return {
    center: outer.center,
    outerKm: outer.radiusKm,
    // 🔑 **Το κέντρο του περικλείοντος, όχι δικό του** — δες την επικεφαλίδα.
    innerKm: geoRingsInscribedRadius(rings, outer.center),
  };
}

/**
 * **Ο ΚΥΚΛΟΣ ΕΙΝΑΙ ΗΔΗ ΑΠΟΤΥΠΩΜΑ** — με `innerKm === outerKm`, και αυτό δεν είναι
 * τέχνασμα: για κύκλο, ο **εγγεγραμμένος** και ο **περιγεγραμμένος** *είναι ο ίδιος*.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🏆 ΑΥΤΗ Η ΜΙΑ ΓΡΑΜΜΗ ΕΙΝΑΙ Η ΑΝΑΓΩΓΗ ΠΟΥ ΕΣΒΗΣΕ ΔΥΟ ΚΕΛΙΑ ΛΟΓΙΚΗΣ
 *
 * Πριν τη Φάση 3 ο κριτής είχε **δύο** συναρτήσεις για τα δύο «μεικτά» κελιά
 * *(`radiusOverArea` και το σώμα του `areasOverCircle`)*, με **αντικατοπτρισμένες**
 * συνθήκες — δηλαδή δύο τόποι όπου το ίδιο λάθος μπορούσε να γραφτεί μία φορά.
 * Με τον κύκλο ως αποτύπωμα, και τα δύο γίνονται **η ίδια κλήση**
 * *(`footprintRelation`)*, και η ισοδυναμία **επαληθεύτηκε όρο προς όρο** πριν
 * σβηστεί οτιδήποτε *(άγκυρα: `coverage-footprint-match.test.ts`)*.
 * ═════════════════════════════════════════════════════════════════════════════
 */
export function circleFootprint(circle: GeoCircle): GeoFootprint {
  return { center: circle.center, outerKm: circle.radiusKm, innerKm: circle.radiusKm };
}
