/** Κάτω από αυτό, η απάντηση δίνεται σε **μέτρα**. */
const METERS_LIMIT = 1000;
/** Ως εδώ, το δέκατο του χιλιομέτρου κουβαλά νόημα. */
const ONE_DECIMAL_LIMIT_KM = 10;

/**
 * Η απόσταση όπως τη διαβάζει άνθρωπος, στη γλώσσα του.
 *
 * @param meters απόσταση σε μέτρα· αρνητικές και μη πεπερασμένες τιμές δίνουν `null`
 * @param locale κωδικός γλώσσας (`currentLanguage` του `useTranslation`)
 * @returns π.χ. `«850 μ.»` · `«3,4 χλμ.»` · `«296 χλμ.»` — ή `null` όταν δεν υπάρχει απόσταση
 *
 * ⚠️ **`null` και όχι κενή συμβολοσειρά**: ο καλών οφείλει να **μη ζωγραφίσει** τη γραμμή,
 * όχι να ζωγραφίσει άδεια. Μια κενή ετικέτα δίπλα σε αριθμούς διαβάζεται ως σφάλμα.
 */
export function formatGeoDistance(
  meters: number | null | undefined,
  locale: string,
): string | null {
  if (typeof meters !== 'number' || !Number.isFinite(meters) || meters < 0) return null;

  if (meters < METERS_LIMIT) {
    return formatUnit(Math.round(meters), 'meter', 0, locale);
  }

  const km = meters / METERS_LIMIT;
  return formatUnit(km, 'kilometer', km < ONE_DECIMAL_LIMIT_KM ? 1 : 0, locale);
}

/**
 * ⚠️ **Το `try` δεν είναι διακοσμητικό.** Το `style: 'unit'` χρειάζεται πλήρες ICU· ένα
 * runtime χωρίς αυτό *(π.χ. Node χτισμένο με `small-icu`)* **πετά**, και μια πρόταση
 * διεύθυνσης δεν είναι λόγος να πέσει η οθόνη. Η υποχώρηση χάνει τη μονάδα, όχι τον αριθμό.
 */
function formatUnit(value: number, unit: 'meter' | 'kilometer', decimals: number, locale: string): string {
  const options: Intl.NumberFormatOptions = {
    maximumFractionDigits: decimals,
    minimumFractionDigits: 0,
  };
  try {
    return new Intl.NumberFormat(locale, { ...options, style: 'unit', unit, unitDisplay: 'short' })
      .format(value);
  } catch {
    return new Intl.NumberFormat(locale, options).format(value);
  }
}
