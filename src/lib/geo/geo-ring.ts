// ΕΓΚΥΡΟΤΗΤΑ ΔΑΚΤΥΛΙΟΥ — τα δύο ερωτήματα που κρίνουν αν ένα σχέδιο είναι σχήμα
// =============================================================================

/**
 * Το **εμβαδόν** που περικλείει ο δακτύλιος, σε m².
 *
 * 🔑 **Δεν είναι διακοσμητικό: είναι το `areaSqm` της {@link PublicLand}.** Όταν ο
 * άνθρωπος ζωγραφίζει το οικόπεδό του, το εμβαδόν **δεν χρειάζεται να δηλωθεί** — το
 * σχήμα το ξέρει ήδη. Ένα ξεχωριστό πεδίο που ο χρήστης συμπληρώνει με το χέρι θα
 * ήταν **δεύτερη αλήθεια** για το ίδιο γεγονός, και μια μέρα θα διαφωνούσε με το
 * σχήμα.
 *
 * ⚠️ **Ανεξάρτητο από τη φορά διαγραφής** (απόλυτη τιμή): ένας δακτύλιος
 * σχεδιασμένος αριστερόστροφα δεν έχει αρνητικό εμβαδόν — έχει το ίδιο εμβαδόν. Η
 * φορά είναι σύμβαση αναπαράστασης· το εμβαδόν είναι γεγονός.
 *
 * ⚠️ `0` για δακτύλιο με < 3 κορυφές — ίδια σημασιολογία με το
 * {@link isPointInGeoOutline}: δύο σημεία δεν περικλείουν τίποτα.
 */
export function geoOutlineAreaSqm(outline: GeoOutline): number {
  if (outline.length < 3) return 0;

  const points = toLocalMetres(outline, vertexCentroid(outline));
  let twiceSignedArea = 0;
  for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
    twiceSignedArea += points[j].x * points[i].y - points[i].x * points[j].y;
  }

  return Math.abs(twiceSignedArea) / 2;
}

/**
 * Είναι ο δακτύλιος **απλός** — δηλαδή δεν τέμνει τον εαυτό του;
 *
 * 🔴 **Ο λόγος που υπάρχει είναι ότι ένα «παπιγιόν» ΔΕΝ φαίνεται λάθος — φαίνεται
 * σχήμα.** Ο αλγόριθμος ρίψης ακτίνας του {@link isPointInGeoOutline} απαντά
 * **ευχάριστα** για έναν αυτοτεμνόμενο δακτύλιο, και η απάντηση είναι το even–odd του
 * σχήματος: ένα σημείο στον έναν βρόχο μετρά «μέσα», στον άλλο «έξω». Δηλαδή το
 * εμπόδιο `outside-area` θα **έλεγε ψέματα** — και το επίπεδο Α το βλέπουν **όλοι**
 * (§14.4).
 *
 * ⚠️ **O(n²), και είναι σωστό εδώ.** Ο δακτύλιος έρχεται από **ανθρώπινο δάχτυλο** —
 * δεκάδες κορυφές, όχι δεκάδες χιλιάδες. Ένας σαρωτής γραμμής (Bentley–Ottmann) θα
 * πρόσθετε αλγόριθμο που κανείς δεν ζήτησε, στο ίδιο πνεύμα με το «όχι Welzl»
 * παραπάνω.
 *
 * ⚠️ Δακτύλιος με < 4 κορυφές είναι **πάντα** απλός: τρία τμήματα που κλείνουν δεν
 * έχουν ζεύγος μη-γειτονικών να τμηθεί.
 */
/**
 * **ΤΟ ΚΑΤΩΦΛΙ ΟΠΟΥ ΤΑ ΤΕΤΡΑΓΩΝΙΚΑ ΜΕΤΡΑ ΠΑΥΟΥΝ ΝΑ ΔΙΑΒΑΖΟΝΤΑΙ** — **1 τ.χλμ.**
 *
 * 🔴 **Βρέθηκε στο ζωντανό περπάτημα** *(ADR-846 Φ3, 2026-09-08)*: το χειριστήριο
 * χάραξης έγραψε **«Εμβαδόν: 519802094 τ.μ.»** για μια δηλωμένη περιοχή εργασίας.
 * Κανένα σφάλμα — απλώς αριθμός που **κανείς άνθρωπος δεν διαβάζει**.
 *
 * ⚠️ **Η αιτία δεν ήταν ελάττωμα, ήταν ΝΕΑ ΚΛΙΜΑΚΑ**: το `place.draw.area` γράφτηκε για
 * **οικόπεδο ή κτίριο** *(δεκάδες έως χιλιάδες τ.μ.)*, και η Φάση 3 έδωσε στην ίδια
 * χειρονομία αντικείμενο **πέντε τάξεις μεγέθους** μεγαλύτερο.
 */
export const AREA_KM2_THRESHOLD_SQM = 1_000_000;

/**
 * Τετραγωνικά **μέτρα** → τετραγωνικά **χιλιόμετρα**, με **ένα** δεκαδικό.
 *
 * 🔑 **Η στρογγυλοποίηση ζει ΕΔΩ, μία φορά**: την ίδια τιμή γράφουν **τρεις** οθόνες
 * *(το χειριστήριο χάραξης, η κάρτα του καταλόγου, η δημόσια βιτρίνα)*, και τρία
 * ανεξάρτητα `Math.round` θα έδειχναν στον ίδιο άνθρωπο **άλλο νούμερο** σε κάθε μία.
 *
 * ⚠️ **Ένα δεκαδικό, όχι μηδέν**: μια γειτονιά είναι ~2 τ.χλμ., και ένα σκέτο
 * `Math.round` θα έγραφε **«0»** για ό,τι μικρότερο — δηλαδή η δήλωση του ανθρώπου θα
 * φαινόταν ανύπαρκτη.
 */
export function areaSqmToKm2(areaSqm: number): number {
  return Number((areaSqm / 1_000_000).toFixed(1));
}

export function isSimpleGeoOutline(outline: GeoOutline): boolean {
  if (outline.length < 4) return true;

  const points = toLocalMetres(outline, vertexCentroid(outline));
  const n = points.length;

  for (let i = 0; i < n; i++) {
    const a1 = points[i];
    const a2 = points[(i + 1) % n];

    // Ξεκινά από `i + 2` και σταματά πριν το τμήμα που **γειτονεύει** με το `i`:
    // γειτονικά τμήματα μοιράζονται κορυφή εξ ορισμού, και μια κοινή κορυφή δεν
    // είναι αυτοτομή.
    for (let j = i + 2; j < n; j++) {
      if (i === 0 && j === n - 1) continue;
      if (localSegmentCrossing(a1, a2, points[j], points[(j + 1) % n]) !== null) return false;
    }
  }

  return true;
}

