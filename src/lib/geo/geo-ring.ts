import type { GeoOutline, GeoPoint } from '@/types/geo/coordinates';

/**
 * Είναι το σημείο **μέσα** στον δακτύλιο;
 *
 * Αλγόριθμος ρίψης ακτίνας (even–odd), η κανονική λύση — ίδια οικογένεια με τις τρεις
 * υπάρχουσες υλοποιήσεις του repo, ώστε η **συμπεριφορά** να μην εκπλήσσει όποιον έχει
 * διαβάσει κάποια από αυτές.
 *
 * ⚠️ **Δακτύλιος με λιγότερες από 3 κορυφές επιστρέφει `false`.** Δεν είναι άμυνα, είναι
 * σημασιολογία: δύο σημεία δεν περικλείουν εμβαδόν, άρα **τίποτα** δεν είναι μέσα. Η
 * εκφυλισμένη είσοδος μπλοκάρεται ήδη στη γραφή (`outline-degenerate`), αλλά μια
 * καθαρή συνάρτηση δεν επιτρέπεται να υποθέτει ότι κάποιος άλλος κοίταξε.
 *
 * ⚠️ **Η ισοπαλία στο όριο δεν είναι εγγυημένη**, όπως σε κάθε even–odd: ένα σημείο
 * ακριβώς πάνω στην ακμή μπορεί να πέσει είτε μέσα είτε έξω, ανάλογα με τη
 * στρογγυλοποίηση. Για τη χρήση εδώ — «*ψάχνω σε αυτό το τετράγωνο*» — η διαφορά είναι
 * κάτω από το πλάτος του πεζοδρομίου, και **καμία απόφαση δεν κρέμεται από αυτήν**.
 */
export function isPointInGeoOutline(point: GeoPoint, outline: GeoOutline): boolean {
  if (outline.length < 3) return false;

  const { lat, lng } = point;
  let inside = false;

  for (let i = 0, j = outline.length - 1; i < outline.length; j = i++) {
    const a = outline[i];
    const b = outline[j];

    const straddles = a.lat > lat !== b.lat > lat;
    if (!straddles) continue;

    const crossingLng = ((b.lng - a.lng) * (lat - a.lat)) / (b.lat - a.lat) + a.lng;
    if (lng < crossingLng) inside = !inside;
  }

  return inside;
}

/**
 * Το **κέντρο βάρους των κορυφών** ενός δακτυλίου.
 *
 * ⚠️ **Δεν είναι το κεντροειδές του εμβαδού, και η διαφορά έχει σημασία εδώ.** Το
 * κεντροειδές εμβαδού είναι «πιο σωστό» για ένα σχήμα· αυτό όμως χρησιμοποιείται
 * **μόνο** ως κέντρο ενός κύκλου που πρέπει να **περικλείει** τον δακτύλιο
 * ({@link geoOutlineBoundingCircle}). Για εκείνη τη δουλειά, μια κορυφή που τραβά το
 * κέντρο προς το μέρος της είναι **ακίνδυνη** (ο κύκλος μεγαλώνει), ενώ ένα
 * κεντροειδές εμβαδού σε σχήμα C μπορεί να πέσει **εκτός** του σχήματος — που είναι
 * παράξενο να το εξηγήσεις και δεν αγοράζει τίποτα.
 */
function vertexCentroid(outline: GeoOutline): GeoPoint {
  let lat = 0;
  let lng = 0;
  for (const vertex of outline) {
    lat += vertex.lat;
    lng += vertex.lng;
  }
  return { lat: lat / outline.length, lng: lng / outline.length };
}

/**
 * Ο **μικρότερος κύκλος που σίγουρα περικλείει** τον δακτύλιο — κέντρο + ακτίνα σε km.
 *
 * 🔑 **Υπάρχει για μία δουλειά: να είναι ΥΠΕΡΣΥΝΟΛΟ.** Το ADR-777 προβάλλει μια ζήτηση
 * με σχεδιασμένη περιοχή σε φίλτρα οθόνης που ξέρουν **μόνο** «σημείο + ακτίνα». Μια
 * προβολή που **στένευε** θα έκρυβε αγγελίες που ταιριάζουν — δηλαδή θα ήταν
 * **λανθασμένη σιωπηλά**. Ένας κύκλος που περισσεύει απλώς δείχνει μερικές παραπάνω,
 * και η μηχανή ταιριάσματος τις κόβει **μετά**, με τον πραγματικό δακτύλιο.
 *
 * ⚠️ Δεν είναι ο **ελάχιστος** περικλείων κύκλος (Welzl). Δεν χρειάζεται να είναι:
 * το συμβόλαιο είναι «*περικλείει*», όχι «*περικλείει σφιχτά*», και η βελτιστοποίηση
 * θα πρόσθετε αλγόριθμο που κανείς δεν ζήτησε.
 *
 * @param outline — δακτύλιος με ≥1 κορυφή
 * @param distanceMetres — ο SSoT απόστασης (`haversineDistance`), περασμένος από τον
 *   καλούντα ώστε αυτό το module να μένει **φύλλο** και η απόσταση να μετριέται με
 *   **μία** μηχανή σε όλο το έργο
 * @returns `null` για κενό δακτύλιο — δεν υπάρχει κύκλος να περικλείσει το τίποτα
 */
export function geoOutlineBoundingCircle(
  outline: GeoOutline,
  distanceMetres: (a: GeoPoint, b: GeoPoint) => number,
): { readonly center: GeoPoint; readonly radiusKm: number } | null {
  if (outline.length === 0) return null;

  const center = vertexCentroid(outline);
  let farthestMetres = 0;
  for (const vertex of outline) {
    const metres = distanceMetres(center, vertex);
    if (metres > farthestMetres) farthestMetres = metres;
  }

  // ⚠️ Δακτύλιος με ταυτόσημες κορυφές δίνει ακτίνα 0 — και το 0 φιλτράρει ΤΑ ΠΑΝΤΑ
  // στους καταναλωτές (`listing-filters.ts`: «*ακτίνα μηδέν … ο επισκέπτης θα έβλεπε
  // άδεια οθόνη χωρίς να ξέρει ότι έφταιγε μια παράμετρος*»). Το κατώτατο όριο κρατά
  // την υπόσχεση «υπερσύνολο» αληθινή ακόμη και στην εκφυλισμένη είσοδο.
  const radiusKm = Math.max(farthestMetres / 1000, MIN_BOUNDING_RADIUS_KM);
  return { center, radiusKm };
}

/** 10 μέτρα — μικρότερο από κάθε οικόπεδο, μεγαλύτερο από κάθε σφάλμα στρογγυλοποίησης. */
const MIN_BOUNDING_RADIUS_KM = 0.01;
