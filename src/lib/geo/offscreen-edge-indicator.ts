/** Σημείο σε **συντεταγμένες οθόνης**: `y` μεγαλώνει προς τα **κάτω** (σύμβαση DOM/canvas). */
export interface ScreenPoint {
  readonly x: number;
  readonly y: number;
}

/** Το ορατό κάδρο, σε pixel. */
export interface ScreenSize {
  readonly width: number;
  readonly height: number;
}

/**
 * Περιθώρια **ανά πλευρά**, σε pixel — ο χώρος που ο δείκτης **δεν** δικαιούται.
 *
 * 🔴 **ΓΙΑΤΙ ΔΕΝ ΑΡΚΕΙ ΕΝΑΣ ΑΡΙΘΜΟΣ — μετρημένο ζωντανά 2026-09-05.** Το κέλυφος του
 * χάρτη δεν είναι συμμετρικό: το «Δες όλες τις πιθανές τοποθεσίες» κάθεται **κάτω
 * κεντρικά**, το «Βρες τη θέση μου» κάτω δεξιά, η απόδοση του OpenStreetMap κάτω δεξιά.
 * Με ομοιόμορφο περιθώριο ο δείκτης ενός υποψήφιου **ακριβώς νότια** πέφτει πάνω στο
 * κουμπί: μετρήθηκε επικάλυψη **15×23 px** στον υποψήφιο «Άγιοι Ανάργυροι».
 *
 * 🔑 **Και γι' αυτό είναι ΞΕΧΩΡΙΣΤΟ από το `inset`.** Τα δύο περιθώρια απαντούν σε
 * **δύο διαφορετικά ερωτήματα**, και η σύγχυσή τους ήταν ακριβώς το ελάττωμα:
 *
 * | Ερώτημα | Ποιος απαντά |
 * |---|---|
 * | *«φαίνεται η ίδια η πινέζα, ή είναι κομμένη στην ακμή;»* | `inset` — **ομοιόμορφο** |
 * | *«πού επιτρέπεται να καθίσει ο δείκτης;»* | `placement` — **ανά πλευρά** |
 *
 * Αν το ίδιο περιθώριο απαντούσε και στα δύο, τότε η δέσμευση 66 px για το κουμπί θα
 * σήμαινε ότι μια πινέζα **50 px πάνω από την κάτω ακμή** — απολύτως ορατή — θα
 * κρινόταν «κρυμμένη» και θα έπαιρνε **και** δείκτη: δύο σημεία για μία διεύθυνση,
 * δηλαδή ακριβώς αυτό που το `null` αυτής της συνάρτησης υπάρχει για να αποτρέπει.
 */
export interface EdgeInsets {
  readonly top: number;
  readonly right: number;
  readonly bottom: number;
  readonly left: number;
}

/** Πού μπαίνει ο δείκτης και προς τα πού δείχνει. */
export interface EdgeIndicator {
  /** Θέση στο κάδρο (pixel από την αριστερή ακμή). */
  readonly x: number;
  /** Θέση στο κάδρο (pixel από την πάνω ακμή). */
  readonly y: number;
  /**
   * Κατεύθυνση του στόχου, σε **μοίρες δεξιόστροφα από το πάνω** *(0° = πάνω/βορράς της
   * οθόνης, 90° = δεξιά)*.
   *
   * ⚠️ Η σύμβαση επιλέχθηκε ώστε ένα βέλος **σχεδιασμένο να δείχνει πάνω** να
   * περιστρέφεται με σκέτο `rotate(angleDeg)`. Η εναλλακτική *(μαθηματικές μοίρες
   * αριστερόστροφα από τον άξονα x)* θα απαιτούσε από **κάθε** καλούντα να θυμάται
   * μετατροπή — δηλαδή θα ήταν ακριβώς η παράμετρος που ο επόμενος ξεχνά.
   */
  readonly angleDeg: number;
}

/**
 * Ο δείκτης για έναν στόχο **εκτός κάδρου** — ή `null` όταν ο στόχος **φαίνεται**.
 *
 * 🔑 **Το `null` είναι η μισή αξία της συνάρτησης.** Όταν ο στόχος χωράει στο κάδρο,
 * ο άνθρωπος βλέπει την ίδια την πινέζα· ένας δείκτης άκρης από πάνω θα ήταν **δεύτερη
 * αναπαράσταση του ίδιου πράγματος**, δηλαδή δύο σημεία για μία διεύθυνση. Ο καλών
 * οφείλει να **μη ζωγραφίσει**, όχι να ζωγραφίσει κάτι ουδέτερο.
 *
 * @param target ο στόχος σε συντεταγμένες οθόνης *(π.χ. `map.project([lng, lat])`)*
 * @param size το ορατό κάδρο
 * @param inset περιθώριο από την ακμή, σε pixel — **ο μισός δείκτης**, ώστε το σήμα να
 *   μη βγαίνει κομμένο στο μισό. Ο στόχος θεωρείται «ορατός» μέσα σε αυτό το μικρότερο
 *   ορθογώνιο: μια πινέζα ακριβώς πάνω στην ακμή είναι **οπτικά κομμένη**, άρα δεν την
 *   έχει δει κανείς.
 * @param placement πού **επιτρέπεται να καθίσει** ο δείκτης — περιθώρια ανά πλευρά, για
 *   να μην πέφτει πάνω στο κέλυφος του χάρτη *(βλ. `EdgeInsets`)*. Όταν παραλείπεται,
 *   ισχύει το ομοιόμορφο `inset`: ο καλών που δεν έχει κέλυφος **δεν χρωστά τίποτα**.
 *

 * ⚠️ **Κάθε μη πεπερασμένη είσοδος δίνει `null`.** Το `map.project()` επιστρέφει `NaN`
 * όταν ο χάρτης δεν έχει ακόμη διαστάσεις — και ένα `NaN` που περνά σε `transform` δεν
 * ρίχνει τίποτα: **εξαφανίζει σιωπηλά** τον δείκτη ή τον καρφώνει στη γωνία. Η ρητή
 * απόρριψη είναι η διαφορά ανάμεσα σε «δεν έχω απάντηση» και «απαντώ σκουπίδια».
 */
export function edgeIndicatorFor(
  target: ScreenPoint,
  size: ScreenSize,
  inset: number,
  placement?: EdgeInsets,
): EdgeIndicator | null {
  if (!Number.isFinite(target.x) || !Number.isFinite(target.y)) return null;
  if (!Number.isFinite(size.width) || !Number.isFinite(size.height)) return null;
  if (!Number.isFinite(inset) || inset < 0) return null;

  const centerX = size.width / 2;
  const centerY = size.height / 2;

  // Μισό πλάτος/ύψος του ορθογωνίου που κρίνει την **ΟΡΑΤΟΤΗΤΑ** — όχι την τοποθέτηση.
  const halfX = centerX - inset;
  const halfY = centerY - inset;

  // Κάδρο μικρότερο από το ίδιο του το περιθώριο δεν έχει «άκρη» να δείξει κάτι.
  if (halfX <= 0 || halfY <= 0) return null;

  const dx = target.x - centerX;
  const dy = target.y - centerY;

  // Μέσα στο κάδρο ⇒ η ίδια η πινέζα φαίνεται. Καλύπτει και το ακριβές κέντρο.
  if (Math.abs(dx) <= halfX && Math.abs(dy) <= halfY) return null;

  const place = resolvePlacement(inset, placement);

  /*
    Πόσο πρέπει να «μαζευτεί» η ακτίνα κέντρο→στόχος ώστε να ακουμπήσει την **επιτρεπτή**
    ακμή. Η αφετηρία μένει το **κέντρο του κάδρου** και όχι το κέντρο του επιτρεπτού
    ορθογωνίου: ο άνθρωπος διαβάζει τη φορά ως ακτίνα από εκεί που κοιτάζει, και μια
    αφετηρία μετατοπισμένη 33 px ψηλότερα θα έστριβε **κάθε** γωνία χωρίς λόγο.

    Επειδή το ορθογώνιο δεν είναι πια συμμετρικό, το όριο κάθε άξονα εξαρτάται από το
    **πρόσημο** της φοράς: στόχος προς τα κάτω κρίνεται από το `bottom`, προς τα πάνω
    από το `top`. Ο έλεγχος `dx !== 0` δεν είναι παράνοια — στόχος ακριβώς πάνω/κάτω
    δίνει `dx === 0`, και το `limitX / 0` είναι `Infinity`, που το `Math.min` **σωστά**
    αγνοεί. Το επικίνδυνο θα ήταν `0 / 0`.
  */
  const limitX = dx > 0 ? size.width - place.right - centerX : centerX - place.left;
  const limitY = dy > 0 ? size.height - place.bottom - centerY : centerY - place.top;

  // Πλευρά που δεσμεύτηκε ολόκληρη δεν έχει «άκρη» να δείξει κάτι.
  if (limitX <= 0 || limitY <= 0) return null;

  const scaleX = dx !== 0 ? limitX / Math.abs(dx) : Number.POSITIVE_INFINITY;
  const scaleY = dy !== 0 ? limitY / Math.abs(dy) : Number.POSITIVE_INFINITY;
  const scale = Math.min(scaleX, scaleY);

  if (!Number.isFinite(scale)) return null;

  return {
    x: centerX + dx * scale,
    y: centerY + dy * scale,
    angleDeg: screenAngleDeg(dx, dy),
  };
}

/**
 * Τα τελικά περιθώρια τοποθέτησης.
 *
 * ⚠️ **Το `Math.max` δεν είναι ευγένεια, είναι φράχτης.** Περιθώριο τοποθέτησης
 * **μικρότερο** από το `inset` θα σήμαινε επιτρεπτό ορθογώνιο **μεγαλύτερο** από εκείνο
 * που κρίνει την ορατότητα: ο στόχος θα μπορούσε να είναι **μέσα** του, το πηλίκο θα
 * έβγαινε `> 1`, και η ακτίνα θα **επεκτεινόταν πέρα από τον ίδιο τον στόχο** — δείκτης
 * που δείχνει προς τα πίσω. Έτσι, η κατάσταση δεν αποφεύγεται με προσοχή του καλούντα·
 * **δεν μπορεί να παρασταθεί**.
 *
 * ⚠️ **Και ΔΕΝ ελέγχει αν οι τιμές είναι αριθμοί — επίτηδες, μετρημένο σε μετάλλαξη.**
 * Ένας τέτοιος έλεγχος γράφτηκε, και η μετάλλαξη που τον αφαίρεσε έμεινε **πράσινη**:
 * ήταν **νεκρός**. Το `NaN` διαδίδεται στο `limit`, από εκεί στο `scale`, και το πιάνει
 * ο **ίδιος** φράχτης που πιάνει κάθε άλλη μη πεπερασμένη είσοδο. Πλεονασμός που δεν
 * μπορεί να κοκκινίσει δεν είναι ασφάλεια — είναι κώδικας που κανείς δεν συντηρεί.
 * **Ένα** επιπλέον όφελος: πλευρά με `NaN` που ο στόχος **δεν χρησιμοποιεί** δεν χαλάει
 * πια μια απάντηση που ήταν σωστή.
 */
function resolvePlacement(inset: number, placement?: EdgeInsets): EdgeInsets {
  if (!placement) return { top: inset, right: inset, bottom: inset, left: inset };

  return {
    top: Math.max(inset, placement.top),
    right: Math.max(inset, placement.right),
    bottom: Math.max(inset, placement.bottom),
    left: Math.max(inset, placement.left),
  };
}

/**
 * Μοίρες **δεξιόστροφα από το πάνω**, στο διάστημα `[0, 360)`.
 *
 * ⚠️ Το `-dy` δεν είναι λάθος πρόσημο: στην οθόνη το `y` μεγαλώνει **προς τα κάτω**, οπότε
 * «πάνω» είναι αρνητικό `dy`. Χωρίς την αναστροφή, ο δείκτης θα έδειχνε **καθρεφτισμένα**
 * — και το σφάλμα θα ήταν αόρατο σε στόχο ακριβώς δεξιά ή αριστερά, δηλαδή θα περνούσε
 * από κάθε πρόχειρη δοκιμή.
 */
function screenAngleDeg(dx: number, dy: number): number {
  const degrees = (Math.atan2(dx, -dy) * 180) / Math.PI;
  return (degrees + 360) % 360;
}
