// Η ΔΕΥΤΕΡΗ ΠΗΓΗ — πίνακας, ρητά κατώτερος από τη μέτρηση
// =============================================================================

/**
 * Τιμές **μόνο** για όταν ο πάροχος δεν έδωσε έκταση.
 *
 * 🔑 **`Record` και όχι `Partial`/`switch` με `default`**: αν αύριο προστεθεί βαθμός
 * στο {@link GEOCODING_ACCURACIES}, ο μεταγλωττιστής **σταματά τη μεταγλώττιση εδώ**
 * και κάποιος **αποφασίζει** πώς προβάλλεται. Ένα `default` θα τον χώνευε σιωπηλά στην
 * πιο κοντινή προβολή — το ίδιο σχήμα που το `geocoding-thresholds.ts` απορρίπτει ρητά
 * για το `POINT_LEVEL_ACCURACIES` («*ο νέος βαθμός θα περνούσε σιωπηλά ως αποδεκτός*»).
 *
 * **Τα ζουμ** είναι οι καθιερωμένες βαθμίδες του OSM (18 κτίριο · 17 τετράγωνο ·
 * 15 συνοικία · 13 οικισμός). **Οι ακτίνες** είναι συντηρητικές: σε αβεβαιότητα, ο
 * μεγαλύτερος κύκλος λέει «ξέρω λιγότερα» — λάθος **προς την ειλικρινή κατεύθυνση**.
 */
const FALLBACK: Record<GeocodingAccuracy, { readonly zoom: number; readonly metres: number | null }> = {
  /** OSM `house`/`building` — το κτίριο **είναι** η απάντηση. */
  exact: { zoom: 18, metres: null },
  /**
   * OSM `street`/`road`.
   *
   * ⚠️ **ΤΟ ΟΝΟΜΑ ΛΕΕΙ ΨΕΜΑΤΑ, ΚΑΙ ΤΟ ΞΕΡΟΥΜΕ**: δεν είναι το `RANGE_INTERPOLATED` της
   * Google (παρεμβολή **αριθμού** επί του άξονα, σφάλμα μέτρων) — ο
   * {@link determineAccuracy} το δίνει σε **ολόκληρο τον δρόμο**, και η τιμή είναι το
   * **κέντρο** του. Άρα η αβεβαιότητα είναι **το μισό μήκος του δρόμου**, όχι το βήμα
   * αρίθμησης. Τα 150 m είναι τυπικό αστικό οικοδομικό τετράγωνο — και ο λόγος που
   * αυτός ο βαθμός **δεν** παίρνει πινέζα.
   */
  interpolated: { zoom: 17, metres: 150 },
  /** OSM `suburb`/`neighbourhood`/`residential` — συνοικία. */
  approximate: { zoom: 15, metres: 500 },
  /**
   * Ό,τι απέμεινε: πόλη, χωριό, ή *«δεν βρήκα τη διεύθυνση, σου δίνω το κέντρο του
   * οικισμού»* — **απόκλιση χιλιομέτρων**, με τα λόγια του `geocoding-thresholds.ts`.
   */
  center: { zoom: 13, metres: 2_000 },
};

