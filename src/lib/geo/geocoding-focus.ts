// Η ΜΙΑ ΣΥΝΑΡΤΗΣΗ
// =============================================================================

/**
 * Η **μισή διαγώνιος** της έκτασης, σε μέτρα — η ακτίνα του κύκλου που την περικλείει.
 *
 * 🔑 Μετριέται με το `distanceMeters` του {@link lib/geo/geo-distance}, τον SSoT
 * απόστασης του έργου. Καμία τριγωνομετρία δεν ξαναγράφεται εδώ.
 *
 * ⚠️ **Περικλείει, δεν εφάπτεται** — ίδιο συμβόλαιο με το `geoOutlineBoundingCircle`:
 * ένας κύκλος που περισσεύει λέει «ξέρω λιγότερα από όσα ξέρω», που είναι ανεκτό· ένας
 * που λείπει λέει «ξέρω περισσότερα», που είναι **ακριβώς το ψέμα** που κυνηγάμε.
 */
function extentRadiusMetres(extent: GeoBoundingBox): number {
  const southWest: GeoPoint = { lat: extent.south, lng: extent.west };
  const northEast: GeoPoint = { lat: extent.north, lng: extent.east };
  return distanceMeters(southWest, northEast) / 2;
}

/**
 * **Πού κοιτάζει ο χάρτης, και τι ζωγραφίζεται.** Ο μόνος τρόπος να απαντηθεί.
 *
 * 🔑 **Το σχήμα κρίνεται ΜΟΝΟ από τον βαθμό, ποτέ από την έκταση.** Ένας πολύ μικρός
 * δρόμος έχει μικρή έκταση, αλλά εξακολουθεί να είναι **δρόμος**: δεν ξέρουμε ποιο
 * κτίριο, και καμία στενότητα του ορθογωνίου δεν μας το μαθαίνει. Το ερώτημα της
 * ένδειξης είναι *«ξέρω το πράγμα;»*, όχι *«είναι μικρό;»*.
 *
 * ⚠️ **ΚΑΙ ΓΙ' ΑΥΤΟ ΔΕΝ ΞΑΝΑΧΡΗΣΙΜΟΠΟΙΕΙΤΑΙ ΤΟ `POINT_LEVEL_ACCURACIES`**, παρότι
 * μοιάζει: εκείνο απαντά *«είναι αυτή η θέση **αρκετά καλή για να δημοσιευτεί**;»* και
 * δέχεται τρεις βαθμούς. Αυτό ρωτά *«ποιο **σχήμα** λέει την αλήθεια;»* και το
 * απαντά ο SSoT της Α5. Δύο ερωτήσεις που μοιάζουν δεν είναι η ίδια ερώτηση — και ένα
 * κοινό σύνολο θα έκανε κάθε μελλοντική αλλαγή του ενός να μετακινεί σιωπηλά το άλλο.
 */
export function focusPresentation(focus: PlaceFocus): FocusPresentation {
  const fallback = FALLBACK[focus.accuracy];
  // 🔑 **Ζητείται, δεν κρίνεται** — δες το {@link ListingMapShape} παραπάνω.
  const shape = mapShapeOfGeocodingAccuracy(focus.accuracy);

  if (!shapeHasHalo(shape)) {
    // Η στέγη δεν έχει αβεβαιότητα να ζωγραφίσει — ακόμη κι όταν ο πάροχος στέλνει
    // έκταση (το περίγραμμα του κτιρίου). Ζουμ κτιρίου, πινέζα, τέλος.
    return { shape, frame: { kind: 'zoom', zoom: fallback.zoom }, uncertaintyMetres: null };
  }

  if (focus.extent !== undefined) {
    return {
      shape,
      frame: { kind: 'extent', extent: focus.extent },
      // 🔑 **Η μετρημένη ακτίνα, όχι η πινακωτή** — και ο πίνακας δεν συμμετέχει καν
      //    ως κατώτατο όριο: θα ήταν σιωπηλή ανάμειξη των δύο πηγών.
      uncertaintyMetres: extentRadiusMetres(focus.extent),
    };
  }

  return {
    shape,
    frame: { kind: 'zoom', zoom: fallback.zoom },
    // Ο πίνακας εγγυάται τιμή για κάθε σχήμα με επιφύλαξη· το `?? ` δεν είναι
    // αμυντικό αλλά **δηλωτικό** — ο τύπος του πίνακα επιτρέπει `null` για το `exact`.
    uncertaintyMetres: fallback.metres ?? 0,
  };
}
