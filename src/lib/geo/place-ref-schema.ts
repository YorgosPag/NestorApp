import { z } from 'zod';

/** Η μορφή του {@link PlaceRef} — **μόνο** μορφή, ποτέ ύπαρξη. */
export const placeRefSchema = z.object({
  landId: z.string().min(1),
  buildingId: z.string().min(1).nullable(),
});
