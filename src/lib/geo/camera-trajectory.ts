/** Ένα καρέ της κίνησης, όπως το είδε ο δειγματολήπτης. */
export interface CameraSample {
  /** Χιλιοστά από την έναρξη της κίνησης. */
  readonly ms: number;
  readonly zoom: number;
  readonly lat: number;
  readonly lng: number;
}

/** Τι έδειξε η διαδρομή, σε αριθμούς — **καμία** ετυμηγορία εδώ. */
export interface CameraTrajectory {
  /** Πόσο κράτησε **πραγματικά** η κίνηση: ως το τελευταίο καρέ που άλλαξε κάτι. */
  readonly durationMs: number;
  /** Πόσα καρέ κατέγραψε ο δειγματολήπτης — μικρός αριθμός = αναξιόπιστη μέτρηση. */
  readonly frames: number;
  /**
   * **Πόσο βυθίστηκε το ζουμ κάτω από ΚΑΙ ΤΑ ΔΥΟ άκρα** — η υπογραφή του van Wijk.
   *
   * `0` σημαίνει *«δεν ζουμάρισε ποτέ έξω»*, δηλαδή **σύρσιμο**, όχι πτήση.
   */
  readonly arcDepth: number;
  /** Πόσο μακριά ήταν τα δύο άκρα, σε μοίρες — το μέτρο του «πόσο μεγάλο ταξίδι». */
  readonly spanDegrees: number;
}

/**
 * Απόσταση σε μοίρες, **επίτηδες αφελής**: εδώ δεν κρίνεται γεωγραφία, μόνο *«πόσο
 * μεγάλο ήταν το άλμα σε σχέση με τα άλλα άλματα»*. Το `lib/geo/geo-distance` απαντά
 * την **πραγματική** ερώτηση και **δεν** αντιγράφεται εδώ *(N.18)*.
 */
function spanOf(first: CameraSample, last: CameraSample): number {
  return Math.hypot(last.lat - first.lat, last.lng - first.lng);
}

/** Το τελευταίο καρέ στο οποίο **άλλαξε** κάτι — όχι το τελευταίο που καταγράφηκε. */
function lastMovingIndex(samples: readonly CameraSample[]): number {
  for (let i = samples.length - 1; i > 0; i--) {
    const now = samples[i];
    const prev = samples[i - 1];
    if (now.zoom !== prev.zoom || now.lat !== prev.lat || now.lng !== prev.lng) return i;
  }
  return 0;
}

/**
 * **Τι έδειξε αυτή η διαδρομή.**
 *
 * ⚠️ Η διάρκεια μετριέται ως *«το τελευταίο καρέ που άλλαξε κάτι»* και **όχι** ως το
 * τελευταίο καρέ: ο δειγματολήπτης συνεχίζει να καταγράφει και μετά την προσγείωση, ώστε
 * να μπορεί να αποδείξει ότι η κίνηση **σταμάτησε**. Χωρίς αυτή τη διάκριση, κάθε
 * διαδρομή θα «διαρκούσε» όσο ο δειγματολήπτης.
 */
export function cameraTrajectory(samples: readonly CameraSample[]): CameraTrajectory {
  if (samples.length === 0) {
    return { durationMs: 0, frames: 0, arcDepth: 0, spanDegrees: 0 };
  }
  const first = samples[0];
  const end = lastMovingIndex(samples);
  const flown = samples.slice(0, end + 1);

  const edgeZoom = Math.min(first.zoom, samples[end].zoom);
  const lowest = flown.reduce((min, s) => Math.min(min, s.zoom), Number.POSITIVE_INFINITY);

  return {
    durationMs: samples[end].ms - first.ms,
    frames: samples.length,
    arcDepth: Math.max(0, edgeZoom - lowest),
    spanDegrees: spanOf(first, samples[end]),
  };
}

/**
 * **Πέταξε;** — η ερώτηση που **καμία** από τις 13 πράσινες άγκυρες δεν έκανε.
 *
 * 🔴 Μόνο αυτή θα είχε πιάσει το `maxDuration`: η κλήση γινόταν, το κάδρο προσγειωνόταν
 * σωστά, και **τίποτα** δεν κοκκίνιζε — απλώς ο άνθρωπος έβλεπε τον χάρτη **να αλλάζει**
 * αντί να **ταξιδεύει**.
 */
export function didFly(trajectory: CameraTrajectory): boolean {
  return trajectory.durationMs >= MIN_PERCEPTIBLE_MS;
}

/**
 * Κάτω από αυτό, η κίνηση **δεν γίνεται αντιληπτή ως κίνηση**.
 *
 * 🔑 Δεν είναι αυθαίρετο: το κατώφλι των **~100 ms** είναι το κλασικό όριο κάτω από το
 * οποίο μια μετάβαση διαβάζεται ως **ακαριαία**. Οι μετρημένες πραγματικές τιμές μας
 * είναι **733–3.824 ms**, δηλαδή **μία τάξη μεγέθους** πάνω — και οι σπασμένες ήταν
 * **1–2 ms**, δηλαδή δύο τάξεις κάτω. Το όριο δεν χρειάζεται ακρίβεια· χρειάζεται να
 * βρίσκεται **ανάμεσα σε δύο πληθυσμούς που απέχουν χίλιες φορές**.
 */
export const MIN_PERCEPTIBLE_MS = 100;

/**
 * **Διαβάζεται ως ταξίδι;** — δηλαδή ζουμάρισε έξω πριν μεταφερθεί.
 *
 * ⚠️ **Ισχύει ΜΟΝΟ για μεγάλα άλματα, και αυτό δεν είναι συμβιβασμός.** Σε μια
 * μετακίνηση δύο τετραγώνων δεν υπάρχει τίποτα να «δει από ψηλά» ο άνθρωπος: ο van Wijk
 * **σωστά** δεν βυθίζει το ζουμ, και μια απαίτηση καμπύλης εκεί θα ήταν λάθος απαίτηση.
 * Ο καλών λέει **ποια** άλματα είναι μεγάλα — δες `LONG_HOP_DEGREES`.
 */
export function readsAsJourney(trajectory: CameraTrajectory): boolean {
  return trajectory.arcDepth >= MIN_ARC_DEPTH;
}

/**
 * Πόσο πρέπει να βυθιστεί το ζουμ ώστε το άλμα να **διαβάζεται** ως ταξίδι.
 *
 * Ένα επίπεδο ζουμ = **διπλάσια** κλίμακα. Κάτι λιγότερο από αυτό δεν είναι «πτήση από
 * ψηλά», είναι θόρυβος στρογγυλοποίησης.
 */
export const MIN_ARC_DEPTH = 1;

/** Πάνω από τόσες μοίρες απόστασης, ένα άλμα θεωρείται **μεγάλο** και οφείλει καμπύλη. */
export const LONG_HOP_DEGREES = 1;
