/**
 * @fileoverview **ΠΩΣ ΚΙΝΕΙΤΑΙ Η ΚΑΜΕΡΑ ΤΟΥ ΧΑΡΤΗ** — μία αρχή, εννέα επιφάνειες.
 * @related types/geo/camera-frame · components/geo/use-camera-frame · lib/geo/geo-map-zoom
 * @module lib/geo/camera-motion
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔴 ΤΟ ΠΕΡΙΣΤΑΤΙΚΟ: Η ΙΔΙΑ ΕΦΑΡΜΟΓΗ ΜΙΛΟΥΣΕ ΤΕΣΣΕΡΙΣ ΓΛΩΣΣΕΣ
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * Μετρημένο **2026-09-08**: **11 κλήσεις** `flyTo`/`fitBounds`/`panBy` σε **7 αρχεία**,
 * με **τέσσερις** διάρκειες *(0 · 900 · 1000 · 2000 ms)*, **τέσσερα** περιθώρια
 * *(48 · 50 · 56 · 64 px)* και **τρία** ταβάνια ζουμ *(15 · 17 · 18)* — σε γειτονικές
 * οθόνες, **χωρίς κανείς να το έχει αποφασίσει**.
 *
 * ⚠️ **Η κίνηση της κάμερας δεν είναι αισθητική.** Είναι το μόνο πράγμα που λέει στον
 * άνθρωπο *«μετακινήθηκα, και να πού»*. Ένα ακαριαίο πήδημα διαβάζεται ως **«άλλαξε ο
 * χάρτης»**, όχι ως *«ταξίδεψα εκεί»*. Το Nestor έκανε **και τα δύο**, εναλλάξ.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🏆 ΤΟ ΕΥΡΗΜΑ ΠΟΥ ΑΛΛΑΞΕ ΤΗ ΛΥΣΗ: **ΤΑ ms ΕΙΝΑΙ ΛΑΘΟΣ ΜΟΝΑΔΑ**
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * Η προφανής θεραπεία *(«ένας πίνακας σταθερών, μία διάρκεια παντού»)* **είναι λάθος**,
 * και ο λόγος είναι μετρήσιμος: με καρφωμένη διάρκεια, ένα άλμα **200 μέτρων** και ένα
 * άλμα **400 χιλιομέτρων** διαρκούν **ακριβώς το ίδιο**. Το πρώτο μοιάζει νωθρό, το
 * δεύτερο ιλιγγιώδες. Το Material Design 3 το λέει ρητά: *«adjust each duration to
 * accommodate the distance travelled … rather than using a single duration for all
 * animations»*.
 *
 * 🔑 **Και το MapLibre ΤΟ ΛΥΝΕΙ ΗΔΗ** — υλοποιεί το `flyTo` πάνω στο
 * *«Smooth and Efficient Zooming and Panning»* των **van Wijk & Nuij (2003)**
 * *(η αναφορά είναι γραμμένη στους ίδιους τους τύπους της βιβλιοθήκης:*
 * *`https://www.win.tue.nl/~vanwijk/zoompan.pdf`)*. Η παράμετρος δεν είναι χρόνος αλλά
 * **`speed` = οθόνες ανά δευτερόλεπτο** — μέγεθος **ανεξάρτητο κλίμακας**, ακριβώς ό,τι
 * χρειάζεται ένας χάρτης Web Mercator.
 *
 * 🔴 **ΚΑΙ ΤΟ ΠΑΡΑΚΑΜΠΤΑΜΕ ΣΕ 5 ΑΠΟ ΤΑ 7 «ΤΑΞΙΔΙΑ».** Επαληθευμένο στον **εγκατεστημένο**
 * κώδικα *(`maplibre-gl 5.15.0`, `dist/maplibre-gl.js`)*, όχι στην τεκμηρίωση:
 *
 * ```js
 * e.duration = "duration" in e ? +e.duration : 1e3 * E / (…speed…)
 * ```
 *
 * Δηλαδή **η παρουσία και μόνο** του κλειδιού `duration` **βραχυκυκλώνει** τον van Wijk.
 * Και ο ίδιος ο `fitBounds` καταλήγει στο `flyTo`, όχι στο `easeTo`:
 * `_fitInternal(…){ … i.linear ? this.easeTo(i,a) : this.flyTo(i,a) }` — με το `linear`
 * αδήλωτο, **κάθε** καδράρισμα είναι van Wijk πτήση.
 *
 * ⇒ **Η εξυπνότερη λύση δεν είναι νέα αφαίρεση: είναι να ΠΑΨΟΥΜΕ να ακυρώνουμε τον
 * αλγόριθμο που οι μεγάλοι έγραψαν, και να δηλώσουμε την επιλογή στη μονάδα που είναι
 * όντως αναλλοίωτη — ΤΑΧΥΤΗΤΑ, όχι ΧΡΟΝΟ.**
 *
 * ⚠️ **Ειρωνεία που αξίζει να μείνει γραμμένη**: η **μόνη** κλήση της εφαρμογής που το
 * έκανε σωστά *(`AddressMapCandidateLayer`, «δες τα όλα»)* το έκανε **κατά λάθος** —
 * απλώς δεν πέρασε `duration` καθόλου.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * ♿ ΤΟ ΔΕΥΤΕΡΟ ΕΥΡΗΜΑ: ΔΥΟ ΠΤΗΣΕΙΣ ΑΚΥΡΩΝΑΝ ΤΗΝ ΠΡΟΣΒΑΣΙΜΟΤΗΤΑ, ΡΗΤΑ
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * Το MapLibre σέβεται **από μόνο του** το `prefers-reduced-motion`: μετατρέπει κάθε
 * `flyTo`/`fitBounds` σε `jumpTo`. Ο έλεγχος υπάρχει **τρεις φορές** στο bundle και
 * είναι `!options.essential && browser.prefersReducedMotion`.
 *
 * 🔴 Το `subapps/geo-canvas/app/useBoundaryLayers.ts` περνούσε **`essential: true`** και
 * στις **δύο** πτήσεις του — δηλαδή **οι δύο μακρύτερες κινήσεις της εφαρμογής (2000 ms)
 * ήταν οι μόνες που δεν μπορούσε να απενεργοποιήσει άνθρωπος με αιθουσαία διαταραχή**.
 * Δεν το αποφάσισε κανείς: το `essential: true` είναι αντιγραμμένο αυτούσιο από το
 * παράδειγμα *«Fly to a location»* της τεκμηρίωσης, όπου υπάρχει για να **δείξει** τη
 * σημαία.
 *
 * ⚠️ Η εξαίρεση «essential» του **WCAG 2.3.3** είναι **στενή**: ισχύει όταν η πράξη
 * *δεν γίνεται* χωρίς την κίνηση. Ο άνθρωπος φτάνει στο ίδιο ακριβώς κάδρο με `jumpTo`
 * — άρα **δεν** είναι essential. Η σημαία αφαιρέθηκε· ο σεβασμός έρχεται δωρεάν από τη
 * βιβλιοθήκη, και **γι' αυτό αυτό το αρχείο δεν ρωτά μόνο του** το
 * `lib/a11y/reduced-motion` *(δεύτερη υλοποίηση της ίδιας ερώτησης = N.18)*.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * 🔑 ΤΙ ΑΝΗΚΕΙ ΕΔΩ ΚΑΙ ΤΙ ΔΕΝ ΑΝΗΚΕΙ
 * ═════════════════════════════════════════════════════════════════════════════
 *
 * Εδώ ζει **ΠΩΣ** κινείται η κάμερα. **ΠΟΤΕ** και **ΠΡΟΣ ΤΑ ΠΟΥ** τα κρατά η επιφάνεια,
 * και αυτό είναι σκόπιμο *(ADR-846: η ακτίνα θέλει πτήση σε **κάθε** αλλαγή, το πολύγωνο
 * **μία φορά** στην άφιξη — αλλιώς ο χάρτης φεύγει κάτω από κάθε κορυφή)*. Μία μηχανή,
 * πολλές σκανδάλες.
 *
 * ⛔ **Καμία γεωμετρία δεν περνά από εδώ** — ούτε κέντρο, ούτε ορθογώνιο, ούτε ζουμ.
 * Αυτά τα λέει το `CameraFrame` *(`types/geo/camera-frame.ts`)*.
 */

/**
 * **Είδε ο άνθρωπος από πού φεύγει;** — η μία ερώτηση που κρίνει αν αξίζει πτήση.
 *
 * 🔑 **Γιατί ΔΥΟ και όχι τρεις.** Η αρχική πρόταση ήθελε τρεις προθέσεις
 * *(`settle` · `travel` · `reveal`)*. Ταξινομήθηκαν **και τα 10** καδραρίσματα της
 * εφαρμογής: **3** στο πρώτο, **7** στο δεύτερο, **0** στο τρίτο. Μια αφαίρεση με άδειο
 * σκέλος είναι πρόωρη — το τρίτο όνομα γράφεται όταν αποκτήσει **μέλος**.
 *
 * ⚠️ **Η ερώτηση δεν είναι «είναι σημαντικό;» αλλά «υπάρχει ΑΠΟ;».** Μια πτήση
 * επικοινωνεί **συνέχεια** ανάμεσα σε ένα «από» και ένα «προς». Όταν ο άνθρωπος δεν
 * είδε ποτέ το «από» *(πρώτο βάψιμο, άνοιγμα κοινοποιημένου συνδέσμου)*, η πτήση δεν
 * επικοινωνεί **τίποτα** — είναι σκέτη καθυστέρηση, και σε χάρτη αποτελεσμάτων που
 * ξανακαδράρεται είναι **ορατό τίναγμα** πάνω στην κίνηση του ίδιου του ανθρώπου.
 */
export type CameraIntent =
  /** Ο άνθρωπος **δεν είδε ποτέ** το «από»: πρώτο βάψιμο, άνοιγμα συνδέσμου με περιοχή. */
  | 'arrive'
  /** Ο άνθρωπος **κοιτούσε** τον χάρτη όταν τον μετακινήσαμε: αναζήτηση, εντοπισμός, επιλογή. */
  | 'travel';

/**
 * **Πόσο μεγάλο είναι το πράγμα που κάθεται στην άκρη;** — η μία ερώτηση που ορίζει το
 * περιθώριο.
 *
 * 🔴 Τα σημερινά τέσσερα περιθώρια *(48 · 50 · 56 · 64)* **δεν ήταν τέσσερις επιλογές**:
 * μόνο **δύο** είχαν γραμμένο λόγο *(«η πινέζα δεν ακουμπά τα χείλη» · «η ετικέτα τιμής
 * στην άκρη μοιάζει κομμένη»)*. Το `50` έγραφε *«Pattern: Google Maps fitBounds
 * padding»* — δηλαδή **καμία μέτρηση**, και το `56` δεν έγραφε τίποτα.
 */
export type FrameEdge =
  /** Πινέζα ή κύκλος — στενό σύμβολο. */
  | 'pin'
  /** Ετικέτα τιμής ή σήμα υποψηφίου — **πλατύ** σύμβολο, θέλει περισσότερο αέρα. */
  | 'label';

/**
 * **Τι ισχυρίζεται αυτό το κάδρο;** — το ταβάνι του ζουμ, ως δήλωση ακρίβειας.
 *
 * ⚠️ **Δεν είναι αισθητικό όριο, είναι όριο ΕΙΛΙΚΡΙΝΕΙΑΣ.** Χωρίς αυτό, ένα ορθογώνιο
 * **μηδενικού εμβαδού** *(ένα και μόνο αποτέλεσμα)* ζουμάρει στο μέγιστο του χάρτη και
 * δείχνει **δύο κτίρια** — προβολή που υπόσχεται ακρίβεια κτιρίου, ενώ η πηγή λέει
 * *«δρόμος»*. Η προβολή οφείλει να μένει **συνεπής με ό,τι ισχυρίζεται η ένδειξη**.
 *
 * 🔑 **Τα τρία ταβάνια ΕΠΙΒΙΩΣΑΝ του ελέγχου, τα τέσσερα περιθώρια όχι** — γιατί εδώ οι
 * τρεις τιμές απαντούν σε **τρεις διαφορετικές** ερωτήσεις επιστημικού βάρους, ενώ εκεί
 * οι τέσσερις απαντούσαν στην **ίδια**.
 */
export type PrecisionCeiling =
  /** Πρόταση γεωκωδικοποιητή, **μη επιβεβαιωμένη** — ή ορθογώνιο που μπορεί να είναι σημείο. */
  | 'suggested'
  /** Ονομασμένη περιοχή *(δρόμος, συνοικία, δήμος)* — ακρίβεια **περιοχής**, όχι κτιρίου. */
  | 'area'
  /** Διεύθυνση που ο άνθρωπος **επιβεβαίωσε** — επιτρέπεται επίπεδο κτιρίου. */
  | 'confirmed';

/**
 * **Η ταχύτητα της πτήσης σε οθόνες ανά δευτερόλεπτο** — η προεπιλογή του van Wijk.
 *
 * 🔑 **Δεν είναι αυθαίρετη και δεν είναι δική μας**: είναι η τιμή που η βιβλιοθήκη
 * επιλέγει όταν δεν της πεις τίποτα, δηλαδή η τιμή που έχει δει τα περισσότερα μάτια
 * στον κόσμο. Γράφεται **ρητά** αντί να παραλειφθεί, ώστε το αρχείο να απαντά *«ποια
 * είναι η ταχύτητα;»* χωρίς να χρειάζεται κανείς να ανοίξει το `node_modules`.
 *
 * ✅ **ΜΕΤΡΗΜΕΝΟ ΣΤΗΝ ΟΘΟΝΗ, ΟΧΙ ΥΠΟΛΟΓΙΣΜΕΝΟ** *(2026-09-09)*: κοντινή μετακίνηση
 * **884 ms** — δίπλα ακριβώς στα `900`/`1000` που κάποιος είχε διαλέξει με το μάτι. Άρα
 * η κοντινή αίσθηση **δεν αλλάζει**· αλλάζει μόνο ό,τι ήταν λάθος: οι μακρινές.
 *
 * ⚠️ **Είναι και η ΜΟΝΗ βαλβίδα.** Αν οι μακρινές πτήσεις κριθούν αργές, ανεβάζεις
 * **αυτόν** τον αριθμό — και πληρώνεις ότι θα επιταχυνθούν **και** οι κοντινές, αναλογικά.
 * Δεν υπάρχει τρόπος να πειράξεις μόνο τη μία άκρη χωρίς να σκοτώσεις τον αλγόριθμο.
 */
const TRAVEL_SCREENFULS_PER_SECOND = 1.2;

/**
 * ⛔⛔ **ΜΗΝ ΠΡΟΣΘΕΣΕΙΣ `maxDuration`. ΔΕΝ ΕΙΝΑΙ ΦΡΑΓΜΟΣ — ΕΙΝΑΙ ΕΓΚΑΤΑΛΕΙΨΗ.** ⛔⛔
 *
 * 🔴 **ΠΛΗΡΩΘΗΚΕ ΜΕ ΠΕΡΙΣΤΑΤΙΚΟ, ΣΤΟ ΖΩΝΤΑΝΟ ΠΕΡΠΑΤΗΜΑ ΤΗΣ 2026-09-09.** Η πρώτη γραφή
 * αυτού του αρχείου περνούσε `maxDuration: 2000` πιστεύοντας ότι *«κόβει τις πολύ μακριές
 * πτήσεις στα 2 δευτερόλεπτα»*. **Κάνει το αντίθετο.** Η τεκμηρίωση τύπων της ίδιας της
 * βιβλιοθήκης το λέει ρητά:
 *
 * > *«The animation's maximum duration… **If duration exceeds maximum duration, it resets
 * > to 0.**»*
 *
 * και ο εγκατεστημένος κώδικας το επιβεβαιώνει:
 * `e.maxDuration && e.duration > e.maxDuration && (e.duration = 0)`.
 *
 * ⇒ **Κάθε πτήση πάνω από το όριο γίνεται ΑΚΑΡΙΑΙΟ ΠΗΔΗΜΑ.** Μετρημένο στην οθόνη:
 *
 * | διαδρομή | με `maxDuration: 2000` | χωρίς |
 * |---|---|---|
 * | ~2 χλμ | 885 ms | 884 ms |
 * | ~15 χλμ | 723 ms | 733 ms |
 * | **~300 χλμ** | **2 ms** 🔴 | 3.824 ms |
 * | **~700 χλμ** | **1 ms** 🔴 | 3.700 ms |
 * | **μόνο ζουμ 12→17** | **1 ms** 🔴 | 2.050 ms |
 *
 * 🔑 **Ήταν χειρότερο από το πρόβλημα που λύναμε**: οι πτήσεις των διοικητικών ορίων
 * πήγαν από `2000 ms` σε **1 ms**. Και **κανένα test δεν το έβλεπε** — μετρούσαν *«κλήθηκε
 * το flyTo;»*, όχι *«πέταξε;»*. Το βρήκε **μόνο** το ρολόι πάνω στον ζωντανό χάρτη.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΚΑΙ ΤΟ ΤΑΒΑΝΙ ΔΕΝ ΧΡΕΙΑΖΕΤΑΙ — ΤΟ ΕΔΕΙΞΕ Η ΙΔΙΑ Η ΜΕΤΡΗΣΗ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Τα **700 χλμ κοστίζουν ΛΙΓΟΤΕΡΟ από τα 300** *(3.700 έναντι 3.824 ms)*. Δεν είναι
 * ανωμαλία: είναι **ακριβώς** η ιδιότητα του van Wijk. Και οι δύο πτήσεις πρέπει να
 * ζουμάρουν έξω σε παρόμοιο ύψος· από εκεί και πέρα η επιπλέον απόσταση κοστίζει
 * **λογαριθμικά**, όχι γραμμικά. Άρα η διάρκεια **δεν αποκλίνει**: όλο το εύρος της
 * Ελλάδας χωρά σε **0,7 – 3,8 δευτερόλεπτα**, και το χειρότερο σενάριο *(«όλη η χώρα»,
 * ζουμ 12→6)* είναι μόλις **2,45 s**.
 *
 * ⚠️ Αν κάποτε χρειαστεί όντως ταβάνι, **δεν υπάρχει έτοιμο**: θα σήμαινε να υπολογίσουμε
 * εμείς τη διάρκεια και να την περάσουμε ως `duration` — δηλαδή να ξανασκοτώσουμε τον van
 * Wijk, που είναι όλο το νόημα αυτού του αρχείου. Η σωστή βαλβίδα είναι το `speed`.
 */

/** Πινέζα: αρκεί να μην ακουμπά τα χείλη του πλαισίου. */
const EDGE_PIN_PX = 48;

/** Ετικέτα: πλατύτερο σύμβολο ⇒ μεγαλύτερος αέρας, αλλιώς διαβάζεται κομμένη. */
const EDGE_LABEL_PX = 64;

const CEILING_ZOOM: Readonly<Record<PrecisionCeiling, number>> = {
  suggested: 15,
  area: 17,
  confirmed: 18,
};

const EDGE_PADDING: Readonly<Record<FrameEdge, number>> = {
  pin: EDGE_PIN_PX,
  label: EDGE_LABEL_PX,
};

/**
 * Οι επιλογές κίνησης, **ως ένωση δύο ασύμβατων σχημάτων**.
 *
 * 🔴 **ΔΕΝ ΕΙΝΑΙ ΚΑΘΑΡΟΤΗΤΑ ΤΥΠΩΝ — ΕΙΝΑΙ ΠΑΓΙΔΑ ΠΟΥ ΚΛΕΙΝΕΙ.** Ένα προαιρετικό
 * `duration?: number` θα ήταν **ενεργά επικίνδυνο**: το MapLibre ελέγχει
 * **`"duration" in options`**, όχι την τιμή. Ένα αντικείμενο με `duration: undefined`
 * περνά τον έλεγχο και υπολογίζει `+undefined` ⇒ **`NaN`** ⇒ πτήση που δεν τελειώνει
 * ποτέ. Με ένωση, το κλειδί **δεν υπάρχει καν** στο σκέλος του ταξιδιού: το λάθος
 * γίνεται **αδύνατο να γραφτεί**, όχι «απαγορευμένο με σχόλιο».
 */
type CameraFlightOptions =
  | { readonly duration: 0 }
  | { readonly speed: number };

/**
 * Οι επιλογές καδραρίσματος έκτασης = κίνηση **συν** τα δύο όρια του `fitBounds`.
 *
 * ⚠️ **ΤΑ ΔΥΟ ΣΧΗΜΑΤΑ ΔΕΝ ΕΞΑΓΟΝΤΑΙ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ.** Η ερώτηση *«ποιος καταναλώνει
 * ό,τι μόλις εξήγαγα;»* τα βρήκε με **μηδέν** καταναλωτές — το ίδιο σχήμα που πλήρωσε το
 * `COVERAGE_MAP_HEIGHT_CLASS` της Φ4β. Το συμβόλαιο το κουβαλούν οι **δύο συναρτήσεις**·
 * όποιος χρειαστεί το όνομα το παίρνει με `ReturnType<typeof cameraFraming>`, και τότε
 * εξάγεται — με καταναλωτή.
 */
type CameraFramingOptions = CameraFlightOptions & {
  readonly padding: number;
  readonly maxZoom: number;
};

/**
 * **Πώς κινείται η κάμερα** για μια δεδομένη πρόθεση.
 *
 * @example
 * map.flyTo({ center, zoom, ...cameraFlight('travel') });
 */
export function cameraFlight(intent: CameraIntent): CameraFlightOptions {
  if (intent === 'arrive') return { duration: 0 };
  return { speed: TRAVEL_SCREENFULS_PER_SECOND };
}

/**
 * **Πώς κινείται και πόσο σφιχτά κλείνει** η κάμερα γύρω από μια έκταση.
 *
 * ⚠️ Και οι τρεις παράμετροι είναι **υποχρεωτικές, χωρίς προεπιλογή**, επίτηδες: μια
 * προεπιλογή θα ήταν ακριβώς η σιωπηλή παράμετρος που αυτό το αρχείο υπάρχει για να
 * καταργήσει. Ο επόμενος που προσθέτει χάρτη **οφείλει** να απαντήσει *«είδε ο άνθρωπος
 * από πού φεύγει;»*, *«τι κάθεται στην άκρη;»* και *«τι ισχυρίζεται το κάδρο;»* — τρεις
 * ερωτήσεις με **σωστή** απάντηση, στη θέση ενός *«πόσα ms;»* που έχει άπειρες.
 *
 * @example
 * map.fitBounds(bounds, cameraFraming('arrive', 'label', 'suggested'));
 */
export function cameraFraming(
  intent: CameraIntent,
  edge: FrameEdge,
  ceiling: PrecisionCeiling,
): CameraFramingOptions {
  return {
    ...cameraFlight(intent),
    padding: EDGE_PADDING[edge],
    maxZoom: CEILING_ZOOM[ceiling],
  };
}
