/**
 * ΕΓΣΑ'87 (GGRS87) ↔ WGS84 — η **μετάθεση datum** που λείπει από το {@link ./egsa87-projection}.
 *
 * ## Γιατί υπάρχει αυτό το αρχείο (και γιατί ΔΕΝ έλειπε μέχρι σήμερα)
 * Το `egsa87-projection.ts` κάνει **προβολή**: ελλειψοειδές ↔ κάνναβος, πάνω στο GRS80. Αυτό είναι
 * σωστό και πλήρες για τον μοναδικό του σημερινό καταναλωτή — τη **σύγκλιση μεσημβρινού** του
 * βέλους Βορρά (ADR-656 M12), όπου η ταυτότητα του datum είναι **αδιάφορη**: η γωνία Grid North →
 * True North δεν αλλάζει επειδή μετακινήθηκε η αρχή του ελλειψοειδούς κατά διακόσια μέτρα.
 *
 * Τη στιγμή όμως που ένα **υπόβαθρο χάρτη** μπαίνει κάτω από το σχέδιο, η ερώτηση αλλάζει: τα
 * πλακίδια του χάρτη είναι **WGS84**, το σχέδιο είναι **ΕΓΣΑ'87**, και τα δύο datum **δεν
 * ταυτίζονται**. Το ΕΓΣΑ'87 προσαρτά το GRS80 σε γεωκεντρική αρχή μετατοπισμένη κατά
 * `(−199,87 · 74,79 · 246,62)` m (EPSG:1272) — μέτρο **326 m**.
 *
 * 🔴 **ΤΟ ΜΕΓΕΘΟΣ ΜΕΤΡΗΘΗΚΕ, ΚΑΙ ΕΙΝΑΙ ΔΥΟ ΤΑΞΕΙΣ ΠΑΝΩ ΑΠΟ ΤΗΝ ΠΡΩΤΗ ΕΚΤΙΜΗΣΗ.** Το σχόλιο
 * αυτό έγραφε αρχικά «~2-6 m, μισό πλάτος δρόμου». Η άγκυρα `Μ1` του
 * `__tests__/basemap-projection.test.ts` το μέτρησε στην Ακρόπολη: **324,86 m**. Ο λόγος είναι
 * ότι η μετάθεση είναι σχεδόν ολόκληρη **οριζόντια** στο γεωγραφικό πλάτος της Ελλάδας — δεν
 * μοιράζεται με την κατακόρυφη. Δηλαδή χωρίς αυτή τη μετάθεση ο χάρτης δεν κάθεται λίγο δίπλα:
 * κάθεται **τρία οικοδομικά τετράγωνα** μακριά.
 *
 * Η διαφορά δεν είναι ακαδημαϊκή. Σφάλμα μέτρων θα διαβαζόταν ως «ανακρίβεια του χάρτη» και θα
 * γινόταν ανεκτό· σφάλμα εκατοντάδων μέτρων φαίνεται αμέσως και **δεν** παραπλανά. Το επικίνδυνο
 * σενάριο ήταν το πρώτο, και γι' αυτό η άγκυρα μετρά **μέγεθος**, όχι απλώς «διάφορο του μηδενός».
 *
 * ⚠️ Γι' αυτό ζει σε **δικό του** αρχείο και όχι μέσα στο `egsa87-projection.ts`: εκείνο απαντά
 * «πού πέφτει αυτό το σημείο στον κάνναβο», αυτό απαντά «σε ποιο **σχήμα της Γης** μετρήθηκε».
 * Δύο ερωτήσεις, δύο σπίτια. Αν συγχωνεύονταν, ο επόμενος καταναλωτής της προβολής θα πλήρωνε
 * σιωπηλά μια μετάθεση που δεν ζήτησε (το βέλος Βορρά είναι ακριβώς τέτοιος καταναλωτής).
 *
 * ## Το μοντέλο
 * Γεωκεντρική μετάθεση 3 παραμέτρων (EPSG:9603, «Geocentric translations»), η **επίσημη** σχέση
 * EPSG:4121 (GGRS87) → EPSG:4326 (WGS84):
 *
 *     [X Y Z]_WGS84 = [X Y Z]_GGRS87 + (ΔX, ΔY, ΔZ)
 *
 * Η διαδρομή είναι γεωδαιτικό → ECEF → μετάθεση → ECEF → γεωδαιτικό, με **διαφορετικό
 * ελλειψοειδές σε κάθε άκρο** (GRS80 ↔ WGS84). Η διαφορά τους είναι μόνο στην πλάτυνση
 * (`1/298,257222101` έναντι `1/298,257223563`) και αντιστοιχεί σε **< 0,1 mm** — αλλά γράφεται
 * ρητά, γιατί μια σταθερά που «είναι σχεδόν ίδια» και δεν δηλώνεται είναι μια σταθερά που ο
 * επόμενος αναγνώστης δεν μπορεί να επαληθεύσει.
 *
 * Μονάδες: **μοίρες / μέτρα** παντού (η σύμβαση της γεωδαισίας, ίδια με το `egsa87-projection`).
 * Οι καταναλωτές που κρατούν canonical mm (ADR-462) μετατρέπουν στο σύνορο. Καθαρό module —
 * μηδέν React/DOM/store.
 *
 * @see ./egsa87-projection.ts — η προβολή (κάνναβος ↔ ελλειψοειδές), το άλλο μισό
 * @see https://epsg.org/transformation/EPSG::1272 — GGRS87 to WGS 84 (1)
 */

/**
 * Γεωγραφικές συντεταγμένες (μοίρες) — υπερσύνολο του `LatLon` της προβολής.
 *
 * ⚠️ Το `height` **επιστρέφεται** και δεν είναι διακοσμητικό: η μετάθεση datum αλλάζει και το
 * ελλειψοειδές ύψος, οπότε πετώντας το, ο κύκλος μετάβασης-επιστροφής δεν κλείνει ακριβώς. Η
 * άγκυρα `Μ2` το μέτρησε σε **1,59 mm** — αμελητέο για χάρτη, αλλά ένα κατώφλι που «χαλαρώνει
 * μέχρι να γίνει πράσινο» κρύβει το γιατί. Επιστρέφοντάς το, ο κύκλος κλείνει στα όρια της
 * αριθμητικής και το test αποδεικνύει τα **μαθηματικά**, όχι την ανοχή μας.
 */
export interface GeodeticPoint {
  readonly lat: number;
  readonly lon: number;
  /** Ελλειψοειδές ύψος (m) στο ελλειψοειδές-προορισμό. */
  readonly height: number;
}

const DEG = Math.PI / 180;

/**
 * Οι δύο σχεδόν-ταυτόσημες μορφές της Γης που εμπλέκονται. Ονομάζονται ξεχωριστά **επίτηδες**:
 * το ότι διαφέρουν κατά < 0,1 mm είναι μέτρηση, όχι υπόθεση, και ο αναγνώστης πρέπει να μπορεί
 * να τη δει.
 */
interface Ellipsoid {
  /** Μεγάλος ημιάξονας (m). */
  readonly a: number;
  /** Πλάτυνση. */
  readonly f: number;
}

/** GRS80 — το ελλειψοειδές του ΕΓΣΑ'87 (GGRS87). */
const GRS80: Ellipsoid = { a: 6_378_137.0, f: 1 / 298.257222101 };

/** WGS84 — το ελλειψοειδές των πλακιδίων χάρτη και του GPS. */
const WGS84: Ellipsoid = { a: 6_378_137.0, f: 1 / 298.257223563 };

/**
 * EPSG:1272 — γεωκεντρική μετάθεση GGRS87 → WGS84 (m).
 *
 * ⚠️ **Η κατεύθυνση είναι μέρος του ορισμού**: προστίθεται πηγαίνοντας **προς** το WGS84 και
 * αφαιρείται επιστρέφοντας. Ένα πρόσημο ανάποδα δίνει σφάλμα ~10 m — αρκετά μικρό ώστε ο χάρτης
 * να συνεχίσει να «μοιάζει σωστός», που είναι ακριβώς ο λόγος που δηλώνεται εδώ και δοκιμάζεται
 * με κύκλο μετάβασης-επιστροφής αντί για οπτικό έλεγχο.
 */
const SHIFT_TO_WGS84 = { dx: -199.87, dy: 74.79, dz: 246.62 } as const;

/** Καρτεσιανές γεωκεντρικές (ECEF) συντεταγμένες, σε μέτρα. */
interface Ecef {
  readonly x: number;
  readonly y: number;
  readonly z: number;
}

/** Γεωδαιτικό (μοίρες, υψόμετρο m) → ECEF (m) πάνω στο `e`. Κλειστός τύπος, χωρίς επανάληψη. */
function geodeticToEcef(lat: number, lon: number, height: number, e: Ellipsoid): Ecef {
  const phi = lat * DEG;
  const lambda = lon * DEG;
  const e2 = e.f * (2 - e.f);
  const sinPhi = Math.sin(phi);
  const cosPhi = Math.cos(phi);
  // Ακτίνα καμπυλότητας κάθετα στον μεσημβρινό.
  const nu = e.a / Math.sqrt(1 - e2 * sinPhi * sinPhi);
  return {
    x: (nu + height) * cosPhi * Math.cos(lambda),
    y: (nu + height) * cosPhi * Math.sin(lambda),
    z: (nu * (1 - e2) + height) * sinPhi,
  };
}

/**
 * ECEF (m) → γεωδαιτικό (μοίρες, υψόμετρο m) πάνω στο `e`, με τη μέθοδο **Bowring**.
 *
 * Κλειστή μορφή, όχι επαναληπτική: μία αποτίμηση δίνει ακρίβεια καλύτερη από **0,1 mm** για
 * γήινα υψόμετρα. Επιλέχθηκε ακριβώς γι' αυτό — ένας επαναληπτικός βρόχος θα εισήγαγε κριτήριο
 * τερματισμού, δηλαδή έναν ακόμη αριθμό που κανείς δεν θα ήξερε πώς να επαληθεύσει.
 */
function ecefToGeodetic(p: Ecef, e: Ellipsoid): { lat: number; lon: number; height: number } {
  const e2 = e.f * (2 - e.f);
  const b = e.a * (1 - e.f);
  const ep2 = (e.a * e.a - b * b) / (b * b);
  const r = Math.hypot(p.x, p.y);
  const theta = Math.atan2(p.z * e.a, r * b);
  const sinTheta = Math.sin(theta);
  const cosTheta = Math.cos(theta);
  const phi = Math.atan2(
    p.z + ep2 * b * sinTheta ** 3,
    r - e2 * e.a * cosTheta ** 3,
  );
  const lambda = Math.atan2(p.y, p.x);
  const sinPhi = Math.sin(phi);
  const nu = e.a / Math.sqrt(1 - e2 * sinPhi * sinPhi);
  return {
    lat: phi / DEG,
    lon: lambda / DEG,
    height: r / Math.cos(phi) - nu,
  };
}

/**
 * ΕΓΣΑ'87 / GGRS87 (γεωγραφικές, μοίρες) → **WGS84** (γεωγραφικές, μοίρες).
 *
 * Το `height` είναι το **ελλειψοειδές** ύψος (m) και είναι προαιρετικό: για επίπεδη τοποθέτηση
 * υποβάθρου η επιλογή του επηρεάζει το αποτέλεσμα κατά κλάσματα του χιλιοστού, οπότε το 0 είναι
 * ασφαλής προεπιλογή. Δηλώνεται όμως ως παράμετρος, ώστε ένας μελλοντικός καταναλωτής με
 * πραγματικά υψόμετρα να μη χρειαστεί δεύτερη συνάρτηση.
 */
export function ggrs87ToWgs84(lat: number, lon: number, height = 0): GeodeticPoint {
  const src = geodeticToEcef(lat, lon, height, GRS80);
  const shifted: Ecef = {
    x: src.x + SHIFT_TO_WGS84.dx,
    y: src.y + SHIFT_TO_WGS84.dy,
    z: src.z + SHIFT_TO_WGS84.dz,
  };
  return ecefToGeodetic(shifted, WGS84);
}

/**
 * **WGS84** (γεωγραφικές, μοίρες) → ΕΓΣΑ'87 / GGRS87 (γεωγραφικές, μοίρες).
 *
 * Ο ακριβής αντίστροφος του {@link ggrs87ToWgs84}: ίδιος πυρήνας, μετάθεση με αντίθετο πρόσημο,
 * ελλειψοειδή εναλλαγμένα. Ζει **δίπλα** στον εμπρός δρόμο επίτηδες — η μέρα που οι δύο
 * κατευθύνσεις θα ζούσαν σε δύο αρχεία είναι η μέρα που η μία θα διορθωνόταν και η άλλη όχι
 * (το ίδιο σκεπτικό με το `project`/`unproject` του `topo-display-frame`).
 */
export function wgs84ToGgrs87(lat: number, lon: number, height = 0): GeodeticPoint {
  const src = geodeticToEcef(lat, lon, height, WGS84);
  const shifted: Ecef = {
    x: src.x - SHIFT_TO_WGS84.dx,
    y: src.y - SHIFT_TO_WGS84.dy,
    z: src.z - SHIFT_TO_WGS84.dz,
  };
  return ecefToGeodetic(shifted, GRS80);
}
