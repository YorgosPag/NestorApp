/**
 * Το **ελάχιστο** σχήμα που χρειάζεται η απόφαση.
 *
 * ⚠️ **`unknown` και όχι `boolean`, επίτηδες**: οι πραγματικοί καλούντες κρατούν το
 * πεδίο **προαιρετικό** και μερικοί το διαβάζουν από ωμό έγγραφο Firestore, όπου
 * μπορεί να λείπει ή να είναι ό,τι έγραψε παλιά μια φόρμα. Ένα `boolean` εδώ θα
 * ανάγκαζε τους καλούντες σε `as` — δηλαδή θα μετέφερε το ψέμα από τη σύγκριση στον
 * μετασχηματισμό τύπου. *(Το `building-update.handler.ts` το έκανε ήδη ακριβώς έτσι.)*
 */
export interface PrimaryFlagged {
  readonly isPrimary?: unknown;
}

/**
 * **Η εγγραφή που εκπροσωπεί αυτή τη λίστα** — ή `undefined` αν δεν υπάρχει καμία.
 *
 * 🔑 **Κύριο πρώτα, αλλιώς το πρώτο — και η σειρά ΔΕΝ αντιστρέφεται.** Η σειρά της
 * λίστας είναι **σειρά καταχώρησης**, όχι προτίμηση. Ένα σκέτο `list[0]` διαλέγει το
 * παλιό email της δουλειάς επειδή καταχωρήθηκε πρώτο, και **κανείς δεν το μαθαίνει**:
 * το μήνυμα φεύγει κανονικά, απλώς στον λάθος παραλήπτη.
 *
 * 🔴 **`=== true`, ΠΟΤΕ truthy — και είναι η υπάρχουσα αυθεντία, όχι νέα αυστηρότητα**:
 * το {@link primaryEmailOf} (ADR-777 §8.33) ήδη συγκρίνει έτσι. Ένα truthy `if` θα
 * δεχόταν `'false'`, `1`, `'no'` — τιμές που **υπάρχουν** σε ωμά έγγραφα από παλιές
 * φόρμες, και που θα σήμαιναν *«αυτό είναι το κύριο»* χωρίς κανείς να το έχει πει.
 *
 * ⚠️ **ΦΙΛΤΡΑΡΕ ΠΡΙΝ, αν το «χρήσιμο» έχει νόημα**:
 * `primaryOrFirst(emails.filter(hasAddress))` — αλλιώς το «πρώτο» μπορεί να είναι μια
 * κενή εγγραφή από μισοσυμπληρωμένη φόρμα, που **δεν είναι `undefined`** και έτσι
 * περνά κάθε έλεγχο «υπάρχει;» μέχρι να σκάσει στον πάροχο.
 *
 * @example
 * primaryOrFirst(addresses)                              // «κύριο ή πρώτο»
 * primaryOrFirst(emails.filter((e) => e.email !== ''))   // «κύριο ή πρώτο ΧΡΗΣΙΜΟ»
 */
export function primaryOrFirst<T extends PrimaryFlagged>(
  entries: readonly T[] | null | undefined,
): T | undefined {
  if (!Array.isArray(entries)) return undefined;

  return entries.find((entry) => entry.isPrimary === true) ?? entries[0];
}
