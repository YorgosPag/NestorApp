/**
 * @fileoverview **Οι διευθύνσεις της προσφοράς** — γραμμένες μία φορά.
 * @related ADR-777 §7 (Α12 · Α14) · §8.12 (CHECK 3.52) · lib/demand/demand-routes.ts
 * @module lib/owner-property/owner-property-routes
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ `/offers` ΚΑΙ ΟΧΙ `/properties` — **μετρημένο, όχι γούστο**
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το `/properties` **είναι πιασμένο**: το `app/(app)/properties` το σερβίρει ήδη. Τα
 * route groups **δεν εμφανίζονται στη διεύθυνση**, οπότε ένα `(me)/properties` θα
 * ήταν **σύγκρουση διαδρομής** — δύο σελίδες που διεκδικούν το ίδιο URL, δηλαδή
 * ακριβώς η κλάση σφάλματος που το **CHECK 3.49** φρουρεί για τα ADR.
 *
 * 🔑 **Και το `/offers` δεν είναι δεύτερη επιλογή — είναι η σωστή.** Η διαδρομή
 * ονομάζει **την πράξη**, όπως και η αδελφή της: `/demands` = «**ζητώ**», `/offers` =
 * «**προσφέρω**». Ο τύπος ονομάζει την **οντότητα** ({@link OwnerProperty}), γιατί
 * απαντά άλλο ερώτημα: *«τι είναι αυτό το έγγραφο;»*, όχι *«τι ήρθε να κάνει εδώ ο
 * άνθρωπος;»*.
 *
 * ⚠️ **ΔΕΝ συγκρούεται με το `PropertyOffer`** (η **διάθεση**, στοιχείο πίνακα μέσα
 * στο ακίνητο): εκείνο είναι όνομα **τύπου**, αυτό όνομα **διαδρομής**. Δεν
 * μοιράζονται χώρο ονομάτων — και το πρόθεμα ταυτότητας τα ξεχωρίζει ούτως ή άλλως
 * (`ownp_*` vs `offr_*`).
 *
 * ⚠️ **Ξεχωριστό αρχείο από το `listing-routes.ts`, με τον ίδιο λόγο που είναι
 * ξεχωριστό και το `demand-routes.ts`**: εκείνο κρατά τις **δημόσιες** διευθύνσεις —
 * τις βλέπει ο ανώνυμος, τις διαβάζει η μηχανή αναζήτησης, μοιράζονται σε σύνδεσμο.
 * Αυτές απαιτούν **ταυτότητα** και δεν επιτρέπεται να ευρετηριαστούν ποτέ
 * (`(me)/layout.tsx` → `robots: noindex`). Δύο σύνολα με **αντίθετο** συμβόλαιο
 * δημοσιότητας σε ένα αρχείο σημαίνει ότι η επόμενη προσθήκη διαλέγει ακροατήριο
 * **σιωπηλά**.
 *
 * **Layering**: leaf — μόνο σταθερές και σύνθεση συμβολοσειρών.
 */

/**
 * **Τα ακίνητά μου** — ο κατάλογος του ανθρώπου.
 *
 * 🔑 **Πληθυντικός, και είναι απόφαση μοντέλου**: τίποτα δεν περιορίζει έναν άνθρωπο
 * σε **ένα** ακίνητο — ο κληρονόμος με τρία διαμερίσματα και μια αποθήκη είναι ο
 * κανόνας, όχι η εξαίρεση. Ενικός εδώ θα προδίκαζε **μία** ανά χρήστη, και θα το
 * ανακάλυπτε κανείς όταν ήταν αργά. Ίδιο σκεπτικό με το `MY_DEMANDS_ROUTE`.
 */
import { typedHref } from '@/lib/workspace/route-worlds';

export const MY_OFFERS_ROUTE = '/offers' as const;

/**
 * **Καταχώρηση ακινήτου** — αποκλειστικά desktop (**Α8**).
 *
 * 🔑 **Ξεχωριστή διαδρομή, ΟΧΙ κατάσταση μέσα στον κατάλογο** — και ο λόγος είναι
 * **μετρημένος**: το route-level code splitting του App Router είναι **αυτόματο**
 * (*«Next.js automatically creates a separate JavaScript bundle for each route … only
 * the JavaScript required for that page is downloaded»*). Άρα το βάρος της φόρμας
 * **δεν ταξιδεύει καν** προς όποιον δεν την άνοιξε.
 *
 * Ένα πάνελ δημιουργίας μέσα στο {@link MY_OFFERS_ROUTE} θα ερχόταν στο **ίδιο**
 * bundle με τον κατάλογο — δηλαδή θα φορτωνόταν σε **κάθε κινητό** που ανοίγει τη
 * λίστα του, και το «μόνο desktop» θα ήταν δήλωση προθέσεων.
 */
export const NEW_OFFER_ROUTE = '/offers/new' as const;

/** Η βάση της **μίας** καταχώρησης. Δυναμικό τμήμα: η ταυτότητα (`ownp_*`). */
export const OFFER_DETAIL_ROUTE_BASE = '/offers';

/**
 * Η σελίδα **μιας** καταχώρησης — θέαση, επεξεργασία, απόσυρση.
 *
 * ⚠️ `encodeURIComponent` παρότι οι enterprise ταυτότητες είναι ασφαλείς χαρακτήρες:
 * η ταυτότητα έρχεται από **δεδομένα**, και μια διεύθυνση που σπάει σε ένα `#` θα
 * αστοχούσε **σιωπηλά** σε ένα μόνο έγγραφο — το χειρότερο είδος σφάλματος, γιατί
 * μοιάζει με «δεν υπάρχει».
 */
export function offerDetailHref(ownerPropertyId: string) {
  return typedHref(`${OFFER_DETAIL_ROUTE_BASE}/${encodeURIComponent(ownerPropertyId)}`);
}
