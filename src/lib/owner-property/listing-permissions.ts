import type { OwnerProperty } from '@/types/owner-property';

import { custodyOf, mayAdminister, type ListingActor } from './listing-custody';

// =============================================================================
// 1. ΟΙ ΠΡΑΞΕΙΣ — κλειστό σύνολο
// =============================================================================

/**
 * **Ό,τι μπορεί να συμβεί σε μια αγγελία**, ονομαστικά.
 *
 * 🔴 **Χωρισμένες σε αυτό το επίπεδο λεπτομέρειας επίτηδες.** Ένα ενιαίο «edit» δεν θα
 * μπορούσε να εκφράσει την απόφαση Giorgio (Α3), όπου ο ιδιώτης κρατά **και** τιμή
 * **και** περιεχόμενο αλλά **όχι** τον σύνδεσμο συγκατάθεσης — που είναι εργαλείο του
 * γραφείου προς **τον ίδιο**, και θα ήταν παράλογο να τον διαχειρίζεται ο παραλήπτης.
 */
export const LISTING_ACTIONS = [
  /** Εμφανίζεται στον κατάλογό του. */
  'view',
  /** Τίτλος, φωτογραφίες, εμβαδόν, όροφος, θέση. */
  'editContent',
  /** Ζητούμενο τίμημα / μίσθωμα. **Ξεχωριστό από το περιεχόμενο**, γιατί είναι ο όρος που ο ιδιοκτήτης αλλάζει συχνότερα και τον αφορά άμεσα. */
  'setPrice',
  /** Απόσυρση από τον δημόσιο χάρτη — **η αγγελία μένει**, παύει να δημοσιεύεται. */
  'withdraw',
  /** Τερματισμός της **εντολής**: ο ιδιοκτήτης ανακαλεί ή το γραφείο παραιτείται. */
  'endMandate',
  /** Ξαναστείλε / ακύρωσε τον σύνδεσμο συγκατάθεσης (ADR-777 §8.34). */
  'manageConsentLink',
] as const;

export type ListingAction = (typeof LISTING_ACTIONS)[number];

/**
 * **Η απάντηση για κάθε πράξη — καμία δεν λείπει.**
 *
 * 🔑 **`Record`, ΟΧΙ `Set`, και ο λόγος είναι ο μεταγλωττιστής.** Με σύνολο, μια νέα
 * πράξη θα σήμαινε σιωπηλά «όχι» για **όλους** — δηλαδή απόφαση που κανείς δεν πήρε.
 * Με `Record` πάνω σε κλειστό σύνολο, η προσθήκη πράξης **δεν μεταγλωττίζεται** μέχρι
 * κάποιος να απαντήσει για **κάθε** ρόλο. Ίδιο δόγμα με το `CAPABILITY_STATUSES` του
 * ADR-824: *«πέμπτη κατάσταση ΔΕΝ μεταγλωττίζεται»*.
 */
export type ListingPermissions = Readonly<Record<ListingAction, boolean>>;

// =============================================================================
// 2. ΤΑ ΤΡΙΑ ΣΥΝΟΛΑ
// =============================================================================

/** Κανένα δικαίωμα — **η προεπιλογή**, fail-closed. */
const NOTHING: ListingPermissions = {
  view: false,
  editContent: false,
  setPrice: false,
  withdraw: false,
  endMandate: false,
  manageConsentLink: false,
};

/**
 * **Ο ιδιοκτήτης** — ό,τι κρατά ο άνθρωπος πάνω στην περιουσία του (ADR-827 Α3).
 *
 * ⚠️ **Το `manageConsentLink` λείπει επίτηδες**, και δεν είναι περικοπή: ο σύνδεσμος
 * συγκατάθεσης είναι το μήνυμα που το γραφείο στέλνει **σε αυτόν**. Παραλήπτης που
 * ξαναστέλνει το γράμμα του εαυτού του δεν είναι δικαίωμα — είναι σύγχυση ρόλων.
 */
const OWNER: ListingPermissions = {
  view: true,
  editContent: true,
  setPrice: true,
  withdraw: true,
  endMandate: true,
  manageConsentLink: false,
};

/**
 * **Το γραφείο** — ό,τι χρειάζεται για να δουλέψει την εντολή.
 *
 * ⚠️ Το `endMandate` **υπάρχει** και εδώ, αλλά σημαίνει **παραίτηση**, όχι ανάκληση:
 * ένα γραφείο πρέπει να μπορεί να αφήσει εντολή που δεν θέλει. Ο δράστης διαφέρει, η
 * πράξη είναι η ίδια — και ποιος την έκανε το κρατά το ίχνος ελέγχου, όχι ο τύπος.
 */
const AGENCY: ListingPermissions = {
  view: true,
  editContent: true,
  setPrice: true,
  withdraw: true,
  endMandate: true,
  manageConsentLink: true,
};

// =============================================================================
// 3. Ο ΚΡΙΤΗΣ
// =============================================================================

/** Ένωση δύο συνόλων — για τον άνθρωπο που είναι **και** συγγραφέας **και** μέλος. */
function union(a: ListingPermissions, b: ListingPermissions): ListingPermissions {
  return {
    view: a.view || b.view,
    editContent: a.editContent || b.editContent,
    setPrice: a.setPrice || b.setPrice,
    withdraw: a.withdraw || b.withdraw,
    endMandate: a.endMandate || b.endMandate,
    manageConsentLink: a.manageConsentLink || b.manageConsentLink,
  };
}

/** Τα δύο πεδία που καθορίζουν τον χώρο — **και τίποτε άλλο**, όπως στο `custodyOf`. */
type PermissionFields = Pick<OwnerProperty, 'authorUserId' | 'authorCompanyId'>;

/**
 * **Τι επιτρέπεται σε αυτόν τον άνθρωπο πάνω σε αυτή την αγγελία.**
 *
 * Δύο ανεξάρτητες πηγές δικαιώματος, και η απάντηση είναι η **ένωσή** τους:
 *
 * | Πηγή | Κριτήριο | Zanzibar |
 * |---|---|---|
 * | **ο χώρος** | {@link mayAdminister} πάνω στο {@link custodyOf} | κληρονομιά από το δοχείο |
 * | **ο συγγραφέας** | `authorUserId === uid` | **ρητό grant στον πόρο** |
 *
 * 🔴 **ΔΕΝ διαβάζει `mandate.kind`, και είναι ρητή απαγόρευση.** Το σχόλιο του
 * {@link custodyOf} την γράφει: *«η εντολή είναι **σχέση με τον ιδιοκτήτη**, η
 * θεματοφυλακή είναι **χώρος εργασίας**… η μέρα που θα αποκλίνουν δεν πρέπει να τις
 * βρει δεμένες»*. Ο ιδιώτης κρατά τα δικαιώματά του επειδή **είναι ο συγγραφέας** —
 * όχι επειδή η εντολή λέει κάτι.
 *
 * ⚠️ **«Επιτρέπεται» ≠ «υπάρχει».** Το `endMandate: true` λέει *«θα σου το επέτρεπα»*,
 * όχι *«υπάρχει εντολή να τερματίσεις»*. Το δεύτερο το ξέρει **μόνο** το
 * `mandate.kind`, και το ρωτά ο καλών. Δύο ερωτήσεις σε μία συνάρτηση θα ήταν δύο
 * δόγματα σε μία πόρτα — ακριβώς η ένσταση που το `listing-custody.ts` κατέγραψε και
 * τήρησε.
 */
export function permissionsOn(
  property: PermissionFields,
  actor: ListingActor,
): ListingPermissions {
  const custody = custodyOf(property);

  // 🔴 **ΤΟ ΔΟΧΕΙΟ ΚΑΘΟΡΙΖΕΙ ΠΟΙΟ ΣΥΝΟΛΟ ΚΛΗΡΟΝΟΜΕΙΤΑΙ — όχι μόνο αν κληρονομείται.**
  //    Η πρώτη γραφή έδινε {@link AGENCY} σε κάθε επιτυχία του `mayAdminister`, άρα ο
  //    ιδιώτης σε **δική του** αγγελία έπαιρνε `manageConsentLink: true` — δικαίωμα σε
  //    σύνδεσμο που **δεν υπάρχει**, γιατί δεν υπάρχει εντολή. Αβλαβές στην πράξη,
  //    **ψευδές** στη σημασία: ένας «αδρανής φρουρός» αντεστραμμένος (ADR-749 §5).
  //    Το βρήκε η άγκυρα Κ6, όχι η ανάγνωση.
  const fromSpace = !mayAdminister(custody, actor)
    ? NOTHING
    : custody.kind === 'company'
      ? AGENCY
      : OWNER;

  // ⚠️ Κενός/απών συγγραφέας δεν ταιριάζει με τίποτα — ούτε με κενό actor.uid.
  //    Ίδια παγίδα με το `hasTenant` του `listing-custody`: δύο κενά που «ταιριάζουν»
  //    σε αφελή `===` δίνουν δικαίωμα σε άγνωστον.
  const isAuthor =
    typeof property.authorUserId === 'string' &&
    property.authorUserId.length > 0 &&
    property.authorUserId === actor.uid;

  return isAuthor ? union(fromSpace, OWNER) : fromSpace;
}

/**
 * **Επιτρέπεται αυτή η μία πράξη;** — η μορφή που θέλουν οι πύλες.
 *
 * 🔑 Υπάρχει ώστε καμία πόρτα να μη γράψει `permissionsOn(...)['withdraw']` με ωμό
 * κλειδί: το `ListingAction` το κάνει **αδύνατο** να ζητηθεί πράξη που δεν υπάρχει.
 */
export function mayPerform(
  property: PermissionFields,
  actor: ListingActor,
  action: ListingAction,
): boolean {
  return permissionsOn(property, actor)[action];
}
