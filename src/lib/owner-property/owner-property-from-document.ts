import { readPropertyType } from '@/constants/property-type-aliases';
import { mediaOf, type OwnerProperty } from '@/types/owner-property';
import { mandatesOf } from '@/types/owner-property-mandate';

/** Τι διαβάστηκε, **και τι χρειάστηκε για να διαβαστεί**. */
export interface StoredOwnerPropertyRead {
  readonly property: OwnerProperty;
  /**
   * Η **αποθηκευμένη** τιμή του `type`, όταν **δεν** ήταν ήδη η κανονική μορφή.
   * `null` όταν το έγγραφο ήταν καθαρό — ή όταν δεν είχε καθόλου `type`.
   *
   * 🔑 **Δεν είναι διαγνωστικό στολίδι — είναι ο ΜΕΤΡΗΤΗΣ ΤΗΣ ΜΕΤΑΝΑΣΤΕΥΣΗΣ.** Και οι
   * δύο πύλες γραφής είναι κλειστές (`owner-property-draft-schema.ts` = `z.enum` ·
   * `property-mutation-gateway.ts` = `normalize` + throw), άρα το παλαιό λεξιλόγιο
   * είναι **ιστορικό και δεν μεγαλώνει**. Αυτό το πεδίο είναι ο μόνος τρόπος να
   * απαντηθεί *«πόσα έγγραφα μένουν παλαιά;»* — δηλαδή να γίνει η **αφαίρεση** των
   * παλαιών τιμών απόφαση **με αριθμό** και όχι τόλμη.
   *
   * ⚠️ **Η ΑΠΟΥΣΙΑ ΔΕΝ ΕΙΝΑΙ ΟΛΙΣΘΗΣΗ, ΚΑΙ ΤΟ ΖΕΥΓΟΣ ΤΑ ΞΕΧΩΡΙΖΕΙ ΧΩΡΙΣ ΤΡΙΤΟ ΠΕΔΙΟ**:
   * `type: null` **με** `vocabularyDrift` ⇒ *ήρθε τιμή που δεν αναγνωρίζεται*·
   * `type: null` **χωρίς** ⇒ *δεν ήρθε τιμή καθόλου*. Δύο γεγονότα, δύο θεραπείες
   * (διόρθωση λεξιλογίου vs συμπλήρωση από άνθρωπο) — και το δεύτερο το ονομάζει ήδη
   * ο δείκτης πληρότητας με τον δικό του κωδικό (`type-missing`).
   */
  readonly vocabularyDrift: string | null;
}

/**
 * **Διαβάζει ένα αποθηκευμένο έγγραφο ως προσφορά ιδιώτη** — ή απαντά `null`.
 *
 * `null` σημαίνει **«αυτό δεν είναι έγγραφο»**, και συμβαίνει σε ακριβώς μία περίπτωση:
 * τα δεδομένα δεν είναι καν αντικείμενο. **Δεν** επιστρέφεται `null` για ελλιπή ή
 * αγνώριστα πεδία — ίδιο συμβόλαιο με το ADR-839: ένα ακίνητο που έχασε ένα πεδίο
 * **εξακολουθεί να είναι ακίνητο**, και ο κάτοχός του δικαιούται να το δει και να το
 * διορθώσει. Η ερώτηση *«επιτρέπεται να το δει ο **κόσμος**;»* είναι **άλλη**, και την
 * απαντά η πύλη δημοσίευσης (`isPubliclyListed`).
 *
 * ⚠️ **Η ΤΑΥΤΟΤΗΤΑ ΕΡΧΕΤΑΙ ΑΠΟ ΕΞΩ, ΚΑΙ ΝΙΚΑ.** Το `id` του **εγγράφου** είναι η
 * αυθεντία, ποτέ ένα `id` γραμμένο μέσα στο περιεχόμενο: το δεύτερο είναι αντίγραφο που
 * μπορεί να αποκλίνει — και ήδη **έξι** από τους δεκαεννιά καταναλωτές το επέβαλλαν
 * χειροκίνητα (`{ ...(doc.data() as OwnerProperty), id: doc.id }`) ακριβώς γι' αυτόν
 * τον λόγο, ενώ οι υπόλοιποι **όχι**.
 *
 * **Ιδιοδύναμη**: δεύτερη διέλευση δίνει το ίδιο αποτέλεσμα — η κανονικοποίηση
 * αυτο-απεικονίζει κάθε κανονική τιμή, και τα `mediaOf`/`mandatesOf` δέχονται ό,τι
 * παρήγαγαν.
 */
export function readStoredOwnerProperty(
  raw: unknown,
  id: string,
): StoredOwnerPropertyRead | null {
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) return null;

  const stored = raw as Readonly<Record<string, unknown>>;
  const { type, drift } = readPropertyType(stored.type);

  return {
    // 🔴 Ο ΕΝΑΣ ισχυρισμός — δες την κεφαλίδα. Το CHECK 3.74 απαγορεύει
    //    `as OwnerProperty` οπουδήποτε αλλού στο repo.
    property: {
      ...(stored as unknown as OwnerProperty),
      id,
      type,
      // ⚠️ Τα δύο υπάρχοντα φύλλα, καλεσμένα **εδώ αντί για παντού** — δες την κεφαλίδα.
      media: mediaOf(stored as { readonly media?: OwnerProperty['media'] }),
      mandates: mandatesOf(
        stored as {
          readonly mandates?: OwnerProperty['mandates'];
          readonly mandate?: Parameters<typeof mandatesOf>[0]['mandate'];
        },
      ),
    },
    vocabularyDrift: drift,
  };
}

/**
 * Η ίδια πράξη όταν ο καταναλωτής **δεν** έχει τι να κάνει με τη διάγνωση.
 *
 * Λεπτό περιτύλιγμα, ώστε η συνηθισμένη κλήση να μη σέρνει πεδία που θα αγνοούσε —
 * και **ποτέ** δεύτερη υλοποίηση: delegate, όχι αντίγραφο.
 */
export function ownerPropertyFromDocument(raw: unknown, id: string): OwnerProperty | null {
  return readStoredOwnerProperty(raw, id)?.property ?? null;
}
