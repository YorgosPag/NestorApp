/**
 * @fileoverview **«ΠΟΙΑ ΑΠΟ ΤΑ ΑΡΧΕΙΑ ΜΟΥ ΔΗΜΟΣΙΕΥΩ;»** — η μία απάντηση (ADR-841 §7 Α2).
 * @related ADR-841 §7 (Α2.1 · Α2.7 · Α12.10) · services/listings/public-shelf.service
 * @module lib/owner-property/owner-media-publication
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΕΝΑ ΞΕΧΩΡΙΣΤΟ MODULE, ΚΑΙ ΟΧΙ ΔΥΟ `filter` ΣΕ ΔΥΟ ΑΡΧΕΙΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η ερώτηση *«τι βλέπει ο κόσμος;»* ρωτιέται από **δύο** εντελώς διαφορετικά μέρη:
 *
 *   • ο **γραφέας** (`owner-property-projection`) — για να γεμίσει το ράφι
 *   • η **οθόνη του κατόχου** — για να δείξει *«1η · 2η · …»* και το όριο
 *
 * Αν κάθε πλευρά έγραφε το δικό της `filter(m => m.published)`, θα ήταν δύο απαντήσεις
 * ελεύθερες να αποκλίνουν — και η απόκλιση θα ήταν **αόρατη**: η οθόνη θα έλεγε
 * *«δημοσιεύονται 30»* ενώ ο κόσμος θα έβλεπε **24**. Ο άνθρωπος δεν θα είχε κανέναν
 * τρόπο να καταλάβει ποια έξι έλειπαν.
 *
 * 🔑 Γι' αυτό το **όριο** ζει εδώ μαζί με το **κριτήριο**: όποιος ρωτά, παίρνει τον
 * **ίδιο** πίνακα — και η οθόνη μπορεί να δείξει *ακριβώς* ό,τι θα φύγει.
 */

import type { OwnerPropertyMedia } from '@/types/owner-property';
import {
  PUBLISHED_MEDIA_LIMIT,
  type PublicShelfSource,
} from '@/services/upload/utils/storage-path-public-shelf';
import {
  MODEL_MATERIAL,
  PHOTO_MATERIAL,
  declaredFloorplanMaterial,
  isPhotoMaterial,
  type ListingMaterial,
} from '@/lib/listings/listing-material';
import { promoteToFront } from '@/lib/ordering/declared-order';

/**
 * **Τα αρχεία που ο άνθρωπος διάλεξε, ΣΤΗ ΣΕΙΡΑ ΤΟΥ**, κομμένα στο όριο.
 *
 * 🔑 **Η σειρά είναι η σειρά του πίνακα** — δηλαδή αυτό ακριβώς που βλέπει και
 * τακτοποιεί ο κάτοχος (Α2.1). ⛔ **Κανένα `sort`**: ταξινόμηση εδώ θα ήταν σιωπηλή
 * απόφαση για το *ποια είναι η πρώτη*, δηλαδή θα αφαιρούσε από τον άνθρωπο ακριβώς την
 * πράξη που του δώσαμε. Και ⛔ **κανένα `uploadedAt`** — η **Α6.2** το απέρριψε ρητά ως
 * κριτήριο σειράς, γιατί χρόνος που δεν επέλεξε ο άνθρωπος διαβάζεται ως επιλογή του.
 *
 * ⚠️ **`=== true`, όχι truthy**: το πεδίο είναι **προαιρετικό**, και ό,τι δεν είναι
 * ρητό `true` (απόν, `undefined`, `false`) σημαίνει **ιδιωτικό**. Ο έλεγχος γράφεται
 * μία φορά, εδώ.
 */
export function publishedOwnerMedia(
  media: readonly OwnerPropertyMedia[],
): readonly OwnerPropertyMedia[] {
  return media.filter((item) => item.published === true).slice(0, PUBLISHED_MEDIA_LIMIT);
}

/**
 * **ΤΙ ΕΙΝΑΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ;** — η **μία** ανάγνωση της δήλωσης του ανθρώπου (Α17).
 *
 * 🔴 **Η ΠΡΟΕΠΙΛΟΓΗ ΓΡΑΦΕΤΑΙ ΕΔΩ ΚΑΙ ΠΟΥΘΕΝΑ ΑΛΛΟΥ.** Το `kind` είναι **προαιρετικό**
 * *(κάθε αρχείο που υπάρχει σήμερα ανέβηκε **πριν** υπάρξει η ερώτηση)*, και ένα
 * `?? 'photo'` αντιγραμμένο σε δύο καλούντες θα ήταν **δύο** προεπιλογές ελεύθερες να
 * αποκλίνουν — ακριβώς το σχήμα που αυτό το module υπάρχει για να αποτρέψει.
 *
 * 🔑 **Η κατεύθυνση της προεπιλογής είναι η ΣΗΜΕΡΙΝΗ ΣΥΜΠΕΡΙΦΟΡΑ, όχι προτίμηση**: τα
 * υπάρχοντα αρχεία είναι **ήδη** στη συλλογή. Προεπιλογή `'floorplan'` θα τα **έβγαζε**
 * σιωπηλά από αυτήν — αλλαγή σε δημοσιευμένη αγγελία που **κανείς άνθρωπος δεν ζήτησε**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴🔴 `switch` ΚΑΙ ΟΧΙ ΤΕΡΝΑΡΙΟ — **Η ΔΕΥΤΕΡΗ ΠΟΡΤΑ** (ADR-845 Φ4.1)
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Ως τη Φ4.1 εδώ υπήρχε `item.kind === 'floorplan' ? … : PHOTO_MATERIAL` — **δυαδικό
 * κατηγόρημα**, δηλαδή **ακριβώς η ίδια κλάση** με το σφάλμα του `withPublishedGallery`
 * *(ADR-845 §2.2)*, σε αρχείο που **κανείς δεν είχε κοιτάξει**: το εύρημα της Φ4.1
 * κατέγραφε **μία** πόρτα, και μετρήθηκαν **δύο**.
 *
 * 🔴 **ΚΑΙ ΕΙΝΑΙ ΠΡΟΣΒΑΣΙΜΗ ΑΠΟ ΤΟ ΣΥΡΜΑ**, όχι θεωρητική: το `kind` επικυρώνεται με
 * `z.enum(LISTING_MATERIAL_KINDS)` *(`owner-property-draft-schema.ts` ·
 * `owner-property-form-values.ts`)*, άρα **κάθε** νέα τιμή του λεξιλογίου γίνεται
 * αυτομάτως δεκτή από το δίκτυο. Με το τερνάριο, δήλωση `kind:'model'` θα γινόταν
 * `PHOTO_MATERIAL` — **μοντέλο ανακοινωμένο ως φωτογραφία**, σιωπηλά.
 *
 * 🔑 **Το `undefined` είναι ΡΗΤΟ σκέλος, όχι πτώση στο `default`.** Η απουσία δήλωσης
 * είναι **γνωστή, τεκμηριωμένη κατάσταση** *(αρχεία προγενέστερα της ερώτησης)*, ενώ το
 * `default` σημαίνει *«κανείς δεν απάντησε»*. Αν η προεπιλογή έπεφτε στο `default`, ο
 * φρουρός θα **σιωπούσε** ακριβώς εκεί που οφείλει να μιλήσει.
 */
export function ownerMediaMaterial(item: OwnerPropertyMedia): ListingMaterial {
  const kind = item.kind;

  switch (kind) {
    case undefined:
    case 'photo':
      return PHOTO_MATERIAL;

    case 'floorplan':
      return declaredFloorplanMaterial(item.uploadedAt);

    case 'model':
      // 🔴 **ΠΟΤΕ ΦΩΤΟΓΡΑΦΙΑ** *(ADR-845 Φ4.1)*. Πριν από αυτόν τον κλάδο, μια δήλωση
      //    `kind:'model'` που έφτανε από το σύρμα *(το `z.enum(LISTING_MATERIAL_KINDS)`
      //    τη δέχεται **αυτομάτως** μόλις μεγάλωσε το λεξιλόγιο)* θα γινόταν
      //    `PHOTO_MATERIAL` — **μοντέλο ανακοινωμένο ως φωτογραφία**, το Ο-20 ξανά.
      // ⚠️ **ΔΗΛΩΜΕΝΟ ΟΡΙΟ, ΟΧΙ ΛΥΜΕΝΟ**: η οθόνη του κατόχου είναι ακόμη **δυαδική**
      //    *(«είναι κάτοψη;»)*, άρα **κανείς άνθρωπος δεν μπορεί να το δηλώσει σήμερα**·
      //    και αν τα bytes φτάσουν στο ράφι, ο raster ψήστης τα **απορρίπτει σιωπηλά**
      //    όπως κάθε μη αναγνώσιμο αρχείο. Ονομασμένη άρνηση σε **εκείνο** το σύνορο
      //    ανήκει στη **Φ4β** και είναι γραμμένη ως ανοιχτό στο ADR-845 §9 (Ο-5).
      return MODEL_MATERIAL;

    default:
      return assertNeverOwnerMediaKind(kind);
  }
}

/**
 * **Ο ΦΡΟΥΡΟΣ ΤΗΣ ΔΗΛΩΣΗΣ ΤΟΥ ΑΝΘΡΩΠΟΥ** — τοπικός και **με όνομα**.
 *
 * ⚠️ **Ξεχωριστός από τον `assertNeverMaterial` της προβολής, επίτηδες**: εκείνος ρωτά
 * *«σε ποιο κουτί της **δημόσιας αγγελίας** κάθεται;»*, αυτός *«σε **τι υλικό** μεταφράζεται
 * η δήλωση του κατόχου;»*. **Δύο ερωτήσεις, δύο μηνύματα** — και το μήνυμα **είναι** ο
 * μηχανισμός. Ένα κοινό βοήθημα θα έλεγε *«άγνωστη τιμή»* και στις δύο περιπτώσεις,
 * δηλαδή θα αφαιρούσε ακριβώς την πληροφορία για την οποία υπάρχει. Ίδιο ιδίωμα με τα
 * `assertNeverShape`/`assertNeverAccuracy` του `listing-map-shape`.
 */
function assertNeverOwnerMediaKind(kind: never): never {
  throw new Error(
    `ownerMediaMaterial: άγνωστη δήλωση είδους — ${JSON.stringify(kind)}. ` +
      'Νέα τιμή στο LISTING_MATERIAL_KINDS χωρίς απάντηση στο «σε τι υλικό μεταφράζεται ' +
      'η δήλωση του κατόχου;» (ADR-845 §2.2, άγκυρα Α-2).',
  );
}

/**
 * **Τα δημοσιευμένα αρχεία που είναι ΦΩΤΟΓΡΑΦΙΕΣ** — δηλαδή η συλλογή.
 *
 * 🔑 Υπάρχει ξεχωριστά από το {@link publishedOwnerMedia} επειδή *«τι φεύγει;»* και
 * *«τι μπαίνει στη ΣΥΛΛΟΓΗ;»* έπαψαν να είναι η ίδια ερώτηση τη στιγμή που η **Α17**
 * έδωσε στην κάτοψη δικό της πεδίο.
 *
 * 🔴 **ΡΩΤΑ ΚΑΤΑΦΑΤΙΚΑ, ΚΑΙ ΗΤΑΝ Η ΤΡΙΤΗ ΠΟΡΤΑ ΤΗΣ ΙΔΙΑΣ ΚΛΑΣΗΣ** *(ADR-845 Φ4.1)*.
 * Ως τη Φ4.1 έγραφε `!isFloorplanMaterial(…)` — δηλαδή *«ό,τι δεν είναι κάτοψη»*, που με
 * **δύο** τιμές συνέπιπτε με *«φωτογραφία»* και με **τρεις** παύει: ένα μοντέλο θα
 * μετρούσε εδώ ως φωτογραφία και το {@link isLeadOwnerMedia} θα το σήμαινε **«1η»** στον
 * κόσμο — ψέμα σε ακριβώς τον άνθρωπο που προσπαθεί να διαλέξει.
 */
export function publishedOwnerPhotos(
  media: readonly OwnerPropertyMedia[],
): readonly OwnerPropertyMedia[] {
  return publishedOwnerMedia(media).filter((item) => isPhotoMaterial(ownerMediaMaterial(item)));
}

/**
 * **Η επιλογή, στη γλώσσα του ραφιού** — μονοπάτια στον **ιδιωτικό** κάδο.
 *
 * ⚠️ Ποτέ bytes και ποτέ URL: ο γραφέας κατεβάζει το πρωτότυπο **ο ίδιος**, ώστε ο
 * καθαρισμός EXIF/GPS να μην μπορεί να παρακαμφθεί από τον καλούντα *(Α12.7)*.
 *
 * 🔴 **ΚΑΙ ΟΙ ΚΑΤΟΨΕΙΣ ΠΕΡΝΟΥΝ ΑΠΟ ΕΔΩ — ΕΝΑ ράφι, ΕΝΑΣ διαχωρισμός στο τέλος** *(Α17.4)*.
 * Δύο κλήσεις του `reconcilePublicShelf` θα ήταν **καταστροφικές**, όχι απλώς περιττές: το
 * πρόθεμα είναι **ένα ανά αγγελία**, άρα το `deleteExtra` της καθεμιάς θα έσβηνε τα
 * αντικείμενα της **άλλης** σε κάθε πέρασμα.
 */
export function publishedOwnerMediaSources(
  media: readonly OwnerPropertyMedia[],
): readonly PublicShelfSource[] {
  return publishedOwnerMedia(media).map((item) => ({
    privateStoragePath: item.storagePath,
    material: ownerMediaMaterial(item),
  }));
}

/**
 * **Είναι αυτό το αρχείο το πρώτο που θα δει ο κόσμος;**
 *
 * 🔑 Απαντά *«πρώτο **από όσα δημοσιεύονται**»*, όχι «πρώτο του πίνακα»: ένα ιδιωτικό
 * αρχείο στην κορυφή της λίστας **δεν** είναι η εικόνα της αγγελίας, και μια οθόνη που
 * θα το σήμαινε ως «1η» θα έλεγε ψέματα σε ακριβώς τον άνθρωπο που προσπαθεί να
 * διαλέξει.
 *
 * 🔴 **ΚΑΙ ΓΙ' ΑΥΤΟ ΑΚΡΙΒΩΣ ΡΩΤΑ ΜΟΝΟ ΤΙΣ ΦΩΤΟΓΡΑΦΙΕΣ, ΑΠΟ ΤΗΝ Α17.** Μια κάτοψη **δεν
 * μπαίνει στη συλλογή καθόλου** — ζει σε δικό της πεδίο. Αν έμενε στον παρονομαστή, μια
 * κάτοψη στην κορυφή του πίνακα θα σημαινόταν *«1η»* ενώ ο κόσμος θα έβλεπε **άλλη**
 * εικόνα πρώτη: **ακριβώς το ίδιο ψέμα** που αυτή η συνάρτηση γράφτηκε για να αποτρέψει,
 * με νέα αιτία. ⚠️ Η ουρά της Α17 που **δεν** φαινόταν στο δημόσιο έγγραφο.
 */
export function isLeadOwnerMedia(
  media: readonly OwnerPropertyMedia[],
  storagePath: string,
): boolean {
  return publishedOwnerPhotos(media)[0]?.storagePath === storagePath;
}

/**
 * **«Να μπει πρώτη»** — ο νέος πίνακας, με αυτό το αρχείο **στην κορυφή**.
 *
 * 🔑 **Μετακίνηση μέσα στον ΙΔΙΟ πίνακα, ποτέ πεδίο σειράς** (Α2.1). Η σειρά που
 * βλέπει ο κάτοχος **είναι** η σειρά που φεύγει· δεν υπάρχει δεύτερη λίστα να μείνει
 * πίσω.
 *
 * 🔴 **ΑΓΝΩΣΤΟ ΜΟΝΟΠΑΤΙ ⇒ Ο ΙΔΙΟΣ ΠΙΝΑΚΑΣ, ΑΜΕΤΑΒΛΗΤΟΣ** — και η πολιτική γράφεται
 * **εδώ**, όχι μέσα στη μηχανή (ADR-841 §7 Α14.7.4). Μια «διόρθωση» με σιωπηλή προσθήκη
 * θα έγραφε στη φόρμα κατάσταση που κανείς δεν ζήτησε: αυτός ο πίνακας **είναι** η
 * συμμετοχή *(Α2.1)*, άρα προσθήκη εδώ σημαίνει **δημοσίευση**.
 *
 * ⚠️ **Η αντίθετη πλευρά επιλέγει το αντίθετο, με δικαίωμα**: η δήλωση σειράς του
 * γραφείου *(`withDeclaredFirst`)* βάζει το άγνωστο κλειδί **μπροστά**, γιατί εκεί η
 * δήλωση **δεν** είναι συμμετοχή. Ίδια μηχανή, ρητά διαφορετικός λόγος.
 */
export function withOwnerMediaFirst(
  media: readonly OwnerPropertyMedia[],
  storagePath: string,
): readonly OwnerPropertyMedia[] {
  return promoteToFront(media, (item) => item.storagePath, storagePath) ?? media;
}
