/**
 * @fileoverview **Η μνήμη του ημιτελούς προσχεδίου** — ό,τι έγραψε ο άνθρωπος πριν συνδεθεί.
 * @related ADR-660 §5.10 · lib/storage/safe-storage.ts · owner-property-form-values.ts
 * @module lib/owner-property/owner-property-draft-memory
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ: Ο ΣΥΝΔΕΣΜΟΣ «ΣΥΝΔΕΣΟΥ» ΕΙΝΑΙ ΦΥΓΗ ΑΠΟ ΤΗ ΣΕΛΙΔΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Το Στάδιο Α.1 έκανε την απουσία λογαριασμού **ορατό εμπόδιο**. Το Α.2 άνοιξε την
 * πόρτα. Μένει το τρίτο: ο άνθρωπος που θα πατήσει «Σύνδεση» **φεύγει από τη
 * σελίδα** — και χωρίς αυτό το αρχείο θα γύριζε σε **άδεια φόρμα**, δηλαδή στο ίδιο
 * αδιέξοδο που καταργήσαμε, με άλλο πρόσωπο.
 *
 * 🏆 **Η αγορά χάνει ακριβώς εδώ.** Zillow και idealista ζητούν λογαριασμό στην
 * υποβολή, με **ανακατεύθυνση** — και το πρότυπο *Lazy Registration* συνιστά ρητά να
 * κρατιέται η δουλειά *«είτε στον πελάτη είτε στη βάση»* πριν ζητηθεί ταυτότητα.
 * Κρατιέται στον πελάτη: **μηδέν νέα υποδομή, μηδέν νέος τύπος ταυτότητας**.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 🔑 ΤΟ `draftId` ΑΠΟΘΗΚΕΥΕΤΑΙ ΜΑΖΙ, ΚΑΙ ΕΙΝΑΙ Η ΜΙΣΗ ΟΥΣΙΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Η ταυτότητα του προσχεδίου γεννιέται **πριν** από την ταυτότητα του ανθρώπου, και
 * τα αρχεία ζουν στο `owner_properties/{uid}/{draftId}/…`. Αν η επαναφορά έκοβε
 * **νέο** `draftId`, τότε ο άνθρωπος που συνδέθηκε και γύρισε θα ανέβαζε τα αρχεία
 * του σε **άλλον φάκελο** από αυτόν που θα δήλωνε η αγγελία. Σήμερα δεν προλαβαίνει
 * να ανεβάσει τίποτα ως ανώνυμος — αλλά η σταθερότητα της ταυτότητας **είναι** η
 * θέση του §5.9, και ένα προσχέδιο που την πετάει στην επαναφορά την αναιρεί.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ⚠️ ΤΡΙΑ ΔΗΛΩΜΕΝΑ ΟΡΙΑ — ΓΡΑΜΜΕΝΑ, ΟΧΙ ΚΡΥΜΜΕΝΑ
 * ────────────────────────────────────────────────────────────────────────────
 *
 * 1. **Ζει ανά ΣΥΣΚΕΥΗ.** Αλλαγή περιηγητή ή μηχανήματος ⇒ το προσχέδιο **χάνεται**.
 *    Είναι το ίδιο δηλωμένο όριο με το `ACTIVE_JOB` (ADR-748 Ε5.β) και η θεραπεία
 *    είναι η ίδια: μετακίνηση σε λογαριασμό — που εδώ **δεν μπορεί να γίνει**, γιατί
 *    ολόκληρο το χαρακτηριστικό υπάρχει ακριβώς για την ώρα που **δεν υπάρχει**
 *    λογαριασμός.
 * 2. **ΔΕΝ είναι ανά χρήστη**, και δεν γίνεται να είναι: γράφεται πριν υπάρξει `uid`.
 *    Σε **κοινό** μηχάνημα, ο επόμενος βλέπει το ημιτελές του προηγούμενου. Γι' αυτό
 *    η επαναφορά είναι **ρητή και ακυρώσιμη** (βλ. παρακάτω) και όχι σιωπηλή, και
 *    γι' αυτό σβήνεται **στην πρώτη επιτυχή υποβολή**.
 * 3. **Κρατά ΜΟΝΟ ό,τι πληκτρολογήθηκε.** Ποτέ `authorUserId`, ποτέ `lifecycle`,
 *    ποτέ `createdAt` — τα ίδια που αρνείται και το `ownerPropertyDraftSchema`. Ένα
 *    προσχέδιο στον περιηγητή είναι **επεξεργάσιμο από τον χρήστη**· ό,τι μπει εδώ
 *    πρέπει να αντέχει να είναι ψεύτικο.
 *
 * 🔴 **Η ΕΠΑΝΑΦΟΡΑ ΕΠΙΚΥΡΩΝΕΤΑΙ ΑΠΟ ΤΟ ΙΔΙΟ ΣΧΗΜΑ ΠΟΥ ΕΠΙΚΥΡΩΝΕΙ ΤΗΝ ΠΛΗΚΤΡΟΛΟΓΗΣΗ**
 * ({@link ownerPropertyFormSchema}) — καμία δεύτερη μηχανή. Ένα προσχέδιο γραμμένο
 * από παλιότερη έκδοση, ή πειραγμένο με το χέρι, **δεν επαναφέρεται**: πέφτει, και ο
 * άνθρωπος ξεκινά καθαρός. *Καλύτερα άδεια φόρμα παρά φόρμα με σκουπίδια που
 * φαίνονται δικά του.*
 *
 * ⚠️ **ΚΑΙ ΤΟ ΒΑΘΟΣ ΤΟΥ ΕΛΕΓΧΟΥ ΕΙΝΑΙ ΑΚΡΙΒΩΣ ΟΣΟ ΠΡΕΠΕΙ — ΜΕΤΡΗΜΕΝΟ, ΟΧΙ ΥΠΟΤΙΘΕΜΕΝΟ.**
 * Το σχήμα κρίνει **δομή** (λείπει πεδίο· `offerKinds` που δεν είναι πίνακας· τιμή
 * εκτός κλειστού συνόλου), **όχι σημασιολογία**: το `optionalNumberSchema` δέχεται
 * ρητά `string` και μετατρέπει το `'πολλά'` σε `null`, *«γιατί αυτό ακριβώς παραδίδει
 * ένα `<input type="number">` που ο άνθρωπος άδειασε»*.
 *
 * 🔑 **Και αυτό ΠΡΕΠΕΙ να ισχύει και στην επαναφορά**: ο τύπος της φόρμας είναι το
 * `z.input` (ό,τι κρατά η οθόνη), όχι το `z.output`. Αν η επαναφορά ήταν
 * **αυστηρότερη από την πληκτρολόγηση**, θα πετούσε δουλειά που ο άνθρωπος είχε
 * γράψει και **μπορούσε να διορθώσει** — μια μισοσυμπληρωμένη φόρμα θα χανόταν επειδή
 * ένα πεδίο ήταν μισογραμμένο τη στιγμή που έφυγε να συνδεθεί. Το «είναι έγκυρη
 * αγγελία;» το απαντούν οι **blockers**, ζωντανά στην οθόνη, όχι αυτό το αρχείο.
 *
 * ⚠️ Γι' αυτό επιστρέφονται οι **ωμές** τιμές και όχι το `parsed.data`: το δεύτερο
 * είναι το `z.output` και **δεν** είναι ο τύπος που κρατά η φόρμα.
 *
 * **Layering**: leaf — καμία εξάρτηση από React ή Firebase.
 */

import { STORAGE_KEYS, safeGetItem, safeRemoveItem, safeSetItem } from '@/lib/storage';
import {
  ownerPropertyFormSchema,
  type OwnerPropertyFormValues,
} from './owner-property-form-values';
import { ownerPropertyIdFromRequest } from './owner-property-draft-schema';

/**
 * Η έκδοση του **σχήματος αποθήκευσης**, όχι του σχήματος της φόρμας.
 *
 * ⚠️ **Δεν είναι πλεονασμός δίπλα στο `safeParse`**: το σχήμα πιάνει ό,τι έπαψε να
 * *διαβάζεται*· η έκδοση πιάνει ό,τι εξακολουθεί να διαβάζεται αλλά έχει αλλάξει
 * **νόημα** (π.χ. ένα πεδίο που κράταγε τετραγωνικά και τώρα κρατά στρέμματα). Το
 * πρώτο είναι σφάλμα τύπου, το δεύτερο σιωπηλό λάθος δεδομένων.
 */
const MEMORY_VERSION = 1;

/** Τι ακριβώς επιβίωσε από την προηγούμενη επίσκεψη. */
export interface RememberedOwnerPropertyDraft {
  readonly draftId: string;
  readonly values: OwnerPropertyFormValues;
}

/**
 * **Θυμήσου το προσχέδιο.**
 *
 * ⚠️ **Σιωπηλή αποτυχία είναι ΣΩΣΤΗ εδώ, και μόνο εδώ**: αν το `localStorage` δεν
 * είναι διαθέσιμο (ιδιωτική περιήγηση, γεμάτη ποσόστωση), ο άνθρωπος πρέπει να
 * μπορεί να **συνεχίσει να γράφει**. Ένα μήνυμα σφάλματος για κάτι που δεν του
 * ζήτησε κανείς θα ήταν θόρυβος πάνω σε ροή που δουλεύει.
 */
export function rememberOwnerPropertyDraft(
  draftId: string,
  values: OwnerPropertyFormValues,
): void {
  safeSetItem(STORAGE_KEYS.OWNER_PROPERTY_DRAFT, {
    version: MEMORY_VERSION,
    draftId,
    values,
  });
}

/**
 * **Τι θυμάται ο περιηγητής;** — `null` όταν δεν υπάρχει, δεν διαβάζεται, ή δεν πείθει.
 *
 * 🔑 **Η ταυτότητα κρίνεται από τον ΙΔΙΟ κριτή που κρίνει το δίκτυο**
 * ({@link ownerPropertyIdFromRequest}), και αυτό **δεν** είναι κομψότητα: το
 * `localStorage` είναι **επεξεργάσιμο από τον χρήστη**, άρα δεν είναι πιο έμπιστο από
 * ό,τι φτάνει από το δίκτυο — και το `draftId` καταλήγει σε **διαδρομή αποθήκευσης**.
 * Ένα `../../` εκεί μέσα δεν είναι θεωρητικό. Δεύτερος έλεγχος γραμμένος εδώ θα ήταν
 * δεύτερη απάντηση, και θα ήταν η **χαλαρότερη** των δύο την ημέρα που ο ένας
 * αυστηροποιούνταν.
 */
export function recallOwnerPropertyDraft(): RememberedOwnerPropertyDraft | null {
  const stored = safeGetItem<unknown>(STORAGE_KEYS.OWNER_PROPERTY_DRAFT, null);
  if (stored === null || typeof stored !== 'object') return null;

  const memory = stored as Partial<{ version: number; draftId: string; values: unknown }>;
  if (memory.version !== MEMORY_VERSION) return null;
  const draftId = ownerPropertyIdFromRequest(memory.draftId);
  if (draftId === null) return null;

  // 🔑 Ο **ίδιος** κριτής που κρίνει ό,τι πληκτρολογείται ζωντανά. Αν δεν περνά,
  // δεν είναι προσχέδιο — είναι σκουπίδι που μοιάζει με προσχέδιο.
  const parsed = ownerPropertyFormSchema.safeParse(memory.values);
  if (!parsed.success) return null;

  return { draftId, values: memory.values as OwnerPropertyFormValues };
}

/**
 * **Ξέχνα το.** — μετά από επιτυχή υποβολή, ή όταν ο άνθρωπος το απορρίψει ρητά.
 *
 * ⚠️ Καλείται **και** στην επιτυχία **και** στην απόρριψη, από **μία** συνάρτηση: δύο
 * διαδρομές διαγραφής θα σήμαινε ότι η μία μπορεί να ξεχαστεί, και ένα προσχέδιο που
 * επιβιώνει της υποβολής του θα επανερχόταν ως «ημιτελές» πάνω σε αγγελία που
 * **δημοσιεύτηκε**.
 */
export function forgetOwnerPropertyDraft(): void {
  safeRemoveItem(STORAGE_KEYS.OWNER_PROPERTY_DRAFT);
}
