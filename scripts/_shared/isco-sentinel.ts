/**
 * =============================================================================
 * ISCO SENTINEL — ο διαχωριστής ανάμεσα στον ΓΝΗΣΙΟ και στον ΕΠΙΝΟΗΜΕΝΟ κωδικό
 * =============================================================================
 *
 * ## Το πρόβλημα σε μία πρόταση
 *
 * Ο παλιός εισαγωγέας ESCO έγραφε `iscoCode: '0000'` όπου το ESCO **δεν έδινε
 * κωδικό**. Το `'0000'` όμως **δεν είναι αδύνατη τιμή**: είναι η μείζων ομάδα
 * **«Ένοπλες Δυνάμεις»** του ISCO-08. Άρα:
 *
 * > 🔴 **Η ΤΙΜΗ ΔΕΝ ΜΠΟΡΕΙ ΝΑ ΚΡΙΝΕΙ ΤΟΝ ΕΑΥΤΟ ΤΗΣ.** Ο `classifyIscoCode('0000')`
 * > απαντά `valid` — και έχει δίκιο. Ένας στρατιωτικός με γνήσιο `'0000'` και ένα
 * > ψέμα του εισαγωγέα είναι **ΑΔΙΑΚΡΙΤΑ** αν κοιτάς μόνο την τιμή.
 *
 * ## Ο διαχωριστής είναι η ΑΥΘΕΝΤΙΑ, όχι η τιμή
 *
 * Κάθε εγγραφή κουβαλά ήδη το `escoUri` που τη γέννησε. Ρωτάμε τη **μνήμη ESCO**
 * *(που έχει επανεισαχθεί σωστά)* τι κωδικό δίνει για **αυτό** το URI:
 *
 * | escoUri | μνήμη λέει | ετυμηγορία |
 * |---|---|---|
 * | υπάρχει | σεντινέλα *(π.χ. `'0000'`)* | **γνήσιο** — πραγματικά Ένοπλες Δυνάμεις |
 * | υπάρχει | **οτιδήποτε άλλο** *(και το κενό)* | **επινοημένο** — ο κωδικός είναι ψέμα |
 * | λείπει · ή άγνωστο στη μνήμη | — | **ανεπιβεβαίωτο** — «δεν ξέρω», ΟΧΙ «μάλλον ψέμα» |
 *
 * ⚠️ **ΤΡΕΙΣ εκβάσεις, ποτέ δύο.** Το να συγχωνευθεί το «δεν ξέρω» με το «ψέμα»
 * θα οδηγούσε σε **σβήσιμο αληθινών δεδομένων** — ακριβώς η κλάση σφάλματος που
 * γέννησε το πρόβλημα.
 *
 * @module scripts/_shared/isco-sentinel
 * @enterprise ADR-132 §10 (ESCO) · ADR-823 §Α · ADR-798 §20.4
 */

/**
 * Οι τιμές που ο **παλιός** εισαγωγέας μπορούσε να γεννήσει ως «άγνωστο».
 *
 * ⚠️ **Καμία τους δεν είναι αδύνατη ως πραγματικός κωδικός** — γι' αυτό ακριβώς
 * το ψέμα έμεινε αόρατο. Η λίστα υπάρχει για να **βρει υπόπτους**, ποτέ για να
 * τους **καταδικάσει**: την καταδίκη την υπογράφει η μνήμη.
 */
export const ISCO_SENTINELS: readonly string[] = ['0000', '000', '00', '0'];

/** Οι τρεις — και μόνο τρεις — εκβάσεις της κρίσης. */
export type IscoVerdict = 'confirmed' | 'fabricated' | 'unverifiable';

/** Είναι η τιμή ύποπτη *(δηλαδή τιμή που ο παλιός εισαγωγέας μπορούσε να γράψει)*; */
export function isSentinelCode(code: unknown): boolean {
  return typeof code === 'string' && ISCO_SENTINELS.includes(code);
}

/**
 * Κρίνει έναν ύποπτο κωδικό **με βάση τη μνήμη**, όχι με βάση την τιμή του.
 *
 * @param escoUri    Το URI που κουβαλά η εγγραφή, ή `null` αν λείπει.
 * @param memoryCode Ο κωδικός που δίνει η **μνήμη ESCO** για αυτό το URI, ή
 *                   `null` αν η μνήμη δεν έχει την έννοια. Το **κενό string**
 *                   είναι έγκυρη απάντηση και σημαίνει *«το ESCO δεν δίνει
 *                   κωδικό»* — δηλαδή ο κωδικός του ανθρώπου είναι **επινοημένος**.
 */
export function judgeIscoCode(escoUri: string | null, memoryCode: string | null): IscoVerdict {
  if (escoUri === null || escoUri.trim().length === 0) return 'unverifiable';
  if (memoryCode === null) return 'unverifiable';
  return isSentinelCode(memoryCode) ? 'confirmed' : 'fabricated';
}
