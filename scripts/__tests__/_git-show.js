'use strict';

const { execFileSync } = require('node:child_process');
const path = require('node:path');

const REPO_ROOT = path.join(__dirname, '..', '..');

/**
 * Διάβασε το περιεχόμενο ενός αρχείου όπως ήταν σε μια **καρφωμένη** αναθεώρηση.
 *
 * @param {string} rev  Καρφωμένο SHA — **ποτέ** `HEAD` ή κινούμενο ref.
 * @param {string} posixPath  Μονοπάτι σχετικό με τη ρίζα, με `/` **πάντα**.
 * @returns {string} Το περιεχόμενο· **πετά** αν είναι κενό.
 */
function gitShow(rev, posixPath) {
  if (/^head$/i.test(rev)) {
    throw new Error(`gitShow: το «${rev}» μετακινείται — καρφώστε SHA, αλλιώς η άγκυρα αυτο-ακυρώνεται.`);
  }
  if (posixPath.includes('\\')) {
    throw new Error(`gitShow: το git θέλει POSIX μονοπάτι, πήρε «${posixPath}».`);
  }
  const out = execFileSync('git', ['show', `${rev}:${posixPath}`], {
    cwd: REPO_ROOT,
    encoding: 'utf8',
    maxBuffer: 8 * 1024 * 1024,
  });
  if (!out || out.trim() === '') {
    throw new Error(`git show ${rev}:${posixPath} → ΚΕΝΟ (η άγκυρα δεν αποδεικνύει τίποτα)`);
  }
  return out;
}

module.exports = { gitShow, REPO_ROOT };
