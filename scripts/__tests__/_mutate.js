'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

/** Χαρακτήρες με νόημα σε κανονική έκφραση — γίνονται **κυριολεκτικοί**. */
function escapeRegExp(literal) {
  return literal.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Η βελόνα → κανονική έκφραση που ταιριάζει **κυριολεκτικά**, αλλά δέχεται **κάθε** σύμβαση
 * τέλους γραμμής.
 *
 * 🔑 **Πρώτα κανονικοποιείται η ΒΕΛΟΝΑ**: στόχος αντιγραμμένος από αρχείο των Windows κουβαλά
 * ήδη `\r\n`· χωρίς αυτό το βήμα θα παρήγαγε `\r?\n\r?\n` — δηλαδή θα απαιτούσε **δύο** αλλαγές
 * γραμμής και δεν θα ταίριαζε **πουθενά**, ξαναφτιάχνοντας το ίδιο σιωπηλό «0 φορές» από την
 * ανάποδη.
 */
function needleToRegExp(needle) {
  const normalized = needle.replace(/\r\n/g, '\n');
  // Ο χαρακτήρας 0x0A επιβιώνει του escapeRegExp (δεν είναι μεταχαρακτήρας) — εδώ γίνεται
  // ρητά «προαιρετικό \r, μετά \n».
  return new RegExp(escapeRegExp(normalized).replace(/\n/g, '\\r?\\n'), 'g');
}

/**
 * Κάθε εμφάνιση της βελόνας, **με τη θέση και το κείμενο που όντως ταίριαξε**.
 *
 * ⚠️ Επιστρέφει το `text` κάθε ταιριάσματος επειδή η αντικατάσταση γίνεται με **τεμαχισμό
 * δεικτών**, ποτέ με `String.replace`: ένα `$&` ή `$1` μέσα στο κείμενο αντικατάστασης θα
 * ερμηνευόταν ως **αναφορά ομάδας** και θα έγραφε κάτι που κανείς δεν ζήτησε.
 */
function findOccurrences(text, needle) {
  const re =
    needle instanceof RegExp
      ? new RegExp(needle.source, needle.flags.includes('g') ? needle.flags : `${needle.flags}g`)
      : needleToRegExp(needle);

  const hits = [];
  let match;
  re.lastIndex = 0;
  while ((match = re.exec(text)) !== null) {
    if (match[0] === '') {
      throw new Error('mutateText: βελόνα μηδενικού μήκους — δεν μεταλλάσσει, μόνο ατέρμονα.');
    }
    hits.push({ index: match.index, text: match[0] });
  }
  return hits;
}

/** Η σύμβαση που κυριαρχεί στο κείμενο — καταφύγιο όταν ο στόχος είναι **μονογραμμικός**. */
function dominantEol(text) {
  const crlf = (text.match(/\r\n/g) || []).length;
  const lf = (text.match(/\n/g) || []).length - crlf;
  return crlf > lf ? '\r\n' : '\n';
}

/**
 * Το κείμενο αντικατάστασης παίρνει τα τέλη γραμμής **του σημείου όπου προσγειώνεται**.
 *
 * 🔑 **Χωρίς αυτό η θεραπεία θα γεννούσε τη βλάβη**: μια μετάλλαξη που **προσθέτει** γραμμές
 * *(π.χ. το `Γ-Μ2`, που εισάγει ολόκληρη νέα εγγραφή στο μητρώο)* θα έγραφε `\n` μέσα σε αρχείο
 * CRLF ⇒ **ανάμεικτο αρχείο** ⇒ ο **επόμενος** αναγνώστης του θα ξαναζούσε ακριβώς το πρόβλημα
 * που λύνουμε, και αυτή τη φορά σε αρχείο που **εμείς** χαλάσαμε.
 */
function alignEndings(replacement, matchedText, haystack) {
  if (!replacement.includes('\n') && !replacement.includes('\r')) return replacement;

  const eol = matchedText.includes('\n')
    ? (matchedText.includes('\r\n') ? '\r\n' : '\n')
    : dominantEol(haystack);

  const asLf = replacement.replace(/\r\n/g, '\n');
  return eol === '\n' ? asLf : asLf.replace(/\n/g, '\r\n');
}

/** Συναρμολόγησε το αποτέλεσμα από **δείκτες**, ποτέ από `String.replace`. */
function spliceAll(text, hits, replacementFor) {
  let out = '';
  let cursor = 0;
  for (const hit of hits) {
    out += text.slice(cursor, hit.index) + replacementFor(hit);
    cursor = hit.index + hit.text.length;
  }
  return out + text.slice(cursor);
}

/**
 * **Ο ΚΑΝΟΝΑΣ** — καθαρή συνάρτηση, καμία γνώση δίσκου.
 *
 * @param {string} text  Το κείμενο που μεταλλάσσεται.
 * @param {string|RegExp} from  Ο στόχος. Συμβολοσειρά ⇒ **κυριολεκτική**, αλλά αδιάφορη στα
 *   τέλη γραμμής. Κανονική έκφραση ⇒ όπως γράφτηκε *(και **επίσης** μετριέται για ασάφεια —
 *   κανένα από τα προηγούμενα αντίγραφα δεν το έκανε αυτό)*.
 * @param {string} to  Το κείμενο αντικατάστασης. Ευθυγραμμίζεται στα τέλη γραμμής του στόχου.
 * @param {{occurrence?: number, all?: boolean, label?: string}} [options]
 *   `occurrence` = **ποια** εμφάνιση *(1-based)*· `all` = **όλες**, ρητά δηλωμένο·
 *   `label` = πώς λέγεται ο στόχος στα μηνύματα σφάλματος.
 * @returns {string} Το μεταλλαγμένο κείμενο.
 */
function mutateText(text, from, to, options = {}) {
  const { occurrence = 1, all = false, label = 'το κείμενο' } = options;
  const hits = findOccurrences(text, from);

  if (hits.length === 0) {
    throw new Error(
      `μετάλλαξη: ο στόχος βρέθηκε 0 φορές στο ${label}. ` +
      'Ο στόχος αναζητείται ΑΝΕΞΑΡΤΗΤΑ από τα τέλη γραμμής — άρα λείπει πράγματι, ' +
      'ή μετακινήθηκε. Άνοιξε το αρχείο, μην «χαλαρώσεις» τον στόχο.',
    );
  }

  if (!all && hits.length < occurrence) {
    throw new Error(
      `μετάλλαξη: ο στόχος βρέθηκε ${hits.length} φορές στο ${label}, ζητήθηκε η #${occurrence}.`,
    );
  }

  if (!all && hits.length > 1 && occurrence === 1) {
    throw new Error(
      `μετάλλαξη: ΑΣΑΦΗΣ στόχος — ${hits.length} εμφανίσεις στο ${label}. ` +
      'Η αντικατάσταση θα χτυπούσε την 1η ΣΙΩΠΗΛΑ, και θα μετακόμιζε μόνη της την ημέρα που ' +
      'προστεθεί όμοιο σημείο. Δήλωσε ρητά ποια θέλεις (`occurrence`) ή ότι τις θέλεις όλες (`all`).',
    );
  }

  const chosen = all ? hits : [hits[occurrence - 1]];
  const after = spliceAll(text, chosen, (hit) => alignEndings(to, hit.text, text));

  if (after === text) {
    throw new Error(
      `μετάλλαξη: Η ΜΕΤΑΛΛΑΞΗ ΔΕΝ ΑΛΛΑΞΕ ΤΙΠΟΤΑ στο ${label} — ` +
      'το κείμενο αντικατάστασης είναι ταυτόσημο με τον στόχο, άρα η άγκυρα δεν αποδεικνύει τίποτα.',
    );
  }
  return after;
}

/**
 * Αντίγραφο ασφαλείας **εκτός δέντρου**, πριν αγγιχτεί οτιδήποτε.
 *
 * 🔴 **ΓΙΑΤΙ, ΚΑΙ ΓΙΑΤΙ ΕΙΝΑΙ ΠΙΟ ΣΟΒΑΡΟ ΕΔΩ ΑΠ' ΟΣΟ ΦΑΙΝΕΤΑΙ**: το `finally` **δεν τρέχει**
 * αν η διεργασία σκοτωθεί *(Ctrl-C, timeout του εκτελεστή, κόλλημα)*. Τότε το αρχείο μένει
 * **μεταλλαγμένο μέσα στο δέντρο** — και σε αυτό το έργο το δέντρο **μοιράζεται με άλλον
 * πράκτορα που έχει εντολή να κάνει commit**. Δηλαδή το τίμημα δεν είναι «χαλασμένο τοπικό
 * αντίγραφο», είναι **μετάλλαξη δοκιμής που φεύγει στην παραγωγή**.
 */
function backupOutsideTree(file, bytes) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'nestor-mutate-'));
  const at = path.join(dir, path.basename(file));
  fs.writeFileSync(at, bytes);
  return { at, dir };
}

/**
 * **Η ΤΕΛΕΤΟΥΡΓΙΑ ΤΟΥ ΔΙΣΚΟΥ** — μετάλλαξε αρχείο του δέντρου, τρέξε, **επανάφερε πάντα**.
 *
 * 🔑 **Η επαναφορά είναι byte-για-byte**: το πρωτότυπο κρατιέται ως **`Buffer`**, όχι ως
 * συμβολοσειρά. Ένα `readFileSync(utf8)` → `writeFileSync(utf8)` είναι ταυτοτικό **σχεδόν**
 * πάντα — και το «σχεδόν» *(BOM, μη έγκυρες ακολουθίες)* θα ήταν αόρατη αλλοίωση αρχείου του
 * δέντρου, δηλαδή ακριβώς ό,τι δεν επιτρέπεται να κάνει ένα test.
 *
 * @param {string} file  Απόλυτο μονοπάτι.
 * @param {string|RegExp} from
 * @param {string} to
 * @param {(mutatedText: string) => T} run  Τι σημαίνει «τρέξε την πύλη» — **το ξέρει ο καλών**.
 * @param {{occurrence?: number, all?: boolean}} [options]
 * @returns {T} Ό,τι επέστρεψε το `run`.
 * @template T
 */
function withMutation(file, from, to, run, options = {}) {
  const originalBytes = fs.readFileSync(file);
  const before = originalBytes.toString('utf8');
  const after = mutateText(before, from, to, { ...options, label: file });

  const backup = backupOutsideTree(file, originalBytes);
  try {
    fs.writeFileSync(file, after, 'utf8');
    return run(after);
  } finally {
    fs.writeFileSync(file, originalBytes);
    fs.rmSync(backup.dir, { recursive: true, force: true });
  }
}

module.exports = { mutateText, withMutation, dominantEol };
