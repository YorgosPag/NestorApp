/** Κανονικοποίηση σε POSIX, σχετική με τη ρίζα — **μία** φορά, για όλους. */
function repoRelativePosix(absPath, root) {
  const posix = (p) => p.split('\\').join('/');
  return posix(absPath).replace(`${posix(root)}/`, '');
}

/** Είναι αυτό το αρχείο δηλωμένος ιδιοκτήτης κλήσης; */
function isCallOwner(repoRelPath, owners = CALL_OWNERS) {
  return Object.hasOwn(owners, repoRelPath);
}

