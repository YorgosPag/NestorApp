'use strict';
/**
 * =============================================================================
 * Χ — ΤΟ ΚΛΕΙΣΤΟ ΣΥΝΟΛΟ ΤΩΝ ΚΑΤΑΣΤΑΣΕΩΝ (CHECK 3.51 Χ · ADR-781 §6)
 * =============================================================================
 *
 * Το αρχείο είναι **φύλλο**: το εισάγουν και ο `probe.js` (που τις παράγει) και
 * ο `oracle.js` (που τις ξανα-εξάγει), και **δεν εισάγει κανένα από τα δύο**.
 * Ο λόγος είναι μετρημένος, όχι αισθητικός: όσο οι καταστάσεις ζούσαν στο ίδιο
 * αρχείο με τον κριτή, κάθε διαχωρισμός του κριτή γεννούσε **κύκλο** — και
 * **κανένα gate αυτού του repo δεν φυλάει κύκλους κάτω από το `scripts/`**
 * (CHECK 3.79/3.80 σαρώνουν μόνο `src/`), άρα ο κύκλος θα περνούσε αόρατος.
 *
 * ⚠️ Η μόνη του εξάρτηση είναι ο `ledger.js`, που δεν εισάγει τίποτα από την
 * τριάδα — άρα η αλυσίδα παραμένει μονόδρομη:
 *
 *     ledger.js ← states.js ← probe.js ← oracle.js
 * =============================================================================
 */

const { assertClosedLedger } = require('./ledger');

const X_STATES = Object.freeze({
  UNREACHABLE: 'route-unreachable',
  PROBE_UNPROVEN: 'probe-unproven',
  RAW_KEY: 'raw-key',
  SKIPPED: 'route-skipped',
  SHELL_ONLY: 'surface-shell-only',
  NOT_RENDERED: 'surface-not-rendered',
  WITHHELD_ANSWERED: 'withheld-but-answered',
  SYNTHETIC_ID: 'surface-synthetic-id',
  WITHHELD: 'route-withheld',
  BACKEND_UNAVAILABLE: 'backend-unavailable',
  REDIRECTED: 'route-redirected',
  CLEAN: 'clean',
});

/** ⛔ ΠΟΤΕ σε baseline: ένας χρησμός που δεν απέδειξε ότι κοίταξε δεν έχει «πρόοδο». */
const X_ZERO_TOLERANCE = Object.freeze([X_STATES.UNREACHABLE, X_STATES.PROBE_UNPROVEN]);

/**
 * 🔴 ratchet κατά ταυτότητα `διαδρομή|επιφάνεια|κλειδί` — ανταλλαγή ⇒ μπλοκ (ADR-749).
 *
 * ⚠️ Το `backend-unavailable` (βλ. `backend-contract.js`) είναι ΕΔΩ και όχι στο 🔶: μια
 * διαδρομή που σήμερα κρίνεται και αύριο κρύβει την επιφάνειά της πίσω από δηλωμένη
 * αδυναμία backend οφείλει να **μπλοκάρει** — «απουσία δεν είναι πρόοδος» (CHECK 3.38).
 *
 * 🔑 **ΚΑΙ ΤΟ `route-redirected` ΕΙΝΑΙ ΕΔΩ — ΟΥΤΕ ⛔ ΟΥΤΕ 🔶, ΚΑΙ ΤΑ ΔΥΟ ΜΕ ΛΟΓΟ**
 * (ADR-781 §13):
 *   - **Όχι ⛔**, παρότι μια ανακατεύθυνση σημαίνει κυριολεκτικά «δεν κοίταξα αυτή τη
 *     σελίδα»: **112+** διαδρομές ανακατευθύνουν σήμερα ⇒ μόνιμα κόκκινη πύλη ⇒ `SKIP_`
 *     ⇒ διακοσμητική. Η ίδια ανταλλαγή δοκιμάστηκε και απορρίφθηκε στο CHECK 3.39, και
 *     είναι ο λόγος που το `raw-key` είναι ratchet αντί για zero-tolerance.
 *   - **Όχι 🔶**, που θα ήταν η εύκολη επιλογή: «μετριέται, δεν απαριθμείται» είναι
 *     **ακριβώς** ο μηχανισμός με τον οποίο το `surface-synthetic-id` κατάπιε τα δύο
 *     τρίτα του προϊόντος αθόρυβα (18,8% → 68,0% χωρίς κανέναν συναγερμό). Το να
 *     έμπαινε εδώ η ανακατεύθυνση θα επαναλάμβανε το σφάλμα που αυτή η κατάσταση
 *     υπάρχει για να διορθώσει.
 */
const X_RATCHETED = Object.freeze([
  X_STATES.RAW_KEY,
  X_STATES.SKIPPED,
  X_STATES.SHELL_ONLY,
  X_STATES.NOT_RENDERED,
  X_STATES.WITHHELD_ANSWERED,
  X_STATES.BACKEND_UNAVAILABLE,
  X_STATES.REDIRECTED,
]);

/**
 * 🔶 ΜΕΤΡΙΕΤΑΙ, ΔΕΝ ΑΠΑΡΙΘΜΕΙΤΑΙ — και **δεν** μπλοκάρει (πρότυπο
 * `unanalyzable-heritage`, CHECK 3.44).
 *
 * Μια δυναμική διαδρομή χτυπιέται με **συνθετικό** τμήμα, δηλαδή με id που δεν
 * υπάρχει. Ό,τι κι αν βάψει, **δεν είναι η σελίδα**: είναι το «δεν βρέθηκε» της.
 * Το να τη λέγαμε `clean` θα ήταν ψέμα· το να τη λέγαμε ⛔ θα έκανε **33 από τις
 * 154** διαδρομές μονίμως κόκκινες ⇒ `SKIP_` ⇒ διακοσμητική πύλη (η παγίδα που
 * το CHECK 3.39 δοκίμασε και απέρριψε). Μένει **ονομασμένη**.
 *
 * ⚠️ Η ασυμμετρία είναι σκόπιμη: πάνω σε **ακρίτη** επιφάνεια ένα «βρήκα ωμό
 * κλειδί» παραμένει **αληθές** (το κλειδί ζωγραφίστηκε όντως), ενώ ένα «δεν
 * βρήκα» δεν αποδεικνύει τίποτα. Γι' αυτό το `raw-key` κρίνεται **πριν** από
 * αυτή την κατάσταση, όχι μετά.
 *
 * 🔴 **ΜΕΤΡΗΜΕΝΟ ΟΡΙΟ ΑΥΤΟΥ ΤΟΥ ΚΑΔΟΥ (ADR-781 §13):** όταν το ADR-787 μετακίνησε
 * 104 διαδρομές πίσω από το πρόθεμα χώρου `/o/[workspace]`, **όλες** έγιναν δυναμικές
 * και προσγειώθηκαν εδώ — 29 → 132, δηλαδή **68% του προϊόντος αθόρυβα άκριτο**, και
 * τα ευρήματα «έπεσαν» 312 → 137 χωρίς να διορθωθεί ούτε μία γραμμή. Ο κάδος
 * σχεδιάστηκε για **οντότητα που μπορεί να μην υπάρχει** (μια αγγελία, μια επαφή)·
 * το `[workspace]` **δεν είναι οντότητα, είναι ταυτότητα**. Η ουσιαστική θεραπεία
 * είναι ο χρησμός με ταυτότητα (golden tenant)· ως τότε η ανακατεύθυνση τουλάχιστον
 * **ονομάζεται** αντί να απορροφάται εδώ.
 */
const X_COUNTED = Object.freeze([X_STATES.SYNTHETIC_ID, X_STATES.WITHHELD]);

/**
 * 🔶 ΤΟ ΔΗΛΩΜΕΝΟ ΤΑΒΑΝΙ ΚΑΘΕ ΜΕΤΡΟΥΜΕΝΟΥ ΚΑΔΟΥ — ως **μερίδιο** των διαδρομών (ADR-781 §15).
 *
 * «Μετριέται, δεν απαριθμείται» ΔΕΝ σημαίνει «χωρίς όριο»: το 29 → 132 πέρασε επειδή το
 * μόνο όριο ήταν η baseline — και η baseline **ξανασπάρθηκε** (οι 40 νέες δηλώσεις το
 * απαιτούσαν), άρα η σπορά ενέκρινε σιωπηλά το 68%. Ένα όριο που γράφει το ίδιο το
 * αποτέλεσμα δεν φυλάει την ίδια του τη σπορά. Γι' αυτό υπάρχουν **δύο** φράχτες:
 *   - ratchet ανά πλήθος έναντι του `by_state` της baseline (πιάνει 🔴→🔶 που μοιάζει πρόοδος)
 *   - αυτό εδώ: **πολιτική** που γράφει άνθρωπος, ανεξάρτητη από κάθε σπορά (πρότυπο
 *     Lighthouse CI `budget.json`) — ισχύει ΚΑΙ στο `--write-baseline`.
 *
 * `null` = ρητά χωρίς ταβάνι, με λόγο. ⚠️ Κλειστό: κάθε `X_COUNTED` έχει γραμμή (άγκυρα Β3).
 *   - `surface-synthetic-id` 20%: ιστορικά αποδεκτό 18,8% (29/154) πριν το ADR-787· το 68%
 *     θα είχε κοκκινίσει. Σφίγγεται μόνο με απόφαση του Giorgio.
 *   - `route-withheld`: `null` — κάθε μέλος του το γράφει άνθρωπος στο `.i18n-ssr-served.json`,
 *     άρα η αύξησή του είναι ήδη απόφαση· το ratchet έναντι baseline αρκεί.
 */
const X_COUNTED_CEILING = Object.freeze({
  [X_STATES.SYNTHETIC_ID]: 0.2,
  [X_STATES.WITHHELD]: null,
});

/** Το τμήμα που μπαίνει στη θέση ενός `[param]`. Σκόπιμα αναγνωρίσιμο στα logs. */
const SYNTHETIC_SEGMENT = 'ssr-probe';

/** Κλειστή λογιστική — ΜΙΑ υλοποίηση για τους τρεις κανόνες (βλ. `ledger.js`). */
function assertClosedX(records) {
  return assertClosedLedger('Χ', X_STATES, records, (record) => `διαδρομή ${record.route}`);
}

module.exports = {
  X_STATES,
  X_ZERO_TOLERANCE,
  X_RATCHETED,
  X_COUNTED,
  X_COUNTED_CEILING,
  SYNTHETIC_SEGMENT,
  assertClosedX,
};
