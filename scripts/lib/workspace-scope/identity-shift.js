'use strict';

const { compareSets } = require('../ratchet-baseline');

/**
 * Κρίνει αν η αλλαγή ταυτοτήτων είναι **μετακίνηση** ή **παλινδρόμηση**.
 *
 * @param {object} input
 * @param {string[]} input.before   ταυτότητες της παλιάς baseline
 * @param {string[]} input.after    ταυτότητες της νέας μέτρησης
 * @param {(id: string) => string} input.shift ο μετασχηματισμός — **ο ίδιος** με τον κώδικα
 * @returns {{verdict: 'move'|'regression'|'identical', appeared: string[], vanished: string[], collided: string[], moved: number}}
 */
function judgeIdentityShift({ before, after, shift }) {
  const beforeSet = [...new Set(before)];
  const afterSet = new Set(after);

  // 🔴 ΤΟ ΠΡΩΤΟ ΠΟΥ ΕΛΕΓΧΕΤΑΙ ΕΙΝΑΙ ΟΤΙ Ο ΜΕΤΑΣΧΗΜΑΤΙΣΜΟΣ ΕΙΝΑΙ ΕΝΕΣΙΜΟΣ.
  //    Αν δύο διαφορετικές παλιές ταυτότητες πέσουν στην ΙΔΙΑ νέα, το πλήθος
  //    μειώνεται και η σύγκριση θα έλεγε «όλα εντάξει, λιγότερα» — δηλαδή ο ίδιος
  //    ο ισομορφισμός θα ήταν το εργαλείο που κρύβει την απώλεια.
  const expected = new Map();
  const collided = [];
  for (const id of beforeSet) {
    const target = shift(id);
    if (expected.has(target)) collided.push(`${expected.get(target)} + ${id} → ${target}`);
    else expected.set(target, id);
  }

  const { added: appeared, removed: vanished } = compareSets([...afterSet], [...expected.keys()]);

  const moved = beforeSet.filter((id) => shift(id) !== id).length;

  let verdict;
  if (collided.length || appeared.length || vanished.length) verdict = 'regression';
  else if (moved === 0) verdict = 'identical';
  else verdict = 'move';

  return { verdict, appeared, vanished, collided, moved };
}

/**
 * Η **ταυτότητα** του CHECK 3.51: `διαδρομή|επιφάνεια|λεπτομέρεια`.
 *
 * ⚠️ Μετασχηματίζεται **μόνο η διαδρομή** — τα υπόλοιπα πεδία μένουν άθικτα, και
 * αυτό είναι που κάνει τον έλεγχο να πιάνει την **τύφλωση**: αν η κατάσταση
 * αλλάξει από `surface-shell-only` σε `surface-synthetic-id`, η νέα ταυτότητα
 * **δεν ταιριάζει** με καμία μετασχηματισμένη παλιά.
 */
function shiftPipeIdentity(id, shiftPath) {
  const parts = id.split('|');
  if (!parts.length) return id;
  parts[0] = shiftPath(parts[0]);
  return parts.join('|');
}

/**
 * Ταυτότητα που είναι **σκέτη διαδρομή** (π.χ. οι `declarations` του 3.51).
 *
 * ⚠️ Το CHECK 3.51 γράφει τις δηλώσεις ως `"/x/y (withheld: μηχανισμός)"` — ο
 * μηχανισμός παρακράτησης είναι **μέρος** της δήλωσης (ADR-790), άρα η διαδρομή
 * είναι μόνο το πρώτο κομμάτι και το υπόλοιπο μένει ανέγγιχτο.
 */
function shiftPlainPathIdentity(id, shiftPath) {
  const [route, ...rest] = id.split(' ');
  return [shiftPath(route), ...rest].join(' ');
}

module.exports = { judgeIdentityShift, shiftPipeIdentity, shiftPlainPathIdentity };
