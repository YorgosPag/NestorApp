'use strict';
/**
 * **ΤΟ ΜΗΤΡΩΟ ΕΙΣΟΔΩΝ ΤΩΝ ΠΥΛΩΝ** (ADR-924 §9) — ΤΟ ΕΝΑ σημείο που λέει «αυτή η κλάση αρχείων είναι είσοδος
 * ΜΟΝΟ για αυτές τις πύλες». Ο δρομολογητής της Φάσης 1 το ρωτά· καμία πύλη δεν κουβαλά δικό της `if` γι' αυτό.
 *
 * Πρότυπο: Bazel/TAP (ένα test ξανατρέχει μόνο αν οι δηλωμένες είσοδοί του τέμνουν την αλλαγή) · Nx `affected` ·
 * Chromium presubmit (`input_api.AffectedFiles(file_filter=…)`). Εδώ η δήλωση γίνεται ΑΝΑΠΟΔΑ, ανά κλάση διαδρομών
 * και όχι ανά πύλη, για να είναι fail-closed:
 *
 *   · Αρχείο που ΔΕΝ ανήκει σε καμία κλάση ⇒ τρέχουν ΟΛΕΣ οι πύλες (η προεπιλογή είναι «η πύλη διαβάζει τα πάντα»).
 *   · Μόνο όταν ΚΑΘΕ αλλαγή του commit ανήκει σε κλάσεις, τρέχουν μόνο οι `readers` τους.
 *   · Νέα πύλη που κανείς δεν δήλωσε εδώ ⇒ παραλείπεται μόνο σε commit που αποτελείται ΑΠΟΚΛΕΙΣΤΙΚΑ από δηλωμένες
 *     κλάσεις, τις οποίες εξ ορισμού ΔΕΝ διαβάζει (αλλιώς θα έπρεπε να μπει στους `readers`).
 *
 * Επέκταση: νέα κλάση = νέα εγγραφή εδώ, με `why` και `readers` που ο καθένας έχει λόγο. Κανένα `if` στον δρομολογητή.
 * Το GitHub CI ΔΕΝ περνά από εδώ: τρέχει τα πάντα, ως δίχτυ ασφαλείας.
 *
 * @module scripts/lib/gate-scope/registry
 */

