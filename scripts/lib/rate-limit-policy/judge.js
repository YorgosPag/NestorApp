#!/usr/bin/env node
/**
 * CHECK 3.78 — Η ΚΡΙΣΗ (ADR-855 Α5). Η απογραφή ζει στο `inventory.js`.
 *
 * ΔΥΟ ΕΡΩΤΗΜΑΤΑ, ΔΥΟ ΚΡΙΤΗΡΙΑ, **ΠΟΤΕ ΕΝΑ ΜΕ «Ή»** (μάθημα CHECK 3.41):
 *
 *   **Κ1** *«δηλώνει αυτή η διαδρομή βαθμίδα ορίου;»*
 *          → πιάνει τον **επόμενο** που θα γράψει διαδρομή χωρίς να το σκεφτεί.
 *   **Κ2** *«συμφωνεί η δήλωση με ό,τι θα επιβληθεί;»*
 *          → πιάνει τη **σημερινή** σιωπηλή αντίφαση: 79 διαδρομές δηλώνουν άλλο όριο από
 *            όσο παίρνουν, και η αντίφαση ήταν αόρατη επειδή κανείς δεν ρώτησε.
 *
 * Ένας κανόνας με «ή» θα έμενε **πράσινος πάνω στο μισό ελάττωμα**: μια διαδρομή μπορεί να
 * δηλώνει σωστά και να επιβάλλεται λάθος, ή να μη δηλώνει καθόλου και τυχαία να παίρνει το
 * σωστό από τον πίνακα.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🏆 ΤΟ ΠΡΟΤΥΠΟ ΥΠΑΡΧΕΙ ΗΔΗ ΣΕ ΑΥΤΟ ΤΟ ΔΕΝΤΡΟ — ΔΕΝ ΕΦΕΥΡΕΘΗΚΕ ΕΔΩ
 * ─────────────────────────────────────────────────────────────────────────────
 * Το `showcase-core` έλυσε **το ίδιο** ερώτημα για έξι δημόσιες διαδρομές token, και το
 * σκεπτικό είναι γραμμένο στο `create-token-route-export.ts:20-23`:
 *
 *   «Making the parameter **required** means every route file now **states** which side it
 *    is on, so the gap is **visible in review** instead of implied by an absent wrapper.»
 *
 * …με άγκυρα που το επιβάλλει (`public-showcase-surface.test.ts:355`) και **tripwire** που
 * καρφώνει την τρέχουσα εικόνα *(«Not an endorsement — a tripwire»)*. Το Κ1/Κ2 είναι η
 * **γενίκευσή** του από 6 διαδρομές στις 449.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠️ RATCHET ΚΑΙ ΟΧΙ ZERO-TOLERANCE — ΜΕΤΡΗΜΕΝΟ, ΟΧΙ ΠΡΟΤΙΜΗΣΗ
 * ─────────────────────────────────────────────────────────────────────────────
 * 77 σιωπηλές + 79 αποκλίσεις = **156** ζωντανές. Zero-tol θα ήταν μονίμως κόκκινο ⇒
 * `SKIP_` ⇒ **διακοσμητική πύλη** — η παγίδα που το CHECK 3.39 δοκίμασε και απέρριψε
 * **γραπτώς**. Το ratchet είναι **κατά ταυτότητα**: «156 → 156» με **ανταλλαγή**
 * μπλοκάρει (ADR-749).
 *
 * @module scripts/lib/rate-limit-policy/judge
 */

'use strict';

/**
 * Οι καταστάσεις. **Κλειστό σύνολο** — άγνωστη ⇒ `throw` με όνομα, ποτέ σιωπηλή απόρριψη.
 */
const STATES = Object.freeze({
  /** 🔴 Καμία δήλωση, ούτε άμεση ούτε μέσω εργοστασίου. Παίρνει ό,τι τύχει ο πίνακας. */
  UNDECLARED: 'undeclared',
  /**
   * 🔴 **Η ΔΗΛΩΣΗ ΚΑΙ Ο ΠΙΝΑΚΑΣ ΛΕΝΕ ΔΙΑΦΟΡΕΤΙΚΑ ΠΡΑΓΜΑΤΑ** — δύο πηγές, μία ερώτηση.
   *
   * ⚠️ **ΔΕΝ σημαίνει «η διαδρομή τρέχει λάθος όριο»** — και η διάκριση μετρήθηκε: μετά τη
   * **Φ1** του ADR-855 η **δήλωση κερδίζει**, άρα η διαδρομή παίρνει ακριβώς ό,τι ζήτησε.
   * Αυτό που μένει σπασμένο είναι η **γραμμή του πίνακα**: για αυτή τη διεύθυνση δεν
   * μπορεί πλέον να πυροδοτήσει **ποτέ** — είναι νεκρή, και κανείς δεν το ξέρει.
   *
   * 🔑 Γι' αυτό είναι παραβίαση: **ADR-749** — δύο απαντήσεις στο ίδιο ερώτημα, με τη μία
   * να παλιώνει σιωπηλά. Ο επόμενος που θα διορθώσει το όριο αλλάζοντας τον **πίνακα** θα
   * δει καμία αλλαγή και θα ψάξει σφάλμα αλλού.
   *
   * ⇒ Θεραπεία: **ένα** από τα δύο. Ή σβήσε/διόρθωσε τη γραμμή του πίνακα, ή αφαίρεσε τη
   *   ρητή δήλωση αν ο πίνακας είναι ο σωστός. Ποτέ «και τα δύο, να είμαστε σίγουροι».
   */
  SHADOWED: 'prefix-shadowed-by-declaration',
  /**
   * ✅ **ΔΗΛΩΝΕΙ ΚΑΤΙ ΑΛΛΟ ΑΠΟ ΤΗΝ ΠΡΟΕΠΙΛΟΓΗ — ΚΑΙ ΕΙΝΑΙ ΑΚΡΙΒΩΣ ΤΟ ΣΩΣΤΟ.**
   *
   * ─────────────────────────────────────────────────────────────────────────
   * 🔴 ΓΕΝΝΗΘΗΚΕ ΑΠΟ ΕΛΑΤΤΩΜΑ ΤΗΣ ΙΔΙΑΣ ΑΥΤΗΣ ΠΥΛΗΣ — 57/84 ΨΕΥΔΩΣ ΘΕΤΙΚΑ
   * ─────────────────────────────────────────────────────────────────────────
   * Μέχρι τις 2026-09-12 αυτές οι διαδρομές μετρούνταν {@link SHADOWED}, δηλαδή
   * *«νεκρή γραμμή πίνακα»* — **και δεν υπάρχει γραμμή**. Το `enforcedCategory`
   * επιστρέφει την **προεπιλογή** όταν κανένα πρόθεμα δεν ταιριάζει, οπότε η
   * σύγκριση `declared !== enforced` έβγαζε παραβίαση για κάθε διαδρομή που
   * δηλώνει σωστά οτιδήποτε ≠ `STANDARD`.
   *
   * **Μετρημένο στη baseline: 57 από 84** ήταν αυτής της μορφής *(κάτω φράγμα 54)*
   * — **δύο στα τρία** του κριτηρίου Κ2 ήταν θόρυβος. Το έπιασε η πύλη **πάνω στον
   * εαυτό της**: μια `withHeavyRateLimit` σε δημόσια διαδρομή token (ADR-853 Φ4)
   * μπλόκαρε commit **χωρίς να υπάρχει τίποτα λάθος**.
   *
   * 🔑 **ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΠΑΡΑΒΙΑΣΗ**: το κριτήριο Κ2 υπάρχει για το σχήμα ADR-749
   * *(δύο απαντήσεις σε ένα ερώτημα, η μία παλιώνει σιωπηλά)*. Εδώ υπάρχει **μία**
   * απάντηση — η δήλωση — και **καμία γραμμή δεν μπορεί να παλιώσει, γιατί καμία
   * δεν γράφτηκε**. Μετά τη Φ1 του ADR-855 αυτό είναι το **κανονικό** σχήμα μιας
   * σωστά γραμμένης διαδρομής: δηλώνει η ίδια, ρητά, στο αρχείο της.
   *
   * ⚠️ **ΚΑΙ ΔΕΝ ΕΙΝΑΙ «ΣΥΜΦΩΝΕΙ»** *({@link AGREES})*: εκείνο σημαίνει ότι μια
   * **γραμμή** λέει το ίδιο με τη δήλωση — δύο ανεξάρτητες πηγές που συμπίπτουν.
   * Το να τα ισοπεδώσουμε θα έκρυβε την πληροφορία *«αυτή η διεύθυνση δεν έχει
   * καθόλου γραμμή»*, που είναι ακριβώς ό,τι χρειάζεται όποιος αποφασίσει ποτέ να
   * θεραπεύσει τις **27** πραγματικά νεκρές γραμμές.
   */
  DECLARED_OVER_DEFAULT: 'declared-over-default',
  /** ✅ Δηλώνει άμεσα, και **μια γραμμή του πίνακα** λέει το ίδιο. */
  AGREES: 'declared-agrees',
  /**
   * ✅ Δηλώνει **μέσω εργοστασίου** — η βαθμίδα ζει εκεί, όχι στο αρχείο της διαδρομής.
   *
   * ⚠️ **ΔΕΝ κρίνεται για συμφωνία, και είναι απόφαση**: το εργοστάσιο τυλίγει μόνο του,
   * οπότε η «δήλωση» της διαδρομής είναι η **επιλογή εργοστασίου**. Μια κρίση συμφωνίας
   * εδώ θα απαιτούσε στατική εκτέλεση του εργοστασίου — δηλαδή μαντεψιά.
   * ⇒ Μπαίνουν στο **κλειστό σύνολο δηλώσεων** ώστε **νέα** τέτοια διαδρομή να τη δει
   *   άνθρωπος (πρότυπο CHECK 3.39 / 3.58: η μάζα ratchet-άρεται, το νέο δηλώνεται).
   */
  VIA_FACTORY: 'declared-via-factory',
});

/** Ό,τι μπαίνει στο ratchet των παραβιάσεων. */
const RATCHETED_STATES = Object.freeze([STATES.UNDECLARED, STATES.SHADOWED]);

/** Η σειρά εκτύπωσης: πρώτα ό,τι μετράει, ώστε να μην κρύβεται. */
const ORDER = Object.freeze([
  STATES.UNDECLARED,
  STATES.SHADOWED,
  STATES.DECLARED_OVER_DEFAULT,
  STATES.AGREES,
  STATES.VIA_FACTORY,
]);

/**
 * Τα είδη δήλωσης που ξέρει ο ταξινομητής. **Κλειστό σύνολο.**
 *
 * 🔴 **ΓΡΑΦΤΗΚΕ ΕΠΕΙΔΗ Ο ΦΡΟΥΡΟΣ ΤΟΥ `judge` ΗΤΑΝ ΑΝΕΝΕΡΓΟΣ — ΤΟ ΕΠΙΑΣΕ Η ΑΓΚΥΡΑ `Λ1`.**
 * Ο έλεγχος `if (!(state in tally)) throw` πυροδοτεί μόνο αν ο `classify` επιστρέψει
 * κατάσταση εκτός καταστίχου — και ο `classify` **δεν μπορούσε**: άγνωστο `kind` με
 * `declared: null` έπεφτε στο σκέλος «χωρίς βαθμίδα» και έβγαινε `undeclared` **σιωπηλά**.
 * Δηλαδή ένας φρουρός γραμμένος και **αδύνατο να πυροδοτήσει** — σχόλιο, όχι φρουρός
 * (ADR-749 §5). Η άρνηση πρέπει να ζει **εκεί που γεννιέται η κατάσταση**.
 */
const KNOWN_KINDS = Object.freeze(['direct', 'factory', 'silent']);

/**
 * Η κατάσταση **μιας** διαδρομής. Ακριβώς μία, πάντα.
 *
 * ⚠️ Η **σειρά είναι συμβόλαιο**: η σιωπή κρίνεται πρώτη *(δεν υπάρχει τίποτα να
 *    συγκριθεί)*, το εργοστάσιο **πριν** τη συμφωνία *(δεν έχει δηλωμένη βαθμίδα να
 *    συγκριθεί)*, και η ασυμφωνία **τελευταία** — αλλιώς μια εργοστασιακή διαδρομή θα
 *    μετρούσε ως ασυμφωνία επειδή το `declared` της είναι `null`.
 */
function classify(route) {
  // 🔴 FAIL-CLOSED ΣΤΗ ΓΕΝΝΗΣΗ ΤΗΣ ΚΑΤΑΣΤΑΣΗΣ, όχι στη λογιστική: δες `KNOWN_KINDS`.
  if (!KNOWN_KINDS.includes(route.kind)) {
    throw new Error(
      `CHECK 3.78: άγνωστη κατάσταση δήλωσης «${route.kind}» για ${route.url}. `
      + 'Η λογιστική δεν επιτρέπεται να χάσει διαδρομή σιωπηλά.',
    );
  }
  if (route.kind === 'silent') return STATES.UNDECLARED;
  if (route.kind === 'factory') return STATES.VIA_FACTORY;
  // Άμεση δήλωση χωρίς βαθμίδα (ωμό `withRateLimit(h)` χωρίς `category`): η δήλωση
  // υπάρχει αλλά δεν λέει τίποτα ⇒ αδήλωτη ως προς την **πολιτική**.
  if (!route.declared) return STATES.UNDECLARED;
  if (route.declared === route.enforced) return STATES.AGREES;

  // 🔴 **Η ΔΙΑΚΡΙΣΗ ΠΟΥ ΕΛΕΙΠΕ** (2026-09-12): «διαφέρει από **γραμμή**» ≠ «διαφέρει από
  //    την **προεπιλογή**». Το πρώτο αφήνει γραμμή που δεν πυροδοτεί ποτέ (ADR-749)· το
  //    δεύτερο δεν αφήνει τίποτα — καμία γραμμή δεν γράφτηκε. Δες `DECLARED_OVER_DEFAULT`.
  // ⚠️ **fail-closed στο ΑΓΝΩΣΤΟ**: μόνο το ρητό `'default'` αθωώνει. Απογραφή παλιότερης
  //    έκδοσης (χωρίς `enforcedFrom`) κρίνεται **παραβίαση**, ποτέ σιωπηλή αθώωση.
  return route.enforcedFrom === 'default' ? STATES.DECLARED_OVER_DEFAULT : STATES.SHADOWED;
}

/**
 * Η ταυτότητα μιας παραβίασης.
 *
 * ⚠️ Η **διεύθυνση** μπαίνει, ο αριθμός γραμμής **όχι** (θα κοκκίνιζε σε κάθε μετακίνηση).
 *    Για την ασυμφωνία μπαίνει **και το ζεύγος** βαθμίδων: αλλαγή από `HEAVY→STANDARD` σε
 *    `HEAVY→SENSITIVE` είναι **άλλη** παραβίαση, και η σιωπηλή μετάβαση δεν επιτρέπεται.
 */
function violationId(finding) {
  return finding.state === STATES.SHADOWED
    ? `${finding.state}::${finding.declared}→${finding.enforced}::${finding.url}`
    : `${finding.state}::${finding.url}`;
}

/**
 * Κρίνει την απογραφή. **Κλειστή λογιστική, fail-closed.**
 *
 * @param {{routes: Array<object>, table: object, fallback: string}} inventory
 * @returns ετυμηγορία με κατάστιχο, ευρήματα, και τα δύο σύνολα ταυτοτήτων
 */
function judge(inventory) {
  const tally = Object.fromEntries(ORDER.map((s) => [s, 0]));
  const findings = [];

  for (const route of inventory.routes) {
    const state = classify(route);
    if (!(state in tally)) {
      throw new Error(
        `CHECK 3.78: άγνωστη κατάσταση «${state}» για ${route.url}. `
        + 'Η λογιστική δεν επιτρέπεται να χάσει διαδρομή σιωπηλά.',
      );
    }
    tally[state] += 1;
    findings.push({ ...route, state });
  }

  // 🔴 Η λογιστική είναι το όργανο που εγγυάται ότι καμία διαδρομή δεν χάνεται — και δεν
  //    επιτρέπεται να χαθεί **η ίδια** (μάθημα CHECK 3.39 `Κ15β` / 3.42).
  const summed = ORDER.reduce((acc, s) => acc + tally[s], 0);
  if (summed !== inventory.routes.length) {
    throw new Error(`CHECK 3.78: η λογιστική δεν κλείνει (${summed} ≠ ${inventory.routes.length}).`);
  }

  const violations = findings.filter((f) => RATCHETED_STATES.includes(f.state));

  return {
    tally,
    findings,
    violations,
    violationIds: violations.map(violationId).sort(),
    // Το κλειστό σύνολο: ποιες διαδρομές κρύβουν τη βαθμίδα τους σε εργοστάσιο.
    declarations: findings
      .filter((f) => f.state === STATES.VIA_FACTORY)
      .map((f) => `${f.factory}::${f.url}`)
      .sort(),
    population: inventory.routes.length,
    unresolvedPrefixes: inventory.table.unresolved,
  };
}

/** Οι ταυτότητες μιας κατάστασης — για αναφορά και για τις άγκυρες. */
function idsOf(verdict, state) {
  return verdict.findings.filter((f) => f.state === state).map((f) => f.url).sort();
}

module.exports = { STATES, RATCHETED_STATES, ORDER, KNOWN_KINDS, classify, violationId, judge, idsOf };
