/**
 * @fileoverview Άγκυρες του αναλυτή του ν. 3852/2010 — ADR-893.
 *
 * Τα αποσπάσματα είναι **αυτούσια** από τη μεταγραφή της Βικιθήκης (με τα σφάλματα OCR της).
 */

import { lawHtmlToText, parseLaw3852, splitEnumeration } from '../law-3852';

const ARTICLE = [
  '<p>Άρθρο 1 Σύσταση δήμων</p>',
  '<p>1. ΝΟΜΟΣ ΡΟΔΟΠΗΣ Α. Συνιστώνται οι κατωτέρω δήμοι:',
  '1. Δήμος Κομοτηνής με έδρα την Κομοτηνή αποτελούμενος από τους δήμους α. Αιγείρου β. Κομοτηνής',
  'και γ. Νέου Σιδηροχωρίου, οι οποίοι καταργούνται.',
  '2. Δήμος Αµυνταίου µε έδρα το Αµύνταιο µε ιστορική έδρα το Νυμφαίο αποτελούμενος από τους δήμους',
  'α. Αετού β. Αµυνταίου γ. Φιλώτα και τις κοινότητες α. Βαρικού β. Λεχόβου γ. Νυμφαίου, οι οποίοι καταργούνται.',
  'Β. Στο δήμο Θέρμου δεν επέρχεται καμία µεταβολή.</p>',
  '<p>Άρθρο 2 Δημοτικές ενότητες</p>',
  '<p>1. Δήμος Ψεύτικος με έδρα κάπου αποτελούμενος από τους δήμους α. Εκτός.</p>',
].join('\n');

describe('parseLaw3852 — άρθρο 1 μόνο', () => {
  const law = parseLaw3852(lawHtmlToText(ARTICLE));

  it('δήμοι με τις δημοτικές τους ενότητες — δήμοι ΚΑΙ κοινότητες, με καθαρισμένο OCR', () => {
    expect(law.municipalities).toEqual([
      { name: 'Κομοτηνής', units: ['Αιγείρου', 'Κομοτηνής', 'Νέου Σιδηροχωρίου'] },
      { name: 'Αμυνταίου', units: ['Αετού', 'Αμυνταίου', 'Φιλώτα', 'Βαρικού', 'Λεχόβου', 'Νυμφαίου'] },
    ]);
  });

  it('οι δήμοι χωρίς μεταβολή μετρούν — αλλιώς ο Δήμος Αθηναίων δεν θα είχε πηγή', () => {
    expect(law.unchanged).toEqual(['Θέρμου']);
  });

  it('τίποτα μετά το άρθρο 2 — εκεί ο νόμος μιλά για άλλα', () => {
    expect(law.municipalities.map((entry) => entry.name)).not.toContain('Ψεύτικος');
  });
});

describe('splitEnumeration', () => {
  it('απαριθμητές ενός και δύο γραμμάτων (α. … στ. … ιθ.)', () => {
    expect(splitEnumeration('τους δήμους α. Άργους στ. Λυρκείας και ζ. Αχλαδόκαμπου')).toEqual([
      'Άργους',
      'Λυρκείας',
      'Αχλαδόκαμπου',
    ]);
  });
});
