'use strict';

/**
 * Σβήσε σχόλια μπλοκ και γραμμής από πηγαίο κώδικα τύπου C (JS/TS/JSX).
 *
 * ⚠️ Το `[^:]` πριν από το `//` αποτρέπει το κόψιμο ενός URL (`https://…`) που ζει μέσα σε
 * συμβολοσειρά — χωρίς αυτό, μισή γραμμή κώδικα θα εξαφανιζόταν σιωπηλά.
 *
 * 🔶 **Δηλωμένο όριο**: δεν είναι tokenizer. Ένα `//` μέσα σε συμβολοσειρά χωρίς `:` πριν, ή
 * ένα `/*` μέσα σε regex literal, μπορούν να κόψουν παραπάνω. Είναι **αποδεκτό για πρόφιλτρο**
 * ακριβώς επειδή αφαιρεί: το χειρότερο αποτέλεσμα είναι να **χαθεί** ένα ταίριασμα, ποτέ να
 * επινοηθεί. Πύλη που χρειάζεται εγγυημένη ακρίβεια οφείλει να χρησιμοποιήσει AST.
 */
function stripComments(source) {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(^|[^:])\/\/[^\n]*/g, '$1 ');
}

/**
 * Σβήσε σχόλια `#` από shell / PowerShell / YAML.
 *
 * 🔑 **ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΕ ΔΕΥΤΕΡΟ ΑΡΧΕΙΟ**: το ερώτημα είναι το ΙΔΙΟ — *«ποιο κείμενο αυτού
 * του αρχείου είναι **εκτέλεση** και ποιο **τεκμηρίωση**;»*. Αλλάζει μόνο η **σύνταξη** του
 * σχολίου, όχι η ερώτηση. Ξεχωριστό module θα ήταν δεύτερη αυθεντία για το ίδιο πράγμα, και
 * ο επόμενος που έψαχνε «πού κόβονται τα σχόλια;» θα έβρισκε **δύο** απαντήσεις (ADR-749).
 *
 * ⚠️ **Το `#` ΔΕΝ ξεκινά πάντα σχόλιο**: μόνο στην αρχή γραμμής ή μετά από κενό. Το
 * `foo#bar` είναι **ταυτοποιητής**, και ένα `${var#prefix}` του bash είναι **επέκταση
 * παραμέτρου**. Γι΄ αυτό απαιτείται αρχή γραμμής ή κενό πριν — αλλιώς θα έσβηνε εκτελέσιμο
 * κείμενο, δηλαδή θα **επινοούσε** απουσία μοτίβου που στην πραγματικότητα υπάρχει.
 *
 * 🔶 **Δηλωμένο όριο, ίδιο με τον αδελφό**: δεν είναι tokenizer. Ένα `#` μέσα σε συμβολοσειρά
 * με κενό πριν (`echo "a # b"`) κόβει παραπάνω. Αποδεκτό **επειδή αφαιρεί**: το χειρότερο
 * αποτέλεσμα είναι να **χαθεί** ταίριασμα, ποτέ να επινοηθεί.
 */
function stripHashComments(source) {
  return source.replace(/(^|[ \t])#[^\n]*/gm, '$1 ');
}

module.exports = { stripComments, stripHashComments };
